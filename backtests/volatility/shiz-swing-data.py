import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adrp_len = 20
    atr_len = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ADR% calculation: 100 * (SMA(high/low, adrp_len) - 1)
        self.adr_pct = self.I(lambda: 100 * (pta.sma(high / low, length=self.adrp_len) - 1))
        
        # ATR calculation
        self.atr_value = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # 52-week high using rolling max
        self.highest_52w = self.I(lambda: high.rolling(window=252).max())
        
        # Distance from 52W high: 100 * (close / 52w_high - 1)
        self.dist_from_high = self.I(lambda: 100 * (close / high.rolling(window=252).max() - 1))

    def next(self):
        # Simple trading rules based on ADR% and distance from 52W high
        # Buy when ADR% is moderate and price is below 52W high
        # Sell when ADR% spikes or price approaches 52W high
        
        if len(self.data) < 252:
            return
        
        adr = self.adr_pct[-1] if not np.isnan(self.adr_pct[-1]) else None
        dist = self.dist_from_high[-1] if not np.isnan(self.dist_from_high[-1]) else None
        
        if adr is None or dist is None:
            return
        
        # Buy signal: ADR% between 1-5% and price is 10-30% below 52W high
        if not self.position:
            if 1 <= adr <= 5 and -30 <= dist <= -10:
                self.buy()
        
        # Sell signal: ADR% > 7% or price within 5% of 52W high
        else:
            if adr > 7 or dist > -5:
                self.sell()