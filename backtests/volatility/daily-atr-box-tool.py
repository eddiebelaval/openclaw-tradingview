import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLen = 14
    avgDays = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Calculate average ATR over avgDays
        atr_series = pta.atr(high, low, close, length=self.atrLen)
        self.avg_atr = self.I(lambda: pta.sma(atr_series, length=self.avgDays))
        
        # Track daily open price (use opening price of each day)
        self.daily_open = self.I(lambda: pd.Series([self.data.Open[i] if i == 0 or pd.Timestamp(self.data.index[i]).date() != pd.Timestamp(self.data.index[i-1]).date() else (self.daily_open[-1] if hasattr(self, 'daily_open') and len(self.daily_open) > 0 else self.data.Open[i]) for i in range(len(self.data.Close))], index=self.data.index))
        
        # Calculate levels
        self.upper_half = self.I(lambda: (self.daily_open + (self.avg_atr * 0.5)))
        self.lower_half = self.I(lambda: (self.daily_open - (self.avg_atr * 0.5)))
        self.upper_full = self.I(lambda: (self.daily_open + self.avg_atr))
        self.lower_full = self.I(lambda: (self.daily_open - self.avg_atr))

    def next(self):
        # Buy when price touches lower half box and shows reversal
        if len(self) > 1:
            if self.data.Low[-1] <= self.lower_half[-1] and self.data.Close[-1] > self.data.Open[-1]:
                if not self.position:
                    self.buy()
        
        # Sell when price touches upper half box and shows reversal
        if len(self) > 1:
            if self.data.High[-1] >= self.upper_half[-1] and self.data.Close[-1] < self.data.Open[-1]:
                if self.position:
                    self.sell()
        
        # Alternative: sell on upper full box touch
        if len(self) > 1:
            if self.data.High[-1] >= self.upper_full[-1]:
                if self.position:
                    self.sell()


