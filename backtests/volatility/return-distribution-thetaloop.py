        skew = self.skewness[-1]
        
        # High Risk: Fat tails + negative skew = potential for sharp downside moves
        # This is bearish for long positions
        high_risk = kurt > self.kurt_alert and skew < self.skew_warn
        
        # Elevated risk: Either high kurtosis OR negative skew
        elevated_risk = (kurt > self.kurt_warn) or (skew < self.skew_warn)
        
        # Normal conditions: Low kurtosis and neutral/positive skew
        normal_conditions = kurt <= self.kurt_warn and skew >= self.skew_warn
        
        # Trading logic: Buy in normal conditions, sell in high risk
        if normal_conditions and not self.position:
            self.buy()
        elif high_risk and self.position:
            self.sell()
        elif elevated_risk and self.position:
            # Exit on elevated risk as a precautionary measure
            self.sell()


