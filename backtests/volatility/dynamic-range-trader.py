import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Band Settings
    band_length = 205
    outer_mult = 2.315
    grad_size = 0.1
    
    # Entry Confirmation
    adx_thresh = 38.0
    adx_len = 14
    adx_smooth = 16
    entry_atr_mult = 0.3
    use_rsi = False
    rsi_len = 14
    rsi_ob = 70
    rsi_os = 30
    use_pattern = False
    cooldown_bars = 10
    
    # Risk & Position Sizing
    risk_per_trade = 100.0
    buying_power = 10000.0
    
    # Session Filter
    use_session_filter = False
    session_start = 930
    session_end = 1600
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Butterworth smoothing function
        def butterworth_smooth(src, length):
            s_a1 = np.exp(-np.sqrt(2) * np.pi / length)
            s_b1 = 2 * s_a1 * np.cos(np.sqrt(2) * np.pi / length)
            s_c3 = -(s_a1 ** 2)
            s_c2 = s_b1
            s_c1 = 1 - s_c2 - s_c3
            
            ss = pd.Series(index=src.index, dtype=float)
            ss.iloc[0] = src.iloc[0]
            
            for i in range(1, len(src)):
                prev_ss = ss.iloc[i-1]
                prev_ss2 = ss.iloc[i-2] if i >= 2 else src.iloc[0]
                ss.iloc[i] = s_c1 * src.iloc[i] + s_c2 * prev_ss + s_c3 * prev_ss2
            
            return ss
        
        # Band calculations
        self.centerline = self.I(lambda: butterworth_smooth(close, self.band_length))
        
        # True Range for smoothing
        tr = high - low
        self.windowrange = self.I(lambda: butterworth_smooth(tr, self.band_length))
        
        # Band levels
        mult2 = np.pi * self.outer_mult
        
        self.bear_cw = self.I(lambda: self.centerline[-1] + (self.windowrange[-1] * mult2) if len(self.centerline) > 0 and len(self.windowrange) > 0 else close.iloc[-1])
        self.bull_cw = self.I(lambda: self.centerline[-1] - (self.windowrange[-1] * mult2) if len(self.centerline) > 0 and len(self.windowrange) > 0 else close.iloc[-1])
        
        # Gradient zone levels
        self.bull_g1 = self.I(lambda: self.bull_cw[-1] - (self.windowrange[-1] * self.grad_size * 4) if len(self.bull_cw) > 0 else low.iloc[-1])
        self.bull_g9 = self.I(lambda: self.bull_cw[-1] + (self.windowrange[-1] * self.grad_size * 4) if len(self.bull_cw) > 0 else low.iloc[-1])
        self.bear_g1 = self.I(lambda: self.bear_cw[-1] + (self.windowrange[-1] * self.grad_size * 4) if len(self.bear_cw) > 0 else high.iloc[-1])
        self.bear_g9 = self.I(lambda: self.bear_cw[-1] - (self.windowrange[-1] * self.grad_size * 4) if len(self.bear_cw) > 0 else high.iloc[-1])
        
        # Confirmation Indicators
        self.rsi_value = self.I(pta.rsi, close, length=self.rsi_len)
        self.atr_value = self.I(pta.atr, high, low, close, length=14)
        
        # ADX/DMI
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_len, scalar=100) or pd.DataFrame(index=close.index))
        self.adx_value = self.I(lambda: adx_result['ADX_' + str(self.adx_len)] if 'ADX_' + str(self.adx_len) in adx_result.columns else pd.Series(50, index=close.index))
        
        # Midpoint
        self.midpoint = self.I(lambda: (self.bear_cw[-1] + self.bull_cw[-1]) / 2 if len(self.bear_cw) > 0 and len(self.bull_cw) > 0 else close.iloc[-1])
        
        # Trade state variables
        self.entry_price = None
        self.stop_loss = None
        self.take_profit = None
        self.pos_size = 0
        self.trade_dir = 0
        self.in_trade = False
        self.last_trade_bar = -np.inf
        self.initial_risk_dist = 0
        self.exp_profit = 0
        self.rr_ratio = 0
    
    def next(self):
        # Current bar values
        current_idx = len(self.data) - 1
        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        
        # Skip if not enough data
        if len(self.centerline) < 2 or len(self.windowrange) < 2:
            return
        
        centerline = self.centerline[-1]
        windowrange = self.windowrange[-1]
        bull_cw = self.bull_cw[-1]
        bear_cw = self.bear_cw[-1]
        midpoint = self.midpoint[-1]
        atr_val = self.atr_value[-1]
        rsi_val = self.rsi_value[-1]
        adx_val = self.adx_value[-1]
        
        bull_g1 = self.bull_g1[-1]
        bear_g1 = self.bear_g1[-1]
        bull_g9 = self.bull_g9[-1]
        bear_g9 = self.bear_g9[-1]
        
        # Market regime
        is_ranging = adx_val < self.adx_thresh
        
        # Proximity to bands
        near_lower_band = low_price <= (bull_cw + self.entry_atr_mult * atr_val)
        near_upper_band = high_price >= (bear_cw - self.entry_atr_mult * atr_val)
        
        # Midpoint rules
        below_midpoint = close_price < midpoint
        above_midpoint = close_price > midpoint
        
        # RSI filter
        rsi_long_ok = not self.use_rsi or rsi_val < self.rsi_os
        rsi_short_ok = not self.use_rsi or rsi_val > self.rsi_ob
        
        # Candle confirmation
        green_candle = self.data.Close[-1] > self.data.Open[-1]
        red_candle = self.data.Close[-1] < self.data.Open[-1]
        
        candle_long_ok = green_candle
        candle_short_ok = red_candle
        
        # Entry conditions
        long_conditions = is_ranging and near_lower_band and below_midpoint and candle_long_ok and rsi_long_ok
        short_conditions = is_ranging and near_upper_band and above_midpoint and candle_short_ok and rsi_short_ok
        
        # Cooldown check
        cooldown_ok = (current_idx - self.last_trade_bar) >= self.cooldown_bars
        
        # Final signals
        long_signal = long_conditions and not self.in_trade and cooldown_ok
        short_signal = short_conditions and not self.in_trade and cooldown_ok
        
        # Stop loss and take profit calculations
        long_sl = bull_g1 - 0.0001
        long_tp = bear_g9
        short_sl = bear_g1 + 0.0001
        short_tp = bull_g9
        
        # Risk distances
        long_risk_dist = max(close_price - long_sl, 0.0001)
        long_reward_dist = max(long_tp - close_price, 0.0001)
        long_rr = long_reward_dist / long_risk_dist
        
        short_risk_dist = max(short_sl - close_price, 0.0001)
        short_reward_dist = max(close_price - short_tp, 0.0001)
        short_rr = short_reward_dist / short_risk_dist
        
        # Position sizing
        long_pos_size = min(self.risk_per_trade / long_risk_dist, self.buying_power / close_price)
        short_pos_size = min(self.risk_per_trade / short_risk_dist, self.buying_power / close_price)
        
        # Expected profit
        long_exp_profit = long_reward_dist * long_pos_size
        short_exp_profit = short_reward_dist * short_pos_size
        
        # Close existing trade
        if self.in_trade:
            exit_now = False
            exit_price = None
            
            if self.trade_dir == 1:
                if low_price <= self.stop_loss:
                    exit_now = True
                    exit_price = self.stop_loss
                elif high_price >= self.take_profit:
                    exit_now = True
                    exit_price = self.take_profit
            
            elif self.trade_dir == -1:
                if high_price >= self.stop_loss:
                    exit_now = True
                    exit_price = self.stop_loss
                elif low_price <= self.take_profit:
                    exit_now = True
                    exit_price = self.take_profit
            
            if exit_now:
                self.sell()
                self.in_trade = False
                self.trade_dir = 0
                self.last_trade_bar = current_idx
        
        # Open new trade
        if long_signal:
            self.buy()
            self.entry_price = close_price
            self.stop_loss = long_sl
            self.take_profit = long_tp
            self.initial_risk_dist = long_risk_dist
            self.pos_size = long_pos_size
            self.exp_profit = long_exp_profit
            self.rr_ratio = long_rr
            self.trade_dir = 1
            self.in_trade = True
            self.last_trade_bar = current_idx
        
        if short_signal:
            self.sell()
            self.entry_price = close_price
            self.stop_loss = short_sl
            self.take_profit = short_tp
            self.initial_risk_dist = short_risk_dist
            self.pos_size = short_pos_size
            self.exp_profit = short_exp_profit
            self.rr_ratio = short_rr
            self.trade_dir = -1
            self.in_trade = True
            self.last_trade_bar = current_idx