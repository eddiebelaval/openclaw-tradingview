import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend Following
    trend_ema_fast = 21
    trend_ema_slow = 50
    trend_ema_filter = 200
    
    # MTF Filter
    mtf_ema_fast = 21
    mtf_ema_slow = 55
    
    # MA Ribbon
    ribbon_ma1 = 8
    ribbon_ma2 = 13
    ribbon_ma3 = 21
    ribbon_ma4 = 34
    ribbon_ma5 = 55
    ribbon_ma6 = 89
    ribbon_ma7 = 144
    ribbon_ma8 = 233
    ribbon_threshold = 6
    
    # Strategy Params
    breakout_length = 20
    bb_length = 20
    bb_mult = 2.0
    rsi_length = 14
    rsi_ob = 70
    rsi_os = 30
    
    # Risk Management
    atr_length = 14
    stop_atr_mult = 2.0
    tp_atr_mult = 3.0
    trailing_atr_mult = 1.5
    
    # Filters
    adx_length = 14
    adx_threshold = 20
    volume_mult = 1.2
    
    # Order Flow
    vwap_std_mult1 = 1.0
    cvd_length = 20
    cvd_threshold = 0.6
    
    # Smart Money
    ob_lookback = 10
    fvg_min_size = 0.5
    liquidity_lookback = 20
    bos_pivot_length = 5
    ds_impulse_mult = 1.5
    
    # Volatility
    bb_vr_length = 20
    bb_vr_mult = 2.0
    atr_percentile_length = 100
    vol_expansion_threshold = 1.5
    vol_contraction_threshold = 0.7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # EMAs for trend
        self.ema_fast = self.I(pta.ema, close, length=self.trend_ema_fast)
        self.ema_slow = self.I(pta.ema, close, length=self.trend_ema_slow)
        self.ema_filter = self.I(pta.ema, close, length=self.trend_ema_filter)
        
        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=self.adx_length)
        self.adx_val = self.I(lambda: adx_result.get('ADX_14') if adx_result is not None and 'ADX_14' in adx_result.columns else pd.Series(20, index=close.index))
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Bollinger Bands
        bb_result = self.I(pta.bbands, close, length=self.bb_length, std=self.bb_mult)
        self.bb_upper = self.I(lambda: bb_result.get(f'BBU_{self.bb_length}_{self.bb_mult}') if bb_result is not None else pd.Series(close.mean() + close.std(), index=close.index))
        self.bb_lower = self.I(lambda: bb_result.get(f'BBL_{self.bb_length}_{self.bb_mult}') if bb_result is not None else pd.Series(close.mean() - close.std(), index=close.index))
        
        # Volume SMA
        self.volume_sma = self.I(pta.sma, volume, length=20)
        
        # Highest High and Lowest Low
        self.highest_high = self.I(lambda: high.rolling(self.breakout_length).max())
        self.lowest_low = self.I(lambda: low.rolling(self.breakout_length).min())
        
        # MA Ribbon (using EMA)
        self.r1 = self.I(pta.ema, close, length=self.ribbon_ma1)
        self.r2 = self.I(pta.ema, close, length=self.ribbon_ma2)
        self.r3 = self.I(pta.ema, close, length=self.ribbon_ma3)
        self.r4 = self.I(pta.ema, close, length=self.ribbon_ma4)
        self.r5 = self.I(pta.ema, close, length=self.ribbon_ma5)
        self.r6 = self.I(pta.ema, close, length=self.ribbon_ma6)
        self.r7 = self.I(pta.ema, close, length=self.ribbon_ma7)
        self.r8 = self.I(pta.ema, close, length=self.ribbon_ma8)
        
        # VWAP calculation
        self.vwap = self.I(self._calc_vwap, close, high, low, volume)

    def _calc_vwap(self, close, high, low, volume):
        hlc3 = (high + low + close) / 3
        cumulative_volume_price = (hlc3 * volume).cumsum()
        cumulative_volume = volume.cumsum()
        vwap = cumulative_volume_price / cumulative_volume
        return vwap

    def next(self):
        if len(self.data) < max(self.ribbon_ma8, self.atr_percentile_length):
            return
        
        # Get current values
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        atr_val = self.atr_val[-1] if len(self.atr_val) > 0 else 0
        ema_fast_val = self.ema_fast[-1] if len(self.ema_fast) > 0 else close_val
        ema_slow_val = self.ema_slow[-1] if len(self.ema_slow) > 0 else close_val
        ema_filter_val = self.ema_filter[-1] if len(self.ema_filter) > 0 else close_val
        adx_val = self.adx_val[-1] if len(self.adx_val) > 0 else 20
        rsi_val = self.rsi[-1] if len(self.rsi) > 0 else 50
        
        bb_upper = self.bb_upper[-1] if len(self.bb_upper) > 0 else close_val
        bb_lower = self.bb_lower[-1] if len(self.bb_lower) > 0 else close_val
        
        volume_sma = self.volume_sma[-1] if len(self.volume_sma) > 0 else volume_val
        
        highest_high = self.highest_high[-1] if len(self.highest_high) > 0 else high_val
        lowest_low = self.lowest_low[-1] if len(self.lowest_low) > 0 else low_val
        
        # Ribbon signals
        ribbon_bullish_count = 0
        if self.r1[-1] > self.r2[-1]:
            ribbon_bullish_count += 1
        if self.r2[-1] > self.r3[-1]:
            ribbon_bullish_count += 1
        if self.r3[-1] > self.r4[-1]:
            ribbon_bullish_count += 1
        if self.r4[-1] > self.r5[-1]:
            ribbon_bullish_count += 1
        if self.r5[-1] > self.r6[-1]:
            ribbon_bullish_count += 1
        if self.r6[-1] > self.r7[-1]:
            ribbon_bullish_count += 1
        if self.r7[-1] > self.r8[-1]:
            ribbon_bullish_count += 1
        
        ribbon_bullish = ribbon_bullish_count >= (self.ribbon_threshold - 1)
        ribbon_filter_long = ribbon_bullish
        
        # Trend conditions
        volume_spike = volume_val > volume_sma * self.volume_mult
        is_trending = adx_val > self.adx_threshold
        is_ranging = adx_val <= self.adx_threshold
        
        bullish_trend = ema_fast_val > ema_slow_val and close_val > ema_filter_val
        bearish_trend = ema_fast_val < ema_slow_val and close_val < ema_filter_val
        
        # Entry conditions
        ema_cross_up = len(self.ema_fast) > 1 and crossover(self.ema_fast, self.ema_slow)
        ema_cross_down = len(self.ema_fast) > 1 and crossover(self.ema_slow, self.ema_fast)
        
        rsi_cross_up = len(self.rsi) > 1 and crossover(self.rsi, pd.Series(self.rsi_os, index=self.data.index))
        rsi_cross_down = len(self.rsi) > 1 and crossover(pd.Series(self.rsi_ob, index=self.data.index), self.rsi)
        
        trend_long = is_trending and bullish_trend and ema_cross_up and volume_spike
        trend_short = is_trending and bearish_trend and ema_cross_down and volume_spike
        
        breakout_long = close_val > highest_high and volume_spike and close_val > ema_filter_val
        breakout_short = close_val < lowest_low and volume_spike and close_val < ema_filter_val
        
        mean_reversion_long = is_ranging and close_val < bb_lower and rsi_val < self.rsi_os and rsi_cross_up
        mean_reversion_short = is_ranging and close_val > bb_upper and rsi_val > self.rsi_ob and rsi_cross_down
        
        long_condition = (trend_long or breakout_long or mean_reversion_long) and ribbon_filter_long
        short_condition = (trend_short or breakout_short or mean_reversion_short) and not ribbon_filter_long
        
        # Position management
        if self.position:
            return
        
        if long_condition:
            stop_loss = close_val - (atr_val * self.stop_atr_mult)
            take_profit = close_val + (atr_val * self.tp_atr_mult)
            self.buy()
        
        elif short_condition:
            stop_loss = close_val + (atr_val * self.stop_atr_mult)
            take_profit = close_val - (atr_val * self.tp_atr_mult)
            self.sell()


