import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 10
    volMultiplier = 1.2
    emaFastLen = 5
    emaSlowLen = 9
    offsetATR = 0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMAs
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)
        
        # EMA Spread
        self.emaSpread = self.I(lambda: (self.emaFast - self.emaSlow).abs())
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Highest High and Lowest Low
        self.highestHigh = self.I(lambda: high.rolling(window=self.lookback).max())
        self.lowestLow = self.I(lambda: low.rolling(window=self.lookback).min())
        
        # Average Volume
        self.avgVol = self.I(pta.sma, volume, length=self.lookback)

    def next(self):
        if len(self.data) < self.lookback + 2:
            return
        
        # Current values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        # Previous values
        highestHigh_prev = self.highestHigh[-2] if len(self.highestHigh) > 1 else self.highestHigh[-1]
        lowestLow_prev = self.lowestLow[-2] if len(self.lowestLow) > 1 else self.lowestLow[-1]
        emaSpread_prev = self.emaSpread[-2] if len(self.emaSpread) > 1 else self.emaSpread[-1]
        atr_prev = self.atr[-2] if len(self.atr) > 1 else self.atr[-1]
        avgVol = self.avgVol[-1] if self.avgVol[-1] is not None else volume
        
        # Conditions
        emaSpreadRising = self.emaSpread[-1] > emaSpread_prev
        atrRising = self.atr[-1] > atr_prev
        volOK = volume > avgVol * self.volMultiplier
        
        bullBreak = close > highestHigh_prev
        bearBreak = close < lowestLow_prev
        
        bullSignal = bullBreak and emaSpreadRising and atrRising and volOK
        bearSignal = bearBreak and emaSpreadRising and atrRising and volOK
        
        # Trading logic
        if bullSignal and not self.position:
            self.buy()
        elif bearSignal and self.position:
            self.position.close()

