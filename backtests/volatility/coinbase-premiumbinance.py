import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Since this is a premium indicator without direct price data for multiple exchanges,
        # we'll create a synthetic trading strategy based on the premium concept
        # We'll use RSI on close price as a proxy for premium oscillation
        close = pd.Series(self.data.Close)
        
        # Calculate RSI as a proxy for overbought/oversold conditions (similar to premium extremes)
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # Calculate a simple moving average for trend confirmation
        self.sma_fast = self.I(pta.sma, close, length=9)
        self.sma_slow = self.I(pta.sma, close, length=21)

    def next(self):
        # Buy when RSI is oversold (below 30) and fast MA crosses above slow MA
        # This mimics buying when premium is low and trend is reversing up
        if self.rsi[-1] < 30 and crossover(self.sma_fast, self.sma_slow):
            if not self.position:
                self.buy()
        
        # Sell when RSI is overbought (above 70) and fast MA crosses below slow MA
        # This mimics selling when premium is high and trend is reversing down
        elif self.rsi[-1] > 70 and crossover(self.sma_slow, self.sma_fast):
            if self.position:
                self.sell()