import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Moving averages
        self.ma20 = self.I(pta.sma, close, length=20)
        self.ma50 = self.I(pta.sma, close, length=50)
        
        # Trend MA for big trades filter
        self.ma_trend = self.I(pta.sma, close, length=200)
        
        # Big trades parameters
        self.final_bt_mult = 3.0
        self.final_lookback = 500
        
        # Detect asset type and set parameters
        ticker = str(self.data._name) if hasattr(self.data, '_name') else "UNKNOWN"
        if "BTC" in ticker:
            self.final_bt_mult = 3.2
            self.final_lookback = 80
        elif "XAU" in ticker or "GOLD" in ticker:
            self.final_bt_mult = 2.0
            self.final_lookback = 250
        elif "US30" in ticker or "NAS100" in ticker:
            self.final_bt_mult = 3.5
            self.final_lookback = 100
        
        # Calculate big trades metrics
        self.range_size = self.I(lambda: high - low)
        
        self.raw_buy_vol = self.I(lambda: np.where(
            (high - low) == 0, 
            0, 
            (close - low) / (high - low) * volume
        ))
        
        self.raw_sell_vol = self.I(lambda: np.where(
            (high - low) == 0, 
            0, 
            (high - close) / (high - low) * volume
        ))
        
        self.avg_buy_vol = self.I(lambda: pta.sma(
            pd.Series(np.where(
                (high - low) == 0, 
                0, 
                (close - low) / (high - low) * volume
            )), 
            length=self.final_lookback
        ) or pd.Series(0, index=close.index))
        
        self.std_buy_vol = self.I(lambda: pta.stdev(
            pd.Series(np.where(
                (high - low) == 0, 
                0, 
                (close - low) / (high - low) * volume
            )), 
            length=self.final_lookback
        ) or pd.Series(0, index=close.index))
        
        self.avg_sell_vol = self.I(lambda: pta.sma(
            pd.Series(np.where(
                (high - low) == 0, 
                0, 
                (high - close) / (high - low) * volume
            )), 
            length=self.final_lookback
        ) or pd.Series(0, index=close.index))
        
        self.std_sell_vol = self.I(lambda: pta.stdev(
            pd.Series(np.where(
                (high - low) == 0, 
                0, 
                (high - close) / (high - low) * volume
            )), 
            length=self.final_lookback
        ) or pd.Series(0, index=close.index))
        
        # Imbalance detection
        self.is_imb_h = self.I(lambda: low > np.roll(high, 2))
        self.is_imb_b = self.I(lambda: high < np.roll(low, 2))
        
        self.last_buy_signal = False
        self.last_sell_signal = False

    def next(self):
        if len(self.data) < 5:
            return
        
        # Get current values
        close_val = self.data.Close[-1]
        ma20_val = self.ma20[-1]
        ma50_val = self.ma50[-1]
        ma_trend_val = self.ma_trend[-1] if len(self.ma_trend) > 0 else close_val
        
        # Calculate big trade thresholds
        if len(self.avg_buy_vol) > 0 and len(self.std_buy_vol) > 0:
            thresh_buy = self.avg_buy_vol[-1] + self.std_buy_vol[-1] * self.final_bt_mult
        else:
            thresh_buy = float('inf')
        
        if len(self.avg_sell_vol) > 0 and len(self.std_sell_vol) > 0:
            thresh_sell = self.avg_sell_vol[-1] + self.std_sell_vol[-1] * self.final_bt_mult
        else:
            thresh_sell = float('inf')
        
        # Get raw volumes
        if len(self.raw_buy_vol) > 0:
            raw_buy = self.raw_buy_vol[-1]
        else:
            raw_buy = 0
        
        if len(self.raw_sell_vol) > 0:
            raw_sell = self.raw_sell_vol[-1]
        else:
            raw_sell = 0
        
        # Detect big trades
        is_bt_buy = (raw_buy > thresh_buy) and (close_val > ma_trend_val)
        is_bt_sell = (raw_sell > thresh_sell) and (close_val < ma_trend_val)
        
        # Detect imbalances
        is_imb_h = False
        is_imb_b = False
        
        if len(self.data) >= 3:
            is_imb_h = self.data.Low[-1] > self.data.High[-3]
            is_imb_b = self.data.High[-1] < self.data.Low[-3]
        
        # Trading logic: Buy on upside imbalance + bullish MA or big buy
        buy_signal = (is_imb_h or is_bt_buy) and (ma20_val > ma50_val)
        sell_signal = (is_imb_b or is_bt_sell) and (ma20_val < ma50_val)
        
        # Entry logic
        if buy_signal and not self.last_buy_signal:
            if not self.position:
                self.buy()
            self.last_buy_signal = True
        else:
            self.last_buy_signal = False
        
        if sell_signal and not self.last_sell_signal:
            if self.position:
                self.sell()
            self.last_sell_signal = True
        else:
            self.last_sell_signal = False
        
        # Exit logic: MA crossover
        if self.position and crossover(self.ma50, self.ma20):
            self.sell()


