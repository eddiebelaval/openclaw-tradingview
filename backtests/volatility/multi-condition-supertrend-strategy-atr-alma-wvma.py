        alma_curr = self.fastALMA[-1]
        
        # Long condition: direction < 0 and VWMA crosses above ALMA
        goLongCondition = (direction_curr < 0) and (vwma_prev <= alma_prev) and (vwma_curr > alma_curr)
        
