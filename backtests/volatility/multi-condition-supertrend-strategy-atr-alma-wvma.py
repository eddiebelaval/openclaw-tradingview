        direction_prev = self.direction[-2]
        direction_curr = self.direction[-1]
        
        vwma_prev = self.fastVWMA[-2] if len(self.fastVWMA) >= 2 else self.fastVWMA[-1]
        vwma_curr = self.fastVWMA[-1]
        
