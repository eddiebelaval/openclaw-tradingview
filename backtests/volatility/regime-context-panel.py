import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen = 200
    slopeLen = 20
    adxLen = 14
    adxSmooth = 14
    adxTrend = 20.0
    atrLen = 14
    atrAvgLen = 100
    atrExpMult = 1.25
    rangeLen = 50
    rangeAtrMult = 6.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema = self.I(pta.ema, close, length=self.emaLen)
        self.ema_slope = self.I(lambda: (close - close.shift(self.slopeLen)) / self.slopeLen)
        
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adxLen, scalar=100))
        self.adx = self.I(lambda: adx_result['ADX_14'] if adx_result is not None and 'ADX_14' in adx_result.columns else pd.Series(0, index=close.index))
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.atr_pct = self.I(lambda: (self.atr / close * 100.0).fillna(0))
        self.atr_pct_avg = self.I(pta.sma, self.atr_pct, length=self.atrAvgLen)
        self.atr_pct_std = self.I(lambda: pd.Series(self.atr_pct).rolling(self.atrAvgLen).std())
        
        self.highest = self.I(lambda: high.rolling(self.rangeLen).max())
        self.lowest = self.I(lambda: low.rolling(self.rangeLen).min())
        
        self.regime_prev = None
        self.regime_current = None

    def next(self):
        if len(self.data) < max(self.emaLen, self.atrAvgLen, self.rangeLen) + 1:
            return
        
        close_val = self.data.Close[-1]
        ema_val = self.ema[-1]
        ema_slope_val = self.ema_slope[-1]
        adx_val = self.adx[-1] if self.adx[-1] is not np.nan else 0
        atr_val = self.atr[-1]
        atr_pct_val = self.atr_pct[-1]
        atr_pct_avg_val = self.atr_pct_avg[-1] if self.atr_pct_avg[-1] is not np.nan else 0
        atr_pct_std_val = self.atr_pct_std[-1] if self.atr_pct_std[-1] is not np.nan else 0
        
        above_ema = close_val >= ema_val
        slope_up = ema_slope_val > 0
        slope_dn = ema_slope_val < 0
        
        trend_strong = adx_val >= self.adxTrend
        
        vol_exp = atr_pct_avg_val > 0 and atr_pct_val > atr_pct_avg_val * self.atrExpMult
        
        hi_val = self.highest[-1]
        lo_val = self.lowest[-1]
        range_width = hi_val - lo_val
        range_ratio = (range_width / (atr_val * self.rangeAtrMult)) if atr_val > 0 else np.nan
        range_bound = not np.isnan(range_ratio) and range_ratio < 1.0
        
        chop = not trend_strong and not range_bound
        
        if vol_exp:
            regime = "VOL_EXP"
        elif trend_strong and above_ema and slope_up:
            regime = "TREND_UP"
        elif trend_strong and not above_ema and slope_dn:
            regime = "TREND_DOWN"
        elif range_bound:
            regime = "RANGE_BOUND"
        elif chop:
            regime = "CHOP"
        else:
            regime = "TRANSITION"
        
        if self.regime_prev is None:
            self.regime_prev = regime
            self.regime_current = regime
        else:
            self.regime_prev = self.regime_current
            self.regime_current = regime
        
        regime_changed = self.regime_prev != self.regime_current
        
        if self.position:
            if regime == "TREND_DOWN" or regime == "CHOP" or regime == "VOL_EXP":
                self.sell()
            elif regime == "TRANSITION" and not above_ema:
                self.sell()
        else:
            if regime == "TREND_UP" and above_ema and slope_up:
                self.buy()
            elif regime == "RANGE_BOUND" and crossover(close_val, lo_val):
                self.buy()