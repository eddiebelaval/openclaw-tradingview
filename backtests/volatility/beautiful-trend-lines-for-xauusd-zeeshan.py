class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Parameters
        _fast = 34
        _slow = 89
        _swingLen = 20
        _atrLen = 14
        _volLen = 20
        _rangeFactor = 0.45
        _breakoutPct = 0.001
        
        # Core indicators
        self.fastEma = self.I(pta.ema, close, length=_fast)
        self.slowEma = self.I(pta.ema, close, length=_slow)
        self.atr = self.I(pta.atr, high, low, close, length=_atrLen)
        self.atrMa = self.I(pta.sma, self.atr, length=_atrLen)
        self.volMa = self.I(pta.sma, volume, length=_volLen)
        
        # Recent high/low using rolling
        self.recentHigh = self.I(lambda: high.rolling(_swingLen).max())
        self.recentLow = self.I(lambda: low.rolling(_swingLen).min())
        
        # Slope absolute value
        self.slopeAbs = self.I(lambda: (self.fastEma - self.fastEma.shift(1)).abs())
        
        # EMA conditions
        self.emaBull = self.I(lambda: self.fastEma > self.slowEma)
        self.emaBear = self.I(lambda: self.fastEma < self.slowEma)
        
        # Slope conditions
        self.slopeBull = self.I(lambda: self.fastEma > self.fastEma.shift(1))
        self.slopeBear = self.I(lambda: self.fastEma < self.fastEma.shift(1))
        
        # Flat slope
        self.flatSlope = self.I(lambda: self.slopeAbs < self.atr * 0.1)
        
        # Structure
        self.structBull = self.I(lambda: close > self.recentLow)
        self.structBear = self.I(lambda: close < self.recentHigh)
        self.noStruct = self.I(lambda: ~self.structBull & ~self.structBear)
        
        # Volume and ATR expansion
        self.volExp = self.I(lambda: volume > self.volMa)
        self.atrExp = self.I(lambda: self.atr > self.atrMa)
        self.atrCompression = self.I(lambda: self.atr < self.atrMa * _rangeFactor)
        self.isRanging = self.I(lambda: self.atrCompression & self.flatSlope & self.noStruct)
        
        # Breakouts
        self.breakoutUp = self.I(lambda: close > self.recentHigh * (1 + _breakoutPct))
        self.breakoutDown = self.I(lambda: close < self.recentLow * (1 - _breakoutPct))
        
        # Raw signals
        self.rawBullPossible = self.I(lambda: ((self.emaBull & self.slopeBull & self.structBull & ~self.isRanging) | self.breakoutUp))
