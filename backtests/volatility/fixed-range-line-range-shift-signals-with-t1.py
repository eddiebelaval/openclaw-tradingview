import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    step = 10.0
    enableT1 = True
    t1Distance = 20.0

    def init(self):
        self.level = None
        self.prevLevel = None
        self.t1Level = None
        self.t1Active = False
        self.tradeDirection = 0
        
        self.buy_signals = []
        self.sell_signals = []
        self.t1_hit_buy_signals = []
        self.t1_hit_sell_signals = []

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        if self.level is None:
            self.level = close
            self.prevLevel = self.level
            return
        
        self.prevLevel = self.level
        
        if close >= self.level + self.step:
            self.level = self.level + self.step
        elif close <= self.level - self.step:
            self.level = self.level - self.step
        
        newUpShift = self.level > self.prevLevel
        newDownShift = self.level < self.prevLevel
        
        buySignal = newUpShift
        sellSignal = newDownShift
        
        if self.enableT1:
            if buySignal:
                self.tradeDirection = 1
                self.t1Level = close + self.t1Distance
                self.t1Active = True
            
            if sellSignal:
                self.tradeDirection = -1
                self.t1Level = close - self.t1Distance
                self.t1Active = True
        
        t1HitBuy = self.t1Active and self.tradeDirection == 1 and high >= self.t1Level
        t1HitSell = self.t1Active and self.tradeDirection == -1 and low <= self.t1Level
        
        if t1HitBuy or t1HitSell:
            self.t1Active = False
        
        if buySignal:
            if not self.position:
                self.buy()
        elif sellSignal:
            if self.position:
                self.position.close()
            else:
                self.sell()
        
        if t1HitBuy and self.position:
            self.position.close()
        
        if t1HitSell and self.position:
            self.position.close()


