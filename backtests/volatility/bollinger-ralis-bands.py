import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Bollinger Bands parameters
    bb_length = 20
    bb_mult = 2.0
    adapt_bb = False
    adapt_atr_len = 14
    adapt_avg_len = 100
    adapt_min_mult = 1.2
    adapt_max_mult = 3.0
    
    # Ralis Ribbon parameters
    enable_ribbon = True
    ribbon_fast = 12
    ribbon_slow = 24
    enable_gap = True
    min_gap_pct = 0.24
    
    # Signal parameters
    buy_cooldown = 2
    sell_cooldown = 2
    max_buy_tiers = 6
    max_sell_tiers = 10
    
    # Other parameters
    rsi_div_len = 14
    pivot_look_l = 5
    pivot_look_r = 2
    div_lookback = 60
    bbwp_len = 124
    bbwp_comp_max = 15
    bbwp_exp_min = 85

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hl2 = (high + low) / 2.0
        
        # Bollinger Bands calculation
        self.basis = self.I(pta.sma, close, length=self.bb_length)
        
        # ATR for adaptive BB
        atr_result = self.I(pta.atr, high, low, close, length=self.adapt_atr_len)
        atr_avg = self.I(pta.sma, atr_result, length=self.adapt_avg_len)
        
        # Effective multiplier (adaptive or static)
        def calc_eff_mult():
            result = []
            for i in range(len(close)):
                if i < max(self.adapt_atr_len, self.adapt_avg_len):
                    result.append(self.bb_mult)
                else:
                    atr_val = atr_result[i]
                    atr_avg_val = atr_avg[i]
                    if atr_avg_val > 0:
                        vol_ratio = atr_val / atr_avg_val
                        adapt_mult = self.adapt_min_mult + (vol_ratio - 1.0) * (self.adapt_max_mult - self.adapt_min_mult)
                        eff = max(self.adapt_min_mult, min(adapt_mult, self.adapt_max_mult))
                    else:
                        eff = self.bb_mult
                    result.append(eff if self.adapt_bb else self.bb_mult)
            return pd.Series(result)
        
        self.eff_mult = self.I(calc_eff_mult)
        
        # Standard deviation
        def calc_dev():
            stdev = close.rolling(window=self.bb_length).std()
            result = []
            for i in range(len(close)):
                if pd.isna(stdev.iloc[i]) or pd.isna(self.eff_mult[i]):
                    result.append(0)
                else:
                    result.append(self.eff_mult[i] * stdev.iloc[i])
            return pd.Series(result)
        
        self.dev = self.I(calc_dev)
        
        self.upper = self.I(lambda: self.basis + self.dev)
        self.lower = self.I(lambda: self.basis - self.dev)
        
        # BB Width and BBWP
        def calc_bbwp():
            bb_width = []
            for i in range(len(close)):
                if self.basis[i] != 0:
                    bw = (self.upper[i] - self.lower[i]) / self.basis[i] * 100.0
                else:
                    bw = 0.0
                bb_width.append(bw)
            
            bw_series = pd.Series(bb_width)
            percentrank_result = []
            for i in range(len(bw_series)):
                if i < self.bbwp_len:
                    percentrank_result.append(0)
                else:
                    window = bw_series.iloc[i - self.bbwp_len + 1:i + 1]
                    rank = (window < bw_series.iloc[i]).sum() / self.bbwp_len * 100.0
                    percentrank_result.append(rank)
            
            return pd.Series(percentrank_result)
        
        self.bbwp = self.I(calc_bbwp)
        
        # Ralis Ribbon (SMMA)
        def calc_smma(src, length):
            smma_vals = []
            smma = None
            for i in range(len(src)):
                if i < length:
                    smma = src.iloc[:i+1].mean()
                else:
                    if smma is None:
                        smma = src.iloc[:length].mean()
                    smma = (smma * (length - 1) + src.iloc[i]) / length
                smma_vals.append(smma)
            return pd.Series(smma_vals)
        
        self.ribbon_fast = self.I(lambda: calc_smma(hl2, self.ribbon_fast))
        self.ribbon_slow = self.I(lambda: calc_smma(hl2, self.ribbon_slow))
        
        # RSI for divergence
        self.div_rsi = self.I(pta.rsi, close, length=self.rsi_div_len)
        
        # RSI for table display
        self.tbl_rsi = self.I(pta.rsi, close, length=14)
        
        # ATR for ADX calculation (DMI)
        self.atr_dmi = self.I(pta.atr, high, low, close, length=14)
        
        # Signal tracking
        self.last_buy_bar = -999
        self.last_sell_bar = -999
        self.buy_count = 0
        self.sell_count = 0
        self.in_sell_phase = False

    def next(self):
        if len(self.data) < max(self.bb_length, self.adapt_avg_len + 10):
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        bar_idx = len(self.data) - 1
        
        # Ribbon conditions
        ribbon_bull = self.ribbon_fast[-1] > self.ribbon_slow[-1]
        ribbon_gap_pct = abs(self.ribbon_fast[-1] - self.ribbon_slow[-1]) / self.ribbon_slow[-1] * 100.0 if self.ribbon_slow[-1] != 0 else 0.0
        ribbon_gap_ok = not self.enable_gap or ribbon_gap_pct >= self.min_gap_pct
        ribbon_buy_ok = not self.enable_ribbon or (not ribbon_bull and ribbon_gap_ok)
        ribbon_sell_ok = not self.enable_ribbon or (ribbon_bull and ribbon_gap_ok)
        
        # Cooldown checks
        buy_cd_ok = (bar_idx - self.last_buy_bar) >= self.buy_cooldown
        sell_cd_ok = (bar_idx - self.last_sell_bar) >= self.sell_cooldown
        
        # Raw signals
        buy_raw = close < self.lower[-1]
        sell_raw = close > self.upper[-1]
        
        # Tier checks
        buy_tier_ok = self.buy_count < self.max_buy_tiers
        sell_tier_ok = self.sell_count < self.max_sell_tiers
        
        # Final signals
        buy_signal = buy_raw and buy_cd_ok and buy_tier_ok and ribbon_buy_ok
        sell_signal = sell_raw and sell_cd_ok and sell_tier_ok and ribbon_sell_ok
        
        # Update counters
        if buy_signal:
            self.last_buy_bar = bar_idx
            if self.in_sell_phase:
                self.sell_count = 0
                self.in_sell_phase = False
            self.buy_count += 1
            self.buy()
        
        if sell_signal:
            self.last_sell_bar = bar_idx
            if not self.in_sell_phase:
                self.buy_count = 0
                self.in_sell_phase = True
            self.sell_count += 1
            self.sell()