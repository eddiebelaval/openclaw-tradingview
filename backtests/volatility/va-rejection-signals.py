import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 30
    va_mult = 1.0
    use_time_filter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate VWAP
        self.vwap_val = self.I(pta.vwap, high, low, close)
        
        # Calculate standard deviation
        self.price_stddev = self.I(pta.stdev, close, length=self.lookback)
        
        # Calculate VAH and VAL
        def calc_vah(vwap, stddev):
            if vwap is None or stddev is None:
                return pd.Series(0, index=close.index)
            return vwap + (stddev * self.va_mult)
        
        def calc_val(vwap, stddev):
            if vwap is None or stddev is None:
                return pd.Series(0, index=close.index)
            return vwap - (stddev * self.va_mult)
        
        self.vah = self.I(lambda: calc_vah(self.vwap_val, self.price_stddev))
        self.val = self.I(lambda: calc_val(self.vwap_val, self.price_stddev))

    def next(self):
        if len(self.data) < self.lookback + 1:
            return
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        
        current_vah = self.vah[-1]
        current_val = self.val[-1]
        
        # BUY: Low went below VAL, but candle closed back above it + Bullish candle
        signal_buy = (current_low < current_val and 
                      current_close > current_val and 
                      current_close > current_open)
        
        # SELL: High went above VAH, but candle closed back below it + Bearish candle
        signal_sell = (current_high > current_vah and 
                       current_close < current_vah and 
                       current_close < current_open)
        
        if signal_buy and not self.position:
            self.buy()
        elif signal_sell and self.position:
            self.position.close()