import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Compression Engine
    compLen = 20
    compRatio = 0.6
    minBars = 5
    
    # Trade Management
    tpPct = 0.5
    slPct = 0.25
    maxBars = 40
    
    # Momentum Filter
    rsiLen = 14
    volLen = 20
    useVolFil = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR values
        self.atr14 = self.I(pta.atr, high, low, close, length=14)
        self.atrSlow = self.I(pta.atr, high, low, close, length=self.compLen * 2)
        
        # RSI and Volume MA
        self.rsi14 = self.I(pta.rsi, close, length=self.rsiLen)
        self.volMa = self.I(pta.sma, volume, length=self.volLen)
        
        # Highest high and lowest low over compression period
        self.vaultHigh = self.I(lambda: high.rolling(self.compLen).max())
        self.vaultLow = self.I(lambda: low.rolling(self.compLen).min())
        
        # Track compression state
        self.compBars = 0
        self.lastVaultBar = -1000
        self.active_vaults = []

    def next(self):
        if len(self.data) < self.compLen + 1:
            return
        
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        atr14_val = self.atr14[-1]
        atrSlow_val = self.atrSlow[-1]
        rsi14_val = self.rsi14[-1]
        volMa_val = self.volMa[-1]
        vaultHigh_val = self.vaultHigh[-1]
        vaultLow_val = self.vaultLow[-1]
        
        if pd.isna(atr14_val) or pd.isna(atrSlow_val) or pd.isna(vaultHigh_val):
            return
        
        # Compression condition
        is_compressed = atr14_val / max(atrSlow_val, 1e-6) < self.compRatio
        
        # Update compression bar counter
        if is_compressed:
            self.compBars += 1
        else:
            self.compBars = 0
        
        # Vault ready when minimum bars in compression reached
        vault_ready = self.compBars >= self.minBars
        
        # Volume confirmation
        vol_ok = (not self.useVolFil) or (volume_val > volMa_val)
        
        # Breakout conditions
        bull_break = close_val > vaultHigh_val and vol_ok
        bear_break = close_val < vaultLow_val and vol_ok
        
        # RSI filters
        rsi_ok_bull = rsi14_val < 75
        rsi_ok_bear = rsi14_val > 25
        
        # Create vault and enter trade
        if vault_ready and len(self) - self.lastVaultBar > self.compLen:
            if bull_break and rsi_ok_bull:
                entry_price = close_val
                tp = entry_price * (1 + self.tpPct / 100)
                sl = entry_price * (1 - self.slPct / 100)
                
                vault_info = {
                    'entry_price': entry_price,
                    'tp': tp,
                    'sl': sl,
                    'entry_bar': len(self),
                    'is_long': True,
                    'vault_high': vaultHigh_val,
                    'vault_low': vaultLow_val
                }
                self.active_vaults.append(vault_info)
                self.lastVaultBar = len(self)
                self.buy()
            
            elif bear_break and rsi_ok_bear:
                entry_price = close_val
                tp = entry_price * (1 - self.tpPct / 100)
                sl = entry_price * (1 + self.slPct / 100)
                
                vault_info = {
                    'entry_price': entry_price,
                    'tp': tp,
                    'sl': sl,
                    'entry_bar': len(self),
                    'is_long': False,
                    'vault_high': vaultHigh_val,
                    'vault_low': vaultLow_val
                }
                self.active_vaults.append(vault_info)
                self.lastVaultBar = len(self)
                self.sell()
        
        # Monitor active trades
        vaults_to_remove = []
        for i, vault in enumerate(self.active_vaults):
            bars_held = len(self) - vault['entry_bar']
            
            if vault['is_long']:
                # TP, SL, or max bars exit
                if high_val >= vault['tp']:
                    self.position.close()
                    vaults_to_remove.append(i)
                elif low_val <= vault['sl']:
                    self.position.close()
                    vaults_to_remove.append(i)
                elif bars_held >= self.maxBars:
                    self.position.close()
                    vaults_to_remove.append(i)
            else:
                # Short position
                if low_val <= vault['tp']:
                    self.position.close()
                    vaults_to_remove.append(i)
                elif high_val >= vault['sl']:
                    self.position.close()
                    vaults_to_remove.append(i)
                elif bars_held >= self.maxBars:
                    self.position.close()
                    vaults_to_remove.append(i)
        
        # Remove completed vaults
        for i in sorted(vaults_to_remove, reverse=True):
            self.active_vaults.pop(i)