import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 20
    smoothInput = 100
    signalInput = 10
    pctRankInput = 252

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Parkinson Volatility calculation
        def calc_park_vol():
            logHL2 = np.power(np.log(high / low), 2)
            parkVar = pta.sma(logHL2, length=self.lengthInput) / (4.0 * np.log(2))
            parkVol = np.sqrt(parkVar) * 100
            return parkVol

        self.parkVol = self.I(calc_park_vol)

        # Z-score normalization
        def calc_osc():
            parkMA = pta.sma(self.parkVol, length=self.smoothInput)
            parkSD = pta.stdev(self.parkVol, length=self.smoothInput)
            osc = np.where(parkSD > 0, (self.parkVol - parkMA) / parkSD, 0.0)
            return pd.Series(osc, index=close.index)

        self.osc = self.I(calc_osc)

        # Signal line
        self.signal = self.I(pta.ema, self.osc, length=self.signalInput)

        # Percentile rank
        def calc_pct_rank():
            return pta.percentrank(self.parkVol, length=self.pctRankInput)

        self.pctRank = self.I(calc_pct_rank)

        # ATR-based z-score
        def calc_atr_osc():
            atrVol = pta.atr(high, low, close, length=self.lengthInput) / close * 100
            atrMA = pta.sma(atrVol, length=self.smoothInput)
            atrSD = pta.stdev(atrVol, length=self.smoothInput)
            atrOsc = np.where(atrSD > 0, (atrVol - atrMA) / atrSD, 0.0)
            return pd.Series(atrOsc, index=close.index)

        self.atrOsc = self.I(calc_atr_osc)

    def next(self):
        # Expansion cross: osc crosses above signal and osc > 0
        expansion_cross = crossover(self.osc, self.signal) and self.osc[-1] > 0

        # Compression cross: osc crosses below signal and osc < 0
        compression_cross = crossover(self.signal, self.osc) and self.osc[-1] < 0

        # Trading logic based on volatility regime
        if expansion_cross:
            # Expansion signal - buy
            if not self.position:
                self.buy()

        elif compression_cross:
            # Compression signal - sell
            if self.position:
                self.position.close()

        # Additional exit condition: if osc drops significantly
        if self.position and self.osc[-1] < -1.0:
            self.position.close()

        # Additional entry condition: percentile rank extremely low (compression)
        if not self.position and self.pctRank[-1] < 20 and self.osc[-1] > -1.0 and crossover(self.osc, self.signal):
            self.buy()


