import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    dv_bull_thr = 0.58
    dv_bear_thr = 0.42

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)

        self.close_arr = close
        self.high_arr = high
        self.low_arr = low
        self.volume_arr = volume
        self.open_arr = open_

        self.prev_score = 0

    def next(self):
        if len(self.data) < 2:
            return

        idx = len(self.data) - 1
        o = self.open_arr.iloc[idx]
        c = self.close_arr.iloc[idx]
        h = self.high_arr.iloc[idx]
        l = self.low_arr.iloc[idx]
        v = self.volume_arr.iloc[idx]

        green = c > o
        delta = v if c > o else -v if c < o else 0.0

        sp = h - l
        if sp > 0:
            buy_vol = v * (c - l) / sp
            sell_vol = v * (h - c) / sp
        else:
            buy_vol = v * 0.5
            sell_vol = v * 0.5

        total_vol = buy_vol + sell_vol
        dv_ratio = buy_vol / total_vol if total_vol > 0 else 0.5

        hid_buy = dv_ratio > self.dv_bull_thr and not green
        hid_sell = dv_ratio < self.dv_bear_thr and green

        score = 0
        if delta > 0:
            score += 1
        elif delta < 0:
            score -= 1

        if dv_ratio > self.dv_bull_thr:
            score += 1
        elif dv_ratio < self.dv_bear_thr:
            score -= 1

        if hid_buy:
            score += 2
        elif hid_sell:
            score -= 2

        current_score = score

        if current_score >= 3 and self.prev_score < 3:
            if not self.position:
                self.buy()
        elif current_score <= -3 and self.prev_score > -3:
            if self.position:
                self.position.close()

        self.prev_score = current_score