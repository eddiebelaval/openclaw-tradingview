import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 100
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Since we're using a single price series as proxy for VIX/VIXEQ ratio analysis
        # We'll create a synthetic ratio-like indicator based on price momentum
        
        # Calculate spread-like measure (using price range)
        self.spread = self.I(lambda: pd.Series(high - low, index=close.index))
        
        # Calculate SMA of spread
        self.spread_ma = self.I(lambda: pta.sma(pd.Series(high - low, index=close.index), length=20))
        
        # Calculate ratio-like measure (using momentum)
        self.ratio = self.I(lambda: close / close.shift(20))
        self.ratio = self.I(lambda: self.ratio.fillna(1.0))
        
        # Calculate SMA of ratio
        self.ratio_ma = self.I(lambda: pta.sma(self.ratio, length=50) if self.ratio is not None else pd.Series(1.0, index=close.index))
        
        # Calculate mean and std dev for adaptive thresholds
        self.spread_mean = self.I(lambda: pta.sma(pd.Series(high - low, index=close.index), length=self.lookback))
        self.spread_stddev = self.I(lambda: pd.Series(high - low, index=close.index).rolling(self.lookback).std())
        
        self.ratio_mean = self.I(lambda: pta.sma(self.ratio, length=self.lookback) if self.ratio is not None else pd.Series(1.0, index=close.index))
        self.ratio_stddev = self.I(lambda: self.ratio.rolling(self.lookback).std() if self.ratio is not None else pd.Series(0.1, index=close.index))
        
        # Calculate Z-Score
        self.zscore = self.I(lambda: (self.spread - self.spread_mean) / (self.spread_stddev + 0.0001) if self.spread_mean is not None and self.spread_stddev is not None else pd.Series(0, index=close.index))
        
        # Regime thresholds
        self.concentration_threshold = self.I(lambda: self.ratio_mean - 1.0 * self.ratio_stddev if self.ratio_mean is not None and self.ratio_stddev is not None else pd.Series(0.9, index=close.index))
        self.normal_upper_threshold = self.I(lambda: self.ratio_mean - 0.25 * self.ratio_stddev if self.ratio_mean is not None and self.ratio_stddev is not None else pd.Series(1.0, index=close.index))
        self.dispersion_threshold = self.I(lambda: self.ratio_mean + 0.5 * self.ratio_stddev if self.ratio_mean is not None and self.ratio_stddev is not None else pd.Series(1.1, index=close.index))
        self.systemic_threshold = self.I(lambda: self.ratio_mean + 1.5 * self.ratio_stddev if self.ratio_mean is not None and self.ratio_stddev is not None else pd.Series(1.25, index=close.index))
    
    def next(self):
        # Determine current regime based on ratio levels
        current_ratio = self.ratio[-1] if len(self.ratio) > 0 and self.ratio[-1] is not None else 1.0
        
        try:
            conc_thresh = self.concentration_threshold[-1] if len(self.concentration_threshold) > 0 and self.concentration_threshold[-1] is not None else 0.9
            norm_upper_thresh = self.normal_upper_threshold[-1] if len(self.normal_upper_threshold) > 0 and self.normal_upper_threshold[-1] is not None else 1.0
            disp_thresh = self.dispersion_threshold[-1] if len(self.dispersion_threshold) > 0 and self.dispersion_threshold[-1] is not None else 1.1
            sys_thresh = self.systemic_threshold[-1] if len(self.systemic_threshold) > 0 and self.systemic_threshold[-1] is not None else 1.25
        except:
            conc_thresh = 0.9
            norm_upper_thresh = 1.0
            disp_thresh = 1.1
            sys_thresh = 1.25
        
        # Classify regime
        is_systemic = current_ratio >= sys_thresh
        is_dispersion = current_ratio >= disp_thresh and current_ratio < sys_thresh
        is_elevated = current_ratio >= norm_upper_thresh and current_ratio < disp_thresh
        is_normal = current_ratio >= conc_thresh and current_ratio < norm_upper_thresh
        is_concentration = current_ratio < conc_thresh
        
        # Trading logic: Enter on regime transitions
        # Buy signals: Entering normal or concentration (lower risk regimes)
        if is_concentration or is_normal:
            if not self.position:
                self.buy()
        
        # Sell signals: Entering elevated, dispersion or systemic (higher risk regimes)
        if is_elevated or is_dispersion or is_systemic:
            if self.position:
                self.sell()
        
        # Additional signal: Z-score extremes for mean reversion
        try:
            current_zscore = self.zscore[-1] if len(self.zscore) > 0 and self.zscore[-1] is not None else 0
            
            # Extreme negative Z-score (spread contracted): potential buy
            if current_zscore < -2 and not self.position:
                self.buy()
            
            # Extreme positive Z-score (spread expanded): potential sell
            if current_zscore > 2 and self.position:
                self.sell()
        except:
            pass


