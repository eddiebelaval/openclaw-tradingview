import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    processNoisePos = 0.05
    processNoiseVel = 0.0001
    measurementNoise = 250
    bandLookback = 200
    bandMultiplier = 2.6
    m = 7.88

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Initialize Kalman Filter state variables
        self.x_p = np.zeros(len(self.data))
        self.x_v = np.zeros(len(self.data))
        self.p00 = np.zeros(len(self.data))
        self.p01 = np.zeros(len(self.data))
        self.p10 = np.zeros(len(self.data))
        self.p11 = np.zeros(len(self.data))
        
        # Initialize first values
        self.x_p[0] = close.iloc[0]
        self.x_v[0] = 0.0
        self.p00[0] = 1.0
        self.p01[0] = 0.0
        self.p10[0] = 0.0
        self.p11[0] = 1.0
        
        self.kalman_price = self.I(self._compute_kalman_filter, close)
        
        self.abs_diff = self.I(lambda: (close - self.kalman_price).abs())
        
        self.mae = self.I(lambda: pta.sma(self.abs_diff, length=self.bandLookback) or pd.Series(0, index=close.index))
        
        self.upper_band = self.I(lambda: self.kalman_price + self.bandMultiplier * self.mae)
        self.lower_band = self.I(lambda: self.kalman_price - self.bandMultiplier * self.mae)

    def _compute_kalman_filter(self, close):
        kalman_prices = np.zeros(len(close))
        
        for i in range(len(close)):
            if i == 0:
                self.x_p[i] = close.iloc[0]
                self.x_v[i] = 0.0
                self.p00[i] = 1.0
                self.p01[i] = 0.0
                self.p10[i] = 0.0
                self.p11[i] = 1.0
                kalman_prices[i] = self.x_p[i]
            else:
                # PREDICT
                pPrime = self.x_p[i-1] + self.x_v[i-1]
                vPrime = self.x_v[i-1]
                
                a00 = 1 * self.p00[i-1] + 1 * self.p10[i-1]
                a01 = 1 * self.p01[i-1] + 1 * self.p11[i-1]
                a10 = 0 * self.p00[i-1] + 1 * self.p10[i-1]
                a11 = 0 * self.p01[i-1] + 1 * self.p11[i-1]
                
                p00_ = a00 * 1 + a01 * 1
                p01_ = a00 * 0 + a01 * 1
                p10_ = a10 * 1 + a11 * 1
                p11_ = a10 * 0 + a11 * 1
                
                p00_ += self.processNoisePos
                p11_ += self.processNoiseVel
                
                # UPDATE
                z = close.iloc[i]
                y = z - pPrime
                S = p00_ + self.measurementNoise
                K0 = p00_ / S
                K1 = p10_ / S
                
                x_p_upd = pPrime + K0 * y
                x_v_upd = vPrime + K1 * y
                
                i00 = 1 - K0
                i01 = 0.0
                i10 = -K1
                i11 = 1.0
                
                pp00 = i00 * p00_ + i01 * p10_
                pp01 = i00 * p01_ + i01 * p11_
                pp10 = i10 * p00_ + i11 * p10_
                pp11 = i10 * p01_ + i11 * p11_
                
                self.x_p[i] = x_p_upd
                self.x_v[i] = x_v_upd
                self.p00[i] = pp00
                self.p01[i] = pp01
                self.p10[i] = pp10
                self.p11[i] = pp11
                
                kalman_prices[i] = self.x_p[i]
        
        return pd.Series(kalman_prices, index=close.index)

    def next(self):
        if len(self.data) < self.bandLookback + 1:
            return
        
        # Check for bullish crossover (close crosses above upper band)
        if len(self.data) > 1:
            if (self.data.Close[-2] <= self.upper_band[-2] and 
                self.data.Close[-1] > self.upper_band[-1]):
                if not self.position:
                    self.buy()
            
            # Check for bearish crossunder (close crosses below lower band)
            if (self.data.Close[-2] >= self.lower_band[-2] and 
                self.data.Close[-1] < self.lower_band[-1]):
                if self.position:
                    self.position.close()


