class TvStrategy(Strategy):
    def init(self):
        self.range1_start_hour = 9
        self.range1_start_minute = 0
        self.range1_end_hour = 9
        self.range1_end_minute = 5
        
        self.range2_start_hour = 16
        self.range2_start_minute = 30
        self.range2_end_hour = 17
        self.range2_end_minute = 0
        
        self.range3_start_hour = 18
        self.range3_start_minute = 5
        self.range3_end_hour = 20
        self.range3_end_minute = 0
        
