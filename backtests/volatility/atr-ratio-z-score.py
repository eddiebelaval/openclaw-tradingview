import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    shortLen = 5
    longLen = 20
    zLen = 50
    smoothLen = 1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for short and long periods
        atr_short = self.I(pta.atr, high, low, close, length=self.shortLen)
        atr_long = self.I(pta.atr, high, low, close, length=self.longLen)
        
        # Calculate ATR Ratio with divide-by-zero protection
        def calc_atr_ratio(atr_s, atr_l):
            ratio = np.where(atr_l != 0, atr_s / atr_l, np.nan)
            return pd.Series(ratio, index=close.index)
        
        atr_ratio_raw = self.I(calc_atr_ratio, atr_short, atr_long)
        
        # Optional smoothing
        if self.smoothLen > 1:
            atr_ratio = self.I(pta.sma, atr_ratio_raw, length=self.smoothLen)
        else:
            atr_ratio = atr_ratio_raw
        
        # Calculate Z-Score
        def calc_zscore(ratio, z_len):
            mean = ratio.rolling(window=z_len).mean()
            std = ratio.rolling(window=z_len).std()
            zscore = np.where(std != 0, (ratio - mean) / std, np.nan)
            return pd.Series(zscore, index=ratio.index)
        
        self.zscore = self.I(calc_zscore, atr_ratio, self.zLen)

    def next(self):
        # Trading logic based on Z-Score
        # Buy when transitioning from compression (-1) to expansion (+1)
        if len(self.data) < 2:
            return
        
        current_zscore = self.zscore[-1]
        prev_zscore = self.zscore[-2]
        
        # Avoid NaN values
        if pd.isna(current_zscore) or pd.isna(prev_zscore):
            return
        
        # Buy signal: Z-Score crosses above 0 from below (compression to expansion)
        if prev_zscore <= 0 and current_zscore > 0:
            if not self.position:
                self.buy()
        
        # Sell signal: Z-Score crosses below 0 from above (expansion to compression)
        elif prev_zscore >= 0 and current_zscore < 0:
            if self.position:
                self.position.close()


