import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Macro SAR Settings
    ma_start = 0.01
    ma_inc = 0.01
    ma_max = 0.15
    ma_mult = 1.5
    
    # Micro SAR Settings
    mi_start = 0.02
    mi_inc = 0.02
    mi_max = 0.2
    mi_mult = 1.0
    
    # Macro EMA Settings
    ema_len = 21
    
    # Confirmation
    use_confirmed = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR for offset calculations
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # SAR calculations - using pandas rolling implementation
        def calc_sar_with_atr(close_series, high_series, low_series, 
                              af_start, af_inc, af_max, atr_mult):
            sar_vals = []
            is_bull_vals = []
            
            af = af_start
            hp = high_series.iloc[0]
            lp = low_series.iloc[0]
            sar = low_series.iloc[0]
            is_bull = True
            
            for i in range(len(close_series)):
                if is_bull:
                    sar = sar + af * (hp - sar)
                    sar = min(sar, low_series.iloc[max(0, i-1):i+1].min())
                    
                    if high_series.iloc[i] > hp:
                        hp = high_series.iloc[i]
                        af = min(af + af_inc, af_max)
                    
                    if low_series.iloc[i] < sar:
                        is_bull = False
                        sar = hp
                        lp = low_series.iloc[i]
                        af = af_start
                else:
                    sar = sar - af * (sar - lp)
                    sar = max(sar, high_series.iloc[max(0, i-1):i+1].max())
                    
                    if low_series.iloc[i] < lp:
                        lp = low_series.iloc[i]
                        af = min(af + af_inc, af_max)
                    
                    if high_series.iloc[i] > sar:
                        is_bull = True
                        sar = lp
                        hp = high_series.iloc[i]
                        af = af_start
                
                sar_vals.append(sar)
                is_bull_vals.append(is_bull)
            
            return pd.Series(sar_vals, index=close_series.index), pd.Series(is_bull_vals, index=close_series.index)
        
        # Calculate macro SAR
        def get_macro_sar():
            sar, is_bull = calc_sar_with_atr(close, high, low, 
                                             self.ma_start, self.ma_inc, self.ma_max, self.ma_mult)
            return sar, is_bull
        
        # Calculate micro SAR
        def get_micro_sar():
            sar, is_bull = calc_sar_with_atr(close, high, low,
                                             self.mi_start, self.mi_inc, self.mi_max, self.mi_mult)
            return sar, is_bull
        
        # Get SAR values and trend direction
        macro_sar, macro_is_bull = get_macro_sar()
        micro_sar, micro_is_bull = get_micro_sar()
        
        # Apply ATR offset
        def apply_offset(sar_series, is_bull_series, atr_series, mult):
            offset = atr_series * mult
            result = pd.Series(index=sar_series.index, dtype=float)
            for i in range(len(sar_series)):
                if is_bull_series.iloc[i]:
                    result.iloc[i] = sar_series.iloc[i] - offset.iloc[i]
                else:
                    result.iloc[i] = sar_series.iloc[i] + offset.iloc[i]
            return result
        
        self.m_lsar = self.I(lambda: apply_offset(macro_sar, macro_is_bull, self.atr, self.ma_mult))
        self.m_bull = self.I(lambda: macro_is_bull)
        
        self.u_lsar = self.I(lambda: apply_offset(micro_sar, micro_is_bull, self.atr, self.mi_mult))
        self.u_bull = self.I(lambda: micro_is_bull)
        
        # EMA for reference
        self.m_ema = self.I(pta.ema, close, length=self.ema_len)
        
        # Alignment states
        def get_bull_align():
            result = pd.Series(index=close.index, dtype=bool)
            for i in range(len(close)):
                result.iloc[i] = self.u_bull[-1] and self.m_bull[-1] if i == len(close) - 1 else False
            return result
        
        def get_bear_align():
            result = pd.Series(index=close.index, dtype=bool)
            for i in range(len(close)):
                result.iloc[i] = (not self.u_bull[-1]) and (not self.m_bull[-1]) if i == len(close) - 1 else False
            return result
        
        self.bull_align = self.I(lambda: pd.Series([self.u_bull[-1] and self.m_bull[-1]] * len(close), index=close.index))
        self.bear_align = self.I(lambda: pd.Series([(not self.u_bull[-1]) and (not self.m_bull[-1])] * len(close), index=close.index))

    def next(self):
        # Check for alignment transitions
        current_bull_align = self.u_bull[-1] and self.m_bull[-1]
        current_bear_align = (not self.u_bull[-1]) and (not self.m_bull[-1])
        
        prev_bull_align = self.u_bull[-2] and self.m_bull[-2] if len(self.u_bull) > 1 else False
        prev_bear_align = (not self.u_bull[-2]) and (not self.m_bull[-2]) if len(self.u_bull) > 1 else False
        
        bull_align_new = current_bull_align and not prev_bull_align
        bear_align_new = current_bear_align and not prev_bear_align
        
        # Entry and exit logic based on alignment
        if bull_align_new and not self.position:
            self.buy()
        elif bear_align_new and self.position:
            self.sell()
        
        # Exit longs on bearish alignment
        if current_bear_align and self.position.is_long:
            self.sell()
        
        # Exit shorts on bullish alignment
        if current_bull_align and self.position.is_short:
            self.buy()