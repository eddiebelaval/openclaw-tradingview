import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    smoothing = "RMA"
    basis_opt = "Current Open"
    wait_close = True
    flip_scale = False

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate True Range
        def calc_tr():
            tr1 = high - low
            tr2 = np.abs(high - close.shift(1))
            tr3 = np.abs(low - close.shift(1))
            tr = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
            return tr

        tr = self.I(calc_tr)

        # Apply smoothing to TR
        def calc_atr():
            tr_series = calc_tr()
            if self.smoothing == "RMA":
                return pta.rma(tr_series, length=self.length)
            elif self.smoothing == "SMA":
                return pta.sma(tr_series, length=self.length)
            elif self.smoothing == "EMA":
                return pta.ema(tr_series, length=self.length)
            else:  # WMA
                return pta.wma(tr_series, length=self.length)

        atr_value = self.I(calc_atr)

        # Calculate basis price
        def calc_basis():
            if self.basis_opt == "Current Open":
                return open_
            else:
                return close.shift(1)

        basis_price = self.I(calc_basis)

        # Calculate ATR percentage
        def calc_atr_percent():
            atr = calc_atr()
            basis = calc_basis()
            atr_pct = np.where(basis != 0, (atr / basis) * 100, np.nan)
            return pd.Series(atr_pct, index=close.index)

        raw_atr_percent = self.I(calc_atr_percent)

        # Apply flip scale
        def calc_plot_val():
            raw = calc_atr_percent()
            if self.flip_scale:
                return -raw
            else:
                return raw

        self.atr_percent = self.I(calc_plot_val)

        # Calculate 3-day and 7-day extremes
        self.low3 = self.I(lambda: self.atr_percent.rolling(window=3).min())
        self.high3 = self.I(lambda: self.atr_percent.rolling(window=3).max())
        self.low7 = self.I(lambda: self.atr_percent.rolling(window=7).min())
        self.high7 = self.I(lambda: self.atr_percent.rolling(window=7).max())

    def next(self):
        # Simple trading logic based on ATR percentage extremes
        # Buy when ATR% reaches 3-day low (potential volatility drying up)
        # Sell when ATR% reaches 3-day high (heightened volatility)

        if len(self.data) < 3:
            return

        current_atr = self.atr_percent[-1]
        low3_val = self.low3[-1]
        high3_val = self.high3[-1]

        # Avoid NaN values
        if pd.isna(current_atr) or pd.isna(low3_val) or pd.isna(high3_val):
            return

        # Buy signal: current ATR% is at 3-day low (low volatility)
        if current_atr == low3_val and low3_val != high3_val and not self.position:
            self.buy()

        # Sell signal: current ATR% is at 3-day high (high volatility)
        elif current_atr == high3_val and low3_val != high3_val and self.position:
            self.sell()


