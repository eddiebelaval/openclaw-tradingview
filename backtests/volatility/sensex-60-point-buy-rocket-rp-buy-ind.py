import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    rsi_buy = 65
    ma_fast = 9
    ma_slow = 21
    target_points = 60

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)

        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_length) or pd.Series(50, index=close.index))
        self.ma9 = self.I(pta.ema, close, length=self.ma_fast)
        self.ma21 = self.I(pta.ema, close, length=self.ma_slow)
        self.atr = self.I(pta.atr, high, low, close, length=14)
        self.vol_avg = self.I(pta.sma, volume, length=20)
        
        self.open_prices = open_
        self.high_prices = high
        self.low_prices = low
        self.close_prices = close
        self.volumes = volume

    def next(self):
        if len(self.data) < 2:
            return

        close = self.close_prices.iloc[-1]
        open_ = self.open_prices.iloc[-1]
        high_prev = self.high_prices.iloc[-2]
        volume = self.volumes.iloc[-1]

        trend_bull = self.ma9[-1] > self.ma21[-1]
        momentum_strong = self.rsi[-1] > self.rsi_buy and self.rsi[-1] < 80
        breakout = close > high_prev and volume > self.vol_avg[-1] * 1.5
        candle_power = (close - open_) > self.atr[-1] * 0.8

        buy_rocket = trend_bull and momentum_strong and breakout and candle_power

        if buy_rocket and not self.position:
            self.buy()
        elif self.position:
            target_price = self.position.open_price + self.target_points
            if close >= target_price:
                self.position.close()
            elif close < self.ma21[-1]:
                self.position.close()