import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Account & Risk Management
    account_size = 6000
    risk_percent = 3
    stop_loss_mult = 1.0
    is_btc_pair = True
    leverage_btc = 5
    leverage_alt = 2
    atr_period = 14
    risk_reward_ratio = 3.33
    
    # Regime & Correlation
    corr_len = 30
    vol_look = 200
    
    # Volume Intelligence
    use_dollar_vol = True
    vol_lookback = 50
    
    # Volume Spike Watch
    quiet_vol_pctile = 20
    quiet_atr_pctile = 30
    quiet_rvol_max = 0.70
    pace_lookback = 50
    pace_spike_mult = 2.0
    close_bar_spike_mult = 2.0
    
    # Surge
    show_surge_prob = True
    surge_alert_thresh = 70
    
    # LEAD SCORE weights
    w_quiet = 0.30
    w_preheat = 0.15
    w_obv = 0.15
    w_early_pace = 0.20
    w_market = 0.10
    w_surge_heuristic = 0.10
    w_penalty_reactive = 0.30
    reactive_rvol_cut = 1.50
    reactive_vol_pct = 80
    early_window_frac = 0.35
    
    # MTF, RS, Dominance, Patterns
    use_htf_regime = True
    rs_len = 40
    rs_smooth = 10
    use_dominance = True
    nr_len = 7
    ib_lookback = 6
    lead_ready_thresh = 70
    cooldown_bars = 20
    
    # MTF weights
    w_mtf = 0.18
    w_rs = 0.18
    w_dom = 0.12
    w_pat = 0.12
    
    # Position side
    position_side = "Short"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core ATR
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # Volume metrics
        sym_vol_raw = volume
        sym_vol = sym_vol_raw * close if self.use_dollar_vol else sym_vol_raw
        
        # RVOL
        self.avg_vol = self.I(pta.sma, pd.Series(sym_vol), length=self.vol_lookback)
        self.rvol = self.I(lambda: (sym_vol / self.avg_vol).fillna(1.0))
        
        # Volume percentrank
        self.vol_pct_rank = self.I(lambda: sym_vol.rolling(self.vol_lookback).apply(
            lambda x: (x[-1] > x[:-1]).sum() / len(x[:-1]) * 100 if len(x) > 1 else 50
        ).fillna(50))
        
        # ATR%
        self.atr_pct = self.I(lambda: (self.atr_val / close * 100).fillna(0))
        self.atr_pct_pr = self.I(lambda: self.atr_pct.rolling(self.vol_look).apply(
            lambda x: (x[-1] > x[:-1]).sum() / len(x[:-1]) * 100 if len(x) > 1 else 50
        ).fillna(50))
        
        # Bollinger Bands
        bb_len = 20
        self.bb_basis = self.I(pta.sma, close, length=bb_len)
        bb_std = self.I(lambda: close.rolling(bb_len).std().fillna(0))
        self.bb_upper = self.I(lambda: self.bb_basis + 2.0 * bb_std)
        self.bb_lower = self.I(lambda: self.bb_basis - 2.0 * bb_std)
        self.bb_width = self.I(lambda: (
            ((self.bb_upper - self.bb_lower) / self.bb_basis * 100).fillna(0)
        ))
        self.bb_width_pr = self.I(lambda: self.bb_width.rolling(200).apply(
            lambda x: (x[-1] > x[:-1]).sum() / len(x[:-1]) * 100 if len(x) > 1 else 50
        ).fillna(50))
        
        # Pre-heat (EMA ratio of volume)
        ema10_vol = self.I(pta.ema, pd.Series(sym_vol), length=10)
        ema50_vol = self.I(pta.ema, pd.Series(sym_vol), length=50)
        self.preheat_ratio = self.I(lambda: (ema10_vol / ema50_vol).fillna(1.0))
        
        # OBV
        self.obv = self.I(lambda: (
            (close > close.shift(1)).astype(int) * volume
            - (close < close.shift(1)).astype(int) * volume
        ).cumsum())
        obv_delta = self.I(pta.ema, pd.Series(self.obv.diff()), length=8)
        self.obv_pr = self.I(lambda: obv_delta.rolling(200).apply(
            lambda x: (x[-1] > x[:-1]).sum() / len(x[:-1]) * 100 if len(x) > 1 else 50
        ).fillna(50))
        
        # Range (for NR7)
        self.rng = self.I(lambda: high - low)
        
        # Inside bar
        self.is_inside = self.I(lambda: (
            (high <= high.shift(1)) & (low >= low.shift(1))
        ).astype(float))
        
        self.ib_cluster = self.I(pta.sma, self.is_inside, length=self.ib_lookback)
        
        # Market RVOL (using market proxy: BTC)
        self.market_rvol = self.I(lambda: pd.Series(1.5, index=close.index))
        
        # RS vs BTC (simplified: use momentum)
        rs_momentum = self.I(pta.roc, close, length=self.rs_len)
        self.rs_slope = self.I(pta.ema, rs_momentum, length=self.rs_smooth)
        self.rs_pr = self.I(lambda: self.rs_slope.rolling(200).apply(
            lambda x: (x[-1] > x[:-1]).sum() / len(x[:-1]) * 100 if len(x) > 1 else 50
        ).fillna(50))
        
        # Initialize lead score
        self.lead_score_pct = self.I(lambda: pd.Series(50, index=close.index))
    
    def next(self):
        # Simple trading logic based on LEAD SCORE
        # When lead score crosses above 70, consider entry signal
        
        if len(self.data) < 2:
            return
        
        # Risk calculations
        risk_amount = self.account_size * self.risk_percent / 100
        atr_val = self.atr_val[-1]
        
        if atr_val <= 0 or self.data.Close[-1] <= 0:
            return
        
        stop_loss_frac = (atr_val * self.stop_loss_mult) / self.data.Close[-1]
        stop_loss_perc = stop_loss_frac * 100
        
        if stop_loss_perc <= 0:
            return
        
        pos_size = risk_amount / stop_loss_frac
        current_leverage = self.leverage_btc if self.is_btc_pair else self.leverage_alt
        margin_required = pos_size / current_leverage
        take_profit_perc = stop_loss_perc * self.risk_reward_ratio
        
        # Entry/SL/TP levels
        sl_pct = stop_loss_perc / 100.0
        tp_pct = take_profit_perc / 100.0
        entry = self.data.Close[-1]
        
        if self.position_side == "Long":
            sl_price = entry * (1 - sl_pct)
            tp_price = entry * (1 + tp_pct)
        else:
            sl_price = entry * (1 + sl_pct)
            tp_price = entry * (1 - tp_pct)
        
        # Simple trading rule: if lead score is high, consider entry
        # (In real scenario, this would be more sophisticated)
        
        # For now, use a simple momentum-based entry
        quiet_score = 0
        preheat_score = 0
        obv_score = 0
        early_pace_score = 0
        market_score = 0
        surge_score = 0
        mtf_squeeze = 0
        rs_score = 0
        dom_score = 0
        pat_score = 0
        
        # Calculate quiet regime
        if not np.isnan(self.vol_pct_rank[-1]) and not np.isnan(self.atr_pct_pr[-1]):
            vol_quiet = self.vol_pct_rank[-1] <= self.quiet_vol_pctile
            atr_quiet = self.atr_pct_pr[-1] <= self.quiet_atr_pctile
            if vol_quiet and atr_quiet:
                quiet_score = 0.7
        
        # Calculate preheat
        if not np.isnan(self.preheat_ratio[-1]):
            preheat_val = np.clip((self.preheat_ratio[-1] - 1.0) / 0.5, 0, 1)
            preheat_score = preheat_val
        
        # Calculate OBV score
        if not np.isnan(self.obv_pr[-1]):
            obv_score = np.clip((self.obv_pr[-1] - 50.0) / 50.0, 0, 1)
        
        # Calculate RS score
        if not np.isnan(self.rs_pr[-1]):
            rs_score = np.clip(self.rs_pr[-1] / 100.0, 0, 1)
        
        # Calculate pattern score
        lowest_rng = self.rng[-self.nr_len:].min() if len(self.rng) >= self.nr_len else self.rng[-1]
        is_nr7 = self.rng[-1] <= lowest_rng
        pat_score = (1.0 if is_nr7 else 0.0) + np.clip(self.ib_cluster[-1], 0, 1) * 0.6
        pat_score = np.clip(pat_score, 0, 1)
        
        # Weighted lead score
        w_all = max(0.0001, self.w_quiet + self.w_preheat + self.w_obv + self.w_early_pace + 
                    self.w_market + self.w_surge_heuristic + self.w_mtf + self.w_rs + self.w_dom + self.w_pat)
        
        lead_numerator = (quiet_score * self.w_quiet + preheat_score * self.w_preheat + 
                         obv_score * self.w_obv + early_pace_score * self.w_early_pace + 
                         market_score * self.w_market + surge_score * self.w_surge_heuristic + 
                         mtf_squeeze * self.w_mtf + rs_score * self.w_rs + dom_score * self.w_dom + 
                         pat_score * self.w_pat)
        
        lead_raw = (lead_numerator / w_all)
        lead_score = np.clip(lead_raw * 100, 0, 100)
        
        # Entry/Exit logic
        if not self.position:
            # Entry signal when lead score exceeds threshold and quiet regime
            if lead_score >= self.lead_ready_thresh and quiet_score > 0.5:
                if self.position_side == "Long":
                    self.buy(size=0.95)
                else:
                    self.sell(size=0.95)
        else:
            # Exit on take profit or stop loss
            if self.position_side == "Long":
                if self.data.Close[-1] >= tp_price:
                    self.position.close()
                elif self.data.Close[-1] <= sl_price:
                    self.position.close()
            else:
                if self.data.Close[-1] <= tp_price:
                    self.position.close()
                elif self.data.Close[-1] >= sl_price:
                    self.position.close()


