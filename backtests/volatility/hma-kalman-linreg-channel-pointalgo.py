import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 16
    baseMult = 1.5
    trendLook = 20
    trendThresh = 1.0
    R_in = 0.01
    Q_in = 0.10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate HMA
        self.hma_line = self.I(pta.hma, close, length=self.len)
        
        # Calculate Kalman Filter
        self.kalman_line = self.I(self._kalman_filter, close)
        
        # Calculate Linear Regression
        self.linreg_line = self.I(pta.linreg, close, length=self.len)
        
        # Calculate Average Line (Mid Line)
        self.avg_line = self.I(
            lambda: (self.hma_line + self.kalman_line + self.linreg_line) / 3.0
        )
        
        # Calculate ATR
        self.atr_val = self.I(pta.atr, high, low, close, length=self.len)
        
        # Calculate Mid Line Change
        self.mid_line_change = self.I(self._calc_mid_line_change)
        
        # Determine if Trending
        self.is_trending = self.I(self._calc_is_trending)
        
        # Calculate Final Multiplier
        self.final_mult = self.I(self._calc_final_mult)
        
        # Calculate Bands
        self.upper_band = self.I(self._calc_upper_band)
        self.lower_band = self.I(self._calc_lower_band)

    def _kalman_filter(self):
        close = pd.Series(self.data.Close)
        estimate = np.full(len(close), np.nan)
        error_est = np.full(len(close), 1.0)
        
        for i in range(len(close)):
            if i == 0:
                estimate[i] = close.iloc[0]
            else:
                prediction = estimate[i - 1]
                error_meas = self.R_in * self.len
                kalman_gain = error_est[i - 1] / (error_est[i - 1] + error_meas)
                estimate[i] = prediction + kalman_gain * (close.iloc[i] - prediction)
                error_est[i] = (1.0 - kalman_gain) * error_est[i - 1] + self.Q_in / self.len
        
        return pd.Series(estimate, index=close.index)

    def _calc_mid_line_change(self):
        if len(self.avg_line) < self.trendLook + 1:
            return pd.Series(0.0, index=self.data.Close.index)
        
        result = np.full(len(self.avg_line), 0.0)
        for i in range(self.trendLook, len(self.avg_line)):
            result[i] = abs(self.avg_line[i] - self.avg_line[i - self.trendLook])
        
        return pd.Series(result, index=self.data.Close.index)

    def _calc_is_trending(self):
        if self.atr_val is None or self.mid_line_change is None:
            return pd.Series(False, index=self.data.Close.index)
        
        threshold = self.atr_val * self.trendThresh
        return self.mid_line_change > threshold

    def _calc_final_mult(self):
        result = np.full(len(self.is_trending), self.baseMult)
        for i in range(len(self.is_trending)):
            if self.is_trending[i]:
                result[i] = self.baseMult * 0.5
            else:
                result[i] = self.baseMult
        
        return pd.Series(result, index=self.data.Close.index)

    def _calc_upper_band(self):
        return self.avg_line + (self.atr_val * self.final_mult)

    def _calc_lower_band(self):
        return self.avg_line - (self.atr_val * self.final_mult)

    def next(self):
        if len(self.data) < self.trendLook + 1:
            return
        
        # Bull Break: Close crosses above Upper Band
        if crossover(self.data.Close, self.upper_band):
            if not self.position:
                self.buy()
        
        # Bear Break: Close crosses below Lower Band
        if crossover(self.lower_band, self.data.Close):
            if self.position:
                self.position.close()


