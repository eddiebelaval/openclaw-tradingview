        if perfect_bull_now:
            if not self.position:
                self.buy()
        # Perfect bear signal
        elif perfect_bear_now:
            if self.position:
                self.position.close()
        # Regular bull explosion
        elif bull_explosion_now:
            if not self.position:
                self.buy()
        # Regular bear explosion
        elif bear_explosion_now:
            if self.position:
                self.position.close()


