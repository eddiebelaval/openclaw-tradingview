import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Pressure Settings
    rsiLen = 14
    wtLen1 = 10
    wtLen2 = 21
    mfiLen = 14
    stochLen = 14
    useStochPressure = True
    
    # Temperature Settings
    atrLen = 14
    atrMultiplier = 10.0
    useBollingerTemp = True
    bbLen = 20
    bbMult = 2.0
    
    # Volume Settings
    volLen = 20
    steamThreshold = 2.0
    useVolDelta = True
    
    # Explosion Settings
    pressureThreshold = 80
    tempThreshold = 70
    steamThresholdExp = 80
    minConfluence = 3
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        hlc3 = (high + low + close) / 3
        
        # RSI Pressure
        self.rsi_pressure = self.I(pta.rsi, close, length=self.rsiLen)
        
        # WaveTrend Pressure
        def calc_wt():
            esa = pta.ema(hlc3, length=self.wtLen1)
            if esa is None:
                return pd.Series(50, index=close.index)
            d = pta.ema(np.abs(hlc3 - esa), length=self.wtLen1)
            if d is None or (d == 0).all():
                return pd.Series(50, index=close.index)
            ci = (hlc3 - esa) / (0.015 * d)
            wt1 = pta.ema(ci, length=self.wtLen2)
            if wt1 is None:
                return pd.Series(50, index=close.index)
            wt_pressure = (wt1 + 100) / 2
            return wt_pressure.fillna(50)
        
        self.wt_pressure = self.I(calc_wt)
        
        # MFI Pressure
        self.mfi_pressure = self.I(pta.mfi, high, low, close, volume, length=self.mfiLen)
        
        # Stochastic RSI Pressure
        def calc_stoch_pressure():
            rsi = pta.rsi(close, length=self.rsiLen)
            if rsi is None:
                return pd.Series(50, index=close.index)
            stoch = pta.stoch(rsi, rsi, rsi, k=self.stochLen, d=3)
            if stoch is None:
                return pd.Series(50, index=close.index)
            stoch_k = stoch.iloc[:, 0] if isinstance(stoch, pd.DataFrame) else stoch
            return stoch_k.fillna(50)
        
        self.stoch_pressure = self.I(calc_stoch_pressure)
        
        # Combined Pressure
        def calc_total_pressure():
            if self.useStochPressure:
                return (self.rsi_pressure + self.wt_pressure + self.mfi_pressure + self.stoch_pressure) / 4
            else:
                return (self.rsi_pressure + self.wt_pressure + self.mfi_pressure) / 3
        
        self.total_pressure = self.I(calc_total_pressure)
        
        # ATR-based temperature
        def calc_atr_temp():
            atr = pta.atr(high, low, close, length=self.atrLen)
            if atr is None:
                return pd.Series(0, index=close.index)
            atr_pct = (atr / close) * 100
            return atr_pct * self.atrMultiplier
        
        self.atr_temp = self.I(calc_atr_temp)
        
        # Bollinger Band Temperature
        def calc_bb_temp():
            bb = pta.bbands(close, length=self.bbLen, std=self.bbMult)
            if bb is None:
                return pd.Series(0, index=close.index)
            bb_upper = bb.iloc[:, 2] if isinstance(bb, pd.DataFrame) else bb
            bb_lower = bb.iloc[:, 0] if isinstance(bb, pd.DataFrame) else bb
            bb_basis = pta.sma(close, length=self.bbLen)
            if bb_basis is None:
                return pd.Series(0, index=close.index)
            bb_width = ((bb_upper - bb_lower) / bb_basis) * 100
            return (bb_width * 5).fillna(0)
        
        self.bb_temp = self.I(calc_bb_temp)
        
        # Combined Temperature
        def calc_temperature():
            if self.useBollingerTemp:
                temp = (self.atr_temp + self.bb_temp) / 2
            else:
                temp = self.atr_temp
            return np.minimum(temp, 100)
        
        self.temperature = self.I(calc_temperature)
        
        # Volume calculations
        self.vol_ma = self.I(pta.sma, volume, length=self.volLen)
        
        def calc_steam():
            vol_ratio = volume / (self.vol_ma + 1e-10)
            steam_base = vol_ratio * 50
            
            if self.useVolDelta:
                buy_vol = pd.Series(np.where(close > open_, volume, 0), index=close.index)
                sell_vol = pd.Series(np.where(close < open_, volume, 0), index=close.index)
                vol_delta = (buy_vol - sell_vol) / (volume + 1e-10) * 50
                steam = steam_base + np.abs(vol_delta)
            else:
                steam = steam_base
            
            return np.minimum(steam, 100)
        
        self.steam = self.I(calc_steam)
        
        # Volume spike direction
        def calc_vol_spike_up():
            return (self.steam > self.steamThresholdExp) & (close > open_)
        
        def calc_vol_spike_down():
            return (self.steam > self.steamThresholdExp) & (close < open_)
        
        self.vol_spike_up = self.I(calc_vol_spike_up)
        self.vol_spike_down = self.I(calc_vol_spike_down)
        
        # Momentum calculations
        def calc_pressure_momentum():
            return self.total_pressure.diff()
        
        self.pressure_momentum = self.I(calc_pressure_momentum)
        
        def calc_pressure_acceleration():
            return self.pressure_momentum.diff()
        
        self.pressure_accel = self.I(calc_pressure_acceleration)
        
        # Confluence Score
        def calc_confluence():
            extreme_steam = self.steam > 90
            score = pd.Series(0, index=close.index)
            score = score + (self.total_pressure > self.pressureThreshold).astype(int)
            score = score + (self.temperature > self.tempThreshold).astype(int)
            score = score + (self.steam > self.steamThresholdExp).astype(int)
            score = score + ((self.wt_pressure > 80) | (self.wt_pressure < 20)).astype(int)
            score = score + extreme_steam.astype(int)
            return score
        
        self.confluence_score = self.I(calc_confluence)
        
        # Momentum shift detection
        def calc_momentum_shift():
            mom_current = self.pressure_momentum > 0
            mom_prev = self.pressure_momentum.shift(1) <= 0
            mom_shift_up = mom_current & mom_prev
            
            mom_current_down = self.pressure_momentum < 0
            mom_prev_down = self.pressure_momentum.shift(1) >= 0
            mom_shift_down = mom_current_down & mom_prev_down
            
            return mom_shift_up | mom_shift_down
        
        self.momentum_shift = self.I(calc_momentum_shift)
        
        # Explosion conditions
        def calc_explosion():
            mom_shift = self.momentum_shift
            accel_strong = np.abs(self.pressure_accel) > 2
            confluence_met = self.confluence_score >= self.minConfluence
            return confluence_met & (mom_shift | accel_strong)
        
        self.explosion = self.I(calc_explosion)
        
        def calc_bull_explosion():
            return (self.explosion) & (self.total_pressure > 50) & (self.pressure_momentum > 0) & ((close > open_) | self.vol_spike_up)
        
        self.bull_explosion = self.I(calc_bull_explosion)
        
        def calc_bear_explosion():
            return (self.explosion) & (self.total_pressure < 50) & (self.pressure_momentum < 0) & ((close < open_) | self.vol_spike_down)
        
        self.bear_explosion = self.I(calc_bear_explosion)
        
        # Perfect explosion
        def calc_perfect_explosion():
            return (self.confluence_score == 5) & (np.abs(self.pressure_momentum) > 3)
        
        self.perfect_explosion = self.I(calc_perfect_explosion)
        
        def calc_perfect_bull():
            return self.perfect_explosion & (self.total_pressure > 50) & (self.pressure_momentum > 0)
        
        self.perfect_bull = self.I(calc_perfect_bull)
        
        def calc_perfect_bear():
            return self.perfect_explosion & (self.total_pressure < 50) & (self.pressure_momentum < 0)
        
        self.perfect_bear = self.I(calc_perfect_bear)

    def next(self):
        # Simple trading logic based on perfect explosions
        if len(self.data) < 2:
            return
        
        perfect_bull_now = self.perfect_bull[-1] if isinstance(self.perfect_bull[-1], (bool, np.bool_)) else bool(self.perfect_bull[-1])
        perfect_bear_now = self.perfect_bear[-1] if isinstance(self.perfect_bear[-1], (bool, np.bool_)) else bool(self.perfect_bear[-1])
        bull_explosion_now = self.bull_explosion[-1] if isinstance(self.bull_explosion[-1], (bool, np.bool_)) else bool(self.bull_explosion[-1])
        bear_explosion_now = self.bear_explosion[-1] if isinstance(self.bear_explosion[-1], (bool, np.bool_)) else bool(self.bear_explosion[-1])
        
