import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    i_length = 100
    i_zVolThr = 2.5
    i_zRangeThr = 2.0
    i_zExtreme = 3.5
    i_usePct = False
    i_pctThr = 95.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        cande_range = high - low
        
        mean_vol = self.I(pta.sma, volume, length=self.i_length)
        std_vol = self.I(pta.stdev, volume, length=self.i_length)
        mean_range = self.I(pta.sma, cande_range, length=self.i_length)
        std_range = self.I(pta.stdev, cande_range, length=self.i_length)
        
        def safe_z_vol():
            result = pd.Series(index=volume.index, dtype=float)
            for i in range(len(volume)):
                if std_vol[i] != 0:
                    result.iloc[i] = (volume.iloc[i] - mean_vol[i]) / std_vol[i]
                else:
                    result.iloc[i] = 0.0
            return result
        
        def safe_z_range():
            result = pd.Series(index=cande_range.index, dtype=float)
            for i in range(len(cande_range)):
                if std_range[i] != 0:
                    result.iloc[i] = (cande_range.iloc[i] - mean_range[i]) / std_range[i]
                else:
                    result.iloc[i] = 0.0
            return result
        
        self.z_vol = self.I(safe_z_vol)
        self.z_range = self.I(safe_z_range)
        
        def percentile_rank_vol():
            result = pd.Series(index=volume.index, dtype=float)
            for bar_idx in range(len(volume)):
                start = max(0, bar_idx - self.i_length + 1)
                window = volume.iloc[start:bar_idx + 1]
                cnt = sum(1 for v in window if v <= volume.iloc[bar_idx])
                result.iloc[bar_idx] = float(cnt) / float(len(window)) * 100.0
            return result
        
        def percentile_rank_range():
            result = pd.Series(index=cande_range.index, dtype=float)
            for bar_idx in range(len(cande_range)):
                start = max(0, bar_idx - self.i_length + 1)
                window = cande_range.iloc[start:bar_idx + 1]
