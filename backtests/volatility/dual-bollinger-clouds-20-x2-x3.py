import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 20
    mult1 = 2.0
    mult2 = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate basis (SMA)
        self.basis = self.I(pta.sma, close, length=self.len)
        
        # Calculate standard deviation
        self.dev = self.I(lambda x: x.rolling(self.len).std(), close)
        
        # Inner bands (mult1 = 2.0)
        self.upper1 = self.I(lambda: self.basis + self.dev * self.mult1)
        self.lower1 = self.I(lambda: self.basis - self.dev * self.mult1)
        
        # Outer bands (mult2 = 3.0)
        self.upper2 = self.I(lambda: self.basis + self.dev * self.mult2)
        self.lower2 = self.I(lambda: self.basis - self.dev * self.mult2)

    def next(self):
        # Buy when price touches lower outer band and reverses up
        if len(self.data) > self.len:
            if self.data.Close[-1] <= self.lower2[-1] and self.data.Close[-1] > self.data.Close[-2]:
                if not self.position:
                    self.buy()
            
            # Sell when price touches upper outer band and reverses down
            elif self.data.Close[-1] >= self.upper2[-1] and self.data.Close[-1] < self.data.Close[-2]:
                if self.position:
                    self.sell()
            
            # Exit long if price crosses back below basis
            elif self.position and self.data.Close[-1] < self.basis[-1]:
                self.sell()


