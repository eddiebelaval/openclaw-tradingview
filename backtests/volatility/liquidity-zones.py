import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 10
    max_zones = 40
    atr_mult = 0.3
    atr_len = 14
    show_bull = True
    show_bear = True
    touch_dist = 0.5
    show_fvg = True
    max_fvg = 15

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        self.pivot_highs = self.I(self._get_pivot_highs, high)
        self.pivot_lows = self.I(self._get_pivot_lows, low)
        
        self.liquidity_zones = []
        self.broken_zones = []
        self.fvg_zones = []
        
        self.in_position = False

    def _get_pivot_highs(self, high):
        result = pd.Series(np.nan, index=high.index)
        for i in range(self.lookback, len(high) - self.lookback):
            if high.iloc[i] == high.iloc[i-self.lookback:i+self.lookback+1].max():
                result.iloc[i] = high.iloc[i]
        return result

    def _get_pivot_lows(self, low):
        result = pd.Series(np.nan, index=low.index)
        for i in range(self.lookback, len(low) - self.lookback):
            if low.iloc[i] == low.iloc[i-self.lookback:i+self.lookback+1].min():
                result.iloc[i] = low.iloc[i]
        return result

    def _is_duplicate(self, level, is_bull, threshold):
        for zone in self.liquidity_zones:
            if not zone['broken'] and zone['is_bull'] == is_bull:
                if abs(zone['level'] - level) < threshold:
                    return True
        return False

    def next(self):
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.001
        if atr_val <= 0:
            atr_val = 0.001
        
        half_h = atr_val * self.atr_mult * 0.5
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        current_bar = len(self.data) - 1
        
        if not np.isnan(self.pivot_highs[-1]) and self.show_bear:
            lvl = self.pivot_highs[-1]
            if not self._is_duplicate(lvl, False, atr_val * 0.4):
                zone = {
                    'level': lvl,
                    'top': lvl + half_h,
                    'bot': lvl - half_h,
                    'is_bull': False,
                    'touches': 1,
                    'born_bar': current_bar - self.lookback,
                    'broken': False
                }
                self.liquidity_zones.append(zone)
        
        if not np.isnan(self.pivot_lows[-1]) and self.show_bull:
            lvl = self.pivot_lows[-1]
            if not self._is_duplicate(lvl, True, atr_val * 0.4):
                zone = {
                    'level': lvl,
                    'top': lvl + half_h,
                    'bot': lvl - half_h,
                    'is_bull': True,
                    'touches': 1,
                    'born_bar': current_bar - self.lookback,
                    'broken': False
                }
                self.liquidity_zones.append(zone)
        
        zones_to_remove = []
        for i, z in enumerate(self.liquidity_zones):
            broke = False
            if z['is_bull']:
                if current_low < z['bot']:
                    broke = True
            else:
                if current_high > z['top']:
                    broke = True
            
            if broke:
                z['broken'] = True
                self.broken_zones.append(z)
                zones_to_remove.append(i)
                continue
            
            if atr_val > 0 and current_bar > z['born_bar'] + self.lookback:
                touched = False
                if z['is_bull']:
                    if current_low <= z['top'] + atr_val * self.touch_dist and current_low >= z['bot'] and current_close > z['bot']:
                        touched = True
                else:
                    if current_high >= z['bot'] - atr_val * self.touch_dist and current_high <= z['top'] and current_close < z['top']:
                        touched = True
                if touched:
                    z['touches'] += 1
        
        for i in sorted(zones_to_remove, reverse=True):
            self.liquidity_zones.pop(i)
        
        if len(self.broken_zones) > self.max_zones:
            self.broken_zones = self.broken_zones[-(self.max_zones):]
        
        if len(self.liquidity_zones) > self.max_zones:
            self.liquidity_zones = self.liquidity_zones[-(self.max_zones):]
        
        if self.show_fvg and current_bar > 2 and atr_val > 0:
            if len(self.data) > 2:
                low_prev2 = self.data.Low[-3]
                high_prev2 = self.data.High[-3]
                low_curr = self.data.Low[-1]
                high_curr = self.data.High[-1]
                close_prev = self.data.Close[-2]
                open_prev = self.data.Open[-2]
                
                if low_curr > high_prev2 and close_prev > open_prev:
                    gap_top = low_curr
                    gap_bot = high_prev2
                    if gap_top - gap_bot > atr_val * 0.05:
                        fvg = {
                            'top': gap_top,
                            'bot': gap_bot,
                            'is_bull': True,
                            'born_bar': current_bar,
                            'filled': False
                        }
                        self.fvg_zones.append(fvg)
                
                if high_curr < low_prev2 and close_prev < open_prev:
                    gap_top = low_prev2
                    gap_bot = high_curr
                    if gap_top - gap_bot > atr_val * 0.05:
                        fvg = {
                            'top': gap_top,
                            'bot': gap_bot,
                            'is_bull': False,
                            'born_bar': current_bar,
                            'filled': False
                        }
                        self.fvg_zones.append(fvg)
        
        fvg_to_remove = []
        for i, fz in enumerate(self.fvg_zones):
            mitigated = False
            if fz['is_bull']:
                if current_close < fz['bot']:
                    mitigated = True
            else:
                if current_close > fz['top']:
                    mitigated = True
            
            if mitigated:
                fvg_to_remove.append(i)
        
        for i in sorted(fvg_to_remove, reverse=True):
            self.fvg_zones.pop(i)
        
        if len(self.fvg_zones) > self.max_fvg:
            self.fvg_zones = self.fvg_zones[-(self.max_fvg):]
        
        bull_zones = sum(1 for z in self.liquidity_zones if z['is_bull'])
        bear_zones = sum(1 for z in self.liquidity_zones if not z['is_bull'])
        
        if len(self.liquidity_zones) > 0:
            highest_touch_zone = max(self.liquidity_zones, key=lambda x: x['touches'])
            
            if highest_touch_zone['is_bull'] and not self.in_position:
                if current_low >= highest_touch_zone['bot'] and current_low <= highest_touch_zone['top']:
                    self.buy()
                    self.in_position = True
            elif not highest_touch_zone['is_bull'] and self.in_position:
                if current_high >= highest_touch_zone['bot'] and current_high <= highest_touch_zone['top']:
                    self.sell()
                    self.in_position = False
        
        if len(self.fvg_zones) > 0:
            for fvg in self.fvg_zones:
                if fvg['is_bull'] and not self.in_position:
                    if current_low >= fvg['bot'] and current_low <= fvg['top']:
                        self.buy()
                        self.in_position = True
                        break
                elif not fvg['is_bull'] and self.in_position:
                    if current_high >= fvg['bot'] and current_high <= fvg['top']:
                        self.sell()
                        self.in_position = False
                        break


