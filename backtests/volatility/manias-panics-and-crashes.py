import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Display parameters
    smooth_period = 3
    
    # Alert thresholds
    mania_threshold = 75
    panic_threshold = 60
    crash_threshold = 70
    
    # Technical parameters
    ma_period = 200
    rsi_period = 14
    vol_period = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Long-term MA and price deviation
        self.ma_long = self.I(pta.sma, close, length=self.ma_period)
        self.price_deviation = self.I(lambda: ((close - self.ma_long) / self.ma_long) * 100)
        
        # RSI and momentum
        self.rsi = self.I(pta.rsi, close, length=self.rsi_period)
        self.roc = self.I(pta.roc, close, length=20)
        self.roc_ma = self.I(pta.sma, self.roc, length=20)
        
        # Volume indicators
        self.vol_avg = self.I(pta.sma, volume, length=self.vol_period)
        self.vol_spike = self.I(lambda: volume / self.vol_avg)
        
        # MACD
        macd_result = self.I(pta.macd, close, fast=12, slow=26, signal=9)
        self.macd_line = self.I(lambda: macd_result['MACD_12_26_9'] if macd_result is not None else pd.Series(0, index=close.index))
        self.macd_signal = self.I(lambda: macd_result['MACDs_12_26_9'] if macd_result is not None else pd.Series(0, index=close.index))
        
        # Peaks and declines
        self.peak_20 = self.I(lambda: high.rolling(20).max())
        self.peak_60 = self.I(lambda: high.rolling(60).max())
        self.decline_20 = self.I(lambda: ((close - self.peak_20) / self.peak_20) * 100)
        self.decline_60 = self.I(lambda: ((close - self.peak_60) / self.peak_60) * 100)
        
        # Breadth proxy (price above 50MA)
        sma_50 = self.I(pta.sma, close, length=50)
        price_above_50ma = self.I(lambda: (close > sma_50).astype(float))
        self.breadth_proxy = self.I(lambda: pta.sma(price_above_50ma, length=20) * 100 if price_above_50ma is not None else pd.Series(50, index=close.index))
        
        # Correlation proxy
        self.correlation_proxy = self.I(lambda: pta.correlation(close, self.ma_long, length=20).abs() * 100)
        
        # Phase scores (raw)
        self.mania_price = self.I(self._calc_mania_price)
        self.mania_rsi = self.I(self._calc_mania_rsi)
        self.mania_breadth = self.I(self._calc_mania_breadth)
        self.mania_momentum = self.I(self._calc_mania_momentum)
        
        self.panic_decline = self.I(self._calc_panic_decline)
        self.panic_volume = self.I(self._calc_panic_volume)
        self.panic_breadth = self.I(self._calc_panic_breadth)
        self.panic_momentum = self.I(self._calc_panic_momentum)
        
        self.crash_extreme_decline = self.I(self._calc_crash_decline)
        self.crash_volume_climax = self.I(self._calc_crash_volume)
        self.crash_breadth_collapse = self.I(self._calc_crash_breadth)
        self.crash_correlation = self.I(self._calc_crash_correlation)
        
        # Raw scores
        self.mania_score_raw = self.I(lambda: self.mania_price[-1] + self.mania_rsi[-1] + self.mania_breadth[-1] + self.mania_momentum[-1])
        self.panic_score_raw = self.I(lambda: self.panic_decline[-1] + self.panic_volume[-1] + self.panic_breadth[-1] + self.panic_momentum[-1])
        self.crash_score_raw = self.I(lambda: self.crash_extreme_decline[-1] + self.crash_volume_climax[-1] + self.crash_breadth_collapse[-1] + self.crash_correlation[-1])
        
        # Smoothed scores
        self.mania_score = self.I(pta.sma, self.mania_score_raw, length=self.smooth_period)
        self.panic_score = self.I(pta.sma, self.panic_score_raw, length=self.smooth_period)
        self.crash_score = self.I(pta.sma, self.crash_score_raw, length=self.smooth_period)
        
        # Composite risk
        self.composite_risk = self.I(lambda: max(self.mania_score[-1], self.panic_score[-1], self.crash_score[-1]))
        
        # Phase state
        self.phase = "NORMAL"
        self.previous_phase = "NORMAL"

    def _calc_mania_price(self):
        if len(self.data) < self.ma_period:
            return pd.Series(0, index=self.data.Close.index)
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(self.ma_period, len(self.data)):
            dev = self.price_deviation[i]
            if dev > 15:
                result.iloc[i] = 25
            elif dev > 10:
                result.iloc[i] = 15
        return result

    def _calc_mania_rsi(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.rsi[i] > 70:
                result.iloc[i] = 15
        return result

    def _calc_mania_breadth(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.breadth_proxy[i] > 60:
                result.iloc[i] = 20
            elif self.breadth_proxy[i] > 50:
                result.iloc[i] = 10
        return result

    def _calc_mania_momentum(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.roc[i] > self.roc_ma[i] and self.roc[i] > 0:
                result.iloc[i] = 15
        return result

    def _calc_panic_decline(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.decline_20[i] < -5 and self.decline_20[i] > -15:
                result.iloc[i] = 20
        return result

    def _calc_panic_volume(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.vol_spike[i] > 1.5 and self.data.Close[i] < self.data.Open[i]:
                result.iloc[i] = 15
        return result

    def _calc_panic_breadth(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.breadth_proxy[i] < 40:
                result.iloc[i] = 15
        return result

    def _calc_panic_momentum(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(1, len(self.data)):
            if crossover(self.macd_signal, self.macd_line):
                result.iloc[i] = 15
        return result

    def _calc_crash_decline(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.decline_60[i] < -15:
                result.iloc[i] = 25
            elif self.decline_60[i] < -10:
                result.iloc[i] = 15
        return result

    def _calc_crash_volume(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.vol_spike[i] > 2.0 and self.data.Close[i] < self.data.Open[i]:
                result.iloc[i] = 15
        return result

    def _calc_crash_breadth(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.breadth_proxy[i] < 20:
                result.iloc[i] = 15
        return result

    def _calc_crash_correlation(self):
        result = pd.Series(0, index=self.data.Close.index)
        for i in range(len(self.data)):
            if self.correlation_proxy[i] > 80:
                result.iloc[i] = 15
        return result

    def next(self):
        # Determine current phase
        if self.crash_score[-1] > self.crash_threshold:
            self.phase = "CRASH"
        elif self.panic_score[-1] > self.panic_threshold:
            self.phase = "PANIC"
        elif self.mania_score[-1] > self.mania_threshold:
            self.phase = "MANIA"
        else:
            self.phase = "NORMAL"
        
        # Trading logic based on phase
        if self.phase == "CRASH":
            # Extreme fear - prepare to buy on capitulation
            if self.position:
                self.sell()
        elif self.phase == "PANIC":
            # High stress - reduce exposure, avoid buying dips
            if self.position and self.composite_risk[-1] > 75:
                self.sell()
        elif self.phase == "MANIA":
            # Elevated risk - take profits
            if self.position and self.composite_risk[-1] > self.mania_threshold:
                self.sell()
        else:
            # Normal conditions
            if not self.position and self.rsi[-1] < 30 and self.roc[-1] > self.roc_ma[-1]:
                self.buy()
            elif self.position and (self.rsi[-1] > 70 or self.composite_risk[-1] > 50):
                self.sell()
        
        self.previous_phase = self.phase