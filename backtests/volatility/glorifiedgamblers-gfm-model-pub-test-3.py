import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime, time


class TvStrategy(Strategy):
    # Gann Session Parameters
    gann_hour_start = 8
    gann_min_start = 0
    gann_hour_end = 9
    gann_min_end = 0
    
    # Filters
    chop_threshold = 3
    vol_lookback = 20
    
    # RSI Divergence
    rsi_div_lbL = 5
    rsi_div_lbR = 5
    rsi_div_lower = 5
    rsi_div_upper = 60

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume and basic indicators
        self.vol_ma = self.I(lambda: pta.sma(volume, length=self.vol_lookback))
        self.rsi_val = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        self.sma20 = self.I(lambda: pta.sma(close, length=20))
        self.ema9 = self.I(lambda: pta.ema(close, length=9))
        
        # VWAP calculation (daily reset)
        self.vwap_val = self.I(self._calculate_vwap)
        
        # State variables for Gann box
        self.gann_high = None
        self.gann_low = None
        self.gann_locked = False
        self.break_count = 0
        self.gann_session_start_idx = None
        self.broken_up = False
        self.broken_down = False
        self.break_was_close_up = False
        self.break_was_close_down = False
        self.last_day = None
        
        # RSI divergence state
        self.pivot_highs = []
        self.pivot_lows = []

    def _calculate_vwap(self):
        """Calculate VWAP from start of day"""
        close = self.data.Close
        high = self.data.High
        low = self.data.Low
        volume = self.data.Volume
        
        typical_price = (high + low + close) / 3
        vwap_series = pd.Series(index=close.index, dtype=float)
        
        cumul_tp_vol = 0.0
        cumul_vol = 0.0
        current_date = None
        
        for i in range(len(close)):
            bar_date = pd.Timestamp(self.data.index[i]).date()
            
            if current_date != bar_date:
                cumul_tp_vol = 0.0
                cumul_vol = 0.0
                current_date = bar_date
            
            cumul_tp_vol += typical_price.iloc[i] * volume.iloc[i]
            cumul_vol += volume.iloc[i]
            
            if cumul_vol > 0:
                vwap_series.iloc[i] = cumul_tp_vol / cumul_vol
            else:
                vwap_series.iloc[i] = typical_price.iloc[i]
        
        return vwap_series

    def _is_gann_session(self, bar_idx):
        """Check if current bar is within Gann session time"""
        try:
            bar_time = pd.Timestamp(self.data.index[bar_idx])
            et_hour = bar_time.hour
            et_min = bar_time.minute
            
            current_mins = et_hour * 60 + et_min
            gann_start_mins = self.gann_hour_start * 60 + self.gann_min_start
            gann_end_mins = self.gann_hour_end * 60 + self.gann_min_end
            
            return current_mins >= gann_start_mins and current_mins < gann_end_mins
        except:
            return False

    def _is_new_day(self, bar_idx):
        """Check if this is a new day"""
        if bar_idx == 0:
            return True
        
        try:
            current_date = pd.Timestamp(self.data.index[bar_idx]).date()
            prev_date = pd.Timestamp(self.data.index[bar_idx - 1]).date()
            return current_date != prev_date
        except:
            return False

    def next(self):
        bar_idx = len(self.data) - 1
        
        # Reset on new day
        if self._is_new_day(bar_idx):
            self.gann_high = None
            self.gann_low = None
            self.gann_locked = False
            self.break_count = 0
            self.gann_session_start_idx = None
            self.broken_up = False
            self.broken_down = False
            self.break_was_close_up = False
            self.break_was_close_down = False
            self.pivot_highs = []
            self.pivot_lows = []
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Track Gann box during session
        if self._is_gann_session(bar_idx) and not self.gann_locked:
            if self.gann_session_start_idx is None:
                self.gann_session_start_idx = bar_idx
            
            if self.gann_high is None:
                self.gann_high = high
            else:
                self.gann_high = max(self.gann_high, high)
            
            if self.gann_low is None:
                self.gann_low = low
            else:
                self.gann_low = min(self.gann_low, low)
        
        # Lock Gann box after session ends
        if not self._is_gann_session(bar_idx) and not self.gann_locked:
            if self.gann_high is not None:
                self.gann_locked = True
        
        # Break detection (only when locked)
        if self.gann_locked and self.gann_high is not None and self.gann_low is not None:
            prev_close = self.data.Close[-2] if bar_idx > 0 else close
            
            es_break_up_close = close > self.gann_high and prev_close <= self.gann_high
            es_break_down_close = close < self.gann_low and prev_close >= self.gann_low
            es_wick_up = high > self.gann_high and close <= self.gann_high and not es_break_up_close
            es_wick_down = low < self.gann_low and close >= self.gann_low and not es_break_down_close
            
            if es_break_up_close or es_break_down_close:
                self.break_count += 1
            
            # Flip detection
            if (es_break_up_close or es_wick_up) and not self.broken_up:
                self.broken_up = True
                self.break_was_close_up = es_break_up_close
            
            if (es_break_down_close or es_wick_down) and not self.broken_down:
                self.broken_down = True
                self.break_was_close_down = es_break_down_close
            
            gann_flip_long = self.broken_down and close > self.gann_low and (bar_idx == 0 or self.data.Close[-2] <= self.gann_low)
            gann_flip_short = self.broken_up and close < self.gann_high and (bar_idx == 0 or self.data.Close[-2] >= self.gann_high)
            
            # Get indicator values safely
            try:
                rsi_val = self.rsi_val[-1] if self.rsi_val[-1] is not None else 50
            except:
                rsi_val = 50
            
            try:
                sma20_val = self.sma20[-1] if self.sma20[-1] is not None else close
            except:
                sma20_val = close
            
            try:
                ema9_val = self.ema9[-1] if self.ema9[-1] is not None else close
            except:
                ema9_val = close
            
            try:
                vwap_val = self.vwap_val[-1] if self.vwap_val[-1] is not None else close
            except:
                vwap_val = close
            
            try:
                vol_ma_val = self.vol_ma[-1] if self.vol_ma[-1] is not None else 0
            except:
                vol_ma_val = 0
            
            vol = self.data.Volume[-1]
            high_volume = vol > vol_ma_val if vol_ma_val > 0 else False
            
            rsi_neutral = rsi_val > 30 and rsi_val < 70
            above_sma = close > sma20_val
            below_sma = close < sma20_val
            above_ema = close > ema9_val
            below_ema = close < ema9_val
            
            is_choppy = self.break_count >= self.chop_threshold
            
            # Simple scoring (reduced complexity)
            score_long = 0
            score_long += gann_flip_long * 3
            score_long += self.break_was_close_down * 1
            score_long += rsi_neutral * 1
            score_long += above_sma * 1
            score_long += above_ema * 1
            score_long += high_volume * 1
            score_long -= is_choppy * 2
            score_long = max(0, min(10, score_long))
            
            score_short = 0
            score_short += gann_flip_short * 3
            score_short += self.break_was_close_up * 1
            score_short += rsi_neutral * 1
            score_short += below_sma * 1
            score_short += below_ema * 1
            score_short += high_volume * 1
            score_short -= is_choppy * 2
            score_short = max(0, min(10, score_short))
            
            # Trading logic: buy on strong long flip, sell on strong short flip
            if gann_flip_long and score_long >= 5 and not self.position:
                self.buy()
            elif gann_flip_short and score_short >= 5 and self.position:
                self.position.close()