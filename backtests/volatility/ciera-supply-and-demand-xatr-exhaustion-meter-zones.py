        self.highest = self.I(lambda: high.rolling(window=self.lookback_leg).max())
        self.lowest = self.I(lambda: low.rolling(window=self.lookback_leg).min())

        self.body = self.I(lambda: (close - open_).abs())
        self.avg_body = self.I(pta.sma, self.body, length=self.body_avg_len)

        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)

