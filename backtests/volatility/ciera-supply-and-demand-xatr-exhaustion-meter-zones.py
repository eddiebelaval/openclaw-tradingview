class TvStrategy(Strategy):
    atr_len = 14
    demand_low = 0.0
    demand_high = 0.0
    supply_low = 0.0
    supply_high = 0.0
    zone_buffer_pts = 0.0
    lookback_leg = 20
    exhausted_atr = 2.0
    energetic_body_mult = 1.3
    body_avg_len = 20
    use_rsi = True
    rsi_len = 14
    zone_touch_mode = "Wick Touch"

