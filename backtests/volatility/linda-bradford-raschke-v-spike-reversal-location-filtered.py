import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    atrMult = 1.3
    wickPercent = 0.5
    riskReward = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        self.prevHigh = self.I(self._get_prev_day_high)
        self.prevLow = self.I(self._get_prev_day_low)

    def _get_prev_day_high(self):
        high = pd.Series(self.data.High)
        dates = self.data.index
        prev_day_high = pd.Series(np.nan, index=dates)
        
        for i in range(1, len(dates)):
            current_date = pd.Timestamp(dates[i]).date()
            prev_date = pd.Timestamp(dates[i-1]).date()
            
            if current_date != prev_date:
                prev_day_high.iloc[i] = high.iloc[i-1]
            else:
                if not pd.isna(prev_day_high.iloc[i-1]):
                    prev_day_high.iloc[i] = prev_day_high.iloc[i-1]
        
        return prev_day_high

    def _get_prev_day_low(self):
        low = pd.Series(self.data.Low)
        dates = self.data.index
        prev_day_low = pd.Series(np.nan, index=dates)
        
        for i in range(1, len(dates)):
            current_date = pd.Timestamp(dates[i]).date()
            prev_date = pd.Timestamp(dates[i-1]).date()
            
            if current_date != prev_date:
                prev_day_low.iloc[i] = low.iloc[i-1]
            else:
                if not pd.isna(prev_day_low.iloc[i-1]):
                    prev_day_low.iloc[i] = prev_day_low.iloc[i-1]
        
        return prev_day_low

    def next(self):
        if len(self.data) < 2 or pd.isna(self.atr[-1]):
            return
        
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_ = self.data.Open[-1]
        close = self.data.Close[-1]
        atr = self.atr[-1]
        
        prevHigh = self.prevHigh[-1]
        prevLow = self.prevLow[-1]
        
        barRange = high - low
        upperWick = high - max(open_, close)
        lowerWick = min(open_, close) - low
        
        bullRejection = (
            barRange > atr * self.atrMult and
            lowerWick > barRange * self.wickPercent and
            low < prevLow
        )
        
        bearRejection = (
            barRange > atr * self.atrMult and
            upperWick > barRange * self.wickPercent and
            high > prevHigh
        )
        
        if bullRejection:
            entryPrice = close
            stopPrice = low
            targetPrice = entryPrice + (entryPrice - stopPrice) * self.riskReward
            
            if not self.position:
                self.buy()
            
            if self.position and self.position.is_long:
                self.position.close()
        
        elif bearRejection:
            entryPrice = close
            stopPrice = high
            targetPrice = entryPrice - (stopPrice - entryPrice) * self.riskReward
            
            if not self.position:
                self.position = self.sell()
            
            if self.position and self.position.is_short:
                self.position.close()


