import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    barsCount = 20
    rangeType = "High-Low"
    pipMode = "Auto"
    pipManual = 0.0001
    decimals = 1

    def init(self):
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)

        if self.rangeType == "High-Low":
            range_series = high - low
        else:
            range_series = pta.true_range(high, low, close)
            if range_series is None:
                range_series = high - low

        self.avgRange = self.I(
            lambda: pta.sma(range_series, length=self.barsCount)
        )

        self.pipSize = self._get_pip_size()

    def _get_pip_size(self):
        if self.pipMode == "Auto":
            return 0.00001
        else:
            return self.pipManual

    def next(self):
        if len(self.data) < self.barsCount:
            return

        if self.avgRange[-1] is None or np.isnan(self.avgRange[-1]):
            return

        pips = self.avgRange[-1] / self.pipSize if self.pipSize > 0 else np.nan

        if np.isnan(pips):
            return

        pow10 = 10.0 ** self.decimals
        pipsRounded = round(pips * pow10) / pow10

        if not self.position:
            if pipsRounded > 50:
                self.buy()
        else:
            if pipsRounded < 30:
                self.sell()


