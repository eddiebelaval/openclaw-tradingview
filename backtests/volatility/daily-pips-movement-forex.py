import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Calculate daily pips movement
        # pip = syminfo.mintick * 10 (assuming forex with standard pip calculation)
        # For backtesting purposes, we'll use a standard pip value
        self.pip_value = 0.0001  # Standard for most forex pairs
        
        # Calculate daily pips as (high - low) / pip
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.daily_pips = self.I(lambda: (high - low) / self.pip_value)
        
        # Track if candle is bullish
        self.is_bull = self.I(lambda: close > pd.Series(self.data.Open))

    def next(self):
        # This is a pure indicator/visualization script with no trading signals
        # Create a simple trading rule based on daily pips movement
        # Buy when daily pips movement is large and candle is bullish
        # Sell when daily pips movement is large and candle is bearish
        
        if len(self.data) < 2:
            return
        
        current_pips = self.daily_pips[-1]
        is_current_bull = self.is_bull[-1]
        
        # Use median daily pips as threshold
        median_pips = np.median(self.daily_pips)
        
        # Entry logic: buy on large bullish movement
        if not self.position and current_pips > median_pips * 1.5 and is_current_bull:
            self.buy()
        
        # Exit logic: sell on large bearish movement or reversion
        elif self.position and (current_pips > median_pips * 1.5 and not is_current_bull):
            self.sell()