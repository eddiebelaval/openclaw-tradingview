import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 14
    reg_lookback = 50
    low_mult = 1.5
    med_mult = 2.5
    high_mult = 3.5
    low_thresh = 0.8
    high_thresh = 1.4
    tss_min_score = 40
    rsi_slope_len = 5
    vol_surge_len = 20
    tp_mult = 3.0
    sl_mult = 1.5
    tp_pct = 1.0
    sl_pct = 0.5
    max_bars = 50
    cooldown = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # ATR calculation
        self.atr_raw = self.I(lambda: pta.atr(high, low, close, length=self.atr_len) or pd.Series(0, index=close.index))
        
        # Volatility Regime Engine
        self.atr_sma = self.I(lambda: pta.sma(self.atr_raw, length=self.reg_lookback) or pd.Series(1, index=close.index))
        self.atr_ratio = self.I(lambda: self.atr_raw / (self.atr_sma + 1e-10))
        
        # Trend Strength Score components
        self.rsi_14 = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        self.vol_ma = self.I(lambda: pta.sma(volume, length=self.vol_surge_len) or pd.Series(1, index=close.index))
        self.atr_short = self.I(lambda: pta.sma(self.atr_raw, length=5) or pd.Series(1, index=close.index))
        
        # Initialize trade state variables
        self.in_trade = False
        self.is_long = False
        self.entry_price = None
        self.entry_bar = None
        self.last_sig_bar = -self.cooldown
        self.tp = None
        self.sl = None
        self.trail = None
        self.trail_up = True
        self.prev_trail_up = True

    def next(self):
        # Current bar data
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        atr_raw = self.atr_raw[-1] if len(self.atr_raw) > 0 else 0
        atr_sma = self.atr_sma[-1] if len(self.atr_sma) > 0 else 1
        vol_ma = self.vol_ma[-1] if len(self.vol_ma) > 0 else 1
        atr_short = self.atr_short[-1] if len(self.atr_short) > 0 else 1
        rsi_14 = self.rsi_14[-1] if len(self.rsi_14) > 0 else 50
        
        # Volatility regime calculation
        atr_ratio = atr_raw / (atr_sma + 1e-10) if atr_sma > 0 else 1.0
        
        if atr_ratio < self.low_thresh:
            active_mult = self.low_mult
        elif atr_ratio > self.high_thresh:
            active_mult = self.high_mult
        else:
            active_mult = self.med_mult
        
        # Trend Strength Score calculation
        rsi_now = rsi_14
        rsi_prev = self.rsi_14[-self.rsi_slope_len - 1] if len(self.rsi_14) > self.rsi_slope_len else rsi_now
        rsi_slope = rsi_now - rsi_prev if not np.isnan(rsi_prev) else 0.0
        rsi_comp = min(abs(rsi_slope) / 20.0, 1.0)
        
        vol_ratio = volume_val / (vol_ma + 1e-10) if vol_ma > 0 else 1.0
        vol_comp = min(max(vol_ratio - 1.0, 0.0) / 1.5, 1.0)
        
        atr_expand = atr_raw / (atr_short + 1e-10) if atr_short > 0 else 1.0
        atr_comp = min(max(atr_expand - 1.0, 0.0) / 0.5, 1.0)
        
        tss_score = (rsi_comp * 0.40 + vol_comp * 0.35 + atr_comp * 0.25) * 100
        
        score_tp_boost = 1.2 if tss_score >= 70 else 1.0
        
        # ATR Trail calculation (Chandelier Exit)
        atr_band = atr_raw * active_mult
        trail_up_val = close_val - atr_band
        trail_dn_val = close_val + atr_band
        
        if self.trail is None:
            self.trail = trail_up_val
            self.trail_up = True
        else:
            new_trail_up = max(trail_up_val, self.trail) if self.trail_up else trail_up_val
            new_trail_dn = min(trail_dn_val, self.trail) if not self.trail_up else trail_dn_val
            
            flip_to_bull = not self.prev_trail_up and close_val > self.trail
            flip_to_bear = self.prev_trail_up and close_val < self.trail
            
            if flip_to_bull:
                self.trail_up = True
                self.trail = new_trail_up
            elif flip_to_bear:
                self.trail_up = False
                self.trail = new_trail_dn
            elif self.trail_up:
                self.trail = new_trail_up
            else:
                self.trail = new_trail_dn
        
        # Flip detection
        flip_to_bull = not self.prev_trail_up and close_val > self.trail
        flip_to_bear = self.prev_trail_up and close_val < self.trail
        
        # Trade management - exits first
        if self.in_trade:
            tp_hit = (self.is_long and high_val >= self.tp) or (not self.is_long and low_val <= self.tp)
            sl_hit = (self.is_long and low_val <= self.sl) or (not self.is_long and high_val >= self.sl)
            time_exit = len(self.data) - self.entry_bar >= self.max_bars
            trail_exit = (self.is_long and flip_to_bear) or (not self.is_long and flip_to_bull)
            
            if tp_hit or sl_hit or time_exit or trail_exit:
                self.sell() if self.is_long else self.buy()
                self.in_trade = False
        
        # Signal generation
        cd_ok = len(self.data) - self.last_sig_bar >= self.cooldown
        ready = not self.in_trade and cd_ok
        
        buy_signal = False
        sell_signal = False
        
        if ready and self.trail is not None:
            score_ok = tss_score >= self.tss_min_score
            if flip_to_bull and score_ok:
                buy_signal = True
            elif flip_to_bear and score_ok:
                sell_signal = True
        
        # Trade execution
        if buy_signal and not self.in_trade:
            self.buy()
            self.in_trade = True
            self.is_long = True
            self.entry_price = close_val
            self.entry_bar = len(self.data)
            self.last_sig_bar = len(self.data)
            self.tp = close_val + atr_raw * self.tp_mult * score_tp_boost
            self.sl = self.trail if self.trail is not None else close_val * (1 - self.sl_pct / 100)
        
        elif sell_signal and not self.in_trade:
            self.sell()
            self.in_trade = True
            self.is_long = False
            self.entry_price = close_val
            self.entry_bar = len(self.data)
            self.last_sig_bar = len(self.data)
            self.tp = close_val - atr_raw * self.tp_mult * score_tp_boost
            self.sl = self.trail if self.trail is not None else close_val * (1 + self.sl_pct / 100)
        
        # Update prev trail state
        self.prev_trail_up = self.trail_up