import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    entryPrice = 0.0
    isLong = True
    startTime = pd.Timestamp("2024-01-01")
    lookback = 20
    mult = 3.0

    def init(self):
        self.highest_since_entry = np.nan
        self.lowest_since_entry = np.nan
        self.trailing_stop = np.nan
        self.tracking = False
        
        close = pd.Series(self.data.Close)
        
        def calculate_returns():
            returns = np.log(close / close.shift(1))
            return returns
        
        def calculate_sigma():
            returns = calculate_returns()
            sigma = returns.rolling(window=self.lookback).std()
            return sigma
        
        def calculate_vol_distance():
            sigma = calculate_sigma()
            vol_distance = self.mult * sigma * close
            return vol_distance
        
        self.returns = self.I(calculate_returns)
        self.sigma = self.I(calculate_sigma)
        self.vol_distance = self.I(calculate_vol_distance)

    def next(self):
        current_time = pd.Timestamp(self.data.index[-1])
        
        if current_time >= self.startTime:
            self.tracking = True
        
        if not self.tracking:
            return
        
        current_price = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        vol_dist = self.vol_distance[-1]
        
        if pd.isna(vol_dist):
            return
        
        if self.isLong:
            if np.isnan(self.highest_since_entry):
                self.highest_since_entry = current_high
            else:
                self.highest_since_entry = max(self.highest_since_entry, current_high)
            
            new_stop = self.highest_since_entry - vol_dist
            
            if np.isnan(self.trailing_stop):
                self.trailing_stop = new_stop
            else:
                self.trailing_stop = max(self.trailing_stop, new_stop)
        else:
            if np.isnan(self.lowest_since_entry):
                self.lowest_since_entry = current_low
            else:
                self.lowest_since_entry = min(self.lowest_since_entry, current_low)
            
            new_stop = self.lowest_since_entry + vol_dist
            
            if np.isnan(self.trailing_stop):
                self.trailing_stop = new_stop
            else:
                self.trailing_stop = min(self.trailing_stop, new_stop)
        
        if self.isLong:
            if current_price <= self.trailing_stop and self.position:
                self.position.close()
