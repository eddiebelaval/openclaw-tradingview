import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pvtSmoothing = 1
    pvtAnchorLookback = 200
    volLength = 14
    volSmoothing = 3
    volEmaLength = 20
    requireBoth = True

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate price change
        def calc_price_change():
            pc = np.zeros(len(close))
            for i in range(1, len(close)):
                if close.iloc[i] != 0 and close.iloc[i-1] != 0:
                    pc[i] = (close.iloc[i] - close.iloc[i-1]) / close.iloc[i-1]
                else:
                    pc[i] = 0
            return pd.Series(pc, index=close.index)

        price_change = self.I(calc_price_change)

        # Calculate raw PVT (cumulative)
        def calc_raw_pvt():
            raw = np.zeros(len(volume))
            for i in range(len(volume)):
                raw[i] = np.sum(volume.iloc[:i+1] * price_change.iloc[:i+1])
            return pd.Series(raw, index=volume.index)

        raw_pvt = self.I(calc_raw_pvt)

        # Smooth PVT
        if self.pvtSmoothing > 1:
            smoothed_pvt = self.I(pta.sma, raw_pvt, length=self.pvtSmoothing)
        else:
            smoothed_pvt = raw_pvt

        # PVT Mean and Std
        pvt_mean = self.I(pta.sma, smoothed_pvt, length=self.pvtAnchorLookback)
        
        def calc_pvt_std():
            result = pta.stdev(smoothed_pvt, length=self.pvtAnchorLookback)
            return result if result is not None else pd.Series(1, index=smoothed_pvt.index)
        
        pvt_std = self.I(calc_pvt_std)

        # Price Mean
        price_mean = self.I(pta.sma, close, length=self.pvtAnchorLookback)

        # ATR for scaling
        atr = self.I(pta.atr, high, low, close, length=self.pvtAnchorLookback)

        # Scale PVT to price level
        def calc_pvt_line():
            pvt_scaled = np.zeros(len(close))
            for i in range(len(close)):
                if pvt_std.iloc[i] != 0:
                    pvt_scaled[i] = price_mean.iloc[i] + (smoothed_pvt.iloc[i] - pvt_mean.iloc[i]) / pvt_std.iloc[i] * (atr.iloc[i] * 2)
                else:
                    pvt_scaled[i] = price_mean.iloc[i] + (smoothed_pvt.iloc[i] - pvt_mean.iloc[i]) * (atr.iloc[i] * 2)
            return pd.Series(pvt_scaled, index=close.index)

        self.pvt_line = self.I(calc_pvt_line)

        # PVT EMAs
        self.pvt_ema10 = self.I(pta.ema, self.pvt_line, length=10)
        self.pvt_ema20 = self.I(pta.ema, self.pvt_line, length=20)
        self.pvt_ema50 = self.I(pta.ema, self.pvt_line, length=50)

        # Smooth volume
        smooth_vol = self.I(pta.sma, volume, length=self.volSmoothing)

        # Volume momentum
        def calc_vol_momentum():
            vol_mom = np.zeros(len(smooth_vol))
            for i in range(len(smooth_vol)):
                if i >= self.volLength:
                    if smooth_vol.iloc[i - self.volLength] != 0:
                        vol_mom[i] = (smooth_vol.iloc[i] - smooth_vol.iloc[i - self.volLength]) / smooth_vol.iloc[i - self.volLength] * 100
                    else:
                        vol_mom[i] = 0
                else:
                    vol_mom[i] = 0
            return pd.Series(vol_mom, index=volume.index)

        self.vol_momentum = self.I(calc_vol_momentum)

        # Volume Momentum EMA
        self.vol_mom_ema20 = self.I(pta.ema, self.vol_momentum, length=self.volEmaLength)

    def next(self):
        # PVT signals
        pvt_bullish = crossover(self.pvt_line, self.pvt_ema20)
        pvt_bearish = crossover(self.pvt_ema20, self.pvt_line)

        # Volume signals
        vol_bullish = crossover(self.vol_momentum, self.vol_mom_ema20)
        vol_bearish = crossover(self.vol_mom_ema20, self.vol_momentum)

        # Combined signals
        if self.requireBoth:
            buy_signal = pvt_bullish and vol_bullish
            sell_signal = pvt_bearish and vol_bearish
        else:
            buy_signal = pvt_bullish
            sell_signal = pvt_bearish

        if buy_signal:
            if not self.position:
                self.buy()
        elif sell_signal:
            if self.position:
                self.position.close()


