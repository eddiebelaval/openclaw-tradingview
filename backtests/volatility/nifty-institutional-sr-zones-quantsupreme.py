import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Zone Parameters
    short_len = 13
    mid_len = 24
    long_len = 52
    z_s1 = 1.0
    z_s2 = 1.5
    z_s3 = 2.0
    atr_mult = 1.5
    atr_len = 14
    
    # Signal Parameters
    buy_z = -1.0
    sell_z = 1.5
    use_vol = True
    vol_mult = 1.2
    vol_ma = 20
    stop_atr = 2.0
    risk_pct = 2.0
    capital = 10000000.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Rolling mean and standard deviation
        self.mu_short = self.I(pta.sma, close, length=self.short_len)
        self.sd_short = self.I(lambda: close.rolling(self.short_len).std())
        
        self.mu_mid = self.I(pta.sma, close, length=self.mid_len)
        self.sd_mid = self.I(lambda: close.rolling(self.mid_len).std())
        
        self.mu_long = self.I(pta.sma, close, length=self.long_len)
        self.sd_long = self.I(lambda: close.rolling(self.long_len).std())
        
        # Z-Scores calculation
        def calc_z_short():
            sd = close.rolling(self.short_len).std()
            mu = close.rolling(self.short_len).mean()
            z = pd.Series(0.0, index=close.index)
            mask = sd != 0
            z[mask] = (close[mask] - mu[mask]) / sd[mask]
            return z
        
        def calc_z_mid():
            sd = close.rolling(self.mid_len).std()
            mu = close.rolling(self.mid_len).mean()
            z = pd.Series(0.0, index=close.index)
            mask = sd != 0
            z[mask] = (close[mask] - mu[mask]) / sd[mask]
            return z
        
        def calc_z_long():
            sd = close.rolling(self.long_len).std()
            mu = close.rolling(self.long_len).mean()
            z = pd.Series(0.0, index=close.index)
            mask = sd != 0
            z[mask] = (close[mask] - mu[mask]) / sd[mask]
            return z
        
        self.z_short = self.I(calc_z_short)
        self.z_mid = self.I(calc_z_mid)
        self.z_long = self.I(calc_z_long)
        
        # ATR for dynamic zone width
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        def calc_zone_half_width():
            atr_vals = pta.atr(high, low, close, length=self.atr_len)
            if atr_vals is None:
                return pd.Series(0.0, index=close.index)
            return atr_vals * self.atr_mult / 2
        
        self.zone_half_width = self.I(calc_zone_half_width)
        
        # Volume analysis
        self.vol_ma = self.I(pta.sma, volume, length=self.vol_ma)
        
        def calc_vol_ratio():
            vol_ma_vals = volume.rolling(self.vol_ma).mean()
            vol_ratio = pd.Series(1.0, index=volume.index)
            mask = vol_ma_vals != 0
            vol_ratio[mask] = volume[mask] / vol_ma_vals[mask]
            return vol_ratio
        
        self.vol_ratio = self.I(calc_vol_ratio)
        
        # S/R Zone centers
        def calc_s1_center():
            return self.mu_long - self.z_s1 * self.sd_long
        
        def calc_s2_center():
            return self.mu_long - self.z_s2 * self.sd_long
        
        def calc_s3_center():
            return self.mu_long - self.z_s3 * self.sd_long
        
        def calc_r1_center():
            return self.mu_long + self.z_s1 * self.sd_long
        
        def calc_r2_center():
            return self.mu_long + self.z_s2 * self.sd_long
        
        def calc_r3_center():
            return self.mu_long + self.z_s3 * self.sd_long
        
        self.s1_center = self.I(calc_s1_center)
        self.s2_center = self.I(calc_s2_center)
        self.s3_center = self.I(calc_s3_center)
        self.r1_center = self.I(calc_r1_center)
        self.r2_center = self.I(calc_r2_center)
        self.r3_center = self.I(calc_r3_center)

    def next(self):
        if len(self.data) < self.long_len:
            return
        
        close_price = self.data.Close[-1]
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        z_mid_val = self.z_mid[-1] if self.z_mid[-1] is not None else 0
        vol_ratio_val = self.vol_ratio[-1] if self.vol_ratio[-1] is not None else 1.0
        
        # Volume confirmation
        vol_spike = vol_ratio_val >= self.vol_mult
        vol_ok = vol_spike if self.use_vol else True
        
        # Buy signal: z_mid crosses above buy_z with volume confirmation
        buy_signal = False
        if len(self.z_mid) > 1:
            if crossover(self.z_mid, self.buy_z):
                buy_signal = True and vol_ok
        
        # Sell signal: z_mid crosses above sell_z
        sell_signal = False
        if len(self.z_mid) > 1:
            if crossover(self.z_mid, self.sell_z):
                sell_signal = True
        
        # Stop loss condition
        stop_hit = False
        if self.position:
            entry_price = self.position.open_price
            stop_price = entry_price - self.stop_atr * atr_val
            if close_price <= stop_price:
                stop_hit = True
        
        # Entry logic
        if buy_signal and not self.position:
            self.buy()
        
        # Exit logic
        if self.position and (sell_signal or stop_hit):
            self.sell()