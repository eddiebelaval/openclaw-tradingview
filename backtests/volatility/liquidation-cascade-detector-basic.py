import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Volume Analysis
    vol_len = 20
    spike_mult = 1.8
    
    # Keltner Channels
    kelt_len = 20
    kelt_mult = 2.0
    atr_len = 14
    
    # Price Action
    liq_wick_ratio = 0.6
    liq_body_max = 0.35
    
    # HTF Trend
    htf_ema_len = 21
    
    # Signal Settings
    threshold = 45.0
    cooldown_bars = 10
    max_signals = 5
    
    # Scoring weights
    WT_VOLUME = 20.0
    WT_KELTNER = 30.0
    WT_PA = 25.0
    WT_HTF = 25.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # Volume indicators
        self.vol_avg = self.I(lambda: pta.sma(volume, length=self.vol_len))
        
        # Keltner Channels
        self.kelt_basis = self.I(lambda: pta.ema(close, length=self.kelt_len))
        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.atr_len))
        
        # Price data for candle analysis
        self.close_data = close
        self.high_data = high
        self.low_data = low
        self.open_data = open_
        self.volume_data = volume
        
        # HTF EMA (using same timeframe as a proxy)
        self.htf_ema = self.I(lambda: pta.ema(close, length=self.htf_ema_len))
        
        # State tracking
        self.bars_since_long = 999
        self.bars_since_short = 999
        self.session_signal_count = 0
        self.last_session_day = None

    def next(self):
        # Update cooldown counters
        self.bars_since_long += 1
        self.bars_since_short += 1
        
        # Reset session counter on new day
        current_day = self.data.index[len(self.data) - 1].day
        if self.last_session_day is None or self.last_session_day != current_day:
            self.session_signal_count = 0
            self.last_session_day = current_day
        
        # ===== MODULE 1: VOLUME ANALYSIS =====
        if len(self.data) < self.vol_len:
            return
        
        vol_avg = self.vol_avg[-1] if self.vol_avg[-1] is not None else 1.0
        vol_ratio = self.data.Volume[-1] / vol_avg if vol_avg > 0 else 0.0
        vol_spike = vol_ratio >= self.spike_mult
        
        # Volume score
        vol_score = 0.0
        if vol_ratio >= 1.0:
            vol_score = self._remap(vol_ratio, 1.0, self.spike_mult * 2.0, 0.0, self.WT_VOLUME)
        
        # ===== MODULE 2: KELTNER CHANNEL EXHAUSTION =====
        if len(self.data) < max(self.kelt_len, self.atr_len):
            return
        
        kelt_basis = self.kelt_basis[-1]
        atr_val = self.atr_val[-1] if self.atr_val[-1] is not None else 0.1
        
        if atr_val <= 0:
            atr_val = 0.1
        
        kelt_upper = kelt_basis + self.kelt_mult * atr_val
        kelt_lower = kelt_basis - self.kelt_mult * atr_val
        
        upper_ext = max(0.0, self.data.High[-1] - kelt_upper) / atr_val
        lower_ext = max(0.0, kelt_lower - self.data.Low[-1]) / atr_val
        
        kelt_score_long = self._remap(lower_ext, 0.0, 2.0, 0.0, self.WT_KELTNER)
        kelt_score_short = self._remap(upper_ext, 0.0, 2.0, 0.0, self.WT_KELTNER)
        
        kelt_exhaust_long = self.data.Low[-1] < kelt_lower
        kelt_exhaust_short = self.data.High[-1] > kelt_upper
        
        # ===== MODULE 3: PRICE ACTION (LIQUIDATION BAR) =====
        bar_range = self.data.High[-1] - self.data.Low[-1]
        body_size = abs(self.data.Close[-1] - self.data.Open[-1])
        body_ratio = body_size / bar_range if bar_range > 0 else 1.0
        
        upper_wick = (self.data.High[-1] - max(self.data.Close[-1], self.data.Open[-1])) / bar_range if bar_range > 0 else 0.0
        lower_wick = (min(self.data.Close[-1], self.data.Open[-1]) - self.data.Low[-1]) / bar_range if bar_range > 0 else 0.0
        
        liq_bar_long = lower_wick >= self.liq_wick_ratio and body_ratio <= self.liq_body_max and vol_ratio >= 1.2
        liq_bar_short = upper_wick >= self.liq_wick_ratio and body_ratio <= self.liq_body_max and vol_ratio >= 1.2
        
        pa_score_long = self.WT_PA if liq_bar_long else 0.0
        pa_score_short = self.WT_PA if liq_bar_short else 0.0
        
        # ===== MODULE 4: HIGHER TIMEFRAME TREND =====
        if len(self.data) < self.htf_ema_len + 1:
            return
        
        htf_ema = self.htf_ema[-1]
        htf_ema_prev = self.htf_ema[-2]
        
        if htf_ema > htf_ema_prev:
            htf_trend = 1
        elif htf_ema < htf_ema_prev:
            htf_trend = -1
        else:
            htf_trend = 0
        
        htf_score_long = self.WT_HTF if htf_trend >= 0 else 0.0
        htf_score_short = self.WT_HTF if htf_trend <= 0 else 0.0
        
        # ===== CONFLUENCE SCORING =====
        long_score = vol_score + kelt_score_long + pa_score_long + htf_score_long
        short_score = vol_score + kelt_score_short + pa_score_short + htf_score_short
        
        # Count modules contributing
        long_modules = sum([
            vol_score > 3,
            kelt_score_long > 3,
            pa_score_long > 3,
            htf_score_long > 3
        ])
        short_modules = sum([
            vol_score > 3,
            kelt_score_short > 3,
            pa_score_short > 3,
            htf_score_short > 3
        ])
        
        long_above_threshold = long_score >= self.threshold and long_modules >= 2
        short_above_threshold = short_score >= self.threshold and short_modules >= 2
        
        # ===== SIGNAL GATING =====
        long_cooldown_ok = self.bars_since_long >= self.cooldown_bars
        short_cooldown_ok = self.bars_since_short >= self.cooldown_bars
        under_signal_cap = self.session_signal_count < self.max_signals
        
        long_raw = long_above_threshold and long_cooldown_ok
        short_raw = short_above_threshold and short_cooldown_ok
        
        long_qualified = long_raw and (not short_raw or long_score >= short_score)
        short_qualified = short_raw and (not long_raw or short_score > long_score)
        
        long_signal = long_qualified and under_signal_cap
        short_signal = short_qualified and under_signal_cap
        
        # ===== EXECUTE TRADES =====
        if long_signal:
            if not self.position:
                self.buy()
            self.bars_since_long = 0
            self.session_signal_count += 1
        
        if short_signal:
            if self.position:
                self.position.close()
            self.bars_since_short = 0
            self.session_signal_count += 1
        
        # Exit logic: use opposite signal or other criteria
        if self.position and short_signal:
            self.position.close()
        
        if not self.position and long_signal:
            self.buy()

    def _remap(self, val, in_lo, in_hi, out_lo, out_hi):
        """Remap a value from one range to another."""
        val = max(in_lo, min(val, in_hi))
        return out_lo + (val - in_lo) / (in_hi - in_lo) * (out_hi - out_lo)


