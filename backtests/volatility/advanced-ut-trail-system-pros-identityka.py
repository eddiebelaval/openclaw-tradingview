import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # UT-Trail Settings
    base_key_value = 2.0
    atr_period = 10
    use_heikin_ashi = True
    
    # Auto-Adaptive AI
    auto_adapt = True
    
    # Take-Profit & Theme
    show_tp = True
    tp1_mult = 1.5
    tp2_mult = 3.0
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # Use close as source (simplified - no Heikin-Ashi conversion in backtest)
        self.src = close
        
        # Calculate dynamic sensitivity based on timeframe
        # For backtesting, we'll use a fixed value
        self.dyn_a = self.base_key_value
        
        # Calculate nLoss (sensitivity factor)
        self.nloss = self.I(lambda: self.dyn_a * self.atr)
        
        # Calculate trailing stop
        self.trailing_stop = self.I(self._calculate_trailing_stop)
        
        # EMA with period 1 (essentially close)
        self.ema = self.I(pta.ema, close, length=1)
        
        # Track position state
        self.pos_state = 0

    def _calculate_trailing_stop(self):
        """Calculate the UT-Trail trailing stop line"""
        close = self.data.Close
        atr = self.atr
        
        trailing_stop = np.zeros(len(close))
        pos = np.zeros(len(close), dtype=int)
        
        for i in range(len(close)):
            if i == 0:
                trailing_stop[i] = close[i]
                pos[i] = 0
                continue
            
            nloss_val = self.dyn_a * atr[i]
            prev_stop = trailing_stop[i-1]
            curr_close = close[i]
            prev_close = close[i-1]
            
            # Update trailing stop based on trend
            if curr_close > prev_stop and prev_close > prev_stop:
                trailing_stop[i] = max(prev_stop, curr_close - nloss_val)
            elif curr_close < prev_stop and prev_close < prev_stop:
                trailing_stop[i] = min(prev_stop, curr_close + nloss_val)
            elif curr_close > prev_stop:
                trailing_stop[i] = curr_close - nloss_val
            else:
                trailing_stop[i] = curr_close + nloss_val
            
            # Update position state
            if prev_close < prev_stop and curr_close > prev_stop:
                pos[i] = 1
            elif prev_close > prev_stop and curr_close < prev_stop:
                pos[i] = -1
            else:
                pos[i] = pos[i-1]
        
        return pd.Series(trailing_stop, index=close.index)

