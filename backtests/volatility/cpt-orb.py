import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        self.or_high = None
        self.or_low = None
        self.or_mid = None
        self.last_day = None
        
    def next(self):
        current_time = self.data.index[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Get current day
        current_day = current_time.date()
        
        # Reset on new day
        if self.last_day is None or current_day != self.last_day:
            self.or_high = None
            self.or_low = None
            self.or_mid = None
            self.last_day = current_day
        
        # Check if we're in the opening range session (8:00-8:15)
        current_hour = current_time.hour
        current_minute = current_time.minute
        
        in_or = (current_hour == 8 and current_minute >= 0 and current_minute <= 15)
        
        # Store range during OR window
        if in_or:
            if self.or_high is None:
                self.or_high = current_high
            else:
                self.or_high = max(self.or_high, current_high)
            
            if self.or_low is None:
                self.or_low = current_low
            else:
                self.or_low = min(self.or_low, current_low)
        
        # Calculate midpoint
        if self.or_high is not None and self.or_low is not None:
            self.or_mid = (self.or_high + self.or_low) / 2.0
        
        # Simple trading logic: buy on midpoint bounce, sell on range breakout
        if self.or_mid is not None and len(self) > 1:
            if not self.position:
                # Buy when price touches lower band and bounces
                if current_low <= self.or_low and current_high > self.or_low:
                    self.buy()
                # Buy on midpoint support
                elif current_low <= self.or_mid and current_high > self.or_mid and len(self) > 2:
                    if self.data.Low[-2] > self.or_mid:
                        self.buy()
            else:
                # Sell on upper range breakout
                if current_high >= self.or_high:
                    self.sell()
                # Sell on midpoint resistance
                elif current_high >= self.or_mid and current_low < self.or_mid and len(self) > 2:
                    if self.data.High[-2] < self.or_mid:
                        self.sell()


