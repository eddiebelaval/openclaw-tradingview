    def _true_range(self, high, low, close):
        """Calculate True Range"""
        tr = np.zeros(len(high))
        tr[0] = high[0] - low[0]
        for i in range(1, len(high)):
            tr[i] = max(high[i] - low[i], abs(high[i] - close[i-1]), abs(low[i] - close[i-1]))
        return tr

    def _percentile_linear_interpolation(self, series, lookback, percentile):
        """Calculate percentile of series"""
        result = pd.Series(np.nan, index=series.index)
        for i in range(lookback - 1, len(series)):
            window = series.iloc[i - lookback + 1:i + 1]
            result.iloc[i] = np.percentile(window, percentile)
        result.fillna(method='bfill', inplace=True)
        return result

    def _range_filter(self, x, r):
        """Range filter for smoothing"""
        rng = np.zeros(len(x))
        rng[0] = x[0]
        for i in range(1, len(x)):
            if x[i] > rng[i - 1]:
                rng[i] = x[i] - r[i] if x[i] - r[i] < rng[i - 1] else x[i] - r[i]
            else:
                rng[i] = x[i] + r[i] if x[i] + r[i] > rng[i - 1] else rng[i - 1]
        return rng

