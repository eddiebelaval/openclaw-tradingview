import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 20
    bbMult = 2.0
    kcMult = 1.5
    normLookbk = 200
    smoothLen = 5
    lowZone = 20.0
    highZone = 80.0
    momLen = 20
    boxPadATR = 0.0
    minSqueezeBars = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # BB/KC calculation
        self.basis = self.I(pta.sma, close, length=self.len)
        self.dev = self.I(lambda: pta.stdev(close, self.len) * self.bbMult if pta.stdev(close, self.len) is not None else pd.Series(0, index=close.index))
        
        self.bbU = self.basis + self.dev
        self.bbL = self.basis - self.dev
        
        atr = self.I(pta.atr, high, low, close, length=self.len)
        self.kcU = self.basis + (atr * self.kcMult)
        self.kcL = self.basis - (atr * self.kcMult)
        
        # Squeeze detection
        self.squeezeOn = self.I(lambda: ((self.bbU < self.kcU) & (self.bbL > self.kcL)).astype(float))
        
        # Volatility oscillator
        bbWidth = self.bbU - self.bbL
        kcWidth = self.kcU - self.kcL
        
        bbWidthPct = self.I(lambda: (bbWidth / self.basis * 100).fillna(0))
        
        minW = self.I(lambda: bbWidthPct.rolling(self.normLookbk).min().fillna(0))
        maxW = self.I(lambda: bbWidthPct.rolling(self.normLookbk).max().fillna(0))
        rangeW = maxW - minW
        
        w01_raw = self.I(lambda: ((bbWidthPct - minW) / rangeW.replace(0, 1)).fillna(0).clip(0, 1))
        
        oscRaw = self.I(lambda: np.where(
            self.squeezeOn[-1] > 0.5,
            w01_raw * self.lowZone,
            self.lowZone + w01_raw * (100.0 - self.lowZone)
        ) if len(self.squeezeOn) > 0 else pd.Series(50, index=close.index))
        
        self.volOsc = self.I(pta.ema, oscRaw, length=self.smoothLen)
        
        # TTM Momentum
        hh = self.I(lambda: high.rolling(self.momLen).max().fillna(0))
        ll = self.I(lambda: low.rolling(self.momLen).min().fillna(0))
        mid = (hh + ll) / 2.0
        momBasis = self.I(pta.sma, close, length=self.momLen)
        val = close - ((mid + momBasis) / 2.0)
        self.mom = self.I(lambda: pta.linreg(val, self.momLen) if pta.linreg(val, self.momLen) is not None else pd.Series(0, index=close.index))
        
        # State tracking
        self.squeeze_active = False
        self.last_squeeze_high = None
        self.last_squeeze_low = None
        self.squeeze_count = 0
        
    def next(self):
        if len(self.data) < max(self.len, self.normLookbk, self.momLen) + 5:
            return
        
        current_squeeze = self.squeezeOn[-1] > 0.5
        prev_squeeze = self.squeezeOn[-2] > 0.5 if len(self.squeezeOn) > 1 else False
        
        # Track squeeze
        if current_squeeze:
            self.squeeze_count += 1
            if self.last_squeeze_high is None:
                self.last_squeeze_high = self.data.High[-1]
                self.last_squeeze_low = self.data.Low[-1]
            else:
                self.last_squeeze_high = max(self.last_squeeze_high, self.data.High[-1])
                self.last_squeeze_low = min(self.last_squeeze_low, self.data.Low[-1])
        else:
            if prev_squeeze and self.squeeze_count >= self.minSqueezeBars:
                self.squeeze_active = True
            self.squeeze_count = 0
        
        # Volume oscillator crossdown signal
        volCrossDown = crossover(self.highZone, self.volOsc)
        
        # Diamond signals
        greenDiamond = volCrossDown and self.mom[-1] < 0
        redDiamond = volCrossDown and self.mom[-1] > 0
        
        # Break signals
        breakUp = False
        breakDown = False
        
        if self.squeeze_active and self.last_squeeze_high and self.last_squeeze_low:
            atr_value = self.data.Close[-1] * 0.02  # Approximate ATR
            pad = atr_value * self.boxPadATR
            
            if self.data.Close[-1] > (self.last_squeeze_high + pad):
                breakUp = True
                self.squeeze_active = False
            elif self.data.Close[-1] < (self.last_squeeze_low - pad):
                breakDown = True
                self.squeeze_active = False
        
        # Trading logic
        if greenDiamond or breakUp:
            if not self.position:
                self.buy()
        elif redDiamond or breakDown:
            if self.position:
                self.sell()


