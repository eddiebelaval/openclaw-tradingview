import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    n1 = 10
    n2 = 21
    obLevel1 = 60
    obLevel2 = 53
    osLevel1 = -60
    osLevel2 = -53

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        hlc3 = (high + low + close) / 3
        
        esa = self.I(pta.ema, hlc3, length=self.n1)
        d = self.I(lambda: pta.ema(pd.Series(np.abs(hlc3 - esa)), length=self.n1) or pd.Series(0, index=close.index))
        
        ci = self.I(lambda: (hlc3 - esa) / (0.015 * (d + 1e-10)))
        wt1 = self.I(pta.ema, ci, length=self.n2)
        wt2 = self.I(pta.sma, wt1, length=4)
        
        self.vwap = self.I(pta.vwap, high=high, low=low, close=close, volume=volume)
        
        self.wt1 = wt1
        self.wt2 = wt2

    def next(self):
        if len(self.data) < 2:
            return
        
        current_wt1 = self.wt1[-1]
        current_wt2 = self.wt2[-1]
        prev_wt1 = self.wt1[-2]
        prev_wt2 = self.wt2[-2]
        current_close = self.data.Close[-1]
        current_vwap = self.vwap[-1]
        
        above_vwap = current_close > current_vwap
        below_vwap = current_close < current_vwap
        
        wt_cross = (prev_wt1 <= prev_wt2 and current_wt1 > current_wt2) or \
                   (prev_wt1 >= prev_wt2 and current_wt1 < current_wt2)
        wt_cross_bull = wt_cross and current_wt1 > current_wt2
        wt_cross_bear = wt_cross and current_wt1 < current_wt2
        
        in_ob = current_wt2 >= self.obLevel2
        in_os = current_wt2 <= self.osLevel2
        in_strong_ob = current_wt2 >= self.obLevel1
        in_strong_os = current_wt2 <= self.osLevel1
        
        strong_buy = wt_cross_bull and in_strong_os and above_vwap
        buy_signal = wt_cross_bull and above_vwap and not in_os
        strong_sell = wt_cross_bear and in_strong_ob and below_vwap
        sell_signal = wt_cross_bear and below_vwap and not in_ob
        
        if strong_buy or buy_signal:
            if not self.position:
                self.buy()
        elif strong_sell or sell_signal:
            if self.position:
                self.sell()