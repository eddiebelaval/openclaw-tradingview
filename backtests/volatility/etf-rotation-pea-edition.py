import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        pass


if __name__ == "__main__":
    # Load data for CW8 (main index)
    cw8_data = pd.read_csv("CW8_daily.csv", index_col=0, parse_dates=True)
    cw8_data.columns = ["Open", "High", "Low", "Close", "Volume"]
    
    # Load data for ETFs
    ese_data = pd.read_csv("ESE_daily.csv", index_col=0, parse_dates=True)
    ese_data.columns = ["Open", "High", "Low", "Close", "Volume"]
    
    pust_data = pd.read_csv("PUST_daily.csv", index_col=0, parse_dates=True)
    pust_data.columns = ["Open", "High", "Low", "Close", "Volume"]
    
    meud_data = pd.read_csv("MEUD_daily.csv", index_col=0, parse_dates=True)
    meud_data.columns = ["Open", "High", "Low", "Close", "Volume"]
    
    paeem_data = pd.read_csv("PAEEM_daily.csv", index_col=0, parse_dates=True)
    paeem_data.columns = ["Open", "High", "Low", "Close", "Volume"]
    
    # Parameters
    vol_len = 252
    anchor_date = pd.Timestamp(2019, 6, 10)
    
    # Align all data to CW8 index
    all_dates = cw8_data.index.union(ese_data.index).union(pust_data.index).union(meud_data.index).union(paeem_data.index)
    
    cw8_data = cw8_data.reindex(all_dates, method='ffill')
    ese_data = ese_data.reindex(all_dates, method='ffill')
    pust_data = pust_data.reindex(all_dates, method='ffill')
    meud_data = meud_data.reindex(all_dates, method='ffill')
    paeem_data = paeem_data.reindex(all_dates, method='ffill')
    
    # Calculate returns and volatility for each ETF
    def calc_log_returns(prices):
        return np.log(prices / prices.shift(1))
    
    ese_returns = calc_log_returns(ese_data['Close'])
    pust_returns = calc_log_returns(pust_data['Close'])
    meud_returns = calc_log_returns(meud_data['Close'])
    paeem_returns = calc_log_returns(paeem_data['Close'])
    
    ese_vol = ese_returns.rolling(vol_len).std() * np.sqrt(252)
    pust_vol = pust_returns.rolling(vol_len).std() * np.sqrt(252)
    meud_vol = meud_returns.rolling(vol_len).std() * np.sqrt(252)
    paeem_vol = paeem_returns.rolling(vol_len).std() * np.sqrt(252)
    
    # Monthly momentum (1, 3, 6, 12 months)
    def get_monthly_returns(prices, periods):
        monthly_data = prices.resample('M').last()
        ret_1m = monthly_data.pct_change(1)
        ret_3m = monthly_data.pct_change(3)
        ret_6m = monthly_data.pct_change(6)
        ret_12m = monthly_data.pct_change(12)
        
        composite_momentum = 0.25 * (ret_1m + ret_3m + ret_6m + ret_12m)
        composite_momentum = composite_momentum.reindex(prices.index, method='ffill')
        return composite_momentum
    
    ese_mom = get_monthly_returns(ese_data['Close'], [1, 3, 6, 12])
    pust_mom = get_monthly_returns(pust_data['Close'], [1, 3, 6, 12])
    meud_mom = get_monthly_returns(meud_data['Close'], [1, 3, 6, 12])
    paeem_mom = get_monthly_returns(paeem_data['Close'], [1, 3, 6, 12])
    
    # Calculate scores (momentum / volatility)
    ese_score = ese_mom / ese_vol.replace(0, 1e-6)
    pust_score = pust_mom / pust_vol.replace(0, 1e-6)
    meud_score = meud_mom / meud_vol.replace(0, 1e-6)
    paeem_score = paeem_mom / paeem_vol.replace(0, 1e-6)
    
    # Determine selected ETF each month (highest score)
    selected_etf = []
    current_selection = None
    
    for date in cw8_data.index:
        if pd.isna(date) or date < anchor_date:
            selected_etf.append(0)  # CW8 (default)
            continue
        
        # Check if new month
        if current_selection is None or date.to_period('M') != current_selection['period']:
            ese_s = ese_score.loc[date] if date in ese_score.index else 0
            pust_s = pust_score.loc[date] if date in pust_score.index else 0
            meud_s = meud_score.loc[date] if date in meud_score.index else 0
            paeem_s = paeem_score.loc[date] if date in paeem_score.index else 0
            
            scores = {1: ese_s, 2: pust_s, 3: meud_s, 4: paeem_s}
            best_etf = max(scores, key=scores.get) if max(scores.values()) > 0 else 0
            current_selection = {'period': date.to_period('M'), 'etf': best_etf}
        
        selected_etf.append(current_selection['etf'])
    
    selected_etf = pd.Series(selected_etf, index=cw8_data.index)
    
    # Build equity curve based on selected ETF each period
    equity_curve = []
    cumulative_equity = 1.0
    prev_price = None
    prev_selected = 0
    
    for i, date in enumerate(cw8_data.index):
        if i == 0:
            equity_curve.append(1.0)
            continue
        
        current_selected = int(selected_etf.iloc[i])
        
        if current_selected == 1:
            curr_price = ese_data['Close'].iloc[i]
            prev_price = ese_data['Close'].iloc[i-1]
        elif current_selected == 2:
            curr_price = pust_data['Close'].iloc[i]
            prev_price = pust_data['Close'].iloc[i-1]
        elif current_selected == 3:
            curr_price = meud_data['Close'].iloc[i]
            prev_price = meud_data['Close'].iloc[i-1]
        elif current_selected == 4:
            curr_price = paeem_data['Close'].iloc[i]
            prev_price = paeem_data['Close'].iloc[i-1]
        else:
            curr_price = cw8_data['Close'].iloc[i]
            prev_price = cw8_data['Close'].iloc[i-1]
        
        if abs(prev_price) > 1e-10 and not pd.isna(curr_price):
            cumulative_equity *= curr_price / prev_price
        
        equity_curve.append(cumulative_equity)
    
    cw8_data['Equity'] = equity_curve
    
    # Filter data from anchor date
    bt_data = cw8_data[cw8_data.index >= anchor_date].copy()
    
    # Run backtest
    bt = Backtest(bt_data, TvStrategy, cash=10000, commission=0.001)
