import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    useATH = True
    use52W = True
    athLookback = 5000
    atrLength = 14
    atrMult = 2.0
    useEMAExit = False
    emaLength = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATH - rolling highest of high over lookback period
        self.ath = self.I(lambda: high.rolling(self.athLookback).max())
        
        # 52-Week High approximation (252 trading days per year, 52 weeks = ~252 bars)
        self.week52h = self.I(lambda: high.rolling(252).max())
        
        # ATR for trailing stop
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # EMA for exit option
        self.ema = self.I(pta.ema, close, length=self.emaLength)
        
        # Track highest price since entry
        self.highest_since_entry = None

    def next(self):
        if len(self.data) < max(self.athLookback, 252, self.atrLength, self.emaLength):
            return
        
        # Get current values
        current_high = self.data.High[-1]
        current_close = self.data.Close[-1]
        
        ath_value = self.ath[-1] if not np.isnan(self.ath[-1]) else 0
        week52_value = self.week52h[-1] if not np.isnan(self.week52h[-1]) else 0
        atr_value = self.atr[-1] if self.atr[-1] is not None and not np.isnan(self.atr[-1]) else 0
        ema_value = self.ema[-1] if self.ema[-1] is not None and not np.isnan(self.ema[-1]) else 0
        
        # Entry conditions
        breakATH = self.useATH and current_high > ath_value
        break52W = self.use52W and current_high > week52_value
        
        longCondition = breakATH or break52W
        
        # Entry logic
        if longCondition and not self.position:
            self.buy()
            self.highest_since_entry = current_high
        
        # Update highest since entry
        if self.position:
            if self.highest_since_entry is None:
                self.highest_since_entry = current_high
            else:
                self.highest_since_entry = max(self.highest_since_entry, current_high)
            
            # Exit logic
            if not self.useEMAExit:
                # ATR Trailing Stop
                if atr_value > 0:
                    atr_stop = self.highest_since_entry - (atr_value * self.atrMult)
                    if current_close < atr_stop:
                        self.sell()
            else:
                # EMA Exit
                if current_close < ema_value:
                    self.sell()
        else:
            self.highest_since_entry = None


