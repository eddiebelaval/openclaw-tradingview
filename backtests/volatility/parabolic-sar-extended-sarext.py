        high = self.data.High
        low = self.data.Low
        
        sar_values = []
        is_long = True
        sar = np.nan
        ep = np.nan
        af = self.af_init_long
        
        for i in range(len(high)):
            if i == 0:
                # Bar 0: store first bar, no output yet
                result = np.nan
            elif i == 1:
                # Bar 1: determine initial direction
                if self.start_value > 0:
                    is_long = True
                    sar = abs(self.start_value)
                elif self.start_value < 0:
                    is_long = False
                    sar = abs(self.start_value)
                else:
                    # Auto-detect from directional movement
                    plus_dm = high.iloc[i] - high.iloc[i-1]
                    minus_dm = low.iloc[i-1] - low.iloc[i]
                    if plus_dm < 0:
                        plus_dm = 0
                    if minus_dm < 0:
                        minus_dm = 0
                    is_long = plus_dm > minus_dm
                    sar = low.iloc[i-1] if is_long else high.iloc[i-1]
                
                # Set initial EP and AF
                ep = high.iloc[i] if is_long else low.iloc[i]
                af = self.af_init_long if is_long else self.af_init_short
                
                # Clamp SAR
                if is_long:
                    if sar > low.iloc[i-1]:
                        sar = low.iloc[i-1]
                    if sar > low.iloc[i]:
                        sar = low.iloc[i]
                else:
                    if sar < high.iloc[i-1]:
                        sar = high.iloc[i-1]
                    if sar < high.iloc[i]:
                        sar = high.iloc[i]
                
                result = sar if is_long else -sar
            else:
                # Bar 2+: standard SAR with asymmetric AF
                new_sar = sar + af * (ep - sar)
                
                if is_long:
                    # Clamp to prior lows
                    new_sar = min(new_sar, low.iloc[i-1])
                    new_sar = min(new_sar, low.iloc[i-2])
                    
                    # Reversal check
                    if low.iloc[i] < new_sar:
                        is_long = False
                        new_sar = ep
