import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sqzLength = 20
    adxThreshold = 20
    rvolThreshold = 1.2
    useLunchFilter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)

        # ADX calculation
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = adx_result

        # Bollinger Bands
        bb_result = self.I(lambda: pta.bbands(close, length=self.sqzLength, std=2.0))
        self.bb_upper = bb_result.iloc[:, 2] if bb_result is not None else None
        self.bb_lower = bb_result.iloc[:, 0] if bb_result is not None else None

        # Keltner Channels
        sma_basis = self.I(lambda: pta.sma(close, length=self.sqzLength))
        range_ma = self.I(lambda: pta.sma(high - low, length=self.sqzLength))
        self.kc_upper = self.I(lambda: pta.sma(close, length=self.sqzLength) + pta.sma(high - low, length=self.sqzLength) * 1.5)
        self.kc_lower = self.I(lambda: pta.sma(close, length=self.sqzLength) - pta.sma(high - low, length=self.sqzLength) * 1.5)

        # Volume calculations
        avg_vol = self.I(lambda: pta.sma(volume, length=20))
        self.avg_vol = avg_vol

        # VWAP
        vwap_result = self.I(lambda: pta.vwap(high, low, close, volume))
        self.vwap = vwap_result

        # Store raw series for calculations in next()
        self.close_series = close
        self.high_series = high
        self.low_series = low
        self.volume_series = volume
        self.open_series = open_

    def next(self):
        if len(self.data) < self.sqzLength + 1:
            return

        current_idx = len(self.data) - 1
        
        # Get current values
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        prev_volume = self.data.Volume[-2] if len(self.data) > 1 else volume

        # ADX value
        adx = self.adx[-1] if self.adx[-1] is not None else self.adxThreshold

        # Bollinger Bands and Keltner Channels
        bb_upper = self.bb_upper[-1] if self.bb_upper[-1] is not None else high
        bb_lower = self.bb_lower[-1] if self.bb_lower[-1] is not None else low
        kc_upper = self.kc_upper[-1] if self.kc_upper[-1] is not None else high
        kc_lower = self.kc_lower[-1] if self.kc_lower[-1] is not None else low

        # Squeeze condition
        sqz_on = (bb_lower > kc_lower) and (bb_upper < kc_upper)

        # Average volume
        avg_vol = self.avg_vol[-1] if self.avg_vol[-1] is not None else volume

        # Dynamic multiplier based on time (simplified: use static 1.5 for backtesting)
        dynamic_mult = 1.5
        is_vol_spike = volume > (avg_vol * dynamic_mult) and volume > prev_volume

        # High confidence conditions
        body_size = abs(close - open_)
        hl_range = high - low
        is_solid_body = (body_size / hl_range) > 0.7 if hl_range > 0 else False
        close_near_high = (close - low) / hl_range > 0.85 if hl_range > 0 else False
        close_near_low = (high - close) / hl_range > 0.85 if hl_range > 0 else False

        rvol = (volume / avg_vol) if avg_vol > 0 else 0

        bull_conf = (is_solid_body and close > open_ and close_near_high and 
                     rvol > self.rvolThreshold and not sqz_on and adx > self.adxThreshold)
        bear_conf = (is_solid_body and close < open_ and close_near_low and 
                     rvol > self.rvolThreshold and not sqz_on and adx > self.adxThreshold)

        # Trading logic
        if bull_conf and not self.position:
            self.buy()
        elif bear_conf and self.position:
            self.sell()

        # Exit on squeeze onset
        if sqz_on and self.position:
            self.sell()


