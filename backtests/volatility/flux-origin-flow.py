import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # ATR-based momentum detection
    atr_len = 14
    atr_mult = 1.4
    zscore_period = 50
    normal_threshold = 1.0
    elevated_threshold = 2.0
    institutional_threshold = 3.0
    cooldown_bars = 5
    small_body_p = 0.33

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Volume z-score
        def calc_vol_zscore():
            vol_series = volume
            m = vol_series.rolling(self.zscore_period).mean()
            s = vol_series.rolling(self.zscore_period).std()
            zscore = (vol_series - m) / s.replace(0, 1)
            return zscore.fillna(0)
        
        self.vol_zscore = self.I(calc_vol_zscore)
        
        # True Range
        def calc_tr():
            prev_close = close.shift(1)
            tr = np.maximum(
                high - low,
                np.maximum(
                    np.abs(high - prev_close),
                    np.abs(low - prev_close)
                )
            )
            return tr
        
        self.tr = self.I(calc_tr)
        
        # Body percentage
        def calc_body_pct():
            body = np.abs(close - self.data.Open)
            rng = high - low
            body_pct = body / rng.replace(0, 1)
            return body_pct
        
        self.body_pct = self.I(calc_body_pct)
        
        self.last_mark_bar = -np.inf

    def next(self):
        if len(self.data) < self.atr_len + self.zscore_period:
            return
        
        # Current bar metrics
        current_atr = self.atr[-1]
        current_vol_zscore = self.vol_zscore[-1]
        current_tr = self.tr[-1]
        current_body_pct = self.body_pct[-1]
        
        if np.isnan(current_atr) or np.isnan(current_vol_zscore):
            return
        
        # Check for range spike (momentum)
        range_spike = current_tr > current_atr * self.atr_mult
        
        # Check for small body (absorption)
        small_body = current_body_pct < self.small_body_p
        
        # Activity levels
        is_elevated = current_vol_zscore >= self.elevated_threshold
        is_institutional = current_vol_zscore >= self.institutional_threshold
        
        # Momentum pattern: elevated + range spike
        raw_momentum = is_elevated and range_spike
        
        # Absorption pattern: elevated + small body
        raw_absorption = is_elevated and small_body
        
        # Cooldown check
        bars_since_mark = len(self.data) - self.last_mark_bar
        on_cooldown = bars_since_mark < self.cooldown_bars
        
        # Entry logic: any confirmed pattern without cooldown
        if not on_cooldown:
            if raw_momentum and self.data.Close[-1] > self.data.Open[-1]:
                # Bullish momentum
                if not self.position:
                    self.buy()
                self.last_mark_bar = len(self.data)
            elif raw_absorption and self.data.Close[-1] < self.data.Open[-1]:
                # Bearish absorption
                if self.position:
                    self.position.close()
                self.last_mark_bar = len(self.data)
        
        # Exit logic: simple reversal after entry
        if self.position:
            # Exit long on bearish absorption
            if raw_absorption and self.data.Close[-1] < self.data.Open[-1]:
                self.position.close()
            # Exit on institutional activity in opposite direction
            elif is_institutional and self.data.Close[-1] < self.data.Open[-1]:
                self.position.close()


