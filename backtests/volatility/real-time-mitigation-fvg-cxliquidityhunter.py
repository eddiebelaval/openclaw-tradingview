class TvStrategy(Strategy):
    # FVG Detection Parameters
    bull_gaps = True
    bear_gaps = True
    volume_bars = True
    
    # Mitigation thresholds
    long_threshold = 5.0
    short_threshold = 5.0
    
    # Volume filters
    use_vol_filter = True
    min_vol_long = 1000
    max_vol_long = 0
    min_vol_short = 1000
    max_vol_short = 0
    
    # Share filters
    use_share_filter = True
    long_bull_share_min = 70
    long_bear_share_max = 100
    short_bear_share_min = 70
    short_bull_share_max = 100
    
    # Age filters
    use_age_filter = True
    min_age_long = 40
    min_age_short = 40
    
    # Candle confirmation & cooldown
    confirm_candle = False
    cooldown_bars = 0
    
    # Mitigation source
    mitigation_src = "high/low"

    def init(self):
        self.fvgs = []
        self.last_bull_left_traded = None
        self.last_bear_left_traded = None
        self.last_entry_bar = None
        
    def detect_fvg(self):
        """Detect Fair Value Gaps"""
        if len(self.data) < 3:
            return
        
        close = self.data.Close
        open_ = self.data.Open
        high = self.data.High
        low = self.data.Low
        volume = self.data.Volume
        
        idx = len(self.data) - 1
        
        if idx < 2:
            return
        
        # Current bar [0], previous [1], two bars ago [2]
        close_1 = close.iloc[idx - 1]
        open_1 = open_.iloc[idx - 1]
        high_1 = high.iloc[idx - 1]
        low_1 = low.iloc[idx - 1]
        high_2 = high.iloc[idx - 2]
        low_2 = low.iloc[idx - 2]
        
        close_cur = close.iloc[idx]
        high_cur = high.iloc[idx]
        low_cur = low.iloc[idx]
        
        # FVG detection logic
        if close_1 > open_1:
            diff = (low_cur - high_2) / low_cur * 100
        else:
            diff = (low_2 - high_cur) / high_cur * 100
        
        # Percentile approximation (simplified)
        size_fvg = abs(diff) * 1.2
        filter_fvg = size_fvg > 10
        
        # Bullish FVG: gap up
        is_bull_gap = (high_2 < low_cur and 
                      high_2 < high_1 and 
                      low_2 < low_cur and 
                      filter_fvg)
        
        # Bearish FVG: gap down
        is_bear_gap = (low_2 > high_cur and 
                      low_2 > low_1 and 
                      high_2 > high_cur and 
                      filter_fvg)
        
        # Volume split estimation (simple: use close position in range)
        hl_range = max(1e-10, high_1 - low_1)
        share = (close_1 - low_1) / hl_range
        share = max(0.0, min(1.0, share))
        bull_vol = volume.iloc[idx - 1] * share
        bear_vol = volume.iloc[idx - 1] * (1.0 - share)
        total_vol = volume.iloc[idx - 1]
        
        bull_pct = (bull_vol / total_vol * 100) if total_vol > 0 else 50
        bear_pct = 100 - bull_pct
        
        # Create FVG entries
        if is_bull_gap and self.bull_gaps and idx > 100:
            self.fvgs.append({
                'type': 'bull',
                'top': high_2,
                'bottom': low_cur,
                'born_bar': idx,
                'total_vol': total_vol,
                'bull_pct': bull_pct,
                'bear_pct': bear_pct
            })
        
        if is_bear_gap and self.bear_gaps and idx > 100:
            self.fvgs.append({
                'type': 'bear',
                'top': high_cur,
                'bottom': low_2,
                'born_bar': idx,
                'total_vol': total_vol,
                'bull_pct': bull_pct,
                'bear_pct': bear_pct
            })
    
    def calculate_mitigation(self, fvg, close_price):
        """Calculate mitigation percentage"""
        top = max(fvg['top'], fvg['bottom'])
        bot = min(fvg['top'], fvg['bottom'])
        height = max(1e-10, top - bot)
        
        if fvg['type'] == 'bull':
            if close_price >= top:
                pct = 0.0
            elif close_price <= bot:
                pct = 100.0
            else:
                pct = ((top - close_price) / height) * 100
        else:
            if close_price <= bot:
                pct = 0.0
            elif close_price >= top:
                pct = 100.0
            else:
                pct = ((close_price - bot) / height) * 100
        
        return max(0, min(100, pct))
    
    def check_filters(self, fvg, bar_idx, close_price, open_price):
        """Check all filters for FVG signal"""
        age_bars = bar_idx - fvg['born_bar']
        mitigation = self.calculate_mitigation(fvg, close_price)
        
        if fvg['type'] == 'bull':
            # Check mitigation threshold
            if mitigation < self.long_threshold:
                return False
            
            # Check candle confirmation
            if self.confirm_candle and close_price <= open_price:
                return False
            
            # Check volume filter
            if self.use_vol_filter:
                if fvg['total_vol'] < self.min_vol_long:
                    return False
                if self.max_vol_long > 0 and fvg['total_vol'] > self.max_vol_long:
                    return False
            
            # Check age filter
            if self.use_age_filter and age_bars < self.min_age_long:
                return False
            
            # Check share filter
            if self.use_share_filter:
                if fvg['bull_pct'] < self.long_bull_share_min:
                    return False
                if fvg['bear_pct'] > self.long_bear_share_max:
                    return False
            
            return True
        
        else:  # bear
            # Check mitigation threshold
            if mitigation < self.short_threshold:
                return False
            
            # Check candle confirmation
            if self.confirm_candle and close_price >= open_price:
                return False
            
            # Check volume filter
            if self.use_vol_filter:
                if fvg['total_vol'] < self.min_vol_short:
                    return False
                if self.max_vol_short > 0 and fvg['total_vol'] > self.max_vol_short:
                    return False
            
            # Check age filter
            if self.use_age_filter and age_bars < self.min_age_short:
                return False
            
            # Check share filter
            if self.use_share_filter:
                if fvg['bear_pct'] < self.short_bear_share_min:
                    return False
                if fvg['bull_pct'] > self.short_bull_share_max:
                    return False
            
            return True
    
    def next(self):
        idx = len(self.data) - 1
        
        # Detect new FVGs
        self.detect_fvg()
        
        # Clean expired FVGs (older than 200 bars or fully crossed)
        self.fvgs = [fvg for fvg in self.fvgs if idx - fvg['born_bar'] < 200]
        
        close_price = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        
