import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLen = 14
    multi = 1.05

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.volatility_pct = self.I(lambda: (self.atr / close * 100) if self.atr is not None else pd.Series(0, index=close.index))
        
        self.suggested_stop = self.I(lambda: close - (self.atr * self.multi) if self.atr is not None else pd.Series(close, index=close.index))
        
        self.suggested_target = self.I(lambda: close + (self.atr * self.multi * 2) if self.atr is not None else pd.Series(close, index=close.index))

    def next(self):
        if len(self) < self.atrLen + 1:
            return
        
        if not self.position:
            if self.suggested_stop[-1] > 0 and self.data.Close[-1] > self.suggested_stop[-1]:
                self.buy()
        else:
            if self.data.Close[-1] <= self.suggested_stop[-1]:
                self.sell()
            elif self.data.Close[-1] >= self.suggested_target[-1]:
                self.sell()