import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    wick_threshold = 8.0
    min_rejection_ratio = 0.5

    def init(self):
        pass

    def next(self):
        if len(self.data) < 1:
            return

        idx = len(self.data) - 1
        open_price = self.data.Open[idx]
        close_price = self.data.Close[idx]
        high_price = self.data.High[idx]
        low_price = self.data.Low[idx]

        body_high = max(open_price, close_price)
        body_low = min(open_price, close_price)
        body_size = body_high - body_low

        lower_wick_size = body_low - low_price
        upper_wick_size = high_price - body_high

        total_range = high_price - low_price

        lower_wick_ratio = lower_wick_size / total_range if total_range > 0 else 0
        upper_wick_ratio = upper_wick_size / total_range if total_range > 0 else 0

        buy_signal = False
        sell_signal = False

        if lower_wick_size >= self.wick_threshold and lower_wick_ratio >= self.min_rejection_ratio:
            if close_price > body_low:
                buy_signal = True

        if upper_wick_size >= self.wick_threshold and upper_wick_ratio >= self.min_rejection_ratio:
            if close_price < body_high:
                sell_signal = True

        if buy_signal:
            if not self.position:
                self.buy()
        elif sell_signal:
            if self.position:
                self.position.close()