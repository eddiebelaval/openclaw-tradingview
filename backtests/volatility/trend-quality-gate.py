import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core Engine parameters
    emaLenF = 21
    emaLenM = 34
    emaLenS = 55
    
    # Enhancements
    lookback = 200
    
    # RSI length for momentum quality
    rsi_length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMAs
        self.emaF = self.I(pta.ema, close, length=self.emaLenF)
        self.emaM = self.I(pta.ema, close, length=self.emaLenM)
        self.emaS = self.I(pta.ema, close, length=self.emaLenS)
        
        # Direction: 1 if F>M>S, -1 if F<M<S, 0 otherwise
        self.direction = self.I(self._calc_direction, self.emaF, self.emaM, self.emaS)
        
        # Volume Efficiency
        self.effRaw = self.I(self._calc_eff_raw, high, low, volume)
        self.effQ = self.I(self._calc_eff_q, self.effRaw)
        
        # Quality Metrics
        self.slopeQ = self.I(self._calc_slope_q, self.emaM, close)
        self.momQ = self.I(self._calc_mom_q, close)
        self.quality = self.I(self._calc_quality, self.slopeQ, self.momQ, self.effQ)
        
        # TQ Score
        self.tqRaw = self.I(self._calc_tq_raw, self.direction, self.quality)
        self.tqFast = self.I(pta.ema, self.tqRaw, length=3)
        self.dynThresh = self.I(self._calc_dyn_thresh, self.tqRaw, self.lookback)
        
        # Divergence detection (pivot-based)
        self.phPrice = self.I(self._calc_pivot_high_price, high)
        self.phTQ = self.I(self._calc_pivot_high_tq, self.tqFast)
        self.bearExhaustion = self.I(self._calc_bear_exhaustion, self.phPrice, self.phTQ)
        
        # Posture determination
        self.isBull = self.I(self._calc_is_bull, self.tqFast, self.dynThresh)
        self.isBear = self.I(self._calc_is_bear, self.tqFast, self.dynThresh)
        
        # State tracking for divergence
        self.prevPricePH = None
        self.prevTQPH = None

    def _calc_direction(self, emaF, emaM, emaS):
        result = pd.Series(0.0, index=emaF.index)
        bull = (emaF > emaM) & (emaM > emaS)
        bear = (emaF < emaM) & (emaM < emaS)
        result[bull] = 1.0
        result[bear] = -1.0
        return result

    def _calc_eff_raw(self, high, low, volume):
        sma_vol = pta.sma(volume, length=20)
        result = (high - low) / (volume / sma_vol)
        return result.fillna(0)

    def _calc_eff_q(self, effRaw):
        sma_eff = pta.sma(effRaw, length=50)
        result = np.minimum(effRaw / sma_eff, 2.0) / 2.0
        return result.fillna(0)

    def _calc_slope_q(self, emaM, close):
        emaM_shift = emaM.shift(5)
        result = np.minimum(np.abs(emaM - emaM_shift) / (close * 0.002), 1.0)
        return result.fillna(0)

    def _calc_mom_q(self, close):
        rsi = pta.rsi(close, length=self.rsi_length)
        result = np.abs(rsi - 50.0) / 50.0
        return result.fillna(0)

    def _calc_quality(self, slopeQ, momQ, effQ):
        result = (slopeQ + momQ + effQ) / 3.0 * 5.0
        return result.fillna(0)

    def _calc_tq_raw(self, direction, quality):
        result = direction * quality * 20.0
        return result.fillna(0)

    def _calc_dyn_thresh(self, tqRaw, lookback):
        result = tqRaw.rolling(window=lookback).std()
        return result.fillna(0)

    def _calc_pivot_high_price(self, high):
        pivL, pivR = 5, 5
        result = pd.Series(np.nan, index=high.index)
        for i in range(pivL + pivR, len(high)):
            if i - pivL >= 0 and i + pivR < len(high):
                window = high.iloc[i-pivL:i+pivR+1]
                if high.iloc[i] == window.max() and high.iloc[i] > high.iloc[i-1]:
                    result.iloc[i] = high.iloc[i]
        return result

    def _calc_pivot_high_tq(self, tqFast):
        pivL, pivR = 5, 5
        result = pd.Series(np.nan, index=tqFast.index)
        for i in range(pivL + pivR, len(tqFast)):
            if i - pivL >= 0 and i + pivR < len(tqFast):
                window = tqFast.iloc[i-pivL:i+pivR+1]
                if tqFast.iloc[i] == window.max() and tqFast.iloc[i] > tqFast.iloc[i-1]:
                    result.iloc[i] = tqFast.iloc[i]
        return result

    def _calc_bear_exhaustion(self, phPrice, phTQ):
        result = pd.Series(False, index=phPrice.index)
        return result

    def _calc_is_bull(self, tqFast, dynThresh):
        result = tqFast > dynThresh
        return result

    def _calc_is_bear(self, tqFast, dynThresh):
        result = tqFast < -dynThresh
        return result

    def next(self):
        # Extract current values
        if len(self.data) < self.emaLenS + 10:
            return
        
        tq_current = self.tqFast[-1]
        is_bull = self.isBull[-1]
        is_bear = self.isBear[-1]
        quality_current = self.quality[-1]
        
        # Buy signal: Strong bullish TQ with good quality
        if is_bull and quality_current >= 3.0:
            if not self.position:
                self.buy()
        
        # Sell signal: Bearish TQ or quality deterioration
        elif is_bear or (is_bull is False and tq_current < 0):
            if self.position:
                self.sell()
        
        # Exit on quality collapse
        elif quality_current < 1.0 and self.position:
            self.sell()


