import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    leftLen = 15
    rightLen = 15
    volLen = 20
    volMult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate volume average
        self.volAvg = self.I(pta.sma, volume, length=self.volLen)

        # Pivot points for resistance and support
        def calc_resistance():
            result = []
            for i in range(len(close)):
                if i < self.leftLen + self.rightLen:
                    result.append(np.nan)
                else:
                    left_idx = i - self.leftLen - 1
                    right_idx = i - 1
                    window = high.iloc[left_idx:right_idx + 1]
                    if len(window) > 0:
                        max_val = window.max()
                        center_idx = self.leftLen
                        if (i - self.leftLen - 1) >= 0 and (i - 1) < len(high):
                            center_high = high.iloc[i - self.rightLen - 1] if (i - self.rightLen - 1) >= 0 else np.nan
                            is_pivot = True
                            for j in range(self.leftLen):
                                if (i - self.leftLen - 1 - j) >= 0:
                                    if high.iloc[i - self.leftLen - 1 - j] >= center_high:
                                        is_pivot = False
                            for j in range(1, self.rightLen + 1):
                                if (i - self.rightLen + j - 1) < len(high):
                                    if high.iloc[i - self.rightLen + j - 1] >= center_high:
                                        is_pivot = False
                            result.append(center_high if is_pivot else np.nan)
                        else:
                            result.append(np.nan)
                    else:
                        result.append(np.nan)
            return pd.Series(result, index=close.index)

        def calc_support():
            result = []
            for i in range(len(close)):
                if i < self.leftLen + self.rightLen:
                    result.append(np.nan)
                else:
                    left_idx = i - self.leftLen - 1
                    right_idx = i - 1
                    window = low.iloc[left_idx:right_idx + 1]
                    if len(window) > 0:
                        min_val = window.min()
                        center_idx = self.leftLen
                        if (i - self.leftLen - 1) >= 0 and (i - 1) < len(low):
                            center_low = low.iloc[i - self.rightLen - 1] if (i - self.rightLen - 1) >= 0 else np.nan
                            is_pivot = True
                            for j in range(self.leftLen):
                                if (i - self.leftLen - 1 - j) >= 0:
                                    if low.iloc[i - self.leftLen - 1 - j] <= center_low:
                                        is_pivot = False
                            for j in range(1, self.rightLen + 1):
                                if (i - self.rightLen + j - 1) < len(low):
                                    if low.iloc[i - self.rightLen + j - 1] <= center_low:
                                        is_pivot = False
                            result.append(center_low if is_pivot else np.nan)
                        else:
                            result.append(np.nan)
                    else:
                        result.append(np.nan)
            return pd.Series(result, index=close.index)

        self.resistance = self.I(calc_resistance)
        self.support = self.I(calc_support)

        # Body range and candle metrics
        def calc_body_range():
            return np.abs(close - open_)

        def calc_candle_range():
            return high - low

        def calc_body_ratio():
            body = np.abs(close - open_)
            candle = high - low
            return np.where(candle > 0, body / candle, 0.5)

        self.bodyRange = self.I(calc_body_range)
        self.candleRange = self.I(calc_candle_range)
        self.bodyRatio = self.I(calc_body_ratio)

        # Volume split
        def calc_bull_volume():
            body = np.abs(close - open_)
            candle = high - low
            ratio = np.where(candle > 0, body / candle, 0.5)
            bull = np.where(close >= open_, volume * (0.5 + ratio * 0.5), volume * (0.5 - ratio * 0.5))
            return bull

        def calc_bear_volume():
            body = np.abs(close - open_)
            candle = high - low
            ratio = np.where(candle > 0, body / candle, 0.5)
            bull = np.where(close >= open_, volume * (0.5 + ratio * 0.5), volume * (0.5 - ratio * 0.5))
            return volume - bull

        self.bullVolume = self.I(calc_bull_volume)
        self.bearVolume = self.I(calc_bear_volume)

        # Wick characteristics
        def calc_long_lower_wick():
            return (open_ - low) > (close - open_) & (close > open_)

        def calc_long_upper_wick():
            return (high - open_) > (open_ - close) & (close < open_)

        self.longLowerWick = self.I(calc_long_lower_wick)
        self.longUpperWick = self.I(calc_long_upper_wick)

    def next(self):
        if len(self.data) < self.leftLen + self.rightLen + 2:
            return

        close = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]

        resistance = self.resistance[-1]
        resistance_prev = self.resistance[-2] if len(self.resistance) > 1 else resistance
        support = self.support[-1]
        support_prev = self.support[-2] if len(self.support) > 1 else support

        volAvg = self.volAvg[-1]
        volSpike = volume >= volAvg * self.volMult

        bullVolume = self.bullVolume[-1]
        bearVolume = self.bearVolume[-1]
        bullDominant = bullVolume > bearVolume
        bearDominant = bearVolume > bullVolume

        longLowerWick = self.longLowerWick[-1]
        longUpperWick = self.longUpperWick[-1]

        bodyBreakUp = close > resistance and close_prev <= resistance_prev
        bodyBreakDown = close < support and close_prev >= support_prev

        bullBreak = bodyBreakUp and volSpike and bullDominant
        bearBreak = bodyBreakDown and volSpike and bearDominant

        bullWickBreak = bodyBreakUp and volSpike and longLowerWick
        bearWickBreak = bodyBreakDown and volSpike and longUpperWick

        # Trading logic
        if bullBreak and not bullWickBreak:
            if self.position:
                self.position.close()
            self.buy()
        elif bearBreak and not bearWickBreak:
            if self.position:
                self.position.close()
            self.sell()
        elif bullWickBreak and self.position.is_short:
            self.position.close()
        elif bearWickBreak and self.position.is_long:
            self.position.close()


