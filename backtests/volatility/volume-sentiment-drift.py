import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    volLen = 20
    atrLen = 14
    eeSmoothLen = 21
    driftSmoothLen = 21
    confirmBars = 5
    hystBand = 0.08

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # 1. Participation (Relative Volume)
        volMA = self.I(pta.sma, volume, length=self.volLen)
        
        # 2. True Range calculation
        tr_vals = self.I(lambda: pd.Series(
            np.maximum(
                high - low,
                np.maximum(
                    np.abs(high - close.shift(1)),
                    np.abs(low - close.shift(1))
                )
            ),
            index=close.index
        ))
        
        # 3. ATR
        atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # 4. Calculate RVOL (Relative Volume)
        def calc_rvol():
            rvol_series = pd.Series(index=volume.index, dtype=float)
            for i in range(len(volume)):
                if volMA.iloc[i] > 0:
                    rvol_series.iloc[i] = volume.iloc[i] / volMA.iloc[i]
                else:
                    rvol_series.iloc[i] = 1.0
            return rvol_series
        
        rvol = self.I(calc_rvol)
        
        # 5. Calculate Efficiency (ATR-normalized True Range)
        def calc_eff():
            eff_series = pd.Series(index=tr_vals.index, dtype=float)
            for i in range(len(tr_vals)):
                if atr.iloc[i] > 0:
                    raw_eff = tr_vals.iloc[i] / atr.iloc[i]
                    eff_series.iloc[i] = min(raw_eff, 3.0)
                else:
                    eff_series.iloc[i] = 0.0
            return eff_series
        
        eff = self.I(calc_eff)
        
        # 6. Emotional Energy (RVOL × Efficiency)
        def calc_ee_raw():
            return rvol * eff
        
        ee_raw = self.I(calc_ee_raw)
        
        # 7. Smooth Energy with EMA
        ee = self.I(pta.ema, ee_raw, length=self.eeSmoothLen)
        
        # 8. Calculate Drift (Change in Energy)
        def calc_drift_raw():
            drift_series = pd.Series(index=ee.index, dtype=float)
            for i in range(len(ee)):
                if i == 0:
                    drift_series.iloc[i] = 0.0
                else:
                    drift_series.iloc[i] = ee.iloc[i] - ee.iloc[i-1]
            return drift_series
        
        drift_raw = self.I(calc_drift_raw)
        
        # 9. Smooth Drift with EMA
        drift = self.I(pta.ema, drift_raw, length=self.driftSmoothLen)
        
        # 10. Normalize Drift by Standard Deviation
        def calc_drift_normalized():
            scale_length = max(10, self.driftSmoothLen)
            drift_std = drift.rolling(window=scale_length).std()
            drift_n = pd.Series(index=drift.index, dtype=float)
            
            for i in range(len(drift)):
                if i > max(self.volLen, self.atrLen, self.eeSmoothLen, self.driftSmoothLen) + 10:
                    if drift_std.iloc[i] > 0:
                        drift_n.iloc[i] = drift.iloc[i] / drift_std.iloc[i]
                    else:
                        drift_n.iloc[i] = 0.0
                else:
                    drift_n.iloc[i] = 0.0
            
            return drift_n
        
        self.drift_n = self.I(calc_drift_normalized)
        self.accel_cnt = 0
        self.decay_cnt = 0

    def next(self):
        drift_val = self.drift_n[-1]
        
        is_accel = drift_val > self.hystBand
        is_decay = drift_val < -self.hystBand
        
        if is_accel:
            self.accel_cnt += 1
            self.decay_cnt = 0
        elif is_decay:
            self.decay_cnt += 1
            self.accel_cnt = 0
        else:
            self.accel_cnt = 0
            self.decay_cnt = 0
        
        # Trading logic: Buy on acceleration signal, sell on decay signal
        if self.accel_cnt >= self.confirmBars and not self.position:
            self.buy()
        elif self.decay_cnt >= self.confirmBars and self.position:
            self.sell()


