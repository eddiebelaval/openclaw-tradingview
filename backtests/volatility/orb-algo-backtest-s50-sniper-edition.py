import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    orb_time = 30
    tp1_mult = 0.75
    tp2_mult = 1.50
    tp3_mult = 2.25

    def init(self):
        self.atr = self.I(pta.atr, self.data.High, self.data.Low, self.data.Close, length=14)
        
        self.orb_high = None
        self.orb_low = None
        self.is_trading = False
        self.sl_price = None
        self.tp1 = None
        self.tp2 = None
        self.tp3 = None
        self.session_start_idx = 0

    def next(self):
        if len(self.data) < 2:
            return

        current_time = self.data.index[-1]
        prev_time = self.data.index[-2]

        is_new_session = current_time.date() != prev_time.date()

        if is_new_session:
            self.orb_high = None
            self.orb_low = None
            self.is_trading = False
            self.session_start_idx = len(self.data) - 1

        session_start_time = self.data.index[self.session_start_idx]
        orb_end_time = session_start_time + pd.Timedelta(minutes=self.orb_time)
        in_orb_period = current_time < orb_end_time

        if in_orb_period:
            if self.orb_high is None:
                self.orb_high = self.data.High[-1]
            else:
                self.orb_high = max(self.orb_high, self.data.High[-1])

            if self.orb_low is None:
                self.orb_low = self.data.Low[-1]
            else:
                self.orb_low = min(self.orb_low, self.data.Low[-1])

        can_trade = not in_orb_period and not self.is_trading and self.orb_high is not None and self.orb_low is not None

        if self.atr[-1] is None or np.isnan(self.atr[-1]):
            return

        long_cond = can_trade and len(self.data) >= 2 and self.data.Close[-2] <= self.orb_high and self.data.Close[-1] > self.orb_high
        short_cond = can_trade and len(self.data) >= 2 and self.data.Close[-2] >= self.orb_low and self.data.Close[-1] < self.orb_low

        if long_cond:
            self.buy()
            self.is_trading = True
            self.sl_price = (self.orb_high + self.orb_low) / 2
            self.tp1 = self.data.Close[-1] + (self.atr[-1] * self.tp1_mult)
            self.tp2 = self.data.Close[-1] + (self.atr[-1] * self.tp2_mult)
            self.tp3 = self.data.Close[-1] + (self.atr[-1] * self.tp3_mult)

        if short_cond:
            self.sell()
            self.is_trading = True
            self.sl_price = (self.orb_high + self.orb_low) / 2
            self.tp1 = self.data.Close[-1] - (self.atr[-1] * self.tp1_mult)
            self.tp2 = self.data.Close[-1] - (self.atr[-1] * self.tp2_mult)
            self.tp3 = self.data.Close[-1] - (self.atr[-1] * self.tp3_mult)

        if self.position:
            if self.position.is_long:
                if self.data.Close[-1] <= self.sl_price or self.data.Close[-1] >= self.tp2:
                    self.position.close()
                    self.is_trading = False
                    self.sl_price = None

            elif self.position.is_short:
                if self.data.Close[-1] >= self.sl_price or self.data.Close[-1] <= self.tp2:
                    self.position.close()
                    self.is_trading = False
                    self.sl_price = None

        if is_new_session and self.position:
            self.position.close()
            self.is_trading = False
            self.sl_price = None


