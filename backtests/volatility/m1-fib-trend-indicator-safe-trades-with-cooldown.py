import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastEMA = 9
    slowEMA = 21
    atrMultiplier = 2.0
    extraBuffer = 0.5
    cooldownBars = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA Trend
        self.emaFast = self.I(pta.ema, close, length=self.fastEMA)
        self.emaSlow = self.I(pta.ema, close, length=self.slowEMA)
        
        # Swing High/Low for Fibonacci (20-period)
        self.swingHigh = self.I(lambda: high.rolling(20).max())
        self.swingLow = self.I(lambda: low.rolling(20).min())
        
        # Fibonacci Levels
        def fib618():
            uptrend = self.emaFast[-1] > self.emaSlow[-1]
            if uptrend:
                return self.swingLow[-1] + (self.swingHigh[-1] - self.swingLow[-1]) * 0.618
            else:
                return self.swingHigh[-1] - (self.swingHigh[-1] - self.swingLow[-1]) * 0.618
        
        def tp161():
            uptrend = self.emaFast[-1] > self.emaSlow[-1]
            if uptrend:
                return self.swingLow[-1] + (self.swingHigh[-1] - self.swingLow[-1]) * 1.618
            else:
                return self.swingHigh[-1] - (self.swingHigh[-1] - self.swingLow[-1]) * 1.618
        
        self.fib618_val = self.I(fib618)
        self.tp161_val = self.I(tp161)
        
        # ATR-based SL
        atr = self.I(pta.atr, high, low, close, length=14)
        
        def sl_long():
            uptrend = self.emaFast[-1] > self.emaSlow[-1]
            if uptrend:
                return self.swingLow[-1] - atr[-1] * self.atrMultiplier - self.extraBuffer
            else:
                return np.nan
        
        def sl_short():
            downtrend = self.emaFast[-1] < self.emaSlow[-1]
            if downtrend:
                return self.swingHigh[-1] + atr[-1] * self.atrMultiplier + self.extraBuffer
            else:
                return np.nan
        
        self.slLong = self.I(sl_long)
        self.slShort = self.I(sl_short)
        
        # Trade tracking
        self.inLong = False
        self.inShort = False
        self.entryPrice = np.nan
        self.stopLoss = np.nan
        self.takeProfit = np.nan
        self.lastExitBar = None

