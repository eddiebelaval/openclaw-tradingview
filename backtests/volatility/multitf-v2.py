class TvStrategy(Strategy):
    # Core Settings
    auto_mode = True
    manual_mode = "Balanced"
    
    # Multi-Timeframe
    use_mtf = True
    htf_min_strength = 60
    
    # Market Regime
    use_regime = True
    adx_len = 14
    adx_threshold = 25
    
    # Session Filter
    use_session = False
    london_session = True
    ny_session = True
    
    # Advanced Exits
    use_trailing = True
    trail_activate = 1.0
    trail_dist = 1.5
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Determine mode based on timeframe
        self.is_fast = True
        self.is_balanced = True
        self.is_swing = False
        self.current_mode = "Balanced"
        
        # Market Regime Detection
        adx_result = pta.adx(high, low, close, length=self.adx_len)
        self.adx = self.I(lambda: adx_result['ADX_14'] if adx_result is not None else pd.Series(25, index=close.index))
        
        bb_result = pta.bbands(close, length=20, std=2)
        self.bb_mid = self.I(lambda: bb_result['BBM_20_2.0'] if bb_result is not None else close)
        self.bb_upper = self.I(lambda: bb_result['BBU_20_2.0'] if bb_result is not None else close)
        self.bb_lower = self.I(lambda: bb_result['BBL_20_2.0'] if bb_result is not None else close)
        
        # Fast Mode Indicators
        self.fast_rsi = self.I(lambda: pta.rsi(close, length=7) or pd.Series(50, index=close.index))
        self.fast_ema9 = self.I(lambda: pta.ema(close, length=9) or close)
        self.fast_ema21 = self.I(lambda: pta.ema(close, length=21) or close)
        self.fast_vol_avg = self.I(lambda: pta.sma(volume, length=20) or volume)
        
        fast_bb = pta.bbands(close, length=10, std=1.5)
        self.fast_bb_upper = self.I(lambda: fast_bb['BBU_10_1.5'] if fast_bb is not None else close)
        self.fast_bb_lower = self.I(lambda: fast_bb['BBL_10_1.5'] if fast_bb is not None else close)
        
