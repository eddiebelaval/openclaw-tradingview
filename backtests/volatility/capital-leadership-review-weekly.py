import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Relative Leadership
    rsFastLen = 10
    rsSlowLen = 30
    rsSlopeLookback = 8
    
    # Absolute Trend
    trendFastLen = 10
    trendSlowLen = 30
    trendSlopeLookback = 8
    
    # Range Position
    rangeLookback = 30
    minRangePosition = 0.65
    maxPctFromHigh = 15.0
    
    # Orderliness
    orderStdevLen = 20
    orderAtrLen = 14
    maxOrderliness = 2.5
    
    # Liquidity
    liquidityLen = 20
    minDollarVolumeM = 20.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Relative Strength calculations
        self.rs_line = self.I(lambda: close / 1.0)  # Simplified: assume benchmark moves similarly
        self.rs_fast = self.I(pta.sma, close, length=self.rsFastLen)
        self.rs_slow = self.I(pta.sma, close, length=self.rsSlowLen)
        
        # Absolute Trend calculations
        self.trend_fast = self.I(pta.sma, close, length=self.trendFastLen)
        self.trend_slow = self.I(pta.sma, close, length=self.trendSlowLen)
        
        # Range Position calculations
        self.range_high = self.I(lambda: high.rolling(self.rangeLookback).max())
        self.range_low = self.I(lambda: low.rolling(self.rangeLookback).min())
        
        # Orderliness calculations
        self.close_stdev = self.I(pta.stdev, close, length=self.orderStdevLen)
        
        # ATR calculation for orderliness
        def calc_atr():
            tr1 = high - low
            tr2 = (high - close.shift(1)).abs()
            tr3 = (low - close.shift(1)).abs()
            tr = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
            atr = pta.rma(tr, length=self.orderAtrLen)
            return atr
        
        self.atr = self.I(calc_atr)
        
        # Liquidity calculation
        def calc_dollar_vol():
            dollar_vol = close * volume
            avg_dol_vol = pta.sma(dollar_vol, length=self.liquidityLen)
            return avg_dol_vol
        
        self.avg_dollar_vol = self.I(calc_dollar_vol)
        
        # Leadership score tracker
        self.leadership_score = None

    def next(self):
        if len(self.data) < max(self.rsSlowLen, self.trendSlowLen, self.rangeLookback, 
                                self.orderStdevLen, self.orderAtrLen, self.liquidityLen):
            return
        
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        
        # Check Relative Leadership
        rs_fast_val = self.rs_fast[-1]
        rs_slow_val = self.rs_slow[-1]
        rs_slow_past = self.rs_slow[-1 - self.rsSlopeLookback] if len(self.rs_slow) > self.rsSlopeLookback else self.rs_slow[-1]
        req_rs = rs_fast_val > rs_slow_val and rs_slow_val > rs_slow_past
        
        # Check Absolute Trend
        trend_fast_val = self.trend_fast[-1]
        trend_slow_val = self.trend_slow[-1]
        trend_slow_past = self.trend_slow[-1 - self.trendSlopeLookback] if len(self.trend_slow) > self.trendSlopeLookback else self.trend_slow[-1]
        req_trend = trend_fast_val > trend_slow_val and close_val > trend_slow_val and trend_slow_val > trend_slow_past
        
        # Check Range Position
        range_high_val = self.range_high[-1]
        range_low_val = self.range_low[-1]
        
        if range_high_val > range_low_val:
            range_pos = (close_val - range_low_val) / (range_high_val - range_low_val)
        else:
            range_pos = 0.5
        
        if range_high_val > 0:
            pct_from_high = (range_high_val - close_val) / range_high_val * 100.0
        else:
            pct_from_high = 0.0
        
        req_position = range_pos >= self.minRangePosition and pct_from_high <= self.maxPctFromHigh
        
        # Check Orderliness
        stdev_val = self.close_stdev[-1]
        atr_val = self.atr[-1]
        
        if atr_val > 0:
            orderliness = stdev_val / atr_val
        else:
            orderliness = 0.0
        
        req_orderly = orderliness <= self.maxOrderliness
        
        # Check Liquidity
        avg_dol_vol = self.avg_dollar_vol[-1]
        min_dollar_volume = self.minDollarVolumeM * 1000000.0
        req_liquidity = avg_dol_vol >= min_dollar_volume
        
        # Calculate composite score
        score = sum([req_rs, req_trend, req_position, req_orderly, req_liquidity])
        leadership_conditions_met = score >= 4
        
        # Simple trading rules based on leadership conditions
        if leadership_conditions_met and not self.position:
            self.buy()
        elif not leadership_conditions_met and self.position:
            self.sell()


