        self.sma10 = self.I(pta.sma, close, length=10)
        self.sma20 = self.I(pta.sma, close, length=20)
        self.sma30 = self.I(pta.sma, close, length=30)
        self.sma50 = self.I(pta.sma, close, length=50)
        self.sma100 = self.I(pta.sma, close, length=100)
        self.sma200 = self.I(pta.sma, close, length=200)
        
        # VWMA
        self.vwma = self.I(pta.vwma, close, volume, length=20)
        
        # Hull MA: WMA(2*WMA(close, 5) - WMA(close, 10), 3)
        wma_half = self.I(pta.wma, close, length=5)
        wma_full = self.I(pta.wma, close, length=10)
        self.hullma = self.I(lambda: pta.wma(2 * wma_half - wma_full, length=3) if wma_half is not None and wma_full is not None else pd.Series(0, index=close.index))
        
        # Ichimoku
        self.conversion_line = self.I(lambda: (high.rolling(9).max() + low.rolling(9).min()) / 2)
        self.base_line = self.I(lambda: (high.rolling(26).max() + low.rolling(26).min()) / 2)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # Stochastic
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=14, d=3, smooth_k=3))
        self.k = self.I(lambda: stoch_result[f'STOCHk_14_3_3'] if stoch_result is not None and f'STOCHk_14_3_3' in stoch_result.columns else pd.Series(50, index=close.index))
        self.d = self.I(lambda: stoch_result[f'STOCHd_14_3_3'] if stoch_result is not None and f'STOCHd_14_3_3' in stoch_result.columns else pd.Series(50, index=close.index))
        
        # StochRSI
        stoch_rsi_result = self.I(lambda: pta.stoch(self.rsi, self.rsi, self.rsi, k=14, d=3, smooth_k=3))
        self.stoch_rsi = self.I(lambda: stoch_rsi_result[f'STOCHk_14_3_3'] / 100 if stoch_rsi_result is not None and f'STOCHk_14_3_3' in stoch_rsi_result.columns else pd.Series(0.5, index=close.index))
        
        # MACD
        ema12 = self.I(pta.ema, close, length=12)
        ema26 = self.I(pta.ema, close, length=26)
        self.macd = self.I(lambda: ema12 - ema26)
        self.signal = self.I(pta.ema, self.macd, length=9)
        
        # ADX components
        self.plus_di = self.I(lambda: pta.adx(high, low, close, length=14)[f'DMP_14'] if pta.adx(high, low, close, length=14) is not None else pd.Series(20, index=close.index))
        self.minus_di = self.I(lambda: pta.adx(high, low, close, length=14)[f'DMN_14'] if pta.adx(high, low, close, length=14) is not None else pd.Series(20, index=close.index))
        self.adx = self.I(lambda: pta.adx(high, low, close, length=14)[f'ADX_14'] if pta.adx(high, low, close, length=14) is not None else pd.Series(20, index=close.index))
        
        # CCI
        self.cci = self.I(pta.cci, high, low, close, length=20)
        
        # Awesome Oscillator
        hl2 = (high + low) / 2
        ao_sma5 = self.I(pta.sma, hl2, length=5)
        ao_sma34 = self.I(pta.sma, hl2, length=34)
        self.ao = self.I(lambda: ao_sma5 - ao_sma34)
        
        # Momentum
        self.mom = self.I(pta.mom, close, length=10)
        
        # Williams %R
        self.wr = self.I(lambda: -100 * (high.rolling(14).max() - close) / (high.rolling(14).max() - low.rolling(14).min()))
        
        # Bull Power and Bear Power
        ema13 = self.I(pta.ema, close, length=13)
        self.bull_power = self.I(lambda: high - ema13)
        self.bear_power = self.I(lambda: low - ema13)
        
        # Ultimate Oscillator
        def calc_ult_osc():
            bp = close - np.minimum(low, close.shift(1))
            tr = np.maximum(high, close.shift(1)) - np.minimum(low, close.shift(1))
            avg7 = bp.rolling(7).mean() / tr.rolling(7).mean()
            avg14 = bp.rolling(14).mean() / tr.rolling(14).mean()
            avg28 = bp.rolling(28).mean() / tr.rolling(28).mean()
            return 100 * (4 * avg7 + 2 * avg14 + avg28) / 7
        
        self.ult_osc = self.I(calc_ult_osc)
        
        self.in_position = False

