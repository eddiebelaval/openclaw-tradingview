import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fast_len = 12
    slow_len = 26
    sig_len = 9
    reg_len = 20
    proj_bars = 5
    scale_mult = 500.0
    quad_damp = 0.6

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Volume-weighted MACD
        fast_vwma = self.I(pta.vwma, close, volume, length=self.fast_len)
        slow_vwma = self.I(pta.vwma, close, volume, length=self.slow_len)
        vmacd_raw = fast_vwma - slow_vwma
        signal_raw = self.I(pta.ema, vmacd_raw, length=self.sig_len)
        
        # Scaled for visibility
        self.vmacd = self.I(lambda: vmacd_raw * self.scale_mult)
        self.signal = self.I(lambda: signal_raw * self.scale_mult)
        
        # Linear regression for slope calculation
        self.linreg_v = self.I(pta.linreg, self.vmacd, length=self.reg_len)
        self.linreg_s = self.I(pta.linreg, self.signal, length=self.reg_len)
        
        # Standard deviation and correlation for slope
        self.stdev_v = self.I(pta.stdev, self.vmacd, length=self.reg_len)
        self.stdev_s = self.I(pta.stdev, self.signal, length=self.reg_len)
        
        # Create bar_index series for correlation
        bar_indices = pd.Series(np.arange(len(close)), index=close.index)
        self.stdev_x = self.I(pta.stdev, bar_indices, length=self.reg_len)
        self.corr_v = self.I(pta.correlation, bar_indices, self.vmacd, length=self.reg_len)
        self.corr_s = self.I(pta.correlation, bar_indices, self.signal, length=self.reg_len)

    def next(self):
        # Calculate slopes
        if len(self.data) < self.reg_len:
            return
        
        stdev_x = self.stdev_x[-1] if not np.isnan(self.stdev_x[-1]) else 1e-10
        slope_v = self.corr_v[-1] * (self.stdev_v[-1] / stdev_x) if stdev_x != 0 else 0.0
        slope_s = self.corr_s[-1] * (self.stdev_s[-1] / stdev_x) if stdev_x != 0 else 0.0
        
        # Curvature estimate
        curv_v = (self.vmacd[-1] - self.linreg_v[-1]) * self.quad_damp * 2 / self.reg_len
        curv_s = (self.signal[-1] - self.linreg_s[-1]) * self.quad_damp * 2 / self.reg_len
        
        # Quadratic projection
        future_v = self.vmacd[-1] + slope_v * self.proj_bars + curv_v * self.proj_bars * self.proj_bars
        future_s = self.signal[-1] + slope_s * self.proj_bars + curv_s * self.proj_bars * self.proj_bars
        
        # Trading logic based on VMACD and Signal line
        if len(self.data) < 2:
            return
        
        # Buy when VMACD crosses above Signal line and projection is positive
        if crossover(self.vmacd, self.signal):
            if future_v > self.vmacd[-1]:
                if not self.position:
                    self.buy()
        
        # Sell when VMACD crosses below Signal line or projection is negative
        elif crossover(self.signal, self.vmacd):
            if future_v < self.vmacd[-1]:
                if self.position:
                    self.position.close()


