import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthSqz = 20
    bbMult = 2.0
    kcMultLow = 2.0
    kcMultMid = 1.5
    kcMultHigh = 1.0
    lenWaveA = 55
    lenWaveB = 144
    lenWaveC = 233
    showWaveA = True
    showWaveB = True
    showWaveC = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        self.bbBasis = self.I(pta.sma, close, length=self.lengthSqz)
        self.bbDev = self.I(lambda: self.bbMult * close.rolling(self.lengthSqz).std())
        self.bbUpper = self.I(lambda: self.bbBasis + self.bbDev)
        self.bbLower = self.I(lambda: self.bbBasis - self.bbDev)
        
        # Keltner Channels
        self.kcBasis = self.I(pta.sma, close, length=self.lengthSqz)
        self.tr = self.I(pta.true_range, high, low, close)
        self.kcTR = self.I(lambda: self.tr.rolling(self.lengthSqz).mean())
        
        # Squeeze Momentum
        self.highest = self.I(lambda: high.rolling(self.lengthSqz).max())
        self.lowest = self.I(lambda: low.rolling(self.lengthSqz).min())
        self.avgHL = self.I(lambda: (self.highest + self.lowest) / 2)
        self.smaClose = self.I(pta.sma, close, length=self.lengthSqz)
        self.momVal = self.I(lambda: pta.linreg(close - (self.avgHL + self.smaClose) / 2, length=self.lengthSqz) or pd.Series(0, index=close.index))
        
        # ABC Waves
        if self.showWaveA:
            self.waveA = self.I(self._calcWave, close, self.lenWaveA)
        else:
            self.waveA = self.I(lambda: pd.Series(0, index=close.index))
            
        if self.showWaveB:
            self.waveB = self.I(self._calcWave, close, self.lenWaveB)
        else:
            self.waveB = self.I(lambda: pd.Series(0, index=close.index))
            
        if self.showWaveC:
            self.waveC = self.I(self._calcWave, close, self.lenWaveC)
        else:
            self.waveC = self.I(lambda: pd.Series(0, index=close.index))

    def _calcWave(self, close, length):
        fastMA = pta.ema(close, length=8)
        slowMA = pta.ema(close, length=length)
        macd = fastMA - slowMA
        signal = pta.ema(macd, length=length)
        result = macd - signal
        return result if result is not None else pd.Series(0, index=close.index)

    def next(self):
        if len(self.data) < self.lengthSqz + 1:
            return
        
        # Squeeze compression states
        isHighSqz = (self.bbUpper[-1] <= self.kcBasis[-1] + self.kcTR[-1] * self.kcMultHigh) and \
                    (self.bbLower[-1] >= self.kcBasis[-1] - self.kcTR[-1] * self.kcMultHigh)
        isMidSqz = (self.bbUpper[-1] <= self.kcBasis[-1] + self.kcTR[-1] * self.kcMultMid) and \
                   (self.bbLower[-1] >= self.kcBasis[-1] - self.kcTR[-1] * self.kcMultMid)
        isLowSqz = (self.bbUpper[-1] <= self.kcBasis[-1] + self.kcTR[-1] * self.kcMultLow) and \
                   (self.bbLower[-1] >= self.kcBasis[-1] - self.kcTR[-1] * self.kcMultLow)
        
        isLowSqz_prev = False
        if len(self.data) >= self.lengthSqz + 2:
            isHighSqz_prev = (self.bbUpper[-2] <= self.kcBasis[-2] + self.kcTR[-2] * self.kcMultHigh) and \
                             (self.bbLower[-2] >= self.kcBasis[-2] - self.kcTR[-2] * self.kcMultHigh)
            isMidSqz_prev = (self.bbUpper[-2] <= self.kcBasis[-2] + self.kcTR[-2] * self.kcMultMid) and \
                            (self.bbLower[-2] >= self.kcBasis[-2] - self.kcTR[-2] * self.kcMultMid)
            isLowSqz_prev = (self.bbUpper[-2] <= self.kcBasis[-2] + self.kcTR[-2] * self.kcMultLow) and \
                            (self.bbLower[-2] >= self.kcBasis[-2] - self.kcTR[-2] * self.kcMultLow)
        
        # Squeeze fire conditions
        bullishSqzFire = not isLowSqz and isLowSqz_prev and \
                         self.momVal[-1] > 0 and self.momVal[-1] > self.momVal[-2]
        bearishSqzFire = not isLowSqz and isLowSqz_prev and \
                         self.momVal[-1] < 0 and self.momVal[-1] < self.momVal[-2]
        
        # ABC alignment
        bullishABC = (not self.showWaveA or self.waveA[-1] > 0) and \
                     (not self.showWaveB or self.waveB[-1] > 0)
        bearishABC = (not self.showWaveA or self.waveA[-1] < 0) and \
                     (not self.showWaveB or self.waveB[-1] < 0)
        
        # Entry signals
        longEntry = bullishSqzFire and bullishABC
        shortEntry = bearishSqzFire and bearishABC
        
        # Exit signals
        longExit = self.momVal[-1] > 0 and self.momVal[-1] < self.momVal[-2]
        shortExit = self.momVal[-1] < 0 and self.momVal[-1] > self.momVal[-2]
        
        # Execute trades
        if self.position:
            if self.position.is_long and longExit:
                self.position.close()
            elif self.position.is_short and shortExit:
                self.position.close()
        else:
            if longEntry:
                self.buy()
            elif shortEntry:
                self.sell()


