import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adxLen = 14
    diLen = 14
    adxThreshold = 25
    atrLen = 14
    volLookback = 100

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ADX and DI calculation
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.diLen, mamode='ema'))
        
        # ATR calculation
        atr_result = self.I(lambda: pta.atr(high, low, close, length=self.atrLen))
        
        # Average ATR (SMA of ATR)
        self.avgAtr = self.I(lambda: pta.sma(pta.atr(high, low, close, length=self.atrLen), length=self.volLookback) or pd.Series(0, index=close.index))
        
        self.adx = adx_result
        self.atr = atr_result
        
        # Extract DI+ and DI- from ADX result
        self.diplus = self.I(lambda: adx_result['DMP_14'] if isinstance(adx_result, pd.DataFrame) and 'DMP_14' in adx_result.columns else pd.Series(0, index=close.index))
        self.diminus = self.I(lambda: adx_result['DMN_14'] if isinstance(adx_result, pd.DataFrame) and 'DMN_14' in adx_result.columns else pd.Series(0, index=close.index))

    def next(self):
        # Get current values
        if len(self.data) < max(self.adxLen, self.atrLen, self.volLookback):
            return
        
        current_adx = self.adx[-1] if self.adx[-1] is not None else 0
        current_atr = self.atr[-1] if self.atr[-1] is not None else 0
        current_avgAtr = self.avgAtr[-1] if self.avgAtr[-1] is not None else 0
        current_diplus = self.diplus[-1] if self.diplus[-1] is not None else 0
        current_diminus = self.diminus[-1] if self.diminus[-1] is not None else 0
        
        # Determine regime conditions
        isTrending = current_adx > self.adxThreshold
        isHighVol = current_atr > current_avgAtr
        isBullish = current_diplus > current_diminus
        
        # Regime determination
        if isTrending and isHighVol:
            # EXPLOSION - Trending with High Volatility
            if isBullish and not self.position:
                self.buy()
            elif not isBullish and self.position:
                self.sell()
        
        elif isTrending and not isHighVol:
            # SLOW - Trending with Low Volatility
            if isBullish and not self.position:
                self.buy()
            elif not isBullish and self.position:
                self.sell()
        
        elif not isTrending and isHighVol:
            # CHOPPY - No Trend with High Volatility
            # Exit positions in choppy markets
            if self.position:
                self.sell()
        
        else:
            # SLEEPING - No Trend with Low Volatility
            # Reduce position activity
            if self.position:
                self.sell()


