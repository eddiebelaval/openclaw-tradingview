import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    period = 20
    vol_type = "High-Low"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        if self.vol_type == "High-Low":
            volatility = high - low
        else:
            atr_result = pta.atr(high, low, close, length=1)
            volatility = atr_result if atr_result is not None else (high - low)
        
        self.avg_vol = self.I(
            lambda: pta.sma(volatility, length=self.period) 
            if pta.sma(volatility, length=self.period) is not None 
            else pd.Series(0, index=volatility.index)
        )
        
        self.entry_price_upper = self.I(
            lambda: pd.Series(self.data.Open) + self.avg_vol
        )
        self.entry_price_lower = self.I(
            lambda: pd.Series(self.data.Open) - self.avg_vol
        )

    def next(self):
        if len(self.data) < self.period + 1:
            return
        
        avg_vol_val = self.avg_vol[-1] if not np.isnan(self.avg_vol[-1]) else 0
        
        if avg_vol_val <= 0:
            return
        
        upper_band = self.entry_price_upper[-1]
        lower_band = self.entry_price_lower[-1]
        current_price = self.data.Close[-1]
        
        if not self.position:
            if current_price >= upper_band and len(self.data) > 1:
                if self.data.Close[-2] < upper_band:
                    self.buy()
            elif current_price <= lower_band and len(self.data) > 1:
                if self.data.Close[-2] > lower_band:
                    self.buy()
        else:
            if self.position.is_long:
                if current_price <= self.entry_price_lower[-1]:
                    self.position.close()
                elif current_price >= self.entry_price_upper[-1] * 1.5:
                    self.position.close()


