import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    bbwp_length = 13
    bbwp_lookback = 252
    atr_period = 14
    atr_lookback = 100
    expansion_threshold = 70.0
    contraction_threshold = 30.0
    extreme_threshold = 85.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate BBWP (Bollinger Band Width Percentile)
        def calc_bbwp():
            basis = pta.sma(close, length=self.bbwp_length)
            dev = close.rolling(window=self.bbwp_length).std()
            bb_width = (dev * 2) / basis * 100
            
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(bb_width)):
                if i < self.bbwp_lookback:
                    result.iloc[i] = 0
                else:
                    lookback_slice = bb_width.iloc[i-self.bbwp_lookback:i]
                    count = (lookback_slice > bb_width.iloc[i]).sum()
                    result.iloc[i] = (count / self.bbwp_lookback) * 100
            return result
        
        self.bbwp = self.I(calc_bbwp)
        
        # Calculate ATR Percentile
        def calc_atr_percentile():
            atr_val = pta.atr(high, low, close, length=self.atr_period)
            natr = np.where(close > 0, (atr_val / close) * 100, 0)
            natr_series = pd.Series(natr, index=close.index)
            
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(natr_series)):
                if i < self.atr_lookback:
                    result.iloc[i] = 0
                else:
                    lookback_slice = natr_series.iloc[i-self.atr_lookback:i]
                    count = (lookback_slice > natr_series.iloc[i]).sum()
                    result.iloc[i] = (count / self.atr_lookback) * 100
            return result
        
        self.atr_percentile = self.I(calc_atr_percentile)
        
        # Combined Volatility Score
        def calc_combined_score():
            return self.bbwp * 0.6 + self.atr_percentile * 0.4
        
        self.combined_score = self.I(calc_combined_score)
        
        # Regime Classification
        def calc_regime():
            regime_codes = pd.Series(index=close.index, dtype=int)
            for i in range(len(self.combined_score)):
                score = self.combined_score[i]
                atr_perc = self.atr_percentile[i]
                
