import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    bb_len = 20
    kc_len = 20
    kc_mult = 1.5
    min_sqz_bars = 4
    proj_mult = 1.0
    max_watch_bars = 20
    enable_tm = True
    cooldown_len = 5
    max_bars_in_trade = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        self.bb_basis = self.I(pta.sma, close, length=self.bb_len)
        self.bb_dev = self.I(lambda: pta.stdev(close, self.bb_len) * 2.0)
        self.bb_up = self.I(lambda: self.bb_basis + self.bb_dev)
        self.bb_dn = self.I(lambda: self.bb_basis - self.bb_dev)
        
        # Keltner Channels
        self.atr_val = self.I(pta.atr, high, low, close, length=self.kc_len)
        self.kc_range = self.I(lambda: self.atr_val * self.kc_mult)
        self.kc_up = self.I(lambda: self.bb_basis + self.kc_range)
        self.kc_dn = self.I(lambda: self.bb_basis - self.kc_range)
        
        # Squeeze detection
        self.squeeze_on = self.I(self._squeeze_check)
        
        # State machine variables
        self.state = 0  # 0=SCANNING, 1=BUILDING, 2=WATCHING, 3=TRADING
        self.sqz_start = None
        self.sqz_hi = None
        self.sqz_lo = None
        self.sqz_len = 0
        self.sqz_end_bar = None
        
        self.trade_dir = 0  # 0=flat, 1=long, -1=short
        self.entry_price = None
        self.tp_level = None
        self.sl_level = None
        self.entry_bar = None
        self.exit_bar = -999
        self.last_trade_dir = 0
        
    def _squeeze_check(self):
        if len(self.data) < max(self.bb_len, self.kc_len):
            return pd.Series(False, index=self.data.Close.index)
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        bb_basis = pta.sma(close, length=self.bb_len)
        bb_dev = pta.stdev(close, self.bb_len) * 2.0
        bb_up = bb_basis + bb_dev
        bb_dn = bb_basis - bb_dev
        
        atr_val = pta.atr(high, low, close, length=self.kc_len)
        kc_range = atr_val * self.kc_mult
        kc_up = bb_basis + kc_range
        kc_dn = bb_basis - kc_range
        
        squeeze = (bb_dn > kc_dn) & (bb_up < kc_up)
        return squeeze
    
    def next(self):
        if len(self.data) < max(self.bb_len, self.kc_len):
            return
        
        squeeze_now = self.squeeze_on[-1]
        high_now = self.data.High[-1]
        low_now = self.data.Low[-1]
        close_now = self.data.Close[-1]
        bar_idx = len(self.data) - 1
        
        bb_up_now = self.bb_up[-1]
        bb_dn_now = self.bb_dn[-1]
        
        # STATE MACHINE
        if self.state == 0:  # SCANNING
            if squeeze_now:
                self.state = 1
                self.sqz_start = bar_idx
                self.sqz_hi = high_now
                self.sqz_lo = low_now
                self.sqz_len = 1
        
        elif self.state == 1:  # BUILDING
            if squeeze_now:
                self.sqz_hi = max(self.sqz_hi, high_now)
                self.sqz_lo = min(self.sqz_lo, low_now)
                self.sqz_len += 1
            else:
                # Squeeze ended
                if self.sqz_len >= self.min_sqz_bars:
                    self.sqz_end_bar = bar_idx
                    cool_ok = (bar_idx - self.exit_bar) >= self.cooldown_len
                    
