import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookbackBars = 20
    evalBars = 6
    minBreakPct = 0.05
    retestTolerancePc = 0.10
    atrLen = 14
    strictTrapCloses = 2
    strongAcceptThresh = 80
    moderateAcceptThresh = 60

    def init(self):
        self.atr = self.I(lambda: pta.atr(
            pd.Series(self.data.High),
            pd.Series(self.data.Low),
            pd.Series(self.data.Close),
            length=self.atrLen
        ))

        self.priorHigh = self.I(lambda: pd.Series(self.data.High).shift(1).rolling(self.lookbackBars).max())
        self.priorLow = self.I(lambda: pd.Series(self.data.Low).shift(1).rolling(self.lookbackBars).min())

        self.activeBull = False
        self.activeBear = False
        self.breakoutLevel = np.nan
        self.breakoutBarIndex = -1
        self.breakoutAtr = np.nan
        self.breakoutCloseScore = np.nan

        self.holdBarsCount = 0
        self.followBarsCount = 0
        self.backInsideCount = 0
        self.wickPenaltyAcc = 0.0

        self.retestSeen = False
        self.retestSuccess = False
        self.retestFailure = False
        self.trapRisk = False

        self.liveScore = np.nan
        self.liveClass = "Idle"

        self.lastClose = np.nan
        self.lastHigh = np.nan
        self.lastLow = np.nan

    def clamp(self, val, minv, maxv):
        return max(minv, min(maxv, val))

    def classification(self, score):
        if score >= self.strongAcceptThresh:
            return "Strong Acceptance"
        elif score >= self.moderateAcceptThresh:
            return "Moderate Acceptance"
        elif score >= 40:
            return "Weak Breakout"
        else:
            return "Trap Risk"

    def closeStrengthBull(self, h, l, c):
        rng = max(h - l, 0.0001)
        return ((c - l) / rng) * 20.0

    def closeStrengthBear(self, h, l, c):
        rng = max(h - l, 0.0001)
        return ((h - c) / rng) * 20.0

    def oppWickBull(self, h, l, c):
        rng = max(h - l, 0.0001)
        return ((h - c) / rng)

    def oppWickBear(self, h, l, c):
        rng = max(h - l, 0.0001)
        return ((c - l) / rng)

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        if len(self.data) < self.lookbackBars + 1:
            self.lastClose = close
            self.lastHigh = high
            self.lastLow = low
            return

        priorHigh = self.priorHigh[-1]
        priorLow = self.priorLow[-1]
        atrNow = self.atr[-1]

        if pd.isna(priorHigh) or pd.isna(priorLow) or pd.isna(atrNow):
            self.lastClose = close
            self.lastHigh = high
            self.lastLow = low
            return

        bullBreak = close > priorHigh * (1.0 + self.minBreakPct / 100.0)
        bearBreak = close < priorLow * (1.0 - self.minBreakPct / 100.0)

        startBullBreakout = not self.activeBull and not self.activeBear and bullBreak
        startBearBreakout = not self.activeBull and not self.activeBear and bearBreak

        if startBullBreakout:
            self.activeBull = True
            self.activeBear = False
            self.breakoutLevel = priorHigh
            self.breakoutBarIndex = len(self.data) - 1
            self.breakoutAtr = atrNow
            self.breakoutCloseScore = self.clamp(self.closeStrengthBull(high, low, close), 0.0, 20.0)

            self.holdBarsCount = 1
            self.followBarsCount = 0
            self.backInsideCount = 0
            self.wickPenaltyAcc = 0.0

            self.retestSeen = False
            self.retestSuccess = False
            self.retestFailure = False
            self.trapRisk = False

            self.liveScore = self.breakoutCloseScore
            self.liveClass = self.classification(self.liveScore)

            if not self.position:
                self.buy()

        elif startBearBreakout:
            self.activeBear = True
            self.activeBull = False
            self.breakoutLevel = priorLow
            self.breakoutBarIndex = len(self.data) - 1
            self.breakoutAtr = atrNow
            self.breakoutCloseScore = self.clamp(self.closeStrengthBear(high, low, close), 0.0, 20.0)

            self.holdBarsCount = 1
            self.followBarsCount = 0
            self.backInsideCount = 0
            self.wickPenaltyAcc = 0.0

            self.retestSeen = False
            self.retestSuccess = False
            self.retestFailure = False
            self.trapRisk = False

            self.liveScore = self.breakoutCloseScore
            self.liveClass = self.classification(self.liveScore)

            if self.position:
                self.sell()

        barsSinceBreakout = len(self.data) - 1 - self.breakoutBarIndex if self.breakoutBarIndex >= 0 else -1
        retestTolerance = self.breakoutLevel * (self.retestTolerancePc / 100.0) if not np.isnan(self.breakoutLevel) else 0

        if self.activeBull and barsSinceBreakout > 0:
            if close > self.breakoutLevel:
                self.holdBarsCount += 1

            if close > self.lastClose:
                self.followBarsCount += 1

            self.wickPenaltyAcc += self.oppWickBull(high, low, close) * 4.0

            nearRetest = low <= self.breakoutLevel + retestTolerance and low >= self.breakoutLevel - retestTolerance
            if nearRetest and not self.retestSeen:
                self.retestSeen = True
                if close > self.breakoutLevel:
                    self.retestSuccess = True

            if close <= self.breakoutLevel:
                self.backInsideCount += 1

            if close < self.breakoutLevel - retestTolerance:
                self.retestFailure = True

            self.trapRisk = self.retestFailure or self.backInsideCount >= self.strictTrapCloses

            holdScore = self.clamp((self.holdBarsCount / self.evalBars) * 20.0, 0.0, 20.0)
            followScore = self.clamp((self.followBarsCount / self.evalBars) * 20.0, 0.0, 20.0)
            retestScore = 20.0 if self.retestSuccess else (10.0 if self.retestSeen else 0.0)
            penaltyScore = self.clamp((self.backInsideCount * 6.0) + self.wickPenaltyAcc, 0.0, 20.0)

            self.liveScore = self.clamp(self.breakoutCloseScore + holdScore + followScore + retestScore + (20.0 - penaltyScore), 0.0, 100.0)
            self.liveClass = "Trap Risk" if self.trapRisk else self.classification(self.liveScore)

            if barsSinceBreakout >= self.evalBars or self.trapRisk:
                self.activeBull = False
                if self.liveScore >= self.strongAcceptThresh and not self.trapRisk:
                    pass
                elif self.trapRisk and self.position:
                    self.sell()

        elif self.activeBear and barsSinceBreakout > 0:
            if close < self.breakoutLevel:
                self.holdBarsCount += 1

            if close < self.lastClose:
                self.followBarsCount += 1

            self.wickPenaltyAcc += self.oppWickBear(high, low, close) * 4.0

            nearRetest = high >= self.breakoutLevel - retestTolerance and high <= self.breakoutLevel + retestTolerance
            if nearRetest and not self.retestSeen:
                self.retestSeen = True
                if close < self.breakoutLevel:
                    self.retestSuccess = True

            if close >= self.breakoutLevel:
                self.backInsideCount += 1

            if close > self.breakoutLevel + retestTolerance:
                self.retestFailure = True

            self.trapRisk = self.retestFailure or self.backInsideCount >= self.strictTrapCloses

            holdScore = self.clamp((self.holdBarsCount / self.evalBars) * 20.0, 0.0, 20.0)
            followScore = self.clamp((self.followBarsCount / self.evalBars) * 20.0, 0.0, 20.0)
            retestScore = 20.0 if self.retestSuccess else (10.0 if self.retestSeen else 0.0)
            penaltyScore = self.clamp((self.backInsideCount * 6.0) + self.wickPenaltyAcc, 0.0, 20.0)

            self.liveScore = self.clamp(self.breakoutCloseScore + holdScore + followScore + retestScore + (20.0 - penaltyScore), 0.0, 100.0)
            self.liveClass = "Trap Risk" if self.trapRisk else self.classification(self.liveScore)

            if barsSinceBreakout >= self.evalBars or self.trapRisk:
                self.activeBear = False
                if self.liveScore >= self.strongAcceptThresh and not self.trapRisk:
                    pass
                elif self.trapRisk and not self.position:
                    self.buy()

        self.lastClose = close
        self.lastHigh = high
        self.lastLow = low


