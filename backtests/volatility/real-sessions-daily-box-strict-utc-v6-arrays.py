import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    """
    Real Sessions + Daily Box strategy converted from Pine Script.
    This is a visualization/analysis indicator that draws session boxes and daily ranges.
    Since it's not a trading strategy, we create a simple trading rule based on daily range breakouts.
    """
    
    def init(self):
        # Track daily highs and lows
        self.daily_high = self.I(self._get_daily_high)
        self.daily_low = self.I(self._get_daily_low)
        self.daily_open = self.I(self._get_daily_open)
        
    def _get_daily_high(self):
        """Calculate daily high using rolling max of highs for each day"""
        close_series = pd.Series(self.data.Close)
        high_series = pd.Series(self.data.High)
        
        # Group by day and get max of highs
        df = pd.DataFrame({
            'High': high_series,
            'Date': pd.to_datetime(self.data.index, unit='s', utc=True).date
        })
        daily_max = df.groupby('Date')['High'].transform('max')
        return daily_max.values
    
    def _get_daily_low(self):
        """Calculate daily low using rolling min of lows for each day"""
        low_series = pd.Series(self.data.Low)
        
        # Group by day and get min of lows
        df = pd.DataFrame({
            'Low': low_series,
            'Date': pd.to_datetime(self.data.index, unit='s', utc=True).date
        })
        daily_min = df.groupby('Date')['Low'].transform('min')
        return daily_min.values
    
    def _get_daily_open(self):
        """Get daily opening price"""
        close_series = pd.Series(self.data.Close)
        open_series = pd.Series(self.data.Open)
        
        # Group by day and get first open
        df = pd.DataFrame({
            'Open': open_series,
            'Date': pd.to_datetime(self.data.index, unit='s', utc=True).date
        })
        daily_opens = df.groupby('Date')['Open'].transform('first')
        return daily_opens.values
    
    def next(self):
        """
        Simple trading logic based on daily range:
        - Buy when price breaks above daily high
        - Sell when price breaks below daily low
        """
        
        if len(self.data) < 2:
            return
        
        current_high = self.daily_high[-1]
        current_low = self.daily_low[-1]
        prev_high = self.daily_high[-2]
        prev_low = self.daily_low[-2]
        
        close = self.data.Close[-1]
        prev_close = self.data.Close[-2]
        
        # Buy on breakout above daily high
        if prev_close <= prev_high and close > current_high and not self.position:
            self.buy()
        
        # Sell on breakout below daily low
        elif prev_close >= prev_low and close < current_low and self.position:
            self.position.close()


