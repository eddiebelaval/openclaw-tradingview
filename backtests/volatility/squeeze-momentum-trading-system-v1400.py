        # Extract BB components
        def get_bb_upper():
            result = pta.bbands(close, length=self.bb_len, std=self.bb_mult)
            if result is not None and 'BBU_' + str(self.bb_len) + '_' + str(self.bb_mult) in result.columns:
                return result['BBU_' + str(self.bb_len) + '_' + str(self.bb_mult)]
            return pd.Series(0, index=close.index)
        
        def get_bb_lower():
            result = pta.bbands(close, length=self.bb_len, std=self.bb_mult)
            if result is not None and 'BBL_' + str(self.bb_len) + '_' + str(self.bb_mult) in result.columns:
                return result['BBL_' + str(self.bb_len) + '_' + str(self.bb_mult)]
            return pd.Series(0, index=close.index)

        self.bb_upper = self.I(get_bb_upper)
        self.bb_lower = self.I(get_bb_lower)

        # Calculate bandwidth and percentrank
        def calc_bw():
            bb = pta.bbands(close, length=self.bb_len, std=self.bb_mult)
            if bb is not None:
                bb_up_col = 'BBU_' + str(self.bb_len) + '_' + str(self.bb_mult)
                bb_lo_col = 'BBL_' + str(self.bb_len) + '_' + str(self.bb_mult)
                bb_mid_col = 'BBM_' + str(self.bb_len) + '_' + str(self.bb_mult)
                if bb_up_col in bb.columns and bb_lo_col in bb.columns and bb_mid_col in bb.columns:
                    bw = (bb[bb_up_col] - bb[bb_lo_col]) / bb[bb_mid_col]
                    return bw
            return pd.Series(0, index=close.index)
        
