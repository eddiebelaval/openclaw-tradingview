import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLen = 14
    hhvLen = 10
    mult = 2.5
    warmup = 15

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Calculate raw stop: high - mult * atr
        raw_stop = self.I(lambda: high - self.mult * atr)
        
        # Calculate highest of raw_stop over hhvLen bars
        ts_core = self.I(lambda: raw_stop.rolling(window=self.hhvLen).max())
        
        # Apply warmup period: use close during warmup, ts_core after
        self.ts = self.I(
            lambda: ts_core.where(
                np.arange(len(close)) >= self.warmup,
                close
            )
        )
        
        self.close = close
        
        # Track whether we're in long mode
        self.long_mode = self.I(lambda: self.close > self.ts)

    def next(self):
        # Buy when price crosses above the trailing stop (entering long mode)
        if len(self.data) > self.warmup and self.close[-1] > self.ts[-1] and (self.close[-2] <= self.ts[-2] if len(self.close) > 1 else False):
            if not self.position:
                self.buy()
        
        # Sell when price crosses below the trailing stop (stop hit)
        if self.position and crossover(self.ts, self.close):
            self.position.close()