import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 14
    er_len = 10
    bb_len = 20
    bb_mult = 2.0
    kc_len = 20
    kc_mult = 1.5
    vol_threshold = 50
    er_threshold = 40

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # 1. ATR and normalized volatility
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # ATR percentile (simplified: using rolling percentile)
        def calc_atr_percentile_high(atr_series):
            return atr_series.rolling(self.atr_len).quantile(0.8)
        
        def calc_atr_percentile_low(atr_series):
            return atr_series.rolling(self.atr_len).quantile(0.2)
        
        self.atr_p_high = self.I(calc_atr_percentile_high, self.atr_val)
        self.atr_p_low = self.I(calc_atr_percentile_low, self.atr_val)
        
        def calc_norm_vol(atr, high, low):
            atr_range = high - low
            result = pd.Series(index=atr.index, dtype=float)
            for i in range(len(atr)):
                if atr_range.iloc[i] > 0:
                    result.iloc[i] = np.clip((atr.iloc[i] - low.iloc[i]) / atr_range.iloc[i] * 100, 0, 100)
                else:
                    result.iloc[i] = 50
            return result
        
        self.norm_vol = self.I(calc_norm_vol, self.atr_val, self.atr_p_high, self.atr_p_low)

        # 2. Efficiency Ratio
        def calc_eff_ratio(close_series):
            result = pd.Series(index=close_series.index, dtype=float)
            for i in range(len(close_series)):
                if i < self.er_len:
                    result.iloc[i] = 0
                else:
                    er_direction = abs(close_series.iloc[i] - close_series.iloc[i - self.er_len])
                    er_path = sum(abs(close_series.iloc[i-j] - close_series.iloc[i-j-1]) for j in range(self.er_len))
                    result.iloc[i] = (er_direction / er_path * 100) if er_path != 0 else 0
            return result
        
        self.eff_ratio = self.I(calc_eff_ratio, close)

        # 3. Bollinger Bands
        bb = self.I(pta.bbands, close, length=self.bb_len, std=self.bb_mult)
        self.bb_upper = bb.iloc[:, 2]
        self.bb_lower = bb.iloc[:, 0]

        # 4. Keltner Channel
        kc_basis = self.I(pta.ema, close, length=self.kc_len)
        
        def calc_kc_bands(atr, basis, mult):
            kc_upper = basis + mult * atr
            kc_lower = basis - mult * atr
            return pd.DataFrame({'upper': kc_upper, 'lower': kc_lower})
        
        kc = self.I(calc_kc_bands, self.atr_val, kc_basis, self.kc_mult)
        self.kc_upper = kc['upper']
        self.kc_lower = kc['lower']

        # 5. Squeeze detection
        def calc_squeeze(bb_lower, bb_upper, kc_lower, kc_upper):
            squeeze = pd.Series(index=bb_lower.index, dtype=bool)
            for i in range(len(bb_lower)):
                squeeze.iloc[i] = (bb_lower.iloc[i] > kc_lower.iloc[i]) and (bb_upper.iloc[i] < kc_upper.iloc[i])
            return squeeze
        
        self.squeeze_on = self.I(calc_squeeze, self.bb_lower, self.bb_upper, self.kc_lower, self.kc_upper)

        # 6. Regime classification
        def calc_regime(norm_vol, eff_ratio, vol_thresh, er_thresh):
            regime = pd.Series(index=norm_vol.index, dtype=int)
            for i in range(len(norm_vol)):
                if norm_vol.iloc[i] <= vol_thresh and eff_ratio.iloc[i] >= er_thresh:
                    regime.iloc[i] = 1
                elif norm_vol.iloc[i] > vol_thresh and eff_ratio.iloc[i] >= er_thresh:
                    regime.iloc[i] = 2
                elif norm_vol.iloc[i] <= vol_thresh and eff_ratio.iloc[i] < er_thresh:
                    regime.iloc[i] = 3
                else:
                    regime.iloc[i] = 4
            return regime
        
        self.regime = self.I(calc_regime, self.norm_vol, self.eff_ratio, self.vol_threshold, self.er_threshold)

        # 7. Momentum direction
        def calc_momentum(close_series, atr):
            momentum = pd.Series(index=close_series.index, dtype=float)
            ema_diff = pta.ema(close_series.diff(), length=5)
            for i in range(len(momentum)):
                if pd.notna(ema_diff.iloc[i]) and atr.iloc[i] > 0:
                    momentum.iloc[i] = (ema_diff.iloc[i] / atr.iloc[i]) * 50 + 50
                else:
                    momentum.iloc[i] = 50
            return momentum
        
        self.momentum_val = self.I(calc_momentum, close, self.atr_val)

    def next(self):
        # Buy signal: transition to regime 1 (low vol trending - best)
        if len(self.regime) > 1:
            if self.regime[-1] == 1 and self.regime[-2] != 1:
                if not self.position:
                    self.buy()
        
        # Sell signal: transition to regime 4 (high vol ranging - worst)
        if len(self.regime) > 1:
            if self.regime[-1] == 4 and self.regime[-2] != 4:
                if self.position:
                    self.sell()
        
        # Additional sell on squeeze release with bearish momentum
        if len(self.squeeze_on) > 1:
            if self.squeeze_on[-2] and not self.squeeze_on[-1]:
                if self.momentum_val[-1] < 45 and self.position:
                    self.sell()
        
        # Exit on very bad conditions
        if self.position and self.regime[-1] == 4:
            self.sell()


