import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    af = 0.02
    af_limit = 0.2

    def init(self):
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        # Calculate Parabolic SAR
        self.psar = self.I(
            lambda: pta.psar(high, low, close, af=self.af, max_af=self.af_limit)['PSARl'].fillna(
                pta.psar(high, low, close, af=self.af, max_af=self.af_limit)['PSARs']
            )
        )

    def next(self):
        # Buy when price crosses above SAR
        if len(self.data) > 1:
            if self.data.Close[-2] <= self.psar[-2] and self.data.Close[-1] > self.psar[-1]:
                if not self.position:
                    self.buy()
            # Sell when price crosses below SAR
            elif self.data.Close[-2] >= self.psar[-2] and self.data.Close[-1] < self.psar[-1]:
                if self.position:
                    self.sell()