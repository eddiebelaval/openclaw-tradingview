import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    startYear = 2023
    startMonth = 6
    startDay = 16
    fastLen = 9
    useBarClose = True

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate Fast RSI
        fast_rsi = self.I(pta.rsi, close, length=self.fastLen)
        
        # Calculate Fast Wave (EMA of (RSI - 50))
        rsi_adjusted = fast_rsi - 50
        self.fastWave = self.I(pta.ema, rsi_adjusted, length=3)
        
        self.baseline = 0.0

    def next(self):
        # Date filter
        current_time = pd.Timestamp(self.data.index[-1])
        start_date = pd.Timestamp(year=self.startYear, month=self.startMonth, day=self.startDay)
        
        if current_time < start_date:
            return
        
        # Get current indicator values
        fastWave_current = self.fastWave[-1]
        
        # State conditions
        above_base = fastWave_current > self.baseline
        below_base = fastWave_current < self.baseline
        
        # Trading logic
        if above_base and self.position.size <= 0:
            self.buy()
        elif below_base and self.position.size >= 0:
            self.sell()


