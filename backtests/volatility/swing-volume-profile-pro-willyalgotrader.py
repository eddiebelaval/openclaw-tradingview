import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_len = 21
    bin_count = 20
    atr_period = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for swing size filtering
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # Detect swing highs and lows using rolling max/min
        self.swing_high = self.I(lambda: high.rolling(window=self.swing_len*2+1, center=True).max())
        self.swing_low = self.I(lambda: low.rolling(window=self.swing_len*2+1, center=True).min())
        
        # Track state
        self.in_long = False
        self.in_short = False
        self.last_swing_high = None
        self.last_swing_low = None
        self.swing_direction = None

    def next(self):
        if len(self.data) < self.swing_len * 2 + 50:
            return
        
        current_atr = self.atr[-1] if len(self.atr) > 0 and not np.isnan(self.atr[-1]) else 0.1
        if np.isnan(current_atr) or current_atr == 0:
            current_atr = 0.1
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        
        swing_hi = self.swing_high[-1] if len(self.swing_high) > 0 else None
        swing_lo = self.swing_low[-1] if len(self.swing_low) > 0 else None
        
        if swing_hi is None or np.isnan(swing_hi) or swing_lo is None or np.isnan(swing_lo):
            return
        
        swing_range = swing_hi - swing_lo
        
        # Detect swing reversals
        if swing_range > current_atr * 0.3:
            if current_close >= current_high * 0.99 and swing_direction != "up":
                # Potential swing low confirmation
                if not self.in_long and self.last_swing_low is not None:
                    if current_low < self.last_swing_low:
                        self.swing_direction = "up"
                        self.last_swing_low = current_low
                        if self.position and self.position.is_short:
                            self.position.close()
                        self.buy()
                        self.in_long = True
                        self.in_short = False
