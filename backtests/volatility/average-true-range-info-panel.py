import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Calculate True Range for last 5 candles manually
        def calc_tr():
            tr_values = []
            for i in range(len(self.data)):
                if i == 0:
                    tr_val = self.data.High[i] - self.data.Low[i]
                else:
                    tr_val = max(self.data.High[i], self.data.Close[i-1]) - min(self.data.Low[i], self.data.Close[i-1])
                tr_values.append(tr_val)
            return pd.Series(tr_values, index=close.index)
        
        self.tr = self.I(calc_tr)

    def next(self):
        # Use ATR for volatility-based trading signals
        if len(self) < self.atr_length + 5:
            return
        
        current_atr = self.atr[-1]
        prev_atr = self.atr[-2] if len(self.atr) > 1 else current_atr
        
        # Simple trading logic based on ATR expansion/contraction
        # Buy on ATR expansion (increasing volatility)
        if not self.position and current_atr > prev_atr * 1.1:
            self.buy()
        
        # Sell on ATR contraction (decreasing volatility)
        elif self.position and current_atr < prev_atr * 0.9:
            self.sell()


