import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_length = 14
    atr_multi = 0.5
    use_filter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
    def next(self):
        if len(self.data) < 3:
            return
        
        # Current values
        low_curr = self.data.Low[-1]
        high_curr = self.data.High[-1]
        close_prev = self.data.Close[-2]
        open_prev = self.data.Open[-2]
        high_2bars = self.data.High[-3]
        low_2bars = self.data.Low[-3]
        
        # ATR value
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        
        # Gap sizes
        gap_bull_size = low_curr - high_2bars
        gap_bear_size = low_2bars - high_curr
        
        # FVG conditions
        is_fvg_bull = low_curr > high_2bars and close_prev > open_prev
        is_fvg_bear = high_curr < low_2bars and close_prev < open_prev
        
        # Size filter
        filter_pass_bull = (gap_bull_size > atr_val * self.atr_multi) if self.use_filter else True
        filter_pass_bear = (gap_bear_size > atr_val * self.atr_multi) if self.use_filter else True
        
        # Valid FVG signals
        valid_bull = is_fvg_bull and filter_pass_bull
        valid_bear = is_fvg_bear and filter_pass_bear
        
        # Trading logic
        if valid_bull:
            if not self.position:
                self.buy()
        elif valid_bear:
            if self.position:
                self.sell()
        elif valid_bear and not self.position:
            self.position.close() if self.position else None


