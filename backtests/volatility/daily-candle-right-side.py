class TvStrategy(Strategy):
    offset = 10
    candleWidth = 4
    topLabelOffset = 2.0
    bottomLabelOffset = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.daily_close = self.I(lambda: close)
        self.daily_high = self.I(lambda: high)
        self.daily_low = self.I(lambda: low)

    def next(self):
        if len(self.data) < 2:
            return
        
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        daily_high = self.daily_high[-1]
        daily_low = self.daily_low[-1]
        daily_close = self.daily_close[-1]
        
        prev_close = self.data.Close[-2]
        
        if daily_close > current_open:
            if not self.position:
                self.buy()
        elif daily_close < current_open:
            if self.position:
                self.sell()
        elif daily_close == current_open:
            if daily_close > prev_close:
                if not self.position:
                    self.buy()
            elif daily_close < prev_close:
                if self.position:
                    self.sell()


