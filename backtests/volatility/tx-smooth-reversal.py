import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Input parameters from Pine Script
    useHA = False
    mode = "Normal"
    useMTF = True
    microTF = "5"
    opTF = "30"
    regTF = "240"
    alignTh = 0.55
    lenATR = 100
    smoothW = 10
    lenER = 20
    kamaFast = 2
    kamaSlow = 30
    widthBase = 1.00
    sigThresh = 75.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate KAMA (Kaufman Adaptive Moving Average)
        def kama_calc(src, lER, fL, sL):
            result = pd.Series(index=src.index, dtype=float)
            for i in range(len(src)):
                if i < lER:
                    result.iloc[i] = src.iloc[i]
                else:
                    change = abs(src.iloc[i] - src.iloc[i - lER])
                    vol = sum(abs(src.iloc[i - j] - src.iloc[i - j - 1]) for j in range(lER))
                    er = change / vol if vol != 0.0 else 0.0
                    sc = pow(er * (2.0 / (fL + 1) - 2.0 / (sL + 1)) + 2.0 / (sL + 1), 2.0)
                    if i == lER:
                        result.iloc[i] = src.iloc[i]
                    else:
                        result.iloc[i] = result.iloc[i - 1] + sc * (src.iloc[i] - result.iloc[i - 1])
            return result
        
        self.center = self.I(lambda: kama_calc(close, self.lenER, self.kamaFast, self.kamaSlow))
        
        # Calculate ATR using RMA
        def atr_calc(high, low, close, period):
            tr = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                h = high.iloc[i]
                l = low.iloc[i]
                cp = close.iloc[i - 1] if i > 0 else close.iloc[i]
                tr.iloc[i] = max(h - l, abs(h - cp), abs(l - cp))
            
            rma = pd.Series(index=close.index, dtype=float)
            alpha = 1.0 / period
            for i in range(len(tr)):
                if i == 0:
                    rma.iloc[i] = tr.iloc[i]
                else:
                    rma.iloc[i] = alpha * tr.iloc[i] + (1 - alpha) * rma.iloc[i - 1]
            return rma
        
        atr = self.I(lambda: atr_calc(high, low, close, self.lenATR))
        
        # Smooth ATR with RMA
        def rma_calc(src, period):
            result = pd.Series(index=src.index, dtype=float)
            alpha = 1.0 / period
            for i in range(len(src)):
                if i == 0:
                    result.iloc[i] = src.iloc[i]
                else:
                    result.iloc[i] = alpha * src.iloc[i] + (1 - alpha) * result.iloc[i - 1]
            return result
        
        width = self.I(lambda: rma_calc(atr, self.smoothW) * self.widthBase)
        
        self.upperOuter = self.I(lambda: self.center + (2.2 * width))
        self.upperInner = self.I(lambda: self.center + (1.2 * width))
        self.lowerInner = self.I(lambda: self.center - (1.2 * width))
        self.lowerOuter = self.I(lambda: self.center - (2.2 * width))
        
        # Calculate slope
        center_diff = self.I(lambda: self.center.diff())
        self.slope = self.I(lambda: pta.ema(center_diff, length=10) or pd.Series(0, index=close.index))
        
        # Calculate deviation
        self.dev = self.I(lambda: (close - self.center) / np.maximum(width, 1e-6))
        
        # Bull and Bear scores
        def bull_score(dev, src_l, lower_outer, src_c):
            score = np.clip((-dev - 1.0), 0, 1) * 50
            score += np.where(src_l < lower_outer, 30, 0)
            score += np.where(src_c.diff() > 0, 20, 0)
            return np.clip(score, 0, 100)
        
        def bear_score(dev, src_h, upper_outer, src_c):
            score = np.clip((dev - 1.0), 0, 1) * 50
            score += np.where(src_h > upper_outer, 30, 0)
            score += np.where(src_c.diff() < 0, 20, 0)
            return np.clip(score, 0, 100)
        
        self.P_rev_bull = self.I(lambda: pd.Series(bull_score(self.dev, low, self.lowerOuter, close)))
        self.P_rev_bear = self.I(lambda: pd.Series(bear_score(self.dev, high, self.upperOuter, close)))
        
        # MTF alignment (simplified for single timeframe backtest)
        self.alignBull = self.I(lambda: pd.Series(
            np.where(self.dev < -0.5, 0.3, 0) +
            np.where(self.slope > 0, 0.3, 0) +
            np.where(self.slope > 0, 0.4, 0)
        ))
        
        self.alignBear = self.I(lambda: pd.Series(
            np.where(self.dev > 0.5, 0.3, 0) +
            np.where(self.slope < 0, 0.3, 0) +
            np.where(self.slope < 0, 0.4, 0)
        ))

    def next(self):
        if len(self.data) < max(self.lenATR, self.lenER, 20):
            return
        
        # Get current values
        bull_prob = self.P_rev_bull[-1]
        bear_prob = self.P_rev_bear[-1]
        align_bull = self.alignBull[-1] if not self.useMTF else self.alignBull[-1]
        align_bear = self.alignBear[-1] if not self.useMTF else self.alignBear[-1]
        src_l = self.data.Low[-1]
        src_h = self.data.High[-1]
        src_c = self.data.Close[-1]
        lower_inner = self.lowerInner[-1]
        upper_inner = self.upperInner[-1]
        
        # MTF gate logic
        mtf_gate_bull = not self.useMTF or align_bull >= self.alignTh
        mtf_gate_bear = not self.useMTF or align_bear >= self.alignTh
        
        # Buy signal
        if (bull_prob >= self.sigThresh and 
            mtf_gate_bull and 
            src_l <= lower_inner and 
            src_c > self.data.Low[-1]):
            if not self.position:
                self.buy()
        
        # Sell signal
        if (bear_prob >= self.sigThresh and 
            mtf_gate_bear and 
            src_h >= upper_inner and 
            src_c < self.data.High[-1]):
            if self.position:
                self.sell()


