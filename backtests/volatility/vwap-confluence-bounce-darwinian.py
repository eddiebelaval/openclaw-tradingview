import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # VWAP Configuration
    anchor = "Decade"
    
    # Band Configuration
    calcMode = "Standard Deviation"
    showBand_1 = True
    bandMult_1 = 1.0
    showBand_2 = False
    bandMult_2 = 2.0
    showBand_3 = False
    bandMult_3 = 3.0
    
    # EMA & Band Detection
    emaLength = 50
    detectBandL3 = True
    detectBandL2 = True
    detectBandL1 = True
    detectBandVWAP = True
    detectBandU1 = False
    detectBandU2 = False
    detectBandU3 = False
    
    # Compression Filter
    useCompression = True
    volLength = 10
    useATR = False
    atrLength = 14
    
    # RSI Filter
    useRSI = True
    rsiLength = 14
    rsiSmaLength = 14
    
    # Directional Indicator Filter
    useDI = True
    diLength = 9
    
    # Candle Color Filter
    useCandleColor = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # EMA
        self.ema50 = self.I(pta.ema, close, length=self.emaLength)
        
        # Volume MA and compression
        self.volMA = self.I(pta.sma, volume, length=self.volLength)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        self.atrSMA = self.I(pta.sma, self.atr, length=self.atrLength)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        self.rsiSma = self.I(pta.sma, self.rsi, length=self.rsiSmaLength)
        
        # Directional Indicator
        self.up = self.I(lambda: high.diff().fillna(0))
        self.down = self.I(lambda: -low.diff().fillna(0))
        
        self.plusDM = self.I(lambda: (
            ((self.up[-1] > self.down[-1]) & (self.up[-1] > 0)).astype(float) * self.up[-1]
            if len(self) > 0 else 0
        ))
        
        self.minusDM = self.I(lambda: (
            ((self.down[-1] > self.up[-1]) & (self.down[-1] > 0)).astype(float) * self.down[-1]
            if len(self) > 0 else 0
        ))
        
        self.tr = self.I(lambda: pd.concat([
            high.diff(),
            (high - low),
            (high - close.shift()).abs()
        ], axis=1).max(axis=1))
        
        self.trur = self.I(lambda: self.tr.ewm(span=self.diLength).mean() if len(self) > self.diLength else self.tr)
        
        self.plusDI_series = self.I(lambda: (100 * (self.plusDM if isinstance(self.plusDM, pd.Series) else pd.Series(self.plusDM))) / (self.trur if self.trur > 0 else 1))
        self.minusDI_series = self.I(lambda: (100 * (self.minusDM if isinstance(self.minusDM, pd.Series) else pd.Series(self.minusDM))) / (self.trur if self.trur > 0 else 1))
        
        # VWAP calculation using hlc3 as source
        hlc3 = (high + low + close) / 3
        
        # Simple VWAP approximation using cumulative volume weighted price
        self.vwap = self.I(lambda: (hlc3 * volume).rolling(window=min(252, len(hlc3))).sum() / volume.rolling(window=min(252, len(volume))).sum())
        
        # Band calculation
        self.stdevAbs = self.I(lambda: (hlc3 - self.vwap[-1]).rolling(window=20).std() if len(self) > 20 else pd.Series(0.1, index=hlc3.index))
        
        self.bandBasis = self.I(lambda: 
            self.stdevAbs[-1] if self.calcMode == "Standard Deviation" 
            else self.vwap[-1] * 0.01 if len(self) > 0 and self.vwap[-1] > 0 
            else 0.01
        )
        
        # Candle color
        self.isGreen = self.I(lambda: close > open_)
        self.isRed = self.I(lambda: close < open_)

    def next(self):
        if len(self.data) < self.emaLength + 20:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        open_ = self.data.Open[-1]
        
        ema = self.ema50[-1]
        
        # Volume contraction
        volMA = self.volMA[-1]
        volContract = volume < volMA
        
        # ATR contraction
        atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        atrSMA = self.atrSMA[-1] if not np.isnan(self.atrSMA[-1]) else atr
        atrContract = atr < atrSMA
        
        compression = (volContract and atrContract) if self.useATR else volContract
        
        # RSI filter
        rsi = self.rsi[-1] if not np.isnan(self.rsi[-1]) else 50
        rsiSma = self.rsiSma[-1] if not np.isnan(self.rsiSma[-1]) else 50
        rsiAboveSma = rsi > rsiSma
        
        # Directional Indicator
        try:
            plusDI = self.plusDI_series[-1] if not np.isnan(self.plusDI_series[-1]) else 20
            minusDI = self.minusDI_series[-1] if not np.isnan(self.minusDI_series[-1]) else 20
        except:
            plusDI = 20
            minusDI = 20
        
        diConditionAbove = plusDI > minusDI
        diConditionBelow = minusDI > plusDI
        
        # Candle color
        isGreenCandle = close > open_
        isRedCandle = close < open_
        
        # VWAP and bands
        vwap = self.vwap[-1] if not np.isnan(self.vwap[-1]) else close
        
        bandBasis = self.bandBasis[-1] if not np.isnan(self.bandBasis[-1]) else 0.01
        if bandBasis == 0:
            bandBasis = 0.01
        
        sectionHeight = bandBasis * 0.25
        
        upperBandValue1 = vwap + bandBasis * self.bandMult_1
        lowerBandValue1 = vwap - bandBasis * self.bandMult_1
        upperBandValue2 = vwap + bandBasis * self.bandMult_2
        lowerBandValue2 = vwap - bandBasis * self.bandMult_2
        upperBandValue3 = vwap + bandBasis * self.bandMult_3
        lowerBandValue3 = vwap - bandBasis * self.bandMult_3
        
        # Band detection
        inBandL3 = close >= lowerBandValue3 and close < (lowerBandValue3 + sectionHeight)
        inBandL2 = close >= lowerBandValue2 and close < (lowerBandValue2 + sectionHeight)
        inBandL1 = close >= lowerBandValue1 and close < (lowerBandValue1 + sectionHeight)
        inBandVWAP = close >= vwap and close < (vwap + sectionHeight)
        inBandU1 = close >= upperBandValue1 and close < (upperBandValue1 + sectionHeight)
        inBandU2 = close >= upperBandValue2 and close < (upperBandValue2 + sectionHeight)
        inBandU3 = close >= upperBandValue3 and close < (upperBandValue3 + sectionHeight)
        
        inTargetBand = ((self.detectBandL3 and inBandL3) or
                       (self.detectBandL2 and inBandL2) or
                       (self.detectBandL1 and inBandL1) or
                       (self.detectBandVWAP and inBandVWAP) or
                       (self.detectBandU1 and inBandU1) or
                       (self.detectBandU2 and inBandU2) or
                       (self.detectBandU3 and inBandU3))
        
        # Position relative to EMA
        priceAboveEMA = close > ema
        priceBelowEMA = close < ema
        
        # Confluence detection layers
        corridorAbove = priceAboveEMA and inTargetBand
        corridorBelow = priceBelowEMA and inTargetBand
        
        stateAbove_1 = (corridorAbove and compression) if self.useCompression else corridorAbove
        stateBelow_1 = (corridorBelow and compression) if self.useCompression else corridorBelow
        
        stateAbove_2 = (stateAbove_1 and rsiAboveSma) if self.useRSI else stateAbove_1
        stateBelow_2 = (stateBelow_1 and rsiAboveSma) if self.useRSI else stateBelow_1
        
        stateAbove_3 = (stateAbove_2 and diConditionAbove) if self.useDI else stateAbove_2
        stateBelow_3 = (stateBelow_2 and diConditionBelow) if self.useDI else stateBelow_2
        
        stateAbove = (stateAbove_3 and isGreenCandle) if self.useCandleColor else stateAbove_3
        stateBelow = (stateBelow_3 and isRedCandle) if self.useCandleColor else stateBelow_3
        
        state = stateAbove or stateBelow
        
        # Trading logic
        if stateAbove and not self.position:
            self.buy()
        elif stateBelow and not self.position:
            self.buy()
        elif self.position and not state:
            self.position.close()