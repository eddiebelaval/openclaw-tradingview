        curr_vol = self.current_vol[-1]
        highest_3m = self.weekly_vol_3m[-1]
        highest_6m = self.weekly_vol_6m[-1]
        
        # Check if we have valid values
        if highest_3m is None or highest_6m is None:
            return
        
