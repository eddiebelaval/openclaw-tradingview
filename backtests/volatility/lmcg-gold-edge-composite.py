import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastEmaLen = 9
    slowEmaLen = 21
    rsiLen = 14
    rsiHigh = 70
    rsiLow = 30
    macdFast = 12
    macdSlow = 26
    macdSigLen = 9
    atrLen = 14
    dxyLen = 20
    strongLvl = 0.55
    mildLvl = 0.15

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA Direction
        emaF = self.I(pta.ema, close, length=self.fastEmaLen)
        emaS = self.I(pta.ema, close, length=self.slowEmaLen)
        self.emaDir = self.I(lambda: pd.Series(
            np.where(emaF > emaS, 1, np.where(emaF < emaS, -1, 0)),
            index=close.index
        ))
        
        # RSI Direction
        rsi = self.I(pta.rsi, close, length=self.rsiLen)
        self.rsiDir = self.I(lambda: pd.Series(
            np.where(rsi < self.rsiLow, 1, np.where(rsi > self.rsiHigh, -1, 0)),
            index=close.index
        ))
        
        # MACD Direction
        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSigLen))
        self.macdDir = self.I(lambda: pd.Series(
            np.where(macd_result.iloc[:, 2] > 0, 1, np.where(macd_result.iloc[:, 2] < 0, -1, 0)),
            index=close.index
        ) if macd_result is not None else pd.Series(0, index=close.index))
        
        # ATR Volatility Scale
        atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.volScale = self.I(lambda: pd.Series(
            1 / np.maximum(0.001, 1 + atr / close),
            index=close.index
        ))
        
        # Composite Score
        self.tech = self.I(lambda: pd.Series(
            (self.emaDir + self.rsiDir + self.macdDir) / 3.0,
            index=close.index
        ))
        
        self.composite = self.I(lambda: pd.Series(
            (0.6 * self.tech + 0.2 * 0) * self.volScale,
            index=close.index
        ))
        
        self.score = self.I(lambda: pd.Series(
            np.maximum(-1.0, np.minimum(1.0, self.composite)),
            index=close.index
        ))
        
        self.in_trade = False

    def next(self):
        if len(self.data) < 2:
            return
        
        score_current = self.score[-1]
        score_prev = self.score[-2]
        
        # Strong Buy signal
        if score_current > self.strongLvl and score_prev <= self.strongLvl:
            if not self.position:
                self.buy()
                self.in_trade = True
        
        # Strong Sell signal
        elif score_current < -self.strongLvl and score_prev >= -self.strongLvl:
            if self.position:
                self.sell()
                self.in_trade = False
        
        # Mild Buy signal
        elif score_current > self.mildLvl and score_prev <= self.mildLvl:
            if not self.position:
                self.buy()
                self.in_trade = True
        
        # Mild Sell signal
        elif score_current < -self.mildLvl and score_prev >= -self.mildLvl:
            if self.position:
                self.sell()
                self.in_trade = False
        
        # Exit on reversal from strong levels
        elif score_current <= 0 and score_prev > self.strongLvl and self.position:
            self.sell()
            self.in_trade = False
        
        elif score_current >= 0 and score_prev < -self.strongLvl and not self.position:
            self.buy()
            self.in_trade = True


