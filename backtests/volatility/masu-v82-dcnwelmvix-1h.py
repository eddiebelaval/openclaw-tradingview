    def _nw_endpoint(self, src, h, lookback):
        """Nadaraya-Watson kernel endpoint estimation"""
        result = pd.Series(index=src.index, dtype=float)
        for i in range(len(src)):
            if i < lookback:
                result.iloc[i] = src.iloc[i]
                continue
            sum_w = 0.0
            sum_wy = 0.0
            for j in range(lookback):
                u = float(j) / h if h > 0 else 0
                w = np.exp(-0.5 * u * u)
                sum_w += w
                sum_wy += w * src.iloc[i - j]
            result.iloc[i] = sum_wy / sum_w if sum_w > 0 else src.iloc[i]
        return result
    
