import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 200
    mult = 2.0
    isInverted = False

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.avg = self.I(lambda: pta.sma(close, length=self.len))
        self.std = self.I(lambda: close.rolling(window=self.len).std())
        
        self.upper = self.I(lambda: self.avg + (self.std * self.mult))
        self.lower = self.I(lambda: self.avg - (self.std * self.mult))

    def next(self):
        if len(self.data) < self.len:
            return
        
        current_price = self.data.Close[-1]
        upper_val = self.upper[-1]
        lower_val = self.lower[-1]
        avg_val = self.avg[-1]
        
        if current_price is None or upper_val is None or lower_val is None or avg_val is None:
            return
        
        if current_price < lower_val and not self.position:
            self.buy()
        elif current_price > upper_val and self.position:
            self.sell()
        elif current_price > avg_val and self.position and current_price > lower_val:
            self.sell()


