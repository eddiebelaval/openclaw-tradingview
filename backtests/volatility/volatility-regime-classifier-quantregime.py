import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Regime Detection Engine
    hurst_len = 100
    adx_len = 14
    adx_smooth = 14
    chop_len = 14
    vol_len = 20
    vol_percentile = 100
    
    # Regime Thresholds
    adx_trend_thresh = 25.0
    adx_strong_thresh = 40.0
    chop_range_thresh = 61.8
    hurst_trend_thresh = 0.55
    hurst_mr_thresh = 0.45
    vol_high_pct = 80.0
    vol_low_pct = 20.0
    
    # Regime enum values
    REGIME_STRONG_BULL = 6
    REGIME_BULL = 5
    REGIME_WEAK_BULL = 4
    REGIME_RANGING = 3
    REGIME_MEAN_REV = 2
    REGIME_WEAK_BEAR = 1
    REGIME_BEAR = 0
    REGIME_STRONG_BEAR = -1
    REGIME_COMPRESSION = 7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Hurst Exponent
        def calc_hurst():
            result = []
            for i in range(len(close)):
                if i < self.hurst_len:
                    result.append(0.5)
                else:
                    window_close = close.iloc[i-self.hurst_len:i+1]
                    log_ret = np.log(window_close / window_close.shift(1)).dropna()
                    
                    if len(log_ret) < 2:
                        result.append(0.5)
                        continue
                    
                    mean_ret = log_ret.mean()
                    cum_dev = (log_ret - mean_ret).cumsum()
                    R = cum_dev.max() - cum_dev.min()
                    S = log_ret.std()
                    
                    if S > 0 and R > 0:
                        rs = R / S
                        H = np.log(rs) / np.log(self.hurst_len)
                        H = max(0.0, min(1.0, H))
                    else:
                        H = 0.5
                    result.append(H)
            return pd.Series(result, index=close.index)
        
        hurst_raw = self.I(calc_hurst)
        self.hurst_smooth = self.I(pta.ema, hurst_raw, length=5)
        
        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=self.adx_len)
        self.adx_val = self.I(lambda: adx_result.iloc[:, 2] if adx_result is not None and len(adx_result.columns) > 2 else pd.Series(20, index=close.index))
        self.di_plus = self.I(lambda: adx_result.iloc[:, 0] if adx_result is not None and len(adx_result.columns) > 0 else pd.Series(25, index=close.index))
        self.di_minus = self.I(lambda: adx_result.iloc[:, 1] if adx_result is not None and len(adx_result.columns) > 1 else pd.Series(25, index=close.index))
        
        # Choppiness Index
        def calc_chop():
            result = []
            for i in range(len(close)):
                if i < self.chop_len:
                    result.append(50.0)
                else:
                    window_high = high.iloc[i-self.chop_len:i+1]
                    window_low = low.iloc[i-self.chop_len:i+1]
                    atr_window = pta.atr(high.iloc[i-self.chop_len:i+1], low.iloc[i-self.chop_len:i+1], close.iloc[i-self.chop_len:i+1], length=1)
                    
                    sum_atr = atr_window.sum() if atr_window is not None else 1.0
                    high_low_range = window_high.max() - window_low.min()
                    
                    if high_low_range > 0 and sum_atr > 0:
                        chop = 100 * np.log10(sum_atr / high_low_range) / np.log10(self.chop_len)
                    else:
                        chop = 50.0
                    result.append(chop)
            return pd.Series(result, index=close.index)
        
        self.chop = self.I(calc_chop)
        
        # ATR and Volatility
        self.atr_val = self.I(pta.atr, high, low, close, length=self.vol_len)
        
        # Volatility Percentile Rank
        def calc_vol_pct():
            result = []
            for i in range(len(self.atr_val)):
                if i < self.vol_percentile:
                    result.append(50.0)
                else:
                    window = self.atr_val.iloc[i-self.vol_percentile:i+1]
                    current_val = self.atr_val.iloc[i]
                    count = (window < current_val).sum()
                    pct = (count / len(window)) * 100
                    result.append(pct)
            return pd.Series(result, index=close.index)
        
        self.vol_pct_rank = self.I(calc_vol_pct)
        
        # EMA Trend
        self.ema_fast = self.I(pta.ema, close, length=21)
        self.ema_slow = self.I(pta.ema, close, length=55)
        
        # ROC
        self.roc_val = self.I(pta.roc, close, length=10)
        
        # Volatility Bands
        self.basis = self.I(pta.ema, close, length=21)
        
        # Regime calculation
        def calc_regime():
            regimes = []
            for i in range(len(close)):
                # Basic checks
                adx = self.adx_val[i] if i < len(self.adx_val) else 20
                di_p = self.di_plus[i] if i < len(self.di_plus) else 25
                di_m = self.di_minus[i] if i < len(self.di_minus) else 25
                chop = self.chop[i] if i < len(self.chop) else 50
                hurst = self.hurst_smooth[i] if i < len(self.hurst_smooth) else 0.5
                vol_pct = self.vol_pct_rank[i] if i < len(self.vol_pct_rank) else 50
                ema_f = self.ema_fast[i] if i < len(self.ema_fast) else close.iloc[i]
                ema_s = self.ema_slow[i] if i < len(self.ema_slow) else close.iloc[i]
                atr = self.atr_val[i] if i < len(self.atr_val) else 1.0
                
                # Classify volatility
                is_high_vol = vol_pct >= self.vol_high_pct
                is_low_vol = vol_pct <= self.vol_low_pct
                
                # Trend direction
                trend_bullish = di_p > di_m
                trend_bearish = di_m > di_p
                ema_bullish = ema_f > ema_s
                ema_bearish = ema_f < ema_s
                
                # Scores
                trend_score = 3 if adx >= self.adx_strong_thresh else 2 if adx >= self.adx_trend_thresh else 1 if adx >= 15 else 0
                chop_score = -2 if chop >= self.chop_range_thresh else -1 if chop >= 50 else 1 if chop >= 38.2 else 2
                hurst_score = 2 if hurst >= self.hurst_trend_thresh else 1 if hurst >= 0.5 else -1 if hurst >= self.hurst_mr_thresh else -2
                
                direction = 1 if (ema_bullish and trend_bullish) else -1 if (ema_bearish and trend_bearish) else 0.5 if (ema_bullish or trend_bullish) else -0.5 if (ema_bearish or trend_bearish) else 0
                
                composite = trend_score + chop_score + hurst_score
                
                # Final regime
                if is_low_vol and chop >= self.chop_range_thresh:
                    regime = self.REGIME_COMPRESSION
                elif hurst < self.hurst_mr_thresh and adx < self.adx_trend_thresh:
                    regime = self.REGIME_MEAN_REV
                elif composite >= 5 and direction > 0:
                    regime = self.REGIME_STRONG_BULL
                elif composite >= 3 and direction > 0:
                    regime = self.REGIME_BULL
                elif composite >= 1 and direction > 0:
                    regime = self.REGIME_WEAK_BULL
                elif composite >= 5 and direction < 0:
                    regime = self.REGIME_STRONG_BEAR
                elif composite >= 3 and direction < 0:
                    regime = self.REGIME_BEAR
                elif composite >= 1 and direction < 0:
                    regime = self.REGIME_WEAK_BEAR
                elif chop >= self.chop_range_thresh or composite <= 0:
                    regime = self.REGIME_RANGING
                else:
                    regime = self.REGIME_RANGING
                
                regimes.append(regime)
            
            return pd.Series(regimes, index=close.index)
        
        self.regime = self.I(calc_regime)

    def next(self):
        # Simple trading logic based on regime
        current_regime = self.regime[-1]
        
        # Buy signals: Strong or weak bull trends
        if current_regime in [self.REGIME_STRONG_BULL, self.REGIME_BULL, self.REGIME_WEAK_BULL]:
            if not self.position:
                self.buy()
        # Sell signals: Strong or weak bear trends, ranging, compression
        elif current_regime in [self.REGIME_STRONG_BEAR, self.REGIME_BEAR, self.REGIME_WEAK_BEAR, self.REGIME_RANGING, self.REGIME_COMPRESSION, self.REGIME_MEAN_REV]:
            if self.position:
                self.sell()


