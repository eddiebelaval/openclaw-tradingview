import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_length = 14
    atr_threshold = 0.25
    box_width = 15

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        self.last_drawn_day = None
        self.last_930_high = None
        self.last_930_low = None
        self.last_930_open = None
        self.last_930_close = None
        self.last_930_index = None

    def next(self):
        if len(self.data) < self.atr_length + 1:
            return
        
        current_time = self.data.index[-1]
        current_hour = current_time.hour
        current_minute = current_time.minute
        current_day = current_time.day
        
        is_930 = current_hour == 9 and current_minute == 30
        
        if is_930 and (self.last_drawn_day is None or current_day != self.last_drawn_day):
            self.last_drawn_day = current_day
            
            h15 = self.data.High[-1]
            l15 = self.data.Low[-1]
            o15 = self.data.Open[-1]
            c15 = self.data.Close[-1]
            
            rng = h15 - l15
            atr_val = self.atr[-1]
            
            if atr_val is None or np.isnan(atr_val):
                return
            
            seuil = atr_val * self.atr_threshold
            liquid = rng >= seuil
            bullish = c15 > o15
            
            self.last_930_high = h15
            self.last_930_low = l15
            self.last_930_open = o15
            self.last_930_close = c15
            self.last_930_index = len(self.data) - 1
            
            if liquid:
                if bullish:
                    self.sell()
                else:
                    self.buy()
        
        if self.last_930_index is not None and len(self.data) - self.last_930_index >= self.box_width:
            if self.position:
                self.position.close()


