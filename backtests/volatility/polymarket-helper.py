import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters
    min_confidence = 50
    pred_threshold = 5.0
    w_ivd = 0.25
    w_m1dv = 0.22
    w_conv = 0.18
    w_m1dir = 0.10
    w_poc = 0.08
    w_micro = 0.07
    w_vpt = 0.05
    w_m1accel = 0.03
    w_close_w = 0.02

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_price = pd.Series(self.data.Open)

        # OBV calculation
        change_src = close.diff()
        obv_series = (np.where(change_src > 0, volume, np.where(change_src < 0, -volume, 0))).cumsum()
        self.obv = self.I(lambda: pd.Series(obv_series, index=close.index))

        # PVT calculation
        pv_sum = ((close - close.shift(1)) / close.shift(1) * volume).fillna(0).cumsum()
        self.pvt = self.I(lambda: pd.Series(pv_sum, index=close.index))

        # OBV-PVT momentum
        res_main = self.obv - self.pvt
        mom_main = res_main.diff()
        self.mom_main = self.I(lambda: mom_main)

        # SMA for OBV momentum normalization
        mom_sma = pta.sma(close, length=20)
        self.mom_sma = self.I(lambda: mom_sma if mom_sma is not None else pd.Series(1.0, index=close.index))

        # ATR for volatility
        self.atr = self.I(pta.atr, high, low, close, length=14)

    def next(self):
        if len(self.data) < 20:
            return

        current_mom = self.mom_main[-1]
        prev_mom = self.mom_main[-2] if len(self.mom_main) > 1 else current_mom
        mom_sma_val = self.mom_sma[-1] if self.mom_sma[-1] is not None else 1.0

        # Calculate OBV strength
        obv_strength = abs(current_mom) / max(abs(mom_sma_val), 1.0)

        # Direction change detection
        prev_direction = 1 if prev_mom >= 0 else 0
        curr_direction = 1 if current_mom >= 0 else 0
        dir_changed = prev_direction != curr_direction

        # Buy signal: OBV momentum turns positive with direction change
        if dir_changed and current_mom >= 0 and obv_strength >= 0.5:
            if not self.position:
                self.buy()
        # Sell signal: OBV momentum turns negative with direction change
        elif dir_changed and current_mom < 0 and obv_strength >= 0.5:
            if self.position:
                self.sell()

        # Exit on extreme weakness in opposite direction
        if self.position:
            if current_mom < -abs(self.mom_sma[-2]) if len(self.mom_sma) > 2 else False:
                self.sell()
        else:
            if current_mom > abs(self.mom_sma[-2]) if len(self.mom_sma) > 2 else False:
                self.buy()


