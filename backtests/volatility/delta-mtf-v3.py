import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Timeframe parameters (not used in backtest - using chart data)
    tf_high = "5"
    tf_low = "1"
    tf_trend = "60"
    use_trend = True

    # Delta Weights
    w_high = 65
    w_low = 35

    # Signal thresholds
    sig_thresh = 40
    rev_thresh = 0.1

    # Reversal Weights
    w_rev_prox = 35
    w_rev_conflict = 25
    w_rev_dv = 20
    w_rev_hidden = 20

    # Enhanced Features
    absorb_thresh_mult = 1.3
    absorb_delta_pct = 0.25
    absorb_sma_len = 20
    slope_len = 3
    slope_min_chg = 0.0
    exhaust_flips = 3
    show_poc_line = True
    show_vwap = True
    vwap_anchor = "UTC midnight"
    show_phase_bar = True
    time_pressure_min = 80

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_price = pd.Series(self.data.Open)

        # Calculate simple indicators for basic trading logic
        self.rsi = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        self.sma_fast = self.I(lambda: pta.sma(close, length=20) or close)
        self.sma_slow = self.I(lambda: pta.sma(close, length=50) or close)

        # Volume analysis
        self.vol_sma = self.I(lambda: pta.sma(volume, length=self.absorb_sma_len) or volume)

        # VWAP calculation
        self.vwap = self.I(self._calc_vwap, high, low, close, volume)

        # Delta-based signals (simplified for backtest)
        self.delta_buy_signal = self.I(self._calc_delta_buy, close, open_price, volume)
        self.delta_sell_signal = self.I(self._calc_delta_sell, close, open_price, volume)

        # Track previous signals
        self.last_buy_signal = False
        self.last_sell_signal = False

    def _calc_vwap(self, high, low, close, volume):
        """Calculate session VWAP"""
        tp = (high + low + close) / 3.0
        vwap_cumsum = (tp * volume).expanding().sum()
        volume_cumsum = volume.expanding().sum()
        vwap = vwap_cumsum / volume_cumsum
        return vwap

    def _calc_delta_buy(self, close, open_price, volume):
        """Calculate buy delta signal"""
        # Buy when close > open (green candle) with above-average volume
        is_green = close > open_price
        delta = np.where(is_green, volume, 0)
        return pd.Series(delta, index=close.index)

    def _calc_delta_sell(self, close, open_price, volume):
        """Calculate sell delta signal"""
        # Sell when close < open (red candle) with above-average volume
        is_red = close < open_price
        delta = np.where(is_red, volume, 0)
        return pd.Series(delta, index=close.index)

    def next(self):
        """Trading logic based on delta and momentum signals"""
        close_price = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        volume = self.data.Volume[-1]

        rsi = self.rsi[-1]
        sma_fast = self.sma_fast[-1]
        sma_slow = self.sma_slow[-1]
        vwap = self.vwap[-1]
        vol_sma = self.vol_sma[-1]

        # Get delta signals
        buy_delta = self.delta_buy_signal[-1] if len(self.delta_buy_signal) > 0 else 0
        sell_delta = self.delta_sell_signal[-1] if len(self.delta_sell_signal) > 0 else 0

        # Volume spike detection
        vol_spike = volume > vol_sma * 1.5

        # Trend direction (fast SMA vs slow SMA)
        trend_up = sma_fast > sma_slow
        trend_down = sma_fast < sma_slow

        # Price position relative to VWAP
        above_vwap = close_price > vwap
        below_vwap = close_price < vwap

        # Hidden signal: volume strength opposite to candle direction
        is_green = close_price > open_price
        is_red = close_price < open_price
        hidden_buy = is_red and buy_delta > vol_sma * 0.8 and vol_spike
        hidden_sell = is_green and sell_delta > vol_sma * 0.8 and vol_spike

        # Reversal detection
        price_from_open = (close_price - open_price) / (open_price + 1e-9)
        near_open = abs(price_from_open) < self.rev_thresh

        # Main trading conditions
        buy_condition = (
            trend_up and
            below_vwap and
            (rsi < 70) and
            vol_spike and
            buy_delta > 0 and
            crossover(sma_fast, sma_slow)
        )

        sell_condition = (
            trend_down and
            above_vwap and
            (rsi > 30) and
            vol_spike and
            sell_delta > 0 and
            crossover(sma_slow, sma_fast)
        )

        # Reversal entries with hidden signals
        reversal_buy = hidden_buy and near_open and trend_up
        reversal_sell = hidden_sell and near_open and trend_down

        # Exhaustion-based exits
        if self.position:
            if self.position.is_long:
                # Exit long on RSI overbought or reversal down
                if rsi > 80 or (is_red and vol_spike and sell_delta > buy_delta):
                    self.position.close()
            else:  # Short position
                # Exit short on RSI oversold or reversal up
                if rsi < 20 or (is_green and vol_spike and buy_delta > sell_delta):
                    self.position.close()

        # Entry logic
        if not self.position:
            if buy_condition or reversal_buy:
                self.buy()
            elif sell_condition or reversal_sell:
                self.sell()