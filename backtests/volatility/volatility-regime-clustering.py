import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLength = 14
    lookback = 200
    numClusters = 3
    smoothing = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # Normalize ATR to basis points
        atr_normalized = self.I(lambda: (atr / close * 10000).fillna(method='bfill'))
        
        self.atr = atr
        self.atr_normalized = atr_normalized
        self.regime_history = []
        self.centroids = None
        self.initialized = False
        self.atr_history = []
        self.candidate_regime = 0
        self.candidate_count = 0
        self.confirmed_regime = 0
        self.bar_count = 0

    def init_centroids(self, atr_history):
        """Initialize centroids using min-max range"""
        if len(atr_history) == 0:
            return [0.0] * self.numClusters
        
        min_atr = min(atr_history)
        max_atr = max(atr_history)
        atr_range = max_atr - min_atr
        
        if atr_range == 0:
            atr_range = 1.0
        
        centroids = []
        if self.numClusters == 1:
            centroids.append((min_atr + max_atr) / 2)
        else:
            for i in range(self.numClusters):
                position = i / (self.numClusters - 1)
                centroid_value = min_atr + (atr_range * position)
                centroids.append(centroid_value)
        
        return centroids

    def assign_clusters(self, atr_history, centroids):
        """Assign each value to nearest centroid"""
        assignments = []
        for value in atr_history:
            min_dist = float('inf')
            cluster = 0
            for j in range(self.numClusters):
                dist = abs(value - centroids[j])
                if dist < min_dist:
                    min_dist = dist
                    cluster = j
            assignments.append(cluster)
        return assignments

    def update_centroids(self, atr_history, assignments):
        """Update centroids based on assignments"""
        new_centroids = [0.0] * self.numClusters
        counts = [0] * self.numClusters
        
        for i, cluster in enumerate(assignments):
            new_centroids[cluster] += atr_history[i]
            counts[cluster] += 1
        
        min_atr = min(atr_history) if atr_history else 0
        max_atr = max(atr_history) if atr_history else 1
        atr_range = max_atr - min_atr
        if atr_range == 0:
            atr_range = 1.0
        
        for i in range(self.numClusters):
            if counts[i] > 0:
                new_centroids[i] = new_centroids[i] / counts[i]
            else:
                position = i / (self.numClusters - 1) if self.numClusters > 1 else 0.5
                new_centroids[i] = min_atr + (atr_range * position)
        
        return new_centroids

    def kmeans_iteration(self, atr_history, centroids):
        """Single k-means iteration"""
        assignments = self.assign_clusters(atr_history, centroids)
        new_centroids = self.update_centroids(atr_history, assignments)
        return new_centroids

    def find_current_regime(self, value, centroids):
        """Find raw regime for current bar"""
        if not self.initialized:
            return 0
        
        min_dist = float('inf')
        regime = 0
        for i in range(self.numClusters):
            dist = abs(value - centroids[i])
            if dist < min_dist:
                min_dist = dist
                regime = i
        return regime

    def next(self):
        self.bar_count += 1
        
        # Get current ATR normalized value
        current_atr_norm = self.atr_normalized[-1]
        if pd.isna(current_atr_norm):
            return
        
        # Build ATR history
        self.atr_history.append(current_atr_norm)
        if len(self.atr_history) > self.lookback:
            self.atr_history.pop(0)
        
        # Initialize clustering when we have enough data
        if len(self.atr_history) >= self.lookback and not self.initialized:
            self.centroids = self.init_centroids(self.atr_history)
            self.initialized = True
        
        # Update clustering every 5 bars
        if self.initialized and self.bar_count % 5 == 0:
            for _ in range(3):
                self.centroids = self.kmeans_iteration(self.atr_history, self.centroids)
        
        # Find raw regime
        raw_regime = self.find_current_regime(current_atr_norm, self.centroids) if self.initialized else 0
        
        # Apply smoothing
        if raw_regime != self.confirmed_regime:
            if raw_regime == self.candidate_regime:
                self.candidate_count += 1
                if self.candidate_count >= self.smoothing:
                    self.confirmed_regime = raw_regime
                    self.candidate_count = 0
            else:
                self.candidate_regime = raw_regime
                self.candidate_count = 1
        else:
            self.candidate_regime = raw_regime
            self.candidate_count = 0
        
        # Track regime history
        self.regime_history.append(self.confirmed_regime)
        if len(self.regime_history) > 50:
            self.regime_history.pop(0)
        
        # Trading logic based on regime changes
        if len(self.regime_history) > 1:
            prev_regime = self.regime_history[-2]
            curr_regime = self.regime_history[-1]
            
            # Buy when transitioning to low volatility regime
            if not self.position and curr_regime == 0 and prev_regime != 0:
                self.buy()
            
            # Sell when transitioning to high volatility regime
            elif self.position and curr_regime == (self.numClusters - 1) and prev_regime != curr_regime:
                self.sell()


