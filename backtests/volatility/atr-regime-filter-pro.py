import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLen = 14
    atrAvg = 50
    lowThr = 0.80
    highThr = 1.80
    emaLen = 200
    slopeBars = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Calculate ATR average
        atr_avg = self.I(lambda: pta.sma(atr, length=self.atrAvg) if atr is not None else pd.Series(1.0, index=close.index))
        
        # Calculate ATR Ratio
        self.atr_ratio = self.I(lambda: atr / atr_avg if atr is not None and atr_avg is not None else pd.Series(1.0, index=close.index))
        
        # Calculate EMA on this timeframe for slope calculation
        ema = self.I(pta.ema, close, length=self.emaLen)
        
        # Calculate EMA slope percentage
        def calc_ema_slope():
            ema_data = pta.ema(close, length=self.emaLen)
            if ema_data is None:
                return pd.Series(0.0, index=close.index)
            
            slope = pd.Series(0.0, index=close.index)
            for i in range(self.slopeBars, len(ema_data)):
                if i >= self.slopeBars and not pd.isna(ema_data.iloc[i]) and not pd.isna(ema_data.iloc[i - self.slopeBars]):
                    slope.iloc[i] = ((ema_data.iloc[i] - ema_data.iloc[i - self.slopeBars]) / close.iloc[i]) * 100.0
            return slope
        
        self.ema_slope = self.I(calc_ema_slope)
        
        # ATR regime states
        self.atr_dead = self.I(lambda: self.atr_ratio < self.lowThr)
        self.atr_extreme = self.I(lambda: self.atr_ratio > self.highThr)
        self.atr_healthy = self.I(lambda: (~self.atr_dead) & (~self.atr_extreme))
        
        # EMA slope states
        self.ema_flat = self.I(lambda: np.abs(self.ema_slope) < 0.05)
        self.ema_bull = self.I(lambda: self.ema_slope > 0.05)
        self.ema_bear = self.I(lambda: self.ema_slope < -0.05)
        
        # Market permission
        self.market_ok = self.I(lambda: self.atr_healthy & (~self.ema_flat))

    def next(self):
        # Only trade when market permission is active
        if len(self.data) < self.slopeBars + self.emaLen + self.atrAvg + 10:
            return
        
        # Get current state values
        current_market_ok = self.market_ok[-1]
        current_ema_bull = self.ema_bull[-1]
        current_ema_bear = self.ema_bear[-1]
        current_atr_ratio = self.atr_ratio[-1]
        
        # Entry logic: Buy when market OK and EMA is bullish
        if current_market_ok and current_ema_bull:
            if not self.position:
                self.buy()
        
        # Entry logic: Short when market OK and EMA is bearish
        elif current_market_ok and current_ema_bear:
            if self.position:
                self.position.close()
        
        # Exit logic: Close position if market permission is revoked
        elif not current_market_ok:
            if self.position:
                self.position.close()
        
        # Exit on extreme volatility
        if current_atr_ratio > self.highThr and self.position:
            self.position.close()


