import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    show_labels = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Track session high and low using rolling max/min
        # We'll use a large window to capture the session high/low
        self.session_high = self.I(lambda: high.rolling(window=len(high), min_periods=1).max())
        self.session_low = self.I(lambda: low.rolling(window=len(low), min_periods=1).min())
        
        self.prev_session_high = None
        self.prev_session_low = None

    def next(self):
        # Get current session high and low
        current_high = self.session_high[-1]
        current_low = self.session_low[-1]
        
        # Initialize previous values on first bar
        if self.prev_session_high is None:
            self.prev_session_high = current_high
            self.prev_session_low = current_low
            return
        
        # Detect new high condition
        new_high_condition = current_high > self.prev_session_high
        
        # Detect new low condition
        new_low_condition = current_low < self.prev_session_low
        
        # Trading logic based on new extremes
        if new_high_condition:
            # New session high formed - bullish signal
            if not self.position:
                self.buy()
        
        if new_low_condition:
            # New session low formed - bearish signal
            if self.position:
                self.position.close()
        
        # Update previous values for next bar
        self.prev_session_high = current_high
        self.prev_session_low = current_low


