import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core lengths
    fastLen = 18
    midLen = 50
    slowLen = 120
    smoothLen = 3
    pullbackLen = 8
    breakoutLen = 20
    effLen = 18
    persistLen = 7
    momLen = 12
    slopeLen = 10
    atrLen = 14
    atrBaseLen = 40
    
    # Thresholds
    minScore = 5.0
    exitScore = 2.5
    minSepPerc = 0.30
    minSlowSlopePerc = 0.03
    minEff = 0.33
    minAtrRegime = 0.95
    minBreakoutAtr = 0.15
    pullbackAtrMult = 0.90
    reclaimAtrMult = 0.15
    cooldownBars = 5
    
    # Risk
    leverage = 2.0
    hardStopPerc = 2.0
    trailAtrMult = 2.8
    profitLockAtrMult = 20.8
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Smoothed EMAs
        ema_fast = self.I(pta.ema, close, length=self.fastLen)
        self.fast = self.I(pta.ema, ema_fast, length=self.smoothLen)
        
        ema_mid = self.I(pta.ema, close, length=self.midLen)
        self.mid = self.I(pta.ema, ema_mid, length=self.smoothLen)
        
        ema_slow = self.I(pta.ema, close, length=self.slowLen)
        self.slow = self.I(pta.ema, ema_slow, length=self.smoothLen)
        
        # ATR and regime
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        atr_sma = self.I(pta.sma, self.atr, length=self.atrBaseLen)
        self.atrRegime = self.I(lambda: self.atr / atr_sma.replace(0, 1))
        
        # Highest high for breakout
        self.hh = self.I(lambda: high.rolling(self.breakoutLen).max().shift(1))
        
        # Lowest low for pullback
        self.pullbackLow = self.I(lambda: low.rolling(self.pullbackLen).min())
        
        self.entry_bar = -1
        self.last_exit_bar = -1
        self.trail_stop = None
        self.high_since_entry = None
        
    def next(self):
        if len(self.data) < max(self.slowLen + self.smoothLen, self.effLen, self.momLen, self.breakoutLen, self.pullbackLen, self.slopeLen, self.atrBaseLen):
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Current indicator values
        fast = self.fast[-1]
        mid = self.mid[-1]
        slow = self.slow[-1]
        atr = self.atr[-1]
        atr_regime = self.atrRegime[-1]
        hh = self.hh[-1]
        pullback_low = self.pullbackLow[-1]
        
        # Regime structure
        bull_stack = fast > mid and mid > slow
        sep_perc = abs(fast - slow) / slow * 100 if slow != 0 else 0.0
        sep_ok = sep_perc >= self.minSepPerc
        
        # Slopes
        fast_prev = self.fast[-1 - self.slopeLen] if len(self.fast) > self.slopeLen else self.fast[-1]
        mid_prev = self.mid[-1 - self.slopeLen] if len(self.mid) > self.slopeLen else self.mid[-1]
        slow_prev = self.slow[-1 - self.slopeLen] if len(self.slow) > self.slopeLen else self.slow[-1]
        
        fast_slope = (fast - fast_prev) / fast_prev * 100 if fast_prev != 0 else 0.0
        mid_slope = (mid - mid_prev) / mid_prev * 100 if mid_prev != 0 else 0.0
        slow_slope = (slow - slow_prev) / slow_prev * 100 if slow_prev != 0 else 0.0
        slope_ok = slow_slope >= self.minSlowSlopePerc and mid_slope > 0 and fast_slope > 0
        
        # Efficiency
        close_eff_back = self.data.Close[-1 - self.effLen] if len(self.data.Close) > self.effLen else self.data.Close[-1]
        net_move = abs(close - close_eff_back)
        step_move = 0.0
        for i in range(1, self.effLen + 1):
            if len(self.data.Close) >= i + 1:
                step_move += abs(self.data.Close[-i] - self.data.Close[-i - 1])
        efficiency = net_move / step_move if step_move != 0 else 0.0
        eff_ok = efficiency >= self.minEff
        
        # Momentum persistence
        up_bars = 0.0
        for i in range(self.persistLen):
            if len(self.data.Close) >= i + 2:
                if self.data.Close[-i] > self.data.Close[-i - 1]:
                    up_bars += 1
        persist_ratio = up_bars / self.persistLen if self.persistLen > 0 else 0.0
        
        close_mom_back = self.data.Close[-1 - self.momLen] if len(self.data.Close) > self.momLen else self.data.Close[-1]
        mom_raw = (close - close_mom_back) / close_mom_back * 100 if close_mom_back != 0 else 0.0
        mom_ok = mom_raw > 0 and persist_ratio >= 0.57
        
        # ATR ok
        atr_ok = atr_regime >= self.minAtrRegime
        
        # Breakout quality
        breakout_dist = close - hh if hh != 0 else 0
        breakout_strength = breakout_dist / atr if atr != 0 else 0.0
        breakout_ok = close > hh and breakout_strength >= self.minBreakoutAtr
        
        # Pullback / reclaim logic
        dist_from_fast_atr = (fast - pullback_low) / atr if atr != 0 else 0.0
        deep_enough_pullback = dist_from_fast_atr >= self.pullbackAtrMult
        
        prev_close = self.data.Close[-2] if len(self.data.Close) > 1 else self.data.Close[-1]
        prev_fast = self.fast[-2] if len(self.fast) > 1 else self.fast[-1]
        prev_mid = self.mid[-2] if len(self.mid) > 1 else self.mid[-1]
        
        reclaim_fast = close > fast and prev_close <= prev_fast
        reclaim_mid = close > mid and prev_close <= prev_mid
        reclaim_strength = (close - fast) / atr if atr != 0 else 0.0
        reclaim_ok = (reclaim_fast or reclaim_mid) and reclaim_strength >= self.reclaimAtrMult
        
        # Bull cross detection
        bull_cross = crossover(self.fast, self.mid) or crossover(self.fast, self.slow) or crossover(self.mid, self.slow)
        bars_since_bull_cross = 0
        for i in range(1, min(15, len(self.data))):
            if len(self.fast) >= i + 1 and len(self.mid) >= i + 1 and len(self.slow) >= i + 1:
                prev_fast_i = self.fast[-i - 1]
                prev_mid_i = self.mid[-i - 1]
                prev_slow_i = self.slow[-i - 1]
                curr_fast_i = self.fast[-i]
                curr_mid_i = self.mid[-i]
                curr_slow_i = self.slow[-i]
                if (curr_fast_i > curr_mid_i and prev_fast_i <= prev_mid_i) or \
                   (curr_fast_i > curr_slow_i and prev_fast_i <= prev_slow_i) or \
                   (curr_mid_i > curr_slow_i and prev_mid_i <= prev_slow_i):
                    bars_since_bull_cross = i
                    break
        recent_trend_birth = bars_since_bull_cross >= 0 and bars_since_bull_cross <= 14
        
        # Weighted score
        trend_score = 0.0
        trend_score += 1.50 if bull_stack else 0.0
        trend_score += 0.90 if sep_ok else 0.0
        trend_score += 1.10 if slope_ok else 0.0
        trend_score += 1.00 if eff_ok else 0.0
        trend_score += 0.80 if atr_ok else 0.0
        trend_score += 1.00 if mom_ok else 0.0
        trend_score += 1.25 if breakout_ok else 0.0
        trend_score += 1.10 if reclaim_ok else 0.0
        
        # Entry models
        trend_continuation_entry = bull_stack and breakout_ok and slope_ok and eff_ok and mom_ok
        pullback_reentry = bull_stack and sep_ok and slope_ok and deep_enough_pullback and reclaim_ok and eff_ok
        early_trend_entry = recent_trend_birth and bull_stack and sep_ok and slope_ok and atr_ok and mom_ok
        
        # Cooldown
        current_bar = len(self.data) - 1
        cooldown_ok = self.last_exit_bar < 0 or (current_bar - self.last_exit_bar) > self.cooldownBars
        
        # Final entry
        enter_long = cooldown_ok and trend_score >= self.minScore and close > slow and \
                     (trend_continuation_entry or pullback_reentry or early_trend_entry) and \
                     not self.position
        
        if enter_long:
            # Manual leveraged sizing
            equity = self.equity
            position_value = equity * self.leverage
            qty = position_value / close if close > 0 else 0
            if qty > 0:
                self.buy(size=qty)
                self.entry_bar = current_bar
                self.trail_stop = None
                self.high_since_entry = high
        
        # Exit logic
        if self.position:
            can_exit_now = self.entry_bar >= 0 and current_bar > self.entry_bar
            
            if can_exit_now:
                # Bear crosses
                bear_cross = crossover(self.mid, self.fast) or crossover(self.slow, self.fast)
                
                # Structure break
                structure_break = close < mid and fast < mid
                
                # Score weak
                score_weak = trend_score <= self.exitScore
                
                # Momentum failure
                momentum_failure = persist_ratio < 0.40 and mom_raw < 0
                
                # Regime failure
                regime_failure = atr_regime < 0.80 and efficiency < 0.25
                
                exit_long = bear_cross or structure_break or score_weak or momentum_failure or regime_failure
                
                if exit_long:
                    self.position.close()
                    self.last_exit_bar = current_bar
                    self.trail_stop = None
                    self.high_since_entry = None
                else:
                    # Risk management
                    hard_stop_price = self.position.open_price * (1 - self.hardStopPerc / 100)
                    
                    if self.high_since_entry is not None:
                        self.high_since_entry = max(self.high_since_entry, high)
                    else:
                        self.high_since_entry = high
                    
                    raw_trail = close - atr * self.trailAtrMult
                    profit_lock = self.high_since_entry - atr * self.profitLockAtrMult
                    combined_trail = max(raw_trail, profit_lock)
                    
                    if self.trail_stop is None:
                        self.trail_stop = combined_trail
                    else:
                        self.trail_stop = max(self.trail_stop, combined_trail)
                    
                    stop_price = max(hard_stop_price, self.trail_stop)
                    
                    if close <= stop_price:
                        self.position.close()
                        self.last_exit_bar = current_bar
                        self.trail_stop = None
                        self.high_since_entry = None


