import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pricevol_length = 22
    pricevol_rank_len = 252
    high_vol_threshold = 50.0
    state_change_threshold = 2.0
    calm_zone_threshold = 25.0
    elevated_zone_threshold = 50.0
    extreme_zone_threshold = 75.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate standard deviations
        self.spot_stdev = self.I(lambda: pta.stdev(close, length=self.pricevol_length) or pd.Series(0, index=close.index))
        self.low_stdev = self.I(lambda: pta.stdev(low, length=self.pricevol_length) or pd.Series(0, index=close.index))
        
        # Calculate price volatility
        def calc_price_vol():
            hi = high.rolling(self.pricevol_length).max()
            result = pd.Series(index=close.index, dtype='float64')
            for i in range(len(close)):
                if hi.iloc[i] != 0.0:
                    result.iloc[i] = ((hi.iloc[i] - low.iloc[i]) / hi.iloc[i]) * 100.0
                else:
                    result.iloc[i] = np.nan
            return result
        
        self.price_vol = self.I(calc_price_vol)
        
        # Normalize to rank
        def normalize_rank():
            result = pd.Series(index=close.index, dtype='float64')
            for i in range(len(self.price_vol)):
                window_data = self.price_vol.iloc[max(0, i - self.pricevol_rank_len + 1):i + 1]
                lo = window_data.min()
                hi = window_data.max()
                rng = hi - lo
                if rng != 0.0 and not pd.isna(self.price_vol.iloc[i]):
                    result.iloc[i] = ((self.price_vol.iloc[i] - lo) / rng) * 100.0
                else:
                    result.iloc[i] = np.nan
            return result
        
        self.price_norm = self.I(normalize_rank)
        
        # Calculate motion state
        def calc_motion_state():
            result = pd.Series(index=close.index, dtype='int64')
            for i in range(len(self.price_norm)):
                if i == 0:
                    result.iloc[i] = 0
                    continue
                    
                if pd.isna(self.price_norm.iloc[i]) or pd.isna(self.price_norm.iloc[i-1]):
                    result.iloc[i] = 0
                    continue
                
                motion_change = self.price_norm.iloc[i] - self.price_norm.iloc[i-1]
                
                if motion_change > self.state_change_threshold:
                    result.iloc[i] = 1  # Expanding
                elif motion_change < -self.state_change_threshold:
                    result.iloc[i] = -1  # Contracting
                elif self.price_norm.iloc[i] >= self.high_vol_threshold:
                    result.iloc[i] = 2  # Stable High
                else:
                    result.iloc[i] = 0  # Stable Low
            
            return result
        
        self.motion_state = self.I(calc_motion_state)

    def next(self):
        if len(self) < 2:
            return
        
        # Get current and previous motion states
        current_motion = self.motion_state[-1]
        prev_motion = self.motion_state[-2] if len(self.motion_state) > 1 else 0
        
        current_price_norm = self.price_norm[-1]
        prev_price_norm = self.price_norm[-2] if len(self.price_norm) > 1 else 0
        
        # Skip if values are NaN
        if pd.isna(current_motion) or pd.isna(current_price_norm):
            return
        
        # Buy signals: volatility expanding or transitioning to high regime
        if current_motion == 1 and prev_motion != 1:  # Expanding starts
            if not self.position:
                self.buy()
        
        # Buy on transition to stable high if coming from low
        elif current_motion == 2 and prev_motion == 0:
            if not self.position:
                self.buy()
        
        # Sell signals: volatility contracting or transitioning to low regime
        if current_motion == -1 and prev_motion != -1:  # Contracting starts
            if self.position:
                self.sell()
        
        # Sell on transition to stable low if coming from high
        elif current_motion == 0 and prev_motion == 2:
            if self.position:
                self.sell()
        
        # Exit on extended contraction
        elif current_motion == -1 and current_price_norm < self.calm_zone_threshold:
            if self.position:
                self.sell()


