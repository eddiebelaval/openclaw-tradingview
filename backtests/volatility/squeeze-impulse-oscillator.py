import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    i_period = 14
    i_smooth = 3
    i_impTh = 0.6
    i_sqzTh = -0.5
    i_sqzMin = 3

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        def calc_sio():
            body_size = np.abs(close - open_)
            range_ = high - low
            body_eff = np.where(range_ > 0, body_size / range_, 0.0)

            upper_wick = high - np.maximum(open_, close)
            lower_wick = np.minimum(open_, close) - low
            total_wick = upper_wick + lower_wick
            wick_ratio = np.where(range_ > 0, total_wick / range_, 0.0)

            chg = close.diff()
            prev_chg = close.diff(2)
            persist = np.where(
                ((chg > 0) & (prev_chg > 0)) | ((chg < 0) & (prev_chg < 0)),
                1.0,
                0.0
            )

            avg_range = pta.sma(range_, length=self.i_period)
            range_ratio = np.where(avg_range > 0, range_ / avg_range, 1.0)

            impulse_score = body_eff * range_ratio * (0.5 + 0.5 * persist)
            squeeze_score = wick_ratio * (2.0 - range_ratio) * (1.0 - persist * 0.5)

            raw_sio = impulse_score - squeeze_score
            sio = pta.ema(pd.Series(raw_sio), length=self.i_smooth)
            return sio

        self.sio = self.I(calc_sio)

        def calc_wick_bias():
            range_ = high - low
            upper_wick = high - np.maximum(open_, close)
            lower_wick = np.minimum(open_, close) - low
            wick_bias = np.where(range_ > 0, (lower_wick - upper_wick) / range_, 0.0)
            avg_wick_bias = pta.sma(pd.Series(wick_bias), length=self.i_period)
            return avg_wick_bias

        self.avg_wick_bias = self.I(calc_wick_bias)

        def calc_sqz_count():
            sqz_count = np.zeros(len(close))
            for i in range(len(close)):
                if i == 0:
                    sqz_count[i] = 0
                else:
                    if self.sio[i] < self.i_sqzTh:
                        sqz_count[i] = sqz_count[i - 1] + 1
                    elif self.sio[i] > 0:
                        sqz_count[i] = 0
                    else:
                        sqz_count[i] = sqz_count[i - 1]
            return pd.Series(sqz_count)

        self.sqz_count = self.I(calc_sqz_count)

    def next(self):
        if len(self.data) < 2:
            return

        sio_current = self.sio[-1]
        sio_prev = self.sio[-2]
        sqz_count_prev = self.sqz_count[-2] if len(self.sqz_count) > 1 else 0
        avg_wick_bias = self.avg_wick_bias[-1]

        was_squeeze = sqz_count_prev >= self.i_sqzMin
        impulse_fired = sio_prev <= self.i_impTh and sio_current > self.i_impTh
        bull_signal = was_squeeze and impulse_fired and avg_wick_bias > 0
        bear_signal = was_squeeze and impulse_fired and avg_wick_bias <= 0

        if bull_signal and not self.position:
            self.buy()
        elif bear_signal and self.position:
            self.sell()

        if self.position and sio_current < self.i_sqzTh:
            self.sell()


