import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sd_length = 20
    regime_lookback = 100
    low_pct = 33
    high_pct = 67

    def init(self):
        close = pd.Series(self.data.Close)
        
        def calc_stdev(src, length, use_sample=False):
            result = []
            src_array = src.values if isinstance(src, pd.Series) else src
            
            for i in range(len(src_array)):
                if i < length - 1:
                    result.append(np.nan)
                else:
                    window = src_array[i - length + 1:i + 1]
                    n = float(length)
                    sum_x = np.sum(window)
                    sum_x2 = np.sum(window ** 2)
                    ssd = sum_x2 - (sum_x * sum_x) / n
                    
                    if use_sample:
                        variance = ssd / (n - 1.0)
                    else:
                        variance = ssd / n
                    
                    stdev_val = np.sqrt(max(variance, 0.0))
                    result.append(stdev_val)
            
            return pd.Series(result, index=src.index)
        
        def calc_percentile_boundary(stdev_series, lookback, percentile):
            result = []
            stdev_array = stdev_series.values
            
            for i in range(len(stdev_array)):
                if i < lookback - 1:
                    result.append(np.nan)
                else:
                    window = stdev_array[i - lookback + 1:i + 1]
                    boundary = np.nanpercentile(window, percentile)
                    result.append(boundary)
            
            return pd.Series(result, index=stdev_series.index)
        
        self.stdev = self.I(calc_stdev, close, self.sd_length, False)
        self.low_boundary = self.I(
            calc_percentile_boundary,
            pd.Series(self.stdev),
            self.regime_lookback,
            self.low_pct
        )
        self.high_boundary = self.I(
            calc_percentile_boundary,
            pd.Series(self.stdev),
            self.regime_lookback,
            self.high_pct
        )

    def next(self):
        if len(self.data) < self.regime_lookback + self.sd_length:
            return
        
        current_stdev = self.stdev[-1]
        current_low = self.low_boundary[-1]
        current_high = self.high_boundary[-1]
        
        if np.isnan(current_stdev) or np.isnan(current_low) or np.isnan(current_high):
            return
        
        if current_stdev < current_low:
            regime = "Low"
        elif current_stdev > current_high:
            regime = "High"
        else:
            regime = "Mid"
        
        prev_stdev = self.stdev[-2] if len(self.stdev) > 1 else np.nan
        
        if np.isnan(prev_stdev):
            return
        
        prev_low = self.low_boundary[-2] if len(self.low_boundary) > 1 else np.nan
        prev_high = self.high_boundary[-2] if len(self.high_boundary) > 1 else np.nan
        
        if np.isnan(prev_low) or np.isnan(prev_high):
            return
        
        prev_regime = "Low" if prev_stdev < prev_low else ("High" if prev_stdev > prev_high else "Mid")
        
        if prev_regime != "High" and regime == "High":
            if not self.position:
                self.buy()
        
        elif prev_regime != "Low" and regime == "Low":
            if self.position:
                self.sell()
        
        elif regime == "Mid" and prev_regime == "High":
            if self.position:
                self.sell()


