import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    useEma = True
    emaLen = 100
    useAtrStops = True
    atrLen = 14
    stopATR = 1.2
    targetATR = 2.0
    useFixed = False
    stopDollars = 4.0
    tgtDollars = 8.0
    useTimeExit = True
    oneTradePerDay = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema = self.I(pta.ema, close, length=self.emaLen)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.asia_high = None
        self.asia_low = None
        self.traded_today = False
        self.last_day = None
        self.in_asia_prev = False
        self.in_trade_prev = False

    def next(self):
        current_bar = len(self.data) - 1
        current_date = pd.Timestamp(self.data.index[current_bar]).date()
        
        if self.last_day is None or current_date != self.last_day:
            self.last_day = current_date
            self.traded_today = False
            self.asia_high = None
            self.asia_low = None
        
        in_asia = self._in_asia_session()
        in_trade = self._in_trade_session()
        
        if in_asia:
            if self.asia_high is None:
                self.asia_high = self.data.High[-1]
            else:
                self.asia_high = max(self.asia_high, self.data.High[-1])
            
