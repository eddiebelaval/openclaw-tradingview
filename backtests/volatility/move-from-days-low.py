import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Calculate daily low using rolling window approach
        # Since we're working with intraday data, we'll use a proxy:
        # get the low from the start of each day
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # For daily low, we use the minimum low value seen so far in the backtest
        # In a real scenario with proper daily data, this would be the daily OHLC low
        # Here we approximate by using rolling minimum over a large period
        self.daily_low = self.I(lambda: low.rolling(window=len(low)).min())
        
        # Calculate percentage move from day's low
        self.percent_move = self.I(lambda: np.where(
            self.daily_low > 0,
            (close - self.daily_low) / self.daily_low * 100,
            0.0
        ))

    def next(self):
        # Trading logic based on percentage move from day's low
        # Buy when price moves up 2% or more from day's low (momentum up)
        # Sell when price falls back to near day's low or goes negative
        
        if len(self.percent_move) < 2:
            return
        
        current_move = self.percent_move[-1]
        previous_move = self.percent_move[-2]
        
        # Buy signal: price moving away from day's low (momentum building)
        if current_move > 2.0 and previous_move <= 2.0:
            if not self.position:
                self.buy()
        
        # Sell signal: price falling back to day's low or reversing
        elif current_move < 0.5 and self.position:
            self.position.close()
        
        # Stop loss if price goes significantly negative
        elif current_move < -1.0 and self.position:
            self.position.close()


