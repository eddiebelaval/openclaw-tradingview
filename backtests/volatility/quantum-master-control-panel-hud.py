import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Account & Risk Management
    acc_bal = 2000.0
    risk_pc = 2.5
    
    # Volatility & Asset Settings
    atr_len = 14
    atr_mul = 1.5
    tick_v = 100.0
    
    # RCI Settings
    rci_len = 10
    
    # Macro Alignment
    ema_len = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for dynamic stop loss
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Calculate RCI (Rate of Change Index) - using momentum as proxy
        self.rci = self.I(lambda: pta.roc(close, length=self.rci_len) or pd.Series(0, index=close.index))
        
        # Calculate EMA for macro trend
        self.ema = self.I(pta.ema, close, length=self.ema_len)
        
        # Track entry price and stop loss
        self.entry_price = None
        self.stop_loss = None

    def next(self):
        # Skip if not enough data
        if len(self.data) < max(self.atr_len, self.rci_len, self.ema_len):
            return
        
        # Get current values
        current_atr = self.atr[-1] if self.atr[-1] is not None else 0
        current_rci = self.rci[-1] if self.rci[-1] is not None else 0
        current_ema = self.ema[-1] if self.ema[-1] is not None else self.data.Close[-1]
        current_close = self.data.Close[-1]
        
        # Calculate risk parameters
        dynamic_sl_points = current_atr * self.atr_mul if current_atr > 0 else 0
        risk_usd = self.acc_bal * (self.risk_pc / 100.0)
        lot_size = (risk_usd / (dynamic_sl_points * self.tick_v)) if dynamic_sl_points > 0 else 0.01
        safe_lot = max(0.01, lot_size)
        
        # Entry Logic
        # Buy when: RCI is positive (bullish) and price is above EMA (macro uptrend)
        if not self.position:
            if current_rci > 0 and current_close > current_ema:
                self.entry_price = current_close
                self.stop_loss = self.entry_price - dynamic_sl_points
                self.buy(size=safe_lot)
            
            # Sell when: RCI is negative (bearish) and price is below EMA (macro downtrend)
            elif current_rci < 0 and current_close < current_ema:
                self.entry_price = current_close
                self.stop_loss = self.entry_price + dynamic_sl_points
                self.sell(size=safe_lot)
        
        # Exit Logic - Stop Loss
        else:
            if self.position.is_long:
                # Exit long if price hits stop loss or RCI reverses bearish
                if current_close <= self.stop_loss or current_rci < 0:
                    self.position.close()
            
            elif self.position.is_short:
                # Exit short if price hits stop loss or RCI reverses bullish
                if current_close >= self.stop_loss or current_rci > 0:
                    self.position.close()


