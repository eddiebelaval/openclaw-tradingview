import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 10
    multiplierInput = 3.0
    thresholdInput = 1.0
    alphaInput = 0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.lengthInput)
        
        # Calculate hl2 (source)
        self.src = self.I(lambda: (high + low) / 2)
        
        # Initialize supertrend line and trend tracking
        self.st_line = np.full(len(self.data), np.nan)
        self.trend = np.full(len(self.data), 1, dtype=int)
        self.trend_change = np.full(len(self.data), 0, dtype=int)

    def next(self):
        idx = len(self.data) - 1
        
        if idx < self.lengthInput:
            return
        
        atr_val = self.atr[-1]
        if atr_val is None or np.isnan(atr_val):
            return
        
        src_val = self.src[-1]
        close_val = self.data.Close[-1]
        
        upperBase = src_val + self.multiplierInput * atr_val
        lowerBase = src_val - self.multiplierInput * atr_val
        
        if idx == 0:
            prevLine = lowerBase if self.trend[idx] == 1 else upperBase
        else:
            prevLine = self.st_line[idx - 1]
            if np.isnan(prevLine):
                prevLine = lowerBase if self.trend[idx - 1] == 1 else upperBase
        
        isNoisy = abs(close_val - prevLine) < (atr_val * self.thresholdInput)
        
        current_trend = self.trend[idx - 1] if idx > 0 else 1
        
        if current_trend == 1:
            if isNoisy:
                self.st_line[idx] = prevLine - (atr_val * self.alphaInput)
            else:
                self.st_line[idx] = max(lowerBase, prevLine)
            
            if close_val < self.st_line[idx]:
                current_trend = -1
                self.st_line[idx] = upperBase
        else:
            if isNoisy:
                self.st_line[idx] = prevLine + (atr_val * self.alphaInput)
            else:
                self.st_line[idx] = min(upperBase, prevLine)
            
            if close_val > self.st_line[idx]:
                current_trend = 1
                self.st_line[idx] = lowerBase
        
        prev_trend = self.trend[idx - 1] if idx > 0 else 1
        self.trend[idx] = current_trend
        
        if current_trend != prev_trend:
            self.trend_change[idx] = 1 if current_trend > prev_trend else -1
        
        # Trading logic
        if self.trend_change[idx] > 0:
            if not self.position:
                self.buy()
        elif self.trend_change[idx] < 0:
            if self.position:
                self.position.close()


