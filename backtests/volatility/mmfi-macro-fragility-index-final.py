        # Helper function for z-score
        def zscore(x, length):
            sma = pta.sma(x, length=length)
            stdev = pta.stdev(x, length=length)
            result = pd.Series(index=x.index, dtype=float)
            mask = (stdev != 0) & stdev.notna() & sma.notna()
            result[mask] = (x[mask] - sma[mask]) / stdev[mask]
            return result
        
        # Helper function for z to 0-1
        def z_to_01(z_series):
            result = 0.5 + (z_series * 0.25)
            result = result.clip(0, 1)
            return result
        
