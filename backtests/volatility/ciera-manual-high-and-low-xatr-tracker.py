import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_length = 14
    anchor_low = 0.0
    anchor_high = 0.0
    round_to_2 = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR on chart timeframe
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)

    def next(self):
        if len(self.data) < self.atr_length:
            return
        
        # Get current ATR value
        if self.atr[-1] is None or np.isnan(self.atr[-1]) or self.atr[-1] == 0:
            return
        
        current_atr = self.atr[-1]
        current_close = self.data.Close[-1]
        
        # Calculate xATR from low if anchor_low is set
        use_low = self.anchor_low != 0.0
        if use_low:
            x_from_low = (current_close - self.anchor_low) / current_atr
        else:
            x_from_low = None
        
        # Calculate xATR from high if anchor_high is set
        use_high = self.anchor_high != 0.0
        if use_high:
            x_from_high = (self.anchor_high - current_close) / current_atr
        else:
            x_from_high = None
        
        # Trading logic based on xATR levels
        # Buy when price is near anchor_low (xATR approaches 0 from above)
        # Sell when price is near anchor_high (xATR approaches 0 from above)
        
        if use_low and x_from_low is not None:
            if 0 < x_from_low <= 0.5 and not self.position:
                self.buy()
            elif x_from_low < 0 and self.position:
                self.sell()
        
        if use_high and x_from_high is not None:
            if 0 < x_from_high <= 0.5 and self.position:
                self.sell()
            elif x_from_high < 0 and not self.position:
                self.buy()


