import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Bollinger Band parameters
    bb_length = 20
    bb_mult = 2.0
    
    # Volatility Filter parameters
    vol_window = 50
    vol_threshold_lo = 0.80
    vol_threshold_hi = 2.00
    atr_len = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        self.basis = self.I(pta.sma, close, length=self.bb_length)
        
        # Standard deviation calculation
        def calc_dev(src):
            dev = pta.stdev(src, length=self.bb_length)
            if dev is not None:
                return dev * self.bb_mult
            return pd.Series(0, index=src.index)
        
        self.dev = self.I(calc_dev, close)
        
        self.upper_band = self.I(lambda: self.basis + self.dev if self.basis is not None and self.dev is not None else pd.Series(0, index=close.index))
        self.lower_band = self.I(lambda: self.basis - self.dev if self.basis is not None and self.dev is not None else pd.Series(0, index=close.index))
        
        # ATR for volatility
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Historical volatility (SMA of ATR)
        def calc_hist_vol(src):
            atr_result = pta.atr(high, low, close, length=self.atr_len)
            if atr_result is not None:
                return pta.sma(atr_result, length=self.vol_window)
            return pd.Series(0, index=src.index)
        
        self.hist_vol = self.I(calc_hist_vol, close)
        
        # Median volatility using percentile
        def calc_median_vol(src):
            hist_vol_result = self.hist_vol
            if hist_vol_result is not None and len(hist_vol_result) > 0:
                recent_vol = hist_vol_result.iloc[-self.vol_window:] if len(hist_vol_result) >= self.vol_window else hist_vol_result
                if len(recent_vol) > 0:
                    median = recent_vol.median()
                    return pd.Series(median, index=src.index)
            return pd.Series(0, index=src.index)
        
        self.median_vol = self.I(calc_median_vol, close)

    def next(self):
        if len(self.data) < self.bb_length + self.vol_window:
            return
        
        # Get current values
        current_close = self.data.Close[-1]
        current_upper = self.upper_band[-1]
        current_lower = self.lower_band[-1]
        current_basis = self.basis[-1]
        current_atr = self.atr[-1] if self.atr[-1] is not None and not np.isnan(self.atr[-1]) else 0
        current_median_vol = self.median_vol[-1] if self.median_vol[-1] is not None and not np.isnan(self.median_vol[-1]) else 1
        
        # Volatility filter
        vol_ok = (current_atr > current_median_vol * self.vol_threshold_lo) and \
                 (current_atr < current_median_vol * self.vol_threshold_hi)
        
        # Entry signals
        long_entry = crossover(self.data.Close, self.upper_band) and vol_ok
        short_entry = crossover(self.lower_band, self.data.Close) and vol_ok
        
        # Exit signals
        exit_long = self.position and self.position.is_long and crossover(self.basis, self.data.Close)
        exit_short = self.position and self.position.is_short and crossover(self.data.Close, self.basis)
        
        # Execute trades
        if exit_long:
            self.position.close()
        elif exit_short:
            self.position.close()
        
        if long_entry and not self.position:
            self.buy()
        elif short_entry and not self.position:
            self.sell()


