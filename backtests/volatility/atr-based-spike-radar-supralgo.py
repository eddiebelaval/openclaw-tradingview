import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # ATR Parameters
    atr_smooth = "RMA"
    atr_len = 14
    min_vol = 0.5
    ma_smooth = "SMA"
    ma_length = 200
    high_vol_only = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate True Range
        def calc_tr():
            tr1 = high - low
            tr2 = np.abs(high - close.shift(1))
            tr3 = np.abs(low - close.shift(1))
            tr = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
            return tr
        
        tr = calc_tr()
        
        # Calculate ATR with selected smoothing
        def calc_atr():
            if self.atr_smooth == "EMA":
                return pta.ema(tr, length=self.atr_len)
            elif self.atr_smooth == "RMA":
                return pta.rma(tr, length=self.atr_len)
            elif self.atr_smooth == "SMA":
                return pta.sma(tr, length=self.atr_len)
            else:  # WMA
                return pta.wma(tr, length=self.atr_len)
        
        self.atr = self.I(calc_atr)
        
        # Calculate MA of ATR with selected smoothing
        def calc_ma():
            if self.ma_smooth == "EMA":
                return pta.ema(self.atr, length=self.ma_length)
            elif self.ma_smooth == "RMA":
                return pta.rma(self.atr, length=self.ma_length)
            elif self.ma_smooth == "SMA":
                return pta.sma(self.atr, length=self.ma_length)
            else:  # WMA
                return pta.wma(self.atr, length=self.ma_length)
        
        self.ma = self.I(calc_ma)
        
        # Track previous ATR for delta calculation
        self.atr_prev = 0
        self.in_spike = False

    def next(self):
        # Get current values
        if len(self.data) < 2:
            return
        
        current_atr = self.atr[-1]
        current_ma = self.ma[-1]
        
        if pd.isna(current_atr) or pd.isna(current_ma):
            return
        
        # Calculate ATR delta
        atr_delta = current_atr - self.atr_prev
        
        # Check for volatility spike
        volatility_spike = (current_atr > self.atr_prev) and (atr_delta >= self.min_vol)
        
        # Check ATR position relative to MA
        atr_above_ma = current_atr > current_ma
        
        # Determine if spike meets criteria
        signal_triggered = False
        if self.high_vol_only:
            signal_triggered = volatility_spike and atr_above_ma
        else:
            signal_triggered = volatility_spike
        
        # Trading logic based on spike detection
        if signal_triggered:
            if not self.position:
                self.buy()
            self.in_spike = True
        else:
            if self.position and self.in_spike:
                self.sell()
                self.in_spike = False
        
        # Update previous ATR
        self.atr_prev = current_atr


