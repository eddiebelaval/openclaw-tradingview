    def next(self):
        # This is a complex multi-asset indicator that requires external data feeds
        # Since backtesting.py works with a single instrument, we'll use price action
        # to generate trading signals based on volatility and trend
        
        close = pd.Series(self.data.Close)
        
        # Calculate basic indicators as proxy for market stress
        rsi = pta.rsi(close, length=14)
        atr = pta.atr(self.data.High, self.data.Low, close, length=14)
        
        if len(close) < 14:
            return
        
        current_rsi = rsi.iloc[-1] if rsi is not None and len(rsi) > 0 else 50
        current_atr = atr.iloc[-1] if atr is not None and len(atr) > 0 else 0
        prev_atr = atr.iloc[-2] if atr is not None and len(atr) > 1 else 0
        
        # Volatility expansion (stress indicator)
        vol_expansion = current_atr > prev_atr * 1.2 if prev_atr > 0 else False
        
        # Entry logic: when RSI shows extreme conditions + volatility
        # Sell (short) when RSI is overbought and volatility expands (stress/crash risk)
        if current_rsi > 70 and vol_expansion and not self.position:
            self.sell()
        
        # Cover short when RSI shows recovery
        elif current_rsi < 30 and self.position:
            self.position.close()
        
        # Buy (long) when RSI is oversold with volatility (panic selling)
        elif current_rsi < 30 and vol_expansion and not self.position:
            self.buy()
        
        # Exit long on recovery
        elif current_rsi > 70 and self.position:
            self.position.close()


