import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    bbLength = 20
    bbMult = 2.0
    atrLength = 14
    lookback = 100
    explosionThreshold = 5.0
    criticalLevel = 90

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        self.basis = self.I(pta.sma, close, length=self.bbLength)
        bb_result = self.I(pta.bbands, close, length=self.bbLength, std=self.bbMult)
        self.upperBB = self.I(lambda: bb_result[f'BBU_{self.bbLength}_{self.bbMult}'] if bb_result is not None else pd.Series(0, index=close.index))
        self.lowerBB = self.I(lambda: bb_result[f'BBL_{self.bbLength}_{self.bbMult}'] if bb_result is not None else pd.Series(0, index=close.index))
        
        # BB Width calculation
        self.bbWidth = self.I(lambda: (self.upperBB[-1] - self.lowerBB[-1]) / self.basis[-1] * 100 if self.basis[-1] != 0 else 0)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        self.atrPercent = self.I(lambda: self.atr[-1] / close.iloc[-1] * 100 if close.iloc[-1] != 0 else 0)
        
        # Average metrics
        self.bbWidth_series = self.I(lambda: pd.Series(
            [(self.data.High[max(0, i-self.bbLength+1):i+1].max() - self.data.Low[max(0, i-self.bbLength+1):i+1].min()) / 
             self.data.Close[i] * 100 if self.data.Close[i] != 0 else 0 
             for i in range(len(self.data.Close))],
            index=close.index
        ))
        
        self.avgBBWidth = self.I(pta.sma, self.bbWidth_series, length=self.lookback)
        
        # EMA for direction bias
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema50 = self.I(pta.ema, close, length=50)
        
        # Compression score tracking
        self.compressionScore = self.I(self._calc_compression, close, high, low)
        
        # State tracking
        self.wasInCritical = False
        self.squeezeStartPrice = 0
        self.barsInSqueeze = 0
        self.squeeze_moves = []
        self.squeeze_times = []

    def _calc_compression(self, close, high, low):
        result = []
        for i in range(len(close)):
            if i < max(self.bbLength, self.atrLength, self.lookback):
                result.append(0)
                continue
            
            # BB Width
            basis_val = close[max(0, i-self.bbLength+1):i+1].mean()
            dev = close[max(0, i-self.bbLength+1):i+1].std() * self.bbMult
            bbWidth = (2 * dev) / basis_val * 100 if basis_val != 0 else 0
            
            # ATR Percent
            atr_val = self._calc_atr(high, low, close, i, self.atrLength)
            atrPercent = atr_val / close[i] * 100 if close[i] != 0 else 0
            
            # Averages
            avgBBWidth = close[max(0, i-self.lookback+1):i+1].std() * 2 / basis_val * 100 if basis_val != 0 else 1
            avgATRPercent = atrPercent
            
            # Compression
            bbComp = (1 - bbWidth / avgBBWidth) * 100 if avgBBWidth > 0 else 0
            atrComp = (1 - atrPercent / avgATRPercent) * 100 if avgATRPercent > 0 else 0
            
            comp = max(0, min(100, (bbComp + atrComp) / 2))
            result.append(comp)
        
        return pd.Series(result, index=close.index)

    def _calc_atr(self, high, low, close, idx, length):
        if idx < length:
            return 0
        tr_values = []
        for j in range(max(0, idx - length + 1), idx + 1):
            tr = max(high[j] - low[j], 
                    abs(high[j] - close[j-1]) if j > 0 else 0,
                    abs(low[j] - close[j-1]) if j > 0 else 0)
            tr_values.append(tr)
        return np.mean(tr_values) if tr_values else 0

    def next(self):
        close = self.data.Close[-1]
        
        # Current compression state
        compression = self.compressionScore[-1]
        isCritical = compression >= self.criticalLevel
        
        # Direction bias
        isBullishTrend = close > self.ema20[-1] and self.ema20[-1] > self.ema50[-1]
        isBearishTrend = close < self.ema20[-1] and self.ema20[-1] < self.ema50[-1]
        
        # Squeeze tracking
        if isCritical and not self.wasInCritical:
            self.squeezeStartPrice = close
            self.barsInSqueeze = 0
            self.wasInCritical = True
        
        if isCritical:
            self.barsInSqueeze += 1
        
        # Squeeze release and breakout
        if self.wasInCritical and not isCritical:
            movePercent = abs((close - self.squeezeStartPrice) / self.squeezeStartPrice * 100)
            self.squeeze_moves.append(movePercent)
            self.squeeze_times.append(self.barsInSqueeze)
            self.wasInCritical = False
            
            # Trading signal on breakout
            if movePercent >= self.explosionThreshold:
                if isBullishTrend:
                    if not self.position:
                        self.buy()
                elif isBearishTrend:
                    if self.position:
                        self.position.close()
        
        # Exit conditions
        if self.position:
            if isBearishTrend:
                self.position.close()


