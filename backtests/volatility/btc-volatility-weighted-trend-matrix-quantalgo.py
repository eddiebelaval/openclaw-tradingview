import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    volLen = 40
    volFactor = 1.1
    fastLen = 21
    slowLen = 55
    atrLen = 14
    atrFilter = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume Confirmation
        self.avgVol = self.I(pta.sma, volume, length=self.volLen)
        self.strongVol = self.I(lambda: volume > self.avgVol * self.volFactor)
        
        # Volatility Filter
        self.atrValue = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.atrMA = self.I(pta.sma, self.atrValue, length=self.atrLen)
        self.highVolatility = self.I(lambda: self.atrValue > self.atrMA * self.atrFilter)
        
        # Trend Engine
        self.fastEMA = self.I(pta.ema, close, length=self.fastLen)
        self.slowEMA = self.I(pta.ema, close, length=self.slowLen)
        
        # Trend signals
        self.bullTrend = self.I(lambda: (self.fastEMA > self.slowEMA) & self.strongVol & self.highVolatility)
        self.bearTrend = self.I(lambda: (self.fastEMA < self.slowEMA) & self.strongVol & self.highVolatility)
        
        # Trend state tracking
        self.trendState = 0
        self.prev_trendState = 0

    def next(self):
        if len(self.data) < max(self.fastLen, self.slowLen, self.atrLen) + 1:
            return
        
        # Update trend state
        self.prev_trendState = self.trendState
        
        if self.bullTrend[-1]:
            self.trendState = 1
        elif self.bearTrend[-1]:
            self.trendState = -1
        
        # Generate signals on state change
        longSignal = self.trendState == 1 and self.prev_trendState != 1
        shortSignal = self.trendState == -1 and self.prev_trendState != -1
        
        # Trading logic
        if longSignal and not self.position:
            self.buy()
