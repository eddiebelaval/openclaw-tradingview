import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 20
    volMult = 1.5
    bodyRatio = 0.35
    rangePerc = 0.6
    hlLookback = 5
    scoreSmooth = 3

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.lookback)

        # Calculate average volume
        avgVol = self.I(pta.sma, volume, length=self.lookback)

        # Calculate candle metrics
        candleRange = self.I(lambda: high - low)
        bodySize = self.I(lambda: np.abs(close - open_))
        bodyToRange = self.I(lambda: np.where(candleRange > 0, bodySize / candleRange, 1.0))

        # Component conditions
        smallBody = self.I(lambda: (bodyToRange < self.bodyRatio).astype(int))
        highVol = self.I(lambda: (volume > avgVol * self.volMult).astype(int))
        tightRange = self.I(lambda: (candleRange < atr * self.rangePerc).astype(int))

        # Higher lows check
        lowest_low = self.I(lambda: low.rolling(self.hlLookback).min())
        isHigherLow = self.I(lambda: low > lowest_low.shift(1))

        # Score components
        volStrength = self.I(lambda: np.minimum(volume / (avgVol * self.volMult) * 30, 30))
        bodyScore = self.I(lambda: np.minimum(np.maximum((self.bodyRatio - bodyToRange) / self.bodyRatio * 20, 0), 20))
        rangeScore = self.I(lambda: np.minimum(np.maximum((atr * self.rangePerc - candleRange) / (atr * self.rangePerc) * 20, 0), 20))
        hlScore = self.I(lambda: np.where(isHigherLow, 15, 0))

        # Base condition
        baseCondition = self.I(lambda: np.where((smallBody.astype(bool)) & (highVol.astype(bool)) & (tightRange.astype(bool)), 15, 0))

        # Raw score
        rawScore = self.I(lambda: baseCondition + volStrength + np.maximum(bodyScore, 0) + np.maximum(rangeScore, 0) + hlScore)

        # Smoothed absorption score
        absScore = self.I(pta.sma, rawScore, length=self.scoreSmooth)
        absScoreNorm = self.I(lambda: np.minimum(absScore, 100))

        # Momentum component
        sma3 = self.I(pta.sma, absScoreNorm, length=3)
        sma8 = self.I(pta.sma, absScoreNorm, length=8)
        momentum = self.I(lambda: sma3 - sma8)

        # Final score with momentum
        self.scoreWithMom = self.I(lambda: np.minimum(absScoreNorm + np.maximum(momentum * 0.5, 0), 100))

    def next(self):
        if len(self.data) < 2:
            return

        current_score = self.scoreWithMom[-1]
        prev_score = self.scoreWithMom[-2]

        # Buy when score crosses above 40 (Medium threshold)
        if prev_score <= 40 < current_score and not self.position:
            self.buy()

        # Sell when score crosses below 40
        if prev_score >= 40 > current_score and self.position:
            self.sell()

        # Additional sell signal: score drops below 20
        if current_score < 20 and self.position:
            self.sell()


