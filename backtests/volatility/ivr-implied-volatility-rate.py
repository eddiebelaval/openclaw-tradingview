import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 52
    lvl = 10
    smooth_period = 21

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate IVR using percentrank
        def calc_ivr():
            ivr = pta.percentrank(close, length=self.len)
            if ivr is None:
                return pd.Series(50, index=close.index)
            ivr = ivr.fillna(50)
            ivr = np.maximum(0, np.minimum(100, ivr))
            return ivr
        
        self.ivr = self.I(calc_ivr)
        
        # Calculate smooth line (EMA of IVR)
        def calc_smooth():
            ivr_vals = calc_ivr()
            smooth = pta.ema(ivr_vals, length=self.smooth_period)
            if smooth is None:
                return pd.Series(50, index=close.index)
            return smooth.fillna(50)
        
        self.smooth_line = self.I(calc_smooth)

    def next(self):
        # Buy signal: IVR crosses above the level (from below)
        if len(self.data) > 1:
            if self.ivr[-2] < self.lvl and self.ivr[-1] >= self.lvl:
                if not self.position:
                    self.buy()
        
        # Sell signal: IVR crosses below the level (from above)
        if len(self.data) > 1:
            if self.ivr[-2] > self.lvl and self.ivr[-1] <= self.lvl:
                if self.position:
                    self.sell()


