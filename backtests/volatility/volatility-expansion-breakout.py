import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    htf = "60"
    emaLen = 200
    atrLen = 14
    atrMult = 2.0
    rangeLen = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # HTF EMA (using current timeframe as proxy since we can't request HTF data)
        self.htfEMA = self.I(pta.ema, close, length=self.emaLen)
        
        # Range highs and lows
        self.rangeHigh = self.I(lambda: high.rolling(self.rangeLen).max())
        self.rangeLow = self.I(lambda: low.rolling(self.rangeLen).min())
        
        # Track previous values
        self.prev_atr = None
        self.prev_rangeHigh = None
        self.prev_rangeLow = None

    def next(self):
        if len(self.data) < self.rangeLen + 1:
            return
        
        # Current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_atr = self.atr[-1]
        current_htfEMA = self.htfEMA[-1]
        current_rangeHigh = self.rangeHigh[-1]
        current_rangeLow = self.rangeLow[-1]
        
        # Previous values
        if len(self.data) >= 2:
            prev_atr = self.atr[-2]
            prev_rangeHigh = self.rangeHigh[-2]
            prev_rangeLow = self.rangeLow[-2]
        else:
            prev_atr = current_atr
            prev_rangeHigh = current_rangeHigh
            prev_rangeLow = current_rangeLow
        
        # Conditions
        bullBias = current_close > current_htfEMA
        bearBias = current_close < current_htfEMA
        atrRising = current_atr > prev_atr
        
        longCondition = bullBias and atrRising and current_close > prev_rangeHigh
        shortCondition = bearBias and atrRising and current_close < prev_rangeLow
        
        # Entry logic
        if longCondition and not self.position:
            self.buy()
        
        if shortCondition and not self.position:
            self.sell()
        
        # Exit logic with trailing stop
        if self.position:
            if self.position.is_long:
                longTrail = current_close - current_atr * self.atrMult
                if current_close <= longTrail:
                    self.position.close()
            
            elif self.position.is_short:
                shortTrail = current_close + current_atr * self.atrMult
                if current_close >= shortTrail:
                    self.position.close()


