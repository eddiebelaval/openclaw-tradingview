import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    oversoldLevel = 30
    overboughtLevel = 70

    def init(self):
        close = pd.Series(self.data.Close)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)

    def next(self):
        if len(self.data) < self.rsiLength + 1:
            return

        current_rsi = self.rsi[-1]
        
        if current_rsi is None or np.isnan(current_rsi):
            return

        if current_rsi < self.oversoldLevel:
            if not self.position:
                self.buy()
        elif current_rsi > self.overboughtLevel:
            if self.position:
                self.sell()
        elif self.oversoldLevel <= current_rsi <= self.overboughtLevel:
            if self.position:
                self.sell()


if __name__ == "__main__":
    from backtesting.test import GOOG

    bt = Backtest(GOOG, TvStrategy, cash=10000, commission=.002)
