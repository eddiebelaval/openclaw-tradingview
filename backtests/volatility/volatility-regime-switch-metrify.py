import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    corelen = 21
    reglen = 55
    sensitivity = 2.0
    cfm = 2
    volsep = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)

        def clamp(v, lo, hi):
            return np.maximum(lo, np.minimum(hi, v))

        def inv_var(x, length):
            var = x.rolling(window=length).var()
            return 1.0 / np.maximum(var.fillna(0.0), 1e-10)

        def z_score(x, length):
            m = x.rolling(window=length).mean()
            s = x.rolling(window=length).std()
            result = np.where(s == 0, 0.0, (x - m) / s)
            return pd.Series(result, index=x.index)

        def squash(x):
            return 0.6366197724 * np.arctan(x)

        def log_returns(c):
            return np.log(c / c.shift(1))

        def atr_custom(h, l, c, length):
            tr = np.maximum(h - l, np.maximum(np.abs(h - c.shift(1)), np.abs(l - c.shift(1))))
            return tr.rolling(window=length).mean()

        def rma(x, length):
            alpha = 1.0 / length
            return x.ewm(alpha=alpha, adjust=False).mean()

        # Core Engine
        ret = log_returns(close)
        atrf = atr_custom(high, low, close, self.corelen)
        slowlen = max(self.corelen + 1, int(round(self.corelen * self.volsep)))
        atrs = atr_custom(high, low, close, slowlen)

        hlc3 = (high + low + close) / 3.0
        sigma = ret.rolling(window=self.corelen * 2).std() * close

        watrfr = inv_var(atrf, self.corelen)
        watrsr = inv_var(atrs, self.corelen)
        wsigr = inv_var(sigma, self.corelen)
        wvsum = watrfr + watrsr + wsigr
        watrf = watrfr / wvsum
        watrs = watrsr / wvsum
        wsig = wsigr / wvsum

        volraw = atrf * watrf + atrs * watrs + sigma * wsig
        volc = np.maximum(volraw, 1e-6)

        abstep = np.abs(close - close.shift(1))
        erden = abstep.rolling(window=self.reglen).mean() * self.reglen
        er = np.where(erden == 0, 0.0, np.abs(close - close.shift(self.reglen)) / erden)

        adxlen = max(7, int(round(self.corelen * 0.8)))
        upmv = high - high.shift(1)
        dnmv = low.shift(1) - low
        pdm = np.where((upmv > dnmv) & (upmv > 0), upmv, 0.0)
        mdm = np.where((dnmv > upmv) & (dnmv > 0), dnmv, 0.0)
        pclose = close.shift(1)
        tr = np.maximum(high - low, np.maximum(np.abs(high - pclose), np.abs(low - pclose)))
        trr = rma(tr, adxlen)
        pdi = np.where(trr == 0, 0.0, 100.0 * rma(pdm, adxlen) / trr)
        mdi = np.where(trr == 0, 0.0, 100.0 * rma(mdm, adxlen) / trr)
        disum = pdi + mdi
        dx = np.where(disum == 0, 0.0, 100.0 * np.abs(pdi - mdi) / disum)
        adxraw = rma(dx, adxlen)
        adxn = clamp(adxraw / 40.0, 0.0, 1.0)

        volrat = clamp(atrf / np.maximum(atrs, 1e-6), 0.5, 1.8)
        volratn = clamp((volrat - 0.5) / 1.3, 0.0, 1.0)

        werr = inv_var(pd.Series(er, index=close.index), self.reglen)
        wadxr = inv_var(adxn, self.reglen)
        wvrr = inv_var(volratn, self.reglen)
        wrsum = werr + wadxr + wvrr
        wer = werr / wrsum
        wadx = wadxr / wrsum
        wvr = wvrr / wrsum

        trreg = clamp(pd.Series(er, index=close.index) * wer + adxn * wadx + volratn * wvr, 0.0, 1.0)
        nsreg = 1.0 - trreg

        emaf = hlc3.ewm(span=self.corelen, adjust=False).mean()
        emas = hlc3.ewm(span=self.corelen * 3, adjust=False).mean()
        anchor = emas + (emaf - emas) * trreg

        bmult = (1.0 + nsreg * 1.35) / self.sensitivity
        bdist = volc * bmult
        upband = anchor + bdist
        lowband = anchor - bdist

        # Intra-Bar Price Action Bias
        rng = np.maximum(high - low, 1e-6)
        bodyn = (close - open_) / rng
        clv = ((close - low) - (high - close)) / rng

        clvz = z_score(clv, self.corelen)
        bodyz = z_score(pd.Series(bodyn, index=close.index), self.corelen)
        cbiasr = (clvz + bodyz) * 0.5
        cbias = cbiasr.ewm(span=3, adjust=False).mean()

        tbias = (emaf - emas) / volc
        tbiasz = z_score(tbias, self.reglen)
        tbiasn = squash(tbiasz)

        dbull = (close - upband) / volc
        dbear = (lowband - close) / volc

        dbullp = np.maximum(dbull, 0.0)
        dbearp = np.maximum(dbear, 0.0)

        biasmix = (cbias + tbiasn) * 0.5
        convr = biasmix.ewm(span=2, adjust=False).mean()
        conviction = convr.ewm(span=3, adjust=False).mean()
        convmag = np.abs(conviction)

        regmid = trreg.rolling(window=self.reglen).mean()
        noisemid = nsreg.rolling(window=self.reglen).mean()

        # Store for next()
        self.trail = self.I(lambda: pd.Series(np.where(trreg >= 0.5, lowband, upband), index=close.index))
        self.conviction = self.I(lambda: conviction)
        self.trreg = self.I(lambda: trreg)
        self.nsreg = self.I(lambda: nsreg)
        self.upband = self.I(lambda: upband)
        self.lowband = self.I(lambda: lowband)
        self.close_series = self.I(lambda: close)
        self.bdist = self.I(lambda: bdist)
        self.volc = self.I(lambda: volc)
        self.regmid = self.I(lambda: regmid)
        self.noisemid = self.I(lambda: noisemid)

    def next(self):
        if len(self.data) < max(self.corelen * 3, self.reglen + 10):
            return

        close_val = self.data.Close[-1]
        trail_val = self.trail[-1]
        conviction_val = self.conviction[-1]
        trreg_val = self.trreg[-1]
        nsreg_val = self.nsreg[-1]
        upband_val = self.upband[-1]
        lowband_val = self.lowband[-1]
        bdist_val = self.bdist[-1]
        regmid_val = self.regmid[-1]
        noisemid_val = self.noisemid[-1]

        if np.isnan(trail_val) or np.isnan(conviction_val):
            return

        convmag_val = np.abs(conviction_val)
        convavg = self.conviction.rolling(window=self.reglen).mean()[-1] if len(self.conviction) >= self.reglen else convmag_val
        convdev = self.conviction.rolling(window=self.reglen).std()[-1] if len(self.conviction) >= self.reglen else 0.1
        trigger = max(convavg + convdev if not np.isnan(convavg) and not np.isnan(convdev) else 0.1, 0.10)

        holds = max(2, int(round(self.corelen * (0.16 + nsreg_val * 0.18))))
        effcfm = self.cfm + (1 if nsreg_val > (noisemid_val if not np.isnan(noisemid_val) else nsreg_val) else 0) + (1 if trreg_val < (regmid_val if not np.isnan(regmid_val) else trreg_val) else 0)

        dispzneed = nsreg_val * 0.50

        bulltrig = close_val > upband_val and conviction_val > trigger
        beartrig = close_val < lowband_val and conviction_val < -trigger

        if self.position:
            if self.position.is_long:
                if beartrig:
                    self.sell()
            else:
                if bulltrig:
                    self.buy()
        else:
            if bulltrig:
                self.buy()
            elif beartrig:
                self.sell()