import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 252
    annual_threshold = 10.0
    smoothing = 5

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate log returns
        returns = np.log(close / close.shift(1))
        
        # Convert annual threshold to daily threshold
        bars_per_year = 252.0
        daily_threshold = np.log(1 + self.annual_threshold / 100) / bars_per_year
        
        # Calculate Omega ratio
        def calculate_omega(returns_series, lookback_period, threshold):
            omega_values = []
            for i in range(len(returns_series)):
                if i < lookback_period:
                    omega_values.append(np.nan)
                else:
                    window = returns_series.iloc[i-lookback_period:i]
                    total_gains = 0.0
                    total_losses = 0.0
                    
                    for ret in window:
                        if pd.notna(ret):
                            if ret > threshold:
                                total_gains += (ret - threshold)
                            else:
                                total_losses += abs(ret - threshold)
                    
                    if total_losses > 0:
                        omega_values.append(total_gains / total_losses)
                    else:
                        omega_values.append(np.nan)
            
            return pd.Series(omega_values, index=returns_series.index)
        
        raw_omega = self.I(calculate_omega, returns, self.lookback, daily_threshold)
        
        # Apply smoothing
        self.omega = self.I(pta.sma, raw_omega, length=self.smoothing)

    def next(self):
        if len(self.data) < self.lookback + self.smoothing:
            return
        
        if pd.isna(self.omega[-1]):
            return
        
        # Buy when Omega crosses above 1.0 (breakeven)
        if len(self.omega) > 1 and not pd.isna(self.omega[-2]):
            if self.omega[-2] <= 1.0 and self.omega[-1] > 1.0:
                if not self.position:
                    self.buy()
            
