import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR calculation for volatility filtering
        self.atr = self.I(pta.atr, high, low, close, length=3)
        
        # Bollinger Bands for signal generation (200-period EMA + std dev)
        bb_result = self.I(
            lambda: pta.bbands(close, length=200, std=0.5) 
            if pta.bbands(close, length=200, std=0.5) is not None 
            else pd.DataFrame(index=close.index)
        )
        
        # Store BB components if available
        if isinstance(bb_result, pd.DataFrame) and len(bb_result.columns) > 0:
            self.bb_lower = bb_result.iloc[:, 0] if bb_result.shape[1] > 0 else None
            self.bb_basis = bb_result.iloc[:, 1] if bb_result.shape[1] > 1 else None
            self.bb_upper = bb_result.iloc[:, 2] if bb_result.shape[1] > 2 else None
        else:
            self.bb_lower = None
            self.bb_basis = None
            self.bb_upper = None
        
        # Simple moving averages for trend confirmation
        self.sma_fast = self.I(pta.sma, close, length=10)
        self.sma_slow = self.I(pta.sma, close, length=50)
        
        # Track ORB range state
        self.orb_high = None
        self.orb_low = None
        self.orb_range_size = None
        self.range_start_idx = None
        self.range_end_idx = None
        self.breakout_detected = False
        self.in_position = False

    def next(self):
        # Skip if insufficient data
        if len(self) < 50:
            return
        
        current_price = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Get current ATR for volatility check
        current_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else None
        
        # ORB Range Definition: 15:30-15:45 (simulated as first 15 bars of session)
        # For backtest purposes, define a rolling 15-bar window as ORB period
        if self.range_start_idx is None and len(self) >= 15:
            # Initialize first range
            self.range_start_idx = len(self) - 15
            self.range_end_idx = len(self)
            
        # Update ORB range during the range period
        if (self.range_start_idx is not None and 
            self.range_start_idx <= len(self) <= self.range_end_idx and 
            not self.breakout_detected):
            
            if self.orb_high is None:
                self.orb_high = current_high
                self.orb_low = current_low
            else:
                self.orb_high = max(self.orb_high, current_high)
                self.orb_low = min(self.orb_low, current_low)
            
            self.orb_range_size = self.orb_high - self.orb_low
        
        # Post-ORB: Check for breakout
        if (self.range_end_idx is not None and 
            len(self) > self.range_end_idx and 
            not self.breakout_detected and 
            self.orb_high is not None and 
            self.orb_low is not None):
            
            # Volatility filter: ORB range should be between 15-60% of previous day ATR
            if current_atr is not None and current_atr > 0:
                vol_ratio = (self.orb_range_size / current_atr) * 100
                
                if vol_ratio < 15 or vol_ratio > 60:
                    return  # No trade due to volatility
            
            # Check for bullish breakout
            if current_price > self.orb_high:
                # Confirm with BB and trend
                bb_bullish = (self.bb_upper is not None and 
                             not np.isnan(self.bb_upper[-1]) and 
                             current_price > self.bb_upper[-1])
                
                trend_bullish = (self.sma_fast is not None and 
                                self.sma_slow is not None and
                                not np.isnan(self.sma_fast[-1]) and 
                                not np.isnan(self.sma_slow[-1]) and
                                self.sma_fast[-1] > self.sma_slow[-1])
                
                if bb_bullish or trend_bullish:
                    if not self.in_position:
                        self.buy()
                        self.in_position = True
                        self.breakout_detected = True
            
            # Check for bearish breakout
            elif current_price < self.orb_low:
                # Confirm with BB and trend
                bb_bearish = (self.bb_lower is not None and 
                             not np.isnan(self.bb_lower[-1]) and 
                             current_price < self.bb_lower[-1])
                
                trend_bearish = (self.sma_fast is not None and 
                                self.sma_slow is not None and
                                not np.isnan(self.sma_fast[-1]) and 
                                not np.isnan(self.sma_slow[-1]) and
                                self.sma_fast[-1] < self.sma_slow[-1])
                
                if bb_bearish or trend_bearish:
                    if not self.in_position:
                        self.sell()
                        self.in_position = True
                        self.breakout_detected = True
        
        # Exit logic: Close at end of day or on reversal
        if self.in_position:
            # Exit on reversal signal
            if self.position.is_long:
                if current_price < self.orb_low or crossover(self.sma_slow, self.sma_fast):
                    self.position.close()
                    self.in_position = False
            
            elif self.position.is_short:
                if current_price > self.orb_high or crossover(self.sma_fast, self.sma_slow):
                    self.position.close()
                    self.in_position = False
        
        # Reset daily
        if len(self) % 1440 == 0:  # Assuming 1-minute bars, reset daily
            self.orb_high = None
            self.orb_low = None
            self.orb_range_size = None
            self.range_start_idx = None
            self.range_end_idx = None
            self.breakout_detected = False
            if self.in_position:
                self.position.close()
                self.in_position = False


