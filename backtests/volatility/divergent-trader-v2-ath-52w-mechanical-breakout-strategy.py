import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    useATH = True
    use52W = True
    athLookback = 5000
    atrLength = 14
    atrMult = 2.0
    useEMAExit = False
    emaLength = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATH calculation - highest high over lookback period
        self.ath = self.I(lambda: high.rolling(window=self.athLookback).max())
        
        # 52-week high approximation (252 bars ≈ 52 weeks of daily data)
        self.week52_high = self.I(lambda: high.rolling(window=252).max())
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # EMA for exit
        self.ema = self.I(pta.ema, close, length=self.emaLength)
        
        # Track highest price since entry
        self.highest_since_entry = np.nan
        
        # Track ATR stop level
        self.atr_stop = np.nan

    def next(self):
        # Update highest price since entry
        if len(self) == 0:
            self.highest_since_entry = np.nan
            self.atr_stop = np.nan
            return
            
        if self.position:
            # Update highest price while in position
            if np.isnan(self.highest_since_entry):
                self.highest_since_entry = self.data.High[-1]
            else:
                self.highest_since_entry = max(self.highest_since_entry, self.data.High[-1])
            
            # Calculate ATR trailing stop
            if not np.isnan(self.atr[-1]):
                self.atr_stop = self.highest_since_entry - (self.atr[-1] * self.atrMult)
        else:
            self.highest_since_entry = np.nan
            self.atr_stop = np.nan
        
        # Entry Logic
        if not self.position:
            breakATH = False
            break52W = False
            
            # Check ATH breakout (only if we have enough data)
            if self.useATH and len(self) > 1:
                if not np.isnan(self.ath[-2]) and self.data.High[-1] > self.ath[-2]:
                    breakATH = True
            
            # Check 52W breakout (only if we have enough data)
            if self.use52W and len(self) > 1:
                if not np.isnan(self.week52_high[-2]) and self.data.High[-1] > self.week52_high[-2]:
                    break52W = True
            
            # Enter on breakout
            if breakATH or break52W:
                self.buy()
        
        # Exit Logic
        else:
            if self.useEMAExit:
                # EMA exit: close if price below EMA
                if not np.isnan(self.ema[-1]) and self.data.Close[-1] < self.ema[-1]:
                    self.sell()
            else:
                # ATR trailing stop exit
                if not np.isnan(self.atr_stop) and self.data.Close[-1] <= self.atr_stop:
                    self.sell()


