        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Helper functions
        def calc_z_score(series, lookback):
            sma = series.rolling(lookback).mean()
            std = series.rolling(lookback).std()
            z = (series - sma) / std.replace(0, np.nan)
            return z.fillna(0)
        
        def norm_rate(v):
            return np.where(v > 20.0, v / 10.0, v)
        
        def clamp_val(x, a):
            return np.maximum(-a, np.minimum(a, x))
        
        def logit_prob(z, k):
            return 100.0 / (1.0 + np.exp(-k * z))
        
        # Since we don't have access to external symbols in backtest,
        # we'll create synthetic rate spreads based on price action
        # Using close prices as proxies for yield data
        
