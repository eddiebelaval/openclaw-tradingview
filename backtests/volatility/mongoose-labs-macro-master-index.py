        r10 = norm_rate(close * 0.05 + 2.5)
        r2 = norm_rate(close * 0.03 + 1.8)
        r3 = norm_rate(close * 0.02 + 1.2)
        
        s10_2 = r10 - r2
        s10_3 = r10 - r3
        s2_3 = r2 - r3
        
        z10_2 = self.I(lambda: calc_z_score(s10_2, self.lenZ))
