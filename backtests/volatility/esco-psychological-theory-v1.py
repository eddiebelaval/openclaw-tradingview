import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.ema21 = self.I(pta.ema, close, length=21)
        self.ema55 = self.I(pta.ema, close, length=55)
        
        # ATR for volatility
        self.atr14 = self.I(pta.atr, high, low, close, length=14)
        self.atr7 = self.I(pta.atr, high, low, close, length=7)
        self.atr50 = self.I(pta.atr, high, low, close, length=50)
        
        # ADX for trend clarity
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = self.I(lambda x=adx_result: x.iloc[:, 2] if x is not None and len(x.columns) > 2 else pd.Series(25, index=close.index))
        
        # Volume indicators
        self.vol_sma = self.I(pta.sma, volume, length=20)
        self.vol_sma5 = self.I(pta.sma, volume, length=5)
        
        # Bollinger and Keltner for squeeze
        self.bb = self.I(pta.bbands, close, length=20, std=2)
        self.ema20 = self.I(pta.ema, close, length=20)
        
        # RSI for overbought/oversold
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # Track regime state
        self.regime = 0
        self.regime_bars = 0
        self.prev_regime = 0

    def next(self):
        if len(self) < 60:
            return
        
        # Extract current values
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        ema21_val = self.ema21[-1]
        ema55_val = self.ema55[-1]
        atr14_val = self.atr14[-1]
        atr7_val = self.atr7[-1]
        atr50_val = self.atr50[-1]
        adx_val = self.adx[-1] if self.adx[-1] is not None else 25
        vol_sma_val = self.vol_sma[-1]
        vol_sma5_val = self.vol_sma5[-1]
        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50
        
        # Calculate derived values
        atr_ratio = atr7_val / atr50_val if atr50_val > 0 else 1.0
        vol_ratio = volume_val / vol_sma_val if vol_sma_val > 0 else 1.0
        vol_spike = volume_val > vol_sma_val * 1.8
        vol_declining = vol_sma5_val < vol_sma_val * 0.7
        
        # Trend detection
        trend_bull = ema21_val > ema55_val
        trend_bear = ema21_val < ema55_val
        is_comp = atr_ratio < 0.6
        
        # Squeeze detection
        bb_upper = self.bb[-1, 1] if self.bb[-1, 1] is not None else close_val
        bb_lower = self.bb[-1, 2] if self.bb[-1, 2] is not None else close_val
        kc_upper = self.ema20[-1] + atr14_val * 1.5
        kc_lower = self.ema20[-1] - atr14_val * 1.5
        in_squeeze = (bb_upper < kc_upper) and (bb_lower > kc_lower)
        squeeze_fired = (len(self) > 1 and 
                        ((self.bb[-2, 1] < self.data.Open[-2] + atr14_val * 1.5) and 
                         not in_squeeze))
        
        # Body and wicks
        body = abs(close_val - self.data.Open[-1])
        u_wick = high_val - max(close_val, self.data.Open[-1])
        d_wick = min(close_val, self.data.Open[-1]) - low_val
        bar_range = high_val - low_val
        wick_ratio_up = u_wick / bar_range if bar_range > 0 else 0
        wick_ratio_down = d_wick / bar_range if bar_range > 0 else 0
        rej_up = wick_ratio_up > 0.55
        rej_down = wick_ratio_down > 0.55
        
        # Displacement
        is_disp = body > atr14_val * 1.5
        is_bull_disp = is_disp and close_val > self.data.Open[-1]
        is_bear_disp = is_disp and close_val < self.data.Open[-1]
        
        # Simple regime machine
        regime_change = False
        
        # Comfort: trend aligned, compressed, no displacement
        if trend_bull and is_comp and not is_disp and adx_val > 20:
            if self.regime != 0:
                self.regime = 0
                regime_change = True
                self.regime_bars = 0
        # Tension: consolidation, equal highs/lows
        elif (rej_up or rej_down) and is_comp and not is_disp:
            if self.regime != 1:
                self.regime = 1
                regime_change = True
                self.regime_bars = 0
        # Hope: displacement with breakout
        elif squeeze_fired or (is_disp and vol_spike):
            if self.regime != 2:
                self.regime = 2
                regime_change = True
                self.regime_bars = 0
        # Panic: volatility spike, trend shift
        elif atr_ratio > 1.4 and vol_spike and is_disp:
            if self.regime != 4:
                self.regime = 4
                regime_change = True
                self.regime_bars = 0
        # Relief: compression after panic
        elif not is_disp and atr_ratio < 0.9 and vol_declining:
            if self.regime != 6:
                self.regime = 6
                regime_change = True
                self.regime_bars = 0
        
        if not regime_change:
            self.regime_bars += 1
        
        # ═══════════════════════════════════════════════════════════════
        # TRADING LOGIC
        # ═══════════════════════════════════════════════════════════════
        
        # Exit existing positions first
        if self.position:
            # Exit long
            if self.position.is_long:
                # Exit on: panic regime, strong downtrend, oversold bounce
                if (self.regime == 4 or 
                    trend_bear or 
                    (rsi_val > 70 and is_bear_disp)):
                    self.position.close()
            
            # Exit short
            if self.position.is_short:
                # Exit on: strong uptrend, overbought, relief regime
                if (trend_bull or 
                    (rsi_val < 30 and is_bull_disp) or 
                    self.regime == 6):
                    self.position.close()
        
        # Entry logic
        if not self.position:
            # Long setup: Bullish confluence
            long_setup = (
                trend_bull and                      # EMA aligned
                (self.regime == 0 or self.regime == 6) and  # Comfortable or relieving
                (rsi_val < 70 or rsi_val > 30) and  # Not overbought entry
                vol_ratio > 0.8 and                 # Healthy volume
                is_bull_disp and                    # Bullish displacement
                self.regime_bars > 2                # Regime confirmation
            )
            
            # Squeeze breakout long
            squeeze_long = (
                squeeze_fired and 
                trend_bull and 
                vol_spike and
                is_bull_disp
            )
            
            # Recovery play
            recovery_long = (
                self.regime == 6 and 
                rsi_val < 50 and
                trend_bull and
                rej_down and
                self.regime_bars > 3
            )
            
            if long_setup or squeeze_long or recovery_long:
                self.buy()
            
            # Short setup: Bearish confluence
            short_setup = (
                trend_bear and                      # EMA aligned
                (self.regime == 1 or self.regime == 4) and  # Tension or panic
                (rsi_val > 30 or rsi_val < 70) and  # Not oversold entry
                vol_ratio > 0.8 and                 # Healthy volume
                is_bear_disp and                    # Bearish displacement
                self.regime_bars > 2                # Regime confirmation
            )
            
            # Panic short
            panic_short = (
                self.regime == 4 and
                is_bear_disp and
                vol_spike and
                rsi_val > 50
            )
            
            # Rejection short
            rejection_short = (
                rej_up and
                trend_bear and
                is_comp and
                not is_disp and
                self.regime_bars > 2
            )
            
            if short_setup or panic_short or rejection_short:
                self.sell()