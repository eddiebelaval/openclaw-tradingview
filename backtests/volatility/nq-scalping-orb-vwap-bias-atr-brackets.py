import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime, time as dt_time


class TvStrategy(Strategy):
    # Inputs
    orbMinutes = 15
    maxTradesPerDay = 4
    useVWAPBias = True
    useVolFilter = True
    volSmaLen = 20
    atrLen = 14
    stopATR = 1.0
    targetATR = 1.4
    useTrail = False
    trailATR = 0.8
    useTimeExit = True
    maxBarsInTrade = 30
    flattenAtEnd = True
    useSession = True
    tradeSessionStart = 930
    tradeSessionEnd = 1500

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Calculate VWAP
        hlc3 = (high + low + close) / 3
        self.vwap = self.I(pta.vwap, hlc3, volume)
        
        # Calculate volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=self.volSmaLen)
        
        # ORB tracking
        self.orb_high = np.nan
        self.orb_low = np.nan
        self.orb_ready = False
        self.orb_bars = 0
        self.orb_start_bar = -1
        
        # Daily trade counter
        self.trades_today = 0
        self.last_day = -1
        
        # Entry bar tracking
        self.entry_bar = -1

    def next(self):
        if len(self.data) < self.atrLen + 1:
            return
        
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_volume = self.data.Volume[-1]
        current_bar = len(self.data) - 1
        
        # Get current time
        current_time = self.data.index[-1]
        current_hour = current_time.hour
        current_minute = current_time.minute
        current_date = current_time.date()
        
        # Reset trade count on new day
        current_day = current_date.toordinal()
        if current_day != self.last_day:
            self.trades_today = 0
            self.last_day = current_day
            self.orb_high = np.nan
            self.orb_low = np.nan
            self.orb_ready = False
            self.orb_bars = 0
            self.orb_start_bar = -1
        
        # Check if in trading session
        is_in_session = (self.tradeSessionStart <= current_hour * 100 + current_minute < self.tradeSessionEnd)
        can_trade = is_in_session if self.useSession else True
        
        # Check trading limits
        trade_limit_ok = self.trades_today < self.maxTradesPerDay
        
        # Check volume filter
        vol_ok = (current_volume > self.vol_sma[-1]) if self.useVolFilter and not np.isnan(self.vol_sma[-1]) else True
        
        # VWAP bias checks
        vwap_long_ok = (current_close > self.vwap[-1]) if self.useVWAPBias and not np.isnan(self.vwap[-1]) else True
        vwap_short_ok = (current_close < self.vwap[-1]) if self.useVWAPBias and not np.isnan(self.vwap[-1]) else True
        
        # ORB calculation
        is_orb_start = (current_hour == 9 and current_minute == 30)
        
        if is_orb_start:
            self.orb_high = np.nan
            self.orb_low = np.nan
            self.orb_ready = False
            self.orb_bars = 0
            self.orb_start_bar = current_bar
        
        # Build ORB window
        is_in_orb_window = False
        if current_hour == 9 and current_minute >= 30:
            minutes_from_start = current_minute - 30
            if minutes_from_start < self.orbMinutes:
                is_in_orb_window = True
        elif self.orbMinutes > 30 and current_hour == 10:
            if current_minute < (self.orbMinutes - 30):
                is_in_orb_window = True
        
        if is_in_orb_window:
            if np.isnan(self.orb_high):
                self.orb_high = current_high
                self.orb_low = current_low
            else:
                self.orb_high = max(self.orb_high, current_high)
                self.orb_low = min(self.orb_low, current_low)
            self.orb_bars += 1
        
        # Mark ORB ready
        if not is_in_orb_window and not np.isnan(self.orb_high) and not np.isnan(self.orb_low) and not self.orb_ready:
            self.orb_ready = True
        
        # Get ATR value
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        
        # Generate signals
        long_signal = (can_trade and trade_limit_ok and vol_ok and self.orb_ready and 
                      vwap_long_ok and current_close > self.orb_high)
        short_signal = (can_trade and trade_limit_ok and vol_ok and self.orb_ready and 
                       vwap_short_ok and current_close < self.orb_low)
        
        # Entry logic
        if long_signal and self.position.size <= 0:
            self.buy()
            self.trades_today += 1
            self.entry_bar = current_bar
        
        if short_signal and self.position.size >= 0:
            self.sell()
            self.trades_today += 1
            self.entry_bar = current_bar
        
        # Exit logic
        if self.position.size > 0:
            # Long exits
            entry_price = self.position.open_price
            long_stop = entry_price - self.stopATR * atr_val
            long_target = entry_price + self.targetATR * atr_val
            
            # Check time exit
            if self.useTimeExit and self.entry_bar >= 0:
                bars_in_trade = current_bar - self.entry_bar
                if bars_in_trade >= self.maxBarsInTrade:
                    self.position.close()
            
            # Check target and stop
            elif current_low <= long_stop:
                self.position.close()
            elif current_high >= long_target:
                self.position.close()
            
            # Check session end
            if self.flattenAtEnd and self.useSession and not is_in_session:
                self.position.close()
        
        elif self.position.size < 0:
            # Short exits
            entry_price = self.position.open_price
            short_stop = entry_price + self.stopATR * atr_val
            short_target = entry_price - self.targetATR * atr_val
            
            # Check time exit
            if self.useTimeExit and self.entry_bar >= 0:
                bars_in_trade = current_bar - self.entry_bar
                if bars_in_trade >= self.maxBarsInTrade:
                    self.position.close()
            
            # Check target and stop
            elif current_high >= short_stop:
                self.position.close()
            elif current_low <= short_target:
                self.position.close()
            
            # Check session end
            if self.flattenAtEnd and self.useSession and not is_in_session:
                self.position.close()


