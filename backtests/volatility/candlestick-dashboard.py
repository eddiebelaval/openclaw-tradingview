import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    atr_length = 14
    atr_mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        self.stop_dist = self.I(lambda: self.atr * self.atr_mult if self.atr is not None else pd.Series(0, index=close.index))
        
        self.long_stop = self.I(lambda: close - (self.atr * self.atr_mult) if self.atr is not None else close)
        self.short_stop = self.I(lambda: close + (self.atr * self.atr_mult) if self.atr is not None else close)
        
        self.spread = self.I(lambda: high - low)
        self.buy_vol = self.I(lambda: self._calc_buy_vol(high, low, close))
        self.sell_vol = self.I(lambda: self._calc_sell_vol(high, low, close))

    def _calc_buy_vol(self, high, low, close):
        spread = high - low
        vol = pd.Series(self.data.Volume)
        buy_vol = pd.Series(index=close.index, dtype=float)
        for i in range(len(spread)):
            if spread.iloc[i] > 0:
                buy_vol.iloc[i] = vol.iloc[i] * (close.iloc[i] - low.iloc[i]) / spread.iloc[i]
            else:
                buy_vol.iloc[i] = vol.iloc[i] * 0.5
        return buy_vol

    def _calc_sell_vol(self, high, low, close):
        spread = high - low
        vol = pd.Series(self.data.Volume)
        sell_vol = pd.Series(index=close.index, dtype=float)
        for i in range(len(spread)):
            if spread.iloc[i] > 0:
                sell_vol.iloc[i] = vol.iloc[i] * (high.iloc[i] - close.iloc[i]) / spread.iloc[i]
            else:
                sell_vol.iloc[i] = vol.iloc[i] * 0.5
        return sell_vol

    def next(self):
        if len(self) < self.atr_length + 1:
            return
        
        if self.atr[-1] is None or np.isnan(self.atr[-1]):
            return
        
        current_atr = self.atr[-1]
        current_long_stop = self.data.Close[-1] - (current_atr * self.atr_mult)
        current_short_stop = self.data.Close[-1] + (current_atr * self.atr_mult)
        
        if not self.position:
            if self.data.Close[-1] <= current_long_stop and self.data.Close[-2] > current_long_stop:
                self.buy()
            elif self.data.Close[-1] >= current_short_stop and self.data.Close[-2] < current_short_stop:
                self.sell()
        else:
            if self.position.is_long:
                if self.data.Close[-1] <= current_long_stop:
                    self.position.close()
            elif self.position.is_short:
                if self.data.Close[-1] >= current_short_stop:
                    self.position.close()


