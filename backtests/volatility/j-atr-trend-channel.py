import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 6
    ATRPeriod = 16
    ATRMultip = 5.1

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        atr = self.I(lambda: pta.atr(high, low, close, length=self.ATRPeriod))
        nl = self.ATRMultip * atr
        
        # Calculate SMAs
        cc = self.I(pta.sma, close, length=self.fastLen)
        oo = self.I(pta.sma, open_, length=self.fastLen)
        hh = self.I(pta.sma, high, length=self.fastLen)
        ll = self.I(pta.sma, low, length=self.fastLen)
        
        # Calculate level of volatility
        lv = self.I(lambda: np.abs(cc - oo) / (hh - ll))
        
        # Initialize defATR values
        self.defATR = np.full(len(close), np.nan)
        self.defATR1 = np.full(len(close), np.nan)
        self.defATR2 = np.full(len(close), np.nan)
        self.a = np.full(len(close), np.nan)
        self.ss = np.full(len(close), np.nan)
        self.ss1 = np.full(len(close), np.nan)
        self.ss2 = np.full(len(close), np.nan)
        
        self.close = close
        self.atr = atr
        self.nl = nl
        self.cc = cc
        self.oo = oo
        self.hh = hh
        self.ll = ll
        self.lv = lv

    def next(self):
        idx = len(self.data) - 1
        
        # Calculate nl value
        if not pd.isna(self.nl[idx]):
            nl_val = self.nl[idx]
        else:
            nl_val = 0
        
        # Initialize defATR, defATR1, defATR2
        if idx == 0:
            self.defATR[idx] = self.close[idx]
            self.defATR1[idx] = self.close[idx]
            self.defATR2[idx] = self.close[idx]
            self.a[idx] = self.close[idx]
        else:
            prev_defATR = self.defATR[idx - 1]
            prev_defATR1 = self.defATR1[idx - 1]
            prev_defATR2 = self.defATR2[idx - 1]
            prev_a = self.a[idx - 1]
            
            close_curr = self.close[idx]
            close_prev = self.close[idx - 1]
            
            # Calculate defATR
            if close_curr > prev_defATR and close_prev > prev_defATR:
                self.defATR[idx] = max(prev_defATR, close_curr - nl_val)
            elif close_curr < prev_defATR and close_prev < prev_defATR:
                self.defATR[idx] = min(prev_defATR, close_curr + nl_val)
            elif close_curr > prev_defATR:
                self.defATR[idx] = close_curr - nl_val
            else:
                self.defATR[idx] = close_curr + nl_val
            
            # Calculate defATR1
            if close_curr > prev_defATR1 and close_prev > prev_defATR1:
                self.defATR1[idx] = max(prev_defATR1, close_curr - nl_val)
            elif close_curr < prev_defATR1 and close_prev < prev_defATR1:
                self.defATR1[idx] = min(prev_defATR1, close_curr + nl_val)
            elif close_curr < prev_defATR1:
                self.defATR1[idx] = close_curr + nl_val
            else:
                self.defATR1[idx] = close_curr + nl_val
            
            # Calculate defATR2
            if close_curr > prev_defATR2 and close_prev > prev_defATR2:
                self.defATR2[idx] = max(prev_defATR2, close_curr - nl_val)
            elif close_curr < prev_defATR2 and close_prev < prev_defATR2:
                self.defATR2[idx] = min(prev_defATR2, close_curr + nl_val)
            elif close_curr > prev_defATR2:
                self.defATR2[idx] = close_curr + nl_val
            else:
                self.defATR2[idx] = close_curr - nl_val
            
            # Calculate smoothed price level
            if not pd.isna(self.lv[idx]):
                self.a[idx] = self.lv[idx] * close_curr + (1 - self.lv[idx]) * prev_a
            else:
                self.a[idx] = close_curr
        
        # Calculate midband values
        if not pd.isna(self.defATR[idx]) and not pd.isna(self.a[idx]):
            if self.defATR[idx] > self.a[idx]:
                self.ss[idx] = self.defATR[idx] - (self.defATR[idx] - self.a[idx]) / 2
            else:
                self.ss[idx] = self.defATR[idx] + (self.a[idx] - self.defATR[idx]) / 2
        
