import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rv_len = 20
    rv_type = "Close-to-Close"
    vov_len = 60
    norm_mode = "Z-Score"
    upper_alert = 2.0
    upper_warn = 1.0
    lower_calm = -1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate log returns for Close-to-Close RV
        def calc_rv_cc():
            log_ret = np.log(close / close.shift(1))
            rv_cc = log_ret.rolling(window=self.rv_len).std() * np.sqrt(252)
            return rv_cc
        
        # Calculate Parkinson RV
        def calc_rv_park():
            hl_log = np.log(high / low)
            parkinson_var = (hl_log * hl_log).rolling(window=self.rv_len).mean() / (4.0 * np.log(2))
            rv_park = np.sqrt(parkinson_var * 252)
            return rv_park
        
        # Select RV based on type
        def calc_rv():
            rv_cc = calc_rv_cc()
            rv_park = calc_rv_park()
            rv = rv_park if self.rv_type == "Parkinson" else rv_cc
            return rv
        
        self.rv = self.I(calc_rv)
        
        # Calculate VoV components
        def calc_vov_cv():
            rv_values = self.rv
            vov_mean = rv_values.rolling(window=self.vov_len).mean()
            vov_raw = rv_values.rolling(window=self.vov_len).std()
            vov_cv = np.where(vov_mean != 0, vov_raw / vov_mean, 0.0)
            return pd.Series(vov_cv, index=close.index)
        
        self.vov_cv = self.I(calc_vov_cv)
        
        # Calculate Z-Score
        def calc_vov_zscore():
            vov_cv_values = self.vov_cv
            vov_zscore_mean = vov_cv_values.rolling(window=self.vov_len).mean()
            vov_zscore_std = vov_cv_values.rolling(window=self.vov_len).std()
            vov_zscore = np.where(vov_zscore_std != 0, 
                                  (vov_cv_values - vov_zscore_mean) / vov_zscore_std, 
                                  0.0)
            return pd.Series(vov_zscore, index=close.index)
        
        self.vov_zscore = self.I(calc_vov_zscore)
        
        # Calculate Percentile
        def calc_vov_percentile():
            vov_cv_values = self.vov_cv
            vov_pct = []
            for i in range(len(vov_cv_values)):
                if i < 20:
                    vov_pct.append(50.0)
                else:
                    history = vov_cv_values[max(0, i-252):i+1]
                    current = vov_cv_values.iloc[i]
                    if pd.isna(current):
                        vov_pct.append(50.0)
                    else:
                        count_below = (history < current).sum()
                        total = len(history)
                        pct = (count_below / total) * 100.0 if total > 0 else 50.0
                        vov_pct.append(pct)
            return pd.Series(vov_pct, index=close.index)
        
        self.vov_pct = self.I(calc_vov_percentile)
        
        # Select display mode
        def calc_vov_display():
            if self.norm_mode == "Z-Score":
                return self.vov_zscore
            elif self.norm_mode == "Percentile":
                return self.vov_pct
            else:
                return self.vov_cv
        
        self.vov_display = self.I(calc_vov_display)
        
        # EMA smoothing
        def calc_vov_ema():
            return pta.ema(self.vov_display, length=5)
        
        self.vov_ema = self.I(calc_vov_ema)

    def next(self):
        if len(self.data) < max(self.rv_len, self.vov_len) + 5:
            return
        
        vov = self.vov_display[-1]
        vov_smooth = self.vov_ema[-1]
        
        if pd.isna(vov) or pd.isna(vov_smooth):
            return
        
        # Determine regime
        if self.norm_mode == "Percentile":
            pct = self.vov_pct[-1]
            is_calm = pct < 25
            is_elevated = pct >= 65 and pct < 85
            is_unstable = pct >= 85
        else:
            is_calm = vov < self.lower_calm
            is_elevated = vov >= self.lower_calm and vov < self.upper_warn
            is_unstable = vov >= self.upper_alert
        
        # Trading logic: Buy in calm regime, sell in unstable regime
        if is_calm and not self.position:
            self.buy()
        elif is_unstable and self.position:
            self.sell()
        elif is_elevated and self.position:
            self.sell()


