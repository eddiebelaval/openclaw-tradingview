import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Bollinger Bands parameters
    bbLength = 20
    bbMult = 2.0
    bbTolerance = 0.2
    
    # Stochastic parameters
    kLength = 5
    dLength = 3
    smoothK = 3
    stochUpper = 80
    stochLower = 20
    
    # Trend parameters
    trendLength = 10
    emaLen = 200
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # Bollinger Bands
        bb = self.I(lambda: pta.bbands(close, length=self.bbLength, std=self.bbMult))
        self.bbUpper = bb.iloc[:, 0] if bb is not None else self.I(lambda x=close: pd.Series(x.mean(), index=x.index))
        self.bbBasis = bb.iloc[:, 1] if bb is not None else self.I(lambda x=close: pd.Series(x.mean(), index=x.index))
        self.bbLower = bb.iloc[:, 2] if bb is not None else self.I(lambda x=close: pd.Series(x.mean(), index=x.index))
        
        # Stochastic
        stoch = self.I(lambda: pta.stoch(high, low, close, k=self.kLength, d=self.dLength, smooth_k=self.smoothK))
        self.stochK = stoch.iloc[:, 0] if stoch is not None else self.I(lambda x=close: pd.Series(50, index=x.index))
        self.stochD = stoch.iloc[:, 1] if stoch is not None else self.I(lambda x=close: pd.Series(50, index=x.index))
        
        # Trend MA
        self.ma = self.I(pta.sma, close, length=self.trendLength)
        
        # Daily EMA for trend (using current timeframe as proxy)
        self.dailyEma = self.I(pta.ema, close, length=self.emaLen)
        self.dailyEma50 = self.I(pta.ema, close, length=50)
        
        # Candle components
        self.body = self.I(lambda o=open_, c=close: np.abs(c - o))
        self.lower_shadow = self.I(lambda o=open_, c=close, l=low: np.minimum(o, c) - l)
        self.upper_shadow = self.I(lambda h=high, o=open_, c=close: h - np.maximum(o, c))
        self.candle_range = self.I(lambda h=high, l=low: h - l)
        
    def next(self):
        # Only trade if we have enough data
        if len(self.data) < max(self.emaLen, self.bbLength, self.kLength):
            return
        
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Current values
        body = self.body[-1]
        lower_shadow = self.lower_shadow[-1]
        upper_shadow = self.upper_shadow[-1]
        candle_range = self.candle_range[-1]
        
        stochK = self.stochK[-1]
        stochD = self.stochD[-1]
        bbUpper = self.bbUpper[-1]
        bbLower = self.bbLower[-1]
        bbBasis = self.bbBasis[-1]
        
        # Daily trend
        dailyTrendUp = close > self.dailyEma[-1]
        dailyTrendDown = close < self.dailyEma[-1]
        momentumUp = close > self.dailyEma50[-1]
        momentumDown = close < self.dailyEma50[-1]
        
        # Pin Bar patterns
        isBullishPB = (lower_shadow > 2 * body and 
                       close > (candle_range / 2 + low) and 
                       body > 0 and 
                       upper_shadow < body / 2)
        
        isBearishPB = (upper_shadow >= body * 2 and 
                       lower_shadow <= body and
                       close < open_)
        
        # Engulfing patterns
        if len(self.data) >= 2:
            close_prev = self.data.Close[-2]
            open_prev = self.data.Open[-2]
            
            isBullishEG = (close > open_ and 
                          close_prev < open_prev and 
                          close > open_prev and 
                          open_ < close_prev)
            
            isBearishEG = (close < open_ and 
                          close_prev > open_prev and 
                          close < open_prev and 
                          open_ > close_prev)
        else:
            isBullishEG = False
            isBearishEG = False
        
        # BB tolerance
        toleranceRange = bbLower * (self.bbTolerance / 100)
        openNearLowerBB = open_ >= (bbLower - toleranceRange) and open_ <= (bbLower + toleranceRange)
        openNearUpperBB = open_ >= (bbUpper - toleranceRange) and open_ <= (bbUpper + toleranceRange)
        
        # Engulfing at BB
        bullishEG_at_LowerBB = isBullishEG and openNearLowerBB
        bearishEG_at_UpperBB = isBearishEG and openNearUpperBB
        
        # Stochastic crossing
        if len(self.data) >= 2:
            stochK_prev = self.stochK[-2]
            stochD_prev = self.stochD[-2]
            
            bullishCross = stochK_prev <= stochD_prev and stochK > stochD
            bearishCross = stochK_prev >= stochD_prev and stochK < stochD
            
            inOversold = (stochK <= self.stochLower or stochD <= self.stochLower or 
                         stochK_prev <= self.stochLower or stochD_prev <= self.stochLower)
            inOverbought = (stochK >= self.stochUpper or stochD >= self.stochUpper or 
                           stochK_prev >= self.stochUpper or stochD_prev >= self.stochUpper)
            
            isStochCrossBelow = bullishCross and inOversold
            isStochCrossAbove = bearishCross and inOverbought
        else:
            isStochCrossBelow = False
            isStochCrossAbove = False
        
        # Trading logic
        # BUY conditions: Daily trend up + momentum up + bullish signals
        buy_signal = (dailyTrendUp and momentumUp and 
                     (isBullishPB or isBullishEG or bullishEG_at_LowerBB or isStochCrossBelow))
        
        # SELL conditions: Daily trend down + momentum down + bearish signals
        sell_signal = (dailyTrendDown and momentumDown and 
                      (isBearishPB or isBearishEG or bearishEG_at_UpperBB or isStochCrossAbove))
        
        # Execute trades
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.position.close()
        elif sell_signal and not self.position:
            self.buy()  # Short entry
        elif buy_signal and self.position and self.position.is_short:
            self.position.close()


