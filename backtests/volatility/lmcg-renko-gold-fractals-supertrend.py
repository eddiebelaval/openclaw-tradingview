import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fractal_len = 2
    atr_len = 10
    factor_base = 2.0
    alpha_perf = 0.15
    vol_ma_len = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)

        # HLC3
        self.hlc3 = self.I(lambda: (high + low + close + close) / 4)

        # Volume MA
        self.vol_ma = self.I(pta.sma, volume, length=self.vol_ma_len)

        # Pivot High/Low for fractals
        self.pivot_high = self.I(self._pivot_high, high, self.fractal_len)
        self.pivot_low = self.I(self._pivot_low, low, self.fractal_len)

        # Performance tracking variables
        self.perf_up = 0.0
        self.perf_down = 0.0
        self.up_trend = np.nan
        self.dn_trend = np.nan
        self.trend_dir = 1
        self.prev_trend_dir = 1

    def _pivot_high(self, high_series, length):
        result = pd.Series(np.nan, index=high_series.index)
        for i in range(length, len(high_series) - length):
            if high_series.iloc[i] == high_series.iloc[i-length:i+length+1].max():
                result.iloc[i] = high_series.iloc[i]
        return result

    def _pivot_low(self, low_series, length):
        result = pd.Series(np.nan, index=low_series.index)
        for i in range(length, len(low_series) - length):
            if low_series.iloc[i] == low_series.iloc[i-length:i+length+1].min():
                result.iloc[i] = low_series.iloc[i]
        return result

    def _tanh(self, x):
        e_x = np.exp(x)
        e_neg_x = np.exp(-x)
        return (e_x - e_neg_x) / (e_x + e_neg_x)

    def next(self):
        if len(self.data) < self.fractal_len + 3:
            return

        idx = len(self.data) - 1
        close_curr = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        close_prev2 = self.data.Close[-3]
        high_curr = self.data.High[-1]
        low_curr = self.data.Low[-1]
        volume_curr = self.data.Volume[-1]

        # Check for pivot high/low (fractals)
        up_fractal = not np.isnan(self.pivot_high[-1])
        dn_fractal = not np.isnan(self.pivot_low[-1])

        # Volume filter
        vol_ma_val = self.vol_ma[-1] if not np.isnan(self.vol_ma[-1]) else volume_curr
        high_vol = volume_curr > vol_ma_val * 1.3

        # ATR and adaptive SuperTrend
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        hlc3_val = self.hlc3[-1] if not np.isnan(self.hlc3[-1]) else (high_curr + low_curr + close_curr) / 3

        # Momentum-based performance
        delta = close_curr - close_prev
        was_up = close_prev > close_prev2
        was_down = close_prev < close_prev2

        momentum = close_curr - (self.data.Close[-4] if len(self.data) >= 4 else close_curr)

        self.perf_up = self.perf_up + self.alpha_perf * (momentum if was_up else 0) - self.alpha_perf * self.perf_up
        self.perf_down = self.perf_down + self.alpha_perf * (-momentum if was_down else 0) - self.alpha_perf * self.perf_down

        # Dynamic factor
        tanh_val = self._tanh(self.perf_up - self.perf_down)
        dyn_factor = self.factor_base * (1.0 - tanh_val * 0.4)

        # SuperTrend bands
        upper_band = hlc3_val - (dyn_factor * atr_val)
        lower_band = hlc3_val + (dyn_factor * atr_val)

        # Update trends
        if np.isnan(self.up_trend):
            self.up_trend = upper_band
        else:
            if close_prev > self.up_trend:
                self.up_trend = max(upper_band, self.up_trend)
            else:
                self.up_trend = upper_band

        if np.isnan(self.dn_trend):
            self.dn_trend = lower_band
        else:
            if close_prev < self.dn_trend:
                self.dn_trend = min(lower_band, self.dn_trend)
            else:
                self.dn_trend = lower_band

        # Determine trend direction
        self.prev_trend_dir = self.trend_dir
        if close_curr > self.dn_trend:
            self.trend_dir = 1
        elif close_curr < self.up_trend:
            self.trend_dir = -1

        # Trend flip signals
        trend_flip_up = self.trend_dir == 1 and self.prev_trend_dir == -1
        trend_flip_down = self.trend_dir == -1 and self.prev_trend_dir == 1

        # Buy/Sell signals
        buy_sig = dn_fractal and trend_flip_up and high_vol
        sell_sig = up_fractal and trend_flip_down and high_vol

        # Execute trades
        if buy_sig:
            if not self.position:
                self.buy()
        elif sell_sig:
            if self.position:
                self.sell()


