import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_period = 14
    smoothing_method = "RMA"
    sl_multiplier = 1.5
    tp1_multiplier = 1.0
    tp2_multiplier = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate True Range
        def calc_tr():
            tr1 = high - low
            tr2 = np.abs(high - close.shift(1))
            tr3 = np.abs(low - close.shift(1))
            return pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
        
        tr = self.I(calc_tr)
        
        # Calculate ATR with selected smoothing method
        def calc_atr():
            tr_series = calc_tr()
            if self.smoothing_method == "RMA":
                return pta.rma(tr_series, length=self.atr_period)
            elif self.smoothing_method == "SMA":
                return pta.sma(tr_series, length=self.atr_period)
            elif self.smoothing_method == "EMA":
                return pta.ema(tr_series, length=self.atr_period)
            elif self.smoothing_method == "WMA":
                return pta.wma(tr_series, length=self.atr_period)
            else:
                return pta.rma(tr_series, length=self.atr_period)
        
        self.atr = self.I(calc_atr)
        
        # Calculate 20-period SMA of ATR for volatility classification
        def calc_atr_avg():
            atr_series = calc_atr()
            return pta.sma(atr_series, length=20)
        
        self.atr_avg = self.I(calc_atr_avg)
        
        # Calculate stop loss and target levels
        def calc_sl_long():
            return low - (self.atr * self.sl_multiplier)
        
        def calc_tp1_long():
            return close + (self.atr * self.tp1_multiplier)
        
        def calc_tp2_long():
            return close + (self.atr * self.tp2_multiplier)
        
        def calc_sl_short():
            return high + (self.atr * self.sl_multiplier)
        
        def calc_tp1_short():
            return close - (self.atr * self.tp1_multiplier)
        
        def calc_tp2_short():
            return close - (self.atr * self.tp2_multiplier)
        
        self.sl_long = self.I(calc_sl_long)
        self.tp1_long = self.I(calc_tp1_long)
        self.tp2_long = self.I(calc_tp2_long)
        self.sl_short = self.I(calc_sl_short)
        self.tp1_short = self.I(calc_tp1_short)
        self.tp2_short = self.I(calc_tp2_short)
        
        # Volatility state calculation
        def calc_volatility_state():
            high_vol = self.atr > (self.atr_avg * 1.3)
            low_vol = self.atr < (self.atr_avg * 0.8)
            vol_state = pd.Series(1, index=close.index)  # 1 = Normal
            vol_state[high_vol] = 2  # 2 = High
            vol_state[low_vol] = 0  # 0 = Low
            return vol_state
        
        self.volatility_state = self.I(calc_volatility_state)

    def next(self):
        if len(self) < self.atr_period + 5:
            return
        
        current_atr = self.atr[-1] if self.atr[-1] is not None else 0
        current_price = self.data.Close[-1]
        
        if current_atr <= 0:
            return
        
        # Simple trading logic based on volatility and price action
        if not self.position:
            # Entry logic: Buy on normal/low volatility with uptrend bias
            if self.volatility_state[-1] <= 1:  # Normal or Low volatility
                if self.data.Close[-1] > self.data.Close[-2]:
                    self.buy()
            # Sell on high volatility with downtrend bias
            elif self.volatility_state[-1] == 2:
                if self.data.Close[-1] < self.data.Close[-2]:
                    self.sell()
        else:
            # Exit logic for long positions
            if self.position.is_long:
                # Exit on TP1
                if current_price >= self.tp1_long[-1]:
                    self.position.close()
                # Exit on SL
                elif current_price <= self.sl_long[-1]:
                    self.position.close()
            
            # Exit logic for short positions
            elif self.position.is_short:
                # Exit on TP1
                if current_price <= self.tp1_short[-1]:
                    self.position.close()
                # Exit on SL
                elif current_price >= self.sl_short[-1]:
                    self.position.close()


