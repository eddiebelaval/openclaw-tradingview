class TvStrategy(Strategy):
    # Liquidation Detection Parameters
    volume_multiplier = 2.0
    volume_lookback = 20
    min_liquidation_size = 3.0
    z_score_threshold = 1.8
    wick_threshold = 0.4
    
    # Multi-timeframe
    use_mtf = True
    mtf_weight = 0.3
    
    # Signal Quality
    use_stop_hunt_filter = True
    use_divergence = True
    use_momentum_filter = True
    require_reversal = False
    reversal_bars = 2
    signal_cooldown = 3
    min_signal_strength = 3
    
    # Line Settings
    line_length = 100
    line_width_base = 2
    max_line_age = 100
    tagged_line_decay = 5
    min_importance_to_show = 25.0
    max_lines = 15
    merge_threshold = 0.3
    
    # Visual Settings
    show_lines = True
    show_signals = True
    show_labels = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume Analysis
        self.avg_volume = self.I(pta.sma, volume, length=self.volume_lookback)
        self.volume_std = self.I(lambda v: v.rolling(self.volume_lookback).std(), volume)
        
        # ATR for volatility
        self.atr14 = self.I(pta.atr, high, low, close, length=14)
        self.atr20 = self.I(pta.atr, high, low, close, length=20)
        
        # RSI for momentum
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # MACD for trend
        macd_result = self.I(lambda c: pta.macd(c, fast=12, slow=26, signal=9), close)
        self.macd_line = self.I(lambda c: (pta.macd(c, fast=12, slow=26, signal=9) or pd.DataFrame()).get('MACD_12_26_9', pd.Series(0, index=c.index)), close)
        
        # Swing highs/lows
        self.swing_high_5 = self.I(lambda h: h.rolling(5).max(), high)
        self.swing_low_5 = self.I(lambda l: l.rolling(5).min(), low)
        self.swing_high_10 = self.I(lambda h: h.rolling(10).max(), high)
        self.swing_low_10 = self.I(lambda l: l.rolling(10).min(), low)
        
        # Tracking variables
        self.last_bullish_signal_bar = 0
        self.last_bearish_signal_bar = 0
        self.liq_levels = []
        self.signal_bars = []

    def calculate_volume_z_score(self):
        """Calculate volume Z-score for abnormal volume detection"""
        if len(self.data) < self.volume_lookback:
            return 0.0
        
        current_vol = self.data.Volume[-1]
        avg_vol = self.avg_volume[-1]
        vol_std = self.volume_std[-1]
        
        if vol_std > 0:
            return (current_vol - avg_vol) / vol_std
        return 0.0

    def calculate_liquidation_size(self):
        """Calculate liquidation size in millions"""
        range_pu = self.data.High[-1] - self.data.Low[-1]
        volume_m = self.data.Volume[-1] / 1e6
        return volume_m * range_pu

    def calculate_liquidation_importance(self, vol_z, liq_size, is_bearish):
        """Calculate importance score for liquidation event (0-100)"""
        importance = 0.0
        
        # Volume component (0-35 points)
        if vol_z >= self.z_score_threshold * 1.8:
            importance += 35.0
        elif vol_z >= self.z_score_threshold * 1.3:
            importance += 28.0
        elif vol_z >= self.z_score_threshold:
            importance += 20.0
        elif self.data.Volume[-1] > self.avg_volume[-1] * self.volume_multiplier:
            importance += 12.0
        
        # Liquidation size component (0-25 points)
        if liq_size >= self.min_liquidation_size * 1.5:
            importance += 25.0
        elif liq_size >= self.min_liquidation_size:
            importance += 20.0
        elif liq_size >= self.min_liquidation_size * 0.5:
            importance += 14.0
        
        # Price range component (0-15 points)
        total_range = self.data.High[-1] - self.data.Low[-1]
        atr_val = self.atr14[-1]
        if atr_val > 0:
            range_ratio = total_range / atr_val
            if range_ratio > 3.0:
                importance += 15.0
            elif range_ratio > 2.0:
                importance += 11.0
            elif range_ratio > 1.5:
                importance += 7.0
            elif range_ratio > 1.0:
                importance += 3.0
        
        # Wick rejection component (0-10 points)
        if total_range > 0:
            upper_wick = self.data.High[-1] - max(self.data.Close[-1], self.data.Open[-1])
            lower_wick = min(self.data.Close[-1], self.data.Open[-1]) - self.data.Low[-1]
            upper_wick_ratio = upper_wick / total_range
            lower_wick_ratio = lower_wick / total_range
            
            if is_bearish and upper_wick_ratio > self.wick_threshold:
                importance += 10.0
            elif not is_bearish and lower_wick_ratio > self.wick_threshold:
                importance += 10.0
            elif upper_wick_ratio > self.wick_threshold * 0.7 or lower_wick_ratio > self.wick_threshold * 0.7:
                importance += 6.0
        
        # Momentum component (0-10 points)
        if self.use_momentum_filter:
            if self.rsi[-1] < 20:
                importance += 10.0
            elif self.rsi[-1] < 30:
                importance += 6.0
            elif self.rsi[-1] > 80:
                importance += 10.0
            elif self.rsi[-1] > 70:
                importance += 6.0
        
        return min(100.0, importance)

    def calculate_signal_strength(self, is_bearish, vol_z, liq_size):
        """Calculate signal strength (0-10)"""
        strength = 0.0
        total_range = self.data.High[-1] - self.data.Low[-1]
        
        # Volume confirmation
        if vol_z >= self.z_score_threshold * 1.8:
            strength += 2.0
        elif vol_z >= self.z_score_threshold * 1.3:
            strength += 1.5
        elif vol_z >= self.z_score_threshold:
            strength += 1.0
        
        # Liquidation magnitude
        if liq_size >= self.min_liquidation_size * 1.5:
            strength += 2.0
        elif liq_size >= self.min_liquidation_size:
            strength += 1.5
        elif liq_size >= self.min_liquidation_size * 0.5:
            strength += 1.0
        
        # Stop hunt pattern
        if self.use_stop_hunt_filter:
            if is_bearish:
                if self.data.High[-1] > self.swing_high_10[-1] and self.data.Close[-1] < self.data.Open[-1]:
                    strength += 2.0
                elif self.data.High[-1] > self.swing_high_5[-1] and self.data.Close[-1] < self.data.Open[-1]:
                    strength += 1.0
            else:
                if self.data.Low[-1] < self.swing_low_10[-1] and self.data.Close[-1] > self.data.Open[-1]:
                    strength += 2.0
                elif self.data.Low[-1] < self.swing_low_5[-1] and self.data.Close[-1] > self.data.Open[-1]:
                    strength += 1.0
        
        # Momentum confirmation
        if self.use_momentum_filter:
            if is_bearish and self.rsi[-1] > 70:
                strength += 1.0
            elif not is_bearish and self.rsi[-1] < 30:
                strength += 1.0
        
        # Wick rejection
        if total_range > 0:
            upper_wick = self.data.High[-1] - max(self.data.Close[-1], self.data.Open[-1])
            lower_wick = min(self.data.Close[-1], self.data.Open[-1]) - self.data.Low[-1]
            upper_wick_ratio = upper_wick / total_range
            lower_wick_ratio = lower_wick / total_range
            
            if is_bearish and upper_wick_ratio > self.wick_threshold:
                strength += 1.5
            elif not is_bearish and lower_wick_ratio > self.wick_threshold:
                strength += 1.5
        
        return min(10.0, strength)

    def detect_major_liquidation(self):
        """Detect if current bar represents a major liquidation event"""
        if len(self.data) < self.volume_lookback:
            return False, 0.0
        
        vol_z = self.calculate_volume_z_score()
        liq_size = self.calculate_liquidation_size()
        
        # Conditions for major liquidation
        very_abnormal_vol = vol_z >= self.z_score_threshold * 1.3
        extreme_vol = vol_z >= self.z_score_threshold * 1.8
        abnormal_vol = vol_z >= self.z_score_threshold
        
        is_major = (very_abnormal_vol and liq_size >= self.min_liquidation_size * 0.5) or \
                   extreme_vol or \
                   (abnormal_vol and liq_size >= self.min_liquidation_size * 0.5)
        
        return is_major, vol_z

