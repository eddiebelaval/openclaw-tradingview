        self.ema20 = self.I(pta.ema, close, length=self.emaPullback)
        self.volumeAvg = self.I(pta.sma, volume, length=20)
        
        self.entry_price = None
        self.sl_price = None
        self.tp1_price = None
        self.tp2_price = None

