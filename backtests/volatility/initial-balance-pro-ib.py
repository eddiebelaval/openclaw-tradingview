        cur_day = current_time.day
        if self.last_day != cur_day:
            self.ib_high = np.nan
            self.ib_low = np.nan
            self.ib_mid = np.nan
            self.ib_formed = False
            self.ib_start_bar = None
            self.signal_fired = False
            self.vwap_sum = 0.0
