    def _is_in_ib_session(self, dt):
        """Check if current time is within IB session"""
        h = dt.hour
        m = dt.minute
        cur = h * 60 + m
        s_t = self.ib_start_hour * 60 + self.ib_start_min
        e_t = self.ib_end_hour * 60 + self.ib_end_min
        return cur >= s_t and cur < e_t
    
    def _is_ib_end(self, dt):
        """Check if current time is at IB end"""
        h = dt.hour
        m = dt.minute
        return h == self.ib_end_hour and m == self.ib_end_min
    
    def _is_regular_session(self, dt):
        """Check if in regular trading session (9:30 - 16:00)"""
        h = dt.hour
        m = dt.minute
        cur = h * 60 + m
        return cur >= (9 * 60 + 30) and cur < (16 * 60 + 0)


