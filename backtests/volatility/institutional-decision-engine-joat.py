import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Regime Engine Parameters
    i_adx_period = 14
    i_trend_threshold = 25
    i_volatility_len = 14
    i_expansion_mult = 1.4
    i_contraction_mult = 0.6
    
    # Structure Engine Parameters
    i_swing_sensitivity = 10
    i_structure_confirm = 3
    
    # Momentum Engine Parameters
    i_pressure_period = 14
    i_wavetrend_ch = 10
    i_wavetrend_avg = 21
    i_rsi_period = 14
    
    # Volatility Layer Parameters
    i_bb_period = 20
    i_bb_mult = 2.0
    i_kc_period = 20
    i_kc_mult = 1.5
    
    # Directional Bias Parameters
    i_fast_ma = 21
    i_slow_ma = 55
    i_anchor_ma = 200
    i_bias_threshold = 60
    
    # Signal Qualification Parameters
    i_min_confluence = 5
    i_signal_cooldown = 5
    i_require_confirm = True
    i_min_rr = 1.5
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR and basic indicators
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # ADX calculation
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.i_adx_period))
        self.adx_value = self.I(lambda: adx_result['ADX_14'] if adx_result is not None else pd.Series(25, index=close.index))
        
        # Volatility regime
        self.atr_current = self.I(pta.atr, high, low, close, length=self.i_volatility_len)
        self.atr_baseline = self.I(lambda: pd.Series(self.data.Close).rolling(self.i_volatility_len * 3).mean() * 0.015)
        
        # Moving averages
        self.ma_fast = self.I(pta.ema, close, length=self.i_fast_ma)
        self.ma_slow = self.I(pta.ema, close, length=self.i_slow_ma)
        self.ma_anchor = self.I(pta.ema, close, length=self.i_anchor_ma)
        
        # RSI
        self.rsi_val = self.I(pta.rsi, close, length=self.i_rsi_period)
        
        # Bollinger Bands
        bb_result = self.I(lambda: pta.bbands(close, length=self.i_bb_period, std=self.i_bb_mult))
        self.bb_upper = self.I(lambda: bb_result['BBU_20_2.0'] if bb_result is not None else high)
        self.bb_lower = self.I(lambda: bb_result['BBL_20_2.0'] if bb_result is not None else low)
        self.bb_basis = self.I(pta.sma, close, length=self.i_bb_period)
        
        # Keltner Channels
        self.kc_basis = self.I(pta.ema, close, length=self.i_kc_period)
        self.kc_upper = self.I(lambda: self.kc_basis[-1] + self.atr[-1] * self.i_kc_mult if len(self.kc_basis) > 0 and len(self.atr) > 0 else high[-1])
        self.kc_lower = self.I(lambda: self.kc_basis[-1] - self.atr[-1] * self.i_kc_mult if len(self.kc_basis) > 0 and len(self.atr) > 0 else low[-1])
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macd_line = self.I(lambda: macd_result['MACD_12_26_9'] if macd_result is not None else pd.Series(0, index=close.index))
        self.macd_signal = self.I(lambda: macd_result['MACDh_12_26_9'] if macd_result is not None else pd.Series(0, index=close.index))
        
        # WaveTrend calculation
        self.wt1, self.wt2 = self._init_wavetrend(close)
        
        # Track signals
        self.last_long_signal_bar = -999
        self.last_short_signal_bar = -999

    def _init_wavetrend(self, close):
        def calc_wavetrend():
            hlc3 = (self.data.High + self.data.Low + close) / 3
            hlc3_series = pd.Series(hlc3)
            esa = pta.ema(hlc3_series, length=self.i_wavetrend_ch)
            d = pta.ema(np.abs(hlc3_series - esa), length=self.i_wavetrend_ch)
            ci = pd.Series(np.where(d != 0, (hlc3_series - esa) / (0.015 * d), 0))
            wt1 = pta.ema(ci, length=self.i_wavetrend_avg)
            wt2 = pta.sma(wt1, length=4)
            return wt1, wt2
        
        wt1 = self.I(lambda: calc_wavetrend()[0])
        wt2 = self.I(lambda: calc_wavetrend()[1])
        return wt1, wt2

    def next(self):
        if len(self.data) < max(self.i_anchor_ma, 50):
            return
        
        current_bar = len(self.data) - 1
        bars_since_long = current_bar - self.last_long_signal_bar
        bars_since_short = current_bar - self.last_short_signal_bar
        
        # Get current values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        ma_fast = self.ma_fast[-1]
        ma_slow = self.ma_slow[-1]
        ma_anchor = self.ma_anchor[-1]
        rsi = self.rsi_val[-1]
        
