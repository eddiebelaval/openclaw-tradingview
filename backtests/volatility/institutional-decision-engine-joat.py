        atr_val = self.atr[-1]
        if len(self.atr) > self.i_volatility_len * 3:
            atr_baseline = np.mean(self.atr[-self.i_volatility_len * 3:])
        else:
            atr_baseline = atr_val
        
        volatility_ratio = atr_baseline > 0 and atr_val / atr_baseline or 1.0
        volatility_state = 1 if volatility_ratio > self.i_expansion_mult else -1 if volatility_ratio < self.i_contraction_mult else 0
        
        # ADX value
        adx = self.adx_value[-1] if len(self.adx_value) > 0 else 25
        
        # Market regime
        market_regime = 0
        if volatility_state == 1 and adx < self.i_trend_threshold:
            market_regime = 3  # Volatile
        elif adx >= self.i_trend_threshold:
            market_regime = 1  # Trending
        elif volatility_state == -1:
            market_regime = 2  # Ranging
        
        # Trend direction
        trend_direction = 1 if rsi > 50 else -1 if rsi < 50 else 0
        
        # Structure bias
        ma_bullish_stack = ma_fast > ma_slow and ma_slow > ma_anchor
        ma_bearish_stack = ma_fast < ma_slow and ma_slow < ma_anchor
        structure_bias = 1 if ma_bullish_stack else -1 if ma_bearish_stack else 0
        
        # Momentum calculation
        wt1 = self.wt1[-1] if len(self.wt1) > 0 else 0
        wt2 = self.wt2[-1] if len(self.wt2) > 0 else 0
        
        wt_bullish = wt1 > wt2 and (len(self.wt1) > 1 and wt1 > self.wt1[-2])
        wt_bearish = wt1 < wt2 and (len(self.wt1) > 1 and wt1 < self.wt1[-2])
        
        rsi_momentum = rsi - (self.rsi_val[-6] if len(self.rsi_val) > 5 else rsi)
        rsi_bullish = rsi > 50 and rsi < 70 and rsi_momentum > 0
        rsi_bearish = rsi < 50 and rsi > 30 and rsi_momentum < 0
        
        momentum_state = 1 if (wt_bullish or rsi_bullish) else -1 if (wt_bearish or rsi_bearish) else 0
        
        # Bias
        price_above = close > ma_fast and close > ma_slow
        price_below = close < ma_fast and close < ma_slow
        
        bullish_bias = (30 if ma_bullish_stack else 0) + (20 if price_above else 0) + (15 if close > ma_anchor else 0)
        bearish_bias = (30 if ma_bearish_stack else 0) + (20 if price_below else 0) + (15 if close < ma_anchor else 0)
        
        net_bias = bullish_bias - bearish_bias
        bias_direction = 1 if net_bias > self.i_bias_threshold / 2 else -1 if net_bias < -self.i_bias_threshold / 2 else 0
        
        # Squeeze detection
        bb_upper = self.bb_upper[-1] if len(self.bb_upper) > 0 else high
        bb_lower = self.bb_lower[-1] if len(self.bb_lower) > 0 else low
        kc_upper = bb_upper - (bb_upper - bb_lower) * 0.3
        kc_lower = bb_lower + (bb_upper - bb_lower) * 0.3
        
        squeeze_on = bb_lower > kc_lower and bb_upper < kc_upper
        
        # Confluence scoring
        bull_confluence = 0
        bull_confluence += 2 if (market_regime == 1 and trend_direction == 1) else 0
        bull_confluence += 1 if (structure_bias == 1) else 0
        bull_confluence += 2 if (momentum_state == 1) else 0
        bull_confluence += 2 if (bias_direction == 1) else 0
        
        bear_confluence = 0
        bear_confluence += 2 if (market_regime == 1 and trend_direction == -1) else 0
        bear_confluence += 1 if (structure_bias == -1) else 0
        bear_confluence += 2 if (momentum_state == -1) else 0
        bear_confluence += 2 if (bias_direction == -1) else 0
        
        # Signal triggers
        bull_trigger = crossover(self.data.Close, self.ma_fast) or (wt1 > wt2 and wt_bullish)
        bear_trigger = crossover(self.ma_fast, self.data.Close) or (wt1 < wt2 and wt_bearish)
        
        # Final signals
        bull_qualified = bull_confluence >= self.i_min_confluence
        bear_qualified = bear_confluence >= self.i_min_confluence
        
        long_signal = (bull_qualified and bull_trigger and bars_since_long > self.i_signal_cooldown 
                      and market_regime != 3)
        short_signal = (bear_qualified and bear_trigger and bars_since_short > self.i_signal_cooldown 
                       and market_regime != 3)
        
        # Risk calculation
        long_stop = max(low - atr_val * 2, low - atr_val * 0.2)
        short_stop = min(high + atr_val * 2, high + atr_val * 0.2)
        
        # Execute trades
        if long_signal and not self.position:
            self.buy()
            self.last_long_signal_bar = current_bar
        
        elif short_signal and not self.position:
            self.sell()
            self.last_short_signal_bar = current_bar
        
        # Exit logic - simple profit taking or stop loss
        if self.position:
            if self.position.is_long:
                # Exit on reversal signal or after profit
                if short_signal or close < long_stop:
                    self.position.close()
            else:
                # Exit on reversal signal or after profit
                if long_signal or close > short_stop:
                    self.position.close()


