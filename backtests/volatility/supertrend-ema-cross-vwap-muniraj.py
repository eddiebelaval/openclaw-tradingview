import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 9
    emaSlowLen = 21
    atrPeriod = 10
    atrMult = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)
        self.vwap = self.I(pta.vwap, close, volume)
        
        self.supertrend_direction = self.I(self._calculate_supertrend_direction, high, low, close)
        
    def _calculate_supertrend_direction(self, high, low, close):
        hl2 = (high + low) / 2
        atr = pta.atr(high, low, close, length=self.atrPeriod)
        
        if atr is None:
            return pd.Series(0, index=close.index)
        
        basic_ub = hl2 + self.atrMult * atr
        basic_lb = hl2 - self.atrMult * atr
        
        final_ub = basic_ub.copy()
        final_lb = basic_lb.copy()
        
        for i in range(1, len(basic_ub)):
            final_ub.iloc[i] = min(basic_ub.iloc[i], final_ub.iloc[i-1]) if close.iloc[i-1] > final_ub.iloc[i-1] else basic_ub.iloc[i]
            final_lb.iloc[i] = max(basic_lb.iloc[i], final_lb.iloc[i-1]) if close.iloc[i-1] < final_lb.iloc[i-1] else basic_lb.iloc[i]
        
        direction = pd.Series(1, index=close.index)
        for i in range(1, len(close)):
            if close.iloc[i] <= final_ub.iloc[i]:
                direction.iloc[i] = 1
            elif close.iloc[i] >= final_lb.iloc[i]:
                direction.iloc[i] = -1
            else:
                direction.iloc[i] = direction.iloc[i-1]
        
        return direction

    def next(self):
        if len(self.data) < max(self.emaFastLen, self.emaSlowLen, self.atrPeriod) + 1:
            return
        
        emaFast_val = self.emaFast[-1]
        emaSlow_val = self.emaSlow[-1]
        vwap_val = self.vwap[-1]
        close_val = self.data.Close[-1]
        direction_val = self.supertrend_direction[-1]
        
        if emaFast_val is None or emaSlow_val is None or vwap_val is None:
            return
        
        emaBull = emaFast_val > emaSlow_val
        emaBear = emaFast_val < emaSlow_val
        
        superBull = direction_val == 1
        superBear = direction_val == -1
        
        vwapBull = close_val > vwap_val
        vwapBear = close_val < vwap_val
        
        buySignal = emaBull and superBull and vwapBull
        sellSignal = emaBear and superBear and vwapBear
        
        if buySignal and not self.position:
            self.buy()
        elif sellSignal and self.position:
            self.position.close()


