import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen1 = 8
    emaLen2 = 20
    emaLen3 = 50
    emaLen4 = 200
    atrLen = 14
    rvolLen = 20
    bandDev1 = 1.0
    bandDev2 = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.ema1 = self.I(pta.ema, close, length=self.emaLen1)
        self.ema2 = self.I(pta.ema, close, length=self.emaLen2)
        self.ema3 = self.I(pta.ema, close, length=self.emaLen3)
        self.ema4 = self.I(pta.ema, close, length=self.emaLen4)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        def calc_rvol():
            sma_vol = pta.sma(volume, length=self.rvolLen)
            if sma_vol is not None:
                rvol = volume / sma_vol
                rvol = rvol.fillna(0)
                return rvol
            return pd.Series(0, index=volume.index)
        
        self.rvol = self.I(calc_rvol)
        
        def calc_vwap_bands():
            cum_vol = volume.cumsum()
            cum_vol_src = (volume * close).cumsum()
            cum_vol_src2 = (volume * close * close).cumsum()
            
            vwap = cum_vol_src / cum_vol
            vwap = vwap.fillna(close)
            
            variance = (cum_vol_src2 / cum_vol) - (vwap * vwap)
            variance = variance.clip(lower=0)
            stdev = np.sqrt(variance)
            
            vwap_upper1 = vwap + stdev * self.bandDev1
            vwap_lower1 = vwap - stdev * self.bandDev1
            vwap_upper2 = vwap + stdev * self.bandDev2
            vwap_lower2 = vwap - stdev * self.bandDev2
            
            return vwap, vwap_upper1, vwap_lower1, vwap_upper2, vwap_lower2
        
        self.vwap_data = self.I(calc_vwap_bands)

