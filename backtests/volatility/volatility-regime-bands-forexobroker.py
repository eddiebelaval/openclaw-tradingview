import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Regime Detection
    adx_len = 14
    adx_thresh = 25
    adx_weak = 18
    regime_smooth = 8
    
    # Band Settings
    band_length = 20
    atr_mult = 1.5
    bb_mult = 2.0
    
    # Signals
    enable_signals = True
    enable_squeeze = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ADX for trend detection
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_len))
        self.adx = adx_result
        
        # ATR for volatility
        atr_result = self.I(lambda: pta.atr(high, low, close, length=self.adx_len))
        self.atr = atr_result
        
        # Center line (EMA)
        center_result = self.I(pta.ema, close, length=self.band_length)
        self.center_line = center_result
        
        # Bollinger Bands for squeeze detection
        bb_result = self.I(lambda: pta.bbands(close, length=self.band_length, std=self.bb_mult))
        self.bb_upper = self.I(lambda: pta.bbands(close, length=self.band_length, std=self.bb_mult)['BBU_20_2.0'])
        self.bb_lower = self.I(lambda: pta.bbands(close, length=self.band_length, std=self.bb_mult)['BBL_20_2.0'])
        
        # Keltner Channels for squeeze detection
        kc_result = self.I(lambda: pta.kc(high, low, close, length=self.band_length, scalar=1.5))
        self.kc_upper = self.I(lambda: pta.kc(high, low, close, length=self.band_length, scalar=1.5)['KCU_20_1.5'])
        self.kc_lower = self.I(lambda: pta.kc(high, low, close, length=self.band_length, scalar=1.5)['KCL_20_1.5'])
        
        # Standard deviation
        std_result = self.I(lambda: close.rolling(self.band_length).std())
        self.std_dev = std_result
        
        # Band width calculation
        self.band_width = self.I(lambda: pd.Series(
            np.where(self.atr[-len(close):] * self.atr_mult > 0, 
                    0.2 * self.atr[-len(close):] * self.atr_mult + 0.8 * self.std_dev[-len(close):] * self.bb_mult,
                    0), 
            index=close.index))
        
        # Smoothed band width
        self.smooth_band = self.I(lambda: pd.Series(self.band_width[-len(close):]).ewm(span=self.regime_smooth).mean())
        
        # Upper and lower bands
        self.upper_band = self.I(lambda: self.center_line[-len(close):] + self.smooth_band[-len(close):])
        self.lower_band = self.I(lambda: self.center_line[-len(close):] - self.smooth_band[-len(close):])
        
        # Regime detection
        self.regime = self.I(lambda: self._detect_regime(high, low, close))
        
        # Squeeze detection
        self.squeeze_on = self.I(lambda: self._squeeze_detection(high, low, close))
        
        # Signal tracking
        self.prev_close_above_upper = False
        self.prev_close_below_lower = False

    def _detect_regime(self, high, low, close):
        """Detect market regime: 0=Trending, 1=Ranging, 2=Volatile"""
        adx = pta.adx(high, low, close, length=self.adx_len)
        if adx is None or len(adx) == 0:
            return pd.Series(1, index=close.index)
        
        adx_vals = adx.fillna(20)
        
        # Simple regime based on ADX
        regime = pd.Series(1, index=close.index)
        regime[adx_vals > self.adx_thresh] = 0
        regime[adx_vals < self.adx_weak] = 1
        
        return regime.ewm(span=self.regime_smooth).mean()

    def _squeeze_detection(self, high, low, close):
        """Detect BB inside KC squeeze"""
        bb = pta.bbands(close, length=self.band_length, std=self.bb_mult)
        kc = pta.kc(high, low, close, length=self.band_length, scalar=1.5)
        
        if bb is None or kc is None:
            return pd.Series(False, index=close.index)
        
        bb_low = bb['BBL_20_2.0']
        bb_up = bb['BBU_20_2.0']
        kc_low = kc['KCL_20_1.5']
        kc_up = kc['KCU_20_1.5']
        
        squeeze = (bb_low > kc_low) & (bb_up < kc_up)
        return squeeze

    def next(self):
        # Current values
        close = self.data.Close[-1]
        upper = self.upper_band[-1] if self.upper_band[-1] == self.upper_band[-1] else close
        lower = self.lower_band[-1] if self.lower_band[-1] == self.lower_band[-1] else close
        center = self.center_line[-1] if self.center_line[-1] == self.center_line[-1] else close
        regime = self.regime[-1] if len(self.regime) > 0 else 1
        squeeze = self.squeeze_on[-1] if len(self.squeeze_on) > 0 else False
        
        if np.isnan(upper) or np.isnan(lower) or np.isnan(center):
            return
        
        # Skip volatile regime
        if regime > 1.5:
            return
        
        # Trending regime signals (breakout)
        if regime < 0.5:
            if close > upper and not self.prev_close_above_upper:
                if not self.position:
                    self.buy()
                self.prev_close_above_upper = True
            elif close < lower and not self.prev_close_below_lower:
                if self.position:
                    self.position.close()
                self.prev_close_below_lower = True
            else:
                self.prev_close_above_upper = False
                self.prev_close_below_lower = False
        
        # Ranging regime signals (mean reversion)
        else:
            if close <= lower and self.data.Close[-2] > self.lower_band[-2]:
                if not self.position:
                    self.buy()
                self.prev_close_below_lower = True
            elif close >= upper and self.data.Close[-2] < self.upper_band[-2]:
                if self.position:
                    self.position.close()
                self.prev_close_above_upper = True
            else:
                self.prev_close_above_upper = False
                self.prev_close_below_lower = False
        
        # Squeeze fire signals
        if self.enable_squeeze and len(self.squeeze_on) > 1:
            if not squeeze and self.squeeze_on[-2]:
                # Squeeze just fired
                momentum = self.data.Close[-1] - self.data.Close[-2]
                if momentum > 0 and not self.position:
                    self.buy()
                elif momentum < 0 and self.position:
                    self.position.close()


