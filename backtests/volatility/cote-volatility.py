import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLength = 14
    multiplier = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # Calculate candle range
        self.candleRange = self.I(lambda: high - low)
        
        # Volatility spike detection
        self.volatilitySpike = self.I(lambda: self.candleRange >= self.atr * self.multiplier)
        
        # Bear and bull spike detection
        self.bearSpike = self.I(lambda: (self.candleRange >= self.atr * self.multiplier) & (close <= pd.Series(self.data.Open)))
        self.bullSpike = self.I(lambda: (self.candleRange >= self.atr * self.multiplier) & (close > pd.Series(self.data.Open)))

    def next(self):
        # Buy on bull spike (volatility spike with close > open)
        if self.bullSpike[-1]:
            if not self.position:
                self.buy()
        
        # Sell on bear spike (volatility spike with close < open) or exit long
        elif self.bearSpike[-1]:
            if self.position:
                self.position.close()