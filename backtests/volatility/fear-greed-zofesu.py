import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback_cal = 300
    vol_target = 98

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        ohlc4 = (self.data.Open + high + low + close) / 4
        
        # Calculate greed raw: (source - lowest(source, 30)) / source
        lowest_30 = self.I(lambda: ohlc4.rolling(30).min())
        self.g_raw = self.I(lambda: (ohlc4 - lowest_30) / ohlc4.replace(0, 1e-6))
        
        # Calculate fear raw: (highest(source, 30) - source) / source
        highest_30 = self.I(lambda: ohlc4.rolling(30).max())
        self.f_raw = self.I(lambda: (highest_30 - ohlc4) / ohlc4.replace(0, 1e-6))
        
        # Percentile rank calculations
        self.g_rank = self.I(lambda: self._percentrank(self.g_raw, self.lookback_cal))
        self.f_rank = self.I(lambda: self._percentrank(self.f_raw, self.lookback_cal))
        self.v_rank = self.I(lambda: self._percentrank(volume, self.lookback_cal))
        
        # Greed and fear signals
        self.curr_greed = self.I(lambda: (self.g_rank > 94) & (self.v_rank > self.vol_target))
        self.curr_fear = self.I(lambda: (self.f_rank > 94) & (self.v_rank > self.vol_target))
        
        self.greed_signal = False
        self.fear_signal = False

    def _percentrank(self, series, lookback):
        """Calculate percentile rank over lookback period"""
        result = pd.Series(index=series.index, dtype=float)
        for i in range(len(series)):
            if i < lookback:
                window = series.iloc[:i+1]
            else:
                window = series.iloc[i-lookback+1:i+1]
            if len(window) > 0:
                result.iloc[i] = (window < series.iloc[i]).sum() / len(window) * 100
            else:
                result.iloc[i] = 0
        return result

    def next(self):
        # Detect greed signal (transition from False to True)
        curr_greed_val = bool(self.curr_greed[-1]) if len(self.curr_greed) > 0 else False
        prev_greed_val = bool(self.curr_greed[-2]) if len(self.curr_greed) > 1 else False
        
        curr_fear_val = bool(self.curr_fear[-1]) if len(self.curr_fear) > 0 else False
        prev_fear_val = bool(self.curr_fear[-2]) if len(self.curr_fear) > 1 else False
        
        greed_detected = curr_greed_val and not prev_greed_val
        fear_detected = curr_fear_val and not prev_fear_val
        
        # Trading logic: Buy on greed detection, sell on fear detection
        if greed_detected:
            if not self.position:
                self.buy()
        
        if fear_detected:
            if self.position:
                self.sell()


