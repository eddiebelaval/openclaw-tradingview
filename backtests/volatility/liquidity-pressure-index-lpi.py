import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vol_len = 20
    atr_len = 14
    smooth = 5
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # VWAP calculation
        hlc3 = (high + low + close) / 3
        self.vwap = self.I(pta.vwap, high, low, close)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Volume Score
        vol_avg = self.I(pta.sma, volume, length=self.vol_len)
        self.vol_score = self.I(lambda: volume / (vol_avg + 1e-8))
        
        # OI Score - using close as proxy since we don't have external OI data
        self.oi_score = self.I(lambda: pd.Series(
            [(close.iloc[i] - close.iloc[i-1]) / (close.iloc[i-1] + 1e-8) * 10 
             if i > 0 else 0 for i in range(len(close))],
            index=close.index
        ))
        
        # Range Score
        candle_range = high - low
        self.range_score = self.I(lambda: candle_range / (self.atr + 1e-8))
        
        # VWAP Distance Score
        dist = self.I(lambda: np.abs(close - (self.vwap or close)))
        self.vwap_score = self.I(lambda: dist / (self.atr + 1e-8))
        
        # Raw LPI
        self.raw_lpi = self.I(lambda: (
            (self.vol_score[-1] if self.vol_score[-1] is not None else 1) +
            (self.oi_score[-1] if self.oi_score[-1] is not None else 0) +
            (self.range_score[-1] if self.range_score[-1] is not None else 0) +
            (self.vwap_score[-1] if self.vwap_score[-1] is not None else 0)
        ) for _ in range(len(close)))
        
        # LPI EMA
        self.lpi = self.I(pta.ema, self.raw_lpi, length=self.smooth)
        
        # Bull and Bear Pressure
        self.bull_pressure = self.I(lambda: pd.Series(
            [(self.lpi[i] if close.iloc[i] > (self.vwap[i] if self.vwap[i] is not None else close.iloc[i]) else 0) 
             for i in range(len(close))],
            index=close.index
        ))
        
        self.bear_pressure = self.I(lambda: pd.Series(
            [(self.lpi[i] if close.iloc[i] < (self.vwap[i] if self.vwap[i] is not None else close.iloc[i]) else 0) 
             for i in range(len(close))],
            index=close.index
        ))
    
    def next(self):
        # Buy signal: Bull pressure crosses above 2 (low pressure threshold)
        if self.bull_pressure[-1] > 2 and (len(self) < 2 or self.bull_pressure[-2] <= 2):
            if not self.position:
                self.buy()
        
        # Strong buy signal: LPI crosses above 4 (expansion)
        elif self.lpi[-1] > 4 and (len(self) < 2 or self.lpi[-2] <= 4):
            if not self.position:
                self.buy()
        
        # Sell signal: Bear pressure > 0 (close below VWAP with pressure)
        elif self.bear_pressure[-1] > 0:
            if self.position:
                self.position.close()
        
        # Exit on LPI drop below 2
        elif self.lpi[-1] < 2:
            if self.position:
                self.position.close()