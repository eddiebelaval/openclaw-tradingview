import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trade Settings
    account_size = 10000
    risk_percent = 1.0
    
    # ATR Settings
    len_atr = 14
    
    # ATR Multipliers
    mult_sl = 1.5
    mult_t1 = 2.0
    mult_t2 = 3.0
    mult_t3 = 4.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.len_atr)
        
    def next(self):
        if len(self) < self.len_atr:
            return
        
        # Current values
        current_price = self.data.Close[-1]
        current_atr = self.atr[-1]
        
        if current_atr is None or np.isnan(current_atr):
            return
        
        # Calculate levels
        sl_price = current_price - current_atr * self.mult_sl
        t1_price = current_price + current_atr * self.mult_t1
        t2_price = current_price + current_atr * self.mult_t2
        t3_price = current_price + current_atr * self.mult_t3
        
        # Risk calculations
        risk_distance = abs(current_price - sl_price)
        risk_amount = self.account_size * (self.risk_percent / 100)
        
        if risk_distance > 0:
            position_size = risk_amount / risk_distance
        else:
            position_size = 0
        
        # Entry logic: Buy on new bar if not already in position
        if not self.position:
            self.buy(size=position_size)
        
        # Exit logic: Close position at target 3 or stop loss
        elif self.position:
            if self.data.Close[-1] >= t3_price:
                self.position.close()
            elif self.data.Close[-1] <= sl_price:
                self.position.close()


