import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Fear score core components
        self.pct_lookback = 252
        self.z_lookback = 63
        self.shock_lookback = 21
        self.z_cap = 2.5
        self.shock_cap = 2.5
        self.trend_cap = 12.0
        self.w_pct = 0.40
        self.w_z = 0.25
        self.w_shock = 0.20
        self.w_trend = 0.15
        
        # Fear TF parameters
        self.fear_fast_len = 13
        self.fear_slow_len = 55
        
        # Direction parameters
        self.dir_fast_len = 13
        self.dir_slow_len = 55
        self.dir_basis_len = 21
        self.dir_mom_len = 8
        self.dir_atr_len = 14
        self.dir_smooth_len = 3
        self.flow_norm_len = 120
        self.dir_neutral_band = 0.08
        
        # Gate parameters
        self.single_lane_fear_thr = 65.0
        self.term_layer_thr = 61.0
        self.contagion_layer_thr = 62.0
        self.tail_layer_thr = 60.0
        self.composite_fear_thr = 63.0
        self.breadth_thr = 0.33
        self.required_hot_layers = 2
        self.min_active_lanes = 8
        self.layer_w_term = 0.45
        self.layer_w_contagion = 0.35
        self.layer_w_tail = 0.20
        
        # Calculate percentrank
        def percentrank(series, period):
            def _percentrank(x):
                if len(x) < period:
                    return np.nan
                return (x.iloc[-period:] < x.iloc[-1]).sum() / period * 100
            return series.rolling(period).apply(_percentrank, raw=False)
        
        # Calculate fear score for a given source
        def calc_fear_score(src):
            pct = percentrank(src, self.pct_lookback)
            mu_z = pta.sma(src, length=self.z_lookback)
            sd_z = src.rolling(self.z_lookback).std()
            z = (src - mu_z) / sd_z.replace(0, np.nan)
            z = z.fillna(0)
            
            shock_raw = src.pct_change()
            mu_s = pta.sma(shock_raw, length=self.shock_lookback)
            sd_s = shock_raw.rolling(self.shock_lookback).std()
            shock_z = (shock_raw - mu_s) / sd_s.replace(0, np.nan)
            shock_z = shock_z.fillna(0)
            
            fast = pta.ema(src, length=self.fear_fast_len)
            slow = pta.ema(src, length=self.fear_slow_len)
            trend = ((fast - slow) / slow.abs().replace(0, np.nan)) * 100
            trend = trend.fillna(0)
            
            pct_n = pct.fillna(50)
            z_n = 50.0 + 50.0 * np.clip(z / self.z_cap, -1, 1)
            shock_n = 50.0 + 50.0 * np.clip(shock_z / self.shock_cap, -1, 1)
            trend_n = 50.0 + 50.0 * np.clip(trend / self.trend_cap, -1, 1)
            
            w_sum = max(self.w_pct + self.w_z + self.w_shock + self.w_trend, 0.0001)
            score = (self.w_pct * pct_n + self.w_z * z_n + self.w_shock * shock_n + self.w_trend * trend_n) / w_sum
            
            return score
        
        # VIX proxy - use close as simple approximation
        self.vix_score = self.I(calc_fear_score, close)
        
        # Price direction components
        self.atr = self.I(pta.atr, high, low, close, length=self.dir_atr_len)
        self.basis = self.I(pta.ema, (high + low + close) / 3, length=self.dir_basis_len)
        self.fast_ma = self.I(pta.ema, close, length=self.dir_fast_len)
        self.slow_ma = self.I(pta.ema, close, length=self.dir_slow_len)
        
        # OBV and CVD
        self.obv = self.I(lambda: pta.obv(close, pd.Series(self.data.Volume)))
        
        # Simple pressure signal
        self.pressure = self.I(lambda: pta.ema(
            np.clip((self.fast_ma - self.slow_ma) / (self.atr * 2.5 + 1e-9), -1, 1) * 100,
            length=self.dir_smooth_len
        ))

    def next(self):
        if len(self) < max(self.pct_lookback, self.fear_slow_len + 50):
            return
        
        # Get current values
        vix = self.vix_score[-1]
        pressure = self.pressure[-1] if len(self.pressure) > 0 else 0
        
        # Simple trading logic
        # Buy signal: VIX cooling (below threshold) and positive pressure
        # Sell signal: VIX heating (above threshold) or negative pressure
        
        if not np.isnan(vix):
            # Risk-off signal when VIX is hot
            risk_off = vix >= self.composite_fear_thr
            
            # Direction signal
            bullish = pressure > 0
            bearish = pressure < 0
            
            # Entry conditions
            if bullish and not risk_off and not self.position:
                self.buy()
            elif (bearish or risk_off) and self.position:
                self.position.close()