import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from datetime import datetime
import pytz


class TvStrategy(Strategy):
    step = 500
    offset = 50
    slPts = 80
    tgt1 = 60
    tgt2 = 160
    beTrigger = 90
    emaLen = 50

    def init(self):
        close = pd.Series(self.data.Close)
        self.ema = self.I(pta.ema, close, length=self.emaLen)

    def next(self):
        current_close = self.data.Close[-1]
        current_low = self.data.Low[-1]
        current_high = self.data.High[-1]
        current_ema = self.ema[-1]
        current_time = self.data.index[-1]

        ista_tz = pytz.timezone("Asia/Kolkata")
        current_time_ista = current_time.astimezone(ista_tz)

        start_hour = 9
        start_minute = 30
        end_hour = 15
        end_minute = 10

        start_time = current_time_ista.replace(hour=start_hour, minute=start_minute, second=0, microsecond=0)
        end_time = current_time_ista.replace(hour=end_hour, minute=end_minute, second=0, microsecond=0)

        in_session = start_time <= current_time_ista <= end_time
        session_end = current_time_ista >= end_time

        roundBase = np.floor(current_close / self.step) * self.step
        upperLevel = roundBase + self.offset
        lowerLevel = roundBase - self.offset

        flatMarket = abs(current_close - current_ema) < 300

        longCond = in_session and flatMarket and current_low <= lowerLevel and current_close > lowerLevel
        shortCond = in_session and flatMarket and current_high >= upperLevel and current_close < upperLevel

        if longCond and not self.position:
            self.buy()

        if shortCond and not self.position:
            self.sell()

        if self.position.size > 0:
            entry = self.position.open_price
            hardStop = entry - self.slPts
            beStop = entry if self.data.High[-1] >= entry + self.beTrigger else hardStop

            if current_close >= entry + self.tgt1:
                self.position.close(0.5)

            if current_close >= entry + self.tgt2:
                self.position.close()
            elif current_close <= beStop:
                self.position.close()

            if session_end:
                self.position.close()

        if self.position.size < 0:
            entry = self.position.open_price
            hardStop = entry + self.slPts
            beStop = entry if self.data.Low[-1] <= entry - self.beTrigger else hardStop

            if current_close <= entry - self.tgt1:
                self.position.close(0.5)

            if current_close <= entry - self.tgt2:
                self.position.close()
            elif current_close >= beStop:
                self.position.close()

            if session_end:
                self.position.close()


