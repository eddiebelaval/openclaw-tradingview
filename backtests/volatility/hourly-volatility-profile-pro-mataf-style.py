import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    weeks_lookback = 10
    peak_multiplier = 1.3

    def init(self):
        self.hourly_vol = []
        self.hourly_count = [0] * 24
        self.hourly_sum = [0.0] * 24
        self.avg_vol_array = [0.0] * 24
        self.current_hour_vol = 0
        self.global_avg = 0
        self.is_peak = False
        self.is_medium = False

    def next(self):
        current_bar = len(self.data) - 1
        
        high = self.data.High[current_bar]
        low = self.data.Low[current_bar]
        
        vol = high - low
        
        current_time = self.data.index[current_bar]
        h = current_time.hour
        
        self.hourly_sum[h] += vol
        self.hourly_count[h] += 1
        
        for i in range(24):
            c = self.hourly_count[i]
            v = self.hourly_sum[i]
            avg = v / c if c > 0 else 0
            self.avg_vol_array[i] = avg
        
        self.current_hour_vol = self.avg_vol_array[h]
        
        if current_bar >= 23:
            recent_vols = self.avg_vol_array[-24:] if len(self.avg_vol_array) >= 24 else self.avg_vol_array
            self.global_avg = np.mean(recent_vols) if recent_vols else 0
        else:
            self.global_avg = np.mean(self.avg_vol_array[:current_bar + 1]) if current_bar >= 0 else 0
        
        self.is_peak = self.current_hour_vol > self.global_avg * self.peak_multiplier if self.global_avg > 0 else False
        self.is_medium = self.current_hour_vol > self.global_avg and not self.is_peak if self.global_avg > 0 else False
        
        if self.is_peak:
            if not self.position:
                self.buy()
            elif self.position.size > 0:
                self.position.close()
        elif self.is_medium:
            if self.position and self.position.size > 0:
                self.position.close()
        else:
            if self.position and self.position.size > 0:
                self.position.close()


