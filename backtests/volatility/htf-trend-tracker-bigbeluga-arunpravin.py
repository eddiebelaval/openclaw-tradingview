import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        self.htf_high = None
        self.htf_low = None
        self.trend = False
        self.last_timeframe_change = -1
        self.count = 0

    def next(self):
        current_idx = len(self.data) - 1
        
        # Simulate HTF change detection (daily timeframe on daily data)
        # For daily data, consider each bar as a complete HTF candle
        if current_idx == 0 or current_idx != self.last_timeframe_change:
            self.last_timeframe_change = current_idx
            
            # Get highest high and lowest low for current HTF period
            lookback = min(20, current_idx + 1)
            htf_high = np.max(self.data.High[-lookback:])
            htf_low = np.min(self.data.Low[-lookback:])
            
            self.htf_high = htf_high
            self.htf_low = htf_low
        
        if self.htf_high is None or self.htf_low is None:
            return
        
        close = self.data.Close[-1]
        
        # Trend logic: crossover HTF high = bullish, crossunder HTF low = bearish
        if close > self.htf_high and not self.trend:
            self.trend = True
            if not self.position:
                self.buy()
        
        if close < self.htf_low and self.trend:
            self.trend = False
            if self.position:
                self.position.close()
            self.sell()


