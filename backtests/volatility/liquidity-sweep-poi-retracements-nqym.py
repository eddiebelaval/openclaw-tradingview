import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    use_htf = True
    pivot_len = 15
    use_fvg = True
    fvg_mitigation = "Close"  # "Touch", "Close", or "50% Level"
    max_poi_age = 20
    
    def init(self):
        self.active_liquidity = []
        self.active_pois = []
        self.last_ssl_sweep = -100
        self.last_bsl_sweep = -100
        
        # Pre-calculate pivot highs and lows for all bars
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.pivot_highs = self._calculate_pivot_highs(high, self.pivot_len)
        self.pivot_lows = self._calculate_pivot_lows(low, self.pivot_len)
        
        # HTF data (simulated as higher timeframe equivalents)
        self.h1_highs = high.rolling(window=60, min_periods=1).max()
        self.h1_lows = low.rolling(window=60, min_periods=1).min()
        self.h4_highs = high.rolling(window=240, min_periods=1).max()
        self.h4_lows = low.rolling(window=240, min_periods=1).min()
    
    def _calculate_pivot_highs(self, high, lookback):
        """Calculate pivot highs"""
        pivot = pd.Series(np.nan, index=high.index)
        for i in range(lookback, len(high) - lookback):
            if high.iloc[i] > high.iloc[i-lookback:i].max() and high.iloc[i] >= high.iloc[i+1:i+lookback+1].max():
                pivot.iloc[i] = high.iloc[i]
        return pivot
    
    def _calculate_pivot_lows(self, low, lookback):
        """Calculate pivot lows"""
        pivot = pd.Series(np.nan, index=low.index)
        for i in range(lookback, len(low) - lookback):
            if low.iloc[i] < low.iloc[i-lookback:i].min() and low.iloc[i] <= low.iloc[i+1:i+lookback+1].min():
                pivot.iloc[i] = low.iloc[i]
        return pivot
    
    def next(self):
        idx = len(self.data) - 1
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        if idx < self.pivot_len * 2:
            return
        
        ssl_swept = False
        bsl_swept = False
        
        # Check pivot-based liquidity sweeps
        if not pd.isna(self.pivot_lows.iloc[idx]):
            pl = self.pivot_lows.iloc[idx]
            self.active_liquidity.append(('lower', pl, idx))
        
        if not pd.isna(self.pivot_highs.iloc[idx]):
            ph = self.pivot_highs.iloc[idx]
            self.active_liquidity.append(('upper', ph, idx))
        
        # Process active liquidity pools
        liquidity_to_remove = []
        for i, (pool_type, pool_price, bar_idx) in enumerate(self.active_liquidity):
            if pool_type == 'lower' and current_low < pool_price and current_close > pool_price:
                ssl_swept = True
                liquidity_to_remove.append(i)
            elif pool_type == 'upper' and current_high > pool_price and current_close < pool_price:
                bsl_swept = True
                liquidity_to_remove.append(i)
            elif (pool_type == 'upper' and current_close > pool_price) or (pool_type == 'lower' and current_close < pool_price):
                liquidity_to_remove.append(i)
        
        for i in sorted(liquidity_to_remove, reverse=True):
            self.active_liquidity.pop(i)
        
        # Check HTF sweeps
        if self.use_htf:
            h1_l = self.h1_lows.iloc[idx]
            h1_h = self.h1_highs.iloc[idx]
            h4_l = self.h4_lows.iloc[idx]
            h4_h = self.h4_highs.iloc[idx]
            
            ssl_swept = ssl_swept or (current_low < h1_l and current_close > h1_l) or (current_low < h4_l and current_close > h4_l)
            bsl_swept = bsl_swept or (current_high > h1_h and current_close < h1_h) or (current_high > h4_h and current_close < h4_h)
        
        # Track recent sweeps
        if ssl_swept:
            self.last_ssl_sweep = idx
        if bsl_swept:
            self.last_bsl_sweep = idx
        
        # FVG Detection
        buy_retrace = False
        sell_retrace = False
        
        if self.use_fvg and idx >= 2:
            prev_high_2 = self.data.High[-3]
            prev_low_2 = self.data.Low[-3]
            
            # Bullish FVG
            is_bullish_fvg = (current_low > prev_high_2 and current_close > current_open and 
                            (idx - self.last_ssl_sweep < 5))
            if is_bullish_fvg:
                top = current_low
                bottom = prev_high_2
                self.active_pois.append({
                    'top': top,
                    'bottom': bottom,
                    'is_bullish': True,
                    'start_bar': idx,
                    'active': True
                })
                self.last_ssl_sweep = -100
            
            # Bearish FVG
            is_bearish_fvg = (current_high < prev_low_2 and current_close < current_open and 
                            (idx - self.last_bsl_sweep < 5))
            if is_bearish_fvg:
                top = prev_low_2
                bottom = current_high
                self.active_pois.append({
                    'top': top,
                    'bottom': bottom,
                    'is_bullish': False,
                    'start_bar': idx,
                    'active': True
                })
                self.last_bsl_sweep = -100
        
        # Retracement Logic
        prev_high = self.data.High[-2] if idx >= 1 else current_high
        prev_low = self.data.Low[-2] if idx >= 1 else current_low
        
        pois_to_remove = []
        for i, poi in enumerate(self.active_pois):
            if not poi['active']:
                continue
            
            # Check age invalidation
            if idx - poi['start_bar'] > self.max_poi_age:
                pois_to_remove.append(i)
                continue
            
            mid = (poi['top'] + poi['bottom']) / 2
            
            if poi['is_bullish']:
                # Bullish POI retracement
                if prev_high > poi['top']:
                    if self.fvg_mitigation == "Touch":
                        condition = current_low <= poi['top']
                    elif self.fvg_mitigation == "50% Level":
                        condition = current_low <= mid
                    else:  # Close
                        condition = current_close <= poi['top'] and current_close >= poi['bottom']
                    
                    if condition:
                        buy_retrace = True
                        pois_to_remove.append(i)
                elif current_close < poi['bottom']:
                    pois_to_remove.append(i)
            else:
                # Bearish POI retracement
                if prev_low < poi['bottom']:
                    if self.fvg_mitigation == "Touch":
                        condition = current_high >= poi['bottom']
                    elif self.fvg_mitigation == "50% Level":
                        condition = current_high >= mid
                    else:  # Close
                        condition = current_close >= poi['bottom'] and current_close <= poi['top']
                    
                    if condition:
                        sell_retrace = True
                        pois_to_remove.append(i)
                elif current_close > poi['top']:
                    pois_to_remove.append(i)
        
        for i in sorted(pois_to_remove, reverse=True):
            self.active_pois.pop(i)
        
        # Trading Logic
        if buy_retrace and not self.position:
            self.buy()
        elif sell_retrace and self.position:
            self.position.close()
        
        # Simple stop-loss: if price closes in opposite direction of POI
        if self.position:
            if self.position.is_long and current_close < self.data.Close[-2] * 0.98:
                self.position.close()


