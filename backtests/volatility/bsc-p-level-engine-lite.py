import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 14
    lookback = 60
    use_atr_norm = True
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        self.anchor = None
        self.anchor_atr = None
        self.session_high = None
        self.session_low = None
        self.up_arr = []
        self.dn_arr = []
        self.p50 = None
        self.p75 = None
        self.n50 = None
        self.n75 = None
        self.hit_p75_up = False
        self.hit_p75_dn = False
        self.session_start_idx = 0
        
    def next(self):
        current_idx = len(self.data) - 1
        
        if self.anchor is None:
            self.anchor = self.data.Open[-1]
            self.anchor_atr = self.atr[-1] if self.atr[-1] is not None else 1.0
            self.session_high = self.data.High[-1]
            self.session_low = self.data.Low[-1]
            self.session_start_idx = current_idx
            return
        
        self.session_high = max(self.session_high, self.data.High[-1])
        self.session_low = min(self.session_low, self.data.Low[-1])
        
        if current_idx - self.session_start_idx >= 390:
            up_move_raw = max(self.session_high - self.anchor, 0)
            dn_move_raw = max(self.anchor - self.session_low, 0)
            
            if self.use_atr_norm and self.anchor_atr and self.anchor_atr > 0:
                up_stored = up_move_raw / self.anchor_atr
                dn_stored = dn_move_raw / self.anchor_atr
            else:
                up_stored = up_move_raw
                dn_stored = dn_move_raw
            
            self.up_arr.append(up_stored)
            self.dn_arr.append(dn_stored)
            
            if len(self.up_arr) > self.lookback:
                self.up_arr.pop(0)
            if len(self.dn_arr) > self.lookback:
                self.dn_arr.pop(0)
            
            self.anchor = self.data.Open[-1]
            self.anchor_atr = self.atr[-1] if self.atr[-1] is not None else 1.0
            self.session_high = self.data.High[-1]
            self.session_low = self.data.Low[-1]
            self.session_start_idx = current_idx
            self.hit_p75_up = False
            self.hit_p75_dn = False
            
            if len(self.up_arr) >= 3:
                sorted_up = sorted(self.up_arr)
                p50_idx = int(len(sorted_up) * 0.5)
                p75_idx = int(len(sorted_up) * 0.75)
                up_50_base = sorted_up[p50_idx]
                up_75_base = sorted_up[p75_idx]
                
                if self.use_atr_norm and self.anchor_atr:
                    self.p50 = self.anchor + up_50_base * self.anchor_atr
                    self.p75 = self.anchor + up_75_base * self.anchor_atr
                else:
                    self.p50 = self.anchor + up_50_base
                    self.p75 = self.anchor + up_75_base
            
            if len(self.dn_arr) >= 3:
                sorted_dn = sorted(self.dn_arr)
                n50_idx = int(len(sorted_dn) * 0.5)
                n75_idx = int(len(sorted_dn) * 0.75)
                dn_50_base = sorted_dn[n50_idx]
                dn_75_base = sorted_dn[n75_idx]
                
                if self.use_atr_norm and self.anchor_atr:
                    self.n50 = self.anchor - dn_50_base * self.anchor_atr
                    self.n75 = self.anchor - dn_75_base * self.anchor_atr
                else:
                    self.n50 = self.anchor - dn_50_base
                    self.n75 = self.anchor - dn_75_base
        
        if self.p75 is not None and self.data.High[-1] >= self.p75 and not self.hit_p75_up:
            self.hit_p75_up = True
            if not self.position:
                self.buy()
        
