class TvStrategy(Strategy):
    def init(self):
        # Parameters
        self.lookback = 1
        self.bull_color = True
        self.bear_color = True
        self.body_thresh = 0.50
        self.green_close_th = 0.75
        self.red_close_th = 0.25
        self.green_930_th = 0.75
        self.red_930_th = 0.25
        self.flush_mult = 1.50
        
        # State variables
        self.fh_open = None
        self.fh_high = None
        self.fh_low = None
        self.fh_close = None
        self.fh_range = None
        self.fh_start_bar = None
        self.fh_end_bar = None
        self.fh_valid = False
        self.fh_green = False
        self.fh_red = False
        self.price_930 = None
        self.has_930 = False
        self.bar_930 = None
        
        # Quality metrics
        self.body_ratio = None
        self.close_pos = None
        self.open_930_pos = None
        self.q_body = False
        self.q_close = False
        self.q_930 = False
        self.signal_grade = "—"
        self.fh_direction = "FLAT"
        
        # Breakout tracking
        self.broke_above = False
        self.broke_below = False
        self.break_bar = None
        self.break_in_1011 = False
        
        # Pullback tracking
        self.pullback_reached = False
        self.pb_deepest = 0.0
        self.pb_depth_pct = 0.0
        self.pb_invalidated = False
        
        # Reversal tracking
        self.rev_signal = False
        self.rev_hour = None
        self.rev_pct = None
        
        # Phase tracking
        self.phase = "WAITING"
        
        # Session tracking
        self.current_date = None
        self.in_fh = False
        self.fh_just_ended = False
        self.rth_start = False
        
    def next(self):
        # Get current bar info
        current_time = self.data.index[len(self.data) - 1]
        current_hour = current_time.hour
        current_minute = current_time.minute
        current_date = current_time.date()
        
        # Check for new day
        if self.current_date is not None and current_date != self.current_date:
            self._reset_day()
        self.current_date = current_date
        
        # Detect 9 AM - 10 AM window (ET)
        in_fh_now = (current_hour == 9 and current_minute < 60) or (current_hour == 9)
        
        # Detect FH just ended
        fh_just_ended = not in_fh_now and self.in_fh
        self.in_fh = in_fh_now
        
        # Detect RTH start (9:30 AM)
        rth_start = current_hour == 9 and current_minute == 30
        
        # Detect post-FH monitoring window
        in_rth = (current_hour >= 9 and current_hour < 16) and not (current_hour == 9 and current_minute < 30)
        post_fh = not in_fh_now and self.fh_valid and in_rth
        
        # Detect hour transitions
        hour_11_start = current_hour == 11 and current_minute == 0
        hour_12_start = current_hour == 12 and current_minute == 0
        hour_13_start = current_hour == 13 and current_minute == 0
        hour_14_start = current_hour == 14 and current_minute == 0
        hour_15_start = current_hour == 15 and current_minute == 0
        
        in_1011 = current_hour == 10
        
        # PHASE 1: CAPTURE 9:30 OPEN + BUILD FH CANDLE
        
        # Capture 9:30 open
        if rth_start and not self.has_930:
            self.price_930 = self.data.Close[-1]
            self.has_930 = True
            self.bar_930 = len(self.data) - 1
        
        # Build FH candle bar by bar
        if in_fh_now:
            self.phase = "FORMING"
            if self.fh_open is None:
                self.fh_open = self.data.Open[-1]
                self.fh_high = self.data.High[-1]
                self.fh_low = self.data.Low[-1]
                self.fh_start_bar = len(self.data) - 1
            else:
                self.fh_high = max(self.fh_high, self.data.High[-1])
                self.fh_low = min(self.fh_low, self.data.Low[-1])
            self.fh_close = self.data.Close[-1]
        
        # PHASE 2: FH COMPLETE — SCORE CANDLE QUALITY
        
        if fh_just_ended and not self.fh_valid:
            self.fh_valid = True
            self.fh_end_bar = len(self.data) - 2
            self.fh_range = self.fh_high - self.fh_low
            self.fh_green = self.fh_close > self.fh_open
            self.fh_red = self.fh_close < self.fh_open
            self.fh_direction = "LONG" if self.fh_green else "SHORT" if self.fh_red else "FLAT"
            
            # Calculate quality metrics
            if self.fh_range > 0:
                self.body_ratio = abs(self.fh_close - self.fh_open) / self.fh_range
                self.close_pos = (self.fh_close - self.fh_low) / self.fh_range
                if self.has_930:
                    self.open_930_pos = (self.price_930 - self.fh_low) / self.fh_range
            else:
                self.body_ratio = 0.0
                self.close_pos = 0.5
            
            # Grade quality filters
            self.q_body = self.body_ratio > self.body_thresh
            
            if not self.has_930:
                self.q_close = False
                self.q_930 = False
            elif self.fh_green:
                self.q_close = self.close_pos > self.green_close_th
                self.q_930 = self.open_930_pos < self.green_930_th if self.open_930_pos is not None else False
            elif self.fh_red:
                self.q_close = self.close_pos < self.red_close_th
                self.q_930 = self.open_930_pos > self.red_930_th if self.open_930_pos is not None else False
            else:
                self.q_close = False
                self.q_930 = False
            
