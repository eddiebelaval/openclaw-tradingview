        # Entry/exit based on signal grade and status
        
        # Long entry on A+ grade breakout confirmation
        if self.signal_grade == "A+" and self.fh_green and self.broke_above and self.break_in_1011:
            if self.pullback_reached and self.data.Low[-1] <= self.fh_high and not self.position:
                self.buy()
        
