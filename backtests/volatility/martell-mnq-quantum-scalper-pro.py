import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Central Parameters
    almaLength = 150
    almaOffset = 0.85
    almaSigma = 6.0
    
    chopLength = 14
    chopLimit = 50.0
    
    tsiLong = 25
    tsiShort = 13
    tsiSignal = 7
    
    atrPeriod = 14
    atrMult = 2.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ALMA - Macro Trend
        self.macroTrend = self.I(pta.alma, close, length=self.almaLength, 
                                  offset=self.almaOffset, sigma=self.almaSigma)
        
        # ATR for Choppiness and Risk Management
        self.atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)
        
        # Choppiness Index
        def calc_chop():
            result = pd.Series(50.0, index=close.index)
            for i in range(self.chopLength, len(close)):
                atr_sum = pta.atr(high.iloc[i-self.chopLength+1:i+1], 
                                  low.iloc[i-self.chopLength+1:i+1], 
                                  close.iloc[i-self.chopLength+1:i+1], 
                                  length=1)
                if atr_sum is not None:
                    atr_sum_val = atr_sum.sum()
                else:
                    atr_sum_val = 0
                
                highest = high.iloc[i-self.chopLength+1:i+1].max()
                lowest = low.iloc[i-self.chopLength+1:i+1].min()
                range_chop = highest - lowest
                
                if range_chop != 0 and atr_sum_val != 0:
                    result.iloc[i] = 100 * np.log10(atr_sum_val / range_chop) / np.log10(self.chopLength)
            return result
        
        self.chop = self.I(calc_chop)
        
        # True Strength Index
        pc = close.diff()
        
        def double_smooth(src, long, short):
            ema_short = pta.ema(src, length=short)
            if ema_short is None:
                return pd.Series(0, index=src.index)
            ema_long = pta.ema(ema_short, length=long)
            if ema_long is None:
                return pd.Series(0, index=src.index)
            return ema_long
        
        double_smoothed_pc = double_smooth(pc, self.tsiLong, self.tsiShort)
        double_smoothed_abs_pc = double_smooth(pc.abs(), self.tsiLong, self.tsiShort)
        
        def calc_tsi():
            result = pd.Series(0.0, index=close.index)
            for i in range(len(close)):
                if double_smoothed_abs_pc.iloc[i] != 0:
                    result.iloc[i] = 100 * (double_smoothed_pc.iloc[i] / double_smoothed_abs_pc.iloc[i])
            return result
        
        self.tsi = self.I(calc_tsi)
        self.tsiEma = self.I(pta.ema, self.tsi, length=self.tsiSignal)
        
        self.trade_state = 0  # 0 = Out, 1 = Long, -1 = Short
        self.entry_price = None
        self.sl_price = None
        self.tp_price = None

    def next(self):
        # Current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        macroTrend_val = self.macroTrend[-1] if len(self.macroTrend) > 0 else current_close
        chop_val = self.chop[-1] if len(self.chop) > 0 else 50
        atr_val = self.atr[-1] if len(self.atr) > 0 else 0
        tsi_val = self.tsi[-1] if len(self.tsi) > 0 else 0
        tsiEma_val = self.tsiEma[-1] if len(self.tsiEma) > 0 else 0
        
        is_trending = chop_val < self.chopLimit
        
        # Detect crossovers
        bullish_cross = False
        bearish_cross = False
        
        if len(self.tsi) > 1 and len(self.tsiEma) > 1:
            bullish_cross = crossover(self.tsi, self.tsiEma) and tsi_val < 0
            bearish_cross = crossover(self.tsiEma, self.tsi) and tsi_val > 0
        
        # Long and Short Conditions
        long_cond = current_close > macroTrend_val and is_trending and bullish_cross
        short_cond = current_close < macroTrend_val and is_trending and bearish_cross
        
        # Check if existing trade hits SL or TP
        if self.trade_state == 1:
            if current_high >= self.tp_price or current_low <= self.sl_price:
                self.trade_state = 0
                if self.position:
                    self.position.close()
        
        if self.trade_state == -1:
            if current_low <= self.tp_price or current_high >= self.sl_price:
                self.trade_state = 0
                if self.position:
                    self.position.close()
        
        # Enter new trades
        if long_cond and self.trade_state == 0:
            self.trade_state = 1
            self.entry_price = current_close
            self.sl_price = current_close - (atr_val * self.atrMult)
            self.tp_price = current_close + (atr_val * self.atrMult)
            self.buy()
        
        if short_cond and self.trade_state == 0:
            self.trade_state = -1
            self.entry_price = current_close
            self.sl_price = current_close + (atr_val * self.atrMult)
            self.tp_price = current_close - (atr_val * self.atrMult)
            self.sell()


