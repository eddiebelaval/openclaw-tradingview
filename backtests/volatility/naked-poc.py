import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    volType = "ZS-HV"
    threshold = 2.0
    volLen = 50
    use_peak = True
    lookback = 20
    peak_tol = 0.85
    prominence = 1.8
    min_range = 0.6
    use_rev = True
    wick_ratio = 0.38

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)

        # Calculate volume indicators
        self.vol_avg = self.I(pta.sma, volume, length=self.volLen)
        self.vol_stdev = self.I(
            lambda: pta.stdev(volume, length=self.volLen) or pd.Series(1.0, index=volume.index)
        )

        # Calculate rolling highest volume for peak detection
        self.highest_vol = self.I(
            lambda: volume.rolling(self.lookback).max() or pd.Series(0.0, index=volume.index)
        )

        # Calculate recent average volume for prominence
        self.recent_avg_vol = self.I(pta.sma, volume, length=5)

        # Calculate volume percentile rank
        self.vol_rank = self.I(
            lambda: volume.rolling(50).apply(
                lambda x: (x.iloc[-1] > x).sum() / len(x) * 100 if len(x) > 0 else 50
            ) or pd.Series(50.0, index=volume.index)
        )

        # Calculate price range
        self.price_range_pct = self.I(
            lambda: ((high - low) / close * 100).replace([np.inf, -np.inf], 0).fillna(0)
            if (close > 0).all()
            else pd.Series(0.0, index=close.index)
        )

        # Calculate candle body and wicks
        self.body = self.I(lambda: (close - open_).abs())
        self.range_k = self.I(lambda: high - low)
        self.wick_up = self.I(lambda: high - pd.concat([close, open_], axis=1).max(axis=1))
        self.wick_dn = self.I(lambda: pd.concat([close, open_], axis=1).min(axis=1) - low)

        # Store raw data for reference
        self.close = close
        self.high = high
        self.low = low
        self.open_ = open_
        self.volume = volume

    def next(self):
        if len(self.data) < self.volLen + self.lookback:
            return

        # Current values
        vol = self.volume.iloc[-1]
        vol_avg = self.vol_avg[-1] if self.vol_avg[-1] is not None else 1
        vol_stdev = self.vol_stdev[-1] if self.vol_stdev[-1] is not None else 1
        h = self.high.iloc[-1]
        l = self.low.iloc[-1]
        c = self.close.iloc[-1]
        o = self.open_.iloc[-1]

        # Calculate signal components
        z_val = (vol - vol_avg) / vol_stdev if vol_stdev != 0 else 0
        ratio_val = vol / vol_avg if vol_avg != 0 else 0

        # Candle pattern analysis
        range_k = self.range_k[-1] if self.range_k[-1] is not None else 0
        body_k = self.body[-1] if self.body[-1] is not None else 0
        wick_up = self.wick_up[-1] if self.wick_up[-1] is not None else 0
        wick_dn = self.wick_dn[-1] if self.wick_dn[-1] is not None else 0

        is_reversal_shape = (
            (wick_up > range_k * self.wick_ratio) or (wick_dn > range_k * self.wick_ratio)
            if range_k > 0
            else False
        )

        price_range_pct = self.price_range_pct[-1] if self.price_range_pct[-1] is not None else 0

        # Track signal detection
        is_panic_vol = (ratio_val >= 2.5) or (z_val >= 3.0)

        base_trigger = (z_val > self.threshold) if self.volType == "ZS-HV" else (ratio_val > self.threshold)

        recent_avg_vol = self.recent_avg_vol[-1] if self.recent_avg_vol[-1] is not None else 1
        is_prominent = vol > (recent_avg_vol * self.prominence)

        has_significant_range = price_range_pct >= self.min_range

        highest_vol = self.highest_vol[-1] if self.highest_vol[-1] is not None else vol
        is_near_peak = vol >= (highest_vol * self.peak_tol)

        vol_rank = self.vol_rank[-1] if self.vol_rank[-1] is not None else 50
        is_high_rank = vol_rank >= 85.0

        is_regular_vol = (
            base_trigger
            and is_prominent
            and has_significant_range
            and (not self.use_peak or is_near_peak or is_high_rank)
        )

        is_signal = is_panic_vol or is_regular_vol or (self.use_rev and base_trigger and is_reversal_shape)

        # Simple trading logic based on volume signal
        if is_signal:
            if not self.position:
                self.buy()
        else:
            if self.position:
                self.sell()