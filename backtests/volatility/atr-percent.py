import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14

    def init(self):
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        atr = self.I(pta.atr, high, low, close, length=self.length)
        self.atr_percent = self.I(lambda: (atr / close) * 100)

    def next(self):
        if len(self.data) < self.length + 1:
            return
        
        current_atr_percent = self.atr_percent[-1]
        
        if current_atr_percent is None or np.isnan(current_atr_percent):
            return
        
        if current_atr_percent > 5 and not self.position:
            self.buy()
        elif current_atr_percent < 2 and self.position:
            self.sell()


