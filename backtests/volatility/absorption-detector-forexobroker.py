import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Detection parameters
    volLen = 20
    volMult = 2.0
    maxBodyPct = 30.0
    minWickPct = 40.0
    atrLen = 14
    maxRangeATR = 1.5
    
    # Classification
    showPassive = True
    showAggress = True
    showExhaust = True
    
    # Signals
    minIntensity = 2
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # Calculate indicators
        self.avgVol = self.I(pta.sma, volume, length=self.volLen)
        self.atrVal = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Calculate bar properties
        self.barRng = self.I(lambda: high - low)
        self.bodySize = self.I(lambda: np.abs(close - open_))
        self.upperWick = self.I(lambda: high - np.maximum(close, open_))
        self.lowerWick = self.I(lambda: np.minimum(close, open_) - low)
        self.totalWick = self.I(lambda: self.upperWick[-1] + self.lowerWick[-1] if len(self.upperWick) > 0 else 0)
        
        # Ratios
        self.bodyPct = self.I(lambda: (self.bodySize[-1] / self.barRng[-1] * 100) if self.barRng[-1] > 0 else 100.0)
        self.wickPct = self.I(lambda: (self.totalWick / self.barRng[-1] * 100) if self.barRng[-1] > 0 else 0.0)
        self.volRatio = self.I(lambda: (volume[-1] / self.avgVol[-1]) if self.avgVol[-1] > 0 else 0.0)
        
        # Absorption detection
        self.isVolSpike = self.I(lambda: volume[-1] > self.avgVol[-1] * self.volMult and volume[-1] > 0)
        self.isContained = self.I(lambda: self.barRng[-1] <= self.atrVal[-1] * self.maxRangeATR and self.barRng[-1] > 0)
        
        # Direction bias
        self.bullWick = self.I(lambda: self.lowerWick[-1] > self.upperWick[-1])
        self.bearWick = self.I(lambda: self.upperWick[-1] > self.lowerWick[-1])
        
        # Engulfing detection
        self.bullEngulf = self.I(lambda: self._check_bull_engulf(close, open_))
        self.bearEngulf = self.I(lambda: self._check_bear_engulf(close, open_))
        
        # Absorption types
        self.passiveAbs = self.I(lambda: self._check_passive())
        self.aggressAbs = self.I(lambda: self._check_aggressive())
        self.exhaustAbs = self.I(lambda: self._check_exhaustion(volume))
        
        self.anyAbsorption = self.I(lambda: self._any_absorption())
        self.isBullish = self.I(lambda: self._is_bullish())
        self.isBearish = self.I(lambda: self._is_bearish())
        self.intensity = self.I(lambda: self._calc_intensity(volume))
        
        self.buy_signal = self.I(lambda: self._buy_signal())
        self.sell_signal = self.I(lambda: self._sell_signal())
        
        self.last_signal = None
        self.signal_bar = 0
    
    def _check_bull_engulf(self, close, open_):
        if len(close) < 2 or len(self.data.Close) < 2:
            return False
        return (close[-1] > open_[-1] and 
                open_[-1] <= close[-2] and 
                close[-1] >= open_[-2] and 
                low[-1] < self.data.Low[-2])
    
    def _check_bear_engulf(self, close, open_):
        if len(close) < 2 or len(self.data.Close) < 2:
            return False
        return (close[-1] < open_[-1] and 
                open_[-1] >= close[-2] and 
                close[-1] <= open_[-2] and 
                self.data.High[-1] > self.data.High[-2])
    
    def _check_passive(self):
        if not self.isVolSpike or not self.isContained:
            return False
        return self.bodyPct <= self.maxBodyPct and self.wickPct >= self.minWickPct
    
    def _check_aggressive(self):
        if not self.isVolSpike or not self.isContained:
            return False
        return self.bullEngulf or self.bearEngulf
    
    def _check_exhaustion(self, volume):
        exhaustMult = self.volMult * 1.5
        isVolClimax = volume[-1] > self.avgVol[-1] * exhaustMult if len(self.avgVol) > 0 else False
        if not isVolClimax or not self.isContained:
            return False
        
        if self.totalWick <= 0:
            return False
        wickDominance = max(self.upperWick[-1], self.lowerWick[-1]) / self.totalWick * 100
        hasRejectionWick = wickDominance > 60 and self.wickPct >= 50
        return hasRejectionWick
    
    def _any_absorption(self):
        if not self.showPassive and not self.showAggress and not self.showExhaust:
            return False
        return (self.passiveAbs and self.showPassive) or (self.aggressAbs and self.showAggress) or (self.exhaustAbs and self.showExhaust)
    
    def _is_bullish(self):
        return self.anyAbsorption and (self.bullWick or self.bullEngulf)
    
    def _is_bearish(self):
        return self.anyAbsorption and (self.bearWick or self.bearEngulf) and not self.isBullish
    
    def _calc_intensity(self, volume):
        if not self.anyAbsorption:
            return 0
        
        intensity = 3 if self.volRatio >= 4.0 else 2 if self.volRatio >= 3.0 else 1
        
        if self.totalWick > 0:
            wickDominance = max(self.upperWick[-1], self.lowerWick[-1]) / self.totalWick * 100
            if wickDominance > 75:
                intensity += 1
        
        if self.exhaustAbs:
            intensity += 1
        
        return min(intensity, 5)
    
    def _buy_signal(self):
        return self.anyAbsorption and self.isBullish and self.intensity >= self.minIntensity
    
    def _sell_signal(self):
        return self.anyAbsorption and self.isBearish and self.intensity >= self.minIntensity
    
    def next(self):
        if len(self.data) < 2:
            return
        
        # Buy on bullish absorption signal
        if self.buy_signal:
            if not self.position:
                self.buy()
            self.last_signal = "BUY"
            self.signal_bar = len(self.data)
        
        # Sell on bearish absorption signal
        elif self.sell_signal:
            if self.position:
                self.position.close()
            self.last_signal = "SELL"
            self.signal_bar = len(self.data)
        
        # Simple exit: close position after 10 bars
