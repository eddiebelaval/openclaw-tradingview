import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Triangle Detection
    pivot_len = 8
    min_points = 2
    max_triangle_bars = 180
    price_tol_pct = 0.20
    slope_tol = 0.0010
    
    # Filters
    use_trend_filter = True
    ema_len = 50
    vol_confirm = False
    vol_mult = 1.3
    use_squeeze = True
    squeeze_len = 20
    atr_len = 14
    min_height_atr = 1.2
    break_buf_atr = 0.10
    use_maturity = True
    min_maturity_pct = 0.35
    
    # Signal Behavior
    no_duplicate_signals = True
    one_per_triangle = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate indicators
        self.ema_trend = self.I(pta.ema, close, length=self.ema_len)
        self.atr_value = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.atr_avg = self.I(pta.sma, self.atr_value, length=self.squeeze_len)
        self.avg_vol = self.I(pta.sma, volume, length=20)
        
        # Pivot detection using rolling max/min
        self.pivot_high = self.I(lambda: high.rolling(window=self.pivot_len*2+1, center=True).max())
        self.pivot_low = self.I(lambda: low.rolling(window=self.pivot_len*2+1, center=True).min())
        
        # State variables
        self.highs = []
        self.high_bars = []
        self.lows = []
        self.low_bars = []
        self.pos_state = 0
        self.last_tri_start = None
        self.long_used_this_tri = False
        self.short_used_this_tri = False
        self.in_triangle = False
        self.upper_now = None
        self.lower_now = None
        self.tri_height = None
        self.tri_start_bar = None
        self.tri_last_bar = None

    def detect_pivots(self, idx):
        """Detect pivot highs and lows at current bar"""
        if idx < self.pivot_len * 2 + 1:
            return
        
        # Check if current bar is a pivot high
        is_ph = True
        center = idx - self.pivot_len
        for i in range(center - self.pivot_len, center + self.pivot_len + 1):
            if i != center and self.data.High[i] > self.data.High[center]:
                is_ph = False
                break
        
        if is_ph:
            self.highs.append(self.data.High[center])
            self.high_bars.append(center)
            if len(self.highs) > 12:
                self.highs.pop(0)
                self.high_bars.pop(0)
        
        # Check if current bar is a pivot low
        is_pl = True
        for i in range(center - self.pivot_len, center + self.pivot_len + 1):
            if i != center and self.data.Low[i] < self.data.Low[center]:
                is_pl = False
                break
        
        if is_pl:
            self.lows.append(self.data.Low[center])
            self.low_bars.append(center)
            if len(self.lows) > 12:
                self.lows.pop(0)
                self.low_bars.pop(0)

    def tol(self, x):
        """Price tolerance function"""
        return x * (self.price_tol_pct * 0.01)

    def detect_triangle(self, idx):
        """Detect symmetric triangle and project levels"""
        self.in_triangle = False
        self.upper_now = None
        self.lower_now = None
        self.tri_height = None
        
        if len(self.highs) < self.min_points or len(self.lows) < self.min_points:
            return
        
        h1 = len(self.high_bars) - 1
        h0 = len(self.high_bars) - self.min_points
        l1 = len(self.low_bars) - 1
        l0 = len(self.low_bars) - self.min_points
        
        if h0 < 0 or l0 < 0:
            return
        
        hb1 = self.high_bars[h1]
        hb0 = self.high_bars[h0]
        lb1 = self.low_bars[l1]
        lb0 = self.low_bars[l0]
        
        tri_start = min(hb0, lb0)
        tri_last = max(hb1, lb1)
        
        age_ok = (idx - tri_start) <= self.max_triangle_bars
        
        hv1 = self.highs[h1]
        hv0 = self.highs[h0]
        lv1 = self.lows[l1]
        lv0 = self.lows[l0]
        
        # Check decreasing highs
        dec_highs = True
        for i in range(1, self.min_points):
            ha = self.highs[len(self.highs) - i]
            hb = self.highs[len(self.highs) - i - 1]
            if ha > hb + self.tol(hb):
                dec_highs = False
                break
        
        # Check rising lows
        ris_lows = True
        for i in range(1, self.min_points):
            la = self.lows[len(self.lows) - i]
            lb = self.lows[len(self.lows) - i - 1]
            if la < lb - self.tol(lb):
                ris_lows = False
                break
        
        # Check convergence
        high_slope = (hv1 - hv0) / max(1, (hb1 - hb0))
        low_slope = (lv1 - lv0) / max(1, (lb1 - lb0))
        
        converging = (high_slope <= 0 and low_slope >= 0) or abs(high_slope + low_slope) < self.slope_tol
        
        self.in_triangle = age_ok and dec_highs and ris_lows and converging
        
        if self.in_triangle:
            self.tri_start_bar = tri_start
            self.tri_last_bar = tri_last
            self.upper_now = hv1 + high_slope * (idx - hb1)
            self.lower_now = lv1 + low_slope * (idx - lb1)
            self.tri_height = abs(hv0 - lv0)

    def next(self):
        idx = len(self.data) - 1
        
        # Detect new pivots
        self.detect_pivots(idx)
        
        # Detect triangle
        self.detect_triangle(idx)
        
        # Get filter values
        atr_val = self.atr_value[-1] if len(self.atr_value) > 0 else 0
        atr_avg_val = self.atr_avg[-1] if len(self.atr_avg) > 0 else 0
        ema_val = self.ema_trend[-1] if len(self.ema_trend) > 0 else self.data.Close[-1]
        avg_vol_val = self.avg_vol[-1] if len(self.avg_vol) > 0 else self.data.Volume[-1]
        squeeze = atr_val < atr_avg_val
        
        # Trend filters
        trend_ok_long = not self.use_trend_filter or self.data.Close[-1] > ema_val
        trend_ok_short = not self.use_trend_filter or self.data.Close[-1] < ema_val
        vol_ok = not self.vol_confirm or self.data.Volume[-1] > avg_vol_val * self.vol_mult
        
        # Robustness filters
        height_ok = self.tri_height is not None and self.tri_height >= atr_val * self.min_height_atr
        
        # Maturity filter
        maturity_ok = True
        if self.use_maturity and self.tri_start_bar is not None and self.tri_last_bar is not None:
            total_span = max(1, self.tri_last_bar - self.tri_start_bar)
            tri_progress = (idx - self.tri_start_bar) / total_span
            maturity_ok = tri_progress >= self.min_maturity_pct
        
        squeeze_ok = (not self.use_squeeze) or squeeze
        
        # Breakout detection
        cross_up = False
        cross_down = False
        
        if self.in_triangle and self.upper_now is not None and self.lower_now is not None:
            upper_level = self.upper_now + atr_val * self.break_buf_atr
            lower_level = self.lower_now - atr_val * self.break_buf_atr
            
            if len(self.data.Close) > 1:
                cross_up = self.data.Close[-2] <= upper_level and self.data.Close[-1] > upper_level
                cross_down = self.data.Close[-2] >= lower_level and self.data.Close[-1] < lower_level
        
        # Raw signals
        raw_long = cross_up and trend_ok_long and vol_ok and height_ok and maturity_ok and squeeze_ok
        raw_short = cross_down and trend_ok_short and vol_ok and height_ok and maturity_ok and squeeze_ok
        
        # Triangle state tracking
        new_triangle = self.in_triangle and self.tri_start_bar is not None and (
            self.last_tri_start is None or self.tri_start_bar != self.last_tri_start
        )
        
        if new_triangle:
            self.last_tri_start = self.tri_start_bar
            self.long_used_this_tri = False
            self.short_used_this_tri = False
        
        # Stateful signal engine
        long_trig = raw_long
        short_trig = raw_short
        
        if self.no_duplicate_signals:
            long_trig = raw_long and (self.pos_state != 1)
            short_trig = raw_short and (self.pos_state != -1)
        
        if self.one_per_triangle:
            long_trig = long_trig and not self.long_used_this_tri
            short_trig = short_trig and not self.short_used_this_tri
        
        # Reset flags when triangle ends
        if not self.in_triangle:
            self.long_used_this_tri = False
            self.short_used_this_tri = False
        
        # Execute trades
        if long_trig:
            if not self.position:
                self.buy()
            self.pos_state = 1
            self.long_used_this_tri = True
        
        if short_trig:
            if self.position:
                self.position.close()
            self.pos_state = -1
            self.short_used_this_tri = True
        
        # Close positions on exit
        if self.position and not self.in_triangle:
            self.position.close()
            self.pos_state = 0


