import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR for zone calculations
        self.atr = self.I(pta.atr, high, low, close, length=200)
        
        # Delta calculation
        def calc_delta():
            v = np.where(volume > 0, volume, (high - low) * 100000)
            rng = high - low
            pct = np.where(rng > 0, (close - low) / rng, 0.5)
            avg_v = pta.sma(volume, length=20)
            ratio = np.where(avg_v > 0, np.minimum(v / avg_v, 3.0), 1.0)
            return v * (2.0 * pct - 1.0) * ratio
        
        self.delta_raw = self.I(calc_delta)
        
        # EMA of delta
        def calc_delta_ema():
            d_raw = calc_delta()
            if d_raw is None:
                return pd.Series(0, index=close.index)
            return pta.ema(pd.Series(d_raw), length=8)
        
        self.delta_ema = self.I(calc_delta_ema)
        
        # Cumulative delta
        def calc_cum_delta():
            d_raw = calc_delta()
            if d_raw is None:
                return pd.Series(0, index=close.index)
            cum = d_raw.cumsum()
            return cum
        
        self.cum_delta = self.I(calc_cum_delta)
        
        # Absorption detection
        def calc_absorb():
            v = np.where(volume > 0, volume, (high - low) * 100000)
            av = pta.sma(volume, length=20)
            body = np.abs(close - pd.Series(self.data.Open))
            rng = high - low
            bp = np.where(rng > 0, body / rng, 0.5)
            
            hvol = v > av * 2.0
            smlbd = bp < 0.3
            wicks = (rng > 0) & ((high - np.maximum(close, pd.Series(self.data.Open))) > body * 0.8) & \
                    ((np.minimum(close, pd.Series(self.data.Open)) - low) > body * 0.8)
            
            return hvol & smlbd & wicks
        
        self.absorption = self.I(calc_absorb)
        
        # ROC for divergence
        def calc_price_roc():
            roc = pta.roc(close, length=12)
            return roc if roc is not None else pd.Series(0, index=close.index)
        
        self.price_roc = self.I(calc_price_roc)
        
        def calc_delta_roc():
            cum_d = calc_cum_delta()
            roc = pta.roc(pd.Series(cum_d), length=12)
            return roc if roc is not None else pd.Series(0, index=close.index)
        
        self.delta_roc = self.I(calc_delta_roc)
        
        # Buy pressure
        def calc_buy_pressure():
            rng = high - low
            bp = np.where(rng > 0, (close - low) / rng * 100, 50)
            return bp
        
        self.buy_pressure = self.I(calc_buy_pressure)
        
        # Tracking variables
        self.last_signal = None
    
    def next(self):
        # Ensure we have enough data
        if len(self.data) < 50:
            return
        
        # Get current values
        delta_ema = self.delta_ema[-1] if not np.isnan(self.delta_ema[-1]) else 0
        cum_delta = self.cum_delta[-1] if not np.isnan(self.cum_delta[-1]) else 0
        cum_delta_prev = self.cum_delta[-2] if len(self.cum_delta) > 1 else cum_delta
        buy_pct = self.buy_pressure[-1] if not np.isnan(self.buy_pressure[-1]) else 50
        
        # Get absorption signal
        absorb = bool(self.absorption[-1]) if not np.isnan(self.absorption[-1]) else False
        
        # Get divergence signals
        price_roc = self.price_roc[-1] if not np.isnan(self.price_roc[-1]) else 0
        delta_roc = self.delta_roc[-1] if not np.isnan(self.delta_roc[-1]) else 0
        
        # Calculate thresholds
        price_roc_std = 0.5 if len(self.price_roc) < 20 else np.std(self.price_roc[-20:])
        delta_roc_std = 0.5 if len(self.delta_roc) < 20 else np.std(self.delta_roc[-20:])
        
        p_thresh = price_roc_std * 0.8
        d_thresh = delta_roc_std * 0.8
        
        # Divergence detection
        bull_div = (price_roc < -p_thresh) and (delta_roc > d_thresh)
        bear_div = (price_roc > p_thresh) and (delta_roc < -d_thresh)
        
        # Trading signals
        # Signal 1: Bullish divergence or absorption on uptick with positive delta
        bull_signal = (bull_div or (absorb and self.data.Close[-1] >= self.data.Open[-1])) and delta_ema > 0
        
        # Signal 2: Bearish divergence or absorption on downtick with negative delta
        bear_signal = (bear_div or (absorb and self.data.Close[-1] < self.data.Open[-1])) and delta_ema < 0
        
        # Signal 3: Delta momentum with cumulative delta confirmation
        delta_rising = cum_delta > cum_delta_prev
        bull_momentum = delta_ema > 0 and delta_rising and buy_pct > 55
        bear_momentum = delta_ema < 0 and not delta_rising and buy_pct < 45
        
        # Entry logic
        if not self.position:
            if bull_signal or bull_momentum:
                self.buy()
                self.last_signal = "long"
            elif bear_signal or bear_momentum:
                self.sell()
                self.last_signal = "short"
        else:
            # Exit logic
            if self.position.is_long:
                # Exit long on bearish signals or delta reversal
                if bear_signal or (delta_ema < 0 and not delta_rising):
                    self.position.close()
                    self.last_signal = None
            else:
                # Exit short on bullish signals or delta reversal
                if bull_signal or (delta_ema > 0 and delta_rising):
                    self.position.close()
                    self.last_signal = None


