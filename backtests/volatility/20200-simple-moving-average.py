import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate SMAs
        self.sma20 = self.I(pta.sma, close, length=20)
        self.sma200 = self.I(pta.sma, close, length=200)

    def next(self):
        # Buy condition: SMA20 crosses above SMA200 and close > SMA200
        if crossover(self.sma20, self.sma200):
            if self.data.Close[-1] > self.sma200[-1]:
                self.buy()
        
        # Sell condition: SMA20 crosses below SMA200 and close < SMA200
        elif crossover(self.sma200, self.sma20):
            if self.data.Close[-1] < self.sma200[-1]:
                self.sell()


if __name__ == "__main__":
    # Load your data here
    df = pd.read_csv("data.csv", index_col=0, parse_dates=True)
    
    # Run backtest
    bt = Backtest(df, TvStrategy, cash=10000, commission=.002)
    stats = bt.run()
