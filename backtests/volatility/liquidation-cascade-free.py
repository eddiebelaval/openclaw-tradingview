import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Volume Analysis
    vol_len = 20
    spike_mult = 1.8
    
    # Keltner Channels
    kelt_len = 20
    kelt_mult = 2.0
    atr_len = 14
    
    # Price Action
    liq_wick_ratio = 0.6
    liq_body_max = 0.35
    
    # Signal Settings
    threshold = 45.0
    cooldown_bars = 10
    max_signals = 5
    
    # Weights
    wt_volume = 20.0
    wt_keltner = 30.0
    wt_pa = 25.0
    wt_htf = 25.0

    def init(self):
        # Prepare data
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # Volume Analysis
        self.vol_avg = self.I(lambda: pta.sma(volume, length=self.vol_len) or pd.Series(1.0, index=volume.index))
        self.vol_ratio = self.I(lambda: volume / (self.vol_avg + 0.0001))
        self.vol_spike = self.I(lambda: (self.vol_ratio >= self.spike_mult).astype(float))
        
        # Volume Score calculation
        def calc_vol_score(ratio):
            score = pd.Series(0.0, index=ratio.index)
            mask = ratio >= 1.0
            score[mask] = np.minimum((ratio[mask] - 1.0) / (self.spike_mult * 2.0) * self.wt_volume, self.wt_volume)
            return score
        self.vol_score = self.I(calc_vol_score, self.vol_ratio)
        
        # Keltner Channels
        self.kelt_basis = self.I(lambda: pta.ema(close, length=self.kelt_len) or pd.Series(close.mean(), index=close.index))
        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.atr_len) or pd.Series(0.1, index=close.index))
        self.kelt_upper = self.I(lambda: self.kelt_basis + self.kelt_mult * self.atr_val)
        self.kelt_lower = self.I(lambda: self.kelt_basis - self.kelt_mult * self.atr_val)
        
        # Keltner Exhaustion
        def calc_upper_ext(h, upper, atr):
            result = pd.Series(0.0, index=h.index)
            mask = atr > 0
            result[mask] = np.maximum(0.0, h[mask] - upper[mask]) / atr[mask]
            return result
        
        def calc_lower_ext(l, lower, atr):
            result = pd.Series(0.0, index=l.index)
            mask = atr > 0
            result[mask] = np.maximum(0.0, lower[mask] - l[mask]) / atr[mask]
            return result
        
        self.upper_ext = self.I(calc_upper_ext, high, self.kelt_upper, self.atr_val)
        self.lower_ext = self.I(calc_lower_ext, low, self.kelt_lower, self.atr_val)
        
        def calc_kelt_score_long(ext):
            score = pd.Series(0.0, index=ext.index)
            mask = ext >= 0.0
            score[mask] = np.minimum((ext[mask] / 2.0) * self.wt_keltner, self.wt_keltner)
            return score
        
        def calc_kelt_score_short(ext):
            score = pd.Series(0.0, index=ext.index)
            mask = ext >= 0.0
            score[mask] = np.minimum((ext[mask] / 2.0) * self.wt_keltner, self.wt_keltner)
            return score
        
        self.kelt_score_long = self.I(calc_kelt_score_long, self.lower_ext)
        self.kelt_score_short = self.I(calc_kelt_score_short, self.upper_ext)
        
        # Price Action
        def calc_bar_metrics(o, h, l, c):
            bar_range = h - l
            body_size = np.abs(c - o)
            upper_wick = np.maximum(c, o)
            lower_wick = np.minimum(c, o)
            
            body_ratio = pd.Series(1.0, index=o.index)
            upper_wick_ratio = pd.Series(0.0, index=o.index)
            lower_wick_ratio = pd.Series(0.0, index=o.index)
            
            mask = bar_range > 0
            body_ratio[mask] = body_size[mask] / bar_range[mask]
            upper_wick_ratio[mask] = (h[mask] - upper_wick[mask]) / bar_range[mask]
            lower_wick_ratio[mask] = (lower_wick[mask] - l[mask]) / bar_range[mask]
            
            return body_ratio, upper_wick_ratio, lower_wick_ratio
        
        # Store metrics separately
        self.body_ratio = self.I(lambda: calc_bar_metrics(open_, high, low, close)[0])
        self.upper_wick_ratio = self.I(lambda: calc_bar_metrics(open_, high, low, close)[1])
        self.lower_wick_ratio = self.I(lambda: calc_bar_metrics(open_, high, low, close)[2])
        
        # Liquidation bars
        def calc_liq_bar_long(lower_wick, body_ratio, vol_r):
            return (lower_wick >= self.liq_wick_ratio) & (body_ratio <= self.liq_body_max) & (vol_r >= 1.2)
        
        def calc_liq_bar_short(upper_wick, body_ratio, vol_r):
            return (upper_wick >= self.liq_wick_ratio) & (body_ratio <= self.liq_body_max) & (vol_r >= 1.2)
        
        self.liq_bar_long = self.I(calc_liq_bar_long, self.lower_wick_ratio, self.body_ratio, self.vol_ratio)
        self.liq_bar_short = self.I(calc_liq_bar_short, self.upper_wick_ratio, self.body_ratio, self.vol_ratio)
        
        # Engulfing patterns
        def calc_bull_engulf(c, o, h, l, vol_r):
            result = pd.Series(False, index=c.index)
            result[1:] = (c[1:] > o[1:]) & (c[1:] > h[:-1].values) & (o[1:] <= l[:-1].values) & (vol_r[1:] >= 1.3)
            return result
        
        def calc_bear_engulf(c, o, h, l, vol_r):
            result = pd.Series(False, index=c.index)
            result[1:] = (c[1:] < o[1:]) & (c[1:] < l[:-1].values) & (o[1:] >= h[:-1].values) & (vol_r[1:] >= 1.3)
            return result
        
        self.bull_engulf = self.I(calc_bull_engulf, close, open_, high, low, self.vol_ratio)
        self.bear_engulf = self.I(calc_bear_engulf, close, open_, high, low, self.vol_ratio)
        
        # PA Score
        def calc_pa_score_long(liq_bar, engulf):
            score = pd.Series(0.0, index=liq_bar.index)
            score[liq_bar] = self.wt_pa
            score[~liq_bar & engulf] = self.wt_pa * 0.6
            return score
        
        def calc_pa_score_short(liq_bar, engulf):
            score = pd.Series(0.0, index=liq_bar.index)
            score[liq_bar] = self.wt_pa
            score[~liq_bar & engulf] = self.wt_pa * 0.6
            return score
        
        self.pa_score_long = self.I(calc_pa_score_long, self.liq_bar_long, self.bull_engulf)
        self.pa_score_short = self.I(calc_pa_score_short, self.liq_bar_short, self.bear_engulf)
        
        # HTF Trend (simplified - using current timeframe)
        self.htf_ema = self.I(lambda: pta.ema(close, length=21) or pd.Series(close.mean(), index=close.index))
        self.htf_ema_prev = self.I(lambda: self.htf_ema.shift(1))
        
        def calc_htf_trend(ema, ema_prev):
            trend = pd.Series(0, index=ema.index)
            trend[ema > ema_prev] = 1
            trend[ema < ema_prev] = -1
            return trend
        
        self.htf_trend = self.I(calc_htf_trend, self.htf_ema, self.htf_ema_prev)
        
        # HTF Score
        def calc_htf_score_long(trend):
            score = pd.Series(0.0, index=trend.index)
            score[trend >= 0] = self.wt_htf
            return score
        
        def calc_htf_score_short(trend):
            score = pd.Series(0.0, index=trend.index)
            score[trend <= 0] = self.wt_htf
            return score
        
        self.htf_score_long = self.I(calc_htf_score_long, self.htf_trend)
        self.htf_score_short = self.I(calc_htf_score_short, self.htf_trend)
        
        # Aggregate Scores
        self.long_score = self.I(lambda: self.vol_score + self.kelt_score_long + self.pa_score_long + self.htf_score_long)
        self.short_score = self.I(lambda: self.vol_score + self.kelt_score_short + self.pa_score_short + self.htf_score_short)
        
        # Module counting
        def count_modules_long(vol, kelt, pa, htf):
            count = pd.Series(0, index=vol.index)
            count[(vol > 3)] += 1
            count[(kelt > 3)] += 1
            count[(pa > 3)] += 1
            count[(htf > 3)] += 1
            return count
        
        def count_modules_short(vol, kelt, pa, htf):
            count = pd.Series(0, index=vol.index)
            count[(vol > 3)] += 1
            count[(kelt > 3)] += 1
            count[(pa > 3)] += 1
            count[(htf > 3)] += 1
            return count
        
        self.long_modules = self.I(count_modules_long, self.vol_score, self.kelt_score_long, self.pa_score_long, self.htf_score_long)
        self.short_modules = self.I(count_modules_short, self.vol_score, self.kelt_score_short, self.pa_score_short, self.htf_score_short)
        
        # State tracking
        self.bars_since_long = 999
        self.bars_since_short = 999
        self.session_signal_count = 0

    def next(self):
        # Update cooldown counters
        self.bars_since_long += 1
        self.bars_since_short += 1
        
        # Get current scores
        long_score = self.long_score[-1]
        short_score = self.short_score[-1]
        long_modules = self.long_modules[-1]
        short_modules = self.short_modules[-1]
        
        # Check thresholds
        long_above_threshold = long_score >= self.threshold and long_modules >= 2
        short_above_threshold = short_score >= self.threshold and short_modules >= 2
        
        # Check cooldowns
        long_cooldown_ok = self.bars_since_long >= self.cooldown_bars
        short_cooldown_ok = self.bars_since_short >= self.cooldown_bars
        
        # Check session cap
        under_signal_cap = self.session_signal_count < self.max_signals
        
        # Raw signal detection
        long_raw = long_above_threshold and long_cooldown_ok
        short_raw = short_above_threshold and short_cooldown_ok
        
        # Conflict resolution
        long_qualified = long_raw and (not short_raw or long_score >= short_score)
        short_qualified = short_raw and (not long_raw or short_score > long_score)
        
        # Apply session cap
        long_signal = long_qualified and under_signal_cap
        short_signal = short_qualified and under_signal_cap
        
        # Execute trades
        if long_signal:
            self.buy()
            self.bars_since_long = 0
            self.session_signal_count += 1
        
        if short_signal:
            self.sell()
            self.bars_since_short = 0
            self.session_signal_count += 1