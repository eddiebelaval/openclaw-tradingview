import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_length = 2
    atr_mult = 0.5
    buffer_ticks = 10
    vol_pct_target = 90.0
    imb_ratio = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Volume calculations
        self.max_vol = self.I(lambda: volume.rolling(20).max())
        self.vol_pct = self.I(lambda: (volume / self.max_vol) * 100)
        
        # State tracking
        self.opening_low = None
        self.trade_state = 0  # 0=Flat, 1=Long, -1=Short
        self.cum_delta = 0.0
        self.last_day = None
        
        # Previous close for crossover detection
        self.prev_close = None

    def next(self):
        if len(self.data) < 2:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        vol_pct = self.vol_pct[-1] if self.vol_pct[-1] is not None else 0
        
        # Get current date
        current_time = self.data.index[-1]
        current_day = current_time.date() if hasattr(current_time, 'date') else current_time
        
        # Reset on new day
        if self.last_day is None or current_day != self.last_day:
            self.opening_low = low
            self.trade_state = 0
            self.cum_delta = 0.0
            self.last_day = current_day
        
        # Calculate levels
        upper_exit = self.opening_low + (atr_val * self.atr_mult)
        lower_exit = self.opening_low - (atr_val * self.atr_mult)
        
        # Buffer logic (using mintick as 0.01)
        mintick = 0.01
        buffer = self.buffer_ticks * mintick
        in_buffer = (abs(close - self.opening_low) <= buffer or 
                     abs(close - upper_exit) <= buffer or 
                     abs(close - lower_exit) <= buffer)
        
        # Crossover detection
        prev_close = self.data.Close[-2] if len(self.data) >= 2 else close
        
        buy_trigger = (prev_close <= self.opening_low and close > self.opening_low and 
                      (self.trade_state == 0 or self.trade_state == -1))
        sell_trigger = (prev_close >= self.opening_low and close < self.opening_low and 
                       (self.trade_state == 0 or self.trade_state == 1))
        
        exit_plus = (self.data.High[-2] <= upper_exit if len(self.data) >= 2 else False) and high > upper_exit and self.trade_state == 1
        exit_minus = (self.data.Low[-2] >= lower_exit if len(self.data) >= 2 else False) and low < lower_exit and self.trade_state == -1
        
        is_90vol = vol_pct >= self.vol_pct_target
        
        # Execute trades
        if buy_trigger and is_90vol:
            if self.trade_state == -1:
                self.sell()
            if not self.position:
                self.buy()
            self.trade_state = 1
        
        elif sell_trigger and is_90vol:
            if self.trade_state == 1:
                self.sell()
            if not self.position:
                self.buy()
            self.trade_state = -1
        
        elif exit_plus and self.trade_state == 1:
            self.sell()
            self.trade_state = 0
        
        elif exit_minus and self.trade_state == -1:
            self.sell()
            self.trade_state = 0


