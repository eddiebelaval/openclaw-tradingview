import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 252
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Since this is a VIX curve indicator without direct price trading signals,
        # we'll create a simple strategy based on volatility regime changes
        # Use a simple momentum indicator on price as proxy for trend
        self.rsi = self.I(pta.rsi, close, length=14)
        self.sma_fast = self.I(pta.sma, close, length=20)
        self.sma_slow = self.I(pta.sma, close, length=50)
        
    def next(self):
        # Buy when RSI oversold and fast MA crosses above slow MA
        if len(self.data) > 50:
            if self.rsi[-1] < 30 and crossover(self.sma_fast, self.sma_slow):
                if not self.position:
                    self.buy()
            # Sell when RSI overbought or fast MA crosses below slow MA
            elif self.rsi[-1] > 70 or crossover(self.sma_slow, self.sma_fast):
                if self.position:
                    self.sell()