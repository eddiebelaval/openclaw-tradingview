import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Volatility Engine Parameters
    rv_len = 20
    trading_days = 252
    iv_pct_lookback = 252
    hi_vrp = 12.0
    mid_vrp = 5.0
    
    # Direction Engine Parameters
    ema_fast_len = 20
    ema_slow_len = 50
    adx_len = 14
    adx_smoothing = 14
    adx_sideways = 18.0
    band_pct = 0.15
    
    # Execution Parameters
    min_score_for_sell = 6

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate daily returns for RV
        self.log_returns = self.I(lambda: np.log(close / close.shift(1)))
        
        # RV calculation (rolling standard deviation of log returns)
        self.rv_daily = self.I(lambda: self.log_returns.rolling(window=self.rv_len).std())
        self.rv_annual = self.I(lambda: self.rv_daily * np.sqrt(self.trading_days) * 100.0)
        
        # For this backtest, use a simple IV proxy (can be extended with external data)
        # Using ATR as a volatility proxy
        atr = self.I(pta.atr, high, low, close, length=14)
        self.iv_used = self.I(lambda: (atr / close * 100.0) * 20)  # Scale ATR to IV-like metric
        
        # IV Percentile
        self.iv_min = self.I(lambda: self.iv_used.rolling(window=self.iv_pct_lookback).min())
        self.iv_max = self.I(lambda: self.iv_used.rolling(window=self.iv_pct_lookback).max())
        self.iv_pct = self.I(lambda: self._calculate_iv_pct())
        
        # VRP
        self.vrp = self.I(lambda: self.iv_used - self.rv_annual)
        
        # RV/IV trend flags (5-bar lookback)
        self.rv_rising = self.I(lambda: self.rv_annual > self.rv_annual.shift(5))
        self.iv_rising = self.I(lambda: self.iv_used > self.iv_used.shift(5))
        
        # Vol Score components
        self.score_ivp = self.I(lambda: self._calculate_score_ivp())
        self.score_vrp = self.I(lambda: self._calculate_score_vrp())
        self.score_ivx = self.I(lambda: self._calculate_score_ivx())
        self.total_score = self.I(lambda: self.score_ivp + self.score_vrp + self.score_ivx)
        self.sell_edge = self.I(lambda: (self.vrp > 0) & (self.total_score >= self.min_score_for_sell))
        
        # EMAs for trend
        self.ema_fast = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema_slow = self.I(pta.ema, close, length=self.ema_slow_len)
        
        # ADX for trend strength
        adx_result = self.I(lambda: self._calculate_adx(high, low, close))
        self.adx = self.I(lambda: adx_result if adx_result is not None else pd.Series(20, index=close.index))
        
        # Spread percentage between EMAs
        self.ema_spread_pct = self.I(lambda: self._calculate_ema_spread(close))
        
        # Trend regime
        self.is_sideways = self.I(lambda: (self.adx < self.adx_sideways) | (self.ema_spread_pct < self.band_pct))
        self.is_bull = self.I(lambda: (self.ema_fast > self.ema_slow) & ~self.is_sideways)
        self.is_bear = self.I(lambda: (self.ema_fast < self.ema_slow) & ~self.is_sideways)

    def _calculate_iv_pct(self):
        """Calculate IV percentile"""
        result = pd.Series(50.0, index=self.iv_used.index)
        for i in range(len(self.iv_used)):
            if pd.notna(self.iv_max.iloc[i]) and pd.notna(self.iv_min.iloc[i]):
                if self.iv_max.iloc[i] != self.iv_min.iloc[i]:
                    val = 100.0 * (self.iv_used.iloc[i] - self.iv_min.iloc[i]) / (self.iv_max.iloc[i] - self.iv_min.iloc[i])
                    result.iloc[i] = np.clip(val, 0.0, 100.0)
        return result

    def _calculate_score_ivp(self):
        """IV Percentile score component"""
        result = pd.Series(0, index=self.iv_pct.index, dtype=int)
        result[self.iv_pct < 40] = 0
        result[(self.iv_pct >= 40) & (self.iv_pct < 70)] = 1
        result[self.iv_pct >= 70] = 2
        return result

    def _calculate_score_vrp(self):
        """VRP score component"""
        result = pd.Series(0, index=self.vrp.index, dtype=int)
        result[self.vrp < 0] = 0
        result[(self.vrp >= 0) & (self.vrp < 2)] = 1
        result[(self.vrp >= 2) & (self.vrp < 4)] = 2
        result[self.vrp >= 4] = 3
        return result

    def _calculate_score_ivx(self):
        """IV index score component"""
        result = pd.Series(0, index=self.iv_pct.index, dtype=int)
        result[self.iv_pct < 50] = 0
        result[(self.iv_pct >= 50) & (self.iv_pct < 75)] = 1
        result[(self.iv_pct >= 75) & (self.iv_pct < 90)] = 2
        result[self.iv_pct >= 90] = 3
        return result

    def _calculate_adx(self, high, low, close):
        """Calculate ADX"""
        try:
            adx_result = pta.adx(high, low, close, length=self.adx_len)
            if adx_result is not None and 'ADX_14' in adx_result.columns:
                return adx_result['ADX_14']
            return None
        except:
            return None

    def _calculate_ema_spread(self, close):
        """Calculate EMA spread as percentage"""
        result = pd.Series(0.0, index=close.index)
        for i in range(len(close)):
            if pd.notna(self.ema_fast.iloc[i]) and pd.notna(self.ema_slow.iloc[i]) and close.iloc[i] != 0:
                spread = abs(self.ema_fast.iloc[i] - self.ema_slow.iloc[i]) / close.iloc[i] * 100.0
                result.iloc[i] = spread
        return result

    def next(self):
        # Current values
        vrp = self.vrp[-1] if len(self.vrp) > 0 and pd.notna(self.vrp[-1]) else 0
        is_bull = self.is_bull[-1] if len(self.is_bull) > 0 else False
        is_bear = self.is_bear[-1] if len(self.is_bear) > 0 else False
        is_sideways = self.is_sideways[-1] if len(self.is_sideways) > 0 else True
        sell_edge = self.sell_edge[-1] if len(self.sell_edge) > 0 else False
        total_score = self.total_score[-1] if len(self.total_score) > 0 else 0
        
        # Simple entry/exit logic based on VRP and trend
        
        # Exit existing positions
        if self.position:
            if self.position.is_long:
                # Exit long if VRP turns negative or trend turns bearish
                if vrp < 0 or is_bear:
                    self.position.close()
            else:
                # Exit short if VRP turns positive or trend turns bullish
                if vrp > 0 or is_bull:
                    self.position.close()
        
        # Entry logic
        if not self.position:
            # Buy signal: positive VRP with bullish trend
            if vrp > self.mid_vrp and is_bull and not is_sideways:
                self.buy()
            # Sell signal: negative VRP with bearish trend
            elif vrp < 0 and is_bear and not is_sideways:
                self.sell()
            # Medium conviction: sideways with medium VRP and sell edge
            elif is_sideways and sell_edge and vrp > self.mid_vrp:
                self.buy()


