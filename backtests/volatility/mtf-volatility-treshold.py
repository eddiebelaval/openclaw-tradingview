import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 10
    low_thresh = 15
    high_thresh = 30

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate log returns
        log_returns = np.log(close / close.shift(1))
        
        # Calculate volatility: stdev(log_returns) * sqrt(365) * 100
        def calc_volatility(series):
            if len(series) < self.length:
                return pd.Series(np.nan, index=series.index)
            volatility = series.rolling(window=self.length).std() * np.sqrt(365) * 100
            return volatility
        
        self.vol = self.I(calc_volatility, log_returns)

    def next(self):
        # Use volatility as a trading indicator
        # Buy when volatility is low and rising
        # Sell when volatility is high and falling
        
        if len(self.vol) < 2:
            return
        
        current_vol = self.vol[-1]
        prev_vol = self.vol[-2]
        
        if np.isnan(current_vol) or np.isnan(prev_vol):
            return
        
        # Buy when volatility crosses above low threshold (increasing volatility)
        if prev_vol <= self.low_thresh and current_vol > self.low_thresh:
            if not self.position:
                self.buy()
        
        # Sell when volatility crosses above high threshold (high volatility)
        elif current_vol > self.high_thresh:
            if self.position:
                self.sell()
        
        # Also sell if volatility drops back below low threshold
        elif prev_vol > self.low_thresh and current_vol <= self.low_thresh:
            if self.position:
                self.sell()


