import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    hist_len = 252
    show_mode = "Percentile Rank"

    def init(self):
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        # Calculate Parkinson realized volatility for each tenor
        def calc_rv(length):
            def _rv():
                hl = np.log(high / low)
                hl_sq = hl * hl
                pv = pta.sma(hl_sq, length=length) / (4.0 * np.log(2))
                rv = np.sqrt(pv * 252) * 100
                return rv if rv is not None else pd.Series(0, index=close.index)
            return self.I(_rv)
        
        self.rv_5 = calc_rv(5)
        self.rv_10 = calc_rv(10)
        self.rv_20 = calc_rv(20)
        self.rv_30 = calc_rv(30)
        self.rv_60 = calc_rv(60)
        self.rv_90 = calc_rv(90)
        self.rv_120 = calc_rv(120)
        self.rv_252 = calc_rv(252)
        
        # Calculate percentile ranks
        def calc_pct_rank(rv_series, lookback):
            def _pct():
                result = pd.Series(50.0, index=close.index)
                for idx in range(lookback, len(close)):
                    current = rv_series.iloc[idx]
                    if pd.notna(current):
                        count = 0
                        total = 0
                        for i in range(idx - lookback, idx):
                            if pd.notna(rv_series.iloc[i]):
                                total += 1
                                if rv_series.iloc[i] < current:
                                    count += 1
                        if total > 0:
                            result.iloc[idx] = (count / total) * 100.0
                return result
            return self.I(_pct)
        
        self.pct_5 = calc_pct_rank(self.rv_5, self.hist_len)
        self.pct_10 = calc_pct_rank(self.rv_10, self.hist_len)
        self.pct_20 = calc_pct_rank(self.rv_20, self.hist_len)
        self.pct_30 = calc_pct_rank(self.rv_30, self.hist_len)
        self.pct_60 = calc_pct_rank(self.rv_60, self.hist_len)
        self.pct_90 = calc_pct_rank(self.rv_90, self.hist_len)
        self.pct_120 = calc_pct_rank(self.rv_120, self.hist_len)
        self.pct_252 = calc_pct_rank(self.rv_252, self.hist_len)

    def next(self):
        # Trading logic based on 20-day volatility percentile rank
        # Buy when vol is cheap (< 15th percentile), sell when vol is expensive (> 85th percentile)
        
        pct_20_val = self.pct_20[-1]
        
        if pct_20_val < 15:
            # Volatility is cheap - buy signal
            if not self.position:
                self.buy()
        elif pct_20_val > 85:
            # Volatility is expensive - sell signal
            if self.position:
                self.position.close()
        elif 35 <= pct_20_val <= 65:
            # Volatility is fair - close position if we have one
            if self.position:
                self.position.close()


