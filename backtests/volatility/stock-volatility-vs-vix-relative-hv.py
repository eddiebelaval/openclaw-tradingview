import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate Historical Volatility (HV)
        def calculate_hv(src):
            returns = np.log(src / src.shift(1))
            stdev = returns.rolling(window=self.length).std()
            hv = stdev * np.sqrt(252) * 100
            return hv
        
        self.stock_hv = self.I(calculate_hv, close)
        
        # VIX approximation using realized volatility of price changes
        def calculate_vix_proxy():
            returns = np.log(close / close.shift(1))
            vix_proxy = returns.rolling(window=self.length).std() * np.sqrt(252) * 100
            return vix_proxy
        
        self.vix_proxy = self.I(calculate_vix_proxy)
        
        # Calculate Relative Volatility
        def calculate_relative_vol():
            rel_vol = self.stock_hv / (self.vix_proxy + 1e-6)
            return rel_vol
        
        self.relative_vol = self.I(calculate_relative_vol)
    
    def next(self):
        # Trading logic based on relative volatility
        # Buy when relative volatility is low (stock HV < VIX)
        # Sell when relative volatility is high (stock HV > VIX)
        
        if len(self.data) < self.length + 5:
            return
        
        current_rel_vol = self.relative_vol[-1]
        prev_rel_vol = self.relative_vol[-2] if len(self.relative_vol) > 1 else current_rel_vol
        
        # Buy signal: relative volatility crosses above 1 (stock HV rising relative to VIX)
        if crossover(self.relative_vol, 1):
            if not self.position:
                self.buy()
        
        # Sell signal: relative volatility crosses below 1 (stock HV falling relative to VIX)
        elif crossover(1, self.relative_vol):
            if self.position:
                self.position.close()