import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Volume Analysis
    vol_len = 20
    spike_mult = 1.8
    
    # Keltner Channels
    kelt_len = 20
    kelt_mult = 2.0
    atr_len = 14
    
    # Price Action
    liq_wick_ratio = 0.6
    liq_body_max = 0.35
    
    # Signal Settings
    threshold = 45.0
    cooldown_bars = 10
    max_signals = 5
    
    # Scoring weights
    WT_VOLUME = 20.0
    WT_KELTNER = 30.0
    WT_PA = 25.0
    WT_HTF = 25.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume indicators
        self.vol_avg = self.I(lambda: pta.sma(volume, length=self.vol_len))
        
        # Keltner channels
        self.kelt_basis = self.I(lambda: pta.ema(close, length=self.kelt_len))
        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.atr_len))
        
        # Price data for candle analysis
        self.open_prices = self.data.Open
        self.high_prices = self.data.High
        self.low_prices = self.data.Low
        self.close_prices = self.data.Close
        
        # State tracking
        self.bars_since_long = 999
        self.bars_since_short = 999
        self.session_signal_count = 0
        self.last_session_date = None

    def next(self):
        # Update state counters
        self.bars_since_long += 1
        self.bars_since_short += 1
        
        # Check session boundary (simple daily reset)
        current_date = pd.Timestamp(self.data.index[-1]).date()
        if self.last_session_date != current_date:
            self.session_signal_count = 0
            self.last_session_date = current_date
        
        # ===== MODULE 1: VOLUME ANALYSIS =====
        vol_avg = self.vol_avg[-1] if self.vol_avg[-1] is not None else 1.0
        vol_ratio = self.data.Volume[-1] / vol_avg if vol_avg > 0 else 0.0
        
        # Volume score: remap from 1.0 to spike_mult*2
        vol_score = 0.0
        if vol_ratio >= 1.0:
            vol_score = max(0, min(self.WT_VOLUME, self.WT_VOLUME * (vol_ratio - 1.0) / (self.spike_mult * 2.0 - 1.0)))
        
        # ===== MODULE 2: KELTNER CHANNEL EXHAUSTION =====
        kelt_basis = self.kelt_basis[-1] if self.kelt_basis[-1] is not None else self.close_prices[-1]
        atr_val = self.atr_val[-1] if self.atr_val[-1] is not None else 0.1
        
        kelt_upper = kelt_basis + self.kelt_mult * atr_val
        kelt_lower = kelt_basis - self.kelt_mult * atr_val
        
        # Overextension calculation
        upper_ext = max(0.0, self.high_prices[-1] - kelt_upper) / atr_val if atr_val > 0 else 0.0
        lower_ext = max(0.0, kelt_lower - self.low_prices[-1]) / atr_val if atr_val > 0 else 0.0
        
        # Keltner scores
        kelt_score_long = max(0, min(self.WT_KELTNER, self.WT_KELTNER * lower_ext / 2.0))
        kelt_score_short = max(0, min(self.WT_KELTNER, self.WT_KELTNER * upper_ext / 2.0))
        
        kelt_exhaust_long = self.low_prices[-1] < kelt_lower
        kelt_exhaust_short = self.high_prices[-1] > kelt_upper
        
        # ===== MODULE 3: PRICE ACTION (LIQUIDATION BAR) =====
        bar_range = self.high_prices[-1] - self.low_prices[-1]
        body_size = abs(self.close_prices[-1] - self.open_prices[-1])
        body_ratio = body_size / bar_range if bar_range > 0 else 1.0
        
        upper_wick = (self.high_prices[-1] - max(self.close_prices[-1], self.open_prices[-1])) / bar_range if bar_range > 0 else 0.0
        lower_wick = (min(self.close_prices[-1], self.open_prices[-1]) - self.low_prices[-1]) / bar_range if bar_range > 0 else 0.0
        
        # Liquidation bars
        liq_bar_long = lower_wick >= self.liq_wick_ratio and body_ratio <= self.liq_body_max and vol_ratio >= 1.2
        liq_bar_short = upper_wick >= self.liq_wick_ratio and body_ratio <= self.liq_body_max and vol_ratio >= 1.2
        
        # Engulfing patterns
        bull_engulf = (self.close_prices[-1] > self.open_prices[-1] and 
                      self.close_prices[-1] > self.high_prices[-2] and 
                      self.open_prices[-1] <= self.low_prices[-2] and 
                      vol_ratio >= 1.3)
        bear_engulf = (self.close_prices[-1] < self.open_prices[-1] and 
                      self.close_prices[-1] < self.low_prices[-2] and 
                      self.open_prices[-1] >= self.high_prices[-2] and 
                      vol_ratio >= 1.3)
        
        # PA scores
        pa_score_long = self.WT_PA if liq_bar_long else (self.WT_PA * 0.6 if bull_engulf else 0.0)
        pa_score_short = self.WT_PA if liq_bar_short else (self.WT_PA * 0.6 if bear_engulf else 0.0)
        
        # ===== MODULE 4: HIGHER TIMEFRAME TREND (simplified) =====
        # Use current EMA slope as trend proxy
        if len(self.data.Close) > 1:
            ema_current = pta.ema(pd.Series(self.data.Close), length=21).iloc[-1]
            ema_prev = pta.ema(pd.Series(self.data.Close), length=21).iloc[-2] if len(self.data.Close) > 1 else ema_current
            
            if ema_current > ema_prev:
                htf_trend = 1
            elif ema_current < ema_prev:
                htf_trend = -1
            else:
                htf_trend = 0
        else:
            htf_trend = 0
        
        htf_score_long = self.WT_HTF if htf_trend >= 0 else 0.0
        htf_score_short = self.WT_HTF if htf_trend <= 0 else 0.0
        
        # ===== CONFLUENCE SCORING =====
        long_score = vol_score + kelt_score_long + pa_score_long + htf_score_long
        short_score = vol_score + kelt_score_short + pa_score_short + htf_score_short
        
        # Module count for minimum confluence
        long_modules = sum([vol_score > 3, kelt_score_long > 3, pa_score_long > 3, htf_score_long > 3])
        short_modules = sum([vol_score > 3, kelt_score_short > 3, pa_score_short > 3, htf_score_short > 3])
        
        long_above_threshold = long_score >= self.threshold and long_modules >= 2
        short_above_threshold = short_score >= self.threshold and short_modules >= 2
        
        # ===== SIGNAL GATING =====
        long_cooldown_ok = self.bars_since_long >= self.cooldown_bars
        short_cooldown_ok = self.bars_since_short >= self.cooldown_bars
        under_signal_cap = self.session_signal_count < self.max_signals
        
        # Conflict resolution
        long_raw = long_above_threshold and long_cooldown_ok
        short_raw = short_above_threshold and short_cooldown_ok
        
        long_qualified = long_raw and (not short_raw or long_score >= short_score)
        short_qualified = short_raw and (not long_raw or short_score > long_score)
        
        # Apply session cap
        long_signal = long_qualified and under_signal_cap
        short_signal = short_qualified and under_signal_cap
        
        # ===== TRADING LOGIC =====
        if long_signal:
            self.buy()
            self.bars_since_long = 0
            self.session_signal_count += 1
        elif short_signal:
            self.sell()
            self.bars_since_short = 0
            self.session_signal_count += 1