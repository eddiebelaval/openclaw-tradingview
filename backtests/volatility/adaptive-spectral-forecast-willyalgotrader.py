import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 144
    num_harmonics = 5
    min_period = 8
    extrap = 55
    confidence_mult = 1.5
    trend_smooth = 30
    decay = 0.97
    min_snr = 2.0
    trend_filter = True
    preset = "Default"

    def init(self):
        self.warmup_bars = max(self.lookback, 50)
        self.last_signal_dir = 0
        self.forecast_dir = 0
        self.bar_count = 0

    def goertzel_power(self, data, period):
        """Calculate power at a specific period using Goertzel algorithm"""
        n = len(data)
        w = 2.0 * np.pi / period
        coeff = 2.0 * np.cos(w)
        s0, s1, s2 = 0.0, 0.0, 0.0
        
        for i in range(n):
            s0 = data[i] + coeff * s1 - s2
            s2 = s1
            s1 = s0
        
        real_part = s1 - s2 * np.cos(w)
        imag_part = s2 * np.sin(w)
        power = (real_part * real_part + imag_part * imag_part) / (n * n * 1.0)
        return power

    def compute_harmonic_coeffs(self, data, period):
        """Compute DFT harmonic coefficients"""
        n = len(data)
        w = 2.0 * np.pi / period
        sum_sin = 0.0
        sum_cos = 0.0
        
        for i in range(n):
            sum_sin += data[i] * np.sin(w * i)
            sum_cos += data[i] * np.cos(w * i)
        
        a = 2.0 * sum_sin / n
        b = 2.0 * sum_cos / n
        return a, b

    def build_trend_array(self, data, smooth):
        """Build EMA trend array"""
        n = len(data)
        result = np.zeros(n)
        alpha = 2.0 / (smooth + 1)
        result[0] = data[0]
        
        for i in range(1, n):
            result[i] = alpha * data[i] + (1.0 - alpha) * result[i - 1]
        
        return result

    def eval_harmonics_decay(self, t, t_base, decay, a_arr, b_arr, periods):
        """Evaluate harmonics with amplitude decay"""
        val = 0.0
        dist = max(t - t_base, 0.0)
        decay_factor = np.power(decay, dist)
        
        for j in range(len(periods)):
            w = 2.0 * np.pi / periods[j]
            val += (a_arr[j] * np.sin(w * t) + b_arr[j] * np.cos(w * t)) * decay_factor
        
        return val

    def eval_harmonics(self, t, a_arr, b_arr, periods):
        """Evaluate harmonics without decay"""
        val = 0.0
        for j in range(len(periods)):
            w = 2.0 * np.pi / periods[j]
            val += a_arr[j] * np.sin(w * t) + b_arr[j] * np.cos(w * t)
        return val

    def array_trend_slope(self, arr, k):
        """Calculate trend slope via linear regression"""
        n = len(arr)
        use_k = min(k, n)
        sum_x = 0.0
        sum_y = 0.0
        sum_xy = 0.0
        sum_x2 = 0.0
        
        for i in range(use_k):
            x = float(i)
            y = arr[n - use_k + i]
            sum_x += x
            sum_y += y
            sum_xy += x * y
            sum_x2 += x * x
        
        denom = use_k * sum_x2 - sum_x * sum_x
        if denom != 0:
            return (use_k * sum_xy - sum_x * sum_y) / denom
        return 0.0

    def next(self):
        self.bar_count += 1
        
        if self.bar_count < self.warmup_bars:
            return
        
        close_data = self.data.Close
        n_bars = min(self.lookback, len(close_data))
        
        if n_bars < self.min_period + 10:
            return
        
        # Build price array (most recent last)
        price_data = np.array(close_data[-n_bars:])
        
        # Extract trend
        trend_arr = self.build_trend_array(price_data, self.trend_smooth)
        
        # Detrend with Hann window
        detrended = np.zeros(n_bars)
        for i in range(n_bars):
            raw = price_data[i] - trend_arr[i]
            hann = 0.5 * (1.0 - np.cos(2.0 * np.pi * i / (n_bars - 1)))
            detrended[i] = raw * hann
        
        # Spectral scan
        max_period_val = min(n_bars - 1, n_bars // 2)
        scan_min = max(self.min_period, 4)
        scan_max = max(max_period_val, scan_min + 1)
        
        all_powers = []
        all_periods = []
        total_power = 0.0
        
        p = scan_min
        while p <= scan_max:
            pwr = self.goertzel_power(detrended, p)
            all_powers.append(pwr)
            all_periods.append(p)
            total_power += pwr
            p += (2 if p > 30 else 1)
        
        scan_count = len(all_powers)
        mean_power = total_power / scan_count if scan_count > 0 else 1.0
        
        # Peak detection with SNR
        peak_periods = []
        peak_powers = []
        peak_snr = []
        
        best_pwr = -1.0
        best_pwr_idx = -1
        
        for i in range(1, len(all_powers) - 1):
            curr_pwr = all_powers[i]
            prev_pwr = all_powers[i - 1]
            nxt_pwr = all_powers[i + 1]
            snr = curr_pwr / mean_power if mean_power > 0 else 0.0
            
            if curr_pwr > best_pwr:
                best_pwr = curr_pwr
                best_pwr_idx = i
            
            if curr_pwr > prev_pwr and curr_pwr > nxt_pwr and snr >= self.min_snr:
                peak_periods.append(all_periods[i])
                peak_powers.append(curr_pwr)
                peak_snr.append(snr)
        
        # Fallback logic
        if len(peak_powers) == 0 and best_pwr_idx >= 0:
            peak_periods.append(all_periods[best_pwr_idx])
            peak_powers.append(best_pwr)
            peak_snr.append(best_pwr / mean_power if mean_power > 0 else 0.0)
        
        if len(peak_powers) == 0 and len(all_powers) > 0 and len(all_powers) <= 2:
            edge_best_pwr = -1.0
            edge_best_idx = -1
            for i in range(len(all_powers)):
                if all_powers[i] > edge_best_pwr:
                    edge_best_pwr = all_powers[i]
                    edge_best_idx = i
            if edge_best_idx >= 0:
                peak_periods.append(all_periods[edge_best_idx])
                peak_powers.append(edge_best_pwr)
                peak_snr.append(edge_best_pwr / mean_power if mean_power > 0 else 0.0)
        
        # Select top harmonics
        detrended_raw = price_data - trend_arr
        selected_periods = []
        selected_snr = []
        sel_a = []
        sel_b = []
        
        to_select = min(self.num_harmonics, len(peak_powers))
        peak_pwr_copy = list(peak_powers)
        peak_per_copy = list(peak_periods)
        peak_snr_copy = list(peak_snr)
        
        for _ in range(to_select):
            if len(peak_pwr_copy) == 0:
                break
            max_pwr = -1.0
            max_idx = -1
            for m in range(len(peak_pwr_copy)):
                if peak_pwr_copy[m] > max_pwr:
                    max_pwr = peak_pwr_copy[m]
                    max_idx = m
            
            if max_idx != -1:
                sel_period = peak_per_copy[max_idx]
                selected_periods.append(sel_period)
                selected_snr.append(peak_snr_copy[max_idx])
                a_coeff, b_coeff = self.compute_harmonic_coeffs(detrended_raw, sel_period)
                sel_a.append(a_coeff)
                sel_b.append(b_coeff)
                peak_pwr_copy.pop(max_idx)
                peak_per_copy.pop(max_idx)
                peak_snr_copy.pop(max_idx)
        
        num_found = len(selected_periods)
        
        if num_found == 0:
            return
        
        # Trend slope
        trend_last = trend_arr[-1]
        trend_slope = self.array_trend_slope(trend_arr, 5)
        
        # Forecast direction
        t_base = float(n_bars - 1)
        
        y0 = self.eval_harmonics_decay(t_base, t_base, self.decay, sel_a, sel_b, selected_periods) + trend_last
        y1 = self.eval_harmonics_decay(t_base + 1.0, t_base, self.decay, sel_a, sel_b, selected_periods) + trend_last + trend_slope
        y2 = self.eval_harmonics_decay(t_base + 2.0, t_base, self.decay, sel_a, sel_b, selected_periods) + trend_last + trend_slope * 2
        y3 = self.eval_harmonics_decay(t_base + 3.0, t_base, self.decay, sel_a, sel_b, selected_periods) + trend_last + trend_slope * 3
        
        up_votes = (1 if y1 > y0 else 0) + (1 if y2 > y1 else 0) + (1 if y3 > y2 else 0)
        new_fcst_dir = 1 if up_votes >= 2 else (-1 if up_votes <= 1 else 0)
        
        # Trend alignment filter
        trend_aligned = not self.trend_filter or \
                       (new_fcst_dir == 1 and trend_slope > 0) or \
                       (new_fcst_dir == -1 and trend_slope < 0)
        
        avg_snr = sum(selected_snr) / len(selected_snr) if len(selected_snr) > 0 else 0.0
        used_fallback = len(selected_snr) > 0 and selected_snr[0] < self.min_snr
        
        if trend_aligned and avg_snr >= self.min_snr and not used_fallback:
            self.forecast_dir = new_fcst_dir
        
        # Signal generation
        dir_changed_buy = self.forecast_dir == 1 and self.last_signal_dir != 1
        dir_changed_sell = self.forecast_dir == -1 and self.last_signal_dir != -1
        
        if dir_changed_buy:
            self.last_signal_dir = 1
            if not self.position:
                self.buy()
        
        if dir_changed_sell:
            self.last_signal_dir = -1
            if self.position:
                self.position.close()


