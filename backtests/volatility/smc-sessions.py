import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR for volatility measurement
        self.atr = self.I(pta.atr, high, low, close, length=200)
        
        # Swing structure detection - using highest/lowest
        swing_length = 50
        self.highest_50 = self.I(lambda: high.rolling(swing_length).max())
        self.lowest_50 = self.I(lambda: low.rolling(swing_length).min())
        
        # Internal structure - using 5 bar lookback
        self.highest_5 = self.I(lambda: high.rolling(5).max())
        self.lowest_5 = self.I(lambda: low.rolling(5).min())
        
        # Track previous swing highs/lows for BOS/CHoCH detection
        self.swing_high = None
        self.swing_low = None
        self.internal_high = None
        self.internal_low = None
        self.swing_trend = 0  # 1 = bullish, -1 = bearish
        self.internal_trend = 0
        
        self.last_bos_signal = None
        self.last_choch_signal = None

    def next(self):
        # Skip if not enough data
        if len(self.data) < 55:
            return
        
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Initialize swing pivots if not set
        if self.swing_high is None:
            self.swing_high = self.highest_50[-1]
            self.swing_low = self.lowest_50[-1]
        
        if self.internal_high is None:
            self.internal_high = self.highest_5[-1]
            self.internal_low = self.lowest_5[-1]
        
        # Update swing structure
        if current_high > self.highest_50[-2]:
            self.swing_trend = -1  # bearish leg
            if self.swing_trend != -1:
                self.swing_high = current_high
        elif current_low < self.lowest_50[-2]:
            self.swing_trend = 1   # bullish leg
            if self.swing_trend != 1:
                self.swing_low = current_low
        
        # Update internal structure
        if current_high > self.highest_5[-2]:
            self.internal_trend = -1
            if self.internal_trend != -1:
                self.internal_high = current_high
        elif current_low < self.lowest_5[-2]:
            self.internal_trend = 1
            if self.internal_trend != 1:
                self.internal_low = current_low
        
        # Swing structure trading logic
        # Bullish BOS: close crosses above swing low when in bullish trend
        if self.swing_low is not None:
            if crossover(pd.Series([self.data.Close[-2], current_close]), 
                        pd.Series([self.swing_low, self.swing_low])):
                if self.swing_trend == -1:  # CHoCH (change of character)
                    if not self.position:
                        self.buy()
                    self.last_choch_signal = 'bullish_choch'
                else:  # BOS (break of structure)
                    if not self.position:
                        self.buy()
                    self.last_bos_signal = 'bullish_bos'
        
        # Bearish BOS: close crosses below swing high when in bearish trend
        if self.swing_high is not None:
            if self.data.Close[-2] > self.swing_high and current_close < self.swing_high:
                if self.swing_trend == 1:  # CHoCH
                    if self.position:
                        self.position.close()
                    else:
                        self.sell()
                    self.last_choch_signal = 'bearish_choch'
                else:  # BOS
                    if self.position:
                        self.position.close()
                    else:
                        self.sell()
                    self.last_bos_signal = 'bearish_bos'
        
        # Internal structure confirmation for entries/exits
        if self.internal_low is not None:
            if crossover(pd.Series([self.data.Close[-2], current_close]), 
                        pd.Series([self.internal_low, self.internal_low])):
                if self.internal_trend == -1 and not self.position:
                    self.buy()
        
        if self.internal_high is not None:
            if self.data.Close[-2] > self.internal_high and current_close < self.internal_high:
                if self.internal_trend == 1 and self.position:
                    self.position.close()
        
        # Equal highs/lows detection and reversal setup
        if len(self.data) >= 10:
            last_swing_high = self.highest_5[-5] if len(self.data) >= 5 else self.swing_high
            if last_swing_high is not None:
                if abs(current_high - last_swing_high) < 0.001 * self.atr[-1]:
                    if self.position:
                        self.position.close()
        
        # Risk management: close positions on significant ATR expansion
        if self.position:
            if (current_high - current_low) > 2 * self.atr[-1]:
                self.position.close()


def run_backtest():
    from backtesting.test import SMA, GOOG
    
    bt = Backtest(GOOG, TvStrategy, cash=10000, commission=.002)
    stats = bt.run()
    print(stats)
    bt.plot()


