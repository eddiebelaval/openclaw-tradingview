import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    bbLength = 21
    bbMult = 2.1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Bollinger Bands
        bbands = self.I(pta.bbands, close, length=self.bbLength, std=self.bbMult)
        self.bb_upper = bbands.iloc[:, 2]
        self.bb_basis = bbands.iloc[:, 1]
        self.bb_lower = bbands.iloc[:, 0]
        
        # State tracking
        self.cycle_state = 0  # 0 = flat, 1 = long, -1 = short
        self.entry_bar = -1
        self.entry_count = 0

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        bb_upper = self.bb_upper[-1]
        bb_basis = self.bb_basis[-1]
        bb_lower = self.bb_lower[-1]
        
        current_bar = len(self.data) - 1
        
        # OPEN LONG: price touches lower band in flat state
        if (self.cycle_state == 0 and 
            low < bb_lower and 
            not self.position):
            self.cycle_state = 1
            self.entry_bar = current_bar
            self.entry_count = 1
            self.buy()
        
        # OPEN SHORT: price touches upper band in flat state
        elif (self.cycle_state == 0 and 
              high > bb_upper and 
              not self.position):
            self.cycle_state = -1
            self.entry_bar = current_bar
            self.entry_count = 1
            self.sell()
        
        # CLOSE LONG: price touches middle band during long cycle
        if (self.cycle_state == 1 and 
            self.position and 
            high >= bb_basis and 
            self.entry_count > 0):
            self.position.close()
            self.cycle_state = 0
            self.entry_bar = -1
            self.entry_count = 0
        
        # CLOSE SHORT: price touches middle band during short cycle
        elif (self.cycle_state == -1 and 
              self.position and 
              low <= bb_basis and 
              self.entry_count > 0):
            self.position.close()
            self.cycle_state = 0
            self.entry_bar = -1
            self.entry_count = 0
        
        # AVERAGE LONG: price touches lower band again during long cycle (only on confirmed bars)
        if (self.cycle_state == 1 and 
            self.position and 
            current_bar > self.entry_bar and 
            close < bb_lower and 
            self.entry_count > 0):
            self.entry_count += 1
            self.buy()
        
        # AVERAGE SHORT: price touches upper band again during short cycle (only on confirmed bars)
        elif (self.cycle_state == -1 and 
              self.position and 
              current_bar > self.entry_bar and 
              close > bb_upper and 
              self.entry_count > 0):
            self.entry_count += 1
            self.sell()


