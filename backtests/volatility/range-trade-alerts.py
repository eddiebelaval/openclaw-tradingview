import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Channel parameters
    lookback = 30
    auto_pivot = True
    manual_pivot_len = 20
    max_pivot_age = 300
    
    # Alert parameters
    alert_mode = "Both"
    atr_len = 14
    min_width = 3.0
    touch_zone = 0.15
    min_rr = 2.0
    cooldown = 5
    
    # Stop placement
    tight_stop = False
    max_stop_atr = 4.0
    
    # Partial profits
    tp1_pct = 50.0
    tp2_pct = 75.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Pivot detection using rolling max/min
        self.pivot_len = self.manual_pivot_len if not self.auto_pivot else self._calc_auto_pivot()
        
        # Track pivots
        self.ph_values = []
        self.ph_bars = []
        self.pl_values = []
        self.pl_bars = []
        
        self.ph1 = None
        self.ph1b = None
        self.ph2 = None
        self.ph2b = None
        self.pl1 = None
        self.pl1b = None
        self.pl2 = None
        self.pl2b = None
        
        # Trend lines
        self.upper_val = None
        self.slope_hi = None
        self.lower_val = None
        self.slope_lo = None
        
        # Signal tracking
        self.last_bull_bar = None
        self.last_bear_bar = None

    def _calc_auto_pivot(self):
        return 20

    def _detect_pivots(self):
        if len(self.data) < self.pivot_len * 2 + 1:
            return
        
        idx = len(self.data) - 1
        
        # Pivot High detection
        if idx >= self.pivot_len and idx < len(self.data) - self.pivot_len:
            is_ph = True
            for i in range(1, self.pivot_len + 1):
                if self.data.High[idx - i] >= self.data.High[idx] or self.data.High[idx + i] >= self.data.High[idx]:
                    is_ph = False
                    break
            
            if is_ph:
                self.ph2 = self.ph1
                self.ph2b = self.ph1b
                self.ph1 = self.data.High[idx]
                self.ph1b = idx
        
        # Pivot Low detection
        if idx >= self.pivot_len and idx < len(self.data) - self.pivot_len:
            is_pl = True
            for i in range(1, self.pivot_len + 1):
                if self.data.Low[idx - i] <= self.data.Low[idx] or self.data.Low[idx + i] <= self.data.Low[idx]:
                    is_pl = False
                    break
            
            if is_pl:
                self.pl2 = self.pl1
                self.pl2b = self.pl1b
                self.pl1 = self.data.Low[idx]
                self.pl1b = idx

    def _calc_trend_lines(self):
        self.upper_val = None
        self.slope_hi = None
        self.lower_val = None
        self.slope_lo = None
        
        if self.ph2 is not None and self.ph1 is not None and self.ph1b != self.ph2b:
            self.slope_hi = (self.ph1 - self.ph2) / (self.ph1b - self.ph2b)
            idx = len(self.data) - 1
            self.upper_val = self.ph1 + self.slope_hi * (idx - self.ph1b)
        
        if self.pl2 is not None and self.pl1 is not None and self.pl1b != self.pl2b:
            self.slope_lo = (self.pl1 - self.pl2) / (self.pl1b - self.pl2b)
            idx = len(self.data) - 1
            self.lower_val = self.pl1 + self.slope_lo * (idx - self.pl1b)

    def next(self):
        self._detect_pivots()
        self._calc_trend_lines()
        
        if len(self.data) < 2 or self.atr[-1] is None:
            return
        
        atr_val = self.atr[-1]
        channel_width = None
        is_wide_enough = False
        
        if self.upper_val is not None and self.lower_val is not None:
            channel_width = self.upper_val - self.lower_val
            is_wide_enough = channel_width >= self.min_width * atr_val
        
        # Touch detection
        touch_buf = self.touch_zone * atr_val
        touch_buf_tight = touch_buf * 0.33
        
        hits_bottom = False
        hits_top = False
        
        if self.lower_val is not None:
            hits_bottom = (self.data.Low[-1] <= self.lower_val + touch_buf and 
                          self.data.Low[-1] >= self.lower_val - touch_buf_tight)
        
        if self.upper_val is not None:
            hits_top = (self.data.High[-1] >= self.upper_val - touch_buf and 
                       self.data.High[-1] <= self.upper_val + touch_buf)
        
        slope_up_ok = self.slope_lo is not None and self.slope_lo > 0
        slope_down_ok = self.slope_hi is not None and self.slope_hi < 0
        
        # Pivot age check
        idx = len(self.data) - 1
        pivots_lo_fresh = (self.pl1b is not None and self.pl2b is not None and 
                          (self.pl1b - self.pl2b) <= self.max_pivot_age)
        pivots_hi_fresh = (self.ph1b is not None and self.ph2b is not None and 
                          (self.ph1b - self.ph2b) <= self.max_pivot_age)
        
        # Stop prices
        tick = 0.01
        bull_stop_raw = None
        bear_stop_raw = None
        
        if self.tight_stop:
            if self.lower_val is not None:
                bull_stop_raw = self.lower_val - tick
            if self.upper_val is not None:
                bear_stop_raw = self.upper_val + tick
        else:
            if self.pl2 is not None:
                bull_stop_raw = self.pl2 - tick
            if self.ph2 is not None:
                bear_stop_raw = self.ph2 + tick
        
        # Cap stop distance
        max_stop_dist = self.max_stop_atr * atr_val
        bull_stop_price = bull_stop_raw
        bear_stop_price = bear_stop_raw
        
        if bull_stop_raw is not None:
            bull_stop_price = max(bull_stop_raw, self.data.Close[-1] - max_stop_dist)
        
        if bear_stop_raw is not None:
            bear_stop_price = min(bear_stop_raw, self.data.Close[-1] + max_stop_dist)
        
        # Reward:Risk calculation
        bull_risk = None
        bull_reward = None
        bull_rr = None
        
        if bull_stop_price is not None:
            bull_risk = self.data.Close[-1] - bull_stop_price
            if self.upper_val is not None:
                bull_reward = self.upper_val - self.data.Close[-1]
                if bull_risk > 0:
                    bull_rr = bull_reward / bull_risk
        
        bear_risk = None
        bear_reward = None
        bear_rr = None
        
        if bear_stop_price is not None:
            bear_risk = bear_stop_price - self.data.Close[-1]
            if self.lower_val is not None:
                bear_reward = self.data.Close[-1] - self.lower_val
                if bear_risk > 0:
                    bear_rr = bear_reward / bear_risk
        
        bull_rr_ok = bull_rr is not None and bull_rr >= self.min_rr
        bear_rr_ok = bear_rr is not None and bear_rr >= self.min_rr
        
        # Alert modes
        bull_mode = self.alert_mode in ["Bull Only", "Both"]
        bear_mode = self.alert_mode in ["Bear Only", "Both"]
        
        # Raw signal conditions
        bull_raw = (hits_bottom and slope_up_ok and is_wide_enough and 
                   bull_rr_ok and pivots_lo_fresh and bull_mode)
        bear_raw = (hits_top and slope_down_ok and is_wide_enough and 
                   bear_rr_ok and pivots_hi_fresh and bear_mode)
        
        # Cooldown logic
        bull_signal = False
        bear_signal = False
        
        if bull_raw:
            if self.last_bull_bar is None or idx - self.last_bull_bar >= self.cooldown:
                bull_signal = True
                self.last_bull_bar = idx
        
        if bear_raw:
            if self.last_bear_bar is None or idx - self.last_bear_bar >= self.cooldown:
                bear_signal = True
                self.last_bear_bar = idx
        
        # Execute trades
        if bull_signal:
            if not self.position:
                self.buy()
        
        if bear_signal:
            if self.position:
                self.sell()