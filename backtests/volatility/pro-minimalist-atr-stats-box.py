import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 14
    dma_len = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate indicators
        self.dma20 = self.I(pta.sma, close, length=self.dma_len)
        self.atr_value = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Calculate levels
        self.p2 = self.I(lambda: self.dma20 + (self.atr_value * 2) if self.atr_value is not None else pd.Series(0, index=close.index))
        self.p1 = self.I(lambda: self.dma20 + (self.atr_value * 1) if self.atr_value is not None else pd.Series(0, index=close.index))
        self.m1 = self.I(lambda: self.dma20 - (self.atr_value * 1) if self.atr_value is not None else pd.Series(0, index=close.index))
        self.m2 = self.I(lambda: self.dma20 - (self.atr_value * 2) if self.atr_value is not None else pd.Series(0, index=close.index))

    def next(self):
        # Buy when price touches lower band (m2) and starts moving up
        if len(self.data) > 1:
            if self.data.Close[-1] <= self.m2[-1] and self.data.Close[-1] > self.data.Close[-2]:
                if not self.position:
                    self.buy()
            
            # Sell when price touches upper band (p2) and starts moving down
            elif self.data.Close[-1] >= self.p2[-1] and self.data.Close[-1] < self.data.Close[-2]:
                if self.position:
                    self.sell()
            
            # Also sell on crossover below DMA (trend confirmation)
            elif crossover(self.dma20, self.data.Close):
                if self.position:
                    self.sell()