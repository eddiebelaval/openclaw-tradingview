import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    bbLength = 20
    bbMult = 2.0
    kcLength = 20
    kcMult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        bb_result = self.I(lambda: pta.bbands(close, length=self.bbLength, std=self.bbMult))
        self.bb_upper = self.I(lambda: bb_result[f'BBU_{self.bbLength}_{self.bbMult}'] if bb_result is not None else pd.Series(0, index=close.index))
        self.bb_lower = self.I(lambda: bb_result[f'BBL_{self.bbLength}_{self.bbMult}'] if bb_result is not None else pd.Series(0, index=close.index))
        self.bb_basis = self.I(lambda: bb_result[f'BB_{self.bbLength}_{self.bbMult}'] if bb_result is not None else pd.Series(0, index=close.index))
        
        # Keltner Channels
        self.ma_kc = self.I(pta.sma, close, length=self.kcLength)
        
        # True Range calculation
        tr = self.I(lambda: pta.true_range(high, low, close))
        self.range_ma_kc = self.I(lambda: pta.sma(tr, length=self.kcLength))
        
        # Keltner Upper and Lower
        self.kc_upper = self.I(lambda: self.ma_kc[-1] + self.range_ma_kc[-1] * self.kcMult if len(self) > max(self.bbLength, self.kcLength) else 0)
        self.kc_lower = self.I(lambda: self.ma_kc[-1] - self.range_ma_kc[-1] * self.kcMult if len(self) > max(self.bbLength, self.kcLength) else 0)
        
        # Squeeze signal: True when BB is inside KC
        self.sqz_on = self.I(lambda: (self.bb_lower[-1] > self.kc_lower[-1]) and (self.bb_upper[-1] < self.kc_upper[-1]) if len(self) > max(self.bbLength, self.kcLength) else False)

    def next(self):
        if len(self) < max(self.bbLength, self.kcLength) + 1:
            return
        
        # Get current values
        bb_lower_curr = self.bb_lower[-1]
        bb_upper_curr = self.bb_upper[-1]
        kc_lower_curr = self.kc_lower[-1]
        kc_upper_curr = self.kc_upper[-1]
        close_curr = self.data.Close[-1]
        
        # Check if squeeze is on (BB inside KC)
        sqz_on_curr = (bb_lower_curr > kc_lower_curr) and (bb_upper_curr < kc_upper_curr)
        
        # Check if squeeze was off in previous bar
        if len(self) >= 2:
            bb_lower_prev = self.bb_lower[-2]
            bb_upper_prev = self.bb_upper[-2]
            kc_lower_prev = self.kc_lower[-2]
            kc_upper_prev = self.kc_upper[-2]
            sqz_on_prev = (bb_lower_prev > kc_lower_prev) and (bb_upper_prev < kc_upper_prev)
            
            # Entry: Squeeze release (transition from squeeze on to off) with upward momentum
            if sqz_on_prev and not sqz_on_curr and close_curr > self.data.Close[-2]:
                if not self.position:
                    self.buy()
            
            # Entry: Squeeze release with downward momentum
            elif sqz_on_prev and not sqz_on_curr and close_curr < self.data.Close[-2]:
                if self.position:
                    self.sell()
            
            # Exit long: Price touches upper Keltner
            elif self.position and close_curr >= kc_upper_curr:
                self.sell()
            
            # Exit short: Price touches lower Keltner
            elif not self.position and close_curr <= kc_lower_curr and sqz_on_curr:
                self.buy()


