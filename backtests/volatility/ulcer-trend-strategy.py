import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 14
    uiMaLen = 5
    uiThreshold = 999.0
    trendMaLen = 50
    allowShort = True
    useStops = True
    stopPct = 2.0
    tpPct = 4.0
    useTrail = False
    atrLen = 14
    atrMult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Ulcer Index calculation
        def calc_ulcer_index(source, length):
            r = 100 * (source - source.rolling(length).max()) / source.rolling(length).max()
            return np.sqrt((r ** 2).rolling(length).mean())
        
        self.ui = self.I(lambda: calc_ulcer_index(close, self.lengthInput))
        self.uiMa = self.I(pta.sma, self.ui, length=self.uiMaLen)
        self.trendEMA = self.I(pta.ema, close, length=self.trendMaLen)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.last_ui = None
        self.last_uiMa = None

    def next(self):
        if len(self.data) < max(self.lengthInput, self.uiMaLen, self.trendMaLen) + 5:
            return
        
        current_ui = self.ui[-1]
        current_uiMa = self.uiMa[-1]
        current_close = self.data.Close[-1]
        current_trendEMA = self.trendEMA[-1]
        
        if current_ui is None or current_uiMa is None or current_trendEMA is None:
            return
        
        useThreshold = self.uiThreshold < 999.0
        
        # Check UI turning down (crosses under its MA) -> bullish bias
        uiTurnDown = (self.last_ui is not None and 
                      self.last_ui >= self.last_uiMa and 
                      current_ui < current_uiMa and 
                      (not useThreshold or current_ui < self.uiThreshold))
        
        # Check UI turning up (crosses over its MA) -> bearish bias
        uiTurnUp = (self.last_ui is not None and 
                    self.last_ui <= self.last_uiMa and 
                    current_ui > current_uiMa and 
                    (not useThreshold or current_ui > self.uiThreshold))
        
        # Entry conditions
        longCond = uiTurnDown and current_close > current_trendEMA
        shortCond = self.allowShort and uiTurnUp and current_close < current_trendEMA
        
        # Close on reverse signal (keeps single-direction positions)
        if uiTurnUp and self.position.size > 0:
            self.position.close()
        elif uiTurnDown and self.position.size < 0:
            self.position.close()
        
        # Entry logic
        if longCond:
            if self.position.size <= 0:
                if self.position.size < 0:
                    self.position.close()
                self.buy()
        elif shortCond:
            if self.position.size >= 0:
                if self.position.size > 0:
                    self.position.close()
                self.sell()
        
        # Fixed Stop / TP
        if self.useStops:
            if self.position.size > 0:
                stop_price = self.position.open_price * (1 - self.stopPct / 100)
                limit_price = self.position.open_price * (1 + self.tpPct / 100)
                
                if current_close <= stop_price:
                    self.position.close()
                elif current_close >= limit_price:
                    self.position.close()
            
            elif self.position.size < 0:
                stop_price = self.position.open_price * (1 + self.stopPct / 100)
                limit_price = self.position.open_price * (1 - self.tpPct / 100)
                
                if current_close >= stop_price:
                    self.position.close()
                elif current_close <= limit_price:
                    self.position.close()
        
        # ATR Trailing Stop
        if self.useTrail and self.atr[-1] is not None:
            atr_value = self.atr[-1]
            
            if self.position.size > 0:
                trail_stop = self.position.open_price - (atr_value * self.atrMult)
                if current_close <= trail_stop:
                    self.position.close()
            
            elif self.position.size < 0:
                trail_stop = self.position.open_price + (atr_value * self.atrMult)
                if current_close >= trail_stop:
                    self.position.close()
        
        self.last_ui = current_ui
        self.last_uiMa = current_uiMa


