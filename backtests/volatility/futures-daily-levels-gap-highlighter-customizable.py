import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    gap_threshold = 5.0
    label_offset = 2

    def init(self):
        pass

    def next(self):
        if len(self.data) < 2:
            return

        close_today = self.data.Close[-1]
        open_today = self.data.Open[-1]
        high_yesterday = self.data.High[-2]
        low_yesterday = self.data.Low[-2]
        close_yesterday = self.data.Close[-2]
        open_yesterday = self.data.Open[-2]

        pdh = high_yesterday
        pdl = low_yesterday
        pdo = open_yesterday
        pdc = close_yesterday
        cd_open = open_today

        gap_size = abs(cd_open - pdc)

        is_new_session = len(self.data) >= 2 and self.data.Close[-2] != close_yesterday

        if is_new_session:
            if gap_size >= self.gap_threshold:
                if cd_open > pdc:
                    if not self.position:
                        self.buy()
                else:
                    if self.position:
                        self.sell()

        if self.position:
            if close_today > pdh:
                self.sell()
            elif close_today < pdl:
                self.sell()


