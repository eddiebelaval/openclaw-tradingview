import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Squeeze zone parameters
    sqz_length = 14
    bb_mult = 2.0
    kc_mult = 1.5
    minSqueezeBars = 12
    atrLowMulti = 0.5
    atrHighMulti = 2.5
    atr_length = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for zone width filtering
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Bollinger Bands components
        self.bb_mid = self.I(pta.sma, close, length=self.sqz_length)
        self.bb_std = self.I(
            lambda: close.rolling(self.sqz_length).std(),
            name="bb_std"
        )
        
        # Keltner Channel components
        self.kc_mid = self.I(pta.ema, close, length=self.sqz_length)
        
        # True Range
        def calc_tr(h, l, c):
            tr1 = h - l
            tr2 = abs(h - c.shift(1))
            tr3 = abs(l - c.shift(1))
            return pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
        
        self.tr = self.I(
            lambda: calc_tr(high, low, close),
            name="tr"
        )
        
        self.tr_sma = self.I(
            lambda: calc_tr(high, low, close).rolling(self.sqz_length).mean(),
            name="tr_sma"
        )
        
        # Squeeze detection
        self.in_squeeze = self.I(self._detect_squeeze, name="in_squeeze")
        
        # Track squeeze fire events
        self.squeeze_fired_prev = False
        self.squeeze_zones = []

    def _detect_squeeze(self):
        """Detect if BB is inside KC"""
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        bb_mid = pta.sma(close, length=self.sqz_length)
        bb_std = close.rolling(self.sqz_length).std()
        bb_up = bb_mid + self.bb_mult * bb_std
        bb_dn = bb_mid - self.bb_mult * bb_std
        
        def calc_tr(h, l, c):
            tr1 = h - l
            tr2 = abs(h - c.shift(1))
            tr3 = abs(l - c.shift(1))
            return pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
        
        tr = calc_tr(high, low, close)
        kc_mid = pta.ema(close, length=self.sqz_length)
        kc_up = kc_mid + self.kc_mult * tr.rolling(self.sqz_length).mean()
        kc_dn = kc_mid - self.kc_mult * tr.rolling(self.sqz_length).mean()
        
        in_sqz = (bb_up < kc_up) & (bb_dn > kc_dn)
        return in_sqz.astype(float)

    def next(self):
        if len(self.data) < self.minSqueezeBars + 1:
            return
        
        # Check if squeeze condition is met for minimum bars
        squeeze_sum = self.in_squeeze[-self.minSqueezeBars:].sum()
        current_squeeze = squeeze_sum == self.minSqueezeBars
        
        # Detect squeeze fire (transition from no squeeze to squeeze)
        squeeze_fired = current_squeeze and not self.squeeze_fired_prev
        
        if squeeze_fired:
            # Get highest high and lowest low over minSqueezeBars
            high_recent = pd.Series(self.data.High[-self.minSqueezeBars:]).max()
            low_recent = pd.Series(self.data.Low[-self.minSqueezeBars:]).min()
            zone_width = high_recent - low_recent
            
            # Check ATR-based width constraints
            atr_val = self.atr[-1] if self.atr[-1] is not None else 1.0
            min_width = atr_val * self.atrLowMulti
            max_width = atr_val * self.atrHighMulti
            
            if zone_width >= min_width and zone_width <= max_width:
                # Squeeze zone is valid - create trading signal
                zone_mid = (high_recent + low_recent) * 0.5
                self.squeeze_zones.append({
                    'top': high_recent,
                    'bottom': low_recent,
                    'mid': zone_mid,
                    'bar': len(self.data)
                })
        
        # Trading logic based on squeeze zones
        if len(self.squeeze_zones) > 0:
            # Use the most recent squeeze zone
            recent_zone = self.squeeze_zones[-1]
            current_price = self.data.Close[-1]
            
            # Buy when price bounces up from lower zone boundary
            if current_price <= recent_zone['bottom'] and not self.position:
                self.buy()
            
            # Sell when price hits upper zone boundary or close above it
            elif current_price >= recent_zone['top'] and self.position:
                self.sell()
            
            # Exit on close below middle if in position
            elif self.position and current_price < recent_zone['bottom']:
                self.sell()
        
        self.squeeze_fired_prev = current_squeeze


