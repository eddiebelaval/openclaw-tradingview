import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Envelope settings
    length = 30
    percent = 2.0
    useEMA = True
    
    # Alert zone
    alertZone = 0.15
    
    # Trend settings
    emaFast = 21
    emaSlow = 50
    adxLen = 14
    
    # Divergence settings
    macdFast = 12
    macdSlow = 26
    macdSignal = 9
    rsiLen = 14
    bbpLen = 13
    efiLen = 5
    divLookback = 5
    
    # Speed settings
    speedLen = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Envelope basis
        if self.useEMA:
            self.basis = self.I(pta.ema, close, length=self.length)
        else:
            self.basis = self.I(pta.sma, close, length=self.length)
        
        # Upper and lower envelope
        self.upperEnv = self.I(lambda: self.basis * (1 + self.percent / 100))
        self.lowerEnv = self.I(lambda: self.basis * (1 - self.percent / 100))
        
        # Price speed
        self.priceSpeed = self.I(lambda: (close - close.shift(self.speedLen)) / self.speedLen)
        self.absSpeed = self.I(lambda: np.abs(self.priceSpeed))
        
        # Distance calculations
        self.distUpper = self.I(lambda: self.upperEnv - close)
        self.distLower = self.I(lambda: close - self.lowerEnv)
        
        # EMA trend
        self.emaF = self.I(pta.ema, close, length=self.emaFast)
        self.emaS = self.I(pta.ema, close, length=self.emaSlow)
        
        # ADX calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.adxLen)
        
        def calc_adx():
            upMove = high - high.shift(1)
            downMove = low.shift(1) - low
            plusDM = np.where((upMove > downMove) & (upMove > 0), upMove, 0)
            minusDM = np.where((downMove > upMove) & (downMove > 0), downMove, 0)
            
            plusDI = 100 * pta.ema(pd.Series(plusDM), length=self.adxLen) / self.atr
            minusDI = 100 * pta.ema(pd.Series(minusDM), length=self.adxLen) / self.atr
            
            dx = 100 * np.abs(plusDI - minusDI) / (plusDI + minusDI)
            adx = pta.ema(pd.Series(dx), length=self.adxLen)
            return adx
        
        self.adxVal = self.I(calc_adx)
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal))
        self.macdHist = self.I(lambda: macd_result.iloc[:, 2] if macd_result is not None else pd.Series(0, index=close.index))
        
        # RSI
        self.rsiVal = self.I(pta.rsi, close, length=self.rsiLen)
        
        # BBPower
        ema_bbp = self.I(pta.ema, close, length=self.bbpLen)
        self.bbpBull = self.I(lambda: high - ema_bbp)
        self.bbpBear = self.I(lambda: low - ema_bbp)
        
        # EFI
        self.efiVal = self.I(lambda: pta.ema(close - close.shift(1), length=self.efiLen) * volume)
        
        # Divergence detection helpers
        def get_lowest_low():
            return low.rolling(self.divLookback).min()
        
        def get_highest_high():
            return high.rolling(self.divLookback).max()
        
        self.priceLow = self.I(get_lowest_low)
        self.priceHigh = self.I(get_highest_high)
        
        def get_macd_low():
            return self.macdHist.rolling(self.divLookback).min()
        
        def get_macd_high():
            return self.macdHist.rolling(self.divLookback).max()
        
        self.macdLow = self.I(get_macd_low)
        self.macdHigh = self.I(get_macd_high)
        
        def get_rsi_low():
            return self.rsiVal.rolling(self.divLookback).min()
        
        def get_rsi_high():
            return self.rsiVal.rolling(self.divLookback).max()
        
        self.rsiLow = self.I(get_rsi_low)
        self.rsiHigh = self.I(get_rsi_high)
        
        def get_bbp_bear_low():
            return self.bbpBear.rolling(self.divLookback).min()
        
        def get_bbp_bull_high():
            return self.bbpBull.rolling(self.divLookback).max()
        
        self.bbpBearLow = self.I(get_bbp_bear_low)
        self.bbpBullHigh = self.I(get_bbp_bull_high)
        
        def get_efi_low():
            return self.efiVal.rolling(self.divLookback).min()
        
        def get_efi_high():
            return self.efiVal.rolling(self.divLookback).max()
        
        self.efiLow = self.I(get_efi_low)
        self.efiHigh = self.I(get_efi_high)

    def next(self):
        # Touch/break detection
        zoneSize = self.data.Close[-1] * self.alertZone / 100
        
        touchUpper = abs(self.data.High[-1] - self.upperEnv[-1]) <= zoneSize or self.data.High[-1] >= self.upperEnv[-1]
        touchLower = abs(self.data.Low[-1] - self.lowerEnv[-1]) <= zoneSize or self.data.Low[-1] <= self.lowerEnv[-1]
        breakAbove = self.data.Close[-1] > self.upperEnv[-1]
        breakBelow = self.data.Close[-1] < self.lowerEnv[-1]
        
        newTouchUpper = touchUpper and (len(self.data) > 1 and not (abs(self.data.High[-2] - self.upperEnv[-2]) <= zoneSize or self.data.High[-2] >= self.upperEnv[-2]))
        newTouchLower = touchLower and (len(self.data) > 1 and not (abs(self.data.Low[-2] - self.lowerEnv[-2]) <= zoneSize or self.data.Low[-2] <= self.lowerEnv[-2]))
        newBreakAbove = breakAbove and (len(self.data) > 1 and self.data.Close[-2] <= self.upperEnv[-2])
        newBreakBelow = breakBelow and (len(self.data) > 1 and self.data.Close[-2] >= self.lowerEnv[-2])
        
        # Divergence scores
        macdBullDiv = (self.data.Low[-1] <= self.priceLow[-1]) and (self.macdHist[-1] > self.macdLow[-1])
        macdBearDiv = (self.data.High[-1] >= self.priceHigh[-1]) and (self.macdHist[-1] < self.macdHigh[-1])
        
        rsiBullDiv = (self.data.Low[-1] <= self.priceLow[-1]) and (self.rsiVal[-1] > self.rsiLow[-1])
        rsiBearDiv = (self.data.High[-1] >= self.priceHigh[-1]) and (self.rsiVal[-1] < self.rsiHigh[-1])
        
        bbpBullDiv = (self.data.Low[-1] <= self.priceLow[-1]) and (self.bbpBear[-1] > self.bbpBearLow[-1])
        bbpBearDiv = (self.data.High[-1] >= self.priceHigh[-1]) and (self.bbpBull[-1] < self.bbpBullHigh[-1])
        
        efiBullDiv = (self.data.Low[-1] <= self.priceLow[-1]) and (self.efiVal[-1] > self.efiLow[-1])
        efiBearDiv = (self.data.High[-1] >= self.priceHigh[-1]) and (self.efiVal[-1] < self.efiHigh[-1])
        
        bullScore = (3.0 if macdBullDiv else 0.0) + (2.0 if bbpBullDiv else 0.0) + (2.0 if rsiBullDiv else 0.0) + (1.0 if efiBullDiv else 0.0)
        bearScore = (3.0 if macdBearDiv else 0.0) + (2.0 if bbpBearDiv else 0.0) + (2.0 if rsiBearDiv else 0.0) + (1.0 if efiBearDiv else 0.0)
        
        # Trading signals
        strongBull = touchLower and bullScore >= 3
        strongBear = touchUpper and bearScore >= 3
        
        # Entry and exit logic
        if strongBull and not self.position:
            self.buy()
        elif strongBear and self.position:
            self.position.close()
        
        # Exit on opposite signal
        if strongBear and not self.position:
            self.sell()
        elif strongBull and self.position.is_short:
            self.position.close()
        
        # Exit on break in opposite direction
        if newBreakAbove and self.position.is_short:
            self.position.close()
        elif newBreakBelow and self.position.is_long:
            self.position.close()


