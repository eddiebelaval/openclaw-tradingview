        # MACD calculation (EMA12 - EMA26)
        ema12 = self.I(pta.ema, close, length=12)
        ema26 = self.I(pta.ema, close, length=26)
        self.f_macd = self.I(lambda: ema12 - ema26)
        
        # Base line (WMA)
        self.base_line = self.I(pta.wma, close, length=self.ai_sensitivity)
        
