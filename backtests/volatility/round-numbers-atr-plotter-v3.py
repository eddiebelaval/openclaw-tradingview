import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
import math


class TvStrategy(Strategy):
    # ATR settings
    atr_len = 26
    atr_mult = 0.7
    number_of_lines = 5
    grav_pct = 25
    round_levels = True
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.atr_val = atr
        
    def next(self):
        # Get current ATR value
        if len(self.data) < self.atr_len:
            return
            
        atr_val = self.atr_val[-1]
        if pd.isna(atr_val) or atr_val <= 0:
            return
        
        # Calculate raw step
        raw_step = atr_val * self.atr_mult
        
        # Round step helper
        def round_step(x):
            if x <= 0:
                return x
            pow10 = math.pow(10, math.floor(math.log10(x)))
            return math.round(x / pow10) * pow10
        
        # Get step
        step_px = round_step(raw_step) if self.round_levels else raw_step
        
        if step_px <= 0:
            return
        
        # Round level helper
        def round_level(price, s):
            if s > 0:
                return math.round(price / s) * s
            return price
        
        # Get center (current price rounded to nearest level)
        center = round_level(self.data.Close[-1], step_px) if self.round_levels else self.data.Close[-1]
        
        # Calculate gravitation offset
        grav_off = step_px * self.grav_pct * 0.01
        
        # Create levels for trading signals
        levels = []
        
        # Center level
        levels.append(center)
        
        # Upper levels
        for i in range(1, self.number_of_lines):
            levels.append(center + i * step_px)
        
        # Lower levels
        for i in range(1, self.number_of_lines):
            levels.append(center - i * step_px)
        
        levels.sort()
        
        current_price = self.data.Close[-1]
        
        # Simple trading logic based on round number levels
        # Buy when price touches lower levels and starts reversing
        # Sell when price touches upper levels and starts reversing
        
        if len(self.data) < 2:
            return
        
        prev_price = self.data.Close[-2]
        
        # Find closest levels above and below current price
        levels_below = [l for l in levels if l < current_price]
        levels_above = [l for l in levels if l > current_price]
        
        if levels_below and levels_above:
            closest_below = max(levels_below)
            closest_above = min(levels_above)
            
            # Buy signal: price bounces from lower level
            if prev_price < closest_below and current_price > closest_below and not self.position:
                self.buy()
            
            # Sell signal: price touches upper level
            if current_price >= closest_above and self.position:
                self.sell()
        
        # Stop loss: if price breaks below lowest level
        if levels_below:
            lowest = min(levels_below)
            if current_price < lowest - step_px and self.position:
                self.sell()


