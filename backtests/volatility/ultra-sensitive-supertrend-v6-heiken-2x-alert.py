import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrPeriod1 = 10
    multiplier1 = 1.0
    atrPeriod2 = 5
    multiplier2 = 0.5
    useHeikenAshi = True

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Heiken-Ashi calculations
        ha_close = (open_ + high + low + close) / 4
        
        def calc_ha_open():
            ha_open = pd.Series(index=close.index, dtype=float)
            ha_open.iloc[0] = (open_.iloc[0] + close.iloc[0]) / 2
            for i in range(1, len(close)):
                ha_open.iloc[i] = (ha_open.iloc[i-1] + ha_close.iloc[i-1]) / 2
            return ha_open
        
        ha_open = self.I(calc_ha_open)
        ha_high = self.I(lambda: pd.Series([max(high.iloc[i], ha_open[-1] if i == len(high) - 1 else max(high.iloc[i], max(ha_open.iloc[i], ha_close.iloc[i]))) for i in range(len(high))], index=high.index))
        ha_low = self.I(lambda: pd.Series([min(low.iloc[i], ha_open[-1] if i == len(low) - 1 else min(low.iloc[i], min(ha_open.iloc[i], ha_close.iloc[i]))) for i in range(len(low))], index=low.index))
        
        price_src = self.I(lambda: ha_close if self.useHeikenAshi else close)

