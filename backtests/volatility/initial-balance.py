import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime


class TvStrategy(Strategy):
    # IB session parameters
    ib_start_hour = 9
    ib_start_minute = 30
    ib_end_hour = 10
    ib_end_minute = 30
    
    # Trading parameters
    extension_ratio = 1.5

    def init(self):
        self.ib_high = None
        self.ib_low = None
        self.ib_range = None
        self.session_started = False
        self.entry_price = None

    def next(self):
        # Get current bar time
        current_time = self.data.index[-1]
        
        # Check if we're in IB session (9:30-10:30)
        is_in_session = (
            current_time.hour == self.ib_start_hour and 
            current_time.minute >= self.ib_start_minute
        ) or (
            current_time.hour == self.ib_end_hour and 
            current_time.minute < self.ib_end_minute
        )
        
        # Check if session just started
        is_first_bar = len(self.data) > 1 and (
            (self.data.index[-2].hour != self.ib_start_hour or 
             self.data.index[-2].minute < self.ib_start_minute) and
            is_in_session
        )
        
        # Initialize IB levels on first bar of session
        if is_first_bar:
            self.ib_high = self.data.High[-1]
            self.ib_low = self.data.Low[-1]
            self.ib_range = self.ib_high - self.ib_low
            self.session_started = True
        
        # Update IB high/low during session
        elif is_in_session and self.session_started:
            self.ib_high = max(self.ib_high, self.data.High[-1])
            self.ib_low = min(self.ib_low, self.data.Low[-1])
            self.ib_range = self.ib_high - self.ib_low
        
        # Trading logic: use IB breakouts
        if self.ib_high is not None and self.ib_low is not None:
            ext_high = self.ib_high + (self.ib_range * self.extension_ratio)
            ext_low = self.ib_low - (self.ib_range * self.extension_ratio)
            
            # Buy on breakout above IB high + extension
            if self.data.Close[-1] > ext_high and not self.position:
                self.buy()
                self.entry_price = self.data.Close[-1]
            
            # Sell on breakout below IB low - extension
            elif self.data.Close[-1] < ext_low and self.position:
                self.sell()
            
            # Exit long on return to IB low
            elif self.position and self.data.Low[-1] < self.ib_low:
                self.sell()


