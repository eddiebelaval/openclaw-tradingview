import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    smoothing = "RMA"
    riskratio = 1.0
    lookback = 3
    stopSizeInput = 1.0
    stopSizeUseATR = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate True Range
        tr = self.I(self._calculate_tr, high, low, close)

        # Calculate ATR with smoothing
        if self.smoothing == "RMA":
            atr_value = self.I(pta.rma, tr, length=self.length)
        elif self.smoothing == "SMA":
            atr_value = self.I(pta.sma, tr, length=self.length)
        elif self.smoothing == "EMA":
            atr_value = self.I(pta.ema, tr, length=self.length)
        else:  # WMA
            atr_value = self.I(pta.wma, tr, length=self.length)

        self.atr_value = atr_value

        # Calculate highest high and lowest low over lookback period
        highest_high = self.I(lambda: high.rolling(self.lookback).max())
        lowest_low = self.I(lambda: low.rolling(self.lookback).min())

        self.highest_high = highest_high
        self.lowest_low = lowest_low

        # Calculate stop size
        self.stop_size = self.I(
            self._calculate_stop_size, atr_value, self.stopSizeInput, self.stopSizeUseATR
        )

        # Calculate entry sizes
        self.long_entry_size = self.I(
            self._calculate_long_entry_size, close, lowest_low, self.stop_size
        )
        self.short_entry_size = self.I(
            self._calculate_short_entry_size, highest_high, close, self.stop_size
        )

    def _calculate_tr(self, high, low, close):
        prev_close = close.shift(1)
        tr1 = high - low
        tr2 = np.abs(high - prev_close)
        tr3 = np.abs(low - prev_close)
        tr = np.maximum(tr1, np.maximum(tr2, tr3))
        return pd.Series(tr, index=close.index)

    def _calculate_stop_size(self, atr_value, stop_size_input, use_atr):
        if use_atr:
            return atr_value * stop_size_input
        else:
            return pd.Series(stop_size_input, index=atr_value.index)

    def _calculate_long_entry_size(self, close, lowest_low, stop_size):
        return close - lowest_low + stop_size

    def _calculate_short_entry_size(self, highest_high, close, stop_size):
        return highest_high - close + stop_size

    def next(self):
        if np.isnan(self.long_entry_size[-1]) or np.isnan(self.short_entry_size[-1]):
            return

        main = self.long_entry_size[-1]
        sig = self.short_entry_size[-1]

        # Detect crossovers
        if len(self.long_entry_size) > 1 and len(self.short_entry_size) > 1:
            prev_main = self.long_entry_size[-2]
            prev_sig = self.short_entry_size[-2]

            cross_up = prev_main <= prev_sig and main > sig
            cross_down = prev_main >= prev_sig and main < sig

            if cross_up and not self.position:
                self.buy()
            elif cross_down and self.position:
                self.position.close()