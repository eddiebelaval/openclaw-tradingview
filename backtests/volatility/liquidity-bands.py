import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    mult = 2.0
    inner_m = 1.0
    signal_mode = "Mean Reversion"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        def calc_lma():
            liq_proxy = volume * pta.atr(high, low, close, length=1)
            liquidity = liq_proxy.fillna(1.0)
            liquidity = liquidity.replace(0, 1.0)
            
            sum_weights = liquidity.rolling(window=self.length).sum()
            lma = (close * liquidity).rolling(window=self.length).sum() / sum_weights
            lma_sq = (close ** 2 * liquidity).rolling(window=self.length).sum() / sum_weights
            
            variance = np.maximum(lma_sq - lma ** 2, 0)
            std_dev = np.sqrt(variance)
            
            upper_band = lma + (self.mult * std_dev)
            lower_band = lma - (self.mult * std_dev)
            
            return lma, upper_band, lower_band, std_dev
        
        self.lma = self.I(calc_lma)
        
        def get_lma_vals():
            lma, _, _, _ = calc_lma()
            return lma
        
        def get_upper_vals():
            _, upper, _, _ = calc_lma()
            return upper
        
        def get_lower_vals():
            _, _, lower, _ = calc_lma()
            return lower
        
        def get_std_vals():
            _, _, _, std = calc_lma()
            return std
        
        self.lma_line = self.I(get_lma_vals)
        self.upper_band = self.I(get_upper_vals)
        self.lower_band = self.I(get_lower_vals)
        self.std_dev = self.I(get_std_vals)
        
        def calc_inner_upper():
            return self.lma_line + (self.inner_m * self.std_dev)
        
        def calc_inner_lower():
            return self.lma_line - (self.inner_m * self.std_dev)
        
        self.inner_upper = self.I(calc_inner_upper)
        self.inner_lower = self.I(calc_inner_lower)
        
        def calc_band_width():
            bw = (self.upper_band - self.lower_band) / np.maximum(self.lma_line, 0.0001) * 100
            return bw
        
        self.band_width = self.I(calc_band_width)
        
        def calc_squeeze():
            lowest_bw = self.band_width.rolling(window=50).min()
            squeeze_cond = self.band_width < lowest_bw * 1.05
            return squeeze_cond.astype(float)
        
        self.squeeze = self.I(calc_squeeze)

    def next(self):
        if len(self.data) < self.length + 1:
            return
        
        close_current = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        
        upper_current = self.upper_band[-1]
        upper_prev = self.upper_band[-2]
        lower_current = self.lower_band[-1]
        lower_prev = self.lower_band[-2]
        
        lma_current = self.lma_line[-1]
        
        mr_buy = close_prev <= lower_prev and close_current > lower_current
        mr_sell = close_prev >= upper_prev and close_current < upper_current
        
        bo_buy = close_prev <= upper_prev and close_current > upper_current
        bo_sell = close_prev >= lower_prev and close_current < lower_current
        
        if self.signal_mode == "Mean Reversion":
            long_signal = mr_buy
            short_signal = mr_sell
        elif self.signal_mode == "Breakout":
            long_signal = bo_buy
            short_signal = bo_sell
        else:
            long_signal = mr_buy or bo_buy
            short_signal = mr_sell or bo_sell
        
        if long_signal and not self.position:
            self.buy()
        elif short_signal and self.position:
            self.sell()


