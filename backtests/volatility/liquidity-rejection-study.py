import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    useTrend = True
    emaLen = 200
    lookbackSR = 20
    volMult = 1.2
    atrLen = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)

        # EMA Trend
        self.emaTrend = self.I(pta.ema, close, length=self.emaLen)

        # Pivot levels using rolling max/min
        self.resLevel = self.I(lambda: high.rolling(self.lookbackSR).max().shift(1).fillna(method='bfill'))
        self.supLevel = self.I(lambda: low.rolling(self.lookbackSR).min().shift(1).fillna(method='bfill'))

        # ATR and volatility calculations
        atr_series = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.atr = atr_series if atr_series is not None else self.I(lambda: pd.Series(0, index=close.index))

        # Body and wicks
        self.body = self.I(lambda: np.abs(close - open_))
        self.uWick = self.I(lambda: high - np.maximum(open_, close))
        self.lWick = self.I(lambda: np.minimum(open_, close) - low)

        # Average volume
        self.avgVol = self.I(pta.sma, volume, length=20)

        # State tracking
        self.limitPrice = np.nan
        self.state = 0

    def next(self):
        if len(self.data) < max(self.emaLen, self.lookbackSR, self.atrLen, 20):
            return

        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]

        emaTrend_val = self.emaTrend[-1]
        resLevel_val = self.resLevel[-1]
        supLevel_val = self.supLevel[-1]
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        body_val = self.body[-1]
        uWick_val = self.uWick[-1]
        lWick_val = self.lWick[-1]
        avgVol_val = self.avgVol[-1]

        # Baseline checks
        isAboveBaseline = (not self.useTrend) or (close_val > emaTrend_val)
        isBelowBaseline = (not self.useTrend) or (close_val < emaTrend_val)

        # Support/Resistance zone checks
        inSupportZone = low_val <= supLevel_val + (atr_val * 0.5)
        inResistZone = high_val >= resLevel_val - (atr_val * 0.5)

        # Rejection signals
        rejectionUp = (lWick_val > (body_val * 2) and 
                       inSupportZone and 
                       volume_val > (avgVol_val * self.volMult) and 
                       isAboveBaseline)
        
        rejectionDn = (uWick_val > (body_val * 2) and 
                       inResistZone and 
                       volume_val > (avgVol_val * self.volMult) and 
                       isBelowBaseline)

        # Update state and limit price
        if rejectionUp:
            self.limitPrice = high_val
            self.state = 1
        elif rejectionDn:
            self.limitPrice = low_val
            self.state = -1

        # Check crossovers
        pivotConfirmedUp = False
        pivotConfirmedDn = False

        if self.state == 1 and not np.isnan(self.limitPrice):
            if crossover(close_val, self.limitPrice):
                pivotConfirmedUp = True

        if self.state == -1 and not np.isnan(self.limitPrice):
            if crossover(self.limitPrice, close_val):
                pivotConfirmedDn = True

        # Reset logic
        if pivotConfirmedUp or pivotConfirmedDn:
            self.state = 0
            self.limitPrice = np.nan

        # Trading logic
        if pivotConfirmedUp:
            if not self.position:
                self.buy()
        elif pivotConfirmedDn:
            if self.position:
                self.sell()