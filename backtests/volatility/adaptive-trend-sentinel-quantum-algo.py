import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sensitivityFactor = 1.2
    volatilityPeriod = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for volatility measurement
        atr = self.I(pta.atr, high, low, close, length=self.volatilityPeriod)
        self.atr = atr
        
        # Calculate boundary distance
        self.boundaryDistance = self.I(lambda: self.atr * self.sensitivityFactor)
        
        # Calculate smoothed price using EMA
        self.smoothedPrice = self.I(pta.ema, close, length=1)
        
        # Initialize sentinel boundary tracker
        self.sentinelBoundary = np.zeros(len(close))
        self.trendRegime = np.zeros(len(close))
        self._calculate_sentinel()
        
    def _calculate_sentinel(self):
        """Pre-calculate sentinel boundary for all bars"""
        close = self.data.Close
        atr = self.atr
        
        for i in range(len(close)):
            if i == 0:
                self.sentinelBoundary[i] = close[i]
                self.trendRegime[i] = 0
            else:
                prev_boundary = self.sentinelBoundary[i-1]
                prev_price = close[i-1]
                curr_price = close[i]
                boundary_dist = atr[i] if atr[i] is not None else (atr[i-1] if i > 0 and atr[i-1] is not None else 0)
                boundary_dist *= self.sensitivityFactor
                
                # Uptrend: boundary ratchets up
                if prev_price > prev_boundary and curr_price > prev_boundary:
                    self.sentinelBoundary[i] = max(prev_boundary, curr_price - boundary_dist)
                # Downtrend: boundary ratchets down
                elif prev_price < prev_boundary and curr_price < prev_boundary:
                    self.sentinelBoundary[i] = min(prev_boundary, curr_price + boundary_dist)
                # Regime flip
                elif curr_price > prev_boundary:
                    self.sentinelBoundary[i] = curr_price - boundary_dist
                else:
                    self.sentinelBoundary[i] = curr_price + boundary_dist
                
                # Update trend regime
                if prev_price < prev_boundary and curr_price > prev_boundary:
                    self.trendRegime[i] = 1
                elif prev_price > prev_boundary and curr_price < prev_boundary:
                    self.trendRegime[i] = -1
                else:
                    self.trendRegime[i] = self.trendRegime[i-1]
    
    def next(self):
        close = self.data.Close[-1]
        smoothed = self.smoothedPrice[-1]
        boundary = self.sentinelBoundary[len(self.data) - 1]
        
        # Check if smoothed price crosses above boundary
        if len(self.data) > 1:
            prev_smoothed = self.smoothedPrice[-2]
            prev_boundary = self.sentinelBoundary[len(self.data) - 2]
            
            priceBreaksAbove = prev_smoothed <= prev_boundary and smoothed > boundary
            priceBreaksBelow = prev_smoothed >= prev_boundary and smoothed < boundary
            
            isBullishRegime = close > boundary
            isBearishRegime = close < boundary
            
            longEntry = isBullishRegime and priceBreaksAbove
            shortEntry = isBearishRegime and priceBreaksBelow
            
            # Entry and exit logic
            if longEntry and not self.position:
                self.buy()
            elif shortEntry and self.position:
                self.sell()