import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # CVD Settings
    reset_mode = "Daily"
    use_wicks = True
    smooth_len = 21
    show_ma = True
    
    # Divergence Settings
    show_div = True
    pivot_len = 5
    min_bars_gap = 5
    show_lines = True
    
    # Alert Settings
    alert_div = True
    alert_cross = True

    def init(self):
        # Prepare data
        self.high = pd.Series(self.data.High)
        self.low = pd.Series(self.data.Low)
        self.close = pd.Series(self.data.Close)
        self.open = pd.Series(self.data.Open)
        self.volume = pd.Series(self.data.Volume)
        
        # Calculate CVD (Cumulative Volume Delta)
        self.delta = self.I(self._calculate_delta)
        self.cvd = self.I(self._calculate_cvd)
        self.cvd_ema = self.I(self._calculate_cvd_ema)
        
        # Crossover signals
        self.crossover_up = self.I(self._detect_crossover_up)
        self.crossover_down = self.I(self._detect_crossover_down)
        
        # Divergence tracking
        self.last_ph_price = None
        self.last_ph_cvd = None
        self.last_ph_bar = None
        
        self.last_pl_price = None
        self.last_pl_cvd = None
        self.last_pl_bar = None
        
        self.in_long = False

    def _calculate_delta(self):
        """Calculate delta for each bar"""
        deltas = []
        for i in range(len(self.data)):
            rng = max(self.high.iloc[i] - self.low.iloc[i], 0.0001)
            pos_in_bar = (self.close.iloc[i] - self.low.iloc[i]) / rng
            
            if self.use_wicks:
                signed_w = (pos_in_bar - 0.5) * 2.0
                delta = self.volume.iloc[i] * signed_w
            else:
                if self.close.iloc[i] > self.open.iloc[i]:
                    delta = self.volume.iloc[i]
                elif self.close.iloc[i] < self.open.iloc[i]:
                    delta = -self.volume.iloc[i]
                else:
                    delta = 0.0
            
            deltas.append(delta)
        
        return pd.Series(deltas, index=self.close.index)

    def _calculate_cvd(self):
        """Calculate cumulative volume delta with reset logic"""
        cvd_values = []
        cumsum = 0
        
        for i in range(len(self.data)):
            # Determine if reset should occur
            should_reset = False
            
            if self.reset_mode == "Daily" and i > 0:
                curr_date = pd.Timestamp(self.data.index[i]).date()
                prev_date = pd.Timestamp(self.data.index[i-1]).date()
                should_reset = curr_date != prev_date
            elif self.reset_mode == "Weekly" and i > 0:
                curr_week = pd.Timestamp(self.data.index[i]).isocalendar()[1]
                prev_week = pd.Timestamp(self.data.index[i-1]).isocalendar()[1]
                should_reset = curr_week != prev_week
            elif self.reset_mode == "Monthly" and i > 0:
                curr_month = pd.Timestamp(self.data.index[i]).month
                prev_month = pd.Timestamp(self.data.index[i-1]).month
                should_reset = curr_month != prev_month
            
            if should_reset:
                cumsum = self.delta.iloc[i]
            else:
                cumsum += self.delta.iloc[i]
            
            cvd_values.append(cumsum)
        
        return pd.Series(cvd_values, index=self.close.index)

    def _calculate_cvd_ema(self):
        """Calculate EMA of CVD"""
        ema = pta.ema(self.cvd, length=self.smooth_len)
        return ema if ema is not None else pd.Series(0, index=self.cvd.index)

    def _detect_crossover_up(self):
        """Detect CVD crossing above zero"""
        crossovers = []
        for i in range(len(self.cvd)):
            if i == 0:
                crossovers.append(False)
            else:
                cross = self.cvd.iloc[i-1] <= 0 and self.cvd.iloc[i] > 0
                crossovers.append(cross)
        return pd.Series(crossovers, index=self.cvd.index)

    def _detect_crossover_down(self):
        """Detect CVD crossing below zero"""
        crossovers = []
        for i in range(len(self.cvd)):
            if i == 0:
                crossovers.append(False)
            else:
                cross = self.cvd.iloc[i-1] >= 0 and self.cvd.iloc[i] < 0
                crossovers.append(cross)
        return pd.Series(crossovers, index=self.cvd.index)

    def _find_pivot_high(self, data, left, right):
        """Find pivot high"""
        for i in range(len(data)):
            if i < left or i > len(data) - right - 1:
                continue
            is_pivot = True
            mid_val = data.iloc[i]
            for j in range(i - left, i):
                if data.iloc[j] >= mid_val:
                    is_pivot = False
                    break
            if is_pivot:
                for j in range(i + 1, i + right + 1):
                    if data.iloc[j] >= mid_val:
                        is_pivot = False
                        break
            if is_pivot:
                yield i, mid_val

    def _find_pivot_low(self, data, left, right):
        """Find pivot low"""
        for i in range(len(data)):
            if i < left or i > len(data) - right - 1:
                continue
            is_pivot = True
            mid_val = data.iloc[i]
            for j in range(i - left, i):
                if data.iloc[j] <= mid_val:
                    is_pivot = False
                    break
            if is_pivot:
                for j in range(i + 1, i + right + 1):
                    if data.iloc[j] <= mid_val:
                        is_pivot = False
                        break
            if is_pivot:
                yield i, mid_val

    def next(self):
        current_idx = len(self.data) - 1
        
        # Get current values
        cvd_val = self.cvd.iloc[current_idx]
        cvd_ema_val = self.cvd_ema.iloc[current_idx]
        cross_up = self.crossover_up.iloc[current_idx]
        cross_down = self.crossover_down.iloc[current_idx]
        
        # Simple trading logic based on CVD crossovers and EMA
        if cross_up and cvd_ema_val > 0:
            if not self.position:
                self.buy()
                self.in_long = True
        
        if cross_down and cvd_val < cvd_ema_val:
            if self.position:
                self.position.close()
                self.in_long = False
        
        # Additional exit signal: CVD turns negative below EMA
        if self.position and cvd_val < 0 and cvd_val < cvd_ema_val:
            self.position.close()
            self.in_long = False
        
        # Divergence detection for position management
        if self.show_div and current_idx >= self.pivot_len * 2:
            # Check for bearish divergence (HH price but LH CVD)
            ph_prices = list(self._find_pivot_high(self.high, self.pivot_len, self.pivot_len))
            ph_cvds = list(self._find_pivot_high(self.cvd, self.pivot_len, self.pivot_len))
            
            if ph_prices and ph_cvds:
                last_ph_idx, last_ph_price = ph_prices[-1]
                last_ph_cvd_idx, last_ph_cvd = ph_cvds[-1]
                
                if (self.last_ph_price is not None and 
                    last_ph_idx - self.last_ph_bar >= self.min_bars_gap):
                    if last_ph_price > self.last_ph_price and last_ph_cvd < self.last_ph_cvd:
                        if self.position:
                            self.position.close()
                
                self.last_ph_price = last_ph_price
                self.last_ph_cvd = last_ph_cvd
                self.last_ph_bar = last_ph_idx
            
            # Check for bullish divergence (LL price but HL CVD)
            pl_prices = list(self._find_pivot_low(self.low, self.pivot_len, self.pivot_len))
            pl_cvds = list(self._find_pivot_low(self.cvd, self.pivot_len, self.pivot_len))
            
            if pl_prices and pl_cvds:
                last_pl_idx, last_pl_price = pl_prices[-1]
                last_pl_cvd_idx, last_pl_cvd = pl_cvds[-1]
                
                if (self.last_pl_price is not None and 
                    last_pl_idx - self.last_pl_bar >= self.min_bars_gap):
                    if last_pl_price < self.last_pl_price and last_pl_cvd > self.last_pl_cvd:
                        if not self.position:
                            self.buy()
                
                self.last_pl_price = last_pl_price
                self.last_pl_cvd = last_pl_cvd
                self.last_pl_bar = last_pl_idx


