import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    amplitude = 2
    channelDeviation = 2.0
    hull_length = 55
    stop_loss_pct = 0.94

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=100)
        
        # HMA (Hull Moving Average)
        def hma_calc(src):
            wma1 = pta.wma(src, length=self.hull_length // 2)
            wma2 = pta.wma(src, length=self.hull_length)
            if wma1 is None or wma2 is None:
                return pd.Series(0, index=src.index)
            combined = 2 * wma1 - wma2
            hma_len = int(np.sqrt(self.hull_length))
            result = pta.wma(combined, length=hma_len)
            return result if result is not None else pd.Series(0, index=src.index)
        
        self.MHULL = self.I(hma_calc, close)
        
        # Shifted MHULL (2 bars back)
        self.SHULL = self.I(lambda: self.MHULL.shift(2).fillna(self.MHULL))
        
        # Hull gap
        self.hullGap = self.I(lambda: np.abs(self.MHULL - self.SHULL))
        
        # Highest and Lowest
        self.highest = self.I(lambda: high.rolling(window=self.amplitude).max())
        self.lowest = self.I(lambda: low.rolling(window=self.amplitude).min())
        
        # SMA for trend logic
        self.sma_high = self.I(pta.sma, high, length=self.amplitude)
        self.sma_low = self.I(pta.sma, low, length=self.amplitude)
        
        # State variables
        self.trend = 0
        self.nextTrend = 0
        self.maxLowPrice = 0
        self.minHighPrice = 0
        self.up = 0
        self.down = 0
        self.prev_trend = 0
        self.arrowUp = False
        self.arrowDown = False

    def next(self):
        if len(self.data) < self.amplitude + 5:
            return
        
        atr2 = self.atr[-1] / 2 if self.atr[-1] else 0
        dev = self.channelDeviation * atr2
        
        highPrice = self.highest[-1] if self.highest[-1] else self.data.High[-1]
        lowPrice = self.lowest[-1] if self.lowest[-1] else self.data.Low[-1]
        
        if self.nextTrend == 1:
            self.maxLowPrice = max(lowPrice, self.maxLowPrice)
            sma_h = self.sma_high[-1] if self.sma_high[-1] else self.data.High[-1]
            if sma_h < self.maxLowPrice and self.data.Close[-1] < self.data.Low[-2]:
                self.trend = 1
                self.nextTrend = 0
                self.minHighPrice = highPrice
        else:
            self.minHighPrice = min(highPrice, self.minHighPrice) if self.minHighPrice != 0 else highPrice
            sma_l = self.sma_low[-1] if self.sma_low[-1] else self.data.Low[-1]
            if sma_l > self.minHighPrice and self.data.Close[-1] > self.data.High[-2]:
                self.trend = 0
                self.nextTrend = 1
                self.maxLowPrice = lowPrice
        
        self.arrowUp = False
        self.arrowDown = False
        
        if self.trend == 0:
            if self.prev_trend != 0:
                self.up = self.down if self.down != 0 else lowPrice
            else:
                self.up = max(self.maxLowPrice, self.up) if self.up != 0 else self.maxLowPrice
            
            if self.prev_trend != 0 and self.prev_trend != self.trend:
                self.arrowUp = True
        else:
            if self.prev_trend != 1:
                self.down = self.up if self.up != 0 else highPrice
            else:
                self.down = min(self.minHighPrice, self.down) if self.down != 0 else self.minHighPrice
            
            if self.prev_trend != 1 and self.prev_trend != self.trend:
                self.arrowDown = True
        
        buySignal = self.arrowUp and self.trend == 0 and self.prev_trend == 1
