import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrFastLen = 10
    atrSlowLen = 14
    sqzLevel = 0.7
    normLen = 30
    volLen = 20
    volMult = 1.2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)

        self.fastATR = self.I(pta.atr, high, low, close, length=self.atrFastLen)
        self.slowATR = self.I(pta.atr, high, low, close, length=self.atrSlowLen)
        
        slowATR_sma = self.I(pta.sma, self.slowATR, length=self.normLen)
        self.normATR = self.I(lambda: self.slowATR / slowATR_sma.replace(0, np.nan))
        
        self.atrCrossoverRatio = self.I(lambda: self.fastATR / self.slowATR.replace(0, np.nan))
        
        self.barRangeRatio = self.I(lambda: (high - low) / self.slowATR.replace(0, np.nan))
        
        self.avgVol = self.I(pta.sma, volume, length=self.volLen)
        self.isVolHigh = self.I(lambda: volume > (self.avgVol * self.volMult))
        self.isBullish = self.I(lambda: close > open_)
        self.isBearish = self.I(lambda: close < open_)

    def next(self):
        if len(self.data) < max(self.atrFastLen, self.atrSlowLen, self.normLen, self.volLen) + 5:
            return

        barRatio = self.barRangeRatio[-1]
        crossoverRatio = self.atrCrossoverRatio[-1]
        normAtr = self.normATR[-1]
        volHigh = self.isVolHigh[-1]
        bullish = self.isBullish[-1]
        bearish = self.isBearish[-1]

        if pd.isna(barRatio) or pd.isna(crossoverRatio) or pd.isna(normAtr):
            return

        highConvictionBullish = barRatio > 1.0 and volHigh and bullish
        highConvictionBearish = barRatio > 1.0 and volHigh and bearish
        squeeze = barRatio < self.sqzLevel

        if highConvictionBullish:
            if not self.position:
                self.buy()
        elif highConvictionBearish:
            if self.position:
                self.position.close()
        elif squeeze:
            if self.position:
                self.position.close()

        if self.position and crossover(self.normATR, self.atrCrossoverRatio):
            self.position.close()


