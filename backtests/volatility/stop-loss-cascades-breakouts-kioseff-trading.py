import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=14)
        self.sma_50 = self.I(pta.sma, close, length=50)
        
    def next(self):
        if len(self.data) < 50:
            return
            
        atr_val = self.atr[-1]
        sma_val = self.sma_50[-1]
        current_price = self.data.Close[-1]
        
        if atr_val is None or np.isnan(atr_val):
            return
        if sma_val is None or np.isnan(sma_val):
            return
            
        if current_price > sma_val and atr_val > 0:
            if not self.position:
                self.buy()
        elif current_price < sma_val and atr_val > 0:
            if self.position:
                self.sell()


