        # In reality, earnings data would come from request.earnings() in Pine Script
        # For this backtest, we'll mark days with unusual volatility as potential earnings days
        
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_price = self.data.Open[-1]
        close_price = self.data.Close[-1]
        
        if open_price > 0:
            move_pct = (high - low) / open_price
            
            # Detect potential earnings day (high volatility spike)
            is_earnings_day = move_pct > 0.03 if len(self.past_moves) > 0 else False
            
            # Apply check_next_day logic
            is_target_day = False
            if self.check_next_day:
                if self.last_earnings_idx >= 0 and current_idx == self.last_earnings_idx + 1:
                    is_target_day = True
            else:
                is_target_day = is_earnings_day
            
            # Record volatility on target day
            if is_target_day:
                self.past_moves.append(move_pct)
                if len(self.past_moves) > self.lookback_earnings:
                    self.past_moves.pop(0)
            
            # Mark earnings days
            if is_earnings_day:
                self.last_earnings_idx = current_idx
            
