class TvStrategy(Strategy):
    lookback_earnings = 4
    check_next_day = True
    future_bars_span = 20

    def init(self):
        self.past_moves = []
        self.avg_volatility = 0.0
        self.earnings_days = []
        self.last_earnings_idx = -1

