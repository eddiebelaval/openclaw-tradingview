import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    bbLength = 20
    bbStdDev = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Bollinger Bands for current timeframe
        bbands = self.I(lambda: pta.bbands(close, length=self.bbLength, std=self.bbStdDev))
        
        # Extract BB components
        self.bb_upper = self.I(lambda: bbands[f'BBU_{self.bbLength}_{self.bbStdDev}'] if bbands is not None and f'BBU_{self.bbLength}_{self.bbStdDev}' in bbands.columns else pd.Series(np.nan, index=close.index))
        self.bb_lower = self.I(lambda: bbands[f'BBL_{self.bbLength}_{self.bbStdDev}'] if bbands is not None and f'BBL_{self.bbLength}_{self.bbStdDev}' in bbands.columns else pd.Series(np.nan, index=close.index))
        self.bb_basis = self.I(lambda: bbands[f'BBM_{self.bbLength}_{self.bbStdDev}'] if bbands is not None and f'BBM_{self.bbLength}_{self.bbStdDev}' in bbands.columns else pd.Series(np.nan, index=close.index))

    def next(self):
        # Trading logic based on Bollinger Bands
        # Buy when price touches lower band with indication of reversal
        # Sell when price touches upper band with indication of reversal
        
        if len(self.data) < self.bbLength + 1:
            return
        
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        bb_upper_val = self.bb_upper[-1]
        bb_lower_val = self.bb_lower[-1]
        bb_basis_val = self.bb_basis[-1]
        
        # Skip if values are NaN
        if pd.isna(bb_upper_val) or pd.isna(bb_lower_val) or pd.isna(bb_basis_val):
            return
        
        # Buy signal: price touches or crosses below lower band
        if not self.position:
            if current_close <= bb_lower_val and current_close > bb_basis_val:
                self.buy()
        
        # Sell signal: price touches or crosses above upper band
        if self.position:
            if current_close >= bb_upper_val and current_close < bb_basis_val:
                self.sell()
            # Also exit if price crosses back below basis
            elif current_close < bb_basis_val and self.position.is_long:
                self.sell()