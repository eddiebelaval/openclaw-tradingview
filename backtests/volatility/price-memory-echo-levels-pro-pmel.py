import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookbackBars = 120
    binCount = 20
    mergeGapBins = 2
    toleranceFactor = 0.60
    recencyBoost = 0.60
    wickWeight = 1.20
    closeWeight = 0.90
    rejectionWeight = 1.40
    bodyPauseWeight = 0.50
    highlightNearby = True
    highlightOnlyStrongest = False

    def init(self):
        self.strongest_level = None
        self.secondary_level = None
        self.tertiary_level = None
        self.strongest_bull = None
        self.strongest_bear = None
        self.secondary_bull = None
        self.secondary_bear = None
        self.tertiary_bull = None
        self.tertiary_bear = None
        self.nearest_level = None
        self.nearest_bias = "Neutral"
        self.in_position = False
        self.last_computed_bar = -1

    def compute_memory_levels(self):
        if len(self.data) < self.lookbackBars:
            return

        current_bar = len(self.data) - 1
        if current_bar == self.last_computed_bar:
            return

        self.last_computed_bar = current_bar

        highs = np.array(self.data.High[-self.lookbackBars:])
        lows = np.array(self.data.Low[-self.lookbackBars:])
        closes = np.array(self.data.Close[-self.lookbackBars:])
        opens = np.array(self.data.Open[-self.lookbackBars:])

        recent_high = np.max(highs)
        recent_low = np.min(lows)
        price_range = recent_high - recent_low

        if price_range <= 0:
            return

        bin_size = price_range / max(self.binCount, 1)
        tol = bin_size * self.toleranceFactor

        scores = np.zeros(self.binCount)
        bulls = np.zeros(self.binCount)
        bears = np.zeros(self.binCount)
        levels = np.zeros(self.binCount)

        for j in range(self.binCount):
            levels[j] = recent_low + bin_size * (j + 0.5)

        for j in range(self.binCount):
            lvl = levels[j]
            s = 0.0
            b = 0.0
            r = 0.0

            for i in range(self.lookbackBars):
                rng = max(highs[i] - lows[i], 1e-10)
                rec_w = 1.0 + ((self.lookbackBars - i) / self.lookbackBars) * self.recencyBoost

                wick_touch = highs[i] >= lvl and lows[i] <= lvl
                close_near = abs(closes[i] - lvl) <= tol * 0.7
                body_pause = abs(closes[i] - opens[i]) <= rng * 0.35 and close_near
                bull_reject = lows[i] < lvl and closes[i] > lvl and wick_touch
                bear_reject = highs[i] > lvl and closes[i] < lvl and wick_touch

                local_score = 0.0
                if wick_touch:
                    local_score += self.wickWeight
                if close_near:
                    local_score += self.closeWeight
                if bull_reject or bear_reject:
                    local_score += self.rejectionWeight
                if body_pause:
                    local_score += self.bodyPauseWeight

                s += local_score * rec_w
                if bull_reject:
                    b += self.rejectionWeight * rec_w
                if bear_reject:
                    r += self.rejectionWeight * rec_w

            scores[j] = s
            bulls[j] = b
            bears[j] = r

        best1_idx = -1
        best1_score = -1.0
        for j in range(self.binCount):
            if scores[j] > best1_score:
                best1_score = scores[j]
                best1_idx = j

        best2_idx = -1
        best2_score = -1.0
        for j in range(self.binCount):
            far_enough_1 = best1_idx == -1 or abs(j - best1_idx) > self.mergeGapBins
            if far_enough_1 and scores[j] > best2_score:
                best2_score = scores[j]
                best2_idx = j

        best3_idx = -1
        best3_score = -1.0
        for j in range(self.binCount):
            far_enough_1 = best1_idx == -1 or abs(j - best1_idx) > self.mergeGapBins
            far_enough_2 = best2_idx == -1 or abs(j - best2_idx) > self.mergeGapBins
            if far_enough_1 and far_enough_2 and scores[j] > best3_score:
                best3_score = scores[j]
                best3_idx = j

        self.strongest_level = levels[best1_idx] if best1_idx >= 0 else None
        self.secondary_level = levels[best2_idx] if best2_idx >= 0 else None
        self.tertiary_level = levels[best3_idx] if best3_idx >= 0 else None

        self.strongest_bull = bulls[best1_idx] if best1_idx >= 0 else 0
        self.strongest_bear = bears[best1_idx] if best1_idx >= 0 else 0
        self.secondary_bull = bulls[best2_idx] if best2_idx >= 0 else 0
        self.secondary_bear = bears[best2_idx] if best2_idx >= 0 else 0
        self.tertiary_bull = bulls[best3_idx] if best3_idx >= 0 else 0
        self.tertiary_bear = bears[best3_idx] if best3_idx >= 0 else 0

        self.update_nearest_level()

    def update_nearest_level(self):
        current_close = self.data.Close[-1]
        nearest_level = None
        nearest_dist = float('inf')
        nearest_bias = "Neutral"

        if self.strongest_level is not None:
            dist = abs(current_close - self.strongest_level)
            if dist < nearest_dist:
                nearest_level = self.strongest_level
                nearest_dist = dist
                nearest_bias = self.get_bias_text(self.strongest_bull, self.strongest_bear)

        if self.secondary_level is not None:
            dist = abs(current_close - self.secondary_level)
            if dist < nearest_dist:
                nearest_level = self.secondary_level
                nearest_dist = dist
                nearest_bias = self.get_bias_text(self.secondary_bull, self.secondary_bear)

        if self.tertiary_level is not None:
            dist = abs(current_close - self.tertiary_level)
            if dist < nearest_dist:
                nearest_level = self.tertiary_level
                nearest_dist = dist
                nearest_bias = self.get_bias_text(self.tertiary_bull, self.tertiary_bear)

        self.nearest_level = nearest_level
        self.nearest_bias = nearest_bias

    def get_bias_text(self, bull_score, bear_score):
        if bull_score > bear_score * 1.15:
            return "Bullish"
        elif bear_score > bull_score * 1.15:
            return "Bearish"
        else:
            return "Neutral"

    def is_near_level(self, level):
        if level is None:
            return False
        price_range = max(self.data.High[-self.lookbackBars:]) - min(self.data.Low[-self.lookbackBars:])
        if price_range <= 0:
            return False
        bin_size = price_range / max(self.binCount, 1)
        tol = bin_size * self.toleranceFactor
        return abs(self.data.Close[-1] - level) <= tol

    def next(self):
        self.compute_memory_levels()

        if self.nearest_level is None:
            return

        current_price = self.data.Close[-1]
        tolerance = (max(self.data.High[-self.lookbackBars:]) - min(self.data.Low[-self.lookbackBars:])) / max(self.binCount, 1) * self.toleranceFactor

        if self.nearest_bias == "Bullish" and not self.in_position:
            if self.is_near_level(self.strongest_level):
                self.buy()
                self.in_position = True

        elif self.nearest_bias == "Bearish" and self.in_position:
            if self.is_near_level(self.strongest_level):
                self.sell()
                self.in_position = False

        if self.in_position:
            if self.nearest_bias == "Bearish" or (self.strongest_level is not None and current_price < self.strongest_level - tolerance * 2):
                self.sell()
                self.in_position = False