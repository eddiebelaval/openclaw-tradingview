        cum_pv = 0
        started = False
        
        for i in range(len(self.data)):
            if not started:
                vwap_series.iloc[i] = np.nan
            else:
                cum_vol += self.data.Volume[i]
                cum_pv += self.data.Close[i] * self.data.Volume[i]
                vwap_series.iloc[i] = cum_pv / cum_vol if cum_vol > 0 else np.nan
            
