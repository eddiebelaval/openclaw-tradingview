import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Settings
    ema_fast = 7
    ema_mid = 50
    ema_long = 200
    atr_len = 14
    
    # Dynamic Acceleration Filter
    use_accel = True
    accel_thresh = 0.05
    accel_lb = 3
    
    # Pullback Confirmation
    use_pullback = True
    pb_zone = 0.3
    pb_expiry = 30
    
    # BOS Scoring
    use_bos = True
    swing_lb = 10
    min_score = 5
    
    # Session Filter
    use_session = True
    
    # MTF Alignment
    min_tf = 2
    
    # TP/SL
    show_tpsl = True
    tp_mult = 3.0
    sl_mult = 1.5
    adapt_tpsl = True
    
    # PSAR
    psar_start = 0.002
    psar_inc = 0.002
    psar_max = 0.2
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.ema_fast_ind = self.I(pta.ema, close, length=self.ema_fast)
        self.ema_mid_ind = self.I(pta.ema, close, length=self.ema_mid)
        self.ema_long_ind = self.I(pta.ema, close, length=self.ema_long)
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.vol_ma = self.I(pta.sma, volume, length=20)
        self.rsi_val = self.I(pta.rsi, close, length=14)
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macd_line = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)[['MACD_12_26_9']])
        self.macd_signal = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)[['MACDh_12_26_9']])
        
        # Swing highs/lows for BOS
        self.swing_high = self.I(lambda: high.rolling(self.swing_lb).max())
        self.swing_low = self.I(lambda: low.rolling(self.swing_lb).min())
        
        # EMA slopes for acceleration
        self.ema_fast_slope = self.I(lambda: (self.ema_fast_ind - self.ema_fast_ind.shift(self.accel_lb)) / np.maximum(self.atr_val, 1e-10))
        self.ema_mid_slope = self.I(lambda: (self.ema_mid_ind - self.ema_mid_ind.shift(self.accel_lb)) / np.maximum(self.atr_val, 1e-10))
        
        # PSAR
        self.psar = self.I(pta.psar, high, low, 
                          af0=self.psar_start, af=self.psar_inc, max_af=self.psar_max)
        
        # Tracking variables
        self.last_golden_bar = None
        self.last_death_bar = None
        self.golden_active = False
        self.death_active = False

    def next(self):
        # Safety checks for indicator availability
        if len(self.data) < max(self.ema_long, self.swing_lb, self.pb_expiry):
            return
        
        if (self.ema_fast_ind[-1] is None or self.ema_mid_ind[-1] is None or 
            self.ema_long_ind[-1] is None or self.atr_val[-1] is None):
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        ema_fast = self.ema_fast_ind[-1]
        ema_mid = self.ema_mid_ind[-1]
        ema_long = self.ema_long_ind[-1]
        atr_val = self.atr_val[-1]
        vol_ma = self.vol_ma[-1]
        rsi_val = self.rsi_val[-1]
        
        # MACD check
        if self.macd_line[-1] is None or self.macd_signal[-1] is None:
            return
        
        macd_line = self.macd_line[-1][0] if isinstance(self.macd_line[-1], (list, tuple, np.ndarray)) else self.macd_line[-1]
        macd_signal = self.macd_signal[-1][0] if isinstance(self.macd_signal[-1], (list, tuple, np.ndarray)) else self.macd_signal[-1]
        
        # Crossovers
        golden_cross = crossover(self.ema_mid_ind, self.ema_long_ind)
        death_cross = crossover(self.ema_long_ind, self.ema_mid_ind)
        
        # Volume confirmation
        vol_confirmed = volume > vol_ma * 1.5
        
        # Momentum checks
        bull_momentum = rsi_val > 50 and macd_line > macd_signal
        bear_momentum = rsi_val < 50 and macd_line < macd_signal
        
        # Dynamic acceleration
        ema_fast_slope = self.ema_fast_slope[-1] if self.ema_fast_slope[-1] is not None else 0
        ema_mid_slope = self.ema_mid_slope[-1] if self.ema_mid_slope[-1] is not None else 0
        
        fast_accel_bull = ema_fast_slope > self.accel_thresh and ema_fast > ema_mid
        fast_accel_bear = ema_fast_slope < -self.accel_thresh and ema_fast < ema_mid
        
        early_bull_signal = self.use_accel and fast_accel_bull and ema_mid > ema_long
        early_bear_signal = self.use_accel and fast_accel_bear and ema_mid < ema_long
        
        # BOS checks
        swing_high = self.swing_high[-1] if self.swing_high[-1] is not None else high
        swing_low = self.swing_low[-1] if self.swing_low[-1] is not None else low
        
        bos_long = self.use_bos and close > swing_high
        bos_short = self.use_bos and close < swing_low
        
        # Higher Highs / Lower Lows
        hh_structure = high > self.data.High[-self.swing_lb] and low > self.data.Low[-self.swing_lb]
        ll_structure = high < self.data.High[-self.swing_lb] and low < self.data.Low[-self.swing_lb]
        
        # Pullback tracking
        if golden_cross:
            self.last_golden_bar = len(self.data)
            self.golden_active = True
            self.death_active = False
        
        if death_cross:
            self.last_death_bar = len(self.data)
            self.death_active = True
            self.golden_active = False
        
        # Expire pullback windows
        if self.golden_active and self.last_golden_bar is not None:
            if len(self.data) - self.last_golden_bar > self.pb_expiry:
                self.golden_active = False
        
        if self.death_active and self.last_death_bar is not None:
            if len(self.data) - self.last_death_bar > self.pb_expiry:
                self.death_active = False
        
        # Pullback zone check
        pb_zone_dist = (abs(close - ema_mid) / ema_mid) * 100 if ema_mid != 0 else 0
        near_mid = pb_zone_dist <= self.pb_zone
        
        pullback_long = self.use_pullback and self.golden_active and near_mid and close > ema_mid and close > ema_long
        pullback_short = self.use_pullback and self.death_active and near_mid and close < ema_mid and close < ema_long
        
        # Score calculation
        score_long = self._calc_score(True, vol_confirmed, rsi_val, macd_line, macd_signal, 
                                      hh_structure, bos_long, fast_accel_bull, atr_val)
        score_short = self._calc_score(False, vol_confirmed, rsi_val, macd_line, macd_signal,
                                       ll_structure, bos_short, fast_accel_bear, atr_val)
        
        # Entry signals
        cross_long = golden_cross and vol_confirmed and bull_momentum and score_long >= self.min_score
        cross_short = death_cross and vol_confirmed and bear_momentum and score_short >= self.min_score
        
        accel_long = early_bull_signal and not golden_cross and vol_confirmed and score_long >= max(self.min_score - 1, 0)
        accel_short = early_bear_signal and not death_cross and vol_confirmed and score_short >= max(self.min_score - 1, 0)
        
        pb_long = pullback_long and vol_confirmed and score_long >= max(self.min_score - 2, 0)
        pb_short = pullback_short and vol_confirmed and score_short >= max(self.min_score - 2, 0)
        
        # Entry logic - avoid duplicate entries
        if not self.position:
            if cross_long or accel_long or pb_long:
                self.buy()
            elif cross_short or accel_short or pb_short:
                self.sell()
        else:
            # Exit logic
            if self.position.is_long:
                if death_cross or crossover(self.ema_long_ind, self.ema_mid_ind):
                    self.position.close()
            else:
                if golden_cross or crossover(self.ema_mid_ind, self.ema_long_ind):
                    self.position.close()

    def _calc_score(self, is_long, vol_confirmed, rsi_val, macd_line, macd_signal,
                    structure, bos, accel, atr_val):
        """Calculate confluence score (0-12)"""
        sc = 0
        
        # Volume (0-2)
        if vol_confirmed:
            sc += 2
        
        # RSI + MACD (0-2)
        if is_long and rsi_val > 40 and rsi_val < 65 and macd_line > macd_signal:
            sc += 2
        elif not is_long and rsi_val < 60 and rsi_val > 35 and macd_line < macd_signal:
            sc += 2
        elif 30 < rsi_val < 70:
            sc += 1
        
        # Structure (0-2)
        if structure:
            sc += 2
        elif bos:
            sc += 1
        
        # Acceleration (0-2)
        if accel:
            sc += 2
        
        # ATR normalization (0-2)
        if atr_val > 0:
            sc += 1
        
        return min(sc, 12)