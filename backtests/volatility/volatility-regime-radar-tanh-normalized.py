import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    atrEmaLength = 14
    normLength = 50
    smoothing = "RMA"
    spreadSmoothLength = 9
    regimeThreshold = 0.20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        def calculate_tr():
            tr1 = high - low
            tr2 = np.abs(high - close.shift(1))
            tr3 = np.abs(low - close.shift(1))
            return np.maximum(tr1, np.maximum(tr2, tr3))
        
        tr = self.I(calculate_tr)
        
        def calculate_up_down_tr():
            tr_vals = calculate_tr()
            up_tr = np.where(close >= close.shift(1), tr_vals, 0.0)
            down_tr = np.where(close < close.shift(1), tr_vals, 0.0)
            return pd.Series(up_tr, index=close.index), pd.Series(down_tr, index=close.index)
        
        up_tr_raw = self.I(lambda: calculate_up_down_tr()[0])
        down_tr_raw = self.I(lambda: calculate_up_down_tr()[1])
        
        def ma_function(source, length):
            if self.smoothing == "RMA":
                return pta.rma(source, length=length)
            elif self.smoothing == "SMA":
                return pta.sma(source, length=length)
            elif self.smoothing == "EMA":
                return pta.ema(source, length=length)
            else:
                return pta.wma(source, length=length)
        
        up_atr = self.I(lambda: ma_function(pd.Series(self.data.Close, index=close.index).where(close >= close.shift(1), 0).rolling(self.length).sum() / self.length, self.length) or pd.Series(0, index=close.index))
        down_atr = self.I(lambda: ma_function(pd.Series(self.data.Close, index=close.index).where(close < close.shift(1), 0).rolling(self.length).sum() / self.length, self.length) or pd.Series(0, index=close.index))
        
        def calc_up_atr():
            tr_vals = calculate_tr()
            up_tr = np.where(close >= close.shift(1), tr_vals, 0.0)
            up_tr_series = pd.Series(up_tr, index=close.index)
            if self.smoothing == "RMA":
                result = pta.rma(up_tr_series, length=self.length)
            elif self.smoothing == "SMA":
                result = pta.sma(up_tr_series, length=self.length)
            elif self.smoothing == "EMA":
                result = pta.ema(up_tr_series, length=self.length)
            else:
                result = pta.wma(up_tr_series, length=self.length)
            return result if result is not None else pd.Series(0, index=close.index)
        
        def calc_down_atr():
            tr_vals = calculate_tr()
            down_tr = np.where(close < close.shift(1), tr_vals, 0.0)
            down_tr_series = pd.Series(down_tr, index=close.index)
            if self.smoothing == "RMA":
                result = pta.rma(down_tr_series, length=self.length)
            elif self.smoothing == "SMA":
                result = pta.sma(down_tr_series, length=self.length)
            elif self.smoothing == "EMA":
                result = pta.ema(down_tr_series, length=self.length)
            else:
                result = pta.wma(down_tr_series, length=self.length)
            return result if result is not None else pd.Series(0, index=close.index)
        
        up_atr = self.I(calc_up_atr)
        down_atr = self.I(calc_down_atr)
        
        up_atr_ema = self.I(lambda: pta.ema(pd.Series(self.data.Close).rolling(1).mean(), length=self.atrEmaLength) or pd.Series(0, index=close.index))
        down_atr_ema = self.I(lambda: pta.ema(pd.Series(self.data.Close).rolling(1).mean(), length=self.atrEmaLength) or pd.Series(0, index=close.index))
        
        def tanh_approx(x):
            clamped = np.clip(x, -10.0, 10.0)
            exp2x = np.exp(2.0 * clamped)
            return (exp2x - 1.0) / (exp2x + 1.0)
        
        def calc_up_dist():
            tr_vals = calculate_tr()
            up_tr = np.where(close >= close.shift(1), tr_vals, 0.0)
            up_tr_series = pd.Series(up_tr, index=close.index)
            if self.smoothing == "RMA":
                up_atr_val = pta.rma(up_tr_series, length=self.length)
            elif self.smoothing == "SMA":
                up_atr_val = pta.sma(up_tr_series, length=self.length)
            elif self.smoothing == "EMA":
                up_atr_val = pta.ema(up_tr_series, length=self.length)
            else:
                up_atr_val = pta.wma(up_tr_series, length=self.length)
            if up_atr_val is None:
                up_atr_val = pd.Series(0, index=close.index)
            up_atr_ema_val = pta.ema(up_atr_val, length=self.atrEmaLength)
            if up_atr_ema_val is None:
                up_atr_ema_val = pd.Series(0, index=close.index)
            return up_atr_val - up_atr_ema_val
        
        def calc_down_dist():
            tr_vals = calculate_tr()
            down_tr = np.where(close < close.shift(1), tr_vals, 0.0)
            down_tr_series = pd.Series(down_tr, index=close.index)
            if self.smoothing == "RMA":
                down_atr_val = pta.rma(down_tr_series, length=self.length)
            elif self.smoothing == "SMA":
                down_atr_val = pta.sma(down_tr_series, length=self.length)
            elif self.smoothing == "EMA":
                down_atr_val = pta.ema(down_tr_series, length=self.length)
            else:
                down_atr_val = pta.wma(down_tr_series, length=self.length)
            if down_atr_val is None:
                down_atr_val = pd.Series(0, index=close.index)
            down_atr_ema_val = pta.ema(down_atr_val, length=self.atrEmaLength)
            if down_atr_ema_val is None:
                down_atr_ema_val = pd.Series(0, index=close.index)
            return down_atr_val - down_atr_ema_val
        
        up_dist = self.I(calc_up_dist)
        down_dist = self.I(calc_down_dist)
        
        def calc_up_scale():
            dist = calc_up_dist()
            std_val = dist.rolling(self.normLength).std()
            return std_val.fillna(1e-10).clip(lower=1e-10)
        
        def calc_down_scale():
            dist = calc_down_dist()
            std_val = dist.rolling(self.normLength).std()
            return std_val.fillna(1e-10).clip(lower=1e-10)
        
        up_scale = self.I(calc_up_scale)
        down_scale = self.I(calc_down_scale)
        
        def calc_up_norm():
            dist = calc_up_dist()
            scale = calc_up_scale()
            return pd.Series(tanh_approx(dist / scale), index=close.index)
        
        def calc_down_norm():
            dist = calc_down_dist()
            scale = calc_down_scale()
            return pd.Series(tanh_approx(dist / scale), index=close.index)
        
        up_norm = self.I(calc_up_norm)
        down_norm = self.I(calc_down_norm)
        
        def calc_down_norm_visual():
            return -self.I(calc_down_norm)
        
        down_norm_visual = self.I(lambda: -calc_down_norm())
        
        def calc_spread():
            return calc_up_norm() - (-calc_down_norm())
        
        spread = self.I(calc_spread)
        
        def calc_smoothed_spread():
            sp = calc_spread()
            smoothed = pta.ema(sp, length=self.spreadSmoothLength)
            return smoothed if smoothed is not None else pd.Series(0, index=close.index)
        
        smoothed_spread = self.I(calc_smoothed_spread)
        
        self.spread_indicator = spread
        self.smoothed_spread_indicator = smoothed_spread

    def next(self):
        if len(self.data) < 2:
            return
        
        spread_val = self.spread_indicator[-1] if len(self.spread_indicator) > 0 else 0
        smoothed_val = self.smoothed_spread_indicator[-1] if len(self.smoothed_spread_indicator) > 0 else 0
        
        prev_smoothed = self.smoothed_spread_indicator[-2] if len(self.smoothed_spread_indicator) > 1 else smoothed_val
        
        if smoothed_val > self.regimeThreshold and prev_smoothed <= self.regimeThreshold:
            if not self.position:
                self.buy()
        elif smoothed_val < -self.regimeThreshold and prev_smoothed >= -self.regimeThreshold:
            if self.position:
                self.position.close()
        
        if self.position and smoothed_val < -self.regimeThreshold:
            self.position.close()


