import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.yzv = self.I(self._calculate_yzv, open_, high, low, close)

    def _calculate_yzv(self, open_, high, low, close):
        length = self.length
        yzv_values = np.full(len(close), np.nan)
        
        raw_rma_val = 0.0
        e_comp_val = 1.0
        EPSILON_YZV = 1e-10
        
        for i in range(len(close)):
            if i == 0:
                pc = open_.iloc[i]
            else:
                pc = close.iloc[i - 1]
            
            o = open_.iloc[i]
            h = high.iloc[i]
            l = low.iloc[i]
            c = close.iloc[i]
            
            ro = np.log(o / pc)
            rc = np.log(c / o)
            rh = np.log(h / o)
            rl = np.log(l / o)
            
            s_o_sq = ro * ro
            s_c_sq = rc * rc
            s_rs_sq = rh * (rh - rc) + rl * (rl - rc)
            
            ratio_N = 1.0 if length <= 1 else (float(length) + 1.0) / (float(length) - 1.0)
            k_yz = 0.34 / (1.34 + ratio_N)
            
            s_sq_daily = s_o_sq + k_yz * s_c_sq + (1.0 - k_yz) * s_rs_sq
            
            rma_alpha = 1.0 / float(length)
            
            if i == 0 or np.isnan(raw_rma_val):
                raw_rma_val = s_sq_daily
            else:
                raw_rma_val = (raw_rma_val * (length - 1) + s_sq_daily) / length
            
            e_comp_val = (1.0 - rma_alpha) * e_comp_val
            
            if e_comp_val > EPSILON_YZV:
                smoothed_s_sq = raw_rma_val / (1.0 - e_comp_val)
            else:
                smoothed_s_sq = raw_rma_val
            
            result = np.sqrt(max(0.0, smoothed_s_sq))
            yzv_values[i] = result
        
        return pd.Series(yzv_values, index=close.index)

    def next(self):
        if len(self.data) < 2:
            return
        
        current_yzv = self.yzv[-1]
        prev_yzv = self.yzv[-2]
        
        if not np.isnan(current_yzv) and not np.isnan(prev_yzv):
            if prev_yzv < 0.015 and current_yzv >= 0.015:
                if not self.position:
                    self.buy()
            elif prev_yzv >= 0.040 and current_yzv < 0.040:
                if self.position:
                    self.position.close()


