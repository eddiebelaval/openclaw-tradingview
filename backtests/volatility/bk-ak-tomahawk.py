import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters
    momLen = 9
    normLen = 120
    
    # Smoothing parameters
    smoothType = "ALMA"
    momSmoothL = 10
    sigLen = 9
    almaOff = 0.85
    almaSig = 6
    
    # Velocity / Accel parameters
    velNormLen = 60
    velSmoothL = 3
    extTh = 120
    
    # Filter parameters
    useTrend = False
    trendLen = 200
    useVWAP = True
    useVolume = False
    volLen = 20
    volMult = 1.2
    
    # MTF parameters
    useMTF = True
    
    # Squeeze parameters
    useSqueeze = True
    sqLen = 20
    sqMult = 0.70
    expMult = 1.30
    
    # Session parameters
    useSession = False
    
    # Signal parameters
    minSep = 8.0
    velTh = 4.0
    leadTh = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ROC (Rate of Change)
        def calc_roc(src, length):
            return src.diff(length) / src.shift(length) * 100
        
        roc_vals = self.I(lambda: calc_roc(close, self.momLen))
        
        # Z-score normalization
        def calc_zscore(src, length):
            mu = src.rolling(window=length).mean()
            sd = src.rolling(window=length).std()
            return (src - mu) / sd.replace(0, 1)
        
        zscore_vals = self.I(lambda: calc_zscore(roc_vals, self.normLen))
        
        # Momentum = Z-score * 50
        def calc_mom(src):
            return src * 50.0
        
        mom_raw = self.I(lambda: calc_mom(zscore_vals))
        
        # Smoothing function
        def smooth_series(src, length):
            if self.smoothType == "EMA":
                return pta.ema(src, length=length)
            elif self.smoothType == "HMA":
                return pta.hma(src, length=length)
            elif self.smoothType == "ALMA":
                return pta.alma(src, length=length, offset=self.almaOff, sigma=self.almaSig)
            elif self.smoothType == "RMA":
                return pta.rma(src, length=length)
            elif self.smoothType == "WMA":
                return pta.wma(src, length=length)
            else:
                return pta.ema(src, length=length)
        
        self.mom_smooth = self.I(lambda: smooth_series(mom_raw, self.momSmoothL) or pd.Series(0, index=mom_raw.index))
        self.signal = self.I(lambda: smooth_series(self.mom_smooth, self.sigLen) or pd.Series(0, index=self.mom_smooth.index))
        
        # Velocity calculation
        def calc_velocity(mom_smooth, vel_norm_len, vel_smooth_len):
            vel_raw = mom_smooth.diff(1)
            v_mu = vel_raw.rolling(window=vel_norm_len).mean()
            v_sd = vel_raw.rolling(window=vel_norm_len).std()
            v_z = (vel_raw - v_mu) / v_sd.replace(0, 1)
            vel_base = v_z * 50.0
            return smooth_series(vel_base, vel_smooth_len) or pd.Series(0, index=mom_smooth.index)
        
        self.velocity = self.I(lambda: calc_velocity(self.mom_smooth, self.velNormLen, self.velSmoothL))
        
        # Acceleration
        def calc_accel(velocity):
            return velocity.diff(1)
        
        self.accel = self.I(lambda: calc_accel(self.velocity))
        
        # Velocity std and avg for squeeze detection
        def calc_vel_std(mom_smooth, vel_norm_len, sq_len):
            vel_raw = mom_smooth.diff(1)
            v_mu = vel_raw.rolling(window=vel_norm_len).mean()
            v_sd = vel_raw.rolling(window=vel_norm_len).std()
            vel_std = v_sd.rolling(window=sq_len).std()
            vel_avg = vel_std.rolling(window=sq_len).mean()
            return vel_std, vel_avg
        
        self.vel_std_vals = self.I(lambda: calc_vel_std(self.mom_smooth, self.velNormLen, self.sqLen)[0])
        self.vel_avg_vals = self.I(lambda: calc_vel_std(self.mom_smooth, self.velNormLen, self.sqLen)[1])
        
        # Filters
        self.trend_ema = self.I(lambda: pta.ema(close, length=self.trendLen) or pd.Series(close.iloc[-1], index=close.index))
        self.vwap_vals = self.I(lambda: pta.vwap(high, low, close, volume) or pd.Series(close.iloc[-1], index=close.index))
        self.vol_sma = self.I(lambda: pta.sma(volume, length=self.volLen) or pd.Series(volume.iloc[-1], index=volume.index))
        
        self.last_up = False
        self.last_dn = False
        self.was_squeeze = False

    def next(self):
        # Current values
        mom_s = self.mom_smooth[-1]
        sig = self.signal[-1]
        vel = self.velocity[-1]
        acc = self.accel[-1]
        vel_std = self.vel_std_vals[-1]
        vel_avg = self.vel_avg_vals[-1]
        
        # Filters
        vol_ok = not self.useVolume or (self.data.Volume[-1] > self.vol_sma[-1] * self.volMult)
        trend_ok = not self.useTrend or (self.data.Close[-1] > self.trend_ema[-1])
        vwap_ok_long = not self.useVWAP or (self.data.Close[-1] > self.vwap_vals[-1])
        vwap_ok_short = not self.useVWAP or (self.data.Close[-1] < self.vwap_vals[-1])
        
        long_filter = trend_ok and vwap_ok_long and vol_ok
        short_filter = trend_ok and vwap_ok_short and vol_ok
        
        # Squeeze logic
        squeeze = self.useSqueeze and (vel_avg != 0 and vel_std < vel_avg * self.sqMult)
        expansion = self.useSqueeze and (vel_avg != 0 and vel_std > vel_avg * self.expMult)
        
        if squeeze:
            self.was_squeeze = True
        
        squeeze_release = self.was_squeeze and expansion
        if squeeze_release:
            self.was_squeeze = False
        
        sq_gate = not self.useSqueeze or squeeze_release or not squeeze
        
        # Crossover signals
        sep_ok = abs(mom_s - sig) >= self.minSep
        bull_cross = crossover(self.mom_smooth, self.signal) and sep_ok
        bear_cross = crossover(self.signal, self.mom_smooth) and sep_ok
        
        if bull_cross:
            self.last_up = True
            self.last_dn = False
        if bear_cross:
            self.last_dn = True
            self.last_up = False
        
        # Thrust signals
        thrust_long = bull_cross and (vel > self.velTh) and (acc > 0) and long_filter and sq_gate
        thrust_short = bear_cross and (vel < -self.velTh) and (acc < 0) and short_filter and sq_gate
        
        # Exhaustion signals
        mom_extreme = abs(mom_s) >= self.extTh
        vel_extreme = abs(vel) >= self.extTh
        exhaust_up = (mom_s > 0 and mom_extreme and acc < 0) or (vel > 0 and vel_extreme and acc < 0)
        exhaust_dn = (mom_s < 0 and mom_extreme and acc > 0) or (vel < 0 and vel_extreme and acc > 0)
        
        # Trading logic
        if thrust_long and not self.position:
            self.buy()
        elif thrust_short and self.position:
            self.sell()
        elif exhaust_up and self.position:
            self.sell()
        elif exhaust_dn and not self.position and bear_cross:
            self.buy()


