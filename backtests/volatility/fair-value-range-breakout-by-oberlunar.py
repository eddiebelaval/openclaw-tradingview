        c_a = htf_candles[-3]
        c_b = htf_candles[-2]
        c_c = htf_candles[-1]
        
        # FVG candle hi/lo (wicks or bodies)
        def c_hi(candle):
            if fvg_source == "Wicks":
                return candle['high']
            else:
                return max(candle['open'], candle['close'])
        
        def c_lo(candle):
            if fvg_source == "Wicks":
                return candle['low']
            else:
                return min(candle['open'], candle['close'])
        
        a_hi = c_hi(c_a)
        a_lo = c_lo(c_a)
        c_hi_ = c_hi(c_c)
        c_lo_ = c_lo(c_c)
        
        min_gap = min_gap_ticks * 0.0001  # syminfo.mintick approximation
        
        # Detect FVG patterns
        fvg_top = None
        fvg_bottom = None
        fvg_dir = 0
        
        # Bull FVG: A high < C low (gap up)
        if a_hi < (c_lo_ - min_gap):
            fvg_top = c_lo_
            fvg_bottom = a_hi
            fvg_dir = 1
        
        # Bear FVG: A low > C high (gap down)
        elif a_lo > (c_hi_ + min_gap):
            fvg_top = a_lo
            fvg_bottom = c_hi_
            fvg_dir = -1
        
        if fvg_dir == 0:
            return
        
        # Calculate signals from FVG zones
        buf = signal_buffer_ticks * 0.0001
        
        close_inside_prev = (close[len(close) - 2] <= fvg_top) and (close[len(close) - 2] >= fvg_bottom)
