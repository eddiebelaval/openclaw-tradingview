        htf_candles = []
        current_candle = None
        bars_in_candle = 0
        
        for i in range(len(self.data)):
            idx = i
            
            if current_candle is None:
                current_candle = {
                    'open': open_[idx],
                    'high': high[idx],
                    'low': low[idx],
                    'close': close[idx],
                    'idx': idx
                }
                bars_in_candle = 1
            else:
                current_candle['high'] = max(current_candle['high'], high[idx])
                current_candle['low'] = min(current_candle['low'], low[idx])
                current_candle['close'] = close[idx]
                bars_in_candle += 1
            
            if bars_in_candle >= tf_multiplier or i == len(self.data) - 1:
                htf_candles.append(current_candle)
                current_candle = None
                bars_in_candle = 0
        
        if len(htf_candles) < 3:
            return
        
