import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smoothing_length = 10
    smoothing_type = "SMA"
    ma_length = 50
    vix_symbol = "VIX"

    def init(self):
        # Since we're backtesting on regular price data, we'll use Close as a proxy
        # In a real scenario, you'd need to load actual VIX data
        close = pd.Series(self.data.Close)
        
        # Apply smoothing to VIX (using Close as proxy)
        if self.smoothing_length == 1:
            self.vix = close
        elif self.smoothing_type == "EMA":
            self.vix = self.I(pta.ema, close, length=self.smoothing_length)
        elif self.smoothing_type == "WMA":
            self.vix = self.I(pta.wma, close, length=self.smoothing_length)
        else:  # SMA
            self.vix = self.I(pta.sma, close, length=self.smoothing_length)
        
        # Calculate VIX Moving Average
        self.vix_ma = self.I(pta.sma, close, length=self.ma_length)
        
        # VIX momentum detection
        self.vix_rising = self.I(lambda x: x > x.shift(1), close)
        self.vix_falling = self.I(lambda x: x < x.shift(1), close)

    def next(self):
        # Trading logic based on VIX crossover with its MA
        # When VIX crosses above MA: Fear zone - consider short (sell long)
        # When VIX crosses below MA: Calm zone - consider long (buy)
        
        if len(self.data.Close) < self.ma_length + self.smoothing_length:
            return
        
        vix_current = self.vix[-1]
        vix_ma_current = self.vix_ma[-1]
        vix_prev = self.vix[-2] if len(self.vix) > 1 else vix_current
        vix_ma_prev = self.vix_ma[-2] if len(self.vix_ma) > 1 else vix_ma_current
        
        # VIX crossing below MA (Calm zone - BUY signal)
        if vix_prev >= vix_ma_prev and vix_current < vix_ma_current:
            if not self.position:
                self.buy()
        
        # VIX crossing above MA (Fear zone - SELL signal)
        elif vix_prev <= vix_ma_prev and vix_current > vix_ma_current:
            if self.position:
                self.position.close()


