import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vel_len = 14
    acc_len = 5
    signal_len = 9
    adx_len = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate raw velocity
        def calc_raw_velocity():
            vel = (close - close.shift(self.vel_len)) / close.shift(self.vel_len) * 100
            return vel
        
        raw_velocity = self.I(calc_raw_velocity)
        
        # Calculate velocity (EMA of raw velocity)
        def calc_velocity():
            vel = (close - close.shift(self.vel_len)) / close.shift(self.vel_len) * 100
            ema_vel = pta.ema(vel, length=3)
            return ema_vel
        
        self.velocity = self.I(calc_velocity)
        
        # Calculate acceleration
        def calc_acceleration():
            vel = (close - close.shift(self.vel_len)) / close.shift(self.vel_len) * 100
            ema_vel = pta.ema(vel, length=3)
            raw_accel = ema_vel - ema_vel.shift(self.acc_len)
            accel = pta.ema(raw_accel, length=3)
            return accel
        
        self.acceleration = self.I(calc_acceleration)
        
        # Calculate signal line
        def calc_signal_line():
            vel = (close - close.shift(self.vel_len)) / close.shift(self.vel_len) * 100
            ema_vel = pta.ema(vel, length=3)
            sig = pta.ema(ema_vel, length=self.signal_len)
            return sig
        
        self.signal_line = self.I(calc_signal_line)
        
        # Calculate ADX and DMI
        def calc_adx():
            adx_result = pta.adx(high, low, close, length=self.adx_len)
            if adx_result is not None and 'ADX_14' in adx_result.columns:
                return adx_result['ADX_14']
            return pd.Series(0, index=close.index)
        
        self.adx_val = self.I(calc_adx)
        
        # Calculate DI+ and DI-
        def calc_di():
            adx_result = pta.adx(high, low, close, length=self.adx_len)
            if adx_result is not None:
                if 'DMP_14' in adx_result.columns and 'DMN_14' in adx_result.columns:
                    di_plus = adx_result['DMP_14']
                    di_minus = adx_result['DMN_14']
                    return di_plus - di_minus
            return pd.Series(0, index=close.index)
        
        self.di_diff = self.I(calc_di)

