import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    # Configuration Parameters
    buy_threshold = 1.0
    sell_threshold = 1.0
    lookback_mode = "Bar Count"  # "Bar Count", "Time Interval", or "Cumulative Streak"
    lookback_bars = 10
    cooldown_bars = 3

    def init(self):
        self.buy_cooldown_counter = 0
        self.sell_cooldown_counter = 0
        
        # Cumulative Streak mode variables
        self.streak_dir = 0
        self.streak_anchor = np.nan
        self.streak_fired = False
        self.is_first_streak = True
        self.last_definitive_close = np.nan

    def next(self):
        if len(self.data) < 2:
            return

        close = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        
        # Decrement cooldown counters
        if self.buy_cooldown_counter > 0:
            self.buy_cooldown_counter -= 1
        if self.sell_cooldown_counter > 0:
            self.sell_cooldown_counter -= 1
        
        # Determine bar direction
        if close > close_prev:
            bar_dir = 1
        elif close < close_prev:
            bar_dir = -1
        else:
            bar_dir = 0
        
        # Track last definitive close
        if not np.isnan(close_prev):
            if bar_dir != 0:
                self.last_definitive_close = close_prev
        
        # Detect streak changes
        if bar_dir != 0 and bar_dir != self.streak_dir:
            if self.streak_dir != 0:
                self.is_first_streak = False
            self.streak_dir = bar_dir
            self.streak_anchor = self.last_definitive_close if not np.isnan(self.last_definitive_close) else close_prev
            self.streak_fired = False
        
        raw_buy = False
        raw_sell = False
        
        if self.lookback_mode == "Cumulative Streak":
            # Cumulative Streak mode
            if not np.isnan(self.streak_anchor) and self.streak_anchor != 0:
                streak_pct_change = (close - self.streak_anchor) / self.streak_anchor * 100
            else:
                streak_pct_change = 0.0
            
            if not self.is_first_streak and not self.streak_fired:
                if self.streak_dir == 1 and streak_pct_change >= self.buy_threshold:
                    raw_buy = True
                    self.streak_fired = True
                elif self.streak_dir == -1 and streak_pct_change <= -self.sell_threshold:
                    raw_sell = True
                    self.streak_fired = True
        else:
            # Bar Count or Time Interval mode
            fixed_n = self.lookback_bars
            
            if fixed_n > 0 and len(self.data) > fixed_n:
                fixed_ref_price = self.data.Close[-fixed_n - 1]
                fixed_pct_change = (close - fixed_ref_price) / fixed_ref_price * 100
                
                fixed_buy_condition = fixed_pct_change >= self.buy_threshold
                fixed_sell_condition = fixed_pct_change <= -self.sell_threshold
                
                # Previous bar conditions
                if len(self.data) > fixed_n + 1:
                    prev_fixed_ref_price = self.data.Close[-fixed_n - 2]
                    prev_fixed_pct_change = (close_prev - prev_fixed_ref_price) / prev_fixed_ref_price * 100
                    
                    prev_fixed_buy_condition = prev_fixed_pct_change >= self.buy_threshold
                    prev_fixed_sell_condition = prev_fixed_pct_change <= -self.sell_threshold
                else:
                    prev_fixed_buy_condition = False
                    prev_fixed_sell_condition = False
                
                # Rising-edge detection
                raw_buy = fixed_buy_condition and not prev_fixed_buy_condition
                raw_sell = fixed_sell_condition and not prev_fixed_sell_condition
        
        # Apply cooldown gate
        panic_buy = raw_buy and self.buy_cooldown_counter == 0
        panic_sell = raw_sell and self.sell_cooldown_counter == 0
        
        # Reset cooldown on signal fire
        if panic_buy:
            self.buy_cooldown_counter = self.cooldown_bars
        if panic_sell:
            self.sell_cooldown_counter = self.cooldown_bars
        
        # Trading logic
        if panic_buy and not self.position:
            self.buy()
        elif panic_sell and self.position:
            self.sell()


