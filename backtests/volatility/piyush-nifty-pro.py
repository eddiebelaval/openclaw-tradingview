import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 4
    atrLength = 5
    volLength = 8
    emaLength = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.rsiValue = self.I(pta.rsi, close, length=self.rsiLength)
        self.atrValue = self.I(pta.atr, high, low, close, length=self.atrLength)
        self.volMA = self.I(pta.sma, volume, length=self.volLength)
        self.emaValue = self.I(pta.ema, close, length=self.emaLength)
        self.atrSMA = self.I(pta.sma, self.atrValue, length=10)

    def next(self):
        if len(self.data) < max(self.rsiLength, self.atrLength, self.volLength, self.emaLength) + 10:
            return
        
        highVolume = self.data.Volume[-1] > self.volMA[-1]
        atrRising = self.atrValue[-1] > self.atrSMA[-1]
        
        buySignal = (
            crossover(self.rsiValue, 50) and
            self.data.Close[-1] > self.emaValue[-1] and
            highVolume and
            atrRising
        )
        
        sellSignal = (
            crossover(50, self.rsiValue) and
            self.data.Close[-1] < self.emaValue[-1] and
            highVolume and
            atrRising
        )
        
        if buySignal:
            self.buy()
        elif sellSignal:
            self.sell()


