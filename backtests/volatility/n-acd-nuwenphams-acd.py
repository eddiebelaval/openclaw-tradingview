class TvStrategy(Strategy):
    # OR Settings
    or_preset = "0900"
    or_mins = 15
    or_gmt_offset = -5
    
    # ATR Settings
    atr_period = 9
    atr_pct_a = 0.125
    atr_pct_c = 0.618
    atr_timeframe = "D"
    
