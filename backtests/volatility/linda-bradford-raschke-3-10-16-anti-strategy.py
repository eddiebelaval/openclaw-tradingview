        self.signal_line = self.I(lambda: pta.macd(close, fast=self.fastLength, slow=self.slowLength, signal=self.signalLength)['MACDh_3_10_16'] if pta.macd(close, fast=self.fastLength, slow=self.slowLength, signal=self.signalLength) is not None else pd.Series(0, index=close.index))
