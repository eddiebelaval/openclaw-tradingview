import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swingLen = 5
    bosLookback = 50
    obScanBars = 20
    maxSetups = 4
    tpPct = 0.5
    slPct = 0.3
    maxBars = 40
    cooldown = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.atr14 = self.I(pta.atr, high, low, close, length=14)
        self.rsi14 = self.I(pta.rsi, close, length=14)
        self.volMa = self.I(pta.sma, volume, length=20)
        
        self.setups = []
        self.g_inTrade = False
        self.lastSigBar = -999
        self.swingHighs = []
        self.swingHighBars = []
        self.swingLows = []
        self.swingLowBars = []
        
    def detect_swings(self, idx):
        if idx < self.swingLen * 2:
            return
        
        high_slice = self.data.High[max(0, idx - self.swingLen):idx + 1]
        low_slice = self.data.Low[max(0, idx - self.swingLen):idx + 1]
        
        if len(high_slice) == self.swingLen + 1:
            mid = self.swingLen
            if high_slice.iloc[mid] == high_slice.max():
                swHigh = high_slice.iloc[mid]
                if len(self.swingHighs) == 0 or abs(self.swingHighs[0] - swHigh) > 1e-6:
                    self.swingHighs.insert(0, swHigh)
                    self.swingHighBars.insert(0, idx - self.swingLen)
                    if len(self.swingHighs) > 20:
                        self.swingHighs.pop()
                        self.swingHighBars.pop()
        
        if len(low_slice) == self.swingLen + 1:
            mid = self.swingLen
            if low_slice.iloc[mid] == low_slice.min():
                swLow = low_slice.iloc[mid]
                if len(self.swingLows) == 0 or abs(self.swingLows[0] - swLow) > 1e-6:
                    self.swingLows.insert(0, swLow)
                    self.swingLowBars.insert(0, idx - self.swingLen)
                    if len(self.swingLows) > 20:
                        self.swingLows.pop()
                        self.swingLowBars.pop()
    
    def detect_bos(self, idx):
        bearBOS = False
        bearBOSLevel = None
        bearBOSBar = None
        bullBOS = False
        bullBOSLevel = None
        bullBOSBar = None
        
        if idx > 0 and len(self.swingLows) > 0:
            cap = min(len(self.swingLows) - 1, 9)
            for i in range(cap + 1):
                lvl = self.swingLows[i]
                bIdx = self.swingLowBars[i]
                if (self.data.Close[idx] < lvl and 
                    self.data.Close[idx - 1] >= lvl and 
                    (idx - bIdx) < self.bosLookback):
                    bearBOS = True
                    bearBOSLevel = lvl
                    bearBOSBar = bIdx
                    break
        
        if idx > 0 and len(self.swingHighs) > 0:
            cap = min(len(self.swingHighs) - 1, 9)
            for i in range(cap + 1):
                lvl = self.swingHighs[i]
                bIdx = self.swingHighBars[i]
                if (self.data.Close[idx] > lvl and 
                    self.data.Close[idx - 1] <= lvl and 
                    (idx - bIdx) < self.bosLookback):
                    bullBOS = True
                    bullBOSLevel = lvl
                    bullBOSBar = bIdx
                    break
        
        return bearBOS, bearBOSLevel, bearBOSBar, bullBOS, bullBOSLevel, bullBOSBar
    
    def find_ob(self, isBearSetup, idx):
        obTop = None
        obBot = None
        obBarIdx = None
        
        for lookback in range(1, self.obScanBars + 1):
            check_idx = idx - lookback
            if check_idx < 0:
                break
            if isBearSetup:
                if self.data.Close[check_idx] > self.data.Open[check_idx]:
                    obTop = self.data.High[check_idx]
                    obBot = min(self.data.Open[check_idx], self.data.Close[check_idx])
                    obBarIdx = check_idx
                    break
            else:
                if self.data.Close[check_idx] < self.data.Open[check_idx]:
                    obTop = max(self.data.Open[check_idx], self.data.Close[check_idx])
                    obBot = self.data.Low[check_idx]
                    obBarIdx = check_idx
                    break
        
        return obTop, obBot, obBarIdx
    
    def next(self):
        idx = len(self.data) - 1
        
        self.detect_swings(idx)
        
        bearBOS, bearBOSLevel, bearBOSBar, bullBOS, bullBOSLevel, bullBOSBar = self.detect_bos(idx)
        
        if bearBOS:
            obT, obB, obBI = self.find_ob(True, idx)
            if obT is not None:
                setup = {
                    'isBear': True,
                    'bosLevel': bearBOSLevel,
                    'bosBar': bearBOSBar,
                    'obTop': obT,
                    'obBot': obB,
                    'obBar': obBI,
                    'liqLevel': bearBOSLevel,
                    'waiting': True,
                    'armed': False,
                    'active': False,
                    'done': False,
                    'entryPrice': None,
                    'tp': None,
                    'sl': None,
                    'entryBar': None,
                    'activatedBar': None,
                }
                self.setups.insert(0, setup)
                if len(self.setups) > self.maxSetups:
                    self.setups.pop()
        
        if bullBOS:
            obT, obB, obBI = self.find_ob(False, idx)
            if obT is not None:
                setup = {
                    'isBear': False,
                    'bosLevel': bullBOSLevel,
                    'bosBar': bullBOSBar,
                    'obTop': obT,
                    'obBot': obB,
                    'obBar': obBI,
                    'liqLevel': bullBOSLevel,
                    'waiting': True,
                    'armed': False,
                    'active': False,
                    'done': False,
                    'entryPrice': None,
                    'tp': None,
                    'sl': None,
                    'entryBar': None,
                    'activatedBar': None,
                }
                self.setups.insert(0, setup)
                if len(self.setups) > self.maxSetups:
                    self.setups.pop()
        
        for s in self.setups:
            if s['done']:
                continue
            
            if s['waiting']:
                priceLeft = (self.data.Close[idx] < s['obBot']) if s['isBear'] else (self.data.Close[idx] > s['obTop'])
                if priceLeft:
                    s['waiting'] = False
                    s['armed'] = True
            
            elif s['armed']:
                retested = (self.data.High[idx] >= s['obBot'] and self.data.Close[idx] <= s['obTop']) if s['isBear'] else (self.data.Low[idx] <= s['obTop'] and self.data.Close[idx] >= s['obBot'])
                invalid = (self.data.Close[idx] > s['obTop']) if s['isBear'] else (self.data.Close[idx] < s['obBot'])
                
                if invalid:
                    s['done'] = True
                elif retested and not self.g_inTrade and (idx - self.lastSigBar >= self.cooldown):
                    self.g_inTrade = True
                    self.lastSigBar = idx
                    s['armed'] = False
                    s['active'] = True
                    s['entryPrice'] = self.data.Close[idx]
                    s['entryBar'] = idx
                    s['activatedBar'] = idx
                    
                    if s['isBear']:
                        s['tp'] = s['entryPrice'] * (1 - self.tpPct / 100)
                        s['sl'] = s['entryPrice'] * (1 + self.slPct / 100)
                    else:
                        s['tp'] = s['entryPrice'] * (1 + self.tpPct / 100)
                        s['sl'] = s['entryPrice'] * (1 - self.slPct / 100)
                    
                    if s['isBear']:
                        self.sell()
                    else:
                        self.buy()
            
            elif s['active']:
                barsHeld = idx - s['entryBar']
                tpHit = (self.data.Low[idx] <= s['tp']) if s['isBear'] else (self.data.High[idx] >= s['tp'])
                slHit = (self.data.High[idx] >= s['sl']) if s['isBear'] else (self.data.Low[idx] <= s['sl'])
                
                if tpHit or slHit or barsHeld >= self.maxBars:
                    s['done'] = True
                    s['active'] = False
                    self.g_inTrade = False
                    if self.position:
                        self.position.close()