import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    basePeriod = 10
    rankPeriod = 200
    smoothInput = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        def get_vol_heat(length, rank, smooth):
            atr = pta.atr(high, low, close, length=length)
            if atr is None:
                return pd.Series(50, index=close.index)
            vol = atr / close
            
            vol_min = vol.rolling(rank).min()
            vol_max = vol.rolling(rank).max()
            vol_range = vol_max - vol_min
            vol_range = vol_range.replace(0, 1)
            rankVal = ((vol - vol_min) / vol_range) * 100
            rankVal = rankVal.fillna(50)
            
            ema_result = pta.ema(rankVal, length=smooth)
            return ema_result if ema_result is not None else rankVal
        
        self.h1 = self.I(lambda: get_vol_heat(self.basePeriod * 1, self.rankPeriod, self.smoothInput))
        self.h2 = self.I(lambda: get_vol_heat(self.basePeriod * 2, self.rankPeriod, self.smoothInput))
        self.h3 = self.I(lambda: get_vol_heat(self.basePeriod * 3, self.rankPeriod, self.smoothInput))
        self.h4 = self.I(lambda: get_vol_heat(self.basePeriod * 4, self.rankPeriod, self.smoothInput))
        self.h5 = self.I(lambda: get_vol_heat(self.basePeriod * 5, self.rankPeriod, self.smoothInput))
        self.h6 = self.I(lambda: get_vol_heat(self.basePeriod * 6, self.rankPeriod, self.smoothInput))
        self.h7 = self.I(lambda: get_vol_heat(self.basePeriod * 7, self.rankPeriod, self.smoothInput))
        self.h8 = self.I(lambda: get_vol_heat(self.basePeriod * 8, self.rankPeriod, self.smoothInput))
        self.h9 = self.I(lambda: get_vol_heat(self.basePeriod * 9, self.rankPeriod, self.smoothInput))
        self.h10 = self.I(lambda: get_vol_heat(self.basePeriod * 10, self.rankPeriod, self.smoothInput))
        
        def get_agg_heat():
            agg = (self.h1 + self.h2 + self.h3 + self.h4 + self.h5 + 
                   self.h6 + self.h7 + self.h8 + self.h9 + self.h10) / 10
            return agg
        
        self.aggHeat = self.I(lambda: get_agg_heat())

    def next(self):
        if len(self.data) < 2:
            return
        
        current_agg = self.aggHeat[-1]
        prev_agg = self.aggHeat[-2] if len(self.aggHeat) > 1 else current_agg
        
        if not self.position:
            if current_agg > 70 and prev_agg <= 70:
                self.buy()
            elif current_agg < 30 and prev_agg >= 30:
                self.buy()
        else:
            if current_agg <= 70 and prev_agg > 70:
                self.sell()
            elif current_agg >= 30 and prev_agg < 30:
                self.sell()