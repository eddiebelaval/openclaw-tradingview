import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Bollinger Bands parameters
    bbLen = 20
    bbMult = 2.0
    
    # Keltner Channels parameters
    kLen = 20
    kMult = 1.5
    
    # Percentile method parameters
    pctLookback = 125
    pctThresh = 25

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Bollinger Bands
        self.bb = self.I(lambda: pta.bbands(close, length=self.bbLen, std=self.bbMult))
        
        # Calculate SMA basis
        self.sma_basis = self.I(lambda: pta.sma(close, length=self.bbLen))
        
        # Calculate standard deviation for BB width
        self.bb_stdev = self.I(lambda: close.rolling(self.bbLen).std())
        
        # Calculate ATR for Keltner Channels
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.kLen))
        
        # Calculate BB width
        self.bb_width = self.I(lambda: self._calc_bb_width(close))
        
        # Calculate percentrank of BB width
        self.bb_width_percentrank = self.I(lambda: self._calc_percentrank(close))
        
        # Squeeze detection flags
        self.sqz_keltner = self.I(lambda: self._calc_sqz_keltner(close, high, low))
        self.sqz_percentile = self.I(lambda: self._calc_sqz_percentile(close))
        
        # Combined squeeze signal
        self.squeeze_active = self.I(lambda: self._calc_squeeze_active(close, high, low))

    def _calc_bb_width(self, close):
        sma = close.rolling(self.bbLen).mean()
        stdev = close.rolling(self.bbLen).std()
        dev = self.bbMult * stdev
        width = (2 * dev) / sma
        return width

    def _calc_percentrank(self, close):
        bb_width = self._calc_bb_width(close)
        percentrank = bb_width.rolling(self.pctLookback).apply(
            lambda x: (x[-1] > x[:-1]).sum() / len(x[:-1]) * 100 if len(x) > 1 else 50,
            raw=False
        )
        return percentrank

    def _calc_sqz_keltner(self, close, high, low):
        # BB calculation
        sma = close.rolling(self.bbLen).mean()
        stdev = close.rolling(self.bbLen).std()
        bb_dev = self.bbMult * stdev
        bb_upper = sma + bb_dev
        bb_lower = sma - bb_dev
        
        # KC calculation
        atr = pta.atr(high, low, close, length=self.kLen)
        kc_upper = sma + self.kMult * atr
        kc_lower = sma - self.kMult * atr
        
        # Squeeze condition: BB inside KC
        sqz = (bb_lower > kc_lower) & (bb_upper < kc_upper)
        return sqz.astype(float)

    def _calc_sqz_percentile(self, close):
        bb_width = self._calc_bb_width(close)
        percentrank = bb_width.rolling(self.pctLookback).apply(
            lambda x: (x[-1] > x[:-1]).sum() / len(x[:-1]) * 100 if len(x) > 1 else 50,
            raw=False
        )
        sqz = percentrank < self.pctThresh
        return sqz.astype(float)

    def _calc_squeeze_active(self, close, high, low):
        sqz_k = self._calc_sqz_keltner(close, high, low)
        sqz_p = self._calc_sqz_percentile(close)
        # Using "Both (either fires)" logic
        return (sqz_k | sqz_p).astype(float)

    def next(self):
        # Check if we have valid data
        if len(self.data) < max(self.bbLen, self.kLen, self.pctLookback):
            return
        
        current_squeeze = self.squeeze_active[-1]
        
        # Buy signal: squeeze ends (transition from squeeze to expansion)
        if len(self.squeeze_active) > 1:
            was_squeezed = self.squeeze_active[-2] > 0.5
            is_expanding = current_squeeze < 0.5
            
            if was_squeezed and is_expanding and not self.position:
                self.buy()
        
        # Sell signal: when squeeze starts (transition from expansion to squeeze)
        if len(self.squeeze_active) > 1:
            was_expanding = self.squeeze_active[-2] < 0.5
            is_squeezed = current_squeeze > 0.5
            
            if was_expanding and is_squeezed and self.position:
                self.sell()


