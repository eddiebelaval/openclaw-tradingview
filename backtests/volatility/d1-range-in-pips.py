import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # This is a display indicator that shows daily range in pips
        # We'll create a simple trading strategy based on daily range
        # Buy when range is expanding, sell when contracting
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate daily range (simple approach using ATR as proxy)
        self.atr = self.I(pta.atr, high, low, close, length=14)
    
    def next(self):
        # Simple strategy: use ATR as a proxy for daily range volatility
        # Buy when ATR is increasing (expanding range)
        # Sell when ATR is decreasing (contracting range)
        
        if len(self.data) < 2:
            return
        
        # Check if we have valid ATR values
        if self.atr[-1] is None or self.atr[-2] is None:
            return
        
        # Buy when range is expanding
        if self.atr[-1] > self.atr[-2]:
            if not self.position:
                self.buy()
        
        # Sell when range is contracting
        elif self.atr[-1] < self.atr[-2]:
            if self.position:
                self.position.close()


