import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenFast = 20
    lenSlow = 100
    lenMom = 1
    lenVol = 10
    lenZ = 20
    longTh = 2.0
    exitTh = 0.0
    atrLen = 14
    atrSL = 2.0
    atrTP = 300.5
    hardSLPct = 2.0
    leverage = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.emaFast = self.I(pta.ema, close, length=self.lenFast)
        self.emaSlow = self.I(pta.ema, close, length=self.lenSlow)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)

        self.trend = self.I(self._calc_trend, close, high, low)
        self.mom = self.I(self._calc_mom, close)
        self.basis = self.I(pta.vwma, close, volume, length=self.lenFast)
        self.stretch = self.I(self._calc_stretch, close, high, low)
        self.mr = self.I(self._calc_mr, close, high, low)
        self.volRaw = self.I(self._calc_volRaw, close)
        self.volReg = self.I(self._calc_volReg, close)
        self.volConf = self.I(self._calc_volConf, volume)
        self.slope = self.I(self._calc_slope, close)
        self.slopeN = self.I(self._calc_slopeN, close)
        self.score = self.I(self._calc_score, close, high, low, volume)
        self.scoreScaled = self.I(lambda: self.score * 7.0)

        self.entry_price = None
        self.runner_mode = False

    def _clamp(self, x, lo, hi):
        return max(lo, min(hi, x))

    def _zscore(self, src_series, length):
        m = src_series.rolling(window=length).mean()
        s = src_series.rolling(window=length).std()
        result = pd.Series(0.0, index=src_series.index)
        mask = s != 0.0
        result[mask] = (src_series[mask] - m[mask]) / s[mask]
        return result

    def _norm(self, src_series, length):
        z = self._zscore(src_series, length)
        return z.apply(lambda x: self._clamp(x, -3.0, 3.0) / 3.0)

    def _calc_trend(self, close, high, low):
        emaFast = pd.Series(pta.ema(close, length=self.lenFast), index=close.index)
        emaSlow = pd.Series(pta.ema(close, length=self.lenSlow), index=close.index)
        atr = pd.Series(pta.atr(high, low, close, length=self.atrLen), index=close.index)
        result = pd.Series(0.0, index=close.index)
        mask = atr != 0.0
        result[mask] = (emaFast[mask] - emaSlow[mask]) / atr[mask]
        result = result.apply(lambda x: self._clamp(x, -3.0, 3.0) / 3.0)
        return result

    def _calc_mom(self, close):
        momRaw = pd.Series(pta.roc(close, length=self.lenMom), index=close.index)
        return self._norm(momRaw, self.lenZ)

    def _calc_stretch(self, close, high, low):
        basis = pd.Series(pta.vwma(close, pd.Series(self.data.Volume), length=self.lenFast), index=close.index)
        atr = pd.Series(pta.atr(high, low, close, length=self.atrLen), index=close.index)
        result = pd.Series(0.0, index=close.index)
        mask = atr != 0.0
        result[mask] = (close[mask] - basis[mask]) / atr[mask]
        return result

    def _calc_mr(self, close, high, low):
        stretch = self._calc_stretch(close, high, low)
        return stretch.apply(lambda x: self._clamp(-x, -3.0, 3.0) / 3.0)

    def _calc_volRaw(self, close):
        log_returns = np.log(close / close.shift(1))
        return pd.Series(log_returns.rolling(window=self.lenVol).std(), index=close.index)

    def _calc_volReg(self, close):
        volRaw = self._calc_volRaw(close)
        return self._norm(volRaw, self.lenZ)

    def _calc_volConf(self, volume):
        return self._norm(volume, self.lenZ)

    def _calc_slope(self, close):
        linreg_current = pd.Series(pta.linreg(close, length=self.lenFast), index=close.index)
        linreg_prev = pd.Series(pta.linreg(close.shift(1), length=self.lenFast), index=close.index)
        return linreg_current - linreg_prev

    def _calc_slopeN(self, close):
        slope = self._calc_slope(close)
        return self._norm(slope, self.lenZ)

    def _calc_score(self, close, high, low, volume):
        trend = self._calc_trend(close, high, low)
        mom = self._calc_mom(close)
        mr = self._calc_mr(close, high, low)
        volReg = self._calc_volReg(close)
        volConf = self._calc_volConf(volume)
        slopeN = self._calc_slopeN(close)

        score = (
            0.20 * trend +
            0.20 * mom +
            0.10 * mr +
            0.0 * volReg * trend.apply(np.sign) +
            0.10 * volConf * mom.apply(np.sign) +
            0.10 * slopeN
        )
        return score

    def next(self):
        if len(self.data) < max(self.lenSlow, self.lenZ + self.lenFast):
            return

        close_val = self.data.Close[-1]
        emaFast_val = self.emaFast[-1]
        emaSlow_val = self.emaSlow[-1]
        atr_val = self.atr[-1]
        scoreScaled_val = self.scoreScaled[-1]

        if emaFast_val is None or emaSlow_val is None or atr_val is None or scoreScaled_val is None:
            return

        regimeLong = emaFast_val > emaSlow_val and close_val > emaSlow_val
        longSignal = scoreScaled_val > self.longTh and regimeLong

        if not self.position:
            safeEquity = max(self.equity, 0)
            posQtyRaw = (safeEquity * self.leverage) / close_val if close_val > 0 else 0
            posQty = max(posQtyRaw, 0)

            if longSignal and posQty > 0:
                self.buy(size=posQty)
                self.entry_price = close_val
                self.runner_mode = False
        else:
            baseExitSignal = scoreScaled_val < self.exitTh or close_val < emaFast_val

            if self.entry_price is not None:
                atrStop = self.entry_price - self.atrSL * atr_val
                hardStop = self.entry_price * (1.0 - self.hardSLPct / 100.0)
                normalStop = max(atrStop, hardStop)
                longTake = self.entry_price + self.atrTP * atr_val

                if baseExitSignal:
                    self.position.close()
                elif close_val <= normalStop:
                    self.position.close()
                elif close_val >= longTake:
                    self.position.close()