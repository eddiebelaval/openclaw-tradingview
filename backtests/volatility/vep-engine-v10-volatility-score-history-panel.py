import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    hvLen = 30
    ivLen = 10
    lookback = 252
    ma21Len = 21
    ma50Len = 50
    ma200Len = 200
    useRSI = True
    rsiLen = 14
    rsiMin = 45
    minMktCapB = 10
    vrpMin = 1.05
    ivRankMin = 40
    ivPctMin = 40
    ivMode = "StdDev Proxy"
    dteDays = 45
    intervalWidth = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        dLog = np.log(close / close.shift(1))
        
        self.hv = self.I(lambda: pta.stdev(dLog, self.hvLen) * np.sqrt(252) * 100.0)
        self.ivProxy = self.I(lambda: pta.stdev(dLog, self.ivLen) * np.sqrt(252) * 100.0)
        
        avgRet = self.I(lambda: pta.sma(dLog, self.dteDays))
        stRet = self.I(lambda: pta.stdev(dLog, self.dteDays))
        
        timeAvg = self.dteDays * avgRet
        timeStd = stRet * np.sqrt(self.dteDays)
        
        upper = close * np.exp(timeAvg + self.intervalWidth * timeStd)
        lower = close * np.exp(timeAvg - self.intervalWidth * timeStd)
        
        width = upper - lower
        standard_dev = width / 2.0
        
        def calc_model_iv():
            result = pd.Series(np.nan, index=close.index)
            for i in range(len(close)):
                if pd.notna(standard_dev.iloc[i]) and pd.notna(close.iloc[i]) and close.iloc[i] > 0:
                    sigma = standard_dev.iloc[i] / (close.iloc[i] * np.sqrt(self.dteDays / 365.0))
                    sigmaAdj = (sigma / 2.0) if sigma > 1.0 else sigma
                    result.iloc[i] = sigmaAdj * 100.0
            return result
        
        self.modelIV = self.I(calc_model_iv)
        
        self.ivUsed = self.modelIV if self.ivMode == "Model IV (DTE-based)" else self.ivProxy
        
        def calc_vrp():
            result = pd.Series(np.nan, index=close.index)
            for i in range(len(close)):
                if pd.notna(self.hv[i]) and self.hv[i] > 0 and pd.notna(self.ivUsed[i]):
                    result.iloc[i] = self.ivUsed[i] / self.hv[i]
            return result
        
        self.vrp = self.I(calc_vrp)
        
        def calc_iv_rank():
            result = pd.Series(np.nan, index=close.index)
            for i in range(self.lookback, len(close)):
                ivLo = self.ivUsed[i-self.lookback:i].min()
                ivHi = self.ivUsed[i-self.lookback:i].max()
                if pd.notna(ivHi) and pd.notna(ivLo) and ivHi != ivLo:
                    result.iloc[i] = 100.0 * (self.ivUsed[i] - ivLo) / (ivHi - ivLo)
            return result
        
        self.ivRank = self.I(calc_iv_rank)
        
        def calc_iv_pct():
            result = pd.Series(np.nan, index=close.index)
            for i in range(self.lookback, len(close)):
                cnt = (self.ivUsed[i-self.lookback:i] <= self.ivUsed[i]).sum()
                result.iloc[i] = 100.0 * cnt / self.lookback
            return result
        
        self.ivPct = self.I(calc_iv_pct)
        
        self.dMA21 = self.I(pta.sma, close, length=self.ma21Len)
        self.dMA50 = self.I(pta.sma, close, length=self.ma50Len)
        self.dMA200 = self.I(pta.sma, close, length=self.ma200Len)
        
        self.dRSI = self.I(pta.rsi, close, length=self.rsiLen)
        
        def calc_total_score():
            result = pd.Series(np.nan, index=close.index)
            for i in range(len(close)):
                structureScore = 0.0
                
                if (pd.notna(self.dMA21[i]) and pd.notna(self.dMA50[i]) and pd.notna(self.dMA200[i]) and
                    close[i] > self.dMA21[i] and close[i] > self.dMA50[i] and close[i] > self.dMA200[i]):
                    structureScore += 30.0
                
                if not self.useRSI:
                    structureScore += 10.0
                elif pd.notna(self.dRSI[i]):
                    rsi_score = self._f_linScore(self.dRSI[i], self.rsiMin, 65.0, 10.0)
