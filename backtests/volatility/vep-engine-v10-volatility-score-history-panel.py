    def _f_clamp(self, x, lo, hi):
        return max(lo, min(hi, x))

    def _f_linScore(self, x, x0, x1, pts):
        r = (x - x0) / (x1 - x0)
        rc = self._f_clamp(r, 0.0, 1.0)
        return rc * pts

