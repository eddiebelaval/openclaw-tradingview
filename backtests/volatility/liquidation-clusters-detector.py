import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core Settings
    lookback = 20
    atr_len = 14
    vol_len = 20
    
    # Threshold Settings
    threshold_mode = 'Z'  # 'Z', 'Percentile', 'SMA+StDev'
    z_threshold = 2.0
    percentile_threshold = 90.0
    k_stdev = 2.0
    
    # Other Settings
    debug = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_price = pd.Series(self.data.Open)
        
        # ATR and Volume calculations
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.vol_avg = self.I(pta.sma, volume, length=self.vol_len)
        
        # Local extremes
        self.local_low = self.I(lambda: low.rolling(self.lookback).min())
        self.local_high = self.I(lambda: high.rolling(self.lookback).max())
        
        # Wick calculations
        self.upper_wick = self.I(lambda: high - np.maximum(open_price, close))
        self.lower_wick = self.I(lambda: np.minimum(open_price, close) - low)
        
        # Intensity history for threshold calculation
        self.intensity_history = []
        self.last_long_peak = 0
        self.last_short_peak = 0

    def next(self):
        if len(self.data) < self.lookback + 5:
            return
        
        # Get current values
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_volume = self.data.Volume[-1]
        
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        vol_avg_val = self.vol_avg[-1] if self.vol_avg[-1] is not None else current_volume
        
        if atr_val == 0 or vol_avg_val == 0:
            return
        
        local_low_prev = self.local_low[-2] if len(self.local_low) > 1 else current_low
        local_high_prev = self.local_high[-2] if len(self.local_high) > 1 else current_high
        
        upper_wick_val = self.upper_wick[-1] if self.upper_wick[-1] is not None else 0
        lower_wick_val = self.lower_wick[-1] if self.lower_wick[-1] is not None else 0
        
        # Long liquidation sweep conditions
        long_sweep_break = current_low < local_low_prev
        long_big_wick = lower_wick_val > atr_val * 1.5
        long_elevated_vol = current_volume > vol_avg_val * 2.0
        long_reclaim = current_close > current_open or current_close > (current_high + current_low) / 2
        long_sweep = long_sweep_break and long_big_wick and long_elevated_vol and long_reclaim
        
        # Short liquidation sweep conditions
        short_sweep_break = current_high > local_high_prev
        short_big_wick = upper_wick_val > atr_val * 1.5
        short_elevated_vol = current_volume > vol_avg_val * 2.0
        short_reversal = current_close < current_open or current_close < (current_high + current_low) / 2
        short_sweep = short_sweep_break and short_big_wick and short_elevated_vol and short_reversal
        
        # Intensity calculation
        normalized_volume = current_volume / vol_avg_val if vol_avg_val > 0 else 1.0
        
        wick_intensity = 0.0
        distance_from_extreme = 0.0
        
        if long_sweep:
            wick_intensity = lower_wick_val / atr_val if atr_val > 0 else 0
            distance_from_extreme = abs(current_low - local_low_prev) / atr_val if atr_val > 0 else 0
        elif short_sweep:
            wick_intensity = upper_wick_val / atr_val if atr_val > 0 else 0
            distance_from_extreme = abs(current_high - local_high_prev) / atr_val if atr_val > 0 else 0
        
        intensity = normalized_volume * wick_intensity * (1 + distance_from_extreme)
        
        # Update intensity history
        if intensity > 0:
            self.intensity_history.append(intensity)
            if len(self.intensity_history) > 200:
                self.intensity_history.pop(0)
        
        # Peak detection based on threshold mode
        is_above_threshold = False
        if len(self.intensity_history) > 20 and intensity > 0:
            if self.threshold_mode == 'Z':
                mean = np.mean(self.intensity_history)
                stdev = np.std(self.intensity_history)
                z_score = (intensity - mean) / stdev if stdev > 0 else 0
                is_above_threshold = z_score > self.z_threshold
            elif self.threshold_mode == 'Percentile':
                sorted_intensity = sorted(self.intensity_history)
                percentile_index = int(np.round(len(sorted_intensity) * self.percentile_threshold / 100)) - 1
                percentile_index = max(0, percentile_index)
                percentile_value = sorted_intensity[percentile_index]
                is_above_threshold = intensity > percentile_value
            elif self.threshold_mode == 'SMA+StDev':
                mean = np.mean(self.intensity_history)
                stdev = np.std(self.intensity_history)
                threshold = mean + self.k_stdev * stdev
                is_above_threshold = intensity > threshold
        
        # Peak signals
        is_long_peak = long_sweep and is_above_threshold
        is_short_peak = short_sweep and is_above_threshold
        
        # Trading logic based on liquidation detection
        if is_long_peak and len(self.position) == 0:
            self.buy()
            self.last_long_peak = len(self.data)
        
        if is_short_peak and len(self.position) > 0:
            self.sell()
            self.last_short_peak = len(self.data)
        
        # Exit long after significant move or time-based
        if len(self.position) > 0 and len(self.data) - self.last_long_peak > 10:
            self.sell()


