import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Parameters
    ema_fast_len = 9
    ema_mid_len = 13
    ema_slow_len = 21
    
    # Range Lookback
    range_len = 3
    
    # Volume Filter
    use_vol_filter = False
    vol_ma_len = 14
    vol_multiplier = 1.2
    
    # Momentum Parameters
    rsi_len = 14
    rsi_high = 70
    rsi_low = 30
    macd_fast = 12
    macd_slow = 26
    macd_sig_len = 9
    atr_len = 14
    
    # Intermarket (DXY)
    use_dxy = False
    dxy_len = 20
    strong_lvl = 0.55
    mild_lvl = 0.15
    
    # Score Thresholds
    min_score_long = 0.05
    min_score_short = -0.05
    
    # Predictive VMACD
    vmacd_fast_len = 12
    vmacd_slow_len = 26
    vmacd_sig_len = 9
    reg_len = 20
    proj_bars = 5
    quad_damp = 0.6

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        bar_index = pd.Series(np.arange(len(close)))
        
        # EMAs on Current Timeframe
        self.ema_fast = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema_mid = self.I(pta.ema, close, length=self.ema_mid_len)
        self.ema_slow = self.I(pta.ema, close, length=self.ema_slow_len)
        
        # Momentum Components
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        macd_result = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig_len))
        self.macd_line = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig_len).iloc[:, 0] if pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig_len) is not None else pd.Series(0, index=close.index))
        self.macd_hist = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig_len).iloc[:, 2] if pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig_len) is not None else pd.Series(0, index=close.index))
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Volume MA
        self.avg_vol = self.I(pta.sma, volume, length=self.vol_ma_len)
        
        # Range High/Low
        self.range_high = self.I(lambda: high.rolling(self.range_len).max())
        self.range_low = self.I(lambda: low.rolling(self.range_len).min())
        
        # VWMA for Predictive VMACD
        self.fast_vwma = self.I(pta.vwma, close, volume, length=self.vmacd_fast_len)
        self.slow_vwma = self.I(pta.vwma, close, volume, length=self.vmacd_slow_len)
        
        self.vmacd_raw = self.I(lambda: self.fast_vwma - self.slow_vwma if self.fast_vwma is not None and self.slow_vwma is not None else pd.Series(0, index=close.index))
        self.signal_raw = self.I(lambda: pta.ema(self.vmacd_raw if self.vmacd_raw is not None else pd.Series(0, index=close.index), length=self.vmacd_sig_len) or pd.Series(0, index=close.index))
        
        # Linear regression for slope and curvature
        self.linreg_v = self.I(lambda: pta.linreg(self.vmacd_raw if self.vmacd_raw is not None else pd.Series(0, index=close.index), length=self.reg_len) or pd.Series(0, index=close.index))
        self.linreg_s = self.I(lambda: pta.linreg(self.signal_raw if self.signal_raw is not None else pd.Series(0, index=close.index), length=self.reg_len) or pd.Series(0, index=close.index))
        
        self.last_signal = None

    def next(self):
        if len(self) < max(self.ema_slow_len, self.reg_len, self.range_len) + self.proj_bars:
            return
        
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        # Current indicator values
        ema_fast_val = self.ema_fast[-1]
        ema_mid_val = self.ema_mid[-1]
        ema_slow_val = self.ema_slow[-1]
        
        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50
        macd_hist_val = self.macd_hist[-1] if self.macd_hist[-1] is not None else 0
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0.001
        
        avg_vol_val = self.avg_vol[-1] if self.avg_vol[-1] is not None else volume_val
        
        range_high_val = self.range_high[-2] if len(self) > 1 else high_val
        range_low_val = self.range_low[-2] if len(self) > 1 else low_val
        
        # Momentum Directions
        ema_dir = 1 if ema_fast_val > ema_slow_val else (-1 if ema_fast_val < ema_slow_val else 0)
        rsi_dir = 1 if rsi_val < self.rsi_low else (-1 if rsi_val > self.rsi_high else 0)
        macd_dir = 1 if macd_hist_val > 0 else (-1 if macd_hist_val < 0 else 0)
        
        # Volume scaling
        vol_scale = 1.0 / max(0.001, 1 + atr_val / close_val) if close_val > 0 else 1.0
        
        # Composite score
        tech = (ema_dir + rsi_dir + macd_dir) / 3.0
        composite = (0.6 * tech) * vol_scale
        score = max(-1.0, min(1.0, composite))
        
        # HTF Trend (approximated with current EMAs since no HTF data)
        htf_bullish = ema_fast_val > ema_mid_val and ema_mid_val > ema_slow_val
        htf_bearish = ema_fast_val < ema_mid_val and ema_mid_val < ema_slow_val
        
        # VMACD Predictive
        vmacd_raw_val = self.vmacd_raw[-1] if self.vmacd_raw[-1] is not None else 0
        signal_raw_val = self.signal_raw[-1] if self.signal_raw[-1] is not None else 0
        linreg_v_val = self.linreg_v[-1] if self.linreg_v[-1] is not None else vmacd_raw_val
        linreg_s_val = self.linreg_s[-1] if self.linreg_s[-1] is not None else signal_raw_val
        
        # Calculate slope using correlation approximation
        slope_v = self._calculate_slope(self.vmacd_raw, self.reg_len)
        slope_s = self._calculate_slope(self.signal_raw, self.reg_len)
        
        # Curvature
        curv_v = (vmacd_raw_val - linreg_v_val) * self.quad_damp * 2 / self.reg_len if self.reg_len > 0 else 0
        curv_s = (signal_raw_val - linreg_s_val) * self.quad_damp * 2 / self.reg_len if self.reg_len > 0 else 0
        
        # Projected values
        future_v = vmacd_raw_val + slope_v * self.proj_bars + curv_v * self.proj_bars * self.proj_bars
        future_s = signal_raw_val + slope_s * self.proj_bars + curv_s * self.proj_bars * self.proj_bars
        
        pred_bullish = future_v > future_s
        pred_bearish = future_v < future_s
        
        # Base conditions
        base_long = htf_bullish and close_val > ema_fast_val and ema_fast_val > ema_mid_val and ema_mid_val > ema_slow_val and close_val > range_high_val
        base_short = htf_bearish and close_val < ema_fast_val and ema_fast_val < ema_mid_val and ema_mid_val < ema_slow_val and close_val < range_low_val
        
        # Volume filter
        high_vol = volume_val > avg_vol_val * self.vol_multiplier
        if self.use_vol_filter:
            base_long = base_long and high_vol
            base_short = base_short and high_vol
        
        # Combined signals
        long_condition = base_long and (score > self.min_score_long) and pred_bullish
        short_condition = base_short and (score < self.min_score_short) and pred_bearish
        
        # Weak signals
        weak_long = htf_bullish and close_val > ema_fast_val and (score > 0.0) and pred_bullish
        weak_short = htf_bearish and close_val < ema_fast_val and (score < 0.0) and pred_bearish
        
        # Execute trades
        if long_condition and self.last_signal != "long":
            if self.position:
                self.position.close()
            self.buy()
            self.last_signal = "long"
        elif weak_long and self.last_signal != "long" and not self.position:
            self.buy()
            self.last_signal = "long"
        elif short_condition and self.last_signal != "short":
            if self.position:
                self.position.close()
            self.sell()
            self.last_signal = "short"
        elif weak_short and self.last_signal != "short" and not self.position:
            self.sell()
            self.last_signal = "short"
    
    def _calculate_slope(self, series, length):
        if len(series) < length:
            return 0.0
        recent = series[-length:]
        x = np.arange(length)
        y = np.array(recent)
        if np.all(np.isnan(y)) or np.all(y == 0):
            return 0.0
        valid_idx = ~np.isnan(y)
        if np.sum(valid_idx) < 2:
            return 0.0
        x_valid = x[valid_idx]
        y_valid = y[valid_idx]
        cov_xy = np.cov(x_valid, y_valid)[0, 1]
        var_x = np.var(x_valid)
        return cov_xy / var_x if var_x > 0 else 0.0


