import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Dump Detection
    anomaly_threshold_pct = 1.0
    days_break_len = 7
    dump_cap_pct = 2.0
    
    # Risk / Exits
    arm_profit_pct = 5.0
    peak_retrace_pct = 1.5
    enable_sl = False
    stop_loss_pct = 15.0
    max_hours_in_loss = 0
    
    # Filters
    resist_lookback_days = 3
    resist_proximity_pct = 1.0
    use_btc_trend_filter = False
    
    # Entry Timing - ATRStop mode
    entry_mode = "ATRStop"
    atr_stop_atr_len = 14
    atr_stop_mult = 0.5
    stop_expiry_bars = 12
    
    # Cooldown
    cooldown_hours = 4

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR for entry modes
        self.atr_stop = self.I(pta.atr, high, low, close, length=self.atr_stop_atr_len)
        
        # Highest/Lowest for resistance and dump tracking
        resist_lookback = max(1, self.resist_lookback_days)
        self.daily_highest = self.I(lambda: high.rolling(resist_lookback).max())
        
        flat_lookback = 5
        self.flat_hh = self.I(lambda: high.rolling(flat_lookback).max())
        self.flat_ll = self.I(lambda: low.rolling(flat_lookback).min())
        
        # State tracking
        self.dump_candle_high = None
        self.waiting_for_reclaim = False
        self.wait_for_green = False
        self.armed_low = None
        self.dump_leg_lowest_low = None
        self.stop_order_active = False
        self.stop_expires_bar = None
        self.stop_trigger_price = None
        self.cooldown_until_bar = None
        self.peak_profit_pct = None
        self.entry_open_bar = None
        self.position_avg_price_tracked = None

    def next(self):
        if len(self.data) < 2:
            return
            
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        current_bar = len(self.data) - 1
        
        # Check if in position
        in_long = self.position.size > 0
        
        # Calculate profit metrics if in position
        if in_long:
            avg_price = self.position.open_price
            profit_pct = (close - avg_price) / avg_price * 100.0
            if self.peak_profit_pct is None:
                self.peak_profit_pct = profit_pct
            else:
                self.peak_profit_pct = max(self.peak_profit_pct, profit_pct)
        
        # Check cooldown
        is_cooling_down = (self.cooldown_until_bar is not None and 
                          current_bar < self.cooldown_until_bar)
        
        # Dump detection
        from_price = open_price
        to_price = close
        diff = (to_price / from_price - 1.0) * 100.0 if from_price != 0 else 0.0
        is_anomaly = abs(diff) > self.anomaly_threshold_pct
        within_dump_cap = abs(diff) <= self.dump_cap_pct or self.dump_cap_pct == 0
        dump_signal = is_anomaly and close < open_price and within_dump_cap
        
        # N-day low break filter
        breaks_n_days_low = True
        if self.days_break_len > 0:
            safe_days_len = max(1, self.days_break_len)
            lookback_low = min([self.data.Low[max(0, current_bar - i)] 
                               for i in range(1, safe_days_len + 1)])
            breaks_n_days_low = low < lookback_low
        
        # Resistance proximity filter
        near_resistance = False
        if current_bar >= 1:
            resistance = self.daily_highest[-1]
            if resistance is not None and not np.isnan(resistance) and resistance > 0:
                dist_to_resist = ((resistance - close) / resistance * 100.0)
                near_resistance = (close < resistance and 
                                 dist_to_resist <= self.resist_proximity_pct)
        
        can_enter = not near_resistance
        can_pyramid = self.position.size < 5
        no_pos = self.position.size == 0
        
        # Arm structure break on dump detection
        if (not is_cooling_down and dump_signal and breaks_n_days_low and 
            (no_pos or (in_long and can_pyramid))):
            self.waiting_for_reclaim = True
            self.dump_candle_high = high
            self.dump_leg_lowest_low = low
            self.stop_order_active = False
            self.stop_expires_bar = None
            self.stop_trigger_price = None
        
        # Cancel waiting during cooldown
        if is_cooling_down and self.waiting_for_reclaim:
            self.waiting_for_reclaim = False
            self.dump_candle_high = None
            self.dump_leg_lowest_low = None
            self.stop_order_active = False
        
        # Update lowest low while waiting
        if self.waiting_for_reclaim and not is_cooling_down:
            curr_diff = (close / open_price - 1.0) * 100.0 if open_price != 0 else 0.0
            curr_within_cap = abs(curr_diff) <= self.dump_cap_pct or self.dump_cap_pct == 0
            if low < (self.dump_leg_lowest_low or 1e10) and curr_within_cap:
                self.dump_leg_lowest_low = low
                self.dump_candle_high = high
                self.stop_order_active = False
        
        # Entry logic - ATRStop mode
        if (self.waiting_for_reclaim and not is_cooling_down and 
            (no_pos or (in_long and can_pyramid))):
            
            if self.dump_candle_high is not None:
                if not self.stop_order_active and can_enter:
                    atr_val = self.atr_stop[-1]
                    if atr_val is not None and not np.isnan(atr_val):
                        self.stop_trigger_price = (self.dump_candle_high + 
                                                 (self.atr_stop_mult * atr_val))
                        
                        # Use stop order logic
                        if high >= self.stop_trigger_price:
                            if no_pos:
                                self.buy()
                            self.waiting_for_reclaim = False
                            self.dump_candle_high = None
                            self.stop_order_active = False
                            self.entry_open_bar = current_bar
                            self.peak_profit_pct = None
                        else:
                            self.stop_order_active = True
                            self.stop_expires_bar = current_bar + self.stop_expiry_bars
                
                # Check stop order expiry
                if (self.stop_order_active and self.stop_expires_bar is not None and 
                    current_bar >= self.stop_expires_bar):
                    self.stop_order_active = False
                    self.stop_expires_bar = None
                    self.stop_trigger_price = None
        
        # Check if position was closed
        if in_long:
            # Profit-taking: peak retrace
            if self.peak_profit_pct is not None:
                armed = self.peak_profit_pct >= self.arm_profit_pct
                if armed:
                    current_profit = (close - self.position.open_price) / self.position.open_price * 100.0
                    retrace = self.peak_profit_pct - current_profit
                    if retrace >= self.peak_retrace_pct:
                        self.position.close()
            
            # Stop loss
            if self.enable_sl:
                stop_price = self.position.open_price * (1.0 - self.stop_loss_pct / 100.0)
                if close <= stop_price:
                    self.position.close()
            
            # Time in loss limiter
            if (self.max_hours_in_loss > 0 and self.entry_open_bar is not None and
                close < self.position.open_price):
                bars_in_loss = current_bar - self.entry_open_bar
                max_bars = self.max_hours_in_loss * 4  # Approximate 4 1h bars per hour
                if bars_in_loss >= max_bars:
                    self.position.close()
        
        # Reset state when position closes
        if self.position.size == 0 and in_long:
            self.waiting_for_reclaim = False
            self.dump_candle_high = None
            self.wait_for_green = False
            self.armed_low = None
            self.dump_leg_lowest_low = None
            self.peak_profit_pct = None
            self.entry_open_bar = None
            self.cooldown_until_bar = current_bar + (self.cooldown_hours * 4)


