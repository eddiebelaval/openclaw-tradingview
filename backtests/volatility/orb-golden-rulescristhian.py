import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Risk Management
    sl_pts = 30.0
    tp_pts = 30.0
    
    # Anti-Chop Filter
    use_chop_filter = True
    adx_threshold = 20
    vol_threshold = 1.0
    
    # ORB Parameters
    orb_start_hour = 9
    orb_start_min = 15
    orb_end_hour = 9
    orb_end_min = 30
    trade_start_hour = 9
    trade_start_min = 30
    trade_end_hour = 11
    trade_end_min = 0
    
    min_range = 20
    max_range = 40
    min_move = 7
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ADX using pandas_ta
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = adx_result
        
        # Calculate average volume
        self.avg_vol = self.I(lambda: pta.sma(volume, length=10))
        
        # State variables
        self.hi915 = None
        self.lo915 = None
        self.trades_today = 0
        self.last_day = None
        self.in_trade = False
    
    def next(self):
        # Get current time info
        current_time = self.data.index[-1]
        current_hour = current_time.hour
        current_min = current_time.minute
        current_day = current_time.day
        
        current_time_mins = current_hour * 60 + current_min
        orb_session_start = self.orb_start_hour * 60 + self.orb_start_min
        orb_session_end = self.orb_end_hour * 60 + self.orb_end_min
        trade_window_start = self.trade_start_hour * 60 + self.trade_start_min
        trade_window_end = self.trade_end_hour * 60 + self.trade_end_min
        
        # Reset on new day
        if self.last_day is None or current_day != self.last_day:
            self.hi915 = None
            self.lo915 = None
            self.trades_today = 0
            self.in_trade = False
            self.last_day = current_day
        
        # ORB Capture Phase (9:15 - 9:30)
        if orb_session_start <= current_time_mins < orb_session_end:
            if self.hi915 is None:
                self.hi915 = self.data.High[-1]
                self.lo915 = self.data.Low[-1]
            else:
                self.hi915 = max(self.hi915, self.data.High[-1])
                self.lo915 = min(self.lo915, self.data.Low[-1])
        
        # Trading Window (9:30 - 11:00)
        if trade_window_start <= current_time_mins < trade_window_end:
            if self.hi915 is not None and self.trades_today == 0 and len(self) > 1:
                range_size = self.hi915 - self.lo915
                is_valid_range = self.min_range <= range_size <= self.max_range
                
                # Check ADX and Volume filters
                adx_value = self.adx[-1] if len(self.adx) > 0 and self.adx[-1] is not None else 0
                avg_vol_value = self.avg_vol[-1] if len(self.avg_vol) > 0 and self.avg_vol[-1] is not None else 1
                
                current_vol = self.data.Volume[-1]
                relative_vol = current_vol / avg_vol_value if avg_vol_value > 0 else 1.0
                
                is_not_choppy = (not self.use_chop_filter) or (adx_value > self.adx_threshold and relative_vol >= self.vol_threshold)
                
                if is_valid_range and is_not_choppy and not self.position:
                    # LONG Entry
                    if self.data.Close[-1] > self.hi915 and self.data.Close[-2] <= self.hi915:
                        move = self.data.High[-1] - self.data.Open[-1]
                        if move > self.min_move:
                            entry_price = self.data.Close[-1]
                            self.buy(sl=entry_price - self.sl_pts, tp=entry_price + self.tp_pts)
                            self.trades_today += 1
                            self.in_trade = True
                    
                    # SHORT Entry
                    elif self.data.Close[-1] < self.lo915 and self.data.Close[-2] >= self.lo915:
                        move = self.data.Open[-1] - self.data.Low[-1]
                        if move > self.min_move:
                            entry_price = self.data.Close[-1]
                            self.buy(sl=entry_price + self.sl_pts, tp=entry_price - self.tp_pts)
                            self.trades_today += 1
                            self.in_trade = True
        
        # Check if position should be closed (end of day or manual exit)
        if self.position and current_time_mins >= trade_window_end:
            self.position.close()