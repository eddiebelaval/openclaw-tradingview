import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_length = 10
    trend_factor = 2.0
    error_margin = 5.0
    ema_length = 14
    hma_length = 70
    num_contracts = 1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Calculate EMA
        self.ema = self.I(pta.ema, close, length=self.ema_length)
        
        # Calculate HMA
        self.hma = self.I(pta.hma, close, length=self.hma_length)
        
        # Calculate trend line
        self.trend_line = self.I(self._calc_trend_line, close, high, low)
        self.trend_dir = self.I(self._calc_trend_dir, close, high, low)
        
        self.in_position = False

    def _calc_trend_line(self, close, high, low):
        trend_line = np.zeros(len(close))
        
        for i in range(1, len(close)):
            if i == 0:
                trend_line[i] = close.iloc[i]
                continue
            
            trend_val = trend_line[i-1]
            
            if close.iloc[i] > close.iloc[i-1]:
                atr_val = self.atr[-1] if i == len(close) - 1 else self.atr[i]
                trend_val = low.iloc[i] - atr_val * self.trend_factor
                if trend_val < trend_line[i-1]:
                    trend_val = trend_line[i-1]
            
            elif close.iloc[i] < close.iloc[i-1]:
                atr_val = self.atr[-1] if i == len(close) - 1 else self.atr[i]
                trend_val = high.iloc[i] + atr_val * self.trend_factor
                if trend_val > trend_line[i-1]:
                    trend_val = trend_line[i-1]
            
            if abs(trend_val - trend_line[i-1]) < self.error_margin:
                trend_val = trend_line[i-1]
            
            trend_line[i] = trend_val
        
        return pd.Series(trend_line, index=close.index)

    def _calc_trend_dir(self, close, high, low):
        trend_line = self._calc_trend_line(close, high, low)
        direction = np.zeros(len(close))
        
        for i in range(1, len(close)):
            if trend_line.iloc[i] > trend_line.iloc[i-1]:
                direction[i] = 1
            elif trend_line.iloc[i] < trend_line.iloc[i-1]:
                direction[i] = -1
            else:
                direction[i] = direction[i-1]
        
        return pd.Series(direction, index=close.index)

    def next(self):
        if len(self.data) < max(self.atr_length, self.ema_length, self.hma_length) + 5:
            return
        
        close_current = self.data.Close[-1]
        trend_line_current = self.trend_line[-1]
        trend_dir_current = self.trend_dir[-1]
        ema_current = self.ema[-1]
        hma_current = self.hma[-1]
        
        if ema_current is None or np.isnan(ema_current):
            return
        if hma_current is None or np.isnan(hma_current):
            return
        
        hma_prev = self.hma[-2] if len(self.hma) > 1 else hma_current
        
        # Long entry: trend is up, price near trend line, HMA trending up
        if not self.position and trend_dir_current > 0:
            if close_current <= trend_line_current + self.error_margin * 2:
                if hma_current > hma_prev:
                    self.buy()
                    self.in_position = True
        
        # Short entry: trend is down, price near trend line, HMA trending down
        if not self.position and trend_dir_current < 0:
            if close_current >= trend_line_current - self.error_margin * 2:
                if hma_current < hma_prev:
                    self.sell()
                    self.in_position = True
        
        # Exit long: trend reverses or price breaks below trend line
        if self.position and self.position.is_long:
            if trend_dir_current < 0 or close_current < trend_line_current - self.error_margin:
                self.position.close()
                self.in_position = False
        
        # Exit short: trend reverses or price breaks above trend line
        if self.position and self.position.is_short:
            if trend_dir_current > 0 or close_current > trend_line_current + self.error_margin:
                self.position.close()
                self.in_position = False


