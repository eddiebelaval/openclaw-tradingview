import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adr_len = 20
    warn_pct = 85.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ADR (Average Daily Range) using SMA of (high - low) from previous bar
        daily_range = high - low
        self.adr = self.I(lambda: pta.sma(daily_range, length=self.adr_len) or pd.Series(0, index=close.index))
        
        # Track today's high and low
        self.today_high = None
        self.today_low = None
        self.today_open = None
        self.last_date = None
        
        # Calculate exhaustion percentage
        self.pct_consumed = self.I(lambda: self._calculate_pct_consumed())
        
        # Track if we're in exhaustion/extended state
        self.was_exhausted = False
        self.was_extended = False

    def _calculate_pct_consumed(self):
        pct_list = []
        today_high = None
        today_low = None
        last_date = None
        
        for i in range(len(self.data)):
            current_high = self.data.High[i]
            current_low = self.data.Low[i]
            current_date = self.data.index[i].date() if hasattr(self.data.index[i], 'date') else None
            
            # Check if new day
            if last_date is None or current_date != last_date:
                today_high = current_high
                today_low = current_low
                last_date = current_date
            else:
                today_high = max(today_high, current_high)
                today_low = min(today_low, current_low)
            
            today_range = today_high - today_low
            adr_val = self.adr[i] if i < len(self.adr) and self.adr[i] is not None else 0
            
            if adr_val > 0:
                pct = (today_range / adr_val) * 100.0
            else:
                pct = 0.0
            
            pct_list.append(pct)
        
        return pd.Series(pct_list, index=self.data.index)

    def next(self):
        if len(self.data) < self.adr_len + 1:
            return
        
        current_pct = self.pct_consumed[-1]
        is_exhausted = current_pct >= self.warn_pct and current_pct < 100.0
        is_extended = current_pct >= 100.0
        
        # Buy signal: when ADR exhaustion is detected (transition from not exhausted to exhausted)
        if is_exhausted and not self.was_exhausted:
            if not self.position:
                self.buy()
            self.was_exhausted = True
        
        # Sell signal: when ADR is extended beyond 100%
        if is_extended and not self.was_extended:
            if self.position:
                self.sell()
            self.was_extended = True
        
        # Reset flags when conditions are no longer met
        if not is_exhausted:
            self.was_exhausted = False
        
        if not is_extended:
            self.was_extended = False
        
        # Exit on extended range if still holding
        if is_extended and self.position:
            self.sell()


