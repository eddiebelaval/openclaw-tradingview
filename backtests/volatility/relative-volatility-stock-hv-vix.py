import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate Historical Volatility (HV)
        def calculate_hv(src, length):
            returns = np.log(src / src.shift(1))
            stdev = returns.rolling(window=length).std()
            hv = stdev * np.sqrt(252) * 100
            return hv
        
        self.stock_hv = self.I(calculate_hv, close, self.length)
        
        # VIX proxy: use ATR as volatility measure (since we don't have actual VIX data)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        atr = self.I(pta.atr, high, low, close, length=self.length)
        
        # Avoid division by zero - use ATR as VIX proxy
        def calculate_relative_vol(hv, vix_proxy):
            with np.errstate(divide='ignore', invalid='ignore'):
                rel_vol = np.where(vix_proxy != 0, hv / vix_proxy, 1.0)
            return pd.Series(rel_vol, index=hv.index)
        
        self.relative_vol = self.I(calculate_relative_vol, self.stock_hv, atr)

    def next(self):
        # Buy when relative volatility crosses above 1 (stock HV > VIX proxy)
        if len(self.relative_vol) > 1:
            if crossover(self.relative_vol, 1.0):
                if not self.position:
                    self.buy()
            # Sell when relative volatility crosses below 1 (stock HV < VIX proxy)
            elif crossover(1.0, self.relative_vol):
                if self.position:
                    self.sell()