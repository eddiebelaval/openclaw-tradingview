import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smaFast = 50
    smaSlow = 200
    atrFast = 20
    atrSlow = 90
    volAvgLen = 20
    rsiLen = 14
    rsiOB = 70
    rsiOS = 30
    macdFast = 12
    macdSlow = 26
    macdSig = 9
    w_sma = 0.25
    w_vol = 0.15
    w_volume = 0.15
    w_rsi = 0.15
    w_macd = 0.15
    w_fg = 0.15

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.sma50 = self.I(pta.sma, close, length=self.smaFast)
        self.sma200 = self.I(pta.sma, close, length=self.smaSlow)

        self.atr20 = self.I(pta.atr, high, low, close, length=self.atrFast)
        self.atr90 = self.I(pta.atr, high, low, close, length=self.atrSlow)

        self.volAvg = self.I(pta.sma, volume, length=self.volAvgLen)

        self.rsiVal = self.I(pta.rsi, close, length=self.rsiLen)

        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSig))
        self.macdLine = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSig)['MACD_12_26_9'] if pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSig) is not None else pd.Series(0, index=close.index))
        self.macdSignalLine = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSig)['MACDsh_12_26_9'] if pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSig) is not None else pd.Series(0, index=close.index))

        self.prev_regime = 0

    def next(self):
        if len(self.data) < self.smaSlow:
            return

        close_val = self.data.Close[-1]
        sma200_val = self.sma200[-1]
        sma50_val = self.sma50[-1]
        atr20_val = self.atr20[-1]
        atr90_val = self.atr90[-1]
        vol_val = self.data.Volume[-1]
        volAvg_val = self.volAvg[-1]
        rsi_val = self.rsiVal[-1]
        macd_val = self.macdLine[-1]
        signal_val = self.macdSignalLine[-1]

        smaRatio = sma50_val / sma200_val if sma200_val > 0 else 1.0
        smaSignal = 1.0 if smaRatio > 1.02 else -1.0 if smaRatio < 0.98 else 0.0

        volRatio = atr20_val / atr90_val if atr90_val > 0 else 1.0
        volSignal = -1.0 if volRatio > 1.5 else 1.0 if volRatio < 0.7 else 0.0

        volLevel = vol_val / volAvg_val if volAvg_val > 0 else 1.0
        volumeSignal = 1.0 if volLevel > 1.3 else -1.0 if volLevel < 0.7 else 0.0

        rsiSignal = 1.0 if rsi_val >= 50 and rsi_val <= self.rsiOB else -1.0 if rsi_val <= 50 and rsi_val >= self.rsiOS else 0.0

        macdSignal = 1.0 if macd_val > signal_val else -1.0 if macd_val < signal_val else 0.0

        fgDistance = ((close_val - sma200_val) / sma200_val) * 100 if sma200_val > 0 else 0.0
        fgValue = max(0, min(100, 50 + fgDistance * 2))
        fgSignal = 1.0 if fgValue >= 65 else -1.0 if fgValue <= 35 else 0.0

        totalWeight = self.w_sma + self.w_vol + self.w_volume + self.w_rsi + self.w_macd + self.w_fg
        safeWeight = totalWeight if totalWeight > 0 else 1.0

        bullScore = (max(0, smaSignal) * self.w_sma + max(0, volSignal) * self.w_vol + 
                     max(0, volumeSignal) * self.w_volume + max(0, rsiSignal) * self.w_rsi + 
                     max(0, macdSignal) * self.w_macd + max(0, fgSignal) * self.w_fg) / safeWeight

        bearScore = (max(0, -smaSignal) * self.w_sma + max(0, -volSignal) * self.w_vol + 
                     max(0, -volumeSignal) * self.w_volume + max(0, -rsiSignal) * self.w_rsi + 
                     max(0, -macdSignal) * self.w_macd + max(0, -fgSignal) * self.w_fg) / safeWeight

        netScore = bullScore - bearScore
        isBull = netScore > 0.2
        isBear = netScore < -0.2
        isChop = not isBull and not isBear

        regimeNum = 1 if isBull else -1 if isBear else 0
        regimeChanged = regimeNum != self.prev_regime

        if regimeChanged:
            if isBull and not self.position:
                self.buy()
            elif isBear and self.position:
                self.sell()

        self.prev_regime = regimeNum