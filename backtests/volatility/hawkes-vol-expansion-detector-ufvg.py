import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume analysis
        vol_len = 50
        vol_ma = self.I(pta.sma, volume, length=vol_len)
        vol_std = self.I(lambda: volume.rolling(vol_len).std())
        
        # Z-score calculation
        self.vol_zscore = self.I(lambda: (volume - vol_ma) / (vol_std + 1e-10))
        
        # ATR for displacement check
        atr_len = 14
        atr_mult = 0.8
        self.atr_val = self.I(pta.atr, high, low, close, length=atr_len)
        self.candle_range = self.I(lambda: (high - low).abs())
        
        # Hawkes process parameters
        mu_eff = 0.05
        alpha_eff = 0.15
        beta_eff = 0.08
        
        self.mu_eff = mu_eff
        self.alpha_eff = alpha_eff
        self.beta_eff = beta_eff
        self.atr_mult = atr_mult
        self.zscore_thr = 1.8
        self.elevated_thr = 0.15
        self.expansion_thr = 0.35
        
        # Initialize lambda tracking
        self.lambda_values = []
        self.excess_intensity_values = []
        self.shock_detected = []
        
    def next(self):
        # Check for shock event
        atr_ok = self.candle_range[-1] > self.atr_val[-1] * self.atr_mult
        is_shock = self.vol_zscore[-1] >= self.zscore_thr and atr_ok
        
        # Update lambda (Hawkes intensity)
        if len(self.lambda_values) == 0:
            lambda_t = self.mu_eff
        else:
            prev_lambda = self.lambda_values[-1]
            lambda_t = self.mu_eff + (prev_lambda - self.mu_eff) * np.exp(-self.beta_eff) + (self.alpha_eff if is_shock else 0.0)
        
        self.lambda_values.append(lambda_t)
        self.shock_detected.append(is_shock)
        
        # Calculate excess intensity
        excess_intensity = max(0, lambda_t - self.mu_eff)
        self.excess_intensity_values.append(excess_intensity)
        
        # Define zones
        zone_expansion = excess_intensity >= self.expansion_thr
        zone_elevated = excess_intensity >= self.elevated_thr and not zone_expansion
        
        # Entry/Exit logic
        # Buy on expansion zone entry
        if zone_expansion:
            if len(self.excess_intensity_values) >= 2:
                prev_excess = self.excess_intensity_values[-2]
                if prev_excess < self.expansion_thr:  # Just entered expansion
                    if not self.position:
                        self.buy()
        
        # Sell on elevated zone or calm zone
        if self.position:
            if not zone_expansion and not zone_elevated:  # Calm zone
                self.sell()
            elif is_shock and zone_expansion:  # Stay in expansion
                pass
            elif not zone_expansion:  # Exit expansion
                self.sell()


