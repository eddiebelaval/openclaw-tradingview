import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    smoothing = "RMA"
    multiplier = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate True Range
        def calc_tr():
            tr1 = high - low
            tr2 = np.abs(high - close.shift(1))
            tr3 = np.abs(low - close.shift(1))
            tr = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
            return tr
        
        true_range = self.I(calc_tr)
        
        # Calculate ATR with selected smoothing method
        def calc_atr():
            tr = calc_tr()
            if self.smoothing == "RMA":
                atr = pta.rma(tr, length=self.length)
            elif self.smoothing == "SMA":
                atr = pta.sma(tr, length=self.length)
            elif self.smoothing == "EMA":
                atr = pta.ema(tr, length=self.length)
            elif self.smoothing == "WMA":
                atr = pta.wma(tr, length=self.length)
            else:
                atr = pta.rma(tr, length=self.length)
            return atr if atr is not None else pd.Series(0, index=tr.index)
        
        self.atr = self.I(calc_atr)
        
        # Calculate bands
        def calc_upper():
            atr_val = calc_atr()
            upper = high + atr_val * self.multiplier
            return upper if atr_val is not None else high
        
        def calc_lower():
            atr_val = calc_atr()
            lower = low - atr_val * self.multiplier
            return lower if atr_val is not None else low
        
        self.upper_band = self.I(calc_upper)
        self.lower_band = self.I(calc_lower)
        
        # Track touchdowns for signal generation
        self.last_touch_upper = False
        self.last_touch_lower = False

    def next(self):
        # Detect touches/crossovers with bands
        if len(self.data) < 2:
            return
        
        current_close = self.data.Close[-1]
        current_upper = self.upper_band[-1]
        current_lower = self.lower_band[-1]
        
        # Upper band touch (potential short entry or long exit)
        touch_upper = (
            (self.data.Close[-2] < self.upper_band[-2] and current_close >= current_upper) or
            (self.data.Close[-2] > self.upper_band[-2] and current_close <= current_upper)
        )
        
        # Lower band touch (potential long entry or short exit)
        touch_lower = (
            (self.data.Close[-2] > self.lower_band[-2] and current_close <= current_lower) or
            (self.data.Close[-2] < self.lower_band[-2] and current_close >= current_lower)
        )
        
        # Simple trading logic based on band touches
        if touch_lower and not self.position:
            self.buy()
        elif touch_upper and self.position:
            self.sell()


