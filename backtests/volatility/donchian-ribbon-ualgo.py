import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    base_length = 20
    step_length = 5
    ribbon_count = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.channels = []
        
        for i in range(self.ribbon_count):
            length = self.base_length + (i * self.step_length)
            
            channel_high = self.I(
                lambda h=high, l=low, ln=length: h.rolling(ln).max()
            )
            channel_low = self.I(
                lambda h=high, l=low, ln=length: l.rolling(ln).min()
            )
            channel_mid = self.I(
                lambda ch=channel_high, cl=channel_low: (ch + cl) / 2
            )
            
            self.channels.append({
                'high': channel_high,
                'low': channel_low,
                'mid': channel_mid,
                'length': length
            })
        
        self.fast_high = self.channels[0]['high']
        self.fast_low = self.channels[0]['low']
        self.slow_high = self.channels[4]['high']
        self.slow_low = self.channels[4]['low']
        self.slow_mid = self.channels[4]['mid']

    def next(self):
        if len(self.data) < self.base_length + (self.ribbon_count - 1) * self.step_length:
            return
        
        current_price = self.data.Close[-1]
        slow_high = self.slow_high[-1]
        slow_low = self.slow_low[-1]
        slow_mid = self.slow_mid[-1]
        
        if not self.position:
            if current_price > slow_mid and current_price > slow_low:
                self.buy()
            elif current_price < slow_mid and current_price < slow_high:
                self.sell()
        else:
            if self.position.is_long:
                if current_price < slow_low or crossover(slow_mid, self.data.Close):
                    self.position.close()
            elif self.position.is_short:
                if current_price > slow_high or crossover(self.data.Close, slow_mid):
                    self.position.close()


