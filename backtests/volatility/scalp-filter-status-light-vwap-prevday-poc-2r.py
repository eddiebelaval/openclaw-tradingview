import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLen = 14
    atrMult = 1.3
    rr = 2.0
    profileLookbackBars = 200
    numBins = 40

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)

        # Store raw data for POC calculation
        self.close_data = close
        self.high_data = high
        self.low_data = low
        self.volume_data = volume

        # Initialize POC array
        self.poc_values = np.full(len(close), np.nan)
        self.vwap_values = np.full(len(close), np.nan)

        # Calculate VWAP
        self.vwap = self.I(self._calculate_vwap)

        # Calculate POC
        self.poc = self.I(self._calculate_poc)

        self.last_state = 0

    def _calculate_vwap(self):
        """Calculate VWAP anchored to daily sessions"""
        close = self.close_data
        high = self.high_data
        low = self.low_data
        volume = self.volume_data

        hlc3 = (high + low + close) / 3
        vwap_values = np.full(len(close), np.nan)

        current_day = None
        cum_pv = 0
        cum_vol = 0

        for i in range(len(close)):
            # Simple day detection: assume bars are chronological
            # In a real scenario, you'd parse timestamps
            day_idx = i // 288  # Assuming 288 bars per day (5-min bars)

            if day_idx != current_day:
                current_day = day_idx
                cum_pv = 0
                cum_vol = 0

            cum_pv += hlc3.iloc[i] * volume.iloc[i]
            cum_vol += volume.iloc[i]

            if cum_vol > 0:
                vwap_values[i] = cum_pv / cum_vol

        return pd.Series(vwap_values, index=close.index)

    def _calculate_poc(self):
        """Calculate Point of Control from previous day"""
        close = self.close_data
        high = self.high_data
        low = self.low_data
        volume = self.volume_data

        poc_values = np.full(len(close), np.nan)

        for current_idx in range(len(close)):
            # Get previous day's bars
            day_idx = current_idx // 288
            if day_idx == 0:
                continue

            prev_day_start = (day_idx - 1) * 288
            prev_day_end = day_idx * 288

            if prev_day_start < 0:
                continue

            prev_day_high = high.iloc[prev_day_start:prev_day_end].max()
            prev_day_low = low.iloc[prev_day_start:prev_day_end].min()

            if prev_day_high <= prev_day_low:
                poc_values[current_idx] = prev_day_low
                continue

            pd_span = prev_day_high - prev_day_low
            bin_size = pd_span / self.numBins
            vol_bins = np.zeros(self.numBins)

            # Distribute volume across bins
            for i in range(prev_day_start, prev_day_end):
                bar_low = low.iloc[i]
                bar_high = high.iloc[i]
                bar_vol = volume.iloc[i]

                if bar_vol <= 0:
                    continue

                lo = min(bar_low, bar_high)
                hi = max(bar_low, bar_high)
                bar_span = hi - lo

                if bar_span <= 0:
                    idx = int((lo - prev_day_low) / bin_size)
                    idx = max(0, min(self.numBins - 1, idx))
                    vol_bins[idx] += bar_vol
                else:
                    start_bin = int((lo - prev_day_low) / bin_size)
                    end_bin = int((hi - prev_day_low) / bin_size)
                    start_bin = max(0, min(self.numBins - 1, start_bin))
                    end_bin = max(0, min(self.numBins - 1, end_bin))

                    for b in range(start_bin, end_bin + 1):
                        bin_low = prev_day_low + b * bin_size
                        bin_high = prev_day_high if b == self.numBins - 1 else (bin_low + bin_size)
                        overlap = max(0.0, min(hi, bin_high) - max(lo, bin_low))

                        if overlap > 0:
                            contrib = bar_vol * (overlap / bar_span)
                            vol_bins[b] += contrib

            # Find POC
            max_vol_idx = np.argmax(vol_bins)
            poc_values[current_idx] = prev_day_low + (max_vol_idx + 0.5) * bin_size

        return pd.Series(poc_values, index=close.index)

    def next(self):
        if len(self.data) < self.atrLen + 1:
            return

        current_close = self.data.Close[-1]
        atr_val = self.atr[-1]
        vwap_val = self.vwap[-1]
        poc_val = self.poc[-1]

        if np.isnan(atr_val) or np.isnan(vwap_val) or np.isnan(poc_val):
            return

        stop_dist = atr_val * self.atrMult
        min_target_dist = self.rr * stop_dist

        has_data = not np.isnan(vwap_val) and not np.isnan(poc_val) and not np.isnan(min_target_dist)

        long_candidate = has_data and current_close < vwap_val and current_close < poc_val
        short_candidate = has_data and current_close > vwap_val and current_close > poc_val

        target_long = np.nan
        target_short = np.nan

        if has_data:
            target_long = min(vwap_val, poc_val)
            target_short = max(vwap_val, poc_val)

        long_dist = np.nan
        short_dist = np.nan

        if has_data:
            long_dist = target_long - current_close
            short_dist = current_close - target_short

        long_ok = long_candidate and not np.isnan(long_dist) and long_dist >= min_target_dist
        short_ok = short_candidate and not np.isnan(short_dist) and short_dist >= min_target_dist

        current_state = 1 if long_ok else (-1 if short_ok else 0)

        fire_long = current_state == 1 and self.last_state != 1
        fire_short = current_state == -1 and self.last_state != -1

        if fire_long:
            if not self.position:
                self.buy()
        elif fire_short:
            if self.position:
                self.sell()

        self.last_state = current_state