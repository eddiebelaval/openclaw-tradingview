import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrPeriod = 10
    multiplier = 3.0
    useRmaAtr = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hl2 = (high + low) / 2
        
        # Calculate True Range
        tr = pta.true_range(high, low, close)
        
        # Calculate ATR values
        if self.useRmaAtr:
            atr_vals = pta.atr(high, low, close, length=self.atrPeriod)
        else:
            atr_vals = pta.sma(tr, length=self.atrPeriod)
        
        # Store for use in next()
        self.atr_vals = self.I(lambda: atr_vals if atr_vals is not None else pd.Series(0, index=close.index))
        self.hl2 = self.I(lambda: hl2)
        self.close_series = close
        self.high_series = high
        self.low_series = low

    def next(self):
        if len(self.data) < 2:
            return
        
        close = self.close_series
        atr_val = self.atr_vals[-1] if len(self.atr_vals) > 0 else 0
        hl2_val = self.hl2[-1] if len(self.hl2) > 0 else 0
        
        # Calculate bands
        upper_band = hl2_val - (self.multiplier * atr_val)
        lower_band = hl2_val + (self.multiplier * atr_val)
        
        # Get previous values from history
        if len(self.data) >= 2:
            prev_close = close.iloc[-2]
            
            # Initialize trend tracking
            if not hasattr(self, 'trend'):
                self.trend = 1
                self.prev_upper = upper_band
                self.prev_lower = lower_band
            
            # Update bands based on previous close
            if prev_close > self.prev_upper:
                self.prev_upper = max(upper_band, self.prev_upper)
            else:
                self.prev_upper = upper_band
            
            if prev_close < self.prev_lower:
                self.prev_lower = min(lower_band, self.prev_lower)
            else:
                self.prev_lower = lower_band
            
            # Update trend
            prev_trend = self.trend
            if self.trend == -1 and close.iloc[-1] > self.prev_lower:
                self.trend = 1
            elif self.trend == 1 and close.iloc[-1] < self.prev_upper:
                self.trend = -1
            
            # Generate signals
            buy_signal = (self.trend == 1 and prev_trend == -1)
            sell_signal = (self.trend == -1 and prev_trend == 1)
            
            # Execute trades
            if buy_signal:
                if not self.position:
                    self.buy()
            elif sell_signal:
                if self.position:
                    self.sell()