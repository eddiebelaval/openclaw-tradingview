class TvStrategy(Strategy):
    # Input parameters from Pine Script
    swingLen = 5
    atrLen = 14
    volLen = 20
    compLen = 10
    momLen = 20
    dispATRmult = 1.2
    volSpikeMult = 1.5
    compFactor = 0.85
    bodyMinPct = 60.0
    scoreTrigger = 7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # Core calculations
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.volMA = self.I(pta.sma, volume, length=self.volLen)
        
        # Candle metrics
        self.candleRange = self.I(lambda: high - low)
        self.candleBody = self.I(lambda: np.abs(close - open_))
        self.bodyPct = self.I(lambda: np.where(self.candleRange[-len(close):] > 0, 
                                                (self.candleBody[-len(close):] / self.candleRange[-len(close):]) * 100.0, 0.0))
        
        # Bullish/bearish candles
        self.bullCandle = self.I(lambda: close > open_)
        self.bearCandle = self.I(lambda: close < open_)
        
        # Displacement logic
        self.bullDisplacement = self.I(lambda: (self.bullCandle[-len(close):]) & 
                                               (self.candleRange[-len(close):] > self.atr[-len(close):] * self.dispATRmult) & 
                                               (self.bodyPct[-len(close):] >= self.bodyMinPct))
        self.bearDisplacement = self.I(lambda: (self.bearCandle[-len(close):]) & 
                                               (self.candleRange[-len(close):] > self.atr[-len(close):] * self.dispATRmult) & 
                                               (self.bodyPct[-len(close):] >= self.bodyMinPct))
        
        # Volume spike
        self.volSpike = self.I(lambda: volume > self.volMA[-len(volume):] * self.volSpikeMult)
        
        # Pivot points for swing structure
        self.lastSwingHigh = self.I(lambda: self._get_pivot_high(high, self.swingLen))
        self.lastSwingLow = self.I(lambda: self._get_pivot_low(low, self.swingLen))
        
        # Breakout of structure
        self.bullBOS = self.I(lambda: (self.lastSwingHigh[-len(close):] != 0) & (close > self.lastSwingHigh[-len(close):]))
        self.bearBOS = self.I(lambda: (self.lastSwingLow[-len(close):] != 0) & (close < self.lastSwingLow[-len(close):]))
        
        # Compression
        self.avgBarRange = self.I(pta.sma, self.candleRange[-len(close):], length=self.compLen)
        self.avgATR = self.I(pta.sma, self.atr, length=self.compLen)
        self.compression = self.I(lambda: self.avgBarRange[-len(close):] < self.avgATR[-len(close):] * self.compFactor)
        
