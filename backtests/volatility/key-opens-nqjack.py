import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from datetime import datetime, timedelta


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        if len(self.data) < 2:
            return
        
        current_time = pd.Timestamp(self.data.index[-1])
        current_hour = current_time.hour
        current_minute = current_time.minute
        
        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        open_price = self.data.Open[-1]
        
        if not self.position:
            if (current_hour == 10 and current_minute == 0):
                self.buy()
        else:
            if (current_hour == 16 and current_minute == 0):
                self.sell()


def run_backtest():
    df = pd.read_csv('data.csv', index_col='time', parse_dates=True)
    
