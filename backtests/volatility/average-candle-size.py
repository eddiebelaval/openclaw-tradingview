import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate candle sizes (high - low) shifted by 1 bar
        candle_size = high - low
        candle_size_prev = candle_size.shift(1)
        
        # Calculate averages of previous candle sizes
        self.avg26 = self.I(lambda: pta.sma(candle_size_prev, length=26))
        self.avg52 = self.I(lambda: pta.sma(candle_size_prev, length=52))
        
        # Calculate stop loss levels
        self.stopLoss = self.I(lambda: self.avg26 + self.avg52 if (self.avg26 is not None and self.avg52 is not None) else pd.Series(0, index=close.index))
        
        # SL levels based on previous candle
        high_prev = high.shift(1)
        low_prev = low.shift(1)
        self.slUpper = self.I(lambda: high_prev + self.stopLoss if self.stopLoss is not None else high_prev)
        self.slLower = self.I(lambda: low_prev - self.stopLoss if self.stopLoss is not None else low_prev)

    def next(self):
        # Simple trading logic based on stop loss levels
        # Buy when price touches lower SL level and is reverting upward
        if len(self.data) > 52:
            current_close = self.data.Close[-1]
            current_low = self.data.Low[-1]
            sl_lower_val = self.slLower[-1]
            sl_upper_val = self.slUpper[-1]
            
            # Buy signal: price touches lower SL and closes above it
            if not self.position:
                if current_low <= sl_lower_val and current_close > sl_lower_val:
                    self.buy()
            else:
                # Sell signal: price reaches upper SL level
                if current_close >= sl_upper_val:
                    self.sell()