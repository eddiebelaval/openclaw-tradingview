import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenShortInput = 13
    lenLongInput = 63
    lenVolInput = 50
    sensitivity = 2.0
    trendPenaltyWeight = 1.0
    hlLookbackInput = 63
    penaltyFactor = 0.75
    bonusMax = 15
    thHigh = 80
    thLow = 60

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Helper to calculate True Range
        def calc_tr():
            tr1 = high - low
            tr2 = np.abs(high - close.shift(1))
            tr3 = np.abs(low - close.shift(1))
            return pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
        
        # A. Price Compression (SMA Base)
        tr = self.I(calc_tr)
        tr_short = self.I(lambda: pta.sma(tr, length=self.lenShortInput) or pd.Series(0, index=close.index))
        tr_long_avg = self.I(lambda: pta.sma(tr, length=self.lenLongInput) or pd.Series(0, index=close.index))
        self.ratio_atr = self.I(lambda: tr_short / (tr_long_avg.replace(0, 0.000001)))
        
        # B. Price Stability (SMA Base)
        std_short = self.I(lambda: close.rolling(self.lenShortInput).std() or pd.Series(0, index=close.index))
        std_long_avg = self.I(lambda: close.rolling(self.lenLongInput).std() or pd.Series(0, index=close.index))
        self.ratio_std = self.I(lambda: std_short / (std_long_avg.replace(0, 0.000001)))
        
        # C. Volume Contraction
        vol_avg = self.I(lambda: pta.sma(volume, length=self.lenVolInput) or pd.Series(1, index=close.index))
        vol_short_avg = self.I(lambda: pta.sma(volume, length=5) or pd.Series(1, index=close.index))
        self.vol_ratio = self.I(lambda: vol_short_avg / (vol_avg.replace(0, 1.0)))
        
        # D. Efficiency Filter
        def calc_efficiency():
            net_change = (close - close.shift(self.lenShortInput)).abs()
            total_travel = tr.rolling(self.lenShortInput).sum()
            return net_change / (total_travel.replace(0, 0.000001))
        
        efficiency = self.I(calc_efficiency)
        self.trend_factor = self.I(lambda: np.maximum(0.0, 1.0 - (efficiency * self.trendPenaltyWeight)))
        
        # E. Structure Check
        def calc_is_higher_low():
            low_recent = low.rolling(self.lenShortInput).min()
            low_base = low.shift(self.lenShortInput).rolling(self.hlLookbackInput).min()
            return low_recent >= low_base
        
        self.is_higher_low = self.I(calc_is_higher_low)
        
        # Score Calculation
        def calc_final_score():
            s_atr = np.maximum(0.0, 1.0 - self.ratio_atr.fillna(1.0)) * self.sensitivity
            s_std = np.maximum(0.0, 1.0 - self.ratio_std.fillna(1.0)) * self.sensitivity
            s_vol = np.maximum(0.0, 1.0 - self.vol_ratio.fillna(1.0))
            
            raw_score = (s_atr * 0.4) + (s_std * 0.4) + (s_vol * 0.2)
            filtered_score = raw_score * self.trend_factor
            physics_score = np.minimum(100, filtered_score * 100)
            
            smooth_physics = pta.ema(physics_score, length=3)
            if smooth_physics is None:
                smooth_physics = pd.Series(0, index=close.index)
            
            is_tight = smooth_physics >= 70
            
            days_tight = pd.Series(0, index=close.index)
            for i in range(len(days_tight)):
                if i == 0:
                    days_tight.iloc[i] = 1 if is_tight.iloc[i] else 0
                else:
                    days_tight.iloc[i] = (days_tight.iloc[i-1] + 1) if is_tight.iloc[i] else 0
            
            weight_physics = (100.0 - self.bonusMax) / 100.0
            weighted_physics_score = smooth_physics * weight_physics
            consistency_score = np.minimum(self.bonusMax, days_tight)
            total_score = weighted_physics_score + consistency_score
            final_score = np.where(self.is_higher_low, total_score, total_score * self.penaltyFactor)
            final_score = final_score.fillna(0.0)
            
            return final_score
        
        self.final_score = self.I(calc_final_score)

    def next(self):
        if len(self.data) < 2:
            return
        
        current_score = self.final_score[-1]
        prev_score = self.final_score[-2] if len(self.final_score) > 1 else current_score
        
        # Buy when score crosses above thLow
        if crossover(self.final_score, self.thLow):
            if not self.position:
                self.buy()
        
        # Sell when score crosses below thLow
        elif self.final_score[-1] < self.thLow and self.position:
            self.sell()


