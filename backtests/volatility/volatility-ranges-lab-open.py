import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adr_period = 5
    awr_period = 13
    amr_period = 6

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.daily_adr = self.I(lambda: self._calculate_adr(high, low, close, self.adr_period))
        self.weekly_adr = self.I(lambda: self._calculate_adr(high, low, close, self.awr_period))
        self.monthly_adr = self.I(lambda: self._calculate_adr(high, low, close, self.amr_period))

    def _calculate_adr(self, high, low, close, period):
        tr = pd.Series(index=close.index, dtype=float)
        for i in range(len(close)):
            if i == 0:
                tr.iloc[i] = high.iloc[i] - low.iloc[i]
            else:
                tr.iloc[i] = max(
                    high.iloc[i] - low.iloc[i],
                    abs(high.iloc[i] - close.iloc[i - 1]),
                    abs(low.iloc[i] - close.iloc[i - 1])
                )
        return pta.sma(tr, length=period)

    def next(self):
        if len(self.data) < 2:
            return

        daily_adr = self.daily_adr[-1] if not pd.isna(self.daily_adr[-1]) else 0
        weekly_adr = self.weekly_adr[-1] if not pd.isna(self.weekly_adr[-1]) else 0
        monthly_adr = self.monthly_adr[-1] if not pd.isna(self.monthly_adr[-1]) else 0

        current_price = self.data.Close[-1]
        previous_price = self.data.Close[-2]

        volatility_score = (daily_adr / current_price if current_price > 0 else 0) * 100

        if not self.position:
            if daily_adr > 0 and volatility_score < 2 and current_price > previous_price:
                self.buy()
        else:
            if daily_adr > 0 and volatility_score > 4:
                self.position.close()
            elif current_price < previous_price and volatility_score > 3:
                self.position.close()