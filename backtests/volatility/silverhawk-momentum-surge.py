import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    roc_length = 9
    momentum_threshold = 0.5
    atr_length = 14
    atr_sma_length = 20
    candle_strength_multiplier = 0.6

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # ROC of RSI
        self.roc_rsi = self.I(pta.roc, self.rsi, length=self.roc_length)
        
        # ATR and ATR SMA
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        self.atr_sma = self.I(pta.sma, self.atr, length=self.atr_sma_length)
        
        # Candle body size
        self.body_size = self.I(lambda: np.abs(close - open_))

    def next(self):
        if len(self.data) < max(self.rsi_length, self.roc_length, self.atr_length, self.atr_sma_length):
            return
        
        # Check volatility expanding
        volatility_expanding = self.atr[-1] > self.atr_sma[-1] if self.atr[-1] is not None and self.atr_sma[-1] is not None else False
        
        # Check candle strength
        is_strong_candle = self.body_size[-1] > (self.candle_strength_multiplier * self.atr[-1]) if self.body_size[-1] is not None and self.atr[-1] is not None else False
        
        # Check candle direction
        is_bullish_candle = self.data.Close[-1] > self.data.Open[-1] and is_strong_candle
