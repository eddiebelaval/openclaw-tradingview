import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Session and timing parameters
    ny_open_start_hour = 9
    ny_open_start_min = 30
    ny_open_end_hour = 9
    ny_open_end_min = 45
    
    # Breakout/Retest parameters
    breakout_buffer_ticks = 0
    retest_buffer_ticks = 4
    min_retest_bars = 1
    max_retest_bars = 20
    max_confirm_bars = 12
    
    # Indecision/Consolidation parameters
    indecision_body_frac = 0.30
    narrow_lookback = 10
    narrow_range_factor = 0.80
    min_pause_bars = 1
    
    # Confirmation parameters
    confirm_body_frac = 0.55
    
    # Risk/Reward parameters
    swing_len = 1
    rr_multiple = 1.5
    
    def init(self):
        self.state = 0
        self.or_high = None
        self.or_low = None
        self.breakout_dir = 0
        self.breakout_level = None
        self.breakout_bar = None
        self.retest_bar = None
        self.pause_bars = 0
        self.retest_low = None
        self.retest_high = None
        self.entry_price = None
        self.stop_price = None
        self.target_price = None
        self.last_swing_low = None
        self.last_swing_high = None
        self.current_ny_day = None
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.avg_range = self.I(lambda: pta.sma(high - low, length=self.narrow_lookback) if len(high) >= self.narrow_lookback else pd.Series(np.nan, index=high.index))
        
        self.pivot_low = self.I(lambda: self._calc_pivot_low(low))
        self.pivot_high = self.I(lambda: self._calc_pivot_high(high))
    
    def _calc_pivot_low(self, low):
        result = pd.Series(np.nan, index=low.index)
        for i in range(self.swing_len, len(low) - self.swing_len):
            if low.iloc[i] == low.iloc[i - self.swing_len:i + self.swing_len + 1].min():
                result.iloc[i] = low.iloc[i]
        return result
    
    def _calc_pivot_high(self, high):
        result = pd.Series(np.nan, index=high.index)
        for i in range(self.swing_len, len(high) - self.swing_len):
            if high.iloc[i] == high.iloc[i - self.swing_len:i + self.swing_len + 1].max():
                result.iloc[i] = high.iloc[i]
        return result
    
    def _get_ny_datetime(self):
        try:
            from datetime import datetime
            idx = len(self.data) - 1
            ts = self.data.index[idx]
            if hasattr(ts, 'tz_localize'):
                return pd.Timestamp(ts, tz='America/New_York')
            return pd.Timestamp(ts, tz='America/New_York') if ts.tz is None else ts.tz_convert('America/New_York')
        except:
            return None
    
    def _is_in_opening_range(self, ny_time):
        if ny_time is None:
            return False
        return (ny_time.hour == self.ny_open_start_hour and ny_time.minute >= self.ny_open_start_min) or \
               (ny_time.hour == self.ny_open_end_hour and ny_time.minute < self.ny_open_end_min)
    
    def _get_ny_day_id(self, ny_time):
        if ny_time is None:
            return None
        return ny_time.year * 10000 + ny_time.month * 100 + ny_time.day
    
    def _is_doji_like(self, body, bar_range):
        return body <= bar_range * self.indecision_body_frac
    
    def _is_inside_bar(self, high, high_prev, low, low_prev):
        return high <= high_prev and low >= low_prev
    
    def _is_narrow_bar(self, bar_range, avg_range):
        if pd.isna(avg_range):
            return False
        return bar_range <= avg_range * self.narrow_range_factor
    
    def _is_pause_bar(self, high, high_prev, low, low_prev, bar_range, avg_range, body):
        doji = self._is_doji_like(body, bar_range)
        inside = self._is_inside_bar(high, high_prev, low, low_prev)
        narrow = self._is_narrow_bar(bar_range, avg_range)
        return doji or inside or narrow
    
    def _bullish_engulfing(self, close, open_, close_prev, open_prev):
        return close > open_ and close_prev < open_prev and close >= open_prev and open_ <= close_prev
    
    def _bearish_engulfing(self, close, open_, close_prev, open_prev):
        return close < open_ and close_prev > open_prev and close <= open_prev and open_ >= close_prev
    
    def _strong_bull_confirm(self, close, open_, high_prev, bar_range):
        body = abs(close - open_)
        return close > open_ and body >= bar_range * self.confirm_body_frac and close > high_prev
    
    def _strong_bear_confirm(self, close, open_, low_prev, bar_range):
        body = abs(close - open_)
        return close < open_ and body >= bar_range * self.confirm_body_frac and close < low_prev
    
    def _overlaps_level(self, high, low, level, buffer):
        return high >= level - buffer and low <= level + buffer
    
