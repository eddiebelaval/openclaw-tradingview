import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Volatility settings
    hv14_length = 14
    hv30_length = 30
    hv7_length = 7
    
    # Trend line settings
    tl_short_period = 10
    tl_long_period = 16
    
    # Display settings
    label_proximity = 200.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate historical volatility (HV) using log returns
        def calc_hv(src, length, annual_factor=365.0):
            log_returns = np.log(src / src.shift(1))
            pop_stdev = log_returns.rolling(length).std()
            sample_correction = np.sqrt(length / (length - 1.0))
            hv = pop_stdev * sample_correction * np.sqrt(annual_factor) * 100.0
            return hv
        
        # Calculate HV14, HV30, HV7
        self.hv14 = self.I(lambda: calc_hv(close, self.hv14_length))
        self.hv30 = self.I(lambda: calc_hv(close, self.hv30_length))
        self.hv7 = self.I(lambda: calc_hv(close, self.hv7_length))
        
        # Calculate highest and lowest for pivot detection
        def get_highest(src, period):
            return src.rolling(period).max()
        
        def get_lowest(src, period):
            return src.rolling(period).min()
        
        self.highest_short = self.I(lambda: get_highest(high, self.tl_short_period))
        self.lowest_short = self.I(lambda: get_lowest(low, self.tl_short_period))
        self.highest_long = self.I(lambda: get_highest(high, self.tl_long_period))
        self.lowest_long = self.I(lambda: get_lowest(low, self.tl_long_period))
        
        # Simple volatility regime indicator
        # Buy when HV7 is low relative to HV14, sell when high
        self.hv_ratio = self.I(lambda: (self.hv7 / self.hv14.fillna(self.hv7)) if isinstance(self.hv14, pd.Series) else pd.Series(1.0, index=close.index))

    def next(self):
        # Guard against insufficient data
        if len(self.data) < max(self.hv14_length, self.hv30_length, self.tl_long_period) + 5:
            return
        
        # Get current values
        current_hv7 = self.hv7[-1] if not np.isnan(self.hv7[-1]) else None
        current_hv14 = self.hv14[-1] if not np.isnan(self.hv14[-1]) else None
        current_hv30 = self.hv30[-1] if not np.isnan(self.hv30[-1]) else None
        
        # Check for valid data
        if current_hv7 is None or current_hv14 is None:
            return
        
        # Trading logic based on volatility regimes
        # Buy signal: volatility is low (HV7 < HV14) and trending up, or HV7 crosses below HV14
        # Sell signal: volatility is high (HV7 > HV14) or HV7 crosses above HV14
        
        if len(self.data) >= 2:
            prev_hv7 = self.hv7[-2] if not np.isnan(self.hv7[-2]) else current_hv7
            prev_hv14 = self.hv14[-2] if not np.isnan(self.hv14[-2]) else current_hv14
            
            # Crossover conditions
            hv7_crosses_below_hv14 = prev_hv7 >= prev_hv14 and current_hv7 < current_hv14
            hv7_crosses_above_hv14 = prev_hv7 <= prev_hv14 and current_hv7 > current_hv14
            
            # Buy when HV7 crosses below HV14 (volatility compression)
            if hv7_crosses_below_hv14 and not self.position:
                self.buy()
            
            # Sell when HV7 crosses above HV14 (volatility expansion) or position takes profit
            elif hv7_crosses_above_hv14 and self.position:
                self.position.close()
            
            # Also use absolute volatility levels
            # Sell if volatility gets too high (above 70th percentile historically)
            elif self.position and current_hv14 > 60:
                self.position.close()
            
            # Alternative: buy if HV7 is low (below 20) and not already in position
            elif not self.position and current_hv7 < 20 and current_hv14 > current_hv7:
                self.buy()


