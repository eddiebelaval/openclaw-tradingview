import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 20
    horizonInput = 10
    volLookbackInput = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Upper and lower range (Donchian Channel)
        self.upperRange = self.I(lambda: high.rolling(self.lengthInput).max())
        self.lowerRange = self.I(lambda: low.rolling(self.lengthInput).min())
        
        # Calculate log returns
        def calc_log_returns():
            returns = np.log(close / close.shift(1))
            return returns
        
        log_returns = self.I(calc_log_returns)
        
        # Volatility (standard deviation of log returns)
        self.sigma = self.I(lambda: log_returns.rolling(self.volLookbackInput).std())
        
        # ATR and average ATR for squeeze calculation
        atr = self.I(pta.atr, high, low, close, length=14)
        self.avgAtr = self.I(lambda: atr.rolling(100).mean())
        
        # Bias tracking
        self.bullProb = None
        self.bearProb = None

    def next(self):
        if len(self.data) < max(self.lengthInput, self.volLookbackInput):
            return
        
        close_val = self.data.Close[-1]
        upper_range = self.upperRange[-1]
        lower_range = self.lowerRange[-1]
        sigma_val = self.sigma[-1]
        atr_val = self.avgAtr[-1]
        
        if pd.isna(upper_range) or pd.isna(lower_range) or pd.isna(sigma_val) or sigma_val <= 0:
            return
        
        # Calculate probabilities using Normal CDF approximation
        horizon_sqrt = np.sqrt(self.horizonInput)
        denominator = sigma_val * horizon_sqrt
        
        if denominator > 0:
            z_upper = np.log(upper_range / close_val) / denominator
            z_lower = np.log(lower_range / close_val) / denominator
            
            self.bullProb = (1.0 - self._norm_cdf(z_upper)) * 100
            self.bearProb = self._norm_cdf(z_lower) * 100
        else:
            self.bullProb = 50.0
            self.bearProb = 50.0
        
        # Check for breakout signals
        bull_signal = self.bullProb > 50
        bear_signal = self.bearProb > 50
        
        # Volatility squeeze
        if pd.notna(atr_val) and atr_val > 0:
            squeeze = max(0, 1 - atr_val / atr_val) * 100
        else:
            squeeze = 0
        
        # Entry/exit logic
        if bull_signal and not self.position:
            self.buy()
        elif bear_signal and self.position:
            self.sell()

    def _norm_cdf(self, x):
        """Abramowitz & Stegun normal CDF approximation"""
        t = 1.0 / (1.0 + 0.2316419 * abs(x))
        d = 0.3989423 * np.exp(-x * x / 2.0)
        p = d * t * (0.3193815 + t * (-0.3565638 + t * (1.7814779 + t * (-1.821256 + t * 1.3302744))))
        return 1.0 - p if x > 0 else p


