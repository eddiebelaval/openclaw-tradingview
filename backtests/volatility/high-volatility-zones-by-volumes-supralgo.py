import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_smooth = "SMA"
    ma_length = 200
    multiplier_vol = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Calculate volume moving average (SMA or EMA)
        if self.ma_smooth == "EMA":
            ma_vol = self.I(pta.ema, volume, length=self.ma_length)
        else:
            ma_vol = self.I(pta.sma, volume, length=self.ma_length)
        
        # Apply multiplier to get final MA threshold
        self.ma_vol_final = self.I(lambda: ma_vol * self.multiplier_vol)
        
        # Check if volume is above the weighted moving average
        self.is_valid_ma = self.I(lambda: volume >= self.ma_vol_final)

    def next(self):
        # Buy when volume crosses above the moving average threshold (high volatility zone detected)
        if len(self.data) > self.ma_length:
            # Check for crossover: volume going from below to above ma_vol_final
            if self.is_valid_ma[-1] and not self.is_valid_ma[-2]:
                if not self.position:
                    self.buy()
            
            # Sell when volume crosses below the moving average threshold
            elif not self.is_valid_ma[-1] and self.is_valid_ma[-2]:
                if self.position:
                    self.position.close()