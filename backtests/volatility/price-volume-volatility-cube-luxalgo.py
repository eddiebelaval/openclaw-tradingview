import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback_period = 100
    cube_size = 50
    x_offset = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate True Range manually
        tr = pd.Series(0.0, index=close.index)
        for i in range(1, len(close)):
            tr.iloc[i] = max(
                high.iloc[i] - low.iloc[i],
                abs(high.iloc[i] - close.iloc[i-1]),
                abs(low.iloc[i] - close.iloc[i-1])
            )
        
        # Calculate rolling min/max for normalization
        self.lowest_price = self.I(lambda: close.rolling(self.lookback_period).min())
        self.highest_price = self.I(lambda: close.rolling(self.lookback_period).max())
        self.lowest_volume = self.I(lambda: volume.rolling(self.lookback_period).min())
        self.highest_volume = self.I(lambda: volume.rolling(self.lookback_period).max())
        self.lowest_tr = self.I(lambda: tr.rolling(self.lookback_period).min())
        self.highest_tr = self.I(lambda: tr.rolling(self.lookback_period).max())
        
        # Store raw series for calculations
        self.close_series = close
        self.volume_series = volume
        self.tr_series = tr
        self.high_series = high
        self.low_series = low

    def next(self):
        # Get current index
        idx = len(self.data) - 1
        
        # Check if we have enough data
        if idx < self.lookback_period:
            return
        
        # Get normalization ranges
        price_range = self.highest_price[-1] - self.lowest_price[-1]
        volume_range = self.highest_volume[-1] - self.lowest_volume[-1]
        tr_range = self.highest_tr[-1] - self.lowest_tr[-1]
        
        # Normalize current values
        if price_range == 0:
            norm_price = 0.5
        else:
            norm_price = (self.data.Close[-1] - self.lowest_price[-1]) / price_range
        
        if volume_range == 0:
            norm_volume = 0.5
        else:
            norm_volume = (self.data.Volume[-1] - self.lowest_volume[-1]) / volume_range
        
        if tr_range == 0:
            norm_tr = 0.5
        else:
            norm_tr = (self.tr_series.iloc[idx] - self.lowest_tr[-1]) / tr_range
        
        # Trading logic based on normalized 3D cube coordinates
        # Buy signal: when price is in upper half (bullish) AND volume is above median
        # Sell signal: when price is in lower half (bearish) AND volume is above median
        
        if norm_price > 0.6 and norm_volume > 0.5:
            if not self.position:
                self.buy()
        elif norm_price < 0.4 and norm_volume > 0.5:
            if self.position:
                self.sell()
        elif norm_price < 0.3:
            if self.position:
                self.sell()
        elif norm_price > 0.7 and norm_tr > 0.6:
            if not self.position:
                self.buy()


