        is_ny_session = (current_hour == 23 and current_minute >= 0 and current_minute < 56)
        
        # Detect session start
        if is_ny_session and not self.in_session:
            self.in_session = True
            self.midnight_high = self.data.High[-1]
            self.midnight_low = self.data.Low[-1]
            self.start_bar = len(self.data) - 1
            self.session_start_idx = len(self.data) - 1
        
        # Update range during session
        if is_ny_session and self.in_session:
            self.midnight_high = max(self.midnight_high, self.data.High[-1])
            self.midnight_low = min(self.midnight_low, self.data.Low[-1])
        
