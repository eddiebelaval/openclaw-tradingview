            df = pd.DataFrame({
                'High': high,
                'Low': low,
                'Close': close
            })
            
            tr = pd.Series(0.0, index=df.index)
            tr = np.maximum(
                df['High'] - df['Low'],
                np.maximum(
                    np.abs(df['High'] - df['Close'].shift(1)),
                    np.abs(df['Low'] - df['Close'].shift(1))
                )
            )
            
            if self.useRMAatr:
                atr_val = pta.atr(df['High'], df['Low'], df['Close'], length=self.atrPeriod)
