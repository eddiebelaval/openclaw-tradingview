        trend_score = 0.0
        if bull_stack:
            trend_score += 1.50
        if sep_ok:
            trend_score += 0.90
        if slope_ok:
            trend_score += 1.10
        if eff_ok:
            trend_score += 1.00
        if atr_ok:
            trend_score += 0.80
        if mom_ok:
            trend_score += 1.00
        if breakout_ok:
            trend_score += 1.25
        if reclaim_ok:
            trend_score += 1.10
        
        # Entry models
        trend_continuation = bull_stack and breakout_ok and slope_ok and eff_ok and mom_ok
        pullback_reentry = bull_stack and sep_ok and slope_ok and deep_enough_pullback and reclaim_ok and eff_ok
        early_trend = bull_stack and sep_ok and slope_ok and atr_ok and mom_ok
        
        # Cooldown
        cooldown_ok = len(self.data) - self.last_exit_bar > self.cooldownBars
        
        # Entry condition
        can_enter = self.position.size == 0 and cooldown_ok and trend_score >= self.minScore and close > slow and (trend_continuation or pullback_reentry or early_trend)
        
        if can_enter:
            equity = self.equity
            position_value = equity * self.leverage
            qty = position_value / close if close > 0 else 0
            if qty > 0:
                self.buy(size=min(qty, self.equity * self.leverage / close / 2))
                self.entry_bar_index = len(self.data) - 1
        
        # Exit logic
        can_exit_now = self.position.size > 0 and len(self.data) - 1 > self.entry_bar_index
        
        if self.position.size > 0:
            if not np.isnan(self.high_since_entry):
                self.high_since_entry = max(self.high_since_entry, high)
            else:
                self.high_since_entry = high
        
        # Risk stops
        hard_stop_price = self.position.avg_price * (1 - self.hardStopPerc / 100) if self.position.size > 0 else np.nan
        
        raw_trail = close - atr * self.trailAtrMult if self.position.size > 0 and atr != 0 else np.nan
        profit_lock = self.high_since_entry - atr * self.profitLockAtrMult if self.position.size > 0 and not np.isnan(self.high_since_entry) else np.nan
        
        if self.position.size > 0:
            if not np.isnan(raw_trail):
                combined_trail = max(raw_trail, profit_lock) if not np.isnan(profit_lock) else raw_trail
            else:
                combined_trail = np.nan
            
            if not np.isnan(combined_trail):
                if np.isnan(self.trail_stop):
                    self.trail_stop = combined_trail
                else:
                    self.trail_stop = max(self.trail_stop, combined_trail)
        
        # Exit signals
        bear_cross = (self.fast[-2] > self.mid[-2] and fast < mid) or (self.fast[-2] > self.slow[-2] and fast < slow)
        structure_break = close < mid and fast < mid
        score_weak = trend_score <= self.exitScore
        momentum_failure = persist_ratio < 0.40 and mom_raw < 0
        regime_failure = atr_regime < 0.80 and efficiency < 0.25
        
        exit_long = can_exit_now and (bear_cross or structure_break or score_weak or momentum_failure or regime_failure)
        
        if exit_long and self.position.size > 0:
            self.position.close()
            self.last_exit_bar = len(self.data) - 1
            self.trail_stop = np.nan
            self.high_since_entry = np.nan
            self.entry_bar_index = -1
        elif can_exit_now and self.position.size > 0:
            if not np.isnan(self.trail_stop) and close <= self.trail_stop:
                self.position.close()
                self.last_exit_bar = len(self.data) - 1
                self.trail_stop = np.nan
                self.high_since_entry = np.nan
                self.entry_bar_index = -1


