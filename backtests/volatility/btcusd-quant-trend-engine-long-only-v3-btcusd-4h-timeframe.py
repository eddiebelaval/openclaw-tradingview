import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 18
    midLen = 50
    slowLen = 120
    smoothLen = 3
    pullbackLen = 8
    breakoutLen = 20
    effLen = 18
    persistLen = 7
    momLen = 12
    slopeLen = 10
    atrLen = 14
    atrBaseLen = 40
    
    minScore = 5.0
    exitScore = 2.5
    minSepPerc = 0.30
    minSlowSlopePerc = 0.03
    minEff = 0.33
    minAtrRegime = 0.95
    minBreakoutAtr = 0.15
    pullbackAtrMult = 0.90
    reclaimAtrMult = 0.15
    cooldownBars = 5
    
    leverage = 3.0
    hardStopPerc = 2.0
    trailAtrMult = 2.8
    profitLockAtrMult = 20.8

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Smoothed EMAs
        fast_ema = self.I(lambda: pta.ema(pta.ema(close, length=self.fastLen), length=self.smoothLen))
        mid_ema = self.I(lambda: pta.ema(pta.ema(close, length=self.midLen), length=self.smoothLen))
        slow_ema = self.I(lambda: pta.ema(pta.ema(close, length=self.slowLen), length=self.smoothLen))
        
        self.fast = fast_ema
        self.mid = mid_ema
        self.slow = slow_ema
        
        # ATR and volatility
        atr = self.I(lambda: pta.atr(high, low, close, length=self.atrLen) or pd.Series(0, index=close.index))
        atr_base = self.I(lambda: pta.sma(atr, length=self.atrBaseLen) or pd.Series(1, index=close.index))
        self.atr = atr
        self.atr_base = atr_base
        
        # Highest high for breakout
        highest_high = self.I(lambda: high.rolling(self.breakoutLen).max() or pd.Series(high, index=high.index))
        self.highest_high = highest_high
        
        # Lowest low for pullback
        lowest_low = self.I(lambda: low.rolling(self.pullbackLen).min() or pd.Series(low, index=low.index))
        self.lowest_low = lowest_low
        
        self.last_exit_bar = -np.inf
        self.entry_bar_index = -1
        self.trail_stop = np.nan
        self.high_since_entry = np.nan

    def next(self):
        if len(self.data) < max(self.slowLen, self.breakoutLen, self.effLen) + 10:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        fast = self.fast[-1]
        mid = self.mid[-1]
        slow = self.slow[-1]
        atr = self.atr[-1]
        atr_base = self.atr_base[-1]
        
        # Regime checks
        bull_stack = fast > mid and mid > slow
        sep_perc = abs(fast - slow) / slow * 100 if slow != 0 else 0.0
        sep_ok = sep_perc >= self.minSepPerc
        
        # Slopes
        fast_slope = (fast - self.fast[-1 - self.slopeLen]) / self.fast[-1 - self.slopeLen] * 100 if len(self.fast) > self.slopeLen and self.fast[-1 - self.slopeLen] != 0 else 0.0
        mid_slope = (mid - self.mid[-1 - self.slopeLen]) / self.mid[-1 - self.slopeLen] * 100 if len(self.mid) > self.slopeLen and self.mid[-1 - self.slopeLen] != 0 else 0.0
        slow_slope = (slow - self.slow[-1 - self.slopeLen]) / self.slow[-1 - self.slopeLen] * 100 if len(self.slow) > self.slopeLen and self.slow[-1 - self.slopeLen] != 0 else 0.0
        slope_ok = slow_slope >= self.minSlowSlopePerc and mid_slope > 0 and fast_slope > 0
        
        # Efficiency
        close_arr = pd.Series(self.data.Close)
        net_move = abs(close - close_arr.iloc[-1 - self.effLen]) if len(close_arr) > self.effLen else 0
        step_move = 0.0
        for i in range(1, min(self.effLen + 1, len(close_arr))):
            step_move += abs(close_arr.iloc[-i] - close_arr.iloc[-i - 1])
        efficiency = net_move / step_move if step_move != 0 else 0.0
        eff_ok = efficiency >= self.minEff
        
        # Momentum persistence
        up_bars = 0.0
        for i in range(min(self.persistLen, len(close_arr) - 1)):
            if close_arr.iloc[-1 - i] > close_arr.iloc[-1 - i - 1]:
                up_bars += 1
        persist_ratio = up_bars / self.persistLen if self.persistLen > 0 else 0.0
        mom_raw = (close - close_arr.iloc[-1 - self.momLen]) / close_arr.iloc[-1 - self.momLen] * 100 if len(close_arr) > self.momLen and close_arr.iloc[-1 - self.momLen] != 0 else 0.0
        mom_ok = mom_raw > 0 and persist_ratio >= 0.57
        
        # ATR regime
        atr_regime = atr / atr_base if atr_base != 0 else 0.0
        atr_ok = atr_regime >= self.minAtrRegime
        
        # Breakout quality
        hh = self.highest_high[-2] if len(self.highest_high) > 1 else high
        breakout_dist = close - hh
        breakout_strength = breakout_dist / atr if atr != 0 else 0.0
        breakout_ok = close > hh and breakout_strength >= self.minBreakoutAtr
        
        # Pullback logic
        pullback_low = self.lowest_low[-1]
        dist_from_fast_atr = (fast - pullback_low) / atr if atr != 0 else 0.0
        deep_enough_pullback = dist_from_fast_atr >= self.pullbackAtrMult
        
        reclaim_fast = close > fast and close_arr.iloc[-2] <= self.fast[-2] if len(close_arr) > 1 else False
        reclaim_mid = close > mid and close_arr.iloc[-2] <= self.mid[-2] if len(close_arr) > 1 else False
        reclaim_strength = (close - fast) / atr if atr != 0 else 0.0
        reclaim_ok = (reclaim_fast or reclaim_mid) and reclaim_strength >= self.reclaimAtrMult
        
