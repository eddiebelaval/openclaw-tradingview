import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script inputs
    sup_level_in = 0.0
    res_level_in = 0.0
    buffer_pts = 0
    sl_points = 10
    ce_tp_pts = 20
    pe_tp_pts = 20

    def init(self):
        pass

    def next(self):
        # Get current data
        close_curr = self.data.Close[-1]
        close_prev = self.data.Close[-2] if len(self.data) > 1 else close_curr
        open_curr = self.data.Open[-1]
        
        # Initialize day tracking
        if not hasattr(self, 'day_open'):
            self.day_open = open_curr
            self.prev_day_open = np.nan
            self.auto_sup = np.nan
            self.auto_res = np.nan
            self.trade = 0
            self.entry = np.nan
            self.sl = np.nan
            self.tp = np.nan
        
        # Check if new day (simplified - check if bar index changes significantly)
        current_date = pd.Timestamp(self.data.index[-1]).date()
        if not hasattr(self, 'last_date'):
            self.last_date = current_date
        elif current_date != self.last_date:
            self.prev_day_open = self.day_open
            self.day_open = open_curr
            self.last_date = current_date
        
        # Manual support/resistance
        use_sup = self.sup_level_in > 0
        use_res = self.res_level_in > 0
        
        sup = self.sup_level_in - self.buffer_pts if use_sup else np.nan
        res = self.res_level_in + self.buffer_pts if use_res else np.nan
        
        # Auto open levels
        round100_up = np.ceil(self.day_open / 100) * 100
        round100_down = np.floor(self.day_open / 100) * 100
        round50_down = np.floor(self.day_open / 50) * 50
        
        is_green_day = self.day_open > self.prev_day_open if not np.isnan(self.prev_day_open) else False
        is_red_day = self.day_open < self.prev_day_open if not np.isnan(self.prev_day_open) else False
        
        # RED DAY → 100 grid
        if is_red_day:
            self.auto_res = round100_up
            self.auto_sup = round100_down
        
        # GREEN DAY → 50 + 100 grid
        if is_green_day:
            self.auto_sup = round50_down
            self.auto_res = round50_down + 100
        
        # Entry signals
        buy_signal = (
            use_sup and self.trade == 0 and
            close_prev <= sup and close_curr > sup
        )
        
        sell_signal = (
            use_res and self.trade == 0 and
            close_prev >= res and close_curr < res
        )
        
        # Entry logic
        if buy_signal:
            self.trade = 1
            self.entry = close_curr
            self.sl = sup - self.sl_points
            self.tp = sup + self.ce_tp_pts
            self.buy()
        
        if sell_signal:
            self.trade = -1
            self.entry = close_curr
            self.sl = res + self.sl_points
            self.tp = res - self.pe_tp_pts
            self.sell()
        
        # Exit logic
        buy_exit = self.trade == 1 and (close_curr > self.tp or close_curr < self.sl)
        sell_exit = self.trade == -1 and (close_curr < self.tp or close_curr > self.sl)
        
        if buy_exit or sell_exit:
            self.trade = 0
            if self.position:
                self.position.close()


