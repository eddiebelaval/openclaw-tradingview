import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Macro SAR Settings
    ma_start = 0.01
    ma_inc = 0.01
    ma_max = 0.15
    
    # Micro SAR Settings
    mi_start = 0.02
    mi_inc = 0.02
    mi_max = 0.2
    
    # Macro EMA Filter
    ema_len = 21

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Micro SAR
        def calc_micro_sar():
            result = pta.sar(high, low, close, iaf=self.mi_start, af=self.mi_inc, maxaf=self.mi_max)
            if result is not None and len(result) > 0:
                return result.iloc[:, 0] if isinstance(result, pd.DataFrame) else result
            return pd.Series(close.values, index=close.index)
        
        # Calculate Macro SAR
        def calc_macro_sar():
            result = pta.sar(high, low, close, iaf=self.ma_start, af=self.ma_inc, maxaf=self.ma_max)
            if result is not None and len(result) > 0:
                return result.iloc[:, 0] if isinstance(result, pd.DataFrame) else result
            return pd.Series(close.values, index=close.index)
        
        # Calculate EMA
        def calc_ema():
            result = pta.ema(close, length=self.ema_len)
            if result is not None:
                return result
            return pd.Series(close.values, index=close.index)
        
        self.mi_sar = self.I(calc_micro_sar)
        self.ma_sar = self.I(calc_macro_sar)
        self.ema = self.I(calc_ema)
    
    def next(self):
        # Get previous bar values (Pine Script uses [1] for previous bar)
        if len(self.data) < 2:
            return
        
        close_prev = self.data.Close[-2]
        mi_sar_prev = self.mi_sar[-2]
        ma_sar_prev = self.ma_sar[-2]
        ema_prev = self.ema[-2]
        
        close_curr = self.data.Close[-1]
        ema_curr = self.ema[-1]
        
        # Determine signals
        u_bull = close_prev > mi_sar_prev
        m_bull = close_prev > ma_sar_prev
        ema_bull = close_curr > ema_curr
        
        # Calculate confluence value
        osc_value = 0.0
        
        if m_bull:
            if u_bull and ema_bull:
                osc_value = 100  # Full confluence bull
            elif u_bull:
                osc_value = 50   # Partial confluence bull
        else:
            if not u_bull and not ema_bull:
                osc_value = -100  # Full confluence bear
            elif not u_bull:
                osc_value = -50   # Partial confluence bear
        
        # Trading logic based on confluence signals
        if not self.position:
            # Entry signals
            if osc_value == 100:
                # Full confluence bull - strong buy signal
                self.buy()
            elif osc_value == -100:
                # Full confluence bear - strong sell signal
                self.sell()
        else:
            # Exit logic
            if self.position.is_long:
                # Exit long on bear signals
                if osc_value <= -50:
                    self.position.close()
            elif self.position.is_short:
                # Exit short on bull signals
                if osc_value >= 50:
                    self.position.close()


