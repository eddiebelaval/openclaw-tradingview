class TvStrategy(Strategy):
    vix_mode = "Trend"
    vix_trend_len = 20
    vix_spike_thresh = 10.0
    add_threshold = 1000
    tick_lookback = 20
    cumtick_slope = 10
    trin_overbought = 1.5
