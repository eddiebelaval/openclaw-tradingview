import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    bufferSizeInput = 5000
    kInput = 50
    smoothInput = 1
    maLength = 9
    multiplier = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.price_array = []
        self.sorted_array = []
        
        def calculate_dispersion():
            result = []
            for i in range(len(close)):
                if i < self.kInput * 2:
                    result.append(np.nan)
                    continue
                
                current_close = close.iloc[i]
                buffer_start = max(0, i - self.bufferSizeInput)
                buffer_prices = []
                
                for j in range(buffer_start, i + 1):
                    buffer_prices.extend([
                        open_.iloc[j],
                        high.iloc[j],
                        low.iloc[j],
                        close.iloc[j]
                    ])
                
                if len(buffer_prices) == 0:
                    result.append(np.nan)
                    continue
                
                sorted_prices = sorted(buffer_prices)
                
                try:
                    idx = np.searchsorted(sorted_prices, current_close)
                except:
                    result.append(np.nan)
                    continue
                
                start_idx = max(0, idx - self.kInput)
                end_idx = min(len(sorted_prices) - 1, idx + self.kInput)
                
                if end_idx > start_idx and end_idx - start_idx >= self.kInput:
                    slice_vals = sorted_prices[start_idx:end_idx + 1]
                    disp = np.std(slice_vals, ddof=1) if len(slice_vals) > 1 else np.nan
                    result.append(disp)
                else:
                    result.append(np.nan)
            
            return pd.Series(result)
        
        self.dispersion = self.I(calculate_dispersion)
        
        def calculate_smoothed_disp():
            disp_series = pd.Series([self.dispersion[i] if i < len(self.dispersion) else np.nan for i in range(len(close))])
            smoothed = disp_series.rolling(window=self.smoothInput, min_periods=1).mean()
            result = []
            for i in range(len(close)):
                if pd.isna(disp_series.iloc[i]):
                    result.append(np.nan)
                else:
                    result.append(smoothed.iloc[i])
            return pd.Series(result)
        
        self.final_disp = self.I(calculate_smoothed_disp)
        
        self.final_disp_ma = self.I(lambda: self.final_disp.rolling(window=self.maLength, min_periods=1).mean() if len(self.final_disp) > 0 else pd.Series(0, index=close.index))
        
        def calculate_diff():
            diff = []
            for i in range(len(close)):
                if i < len(self.final_disp) and i < len(self.final_disp_ma):
                    if pd.notna(self.final_disp[i]) and pd.notna(self.final_disp_ma[i]):
                        diff.append(self.final_disp[i] - self.final_disp_ma[i])
                    else:
                        diff.append(np.nan)
                else:
                    diff.append(np.nan)
            return pd.Series(diff)
        
        self.diff = self.I(calculate_diff)
        
        def calculate_cmean():
            cmean = []
            cumsum = 0
            count = 0
            for i in range(len(close)):
                if i < len(self.final_disp) and pd.notna(self.final_disp[i]):
                    cumsum += self.final_disp[i]
                    count += 1
                    cmean.append((cumsum / (i + 1)) * self.multiplier)
                else:
                    cmean.append(np.nan)
            return pd.Series(cmean)
        
        self.cmean = self.I(calculate_cmean)

    def next(self):
        if len(self) < self.kInput * 2 + self.maLength:
            return
        
        current_disp = self.final_disp[-1]
        current_ma = self.final_disp_ma[-1]
        current_cmean = self.cmean[-1]
        prev_disp = self.final_disp[-2] if len(self.final_disp) > 1 else np.nan
        prev_ma = self.final_disp_ma[-2] if len(self.final_disp_ma) > 1 else np.nan
        
        if pd.isna(current_disp) or pd.isna(current_ma) or pd.isna(current_cmean):
            return
        
        if pd.notna(prev_disp) and pd.notna(prev_ma):
            if prev_disp < prev_ma and current_disp > current_ma and current_disp > current_cmean:
                if not self.position:
                    self.buy()
            elif prev_disp > prev_ma and current_disp < current_ma and current_disp < current_cmean:
                if self.position:
                    self.position.close()