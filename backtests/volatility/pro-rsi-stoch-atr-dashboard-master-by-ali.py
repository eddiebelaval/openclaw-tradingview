import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    stochLen = 14
    kSmooth = 3
    dSmooth = 3
    atrLen = 14
    rsiOB = 70
    rsiOS = 30
    stOB = 80
    stOS = 20
    minBullForBuy = 3
    maxBullForSell = 1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Current timeframe indicators (15m equivalent - using current data)
        self.rsi_current = self.I(lambda: pta.rsi(close, length=self.rsiLen) or pd.Series(50, index=close.index))
        
        # Stochastic calculation
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=self.stochLen, d=self.stochLen, smooth_k=self.kSmooth, smooth_d=self.dSmooth) or pd.DataFrame(index=close.index))
        self.k_current = self.I(lambda: stoch_result[f'STOCHk_{self.stochLen}_{self.stochLen}_{self.kSmooth}'] if isinstance(stoch_result, pd.DataFrame) and len(stoch_result.columns) > 0 else pd.Series(50, index=close.index))
        self.d_current = self.I(lambda: stoch_result[f'STOCHd_{self.stochLen}_{self.stochLen}_{self.kSmooth}'] if isinstance(stoch_result, pd.DataFrame) and len(stoch_result.columns) > 1 else pd.Series(50, index=close.index))
        
        # ATR
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atrLen) or pd.Series(0, index=close.index))
        
        # Trend RSI (using 4H logic - use current RSI as proxy since we're on single timeframe)
        self.trendRsi = self.I(lambda: pta.rsi(close, length=self.rsiLen) or pd.Series(50, index=close.index))
        
        # Bull count proxy - count how many "timeframes" show RSI > 50
        # Since we only have one timeframe, we'll use RSI > 50 as the main signal
        self.bullSignal = self.I(lambda: (self.trendRsi > 50).astype(float) * 4)

    def next(self):
        if len(self.data) < 2:
            return
        
        rsi_val = self.rsi_current[-1]
        k_val = self.k_current[-1]
        d_val = self.d_current[-1]
        trend_bull = self.trendRsi[-1] >= 50
        
        # Simplified alignment: just check if RSI is bullish
        bull_count = 4 if trend_bull else 0
        
        # Crossover signals
        k_d_crossover_up = crossover(self.k_current, self.d_current)
        k_d_crossover_down = crossover(self.d_current, self.k_current)
        
        # Master Buy: Trend LONG + enough bull alignment + K/D cross up + K,D in oversold region
        master_buy = (trend_bull and 
                     bull_count >= self.minBullForBuy and 
                     k_d_crossover_up and
                     rsi_val < self.rsiOB and
                     k_val < self.stOB)
        
        # Master Sell: Trend SHORT + few bull signals + K/D cross down + K,D in overbought region
        master_sell = (not trend_bull and 
                      bull_count <= self.maxBullForSell and 
                      k_d_crossover_down and
                      rsi_val > self.rsiOS and
                      k_val > self.stOS)
        
        # Alternative simpler logic: buy on oversold with K/D cross up, sell on overbought with K/D cross down
        if not self.position:
            # Buy signal: RSI oversold or approaching, K crosses D upward
            if rsi_val < (self.rsiOS + 10) and k_d_crossover_up:
                self.buy()
            # Or use master buy
            elif master_buy:
                self.buy()
        else:
            # Sell signal: RSI overbought or approaching, K crosses D downward
            if rsi_val > (self.rsiOB - 10) and k_d_crossover_down:
                self.sell()
            # Or use master sell
            elif master_sell:
                self.sell()


