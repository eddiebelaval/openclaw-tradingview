import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters from the Pine Script
    atr_len = 14
    atr_mult = 1.4
    zscore_period = 50
    normal_threshold = 1.0
    elevated_threshold = 2.0
    institutional_threshold = 3.0
    cooldown_bars = 5
    small_body_p = 0.33
    use_adaptive = True
    confidence_smooth_len = 5
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR calculation
        self.atr_current = self.I(lambda: pta.atr(high, low, close, length=self.atr_len))
        self.atr_avg = self.I(lambda: pta.sma(self.atr_current, length=20))
        
        # SMA and slope for trending
        self.ma20 = self.I(lambda: pta.sma(close, length=20))
        self.atr_10 = self.I(lambda: pta.atr(high, low, close, length=10))
        
        # Z-score calculation
        def calc_zscore(src):
            m = pta.sma(src, length=self.zscore_period)
            s = pta.stdev(src, length=self.zscore_period)
            zscore = (src - m) / s.fillna(1)
            return zscore.fillna(0)
        
        def calc_vol():
            return close * self.data.Volume
        
        self.vol_raw = self.I(calc_vol)
        self.z_local = self.I(lambda: calc_zscore(self.vol_raw))
        
        # Candle features
        def calc_tr():
            prev_close = close.shift(1)
            tr = np.maximum(high - low, 
                           np.maximum(np.abs(high - prev_close), 
                                     np.abs(low - prev_close)))
            return tr.fillna(0)
        
        self.tr = self.I(calc_tr)
        
        def calc_body():
            return np.abs(close - pd.Series(self.data.Open))
        
        self.body = self.I(calc_body)
        
        def calc_rng():
            return high - low
        
        self.rng = self.I(calc_rng)
        
        # Tracking variables
        self.last_mark_bar = -999
        self.last_signal = None
        
    def next(self):
        if len(self.data) < self.zscore_period + 10:
            return
        
        # Current values
        atr_bar = self.atr_current[-1] if not np.isnan(self.atr_current[-1]) else 0
        atr_avg = self.atr_avg[-1] if not np.isnan(self.atr_avg[-1]) else 0
        rng = self.rng[-1] if not np.isnan(self.rng[-1]) else 0
        body = self.body[-1] if not np.isnan(self.body[-1]) else 0
        tr = self.tr[-1] if not np.isnan(self.tr[-1]) else 0
        z = self.z_local[-1] if not np.isnan(self.z_local[-1]) else 0
        
        # Adaptive multiplier
        ma20 = self.ma20[-1] if not np.isnan(self.ma20[-1]) else 0
        ma20_5_bars_ago = self.ma20[-6] if len(self.ma20) >= 6 and not np.isnan(self.ma20[-6]) else ma20
        atr_10 = self.atr_10[-1] if not np.isnan(self.atr_10[-1]) else 1
        
        ma_slope = ((ma20 - ma20_5_bars_ago) / (atr_10 if atr_10 > 0 else 1)) * 100 if atr_10 > 0 else 0
        is_trending = abs(ma_slope) > 0.5
        is_high_vol = atr_bar > (atr_avg * 1.2) if atr_avg > 0 else False
        
        adaptive_multiplier = ((1.3 if is_trending else 0.8) * (1.2 if is_high_vol else 1.0)) if self.use_adaptive else 1.0
        
        current_normal = self.normal_threshold * adaptive_multiplier
        current_elevated = self.elevated_threshold * adaptive_multiplier
        current_institutional = self.institutional_threshold * adaptive_multiplier
        min_score_gate = 3.0
        
        # Candle patterns
        body_pct = (body / rng) if rng > 0 else 0
        range_spike = tr > (atr_bar * self.atr_mult) if atr_bar > 0 else False
        small_body = (rng > 0) and (body_pct < self.small_body_p)
        
        is_elevated = z >= current_elevated
        is_institutional = z >= current_institutional
        
        # Pattern scoring
        vol_score = min(3.0, max(0.0, z - current_normal))
        range_score = min(2.0, max(0.0, (tr / atr_bar - self.atr_mult))) if atr_bar > 0 else 0
        tight_body = min(2.0, max(0.0, (self.small_body_p - body_pct) * 4.0))
        
        score_momentum = (vol_score + range_score + (1.0 if is_institutional else 0.0)) if (is_elevated and range_spike) else 0.0
        score_absorption = (vol_score + tight_body + (1.0 if is_institutional else 0.0)) if (is_elevated and small_body) else 0.0
        
        # Prefer momentum over absorption if both occur
        prefer_momentum = (is_elevated and range_spike) and (not (is_elevated and small_body) or score_momentum >= score_absorption)
        prefer_absorption = (is_elevated and small_body) and not prefer_momentum
        
        # Cooldown logic
        bars_since_mark = len(self.data) - self.last_mark_bar
        on_cooldown = bars_since_mark < self.cooldown_bars
        
        can_emit = not on_cooldown
        
        # Generate signals
        mark_momentum = prefer_momentum and score_momentum >= min_score_gate and can_emit
        mark_abs = prefer_absorption and score_absorption >= min_score_gate and can_emit
        
        # Simple trading rules based on signals
        if mark_momentum:
            if not self.position:
                self.buy()
            self.last_mark_bar = len(self.data)
            self.last_signal = "momentum"
        elif mark_abs:
            if self.position:
                self.position.close()
            self.last_mark_bar = len(self.data)
            self.last_signal = "absorption"
        
        # Exit on momentum reversal or after holding
        if self.position and len(self.data) - self.last_mark_bar > 20:
            self.position.close()


