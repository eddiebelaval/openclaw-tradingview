import numpy as np
import pandas as pd
from datetime import datetime, timedelta
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    orb_mins = 15
    tz = "America/New_York"
    
    show_asia = True
    asia_sh, asia_sm = 20, 0
    asia_eh, asia_em = 0, 0
    
    show_london = True
    lon_sh, lon_sm = 2, 0
    lon_eh, lon_em = 6, 0
    
    show_ny_am = True
    ny_am_sh, ny_am_sm = 9, 30
    ny_am_eh, ny_am_em = 11, 0
    
    show_ny_pm = True
    ny_pm_sh, ny_pm_sm = 13, 0
    ny_pm_eh, ny_pm_em = 16, 0
    
    box_mode = "Full Session"

    def init(self):
        self.orb_highs = {}
        self.orb_lows = {}
        self.session_locked = {}
        self.last_session_check = {}
        
        self.sessions = [
            ("asia", self.show_asia, self.asia_sh, self.asia_sm, self.asia_eh, self.asia_em),
            ("london", self.show_london, self.lon_sh, self.lon_sm, self.lon_eh, self.lon_em),
            ("ny_am", self.show_ny_am, self.ny_am_sh, self.ny_am_sm, self.ny_am_eh, self.ny_am_em),
            ("ny_pm", self.show_ny_pm, self.ny_pm_sh, self.ny_pm_sm, self.ny_pm_eh, self.ny_pm_em),
        ]
        
        for name, *_ in self.sessions:
            self.orb_highs[name] = None
            self.orb_lows[name] = None
            self.session_locked[name] = False
            self.last_session_check[name] = None

    def _get_session_bounds(self, dt, sh, sm, eh, em):
        y, mo, d = dt.year, dt.month, dt.day
        start_today = datetime(y, mo, d, sh, sm, 0)
        end_today = datetime(y, mo, d, eh, em, 0)
        
        start_min = sh * 60 + sm
        end_min = eh * 60 + em
        cross_mid = end_min <= start_min
        
        if cross_mid:
            if dt < end_today:
                start_ts = start_today - timedelta(days=1)
                end_ts = end_today
            else:
                start_ts = start_today
                end_ts = end_today + timedelta(days=1)
        else:
            start_ts = start_today
            end_ts = end_today
        
        return start_ts, end_ts

    def _update_orb(self, name, enabled, sh, sm, eh, em):
        if not enabled:
            return
        
        current_time = pd.Timestamp(self.data.index[-1]).to_pydatetime()
        sess_start, sess_end = self._get_session_bounds(current_time, sh, sm, eh, em)
        
        orb_end = sess_start + timedelta(minutes=self.orb_mins)
        
        in_session = sess_start <= current_time < sess_end
        new_session = in_session and (self.last_session_check[name] is None or not (sess_start <= self.last_session_check[name] < sess_end))
        in_orb = in_session and sess_start <= current_time < orb_end
        
        if new_session:
            self.orb_highs[name] = None
            self.orb_lows[name] = None
            self.session_locked[name] = False
        
        if in_orb:
            h = self.data.High[-1]
            l = self.data.Low[-1]
            
            if self.orb_highs[name] is None:
                self.orb_highs[name] = h
            else:
                self.orb_highs[name] = max(self.orb_highs[name], h)
            
            if self.orb_lows[name] is None:
                self.orb_lows[name] = l
            else:
                self.orb_lows[name] = min(self.orb_lows[name], l)
        
        if in_session and not self.session_locked[name] and current_time >= orb_end and self.orb_highs[name] is not None and self.orb_lows[name] is not None:
            self.session_locked[name] = True
        
        if not in_session and current_time >= sess_end:
            self.session_locked[name] = False
        
        self.last_session_check[name] = current_time

    def next(self):
        for name, enabled, sh, sm, eh, em in self.sessions:
            self._update_orb(name, enabled, sh, sm, eh, em)
        
        close = self.data.Close[-1]
        
        buy_signal = False
        sell_signal = False
        
        for name, enabled, *_ in self.sessions:
            if not enabled or self.orb_highs[name] is None or self.orb_lows[name] is None:
                continue
            
            orb_high = self.orb_highs[name]
            orb_low = self.orb_lows[name]
            
            if close > orb_high and len(self.data) > 1 and self.data.Close[-2] <= orb_high:
                buy_signal = True
            
            if close < orb_low and len(self.data) > 1 and self.data.Close[-2] >= orb_low:
                sell_signal = True
        
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.position.close()