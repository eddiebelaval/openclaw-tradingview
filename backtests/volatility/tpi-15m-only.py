import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # SuperTrend calculation (manual implementation)
        atr_length = 96
        st_factor = 2.0
        atr = self.I(pta.atr, high, low, close, length=atr_length)
        hl_avg = (high + low) / 2
        
        def calc_supertrend():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if i < atr_length:
                    result.iloc[i] = np.nan
                else:
                    hl = hl_avg.iloc[i]
                    atr_val = atr.iloc[i]
                    if pd.isna(atr_val):
                        result.iloc[i] = np.nan
                    else:
                        basic_ub = hl + st_factor * atr_val
                        basic_lb = hl - st_factor * atr_val
                        result.iloc[i] = basic_ub
            return result
        
        self.st_val = self.I(calc_supertrend)
        
        # TSI Calculation (15m equivalent - using current close as proxy)
        tsi_long = 25
        tsi_short = 13
        tsi_signal = 13
        
        def calc_tsi():
            pc = close.diff()
            ema1 = pc.ewm(span=tsi_long).mean()
            num = ema1.ewm(span=tsi_short).mean()
            ema1_abs = pc.abs().ewm(span=tsi_long).mean()
            den = ema1_abs.ewm(span=tsi_short).mean()
            tsi = np.where(den == 0, 0, 100 * (num / den))
            return pd.Series(tsi, index=close.index)
        
        self.tsi_val = self.I(calc_tsi)
        
        def calc_tsi_signal():
            tsi_series = self.tsi_val
            return tsi_series.ewm(span=tsi_signal).mean()
        
        self.tsi_sig = self.I(calc_tsi_signal)
        
        # EMA Calculation
        emaS_len = 18
        emaB_len = 36
        
        self.emaS = self.I(pta.ema, close, length=emaS_len)
        self.emaB = self.I(pta.ema, close, length=emaB_len)
        
        # Swing tracking
        self.last_swing_type = "NONE"
        self.current_sh = None
        self.current_sl = None
        self.prev_sh = None
        self.prev_sl = None
        self.bos_ready = True
        self.trend_dir = "NEUTRAL"
        self.last_bos_direction = "NONE"
        self.consecutive_bos = 0
        self.last_bullish_origin_sl = None
        self.last_bearish_origin_sh = None
        
    def next(self):
        # Get current values
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        
        # SuperTrend score
        st_val = self.st_val[-1]
        if not pd.isna(st_val):
            supertrend_score = 1.0 if close_val > st_val else -1.0
        else:
            supertrend_score = 0.0
        
        # TSI score
        tsi_val = self.tsi_val[-1]
        tsi_sig = self.tsi_sig[-1]
        if not pd.isna(tsi_val) and not pd.isna(tsi_sig):
            tsi_above_signal = tsi_val > tsi_sig
            tsi_above_zero = tsi_val > 0
            if tsi_above_signal and tsi_above_zero:
                tsi_score = 1.0
            elif tsi_above_signal and not tsi_above_zero:
                tsi_score = 0.5
            elif not tsi_above_signal and not tsi_above_zero:
                tsi_score = -1.0
            else:
                tsi_score = 0.5
        else:
            tsi_score = 0.0
        
        # EMA score
        emaS = self.emaS[-1]
        emaB = self.emaB[-1]
        if not pd.isna(emaS) and not pd.isna(emaB):
            ema_green = emaS >= emaB
            price_above_both = close_val > emaS and close_val > emaB
            price_below_both = close_val < emaS and close_val < emaB
            price_between = close_val > min(emaS, emaB) and close_val < max(emaS, emaB)
            
            if ema_green:
                ema_score = 1.0 if price_above_both else 0.5
            else:
                ema_score = -1.0 if price_below_both else -0.5
        else:
            ema_score = 0.0
        
        # Dynamic swing tracking and trend detection
        if self.last_swing_type == "NONE":
            if close_val > open_val:
                self.current_sh = close_val
                self.last_swing_type = "SH"
            else:
                self.current_sl = close_val
                self.last_swing_type = "SL"
        
        if self.last_swing_type == "SH":
            if close_val > self.current_sh:
                self.current_sh = close_val
            elif close_val < self.current_sh:
                self.prev_sh = self.current_sh
                self.current_sl = close_val
                self.last_swing_type = "SL"
                self.bos_ready = True
        
        if self.last_swing_type == "SL":
            if close_val < self.current_sl:
                self.current_sl = close_val
            elif close_val > self.current_sl:
                self.prev_sl = self.current_sl
                self.current_sh = close_val
                self.last_swing_type = "SH"
                self.bos_ready = True
        
        # BOS/MSB logic
        trend_score = 0.0
        if self.bos_ready and self.prev_sh is not None and self.prev_sl is not None:
            if close_val > self.prev_sh:
                is_msb = self.last_bos_direction == "DOWN" and self.last_bearish_origin_sh is not None and close_val > self.last_bearish_origin_sh
                if self.last_bos_direction != "UP" and not is_msb:
                    self.consecutive_bos = 1
                else:
                    self.consecutive_bos += 1
                
                self.last_bos_direction = "UP"
                if is_msb or self.consecutive_bos >= 2:
                    self.trend_dir = "UP"
                    trend_score = 1.0
                else:
                    trend_score = 0.5
                self.last_bullish_origin_sl = self.prev_sl
                self.bos_ready = False
            
            elif close_val < self.prev_sl:
                is_msb = self.last_bos_direction == "UP" and self.last_bullish_origin_sl is not None and close_val < self.last_bullish_origin_sl
                if self.last_bos_direction != "DOWN" and not is_msb:
                    self.consecutive_bos = 1
                else:
                    self.consecutive_bos += 1
                
                self.last_bos_direction = "DOWN"
                if is_msb or self.consecutive_bos >= 2:
                    self.trend_dir = "DOWN"
                    trend_score = -1.0
                else:
                    trend_score = -0.5
                self.last_bearish_origin_sh = self.prev_sh
                self.bos_ready = False
        
        if self.trend_dir == "UP":
            trend_score = 1.0
        elif self.trend_dir == "DOWN":
            trend_score = -1.0
        else:
            trend_score = 0.0
        
        # TPI calculation
        tpi = (supertrend_score + tsi_score + ema_score + trend_score) / 4.0
        
        # Trading logic based on TPI
        if tpi > 0.5:
            if not self.position:
                self.buy()
        elif tpi < -0.5:
            if self.position:
                self.sell()


