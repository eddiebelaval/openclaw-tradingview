        # Check if we have valid indicator values
        if len(self.data) < 2:
            return

        # Bull Divergence with bullish pressure and uptrend
        if (self.bull_div[-1] and 
            self.pressure[-1] > 0 and 
            self.data.Close[-1] > self.ema_trend[-1] and
            not self.position):
            self.buy()

