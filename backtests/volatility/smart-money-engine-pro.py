        if (self.bear_div[-1] and 
            self.pressure[-1] < 0 and 
            self.data.Close[-1] < self.ema_trend[-1] and
            self.position):
            self.sell()

        # Bull Trap detection - exit long position
        if self.bull_trap[-1] and self.position:
            self.sell()

