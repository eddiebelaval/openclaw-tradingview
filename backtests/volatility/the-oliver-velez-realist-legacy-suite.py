import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    min_body_pct = 70.0
    extension = 5
    flat_thresh = 8.0
    sqz_dist_atr = 100.0
    e_body_mult = 2.0
    e_clear_bars = 3
    e_min_solid = 85.0
    dev_target = 2.0
    slow_len = 20
    trend_len = 200

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ma_slow = self.I(pta.sma, close, length=self.slow_len)
        self.ma_trend = self.I(pta.sma, close, length=self.trend_len)
        self.atr = self.I(pta.atr, high, low, close, length=14)
        self.body_sma = self.I(pta.sma, (open_ - close).abs(), length=20)
        self.stdev = self.I(lambda: close.rolling(self.slow_len).std())
        
        self.p_cnt = 0

    def next(self):
        if len(self.data) < max(self.slow_len, self.trend_len) + self.e_clear_bars + 2:
            return

        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        close_prev = self.data.Close[-2]
        open_prev = self.data.Open[-2]
        high_prev = self.data.High[-2]
        low_prev = self.data.Low[-2]
        
        close_2 = self.data.Close[-3]
        open_2 = self.data.Open[-3]
        
        ma_slow = self.ma_slow[-1]
        ma_trend = self.ma_trend[-1]
        atr = self.atr[-1]
        body_sma = self.body_sma[-1]
        stdev = self.stdev[-1]
        
        body = abs(open_ - close)
        candle_range = high - low
        body_prev = abs(open_prev - close_prev)
        candle_range_prev = high_prev - low_prev
        body_2 = abs(open_2 - close_2)
        
        # Angle calculation
        ma_slow_5 = self.ma_slow[-6] if len(self.data) >= 6 else ma_slow
        angle_20 = 180 / np.pi * np.arctan((ma_slow - ma_slow_5) / 5) if (5 != 0) else 0
        
        # Squeeze detection
        is_squeeze = (abs(angle_20) <= self.flat_thresh and 
                     abs(ma_slow - ma_trend) < (atr * self.sqz_dist_atr / 100.0))
        
        # Clearing logic
        highest_high_clear = max(self.data.High[-(self.e_clear_bars + 1):-1]) if len(self.data) > self.e_clear_bars else 0
        lowest_low_clear = min(self.data.Low[-(self.e_clear_bars + 1):-1]) if len(self.data) > self.e_clear_bars else float('inf')
        
        clears_bull = close > highest_high_clear
        clears_bear = close < lowest_low_clear
        
        # Elephant bar detection
        is_bull_e = (close > open_ and 
                    body >= (body_sma * self.e_body_mult) and 
                    (body / candle_range * 100 >= self.e_min_solid if candle_range > 0 else False) and 
                    clears_bull)
        
        is_bear_e = (close < open_ and 
                    body >= (body_sma * self.e_body_mult) and 
                    (body / candle_range * 100 >= self.e_min_solid if candle_range > 0 else False) and 
                    clears_bear)
        
        # 180 pattern detection
        bull_180 = (open_prev > close_prev and 
                   close > open_ and 
                   close >= open_prev and 
                   (body_prev / candle_range_prev * 100 >= self.min_body_pct if candle_range_prev > 0 else False))
        
        bear_180 = (close_prev > open_prev and 
                   open_ > close and 
                   close <= open_prev and 
                   (body_prev / candle_range_prev * 100 >= self.min_body_pct if candle_range_prev > 0 else False))
        
        # Ignored bars (GBI/RBI)
        is_gbi = (close_2 > open_2 and 
                 close_prev < open_prev and 
                 close > high_prev and 
                 close > open_ and 
                 (body_2 > body_prev))
        
        is_rbi = (close_2 < open_2 and 
                 close_prev > open_prev and 
                 close < low_prev and 
                 close < open_ and 
                 (body_2 > body_prev))
        
        # 20 MA halt detection
        ma_slow_prev = self.ma_slow[-2] if len(self.data) >= 2 else ma_slow
        is_halt_bull = (low <= (ma_slow + (atr * 0.15)) and 
                       low >= (ma_slow - (atr * 0.15)) and 
                       ma_slow > ma_slow_prev and 
                       close > ma_slow)
        
        is_halt_bear = (high >= (ma_slow - (atr * 0.15)) and 
                       high <= (ma_slow + (atr * 0.15)) and 
                       ma_slow < ma_slow_prev and 
                       close < ma_slow)
        
        # Update pillar count
        if bull_180 or bear_180 or is_bull_e or is_bear_e or is_gbi or is_rbi:
            self.p_cnt = self.extension + 1
        else:
            self.p_cnt = max(0, self.p_cnt - 1)
        
        # Trading logic
        any_signal = is_bull_e or is_bear_e or bull_180 or bear_180 or is_gbi or is_rbi or is_halt_bull or is_halt_bear
        
        if any_signal:
            if is_bull_e or bull_180 or is_gbi or is_halt_bull:
                if not self.position:
                    self.buy()
            elif is_bear_e or bear_180 or is_rbi or is_halt_bear:
                if self.position:
                    self.position.close()