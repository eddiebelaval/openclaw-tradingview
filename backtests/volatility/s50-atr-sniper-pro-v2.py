import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    totalQty = 10
    atrPeriod = 28
    atrMult = 5.0
    emaFilter = 100

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)
        
        # Calculate EMA
        self.ema = self.I(pta.ema, close, length=self.emaFilter)
        
        # Initialize trailing stop and trend tracking
        self.trailing_stop = np.zeros(len(self.data))
        self.trend = np.zeros(len(self.data))

    def next(self):
        close_price = self.data.Close[-1]
        prev_close = self.data.Close[-2] if len(self.data) > 1 else close_price
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        ema_val = self.ema[-1] if not np.isnan(self.ema[-1]) else close_price
        
        idx = len(self.data) - 1
        
        # Get previous trailing stop and trend
        if idx == 0:
            prev_trailing_stop = close_price
            prev_trend = 0
        else:
            prev_trailing_stop = self.trailing_stop[idx - 1]
            prev_trend = self.trend[idx - 1]
        
        # Update trailing stop logic
        if close_price > prev_trailing_stop and prev_close > prev_trailing_stop:
            # Trend continuation (Long)
            new_trailing_stop = max(prev_trailing_stop, close_price - (atr_val * self.atrMult))
            new_trend = 1
        elif close_price < prev_trailing_stop and prev_close < prev_trailing_stop:
            # Trend continuation (Short)
            new_trailing_stop = min(prev_trailing_stop, close_price + (atr_val * self.atrMult))
            new_trend = -1
        else:
            # Trend flip
            if close_price > prev_trailing_stop:
                new_trailing_stop = close_price - (atr_val * self.atrMult)
                new_trend = 1
            else:
                new_trailing_stop = close_price + (atr_val * self.atrMult)
                new_trend = -1
        
        self.trailing_stop[idx] = new_trailing_stop
        self.trend[idx] = new_trend
        
        # Detect trend change
        trend_change = new_trend - prev_trend if idx > 0 else 0
        
        # Entry conditions
        long_cond = trend_change > 0 and close_price > ema_val
        short_cond = trend_change < 0 and close_price < ema_val
        
        # Exit conditions
        long_exit = new_trend == -1 and self.position and self.position.is_long
        short_exit = new_trend == 1 and self.position and self.position.is_short
        
        # Execute trades
        if long_exit:
            self.position.close()
        elif short_exit:
            self.position.close()
        elif long_cond:
            if self.position:
                self.position.close()
            self.buy(size=self.totalQty)
        elif short_cond:
            if self.position:
                self.position.close()
            self.sell(size=self.totalQty)