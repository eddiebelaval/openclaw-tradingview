class TvStrategy(Strategy):
    # Fair Value Gap parameters
    extend_mode = "Right"  # "None", "Right", "Bars"
    extend_bars = 200
    min_gap_ticks = 0.0
    keep_history = True
    mark_mitigated = True
    stop_extend_on_fill = True
    max_fvgs_to_keep = 250
    show_midline = False

    def init(self):
        # Store FVG data
        self.fvgs = []  # List of dicts: {type, top, bot, entry_bar, mitigated}
        self.last_fvg_bars = []  # Track bars where FVGs were created

    def next(self):
        # Get current bar data
        if len(self.data) < 3:
            return

        current_idx = len(self.data) - 1
        current_low = self.data.Low[-1]
        current_high = self.data.High[-1]
        current_close = self.data.Close[-1]

        # Get previous bars
        low_0 = self.data.Low[-1]
        low_1 = self.data.Low[-2] if len(self.data) >= 2 else low_0
        low_2 = self.data.Low[-3] if len(self.data) >= 3 else low_1

        high_0 = self.data.High[-1]
        high_1 = self.data.High[-2] if len(self.data) >= 2 else high_0
        high_2 = self.data.High[-3] if len(self.data) >= 3 else high_1

        tick_size = 0.01  # Default tick size (can be adjusted)
        min_gap = self.min_gap_ticks * tick_size

        # Detect Bullish FVG: low > high[2]
        bull_fvg = (low_0 > high_2) and ((low_0 - high_2) >= min_gap)

        # Detect Bearish FVG: high < low[2]
        bear_fvg = (high_0 < low_2) and ((low_2 - high_0) >= min_gap)

        # Create new FVGs
        if bull_fvg:
            top = low_0
            bot = high_2
            self.fvgs.append({
                'type': 'bull',
                'top': top,
                'bot': bot,
                'entry_bar': current_idx - 2,
                'mitigated': False,
                'entry_price': current_close
            })

        if bear_fvg:
            top = low_2
            bot = high_0
            self.fvgs.append({
                'type': 'bear',
                'top': top,
                'bot': bot,
                'entry_bar': current_idx - 2,
                'mitigated': False,
                'entry_price': current_close
            })

        # Trim FVGs list if it exceeds max
        if len(self.fvgs) > self.max_fvgs_to_keep:
            self.fvgs = self.fvgs[-self.max_fvgs_to_keep:]

        # Check for mitigation of existing FVGs and generate signals
        for i, fvg in enumerate(self.fvgs):
            if not fvg['mitigated']:
                # Bullish FVG mitigated when low <= bot
                if fvg['type'] == 'bull' and current_low <= fvg['bot']:
                    fvg['mitigated'] = True
                    # Exit any existing position
                    if self.position:
                        self.position.close()

                # Bearish FVG mitigated when high >= top
                elif fvg['type'] == 'bear' and current_high >= fvg['top']:
                    fvg['mitigated'] = True
                    # Exit any existing position
                    if self.position:
                        self.position.close()

        # Simple trading logic based on FVG detection
        # Buy on bullish FVG formation
        if bull_fvg and not self.position:
            self.buy()

        # Sell on bearish FVG formation (close long or go short)
        elif bear_fvg:
            if self.position:
                self.position.close()
            else:
                self.sell()

        # Exit on mitigation
        for fvg in self.fvgs:
            if fvg['mitigated'] and self.position:
                self.position.close()
                break


