import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pricevol_length = 22
    pricevol_rank_len = 252
    volatility_choice = "IV Rank"

    def init(self):
        close = pd.Series(self.data.Close)
        low = pd.Series(self.data.Low)
        high = pd.Series(self.data.High)

        spot_stdev = self.I(lambda: pta.stdev(close, length=self.pricevol_length))
        low_stdev = self.I(lambda: pta.stdev(low, length=self.pricevol_length))

        def pricevol_side(mult, is_up):
            spot_adj = close + spot_stdev * mult if is_up else close - spot_stdev * mult
            low_adj = low + low_stdev * mult if is_up else low - low_stdev * mult
            spot_hi = spot_adj.rolling(window=self.pricevol_length).max()
            result = ((spot_hi - low_adj) / spot_hi * 100.0).where(spot_hi != 0.0, np.nan)
            return result

        def calc_avg_up():
            s1 = pricevol_side(1.0, True)
            s2 = pricevol_side(2.0, True)
            s3 = pricevol_side(3.0, True)
            return (s1 + s2 + s3) / 3.0

        def calc_avg_dn():
            s1 = pricevol_side(1.0, False)
            s2 = pricevol_side(2.0, False)
            s3 = pricevol_side(3.0, False)
            return (s1 + s2 + s3) / 3.0

        avg_up = self.I(calc_avg_up)
        avg_dn = self.I(calc_avg_dn)
        self.pricevol_skew = self.I(lambda: avg_up - avg_dn)

        spot_hi0 = self.I(lambda: close.rolling(window=self.pricevol_length).max())
        self.price_vol = self.I(lambda: ((spot_hi0 - low) / spot_hi0 * 100.0).where(spot_hi0 != 0.0, np.nan))

        lo = self.I(lambda: self.price_vol.rolling(window=self.pricevol_rank_len).min())
        hi = self.I(lambda: self.price_vol.rolling(window=self.pricevol_rank_len).max())
        rng = self.I(lambda: hi - lo)

        def calc_ivr():
            result = ((self.price_vol - lo) / rng * 100.0).where(rng != 0.0, np.nan)
            return result

        self.ivr = self.I(calc_ivr)

        def calc_pct_rank():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if i < self.pricevol_rank_len:
                    result.iloc[i] = np.nan
                else:
                    window = self.price_vol.iloc[i - self.pricevol_rank_len + 1:i + 1]
                    current_val = self.price_vol.iloc[i]
                    if pd.isna(current_val):
                        result.iloc[i] = np.nan
                    else:
                        rank = (window <= current_val).sum() - 1
                        result.iloc[i] = rank / self.pricevol_rank_len * 100.0
            return result

        self.pct_rank = self.I(calc_pct_rank)

        if self.volatility_choice == "IV Percentile":
            self.out = self.pct_rank
        elif self.volatility_choice == "IV Rank":
            self.out = self.ivr
        elif self.volatility_choice == "Volatility Skew Index":
            self.out = self.pricevol_skew
        else:
            self.out = self.I(lambda: self.price_vol * 100.0)

    def next(self):
        if len(self.data) < self.pricevol_rank_len + 10:
            return

        if pd.isna(self.out[-1]):
            return

        if self.volatility_choice in ["IV Percentile", "IV Rank"]:
            if crossover(50, self.out):
                if not self.position:
                    self.buy()
            elif crossover(self.out, 50):
                if self.position:
                    self.position.close()
        else:
            if self.out[-1] > 50:
                if not self.position:
                    self.buy()
            elif self.out[-1] < 30:
                if self.position:
                    self.position.close()