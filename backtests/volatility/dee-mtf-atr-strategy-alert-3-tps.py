import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    stAtrLen = 10
    stMult = 3.0
    smaFastLen = 8
    smaSlowLen = 9
    atrLen = 10
    atrRiskMult = 1.5
    tp1MultR = 1.0
    tp2MultR = 2.0
    tp3MultR = 3.0
    useRiskSizing = False
    riskUsdPerTrade = 100.0
    fixedQty = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Calculate SMAs
        self.smaFast = self.I(pta.sma, close, length=self.smaFastLen)
        self.smaSlow = self.I(pta.sma, close, length=self.smaSlowLen)
        
        # Supertrend for LTF
        self.ltfDir = None
        self.ltfLine = None
        self.supertrend_ltf()
        
        # Position tracking
        self.entry_price = None
        self.entry_type = None
        self.tp_levels = {"long": [None, None, None], "short": [None, None, None]}
        self.sl_level = None

    def supertrend_ltf(self):
        """Calculate supertrend for current timeframe"""
        close = pd.Series(self.data.Close)
        atr = pd.Series(self.atr)
        
        def calc_supertrend():
            upper = close + self.stMult * atr
            lower = close - self.stMult * atr
            
            dir_series = pd.Series(index=close.index, dtype=float)
            line_series = pd.Series(index=close.index, dtype=float)
            
            curr_dir = 1.0
            curr_line = lower.iloc[0]
            
            for i in range(len(close)):
                if close.iloc[i] > curr_line:
                    curr_dir = 1.0
                    curr_line = max(lower.iloc[i], curr_line)
                else:
                    curr_dir = -1.0
                    curr_line = min(upper.iloc[i], curr_line)
                
                dir_series.iloc[i] = curr_dir
                line_series.iloc[i] = curr_line
            
            return dir_series, line_series
        
        self.ltfDir = self.I(lambda: calc_supertrend()[0])
        self.ltfLine = self.I(lambda: calc_supertrend()[1])

    def next(self):
        close = self.data.Close[-1]
        atr_val = self.atr[-1]
        
        if atr_val is None or np.isnan(atr_val):
            return
        
        ltf_dir = self.ltfDir[-1]
        ltf_line = self.ltfLine[-1]
        sma_fast = self.smaFast[-1]
        sma_slow = self.smaSlow[-1]
        
        # Validate data
        if (ltf_dir is None or np.isnan(ltf_dir) or 
            ltf_line is None or np.isnan(ltf_line) or
            sma_fast is None or np.isnan(sma_fast) or
            sma_slow is None or np.isnan(sma_slow)):
            return
        
        # LTF trend conditions
        bull_ltf = (ltf_dir == 1.0) and (close > ltf_line)
        bear_ltf = (ltf_dir == -1.0) and (close < ltf_line)
        
        # For HTF, we use LTF as proxy (in multi-timeframe scenario would need separate calculation)
        # Here we simplify: HTF trend confirmation is the direction itself
        bull_htf = (ltf_dir == 1.0)
        bear_htf = (ltf_dir == -1.0)
        
        bull = bull_ltf and bull_htf
        bear = bear_ltf and bear_htf
        
        strong_buy = bull and sma_fast >= sma_slow
        strong_sell = bear and sma_fast <= sma_slow
        
        # Calculate risk metrics
        long_sl = close - self.atrRiskMult * atr_val
        long_r = close - long_sl if long_sl < close else 1.0
        
        short_sl = close + self.atrRiskMult * atr_val
        short_r = short_sl - close if short_sl > close else 1.0
        
        # Position size
        if self.useRiskSizing and long_r > 0:
            long_qty = max(1, int(self.riskUsdPerTrade / long_r))
        else:
            long_qty = int(self.fixedQty)
        
        if self.useRiskSizing and short_r > 0:
            short_qty = max(1, int(self.riskUsdPerTrade / short_r))
        else:
            short_qty = int(self.fixedQty)
        
        # Entry logic
        if strong_buy and not self.position:
            if long_qty > 0 and long_r > 0:
                self.entry_price = close
                self.entry_type = "long"
                self.sl_level = long_sl
                self.tp_levels["long"] = [
                    close + self.tp1MultR * long_r,
                    close + self.tp2MultR * long_r,
                    close + self.tp3MultR * long_r
                ]
                self.buy(size=long_qty)
        
        elif strong_sell and not self.position:
            if short_qty > 0 and short_r > 0:
                self.entry_price = close
                self.entry_type = "short"
                self.sl_level = short_sl
                self.tp_levels["short"] = [
                    close - self.tp1MultR * short_r,
                    close - self.tp2MultR * short_r,
                    close - self.tp3MultR * short_r
                ]
                self.sell(size=short_qty)
        
        # Exit logic for long positions
        elif self.position and self.position.is_long:
            avg = self.position.open_price
            r = self.atrRiskMult * atr_val
            
            long_sl_now = avg - self.atrRiskMult * atr_val
            long_tp1_now = avg + self.tp1MultR * r
            long_tp2_now = avg + self.tp2MultR * r
            long_tp3_now = avg + self.tp3MultR * r
            
            # Exit on SL hit
            if close <= long_sl_now:
                self.position.close()
            # Exit on TP hits (simplified: close at first TP hit for now)
            elif close >= long_tp3_now:
                self.position.close()
            elif close >= long_tp2_now:
                self.position.close()
            elif close >= long_tp1_now:
                self.position.close()
        
        # Exit logic for short positions
        elif self.position and self.position.is_short:
            avg = self.position.open_price
            r = self.atrRiskMult * atr_val
            
            short_sl_now = avg + self.atrRiskMult * atr_val
            short_tp1_now = avg - self.tp1MultR * r
            short_tp2_now = avg - self.tp2MultR * r
            short_tp3_now = avg - self.tp3MultR * r
            
            # Exit on SL hit
            if close >= short_sl_now:
                self.position.close()
            # Exit on TP hits (simplified: close at first TP hit for now)
            elif close <= short_tp3_now:
                self.position.close()
            elif close <= short_tp2_now:
                self.position.close()
            elif close <= short_tp1_now:
                self.position.close()


