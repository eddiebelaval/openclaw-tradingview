import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # ATR Parameters
    atr_period = 14
    atr_avg_period = 30
    
    # Thresholds and Scaling
    atr_low_threshold = 0.8
    atr_high_threshold = 1.2
    atr_max_scaling = 2.0
    
    # Target RR
    target_rr = 2.0
    rr_absolute_min = 1.0
    rr_absolute_max = 3.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # Calculate average ATR using SMA of ATR
        def avg_atr_calc():
            atr_series = pta.atr(high, low, close, length=self.atr_period)
            if atr_series is None:
                return pd.Series(1.0, index=close.index)
            avg = pta.sma(atr_series, length=self.atr_avg_period)
            return avg if avg is not None else pd.Series(1.0, index=close.index)
        
        self.average_atr = self.I(avg_atr_calc)
        
        # Calculate ATR Ratio
        def atr_ratio_calc():
            atr_series = pta.atr(high, low, close, length=self.atr_period)
            avg_atr_series = avg_atr_calc()
            if atr_series is None or avg_atr_series is None:
                return pd.Series(1.0, index=close.index)
            ratio = atr_series / avg_atr_series.replace(0, 1)
            return ratio
        
        self.atr_ratio = self.I(atr_ratio_calc)
        
        # Calculate scaling factor
        def scaling_calc():
            ratio_series = self.atr_ratio
            scaling = pd.Series(1.0, index=ratio_series.index)
            
            for i in range(len(ratio_series)):
                ratio = ratio_series.iloc[i]
                
                if ratio < self.atr_low_threshold:
                    atr_range = self.atr_low_threshold
                    min_scaling = 1.0 / self.atr_max_scaling
                    scaling.iloc[i] = min_scaling + (1.0 - min_scaling) * (ratio / atr_range)
                elif ratio > self.atr_high_threshold:
                    atr_range = self.atr_high_threshold
                    ratio_above = ratio - self.atr_high_threshold
                    scaling.iloc[i] = 1.0 + (self.atr_max_scaling - 1.0) * min(ratio_above / atr_range, 1.0)
                else:
                    normalized = (ratio - self.atr_low_threshold) / (self.atr_high_threshold - self.atr_low_threshold)
                    scaling.iloc[i] = 0.9 + 0.2 * normalized
            
            return scaling
        
        self.scaling = self.I(scaling_calc)
        
        # Calculate adaptive RR
        def adaptive_rr_calc():
            adaptive = self.target_rr * self.scaling
            return adaptive
        
        self.adaptive_rr = self.I(adaptive_rr_calc)
        
        # Calculate final adaptive RR with limits
        def adaptive_rr_final_calc():
            adaptive = self.adaptive_rr
            final = np.maximum(self.rr_absolute_min, np.minimum(adaptive, self.rr_absolute_max))
            return final
        
        self.adaptive_rr_final = self.I(adaptive_rr_final_calc)
        
        # Volatility status tracking
        self.prev_ratio = None
        self.volatility_changed = False

    def next(self):
        # Get current values
        current_ratio = self.atr_ratio[-1]
        current_adaptive_rr = self.adaptive_rr_final[-1]
        
        # Determine volatility status
        if current_ratio < self.atr_low_threshold:
            volatility_status = "Low"
        elif current_ratio > self.atr_high_threshold:
            volatility_status = "High"
        else:
            volatility_status = "Normal"
        
        # Simple trading logic based on volatility and adaptive RR
        # Buy when volatility increases (ratio crosses high threshold)
        # Sell when volatility decreases significantly (ratio crosses low threshold)
        
        if self.prev_ratio is not None:
            prev_ratio = self.prev_ratio
            
            # Check for volatility threshold crossover
            if prev_ratio <= self.atr_high_threshold and current_ratio > self.atr_high_threshold:
                # High volatility detected - potential breakout trade
                if not self.position:
                    self.buy()
            
            elif prev_ratio >= self.atr_low_threshold and current_ratio < self.atr_low_threshold:
                # Low volatility detected - risk reduction
                if self.position:
                    self.position.close()
        
        self.prev_ratio = current_ratio