import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime, time


class TvStrategy(Strategy):
    def init(self):
        # Session time detection using UTC times
        self.asian_active = False
        self.london_active = False
        self.nyam_active = False
        self.nypm_active = False
        self.overlap_active = False
        
        # Killzone tracking
        self.lon_open_kz_active = False
        self.ny_open_kz_active = False
        self.lon_close_kz_active = False
        
        # Silver Bullet tracking
        self.lon_sb_active = False
        self.nyam_sb_active = False
        self.nypm_sb_active = False
        
        # Session state tracking
        self.asian_session_data = {
            'open_price': None, 'high': None, 'low': None, 'volume': 0, 'active': False
        }
        self.london_session_data = {
            'open_price': None, 'high': None, 'low': None, 'volume': 0, 'active': False
        }
        self.nyam_session_data = {
            'open_price': None, 'high': None, 'low': None, 'volume': 0, 'active': False
        }
        self.nypm_session_data = {
            'open_price': None, 'high': None, 'low': None, 'volume': 0, 'active': False
        }
        
        # Prior session reference levels
        self.asian_prior_high = None
        self.asian_prior_low = None
        self.london_prior_high = None
        self.london_prior_low = None
        self.nyam_prior_high = None
        self.nyam_prior_low = None
        self.nypm_prior_high = None
        self.nypm_prior_low = None
        
        # Killzone state
        self.lon_open_kz_high = None
        self.lon_open_kz_low = None
        self.ny_open_kz_high = None
        self.ny_open_kz_low = None
        self.lon_close_kz_high = None
        self.lon_close_kz_low = None

    def is_session_time(self, session_start_hour, session_end_hour):
        """Check if current bar is within session time (simplified for backtesting)"""
        if len(self.data) == 0:
            return False
        
        # Get hour from the current bar's datetime index
        current_time = self.data.index[-1]
        current_hour = current_time.hour
        
        if session_start_hour <= session_end_hour:
            return session_start_hour <= current_hour < session_end_hour
        else:
            return current_hour >= session_start_hour or current_hour < session_end_hour

    def is_weekday(self):
        """Check if current bar is on a weekday (Mon=0, Sun=6)"""
        if len(self.data) == 0:
            return False
        current_time = self.data.index[-1]
        return current_time.weekday() < 5

    def update_session(self, session_data, is_active, high, low, close, volume):
        """Update session tracking data"""
        if is_active and not session_data['active']:
            # Session just started
            session_data['open_price'] = self.data.Open[-1]
            session_data['high'] = high
            session_data['low'] = low
            session_data['volume'] = volume
            session_data['active'] = True
        elif is_active and session_data['active']:
            # Session ongoing
            session_data['high'] = max(session_data['high'], high)
            session_data['low'] = min(session_data['low'], low)
            session_data['volume'] += volume
        elif not is_active and session_data['active']:
            # Session just ended
            if session_data['high'] is not None and session_data['low'] is not None:
                session_data['active'] = False
        
        return session_data

    def next(self):
        if len(self.data) < 2:
            return
        
        is_weekday = self.is_weekday()
        if not is_weekday:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        # Session detection (UTC times)
        asian_active = is_weekday and self.is_session_time(0, 9)
        london_active = is_weekday and self.is_session_time(7, 16)
        nyam_active = is_weekday and self.is_session_time(12, 17)
        nypm_active = is_weekday and self.is_session_time(17, 21)
        overlap_active = is_weekday and self.is_session_time(12, 16)
        
        # Killzone detection
        lon_open_kz = is_weekday and self.is_session_time(7, 8)
        ny_open_kz = is_weekday and self.is_session_time(12, 13)
        lon_close_kz = is_weekday and self.is_session_time(15, 16)
        
        # Silver Bullet detection
        lon_sb = is_weekday and self.is_session_time(10, 11)
        nyam_sb = is_weekday and self.is_session_time(14, 15)
        nypm_sb = is_weekday and self.is_session_time(19, 20)
        
        # Update session tracking
        self.asian_session_data = self.update_session(
            self.asian_session_data, asian_active, high, low, close, volume
        )
        self.london_session_data = self.update_session(
            self.london_session_data, london_active, high, low, close, volume
        )
        self.nyam_session_data = self.update_session(
            self.nyam_session_data, nyam_active, high, low, close, volume
        )
        self.nypm_session_data = self.update_session(
            self.nypm_session_data, nypm_active, high, low, close, volume
        )
        
        # Detect session open breaks
        asian_open_break_up = (
            asian_active and 
            self.asian_session_data['open_price'] is not None and
            close > self.asian_session_data['open_price'] and
            self.data.Close[-2] <= self.asian_session_data['open_price']
        )
        
        london_open_break_up = (
            london_active and 
            self.london_session_data['open_price'] is not None and
            close > self.london_session_data['open_price'] and
            self.data.Close[-2] <= self.london_session_data['open_price']
        )
        
        nyam_open_break_up = (
            nyam_active and 
            self.nyam_session_data['open_price'] is not None and
            close > self.nyam_session_data['open_price'] and
            self.data.Close[-2] <= self.nyam_session_data['open_price']
        )
        
        nypm_open_break_up = (
            nypm_active and 
            self.nypm_session_data['open_price'] is not None and
            close > self.nypm_session_data['open_price'] and
            self.data.Close[-2] <= self.nypm_session_data['open_price']
        )
        
        # Detect killzone openings
        lon_kz_opening = lon_open_kz and not self.lon_open_kz_active
        ny_kz_opening = ny_open_kz and not self.ny_open_kz_active
        
        # Detect prior session high/low breaks
        asian_prior_high_break = (
            asian_active and 
            self.asian_prior_high is not None and
            high > self.asian_prior_high
        )
        
        london_prior_high_break = (
            london_active and 
            self.london_prior_high is not None and
            high > self.london_prior_high
        )
        
        # Trading logic: Buy on session opens with breakout
        if asian_open_break_up and not self.position:
            self.buy()
        elif london_open_break_up and not self.position:
            self.buy()
        elif nyam_open_break_up and not self.position:
            self.buy()
        elif nypm_open_break_up and not self.position:
            self.buy()
        
        # Buy on prior session high breaks
        if asian_prior_high_break and not self.position:
            self.buy()
        elif london_prior_high_break and not self.position:
            self.buy()
        
        # Buy on killzone entries (volatility signals)
        if lon_kz_opening and not self.position:
            self.buy()
        elif ny_kz_opening and not self.position:
            self.buy()
        
        # Sell signals: Exit on session close or opposite breaks
        asian_open_break_down = (
            asian_active and 
            self.asian_session_data['open_price'] is not None and
            close < self.asian_session_data['open_price'] and
            self.data.Close[-2] >= self.asian_session_data['open_price']
        )
        
        if asian_open_break_down and self.position:
            self.sell()
        
        # Store prior session levels at session transitions
        if asian_active and not self.asian_active:
            if self.asian_session_data['high'] is not None:
                self.asian_prior_high = self.asian_session_data['high']
                self.asian_prior_low = self.asian_session_data['low']
        
        if london_active and not self.london_active:
            if self.london_session_data['high'] is not None:
                self.london_prior_high = self.london_session_data['high']
                self.london_prior_low = self.london_session_data['low']
        
        # Update killzone states
        self.lon_open_kz_active = lon_open_kz
        self.ny_open_kz_active = ny_open_kz
        self.lon_close_kz_active = lon_close_kz
        
        # Update session states
        self.asian_active = asian_active
        self.london_active = london_active
        self.nyam_active = nyam_active
        self.nypm_active = nypm_active
        self.overlap_active = overlap_active


