        bearish_score += 1 if rsi < 50 else 0  # Secondary RSI approximation
        
        # Signal detection
        bullish_cross = crossover(self.fast_ma, self.slow_ma)
        bearish_cross = crossover(self.slow_ma, self.fast_ma)
        
        # Apply confluence filter
        confluence_bull_pass = bullish_score >= self.min_confluence_score if self.use_confluence_filter else True
