import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Signal Settings
    fast_ma_period = 9
    slow_ma_period = 21
    bar_close_confirm = True
    
    # Confluence Filter
    use_confluence_filter = True
    min_confluence_score = 4
    
    # Risk Management
    atr_sl_multiplier = 1.5
    atr_period = 14
    target_count = 5
    trail_sl_to_breakeven = True
    
    # Secondary Timeframe RSI (we'll use 14-period RSI on main timeframe for simplicity)
    secondary_rsi_period = 14
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.fast_ma = self.I(pta.ema, close, length=self.fast_ma_period)
        self.slow_ma = self.I(pta.ema, close, length=self.slow_ma_period)
        
        # VWAP calculation
        hlc3 = (high + pd.Series(self.data.High) + low + close) / 3
        vwap_result = self.I(lambda: pta.vwap(high, low, close, volume) or pd.Series(close.iloc[0], index=close.index))
        self.vwap = vwap_result
        
        # ATR for risk management
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macd_main = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        
        # DMI/ADX
        adx_result = self.I(pta.adx, high, low, close, length=14)
        self.adx = adx_result
        
        # Volume average
        self.volume_avg = self.I(pta.sma, volume, length=20)
        
        # State tracking
        self.active_direction = 0  # 0: flat, 1: long, -1: short
        self.entry_price = 0.0
        self.stop_loss_price = 0.0
        self.target_prices = [0.0] * 5
        self.targets_reached = [False] * 5
        self.sl_moved_to_breakeven = False
        self.last_signal_index = -1

    def next(self):
        # Skip if not enough data
        if len(self.data) < max(self.slow_ma_period, self.atr_period) + 1:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        open_price = self.data.Open[-1]
        
        # Get indicator values
        fast_ma = self.fast_ma[-1] if len(self.fast_ma) > 0 else close
        slow_ma = self.slow_ma[-1] if len(self.slow_ma) > 0 else close
        vwap = self.vwap[-1] if len(self.vwap) > 0 else close
        atr = self.atr[-1] if len(self.atr) > 0 else 0
        rsi = self.rsi[-1] if len(self.rsi) > 0 else 50
        adx = self.adx[-1] if len(self.adx) > 0 else 20
        vol_avg = self.volume_avg[-1] if len(self.volume_avg) > 0 else volume
        
        # Get MACD values
        macd_data = self.macd_main[-1]
        if isinstance(macd_data, (pd.Series, dict)):
            if isinstance(macd_data, pd.Series):
                macd_main = macd_data.iloc[0] if len(macd_data) > 0 else 0
                macd_signal = macd_data.iloc[1] if len(macd_data) > 1 else 0
            else:
                macd_main = macd_data.get('MACD_12_26_9', 0)
                macd_signal = macd_data.get('MACDs_12_26_9', 0)
        else:
            macd_main = 0
            macd_signal = 0
        
        # Confluence scoring
        bullish_score = 0
        bullish_score += 1 if close > vwap else 0
        bullish_score += 1 if rsi > 50 else 0
        bullish_score += 1 if macd_main > macd_signal else 0
        bullish_score += 1 if fast_ma > slow_ma else 0
        bullish_score += 1 if adx > 25 and close > fast_ma else 0
        bullish_score += 1 if volume > vol_avg and close > open_price else 0
        bullish_score += 1 if rsi > 50 else 0  # Secondary RSI approximation
        
        bearish_score = 0
        bearish_score += 1 if close < vwap else 0
        bearish_score += 1 if rsi < 50 else 0
        bearish_score += 1 if macd_main < macd_signal else 0
        bearish_score += 1 if fast_ma < slow_ma else 0
        bearish_score += 1 if adx > 25 and close < fast_ma else 0
