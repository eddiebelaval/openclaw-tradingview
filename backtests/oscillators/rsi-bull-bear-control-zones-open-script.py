import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 14

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI manually using RMA (Wilder's smoothing)
        def calculate_rsi(src, length):
            deltas = src.diff()
            seed = deltas[:length+1].std()
            
            ups = deltas.copy()
            downs = deltas.copy()
            ups[ups < 0] = 0
            downs[downs > 0] = 0
            downs = abs(downs)
            
            p_up = ups.ewm(span=length, adjust=False).mean()
            p_down = downs.ewm(span=length, adjust=False).mean()
            
            rs = p_up / p_down
            rsi = 100 - (100 / (1 + rs))
            rsi[rsi.isna()] = 50
            
            return rsi
        
        self.rsi = self.I(lambda: calculate_rsi(close, self.len))

    def next(self):
        # Buy when RSI crosses above 38.2 (Bear zone high - entering recovery)
        if crossover(self.rsi, 38.2):
            if not self.position:
                self.buy()
