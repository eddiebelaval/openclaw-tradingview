class Point:
    def __init__(self, x, y):
        self.x = x
        self.y = y


def get_distance(p1, p2, p0):
    x1, y1 = p1.x, p1.y
    x2, y2 = p2.x, p2.y
    x0, y0 = p0.x, p0.y
    
    dx = x2 - x1
    dy = y2 - y1
    
    numerator = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1)
    denominator = np.sqrt(dy * dy + dx * dx)
    
    return 0 if denominator == 0 else numerator / denominator


def calculate_gbo(close_prices, atr_values, length, mult):
    """Calculate Geometric Bias Oscillator for the last bar"""
    if len(close_prices) < length or atr_values[-1] is None or atr_values[-1] <= 0:
        return 0.0
    
    atr = atr_values[-1]
    threshold = mult
    
    prices = []
    norm_points = []
    
    for i in range(length):
        p = close_prices[-(length - i)]
        prices.append(p)
        norm_points.append(Point(i, p / atr))
    
    n = len(norm_points)
    keep = [False] * n
    keep[0] = True
    keep[n - 1] = True
    
    stack = [0, n - 1]
    
    while len(stack) > 0:
        last_idx = stack.pop()
        first_idx = stack.pop()
        
        max_dist = 0.0
        index = first_idx
        
        p_first = norm_points[first_idx]
        p_last = norm_points[last_idx]
        
        for i in range(first_idx + 1, last_idx):
            d = get_distance(p_first, p_last, norm_points[i])
            if d > max_dist:
                max_dist = d
                index = i
        
        if max_dist > threshold:
            keep[index] = True
            stack.append(index)
            stack.append(last_idx)
            stack.append(first_idx)
            stack.append(index)
    
    bull_sum = 0.0
    bear_sum = 0.0
    last_kept_idx = 0
    
    for i in range(1, n):
        if keep[i]:
            current_price = prices[i]
            prev_price = prices[last_kept_idx]
            diff = current_price - prev_price
            
            if diff > 0:
                bull_sum += diff
            elif diff < 0:
                bear_sum += abs(diff)
            
            last_kept_idx = i
    
    total_magnitude = bull_sum + bear_sum
    smi_value = ((bull_sum - bear_sum) / total_magnitude) * 100.0 if total_magnitude > 0 else 0.0
    
    return smi_value


class TvStrategy(Strategy):
    lengthInput = 100
    multInput = 2.0
    atrLengthInput = 14
    smoothInput = 1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLengthInput)
        
        def gbo_calc():
            if len(self.data) < self.lengthInput:
                return pd.Series(0, index=close.index)
            
            gbo_values = []
            for i in range(len(close)):
                if i < self.lengthInput - 1:
                    gbo_values.append(0.0)
                else:
                    close_slice = close.iloc[i - self.lengthInput + 1:i + 1].values
                    atr_slice = self.atr[max(0, i - self.lengthInput + 1):i + 1]
                    atr_val = atr_slice.iloc[-1] if len(atr_slice) > 0 and atr_slice.iloc[-1] is not None else 0
                    
                    gbo_val = calculate_gbo(close_slice, [atr_val] * len(close_slice), self.lengthInput, self.multInput)
                    gbo_values.append(gbo_val)
            
            return pd.Series(gbo_values, index=close.index)
        
        self.gbo_raw = self.I(gbo_calc)
        self.gbo = self.I(pta.sma, self.gbo_raw, length=self.smoothInput)

    def next(self):
        if len(self.data) < self.lengthInput + self.smoothInput:
            return
        
        if not self.position:
            if crossover(self.gbo, -80):
                self.buy()
            elif crossover(80, self.gbo):
                self.sell()
        else:
            if self.position.is_long and crossover(80, self.gbo):
                self.position.close()
            elif self.position.is_short and crossover(self.gbo, -80):
                self.position.close()