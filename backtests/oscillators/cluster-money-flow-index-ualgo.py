    def _process_pivot(self, pivot_val, is_ob, proximity_val):
        was_clustered = False

        for cluster in self.clusters:
            if cluster['valid'] and cluster['isOB'] == is_ob:
                if abs(pivot_val - cluster['center']) <= proximity_val:
                    cluster['touches'] += 1
                    cluster['lastTouchTime'] = len(self.data)
                    if pivot_val > cluster['top']:
                        cluster['top'] = pivot_val
                    if pivot_val < cluster['bottom']:
                        cluster['bottom'] = pivot_val
                    cluster['center'] = (cluster['top'] + cluster['bottom']) / 2.0
                    was_clustered = True
                    break

        if not was_clustered:
            zone_half = max(proximity_val * 0.15, 0.8)
            new_cluster = {
                'top': pivot_val + zone_half,
                'bottom': pivot_val - zone_half,
                'center': pivot_val,
                'isOB': is_ob,
                'touches': 1,
                'firstBarTime': len(self.data),
                'lastTouchTime': len(self.data),
                'valid': True
            }
            self.clusters.append(new_cluster)

            if len(self.clusters) > 40:
                self.clusters.pop(0)

        for cluster in self.clusters:
            if cluster['valid']:
                raw_mfi = self.rawMFI[-1]
                if cluster['isOB']:
                    if raw_mfi > cluster['top'] + 2:
                        cluster['valid'] = False
                else:
                    if raw_mfi < cluster['bottom'] - 2:
                        cluster['valid'] = False


