class TvStrategy(Strategy):
    roc_length = 18

    def init(self):
        close = pd.Series(self.data.Close)
        self.roc = self.I(pta.roc, close, length=self.roc_length)

    def next(self):
        if len(self.data) < self.roc_length + 1:
            return
        
        current_roc = self.roc[-1]
        
        if current_roc is None:
            return
        
        if current_roc < -10 and (len(self.roc) < 2 or self.roc[-2] >= -10):
            if not self.position:
                self.buy()
        
        elif current_roc > 0 and (len(self.roc) < 2 or self.roc[-2] <= 0):
            if self.position:
                self.sell()