import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ls_len = 21
    smooth_len = 4
    sd_len = 32
    sd_mult = 2.9
    long_threshold = 76
    short_threshold = 30
    trade_mode = "Long/Cash"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)

        def calc_linreg(src, length):
            result = pd.Series(index=src.index, dtype=float)
            for i in range(len(src)):
                if i < length - 1:
                    result.iloc[i] = np.nan
                else:
                    x = np.arange(length)
                    y = src.iloc[i - length + 1:i + 1].values
                    coeffs = np.polyfit(x, y, 1)
                    result.iloc[i] = coeffs[0] * (length - 1) + coeffs[1]
            return result

        def calc_stdev(src, length):
            return src.rolling(window=length).std()

        raw_lsma = self.I(lambda: calc_linreg(close, self.ls_len))
        basis = self.I(lambda: pta.ema(raw_lsma, length=self.smooth_len) or pd.Series(close.iloc[-1], index=close.index))
        dev = self.I(lambda: self.sd_mult * calc_stdev(close, self.sd_len))
        upper = self.I(lambda: basis + dev)
        lower = self.I(lambda: basis - dev)

        band_rng = self.I(lambda: upper - lower)

        self.osc = self.I(lambda: self._calc_osc(close, lower, band_rng))
        self.raw_lsma = raw_lsma
        self.basis = basis
        self.dev = dev
        self.upper = upper
        self.lower = lower
        self.band_rng = band_rng

        self.in_long = False

    def _calc_osc(self, src, lower, band_rng):
        osc = pd.Series(index=src.index, dtype=float)
        for i in range(len(src)):
            if pd.isna(band_rng.iloc[i]) or band_rng.iloc[i] <= 0:
                osc.iloc[i] = 50.0
            else:
                osc.iloc[i] = 100.0 * (src.iloc[i] - lower.iloc[i]) / band_rng.iloc[i]
        return osc

    def next(self):
        if len(self) < max(self.ls_len, self.sd_len):
            return

        if pd.isna(self.osc[-1]):
            return

        osc_current = self.osc[-1]
        osc_prev = self.osc[-2] if len(self.osc) > 1 else self.osc[-1]

        long_crossover = osc_prev <= self.long_threshold and osc_current > self.long_threshold
        short_crossunder = osc_prev >= self.short_threshold and osc_current < self.short_threshold

        if long_crossover and not self.position:
            self.buy()
            self.in_long = True
        elif short_crossunder:
            if self.position:
                self.position.close()
            self.in_long = False