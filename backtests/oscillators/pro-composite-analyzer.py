        # MACD histogram normalized
        def macd_norm_calc():
            macd_result = pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_signal)
            if macd_result is None or macd_result.empty:
                return pd.Series(0, index=close.index)
            hist = macd_result.iloc[:, 2] if macd_result.shape[1] > 2 else macd_result.iloc[:, 0]
            mx = hist.abs().rolling(self.macd_norm_len).max()
            return (hist / mx.clip(lower=1e-10)).clip(-1, 1)
        self.macd_norm = self.I(macd_norm_calc)
        
        # Stochastic RSI normalized
        def srsi_norm_calc():
            rsi_vals = pta.rsi(close, length=self.srsi_rsi_len)
            if rsi_vals is None:
                return pd.Series(0, index=close.index)
            lo = rsi_vals.rolling(self.srsi_stoch_len).min()
            hi = rsi_vals.rolling(self.srsi_stoch_len).max()
            k = 100.0 * (rsi_vals - lo) / (hi - lo).clip(lower=1e-10)
            ks = pta.sma(k, length=self.srsi_k_smooth)
            return (ks - 50.0) / 50.0 if ks is not None else pd.Series(0, index=close.index)
        self.srsi_norm = self.I(srsi_norm_calc)
        
        # CCI normalized
        def cci_norm_calc():
            cci = pta.cci(high, low, close, length=self.cci_length)
            if cci is None:
                return pd.Series(0, index=close.index)
            mx = cci.abs().rolling(self.cci_norm_len).max()
            return (cci / mx.clip(lower=1e-10)).clip(-1, 1)
        self.cci_norm = self.I(cci_norm_calc)
        
        # ADX normalized
