import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 9
    slowLen = 21
    trendLen = 50
    volumeLen = 20
    normLen = 100
    signalLen = 7
    obLevel = 60.0
    osLevel = -60.0
    requireZeroConf = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # 1) Momentum component
        fastEma = self.I(pta.ema, close, length=self.fastLen)
        slowEma = self.I(pta.ema, close, length=self.slowLen)
        rawMomentum = fastEma - slowEma
        
        def normalize_momentum(series_data):
            if len(series_data) < self.normLen:
                return pd.Series(0, index=series_data.index)
            hi = series_data.rolling(window=self.normLen).max()
            lo = series_data.rolling(window=self.normLen).min()
            rng = hi - lo
            result = ((series_data - lo) / rng.replace(0, 1)) * 200 - 100
            return result.fillna(0)
        
        momentumNorm = self.I(normalize_momentum, rawMomentum)

        # 2) Trend bias component
        trendEma = self.I(pta.ema, close, length=self.trendLen)
        trendDelta = close - trendEma
        trendNorm = self.I(normalize_momentum, trendDelta)

        # 3) Volume pressure component
        spread = high - low
        def calc_vol_pressure():
            safe_spread = spread.copy()
            safe_spread[safe_spread == 0] = 0.00001
            closePosInBar = ((close - low) / safe_spread) * 2 - 1
            volPressureRaw = closePosInBar * volume
            volPressureSmooth = pta.ema(volPressureRaw, length=self.volumeLen)
            if volPressureSmooth is None:
                return pd.Series(0, index=close.index)
            return volPressureSmooth
        
        volPressureSmooth = self.I(calc_vol_pressure)
        volNorm = self.I(normalize_momentum, volPressureSmooth)

        # Signal Goat Oscillator
        def calc_osc():
            rawOsc = (momentumNorm * 0.45) + (trendNorm * 0.35) + (volNorm * 0.20)
            sgOsc = pta.ema(rawOsc, length=3)
            if sgOsc is None:
                return pd.Series(0, index=close.index), pd.Series(0, index=close.index)
            signal = pta.ema(sgOsc, length=self.signalLen)
            if signal is None:
                signal = pd.Series(0, index=close.index)
            return sgOsc, signal
        
        def get_osc_only():
            result = calc_osc()
            return result[0]
        
        def get_signal_only():
            result = calc_osc()
            return result[1]

