import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 14
    lookbackInput = 5

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate Volume Delta
        volume_delta = pd.Series(np.where(close > open_, volume, np.where(close < open_, -volume, 0)), index=close.index)
        
        # Calculate oscillator (EMA of Volume Delta)
        self.oscillator = self.I(lambda: pta.ema(volume_delta, length=self.lengthInput) or pd.Series(0, index=close.index))
        
        # Highest and lowest for divergence detection
        self.price_high = self.I(lambda: high.rolling(window=self.lookbackInput).max())
        self.price_low = self.I(lambda: low.rolling(window=self.lookbackInput).min())
        self.osc_high = self.I(lambda: self.oscillator.rolling(window=self.lookbackInput).max())
        self.osc_low = self.I(lambda: self.oscillator.rolling(window=self.lookbackInput).min())
        
        # For pivot detection - oscillator extreme over 2*lookbackInput + 1 window
        window_size = self.lookbackInput * 2 + 1
        self.osc_highest = self.I(lambda: self.oscillator.rolling(window=window_size).max())
        self.osc_lowest = self.I(lambda: self.oscillator.rolling(window=window_size).min())
        
        # Store previous pivot values
        self.prev_top_price = None
        self.prev_top_osc = None
        self.prev_bot_price = None
        self.prev_bot_osc = None

    def next(self):
        # Check if we have enough data
        if len(self.data) < self.lookbackInput * 2 + 1:
            return
        
        current_idx = len(self.data) - 1
        
        # Check if current oscillator is at a high pivot
        is_high = (
            self.oscillator[-1] == self.osc_highest[-1] and 
            self.osc_highest[-1] is not None and
            not np.isnan(self.osc_highest[-1])
        )
        
        # Check if current oscillator is at a low pivot
        is_low = (
            self.oscillator[-1] == self.osc_lowest[-1] and 
            self.osc_lowest[-1] is not None and
            not np.isnan(self.osc_lowest[-1])
        )
        
        # Update pivot values
        if is_high:
            self.prev_top_price = self.data.High[-1]
            self.prev_top_osc = self.oscillator[-1]
        
        if is_low:
            self.prev_bot_price = self.data.Low[-1]
            self.prev_bot_osc = self.oscillator[-1]
        
        # Bullish Divergence: lower low in price but higher low in oscillator
        bull_div = (
            is_low and 
            self.prev_bot_price is not None and
            self.prev_bot_osc is not None and
            self.data.Low[-1] < self.prev_bot_price and
            self.oscillator[-1] > self.prev_bot_osc
        )
        
        # Bearish Divergence: higher high in price but lower high in oscillator
        bear_div = (
            is_high and 
            self.prev_top_price is not None and
            self.prev_top_osc is not None and
            self.data.High[-1] > self.prev_top_price and
            self.oscillator[-1] < self.prev_top_osc
        )
        
        # Trading signals based on divergence
        if bull_div:
            if not self.position:
                self.buy()
        
        if bear_div:
            if self.position:
                self.sell()


