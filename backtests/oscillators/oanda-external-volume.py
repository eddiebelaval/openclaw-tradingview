import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_length = 20

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Since we're working with single data source in backtest,
        # we treat the volume as aggregate volume from multiple sources
        self.total_vol = volume
        
        # Calculate volume moving average
        self.avg_vol = self.I(pta.sma, volume, length=self.ma_length)

    def next(self):
        # Buy when current volume is above the MA (volume surge)
        # and price is rising (close > open)
        if len(self) > self.ma_length:
            current_vol = self.total_vol.iloc[-1]
            avg_vol_val = self.avg_vol[-1]
            
            if current_vol > avg_vol_val and self.data.Close[-1] > self.data.Open[-1]:
                if not self.position:
                    self.buy()
            
            # Sell when volume drops below MA or price is falling
            elif current_vol < avg_vol_val or self.data.Close[-1] < self.data.Open[-1]:
                if self.position:
                    self.sell()


