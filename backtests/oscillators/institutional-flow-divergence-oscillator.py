import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 14
    smoothInput = 5
    pivotLookback = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Institutional Flow Proxy
        def calc_flow_raw():
            price_range = self.data.High - self.data.Low
            flow_raw = np.where(
                price_range != 0,
                ((self.data.Close - self.data.Low) - (self.data.High - self.data.Close)) / price_range * self.data.Volume,
                0.0
            )
            return pd.Series(flow_raw, index=close.index)

        flow_raw_series = self.I(calc_flow_raw)

        # Flow EMA
        def calc_flow_ema():
            return pta.ema(flow_raw_series, length=self.lengthInput) or pd.Series(0, index=close.index)

        flow_ema = self.I(calc_flow_ema)

        # Up Flow and Down Flow
        def calc_up_flow():
            flow_diff = flow_ema.diff()
            up = np.maximum(flow_diff, 0)
            return pta.ema(pd.Series(up, index=close.index), length=self.lengthInput) or pd.Series(0, index=close.index)

        def calc_down_flow():
            flow_diff = flow_ema.diff()
            down = np.maximum(-flow_diff, 0)
            return pta.ema(pd.Series(down, index=close.index), length=self.lengthInput) or pd.Series(0, index=close.index)

        up_flow = self.I(calc_up_flow)
        down_flow = self.I(calc_down_flow)

        # RSI Flow
        def calc_rsi_flow():
            rsi_values = []
            for i in range(len(up_flow)):
                if down_flow.iloc[i] == 0:
                    rsi_val = 100 if up_flow.iloc[i] > 0 else 0
                elif up_flow.iloc[i] == 0:
                    rsi_val = 0
                else:
                    rsi_val = 100 - (100 / (1 + up_flow.iloc[i] / down_flow.iloc[i]))
                rsi_values.append(rsi_val)
            return pd.Series(rsi_values, index=close.index)

        rsi_flow = self.I(calc_rsi_flow)

        # Centered Oscillator
        def calc_oscillator():
            centered = rsi_flow - 50
            return pta.ema(centered, length=self.smoothInput) * 2 or pd.Series(0, index=close.index)

        self.oscillator = self.I(calc_oscillator)

        # Pivot Highs and Lows
        def calc_pivot_high():
            pivots = []
            for i in range(len(self.data.High)):
                if i < self.pivotLookback or i >= len(self.data.High) - self.pivotLookback:
                    pivots.append(np.nan)
                else:
                    left = self.data.High[i-self.pivotLookback:i]
                    right = self.data.High[i+1:i+self.pivotLookback+1]
                    if self.data.High[i] > left.max() and self.data.High[i] > right.max():
                        pivots.append(self.data.High[i])
                    else:
                        pivots.append(np.nan)
            return pd.Series(pivots, index=close.index)

        def calc_pivot_low():
            pivots = []
            for i in range(len(self.data.Low)):
                if i < self.pivotLookback or i >= len(self.data.Low) - self.pivotLookback:
                    pivots.append(np.nan)
                else:
                    left = self.data.Low[i-self.pivotLookback:i]
                    right = self.data.Low[i+1:i+self.pivotLookback+1]
                    if self.data.Low[i] < left.min() and self.data.Low[i] < right.min():
                        pivots.append(self.data.Low[i])
                    else:
                        pivots.append(np.nan)
            return pd.Series(pivots, index=close.index)

        def calc_osc_pivot_high():
            pivots = []
            for i in range(len(self.oscillator)):
                if i < self.pivotLookback or i >= len(self.oscillator) - self.pivotLookback:
                    pivots.append(np.nan)
                else:
                    left = self.oscillator.iloc[i-self.pivotLookback:i]
                    right = self.oscillator.iloc[i+1:i+self.pivotLookback+1]
                    if self.oscillator.iloc[i] > left.max() and self.oscillator.iloc[i] > right.max():
                        pivots.append(self.oscillator.iloc[i])
                    else:
                        pivots.append(np.nan)
            return pd.Series(pivots, index=close.index)

        def calc_osc_pivot_low():
            pivots = []
            for i in range(len(self.oscillator)):
                if i < self.pivotLookback or i >= len(self.oscillator) - self.pivotLookback:
                    pivots.append(np.nan)
                else:
                    left = self.oscillator.iloc[i-self.pivotLookback:i]
                    right = self.oscillator.iloc[i+1:i+self.pivotLookback+1]
                    if self.oscillator.iloc[i] < left.min() and self.oscillator.iloc[i] < right.min():
                        pivots.append(self.oscillator.iloc[i])
                    else:
                        pivots.append(np.nan)
            return pd.Series(pivots, index=close.index)

        self.price_ph = self.I(calc_pivot_high)
        self.price_pl = self.I(calc_pivot_low)
        self.osc_ph = self.I(calc_osc_pivot_high)
        self.osc_pl = self.I(calc_osc_pivot_low)

        self.last_osc_low = np.nan
        self.last_price_low = np.nan
        self.last_osc_high = np.nan
        self.last_price_high = np.nan

    def next(self):
        current_osc = self.oscillator[-1]
        current_price_high = self.data.High[-1]
        current_price_low = self.data.Low[-1]

        bull_div = False
        bear_div = False

        # Detect pivot lows
        if not np.isnan(self.osc_pl[-1]):
            if not np.isnan(self.last_osc_low):
                if current_osc > self.last_osc_low and current_price_low < self.last_price_low:
                    bull_div = True
            self.last_osc_low = current_osc
            self.last_price_low = current_price_low

        # Detect pivot highs
        if not np.isnan(self.osc_ph[-1]):
            if not np.isnan(self.last_osc_high):
                if current_osc < self.last_osc_high and current_price_high > self.last_price_high:
                    bear_div = True
            self.last_osc_high = current_osc
            self.last_price_high = current_price_high

        # Trading logic: Buy on bullish divergence, sell on bearish divergence
        if bull_div:
            if not self.position:
                self.buy()
        elif bear_div:
            if self.position:
                self.sell()


