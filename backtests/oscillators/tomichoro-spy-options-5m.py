import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Moving Average parameters
    short_ma_period = 8
    long_ma_period = 21
    bonus_ma1_period = 34
    
    # VWAP parameters
    vwap_sd1 = 1.0
    vwap_sd2 = 2.0
    vwap_sd3 = 3.0
    
    # A+ Filter parameters
    pivot_len = 5
    tol_pct = 0.05
    vol_len = 20
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Moving Averages
        self.short_ma = self.I(pta.ema, close, length=self.short_ma_period)
        self.long_ma = self.I(pta.ema, close, length=self.long_ma_period)
        self.bonus_ma1 = self.I(pta.ema, close, length=self.bonus_ma1_period)
        
        # VWAP calculation
        hlc3 = (high + low + close) / 3
        
        def calc_vwap():
            vwap_values = []
            cumsum_pv = 0
            cumsum_v = 0
            cumsum_pv2 = 0
            
            for i in range(len(hlc3)):
                cumsum_v += volume.iloc[i]
                cumsum_pv += hlc3.iloc[i] * volume.iloc[i]
                cumsum_pv2 += (hlc3.iloc[i] ** 2) * volume.iloc[i]
                
                if cumsum_v > 0:
                    mvwap = cumsum_pv / cumsum_v
                    variance = (cumsum_pv2 / cumsum_v) - (mvwap ** 2)
                    variance = max(0, variance)
                    std_dev = np.sqrt(variance)
                    vwap_values.append(mvwap)
                else:
                    vwap_values.append(np.nan)
            
            return pd.Series(vwap_values, index=hlc3.index)
        
        self.vwap = self.I(calc_vwap)
        
        # Volume SMA for filter
        self.vol_sma = self.I(pta.sma, volume, length=self.vol_len)
        
        # Pivot detection for Fibonacci
        def calc_pivot_high():
            pivots = []
            for i in range(len(high)):
                if i < self.pivot_len or i >= len(high) - self.pivot_len:
                    pivots.append(np.nan)
                else:
                    window = high.iloc[i-self.pivot_len:i+self.pivot_len+1]
                    if high.iloc[i] == window.max():
                        pivots.append(high.iloc[i])
                    else:
                        pivots.append(np.nan)
            return pd.Series(pivots, index=high.index)
        
        def calc_pivot_low():
            pivots = []
            for i in range(len(low)):
                if i < self.pivot_len or i >= len(low) - self.pivot_len:
                    pivots.append(np.nan)
                else:
                    window = low.iloc[i-self.pivot_len:i+self.pivot_len+1]
                    if low.iloc[i] == window.min():
                        pivots.append(low.iloc[i])
                    else:
                        pivots.append(np.nan)
            return pd.Series(pivots, index=low.index)
        
        self.pivot_high = self.I(calc_pivot_high)
        self.pivot_low = self.I(calc_pivot_low)
        
        # Crossover signals
        self.bull_signal = self.I(lambda: crossover(self.short_ma, self.long_ma))
        self.bear_signal = self.I(lambda: crossover(self.long_ma, self.short_ma))
    
    def next(self):
        # Skip if we don't have enough data
        if len(self.data) < max(self.short_ma_period, self.long_ma_period, self.pivot_len * 2 + 1):
            return
        
        # Base crossover signals
        bull = crossover(self.short_ma, self.long_ma)
        bear = crossover(self.long_ma, self.short_ma)
        
        # VWAP filter
        vwap_call_ok = self.data.Close[-1] > self.vwap[-1]
        vwap_put_ok = self.data.Close[-1] < self.vwap[-1]
        
        # Volume filter
        vol_ok = self.data.Volume[-1] > self.vol_sma[-1]
        
        # Fibonacci zone filter - simplified
        # Look for last pivot high and low
        last_pivot_h = None
        last_pivot_l = None
        last_h_idx = -1
        last_l_idx = -1
        
        for i in range(len(self.data) - 1, max(0, len(self.data) - 100), -1):
            if last_pivot_h is None and not np.isnan(self.pivot_high[i]):
                last_pivot_h = self.pivot_high[i]
                last_h_idx = i
            if last_pivot_l is None and not np.isnan(self.pivot_low[i]):
                last_pivot_l = self.pivot_low[i]
                last_l_idx = i
            if last_pivot_h is not None and last_pivot_l is not None:
                break
        
        in_fib_zone = False
        if last_pivot_h is not None and last_pivot_l is not None:
            rng = abs(last_pivot_h - last_pivot_l)
