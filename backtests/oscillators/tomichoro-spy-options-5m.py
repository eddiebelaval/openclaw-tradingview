        # A+ Put: Bear + Fib + VWAP below + Volume
        a_plus_put = bear and in_fib_zone and vwap_put_ok and vol_ok
        
        # Trading logic
        if a_plus_call and not self.position:
            self.buy()
        elif a_plus_put and self.position:
            self.position.close()