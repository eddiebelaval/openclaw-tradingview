import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sell_zone_level = 0.90
    buy_zone_level = 0.10

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate SMA111 and SMA350*2 on daily data
        # Since we're working with daily data already, calculate directly
        sma111 = self.I(pta.sma, close, length=111)
        sma350x2 = self.I(pta.sma, close, length=350)
        
        # Create ratio: SMA111 / (SMA350 * 2)
        self.ratio = self.I(lambda: sma111 / (sma350x2 * 2.0))
        
        # Constants from Pine Script
        ratio_start_ms = 1292275200000  # Dec 13 2010 in milliseconds
        ms_in_day = 86400000
        top_offset_days = -53
        
        bottom_k = -0.0000000000000939
        bottom_b = 0.3256784268173674
        top_a = -0.1511868254833189
        top_b = 5.007692389976341
        
        # Calculate lines based on time
        def calculate_lines():
            times = self.data.index.astype(np.int64) // 10**6  # Convert to milliseconds
            days_since_ratio_start = times - ratio_start_ms
            
            bottom_line = bottom_k * days_since_ratio_start + bottom_b
            top_line = top_a * np.log(days_since_ratio_start + top_offset_days * ms_in_day) + top_b
            middle_line = bottom_line + (top_line - bottom_line) / 2.0
            
            risk_value = (sma111 / (sma350x2 * 2.0) - bottom_line) / (top_line - bottom_line)
            sell_level = bottom_line + (top_line - bottom_line) * self.sell_zone_level
            buy_level = bottom_line + (top_line - bottom_line) * self.buy_zone_level
            
            return pd.DataFrame({
                'bottom_line': bottom_line,
                'top_line': top_line,
                'middle_line': middle_line,
                'risk_value': risk_value,
                'sell_level': sell_level,
                'buy_level': buy_level
            })
        
        lines_df = calculate_lines()
        self.bottom_line = self.I(lambda: lines_df['bottom_line'])
        self.top_line = self.I(lambda: lines_df['top_line'])
        self.risk_value = self.I(lambda: lines_df['risk_value'])
        self.sell_level = self.I(lambda: lines_df['sell_level'])
        self.buy_level = self.I(lambda: lines_df['buy_level'])

    def next(self):
        if len(self.data) < 400:  # Need enough data for 350 SMA
            return
        
        # Buy when risk_value crosses below buy_zone_level from above
        if crossover(self.buy_zone_level, self.risk_value):
            if not self.position:
                self.buy()
        
        # Sell when risk_value crosses above sell_zone_level from below
        elif crossover(self.risk_value, self.sell_zone_level):
            if self.position:
                self.sell()


