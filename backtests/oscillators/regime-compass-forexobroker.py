import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Detection parameters
    adx_len = 14
    adx_smooth = 14
    bb_len = 20
    bb_mult = 2.0
    atr_len = 14
    hurst_len = 100
    
    # Threshold parameters
    strong_trend_adx = 30.0
    weak_trend_adx = 20.0
    high_vol_bbw = 75
    low_vol_bbw = 25
    high_vol_atr = 75
    hurst_trend = 0.55
    hurst_mean_rev = 0.45
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ADX calculation
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_len) or pd.DataFrame({'ADX': [50]*len(close)}))
        self.adx_val = self.I(lambda: adx_result['ADX'] if isinstance(adx_result, pd.DataFrame) and 'ADX' in adx_result.columns else pd.Series([50]*len(close)))
        
        # Bollinger Band Width
        bbw_result = self.I(lambda: pta.bbands(close, length=self.bb_len, std=self.bb_mult) or pd.DataFrame())
        self.bbw = self.I(lambda: (bbw_result['BBL_' + str(self.bb_len) + '_' + str(self.bb_mult)] - bbw_result['BBU_' + str(self.bb_len) + '_' + str(self.bb_mult)]).abs() if isinstance(bbw_result, pd.DataFrame) and len(bbw_result.columns) > 0 else pd.Series([0]*len(close)))
        
        # Simple moving average for BBW percentrank fallback
        self.bbw_rank = self.I(lambda: self._percentrank(self.bbw, 100) or pd.Series([50]*len(close)))
        
        # ATR calculation
        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.atr_len) or pd.Series([1]*len(close)))
        self.atr_rank = self.I(lambda: self._percentrank(self.atr_val, 100) or pd.Series([50]*len(close)))
        
        # Hurst Exponent calculation
        self.hurst = self.I(self._calculate_hurst, close)
        
        # Compass calculation
        self.compass = self.I(lambda: self._calculate_compass())
        
        # Regime classification
        self.regime = self.I(lambda: self._classify_regime())
        
        # Track previous regime for change detection
        self.prev_regime = 1
        
    def _percentrank(self, series, period):
        if series is None or len(series) == 0:
            return pd.Series([50]*len(self.data.Close))
        try:
            result = series.rolling(window=period).apply(lambda x: (x[-1] > x).sum() / len(x) * 100, raw=False)
            return result.fillna(50)
        except:
            return pd.Series([50]*len(series))
    
    def _calculate_hurst(self, close):
        if len(close) < self.hurst_len:
            return pd.Series([0.5]*len(close))
        
        hurst_values = []
        for i in range(len(close)):
            if i < self.hurst_len:
                hurst_values.append(0.5)
                continue
            
            window = close.iloc[i-self.hurst_len:i].values
            log_returns = np.diff(np.log(window))
            
            if len(log_returns) < 2 or np.std(log_returns) == 0:
                hurst_values.append(0.5)
                continue
            
            mean_ret = np.mean(log_returns)
            deviations = log_returns - mean_ret
            cum_dev = np.cumsum(deviations)
            
            range_val = np.max(cum_dev) - np.min(cum_dev)
            std_dev = np.std(log_returns)
            
            rs_ratio = range_val / std_dev if std_dev > 0 else 1.0
            h = np.log(rs_ratio) / np.log(self.hurst_len) if self.hurst_len > 1 else 0.5
            h = max(0.0, min(1.0, h))
            hurst_values.append(h)
        
        return pd.Series(hurst_values)
    
    def _calculate_compass(self):
        if len(self.adx_val) == 0 or len(self.bbw_rank) == 0 or len(self.atr_rank) == 0 or len(self.hurst) == 0:
            return pd.Series([50]*len(self.data.Close))
        
        adx_norm = (self.adx_val / 100.0 * 25).fillna(25)
        bbw_norm = (self.bbw_rank / 100.0 * 25).fillna(25)
        atr_norm = (self.atr_rank / 100.0 * 25).fillna(25)
        hurst_norm = (self.hurst * 25).fillna(12.5)
        
        compass_raw = adx_norm + bbw_norm + atr_norm + hurst_norm
        compass_ema = pta.ema(compass_raw, length=5)
        return compass_ema.fillna(50)
    
    def _classify_regime(self):
        regimes = []
        
        for i in range(len(self.data.Close)):
            if i < max(self.adx_len, self.bb_len, self.atr_len, self.hurst_len):
                regimes.append(1)
                continue
            
            adx = self.adx_val.iloc[i] if i < len(self.adx_val) else 20
            bbw_rank = self.bbw_rank.iloc[i] if i < len(self.bbw_rank) else 50
            atr_rank = self.atr_rank.iloc[i] if i < len(self.atr_rank) else 50
            hurst = self.hurst.iloc[i] if i < len(self.hurst) else 0.5
            
            trend_votes = 0
            range_votes = 0
            volatile_votes = 0
            
            # ADX voting
            if adx > self.strong_trend_adx:
                trend_votes += 2
            elif adx > self.weak_trend_adx:
                trend_votes += 1
            else:
                range_votes += 1
            
            # BB Width voting
            if bbw_rank > self.high_vol_bbw:
                trend_votes += 1
                volatile_votes += 1
            elif bbw_rank < self.low_vol_bbw:
                range_votes += 2
            
            # ATR voting
            if atr_rank > self.high_vol_atr:
                volatile_votes += 2
            elif atr_rank < self.low_vol_bbw:
                range_votes += 1
            
            # Hurst voting
            if hurst > self.hurst_trend:
                trend_votes += 2
            elif hurst < self.hurst_mean_rev:
                range_votes += 2
            else:
                volatile_votes += 1
            
            # Classification
            if volatile_votes >= 4:
                regime = 3
            elif trend_votes > range_votes and trend_votes > volatile_votes:
                regime = 0 if adx > self.strong_trend_adx else 1
            elif range_votes >= trend_votes:
                regime = 2
            else:
                regime = 1
            
            regimes.append(regime)
        
        return pd.Series(regimes)
    
    def next(self):
        if len(self) < max(self.adx_len, self.bb_len, self.atr_len, self.hurst_len):
            return
        
        current_regime = int(self.regime[-1]) if len(self.regime) > 0 else 1
        compass_val = self.compass[-1] if len(self.compass) > 0 else 50
        
        # Trading logic based on regime
        if current_regime == 0:  # Strong Trend
            if not self.position:
                self.buy()
        elif current_regime == 1:  # Weak Trend
            if not self.position:
                self.buy()
        elif current_regime == 2:  # Ranging
            if self.position:
                self.sell()
        elif current_regime == 3:  # Volatile
            if self.position:
                self.sell()
        
        # Exit on regime change to volatile or ranging
        if current_regime in [2, 3] and self.position:
            self.sell()