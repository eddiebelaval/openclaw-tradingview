import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    maLength = 14
    maType = "SMA"
    obLevel = 70
    osLevel = 30

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        
        # Calculate MA on RSI based on maType
        if self.maType == "SMA":
            self.rsiMA = self.I(pta.sma, self.rsi, length=self.maLength)
        elif self.maType == "EMA":
            self.rsiMA = self.I(pta.ema, self.rsi, length=self.maLength)
        elif self.maType == "SMMA (RMA)":
            self.rsiMA = self.I(pta.rma, self.rsi, length=self.maLength)
        elif self.maType == "WMA":
            self.rsiMA = self.I(pta.wma, self.rsi, length=self.maLength)
        elif self.maType == "VWMA":
            self.rsiMA = self.I(pta.vwma, close, volume, length=self.maLength)
        else:
            self.rsiMA = self.I(pta.sma, self.rsi, length=self.maLength)

    def next(self):
        # Buy when RSI crosses above oversold level and is below the MA
        if crossover(self.osLevel, self.rsi):
            if not self.position:
                self.buy()
        
        # Sell when RSI crosses below overbought level or RSI crosses below its MA
        elif crossover(self.rsi, self.obLevel):
            if self.position:
                self.sell()
        
        # Alternative sell: RSI crosses below its MA
        elif crossover(self.rsiMA, self.rsi):
            if self.position:
                self.sell()


