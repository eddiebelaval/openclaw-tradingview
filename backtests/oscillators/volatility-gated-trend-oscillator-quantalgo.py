        # Update trend state and locked value
        if idx == 0:
            current_raw = self.raw_diff[-1] if self.raw_diff[-1] is not None else 0
            current_noise = self.noise_floor[-1] if self.noise_floor[-1] is not None else 0
            
            if current_raw > current_noise:
                self.trend_state[idx] = 1
                self.locked_val[idx] = current_raw
