        # K-Means Update Logic
        d1 = abs(rsi_value - self.c1)
        d2 = abs(rsi_value - self.c2)
        d3 = abs(rsi_value - self.c3)
        d4 = abs(rsi_value - self.c4)
        d5 = abs(rsi_value - self.c5)
        
        min_dist = min(d1, d2, d3, d4, d5)
        
        # Update winning centroid
        if min_dist == d1:
            self.c1 += (rsi_value - self.c1) * self.alphaInput
        elif min_dist == d2:
            self.c2 += (rsi_value - self.c2) * self.alphaInput
        elif min_dist == d3:
            self.c3 += (rsi_value - self.c3) * self.alphaInput
