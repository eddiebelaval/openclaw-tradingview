        dev_std = self.I(lambda: deviation_smooth.rolling(50).std())
        dev_scaled = self.I(lambda: np.where(dev_std > 0, deviation_smooth / (dev_std * 2) * 1.5, 0))
        
        # FORMULA 2: COMPOSITE
        rsi = self.I(pta.rsi, close, length=14)
        stoch = self.I(pta.stoch, high, low, close, k=14, d=3, smooth_k=3)
        cci = self.I(pta.cci, high, low, close, length=20)
        
        rsi_centered = self.I(lambda: (rsi - 50) / 50)
        stoch_centered = self.I(lambda: (stoch - 50) / 50)
        cci_norm = self.I(lambda: cci / 150)
        
        composite = self.I(lambda: (rsi_centered + stoch_centered * 2 + cci_norm) / 3)
        composite_smoothed = self.I(pta.ema, composite, length=self.smooth_period)
        composite_scaled = self.I(lambda: composite_smoothed * 2)
        
        # FORMULA 3: MOMENTUM
        roc = self.I(lambda: ((close - close.shift(self.ma_period)) / close.shift(self.ma_period)) * 100)
        roc_smooth = self.I(pta.ema, roc, length=self.smooth_period)
        roc_std = self.I(lambda: roc_smooth.rolling(50).std())
        roc_scaled = self.I(lambda: np.where(roc_std > 0, roc_smooth / (roc_std * 2) * 1.5, 0))
        
