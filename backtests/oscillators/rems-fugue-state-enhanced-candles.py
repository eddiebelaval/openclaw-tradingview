import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI Parameters
    rsi_length = 14
    rsi_sma_length = 20
    rsi_lookback = 3
    rsi_lookahead = 3
    rsi_deadzone = 0.0
    rsi_threshold = 0.0
    rsi_mode = "RSI vs 50"
    rsi_observe = "Confirm"
    
    # EMA Parameters
    ema_fast_len = 8
    ema_slow_len = 21
    ema_lookback = 3
    ema_lookahead = 3
    ema_deadzone = 0.0
    ema_threshold = 0.0
    ema_observe = "Confirm"
    
    # MACD Parameters
    macd_fast_len = 12
    macd_slow_len = 26
    macd_signal_len = 9
    macd_lookback = 3
    macd_lookahead = 3
    macd_deadzone = 0.0
    macd_threshold = 0.0
    macd_observe = "Confirm"
    
    # Stochastic Parameters
    stoch_mode = "Stochastic RSI"
    stoch_rsi_len = 14
    stoch_k_len = 8
    stoch_k_smooth = 3
    stoch_d_smooth = 3
    stoch_lookback = 3
    stoch_deadzone = 0.0
    stoch_threshold = 0.0
    stoch_obs_mode = "Confirm"
    stoch_range_mode = "Ignore"
    stoch_min_long = 0.0
    stoch_max_long = 90.0
    stoch_min_short = 10.0
    stoch_max_short = 100.0
    
    # VWAP Parameters
    vwap_mode = "Ignore"
    vwap_authority = "Supplemental"
    vwap_deadzone = 0.0
    vwap_threshold = 0.0
    vwap_recency_bars = 5
    
    # Bollinger Bands Parameters
    bb_mode = "Off"
    bb_band_scope = "Outer"
    bb_length = 21
    bb_std_dev = 2.0
    bb_runway = 0.0
    
    # Aggregation
    aggregation_mode = "Strict Consensus"
    eval_point = "Close"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # RSI
        self.rsi_val = self.I(lambda: pta.rsi(close, length=self.rsi_length) or pd.Series(50, index=close.index))
        self.rsi_ma = self.I(lambda: pta.sma(self.rsi_val, length=self.rsi_sma_length) or pd.Series(50, index=close.index))
        
        # EMA
        self.ema_fast = self.I(lambda: pta.ema(close, length=self.ema_fast_len) or close)
        self.ema_slow = self.I(lambda: pta.ema(close, length=self.ema_slow_len) or close)
        
        # MACD
        def calc_macd():
            macd_result = pta.macd(close, fast=self.macd_fast_len, slow=self.macd_slow_len, signal=self.macd_signal_len)
            if macd_result is not None and len(macd_result.columns) >= 3:
                return macd_result.iloc[:, 2]  # histogram
            return pd.Series(0, index=close.index)
        self.macd_hist = self.I(calc_macd)
        
        # Stochastic
        def calc_stoch():
            stoch_result = pta.stoch(high, low, close, k=self.stoch_k_len, d=self.stoch_d_smooth, smooth_k=self.stoch_k_smooth)
            if stoch_result is not None and len(stoch_result.columns) >= 1:
                return stoch_result.iloc[:, 0]  # %K
            return pd.Series(50, index=close.index)
        self.stoch_k = self.I(calc_stoch)
        
        def calc_stoch_d():
            stoch_result = pta.stoch(high, low, close, k=self.stoch_k_len, d=self.stoch_d_smooth, smooth_k=self.stoch_k_smooth)
            if stoch_result is not None and len(stoch_result.columns) >= 2:
                return stoch_result.iloc[:, 1]  # %D
            return pd.Series(50, index=close.index)
        self.stoch_d = self.I(calc_stoch_d)
        
        # VWAP
        self.vwap = self.I(lambda: pta.vwap(high, low, close, volume) or close)
        
        # Bollinger Bands
        def calc_bb_upper():
            bb_result = pta.bbands(close, length=self.bb_length, std=self.bb_std_dev)
            if bb_result is not None and len(bb_result.columns) >= 3:
                return bb_result.iloc[:, 2]  # upper
            return close
        self.bb_upper = self.I(calc_bb_upper)
        
        def calc_bb_lower():
            bb_result = pta.bbands(close, length=self.bb_length, std=self.bb_std_dev)
            if bb_result is not None and len(bb_result.columns) >= 1:
                return bb_result.iloc[:, 0]  # lower
            return close
        self.bb_lower = self.I(calc_bb_lower)
        
        def calc_bb_mid():
            bb_result = pta.bbands(close, length=self.bb_length, std=self.bb_std_dev)
            if bb_result is not None and len(bb_result.columns) >= 2:
                return bb_result.iloc[:, 1]  # middle
            return close
        self.bb_mid = self.I(calc_bb_mid)

    def _calc_rsi_state(self, rsi_val, rsi_ma):
        """Calculate RSI directional state"""
        if self.rsi_observe == "Ignore":
            return 0
        
        rsi_state_raw = rsi_val - self.rsi_ma[-1] if self.rsi_mode == "RSI vs SMA" else rsi_val - 50
        rsi_state_base = 0 if abs(rsi_state_raw) < self.rsi_deadzone else rsi_state_raw
        
        if self.rsi_observe == "Confirm":
            return np.sign(rsi_state_base)
        elif self.rsi_observe == "Defer":
            return 0
        elif self.rsi_observe == "Infer":
            # Simplified infer logic
            return np.sign(rsi_state_base)
        
        return 0

    def _calc_ema_state(self, ema_fast, ema_slow):
        """Calculate EMA directional state"""
        if self.ema_observe == "Ignore":
            return 0
        
        ema_diff = ema_fast - ema_slow
        ema_state_base = 0 if abs(ema_diff) < self.ema_deadzone else ema_diff
        
        if self.ema_observe == "Confirm":
            return np.sign(ema_state_base)
        elif self.ema_observe == "Defer":
            return 0
        elif self.ema_observe == "Infer":
            return np.sign(ema_state_base)
        
        return 0

    def _calc_macd_state(self, macd_hist):
        """Calculate MACD directional state"""
        if self.macd_observe == "Ignore":
            return 0
        
        macd_state_base = 0 if abs(macd_hist) < self.macd_deadzone else macd_hist
        
        if self.macd_observe == "Confirm":
            return np.sign(macd_state_base)
        elif self.macd_observe == "Defer":
            return 0
        elif self.macd_observe == "Infer":
            return np.sign(macd_state_base)
        
        return 0

    def _calc_stoch_state(self, stoch_k, stoch_d):
        """Calculate Stochastic directional state"""
        if self.stoch_obs_mode == "Ignore":
            return 0
        
        delta = abs(stoch_k - stoch_d)
        
        if delta < self.stoch_deadzone:
            return 0
        
        # Range checking
        if self.stoch_range_mode == "Invalidate":
            in_long_range = stoch_k >= self.stoch_min_long and stoch_k <= self.stoch_max_long and stoch_k > stoch_d
            in_short_range = stoch_k >= self.stoch_min_short and stoch_k <= self.stoch_max_short and stoch_k < stoch_d
            if not (in_long_range or in_short_range):
                return 0
        
        # Confirm logic
        if stoch_k > stoch_d:
            return 1
        elif stoch_k < stoch_d:
            return -1
        
        return 0

    def next(self):
        if len(self) < max(self.rsi_length, self.ema_fast_len, self.macd_slow_len, self.stoch_k_len) + 10:
            return
        
        # Get current values
        rsi_val = self.rsi_val[-1]
        rsi_ma = self.rsi_ma[-1]
        ema_fast = self.ema_fast[-1]
        ema_slow = self.ema_slow[-1]
        macd_hist = self.macd_hist[-1]
        stoch_k = self.stoch_k[-1]
        stoch_d = self.stoch_d[-1]
        
        # Calculate states
        rsi_state = self._calc_rsi_state(rsi_val, rsi_ma)
        ema_state = self._calc_ema_state(ema_fast, ema_slow)
        macd_state = self._calc_macd_state(macd_hist)
        stoch_state = self._calc_stoch_state(stoch_k, stoch_d)
        
        # Aggregate votes
        bull_votes = sum([1 for s in [rsi_state, ema_state, macd_state, stoch_state] if s == 1])
        bear_votes = sum([1 for s in [rsi_state, ema_state, macd_state, stoch_state] if s == -1])
        active_votes = bull_votes + bear_votes
        
        # Determine aggregate state
        if self.aggregation_mode == "Strict Consensus":
            if active_votes > 0 and bull_votes == active_votes:
                aggregate_state = 1
            elif active_votes > 0 and bear_votes == active_votes:
                aggregate_state = -1
            else:
                aggregate_state = 0
        else:  # Directional Tolerance
            if bull_votes > 0 and bear_votes == 0:
                aggregate_state = 1
            elif bear_votes > 0 and bull_votes == 0:
                aggregate_state = -1
            else:
                aggregate_state = 0
        
        # VWAP processing
        vwap_val = self.vwap[-1]
        price_delta = self.data.Close[-1] - vwap_val
        
        vwap_state = 0
        if self.vwap_mode == "Confirm":
            if abs(price_delta) > self.vwap_deadzone:
                vwap_state = 1 if price_delta > 0 else -1
        
        # Apply VWAP authority
        final_state = aggregate_state
        if self.vwap_mode != "Ignore":
            if self.vwap_authority == "Override" and vwap_state != 0:
                final_state = vwap_state
            elif self.vwap_authority == "Absolute" and vwap_state != 0 and vwap_state != aggregate_state:
                final_state = 0
            elif self.vwap_authority == "Supplemental" and aggregate_state == 0 and vwap_state != 0:
                final_state = vwap_state
        
        # Bollinger Bands validation
        if self.bb_mode != "Off" and final_state != 0:
            bb_upper = self.bb_upper[-1]
            bb_lower = self.bb_lower[-1]
            
            if final_state == 1:
                # Bullish: check upper band rejection
                if self.data.High[-1] > bb_upper and self.data.Close[-1] < bb_upper:
                    final_state = 0  # Rejection
            elif final_state == -1:
                # Bearish: check lower band rejection
                if self.data.Low[-1] < bb_lower and self.data.Close[-1] > bb_lower:
                    final_state = 0  # Rejection
        
        # Trading logic
        if final_state == 1:
            if not self.position:
                self.buy()
        elif final_state == -1:
            if self.position:
                self.position.close()