import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaTrendLen = 200
    emaExitLen = 50
    rsiLen = 14
    atrLen = 14
    atrMaLen = 20
    atrMultiplier = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema200 = self.I(pta.ema, close, length=self.emaTrendLen)
        self.ema50 = self.I(pta.ema, close, length=self.emaExitLen)
        
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.atrSma = self.I(lambda: pta.sma(pd.Series(self.atr), length=self.atrMaLen) or pd.Series(0, index=close.index))

    def next(self):
        if len(self.data) < max(self.emaTrendLen, self.emaExitLen, self.rsiLen, self.atrLen, self.atrMaLen):
            return
        
        close_val = self.data.Close[-1]
        ema200_val = self.ema200[-1]
        ema50_val = self.ema50[-1]
        rsi_val = self.rsi[-1]
        atr_val = self.atr[-1]
        atrSma_val = self.atrSma[-1]
        
        atr_filter = atr_val > atrSma_val * self.atrMultiplier
        
        long_condition = (
            close_val > ema200_val and
            crossover(self.rsi, 50) and
            atr_filter
        )
        
        short_condition = (
            close_val < ema200_val and
            crossover(50, self.rsi) and
            atr_filter
        )
        
        if long_condition and not self.position:
            self.buy()
        elif short_condition and not self.position:
            self.sell()
        
        if self.position and self.position.is_long and close_val < ema50_val:
            self.position.close()
        
        if self.position and self.position.is_short and close_val > ema50_val:
            self.position.close()


