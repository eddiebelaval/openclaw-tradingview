class TvStrategy(Strategy):
    buffer_size = 1000
    k_neighbors = 50
    smooth = 1
    mult = 2.0

    def init(self):
        self.price_array = []
        self.sorted_array = []
        self.bull_dispersions = []
        self.bear_dispersions = []
        self.cum_sum_bull = 0.0
        self.cum_count_bull = 0
        self.cum_sum_bear = 0.0
        self.cum_count_bear = 0
        
        self.smoothed_bull_values = []
        self.smoothed_bear_values = []
        self.final_bull_values = []
        self.final_bear_values = []
        self.cum_mean_bull_values = []
        self.cum_mean_bear_values = []

    def _binary_search_leftmost(self, arr, val):
        left, right = 0, len(arr)
        while left < right:
            mid = (left + right) // 2
            if arr[mid] < val:
                left = mid + 1
            else:
                right = mid
        return left

    def _remove_value(self, val):
        if len(self.sorted_array) > 0:
            idx = self._binary_search_leftmost(self.sorted_array, val)
            if idx < len(self.sorted_array) and abs(self.sorted_array[idx] - val) < 1e-10:
                self.sorted_array.pop(idx)

    def _add_value(self, val):
        idx = 0
        if len(self.sorted_array) > 0:
            idx = self._binary_search_leftmost(self.sorted_array, val)
            if idx < len(self.sorted_array) and self.sorted_array[idx] < val:
                idx += 1
        self.sorted_array.insert(idx, val)

