import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Structure and fractal settings
    htf_equivalent_bars = 12  # Approximate for 60-min on 1-min chart
    fractal_sensitivity = 5
    
    # ATR for confluences
    atr_length = 14
    
    # EMA for buy/sell signals
    fast_ema_length = 21
    slow_ema_length = 89
    ema_gap_threshold = 0.5
    
    # RSI for early signals
    rsi_length = 14
    rsi_overbought = 70
    rsi_oversold = 30
    
    # FVG settings
    enable_fvg = True
    fvg_lookback = 3
    
    def init(self):
        # Calculate ATR
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Calculate EMAs for trend and signals
        self.fast_ema = self.I(pta.ema, close, length=self.fast_ema_length)
        self.slow_ema = self.I(pta.ema, close, length=self.slow_ema_length)
        
        # RSI for momentum confirmation
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Pivots for structure detection (approximation)
        def pivot_high_func():
            result = pd.Series(np.nan, index=close.index)
            for i in range(self.fractal_sensitivity, len(close) - self.fractal_sensitivity):
                is_pivot = True
                center = high.iloc[i]
                for j in range(1, self.fractal_sensitivity + 1):
                    if high.iloc[i-j] >= center or high.iloc[i+j] >= center:
                        is_pivot = False
                        break
                if is_pivot:
                    result.iloc[i] = center
            return result
        
        def pivot_low_func():
            result = pd.Series(np.nan, index=close.index)
            for i in range(self.fractal_sensitivity, len(close) - self.fractal_sensitivity):
                is_pivot = True
                center = low.iloc[i]
                for j in range(1, self.fractal_sensitivity + 1):
                    if low.iloc[i-j] <= center or low.iloc[i+j] <= center:
                        is_pivot = False
                        break
                if is_pivot:
                    result.iloc[i] = center
            return result
        
        self.pivot_high = self.I(pivot_high_func)
        self.pivot_low = self.I(pivot_low_func)
        
        # Track structure state
        self.last_swing_high = None
        self.last_swing_low = None
        self.trend_dir = "Neutral"
        self.last_buy_bar = None
        self.last_sell_bar = None

    def next(self):
        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        
        # Update swing highs/lows
        if not pd.isna(self.pivot_high[-1]):
            self.last_swing_high = self.pivot_high[-1]
