        fast_ema_val = self.fast_ema[-1]
        slow_ema_val = self.slow_ema[-1]
        rsi_val = self.rsi[-1]
        
        ema_gap_pct = abs(fast_ema_val - slow_ema_val) / close_price * 100
        price_above_slow = close_price > slow_ema_val
        price_below_slow = close_price < slow_ema_val
        ema_separated = ema_gap_pct >= self.ema_gap_threshold
        
        # Crossover detection
        ema_crossup = crossover(self.fast_ema, self.slow_ema)
        ema_crossdn = crossover(self.slow_ema, self.fast_ema)
        
