    def _calculate_composite_risk(self, close, high, low):
        """
        Simplified composite risk metric based on available OHLC data only.
        Without access to FRED, Glassnode, and other external APIs, we create
        a proxy risk oscillator using price action, volatility, and momentum.
        """
        result = pd.Series(0.5, index=close.index)
        
        if len(close) < 200:
            return result
        
        # Component 1: Price position vs 200 SMA (Technical)
        sma200 = close.rolling(200).mean()
        price_ratio = close / sma200
        price_score = np.clip((price_ratio - 0.8) / 2.2, 0, 1)
        
        # Component 2: Volatility (20-day realized)
        returns = close.pct_change()
        vol20 = returns.rolling(20).std() * np.sqrt(252)
        vol_pct = (vol20 - vol20.min()) / (vol20.max() - vol20.min() + 0.0001)
        vol_score = 1.0 - np.clip(vol_pct, 0, 1)  # Invert: high vol = fear
        
        # Component 3: Momentum (RSI)
        rsi = pta.rsi(close, length=14)
        rsi_norm = rsi / 100.0 if rsi is not None else pd.Series(0.5, index=close.index)
        
        # Component 4: Mean reversion (distance from SMA50)
        sma50 = close.rolling(50).mean()
        ma_ratio = close / sma50
        ma_score = np.clip((ma_ratio - 0.9) / 0.3, 0, 1)
        
        # Component 5: Trend (111 vs 350 SMA for pi cycle proxy)
        sma111 = close.rolling(111).mean()
        sma350 = close.rolling(350).mean()
        pi_ratio = sma111 / (sma350 * 2.0 + 0.0001)
        pi_score = np.clip(pi_ratio / 1.05, 0, 1)
        
        # Composite: equal weight all components
        raw_composite = (price_score * 0.25 + 
                        vol_score * 0.25 + 
                        rsi_norm * 0.25 + 
                        ma_score * 0.15 +
                        pi_score * 0.10)
        
        # Smooth with SMA
        smooth_composite = raw_composite.rolling(self.smooth_len).mean()
        
        # Apply sigmoid rescaling
        sigmoid_input = -self.steepness * (smooth_composite - self.center_point)
        sigmoid = 1.0 / (1.0 + np.exp(sigmoid_input))
        composite = np.clip(sigmoid, 0.05, 0.95)
        
        return composite

