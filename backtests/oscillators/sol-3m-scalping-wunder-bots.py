import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime


class TvStrategy(Strategy):
    # Risk & Money Management
    capital = 1000
    risk_per_trade = 1.0
    riskReward = 2.0
    use_leverage = 5
    max_daily_loss = 3.0
    max_positions = 5
    
    # Support & Resistance
    sr_lookback = 20
    sr_tolerance = 0.3
    
    # Bollinger Bands
    bb_length = 20
    bb_mult = 2.0
    
    # Moving Average Cross
    fast_ma_len = 9
    slow_ma_len = 21
    ma_type = 'EMA'
    
    # Filters
    use_volume_filter = True
    vol_mult = 1.2
    use_atr_filter = True
    atr_min_mult = 0.5
    min_bars_between = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Bollinger Bands
        bb_result = self.I(lambda: pta.bbands(close, length=self.bb_length, std=self.bb_mult))
        self.bb_upper = bb_result.iloc[:, 2] if bb_result is not None else pd.Series(close)
        self.bb_lower = bb_result.iloc[:, 0] if bb_result is not None else pd.Series(close)
        self.bb_basis = bb_result.iloc[:, 1] if bb_result is not None else pd.Series(close)
        
        # Moving Averages
        if self.ma_type == 'EMA':
            self.fast_ma = self.I(pta.ema, close, length=self.fast_ma_len)
            self.slow_ma = self.I(pta.ema, close, length=self.slow_ma_len)
        elif self.ma_type == 'SMA':
            self.fast_ma = self.I(pta.sma, close, length=self.fast_ma_len)
            self.slow_ma = self.I(pta.sma, close, length=self.slow_ma_len)
        else:  # WMA
            self.fast_ma = self.I(pta.wma, close, length=self.fast_ma_len)
            self.slow_ma = self.I(pta.wma, close, length=self.slow_ma_len)
        
        # ATR
        self.atr_val = self.I(pta.atr, high, low, close, length=14)
        self.atr_avg = self.I(lambda: pd.Series(pta.sma(self.atr_val, length=50)))
        
        # Volume
        self.vol_avg = self.I(pta.sma, volume, length=20)
        
        # Pivot Points (support/resistance)
        self.pivot_high = self.I(self._calc_pivot_high, high, self.sr_lookback)
        self.pivot_low = self.I(self._calc_pivot_low, low, self.sr_lookback)
        
        # State variables
        self.resistance_level = np.nan
        self.support_level = np.nan
        self.trade_counter = 0
        self.bars_since_entry = 100
        self.daily_pnl = 0.0
        self.last_trade_day = 0
        self.position_entry_price = {}

    def _calc_pivot_high(self, high):
        result = pd.Series(np.nan, index=high.index)
        for i in range(self.sr_lookback, len(high) - self.sr_lookback):
            if high.iloc[i] == high.iloc[i-self.sr_lookback:i+self.sr_lookback+1].max():
                result.iloc[i] = high.iloc[i]
        return result

    def _calc_pivot_low(self, low):
        result = pd.Series(np.nan, index=low.index)
        for i in range(self.sr_lookback, len(low) - self.sr_lookback):
            if low.iloc[i] == low.iloc[i-self.sr_lookback:i+self.sr_lookback+1].min():
                result.iloc[i] = low.iloc[i]
        return result

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        # Update pivot levels
        if not np.isnan(self.pivot_high[-1]):
            self.resistance_level = self.pivot_high[-1]
        if not np.isnan(self.pivot_low[-1]):
            self.support_level = self.pivot_low[-1]
        
        # S/R zone proximity checks
        sr_zone = close * (self.sr_tolerance / 100)
        near_resistance = not np.isnan(self.resistance_level) and abs(close - self.resistance_level) <= sr_zone
        near_support = not np.isnan(self.support_level) and abs(close - self.support_level) <= sr_zone
        
        # Bollinger Bands signals (reversed logic)
        bb_long_signal = close > self.bb_upper[-1]
        bb_short_signal = close < self.bb_lower[-1]
        
        # MA Cross signals (reversed logic)
        ma_bearish_cross = crossover(self.slow_ma, self.fast_ma)  # Death cross
        ma_bullish_cross = crossover(self.fast_ma, self.slow_ma)  # Golden cross
        
        # Volume filter
        vol_ok = (not self.use_volume_filter) or (volume >= self.vol_avg[-1] * self.vol_mult)
        
        # ATR filter
        atr_ok = (not self.use_atr_filter) or (self.atr_val[-1] >= self.atr_avg[-1] * self.atr_min_mult)
        
        # Scoring (require 2 of 3 reversed conditions)
        long_score = int(near_resistance) + int(bb_long_signal) + int(ma_bearish_cross)
        short_score = int(near_support) + int(bb_short_signal) + int(ma_bullish_cross)
        
        reverse_long_condition = long_score >= 2 and vol_ok and atr_ok
        reverse_short_condition = short_score >= 2 and vol_ok and atr_ok
        
        # Position management
        self.bars_since_entry += 1
        
        # Daily P&L tracking
        current_day = len(self.data)
        if current_day != self.last_trade_day:
            self.daily_pnl = 0.0
            self.last_trade_day = current_day
        
        # Check daily loss limit
        daily_loss_ok = self.daily_pnl > -(self.capital * self.max_daily_loss / 100)
        
        # Count open positions
        open_trades = len(self.position_entry_price)
        can_open_new = open_trades < self.max_positions and self.bars_since_entry >= self.min_bars_between
        
        # ATR-based stop loss distance
        atr_stop_distance = self.atr_val[-1] * 1.5
        
        # Entry logic
        if can_open_new and daily_loss_ok:
            
            # LONG ENTRY
            if reverse_long_condition:
                self.trade_counter += 1
                entry_price = close
                stop_val = close - atr_stop_distance
                take_val = close + (atr_stop_distance * self.riskReward)
                
                # Position sizing
                risk_amount = self.capital * (self.risk_per_trade / 100)
                stop_dist_pct = abs(entry_price - stop_val) / entry_price if entry_price > 0 else 0
                qty = (risk_amount / stop_dist_pct / close) if stop_dist_pct > 0 else 0
                qty = max(0.001, qty)
                
                trade_id = f"Long_{self.trade_counter}"
                self.buy(size=qty)
                self.position_entry_price[trade_id] = {'price': entry_price, 'tp': take_val, 'sl': stop_val}
                self.bars_since_entry = 0
            
            # SHORT ENTRY
            if reverse_short_condition:
                self.trade_counter += 1
                entry_price = close
                stop_val = close + atr_stop_distance
                take_val = close - (atr_stop_distance * self.riskReward)
                
                # Position sizing
                risk_amount = self.capital * (self.risk_per_trade / 100)
                stop_dist_pct = abs(stop_val - entry_price) / entry_price if entry_price > 0 else 0
                qty = (risk_amount / stop_dist_pct / close) if stop_dist_pct > 0 else 0
                qty = max(0.001, qty)
                
                trade_id = f"Short_{self.trade_counter}"
                self.sell(size=qty)
                self.position_entry_price[trade_id] = {'price': entry_price, 'tp': take_val, 'sl': stop_val}
                self.bars_since_entry = 0
        
        # Exit logic based on SL/TP
        if self.position:
            for trade_id, trade_info in list(self.position_entry_price.items()):
                tp = trade_info['tp']
                sl = trade_info['sl']
                
                if self.position.is_long:
                    if close >= tp or close <= sl:
                        self.position.close()
                        del self.position_entry_price[trade_id]
                        break
                else:
                    if close <= tp or close >= sl:
                        self.position.close()
                        del self.position_entry_price[trade_id]
                        break


