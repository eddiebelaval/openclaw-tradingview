import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 14
    smooth = "RMA"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate True Range
        def calc_tr():
            tr = pd.Series(0.0, index=close.index)
            for i in range(1, len(close)):
                tr.iloc[i] = max(
                    high.iloc[i] - low.iloc[i],
                    abs(high.iloc[i] - close.iloc[i-1]),
                    abs(low.iloc[i] - close.iloc[i-1])
                )
            return tr
        
        tr = self.I(calc_tr)
        
        # Apply smoothing to TR
        if self.smooth == "SMA":
            self.atr = self.I(pta.sma, tr, length=self.len)
        elif self.smooth == "EMA":
            self.atr = self.I(pta.ema, tr, length=self.len)
        elif self.smooth == "RMA":
            self.atr = self.I(pta.rma, tr, length=self.len)
        else:  # WMA
            self.atr = self.I(pta.wma, tr, length=self.len)
    
    def next(self):
        # Simple trading logic based on ATR
        # Buy when ATR is rising (indicating increased volatility)
        # Sell when ATR is falling (indicating decreased volatility)
        
        if len(self.data) < 2:
            return
        
        if self.atr[-1] is not None and self.atr[-2] is not None:
            if self.atr[-1] > self.atr[-2] and not self.position:
                self.buy()
            elif self.atr[-1] < self.atr[-2] and self.position:
                self.position.close()