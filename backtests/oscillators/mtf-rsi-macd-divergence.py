import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_len = 14
    rsi_ob = 70
    rsi_os = 30
    macd_fast = 12
    macd_slow = 26
    macd_sig = 9
    div_lb = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        macd_result = self.I(
            lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig)
        )
        
        self.macd_line = self.I(
            lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig)['MACD_12_26_9']
            if pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig) is not None
            else pd.Series(0, index=close.index)
        )
        
        self.macd_signal = self.I(
            lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig)['MACDh_12_26_9']
            if pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig) is not None
            else pd.Series(0, index=close.index)
        )
        
        self.highest_high = self.I(
            lambda: high.rolling(self.div_lb * 2 + 1).max()
        )
        self.lowest_low = self.I(
            lambda: low.rolling(self.div_lb * 2 + 1).min()
        )
        
        self.rsi_prev = None
        self.macd_line_prev = None
        self.last_high_rsi = None
        self.last_low_rsi = None
        self.last_high_price = None
        self.last_low_price = None
        self.last_high_macd = None
        self.last_low_macd = None
        self.divergence_signal = 0

    def next(self):
        if len(self.data) < self.div_lb + 1:
            return

        current_rsi = self.rsi[-1]
        current_macd = self.macd_line[-1]
        current_price = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]

        is_pivot_high = False
        is_pivot_low = False

        if len(self.data) > self.div_lb * 2:
            mid_idx = len(self.data) - self.div_lb - 1
            if mid_idx >= self.div_lb:
                left_highs = [self.data.High[mid_idx - i] for i in range(1, self.div_lb + 1)]
                right_highs = [self.data.High[mid_idx + i] for i in range(1, self.div_lb + 1)]
                
                if self.data.High[mid_idx] > max(left_highs) and self.data.High[mid_idx] > max(right_highs):
                    is_pivot_high = True

                left_lows = [self.data.Low[mid_idx - i] for i in range(1, self.div_lb + 1)]
                right_lows = [self.data.Low[mid_idx + i] for i in range(1, self.div_lb + 1)]
                
                if self.data.Low[mid_idx] < min(left_lows) and self.data.Low[mid_idx] < min(right_lows):
                    is_pivot_low = True

        if is_pivot_high:
            if self.last_high_price is not None:
                if current_price > self.last_high_price and current_rsi < self.last_high_rsi:
                    self.divergence_signal = 2
                elif current_price < self.last_high_price and current_rsi > self.last_high_rsi:
                    self.divergence_signal = 4
            
            self.last_high_price = current_high
            self.last_high_rsi = current_rsi
            self.last_high_macd = current_macd

        if is_pivot_low:
            if self.last_low_price is not None:
                if current_price < self.last_low_price and current_rsi > self.last_low_rsi:
                    self.divergence_signal = 1
                elif current_price > self.last_low_price and current_rsi < self.last_low_rsi:
                    self.divergence_signal = 3
            
            self.last_low_price = current_low
            self.last_low_rsi = current_rsi
            self.last_low_macd = current_macd

        rsi_oversold = current_rsi <= self.rsi_os
        rsi_overbought = current_rsi >= self.rsi_ob
        macd_bullish = crossover(self.macd_line, self.macd_signal)
        macd_bearish = crossover(self.macd_signal, self.macd_line)

        if self.position:
            if rsi_overbought or macd_bearish or self.divergence_signal == 2:
                self.position.close()
        else:
            if (rsi_oversold or macd_bullish or self.divergence_signal == 1) and current_price > self.data.Open[-1]:
                self.buy()

        self.rsi_prev = current_rsi
        self.macd_line_prev = current_macd