import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    bbLength = 20
    bbMult = 2.0
    kcLength = 20
    kcMult = 1.5
    useTrueRange = True
    normLen = 200
    targetRange = 100.0
    zClamp = 3.0
    bandLevel = 60.0
    fastLen = 12
    slowLen = 26
    sigLen = 9
    oscType = "EMA"
    sigType = "EMA"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        bb = self.I(lambda: pta.bbands(close, length=self.bbLength, std=self.bbMult))
        self.bb_upper = bb.iloc[:, 0]
        self.bb_lower = bb.iloc[:, 2]
        
        # Keltner Channels
        kc_basis = self.I(lambda: pta.sma(close, length=self.kcLength))
        
        if self.useTrueRange:
            tr = self.I(lambda: pta.atr(high, low, close, length=1))
            kc_range = tr
        else:
            kc_range = self.I(lambda: high - low)
        
        kc_avg = self.I(lambda: pta.sma(kc_range, length=self.kcLength) if isinstance(kc_range, pd.Series) else pd.Series(0, index=close.index))
        
        self.kc_upper = self.I(lambda: kc_basis + kc_avg * self.kcMult if kc_basis is not None and kc_avg is not None else pd.Series(0, index=close.index))
        self.kc_lower = self.I(lambda: kc_basis - kc_avg * self.kcMult if kc_basis is not None and kc_avg is not None else pd.Series(0, index=close.index))
        
        # Highest/Lowest
        self.hh = self.I(lambda: high.rolling(self.kcLength).max())
        self.ll = self.I(lambda: low.rolling(self.kcLength).min())
        
        # Mid price
        mid_sma = self.I(lambda: pta.sma(close, length=self.kcLength))
        self.mid = self.I(lambda: ((self.hh + self.ll) / 2 + mid_sma) / 2 if self.hh is not None and self.ll is not None and mid_sma is not None else pd.Series(0, index=close.index))
        
        # Raw momentum (linear regression of src - mid)
        self.val_raw = self.I(lambda: pta.linreg(close - self.mid, length=self.kcLength) if self.mid is not None else pd.Series(0, index=close.index))
        
        # Normalized trend oscillator
        self.trend_osc = self.I(lambda: self._normalize_to_range(self.val_raw, self.normLen, self.targetRange, self.zClamp))
        
        # MACD components
        ma_fast = self.I(lambda: self._ma_type(close, self.fastLen, self.oscType))
        ma_slow = self.I(lambda: self._ma_type(close, self.slowLen, self.oscType))
        
        macd_raw = self.I(lambda: ma_fast - ma_slow if ma_fast is not None and ma_slow is not None else pd.Series(0, index=close.index))
        signal_raw = self.I(lambda: self._ma_type(macd_raw, self.sigLen, self.sigType))
        
        self.macd_norm = self.I(lambda: self._normalize_to_range(macd_raw, self.normLen, self.targetRange, self.zClamp))
        self.signal_norm = self.I(lambda: self._normalize_to_range(signal_raw, self.normLen, self.targetRange, self.zClamp))
        
        # Squeeze detection
        self.sqz_on = self.I(lambda: (self.bb_lower > self.kc_lower) & (self.bb_upper < self.kc_upper))
        self.sqz_off = self.I(lambda: (self.bb_lower < self.kc_lower) & (self.bb_upper > self.kc_upper))

    def _normalize_to_range(self, x, length, target_range, z_clamp):
        if x is None or len(x) < length:
            return pd.Series(0, index=x.index if x is not None else range(len(self.data.Close)))
        
        mean = pta.sma(x, length=length)
        stdev = x.rolling(length).std()
        
        z = pd.Series(0, index=x.index)
        mask = stdev != 0
        z[mask] = (x[mask] - mean[mask]) / stdev[mask]
        
        z = z.clip(-z_clamp, z_clamp)
        result = target_range * (z / z_clamp)
        return result

    def _ma_type(self, src, length, ma_type):
        if ma_type == "EMA":
            return pta.ema(src, length=length)
        else:
            return pta.sma(src, length=length)

    def next(self):
        if len(self.data) < self.normLen + self.slowLen:
            return
        
        trend = self.trend_osc[-1] if self.trend_osc[-1] is not None else 0
        macd = self.macd_norm[-1] if self.macd_norm[-1] is not None else 0
        signal = self.signal_norm[-1] if self.signal_norm[-1] is not None else 0
        
        # Buy signal: trend oscillator crosses above zero with MACD above signal
        if len(self.trend_osc) > 1:
            trend_prev = self.trend_osc[-2] if self.trend_osc[-2] is not None else 0
            if trend_prev <= 0 and trend > 0 and macd > signal:
                if not self.position:
                    self.buy()
        
        # Sell signal: trend oscillator crosses below zero or MACD crosses below signal
        if len(self.trend_osc) > 1 and len(self.macd_norm) > 1:
            trend_prev = self.trend_osc[-2] if self.trend_osc[-2] is not None else 0
            macd_prev = self.macd_norm[-2] if self.macd_norm[-2] is not None else 0
            
            if (trend_prev > 0 and trend <= 0) or (macd_prev > signal and macd <= signal):
                if self.position:
                    self.sell()


