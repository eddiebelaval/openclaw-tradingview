import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    contracts = 1
    rsiLength = 14
    shortStretch = 60
    longStretch = 40
    rangeLookback = 100
    zonePercent = 0.20
    targetTicks = 12
    stopTicks = 11

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI calculation
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        
        # Range model using rolling max/min
        self.rangeHigh = self.I(lambda: high.rolling(self.rangeLookback).max())
        self.rangeLow = self.I(lambda: low.rolling(self.rangeLookback).min())
        
    def next(self):
        if len(self.data) < self.rangeLookback + 2:
            return
        
        # Current values
        current_close = self.data.Close[-1]
        current_rsi = self.rsi[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Previous values
        prev_rsi = self.rsi[-2]
        prev_prev_rsi = self.rsi[-3] if len(self.data) >= 3 else None
        
        # Range levels
        range_high = self.rangeHigh[-1]
        range_low = self.rangeLow[-1]
        range_size = range_high - range_low
        
        premium_level = range_high - range_size * self.zonePercent
        discount_level = range_low + range_size * self.zonePercent
        
        # Conditions
        in_premium = current_close >= premium_level
        in_discount = current_close <= discount_level
        
        # RSI swing detection
        rsi_swing_high = (prev_prev_rsi is not None and 
                         prev_rsi > prev_prev_rsi and 
                         prev_rsi > current_rsi)
        rsi_swing_low = (prev_prev_rsi is not None and 
                        prev_rsi < prev_prev_rsi and 
                        prev_rsi < current_rsi)
        
        # RSI momentum shift
        rsi_turn_down = current_rsi < prev_rsi
        rsi_turn_up = current_rsi > prev_rsi
        
        # SHORT ENTRY
        short_condition = (
            in_premium and
            prev_rsi > self.shortStretch and
            rsi_swing_high and
            rsi_turn_down and
            self.position.size >= 0
        )
        
        # LONG ENTRY
        long_condition = (
            in_discount and
            prev_rsi < self.longStretch and
            rsi_swing_low and
            rsi_turn_up and
            self.position.size <= 0
        )
        
        # Tick value (use 0.01 as default for most instruments)
        tick = 0.01
        
        # EXIT logic
        if self.position.size < 0:
            # Short position - exit at target or stop
            exit_price = self.position.open_price - self.targetTicks * tick
            stop_price = self.position.open_price + self.stopTicks * tick
            
            if current_low <= exit_price or current_high >= stop_price:
                self.position.close()
        
        elif self.position.size > 0:
            # Long position - exit at target or stop
            exit_price = self.position.open_price + self.targetTicks * tick
            stop_price = self.position.open_price - self.stopTicks * tick
            
            if current_high >= exit_price or current_low <= stop_price:
                self.position.close()
        
        # ENTRY execution
        if short_condition and self.position.size == 0:
            self.sell(size=self.contracts)
        
        elif long_condition and self.position.size == 0:
            self.buy(size=self.contracts)


