import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_len = 14
    lookback = 300
    bin_count = 20
    va_pct = 70.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        self.highest_high = self.I(lambda: high.rolling(self.lookback).max())
        self.lowest_low = self.I(lambda: low.rolling(self.lookback).min())
        
        self.in_position = False

    def next(self):
        if len(self.data) < self.lookback + self.rsi_len:
            return
        
        rsi_current = self.rsi[-1]
        
        if rsi_current is None or np.isnan(rsi_current):
            return
        
        highest = self.highest_high[-1]
        lowest = self.lowest_low[-1]
        
        if highest is None or lowest is None or np.isnan(highest) or np.isnan(lowest):
            return
        
        price_range = highest - lowest
        if price_range <= 0:
            return
        
        normalized_rsi = rsi_current
        
        if normalized_rsi < 30 and not self.position:
            self.buy()
            self.in_position = True
        elif normalized_rsi > 70 and self.position:
            self.sell()
            self.in_position = False
        elif normalized_rsi < 20 and self.position:
            self.sell()
            self.in_position = False


