import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    swing_depth = 5
    min_bar_gap = 10

    def init(self):
        close = pd.Series(self.data.Close)
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        self.last_buy_price = None
        self.last_sell_price = None

    def next(self):
        if len(self.data) < self.rsi_length + self.swing_depth + 1:
            return
        
        rsi_val = self.rsi[-1]
        
        if not np.isnan(rsi_val):
            if rsi_val < 30 and not self.position:
                if len(self.data) > 1 and self.rsi[-2] < self.rsi[-1]:
                    self.buy()
            
            elif rsi_val > 70 and self.position:
                self.sell()
            
            elif rsi_val > 80 and self.position:
                self.sell()