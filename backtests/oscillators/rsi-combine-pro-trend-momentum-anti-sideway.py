        self.rsiValue = self.I(pta.rsi, close, length=self.rsiLength)

        # Calculate WMA on RSI
        self.wmaOnRsi = self.I(lambda: pta.wma(self.rsiValue, length=self.wmaLength))

        # Calculate EMA on RSI
        self.emaOnRsi = self.I(lambda: pta.ema(self.rsiValue, length=self.emaLength))

        # Calculate EMA RSI for divergence
        self.emaRsiDiv = self.I(lambda: pta.ema(self.rsiValue, length=self.emaDivLen))

        # Calculate RSI slope
        self.rsiSlope = self.I(lambda: pta.sma(
            pd.Series(np.where(len(self.rsiValue) > 0, 
                              np.diff(np.concatenate([[self.rsiValue[0]], self.rsiValue]), n=1), 
                              0)), 
            length=self.slopeLen
        ))

        # Calculate RSI range (highest - lowest over 10 bars)
        self.rsiRange = self.I(lambda: (
            pd.Series(self.rsiValue).rolling(window=10).max() - 
            pd.Series(self.rsiValue).rolling(window=10).min()
        ))

