import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    shortLen = 9
    midLen = 26
    longLen = 52

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RCI calculation: Rank Correlation Index
        # RCI = (1 - 6*Σ(d²) / (n*(n²-1))) * 100
        def calc_rci(src, length):
            result = pd.Series(index=src.index, dtype=float)
            for i in range(length - 1, len(src)):
                window = src.iloc[i - length + 1:i + 1]
                rank_src = window.rank().values
                rank_idx = np.arange(1, length + 1)
                d_squared = np.sum((rank_src - rank_idx) ** 2)
                rci_value = (1 - (6 * d_squared) / (length * (length ** 2 - 1))) * 100
                result.iloc[i] = rci_value
            return result
        
        self.rciS = self.I(lambda: calc_rci(close, self.shortLen))
        self.rciM = self.I(lambda: calc_rci(close, self.midLen))
        self.rciL = self.I(lambda: calc_rci(close, self.longLen))

    def next(self):
        if len(self.data) < self.longLen + 1:
            return
        
        rciS_curr = self.rciS[-1]
        rciM_curr = self.rciM[-1]
        rciL_curr = self.rciL[-1]
        rciL_prev = self.rciL[-2] if len(self.rciL) > 1 else rciL_curr
        
        isStrongUptrend = (rciL_curr >= 85) or (rciL_curr > 0 and rciL_curr > rciL_prev and rciM_curr >= 85)
        isStrongDowntrend = (rciL_curr <= -85) or (rciL_curr < 0 and rciL_curr < rciL_prev and rciM_curr <= -85)
        
        if isStrongUptrend and not self.position:
            self.buy()
        elif isStrongDowntrend and self.position:
            self.sell()