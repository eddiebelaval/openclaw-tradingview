import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smoothK = 8
    smoothD = 3
    lengthRSI = 14
    lengthStoch = 7
    bb_period = 20
    bb_mult_outer = 4.0
    bb_mult_inner = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Helper function for drop1st
        def drop1st_func(src):
            result = src.copy()
            result.iloc[0] = np.nan
            return result
        
        # Helper function for xrma
        def xrma_func(src, length):
            result = pd.Series(index=src.index, dtype=float)
            val = src.iloc[0]
            for i in range(len(src)):
                if i == 0:
                    result.iloc[i] = val
                else:
                    val = (src.iloc[i] + (length - 1) * val) / length
                    result.iloc[i] = val
            return result
        
        # Helper function for xrsi
        def xrsi_func(src, length):
            msig = src.diff().fillna(0.0)
            up = xrma_func(np.maximum(msig, 0.0), length)
            dn = xrma_func(np.maximum(-msig, 0.0), length)
            rs = up / dn
            return 100.0 - 100.0 / (1.0 + rs)
        
        # Helper function for Ehlers Super Smoother
        def ehlers_super_smoother(src, lower):
            PI = 3.14159265359
            a1 = np.exp(-PI * np.sqrt(2) / lower)
            coeff2 = 2 * a1 * np.cos(np.sqrt(2) * PI / lower)
            coeff3 = -(a1 ** 2)
            coeff1 = (1 - coeff2 - coeff3) / 2
            
            result = pd.Series(index=src.index, dtype=float)
            for i in range(len(src)):
                if i == 0:
                    result.iloc[i] = src.iloc[i]
                elif i == 1:
                    result.iloc[i] = coeff1 * (src.iloc[i] + src.iloc[i-1]) + coeff2 * result.iloc[i-1]
                else:
                    result.iloc[i] = (coeff1 * (src.iloc[i] + src.iloc[i-1]) + 
                                     coeff2 * result.iloc[i-1] + 
                                     coeff3 * result.iloc[i-2])
            return result
        
        # Calculate price (log of close)
        price = np.log(drop1st_func(close))
        
        # Calculate xrsi
