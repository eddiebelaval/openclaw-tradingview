import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core Momentum Parameters
    rFast = 13
    sFast = 25
    rSlow = 25
    sSlow = 50
    sigLen = 7
    useAdaptive = True
    volLook = 200
    atrLen = 14
    
    # Bands/Extremes
    bandMode = "Dynamic"
    dynLook = 100
    dynMult = 1.6
    staticLevel = 40
    
    # Filters
    useVWAPGate = True
    vwapSlopeLen = 10
    threshPct = 0.05
    useGannSwing = True
    swingN = 2
    useVolConf = True
    volLookback = 20
    volBullThresh = 1.5
    volBearExhaust = 0.8
    volBearSpike = 1.2
    
    # SNR Filter
    useSNR = True
    snrThresh = 1.5
    snrLookback = 10
    
    # Whipsaw Guard
    useWhipsaw = True
    minBarsBetween = 3
    
    # Scoring
    useScoring = True
    minScore = 50
    
    # Consolidation
    useConsFilter = True
    consolThresh = 0.7
    consolLookback = 50
    consolPenalty = 7
    
    # Acceleration
    useAccel = True
    accelSensitivity = 0.7
    
    def init(self):
        # Prepare data series
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # TSI Calculation
        def calc_tsi(src, r, s):
            m = src.diff()
            e1 = m.ewm(span=r, adjust=False).mean()
            e2 = e1.ewm(span=s, adjust=False).mean()
            a1 = m.abs().ewm(span=r, adjust=False).mean()
            a2 = a1.ewm(span=s, adjust=False).mean()
            result = 100.0 * (e2 / a2.replace(0, np.nan))
            return result.fillna(0)
        
        # Calculate TSI values
        self.tsi_fast = self.I(lambda: calc_tsi(close, self.rFast, self.sFast))
        self.tsi_slow = self.I(lambda: calc_tsi(close, self.rSlow, self.sSlow))
        
        # ATR for volatility weighting
        self.atr_vals = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Adaptive weighting
        def calc_atr_weight():
            atrp = self.atr_vals / close
            atr_min = atrp.rolling(self.volLook).min()
            atr_max = atrp.rolling(self.volLook).max()
            w_raw = (atrp - atr_min) / (atr_max - atr_min).replace(0, np.nan)
            return w_raw.fillna(0.5).clip(0, 1)
        
        self.atr_weight = self.I(calc_atr_weight)
        
        # Momentum calculation
        def calc_momentum():
            if self.useAdaptive:
                return self.atr_weight * self.tsi_fast + (1 - self.atr_weight) * self.tsi_slow
            else:
                r_mid = int((self.rFast + self.rSlow) / 2)
                s_mid = int((self.sFast + self.sSlow) / 2)
                return calc_tsi(close, r_mid, s_mid)
        
        self.mom = self.I(calc_momentum)
        self.signal = self.I(lambda: self.mom.ewm(span=self.sigLen, adjust=False).mean())
        
        # Bands
        def calc_bands():
            stdev_mom = self.mom.rolling(self.dynLook).std()
            if self.bandMode == "Dynamic":
                return stdev_mom * self.dynMult
            else:
                return pd.Series(self.staticLevel, index=self.mom.index)
        
        self.upper_band = self.I(calc_bands)
        self.lower_band = self.I(lambda: -self.upper_band)
        
        # Pivots
        self.pivot_len = 5
        
        # VWAP
        self.vwap_val = self.I(pta.vwap, high, low, close, volume)
        
        # Volume confirmation
        self.vol_avg = self.I(lambda: volume.rolling(self.volLookback).mean())
        
        # ATR for consolidation
        self.atr_slow = self.I(lambda: self.atr_vals.rolling(self.consolLookback).mean())
        
        # Gann Swing
        self.swing_high = self.I(lambda: high.rolling(self.swingN + 1).max())
        self.swing_low = self.I(lambda: low.rolling(self.swingN + 1).min())
        
        # Momentum derivatives
        self.mom_velocity = self.I(lambda: self.mom.diff())
        self.mom_accel = self.I(lambda: self.mom_velocity.diff())
        
        # SNR calculation
        def calc_snr():
            signal_mag = (self.mom - self.signal).abs()
            noise_mag = (self.mom - self.signal).rolling(self.snrLookback).std()
            snr = signal_mag / noise_mag.replace(0, np.nan)
            return snr.fillna(1.5)
        
        self.snr = self.I(calc_snr)
        
        # Signal tracking
        self.last_bull_bar = -1000
        self.last_bear_bar = -1000
    
    def next(self):
        if len(self.data) < max(self.dynLook, self.volLookback, self.consolLookback) + 10:
            return
        
        # Current values
        mom = self.mom[-1]
        sig = self.signal[-1]
        upper = self.upper_band[-1]
        lower = self.lower_band[-1]
        close_price = self.data.Close[-1]
        
        # Basic checks
        if upper <= 0 or pd.isna(upper) or pd.isna(lower) or pd.isna(mom) or pd.isna(sig):
            return
        
        # Volume confirmation
        vol_ratio = self.data.Volume[-1] / self.vol_avg[-1] if self.vol_avg[-1] > 0 else 1.0
        vol_bull_confirm = vol_ratio > self.volBullThresh
        vol_bear_confirm = vol_ratio < self.volBearExhaust or vol_ratio > self.volBearSpike
        
        # Consolidation filter
        atr_current = self.atr_vals[-1]
        atr_slow = self.atr_slow[-1]
        is_consolidating = (atr_current < atr_slow * self.consolThresh) if atr_slow > 0 else False
        
        # Gann Swing
        swing_up = close_price > self.swing_high[-2] if len(self.data) > self.swingN + 1 else True
        swing_down = close_price < self.swing_low[-2] if len(self.data) > self.swingN + 1 else True
        
        # VWAP gate
        vwap = self.vwap_val[-1]
        gate_long = (close_price < vwap) if not pd.isna(vwap) else True
        gate_short = (close_price > vwap) if not pd.isna(vwap) else True
        
        # SNR check
        snr_ok = self.snr[-1] >= self.snrThresh if self.useSNR else True
        
        # Momentum extremes
        mom_in_os = mom < lower
        mom_in_ob = mom > upper
        
        # Acceleration
        vel = self.mom_velocity[-1]
        accel = self.mom_accel[-1]
        is_accel_up = accel > self.accelSensitivity and vel > 0
        is_accel_down = accel < -self.accelSensitivity and vel < 0
        
        # Pivot detection (simple version)
        if len(self.data) > self.pivot_len:
            low_idx = self.data.Low[-(self.pivot_len + 1):-1].idxmin()
            high_idx = self.data.High[-(self.pivot_len + 1):-1].idxmax()
            
            bull_pivot = mom_in_os and len(self.data) > self.pivot_len
            bear_pivot = mom_in_ob and len(self.data) > self.pivot_len
        else:
            bull_pivot = False
            bear_pivot = False
        
        # Scoring system
        bull_score = 0.0
        if mom < 0:
            prox = max(0, min(1, (0 - mom) / max(1, (0 - lower))))
            bull_score += 15 * prox
        
        bull_score += 10  # VWAP/gate base
        if gate_long:
            bull_score += 10
        
        bull_score += 10  # Volume base
        if vol_bull_confirm:
            bull_score += 10
        
        if is_accel_up:
            bull_score += 10
        elif vel > 0:
            bull_score += 5
        
        if mom > sig:
            bull_score += 5
        
        if not is_consolidating:
            bull_score += 5
        
        bull_score = min(100, max(0, bull_score))
        
        bear_score = 0.0
        if mom > 0:
            prox = max(0, min(1, (mom - 0) / max(1, (upper - 0))))
            bear_score += 15 * prox
        
        bear_score += 10
        if gate_short:
            bear_score += 10
        
        bear_score += 10
        if vol_bear_confirm:
            bear_score += 10
        
        if is_accel_down:
            bear_score += 10
        elif vel < 0:
            bear_score += 5
        
        if mom < sig:
            bear_score += 5
        
        if not is_consolidating:
            bear_score += 5
        
        bear_score = min(100, max(0, bear_score))
        
        # Signal generation
        bull_signal = (bull_pivot or mom_in_os) and bull_score >= self.minScore and snr_ok and swing_up and gate_long
        bear_signal = (bear_pivot or mom_in_ob) and bear_score >= self.minScore and snr_ok and swing_down and gate_short
        
        # Whipsaw protection
        if bull_signal and (len(self.data) - self.last_bear_bar) < self.minBarsBetween:
            bull_signal = False
        if bear_signal and (len(self.data) - self.last_bull_bar) < self.minBarsBetween:
            bear_signal = False
        
        # Execute trades
        if bull_signal and not self.position:
            self.buy()
            self.last_bull_bar = len(self.data)
        elif bear_signal and self.position:
            self.position.close()
            self.last_bear_bar = len(self.data)
        
        if bear_signal and not self.position:
            self.sell()
            self.last_bear_bar = len(self.data)
        elif bull_signal and self.position.is_short:
            self.position.close()
            self.last_bull_bar = len(self.data)


