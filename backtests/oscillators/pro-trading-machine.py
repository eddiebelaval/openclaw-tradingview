import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # VZO calculation
        def calc_vzo():
            dir_series = np.where(close > close.shift(3), volume, -volume)
            raw = 100.0 * close.rolling(20).apply(lambda x: np.polyfit(range(len(x)), x, 1)[0] if len(x) > 1 else 0, raw=False) / np.maximum(volume.rolling(20).apply(lambda x: np.polyfit(range(len(x)), x, 1)[0] if len(x) > 1 else 0, raw=False), 1e-6)
            clamped = np.clip(raw, -120.0, 120.0)
            return pd.Series(clamped).ewm(span=5, adjust=False).mean()
        
        self.vzo = self.I(calc_vzo)
        
        # Z-Score calculation
        def calc_zscore():
            zs = (close - close.rolling(20).mean()) / np.maximum(close.rolling(20).std(), 1e-10)
            return np.clip(zs, -4.0, 4.0)
        
        self.zscore = self.I(calc_zscore)
        
        # CTO calculation (simplified 33-MA cluster voting)
        def calc_cto():
            scores = pd.Series(0, index=close.index, dtype=float)
            for i in range(1, 34):
                ema = close.ewm(span=i*2, adjust=False).mean()
                scores += np.where(close > ema, 1, -1)
            raw = scores / 33.0
            sm = raw.ewm(span=3, adjust=False).mean()
            return np.clip(sm / 1.0, -1.0, 1.0)
        
        self.cto = self.I(calc_cto)
        
        # ADX calculation
        def calc_adx():
            adx_result = pta.adx(high, low, close, length=14)
            if adx_result is not None and len(adx_result) > 0:
                adx_vals = adx_result.iloc[:, 0] if hasattr(adx_result, 'iloc') else adx_result
                return np.clip((adx_vals - 20.0) / 20.0, -1.0, 1.0)
            return pd.Series(0, index=close.index)
        
        self.adx = self.I(calc_adx)
        
        # RSI calculation
        def calc_rsi():
            rsi_vals = pta.rsi(close, length=14)
            if rsi_vals is not None:
                return np.clip((rsi_vals - 50.0) / 50.0, -1.0, 1.0)
            return pd.Series(0, index=close.index)
        
        self.rsi = self.I(calc_rsi)
        
        # Composite calculation (weighted average of components)
        def calc_composite():
            comp = (self.cto + self.adx + self.rsi) / 3.0
            return comp.ewm(span=3, adjust=False).mean() * 100.0
        
        self.composite = self.I(calc_composite)

    def next(self):
        # Entry conditions based on confluence of indicators
        vzo_bullish = self.vzo[-1] > 20
        zscore_bullish = self.zscore[-1] > 0.5
        cto_bullish = self.cto[-1] > 0.3
        composite_bullish = self.composite[-1] > 10
        
        vzo_bearish = self.vzo[-1] < -20
        zscore_bearish = self.zscore[-1] < -0.5
        cto_bearish = self.cto[-1] < -0.3
        composite_bearish = self.composite[-1] < -10
        
        # Buy signal: 2+ bullish indicators aligned
        bull_signals = sum([vzo_bullish, zscore_bullish, cto_bullish, composite_bullish])
        if bull_signals >= 2 and not self.position:
            self.buy()
        
        # Sell signal: 2+ bearish indicators aligned or exit on reversal
        bear_signals = sum([vzo_bearish, zscore_bearish, cto_bearish, composite_bearish])
        if bear_signals >= 2 and self.position:
            self.position.close()
        
        # Exit on strong reversal signals
        if self.position and bear_signals >= 3:
            self.position.close()
        
        # Stop-loss based on recent extreme
        if self.position:
            recent_high = max(self.data.High[-20:]) if len(self.data.High) >= 20 else self.data.High[-1]
            recent_low = min(self.data.Low[-20:]) if len(self.data.Low) >= 20 else self.data.Low[-1]
            atr = recent_high - recent_low
            
            if self.position.is_long and self.data.Close[-1] < self.position.open_price - atr:
                self.position.close()


