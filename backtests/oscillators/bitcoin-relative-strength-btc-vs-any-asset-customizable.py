import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA1 parameters
    ma1_len = 20
    ma1_type = "EMA"
    
    # MA2 parameters
    ma2_len = 50
    ma2_type = "SMA"
    
    # Bollinger Bands parameters
    bb_len = 20
    bb_mult = 2.0
    
    # RSI parameters
    rsi_len = 14
    rsi_ob = 70
    rsi_os = 30
    
    # Percent change period
    pct_period = 30

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # MA1 calculation
        if self.ma1_type == "SMA":
            self.ma1 = self.I(pta.sma, close, length=self.ma1_len)
        elif self.ma1_type == "EMA":
            self.ma1 = self.I(pta.ema, close, length=self.ma1_len)
        elif self.ma1_type == "WMA":
            self.ma1 = self.I(pta.wma, close, length=self.ma1_len)
        elif self.ma1_type == "RMA":
            self.ma1 = self.I(pta.rma, close, length=self.ma1_len)
        else:
            self.ma1 = self.I(pta.ema, close, length=self.ma1_len)
        
        # MA2 calculation
        if self.ma2_type == "SMA":
            self.ma2 = self.I(pta.sma, close, length=self.ma2_len)
        elif self.ma2_type == "EMA":
            self.ma2 = self.I(pta.ema, close, length=self.ma2_len)
        elif self.ma2_type == "WMA":
            self.ma2 = self.I(pta.wma, close, length=self.ma2_len)
        elif self.ma2_type == "RMA":
            self.ma2 = self.I(pta.rma, close, length=self.ma2_len)
        else:
            self.ma2 = self.I(pta.sma, close, length=self.ma2_len)
        
        # Bollinger Bands
        bb = self.I(pta.bbands, close, length=self.bb_len, std=self.bb_mult)
        self.bb_upper = bb.iloc[:, 0] if bb is not None else self.I(lambda: pd.Series(np.nan, index=close.index))
        self.bb_lower = bb.iloc[:, 2] if bb is not None else self.I(lambda: pd.Series(np.nan, index=close.index))
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)

    def next(self):
        # Ensure we have enough data
        if len(self.data) < max(self.ma1_len, self.ma2_len, self.pct_period):
            return
        
        close_val = self.data.Close[-1]
        ma1_val = self.ma1[-1]
        ma2_val = self.ma2[-1]
        bb_upper_val = self.bb_upper[-1]
        bb_lower_val = self.bb_lower[-1]
        rsi_val = self.rsi[-1]
        
        # Skip if any critical values are NaN
        if np.isnan(ma1_val) or np.isnan(ma2_val):
            return
        
        # Entry signals
        
        # 1. Ratio crosses above MA1 - bullish
        if crossover(self.ma1, self.data.Close):
            if not self.position:
                self.buy()
        
        # 2. Ratio crosses below MA1 - bearish
        elif crossover(self.data.Close, self.ma1):
            if self.position:
                self.position.close()
        
        # 3. Golden cross (MA1 above MA2) - bullish confirmation
        if not np.isnan(ma2_val) and crossover(self.ma1, self.ma2):
            if not self.position:
                self.buy()
        
        # 4. Death cross (MA1 below MA2) - bearish confirmation
        if not np.isnan(ma2_val) and crossover(self.ma2, self.ma1):
            if self.position:
                self.position.close()
        
        # 5. Bollinger Band breakout above upper band - bullish
        if not np.isnan(bb_upper_val) and close_val > bb_upper_val:
            if not self.position:
                self.buy()
        
