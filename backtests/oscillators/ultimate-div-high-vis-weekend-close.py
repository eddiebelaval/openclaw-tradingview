import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 5
    min_conf = 2
    use_weekend_close = True
    friday_close_hour = 21

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI
        self.rsi_val = self.I(pta.rsi, close, length=14)
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.m_line = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACD_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        self.m_sig = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACDs_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        
        # Stochastic
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=14, d=3, smooth_k=3))
        self.stoch_k = self.I(lambda: pta.stoch(high, low, close, k=14, d=3, smooth_k=3)['STOCHk_14_3_3'] if pta.stoch(high, low, close, k=14, d=3, smooth_k=3) is not None else pd.Series(50, index=close.index))
        
        # Ichimoku Components
        self.tenkan = self.I(lambda: (high.rolling(9).max() + low.rolling(9).min()) / 2)
        self.kijun = self.I(lambda: (high.rolling(26).max() + low.rolling(26).min()) / 2)
        self.senkouA = self.I(lambda: ((high.rolling(9).max() + low.rolling(9).min()) / 2 + (high.rolling(26).max() + low.rolling(26).min()) / 2) / 2)
        self.senkouB = self.I(lambda: (high.rolling(52).max() + low.rolling(52).min()) / 2)
        
        # Pivot detection helpers
        self.pivot_low_detector = self.I(lambda: self._detect_pivot_low(low))
        self.pivot_high_detector = self.I(lambda: self._detect_pivot_high(high))
        
    def _detect_pivot_low(self, low_series):
        result = pd.Series(False, index=low_series.index)
        lb = self.lookback
        for i in range(lb, len(low_series) - lb):
            if low_series.iloc[i] == low_series.iloc[i-lb:i+lb+1].min():
                result.iloc[i] = True
        return result
    
    def _detect_pivot_high(self, high_series):
        result = pd.Series(False, index=high_series.index)
        lb = self.lookback
        for i in range(lb, len(high_series) - lb):
            if high_series.iloc[i] == high_series.iloc[i-lb:i+lb+1].max():
                result.iloc[i] = True
        return result
    
    def _check_bullish_div(self, src, low_data, high_data):
        lb = self.lookback
        if len(src) < lb * 2 + 1:
            return False
        
        current_idx = len(src) - 1
        
        # Find last pivot low in oscillator
        last_pivot_low_idx = None
        for i in range(current_idx - lb, max(0, current_idx - lb * 10), -1):
            if i >= lb and i < len(low_data) - lb:
                is_pivot = low_data.iloc[i] == low_data.iloc[max(0, i-lb):min(len(low_data), i+lb+1)].min()
                if is_pivot:
                    last_pivot_low_idx = i
                    break
        
        if last_pivot_low_idx is None or current_idx - last_pivot_low_idx < lb:
            return False
        
        last_low_price = low_data.iloc[last_pivot_low_idx]
        last_low_osc = src.iloc[last_pivot_low_idx]
        current_low = low_data.iloc[current_idx]
        current_osc = src.iloc[current_idx]
        
        div_found = current_low < last_low_price and current_osc > last_low_osc
        return div_found
    
    def _check_bearish_div(self, src, low_data, high_data):
        lb = self.lookback
        if len(src) < lb * 2 + 1:
            return False
        
        current_idx = len(src) - 1
        
        # Find last pivot high in oscillator
        last_pivot_high_idx = None
        for i in range(current_idx - lb, max(0, current_idx - lb * 10), -1):
            if i >= lb and i < len(high_data) - lb:
                is_pivot = high_data.iloc[i] == high_data.iloc[max(0, i-lb):min(len(high_data), i+lb+1)].max()
                if is_pivot:
                    last_pivot_high_idx = i
                    break
        
        if last_pivot_high_idx is None or current_idx - last_pivot_high_idx < lb:
            return False
        
        last_high_price = high_data.iloc[last_pivot_high_idx]
        last_high_osc = src.iloc[last_pivot_high_idx]
        current_high = high_data.iloc[current_idx]
        current_osc = src.iloc[current_idx]
        
        div_found = current_high > last_high_price and current_osc < last_high_osc
        return div_found

    def next(self):
        close_series = pd.Series(self.data.Close)
        high_series = pd.Series(self.data.High)
        low_series = pd.Series(self.data.Low)
        
        if len(self.data) < self.lookback * 2 + 10:
            return
        
        # Ichimoku conditions
        ichi_bull = self.data.Close[-1] > self.senkouA[-26] and self.data.Close[-1] > self.senkouB[-26]
        ichi_bear = self.data.Close[-1] < self.senkouA[-26] and self.data.Close[-1] < self.senkouB[-26]
        
        # Check divergences
        r_b = self._check_bullish_div(self.rsi_val[-len(self.data):], low_series, high_series)
        m_b = self._check_bullish_div(self.m_line[-len(self.data):], low_series, high_series)
        s_b = self._check_bullish_div(self.stoch_k[-len(self.data):], low_series, high_series)
        
        r_s = self._check_bearish_div(self.rsi_val[-len(self.data):], low_series, high_series)
        m_s = self._check_bearish_div(self.m_line[-len(self.data):], low_series, high_series)
        s_s = self._check_bearish_div(self.stoch_k[-len(self.data):], low_series, high_series)
        
        total_bull = sum([r_b, m_b, s_b])
        total_bear = sum([r_s, m_s, s_s])
        
        buy_sig = total_bull >= self.min_conf and ichi_bull
        sell_sig = total_bear >= self.min_conf and ichi_bear
        
        if self.position:
            if sell_sig and self.position.size > 0:
                self.position.close()
            elif buy_sig and self.position.size < 0:
                self.position.close()
        
        if buy_sig and not self.position:
            self.buy()
        elif sell_sig and not self.position:
            self.sell()