import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 21
    smooth = 9

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate price change (momentum)
        diff = close.diff()
        
        # Apply double EMA smoothing to the momentum
        ema1_diff = self.I(pta.ema, diff, length=self.length)
        smooth_diff = self.I(pta.ema, ema1_diff, length=self.smooth)
        
        # Apply double EMA smoothing to absolute momentum
        abs_diff = diff.abs()
        ema1_abs = self.I(pta.ema, abs_diff, length=self.length)
        smooth_abs = self.I(pta.ema, ema1_abs, length=self.smooth)
        
        # Normalize oscillator between -100 and 100
        def calc_osc():
            osc_values = pd.Series(np.where(smooth_abs == 0, 0, (100 * (smooth_diff / smooth_abs))))
            return pd.Series(osc_values, index=close.index)
        
        self.osc = self.I(calc_osc)
        
        # Signal line
        self.signal = self.I(pta.ema, self.osc, length=self.smooth)

    def next(self):
        # Bullish signal: crossover of osc above signal when osc < 0
        if len(self.data) < 2:
            return
        
        bull_cross = crossover(self.osc, self.signal) and self.osc[-1] < 0
        bear_cross = crossover(self.signal, self.osc) and self.osc[-1] > 0
        
        if bull_cross:
            self.buy()
        elif bear_cross:
            self.sell()