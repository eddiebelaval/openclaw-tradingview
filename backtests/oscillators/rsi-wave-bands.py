import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    bandSmoothingLength = 8

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Constants
        self.halfRange = 50.0
        self.epsilon = 1e-10
        self.smoothingFactor = 1.0 / self.rsiLength
        self.inverseSqrtLengthMinusOne = 1.0 / np.power(np.maximum(self.rsiLength - 1.0, 1.0), 0.5)
        
        # Helper function: custom tanh
        def custom_tanh(value):
            exp_val = np.exp(2.0 * value)
            return (exp_val - 1.0) / (exp_val + 1.0)
        
        def rsi_distance_from_50(z_score):
            return self.halfRange * custom_tanh(z_score * self.inverseSqrtLengthMinusOne)
        
        # Adaptive RSI engine
        def calc_bands():
            middle = pta.rma(close, length=self.rsiLength)
            
            close_volatility = pta.rma(np.abs(close - close.shift(1)), length=self.rsiLength)
            
            close_denominator = np.maximum(close_volatility, self.epsilon) * (self.rsiLength - 1.0)
            
            adaptive_rsi = self.halfRange + self.halfRange * ((close - middle) / close_denominator)
            
            def price_at_rsi(rsi_value):
                return middle + ((rsi_value - 50.0) / 50.0) * close_denominator
            
            # Thresholds
            reversal_threshold = np.sqrt(3.0)
            tail_threshold = np.sqrt((5.0 + np.sqrt(17.0)) / 2.0)
            
            overbought_inner = 50.0 + rsi_distance_from_50(reversal_threshold)
            overbought_outer = 50.0 + rsi_distance_from_50(tail_threshold)
            oversold_inner = 50.0 - rsi_distance_from_50(reversal_threshold)
            oversold_outer = 50.0 - rsi_distance_from_50(tail_threshold)
            
            upper_band_raw = price_at_rsi(overbought_inner)
            lower_band_raw = price_at_rsi(oversold_inner)
            upper_tail_raw = price_at_rsi(overbought_outer)
            lower_tail_raw = price_at_rsi(oversold_outer)
            
