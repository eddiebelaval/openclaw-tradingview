import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    mfi_len = 60
    mfi_mult = 0.15
    conf_bars = 3
    extreme_lvl = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # HLC3 calculation
        hlc3 = (high + low + close) / 3
        
        # Core Money Flow Logic
        raw_mfi = self.I(pta.mfi, high, low, close, length=self.mfi_len)
        centered_mfi = (raw_mfi - 50) * self.mfi_mult
        self.mf = self.I(pta.ema, centered_mfi, length=3)
        
        # Curvature Analysis
        self.slope = self.I(lambda: self.mf - self.mf.shift(1))
        self.acceleration = self.I(lambda: self.slope - self.slope.shift(1))
        
        # Pattern Detection signals
        self.is_rounding_bull = self.I(
            lambda: (self.mf < -self.extreme_lvl) & 
                    (self.slope > 0) & 
                    (self.acceleration > 0)
        )
        self.is_rounding_bear = self.I(
            lambda: (self.mf > self.extreme_lvl) & 
                    (self.slope < 0) & 
                    (self.acceleration < 0)
        )
        
        # Duration tracking
        self.bull_dur = self.I(self._calc_bull_duration)
        self.bear_dur = self.I(self._calc_bear_duration)
        
        # High Confidence signals
        self.early_bullish = self.I(lambda: self.bull_dur >= self.conf_bars)
        self.early_bearish = self.I(lambda: self.bear_dur >= self.conf_bars)

    def _calc_bull_duration(self):
        result = pd.Series(0, index=self.data.Close.index)
        duration = 0
        for i in range(len(self.data.Close)):
            if self.is_rounding_bull.iloc[i]:
                duration += 1
            else:
                duration = 0
            result.iloc[i] = duration
        return result

    def _calc_bear_duration(self):
        result = pd.Series(0, index=self.data.Close.index)
        duration = 0
        for i in range(len(self.data.Close)):
            if self.is_rounding_bear.iloc[i]:
                duration += 1
            else:
                duration = 0
            result.iloc[i] = duration
        return result

    def next(self):
        if len(self.data) < 2:
            return
        
        # High confidence bullish signal
        if self.early_bullish[-1] and not self.position:
            self.buy()
        
        # High confidence bearish signal
        elif self.early_bearish[-1] and self.position:
            self.sell()


