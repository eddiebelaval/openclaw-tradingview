class TvStrategy(Strategy):
    ema1_len = 10
    ema2_len = 20
    rsi_len = 5
    ma_rsi_len = 9
    alpha = 0.1
    use_weighted = False
    low_thr = 28.0
    high_thr = 72.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema1 = self.I(pta.ema, close, length=self.ema1_len)
        self.ema2 = self.I(pta.ema, close, length=self.ema2_len)
        
        # Calculate diff and slope
        def calc_diff():
            return self.ema1 - self.ema2
        self.diff = self.I(calc_diff)
        
        # RSI values
        self.rsi_val = self.I(pta.rsi, close, length=self.rsi_len)
        
        # MA of RSI
        self.ma_exp_rsi = self.I(pta.ema, self.rsi_val, length=self.ma_rsi_len)
        self.ma_wei_rsi = self.I(pta.wma, self.rsi_val, length=self.ma_rsi_len)
        
        # InvFish calculation
        def calc_invfish():
            ma = self.ma_wei_rsi if self.use_weighted else self.ma_exp_rsi
            x = self.alpha * (ma - 50.0)
            e2 = np.exp(2.0 * x)
            t = (e2 - 1.0) / (e2 + 1.0)
            return 50.0 * (t + 1.0)
        
        self.invfish = self.I(calc_invfish)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Determine slopes
        sloping_down = self.diff[-1] < self.diff[-2]
        sloping_up = self.diff[-1] > self.diff[-2]
        
        # Conditions
        red_cond = sloping_down and self.invfish[-1] < self.low_thr
        green_cond = sloping_up and self.invfish[-1] > self.high_thr
        
        # Trading logic
        if green_cond and not self.position:
            self.buy()
        elif red_cond and self.position:
            self.sell()


