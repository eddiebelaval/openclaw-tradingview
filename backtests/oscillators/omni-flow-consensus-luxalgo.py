import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    flowLenInput = 24
    spectralLenInput = 10
    boostInput = 1.5
    smoothSignalsInput = True
    strictnessInput = 3
    thresholdInput = 15.0

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume) if hasattr(self.data, 'Volume') else pd.Series(0, index=close.index)

        def calculate_flow():
            smart_vol = np.where(volume > 0, volume, pta.atr(high, low, close, length=1))
            vol_pressure = (close - open_) / np.maximum(high - low, 0.00001) * smart_vol
            fpi_raw = pta.sma(pd.Series(vol_pressure), length=self.flowLenInput)
            
            fpi_highest = fpi_raw.rolling(window=self.flowLenInput * 2).max()
            fpi_lowest = fpi_raw.rolling(window=self.flowLenInput * 2).min()
            fpi_range = np.maximum(fpi_highest - fpi_lowest, 0.00001)
            fpi_norm = ((fpi_raw - fpi_lowest) / fpi_range * 200) - 100
            
            boosted_flow = np.sign(fpi_norm) * np.power(np.abs(fpi_norm) / 100, 1 / self.boostInput) * 100
            
            return boosted_flow

        def asf_calculation(boosted_flow_series):
            alpha = 2.0 / (self.spectralLenInput + 1)
            atr_val = pta.atr(high, low, close, length=self.spectralLenInput)
            
            result = pd.Series(index=boosted_flow_series.index, dtype=float)
            out = boosted_flow_series.iloc[0]
            
            for i in range(len(boosted_flow_series)):
                if i == 0:
                    result.iloc[i] = boosted_flow_series.iloc[i]
                    out = boosted_flow_series.iloc[i]
                else:
                    diff = abs(boosted_flow_series.iloc[i] - boosted_flow_series.iloc[i-1])
                    atr_safe = atr_val.iloc[i] if not pd.isna(atr_val.iloc[i]) else 0.00001
                    adaptive_alpha = min(1.0, alpha * (diff / (atr_safe + 0.00001)))
                    out = out + adaptive_alpha * (boosted_flow_series.iloc[i] - out)
                    result.iloc[i] = out
            
            return result

        boosted_flow_series = self.I(calculate_flow)
        self.flow_main = self.I(asf_calculation, boosted_flow_series)
        self.flow_signal = self.I(pta.ema, self.flow_main, length=5)

    def next(self):
        if len(self.flow_main) < 2 or len(self.flow_signal) < 2:
            return

        flow_main_current = self.flow_main[-1]
        flow_signal_current = self.flow_signal[-1]
        flow_main_prev = self.flow_main[-2]
        flow_signal_prev = self.flow_signal[-2]

        is_bullish = flow_main_current > 0
        
        raw_cross_up = flow_main_prev <= flow_signal_prev and flow_main_current > flow_signal_current
        raw_cross_dn = flow_main_prev >= flow_signal_prev and flow_main_current < flow_signal_current

        is_impulse_bull = raw_cross_up and is_bullish and flow_main_current > self.thresholdInput
        is_impulse_bear = raw_cross_dn and not is_bullish and flow_main_current < -self.thresholdInput

        if is_impulse_bull:
            if not self.position:
                self.buy()
        elif is_impulse_bear:
            if self.position:
                self.position.close()