import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    period = 22
    cutoff_factor = 0.3
    smooth = 3
    sig_len = 9
    rev_threshold = 20.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate True Price (HLC3)
        tp = (high + low + close) / 3
        
        # Calculate Money Flow
        mf = close - (high + low) / 2 + tp - tp.shift(1)
        mf = mf.fillna(0)
        
        # Calculate ATR for adaptive cutoff
        atr = self.I(pta.atr, high, low, close, length=self.period)
        
        # Calculate cutoff level
        cutoff = atr * self.cutoff_factor
        
        # Volume Flow Decision
        v_flow = pd.Series(0.0, index=close.index)
        v_flow[mf > cutoff] = volume[mf > cutoff]
        v_flow[mf < -cutoff] = -volume[mf < -cutoff]
        
        # FVE Raw calculation
        def calc_fve_raw(idx):
            if idx < self.period:
                return 0.0
            period_v_flow = v_flow.iloc[idx-self.period+1:idx+1].sum()
            period_volume = volume.iloc[idx-self.period+1:idx+1].sum()
            if period_volume == 0:
                return 0.0
            return (period_v_flow / period_volume) * 100
        
        fve_raw = self.I(lambda: pd.Series([calc_fve_raw(i) for i in range(len(close))], index=close.index))
        
        # Smooth FVE
        if self.smooth > 1:
            self.fve = self.I(pta.ema, fve_raw, length=self.smooth)
        else:
            self.fve = fve_raw
        
        # Signal Line (SMA)
        self.signal_line = self.I(pta.sma, self.fve, length=self.sig_len)
        
        # Track pivot states for divergence
        self.last_high_pivot_val = None
        self.last_high_pivot_price = None
        self.last_low_pivot_val = None
        self.last_low_pivot_price = None

    def next(self):
        if len(self) < max(self.period, self.sig_len, 5):
            return
        
        fve_current = self.fve[-1]
        fve_prev = self.fve[-2] if len(self.fve) > 1 else fve_current
        signal_current = self.signal_line[-1]
        signal_prev = self.signal_line[-2] if len(self.signal_line) > 1 else signal_current
        
        # Reversal conditions
        is_oversold = signal_current < -self.rev_threshold
        is_overbought = signal_current > self.rev_threshold
        
        bull_rev = crossover(self.fve, self.signal_line) and is_oversold
        bear_rev = crossover(self.signal_line, self.fve) and is_overbought
        
        # Trading logic based on reversals
        if bull_rev:
            if not self.position:
                self.buy()
        elif bear_rev:
            if self.position:
                self.sell()


