    def _poc_near_val(self, close, high, low, volume):
        poc = self._calculate_poc(close, high, low, volume)
        val = self._calculate_val(close, high, low, volume)
        vah = self._calculate_vah(close, high, low, volume)
        
        result = []
        for i in range(len(poc)):
            va_range = vah.iloc[i] - val.iloc[i]
            if va_range != 0:
                poc_pos = (poc.iloc[i] - val.iloc[i]) / va_range
            else:
                poc_pos = 0.5
            result.append(poc_pos < self.pocSkew)
        
        return pd.Series(result, index=close.index)

    def _poc_near_vah(self, close, high, low, volume):
        poc = self._calculate_poc(close, high, low, volume)
