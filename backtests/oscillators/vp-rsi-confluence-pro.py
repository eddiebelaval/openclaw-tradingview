    def _calculate_poc(self, close, high, low, volume):
        if len(close) < self.vpLength:
            return pd.Series(0, index=close.index)
        
        result = []
        for idx in range(len(close)):
            if idx < self.vpLength - 1:
                result.append(0)
            else:
                start = idx - self.vpLength + 1
                end = idx + 1
                
                close_slice = close.iloc[start:end]
                vol_slice = volume.iloc[start:end]
                high_slice = high.iloc[start:end]
                low_slice = low.iloc[start:end]
                
                highest = high_slice.max()
                lowest = low_slice.min()
                price_range = highest - lowest
                
                if price_range == 0:
                    result.append(0)
                    continue
                
                row_height = price_range / self.numRows
                vol_profile = np.zeros(self.numRows)
                
                for j in range(len(close_slice)):
                    bin_idx = min(int((close_slice.iloc[j] - lowest) / row_height), self.numRows - 1)
                    if bin_idx >= 0:
                        vol_profile[bin_idx] += vol_slice.iloc[j]
                
                poc_idx = np.argmax(vol_profile)
                poc_price = lowest + (poc_idx + 0.5) * row_height
                result.append(poc_price)
        
        return pd.Series(result, index=close.index)

