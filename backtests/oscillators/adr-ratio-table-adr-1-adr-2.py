import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    shortLen = 5
    longLen = 21
    adr_ratio_threshold = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate daily range (high - low for each bar, treating as daily)
        daily_range = high - low
        
        # Calculate ADR Short and ADR Long
        self.adr_short = self.I(pta.sma, daily_range, length=self.shortLen)
        self.adr_long = self.I(pta.sma, daily_range, length=self.longLen)
        
        # Calculate ADR Ratio with protection against division by zero
        def calculate_ratio():
            ratio = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if self.adr_long[i] != 0 and self.adr_long[i] is not None:
                    ratio.iloc[i] = self.adr_short[i] / self.adr_long[i]
                else:
                    ratio.iloc[i] = np.nan
            return ratio
        
        self.adr_ratio = self.I(calculate_ratio)

    def next(self):
        # Trading logic based on ADR Ratio
        # Buy when ADR Ratio crosses above threshold (volatility expanding)
        if len(self.data) > 1:
            if not np.isnan(self.adr_ratio[-1]) and not np.isnan(self.adr_ratio[-2]):
                if self.adr_ratio[-2] <= self.adr_ratio_threshold and self.adr_ratio[-1] > self.adr_ratio_threshold:
                    if not self.position:
                        self.buy()
                # Sell when ADR Ratio crosses below threshold (volatility contracting)
                elif self.adr_ratio[-2] >= self.adr_ratio_threshold and self.adr_ratio[-1] < self.adr_ratio_threshold:
                    if self.position:
                        self.position.close()