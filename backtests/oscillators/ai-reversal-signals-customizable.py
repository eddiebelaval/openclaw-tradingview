import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_len = 14
    atr_len = 14
    tp1_mult = 1.5
    tp2_mult = 3.0
    sl_mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
    def next(self):
        if len(self.data) < self.rsi_len or len(self.data) < self.atr_len:
            return
        
        if self.rsi[-1] is None or self.atr[-1] is None:
            return
        
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        atr_val = self.atr[-1]
        
        long_cond = crossover(self.rsi, 30) and close > open_
        short_cond = crossover(70, self.rsi) and close < open_
        
        if long_cond:
            ep = close
            sl = low - (atr_val * self.sl_mult)
            tp1 = close + (atr_val * self.tp1_mult)
            tp2 = close + (atr_val * self.tp2_mult)
            
            if not self.position:
                self.buy()
        
        elif short_cond:
            ep = close
            sl = high + (atr_val * self.sl_mult)
            tp1 = close - (atr_val * self.tp1_mult)
            tp2 = close - (atr_val * self.tp2_mult)
            
            if self.position:
                self.sell()
            else:
                self.sell()
        
        elif self.position:
            if self.position.is_long:
                sl = low - (atr_val * self.sl_mult)
                tp1 = self.position.open_price + (atr_val * self.tp1_mult)
                tp2 = self.position.open_price + (atr_val * self.tp2_mult)
                
                if close <= sl or close >= tp2:
                    self.sell()
            elif self.position.is_short:
                sl = high + (atr_val * self.sl_mult)
                tp1 = self.position.open_price - (atr_val * self.tp1_mult)
                tp2 = self.position.open_price - (atr_val * self.tp2_mult)
                
                if close >= sl or close <= tp2:
                    self.buy()


