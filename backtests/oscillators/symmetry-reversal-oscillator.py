import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_len = 14
    atr_len = 20
    max_smooth = 15
    min_smooth = 5
    vol_factor = 0.5
    ob_level = 60
    os_level = -60

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate swing high and low
        self.swing_high = self.I(lambda: high.rolling(self.swing_len).max())
        self.swing_low = self.I(lambda: low.rolling(self.swing_len).min())
        
        # Calculate swing range
        self.swing_range = self.I(lambda: self.swing_high - self.swing_low)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.atr_val = self.I(lambda: atr.fillna(method='bfill').fillna(1e-10).clip(lower=1e-10))
        
        # Calculate oscillator
        def calc_osc():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if self.swing_range.iloc[i] > 0:
                    if close.iloc[i] >= self.swing_low.iloc[i] and close.iloc[i] <= self.swing_high.iloc[i]:
                        pos = (close.iloc[i] - self.swing_low.iloc[i]) / self.swing_range.iloc[i]
                        result.iloc[i] = (pos * 200) - 100
                    elif close.iloc[i] > self.swing_high.iloc[i]:
                        result.iloc[i] = 100
                    else:
                        result.iloc[i] = -100
                else:
                    result.iloc[i] = np.nan
            return result
        
        self.osc = self.I(calc_osc)
        
        # Calculate adaptive EMA
        def calc_adaptive_ema():
            result = pd.Series(index=close.index, dtype=float)
            adaptive_ema = np.nan
            
            for i in range(len(close)):
                if pd.isna(self.osc.iloc[i]):
                    result.iloc[i] = np.nan
                else:
                    if pd.isna(adaptive_ema):
                        adaptive_ema = self.osc.iloc[i]
                    else:
                        price_change = close.iloc[i] - close.iloc[i-1] if i > 0 else 0
                        volatility = min(max(abs(price_change) / max(self.atr_val.iloc[i], 1e-10) * self.vol_factor, 0), 1)
                        adaptive_len = round(min(max(self.max_smooth * (1 - volatility), self.min_smooth), self.max_smooth))
                        alpha = 2.0 / (adaptive_len + 1)
                        adaptive_ema = adaptive_ema + alpha * (self.osc.iloc[i] - adaptive_ema)
                    
                    result.iloc[i] = adaptive_ema
            
            return result
        
        self.ma1 = self.I(calc_adaptive_ema)
        
        # Trend determination
        self.trend_up = self.I(lambda: self.ma1 >= 0)
        
        # Signals
        def calc_long_signal():
            result = pd.Series(False, index=close.index)
            for i in range(1, len(self.ma1)):
                if not pd.isna(self.ma1.iloc[i-1]) and not pd.isna(self.ma1.iloc[i]):
                    if self.ma1.iloc[i-1] <= self.os_level and self.ma1.iloc[i] > self.os_level:
                        result.iloc[i] = True
            return result
        
        def calc_short_signal():
            result = pd.Series(False, index=close.index)
            for i in range(1, len(self.ma1)):
                if not pd.isna(self.ma1.iloc[i-1]) and not pd.isna(self.ma1.iloc[i]):
                    if self.ma1.iloc[i-1] >= self.ob_level and self.ma1.iloc[i] < self.ob_level:
                        result.iloc[i] = True
            return result
        
        self.long_signal = self.I(calc_long_signal)
        self.short_signal = self.I(calc_short_signal)

    def next(self):
        if len(self.data) < 2:
            return
        
        if self.long_signal[-1] and not self.position:
            self.buy()
        elif self.short_signal[-1] and self.position:
            self.position.close()