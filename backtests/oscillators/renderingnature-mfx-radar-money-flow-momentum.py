        def calc_wt1():
            ap = pta.sma(hlc3, length=wt_channel_length)
            esa = pta.ema(ap, length=wt_average_length)
            d = pta.ema((ap - esa).abs(), length=wt_average_length)
            d_safe = d.replace(0, 0.001)
            ci = (ap - esa) / (0.015 * d_safe)
            ci = ci.fillna(0)
            return pta.ema(ci, length=wt_ma_length)
        
