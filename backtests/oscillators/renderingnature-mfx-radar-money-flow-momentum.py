        self.rsi = self.I(pta.rsi, close, length=rsi_length)
        
        # Calculate BBWP
        def calc_bbwp():
            basis = pta.sma(close, length=bbwp_length)
            bbw = (pta.stdev(close, length=bbwp_length) / basis.replace(0, 0.001)) * 100
            lo = bbw.rolling(window=bbwp_lookback).min()
            hi = bbw.rolling(window=bbwp_lookback).max()
            rng = hi - lo
            rng_safe = rng.replace(0, 0.001)
            return ((bbw - lo) / rng_safe) * 100
        
        self.bbwp = self.I(calc_bbwp)
        
        # Calculate Hybrid Money Flow (CMF + MFI normalized)
        def calc_hybrid_mf():
            mfv = np.where(high != low, (((close - low) - (high - close)) / (high - low)), 0)
