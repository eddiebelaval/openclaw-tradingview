import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fast_length = 12
    slow_length = 26
    signal_length = 9
    rsi_length = 14
    smooth_length = 3
    ema_length = 14
    trend_length = 200
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hlc3 = (high + low + close) / 3
        
        fast_ma = pta.ema(close, length=self.fast_length)
        slow_ma = pta.ema(close, length=self.slow_length)
        
        macd_raw = 10000 * (fast_ma - slow_ma) / slow_ma
        self.macd = self.I(lambda: macd_raw if macd_raw is not None else pd.Series(0, index=close.index))
        
        signal_raw = pta.ema(self.macd, length=self.signal_length)
        self.signal = self.I(lambda: signal_raw if signal_raw is not None else pd.Series(0, index=close.index))
        
        rsi = pta.rsi(close, length=self.rsi_length)
        rsi_smoothed = pta.ema(rsi, length=self.smooth_length) if rsi is not None else None
        self.osc = self.I(lambda: rsi_smoothed if rsi_smoothed is not None else pd.Series(50, index=close.index))
        
        basis_raw = pta.ema(self.osc, length=self.ema_length)
        self.basis = self.I(lambda: basis_raw if basis_raw is not None else pd.Series(50, index=close.index))
        
        trend_ema = pta.ema(close, length=self.trend_length)
        self.trend_ema = self.I(lambda: trend_ema if trend_ema is not None else pd.Series(close.iloc[0], index=close.index))
    
    def next(self):
        if len(self.data) < max(self.fast_length, self.slow_length, self.signal_length, self.trend_length) + 10:
            return
        
        macd_crossover = crossover(self.macd, self.signal)
        macd_crossunder = crossover(self.signal, self.macd)
        
        osc_crossover_signal = crossover(self.osc, self.basis)
        osc_crossunder_signal = crossover(self.basis, self.osc)
        
        osc_overlow = 10
        osc_overhigh = 90
        
        macd_buy = (
            self.data.Close[-1] > self.trend_ema[-1] and
            macd_crossover and
            (self.macd[-1] < 0 or self.macd[-2] < 0)
        )
        
        macd_sell = (
            self.data.Close[-1] < self.trend_ema[-1] and
            macd_crossunder and
            (self.macd[-1] > 0 or self.macd[-2] > 0)
        )
        
        rsi_buy = (
            (self.data.High[-1] + self.data.Low[-1]) / 2 > self.trend_ema[-1] and
            self.data.Close[-1] > self.trend_ema[-1] and
            (osc_crossover_signal or 
             (osc_crossover_signal and (self.osc[-1] < osc_overlow or self.osc[-2] < osc_overlow)))
        )
        
        rsi_sell = (
            (self.data.High[-1] + self.data.Low[-1]) / 2 < self.trend_ema[-1] and
            self.data.Close[-1] < self.trend_ema[-1] and
            (osc_crossunder_signal or
             (osc_crossunder_signal and (self.osc[-1] > osc_overhigh or self.osc[-2] > osc_overhigh)))
        )
        
        if macd_buy or rsi_buy:
            self.buy()
        elif macd_sell or rsi_sell:
            self.sell()


