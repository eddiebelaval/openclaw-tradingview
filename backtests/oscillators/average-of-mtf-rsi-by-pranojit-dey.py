class TvStrategy(Strategy):
    # Default parameters from the Pine Script
    currLen = 14
    len1 = 14
    len2 = 14
    len3 = 14
    len4 = 14
    obLevel = 70
    osLevel = 30

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI for current timeframe (using previous bar)
        rsi_curr_full = self.I(lambda: pta.rsi(close, length=self.currLen) or pd.Series(50, index=close.index))
        self.rsiCurr = self.I(lambda: rsi_curr_full.shift(1))
        
        # For MTF RSI, we simulate using the same close data with different lengths
        # Since backtesting.py doesn't support true multi-timeframe data,
        # we'll use the RSI values shifted to approximate MTF behavior
        rsi1_full = self.I(lambda: pta.rsi(close, length=self.len1) or pd.Series(50, index=close.index))
        rsi2_full = self.I(lambda: pta.rsi(close, length=self.len2) or pd.Series(50, index=close.index))
        rsi3_full = self.I(lambda: pta.rsi(close, length=self.len3) or pd.Series(50, index=close.index))
        rsi4_full = self.I(lambda: pta.rsi(close, length=self.len4) or pd.Series(50, index=close.index))
        
        self.rsi1 = self.I(lambda: rsi1_full.shift(1))
        self.rsi2 = self.I(lambda: rsi2_full.shift(1))
        self.rsi3 = self.I(lambda: rsi3_full.shift(1))
        self.rsi4 = self.I(lambda: rsi4_full.shift(1))
        
        # Calculate average RSI
        self.avgRSI = self.I(self._calculate_avg_rsi, rsi_curr_full, rsi1_full, rsi2_full, rsi3_full, rsi4_full)

    def _calculate_avg_rsi(self, rsi_curr, rsi1, rsi2, rsi3, rsi4):
        # Create shifted versions to match previous bar
        rsi_curr_shifted = rsi_curr.shift(1)
        rsi1_shifted = rsi1.shift(1)
        rsi2_shifted = rsi2.shift(1)
        rsi3_shifted = rsi3.shift(1)
        rsi4_shifted = rsi4.shift(1)
        
        avg = (rsi_curr_shifted + rsi1_shifted + rsi2_shifted + rsi3_shifted + rsi4_shifted) / 5.0
        return avg.fillna(50)

