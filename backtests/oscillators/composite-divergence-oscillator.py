import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    macdFast = 12
    macdSlow = 26
    macdSig = 9
    momLen = 10
    mfiLen = 14
    normLen = 50
    lbL = 5
    lbR = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)

        # MACD Histogram
        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSig))
        
        def get_macd_hist():
            result = pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSig)
            if result is None or result.empty:
                return pd.Series(0, index=close.index)
            macd_line = result.iloc[:, 0]
            signal_line = result.iloc[:, 1]
            return macd_line - signal_line
        
        self.macd_hist = self.I(get_macd_hist)

        # Normalize MACD Histogram
        def norm_macd():
            macd_h = get_macd_hist()
            macd_min = macd_h.rolling(window=self.normLen).min()
            macd_max = macd_h.rolling(window=self.normLen).max()
            normalized = (macd_h - macd_min) / (macd_max - macd_min + 1e-10) * 100
            return normalized.fillna(50)
        
        self.norm_macd = self.I(norm_macd)

        # Momentum
        def get_momentum():
            mom = close.diff(self.momLen)
            return mom.fillna(0)
        
        self.mom_val = self.I(get_momentum)

        # Normalize Momentum
        def norm_mom():
            mom = get_momentum()
            mom_min = mom.rolling(window=self.normLen).min()
            mom_max = mom.rolling(window=self.normLen).max()
            normalized = (mom - mom_min) / (mom_max - mom_min + 1e-10) * 100
            return normalized.fillna(50)
        
        self.norm_mom = self.I(norm_mom)

        # MFI (Money Flow Index)
        self.mfi = self.I(pta.mfi, high, low, close, volume, length=self.mfiLen)

        # Composite Oscillator (Average)
        def get_composite():
            rsi_vals = self.rsi
            macd_vals = self.norm_macd
            mom_vals = self.norm_mom
            mfi_vals = self.mfi
            
            composite = (rsi_vals + macd_vals + mom_vals + mfi_vals) / 4
            return composite.fillna(50)
        
        self.composite = self.I(get_composite)

