import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    bandSmoothingLength = 8
    panelMaLengthInput = 21
    bbMultInput = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Constants
        epsilon = 1e-10
        smoothingFactor = 1.0 / self.rsiLength
        inverseSqrtLengthMinusOne = 1.0 / np.power(np.maximum(self.rsiLength - 1.0, 1.0), 0.5)
        halfRange = 50.0

        # Helper functions
        def logit_transform(value, eps):
            clamped = np.clip(value, eps, 100.0 - eps)
            return np.log(clamped / (100.0 - clamped))

        def inverse_logit_transform(value):
            return 100.0 / (1.0 + np.exp(-value))

        def tanh_custom(value):
            exponent = np.exp(2.0 * value)
            return (exponent - 1.0) / (exponent + 1.0)

        def rsi_distance_from_50(zScore):
            return halfRange * tanh_custom(zScore * inverseSqrtLengthMinusOne)

        # Adaptive RSI engine
        def adaptive_rsi_calc():
            rma_close = pta.rma(close, length=self.rsiLength)
            if rma_close is None:
                return pd.Series(50.0, index=close.index)
            rma_close = rma_close.fillna(method='bfill').fillna(50.0)

            close_vol = pta.rma(np.abs(close.diff().fillna(0)), length=self.rsiLength)
            if close_vol is None:
                close_vol = pd.Series(0.1, index=close.index)
            close_vol = close_vol.fillna(0.1)

            close_denom = np.maximum(close_vol, epsilon) * (self.rsiLength - 1.0)
            adaptive_rsi = halfRange + halfRange * ((close - rma_close) / close_denom)
            return np.clip(adaptive_rsi, 0, 100)

        def logit_close_calc():
            rsi = adaptive_rsi_calc()
            return logit_transform(rsi, epsilon)

        def middle_calc():
            rma = pta.rma(close, length=self.rsiLength)
            return rma.fillna(method='bfill').fillna(close.iloc[0]) if rma is not None else close

        def price_at_rsi_calc(rsi_val):
            mid = middle_calc()
            rma_close = pta.rma(close, length=self.rsiLength)
            rma_close = rma_close.fillna(method='bfill').fillna(close.iloc[0])
            close_vol = pta.rma(np.abs(close.diff().fillna(0)), length=self.rsiLength)
            close_vol = close_vol.fillna(0.1)
            close_denom = np.maximum(close_vol, epsilon) * (self.rsiLength - 1.0)
            return mid + ((rsi_val - 50.0) / 50.0) * close_denom

        # Thresholds
        bodyThreshold = np.sqrt((5.0 - np.sqrt(17.0)) / 2.0)
        tailThreshold = np.sqrt((5.0 + np.sqrt(17.0)) / 2.0)
        breakoutThreshold = 1.0
        reversalThreshold = np.sqrt(3.0)

        supportInnerDistance = rsi_distance_from_50(bodyThreshold)
        supportOuterDistance = rsi_distance_from_50(breakoutThreshold)
        extremeInnerDistance = rsi_distance_from_50(reversalThreshold)
        extremeOuterDistance = rsi_distance_from_50(tailThreshold)

        # Wave band RSI thresholds
        waveOverboughtInner = 50.0 + extremeInnerDistance
        waveOversoldInner = 50.0 - extremeInnerDistance
        waveOverboughtOuter = 50.0 + extremeOuterDistance
        waveOversoldOuter = 50.0 - extremeOuterDistance

        # Store constants for next()
        self.extremeInnerDistance = extremeInnerDistance
        self.extremeOuterDistance = extremeOuterDistance
        self.waveOverboughtInner = waveOverboughtInner
        self.waveOversoldInner = waveOversoldInner

        # Calculate adaptive RSI
        self.adaptiveRsi = self.I(adaptive_rsi_calc)

        # Calculate wave bands
        def upper_band_raw():
            return price_at_rsi_calc(waveOverboughtInner)

        def lower_band_raw():
            return price_at_rsi_calc(waveOversoldInner)

        upper_raw = self.I(upper_band_raw)
        lower_raw = self.I(lower_band_raw)

        # Smooth bands with RMA
        def upper_band_smooth():
            rma = pta.rma(upper_raw, length=self.bandSmoothingLength)
            return rma.fillna(method='bfill').fillna(upper_raw.iloc[0]) if rma is not None else upper_raw

        def lower_band_smooth():
            rma = pta.rma(lower_raw, length=self.bandSmoothingLength)
            return rma.fillna(method='bfill').fillna(lower_raw.iloc[0]) if rma is not None else lower_raw

        self.upperBand = self.I(upper_band_smooth)
        self.lowerBand = self.I(lower_band_smooth)

    def next(self):
        current_rsi = self.adaptiveRsi[-1]
        current_upper_band = self.upperBand[-1]
        current_lower_band = self.lowerBand[-1]
        current_price = self.data.Close[-1]

        # Buy when price touches lower band and RSI is oversold
        if current_price <= current_lower_band and current_rsi < self.waveOversoldInner:
            if not self.position:
                self.buy()
        # Sell when price touches upper band and RSI is overbought
        elif current_price >= current_upper_band and current_rsi > self.waveOverboughtInner:
            if self.position:
                self.position.close()
        # Exit on extreme overbought
        elif current_rsi > self.extremeOuterDistance + 50.0:
            if self.position:
                self.position.close()
        # Exit on extreme oversold reversal
        elif current_rsi < 50.0 - self.extremeOuterDistance and current_rsi > 50.0 - self.extremeInnerDistance:
            if self.position:
                self.position.close()


