import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters
    bb_mult = 2.0
    bb_len = 20
    stoch_len = 14
    stoch_k = 3
    stoch_d = 3
    adx_len = 14
    adx_cutoff = 25
    atr_len = 14
    tp_mult = 3.5
    sl_mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        bb = self.I(lambda: pta.bbands(close, length=self.bb_len, std=self.bb_mult))
        self.bb_upper = self.I(lambda: bb['BBU_' + str(self.bb_len) + '_' + str(self.bb_mult)] if bb is not None else pd.Series(0, index=close.index))
        self.bb_mid = self.I(lambda: bb['BBM_' + str(self.bb_len) + '_' + str(self.bb_mult)] if bb is not None else pd.Series(0, index=close.index))
        self.bb_lower = self.I(lambda: bb['BBL_' + str(self.bb_len) + '_' + str(self.bb_mult)] if bb is not None else pd.Series(0, index=close.index))
        
        # Stochastic
        stoch = self.I(lambda: pta.stoch(high, low, close, k=self.stoch_len, d=self.stoch_d, smooth_k=self.stoch_k))
        self.stoch_k_val = self.I(lambda: stoch['STOCHk_' + str(self.stoch_len) + '_' + str(self.stoch_d) + '_' + str(self.stoch_k)] if stoch is not None else pd.Series(50, index=close.index))
        
        # ADX
        adx = self.I(lambda: pta.adx(high, low, close, length=self.adx_len))
        self.adx = self.I(lambda: adx['ADX_' + str(self.adx_len)] if adx is not None else pd.Series(20, index=close.index))
        
        # ATR
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atr_len))

    def next(self):
        # Current values
        current_high = self.data.High[-1]
        current_close = self.data.Close[-1]
        current_stoch = self.stoch_k_val[-1]
        current_adx = self.adx[-1]
        current_atr = self.atr[-1]
        current_bb_upper = self.bb_upper[-1]
        
        # Avoid NaN values
        if pd.isna(current_stoch) or pd.isna(current_adx) or pd.isna(current_atr) or pd.isna(current_bb_upper):
            return
        
        # Market is flat if ADX < threshold
        is_flat = current_adx < self.adx_cutoff
        
        # Short signal: Price crosses above BB upper + Stoch > 80 + Flat
        short_signal = (len(self.data) > 1 and 
                       self.data.High[-2] <= self.bb_upper[-2] and 
                       current_high > current_bb_upper and 
                       current_stoch > 80 and 
                       is_flat)
        
        # Entry logic
        if short_signal and not self.position:
            self.buy()
        
        # Exit logic
        if self.position:
            sl = current_close + (current_atr * self.sl_mult)
            tp = current_close - (current_atr * self.tp_mult)
            
            if current_close >= sl or current_close <= tp:
                self.sell()


