import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fast_length = 12
    slow_length = 26
    signal_length = 9

    def init(self):
        close = pd.Series(self.data.Close)
        
        fast_ma = self.I(pta.ema, close, length=self.fast_length)
        slow_ma = self.I(pta.ema, close, length=self.slow_length)
        
        macd_line = self.I(lambda: fast_ma - slow_ma)
        signal_line = self.I(pta.sma, macd_line, length=self.signal_length)
        
        self.macd_line = macd_line
        self.signal_line = signal_line

    def next(self):
        if crossover(self.macd_line, self.signal_line):
            if not self.position:
                self.buy()
        elif crossover(self.signal_line, self.macd_line):
            if self.position:
                self.position.close()


