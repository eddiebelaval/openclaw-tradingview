import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    SCRSI = 30
    SVRSI = 70

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        
        self.gain = self.I(lambda: pta.rma(np.maximum(close.diff(), 0), length=self.rsiLength) or pd.Series(0, index=close.index))
        self.loss = self.I(lambda: pta.rma(np.maximum(-close.diff(), 0), length=self.rsiLength) or pd.Series(0, index=close.index))

    def next(self):
        if len(self.data) < self.rsiLength + 1:
            return
        
        rsi_val = self.rsi[-1]
        
        if rsi_val is None or pd.isna(rsi_val):
            return
        
        if not self.position:
            if rsi_val < self.SCRSI:
                self.buy()
            elif rsi_val > self.SVRSI:
                self.sell()
        else:
            if self.position.is_long and rsi_val > self.SVRSI:
                self.position.close()
            elif self.position.is_short and rsi_val < self.SCRSI:
                self.position.close()


