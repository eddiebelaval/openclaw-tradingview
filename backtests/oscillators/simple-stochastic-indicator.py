import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    kLength = 14
    dLength = 3
    smoothK = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Stochastic
        stoch_result = self.I(pta.stoch, high, low, close, k=self.kLength, d=self.dLength)
        stoch_k = stoch_result.iloc[:, 0] if stoch_result is not None else pd.Series(50, index=close.index)
        
        # Smooth K line
        self.k = self.I(pta.sma, stoch_k, length=self.smoothK)
        
        # Calculate D line (SMA of K)
        self.d = self.I(pta.sma, self.k, length=self.dLength)

    def next(self):
        if len(self.data) < max(self.kLength, self.smoothK, self.dLength) + 5:
            return
        
        # Buy when K crosses above D from below oversold level (20)
        if crossover(self.k, self.d) and self.k[-1] < 30:
            if not self.position:
                self.buy()
        
        # Sell when K crosses below D from above overbought level (80)
        elif crossover(self.d, self.k) and self.k[-1] > 70:
            if self.position:
                self.sell()
        
        # Alternative: Sell when K crosses below oversold threshold
        elif self.k[-1] < 20 and self.k[-2] >= 20:
            if self.position:
                self.sell()