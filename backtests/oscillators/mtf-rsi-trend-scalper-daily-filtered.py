import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI on current timeframe (hourly equivalent)
        self.rsiHourly = self.I(pta.rsi, close, length=self.rsiLength)
        
        # For daily RSI, we'll use a longer period as a proxy since we're working with intraday data
        # Using a 24-period RSI as a substitute for daily RSI on hourly data
        self.rsiDaily = self.I(pta.rsi, close, length=self.rsiLength * 24)

    def next(self):
        # Long condition: daily RSI > 60 and hourly RSI < 20
        longCondition = (self.rsiDaily[-1] > 60) and (self.rsiHourly[-1] < 20)
        
        # Short condition: daily RSI < 40 and hourly RSI > 80
        shortCondition = (self.rsiDaily[-1] < 40) and (self.rsiHourly[-1] > 80)
        
        # Entry logic
        if longCondition and not self.position:
            self.buy()
        elif shortCondition and not self.position:
            self.position.close() if self.position else None
            self.sell()
        
        # Exit logic - simple exit after entry signal reversal
        if self.position:
            if self.position.is_long and shortCondition:
                self.position.close()
            elif self.position.is_short and longCondition:
                self.position.close()