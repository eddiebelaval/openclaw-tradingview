            old_pl_price = low_arr[old_idx]
            
            is_bull = old_pl_price > prev_pl_price and old_pl_rsi < prev_pl_rsi
            filter_pass = not self.filter_ob_os or (prev_pl_rsi < 30 and old_pl_rsi < 30)
            
            if is_bull and filter_pass:
                self.bull_divs[current_idx] = 1
                break

