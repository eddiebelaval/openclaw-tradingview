class TvStrategy(Strategy):
    rsi_len = 14
    lbR = 5
    lbL = 5
    filter_ob_os = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        self.bull_divs = np.zeros(len(self.data))
        self.bear_divs = np.zeros(len(self.data))
        
        self.prev_bull_div_bar = -1
        self.prev_bear_div_bar = -1

    def next(self):
        if len(self) < self.lbL + self.lbR + 1:
            return
        
        idx = len(self) - 1
        
        self.detect_divergences(idx)
        
        if self.bull_divs[idx] > 0 and idx > self.prev_bull_div_bar:
            self.prev_bull_div_bar = idx
            if not self.position:
                self.buy()
        
        elif self.bear_divs[idx] > 0 and idx > self.prev_bear_div_bar:
            self.prev_bear_div_bar = idx
            if self.position:
                self.position.close()

    def detect_divergences(self, current_idx):
        if current_idx < self.lbL + self.lbR:
            return
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
