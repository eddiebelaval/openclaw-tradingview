import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # SMI Parameters
    length_smi = 101
    length_ma_smi = 365
    source_ma_smi = 'EMA'
    signal_smi = '50'  # '50' or 'SMI MA'

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Stochastic
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=self.length_smi, d=3, smooth_k=3))
        self.smi = stoch_result
        
        # Calculate Moving Average of SMI
        def calc_smi_ma():
            stoch_vals = pta.stoch(high, low, close, k=self.length_smi, d=3, smooth_k=3)
            if stoch_vals is None or len(stoch_vals) == 0:
                return pd.Series(50, index=close.index)
            
            if self.source_ma_smi == 'EMA':
                ma_result = pta.ema(stoch_vals, length=self.length_ma_smi)
            elif self.source_ma_smi == 'SMA':
                ma_result = pta.sma(stoch_vals, length=self.length_ma_smi)
            elif self.source_ma_smi == 'RMA':
                ma_result = pta.rma(stoch_vals, length=self.length_ma_smi)
            elif self.source_ma_smi == 'WMA':
                ma_result = pta.wma(stoch_vals, length=self.length_ma_smi)
            elif self.source_ma_smi == 'VWMA':
                volume = pd.Series(self.data.Volume)
                ma_result = pta.vwma(stoch_vals, volume, length=self.length_ma_smi)
            else:
                ma_result = pta.sma(stoch_vals, length=self.length_ma_smi)
            
            if ma_result is None:
                return pd.Series(50, index=close.index)
            return ma_result
        
        self.smi_ma = self.I(calc_smi_ma)
        
        # Determine entry signal level
        if self.signal_smi == 'SMI MA':
            self.entry_level = self.smi_ma
        else:
            self.entry_level = self.I(lambda: pd.Series(50, index=close.index))

    def next(self):
        # Get current SMI and entry level values
        smi_current = self.smi[-1] if len(self.smi) > 0 else 50
        smi_prev = self.smi[-2] if len(self.smi) > 1 else 50
        entry_current = self.entry_level[-1] if len(self.entry_level) > 0 else 50
        entry_prev = self.entry_level[-2] if len(self.entry_level) > 1 else 50
        
        # Check for crossover (LONG signal)
        bull_signal = (smi_prev <= entry_prev) and (smi_current > entry_current)
        
        # Check for crossunder (SHORT signal)
        bear_signal = (smi_prev >= entry_prev) and (smi_current < entry_current)
        
        if bull_signal:
            if self.position:
                self.position.close()
            self.buy()
        elif bear_signal:
            if self.position:
                self.position.close()
            self.sell()


