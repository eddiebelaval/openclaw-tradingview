import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 20
    normLengthInput = 50
    thresholdInput = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate order flow delta
        def calc_delta():
            price_range = high - low
            buy_vol = np.where(price_range == 0, 0.0, volume * (close - low) / price_range)
            sell_vol = np.where(price_range == 0, 0.0, volume * (high - close) / price_range)
            return buy_vol - sell_vol
        
        delta = self.I(calc_delta)
        
        # Calculate relative delta
        def calc_rel_delta():
            rel_delta = np.where(volume == 0, 0.0, delta / volume)
            return rel_delta
        
        rel_delta = self.I(calc_rel_delta)
        
        # Smooth with EMA
        smooth_delta = self.I(pta.ema, pd.Series(rel_delta), length=self.lengthInput)
        
        # Z-score normalization
        def calc_zscore():
            mean = smooth_delta.rolling(window=self.normLengthInput).mean()
            stdev = smooth_delta.rolling(window=self.normLengthInput).std()
            zscore = np.where(stdev == 0, 0.0, (smooth_delta - mean) / stdev)
            return pd.Series(zscore, index=smooth_delta.index)
        
        self.zscore = self.I(calc_zscore)

    def next(self):
        # Buy signal: Z-score crosses above threshold (extreme positive flow)
        if len(self.data) > self.normLengthInput + 1:
            if self.zscore[-2] <= self.thresholdInput and self.zscore[-1] > self.thresholdInput:
                if not self.position:
                    self.buy()
            
            # Sell signal: Z-score crosses below negative threshold (extreme negative flow)
            if self.zscore[-2] >= -self.thresholdInput and self.zscore[-1] < -self.thresholdInput:
                if self.position:
                    self.position.close()
            
            # Additional exit: Z-score crosses zero line going down
            if self.zscore[-2] > 0 and self.zscore[-1] <= 0:
                if self.position:
                    self.position.close()


