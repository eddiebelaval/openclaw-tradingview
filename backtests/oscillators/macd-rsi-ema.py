import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    emaLen = 200
    fastLen = 12
    slowLen = 26
    sigLen = 9
    rsiLen = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMA (Trend Filter)
        self.ema = self.I(pta.ema, close, length=self.emaLen)
        
        # Calculate MACD
        macd_result = self.I(lambda: pta.macd(close, fast=self.fastLen, slow=self.slowLen, signal=self.sigLen))
        self.macd_line = self.I(lambda: pta.macd(close, fast=self.fastLen, slow=self.slowLen, signal=self.sigLen).iloc[:, 0] if pta.macd(close, fast=self.fastLen, slow=self.slowLen, signal=self.sigLen) is not None else pd.Series(0, index=close.index))
        self.signal_line = self.I(lambda: pta.macd(close, fast=self.fastLen, slow=self.slowLen, signal=self.sigLen).iloc[:, 1] if pta.macd(close, fast=self.fastLen, slow=self.slowLen, signal=self.sigLen) is not None else pd.Series(0, index=close.index))
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)

    def next(self):
        close_val = self.data.Close[-1]
        ema_val = self.ema[-1]
        macd_val = self.macd_line[-1]
        signal_val = self.signal_line[-1]
        rsi_val = self.rsi[-1]
        
        # Avoid NaN values
        if pd.isna(ema_val) or pd.isna(macd_val) or pd.isna(signal_val) or pd.isna(rsi_val):
            return
        
