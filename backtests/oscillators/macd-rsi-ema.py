        # 1. Trend is Up (Price > EMA)
        # 2. MACD Bullish Crossover
        # 3. RSI is Healthy (Between 50 and 65)
        long_condition = (close_val > ema_val) and crossover(self.macd_line, self.signal_line) and (rsi_val > 50 and rsi_val < 65)
        
        # SHORT CONDITION
        # 1. Trend is Down (Price < EMA)
        # 2. MACD Bearish Crossover
        # 3. RSI is Healthy (Between 35 and 50)
