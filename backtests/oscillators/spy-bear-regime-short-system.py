import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_long_len = 250
    ma_short_len = 5
    rsi_len = 3
    rsi_thresh = 70.0
    gap_pct = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ma_long = self.I(pta.sma, close, length=self.ma_long_len)
        self.ma_short = self.I(pta.sma, close, length=self.ma_short_len)
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)

    def next(self):
        if len(self.data) < max(self.ma_long_len, self.ma_short_len, self.rsi_len):
            return
        
        close = self.data.Close[-1]
        ma_long_val = self.ma_long[-1]
        ma_short_val = self.ma_short[-1]
        rsi_val = self.rsi[-1]
        
        if ma_long_val is None or ma_short_val is None or rsi_val is None:
            return
        
        below_long_ma = close < ma_long_val
        above_short_ma = close > ma_short_val
        rsi_cross_ob = crossover(self.rsi, self.rsi_thresh)
        gap_ok = close <= ma_long_val * (1 - self.gap_pct / 100)
        
        entry_signal = below_long_ma and above_short_ma and rsi_cross_ob and gap_ok
        
        exit_below_short = close < ma_short_val
        exit_above_long = close > ma_long_val
        exit_signal = exit_below_short or exit_above_long
        
        if entry_signal and not self.position:
            self.sell()
        
        if exit_signal and self.position:
            self.position.close()