import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    baseLen = 12
    atrLen = 43
    adxLen = 16
    multBase = 2.5
    adxFloor = 10.0
    adxCeil = 35.0
    boostMax = 1.50
    boostPow = 0.65
    momLen = 2
    momGate = 0.1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.baseline = self.I(pta.ema, close, length=self.baseLen)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adxLen))
        self.adx = self.I(lambda: adx_result['ADX_16'] if adx_result is not None else pd.Series(20, index=close.index))
        
        self.dir_prev = 1
        self.st_prev = None

    def next(self):
        if len(self.data) < max(self.baseLen, self.atrLen, self.adxLen) + 1:
            return
        
        baseline_val = self.baseline[-1]
        baseline_prev = self.baseline[-2] if len(self.baseline) > 1 else baseline_val
        atr_val = self.atr[-1]
        adx_val = self.adx[-1]
        close_val = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        
        if atr_val is None or atr_val == 0 or np.isnan(atr_val):
            return
        
        denom = self.adxCeil - self.adxFloor
        t_raw = (adx_val - self.adxFloor) / denom if denom != 0 else 0.0
        t = max(min(t_raw, 1.0), 0.0)
        
        scale_raw = 1.0 + (self.boostMax - 1.0) * (t ** self.boostPow)
        scale = max(min(scale_raw, self.boostMax), 1.0)
        
        eff_mult = self.multBase * scale
        
        upperband = baseline_val + eff_mult * atr_val
        lowerband = baseline_val - eff_mult * atr_val
        
        if self.st_prev is None:
            self.st_prev = lowerband
            self.dir_prev = -1
        else:
            if self.dir_prev == -1:
                lowerband = max(lowerband, self.st_prev) if close_prev > self.st_prev else lowerband
            else:
                upperband = min(upperband, self.st_prev) if close_prev < self.st_prev else upperband
        
        mom = baseline_val - baseline_prev
        mom_norm = mom / atr_val if atr_val != 0 else 0.0
        
        if self.dir_prev == -1:
            if close_val > upperband and mom_norm > self.momGate:
                new_dir = 1
            else:
                new_dir = -1
        else:
            if close_val < lowerband and mom_norm < -self.momGate:
                new_dir = -1
            else:
                new_dir = 1
        
        if new_dir == -1:
            st = lowerband
        else:
            st = upperband
        
        bull_flip = self.dir_prev > 0 and new_dir < 0
        bear_flip = self.dir_prev < 0 and new_dir > 0
        
        if bull_flip and not self.position:
            self.buy()
        elif bear_flip and self.position:
            self.sell()
        
        self.dir_prev = new_dir
        self.st_prev = st


