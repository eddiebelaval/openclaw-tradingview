import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    slopeLen = 14
    atrLen = 14
    scoreSmoothLen = 5
    beta = 1.0
    scoreScale = 1.5
    pivotLeft = 5
    pivotRight = 5
    minScoreBull = 20.0
    maxScoreBear = -20.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)

        # ATR and RSI std dev
        atr_result = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.atr = atr_result if atr_result is not None else self.I(lambda: pd.Series(1.0, index=close.index))

        rsi_std_result = self.I(lambda: close.rolling(self.slopeLen).std())
        self.rsi_std = rsi_std_result if rsi_std_result is not None else self.I(lambda: pd.Series(0.0001, index=close.index))

        # Linear regression for price and RSI slopes
        self.price_slope_now = self.I(lambda: self._linreg(close, self.slopeLen, 0))
        self.price_slope_prev = self.I(lambda: self._linreg(close, self.slopeLen, 1))
        self.rsi_slope_now = self.I(lambda: self._linreg(self.rsi, self.slopeLen, 0))
        self.rsi_slope_prev = self.I(lambda: self._linreg(self.rsi, self.slopeLen, 1))

        # Normalized slopes and score
        self.price_slope_norm = self.I(lambda: self._safe_divide(
            self.price_slope_now - self.price_slope_prev,
            np.maximum(self.atr, 1e-10)
        ))
        self.rsi_slope_norm = self.I(lambda: self._safe_divide(
            self.rsi_slope_now - self.rsi_slope_prev,
            np.maximum(self.rsi_std, 0.0001)
        ))
        self.raw_score = self.I(lambda: self.rsi_slope_norm - self.beta * self.price_slope_norm)
        self.score = self.I(lambda: 100.0 * self._tanh(self.raw_score / self.scoreScale))
        self.score_smoothed = self.I(pta.ema, pd.Series(self.score), length=self.scoreSmoothLen)

        # Pivot detection
        self.rsi_pivot_low = self.I(lambda: self._pivot_low(self.rsi, self.pivotLeft, self.pivotRight))
        self.rsi_pivot_high = self.I(lambda: self._pivot_high(self.rsi, self.pivotLeft, self.pivotRight))

        # State for divergence tracking
        self.prev_price_low = None
        self.prev_rsi_low = None
        self.prev_score_low = None
        self.prev_price_high = None
        self.prev_rsi_high = None
        self.prev_score_high = None
        self.bull_signal_triggered = False
        self.bear_signal_triggered = False

    def _linreg(self, series, length, offset):
        """Linear regression with offset"""
        if len(series) < length:
            return pd.Series(np.nan, index=series.index)
        result = pd.Series(np.nan, index=series.index)
        for i in range(length - 1, len(series)):
            data = series.iloc[i - length + 1:i + 1].values
            x = np.arange(len(data))
            coeffs = np.polyfit(x, data, 1)
            result.iloc[i] = coeffs[0] * (len(data) - 1 - offset) + coeffs[1]
        return result

    def _safe_divide(self, numerator, denominator):
        """Safe division with fallback"""
        return pd.Series(np.divide(numerator, denominator, where=denominator != 0, out=np.zeros_like(numerator)))

    def _tanh(self, x):
        """Hyperbolic tangent function"""
        ex = np.exp(np.minimum(x, 100))
        enx = np.exp(-np.minimum(x, 100))
        return (ex - enx) / (ex + enx)

    def _pivot_low(self, series, left, right):
        """Detect pivot lows"""
        result = pd.Series(np.nan, index=series.index)
        for i in range(left, len(series) - right):
            if series.iloc[i] == series.iloc[i - left:i + right + 1].min():
                result.iloc[i] = series.iloc[i]
        return result

    def _pivot_high(self, series, left, right):
        """Detect pivot highs"""
        result = pd.Series(np.nan, index=series.index)
        for i in range(left, len(series) - right):
            if series.iloc[i] == series.iloc[i - left:i + right + 1].max():
                result.iloc[i] = series.iloc[i]
        return result

    def next(self):
        idx = len(self.data) - 1

        # Check for pivot low (bullish divergence)
        if not np.isnan(self.rsi_pivot_low[-1]):
            price_at_pivot = self.data.Low[-self.pivotRight - 1] if self.pivotRight + 1 <= len(self.data) else self.data.Low[-1]
            rsi_at_pivot = self.rsi[-self.pivotRight - 1] if self.pivotRight + 1 <= len(self.data) else self.rsi[-1]
            score_at_pivot = self.score_smoothed[-self.pivotRight - 1] if self.pivotRight + 1 <= len(self.data) else self.score_smoothed[-1]

            if self.prev_price_low is not None:
                bull_classical = price_at_pivot < self.prev_price_low and rsi_at_pivot > self.prev_rsi_low
                bull_score_ok = score_at_pivot >= self.minScoreBull
                if bull_classical and bull_score_ok and not self.bull_signal_triggered:
                    self.buy()
                    self.bull_signal_triggered = True
                elif not (bull_classical and bull_score_ok):
                    self.bull_signal_triggered = False

            self.prev_price_low = price_at_pivot
            self.prev_rsi_low = rsi_at_pivot
            self.prev_score_low = score_at_pivot

        # Check for pivot high (bearish divergence)
        if not np.isnan(self.rsi_pivot_high[-1]):
            price_at_pivot = self.data.High[-self.pivotRight - 1] if self.pivotRight + 1 <= len(self.data) else self.data.High[-1]
            rsi_at_pivot = self.rsi[-self.pivotRight - 1] if self.pivotRight + 1 <= len(self.data) else self.rsi[-1]
            score_at_pivot = self.score_smoothed[-self.pivotRight - 1] if self.pivotRight + 1 <= len(self.data) else self.score_smoothed[-1]

            if self.prev_price_high is not None:
                bear_classical = price_at_pivot > self.prev_price_high and rsi_at_pivot < self.prev_rsi_high
                bear_score_ok = score_at_pivot <= self.maxScoreBear
                if bear_classical and bear_score_ok and not self.bear_signal_triggered:
                    self.sell()
                    self.bear_signal_triggered = True
                elif not (bear_classical and bear_score_ok):
                    self.bear_signal_triggered = False

            self.prev_price_high = price_at_pivot
            self.prev_rsi_high = rsi_at_pivot
            self.prev_score_high = score_at_pivot


