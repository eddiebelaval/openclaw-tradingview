import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Pivot Settings
    leftBars = 5
    rightBars = 5
    
    # Divergence Type Selection
    showRegularBull = True
    showRegularBear = True
    showHiddenBull = True
    showHiddenBear = True
    
    # Lookback Settings
    maxLookback = 60
    minLookback = 5

    def init(self):
        self.priceHighs = []
        self.priceHighBars = []
        self.indicatorHighs = []
        
        self.priceLows = []
        self.priceLowBars = []
        self.indicatorLows = []
        
        self.MAX_ARRAY_SIZE = 100
        
        self.last_signal_bar = -999
        
    def detect_pivot_high(self, idx):
        if idx < self.leftBars + self.rightBars:
            return False, 0.0, 0.0
        
        left_start = idx - self.leftBars
        right_end = idx + self.rightBars
        
        if right_end >= len(self.data.High):
            return False, 0.0, 0.0
        
        pivot_bar = idx
        pivot_high = self.data.High[pivot_bar]
        pivot_indicator = self.data.Close[pivot_bar]
        
        for i in range(left_start, pivot_bar):
            if self.data.High[i] >= pivot_high:
                return False, 0.0, 0.0
        
        for i in range(pivot_bar + 1, right_end + 1):
            if self.data.High[i] >= pivot_high:
                return False, 0.0, 0.0
        
        return True, pivot_high, pivot_indicator
    
    def detect_pivot_low(self, idx):
        if idx < self.leftBars + self.rightBars:
            return False, 0.0, 0.0
        
        left_start = idx - self.leftBars
        right_end = idx + self.rightBars
        
        if right_end >= len(self.data.Low):
            return False, 0.0, 0.0
        
        pivot_bar = idx
        pivot_low = self.data.Low[pivot_bar]
        pivot_indicator = self.data.Close[pivot_bar]
        
        for i in range(left_start, pivot_bar):
            if self.data.Low[i] <= pivot_low:
                return False, 0.0, 0.0
        
        for i in range(pivot_bar + 1, right_end + 1):
            if self.data.Low[i] <= pivot_low:
                return False, 0.0, 0.0
        
        return True, pivot_low, pivot_indicator
    
    def detect_regular_bullish(self):
        if len(self.priceLows) < 2:
            return False
        
        current_low_price = self.priceLows[0]
        current_low_bar = self.priceLowBars[0]
        current_low_ind = self.indicatorLows[0]
        
        for i in range(1, min(len(self.priceLows), self.maxLookback + 1)):
            prev_low_price = self.priceLows[i]
            prev_low_bar = self.priceLowBars[i]
            prev_low_ind = self.indicatorLows[i]
            
            bar_diff = current_low_bar - prev_low_bar
            
            if self.minLookback <= bar_diff <= self.maxLookback:
                if current_low_price < prev_low_price and current_low_ind > prev_low_ind:
                    return True
        
        return False
    
