    def next(self):
        current_idx = len(self.data) - 1
        
        # Check for pivot high at the confirmed position (rightBars back)
        if current_idx >= self.rightBars:
            confirm_idx = current_idx - self.rightBars
            pivot_high_found, pivot_high_val, pivot_high_ind = self.detect_pivot_high(confirm_idx)
            
            if pivot_high_found:
                bar_idx = confirm_idx
