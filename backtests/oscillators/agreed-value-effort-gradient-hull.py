import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vol_length = 50
    vol_z_threshold = 2.5
    anchor_cooldown = 5
    effort_smooth = 3
    show_zscore = True
    z_len = 50
    signal_len = 9
    color_smooth = 1
    show_sd_bands = True
    sd_mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # OHLC4 source
        ohlc4 = (open_ + high + low + close) / 4
        
        # Volume Z-Score
        vol_sma = self.I(pta.sma, volume, length=self.vol_length)
        vol_sd = self.I(pta.stdev, volume, length=self.vol_length)
        
        def calc_vol_z():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if vol_sd.iloc[i] > 0:
                    result.iloc[i] = (volume.iloc[i] - vol_sma.iloc[i]) / vol_sd.iloc[i]
                else:
                    result.iloc[i] = 0
            return result
        
        self.vol_z = self.I(calc_vol_z)
        
        # HAV and Derivative calculation
        def calc_hav_derivative():
            anchors = []
            active_states = []
            bars_since_anchor = self.anchor_cooldown
            
            result_hav = pd.Series(index=close.index, dtype=float)
            result_d_dx = pd.Series(index=close.index, dtype=float)
            
            for bar_idx in range(len(close)):
                bars_since_anchor += 1
                
                is_anomaly = (self.vol_z.iloc[bar_idx] >= self.vol_z_threshold and 
                             bars_since_anchor >= self.anchor_cooldown)
                
                if is_anomaly:
                    bars_since_anchor = 0
                    anchors.insert(0, bar_idx)
                    active_states.insert(0, True)
                    
                    if len(anchors) > 24:
                        anchors.pop()
                        active_states.pop()
                
                active_hmas = []
                
                for rank in range(1, min(25, len(anchors) + 1)):
                    anchor = anchors[rank - 1] if rank - 1 < len(anchors) else -1
                    active = active_states[rank - 1] if rank - 1 < len(active_states) else False
                    
                    count = (bar_idx - anchor + 1) if (active and anchor != -1) else 0
                    
                    if count >= 2 and active:
                        length = max(2, count)
                        half_len = max(1, int(np.floor(length / 2)))
                        sqrt_len = max(1, int(np.floor(np.sqrt(length))))
                        
                        start_idx = max(0, bar_idx - length + 1)
                        subset = ohlc4.iloc[start_idx:bar_idx + 1]
                        
                        if len(subset) >= half_len:
                            half_wma_val = subset.ewm(span=half_len, adjust=False).mean().iloc[-1]
                            full_wma_val = subset.ewm(span=length, adjust=False).mean().iloc[-1]
                            
                            raw_hma_input = 2 * half_wma_val - full_wma_val
                            
                            if np.isfinite(raw_hma_val := raw_hma_input):
                                active_hmas.append(raw_hma_val)
                
                if active_hmas:
                    hav = np.mean(active_hmas)
                    result_hav.iloc[bar_idx] = hav
                    
                    if bar_idx > 0 and np.isfinite(result_hav.iloc[bar_idx - 1]):
                        raw_d_dx = hav - result_hav.iloc[bar_idx - 1]
                    else:
                        raw_d_dx = 0
                    
                    result_d_dx.iloc[bar_idx] = raw_d_dx
                else:
                    result_hav.iloc[bar_idx] = np.nan
                    result_d_dx.iloc[bar_idx] = np.nan
            
            return result_hav, result_d_dx
        
        # Calculate HAV and raw derivative
        def hav_func():
            hav, _ = calc_hav_derivative()
            return hav
        
        def d_dx_func():
            _, d_dx = calc_hav_derivative()
            return d_dx
        
        hav = self.I(hav_func)
        raw_d_dx = self.I(d_dx_func)
        
        # Smoothed derivative
        d_dx = self.I(pta.wma, raw_d_dx.fillna(method='bfill'), length=self.effort_smooth)
        
        # Z-Score standardization
        d_dx_sma = self.I(pta.sma, d_dx, length=self.z_len)
        d_dx_sd = self.I(pta.stdev, d_dx, length=self.z_len)
        
        def calc_osc_val():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if d_dx_sd.iloc[i] > 0:
                    result.iloc[i] = (d_dx.iloc[i] - d_dx_sma.iloc[i]) / d_dx_sd.iloc[i]
                else:
                    result.iloc[i] = 0
            return result
        
        osc_val = self.I(calc_osc_val)
        
        # Signal line
        signal = self.I(pta.sma, osc_val, length=self.signal_len)
        
        # Volatility bands
        osc_baseline = self.I(pta.sma, osc_val, length=self.z_len)
        osc_stdev_bands = self.I(pta.stdev, osc_val, length=self.z_len)
        
        def calc_upper_band():
            return osc_baseline + (osc_stdev_bands * self.sd_mult)
        
        def calc_lower_band():
            return osc_baseline - (osc_stdev_bands * self.sd_mult)
        
        upper_band = self.I(calc_upper_band)
        lower_band = self.I(calc_lower_band)
        
        self.osc_val = osc_val
        self.signal = signal
        self.upper_band = upper_band
        self.lower_band = lower_band
        self.vol_z = self.vol_z

    def next(self):
        if len(self.data) < 2:
            return
        
        # Exhaustion signals
        exhaustion_peak = (crossover(self.signal, self.osc_val) and 
                          self.osc_val[-1] > self.upper_band[-1])
        exhaustion_trough = (crossover(self.osc_val, self.signal) and 
                            self.osc_val[-1] < self.lower_band[-1])
        
        # Simple trading logic based on exhaustion signals
        if exhaustion_trough and not self.position:
            self.buy()
        elif exhaustion_peak and self.position:
            self.sell()