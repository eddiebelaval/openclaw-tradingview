import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    smoothLen = 9
    maLen = 14
    maType = "RMA"
    maFlatThr = 0.05

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI
        rsi_raw = self.I(pta.rsi, close, length=self.rsiLen)
        
        # Calculate smoothed RSI (RMA)
        def calc_rma_smooth(src):
            rsi_values = pta.rsi(src, length=self.rsiLen)
            if rsi_values is None:
                return pd.Series(50, index=src.index)
            rma_values = pta.rma(rsi_values, length=self.smoothLen)
            return rma_values if rma_values is not None else pd.Series(50, index=src.index)
        
        self.rsi_smooth = self.I(calc_rma_smooth, close)
        
        # Calculate RSI MA
        def calc_rsi_ma(src):
            rsi_values = pta.rsi(src, length=self.rsiLen)
            if rsi_values is None:
                return pd.Series(50, index=src.index)
            rma_values = pta.rma(rsi_values, length=self.smoothLen)
            if rma_values is None:
                return pd.Series(50, index=src.index)
            
            if self.maType == "RMA":
                ma = pta.rma(rma_values, length=self.maLen)
            elif self.maType == "EMA":
                ma = pta.ema(rma_values, length=self.maLen)
            elif self.maType == "SMA":
                ma = pta.sma(rma_values, length=self.maLen)
            elif self.maType == "WMA":
                ma = pta.wma(rma_values, length=self.maLen)
            else:
                ma = pta.rma(rma_values, length=self.maLen)
            
            return ma if ma is not None else pd.Series(50, index=src.index)
        
        self.rsi_ma = self.I(calc_rsi_ma, close)

    def next(self):
        # Simple trading logic based on RSI smoothed and MA
        if len(self.data) < 2:
            return
        
        rsi_current = self.rsi_smooth[-1]
        rsi_prev = self.rsi_smooth[-2]
        
        ma_current = self.rsi_ma[-1]
        ma_prev = self.rsi_ma[-2]
        
        # Avoid NaN values
        if np.isnan(rsi_current) or np.isnan(ma_current):
            return
        
        # Calculate MA slope
        ma_delta = ma_current - ma_prev
        
        # Buy signal: RSI crosses above 50 and MA is in uptrend
        if crossover(self.rsi_smooth, 50) and ma_delta > self.maFlatThr:
            if not self.position:
                self.buy()
        
        # Sell signal: RSI crosses below 50 or MA turns down
        elif crossover(50, self.rsi_smooth) or (self.position and ma_delta < -self.maFlatThr):
            if self.position:
                self.sell()
        
        # Exit on RSI overbought (>70) after position is profitable
        elif self.position and rsi_current > 70:
            if self.position.pl > 0:
                self.sell()
        
