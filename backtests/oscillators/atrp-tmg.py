import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLength = 14
    maType = "RMA"
    highThreshold = 3.0
    lowThreshold = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate True Range
        def calc_tr():
            tr = pta.tr(high=high, low=low, close=close, talib=False)
            return tr if tr is not None else pd.Series(0, index=close.index)
        
        tr = self.I(calc_tr)
        
        # Calculate ATR based on ma type
        def calc_atr():
            tr_series = pta.tr(high=high, low=low, close=close, talib=False)
            if tr_series is None:
                tr_series = pd.Series(0, index=close.index)
            
            if self.maType == "RMA":
                atr = pta.rma(tr_series, length=self.atrLength)
            elif self.maType == "SMA":
                atr = pta.sma(tr_series, length=self.atrLength)
            elif self.maType == "EMA":
                atr = pta.ema(tr_series, length=self.atrLength)
            else:
                atr = pta.rma(tr_series, length=self.atrLength)
            
            return atr if atr is not None else pd.Series(0, index=close.index)
        
        atr = self.I(calc_atr)
        
        # Calculate ATRP (ATR / Close * 100)
        def calc_atrp():
            tr_series = pta.tr(high=high, low=low, close=close, talib=False)
            if tr_series is None:
                tr_series = pd.Series(0, index=close.index)
            
            if self.maType == "RMA":
                atr_val = pta.rma(tr_series, length=self.atrLength)
            elif self.maType == "SMA":
                atr_val = pta.sma(tr_series, length=self.atrLength)
            elif self.maType == "EMA":
                atr_val = pta.ema(tr_series, length=self.atrLength)
            else:
                atr_val = pta.rma(tr_series, length=self.atrLength)
            
            if atr_val is None:
                atr_val = pd.Series(0, index=close.index)
            
            atrp = (atr_val / close) * 100
            return atrp if atrp is not None else pd.Series(0, index=close.index)
        
        self.atrp = self.I(calc_atrp)
        
        self.high_threshold = pd.Series(self.highThreshold, index=close.index)
        self.low_threshold = pd.Series(self.lowThreshold, index=close.index)

    def next(self):
        if len(self.data) < self.atrLength + 1:
            return
        
        current_atrp = self.atrp[-1]
        
        # Buy when ATRP crosses above high threshold (entering high volatility)
        if crossover(self.atrp, self.high_threshold):
            if not self.position:
                self.buy()
        
        # Sell when ATRP crosses below low threshold (entering low volatility)
        elif crossover(self.low_threshold, self.atrp):
            if self.position:
                self.position.close()
        
        # Exit when crossing back below high threshold from high volatility
        elif crossover(self.high_threshold, self.atrp):
            if self.position:
                self.position.close()
        
        # Exit on crossing above low threshold from low volatility
        elif crossover(self.atrp, self.low_threshold):
            if self.position:
                self.position.close()


