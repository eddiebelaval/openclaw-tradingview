import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    startDate = pd.Timestamp("2023-01-01 00:00")
    endDate = pd.Timestamp("2026-12-31 00:00")

    def init(self):
        close = pd.Series(self.data.Close)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)

    def next(self):
        current_time = self.data.index[-1]
        
        in_range = (current_time >= self.startDate and current_time <= self.endDate)
        
        if not in_range:
            return
        
        # Buy signal: RSI crosses under 50
        if len(self.rsi) >= 2:
            if self.rsi[-2] >= 50 and self.rsi[-1] < 50:
                if not self.position:
                    self.buy()
        
        # Sell signal: RSI crosses over 70
        if len(self.rsi) >= 2:
            if self.rsi[-2] <= 70 and self.rsi[-1] > 70:
                if self.position:
                    self.position.close()