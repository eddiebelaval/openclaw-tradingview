import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ceLen = 22
    atrLen = 22
    atrMult = 3.0
    useCloseExtremes = False
    useTrendFilter = True
    emaLen = 20
    useVolFilter = False
    volMaLen = 20
    volMult = 1.2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate highest and lowest
        highestSrc = close if self.useCloseExtremes else high
        lowestSrc = close if self.useCloseExtremes else low

        self.hh = self.I(lambda: highestSrc.rolling(self.ceLen).max())
        self.ll = self.I(lambda: lowestSrc.rolling(self.ceLen).min())
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)

        # EMA trend filter
        self.emaBase = self.I(pta.ema, close, length=self.emaLen)

        # Volume filter
        self.volMA = self.I(pta.sma, volume, length=self.volMaLen)

    def next(self):
        if len(self.data) < self.ceLen + 1:
            return

        # Get current values
        hh = self.hh[-1]
        ll = self.ll[-1]
        atr = self.atr[-1]

        if pd.isna(hh) or pd.isna(ll) or pd.isna(atr):
            return

        # Calculate raw Chandelier values
        longRaw = hh - self.atrMult * atr
        shortRaw = ll + self.atrMult * atr

        # Initialize or update Chandelier Exit levels
        if not hasattr(self, 'longCE_prev'):
            self.longCE_prev = longRaw
            self.shortCE_prev = shortRaw
        else:
            # longCE only moves up, not down
            if self.data.Close[-2] > self.longCE_prev:
                self.longCE_prev = max(longRaw, self.longCE_prev)
            else:
                self.longCE_prev = longRaw

            # shortCE only moves down, not up
            if self.data.Close[-2] < self.shortCE_prev:
                self.shortCE_prev = min(shortRaw, self.shortCE_prev)
            else:
                self.shortCE_prev = shortRaw

        longCE = self.longCE_prev
        shortCE = self.shortCE_prev

        # Filter conditions
        trendLongOk = (not self.useTrendFilter) or (self.data.Close[-1] > self.emaBase[-1])
        trendShortOk = (not self.useTrendFilter) or (self.data.Close[-1] < self.emaBase[-1])

        volMA = self.volMA[-1]
        volLongOk = (not self.useVolFilter) or (self.data.Volume[-1] > volMA * self.volMult)
        volShortOk = (not self.useVolFilter) or (self.data.Volume[-1] > volMA * self.volMult)

        # Detect crossovers
        buySignal = (
            crossover(self.data.Close, shortCE) and
            trendLongOk and
            volLongOk
        )
        sellSignal = (
            crossover(longCE, self.data.Close) and
            trendShortOk and
            volShortOk
        )

        # Trading logic
        if buySignal:
            if not self.position:
                self.buy()
        elif sellSignal:
            if self.position:
                self.position.close()


