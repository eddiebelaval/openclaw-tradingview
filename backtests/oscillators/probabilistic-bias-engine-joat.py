import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Bayesian Parameters
    bayesian_length = 14
    smoothing_period = 2
    
    # Loop Analysis Parameters
    loop_start = 1
    loop_lookback = 70
    
    # MTF Parameters
    enable_mtf = True
    confluence_threshold = 2
    
    # Volatility and RSI parameters
    atr_length = 14
    rsi_length = 14
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Core indicator: HLC3 source
        hlc3 = (high + low + close) / 3
        
        # For-loop analysis: compare current price to historical prices
        def forloop_analysis(src):
            result = pd.Series(index=src.index, dtype=float)
            for idx in range(len(src)):
                if idx < self.loop_lookback:
                    result.iloc[idx] = np.nan
                    continue
                sum_val = 0.0
                for i in range(self.loop_start, min(self.loop_lookback + 1, idx + 1)):
                    sum_val += 1.0 if src.iloc[idx] > src.iloc[idx - i] else -1.0
                normalized = sum_val / (min(self.loop_lookback, idx) - self.loop_start + 1)
                result.iloc[idx] = normalized
            return result
        
        # Bayesian probability calculation
        def bayesian_prob(loop_val):
            evidence = np.where(loop_val > 0, 0.7, 0.3)
            prior = 0.5
            posterior = (prior * evidence) / (prior * evidence + (1 - prior) * (1 - evidence))
            return pd.Series(posterior, index=loop_val.index)
        
        # Calculate loop score
        self.loop_score = self.I(forloop_analysis, hlc3)
        
        # Calculate short-term probability
        self.short_term_prob = self.I(bayesian_prob, self.loop_score)
        
        # Calculate long-term probability (with SMA smoothing)
        sma_loop = self.I(pta.sma, self.loop_score, length=self.bayesian_length)
        self.long_term_prob = self.I(bayesian_prob, sma_loop)
        
        # Combined probability
        def combined_prob(short, long):
            result = (short * 100 + long * 100) / 2
            return result
        
        self.combined_prob = self.I(combined_prob, self.short_term_prob, self.long_term_prob)
        
        # Smoothed probability (EMA)
        self.smoothed_prob = self.I(pta.ema, self.combined_prob, length=self.smoothing_period)
        
        # Calculate probability strength
        def prob_strength(prob):
            return np.abs(prob - 50)
        
        self.prob_strength = self.I(prob_strength, self.smoothed_prob)
        
        # ATR for volatility
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # RSI for divergence detection
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Confidence score based on multiple factors
        def confidence_calc(prob, strength, atr_val, rsi_val, close_val):
            result = pd.Series(index=prob.index, dtype=float)
            
            for idx in range(len(prob)):
                conf = 0.0
                
                # Factor 1: Probability strength (0-40 points)
                if not pd.isna(strength.iloc[idx]):
                    conf += min(strength.iloc[idx] * 0.8, 40)
                
                # Factor 2: Basic divergence simulation (0-20 points)
                if idx > 5:
                    if rsi_val.iloc[idx] > 30 and rsi_val.iloc[idx] < 70:
                        conf += 10
                
                # Factor 3: Regime favorability based on ATR (0-10 points)
                if not pd.isna(atr_val.iloc[idx]) and close_val.iloc[idx] > 0:
                    natr = (atr_val.iloc[idx] / close_val.iloc[idx]) * 100
                    if natr < 2:
                        conf += 10
                    elif natr < 3:
                        conf += 5
                
                result.iloc[idx] = min(conf, 100)
            
            return result
        
        self.confidence = self.I(confidence_calc, self.smoothed_prob, self.prob_strength, 
                                 self.atr, self.rsi, close)
    
    def next(self):
        # Avoid trading if we don't have enough data
        if len(self.data) < self.loop_lookback + 10:
            return
        
        current_prob = self.smoothed_prob[-1]
        current_strength = self.prob_strength[-1]
        current_confidence = self.confidence[-1]
        
        if pd.isna(current_prob) or pd.isna(current_strength) or pd.isna(current_confidence):
            return
        
        # PRIMARY SIGNALS: HIGH CONVICTION
        # Bullish: Probability > 65%, Confidence >= 70%
        bullish_signal = (current_prob > 65) and (current_confidence >= 70)
        
        # Bearish: Probability < 35%, Confidence >= 70%
        bearish_signal = (current_prob < 35) and (current_confidence >= 70)
        
        # SECONDARY SIGNALS: REGIME SHIFT
        # Bullish crossover of 50 with strength
        regime_bull = (len(self.data) > 1 and 
                      self.smoothed_prob[-2] <= 50 and 
                      current_prob > 50 and 
                      current_strength > 10)
        
        # Bearish crossover of 50 with strength
        regime_bear = (len(self.data) > 1 and 
                      self.smoothed_prob[-2] >= 50 and 
                      current_prob < 50 and 
                      current_strength > 10)
        
        # Entry logic
        if not self.position:
            if bullish_signal or regime_bull:
                self.buy()
            elif bearish_signal or regime_bear:
                self.sell()
        else:
            # Exit logic - opposite signals
            if self.position.is_long:
                if bearish_signal or regime_bear or current_prob < 45:
                    self.position.close()
            elif self.position.is_short:
                if bullish_signal or regime_bull or current_prob > 55:
                    self.position.close()