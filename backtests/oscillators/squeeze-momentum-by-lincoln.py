import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate SMA (middle line)
        self.ma = self.I(pta.sma, close, length=self.length)
        
        # Calculate standard deviation for Bollinger Bands
        self.devBB = self.I(lambda: close.rolling(self.length).std())
        
        # Calculate True Range and its SMA for Keltner Channel
        def calc_tr():
            tr1 = high - low
            tr2 = (high - close.shift(1)).abs()
            tr3 = (low - close.shift(1)).abs()
            tr = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
            return tr.rolling(self.length).mean()
        
        self.devKC = self.I(calc_tr)
        
        # Bollinger Bands 2x
        self.upBB = self.I(lambda: self.ma + self.devBB * 2)
        self.lowBB = self.I(lambda: self.ma - self.devBB * 2)
        
        # Keltner Channels
        self.upKCWide = self.I(lambda: self.ma + self.devKC * 2)
        self.lowKCWide = self.I(lambda: self.ma - self.devKC * 2)
        
        self.upKCNormal = self.I(lambda: self.ma + self.devKC * 1.5)
        self.lowKCNormal = self.I(lambda: self.ma - self.devKC * 1.5)
        
        self.upKCNarrow = self.I(lambda: self.ma + self.devKC)
        self.lowKCNarrow = self.I(lambda: self.ma - self.devKC)
        
        # Squeeze conditions
        def calc_sqz_on_wide():
            result = []
            for i in range(len(self.data)):
                if i == 0:
                    result.append(False)
                else:
                    sqz = (self.lowBB[i] >= self.lowKCWide[i]) and (self.upBB[i] <= self.upKCWide[i])
                    result.append(sqz)
            return pd.Series(result, index=close.index)
        
        def calc_sqz_on_normal():
            result = []
            for i in range(len(self.data)):
                if i == 0:
                    result.append(False)
                else:
                    sqz = (self.lowBB[i] >= self.lowKCNormal[i]) and (self.upBB[i] <= self.upKCNormal[i])
                    result.append(sqz)
            return pd.Series(result, index=close.index)
        
        def calc_sqz_on_narrow():
            result = []
            for i in range(len(self.data)):
                if i == 0:
                    result.append(False)
                else:
                    sqz = (self.lowBB[i] >= self.lowKCNarrow[i]) and (self.upBB[i] <= self.upKCNarrow[i])
                    result.append(sqz)
            return pd.Series(result, index=close.index)
        
        def calc_sqz_off_wide():
            result = []
            for i in range(len(self.data)):
                if i == 0:
                    result.append(False)
                else:
                    sqz = (self.lowBB[i] < self.lowKCWide[i]) and (self.upBB[i] > self.upKCWide[i])
                    result.append(sqz)
            return pd.Series(result, index=close.index)
        
        self.sqzOnWide = self.I(calc_sqz_on_wide)
        self.sqzOnNormal = self.I(calc_sqz_on_normal)
        self.sqzOnNarrow = self.I(calc_sqz_on_narrow)
        self.sqzOffWide = self.I(calc_sqz_off_wide)
        
        # Momentum calculation
        def calc_momentum():
            highest_high = high.rolling(self.length).max()
            lowest_low = low.rolling(self.length).min()
            hl_avg = (highest_high + lowest_low) / 2
            sma_close = close.rolling(self.length).mean()
            basis = (hl_avg + sma_close) / 2
            momentum_raw = close - basis
            
            # Linear regression approximation
            momentum = momentum_raw.rolling(self.length).mean()
            return momentum
        
        self.mom = self.I(calc_momentum)
        
        self.in_trade = False

    def next(self):
        if len(self.data) < self.length + 1:
            return
        
        # Momentum direction and strength
        mom_current = self.mom[-1]
        mom_prev = self.mom[-2] if len(self.mom) > 1 else mom_current
        
        # Squeeze status
        sqz_narrow = self.sqzOnNarrow[-1]
        sqz_normal = self.sqzOnNormal[-1]
        sqz_wide = self.sqzOnWide[-1]
        sqz_off = self.sqzOffWide[-1]
        
        # Buy signal: Squeeze release with upward momentum
        if sqz_off and mom_current > 0 and not self.in_trade:
            self.buy()
            self.in_trade = True
        
        # Sell signal: Momentum turns negative
        elif self.in_trade and mom_current < 0:
            self.sell()
            self.in_trade = False
        
        # Exit on extreme squeeze if momentum weakens
        elif self.in_trade and sqz_narrow and mom_current < mom_prev:
            self.sell()
            self.in_trade = False