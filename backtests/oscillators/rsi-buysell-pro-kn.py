import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    rsi_source = "close"
    up_threshold = 70
    dn_threshold = 30
    consec_len = 2

    def init(self):
        close = pd.Series(self.data.Close)
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        self.count_below = 0
        self.count_above = 0

    def next(self):
        if len(self.data) < self.rsi_length + 1:
            return
        
        rsi_current = self.rsi[-1]
        rsi_prev = self.rsi[-2] if len(self.rsi) > 1 else rsi_current
        
        if rsi_current < self.dn_threshold:
            self.count_below += 1
        else:
            self.count_below = 0
        
        if rsi_current > self.up_threshold:
            self.count_above += 1
        else:
            self.count_above = 0
        
        count_below_prev = self.count_below - (1 if rsi_current < self.dn_threshold else 0)
        count_above_prev = self.count_above - (1 if rsi_current > self.up_threshold else 0)
        
        buy_signal = (count_below_prev >= self.consec_len) and crossover(self.rsi, self.dn_threshold)
        sell_signal = (count_above_prev >= self.consec_len) and crossover(self.up_threshold, self.rsi)
        
        if buy_signal:
            if not self.position:
                self.buy()
        
        if sell_signal:
            if self.position:
                self.position.close()