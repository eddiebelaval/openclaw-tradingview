import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI parameters
    len1 = 6
    len2 = 24
    len3 = 24
    len4 = 50
    len5 = 100
    
    # Level parameters
    obLevel = 70
    midLevel = 50
    osLevel = 30

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI indicators
        self.rsi1 = self.I(lambda: pta.rsi(close, length=self.len1) or pd.Series(50, index=close.index))
        self.rsi2 = self.I(lambda: pta.rsi(close, length=self.len2) or pd.Series(50, index=close.index))
        self.rsi3 = self.I(lambda: pta.rsi(close, length=self.len3) or pd.Series(50, index=close.index))
        self.rsi4 = self.I(lambda: pta.rsi(close, length=self.len4) or pd.Series(50, index=close.index))
        self.rsi5 = self.I(lambda: pta.rsi(close, length=self.len5) or pd.Series(50, index=close.index))

    def next(self):
        # Buy signal: RSI1 crosses above oversold level
        if crossover(self.rsi1, self.osLevel):
            if not self.position:
                self.buy()
        
        # Sell signal: RSI1 crosses above overbought level
        elif crossover(self.rsi1, self.obLevel):
            if self.position:
                self.position.close()
        
        # Additional confirmation: RSI2 also in oversold territory for buy
        elif crossover(self.rsi2, self.osLevel):
            if not self.position:
                self.buy()
        
        # Exit on RSI2 overbought
        elif crossover(self.rsi2, self.obLevel):
            if self.position:
                self.position.close()