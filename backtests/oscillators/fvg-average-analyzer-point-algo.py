import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 20
    threshold = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate FVG size
        def calculate_fvg_size():
            result = np.zeros(len(close))
            for i in range(2, len(close)):
                bull_gap = low.iloc[i] - high.iloc[i-2]
                bear_gap = low.iloc[i-2] - high.iloc[i]
                
                if bull_gap > 0:
                    result[i] = bull_gap
                elif bear_gap > 0:
                    result[i] = bear_gap
                else:
                    result[i] = 0.0
            return pd.Series(result, index=close.index)
        
        self.fvg_size = self.I(calculate_fvg_size)
        
        # Calculate average FVG size
        def calculate_avg_fvg():
            fvg = calculate_fvg_size()
            return pta.sma(fvg, length=self.lookback)
        
        self.avg_fvg_size = self.I(calculate_avg_fvg)
        
        # Detect mega gaps
        def calculate_is_mega():
            fvg = calculate_fvg_size()
            avg = pta.sma(fvg, length=self.lookback)
            result = (fvg > (avg * 2)) & (fvg > 0)
            return result.astype(float)
        
        self.is_mega = self.I(calculate_is_mega)

    def next(self):
        if len(self) < self.lookback + 2:
            return
        
        current_fvg = self.fvg_size[-1]
        current_avg = self.avg_fvg_size[-1]
        is_mega_current = self.is_mega[-1] > 0.5
        
        # Buy on mega gap detection (volatile market opportunity)
        if is_mega_current and not self.position:
            self.buy()
        
        # Sell if market becomes efficient (gap size drops below average)
        if self.position and current_fvg < current_avg and current_fvg > 0:
            self.sell()
        
        # Exit if gap disappears
        if self.position and current_fvg <= 0:
            self.sell()


