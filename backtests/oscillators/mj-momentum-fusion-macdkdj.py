import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    shortLen = 12
    longLen = 26
    midLen = 9
    kdjP1 = 9
    kdjP2 = 3
    kdjP3 = 3
    nLookback = 300

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # KDJ Calculation
        lowMin = self.I(lambda: low.rolling(self.kdjP1).min())
        highMax = self.I(lambda: high.rolling(self.kdjP1).max())
        
        rsv = self.I(lambda: 100 * (close - lowMin) / (highMax - lowMin))
        rsv = rsv.fillna(50)
        
        k = self.I(pta.sma, rsv, length=self.kdjP2)
        d = self.I(pta.sma, k, length=self.kdjP3)
        
        j = self.I(lambda: 3 * k - 2 * d)
        
        # MACD Calculation
        ema_short = self.I(pta.ema, close, length=self.shortLen)
        ema_long = self.I(pta.ema, close, length=self.longLen)
        
        dif = self.I(lambda: ema_short - ema_long)
        dea = self.I(pta.ema, dif, length=self.midLen)
        macd = self.I(lambda: (dif - dea) * 2)
        
        # Normalization Engine
        kdj_combined = self.I(lambda: pd.concat([k, d, j], axis=1).max(axis=1))
        kdj_min_combined = self.I(lambda: pd.concat([k, d, j], axis=1).min(axis=1))
        
        kdjMax = self.I(lambda: kdj_combined.rolling(self.nLookback).max())
        kdjMin = self.I(lambda: kdj_min_combined.rolling(self.nLookback).min())
        
        kdj_A2 = self.I(lambda: kdjMax - kdjMin)
        kdj_M2 = self.I(lambda: (kdjMax + kdjMin) / 2)
        
        macd_combined = self.I(lambda: pd.concat([dif, dea, macd], axis=1).max(axis=1))
        macd_min_combined = self.I(lambda: pd.concat([dif, dea, macd], axis=1).min(axis=1))
        
        macdMax = self.I(lambda: macd_combined.rolling(self.nLookback).max())
        macdMin = self.I(lambda: macd_min_combined.rolling(self.nLookback).min())
        
        macd_A1 = self.I(lambda: macdMax - macdMin)
        macd_M1 = self.I(lambda: (macdMax + macdMin) / 2)
        
        new_base = self.I(lambda: (0 - macd_M1) * kdj_A2 / macd_A1 + kdj_M2)
        new_base = new_base.fillna(0)
        
        # Normalized Lines
        self.j_new = self.I(lambda: j - new_base)
        self.macd_new = self.I(lambda: (macd - macd_M1) * kdj_A2 / macd_A1 + kdj_M2 - new_base)
        
        # Store for signal detection
        self.macd_prev = None
        self.j_prev = None
        self.macd_green_bar = None
        self.macd_red_bar = None

    def next(self):
        # Get current values
        j_current = self.j_new[-1] if len(self.j_new) > 0 else 0
        macd_current = self.macd_new[-1] if len(self.macd_new) > 0 else 0
        
        # Get previous values
        j_prev = self.j_new[-2] if len(self.j_new) > 1 else 0
        macd_prev = self.macd_new[-2] if len(self.macd_new) > 1 else 0
        
        # Detect MACD color changes
        if macd_prev <= 0 and macd_current > 0:
            self.macd_green_bar = 0
        elif self.macd_green_bar is not None:
            self.macd_green_bar += 1
            
        if macd_prev >= 0 and macd_current < 0:
            self.macd_red_bar = 0
        elif self.macd_red_bar is not None:
            self.macd_red_bar += 1
        
        # Detect J-Line crossovers
        j_crossover_up = j_prev <= 0 and j_current > 0
        j_crossover_down = j_prev >= 0 and j_current < 0
        
        # Signal conditions
        bullish_signal = (j_crossover_up and 
                         macd_current > 0 and 
                         self.macd_green_bar is not None and 
                         self.macd_green_bar <= 1)
        
        bearish_signal = (j_crossover_down and 
                         macd_current < 0 and 
                         self.macd_red_bar is not None and 
                         self.macd_red_bar <= 1)
        
        # Trading logic
        if bullish_signal and not self.position:
            self.buy()
        elif bearish_signal and self.position:
            self.sell()


