import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sensitivityPeriod = 21
    volatilityMultiplier = 1.5
    fastLength = 13
    slowLength = 34
    signalLength = 8
    chaosThreshold = 0.8
    useTrendFilter = True
    trendPeriod = 89
    stopLossPercent = 3.5
    takeProfitPercent = 7.0
    useTrailingStop = True
    trailingStopPercent = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Rate of Change
        self.roc = self.I(lambda: pta.roc(close, length=self.sensitivityPeriod) or pd.Series(0, index=close.index))
        
        # Acceleration (change in ROC)
        self.acceleration = self.I(lambda: pd.Series(self.roc).diff(1) or pd.Series(0, index=close.index))
        
        # Volatility (ATR)
        self.volatility = self.I(lambda: pta.atr(high, low, close, length=self.sensitivityPeriod) or pd.Series(0, index=close.index))
        
        # Sensitivity Index
        def calc_sensitivity():
            vol = self.volatility
            acc = self.acceleration
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(vol)):
                if vol.iloc[i] > 0:
                    result.iloc[i] = abs(acc.iloc[i]) / vol.iloc[i] * 100
                else:
                    result.iloc[i] = 0
            return result
        
        self.sensitivityIndex = self.I(calc_sensitivity)
        
        # EMA Fast and Slow
        self.ema_fast = self.I(lambda: pta.ema(close, length=self.fastLength) or pd.Series(close.iloc[0], index=close.index))
        self.ema_slow = self.I(lambda: pta.ema(close, length=self.slowLength) or pd.Series(close.iloc[0], index=close.index))
        
        # Chaos Deviation
        def calc_chaos_deviation():
            fast = self.ema_fast
            slow = self.ema_slow
            vol = self.volatility
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(fast)):
                if vol.iloc[i] > 0:
                    result.iloc[i] = (fast.iloc[i] - slow.iloc[i]) / (vol.iloc[i] * self.volatilityMultiplier)
                else:
                    result.iloc[i] = 0
            return result
        
        self.chaosDeviation = self.I(calc_chaos_deviation)
        
        # Signal Line (EMA of Chaos Deviation)
        self.signalLine = self.I(lambda: pta.ema(pd.Series(self.chaosDeviation), length=self.signalLength) or pd.Series(0, index=close.index))
        
        # Highest High and Lowest Low
        def calc_highest_high():
            return high.rolling(window=self.sensitivityPeriod).max()
        
        def calc_lowest_low():
            return low.rolling(window=self.sensitivityPeriod).min()
        
        self.highestHigh = self.I(calc_highest_high)
        self.lowestLow = self.I(calc_lowest_low)
        
        # Price Range and Fractal Complexity
        def calc_fractal():
            hh = self.highestHigh
            ll = self.lowestLow
            vol = self.volatility
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(hh)):
                price_range = hh.iloc[i] - ll.iloc[i]
                if price_range > 0:
                    result.iloc[i] = vol.iloc[i] / price_range
                else:
                    result.iloc[i] = 0
            return result
        
        self.fractalComplexity = self.I(calc_fractal)
        
        # RSI for momentum confirmation
        self.rsi = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        
        # Trend EMA
        self.trendEMA = self.I(lambda: pta.ema(close, length=self.trendPeriod) or pd.Series(close.iloc[0], index=close.index))
        
        # Average Volatility (SMA of ATR)
        self.avgVolatility = self.I(lambda: pta.sma(pd.Series(self.volatility), length=20) or pd.Series(0, index=close.index))

    def next(self):
        close_price = self.data.Close[-1]
        
        # Current values
        chaos_dev = self.chaosDeviation[-1]
        signal_line = self.signalLine[-1]
        rsi = self.rsi[-1]
        trend_ema = self.trendEMA[-1]
        volatility = self.volatility[-1]
        avg_vol = self.avgVolatility[-1]
        
        # Conditions
        uptrend = close_price > trend_ema
        downtrend = close_price < trend_ema
        
        momentumBullish = rsi > 40 and rsi < 70
        momentumBearish = rsi < 60 and rsi > 30
        
        sufficientVolatility = volatility > avg_vol * 0.7
        
        # Entry signals
        bullishSetup = crossover(self.chaosDeviation, self.signalLine) and \
                       chaos_dev > self.chaosThreshold and \
                       momentumBullish and \
                       sufficientVolatility
        
        bullishChaos = (bullishSetup and uptrend) if self.useTrendFilter else bullishSetup
        
        bearishSetup = crossover(self.signalLine, self.chaosDeviation) and \
                       chaos_dev < -self.chaosThreshold and \
                       momentumBearish and \
                       sufficientVolatility
        
        bearishChaos = (bearishSetup and downtrend) if self.useTrendFilter else bearishSetup
        
        # Position management
        if bullishChaos and not self.position:
            self.buy()
        elif bearishChaos and not self.position:
            self.sell()
        
        # Exit conditions
        if self.position.is_long:
            stop_level = self.position.open_price * (1 - self.stopLossPercent / 100)
            profit_level = self.position.open_price * (1 + self.takeProfitPercent / 100)
            
            if close_price <= stop_level or close_price >= profit_level:
                self.position.close()
            elif bearishChaos:
                self.position.close()
        
        elif self.position.is_short:
            stop_level = self.position.open_price * (1 + self.stopLossPercent / 100)
            profit_level = self.position.open_price * (1 - self.takeProfitPercent / 100)
            
            if close_price >= stop_level or close_price <= profit_level:
                self.position.close()
            elif bullishChaos:
                self.position.close()


