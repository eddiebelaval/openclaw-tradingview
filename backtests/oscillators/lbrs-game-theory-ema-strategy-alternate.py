import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFast = 9
    emaSlow = 21
    emaTrend = 50
    atrPeriod = 14
    atrMult = 1.2
    rr = 1.5
    adxLen = 14
    adxThresh = 20
    useADX = True
    maxTradesPerDay = 5
    maxDailyLossPct = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema_fast = self.I(pta.ema, close, length=self.emaFast)
        self.ema_slow = self.I(pta.ema, close, length=self.emaSlow)
        self.ema_trend = self.I(pta.ema, close, length=self.emaTrend)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)
        
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adxLen) or pd.DataFrame(0, index=close.index, columns=['ADX']))
        self.adx = self.I(lambda: adx_result['ADX'] if isinstance(adx_result, pd.DataFrame) and 'ADX' in adx_result.columns else pd.Series(0, index=close.index))
        
        self.rsi = self.I(pta.rsi, close, length=14)
        
        self.trades_today = 0
        self.day_start_equity = self.equity
        self.last_day = None

    def next(self):
        close = self.data.Close[-1]
        
        current_day = pd.Timestamp(self.data.index[-1]).date()
        if self.last_day != current_day:
            self.trades_today = 0
            self.day_start_equity = self.equity
            self.last_day = current_day
        
        ema_fast_val = self.ema_fast[-1]
        ema_slow_val = self.ema_slow[-1]
        ema_trend_val = self.ema_trend[-1]
        atr_val = self.atr[-1]
        adx_val = self.adx[-1]
        rsi_val = self.rsi[-1]
        
        if np.isnan(ema_fast_val) or np.isnan(ema_slow_val) or np.isnan(ema_trend_val) or np.isnan(atr_val) or np.isnan(rsi_val):
            return
        
        utility = (rsi_val - 50) / 50
        buyer_edge = utility > 0.1
        seller_edge = utility < -0.1
        equilibrium = abs(utility) < 0.1
        
        ema_cross_up = crossover(self.ema_fast, self.ema_slow)
        ema_cross_down = crossover(self.ema_slow, self.ema_fast)
        
        uptrend = close > ema_trend_val
        downtrend = close < ema_trend_val
        
        strong_trend = adx_val > self.adxThresh
        
        daily_drawdown = (self.equity - self.day_start_equity) / self.day_start_equity * 100
        daily_allowed = daily_drawdown > -self.maxDailyLossPct
        
        long_cond = (
            ema_cross_up and
            uptrend and
            buyer_edge and
            not equilibrium and
            (not self.useADX or strong_trend) and
            self.trades_today < self.maxTradesPerDay and
            daily_allowed
        )
        
        short_cond = (
            ema_cross_down and
            downtrend and
            seller_edge and
            not equilibrium and
            (not self.useADX or strong_trend) and
            self.trades_today < self.maxTradesPerDay and
            daily_allowed
        )
        
        risk_pct = 2.0
        risk_capital = self.equity * risk_pct / 100
        
        long_stop_dist = atr_val * self.atrMult
        short_stop_dist = atr_val * self.atrMult
        
        if long_stop_dist > 0:
            long_qty = risk_capital / long_stop_dist
        else:
            long_qty = 0
        
        if short_stop_dist > 0:
            short_qty = risk_capital / short_stop_dist
        else:
            short_qty = 0
        
        if long_cond and not self.position:
            self.buy(size=long_qty)
            self.trades_today += 1
        
        if short_cond and not self.position:
            self.sell(size=short_qty)
            self.trades_today += 1
        
        if self.position.size > 0:
            stop_level = self.position.open_price - long_stop_dist
            target_level = self.position.open_price + long_stop_dist * self.rr
            
            if close <= stop_level:
                self.position.close()
            elif close >= target_level:
                self.position.close()
        
        if self.position.size < 0:
            stop_level = self.position.open_price + short_stop_dist
            target_level = self.position.open_price - short_stop_dist * self.rr
            
            if close >= stop_level:
                self.position.close()
            elif close <= target_level:
                self.position.close()


