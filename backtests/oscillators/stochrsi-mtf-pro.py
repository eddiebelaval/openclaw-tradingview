import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_len = 14
    stoch_len = 14
    smooth_k = 3
    smooth_d = 3
    extra_sm = 4
    ob = 80
    os_lv = 20

    def init(self):
        close = pd.Series(self.data.Close)
        
        rsi_v = self.I(pta.rsi, close, length=self.rsi_len)
        
        def stoch_rsi():
            rsi_series = pta.rsi(close, length=self.rsi_len)
            if rsi_series is None:
                return pd.Series(50, index=close.index)
            stoch_result = pta.stoch(rsi_series, rsi_series, rsi_series, k=self.stoch_len)
            if stoch_result is None or stoch_result.empty:
                return pd.Series(50, index=close.index)
            stoch_col = [col for col in stoch_result.columns if 'STOCHk' in col]
            if stoch_col:
                return stoch_result[stoch_col[0]]
            return pd.Series(50, index=close.index)
        
        stoch_v = self.I(stoch_rsi)
        
        k_raw = self.I(pta.sma, stoch_v, length=self.smooth_k)
        d_raw = self.I(pta.sma, k_raw, length=self.smooth_d)
        
        self.k = self.I(pta.ema, k_raw, length=self.extra_sm)
        self.d = self.I(pta.ema, d_raw, length=self.extra_sm)

    def next(self):
        if len(self.data) < 2:
            return
        
        if crossover(self.k, self.d):
            if not self.position:
                self.buy()
        elif crossover(self.d, self.k):
            if self.position:
                self.position.close()
        
        if self.k[-1] > self.ob and not self.position:
            pass
        elif self.k[-1] < self.os_lv and self.position:
            self.position.close()


