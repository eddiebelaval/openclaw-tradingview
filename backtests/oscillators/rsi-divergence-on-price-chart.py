import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 14
    lbR = 34
    lbL = 21
    rangeUpper = 60
    rangeLower = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.rsi = self.I(pta.rsi, close, length=self.len)
        self.ema3 = self.I(pta.ema, close, length=34)
        self.ema4 = self.I(pta.ema, (high + low) / 2, length=89)
        
        self.pivot_low_signal = self.I(self._detect_pivot_low, low)
        self.pivot_high_signal = self.I(self._detect_pivot_high, high)
        
        self.last_pl_bar = -999
        self.last_pl_low = 0
        self.last_pl_rsi = 0
        self.last_ph_bar = -999
        self.last_ph_high = 0
        self.last_ph_rsi = 0

    def _detect_pivot_low(self, low_series):
        result = np.zeros(len(low_series))
        for i in range(self.lbL, len(low_series) - self.lbR):
            is_pivot = True
            current_low = low_series.iloc[i]
            for j in range(i - self.lbL, i):
                if low_series.iloc[j] < current_low:
                    is_pivot = False
                    break
            if is_pivot:
                for j in range(i + 1, i + self.lbR + 1):
                    if low_series.iloc[j] < current_low:
                        is_pivot = False
                        break
            if is_pivot:
                result[i] = 1
        return pd.Series(result, index=low_series.index)

    def _detect_pivot_high(self, high_series):
        result = np.zeros(len(high_series))
        for i in range(self.lbL, len(high_series) - self.lbR):
            is_pivot = True
            current_high = high_series.iloc[i]
            for j in range(i - self.lbL, i):
                if high_series.iloc[j] > current_high:
                    is_pivot = False
                    break
            if is_pivot:
                for j in range(i + 1, i + self.lbR + 1):
                    if high_series.iloc[j] > current_high:
                        is_pivot = False
                        break
            if is_pivot:
                result[i] = 1
        return pd.Series(result, index=high_series.index)

    def next(self):
        low = self.data.Low[-1]
        high = self.data.High[-1]
        rsi = self.rsi[-1]
        current_bar = len(self.data) - 1
        
        if not np.isnan(self.pivot_low_signal[-1]) and self.pivot_low_signal[-1] > 0:
            if self.last_pl_bar > -999:
                bars_apart = current_bar - self.last_pl_bar
                if self.rangeLower <= bars_apart <= self.rangeUpper:
                    if low < self.last_pl_low and rsi > self.last_pl_rsi:
                        if not self.position:
                            self.buy()
            
            self.last_pl_bar = current_bar
            self.last_pl_low = low
            self.last_pl_rsi = rsi
        
        if not np.isnan(self.pivot_high_signal[-1]) and self.pivot_high_signal[-1] > 0:
            if self.last_ph_bar > -999:
                bars_apart = current_bar - self.last_ph_bar
                if self.rangeLower <= bars_apart <= self.rangeUpper:
                    if high > self.last_ph_high and rsi < self.last_ph_rsi:
                        if self.position:
                            self.sell()
            
            self.last_ph_bar = current_bar
            self.last_ph_high = high
            self.last_ph_rsi = rsi


