import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    slow_len = 10
    fast_len = 3
    decay_rate = 0.7
    mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        def calculate_cd():
            cd_values = []
            
            pool_bull = 0.0
            pool_bear = 0.0
            pool_path = 0.0
            adapt_len = self.slow_len
            rma_bull = 0.0
            rma_bear = 0.0
            rma_path = 0.0
            
            for i in range(len(close)):
                body_abs = abs(close.iloc[i] - open_.iloc[i])
                upper_wick = high.iloc[i] - max(open_.iloc[i], close.iloc[i])
                lower_wick = min(open_.iloc[i], close.iloc[i]) - low.iloc[i]
                
                prev_close_val = close.iloc[i-1] if i > 0 else open_.iloc[i]
                gap_up = max(0, open_.iloc[i] - prev_close_val)
                gap_down = max(0, prev_close_val - open_.iloc[i])
                abs_gap = gap_up + gap_down
                
                total_path = upper_wick + lower_wick + body_abs + abs_gap
                total_path = total_path if total_path != 0 else 0.00001
                
                bull_body = body_abs if close.iloc[i] > open_.iloc[i] else 0
                bear_body = body_abs if close.iloc[i] < open_.iloc[i] else 0
                
                bull_force = bull_body + lower_wick + gap_up
                bear_force = bear_body + upper_wick + gap_down
                
                pool_bull = bull_force + pool_bull * self.decay_rate
                pool_bear = bear_force + pool_bear * self.decay_rate
                pool_path = total_path + pool_path * self.decay_rate
                
                avg_path_val = close.iloc[max(0, i-self.slow_len+1):i+1].rolling(min(i+1, self.slow_len)).apply(
                    lambda x: abs(x.iloc[-1] - (open_.iloc[max(0, len(x)-1)] if len(x) > 0 else x.iloc[-1])) + 
                    high.iloc[max(0, i-len(x)+1):i+1].max() - max(open_.iloc[i], close.iloc[i]) +
                    min(open_.iloc[i], close.iloc[i]) - low.iloc[max(0, i-len(x)+1):i+1].min()
                ).mean() if i >= self.slow_len else total_path
                
                if i == 0:
                    avg_path_val = total_path
                else:
                    path_vals = []
                    for j in range(max(0, i - self.slow_len + 1), i + 1):
                        body = abs(close.iloc[j] - open_.iloc[j])
                        uw = high.iloc[j] - max(open_.iloc[j], close.iloc[j])
                        lw = min(open_.iloc[j], close.iloc[j]) - low.iloc[j]
                        pg = max(0, open_.iloc[j] - (close.iloc[j-1] if j > 0 else open_.iloc[j]))
                        pd = max(0, (close.iloc[j-1] if j > 0 else open_.iloc[j]) - open_.iloc[j])
                        path_vals.append(body + uw + lw + pg + pd)
                    avg_path_val = np.mean(path_vals) if path_vals else 0.00001
                
                avg_path_val = avg_path_val if avg_path_val != 0 else 0.00001
                decay_mult = 1.0 / (1.0 - self.decay_rate)
                is_active = pool_path > (avg_path_val * decay_mult * 0.7)
                
                bull_impulse = (pool_bull > (pool_bear * 1.5)) and is_active
                bear_impulse = (pool_bear > (pool_bull * 1.5)) and is_active
                
                if bull_impulse or bear_impulse:
                    adapt_len = self.fast_len
                else:
                    adapt_len = min(self.slow_len, adapt_len + 1)
                
                if i == 0:
                    rma_bull = bull_force
                    rma_bear = bear_force
                    rma_path = total_path
                else:
                    rma_bull = (bull_force + rma_bull * (adapt_len - 1.0)) / adapt_len
                    rma_bear = (bear_force + rma_bear * (adapt_len - 1.0)) / adapt_len
                    rma_path = (total_path + rma_path * (adapt_len - 1.0)) / adapt_len
                
                rma_path = rma_path if rma_path > 0 else 0.00001
                
                smoothed_cd_plus = (rma_bull / rma_path) * 100
                smoothed_cd_minus = (rma_bear / rma_path) * 100
                raw_cd_net = smoothed_cd_plus - smoothed_cd_minus
                
                cd_values.append(raw_cd_net)
            
            cd_series = pd.Series(cd_values)
            return cd_series

        def apply_tema(src_series):
            ema1 = pta.ema(src_series, length=5)
            if ema1 is None:
                return pd.Series(0, index=src_series.index)
            ema2 = pta.ema(ema1, length=5)
            if ema2 is None:
                return pd.Series(0, index=src_series.index)
            ema3 = pta.ema(ema2, length=5)
            if ema3 is None:
                return pd.Series(0, index=src_series.index)
            return 3 * (ema1 - ema2) + ema3

        self.cd_net = self.I(calculate_cd)
        self.smoothed_cd = self.I(lambda: apply_tema(self.cd_net))
        self.stdev_net = self.I(lambda: pd.Series(self.cd_net).rolling(self.slow_len).std().fillna(0))
        self.upper_band = self.I(lambda: self.stdev_net * self.mult)
        self.lower_band = self.I(lambda: -self.stdev_net * self.mult)

    def next(self):
        if len(self.data) < 2:
            return

        current_cd = self.smoothed_cd[-1]
        prev_cd = self.smoothed_cd[-2] if len(self.smoothed_cd) > 1 else current_cd
        
        upper = self.upper_band[-1]
        lower = self.lower_band[-1]

        if crossover(self.smoothed_cd, self.lower_band):
            if not self.position:
                self.buy()
        elif crossover(self.upper_band, self.smoothed_cd):
            if self.position:
                self.position.close()

        if current_cd < lower and prev_cd >= lower:
            if not self.position:
                self.buy()
        elif current_cd > upper and prev_cd <= upper:
            if self.position:
                self.position.close()