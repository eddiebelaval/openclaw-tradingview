import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 14
    smoothLen = 5
    confirmBars = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # Core calculations
        self.avgRange = self.I(lambda: pta.sma(high - low, length=self.len))
        self.avgBody = self.I(lambda: pta.sma(np.abs(close - open_), length=self.len))
        self.direction = self.I(lambda: pta.ema(close.diff(1), length=self.smoothLen))
        self.momentumSlope = self.I(lambda: pta.ema(close.diff(2), length=self.smoothLen))
        
        # State tracking
        self.state_count = 0
        self.stable_story = "Market is transitioning"
        self.bull_signal_active = False
        self.bear_signal_active = False

    def next(self):
        if len(self.data) < max(self.len, self.smoothLen) + 2:
            return
        
        # Get current values
        avg_range = self.avgRange[-1] if self.avgRange[-1] is not None else 1e-6
        avg_body = self.avgBody[-1] if self.avgBody[-1] is not None else 0
        direction = self.direction[-1] if self.direction[-1] is not None else 0
        
        # Avoid division by zero
        avg_range = max(avg_range, 1e-6)
        
        # Calculate strength metrics
        strength = avg_body / avg_range
        direction_strength = abs(direction) / avg_range
        
        # Determine market conditions
        bull_control = direction > 0 and strength > 0.55
        bear_control = direction < 0 and strength > 0.55
        weak_move = strength < 0.35
        choppy = abs(direction) < 1e-6 * 2
        
        # Determine current story
        if bull_control:
            current_story = "Buyers are in control"
        elif bear_control:
            current_story = "Sellers are in control"
        elif weak_move:
            current_story = "Market is weak and uncertain"
        elif choppy:
            current_story = "Market is sideways / indecisive"
        else:
            current_story = "Market is transitioning"
        
        # Update state count for confirmation
        if current_story == self.stable_story:
            self.state_count += 1
        else:
            self.state_count = 1
        
        # Update stable story after confirmation bars
        if self.state_count >= self.confirmBars:
            self.stable_story = current_story
        
        # Determine no trade zone
        is_no_trade_zone = (
            (self.stable_story == "Market is transitioning" or 
             self.stable_story == "Market is sideways / indecisive") 
            and self.state_count >= self.confirmBars
        )
        
        # Trading logic based on market story
        if is_no_trade_zone:
            # Close any open positions in no trade zone
            if self.position:
                self.position.close()
        else:
            if self.stable_story == "Buyers are in control":
                # Buy signal: entering bullish trend
                if not self.bull_signal_active and not self.position:
                    self.buy()
                    self.bull_signal_active = True
                    self.bear_signal_active = False
                # Exit if story changes to bearish
                elif self.stable_story != "Buyers are in control" and self.position:
                    self.position.close()
                    self.bull_signal_active = False
                    
            elif self.stable_story == "Sellers are in control":
                # Sell signal: entering bearish trend
                if not self.bear_signal_active and self.position:
                    self.position.close()
                    self.bear_signal_active = True
                    self.bull_signal_active = False
                # Exit longs if story changes to bearish
                elif self.position and self.position.is_long:
                    self.position.close()
                    self.bear_signal_active = True
                    self.bull_signal_active = False
                    
            elif self.stable_story == "Market is weak and uncertain":
                # Close positions on weak moves
                if self.position:
                    self.position.close()
                self.bull_signal_active = False
                self.bear_signal_active = False
            
            elif self.stable_story == "Market is transitioning":
                # Hold existing positions but don't enter new ones
                pass


