import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 20
    bbMult = 2.0
    kcMult = 1.5
    normLookbk = 200
    smoothLen = 5
    lowZone = 20.0
    highZone = 80.0
    momScaleMode = "Auto"
    momScale = 1.0
    momAutoLookbk = 200
    exhLookback = 40
    nearPeakPct = 0.98
    fallBars = 3
    ratioLookback = 252

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # BB and KC calculation
        def calc_basis():
            return pta.sma(close, length=self.len)

        def calc_bb_dev():
            sma = pta.sma(close, length=self.len)
            stdev = close.rolling(window=self.len).std()
            return self.bbMult * stdev

        def calc_atr():
            return pta.atr(high, low, close, length=self.len)

        self.basis = self.I(calc_basis)
        self.bb_dev = self.I(calc_bb_dev)
        self.atr = self.I(calc_atr)

        def calc_bb_u():
            return self.basis + self.bb_dev

        def calc_bb_l():
            return self.basis - self.bb_dev

        def calc_kc_u():
            return self.basis + self.kcMult * self.atr

        def calc_kc_l():
            return self.basis - self.kcMult * self.atr

        self.bbU = self.I(calc_bb_u)
        self.bbL = self.I(calc_bb_l)
        self.kcU = self.I(calc_kc_u)
        self.kcL = self.I(calc_kc_l)

        # Squeeze detection
        def calc_squeeze_on():
            result = np.zeros(len(close))
            for i in range(len(close)):
                if i < len(self.bbU) and i < len(self.kcU):
                    result[i] = 1.0 if (self.bbU[i] < self.kcU[i] and self.bbL[i] > self.kcL[i]) else 0.0
            return pd.Series(result, index=close.index)

        def calc_squeeze_off():
            result = np.zeros(len(close))
            for i in range(len(close)):
                if i < len(self.bbU) and i < len(self.kcU):
                    result[i] = 1.0 if (self.bbU[i] > self.kcU[i] and self.bbL[i] < self.kcL[i]) else 0.0
            return pd.Series(result, index=close.index)

        self.squeezeOn = self.I(calc_squeeze_on)
        self.squeezeOff = self.I(calc_squeeze_off)

        # Volatility line calculation
        def calc_bb_width_pct():
            result = np.zeros(len(close))
            for i in range(len(close)):
                if i < len(self.basis) and self.basis[i] != 0:
                    result[i] = ((self.bbU[i] - self.bbL[i]) / self.basis[i]) * 100.0
                else:
                    result[i] = np.nan
            return pd.Series(result, index=close.index)

        self.bbWidthPct = self.I(calc_bb_width_pct)

        def calc_normalized_width():
            minW = self.bbWidthPct.rolling(window=self.normLookbk).min()
            maxW = self.bbWidthPct.rolling(window=self.normLookbk).max()
            rangeW = maxW - minW
            result = np.zeros(len(close))
            for i in range(len(close)):
                if rangeW[i] != 0 and not np.isnan(self.bbWidthPct[i]):
                    w01_raw = (self.bbWidthPct[i] - minW[i]) / rangeW[i]
                    result[i] = max(0.0, min(1.0, w01_raw))
                else:
                    result[i] = 0.0
            return pd.Series(result, index=close.index)

        self.w01 = self.I(calc_normalized_width)

        def calc_osc_raw():
            result = np.zeros(len(close))
            for i in range(len(close)):
                if i < len(self.squeezeOn) and i < len(self.w01):
                    if self.squeezeOn[i] > 0.5:
                        result[i] = self.w01[i] * self.lowZone
                    else:
                        result[i] = self.lowZone + self.w01[i] * (100.0 - self.lowZone)
            return pd.Series(result, index=close.index)

        self.oscRaw = self.I(calc_osc_raw)

        def calc_vol_osc():
            ema_result = pta.ema(self.oscRaw, length=self.smoothLen)
            return ema_result if ema_result is not None else pd.Series(50.0, index=close.index)

        self.volOsc = self.I(calc_vol_osc)

        # TTM Momentum
        def calc_hh():
            return high.rolling(window=self.len).max()

        def calc_ll():
            return low.rolling(window=self.len).min()

        self.hh = self.I(calc_hh)
        self.ll = self.I(calc_ll)

        def calc_mid_hl():
            return (self.hh + self.ll) / 2.0

        def calc_mid_ma():
            return pta.sma(close, length=self.len)

        self.midHL = self.I(calc_mid_hl)
        self.midMA = self.I(calc_mid_ma)

        def calc_mid():
            return (self.midHL + self.midMA) / 2.0

        self.mid = self.I(calc_mid)

        def calc_mom():
            diff = close - self.mid
            return pta.linreg(diff, length=self.len) or pd.Series(0.0, index=close.index)

        self.mom = self.I(calc_mom)

        def calc_scale():
            if self.momScaleMode == "Auto":
                absMax = self.mom.abs().rolling(window=self.momAutoLookbk).max()
                result = np.zeros(len(close))
                for i in range(len(close)):
                    result[i] = (50.0 / absMax[i]) if absMax[i] != 0 else 1.0
                return pd.Series(result, index=close.index)
            else:
                return pd.Series(self.momScale, index=close.index)

        self.scale = self.I(calc_scale)

        def calc_mom_delta():
            return self.mom * self.scale

        self.momDelta = self.I(calc_mom_delta)

        def calc_mom_plot():
            return 50.0 + self.momDelta

        self.momPlot = self.I(calc_mom_plot)

        # Expansion exhaustion
        def calc_expansion_exhaustion():
            wPeak = self.bbWidthPct.rolling(window=self.exhLookback).max()
            result = np.zeros(len(close))
            for i in range(self.fallBars, len(close)):
                nearPk = self.bbWidthPct[i] >= wPeak[i] * self.nearPeakPct
                fallingWid = all(self.bbWidthPct[i - j] > self.bbWidthPct[i - j + 1] for j in range(self.fallBars))
                if i < len(self.squeezeOff):
                    result[i] = 1.0 if (self.squeezeOff[i] > 0.5 and nearPk and fallingWid) else 0.0
            return pd.Series(result, index=close.index)

        self.expExhaust = self.I(calc_expansion_exhaustion)

    def next(self):
        # Simple trading logic based on TTM Volatility and Momentum
        if len(self) < 2:
            return

        # Buy when squeeze releases (BB moves outside KC) and momentum is positive
        if self.squeezeOff[-1] > 0.5 and self.squeezeOn[-2] > 0.5:
            if self.momDelta[-1] > 0:
                if not self.position:
                    self.buy()

        # Sell when volatility reaches extreme high or momentum turns very negative
        if self.position:
            if self.volOsc[-1] > self.highZone and self.momDelta[-1] < 0:
                self.sell()
            elif self.expExhaust[-1] > 0.5:
                self.sell()

        # Exit on squeeze return if position is in profit
        if self.position and self.squeezeOn[-1] > 0.5:
            if self.position.pl_pct > 0.02:
                self.sell()