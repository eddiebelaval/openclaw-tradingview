import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length_fisher = 41
    length_ma_fisher = 365
    source_ma_fisher = 'EMA'
    t_factor = 0.7
    signal_fisher = '0'
    bool_fisher = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Fisher Transform
        self.fisher_1 = self.I(self._calculate_fisher_1)
        self.fisher_2 = self.I(self._calculate_fisher_2)
        self.fisher = self.I(self._calculate_fisher)
        self.fisher_ma = self.I(self._calculate_fisher_ma)
        
        # Calculate signals
        self.bull_signal = self.I(self._calculate_bull_signal)
        self.bear_signal = self.I(self._calculate_bear_signal)

    def _calculate_fisher_1(self):
        source = (pd.Series(self.data.High) + pd.Series(self.data.Low)) / 2
        length = self.length_fisher
        
        fisher_high = source.rolling(window=length).max()
        fisher_low = source.rolling(window=length).min()
        
        normalized = (source - fisher_low) / (fisher_high - fisher_low + 1e-10)
        normalized = normalized.clip(-0.99, 0.99)
        
        fisher_value = pd.Series(index=source.index, dtype=float)
        fisher_1 = pd.Series(index=source.index, dtype=float)
        
        for i in range(len(source)):
            if i == 0:
                fv = 0.66 * (normalized.iloc[i] - 0.5) + 0.67 * 0
                f1 = 0.5 * np.log((1 + fv) / (1 - fv + 1e-10)) + 0.5 * 0
            else:
                fv = 0.66 * (normalized.iloc[i] - 0.5) + 0.67 * fisher_value.iloc[i-1]
                fv = np.clip(fv, -0.99, 0.99)
                f1 = 0.5 * np.log((1 + fv) / (1 - fv + 1e-10)) + 0.5 * fisher_1.iloc[i-1]
            
            fisher_value.iloc[i] = fv
            fisher_1.iloc[i] = f1
        
        return fisher_1

    def _calculate_fisher_2(self):
        fisher_1 = self._calculate_fisher_1()
        return fisher_1.shift(1)

    def _calculate_fisher(self):
        fisher_1 = self._calculate_fisher_1()
        fisher_2 = self._calculate_fisher_2()
        return (fisher_1 + fisher_2) / 2

    def _calculate_fisher_ma(self):
        fisher = self._calculate_fisher()
        length = self.length_ma_fisher
        ma_type = self.source_ma_fisher
        
        if ma_type == 'EMA':
            return pta.ema(fisher, length=length)
        elif ma_type == 'SMA':
            return pta.sma(fisher, length=length)
        elif ma_type == 'RMA':
            return fisher.ewm(span=length, adjust=False).mean()
        elif ma_type == 'WMA':
            return pta.wma(fisher, length=length)
        elif ma_type == 'VWMA':
            return pta.vwma(fisher, pd.Series(self.data.Volume), length=length)
        elif ma_type == 'HMA':
            return pta.hma(fisher, length=length)
        elif ma_type == 'DEMA':
            return pta.dema(fisher, length=length)
        elif ma_type == 'TEMA':
            return pta.tema(fisher, length=length)
        elif ma_type == 'TRIMA':
            return pta.trima(fisher, length=length)
        elif ma_type == 'FRAMA':
            return pta.frama(fisher, length=length)
        elif ma_type == 'T3':
            return pta.t3(fisher, length=length, factor=self.t_factor)
        else:
            return pta.ema(fisher, length=length)

    def _calculate_bull_signal(self):
        if self.signal_fisher == '0':
            return crossover(self.fisher_1, self.fisher_2)
        else:
            fisher = self._calculate_fisher()
            fisher_ma = self._calculate_fisher_ma()
            return crossover(fisher, fisher_ma)

    def _calculate_bear_signal(self):
        if self.signal_fisher == '0':
            return crossover(self.fisher_2, self.fisher_1)
        else:
            fisher = self._calculate_fisher()
            fisher_ma = self._calculate_fisher_ma()
            return crossover(fisher_ma, fisher)

    def next(self):
        if len(self) < max(self.length_fisher, self.length_ma_fisher) + 10:
            return
        
        # Entry signals
