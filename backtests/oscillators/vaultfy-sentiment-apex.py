        # Buy when green line is in extreme zone (high green sentiment)
        # Sell when red line is in extreme zone (high red sentiment)
        
        if len(self) < 2:
            return
        
        current_extreme = self.isExtreme[-1]
        prev_extreme = self.isExtreme[-2]
        
        current_red = self.lineRed[-1]
        current_green = self.lineGreen[-1]
        prev_red = self.lineRed[-2]
        prev_green = self.lineGreen[-2]
        
