import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen = 100
    rsiLen = 14
    rsiLongMax = 45.0
    rsiShortMin = 55.0
    useSession = False
    riskMode = "Ticks"
    slTicks = 40
    tpTicks = 80
    atrLen = 14
    slATRmult = 1.5
    tpATRmult = 3.0
    useTrail = False
    trailTicks = 20
    qty = 1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema = self.I(pta.ema, close, length=self.emaLen)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.tick = 0.01
        self.entry_price = None
        self.is_long = None

    def next(self):
        close = self.data.Close[-1]
        ema_val = self.ema[-1]
        rsi_val = self.rsi[-1]
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        
        if pd.isna(ema_val) or pd.isna(rsi_val):
            return
        
        trend_up = close > ema_val
        trend_down = close < ema_val
        
        long_cond = trend_up and rsi_val <= self.rsiLongMax
        short_cond = trend_down and rsi_val >= self.rsiShortMin
        
        # Entry logic
        if not self.position:
            if long_cond:
                self.buy(size=self.qty)
                self.entry_price = close
                self.is_long = True
            elif short_cond:
                self.sell(size=self.qty)
                self.entry_price = close
                self.is_long = False
        else:
            # Exit logic
            if self.position.size > 0:
                if self.riskMode == "Ticks":
                    sl = self.entry_price - self.slTicks * self.tick
                    tp = self.entry_price + self.tpTicks * self.tick
