import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    pivotLeft = 16
    pivotRight = 16

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        
        # Calculate pivot lows for price and RSI
        self.price_pivot_low = self.I(self._pivot_low, low, self.pivotLeft, self.pivotRight)
        self.rsi_pivot_low = self.I(self._pivot_low, self.rsi, self.pivotLeft, self.pivotRight)
        
        # Calculate pivot highs for price and RSI
        self.price_pivot_high = self.I(self._pivot_high, high, self.pivotLeft, self.pivotRight)
        self.rsi_pivot_high = self.I(self._pivot_high, self.rsi, self.pivotLeft, self.pivotRight)
        
        # Store last pivot values
        self.last_price_low = None
        self.last_rsi_low = None
        self.last_price_high = None
        self.last_rsi_high = None
        
        # Track divergence signals
        self.bullish_divergence = False
        self.bearish_divergence = False

    def _pivot_low(self, series, left, right):
        """Detect pivot lows in a series"""
        result = pd.Series(np.nan, index=series.index)
        for i in range(left, len(series) - right):
            if series.iloc[i] == series.iloc[i-left:i+right+1].min():
                result.iloc[i] = series.iloc[i]
        return result

    def _pivot_high(self, series, left, right):
        """Detect pivot highs in a series"""
        result = pd.Series(np.nan, index=series.index)
        for i in range(left, len(series) - right):
            if series.iloc[i] == series.iloc[i-left:i+right+1].max():
                result.iloc[i] = series.iloc[i]
        return result

    def next(self):
        # Reset divergence flags
        self.bullish_divergence = False
        self.bearish_divergence = False
        
        # Check for bullish divergence (price lower, RSI higher)
        if not np.isnan(self.price_pivot_low[-1]) and not np.isnan(self.rsi_pivot_low[-1]):
            if self.last_price_low is not None and self.last_rsi_low is not None:
                if (self.price_pivot_low[-1] < self.last_price_low) and (self.rsi_pivot_low[-1] > self.last_rsi_low):
                    self.bullish_divergence = True
            
            self.last_price_low = self.price_pivot_low[-1]
            self.last_rsi_low = self.rsi_pivot_low[-1]
        
        # Check for bearish divergence (price higher, RSI lower)
        if not np.isnan(self.price_pivot_high[-1]) and not np.isnan(self.rsi_pivot_high[-1]):
            if self.last_price_high is not None and self.last_rsi_high is not None:
                if (self.price_pivot_high[-1] > self.last_price_high) and (self.rsi_pivot_high[-1] < self.last_rsi_high):
                    self.bearish_divergence = True
            
            self.last_price_high = self.price_pivot_high[-1]
            self.last_rsi_high = self.rsi_pivot_high[-1]
        
        # Trading logic based on divergences
        if self.bullish_divergence:
            if not self.position:
                self.buy()
        elif self.bearish_divergence:
            if self.position:
                self.sell()