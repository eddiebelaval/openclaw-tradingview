    def _rma_value(self, values, length):
        """Calculate RMA (Wilder's moving average) for a list of values"""
        if len(values) == 0:
            return 0
        
        alpha = 1.0 / length
        rma = values[0]
        
        for i in range(1, len(values)):
            rma = rma * (1 - alpha) + values[i] * alpha
        
        return rma

    def _calc_rma(self, series, length):
        """Calculate RMA for a pandas series"""
        result = []
        alpha = 1.0 / length
        
        for i in range(len(series)):
            if i == 0:
                result.append(series.iloc[i])
            else:
                rma = result[i - 1] * (1 - alpha) + series.iloc[i] * alpha
                result.append(rma)
        
        return pd.Series(result, index=series.index)

