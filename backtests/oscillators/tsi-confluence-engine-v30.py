import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # TSI Parameters - Auto-detected based on timeframe
    tsi_long = 13
    tsi_short = 7
    tsi_signal = 5
    trend_ema = 21
    adx_threshold = 20.0
    rsi_length = 14
    swing_lookback = 5
    atr_fast = 14
    atr_slow = 50
    adx_length = 14
    
    # Thresholds
    ob_level = 25.0
    os_level = -25.0
    min_slope = 0.3
    
    # Filters
    use_trend_filter = True
    use_adx_filter = True
    use_mtf = True
    use_structure = True
    use_adaptive_tsi = True
    use_session_filter = False
    use_slope_filter = True
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # TSI Calculation
        mom = close.diff()
        smooth_mom = pta.ema(pta.ema(mom, length=self.tsi_long), length=self.tsi_short)
        smooth_abs = pta.ema(pta.ema(np.abs(mom), length=self.tsi_long), length=self.tsi_short)
        
        tsi_raw = (100.0 * smooth_mom / smooth_abs).fillna(0)
        self.tsi = self.I(lambda: tsi_raw)
        
        # TSI Signal Line
        self.signal = self.I(pta.ema, tsi_raw, length=self.tsi_signal)
        
        # Histogram
        self.hist = self.I(lambda: self.tsi - self.signal)
        
        # EMA Trend Filter
        self.ema = self.I(pta.ema, close, length=self.trend_ema)
        
        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=self.adx_length)
        self.adx = self.I(lambda: adx_result.iloc[:, 0] if adx_result is not None and len(adx_result.columns) > 0 else pd.Series(20, index=close.index))
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # ATR for volatility
        self.atr_fast = self.I(pta.atr, high, low, close, length=self.atr_fast)
        self.atr_slow = self.I(pta.atr, high, low, close, length=self.atr_slow)
        
        # Dynamic OB/OS levels based on ATR ratio
        self.vol_ratio = self.I(lambda: (self.atr_fast / self.atr_slow).fillna(1.0))
        self.dyn_ob = self.I(lambda: self.ob_level * self.vol_ratio)
        self.dyn_os = self.I(lambda: -self.ob_level * self.vol_ratio)
        
        # Swing pivots for structure
        def get_swing_high():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(self.swing_lookback, len(high) - self.swing_lookback):
                window = high.iloc[i-self.swing_lookback:i+self.swing_lookback+1]
                if high.iloc[i] == window.max():
                    result.iloc[i] = high.iloc[i]
                else:
                    result.iloc[i] = np.nan
            return result
        
        def get_swing_low():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(self.swing_lookback, len(low) - self.swing_lookback):
                window = low.iloc[i-self.swing_lookback:i+self.swing_lookback+1]
                if low.iloc[i] == window.min():
                    result.iloc[i] = low.iloc[i]
                else:
                    result.iloc[i] = np.nan
            return result
        
        self.swing_high = self.I(get_swing_high)
        self.swing_low = self.I(get_swing_low)
        
        # Crossover slope
        def calc_slope():
            return (self.hist - pd.Series(self.hist).shift(2)) / 2.0
        
        self.slope = self.I(calc_slope)
        
        # Track structure bias
        self.struct_bias = 0
        self.last_swing_high = None
        self.last_swing_low = None
        
        # Tracking variables
        self.last_buy_bar = -999
        self.last_sell_bar = -999
        self.cooldown_bars = 5

    def next(self):
        # Current values
        tsi = self.tsi[-1]
        sig = self.signal[-1]
        close_price = self.data.Close[-1]
        ema_val = self.ema[-1]
        adx_val = self.adx[-1]
        rsi_val = self.rsi[-1]
        dyn_ob = self.dyn_ob[-1]
        dyn_os = self.dyn_os[-1]
        slope = abs(self.slope[-1]) if not np.isnan(self.slope[-1]) else 0
        
        # Trend checks
        trend_up = close_price > ema_val
        trend_down = close_price < ema_val
        is_trending = adx_val > self.adx_threshold
        
        # Extreme zones
        in_ob_zone = tsi > dyn_ob
        in_os_zone = tsi < dyn_os
        
        # Crossovers
        bull_cross = crossover(self.tsi, self.signal)
        bear_cross = crossover(self.signal, self.tsi)
        
        # Slope filter
        slope_ok = slope >= self.min_slope if self.use_slope_filter else True
        
        # Structure tracking
        if not np.isnan(self.swing_high[-1]):
            self.last_swing_high = self.swing_high[-1]
            self.struct_bias = 1
        if not np.isnan(self.swing_low[-1]):
            self.last_swing_low = self.swing_low[-1]
            self.struct_bias = -1
        
        struct_bullish = self.struct_bias > 0 if self.use_structure else True
        struct_bearish = self.struct_bias < 0 if self.use_structure else True
        
        # Filters
        trend_bull_ok = trend_up if self.use_trend_filter else True
        trend_bear_ok = trend_down if self.use_trend_filter else True
        adx_ok = is_trending if self.use_adx_filter else True
        
        # BUY Signal: TSI crosses above signal in oversold zone with uptrend
        buy_signal = (
            bull_cross and
            in_os_zone and
            trend_bull_ok and
            adx_ok and
            slope_ok and
            struct_bullish and
            len(self) - self.last_buy_bar > self.cooldown_bars
        )
        
        # SELL Signal: TSI crosses below signal in overbought zone with downtrend
        sell_signal = (
            bear_cross and
            in_ob_zone and
            trend_bear_ok and
            adx_ok and
            slope_ok and
            struct_bearish and
            len(self) - self.last_sell_bar > self.cooldown_bars
        )
        
        # Execute trades
        if buy_signal:
            if self.position.is_short:
                self.position.close()
            if not self.position:
                self.buy()
            self.last_buy_bar = len(self)
        
        if sell_signal:
            if self.position.is_long:
                self.position.close()
            if not self.position:
                self.sell()
            self.last_sell_bar = len(self)
        
        # Exit on opposite extreme
        if self.position.is_long and tsi > dyn_ob * 0.9:
            self.position.close()
        
        if self.position.is_short and tsi < dyn_os * 0.9:
            self.position.close()