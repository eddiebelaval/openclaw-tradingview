import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # OVI calculation
        # ovi_base = ta.sma(close > close[1] ? volume : -volume, 10)
        def calc_ovi_base():
            volume_signed = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if i == 0:
                    volume_signed.iloc[i] = volume.iloc[i]
                else:
                    volume_signed.iloc[i] = volume.iloc[i] if close.iloc[i] > close.iloc[i-1] else -volume.iloc[i]
            return pta.sma(volume_signed, length=10)
        
        self.ovi_base = self.I(calc_ovi_base)
        
        # ovi_norm = math.abs(ta.stdev(ovi_base, 10))
        def calc_ovi_norm():
            base = calc_ovi_base()
            if base is None:
                return pd.Series(1, index=close.index)
            stdev = pta.stdev(base, length=10)
            if stdev is None:
                return pd.Series(1, index=close.index)
            return stdev.abs()
        
        self.ovi_norm = self.I(calc_ovi_norm)
        
        # val_ovi = 50 + (ovi_base / (ovi_norm == 0 ? 1 : ovi_norm))
        def calc_val_ovi():
            base = calc_ovi_base()
            norm = calc_ovi_norm()
            if base is None or norm is None:
                return pd.Series(50, index=close.index)
            norm_safe = norm.replace(0, 1)
            return 50 + (base / norm_safe)
        
        self.val_ovi = self.I(calc_val_ovi)
        
        # val_rsi = ta.rsi(close, 7)
        self.val_rsi = self.I(pta.rsi, close, length=7)
        
        # vol_rel = volume / ta.sma(volume, 20)
        def calc_vol_rel():
            vol_sma = pta.sma(volume, length=20)
            if vol_sma is None:
                return pd.Series(1, index=volume.index)
            vol_sma_safe = vol_sma.replace(0, 1)
            return volume / vol_sma_safe
        
        self.vol_rel = self.I(calc_vol_rel)
        
        # es_apto = val_ovi > 50 and val_ovi > val_ovi[1] and val_rsi < 65
        def calc_es_apto():
            ovi = calc_val_ovi()
            rsi = pta.rsi(close, length=7)
            if ovi is None or rsi is None:
                return pd.Series(False, index=close.index)
            ovi_rising = ovi > ovi.shift(1)
            return (ovi > 50) & ovi_rising & (rsi < 65)
        
        self.es_apto = self.I(calc_es_apto)

    def next(self):
        if len(self.data) < 20:
            return
        
        ovi = self.val_ovi[-1] if len(self.val_ovi) > 0 else 50
        rsi = self.val_rsi[-1] if len(self.val_rsi) > 0 else 50
        es_apto = self.es_apto[-1] if len(self.es_apto) > 0 else False
        
        # Buy signal when OVI > 50, OVI rising, and RSI < 65
        if es_apto and not self.position:
            self.buy()
        
        # Sell signal when conditions no longer met or RSI overbought
        if self.position and (ovi <= 50 or rsi >= 70):
            self.sell()