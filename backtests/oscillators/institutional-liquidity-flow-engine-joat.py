import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    volumeLength = 20
    rvolThreshold = 1.5
    extremeRvolThreshold = 3.0
    atrLength = 14
    rsiLength = 14
    rsiOverbought = 70
    rsiOversold = 30

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_price = pd.Series(self.data.Open)

        self.avgVolume = self.I(lambda: pta.sma(volume, length=self.volumeLength))
        self.relativeVolume = self.I(lambda: volume / self.avgVolume.replace(0, 1))
        
        self.volumeMA = self.I(lambda: pta.ema(volume, length=self.volumeLength))
        
        shortVol = self.I(lambda: pta.ema(volume, length=5))
        longVol = self.I(lambda: pta.ema(volume, length=10))
        self.volumeOsc = self.I(lambda: 100 * (shortVol - longVol) / longVol.replace(0, 1))
        
        self.atrValue = self.I(lambda: pta.atr(high, low, close, length=self.atrLength))
        
        self.buyerVolume = self.I(lambda: pd.Series(
            [volume.iloc[i] if close.iloc[i] > open_price.iloc[i] else 0 
             for i in range(len(close))], index=close.index
        ))
        self.sellerVolume = self.I(lambda: pd.Series(
            [volume.iloc[i] if close.iloc[i] < open_price.iloc[i] else 0 
             for i in range(len(close))], index=close.index
        ))
        
        self.buyerStrength = self.I(lambda: pta.sma(self.buyerVolume, length=self.volumeLength))
        self.sellerStrength = self.I(lambda: pta.sma(self.sellerVolume, length=self.volumeLength))
        
        self.rsiValue = self.I(lambda: pta.rsi(close, length=self.rsiLength))
        
        self.netPressure = self.I(lambda: self.buyerStrength - self.sellerStrength)
        
        self.mfi = self.I(lambda: pta.mfi(high, low, close, volume, length=self.volumeLength))
        
        self.vwap = self.I(lambda: pta.vwap(high, low, close, volume))
        self.vwapDeviation = self.I(lambda: close - self.vwap)
        
        self.obv = self.I(lambda: pta.obv(close, volume))
        self.obvMA = self.I(lambda: pta.sma(self.obv, length=self.volumeLength))
        
        self.ad = self.I(lambda: pta.ad(high, low, close, volume))

    def next(self):
        if len(self.data) < self.atrLength + 1:
            return

        current_rvol = self.relativeVolume[-1]
        current_rsi = self.rsiValue[-1]
        current_obv = self.obv[-1]
        current_obv_ma = self.obvMA[-1]
        current_mfi = self.mfi[-1]
        current_pressure = self.netPressure[-1]
        prev_pressure = self.netPressure[-2] if len(self.netPressure) > 1 else 0
        
        buy_signal = False
        sell_signal = False

        if len(self.relativeVolume) > 1:
            prev_rvol = self.relativeVolume[-2]
            if prev_rvol < self.rvolThreshold and current_rvol >= self.rvolThreshold:
                if current_rsi < self.rsiOversold or (current_obv > current_obv_ma and current_mfi < 50):
                    buy_signal = True
            
            if prev_rvol >= self.rvolThreshold and current_rvol < self.rvolThreshold:
                if current_rsi > self.rsiOverbought or (current_obv < current_obv_ma and current_mfi > 50):
                    sell_signal = True

        if current_pressure > 0 and prev_pressure <= 0 and current_rvol > 1.0:
            if current_rsi < 60 and current_mfi < 70:
                buy_signal = True

        if current_pressure < 0 and prev_pressure >= 0 and current_rvol > 1.0:
            if current_rsi > 40 and current_mfi > 30:
                sell_signal = True

        if current_rsi < self.rsiOversold and current_rvol > 1.0 and current_obv > current_obv_ma:
            buy_signal = True

        if current_rsi > self.rsiOverbought and current_rvol > 1.0 and current_obv < current_obv_ma:
            sell_signal = True

        if current_rvol >= self.extremeRvolThreshold:
            if current_pressure > 0 and current_rsi < 70:
                buy_signal = True
            elif current_pressure < 0 and current_rsi > 30:
                sell_signal = True

        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()