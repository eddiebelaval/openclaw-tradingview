import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiPeriod = 14
    rsiOverbought = 65
    rsiOversold = 35

    def init(self):
        close = pd.Series(self.data.Close)
        self.rsi = self.I(pta.rsi, close, length=self.rsiPeriod)

    def next(self):
        if len(self.data) < 2:
            return
        
        current_rsi = self.rsi[-1]
        prev_rsi = self.rsi[-2]
        
        if current_rsi is None or prev_rsi is None:
            return
        
        if not self.position:
            if current_rsi <= self.rsiOversold and prev_rsi < current_rsi:
                self.buy()
            elif current_rsi >= self.rsiOverbought and prev_rsi > current_rsi:
                self.sell()
        else:
            if self.position.is_long:
                if current_rsi >= self.rsiOverbought:
                    self.position.close()
            elif self.position.is_short:
                if current_rsi <= self.rsiOversold:
                    self.position.close()


