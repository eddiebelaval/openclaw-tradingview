import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Engine Parameters
    ema_fast_len = 13
    ema_slow_len = 26
    ema_L_len = 200
    macd_fast = 12
    macd_slow = 26
    macd_sig = 9
    stoch_k = 14
    stoch_ob = 80
    stoch_os = 20
    env_len = 26
    env_mult = 2.7
    tf_mult = 5
    
    # Strategy Logic
    trade_mode = "Standard (Triple Screen)"
    tide_src = "HTF EMA Direction (Trend)"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Screen 2: Tactical Chart
        self.ema_13 = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema_26 = self.I(pta.ema, close, length=self.ema_slow_len)
        
        # MACD on tactical chart
        macd_result = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig) or pd.DataFrame(index=close.index))
        self.macd_S = self.I(lambda: macd_result.iloc[:, 0] if macd_result is not None and len(macd_result.columns) > 0 else pd.Series(0, index=close.index))
        self.sig_S = self.I(lambda: macd_result.iloc[:, 1] if macd_result is not None and len(macd_result.columns) > 1 else pd.Series(0, index=close.index))
        self.hist_S = self.I(lambda: macd_result.iloc[:, 2] if macd_result is not None and len(macd_result.columns) > 2 else pd.Series(0, index=close.index))
        
        # Stochastic
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=self.stoch_k) or pd.DataFrame(index=close.index))
        self.stoch_val = self.I(lambda: stoch_result.iloc[:, 0] if stoch_result is not None and len(stoch_result.columns) > 0 else pd.Series(50, index=close.index))
        self.stoch_smooth = self.I(pta.sma, self.I(lambda: self.stoch_val), length=3)
        
        # Envelope
        self.env_basis = self.I(pta.ema, close, length=self.env_len)
        self.env_dev = self.I(lambda: pta.sma(np.abs(close - self.env_basis), length=100) * self.env_mult if self.env_basis is not None else pd.Series(0, index=close.index))
        self.env_upper = self.I(lambda: self.env_basis + self.env_dev if self.env_basis is not None and self.env_dev is not None else pd.Series(close.iloc[-1], index=close.index))
        self.env_lower = self.I(lambda: self.env_basis - self.env_dev if self.env_basis is not None and self.env_dev is not None else pd.Series(close.iloc[-1], index=close.index))

    def next(self):
        # Access current bar values
        if len(self.data) < max(self.ema_fast_len, self.ema_slow_len, self.stoch_k) + 5:
            return
        
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        high_prev = self.data.High[-2]
        low_prev = self.data.Low[-2]
        
        ema_13_val = self.ema_13[-1]
        ema_13_prev = self.ema_13[-2] if len(self.ema_13) > 1 else ema_13_val
        ema_26_val = self.ema_26[-1]
        
        hist_S_val = self.hist_S[-1]
        hist_S_prev = self.hist_S[-2] if len(self.hist_S) > 1 else hist_S_val
        
        stoch_smooth_val = self.stoch_smooth[-1]
        stoch_smooth_prev = self.stoch_smooth[-2] if len(self.stoch_smooth) > 1 else stoch_smooth_val
        
        # Impulse Logic
        impulse_up = (ema_13_val > ema_13_prev) and (hist_S_val > hist_S_prev)
        impulse_down = (ema_13_val < ema_13_prev) and (hist_S_val < hist_S_prev)
        
        # Tide Logic (using EMA direction for trend)
        tide_bull = close_val > ema_26_val
        tide_bear = close_val < ema_26_val
        
        # Stochastic zones
        stoch_crossover = crossover(self.stoch_smooth, self.stoch_os)
        stoch_crossunder = crossover(self.stoch_ob, self.stoch_smooth)
        buy_zone = (stoch_smooth_val < self.stoch_os) or stoch_crossover
        sell_zone = (stoch_smooth_val > self.stoch_ob) or stoch_crossunder
        
        # Triggers
        trigger_buy = close_val > high_prev
        trigger_sell = close_val < low_prev
        
        # Signal generation based on trade mode
        if self.trade_mode == "Standard (Triple Screen)":
            sig_buy = tide_bull and buy_zone and trigger_buy
            sig_sell = tide_bear and sell_zone and trigger_sell
        elif self.trade_mode == "Aggressive (Impulse Momentum)":
            sig_buy = tide_bull and impulse_up and not (len(self.ema_13) > 2 and self.ema_13[-2] > self.ema_13[-3] and self.hist_S[-2] > self.hist_S[-3])
            sig_sell = tide_bear and impulse_down and not (len(self.ema_13) > 2 and self.ema_13[-2] < self.ema_13[-3] and self.hist_S[-2] < self.hist_S[-3])
        else:  # Hybrid
            sig_buy = (tide_bull and buy_zone and trigger_buy) or (tide_bull and impulse_up)
            sig_sell = (tide_bear and sell_zone and trigger_sell) or (tide_bear and impulse_down)
        
        # Execute trades
        if sig_buy and not self.position:
            self.buy()
        elif sig_sell and self.position:
            self.position.close()


