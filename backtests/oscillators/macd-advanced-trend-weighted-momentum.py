import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    m200l = 200
    lb = 50
    f1 = 12
    f2 = 26
    si = 9

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMA for ratio calculation
        ma200 = self.I(pta.ema, close, length=self.m200l)
        
        # Calculate EMA with offset (lb periods back)
        close_offset = pd.Series([close.iloc[max(0, i-self.lb)] for i in range(len(close))], index=close.index)
        ma201 = self.I(pta.ema, close_offset, length=self.m200l)
        
        # Calculate ratio
        def calc_ratio():
            ratio = np.zeros(len(close))
            for i in range(len(close)):
                if ma201[i] != 0:
                    ratio[i] = (ma200[i] / ma201[i]) - 1
                else:
                    ratio[i] = 0
            return pd.Series(ratio, index=close.index)
        
        r = self.I(calc_ratio)
        
        # Calculate MACD
        macd_result = self.I(pta.macd, close, fast=self.f1, slow=self.f2, signal=self.si)
        
        # Extract MACD components
        def get_macd():
            if macd_result is not None and len(macd_result.columns) >= 3:
                macd_col = macd_result.iloc[:, 0]
                return pd.Series(macd_col, index=close.index)
            return pd.Series(0, index=close.index)
        
        def get_signal():
            if macd_result is not None and len(macd_result.columns) >= 3:
                signal_col = macd_result.iloc[:, 2]
                return pd.Series(signal_col, index=close.index)
            return pd.Series(0, index=close.index)
        
        def get_hist():
            if macd_result is not None and len(macd_result.columns) >= 3:
                hist_col = macd_result.iloc[:, 1]
                return pd.Series(hist_col, index=close.index)
            return pd.Series(0, index=close.index)
        
        self.macd = self.I(get_macd)
        self.signal = self.I(get_signal)
        self.hist = self.I(get_hist)
        
        # Adjust MACD with ratio
        def adjusted_macd():
            return self.macd + r
        
        self.macd_adj = self.I(adjusted_macd)

    def next(self):
        # Histogram crossover zero
        hist_upc = crossover(self.hist, 0)
        hist_dnc = crossover(0, self.hist)
        
        # MACD crossover zero
        macd_upc = crossover(self.macd_adj, 0)
        macd_dnc = crossover(0, self.macd_adj)
        
        # Entry and exit logic
        if hist_upc or macd_upc:
            if not self.position:
                self.buy()
        elif hist_dnc or macd_dnc:
            if self.position:
                self.position.close()