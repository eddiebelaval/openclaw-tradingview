import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen = 50
    rsiLen = 14
    swingLen = 10
    useADX = True
    adxLen = 14
    adxSmoothing = 14
    adxMin = 18.0
    useVwapDist = True
    vwapDistPct = 0.30
    useCooldown = True
    cooldownBars = 6
    useTrendLock = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.vwap = self.I(pta.vwap, high, low, close, volume)
        self.ema_trend = self.I(pta.ema, close, length=self.emaLen)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)

        self.swing_high = self.I(lambda: high.rolling(self.swingLen).max())
        self.swing_low = self.I(lambda: low.rolling(self.swingLen).min())

        adx_result = self.I(pta.adx, high, low, close, length=self.adxLen)
        self.adx = adx_result

        self.last_entry_bar = -np.inf
        self.in_long = False
        self.in_short = False

    def next(self):
        if len(self.data) < self.swingLen + 1:
            return

        close = self.data.Close[-1]
        vwap = self.vwap[-1]
        ema = self.ema_trend[-1]
        rsi = self.rsi[-1]
        swing_h = self.swing_high[-1]
        swing_l = self.swing_low[-1]
        swing_h_prev = self.swing_high[-2] if len(self.data) > 1 else swing_h
        swing_l_prev = self.swing_low[-2] if len(self.data) > 1 else swing_l

        if pd.isna(vwap) or pd.isna(ema) or pd.isna(rsi) or pd.isna(swing_h) or pd.isna(swing_l):
            return

        bull_regime = close > vwap and close > ema
        bear_regime = close < vwap and close < ema

        bull_momentum = rsi > 55
        bear_momentum = rsi < 45

        bull_break = close > swing_h_prev
        bear_break = close < swing_l_prev

        long_core = bull_regime and bull_momentum and bull_break
        short_core = bear_regime and bear_momentum and bear_break

        adx_ok = True
        if self.useADX:
            adx = self.adx[-1]
            if not pd.isna(adx):
                adx_ok = adx >= self.adxMin

        vwap_dist_ok = True
        if self.useVwapDist:
            if vwap != 0:
                vwap_dist = abs(close - vwap) / vwap * 100.0
                vwap_dist_ok = vwap_dist <= self.vwapDistPct

        cooldown_ok = True
        if self.useCooldown:
            cooldown_ok = (len(self.data) - self.last_entry_bar) > self.cooldownBars

        long_filtered = long_core and adx_ok and vwap_dist_ok and cooldown_ok
        short_filtered = short_core and adx_ok and vwap_dist_ok and cooldown_ok

        allow_long = True
        allow_short = True

        if self.useTrendLock:
            allow_long = not self.in_short or (self.in_short and bear_regime)
            allow_short = not self.in_long or (self.in_long and bull_regime)

        long_signal = long_filtered and allow_long
        short_signal = short_filtered and allow_short

        if long_signal:
            if self.position:
                self.position.close()
            self.buy()
            self.last_entry_bar = len(self.data)
            self.in_long = True
            self.in_short = False

        if short_signal:
            if self.position:
                self.position.close()
            self.sell()
            self.last_entry_bar = len(self.data)
            self.in_short = True
            self.in_long = False

        if self.position:
            if self.position.is_long and bear_regime:
                self.position.close()
                self.in_long = False
            elif self.position.is_short and bull_regime:
                self.position.close()
                self.in_short = False


