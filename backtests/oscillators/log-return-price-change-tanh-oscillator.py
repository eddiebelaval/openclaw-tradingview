import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    velocityLen = 8
    accelSmoothLen = 5
    finalSmoothLen = 3
    returnBars = 14
    normLookback = 80
    tanhScale = 2.2
    velocityWeight = 0.65
    accelWeight = 0.35
    deadZone = 7.0
    signalLen = 9

