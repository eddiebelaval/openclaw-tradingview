        self.vwap = self.I(pta.vwap, high, low, close, volume)
        
        # Exponential Smoothing
        def calc_es():
            result = []
            es_val = np.nan
            for i in range(len(close)):
                if np.isnan(es_val):
                    es_val = close.iloc[i]
                else:
                    es_val = self.esAlpha * close.iloc[i] + (1.0 - self.esAlpha) * es_val
