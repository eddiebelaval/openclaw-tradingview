        def calc_linreg():
            result = []
            for i in range(len(close)):
                if i < self.lrLen:
                    result.append(np.nan)
                else:
                    y_vals = close.iloc[i-self.lrLen+1:i+1].values
                    x_vals = np.arange(self.lrLen)
                    coeffs = np.polyfit(x_vals, y_vals, 1)
                    result.append(coeffs[1] + coeffs[0] * (self.lrLen - 1))
            return pd.Series(result)
        
        def calc_linreg_dev():
            result = []
            for i in range(len(close)):
                if i < self.lrLen:
                    result.append(np.nan)
                else:
                    y_vals = close.iloc[i-self.lrLen+1:i+1].values
                    x_vals = np.arange(self.lrLen)
                    coeffs = np.polyfit(x_vals, y_vals, 1)
                    fit = coeffs[1] + coeffs[0] * x_vals
                    dev = np.std(y_vals - fit)
                    result.append(dev)
            return pd.Series(result)
        
        def calc_linreg_slope():
            result = []
            for i in range(len(close)):
                if i < self.lrLen:
                    result.append(np.nan)
                else:
                    y_vals = close.iloc[i-self.lrLen+1:i+1].values
                    x_vals = np.arange(self.lrLen)
                    coeffs = np.polyfit(x_vals, y_vals, 1)
                    result.append(coeffs[0])
            return pd.Series(result)
        
