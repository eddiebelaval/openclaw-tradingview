import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Linear Regression
    lrLen = 34
    lrForecast = 3
    lrDevMult = 2.0
    
    # Moving Averages
    fastLen = 8
    slowLen = 21
    trendLen = 50
    
    # RSI
    rsiLen = 14
    rsiOB = 65
    rsiOS = 35
    rsiMid = 50
    
    # Exponential Smoothing
    esAlpha = 0.1
    esLen = 20
    
    # ARIMA-proxy
    diffLen = 5
    diffSmooth = 3
    
    # Prophet Bands
    prophetLen = 50
    prophetMult = 1.5
    
    # Anomaly Detection
    anomalyLen = 20
    anomalySigma = 2.5
    
    # Confluence Gate
    minScore = 6
    
    # ATR Risk Management
    atrLen = 14
    atrMult_SL = 1.5
    atrMult_TP = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
