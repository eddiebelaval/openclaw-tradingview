import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    mom_len = 14
    vol_len = 20
    ob_level = 70
    os_level = -70
    trend_len = 50
    lbR = 5
    lbL = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Momentum calculation: ROC normalized
        mom_raw = self.I(lambda: pta.roc(close, length=self.mom_len) or pd.Series(0, index=close.index))
        mom_max = self.I(lambda: np.abs(mom_raw).rolling(window=100).max() or pd.Series(1, index=close.index))
        self.mom_norm = self.I(lambda: np.where(mom_max != 0, mom_raw / mom_max * 100, 0))
        
        # Volume ratio
        vol_ma = self.I(pta.sma, volume, length=self.vol_len)
        vol_ratio = self.I(lambda: volume / vol_ma)
        self.vol_scaled = self.I(lambda: np.minimum(vol_ratio, 3.0) / 3.0)
        
        # RSI-based oscillator
        rsi_val = self.I(pta.rsi, close, length=self.mom_len)
        self.osc_line = self.I(lambda: (rsi_val - 50) * 1.4)
        
        # Trend calculation
        ema_fast = self.I(pta.ema, close, length=21)
        ema_slow = self.I(pta.ema, close, length=self.trend_len)
        trend_raw = self.I(lambda: (ema_fast - ema_slow) / ema_slow * 1000)
        self.trend_smooth = self.I(pta.ema, trend_raw, length=8)
        
        # Pivot highs and lows for divergence detection
        self.mom_norm_list = []
        self.high_list = []
        self.low_list = []
        self.bar_count = 0
        
        self.last_ph_mom = None
        self.last_pl_mom = None
        self.last_ph_price = None
        self.last_pl_price = None
        self.bear_div = False
        self.bull_div = False

    def next(self):
        self.bar_count += 1
        self.mom_norm_list.append(self.mom_norm[-1])
        self.high_list.append(self.data.High[-1])
        self.low_list.append(self.data.Low[-1])
        
        # Detect pivot highs and lows
        if len(self.mom_norm_list) > self.lbL + self.lbR:
            idx = len(self.mom_norm_list) - self.lbR - 1
            
            # Check for pivot high
            is_ph = all(self.mom_norm_list[idx] >= self.mom_norm_list[i] 
                       for i in range(idx - self.lbL, idx + self.lbR + 1) if i >= 0 and i < len(self.mom_norm_list))
            
            if is_ph:
                curr_ph_mom = self.mom_norm_list[idx]
                curr_ph_price = self.high_list[idx]
                
                if self.last_ph_mom is not None and self.last_ph_price is not None:
                    if curr_ph_price > self.last_ph_price and curr_ph_mom < self.last_ph_mom:
                        self.bear_div = True
                
                self.last_ph_mom = curr_ph_mom
                self.last_ph_price = curr_ph_price
            
            # Check for pivot low
            is_pl = all(self.mom_norm_list[idx] <= self.mom_norm_list[i] 
                       for i in range(idx - self.lbL, idx + self.lbR + 1) if i >= 0 and i < len(self.mom_norm_list))
            
            if is_pl:
                curr_pl_mom = self.mom_norm_list[idx]
                curr_pl_price = self.low_list[idx]
                
                if self.last_pl_mom is not None and self.last_pl_price is not None:
                    if curr_pl_price < self.last_pl_price and curr_pl_mom > self.last_pl_mom:
                        self.bull_div = True
                
                self.last_pl_mom = curr_pl_mom
                self.last_pl_price = curr_pl_price
        
        # Entry/Exit Logic
        # Buy on bullish divergence or when osc_line crosses above oversold level
        if self.bull_div or crossover(self.osc_line, self.os_level):
            if not self.position:
                self.buy()
            self.bull_div = False
        
        # Sell on bearish divergence or when osc_line crosses below overbought level
        if self.bear_div or crossover(self.ob_level, self.osc_line):
            if self.position:
                self.sell()
            self.bear_div = False
        
        # Exit on trend reversal
        if self.position:
            if crossover(0, self.trend_smooth):
                self.sell()
        else:
            if crossover(self.trend_smooth, 0):
                self.buy()


