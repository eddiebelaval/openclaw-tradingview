import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFast = 9
    emaSlow = 21
    emaTrend = 50
    atrPeriod = 14
    atrMult = 1.5
    rr = 1.8
    adxLen = 14
    adxThresh = 20
    useADX = True
    riskPercent = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.ema_fast = self.I(pta.ema, close, length=self.emaFast)
        self.ema_slow = self.I(pta.ema, close, length=self.emaSlow)
        self.ema_trend = self.I(pta.ema, close, length=self.emaTrend)

        self.atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)

        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adxLen))
        self.adx = self.I(lambda: adx_result['ADX_14'] if adx_result is not None and 'ADX_14' in adx_result.columns else pd.Series(20, index=close.index))

        self.rsi = self.I(pta.rsi, close, length=14)

        self.entry_price = None
        self.entry_stop = None
        self.entry_target = None

    def next(self):
        close_val = self.data.Close[-1]
        atr_val = self.atr[-1]
        rsi_val = self.rsi[-1]
        ema_fast_val = self.ema_fast[-1]
        ema_slow_val = self.ema_slow[-1]
        ema_trend_val = self.ema_trend[-1]
        adx_val = self.adx[-1]

        if atr_val is None or np.isnan(atr_val):
            return

        utility_edge = (rsi_val - 50) / 50
        buyer_edge = utility_edge > 0
        seller_edge = utility_edge < 0
        equilibrium = abs(utility_edge) < 0.1

        uptrend = close_val > ema_trend_val
        downtrend = close_val < ema_trend_val

        strong_trend = adx_val > self.adxThresh

        ema_cross_up = crossover(self.ema_fast, self.ema_slow)
        ema_cross_down = crossover(self.ema_slow, self.ema_fast)

        long_cond = ema_cross_up and uptrend and buyer_edge and not equilibrium and (not self.useADX or strong_trend)
        short_cond = ema_cross_down and downtrend and seller_edge and not equilibrium and (not self.useADX or strong_trend)

        if self.position:
            if self.position.is_long:
                if close_val <= self.entry_stop or close_val >= self.entry_target:
                    self.position.close()
            elif self.position.is_short:
                if close_val >= self.entry_stop or close_val <= self.entry_target:
                    self.position.close()
        else:
            if long_cond:
                capital_risk = self.equity * (self.riskPercent / 100)
                long_stop = close_val - atr_val * self.atrMult
                long_risk = close_val - long_stop

                if long_risk > 0:
                    qty = capital_risk / long_risk
                    self.buy(size=qty)
                    self.entry_price = close_val
                    self.entry_stop = long_stop
                    self.entry_target = close_val + (atr_val * self.atrMult * self.rr)

            elif short_cond:
                capital_risk = self.equity * (self.riskPercent / 100)
                short_stop = close_val + atr_val * self.atrMult
                short_risk = short_stop - close_val

                if short_risk > 0:
                    qty = capital_risk / short_risk
                    self.sell(size=qty)
                    self.entry_price = close_val
                    self.entry_stop = short_stop
                    self.entry_target = close_val - (atr_val * self.atrMult * self.rr)


