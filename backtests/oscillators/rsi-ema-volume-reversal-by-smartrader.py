import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    rsi_overbought = 70
    rsi_oversold = 30
    lookback = 10
    ema_length = 13
    use_vol_filter = True
    vol_length = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Calculate EMA
        self.ema = self.I(pta.ema, close, length=self.ema_length)
        
        # Calculate Volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=self.vol_length)
        
        # Calculate lowest RSI over lookback period
        self.rsi_lowest = self.I(lambda: self.rsi.rolling(window=self.lookback).min())
        
        # Calculate highest RSI over lookback period
        self.rsi_highest = self.I(lambda: self.rsi.rolling(window=self.lookback).max())

    def next(self):
        if len(self.data) < max(self.rsi_length, self.ema_length, self.lookback, self.vol_length) + 1:
            return
        
        close_current = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        ema_current = self.ema[-1]
        ema_prev = self.ema[-2]
        volume_current = self.data.Volume[-1]
        vol_sma_current = self.vol_sma[-1]
        rsi_lowest = self.rsi_lowest[-1]
        rsi_highest = self.rsi_highest[-1]
        
        # Volume condition
        vol_condition = (not self.use_vol_filter) or (volume_current > vol_sma_current)
        
        # Reversal conditions
        was_oversold = rsi_lowest <= self.rsi_oversold
        was_overbought = rsi_highest >= self.rsi_overbought
        
        # Crossover conditions
        close_cross_above_ema = close_prev <= ema_prev and close_current > ema_current
        close_cross_below_ema = close_prev >= ema_prev and close_current < ema_current
        
        # Buy signal: RSI was oversold AND price crossed above EMA AND volume condition
        if was_oversold and close_cross_above_ema and vol_condition:
            if not self.position:
                self.buy()
        
        # Sell signal: RSI was overbought AND price crossed below EMA AND volume condition
        elif was_overbought and close_cross_below_ema and vol_condition:
            if self.position:
                self.sell()


