import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenDI = 14
    lenADX = 14
    sigLen = 5
    trendThresh = 25.0
    extremePct = 0.80
    cooldownBars = 6
    minQuality = 0.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # ATR and True Range
        self.atr = self.I(pta.atr, high, low, close, length=self.lenDI)

        # DM Calculations
        up = high.diff()
        down = -low.diff()
        plusDM = np.where((up > down) & (up > 0), up, 0)
        minusDM = np.where((down > up) & (down > 0), down, 0)

        # RMA (EMA-like)
        self.plus = self.I(lambda: self._rma_series(pd.Series(plusDM), self.lenDI) / (self._rma_series(pd.Series(self.data.High.diff()), self.lenDI) + 1e-10) * 100)
        self.minus = self.I(lambda: self._rma_series(pd.Series(minusDM), self.lenDI) / (self._rma_series(pd.Series(-self.data.Low.diff()), self.lenDI) + 1e-10) * 100)

        # ADX
        sum_dm = self.plus + self.minus
        diff_dm = self.plus - self.minus
        self.adx = self.I(lambda: 100 * self._rma_series(np.abs(diff_dm) / (sum_dm + 1e-10), self.lenADX))

        # Zenith (Signed DX)
        self.zenRaw = self.I(lambda: (diff_dm / (sum_dm + 1e-10)) * 100.0)
        self.zenSig = self.I(pta.ema, self.zenRaw, length=self.sigLen)

        # Dynamic bands
        self.band = self.I(lambda: 1.6 * self.zenRaw.rolling(100).std())
        self.upper = self.band
        self.lower = -self.band

        self.zenVel = self.I(lambda: self.zenRaw.diff())

        # Extreme zones
        self.extremeUpper = self.upper * self.extremePct
        self.extremeLower = self.lower * self.extremePct
        self.nearOB = self.I(lambda: self.zenRaw >= self.extremeUpper)
        self.nearOS = self.I(lambda: self.zenRaw <= self.extremeLower)

        # Volume
        self.volMA = self.I(pta.sma, volume, length=20)
        self.relVol = self.I(lambda: volume / (self.volMA + 1e-10))

        # Signal state tracking
        self.bars_since_peak = 999
        self.bars_since_valley = 999

    def _rma_series(self, src, length):
        return src.ewm(span=length, adjust=False).mean()

    def next(self):
        self.bars_since_peak += 1
        self.bars_since_valley += 1

        if len(self.data) < self.lenDI + self.sigLen + 5:
            return

        # Signal detection
        sig_cross_down = crossover(self.zenSig, self.zenRaw)
        sig_cross_up = crossover(self.zenRaw, self.zenSig)

        in_trend = self.adx[-1] >= self.trendThresh
        in_upper_extreme = self.nearOB[-1]
        in_lower_extreme = self.nearOS[-1]

        peak_signal = (sig_cross_down and in_upper_extreme and 
                      self.zenVel[-1] < 0 and self.bars_since_peak >= self.cooldownBars)
        valley_signal = (sig_cross_up and in_lower_extreme and 
                        self.zenVel[-1] > 0 and self.bars_since_valley >= self.cooldownBars)

        # Quality scoring
        peak_quality = 0.0
        valley_quality = 0.0

        if peak_signal:
            peak_quality = 40.0
            if in_trend:
                peak_quality += 5.0
            peak_quality = min(peak_quality, 100.0)
            if peak_quality >= self.minQuality:
                self.sell()
                self.bars_since_peak = 0

        if valley_signal:
            valley_quality = 40.0
            if in_trend:
                valley_quality += 5.0
            valley_quality = min(valley_quality, 100.0)
            if valley_quality >= self.minQuality:
                self.buy()
                self.bars_since_valley = 0


