import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrPeriod = 10
    factor = 3.0
    adxlen = 14
    dilen = 14
    adxThreshold = 25
    trailPerc = 1.5
    trailOffsetPerc = 0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Supertrend
        self.supertrend_result = self.I(self._calc_supertrend, high, low, close)
        
        # Calculate ADX
        self.adx_result = self.I(self._calc_adx, high, low, close)
        
        # Heikin Ashi calculations
        self.ha_close = self.I(self._calc_ha_close)
        self.ha_open = self.I(self._calc_ha_open)

    def _calc_supertrend(self, high, low, close):
        hl2 = (high + low) / 2
        atr = pta.atr(high, low, close, length=self.atrPeriod)
        if atr is None:
            return pd.Series(0, index=close.index)
        
        basic_ub = hl2 + self.factor * atr
        basic_lb = hl2 - self.factor * atr
        
        final_ub = pd.Series(index=close.index, dtype=float)
        final_lb = pd.Series(index=close.index, dtype=float)
        
        for i in range(len(close)):
            if i == 0:
                final_ub.iloc[i] = basic_ub.iloc[i]
                final_lb.iloc[i] = basic_lb.iloc[i]
            else:
                final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
        
        supertrend = pd.Series(index=close.index, dtype=float)
        direction = pd.Series(index=close.index, dtype=int)
        
        for i in range(len(close)):
            if i == 0:
                supertrend.iloc[i] = final_ub.iloc[i]
                direction.iloc[i] = -1
            else:
                if supertrend.iloc[i-1] == final_ub.iloc[i-1]:
                    if close.iloc[i] <= final_ub.iloc[i]:
                        supertrend.iloc[i] = final_ub.iloc[i]
                        direction.iloc[i] = -1
                    else:
                        supertrend.iloc[i] = final_lb.iloc[i]
                        direction.iloc[i] = 1
                else:
                    if close.iloc[i] >= final_lb.iloc[i]:
                        supertrend.iloc[i] = final_lb.iloc[i]
                        direction.iloc[i] = 1
                    else:
                        supertrend.iloc[i] = final_ub.iloc[i]
                        direction.iloc[i] = -1
        
        self.direction = direction
        return supertrend

    def _calc_adx(self, high, low, close):
        up = high.diff()
        down = -low.diff()
        
        plus_dm = pd.Series(0.0, index=close.index)
        minus_dm = pd.Series(0.0, index=close.index)
        
        for i in range(len(close)):
            if pd.isna(up.iloc[i]) or pd.isna(down.iloc[i]):
                continue
            if up.iloc[i] > down.iloc[i] and up.iloc[i] > 0:
                plus_dm.iloc[i] = up.iloc[i]
            if down.iloc[i] > up.iloc[i] and down.iloc[i] > 0:
                minus_dm.iloc[i] = down.iloc[i]
        
        atr = pta.atr(high, low, close, length=self.dilen)
        if atr is None:
            return pd.Series(50, index=close.index)
        
        plus_di = 100 * plus_dm.ewm(span=self.dilen).mean() / atr
        minus_di = 100 * minus_dm.ewm(span=self.dilen).mean() / atr
        
        di_sum = plus_di + minus_di
        di_diff = (plus_di - minus_di).abs()
        
        adx = 100 * (di_diff / di_sum.replace(0, 1)).ewm(span=self.adxlen).mean()
        adx = adx.fillna(50)
        
        return adx

    def _calc_ha_close(self):
        close = pd.Series(self.data.Close)
        open_price = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        ha_close = (open_price + high + low + close) / 4
        return ha_close

    def _calc_ha_open(self):
        close = pd.Series(self.data.Close)
        open_price = pd.Series(self.data.Open)
        
        ha_open = pd.Series(index=close.index, dtype=float)
        ha_open.iloc[0] = (open_price.iloc[0] + close.iloc[0]) / 2
        
        for i in range(1, len(close)):
            ha_open.iloc[i] = (ha_open.iloc[i-1] + (open_price.iloc[i] + close.iloc[i]) / 2) / 2
        
        return ha_open

    def next(self):
        if len(self.data) < max(self.atrPeriod, self.adxlen, self.dilen) + 5:
            return
        
        close = self.data.Close[-1]
        adx_val = self.adx_result[-1]
        direction_val = self.direction.iloc[-1]
        ha_close = self.ha_close[-1]
        ha_open = self.ha_open[-1]
        
        is_trending = adx_val > self.adxThreshold
        bullish_trend = direction_val < 0
        bearish_trend = direction_val > 0
        ha_bullish = ha_close > ha_open
        ha_bearish = ha_close < ha_open
        
        long_condition = bullish_trend and is_trending and ha_bullish
        short_condition = bearish_trend and is_trending and ha_bearish
        
        if long_condition and not self.position:
            self.buy()
        
        if short_condition and self.position.is_long:
            self.position.close()
        
        if self.position.is_long:
            trail_ticks = (close * (self.trailPerc / 100))
            trail_offset = (close * (self.trailOffsetPerc / 100))
            
            highest_close = max(self.data.Close[-min(len(self.data), 100):])
            stop_price = highest_close - trail_ticks - trail_offset
            
            if close <= stop_price:
                self.position.close()
        
        if self.position.is_short:
            trail_ticks = (close * (self.trailPerc / 100))
            trail_offset = (close * (self.trailOffsetPerc / 100))
            
            lowest_close = min(self.data.Close[-min(len(self.data), 100):])
            stop_price = lowest_close + trail_ticks + trail_offset
            
            if close >= stop_price:
                self.position.close()


