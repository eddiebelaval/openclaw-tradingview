import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI on the current timeframe (1-hour equivalent for backtest)
        self.rsi = self.I(pta.rsi, close, length=self.length)

    def next(self):
        # Buy when RSI crosses above 30 (oversold + turning up)
        if crossover(self.rsi, 30):
            self.buy()
        # Sell when RSI crosses above 70 (overbought)
        elif crossover(70, self.rsi):
            self.sell()