import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Ribbon parameters
    ema1_len = 8
    ema2_len = 13
    ema3_len = 21
    ema4_len = 34
    ema5_len = 55
    ema6_len = 89
    ema7_len = 144
    ema8_len = 200
    
    # Signal Engine parameters
    atr_len = 14
    rsi_len = 14
    lookback = 20
    cooldown = 10
    rsi_ob = 70
    rsi_os = 30

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA calculations
        self.ema1 = self.I(pta.ema, close, length=self.ema1_len)
        self.ema2 = self.I(pta.ema, close, length=self.ema2_len)
        self.ema3 = self.I(pta.ema, close, length=self.ema3_len)
        self.ema4 = self.I(pta.ema, close, length=self.ema4_len)
        self.ema5 = self.I(pta.ema, close, length=self.ema5_len)
        self.ema6 = self.I(pta.ema, close, length=self.ema6_len)
        self.ema7 = self.I(pta.ema, close, length=self.ema7_len)
        self.ema8 = self.I(pta.ema, close, length=self.ema8_len)
        
        # RSI and ATR
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Highest and lowest for channel detection
        self.highest_hi = self.I(lambda x: x.rolling(window=self.lookback * 2).max(), high)
        self.lowest_lo = self.I(lambda x: x.rolling(window=self.lookback * 2).min(), low)
        
        # Pivot detection using rolling max/min
        self.pivot_high = self.I(lambda x: x.rolling(window=self.lookback).max(), high)
        self.pivot_low = self.I(lambda x: x.rolling(window=self.lookback).min(), low)
        
        # Track last signals for cooldown
        self.bars_since_buy = self.cooldown + 1
        self.bars_since_sell = self.cooldown + 1

    def next(self):
        # Update cooldown counters
        self.bars_since_buy += 1
        self.bars_since_sell += 1
        
        # Check if we have enough data
        if len(self.data) < max(self.ema8_len, self.lookback * 2) + 5:
            return
        
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        close_prev = self.data.Close[-2] if len(self.data) > 1 else close
        open_prev = self.data.Open[-2] if len(self.data) > 1 else open_price
        
        # Get current indicator values
        ema1_val = self.ema1[-1]
        ema2_val = self.ema2[-1]
        ema3_val = self.ema3[-1]
        ema4_val = self.ema4[-1]
        ema5_val = self.ema5[-1]
        ema8_val = self.ema8[-1]
        rsi_val = self.rsi[-1]
        atr_val = self.atr[-1]
        
        highest_val = self.highest_hi[-1]
        lowest_val = self.lowest_lo[-1]
        
        # Trend Detection
        ribbon_bull = ema1_val > ema2_val and ema2_val > ema3_val and ema3_val > ema4_val and ema4_val > ema5_val
        ribbon_bear = ema1_val < ema2_val and ema2_val < ema3_val and ema3_val < ema4_val and ema4_val < ema5_val
        
        trend_bull = ema5_val > ema8_val
        trend_bear = ema5_val < ema8_val
        
        # EMA slopes
        ema1_3bars_ago = self.ema1[-4] if len(self.ema1) > 3 else ema1_val
        ema5_3bars_ago = self.ema5[-4] if len(self.ema5) > 3 else ema5_val
