import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lotSize = 25
    numLots = 2
    atrMult = 4.0
    rrRatio = 2.5
    emaFast = 50
    emaSlow = 200
    adxThreshold = 20
    useDailyFilter = True
    stochLen = 14
    stochLevel = 20
    useTrailing = True
    trailActivPc = 2.0
    trailOffsetPc = 1.2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Fast and Slow EMAs
        self.fEma = self.I(pta.ema, close, length=self.emaFast)
        self.sEma = self.I(pta.ema, close, length=self.emaSlow)
        
        # ADX for trend strength
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = self.I(lambda: adx_result['ADX_14'] if adx_result is not None else pd.Series(0, index=close.index))
        
        # RSI and Stochastic RSI
        rsi_vals = self.I(pta.rsi, close, length=self.stochLen)
        
        # Stochastic of RSI
        stoch_result = self.I(lambda: pta.stoch(rsi_vals, rsi_vals, rsi_vals, k=self.stochLen, d=3, smooth_k=3))
        self.stochK = self.I(lambda: stoch_result['STOCHk_14_3_3'] if stoch_result is not None else pd.Series(50, index=close.index))
        self.stochD = self.I(lambda: stoch_result['STOCHd_14_3_3'] if stoch_result is not None else pd.Series(50, index=close.index))
        
        # ATR for stop loss calculation
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Daily EMA filter (using current close as proxy for daily filter)
        self.dailyEma = self.I(pta.ema, close, length=50)
        
        # Track active distance and entry price
        self.activeDist = None
        self.entryPrice = None

    def next(self):
        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        
        # Check trend conditions
        fEma_val = self.fEma[-1]
        sEma_val = self.sEma[-1]
        adx_val = self.adx[-1]
        stochK_val = self.stochK[-1]
        stochD_val = self.stochD[-1]
        atr_val = self.atr[-1]
        dailyEma_val = self.dailyEma[-1]
        
        # Trend signals
        dailyBull = close_price > dailyEma_val
        dailyBear = close_price < dailyEma_val
        
        trendBull = fEma_val > sEma_val and adx_val > self.adxThreshold and (not self.useDailyFilter or dailyBull)
        trendBear = fEma_val < sEma_val and adx_val > self.adxThreshold and (not self.useDailyFilter or dailyBear)
        
        # Stochastic crossovers
        stochCrossOver = crossover(self.stochK, self.stochD)
        stochCrossUnder = crossover(self.stochD, self.stochK)
        
        # Entry signals
        longSignal = trendBull and stochCrossOver and stochK_val < self.stochLevel
        shortSignal = trendBear and stochCrossUnder and stochK_val > (100 - self.stochLevel)
        
        tradeQty = self.lotSize * self.numLots
        
        # Entry Logic
        if longSignal and not self.position:
            self.activeDist = atr_val * self.atrMult
            self.entryPrice = close_price
            self.buy(size=tradeQty)
        
        if shortSignal and not self.position:
            self.activeDist = atr_val * self.atrMult
            self.entryPrice = close_price
            self.sell(size=tradeQty)
        
        # Exit Logic
        if self.position:
            entry = self.position.open_price
            
            if self.position.is_long:
                slPrice = entry - self.activeDist
                tpPrice = entry + (self.activeDist * self.rrRatio)
                
                # Simple exit on SL or TP
                if close_price <= slPrice:
                    self.sell(size=abs(self.position.size))
                elif close_price >= tpPrice:
                    self.sell(size=abs(self.position.size))
            
            else:  # short position
                slPrice = entry + self.activeDist
                tpPrice = entry - (self.activeDist * self.rrRatio)
                
                # Simple exit on SL or TP
                if close_price >= slPrice:
                    self.buy(size=abs(self.position.size))
                elif close_price <= tpPrice:
                    self.buy(size=abs(self.position.size))


