import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    volLen = 20
    smoothLen = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate RSI
        self.rsi_val = self.I(pta.rsi, close, length=self.rsiLen)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.volLen)
        
        # Calculate average ATR (SMA of ATR)
        def avg_atr_calc():
            atr_series = pta.atr(high, low, close, length=self.volLen)
            if atr_series is None:
                return pd.Series(0, index=close.index)
            return pta.sma(atr_series, length=self.volLen * 2)
        
        self.avg_atr = self.I(avg_atr_calc)
        
        # Calculate volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=self.volLen)
        
        # Calculate sentiment score with adjustments
        def sentiment_calc():
            sentiment_raw = self.rsi_val.copy() if hasattr(self.rsi_val, 'copy') else pd.Series(self.rsi_val)
            
            # Adjustment for high volatility with downward price
            for i in range(len(close)):
                if i > 0:
                    curr_atr = self.atr.iloc[i] if hasattr(self.atr, 'iloc') else self.atr[i]
                    curr_avg_atr = self.avg_atr.iloc[i] if hasattr(self.avg_atr, 'iloc') else self.avg_atr[i]
                    
                    if close.iloc[i] < close.iloc[i-1] and curr_atr > curr_avg_atr:
                        adjustment = (curr_atr / max(curr_avg_atr, 1)) * 5
                        sentiment_raw.iloc[i] = sentiment_raw.iloc[i] - adjustment
            
            # Adjustment for high volume with upward price
            for i in range(len(close)):
                if i > 0:
                    curr_vol = volume.iloc[i] if hasattr(volume, 'iloc') else volume[i]
                    curr_vol_sma = self.vol_sma.iloc[i] if hasattr(self.vol_sma, 'iloc') else self.vol_sma[i]
                    
                    if close.iloc[i] > close.iloc[i-1] and curr_vol > (curr_vol_sma * 1.2):
                        adjustment = (curr_vol / max(curr_vol_sma, 1)) * 2
                        sentiment_raw.iloc[i] = sentiment_raw.iloc[i] + adjustment
            
            # Clamp values between 0 and 100
            sentiment_raw = sentiment_raw.clip(lower=0, upper=100)
            
            return sentiment_raw
        
        self.sentiment_raw = self.I(sentiment_calc)
        
        # Calculate final smoothed score
        def final_score_calc():
            smoothed = pta.ema(self.sentiment_raw, length=self.smoothLen)
            if smoothed is None:
                return pd.Series(50, index=close.index)
            return smoothed
        
        self.final_score = self.I(final_score_calc)

    def next(self):
        if len(self.data) < max(self.rsiLen, self.volLen, self.smoothLen) + 5:
            return
        
        current_score = self.final_score[-1]
        
        # Buy signal: extreme fear or transition from fear to neutral
        if current_score < 30:
            if not self.position:
                self.buy()
        
        # Sell signal: extreme greed
        if current_score > 70:
            if self.position:
                self.sell()
        
        # Exit from fear zone if score recovers
        if self.position and current_score > 50:
            self.sell()