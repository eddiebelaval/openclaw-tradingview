import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters
    hurst_len = 100
    channel_len = 20
    mult_base = 2.0
    smoothing = 5
    trend_thresh = 0.55
    revert_thresh = 0.45
    cooldown = 5

    def init(self):
        # Prepare data
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate log returns for R/S analysis
        log_returns = np.log(close / close.shift(1)).fillna(0)
        
        # Hurst exponent calculation using R/S analysis
        def calc_rs(src_series, total_len, n):
            """Calculate average R/S for non-overlapping subseries"""
            sum_rs = 0.0
            count = 0
            num_subs = int(np.floor(total_len / n))
            
            for s in range(num_subs):
                start_idx = s * n
                if start_idx + n > len(src_series):
                    break
                    
                subseries = src_series.iloc[start_idx:start_idx + n]
                mean = subseries.mean()
                
                cum_dev = (subseries - mean).cumsum()
                r_val = cum_dev.max() - cum_dev.min()
                
                std_val = subseries.std(ddof=1) if len(subseries) > 1 else subseries.std()
                
                if std_val > 1e-10:
                    sum_rs += r_val / std_val
                    count += 1
            
            return sum_rs / count if count > 0 else 0.0
        
        def calc_hurst(src_series, total_len):
            """Calculate Hurst exponent from R/S analysis"""
            n1 = max(int(np.floor(total_len / 2)), 8)
            n2 = max(int(np.floor(total_len / 4)), 6)
            n3 = max(int(np.floor(total_len / 6)), 5)
            n4 = max(int(np.floor(total_len / 10)), 4)
            n5 = max(int(np.floor(total_len / 20)), 4)
            
            rs1 = calc_rs(src_series, total_len, n1)
            rs2 = calc_rs(src_series, total_len, n2)
            rs3 = calc_rs(src_series, total_len, n3)
            rs4 = calc_rs(src_series, total_len, n4)
            rs5 = calc_rs(src_series, total_len, n5)
            
            sum_x = 0.0
            sum_y = 0.0
            sum_xy = 0.0
            sum_x2 = 0.0
            pts = 0
            
            for rs_val, n_val in [(rs1, n1), (rs2, n2), (rs3, n3), (rs4, n4), (rs5, n5)]:
                if rs_val > 0:
                    lx = np.log(n_val)
                    ly = np.log(rs_val)
                    sum_x += lx
                    sum_y += ly
                    sum_xy += lx * ly
                    sum_x2 += lx * lx
                    pts += 1
            
            denom = pts * sum_x2 - sum_x * sum_x if pts > 0 else 0
            if denom != 0 and pts >= 3:
                h = (pts * sum_xy - sum_x * sum_y) / denom
            else:
                h = 0.5
            
            return np.clip(h, 0.01, 0.99)
        
        def hurst_series(src):
            """Calculate Hurst exponent for each bar"""
            hurst_vals = []
            for i in range(len(src)):
                if i < self.hurst_len:
                    hurst_vals.append(0.5)
                else:
                    h = calc_hurst(src.iloc[i-self.hurst_len:i], self.hurst_len)
                    hurst_vals.append(h)
            return pd.Series(hurst_vals, index=src.index)
        
        # Calculate raw Hurst
        raw_hurst = self.I(hurst_series, log_returns)
        
        # Smooth Hurst with EMA
        self.hurst = self.I(pta.ema, raw_hurst, length=self.smoothing)
        
        # Channel center line
        self.basis = self.I(pta.ema, close, length=self.channel_len)
        
        # Standard deviation
        self.dev = self.I(pta.stdev, close, length=self.channel_len)
        
        # Adaptive multiplier based on Hurst
        def calc_adaptive_mult(hurst_series):
            hurst_norm = np.clip(hurst_series - 0.5, -0.5, 0.5)
            return self.mult_base * np.power(2.0, hurst_norm)
        
        self.hurst_adaptive = self.I(calc_adaptive_mult, self.hurst)
        
        # Band width calculation
        def calc_band_width(basis_s, dev_s, adaptive_s):
            min_band = basis_s * 0.001
            raw_width = np.maximum(adaptive_s * dev_s, min_band)
            return raw_width
        
        self.band_width = self.I(calc_band_width, self.basis, self.dev, self.hurst_adaptive)
        
        # Upper and lower bands
        self.upper = self.I(lambda: self.basis + self.band_width)
        self.lower = self.I(lambda: self.basis - self.band_width)
        
        # Regime detection
        self.is_trending = self.I(lambda: self.hurst > self.trend_thresh)
        self.is_reverting = self.I(lambda: self.hurst < self.revert_thresh)
        
        # Signal detection
        self.to_trend = self.I(lambda: crossover(self.hurst, self.trend_thresh))
        self.to_revert = self.I(lambda: crossover(self.revert_thresh, self.hurst))
        
        self.trend_break_up = self.I(lambda: self.is_trending and crossover(close, self.upper))
        self.trend_break_down = self.I(lambda: self.is_trending and crossover(self.lower, close))
        
        # Counters for cooldown
        self.bars_since_upper = 999
        self.bars_since_lower = 999

    def next(self):
        # Update cooldown counters
        self.bars_since_upper += 1
        self.bars_since_lower += 1
        
        # Band touch detection with cooldown
        touch_upper_raw = (self.is_reverting[-1] and 
                          self.data.High[-1] >= self.upper[-1] and 
                          self.bars_since_upper >= self.cooldown)
        touch_lower_raw = (self.is_reverting[-1] and 
                          self.data.Low[-1] <= self.lower[-1] and 
                          self.bars_since_lower >= self.cooldown)
        
        # Prioritize: don't fire both in same bar
        touch_upper = touch_upper_raw and not touch_lower_raw
        touch_lower = touch_lower_raw and not touch_upper_raw
        
        if touch_upper:
            self.bars_since_upper = 0
        if touch_lower:
            self.bars_since_lower = 0
        
        # Confluence signals
        confluence_long = (self.to_revert[-1] and 
                          self.data.Low[-1] <= self.lower[-1])
        confluence_short = (self.to_revert[-1] and 
                           self.data.High[-1] >= self.upper[-1])
        confluence_trend_up = (self.to_trend[-1] and 
                              self.data.Close[-1] > self.upper[-1])
        confluence_trend_down = (self.to_trend[-1] and 
                                self.data.Close[-1] < self.lower[-1])
        
        # Trading logic
        # Long entries
        if touch_lower or confluence_long:
            if not self.position:
                self.buy()
        
        # Short entries
        if touch_upper or confluence_short:
            if self.position:
                self.sell()
        
        # Trend continuation entries
        if self.trend_break_up[-1] or confluence_trend_up:
            if not self.position:
                self.buy()
        
        if self.trend_break_down[-1] or confluence_trend_down:
            if self.position:
                self.sell()
        
        # Exit logic - simple reversal at opposite band
        if self.position:
            if self.position.is_long and self.data.High[-1] >= self.upper[-1]:
                self.sell()
            elif self.position.is_short and self.data.Low[-1] <= self.lower[-1]:
                self.buy()


