import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Initialize data series
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_price = pd.Series(self.data.Open)
        
        # Delta estimation using candle anatomy
        def calc_delta():
            deltas = []
            for i in range(len(close)):
                rng = high.iloc[i] - low.iloc[i]
                if rng == 0:
                    deltas.append(0.0)
                else:
                    body = abs(close.iloc[i] - open_price.iloc[i])
                    body_pct = body / rng
                    upper_wick = high.iloc[i] - max(open_price.iloc[i], close.iloc[i])
                    lower_wick = min(open_price.iloc[i], close.iloc[i]) - low.iloc[i]
                    
                    is_green = close.iloc[i] >= open_price.iloc[i]
                    
                    if is_green:
                        buy_pct = 0.5 + (body_pct * 0.3) + (lower_wick / rng * 0.1) - (upper_wick / rng * 0.1)
                        buy_pct = max(0.2, min(0.85, buy_pct))
                        bv = volume.iloc[i] * buy_pct
                        sv = volume.iloc[i] - bv
                    else:
                        sell_pct = 0.5 + (body_pct * 0.3) + (upper_wick / rng * 0.1) - (lower_wick / rng * 0.1)
                        sell_pct = max(0.2, min(0.85, sell_pct))
                        sv = volume.iloc[i] * sell_pct
                        bv = volume.iloc[i] - sv
                    
                    delta = bv - sv
                    deltas.append(delta)
            
            return pd.Series(deltas, index=close.index)
        
        raw_delta = self.I(calc_delta)
        
        # Smooth delta
        def smooth_delta():
            delta_series = calc_delta()
            return pta.sma(delta_series, length=1)
        
        self.delta = self.I(smooth_delta)
        
        # Cumulative delta
        def calc_cum_delta():
            delta_series = calc_delta()
            cum = delta_series.cumsum()
            return cum
        
        self.cum_delta = self.I(calc_cum_delta)
        
        # Cumulative delta SMA
        def calc_cum_delta_sma():
            delta_series = calc_delta()
            cum = delta_series.cumsum()
            return pta.sma(cum, length=20)
        
        self.cum_delta_sma = self.I(calc_cum_delta_sma)
        
        # Volume average
        self.vol_avg = self.I(pta.sma, volume, length=20)
        
        # Body percentage
        def calc_body_pct():
            rng = high - low
            body = (close - open_price).abs()
            body_pct = np.where(rng > 0, (body / rng * 100), 50)
            return pd.Series(body_pct, index=close.index)
        
        self.body_pct = self.I(calc_body_pct)
        
        # Absorption detection
        def calc_absorption():
            absorptions = []
            for i in range(len(close)):
                vol_avg_val = self.vol_avg[i] if i < len(self.vol_avg) and self.vol_avg[i] else volume.iloc[i]
                is_abs = volume.iloc[i] > vol_avg_val * 2.0 and self.body_pct[i] < 30.0
                absorptions.append(is_abs)
            return pd.Series(absorptions, index=close.index)
        
        self.is_absorption = self.I(calc_absorption)
        
        # Imbalance ratio
        def calc_imbal():
            imbal_ratios = []
            for i in range(len(close)):
                rng = high.iloc[i] - low.iloc[i]
                if rng == 0:
                    imbal_ratios.append(1.0)
                else:
                    body = abs(close.iloc[i] - open_price.iloc[i])
                    body_pct = body / rng
                    upper_wick = high.iloc[i] - max(open_price.iloc[i], close.iloc[i])
                    lower_wick = min(open_price.iloc[i], close.iloc[i]) - low.iloc[i]
                    
                    is_green = close.iloc[i] >= open_price.iloc[i]
                    
                    if is_green:
                        buy_pct = 0.5 + (body_pct * 0.3) + (lower_wick / rng * 0.1) - (upper_wick / rng * 0.1)
                        buy_pct = max(0.2, min(0.85, buy_pct))
                        bv = volume.iloc[i] * buy_pct
                        sv = volume.iloc[i] - bv
                    else:
                        sell_pct = 0.5 + (body_pct * 0.3) + (upper_wick / rng * 0.1) - (lower_wick / rng * 0.1)
                        sell_pct = max(0.2, min(0.85, sell_pct))
                        sv = volume.iloc[i] * sell_pct
                        bv = volume.iloc[i] - sv
                    
                    ratio = bv / sv if sv > 0 else (999.0 if bv > 0 else 1.0)
                    imbal_ratios.append(ratio)
            
            return pd.Series(imbal_ratios, index=close.index)
        
        self.imbal_ratio = self.I(calc_imbal)
        
        # Buy/Sell imbalance detection
        def calc_buy_imbal():
            return self.imbal_ratio >= 2.0
        
        def calc_sell_imbal():
            return self.imbal_ratio <= (1.0 / 2.0)
        
        self.is_buy_imbal = self.I(calc_buy_imbal)
        self.is_sell_imbal = self.I(calc_sell_imbal)
        
        # Highest and lowest
        def calc_highest():
            return pd.Series(high).rolling(10).max()
        
        def calc_lowest():
            return pd.Series(low).rolling(10).min()
        
        self.highest_10 = self.I(calc_highest)
        self.lowest_10 = self.I(calc_lowest)
        
        # Divergence detection
        def calc_delta_sma():
            delta_series = calc_delta()
            return pta.sma(delta_series, length=10)
        
        self.delta_sma = self.I(calc_delta_sma)
        
        # Price divergence
        def calc_bear_diverg():
            divergences = []
            for i in range(10, len(close)):
                price_hh = high.iloc[i] > self.highest_10.iloc[i-1]
                delta_declining = self.delta_sma.iloc[i] < self.delta_sma.iloc[i-10]
                divergences.append(price_hh and delta_declining)
            
            # Pad with False for early bars
            return pd.Series([False]*10 + divergences, index=close.index)
        
        self.bear_diverg = self.I(calc_bear_diverg)
        
        def calc_bull_diverg():
            divergences = []
            for i in range(10, len(close)):
                price_ll = low.iloc[i] < self.lowest_10.iloc[i-1]
                delta_rising = self.delta_sma.iloc[i] > self.delta_sma.iloc[i-10]
                divergences.append(price_ll and delta_rising)
            
            # Pad with False for early bars
            return pd.Series([False]*10 + divergences, index=close.index)
        
        self.bull_diverg = self.I(calc_bull_diverg)
        
        # Exhaustion detection
        def calc_exhaustion():
            delta_series = calc_delta()
            delta_avg = pta.sma(delta_series, length=14)
            delta_std = delta_series.rolling(14).std()
            
            buy_exh = delta_series > (delta_avg + delta_std * 2.5)
            sell_exh = delta_series < (delta_avg - delta_std * 2.5)
            
            return buy_exh, sell_exh
        
        def get_buy_exhaust():
            buy_exh, _ = calc_exhaustion()
            return buy_exh
        
        def get_sell_exhaust():
            _, sell_exh = calc_exhaustion()
            return sell_exh
        
        self.buy_exhaustion = self.I(get_buy_exhaust)
        self.sell_exhaustion = self.I(get_sell_exhaust)
        
        # Absorption bull/bear
        def calc_absorb_bull():
            absorb_bulls = []
            for i in range(len(close)):
                vol_avg_val = self.vol_avg[i] if i < len(self.vol_avg) and self.vol_avg[i] else volume.iloc[i]
                is_abs = volume.iloc[i] > vol_avg_val * 2.0 and self.body_pct[i] < 30.0
                is_green = close.iloc[i] >= open_price.iloc[i]
                absorb_bulls.append(is_abs and is_green)
            return pd.Series(absorb_bulls, index=close.index)
        
        def calc_absorb_bear():
            absorb_bears = []
            for i in range(len(close)):
                vol_avg_val = self.vol_avg[i] if i < len(self.vol_avg) and self.vol_avg[i] else volume.iloc[i]
                is_abs = volume.iloc[i] > vol_avg_val * 2.0 and self.body_pct[i] < 30.0
                is_green = close.iloc[i] >= open_price.iloc[i]
                absorb_bears.append(is_abs and not is_green)
            return pd.Series(absorb_bears, index=close.index)
        
        self.absorb_bull = self.I(calc_absorb_bull)
        self.absorb_bear = self.I(calc_absorb_bear)

    def next(self):
        # Trading logic based on order flow signals
        
        # Buy signals: stacked buy imbalances, bull divergence, bullish absorption
        if len(self.data) > 3:
            recent_buy_imbal = sum(1 for i in range(1, 4) if self.is_buy_imbal[-i])
            
            if recent_buy_imbal >= 2 and not self.position:
                self.buy()
            elif self.bull_diverg[-1] and not self.position:
                self.buy()
            elif self.absorb_bull[-1] and not self.position:
                self.buy()
        
        # Sell signals: stacked sell imbalances, bear divergence, bearish absorption
        if len(self.data) > 3:
            recent_sell_imbal = sum(1 for i in range(1, 4) if self.is_sell_imbal[-i])
            
            if recent_sell_imbal >= 2 and self.position:
                self.sell()
            elif self.bear_diverg[-1] and self.position:
                self.sell()
            elif self.absorb_bear[-1] and self.position:
                self.sell()
        
        # Exit on exhaustion signals
        if self.sell_exhaustion[-1] and self.position:
            self.sell()
        elif self.buy_exhaustion[-1] and self.position:
            self.sell()
        
        # Exit if delta reverses significantly
        if len(self.delta) > 1:
            if self.position and self.delta[-1] < 0 and self.delta[-2] > 0:
                self.sell()


