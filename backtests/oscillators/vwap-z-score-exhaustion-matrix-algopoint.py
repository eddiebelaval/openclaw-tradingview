import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters from the Pine Script
    length = 50
    z_threshold = 2.5
    vol_len = 20
    use_delta = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate typical price (hlc3)
        typical_price = (high + low + close) / 3
        
        # Calculate rolling VWAP
        self.rolling_vwap = self.I(pta.vwma, typical_price, volume, length=self.length)
        
        # Calculate volume-weighted standard deviation
        def calc_vw_stdev(typical_price, vwap, volume, length):
            sq_diff = (typical_price - vwap) ** 2 * volume
            sum_sq_diff = sq_diff.rolling(window=length).sum()
            sum_vol = volume.rolling(window=length).sum()
            vw_variance = sum_sq_diff / sum_vol.replace(0, np.nan)
            vw_stdev = np.sqrt(vw_variance)
            return vw_stdev
        
        self.vw_stdev = self.I(calc_vw_stdev, typical_price, self.rolling_vwap, volume, self.length)
        
        # Calculate Z-Score
        def calc_z_score(typical_price, vwap, vw_stdev):
            z_score = (typical_price - vwap) / vw_stdev.replace(0, np.nan)
            return z_score.fillna(0)
        
        self.z_score = self.I(calc_z_score, typical_price, self.rolling_vwap, self.vw_stdev)
        
        # Calculate average volume
        self.avg_vol = self.I(pta.sma, volume, length=self.vol_len)
        
        # Volume exhaustion check
        def calc_is_exhausted(volume, avg_vol):
            return volume < avg_vol
        
        self.is_exhausted = self.I(calc_is_exhausted, volume, self.avg_vol)
        
        # Calculate order flow delta proxy
        def calc_vol_delta(high, low, close, open_price, volume):
            bar_range = high - low
            buy_pressure = close - low
            sell_pressure = high - close
            
            # Avoid division by zero
            up_vol = np.where(
                bar_range > 0,
                (buy_pressure / bar_range) * volume,
                np.where(close >= open_price, volume, 0)
            )
            dn_vol = np.where(
                bar_range > 0,
                (sell_pressure / bar_range) * volume,
                np.where(close < open_price, volume, 0)
            )
            vol_delta = up_vol - dn_vol
            return vol_delta
        
        open_price = pd.Series(self.data.Open)
        self.vol_delta = self.I(calc_vol_delta, high, low, close, open_price, volume)

    def next(self):
        # Get current values
        z_score = self.z_score[-1]
        is_exhausted = self.is_exhausted[-1]
        vol_delta = self.vol_delta[-1]
        
        # Check delta conditions
        delta_short_ok = (vol_delta < 0) if self.use_delta else True
        delta_long_ok = (vol_delta > 0) if self.use_delta else True
        
        # Signal conditions
        fade_long = (z_score <= -self.z_threshold) and is_exhausted and delta_long_ok
        fade_short = (z_score >= self.z_threshold) and is_exhausted and delta_short_ok
        
        # Trading logic
        if fade_long and not self.position:
            self.buy()
        elif fade_short and self.position:
            self.sell()


