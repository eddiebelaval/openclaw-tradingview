import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 5
    ma_fast_len = 50
    ma_slow_len = 200
    rsi_len = 14
    rsi_ob = 70
    rsi_os = 30
    div_lookback = 30
    vol_len = 20
    vol_z_thresh = 2.0
    fvg_min_pct = 0.5
    eqh_threshold = 0.3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.ma_fast = self.I(pta.sma, close, length=self.ma_fast_len)
        self.ma_slow = self.I(pta.sma, close, length=self.ma_slow_len)

        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)

        self.vol_ma = self.I(pta.sma, volume, length=self.vol_len)
        
        def vol_std_calc():
            result = pta.stdev(volume, length=self.vol_len)
            if result is not None:
                return result
            return pd.Series(0.0, index=volume.index)
        
        self.vol_std = self.I(vol_std_calc)

        def pivot_high_calc():
            return high.rolling(window=2 * self.pivot_len + 1, center=True).max()
        
        def pivot_low_calc():
            return low.rolling(window=2 * self.pivot_len + 1, center=True).min()

        self.pivot_high = self.I(pivot_high_calc)
        self.pivot_low = self.I(pivot_low_calc)

        self.price_above_fast = None
        self.price_above_slow = None
        self.trend = 0
        self.swing_high_1 = None
        self.swing_high_2 = None
        self.swing_low_1 = None
        self.swing_low_2 = None
        self.prev_price_low = None
        self.prev_rsi_low = None
        self.prev_price_low_bar = None
        self.prev_price_high = None
        self.prev_rsi_high = None
        self.prev_price_high_bar = None
        self.bull_div_active = False
        self.bear_div_active = False
        self.choch_bull = False
        self.choch_bear = False
        self.bos_bull = False
        self.bos_bear = False
        self.vol_spike = False
        self.vol_bull_spike = False
        self.vol_bear_spike = False
        self.conf_score = 0

    def next(self):
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]

        self.price_above_fast = close_val > self.ma_fast[-1]
        self.price_above_slow = close_val > self.ma_slow[-1]

        vol_ma_val = self.vol_ma[-1]
        vol_std_val = self.vol_std[-1]
        vol_z = (volume_val - vol_ma_val) / vol_std_val if vol_std_val != 0 else 0
        self.vol_spike = vol_z >= self.vol_z_thresh and volume_val > 0
        self.vol_bull_spike = self.vol_spike and close_val > open_val
        self.vol_bear_spike = self.vol_spike and close_val <= open_val

        self.choch_bull = False
        self.choch_bear = False
        self.bos_bull = False
        self.bos_bear = False
        self.bull_div_active = False
        self.bear_div_active = False

        if len(self.data) >= 2 * self.pivot_len + 1:
            if self.pivot_high[-1] == high_val:
                self.swing_high_2 = self.swing_high_1
                self.swing_high_1 = high_val

                if self.swing_high_2 is not None:
                    if high_val > self.swing_high_2:
                        if self.trend == -1:
                            self.choch_bull = True
                        else:
                            self.bos_bull = True
                        self.trend = 1
                    else:
                        if self.trend == 1:
                            self.choch_bear = True
                        self.trend = -1

            if self.pivot_low[-1] == low_val:
                self.swing_low_2 = self.swing_low_1
                self.swing_low_1 = low_val

                if self.swing_low_2 is not None:
                    if low_val > self.swing_low_2:
                        if self.trend == -1:
                            self.choch_bull = True
                        self.trend = 1
                    else:
                        if self.trend == 1:
                            self.choch_bear = True
                        else:
                            self.bos_bear = True
                        self.trend = -1

        self.conf_score = 0
        if self.price_above_fast:
            self.conf_score += 1
        else:
            self.conf_score -= 1

        if self.price_above_slow:
            self.conf_score += 1
        else:
            self.conf_score -= 1

        if self.trend == 1:
            self.conf_score += 1
        elif self.trend == -1:
            self.conf_score -= 1

        if self.rsi[-1] < self.rsi_os:
            self.conf_score += 1
        elif self.rsi[-1] > self.rsi_ob:
            self.conf_score -= 1

        if self.vol_bull_spike:
            self.conf_score += 1
        elif self.vol_bear_spike:
            self.conf_score -= 1

        entry_signal = (
            (crossover(self.ma_fast, self.ma_slow) or self.choch_bull) and 
            self.conf_score >= 2
        )
        exit_signal = (
            (crossover(self.ma_slow, self.ma_fast) or self.choch_bear) or
            self.conf_score <= -2
        )

        if entry_signal and not self.position:
            self.buy()
        elif exit_signal and self.position:
            self.sell()