import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        
        # HMA Breakout Intraday Trend Filter
        self.hma1 = self.I(lambda: pta.hma(close, length=20) or pd.Series(np.nan, index=close.index))
        self.hma2 = self.I(lambda: pta.hma(close, length=50) or pd.Series(np.nan, index=close.index))
        self.hma3 = self.I(lambda: pta.hma(close, length=100) or pd.Series(np.nan, index=close.index))
        
        # PMO (Price Momentum Oscillator) - Manual calculation
        # PMO = EMA(fast) of ROC - EMA(slow) of ROC
        # Signal = EMA of PMO
        def calc_pmo():
            roc = close.pct_change(1) * 100
            ema_fast = pta.ema(roc, length=10)
            ema_slow = pta.ema(roc, length=10)
            pmo_vals = ema_fast - ema_slow
            pmo_signal = pta.ema(pmo_vals, length=6)
            return pmo_vals if pmo_vals is not None else pd.Series(0, index=close.index)
        
        self.pmo = self.I(calc_pmo)
        
        # 60-Point Signal indicators
        self.ma_60 = self.I(pta.sma, close, length=50)
        self.atr_60 = self.I(pta.atr, high, low, close, length=200)
        
        # Volume comparison
        self.vol_ratio = self.I(lambda: (volume > volume.shift(1)).astype(float))

    def next(self):
        if len(self.data) < 100:
            return
        
        # HMA Trend Detection
        is_long_trend = False
        is_short_trend = False
        
        if (self.hma3[-1] < self.hma2[-1] and 
            self.hma3[-1] < self.hma1[-1] and 
            self.hma1[-1] > self.hma2[-1]):
            is_long_trend = True
        elif (self.hma3[-1] > self.hma2[-1] and 
              self.hma3[-1] > self.hma1[-1] and 
              self.hma2[-1] > self.hma1[-1]):
            is_short_trend = True
        
        # 60-Point Signal Calculation
        range_atr = self.atr_60[-1] * 1.1
        
        if range_atr > 0:
            big_move_up = ((self.data.Close[-1] - self.data.Open[-1]) / range_atr * 100) >= 62.0
            big_move_dn = ((self.data.Open[-1] - self.data.Close[-1]) / range_atr * 100) >= 62.0
        else:
            big_move_up = False
            big_move_dn = False
        
        # Volume Filter
        vol_up = self.vol_ratio[-1] > 0
        
        # Long Condition
        long_condition = (is_long_trend and 
                         self.pmo[-1] > 0 and 
                         big_move_up and 
                         vol_up)
        
        # Short Condition
        short_condition = (is_short_trend and 
                          self.pmo[-1] < 0 and 
                          big_move_dn and 
                          vol_up)
        
        # Entry Logic
        if long_condition and not self.position:
            self.buy()
        elif short_condition and self.position:
            self.position.close()


