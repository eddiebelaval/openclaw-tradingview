        if self.lastSessionDate is None or currentDate != self.lastSessionDate:
            self.orbHigh = self.data.High[-1]
            self.orbLow = self.data.Low[-1]
            self.orbCount = 1
            self.lastSessionDate = currentDate
        elif self.orbCount > 0 and self.orbCount < self.orbBars:
            self.orbHigh = max(self.orbHigh, self.data.High[-1])
            self.orbLow = min(self.orbLow, self.data.Low[-1])
            self.orbCount += 1
        
