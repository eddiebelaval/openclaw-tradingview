import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Input parameters
    fastSmaLen = 20
    medSmaLen = 50
    slowSmaLen = 200
    stochLen = 22
    slopeLen = 22
    slopeMethod = "LinReg"  # "Delta" or "LinReg"
    atrLen = 22
    stopAtrMult = 4.0
    tpAtrMult = 10.0
    UseTpPrice = False
    stochThresh = 30
    stochLookback = 3
    minHoldBars = 1
    trailActivateATR = 0.0
    atrRefMode = "Entry"  # "Entry", "Max(Entry,Current)", "Current"
    preventSameBarExit = True
    tradeRegime1 = True
    tradeRegime2 = True
    tradeRegime3 = False
    tradeRegime4 = False
    tradeRegime0 = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate SMAs
        self.fastSMA = self.I(pta.sma, close, length=self.fastSmaLen)
        self.medSMA = self.I(pta.sma, close, length=self.medSmaLen)
        self.slowSMA = self.I(pta.sma, close, length=self.slowSmaLen)

        # Calculate Stochastic
        stoch_result = self.I(lambda x_high, x_low, x_close: pta.stoch(x_high, x_low, x_close, k=self.stochLen, d=14, smooth_k=3) or pd.DataFrame(index=x_close.index), high, low, close)
        self.stochK = self.I(lambda: stoch_result['STOCHk_' + str(self.stochLen) + '_14_3'] if stoch_result is not None and 'STOCHk_' + str(self.stochLen) + '_14_3' in stoch_result.columns else pd.Series(50, index=close.index))

        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)

        # Linear regression for slope calculation
        def linreg_slope_up(src, length, method):
            if method == "Delta":
                return src - src.shift(length) > 0
            else:
                # LinReg slope: use change of linear regression
                lr = src.rolling(window=length).apply(lambda x: np.polyfit(np.arange(length), x, 1)[0] if len(x) == length else np.nan)
                return lr > 0

        def linreg_slope_dn(src, length, method):
            if method == "Delta":
                return src - src.shift(length) < 0
            else:
                lr = src.rolling(window=length).apply(lambda x: np.polyfit(np.arange(length), x, 1)[0] if len(x) == length else np.nan)
                return lr < 0

        # Slope indicators
        self.fastUp = self.I(lambda: linreg_slope_up(self.fastSMA, self.slopeLen, self.slopeMethod))
        self.fastDown = self.I(lambda: linreg_slope_dn(self.fastSMA, self.slopeLen, self.slopeMethod))
        self.medUp = self.I(lambda: linreg_slope_up(self.medSMA, self.slopeLen, self.slopeMethod))
        self.medDown = self.I(lambda: linreg_slope_dn(self.medSMA, self.slopeLen, self.slopeMethod))
        self.slowUp = self.I(lambda: linreg_slope_up(self.slowSMA, self.slopeLen, self.slopeMethod))
        self.slowDown = self.I(lambda: linreg_slope_dn(self.slowSMA, self.slopeLen, self.slopeMethod))

        # Pullback indicators
        self.stochWasBelow = self.I(lambda: self.stochK.rolling(self.stochLookback).min() < self.stochThresh)
        self.closeWasBelowFastSMA = self.I(lambda: (close - self.fastSMA).rolling(self.stochLookback).min() < 0)

        # Entry state tracking
        self.entry_price = None
        self.entry_atr = None
        self.entry_regime = 0
        self.entry_bar_idx = None
        self.hh_since_entry = None
        self.trail_stop = None
        self.trail_armed = False
        self.pullback_armed = False
        self.last_pullback = False

    def next(self):
        # Current values
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        fast_sma = self.fastSMA[-1]
        med_sma = self.medSMA[-1]
        slow_sma = self.slowSMA[-1]
        
        if np.isnan(fast_sma) or np.isnan(med_sma) or np.isnan(slow_sma):
            return

        # Regime detection
        fast_up = self.fastUp[-1] if not np.isnan(self.fastUp[-1]) else False
        fast_down = self.fastDown[-1] if not np.isnan(self.fastDown[-1]) else False
        med_up = self.medUp[-1] if not np.isnan(self.medUp[-1]) else False
        med_down = self.medDown[-1] if not np.isnan(self.medDown[-1]) else False
        slow_up = self.slowUp[-1] if not np.isnan(self.slowUp[-1]) else False
        slow_down = self.slowDown[-1] if not np.isnan(self.slowDown[-1]) else False

        regime1 = (med_sma > slow_sma) and med_up and slow_up and fast_up
        regime2a = (med_sma > slow_sma) and slow_down and med_up
        regime2b = fast_up and med_up and slow_up
        regime2c = (med_sma > slow_sma) and med_up and slow_up and fast_down
        regime2 = regime2a or regime2b or regime2c
        regime3 = (med_sma < slow_sma) and med_down and slow_down
        regime4 = (med_sma < slow_sma) and (slow_up or med_up)

        regime_id = 1 if regime1 else 2 if regime2 else 3 if regime3 else 4 if regime4 else 0

        trade_allowed = (
            (regime_id == 1 and self.tradeRegime1) or
            (regime_id == 2 and self.tradeRegime2) or
            (regime_id == 3 and self.tradeRegime3) or
            (regime_id == 4 and self.tradeRegime4) or
            (regime_id == 0 and self.tradeRegime0)
        )

        # Pullback detection
        stoch_below = self.stochWasBelow[-1] if not np.isnan(self.stochWasBelow[-1]) else False
        close_below_fast = self.closeWasBelowFastSMA[-1] if not np.isnan(self.closeWasBelowFastSMA[-1]) else False
        pullback = stoch_below or close_below_fast
        new_pullback = pullback and not self.last_pullback

        if new_pullback:
            self.pullback_armed = True

        self.last_pullback = pullback

        # Entry signal logic
        bullish_regime = trade_allowed

        # Find reference high (high of bar where lowest low occurred in lookback)
        ref_high = None
        if len(self.data) >= self.stochLookback:
            low_slice = self.data.Low[-self.stochLookback:-1]
            if len(low_slice) > 0:
                ll_idx = low_slice.argmin()
                ll_offset = len(low_slice) - 1 - ll_idx
                if ll_offset >= 0 and ll_offset < len(self.data):
                    ref_high = self.data.High[-(ll_offset + 2)]

        entry_signal_raw = (
            bullish_regime and pullback and
            (close > open_) and
            (ref_high is not None and close > ref_high)
        )
        entry_signal = entry_signal_raw and self.pullback_armed

        if entry_signal:
            self.pullback_armed = False
            if not self.position:
                self.buy()
                self.entry_price = close
                self.entry_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
                self.entry_regime = regime_id
                self.entry_bar_idx = len(self.data) - 1
                self.hh_since_entry = high
                self.trail_stop = self.entry_price - self.stopAtrMult * self.entry_atr
                self.trail_armed = (self.trailActivateATR <= 0)

        # Update highest high since entry
        if self.position:
            if self.hh_since_entry is None:
                self.hh_since_entry = high
            else:
                self.hh_since_entry = max(self.hh_since_entry, high)

            # Arm trailing after profit threshold
            if not self.trail_armed and self.entry_price is not None and self.entry_atr is not None:
                profit_threshold = self.entry_price + self.trailActivateATR * self.entry_atr
                self.trail_armed = self.hh_since_entry >= profit_threshold

            # Determine ATR reference for trailing stop
            atr_current = self.atr[-1] if not np.isnan(self.atr[-1]) else self.entry_atr
            if self.atrRefMode == "Entry":
                atr_ref = self.entry_atr
            elif self.atrRefMode == "Max(Entry,Current)":
                atr_ref = max(self.entry_atr, atr_current)
            else:  # "Current"
                atr_ref = atr_current

            # Calculate take profit price
            tp_price = None
            if self.UseTpPrice and self.entry_price is not None and self.entry_atr is not None:
                tp_price = self.entry_price + self.entry_atr * self.tpAtrMult

            # Update trailing stop
            if self.trail_armed and self.hh_since_entry is not None and atr_ref is not None:
                candidate_stop = self.hh_since_entry - self.stopAtrMult * atr_ref
                if self.trail_stop is None:
                    self.trail_stop = candidate_stop
                else:
                    self.trail_stop = max(self.trail_stop, candidate_stop)

            # Check exit conditions
            bars_since_entry = len(self.data) - 1 - self.entry_bar_idx if self.entry_bar_idx is not None else None
            exit_allowed = (
                (not self.preventSameBarExit or (bars_since_entry is not None and bars_since_entry >= 1)) and
                (bars_since_entry is None or bars_since_entry >= self.minHoldBars)
            )

            if exit_allowed:
                exit_price = None
                if self.trail_stop is not None and close <= self.trail_stop:
                    self.sell()
                elif tp_price is not None and close >= tp_price:
                    self.sell()
        else:
            # Reset when flat
            self.entry_price = None
            self.entry_atr = None
            self.entry_regime = 0
            self.entry_bar_idx = None
            self.hh_since_entry = None
            self.trail_stop = None
            self.trail_armed = False