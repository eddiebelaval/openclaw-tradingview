import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smaLength = 200
    apexPct = 0.3
    scoutPct = 0.2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate SMA
        self.vSMA = self.I(pta.sma, close, length=self.smaLength)
        
        # Calculate distance percentage from SMA
        self.currentDist = self.I(lambda: ((close - self.vSMA) / self.vSMA) * 100)
        
        # Calculate bands
        self.apexUpper = self.I(lambda: self.vSMA * (1 + (self.apexPct / 100)))
        self.apexLower = self.I(lambda: self.vSMA * (1 - (self.apexPct / 100)))
        self.scoutUpper = self.I(lambda: self.vSMA * (1 + (self.scoutPct / 100)))
        self.scoutLower = self.I(lambda: self.vSMA * (1 - (self.scoutPct / 100)))
        
        # Store high and low for crossover detection
        self.high = self.I(lambda: high)
        self.low = self.I(lambda: low)

    def next(self):
        # Check if price crosses above apex upper band (sell signal)
        if len(self.data) > 1:
            if self.high[-2] <= self.apexUpper[-2] and self.high[-1] > self.apexUpper[-1]:
                if not self.position:
                    self.sell()
        
        # Check if price crosses below apex lower band (buy signal)
        if len(self.data) > 1:
            if self.low[-2] >= self.apexLower[-2] and self.low[-1] < self.apexLower[-1]:
                if not self.position:
                    self.buy()
        
        # Exit conditions
        if self.position:
            if self.position.is_long:
                # Exit long if price crosses back above SMA or reaches upper bands
                if crossover(self.vSMA, self.data.Close):
                    self.position.close()
            elif self.position.is_short:
                # Exit short if price crosses back below SMA or reaches lower bands
                if crossover(self.data.Close, self.vSMA):
                    self.position.close()