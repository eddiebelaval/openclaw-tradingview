        current_pivot = self.pivot_low[-1]

        if not np.isnan(current_pivot):
            self.last_liq = current_pivot

        trend_ok = not self.use_trend_filter or (current_close > current_ema200)

        vol_ok = current_volume > (current_avg_vol * self.vol_mul)
        safe_zone = current_rsi < self.rsi_lim

        stock_ret = self.stock_ret[-1] if not np.isnan(self.stock_ret[-1]) else 0.0
        tasi_ret = 0.0
        rs_value = (stock_ret - tasi_ret) * 100.0

        is_strong = rs_value >= self.min_rs

