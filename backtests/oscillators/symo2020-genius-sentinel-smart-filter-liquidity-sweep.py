import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 14
    sl_mult = 1.5
    htf_pivot_len = 5
    sweep_atr_mult = 0.20
    confirm_bars = 15
    use_trend_filter = True
    use_reclaim = True
    use_break_high = True
    rsi_lim = 60
    vol_mul = 1.5
    rs_lookback = 5
    use_rs = True
    min_rs = 0.0
    use_vol = True
    use_rsi = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.rsi = self.I(pta.rsi, close, length=14)
        self.avg_vol = self.I(pta.sma, volume, length=20)
        
        self.ema200 = self.I(pta.ema, close, length=200)
        
        self.pivot_low = self.I(lambda: self._calc_pivot_low(low, self.htf_pivot_len))
        
        self.stock_ret = self.I(lambda: self._calc_stock_return(close))
        
        self.last_liq = np.nan
        self.got_sweep = False
        self.sweep_bar = -1

    def _calc_pivot_low(self, low_series, period):
        result = pd.Series(np.nan, index=low_series.index)
        for i in range(period, len(low_series) - period):
            window = low_series.iloc[i - period:i + period + 1]
            if low_series.iloc[i] == window.min():
                result.iloc[i] = low_series.iloc[i]
        return result

    def _calc_stock_return(self, close_series):
        result = pd.Series(0.0, index=close_series.index)
        for i in range(self.rs_lookback, len(close_series)):
            if close_series.iloc[i - self.rs_lookback] != 0:
                result.iloc[i] = (close_series.iloc[i] - close_series.iloc[i - self.rs_lookback]) / close_series.iloc[i - self.rs_lookback]
        return result

    def next(self):
        if len(self) < self.rs_lookback + 1:
            return

        current_close = self.data.Close[-1]
        current_low = self.data.Low[-1]
        current_high = self.data.High[-1]
        current_volume = self.data.Volume[-1]
        current_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
