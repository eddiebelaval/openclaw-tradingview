    def _detect_pivot_high(self, lookback):
        if len(self.data) < 2 * lookback + 1:
            return None
        
        high_series = self.data.High
        current_idx = len(high_series) - 1
        center_idx = current_idx - lookback
        
        if center_idx < lookback or center_idx + lookback >= len(high_series):
            return None
        
        center_high = high_series.iloc[center_idx]
        
        for i in range(center_idx - lookback, center_idx):
            if high_series.iloc[i] > center_high:
                return None
        
        for i in range(center_idx + 1, center_idx + lookback + 1):
            if high_series.iloc[i] > center_high:
                return None
        
        return center_high
    
