        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        pivot_high = self._detect_pivot_high(self.lookback)
        pivot_low = self._detect_pivot_low(self.lookback)
        
        if pivot_high is not None:
            self.ph_price_vals.append(pivot_high)
            self.ph_price_bars.append(current_bar - self.lookback)
            if len(self.ph_price_vals) > 10:
                self.ph_price_vals.pop(0)
                self.ph_price_bars.pop(0)
        
        if pivot_low is not None:
            self.pl_price_vals.append(pivot_low)
            self.pl_price_bars.append(current_bar - self.lookback)
