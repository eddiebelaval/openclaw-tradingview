import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    stoch_len = 14
    smooth_len1 = 3
    smooth_len2 = 3
    signal_len = 9
    use_htf_filter = True
    htf_timeframe = "60"
    htf_ema_len = 200
    use_price_filter = True
    use_range_filter = True
    range_lower = 40
    range_upper = 60

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate SSMI
        def calc_ssmi():
            lowest_low = low.rolling(window=self.stoch_len).min()
            highest_high = high.rolling(window=self.stoch_len).max()
            raw = 100 * (close - lowest_low) / (highest_high - lowest_low).clip(lower=1e-6)
            smooth1 = pta.ema(raw, length=self.smooth_len1)
            smooth2 = pta.ema(smooth1, length=self.smooth_len2)
            return smooth2
        
        self.ssmi = self.I(calc_ssmi)
        self.signal = self.I(pta.ema, close, length=self.signal_len)
        
        # Calculate local structure (highest of last 2 bars, lowest of last 2 bars)
        def calc_local_high():
            return high.shift(1).rolling(window=2).max()
        
        def calc_local_low():
            return low.shift(1).rolling(window=2).min()
        
        self.local_high = self.I(calc_local_high)
        self.local_low = self.I(calc_local_low)
        
        # HTF EMA (simplified - use same timeframe for backtesting)
        self.htf_ema = self.I(pta.ema, close, length=self.htf_ema_len)

    def next(self):
        if len(self.data) < max(self.stoch_len, self.signal_len, self.htf_ema_len) + 5:
            return
        
        # Current values
        ssmi_current = self.ssmi[-1]
        signal_current = self.signal[-1]
        close_current = self.data.Close[-1]
        htf_ema_current = self.htf_ema[-1]
        local_high = self.local_high[-1]
        local_low = self.local_low[-1]
        
        # Check if values are valid
        if pd.isna(ssmi_current) or pd.isna(signal_current) or pd.isna(local_high) or pd.isna(local_low):
            return
        
        # Range filter
        in_range = ssmi_current >= self.range_lower and ssmi_current <= self.range_upper
        
        # Crossover conditions
        ssmi_bullish = crossover(self.ssmi, self.signal)
        ssmi_bearish = crossover(self.signal, self.ssmi)
        
        # Apply range filter to crossover signals
        if self.use_range_filter:
            ssmi_bullish = ssmi_bullish and in_range
            ssmi_bearish = ssmi_bearish and in_range
        else:
            ssmi_bullish = ssmi_bullish and ssmi_current > 50
            ssmi_bearish = ssmi_bearish and ssmi_current < 50
        
        long_signal = ssmi_bullish
        short_signal = ssmi_bearish
        
        # Apply HTF filter (close > EMA for bullish, close < EMA for bearish)
        if self.use_htf_filter:
            htf_bullish = close_current > htf_ema_current
            htf_bearish = close_current < htf_ema_current
            long_signal = long_signal and htf_bullish
            short_signal = short_signal and htf_bearish
        
        # Apply price filter (structure breakout)
        if self.use_price_filter:
            break_high = close_current > local_high
            break_low = close_current < local_low
            long_signal = long_signal and break_high
            short_signal = short_signal and break_low
        
        # Execute trades
        if long_signal:
            if not self.position:
                self.buy()
        elif short_signal:
            if self.position:
                self.position.close()


