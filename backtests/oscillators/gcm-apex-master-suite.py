                smi_falling = self.smi[-1] < self.smi[-2] if len(self.data) > 1 else False
                obv_bearish = self.obv_raw[-1] < self.obv_sma[-1]
                vwap_bearish = close < self.vwap[-1]
                vwma_bearish = close < self.vwma[-1]
                
                bearish_signals = sum([
                    rsi_falling,
                    smi_falling,
                    obv_bearish,
                    vwap_bearish,
                    vwma_bearish
                ])
                
                if bearish_signals >= 3:
                    self.sell()
                    self.in_trade = True
                    self.is_long = False
                    self.entry_price = close
