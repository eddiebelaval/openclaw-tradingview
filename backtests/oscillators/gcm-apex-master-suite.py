import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Position Suit Core Settings
    prd = 3
    trade_mode = "ALL"  # ALL, LONG, SHORT
    
    # HUD Settings
    show_vwap = True
    show_vwma = True
    show_obv = True
    show_smi = True
    show_rsi = True
    show_dvol = True
    show_vol = True
    
    # Momentum, Vol & SMI
    rsi_length = 14
    smi_k_len = 10
    smi_d_len = 2
    obv_sma_len = 21
    vol_sma_len = 20
    vwma_len = 20
    
    # Dual Divergence
    lb = 5
    show_reg = True
    show_hid = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # SMI Calculation
        def calc_smi():
            smi_hh = high.rolling(self.smi_k_len).max()
            smi_ll = low.rolling(self.smi_k_len).min()
            smi_rdv = close - (smi_hh + smi_ll) / 2
            smi_diff = smi_hh - smi_ll
            smi_avg_rel = pta.ema(pta.ema(smi_rdv, length=self.smi_d_len), length=self.smi_d_len)
            smi_avg_diff = pta.ema(pta.ema(smi_diff, length=self.smi_d_len), length=self.smi_d_len)
            smi_val = np.where(smi_avg_diff != 0, (smi_avg_rel / (smi_avg_diff / 2) * 100), 0)
            return pd.Series(smi_val, index=close.index)
        
        self.smi = self.I(calc_smi)
        
        # OBV
        def calc_obv():
            obv = np.cumsum(np.sign(close.diff()) * volume)
            return pd.Series(obv, index=close.index)
        
        self.obv_raw = self.I(calc_obv)
        self.obv_sma = self.I(pta.sma, self.obv_raw, length=self.obv_sma_len)
        
        # VWAP
        self.vwap = self.I(lambda: pta.vwap(high, low, close, volume) or pd.Series(close.iloc[0], index=close.index))
        
        # VWMA
        self.vwma = self.I(pta.vwma, close, volume, length=self.vwma_len)
        
        # Volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=self.vol_sma_len)
        
        # Delta Volume Calculation
        def calc_dvol():
            range_hl = high - low
            bp = np.where(range_hl == 0, 
                         np.where(close >= open_, 1.0, 0.0),
                         (close - low) / range_hl)
            buy_vol = volume * bp
            sell_vol = volume - buy_vol
            delta = buy_vol - sell_vol
            dvol_pct = np.where(volume == 0, 0, (delta / volume) * 100)
            return pd.Series(dvol_pct, index=close.index)
        
        self.dvol_pct = self.I(calc_dvol)
        
        # Pivots for Position Suit
        def calc_pivot_high():
            return high.rolling(window=self.prd*2+1, center=True).max() == high
        
        def calc_pivot_low():
            return low.rolling(window=self.prd*2+1, center=True).min() == low
        
        self.pivot_high = self.I(calc_pivot_high)
        self.pivot_low = self.I(calc_pivot_low)
        
        # State tracking
        self.in_trade = False
        self.is_long = False
        self.entry_price = 0.0
        self.entry_sl = 0.0

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        can_long = self.trade_mode in ["ALL", "LONG"]
        can_short = self.trade_mode in ["ALL", "SHORT"]
        
        # Check for pivot points
        idx = len(self.data) - 1
        pivot_high_triggered = (idx >= self.prd and 
                               self.pivot_high[-1] and 
                               idx > self.prd)
        pivot_low_triggered = (idx >= self.prd and 
                              self.pivot_low[-1] and 
                              idx > self.prd)
        
        # Position Suit Logic
        if self.in_trade:
            # Check stop loss
            if self.is_long and close < self.entry_sl:
                self.sell()
                self.in_trade = False
            elif not self.is_long and close > self.entry_sl:
                self.buy()
                self.in_trade = False
        else:
            # Entry signals based on pivot + confluence
            rsi_rising = self.rsi[-1] > self.rsi[-2] if len(self.data) > 1 else False
            smi_rising = self.smi[-1] > self.smi[-2] if len(self.data) > 1 else False
            obv_bullish = self.obv_raw[-1] > self.obv_sma[-1]
            vwap_bullish = close > self.vwap[-1]
            vwma_bullish = close > self.vwma[-1]
            
            # Long Entry: Pivot Low + Bullish Confluence
            if pivot_low_triggered and can_long:
                bullish_signals = sum([
                    rsi_rising,
                    smi_rising,
                    obv_bullish,
                    vwap_bullish,
                    vwma_bullish
                ])
                
                if bullish_signals >= 3:
                    self.buy()
                    self.in_trade = True
                    self.is_long = True
                    self.entry_price = close
                    self.entry_sl = low
            
