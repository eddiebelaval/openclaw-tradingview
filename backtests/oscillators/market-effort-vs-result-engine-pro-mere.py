import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    calcLen = 18
    baselineLen = 50
    smoothLen = 5
    effHighThresh = 55.0
    effLowThresh = 22.0
    effortHotLevel = 115.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        def calc_total_effort():
            result = []
            for i in range(len(close)):
                if i < self.calcLen:
                    result.append(np.nan)
                else:
                    effort = sum(high.iloc[i - j] - low.iloc[i - j] for j in range(self.calcLen))
                    result.append(effort)
            return pd.Series(result, index=close.index)

        def calc_baseline_avg_effort():
            result = []
            for i in range(len(close)):
                if i < self.baselineLen:
                    result.append(np.nan)
                else:
                    baseline = sum(high.iloc[i - j] - low.iloc[i - j] for j in range(self.baselineLen)) / self.baselineLen
                    result.append(baseline)
            return pd.Series(result, index=close.index)

        def calc_net_move():
            result = []
            for i in range(len(close)):
                if i < self.calcLen:
                    result.append(np.nan)
                else:
                    net = close.iloc[i] - close.iloc[i - self.calcLen]
                    result.append(net)
            return pd.Series(result, index=close.index)

        def calc_efficiency_pct():
            total_effort = calc_total_effort()
            net_move = calc_net_move()
            result = []
            for i in range(len(close)):
                if pd.isna(total_effort.iloc[i]) or pd.isna(net_move.iloc[i]):
                    result.append(np.nan)
                else:
                    eff = (abs(net_move.iloc[i]) / max(total_effort.iloc[i], 1e-10)) * 100.0
                    result.append(eff)
            return pd.Series(result, index=close.index)

        def calc_signed_efficiency():
            total_effort = calc_total_effort()
            net_move = calc_net_move()
            efficiency_pct = calc_efficiency_pct()
            result = []
            for i in range(len(close)):
                if pd.isna(efficiency_pct.iloc[i]) or pd.isna(net_move.iloc[i]):
                    result.append(np.nan)
                else:
                    dir_sign = 1.0 if net_move.iloc[i] > 0 else (-1.0 if net_move.iloc[i] < 0 else 0.0)
                    signed = efficiency_pct.iloc[i] * dir_sign
                    result.append(signed)
            return pd.Series(result, index=close.index)

        def calc_effort_pressure():
            total_effort = calc_total_effort()
            baseline_avg = calc_baseline_avg_effort()
            result = []
            for i in range(len(close)):
                if pd.isna(total_effort.iloc[i]) or pd.isna(baseline_avg.iloc[i]):
                    result.append(np.nan)
                else:
                    avg_effort_now = total_effort.iloc[i] / self.calcLen
                    pressure = (avg_effort_now / max(baseline_avg.iloc[i], 1e-10)) * 100.0
                    result.append(pressure)
            return pd.Series(result, index=close.index)

        def calc_churn_pressure():
            efficiency_pct = calc_efficiency_pct()
            effort_pressure = calc_effort_pressure()
            result = []
            for i in range(len(close)):
                if pd.isna(efficiency_pct.iloc[i]) or pd.isna(effort_pressure.iloc[i]):
                    result.append(np.nan)
                else:
                    churn = (100.0 - efficiency_pct.iloc[i]) * (effort_pressure.iloc[i] / 100.0)
                    churn = max(0.0, min(200.0, churn))
                    result.append(churn)
            return pd.Series(result, index=close.index)

        self.total_effort = self.I(calc_total_effort)
        self.baseline_avg_effort = self.I(calc_baseline_avg_effort)
        self.net_move = self.I(calc_net_move)
        self.efficiency_pct = self.I(calc_efficiency_pct)
        self.signed_efficiency = self.I(calc_signed_efficiency)
        self.effort_pressure = self.I(calc_effort_pressure)
        self.churn_pressure = self.I(calc_churn_pressure)

        def smooth_signed_eff():
            signed_eff = self.signed_efficiency
            smoothed = pta.ema(signed_eff.fillna(0.0), length=self.smoothLen)
            if smoothed is not None:
                return smoothed
            return pd.Series(0.0, index=signed_eff.index)

        def smooth_efficiency():
            eff = self.efficiency_pct
            smoothed = pta.ema(eff.fillna(0.0), length=self.smoothLen)
            if smoothed is not None:
                return smoothed
            return pd.Series(0.0, index=eff.index)

        def smooth_churn():
            churn = self.churn_pressure
            smoothed = pta.ema(churn.fillna(0.0), length=self.smoothLen)
            if smoothed is not None:
                return smoothed
            return pd.Series(0.0, index=churn.index)

        self.signed_eff_smooth = self.I(smooth_signed_eff)
        self.efficiency_smooth = self.I(smooth_efficiency)
        self.churn_smooth = self.I(smooth_churn)

    def next(self):
        if len(self.data) < max(self.calcLen, self.baselineLen):
            return

        signed_eff = self.signed_eff_smooth[-1] if not np.isnan(self.signed_eff_smooth[-1]) else 0.0
        efficiency = self.efficiency_smooth[-1] if not np.isnan(self.efficiency_smooth[-1]) else 0.0
        effort_press = self.effort_pressure[-1] if not np.isnan(self.effort_pressure[-1]) else 0.0

        is_efficient_up = signed_eff >= self.effHighThresh
        is_efficient_down = signed_eff <= -self.effHighThresh
        is_absorption = efficiency <= self.effLowThresh and effort_press >= self.effortHotLevel

        if is_efficient_up and not self.position:
            self.buy()
        elif (is_efficient_down or is_absorption) and self.position:
            self.sell()