import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    use_adapt = True
    base_bull = 0.70
    base_bear = 0.70
    base_chop = 0.50
    sig_len = 9
    bb_len = 20
    bb_mult = 2.0
    piv_len = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Efficiency Ratio (ER)
        def calc_er():
            er_series = pd.Series(index=close.index, dtype=float)
            for i in range(self.length, len(close)):
                change = abs(close.iloc[i] - close.iloc[i - self.length])
                volatility = sum(abs(close.iloc[j] - close.iloc[j-1]) for j in range(i - self.length + 1, i + 1))
                er_series.iloc[i] = change / volatility if volatility != 0 else 0.0
            return er_series.fillna(0)
        
        self.er = self.I(calc_er)
        
        # Dynamic probabilities
        def calc_dyn_probs():
            probs = pd.DataFrame(index=close.index, dtype=float)
            for i in range(len(close)):
                er_val = self.er[i] if i < len(self.er) else 0
                probs.loc[i, 'bull'] = min(0.99, self.base_bull + (er_val * 0.25)) if self.use_adapt else self.base_bull
                probs.loc[i, 'bear'] = min(0.99, self.base_bear + (er_val * 0.25)) if self.use_adapt else self.base_bear
                probs.loc[i, 'chop'] = min(0.99, self.base_chop + ((1.0 - er_val) * 0.35)) if self.use_adapt else self.base_chop
            return probs
        
        # Momentum observations
        mom_raw = pta.roc(close, length=1)
        mom_smooth = pta.ema(mom_raw, length=self.length) if pta.ema(mom_raw, length=self.length) is not None else pd.Series(0, index=close.index)
        mom_std = pta.stdev(mom_smooth, length=self.length) if pta.stdev(mom_smooth, length=self.length) is not None else pd.Series(1, index=close.index)
        mom_sma = pta.sma(mom_smooth, length=self.length) if pta.sma(mom_smooth, length=self.length) is not None else pd.Series(0, index=close.index)
        
        def calc_obs_mom():
            obs = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if mom_std.iloc[i] != 0:
                    obs.iloc[i] = (mom_smooth.iloc[i] - mom_sma.iloc[i]) / mom_std.iloc[i]
                else:
                    obs.iloc[i] = 0.0
            return obs
        
        self.obs_mom = self.I(calc_obs_mom)
        
        # Volatility observations
        vol_raw = pta.atr(high, low, close, length=self.length) if pta.atr(high, low, close, length=self.length) is not None else pd.Series(0, index=close.index)
        vol_std = pta.stdev(vol_raw, length=self.length) if pta.stdev(vol_raw, length=self.length) is not None else pd.Series(1, index=close.index)
        vol_sma = pta.sma(vol_raw, length=self.length) if pta.sma(vol_raw, length=self.length) is not None else pd.Series(0, index=close.index)
        
        def calc_obs_vol():
            obs = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if vol_std.iloc[i] != 0:
                    obs.iloc[i] = (vol_raw.iloc[i] - vol_sma.iloc[i]) / vol_std.iloc[i]
                else:
                    obs.iloc[i] = 0.0
            return obs
        
        self.obs_vol = self.I(calc_obs_vol)
        
        # PDF function
        def f_pdf(x, mu, sigma):
            var = sigma * sigma
            if var == 0:
                var = 1e-6
            return (1.0 / np.sqrt(2.0 * np.pi * var)) * np.exp(-((x - mu) ** 2) / (2.0 * var))
        
        # Likelihoods
        def calc_likelihoods():
            like = pd.DataFrame(index=close.index, dtype=float)
            for i in range(len(close)):
                obs_m = self.obs_mom[i] if i < len(self.obs_mom) else 0
                obs_v = self.obs_vol[i] if i < len(self.obs_vol) else 0
                like.loc[i, 'bull'] = f_pdf(obs_m, 1.0, 1.0) * f_pdf(obs_v, -0.5, 1.0)
                like.loc[i, 'bear'] = f_pdf(obs_m, -1.0, 1.0) * f_pdf(obs_v, 1.0, 1.0)
                like.loc[i, 'chop'] = f_pdf(obs_m, 0.0, 0.5) * f_pdf(obs_v, 1.5, 1.0)
            return like
        
        self.likelihoods = self.I(calc_likelihoods)
        
        # HMM state probabilities
        def calc_net_regime():
            prob_bull = 1/3.0
            prob_bear = 1/3.0
            prob_chop = 1/3.0
            
            net_reg = pd.Series(index=close.index, dtype=float)
            
            for i in range(len(close)):
                er_val = self.er[i] if i < len(self.er) else 0
                dyn_bull = min(0.99, self.base_bull + (er_val * 0.25)) if self.use_adapt else self.base_bull
                dyn_bear = min(0.99, self.base_bear + (er_val * 0.25)) if self.use_adapt else self.base_bear
                dyn_chop = min(0.99, self.base_chop + ((1.0 - er_val) * 0.35)) if self.use_adapt else self.base_chop
                
                trans_bull_bear = (1.0 - dyn_bull) * 0.2
                trans_bull_chop = (1.0 - dyn_bull) * 0.8
                trans_bear_bull = (1.0 - dyn_bear) * 0.2
                trans_bear_chop = (1.0 - dyn_bear) * 0.8
                trans_chop_bull = (1.0 - dyn_chop) * 0.5
                trans_chop_bear = (1.0 - dyn_chop) * 0.5
                
                prior_bull = (prob_bull * dyn_bull) + (prob_bear * trans_bear_bull) + (prob_chop * trans_chop_bull)
                prior_bear = (prob_bull * trans_bull_bear) + (prob_bear * dyn_bear) + (prob_chop * trans_chop_bear)
                prior_chop = (prob_bull * trans_bull_chop) + (prob_bear * trans_bear_chop) + (prob_chop * dyn_chop)
                
                like_bull = self.likelihoods.iloc[i, 0] if i < len(self.likelihoods) else 1e-6
                like_bear = self.likelihoods.iloc[i, 1] if i < len(self.likelihoods) else 1e-6
                like_chop = self.likelihoods.iloc[i, 2] if i < len(self.likelihoods) else 1e-6
                
                post_bull = prior_bull * like_bull
                post_bear = prior_bear * like_bear
                post_chop = prior_chop * like_chop
                
                total_post = post_bull + post_bear + post_chop
                
                if total_post > 0:
                    prob_bull = post_bull / total_post
                    prob_bear = post_bear / total_post
                    prob_chop = post_chop / total_post
                
                pct_bull = prob_bull * 100
                pct_bear = prob_bear * 100
                net_reg.iloc[i] = pct_bull - pct_bear
            
            return net_reg
        
        self.net_regime = self.I(calc_net_regime)
        
        # Signal line
        self.sig_line = self.I(pta.ema, self.net_regime, length=self.sig_len) or self.I(lambda: pd.Series(0, index=close.index))
        
        # Bollinger Bands
        self.bb_basis = self.I(pta.sma, self.net_regime, length=self.bb_len) or self.I(lambda: pd.Series(0, index=close.index))
        self.bb_std = self.I(pta.stdev, self.net_regime, length=self.bb_len) or self.I(lambda: pd.Series(0.1, index=close.index))
        
        def calc_bb_upper():
            return self.bb_basis + (self.bb_mult * self.bb_std)
        
        def calc_bb_lower():
            return self.bb_basis - (self.bb_mult * self.bb_std)
        
        self.bb_upper = self.I(calc_bb_upper)
        self.bb_lower = self.I(calc_bb_lower)

    def next(self):
        if len(self) < self.sig_len + 10:
            return
        
        # Buy signal: net_regime crosses above signal line while below 0
        if crossover(self.net_regime, self.sig_line):
            if self.net_regime[-1] < 0:
                if not self.position:
                    self.buy()
        
        # Sell signal: net_regime crosses below signal line while above 0
        if crossover(self.sig_line, self.net_regime):
            if self.net_regime[-1] > 0:
                if self.position:
                    self.position.close()


