import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vpLength = 100
    numRows = 50
    vaPercent = 0.70
    rsiLen = 14
    rsiOB = 70
    rsiOS = 30
    pocSkew = 0.3
    proximity = 0.005

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        self.momentum = self.I(pta.mom, close, length=10)
        
        def calculate_volume_profile():
            result = pd.DataFrame({
                'poc': np.zeros(len(close)),
                'vah': np.zeros(len(close)),
                'val': np.zeros(len(close)),
                'poc_near_val': np.zeros(len(close)),
                'poc_near_vah': np.zeros(len(close))
            })
            
            for bar_idx in range(len(close)):
                if bar_idx < self.vpLength:
                    result.loc[bar_idx] = [0, 0, 0, 0, 0]
                    continue
                
                start_idx = max(0, bar_idx - self.vpLength)
                end_idx = bar_idx + 1
                
                h_slice = high.iloc[start_idx:end_idx]
                l_slice = low.iloc[start_idx:end_idx]
                c_slice = close.iloc[start_idx:end_idx]
                v_slice = volume.iloc[start_idx:end_idx]
                
                highest = h_slice.max()
                lowest = l_slice.min()
                price_range = highest - lowest
                
                if price_range == 0:
                    result.loc[bar_idx] = [c_slice.iloc[-1], highest, lowest, 0, 0]
                    continue
                
                row_height = price_range / self.numRows
                vol_profile = np.zeros(self.numRows)
                
                for j in range(len(c_slice)):
                    idx = int(np.floor((c_slice.iloc[j] - lowest) / row_height))
                    idx = max(0, min(idx, self.numRows - 1))
                    vol_profile[idx] += v_slice.iloc[j]
                
                poc_idx = np.argmax(vol_profile)
                poc_price = lowest + (poc_idx + 0.5) * row_height
                
                total_vol = vol_profile.sum()
                va_target_vol = total_vol * self.vaPercent
                va_vol = vol_profile[poc_idx]
                upper_idx = poc_idx
                lower_idx = poc_idx
                
                while va_vol < va_target_vol and (upper_idx < self.numRows - 1 or lower_idx > 0):
                    up_vol = vol_profile[upper_idx + 1] if upper_idx < self.numRows - 1 else 0.0
                    dn_vol = vol_profile[lower_idx - 1] if lower_idx > 0 else 0.0
                    
                    if up_vol >= dn_vol and upper_idx < self.numRows - 1:
                        upper_idx += 1
                        va_vol += up_vol
                    elif lower_idx > 0:
                        lower_idx -= 1
                        va_vol += dn_vol
                    else:
                        upper_idx += 1
                        va_vol += up_vol
                
                vah_price = lowest + (upper_idx + 1) * row_height
                val_price = lowest + lower_idx * row_height
                
                va_range = vah_price - val_price
                poc_position = (poc_price - val_price) / va_range if va_range != 0 else 0.5
                poc_near_val = 1 if poc_position < self.pocSkew else 0
                poc_near_vah = 1 if poc_position > (1.0 - self.pocSkew) else 0
                
                result.loc[bar_idx] = [poc_price, vah_price, val_price, poc_near_val, poc_near_vah]
            
            return result
        
        self.vp_data = self.I(calculate_volume_profile)

    def next(self):
        if len(self.data) < self.vpLength + 1:
            return
        
        current_idx = len(self.data) - 1
        
        poc_price = self.vp_data.iloc[current_idx, 0]
        vah_price = self.vp_data.iloc[current_idx, 1]
        val_price = self.vp_data.iloc[current_idx, 2]
        poc_near_val = self.vp_data.iloc[current_idx, 3]
        poc_near_vah = self.vp_data.iloc[current_idx, 4]
        
        current_close = self.data.Close[-1]
        prox_amt = current_close * self.proximity
        
        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50
        
        near_val = abs(current_close - val_price) < prox_amt
        near_vah = abs(current_close - vah_price) < prox_amt
        below_val = current_close < val_price
        
        strong_buy = near_val and poc_near_val and rsi_val < self.rsiOS
        buy_signal = near_val and rsi_val < self.rsiOS and not strong_buy
        strong_sell = near_vah and poc_near_vah and rsi_val > self.rsiOB
        sell_signal = near_vah and rsi_val > self.rsiOB and not strong_sell
        
        momentum_val = self.momentum[-1] if self.momentum[-1] is not None else 0
        falling_momentum = len(self.momentum) > 3 and self.momentum[-1] < self.momentum[-3]
        danger_zone = below_val and poc_near_val and falling_momentum
        
        if self.position:
            if strong_sell or sell_signal or danger_zone:
                self.position.close()
        else:
            if strong_buy or buy_signal:
                self.buy()


