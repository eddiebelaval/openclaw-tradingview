import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    bb_mult = 2.0
    kc_mult = 1.5
    ema_length = 50
    adx_threshold = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        bb_basis = self.I(pta.sma, close, length=self.length)
        bb_dev = self.I(lambda: pta.stdev(close, length=self.length) * self.bb_mult)
        self.upperBB = self.I(lambda: bb_basis + bb_dev)
        self.lowerBB = self.I(lambda: bb_basis - bb_dev)
        
        # True Range for Keltner Channels
        tr = self.I(lambda: pta.tr(high, low, close))
        
        # Keltner Channels
        kc_basis = self.I(pta.sma, close, length=self.length)
        kc_range = self.I(pta.ema, tr, length=self.length)
        self.upperKC = self.I(lambda: kc_basis + kc_range * self.kc_mult)
        self.lowerKC = self.I(lambda: kc_basis - self.kc_mult * kc_range)
        
        # Squeeze detection
        self.sqzOn = self.I(lambda: (self.lowerBB > self.lowerKC) & (self.upperBB < self.upperKC))
        self.sqzOff = self.I(lambda: (self.lowerBB < self.lowerKC) | (self.upperBB > self.upperKC))
        
        # Momentum Oscillator
        highest = self.I(lambda: high.rolling(self.length).max())
        lowest = self.I(lambda: low.rolling(self.length).min())
        avg_hl = self.I(lambda: (highest + lowest) / 2)
        momentum_input = self.I(lambda: close - ((avg_hl + kc_basis) / 2))
        self.momentum = self.I(pta.linreg, momentum_input, length=self.length)
        
        # EMA Trend Filter
        self.ema_trend = self.I(pta.ema, close, length=self.ema_length)
        
        # ADX for trend strength
        adx_result = self.I(pta.adx, high, low, close, length=14)
        self.adx = self.I(lambda: adx_result)

    def next(self):
        # Trend filters
        bull_trend = self.data.Close[-1] > self.ema_trend[-1]
        bear_trend = self.data.Close[-1] < self.ema_trend[-1]
        
        # Trend strength
        strong_trend = self.adx[-1] > self.adx_threshold if self.adx[-1] is not None else False
        
        # Squeeze fired: sqzOn in previous bar and sqzOff now
        if len(self.data) > 1:
            squeeze_fired = self.sqzOn[-2] and self.sqzOff[-1]
        else:
            squeeze_fired = False
        
        # Momentum conditions
        momentum_positive = self.momentum[-1] > 0 if self.momentum[-1] is not None else False
        momentum_negative = self.momentum[-1] < 0 if self.momentum[-1] is not None else False
        
        # Base firing triggers
        long_fire = squeeze_fired and momentum_positive
        short_fire = squeeze_fired and momentum_negative
        
        # High-probability triggers
        hp_long = long_fire and bull_trend and strong_trend
        hp_short = short_fire and bear_trend and strong_trend
        
        # Trading logic
        if hp_long and not self.position:
            self.buy()
        elif hp_short and self.position:
            self.sell()
        elif not hp_long and self.position and not hp_short:
            self.sell()


