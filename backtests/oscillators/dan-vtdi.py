        self.rsi = self.I(pta.rsi, close, length=self.rsi_period)
        self.ma_rsi = self.I(pta.sma, self.rsi, length=self.band_length)
        
        # Calculate standard deviation for offset
        def calc_offset(rsi_series):
            return 1.6185 * rsi_series.std()
        
        self.offset = self.I(lambda: pd.Series(
            [1.6185 * close.iloc[max(0, i-self.band_length+1):i+1].rolling(self.band_length).std().iloc[-1] 
             if i >= self.band_length - 1 else 0 for i in range(len(close))],
            index=close.index
        ))
        
        self.up = self.I(lambda: self.ma_rsi + self.offset)
        self.dn = self.I(lambda: self.ma_rsi - self.offset)
        self.mid = self.I(lambda: (self.up + self.dn) / 2)
        
        self.fast_ma_rsi = self.I(pta.sma, self.rsi, length=self.fast_ma_length)
        self.slow_ma_rsi = self.I(pta.sma, self.rsi, length=self.slow_ma_length)

