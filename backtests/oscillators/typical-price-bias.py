import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLenInput = 13
    slowLenInput = 26
    oscTypeInput = "EMA"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hl2 = (high + low) / 2

        def calculate_ma(source, length, ma_type):
            if ma_type == "NONE":
                return source
            elif ma_type == "EMA":
                result = pta.ema(source, length=length)
                return result if result is not None else source
            elif ma_type == "SMA":
                result = pta.sma(source, length=length)
                return result if result is not None else source
            elif ma_type == "RMA":
                result = pta.rma(source, length=length)
                return result if result is not None else source
            elif ma_type == "VWMA":
                result = pta.vwma(source, volume, length=length)
                return result if result is not None else source
            elif ma_type == "WMA":
                result = pta.wma(source, length=length)
                return result if result is not None else source
            elif ma_type == "ALMA":
                result = pta.alma(source, length=length, offset=0.85, sigma=6)
                return result if result is not None else source
            elif ma_type == "SWMA":
                result = pta.swma(source)
                return result if result is not None else source
            elif ma_type == "HMA":
                result = pta.hma(source, length=length)
                return result if result is not None else source
            else:
                return source

        def calculate_fast_bias():
            ma_close_fast = calculate_ma(close, self.fastLenInput, self.oscTypeInput)
            ma_hl2_fast = calculate_ma(hl2, self.fastLenInput, self.oscTypeInput)
            
            den = hl2.shift(1).fillna(hl2)
            den = den.replace(0.0, 1e-10)
            
            fast = (ma_close_fast - ma_hl2_fast) / den
            return fast

        def calculate_base_bias():
            ma_close_slow = calculate_ma(close, self.slowLenInput, self.oscTypeInput)
            ma_hl2_slow = calculate_ma(hl2, self.slowLenInput, self.oscTypeInput)
            
            den = hl2.shift(1).fillna(hl2)
            den = den.replace(0.0, 1e-10)
            
            base = (ma_close_slow - ma_hl2_slow) / den
            return base

        self.fast_bias = self.I(calculate_fast_bias)
        self.base_bias = self.I(calculate_base_bias)

    def next(self):
        if len(self.data) < 2:
            return

        fast_current = self.fast_bias[-1]
        fast_prev = self.fast_bias[-2]

        if pd.isna(fast_current) or pd.isna(fast_prev):
            return

        if crossover(self.fast_bias, 0):
            if not self.position:
                self.buy()
        elif crossover(0, self.fast_bias):
            if self.position:
                self.position.close()