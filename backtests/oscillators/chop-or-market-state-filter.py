import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adxLen = 14
    adxThresh = 20
    atrLen = 14
    atrMult = 0.8
    volLen = 20
    useVol = True
    useCong = True
    congBars = 5
    congPerc = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # ADX Calculation
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adxLen))
        self.adx = adx_result

        # ATR Calculation
        atr_result = self.I(lambda: pta.atr(high, low, close, length=self.atrLen))
        self.atr = atr_result

        # ATR EMA
        atr_series = pd.Series(self.data.High)
        atr_for_ema = self.I(lambda: pta.atr(high, low, close, length=self.atrLen))
        self.atrEma = self.I(lambda: pta.ema(atr_for_ema, length=self.atrLen * 2))

        # Volume MA
        self.volMa = self.I(lambda: pta.sma(volume, length=self.volLen))

        # Highest High and Lowest Low for Congestion
        self.highestHigh = self.I(lambda: high.rolling(window=self.congBars).max())
        self.lowestLow = self.I(lambda: low.rolling(window=self.congBars).min())

        # Track previous chop state
        self.prevChop = False

    def next(self):
        # 1. ADX Check
        if len(self.adx) == 0 or self.adx[-1] is None:
            return
        isLowTrend = self.adx[-1] < self.adxThresh

        # 2. Relative Volatility (ATR)
        if len(self.atr) == 0 or self.atr[-1] is None or len(self.atrEma) == 0 or self.atrEma[-1] is None:
            return
        isLowVolat = self.atr[-1] < (self.atrEma[-1] * self.atrMult)

        # 3. Volume Filter
        if self.useVol:
            if len(self.volMa) == 0 or self.volMa[-1] is None:
                isLowVolum = False
            else:
                isLowVolum = self.data.Volume[-1] < self.volMa[-1]
        else:
            isLowVolum = False

        # 4. Congestion Filter
        if self.useCong:
            if len(self.highestHigh) == 0 or self.highestHigh[-1] is None or len(self.lowestLow) == 0 or self.lowestLow[-1] is None:
                isCongested = False
            else:
                rangeHeight = self.highestHigh[-1] - self.lowestLow[-1]
                isCongested = rangeHeight < (self.atr[-1] * self.congPerc)
        else:
            isCongested = False

        # Determine Chop Condition
        isChop = isLowTrend and (isLowVolat or isLowVolum or isCongested)

        # Trading Logic
        # Buy when trend resumes (exiting chop)
        if self.prevChop and not isChop:
            if not self.position:
                self.buy()
        # Sell when entering chop
        elif isChop and not self.prevChop:
            if self.position:
                self.sell()

        self.prevChop = isChop