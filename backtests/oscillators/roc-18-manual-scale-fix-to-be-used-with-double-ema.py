import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    roc_len = 18

    def init(self):
        close = pd.Series(self.data.Close)
        self.roc = self.I(pta.roc, close, length=self.roc_len)

    def next(self):
        if len(self.data) < self.roc_len + 1:
            return
        
        current_roc = self.roc[-1]
        
        if current_roc is None or np.isnan(current_roc):
            return
        
        if not self.position:
            if current_roc <= -10:
                self.buy()
        else:
            if current_roc > 0:
                self.sell()


