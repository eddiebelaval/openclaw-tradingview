import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fast_len = 12
    slow_len = 26
    signal_len = 9
    filter_len = 5

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate MACD components
        macd_result = self.I(pta.macd, close, fast=self.fast_len, slow=self.slow_len, signal=self.signal_len)
        
        # Extract MACD line, signal line, and histogram
        self.macd_line = macd_result.iloc[:, 0]
        self.signal_line = macd_result.iloc[:, 1]
        self.hist_line = macd_result.iloc[:, 2]
        
        # Secondary smoothing of histogram
        self.smooth_hist = self.I(pta.ema, self.hist_line, length=self.filter_len)

    def next(self):
        # Check if we have enough data
        if len(self.data) < 2:
            return
        
        # Ensure indicators have valid values
        if pd.isna(self.hist_line[-1]) or pd.isna(self.smooth_hist[-1]) or pd.isna(self.macd_line[-1]):
            return
        
        # Buy signal: histogram crosses above smoothed histogram AND macd_line > previous macd_line
        buy_signal = (crossover(self.hist_line, self.smooth_hist) and 
                      self.macd_line[-1] > self.macd_line[-2])
        
        # Sell signal: histogram crosses below smoothed histogram AND macd_line < previous macd_line
        sell_signal = (crossover(self.smooth_hist, self.hist_line) and 
                       self.macd_line[-1] < self.macd_line[-2])
        
        if buy_signal:
            if not self.position:
                self.buy()
        elif sell_signal:
            if self.position:
                self.position.close()


