import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    short_len = 30
    long_len = 90
    smooth_len = 1
    w_vol = 25
    w_mom = 25
    w_volume = 15
    w_btcd = 15
    w_stable = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Helper function to clamp values
        def clamp(val):
            return np.maximum(0.0, np.minimum(100.0, val))

        # 1. VOLATILITY SCORE
        def calc_vol_score():
            true_range = high - low
            vol_short = pta.sma(true_range / close * 100, length=self.short_len)
            vol_long = pta.sma(true_range / close * 100, length=self.long_len)
            vol_baseline = (vol_short + vol_long) / 2
            vol_current = pta.sma(true_range / close * 100, length=7)
            vol_ratio = vol_current / vol_baseline
            vol_score = clamp(100 - (vol_ratio - 0.5) * 60)
            return vol_score

        # 2. MOMENTUM SCORE
        def calc_mom_score():
            ma_short = pta.sma(close, length=self.short_len)
            ma_long = pta.sma(close, length=self.long_len)
            dev_short = (close - ma_short) / ma_short * 100
            dev_long = (close - ma_long) / ma_long * 100
            dev_avg = (dev_short + dev_long) / 2
            mom_score = clamp(50 + dev_avg * (50.0 / 30.0))
            return mom_score

        # 3. VOLUME SCORE
        def calc_volume_score():
            vol_ma_short = pta.sma(volume, length=self.short_len)
            vol_ma_long = pta.sma(volume, length=self.long_len)
            vol_ma_week = pta.sma(volume, length=7)
            vol_avg_base = (vol_ma_short + vol_ma_long) / 2
            vol_buy_ratio = vol_ma_week / vol_avg_base
            
            price_change = close.diff()
            price_dir_series = pta.sma(price_change, length=7) > 0
            price_dir = price_dir_series.astype(float) * 2 - 1
            
            vol_dir_score = vol_buy_ratio * price_dir
            volume_score = clamp(50 + vol_dir_score * 30)
            return volume_score

        # 4. BTC DOMINANCE SCORE (using close as proxy since we don't have BTC.D data)
        def calc_btcd_score():
            btcd_ma_short = pta.sma(close, length=self.short_len)
            btcd_ma_long = pta.sma(close, length=self.long_len)
            btcd_ma = (btcd_ma_short + btcd_ma_long) / 2
            btcd_dev = (close - btcd_ma) / btcd_ma * 100
            btcd_score = clamp(50 - btcd_dev * 8)
            return btcd_score

        # 5. STABLECOIN DOMINANCE SCORE (using volume as proxy since we don't have USDT.D data)
        def calc_stable_score():
            usdt_ma_short = pta.sma(volume, length=self.short_len)
            usdt_ma_long = pta.sma(volume, length=self.long_len)
            usdt_ma = (usdt_ma_short + usdt_ma_long) / 2
            usdt_dev = (volume - usdt_ma) / usdt_ma * 100
            stable_score = clamp(50 - usdt_dev * 5)
            return stable_score

        # Calculate individual scores
        self.vol_score = self.I(calc_vol_score)
        self.mom_score = self.I(calc_mom_score)
        self.volume_score = self.I(calc_volume_score)
        self.btcd_score = self.I(calc_btcd_score)
        self.stable_score = self.I(calc_stable_score)

        # Calculate composite index
        def calc_fgi():
            total_weight = self.w_vol + self.w_mom + self.w_volume + self.w_btcd + self.w_stable
            raw_index = (
                self.vol_score * self.w_vol +
                self.mom_score * self.w_mom +
                self.volume_score * self.w_volume +
                self.btcd_score * self.w_btcd +
                self.stable_score * self.w_stable
            ) / (total_weight if total_weight > 0 else 1)
            
            if self.smooth_len > 1:
                fgi = pta.ema(raw_index, length=self.smooth_len)
            else:
                fgi = raw_index
            
            return fgi if fgi is not None else pd.Series(50, index=raw_index.index)

        self.fgi = self.I(calc_fgi)

    def next(self):
        # Trading logic based on Fear & Greed Index
        # Buy on crossover to greed (above 50), sell on crossover to fear (below 50)
        
        if len(self.fgi) < 2:
            return

        current_fgi = self.fgi[-1]
        prev_fgi = self.fgi[-2]

        # Buy signal: FGI crosses above 50 (neutral to greed)
        if crossover(self.fgi, 50):
            if not self.position:
                self.buy()
        
        # Sell signal: FGI crosses below 50 (greed to neutral/fear)
        elif crossover(50, self.fgi):
            if self.position:
                self.position.close()

        # Alternative: Trade extreme sentiment reversals
        # Buy on extreme fear (below 25)
        if current_fgi < 25 and prev_fgi >= 25:
            if not self.position:
                self.buy()
        
        # Sell on extreme greed (above 75)
        if current_fgi > 75 and prev_fgi <= 75:
            if self.position:
                self.position.close()


