        # Calculate oscillators
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLength) or pd.Series(50, index=close.index))
        
        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal))
        self.macd_hist = self.I(lambda: macd_result.iloc[:, 2] if macd_result is not None and macd_result.shape[1] > 2 else pd.Series(0, index=close.index))
        
        self.stoch = self.I(lambda: pta.stoch(high, low, close, k=self.stochLength, d=self.stochLength, smooth_k=3).iloc[:, 0] if pta.stoch(high, low, close, k=self.stochLength, d=self.stochLength, smooth_k=3) is not None else pd.Series(50, index=close.index))
        
