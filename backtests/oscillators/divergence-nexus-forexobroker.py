    def next(self):
        if len(self.data) < self.pivotLookback + 2:
            return
        
        idx = len(self.data) - 1
        self.bull_confluence = 0
        self.bear_confluence = 0
        
        # Detect pivots and divergences for each oscillator
        if self.enableRSI:
            self._check_divergence_rsi()
        if self.enableMACD:
            self._check_divergence_macd()
        if self.enableStoch:
            self._check_divergence_stoch()
        if self.enableCCI:
            self._check_divergence_cci()
        
        # Trading logic based on confluences
        if self.bull_confluence >= self.minConfluenceAlert:
            if not self.position:
                self.buy()
        elif self.bear_confluence >= self.minConfluenceAlert:
            if self.position:
                self.sell()

    def _check_divergence_rsi(self):
        idx = len(self.data) - 1
        if idx < self.pivotLookback + 1:
            return
        
        current_price = self.data.Close[-1]
        current_rsi = self.rsi[-1]
        
        # Check for price pivot high and RSI pivot high
        if idx > self.pivotLookback:
            is_price_high = (self.data.High[-1] == self.price_high[-1])
            is_rsi_high = (self.rsi[-1] == self.rsi_high[-1])
            
            if is_price_high and is_rsi_high:
                self.rsi_pivots_high.append((idx, current_price, current_rsi))
                self.rsi_pivots_high = self.rsi_pivots_high[-10:]
                
                if len(self.rsi_pivots_high) >= 2:
                    recent = self.rsi_pivots_high[-1]
                    previous = self.rsi_pivots_high[-2]
                    bars_diff = recent[0] - previous[0]
                    
                    if self.minBarsBetween <= bars_diff <= self.maxBarsBetween:
                        if self.detectRegular and recent[1] > previous[1] and recent[2] < previous[2]:
                            self.bear_confluence += 1
                        elif self.detectHidden and recent[1] < previous[1] and recent[2] > previous[2]:
                            self.bear_confluence += 1
            
            is_price_low = (self.data.Low[-1] == self.price_low[-1])
