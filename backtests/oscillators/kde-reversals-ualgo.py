class TvStrategy(Strategy):
    lengthInput = 100
    upperThreshold = 95.0
    lowerThreshold = 5.0

    def init(self):
        self.kde_prices = []
        self.cdf_percent_values = []
        
    def erf(self, x):
        sign = np.sign(x)
        x_abs = np.abs(x)
        a1 = 0.254829592
        a2 = -0.284496736
        a3 = 1.421413741
        a4 = -1.453152027
        a5 = 1.061405429
        p = 0.3275911
        t = 1.0 / (1.0 + p * x_abs)
        y = 1.0 - (((((a5 * t + a4) * t) + a3) * t + a2) * t + a1) * t * np.exp(-x_abs * x_abs)
        return sign * y
    
    def norm_cdf(self, z):
        sqrt2 = np.sqrt(2)
        return 0.5 * (1.0 + self.erf(z / sqrt2))
    
    def get_iqr(self, prices):
        n = len(prices)
        if n < 4:
            return 0.0
        sorted_prices = sorted(prices)
        q1_idx = int(np.floor(n * 0.25))
        q3_idx = int(np.floor(n * 0.75))
        return sorted_prices[q3_idx] - sorted_prices[q1_idx]
    
    def get_kde_cdf(self, prices, current_price):
        n = len(prices)
        if n < 2:
            return 50.0
        
        stdev = np.std(prices, ddof=1) if len(prices) > 1 else 0.0
        iqr = self.get_iqr(prices)
        spread = min(stdev, iqr / 1.34) if iqr > 0 else stdev
        
