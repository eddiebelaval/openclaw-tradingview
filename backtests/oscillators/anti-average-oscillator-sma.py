import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_length = 50

    def init(self):
        close = pd.Series(self.data.Close)
        sma = self.I(pta.sma, close, length=self.ma_length)
        self.anti_avg_osc = self.I(lambda: close - sma)

    def next(self):
        if len(self.data) < self.ma_length:
            return
        
        if crossover(self.anti_avg_osc, 0):
            if not self.position:
                self.buy()
        elif crossover(0, self.anti_avg_osc):
            if self.position:
                self.position.close()