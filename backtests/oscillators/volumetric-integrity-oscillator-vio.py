import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 20
    smooth_len = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # 1. Chaikin Money Flow (CMF) Logic
        def calc_cmf():
            range_val = high - low
            mf_multiplier = np.where(range_val == 0, 0, ((close - low) - (high - close)) / range_val)
            mf_volume = mf_multiplier * volume
            cmf_sma = pta.sma(pd.Series(mf_volume), length=self.len)
            vol_sma = pta.sma(volume, length=self.len)
            cmf_val = cmf_sma / (vol_sma + 1e-10)
            return cmf_val
        
        self.cmf = self.I(calc_cmf)
        
        # 2. Normalized CCI
        def calc_cci_norm():
            cci_val = pta.cci(high, low, close, length=self.len)
            return cci_val / 250 if cci_val is not None else pd.Series(0, index=close.index)
        
        self.cci_norm = self.I(calc_cci_norm)
        
        # 3. OBV Trend Normalization (Z-Score approach)
        def calc_obv_norm():
            obv_val = pta.obv(close, volume)
            obv_sma = pta.sma(obv_val, length=self.len)
            obv_stdev = pta.stdev(obv_val, length=self.len)
            obv_norm = (obv_val - obv_sma) / (obv_stdev + 1e-10)
            obv_final = np.clip(obv_norm, -1, 1)
            return obv_final
        
        self.obv_final = self.I(calc_obv_norm)
        
        # 4. VWMA Deviation
        def calc_vwma_diff():
            vwma_val = pta.vwma(close, volume, length=self.len)
            vwma_diff = ((close - vwma_val) / vwma_val) * 5
            return vwma_diff
        
        self.vwma_diff = self.I(calc_vwma_diff)
        
        # Integrated Oscillator (VIO)
        def calc_vio_raw():
            vio = (self.cci_norm * 0.25) + (self.cmf * 0.35) + (self.obv_final * 0.20) + (self.vwma_diff * 0.20)
            return vio
        
        self.vio_raw = self.I(calc_vio_raw)
        
        # VIO Smoothed with EMA
        def calc_vio_smooth():
            vio_smooth = pta.ema(self.vio_raw, length=self.smooth_len)
            return vio_smooth if vio_smooth is not None else pd.Series(0, index=close.index)
        
        self.vio_smooth = self.I(calc_vio_smooth)

    def next(self):
        # Buy signal: VIO crosses above 0
        if crossover(self.vio_smooth, 0):
            self.buy()
        # Sell signal: VIO crosses below 0
        elif crossover(0, self.vio_smooth):
            self.sell()