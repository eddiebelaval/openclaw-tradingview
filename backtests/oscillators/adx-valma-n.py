import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 14
    offset_valma = 0.7
    sigma = 4.0
    th = 22
    normLen = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        def valma_calc(src, length, off, sig):
            vol = volume.fillna(1)
            alma_src = pta.alma(src * vol, length=length, offset=off, sigma=sig)
            alma_vol = pta.alma(vol, length=length, offset=off, sigma=sig)
            result = alma_src / alma_vol.replace(0, 1e-10)
            return result

        def normalize_calc(src, length):
            minVal = src.rolling(length).min()
            maxVal = src.rolling(length).max()
            result = 100 * (src - minVal) / (maxVal - minVal).clip(lower=1e-10)
            return result

        def dm_calc():
            up = high.diff()
            down = -low.diff()
            
            plusDM = pd.Series(0, index=close.index)
            minusDM = pd.Series(0, index=close.index)
            
            for i in range(1, len(close)):
                if pd.notna(up.iloc[i]):
                    if up.iloc[i] > down.iloc[i] and up.iloc[i] > 0:
                        plusDM.iloc[i] = up.iloc[i]
                    else:
                        plusDM.iloc[i] = 0
                        
                if pd.notna(down.iloc[i]):
                    if down.iloc[i] > up.iloc[i] and down.iloc[i] > 0:
                        minusDM.iloc[i] = down.iloc[i]
                    else:
                        minusDM.iloc[i] = 0
            
            tr = pta.true_range(high, low, close)
            return plusDM, minusDM, tr

        plusDM, minusDM, tr = dm_calc()

        self.smoothedPlusDM = self.I(lambda: valma_calc(plusDM, self.len, self.offset_valma, self.sigma) or pd.Series(0, index=close.index))
        self.smoothedMinusDM = self.I(lambda: valma_calc(minusDM, self.len, self.offset_valma, self.sigma) or pd.Series(0, index=close.index))
        self.smoothedTR = self.I(lambda: valma_calc(tr, self.len, self.offset_valma, self.sigma) or pd.Series(1, index=close.index))

        def di_calc():
            diPlus = (self.smoothedPlusDM / self.smoothedTR.replace(0, 1e-10)) * 100
            diMinus = (self.smoothedMinusDM / self.smoothedTR.replace(0, 1e-10)) * 100
            return diPlus, diMinus

        def adx_calc():
            diPlus = (self.smoothedPlusDM / self.smoothedTR.replace(0, 1e-10)) * 100
            diMinus = (self.smoothedMinusDM / self.smoothedTR.replace(0, 1e-10)) * 100
            dx = (np.abs(diPlus - diMinus) / np.maximum(diPlus + diMinus, 1e-10)) * 100
            adx_raw = valma_calc(dx, self.len, self.offset_valma, self.sigma)
            adx_final = normalize_calc(adx_raw, self.normLen)
            return adx_final, diPlus, diMinus

        self.adx_final, self.diPlus, self.diMinus = self.I(adx_calc)

    def next(self):
        if len(self.data) < 2:
            return

        if crossover(self.diPlus, self.diMinus):
            if not self.position:
                self.buy()
        elif crossover(self.diMinus, self.diPlus):
            if self.position:
                self.position.close()