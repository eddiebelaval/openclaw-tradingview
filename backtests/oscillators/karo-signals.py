import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLength = 200
    showEMA = False
    useEMAFilter = True
    atrLength = 14
    atrMult = 0.6
    macdFast = 8
    macdSlow = 21
    macdSignal = 5
    rsiLength = 14
    useDivergence = True
    pivotLen = 5
    useSetups = True
    slLookback = 10
    slBars = 8
    cooldownBars = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)

        # EMA200
        self.ema200 = self.I(pta.ema, close, length=self.emaLength)

        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal))
        self.macdLine = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal)['MACD_8_21_5'])
        self.signalLine = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal)['SIGNAL_8_21_5'])
        self.hist = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal)['HIST_8_21_5'])

        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)

        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)

        # Candle metrics
        self.body = self.I(lambda: (close - open_).abs())
        self.candleRange = self.I(lambda: high - low)

        # Lowest low and highest high for stop loss
        self.longSL = self.I(lambda: low.rolling(window=self.slLookback).min())
        self.shortSL = self.I(lambda: high.rolling(window=self.slLookback).max())

        # Last signal bar tracker
        self.lastSignalBar = -np.inf

    def next(self):
        if len(self.data.Close) < max(self.emaLength, self.macdSlow, self.rsiLength, self.slLookback) + 10:
            return

        # Current values
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        atr_val = self.atr[-1] if self.atr[-1] is not None and not np.isnan(self.atr[-1]) else 0
        buffer = atr_val * self.atrMult

        ema200_val = self.ema200[-1] if self.ema200[-1] is not None and not np.isnan(self.ema200[-1]) else close_val
        rsi_val = self.rsi[-1] if self.rsi[-1] is not None and not np.isnan(self.rsi[-1]) else 50

        macdLine_val = self.macdLine[-1] if self.macdLine[-1] is not None and not np.isnan(self.macdLine[-1]) else 0
        signalLine_val = self.signalLine[-1] if self.signalLine[-1] is not None and not np.isnan(self.signalLine[-1]) else 0
        
        macdLine_prev = self.macdLine[-2] if len(self.macdLine) > 1 and self.macdLine[-2] is not None and not np.isnan(self.macdLine[-2]) else 0
        signalLine_prev = self.signalLine[-2] if len(self.signalLine) > 1 and self.signalLine[-2] is not None and not np.isnan(self.signalLine[-2]) else 0
        hist_val = self.hist[-1] if self.hist[-1] is not None and not np.isnan(self.hist[-1]) else 0
        hist_prev = self.hist[-2] if len(self.hist) > 1 and self.hist[-2] is not None and not np.isnan(self.hist[-2]) else 0

        body_val = self.body[-1] if self.body[-1] is not None and not np.isnan(self.body[-1]) else 0
        candleRange_val = self.candleRange[-1] if self.candleRange[-1] is not None and not np.isnan(self.candleRange[-1]) else 1

        longSL_val = self.longSL[-1] if self.longSL[-1] is not None and not np.isnan(self.longSL[-1]) else self.data.Low[-1]
        shortSL_val = self.shortSL[-1] if self.shortSL[-1] is not None and not np.isnan(self.shortSL[-1]) else self.data.High[-1]

        # Trend filters
        trendLong = not self.useEMAFilter or close_val > ema200_val + buffer
        trendShort = not self.useEMAFilter or close_val < ema200_val - buffer

        # Momentum
        rsiLong = rsi_val > 55
        rsiShort = rsi_val < 45

        macdLong = crossover(self.macdLine, self.signalLine)
        macdShort = crossover(self.signalLine, self.macdLine)

        histUp = hist_val > hist_prev
        histDown = hist_val < hist_prev

        # Impulse candle
        impulse = body_val > candleRange_val * 0.6

        # Cooldown
        cooldownOK = len(self.data.Close) - self.lastSignalBar > self.cooldownBars

        # Entry signals
        longEntry = trendLong and macdLong and rsiLong and histUp and impulse and cooldownOK
        shortEntry = trendShort and macdShort and rsiShort and histDown and impulse and cooldownOK

        if longEntry:
            if not self.position:
                self.buy()
            self.lastSignalBar = len(self.data.Close)
        elif shortEntry:
            if self.position:
                self.position.close()
            self.lastSignalBar = len(self.data.Close)

        # Setup signals
        macdDistance = abs(macdLine_val - signalLine_val)
        setupThreshold = atr_val * 0.02

        longSetup = (self.useSetups and trendLong and rsi_val > 50 and
                     macdLine_val < signalLine_val and macdLine_val > macdLine_prev and
                     macdDistance < setupThreshold)

        shortSetup = (self.useSetups and trendShort and rsi_val < 50 and
                      macdLine_val > signalLine_val and macdLine_val < macdLine_prev and
                      macdDistance < setupThreshold)

        # Exit on setup signals (optional, can be removed)
        if longSetup and not self.position:
            self.buy()
        elif shortSetup and self.position:
            self.position.close()

        # Simple exit on trend reversal
        if self.position and trendShort:
            self.position.close()
        elif not self.position and trendLong and self.position.is_short:
            self.position.close()


