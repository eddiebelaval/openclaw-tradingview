import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 100
    sensitivity = 1.0
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.periods = [5, 8, 13, 21, 34, 55, 89, 120]
        
        self.osc_value = self.I(self._compute_oscillator, close, high, low)
    
    def _compute_oscillator(self, close, high, low):
        result = np.zeros(len(close))
        
        for i in range(len(close)):
            if i < self.lookback:
                result[i] = 50.0
                continue
            
            lookback_data = close.iloc[max(0, i - self.lookback + 1):i + 1].values
            
            if len(lookback_data) < 2:
                result[i] = 50.0
                continue
            
            mn = np.mean(lookback_data)
            sd = np.std(lookback_data)
            
            if sd == 0:
                norm_data = np.zeros_like(lookback_data)
            else:
                norm_data = (lookback_data - mn) / sd
            
            dom_amp = 0.0
            dom_phase = 0.0
            
            for period in self.periods:
                omega = 2.0 * np.pi / period
                s_cos = 0.0
                s_sin = 0.0
                window = min(len(norm_data) - 1, 99)
                
                for k in range(window + 1):
                    if k < len(norm_data):
                        val = norm_data[-(k + 1)]
                        angle = omega * k
                        s_cos += val * np.cos(angle)
                        s_sin += val * np.sin(angle)
                
                amp = min(np.sqrt(s_cos * s_cos + s_sin * s_sin) / len(norm_data) * 100.0 * self.sensitivity, 100.0)
                phase = np.arctan2(s_sin, s_cos)
                
                if amp > dom_amp:
                    dom_amp = amp
                    dom_phase = phase
            
            osc_raw = np.cos(dom_phase)
            osc_val = 50.0 + 50.0 * osc_raw
            result[i] = osc_val
        
        return result
    
    def next(self):
        if len(self) < self.lookback + 1:
            return
        
        osc = self.osc_value[-1]
        osc_prev = self.osc_value[-2] if len(self.osc_value) > 1 else 50.0
        
        if crossover(self.osc_value, 50):
            if not self.position:
                self.buy()
        
        elif crossover(50, self.osc_value):
            if self.position:
                self.position.close()
        
        elif osc > 80 and osc_prev <= 80:
            if self.position:
                self.position.close()
        
        elif osc < 20 and osc_prev >= 20:
            if not self.position:
                self.buy()


