import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_len = 20
    use_ema = False
    require_rising_ma = False
    ret_len = 5
    corr_len = 90
    min_corr = 0.20
    switch_delta = 0.05
    piv_l = 5
    piv_r = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Helper function for MA
        def get_ma(src, length):
            if self.use_ema:
                return pta.ema(src, length=length)
            else:
                return pta.sma(src, length=length)
        
        # RS ratios (simplified: using close only, no multi-symbol data)
        def rs_ratio():
            return close / close.shift(1)
        
        # Moving average of RS ratio
        def ma_rs():
            rs = rs_ratio()
            return get_ma(rs, self.ma_len)
        
        # Signal: % above/below MA
        def signal_series():
            rs = rs_ratio()
            ma_rs_val = ma_rs()
            sig = pd.Series(np.where(ma_rs_val != 0, 100.0 * (rs / ma_rs_val - 1.0), np.nan), index=close.index)
            return sig
        
        # Green condition: RS > MA
        def green_condition():
            rs = rs_ratio()
            ma_rs_val = ma_rs()
            if self.require_rising_ma:
                ma_rising = ma_rs_val >= ma_rs_val.shift(1)
                return (rs > ma_rs_val) & ma_rising
            else:
                return rs > ma_rs_val
        
        # Pivot points for divergence
        def pivot_low_price():
            return low.rolling(window=2*self.piv_l+1, center=True).min() == low
        
        def pivot_high_price():
            return high.rolling(window=2*self.piv_l+1, center=True).max() == high
        
        def pivot_low_rs():
            rs = rs_ratio()
            return rs.rolling(window=2*self.piv_l+1, center=True).min() == rs
        
        def pivot_high_rs():
            rs = rs_ratio()
            return rs.rolling(window=2*self.piv_l+1, center=True).max() == rs
        
        # Store indicators
        self.signal = self.I(signal_series)
        self.green = self.I(green_condition)
        self.rs_ratio = self.I(rs_ratio)
        self.ma_rs = self.I(ma_rs)
        self.pivot_low_p = self.I(pivot_low_price)
        self.pivot_high_p = self.I(pivot_high_price)
        self.pivot_low_rs = self.I(pivot_low_rs)
        self.pivot_high_rs = self.I(pivot_high_rs)
        
        # Divergence tracking
        self.prev_pl_p = None
        self.prev_pl_rs = None
        self.prev_ph_p = None
        self.prev_ph_rs = None
        self.bull_div = False
        self.bear_div = False

    def next(self):
        # Check for signal crossovers
        if len(self) < 2:
            return
        
        signal_current = self.signal[-1]
        signal_prev = self.signal[-2]
        
        # Entry condition: signal crosses above 0 (RS crosses above MA)
        if not np.isnan(signal_current) and not np.isnan(signal_prev):
            if signal_prev <= 0 < signal_current:
                if not self.position:
                    self.buy()
            # Exit condition: signal crosses below 0 (RS crosses below MA)
            elif signal_prev >= 0 > signal_current:
                if self.position:
                    self.sell()
        
        # Alternative: use green condition for entries
        if len(self) >= 2:
            green_current = self.green[-1]
            green_prev = self.green[-2] if len(self) > 1 else False
            
            # Entry on green condition becoming true
            if green_current and not green_prev:
                if not self.position:
                    self.buy()
            # Exit on green condition becoming false
            elif not green_current and green_prev:
                if self.position:
                    self.sell()


