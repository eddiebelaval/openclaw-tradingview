import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLength = 14
    lookback = 50
    smoothOutput = 3
    useTrueRange = False
    useDollarVol = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)

        # True Range calculation
        def calc_tr():
            tr1 = high - low
            tr2 = np.abs(high - close.shift(1))
            tr3 = np.abs(low - close.shift(1))
            tr = np.maximum(tr1, np.maximum(tr2, tr3))
            return pd.Series(tr, index=close.index)

        tr = self.I(calc_tr)

        # ATR using RMA (Wilder's moving average)
        def calc_atr():
            tr_series = calc_tr()
            if len(tr_series) < self.atrLength:
                return tr_series
            atr_vals = tr_series.ewm(alpha=1/self.atrLength, adjust=False).mean()
            return atr_vals

        atr = self.I(calc_atr)

        # Price move (close-to-close or true range normalized by ATR)
        def calc_move():
            tr_series = calc_tr()
            atr_series = calc_atr()
            atr_series = atr_series.replace(0, 1)
            
            if self.useTrueRange:
                moveRaw = tr_series / atr_series
            else:
                ccMove = np.abs(close - close.shift(1)) / atr_series
                moveRaw = ccMove
            return moveRaw

        moveRaw = self.I(calc_move)

        # Volume calculation
        def calc_vol_raw():
            if self.useDollarVol:
                volBase = volume * close
            else:
                volBase = volume
            volRaw = np.log(volBase.replace(0, 1e-8))
            return volRaw

        volRaw = self.I(calc_vol_raw)

        # Standardize (Z-scores)
        def calc_z_move():
            move = calc_move()
            moveMean = move.rolling(window=self.lookback).mean()
            moveStd = move.rolling(window=self.lookback).std()
            moveStd = moveStd.replace(0, 1)
            zMove = (move - moveMean) / moveStd
            return zMove.fillna(0)

        zMove = self.I(calc_z_move)

        def calc_z_vol():
            vol = calc_vol_raw()
            volMean = vol.rolling(window=self.lookback).mean()
            volStd = vol.rolling(window=self.lookback).std()
            volStd = volStd.replace(0, 1)
            zVol = (vol - volMean) / volStd
            return zVol.fillna(0)

        zVol = self.I(calc_z_vol)

        # Linear regression for expected volume
        def calc_expected_zvol():
            zmove = calc_z_move()
            zvol = calc_z_vol()
            
            meanZMove = zmove.rolling(window=self.lookback).mean()
            meanZVol = zvol.rolling(window=self.lookback).mean()
            
            cov = ((zmove - meanZMove) * (zvol - meanZVol)).rolling(window=self.lookback).mean()
            var = ((zmove - meanZMove) ** 2).rolling(window=self.lookback).mean()
            var = var.replace(0, 1)
            
            beta = cov / var
            alpha = meanZVol - beta * meanZMove
            
            expectedZVol = alpha + beta * zmove
            return expectedZVol.fillna(0)

        expectedZVol = self.I(calc_expected_zvol)

        # Calculate residual and smooth signal
        def calc_signal():
            zvol = calc_z_vol()
            expected = calc_expected_zvol()
            rawResidual = zvol - expected
            signal = rawResidual.rolling(window=self.smoothOutput).mean()
            return signal.fillna(0)

        self.signal = self.I(calc_signal)

    def next(self):
        # Entry: when signal crosses above -1 (volume bullish divergence)
        if len(self.signal) > 1:
            if crossover(self.signal, -1):
                if not self.position:
                    self.buy()
            # Exit: when signal crosses below 1 (volume bearish divergence)
            elif crossover(1, self.signal):
                if self.position:
                    self.position.close()
            # Also exit on crossing back through 0 if in position
            elif self.position and crossover(0, self.signal):
                self.position.close()