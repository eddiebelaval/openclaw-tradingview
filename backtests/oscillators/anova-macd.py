import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLength = 12
    slowLength = 26
    signalSmoothing = 9

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Simple ANOVA approximation using price momentum
        # Since the library function is not available, use a momentum-based approach
        def calculate_anova_macd():
            anova = close.copy()
            for i in range(len(close)):
                if i > 0:
                    price_range = high.iloc[i] - low.iloc[i]
                    anova.iloc[i] = close.iloc[i] * (1 + (price_range / close.iloc[i]) * 0.1)
                else:
                    anova.iloc[i] = close.iloc[i]
            return anova
        
        anova = self.I(calculate_anova_macd)
        
        # Calculate MACD using ANOVA data
        ema_fast = self.I(pta.ema, anova, length=self.fastLength)
        ema_slow = self.I(pta.ema, anova, length=self.slowLength)
        
        self.macd = self.I(lambda: ema_fast - ema_slow)
        self.signal = self.I(pta.ema, self.macd, length=self.signalSmoothing)
        self.histogram = self.I(lambda: self.macd - self.signal)

    def next(self):
        # Buy when MACD crosses above signal line
        if crossover(self.macd, self.signal):
            if not self.position:
                self.buy()
        # Sell when MACD crosses below signal line
        elif crossover(self.signal, self.macd):
            if self.position:
                self.position.close()