import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_len = 14
    cmo_len = 14
    er_len = 10
    vortex_len = 14
    smooth_len = 3
    ob_level = 65.0
    os_level = -65.0
    sq_len = 20
    bb_mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # 1. Normalized RSI Momentum
        rsi_raw = self.I(pta.rsi, close, length=self.rsi_len)
        rsi_norm = self.I(lambda: (rsi_raw - 50.0) * 2.0)

        # 2. Kaufman Efficiency Ratio (ER)
        def calc_er():
            er_values = []
            for i in range(len(close)):
                if i < self.er_len:
                    er_values.append(0.0)
                else:
                    price_change = abs(close.iloc[i] - close.iloc[i - self.er_len])
                    path_length = 0.0
                    for j in range(self.er_len):
                        path_length += abs(close.iloc[i - j] - close.iloc[i - j - 1])
                    er_val = price_change / path_length if path_length != 0.0 else 0.5
                    er_dir = 1.0 if close.iloc[i] > close.iloc[i - self.er_len] else -1.0
                    er_values.append(er_val * er_dir * 100.0)
            return pd.Series(er_values, index=close.index)

        er_norm = self.I(calc_er)

        # 3. Vortex Indicator Strength
        def calc_vortex():
            vortex_values = []
            for i in range(len(close)):
                if i < self.vortex_len:
                    vortex_values.append(0.0)
                else:
                    vm_plus = 0.0
                    vm_minus = 0.0
                    tr_sum = 0.0
                    for j in range(self.vortex_len):
                        idx = i - j
                        vm_plus += abs(high.iloc[idx] - low.iloc[idx - 1]) if idx > 0 else 0.0
                        vm_minus += abs(low.iloc[idx] - high.iloc[idx - 1]) if idx > 0 else 0.0
                        tr_val = max(high.iloc[idx] - low.iloc[idx],
                                   abs(high.iloc[idx] - close.iloc[idx - 1]) if idx > 0 else 0.0,
                                   abs(low.iloc[idx] - close.iloc[idx - 1]) if idx > 0 else 0.0)
                        tr_sum += tr_val
                    vi_plus = vm_plus / tr_sum if tr_sum != 0.0 else 1.0
                    vi_minus = vm_minus / tr_sum if tr_sum != 0.0 else 1.0
                    vortex_diff = (vi_plus - vi_minus) * 100.0
                    vortex_values.append(vortex_diff)
            return pd.Series(vortex_values, index=close.index)

        vortex_diff = self.I(calc_vortex)

        # 4. Chande Momentum Oscillator (CMO)
        def calc_cmo():
            cmo_values = []
            for i in range(len(close)):
                if i < self.cmo_len:
                    cmo_values.append(0.0)
                else:
                    up_sum = 0.0
                    down_sum = 0.0
                    for j in range(self.cmo_len):
                        idx = i - j
                        diff = close.iloc[idx] - close.iloc[idx - 1] if idx > 0 else 0.0
                        up_sum += diff if diff > 0.0 else 0.0
                        down_sum += abs(diff) if diff < 0.0 else 0.0
                    cmo_val = ((up_sum - down_sum) / (up_sum + down_sum)) * 100.0 if (up_sum + down_sum) != 0.0 else 0.0
                    cmo_values.append(cmo_val)
            return pd.Series(cmo_values, index=close.index)

        cmo = self.I(calc_cmo)

        # 5. Composite Confluence Score (QMC)
        w1, w2, w3, w4 = 0.30, 0.25, 0.20, 0.25
        qmc_raw = self.I(lambda: (rsi_norm * w1) + (er_norm * w2) + (vortex_diff * w3) + (cmo * w4))
        qmc = self.I(pta.ema, qmc_raw, length=self.smooth_len)
        qmc_sig = self.I(pta.ema, qmc, length=self.smooth_len + 2)
        qmc_hist = self.I(lambda: qmc - qmc_sig)

        # 6. Bollinger Band Squeeze Detection
        bb_basis = self.I(pta.sma, close, length=self.sq_len)
        
        def calc_bb_squeeze():
            bb_dev = close.rolling(window=self.sq_len).std()
            bb_upper = bb_basis + self.bb_mult * bb_dev
            bb_lower = bb_basis - self.bb_mult * bb_dev
            bb_width = (bb_upper - bb_lower) / bb_basis * 100.0
            bb_width_ma = bb_width.rolling(window=self.sq_len).mean()
            bb_squeeze = bb_width < bb_width_ma * 0.75
            return bb_squeeze
        
        bb_squeeze = self.I(calc_bb_squeeze)

        # Store indicators
        self.qmc = qmc
        self.qmc_sig = qmc_sig
        self.qmc_hist = qmc_hist
        self.bb_squeeze = bb_squeeze

    def next(self):
        if len(self.data) < 2:
            return

        # Bull cross: QMC crosses above signal line
        if crossover(self.qmc, self.qmc_sig):
            if not self.position:
                self.buy()
        # Bear cross: QMC crosses below signal line
        elif crossover(self.qmc_sig, self.qmc):
            if self.position:
                self.position.close()
        
        # Additional exit on overbought reversal
        if len(self.data) > 1:
            if self.qmc[-1] > self.ob_level and self.qmc[-2] > self.qmc[-1]:
                if self.position:
                    self.position.close()


