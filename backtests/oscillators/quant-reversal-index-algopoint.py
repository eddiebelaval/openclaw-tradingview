import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Quantitative Core Settings
    quant_len = 100
    ou_mult = 2.0
    hurst_threshold = 0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Hurst Exponent Calculation (Variance Ratio Approximation)
        tau1 = 2
        tau2 = 8

        def calc_hurst():
            hurst_values = []
            for i in range(len(close)):
                if i < self.quant_len:
                    hurst_values.append(np.nan)
                else:
                    window_close = close.iloc[i - self.quant_len + 1:i + 1].values
                    var1 = np.var(window_close - np.roll(window_close, tau1)[:self.quant_len])
                    var2 = np.var(window_close - np.roll(window_close, tau2)[:self.quant_len])
                    if var1 > 0 and var2 > 0:
                        h = (np.log(var2) - np.log(var1)) / (2 * (np.log(tau2) - np.log(tau1)))
                        hurst_values.append(h)
                    else:
                        hurst_values.append(np.nan)
            return pd.Series(hurst_values, index=close.index)

        self.hurst_value = self.I(calc_hurst)

        # Mean Reverting Regime
        def is_mean_reverting_calc():
            return self.hurst_value < self.hurst_threshold

        self.is_mean_reverting = self.I(is_mean_reverting_calc)

        # Half-Life Calculation (AR(1) Model)
        def calc_half_life():
            half_life_values = []
            delta_p = close.diff()
            p_prev = close.shift(1)

            for i in range(len(close)):
                if i < self.quant_len:
                    half_life_values.append(np.nan)
                else:
                    window_delta = delta_p.iloc[i - self.quant_len + 1:i + 1]
                    window_p_prev = p_prev.iloc[i - self.quant_len + 1:i + 1]

                    mean_delta = window_delta.mean()
                    mean_p = window_p_prev.mean()

                    cov_p = ((window_delta - mean_delta) * (window_p_prev - mean_p)).mean()
                    var_p = window_p_prev.var()

                    if var_p > 0:
                        lambda_val = cov_p / var_p
                        if lambda_val < 0:
                            hl = -np.log(2) / lambda_val
                            half_life_values.append(hl)
                        else:
                            half_life_values.append(np.nan)
                    else:
                        half_life_values.append(np.nan)

            return pd.Series(half_life_values, index=close.index)

        self.half_life = self.I(calc_half_life)

        # Dynamic Half-Life Length
        def calc_hl_len():
            hl_len_values = []
            for i in range(len(close)):
                hl = self.half_life[i]
                if pd.isna(hl) or hl <= 2 or hl > 100:
                    hl_len_values.append(20)
                else:
                    hl_len_values.append(int(round(hl)))
            return pd.Series(hl_len_values, index=close.index)

        self.hl_len = self.I(calc_hl_len)

        # OU Mean and Sigma with Dynamic Length
        def calc_ou_params():
            mu_values = []
            sigma_values = []
            for i in range(len(close)):
                hl = self.hl_len[i]
                if i < hl:
                    mu_values.append(close.iloc[:i + 1].mean())
                    sigma_values.append(close.iloc[:i + 1].std())
                else:
                    window = close.iloc[i - hl + 1:i + 1]
                    mu_values.append(window.mean())
                    sigma_values.append(window.std())
            return pd.Series(mu_values, index=close.index), pd.Series(sigma_values, index=close.index)

        self.mu, self.sigma = self.I(calc_ou_params)

        # Upper and Lower OU Bands
        def calc_ou_bands():
            upper = self.mu + (self.ou_mult * self.sigma)
            lower = self.mu - (self.ou_mult * self.sigma)
            return upper, lower

        self.upper_ou, self.lower_ou = self.I(calc_ou_bands)

        # Quant Index (0-100 normalized)
        def calc_quant_index():
            quant_index_values = []
            for i in range(len(close)):
                band_range = self.upper_ou[i] - self.lower_ou[i]
                if band_range != 0:
                    idx = ((close.iloc[i] - self.lower_ou[i]) / band_range) * 100
                    quant_index_values.append(idx)
                else:
                    quant_index_values.append(np.nan)
            return pd.Series(quant_index_values, index=close.index)

        self.quant_index = self.I(calc_quant_index)

    def next(self):
        # Buy Signal: Quant Index crosses above 0 while in mean reverting regime
        if len(self.quant_index) < 2:
            return

        buy_signal = (
            crossover(self.quant_index, 0) and
            self.is_mean_reverting[-1]
        )

        # Sell Signal: Quant Index crosses below 100 while in mean reverting regime
        sell_signal = (
            crossover(100, self.quant_index) and
            self.is_mean_reverting[-1]
        )

        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.position.close()