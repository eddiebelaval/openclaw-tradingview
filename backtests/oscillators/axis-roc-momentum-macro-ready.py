import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    roc_length = 11

    def init(self):
        close = pd.Series(self.data.Close)
        
        def calculate_roc():
            roc_values = []
            for i in range(len(close)):
                if i < self.roc_length:
                    roc_values.append(np.nan)
                else:
                    roc = ((close.iloc[i] - close.iloc[i - self.roc_length]) / close.iloc[i - self.roc_length]) * 100
                    roc_values.append(roc)
            return pd.Series(roc_values, index=close.index)
        
        self.roc = self.I(calculate_roc)

    def next(self):
        if len(self.data) < self.roc_length + 1:
            return
        
        current_roc = self.roc[-1]
        prev_roc = self.roc[-2]
        
        if pd.isna(current_roc) or pd.isna(prev_roc):
            return
        
        if crossover(self.roc, 0):
            if not self.position:
                self.buy()
        elif crossover(0, self.roc):
            if self.position:
                self.position.close()