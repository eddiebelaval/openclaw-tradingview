import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    maLen = 14
    obLevel = 70
    osLevel = 30
    atrLen = 14
    slMult = 1.5
    tpMult = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI calculation
        self.rsi = self.I(self._calc_rsi, close)
        
        # RSI SMA
        self.rsi_ma = self.I(lambda: pta.sma(self.rsi, length=self.maLen) if len(self.rsi) > 0 else pd.Series(50, index=close.index))
        
        # ATR for stop loss and take profit
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Track active trades
        self.in_trade = False
        self.entry_price = None
        self.sl_price = None
        self.tp_price = None
        self.trade_type = None  # 'long' or 'short'

    def _calc_rsi(self, src):
        """Custom RSI calculation using RMA (EMA)"""
        delta = src.diff()
        gain = delta.clip(lower=0)
        loss = -delta.clip(upper=0)
        
        # Use EMA (RMA equivalent)
        avg_gain = pta.ema(gain, length=self.rsiLen)
        avg_loss = pta.ema(loss, length=self.rsiLen)
        
        rs = avg_gain / avg_loss
        rsi = 100 - (100 / (1 + rs))
        
        return rsi.fillna(50)

    def next(self):
        if not self.in_trade:
            # Buy signal: RSI crosses above oversold level
            if len(self.rsi) > 1:
                if crossover(self.rsi, self.osLevel):
                    self.entry_price = self.data.Close[-1]
                    atr_val = self.atr[-1] if self.atr[-1] is not None else 0
                    if atr_val > 0:
                        self.sl_price = self.entry_price - (atr_val * self.slMult)
                        self.tp_price = self.entry_price + (atr_val * self.tpMult)
                        self.trade_type = 'long'
                        self.in_trade = True
                        self.buy()
                
                # Sell signal: RSI crosses below overbought level
                elif crossover(self.obLevel, self.rsi):
                    self.entry_price = self.data.Close[-1]
                    atr_val = self.atr[-1] if self.atr[-1] is not None else 0
                    if atr_val > 0:
                        self.sl_price = self.entry_price + (atr_val * self.slMult)
                        self.tp_price = self.entry_price - (atr_val * self.tpMult)
                        self.trade_type = 'short'
                        self.in_trade = True
                        self.sell()
        else:
            # Manage active trade
            if self.trade_type == 'long':
                # Check stop loss
                if self.data.Low[-1] <= self.sl_price:
                    self.sell()
                    self.in_trade = False
                # Check take profit
                elif self.data.High[-1] >= self.tp_price:
                    self.sell()
                    self.in_trade = False
            
            elif self.trade_type == 'short':
                # Check stop loss
                if self.data.High[-1] >= self.sl_price:
                    self.buy()
                    self.in_trade = False
                # Check take profit
                elif self.data.Low[-1] <= self.tp_price:
                    self.buy()
                    self.in_trade = False


