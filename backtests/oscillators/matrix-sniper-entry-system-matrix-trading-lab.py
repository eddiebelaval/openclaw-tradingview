import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 20
    slowLen = 50
    trendLen = 200
    rsiLen = 14
    atrLen = 14
    pullbackAtr = 0.25
    minAtrPct = 0.20
    slAtrMult = 1.0
    tpAtrMult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.fastEMA = self.I(pta.ema, close, length=self.fastLen)
        self.slowEMA = self.I(pta.ema, close, length=self.slowLen)
        self.trendEMA = self.I(pta.ema, close, length=self.trendLen)
        self.rsiValue = self.I(pta.rsi, close, length=self.rsiLen)
        self.atrValue = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.last_entry_price = None
        self.last_sl = None
        self.last_tp = None
        self.last_direction = None

    def next(self):
        if len(self.data.Close) < self.trendLen:
            return
        
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        fastEMA = self.fastEMA[-1]
        slowEMA = self.slowEMA[-1]
        trendEMA = self.trendEMA[-1]
        rsiValue = self.rsiValue[-1]
        atrValue = self.atrValue[-1]
        
        if atrValue is None or fastEMA is None or slowEMA is None or trendEMA is None or rsiValue is None:
            return
        
        atrPct = (atrValue / close) * 100.0 if close != 0.0 else 0.0
        volatilityOk = atrPct >= self.minAtrPct
        
        bullTrend = fastEMA > slowEMA and close > trendEMA
        bearTrend = fastEMA < slowEMA and close < trendEMA
        
        bullPullbackZone = low <= fastEMA + atrValue * self.pullbackAtr and low >= slowEMA - atrValue * self.pullbackAtr
        bearPullbackZone = high >= fastEMA - atrValue * self.pullbackAtr and high <= slowEMA + atrValue * self.pullbackAtr
        
        bullMomentum = rsiValue > 50 and rsiValue < 70
        bearMomentum = rsiValue < 50 and rsiValue > 30
        
        bullSignal = bullTrend and bullPullbackZone and bullMomentum and volatilityOk and close > open_price
        bearSignal = bearTrend and bearPullbackZone and bearMomentum and volatilityOk and close < open_price
        
        newBullSignal = False
        newBearSignal = False
        
        if len(self.data.Close) >= 2:
            prev_close = self.data.Close[-2]
            prev_open = self.data.Open[-2]
            
            if prev_close <= self.slowEMA[-2] or prev_close <= self.fastEMA[-2]:
                if bullSignal:
                    newBullSignal = True
            
            if prev_close >= self.slowEMA[-2] or prev_close >= self.fastEMA[-2]:
                if bearSignal:
                    newBearSignal = True
        
        if newBullSignal:
            if self.position:
                self.position.close()
            self.last_entry_price = close
            self.last_sl = close - atrValue * self.slAtrMult
            self.last_tp = close + atrValue * self.tpAtrMult
            self.last_direction = 1
            self.buy()
        
        if newBearSignal:
            if self.position:
                self.position.close()
            self.last_entry_price = close
            self.last_sl = close + atrValue * self.slAtrMult
            self.last_tp = close - atrValue * self.tpAtrMult
            self.last_direction = -1
            self.sell()
        
        if self.position:
            if self.last_direction == 1:
                if close <= self.last_sl:
                    self.position.close()
                elif close >= self.last_tp:
                    self.position.close()
            elif self.last_direction == -1:
                if close >= self.last_sl:
                    self.position.close()
