import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime


class TvStrategy(Strategy):
    # EMA Parameters
    e1 = 8
    e2 = 21
    e3 = 55
    e3_slope_bars = 10
    
    # MACD Parameters
    m1 = 12
    m2 = 26
    m3 = 9
    use_macd_zero = True
    
    # RSI Parameters
    r_len = 14
    r_long_min = 50
    r_long_max = 68
    r_short_max = 50
    r_short_min = 32
    
    # ATR Risk Parameters
    a_len = 14
    sl_m = 1.0
    tp1_m = 2.0
    tp2_m = 5.0
    use_be = True
    
    # ADX Parameters
    adx_min = 20
    
    # Candle Filter
    use_candle = True
    
    # Session Filter
    use_session = True
    kst_block_start = 0
    kst_block_end = 6
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema1 = self.I(pta.ema, close, length=self.e1)
        self.ema2 = self.I(pta.ema, close, length=self.e2)
        self.ema3 = self.I(pta.ema, close, length=self.e3)
        
        # Calculate MACD
        macd_result = self.I(lambda x: pta.macd(x, fast=self.m1, slow=self.m2, signal=self.m3), close)
        self.macd_line = self.I(lambda x: pta.macd(x, fast=self.m1, slow=self.m2, signal=self.m3)['MACD_12_26_9'] if pta.macd(x, fast=self.m1, slow=self.m2, signal=self.m3) is not None else pd.Series(0, index=x.index), close)
        self.macd_signal = self.I(lambda x: pta.macd(x, fast=self.m1, slow=self.m2, signal=self.m3)['MACDh_12_26_9'] if pta.macd(x, fast=self.m1, slow=self.m2, signal=self.m3) is not None else pd.Series(0, index=x.index), close)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.r_len)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.a_len)
        
        # Calculate ADX
        adx_result = self.I(lambda h, l, c: pta.adx(h, l, c, length=14), high, low, close)
        self.adx = self.I(lambda h, l, c: pta.adx(h, l, c, length=14)['ADX_14'] if pta.adx(h, l, c, length=14) is not None else pd.Series(20, index=h.index), high, low, close)
        
        self.entry_price = None
        self.be_active = False
        self.long_sl = None
        self.long_tp1 = None
        self.long_tp2 = None
        self.short_sl = None
        self.short_tp1 = None
        self.short_tp2 = None
        
    def next(self):
        # Get current values
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        ema1_val = self.ema1[-1]
        ema2_val = self.ema2[-1]
        ema3_val = self.ema3[-1]
        
        ema1_prev = self.ema1[-2] if len(self.ema1) > 1 else ema1_val
        ema2_prev = self.ema2[-2] if len(self.ema2) > 1 else ema2_val
        ema3_prev = self.ema3[-2] if len(self.ema3) > 1 else ema3_val
        
        # EMA slope check (compare with bars back)
        ema3_slope_idx = max(0, len(self.ema3) - self.e3_slope_bars - 1)
        ema3_slope_val = self.ema3[ema3_slope_idx] if ema3_slope_idx >= 0 else ema3_val
        
        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0.1
        adx_val = self.adx[-1] if self.adx[-1] is not None else 20
        
        macd_val = self.macd_line[-1] if len(self.macd_line) > 0 and self.macd_line[-1] is not None else 0
        macd_prev = self.macd_line[-2] if len(self.macd_line) > 1 and self.macd_line[-2] is not None else 0
        macd_signal_val = self.macd_signal[-1] if len(self.macd_signal) > 0 and self.macd_signal[-1] is not None else 0
        macd_signal_prev = self.macd_signal[-2] if len(self.macd_signal) > 1 and self.macd_signal[-2] is not None else 0
        
        # EMA alignment
        bull_align = ema1_val > ema2_val and ema2_val > ema3_val
        bear_align = ema1_val < ema2_val and ema2_val < ema3_val
        
        # EMA slope
        ema3_up = ema3_val > ema3_slope_val
        ema3_down = ema3_val < ema3_slope_val
        
        # MACD crossover
        macd_up = crossover(self.macd_line, self.macd_signal)
        macd_down = crossover(self.macd_signal, self.macd_line)
        
        # MACD zero line filter
        macd_zero_long = not self.use_macd_zero or macd_val > 0 or macd_val > macd_prev
        macd_zero_short = not self.use_macd_zero or macd_val < 0 or macd_val < macd_prev
        
        # RSI ranges
        rsi_long_ok = rsi_val >= self.r_long_min and rsi_val <= self.r_long_max
        rsi_short_ok = rsi_val <= self.r_short_max and rsi_val >= self.r_short_min
        
        # ADX check
        adx_ok = adx_val >= self.adx_min
        
        # Candle direction
        bull_candle = not self.use_candle or close > open_
        bear_candle = not self.use_candle or close < open_
        
        # Session filter (KST hour check)
        now = pd.Timestamp(self.data.index[-1])
        kst_time = now.tz_localize('UTC').tz_convert('Asia/Seoul')
        kst_hour = kst_time.hour
        in_block = kst_hour >= self.kst_block_start and kst_hour < self.kst_block_end
        session_ok = not self.use_session or not in_block
        
        # Entry signals
        long_sig = (macd_up and bull_align and ema3_up and rsi_long_ok and 
                   adx_ok and macd_zero_long and bull_candle and session_ok and 
                   self.position.size == 0)
        
        short_sig = (macd_down and bear_align and ema3_down and rsi_short_ok and 
                    adx_ok and macd_zero_short and bear_candle and session_ok and 
                    self.position.size == 0)
        
        # Exit signals
        long_exit = (crossover(self.ema2, self.ema1) or rsi_val > self.r_long_max + 5)
        short_exit = (crossover(self.ema1, self.ema2) or rsi_val < self.r_short_min - 5)
        
        # TP1 hit check
        if self.position.size > 0 and high >= self.entry_price + atr_val * self.tp1_m:
            self.be_active = True
        if self.position.size < 0 and low <= self.entry_price - atr_val * self.tp1_m:
            self.be_active = True
        
        # Breakeven stop logic
        if self.position.size > 0:
            cur_sl = (self.entry_price + atr_val * 0.1) if (self.be_active and self.use_be) else self.long_sl
            if self.be_active and self.use_be and low < self.entry_price + atr_val * 0.1:
                self.position.close()
        
        if self.position.size < 0:
            cur_sl = (self.entry_price - atr_val * 0.1) if (self.be_active and self.use_be) else self.short_sl
            if self.be_active and self.use_be and high > self.entry_price - atr_val * 0.1:
                self.position.close()
        
        # Long entry
        if long_sig:
            self.entry_price = close
            self.be_active = False
            self.long_sl = close - atr_val * self.sl_m
            self.long_tp1 = close + atr_val * self.tp1_m
            self.long_tp2 = close + atr_val * self.tp2_m
            self.buy(size=2)
        
        # Short entry
        if short_sig:
            self.entry_price = close
            self.be_active = False
            self.short_sl = close + atr_val * self.sl_m
            self.short_tp1 = close - atr_val * self.tp1_m
            self.short_tp2 = close - atr_val * self.tp2_m
            self.sell(size=2)
        
        # Exit conditions
        if long_exit and self.position.size > 0:
            self.position.close()
        
        if short_exit and self.position.size < 0:
            self.position.close()
        
        # TP management for long
        if self.position.size > 0:
            if high >= self.long_tp2:
                self.position.close()
            elif high >= self.long_tp1 and self.position.size == 2:
                self.sell(size=1)
        
        # TP management for short
        if self.position.size < 0:
            if low <= self.short_tp2:
                self.position.close()
            elif low <= self.short_tp1 and self.position.size == -2:
                self.buy(size=1)


