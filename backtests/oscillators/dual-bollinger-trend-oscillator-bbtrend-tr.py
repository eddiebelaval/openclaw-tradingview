import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Short_Len_BB = 10
    Long_Len_BB = 50
    Short_Mult_BB = 1.0
    Long_Mult_BB = 2.0
    Length_MA_BB = 14
    MA_Type_BB = 'EMA'
    T_Factor = 0.7

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate Bollinger Bands
        short_bb = self.I(lambda: pta.bbands(close, length=self.Short_Len_BB, std=self.Short_Mult_BB))
        long_bb = self.I(lambda: pta.bbands(close, length=self.Long_Len_BB, std=self.Long_Mult_BB))
        
        # Extract bands
        self.short_mid = self.I(lambda: pta.bbands(close, length=self.Short_Len_BB, std=self.Short_Mult_BB)['BBM_{}'.format(self.Short_Len_BB)])
        self.short_up = self.I(lambda: pta.bbands(close, length=self.Short_Len_BB, std=self.Short_Mult_BB)['BBU_{}'.format(self.Short_Len_BB)])
        self.short_lo = self.I(lambda: pta.bbands(close, length=self.Short_Len_BB, std=self.Short_Mult_BB)['BBL_{}'.format(self.Short_Len_BB)])
        
        self.long_mid = self.I(lambda: pta.bbands(close, length=self.Long_Len_BB, std=self.Long_Mult_BB)['BBM_{}'.format(self.Long_Len_BB)])
        self.long_up = self.I(lambda: pta.bbands(close, length=self.Long_Len_BB, std=self.Long_Mult_BB)['BBU_{}'.format(self.Long_Len_BB)])
        self.long_lo = self.I(lambda: pta.bbands(close, length=self.Long_Len_BB, std=self.Long_Mult_BB)['BBL_{}'.format(self.Long_Len_BB)])
        
        # BBTrend calculation
        self.bbtrend_hist = self.I(self._calc_bbtrend_hist)
        self.bbtrend = self.I(self._calc_bbtrend)
        
        # Moving Average on BBTrend
        if self.MA_Type_BB == 'EMA':
            self.ma_bb = self.I(lambda: pta.ema(self.bbtrend, length=self.Length_MA_BB))
        elif self.MA_Type_BB == 'SMA':
            self.ma_bb = self.I(lambda: pta.sma(self.bbtrend, length=self.Length_MA_BB))
        elif self.MA_Type_BB == 'WMA':
            self.ma_bb = self.I(lambda: pta.wma(self.bbtrend, length=self.Length_MA_BB))
        elif self.MA_Type_BB == 'RMA':
            self.ma_bb = self.I(lambda: pta.rma(self.bbtrend, length=self.Length_MA_BB))
        else:
            self.ma_bb = self.I(lambda: pta.ema(self.bbtrend, length=self.Length_MA_BB))

    def _calc_bbtrend_hist(self):
        safe_div = np.where(self.short_mid[-1] != 0, self.short_mid[-1], 0.000001)
        bbtrend_hist = (np.abs(self.short_lo[-1] - self.long_lo[-1]) - np.abs(self.short_up[-1] - self.long_up[-1])) / safe_div * 100
        return bbtrend_hist

    def _calc_bbtrend(self):
        safe_div = np.where(self.short_mid[-1] != 0, self.short_mid[-1], 0.000001)
        bbtrend = (np.abs(self.short_lo[-1] - self.long_lo[-1]) - np.abs(self.short_up[-1] - self.long_up[-1])) / safe_div * 100
        return bbtrend

    def next(self):
        if len(self.data) < self.Length_MA_BB + self.Long_Len_BB:
            return
        
        # Get current and previous values
        bbtrend_current = self.bbtrend[-1]
        bbtrend_prev = self.bbtrend[-2] if len(self.bbtrend) > 1 else bbtrend_current
        
        bbtrend_hist_current = self.bbtrend_hist[-1]
        bbtrend_hist_prev = self.bbtrend_hist[-2] if len(self.bbtrend_hist) > 1 else bbtrend_hist_current
        
        ma_bb_current = self.ma_bb[-1]
        
        # Bullish signal: BBTrend crosses above MA_BB
        bull_bb = crossover(self.bbtrend, self.ma_bb)
        
        # Bearish signal: BBTrend crosses below MA_BB
        bear_bb = crossover(self.ma_bb, self.bbtrend)
        
        # Histogram based signals
        bull_bb_hist = bbtrend_hist_prev <= 0 and bbtrend_hist_current > 0
        bear_bb_hist = bbtrend_hist_prev >= 0 and bbtrend_hist_current < 0
        
        # Entry and exit logic
        if bull_bb or bull_bb_hist:
            if not self.position:
                self.buy()
        
        elif bear_bb or bear_bb_hist:
            if self.position:
                self.sell()