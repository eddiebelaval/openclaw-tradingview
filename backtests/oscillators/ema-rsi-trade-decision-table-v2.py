import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters from the Pine Script
    rsiLen = 14
    ema50Len = 50
    ema100Len = 100
    ema200Len = 200
    
    entryDistMaxPct = 0.20
    useEntryDistanceAsGate = True
    minEMADistPct = 0.50
    maxPriceEma50DistPct = 0.40
    
    bullLongLow = 45
    bullLongHigh = 75
    bullShortLow = 70
    bullShortHigh = 90
    
    bearLongLow = 10
    bearLongHigh = 35
    bearShortLow = 25
    bearShortHigh = 55
    
    neutralLow = 40
    neutralHigh = 60
    useEMA200Regime = False
    
    gradeA_min = 75
    gradeB_min = 60
    
    rsiLongMin = 55
    rsiShortMax = 45
    requireRejection = True
    
    tradeDecisionMinScore = 92

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema50 = self.I(pta.ema, close, length=self.ema50Len)
        self.ema100 = self.I(pta.ema, close, length=self.ema100Len)
        self.ema200 = self.I(pta.ema, close, length=self.ema200Len)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)

    def next(self):
        if len(self.data) < max(self.ema50Len, self.ema100Len, self.ema200Len, self.rsiLen):
            return
        
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        ema50 = self.ema50[-1]
        ema100 = self.ema100[-1]
        ema200 = self.ema200[-1]
        rsi_val = self.rsi[-1]
        
        if pd.isna(ema50) or pd.isna(ema100) or pd.isna(ema200) or pd.isna(rsi_val):
            return
        
        # Calculate distances
        price_to_ema50_pct = abs(close - ema50) / ema50 * 100.0
        ema_dist_pct = abs(ema50 - ema100) / ema100 * 100.0
        
        # Blockers
        price_too_far = price_to_ema50_pct > self.maxPriceEma50DistPct
        ema_too_close = ema_dist_pct < self.minEMADistPct
        
        # Regime
        ema_bull = ema50 > ema100
        ema_bear = ema50 < ema100
        
        bull_regime = ema_bull
        bear_regime = ema_bear
        
        if self.useEMA200Regime:
            bull_regime = ema_bull and close > ema200
            bear_regime = ema_bear and close < ema200
        
        # RSI Zones
        if bull_regime and not bear_regime:
            long_zone_low = self.bullLongLow
            long_zone_high = self.bullLongHigh
            short_zone_low = self.bullShortLow
            short_zone_high = self.bullShortHigh
        elif bear_regime and not bull_regime:
            long_zone_low = self.bearLongLow
            long_zone_high = self.bearLongHigh
            short_zone_low = self.bearShortLow
            short_zone_high = self.bearShortHigh
        else:
            long_zone_low = self.neutralLow
            long_zone_high = self.neutralHigh
            short_zone_low = self.neutralLow
            short_zone_high = self.neutralHigh
        
        rsi_in_long_zone = rsi_val >= long_zone_low and rsi_val <= long_zone_high
        rsi_in_short_zone = rsi_val >= short_zone_low and rsi_val <= short_zone_high
        
        rsi_long_ok = rsi_val >= self.rsiLongMin
        rsi_short_ok = rsi_val <= self.rsiShortMax
        
        # EMA Crosses
        bull_cross_up_now = crossover(self.ema50, self.ema100)
        bear_cross_dn_now = crossover(self.ema100, self.ema50)
        
        short_blocked = bull_cross_up_now or ema_too_close or price_too_far
        long_blocked = bear_cross_dn_now or ema_too_close or price_too_far
        
        # Entry Distance (EMA50)
        long_side_ok = close > ema50
        short_side_ok = close < ema50
        
        side_to_go_long_pct = ((ema50 - close) / ema50 * 100.0) if close <= ema50 else 0.0
        side_to_go_short_pct = ((close - ema50) / ema50 * 100.0) if close >= ema50 else 0.0
        
        entry_dist_long_pct = price_to_ema50_pct if long_side_ok else side_to_go_long_pct
        entry_dist_short_pct = price_to_ema50_pct if short_side_ok else side_to_go_short_pct
        
        entry_dist_long_ok = entry_dist_long_pct <= self.entryDistMaxPct
        entry_dist_short_ok = entry_dist_short_pct <= self.entryDistMaxPct
        
        # Rejection Candle
        long_candle_ok = (not self.requireRejection) or (close > open_)
        short_candle_ok = (not self.requireRejection) or (close < open_)
        
        # Final Entry Confirmation
        long_entry_ok = (not self.useEntryDistanceAsGate) or entry_dist_long_ok
        short_entry_ok = (not self.useEntryDistanceAsGate) or entry_dist_short_ok
        
        ema_pullback_long = long_entry_ok and long_side_ok and long_candle_ok
        ema_pullback_short = short_entry_ok and short_side_ok and short_candle_ok
        
        # Trade Allowed
        short_allowed = rsi_in_short_zone and rsi_short_ok and ema_pullback_short and ema_bear and not short_blocked
        long_allowed = rsi_in_long_zone and rsi_long_ok and ema_pullback_long and ema_bull and not long_blocked
        
        # Confidence Score
        short_score = 0.0
        if rsi_in_short_zone and rsi_short_ok:
            short_score += 30
        if ema_pullback_short:
            short_score += 30
        if ema_bear:
            short_score += 25
        if close < ema200:
            short_score += 15
        else:
            short_score += 5
        if ema_too_close:
            short_score -= 15
        if bull_cross_up_now:
            short_score -= 10
        if price_too_far:
            short_score -= 20
        short_score = max(0.0, min(100.0, short_score))
        
        long_score = 0.0
        if rsi_in_long_zone and rsi_long_ok:
            long_score += 30
        if ema_pullback_long:
            long_score += 30
        if ema_bull:
            long_score += 25
        if close > ema200:
            long_score += 15
        else:
            long_score += 5
        if ema_too_close:
            long_score -= 15
        if bear_cross_dn_now:
            long_score -= 10
        if price_too_far:
            long_score -= 20
        long_score = max(0.0, min(100.0, long_score))
        
        # Decision Gate
        short_yes = short_allowed and short_score >= self.tradeDecisionMinScore
        long_yes = long_allowed and long_score >= self.tradeDecisionMinScore
        
        # Trading Logic
        if long_yes and not self.position:
            self.buy()
        elif short_yes and self.position:
            self.sell()
        elif short_yes and not self.position:
            self.sell()
        elif long_yes and self.position and self.position.is_short:
            self.buy()