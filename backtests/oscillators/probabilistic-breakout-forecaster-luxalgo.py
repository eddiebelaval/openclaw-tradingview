import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 20
    horizonInput = 10
    volLookbackInput = 50
    atr_length = 14
    atr_ma_length = 100

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Upper and Lower Range (Highest High and Lowest Low)
        self.upperRange = self.I(lambda: high.rolling(self.lengthInput).max())
        self.lowerRange = self.I(lambda: low.rolling(self.lengthInput).min())
        
        # Log Returns
        self.logReturns = self.I(lambda: np.log(close / close.shift(1)))
        
        # Volatility (Standard Deviation of log returns)
        self.sigma = self.I(lambda: self.logReturns.rolling(int(self.volLookbackInput)).std())
        
        # ATR for squeeze calculation
        atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        self.avgAtr = self.I(lambda: atr.rolling(self.atr_ma_length).mean())
        
        # Probability calculations
        self.bullProb = self.I(self._calculate_bull_prob, close, self.upperRange, self.sigma, self.horizonInput)
        self.bearProb = self.I(self._calculate_bear_prob, close, self.lowerRange, self.sigma, self.horizonInput)
        
        # Squeeze calculation
        self.squeeze = self.I(self._calculate_squeeze, atr, self.avgAtr)

    def _ncdf(self, x):
        """Normal Cumulative Distribution Function approximation"""
        t = 1.0 / (1.0 + 0.2316419 * np.abs(x))
        d = 0.3989423 * np.exp(-x * x / 2.0)
        p = d * t * (0.3193815 + t * (-0.3565638 + t * (1.7814779 + t * (-1.821256 + t * 1.3302744))))
        return np.where(x > 0, 1.0 - p, p)

    def _calculate_bull_prob(self, close, upperRange, sigma, horizon):
        """Calculate bullish breakout probability"""
        bullProb = pd.Series(0.0, index=close.index)
        horizonSqrt = np.sqrt(horizon)
        
        for i in range(len(close)):
            if pd.notna(sigma.iloc[i]) and sigma.iloc[i] > 0 and pd.notna(upperRange.iloc[i]):
                denominator = sigma.iloc[i] * horizonSqrt
                if denominator > 0:
                    zUpper = np.log(upperRange.iloc[i] / close.iloc[i]) / denominator
                    bullProb.iloc[i] = (1.0 - self._ncdf(zUpper)) * 100
        
        return bullProb

    def _calculate_bear_prob(self, close, lowerRange, sigma, horizon):
        """Calculate bearish breakout probability"""
        bearProb = pd.Series(0.0, index=close.index)
        horizonSqrt = np.sqrt(horizon)
        
        for i in range(len(close)):
            if pd.notna(sigma.iloc[i]) and sigma.iloc[i] > 0 and pd.notna(lowerRange.iloc[i]):
                denominator = sigma.iloc[i] * horizonSqrt
                if denominator > 0:
                    zLower = np.log(lowerRange.iloc[i] / close.iloc[i]) / denominator
                    bearProb.iloc[i] = self._ncdf(zLower) * 100
        
        return bearProb

    def _calculate_squeeze(self, atr, avgAtr):
        """Calculate volatility squeeze factor"""
        squeeze = pd.Series(0.0, index=atr.index)
        
        for i in range(len(atr)):
            if pd.notna(atr.iloc[i]) and pd.notna(avgAtr.iloc[i]) and avgAtr.iloc[i] > 0:
                squeeze.iloc[i] = max(0, (1 - atr.iloc[i] / avgAtr.iloc[i]) * 100)
        
        return squeeze

    def next(self):
        # Get current probability values
        current_bull_prob = self.bullProb[-1] if not np.isnan(self.bullProb[-1]) else 0
        current_bear_prob = self.bearProb[-1] if not np.isnan(self.bearProb[-1]) else 0
        current_squeeze = self.squeeze[-1] if not np.isnan(self.squeeze[-1]) else 0
        
        # Trading logic based on breakout probabilities
        # Buy when bullish probability exceeds 50% and squeeze is moderate (indicates potential breakout)
        if current_bull_prob > 50 and current_squeeze < 80:
            if not self.position:
                self.buy()
        # Sell when bearish probability exceeds 50%
        elif current_bear_prob > 50:
            if self.position:
                self.position.close()


