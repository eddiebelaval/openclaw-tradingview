import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI calculation
        self.rsi = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        
        # Pivot High/Low for divergence detection
        self.pivot_lookback_right = 5
        self.pivot_lookback_left = 5
        
        # Tracking variables for divergences
        self.last_pl_price = None
        self.last_pl_rsi = None
        self.last_pl_index = None
        self.last_ph_price = None
        self.last_ph_rsi = None
        self.last_ph_index = None
        
        self.bull_div_detected = False
        self.bear_div_detected = False

    def next(self):
        current_idx = len(self.data) - 1
        
        if current_idx < self.pivot_lookback_left + self.pivot_lookback_right + 1:
            return
        
        rsi_current = self.rsi[-1]
        rsi_prev = self.rsi[-self.pivot_lookback_right - 1] if len(self.rsi) > self.pivot_lookback_right else None
        
        # Simple pivot detection for RSI lows
        if current_idx >= self.pivot_lookback_left + self.pivot_lookback_right:
            is_pivot_low = True
            is_pivot_high = True
            
            center_idx = current_idx - self.pivot_lookback_right
            center_rsi = self.rsi[center_idx]
            center_price = self.data.Low[center_idx]
            center_price_high = self.data.High[center_idx]
            
            # Check if center is pivot low
            for i in range(self.pivot_lookback_left):
                if self.rsi[center_idx - i - 1] <= center_rsi:
                    is_pivot_low = False
                    break
            
            for i in range(self.pivot_lookback_right):
                if self.rsi[center_idx + i + 1] <= center_rsi:
                    is_pivot_low = False
                    break
            
            # Check if center is pivot high
            for i in range(self.pivot_lookback_left):
                if self.rsi[center_idx - i - 1] >= center_rsi:
                    is_pivot_high = False
                    break
            
            for i in range(self.pivot_lookback_right):
                if self.rsi[center_idx + i + 1] >= center_rsi:
                    is_pivot_high = False
                    break
            
            # Bullish divergence: lower lows in price, higher lows in RSI
            if is_pivot_low:
                if (self.last_pl_price is not None and 
                    center_price < self.last_pl_price and 
                    center_rsi > self.last_pl_rsi):
                    self.bull_div_detected = True
                
                self.last_pl_price = center_price
                self.last_pl_rsi = center_rsi
                self.last_pl_index = center_idx
            
            # Bearish divergence: higher highs in price, lower highs in RSI
            if is_pivot_high:
                if (self.last_ph_price is not None and 
                    center_price_high > self.last_ph_price and 
                    center_rsi < self.last_ph_rsi):
                    self.bear_div_detected = True
                
                self.last_ph_price = center_price_high
                self.last_ph_rsi = center_rsi
                self.last_ph_index = center_idx
        
        # Trading logic based on divergences and RSI oversold/overbought
        if self.bull_div_detected and rsi_current < 50:
            if not self.position:
                self.buy()
            self.bull_div_detected = False
        
        if self.bear_div_detected and rsi_current > 50:
            if self.position:
                self.sell()
            self.bear_div_detected = False
        
        # Additional RSI-based exits
        if self.position and rsi_current > 70:
            self.sell()
        
        if not self.position and rsi_current < 30:
            self.buy()


