import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smoothK = 3
    smoothD = 3
    lengthRSI = 14
    lengthStoch = 14
    N = 4
    per = 144
    mult = 1.414
    modeLag = False
    modeFast = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI calculation
        rsi_values = self.I(pta.rsi, close, length=self.lengthRSI)
        
        # Stochastic on RSI values
        def stoch_on_rsi(rsi_series):
            if rsi_series is None:
                return pd.Series(50, index=close.index)
            stoch_result = pta.stoch(rsi_series, rsi_series, rsi_series, 
                                     k=self.lengthStoch, d=self.smoothD, smooth_k=self.smoothK)
            if stoch_result is None or stoch_result.empty:
                return pd.Series(50, index=close.index)
            k_col = [col for col in stoch_result.columns if 'STOCHk' in col]
            if k_col:
                return stoch_result[k_col[0]]
            return pd.Series(50, index=close.index)
        
        k_values = self.I(stoch_on_rsi, rsi_values)
        
        # SMA smoothing of K
        k_smooth = self.I(pta.sma, k_values, length=self.smoothK)
        
        # D value (SMA of K)
        self.d_value = self.I(pta.sma, k_smooth, length=self.smoothD)
        self.k_value = k_smooth
        
        # Gaussian filter implementation
        beta = (1 - np.cos(4 * np.arcsin(1) / self.per)) / (np.power(1.414, 2/self.N) - 1)
        self.alpha = -beta + np.sqrt(np.power(beta, 2) + 2*beta)
        
        # Source and TR for filter
        hlc3 = (high + low + close) / 3
        src_data = hlc3
        
        # True Range calculation
        tr = self.I(pta.atr, high, low, close, length=1)
        tr_data = tr
        
        # Simplified Gaussian pole filter using exponential smoothing
        def apply_gaussian_filter(data, alpha_val, order):
            if data is None or len(data) == 0:
                return pd.Series(0, index=close.index)
            result = pd.Series(0.0, index=data.index)
            for i in range(len(data)):
                if i == 0:
                    result.iloc[i] = data.iloc[i]
                else:
                    result.iloc[i] = alpha_val * data.iloc[i] + (1 - alpha_val) * result.iloc[i-1]
            return result
        
        self.filt = self.I(lambda: apply_gaussian_filter(src_data, self.alpha, self.N))
        self.filttr = self.I(lambda: apply_gaussian_filter(tr_data, self.alpha, self.N))
        
        # Bands
        self.hband = self.I(lambda: self.filt + self.filttr * self.mult)
        self.lband = self.I(lambda: self.filt - self.filttr * self.mult)

    def next(self):
        if len(self.data) < self.lengthRSI + self.lengthStoch + 5:
            return
        
        # Conditions
        gaussian_green = self.filt[-1] > self.filt[-2] if len(self.filt) > 1 else False
        stoch_signal = self.k_value[-1] > self.d_value[-1]
        long_condition = gaussian_green and (self.data.Close[-1] > self.hband[-1]) and stoch_signal
        close_long_condition = crossover(self.hband, self.data.Close)
        
        if long_condition and not self.position:
            self.buy()
        
        if close_long_condition and self.position:
            self.sell()


