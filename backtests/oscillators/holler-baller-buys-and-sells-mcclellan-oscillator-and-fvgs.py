import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    isRA = True
    rm = 1000
    moonel = 16
    mtwol = 36
    normLength = 100
    zExtreme = -2.0
    sweepLookback = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Since we don't have ADVN.US and DECL.US data, we'll use a proxy
        # based on price movement direction as a simplified approximation
        adv = pd.Series(np.where(close.diff() > 0, 1, 0))
        dec = pd.Series(np.where(close.diff() < 0, 1, 0))
        
        ai = adv.fillna(0)
        di = dec.fillna(0)
        
        # Calculate ratio-adjusted momentum
        rana = self.rm * (ai - di) / np.maximum(ai + di, 1)
        
        # Calculate EMAs for McClellan oscillator
        if self.isRA:
            e1 = self.I(pta.ema, rana, length=self.moonel)
            e2 = self.I(pta.ema, rana, length=self.mtwol)
        else:
            diff = ai - di
            e1 = self.I(pta.ema, diff, length=self.moonel)
            e2 = self.I(pta.ema, diff, length=self.mtwol)
        
        # Calculate momentum oscillator
        mo = e1 - e2
        
        # Normalize oscillator
        moMean = self.I(pta.sma, mo, length=self.normLength)
        moStd = self.I(lambda x: x.rolling(window=self.normLength).std(), mo)
        
        # Z-score
        z_values = (mo - moMean) / np.maximum(moStd, 1e-10)
        self.z = self.I(lambda: z_values)
        
        # Turning up detection
        self.turning_up = self.I(lambda: (z_values > z_values.shift(1)).astype(float))
        
        # Extreme breadth
        self.extreme_breadth = self.I(lambda: ((z_values < self.zExtreme) & (z_values > z_values.shift(1))).astype(float))
        
        # Liquidity sweep: low < lowest(low[1], sweepLookback) and close > prevLow
        prev_low = self.I(lambda: low.shift(1).rolling(window=self.sweepLookback).min())
        self.liquidity_sweep = self.I(lambda: ((low < prev_low) & (close > prev_low)).astype(float))
        
        # Fair value gaps
        self.bullish_fvg = self.I(lambda: (low > high.shift(2)).astype(float))
        self.bearish_fvg = self.I(lambda: (high < low.shift(2)).astype(float))
        
        # State tracking
        self.waiting_for_sell = False
        self.waiting_for_buy = True

    def next(self):
        # Check for buy signal
        if self.waiting_for_buy:
            buy_signal = (self.liquidity_sweep[-1] > 0.5) or (self.bullish_fvg[-1] > 0.5)
            if buy_signal:
                self.buy()
                self.waiting_for_sell = True
                self.waiting_for_buy = False
        
        # Check for sell signal
        if self.waiting_for_sell:
            sell_signal = self.bearish_fvg[-1] > 0.5
            if sell_signal:
                self.sell()
                self.waiting_for_sell = False
                self.waiting_for_buy = True


