        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # VZO Calculation
        def calc_vzo():
            dirVol = np.where(close > close.shift(1), volume, -volume)
            vp = pta.ema(pd.Series(dirVol), length=self.vzoLen)
            tv = pta.ema(volume, length=self.vzoLen)
            vzo = np.where(tv != 0, vp / tv, 0.0)
            return pd.Series(vzo)
        
        self.vzo = self.I(calc_vzo)
        
        # BB MR Calculation
        def calc_bbmr():
            bbBasis = pta.sma(close, length=self.bbLen)
            bbDev = self.bbMult * close.rolling(window=self.bbLen).std()
