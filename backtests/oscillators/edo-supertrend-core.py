import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    profile = "Balanced"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Set parameters based on profile
        if self.profile == "Fast":
            atr_period = 7
            factor = 2.0
        elif self.profile == "Balanced":
            atr_period = 10
            factor = 2.3
        else:  # Slow
            atr_period = 14
            factor = 3.0
        
        # Calculate RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        
        # Calculate ATR
        self.atr = self.I(lambda: pta.atr(high, low, close, length=atr_period) or pd.Series(0, index=close.index))
        
        # Calculate HL2
        self.hl2 = self.I(lambda: (high + low) / 2)
        
        # Manual SuperTrend calculation
        self.supertrend = self.I(lambda: self._calculate_supertrend(high, low, close, atr_period, factor))
        
        # Direction tracking
        self.direction = self.I(lambda: self._calculate_direction(high, low, close, atr_period, factor))
        
        self.in_long = False
        self.in_short = False
    
    def _calculate_supertrend(self, high, low, close, atr_period, factor):
        atr = pta.atr(high, low, close, length=atr_period)
        if atr is None:
            return pd.Series(0, index=close.index)
        
        hl2 = (high + low) / 2
        basic_ub = hl2 + factor * atr
        basic_lb = hl2 - factor * atr
        
        final_ub = pd.Series(index=close.index, dtype=float)
        final_lb = pd.Series(index=close.index, dtype=float)
        
        for i in range(len(close)):
            if i == 0:
                final_ub.iloc[i] = basic_ub.iloc[i]
                final_lb.iloc[i] = basic_lb.iloc[i]
            else:
                final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
        
        supertrend = pd.Series(index=close.index, dtype=float)
        for i in range(len(close)):
            if i == 0:
                supertrend.iloc[i] = final_ub.iloc[i]
            else:
                supertrend.iloc[i] = final_ub.iloc[i] if close.iloc[i] <= final_ub.iloc[i] else final_lb.iloc[i]
        
        return supertrend
    
    def _calculate_direction(self, high, low, close, atr_period, factor):
        atr = pta.atr(high, low, close, length=atr_period)
        if atr is None:
            return pd.Series(1, index=close.index)
        
        hl2 = (high + low) / 2
        basic_ub = hl2 + factor * atr
        basic_lb = hl2 - factor * atr
        
        final_ub = pd.Series(index=close.index, dtype=float)
        final_lb = pd.Series(index=close.index, dtype=float)
        
        for i in range(len(close)):
            if i == 0:
                final_ub.iloc[i] = basic_ub.iloc[i]
                final_lb.iloc[i] = basic_lb.iloc[i]
            else:
                final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
        
        direction = pd.Series(index=close.index, dtype=float)
        for i in range(len(close)):
            if i == 0:
                direction.iloc[i] = 1
            else:
                if close.iloc[i] <= final_ub.iloc[i]:
                    direction.iloc[i] = 1
                else:
                    direction.iloc[i] = -1
        
        return direction
    
    def next(self):
        if len(self.data) < 2:
            return
        
        current_direction = self.direction[-1]
        prev_direction = self.direction[-2] if len(self.direction) > 1 else current_direction
        current_rsi = self.rsi[-1]
        
        # Apply RSI filter to direction
        filtered_direction = current_direction
        if current_direction < 0 and current_rsi <= 50:
            filtered_direction = prev_direction
        if current_direction > 0 and current_rsi >= 50:
            filtered_direction = prev_direction
        
        # Entry logic
        if filtered_direction < 0 and not self.in_long:
            if self.in_short:
                self.position.close()
            self.buy()
            self.in_long = True
            self.in_short = False
        elif filtered_direction > 0 and not self.in_short:
            if self.in_long:
                self.position.close()
            self.sell()
            self.in_short = True
            self.in_long = False


