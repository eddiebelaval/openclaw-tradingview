import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 200
    innermult = 1.0
    outermult = 2.415
    bb_length = 20
    bb_mult = 2.0
    rsi_length = 14
    rsi_ob = 70
    rsi_os = 30

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.bb_basis = self.I(pta.sma, close, length=self.bb_length)
        self.bb_dev = self.I(lambda: pta.stdev(close, length=self.bb_length))
        self.bb_upper = self.I(lambda: self.bb_basis + self.bb_mult * (pta.stdev(close, length=self.bb_length) or pd.Series(0, index=close.index)))
        self.bb_lower = self.I(lambda: self.bb_basis - self.bb_mult * (pta.stdev(close, length=self.bb_length) or pd.Series(0, index=close.index)))
        
        self.rsi_value = self.I(pta.rsi, close, length=self.rsi_length)

    def next(self):
        if len(self.data) < self.length + 5:
            return
        
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        bb_upper_current = self.bb_upper[-1]
        bb_lower_current = self.bb_lower[-1]
        bb_basis_current = self.bb_basis[-1]
        
        rsi_current = self.rsi_value[-1]
        
        if not np.isnan(rsi_current) and not np.isnan(bb_upper_current) and not np.isnan(bb_lower_current):
            bull_signal = current_low <= bb_lower_current and rsi_current <= self.rsi_os and current_close < bb_basis_current
            bear_signal = current_high >= bb_upper_current and rsi_current >= self.rsi_ob and current_close > bb_basis_current
            
            if bull_signal and not self.position:
                self.buy()
            elif bear_signal and self.position:
                self.sell()
            elif bear_signal and not self.position:
                self.buy()
            elif bull_signal and self.position:
                self.sell()


