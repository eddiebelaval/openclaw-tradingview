import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_period = 14
    smooth_period = 3
    trend_ema_period = 20

    def init(self):
        close = pd.Series(self.data.Close)
        
        rsi_val = self.I(pta.rsi, close, length=self.len_period)
        osc_raw = rsi_val - 50
        self.osc = self.I(pta.ema, pd.Series(osc_raw), length=self.smooth_period)
        self.trend_ema = self.I(pta.ema, close, length=self.trend_ema_period)

    def next(self):
        if len(self.data) < max(self.len_period, self.smooth_period, self.trend_ema_period) + 1:
            return

        osc_curr = self.osc[-1]
        osc_prev = self.osc[-2]
        
        close_curr = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        
        trend_ema_curr = self.trend_ema[-1]
        trend_ema_prev = self.trend_ema[-2]

        long_signal = (crossover(self.osc, 0) or 
                       (osc_curr > 15 and close_prev <= trend_ema_prev and close_curr > trend_ema_curr))
        
        short_signal = (crossover(0, self.osc) or 
                        (osc_curr < -15 and close_prev >= trend_ema_prev and close_curr < trend_ema_curr))

        if long_signal and osc_curr > 0:
            if not self.position:
                self.buy()
        elif short_signal and osc_curr < 0:
            if self.position:
                self.position.close()