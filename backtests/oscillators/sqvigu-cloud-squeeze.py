import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 20
    bbMult = 2.0
    kcMult = 1.5
    thickness = 4.0
    smoothing = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Basis and deviation for Bollinger Bands
        self.basis = self.I(pta.sma, close, length=self.len)
        self.dev = self.I(lambda: pta.stdev(close, length=self.len) * self.bbMult if pta.stdev(close, length=self.len) is not None else pd.Series(0, index=close.index))
        
        # True Range and Keltner Channel
        self.tr = self.I(lambda: pta.true_range(high, low, close))
        self.ran = self.I(lambda: pta.ema(self.tr, length=self.len) * self.kcMult if pta.ema(self.tr, length=self.len) is not None else pd.Series(0, index=close.index))
        
        # Highest and lowest over len period
        self.highest = self.I(lambda: high.rolling(self.len).max())
        self.lowest = self.I(lambda: low.rolling(self.len).min())
        
        # Base momentum calculation
        self.hl_avg = self.I(lambda: (self.highest + self.lowest) / 2)
        self.hl_basis_avg = self.I(lambda: (self.hl_avg + self.basis) / 2)
        self.base_mom_raw = self.I(lambda: close - self.hl_basis_avg)
        
        # Linear regression of base momentum
        self.base_mom = self.I(lambda: self._linreg(close - self.hl_basis_avg, self.len))
        
        # Smoothed momentum
        self.mom = self.I(lambda: pta.ema(self.base_mom, length=self.smoothing) if pta.ema(self.base_mom, length=self.smoothing) is not None else pd.Series(0, index=close.index))
        
        # Volatility and layers
        self.vol = self.I(lambda: pta.ema(pta.stdev(self.mom, length=10), length=self.smoothing) * self.thickness if pta.ema(pta.stdev(self.mom, length=10), length=self.smoothing) is not None else pd.Series(0, index=close.index))
        
        # Squeeze condition
        self.sqz_on = self.I(self._squeeze_condition, close, high, low)
        
        # Fire signals
        self.long_fire = self.I(self._long_fire_signal)
        self.short_fire = self.I(self._short_fire_signal)

    def _linreg(self, series, period):
        """Simple linear regression"""
        result = pd.Series(index=series.index, dtype=float)
        for i in range(len(series)):
            if i < period - 1:
                result.iloc[i] = np.nan
            else:
                y = series.iloc[i - period + 1:i + 1].values
                x = np.arange(len(y))
                if len(y) > 1:
                    coeffs = np.polyfit(x, y, 1)
                    result.iloc[i] = coeffs[0] * (len(y) - 1) + coeffs[1]
                else:
                    result.iloc[i] = y[0]
        return result

    def _squeeze_condition(self, close, high, low):
        """Calculate squeeze on/off condition"""
        result = pd.Series(index=close.index, dtype=bool)
        basis_vals = pta.sma(close, length=self.len)
        dev_vals = pta.stdev(close, length=self.len) * self.bbMult
        
        tr_vals = pta.true_range(high, low, close)
        ran_vals = pta.ema(tr_vals, length=self.len) * self.kcMult
        
        for i in range(len(close)):
            if (basis_vals.iloc[i] is not None and dev_vals.iloc[i] is not None and 
                ran_vals.iloc[i] is not None):
                bb_low = basis_vals.iloc[i] - dev_vals.iloc[i]
                bb_high = basis_vals.iloc[i] + dev_vals.iloc[i]
                kc_low = basis_vals.iloc[i] - ran_vals.iloc[i]
                kc_high = basis_vals.iloc[i] + ran_vals.iloc[i]
                result.iloc[i] = (bb_low > kc_low) and (bb_high < kc_high)
            else:
                result.iloc[i] = False
        return result

    def _long_fire_signal(self):
        """Long fire signal: squeeze release with positive momentum"""
        result = pd.Series(index=self.data.Close.index, dtype=bool)
        for i in range(1, len(self.data.Close)):
            if (self.sqz_on[-2] if len(self.sqz_on) > 1 else False) and not self.sqz_on[-1] and self.mom[-1] > 0:
                result.iloc[i] = True
            else:
                result.iloc[i] = False
        return result

    def _short_fire_signal(self):
        """Short fire signal: squeeze release with negative momentum"""
        result = pd.Series(index=self.data.Close.index, dtype=bool)
        for i in range(1, len(self.data.Close)):
            if (self.sqz_on[-2] if len(self.sqz_on) > 1 else False) and not self.sqz_on[-1] and self.mom[-1] < 0:
                result.iloc[i] = True
            else:
                result.iloc[i] = False
        return result

    def next(self):
        if len(self.data) < self.len + 5:
            return
        
        # Entry signals on squeeze release
        if self.long_fire[-1] and not self.position:
            self.buy()
        elif self.short_fire[-1] and not self.position:
            self.sell()
        
        # Exit on momentum reversal
        if self.position:
            if self.position.is_long:
                if self.mom[-1] < 0:
                    self.position.close()
            elif self.position.is_short:
                if self.mom[-1] > 0:
                    self.position.close()