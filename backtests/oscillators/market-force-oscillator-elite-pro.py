import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Base parameters
        self.base_length = 14
        self.vol_length = 14
        self.ob_level = 1.5
        self.os_level = -1.5
        self.sig_thresh = 1.0
        self.pivot_lookback = 5
        
        # Calculate ATR for dynamic levels
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.base_length))
        
        # Calculate force components
        def calc_osc():
            pr = np.maximum(high.values - low.values, 1e-6)
            vpma = pta.sma(volume, length=self.vol_length)
            vpma_safe = np.maximum(np.where(pd.isna(vpma), 1, vpma), 1e-6)
            safe_vol = np.where(volume.values == 0, np.roll(volume.values, 1), volume.values)
            safe_vol[0] = volume.iloc[0] if volume.iloc[0] > 0 else 1
            
            rv = safe_vol / vpma_safe.values
            ramp = np.where(rv >= 1.5, 1.0, np.where(rv > 1.5, (rv - 1.5) / 1.0, 0))
            vw = 1 + ramp * np.log10(np.maximum(rv, 1.0))
            
            mom_raw = (close.diff() / close) * 100
            mom = np.clip(mom_raw.values * 1.0, -5, 5) / 100.0
            
            bp = safe_vol * ((close.values - low.values) / pr) * (1 + mom)
            sp = safe_vol * ((high.values - close.values) / pr) * (1 - mom)
            
            raw = (bp - sp) * vw
            smooth_len = max(1, self.base_length // 2)
            force_ma = pta.ema(pd.Series(raw), length=smooth_len)
            
            mass = np.maximum(pta.ema(pd.Series(safe_vol), length=self.vol_length), 1e-6)
            
            accel = close.diff().diff()
            force_normalized = (force_ma / mass.values) if mass is not None else pd.Series(0, index=close.index)
            
            osc_raw = accel - force_normalized
            mean_osc = pta.sma(pd.Series(osc_raw.values), length=self.base_length)
            osc_std = close.rolling(self.base_length).std()
            
            osc_std = np.where(pd.isna(osc_std), close.rolling(self.base_length).apply(lambda x: np.std(x), raw=True), osc_std)
            osc_scale = np.maximum(osc_std, 0.01)
            
            osc_num = osc_raw.values - mean_osc.values
            osc_unclamped = osc_num / osc_scale
            osc = np.clip(osc_unclamped, -8.0, 8.0)
            
            return pd.Series(osc, index=close.index)
        
        self.osc = self.I(calc_osc)
        
        # EMA for trend
        self.ema_ltf = self.I(lambda: pta.ema(close, length=self.base_length))
        
        # Dynamic levels
        def calc_dynamic_levels():
            close_safe = np.maximum(close.values, 1e-6)
            atr_pct = (self.atr[-1] / close_safe[-1] * 100) if self.atr[-1] else 0
            atr_pct_ref = 35.0
            atr_pct_eff = atr_pct / (1 + atr_pct / atr_pct_ref)
            atr_factor = 1 + np.clip(atr_pct_eff * 0.18 * 0.55, 0, 2)
            
            dyn_ob = self.ob_level * atr_factor
            dyn_os = self.os_level * atr_factor
            return dyn_ob, dyn_os
        
        self.dyn_levels = self.I(calc_dynamic_levels)
        
        # Signal quality
        def calc_signal_quality():
            vol_sma = np.maximum(pta.sma(volume, length=self.vol_length), 1e-6)
            rv_cap = volume.values / vol_sma.values
            vol_component = np.minimum(rv_cap, 10.0)
            sig_quality_raw = np.abs(self.osc) * vol_component
            return pd.Series(sig_quality_raw, index=close.index)
        
        self.sig_quality = self.I(calc_signal_quality)
        
        # Pivot highs/lows for divergence
        self.lookback = self.pivot_lookback
        
    def next(self):
        if len(self.data) < self.base_length + 10:
            return
        
        dyn_ob, dyn_os = self.dyn_levels[-1]
        
        # Signal quality check
        qual_pass = self.sig_quality[-1] > self.sig_thresh
        
        # Trend check
        trend_ok = self.data.Close[-1] > self.ema_ltf[-1]
        
        # Bullish signal: oscillator crosses above oversold level
        if (self.osc[-1] > dyn_os and 
            self.osc[-2] <= dyn_os and 
            trend_ok and 
            qual_pass and
            not self.position):
            self.buy()
        
        # Bearish signal: oscillator crosses below overbought level
        elif (self.osc[-1] < dyn_ob and 
              self.osc[-2] >= dyn_ob and 
              not trend_ok and 
              qual_pass and
              self.position):
            self.sell()
        
        # Exit on trend reversal
        if self.position:
            if self.data.Close[-1] < self.ema_ltf[-1]:
                self.sell()


