import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Bollinger Bands
    bb_len = 20
    bb_mult = 2.0
    
    # Ichimoku
    tenkan_len = 9
    kijun_len = 26
    senkou_b_len = 52
    displacement = 26
    
    # RSI
    rsi_len = 14
    rsi_overbought = 70
    rsi_oversold = 30
    
    # MACD
    fast_len = 12
    slow_len = 26
    sig_len = 9

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        self.basis = self.I(pta.sma, close, length=self.bb_len)
        bb_result = self.I(pta.bbands, close, length=self.bb_len, std=self.bb_mult)
        self.bb_upper = self.I(lambda: (pta.bbands(close, length=self.bb_len, std=self.bb_mult) or pd.DataFrame()).iloc[:, 2] if not (pta.bbands(close, length=self.bb_len, std=self.bb_mult) or pd.DataFrame()).empty else pd.Series(0, index=close.index))
        self.bb_lower = self.I(lambda: (pta.bbands(close, length=self.bb_len, std=self.bb_mult) or pd.DataFrame()).iloc[:, 0] if not (pta.bbands(close, length=self.bb_len, std=self.bb_mult) or pd.DataFrame()).empty else pd.Series(0, index=close.index))
        
        # Ichimoku - Donchian calculations
        self.tenkan = self.I(lambda: (high.rolling(self.tenkan_len).max() + low.rolling(self.tenkan_len).min()) / 2)
        self.kijun = self.I(lambda: (high.rolling(self.kijun_len).max() + low.rolling(self.kijun_len).min()) / 2)
        self.senkou_b = self.I(lambda: (high.rolling(self.senkou_b_len).max() + low.rolling(self.senkou_b_len).min()) / 2)
        self.senkou_a = self.I(lambda: (self.tenkan + self.kijun) / 2)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        # MACD
        macd_result = self.I(pta.macd, close, fast=self.fast_len, slow=self.slow_len, signal=self.sig_len)
        self.macd_line = self.I(lambda: (pta.macd(close, fast=self.fast_len, slow=self.slow_len, signal=self.sig_len) or pd.DataFrame()).iloc[:, 0] if not (pta.macd(close, fast=self.fast_len, slow=self.slow_len, signal=self.sig_len) or pd.DataFrame()).empty else pd.Series(0, index=close.index))
        self.macd_signal = self.I(lambda: (pta.macd(close, fast=self.fast_len, slow=self.slow_len, signal=self.sig_len) or pd.DataFrame()).iloc[:, 2] if not (pta.macd(close, fast=self.fast_len, slow=self.slow_len, signal=self.sig_len) or pd.DataFrame()).empty else pd.Series(0, index=close.index))

    def next(self):
        # Primary signal: MACD crossover
        if len(self.data) < self.slow_len + self.sig_len:
            return
        
        # Buy signal: MACD line crosses above signal line
        if crossover(self.macd_line, self.macd_signal):
            if not self.position:
                self.buy()
        
        # Sell signal: MACD line crosses below signal line
        elif crossover(self.macd_signal, self.macd_line):
            if self.position:
                self.position.close()


