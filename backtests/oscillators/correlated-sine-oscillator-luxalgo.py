import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    period_input = 20
    smooth_mult_input = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        smooth_length = max(1, round(self.period_input * self.smooth_mult_input))
        
        def calculate_oscillator():
            close_data = pd.Series(self.data.Close)
            
            sma_close = pta.sma(close_data, length=self.period_input)
            detrended = close_data - sma_close
            
            omega = 2 * np.pi / self.period_input
            
            osc_values = []
            for i in range(len(close_data)):
                angle = omega * i
                
                inst_real = detrended.iloc[i] * np.cos(angle)
                inst_imag = detrended.iloc[i] * np.sin(angle)
                
                if i < smooth_length - 1:
                    osc_values.append(0)
                    continue
                
                real_values = []
                imag_values = []
                for j in range(i - smooth_length + 1, i + 1):
                    angle_j = omega * j
                    real_values.append(detrended.iloc[j] * np.cos(angle_j))
                    imag_values.append(detrended.iloc[j] * np.sin(angle_j))
                
                real = np.mean(real_values)
                imag = np.mean(imag_values)
                
                if real != 0:
                    phase = np.arctan(imag / real)
                else:
                    phase = np.pi / 2 if imag >= 0 else -np.pi / 2
                
                if real < 0:
                    phase += np.pi
                
                osc = np.cos(angle - phase)
                osc_values.append(osc)
            
            return pd.Series(osc_values, index=close_data.index)
        
        self.osc = self.I(calculate_oscillator)

    def next(self):
        if len(self.data) < 2:
            return
        
        if crossover(self.osc, 0):
            if not self.position:
                self.buy()
        elif crossover(0, self.osc):
            if self.position:
                self.position.close()


