import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    cciLength = 20
    atrLength = 14
    rocLength = 12
    wtEmaLength = 10
    wtChannelLength = 21
    optWindow = 5
    useKalman = False
    useRegime = True
    regimeEMA_len = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI
        self.rsi_value = self.I(pta.rsi, close, length=self.rsiLength)
        
        # CCI Calculation
        typical_price = (high + low + close) / 3
        sma_typical = self.I(pta.sma, typical_price, length=self.cciLength)
        mean_dev = self.I(lambda: pta.sma(np.abs(typical_price - sma_typical), length=self.cciLength))
        
        def calc_cci():
            tp = (self.data.High[-1] + self.data.Low[-1] + self.data.Close[-1]) / 3
            sma_tp = self.sma_typical[-1]
            md = self.mean_dev[-1]
            if md == 0:
                return 0
            return (tp - sma_tp) / (0.015 * md)
        
        self.cci_value = self.I(calc_cci)
        self.sma_typical = sma_typical
        self.mean_dev = mean_dev
        
        # ATR
        self.atr_value = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        def calc_norm_atr():
            atr = self.atr_value[-1]
            c = self.data.Close[-1]
            if c == 0:
                return 0
            return (atr / c) * 100
        
        self.norm_atr = self.I(calc_norm_atr)
        
        # ROC
        self.roc_value = self.I(pta.roc, close, length=self.rocLength)
        
        # WT (Williams Transform)
        ap = (high + low + close) / 3
        esa = self.I(pta.ema, ap, length=self.wtEmaLength)
        d = self.I(lambda: pta.ema(np.abs(ap - esa), length=self.wtEmaLength))
        
        def calc_ci():
            ap_val = (self.data.High[-1] + self.data.Low[-1] + self.data.Close[-1]) / 3
            esa_val = self.esa[-1]
            d_val = self.d[-1]
            if d_val == 0:
                return 0
            return (ap_val - esa_val) / (0.015 * d_val)
        
        self.ci = self.I(calc_ci)
        self.esa = esa
        self.d = d
        
        self.wt1 = self.I(pta.ema, self.ci, length=self.wtChannelLength)
        
        # Normalization
        def calc_rsin():
            return (self.rsi_value[-1] - 50) / 50
        
        def calc_ccin():
            return max(min(self.cci_value[-1], 200), -200) / 200
        
        def calc_atrn():
            return min(self.norm_atr[-1] / 5, 1)
        
        def calc_rocn():
            roc = self.roc_value[-1]
            if pd.isna(roc):
                roc = 0
            return max(min(roc, 5), -5) / 5
        
        def calc_wtn():
            return max(min(self.wt1[-1], 60), -60) / 60
        
        self.rsin = self.I(calc_rsin)
        self.ccin = self.I(calc_ccin)
        self.atrn = self.I(calc_atrn)
        self.rocn = self.I(calc_rocn)
        self.wtn = self.I(calc_wtn)
        
        # Price change for correlation
        def calc_price_change():
            if len(self.data.Close) < 2:
                return 0
            return self.data.Close[-1] - self.data.Close[-2]
        
        self.price_change = self.I(calc_price_change)
        
        # Composite Score
        def calc_composite():
            if len(self.data.Close) < self.optWindow + 1:
                return 0
            
            close_series = pd.Series(self.data.Close)
            price_change_series = close_series.diff()
            
            rsin_series = pd.Series([self.rsin[i] if i < len(self.rsin) and not np.isnan(self.rsin[i]) else 0 for i in range(len(self.rsin))])
            ccin_series = pd.Series([self.ccin[i] if i < len(self.ccin) and not np.isnan(self.ccin[i]) else 0 for i in range(len(self.ccin))])
            atrn_series = pd.Series([self.atrn[i] if i < len(self.atrn) and not np.isnan(self.atrn[i]) else 0 for i in range(len(self.atrn))])
            rocn_series = pd.Series([self.rocn[i] if i < len(self.rocn) and not np.isnan(self.rocn[i]) else 0 for i in range(len(self.rocn))])
            wtn_series = pd.Series([self.wtn[i] if i < len(self.wtn) and not np.isnan(self.wtn[i]) else 0 for i in range(len(self.wtn))])
            
            window = min(self.optWindow, len(close_series) - 1)
            if window < 2:
                return 0
            
            w_rsi = rsin_series.iloc[-window:].corr(price_change_series.iloc[-window:]) or 0.2
            w_cci = ccin_series.iloc[-window:].corr(price_change_series.iloc[-window:]) or 0.2
            w_atr = (atrn_series.iloc[-window:].corr(price_change_series.iloc[-window:]) or 0.2) * -1
            w_roc = rocn_series.iloc[-window:].corr(price_change_series.iloc[-window:]) or 0.2
            w_wt = wtn_series.iloc[-window:].corr(price_change_series.iloc[-window:]) or 0.2
            
            total_w = abs(w_rsi) + abs(w_cci) + abs(w_atr) + abs(w_roc) + abs(w_wt)
            if total_w == 0:
                total_w = 1
            
            composite = (w_rsi * self.rsin[-1] + w_cci * self.ccin[-1] + w_atr * self.atrn[-1] + w_roc * self.rocn[-1] + w_wt * self.wtn[-1]) / total_w
            return composite
        
        self.composite = self.I(calc_composite)
        
        # Kalman Filter
        self.kf_state = 0.0
        self.kf_p = 1.0
        self.kalman_gain = 0.2
        self.kalman_noise = 0.01
        
        def calc_kf_output():
            if len(self.data.Close) == 1:
                self.kf_state = self.composite[-1]
                return self.composite[-1]
            else:
                self.kf_p = self.kf_p + self.kalman_noise
                kalman_k = self.kf_p / (self.kf_p + self.kalman_gain)
                self.kf_state = self.kf_state + kalman_k * (self.composite[-1] - self.kf_state)
                self.kf_p = (1 - kalman_k) * self.kf_p
                return self.kf_state
        
        self.kf_output = self.I(calc_kf_output)
        
        # Regime Filter (simplified - using SMA as proxy)
        self.regime_ema = self.I(pta.ema, close, length=self.regimeEMA_len)
        
        def calc_final_output():
            kf = self.kf_output[-1]
            if not self.useRegime:
                return kf
            
            c = self.data.Close[-1]
            regime = self.regime_ema[-1]
            
            if c > regime:
                return max(kf, 0)
            elif c < regime:
                return min(kf, 0)
            else:
                return 0
        
        self.final_output = self.I(calc_final_output)
        
        # Position tracking
        self.current_pos = 0

    def next(self):
        final = self.final_output[-1]
        prev_final = self.final_output[-2] if len(self.final_output) > 1 else 0
        
        # Long signal: crossover above 0
        if prev_final <= 0 < final and self.current_pos <= 0:
            self.buy()
            self.current_pos = 1
        
        # Short signal: crossunder below 0
        elif prev_final >= 0 > final and self.current_pos >= 0:
            self.sell()
            self.current_pos = -1