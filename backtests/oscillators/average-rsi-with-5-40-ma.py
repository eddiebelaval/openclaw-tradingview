import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    ma_short = 5
    ma_long = 40

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI of price
        rsi_val = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Calculate MAs of the RSI
        rsi_ma_short = self.I(lambda: pta.sma(rsi_val, length=self.ma_short) if rsi_val is not None else pd.Series(50, index=close.index))
        rsi_ma_long = self.I(lambda: pta.sma(rsi_val, length=self.ma_long) if rsi_val is not None else pd.Series(50, index=close.index))
        
        # Average of both MAs
        self.rsi_avg = self.I(lambda: (rsi_ma_short + rsi_ma_long) / 2)
        self.rsi_ma_short = rsi_ma_short
        self.rsi_ma_long = rsi_ma_long

    def next(self):
        # Buy when average RSI crosses above 30 (oversold threshold)
        if len(self.rsi_avg) > 1:
            if crossover(self.rsi_avg, 30):
                self.buy()
            # Sell when average RSI crosses below 70 (overbought threshold)
            elif crossover(70, self.rsi_avg):
                self.sell()