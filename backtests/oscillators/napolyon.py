class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        macd_result = self.I(pta.macd, close, fast=7, slow=26, signal=9)
        
        self.macd_line = macd_result.iloc[:, 0] if macd_result is not None else self.I(lambda: pd.Series(0, index=close.index))
        self.signal_line = macd_result.iloc[:, 1] if macd_result is not None else self.I(lambda: pd.Series(0, index=close.index))
        self.hist = macd_result.iloc[:, 2] if macd_result is not None else self.I(lambda: pd.Series(0, index=close.index))
        
        self.up_seq = 0
        self.down_seq = 0
        self.weak_seen_pos = False
        self.weak_seen_neg = False
        self.prev_hist = 0

    def next(self):
        if len(self.hist) < 2:
            return
        
        current_hist = self.hist[-1]
        prev_hist = self.hist[-2]
        
        is_up = current_hist > prev_hist
        is_down = current_hist < prev_hist
        
        is_pos = current_hist > 0
        is_neg = current_hist < 0
        
        buy_signal = False
        sell_signal = False
        
        # AL (Buy Signal Logic)
        if is_pos:
            if is_down:
                self.weak_seen_pos = True
                self.up_seq = 0
            if is_up and self.weak_seen_pos:
                self.up_seq += 1
                if self.up_seq == 2:
                    buy_signal = True
        else:
            self.weak_seen_pos = False
            self.up_seq = 0
        
        # SAT (Sell Signal Logic)
        if is_neg:
            if is_up:
                self.weak_seen_neg = True
                self.down_seq = 0
            if is_down and self.weak_seen_neg:
                self.down_seq += 1
                if self.down_seq == 2:
                    sell_signal = True
        else:
            self.weak_seen_neg = False
            self.down_seq = 0
        
        if buy_signal:
            if not self.position:
                self.buy()
        
        if sell_signal:
            if self.position:
                self.position.close()