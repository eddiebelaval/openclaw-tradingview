import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Main Settings
    avg_vol_window = 20
    pos_ob_level = 15
    neg_os_level = -15
    pivot_left_len = 2
    pivot_right_len = 2
    use_price_filter = False
    max_pivot_line_length = 200
    operation_mode = "Signals after pivot breakout"  # or "OB/OS continuation signals"
    
    # TP/SL Settings
    use_atr_for_sl = True
    atr_period = 14
    sl_atr_mult = 1.5
    sl_percent = 1.0
    rr_tp1 = 1.0
    rr_tp2 = 2.0
    rr_tp3 = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate Volume Weighted Oscillator (VWO)
        vol_avg = self.I(pta.sma, volume, length=self.avg_vol_window)
        vol_std = self.I(lambda: volume.rolling(self.avg_vol_window).std() or pd.Series(1.0, index=volume.index))
        vol_norm = self.I(lambda: np.maximum((volume - vol_avg) / vol_std, 0))
        
        price_change = self.I(lambda: close.diff())
        vwo = self.I(lambda: price_change * vol_norm)
        
        vwo_avg = self.I(pta.sma, vwo, length=self.avg_vol_window)
        vwo_std = self.I(lambda: vwo.rolling(self.avg_vol_window).std() or pd.Series(1.0, index=vwo.index))
        self.vwo_norm = self.I(lambda: (vwo - vwo_avg) / vwo_std * 10)
        
        # ATR for stop loss
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # Pivot detection
        self.pivot_high = self.I(lambda: self._pivot_high(self.vwo_norm, self.pivot_left_len, self.pivot_right_len))
        self.pivot_low = self.I(lambda: self._pivot_low(self.vwo_norm, self.pivot_left_len, self.pivot_right_len))
        
        # Crossover signals for OB/OS mode
        self.bull_cross_obc = self.I(lambda: self._crossover(self.vwo_norm, self.pos_ob_level))
        self.bear_cross_obc = self.I(lambda: self._crossunder(self.vwo_norm, self.neg_os_level))
        
        # State tracking
        self.trade_dir = 0
        self.entry_price = 0
        self.sl_level = 0
        self.tp_level = 0
        self.entry_bar = -1
        
        self.last_hi_lvl = None
        self.last_hi_close = None
        self.last_lo_lvl = None
        self.last_lo_close = None
        
        self.hi_lvls = []
        self.lo_lvls = []
        self.active_boxes = []

    def _pivot_high(self, series, left_len, right_len):
        result = pd.Series(np.nan, index=series.index)
        for i in range(left_len + right_len, len(series)):
            if all(series.iloc[i] > series.iloc[i - j] for j in range(1, left_len + 1)) and \
               all(series.iloc[i] > series.iloc[i + j] for j in range(1, right_len + 1)):
                result.iloc[i] = series.iloc[i]
        return result

    def _pivot_low(self, series, left_len, right_len):
        result = pd.Series(np.nan, index=series.index)
        for i in range(left_len + right_len, len(series)):
            if all(series.iloc[i] < series.iloc[i - j] for j in range(1, left_len + 1)) and \
               all(series.iloc[i] < series.iloc[i + j] for j in range(1, right_len + 1)):
                result.iloc[i] = series.iloc[i]
        return result

    def _crossover(self, a, b):
        result = pd.Series(False, index=a.index)
        for i in range(1, len(a)):
            if a.iloc[i - 1] <= b and a.iloc[i] > b:
                result.iloc[i] = True
        return result

    def _crossunder(self, a, b):
        result = pd.Series(False, index=a.index)
        for i in range(1, len(a)):
            if a.iloc[i - 1] >= b and a.iloc[i] < b:
                result.iloc[i] = True
        return result

    def next(self):
        vwo_current = self.vwo_norm[-1]
        close_current = self.data.Close[-1]
        high_current = self.data.High[-1]
        low_current = self.data.Low[-1]
        atr_current = self.atr_val[-1] if not np.isnan(self.atr_val[-1]) else 0
        
        signal_bull = False
        signal_bear = False
        
        if self.operation_mode == "Signals after pivot breakout":
            pivot_h = self.pivot_high[-1]
            pivot_l = self.pivot_low[-1]
            
            # High pivot breakout
            if not np.isnan(pivot_h) and pivot_h > self.pos_ob_level:
                if self.last_hi_lvl is None or (pivot_h > self.last_hi_lvl and 
                    (not self.use_price_filter or close_current > self.last_hi_close)):
                    self.last_hi_lvl = pivot_h
                    self.last_hi_close = close_current
                    self.hi_lvls.append(pivot_h)
            
            # Low pivot breakout
            if not np.isnan(pivot_l) and pivot_l < self.neg_os_level:
                if self.last_lo_lvl is None or (pivot_l < self.last_lo_lvl and 
                    (not self.use_price_filter or close_current < self.last_lo_close)):
                    self.last_lo_lvl = pivot_l
                    self.last_lo_close = close_current
                    self.lo_lvls.append(pivot_l)
            
            # Check for breakouts above/below pivot levels
            for lvl in self.hi_lvls:
                if vwo_current > lvl:
                    signal_bull = True
                    self.hi_lvls.remove(lvl)
                    break
            
            for lvl in self.lo_lvls:
                if vwo_current < lvl:
                    signal_bear = True
                    self.lo_lvls.remove(lvl)
                    break
        
        else:  # OB/OS continuation mode
            if self.bull_cross_obc[-1]:
                signal_bull = True
            if self.bear_cross_obc[-1]:
                signal_bear = True
        
        # Entry logic
        if signal_bull and self.trade_dir == 0:
            risk_dist = atr_current * self.sl_atr_mult if self.use_atr_for_sl else close_current * (self.sl_percent / 100)
            self.sl_level = close_current - risk_dist
            self.tp_level = close_current + risk_dist * self.rr_tp3
            self.entry_price = close_current
            self.trade_dir = 1
            self.entry_bar = len(self.data)
            self.buy()
        
        elif signal_bear and self.trade_dir == 0:
            risk_dist = atr_current * self.sl_atr_mult if self.use_atr_for_sl else close_current * (self.sl_percent / 100)
            self.sl_level = close_current + risk_dist
            self.tp_level = close_current - risk_dist * self.rr_tp3
            self.entry_price = close_current
            self.trade_dir = -1
            self.entry_bar = len(self.data)
            self.sell()
        
        # Exit logic
        if self.trade_dir == 1:
            if low_current <= self.sl_level or high_current >= self.tp_level:
                self.sell()
                self.trade_dir = 0
        
        elif self.trade_dir == -1:
            if high_current >= self.sl_level or low_current <= self.tp_level:
                self.buy()
                self.trade_dir = 0