import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # AO Parameters
    length_ao_1 = 22
    length_ao_2 = 49
    ma_ao_type = 'EMA'
    length_ma_ao = 730
    source_ma_ao_type = 'EMA'

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate moving averages for AO
        def get_ma(source, length, ma_type):
            if ma_type == 'EMA':
                return pta.ema(source, length=length)
            elif ma_type == 'SMA':
                return pta.sma(source, length=length)
            elif ma_type == 'RMA':
                return pta.rma(source, length=length)
            elif ma_type == 'WMA':
                return pta.wma(source, length=length)
            elif ma_type == 'VWMA':
                high = pd.Series(self.data.High)
                low = pd.Series(self.data.Low)
                volume = pd.Series(self.data.Volume)
                return pta.vwma(source, volume, length=length)
            elif ma_type == 'HMA':
                return pta.hma(source, length=length)
            return source
        
        # Calculate AO (Awesome Oscillator)
        ma1 = self.I(lambda: get_ma(close, self.length_ao_1, self.ma_ao_type) or pd.Series(0, index=close.index))
        ma2 = self.I(lambda: get_ma(close, self.length_ao_2, self.ma_ao_type) or pd.Series(0, index=close.index))
        
        self.ao = self.I(lambda: ma1 - ma2)
        
        # Calculate AO MA (signal line)
        self.ao_ma = self.I(lambda: get_ma(self.ao, self.length_ma_ao, self.source_ma_ao_type) or pd.Series(0, index=close.index))

    def next(self):
        # Get current values
        ao_current = self.ao[-1]
        ao_ma_current = self.ao_ma[-1]
        
        # Entry signal: AO crosses above AO MA (bullish)
        if len(self.ao) > 1 and len(self.ao_ma) > 1:
            ao_prev = self.ao[-2]
            ao_ma_prev = self.ao_ma[-2]
            
            # Long entry: AO crosses above AO MA
            if ao_prev <= ao_ma_prev and ao_current > ao_ma_current:
                if not self.position:
                    self.buy()
            
            # Short exit or reverse: AO crosses below AO MA
            elif ao_prev >= ao_ma_prev and ao_current < ao_ma_current:
                if self.position:
                    self.position.close()


