import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 9
    slowLen = 21

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate fast and slow EMAs on current timeframe
        self.fast_ema = self.I(pta.ema, close, length=self.fastLen)
        self.slow_ema = self.I(pta.ema, close, length=self.slowLen)
        
        # Calculate the EMA cross oscillator value
        # This simulates the multi-timeframe bullish count
        self.bull_count = self.I(self._calc_bull_count)
        
    def _calc_bull_count(self):
        """
        Simulate the multi-timeframe bullish count.
        Since backtesting.py doesn't support multi-timeframe data,
        we use the current timeframe fast/slow EMA relationship
        as a proxy for the oscillator value (0-7 scale).
        """
        close = pd.Series(self.data.Close)
        fast = pta.ema(close, length=self.fastLen)
        slow = pta.ema(close, length=self.slowLen)
        
        # Count how many bars the fast EMA is above slow EMA
        # in a rolling window to simulate multi-TF agreement
        bull_signal = (fast > slow).astype(int)
        
        # Use a rolling sum to create a smoother oscillator (0-7 range)
        bull_count = bull_signal.rolling(window=7, min_periods=1).sum()
        
        return bull_count

    def next(self):
        # Trading logic based on oscillator levels
        current_bull = self.bull_count[-1]
        
        # Buy when oscillator crosses above 3.5 (more than 50% of TFs bullish)
        if len(self.bull_count) > 1:
            prev_bull = self.bull_count[-2]
            
            if prev_bull <= 3.5 and current_bull > 3.5:
                if not self.position:
                    self.buy()
            
            # Sell when oscillator crosses below 3.5
            elif prev_bull > 3.5 and current_bull <= 3.5:
                if self.position:
                    self.position.close()