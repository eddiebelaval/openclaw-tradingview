    def _calculate_accel_atr(self):
        """Calculate acceleration (change in slope)"""
        result = pd.Series(index=self.data.Close.index, dtype=float)
        
        for i in range(len(self.slopeAtr)):
            if i == 0 or self.slopeAtr[i] is None or self.slopeAtr[i-1] is None:
                result.iloc[i] = np.nan
            else:
                result.iloc[i] = self.slopeAtr[i] - self.slopeAtr[i-1]
        
        return result
    
    def next(self):
        if len(self.data) < self.length:
            return
        
        lowess_val = self.lowess[-1]
        slope_atr = self.slopeAtr[-1]
        accel_atr = self.accelAtr[-1]
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        if lowess_val is None or slope_atr is None or accel_atr is None:
            return
        
        # Regime detection
        upRegime = slope_atr > self.slopeThreshold
        downRegime = slope_atr < -self.slopeThreshold
        
        # Pullback detection
        bullPbBars = self._bars_since(low < lowess_val)
        bearPbBars = self._bars_since(high > lowess_val)
        bullPullbackRecent = bullPbBars <= self.pullbackLookback
        bearPullbackRecent = bearPbBars <= self.pullbackLookback
        
        # Slope crossovers
        slopeCrossUp = len(self.data) > 1 and self.slopeAtr[-2] <= 0 and slope_atr > 0
        slopeCrossDown = len(self.data) > 1 and self.slopeAtr[-2] >= 0 and slope_atr < 0
        
        # Price crossovers
        priceCrossUp = len(self.data) > 1 and self.data.Close[-2] <= lowess_val and close > lowess_val
        priceCrossDown = len(self.data) > 1 and self.data.Close[-2] >= lowess_val and close < lowess_val
        
        # Reversal signals
        bullRevRaw = slopeCrossUp and accel_atr > 0 and close > lowess_val
        bearRevRaw = slopeCrossDown and accel_atr < 0 and close < lowess_val
        
        # Continuation signals
        bullContRaw = upRegime and bullPullbackRecent and priceCrossUp and accel_atr > 0 and not bullRevRaw
        bearContRaw = downRegime and bearPullbackRecent and priceCrossDown and accel_atr < 0 and not bearRevRaw
        
        # Cooldown check
        bullRev = bullRevRaw and (len(self.data) - self.lastBullRev > self.cooldownBars)
        bearRev = bearRevRaw and (len(self.data) - self.lastBearRev > self.cooldownBars)
        bullCont = bullContRaw and (len(self.data) - self.lastBullCont > self.cooldownBars)
        bearCont = bearContRaw and (len(self.data) - self.lastBearCont > self.cooldownBars)
        
        # Update last signal indices
        if bullRev:
            self.lastBullRev = len(self.data)
        if bearRev:
            self.lastBearRev = len(self.data)
        if bullCont:
            self.lastBullCont = len(self.data)
        if bearCont:
            self.lastBearCont = len(self.data)
        
        # Trading logic
        if bullRev or bullCont:
            if self.position.is_short:
                self.position.close()
            if not self.position.is_long:
                self.buy()
        elif bearRev or bearCont:
            if self.position.is_long:
                self.position.close()
            if not self.position.is_short:
                self.sell()
    
    def _bars_since(self, condition):
        """Count bars since condition was true"""
        for i in range(len(self.data) - 1, -1, -1):
            try:
                if condition.iloc[i] if hasattr(condition, 'iloc') else condition:
                    return len(self.data) - 1 - i
            except:
                pass
        return 100000


