import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastMA = 12
    slowMA = 26
    signalLength = 9
    rsiLength = 14

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate MACD
        macd_result = self.I(lambda: pta.macd(close, fast=self.fastMA, slow=self.slowMA, signal=self.signalLength))
        self.macdLine = macd_result.iloc[:, 0] if macd_result is not None else pd.Series(0, index=close.index)
        self.macdSignal = macd_result.iloc[:, 1] if macd_result is not None else pd.Series(0, index=close.index)
        self.macdHist = macd_result.iloc[:, 2] if macd_result is not None else pd.Series(0, index=close.index)
        
        # Calculate RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLength) or pd.Series(50, index=close.index))

    def next(self):
        if len(self.data) < 2:
            return
        
        # Current values
        macdLine_curr = self.macdLine[-1]
        macdLine_prev = self.macdLine[-2]
        rsi_curr = self.rsi[-1]
        rsi_prev = self.rsi[-2]
        
        # Conditions
        bullCondition_curr = macdLine_curr > 0 and rsi_curr > 50
        bullCondition_prev = macdLine_prev > 0 and rsi_prev > 50
        
        bearCondition_curr = macdLine_curr < 0 and rsi_curr < 50
        bearCondition_prev = macdLine_prev < 0 and rsi_prev < 50
        
        # Generate signals
        buySignal = bullCondition_curr and not bullCondition_prev
        sellSignal = bearCondition_curr and not bearCondition_prev
        
        # Trading logic
        if buySignal:
            self.buy()
        elif sellSignal:
            self.sell()