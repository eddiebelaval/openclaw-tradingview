import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MFI Settings
    length_mfi = 14
    length_ma_mfi = 365
    source_ma_mfi = 'EMA'
    signal_mfi = '50'

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate MFI
        self.mfi = self.I(pta.mfi, high, low, close, volume, length=self.length_mfi)

        # Calculate MFI Moving Average
        def calc_mfi_ma():
            mfi_values = pta.mfi(high, low, close, volume, length=self.length_mfi)
            if mfi_values is None:
                return pd.Series(50, index=close.index)

            if self.source_ma_mfi == 'EMA':
                ma_result = pta.ema(mfi_values, length=self.length_ma_mfi)
            elif self.source_ma_mfi == 'SMA':
                ma_result = pta.sma(mfi_values, length=self.length_ma_mfi)
            elif self.source_ma_mfi == 'RMA':
                ma_result = pta.rma(mfi_values, length=self.length_ma_mfi)
            elif self.source_ma_mfi == 'WMA':
                ma_result = pta.wma(mfi_values, length=self.length_ma_mfi)
            elif self.source_ma_mfi == 'VWMA':
                ma_result = pta.vwma(close, volume, length=self.length_ma_mfi)
            elif self.source_ma_mfi == 'HMA':
                ma_result = pta.hma(mfi_values, length=self.length_ma_mfi)
            else:
                ma_result = pta.ema(mfi_values, length=self.length_ma_mfi)

            return ma_result if ma_result is not None else pd.Series(50, index=close.index)

        self.mfi_ma = self.I(calc_mfi_ma)

        # Determine entry signal level
        def get_entry_signal():
            if self.signal_mfi == 'MFI MA':
                return self.mfi_ma
            else:
                return pd.Series(50, index=close.index)

        self.entry_signal = self.I(get_entry_signal)

    def next(self):
        # Get current values
        mfi_current = self.mfi[-1]
        entry_signal_current = self.entry_signal[-1]

        # Check for crossover (Bull signal)
        if len(self.mfi) > 1 and len(self.entry_signal) > 1:
            if crossover(self.mfi, self.entry_signal):
                if not self.position:
                    self.buy()
            # Check for crossunder (Bear signal)
            elif crossover(self.entry_signal, self.mfi):
                if self.position:
                    self.sell()