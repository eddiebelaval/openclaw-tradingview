    def _calculate_hurst_value(self, returns):
        """Calculate Hurst exponent from returns array"""
        if len(returns) < self.hurst_len:
            return 0.5
        
        sum_log_rs = 0.0
        sum_log_n = 0.0
        sum_log_rs_logn = 0.0
        sum_log_n2 = 0.0
        valid_count = 0
        
        for div in range(2, self.hurst_subdiv + 1):
            sub_len = int(len(returns) / div)
            if sub_len < 10:
                continue
            
            total_rs = 0.0
            rs_count = 0
            
            for seg in range(div):
                start_idx = seg * sub_len
                if start_idx + sub_len > len(returns):
                    continue
                
                seg_data = returns[start_idx:start_idx + sub_len]
                seg_mean = np.mean(seg_data)
                
                cum_dev = np.cumsum(seg_data - seg_mean)
                max_dev = np.max(cum_dev)
                min_dev = np.min(cum_dev)
                range_rs = max_dev - min_dev
                
                std_dev = np.std(seg_data, ddof=1)
                if std_dev > 0:
                    total_rs += range_rs / std_dev
                    rs_count += 1
            
            if rs_count > 0:
                avg_rs = total_rs / rs_count
                if avg_rs > 0:
                    log_n = np.log(sub_len)
                    log_rs = np.log(avg_rs)
                    sum_log_rs += log_rs
                    sum_log_n += log_n
                    sum_log_rs_logn += log_rs * log_n
                    sum_log_n2 += log_n * log_n
                    valid_count += 1
        
        if valid_count >= 3:
            n = float(valid_count)
            slope = (n * sum_log_rs_logn - sum_log_rs * sum_log_n) / (n * sum_log_n2 - sum_log_n * sum_log_n)
            return np.clip(slope, 0.0, 1.0)
        
        return 0.5

    def _calculate_shannon_entropy(self, returns, bins):
        """Calculate Shannon entropy from returns array"""
        if len(returns) == 0:
            return 0.0
        
        min_val = np.min(returns)
        max_val = np.max(returns)
        range_val = max_val - min_val
        
        if range_val == 0:
            return 0.0
        
        bin_width = range_val / bins
        entropy = 0.0
        
        for b in range(bins):
            bin_lo = min_val + b * bin_width
            bin_hi = bin_lo + bin_width
            
            if b == bins - 1:
                count = np.sum((returns >= bin_lo) & (returns <= bin_hi))
            else:
                count = np.sum((returns >= bin_lo) & (returns < bin_hi))
            
            prob = count / len(returns)
            if prob > 0:
                entropy -= prob * np.log2(prob)
        
        return entropy

