import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core Settings
    signal_mode = "Pivot Breakout"  # "Pivot Breakout" or "OB/OS Continuation"
    volume_window = 20
    overbought_level = 15.0
    oversold_level = -15.0
    
    # Pivot Settings
    pivot_look_left = 2
    pivot_look_right = 2
    price_direction_filter = False
    max_pivot_line_bars = 200
    
    # Signal Filters
    bar_close_confirm = True
    signal_cooldown = 5
    use_trend_filter = False
    trend_filter_period = 50
    
    # Risk Management
    atr_based_sl = True
    atr_calc_period = 14
    sl_atr_factor = 1.5
    sl_percent = 1.0
    tp1_ratio = 1.0
    tp2_ratio = 2.0
    tp3_ratio = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate Volume Momentum Oscillator
        vol_mean = self.I(lambda: pta.sma(volume, length=self.volume_window))
        vol_std_dev = self.I(lambda: volume.rolling(self.volume_window).std())
        vol_normalized = self.I(lambda: np.maximum((volume - vol_mean) / vol_std_dev, 0))
        
        price_movement = self.I(lambda: close.diff())
        raw_momentum = self.I(lambda: price_movement * vol_normalized)
        
        momentum_mean = self.I(lambda: pta.sma(raw_momentum, length=self.volume_window))
        momentum_std_dev = self.I(lambda: raw_momentum.rolling(self.volume_window).std())
        
        self.oscillator = self.I(
            lambda: ((raw_momentum - momentum_mean) / momentum_std_dev * 10).fillna(0)
        )
        
        # ATR for risk management
        self.atr_value = self.I(lambda: pta.atr(high, low, close, length=self.atr_calc_period))
        
        # Trend filter EMA
        self.trend_ema = self.I(lambda: pta.ema(close, length=self.trend_filter_period))
        
        # Volume surge detection
        self.vol_mean = vol_mean
        self.volume_surge_threshold = 2.0
        
        # State tracking
        self.trade_direction = 0
        self.trade_entry_price = None
        self.trade_sl = None
        self.trade_tp = None
        self.last_signal_bar = -self.signal_cooldown
        self.last_pivot_high = None
        self.last_pivot_low = None
        
    def next(self):
        # Prevent trading if insufficient data
        if len(self.data) < max(self.volume_window, self.atr_calc_period, self.trend_filter_period):
            return
        
        current_osc = self.oscillator[-1]
        current_vol = self.data.Volume[-1]
        vol_mean_val = self.vol_mean[-1]
        
        # Detect volume surge
        is_volume_surge = current_vol > vol_mean_val * self.volume_surge_threshold
        
        raw_bull_signal = False
        raw_bear_signal = False
        
        if self.signal_mode == "Pivot Breakout":
            # Detect pivot highs and lows
            if len(self.oscillator) > self.pivot_look_left + self.pivot_look_right + 1:
                # Check for pivot high
                idx = len(self.oscillator) - 1 - self.pivot_look_right
                if idx >= self.pivot_look_left and idx < len(self.oscillator) - self.pivot_look_right:
                    is_pivot_high = True
                    for i in range(1, self.pivot_look_left + 1):
                        if self.oscillator[idx - i] >= self.oscillator[idx]:
                            is_pivot_high = False
                            break
                    for i in range(1, self.pivot_look_right + 1):
                        if self.oscillator[idx + i] >= self.oscillator[idx]:
                            is_pivot_high = False
                            break
                    
                    if is_pivot_high and self.oscillator[idx] > self.overbought_level:
                        if self.last_pivot_high is None or self.oscillator[idx] > self.last_pivot_high:
                            self.last_pivot_high = self.oscillator[idx]
                            raw_bull_signal = True
                
                # Check for pivot low
                if idx >= self.pivot_look_left and idx < len(self.oscillator) - self.pivot_look_right:
                    is_pivot_low = True
                    for i in range(1, self.pivot_look_left + 1):
                        if self.oscillator[idx - i] <= self.oscillator[idx]:
                            is_pivot_low = False
                            break
                    for i in range(1, self.pivot_look_right + 1):
                        if self.oscillator[idx + i] <= self.oscillator[idx]:
                            is_pivot_low = False
                            break
                    
                    if is_pivot_low and self.oscillator[idx] < self.oversold_level:
                        if self.last_pivot_low is None or self.oscillator[idx] < self.last_pivot_low:
                            self.last_pivot_low = self.oscillator[idx]
                            raw_bear_signal = True
        else:
            # OB/OS Continuation mode
            if len(self.oscillator) > 1:
                if crossover(self.oscillator, self.overbought_level):
                    raw_bull_signal = True
                if crossover(self.oversold_level, self.oscillator):
                    raw_bear_signal = True
        
        # Apply filters
        cooldown_clear = (len(self.data) - self.last_signal_bar) >= self.signal_cooldown
        trend_bull_ok = not self.use_trend_filter or self.data.Close[-1] > self.trend_ema[-1]
        trend_bear_ok = not self.use_trend_filter or self.data.Close[-1] < self.trend_ema[-1]
        
        confirmed_bull = raw_bull_signal and cooldown_clear and trend_bull_ok
        confirmed_bear = raw_bear_signal and cooldown_clear and trend_bear_ok
        
        # Close existing trade if TP/SL hit
        if self.trade_direction != 0:
            if self.trade_direction == 1:
                if self.data.Low[-1] <= self.trade_sl or self.data.High[-1] >= self.trade_tp:
                    self.position.close()
                    self.trade_direction = 0
            else:
                if self.data.High[-1] >= self.trade_sl or self.data.Low[-1] <= self.trade_tp:
                    self.position.close()
                    self.trade_direction = 0
        
        # Enter new trade
        if confirmed_bull and not self.position:
            entry_price = self.data.Close[-1]
            if self.atr_based_sl:
                risk_dist = self.atr_value[-1] * self.sl_atr_factor
            else:
                risk_dist = entry_price * (self.sl_percent / 100)
            
            sl_price = entry_price - risk_dist
            tp_price = entry_price + risk_dist * self.tp3_ratio
            
            self.trade_sl = sl_price
            self.trade_tp = tp_price
            self.trade_direction = 1
            self.trade_entry_price = entry_price
            self.last_signal_bar = len(self.data)
            self.buy()
        
        elif confirmed_bear and not self.position:
            entry_price = self.data.Close[-1]
            if self.atr_based_sl:
                risk_dist = self.atr_value[-1] * self.sl_atr_factor
            else:
                risk_dist = entry_price * (self.sl_percent / 100)
            
            sl_price = entry_price + risk_dist
            tp_price = entry_price - risk_dist * self.tp3_ratio
            
            self.trade_sl = sl_price
            self.trade_tp = tp_price
            self.trade_direction = -1
            self.trade_entry_price = entry_price
            self.last_signal_bar = len(self.data)
            self.sell()


