import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 20
    slowLen = 50
    atrLen = 14
    atrMult = 1.5
    rr = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.emaFast = self.I(pta.ema, close, length=self.fastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.slowLen)
        self.atrVal = self.I(pta.atr, high, low, close, length=self.atrLen)

    def next(self):
        if len(self.data) < 2:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        prev_high = self.data.High[-2]
        prev_low = self.data.Low[-2]
        
        emaFastVal = self.emaFast[-1]
        emaSlowVal = self.emaSlow[-1]
        atrValue = self.atrVal[-1]
        
        if emaFastVal is None or emaSlowVal is None or atrValue is None:
            return
        
        trendUp = emaFastVal > emaSlowVal
        trendDown = emaFastVal < emaSlowVal
        
        breakHigh = close > prev_high
        breakLow = close < prev_low
        
        pullbackLong = trendUp and close < emaFastVal
        pullbackShort = trendDown and close > emaFastVal
        
        longTrigger = pullbackLong and breakHigh
        shortTrigger = pullbackShort and breakLow
        
        if longTrigger and not self.position:
            self.buy()
        
        if shortTrigger and not self.position:
            self.sell()
        
        if self.position:
            if self.position.is_long:
                entry_price = self.position.open_price
                longSL = entry_price - atrValue * self.atrMult
                longTP = entry_price + atrValue * self.atrMult * self.rr
                
                if close <= longSL or close >= longTP:
                    self.position.close()
            
            elif self.position.is_short:
                entry_price = self.position.open_price
                shortSL = entry_price + atrValue * self.atrMult
                shortTP = entry_price - atrValue * self.atrMult * self.rr
                
                if close >= shortSL or close <= shortTP:
                    self.position.close()


