import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    period_input = 100
    delta_input = 0.5
    lookback_mult_input = 1.0
    signal_length_input = 9
    ob_input = 0.8
    os_input = -0.8

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate source (hl2 = (high + low) / 2)
        src = (high + low) / 2
        
        # Resonator Math (Bilinear Transform / Unity Gain)
        PI = np.pi
        omega = 2 * PI / self.period_input
        alpha = np.tan(PI * self.delta_input / self.period_input)
        beta = np.cos(omega)
        r = 1.0 / (1.0 + alpha)
        
        c1 = 2 * r * beta
        c2 = -(2 * r - 1)
        gain = alpha * r
        
        # Bandpass filter calculation
        def calc_bp():
            bp = np.zeros(len(src))
            for i in range(len(src)):
                if i < 2:
                    bp[i] = gain * (src.iloc[i] - (src.iloc[0] if i < 2 else src.iloc[i-2]))
                else:
                    bp[i] = gain * (src.iloc[i] - src.iloc[i-2]) + c1 * bp[i-1] + c2 * bp[i-2]
            return pd.Series(bp, index=src.index)
        
        bp = self.I(calc_bp)
        
        # Normalization via Lookback Multiplier
        peak_lookback = max(1, int(self.period_input * self.lookback_mult_input))
        
        def calc_oscillator():
            osc = np.zeros(len(bp))
            for i in range(len(bp)):
                lookback_start = max(0, i - peak_lookback + 1)
                peak = np.max(np.abs(bp[lookback_start:i+1]))
                osc[i] = bp[i] / peak if peak != 0 else 0
            return pd.Series(osc, index=bp.index)
        
        oscillator = self.I(calc_oscillator)
        
        # Signal Line
        signal_line = self.I(pta.ema, pd.Series(oscillator), length=self.signal_length_input)
        
        self.oscillator = oscillator
        self.signal_line = signal_line

    def next(self):
        # Crossover Logic
        cross_up = crossover(self.oscillator, self.signal_line) and self.oscillator[-1] < self.os_input
        cross_down = crossover(self.signal_line, self.oscillator) and self.oscillator[-1] > self.ob_input
        
        if cross_up:
            self.buy()
        elif cross_down:
            self.sell()


