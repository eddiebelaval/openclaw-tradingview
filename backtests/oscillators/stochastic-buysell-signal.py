import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    periodK = 21
    smoothK = 8
    periodD = 8

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate raw stochastic
        stoch_result = self.I(pta.stoch, high, low, close, k=self.periodK, d=self.periodD, smooth_k=self.smoothK)
        
        # Extract %K line (first column of stochastic output)
        self.k = self.I(lambda: pta.stoch(high, low, close, k=self.periodK, d=self.periodD, smooth_k=self.smoothK).iloc[:, 0] if pta.stoch(high, low, close, k=self.periodK, d=self.periodD, smooth_k=self.smoothK) is not None else pd.Series(50, index=close.index))
        
        # Calculate %D as SMA of %K
        self.d = self.I(lambda: pta.sma(self.k, length=self.periodD) if len(self.k) > 0 else pd.Series(50, index=close.index))

    def next(self):
        if len(self.k) < 2 or len(self.d) < 2:
            return
        
        # Bull signal: K crosses above D and K < 20
        bull = crossover(self.k, self.d)
        bull_filter = bull and self.k[-1] < 20
        
        # Bear signal: K crosses below D and K > 80
        bear = crossover(self.d, self.k)
        bear_filter = bear and self.k[-1] > 80
        
        if bull_filter:
            if not self.position:
                self.buy()
        elif bear_filter:
            if self.position:
                self.sell()