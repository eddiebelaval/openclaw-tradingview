import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    pivotLen = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI
        self.myRsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        # Track pivot highs and lows manually
        self.rsiPivotHighs = self._calculate_pivot_highs(self.myRsi, self.pivotLen)
        self.rsiPivotLows = self._calculate_pivot_lows(self.myRsi, self.pivotLen)
        
        self.pricePivotHighs = self._calculate_pivot_highs(high, self.pivotLen)
        self.pricePivotLows = self._calculate_pivot_lows(low, self.pivotLen)
        
        # Regime tracking
        self.regime = 0
        self.p1_rsiHigh = None
        self.p1_priceHigh = None
        self.p1_highBar = None
        self.p1_rsiLow = None
        self.p1_priceLow = None
        self.p1_lowBar = None
        
        # Signal flags
        self.divergence_signal = 0

    def _calculate_pivot_highs(self, series, lookback):
        """Calculate pivot highs"""
        pivots = [False] * len(series)
        for i in range(lookback, len(series) - lookback):
            is_pivot = True
            for j in range(1, lookback + 1):
                if series.iloc[i] <= series.iloc[i - j] or series.iloc[i] <= series.iloc[i + j]:
                    is_pivot = False
                    break
            pivots[i] = is_pivot
        return pivots

    def _calculate_pivot_lows(self, series, lookback):
        """Calculate pivot lows"""
        pivots = [False] * len(series)
        for i in range(lookback, len(series) - lookback):
            is_pivot = True
            for j in range(1, lookback + 1):
                if series.iloc[i] >= series.iloc[i - j] or series.iloc[i] >= series.iloc[i + j]:
                    is_pivot = False
                    break
            pivots[i] = is_pivot
        return pivots

    def next(self):
        close = self.data.Close
        high = self.data.High
        low = self.data.Low
        rsi = self.myRsi
        
        idx = len(self) - 1
        
        # Update regime based on crossovers
        if idx > 0:
            if rsi[-2] <= 60 and rsi[-1] > 60:
                self.regime = 1
            elif rsi[-2] >= 40 and rsi[-1] < 40:
                self.regime = -1
        
        # Process pivot highs for bearish divergences
        if idx >= self.pivotLen and self.rsiPivotHighs[idx - self.pivotLen]:
            p2_rsiHigh = rsi[-(self.pivotLen + 1)]
            p2_priceHigh = high[-(self.pivotLen + 1)]
            p2_highBar = idx - self.pivotLen
            
            if self.p1_rsiHigh is not None:
                price_delta = abs(self.p1_priceHigh - p2_priceHigh)
                
                # Simple Bearish: Price HH, RSI LH
                if p2_priceHigh > self.p1_priceHigh and p2_rsiHigh < self.p1_rsiHigh:
                    self.divergence_signal = -1
                
                # Hidden Bearish: Price LH, RSI HH
                elif p2_priceHigh < self.p1_priceHigh and p2_rsiHigh > self.p1_rsiHigh:
                    self.divergence_signal = -1
            
            self.p1_rsiHigh = p2_rsiHigh
            self.p1_priceHigh = p2_priceHigh
            self.p1_highBar = p2_highBar
        
        # Process pivot lows for bullish divergences
        if idx >= self.pivotLen and self.rsiPivotLows[idx - self.pivotLen]:
            p2_rsiLow = rsi[-(self.pivotLen + 1)]
            p2_priceLow = low[-(self.pivotLen + 1)]
            p2_lowBar = idx - self.pivotLen
            
            if self.p1_rsiLow is not None:
                price_delta = abs(self.p1_priceLow - p2_priceLow)
                
                # Simple Bullish: Price LL, RSI HL
                if p2_priceLow < self.p1_priceLow and p2_rsiLow > self.p1_rsiLow:
                    self.divergence_signal = 1
                
                # Hidden Bullish: Price HL, RSI LL
                elif p2_priceLow > self.p1_priceLow and p2_rsiLow < self.p1_rsiLow:
                    self.divergence_signal = 1
            
            self.p1_rsiLow = p2_rsiLow
            self.p1_priceLow = p2_priceLow
            self.p1_lowBar = p2_lowBar
        
        # Trading logic based on regime and divergence
        if self.regime == 1 and self.divergence_signal == 1:
            if not self.position:
                self.buy()
            self.divergence_signal = 0
        elif self.regime == -1 and self.divergence_signal == -1:
            if self.position:
                self.position.close()
            self.divergence_signal = 0
        
        # Exit on regime shift
        if self.regime == -1 and self.position:
            self.position.close()
        elif self.regime == 1 and not self.position and rsi[-1] < 50:
            pass


