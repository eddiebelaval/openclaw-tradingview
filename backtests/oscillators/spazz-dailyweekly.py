import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    RSI_LENGTH = 14
    BB_LENGTH = 20
    BB_MULT = 1.76

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        bb = self.I(lambda: pta.bbands(close, length=self.BB_LENGTH, std=self.BB_MULT))
        self.bb_upper = bb.iloc[:, 2] if bb is not None else pd.Series(0, index=close.index)
        self.bb_lower = bb.iloc[:, 0] if bb is not None else pd.Series(0, index=close.index)
        
        # RSI and RSI Z-Score
        rsi = self.I(lambda: pta.rsi(close, length=self.RSI_LENGTH) or pd.Series(50, index=close.index))
        
        # RSI Mean and StdDev
        rsi_mean = self.I(lambda: pta.sma(rsi, length=self.RSI_LENGTH) or pd.Series(50, index=close.index))
        
        # RSI StdDev calculation
        def rsi_stddev():
            rsi_vals = pta.rsi(close, length=self.RSI_LENGTH)
            if rsi_vals is None:
                return pd.Series(0, index=close.index)
            return rsi_vals.rolling(window=self.RSI_LENGTH).std()
        
        rsi_std = self.I(rsi_stddev)
        
        # Z-Score calculation
        def zscore_calc():
            rsi_vals = pta.rsi(close, length=self.RSI_LENGTH)
            if rsi_vals is None:
                return pd.Series(0, index=close.index)
            rsi_m = pta.sma(rsi_vals, length=self.RSI_LENGTH)
            if rsi_m is None:
                return pd.Series(0, index=close.index)
            rsi_std_vals = rsi_vals.rolling(window=self.RSI_LENGTH).std()
            if rsi_std_vals is None:
                return pd.Series(0, index=close.index)
            zscore = (rsi_vals - rsi_m) / rsi_std_vals.replace(0, 1)
            return zscore
        
        self.zscore = self.I(zscore_calc)
        self.close = self.I(lambda: close)

    def next(self):
        # Signal conditions
        up = crossover(self.zscore, 0)
        down = crossover(0, self.zscore)
        uppies = crossover(self.close, self.bb_lower)
        downies = crossover(self.bb_upper, self.close)
        
        # Buy signal: zscore crosses above 0 AND close crosses above lower BB
        if up and uppies:
            if not self.position:
                self.buy()
        
