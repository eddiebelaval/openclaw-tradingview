import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    indicator_type = "RSI Delta"
    rsi_len = 14
    rsi_ma_len = 14
    rsi_ma_type = "SMA"
    macd_fast_len = 12
    macd_slow_len = 26
    macd_signal_len = 9
    stoch_k_len = 14
    stoch_k_smooth = 1
    stoch_d_smooth = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        if self.indicator_type == "RSI Delta":
            rsi = self.I(pta.rsi, close, length=self.rsi_len)
            
            if self.rsi_ma_type == "SMA":
                rsi_ma = self.I(pta.sma, rsi, length=self.rsi_ma_len)
            elif self.rsi_ma_type == "EMA":
                rsi_ma = self.I(pta.ema, rsi, length=self.rsi_ma_len)
            elif self.rsi_ma_type == "WMA":
                rsi_ma = self.I(pta.wma, rsi, length=self.rsi_ma_len)
            else:  # RMA
                rsi_ma = self.I(pta.rma, rsi, length=self.rsi_ma_len)
            
            self.delta = self.I(lambda: rsi - rsi_ma)

        elif self.indicator_type == "MACD Delta":
            macd_result = self.I(
                pta.macd,
                close,
                fast=self.macd_fast_len,
                slow=self.macd_slow_len,
                signal=self.macd_signal_len
            )
            self.delta = self.I(
                lambda: macd_result.iloc[:, 2] if macd_result is not None and macd_result.shape[1] > 2 else pd.Series(0, index=close.index)
            )

        elif self.indicator_type == "Stochastic Delta":
            stoch_result = self.I(
                pta.stoch,
                high,
                low,
                close,
                k=self.stoch_k_len,
                d=self.stoch_d_smooth,
                smooth_k=self.stoch_k_smooth
            )
            
            if stoch_result is not None and not stoch_result.empty:
                stoch_k_col = [col for col in stoch_result.columns if 'STOCHk' in col or col.startswith('STOCH_K')]
                stoch_d_col = [col for col in stoch_result.columns if 'STOCHd' in col or col.startswith('STOCH_D')]
                
                if stoch_k_col and stoch_d_col:
                    stoch_k_smoothed = self.I(lambda: stoch_result[stoch_k_col[0]])
                    stoch_d = self.I(lambda: stoch_result[stoch_d_col[0]])
                    self.delta = self.I(lambda: stoch_k_smoothed - stoch_d)
                else:
                    self.delta = self.I(lambda: pd.Series(0, index=close.index))
            else:
                self.delta = self.I(lambda: pd.Series(0, index=close.index))

    def next(self):
        if len(self.data) < 2:
            return

        current_delta = self.delta[-1]
        prev_delta = self.delta[-2] if len(self.delta) > 1 else current_delta

        if prev_delta <= 0 and current_delta > 0:
            if not self.position:
                self.buy()
        elif prev_delta >= 0 and current_delta < 0:
            if self.position:
                self.position.close()