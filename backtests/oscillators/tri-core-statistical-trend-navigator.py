import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 14
    sl_mult = 1.5
    tp1_mult = 1.5
    tp2_mult = 3.0
    tp3_mult = 4.5
    z_length = 20
    chop_length = 14
    rsi_length = 14
    dmi_length = 14
    supertrend_factor = 3
    supertrend_atr = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Golden POC (VWAP)
        self.golden_poc = self.I(pta.vwap, high, low, close, volume)

        # Engine 1: Z-Score
        self.z_mean = self.I(pta.sma, close, length=self.z_length)
        self.z_std = self.I(lambda: close.rolling(self.z_length).std())
        self.z_score = self.I(lambda: (close - self.z_mean) / (self.z_std + 1e-10))

        # Engine 2: MACD
        macd_result = self.I(pta.macd, close, fast=12, slow=26, signal=9)
        self.macd_line = self.I(lambda: macd_result.iloc[:, 0] if macd_result is not None else pd.Series(0, index=close.index))
        self.signal_line = self.I(lambda: macd_result.iloc[:, 1] if macd_result is not None else pd.Series(0, index=close.index))

        # Engine 3: Moving Averages
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema50 = self.I(pta.ema, close, length=50)

        # ATR for SL/TP
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)

        # RSI for divergence
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)

        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=self.dmi_length)
        self.adx = self.I(lambda: adx_result.iloc[:, 2] if adx_result is not None else pd.Series(20, index=close.index))

        # Supertrend
        st_result = self.I(lambda: self._supertrend(high, low, close, self.supertrend_atr, self.supertrend_factor))
        self.supertrend = self.I(lambda: st_result[0] if st_result is not None else pd.Series(0, index=close.index))
        self.st_dir = self.I(lambda: st_result[1] if st_result is not None else pd.Series(0, index=close.index))

        # Highest/Lowest for CHOP
        self.highest_close_10 = self.I(lambda: close.rolling(10).max())
        self.lowest_close_10 = self.I(lambda: close.rolling(10).min())
        self.highest_rsi_10 = self.I(lambda: self.rsi.rolling(10).max())
        self.lowest_rsi_10 = self.I(lambda: self.rsi.rolling(10).min())
        self.highest_high = self.I(lambda: high.rolling(self.chop_length).max())
        self.lowest_low = self.I(lambda: low.rolling(self.chop_length).min())

        self.entry_price = None
        self.trade_dir = 0

    def _supertrend(self, high, low, close, atr_period, multiplier):
        hl2 = (high + low) / 2
        atr = pta.atr(high, low, close, length=atr_period)
        if atr is None:
            return None, None

        basic_ub = hl2 + multiplier * atr
        basic_lb = hl2 - multiplier * atr

        final_ub = pd.Series(index=close.index, dtype=float)
        final_lb = pd.Series(index=close.index, dtype=float)

        for i in range(len(close)):
            if i == 0:
                final_ub.iloc[i] = basic_ub.iloc[i]
                final_lb.iloc[i] = basic_lb.iloc[i]
            else:
                final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i - 1] or close.iloc[i - 1] > final_ub.iloc[i - 1] else final_ub.iloc[i - 1]
                final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i - 1] or close.iloc[i - 1] < final_lb.iloc[i - 1] else final_lb.iloc[i - 1]

        supertrend = pd.Series(index=close.index, dtype=float)
        st_dir = pd.Series(index=close.index, dtype=float)

        for i in range(len(close)):
            if i == 0:
                supertrend.iloc[i] = final_ub.iloc[i]
                st_dir.iloc[i] = -1
            else:
                if supertrend.iloc[i - 1] == final_ub.iloc[i - 1]:
                    supertrend.iloc[i] = final_ub.iloc[i] if close.iloc[i] <= final_ub.iloc[i] else final_lb.iloc[i]
                    st_dir.iloc[i] = -1 if close.iloc[i] <= final_ub.iloc[i] else 1
                else:
                    supertrend.iloc[i] = final_lb.iloc[i] if close.iloc[i] >= final_lb.iloc[i] else final_ub.iloc[i]
                    st_dir.iloc[i] = 1 if close.iloc[i] >= final_lb.iloc[i] else -1

        return supertrend, st_dir

    def next(self):
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]

        if len(self.data) < self.z_length + 5:
            return

        # Safely access indicators
        golden_poc = self.golden_poc[-1] if len(self.golden_poc) > 0 else close_val
        z_score = self.z_score[-1] if len(self.z_score) > 0 else 0
        macd_line = self.macd_line[-1] if len(self.macd_line) > 0 else 0
        signal_line = self.signal_line[-1] if len(self.signal_line) > 0 else 0
        ema20 = self.ema20[-1] if len(self.ema20) > 0 else close_val
        ema50 = self.ema50[-1] if len(self.ema50) > 0 else close_val
        atr = self.atr[-1] if len(self.atr) > 0 else 0

        # MACD crossovers
        mom_cross_up = crossover(self.macd_line, self.signal_line)
        mom_cross_down = crossover(self.signal_line, self.macd_line)

        # Long signals
        long_a_plus = mom_cross_up and (z_score < -1.5) and (close_val > ema50)
        long_a = mom_cross_up and (close_val > ema50) and (close_val > golden_poc) and not long_a_plus
        long_b = mom_cross_up and not long_a_plus and not long_a

        # Short signals
        short_a_plus = mom_cross_down and (z_score > 1.5) and (close_val < ema50)
        short_a = mom_cross_down and (close_val < ema50) and (close_val < golden_poc) and not short_a_plus
        short_b = mom_cross_down and not short_a_plus and not short_a

        # Execute trades
        if long_a_plus or long_a or long_b:
            if not self.position:
                self.buy()
                self.entry_price = close_val
                self.trade_dir = 1

        elif short_a_plus or short_a or short_b:
            if not self.position:
                self.sell()
                self.entry_price = close_val
                self.trade_dir = -1

        # Exit logic with TP levels
        if self.position:
            if self.trade_dir == 1:
                tp3 = self.entry_price + (atr * self.tp3_mult)
                tp2 = self.entry_price + (atr * self.tp2_mult)
                sl = self.entry_price - (atr * self.sl_mult)

                if close_val >= tp3:
                    self.position.close()
                    self.trade_dir = 0
                elif close_val >= tp2 and len(self.data) % 3 == 0:
                    self.position.close()
                    self.trade_dir = 0
                elif close_val <= sl:
                    self.position.close()
                    self.trade_dir = 0

            elif self.trade_dir == -1:
                tp3 = self.entry_price - (atr * self.tp3_mult)
                tp2 = self.entry_price - (atr * self.tp2_mult)
                sl = self.entry_price + (atr * self.sl_mult)

                if close_val <= tp3:
                    self.position.close()
                    self.trade_dir = 0
                elif close_val <= tp2 and len(self.data) % 3 == 0:
                    self.position.close()
                    self.trade_dir = 0
                elif close_val >= sl:
                    self.position.close()
                    self.trade_dir = 0


