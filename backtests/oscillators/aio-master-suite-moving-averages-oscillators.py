import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA1 defaults
    len_ma1 = 5
    type_ma1 = "EMA"
    
    # MA2 defaults
    len_ma2 = 8
    type_ma2 = "EMA"
    
    # MA3 defaults
    len_ma3 = 13
    type_ma3 = "EMA"
    
    # Oscillator defaults
    rsi_len = 14
    macd_fast = 12
    macd_slow = 26
    macd_sig = 9
    mfi_len = 14
    cmf_len = 20
    adx_len = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # MA1 - EMA(5)
        self.ma1 = self.I(lambda: pta.ema(close, length=self.len_ma1) or pd.Series(close))
        
        # MA2 - EMA(8)
        self.ma2 = self.I(lambda: pta.ema(close, length=self.len_ma2) or pd.Series(close))
        
        # MA3 - EMA(13)
        self.ma3 = self.I(lambda: pta.ema(close, length=self.len_ma3) or pd.Series(close))
        
        # RSI(14)
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_len) or pd.Series(50, index=close.index))
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig))
        self.macd_line = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig).iloc[:, 0] if pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig) is not None else pd.Series(0, index=close.index))
        self.macd_signal = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig).iloc[:, 1] if pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig) is not None else pd.Series(0, index=close.index))
        self.macd_hist = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig).iloc[:, 2] if pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig) is not None else pd.Series(0, index=close.index))
        
        # MFI(14)
        self.mfi = self.I(lambda: pta.mfi(high, low, close, volume, length=self.mfi_len) or pd.Series(50, index=close.index))
        
        # CMF(20)
        def calc_cmf():
            ad = pd.Series(0.0, index=close.index)
            for i in range(len(close)):
                if high.iloc[i] == low.iloc[i]:
                    ad.iloc[i] = 0
                else:
                    ad.iloc[i] = ((2 * close.iloc[i] - low.iloc[i] - high.iloc[i]) / (high.iloc[i] - low.iloc[i])) * volume.iloc[i]
            cmf = ad.rolling(window=self.cmf_len).sum() / volume.rolling(window=self.cmf_len).sum()
            return cmf
        
        self.cmf = self.I(calc_cmf)
        
        # ADX(14)
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_len))
        self.adx = self.I(lambda: pta.adx(high, low, close, length=self.adx_len).iloc[:, 2] if pta.adx(high, low, close, length=self.adx_len) is not None else pd.Series(0, index=close.index))

    def next(self):
        # Trading signals based on moving averages and oscillators
        
        # Buy signal: Fast MA crosses above slow MA + RSI not overbought + MACD positive
        ma_bullish = crossover(self.ma1, self.ma2)
        rsi_ok = self.rsi[-1] < 70
        macd_ok = self.macd_line[-1] > self.macd_signal[-1]
        
        if ma_bullish and rsi_ok and macd_ok and not self.position:
            self.buy()
        
        # Sell signal: Fast MA crosses below slow MA or RSI overbought or MACD negative
        ma_bearish = crossover(self.ma2, self.ma1)
        rsi_overbought = self.rsi[-1] > 70
        macd_bearish = self.macd_line[-1] < self.macd_signal[-1]
        
        if (ma_bearish or rsi_overbought or macd_bearish) and self.position:
            self.sell()


