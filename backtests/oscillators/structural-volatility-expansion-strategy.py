import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 5
    atr_length = 14
    vol_lookback = 50
    compression_mult = 0.8
    htf_len = 50
    atr_stop_mult = 1.5
    rr_target = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # ATR and volatility regime
        self.atr_value = self.I(pta.atr, high, low, close, length=self.atr_length)
        self.atr_mean = self.I(pta.sma, self.atr_value, length=self.vol_lookback)

        # Pivot points using rolling max/min
        self.pivot_high = self.I(
            lambda: high.rolling(window=self.pivot_len * 2 + 1, center=True).max()
        )
        self.pivot_low = self.I(
            lambda: low.rolling(window=self.pivot_len * 2 + 1, center=True).min()
        )

        # HTF Moving Average (simulated with standard MA on current timeframe)
        self.htf_ma = self.I(pta.sma, close, length=self.htf_len)

        # Track last pivot values
        self.last_high = None
        self.last_low = None

    def next(self):
        # Update last pivot values
        if not np.isnan(self.pivot_high[-1]) and self.pivot_high[-1] > 0:
            self.last_high = self.pivot_high[-1]

        if not np.isnan(self.pivot_low[-1]) and self.pivot_low[-1] > 0:
            self.last_low = self.pivot_low[-1]

        # Check if indicators are ready
        if np.isnan(self.atr_value[-1]) or np.isnan(self.atr_mean[-1]) or np.isnan(self.htf_ma[-1]):
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        atr_val = self.atr_value[-1]
        atr_mn = self.atr_mean[-1]
        htf_ma = self.htf_ma[-1]

        # Volatility regime detection
        is_compression = atr_val < atr_mn * self.compression_mult
        is_expansion = atr_val > atr_mn

        # Structure break detection
        bos_up = self.last_high is not None and close > self.last_high
        bos_down = self.last_low is not None and close < self.last_low

        # Liquidity sweep filter
        liquidity_sweep_high = (
            self.last_high is not None
            and high > self.last_high
            and close < self.last_high
        )
        liquidity_sweep_low = (
            self.last_low is not None
            and low < self.last_low
            and close > self.last_low
        )

        # HTF bias
        htf_bull = close > htf_ma
        htf_bear = close < htf_ma

        # Entry conditions
        long_condition = (
            is_expansion
            and bos_up
            and not liquidity_sweep_high
            and htf_bull
        )

        short_condition = (
            is_expansion
            and bos_down
            and not liquidity_sweep_low
            and htf_bear
        )

        # Execution
        if long_condition and not self.position:
            stop_price = close - atr_val * self.atr_stop_mult
            risk_points = close - stop_price
            target_price = close + risk_points * self.rr_target

            self.buy()
            self.sl = stop_price
            self.tp = target_price

        elif short_condition and not self.position:
            stop_price = close + atr_val * self.atr_stop_mult
            risk_points = stop_price - close
            target_price = close - risk_points * self.rr_target

            self.sell()
            self.sl = stop_price
            self.tp = target_price

        # Check stops and targets
        if self.position:
            if self.position.is_long:
                if close <= self.sl or close >= self.tp:
                    self.position.close()
            elif self.position.is_short:
                if close >= self.sl or close <= self.tp:
                    self.position.close()


