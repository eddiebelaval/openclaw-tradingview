import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vol_length = 50
    vol_z_threshold = 2.5
    max_anchors = 24
    anchor_cooldown = 5
    hist_scale = 1.0
    color_smooth = 1
    streak_window = 14

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate volume z-score
        def calc_vol_z():
            vol_sma = pta.sma(volume, length=self.vol_length)
            vol_sd = pta.stdev(volume, length=self.vol_length)
            vol_z = np.where(vol_sd > 0, (volume - vol_sma) / vol_sd, 0)
            return pd.Series(vol_z, index=volume.index)
        
        self.vol_z = self.I(calc_vol_z)
        
        # Store historical data for anchor tracking
        self.sum_gain_arr = []
        self.sum_loss_arr = []
        self.count_arr = []
        self.bars_since_last_anchor = 0
        self.active_rsis = []
        self.meta_mean_history = []
        self.scaled_engine_history = []
        self.max_rsi_history = []
        self.min_rsi_history = []
        self.is_anomaly_history = []
        self.bg_streak_count = 0
        self.last_consensus_bar = -100

    def next(self):
        if len(self.data) < 1:
            return
        
        idx = len(self.data) - 1
        current_time = self.data.index[-1]
        lookback_time = pd.Timestamp("2024-03-21 04:00:00", tz='UTC')
        is_within_lookback = current_time >= lookback_time
        
        # Volume anomaly detection
        self.bars_since_last_anchor += 1
        
        current_vol_z = self.vol_z[-1] if not np.isnan(self.vol_z[-1]) else 0
        is_anomaly = (current_vol_z >= self.vol_z_threshold) and is_within_lookback and (self.bars_since_last_anchor >= self.anchor_cooldown)
        self.is_anomaly_history.append(is_anomaly)
        
        if is_anomaly:
            self.bars_since_last_anchor = 0
            self.sum_gain_arr.insert(0, 0.0)
            self.sum_loss_arr.insert(0, 0.0)
            self.count_arr.insert(0, 0)
            
            if len(self.sum_gain_arr) > self.max_anchors:
                self.sum_gain_arr.pop()
                self.sum_loss_arr.pop()
                self.count_arr.pop()
        
        # Current bar gains/losses
        if idx > 0:
            chg = self.data.Close[-1] - self.data.Close[-2]
        else:
            chg = 0
        current_gain = max(chg, 0)
        current_loss = max(-chg, 0)
        
        self.active_rsis = []
        current_cluster_size = len(self.sum_gain_arr)
        
        if current_cluster_size > 0:
            for i in range(current_cluster_size):
                g_sum = self.sum_gain_arr[i] + current_gain
                l_sum = self.sum_loss_arr[i] + current_loss
                cnt = self.count_arr[i] + 1
                
                self.sum_gain_arr[i] = g_sum
                self.sum_loss_arr[i] = l_sum
                self.count_arr[i] = cnt
                
                rsi_val = 50.0
                if cnt > 0:
                    if l_sum == 0:
                        rsi_val = 100.0
                    elif g_sum == 0:
                        rsi_val = 0.0
                    else:
                        rs = g_sum / l_sum
                        rsi_val = 100.0 - (100.0 / (1.0 + rs))
                
                self.active_rsis.append(rsi_val)
        
        # Calculate meta mean and engine
        sz = len(self.active_rsis)
        meta_mean = np.mean(self.active_rsis) if sz > 0 else np.nan
        engine_dev = meta_mean - 50.0 if not np.isnan(meta_mean) else 0
        scaled_engine = 50.0 + (engine_dev * self.hist_scale)
        
        self.meta_mean_history.append(meta_mean)
        self.scaled_engine_history.append(scaled_engine)
        
        if sz > 0:
            max_rsi = max(self.active_rsis)
            min_rsi = min(self.active_rsis)
        else:
            max_rsi = np.nan
            min_rsi = np.nan
        
        self.max_rsi_history.append(max_rsi)
        self.min_rsi_history.append(min_rsi)
        
        # Full consensus streak
        all_below_50 = sz > 0 and max_rsi < 50
        all_above_50 = sz > 0 and min_rsi > 50
        
        if all_below_50 or all_above_50:
            if idx - self.last_consensus_bar <= self.streak_window:
                self.bg_streak_count += 1
            else:
                self.bg_streak_count = 1
            self.last_consensus_bar = idx
        else:
            if idx - self.last_consensus_bar > self.streak_window:
                self.bg_streak_count = 0
        
        # Trading logic
        if not np.isnan(scaled_engine):
            prev_engine = self.scaled_engine_history[-2] if len(self.scaled_engine_history) > 1 else 50
            
            # Buy when engine crosses above 50 and all RSIs below 50 (bullish consensus)
            if all_below_50 and crossover(self.scaled_engine_history[-2:], 50):
                if not self.position:
                    self.buy()
            
            # Sell when engine crosses below 50 and all RSIs above 50 (bearish consensus)
            elif all_above_50 and crossover(50, self.scaled_engine_history[-2:]):
                if self.position:
                    self.sell()
            
            # Exit on strong reversal signals
            elif self.position and all_above_50 and scaled_engine > 70:
                self.sell()
            elif not self.position and all_below_50 and scaled_engine < 30:
                self.buy()


