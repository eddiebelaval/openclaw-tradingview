    def _find_pivot_low(self, idx):
        if idx < self.pivotLeft + self.pivotRight:
            return False, -1, 0, 0
        center = idx - self.pivotRight
        if center < self.pivotLeft:
            return False, -1, 0, 0

        rsi_vals = [self.rsi[i] for i in range(max(0, center - self.pivotLeft), center + self.pivotRight + 1)]
        low_vals = [self.low_series.iloc[i] for i in range(max(0, center - self.pivotLeft), center + self.pivotRight + 1)]

        if len(rsi_vals) != self.pivotLeft + 1 + self.pivotRight:
            return False, -1, 0, 0

        is_pivot = True
        for i in range(self.pivotLeft):
            if rsi_vals[i] <= rsi_vals[self.pivotLeft]:
                is_pivot = False
                break
        if is_pivot:
            for i in range(self.pivotLeft + 1, self.pivotLeft + 1 + self.pivotRight):
                if rsi_vals[i] <= rsi_vals[self.pivotLeft]:
                    is_pivot = False
                    break

        if is_pivot:
            return True, center, rsi_vals[self.pivotLeft], low_vals[self.pivotLeft]
        return False, -1, 0, 0

