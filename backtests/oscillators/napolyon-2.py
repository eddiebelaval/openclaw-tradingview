import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        macd_result = self.I(pta.macd, close, fast=12, slow=26, signal=9)
        self.macd_line = macd_result.iloc[:, 0]
        self.signal_line = macd_result.iloc[:, 1]
        self.histogram = macd_result.iloc[:, 2]

    def next(self):
        if len(self.data) < 2:
            return

        hist_current = self.histogram[-1]
        hist_prev = self.histogram[-2]

        is_up = hist_current > hist_prev
        is_down = hist_current < hist_prev
        is_pos = hist_current > 0
        is_neg = hist_current < 0

        if not hasattr(self, '_up_count'):
            self._up_count = 0
            self._down_count = 0
            self._ready_for_buy = False
            self._ready_for_sell = False

        buy_signal = False
        sell_signal = False

        # Buy logic
        if is_pos:
            if is_down:
                self._ready_for_buy = True
                self._up_count = 0
            if is_up and self._ready_for_buy:
                self._up_count += 1
                if self._up_count == 2:
                    buy_signal = True
        else:
            self._ready_for_buy = False
            self._up_count = 0

        # Sell logic
        if is_neg:
            if is_up:
                self._ready_for_sell = True
                self._down_count = 0
            if is_down and self._ready_for_sell:
                self._down_count += 1
                if self._down_count == 2:
                    sell_signal = True
        else:
            self._ready_for_sell = False
            self._down_count = 0

        # Execute trades
        if buy_signal:
            if not self.position:
                self.buy()
        elif sell_signal:
            if self.position:
                self.position.close()


