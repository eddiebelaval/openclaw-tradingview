class TvStrategy(Strategy):
    iOffset = 25
    iRSLineMovingAverageType = "SMA"
    iRSLineMovingAverageLength = 50
    iSlopeLookbackBars = 5
    iFlatBandPct = 0.15

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Fetch SPX (index) data - using close price as proxy
        # In a real backtest, you'd load SPX separately
        self.spx_close = pd.Series([100] * len(close), index=close.index)
        
        # Calculate RS Line (Relative Strength Line)
        def calc_rs_ratio():
            ratio = (close / self.spx_close) * 100.0
            return ratio * self.iOffset
        
        self.rs_line = self.I(calc_rs_ratio)
        
        # Calculate RS Moving Average
        def calc_rs_ma():
            rs_series = (close / self.spx_close) * 100.0 * self.iOffset
            if self.iRSLineMovingAverageType == "SMA":
                return pta.sma(pd.Series(rs_series), length=self.iRSLineMovingAverageLength)
            else:
                return pta.ema(pd.Series(rs_series), length=self.iRSLineMovingAverageLength)
        
        self.rs_ma = self.I(calc_rs_ma)
        
        # Calculate MA slope state
        def calc_ma_state():
            rs_series = (close / self.spx_close) * 100.0 * self.iOffset
            if self.iRSLineMovingAverageType == "SMA":
                ma = pta.sma(pd.Series(rs_series), length=self.iRSLineMovingAverageLength)
            else:
                ma = pta.ema(pd.Series(rs_series), length=self.iRSLineMovingAverageLength)
            
            ma_state = pd.Series(0, index=ma.index)
            
            for i in range(self.iSlopeLookbackBars, len(ma)):
                ma_ref = ma.iloc[i - self.iSlopeLookbackBars]
                ma_delta = ma.iloc[i] - ma_ref
                
                if ma_ref != 0.0:
                    ma_pct_move = (ma_delta / ma_ref) * 100.0
                    if ma_pct_move > self.iFlatBandPct:
                        ma_state.iloc[i] = 1  # Green (Up)
                    elif ma_pct_move < -self.iFlatBandPct:
                        ma_state.iloc[i] = -1  # Red (Down)
                    else:
                        ma_state.iloc[i] = 0  # White (Flat)
            
            return ma_state
        
        self.ma_state = self.I(calc_ma_state)

    def next(self):
        # Trading logic based on MA state transitions
        current_state = self.ma_state[-1]
        prev_state = self.ma_state[-2] if len(self.ma_state) > 1 else 0
        
