        if current_state == 1 and prev_state != 1:
            if not self.position:
                self.buy()
        
        # Red state (downtrend) - sell signal
        elif current_state == -1 and prev_state != -1:
            if self.position:
                self.position.close()
        
        # White state (flat) - exit position
        elif current_state == 0 and prev_state != 0:
            if self.position:
                self.position.close()


