import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ermaLen = 13
    orcaLen = 34
    confirmBars = 3
    cooldown = 15
    atrLen = 14
    atrSmth = 20
    atrMult = 1.1
    adxLen = 14
    adxTh = 22
    slopeLen = 5
    htfOn = True
    htfSlpLen = 3
    strongTh = 0.08

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ERMA calculation
        def calc_erma():
            result = []
            for idx in range(len(close)):
                sw = 0.0
                sp = 0.0
                start = max(0, idx - self.ermaLen + 1)
                for i in range(start, idx + 1):
                    r = high.iloc[i] - low.iloc[i]
                    b = abs(close.iloc[i] - self.data.Open[i])
                    e = b / r if r > 0.0 else 0.01
                    w = e ** 1.5
                    sw += w
                    sp += w * close.iloc[i]
                result.append(sp / sw if sw > 0.0 else close.iloc[idx])
            return pd.Series(result, index=close.index)
        
        # ORCA calculation
        def calc_orca():
            ema_val = pta.ema(close, length=self.orcaLen)
            d = close - ema_val
            s = pta.ema(d, length=max(round(self.orcaLen / 3), 2))
            return ema_val + s * 0.618
        
        eRaw = self.I(calc_erma)
        oRaw = self.I(calc_orca)
        base = self.I(pta.sma, close, length=self.orcaLen)
        
        self.erma = self.I(lambda: (eRaw / base - 1.0) * 100.0 if base is not None else pd.Series(0, index=close.index))
        self.orca = self.I(lambda: (oRaw / base - 1.0) * 100.0 if base is not None else pd.Series(0, index=close.index))
        self.diff = self.I(lambda: self.erma - self.orca)
        
        # ATR Volatility Filter
        atrNow = self.I(pta.atr, high, low, close, length=self.atrLen)
        atrAvg = self.I(pta.sma, atrNow, length=self.atrSmth)
        self.atrOK = self.I(lambda: (atrNow > atrAvg * self.atrMult) & (atrNow.shift(1) > atrAvg.shift(1) * (self.atrMult * 0.95)))
        
        # ADX Trend Detection
        def calc_adx():
            atrD = pta.atr(high, low, close, length=self.adxLen)
            upm = high.diff()
            dnm = -low.diff()
            pDM = ((upm > dnm) & (upm > 0)).astype(float) * upm
            mDM = ((dnm > upm) & (dnm > 0)).astype(float) * dnm
            pDI = 100.0 * pta.rma(pDM, length=self.adxLen) / atrD.clip(lower=1e-10)
            mDI = 100.0 * pta.rma(mDM, length=self.adxLen) / atrD.clip(lower=1e-10)
            dSum = pDI + mDI
            adx_val = pta.rma(100.0 * (pDI - mDI).abs() / dSum.clip(lower=1e-10), length=self.adxLen)
            return adx_val, pDI, mDI
        
        def get_adx_val():
            result = calc_adx()
            if result is not None:
                return result[0]
            return pd.Series(50, index=close.index)
        
        def get_pdi():
            result = calc_adx()
            if result is not None:
                return result[1]
            return pd.Series(50, index=close.index)
        
        def get_mdi():
            result = calc_adx()
            if result is not None:
                return result[2]
            return pd.Series(50, index=close.index)
        
        self.adx = self.I(get_adx_val)
        self.pDI = self.I(get_pdi)
        self.mDI = self.I(get_mdi)
        
        self.isTrend = self.I(lambda: self.adx >= self.adxTh)
        self.isBullTr = self.I(lambda: self.isTrend & (self.pDI > self.mDI))
        self.isBearTr = self.I(lambda: self.isTrend & (self.mDI > self.pDI))
        
        # ORCA Slope
        self.oSlope = self.I(lambda: (oRaw - oRaw.shift(self.slopeLen)) / oRaw.shift(self.slopeLen).clip(lower=1e-10) * 100.0)
        self.oSlopeUp = self.I(lambda: self.oSlope > 0.0)
        
        # RSI
        rsi = self.I(pta.rsi, close, length=14)
        self.rsiBC = self.I(lambda: (self.isTrend * 68.0 + (~self.isTrend) * 55.0))
        self.rsiBF = self.I(lambda: (self.isTrend * 32.0 + (~self.isTrend) * 45.0))
        
        def lowest_rsi():
            return rsi.rolling(window=5).min()
        
        def highest_rsi():
            return rsi.rolling(window=5).max()
        
        self.rsiWasLo = self.I(lowest_rsi) < 50.0
        self.rsiWasHi = self.I(highest_rsi) > 50.0
        self.rsiBuy = self.I(lambda: rsi < self.rsiBC)
        self.rsiSell = self.I(lambda: rsi > self.rsiBF)
        
        # Candle analysis
        cRng = high - low
        cBdy = (close - self.data.Open).abs()
        uWick = high - close.clip(self.data.Open)
        lWick = close.clip(self.data.Open) - low
        
        isBull = close > self.data.Open
        isBear = close < self.data.Open
        
        hammer = (lWick >= cBdy * 2.0) & (uWick <= cBdy * 0.3) & (cBdy > cRng * 0.1)
        star = (uWick >= cBdy * 2.0) & (lWick <= cBdy * 0.3) & (cBdy > cRng * 0.1)
        bullEng = (isBull) & (close.shift(1) < self.data.Open.shift(1)) & (close > self.data.Open.shift(1)) & (self.data.Open < close.shift(1))
        bearEng = (isBear) & (close.shift(1) > self.data.Open.shift(1)) & (close < self.data.Open.shift(1)) & (self.data.Open > close.shift(1))
        
        self.bBon = self.I(lambda: (hammer.astype(int) + bullEng.astype(int)))
        self.sBon = self.I(lambda: (star.astype(int) + bearEng.astype(int)))
        
        # Volume
        volAvg = self.I(pta.sma, volume, length=20)
        self.volOK = self.I(lambda: volume > volAvg * 1.1)
        
        # Base conditions
        self.bBase = self.I(lambda: (self.diff > 0.0) & self.rsiWasLo & self.rsiBuy & self.volOK & (close > oRaw))
        self.sBase = self.I(lambda: (self.diff < 0.0) & self.rsiWasHi & self.rsiSell & self.volOK & (close < oRaw))
        
        # Structural filters
        self.bBase = self.I(lambda: self.bBase & ~(self.isBearTr & ~self.oSlopeUp))
        self.sBase = self.I(lambda: self.sBase & ~(self.isBullTr & self.oSlopeUp))
        
        # Diff crossover
        self.cUp = self.I(lambda: crossover(self.diff, 0.0))
        self.cDown = self.I(lambda: crossover(0.0, self.diff))
        
        self.last_buy_idx = -50
        self.last_sell_idx = -50
        self.b_cnt = 0
        self.s_cnt = 0

    def next(self):
        # Update confirmation counters
        if len(self.data) < 2:
            return
            
        if self.cUp[-1]:
            self.b_cnt = 1
            self.s_cnt = 0
        elif self.cDown[-1]:
            self.s_cnt = 1
            self.b_cnt = 0
        elif self.diff[-1] > 0.0 and self.b_cnt > 0:
            self.b_cnt += 1
        elif self.diff[-1] < 0.0 and self.s_cnt > 0:
            self.s_cnt += 1
        else:
            self.b_cnt = 0
            self.s_cnt = 0
        
        bEff = self.b_cnt + self.bBon[-1]
        sEff = self.s_cnt + self.sBon[-1]
        
        bullSig = (bEff >= self.confirmBars and 
                   self.bBase[-1] and 
                   self.atrOK[-1] and 
                   (len(self.data) - self.last_buy_idx) > self.cooldown)
        
        bearSig = (sEff >= self.confirmBars and 
                   self.sBase[-1] and 
                   self.atrOK[-1] and 
                   (len(self.data) - self.last_sell_idx) > self.cooldown)
        
        if bullSig:
            if not self.position:
                self.buy()
            self.last_buy_idx = len(self.data)
        
        if bearSig:
            if self.position:
                self.sell()
            self.last_sell_idx = len(self.data)


