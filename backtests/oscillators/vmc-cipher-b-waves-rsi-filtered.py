import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # WaveTrend Settings
    wtChannelLen = 10
    wtAverageLen = 21
    wtMALen = 3
    obLevel = 60
    obLevel2 = 53
    obLevel3 = 100
    osLevel = -60
    osLevel2 = -53
    osLevel3 = -75
    wtDivOBLevel = 45
    wtDivOSLevel = -65
    wtDivOBLevel_add = 15
    wtDivOSLevel_add = -40
    
    # RSI Filter Settings
    useRsiFilter = True
    rsiSellFilter = 60
    rsiBuyFilter = 40
    
    # RSI Settings
    rsiLen = 14
    rsiOversold = 30
    rsiOverbought = 60
    
    # Stoch Settings
    stochLen = 14
    stochRsiLen = 14
    stochKSmooth = 3
    stochDSmooth = 3
    stochUseLog = True
    
    # MFI Settings
    rsiMFIperiod = 60
    rsiMFIMultiplier = 150
    rsiMFIPosY = 2.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hlc3 = (high + low + close) / 3
        
        # RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLen) or pd.Series(50, index=close.index))
        
        # WaveTrend calculation
        self.wt1 = self.I(self._calc_wt1, hlc3)
        self.wt2 = self.I(self._calc_wt2, hlc3)
        self.wtVwap = self.I(lambda: self.wt1 - self.wt2)
        
        # Stochastic RSI
        self.stochK = self.I(self._calc_stoch_k, close)
        self.stochD = self.I(self._calc_stoch_d, close)
        
        # RSI MFI
        self.rsiMFI = self.I(self._calc_rsi_mfi, close, high, low)
        
        # Fractal tracking for divergences
        self.fractal_tops = self.I(self._find_fractal_tops, self.wt2)
        self.fractal_bots = self.I(self._find_fractal_bots, self.wt2)

    def _calc_wt1(self, hlc3):
        esa = pta.ema(hlc3, length=self.wtChannelLen)
        if esa is None:
            return pd.Series(0, index=hlc3.index)
        de = pta.ema((hlc3 - esa).abs(), length=self.wtChannelLen)
        if de is None:
            return pd.Series(0, index=hlc3.index)
        de = de.replace(0, 0.001)
        ci = (hlc3 - esa) / (0.015 * de)
        wt1 = pta.ema(ci, length=self.wtAverageLen)
        return wt1 if wt1 is not None else pd.Series(0, index=hlc3.index)

    def _calc_wt2(self, hlc3):
        esa = pta.ema(hlc3, length=self.wtChannelLen)
        if esa is None:
            return pd.Series(0, index=hlc3.index)
        de = pta.ema((hlc3 - esa).abs(), length=self.wtChannelLen)
        if de is None:
            return pd.Series(0, index=hlc3.index)
        de = de.replace(0, 0.001)
        ci = (hlc3 - esa) / (0.015 * de)
        wt1 = pta.ema(ci, length=self.wtAverageLen)
        if wt1 is None:
            return pd.Series(0, index=hlc3.index)
        wt2 = pta.sma(wt1, length=self.wtMALen)
        return wt2 if wt2 is not None else pd.Series(0, index=hlc3.index)

    def _calc_stoch_k(self, close):
        rsi = pta.rsi(close, length=self.stochRsiLen)
        if rsi is None:
            return pd.Series(50, index=close.index)
        stoch = pta.stoch(rsi, rsi, rsi, k=self.stochLen)
        if stoch is None or len(stoch.columns) == 0:
            return pd.Series(50, index=close.index)
        k_raw = stoch.iloc[:, 0] if stoch.shape[1] > 0 else pd.Series(50, index=close.index)
        k = pta.sma(k_raw, length=self.stochKSmooth)
        return k if k is not None else pd.Series(50, index=close.index)

    def _calc_stoch_d(self, close):
        rsi = pta.rsi(close, length=self.stochRsiLen)
        if rsi is None:
            return pd.Series(50, index=close.index)
        stoch = pta.stoch(rsi, rsi, rsi, k=self.stochLen)
        if stoch is None or len(stoch.columns) == 0:
            return pd.Series(50, index=close.index)
        k_raw = stoch.iloc[:, 0] if stoch.shape[1] > 0 else pd.Series(50, index=close.index)
        k = pta.sma(k_raw, length=self.stochKSmooth)
        if k is None:
            return pd.Series(50, index=close.index)
        d = pta.sma(k, length=self.stochDSmooth)
        return d if d is not None else pd.Series(50, index=close.index)

    def _calc_rsi_mfi(self, close, high, low):
        df = pd.DataFrame({
            'close': close,
            'high': high,
            'low': low,
            'open': self.data.Open
        })
        mfi_raw = ((df['close'] - df['open']) / (df['high'] - df['low'])) * self.rsiMFIMultiplier
        mfi = pta.sma(mfi_raw, length=self.rsiMFIperiod)
        if mfi is None:
            return pd.Series(0, index=close.index)
        return mfi - self.rsiMFIPosY

    def _find_fractal_tops(self, wt2):
        result = pd.Series(0, index=wt2.index)
        for i in range(4, len(wt2)):
            if wt2.iloc[i-4] < wt2.iloc[i-2] and wt2.iloc[i-3] < wt2.iloc[i-2] and wt2.iloc[i-2] > wt2.iloc[i-1] and wt2.iloc[i-2] > wt2.iloc[i]:
                result.iloc[i-2] = 1
        return result

    def _find_fractal_bots(self, wt2):
        result = pd.Series(0, index=wt2.index)
        for i in range(4, len(wt2)):
            if wt2.iloc[i-4] > wt2.iloc[i-2] and wt2.iloc[i-3] > wt2.iloc[i-2] and wt2.iloc[i-2] < wt2.iloc[i-1] and wt2.iloc[i-2] < wt2.iloc[i]:
                result.iloc[i-2] = -1
        return result

    def next(self):
        if len(self.data) < 5:
            return
        
        # Current values
        wt1_curr = self.wt1[-1] if len(self.wt1) > 0 else 0
        wt2_curr = self.wt2[-1] if len(self.wt2) > 0 else 0
        rsi_curr = self.rsi[-1] if len(self.rsi) > 0 else 50
        
        # Check for WaveTrend cross signals
        wt_cross = False
        wt_cross_up = False
        wt_cross_down = False
        
        if len(self.wt1) > 1 and len(self.wt2) > 1:
            if crossover(self.wt2, self.wt1):
                wt_cross = True
                wt_cross_up = True
            elif crossover(self.wt1, self.wt2):
                wt_cross = True
                wt_cross_down = True
        
        wt_oversold = wt2_curr <= self.osLevel
        wt_overbought = wt2_curr >= self.obLevel
        
        # Buy Signal: WaveTrend cross up in oversold
        if wt_cross and wt_cross_up and wt_oversold:
            if not self.position:
                self.buy()
        
        # Sell Signal: WaveTrend cross down in overbought
        if wt_cross and wt_cross_down and wt_overbought:
            if self.position:
                self.position.close()
        
        # Divergence signals with RSI filter
        # For simplicity, use RSI extremes as proxy for divergences
        if len(self.rsi) > 5:
            rsi_prev = self.rsi[-5] if len(self.rsi) > 5 else 50
            rsi_min_5 = min(self.rsi[-5:]) if len(self.rsi) >= 5 else 50
            rsi_max_5 = max(self.rsi[-5:]) if len(self.rsi) >= 5 else 50
            
            # Bullish divergence signal (RSI oversold with rising price)
            if rsi_curr < self.rsiBuyFilter and wt2_curr < self.wtDivOSLevel:
                if not self.position:
                    self.buy()
            
            # Bearish divergence signal (RSI overbought with falling price)
            if rsi_curr > self.rsiSellFilter and wt2_curr > self.wtDivOBLevel:
                if self.position:
                    self.position.close()
        
        # Risk management: exit if WT moves significantly against us
        if self.position:
            if wt2_curr >= self.obLevel3:
                self.position.close()
        
        # Exit based on Stochastic RSI if configured
        if len(self.stochK) > 1 and len(self.stochD) > 1:
            if self.position and crossover(self.stochK, 80):
                self.position.close()
            elif not self.position and crossover(20, self.stochK):
                self.buy()


