import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI parameters
    rsi_length = 14
    rsi_sma_length = 20
    rsi_lookback = 3
    rsi_lookahead = 3
    rsi_deadzone = 0.0
    rsi_threshold = 0.0
    rsi_mode = "RSI vs 50"
    rsi_observe = "Confirm"
    
    # EMA parameters
    ema_fast_len = 8
    ema_slow_len = 21
    ema_lookback = 3
    ema_lookahead = 3
    ema_deadzone = 0.0
    ema_threshold = 0.0
    ema_observe = "Confirm"
    
    # MACD parameters
    macd_fast_len = 12
    macd_slow_len = 26
    macd_signal_len = 9
    macd_lookback = 3
    macd_lookahead = 3
    macd_deadzone = 0.0
    macd_threshold = 0.0
    macd_observe = "Confirm"
    
    # Stochastic parameters
    stoch_mode = "Stochastic RSI"
    stoch_rsi_len = 14
    stoch_k_len = 8
    stoch_k_smooth = 3
    stoch_d_smooth = 3
    stoch_lookback = 3
    stoch_deadzone = 0.0
    stoch_threshold = 0.0
    stoch_range_mode = "Ignore"
    stoch_min_long = 0.0
    stoch_max_long = 90.0
    stoch_min_short = 10.0
    stoch_max_short = 100.0
    stoch_obs_mode = "Confirm"
    
    # Aggregation mode
    aggregation_mode = "Strict Consensus"
    eval_point = "Close"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI indicators
        self.rsi_val = self.I(pta.rsi, close, length=self.rsi_length)
        self.rsi_ma = self.I(pta.sma, self.rsi_val, length=self.rsi_sma_length)
        
        # EMA indicators
        self.ema_fast = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema_slow = self.I(pta.ema, close, length=self.ema_slow_len)
        
        # MACD indicator
        def get_macd_hist():
            macd_result = pta.macd(close, fast=self.macd_fast_len, slow=self.macd_slow_len, signal=self.macd_signal_len)
            if macd_result is not None and 'MACDH_' + str(self.macd_fast_len) + '_' + str(self.macd_slow_len) + '_' + str(self.macd_signal_len) in macd_result.columns:
                hist_col = [col for col in macd_result.columns if 'MACDH' in col][0]
                return macd_result[hist_col]
            return pd.Series(0, index=close.index)
        
        self.macd_hist = self.I(get_macd_hist)
        
        # Stochastic indicators
        def get_stoch_k():
            if self.stoch_mode == "Stochastic RSI":
                rsi_series = pta.rsi(close, length=self.stoch_rsi_len)
                lowest_rsi = rsi_series.rolling(self.stoch_k_len).min()
                highest_rsi = rsi_series.rolling(self.stoch_k_len).max()
                rsi_range = highest_rsi - lowest_rsi
                raw_k = np.where(rsi_range != 0, 100 * (rsi_series - lowest_rsi) / rsi_range, 50)
                return pd.Series(raw_k, index=close.index).rolling(self.stoch_k_smooth).mean()
            else:
                hh = high.rolling(self.stoch_k_len).max()
                ll = low.rolling(self.stoch_k_len).min()
                price_range = hh - ll
                raw_k = np.where(price_range != 0, 100.0 * (close - ll) / price_range, 0.0)
                raw_k = np.clip(raw_k, 0, 100)
                return pd.Series(raw_k, index=close.index).rolling(self.stoch_k_smooth).mean()
        
        def get_stoch_d():
            k_series = get_stoch_k()
            return k_series.rolling(self.stoch_d_smooth).mean()
        
        self.stoch_k = self.I(get_stoch_k)
        self.stoch_d = self.I(get_stoch_d)
        
        # Track previous states
        self.prev_agg_state = 0
    
    def next(self):
        # Calculate RSI state
        rsi_val = self.rsi_val[-1]
        rsi_ma = self.rsi_ma[-1]
        
        if pd.isna(rsi_val) or pd.isna(rsi_ma):
            rsi_state = 0
        else:
            rsi_state_raw = (rsi_val - rsi_ma) if self.rsi_mode == "RSI vs SMA" else (rsi_val - 50)
            rsi_state_base = 0.0 if abs(rsi_state_raw) < self.rsi_deadzone else rsi_state_raw
            
            if self.rsi_observe == "Ignore":
                rsi_state = 0
            elif self.rsi_observe == "Confirm":
                rsi_state = np.sign(rsi_state_base)
            else:
                rsi_state = 0
        
        # Calculate EMA state
        ema_fast = self.ema_fast[-1]
        ema_slow = self.ema_slow[-1]
        
        if pd.isna(ema_fast) or pd.isna(ema_slow):
            ema_state = 0
        else:
            ema_diff = ema_fast - ema_slow
            ema_state_base = 0.0 if abs(ema_diff) < self.ema_deadzone else ema_diff
            
            if self.ema_observe == "Ignore":
                ema_state = 0
            elif self.ema_observe == "Confirm":
                ema_state = np.sign(ema_state_base)
            else:
                ema_state = 0
        
        # Calculate MACD state
        macd_val = self.macd_hist[-1]
        
        if pd.isna(macd_val):
            macd_state = 0
        else:
            macd_state_base = 0.0 if abs(macd_val) < self.macd_deadzone else macd_val
            
            if self.macd_observe == "Ignore":
                macd_state = 0
            elif self.macd_observe == "Confirm":
                macd_state = np.sign(macd_state_base)
            else:
                macd_state = 0
        
        # Calculate Stochastic state
        stoch_k = self.stoch_k[-1]
        stoch_d = self.stoch_d[-1]
        
        if pd.isna(stoch_k) or pd.isna(stoch_d):
            stoch_state = 0
        else:
            delta = abs(stoch_k - stoch_d)
            
            if self.stoch_obs_mode == "Ignore":
                stoch_state = 0
            elif delta < self.stoch_deadzone:
                stoch_state = 0
            else:
                in_long_range = stoch_k >= self.stoch_min_long and stoch_k <= self.stoch_max_long and stoch_k > stoch_d
                in_short_range = stoch_k >= self.stoch_min_short and stoch_k <= self.stoch_max_short and stoch_k < stoch_d
                
                if self.stoch_range_mode == "Invalidate" and not (in_long_range or in_short_range):
                    stoch_state = 0
                else:
                    if stoch_k > stoch_d:
                        stoch_state = 1
                    elif stoch_k < stoch_d:
                        stoch_state = -1
                    else:
                        stoch_state = 0
        
        # Aggregate votes
        bull_votes = 0
        bear_votes = 0
        neutral_votes = 0
        active_votes = 0
        
        if self.rsi_observe != "Ignore":
            active_votes += 1
            if rsi_state == 1:
                bull_votes += 1
            elif rsi_state == -1:
                bear_votes += 1
            else:
                neutral_votes += 1
        
        if self.ema_observe != "Ignore":
            active_votes += 1
            if ema_state == 1:
                bull_votes += 1
            elif ema_state == -1:
                bear_votes += 1
            else:
                neutral_votes += 1
        
        if self.macd_observe != "Ignore":
            active_votes += 1
            if macd_state == 1:
                bull_votes += 1
            elif macd_state == -1:
                bear_votes += 1
            else:
                neutral_votes += 1
        
        if self.stoch_obs_mode != "Ignore":
            active_votes += 1
            if stoch_state == 1:
                bull_votes += 1
            elif stoch_state == -1:
                bear_votes += 1
            else:
                neutral_votes += 1
        
        # Compute aggregate state
        if active_votes == 0:
            agg_state = 0
        elif self.aggregation_mode == "Strict Consensus":
            if active_votes > 0 and bull_votes == active_votes:
                agg_state = 1
            elif active_votes > 0 and bear_votes == active_votes:
                agg_state = -1
            else:
                agg_state = 0
        else:  # Directional Tolerance
            if bull_votes > 0 and bear_votes == 0:
                agg_state = 1
            elif bear_votes > 0 and bull_votes == 0:
                agg_state = -1
            else:
                agg_state = 0
        
        # Trading logic based on aggregate state changes
        if self.prev_agg_state <= 0 and agg_state == 1:
            self.buy()
        elif self.prev_agg_state >= 0 and agg_state == -1:
            self.sell()
        
        self.prev_agg_state = agg_state


