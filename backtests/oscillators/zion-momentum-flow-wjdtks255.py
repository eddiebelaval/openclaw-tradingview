import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 14
    smooth = 3
    level = 15

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI
        rsi_val = self.I(pta.rsi, close, length=self.len)
        
        # Calculate oscillator: EMA of (RSI - 50)
        rsi_centered = self.I(lambda x: x - 50, rsi_val)
        self.osc = self.I(pta.ema, rsi_centered, length=self.smooth)

    def next(self):
        # Buy when oscillator crosses above the upper level (bullish momentum breakthrough)
        if len(self.osc) > 1:
            if self.osc[-2] <= self.level and self.osc[-1] > self.level:
                if not self.position:
                    self.buy()
            
            # Sell when oscillator crosses below the lower level (bearish momentum breakthrough)
            elif self.osc[-2] >= -self.level and self.osc[-1] < -self.level:
                if self.position:
                    self.sell()