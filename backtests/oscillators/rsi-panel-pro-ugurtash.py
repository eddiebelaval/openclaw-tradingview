class TvStrategy(Strategy):
    rsi_length = 14
    rsi_overbought = 70
    rsi_oversold = 30
    signal_length = 9

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        self.signal = self.I(pta.ema, self.rsi, length=self.signal_length)

    def next(self):
        if len(self.data) < self.signal_length + self.rsi_length:
            return
        
        rsi_current = self.rsi[-1]
        signal_current = self.signal[-1]
        
        if rsi_current is None or signal_current is None:
            return
        
        rsi_prev = self.rsi[-2] if len(self.rsi) > 1 else rsi_current
        signal_prev = self.signal[-2] if len(self.signal) > 1 else signal_current
        
        if not self.position:
            if (rsi_prev <= self.rsi_oversold and rsi_current > self.rsi_oversold) or \
               (rsi_current < self.rsi_oversold and crossover(self.signal, self.rsi)):
                self.buy()
        else:
            if (rsi_prev >= self.rsi_overbought and rsi_current < self.rsi_overbought) or \
               (rsi_current > self.rsi_overbought and crossover(self.rsi, self.signal)):
                self.sell()


