import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_len = 16
    mad_len = 25

    def init(self):
        low = pd.Series(self.data.Low)
        
        # Calculate RSI on Low prices
        self.rsi = self.I(lambda: pta.rsi(low, length=self.rsi_len) or pd.Series(50, index=low.index))
        
        # Calculate Mean Absolute Deviation
        def calc_mad(rsi_series):
            if rsi_series is None or len(rsi_series) < self.mad_len:
                return pd.Series(0, index=rsi_series.index if rsi_series is not None else low.index)
            mean_rsi = pta.sma(rsi_series, length=self.mad_len)
            if mean_rsi is None:
                return pd.Series(0, index=rsi_series.index)
            abs_dev = np.abs(rsi_series - mean_rsi)
            mad = pta.sma(abs_dev, length=self.mad_len)
            if mad is None:
                return pd.Series(0, index=rsi_series.index)
            return mad
        
        self.mad = self.I(lambda: calc_mad(self.rsi))
        
        # Calculate upper and lower bands
        self.upper = self.I(lambda: self.rsi + self.mad)
        self.lower = self.I(lambda: self.rsi - self.mad)
        
        # State tracking
        self.position_state = 0  # 0 = neutral, 1 = long bias, -1 = short bias

    def next(self):
        if len(self.data) < self.mad_len + self.rsi_len:
            return
        
        rsi_val = self.rsi[-1]
        upper_val = self.upper[-1]
        lower_val = self.lower[-1]
        
        long_condition = lower_val > 50
        short_condition = upper_val < 50
        
        # Update position state
        if long_condition and not short_condition:
            self.position_state = 1
        elif short_condition:
            self.position_state = -1
        
        # Trading logic
        if self.position_state == 1 and not self.position:
            self.buy()
        elif self.position_state == -1 and self.position:
            self.sell()