import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Production Cost Model Parameters
    alpha = 0.51
    cal_price = 87000.0
    cal_diff = 141.0
    efficiency = 25.0
    elec_cost = 0.06
    overhead = 1.30
    block_reward = 3.125
    
    # Component Weights
    w_ppc = 0.40
    w_diff = 0.20
    w_puel = 0.25
    w_hash = 0.15
    
    # Lookback Windows
    diff_fast = 14
    diff_slow = 90
    puell_ma = 365
    hash_sma = 90
    norm_window = 730
    
    # Signal Thresholds
    strong_buy = -1.5
    buy = -0.5
    sell = 0.5
    strong_sell = 1.5
    
    # Visual Settings
    mei_smooth = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Component 1: PPC Ratio
        def calc_production_cost():
            cal_diff_raw = self.cal_diff * 1e12
            k = self.cal_price / (cal_diff_raw ** self.alpha)
            # Use difficulty approximation based on close price volatility proxy
            diff_approx = cal_diff_raw * (close / self.cal_price) ** (1 / self.alpha)
            prod_cost = k * (diff_approx ** self.alpha)
            return prod_cost
        
        prod_cost = self.I(calc_production_cost)
        ppc_ratio = close / prod_cost
        log_ppc = self.I(lambda: np.log(ppc_ratio))
        
        # Component 2: Difficulty Momentum
        def calc_diff_momentum():
            # Approximate difficulty from price action
            cal_diff_raw = self.cal_diff * 1e12
            diff_approx = cal_diff_raw * (close / self.cal_price) ** (1 / self.alpha)
            
            diff_roc_fast = (diff_approx - diff_approx.shift(self.diff_fast)) / diff_approx.shift(self.diff_fast)
            diff_roc_slow = (diff_approx - diff_approx.shift(self.diff_slow)) / diff_approx.shift(self.diff_slow)
            diff_momentum = diff_roc_fast - diff_roc_slow
            
            diff_mom_mean = pta.sma(diff_momentum, length=365)
            diff_mom_std = diff_momentum.rolling(365).std()
            diff_zscore = (diff_momentum - diff_mom_mean) / (diff_mom_std + 1e-10)
            return diff_zscore
        
        diff_zscore = self.I(calc_diff_momentum)
        
        # Component 3: Puell Multiple
        def calc_puell():
            daily_issuance_usd = close * self.block_reward * 144.0
            issuance_ma_365 = pta.sma(daily_issuance_usd, length=self.puell_ma)
            puell_multiple = daily_issuance_usd / (issuance_ma_365 + 1e-10)
            log_puell = np.log(puell_multiple + 1e-10)
            return log_puell
        
        log_puell = self.I(calc_puell)
        
        # Component 4: Hashrate Z-Score
        def calc_hash_zscore():
            # Approximate hashrate from price volatility
            hash_filled = close * 1e6  # Arbitrary scaling
            hash_sma_val = pta.sma(hash_filled, length=self.hash_sma)
            hash_deviation = (hash_filled - hash_sma_val) / (hash_sma_val + 1e-10)
            
            hash_dev_mean = pta.sma(hash_deviation, length=365)
            hash_dev_std = hash_deviation.rolling(365).std()
            hash_zscore = (hash_deviation - hash_dev_mean) / (hash_dev_std + 1e-10)
            return hash_zscore
        
        hash_zscore = self.I(calc_hash_zscore)
        
        # Normalization
        def normalize_component(component, window):
            comp_mean = pta.sma(component, length=window)
            comp_std = component.rolling(window).std()
            normalized = (component - comp_mean) / (comp_std + 1e-10)
            return normalized
        
        ppc_norm = self.I(lambda: normalize_component(log_ppc, self.norm_window))
        diff_norm = self.I(lambda: normalize_component(diff_zscore, self.norm_window))
        puel_norm = self.I(lambda: normalize_component(log_puell, self.norm_window))
        hash_norm = self.I(lambda: normalize_component(hash_zscore, self.norm_window))
        
        # Composite MEI
        def calc_mei_raw():
            mei_composite = (self.w_ppc * ppc_norm.fillna(0) + 
                           self.w_diff * diff_norm.fillna(0) + 
                           self.w_puel * puel_norm.fillna(0) + 
                           self.w_hash * hash_norm.fillna(0))
            return mei_composite
        
        mei_raw = self.I(calc_mei_raw)
        
        # Smooth MEI
        if self.mei_smooth > 1:
            self.mei = self.I(pta.ema, mei_raw, length=self.mei_smooth)
        else:
            self.mei = mei_raw

    def next(self):
        # Strong Buy Signal
        if crossover(self.strong_buy, self.mei):
            if not self.position:
                self.buy()
        
        # Buy Signal
        elif crossover(self.buy, self.mei):
            if not self.position:
                self.buy()
        
        # Sell Signal
        elif crossover(self.mei, self.sell):
            if self.position:
                self.position.close()
        
        # Strong Sell Signal
        elif crossover(self.mei, self.strong_sell):
            if self.position:
                self.position.close()


