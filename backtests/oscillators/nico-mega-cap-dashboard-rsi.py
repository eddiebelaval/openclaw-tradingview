import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)

    def next(self):
        if len(self.data) < self.rsi_length + 1:
            return
        
        current_rsi = self.rsi[-1]
        
        if current_rsi is None or np.isnan(current_rsi):
            return
        
        if crossover(self.rsi, 30):
            if not self.position:
                self.buy()
        elif crossover(70, self.rsi):
            if self.position:
                self.position.close()


if __name__ == "__main__":
    df = pd.read_csv("data.csv", index_col=0, parse_dates=True)
    
    bt = Backtest(df, TvStrategy, cash=10000, commission=0.002)
    stats = bt.run()
    print(stats)
    bt.plot()