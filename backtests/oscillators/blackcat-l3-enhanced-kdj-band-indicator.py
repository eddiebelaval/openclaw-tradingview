    def next(self):
        # Get current KDJ values
        k13 = self.k13[-1]
        d13 = self.d13[-1]
        k21 = self.k21[-1]
        d21 = self.d21[-1]
        k34 = self.k34[-1]
        d34 = self.d34[-1]
        k55 = self.k55[-1]
        d55 = self.d55[-1]

        # Check for overbought/oversold conditions
        overbought13 = k13 > 80 and d13 > 80
        overbought21 = k21 > 80 and d21 > 80
        overbought34 = k34 > 80 and d34 > 80
        overbought55 = k55 > 80 and d55 > 80

        oversold13 = k13 < 20 and d13 < 20
        oversold21 = k21 < 20 and d21 < 20
        oversold34 = k34 < 20 and d34 < 20
        oversold55 = k55 < 20 and d55 < 20

        # Check for crossover signals
        golden_cross_13 = crossover(self.k13, self.d13)
        death_cross_13 = crossover(self.d13, self.k13)
        golden_cross_21 = crossover(self.k21, self.d21)
        death_cross_21 = crossover(self.d21, self.k21)
        golden_cross_34 = crossover(self.k34, self.d34)
        death_cross_34 = crossover(self.d34, self.k34)

        # Calculate strong signals
        strong_buy_signal = (oversold13 and oversold21 and oversold34 and 
                            (golden_cross_13 or golden_cross_21 or golden_cross_34))
