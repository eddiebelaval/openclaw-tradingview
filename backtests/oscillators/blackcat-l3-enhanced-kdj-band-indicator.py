import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    period13 = 13
    period21 = 21
    period34 = 34
    period55 = 55
    smoothK = 3
    smoothD = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Helper function to calculate RSV (Raw Stochastic Value)
        def calc_rsv(period):
            lowest_low = low.rolling(window=period).min()
            highest_high = high.rolling(window=period).max()
            rsv = ((close - lowest_low) / (highest_high - lowest_low)) * 100
            return rsv.fillna(50)

        # Calculate 13-day period KDJ
        rsv13 = self.I(calc_rsv, self.period13)
        k13_raw = self.I(pta.sma, pd.Series(rsv13), length=self.smoothK)
        self.k13 = self.I(pta.sma, pd.Series(k13_raw), length=self.smoothK)
        self.d13 = self.I(pta.sma, pd.Series(self.k13), length=self.smoothD)
        self.j13 = self.I(lambda: 3 * pd.Series(self.k13) - 2 * pd.Series(self.d13))

        # Calculate 21-day period KDJ
        rsv21 = self.I(calc_rsv, self.period21)
        k21_raw = self.I(pta.sma, pd.Series(rsv21), length=self.smoothK)
        self.k21 = self.I(pta.sma, pd.Series(k21_raw), length=self.smoothK)
        self.d21 = self.I(pta.sma, pd.Series(self.k21), length=self.smoothD)
