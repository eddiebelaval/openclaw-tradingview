        roc_z = self.I(self._zscore, roc_raw, self.z_len)
        
        # RSI calculation and deviation from 50
        rsi_raw = self.I(lambda: pta.rsi(close, length=self.rsi_len) or pd.Series(50, index=close.index))
        rsi_dev = self.I(lambda: rsi_raw - 50.0)
        rsi_z = self.I(self._zscore, rsi_dev, self.z_len)
        
        # MACD calculation
        macd_result = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig) or pd.DataFrame(0, index=close.index, columns=['MACD_12_26_9', 'MACDh_12_26_9', 'MACDs_12_26_9']))
        macd_hist = self.I(lambda: macd_result.iloc[:, 1] if macd_result is not None else pd.Series(0, index=close.index))
        macd_z = self.I(self._zscore, macd_hist, self.z_len)
        
        # Normalize weights
        w_total = self.w_roc + self.w_rsi + self.w_macd
        self.w_roc_norm = self.w_roc / w_total if w_total > 0 else 0.333
        self.w_rsi_norm = self.w_rsi / w_total if w_total > 0 else 0.333
        self.w_macd_norm = self.w_macd / w_total if w_total > 0 else 0.334
        
        # AMC calculation
        self.amc = self.I(lambda: self._calc_amc(roc_z, rsi_z, macd_z))
        
