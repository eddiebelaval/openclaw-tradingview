import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smaLen = 50
    thresholdMode = "Absolute"
    inchAbove = 4.0
    inchBelow = 4.0
    atrLen = 14
    maxBars = 3
    minBarsBetween = 10
    autoUniversal = True
    normMode = "ATR"
    normLookback = 100
    breakMult = 0.60
    bandMult = 0.25
    roundToTick = True
    pbBandMode = "ATR"
    pbBandValue = 0.25
    useReclaimExtreme = True
    useADXFilter = False
    diLen = 14
    adxSmoothing = 14
    adxMin = 18.0
    useSlopeFilter = False
    slopeLen = 10
    slopeMinMult = 0.20
    useNormFloor = True
    minNormTicks = 20
    enforceAlternation = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.sma = self.I(pta.sma, close, length=self.smaLen)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        if self.useADXFilter:
            adx_result = self.I(lambda: pta.adx(high, low, close, length=self.diLen) or pd.DataFrame(index=close.index))
            if isinstance(adx_result, pd.DataFrame):
                self.adx_val = adx_result.iloc[:, 0] if len(adx_result.columns) > 0 else pd.Series(0, index=close.index)
            else:
                self.adx_val = pd.Series(0, index=close.index)
        else:
            self.adx_val = pd.Series(0, index=close.index)
        
        self.z_series = close - self.sma
        z_std_raw = self.I(lambda: self.z_series.rolling(self.normLookback).std())
        self.z_std_safe = z_std_raw.fillna(method='bfill').fillna(0).apply(lambda x: max(x, 0.0001))
        
        def get_norm_unit():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if self.normMode == "ATR":
                    norm_unit0 = self.atr.iloc[i] if i < len(self.atr) else 0
                else:
                    norm_unit0 = self.z_std_safe.iloc[i] if i < len(self.z_std_safe) else 0
                
                min_norm = self.minNormTicks * 0.01
                norm_unit = max(norm_unit0, min_norm) if self.useNormFloor else norm_unit0
                result.iloc[i] = norm_unit
            return result
        
        self.norm_unit = self.I(get_norm_unit)
        
        def get_base_thr_above():
            if self.thresholdMode == "Absolute":
                return pd.Series(self.inchAbove, index=close.index)
            elif self.thresholdMode == "Percent":
                return self.sma * self.inchAbove / 100
            else:
                return self.atr * self.inchAbove
        
        def get_base_thr_below():
            if self.thresholdMode == "Absolute":
                return pd.Series(self.inchBelow, index=close.index)
            elif self.thresholdMode == "Percent":
                return self.sma * self.inchBelow / 100
            else:
                return self.atr * self.inchBelow
        
        def get_base_pb_band():
            if self.pbBandMode == "Absolute":
                return pd.Series(self.pbBandValue, index=close.index)
            elif self.pbBandMode == "Percent":
                return self.sma * self.pbBandValue / 100
            else:
                return self.atr * self.pbBandValue
        
        self.base_thr_above = self.I(get_base_thr_above)
        self.base_thr_below = self.I(get_base_thr_below)
        self.base_pb_band = self.I(get_base_pb_band)
        
        def get_eff_thr_above():
            if self.autoUniversal:
                return self.breakMult * self.norm_unit
            else:
                return self.base_thr_above
        
        def get_eff_thr_below():
            if self.autoUniversal:
                return self.breakMult * self.norm_unit
            else:
                return self.base_thr_below
        
        def get_eff_pb_band():
            if self.autoUniversal:
                return self.bandMult * self.norm_unit
            else:
                return self.base_pb_band
        
        self.eff_thr_above = self.I(get_eff_thr_above)
        self.eff_thr_below = self.I(get_eff_thr_below)
        self.eff_pb_band = self.I(get_eff_pb_band)
        
        self.slope_abs = self.I(lambda: (self.sma - self.sma.shift(self.slopeLen)).abs())
        
        self.in_buy = False
        self.pulled_buy = False
        self.fired_b = False
        self.start_b = None
        self.hi_b = None
        self.last_buy_bar = None
        
        self.in_sell = False
        self.pulled_sell = False
        self.fired_s = False
        self.start_s = None
        self.lo_s = None
        self.last_sell_bar = None
        
        self.last_signal = 0

    def next(self):
        idx = len(self.data) - 1
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_ = self.data.Open[-1]
        
        sma = self.sma[-1]
        atr = self.atr[-1]
        eff_thr_above = self.eff_thr_above[-1]
        eff_thr_below = self.eff_thr_below[-1]
        eff_pb_band = self.eff_pb_band[-1]
        
        trend_ok = True
        if self.useADXFilter:
            adx_val = self.adx_val[-1]
            trend_ok = adx_val >= self.adxMin
        
        slope_ok = True
        if self.useSlopeFilter:
            slope_abs = self.slope_abs[-1]
            norm_unit = self.norm_unit[-1]
            slope_ok = slope_abs >= self.slopeMinMult * norm_unit
        
        regime_ok = trend_ok and slope_ok
        
        can_buy_by_alt = not self.enforceAlternation or (self.last_signal <= 0)
        can_sell_by_alt = not self.enforceAlternation or (self.last_signal >= 0)
        
        # BUY FLOW
        if close < sma:
            self.in_buy = False
            self.pulled_buy = False
            self.fired_b = False
        
        if not self.in_buy and regime_ok and close > sma + eff_thr_above:
            self.in_buy = True
            self.pulled_buy = False
            self.fired_b = False
            self.start_b = idx
            self.hi_b = high
        
        if self.in_buy and not self.pulled_buy:
            self.hi_b = max(self.hi_b, high)
        
        if self.in_buy and self.start_b is not None and (idx - self.start_b > self.maxBars):
            self.in_buy = False
            self.pulled_buy = False
            self.fired_b = False
        
        buy_pulled = self.in_buy and not self.pulled_buy and (low <= sma + eff_pb_band) and (close > sma)
        if buy_pulled:
            self.pulled_buy = True
        
        buy_resume_ok = (not self.useReclaimExtreme) or (close > self.hi_b)
        
        buy_signal_raw = (
            self.in_buy and self.pulled_buy and not self.fired_b and
            close > sma and close > open_ and
            buy_resume_ok and
            (self.start_b is None or (idx - self.start_b <= self.maxBars)) and
            (self.last_buy_bar is None or idx - self.last_buy_bar >= self.minBarsBetween)
        )
        
        buy_signal = buy_signal_raw and can_buy_by_alt
        
        if buy_signal:
            self.fired_b = True
            self.last_buy_bar = idx
            self.last_signal = 1
            self.buy()
        
        # SELL FLOW
        if close > sma:
            self.in_sell = False
            self.pulled_sell = False
            self.fired_s = False
        
        if not self.in_sell and regime_ok and close < sma - eff_thr_below:
            self.in_sell = True
            self.pulled_sell = False
            self.fired_s = False
            self.start_s = idx
            self.lo_s = low
        
        if self.in_sell and not self.pulled_sell:
            self.lo_s = min(self.lo_s, low)
        
        if self.in_sell and self.start_s is not None and (idx - self.start_s > self.maxBars):
            self.in_sell = False
            self.pulled_sell = False
            self.fired_s = False
        
        sell_pulled = self.in_sell and not self.pulled_sell and (high >= sma - eff_pb_band) and (close < sma)
        if sell_pulled:
            self.pulled_sell = True
        
        sell_resume_ok = (not self.useReclaimExtreme) or (close < self.lo_s)
        
        sell_signal_raw = (
            self.in_sell and self.pulled_sell and not self.fired_s and
            close < sma and close < open_ and
            sell_resume_ok and
            (self.start_s is None or (idx - self.start_s <= self.maxBars)) and
            (self.last_sell_bar is None or idx - self.last_sell_bar >= self.minBarsBetween)
        )
        
        sell_signal = sell_signal_raw and can_sell_by_alt
        
        if sell_signal:
            self.fired_s = True
            self.last_sell_bar = idx
            self.last_signal = -1
            self.sell()