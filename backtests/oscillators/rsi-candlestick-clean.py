import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.rsiClose = self.I(pta.rsi, close, length=self.rsiLen)
        self.rsiHigh = self.I(pta.rsi, high, length=self.rsiLen)
        self.rsiLow = self.I(pta.rsi, low, length=self.rsiLen)

    def next(self):
        if len(self.data) < 2:
            return
        
        rsiCloseVal = self.rsiClose[-1]
        rsiHighVal = self.rsiHigh[-1]
        rsiLowVal = self.rsiLow[-1]
        
        if rsiLowVal < 30 and rsiCloseVal > 30:
            if not self.position:
                self.buy()
        
        elif rsiHighVal > 70 and rsiCloseVal < 70:
            if self.position:
                self.sell()