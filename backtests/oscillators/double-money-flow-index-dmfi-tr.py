import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Length_DMFI = 14
    Length_MA_DMFI = 365
    Source_MA_DMFI = 'EMA'
    T_Factor = 0.7
    Signal_DMFI = '50'

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate MFI
        self.mfi = self.I(pta.mfi, high, low, close, volume, length=self.Length_DMFI)
        
        # Calculate DMFI = 2 * MFI - MFI(MFI)
        def calc_dmfi():
            mfi_vals = pta.mfi(high, low, close, volume, length=self.Length_DMFI)
            if mfi_vals is None or len(mfi_vals) < self.Length_DMFI:
                return pd.Series(50, index=close.index)
            mfi_of_mfi = pta.mfi(mfi_vals, mfi_vals, mfi_vals, volume, length=self.Length_DMFI)
            if mfi_of_mfi is None:
                return pd.Series(50, index=close.index)
            dmfi = 2 * mfi_vals - mfi_of_mfi
            return dmfi
        
        self.dmfi = self.I(calc_dmfi)
        
        # Calculate DMFI MA based on selected type
        def calc_dmfi_ma():
            dmfi_vals = self.dmfi
            if dmfi_vals is None or len(dmfi_vals) < self.Length_MA_DMFI:
                return pd.Series(50, index=close.index)
            
            if self.Source_MA_DMFI == 'EMA':
                ma_result = pta.ema(dmfi_vals, length=self.Length_MA_DMFI)
            elif self.Source_MA_DMFI == 'SMA':
                ma_result = pta.sma(dmfi_vals, length=self.Length_MA_DMFI)
            elif self.Source_MA_DMFI == 'RMA':
                ma_result = pta.rma(dmfi_vals, length=self.Length_MA_DMFI)
            elif self.Source_MA_DMFI == 'WMA':
                ma_result = pta.wma(dmfi_vals, length=self.Length_MA_DMFI)
            elif self.Source_MA_DMFI == 'VWMA':
                ma_result = pta.vwma(dmfi_vals, volume, length=self.Length_MA_DMFI)
            elif self.Source_MA_DMFI == 'HMA':
                ma_result = pta.hma(dmfi_vals, length=self.Length_MA_DMFI)
            elif self.Source_MA_DMFI == 'DEMA':
                ma_result = pta.dema(dmfi_vals, length=self.Length_MA_DMFI)
            elif self.Source_MA_DMFI == 'TEMA':
                ma_result = pta.tema(dmfi_vals, length=self.Length_MA_DMFI)
            else:
                ma_result = pta.ema(dmfi_vals, length=self.Length_MA_DMFI)
            
            if ma_result is None:
                return pd.Series(50, index=close.index)
            return ma_result
        
        self.dmfi_ma = self.I(calc_dmfi_ma)
        
        # Entry signal
        def get_entry_signal():
            if self.Signal_DMFI == 'DMFI MA':
                return self.dmfi_ma
            else:
                return pd.Series(50.0, index=close.index)
        
        self.entry_signal = self.I(get_entry_signal)

    def next(self):
        # Get current values
        dmfi = self.dmfi[-1]
        entry = self.entry_signal[-1]
        
        # Skip if values are NaN
        if np.isnan(dmfi) or np.isnan(entry):
            return
        
        # Bull signal: DMFI crosses above entry signal
        if len(self.dmfi) > 1 and len(self.entry_signal) > 1:
            prev_dmfi = self.dmfi[-2]
            prev_entry = self.entry_signal[-2]
            
            if not np.isnan(prev_dmfi) and not np.isnan(prev_entry):
                # Bullish crossover
                if prev_dmfi <= prev_entry and dmfi > entry:
                    if not self.position:
                        self.buy()
                
                # Bearish crossunder
                elif prev_dmfi >= prev_entry and dmfi < entry:
                    if self.position:
                        self.position.close()


