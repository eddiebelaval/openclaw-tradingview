class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        
        # Extract MACD line, signal line, and histogram
        self.macd_line = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACD_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        self.signal_line = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACDsh_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        self.hist_line = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACDh_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))

    def next(self):
        # Buy when histogram crosses above zero (from negative to positive)
        if len(self.hist_line) > 1:
            if self.hist_line[-2] < 0 and self.hist_line[-1] >= 0:
                if not self.position:
                    self.buy()
        
        # Sell when histogram crosses below zero (from positive to negative)
        if len(self.hist_line) > 1:
            if self.hist_line[-2] >= 0 and self.hist_line[-1] < 0:
                if self.position:
                    self.sell()