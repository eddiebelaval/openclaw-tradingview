class TvStrategy(Strategy):
    lensig = 14
    len_di = 14

    def init(self):
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        def calculate_dmi():
            up = high.diff()
            down = -low.diff()
            
            plus_dm = np.where(
                (up > down) & (up > 0),
                up,
                0
            )
            minus_dm = np.where(
                (down > up) & (down > 0),
                down,
                0
            )
            
            tr = pta.true_range(high, low, close)
            
            plus_dm_series = pd.Series(plus_dm, index=high.index)
            minus_dm_series = pd.Series(minus_dm, index=high.index)
            
            trur = plus_dm_series.ewm(span=self.len_di, adjust=False).mean()
            trur = pta.true_range(high, low, close).ewm(span=self.len_di, adjust=False).mean()
            
            plus_di_raw = (100 * plus_dm_series.ewm(span=self.len_di, adjust=False).mean() / trur).fillna(method='bfill').fillna(0)
            minus_di_raw = (100 * minus_dm_series.ewm(span=self.len_di, adjust=False).mean() / trur).fillna(method='bfill').fillna(0)
            
            plus_di = plus_di_raw
            minus_di = minus_di_raw
            
            di_sum = plus_di + minus_di
            di_sum = di_sum.replace(0, 1)
            
            adx_raw = 100 * (np.abs(plus_di - minus_di) / di_sum)
            adx = adx_raw.ewm(span=self.lensig, adjust=False).mean()
            
