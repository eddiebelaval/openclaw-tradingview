import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Parameters
    EMAlen = 310
    EMAslop = 0.02
    useTrendFilter = True
    
    # ROC Parameters
    rocLen = 55
    maLen = 7
    sigLen = 10
    ma_type = "TEMA"
    neutralThr = 0.0
    sigPct = 75.0
    
    # RSI Parameters
    rsiLenBase = 14
    bandWidth = 20.0
    borneBasDef = 30.0
    borneHautDef = 70.0
    cciSlowBarsF = 1
    cciEMAav = 1000
    
    # CCI Parameters
    cciPeriodBase = 20
    cciSmaLenBase = 14
    cciVisScaleBase = 200
    useCCIFilter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hlc3 = (high + low + close) / 3.0
        hlcc4 = (high + low + close + close) / 4.0
        
        # EMA trend
        self.emaVal = self.I(pta.ema, close, length=self.EMAlen)
        self.atrVal = self.I(pta.atr, high, low, close, length=14)
        
        # RSI base
        self.rsiBase = self.I(pta.rsi, close, length=self.rsiLenBase)
        
        # CCI base
        self.cciRawBase = self.I(pta.cci, high, low, close, length=self.cciPeriodBase)
        self.cciSmaBase = self.I(lambda: pta.sma(self.cciRawBase, length=self.cciSmaLenBase) if self.cciRawBase is not None else pd.Series(0, index=close.index))
        
        # CCI mapped
        def map_cci(cci_sma):
            if cci_sma is None:
                return pd.Series(50, index=close.index)
            mapped = 50.0 + 50.0 * (cci_sma / self.cciVisScaleBase)
            return mapped.clip(0, 100)
        
        self.cciMappedBase = self.I(map_cci, self.cciSmaBase)
        
        # ROC calculation
        self.roc = self.I(pta.roc, hlcc4, length=self.rocLen)
        
        def normalize_roc(roc_series):
            if roc_series is None:
                return pd.Series(0, index=close.index)
            rocLo = roc_series.rolling(window=self.rocLen).min()
            rocHi = roc_series.rolling(window=self.rocLen).max()
            den = rocHi - rocLo
            normalized = pd.Series(index=roc_series.index, dtype=float)
            normalized[:] = 0.0
            mask = den != 0
            normalized[mask] = (roc_series[mask] - rocLo[mask]) / den[mask]
            return normalized
        
        self.normalized_roc = self.I(normalize_roc, self.roc)
        
        # Base MA
        def calc_base_ma(source):
            if source is None:
                return pd.Series(0, index=close.index)
            if self.ma_type == "TEMA":
                ema1 = pta.ema(source, length=self.maLen)
                ema2 = pta.ema(ema1, length=self.maLen)
                ema3 = pta.ema(ema2, length=self.maLen)
                return 3 * (ema1 - ema2) + ema3
            elif self.ma_type == "DEMA":
                ema1 = pta.ema(source, length=self.maLen)
                ema2 = pta.ema(ema1, length=self.maLen)
                return 2 * ema1 - ema2
            elif self.ma_type == "SMA":
                return pta.sma(source, length=self.maLen)
            elif self.ma_type == "EMA":
                return pta.ema(source, length=self.maLen)
            elif self.ma_type == "WMA":
                return pta.wma(source, length=self.maLen)
            else:
                return pta.sma(source, length=self.maLen)
        
        self.base_ma = self.I(calc_base_ma, hlcc4)
        
        # Weighted diff and RWMA
        def calc_rwma(normalized_roc, src, base_ma):
            if normalized_roc is None or base_ma is None:
                return pd.Series(0, index=close.index)
            weighted_diff = normalized_roc * (src - base_ma)
            return base_ma + weighted_diff
        
        self.rwma = self.I(calc_rwma, self.normalized_roc, hlcc4, self.base_ma)
        
        # ZScore
        def calc_zscore(rwma_series):
            if rwma_series is None:
                return pd.Series(0, index=close.index)
            mean = rwma_series.rolling(window=self.rocLen).mean()
            stdev = rwma_series.rolling(window=self.rocLen).std()
            zscore = pd.Series(index=rwma_series.index, dtype=float)
            zscore[:] = 0.0
            mask = stdev != 0
            zscore[mask] = (rwma_series[mask] - mean[mask]) / stdev[mask]
            return zscore
        
        self.oscillator = self.I(calc_zscore, self.rwma)
        
        # Signal
        self.signal = self.I(pta.ema, self.oscillator, length=self.sigLen)
        
        # CCI Dynamic levels
        self.cciAvg = self.I(pta.ema, self.cciSmaBase, length=self.cciEMAav)
        
        def calc_cci_dc(cci_avg):
            if cci_avg is None:
                return pd.Series(0, index=close.index)
            return pta.sma(cci_avg, length=200)
        
        self.cciDC = self.I(calc_cci_dc, self.cciAvg)
        
        def calc_cci_hp(cci_avg, cci_dc):
            if cci_avg is None or cci_dc is None:
                return pd.Series(0, index=close.index)
            return cci_avg - cci_dc
        
        self.LevelDyn = self.I(calc_cci_hp, self.cciAvg, self.cciDC)
        
        # Trend calculation
        self.slope_series = self.I(lambda: self._calc_slope())
        
        # Track state variables
        self.inNeutralZone_prev = False
        self.maxBull = 0.0
        self.maxBearAbs = 0.0
        self.BullThrflag = False
        self.BearThrflag = False
        self.bullThr = 0.0
        self.bearThr = 0.0
        
    def _calc_slope(self):
        close = pd.Series(self.data.Close)
        emaVal = self.emaVal
        if emaVal is None:
            return pd.Series(0, index=close.index)
        
        slope = pd.Series(index=close.index, dtype=float)
        slope[:] = 0.0
        
        for i in range(50, len(emaVal)):
            if i >= 50:
                slope.iloc[i] = (emaVal.iloc[i] - emaVal.iloc[i - 50]) / 50
        
        return slope

    def next(self):
        if len(self.data) < max(self.EMAlen, self.rocLen, self.cciEMAav) + 10:
            return
        
        # Current values
        osc = self.oscillator[-1] if self.oscillator[-1] is not None else 0.0
        sig = self.signal[-1] if self.signal[-1] is not None else 0.0
        rsi = self.rsiBase[-1] if self.rsiBase[-1] is not None else 50.0
        cci_mapped = self.cciMappedBase[-1] if self.cciMappedBase[-1] is not None else 50.0
        cci_ma_f = cci_mapped
        level_dyn = self.LevelDyn[-1] if self.LevelDyn[-1] is not None else 0.0
        
