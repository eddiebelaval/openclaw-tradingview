        borne_haut_mid_eff = self.borneHautDef + level_dyn
        borne_bas_mid_eff = self.borneBasDef + level_dyn
        
        # Neutral zone
        in_neutral_zone = osc > -self.neutralThr and osc < self.neutralThr
        
        # Max oscillator tracking
        if not in_neutral_zone and in_neutral_zone != self.inNeutralZone_prev:
            self.maxBull = 0.0
            self.maxBearAbs = 0.0
            self.BullThrflag = False
            self.BearThrflag = False
        
        if not in_neutral_zone:
            if osc < 0:
                self.maxBull = min(self.maxBull, osc) if self.maxBull < 0 else osc
                self.bullThr = self.maxBull * (self.sigPct / 100.0)
                self.BullThrflag = sig >= self.bullThr
            if osc >= 0:
                self.maxBull = max(self.maxBull, osc) if self.maxBull > 0 else osc
                self.bearThr = self.maxBull * (self.sigPct / 100.0)
                self.BearThrflag = sig <= self.bearThr
        
        # Signal slopes
        sig_down = self.signal[-1] < self.signal[-2] if len(self.signal) > 1 else False
        sig_up = self.signal[-1] > self.signal[-2] if len(self.signal) > 1 else False
        
        # Base triggers
        bull_base_trig = osc <= 0 and not in_neutral_zone and self.BullThrflag and sig_up
        bear_base_trig = osc >= 0 and not in_neutral_zone and self.BearThrflag and sig_down
        
        # CCI slopes
        cci_sell_slope = True
        cci_buy_slope = True
        
        for i in range(min(self.cciSlowBarsF, len(self.cciMappedBase) - 1)):
            if len(self.cciMappedBase) > i + 1:
                cci_sell_slope = cci_sell_slope and (self.cciMappedBase[-(i+1)] < self.cciMappedBase[-i-2] if i+2 <= len(self.cciMappedBase) else True)
                cci_buy_slope = cci_buy_slope and (self.cciMappedBase[-(i+1)] > self.cciMappedBase[-i-2] if i+2 <= len(self.cciMappedBase) else True)
        
        # CCI states
        cci_sell_state = cci_sell_slope and (cci_ma_f > borne_haut_mid_eff)
        cci_buy_state = cci_buy_slope and (cci_ma_f < borne_bas_mid_eff)
        
        # Apply CCI filter
        bull_trig = bull_base_trig and cci_buy_state
        bear_trig = bear_base_trig and cci_sell_state
        
        # Trend filter
        if self.useTrendFilter and len(self.slope_series) > 50:
            slope = self.slope_series[-1] if self.slope_series[-1] is not None else 0.0
            atr = self.atrVal[-1] if self.atrVal[-1] is not None else 1.0
            norm_slope = slope / atr if atr != 0 else 0.0
            
            trend_up = slope >= self.EMAslop
            trend_down = slope <= -self.EMAslop
            
            bull_trig = bull_trig and trend_up
            bear_trig = bear_trig and trend_down
        
        # Entry/Exit logic
        if bull_trig and not self.position:
            self.buy()
        elif bear_trig and self.position:
            self.sell()
        
        self.inNeutralZone_prev = in_neutral_zone


