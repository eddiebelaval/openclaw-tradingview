import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    kj_len = 26
    tk_len = 9

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate Kijun (26-period midpoint of highest high and lowest low)
        def calc_kijun():
            kijun_vals = []
            for i in range(len(close)):
                if i < self.kj_len - 1:
                    kijun_vals.append(np.nan)
                else:
                    period_high = high.iloc[i - self.kj_len + 1:i + 1].max()
                    period_low = low.iloc[i - self.kj_len + 1:i + 1].min()
                    kijun_vals.append((period_high + period_low) / 2.0)
            return pd.Series(kijun_vals, index=close.index)

        # Calculate Tenkan (9-period midpoint of highest high and lowest low)
        def calc_tenkan():
            tenkan_vals = []
            for i in range(len(close)):
                if i < self.tk_len - 1:
                    tenkan_vals.append(np.nan)
                else:
                    period_high = high.iloc[i - self.tk_len + 1:i + 1].max()
                    period_low = low.iloc[i - self.tk_len + 1:i + 1].min()
                    tenkan_vals.append((period_high + period_low) / 2.0)
            return pd.Series(tenkan_vals, index=close.index)

        self.kijun = self.I(calc_kijun)
        self.tenkan = self.I(calc_tenkan)

        # Calculate distances
        def calc_kj_dist():
            return close - self.kijun

        def calc_tk_dist():
            return close - self.tenkan

        def calc_tk_kj_dist():
            return self.tenkan - self.kijun

        self.kj_dist = self.I(calc_kj_dist)
        self.tk_dist = self.I(calc_tk_dist)
        self.tk_kj_dist = self.I(calc_tk_kj_dist)

    def next(self):
        # Primary signal: Price crosses Kijun (kj_dist crosses 0)
        # Buy when price crosses above Kijun
        if len(self.kj_dist) > 1:
            if crossover(self.kj_dist, 0):
                if not self.position:
                    self.buy()
            # Sell when price crosses below Kijun
            elif crossover(0, self.kj_dist):
                if self.position:
                    self.position.close()

        # Secondary confirmation: Tenkan-Kijun distance
        # If Tenkan crosses above Kijun, reinforce buy bias
        # If Tenkan crosses below Kijun, reinforce sell bias
