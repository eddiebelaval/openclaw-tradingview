import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 20
    structureLen = 5
    atrLen = 14
    atrMult = 1.5
    rr = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.recentHigh = self.I(lambda: high.shift(1).rolling(self.lookback).max())
        self.recentLow = self.I(lambda: low.shift(1).rolling(self.lookback).min())
        
        self.structureHigh = self.I(lambda: high.rolling(self.structureLen).max())
        self.structureLow = self.I(lambda: low.rolling(self.structureLen).min())

    def next(self):
        if len(self.data) < self.lookback + 2:
            return
        
        high = self.data.High[-1]
        low = self.data.Low[-1]
        close = self.data.Close[-1]
        
        recentHigh = self.recentHigh[-1]
        recentLow = self.recentLow[-1]
        structureHigh = self.structureHigh[-2] if len(self.structureHigh) > 1 else self.structureHigh[-1]
        structureLow = self.structureLow[-2] if len(self.structureLow) > 1 else self.structureLow[-1]
        
        if pd.isna(recentHigh) or pd.isna(recentLow) or pd.isna(structureHigh) or pd.isna(structureLow):
            return
        
        sweepLow = low < recentLow and close > recentLow
        sweepHigh = high > recentHigh and close < recentHigh
        
        bullStructureBreak = close > structureHigh
        bearStructureBreak = close < structureLow
        
        longCondition = False
        shortCondition = False
        
        if len(self) > 1:
            prev_low = self.data.Low[-2]
            prev_high = self.data.High[-1]
            prev_close = self.data.Close[-2]
            
            prev_recentLow = self.recentLow[-2] if len(self.recentLow) > 1 else self.recentLow[-1]
            prev_recentHigh = self.recentHigh[-2] if len(self.recentHigh) > 1 else self.recentHigh[-1]
            
            if not pd.isna(prev_recentLow) and not pd.isna(prev_recentHigh):
                prev_sweepLow = prev_low < prev_recentLow and prev_close > prev_recentLow
                prev_sweepHigh = prev_high > prev_recentHigh and prev_close < prev_recentHigh
                
                longCondition = prev_sweepLow and bullStructureBreak
                shortCondition = prev_sweepHigh and bearStructureBreak
        
