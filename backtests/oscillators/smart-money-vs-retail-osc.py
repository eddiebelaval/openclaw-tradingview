import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sm_len = 7
    rt_len = 21
    vol_len = 14
    sig_thresh = 0.15

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Volume decomposition
        def calc_bull_vol():
            return np.where(close >= open_, volume, 0.0)

        def calc_bear_vol():
            return np.where(close < open_, volume, 0.0)

        bull_vol = self.I(calc_bull_vol)
        bear_vol = self.I(calc_bear_vol)

        # Smart Money calculations
        sm_bull = self.I(pta.ema, bull_vol, length=self.sm_len)
        sm_bear = self.I(pta.ema, bear_vol, length=self.sm_len)
        sm_tot = self.I(pta.ema, volume, length=self.sm_len)

        def calc_sm_raw():
            result = np.zeros(len(close))
            for i in range(len(close)):
                if sm_tot[i] > 0:
                    result[i] = (sm_bull[i] - sm_bear[i]) / sm_tot[i]
                else:
                    result[i] = 0.0
            return result

        sm_raw = self.I(calc_sm_raw)

        # Retail calculations
        rt_bull = self.I(pta.ema, bull_vol, length=self.rt_len)
        rt_bear = self.I(pta.ema, bear_vol, length=self.rt_len)
        rt_tot = self.I(pta.ema, volume, length=self.rt_len)

        def calc_rt_raw():
            result = np.zeros(len(close))
            for i in range(len(close)):
                if rt_tot[i] > 0:
                    result[i] = (rt_bull[i] - rt_bear[i]) / rt_tot[i]
                else:
                    result[i] = 0.0
            return result

        rt_raw = self.I(calc_rt_raw)

        # Normalization to 0-3 scale
        LKBK = 100

        def calc_sm_norm():
            result = np.zeros(len(close))
            for i in range(len(close)):
                if i < LKBK:
                    result[i] = 1.5
                else:
                    sm_hi = np.max(sm_raw[max(0, i-LKBK):i+1])
                    sm_lo = np.min(sm_raw[max(0, i-LKBK):i+1])
                    if sm_hi != sm_lo:
                        result[i] = (sm_raw[i] - sm_lo) / (sm_hi - sm_lo) * 3.0
                    else:
                        result[i] = 1.5
            return result

        def calc_rt_norm():
            result = np.zeros(len(close))
            for i in range(len(close)):
                if i < LKBK:
                    result[i] = 0.8 + 0.5 * 1.4
                else:
                    rt_hi = np.max(rt_raw[max(0, i-LKBK):i+1])
                    rt_lo = np.min(rt_raw[max(0, i-LKBK):i+1])
                    if rt_hi != rt_lo:
                        rt_pct = (rt_raw[i] - rt_lo) / (rt_hi - rt_lo)
                        result[i] = 0.8 + rt_pct * 1.4
                    else:
                        result[i] = 0.8 + 0.5 * 1.4
            return result

        sm_norm = self.I(calc_sm_norm)
        rt_norm = self.I(calc_rt_norm)

        self.sm_plot = self.I(pta.ema, sm_norm, length=3)
        self.rt_plot = self.I(pta.ema, rt_norm, length=5)

        # Regime detection
        vol_ma = self.I(pta.sma, volume, length=self.vol_len)

        def calc_vol_ratio():
            result = np.zeros(len(volume))
            for i in range(len(volume)):
                result[i] = volume[i] / max(vol_ma[i], 1)
            return result

        self.vol_ratio = self.I(calc_vol_ratio)

        adx_result = self.I(pta.adx, high, low, close, length=14)

        def extract_adx():
            if adx_result is None:
                return np.full(len(close), 20.0)
            return adx_result.iloc[:, 2].values if len(adx_result.columns) > 2 else np.full(len(close), 20.0)

        self.adx = self.I(extract_adx)

        # Control label logic
        def calc_diff():
            return self.sm_plot - self.rt_plot

        self.diff = self.I(calc_diff)

    def next(self):
        if len(self) < 30:
            return

        sm_plot_val = self.sm_plot[-1]
        rt_plot_val = self.rt_plot[-1]
        diff_val = self.diff[-1]
        vol_ratio_val = self.vol_ratio[-1]
        adx_val = self.adx[-1]

        # Buy signal: SM crosses above RT with sufficient gap
        if (len(self.sm_plot) > 1 and 
            self.sm_plot[-2] <= self.rt_plot[-2] and 
            sm_plot_val > rt_plot_val and 
            abs(diff_val) > self.sig_thresh):
            if not self.position:
                self.buy()

        # Sell signal: SM crosses below RT with sufficient gap
        if (len(self.sm_plot) > 1 and 
            self.sm_plot[-2] >= self.rt_plot[-2] and 
            sm_plot_val < rt_plot_val and 
            abs(diff_val) > self.sig_thresh):
            if self.position:
                self.position.close()


