import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 30
    k_limit = 2.0
    s_high = 1.0
    s_low = -1.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate mean and standard deviation
        mean = self.I(pta.sma, close, length=self.length)
        std = self.I(lambda x: x.rolling(window=self.length).std(), close)
        
        # Calculate z-score
        z_score = self.I(lambda: (close - mean) / std.fillna(1))
        
        # Calculate skewness (third moment)
        skew = self.I(lambda: pta.sma(z_score ** 3, length=self.length))
        
        # Calculate kurtosis (fourth moment - 3)
        kurt = self.I(lambda: pta.sma(z_score ** 4, length=self.length) - 3)
        
        self.mean = mean
        self.std = std
        self.z_score = z_score
        self.skew = skew
        self.kurt = kurt

    def next(self):
        # Buy signals based on positive skew crossing above threshold (upside bias)
        if len(self.data) > self.length:
            if crossover(self.skew, self.s_high):
                if not self.position:
                    self.buy()
            
            # Sell signals based on negative skew crossing below threshold (downside bias)
            elif crossover(self.s_low, self.skew):
                if self.position:
                    self.position.close()
            
            # Emergency exit on extreme kurtosis (high risk)
            if self.kurt[-1] > self.k_limit:
                if self.position:
                    self.position.close()


