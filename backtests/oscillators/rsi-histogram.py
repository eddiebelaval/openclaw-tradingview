import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    lower_th = 30
    upper_th = 70
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI using manual calculation (similar to Pine Script ta.rma)
        change = close.diff()
        gain = change.where(change > 0, 0)
        loss = -change.where(change < 0, 0)
        
        avg_gain = gain.ewm(span=self.rsi_length, adjust=False).mean()
        avg_loss = loss.ewm(span=self.rsi_length, adjust=False).mean()
        
        rs = avg_gain / avg_loss
        rsi = 100 - (100 / (1 + rs))
        
        self.rsi = self.I(lambda: rsi)
        
        # Store pivot detection for divergence
        self.pivot_lookback_left = 5
        self.pivot_lookback_right = 5
        self.range_upper = 60
        self.range_lower = 5
        
    def next(self):
        # Simple trading logic based on RSI thresholds
        # Buy when RSI crosses above lower threshold from below
        if len(self.data) > self.pivot_lookback_right + 1:
            if crossover(self.rsi, self.lower_th):
                if not self.position:
                    self.buy()
            # Sell when RSI crosses below upper threshold from above
            elif crossover(self.upper_th, self.rsi):
                if self.position:
                    self.position.close()
            
            # Also sell if RSI gets too high (overbought)
            if self.rsi[-1] > 80 and self.position:
                self.position.close()
            
            # Also buy if RSI gets too low (oversold)
            if self.rsi[-1] < 20 and not self.position:
                self.buy()


