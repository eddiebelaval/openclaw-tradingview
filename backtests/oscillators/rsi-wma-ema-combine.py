import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    wmaLength = 9
    emaLength = 21

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI
        self.rsiValue = self.I(pta.rsi, close, length=self.rsiLength)
        
        # Calculate WMA on RSI
        self.wmaOnRsi = self.I(lambda: pta.wma(self.rsiValue, length=self.wmaLength) if self.rsiValue is not None else pd.Series(50, index=close.index))
        
        # Calculate EMA on RSI
        self.emaOnRsi = self.I(lambda: pta.ema(self.rsiValue, length=self.emaLength) if self.rsiValue is not None else pd.Series(50, index=close.index))

    def next(self):
        # Bull signal: RSI crosses above WMA and RSI > EMA
        if len(self.data) > 1:
            rsi_current = self.rsiValue[-1]
            rsi_prev = self.rsiValue[-2]
            wma_current = self.wmaOnRsi[-1]
            wma_prev = self.wmaOnRsi[-2]
            ema_current = self.emaOnRsi[-1]
            
            if rsi_current is not None and rsi_prev is not None and wma_current is not None and wma_prev is not None and ema_current is not None:
                bullSignal = (rsi_prev <= wma_prev and rsi_current > wma_current) and (rsi_current > ema_current)
                bearSignal = (rsi_prev >= wma_prev and rsi_current < wma_current) and (rsi_current < ema_current)
                
                if bullSignal:
                    self.buy()
                elif bearSignal:
                    self.sell()


