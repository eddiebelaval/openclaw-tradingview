import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Moving Averages
        self.sma20 = self.I(pta.sma, close, length=20)
        self.sma60 = self.I(pta.sma, close, length=60)
        self.sma120 = self.I(pta.sma, close, length=120)
        
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema60 = self.I(pta.ema, close, length=60)
        self.ema120 = self.I(pta.ema, close, length=120)
        
        # ATR for offsets
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Trend structure flags
        self.bullStack = None
        self.bearStack = None
        
        # Slope calculations
        self.slope20 = None
        self.slope60 = None
        
    def next(self):
        # Ensure we have enough data
        if len(self.data) < 120:
            return
        
        # Calculate current values
        sma20_curr = self.sma20[-1]
        sma60_curr = self.sma60[-1]
        sma120_curr = self.sma120[-1]
        
        # Check for NaN values
        if pd.isna(sma20_curr) or pd.isna(sma60_curr) or pd.isna(sma120_curr):
            return
        
        # Trend structure
        bullStack = sma20_curr > sma60_curr and sma60_curr > sma120_curr
        bearStack = sma20_curr < sma60_curr and sma60_curr < sma120_curr
        
        # Golden Cross (SMA20 crosses above SMA60) - Buy signal
        if crossover(self.sma20, self.sma60):
            if not self.position:
                self.buy()
        
        # Death Cross (SMA20 crosses below SMA60) - Sell signal
        elif crossover(self.sma60, self.sma20):
            if self.position:
                self.position.close()
        
        # Additional exit: if bear stack forms and we're in a position, exit
        if bearStack and self.position:
            self.position.close()
        
        # Additional entry: if bull stack forms and we're not in position, enter
        if bullStack and not self.position:
            # Only enter if we just confirmed bull stack
            if len(self.data) > 120:
                sma20_prev = self.sma20[-2]
                sma60_prev = self.sma60[-2]
                sma120_prev = self.sma120[-2]
                
                bullStack_prev = sma20_prev > sma60_prev and sma60_prev > sma120_prev
                
                if not bullStack_prev and bullStack:
                    self.buy()


