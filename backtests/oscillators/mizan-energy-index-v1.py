import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_thrust = 7
    len_norm = 100
    len_psi = 14
    ex_level = 0.8
    psi_thresh = 0.3
    alpha = 0.5
    beta = 0.5
    use_vol = True

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Thrust Oscillator
        vol_sma_50 = self.I(pta.sma, volume, length=50)
        rv = self.I(lambda: volume / vol_sma_50)
        pc = self.I(lambda: close.diff())
        
        th_raw_calc = self.I(lambda: pta.ema(
            pd.Series(np.log(1 + np.abs(pc * rv)) * np.sign(pc), index=close.index),
            length=self.len_thrust
        ))
        
        mean_th = self.I(pta.sma, th_raw_calc, length=self.len_norm)
        std_th = self.I(pta.stdev, th_raw_calc, length=self.len_norm)
        
        z_th = self.I(lambda: (th_raw_calc - mean_th) / (std_th + 1e-10))
        
        th_osc = self.I(lambda: (np.exp(z_th) - np.exp(-z_th)) / (np.exp(z_th) + np.exp(-z_th)))
        
        # PSI Oscillator
        total_range = self.I(lambda: high - low)
        body_size = self.I(lambda: close - open_)
        abs_body = self.I(lambda: np.abs(body_size))
        efficiency = self.I(lambda: np.where(total_range != 0, abs_body / total_range, 0))
        
        vol_factor = self.I(lambda: (volume / vol_sma_50) if self.use_vol else pd.Series(1.0, index=close.index))
        
        psi_raw = self.I(lambda: np.where(efficiency > self.psi_thresh, body_size * efficiency * vol_factor, 0))
        
        psi_line = self.I(lambda: self._hma(pd.Series(psi_raw, index=close.index), self.len_psi))
        
        # Energy Index
        self.energy_index = self.I(lambda: self.alpha * th_osc + self.beta * psi_line)
        self.psi_line = psi_line

    def _hma(self, src, length):
        """Hull Moving Average"""
        wma1 = pta.wma(src, length=length // 2)
        wma2 = pta.wma(src, length=length)
        raw_hma = 2 * wma1 - wma2
        hma = pta.wma(raw_hma, length=int(np.sqrt(length)))
        return hma if hma is not None else src

    def next(self):
        if crossover(self.energy_index, 0):
            if not self.position:
                self.buy()
        elif crossover(0, self.energy_index):
            if self.position:
                self.position.close()