import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 20
    smoothInput = 3
    thresholdInput = 5

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Body boundaries
        body_high = np.maximum(open_, close)
        body_low = np.minimum(open_, close)

        # Calculate max body high and min body low within rolling window
        max_body_high = self.I(lambda: body_high.rolling(self.lengthInput).max())
        min_body_low = self.I(lambda: body_low.rolling(self.lengthInput).min())

        # Calculate raw metrics
        def calculate_metrics():
            bull_count = pd.Series(0.0, index=close.index)
            bear_count = pd.Series(0.0, index=close.index)

            for i in range(len(close)):
                if i < self.lengthInput - 1:
                    continue

                max_bh = max_body_high.iloc[i]
                min_bl = min_body_low.iloc[i]

                if pd.isna(max_bh) or pd.isna(min_bl):
                    continue

                upper_level = None
                lower_level = None

                for j in range(i - self.lengthInput + 1, i + 1):
                    h = high.iloc[j]
                    l = low.iloc[j]

                    if h >= max_bh:
                        if upper_level is None or h < upper_level:
                            upper_level = h

                    if l <= min_bl:
                        if lower_level is None or l > lower_level:
                            lower_level = l

                if upper_level is not None and lower_level is not None:
                    for j in range(i - self.lengthInput + 1, i + 1):
                        if high.iloc[j] >= upper_level:
                            bear_count.iloc[i] += 1
                        if low.iloc[j] <= lower_level:
                            bull_count.iloc[i] += 1

            return bull_count, bear_count

        self.raw_bull_metric, self.raw_bear_metric = calculate_metrics()

        # Smoothing
        self.smoothed_bull = self.I(lambda: pta.sma(self.raw_bull_metric, length=self.smoothInput) or pd.Series(0, index=close.index))
        self.smoothed_bear = self.I(lambda: -pta.sma(self.raw_bear_metric, length=self.smoothInput) or pd.Series(0, index=close.index))

        # Trend metric
        self.trend_metric = self.I(lambda: self.smoothed_bull + self.smoothed_bear)

    def next(self):
        if len(self.data) < self.lengthInput + self.smoothInput:
            return

        raw_bull = self.raw_bull_metric.iloc[-1]
        raw_bear = self.raw_bear_metric.iloc[-1]

        bull_signal = crossover(self.raw_bull_metric.iloc[-2:].values, self.thresholdInput)
        bear_signal = crossover(self.raw_bear_metric.iloc[-2:].values, self.thresholdInput)

        if bull_signal and not self.position:
            self.buy()
        elif bear_signal and self.position:
            self.sell()