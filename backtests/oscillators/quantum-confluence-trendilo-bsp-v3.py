import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smooth = 1
    length = 50
    sens = 1.0
    bmult = 1.0
    bsp_len = 20
    bsp_sens = 1.0
    div_lookback = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate adaptive engine
        def calc_ama(val_series, length, s):
            result = pd.Series(index=close.index, dtype=float)
            ama_val = val_series.iloc[0]
            for i in range(len(val_series)):
                change = abs(close.iloc[i] - close.iloc[max(0, i-10)])
                volatility = close.iloc[max(0, i-10):i+1].diff().abs().rolling(10).mean()
                if pd.isna(volatility.iloc[-1]):
                    volatility_val = 0.0001
                else:
                    volatility_val = max(volatility.iloc[-1], 0.0001)
                er = change / (volatility_val * 10) if volatility_val != 0 else 0
                alpha = np.power(er * (2.0 / (length + 1)), s)
                ama_val = alpha * val_series.iloc[i] + (1 - alpha) * ama_val
                result.iloc[i] = ama_val
            return result

        def calc_z(val_series, length):
            sma = val_series.rolling(length).mean()
            stdev = val_series.rolling(length).std()
            stdev = stdev.replace(0, 0.0001)
            return (val_series - sma) / stdev

        # BSP Calculations
        raw_bp = (close - low.clip(upper=close)) * volume
        raw_sp = (high.clip(lower=close) - close) * volume

        self.adapt_bp = self.I(lambda: calc_ama(raw_bp, self.bsp_len, self.bsp_sens))
        self.adapt_sp = self.I(lambda: calc_ama(raw_sp, self.bsp_len, self.bsp_sens))
        self.z_bsp = self.I(lambda: calc_z(self.adapt_bp - self.adapt_sp, self.length))

        # Trendilo Calculations
        pch = close.diff(self.smooth) / close * 100
        self.adapt_pch = self.I(lambda: calc_ama(pch, self.length, self.sens))
        self.z_trendilo = self.I(lambda: calc_z(self.adapt_pch, self.length))

        # RMS Band
        def calc_rms(z_series, length, mult):
            sum_sq = (z_series * z_series).rolling(length).sum()
            return mult * np.sqrt(sum_sq / length)

        self.rms = self.I(lambda: calc_rms(self.z_trendilo, self.length, self.bmult))

        # Pivot detection for divergences
        self.prev_low = self.I(lambda: low.rolling(2 * self.div_lookback + 1, center=True).min())
        self.prev_high = self.I(lambda: high.rolling(2 * self.div_lookback + 1, center=True).max())
        self.prev_z_low = self.I(lambda: self.z_trendilo.rolling(2 * self.div_lookback + 1, center=True).min())
        self.prev_z_high = self.I(lambda: self.z_trendilo.rolling(2 * self.div_lookback + 1, center=True).max())

    def next(self):
        # Confluence logic
        trend_bull = self.z_trendilo[-1] > self.rms[-1]
        trend_bear = self.z_trendilo[-1] < -self.rms[-1]
        bsp_bull = self.z_bsp[-1] > 0
        bsp_bear = self.z_bsp[-1] < 0

        # Strong confluence conditions
        strong_bull = trend_bull and bsp_bull
        strong_bear = trend_bear and bsp_bear

        # Entry conditions
        if strong_bull and not self.position:
            self.buy()
        elif strong_bear and self.position:
            self.sell()

        # Exit long position on trend reversal
        if self.position and self.z_trendilo[-1] < -self.rms[-1]:
            self.sell()

        # Exit short position on trend reversal
        if not self.position and self.z_trendilo[-1] > self.rms[-1]:
            self.buy()