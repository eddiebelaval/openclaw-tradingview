import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenght_dmi = 8
    smooth_adx = 1
    length_ma_dmi = 365
    source_ma_dmi = 'EMA'

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.lenght_dmi))
        
        def get_dmi_components():
            result = pta.adx(high, low, close, length=self.lenght_dmi)
            if result is not None and len(result) > 0:
                diplus = result.iloc[:, 0] if result.shape[1] > 0 else pd.Series(0, index=close.index)
                diminus = result.iloc[:, 1] if result.shape[1] > 1 else pd.Series(0, index=close.index)
                return diplus, diminus
            return pd.Series(0, index=close.index), pd.Series(0, index=close.index)
        
        diplus, diminus = get_dmi_components()
        self.diplus = self.I(lambda: diplus)
        self.diminus = self.I(lambda: diminus)
        
        dmi = diplus - diminus
        
        if self.source_ma_dmi == 'EMA':
            dmi_ma = self.I(lambda: pta.ema(dmi, length=self.length_ma_dmi) or pd.Series(0, index=close.index))
        elif self.source_ma_dmi == 'SMA':
            dmi_ma = self.I(lambda: pta.sma(dmi, length=self.length_ma_dmi) or pd.Series(0, index=close.index))
        elif self.source_ma_dmi == 'RMA':
            dmi_ma = self.I(lambda: pta.rma(dmi, length=self.length_ma_dmi) or pd.Series(0, index=close.index))
        elif self.source_ma_dmi == 'WMA':
            dmi_ma = self.I(lambda: pta.wma(dmi, length=self.length_ma_dmi) or pd.Series(0, index=close.index))
        elif self.source_ma_dmi == 'VWMA':
            dmi_ma = self.I(lambda: pta.vwma(close, volume, length=self.length_ma_dmi) or pd.Series(0, index=close.index))
        elif self.source_ma_dmi == 'HMA':
            dmi_ma = self.I(lambda: pta.hma(dmi, length=self.length_ma_dmi) or pd.Series(0, index=close.index))
        else:
            dmi_ma = self.I(lambda: pta.ema(dmi, length=self.length_ma_dmi) or pd.Series(0, index=close.index))
        
        self.dmi = self.I(lambda: dmi)
        self.dmi_ma = dmi_ma
        
        self.adx = adx_result

    def next(self):
        if len(self.data) < 2:
            return
        
        bull_dmi = crossover(self.diplus, self.diminus)
        bear_dmi = crossover(self.diminus, self.diplus)
        
        if bull_dmi:
            if not self.position:
                self.buy()
        elif bear_dmi:
            if self.position:
                self.sell()


