import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    cycleLen = 20
    smooth = 6

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        def calculate_cycle_wave():
            stoch1 = pta.stoch(high, low, close, k=self.cycleLen, d=3, smooth_k=1)['STOCHk']
            stoch2 = pta.stoch(high, low, close, k=max(2, round(self.cycleLen * 1.5)), d=3, smooth_k=1)['STOCHk']
            stoch3 = pta.stoch(high, low, close, k=max(2, round(self.cycleLen / 2)), d=3, smooth_k=1)['STOCHk']
            
            if stoch1 is None or stoch2 is None or stoch3 is None:
                return pd.Series(0, index=close.index)
            
            avgCycle = (stoch1 + stoch2 + stoch3) / 3
            cycleWave = pta.wma(avgCycle - 50, length=self.smooth)
            
            if cycleWave is None:
                return pd.Series(0, index=close.index)
            
            return cycleWave

        def calculate_signal_line():
            stoch1 = pta.stoch(high, low, close, k=self.cycleLen, d=3, smooth_k=1)['STOCHk']
            stoch2 = pta.stoch(high, low, close, k=max(2, round(self.cycleLen * 1.5)), d=3, smooth_k=1)['STOCHk']
            stoch3 = pta.stoch(high, low, close, k=max(2, round(self.cycleLen / 2)), d=3, smooth_k=1)['STOCHk']
            
            if stoch1 is None or stoch2 is None or stoch3 is None:
                return pd.Series(0, index=close.index)
            
            avgCycle = (stoch1 + stoch2 + stoch3) / 3
            cycleWave = pta.wma(avgCycle - 50, length=self.smooth)
            
            if cycleWave is None:
                return pd.Series(0, index=close.index)
            
            signalLine = pta.ema(cycleWave, length=self.smooth * 2)
            
            if signalLine is None:
                return pd.Series(0, index=close.index)
            
            return signalLine

        self.cycleWave = self.I(calculate_cycle_wave)
        self.signalLine = self.I(calculate_signal_line)

    def next(self):
        if len(self.data) < self.smooth * 2 + 10:
            return

        buySignal = crossover(self.cycleWave, self.signalLine) and self.cycleWave[-1] < -15
        sellSignal = crossover(self.signalLine, self.cycleWave) and self.cycleWave[-1] > 15

        if buySignal:
            if not self.position:
                self.buy()
        elif sellSignal:
            if self.position:
                self.position.close()