import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adxLength = 14
    rsiLength = 14
    bbLength = 20
    bbMult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ADX via DMI
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adxLength))
        self.adx = adx_result
        
        # RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLength))
        
        # Bollinger Bands
        self.basis = self.I(lambda: pta.sma(close, length=self.bbLength))
        self.dev = self.I(lambda: self.bbMult * close.rolling(window=self.bbLength).std())
        self.upper = self.I(lambda: self.basis[-1] + self.dev[-1] if len(self.basis) > 0 and len(self.dev) > 0 else close.iloc[-1])
        self.lower = self.I(lambda: self.basis[-1] - self.dev[-1] if len(self.basis) > 0 and len(self.dev) > 0 else close.iloc[-1])
        
        # BB Score
        self.bb_score = self.I(lambda: (close - self.basis) / (self.dev + 1e-10))
        
        self.in_trade = False

    def next(self):
        close = self.data.Close[-1]
        adx_val = self.adx[-1] if len(self.adx) > 0 and not np.isnan(self.adx[-1]) else 0
        rsi_val = self.rsi[-1] if len(self.rsi) > 0 and not np.isnan(self.rsi[-1]) else 50
        bb_score_val = self.bb_score[-1] if len(self.bb_score) > 0 and not np.isnan(self.bb_score[-1]) else 0
        
        # Stop Grid Alert Condition
        stop_grid_condition = (
            adx_val > 22 or
            rsi_val > 70 or rsi_val < 30 or
            bb_score_val > 1.5 or bb_score_val < -1.5
        )
        
        # Trading logic based on alert condition
        if stop_grid_condition and not self.position:
            # Enter trade when alert condition is triggered
            self.buy()
            self.in_trade = True
        elif self.position and not stop_grid_condition:
            # Exit trade when alert condition resolves
            self.sell()
            self.in_trade = False


