import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend Module Parameters
    atr_period = 10
    factor = 3.0
    
    # AO Module Parameters
    show_zero_cross = True
    enable_three_to_zero = True
    three_to_zero_on_next_bar = False
    
    # ADX Module Parameters
    adx_len = 14
    di_len = 14
    adx_min_level = 20.0
    require_di_direction = True
    
    # Combined Signal Logic Parameters
    confirm_window_bars = 3
    
    # Module Enablement
    enable_trend_module = True
    enable_ao_module = True
    enable_adx_module = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Trend Module - Supertrend calculation
        def calc_supertrend():
            hl2 = (high + low) / 2
            atr = pta.atr(high, low, close, length=self.atr_period)
            if atr is None:
                atr = pd.Series(0, index=close.index)
            
            basic_ub = hl2 + self.factor * atr
            basic_lb = hl2 - self.factor * atr
            
            final_ub = pd.Series(index=close.index, dtype=float)
            final_lb = pd.Series(index=close.index, dtype=float)
            
            for i in range(len(close)):
                if i == 0:
                    final_ub.iloc[i] = basic_ub.iloc[i]
                    final_lb.iloc[i] = basic_lb.iloc[i]
                else:
                    final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                    final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
            
            supertrend = pd.Series(index=close.index, dtype=float)
            state = pd.Series(index=close.index, dtype=float)
            
            for i in range(len(close)):
                if close.iloc[i] <= final_ub.iloc[i]:
                    supertrend.iloc[i] = final_ub.iloc[i]
                    state.iloc[i] = -1
                else:
                    supertrend.iloc[i] = final_lb.iloc[i]
                    state.iloc[i] = 1
            
            return supertrend, state
        
        self.supertrend, self.st_state = self.I(calc_supertrend)
        
        # AO Module
        median_price = (high + low) / 2.0
        sma5 = self.I(pta.sma, median_price, length=5)
        sma34 = self.I(pta.sma, median_price, length=34)
        
        def calc_ao():
            return sma5 - sma34
        
        self.ao = self.I(calc_ao)
        
        # ADX Module
        def calc_dirmov(dilen):
            up = high.diff()
            down = -low.diff()
            
            plus_dm = pd.Series(0.0, index=close.index)
            minus_dm = pd.Series(0.0, index=close.index)
            
            for i in range(len(close)):
                if i == 0:
                    continue
                if up.iloc[i] > down.iloc[i] and up.iloc[i] > 0:
                    plus_dm.iloc[i] = up.iloc[i]
                if down.iloc[i] > up.iloc[i] and down.iloc[i] > 0:
                    minus_dm.iloc[i] = down.iloc[i]
            
            tr = pta.atr(high, low, close, length=dilen)
            if tr is None:
                tr = pd.Series(1.0, index=close.index)
            
            plus_di = 100 * pta.rma(plus_dm, length=dilen) / tr
            minus_di = 100 * pta.rma(minus_dm, length=dilen) / tr
            
            if plus_di is None:
                plus_di = pd.Series(50, index=close.index)
            if minus_di is None:
                minus_di = pd.Series(50, index=close.index)
            
            return plus_di.fillna(50), minus_di.fillna(50)
        
        self.plus_di, self.minus_di = self.I(calc_dirmov, self.di_len)
        
        def calc_adx():
            up = high.diff()
            down = -low.diff()
            
            plus_dm = pd.Series(0.0, index=close.index)
            minus_dm = pd.Series(0.0, index=close.index)
            
            for i in range(len(close)):
                if i == 0:
                    continue
                if up.iloc[i] > down.iloc[i] and up.iloc[i] > 0:
                    plus_dm.iloc[i] = up.iloc[i]
                if down.iloc[i] > up.iloc[i] and down.iloc[i] > 0:
                    minus_dm.iloc[i] = down.iloc[i]
            
            tr = pta.atr(high, low, close, length=self.di_len)
            if tr is None:
                tr = pd.Series(1.0, index=close.index)
            
            plus_rma = pta.rma(plus_dm, length=self.di_len)
            minus_rma = pta.rma(minus_dm, length=self.di_len)
            
            if plus_rma is None:
                plus_rma = pd.Series(0, index=close.index)
            if minus_rma is None:
                minus_rma = pd.Series(0, index=close.index)
            
            sum_di = plus_rma + minus_rma
            diff_di = (plus_rma - minus_rma).abs()
            
            di_ratio = diff_di / (sum_di.replace(0, 1))
            adxv = 100 * pta.rma(di_ratio, length=self.adx_len)
            
            if adxv is None:
                adxv = pd.Series(20, index=close.index)
            
            return adxv.fillna(20)
        
        self.adx_value = self.I(calc_adx)
        
        # Track recent events
        self.trend_long_bars = 0
        self.trend_short_bars = 0
        self.ao_long_bars = 0
        self.ao_short_bars = 0
        self.adx_long_bars = 0
        self.adx_short_bars = 0
        
        self.bias = 0

    def next(self):
        # Update bar counters
        self.trend_long_bars += 1
        self.trend_short_bars += 1
        self.ao_long_bars += 1
        self.ao_short_bars += 1
        self.adx_long_bars += 1
        self.adx_short_bars += 1
        
        # Trend Module Events
        trend_long_event = False
        trend_short_event = False
        
        if self.enable_trend_module and len(self.st_state) > 1:
            if self.st_state[-2] < 0 and self.st_state[-1] > 0:
                trend_long_event = True
                self.trend_long_bars = 0
            elif self.st_state[-2] > 0 and self.st_state[-1] < 0:
                trend_short_event = True
                self.trend_short_bars = 0
        
        # AO Module Events
        ao_long_event = False
        ao_short_event = False
        
        if self.enable_ao_module and len(self.ao) > 2:
            # Zero cross
            if self.show_zero_cross:
                if crossover(self.ao, 0):
                    ao_long_event = True
                    self.ao_long_bars = 0
                elif crossover(0, self.ao):
                    ao_short_event = True
                    self.ao_short_bars = 0
            
            # 3 to 0 pattern
            if self.enable_three_to_zero and len(self.ao) > 3:
                toward_zero_bull = (self.ao[-1] < 0) and (self.ao[-1] > self.ao[-2]) and (self.ao[-2] > self.ao[-3])
                toward_zero_bear = (self.ao[-1] > 0) and (self.ao[-1] < self.ao[-2]) and (self.ao[-2] < self.ao[-3])
                
                was_away_bull = (self.ao[-4] < 0) and (self.ao[-4] > self.ao[-3])
                was_away_bear = (self.ao[-4] > 0) and (self.ao[-4] < self.ao[-3])
                
                if toward_zero_bull and was_away_bull:
                    if not self.three_to_zero_on_next_bar:
                        ao_long_event = True
                        self.ao_long_bars = 0
                
                if toward_zero_bear and was_away_bear:
                    if not self.three_to_zero_on_next_bar:
                        ao_short_event = True
                        self.ao_short_bars = 0
        
        # ADX Module Events
        adx_pass = self.adx_value[-1] >= self.adx_min_level
        di_bull_pass = not self.require_di_direction or (self.plus_di[-1] > self.minus_di[-1])
        di_bear_pass = not self.require_di_direction or (self.minus_di[-1] > self.plus_di[-1])
        
        adx_long_event = self.enable_adx_module and adx_pass and di_bull_pass
        adx_short_event = self.enable_adx_module and adx_pass and di_bear_pass
        
        if adx_long_event:
            self.adx_long_bars = 0
        if adx_short_event:
            self.adx_short_bars = 0
        
        # Check recent events within confirmation window
        recent_long_trend = self.trend_long_bars <= self.confirm_window_bars if self.enable_trend_module else True
        recent_short_trend = self.trend_short_bars <= self.confirm_window_bars if self.enable_trend_module else True
        
        recent_long_ao = self.ao_long_bars <= self.confirm_window_bars if self.enable_ao_module else True
        recent_short_ao = self.ao_short_bars <= self.confirm_window_bars if self.enable_ao_module else True
        
        recent_long_adx = self.adx_long_bars <= self.confirm_window_bars if self.enable_adx_module else True
        recent_short_adx = self.adx_short_bars <= self.confirm_window_bars if self.enable_adx_module else True
        
        # Combined signal logic
        enabled_modules = sum([self.enable_trend_module, self.enable_ao_module, self.enable_adx_module])
        
        combined_long_setup = (
            recent_long_trend and
            recent_long_ao and
            recent_long_adx and
            enabled_modules > 0
        )
        
        combined_short_setup = (
            recent_short_trend and
            recent_short_ao and
            recent_short_adx and
            enabled_modules > 0
        )
        
        # Edge detection
        prev_long_setup = hasattr(self, '_prev_long_setup') and self._prev_long_setup
        prev_short_setup = hasattr(self, '_prev_short_setup') and self._prev_short_setup
        
        combined_long_signal = combined_long_setup and not prev_long_setup
        combined_short_signal = combined_short_setup and not prev_short_setup
        
        self._prev_long_setup = combined_long_setup
        self._prev_short_setup = combined_short_setup
        
        # Update bias and trade
        if combined_long_signal:
            self.bias = 1
            if self.position and not self.position.is_long:
                self.position.close()
            if not self.position:
                self.buy()
        
        if combined_short_signal:
            self.bias = -1
            if self.position and self.position.is_long:
                self.position.close()
            if not self.position:
                self.sell()


