import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    rsiOS = 30
    stochLen = 14
    stochK = 3
    stochD = 3
    stochOS = 20
    stochOB = 90
    slPercent = 0.6

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI calculation
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        # Stochastic calculation
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=self.stochLen, d=self.stochD, smooth_k=self.stochK))
        
        # Extract %K from stoch result (first column or named 'STOCHk_14_3_3')
        self.stoch_k = self.I(lambda: (
            pta.stoch(high, low, close, k=self.stochLen, d=self.stochD, smooth_k=self.stochK).iloc[:, 0]
            if pta.stoch(high, low, close, k=self.stochLen, d=self.stochD, smooth_k=self.stochK) is not None
            else pd.Series(50, index=close.index)
        ))
        
        # Higher High detection
        self.higher_high = self.I(lambda: high > high.shift(1))

    def next(self):
        # Check if we have enough data
        if len(self.data) < 2:
            return
        
        # Get previous bar values
        rsi_prev = self.rsi[-2] if len(self.rsi) >= 2 else self.rsi[-1]
        stoch_k_prev = self.stoch_k[-2] if len(self.stoch_k) >= 2 else self.stoch_k[-1]
        
        rsi_curr = self.rsi[-1]
        stoch_k_curr = self.stoch_k[-1]
        
        # Oversold check from previous bar
        is_oversold = (rsi_prev <= self.rsiOS) and (stoch_k_prev <= self.stochOS)
        
        # Buy condition: was oversold and current bar makes higher high
        buy_condition = is_oversold and (self.data.High[-1] > self.data.High[-2])
        
        # TP condition: Stochastic %K enters overbought zone
        tp_condition = stoch_k_curr >= self.stochOB
        
        # Entry logic
        if buy_condition and not self.position:
            self.buy()
        
        # Exit logic
        if self.position:
            # Stop Loss at fixed 0.6%
            stop_level = self.position.open_price * (1 - (self.slPercent / 100))
            if self.data.Close[-1] <= stop_level:
                self.position.close()
            
            # Take Profit when Stochastic enters overbought
            elif tp_condition:
                self.position.close()


