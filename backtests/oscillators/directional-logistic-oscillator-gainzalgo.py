import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # DMI Settings
    di_len = 14
    mean_lb = 360
    
    # Logistic Probability Settings
    slope = 0.18
    smooth_len = 3
    
    # Oscillator Settings
    osc_scale = 2.5
    osc_smooth_len = 7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate DMI components
        adx_result = self.I(pta.adx, high, low, close, length=self.di_len)
        
        # Extract DI+ and DI- from ADX result
        # pta.adx returns a DataFrame with columns: ADX, DMP, DMN
        def get_di_plus(h, l, c):
            result = pta.adx(h, l, c, length=self.di_len)
            if result is not None and 'DMP' in result.columns:
                return result['DMP']
            return pd.Series(0, index=c.index)
        
        def get_di_minus(h, l, c):
            result = pta.adx(h, l, c, length=self.di_len)
            if result is not None and 'DMN' in result.columns:
                return result['DMN']
            return pd.Series(0, index=c.index)
        
        def get_adx_line(h, l, c):
            result = pta.adx(h, l, c, length=self.di_len)
            if result is not None and 'ADX' in result.columns:
                return result['ADX']
            return pd.Series(50, index=c.index)
        
        plus_di = self.I(get_di_plus, high, low, close)
        minus_di = self.I(get_di_minus, high, low, close)
        adx = self.I(get_adx_line, high, low, close)
        
        # Logistic Probability Function
        def logistic_prob(series, mean_lb, slope, smooth_len):
            mean = series.rolling(mean_lb).mean()
            z = (series - mean) * slope
            prob_raw = 1.0 / (1.0 + np.exp(-z))
            return pta.ema(prob_raw, length=smooth_len)
        
        prob_plus = self.I(lambda: logistic_prob(plus_di, self.mean_lb, self.slope, self.smooth_len) or pd.Series(0.5, index=close.index))
        prob_minus = self.I(lambda: logistic_prob(minus_di, self.mean_lb, self.slope, self.smooth_len) or pd.Series(0.5, index=close.index))
        prob_adx = self.I(lambda: logistic_prob(adx, self.mean_lb, self.slope, self.smooth_len) or pd.Series(0.5, index=close.index))
        
        # Tanh function
        def tanh_func(x):
            e2x = np.exp(2 * x)
            return (e2x - 1) / (e2x + 1)
        
        # Calculate net directional strength
        def calc_strength(p_plus, p_minus, p_adx, osc_scale, smooth_len):
            net_dir = p_plus - p_minus
            strength_raw = net_dir * p_adx * osc_scale
            strength_bound = tanh_func(strength_raw)
            return pta.ema(strength_bound, length=smooth_len)
        
        strength = self.I(lambda: calc_strength(prob_plus, prob_minus, prob_adx, self.osc_scale, self.smooth_len) or pd.Series(0, index=close.index))
        
        # Smoothed lines
        s_sma = self.I(pta.sma, strength, length=self.osc_smooth_len)
        s_ema = self.I(pta.ema, strength, length=self.osc_smooth_len)
        
        def s_sma_cycle_calc(sma_series, osc_smooth_len):
            return pta.ema(sma_series, length=int(np.ceil(osc_smooth_len / 2)))
        
        s_sma_cycle = self.I(lambda: s_sma_cycle_calc(s_sma, self.osc_smooth_len) or pd.Series(0, index=close.index))
        
        # Percentile thresholds
        def lower_threshold_sma_calc(sma_series, mean_lb):
            percentiles = sma_series.rolling(mean_lb).apply(lambda x: np.percentile(x, 10))
            return percentiles
        
        def upper_threshold_sma_calc(sma_series, mean_lb):
            percentiles = sma_series.rolling(mean_lb).apply(lambda x: np.percentile(x, 90))
            return percentiles
        
        def lower_threshold_ema_calc(ema_series, mean_lb):
            percentiles = ema_series.rolling(mean_lb).apply(lambda x: np.percentile(x, 5))
            return percentiles
        
        def upper_threshold_ema_calc(ema_series, mean_lb):
            percentiles = ema_series.rolling(mean_lb).apply(lambda x: np.percentile(x, 95))
            return percentiles
        
        lower_threshold_sma = self.I(lambda: lower_threshold_sma_calc(s_sma, self.mean_lb) or pd.Series(-0.3, index=close.index))
        upper_threshold_sma = self.I(lambda: upper_threshold_sma_calc(s_sma, self.mean_lb) or pd.Series(0.3, index=close.index))
        lower_threshold_ema = self.I(lambda: lower_threshold_ema_calc(s_ema, self.mean_lb) or pd.Series(-0.4, index=close.index))
        upper_threshold_ema = self.I(lambda: upper_threshold_ema_calc(s_ema, self.mean_lb) or pd.Series(0.4, index=close.index))
        
        self.strength = strength
        self.s_sma = s_sma
        self.s_ema = s_ema
        self.s_sma_cycle = s_sma_cycle
        self.lower_threshold_sma = lower_threshold_sma
        self.upper_threshold_sma = upper_threshold_sma
        self.lower_threshold_ema = lower_threshold_ema
        self.upper_threshold_ema = upper_threshold_ema

    def next(self):
        # Mean-reversion buy signals
        bc1 = crossover(self.s_sma, self.lower_threshold_sma)
        bc2 = crossover(self.s_ema, self.lower_threshold_ema)
        
        # Mean-reversion sell signals
        sc1 = crossover(self.upper_threshold_sma, self.s_sma)
        sc2 = crossover(self.upper_threshold_ema, self.s_ema)
        
        # Reversion signals (cycle turning points)
        rev_up = len(self.s_sma_cycle) >= 3 and self.s_sma_cycle[-1] > self.s_sma_cycle[-2] and not (self.s_sma_cycle[-2] > self.s_sma_cycle[-3])
        rev_dn = len(self.s_sma_cycle) >= 3 and self.s_sma_cycle[-1] < self.s_sma_cycle[-2] and not (self.s_sma_cycle[-2] < self.s_sma_cycle[-3])
        
        # Zero-line crosses
        strength_cross_up = crossover(self.strength, 0)
        strength_cross_dn = crossover(0, self.strength)
        
        # Trading logic: Buy on mean-reversion signals or reversion up or zero-line cross up
        if (bc1 or bc2 or rev_up or strength_cross_up) and not self.position:
            self.buy()
        
        # Trading logic: Sell on mean-reversion signals or reversion down or zero-line cross down
        elif (sc1 or sc2 or rev_dn or strength_cross_dn) and self.position:
            self.sell()


