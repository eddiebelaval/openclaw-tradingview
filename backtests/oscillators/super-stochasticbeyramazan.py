        # We need to handle this properly
        def get_k_line():
            result = pta.stoch(high, low, close, k=self.periodK, d=self.periodD, smooth_k=self.smoothK)
            if result is not None and not result.empty:
                k_col = [col for col in result.columns if 'STOCHk' in col][0]
                return result[k_col]
            return pd.Series(50, index=close.index)
        
        def get_d_line():
            result = pta.stoch(high, low, close, k=self.periodK, d=self.periodD, smooth_k=self.smoothK)
            if result is not None and not result.empty:
                d_col = [col for col in result.columns if 'STOCHd' in col][0]
                return result[d_col]
            return pd.Series(50, index=close.index)
        
        self.k = self.I(get_k_line)
        self.d = self.I(get_d_line)

