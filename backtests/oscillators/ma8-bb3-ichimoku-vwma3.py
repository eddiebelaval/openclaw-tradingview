import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA parameters
    ma1_len = 5
    ma1_type = "SMA"
    ma2_len = 10
    ma2_type = "SMA"
    ma3_len = 20
    ma3_type = "SMA"
    ma4_len = 60
    ma4_type = "SMA"
    
    # BB parameters
    bb1_len = 20
    bb1_mult = 2.0
    
    # Ichimoku parameters
    tenkan_len = 9
    kijun_len = 26
    senkou_b_len = 52
    
    # VWMA parameters
    vw1_len = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # MA1
        self.ma1 = self.I(lambda: pta.sma(close, length=self.ma1_len) if self.ma1_type == "SMA" else pta.ema(close, length=self.ma1_len))
        
        # MA2
        self.ma2 = self.I(lambda: pta.sma(close, length=self.ma2_len) if self.ma2_type == "SMA" else pta.ema(close, length=self.ma2_len))
        
        # MA3
        self.ma3 = self.I(lambda: pta.sma(close, length=self.ma3_len) if self.ma3_type == "SMA" else pta.ema(close, length=self.ma3_len))
        
        # MA4
        self.ma4 = self.I(lambda: pta.sma(close, length=self.ma4_len) if self.ma4_type == "SMA" else pta.ema(close, length=self.ma4_len))
        
        # Bollinger Bands
        bb = self.I(lambda: pta.bbands(close, length=self.bb1_len, std=self.bb1_mult))
        self.bb_upper = bb.iloc[:, 2] if bb is not None and bb.shape[1] > 2 else pd.Series(0, index=close.index)
        self.bb_lower = bb.iloc[:, 0] if bb is not None and bb.shape[1] > 0 else pd.Series(0, index=close.index)
        self.bb_basis = bb.iloc[:, 1] if bb is not None and bb.shape[1] > 1 else pd.Series(0, index=close.index)
        
        # Ichimoku - Donchian calculations
        def donchian_high(length):
            return high.rolling(window=length).max()
        
        def donchian_low(length):
            return low.rolling(window=length).min()
        
        self.tenkan = self.I(lambda: (donchian_high(self.tenkan_len) + donchian_low(self.tenkan_len)) / 2)
        self.kijun = self.I(lambda: (donchian_high(self.kijun_len) + donchian_low(self.kijun_len)) / 2)
        
        senkou_b_temp = self.I(lambda: (donchian_high(self.senkou_b_len) + donchian_low(self.senkou_b_len)) / 2)
        self.senkou_b = senkou_b_temp
        
        # VWMA
        self.vwma1 = self.I(lambda: pta.vwma(close, volume, length=self.vw1_len) if volume.sum() > 0 else pta.sma(close, length=self.vw1_len))

    def next(self):
        # Buy signal: MA1 crosses above MA2, price above MA3, and price above BB lower band
        if len(self) < max(self.ma1_len, self.ma2_len, self.ma3_len, self.bb1_len) + 1:
            return
        
        if crossover(self.ma1, self.ma2):
            if self.data.Close[-1] > self.ma3[-1] and self.data.Close[-1] > self.bb_lower[-1]:
                if not self.position:
                    self.buy()
        
        # Sell signal: Price falls below MA3 or MA1 crosses below MA2
        if self.position:
            if crossover(self.ma2, self.ma1):
                self.sell()
            elif self.data.Close[-1] < self.ma3[-1]:
                self.sell()
            elif self.data.Close[-1] < self.bb_lower[-1]:
                self.sell()