import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        
        # Calculate momentum: SMA of (close - open) with period 3
        momentum = self.I(lambda: pta.sma(close - open_, length=3))
        
        # Calculate kagemusha_wing: close + (momentum * 2)
        self.kagemusha_wing = self.I(lambda: close + (momentum * 2))

    def next(self):
        # Buy when kagemusha_wing crosses above close
        if len(self.data) > 1:
            if crossover(self.kagemusha_wing, pd.Series(self.data.Close)):
                if not self.position:
                    self.buy()
            # Sell when kagemusha_wing crosses below close
            elif crossover(pd.Series(self.data.Close), self.kagemusha_wing):
                if self.position:
                    self.position.close()


if __name__ == '__main__':
    from backtesting.test import SMA, GOOG
    
    bt = Backtest(GOOG, TvStrategy, cash=10000, commission=.002)
