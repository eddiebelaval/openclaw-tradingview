import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    maType = "SMA"
    mult1 = 1.0
    mult2 = 2.0
    mult3 = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate basis line based on MA type
        if self.maType == "SMA":
            self.basis = self.I(pta.sma, close, length=self.length)
        elif self.maType == "EMA":
            self.basis = self.I(pta.ema, close, length=self.length)
        elif self.maType == "SMMA (RMA)":
            self.basis = self.I(pta.rma, close, length=self.length)
        elif self.maType == "WMA":
            self.basis = self.I(pta.wma, close, length=self.length)
        elif self.maType == "VWMA":
            self.basis = self.I(pta.vwma, close, volume, length=self.length)
        else:
            self.basis = self.I(pta.sma, close, length=self.length)
        
        # Calculate standard deviation
        self.stddev = self.I(pta.stdev, close, length=self.length)
        
        # Calculate deviations and bands for each sigma level
        # Sigma 1
        self.dev1 = self.I(lambda: self.mult1 * self.stddev[-len(self.stddev):] if len(self.stddev) > 0 else pd.Series(0, index=close.index))
        self.upper1 = self.I(lambda: self.basis[-len(self.basis):] + self.dev1[-len(self.dev1):] if len(self.basis) > 0 and len(self.dev1) > 0 else pd.Series(0, index=close.index))
        self.lower1 = self.I(lambda: self.basis[-len(self.basis):] - self.dev1[-len(self.dev1):] if len(self.basis) > 0 and len(self.dev1) > 0 else pd.Series(0, index=close.index))
        
        # Sigma 2
        self.dev2 = self.I(lambda: self.mult2 * self.stddev[-len(self.stddev):] if len(self.stddev) > 0 else pd.Series(0, index=close.index))
        self.upper2 = self.I(lambda: self.basis[-len(self.basis):] + self.dev2[-len(self.dev2):] if len(self.basis) > 0 and len(self.dev2) > 0 else pd.Series(0, index=close.index))
        self.lower2 = self.I(lambda: self.basis[-len(self.basis):] - self.dev2[-len(self.dev2):] if len(self.basis) > 0 and len(self.dev2) > 0 else pd.Series(0, index=close.index))
        
        # Sigma 3
        self.dev3 = self.I(lambda: self.mult3 * self.stddev[-len(self.stddev):] if len(self.stddev) > 0 else pd.Series(0, index=close.index))
        self.upper3 = self.I(lambda: self.basis[-len(self.basis):] + self.dev3[-len(self.dev3):] if len(self.basis) > 0 and len(self.dev3) > 0 else pd.Series(0, index=close.index))
        self.lower3 = self.I(lambda: self.basis[-len(self.basis):] - self.dev3[-len(self.dev3):] if len(self.basis) > 0 and len(self.dev3) > 0 else pd.Series(0, index=close.index))

    def next(self):
        # Buy when price touches lower band with reversal signal
        if len(self) < 2:
            return
        
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        prev_close = self.data.Close[-2]
        
        # Check if we have valid indicator values
        if np.isnan(self.basis[-1]) or np.isnan(self.upper2[-1]) or np.isnan(self.lower2[-1]):
            return
        
        # Buy signal: price touches or crosses below lower band 2, then reverses up
        if current_low <= self.lower2[-1] and current_close > self.basis[-1]:
            if not self.position:
                self.buy()
        
        # Sell signal: price touches or crosses above upper band 2, then reverses down
        elif current_high >= self.upper2[-1] and current_close < self.basis[-1]:
            if self.position:
                self.sell()
        
        # Exit on close crossing back through basis
        elif self.position and crossover(self.basis, self.data.Close):
            self.sell()


