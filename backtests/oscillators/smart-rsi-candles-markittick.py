import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_len = 14
    div_left = 5
    div_right = 5
    max_lookb = 60
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        self.raw_rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        self.rsi_highest = self.I(lambda: close.rolling(self.rsi_len).max().fillna(method='bfill') if hasattr(close.rolling(self.rsi_len).max(), 'fillna') else close.rolling(self.rsi_len).max())
        self.rsi_lowest = self.I(lambda: close.rolling(self.rsi_len).min().fillna(method='bfill') if hasattr(close.rolling(self.rsi_len).min(), 'fillna') else close.rolling(self.rsi_len).min())
        self.price_highest = self.I(lambda: high.rolling(self.rsi_len).max().fillna(method='bfill') if hasattr(high.rolling(self.rsi_len).max(), 'fillna') else high.rolling(self.rsi_len).max())
        self.price_lowest = self.I(lambda: low.rolling(self.rsi_len).min().fillna(method='bfill') if hasattr(low.rolling(self.rsi_len).min(), 'fillna') else low.rolling(self.rsi_len).min())
        
        self.last_pl_price = None
        self.last_pl_rsi = None
        self.last_pl_idx = None
        self.last_ph_price = None
        self.last_ph_rsi = None
        self.last_ph_idx = None
        
        self.bull_div_detected = False
        self.bear_div_detected = False

    def next(self):
        if len(self.data) < self.rsi_len + self.div_right:
            return
        
        current_idx = len(self.data) - 1
        current_price_low = self.data.Low[-self.div_right] if len(self.data) >= self.div_right else self.data.Low[-1]
        current_rsi_low = self.raw_rsi[-self.div_right] if len(self.raw_rsi) >= self.div_right else self.raw_rsi[-1]
        current_price_high = self.data.High[-self.div_right] if len(self.data) >= self.div_right else self.data.High[-1]
        current_rsi_high = self.raw_rsi[-self.div_right] if len(self.raw_rsi) >= self.div_right else self.raw_rsi[-1]
        
        if current_idx >= self.div_left + self.div_right:
            is_pivot_low = self._is_pivot_low(current_idx)
            is_pivot_high = self._is_pivot_high(current_idx)
            
            if is_pivot_low:
                self.bull_div_detected = False
                if self.last_pl_price is not None and self.last_pl_idx is not None:
                    bars_passed = current_idx - self.last_pl_idx
                    if bars_passed <= self.max_lookb:
                        if current_price_low < self.last_pl_price and current_rsi_low > self.last_pl_rsi:
                            self.bull_div_detected = True
                        elif current_price_low > self.last_pl_price and current_rsi_low < self.last_pl_rsi:
                            self.bull_div_detected = True
                
                self.last_pl_price = current_price_low
                self.last_pl_rsi = current_rsi_low
                self.last_pl_idx = current_idx
            
            if is_pivot_high:
                self.bear_div_detected = False
                if self.last_ph_price is not None and self.last_ph_idx is not None:
                    bars_passed = current_idx - self.last_ph_idx
                    if bars_passed <= self.max_lookb:
                        if current_price_high > self.last_ph_price and current_rsi_high < self.last_ph_rsi:
                            self.bear_div_detected = True
                        elif current_price_high < self.last_ph_price and current_rsi_high > self.last_ph_rsi:
                            self.bear_div_detected = True
                
                self.last_ph_price = current_price_high
                self.last_ph_rsi = current_rsi_high
                self.last_ph_idx = current_idx
        
        if self.bull_div_detected and not self.position:
            self.buy()
        elif self.bear_div_detected and self.position:
            self.sell()

    def _is_pivot_low(self, idx):
        if idx < self.div_left + self.div_right:
            return False
        
        center = idx - self.div_right
        if center < self.div_left or center + self.div_right >= len(self.raw_rsi):
            return False
        
        center_val = self.raw_rsi[center]
        
        for i in range(self.div_left):
            if self.raw_rsi[center - i - 1] <= center_val:
                return False
        
        for i in range(self.div_right):
            if self.raw_rsi[center + i + 1] <= center_val:
                return False
        
        return True

    def _is_pivot_high(self, idx):
        if idx < self.div_left + self.div_right:
            return False
        
        center = idx - self.div_right
        if center < self.div_left or center + self.div_right >= len(self.raw_rsi):
            return False
        
        center_val = self.raw_rsi[center]
        
        for i in range(self.div_left):
            if self.raw_rsi[center - i - 1] >= center_val:
                return False
        
        for i in range(self.div_right):
            if self.raw_rsi[center + i + 1] >= center_val:
                return False
        
        return True


