import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smoothK = 3
    smoothD = 3
    lengthRSI = 14
    lengthStoch = 14

    def init(self):
        close = pd.Series(self.data.Close)
        
        rsi = self.I(pta.rsi, close, length=self.lengthRSI)
        
        stoch_result = self.I(lambda: pta.stoch(
            self.data.High,
            self.data.Low,
            rsi,
            k=self.lengthStoch,
            d=self.lengthStoch,
            smooth_k=1
        ))
        
        stoch_k_raw = self.I(lambda: stoch_result['STOCHk_14_14_1'] if stoch_result is not None and 'STOCHk_14_14_1' in stoch_result else pd.Series(50, index=close.index))
        
        self.k = self.I(pta.sma, stoch_k_raw, length=self.smoothK)
        
        self.d = self.I(pta.sma, self.k, length=self.smoothD)

    def next(self):
        if len(self.data) < max(self.lengthRSI, self.lengthStoch) + self.smoothK + self.smoothD:
            return
        
        if crossover(self.k, 20):
            if not self.position:
                self.buy()
        elif crossover(80, self.k):
            if self.position:
                self.position.close()