import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters
    rank_cycles = 12
    bars_per_cycle = 21
    smooth_len = 10
    
    # Normalization parameters
    norm_lookback = 252
    use_zscore = True
    z_clamp = 2.5
    
    # Level parameters
    L1 = 25
    L2 = 60

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ROC (Rate of Change)
        lookback_bars = self.rank_cycles * self.bars_per_cycle
        
        def calculate_roc():
            roc_values = []
            for i in range(len(close)):
                if i >= lookback_bars:
                    roc_val = (close.iloc[i] / close.iloc[i - lookback_bars] - 1.0) * 100.0
                    roc_values.append(roc_val)
                else:
                    roc_values.append(np.nan)
            return pd.Series(roc_values, index=close.index)
        
        roc = self.I(calculate_roc)
        
        # Smooth ROC with EMA
        roc_sm = self.I(pta.ema, roc.fillna(method='bfill'), length=self.smooth_len)
        
        # Normalize to oscillator
        def calculate_osc_raw():
            osc_raw_values = []
            for i in range(len(roc_sm)):
                if i < self.norm_lookback:
                    osc_raw_values.append(np.nan)
                else:
                    lookback_slice = roc_sm.iloc[i - self.norm_lookback + 1:i + 1]
                    
                    if self.use_zscore:
                        mu = lookback_slice.mean()
                        sd = lookback_slice.std()
                        if sd == 0 or np.isnan(sd):
                            sd = 1e-6
                        z = (roc_sm.iloc[i] - mu) / max(sd, 1e-6)
                        zc = max(-self.z_clamp, min(self.z_clamp, z))
                        osc_raw_val = (zc / self.z_clamp) * 100.0
                    else:
                        hi = lookback_slice.max()
                        lo = lookback_slice.min()
                        denom = max(hi - lo, 1e-6)
                        u = (roc_sm.iloc[i] - lo) / denom
                        osc_raw_val = (u * 2.0 - 1.0) * 100.0
                    
                    osc_raw_values.append(osc_raw_val)
            
            return pd.Series(osc_raw_values, index=roc_sm.index)
        
        osc_raw = self.I(calculate_osc_raw)
        
        # Apply EMA smoothing to raw oscillator
        smooth_factor = max(1, self.smooth_len // 2)
        self.osc = self.I(pta.ema, osc_raw.fillna(method='bfill'), length=smooth_factor)
        
        # Calculate signal line
        self.sig = self.I(pta.ema, self.osc, length=max(2, self.smooth_len))
        
        # Track previous values for crossover detection
        self.osc_prev = None
        self.sig_prev = None

    def next(self):
        # Get current values
        osc_curr = self.osc[-1]
        sig_curr = self.sig[-1]
        
        if np.isnan(osc_curr) or np.isnan(sig_curr):
            return
        
        # Initialize on first valid bar
        if self.osc_prev is None:
            self.osc_prev = osc_curr
            self.sig_prev = sig_curr
            return
        
        # Detect crossovers manually
        cross_up_0 = self.osc_prev <= 0 and osc_curr > 0
        cross_dn_0 = self.osc_prev >= 0 and osc_curr < 0
        cross_up_L2 = self.osc_prev <= self.L2 and osc_curr > self.L2
        cross_dn_L2 = self.osc_prev >= -self.L2 and osc_curr < -self.L2
        
        # Trading logic: Use extremes and zero crosses for entries/exits
        if cross_dn_L2:
            # Extreme Fear - enter long (buy signal)
            if not self.position:
                self.buy()
        elif cross_up_L2:
            # Extreme Greed - exit long (sell signal)
            if self.position:
                self.position.close()
        elif cross_up_0:
            # Momentum crosses up through zero - confirm long
            if not self.position:
                self.buy()
        elif cross_dn_0:
            # Momentum crosses down through zero - exit long
            if self.position:
                self.position.close()
        
        # Update previous values
        self.osc_prev = osc_curr
        self.sig_prev = sig_curr


