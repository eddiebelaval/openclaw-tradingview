import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate the main oscillator (o_val)
        self.omni = self.I(self._calc_omni, close, high, low, volume)
        self.o_val = self.I(self._calc_o_val, close, high, low, volume)
        self.sig = self.I(lambda: pta.sma(self.o_val, length=9) if len(self.o_val) >= 9 else pd.Series(0, index=close.index))
        
    def _calc_omni(self, close, high, low, volume):
        """Calculate omni value from all 20 factors"""
        omni_vals = []
        for i in range(len(close)):
            if i < 50:
                omni_vals.append(0)
                continue
            
            # Simplified calculation - average of major indicators
            try:
                rsi = pta.rsi(close.iloc[:i+1], length=14)
                macd = pta.macd(close.iloc[:i+1], fast=12, slow=26, signal=9)
                atr = pta.atr(high.iloc[:i+1], low.iloc[:i+1], close.iloc[:i+1], length=14)
                
                if rsi is not None and not rsi.empty and macd is not None and not macd.empty and atr is not None and not atr.empty:
                    val = (rsi.iloc[-1] - 50) / 50 + (macd.iloc[-1, 0] / (close.iloc[i] + 0.0001)) + (atr.iloc[-1] / (close.iloc[i] + 0.0001))
                    omni_vals.append(val / 3.0)
                else:
                    omni_vals.append(0)
            except:
                omni_vals.append(0)
        
        return pd.Series(omni_vals, index=close.index)
    
    def _calc_o_val(self, close, high, low, volume):
        """Calculate the normalized o_val oscillator"""
        vals = []
        for i in range(len(close)):
            if i < 50:
                vals.append(0)
                continue
            
            try:
                window = close.iloc[max(0, i-50):i+1]
                mean = window.mean()
                std = window.std()
                
                if std > 0:
                    zscore = (close.iloc[i] - mean) / std
                else:
                    zscore = 0
                
                vals.append(zscore)
            except:
                vals.append(0)
        
        return pd.Series(vals, index=close.index)
    
    def next(self):
        # Buy signal: when o_val crosses above 0 (momentum turning positive)
        if len(self.o_val) >= 2:
            if crossover(self.o_val, 0):
                if not self.position:
                    self.buy()
            # Sell signal: when o_val crosses below 0 (momentum turning negative)
            elif crossover(0, self.o_val):
                if self.position:
                    self.position.close()