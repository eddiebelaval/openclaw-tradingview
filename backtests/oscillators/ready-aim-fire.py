    def _calculate_fisher(self, close_series):
        k3v_series = np.maximum(-0.999, np.minimum(0.999, self.k3v))
        logVal = np.log((1.0 + k3v_series) / (1.0 - k3v_series))
        
        f3_vals = np.full(len(close_series), np.nan)
        f3_prev = 0.0
        
        for i in range(len(close_series)):
            if np.isnan(logVal[i]):
                f3_vals[i] = f3_prev
            else:
                f3_new = 0.5 * (logVal[i] + f3_prev)
                f3_vals[i] = f3_new
                f3_prev = f3_new
        
        return pd.Series(f3_vals, index=close_series.index)

    def next(self):
        if len(self.data) < 3:
            return
        
        k1v_curr = self.k1v[-1]
        k1v_prev = self.k1v[-2]
        k2v_curr = self.k2v[-1]
        k2v_prev = self.k2v[-2]
        f3_curr = self.f3[-1]
        f3_prev = self.f3[-2]
        f3_prev2 = self.f3[-3] if len(self.f3) >= 3 else f3_prev
        
        # Update state counter (SC)
        if k2v_curr > 0:
            if k1v_curr <= k2v_curr and k1v_prev > k2v_prev and k2v_prev > 0:
                chg = -1
            else:
                chg = 0
            self.SC = min(0, self.SC) + chg
        else:
            if k1v_curr >= k2v_curr and k1v_prev < k2v_prev and k2v_prev <= 0:
                chg = 1
            else:
                chg = 0
            self.SC = max(0, self.SC) + chg
        
        # FIRE signals (Fisher inflection points)
        sign_curr = np.sign(f3_curr - f3_prev) if not np.isnan(f3_curr) and not np.isnan(f3_prev) else 0
        sign_prev = np.sign(f3_prev - f3_prev2) if not np.isnan(f3_prev) and not np.isnan(f3_prev2) else 0
        
        majorBuy = sign_curr > sign_prev and not np.isnan(f3_curr)
        majorSell = sign_curr < sign_prev and not np.isnan(f3_curr)
        
        # Trading logic based on FIRE signals and state
        if majorBuy and self.SC > 0:
            if not self.position:
                self.buy()
        elif majorSell and self.SC < 0:
            if self.position:
                self.position.close()
        
        # Additional exits on opposite signal
        if majorSell and self.position:
            self.position.close()
        elif majorBuy and not self.position and self.SC > 0:
            self.buy()


