        rawK1 = self.I(pta.stoch, high, low, close, k=5, d=3, smooth_k=3)
        k1ema = self.I(pta.ema, rawK1, length=3)
        self.k1v = self.I(lambda: np.maximum(-100.0, np.minimum(100.0, k1ema - 50.0)) / 50.01)
        
        rawK2 = self.I(pta.stoch, high, low, close, k=8, d=5, smooth_k=5)
        k2ema = self.I(pta.ema, rawK2, length=5)
        self.k2v = self.I(lambda: np.maximum(-100.0, np.minimum(100.0, k2ema - 50.0)) / 50.01)
        
        rawK3 = self.I(pta.stoch, high, low, close, k=17, d=5, smooth_k=5)
        k3ema = self.I(pta.ema, rawK3, length=5)
        self.k3v = self.I(lambda: np.maximum(-100.0, np.minimum(100.0, k3ema - 50.0)) / 50.01)
        
        # TEMA trend filter
        ema1 = self.I(pta.ema, close, length=self.proLength)
        ema2 = self.I(pta.ema, ema1, length=self.proLength)
        ema3 = self.I(pta.ema, ema2, length=self.proLength)
        self.tavg = self.I(lambda: 3.0 * ema1 - 3.0 * ema2 + ema3)
        
