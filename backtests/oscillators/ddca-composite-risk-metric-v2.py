import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI for Fear & Greed proxy
        self.rsi_14 = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        self.rsi_30 = self.I(lambda: pta.rsi(close, length=30) or pd.Series(50, index=close.index))
        
        # Calculate SMAs for price strength
        self.sma_50 = self.I(lambda: pta.sma(close, length=50) or pd.Series(close.iloc[0], index=close.index))
        self.sma_200 = self.I(lambda: pta.sma(close, length=200) or pd.Series(close.iloc[0], index=close.index))
        self.sma_365 = self.I(lambda: pta.sma(close, length=365) or pd.Series(close.iloc[0], index=close.index))
        
        # Calculate volatility (20-day realized volatility)
        self.returns = self.I(lambda: (close / close.shift(1) - 1.0).fillna(0))
        self.vol_20 = self.I(lambda: self.returns.rolling(20).std() * np.sqrt(365) * 100)
        
        # Calculate momentum indicators
        self.ma_111 = self.I(lambda: pta.sma(close, length=111) or pd.Series(close.iloc[0], index=close.index))
        self.ma_350 = self.I(lambda: pta.sma(close, length=350) or pd.Series(close.iloc[0], index=close.index))
        
        # Simple composite risk score based on available indicators
        self.composite = self.I(self._calculate_composite_risk, close, high, low)
        
    def _calculate_composite_risk(self, close, high, low):
        """Calculate simplified composite risk score 0-1"""
        result = pd.Series(0.5, index=close.index)
        
        if len(close) < 50:
            return result
            
        # Component 1: Momentum (RSI blend, 40%)
        rsi_14 = pta.rsi(close, length=14)
        rsi_30 = pta.rsi(close, length=30)
        if rsi_14 is not None and rsi_30 is not None:
            momentum = (rsi_14 * 0.6 + rsi_30 * 0.4) / 100.0
        else:
            momentum = pd.Series(0.5, index=close.index)
        
        # Component 2: Volatility (30%) - inverted so high vol = fear = low score
        returns = close / close.shift(1) - 1.0
        vol_20 = returns.rolling(20).std() * np.sqrt(365) * 100
        vol_pct = vol_20.rolling(365).apply(lambda x: (x[-1] - x.min()) / (x.max() - x.min() + 0.001) if len(x) > 0 else 0.5, raw=False)
        vol_score = 1.0 - vol_pct.fillna(0.5)
        
        # Component 3: Price Strength (30%)
        sma_50 = pta.sma(close, length=50)
        sma_200 = pta.sma(close, length=200)
        
        above_50 = (close > sma_50).astype(float)
        above_200 = (close > sma_200).astype(float)
        
        if sma_50 is not None:
            margin_50 = (close / sma_50 - 0.85) / 0.3
            margin_50 = margin_50.clip(0, 1)
        else:
            margin_50 = pd.Series(0.5, index=close.index)
            
        strength = above_50 * 0.3 + above_200 * 0.3 + margin_50 * 0.4
        
        # Composite: 40% momentum + 30% volatility + 30% strength
        composite = momentum * 0.4 + vol_score * 0.3 + strength * 0.3
        
        # Smooth with SMA
        sma_7 = pta.sma(composite, length=7)
        if sma_7 is not None:
            result = sma_7.clip(0.05, 0.95)
        else:
            result = composite.clip(0.05, 0.95)
            
        return result.fillna(0.5)
    
    def next(self):
        """Trading logic based on DDCA Risk composite score"""
        composite = self.composite[-1]
        
        # ALL-IN signal: Risk < 0.25
        if len(self.data) > 1:
            prev_composite = self.composite[-2] if len(self.composite) > 1 else self.composite[-1]
            
            # BUY signals (composite crosses below thresholds)
            if crossover(prev_composite, 0.25) or (composite < 0.25 and prev_composite >= 0.25):
                if not self.position:
                    self.buy()
            elif crossover(prev_composite, 0.35) or (composite < 0.35 and prev_composite >= 0.35):
                if not self.position:
                    self.buy()
            elif crossover(prev_composite, 0.45) or (composite < 0.45 and prev_composite >= 0.45):
                if not self.position:
                    self.buy()
            
            # SELL signals (composite crosses above thresholds)
            elif crossover(0.55, composite) or (composite > 0.55 and prev_composite <= 0.55):
                if self.position:
                    self.sell()
            elif crossover(0.65, composite) or (composite > 0.65 and prev_composite <= 0.65):
                if self.position:
                    self.sell()
            elif crossover(0.75, composite) or (composite > 0.75 and prev_composite <= 0.75):
                if self.position:
                    self.sell()
            
            # HOLD zone (0.45-0.55) - no action
            # Exit early if entering sell zone
            elif composite > 0.55 and self.position:
                self.sell()


