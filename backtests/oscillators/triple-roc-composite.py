import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Fast Engine parameters
    f_l1 = 3
    f_l2 = 5
    f_l3 = 8
    f_l4 = 13
    f_sm = 3
    f_vol = 55
    f_mult = 1.6
    f_clamp = 2.5
    
    # Balanced Engine parameters
    b_l1 = 5
    b_l2 = 13
    b_l3 = 21
    b_l4 = 34
    b_sm = 5
    b_vol = 100
    b_mult = 2.0
    b_clamp = 2.5
    
    # Slow Engine parameters
    s_l1 = 8
    s_l2 = 21
    s_l3 = 34
    s_l4 = 55
    s_sm = 8
    s_vol = 144
    s_mult = 2.4
    s_clamp = 2.5
    
    # Composite parameters
    w_f = 0.35
    w_b = 0.40
    w_s = 0.25
    adapt_weights = True
    comp_sm = 3
    dead_zone = 0.10
    thresh_mult = 1.5
    thresh_lb = 100
    slope_sm = 3
    
    # Range parameters
    range_lb = 50
    eff_lb = 20
    chop_lb = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ROC for engines
        def calc_roc(src, period):
            return src.diff(period) / src.shift(period) * 100
        
        def calc_engine(l1, l2, l3, l4, sm, vol_lb, mult, clamp):
            roc1 = self.I(lambda: calc_roc(close, l1))
            roc2 = self.I(lambda: calc_roc(close, l2))
            roc3 = self.I(lambda: calc_roc(close, l3))
            roc4 = self.I(lambda: calc_roc(close, l4))
            
            raw = self.I(lambda: (roc1 + roc2 + roc3 + roc4) / 4.0 if isinstance(roc1, pd.Series) else pd.Series(0, index=close.index))
            osc = self.I(lambda: pta.ema(raw, length=sm) if isinstance(raw, pd.Series) else pd.Series(0, index=close.index))
            
            vol_raw = self.I(lambda: pta.stdev(osc, vol_lb) if isinstance(osc, pd.Series) else pd.Series(1, index=close.index))
            vol_min = self.I(lambda: pta.sma(osc.abs(), vol_lb) * 0.25 if isinstance(osc, pd.Series) else pd.Series(0.25, index=close.index))
            vol = self.I(lambda: vol_raw.fillna(1).clip(lower=vol_min.fillna(1)).clip(lower=1e-10))
            
            upper = self.I(lambda: vol * mult)
            norm_c = self.I(lambda: (osc / upper).clip(-clamp, clamp))
            
            return norm_c, osc, upper, vol
        
        # Fast engine
        self.f_norm, self.f_osc, self.f_upper, self.f_vol = calc_engine(
            self.f_l1, self.f_l2, self.f_l3, self.f_l4, self.f_sm, self.f_vol, self.f_mult, self.f_clamp)
        
        # Balanced engine
        self.b_norm, self.b_osc, self.b_upper, self.b_vol = calc_engine(
            self.b_l1, self.b_l2, self.b_l3, self.b_l4, self.b_sm, self.b_vol, self.b_mult, self.b_clamp)
        
        # Slow engine
        self.s_norm, self.s_osc, self.s_upper, self.s_vol = calc_engine(
            self.s_l1, self.s_l2, self.s_l3, self.s_l4, self.s_sm, self.s_vol, self.s_mult, self.s_clamp)
        
        # Composite calculation
        def calc_composite():
            w_sum = max(self.w_f + self.w_b + self.w_s, 1e-9)
            w_fst = self.w_f / w_sum
            w_bal = self.w_b / w_sum
            w_slw = self.w_s / w_sum
            
            f_vol_n = self.I(lambda: pta.stdev(self.f_norm, 20).fillna(1e-9).clip(lower=1e-9))
            b_vol_n = self.I(lambda: pta.stdev(self.b_norm, 20).fillna(1e-9).clip(lower=1e-9))
            s_vol_n = self.I(lambda: pta.stdev(self.s_norm, 20).fillna(1e-9).clip(lower=1e-9))
            
            inv_sum = self.I(lambda: (1.0 / f_vol_n + 1.0 / b_vol_n + 1.0 / s_vol_n).clip(lower=1e-9))
            
            a_w_fst = self.I(lambda: (1.0 / f_vol_n) / inv_sum)
            a_w_bal = self.I(lambda: (1.0 / b_vol_n) / inv_sum)
            a_w_slw = self.I(lambda: (1.0 / s_vol_n) / inv_sum)
            
            if self.adapt_weights:
                n_w_fst = self.I(lambda: ((w_fst * 0.5 + a_w_fst * 0.5) / (w_fst * 0.5 + a_w_fst * 0.5 + w_bal * 0.5 + a_w_bal * 0.5 + w_slw * 0.5 + a_w_slw * 0.5)).clip(0, 1))
                n_w_bal = self.I(lambda: ((w_bal * 0.5 + a_w_bal * 0.5) / (w_fst * 0.5 + a_w_fst * 0.5 + w_bal * 0.5 + a_w_bal * 0.5 + w_slw * 0.5 + a_w_slw * 0.5)).clip(0, 1))
                n_w_slw = self.I(lambda: ((w_slw * 0.5 + a_w_slw * 0.5) / (w_fst * 0.5 + a_w_fst * 0.5 + w_bal * 0.5 + a_w_bal * 0.5 + w_slw * 0.5 + a_w_slw * 0.5)).clip(0, 1))
            else:
                n_w_fst = pd.Series(w_fst, index=close.index)
                n_w_bal = pd.Series(w_bal, index=close.index)
                n_w_slw = pd.Series(w_slw, index=close.index)
            
            comp_raw = self.I(lambda: self.f_norm * n_w_fst + self.b_norm * n_w_bal + self.s_norm * n_w_slw)
            composite = self.I(lambda: pta.ema(comp_raw, length=self.comp_sm) if isinstance(comp_raw, pd.Series) else pd.Series(0, index=close.index))
            
            return composite
        
        self.composite = calc_composite()
        
        # Composite thresholds
        self.c_vol_raw = self.I(lambda: pta.stdev(self.composite, self.thresh_lb).fillna(1e-10))
        self.c_vol_min = self.I(lambda: pta.sma(self.composite.abs(), self.thresh_lb) * 0.25)
        self.c_vol = self.I(lambda: self.c_vol_raw.fillna(1e-10).clip(lower=self.c_vol_min.fillna(1e-10)).clip(lower=1e-10))
        self.comp_upper = self.I(lambda: self.c_vol * self.thresh_mult)
        self.comp_lower = self.I(lambda: -self.comp_upper)
        
        # Slope
        self.slope_raw = self.I(lambda: self.composite.diff(1))
        self.slope = self.I(lambda: pta.ema(self.slope_raw, length=self.slope_sm) if isinstance(self.slope_raw, pd.Series) else pd.Series(0, index=close.index))
        
        # Range position
        self.r_high = self.I(lambda: close.rolling(self.range_lb).max())
        self.r_low = self.I(lambda: close.rolling(self.range_lb).min())
        self.r_range = self.I(lambda: (self.r_high - self.r_low).clip(lower=1e-9))
        self.r_pct = self.I(lambda: ((close - self.r_low) / self.r_range).clip(0, 1))
        
        # Trend quality
        def calc_trend_quality():
            net_move = self.I(lambda: (close - close.shift(self.eff_lb)).abs())
            total_path = self.I(lambda: close.diff(1).abs().rolling(self.eff_lb).sum())
            eff_ratio = self.I(lambda: (net_move / total_path.clip(lower=1e-9)).clip(0, 1))
            
            atr_sum = self.I(lambda: pta.atr(high, low, close, length=1).fillna(0).rolling(self.chop_lb).sum())
            chop_high = self.I(lambda: high.rolling(self.chop_lb).max())
            chop_low = self.I(lambda: low.rolling(self.chop_lb).min())
            chop_range = self.I(lambda: (chop_high - chop_low).clip(lower=1e-9))
            chop_raw = self.I(lambda: (np.log(atr_sum + 1e-9) - np.log(chop_range + 1e-9)) / np.log(self.chop_lb))
            chop = self.I(lambda: chop_raw.clip(0, 1))
            
            trend_quality = self.I(lambda: (eff_ratio + (1.0 - chop)) / 2.0)
            return trend_quality
        
        self.trend_quality = calc_trend_quality()

    def next(self):
        if len(self) < self.thresh_lb:
            return
        
        # Get current values
        comp_val = self.composite[-1] if len(self.composite) > 0 else 0
        comp_upper = self.comp_upper[-1] if len(self.comp_upper) > 0 else 0
        comp_lower = self.comp_lower[-1] if len(self.comp_lower) > 0 else 0
        slope_val = self.slope[-1] if len(self.slope) > 0 else 0
        r_pct = self.r_pct[-1] if len(self.r_pct) > 0 else 0.5
        trend_qual = self.trend_quality[-1] if len(self.trend_quality) > 0 else 0.5
        
        # Trading logic based on composite
        is_neutral = abs(comp_val) < self.dead_zone
        comp_bull = comp_val > self.dead_zone
        comp_bear = comp_val < -self.dead_zone
        comp_str_bull = comp_val > comp_upper
        comp_str_bear = comp_val < comp_lower
        
        # Entry conditions
        buy_signal = (
            (comp_str_bull and slope_val > 0) or
            (crossover(self.composite, self.comp_upper) and trend_qual > 0.5) or
            (comp_bull and crossover(self.slope, 0) and r_pct > 0.5)
        )
        
        sell_signal = (
            (comp_str_bear and slope_val < 0) or
            (crossover(self.comp_lower, self.composite) and trend_qual < 0.5) or
            (comp_bear and crossover(0, self.slope) and r_pct < 0.5)
        )
        
        # Position management
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()
        
        # Exit on reversal signals
        if self.position.is_long and crossover(self.comp_lower, self.composite):
            self.sell()
        elif self.position.is_short and crossover(self.composite, self.comp_upper):
            self.buy()


