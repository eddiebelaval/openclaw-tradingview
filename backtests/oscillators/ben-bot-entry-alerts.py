        self.di_plus = self.I(lambda: pta.adx(high, low, close, length=self.dmiLength)['DMP_14'] if pta.adx(high, low, close, length=self.dmiLength) is not None else pd.Series(0, index=close.index))
        self.di_minus = self.I(lambda: pta.adx(high, low, close, length=self.dmiLength)['DMN_14'] if pta.adx(high, low, close, length=self.dmiLength) is not None else pd.Series(0, index=close.index))
        self.adx = self.I(lambda: pta.adx(high, low, close, length=self.dmiLength)['ADX_14'] if pta.adx(high, low, close, length=self.dmiLength) is not None else pd.Series(20, index=close.index))
        
        # OR High/Low tracking
        self.or_high = None
        self.or_low = None
        self.or_complete = False
        self.last_session_state = False

