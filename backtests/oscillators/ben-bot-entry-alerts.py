        if bar_index > 0:
            # Check if we're in opening range window (first 30 bars approximately)
            if bar_index % 390 == 1:  # Reset per trading day (390 bars = 1 day on 1-min)
                self.or_high = self.data.High[-1]
                self.or_low = self.data.Low[-1]
                self.or_complete = False
