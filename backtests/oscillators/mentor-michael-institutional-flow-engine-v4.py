import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    deltaLen = 20
    momentumLen = 10
    swingLen = 5
    rsiLen = 14
    rsiOB = 70
    rsiOS = 30
    useRSIFilter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLen) or pd.Series(50, index=close.index))
        
        # Calculate Delta components
        self.buy_vol = self.I(lambda: pd.Series(
            [volume.iloc[i] if close.iloc[i] > self.data.Open[i] else 0.0 for i in range(len(close))],
            index=close.index
        ))
        
        self.sell_vol = self.I(lambda: pd.Series(
            [volume.iloc[i] if close.iloc[i] < self.data.Open[i] else 0.0 for i in range(len(close))],
            index=close.index
        ))
        
        # Rolling sums for buy/sell volume
        self.buy_sum = self.I(lambda: self.buy_vol.rolling(window=self.deltaLen).sum())
        self.sell_sum = self.I(lambda: self.sell_vol.rolling(window=self.deltaLen).sum())
        
        # Calculate rolling delta
        self.bar_delta = self.I(lambda: pd.Series(
            [volume.iloc[i] if close.iloc[i] > self.data.Open[i] else (-volume.iloc[i] if close.iloc[i] < self.data.Open[i] else 0.0) for i in range(len(close))],
            index=close.index
        ))
        
        self.rolling_delta = self.I(lambda: self.bar_delta.rolling(window=self.deltaLen).sum())
        
        self.delta_momentum = self.I(lambda: pd.Series(
            [self.rolling_delta.iloc[i] - (self.rolling_delta.iloc[i - self.momentumLen] if i >= self.momentumLen else self.rolling_delta.iloc[0]) 
             for i in range(len(self.rolling_delta))],
            index=self.rolling_delta.index
        ))
        
        # Swing highs/lows using pivots
        self.swing_high = self.I(lambda: self._calculate_swing_high(high, self.swingLen))
        self.swing_low = self.I(lambda: self._calculate_swing_low(low, self.swingLen))
        
        # BOS (Break of Structure)
        self.bull_bos = self.I(lambda: self._calculate_bull_bos(close, high))
        self.bear_bos = self.I(lambda: self._calculate_bear_bos(close, low))
        
        # FVG (Fair Value Gap)
        self.bull_fvg = self.I(lambda: self._calculate_bull_fvg(low, high))
        self.bear_fvg = self.I(lambda: self._calculate_bear_fvg(high, low))
        
        # Sweep detection
        self.sweep_low = self.I(lambda: self._calculate_sweep_low(low, close, self.data.Open, high))
        self.sweep_high = self.I(lambda: self._calculate_sweep_high(high, close, self.data.Open, low))
        
        # Institutional Score
        self.score = self.I(lambda: self._calculate_score())

    def _calculate_swing_high(self, high, length):
        result = pd.Series(np.nan, index=high.index)
        for i in range(length, len(high) - length):
            if high.iloc[i] > high.iloc[i-length:i].max() and high.iloc[i] > high.iloc[i+1:i+length+1].max():
                result.iloc[i] = high.iloc[i]
        return result

    def _calculate_swing_low(self, low, length):
        result = pd.Series(np.nan, index=low.index)
        for i in range(length, len(low) - length):
            if low.iloc[i] < low.iloc[i-length:i].min() and low.iloc[i] < low.iloc[i+1:i+length+1].min():
                result.iloc[i] = low.iloc[i]
        return result

    def _calculate_bull_bos(self, close, high):
        result = pd.Series(False, index=close.index)
        last_high = np.nan
        for i in range(len(close)):
            if not np.isnan(self.swing_high.iloc[i]):
                last_high = high.iloc[i - self.swingLen] if i >= self.swingLen else np.nan
            if not np.isnan(last_high) and close.iloc[i] > last_high:
                result.iloc[i] = True
        return result

    def _calculate_bear_bos(self, close, low):
        result = pd.Series(False, index=close.index)
        last_low = np.nan
        for i in range(len(close)):
            if not np.isnan(self.swing_low.iloc[i]):
                last_low = low.iloc[i - self.swingLen] if i >= self.swingLen else np.nan
            if not np.isnan(last_low) and close.iloc[i] < last_low:
                result.iloc[i] = True
        return result

    def _calculate_bull_fvg(self, low, high):
        result = pd.Series(False, index=low.index)
        for i in range(2, len(low)):
            if low.iloc[i] > high.iloc[i-2]:
                result.iloc[i] = True
        return result

    def _calculate_bear_fvg(self, high, low):
        result = pd.Series(False, index=high.index)
        for i in range(2, len(high)):
            if high.iloc[i] < low.iloc[i-2]:
                result.iloc[i] = True
        return result

    def _calculate_sweep_low(self, low, close, open_prices, high):
        result = pd.Series(False, index=low.index)
        for i in range(self.swingLen, len(low)):
            prev_low_min = low.iloc[max(0, i-self.swingLen):i].min()
            if low.iloc[i] < prev_low_min and close.iloc[i] > open_prices[i]:
                result.iloc[i] = True
        return result

    def _calculate_sweep_high(self, high, close, open_prices, low):
        result = pd.Series(False, index=high.index)
        for i in range(self.swingLen, len(high)):
            prev_high_max = high.iloc[max(0, i-self.swingLen):i].max()
            if high.iloc[i] > prev_high_max and close.iloc[i] < open_prices[i]:
                result.iloc[i] = True
        return result

    def _calculate_score(self):
        score = pd.Series(0.0, index=pd.Series(self.data.Close).index)
        
        for i in range(len(score)):
            s = 0.0
            
            # Rolling delta contribution
            if self.rolling_delta.iloc[i] > 0:
                s += 20
            
            # Delta momentum contribution
            if self.delta_momentum.iloc[i] > 0:
                s += 15
            
            # Aggression (buy/sell ratio)
            if self.sell_sum.iloc[i] != 0:
                aggression = self.buy_sum.iloc[i] / self.sell_sum.iloc[i]
                if aggression > 1:
                    s += 15
            
            # Bull BOS
            if self.bull_bos.iloc[i]:
                s += 20
            
            # Sweep low
            if self.sweep_low.iloc[i]:
                s += 10
            
            # Bull FVG
            if self.bull_fvg.iloc[i]:
                s += 10
            
            # RSI Filter
            if self.useRSIFilter:
                if self.rsi.iloc[i] > 50:
                    s += 10
                if self.rsi.iloc[i] > self.rsiOB:
                    s -= 5
            
            score.iloc[i] = max(min(s, 100), 0)
        
        return score

    def next(self):
        if len(self.data) < self.swingLen + self.momentumLen:
            return
        
        current_score = self.score[-1]
        current_rsi = self.rsi[-1]
        
        # Buy signal: High confidence bullish flow
        if current_score >= 85:
            if not self.position:
                self.buy()
        
        # Sell signal: High confidence bearish flow
        elif current_score <= 15:
            if self.position:
                self.sell()
        
        # Exit on reversal
        if self.position:
            if current_score < 50 or current_rsi < 30:
                self.sell()