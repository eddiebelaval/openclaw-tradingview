class TvStrategy(Strategy):
    rsiLen = 20
    maLen = 10
    maType = "RMA"
    atrLen = 14
    factor = 4.0
    baseMode = "RSI MA"
    trixLen = 9
    trixSlopeLen = 1
    flatTh = 0.0
    ribbonFast = 21
