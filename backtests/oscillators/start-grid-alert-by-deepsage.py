import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adx_length = 14
    adx_smoothing = 14
    chop_length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_length))
        self.adx = adx_result
        
        # Calculate CHOP
        def calculate_chop():
            hh = high.rolling(window=self.chop_length).max()
            ll = low.rolling(window=self.chop_length).min()
            
            hh_highest = hh.rolling(window=self.chop_length).max()
            ll_lowest = ll.rolling(window=self.chop_length).min()
            
            denominator = hh_highest - ll_lowest
            denominator = denominator.replace(0, np.nan)
            
            chop = 100 * ((hh - ll) / denominator)
            return chop
        
        self.chop = self.I(calculate_chop)

    def next(self):
        if len(self.data) < self.chop_length + 1:
            return
        
        adx_val = self.adx[-1]
        chop_val = self.chop[-1]
        
        if pd.isna(adx_val) or pd.isna(chop_val):
            return
        
        # Start Grid condition: ADX < 18 and CHOP > 60
        if (adx_val < 18) and (chop_val > 60):
            if not self.position:
                self.buy()
        # Exit condition: ADX >= 18 or CHOP <= 60
        elif self.position:
            if (adx_val >= 18) or (chop_val <= 60):
                self.position.close()