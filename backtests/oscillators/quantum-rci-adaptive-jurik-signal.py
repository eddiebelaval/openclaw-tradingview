import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rci_len = 10
    sig_len = 7
    sig_pha = 50
    sig_pow = 2
    er_len = 10
    min_bb = 10
    max_bb = 30
    bb_mult = 2.0
    adx_len = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RCI calculation
        self.rci = self.I(self._calc_rci, close, self.rci_len)
        
        # JMA Signal Line
        self.sig = self.I(self._calc_jma, self.rci, self.sig_len, self.sig_pha, self.sig_pow)
        
        # ADX for strength
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_len))
        self.adx = self.I(lambda: adx_result['ADX_' + str(self.adx_len)] if adx_result is not None and ('ADX_' + str(self.adx_len)) in adx_result else pd.Series(20, index=close.index))
        
        # Efficiency Ratio for adaptive BB
        self.er = self.I(self._calc_er, close, self.er_len)
        
        # Adaptive BB Length
        self.dyn_bb_len = self.I(self._calc_dyn_bb_len, self.er, self.min_bb, self.max_bb)
        
        # Adaptive Bollinger Bands on RCI
        self.bb_basis = self.I(self._calc_bb_basis, self.rci, self.dyn_bb_len)
        self.bb_upper = self.I(self._calc_bb_upper, self.rci, self.dyn_bb_len, self.bb_mult)
        self.bb_lower = self.I(self._calc_bb_lower, self.rci, self.dyn_bb_len, self.bb_mult)

    def _calc_rci(self, close, length):
        rci_vals = []
        for i in range(len(close)):
            if i < length - 1:
                rci_vals.append(0)
            else:
                window = close.iloc[i-length+1:i+1]
                ranked = pd.Series(range(1, length + 1), index=window.index)
                rank_close = ranked[window.argsort().argsort()].iloc[-1]
                rci = (rank_close - (length + 1) / 2) / ((length ** 2 - 1) / 12) ** 0.5 * 100
                rci_vals.append(rci)
        return pd.Series(rci_vals, index=close.index)

    def _calc_jma(self, src, length, phase, power):
        phase_ratio = 0.5 if phase < -100 else 2.5 if phase > 100 else phase / 100 + 1.5
        beta = 0.45 * (length - 1) / (0.45 * (length - 1) + 2)
        alpha = beta ** power
        
        e0 = pd.Series(0.0, index=src.index)
        e1 = pd.Series(0.0, index=src.index)
        e2 = pd.Series(0.0, index=src.index)
        jma_val = pd.Series(0.0, index=src.index)
        
        for i in range(len(src)):
            e0_prev = e0.iloc[i-1] if i > 0 else 0
            e1_prev = e1.iloc[i-1] if i > 0 else 0
            e2_prev = e2.iloc[i-1] if i > 0 else 0
            jma_prev = jma_val.iloc[i-1] if i > 0 else 0
            
            e0.iloc[i] = (1 - alpha) * src.iloc[i] + alpha * e0_prev
            e1.iloc[i] = (src.iloc[i] - e0.iloc[i]) * (1 - beta) + beta * e1_prev
            e2.iloc[i] = (e0.iloc[i] + phase_ratio * e1.iloc[i] - jma_prev) * ((1 - alpha) ** 2) + (alpha ** 2) * e2_prev
            jma_val.iloc[i] = e2.iloc[i] + jma_prev
        
        return jma_val

    def _calc_er(self, close, length):
        er_vals = []
        for i in range(len(close)):
            if i < length:
                er_vals.append(0)
            else:
                direction = abs(close.iloc[i] - close.iloc[i-length])
                volatility = sum(abs(close.iloc[j] - close.iloc[j-1]) for j in range(i-length+1, i+1))
                er = direction / volatility if volatility != 0 else 0
                er_vals.append(er)
        return pd.Series(er_vals, index=close.index)

    def _calc_dyn_bb_len(self, er, min_bb, max_bb):
        bb_lens = []
        for i in range(len(er)):
            dyn_len = min_bb + (max_bb - min_bb) * (1.0 - er.iloc[i])
            dyn_len = max(1, round(dyn_len))
            bb_lens.append(dyn_len)
        return pd.Series(bb_lens, index=er.index)

    def _calc_bb_basis(self, rci, dyn_bb_len):
        basis = []
        for i in range(len(rci)):
            if i < 1:
                basis.append(rci.iloc[i])
            else:
                length = int(dyn_bb_len.iloc[i]) if hasattr(dyn_bb_len.iloc[i], '__int__') else dyn_bb_len.iloc[i]
                length = max(1, min(length, i + 1))
                window = rci.iloc[max(0, i-length+1):i+1]
                basis.append(window.mean())
        return pd.Series(basis, index=rci.index)

    def _calc_bb_upper(self, rci, dyn_bb_len, bb_mult):
        upper = []
        for i in range(len(rci)):
            if i < 1:
                upper.append(rci.iloc[i])
            else:
                length = int(dyn_bb_len.iloc[i]) if hasattr(dyn_bb_len.iloc[i], '__int__') else dyn_bb_len.iloc[i]
                length = max(1, min(length, i + 1))
                window = rci.iloc[max(0, i-length+1):i+1]
                basis = window.mean()
                dev = window.std() * bb_mult
                upper.append(basis + dev)
        return pd.Series(upper, index=rci.index)

    def _calc_bb_lower(self, rci, dyn_bb_len, bb_mult):
        lower = []
        for i in range(len(rci)):
            if i < 1:
                lower.append(rci.iloc[i])
            else:
                length = int(dyn_bb_len.iloc[i]) if hasattr(dyn_bb_len.iloc[i], '__int__') else dyn_bb_len.iloc[i]
                length = max(1, min(length, i + 1))
                window = rci.iloc[max(0, i-length+1):i+1]
                basis = window.mean()
                dev = window.std() * bb_mult
                lower.append(basis - dev)
        return pd.Series(lower, index=rci.index)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Crossover signals
        if crossover(self.rci, self.sig):
            if not self.position:
                self.buy()
        elif crossover(self.sig, self.rci):
            if self.position:
                self.sell()


