    def _calculate_toxicity(self):
        """Calculate order flow toxicity index"""
        lookback = min(self.toxicity_lookback, len(self.data))
        
        aggressive_buy = 0.0
        aggressive_sell = 0.0
        passive_flow = 0.0
        
        for i in range(0, lookback, 2):
            idx = -(i + 1)
            if len(self.data) < abs(idx):
                continue
            
            high = self.data.High[idx]
            low = self.data.Low[idx]
            close = self.data.Close[idx]
            open_price = self.data.Open[idx]
            vol = self.data.Volume[idx]
            
            range_val = high - low
            if range_val > 0:
                candle_pos = (close - low) / range_val
            else:
                candle_pos = 0.5
            
            if close > open_price and candle_pos > 0.75:
                aggressive_buy += vol
            elif close < open_price and candle_pos < 0.25:
                aggressive_sell += vol
            else:
                passive_flow += vol
        
        total_flow = aggressive_buy + aggressive_sell + passive_flow
        tox_buy = aggressive_buy / total_flow if total_flow > 0 else 0.0
        tox_sell = aggressive_sell / total_flow if total_flow > 0 else 0.0
        
        toxic_buy_flow = tox_buy > self.toxicity_threshold
        toxic_sell_flow = tox_sell > self.toxicity_threshold
        
        return toxic_buy_flow, toxic_sell_flow
    
    def _calculate_absorption(self, open_price, close, high, low, vol):
        """Calculate absorption coefficient"""
        body = abs(close - open_price)
        total_range = high - low
        body_ratio = body / total_range if total_range > 0 else 0.0
        
        vol_avg = self.vol_sma_20[-1] if self.vol_sma_20[-1] > 0 else 1.0
        vol_ratio = vol / vol_avg
        
        absorption = vol_ratio * (1.0 - body_ratio)
        dir_absorption = absorption if close > open_price else -absorption
        
        return absorption, dir_absorption
    
    def _calculate_volume_profile(self, close):
        """Calculate volume profile metrics"""
        hlc3 = (self.data.High[-1] + self.data.Low[-1] + close) / 3.0
        poc = hlc3
        poc_distance = (close - poc) / poc * 100 if poc > 0 else 0.0
        near_poc = abs(poc_distance) < self.poc_sensitivity * 100
        in_value_area = True  # Simplified
        
        return poc_distance, near_poc, in_value_area
    
    def _calculate_microstructure(self, high, low, close, vol):
        """Calculate market microstructure metrics"""
        spread = (high - low) / close * 100 if close > 0 else 0.0
        
        depth_proxy = vol / spread if spread > 0 else 0.0
        
        mm_providing = spread < 0.5
        mm_withdrawing = spread > 1.0
        
        return spread, depth_proxy, mm_providing, mm_withdrawing
    
    def _calculate_divergence(self):
        """Calculate smart money divergence"""
        if len(self.rsi) < 10 or self.rsi[-1] is None:
            return False, False
        
        lookback_idx = min(10, len(self.rsi) - 1)
        
        price_higher = self.data.Close[-1] > self.data.Close[-(lookback_idx + 1)]
        price_lower = self.data.Close[-1] < self.data.Close[-(lookback_idx + 1)]
        
        rsi_lower = self.rsi[-1] < self.rsi[-(lookback_idx + 1)]
        rsi_higher = self.rsi[-1] > self.rsi[-(lookback_idx + 1)]
        
        bull_div = price_lower and rsi_higher
        bear_div = price_higher and rsi_lower
        
        return bull_div, bear_div
    
    def _calculate_liquidity_void(self, vol):
        """Calculate liquidity void detection"""
        if self.vol_sma[-1] is None or self.vol_sma[-1] == 0:
            return False, False
        
        vol_avg = self.vol_sma[-1]
        low_volume = vol < vol_avg * 0.7
        
        # Simplified narrow range check
        range_val = self.data.High[-1] - self.data.Low[-1]
        range_avg = 0.01 * self.data.Close[-1]  # Simplified
        narrow_range = range_val < range_avg * 0.5
        
        liq_void = low_volume and narrow_range
        sig_void = liq_void
        
        return liq_void, sig_void
    
    def _calculate_tape_reading(self, open_price, close, high, low, vol):
        """Calculate tape reading metrics"""
        range_val = high - low
        if range_val > 0:
            candle_pos = (close - low) / range_val
        else:
            candle_pos = 0.5
        
        vol_sma = self.vol_sma_20[-1] if self.vol_sma_20[-1] > 0 else 1.0
        
        aggressive_buy = candle_pos > 0.8 and close > open_price and vol > vol_sma
        aggressive_sell = candle_pos < 0.2 and close < open_price and vol > vol_sma
        
        return aggressive_buy, aggressive_sell, candle_pos
    
    def _calculate_confidence(self, strong_absorption, toxic_buy, toxic_sell, 
                             deep_market, bull_div, bear_div, near_poc):
        """Calculate confidence score"""
        confidence = 0.0
        
        if strong_absorption:
            confidence += 25.0
        if toxic_buy or toxic_sell:
            confidence += 20.0
        if deep_market:
            confidence += 15.0
        if bull_div or bear_div:
            confidence += 20.0
        if near_poc:
            confidence += 10.0
        
        return confidence


