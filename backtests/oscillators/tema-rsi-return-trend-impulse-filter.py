import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    temaLen = 9
    normLen = 100
    upperBand = 90
    lowerBand = 10
    slopeLen = 3
    atrLen = 14
    impMult = 1.2
    labelOffset = 0.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # TEMA calculation
        ema1 = self.I(pta.ema, close, length=self.temaLen)
        ema2 = self.I(pta.ema, ema1, length=self.temaLen)
        ema3 = self.I(pta.ema, ema2, length=self.temaLen)
        self.tema = self.I(lambda: 3 * (ema1 - ema2) + ema3)
        
        # TEMA Slope
        self.tema_slope = self.I(lambda: self.tema - np.roll(self.tema, self.slopeLen))
        
        # ATR and impulse filter
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.candle_range = self.I(lambda: high - low)
        self.has_impulse = self.I(lambda: self.candle_range >= self.atr * self.impMult)
        
        # Normalize TEMA to RSI scale
        self.tema_high = self.I(lambda: pd.Series(self.tema).rolling(self.normLen).max())
        self.tema_low = self.I(lambda: pd.Series(self.tema).rolling(self.normLen).min())
        
        def calc_tema_osc():
            diff = self.tema_high - self.tema_low
            result = np.where(
                diff != 0,
                100 * (self.tema - self.tema_low) / diff,
                50
            )
            return pd.Series(result, index=close.index)
        
        self.tema_osc = self.I(calc_tema_osc)
        
        # State tracking
        self.buy_armed = False
        self.sell_armed = False

    def next(self):
        if len(self.data) < max(self.temaLen * 3, self.normLen, self.slopeLen, self.atrLen) + 1:
            return
        
        # Check for None values in critical indicators
        if (self.tema[-1] is None or self.tema_slope[-1] is None or 
            self.atr[-1] is None or self.candle_range[-1] is None or 
            self.has_impulse[-1] is None or self.tema_osc[-1] is None):
            return
        
        # Trend conditions
        up_trend = self.data.Close[-1] > self.tema[-1] and self.tema_slope[-1] > 0
        down_trend = self.data.Close[-1] < self.tema[-1] and self.tema_slope[-1] < 0
        
        # Arm buy/sell signals
        if self.tema_osc[-1] < self.lowerBand:
            self.buy_armed = True
        
        if self.tema_osc[-1] > self.upperBand:
            self.sell_armed = True
        
        # Final signals
        buy_signal = (self.buy_armed and 
                      self.tema_osc[-1] > self.lowerBand and 
                      up_trend and 
                      self.has_impulse[-1])
        
        sell_signal = (self.sell_armed and 
                       self.tema_osc[-1] < self.upperBand and 
                       down_trend and 
                       self.has_impulse[-1])
        
        # Execute trades
        if buy_signal:
            if not self.position:
                self.buy()
            self.buy_armed = False
        
        if sell_signal:
            if self.position:
                self.sell()
            self.sell_armed = False


