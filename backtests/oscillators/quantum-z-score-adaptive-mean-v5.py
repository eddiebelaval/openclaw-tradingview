import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 14
    sens = 0.5
    sig_len = 9
    sig_sens = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate adaptive mean (AMA)
        def calc_ama(src, length, sensitivity):
            result = pd.Series(index=src.index, dtype=float)
            ama_val = src.iloc[0]
            
            for i in range(len(src)):
                if i < 10:
                    result.iloc[i] = src.iloc[i]
                    ama_val = src.iloc[i]
                else:
                    change = abs(src.iloc[i] - src.iloc[i-10])
                    volatility = abs(src.iloc[i] - src.iloc[i-10]).rolling(window=10).mean()
                    if volatility.iloc[i] == 0:
                        volatility_val = 0.0001
                    else:
                        volatility_val = volatility.iloc[i]
                    
                    er = change / (volatility_val * 10)
                    alpha = (er * (2.0 / (length + 1))) ** sensitivity
                    ama_val = alpha * src.iloc[i] + (1 - alpha) * ama_val
                    result.iloc[i] = ama_val
            
            return result
        
        # Calculate mean and standard deviation
        self.mean_val = self.I(lambda: calc_ama(close, self.len, self.sens))
        self.stdev_val = self.I(pta.stdev, close, length=self.len)
        
        # Calculate Z-Score
        def calc_zscore(src, mean, stdev):
            return (src - mean) / np.maximum(stdev, 0.0001)
        
        self.z_score = self.I(lambda: calc_zscore(close, self.mean_val[-len(close):], self.stdev_val[-len(close):]))
        
        # Calculate Z-Score signal (AMA of Z-Score)
        self.z_signal = self.I(lambda: calc_ama(pd.Series(self.z_score[-len(close):]), self.sig_len, self.sig_sens))
        
        # Pivot points for divergence
        lb = 5
        
        def calc_pivot_low(z_src, lback):
            result = pd.Series(index=z_src.index, dtype=float)
            for i in range(lback, len(z_src) - lback):
                is_pivot = True
                for j in range(1, lback + 1):
                    if z_src.iloc[i] >= z_src.iloc[i-j] or z_src.iloc[i] >= z_src.iloc[i+j]:
                        is_pivot = False
                        break
                result.iloc[i] = z_src.iloc[i] if is_pivot else np.nan
            return result
        
        def calc_pivot_high(z_src, lback):
            result = pd.Series(index=z_src.index, dtype=float)
            for i in range(lback, len(z_src) - lback):
                is_pivot = True
