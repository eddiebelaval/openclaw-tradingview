import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 14
    adx_len = 14
    efficiency_lookback = 10
    donchian_len = 20
    bb_len = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # ADX and DMI
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_len))
        
        # Efficiency calculation (Kaufman Ratio)
        def calc_efficiency():
            result = pd.Series(index=close.index, dtype='float64')
            for i in range(self.efficiency_lookback, len(close)):
                change_abs = np.abs(close.iloc[i] - close.iloc[i-1])
                sum_change = np.sum(np.abs(close.iloc[i-self.efficiency_lookback:i+1].diff()))
                net_change = np.abs(close.iloc[i] - close.iloc[i-self.efficiency_lookback])
                result.iloc[i] = net_change / sum_change if sum_change != 0 else 0
            return result
        
        self.efficiency = self.I(calc_efficiency)

        # Donchian Channels (Trend Mode)
        def calc_donchian_upper():
            return high.rolling(window=self.donchian_len).max()
        
        def calc_donchian_lower():
            return low.rolling(window=self.donchian_len).min()
        
        self.upper_ch = self.I(calc_donchian_upper)
        self.lower_ch = self.I(calc_donchian_lower)

        # Bollinger Bands (Range Mode)
        bb_result = self.I(lambda: pta.bbands(close, length=self.bb_len, std=2))
        
        def get_bb_upper():
            if bb_result is not None and not bb_result.empty:
                return bb_result.iloc[:, 2]
            return pd.Series(close.mean(), index=close.index)
        
        def get_bb_lower():
            if bb_result is not None and not bb_result.empty:
                return bb_result.iloc[:, 0]
            return pd.Series(close.mean(), index=close.index)
        
        self.bb_upper = self.I(get_bb_upper)
        self.bb_lower = self.I(get_bb_lower)
        
        self.adx = adx_result

    def next(self):
        # Extract ADX value
        if len(self.adx) == 0 or self.adx[-1] is None:
            return
        
        adx_val = self.adx[-1]
        eff_val = self.efficiency[-1] if len(self.efficiency) > 0 else 0

        # Regime classification
        is_trending = adx_val > 25 and eff_val > 0.3
        is_ranging = adx_val < 20 and eff_val < 0.2

        # Trend Signals (Breakouts)
        if is_trending:
            if len(self.data.Close) > 1 and len(self.upper_ch) > 1:
                if crossover(self.data.Close, self.upper_ch):
                    if not self.position:
                        self.buy()
            
            if len(self.data.Close) > 1 and len(self.lower_ch) > 1:
                if crossover(self.lower_ch, self.data.Close):
                    if self.position:
                        self.position.close()

        # Range Signals (Fades)
        if is_ranging:
            if len(self.data.Close) > 0 and len(self.bb_lower) > 0:
                if crossover(self.data.Close, self.bb_lower):
                    if not self.position:
                        self.buy()
            
            if len(self.data.Close) > 0 and len(self.bb_upper) > 0:
                if crossover(self.bb_upper, self.data.Close):
                    if self.position:
                        self.position.close()


