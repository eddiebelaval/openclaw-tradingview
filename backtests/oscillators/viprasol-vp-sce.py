import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Signal Settings
    fast_ma_period = 9
    slow_ma_period = 21
    bar_close_confirm = True
    
    # Confluence Filter
    use_confluence_filter = True
    min_confluence_score = 4
    
    # Risk Management
    atr_sl_multiplier = 1.5
    atr_period = 14
    target_count = 5
    trail_sl_to_breakeven = True
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core Indicators
        self.fast_ma = self.I(pta.ema, close, length=self.fast_ma_period)
        self.slow_ma = self.I(pta.ema, close, length=self.slow_ma_period)
        self.vwap = self.I(self._calc_vwap, high, low, close, volume)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # MACD
        macd_result = self.I(pta.macd, close, fast=12, slow=26, signal=9)
        self.macd_main = self.I(lambda: macd_result['MACD_12_26_9'] if macd_result is not None else pd.Series(0, index=close.index))
        self.macd_signal = self.I(lambda: macd_result['MACDs_12_26_9'] if macd_result is not None else pd.Series(0, index=close.index))
        
        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=14)
        self.adx = self.I(lambda: adx_result['ADX_14'] if adx_result is not None else pd.Series(25, index=close.index))
        
        # Volume Average
        self.volume_avg = self.I(pta.sma, volume, length=20)
        
        # Trade state variables
        self.active_direction = 0
        self.entry_price = 0.0
        self.stop_loss_price = 0.0
        self.target_prices = [0.0] * 5
        self.targets_reached = [False] * 5
        self.sl_moved_to_breakeven = False
        
    def _calc_vwap(self, high, low, close, volume):
        hlc3 = (high + low + close) / 3
        vwap = pta.vwap(high, low, close, volume=volume)
        return vwap if vwap is not None else hlc3
    
    def _calc_confluence_scores(self):
        close_val = self.data.Close[-1]
        vwap_val = self.vwap[-1]
        rsi_val = self.rsi[-1]
        macd_main_val = self.macd_main[-1]
        macd_signal_val = self.macd_signal[-1]
        fast_ma_val = self.fast_ma[-1]
        slow_ma_val = self.slow_ma[-1]
        adx_val = self.adx[-1]
        volume_val = self.data.Volume[-1]
        volume_avg_val = self.volume_avg[-1]
        open_val = self.data.Open[-1]
        
        bullish_score = 0
        bullish_score += 1 if close_val > vwap_val else 0
        bullish_score += 1 if rsi_val > 50 else 0
        bullish_score += 1 if macd_main_val > macd_signal_val else 0
        bullish_score += 1 if fast_ma_val > slow_ma_val else 0
        bullish_score += 1 if adx_val > 25 and close_val > fast_ma_val else 0
        bullish_score += 1 if volume_val > volume_avg_val and close_val > open_val else 0
        bullish_score += 1 if rsi_val > 50 else 0
        
        bearish_score = 0
        bearish_score += 1 if close_val < vwap_val else 0
        bearish_score += 1 if rsi_val < 50 else 0
        bearish_score += 1 if macd_main_val < macd_signal_val else 0
        bearish_score += 1 if fast_ma_val < slow_ma_val else 0
        bearish_score += 1 if adx_val > 25 and close_val < fast_ma_val else 0
        bearish_score += 1 if volume_val > volume_avg_val and close_val < open_val else 0
        bearish_score += 1 if rsi_val < 50 else 0
        
        return bullish_score, bearish_score
    
    def next(self):
        if len(self.data) < max(self.fast_ma_period, self.slow_ma_period, self.atr_period) + 1:
            return
        
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        fast_ma_val = self.fast_ma[-1]
        slow_ma_val = self.slow_ma[-1]
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.0
        
        # Check for crossovers
        raw_bullish_cross = crossover(self.fast_ma, self.slow_ma)
        raw_bearish_cross = crossover(self.slow_ma, self.fast_ma)
        
        confirmed_bull_cross = raw_bullish_cross
        confirmed_bear_cross = raw_bearish_cross
        
        # Confluence check
        bullish_score, bearish_score = self._calc_confluence_scores()
        confluence_bull_pass = bullish_score >= self.min_confluence_score if self.use_confluence_filter else True
        confluence_bear_pass = bearish_score >= self.min_confluence_score if self.use_confluence_filter else True
        
        # Entry signals
        entry_long_signal = confirmed_bull_cross and self.active_direction <= 0 and confluence_bull_pass
        entry_short_signal = confirmed_bear_cross and self.active_direction >= 0 and confluence_bear_pass
        
        # Process new entries
        if entry_long_signal or entry_short_signal:
            if entry_long_signal:
                self.active_direction = 1
                self.entry_price = close_val
                risk_amount = atr_val * self.atr_sl_multiplier
                self.stop_loss_price = self.entry_price - risk_amount
                for i in range(self.target_count):
                    self.target_prices[i] = self.entry_price + (risk_amount * (i + 1))
            else:
                self.active_direction = -1
                self.entry_price = close_val
                risk_amount = atr_val * self.atr_sl_multiplier
                self.stop_loss_price = self.entry_price + risk_amount
                for i in range(self.target_count):
                    self.target_prices[i] = self.entry_price - (risk_amount * (i + 1))
            
            self.targets_reached = [False] * 5
            self.sl_moved_to_breakeven = False
            self.buy()
        
        # Update target hits
        if self.active_direction == 1:
            for i in range(self.target_count):
                if high_val >= self.target_prices[i]:
                    self.targets_reached[i] = True
        elif self.active_direction == -1:
            for i in range(self.target_count):
                if low_val <= self.target_prices[i]:
                    self.targets_reached[i] = True
        
        # Trail SL to breakeven at TP1
        if self.trail_sl_to_breakeven and self.targets_reached[0] and not self.sl_moved_to_breakeven:
            self.stop_loss_price = self.entry_price
            self.sl_moved_to_breakeven = True
        
        # Exit logic
        if self.active_direction == 1:
            if low_val <= self.stop_loss_price or high_val >= self.target_prices[self.target_count - 1]:
                self.sell()
                self.active_direction = 0
        elif self.active_direction == -1:
            if high_val >= self.stop_loss_price or low_val <= self.target_prices[self.target_count - 1]:
                self.sell()
                self.active_direction = 0


