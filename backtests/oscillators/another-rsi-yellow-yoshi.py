import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    maType = "EMA"
    maLength = 50
    shortLen = 5
    longLen = 13
    shortSmooth = 2
    longSmooth = 3
    threshold = 1.0
    atr_length = 7
    stochLen = 10
    stochSmth = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate MA based on type
        if self.maType == "SMA":
            self.ma_val = self.I(pta.sma, close, length=self.maLength)
        elif self.maType == "EMA":
            self.ma_val = self.I(pta.ema, close, length=self.maLength)
        elif self.maType == "WMA":
            self.ma_val = self.I(pta.wma, close, length=self.maLength)
        elif self.maType == "HMA":
            self.ma_val = self.I(pta.hma, close, length=self.maLength)
        elif self.maType == "DEMA":
            ema1 = self.I(pta.ema, close, length=self.maLength)
            ema2 = self.I(pta.ema, ema1, length=self.maLength)
            self.ma_val = self.I(lambda: 2 * ema1 - ema2)
        elif self.maType == "TEMA":
            ema1 = self.I(pta.ema, close, length=self.maLength)
            ema2 = self.I(pta.ema, ema1, length=self.maLength)
            ema3 = self.I(pta.ema, ema2, length=self.maLength)
            self.ma_val = self.I(lambda: 3 * (ema1 - ema2) + ema3)
        else:
            self.ma_val = self.I(pta.ema, close, length=self.maLength)

        # RSI Calculations
        rsi_short = self.I(pta.rsi, close, length=self.shortLen)
        rsi_long = self.I(pta.rsi, close, length=self.longLen)
        self.rsi_s = self.I(pta.ema, rsi_short, length=self.shortSmooth)
        self.rsi_l = self.I(pta.ema, rsi_long, length=self.longSmooth)
        self.diff = self.I(lambda: self.rsi_s - self.rsi_l)

        # Stochastic Calculations
        stoch_raw = self.I(pta.stoch, high, low, close, k=self.stochLen, d=3, smooth_k=1, smooth_d=1)
        stoch_k = self.I(lambda: stoch_raw.iloc[:, 0] if stoch_raw is not None and len(stoch_raw.columns) > 0 else pd.Series(50, index=close.index))
        self.db_stoch = self.I(pta.ema, self.I(pta.ema, stoch_k, length=self.stochSmth), length=self.stochSmth)

        # Volume Filter
        vol_ma = self.I(pta.sma, volume, length=20)
        self.vol_filter = self.I(lambda: (volume / vol_ma > 1.1) if (volume > 0).all() else pd.Series(True, index=close.index))

        # ATR for daily reference (using current ATR as proxy)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)

    def next(self):
        # Current values
        if len(self.data) < max(self.maLength, self.stochLen, self.shortLen, self.longLen) + 5:
            return

        diff_val = self.diff[-1] if self.diff[-1] is not None else 0
        ma_val = self.ma_val[-1] if self.ma_val[-1] is not None else self.data.Close[-1]
        close_val = self.data.Close[-1]
        stoch_val = self.db_stoch[-1] if self.db_stoch[-1] is not None else 50
        vol_filt = self.vol_filter[-1] if isinstance(self.vol_filter[-1], (bool, np.bool_)) else True

        # Define conditions
        is_bull = diff_val > self.threshold and close_val > ma_val
        is_bear = diff_val < -self.threshold and close_val < ma_val
        stoch_in_os = stoch_val <= 35
        stoch_in_ob = stoch_val >= 60

        # High confluence conditions
        high_conv_long = is_bull and vol_filt and stoch_in_os
        high_conv_short = is_bear and vol_filt and stoch_in_ob

        # Entry Logic
        if high_conv_long and not self.position:
            self.buy()
        elif high_conv_short and self.position:
            self.position.close()

        # Exit Logic
        if self.position and high_conv_short:
            self.position.close()
        elif not self.position and high_conv_long and len(self.data) > 1:
            if not (self.diff[-2] > self.threshold and self.data.Close[-2] > self.ma_val[-2]):
                self.buy()

        # Stop loss and take profit
        if self.position:
            if self.position.is_long:
                if close_val < ma_val and diff_val < -self.threshold:
                    self.position.close()
            else:
                if close_val > ma_val and diff_val > self.threshold:
                    self.position.close()


