import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 9
    emaSlowLen = 21
    kLen = 14
    kSmooth = 3
    atrLen = 14
    slAtrMult = 1.0
    tp1RR = 1.0
    tp2RR = 2.0
    tp3RR = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)
        self.atrVal = self.I(pta.atr, high, low, close, length=self.atrLen)

        def calculate_stoch():
            highest = high.rolling(window=self.kLen).max()
            lowest = low.rolling(window=self.kLen).min()
            rawK = np.where(
                highest != lowest,
                100 * (close - lowest) / (highest - lowest),
                0
            )
            rawK_series = pd.Series(rawK, index=close.index)
            stochK = pta.sma(rawK_series, length=self.kSmooth)
            return stochK if stochK is not None else pd.Series(50, index=close.index)

        self.stochK = self.I(calculate_stoch)

        self.entry_price = None
        self.sl_price = None
        self.tp1_price = None
        self.tp2_price = None
        self.tp3_price = None
        self.in_trade = False

    def next(self):
        close = self.data.Close[-1]
        ema_fast = self.emaFast[-1]
        ema_slow = self.emaSlow[-1]
        stoch_k = self.stochK[-1]
        atr_val = self.atrVal[-1]

        if ema_fast is None or ema_slow is None or stoch_k is None or atr_val is None:
            return

        long_trend = ema_fast > ema_slow
        short_trend = ema_fast < ema_slow

        buy_signal = long_trend and crossover(self.stochK, 20)
        sell_signal = short_trend and crossover(80, self.stochK)

        if buy_signal and not self.position:
            self.entry_price = close
            self.sl_price = close - atr_val * self.slAtrMult
            risk = self.entry_price - self.sl_price
            self.tp1_price = self.entry_price + risk * self.tp1RR
            self.tp2_price = self.entry_price + risk * self.tp2RR
            self.tp3_price = self.entry_price + risk * self.tp3RR
            self.in_trade = True
            self.buy()

        if sell_signal and not self.position:
            self.entry_price = close
            self.sl_price = close + atr_val * self.slAtrMult
            risk = self.sl_price - self.entry_price
            self.tp1_price = self.entry_price - risk * self.tp1RR
            self.tp2_price = self.entry_price - risk * self.tp2RR
            self.tp3_price = self.entry_price - risk * self.tp3RR
            self.in_trade = True
            self.sell()

        if self.position:
            if self.position.is_long:
                if close <= self.sl_price or close >= self.tp3_price:
                    self.position.close()
                    self.in_trade = False
            elif self.position.is_short:
                if close >= self.sl_price or close <= self.tp3_price:
                    self.position.close()
                    self.in_trade = False


