import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_psi = 14
    threshold = 0.3
    use_vol = True

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate PSI Energy
        def calculate_psi_raw():
            total_range = high - low
            body_size = close - open_
            abs_body = np.abs(body_size)
            
            efficiency = np.where(total_range == 0, 0, abs_body / total_range)
            
            vol_factor = (volume / pta.sma(volume, length=50)) if self.use_vol else np.ones(len(close))
            vol_factor = np.nan_to_num(vol_factor, nan=1.0)
            
            psi_raw = np.where(efficiency > self.threshold, body_size * efficiency * vol_factor, 0)
            return pd.Series(psi_raw, index=close.index)
        
        psi_raw_series = self.I(calculate_psi_raw)
        
        # Calculate HMA of PSI
        def calculate_psi_hma():
            psi_raw = calculate_psi_raw()
            hma_result = pta.hma(psi_raw, length=self.len_psi)
            return hma_result if hma_result is not None else pd.Series(0, index=psi_raw.index)
        
        self.psi_line = self.I(calculate_psi_hma)

    def next(self):
        if len(self.data) < 3:
            return
        
        psi_current = self.psi_line[-1]
        psi_prev = self.psi_line[-2]
        psi_prev2 = self.psi_line[-3]
        
        # Strong uptrend: PSI above 0 and rising
        if psi_current > 0 and psi_current > psi_prev:
            if not self.position:
                self.buy()
        
        # Momentum loss signal: PSI above 0 but falling (and was rising before)
        elif psi_current > 0 and psi_current < psi_prev and psi_prev > psi_prev2:
            if self.position:
                self.position.close()
        
        # Strong downtrend: PSI below 0 and falling
        elif psi_current < 0 and psi_current < psi_prev:
            if self.position:
                self.position.close()
        
        # Seller exhaustion: PSI below 0 but rising
        elif psi_current < 0 and psi_current > psi_prev:
            if not self.position:
                self.buy()


