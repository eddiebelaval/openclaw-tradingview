import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Length_SVZO = 14
    Smoothing_SVZO = 5
    Source_MA_SVZO = 'EMA'

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate typical price
        def calc_typical_price():
            return (high + low + close) / 3

        typical_price = self.I(calc_typical_price)

        # Calculate volume up and down
        def calc_vol_up():
            tp = (high + low + close) / 3
            tp_prev = tp.shift(1)
            return volume * (tp > tp_prev).astype(int)

        def calc_vol_down():
            tp = (high + low + close) / 3
            tp_prev = tp.shift(1)
            return volume * (tp < tp_prev).astype(int)

        vol_up = self.I(calc_vol_up)
        vol_down = self.I(calc_vol_down)

        # Calculate sum of volumes
        def calc_sum_vol_up():
            tp = (high + low + close) / 3
            tp_prev = tp.shift(1)
            vol_up_series = volume * (tp > tp_prev).astype(int)
            return vol_up_series.rolling(window=self.Length_SVZO).sum()

        def calc_sum_vol_down():
            tp = (high + low + close) / 3
            tp_prev = tp.shift(1)
            vol_down_series = volume * (tp < tp_prev).astype(int)
            return vol_down_series.rolling(window=self.Length_SVZO).sum()

        sum_vol_up = self.I(calc_sum_vol_up)
        sum_vol_down = self.I(calc_sum_vol_down)

        # Calculate SVZO
        def calc_svzo():
            tp = (high + low + close) / 3
            tp_prev = tp.shift(1)
            vol_up_series = volume * (tp > tp_prev).astype(int)
            vol_down_series = volume * (tp < tp_prev).astype(int)
            sum_up = vol_up_series.rolling(window=self.Length_SVZO).sum()
            sum_down = vol_down_series.rolling(window=self.Length_SVZO).sum()
            total = sum_up + sum_down
            svzo = (sum_up - sum_down) / total.replace(0, 1) * 100
            return svzo

        svzo = self.I(calc_svzo)

        # Calculate smoothed SVZO
        def calc_smoothed_svzo():
            tp = (high + low + close) / 3
            tp_prev = tp.shift(1)
            vol_up_series = volume * (tp > tp_prev).astype(int)
            vol_down_series = volume * (tp < tp_prev).astype(int)
            sum_up = vol_up_series.rolling(window=self.Length_SVZO).sum()
            sum_down = vol_down_series.rolling(window=self.Length_SVZO).sum()
            total = sum_up + sum_down
            svzo_raw = (sum_up - sum_down) / total.replace(0, 1) * 100

            if self.Source_MA_SVZO == 'EMA':
                return pta.ema(svzo_raw, length=self.Smoothing_SVZO)
            elif self.Source_MA_SVZO == 'SMA':
                return pta.sma(svzo_raw, length=self.Smoothing_SVZO)
            elif self.Source_MA_SVZO == 'RMA':
                return pta.rma(svzo_raw, length=self.Smoothing_SVZO)
            elif self.Source_MA_SVZO == 'WMA':
                return pta.wma(svzo_raw, length=self.Smoothing_SVZO)
            elif self.Source_MA_SVZO == 'VWMA':
                return pta.vwma(close, volume, length=self.Smoothing_SVZO)
            else:
                return pta.ema(svzo_raw, length=self.Smoothing_SVZO)

        self.smoothed_vzo = self.I(calc_smoothed_svzo)

    def next(self):
        # Buy when smoothed VZO crosses above 0
        if crossover(self.smoothed_vzo, 0):
            if not self.position:
                self.buy()
