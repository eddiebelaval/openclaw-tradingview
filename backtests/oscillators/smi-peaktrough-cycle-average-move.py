import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    a = 9
    b = 5
    obLevel = 40
    osLevel = -40
    lookbackN = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate highest high and lowest low
        def calc_hh(h, period=self.a):
            return h.rolling(window=period).max()
        
        def calc_ll(l, period=self.a):
            return l.rolling(window=period).min()
        
        hh = self.I(lambda: calc_hh(high, self.a))
        ll = self.I(lambda: calc_ll(low, self.a))
        
        # Calculate diff and rdiff
        def calc_diff(h, l):
            hh_vals = h.rolling(window=self.a).max()
            ll_vals = l.rolling(window=self.a).min()
            return hh_vals - ll_vals
        
        def calc_rdiff(c, h, l):
            hh_vals = h.rolling(window=self.a).max()
            ll_vals = l.rolling(window=self.a).min()
            return c - (hh_vals + ll_vals) / 2.0
        
        diff = self.I(lambda: calc_diff(high, low))
        rdiff = self.I(lambda: calc_rdiff(close, high, low))
        
        # Calculate EMA of EMA
        def calc_avgrel(r, period=self.b):
            ema1 = pta.ema(r, length=period)
            if ema1 is None or ema1.isna().all():
                return pd.Series(0, index=r.index)
            ema2 = pta.ema(ema1, length=period)
            return ema2 if ema2 is not None else pd.Series(0, index=r.index)
        
        def calc_avgdiff(d, period=self.b):
            ema1 = pta.ema(d, length=period)
            if ema1 is None or ema1.isna().all():
                return pd.Series(0, index=d.index)
            ema2 = pta.ema(ema1, length=period)
            return ema2 if ema2 is not None else pd.Series(0, index=d.index)
        
        avgrel = self.I(lambda: calc_avgrel(rdiff, self.b))
        avgdiff = self.I(lambda: calc_avgdiff(diff, self.b))
        
        # Calculate SMI
        def calc_smi(avgrel_vals, avgdiff_vals):
            result = pd.Series(0.0, index=avgrel_vals.index)
            for i in range(len(avgrel_vals)):
                if pd.notna(avgdiff_vals.iloc[i]) and avgdiff_vals.iloc[i] != 0:
                    result.iloc[i] = (avgrel_vals.iloc[i] / (avgdiff_vals.iloc[i] / 2.0)) * 100.0
                else:
                    result.iloc[i] = 0.0
            return result
        
        self.smi = self.I(lambda: calc_smi(avgrel, avgdiff))
        self.smi_signal = self.I(pta.ema, self.smi, length=self.b)
        
        # State tracking
        self.os_candidate_smi = None
        self.os_candidate_price = None
        self.os_candidate_bar = None
        
        self.ob_candidate_smi = None
        self.ob_candidate_price = None
        self.ob_candidate_bar = None
        
        self.last_extreme_type = None
        self.last_extreme_price = None
        self.last_extreme_bar = None
        
        self.up_points_arr = []
        self.down_points_arr = []
        self.up_bars_arr = []
        self.down_bars_arr = []
        
        self.in_cycle = False

    def next(self):
        idx = len(self.data) - 1
        current_smi = self.smi[-1]
        current_price = self.data.Close[-1]
        
        in_oversold = current_smi < self.osLevel
        in_overbought = current_smi > self.obLevel
        
        # Track oversold candidates
        if in_oversold:
            if self.os_candidate_smi is None or current_smi < self.os_candidate_smi:
                self.os_candidate_smi = current_smi
                self.os_candidate_price = current_price
                self.os_candidate_bar = idx
        
        # Track overbought candidates
        if in_overbought:
            if self.ob_candidate_smi is None or current_smi > self.ob_candidate_smi:
                self.ob_candidate_smi = current_smi
                self.ob_candidate_price = current_price
                self.ob_candidate_bar = idx
        
        # Check exits from extremes
        prev_in_oversold = len(self.data) > 1 and self.smi[-2] < self.osLevel
        prev_in_overbought = len(self.data) > 1 and self.smi[-2] > self.obLevel
        
        exit_oversold = prev_in_oversold and not in_oversold
        exit_overbought = prev_in_overbought and not in_overbought
        
        # Confirm oversold (trough)
        if exit_oversold and self.os_candidate_price is not None:
            trough_price = self.os_candidate_price
            trough_bar = self.os_candidate_bar
            
            if self.last_extreme_type == "peak" and self.last_extreme_price is not None:
                down_move_pts = trough_price - self.last_extreme_price
                down_move_bars = trough_bar - self.last_extreme_bar
                
                self.down_points_arr.append(down_move_pts)
                self.down_bars_arr.append(down_move_bars)
                
                if len(self.down_points_arr) > self.lookbackN:
                    self.down_points_arr.pop(0)
                    self.down_bars_arr.pop(0)
            
            self.last_extreme_type = "trough"
            self.last_extreme_price = trough_price
            self.last_extreme_bar = trough_bar
            
            self.os_candidate_smi = None
            self.os_candidate_price = None
            self.os_candidate_bar = None
            self.in_cycle = True
        
        # Confirm overbought (peak)
        if exit_overbought and self.ob_candidate_price is not None:
            peak_price = self.ob_candidate_price
            peak_bar = self.ob_candidate_bar
            
            if self.last_extreme_type == "trough" and self.last_extreme_price is not None:
                up_move_pts = peak_price - self.last_extreme_price
                up_move_bars = peak_bar - self.last_extreme_bar
                
                self.up_points_arr.append(up_move_pts)
                self.up_bars_arr.append(up_move_bars)
                
                if len(self.up_points_arr) > self.lookbackN:
                    self.up_points_arr.pop(0)
                    self.up_bars_arr.pop(0)
            
            self.last_extreme_type = "peak"
            self.last_extreme_price = peak_price
            self.last_extreme_bar = peak_bar
            
            self.ob_candidate_smi = None
            self.ob_candidate_price = None
            self.ob_candidate_bar = None
            self.in_cycle = True
        
        # Simple trading logic based on SMI signal crossovers
        if len(self.data) > 1:
            if crossover(self.smi, self.smi_signal):
                if not self.position:
                    self.buy()
            elif crossover(self.smi_signal, self.smi):
                if self.position:
                    self.position.close()


