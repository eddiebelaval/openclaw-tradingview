import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    ma_type = "VWMA"
    ma_length = 14
    bb_mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate RSI using RMA (Wilder's smoothing)
        def calc_rsi(src):
            change = src.diff()
            up = change.clip(lower=0)
            down = -change.clip(upper=0)
            
            up_rma = pta.rma(up, length=self.rsi_length)
            down_rma = pta.rma(down, length=self.rsi_length)
            
            rsi = pd.Series(np.where(
                down_rma == 0, 100,
                np.where(up_rma == 0, 0, 100 - (100 / (1 + up_rma / down_rma)))
            ), index=src.index)
            return rsi
        
        self.rsi = self.I(calc_rsi, close)
        
        # Calculate smoothing MA based on type
        def calc_ma(rsi_vals):
            if self.ma_type == "SMA":
                return pta.sma(rsi_vals, length=self.ma_length)
            elif self.ma_type == "EMA":
                return pta.ema(rsi_vals, length=self.ma_length)
            elif self.ma_type == "SMMA (RMA)":
                return pta.rma(rsi_vals, length=self.ma_length)
            elif self.ma_type == "WMA":
                return pta.wma(rsi_vals, length=self.ma_length)
            elif self.ma_type == "VWMA":
                return pta.vwma(rsi_vals, volume, length=self.ma_length)
            else:
                return pd.Series(np.nan, index=rsi_vals.index)
        
        self.smoothing_ma = self.I(calc_ma, self.rsi)
        
        # Calculate Bollinger Bands on RSI
        def calc_bb_bands(rsi_vals):
            stdev = rsi_vals.rolling(window=self.ma_length).std()
            bb_upper = self.smoothing_ma + (stdev * self.bb_mult)
            bb_lower = self.smoothing_ma - (stdev * self.bb_mult)
            return bb_upper, bb_lower
        
        self.bb_upper = self.I(lambda: calc_bb_bands(self.rsi)[0])
        self.bb_lower = self.I(lambda: calc_bb_bands(self.rsi)[1])
        
        # Pivot detection for divergences
        lookback_left = 5
        lookback_right = 5
        
        def detect_pivot_lows(rsi_vals):
            pivots = pd.Series(np.nan, index=rsi_vals.index)
            for i in range(lookback_left + lookback_right, len(rsi_vals)):
                is_pivot = True
                for j in range(1, lookback_left + 1):
                    if rsi_vals.iloc[i - j] <= rsi_vals.iloc[i]:
                        is_pivot = False
                        break
                for j in range(1, lookback_right + 1):
                    if rsi_vals.iloc[i + j] <= rsi_vals.iloc[i]:
                        is_pivot = False
                        break
                if is_pivot:
                    pivots.iloc[i] = rsi_vals.iloc[i]
            return pivots
        
        def detect_pivot_highs(rsi_vals):
            pivots = pd.Series(np.nan, index=rsi_vals.index)
            for i in range(lookback_left + lookback_right, len(rsi_vals)):
                is_pivot = True
                for j in range(1, lookback_left + 1):
                    if rsi_vals.iloc[i - j] >= rsi_vals.iloc[i]:
                        is_pivot = False
                        break
                for j in range(1, lookback_right + 1):
                    if rsi_vals.iloc[i + j] >= rsi_vals.iloc[i]:
                        is_pivot = False
                        break
                if is_pivot:
                    pivots.iloc[i] = rsi_vals.iloc[i]
            return pivots
        
        self.pivot_lows = self.I(detect_pivot_lows, self.rsi)
        self.pivot_highs = self.I(detect_pivot_highs, self.rsi)

    def next(self):
        # Trading logic based on RSI crossing above/below smoothing MA
        if len(self.data) < 2:
            return
        
        # Bullish cross: RSI crosses above smoothing MA
        if (self.ma_type != "None" and 
            not np.isnan(self.smoothing_ma[-2]) and 
            not np.isnan(self.smoothing_ma[-1]) and
            self.rsi[-2] <= self.smoothing_ma[-2] and 
            self.rsi[-1] > self.smoothing_ma[-1]):
            if not self.position:
                self.buy()
        
        # Bearish cross: RSI crosses below smoothing MA
        elif (self.ma_type != "None" and 
              not np.isnan(self.smoothing_ma[-2]) and 
              not np.isnan(self.smoothing_ma[-1]) and
              self.rsi[-2] >= self.smoothing_ma[-2] and 
              self.rsi[-1] < self.smoothing_ma[-1]):
            if self.position:
                self.position.close()
        
        # RSI overbought exit
        if self.position and self.rsi[-1] > 70:
            self.position.close()
        
        # RSI oversold entry (if not in position and no MA smoothing)
        if self.ma_type == "None" and not self.position and self.rsi[-1] < 30:
            self.buy()


