import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_len = 14
    src_type = "Close"
    smooth_type = "HMA"
    sig_smooth_len = 5
    basis_len = 100
    band_mult = 1.618
    show_div = True
    div_left = 25
    div_rsi_min = 2.0
    div_atr_min = 0.2
    ema_len = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Source selection
        if self.src_type == "Close":
            src = close
        elif self.src_type == "HL2":
            src = (high + low) / 2
        elif self.src_type == "OHLC4":
            src = (pd.Series(self.data.Open) + high + low + close) / 4
        else:
            src = close
        
        # Raw RSI
        self.raw_rsi = self.I(pta.rsi, src, length=self.rsi_len)
        
        # Smoothed RSI signal
        if self.smooth_type == "SMA":
            self.signal_rsi = self.I(pta.sma, self.raw_rsi, length=self.sig_smooth_len)
        elif self.smooth_type == "EMA":
            self.signal_rsi = self.I(pta.ema, self.raw_rsi, length=self.sig_smooth_len)
        elif self.smooth_type == "RMA":
            self.signal_rsi = self.I(pta.rma, self.raw_rsi, length=self.sig_smooth_len)
        elif self.smooth_type == "HMA":
            self.signal_rsi = self.I(pta.hma, self.raw_rsi, length=self.sig_smooth_len)
        else:
            self.signal_rsi = self.raw_rsi
        
        # RSI basis and bands
        self.rsi_basis = self.I(pta.hma, self.raw_rsi, length=self.basis_len)
        
        def calc_stdev(s):
            return s.rolling(self.basis_len).std()
        
        self.rsi_stdev = self.I(calc_stdev, self.raw_rsi)
        
        def calc_upper_band():
            basis_vals = self.rsi_basis
            stdev_vals = self.rsi_stdev
            upper = basis_vals + (stdev_vals * self.band_mult)
            return upper.clip(upper=100)
        
        def calc_lower_band():
            basis_vals = self.rsi_basis
            stdev_vals = self.rsi_stdev
            lower = basis_vals - (stdev_vals * self.band_mult)
            return lower.clip(lower=0)
        
        self.upper_band = self.I(calc_upper_band)
        self.lower_band = self.I(calc_lower_band)
        
        # EMA of signal RSI
        self.rsi_ema = self.I(pta.ema, self.signal_rsi, length=self.ema_len)
        
        # ATR for divergence
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Divergence tracking
        self.last_ph_rsi = None
        self.last_ph_price = None
        self.last_ph_bar = None
        
        self.last_pl_rsi = None
        self.last_pl_price = None
        self.last_pl_bar = None
        
        # Trading signals
        self.bullish_div_found = False
        self.bearish_div_found = False

    def next(self):
        if len(self.data) < self.basis_len + self.div_left:
            return
        
        # Current values
        current_signal_rsi = self.signal_rsi[-1]
        current_upper = self.upper_band[-1]
        current_lower = self.lower_band[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_atr = self.atr[-1]
        current_bar = len(self.data) - 1
        
        # Detect pivot highs and lows for divergence
        if self.show_div and len(self.data) > self.div_left + 2:
            # Check for pivot high
            is_pivot_high = True
            pivot_high_rsi = self.signal_rsi[-(self.div_left + 1)]
            pivot_high_price = self.data.High[-(self.div_left + 1)]
            
            for i in range(1, self.div_left + 1):
                if self.signal_rsi[-i - 1] >= pivot_high_rsi or self.signal_rsi[-(self.div_left + 1 + i)] >= pivot_high_rsi:
                    is_pivot_high = False
                    break
            
            if is_pivot_high:
                if self.last_ph_rsi is not None:
                    price_hh = pivot_high_price > self.last_ph_price
                    rsi_lh = pivot_high_rsi < self.last_ph_rsi
                    steep_rsi = (self.last_ph_rsi - pivot_high_rsi) > self.div_rsi_min
                    sig_price = (pivot_high_price - self.last_ph_price) > (current_atr * self.div_atr_min)
                    
                    if price_hh and rsi_lh and steep_rsi and sig_price:
                        self.bearish_div_found = True
                
                self.last_ph_rsi = pivot_high_rsi
                self.last_ph_price = pivot_high_price
                self.last_ph_bar = current_bar - self.div_left - 1
            
            # Check for pivot low
            is_pivot_low = True
            pivot_low_rsi = self.signal_rsi[-(self.div_left + 1)]
            pivot_low_price = self.data.Low[-(self.div_left + 1)]
            
            for i in range(1, self.div_left + 1):
                if self.signal_rsi[-i - 1] <= pivot_low_rsi or self.signal_rsi[-(self.div_left + 1 + i)] <= pivot_low_rsi:
                    is_pivot_low = False
                    break
            
            if is_pivot_low:
                if self.last_pl_rsi is not None:
                    price_ll = pivot_low_price < self.last_pl_price
                    rsi_hl = pivot_low_rsi > self.last_pl_rsi
                    steep_rsi = (pivot_low_rsi - self.last_pl_rsi) > self.div_rsi_min
                    sig_price = (self.last_pl_price - pivot_low_price) > (current_atr * self.div_atr_min)
                    
                    if price_ll and rsi_hl and steep_rsi and sig_price:
                        self.bullish_div_found = True
                
                self.last_pl_rsi = pivot_low_rsi
                self.last_pl_price = pivot_low_price
                self.last_pl_bar = current_bar - self.div_left - 1
        
        # Trading logic based on RSI levels and divergences
        if current_signal_rsi < current_lower:
            # Oversold condition - bullish signal
            if self.bullish_div_found or crossover(self.signal_rsi, current_lower):
                if not self.position:
                    self.buy()
                self.bullish_div_found = False
        
        elif current_signal_rsi > current_upper:
            # Overbought condition - bearish signal
            if self.bearish_div_found or crossover(current_upper, self.signal_rsi):
                if self.position:
                    self.position.close()
                else:
                    self.sell()
                self.bearish_div_found = False
        
        # Exit long on signal RSI crossing below basis
        if self.position and crossover(self.rsi_basis, self.signal_rsi):
            self.position.close()
        
        # Exit short on signal RSI crossing above basis
        if not self.position and crossover(self.signal_rsi, self.rsi_basis):
            if len(self.orders) > 0:
                self.orders[-1].cancel()


