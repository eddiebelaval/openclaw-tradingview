import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length_trama = 99
    src_trama = "close"
    Periods = 10
    Multiplier = 3.0
    changeATR = True
    length_sto = 10
    mult_sto = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # TRAMA Calculation
        def calculate_trama():
            ama_values = np.zeros(len(close))
            highest = close.rolling(window=self.length_trama).max()
            lowest = close.rolling(window=self.length_trama).min()
            hh = (highest.diff() > 0).astype(float)
            ll = (-lowest.diff() > 0).astype(float)
            condition = (hh | ll).astype(float)
            tc = pta.sma(condition, length=self.length_trama) ** 2
            
            ama_values[0] = close.iloc[0]
            for i in range(1, len(close)):
                if pd.isna(tc.iloc[i]):
                    ama_values[i] = ama_values[i-1]
                else:
                    ama_values[i] = ama_values[i-1] + tc.iloc[i] * (close.iloc[i] - ama_values[i-1])
            
            return pd.Series(ama_values, index=close.index)
        
        self.trama = self.I(calculate_trama)
        
        # Supertrend Calculation
        def calculate_supertrend():
            src_st = (high + low) / 2
            tr = pta.tr(high, low, close)
            atr2 = pta.sma(tr, length=self.Periods)
            atr_val = pta.atr(high, low, close, length=self.Periods) if self.changeATR else atr2
            
            up = src_st - (self.Multiplier * atr_val)
            dn = src_st + (self.Multiplier * atr_val)
            
            up_values = np.zeros(len(close))
            dn_values = np.zeros(len(close))
            trend_st = np.zeros(len(close))
            
            up_values[0] = up.iloc[0]
            dn_values[0] = dn.iloc[0]
            trend_st[0] = 1
            
            for i in range(1, len(close)):
                up1 = up_values[i-1]
                dn1 = dn_values[i-1]
                
                if close.iloc[i-1] > up1:
                    up_values[i] = max(up.iloc[i], up1)
                else:
                    up_values[i] = up.iloc[i]
                
                if close.iloc[i-1] < dn1:
                    dn_values[i] = min(dn.iloc[i], dn1)
                else:
                    dn_values[i] = dn.iloc[i]
                
                if trend_st[i-1] == -1 and close.iloc[i] > dn1:
                    trend_st[i] = 1
                elif trend_st[i-1] == 1 and close.iloc[i] < up1:
                    trend_st[i] = -1
                else:
                    trend_st[i] = trend_st[i-1]
            
            return pd.Series(trend_st, index=close.index), pd.Series(up_values, index=close.index), pd.Series(dn_values, index=close.index)
        
        self.trend_st, self.up_st, self.dn_st = self.I(calculate_supertrend)
        
        # SuperOsc Calculation
        def calculate_superasc():
            atr_sto = pta.atr(high, low, close, length=self.length_sto) * self.mult_sto
            hl2 = (high + low) / 2
            up_sto = hl2 + atr_sto
            dn_sto = hl2 - atr_sto
            
            upper_sto = np.zeros(len(close))
            lower_sto = np.zeros(len(close))
            trend_sto_osc = np.zeros(len(close))
            
            upper_sto[0] = up_sto.iloc[0]
            lower_sto[0] = dn_sto.iloc[0]
            trend_sto_osc[0] = 0
            
            for i in range(1, len(close)):
                if close.iloc[i-1] < upper_sto[i-1]:
                    upper_sto[i] = min(up_sto.iloc[i], upper_sto[i-1])
                else:
                    upper_sto[i] = up_sto.iloc[i]
                
                if close.iloc[i-1] > lower_sto[i-1]:
                    lower_sto[i] = max(dn_sto.iloc[i], lower_sto[i-1])
                else:
                    lower_sto[i] = dn_sto.iloc[i]
                
                if close.iloc[i] > upper_sto[i-1]:
                    trend_sto_osc[i] = 1
                elif close.iloc[i] < lower_sto[i-1]:
                    trend_sto_osc[i] = 0
                else:
                    trend_sto_osc[i] = trend_sto_osc[i-1]
            
            Spt = trend_sto_osc * lower_sto + (1 - trend_sto_osc) * upper_sto
            osc = np.zeros(len(close))
            for i in range(len(close)):
                denominator = upper_sto[i] - lower_sto[i]
                if denominator != 0:
                    osc[i] = max(min((close.iloc[i] - Spt[i]) / denominator, 1), -1)
                else:
                    osc[i] = 0
            
            return pd.Series(osc, index=close.index)
        
        self.osc = self.I(calculate_superasc)

    def next(self):
        if len(self) < 2:
            return
        
        close_price = self.data.Close[-1]
        trama_val = self.trama[-1]
        osc_val = self.osc[-1]
        trend_val = self.trend_st[-1]
        trend_prev = self.trend_st[-2]
        
        # Entry signals
        buySignal = (trend_val == 1 and trend_prev == -1)
        primaryLong = buySignal and (close_price > trama_val) and (osc_val > 0)
        
        additionalLong = (trend_val == 1) and crossover(self.data.Close[-2:], self.trama[-2:]) and (osc_val > 0) and (self.position.size == 0)
        
        longCondition = primaryLong or additionalLong
        
        # Exit signal
        sellSignal = (trend_val == -1 and trend_prev == 1)
        
        if longCondition and self.position.size == 0:
            self.buy()
        
        if sellSignal and self.position.size > 0:
            self.sell()


