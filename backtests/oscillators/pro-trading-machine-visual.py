import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # VZO calculation
        def calc_vzo():
            vzo_len = 22
            vzo_smooth_n = 5
            dir_val = np.where(close > close.shift(3), volume, -volume)
            tvol = close.rolling(vzo_len).apply(lambda x: np.polyfit(range(len(x)), x, 1)[0] if len(x) == vzo_len else np.nan, raw=False)
            dvol = pd.Series(dir_val).rolling(vzo_len).apply(lambda x: np.polyfit(range(len(x)), x, 1)[0] if len(x) == vzo_len else np.nan, raw=False)
            raw_vzo = 100.0 * dvol / np.maximum(tvol, 1e-6)
            raw_vzo = np.maximum(-120.0, np.minimum(120.0, raw_vzo))
            vzo_ema = pd.Series(raw_vzo).ewm(span=vzo_smooth_n).mean()
            return vzo_ema
        
        self.vzo = self.I(calc_vzo)
        
        # Z-Score calculation
        def calc_zscore():
            zs_len = 40
            z_std = close.rolling(zs_len).std()
            z_sma = close.rolling(zs_len).mean()
            zscore = (close - z_sma) / np.maximum(z_std, 1e-10)
            zscore = np.maximum(-4.0, np.minimum(4.0, zscore))
            return zscore
        
        self.zscore = self.I(calc_zscore)
        
        # CTO (Cluster Trading Oscillator)
        def calc_cto():
            cto_sp = 2
            cto_ps_len = 3
            c_cluster = []
            for i in range(1, 34):
                c_cluster.append(close.ewm(span=i*cto_sp).mean())
            
            def count_alignment(idx):
                if idx < 1:
                    return 0
                count = 0
                for i in range(len(c_cluster)-1):
                    if c_cluster[i].iloc[idx] > c_cluster[i+1].iloc[idx]:
                        count += 1
                    else:
                        count -= 1
                return count / 33.0
            
            raw_cto = pd.Series([count_alignment(i) for i in range(len(close))])
            cto_sm = raw_cto.ewm(span=cto_ps_len).mean()
            cto_ema1 = cto_sm.ewm(span=3).mean()
            cto_ema2 = cto_ema1.ewm(span=3).mean()
            cto_final = np.maximum(-1.0, np.minimum(1.0, cto_ema2))
            return cto_final
        
        self.cto = self.I(calc_cto)
        
        # RSI calculation
        def calc_rsi():
            rsi_raw = pta.rsi(close, length=14)
            rsi_norm = (rsi_raw - 50.0) / 50.0
            rsi_norm = np.maximum(-1.0, np.minimum(1.0, rsi_norm))
            rsi_ema1 = rsi_norm.ewm(span=3).mean()
            rsi_ema2 = rsi_ema1.ewm(span=3).mean()
            return rsi_ema2
        
        self.rsi = self.I(calc_rsi)
        
        # ADX calculation
        def calc_adx():
            adx_result = pta.adx(high, low, close, length=14)
            if adx_result is None:
                return pd.Series(0, index=close.index)
            adx_vals = adx_result.iloc[:, 2] if adx_result.shape[1] > 2 else pd.Series(0, index=close.index)
            adx_norm = (adx_vals - 20.0) / np.maximum(20.0, 1e-6)
            return np.maximum(-1.0, np.minimum(1.0, adx_norm))
        
        self.adx = self.I(calc_adx)
        
        # Composite calculation
        def calc_composite():
            comp_raw = (self.cto * 0.20 + self.adx * 0.15 + self.rsi * 0.15) / 0.50
            comp_ema = comp_raw.ewm(span=3).mean()
            return comp_ema
        
        self.composite = self.I(calc_composite)
        
        # DMI calculation
        def calc_dmi():
            hi_d = high - high.shift(1)
            lo_d = low.shift(1) - low
            p_dm = np.where((hi_d > lo_d) & (hi_d > 0), hi_d, 0.0)
            m_dm = np.where((lo_d > hi_d) & (lo_d > 0), lo_d, 0.0)
            tr = np.maximum(high - low, np.maximum(np.abs(high - close.shift(1)), np.abs(low - close.shift(1))))
            atr_val = pd.Series(tr).rolling(14).apply(lambda x: x.mean() if len(x) > 0 else 1e-6, raw=False)
            di_p = 100.0 * pd.Series(p_dm).rolling(14).mean() / np.maximum(atr_val, 1e-6)
            di_m = 100.0 * pd.Series(m_dm).rolling(14).mean() / np.maximum(atr_val, 1e-6)
            raw_dmi = np.abs(di_p - di_m) * np.where(di_p >= di_m, 1.0, -1.0)
            mx = raw_dmi.rolling(150).max()
            dmi_final = raw_dmi / np.maximum(mx, 1e-6)
            return np.maximum(-1.0, np.minimum(1.0, dmi_final))
        
        self.dmi = self.I(calc_dmi)
    
    def next(self):
        # Trading rules based on composite and divergence signals
        composite_val = self.composite[-1] if not np.isnan(self.composite[-1]) else 0
        vzo_val = self.vzo[-1] if not np.isnan(self.vzo[-1]) else 0
        zscore_val = self.zscore[-1] if not np.isnan(self.zscore[-1]) else 0
        dmi_val = self.dmi[-1] if not np.isnan(self.dmi[-1]) else 0
        
        # Buy signal: composite and DMI aligned bullish, Z-score not extremely overbought
        buy_signal = (
            composite_val > 20 and 
            dmi_val > 0.1 and 
            zscore_val < 2.5 and
            vzo_val > -30
        )
        
        # Sell signal: composite and DMI aligned bearish, Z-score not extremely oversold
        sell_signal = (
            composite_val < -20 and 
            dmi_val < -0.1 and 
            zscore_val > -2.5 and
            vzo_val < 30
        )
        
        # Entry logic
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.position.close()
        
        # Exit long on reversal signals
        if self.position and sell_signal:
            self.position.close()