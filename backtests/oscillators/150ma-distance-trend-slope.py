import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    maLen = 150
    lookback = 1

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate 150-period SMA
        ma = self.I(pta.sma, close, length=self.maLen)
        
        # Distance % from MA
        self.dist_pct = self.I(lambda: ((close - ma) / ma) * 100)
        
        # Raw slope of MA
        def calculate_slope():
            ma_vals = pta.sma(close, length=self.maLen)
            if ma_vals is None:
                return pd.Series(0, index=close.index)
            slope_vals = (ma_vals - ma_vals.shift(self.lookback)) / self.lookback
            return slope_vals
        
        slope = self.I(calculate_slope)
        
        # Angle in degrees
        RAD2DEG = 180.0 / np.pi
        self.angle_deg = self.I(lambda: np.arctan(slope) * RAD2DEG)

    def next(self):
        # Buy when distance % crosses above zero (price above MA and increasing)
        # and slope is positive (MA trending up)
        if crossover(self.dist_pct, 0):
            if self.angle_deg[-1] > 0:
                self.buy()
        
        # Sell when distance % crosses below zero (price below MA)
        # or slope turns negative (MA trending down)
        elif crossover(0, self.dist_pct):
            self.sell()
        elif len(self) > 1 and self.angle_deg[-2] > 0 and self.angle_deg[-1] < 0:
            self.sell()