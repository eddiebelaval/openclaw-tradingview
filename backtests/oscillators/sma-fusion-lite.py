import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smaLength = 9
    rsiLength = 14
    adxLength = 14
    chopLength = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # SMA
        self.sma = self.I(pta.sma, close, length=self.smaLength)

        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)

        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macdLine = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACD_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        self.signalLine = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACDs_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))

        # True Range and ATR for ADX calculation
        tr = self.I(lambda: pta.tr(high, low, close, True))

        # Highest and Lowest for Choppiness
        self.hh = self.I(lambda: high.rolling(window=self.chopLength).max())
        self.ll = self.I(lambda: low.rolling(window=self.chopLength).min())

        # Sum of True Range
        self.sumTR = self.I(lambda: tr.rolling(window=self.chopLength).sum())

        # ADX Calculation
        self.adx = self.I(lambda: pta.adx(high, low, close, length=self.adxLength)['ADX_14'] if pta.adx(high, low, close, length=self.adxLength) is not None else pd.Series(25, index=close.index))

        # Choppiness Index
        self.chop = self.I(self._calculate_chop, high, low, close)

        # Score calculation
        self.score = self.I(self._calculate_score, close, high, low)

        self.prev_buy_signal = False
        self.prev_sell_signal = False

    def _calculate_chop(self, high, low, close):
        tr = pta.tr(high, low, close, True)
        if tr is None:
            return pd.Series(50, index=close.index)
        
        sumTR = tr.rolling(window=self.chopLength).sum()
        hh = high.rolling(window=self.chopLength).max()
        ll = low.rolling(window=self.chopLength).min()
        priceRange = hh - ll
        
        chop = pd.Series(index=close.index, dtype=float)
        for i in range(len(close)):
            if priceRange.iloc[i] != 0 and sumTR.iloc[i] > 0:
                chop.iloc[i] = 100 * np.log10(sumTR.iloc[i] / priceRange.iloc[i]) / np.log10(self.chopLength)
            else:
                chop.iloc[i] = 50
        
        return chop

    def _calculate_score(self, close, high, low):
        score = pd.Series(index=close.index, dtype=float)
        
        for i in range(len(close)):
            s = 0
            
            # SMA component
            if not pd.isna(self.sma[i]):
                s += 2 if close.iloc[i] > self.sma[i] else -2
            
            # RSI component
            if not pd.isna(self.rsi[i]):
                if self.rsi[i] > 55:
                    s += 1
                elif self.rsi[i] < 45:
                    s += -1
            
            # MACD component
            if not pd.isna(self.macdLine[i]) and not pd.isna(self.signalLine[i]):
                s += 1 if self.macdLine[i] > self.signalLine[i] else -1
            
            # ADX component
            if not pd.isna(self.adx[i]) and self.adx[i] > 20:
                s += 1
            
            # Choppiness component
            if not pd.isna(self.chop[i]) and self.chop[i] > 60:
                s += -1
            
            score.iloc[i] = s
        
        return score

    def next(self):
        if len(self.data) < self.adxLength + self.chopLength:
            return

        current_score = self.score[-1]
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_sma = self.sma[-1]
        current_macdLine = self.macdLine[-1]
        current_signalLine = self.signalLine[-1]
        current_adx = self.adx[-1]
        current_chop = self.chop[-1]

        isChoppy = current_adx < 20 and current_chop > 60

        buyCondition = (
            current_score >= 3 and
            current_close > current_sma and
            current_low > current_sma and
            current_macdLine > current_signalLine and
            not isChoppy
        )

        sellCondition = (
            current_score <= -3 and
            current_close < current_sma and
            current_high < current_sma and
            current_macdLine < current_signalLine and
            not isChoppy
        )

        buySignal = buyCondition and not self.prev_buy_signal
        sellSignal = sellCondition and not self.prev_sell_signal

        if buySignal:
            self.buy()
            self.prev_buy_signal = True
        else:
            self.prev_buy_signal = False

        if sellSignal:
            self.sell()
            self.prev_sell_signal = True
        else:
            self.prev_sell_signal = False