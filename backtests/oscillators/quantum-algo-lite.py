import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate HLC3
        hlc3 = (high + low + close) / 3
        
        # WaveTrend calculation
        # wt1 = ta.ema(nz((hlc3 - ta.ema(hlc3, 10)) / (0.015 * ta.ema(math.abs(hlc3 - ta.ema(hlc3, 10)), 10))), 21)
        def calc_wt1():
            ema_hlc3_10 = pta.ema(hlc3, length=10)
            if ema_hlc3_10 is None:
                return pd.Series(0, index=close.index)
            
            numerator = hlc3 - ema_hlc3_10
            abs_numerator = np.abs(numerator)
            ema_abs_10 = pta.ema(abs_numerator, length=10)
            if ema_abs_10 is None:
                return pd.Series(0, index=close.index)
            
            denominator = 0.015 * ema_abs_10
            denominator = denominator.replace(0, 1)
            
            ratio = numerator / denominator
            wt1_result = pta.ema(ratio.fillna(0), length=21)
            return wt1_result if wt1_result is not None else pd.Series(0, index=close.index)
        
        self.wt1 = self.I(calc_wt1)
        
        # wt2 = ta.sma(wt1, 4)
        def calc_wt2():
            wt1_series = pd.Series(self.wt1)
            wt2_result = pta.sma(wt1_series, length=4)
            return wt2_result if wt2_result is not None else pd.Series(0, index=close.index)
        
        self.wt2 = self.I(calc_wt2)
        
        # hx = ta.cross(wt1 - wt2, 0)
        def calc_hx():
            wt1_series = pd.Series(self.wt1)
            wt2_series = pd.Series(self.wt2)
            diff = wt1_series - wt2_series
            hx_result = pd.Series(0, index=close.index)
            for i in range(1, len(diff)):
                if diff.iloc[i] * diff.iloc[i-1] < 0:
                    hx_result.iloc[i] = 1
            return hx_result
        
        self.hx = self.I(calc_hx)
        
        # v = ta.linreg(close - math.avg(math.avg(ta.highest(high,20), ta.lowest(low,20)), ta.sma(close,20)), 20, 0)
        def calc_v():
            highest_20 = high.rolling(window=20).max()
            lowest_20 = low.rolling(window=20).min()
            avg1 = (highest_20 + lowest_20) / 2
            sma_close_20 = pta.sma(close, length=20)
            if sma_close_20 is None:
                sma_close_20 = pd.Series(0, index=close.index)
            avg2 = (avg1 + sma_close_20) / 2
            
            linreg_input = close - avg2
            v_result = pd.Series(0, index=close.index)
            for i in range(20, len(close)):
                window = linreg_input.iloc[i-20:i]
                if len(window) == 20:
                    coeffs = np.polyfit(np.arange(20), window.values, 1)
                    v_result.iloc[i] = coeffs[1]
            return v_result
        
        self.v = self.I(calc_v)
        
        # mv = nz(ta.highest(math.abs(v), 100), 1)
        def calc_mv():
            abs_v = np.abs(pd.Series(self.v))
            mv_result = abs_v.rolling(window=100).max().fillna(1)
            return mv_result
        
        self.mv = self.I(calc_mv)
        
        # sv = mv != 0 ? (v / mv) * 60 : v
        def calc_sv():
            v_series = pd.Series(self.v)
            mv_series = pd.Series(self.mv)
            sv_result = pd.Series(0, index=close.index)
            for i in range(len(close)):
                if mv_series.iloc[i] != 0:
                    sv_result.iloc[i] = (v_series.iloc[i] / mv_series.iloc[i]) * 60
                else:
                    sv_result.iloc[i] = v_series.iloc[i]
            return sv_result
        
        self.sv = self.I(calc_sv)

    def next(self):
        wt1_val = self.wt1[-1]
        wt2_val = self.wt2[-1]
        hx_val = self.hx[-1]
        sv_val = self.sv[-1]
        
        # Buy signal: WaveTrend crosses above (wt1 crosses above wt2) and not overbought
        if len(self.wt1) > 1:
            if crossover(self.wt1, self.wt2):
                if wt1_val < 60:
                    if not self.position:
                        self.buy()
        
        # Sell signal: WaveTrend crosses below (wt1 crosses below wt2) or overbought condition
        if len(self.wt1) > 1:
            if crossover(self.wt2, self.wt1):
                if self.position:
                    self.sell()
            elif wt1_val > 60:
                if self.position:
                    self.sell()