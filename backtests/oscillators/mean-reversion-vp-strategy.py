        def calc_poc(close_series, length):
            result = pd.Series(index=close_series.index, dtype=float)
            for i in range(len(close_series)):
                if i < length:
                    result.iloc[i] = close_series.iloc[:i+1].median()
                else:
                    window = close_series.iloc[i-length+1:i+1]
                    result.iloc[i] = window.median()
            return result
        
