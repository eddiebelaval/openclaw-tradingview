import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    mean_length = 9
    sd_mult = 2.0
    color_smooth = 1
    agg_method = "Average"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate OHLC4 as source
        ohlc4 = (self.data.Open + high + low + close) / 4
        
        # TWAP calculation for each hour (simplified - using rolling average instead of intraday logic)
        # In a real backtest, we'd need intraday data; here we simulate by using rolling means
        self.twap_values = []
        for i in range(24):
            twap = self.I(lambda src=pd.Series(ohlc4), length=max(1, len(src)//24): 
                         src.rolling(window=max(1, len(src)//24)).mean() if len(src) > 0 else pd.Series(0, index=src.index))
            self.twap_values.append(twap)
        
        # Aggregate TWAP values to get cluster center
        def calc_cluster(ohlc):
            if len(self.twap_values) == 0:
                return pd.Series(0, index=ohlc.index)
            
            valid_twaps = [tv for tv in self.twap_values if tv is not None]
            if len(valid_twaps) == 0:
                return pd.Series(0, index=ohlc.index)
            
            if self.agg_method == "Average":
                cluster = pd.concat(valid_twaps, axis=1).mean(axis=1)
            else:
                cluster = pd.concat(valid_twaps, axis=1).median(axis=1)
            return cluster
        
        self.cluster_center = self.I(calc_cluster, pd.Series(ohlc4))
        
        # Oscillator value: price - cluster center
        self.osc_val = self.I(lambda ohlc=pd.Series(ohlc4), cc=self.cluster_center: 
                             ohlc - cc if cc is not None else pd.Series(0, index=ohlc.index))
        
        # Signal line: SMA of oscillator
        self.signal = self.I(pta.sma, self.osc_val, length=self.mean_length)
        
        # Cluster envelope (high/low of active TWAPS)
        def calc_env_top(ohlc):
            if len(self.twap_values) == 0:
                return pd.Series(0, index=ohlc.index)
            valid_twaps = [tv for tv in self.twap_values if tv is not None]
            if len(valid_twaps) == 0:
                return pd.Series(0, index=ohlc.index)
            env_high = pd.concat(valid_twaps, axis=1).max(axis=1)
            return env_high - self.cluster_center
        
        def calc_env_bot(ohlc):
            if len(self.twap_values) == 0:
                return pd.Series(0, index=ohlc.index)
            valid_twaps = [tv for tv in self.twap_values if tv is not None]
            if len(valid_twaps) == 0:
                return pd.Series(0, index=ohlc.index)
            env_low = pd.concat(valid_twaps, axis=1).min(axis=1)
            return env_low - self.cluster_center
        
        self.env_top = self.I(calc_env_top, pd.Series(ohlc4))
        self.env_bottom = self.I(calc_env_bot, pd.Series(ohlc4))
        
        # StdDev bands
        def calc_sd_upper(ohlc):
            if len(self.twap_values) == 0:
                return pd.Series(0, index=ohlc.index)
            valid_twaps = [tv for tv in self.twap_values if tv is not None]
            if len(valid_twaps) == 0:
                return pd.Series(0, index=ohlc.index)
            cluster_sd = pd.concat(valid_twaps, axis=1).std(axis=1)
            return self.env_top + (cluster_sd * self.sd_mult)
        
        def calc_sd_lower(ohlc):
            if len(self.twap_values) == 0:
                return pd.Series(0, index=ohlc.index)
            valid_twaps = [tv for tv in self.twap_values if tv is not None]
            if len(valid_twaps) == 0:
                return pd.Series(0, index=ohlc.index)
            cluster_sd = pd.concat(valid_twaps, axis=1).std(axis=1)
            return self.env_bottom - (cluster_sd * self.sd_mult)
        
        self.sd_upper = self.I(calc_sd_upper, pd.Series(ohlc4))
        self.sd_lower = self.I(calc_sd_lower, pd.Series(ohlc4))

    def next(self):
        # Check if oscillator is crossing above/below cluster boundaries
        # Buy when oscillator crosses above lower cluster boundary (oversold reversal)
        if len(self) < 2:
            return
        
        # Long signal: signal crosses above lower boundary or oscillator crosses above env_bottom
        if crossover(self.signal, self.env_bottom):
            if not self.position:
                self.buy()
        # Short signal: signal crosses below upper boundary or oscillator crosses below env_top
        elif crossover(self.env_top, self.signal):
            if self.position:
                self.position.close()
        
        # Also exit on SD band crossovers
        if crossover(self.signal, self.sd_upper):
            if self.position:
                self.position.close()
        elif crossover(self.sd_lower, self.signal):
            if not self.position:
                self.buy()


