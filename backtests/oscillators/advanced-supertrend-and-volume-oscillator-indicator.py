import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_period = 10
    factor = 3.0
    short_vol_len = 5
    long_vol_len = 10
    rsi_len = 14
    stoch_len = 14
    k_smooth = 3
    d_smooth = 3
    eod_hour = 15
    eod_minute = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hlc3 = (high + low + close) / 3

        # SuperTrend calculation
        def calc_supertrend():
            hl2 = (high + low) / 2
            atr = pta.atr(high, low, close, length=self.atr_period)
            if atr is None:
                atr = pd.Series(0, index=close.index)
            
            basic_ub = hl2 + self.factor * atr
            basic_lb = hl2 - self.factor * atr
            
            final_ub = basic_ub.copy()
            final_lb = basic_lb.copy()
            
            for i in range(1, len(final_ub)):
                final_ub.iloc[i] = min(basic_ub.iloc[i], final_ub.iloc[i-1]) if close.iloc[i-1] > final_ub.iloc[i-1] else basic_ub.iloc[i]
                final_lb.iloc[i] = max(basic_lb.iloc[i], final_lb.iloc[i-1]) if close.iloc[i-1] < final_lb.iloc[i-1] else basic_lb.iloc[i]
            
            supertrend = pd.Series(index=close.index, dtype=float)
            direction = pd.Series(index=close.index, dtype=int)
            
            supertrend.iloc[0] = final_ub.iloc[0]
            direction.iloc[0] = 1
            
            for i in range(1, len(close)):
                if supertrend.iloc[i-1] == final_ub.iloc[i-1]:
                    if close.iloc[i] <= final_ub.iloc[i]:
                        supertrend.iloc[i] = final_ub.iloc[i]
                        direction.iloc[i] = 1
                    else:
                        supertrend.iloc[i] = final_lb.iloc[i]
                        direction.iloc[i] = -1
                else:
                    if close.iloc[i] >= final_lb.iloc[i]:
                        supertrend.iloc[i] = final_lb.iloc[i]
                        direction.iloc[i] = -1
                    else:
                        supertrend.iloc[i] = final_ub.iloc[i]
                        direction.iloc[i] = 1
            
            return supertrend, direction
        
        self.supertrend = self.I(calc_supertrend)
        
        # VWAP
        def calc_vwap():
            cum_tp_vol = (hlc3 * volume).cumsum()
            cum_vol = volume.cumsum()
            return cum_tp_vol / cum_vol
        
        self.vwap_value = self.I(calc_vwap)
        
        # Volume Oscillator
        short_vol = pta.ema(volume, length=self.short_vol_len)
        long_vol = pta.ema(volume, length=self.long_vol_len)
        if short_vol is None:
            short_vol = pd.Series(0, index=volume.index)
        if long_vol is None:
            long_vol = pd.Series(0, index=volume.index)
        self.vol_osc = self.I(lambda: 100 * (short_vol - long_vol) / (long_vol + 1e-10))
        
        # Stochastic RSI
        rsi_val = pta.rsi(close, length=self.rsi_len)
        if rsi_val is None:
            rsi_val = pd.Series(50, index=close.index)
        
        def calc_stoch_rsi():
            stoch_result = pta.stoch(rsi_val, rsi_val, rsi_val, k=self.stoch_len, d=14, smooth_k=self.k_smooth)
            if stoch_result is None or stoch_result.empty:
                return pd.Series(50, index=close.index)
            k_col = [col for col in stoch_result.columns if 'STOCHk' in col]
            d_col = [col for col in stoch_result.columns if 'STOCHd' in col]
            if k_col and d_col:
                k_vals = stoch_result[k_col[0]]
                d_vals = stoch_result[d_col[0]]
                k_smooth_vals = pta.sma(k_vals, length=self.k_smooth)
                if k_smooth_vals is None:
                    k_smooth_vals = k_vals
                d_smooth_vals = pta.sma(d_vals, length=self.d_smooth)
                if d_smooth_vals is None:
                    d_smooth_vals = d_vals
                return (k_smooth_vals + d_smooth_vals) / 2
            return pd.Series(50, index=close.index)
        
        self.avg_stoch = self.I(calc_stoch_rsi)
        
        # Rising/Falling indicators (2-bar confirmation)
        def vol_rising():
            return self.vol_osc[-2] < self.vol_osc[-1]
        
        def vol_falling():
            return self.vol_osc[-2] > self.vol_osc[-1]
        
        def stoch_rising():
            return self.avg_stoch[-2] < self.avg_stoch[-1]
        
        def stoch_falling():
            return self.avg_stoch[-2] > self.avg_stoch[-1]
        
        self.vol_rising_flag = vol_rising
        self.vol_falling_flag = vol_falling
        self.stoch_rising_flag = stoch_rising
        self.stoch_falling_flag = stoch_falling
        
        # Store direction
        self.direction = self.I(lambda: self.supertrend[1] if len(self.supertrend) > 1 else pd.Series(0, index=close.index))

    def next(self):
        if len(self.data) < self.atr_period + 10:
            return
        
        close = self.data.Close[-1]
        open_val = self.data.Open[-1]
