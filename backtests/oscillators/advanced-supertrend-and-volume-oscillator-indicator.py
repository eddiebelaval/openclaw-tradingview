        stoch_stuck_bot = avg_stoch_val <= 1
        stoch_stuck_top = avg_stoch_val >= 99
        
        candle_green = close > open_val
        candle_red = close < open_val
        
        try:
            vol_rising = self.vol_rising_flag()
            vol_falling = self.vol_falling_flag()
            stoch_rising = self.stoch_rising_flag()
            stoch_falling = self.stoch_falling_flag()
        except:
            vol_rising = False
            vol_falling = False
            stoch_rising = False
            stoch_falling = False
        
        buy_standard = st_green and price_above and vol_rising and stoch_rising and candle_green
        buy_stuck = stoch_stuck_bot and st_green and price_above and vol_rising and candle_green
        buy_override = stoch_os and vol_rising and stoch_rising and price_above and st_red and candle_green
        raw_long_signal = buy_standard or buy_stuck or buy_override
        
        sell_standard = st_red and price_below and vol_rising and stoch_falling and candle_red
        sell_stuck = stoch_stuck_top and st_red and price_below and vol_falling and candle_red
        sell_override = stoch_ob and vol_rising and stoch_falling and price_below and st_green and candle_red
        raw_short_signal = sell_standard or sell_stuck or sell_override
        
        # Simple trading logic
        if raw_long_signal and not self.position:
            self.buy()
        elif raw_short_signal and self.position:
            self.sell()
        elif self.position and close < vwap_val:
            self.sell()


