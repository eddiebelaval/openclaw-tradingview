import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 12
    slowLen = 26
    cycleLen = 28
    smooth1Len = 3
    smooth2Len = 3
    Upper_Band = 75
    Lower_Band = 25
    MA_Type = 'EMA'
    factor = 0.7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Moving average engine
        def ma(source, length, ma_type, factor):
            if ma_type == 'EMA':
                return pta.ema(source, length=length)
            elif ma_type == 'SMA':
                return pta.sma(source, length=length)
            elif ma_type == 'RMA':
                return pta.rma(source, length=length)
            elif ma_type == 'WMA':
                return pta.wma(source, length=length)
            elif ma_type == 'VWMA':
                return pta.vwma(source, volume, length=length)
            elif ma_type == 'HMA':
                return pta.hma(source, length=length)
            elif ma_type == 'DEMA':
                return pta.dema(source, length=length)
            elif ma_type == 'TEMA':
                return pta.tema(source, length=length)
            elif ma_type == 'TRIMA':
                return pta.trima(source, length=length)
            elif ma_type == 'FRAMA':
                return pta.frama(source, length=length)
            elif ma_type == 'SWMA':
                return pta.swma(source)
            elif ma_type == 'T3':
                return pta.t3(source, length=length, factor=factor)
            else:
                return pta.ema(source, length=length)

        # Calculate Line (difference between fast and slow MA)
        fast_ma = self.I(lambda: ma(close, self.fastLen, self.MA_Type, self.factor))
        slow_ma = self.I(lambda: ma(close, self.slowLen, self.MA_Type, self.factor))
        line = self.I(lambda: fast_ma - slow_ma if fast_ma is not None and slow_ma is not None else pd.Series(0, index=close.index))

        # First stochastic
        k1 = self.I(lambda: pta.stoch(line, line, line, k=self.cycleLen) or pd.Series(50, index=close.index))

        # First smoothing
        d1 = self.I(lambda: ma(k1, self.smooth1Len, self.MA_Type, self.factor))

        # Second stochastic
        k2 = self.I(lambda: pta.stoch(d1, d1, d1, k=self.cycleLen) or pd.Series(50, index=close.index))

        # Second smoothing (final STC)
        stc_raw = self.I(lambda: ma(k2, self.smooth2Len, self.MA_Type, self.factor))

        # Clamp STC between 0 and 100
        self.stc = self.I(lambda: np.clip(stc_raw, 0, 100) if stc_raw is not None else pd.Series(50, index=close.index))

    def next(self):
        # Check for crossover above Upper Band (bullish signal)
        if len(self.data) > 1:
            if crossover(self.stc, self.Upper_Band):
                if not self.position:
                    self.buy()
            # Check for crossunder below Lower Band (bearish signal)
            elif crossover(self.Lower_Band, self.stc):
                if self.position:
                    self.position.close()


