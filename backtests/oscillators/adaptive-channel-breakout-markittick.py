import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_in = 20
    mult_in = 3.2
    log_in = False
    adx_th = 25
    time_ex = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate logarithmic or linear price sources
        if self.log_in:
            src_h = np.log(high)
            src_l = np.log(low)
            src_c = np.log(close)
        else:
            src_h = high
            src_l = low
            src_c = close
        
        # Calculate DMI/ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.len_in))
        self.di_plus = self.I(lambda: pta.adx(high, low, close, length=self.len_in)['DMP_' + str(self.len_in)])
        self.di_minus = self.I(lambda: pta.adx(high, low, close, length=self.len_in)['DMN_' + str(self.len_in)])
        self.adx_val = self.I(lambda: pta.adx(high, low, close, length=self.len_in)['ADX_' + str(self.len_in)])
        
        # Calculate True Range and ATR (manual for log scale compatibility)
        def calc_tr_log():
            if self.log_in:
                tr_log = np.maximum(
                    src_h - src_l,
                    np.maximum(
                        np.abs(src_h - src_c.shift(1)),
                        np.abs(src_l - src_c.shift(1))
                    )
                )
                return tr_log
            else:
                tr = np.maximum(
                    high - low,
                    np.maximum(
                        np.abs(high - close.shift(1)),
                        np.abs(low - close.shift(1))
                    )
                )
                return tr
        
        tr = self.I(calc_tr_log)
        atr_log = self.I(lambda: pta.sma(tr, length=self.len_in))
        
        # ATR band
        atr_band = self.I(lambda: atr_log * self.mult_in if atr_log is not None else pd.Series(0, index=close.index))
        
        # Highest and Lowest
        highest_h = self.I(lambda: high.rolling(window=self.len_in).max())
        lowest_l = self.I(lambda: low.rolling(window=self.len_in).min())
        
        # Channel calculation
        def calc_ch_upper():
            if self.log_in:
                return np.exp(highest_h - atr_band)
            else:
                return highest_h - atr_band
        
        def calc_ch_lower():
            if self.log_in:
                return np.exp(lowest_l + atr_band)
            else:
                return lowest_l + atr_band
        
        self.ch_upper = self.I(calc_ch_upper)
        self.ch_lower = self.I(calc_ch_lower)
        
        self.atr_final = self.I(lambda: np.exp(atr_log) if self.log_in else atr_log)
        
        # State tracking
        self.trade_dir = 0
        self.bars_since_entry = 0

    def next(self):
        # Determine market regime
        is_trending = self.adx_val[-1] >= self.adx_th if len(self.adx_val) > 0 else False
        regime_bull = is_trending and (self.di_plus[-1] > self.di_minus[-1])
        regime_bear = is_trending and (self.di_minus[-1] > self.di_plus[-1])
        regime_range = not is_trending
        
        # Filters
        filter_long = regime_range or regime_bull
        filter_short = regime_range or regime_bear
        
        # Signals
        long_signal = crossover(self.data.Close, self.ch_upper) and filter_long
        short_signal = crossover(self.ch_lower, self.data.Close) and filter_short
        
        # State management
        if long_signal:
            self.trade_dir = 1
            self.bars_since_entry = 0
        elif short_signal:
            self.trade_dir = -1
            self.bars_since_entry = 0
        else:
            self.bars_since_entry += 1
        
        is_stale = self.bars_since_entry == self.time_ex and self.trade_dir != 0
        
        # Entry and exit logic
        if long_signal:
            if self.position:
                self.position.close()
            self.buy()
        elif short_signal:
            if self.position:
                self.position.close()
            self.sell()
        elif is_stale:
            if self.position:
                self.position.close()


