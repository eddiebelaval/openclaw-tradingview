        if result == "Strong Downward" and bear_score > 0:
            should_sell = True
        
        # No Demand confirmation
        if len(self.data) >= 2 and no_demand and close < close_prev1:
            should_sell = True
        
        # No Supply confirmation
        if len(self.data) >= 2 and no_supply and close > close_prev1:
            should_buy = True
        
        # Execute trades
        if should_buy and not self.position:
            self.buy()
        elif should_sell and self.position:
            self.sell()
        
        # Profit taking on significant moves
        if self.position:
            entry_price = self.position.open_price
            current_price = close
            
            if self.position.is_long:
                pnl_pct = (current_price - entry_price) / entry_price
                if pnl_pct > 0.05 or (result == "Strong Downward" and bear_score > 0):
                    self.sell()
            else:
                pnl_pct = (entry_price - current_price) / entry_price
                if pnl_pct > 0.05 or (result == "Strong Upward" and bull_score > 0):
                    self.buy()


