import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLength = 12
    slowLength = 26
    signalLength = 9
    atrLength = 26
    bbLen = 20
    bbMult = 2.0
    compressionLen = 20
    histCompressionThresh = 0.60
    bandCompressionThresh = 0.70
    expansionThresh = 1.20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate MACD-V components
        fastEMA = self.I(pta.ema, close, length=self.fastLength)
        slowEMA = self.I(pta.ema, close, length=self.slowLength)
        macdLine = fastEMA - slowEMA
        
        atrValue = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # MACD-V: MACD normalized by ATR
        def calc_macdv(macdline, atr):
            result = pd.Series(index=macdline.index, dtype='float64')
            for i in range(len(macdline)):
                if pd.notna(macdline.iloc[i]) and pd.notna(atr.iloc[i]) and atr.iloc[i] != 0:
                    result.iloc[i] = (macdline.iloc[i] / atr.iloc[i]) * 100
                else:
                    result.iloc[i] = np.nan
            return result
        
        self.macdV = self.I(calc_macdv, macdLine, atrValue)
        
        # Signal line
        self.signal = self.I(pta.ema, self.macdV, length=self.signalLength)
        
        # Histogram
        self.hist = self.macdV - self.signal
        
        # Bollinger Bands on MACD-V
        bbBasis = self.I(pta.ema, self.macdV, length=self.bbLen)
        
        def calc_bbdev(macdv, length, mult):
            result = pd.Series(index=macdv.index, dtype='float64')
            for i in range(length - 1, len(macdv)):
                window = macdv.iloc[i - length + 1:i + 1]
                if len(window) == length and pd.notna(window).all():
                    result.iloc[i] = window.std() * mult
                else:
                    result.iloc[i] = np.nan
            return result
        
        bbDev = self.I(calc_bbdev, self.macdV, self.bbLen, self.bbMult)
        self.bbUpper = bbBasis + bbDev
        self.bbLower = bbBasis - bbDev
        self.bandWidth = self.bbUpper - self.bbLower
        
        # Histogram compression detection
        histAbs = self.I(lambda x: x.abs(), self.hist)
        histAbsAvg = self.I(pta.ema, histAbs, length=self.compressionLen)
        
        def calc_hist_compressed(histabs, histabsavg, thresh):
            result = pd.Series(index=histabs.index, dtype='bool')
            for i in range(len(histabs)):
                if pd.notna(histabs.iloc[i]) and pd.notna(histabsavg.iloc[i]) and histabsavg.iloc[i] != 0:
                    result.iloc[i] = histabs.iloc[i] < histabsavg.iloc[i] * thresh
                else:
                    result.iloc[i] = False
            return result
        
        def calc_hist_expanded(histabs, histabsavg, thresh):
            result = pd.Series(index=histabs.index, dtype='bool')
            for i in range(len(histabs)):
                if pd.notna(histabs.iloc[i]) and pd.notna(histabsavg.iloc[i]) and histabsavg.iloc[i] != 0:
                    result.iloc[i] = histabs.iloc[i] > histabsavg.iloc[i] * thresh
                else:
                    result.iloc[i] = False
            return result
        
        self.histCompressed = self.I(calc_hist_compressed, histAbs, histAbsAvg, self.histCompressionThresh)
        self.histExpanded = self.I(calc_hist_expanded, histAbs, histAbsAvg, self.expansionThresh)
        
        # Band width compression detection
        bandWidthAvg = self.I(pta.ema, self.bandWidth, length=self.compressionLen)
        
        def calc_band_compressed(bandwidth, bandwidthavg, thresh):
            result = pd.Series(index=bandwidth.index, dtype='bool')
            for i in range(len(bandwidth)):
                if pd.notna(bandwidth.iloc[i]) and pd.notna(bandwidthavg.iloc[i]) and bandwidthavg.iloc[i] != 0:
                    result.iloc[i] = bandwidth.iloc[i] < bandwidthavg.iloc[i] * thresh
                else:
                    result.iloc[i] = False
            return result
        
        def calc_band_expanded(bandwidth, bandwidthavg, thresh):
            result = pd.Series(index=bandwidth.index, dtype='bool')
            for i in range(len(bandwidth)):
                if pd.notna(bandwidth.iloc[i]) and pd.notna(bandwidthavg.iloc[i]) and bandwidthavg.iloc[i] != 0:
                    result.iloc[i] = bandwidth.iloc[i] > bandwidthavg.iloc[i] * thresh
                else:
                    result.iloc[i] = False
            return result
        
        self.bandCompressed = self.I(calc_band_compressed, self.bandWidth, bandWidthAvg, self.bandCompressionThresh)
        self.bandExpanded = self.I(calc_band_expanded, self.bandWidth, bandWidthAvg, self.expansionThresh)
        
        # Combined compression and expansion states
        def calc_is_compressed(histcomp, bandcomp):
            result = pd.Series(index=histcomp.index, dtype='bool')
            for i in range(len(histcomp)):
                result.iloc[i] = histcomp.iloc[i] and bandcomp.iloc[i]
            return result
        
        def calc_is_expanded(histexp, bandexp):
            result = pd.Series(index=histexp.index, dtype='bool')
            for i in range(len(histexp)):
                result.iloc[i] = histexp.iloc[i] or bandexp.iloc[i]
            return result
        
        self.isCompressed = self.I(calc_is_compressed, self.histCompressed, self.bandCompressed)
        self.isExpanded = self.I(calc_is_expanded, self.histExpanded, self.bandExpanded)
        
        # Ignition signals
        def calc_bull_ignition(iscomp, isexp, hist):
            result = pd.Series(index=hist.index, dtype='bool')
            for i in range(1, len(hist)):
                if pd.notna(iscomp.iloc[i]) and pd.notna(isexp.iloc[i]) and pd.notna(hist.iloc[i]):
                    result.iloc[i] = iscomp.iloc[i - 1] and isexp.iloc[i] and hist.iloc[i] > 0
                else:
                    result.iloc[i] = False
            return result
        
        def calc_bear_ignition(iscomp, isexp, hist):
            result = pd.Series(index=hist.index, dtype='bool')
            for i in range(1, len(hist)):
                if pd.notna(iscomp.iloc[i]) and pd.notna(isexp.iloc[i]) and pd.notna(hist.iloc[i]):
                    result.iloc[i] = iscomp.iloc[i - 1] and isexp.iloc[i] and hist.iloc[i] < 0
                else:
                    result.iloc[i] = False
            return result
        
        self.bullIgnition = self.I(calc_bull_ignition, self.isCompressed, self.isExpanded, self.hist)
        self.bearIgnition = self.I(calc_bear_ignition, self.isCompressed, self.isExpanded, self.hist)

    def next(self):
        # Entry signals based on MACD-V ignition and regime
        if len(self) < 2:
            return
        
        # Bull ignition after compression
        if self.bullIgnition[-1]:
            if not self.position:
                self.buy()
        
        # Bear ignition after compression
        elif self.bearIgnition[-1]:
            if self.position:
                self.position.close()
        
        # Alternative: MACD-V crosses above +50
