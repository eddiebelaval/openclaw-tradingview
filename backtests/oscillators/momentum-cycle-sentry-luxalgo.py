import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 20
    smoothingInput = 5
    magnitudeInput = 1.0
    retraceLenInput = 2
    obLengthInput = 50
    obMultInnerInput = 2.0
    obMultOuterInput = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Base momentum calculation
        self.mom = self.I(lambda: pta.mom(close, length=self.lengthInput))

        # Function to calculate smoothed layers
        def get_layer_1():
            mom_val = pta.mom(close, length=self.lengthInput)
            if mom_val is None:
                return pd.Series(0, index=close.index)
            layer = pta.ema(mom_val, length=self.smoothingInput) * self.magnitudeInput
            return layer if layer is not None else pd.Series(0, index=close.index)

        def get_layer_2():
            mom_val = pta.mom(close, length=self.lengthInput)
            if mom_val is None:
                return pd.Series(0, index=close.index)
            layer = pta.ema(mom_val, length=self.smoothingInput * 2) * self.magnitudeInput
            return layer if layer is not None else pd.Series(0, index=close.index)

        def get_layer_3():
            mom_val = pta.mom(close, length=self.lengthInput)
            if mom_val is None:
                return pd.Series(0, index=close.index)
            layer = pta.ema(mom_val, length=self.smoothingInput * 3) * self.magnitudeInput
            return layer if layer is not None else pd.Series(0, index=close.index)

        def get_layer_4():
            mom_val = pta.mom(close, length=self.lengthInput)
            if mom_val is None:
                return pd.Series(0, index=close.index)
            layer = pta.ema(mom_val, length=self.smoothingInput * 4) * self.magnitudeInput
            return layer if layer is not None else pd.Series(0, index=close.index)

        def get_layer_5():
            mom_val = pta.mom(close, length=self.lengthInput)
            if mom_val is None:
                return pd.Series(0, index=close.index)
            layer = pta.ema(mom_val, length=self.smoothingInput * 5) * self.magnitudeInput
            return layer if layer is not None else pd.Series(0, index=close.index)

        self.p1 = self.I(get_layer_1)
        self.p2 = self.I(get_layer_2)
        self.p3 = self.I(get_layer_3)
        self.p4 = self.I(get_layer_4)
        self.p5 = self.I(get_layer_5)

        # Dynamic OB/OS Calculation
        def get_stdev():
            result = pta.stdev(self.p1, length=self.obLengthInput)
            return result if result is not None else pd.Series(0, index=close.index)

        self.stdev_val = self.I(get_stdev)

        # Trend & Retracement Logic
        def get_rising():
            if len(self.p1) < self.retraceLenInput:
                return pd.Series(False, index=close.index)
            return pd.Series([self.p1[i] > self.p1[i - self.retraceLenInput] if i >= self.retraceLenInput else False for i in range(len(self.p1))], index=close.index)

        def get_falling():
            if len(self.p1) < self.retraceLenInput:
                return pd.Series(False, index=close.index)
            return pd.Series([self.p1[i] < self.p1[i - self.retraceLenInput] if i >= self.retraceLenInput else False for i in range(len(self.p1))], index=close.index)

        self.rising_p1 = self.I(get_rising)
        self.falling_p1 = self.I(get_falling)

    def next(self):
        if len(self.data) < self.lengthInput + max(self.smoothingInput * 5, self.obLengthInput):
            return

        # Current values
        p1_curr = self.p1[-1]
        stdev_curr = self.stdev_val[-1]
        rising = self.rising_p1[-1]
        falling = self.falling_p1[-1]

        # Trend determination
        is_uptrend = p1_curr > 0
        is_downtrend = p1_curr < 0

        # Retracement logic
        is_retracing = (is_uptrend and falling) or (is_downtrend and rising)

        # OB/OS levels
        ob_inner = stdev_curr * self.obMultInnerInput
        os_outer = -stdev_curr * self.obMultOuterInput

        # Trading logic: buy on uptrend momentum, sell on downtrend momentum
        if is_uptrend and not is_retracing and p1_curr > ob_inner:
            if not self.position:
                self.buy()
        elif is_downtrend and not is_retracing and p1_curr < os_outer:
            if self.position:
                self.sell()
        elif is_retracing and self.position:
            self.sell()
        elif is_retracing and not self.position and is_downtrend:
            self.buy()


