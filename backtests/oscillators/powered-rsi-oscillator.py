import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    ob = 80
    os = 20
    pivotLen = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Custom WiMA implementation
        def wima(src, length):
            result = pd.Series(index=src.index, dtype=float)
            ma = 0
            for i in range(len(src)):
                ma = (src.iloc[i] + ma * (length - 1)) / length
                result.iloc[i] = ma
            return result
        
        # RSI Volume calculation
        def calc_rsi_volume(fv, length):
            up = pd.Series(index=fv.index, dtype=float)
            dn = pd.Series(index=fv.index, dtype=float)
            
            for i in range(len(fv)):
                if i == 0:
                    up.iloc[i] = 0
                    dn.iloc[i] = 0
                else:
                    if fv.iloc[i] > fv.iloc[i-1]:
                        up.iloc[i] = abs(fv.iloc[i] - fv.iloc[i-1]) * volume.iloc[i]
                    else:
                        up.iloc[i] = 0
                    
                    if fv.iloc[i] < fv.iloc[i-1]:
                        dn.iloc[i] = abs(fv.iloc[i] - fv.iloc[i-1]) * volume.iloc[i]
                    else:
                        dn.iloc[i] = 0
            
            upt = wima(up, length)
            dnt = wima(dn, length)
            
            result = pd.Series(index=fv.index, dtype=float)
            for i in range(len(fv)):
                if upt.iloc[i] + dnt.iloc[i] != 0:
                    result.iloc[i] = 100 * (upt.iloc[i] / (upt.iloc[i] + dnt.iloc[i]))
                else:
                    result.iloc[i] = 50
            
            return result
        
        # Pivot detection
        def find_pivot_low(data, length):
            result = pd.Series(index=data.index, dtype=float)
            for i in range(length, len(data) - length):
                is_pivot = True
                for j in range(1, length + 1):
                    if data.iloc[i] >= data.iloc[i - j] or data.iloc[i] >= data.iloc[i + j]:
                        is_pivot = False
                        break
                result.iloc[i] = data.iloc[i] if is_pivot else np.nan
            return result
        
        def find_pivot_high(data, length):
            result = pd.Series(index=data.index, dtype=float)
            for i in range(length, len(data) - length):
                is_pivot = True
                for j in range(1, length + 1):
                    if data.iloc[i] <= data.iloc[i - j] or data.iloc[i] <= data.iloc[i + j]:
                        is_pivot = False
                        break
                result.iloc[i] = data.iloc[i] if is_pivot else np.nan
            return result
        
        self.rsi_v = self.I(calc_rsi_volume, close, self.length)
        self.price_low = self.I(find_pivot_low, low, self.pivotLen)
        self.price_high = self.I(find_pivot_high, high, self.pivotLen)
        self.osc_low = self.I(find_pivot_low, self.rsi_v, self.pivotLen)
        self.osc_high = self.I(find_pivot_high, self.rsi_v, self.pivotLen)
        
        self.prev_price_low = None
        self.prev_osc_low = None
        self.prev_low_bar = None
        self.prev_price_high = None
        self.prev_osc_high = None
        self.prev_high_bar = None
        
        self.in_divergence = False

    def next(self):
        current_rsi = self.rsi_v[-1]
        
        # Check for pivot lows (bullish signals)
        if not np.isnan(self.price_low[-1]) and not np.isnan(self.osc_low[-1]):
            curr_bar = len(self.data) - 1 - self.pivotLen
            
            # Regular Bullish: Price makes Lower Low, Oscillator makes Higher Low
            if (self.prev_price_low is not None and 
                self.price_low[-1] < self.prev_price_low and 
                self.osc_low[-1] > self.prev_osc_low):
                if not self.position:
                    self.buy()
                    self.in_divergence = True
            
            # Hidden Bullish: Price makes Higher Low, Oscillator makes Lower Low
            if (self.prev_price_low is not None and 
                self.price_low[-1] > self.prev_price_low and 
                self.osc_low[-1] < self.prev_osc_low):
                if not self.position:
                    self.buy()
                    self.in_divergence = True
            
            self.prev_price_low = self.price_low[-1]
            self.prev_osc_low = self.osc_low[-1]
            self.prev_low_bar = curr_bar
        
        # Check for pivot highs (bearish signals)
        if not np.isnan(self.price_high[-1]) and not np.isnan(self.osc_high[-1]):
            curr_bar = len(self.data) - 1 - self.pivotLen
            
            # Regular Bearish: Price makes Higher High, Oscillator makes Lower High
            if (self.prev_price_high is not None and 
                self.price_high[-1] > self.prev_price_high and 
                self.osc_high[-1] < self.prev_osc_high):
                if self.position:
                    self.sell()
                    self.in_divergence = False
            
            # Hidden Bearish: Price makes Lower High, Oscillator makes Higher High
            if (self.prev_price_high is not None and 
                self.price_high[-1] < self.prev_price_high and 
                self.osc_high[-1] > self.prev_osc_high):
                if self.position:
                    self.sell()
                    self.in_divergence = False
            
            self.prev_price_high = self.price_high[-1]
            self.prev_osc_high = self.osc_high[-1]
            self.prev_high_bar = curr_bar
        
        # Exit on overbought/oversold levels
        if self.position:
            if current_rsi > self.ob:
                self.sell()
            elif current_rsi < self.os:
                self.sell()


