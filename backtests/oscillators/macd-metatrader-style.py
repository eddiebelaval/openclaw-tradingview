import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLenInput = 12
    slowLenInput = 26
    sigLenInput = 9

    def init(self):
        close = pd.Series(self.data.Close)
        
        fastEMA = self.I(pta.ema, close, length=self.fastLenInput)
        slowEMA = self.I(pta.ema, close, length=self.slowLenInput)
        
        macd = self.I(lambda: fastEMA - slowEMA)
        signal = self.I(pta.sma, macd, length=self.sigLenInput)
        
        self.macd = macd
        self.signal = signal

    def next(self):
        if crossover(self.macd, self.signal):
            if not self.position:
                self.buy()
        elif crossover(self.signal, self.macd):
            if self.position:
                self.position.close()