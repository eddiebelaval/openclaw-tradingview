import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    cci_length = 11
    ci_length = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate typical price: (high + low + close) / 3
        def calc_typical_price():
            return (high + low + close) / 3
        
        typical_price = self.I(calc_typical_price)
        
        # Calculate average deviation for CCI
        def calc_avg_dev(tp_series):
            result = pd.Series(index=tp_series.index, dtype=float)
            sma_tp = pta.sma(tp_series, length=self.cci_length)
            
            for i in range(len(tp_series)):
                if i < self.cci_length - 1:
                    result.iloc[i] = np.nan
                else:
                    sum_dev = sum(abs(tp_series.iloc[i - j] - sma_tp.iloc[i]) for j in range(self.cci_length))
                    result.iloc[i] = sum_dev / self.cci_length
            return result
        
        avg_dev = self.I(lambda: calc_avg_dev(typical_price))
        
        # Calculate CCI
        def calc_cci():
            sma_tp = pta.sma(typical_price, length=self.cci_length)
            avg_dev_vals = calc_avg_dev(typical_price)
            cci = (typical_price - sma_tp) / (0.015 * (avg_dev_vals + 1e-10))
            return cci
        
        self.cci = self.I(calc_cci)
        
        # Calculate CI line: EMA of CCI
        def calc_ci():
            cci_vals = calc_cci()
            ci = pta.ema(cci_vals, length=self.ci_length)
            return ci
        
        self.ci = self.I(calc_ci)

    def next(self):
        if len(self.data) < self.cci_length + self.ci_length:
            return
        
        # Strong Buy: CCI crosses above CI in oversold zone (CCI < -100)
        if crossover(self.cci, self.ci) and self.cci[-1] < -100:
            if not self.position:
                self.buy()
        
        # Normal Buy: CCI crosses above CI in weak zone (-100 <= CCI < 0)
        elif crossover(self.cci, self.ci) and -100 <= self.cci[-1] < 0:
            if not self.position:
                self.buy()
        
        # Strong Sell: CCI crosses below CI in overbought zone (CCI > 100)
        elif crossover(self.ci, self.cci) and self.cci[-1] > 100:
            if self.position:
                self.position.close()
        
        # Normal Sell: CCI crosses below CI in strong zone (0 < CCI <= 100)
        elif crossover(self.ci, self.cci) and 0 < self.cci[-1] <= 100:
            if self.position:
                self.position.close()


