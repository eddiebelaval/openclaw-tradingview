import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenrsi = 3
    lenupdown = 2
    lenroc = 100
    upper_level = 80
    lower_level = 20

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.lenrsi)
        
        # Calculate UpDown sequence
        def calculate_updown(s):
            updown_series = pd.Series(0.0, index=s.index)
            for i in range(1, len(s)):
                if s.iloc[i] == s.iloc[i-1]:
                    updown_series.iloc[i] = 0
                elif s.iloc[i] > s.iloc[i-1]:
                    updown_series.iloc[i] = 1 if updown_series.iloc[i-1] <= 0 else updown_series.iloc[i-1] + 1
                else:
                    updown_series.iloc[i] = -1 if updown_series.iloc[i-1] >= 0 else updown_series.iloc[i-1] - 1
            return updown_series
        
        updown_seq = self.I(calculate_updown, close)
        
        # Calculate RSI of UpDown
        self.updownrsi = self.I(pta.rsi, updown_seq, length=self.lenupdown)
        
        # Calculate ROC and PercentRank
        def calculate_percentrank(s, length):
            roc = s.pct_change() * 100
            percentrank = pd.Series(0.0, index=s.index)
            for i in range(length, len(roc)):
                window = roc.iloc[i-length:i+1]
                rank = (window < roc.iloc[i]).sum()
                percentrank.iloc[i] = (rank / (length + 1)) * 100
            return percentrank
        
        self.percentrank = self.I(calculate_percentrank, close, self.lenroc)
        
        # Calculate Connors RSI as average of three components
        def calculate_crsi(rsi, updownrsi, percentrank):
            crsi = (rsi + updownrsi + percentrank) / 3.0
            return crsi
        
        self.crsi = self.I(calculate_crsi, self.rsi, self.updownrsi, self.percentrank)

    def next(self):
        if len(self.data) < self.lenroc + 5:
            return
        
        current_crsi = self.crsi[-1]
        prev_crsi = self.crsi[-2] if len(self.crsi) > 1 else current_crsi
        
        # Buy when CRSI crosses above lower level from below (oversold bounce)
        if crossover(self.crsi, self.lower_level):
            if not self.position:
                self.buy()
        
        # Sell when CRSI crosses below upper level from above (overbought reversal)
        elif crossover(self.upper_level, self.crsi):
            if self.position:
                self.position.close()


