import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Moving Averages
    ma_c1 = 9
    ma_c2 = 22
    
    # RSI
    rsi_len = 14
    rsi_scale = 1.0
    rsi_shift = 20
    
    # MACD SLOW
    f_len1 = 12
    s_len1 = 31
    sig_len1 = 14
    scale_m1 = 1200
    shift_m1 = -60
    
    # MACD FAST
    f_len2 = 4
    s_len2 = 9
    sig_len2 = 14
    scale_m2 = 1200
    shift_m2 = -220

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Moving Averages
        self.ma1 = self.I(pta.sma, close, length=self.ma_c1)
        self.ma2 = self.I(pta.sma, close, length=self.ma_c2)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        # MACD SLOW
        macd_slow = self.I(pta.macd, close, fast=self.f_len1, slow=self.s_len1, signal=self.sig_len1)
        self.macd1 = macd_slow.iloc[:, 0] if macd_slow is not None and len(macd_slow.columns) > 0 else self.I(lambda: pd.Series(0, index=close.index))
        self.signal1 = macd_slow.iloc[:, 2] if macd_slow is not None and len(macd_slow.columns) > 2 else self.I(lambda: pd.Series(0, index=close.index))
        
        # MACD FAST
        macd_fast = self.I(pta.macd, close, fast=self.f_len2, slow=self.s_len2, signal=self.sig_len2)
        self.macd2 = macd_fast.iloc[:, 0] if macd_fast is not None and len(macd_fast.columns) > 0 else self.I(lambda: pd.Series(0, index=close.index))
        self.signal2 = macd_fast.iloc[:, 2] if macd_fast is not None and len(macd_fast.columns) > 2 else self.I(lambda: pd.Series(0, index=close.index))

    def next(self):
        # Buy signal: MA1 crosses above MA2, RSI below 70, MACD Fast Line above Signal
        if (len(self.data) > 1 and 
            crossover(self.ma1, self.ma2) and 
            self.rsi[-1] < 70 and 
            self.macd2[-1] > self.signal2[-1]):
            self.buy()
        
        # Sell signal: MA1 crosses below MA2, or RSI above 70, or MACD Fast Line below Signal
        elif (len(self.data) > 1 and self.position and
              (crossover(self.ma2, self.ma1) or 
               self.rsi[-1] > 70 or 
               crossover(self.signal2, self.macd2))):
            self.sell()


