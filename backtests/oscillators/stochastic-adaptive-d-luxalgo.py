import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    kLengthInput = 20
    dSmoothingInput = 9
    preSmoothInput = 20
    attenuationInput = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Price Pre-Smoothing
        sHigh = self.I(pta.sma, high, length=self.preSmoothInput)
        sLow = self.I(pta.sma, low, length=self.preSmoothInput)
        sClose = self.I(pta.sma, close, length=self.preSmoothInput)
        
        # Standard Stochastic calculation
        def calc_stoch_raw():
            stoch_result = pta.stoch(sClose, sHigh, sLow, k=self.kLengthInput, d=self.dSmoothingInput)
            if stoch_result is not None and 'STOCHk_' + str(self.kLengthInput) + '_' + str(self.dSmoothingInput) in stoch_result.columns:
                return stoch_result['STOCHk_' + str(self.kLengthInput) + '_' + str(self.dSmoothingInput)]
            return pd.Series(50, index=close.index)
        
        stochRaw = self.I(calc_stoch_raw)
        
        def calc_stoch():
            return 50 + (stochRaw - 50) / 2
        
        stoch = self.I(calc_stoch)
        
        def calc_stoch_d():
            sma_stoch = pta.sma(stochRaw, length=self.dSmoothingInput)
            if sma_stoch is not None:
                return 50 + (sma_stoch - 50) / 2
            return pd.Series(50, index=close.index)
        
        stochD = self.I(calc_stoch_d)
        
        # Adaptive Moving Average (AMA) logic
        def calc_ama():
            amaValue = pd.Series(50.0, index=close.index)
            for i in range(len(close)):
                if i == 0:
                    amaValue.iloc[i] = 50.0
                else:
                    alpha = (abs(stochD.iloc[i] - 50) / 100) / self.attenuationInput
                    srcAma = (stochD.iloc[i] - 50) / self.attenuationInput + 50
                    amaValue.iloc[i] = amaValue.iloc[i-1] + alpha * (srcAma - amaValue.iloc[i-1])
            return amaValue
        
        self.amaValue = self.I(calc_ama)
        
        # Difference calculation
        def calc_diff():
            return 50 + (stochD - self.amaValue) * 2
        
        self.diffPlotValue = self.I(calc_diff)

    def next(self):
        # Buy when adaptive %D crosses above midline (50) from below
        if crossover(self.amaValue, 50):
            if not self.position:
                self.buy()
        
        # Sell when adaptive %D crosses below midline (50) from above
        elif crossover(50, self.amaValue):
            if self.position:
                self.position.close()


