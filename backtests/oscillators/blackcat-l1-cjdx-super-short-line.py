import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    signal_gap_period = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate weighted typical price: (2*close + high + low) / 4
        def calc_weighted_typical_price():
            return (2 * self.data.Close + self.data.High + self.data.Low) / 4
        
        weighted_tp = self.I(calc_weighted_typical_price)
        
        # Triple EMA of weighted typical price
        def calc_triple_ema(series):
            df = pd.DataFrame({'price': series})
            ema1 = pta.ema(df['price'], length=4)
            if ema1 is None:
                return pd.Series(0, index=series.index)
            ema2 = pta.ema(ema1, length=4)
            if ema2 is None:
                return pd.Series(0, index=series.index)
            ema3 = pta.ema(ema2, length=4)
            if ema3 is None:
                return pd.Series(0, index=series.index)
            return ema3
        
        triple_ema = self.I(lambda: calc_triple_ema(weighted_tp))
        
        # Calculate J line momentum: (current - previous) / previous * 100
        def calc_j_momentum(series):
            j_momentum = pd.Series(index=series.index, dtype=float)
            for i in range(1, len(series)):
                if series.iloc[i-1] != 0:
                    j_momentum.iloc[i] = (series.iloc[i] - series.iloc[i-1]) / series.iloc[i-1] * 100
                else:
                    j_momentum.iloc[i] = 0
            return j_momentum
        
        j_line = self.I(lambda: calc_j_momentum(triple_ema))
        
        # K line: 3-day EMA of J line
        k_line = self.I(lambda: pta.ema(j_line, length=3) or pd.Series(0, index=j_line.index))
        
        # D line: 5-day EMA of J line
        d_line = self.I(lambda: pta.ema(j_line, length=5) or pd.Series(0, index=j_line.index))
        
        self.j_line = j_line
        self.k_line = k_line
        self.d_line = d_line
        
        self.last_buy_bar = -np.inf
        self.last_sell_bar = -np.inf

    def next(self):
        current_bar = len(self.data) - 1
        
        if current_bar < 2:
            return
        
        j_current = self.j_line[-1] if len(self.j_line) > 0 else 0
        j_prev = self.j_line[-2] if len(self.j_line) > 1 else 0
        k_current = self.k_line[-1] if len(self.k_line) > 0 else 0
        k_prev = self.k_line[-2] if len(self.k_line) > 1 else 0
        d_current = self.d_line[-1] if len(self.d_line) > 0 else 0
        d_prev = self.d_line[-2] if len(self.d_line) > 1 else 0
        
        # Golden cross: K crosses above D
        is_golden_cross = k_prev <= d_prev and k_current > d_current
        
        # Death cross: K crosses below D
        is_death_cross = k_prev >= d_prev and k_current < d_current
        
        # Raw signals with momentum confirmation
        raw_buy_signal = is_golden_cross and j_current > 0
        raw_sell_signal = is_death_cross and j_current < 0
        
        # Filter signals: at least signal_gap_period bars apart
        filtered_buy_signal = raw_buy_signal and (current_bar - self.last_buy_bar) >= self.signal_gap_period
        filtered_sell_signal = raw_sell_signal and (current_bar - self.last_sell_bar) >= self.signal_gap_period
        
        if filtered_buy_signal:
            if self.position:
                self.position.close()
            self.buy()
            self.last_buy_bar = current_bar
        
        if filtered_sell_signal:
            if self.position:
                self.position.close()
            self.last_sell_bar = current_bar


