import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI Engine Parameters
    rsi_length = 14
    smooth_mode = "EMA"
    smooth_len = 5
    signal_len = 9
    signal_mode = "EMA"
    
    # Zones Parameters
    overbought = 70
    oversold = 30
    extreme_high = 80
    extreme_low = 20
    
    # Trade Engine Parameters
    entry_mode = "Close"
    sl_mode = "ATR"
    rr_target = 5.0
    atr_len = 14
    atr_mult = 1.0
    percent_sl = 0.50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI
        rsi_raw = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Apply smoothing to RSI
        if self.smooth_mode == "EMA":
            rsi_smooth = self.I(pta.ema, rsi_raw, length=self.smooth_len)
        elif self.smooth_mode == "SMA":
            rsi_smooth = self.I(pta.sma, rsi_raw, length=self.smooth_len)
        elif self.smooth_mode == "RMA":
            rsi_smooth = self.I(pta.rma, rsi_raw, length=self.smooth_len)
        else:
            rsi_smooth = rsi_raw
        
        # Calculate signal line
        if self.signal_mode == "EMA":
            signal = self.I(pta.ema, rsi_smooth, length=self.signal_len)
        elif self.signal_mode == "SMA":
            signal = self.I(pta.sma, rsi_smooth, length=self.signal_len)
        else:
            signal = self.I(pta.rma, rsi_smooth, length=self.signal_len)
        
        # Calculate ATR
        atr_value = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Store indicators
        self.rsi_smooth = rsi_smooth
        self.signal = signal
        self.atr_value = atr_value
        
        # Track trades
        self.trades_log = []

    def next(self):
        if len(self.data) < self.signal_len + self.smooth_len + 2:
            return
        
        rsi = self.rsi_smooth[-1]
        sig = self.signal[-1]
        atr = self.atr_value[-1]
        
        if np.isnan(rsi) or np.isnan(sig) or np.isnan(atr):
            return
        
        # Entry signals
        up_signal = crossover(self.rsi_smooth, self.extreme_low)
        down_signal = crossover(self.extreme_high, self.rsi_smooth)
        
        # Long entry
        if up_signal and not self.position:
            entry_price = self.data.Close[-1]
            
            # Calculate stop loss based on mode
            if self.sl_mode == "Signal Candle":
                sl_price = self.data.Low[-1]
            elif self.sl_mode == "ATR":
                sl_price = entry_price - atr * self.atr_mult
            else:  # Percent
                sl_price = entry_price * (1.0 - self.percent_sl / 100.0)
            
            risk = entry_price - sl_price
            
            if risk > 0:
                tp_price = entry_price + risk * self.rr_target
                self.buy()
                self.trades_log.append({
                    'entry': entry_price,
                    'tp': tp_price,
                    'sl': sl_price,
                    'direction': 'long',
                    'bar': len(self.data)
                })
        
        # Short entry
        if down_signal and not self.position:
            entry_price = self.data.Close[-1]
            
            # Calculate stop loss based on mode
            if self.sl_mode == "Signal Candle":
                sl_price = self.data.High[-1]
            elif self.sl_mode == "ATR":
                sl_price = entry_price + atr * self.atr_mult
            else:  # Percent
                sl_price = entry_price * (1.0 + self.percent_sl / 100.0)
            
            risk = sl_price - entry_price
            
            if risk > 0:
                tp_price = entry_price - risk * self.rr_target
                self.sell()
                self.trades_log.append({
                    'entry': entry_price,
                    'tp': tp_price,
                    'sl': sl_price,
                    'direction': 'short',
                    'bar': len(self.data)
                })
        
        # Exit logic
        if self.position:
            if self.position.is_long:
                # Check for TP or SL hit
                trade = self.trades_log[-1] if self.trades_log else None
                if trade and trade['direction'] == 'long':
                    if self.data.High[-1] >= trade['tp']:
                        self.position.close()
                    elif self.data.Low[-1] <= trade['sl']:
                        self.position.close()
            
            elif self.position.is_short:
                # Check for TP or SL hit
                trade = self.trades_log[-1] if self.trades_log else None
                if trade and trade['direction'] == 'short':
                    if self.data.Low[-1] <= trade['tp']:
                        self.position.close()
                    elif self.data.High[-1] >= trade['sl']:
                        self.position.close()


