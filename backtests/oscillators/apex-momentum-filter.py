import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core Strategy
    minPrice = 10.0
    fastLen = 5
    slowLen = 15
    
    # OsMA Settings
    osmaFast = 6
    osmaSlow = 12
    osmaSignal = 4
    strongThresh = 0.60
    
    # RSI Settings
    rsiLen = 14
    rsiOverbought = 70
    rsiOversold = 30
    
    # Bollinger Band Settings
    bbLen = 10
    bbStdDev = 1.5
    bbUpperLimit = 0.85
    bbLowerLimit = 0.15

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # 1. SMAs
        self.fast = self.I(pta.sma, close, length=self.fastLen)
        self.slow = self.I(pta.sma, close, length=self.slowLen)
        
        # 2. OsMA (MACD - Signal)
        macd_result = self.I(lambda: pta.macd(close, fast=self.osmaFast, slow=self.osmaSlow, signal=self.osmaSignal))
        self.macdLine = self.I(lambda: pta.macd(close, fast=self.osmaFast, slow=self.osmaSlow, signal=self.osmaSignal)['MACD_{}_{}_{}'.format(self.osmaFast, self.osmaSlow, self.osmaSignal)])
        self.signalLine = self.I(lambda: pta.macd(close, fast=self.osmaFast, slow=self.osmaSlow, signal=self.osmaSignal)['MSs_{}_{}_{}'.format(self.osmaFast, self.osmaSlow, self.osmaSignal)])
        
        # Calculate osma directly
        def calc_osma():
            macd_df = pta.macd(close, fast=self.osmaFast, slow=self.osmaSlow, signal=self.osmaSignal)
            if macd_df is None or macd_df.empty:
                return pd.Series(0, index=close.index)
            macd_col = 'MACD_{}_{}_{}'.format(self.osmaFast, self.osmaSlow, self.osmaSignal)
            signal_col = 'MSs_{}_{}_{}'.format(self.osmaFast, self.osmaSlow, self.osmaSignal)
            if macd_col in macd_df.columns and signal_col in macd_df.columns:
                return macd_df[macd_col] - macd_df[signal_col]
            return pd.Series(0, index=close.index)
        
        self.osma = self.I(calc_osma)
        
        # OsMA intensity
        def calc_intensity():
            osma_calc = calc_osma()
            abs_osma = osma_calc.abs()
            osma_max = abs_osma.rolling(window=50).max()
            intensity = osma_max.copy()
            mask = osma_max != 0
            intensity[mask] = abs_osma[mask] / osma_max[mask]
            intensity[~mask] = 0.0
            return intensity
        
        self.intensity = self.I(calc_intensity)
        
        # 3. RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        # 4. Bollinger Bands
        bb_result = self.I(lambda: pta.bbands(close, length=self.bbLen, std=self.bbStdDev))
        
        def calc_bb_bands():
            bb_df = pta.bbands(close, length=self.bbLen, std=self.bbStdDev)
            if bb_df is None or bb_df.empty:
                return pd.DataFrame({
                    'upper': pd.Series(close.iloc[0], index=close.index),
                    'lower': pd.Series(close.iloc[0], index=close.index),
                    'basis': close.copy()
                })
            bb_cols = [col for col in bb_df.columns if 'BB_' in col]
            if len(bb_cols) >= 3:
                bb_sorted = sorted(bb_cols)
                return pd.DataFrame({
                    'upper': bb_df[bb_sorted[2]],
                    'basis': bb_df[bb_sorted[1]],
                    'lower': bb_df[bb_sorted[0]]
                })
            return pd.DataFrame({
                'upper': pd.Series(close.iloc[0], index=close.index),
                'lower': pd.Series(close.iloc[0], index=close.index),
                'basis': close.copy()
            })
        
        bb_data = calc_bb_bands()
        self.bbUpper = self.I(lambda: bb_data['upper'])
        self.bbLower = self.I(lambda: bb_data['lower'])
        self.bbBasis = self.I(lambda: bb_data['basis'])
        
        # PercentB
        def calc_percent_b():
            bb_data = calc_bb_bands()
            denom = bb_data['upper'] - bb_data['lower']
            percent_b = (close - bb_data['lower']) / denom
            percent_b = percent_b.fillna(0.5)
            return percent_b.clip(0, 1)
        
        self.percentB = self.I(calc_percent_b)

    def next(self):
        # Price filter
        if self.data.Close[-1] <= self.minPrice:
            return
        
        # Current values
        fast_val = self.fast[-1]
        slow_val = self.slow[-1]
        osma_val = self.osma[-1]
        rsi_val = self.rsi[-1]
        intensity_val = self.intensity[-1]
        percent_b_val = self.percentB[-1]
        
        # Crossovers
        cross_up = crossover(self.fast, self.slow)
        cross_down = crossover(self.slow, self.fast)
        
        # Filters
        rsi_ok_buy = rsi_val < self.rsiOverbought
        rsi_ok_sell = rsi_val > self.rsiOversold
        bb_ok_buy = percent_b_val < self.bbUpperLimit
        bb_ok_sell = percent_b_val > self.bbLowerLimit
        
        # Strong signal definitions
        is_strong_buy = (intensity_val >= self.strongThresh and 
                        rsi_val >= 40 and rsi_val <= 65 and 
                        bb_ok_buy)
        is_strong_sell = (intensity_val >= self.strongThresh and 
                         rsi_val <= 60 and rsi_val >= 35 and 
                         bb_ok_sell)
        
        # Final signal categories
        strong_buy = (cross_up and osma_val > 0 and 
                     rsi_ok_buy and is_strong_buy)
        normal_buy = (cross_up and osma_val > 0 and 
                     rsi_ok_buy and not is_strong_buy)
        strong_sell = (cross_down and osma_val < 0 and 
                      rsi_ok_sell and is_strong_sell)
        normal_sell = (cross_down and osma_val < 0 and 
                      rsi_ok_sell and not is_strong_sell)
        
        # Trading logic
        if self.position:
            if strong_sell or normal_sell:
                self.position.close()
        else:
            if strong_buy or normal_buy:
                self.buy()


