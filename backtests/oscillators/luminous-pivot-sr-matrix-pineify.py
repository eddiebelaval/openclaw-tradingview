import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivotLen = 15
    atrMult = 0.8
    maxZones = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr_series = self.I(pta.atr, high, low, close, length=14)
        
        self.pivot_highs = self.I(self._detect_pivot_highs, high)
        self.pivot_lows = self.I(self._detect_pivot_lows, low)
        
        self.res_zones = []
        self.sup_zones = []
        
        self.bull_break = self.I(self._detect_bull_break, close, high, low)
        self.bear_break = self.I(self._detect_bear_break, close, high, low)

    def _detect_pivot_highs(self, high):
        result = pd.Series(index=high.index, dtype=float)
        for i in range(len(high)):
            if i < self.pivotLen or i >= len(high) - self.pivotLen:
                result.iloc[i] = np.nan
            else:
                is_pivot = True
                for j in range(1, self.pivotLen + 1):
                    if high.iloc[i - j] >= high.iloc[i] or high.iloc[i + j] >= high.iloc[i]:
                        is_pivot = False
                        break
                result.iloc[i] = high.iloc[i] if is_pivot else np.nan
        return result

    def _detect_pivot_lows(self, low):
        result = pd.Series(index=low.index, dtype=float)
        for i in range(len(low)):
            if i < self.pivotLen or i >= len(low) - self.pivotLen:
                result.iloc[i] = np.nan
            else:
                is_pivot = True
                for j in range(1, self.pivotLen + 1):
                    if low.iloc[i - j] <= low.iloc[i] or low.iloc[i + j] <= low.iloc[i]:
                        is_pivot = False
                        break
                result.iloc[i] = low.iloc[i] if is_pivot else np.nan
        return result

    def _detect_bull_break(self, close, high, low):
        result = pd.Series(False, index=close.index)
        return result

    def _detect_bear_break(self, close, high, low):
        result = pd.Series(False, index=close.index)
        return result

    def next(self):
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_atr = self.atr_series[-1] if len(self.atr_series) > 0 and not np.isnan(self.atr_series[-1]) else 0
        
        current_idx = len(self.data) - 1
        
        if not np.isnan(self.pivot_highs[-1]):
            ph = self.pivot_highs[-1]
            atr_val = current_atr * self.atrMult
            z_top = ph + atr_val / 2
            z_btm = ph - atr_val / 2
            
            self.res_zones.insert(0, {
                'price': ph,
                'top': z_top,
                'btm': z_btm,
                'active': True,
                'bar_idx': current_idx - self.pivotLen
            })
            
            if len(self.res_zones) > self.maxZones:
                self.res_zones.pop()
        
        if not np.isnan(self.pivot_lows[-1]):
            pl = self.pivot_lows[-1]
            atr_val = current_atr * self.atrMult
            z_top = pl + atr_val / 2
            z_btm = pl - atr_val / 2
            
            self.sup_zones.insert(0, {
                'price': pl,
                'top': z_top,
                'btm': z_btm,
                'active': True,
                'bar_idx': current_idx - self.pivotLen
            })
            
            if len(self.sup_zones) > self.maxZones:
                self.sup_zones.pop()
        
        bull_break = False
        bear_break = False
        
        for zone in self.res_zones:
            if zone['active'] and current_close > zone['price']:
                zone['active'] = False
                bull_break = True
        
        for zone in self.sup_zones:
            if zone['active'] and current_close < zone['price']:
                zone['active'] = False
                bear_break = True
        
        if bull_break and not self.position:
            self.buy()
        elif bear_break and self.position:
            self.sell()


