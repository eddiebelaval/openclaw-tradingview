import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Liquidation Bubbles parameters
    lnt = 21
    sens = 2.5
    comb = False
    
    # HARSI parameters
    harsiLen = 14
    harsiSmooth = 1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate HARSI components
        self.ho = self.I(self._calc_harsi_open, high, low, close)
        self.hc = self.I(self._calc_harsi_close, high, low, close)
        
        # HARSI bias
        self.harsiBull = self.I(lambda: self.hc > self.ho)
        self.harsiBear = self.I(lambda: self.hc < self.ho)
        
        # Calculate liquidation bubbles
        self.bubbleSmall = self.I(self._calc_bubble_small, close, high, low, volume)
        self.bubbleBig = self.I(self._calc_bubble_big, close, high, low, volume)
        
        # Confluence signals
        self.bullConfluence = self.I(lambda: (self.bubbleSmall[-1] > 0 or self.bubbleBig[-1] > 0) and self.harsiBull[-1])
        self.bearConfluence = self.I(lambda: (self.bubbleSmall[-1] < 0 or self.bubbleBig[-1] < 0) and self.harsiBear[-1])

    def _advanced_vwma(self, src_series, length, vol_series):
        """Calculate advanced VWMA with inverse volume weighting"""
        src_array = src_series.values if isinstance(src_series, pd.Series) else src_series
        vol_array = vol_series.values if isinstance(vol_series, pd.Series) else vol_series
        
        result = np.full(len(src_array), np.nan)
        
        for i in range(len(src_array)):
            start_idx = max(0, i - length + 1)
            src_slice = src_array[start_idx:i+1]
            vol_slice = vol_array[start_idx:i+1]
            
            if len(src_slice) > 0:
                w = 1.0 / np.power(np.maximum(vol_slice, 0.0001), 1.0)
                numerator = np.sum(src_slice * w)
                denominator = np.sum(w)
                result[i] = numerator / denominator if denominator != 0 else np.nan
        
        return pd.Series(result, index=src_series.index if isinstance(src_series, pd.Series) else None)

    def _calc_bubble_component(self, close_series, high_series, low_series, vol_series, length, threshold):
        """Calculate liquidation bubble signal"""
        close_arr = close_series.values if isinstance(close_series, pd.Series) else close_series
        high_arr = high_series.values if isinstance(high_series, pd.Series) else high_series
        low_arr = low_series.values if isinstance(low_series, pd.Series) else low_series
        vol_arr = vol_series.values if isinstance(vol_series, pd.Series) else vol_series
        
        result = np.zeros(len(close_arr))
        
        for i in range(len(close_arr)):
            start_idx = max(0, i - length + 1)
            
            close_slice = close_arr[start_idx:i+1]
            high_slice = high_arr[start_idx:i+1]
            low_slice = low_arr[start_idx:i+1]
            vol_slice = vol_arr[start_idx:i+1]
            
            if len(close_slice) < max(2, length // 2):
                continue
            
            # Price mean with inverse volume weighting
            w_price = 1.0 / np.power(np.maximum(vol_slice, 0.0001), 1.0)
            pricemean = np.sum(close_slice * w_price) / np.sum(w_price)
            
            # Price deviation
            pricedev = np.maximum(np.abs(high_slice[-1] - pricemean), np.abs(pricemean - low_slice[-1]))
            
            # Price deviation average
            pricedev_window = max(2, length * 2)
            hist_idx = max(0, i - pricedev_window + 1)
            pricedev_history = []
            for j in range(hist_idx, i+1):
                start_j = max(0, j - length + 1)
                w_p = 1.0 / np.power(np.maximum(vol_arr[start_j:j+1], 0.0001), 1.0)
                pm = np.sum(close_arr[start_j:j+1] * w_p) / np.sum(w_p)
                pd_val = np.maximum(np.abs(high_arr[j] - pm), np.abs(pm - low_arr[j]))
                pricedev_history.append(pd_val)
            
            pricedevavg = np.mean(pricedev_history) if pricedev_history else pricedev
            
            # Price Z-score
            pricez = 0 if pricedevavg == 0 else ((pricedev * (1 if high_slice[-1] - pricemean > pricemean - low_slice[-1] else -1)) / pricedevavg)
            
            # Volume mean and deviation
            w_vol = 1.0 / np.power(np.maximum(vol_slice, 0.0001), 1.0)
            volumemean = np.sum(vol_slice * w_vol) / np.sum(w_vol)
            volumedev = vol_slice[-1] - volumemean
            
            # Volume deviation average
            vol_history = []
            for j in range(hist_idx, i+1):
                start_j = max(0, j - length + 1)
                w_v = 1.0 / np.power(np.maximum(vol_arr[start_j:j+1], 0.0001), 1.0)
                vm = np.sum(vol_arr[start_j:j+1] * w_v) / np.sum(w_v)
                vd = np.abs(vol_arr[j] - vm)
                vol_history.append(vd)
            
            volumedevavg = np.mean(vol_history) if vol_history else np.abs(volumedev)
            
            # Volume Z-score
            volumez = 0 if volumedevavg == 0 else volumedev / volumedevavg
            
            # Bubble signal
            if self.comb:
                avg_score = (np.abs(pricez) + np.abs(volumez)) / 2.0
                if avg_score > threshold:
                    result[i] = np.sign(pricez) * -1
            else:
                if volumez > threshold and np.abs(pricez) > threshold:
                    result[i] = np.sign(pricez) * -1
        
        return pd.Series(result, index=close_series.index if isinstance(close_series, pd.Series) else None)

    def _calc_bubble_small(self, close, high, low, volume):
        return self._calc_bubble_component(close, high, low, volume, self.lnt, self.sens - 0.5)

    def _calc_bubble_big(self, close, high, low, volume):
        return self._calc_bubble_component(close, high, low, volume, self.lnt, self.sens + 0.5)

    def _calc_harsi_open(self, high, low, close):
        """Calculate HARSI open component"""
        close_arr = close.values if isinstance(close, pd.Series) else close
        high_arr = high.values if isinstance(high, pd.Series) else high
        low_arr = low.values if isinstance(low, pd.Series) else low
        
        # Zero-referenced RSI
        rsi_close = pta.rsi(close, length=self.harsiLen).values - 50.0
        rsi_high = pta.rsi(high, length=self.harsiLen).values - 50.0
        rsi_low = pta.rsi(low, length=self.harsiLen).values - 50.0
        
        ho = np.full(len(close_arr), np.nan)
        
        for i in range(len(close_arr)):
            if i == 0:
                ho[i] = (rsi_close[i] + rsi_close[i]) / 2.0
            else:
                if np.isnan(ho[i-1]):
                    ho[i] = (rsi_close[i-1] + rsi_close[i]) / 2.0
                else:
                    ho[i] = (ho[i-1] * self.harsiSmooth + (rsi_close[i-1] if i > 0 else rsi_close[i])) / (self.harsiSmooth + 1.0)
        
        return pd.Series(ho, index=close.index if isinstance(close, pd.Series) else None)

    def _calc_harsi_close(self, high, low, close):
        """Calculate HARSI close component"""
        close_arr = close.values if isinstance(close, pd.Series) else close
        high_arr = high.values if isinstance(high, pd.Series) else high
        low_arr = low.values if isinstance(low, pd.Series) else low
        
        # Zero-referenced RSI
        rsi_close = pta.rsi(close, length=self.harsiLen).values - 50.0
        rsi_high = pta.rsi(high, length=self.harsiLen).values - 50.0
        rsi_low = pta.rsi(low, length=self.harsiLen).values - 50.0
        
        ho = self._calc_harsi_open(high, low, close).values
        
        hc = np.full(len(close_arr), np.nan)
        
        for i in range(len(close_arr)):
            highRSI_raw = rsi_high[i]
            lowRSI_raw = rsi_low[i]
            highRSI = max(highRSI_raw, lowRSI_raw)
            lowRSI = min(highRSI_raw, lowRSI_raw)
            
            hc[i] = (ho[i] + highRSI + lowRSI + rsi_close[i]) / 4.0
        
        return pd.Series(hc, index=close.index if isinstance(close, pd.Series) else None)

    def next(self):
        # Entry signals based on confluence
        if len(self.data) < 2:
            return
        
        # Bull confluence: liquidation bubble + HARSI bullish
        if self.bullConfluence[-1] and not self.position:
            self.buy()
        
        # Bear confluence: liquidation bubble + HARSI bearish
        elif self.bearConfluence[-1] and self.position:
            self.position.close()
        
        # Exit on reversal
        if self.position and not self.harsiBull[-1]:
            self.position.close()


