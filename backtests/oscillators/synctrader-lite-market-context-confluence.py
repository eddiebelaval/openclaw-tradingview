import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    rsi_length = 14
    bb_length = 20
    bb_std = 2.0
    ema1_length = 8
    ema2_length = 21
    ma1_length = 10
    ma2_length = 50
    atr_length = 14
    hma_length = 20
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Core indicators
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        self.bb_upper = self.I(lambda: pta.bbands(close, length=self.bb_length, std=self.bb_std)['BBU_' + str(self.bb_length) + '_' + str(self.bb_std)] or pd.Series(close.mean(), index=close.index))
        self.bb_lower = self.I(lambda: pta.bbands(close, length=self.bb_length, std=self.bb_std)['BBL_' + str(self.bb_length) + '_' + str(self.bb_std)] or pd.Series(close.mean(), index=close.index))
        self.bb_middle = self.I(lambda: pta.bbands(close, length=self.bb_length, std=self.bb_std)['BBM_' + str(self.bb_length) + '_' + str(self.bb_std)] or pd.Series(close.mean(), index=close.index))
        
        # EMA Cloud
        self.ema1 = self.I(pta.ema, close, length=self.ema1_length)
        self.ema2 = self.I(pta.ema, close, length=self.ema2_length)
        
        # Moving Averages
        self.ma1 = self.I(pta.ema, close, length=self.ma1_length)
        self.ma2 = self.I(pta.sma, close, length=self.ma2_length)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # HMA
        self.hma = self.I(pta.hma, close, length=self.hma_length)
        
        # Pivots
        self.pivot_high = self.I(lambda: high.rolling(5).max().shift(2))
        self.pivot_low = self.I(lambda: low.rolling(5).min().shift(2))

    def next(self):
        # Signal counters for confluence
        buy_signals = 0
        sell_signals = 0
        
        # 1. EMA Cloud Cross - Strong signal
        if crossover(self.ema1, self.ema2):
            buy_signals += 2
        elif crossover(self.ema2, self.ema1):
            sell_signals += 2
        
        # 2. MA Cross
        if crossover(self.ma1, self.ma2):
            buy_signals += 2
        elif crossover(self.ma2, self.ma1):
            sell_signals += 2
        
        # 3. Bollinger Bands
        if len(self.data) > self.bb_length:
            if self.data.Close[-1] < self.bb_lower[-1] and self.rsi[-1] < 30:
                buy_signals += 1
            elif self.data.Close[-1] > self.bb_upper[-1] and self.rsi[-1] > 70:
                sell_signals += 1
        
        # 4. RSI Oversold/Overbought with reversal
        if len(self.rsi) > 1:
            if self.rsi[-2] < 30 and self.rsi[-1] > self.rsi[-2]:
                buy_signals += 1
            elif self.rsi[-2] > 70 and self.rsi[-1] < self.rsi[-2]:
                sell_signals += 1
        
        # 5. HMA Slope confirmation
        if len(self.hma) > 1:
            if self.hma[-1] > self.hma[-2]:
                buy_signals += 1
            elif self.hma[-1] < self.hma[-2]:
                sell_signals += 1
        
        # 6. Pivot breakouts
        if len(self.pivot_high) > 1 and not np.isnan(self.pivot_high[-1]):
            if crossover(pd.Series([self.data.High[-2], self.data.High[-1]]), 
                        pd.Series([self.pivot_high[-1], self.pivot_high[-1]])):
                buy_signals += 1
        
        if len(self.pivot_low) > 1 and not np.isnan(self.pivot_low[-1]):
            if crossover(pd.Series([self.pivot_low[-1], self.pivot_low[-1]]),
                        pd.Series([self.data.Low[-2], self.data.Low[-1]])):
                sell_signals += 1
        
        # Entry/Exit Logic using confluence score
        if not self.position:
            if buy_signals >= 3:
                self.buy()
            elif sell_signals >= 3:
                self.sell()
        else:
            # Exit logic based on opposite signals or ATR-based stop loss
            if self.position.is_long:
                if sell_signals >= 3:
                    self.position.close()
                elif self.data.Close[-1] < self.data.Close[-1] - 2 * self.atr[-1]:
                    self.position.close()
            
            elif self.position.is_short:
                if buy_signals >= 3:
                    self.position.close()
                elif self.data.Close[-1] > self.data.Close[-1] + 2 * self.atr[-1]:
                    self.position.close()


