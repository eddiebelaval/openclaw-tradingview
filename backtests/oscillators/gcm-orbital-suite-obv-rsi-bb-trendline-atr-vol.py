    def _apply_ma(self, src, length, ma_type):
        if ma_type == "EMA":
            return pta.ema(src, length=length)
        elif ma_type == "SMA":
            return pta.sma(src, length=length)
        elif ma_type == "WMA":
            return pta.wma(src, length=length)
        elif ma_type == "HMA":
            return pta.hma(src, length=length)
        elif ma_type == "DEMA":
            ema1 = pta.ema(src, length=length)
            ema2 = pta.ema(ema1, length=length)
            return 2 * ema1 - ema2
