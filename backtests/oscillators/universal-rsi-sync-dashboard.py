import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    threshold = 0.5
    ma_len = 50
    rsi_len = 14
    ema_len = 233

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # RSI calculation for ribbon state
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)

        # EMA for structural state
        self.ema = self.I(pta.ema, close, length=self.ema_len)

        # Previous day high/low for structural comparison
        self.prev_day_high = self.I(lambda: high.rolling(window=1).max())
        self.prev_day_low = self.I(lambda: low.rolling(window=1).min())

    def get_ribbon_state(self, rsi_val):
        """
        Returns 1 for bullish, -1 for bearish, 0 for neutral
        """
        if rsi_val is None or np.isnan(rsi_val):
            return 0
        diff = rsi_val - 50
        if diff > self.threshold:
            return 1
        elif diff < -self.threshold:
            return -1
        else:
            return 0

    def get_struct_state(self, close_val, ema_val, ph, pl):
        """
        Returns 1 for bullish structure, -1 for bearish structure, 0 for neutral
        """
        if close_val is None or ema_val is None or ph is None or pl is None:
            return 0
        if np.isnan(close_val) or np.isnan(ema_val) or np.isnan(ph) or np.isnan(pl):
            return 0

        if close_val > ema_val and close_val > ph:
            return 1
        elif close_val < ema_val and close_val < pl:
            return -1
        else:
            return 0

    def next(self):
        if len(self.data) < self.ema_len:
            return

        current_rsi = self.rsi[-1]
        current_ema = self.ema[-1]
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]

        # Get ribbon state (5m equivalent in single timeframe)
        ribbon_state = self.get_ribbon_state(current_rsi)

        # Get structural state
        prev_high = current_high if len(self.data) < 2 else self.data.High[-2]
        prev_low = current_low if len(self.data) < 2 else self.data.Low[-2]
        struct_state = self.get_struct_state(current_close, current_ema, prev_high, prev_low)

        # Simple trading logic: buy on bullish signals, sell on bearish
        # Require both ribbon and structure to agree for stronger signal
        bullish_signal = ribbon_state == 1 and struct_state == 1
        bearish_signal = ribbon_state == -1 and struct_state == -1

        # Alternative: buy on any bullish ribbon, sell on any bearish ribbon
        if ribbon_state == 1 and not self.position:
            self.buy()
        elif ribbon_state == -1 and self.position:
            self.sell()