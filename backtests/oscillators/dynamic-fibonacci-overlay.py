import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    length = 14

    def init(self):
        pass

    def next(self):
        if len(self.data) < self.length:
            return

        bar_start_idx = max(0, len(self.data) - self.length - 1)
        bar_end_idx = len(self.data) - 1

        top_close = self.data.Close[-1]
        bottom_close = self.data.Close[bar_start_idx]
        mid_close = (top_close + bottom_close) / 2

        fib_382 = bottom_close + (top_close - bottom_close) * 0.382
        fib_618 = bottom_close + (top_close - bottom_close) * 0.618

        current_price = self.data.Close[-1]

        if current_price > top_close:
            if not self.position:
                self.buy()
        elif current_price < bottom_close:
            if self.position:
                self.position.close()
        elif current_price > fib_618 and current_price < top_close:
            if not self.position:
                self.buy()
        elif current_price < fib_382 and current_price > bottom_close:
            if self.position:
                self.position.close()


