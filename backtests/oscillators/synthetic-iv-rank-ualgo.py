import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    hv_length = 20
    lookback_length = 252
    is_crypto = False

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Yang-Zhang Volatility and IV Rank
        self.yz_iv = self.I(self._calculate_yang_zhang, close, open_, high, low)
        self.iv_rank = self.I(self._calculate_iv_rank, self.yz_iv)

    def _calculate_yang_zhang(self, close, open_, high, low):
        """Calculate Yang-Zhang volatility estimator"""
        df = pd.DataFrame({
            'close': close,
            'open': open_,
            'high': high,
            'low': low
        })
        
        results = []
        
        for i in range(len(df)):
            if i < self.hv_length:
                results.append(np.nan)
                continue
            
            window = df.iloc[i - self.hv_length + 1:i + 1]
            
            # 1. Overnight Volatility (Close[i-1] to Open[i])
            log_ho = np.log(window['close'].values / np.roll(window['close'].values, 1)[1:].tolist() + [window['close'].iloc[-2] if i > 0 else window['close'].iloc[0]])
            
            # Simplified: use close to close for log_ho calculation
            close_vals = window['close'].values
            if len(close_vals) > 1:
                log_ho_vals = np.log(close_vals[1:] / close_vals[:-1])
                var_ho = np.var(log_ho_vals)
            else:
                var_ho = 0
            
            # 2. Open-to-Close Volatility
            log_oc = np.log(window['close'].values / window['open'].values)
            var_oc = np.var(log_oc)
            
            # 3. Rogers-Satchell Volatility
            rs_log_hc = np.log(window['high'].values / window['close'].values)
            rs_log_ho = np.log(window['high'].values / window['open'].values)
            rs_log_lc = np.log(window['low'].values / window['close'].values)
            rs_log_lo = np.log(window['low'].values / window['open'].values)
            
            rs_daily = rs_log_hc * rs_log_ho + rs_log_lc * rs_log_lo
            var_rs = np.mean(rs_daily)
            
            # 4. Calculate k and combine
            k = 0.34 / (1.34 + (self.hv_length + 1) / (self.hv_length - 1))
            yz_variance = var_ho + k * var_oc + (1 - k) * var_rs
            yz_vol = np.sqrt(abs(yz_variance))
            
            # 5. Annualize
            days_per_year = 365.0 if self.is_crypto else 252.0
            annual_factor = np.sqrt(days_per_year)
            annualized_vol = yz_vol * annual_factor * 100
            
            results.append(annualized_vol)
        
        return pd.Series(results)

    def _calculate_iv_rank(self, yz_iv):
        """Calculate IV Rank from Yang-Zhang volatility"""
        results = []
        
        for i in range(len(yz_iv)):
            if i < self.lookback_length or pd.isna(yz_iv.iloc[i]):
                results.append(np.nan)
                continue
            
            window = yz_iv.iloc[i - self.lookback_length + 1:i + 1]
            window = window.dropna()
            
            if len(window) == 0:
                results.append(50.0)
                continue
            
            iv_min = window.min()
            iv_max = window.max()
            current_iv = yz_iv.iloc[i]
            
            if (iv_max - iv_min) != 0:
                iv_rank = ((current_iv - iv_min) / (iv_max - iv_min)) * 100
            else:
                iv_rank = 50.0
            
            results.append(max(0, min(100, iv_rank)))
        
        return pd.Series(results)

    def next(self):
        # Trading logic based on IV Rank levels
        # Buy when volatility is low (complacency) and expect mean reversion
        # Sell when volatility is high (fear)
        
        if len(self.iv_rank) < 2:
            return
        
        current_rank = self.iv_rank[-1]
        prev_rank = self.iv_rank[-2] if len(self.iv_rank) > 1 else current_rank
        
        # Entry: When IV Rank crosses above 20 (from low volatility to normal)
        if prev_rank <= 20 and current_rank > 20 and not self.position:
            self.buy()
        
        # Exit: When IV Rank crosses above 80 (extreme fear - take profits)
        elif current_rank >= 80 and self.position:
            self.sell()
        
        # Stop loss: Exit if IV Rank drops below 10 (something wrong)
        elif current_rank < 10 and self.position:
            self.sell()