import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    multBB = 2.0
    multKC = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands calculation
        basis = self.I(pta.sma, close, length=self.length)
        dev = self.I(lambda: self.multBB * close.rolling(self.length).std())
        upperBB = self.I(lambda: basis + dev)
        lowerBB = self.I(lambda: basis - dev)
        
        # Keltner Channels calculation
        rangeLen = self.I(lambda: high.rolling(self.length).max() - low.rolling(self.length).min())
        maRange = self.I(pta.sma, rangeLen, length=self.length)
        upperKC = self.I(lambda: basis + maRange * self.multKC)
        lowerKC = self.I(lambda: basis - maRange * self.multKC)
        
        # Squeeze momentum histogram
        linreg_input = self.I(lambda: close - pta.sma(close, length=self.length))
        self.hist = self.I(pta.linreg, linreg_input, length=self.length)
        
        self.basis = basis
        self.upperBB = upperBB
        self.lowerBB = lowerBB
        self.upperKC = upperKC
        self.lowerKC = lowerKC

    def next(self):
        if len(self.data) < 2:
            return
        
        # Current and previous histogram values
        hist_current = self.hist[-1]
        hist_prev = self.hist[-2]
        
        # Determine color code
        if hist_current is None or hist_prev is None:
            return
        
        isIncreasing = hist_current > hist_prev
        isDecreasing = hist_current < hist_prev
        
        if hist_current > 0 and isIncreasing:
            colorCode = 1  # light green
        elif hist_current > 0 and isDecreasing:
            colorCode = 2  # dark green
        elif hist_current < 0 and isDecreasing:
            colorCode = 3  # dark red
        elif hist_current < 0 and isIncreasing:
            colorCode = 4  # light red
        else:
            colorCode = 0
        
        # Previous color code (need to track it)
