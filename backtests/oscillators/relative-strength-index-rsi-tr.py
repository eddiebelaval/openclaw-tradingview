import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Length_RSI = 14
    Length_MA_RSI = 365
    Source_MA_RSI = 'EMA'
    Signal_RSI = '50'

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.rsi = self.I(pta.rsi, close, length=self.Length_RSI)
        
        if self.Signal_RSI == 'RSI MA':
            if self.Source_MA_RSI == 'EMA':
                self.entry_signal = self.I(pta.ema, self.rsi, length=self.Length_MA_RSI)
            elif self.Source_MA_RSI == 'SMA':
                self.entry_signal = self.I(pta.sma, self.rsi, length=self.Length_MA_RSI)
            elif self.Source_MA_RSI == 'RMA':
                self.entry_signal = self.I(pta.rma, self.rsi, length=self.Length_MA_RSI)
            elif self.Source_MA_RSI == 'WMA':
                self.entry_signal = self.I(pta.wma, self.rsi, length=self.Length_MA_RSI)
            elif self.Source_MA_RSI == 'VWMA':
                volume = pd.Series(self.data.Volume)
                self.entry_signal = self.I(pta.vwma, self.rsi, volume, length=self.Length_MA_RSI)
            elif self.Source_MA_RSI == 'HMA':
                self.entry_signal = self.I(pta.hma, self.rsi, length=self.Length_MA_RSI)
            else:
                self.entry_signal = self.I(lambda: pd.Series(50, index=self.rsi.index))
        else:
            self.entry_signal = self.I(lambda: pd.Series(50, index=self.rsi.index))

    def next(self):
        if len(self.data) < self.Length_RSI + 1:
            return
        
        rsi_current = self.rsi[-1]
        signal_current = self.entry_signal[-1]
        
        if np.isnan(rsi_current) or np.isnan(signal_current):
            return
        
        rsi_prev = self.rsi[-2]
        signal_prev = self.entry_signal[-2]
        
        bull_condition = rsi_prev <= signal_prev and rsi_current > signal_current
        bear_condition = rsi_prev >= signal_prev and rsi_current < signal_current
        
        if bull_condition:
            if self.position:
                self.position.close()
            self.buy()
        elif bear_condition:
            if self.position:
                self.position.close()