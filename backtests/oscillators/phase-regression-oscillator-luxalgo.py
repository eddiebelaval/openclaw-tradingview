import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
import math


class TvStrategy(Strategy):
    n_input = 20
    period_pct_input = 100.0
    ob_level = 0.8
    os_level = -0.8

    def init(self):
        self.osc_values = []
        self.osc_cos_values = []

    def next(self):
        if len(self.data) < self.n_input:
            return

        close_data = self.data.Close
        n = self.n_input
        P = n * (self.period_pct_input / 100.0)
        omega = 2.0 * math.pi / P

        s_s = 0.0
        s_c = 0.0
        s_ss = 0.0
        s_cc = 0.0
        s_sc = 0.0
        s_ys = 0.0
        s_yc = 0.0
        s_y = 0.0

        for i in range(n):
            idx = len(close_data) - 1 - i
            if idx < 0:
                return
            val = close_data[idx]
            x = -i
            sn = math.sin(omega * x)
            cs = math.cos(omega * x)

            s_s += sn
            s_c += cs
            s_ss += sn * sn
            s_cc += cs * cs
            s_sc += sn * cs
            s_y += val
            s_ys += val * sn
            s_yc += val * cs

        a, b, c = self._solve3x3(
            s_ss, s_sc, s_s, s_ys,
            s_sc, s_cc, s_c, s_yc,
            s_s, s_c, float(n), s_y
        )

        phi = self._atan2(b, a)

        osc = math.sin(phi)
        osc_cos = math.cos(phi)

        self.osc_values.append(osc)
        self.osc_cos_values.append(osc_cos)

        if len(self.osc_values) < 2:
            return

        prev_osc = self.osc_values[-2]
        curr_osc = self.osc_values[-1]

        if prev_osc < self.os_level and curr_osc >= self.os_level:
            if not self.position:
                self.buy()
        elif prev_osc > self.ob_level and curr_osc <= self.ob_level:
            if self.position:
                self.position.close()

        if crossover(self.os_level, curr_osc) and not self.position:
            self.buy()
        elif crossover(curr_osc, self.ob_level) and self.position:
            self.position.close()

    def _atan2(self, y, x):
        if x > 0:
            phi = math.atan(y / x)
        elif x < 0:
            if y >= 0:
                phi = math.atan(y / x) + math.pi
            else:
                phi = math.atan(y / x) - math.pi
        else:
            if y > 0:
                phi = math.pi / 2.0
            elif y < 0:
                phi = -math.pi / 2.0
            else:
                phi = 0.0
        return phi

    def _solve3x3(self, a1, b1, c1, d1, a2, b2, c2, d2, a3, b3, c3, d3):
        det = a1 * (b2 * c3 - b3 * c2) - b1 * (a2 * c3 - a3 * c2) + c1 * (a2 * b3 - a3 * b2)
        if abs(det) < 1e-12:
            return 0.0, 0.0, 0.0
        else:
            dx = d1 * (b2 * c3 - b3 * c2) - b1 * (d2 * c3 - d3 * c2) + c1 * (d2 * b3 - d3 * b2)
            dy = a1 * (d2 * c3 - d3 * c2) - d1 * (a2 * c3 - a3 * c2) + c1 * (a2 * d3 - a3 * d2)
            dz = a1 * (b2 * d3 - b3 * d2) - b1 * (a2 * d3 - a3 * d2) + d1 * (a2 * b3 - a3 * b2)
            return dx / det, dy / det, dz / det


