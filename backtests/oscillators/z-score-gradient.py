import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 50
    anchorOpt = "SMA"
    volOpt = "Stdev (classic)"
    madK = 1.4826
    kamaLen = 21
    kalmanQ = 0.01
    kalmanR = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # KAMA calculation
        def calculate_kama():
            nfastend = 2.0 / (2.0 + 1.0)
            nslowend = 2.0 / (30.0 + 1.0)
            
            kama_series = close.copy()
            kama_series.iloc[0] = close.iloc[0]
            
            for i in range(1, len(close)):
                xvnoise = abs(close.iloc[i] - close.iloc[i-1])
                if i >= self.kamaLen:
                    nsignal = abs(close.iloc[i] - close.iloc[i-self.kamaLen])
                    nnoise = sum(abs(close.iloc[j] - close.iloc[j-1]) for j in range(i-self.kamaLen+1, i+1))
                    nefratio = nsignal / nnoise if nnoise != 0 else 0.0
                else:
                    nefratio = 0.0
                
                nsmooth = pow(nefratio * (nfastend - nslowend) + nslowend, 2)
                kama_series.iloc[i] = kama_series.iloc[i-1] + nsmooth * (close.iloc[i] - kama_series.iloc[i-1])
            
            return kama_series
        
        # Kalman Filter calculation
        def calculate_kalman():
            kalman_series = close.copy()
            kalman_x = close.iloc[0]
            kalman_p = 1.0
            
            for i in range(1, len(close)):
                kalman_ppred = kalman_p + self.kalmanQ
                kalman_k = kalman_ppred / (kalman_ppred + self.kalmanR)
                kalman_x = kalman_x + kalman_k * (close.iloc[i] - kalman_x)
                kalman_p = (1.0 - kalman_k) * kalman_ppred
                kalman_series.iloc[i] = kalman_x
            
            return kalman_series
        
        # Basis selection
        if self.anchorOpt == "VWAP":
            self.basis = self.I(pta.vwap, high, low, close, volume)
        elif self.anchorOpt == "SMA":
            self.basis = self.I(pta.sma, close, length=self.len)
        elif self.anchorOpt == "EMA":
            self.basis = self.I(pta.ema, close, length=self.len)
        elif self.anchorOpt == "KAMA":
            self.basis = self.I(calculate_kama)
        elif self.anchorOpt == "Kalman":
            self.basis = self.I(calculate_kalman)
        else:
            self.basis = self.I(pta.sma, close, length=self.len)
        
        # Volatility calculation
        def calculate_volatility():
            if self.volOpt == "Stdev (classic)":
                st = close.rolling(self.len).std()
                return st.fillna(method='bfill')
            else:
                med = close.rolling(self.len).quantile(0.5)
                mad_approx = (close - med).abs().rolling(self.len).quantile(0.5)
                robust_vol = self.madK * mad_approx
                return robust_vol.fillna(method='bfill')
        
        self.volatility = self.I(calculate_volatility)
        
        # Z-score calculation
        def calculate_zscore():
            vol_safe = np.maximum(self.volatility, 1e-10)
            z = (close - self.basis) / vol_safe
            return z.fillna(0)
        
        self.z_score = self.I(calculate_zscore)

    def next(self):
        if len(self.data) < self.len + 1:
            return
        
        z_current = self.z_score[-1]
        z_prev = self.z_score[-2] if len(self.z_score) > 1 else z_current
        
        # Buy when z-score crosses above -2 (oversold reversal)
        if z_prev <= -2.0 and z_current > -2.0:
            if not self.position:
                self.buy()
        
        # Sell when z-score crosses below +2 (overbought reversal)
        elif z_prev >= 2.0 and z_current < 2.0:
            if self.position:
                self.position.close()
        
        # Exit on extreme z-score levels
        elif z_current > 3.0:
            if self.position:
                self.position.close()
        elif z_current < -3.0:
            if not self.position:
                self.buy()


