import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.p = 200
        self.atr_p = 14
        self.mult = 1.0
        self.mode = "Type A"
        self.use_ema_smoother = "No"
        self.src_ema_period = 3
        self.atr_mult_stop = 2.0
        self.atr_mult_trail = 1.0
        
        self.use_date_filter = True
        self.start_time = pd.Timestamp("2024-01-01")
        self.end_time = pd.Timestamp("2026-12-31")
        self.close_after_end = True
        
        if self.use_ema_smoother == "Yes":
            src_series = self.I(pta.ema, close, length=self.src_ema_period)
        else:
            src_series = close
        
        self.h = self.I(lambda: src_series.rolling(window=self.p).max())
        self.l = self.I(lambda: src_series.rolling(window=self.p).min())
        self.d = self.I(lambda: self.h - self.l)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_p)
        
        self.src_series = src_series
        
        self.last_signal = None
        self.m_value = None
        self.entry_price = None

    def next(self):
        if len(self.data) < self.p + 1:
            return
        
        current_date = self.data.index[-1]
        
        in_date_range = (not self.use_date_filter or 
                        (current_date >= self.start_time and current_date <= self.end_time))
        
        src_val = self.src_series[-1]
        h_val = self.h[-1]
        l_val = self.l[-1]
        d_val = self.d[-1]
        atr_val = self.atr[-1]
        
        if np.isnan(src_val) or np.isnan(h_val) or np.isnan(l_val) or np.isnan(d_val) or np.isnan(atr_val):
            return
        
        if self.m_value is None:
            self.m_value = (h_val + l_val) / 2.0
        
        epsilon = self.mult * atr_val
        
        sb = self.data.Open[-1] < l_val + d_val / 8 and self.data.Open[-1] >= l_val
        ss = self.data.Open[-1] > h_val - d_val / 8 and self.data.Open[-1] <= h_val
        
        strong_buy = sb
        strong_sell = ss
        
        if self.mode == "Type B":
            change_up = (src_val > self.m_value + epsilon and 
                        (len(self.data) < 2 or self.src_series[-2] <= self.m_value + epsilon))
            change_down = (src_val < self.m_value - epsilon and 
                          (len(self.data) < 2 or self.src_series[-2] >= self.m_value - epsilon))
        else:
            change_up = (src_val > self.m_value + epsilon and 
                        (len(self.data) < 2 or self.src_series[-2] <= self.m_value + epsilon)) or src_val > self.m_value + epsilon
            change_down = (src_val < self.m_value - epsilon and 
                          (len(self.data) < 2 or self.src_series[-2] >= self.m_value - epsilon)) or src_val < self.m_value - epsilon
        
        if change_up or change_down:
            self.m_value = self.m_value + epsilon if change_up else self.m_value - epsilon
        
        signal = "B" if change_up else ("S" if change_down else self.last_signal)
        
        if signal != self.last_signal:
            self.last_signal = signal
        
        long_condition = change_up and self.last_signal != "B" and in_date_range
        short_condition = change_down and self.last_signal != "S" and in_date_range
        
        if long_condition:
            if self.position.is_short:
                self.position.close()
            self.buy()
            self.entry_price = self.data.Close[-1]
        
        if short_condition:
            if self.position.is_long:
                self.position.close()
            self.sell()
            self.entry_price = self.data.Close[-1]
        
        if self.use_date_filter and self.close_after_end and current_date >= self.end_time:
            if self.position:
                self.position.close()
        
        if self.position.is_long:
            stop_loss = self.entry_price - (atr_val * self.atr_mult_stop)
            if self.data.Close[-1] <= stop_loss:
                self.position.close()
        elif self.position.is_short:
            stop_loss = self.entry_price + (atr_val * self.atr_mult_stop)
            if self.data.Close[-1] >= stop_loss:
                self.position.close()


