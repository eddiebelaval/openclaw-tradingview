import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI Settings
    rsi_len = 14
    ob = 70.0
    os = 30.0
    
    # Divergence Settings
    piv_left = 5
    piv_right = 5
    show_reg_bear = True
    show_reg_bull = True
    show_hid_bear = False
    show_hid_bull = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        # Detect pivot highs and lows
        self.ph = self.I(self._pivot_high, high, self.piv_left, self.piv_right)
        self.pl = self.I(self._pivot_low, low, self.piv_left, self.piv_right)
        
        # Track previous pivots
        self.last_ph_bar = None
        self.last_ph_price = None
        self.last_ph_rsi = None
        
        self.last_pl_bar = None
        self.last_pl_price = None
        self.last_pl_rsi = None
        
        # Divergence flags
        self.reg_bull_div = False
        self.reg_bear_div = False
        self.hid_bull_div = False
        self.hid_bear_div = False

    def _pivot_high(self, high_series, left, right):
        """Detect pivot highs"""
        result = pd.Series(np.nan, index=high_series.index)
        for i in range(left, len(high_series) - right):
            if high_series.iloc[i] == high_series.iloc[i-left:i+right+1].max():
                result.iloc[i] = high_series.iloc[i]
        return result

    def _pivot_low(self, low_series, left, right):
        """Detect pivot lows"""
        result = pd.Series(np.nan, index=low_series.index)
        for i in range(left, len(low_series) - right):
            if low_series.iloc[i] == low_series.iloc[i-left:i+right+1].min():
                result.iloc[i] = low_series.iloc[i]
        return result

    def next(self):
        # Current bar index
        curr_idx = len(self.data) - 1
        
        # Check for pivot high
        if not np.isnan(self.ph[-1]):
            curr_bar = curr_idx
            curr_rsi = self.rsi[-1]
            curr_price = self.data.High[-1]
            
            if self.last_ph_bar is not None:
                # Regular bearish: price HH + RSI LH
                if (self.show_reg_bear and 
                    curr_price > self.last_ph_price and 
                    curr_rsi < self.last_ph_rsi):
                    self.reg_bear_div = True
                
                # Hidden bearish: price LH + RSI HH
                if (self.show_hid_bear and 
                    curr_price < self.last_ph_price and 
                    curr_rsi > self.last_ph_rsi):
                    self.hid_bear_div = True
            
            self.last_ph_bar = curr_bar
            self.last_ph_price = curr_price
            self.last_ph_rsi = curr_rsi
        
        # Check for pivot low
        if not np.isnan(self.pl[-1]):
            curr_bar = curr_idx
            curr_rsi = self.rsi[-1]
            curr_price = self.data.Low[-1]
            
            if self.last_pl_bar is not None:
                # Regular bullish: price LL + RSI HL
                if (self.show_reg_bull and 
                    curr_price < self.last_pl_price and 
                    curr_rsi > self.last_pl_rsi):
                    self.reg_bull_div = True
                
                # Hidden bullish: price HL + RSI LL
                if (self.show_hid_bull and 
                    curr_price > self.last_pl_price and 
                    curr_rsi < self.last_pl_rsi):
                    self.hid_bull_div = True
            
            self.last_pl_bar = curr_bar
            self.last_pl_price = curr_price
            self.last_pl_rsi = curr_rsi
        
        # Trading logic based on divergences and RSI crossovers
        # Buy on regular bullish divergence or RSI crossing above oversold
        if self.reg_bull_div or crossover(self.rsi, self.os):
            if not self.position:
                self.buy()
            self.reg_bull_div = False
        
        # Sell on regular bearish divergence or RSI crossing below overbought
        if self.reg_bear_div or crossover(self.ob, self.rsi):
            if self.position:
                self.sell()
            self.reg_bear_div = False
        
        # Reset divergence flags
        self.hid_bull_div = False
        self.hid_bear_div = False


