import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenHigh = 252
    lenMA = 200
    rsiLen = 14
    maProxPct = 15.0
    mode = "40-60% off High"
    atrLen = 14
    atrMult = 1.5
    hvRankMax = 50
    vixMax = 25.0
    sectorMALen = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Core indicators
        self.hh = self.I(lambda: high.rolling(self.lenHigh).max())
        self.offHighPc = self.I(lambda: (self.hh - close) / self.hh * 100)
        self.maLong = self.I(pta.sma, close, length=self.lenMA)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        self.volAvg = self.I(pta.sma, volume, length=20)
        self.relVol = self.I(lambda: volume / self.volAvg)
        self.maDistPct = self.I(lambda: np.abs(close - self.maLong) / self.maLong * 100)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)

        # HV Rank calculation
        self.logReturn = self.I(lambda: np.log(close / close.shift(1)))
        self.hvCurrent = self.I(lambda: self.logReturn.rolling(20).std() * np.sqrt(252) * 100)
        self.hvHigh52 = self.I(lambda: self.hvCurrent.rolling(252).max())
        self.hvLow52 = self.I(lambda: self.hvCurrent.rolling(252).min())
        self.hvRange = self.I(lambda: self.hvHigh52 - self.hvLow52)
        self.hvRank = self.I(lambda: (self.hvCurrent - self.hvLow52) / (self.hvRange + 1e-10) * 100)

        # ATR Stop and Targets
        self.stopPrice = self.I(lambda: close - (self.atrMult * self.atr))
        
        # Mode parameters
        if self.mode == "40-60% off High":
            self.rsiMin = 40.0
            self.rsiMax = 70.0
            self.tgtPct = 20.0
            self.volMult = 1.3
        elif self.mode == "60-80% off High (Deep)":
            self.rsiMin = 35.0
            self.rsiMax = 70.0
            self.tgtPct = 35.0
            self.volMult = 1.3
        else:  # Crypto-Linked
            self.rsiMin = 25.0
            self.rsiMax = 75.0
            self.tgtPct = 50.0
            self.volMult = 1.1

        self.tgtPrice = self.I(lambda: close * (1.0 + self.tgtPct / 100.0))
        self.tgt2Price = self.I(lambda: close * (1.0 + (self.tgtPct * 2.0) / 100.0))
        self.tgt3Price = self.I(lambda: self.hh)

        # Value band logic
        if self.mode == "40-60% off High":
            self.inValueBand = self.I(lambda: (self.offHighPc >= 40) & (self.offHighPc <= 60))
        elif self.mode == "60-80% off High (Deep)":
            self.inValueBand = self.I(lambda: (self.offHighPc >= 60) & (self.offHighPc <= 80))
        else:
            self.inValueBand = self.I(lambda: pd.Series(True, index=close.index))

        # RSI turn up
        self.rsiTurnUp = self.I(lambda: (self.rsi > self.rsiMin) & (self.rsi < self.rsiMax) & (self.rsi > self.rsi.shift(1)))

        # Volume OK
        self.volOK = self.I(lambda: self.relVol >= self.volMult)

        # Near MA
        self.nearMA = self.I(lambda: self.maDistPct <= self.maProxPct)

        # HV Rank OK
        self.hvRankOK = self.I(lambda: self.hvRank <= self.hvRankMax)

        # Price and RSI divergence
        self.priceLowerLow = self.I(lambda: (low < low.shift(1)) & (low.shift(1) < low.shift(2)))
        self.rsiHigherLow = self.I(lambda: (self.rsi > self.rsi.shift(1)) & (self.rsi.shift(1) > self.rsi.shift(2)))
        self.bullDiv = self.I(lambda: self.priceLowerLow & self.rsiHigherLow)

        # Base signal
        self.baseSignal = self.I(
            lambda: self.inValueBand & self.nearMA & self.rsiTurnUp & self.volOK
        )

        # Full signal with IV filter
        self.a1ValueTurn = self.I(
            lambda: self.baseSignal & self.hvRankOK
        )

    def next(self):
        if len(self.data) < 252:
            return

        # Entry condition
        if self.a1ValueTurn[-1]:
            if not self.position:
                self.buy()
                self.entry_price = self.data.Close[-1]
                self.stop_price = self.stopPrice[-1]
                self.tgt1_price = self.tgtPrice[-1]
                self.tgt2_price = self.tgt2Price[-1]
                self.tgt3_price = self.tgt3Price[-1]

        # Exit conditions
        if self.position:
            # Stop loss
            if self.data.Low[-1] <= self.stop_price:
                self.position.close()
            # Target 3 (52W High)
            elif self.data.High[-1] >= self.tgt3_price:
                self.position.close()
            # Target 2
            elif self.data.High[-1] >= self.tgt2_price:
                self.position.close()
            # Target 1
            elif self.data.High[-1] >= self.tgt1_price:
                self.position.close()


