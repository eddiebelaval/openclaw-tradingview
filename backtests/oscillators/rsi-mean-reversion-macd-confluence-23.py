import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI Settings
    rsi_length = 14
    rsi_oversold = 35
    rsi_overbought = 65
    
    # Mean Reversion Settings
    mr_length = 20
    mr_mult = 2.0
    
    # MACD Settings
    macd_fast = 12
    macd_slow = 26
    macd_signal = 9

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI Calculation
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Mean Reversion (Bollinger Bands)
        self.bb_basis = self.I(pta.sma, close, length=self.mr_length)
        
        # Standard deviation for Bollinger Bands
        def bb_dev_calc(c):
            result = pta.stdev(c, length=self.mr_length)
            return result if result is not None else pd.Series(0, index=c.index)
        
        self.bb_dev_raw = self.I(bb_dev_calc, close)
        
        def bb_upper_calc(c):
            basis = pta.sma(c, length=self.mr_length)
            dev = pta.stdev(c, length=self.mr_length)
            if basis is not None and dev is not None:
                return basis + (self.mr_mult * dev)
            return pd.Series(0, index=c.index)
        
        def bb_lower_calc(c):
            basis = pta.sma(c, length=self.mr_length)
            dev = pta.stdev(c, length=self.mr_length)
            if basis is not None and dev is not None:
                return basis - (self.mr_mult * dev)
            return pd.Series(0, index=c.index)
        
        self.bb_upper = self.I(bb_upper_calc, close)
        self.bb_lower = self.I(bb_lower_calc, close)
        
        # MACD Calculation
        def macd_calc(c):
            result = pta.macd(c, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_signal)
            if result is not None and not result.empty:
                return result.iloc[:, 0]
            return pd.Series(0, index=c.index)
        
        def macd_signal_calc(c):
            result = pta.macd(c, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_signal)
            if result is not None and not result.empty:
                return result.iloc[:, 2]
            return pd.Series(0, index=c.index)
        
        self.macd_line = self.I(macd_calc, close)
        self.macd_signal_line = self.I(macd_signal_calc, close)

