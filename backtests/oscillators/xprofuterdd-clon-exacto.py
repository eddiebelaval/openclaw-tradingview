import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    per = 14
    drawShift = 14
    maPeriod = 34
    showFuture = True

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        
        # Calculate point_mult equivalent (1.0 / syminfo.mintick)
        # Using 1.0 as default multiplier for normalized values
        point_mult = 1.0
        
        # Calculate body: (close - open) * point_mult
        def calculate_body():
            return (self.data.Close - self.data.Open) * point_mult
        
        # Calculate signal_hist: sum of body over (per + 1) bars
        def calculate_signal_hist():
            body = (self.data.Close - self.data.Open) * point_mult
            result = pd.Series(index=body.index, dtype=float)
            for i in range(len(body)):
                if i < self.per:
                    result.iloc[i] = np.nan
                else:
                    result.iloc[i] = body.iloc[i-self.per:i+1].sum()
            return result
        
        # Calculate moving average of signal_hist
        def calculate_ma_hist():
            signal = calculate_signal_hist()
            return signal.rolling(window=self.maPeriod).mean()
        
        self.signal_hist = self.I(calculate_signal_hist)
        self.ma_hist = self.I(calculate_ma_hist)

    def next(self):
        # Generate trading signals based on crossovers between signal and MA
        if len(self.signal_hist) < 2 or len(self.ma_hist) < 2:
            return
        
        # Buy signal: signal crosses above MA
        if crossover(self.signal_hist, self.ma_hist):
            if not self.position:
                self.buy()
        
        # Sell signal: signal crosses below MA
        elif crossover(self.ma_hist, self.signal_hist):
            if self.position:
                self.sell()


