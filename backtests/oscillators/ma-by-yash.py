import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA period based on default "2 years" timeframe
    MA_PERIOD = 730
    MULTIPLIER = 5.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate moving average
        self.ma = self.I(pta.sma, close, length=self.MA_PERIOD)
        
        # Calculate upper band
        self.upper_band = self.I(lambda: self.ma * self.MULTIPLIER)

    def next(self):
        # Buy when price crosses above the moving average from below
        if len(self.data) > self.MA_PERIOD and crossover(self.data.Close, self.ma):
            if not self.position:
                self.buy()
        
        # Sell when price crosses below the upper band from above
        elif len(self.data) > self.MA_PERIOD and crossover(self.upper_band, self.data.Close):
            if self.position:
                self.position.close()
        
        # Also sell if price falls back below moving average when in position
        elif len(self.data) > self.MA_PERIOD and self.position and self.data.Close[-1] < self.ma[-1]:
            self.position.close()


