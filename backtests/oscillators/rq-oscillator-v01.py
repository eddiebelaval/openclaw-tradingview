import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    smoothLength = 3

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Linear regression: ta.linreg(src, length, 0)
        # pandas_ta doesn't have linreg, so we'll implement it manually
        def linreg_calc(src):
            result = pd.Series(np.nan, index=src.index)
            for i in range(len(src)):
                if i < self.length - 1:
                    result.iloc[i] = np.nan
                else:
                    y = src.iloc[i - self.length + 1:i + 1].values
                    x = np.arange(len(y))
                    coeffs = np.polyfit(x, y, 1)
                    result.iloc[i] = coeffs[0] * (len(y) - 1) + coeffs[1]
            return result
        
        linreg = self.I(linreg_calc, close)
        
        # osc = src - linreg
        osc = self.I(lambda: close - linreg)
        
        # smoothedOsc = ta.sma(osc, smoothLength)
        smoothed_osc = self.I(lambda: pta.sma(osc, length=self.smoothLength))
        
        self.smoothed_osc = smoothed_osc

    def next(self):
        if len(self.data) < self.length + self.smoothLength:
            return
        
        current = self.smoothed_osc[-1]
        previous = self.smoothed_osc[-2] if len(self.smoothed_osc) > 1 else current
        
        # Buy when oscillator crosses above 0 and is rising
        if crossover(self.smoothed_osc, 0):
            if not self.position:
                self.buy()
        
        # Sell when oscillator crosses below 0 and is falling
        elif crossover(0, self.smoothed_osc):
            if self.position:
                self.sell()