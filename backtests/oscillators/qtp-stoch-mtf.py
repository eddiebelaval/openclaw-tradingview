import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 14
    smoothK = 3
    smoothD = 3
    upLine = 80
    lowLine = 20
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        stoch_raw = self.I(lambda: pta.stoch(high, low, close, k=self.len, d=self.smoothD, smooth_k=self.smoothK) or pd.DataFrame(index=close.index))
        
        if isinstance(stoch_raw, pd.DataFrame):
            self.k = self.I(lambda x=stoch_raw: x.iloc[:, 0] if len(x.columns) > 0 else pd.Series(50, index=close.index))
            self.d = self.I(lambda x=stoch_raw: x.iloc[:, 1] if len(x.columns) > 1 else pd.Series(50, index=close.index))
        else:
            self.k = self.I(lambda: pd.Series(50, index=close.index))
            self.d = self.I(lambda: pd.Series(50, index=close.index))
        
        self.upline_val = self.upLine
        self.lowline_val = self.lowLine
    
    def next(self):
        if len(self.data) < 2:
            return
        
        k_curr = self.k[-1] if len(self.k) > 0 else 50
        k_prev = self.k[-2] if len(self.k) > 1 else 50
        d_curr = self.d[-1] if len(self.d) > 0 else 50
        d_prev = self.d[-2] if len(self.d) > 1 else 50
        
        crossUp = (k_prev < d_prev and k_prev < self.lowline_val) and (k_curr > d_curr)
        crossDn = (k_prev > d_prev and k_prev > self.upline_val) and (k_curr < d_curr)
        
        if crossUp and not self.position:
            self.buy()
        elif crossDn and self.position:
            self.sell()


