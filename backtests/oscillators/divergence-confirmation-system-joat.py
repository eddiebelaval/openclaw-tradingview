        stoch_rsi_result = self.I(lambda: pta.stoch(rsi_for_stoch, rsi_for_stoch, rsi_for_stoch, k=self.stoch_period))
        self.stoch_rsi_k = stoch_rsi_result['STOCHk'] if stoch_rsi_result is not None else self.I(lambda: pd.Series(50, index=close.index))
        
