        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_period))
        self.mfi = self.I(lambda: pta.mfi(hlc3, length=self.mfi_period))
        
        stoch_result = self.I(lambda: pta.stoch(close, high, low, k=self.stoch_period))
        self.stoch_k = stoch_result['STOCHk'] if stoch_result is not None else self.I(lambda: pd.Series(50, index=close.index))
        
        macd_result = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_signal))
        self.macd_hist = macd_result['MACD_12_26_9'] - macd_result['MACDh_12_26_9'] if macd_result is not None else self.I(lambda: pd.Series(0, index=close.index))
        
        # CCI and Stoch RSI
        self.cci = self.I(lambda: pta.cci(high, low, close, length=20))
        
