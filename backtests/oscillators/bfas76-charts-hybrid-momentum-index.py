import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Input parameters from Pine Script
    pctile = 90  # Over_Bought
    wrnpctile = 70  # Over_Sold
    Short = 0.3  # LONG
    Long = 0.5  # SHORT
    lkbT = 250  # 'PRO-Top
    lkbB = 250  # 'PRO-Bottom
    DMIlength = 10  # DMI
    Stolength = 6  # DMI Stoch
    os = 15  # OS %
    ob = 85  # OB %

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Lag function implementation
        def calculate_lag(g, p_series):
            L0 = pd.Series(0.0, index=p_series.index)
            L1 = pd.Series(0.0, index=p_series.index)
            L2 = pd.Series(0.0, index=p_series.index)
            L3 = pd.Series(0.0, index=p_series.index)
            
            for i in range(len(p_series)):
                p = p_series.iloc[i]
                L0_prev = L0.iloc[i-1] if i > 0 else 0
                L1_prev = L1.iloc[i-1] if i > 0 else 0
                L2_prev = L2.iloc[i-1] if i > 0 else 0
                L3_prev = L3.iloc[i-1] if i > 0 else 0
                
                L0_val = (1 - g) * p + g * L0_prev
                L1_val = -g * L0_val + L0_prev + g * L1_prev
                L2_val = -g * L1_val + L1_prev + g * L2_prev
                L3_val = -g * L2_val + L2_prev + g * L3_prev
                
                L0.iloc[i] = L0_val
                L1.iloc[i] = L1_val
                L2.iloc[i] = L2_val
                L3.iloc[i] = L3_val
            
            result = (L0 + 2 * L1 + 2 * L2 + L3) / 6
            return result
        
        # hl2 calculation
        hl2 = (high + low) / 2
        
        # Laguerre lag calculation
        lmas = self.I(lambda: calculate_lag(self.Short, hl2))
        lmal = self.I(lambda: calculate_lag(self.Long, hl2))
        
        # PPO calculation
        ppoT = (lmas - lmal) / lmal * 100
        
        # Percentile rank
        pctRankT = self.I(lambda: pta.percentrank(ppoT, self.lkbT) or pd.Series(50, index=ppoT.index))
        
        # Custom WWMA function
        def calculate_wwma(src_series, length):
            result = pd.Series(0.0, index=src_series.index)
            for i in range(len(src_series)):
                if i == 0:
                    result.iloc[i] = src_series.iloc[i]
                else:
                    result.iloc[i] = (result.iloc[i-1] * (length - 1) + src_series.iloc[i]) / length
            return result
        
        # DMI calculations
        hiDiff = high.diff()
        loDiff = -low.diff()
        
        plusDM = pd.Series(0.0, index=close.index)
        minusDM = pd.Series(0.0, index=close.index)
        
        for i in range(len(close)):
            if i == 0:
                plusDM.iloc[i] = 0
                minusDM.iloc[i] = 0
            else:
                if hiDiff.iloc[i] > loDiff.iloc[i] and hiDiff.iloc[i] > 0:
                    plusDM.iloc[i] = hiDiff.iloc[i]
                else:
                    plusDM.iloc[i] = 0
                    
                if loDiff.iloc[i] > hiDiff.iloc[i] and loDiff.iloc[i] > 0:
                    minusDM.iloc[i] = loDiff.iloc[i]
                else:
                    minusDM.iloc[i] = 0
        
        # TR calculation
        tr = pd.Series(0.0, index=close.index)
        for i in range(len(close)):
            if i == 0:
                tr.iloc[i] = high.iloc[i] - low.iloc[i]
            else:
                tr.iloc[i] = max(
                    high.iloc[i] - low.iloc[i],
                    abs(high.iloc[i] - close.iloc[i-1]),
                    abs(low.iloc[i] - close.iloc[i-1])
                )
        
        # ATR and DI calculations
        ATR = self.I(lambda: calculate_wwma(tr, self.DMIlength))
        PlusDI = self.I(lambda: 100 * calculate_wwma(plusDM, self.DMIlength) / (ATR + 1e-10))
        MinusDI = self.I(lambda: 100 * calculate_wwma(minusDM, self.DMIlength) / (ATR + 1e-10))
        
        # Stochastic calculation
        osc = PlusDI - MinusDI
        
        def calculate_stoch(osc_series, length):
            hi = osc_series.rolling(window=length).max()
            lo = osc_series.rolling(window=length).min()
            
            numerator = (osc_series - lo).rolling(window=length).sum()
            denominator = (hi - lo).rolling(window=length).sum()
            
            stoch = (numerator / (denominator + 1e-10)) * 100
            return stoch.fillna(50)
        
        self.Stoch = self.I(lambda: calculate_stoch(osc, self.Stolength))
        
        self.crossUp_signal = False
        self.crossDo_signal = False

    def next(self):
        # Signal detection
        if len(self.data) > 1:
            if self.Stoch[-2] < self.os and self.Stoch[-1] >= self.os:
                self.crossUp_signal = True
            else:
                self.crossUp_signal = False
            
            if self.Stoch[-2] > self.ob and self.Stoch[-1] <= self.ob:
                self.crossDo_signal = True
            else:
                self.crossDo_signal = False
        
        # Trading logic
        if self.crossUp_signal:
            if self.position.is_short:
                self.position.close()
            self.buy()
        elif self.crossDo_signal:
            if self.position.is_long:
                self.position.close()
            self.sell()