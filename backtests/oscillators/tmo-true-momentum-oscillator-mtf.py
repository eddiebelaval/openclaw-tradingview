import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    calcLength = 5
    smoothLength = 3

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        
        def calculate_tmo(len_val, clen, slen):
            data = pd.Series(0, index=close.index)
            for i in range(len(close)):
                if i < len_val:
                    lookback = min(i + 1, len_val)
                    count = 0
                    for j in range(lookback):
                        if close.iloc[i] > open_.iloc[i - j]:
                            count += 1
                        elif close.iloc[i] < open_.iloc[i - j]:
                            count -= 1
                    data.iloc[i] = count
                else:
                    count = 0
                    for j in range(len_val):
                        if close.iloc[i] > open_.iloc[i - j]:
                            count += 1
                        elif close.iloc[i] < open_.iloc[i - j]:
                            count -= 1
                    data.iloc[i] = count
            
            ema5 = pta.ema(data, length=clen)
            if ema5 is None:
                ema5 = pd.Series(0, index=close.index)
            main = pta.ema(ema5, length=slen)
            if main is None:
                main = pd.Series(0, index=close.index)
            signal = pta.ema(main, length=slen)
            if signal is None:
                signal = pd.Series(0, index=close.index)
            
            return main, signal
        
        self.main, self.signal = calculate_tmo(self.length, self.calcLength, self.smoothLength)

    def next(self):
        if len(self.data) < self.length + self.calcLength + self.smoothLength:
            return
        
        # Buy on crossover of main above signal
        if crossover(self.main, self.signal):
            if not self.position:
                self.buy()
        
        # Sell on crossunder of main below signal
        elif crossover(self.signal, self.main):
            if self.position:
                self.position.close()


