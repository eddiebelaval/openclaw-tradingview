        K0 = Pp00 / S_k if S_k != 0 else 0.0
        K1 = Pp10 / S_k if S_k != 0 else 0.0
        
        # ── 4. UPDATE STEP ──
        self.x0_state = xp0 + K0 * innov
        self.x1_state = xp1 + K1 * innov
