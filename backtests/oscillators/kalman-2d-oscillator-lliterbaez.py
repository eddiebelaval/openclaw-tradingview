        current_price = self.data.Close[-1]
        
        # Calculate adaptive noise parameters
        if len(self.price_std) > 0 and self.price_std[-1] is not None:
            price_std_val = self.price_std[-1]
        else:
            price_std_val = 0.0001
        
        R_k = price_std_val ** 2
        Q_k = self.q_scale * R_k
        
