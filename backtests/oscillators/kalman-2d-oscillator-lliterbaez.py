        xp0 = self.x0_state + self.x1_state
        xp1 = self.x1_state
        Pp00 = self.P00_state + self.P01_state + self.P10_state + self.P11_state + Q_k
        Pp01 = self.P01_state + self.P11_state
        Pp10 = self.P10_state + self.P11_state
        Pp11 = self.P11_state + Q_k
        
        # ── 2. INNOVATION ──
        innov = current_price - xp0
        S_k = Pp00 + R_k
        
