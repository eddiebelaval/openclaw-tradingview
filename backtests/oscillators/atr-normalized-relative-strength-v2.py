import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 14
    normalization_mode = "ATR%"
    display_mode = "RS"
    rs_ma_type = "SMA"
    rs_ma_len = 50
    color_by_ma = True
    mansfield_len = 200
    mansfield_scale = 100.0
    show_mansfield_zero = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate base ATR and normalized values
        base_atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # ATR% calculation
        def calc_base_atr_pct():
            atr = pta.atr(high, low, close, length=self.atr_len)
            if atr is None:
                return pd.Series(np.nan, index=close.index)
            result = pd.Series(np.nan, index=close.index)
            mask = (atr.notna()) & (close != 0.0)
            result[mask] = atr[mask] / close[mask]
            return result
        
        base_atr_pct = self.I(calc_base_atr_pct)
        
        # Normalized ATR Price
        def calc_base_norm_atr():
            atr = pta.atr(high, low, close, length=self.atr_len)
            if atr is None:
                return pd.Series(np.nan, index=close.index)
            result = pd.Series(np.nan, index=close.index)
            mask = (atr.notna()) & (atr != 0.0)
            result[mask] = close[mask] / atr[mask]
            return result
        
        base_norm_atr = self.I(calc_base_norm_atr)
        
        # Normalized ATR%
        def calc_base_norm_atr_pct():
            atr = pta.atr(high, low, close, length=self.atr_len)
            if atr is None:
                return pd.Series(np.nan, index=close.index)
            atr_pct = pd.Series(np.nan, index=close.index)
            mask1 = (atr.notna()) & (close != 0.0)
            atr_pct[mask1] = atr[mask1] / close[mask1]
            result = pd.Series(np.nan, index=close.index)
            mask2 = (atr_pct.notna()) & (atr_pct != 0.0)
            result[mask2] = close[mask2] / atr_pct[mask2]
            return result
        
        base_norm_atr_pct = self.I(calc_base_norm_atr_pct)
        
        # Select normalization mode
        def calc_base_norm():
            if self.normalization_mode == "ATR Price":
                return base_norm_atr
            else:
                return base_norm_atr_pct
        
        self.base_norm = self.I(calc_base_norm)
        
        # For comparison symbol, we only have the current symbol data
        # So we'll use the same calculations for both base and comparison
        self.comp_norm = self.base_norm
        
        # Calculate ATR normalized RS
        def calc_atr_normalized_rs():
            result = pd.Series(np.nan, index=close.index)
            mask = (self.base_norm.notna()) & (self.comp_norm.notna()) & (self.comp_norm != 0.0)
            result[mask] = self.base_norm[mask] / self.comp_norm[mask]
            return result
        
        self.atr_normalized_rs = self.I(calc_atr_normalized_rs)
        
        # Calculate RS MA
        def calc_rs_ma():
            if self.rs_ma_type == "EMA":
                return pta.ema(self.atr_normalized_rs, length=self.rs_ma_len)
            else:
                return pta.sma(self.atr_normalized_rs, length=self.rs_ma_len)
        
        self.rs_ma = self.I(calc_rs_ma)
        
        # Calculate Mansfield
        mansfield_ma = self.I(pta.sma, self.atr_normalized_rs, length=self.mansfield_len)
        
        def calc_mansfield():
            result = pd.Series(np.nan, index=close.index)
            mask = (self.atr_normalized_rs.notna()) & (mansfield_ma.notna()) & (mansfield_ma != 0.0)
            result[mask] = ((self.atr_normalized_rs[mask] / mansfield_ma[mask]) - 1.0) * self.mansfield_scale
            return result
        
        self.mansfield = self.I(calc_mansfield)

    def next(self):
        # Buy when RS crosses above its MA
        if len(self.data) > self.rs_ma_len:
            if crossover(self.atr_normalized_rs, self.rs_ma):
                if not self.position:
                    self.buy()
            # Sell when RS crosses below its MA
            elif crossover(self.rs_ma, self.atr_normalized_rs):
                if self.position:
                    self.position.close()