import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Squeeze Detection Parameters
    i_bbLen = 20
    i_bbMult = 2.0
    i_kcLen = 20
    i_kcMultHi = 1.0
    i_kcMultMd = 1.5
    i_kcMultLo = 2.0
    i_minSqzLen = 8
    
    # Momentum Parameters
    i_momLen = 20
    i_momSmooth = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        self.bbBasis = self.I(pta.sma, close, length=self.i_bbLen)
        self.bbDev = self.I(lambda: self.i_bbMult * close.rolling(self.i_bbLen).std())
        self.bbUpper = self.I(lambda: self.bbBasis + self.bbDev)
        self.bbLower = self.I(lambda: self.bbBasis - self.bbDev)
        
        # ATR for Keltner Channels
        self.atrVal = self.I(pta.atr, high, low, close, length=self.i_kcLen)
        
        # Keltner Channel basis
        self.kcBasis = self.I(pta.sma, close, length=self.i_kcLen)
        
        # Keltner Channel High Squeeze (tightest)
        self.kcUpHi = self.I(lambda: self.kcBasis + self.i_kcMultHi * self.atrVal.fillna(0))
        self.kcLoHi = self.I(lambda: self.kcBasis - self.i_kcMultHi * self.atrVal.fillna(0))
        
        # Keltner Channel Mid Squeeze
        self.kcUpMd = self.I(lambda: self.kcBasis + self.i_kcMultMd * self.atrVal.fillna(0))
        self.kcLoMd = self.I(lambda: self.kcBasis - self.i_kcMultMd * self.atrVal.fillna(0))
        
        # Keltner Channel Low Squeeze (widest)
        self.kcUpLo = self.I(lambda: self.kcBasis + self.i_kcMultLo * self.atrVal.fillna(0))
        self.kcLoLo = self.I(lambda: self.kcBasis - self.i_kcMultLo * self.atrVal.fillna(0))
        
        # Momentum calculation
        highest_hi = self.I(lambda: high.rolling(self.i_momLen).max())
        lowest_lo = self.I(lambda: low.rolling(self.i_momLen).min())
        sma_close = self.I(pta.sma, close, length=self.i_momLen)
        
        self.midline = self.I(lambda: (highest_hi + lowest_lo) / 2.0)
        
        # Linear regression of (close - midline)
        self.mom = self.I(self._calc_mom, close)
        
        # EMA smoothing of momentum
        self.momEMA = self.I(lambda: pta.ema(self.mom.fillna(0), length=self.i_momSmooth))
        
        # Track squeeze state
        self.sqz_duration = 0
        self.prev_sqz_on = False
        self.total_sqz_duration = 0
        self.sqz_count = 0
        self.last_fire_bar = -1000
        self.last_fire_dir = 0
        
    def _calc_mom(self, close):
        """Calculate momentum using linear regression"""
        mom_series = pd.Series(0.0, index=close.index)
        
        for i in range(self.i_momLen, len(close)):
            window_close = close.iloc[i - self.i_momLen:i]
            window_high = self.data.High[i - self.i_momLen:i]
            window_low = self.data.Low[i - self.i_momLen:i]
            
            highest = window_high.max()
            lowest = window_low.min()
            midline = (highest + lowest) / 2.0
            
            deviation = window_close - midline
            x = np.arange(len(deviation))
            
            if len(deviation) > 1:
                coeffs = np.polyfit(x, deviation.values, 1)
                mom_series.iloc[i] = coeffs[0]
        
        return mom_series

    def next(self):
        if len(self.data) < self.i_momLen + self.i_bbLen:
            return
        
        # Current values
        bb_upper = self.bbUpper[-1]
        bb_lower = self.bbLower[-1]
        kc_up_hi = self.kcUpHi[-1]
        kc_lo_hi = self.kcLoHi[-1]
        kc_up_lo = self.kcUpLo[-1]
        kc_lo_lo = self.kcLoLo[-1]
        mom = self.mom[-1]
        
        # Squeeze conditions
        sqz_high = bb_upper < kc_up_hi and bb_lower > kc_lo_hi
        sqz_low = bb_upper < kc_up_lo and bb_lower > kc_lo_lo
        sqz_on = sqz_low
        
        # Update squeeze tracking
        if sqz_on:
            self.sqz_duration += 1
        
        # Detect squeeze fire (transition from ON to OFF)
        sqz_fire = False
        if self.prev_sqz_on and not sqz_on and self.sqz_duration >= self.i_minSqzLen:
            sqz_fire = True
            self.sqz_count += 1
            self.total_sqz_duration += self.sqz_duration
            self.last_fire_bar = len(self.data)
            self.last_fire_dir = 1 if mom > 0 else -1
        
        # Reset duration after fire check
        if self.prev_sqz_on and not sqz_on:
            self.sqz_duration = 0
        
        self.prev_sqz_on = sqz_on
        
        # Momentum direction (for reversal signals)
        mom_prev = self.mom[-2] if len(self.mom) > 1 else mom
        mom_rising = mom > mom_prev
        mom_falling = mom < mom_prev
        
        # Entry signals: Squeeze fire with momentum direction
        if sqz_fire:
            if mom > 0 and mom_rising:
                # Bullish squeeze fire
                if not self.position:
                    self.buy()
            elif mom < 0 and mom_falling:
                # Bearish squeeze fire
                if self.position:
                    self.position.close()
        
        # Exit signals: Momentum zero-line cross
        mom_prev = self.mom[-2] if len(self.mom) > 1 else 0
        
        if self.position:
            # Exit long on bearish momentum flip
            if mom >= 0 and mom_prev < 0:
                self.position.close()
            # Exit short on bullish momentum flip
            elif mom < 0 and mom_prev >= 0:
                self.position.close()
            
            # Also exit if momentum crosses back through zero aggressively
            if mom_falling and mom < 0 and self.position.is_long:
                self.position.close()