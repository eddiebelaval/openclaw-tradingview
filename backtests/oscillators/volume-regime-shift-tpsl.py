import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    short_length = 5
    long_length = 100
    low_mult = 0.7
    normal_mult = 1.2
    high_mult = 1.8
    maxBars = 100
    atr_period = 14
    sl_atr_mult = 1.5
    sl_percent = 1.0
    rr_tp1 = 1.0
    rr_tp2 = 2.0
    rr_tp3 = 3.0
    use_atr_sl = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.vol_short = self.I(pta.sma, volume, length=self.short_length)
        self.vol_long = self.I(pta.sma, volume, length=self.long_length)
        
        self.vol_regime = self.I(
            lambda: self.vol_short / np.maximum(self.vol_long, 0.000001)
        )
        
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_period)

        self.entry_price = None
        self.sl_level = None
        self.tp1_level = None
        self.tp2_level = None
        self.tp3_level = None
        self.entry_bar = None
        self.box_top = None
        self.box_bottom = None
        self.box_start_bar = None
        self.building = False
        self.box_active = False

    def next(self):
        if len(self.data) < max(self.short_length, self.long_length, self.atr_period):
            return

        vol_regime_current = self.vol_regime[-1]
        is_high_vol = vol_regime_current > self.high_mult
        high = self.data.High[-1]
        low = self.data.Low[-1]
        close = self.data.Close[-1]

        start_sequence = is_high_vol and not self.building and not self.box_active

        if start_sequence:
            self.building = True
            self.box_active = True
            self.box_top = high
            self.box_bottom = low
            self.box_start_bar = len(self.data) - 1

        if self.building and is_high_vol:
            self.box_top = max(self.box_top, high)
            self.box_bottom = min(self.box_bottom, low)

        if self.building and not is_high_vol:
            self.building = False

        breakout_up = self.box_active and close > self.box_top
        breakout_down = self.box_active and close < self.box_bottom

        if self.box_active:
            bars_alive = len(self.data) - 1 - self.box_start_bar
            timeout = bars_alive > self.maxBars
            if timeout:
                self.box_active = False
                self.building = False

        if breakout_up:
            if not self.position:
                self.entry_price = close
                self.entry_bar = len(self.data) - 1
                atr_current = self.atr_val[-1] if self.atr_val[-1] is not None else 0
                
                if self.use_atr_sl:
                    risk_dist = atr_current * self.sl_atr_mult
                else:
                    risk_dist = self.entry_price * (self.sl_percent / 100)

                self.sl_level = self.entry_price - risk_dist
                self.tp1_level = self.entry_price + risk_dist * self.rr_tp1
                self.tp2_level = self.entry_price + risk_dist * self.rr_tp2
                self.tp3_level = self.entry_price + risk_dist * self.rr_tp3

                self.buy()

            self.box_active = False
            self.building = False

        elif breakout_down:
            if self.position:
                self.position.close()

            self.entry_price = close
            self.entry_bar = len(self.data) - 1
            atr_current = self.atr_val[-1] if self.atr_val[-1] is not None else 0
            
            if self.use_atr_sl:
                risk_dist = atr_current * self.sl_atr_mult
            else:
                risk_dist = self.entry_price * (self.sl_percent / 100)

            self.sl_level = self.entry_price + risk_dist
            self.tp1_level = self.entry_price - risk_dist * self.rr_tp1
            self.tp2_level = self.entry_price - risk_dist * self.rr_tp2
            self.tp3_level = self.entry_price - risk_dist * self.rr_tp3

            self.box_active = False
            self.building = False

        if self.position:
            if self.position.is_long:
                if low <= self.sl_level or high >= self.tp3_level:
                    self.position.close()
            elif self.position.is_short:
                if high >= self.sl_level or low <= self.tp3_level:
                    self.position.close()


