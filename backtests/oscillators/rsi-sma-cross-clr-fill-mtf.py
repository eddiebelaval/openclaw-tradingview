import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    ma_length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI using RMA (EMA-like smoothing)
        def calc_rsi(src, length):
            change = src.diff()
            up = change.clip(lower=0).ewm(span=length, adjust=False).mean()
            down = -change.clip(upper=0).ewm(span=length, adjust=False).mean()
            rs = up / down
            rsi = 100 - (100 / (1 + rs))
            return rsi.fillna(50)
        
        self.rsi = self.I(lambda: calc_rsi(close, self.rsi_length))
        
        # Calculate SMA of RSI
        self.sma = self.I(pta.sma, pd.Series(self.rsi), length=self.ma_length)

    def next(self):
        # Buy when RSI crosses above SMA
        if crossover(self.rsi, self.sma):
            self.buy()
        # Sell when RSI crosses below SMA
        elif crossover(self.sma, self.rsi):
            self.sell()


