import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # CRSI Parameters
    rsiLen = 2
    streakLen = 3
    prcLen = 80
    crsiOversold = 25
    crsiOverbought = 75
    
    # Keltner Parameters
    keltnerLength = 18
    keltnerMult = 1.5
    
    # Risk Management Parameters
    useStopLoss = True
    slAtrMult = 2.2
    useTakeProfit = True
    tpRatio = 2.5
    useTrailingStop = True
    trailActivationMult = 1.5
    trailOffsetMult = 1.0
    
    minDistance = 5
    minHoldBars = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=10)
        
        # Calculate Keltner EMA basis
        self.basis = self.I(pta.ema, close, length=self.keltnerLength)
        
        # Calculate CRSI for signal timeframe (5m equivalent - using current data)
        self.crsi_signal = self.I(self._calc_crsi, close)
        
        # For trend (would need multi-timeframe data in real implementation)
        # Here we use the same CRSI but with a smoothing to simulate 30m
        self.crsi_trend = self.I(self._calc_crsi_smoothed, close)
        
        # Track entry bars
        self.last_trade_bar = -np.inf
        self.long_entry_bar = -np.inf
        self.short_entry_bar = -np.inf

    def _calc_crsi(self, close_series):
        """Calculate CRSI indicator"""
        if len(close_series) < max(self.rsiLen, self.streakLen, self.prcLen) + 1:
            return pd.Series(50, index=close_series.index)
        
        try:
            rsi1 = pta.rsi(close_series, length=self.rsiLen)
            
            # Calculate streak
            streak = pd.Series(0, index=close_series.index, dtype=float)
            for i in range(1, len(close_series)):
                if close_series.iloc[i] > close_series.iloc[i-1]:
                    streak.iloc[i] = streak.iloc[i-1] + 1 if streak.iloc[i-1] > 0 else 1
                elif close_series.iloc[i] < close_series.iloc[i-1]:
                    streak.iloc[i] = streak.iloc[i-1] - 1 if streak.iloc[i-1] < 0 else -1
                else:
                    streak.iloc[i] = 0
            
            rsi2 = pta.rsi(streak, length=self.streakLen)
            
            # Percent rank of close change
            close_change = close_series.diff()
            percentrank = pta.percentrank(close_change, length=self.prcLen)
            
            crsi = (rsi1 + rsi2 + percentrank) / 3
            return crsi.fillna(50)
        except:
            return pd.Series(50, index=close_series.index)
    
    def _calc_crsi_smoothed(self, close_series):
        """Calculate smoothed CRSI for trend (simulating 30m from 5m)"""
        crsi = self._calc_crsi(close_series)
        smoothed = pta.ema(crsi, length=6)
        return smoothed.fillna(50)

    def next(self):
        # Current values
        crsi_signal = self.crsi_signal[-1]
        crsi_trend = self.crsi_trend[-1]
        close_price = self.data.Close[-1]
        atr_val = self.atr[-1]
        basis_val = self.basis[-1]
        
        # Trend determination
        in_range = 40 <= crsi_trend <= 60
        trend_bull = crsi_trend > 60
        trend_bear = crsi_trend < 40
        
        # CRSI signals
        crsi_oversold = crsi_signal <= self.crsiOversold
        crsi_overbought = crsi_signal >= self.crsiOverbought
        
        # Candle patterns
        open_price = self.data.Open[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        
        body = abs(close_price - open_price)
        range_val = high_price - low_price
        
        bullish_candle = (close_price > open_price and 
                         body >= range_val * 0.3)
        bearish_candle = (close_price < open_price and 
                         body >= range_val * 0.3)
        
        # Keltner bands
        upper_band = basis_val + self.keltnerMult * atr_val
        lower_band = basis_val - self.keltnerMult * atr_val
        
        # Range trading signals
        range_buy = (in_range and 
                    low_price < lower_band and 
                    crsi_oversold and 
                    bullish_candle)
        range_sell = (in_range and 
                     high_price > upper_band and 
                     crsi_overbought and 
                     bearish_candle)
        
        # Trend trading signals
        trend_buy_pullback = (trend_bull and 
                             crsi_oversold and 
                             close_price <= lower_band * 1.02)
        trend_sell_pullback = (trend_bear and 
                              crsi_overbought and 
                              close_price >= upper_band * 0.98)
        
        trend_buy_breakout = (trend_bull and 
                             crsi_oversold)
        trend_sell_breakout = (trend_bear and 
                              crsi_overbought)
        
        trend_buy = trend_buy_pullback or trend_buy_breakout
        trend_sell = trend_sell_pullback or trend_sell_breakout
        
        # Final signals
        raw_buy_signal = range_buy or trend_buy
        raw_sell_signal = range_sell or trend_sell
        
        # Position management
        can_trade = len(self) - self.last_trade_bar >= self.minDistance
        
        can_close_long = (len(self) - self.long_entry_bar >= self.minHoldBars 
                         if self.long_entry_bar > -np.inf else False)
        can_close_short = (len(self) - self.short_entry_bar >= self.minHoldBars 
                          if self.short_entry_bar > -np.inf else False)
        
        # Execute trades
        if raw_buy_signal and can_trade and not self.position:
            long_stop = close_price - self.slAtrMult * atr_val
            long_target = close_price + self.tpRatio * self.slAtrMult * atr_val
            
            self.buy()
            self.last_trade_bar = len(self)
            self.long_entry_bar = len(self)
        
        if raw_sell_signal and can_trade and not self.position:
            short_stop = close_price + self.slAtrMult * atr_val
            short_target = close_price - self.tpRatio * self.slAtrMult * atr_val
            
            self.sell()
            self.last_trade_bar = len(self)
            self.short_entry_bar = len(self)
        
        # Close positions on opposite signals
        if raw_sell_signal and can_close_long and self.position.size > 0:
            self.position.close()
        
        if raw_buy_signal and can_close_short and self.position.size < 0:
            self.position.close()


