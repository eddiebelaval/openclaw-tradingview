        ema26 = self.I(pta.ema, close, length=26)
        macd = ema12 - ema26
        ema_signal = self.I(pta.ema, macd, length=9)
        macd_hist = macd - ema_signal
        
        macd_std = pd.Series(macd_hist).rolling(self.polarityLength).std()
        macd_normalized = np.where(macd_std > 0, (macd_hist / macd_std) * 30, 0)
        momentum_polarity = (rsi_polarity + macd_normalized) / 2
