        price_high = high.rolling(self.polarityLength).max()
        price_low = low.rolling(self.polarityLength).min()
        price_range = price_high - price_low
        price_polarity = np.where(price_range > 0, (price_change / price_range) * 100, 0)
        self.smooth_price_polarity = self.I(pta.ema, pd.Series(price_polarity), length=self.smoothing)

        # Volume Polarity
        bull_volume = np.where(close > open_, volume, 0)
        bear_volume = np.where(close < open_, volume, 0)
        bull_vol_sma = pd.Series(bull_volume).rolling(self.polarityLength).mean()
        bear_vol_sma = pd.Series(bear_volume).rolling(self.polarityLength).mean()
        total_volume = volume.rolling(self.polarityLength).mean()
        volume_polarity = np.where(total_volume > 0, ((bull_vol_sma - bear_vol_sma) / total_volume) * 100, 0)
        self.smooth_volume_polarity = self.I(pta.ema, pd.Series(volume_polarity), length=self.smoothing)

        # Momentum Polarity
        rsi = self.I(pta.rsi, close, length=self.polarityLength)
        rsi_polarity = (rsi - 50) * 2
        
