import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    preset_config = 'Default'
    band_multiplier = 3.0
    band_atr_length = 10
    er_length = 10
    norm_atr_fast = 5
    norm_atr_slow = 30
    enable_neutral = True
    neutral_threshold = 25.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Apply preset configuration
        active_multiplier = self.band_multiplier
        active_atr_length = self.band_atr_length
        active_er_length = self.er_length
        active_norm_fast = self.norm_atr_fast
        active_norm_slow = self.norm_atr_slow
        
        if self.preset_config == 'Fast Response':
            active_multiplier = 2.0
            active_atr_length = 7
            active_er_length = 7
            active_norm_fast = 3
            active_norm_slow = 20
        elif self.preset_config == 'Smooth Trend':
            active_multiplier = 4.0
            active_atr_length = 14
            active_er_length = 20
            active_norm_fast = 8
            active_norm_slow = 50
        
        # Calculate SuperTrend manually
        def calculate_supertrend(high, low, close, multiplier, atr_length):
            atr_vals = pta.atr(high, low, close, length=atr_length)
            if atr_vals is None:
                atr_vals = pd.Series(0, index=close.index)
            
            hl_avg = (high + low) / 2
            basic_ub = hl_avg + multiplier * atr_vals
            basic_lb = hl_avg - multiplier * atr_vals
            
            final_ub = pd.Series(0.0, index=close.index)
            final_lb = pd.Series(0.0, index=close.index)
            
            for i in range(len(close)):
                if i == 0:
                    final_ub.iloc[i] = basic_ub.iloc[i]
                    final_lb.iloc[i] = basic_lb.iloc[i]
                else:
                    final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                    final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
            
            supertrend = pd.Series(0.0, index=close.index)
            for i in range(len(close)):
                if i == 0:
                    supertrend.iloc[i] = final_ub.iloc[i]
                else:
                    if supertrend.iloc[i-1] == final_ub.iloc[i-1]:
                        supertrend.iloc[i] = final_ub.iloc[i] if close.iloc[i] <= final_ub.iloc[i] else final_lb.iloc[i]
                    else:
                        supertrend.iloc[i] = final_lb.iloc[i] if close.iloc[i] >= final_lb.iloc[i] else final_ub.iloc[i]
            
            return supertrend
        
        self.supertrend_line = self.I(lambda: calculate_supertrend(high, low, close, active_multiplier, active_atr_length))
        
        # Price distance from supertrend
        self.price_distance = self.I(lambda: close - self.supertrend_line)
        
        # Efficiency Ratio
        def calc_efficiency_ratio(close, er_len):
            price_change = np.abs(close - close.shift(er_len))
            path_length = pd.Series(0.0, index=close.index)
            for i in range(len(close)):
                if i >= er_len:
                    path_length.iloc[i] = np.sum(np.abs(close.iloc[i-er_len+1:i+1].diff().dropna()))
                else:
                    path_length.iloc[i] = 0
            
            efficiency_ratio = pd.Series(0.0, index=close.index)
            for i in range(len(close)):
                if path_length.iloc[i] != 0:
                    efficiency_ratio.iloc[i] = price_change.iloc[i] / path_length.iloc[i]
                else:
                    efficiency_ratio.iloc[i] = 0.0
            return efficiency_ratio
        
        self.efficiency_ratio = self.I(lambda: calc_efficiency_ratio(close, active_er_length))
        
        # Adaptive ATR
        atr_fast = self.I(pta.atr, high, low, close, length=active_norm_fast)
        atr_slow = self.I(pta.atr, high, low, close, length=active_norm_slow)
        
        def calc_adaptive_atr(er, atr_f, atr_s):
            if atr_f is None or atr_s is None:
                return pd.Series(1.0, index=close.index)
            return er * atr_f + (1.0 - er) * atr_s
        
        self.adaptive_atr = self.I(lambda: calc_adaptive_atr(self.efficiency_ratio, atr_fast, atr_slow))
        
        # Calculate score
        def calc_score(price_dist, adapt_atr):
            score = pd.Series(0.0, index=price_dist.index)
            for i in range(len(price_dist)):
                if adapt_atr.iloc[i] != 0:
                    score.iloc[i] = (price_dist.iloc[i] / adapt_atr.iloc[i]) * 100
                else:
                    score.iloc[i] = 0.0
            return score
        
        self.score = self.I(lambda: calc_score(self.price_distance, self.adaptive_atr))
        
        # Score deviation for overbought/oversold levels
        def calc_score_dev(score):
            return score.rolling(window=100).std()
        
        self.score_deviation = self.I(lambda: calc_score_dev(self.score))
        
        # Trend detection
        def calc_trend_state(score, score_dev, neutral_thresh, neutral_enabled):
            is_neutral = pd.Series(False, index=score.index)
            is_bullish = pd.Series(False, index=score.index)
            
            for i in range(len(score)):
                if score_dev.iloc[i] != 0 and neutral_enabled:
                    is_neutral.iloc[i] = np.abs(score.iloc[i]) <= neutral_thresh
                else:
                    is_neutral.iloc[i] = False
                
                if not is_neutral.iloc[i]:
                    is_bullish.iloc[i] = score.iloc[i] > 0
            
            return is_neutral, is_bullish
        
        self.is_neutral = self.I(lambda: calc_trend_state(self.score, self.score_deviation, self.neutral_threshold, self.enable_neutral)[0])
        self.is_bullish = self.I(lambda: calc_trend_state(self.score, self.score_deviation, self.neutral_threshold, self.enable_neutral)[1])
        
        # Trend changes
        def calc_trend_changes(is_bull, is_neutr):
            trend_turned_bullish = pd.Series(False, index=is_bull.index)
            trend_turned_bearish = pd.Series(False, index=is_bull.index)
            
            for i in range(1, len(is_bull)):
                trend_turned_bullish.iloc[i] = is_bull.iloc[i] and not is_bull.iloc[i-1]
                trend_turned_bearish.iloc[i] = not is_neutr.iloc[i] and not is_bull.iloc[i] and (is_bull.iloc[i-1] or is_neutr.iloc[i-1])
            
            return trend_turned_bullish, trend_turned_bearish
        
        self.trend_turned_bullish = self.I(lambda: calc_trend_changes(self.is_bullish, self.is_neutral)[0])
        self.trend_turned_bearish = self.I(lambda: calc_trend_changes(self.is_bullish, self.is_neutral)[1])

    def next(self):
        if len(self.data) < 101:
            return
        
        # Buy on bullish trend confirmation
        if self.trend_turned_bullish[-1] and not self.position:
            self.buy()
        
        # Sell on bearish trend confirmation
        elif self.trend_turned_bearish[-1] and self.position:
            self.position.close()
        
        # Exit long if score becomes neutral and we have a position
        if self.position and self.is_neutral[-1] and not self.is_bullish[-1]:
            self.position.close()