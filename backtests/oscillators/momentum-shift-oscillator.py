import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    stochLen = 14
    kSmooth = 3
    dSmooth = 3
    rocLen = 10
    sigLen = 5
    macdFast = 12
    macdSlow = 26
    macdSignal = 9
    normLen = 100
    normMult = 10.0
    wRSI = 0.45
    wSRSI = 0.15
    wMACD = 0.25
    wROC = 0.15

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # RSI
        self.rsiVal = self.I(pta.rsi, close, length=self.rsiLen)

        # Stoch RSI
        rsiBase = self.I(pta.rsi, close, length=self.rsiLen)
        rsiLowest = self.I(lambda: rsiBase.rolling(self.stochLen).min() if len(rsiBase) > 0 else pd.Series(50, index=close.index))
        rsiHighest = self.I(lambda: rsiBase.rolling(self.stochLen).max() if len(rsiBase) > 0 else pd.Series(50, index=close.index))
        
        def stoch_rsi_raw():
            result = pd.Series(50.0, index=close.index)
            for i in range(len(rsiBase)):
                if rsiHighest[i] - rsiLowest[i] != 0.0:
                    result.iloc[i] = 100.0 * (rsiBase[i] - rsiLowest[i]) / (rsiHighest[i] - rsiLowest[i])
                else:
                    result.iloc[i] = 50.0
            return result
        
        stochRsiRaw = self.I(stoch_rsi_raw)
        stochRsiK = self.I(pta.sma, stochRsiRaw, length=self.kSmooth)
        stochRsiD = self.I(pta.sma, stochRsiK, length=self.dSmooth)
        self.stochRsiUsed = stochRsiK

        # MACD
        emaFast = self.I(pta.ema, close, length=self.macdFast)
        emaSlow = self.I(pta.ema, close, length=self.macdSlow)
        
        def macdLine():
            return emaFast - emaSlow
        
        macdLineVal = self.I(macdLine)
        macdSigVal = self.I(pta.ema, macdLineVal, length=self.macdSignal)
        
        def macdHist():
            return macdLineVal - macdSigVal
        
        macdHistVal = self.I(macdHist)
        self.macdNorm = self.I(lambda: self._normalizeZToOsc(macdHistVal, self.normLen, self.normMult))

        # ROC
        self.rocVal = self.I(pta.roc, close, length=self.rocLen)
        self.rocNorm = self.I(lambda: self._normalizeZToOsc(self.rocVal, self.normLen, self.normMult))

        # Composite
        def composite_raw():
            weightSum = self.wRSI + self.wSRSI + self.wMACD + self.wROC
            if weightSum > 0:
                result = (
                    self.rsiVal * self.wRSI +
                    self.stochRsiUsed * self.wSRSI +
                    self.macdNorm * self.wMACD +
                    self.rocNorm * self.wROC
                ) / weightSum
            else:
                result = pd.Series(50.0, index=close.index)
            return result
        
        compositeRaw = self.I(composite_raw)
        self.composite = self.I(pta.ema, compositeRaw, length=2)
        self.signal = self.I(pta.ema, self.composite, length=self.sigLen)
        
        def hist():
            return self.composite - self.signal
        
        self.hist = self.I(hist)

    def _normalizeZToOsc(self, src, length, mult):
        mean = src.rolling(length).mean()
        std = src.rolling(length).std()
        zscore = pd.Series(0.0, index=src.index)
        for i in range(len(src)):
            if std.iloc[i] != 0.0:
                zscore.iloc[i] = (src.iloc[i] - mean.iloc[i]) / std.iloc[i]
            else:
                zscore.iloc[i] = 0.0
        normalized = 50.0 + zscore * mult
        return normalized.clip(0.0, 100.0)

    def next(self):
        if len(self.composite) < 2 or len(self.signal) < 2:
            return

        bullCross = crossover(self.composite, self.signal)
        bearCross = crossover(self.signal, self.composite)

        if bullCross and self.composite[-1] > 50:
            if not self.position:
                self.buy()
        elif bearCross and self.composite[-1] < 50:
            if self.position:
                self.position.close()


