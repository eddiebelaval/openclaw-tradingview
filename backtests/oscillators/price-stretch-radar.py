import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen = 21
    lookback = 200
    mult = 2.0
    volLookback = 10
    volMultiplier = 2.5
    atrLen = 14
    atrFilterLen = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core calculations
        self.emaValue = self.I(pta.ema, close, length=self.emaLen)
        self.vwapVal = self.I(pta.vwap, high, low, close, volume)
        
        # Stretch calculations
        self.stretchEMA = self.I(
            lambda: (close - self.emaValue) / self.emaValue * 100
        )
        self.stretchVWAP = self.I(
            lambda: (close - self.vwapVal) / self.vwapVal * 100
        )
        
        # Statistics
        self.meanStretch = self.I(pta.sma, self.stretchEMA, length=self.lookback)
        self.devStretch = self.I(pta.stdev, self.stretchEMA, length=self.lookback)
        
        # Extreme zones
        self.upperExtreme = self.I(
            lambda: self.meanStretch + self.devStretch * self.mult
        )
        self.lowerExtreme = self.I(
            lambda: self.meanStretch - self.devStretch * self.mult
        )
        
        # Volume spike detection
        self.avgVol = self.I(pta.sma, volume, length=self.volLookback)
        self.volSpike = self.I(
            lambda: volume > self.avgVol * self.volMultiplier
        )
        
        # Volatility regime detection
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.atrBaseline = self.I(pta.sma, self.atr, length=self.atrFilterLen)
        
        self.marketAwake = self.I(
            lambda: self.atr > self.atrBaseline
        )
        self.saturdayMode = self.I(
            lambda: self.atr < self.atrBaseline
        )

    def next(self):
        # Skip if not enough data
        if len(self.data) < self.lookback + self.atrFilterLen:
            return
        
        # Get current values
        stretch_ema = self.stretchEMA[-1]
