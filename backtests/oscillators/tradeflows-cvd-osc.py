import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    shortPeriod = 34
    longPeriod = 200

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume Delta approximation
        def calc_vol_delta():
            high_low_diff = high - low + 0.000001
            vol_delta = volume * (close - open_) / high_low_diff
            return vol_delta
        
        vol_delta = self.I(calc_vol_delta)
        
        # Fast and Slow CVD EMA
        self.fastCVD = self.I(pta.ema, vol_delta, length=self.shortPeriod)
        self.slowCVD = self.I(pta.ema, vol_delta, length=self.longPeriod)
        
        # CVD Oscillator
        def calc_cvd_osc():
            fast = self.fastCVD
            slow = self.slowCVD
            if fast is None or slow is None:
                return pd.Series(0, index=close.index)
            return fast - slow
        
        self.cvdOsc = self.I(calc_cvd_osc)
        
        # Divergence detection
        def calc_bullish_div():
            result = pd.Series(False, index=close.index)
            for i in range(2, len(close)):
                low_falling = low.iloc[i] < low.iloc[i-1] and low.iloc[i-1] < low.iloc[i-2]
                cvd_rising = self.cvdOsc[i] > self.cvdOsc[i-1] and self.cvdOsc[i-1] > self.cvdOsc[i-2]
                if low_falling and cvd_rising:
                    result.iloc[i] = True
            return result
        
        def calc_bearish_div():
            result = pd.Series(False, index=close.index)
            for i in range(2, len(close)):
                high_rising = high.iloc[i] > high.iloc[i-1] and high.iloc[i-1] > high.iloc[i-2]
                cvd_falling = self.cvdOsc[i] < self.cvdOsc[i-1] and self.cvdOsc[i-1] < self.cvdOsc[i-2]
                if high_rising and cvd_falling:
                    result.iloc[i] = True
            return result
        
        self.bullishDiv = self.I(calc_bullish_div)
        self.bearishDiv = self.I(calc_bearish_div)

    def next(self):
        # Entry on bullish divergence or bullish zero cross
        if self.bullishDiv[-1]:
            if not self.position:
                self.buy()
        elif crossover(self.cvdOsc, 0):
            if not self.position:
                self.buy()
        
        # Exit on bearish divergence or bearish zero cross
        if self.bearishDiv[-1]:
            if self.position:
                self.sell()
        elif crossover(0, self.cvdOsc):
            if self.position:
                self.sell()