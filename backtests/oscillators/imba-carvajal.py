class TvStrategy(Strategy):
    sensitivity = 18
    risk_percent = 1
    break_even_target = "1"
    tp1_percent = 0.01
    tp1_percent_fix = 0.40
    tp2_percent = 0.02
    tp2_percent_fix = 0.30
    tp3_percent = 0.03
    tp3_percent_fix = 0.20
    tp4_percent = 0.04
    tp4_percent_fix = 0.10
