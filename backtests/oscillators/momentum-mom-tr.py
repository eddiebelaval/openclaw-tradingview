import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Length_MOM = 36
    Length_MA_MOM = 365
    Source_MA_MOM = 'EMA'

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate MOM (Momentum)
        self.mom = self.I(lambda x: pta.mom(x, length=self.Length_MOM), close)
        
        # Calculate MA of MOM based on Source_MA_MOM
        if self.Source_MA_MOM == 'EMA':
            self.mom_ma = self.I(lambda x: pta.ema(x, length=self.Length_MA_MOM), self.mom)
        elif self.Source_MA_MOM == 'SMA':
            self.mom_ma = self.I(lambda x: pta.sma(x, length=self.Length_MA_MOM), self.mom)
        elif self.Source_MA_MOM == 'RMA':
            self.mom_ma = self.I(lambda x: pta.rma(x, length=self.Length_MA_MOM), self.mom)
        elif self.Source_MA_MOM == 'WMA':
            self.mom_ma = self.I(lambda x: pta.wma(x, length=self.Length_MA_MOM), self.mom)
        elif self.Source_MA_MOM == 'VWMA':
            volume = pd.Series(self.data.Volume)
            self.mom_ma = self.I(lambda x, v: pta.vwma(x, v, length=self.Length_MA_MOM), self.mom, volume)
        elif self.Source_MA_MOM == 'HMA':
            self.mom_ma = self.I(lambda x: pta.hma(x, length=self.Length_MA_MOM), self.mom)
        else:
            self.mom_ma = self.I(lambda x: pta.ema(x, length=self.Length_MA_MOM), self.mom)

    def next(self):
        # Entry signal: MOM crosses above MOM_MA
        if crossover(self.mom, self.mom_ma):
            if not self.position:
                self.buy()
        
        # Exit signal: MOM crosses below MOM_MA
        elif crossover(self.mom_ma, self.mom):
            if self.position:
                self.position.close()