import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MACD parameters
    fast_len = 12
    slow_len = 26
    sig_len = 9

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate MACD components
        fast_ma = self.I(pta.ema, close, length=self.fast_len)
        slow_ma = self.I(pta.ema, close, length=self.slow_len)
        
        # MACD line = fast EMA - slow EMA
        self.macd = self.I(lambda: fast_ma - slow_ma)
        
        # Signal line = EMA of MACD
        self.signal = self.I(pta.ema, self.macd, length=self.sig_len)
        
        # Histogram = MACD - Signal
        self.hist = self.I(lambda: self.macd - self.signal)

    def next(self):
        # Bullish PCO: MACD crosses above signal
        if len(self.data) > 1:
            if crossover(self.macd, self.signal):
                self.buy()
            # Bearish PCO: MACD crosses below signal
            elif crossover(self.signal, self.macd):
                self.sell()