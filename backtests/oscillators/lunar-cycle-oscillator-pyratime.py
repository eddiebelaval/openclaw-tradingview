import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Lunar cycle constants
        self.SYNODIC_MONTH = 2551442841.6
        self.KNOWN_NEW_MOON = 1704974220000
        
        # Calculate lunar phase and wave
        def calc_lunar_wave(data_index):
            if len(self.data) == 0:
                return 0.0
            
            # Get the timestamp from the index (convert to milliseconds if needed)
            bar_time = self.data.index[min(data_index, len(self.data) - 1)]
            
            # Convert pandas Timestamp to milliseconds
            if hasattr(bar_time, 'timestamp'):
                time_ms = bar_time.timestamp() * 1000
            else:
                time_ms = bar_time * 1000
            
            # Calculate phase
            phase = ((time_ms - self.KNOWN_NEW_MOON) % self.SYNODIC_MONTH) / self.SYNODIC_MONTH
            
            if phase < 0:
                phase += 1
            
            # Convert to wave
            lunar_wave = np.sin((phase - 0.25) * 2 * np.pi)
            return lunar_wave
        
        # Store lunar wave calculation
        self.lunar_wave_values = []
        for i in range(len(self.data)):
            self.lunar_wave_values.append(calc_lunar_wave(i))
        
        self.lunar_wave = self.I(lambda: pd.Series(self.lunar_wave_values, index=self.data.index))
    
    def next(self):
        # Get current lunar wave value
        current_wave = self.lunar_wave[-1]
        
        # Get previous lunar wave value
        prev_wave = self.lunar_wave[-2] if len(self.lunar_wave) > 1 else current_wave
        
        # Simple trading rules based on lunar wave oscillator
        # Buy when lunar wave crosses above 0 (entering waxing/positive phase)
        if crossover(self.lunar_wave, 0):
            if not self.position:
                self.buy()
        
        # Sell when lunar wave crosses below 0 (entering waning/negative phase)
        elif crossover(0, self.lunar_wave):
            if self.position:
                self.sell()


