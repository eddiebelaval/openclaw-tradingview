import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pressure_window = 130
    noise_gate = 0.2
    participation_cap = 2.5
    trigger_smoothing = 5
    use_extra_smooth = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # HLC3 anchor price
        hlc3 = (high + low + close) / 3
        
        # Step 1: Logarithmic price differential
        log_delta = np.log(hlc3) - np.log(hlc3.shift(1))
        
        # Step 2: Adaptive volatility noise gate
        dispersion = log_delta.rolling(window=30).std()
        gate_threshold = self.noise_gate * dispersion * close
        
        # Step 3: Participation normalization
        baseline_participation = volume.rolling(window=self.pressure_window).mean().shift(1)
        participation_ceiling = baseline_participation * self.participation_cap
        normalized_activity = np.minimum(volume, participation_ceiling)
        
        # Step 4: Directional pressure classification
        bar_delta = hlc3 - hlc3.shift(1)
        classified_pressure = np.where(
            bar_delta > gate_threshold,
            normalized_activity,
            np.where(bar_delta < -gate_threshold, -normalized_activity, 0.0)
        )
        
        # Step 5: Cumulative pressure oscillator
        cumulative_pressure = pd.Series(classified_pressure).rolling(window=self.pressure_window).sum()
        raw_oscillator = cumulative_pressure / baseline_participation.fillna(1)
        
        if self.use_extra_smooth:
            pressure_oscillator = raw_oscillator.rolling(window=3).mean()
        else:
            pressure_oscillator = raw_oscillator.rolling(window=3).mean()
        
        # Step 6: Trigger line & conviction spread
        trigger_line = self.I(
            lambda: pta.ema(pd.Series(pressure_oscillator.fillna(0)), length=self.trigger_smoothing) or pd.Series(0, index=close.index)
        )
        
        self.pressure_osc = self.I(lambda: pd.Series(pressure_oscillator.fillna(0)))
        self.trigger = trigger_line
        
        # Conviction spread
        self.conviction = self.I(lambda: pd.Series(pressure_oscillator.fillna(0)) - pd.Series(trigger_line.fillna(0)))

    def next(self):
        # Bullish shift: pressure oscillator crosses above trigger line
        if len(self.pressure_osc) > 1 and len(self.trigger) > 1:
            if crossover(self.pressure_osc, self.trigger):
                if not self.position:
                    self.buy()
            # Bearish shift: pressure oscillator crosses below trigger line
            elif crossover(self.trigger, self.pressure_osc):
                if self.position:
                    self.position.close()
        
        # Alternative: Use zero-line crossovers
        if len(self.pressure_osc) > 1:
            if crossover(self.pressure_osc, 0):
                if not self.position:
                    self.buy()
            elif crossover(0, self.pressure_osc):
                if self.position:
                    self.position.close()


