import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 50
    mult = 1.1
    threshold = 60.0

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate MA
        self.ma = self.I(pta.sma, close, length=self.length)
        
        # Calculate ATR
        self.atr_value = self.I(pta.atr, high, low, close, length=200)
        
        # Calculate range ATR
        self.range_atr = self.atr_value * self.mult
        
        # Calculate oscillator
        def calc_osc(close, ma, range_atr):
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if range_atr.iloc[i] != 0:
                    result.iloc[i] = 100 * (close.iloc[i] - ma.iloc[i]) / range_atr.iloc[i]
                else:
                    result.iloc[i] = 0
            return result
        
        self.osc = self.I(lambda: calc_osc(close, self.ma, self.range_atr))
        
        # Calculate big move signals
        def calc_big_move_up(open_, close, range_atr, threshold):
            result = pd.Series(index=close.index, dtype=bool)
            for i in range(len(close)):
                if range_atr.iloc[i] != 0:
                    move = (close.iloc[i] - open_.iloc[i]) / range_atr.iloc[i] * 100
                    result.iloc[i] = move >= threshold
                else:
                    result.iloc[i] = False
            return result
        
        def calc_big_move_dn(open_, close, range_atr, threshold):
            result = pd.Series(index=close.index, dtype=bool)
            for i in range(len(close)):
                if range_atr.iloc[i] != 0:
                    move = (open_.iloc[i] - close.iloc[i]) / range_atr.iloc[i] * 100
                    result.iloc[i] = move >= threshold
                else:
                    result.iloc[i] = False
            return result
        
        self.big_move_up = self.I(lambda: calc_big_move_up(open_, close, self.range_atr, self.threshold))
        self.big_move_dn = self.I(lambda: calc_big_move_dn(open_, close, self.range_atr, self.threshold))

    def next(self):
        # Buy on big upward move
        if self.big_move_up[-1]:
            if not self.position:
                self.buy()
        
        # Sell on big downward move or close on upward position
        if self.big_move_dn[-1]:
            if self.position:
                self.position.close()
            elif not self.position:
                self.sell()
        
        # Exit short on big upward move
        if self.big_move_up[-1]:
            if self.position and self.position.is_short:
                self.position.close()