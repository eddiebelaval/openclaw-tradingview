import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLength = 23
    slowLength = 50
    cycleLength = 10
    d1Length = 3
    d2Length = 3
    upper = 75
    lower = 25

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate STC indicator
        def calc_stc():
            # Calculate MACD line
            ema_fast = pta.ema(close, length=self.fastLength)
            ema_slow = pta.ema(close, length=self.slowLength)
            macd_line = ema_fast - ema_slow
            
            # First stochastic on MACD
            stoch_result_1 = pta.stoch(macd_line, macd_line, macd_line, k=self.cycleLength, d=1, smooth_k=1)
            if stoch_result_1 is not None and len(stoch_result_1.columns) > 0:
                k_values = stoch_result_1.iloc[:, 0]
            else:
                k_values = pd.Series(50, index=close.index)
            
            # First D smoothing
            d1_values = pta.ema(k_values, length=self.d1Length)
            if d1_values is None:
                d1_values = pd.Series(50, index=close.index)
            
            # Second stochastic on D1
            stoch_result_2 = pta.stoch(d1_values, d1_values, d1_values, k=self.cycleLength, d=1, smooth_k=1)
            if stoch_result_2 is not None and len(stoch_result_2.columns) > 0:
                kd_values = stoch_result_2.iloc[:, 0]
            else:
                kd_values = pd.Series(50, index=close.index)
            
            # Second D smoothing (final STC)
            stc_values = pta.ema(kd_values, length=self.d2Length)
            if stc_values is None:
                stc_values = pd.Series(50, index=close.index)
            
            # Clamp between 0 and 100
            stc_values = np.clip(stc_values, 0, 100)
            return stc_values
        
        self.stc = self.I(calc_stc)

    def next(self):
        # Buy signal: STC crosses above lower band
        if len(self.stc) > 1:
            if crossover(self.stc, self.lower):
                if not self.position:
                    self.buy()
            # Sell signal: STC crosses below upper band
            elif crossover(self.upper, self.stc):
                if self.position:
                    self.position.close()