import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Hyper Wave Settings
    hw_len1 = 10
    hw_len2 = 21
    
    # MFI Settings
    rsiMFIperiod = 60
    rsiMFIMultiplier = 150.0
    rsiMFIPosY = 2.5
    
    # RSI Settings
    rsiLengthInput = 14
    
