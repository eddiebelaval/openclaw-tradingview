        hlc3 = (high + low + close) / 3
        esa = self.I(pta.ema, hlc3, length=self.hw_len1)
        
        d_series = self.I(lambda: pta.ema(np.abs(hlc3 - pta.ema(hlc3, length=self.hw_len1)), length=self.hw_len1))
        
        ci = self.I(lambda: (hlc3 - pta.ema(hlc3, length=self.hw_len1)) / (0.015 * (np.abs(hlc3 - pta.ema(hlc3, length=self.hw_len1)) + 1e-10)))
        
        tci = self.I(pta.ema, ci, length=self.hw_len2)
        
        self.wt1 = tci
        self.wt2 = self.I(pta.sma, tci, length=4)
        
        # RSI Calculation
        change = close.diff()
        up = self.I(pta.rma, change.clip(lower=0), length=self.rsiLengthInput)
        down = self.I(pta.rma, (-change).clip(lower=0), length=self.rsiLengthInput)
        
        self.rsi = self.I(lambda: 100 - (100 / (1 + up / (down + 1e-10))))
        
        # MFI Calculation
        self.rsiMFI = self.I(lambda: pta.sma((close - open_) / (high - low + 1e-10) * self.rsiMFIMultiplier, length=self.rsiMFIperiod) - self.rsiMFIPosY)
        
