import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20

    def init(self):
        self.oscillator = self.I(self.calculate_isotonic_oscillator)

    def calculate_isotonic_oscillator(self):
        close = pd.Series(self.data.Close)
        oscillator_values = []
        
        for bar_idx in range(len(close)):
            if bar_idx < self.length:
                oscillator_values.append(0.0)
            else:
                data = close[bar_idx - self.length + 1:bar_idx + 1].values[::-1].tolist()
                
                inc_fit = self.pava(data, True)
                dec_fit = self.pava(data, False)
                
                if inc_fit['mse'] < dec_fit['mse']:
                    osc_val = ((inc_fit['pools'] - 1.0) / (self.length - 1.0)) * 100.0
                elif dec_fit['mse'] < inc_fit['mse']:
                    osc_val = -((dec_fit['pools'] - 1.0) / (self.length - 1.0)) * 100.0
                else:
                    osc_val = 0.0
                
                oscillator_values.append(osc_val)
        
        return pd.Series(oscillator_values, index=close.index)

    def pava(self, data, non_decreasing):
        n = len(data)
        pool_vals = []
        pool_weights = []
        
        for i in range(n):
            current_val = data[i]
            current_pool = current_val
            current_weight = 1
            
            while len(pool_vals) > 0:
                prev_pool = pool_vals[-1]
                violation = (prev_pool > current_pool) if non_decreasing else (prev_pool < current_pool)
                
                if violation:
                    prev_weight = pool_weights.pop()
                    last_pool = pool_vals.pop()
                    
                    current_pool = (last_pool * prev_weight + current_pool * current_weight) / (prev_weight + current_weight)
                    current_weight += prev_weight
                else:
                    break
            
            pool_vals.append(current_pool)
            pool_weights.append(current_weight)
        
        total_error = 0.0
        idx = 0
        for j in range(len(pool_vals)):
            p_val = pool_vals[j]
            p_weight = pool_weights[j]
            for k in range(p_weight):
                total_error += (data[idx] - p_val) ** 2
                idx += 1
        
        mse = total_error / n
        
        return {
            'mse': mse,
            'pools': len(pool_vals),
            'vals': pool_vals,
            'weights': pool_weights
        }

    def next(self):
        if len(self.data) < self.length:
            return
        
        if crossover(self.oscillator, 0):
            if not self.position:
                self.buy()
        elif crossover(0, self.oscillator):
            if self.position:
                self.position.close()


