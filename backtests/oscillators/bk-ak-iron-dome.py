import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI and indicator parameters
    rsi_len = 14
    mfi_len = 14
    mom_len = 10
    vwap_dev = 2.0
    
    # Thresholds
    peak_thresh = 90.0
    valley_thresh = -90.0
    
    # Divergence parameters
    enable_div_check = True
    div_lookback_l = 5
    div_lookback_r = 3
    min_div_bars = 5
    max_div_bars = 50
    
    # Score smoothing
    score_ma_len = 9
    
    # Other parameters
    stop_atr_mult = 1.5
    target1_rr = 1.5
    target2_rr = 2.5
    target3_rr = 4.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hlc3 = (high + low + close) / 3
        
        # Core indicators
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_len) or pd.Series(50, index=close.index))
        self.mfi = self.I(lambda: pta.mfi(hlc3, volume, length=self.mfi_len) or pd.Series(50, index=close.index))
        self.momentum = self.I(lambda: pta.mom(close, length=self.mom_len) or pd.Series(0, index=close.index))
        
        # ATR for targets
        self.atr = self.I(lambda: pta.atr(high, low, close, length=14) or pd.Series(1, index=close.index))
        
        # VWAP calculation
        self.vwap = self.I(lambda: pta.vwma(hlc3, volume, length=self.rsi_len) or pd.Series(close.iloc[0], index=close.index))
        
        # Smoothed RSI
        rsi_smooth = self.I(lambda: pta.sma(pta.rsi(close, length=self.rsi_len) or pd.Series(50, index=close.index), length=3) or pd.Series(50, index=close.index))
        self.rsi_smooth = rsi_smooth
        
        # Base score calculation
        self.reversal_score = self.I(self._calculate_score, close, high, low, hlc3, volume)
        
        # Score MA
        self.score_ma = self.I(lambda: pta.ema(self.reversal_score, length=self.score_ma_len) or pd.Series(0, index=close.index))
        
