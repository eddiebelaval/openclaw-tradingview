import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 20
    maLen = 10
    maType = "RMA"
    atrLen = 14
    factor = 4.0
    baseMode = "RSI MA"

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLen) or pd.Series(50, index=close.index))
        
        # Calculate RSI MA based on maType
        def calc_ma(rsi_series, length, ma_type):
            if ma_type == "SMA":
                return pta.sma(rsi_series, length=length)
            elif ma_type == "EMA":
                return pta.ema(rsi_series, length=length)
            elif ma_type == "RMA":
                return pta.rma(rsi_series, length=length)
            else:  # WMA
                return pta.wma(rsi_series, length=length)
        
        self.rsiMA = self.I(lambda: calc_ma(self.rsi, self.maLen, self.maType) or pd.Series(50, index=close.index))
        
        # Base line selection
        def get_base():
            if self.baseMode == "RSI":
                return self.rsi
            else:
                return self.rsiMA
        
        self.base = self.I(get_base)
        
        # ATR on RSI (TR calculation)
        def calc_atr_rsi():
            base_vals = np.array(self.base)
            if len(base_vals) < 2:
                return pd.Series(0, index=close.index)
            tr = np.abs(np.diff(base_vals, prepend=base_vals[0]))
            tr_series = pd.Series(tr, index=close.index)
            atr = pta.rma(tr_series, length=self.atrLen)
            return atr if atr is not None else pd.Series(0, index=close.index)
        
        self.atrRSI = self.I(calc_atr_rsi)
        
        # Upper and lower bands
        def calc_upper():
            return self.base + self.factor * self.atrRSI
        
        def calc_lower():
            return self.base - self.factor * self.atrRSI
        
        self.upper = self.I(calc_upper)
        self.lower = self.I(calc_lower)
        
        # Track direction and bands
        self.direction = 1
        self.fUpper = None
        self.fLower = None
        self.prev_direction = 1
        self.flipUp_signal = False
        self.flipDn_signal = False

    def next(self):
        # Initialize forward bands
        if self.fUpper is None:
            self.fUpper = self.upper[-1]
        if self.fLower is None:
            self.fLower = self.lower[-1]
        
        # Update forward bands (carry forward logic)
        current_upper = self.upper[-1]
        current_lower = self.lower[-1]
        current_base = self.base[-1]
        
        if len(self) > 1:
            prev_base = self.base[-2]
        else:
            prev_base = current_base
        
        # SuperTrend-like band update
        if current_upper < self.fUpper or prev_base > self.fUpper:
            self.fUpper = current_upper
        
        if current_lower > self.fLower or prev_base < self.fLower:
            self.fLower = current_lower
        
        # Direction logic
        self.prev_direction = self.direction
        
        if self.prev_direction == 1:
            if current_base < self.fLower:
                self.direction = -1
            else:
                self.direction = 1
        else:
            if current_base > self.fUpper:
                self.direction = 1
            else:
                self.direction = -1
        
        # Flip detection
        self.flipUp_signal = (self.direction == 1 and self.prev_direction == -1)
        self.flipDn_signal = (self.direction == -1 and self.prev_direction == 1)
        
        # Trading logic based on flip signals
        if self.flipUp_signal:
            if not self.position:
                self.buy()
        elif self.flipDn_signal:
            if self.position:
                self.sell()


