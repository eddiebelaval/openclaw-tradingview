import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_len = 14
    lb_r = 5
    lb_l = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_len) or pd.Series(50, index=close.index))
        
        self.ph = self.I(self._pivot_high, high, self.lb_l, self.lb_r)
        self.pl = self.I(self._pivot_low, low, self.lb_l, self.lb_r)
        
        self.bull_div_signal = False
        self.bear_div_signal = False
        
        self.pl_price = None
        self.pl_rsi = None
        self.pl_index = None
        
        self.ph_price = None
        self.ph_rsi = None
        self.ph_index = None

    def _pivot_high(self, high, left, right):
        result = pd.Series(np.nan, index=high.index)
        for i in range(left, len(high) - right):
            if high.iloc[i] == high.iloc[i-left:i+right+1].max():
                result.iloc[i] = high.iloc[i]
        return result

    def _pivot_low(self, low, left, right):
        result = pd.Series(np.nan, index=low.index)
        for i in range(left, len(low) - right):
            if low.iloc[i] == low.iloc[i-left:i+right+1].min():
                result.iloc[i] = low.iloc[i]
        return result

    def next(self):
        if len(self) < self.lb_l + self.lb_r + 1:
            return
        
        self.bull_div_signal = False
        self.bear_div_signal = False
        
        if not np.isnan(self.pl[-1]):
            if self.pl_price is not None and self.rsi[-self.lb_r-1] > self.pl_rsi and self.data.Low[-self.lb_r-1] < self.pl_price:
                self.bull_div_signal = True
            self.pl_price = self.data.Low[-self.lb_r-1]
            self.pl_rsi = self.rsi[-self.lb_r-1]
            self.pl_index = len(self) - self.lb_r - 1
        
        if not np.isnan(self.ph[-1]):
            if self.ph_price is not None and self.rsi[-self.lb_r-1] < self.ph_rsi and self.data.High[-self.lb_r-1] > self.ph_price:
                self.bear_div_signal = True
            self.ph_price = self.data.High[-self.lb_r-1]
            self.ph_rsi = self.rsi[-self.lb_r-1]
            self.ph_index = len(self) - self.lb_r - 1
        
        if self.bull_div_signal:
            if not self.position:
                self.buy()
        elif self.bear_div_signal:
            if self.position:
                self.sell()