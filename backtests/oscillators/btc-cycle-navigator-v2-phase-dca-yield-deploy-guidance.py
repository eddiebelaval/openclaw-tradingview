        if is_mature_bull and (self.cycle_high is None or self.data.Close[-1] > self.cycle_high):
            self.cycle_high = self.data.Close[-1]
        
        if is_deep_bear:
            self.weeks_in_bear += 1
        else:
            self.weeks_in_bear = 0

