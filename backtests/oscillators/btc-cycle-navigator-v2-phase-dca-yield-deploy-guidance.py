import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI Settings
    rsi_length = 50
    linreg_period = 200
    deviations = 2.0
    ob_level = 65
    os_level = 35
    
    # DCA Settings
    base_dca = 100
    
    # Yield Deploy Settings
    yield_basket_size = 100000
    yield_target_keep = 20.0
    hybrid_max_pct_pool = 4.0
    hybrid_deploy_pct = 25.0
    hybrid_ramp_weeks = 25.0
    hybrid_start_cap = 10.0
    hybrid_drawdown_exp = 3.0
    
    # Logic Toggles
    use_false_filter = True
    
    # Start Date
    use_start_date = True
    start_year = 2013
    start_month = 1
    start_day = 1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate base RSI with WMA smoothing
        rsi_raw = self.I(lambda: pta.rsi(close, length=self.rsi_length))
        rsi_smoothed = self.I(lambda: pta.wma(rsi_raw, length=5) if rsi_raw is not None else pd.Series(50, index=close.index))
        self.rsi = rsi_smoothed
        
        # Linear regression calculation
        self.linreg_mid = self.I(self._calculate_linreg_mid, close)
        self.linreg_lower = self.I(self._calculate_linreg_lower, close)
        self.linreg_upper = self.I(self._calculate_linreg_upper, close)
        
        # Phase tracking variables
        self.phase = "UNKNOWN"
        self.post_peak = False
        self.overbought_armed = False
        self.sell_count = 0
        self.prev_above_mid = False
        self.sell_paused_by_plunge = False
        self.dca_paused = False
        self.sell_signal_text = "NONE"
        self.weeks_in_bear = 0
        self.cycle_high = None
        self.prev_phase = "UNKNOWN"

    def _calculate_linreg_mid(self, close):
        df = pd.DataFrame({"close": close})
        df["rsi"] = pta.rsi(close, length=self.rsi_length)
        df["rsi"] = pta.wma(df["rsi"], length=5)
        
        result = pd.Series(index=close.index, dtype=float)
        
        for bar_idx in range(len(df)):
            if bar_idx < self.linreg_period - 1:
                result.iloc[bar_idx] = np.nan
                continue
            
            start_idx = bar_idx - self.linreg_period + 1
            y_vals = df["rsi"].iloc[start_idx:bar_idx+1].values
            x_vals = np.arange(len(y_vals))
            
            ex = np.sum(x_vals)
            ey = np.sum(y_vals)
            ex2 = np.sum(x_vals ** 2)
            exy = np.sum(x_vals * y_vals)
            exex = ex * ex
            
            if ex2 != exex:
                slope = (self.linreg_period * exy - ex * ey) / (self.linreg_period * ex2 - exex)
            else:
                slope = 0
            
            intercept = (ey - slope * ex) / self.linreg_period
            result.iloc[bar_idx] = intercept
        
        result = pta.wma(result, length=5)
        return result

    def _calculate_linreg_lower(self, close):
        df = pd.DataFrame({"close": close})
        df["rsi"] = pta.rsi(close, length=self.rsi_length)
        df["rsi"] = pta.wma(df["rsi"], length=5)
        
        mid = self._calculate_linreg_mid(close)
        stdev = pta.stdev(df["rsi"], length=20)
        
        result = mid - (self.deviations * stdev)
        return result

    def _calculate_linreg_upper(self, close):
        df = pd.DataFrame({"close": close})
        df["rsi"] = pta.rsi(close, length=self.rsi_length)
        df["rsi"] = pta.wma(df["rsi"], length=5)
        
        mid = self._calculate_linreg_mid(close)
        stdev = pta.stdev(df["rsi"], length=20)
        
        result = mid + (self.deviations * stdev)
        return result

    def _is_live(self):
        if not self.use_start_date:
            return True
        
        bar_time = self.data.index[len(self.data) - 1]
        start_time = pd.Timestamp(self.start_year, self.start_month, self.start_day)
        
        return bar_time >= start_time

    def _update_phase(self):
        if not self._is_live():
            return
        
        rsi_val = self.rsi[-1]
        mid_val = self.linreg_mid[-1]
        lower_val = self.linreg_lower[-1]
        upper_val = self.linreg_upper[-1]
        
        is_deep_bear = rsi_val <= 50 and rsi_val <= lower_val
        is_bear_recovery = rsi_val <= 50 and rsi_val > lower_val and rsi_val <= mid_val
        is_early_bull = rsi_val > mid_val and rsi_val < 50
        is_bull_confirmed = rsi_val > 50 and rsi_val > upper_val
        is_mature_bull = rsi_val > self.ob_level
        is_bull_building = rsi_val > 50 and not is_bull_confirmed and not is_mature_bull
        
        if is_mature_bull:
            self.post_peak = True
        if is_deep_bear:
            self.post_peak = False
        
        prev_phase = self.phase
        
        if is_mature_bull:
            self.phase = "MATURE_BULL"
        elif is_bull_confirmed and not self.post_peak:
            self.phase = "BULL_CONFIRMED"
        elif is_bull_confirmed and self.post_peak:
            self.phase = "DISTRIBUTION"
        elif is_bull_building and not self.post_peak:
            self.phase = "BULL_BUILDING"
        elif is_bull_building and self.post_peak:
            self.phase = "WEAKENING"
        elif is_early_bull:
            self.phase = "EARLY_BULL"
        elif is_bear_recovery:
            self.phase = "BEAR_RECOVERY"
        elif is_deep_bear:
            self.phase = "DEEP_BEAR"
        else:
            self.phase = "UNKNOWN"
        
        if self.phase != prev_phase:
            self.prev_phase = prev_phase

    def _update_sell_logic(self):
        if not self._is_live():
            return
        
        rsi_val = self.rsi[-1]
        mid_val = self.linreg_mid[-1]
        lower_val = self.linreg_lower[-1]
        
        if rsi_val > self.ob_level:
            self.overbought_armed = True
        if rsi_val < 50 and rsi_val < mid_val:
            self.overbought_armed = False
        
        sell_filter_ok = (not self.use_false_filter) or self.overbought_armed
        
        rsi_prev = self.rsi[-2] if len(self.rsi) > 1 else self.rsi[-1]
        mid_prev = self.linreg_mid[-2] if len(self.linreg_mid) > 1 else self.linreg_mid[-1]
        
        prev_above_mid = rsi_prev > mid_prev
        rsi_below_mid = rsi_val < mid_val
        midline_break_down = prev_above_mid and rsi_below_mid
        
        if self.sell_count == 1 and rsi_val <= lower_val:
            self.sell_paused_by_plunge = True
        
        if sell_filter_ok and midline_break_down and not self.sell_paused_by_plunge:
            self.sell_count += 1
            if self.sell_count == 1:
                self.sell_signal_text = "FIRST_SELL"
            elif self.sell_count == 2:
                self.sell_signal_text = "SECOND_SELL"
                self.dca_paused = True
            else:
                self.sell_signal_text = "SELLS_DONE"
        else:
            self.sell_signal_text = "NONE"
        
        is_bull_confirmed = rsi_val > 50 and rsi_val > self.linreg_upper[-1]
        if is_bull_confirmed:
            self.sell_count = 0
            self.sell_paused_by_plunge = False
        
        is_deep_bear = rsi_val <= 50 and rsi_val <= lower_val
        if is_deep_bear:
            self.dca_paused = False

