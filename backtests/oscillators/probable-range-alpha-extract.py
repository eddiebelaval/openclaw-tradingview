import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    window = 20
    confidence = 0.95
    upperSTD = 1.5
    lowerSTD = 1.5
    pos_num = 30

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Z-score based on confidence level
        if self.confidence == 0.68:
            z_score = 1.0
        elif self.confidence == 0.95:
            z_score = 1.96
        elif self.confidence == 0.99:
            z_score = 2.33
        else:
            z_score = 1.0
        
        # Rolling mean and std deviation
        self.mean_price = self.I(pta.sma, close, length=self.window)
        self.std_dev = self.I(lambda: pta.stdev(close, length=self.window) or pd.Series(0, index=close.index))
        
        # Probable range bounds
        self.upper_bound = self.I(lambda: self.mean_price[-1] + z_score * self.std_dev[-1] if len(self.mean_price) > 0 and len(self.std_dev) > 0 else 0)
        self.lower_bound = self.I(lambda: max(0.0, self.mean_price[-1] - z_score * self.std_dev[-1]) if len(self.mean_price) > 0 and len(self.std_dev) > 0 else 0)
        
        # Calculate oscillator
        self.oscillator = self.I(self._calc_oscillator)
        
        # Smoothed oscillator
        self.smoothed_oscillator = self.I(lambda: pta.sma(self.oscillator, length=7) or pd.Series(0.5, index=close.index))
        
        # Expanding stats for oscillator
        self.expanding_mean = self.I(self._calc_expanding_mean)
        self.expanding_std = self.I(self._calc_expanding_std)
        self.up_band = self.I(self._calc_up_band)
        self.low_band = self.I(self._calc_low_band)
        
        # Probable histogram
        self.probable_histo = self.I(self._calc_probable_histo)
    
    def _calc_oscillator(self):
        result = []
        for i in range(len(self.data.Close)):
            if i < self.window - 1:
                result.append(0.5)
            else:
                close_slice = pd.Series(self.data.Close[max(0, i - self.window + 1):i + 1])
                mean = close_slice.mean()
                std = close_slice.std()
                z_score = 1.96 if self.confidence == 0.95 else (1.0 if self.confidence == 0.68 else 2.33)
                upper = mean + z_score * std
                lower = max(0.0, mean - z_score * std)
                osc = (self.data.Close[i] - lower) / (upper - lower) if upper > lower else 0.5
                result.append(max(0.0, min(1.0, osc)))
        return pd.Series(result, index=self.data.Close.index)
    
    def _calc_expanding_mean(self):
        result = []
        cum_sum = 0
        count = 0
        for i in range(len(self.oscillator)):
            if not np.isnan(self.oscillator.iloc[i]):
                cum_sum += self.oscillator.iloc[i]
                count += 1
            result.append(cum_sum / count if count > 0 else 0)
        return pd.Series(result, index=self.oscillator.index)
    
    def _calc_expanding_std(self):
        result = []
        cum_sum = 0
        cum_square_sum = 0
        count = 0
        for i in range(len(self.oscillator)):
            if not np.isnan(self.oscillator.iloc[i]):
                cum_sum += self.oscillator.iloc[i]
                cum_square_sum += self.oscillator.iloc[i] * self.oscillator.iloc[i]
                count += 1
            if count > 0:
                mean = cum_sum / count
                variance = (cum_square_sum / count) - (mean * mean)
                std = np.sqrt(max(0, variance))
                result.append(std)
            else:
                result.append(0)
        return pd.Series(result, index=self.oscillator.index)
    
    def _calc_up_band(self):
        result = []
        cum_sum = 0
        cum_square_sum = 0
        count = 0
        for i in range(len(self.oscillator)):
            if not np.isnan(self.oscillator.iloc[i]):
                cum_sum += self.oscillator.iloc[i]
                cum_square_sum += self.oscillator.iloc[i] * self.oscillator.iloc[i]
                count += 1
            if count > 0:
                mean = cum_sum / count
                variance = (cum_square_sum / count) - (mean * mean)
                std = np.sqrt(max(0, variance))
                upper = mean + (std * self.upperSTD)
                result.append(upper)
            else:
                result.append(0)
        return pd.Series(result, index=self.oscillator.index)
    
    def _calc_low_band(self):
        result = []
        cum_sum = 0
        cum_square_sum = 0
        count = 0
        for i in range(len(self.oscillator)):
            if not np.isnan(self.oscillator.iloc[i]):
                cum_sum += self.oscillator.iloc[i]
                cum_square_sum += self.oscillator.iloc[i] * self.oscillator.iloc[i]
                count += 1
            if count > 0:
                mean = cum_sum / count
                variance = (cum_square_sum / count) - (mean * mean)
                std = np.sqrt(max(0, variance))
                lower = mean - (std * self.lowerSTD)
                result.append(lower)
            else:
                result.append(0)
        return pd.Series(result, index=self.oscillator.index)
    
    def _calc_probable_histo(self):
        osc_sma = pta.sma(self.oscillator, length=self.pos_num)
        if osc_sma is None:
            return pd.Series(0, index=self.oscillator.index)
        histo = osc_sma - self.expanding_mean
        return histo

    def next(self):
        if len(self.oscillator) < 20:
            return
        
        # Trading logic based on oscillator position
        current_osc = self.oscillator[-1]
        current_histo = self.probable_histo[-1]
        
        # Buy when oscillator crosses above lower band and histogram is positive
        if len(self.oscillator) > 1:
            prev_osc = self.oscillator[-2]
            prev_low = self.low_band[-2]
            curr_low = self.low_band[-1]
            
            if prev_osc <= prev_low and current_osc > curr_low and current_histo > 0:
                if not self.position:
                    self.buy()
            
            # Sell when oscillator crosses below upper band or histogram turns negative
            prev_up = self.up_band[-2]
            curr_up = self.up_band[-1]
            
            if (prev_osc >= prev_up and current_osc < curr_up) or (self.probable_histo[-2] > 0 and current_histo <= 0):
                if self.position:
                    self.sell()


