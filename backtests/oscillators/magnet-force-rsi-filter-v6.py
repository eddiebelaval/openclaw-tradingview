import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    mult = 2.0
    rsi_length = 14
    rsi_overbought = 70
    rsi_oversold = 30

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate VWMA (magnet core)
        self.magnet_core = self.I(pta.vwma, close, volume, length=self.length)
        
        # Calculate standard deviation
        self.stdev = self.I(pta.stdev, close, length=self.length)
        
        # Calculate RSI
        self.rsi_val = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Calculate attraction bands
        def upper_band():
            magnet = pta.vwma(close, volume, length=self.length)
            dev = self.mult * pta.stdev(close, length=self.length)
            if magnet is not None and dev is not None:
                return magnet + dev
            return pd.Series(0, index=close.index)
        
        def lower_band():
            magnet = pta.vwma(close, volume, length=self.length)
            dev = self.mult * pta.stdev(close, length=self.length)
            if magnet is not None and dev is not None:
                return magnet - dev
            return pd.Series(0, index=close.index)
        
        self.upper_attraction = self.I(upper_band)
        self.lower_attraction = self.I(lower_band)

    def next(self):
        if len(self.data) < 2:
            return
        
        close_current = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        upper_current = self.upper_attraction[-1]
        lower_current = self.lower_attraction[-1]
        rsi_current = self.rsi_val[-1]
        rsi_prev = self.rsi_val[-2]
        
        # Sell signal: price crosses under upper band and RSI was overbought
        sell_signal = (close_prev > upper_current and close_current <= upper_current and 
                       rsi_prev >= self.rsi_overbought)
        
        # Buy signal: price crosses over lower band and RSI was oversold
        buy_signal = (close_prev < lower_current and close_current >= lower_current and 
                      rsi_prev <= self.rsi_oversold)
        
        if sell_signal:
            if self.position:
                self.position.close()
            else:
                self.sell()
        
        if buy_signal:
            if not self.position:
                self.buy()


