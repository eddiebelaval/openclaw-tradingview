import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    longLen = 25
    shortLen = 13
    sigLen = 13
    ob2 = 50
    ob1 = 25
    os1 = -25
    os2 = -50

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate price change
        pc = close.diff()
        
        # Double smooth function: EMA of EMA
        def double_smooth(src, long_len, short_len):
            ema1 = pta.ema(src, length=long_len)
            if ema1 is None:
                return None
            ema2 = pta.ema(ema1, length=short_len)
            return ema2
        
        # Base TSI calculation
        pc_smooth = self.I(lambda: double_smooth(pc, self.longLen, self.shortLen) or pd.Series(0, index=close.index))
        pc_abs_smooth = self.I(lambda: double_smooth(pc.abs(), self.longLen, self.shortLen) or pd.Series(1, index=close.index))
        
        # TSI value with division protection
        self.tsi_value = self.I(lambda: 100 * (pc_smooth / pc_abs_smooth.replace(0, 1)))
        
        # Signal line (EMA of TSI)
        self.signal_line = self.I(pta.ema, self.tsi_value, length=self.sigLen)

    def next(self):
        if len(self.data) < 2:
            return
        
        tsi_curr = self.tsi_value[-1]
        tsi_prev = self.tsi_value[-2]
        signal_curr = self.signal_line[-1]
        signal_prev = self.signal_line[-2]
        
        # Crossover detection
        if crossover(self.tsi_value, self.signal_line):
            if not self.position:
                self.buy()
        elif crossover(self.signal_line, self.tsi_value):
            if self.position:
                self.position.close()
        
        # Additional exit conditions based on extreme levels
        if self.position and tsi_curr > self.ob2:
            self.position.close()
        elif self.position and tsi_curr < self.os2:
            self.position.close()


