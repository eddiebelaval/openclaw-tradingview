import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    mfi_length = 14
    lookback_left = 14
    lookback_right = 5
    calculate_divergence = True
    expiry_age = 1000
    mitigate = "body"
    allow_rejection = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # MFI calculation
        self.mfi = self.I(pta.mfi, high, low, close, length=self.mfi_length)
        
        # HMA calculation for smoothing
        def calc_hma_smooth(mfi_series):
            if mfi_series is None or len(mfi_series) < 21:
                return pd.Series(50, index=close.index)
            hma = pta.hma(mfi_series, length=21)
            return hma if hma is not None else pd.Series(50, index=close.index)
        
        self.mfi_smooth = self.I(calc_hma_smooth, self.mfi)
        
        # Store price data for divergence detection
        self.high_data = high
        self.low_data = low
        self.open_data = open_
        self.close_data = close
        
        # Tracking variables
        self.bull_zones = []
        self.bear_zones = []
        self.last_bull_signal = None
        self.last_bear_signal = None

    def next(self):
        idx = len(self.data) - 1
        
        if idx < self.lookback_left + self.lookback_right + 5:
            return
        
        # Get current and previous MFI smooth values
        curr_mfi_smooth = self.mfi_smooth[-1]
        prev_mfi_smooth = self.mfi_smooth[-2] if len(self.mfi_smooth) > 1 else curr_mfi_smooth
        
        # Check for oscillator crosses
        osc_cross_up = crossover(self.mfi_smooth, self.mfi_smooth[1:])
        osc_cross_down = crossover(self.mfi_smooth[1:], self.mfi_smooth)
        
        # Divergence detection logic simplified
        # Look for price pivot lows with oscillator higher lows (bullish)
        # Look for price pivot highs with oscillator lower highs (bearish)
        
        if self.calculate_divergence and idx >= self.lookback_left + self.lookback_right:
            # Check for bullish divergence setup
            # Price makes lower low but oscillator makes higher low
            price_ll = self.low_data.iloc[idx] < self.low_data.iloc[idx - self.lookback_right - self.lookback_left]
            osc_hl = self.mfi_smooth[-1] > self.mfi_smooth[-(self.lookback_right + self.lookback_left)]
            
            if price_ll and osc_hl and self.last_bull_signal != idx:
                self.last_bull_signal = idx
                bull_zone = {
                    'type': 'bull',
                    'created_at': idx,
                    'low': self.low_data.iloc[idx],
                    'body_low': min(self.open_data.iloc[idx], self.close_data.iloc[idx])
                }
                self.bull_zones.append(bull_zone)
                self.buy()
            
            # Check for bearish divergence setup
            # Price makes higher high but oscillator makes lower high
            price_hh = self.high_data.iloc[idx] > self.high_data.iloc[idx - self.lookback_right - self.lookback_left]
            osc_lh = self.mfi_smooth[-1] < self.mfi_smooth[-(self.lookback_right + self.lookback_left)]
            
            if price_hh and osc_lh and self.last_bear_signal != idx:
                self.last_bear_signal = idx
                bear_zone = {
                    'type': 'bear',
                    'created_at': idx,
                    'high': self.high_data.iloc[idx],
                    'body_high': max(self.open_data.iloc[idx], self.close_data.iloc[idx])
                }
                self.bear_zones.append(bear_zone)
                self.sell()
        
        # Zone mitigation logic
        zones_to_remove = []
        
        for i, zone in enumerate(self.bull_zones):
            age = idx - zone['created_at']
            
            if age > self.expiry_age:
                zones_to_remove.append(i)
                continue
            
            sweep_price = self.close_data.iloc[idx] if self.mitigate == "body" else self.low_data.iloc[idx]
            sweep_price_prev = self.close_data.iloc[idx - 1] if self.mitigate == "body" else self.low_data.iloc[idx - 1]
            
            remove = False
            if self.allow_rejection and self.mitigate == "body":
                remove = sweep_price < zone['body_low'] and sweep_price_prev < zone['body_low']
            else:
                remove = sweep_price < zone['low']
            
            if remove:
                zones_to_remove.append(i)
        
        for i in reversed(zones_to_remove):
            self.bull_zones.pop(i)
        
        zones_to_remove = []
        
        for i, zone in enumerate(self.bear_zones):
            age = idx - zone['created_at']
            
            if age > self.expiry_age:
                zones_to_remove.append(i)
                continue
            
            sweep_price = self.close_data.iloc[idx] if self.mitigate == "body" else self.high_data.iloc[idx]
            sweep_price_prev = self.close_data.iloc[idx - 1] if self.mitigate == "body" else self.high_data.iloc[idx - 1]
            
            remove = False
            if self.allow_rejection and self.mitigate == "body":
                remove = sweep_price > zone['body_high'] and sweep_price_prev > zone['body_high']
            else:
                remove = sweep_price > zone['high']
            
            if remove:
                zones_to_remove.append(i)
        
        for i in reversed(zones_to_remove):
            self.bear_zones.pop(i)
        
        # Oscillator signal trading
        if osc_cross_up and len(self.bull_zones) > 0:
            if not self.position:
                self.buy()
        elif osc_cross_down and len(self.bear_zones) > 0:
            if self.position:
                self.sell()