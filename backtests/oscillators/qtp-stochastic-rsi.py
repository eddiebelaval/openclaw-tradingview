import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smoothK = 3
    smoothD = 3
    lengthRSI = 14
    lengthStoch = 14
    upLine = 80
    midLine = 50
    lowLine = 20

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI
        rsi1 = self.I(pta.rsi, close, length=self.lengthRSI)
        
        # Calculate Stochastic on RSI values
        # ta.stoch(rsi1, rsi1, rsi1, lengthStoch) applies stochastic to RSI
        stoch_result = self.I(
            lambda: pta.stoch(rsi1, rsi1, rsi1, k=self.lengthStoch, d=self.lengthStoch, smooth_k=1, smooth_d=1)
            if rsi1 is not None and len(rsi1.dropna()) > self.lengthStoch 
            else pd.DataFrame(index=close.index, columns=['STOCHk_' + str(self.lengthStoch) + '_' + str(self.lengthStoch) + '_1', 'STOCHd_' + str(self.lengthStoch) + '_' + str(self.lengthStoch) + '_1']).fillna(50)
        )
        
        # Extract stochastic K line
        stoch_k_raw = self.I(
            lambda: pta.stoch(rsi1, rsi1, rsi1, k=self.lengthStoch, d=self.lengthStoch, smooth_k=1, smooth_d=1).iloc[:, 0]
            if rsi1 is not None and len(rsi1.dropna()) > self.lengthStoch
            else pd.Series(50, index=close.index)
        )
        
        # Smooth K with SMA
        self.k = self.I(
            lambda: pta.sma(stoch_k_raw, length=self.smoothK)
            if stoch_k_raw is not None 
            else pd.Series(50, index=close.index)
        )
        
        # Smooth D with SMA
        self.d = self.I(
            lambda: pta.sma(self.k, length=self.smoothD)
            if self.k is not None
            else pd.Series(50, index=close.index)
        )

    def next(self):
        # Buy when K crosses above lower band (oversold + turning up)
        if len(self.data) > 1:
            if crossover(self.k, self.lowLine):
                if not self.position:
                    self.buy()
            # Sell when K crosses below upper band (overbought + turning down)
            elif crossover(self.upLine, self.k):
                if self.position:
                    self.sell()