import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    overboughtLevel = 70
    oversoldLevel = 30
    pivotLeftBars = 5
    pivotRightBars = 5
    liqLeftBars = 3
    liqRightBars = 3
    fvgLookbackBars = 6
    emaLen = 200
    tolPct = 0.5
    
    useLiquidityFilter = True
    useFVGFilter = True
    useBiasFilter = True
    biasMode = "EMA200"
    useBreakoutEntries = True
    breakoutNeedsRetest = False
    breakoutUseFVG = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI calculation
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLength) or pd.Series(50, index=close.index))
        
        # EMA for bias
        self.ema = self.I(lambda: pta.ema(close, length=self.emaLen) or pd.Series(close, index=close.index))
        
        # Pivot highs and lows
        self.pivot_high = self.I(self._get_pivot_high, high, low)
        self.pivot_low = self.I(self._get_pivot_low, high, low)
        
        # Liquidity pivots
        self.liq_pivot_high = self.I(self._get_liq_pivot_high, high, low)
        self.liq_pivot_low = self.I(self._get_liq_pivot_low, high, low)
        
        # Track last liquidity levels
        self.last_liq_high = None
        self.last_liq_low = None
        
        # Track structure levels
        self.r1 = None
        self.s1 = None
        
        # FVG tracking
        self.fvg_bull_recent = False
        self.fvg_bear_recent = False
        self.bars_since_bull_fvg = 999
        self.bars_since_bear_fvg = 999

    def _get_pivot_high(self, high):
        result = pd.Series(np.nan, index=high.index)
        for i in range(self.pivotLeftBars + self.pivotRightBars, len(high)):
            if high.iloc[i - self.pivotRightBars] == high.iloc[i - self.pivotRightBars - self.pivotLeftBars:i - self.pivotRightBars].max():
                result.iloc[i - self.pivotRightBars] = high.iloc[i - self.pivotRightBars]
        return result

    def _get_pivot_low(self, low):
        result = pd.Series(np.nan, index=low.index)
        for i in range(self.pivotLeftBars + self.pivotRightBars, len(low)):
            if low.iloc[i - self.pivotRightBars] == low.iloc[i - self.pivotRightBars - self.pivotLeftBars:i - self.pivotRightBars].min():
                result.iloc[i - self.pivotRightBars] = low.iloc[i - self.pivotRightBars]
        return result

    def _get_liq_pivot_high(self, high):
        result = pd.Series(np.nan, index=high.index)
        for i in range(self.liqLeftBars + self.liqRightBars, len(high)):
            if high.iloc[i - self.liqRightBars] == high.iloc[i - self.liqRightBars - self.liqLeftBars:i - self.liqRightBars].max():
                result.iloc[i - self.liqRightBars] = high.iloc[i - self.liqRightBars]
        return result

    def _get_liq_pivot_low(self, low):
        result = pd.Series(np.nan, index=low.index)
        for i in range(self.liqLeftBars + self.liqRightBars, len(low)):
            if low.iloc[i - self.liqRightBars] == low.iloc[i - self.liqRightBars - self.liqLeftBars:i - self.liqRightBars].min():
                result.iloc[i - self.liqRightBars] = low.iloc[i - self.liqRightBars]
        return result

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Update liquidity levels
        if not np.isnan(self.liq_pivot_low[-1]):
            self.last_liq_low = self.liq_pivot_low[-1]
        if not np.isnan(self.liq_pivot_high[-1]):
            self.last_liq_high = self.liq_pivot_high[-1]
        
        # Update structure levels
        if not np.isnan(self.pivot_high[-1]):
            self.r1 = self.pivot_high[-1]
        if not np.isnan(self.pivot_low[-1]):
            self.s1 = self.pivot_low[-1]
        
        # FVG detection
        if len(self.data) >= 3:
            bull_fvg = low > self.data.High[-3]
            bear_fvg = high < self.data.Low[-3]
            
            if bull_fvg:
                self.bars_since_bull_fvg = 0
                self.fvg_bull_recent = True
            else:
                self.bars_since_bull_fvg += 1
                if self.bars_since_bull_fvg > self.fvgLookbackBars:
                    self.fvg_bull_recent = False
            
            if bear_fvg:
                self.bars_since_bear_fvg = 0
                self.fvg_bear_recent = True
            else:
                self.bars_since_bear_fvg += 1
                if self.bars_since_bear_fvg > self.fvgLookbackBars:
                    self.fvg_bear_recent = False
        
        # Liquidity sweep detection
        sweep_down = self.last_liq_low is not None and low < self.last_liq_low and close > self.last_liq_low
        sweep_up = self.last_liq_high is not None and high > self.last_liq_high and close < self.last_liq_high
        
        liq_buy_ok = not self.useLiquidityFilter or sweep_down
        liq_sell_ok = not self.useLiquidityFilter or sweep_up
        
        # FVG filter
        fvg_buy_ok = not self.useFVGFilter or self.fvg_bull_recent
        fvg_sell_ok = not self.useFVGFilter or self.fvg_bear_recent
        
        # Bias filter
        trend_up = True
        trend_dn = True
        if self.useBiasFilter and self.biasMode == "EMA200":
            trend_up = close > self.ema[-1]
            trend_dn = close < self.ema[-1]
        
        apply_bias = self.useBiasFilter and self.biasMode != "None"
        
        # Mean reversion entries
        if len(self.rsi) >= 2:
            rsi_buy = crossover(self.rsi, self.oversoldLevel)
            rsi_sell = crossover(self.overboughtLevel, self.rsi)
        else:
            rsi_buy = False
            rsi_sell = False
        
        buy_entry_mr = rsi_buy and liq_buy_ok and fvg_buy_ok and (not apply_bias or trend_up)
        sell_entry_mr = rsi_sell and liq_sell_ok and fvg_sell_ok and (not apply_bias or trend_dn)
        
        # Breakout entries
        tol = self.tolPct / 100.0
        
        if self.r1 is not None and len(self.data) >= 2:
            break_buy_raw = self.useBreakoutEntries and crossover(pd.Series([self.data.Close[-2], close]), self.r1)
            retest_buy_ok = not self.breakoutNeedsRetest or (close > self.r1 and low <= self.r1 * (1 + tol))
            break_fvg_buy_ok = not self.breakoutUseFVG or self.fvg_bull_recent
            buy_entry_bo = break_buy_raw and retest_buy_ok and break_fvg_buy_ok and (not apply_bias or trend_up)
        else:
            buy_entry_bo = False
        
        if self.s1 is not None and len(self.data) >= 2:
            break_sell_raw = self.useBreakoutEntries and crossover(self.s1, pd.Series([self.data.Close[-2], close]))
            retest_sell_ok = not self.breakoutNeedsRetest or (close < self.s1 and high >= self.s1 * (1 - tol))
            break_fvg_sell_ok = not self.breakoutUseFVG or self.fvg_bear_recent
            sell_entry_bo = break_sell_raw and retest_sell_ok and break_fvg_sell_ok and (not apply_bias or trend_dn)
        else:
            sell_entry_bo = False
        
        # Execute trades
        if (buy_entry_mr or buy_entry_bo) and not self.position:
            self.buy()
        elif (sell_entry_mr or sell_entry_bo) and self.position:
            self.position.close()


