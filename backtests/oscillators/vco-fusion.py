import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 10
    scale = 200
    overbought = 25
    oversold = -25
    smoothLen1 = 7
    maLen1 = 5
    smoothLen2 = 10
    maLen2 = 5
    bull_circle_upper = 20
    bull_circle_lower = 1
    bear_circle_upper = -1
    bear_circle_lower = -20
    hist_peak_upper = 3
    hist_peak_lower = -3
    pivotLength = 2
    showDivergence = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate candle mid and ranges
        candleMid = (high + low) / 2
        midSma = self.I(pta.sma, candleMid, length=self.length)
        avgRange = self.I(pta.sma, high - low, length=self.length)
        avgBody = self.I(pta.sma, np.abs(close - pd.Series(self.data.Open)), length=self.length)
        
        # Calculate bands
        def calc_offset(mid_sma, avg_range, avg_body):
            if mid_sma is None or avg_range is None or avg_body is None:
                return pd.Series(0, index=close.index)
            return avg_range * self.scale / 100 * (1 + avg_body / np.maximum(avg_range, 1e-10))
        
        offset = self.I(calc_offset, midSma, avgRange, avgBody)
        
        def calc_upper(mid_sma, offset_vals):
            if mid_sma is None or offset_vals is None:
                return pd.Series(0, index=close.index)
            return mid_sma + offset_vals
        
        def calc_lower(mid_sma, offset_vals):
            if mid_sma is None or offset_vals is None:
                return pd.Series(0, index=close.index)
            return mid_sma - offset_vals
        
        upperBand = self.I(calc_upper, midSma, offset)
        lowerBand = self.I(calc_lower, midSma, offset)
        
        # Calculate band width and oscillator
        def calc_bandwidth(upper, lower):
            if upper is None or lower is None:
                return pd.Series(1, index=close.index)
            return np.maximum(upper - lower, 1e-10)
        
        bandWidth = self.I(calc_bandwidth, upperBand, lowerBand)
        
        def calc_osc(cls_data, lower, bandwidth):
            if lower is None or bandwidth is None:
                return pd.Series(0, index=close.index)
            raw = 100 * (cls_data - lower) / bandwidth - 50
            return np.maximum(np.minimum(raw, 100), -100)
        
        oscValue = self.I(calc_osc, close, lowerBand, bandWidth)
        
        # Smooth oscillator
        oscSmooth1 = self.I(pta.ema, oscValue, length=self.smoothLen1)
        self.ma1 = self.I(pta.sma, oscSmooth1, length=self.maLen1)
        
        oscSmooth2 = self.I(pta.ema, oscValue, length=self.smoothLen2)
        self.ma2 = self.I(pta.sma, oscSmooth2, length=self.maLen2)
        
        # Histogram
        def calc_hist(m1, m2):
            if m1 is None or m2 is None:
                return pd.Series(0, index=close.index)
            return m1 - m2
        
        self.hist = self.I(calc_hist, self.ma1, self.ma2)
        
        # Store high and low for divergences
        self.high_series = high
        self.low_series = low
        self.close_series = close
        self.last_pivot_high = None
        self.last_pivot_low = None
        self.last_pivot_high_idx = None
        self.last_pivot_low_idx = None

    def next(self):
        if len(self.data) < self.pivotLength * 2 + 1:
            return
        
        # Check for histogram turn (peak down and peak up)
        if len(self.hist) >= 3:
            hist_turn_down = (self.hist[-1] < self.hist[-2] and 
                             self.hist[-2] > self.hist[-3] and 
                             self.hist[-2] > self.hist_peak_upper)
            hist_turn_up = (self.hist[-1] > self.hist[-2] and 
                           self.hist[-2] < self.hist[-3] and 
                           self.hist[-2] < self.hist_peak_lower)
        else:
            hist_turn_down = False
            hist_turn_up = False
        
        # Check for MA1/MA2 crossovers
        crossUp = crossover(self.ma1, self.ma2)
        crossDown = crossover(self.ma2, self.ma1)
        
        # Range-based circle signals
        bullCrossSignal = (crossUp and 
                          self.ma1[-1] >= self.bull_circle_lower and 
                          self.ma1[-1] <= self.bull_circle_upper)
        bearCrossSignal = (crossDown and 
                          self.ma1[-1] >= self.bear_circle_lower and 
                          self.ma1[-1] <= self.bear_circle_upper)
        
        # Long/Short signals based on oversold/overbought
        longSignal = crossover(self.ma1, self.oversold)
        shortSignal = crossover(self.overbought, self.ma1)
        
        # Entry/Exit logic
        if not self.position:
            # Buy signals
            if longSignal or bullCrossSignal or hist_turn_up:
                self.buy()
            # Short signals (for completeness in oscillator trading)
            elif shortSignal or bearCrossSignal or hist_turn_down:
                self.sell()
        else:
            # Exit logic for long positions
            if self.position.is_long:
                if shortSignal or bearCrossSignal or hist_turn_down:
                    self.position.close()
            # Exit logic for short positions
            elif self.position.is_short:
                if longSignal or bullCrossSignal or hist_turn_up:
                    self.position.close()


