import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    length_k = 10
    length_d = 3
    length_ema = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI calculation
        self.rsi = self.I(self._calculate_rsi, close, self.rsi_length)
        
        # Stochastic Momentum Index calculation
        self.smi, self.smi_ema = self.I(self._calculate_smi, high, low, close, 
                                         self.length_k, self.length_d, self.length_ema)

    def _calculate_rsi(self, close, length):
        change = close.diff()
        up = change.clip(lower=0).rolling(window=length).mean()
        down = -change.clip(upper=0).rolling(window=length).mean()
        rs = up / down
        rsi = 100 - (100 / (1 + rs))
        rsi = rsi.fillna(50)
        return rsi

    def _calculate_smi(self, high, low, close, length_k, length_d, length_ema):
        highest_high = high.rolling(window=length_k).max()
        lowest_low = low.rolling(window=length_k).min()
        highest_lowest_range = highest_high - lowest_low
        relative_range = close - (highest_high + lowest_low) / 2
        
        # Double EMA of relative range and range
        ema_relative = relative_range.ewm(span=length_d, adjust=False).mean()
        ema_relative_ema = ema_relative.ewm(span=length_d, adjust=False).mean()
        
        ema_range = highest_lowest_range.ewm(span=length_d, adjust=False).mean()
        ema_range_ema = ema_range.ewm(span=length_d, adjust=False).mean()
        
        # Avoid division by zero
        smi_raw = np.where(ema_range_ema != 0, 200 * (ema_relative_ema / ema_range_ema), 0)
        smi_raw = pd.Series(smi_raw, index=close.index)
        
        smi_ema_raw = smi_raw.ewm(span=length_ema, adjust=False).mean()
        
        smi = (smi_raw / 2.0) + 50
        smi_ema = (smi_ema_raw / 2.0) + 50
        
        smi = smi.fillna(50)
        smi_ema = smi_ema.fillna(50)
        
        return smi, smi_ema

    def next(self):
        # Buy when RSI crosses above 30 (oversold)
        if crossover(self.rsi, 30):
            self.buy()
        # Sell when RSI crosses above 70 (overbought)
        elif crossover(70, self.rsi):
            self.sell()
        
        # Additional signals from SMI
        # Buy when SMI EMA crosses above 30
        if crossover(self.smi_ema, 30) and not self.position:
            self.buy()
        # Sell when SMI EMA crosses above 70
        elif crossover(70, self.smi_ema) and self.position:
            self.sell()


