import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenInput = 20
    sensitivityInput = 1.5
    signalLenInput = 9
    minRvolInput = 1.2
    minAgreementInput = 0.6

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # 1. Momentum Drive: Aggression of movement
        momROC = self.I(lambda: pta.roc(close, length=self.lenInput) or pd.Series(0, index=close.index))
        momStd = self.I(lambda: close.rolling(self.lenInput).std() or pd.Series(0.001, index=close.index))
        momDrive = self.I(lambda: pta.ema(momROC / (momStd + 0.00001), length=5) or pd.Series(0, index=close.index))

        # 2. Structural Alignment: Support of trend
        emaFast = self.I(lambda: pta.ema(close, length=self.lenInput) or pd.Series(close.iloc[0], index=close.index))
        emaSlow = self.I(lambda: pta.ema(close, length=self.lenInput * 2) or pd.Series(close.iloc[0], index=close.index))
        
        def calc_struct():
            struct_vals = (close - emaSlow) / (emaFast - emaSlow + 0.00001)
            struct_vals = struct_vals.clip(-2, 2)
            return pta.ema(struct_vals, length=5) or pd.Series(0, index=close.index)
        
        structAlign = self.I(calc_struct)

        # 3. Pullback Quality: Health of retracements
        highest = self.I(lambda: high.rolling(self.lenInput).max() or pd.Series(high.iloc[0], index=high.index))
        lowest = self.I(lambda: low.rolling(self.lenInput).min() or pd.Series(low.iloc[0], index=low.index))
        
        def calc_pullback():
            range_ = highest - lowest
            pb = (close - lowest) / (range_ + 0.00001)
            pb = pb.fillna(0.5)
            return (pb - 0.5) * 2
        
        pbQuality = self.I(calc_pullback)

        # 4. Component Normalization (tanh approximation)
        def tanh_approx(x):
            e2x = np.exp(2 * x.clip(-10, 10))
            return (e2x - 1) / (e2x + 1)

        normMom = self.I(lambda: tanh_approx(momDrive * self.sensitivityInput))
        normStruct = self.I(lambda: tanh_approx(structAlign * self.sensitivityInput))
        normPB = self.I(lambda: tanh_approx(pbQuality * self.sensitivityInput))

        # 5. Volume Metrics
        avgVol = self.I(lambda: pta.sma(volume, length=20) or pd.Series(volume.iloc[0], index=volume.index))
        rvol = self.I(lambda: volume / (avgVol + 0.00001))

        # 6. Agreement Metric
        agreement = self.I(lambda: 1.0 - np.abs(normMom - normStruct) * 0.3 - np.abs(normStruct - normPB) * 0.3)

        # 7. Composite Pressure Score
        composite = self.I(lambda: (normMom + normStruct + normPB) / 3)
        compScore = self.I(lambda: composite * 100)

        # 8. Signal Line & Filtered Crossovers
        sigLine = self.I(lambda: pta.ema(compScore, length=self.signalLenInput) or pd.Series(0, index=compScore.index))

        self.momDrive = momDrive
        self.structAlign = structAlign
        self.pbQuality = pbQuality
        self.normMom = normMom
        self.normStruct = normStruct
        self.normPB = normPB
        self.rvol = rvol
        self.agreement = agreement
        self.composite = composite
        self.compScore = compScore
        self.sigLine = sigLine

    def next(self):
        if len(self.data.Close) < self.lenInput * 2 + self.signalLenInput:
            return

        compScore = self.compScore[-1]
        sigLine = self.sigLine[-1]
        rvol = self.rvol[-1]
        agreement = self.agreement[-1]

        bullCrossRaw = crossover(self.compScore, self.sigLine)
        bearCrossRaw = crossover(self.sigLine, self.compScore)

        bullCross = bullCrossRaw and rvol > self.minRvolInput and agreement > self.minAgreementInput and compScore < 40
        bearCross = bearCrossRaw and rvol > self.minRvolInput and agreement > self.minAgreementInput and compScore > -40

        if bullCross:
            if not self.position:
                self.buy()
        elif bearCross:
            if self.position:
                self.position.close()
        elif compScore > 40 and agreement > 0.7:
            if not self.position:
                self.buy()
        elif compScore < -40 and agreement > 0.7:
            if self.position:
                self.position.close()
        elif agreement < 0.5:
            if self.position:
                self.position.close()


