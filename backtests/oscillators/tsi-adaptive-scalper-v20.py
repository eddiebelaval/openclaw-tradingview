        # ===== ADX Calculation =====
        def calc_adx():
            tr = pta.tr(high, low, close, True)
            up_move = high.diff()
            dn_move = -low.diff()
            
            plus_dm = np.where((up_move > dn_move) & (up_move > 0), up_move, 0.0)
