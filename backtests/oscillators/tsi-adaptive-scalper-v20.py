            di_sum = di_plus + di_minus
            dx = np.where(di_sum != 0, 100.0 * np.abs(di_plus - di_minus) / di_sum, 0.0)
            
            adx = pta.rma(pd.Series(dx), length=self.adxLen)
            return adx if adx is not None else pd.Series(0, index=close.index)
        
