        clamped_vol = np.clip(atr_ratio.fillna(1.0), self.volFloor, self.volCeiling)
        
        self.dynOB = self.I(lambda: pd.Series(np.where(self.useDynVol, self.lvlOB * clamped_vol, self.lvlOB)))
