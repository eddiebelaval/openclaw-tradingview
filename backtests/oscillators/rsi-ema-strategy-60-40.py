import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    rsiUpper = 60
    rsiLower = 40
    emaShortLength = 50
    emaLongLength = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        self.ema50 = self.I(pta.ema, close, length=self.emaShortLength)
        self.ema200 = self.I(pta.ema, close, length=self.emaLongLength)

    def next(self):
        close = self.data.Close[-1]
        rsi = self.rsi[-1]
        ema50 = self.ema50[-1]
        ema200 = self.ema200[-1]
        
        if np.isnan(rsi) or np.isnan(ema50) or np.isnan(ema200):
            return
        
        buy_condition = (close > ema50 and 
                        ema50 > ema200 and 
                        crossover(self.rsi, self.rsiUpper))
        
        sell_condition = (close < ema50 and 
                         ema50 < ema200 and 
                         crossover(self.rsiLower, self.rsi))
        
        if buy_condition:
            self.buy()
        elif sell_condition:
            self.sell()


