import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    hw_len1 = 10
    hw_len2 = 21
    mf_len = 60
    mf_mult = 3.0
    lookback = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # HLC3
        hlc3 = (high + low + close) / 3
        
        # Hyper Wave (WaveTrend Logic)
        esa = self.I(pta.ema, hlc3, length=self.hw_len1)
        
        def calc_d():
            esa_vals = pd.Series(self.data.Close).ewm(span=self.hw_len1, adjust=False).mean()
            hlc3_vals = (pd.Series(self.data.High) + pd.Series(self.data.Low) + pd.Series(self.data.Close)) / 3
            abs_diff = (hlc3_vals - esa_vals).abs()
            return abs_diff.ewm(span=self.hw_len1, adjust=False).mean()
        
        d = self.I(calc_d)
        
        def calc_ci():
            esa_vals = pd.Series(self.data.Close).ewm(span=self.hw_len1, adjust=False).mean()
            hlc3_vals = (pd.Series(self.data.High) + pd.Series(self.data.Low) + pd.Series(self.data.Close)) / 3
            d_vals = (hlc3_vals - esa_vals).abs().ewm(span=self.hw_len1, adjust=False).mean()
            ci_vals = (hlc3_vals - esa_vals) / (0.015 * d_vals + 1e-10)
            return ci_vals
        
        ci = self.I(calc_ci)
        tci = self.I(pta.ema, ci, length=self.hw_len2)
        
        self.wt1 = tci
        self.wt2 = self.I(pta.sma, self.wt1, length=4)
        
