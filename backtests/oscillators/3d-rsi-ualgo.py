import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    LEN = 14
    THICKNESS = 2.0
    DIV_LB = 5
    DIV_RB = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.LEN) or pd.Series(50, index=close.index))
        
        # Calculate pivot highs and lows for divergence detection
        self.pivot_high = self.I(self._calculate_pivot_high, high, low, close)
        self.pivot_low = self.I(self._calculate_pivot_low, high, low, close)
        
        # Track previous pivot points for divergence
        self.last_pivot_high_idx = -1
        self.last_pivot_high_price = 0
        self.last_pivot_high_rsi = 0
        
        self.last_pivot_low_idx = -1
        self.last_pivot_low_price = 0
        self.last_pivot_low_rsi = 0
        
        self.in_position = False

    def _calculate_pivot_high(self, high, low, close):
        """Calculate pivot highs"""
        result = pd.Series(np.nan, index=high.index)
        for i in range(self.DIV_LB + self.DIV_RB, len(high)):
            pivot_idx = i - self.DIV_RB
            if pivot_idx >= self.DIV_LB:
                is_pivot = True
                pivot_high = high.iloc[pivot_idx]
                for j in range(pivot_idx - self.DIV_LB, pivot_idx):
                    if high.iloc[j] >= pivot_high:
                        is_pivot = False
                        break
                for j in range(pivot_idx + 1, pivot_idx + self.DIV_RB + 1):
                    if high.iloc[j] >= pivot_high:
                        is_pivot = False
                        break
                if is_pivot:
                    result.iloc[pivot_idx] = pivot_high
        return result

    def _calculate_pivot_low(self, high, low, close):
        """Calculate pivot lows"""
        result = pd.Series(np.nan, index=low.index)
        for i in range(self.DIV_LB + self.DIV_RB, len(low)):
            pivot_idx = i - self.DIV_RB
            if pivot_idx >= self.DIV_LB:
                is_pivot = True
                pivot_low = low.iloc[pivot_idx]
                for j in range(pivot_idx - self.DIV_LB, pivot_idx):
                    if low.iloc[j] <= pivot_low:
                        is_pivot = False
                        break
                for j in range(pivot_idx + 1, pivot_idx + self.DIV_RB + 1):
                    if low.iloc[j] <= pivot_low:
                        is_pivot = False
                        break
                if is_pivot:
                    result.iloc[pivot_idx] = pivot_low
        return result

    def next(self):
        current_rsi = self.rsi[-1]
        
        # Simple RSI-based trading logic
        # Buy when RSI crosses above 30 (oversold) and not already in position
        if not self.position and crossover(self.rsi, 30):
            self.buy()
            self.in_position = True
        
        # Sell when RSI crosses below 70 (overbought) or crosses below 50 for exit
        elif self.position and crossover(70, self.rsi):
            self.sell()
            self.in_position = False
        
        # Also sell if RSI drops significantly
        elif self.position and self.rsi[-1] < 40 and len(self.rsi) > 1 and self.rsi[-2] > self.rsi[-1]:
            self.sell()
            self.in_position = False