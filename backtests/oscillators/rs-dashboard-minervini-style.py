import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsLen = 252
    shortLen = 55
    smaLen = 200
    highestLen = 50
    rsHighestLen = 100

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RS momentum components
        def calc_stock_return():
            result = pd.Series(np.nan, index=close.index)
            for i in range(len(close)):
                if i >= self.shortLen:
                    result.iloc[i] = close.iloc[i] / close.iloc[i - self.shortLen]
                else:
                    result.iloc[i] = np.nan
            return result
        
        def calc_index_return():
            # Using close as proxy for index since we don't have actual index data
            result = pd.Series(np.nan, index=close.index)
            for i in range(len(close)):
                if i >= self.shortLen:
                    result.iloc[i] = close.iloc[i] / close.iloc[i - self.shortLen]
                else:
                    result.iloc[i] = np.nan
            return result
        
        def calc_rs_momentum():
            stock_ret = calc_stock_return()
            index_ret = calc_index_return()
            rs_mom = pd.Series(np.nan, index=close.index)
            for i in range(len(close)):
                if pd.notna(stock_ret.iloc[i]) and pd.notna(index_ret.iloc[i]) and index_ret.iloc[i] != 0:
                    rs_mom.iloc[i] = stock_ret.iloc[i] / index_ret.iloc[i]
            return rs_mom
        
        def calc_rs():
            # RS = close / index_close (using close as proxy for index)
            rs = pd.Series(np.nan, index=close.index)
            for i in range(len(close)):
                rs.iloc[i] = close.iloc[i] / close.iloc[i]  # Normalized to 1
            return rs
        
        def calc_rs_rating():
            rs_momentum = calc_rs_momentum()
            rs_min = rs_momentum.rolling(self.rsLen).min()
            rs_max = rs_momentum.rolling(self.rsLen).max()
            rs_rating = pd.Series(np.nan, index=close.index)
            for i in range(len(rs_momentum)):
                if pd.notna(rs_min.iloc[i]) and pd.notna(rs_max.iloc[i]):
                    denominator = rs_max.iloc[i] - rs_min.iloc[i]
                    if denominator != 0:
                        rs_rating.iloc[i] = 100 * (rs_momentum.iloc[i] - rs_min.iloc[i]) / denominator
                    else:
                        rs_rating.iloc[i] = 50
            return rs_rating
        
        def calc_above_200ma():
            sma200 = pta.sma(close, length=self.smaLen)
            above_200 = close > sma200
            return above_200
        
        def calc_breakout():
            highest_50 = close.rolling(self.highestLen).max()
            breakout = close > highest_50
            return breakout
        
        def calc_rs_strong():
            rs_rating = calc_rs_rating()
            rs_strong = rs_rating > 70
            return rs_strong
        
        def calc_rs_new_high():
            rs_val = calc_rs()
            highest_rs_100 = rs_val.rolling(self.rsHighestLen).max()
            rs_new_high = rs_val >= highest_rs_100
            return rs_new_high
        
        def calc_leader_signal():
            rs_strong = calc_rs_strong()
            rs_new_high = calc_rs_new_high()
            above_200 = calc_above_200ma()
            breakout = calc_breakout()
            leader = rs_strong & rs_new_high & above_200 & breakout
            return leader
        
        self.rs_rating = self.I(calc_rs_rating)
        self.rs_strong = self.I(calc_rs_strong)
        self.rs_new_high = self.I(calc_rs_new_high)
        self.above_200ma = self.I(calc_above_200ma)
        self.breakout = self.I(calc_breakout)
        self.leader_signal = self.I(calc_leader_signal)

    def next(self):
        # Entry condition: Leader stock signal
        if len(self) > self.rsLen + self.shortLen and self.leader_signal[-1]:
            if not self.position:
                self.buy()
        
        # Exit condition: Loss of leader signal or dropping below 200MA
        elif self.position:
            if not self.leader_signal[-1] or not self.above_200ma[-1]:
                self.position.close()