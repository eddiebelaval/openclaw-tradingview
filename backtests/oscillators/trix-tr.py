import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Length_TRIX = 18
    Length_MA_TRIX = 365
    MA_Type_TRIX = 'EMA'
    Signal_TRIX = 'TRIX MA'

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate TRIX
        log_source = np.log(close)
        
        # Apply moving average function based on type
        def apply_ma(series, length, ma_type):
            if ma_type == 'EMA':
                return pta.ema(series, length=length)
            elif ma_type == 'SMA':
                return pta.sma(series, length=length)
            elif ma_type == 'RMA':
                return pta.rma(series, length=length)
            elif ma_type == 'WMA':
                return pta.wma(series, length=length)
            elif ma_type == 'VWMA':
                return pta.vwma(series, self.data.Volume, length=length)
            elif ma_type == 'HMA':
                return pta.hma(series, length=length)
            else:
                return pta.ema(series, length=length)
        
        # Triple moving average on log source
        ma1 = self.I(lambda: apply_ma(log_source, self.Length_TRIX, self.MA_Type_TRIX) or pd.Series(0, index=close.index))
        ma2 = self.I(lambda: apply_ma(ma1, self.Length_TRIX, self.MA_Type_TRIX) or pd.Series(0, index=close.index))
        ma3 = self.I(lambda: apply_ma(ma2, self.Length_TRIX, self.MA_Type_TRIX) or pd.Series(0, index=close.index))
        
        # Calculate TRIX as rate of change
        def calc_trix(ma3_series):
            trix_values = pd.Series(index=ma3_series.index, dtype=float)
            for i in range(1, len(ma3_series)):
                if pd.notna(ma3_series.iloc[i]) and pd.notna(ma3_series.iloc[i-1]):
                    trix_values.iloc[i] = 10000 * (ma3_series.iloc[i] - ma3_series.iloc[i-1])
                else:
                    trix_values.iloc[i] = 0
            return trix_values
        
        self.trix = self.I(lambda: calc_trix(ma3))
        
        # Calculate TRIX MA signal line
        self.trix_ma = self.I(lambda: apply_ma(self.trix, self.Length_MA_TRIX, self.MA_Type_TRIX) or pd.Series(0, index=close.index))
        
        # Determine entry signal level
        if self.Signal_TRIX == 'TRIX MA':
            self.entry_level = self.trix_ma
        else:
            self.entry_level = self.I(lambda: pd.Series(0, index=close.index))

    def next(self):
        # Get current TRIX value
        trix_current = self.trix[-1] if len(self.trix) > 0 else 0
        entry_current = self.entry_level[-1] if len(self.entry_level) > 0 else 0
        
        # Buy signal: TRIX crosses above entry level
        if len(self.trix) > 1:
            trix_prev = self.trix[-2]
            entry_prev = self.entry_level[-2]
            
            if crossover(self.trix, self.entry_level):
                if not self.position:
                    self.buy()
            # Sell signal: TRIX crosses below entry level
            elif crossover(self.entry_level, self.trix):
                if self.position:
                    self.position.close()