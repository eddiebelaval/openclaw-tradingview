import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Length_DCCI = 55
    Length_MA_DCCI = 365
    Source_MA_DCCI = 'EMA'
    T_Factor = 0.7
    Signal_DCCI = '0'

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate CCI
        self.cci = self.I(lambda: pta.cci(high, low, close, length=self.Length_DCCI) or pd.Series(0, index=close.index))
        
        # Calculate DCCI = 2 * CCI - CCI(CCI)
        def calc_dcci():
            cci_vals = pta.cci(high, low, close, length=self.Length_DCCI)
            if cci_vals is None or len(cci_vals) == 0:
                return pd.Series(0, index=close.index)
            cci_of_cci = pta.cci(pd.Series(cci_vals.values), pd.Series(cci_vals.values), pd.Series(cci_vals.values), length=self.Length_DCCI)
            if cci_of_cci is None:
                return pd.Series(0, index=close.index)
            return 2 * cci_vals - cci_of_cci
        
        self.dcci = self.I(calc_dcci)
        
        # Calculate DCCI MA
        def calc_dcci_ma():
            dcci_vals = calc_dcci()
            if dcci_vals is None or len(dcci_vals) == 0:
                return pd.Series(0, index=close.index)
            
            if self.Source_MA_DCCI == 'EMA':
                ma_vals = pta.ema(dcci_vals, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'SMA':
                ma_vals = pta.sma(dcci_vals, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'RMA':
                ma_vals = pta.rma(dcci_vals, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'WMA':
                ma_vals = pta.wma(dcci_vals, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'VWMA':
                volume = pd.Series(self.data.Volume)
                ma_vals = pta.vwma(dcci_vals, volume, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'HMA':
                ma_vals = pta.hma(dcci_vals, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'DEMA':
                ma_vals = pta.dema(dcci_vals, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'TEMA':
                ma_vals = pta.tema(dcci_vals, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'TRIMA':
                ma_vals = pta.trima(dcci_vals, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'FRAMA':
                ma_vals = pta.frama(dcci_vals, length=self.Length_MA_DCCI)
            elif self.Source_MA_DCCI == 'SWMA':
                ma_vals = pta.swma(dcci_vals)
            elif self.Source_MA_DCCI == 'T3':
                ma_vals = pta.t3(dcci_vals, length=self.Length_MA_DCCI, factor=self.T_Factor)
            else:
                ma_vals = pta.ema(dcci_vals, length=self.Length_MA_DCCI)
            
            if ma_vals is None:
                return pd.Series(0, index=close.index)
            return ma_vals
        
        self.dcci_ma = self.I(calc_dcci_ma)

    def next(self):
        if len(self.data) < self.Length_DCCI + self.Length_MA_DCCI:
            return
        
        # Determine entry signal threshold
        if self.Signal_DCCI == 'DCCI MA':
            entry_threshold = self.dcci_ma[-1]
        else:
            entry_threshold = 0.0
        
        # Check for bull and bear crossovers
        dcci_current = self.dcci[-1]
        dcci_prev = self.dcci[-2] if len(self.dcci) > 1 else dcci_current
        entry_current = entry_threshold
        entry_prev = self.dcci_ma[-2] if len(self.dcci_ma) > 1 else entry_threshold
        
        # Crossover detection
        bull_crossover = dcci_prev <= entry_prev and dcci_current > entry_current
        bear_crossover = dcci_prev >= entry_prev and dcci_current < entry_current
        
        if bull_crossover:
            if self.position:
                self.position.close()
            self.buy()
        elif bear_crossover:
            if self.position:
                self.position.close()