import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    maLength = 9
    priceRangeBars = 30
    smoothLength = 10
    smoothType = "EMA"
    multiplier = 2.5
    periods = 100
    rsiOB = 70
    rsiOS = 30
    atrPeriod = 14
    slAtrMult = 1.5
    slPercent = 1.0
    rrTp1 = 1.0
    rrTp2 = 2.0
    rrTp3 = 3.0
    useAtrForSl = True
    trendFollowingOnly = False
    counterTrendOnly = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLength) or pd.Series(50, index=close.index))
        self.ma_rsi = self.I(lambda: pta.sma(self.rsi, length=self.maLength) or pd.Series(50, index=close.index))
        
        self.price_high = self.I(lambda: high.rolling(window=self.priceRangeBars).max())
        self.price_low = self.I(lambda: low.rolling(window=self.priceRangeBars).min())
        
        self.scale = self.I(lambda: (self.price_high - self.price_low) / 100.0)
        self.projected = self.I(lambda: self.price_low + self.ma_rsi * self.scale)
        
        if self.smoothType == "SMA":
            self.avg_line = self.I(lambda: pta.sma(self.projected, length=self.smoothLength) or self.projected)
        elif self.smoothType == "WMA":
            self.avg_line = self.I(lambda: pta.wma(self.projected, length=self.smoothLength) or self.projected)
        else:
            self.avg_line = self.I(lambda: pta.ema(self.projected, length=self.smoothLength) or self.projected)
        
        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.atrPeriod) or pd.Series(0, index=close.index))
        
        self.body = self.I(lambda: pd.Series(np.abs(self.data.Open - self.data.Close)))
        self.avg_body = self.I(lambda: self.body.rolling(window=self.periods).mean())
        self.tolerance = self.I(lambda: self.multiplier * self.avg_body)
        
        self.is_uptrend = True
        self.margin_line = self.I(lambda: self._calc_margin_line())
        
        self.trend_distance = self.I(lambda: pd.Series(np.abs(close - self.margin_line)))
        self.max_distance = self.I(lambda: self.trend_distance.rolling(window=self.periods).max())
        
        self.is_ob = self.I(lambda: self.rsi > self.rsiOB)
        self.is_os = self.I(lambda: self.rsi < self.rsiOS)
        
        self.trade_dir = 0
        self.entry_price = None
        self.sl_level = None
        self.extreme_level = None
        self.entry_bar = None
        self.ob_break_signal = False
        self.ob_bottom_break_signal = False
        self.os_break_signal = False
        self.os_top_break_signal = False
        self.prev_is_ob = False
        self.prev_is_os = False
        self.ob_line_level = None
        self.ob_bottom_line_level = None
        self.os_line_level = None
        self.os_top_line_level = None
        self.ob_line_frozen = False
        self.ob_bottom_line_frozen = False
        self.os_line_frozen = False
        self.os_top_line_frozen = False

    def _calc_margin_line(self):
        if len(self.avg_line) == 0:
            return pd.Series(0, index=pd.RangeIndex(len(self.data)))
        tolerance_vals = self.tolerance if len(self.tolerance) == len(self.avg_line) else pd.Series(0, index=self.avg_line.index)
        if self.is_uptrend:
            return self.avg_line - tolerance_vals
        else:
            return self.avg_line + tolerance_vals

    def next(self):
        if len(self) < self.priceRangeBars + max(self.rsiLength, self.maLength, self.smoothLength) + self.periods:
            return

        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_margin = self.margin_line[-1]
        current_is_ob = self.is_ob[-1]
        current_is_os = self.is_os[-1]
        current_atr = self.atr_val[-1]
        current_avg_line = self.avg_line[-1]
        current_tolerance = self.tolerance[-1]
        current_rsi = self.rsi[-1]
        
        if self.is_uptrend and current_close < current_margin:
            self.is_uptrend = False
        elif not self.is_uptrend and current_close > current_margin:
            self.is_uptrend = True
        
        if current_is_ob:
            if self.ob_line_level is None:
                self.ob_line_level = current_high
                self.ob_bottom_line_level = current_low
            else:
                self.ob_line_level = max(self.ob_line_level, current_high)
                self.ob_bottom_line_level = min(self.ob_bottom_line_level, current_low)
        else:
            if self.prev_is_ob and not current_is_ob:
                if self.ob_line_level is not None:
                    self.ob_line_frozen = False
                    self.ob_bottom_line_frozen = False
                self.ob_line_level = None
                self.ob_bottom_line_level = None
        
        if current_is_os:
            if self.os_line_level is None:
                self.os_line_level = current_low
                self.os_top_line_level = current_high
