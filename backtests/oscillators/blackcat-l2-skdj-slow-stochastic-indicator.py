import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    kPeriod = 9
    dPeriod = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate lowest and highest values
        self.lowestValue = self.I(lambda: low.rolling(self.kPeriod).min())
        self.highestValue = self.I(lambda: high.rolling(self.kPeriod).max())
        
        # Calculate RSV (Raw Stochastic Value)
        def calc_rsv():
            rsv_values = []
            for i in range(len(close)):
                if i < self.kPeriod - 1:
                    rsv_values.append(np.nan)
                else:
                    lowest = low.iloc[i - self.kPeriod + 1:i + 1].min()
                    highest = high.iloc[i - self.kPeriod + 1:i + 1].max()
                    if highest - lowest == 0:
                        rsv_values.append(50)
                    else:
                        rsv = (close.iloc[i] - lowest) / (highest - lowest) * 100
                        rsv_values.append(rsv)
            return pd.Series(rsv_values, index=close.index)
        
        rsv_series = self.I(calc_rsv)
        
        # Calculate K value: EMA of RSV
        self.kValue = self.I(lambda: pta.ema(rsv_series, length=self.dPeriod) or pd.Series(50, index=close.index))
        
        # Calculate D value: SMA of K value
        self.dValue = self.I(lambda: pta.sma(self.kValue, length=self.dPeriod) or pd.Series(50, index=close.index))

    def next(self):
        # Buy signal: K crosses above D in oversold zone (D < 30)
        if len(self.data) < 2:
            return
        
        k_curr = self.kValue[-1]
        k_prev = self.kValue[-2]
        d_curr = self.dValue[-1]
        d_prev = self.dValue[-2]
        
        buy_signal = (k_prev <= d_prev and k_curr > d_curr and d_curr < 30)
        sell_signal = (k_prev >= d_prev and k_curr < d_curr and d_curr > 70)
        
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()


