import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    overbought_level = 70.0
    oversold_level = 30.0

    def init(self):
        close = pd.Series(self.data.Close)
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)

    def next(self):
        if len(self) < self.rsi_length + 1:
            return

        current_rsi = self.rsi[-1]
        prev_rsi = self.rsi[-2] if len(self.rsi) > 1 else current_rsi

        if not self.position:
            if prev_rsi <= self.oversold_level and current_rsi > self.oversold_level:
                self.buy()
            elif prev_rsi >= self.overbought_level and current_rsi < self.overbought_level:
                self.sell()
        else:
            if self.position.is_long:
                if current_rsi > self.overbought_level:
                    self.position.close()
            elif self.position.is_short:
                if current_rsi < self.oversold_level:
                    self.position.close()


