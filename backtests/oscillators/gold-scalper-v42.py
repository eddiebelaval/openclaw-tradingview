import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ltf_length = 20
    ltf_mult1 = 1.0
    ltf_mult2 = 2.0
    htf_length = 20
    htf_mult1 = 1.5
    htf_mult2 = 2.25
    bv_threshold = 0.4
    sv_threshold = 0.4

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # LTF Kalman filter basis
        self.ltf_basis = self.I(self._kalman_filter, close)

        # LTF Standard deviation
        self.ltf_stdev = self.I(lambda: close.rolling(self.ltf_length).std())

        # LTF Bollinger Bands
        self.ltf_bb1_up = self.I(lambda: self.ltf_basis + self.ltf_mult1 * self.ltf_stdev)
        self.ltf_bb1_lo = self.I(lambda: self.ltf_basis - self.ltf_mult1 * self.ltf_stdev)
        self.ltf_bb2_up = self.I(lambda: self.ltf_basis + self.ltf_mult2 * self.ltf_stdev)
        self.ltf_bb2_lo = self.I(lambda: self.ltf_basis - self.ltf_mult2 * self.ltf_stdev)

        # HTF SMA and stdev (using close as proxy for HTF data)
        self.htf_sma = self.I(pta.sma, close, length=self.htf_length)
        self.htf_stdev = self.I(lambda: close.rolling(self.htf_length).std())

        # HTF Bollinger Bands
        self.htf_bb1_up = self.I(lambda: self.htf_sma + self.htf_mult1 * self.htf_stdev)
        self.htf_bb1_lo = self.I(lambda: self.htf_sma - self.htf_mult1 * self.htf_stdev)
        self.htf_bb2_up = self.I(lambda: self.htf_sma + self.htf_mult2 * self.htf_stdev)
        self.htf_bb2_lo = self.I(lambda: self.htf_sma - self.htf_mult2 * self.htf_stdev)

        # Volume-based gradient
        hl = np.maximum(high - low, 1e-10)
        vol = np.maximum(volume, 1e-10)
        bv_pct = (volume * (close - low) / hl) / vol
        sv_pct = (volume * (high - close) / hl) / vol

        self.bv_ema = self.I(pta.ema, bv_pct, length=3)
        self.sv_ema = self.I(pta.ema, sv_pct, length=3)

        # Signal state tracking
        self.crossed_above = False
        self.crossed_below = False
        self.bear_signaled = False
        self.bull_signaled = False
        self.last_entry = np.nan
        self.last_side = None

    def _kalman_filter(self, src):
        """Simple Kalman filter implementation"""
        result = []
        estimate = src.iloc[0]
        error_est = 1.0

        for i, val in enumerate(src):
            process_noise = 0.005 * max(val, 1.0)
            measurement_err = 0.020 * max(val, 1.0)

            prediction = estimate
            kalman_gain = error_est / (error_est + measurement_err)
            estimate = prediction + kalman_gain * (val - prediction)
            error_est = (1.0 - kalman_gain) * error_est + process_noise

            result.append(estimate)

        return pd.Series(result, index=src.index)

    def next(self):
        if len(self.data) < self.ltf_length + 1:
            return

        close = self.data.Close[-1]
        ltf_bb2_up = self.ltf_bb2_up[-1]
        ltf_bb2_lo = self.ltf_bb2_lo[-1]
        ltf_bb1_up = self.ltf_bb1_up[-1]
        ltf_bb1_lo = self.ltf_bb1_lo[-1]
        htf_basis = self.htf_sma[-1]
        htf_bb1_up = self.htf_bb1_up[-1]
        htf_bb1_lo = self.htf_bb1_lo[-1]
        bv_ema = self.bv_ema[-1] if self.bv_ema[-1] is not None else 0
        sv_ema = self.sv_ema[-1] if self.sv_ema[-1] is not None else 0

        # Zone detection
        in_bear_zone = close > ltf_bb2_up
        in_bull_zone = close < ltf_bb2_lo
        htf_bullish = close > htf_basis
        htf_bearish = close < htf_basis

        # Momentum
        ltf_bear_momentum = (self.ltf_bb2_up[-1] < self.ltf_bb2_up[-2] and
                             self.data.Close[-1] < self.data.Close[-2])
        ltf_bull_momentum = (self.ltf_bb2_lo[-1] > self.ltf_bb2_lo[-2] and
                             self.data.Close[-1] > self.data.Close[-2])

        # Crossover tracking
        if in_bear_zone:
            self.crossed_above = True
        if in_bull_zone:
            self.crossed_below = True

        # Reset crossing on reversal
        if close < ltf_bb1_up and close < htf_bb1_up:
            self.crossed_above = False
            self.bear_signaled = False
        if close > ltf_bb1_lo and close > htf_bb1_lo:
            self.crossed_below = False
            self.bull_signaled = False

        # Volume filters
        has_bull_vol = bv_ema > self.bv_threshold
        has_bear_vol = sv_ema > self.sv_threshold

        # Signal generation
        sell_signal = (self.crossed_above and ltf_bear_momentum and htf_bearish and
                       has_bear_vol and not self.bear_signaled)
        buy_signal = (self.crossed_below and ltf_bull_momentum and htf_bullish and
                      has_bull_vol and not self.bull_signaled)

        if sell_signal and not self.position:
            self.sell()
            self.bear_signaled = True
            self.last_entry = close
            self.last_side = "SELL"

        if buy_signal and not self.position:
            self.buy()
            self.bull_signaled = True
            self.last_entry = close
            self.last_side = "BUY"

        # Exit logic: sell at upper band, buy at lower band
        if self.position and self.last_side == "BUY":
            if close > ltf_bb2_up:
                self.position.close()

        if self.position and self.last_side == "SELL":
            if close < ltf_bb2_lo:
                self.position.close()


