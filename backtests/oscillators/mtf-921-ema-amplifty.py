import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenFast = 9
    lenSlow = 21

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Current timeframe EMAs
        self.emaFast = self.I(pta.ema, close, length=self.lenFast)
        self.emaSlow = self.I(pta.ema, close, length=self.lenSlow)
        
        # SMAs for reference
        self.sma50 = self.I(pta.sma, close, length=50)
        self.sma100 = self.I(pta.sma, close, length=100)
        self.sma200 = self.I(pta.sma, close, length=200)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Buy on fast EMA crossing above slow EMA
        if crossover(self.emaFast, self.emaSlow):
            if not self.position:
                self.buy()
        
        # Sell on fast EMA crossing below slow EMA
        elif crossover(self.emaSlow, self.emaFast):
            if self.position:
                self.position.close()


