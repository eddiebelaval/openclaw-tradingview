import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    preset = "Original"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Determine parameters based on preset
        if self.preset == "Agressif":
            self.rsi_period = 7
            self.buy_threshold = 80
            self.sell_threshold = 70
            self.use_wma_exit = False
            self.smooth_rsi_enabled = False
        else:  # Original
            self.rsi_period = 20
            self.buy_threshold = 60
            self.sell_threshold = 50
            self.use_wma_exit = True
            self.smooth_rsi_enabled = True
        
        self.market_filter_enabled = True
        self.wma_length = 50
        self.smooth_rsi_period = 10
        self.smooth_rsi_method = "SMA"
        self.market_filter_ema_period = 50
        
        # RSI Calculation
        self.rsi = self.I(pta.rsi, close, length=self.rsi_period)
        
        # Smooth RSI Calculation
        if self.smooth_rsi_enabled:
            if self.smooth_rsi_method == "SMA":
                self.smooth_rsi = self.I(pta.sma, self.rsi, length=self.smooth_rsi_period)
            else:  # EMA
                self.smooth_rsi = self.I(pta.ema, self.rsi, length=self.smooth_rsi_period)
            self.final_rsi = self.smooth_rsi
        else:
            self.final_rsi = self.rsi
        
        # WMA Calculation for Exit
        self.wma_exit = self.I(pta.wma, close, length=self.wma_length)
        
        # Market filter using daily data approximation
        # Since we can't use request.security, we'll use the current timeframe data
        self.market_ema = self.I(pta.ema, close, length=self.market_filter_ema_period)

    def next(self):
        if len(self.data) < max(self.rsi_period, self.wma_length, self.market_filter_ema_period) + 5:
            return
        
        # Get current values
        current_rsi = self.final_rsi[-1]
        current_close = self.data.Close[-1]
        current_wma = self.wma_exit[-1]
        current_market_ema = self.market_ema[-1]
        
        # Market filter condition
        market_above_ema = current_close > current_market_ema
        
        # Buy condition
        buy_condition = (not self.market_filter_enabled or market_above_ema) and current_rsi > self.buy_threshold
        
        # Sell condition
