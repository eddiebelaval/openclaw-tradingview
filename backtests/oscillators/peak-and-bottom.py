import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        short_len = int(self.length / 2)
        hull_len = int(np.sqrt(self.length))
        
        den1 = short_len * (short_len + 1) / 2
        den2 = self.length * (self.length + 1) / 2
        den3 = hull_len * (hull_len + 1) / 2
        
        lcwa_coeffs = []
        for i in range(self.length):
            sum1 = max(short_len - i, 0)
            sum2 = self.length - i
            lcwa_coeffs.insert(0, 2 * (sum1 / den1) - (sum2 / den2))
        
        for i in range(hull_len - 1):
            lcwa_coeffs.insert(0, 0)
        
        hull_coeffs = []
        for i in range(hull_len, len(lcwa_coeffs)):
            sum3 = 0.0
            for j in range(i - hull_len, i):
                sum3 += lcwa_coeffs[j] * (i - j)
            hull_coeffs.insert(0, sum3 / den3)
        
        self.hull_coeffs = hull_coeffs
        self.hull_len = hull_len
        
        def calc_hso():
            hso_values = []
            for bar_idx in range(len(self.data.Close)):
                if bar_idx < len(self.hull_coeffs) - 1:
                    hso_values.append(0)
                    continue
                
                hma = 0.0
                inv_hma = 0.0
                coeffs_len = len(self.hull_coeffs) - 1
                
                for i in range(coeffs_len + 1):
                    price_idx = bar_idx - i
                    if price_idx >= 0:
                        hma += self.data.Close[price_idx] * self.hull_coeffs[i]
                        inv_hma += self.data.Close[bar_idx - coeffs_len + i] * self.hull_coeffs[i]
                
                hso_values.append(hma - inv_hma)
            
            return pd.Series(hso_values, index=close.index)
        
        self.hso = self.I(calc_hso)
        
        def calc_cmean():
            cmean_values = []
            cum_sum = 0.0
            for i, val in enumerate(self.hso):
                if pd.isna(val):
                    cmean_values.append(np.nan)
                    continue
                cum_sum += abs(val)
                if i == 0:
                    cmean_values.append(np.nan)
                else:
                    cmean_values.append(cum_sum / (i + 1) * self.mult)
            
            return pd.Series(cmean_values, index=close.index)
        
        self.cmean = self.I(calc_cmean)
        
        def calc_os():
            os_values = [0]
            hso_prev = self.hso[0] if not pd.isna(self.hso[0]) else 0
            os_state = 0
            
            for i in range(1, len(self.hso)):
                if pd.isna(self.hso[i]) or pd.isna(self.cmean[i]):
                    os_values.append(0)
                    continue
                
                hso_curr = self.hso[i]
                cmean_curr = self.cmean[i]
                
                if crossover(pd.Series([hso_prev, hso_curr]), pd.Series([cmean_curr, cmean_curr])) or \
                   crossover(pd.Series([hso_prev, hso_curr]), pd.Series([-cmean_curr, -cmean_curr])):
                    os_state = 0
                elif hso_curr < hso_prev and hso_curr > cmean_curr:
                    os_state = -1
                elif hso_curr > hso_prev and hso_curr < -cmean_curr:
                    os_state = 1
                
                os_values.append(os_state)
                hso_prev = hso_curr
            
            return pd.Series(os_values, index=close.index)
        
        self.os = self.I(calc_os)

    def next(self):
        if len(self.data) < 2:
            return
        
        if pd.isna(self.os[-1]) or pd.isna(self.os[-2]):
            return
        
        bull_signal = self.os[-1] > self.os[-2] and self.os[-1] == 1
        bear_signal = self.os[-1] < self.os[-2] and self.os[-1] == -1
        
        if bull_signal:
            if not self.position:
                self.buy()
        elif bear_signal:
            if self.position:
                self.position.close()


