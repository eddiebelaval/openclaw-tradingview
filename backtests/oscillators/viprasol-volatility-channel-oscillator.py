import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Oscillator Settings
    sma_len = 30
    band_scale = 200.0
    signal_len = 20
    
    # Threshold Levels
    ob_thresh = 50.0
    os_thresh = -50.0
    ma_ob_thresh = 30.0
    ma_os_thresh = -30.0
    
    # Divergence Detection
    pivot_len = 2
    enable_div = True
    
    # Signal Settings
    signal_mode = "Overbought/Oversold"
    enable_confluence = False
    cooldown_bars = 5
    
    # Squeeze Detection
    enable_squeeze = True
    squeeze_len = 50
    squeeze_mult = 0.8

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Core oscillator calculation
        candle_midpoint = (high + low) / 2.0
        midpoint_sma = self.I(pta.sma, candle_midpoint, length=self.sma_len)
        avg_candle_range = self.I(pta.sma, high - low, length=self.sma_len)
        avg_body_size = self.I(pta.sma, np.abs(close - pd.Series(self.data.Open)), length=self.sma_len)
        
        def calc_channel_offset():
            result = avg_candle_range[-1] * self.band_scale / 100.0 * (1.0 + avg_body_size[-1] / max(avg_candle_range[-1], 1e-10))
            return result
        
        def calc_osc():
            offset = calc_channel_offset()
            upper = midpoint_sma[-1] + offset
            lower = midpoint_sma[-1] - offset
            band_span = max(upper - lower, 1e-10)
            raw_osc = 100.0 * (close[-1] - lower) / band_span - 50.0
            return max(min(raw_osc, 100.0), -100.0)
        
        self.osc = self.I(lambda: pd.Series([calc_osc()] * len(close), index=close.index))
        self.signal_line = self.I(pta.sma, self.osc, length=self.signal_len)
        
        # Momentum histogram
        self.hist = self.I(lambda: self.osc - self.signal_line)
        
        # Bandwidth for squeeze detection
        def calc_bandwidth():
            offset = calc_channel_offset()
            upper = midpoint_sma[-1] + offset
            lower = midpoint_sma[-1] - offset
            band_span = upper - lower
            bw_pct = band_span / max(midpoint_sma[-1], 1e-10) * 100.0
            return bw_pct
        
        self.bandwidth_pct = self.I(lambda: pd.Series([calc_bandwidth()] * len(close), index=close.index))
        self.bandwidth_sma = self.I(pta.sma, self.bandwidth_pct, length=self.squeeze_len)
        
        # Track signals for cooldown
        self.last_long_bar = -999
        self.last_short_bar = -999
        self.bars_since_bull_div = 999
        self.bars_since_bear_div = 999

    def next(self):
        # Current values
        osc_val = self.osc[-1]
        signal_val = self.signal_line[-1]
        hist_val = self.hist[-1]
        
        # Squeeze detection
        is_squeeze = (self.enable_squeeze and 
                     self.bandwidth_pct[-1] < self.bandwidth_sma[-1] * self.squeeze_mult)
        
        # Raw crossover signals
        raw_long_obos = crossover(self.osc, self.os_thresh)
        raw_short_obos = crossover(self.ob_thresh, self.osc)
        raw_long_zero = crossover(self.osc, 0)
        raw_short_zero = crossover(0, self.osc)
        raw_long_ma_zero = crossover(self.signal_line, 0)
        raw_short_ma_zero = crossover(0, self.signal_line)
        
        # Confluence gate (simplified - no divergence tracking in backtest)
        long_obos = raw_long_obos and (not self.enable_confluence or self.bars_since_bull_div <= 10)
        short_obos = raw_short_obos and (not self.enable_confluence or self.bars_since_bear_div <= 10)
        
        # Cooldown logic
        cooldown_long_ok = (len(self.data) - self.last_long_bar) >= self.cooldown_bars
        cooldown_short_ok = (len(self.data) - self.last_short_bar) >= self.cooldown_bars
        
        long_obos_filtered = long_obos and cooldown_long_ok
        short_obos_filtered = short_obos and cooldown_short_ok
        long_zero_filtered = raw_long_zero and cooldown_long_ok
        short_zero_filtered = raw_short_zero and cooldown_short_ok
        long_ma_zero_filtered = raw_long_ma_zero and cooldown_long_ok
        short_ma_zero_filtered = raw_short_ma_zero and cooldown_short_ok
        
        # Determine which signals are active
        show_obos = self.signal_mode in ["Overbought/Oversold", "All"]
        show_zero = self.signal_mode in ["Zero Line", "All"]
        show_ma_zero = self.signal_mode in ["MA Zero Line", "All"]
        
        # Long signals
        any_long = False
        if show_obos and long_obos_filtered:
            if not self.position:
                self.buy()
            any_long = True
        elif show_zero and long_zero_filtered:
            if not self.position:
                self.buy()
            any_long = True
        elif show_ma_zero and long_ma_zero_filtered:
            if not self.position:
                self.buy()
            any_long = True
        
