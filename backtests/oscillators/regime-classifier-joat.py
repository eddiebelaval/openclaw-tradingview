import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    i_adx_len = 14
    i_atr_len = 14
    i_regime_smooth = 3
    i_trend_thresh = 25.0
    i_vol_exp_mult = 1.3
    i_vol_con_mult = 0.7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        def calc_adx():
            adx_result = pta.adx(high, low, close, length=self.i_adx_len)
            if adx_result is not None and 'ADX_14' in adx_result.columns:
                return adx_result['ADX_14'].fillna(method='bfill').fillna(25.0)
            return pd.Series(25.0, index=close.index)
        
        def calc_atr():
            atr_result = pta.atr(high, low, close, length=self.i_atr_len)
            if atr_result is not None:
                return atr_result.fillna(method='bfill').fillna(1.0)
            return pd.Series(1.0, index=close.index)
        
        def calc_ema_fast():
            return pta.ema(close, length=self.i_adx_len).fillna(method='bfill')
        
        def calc_ema_slow():
            return pta.ema(close, length=self.i_adx_len * 2).fillna(method='bfill')
        
        def calc_vol_ratio():
            atr = pta.atr(high, low, close, length=self.i_atr_len)
            if atr is not None:
                atr_ma = pta.sma(atr, length=self.i_atr_len * 3)
                if atr_ma is not None:
                    vol_ratio = atr / atr_ma
                    vol_ratio = vol_ratio.replace([np.inf, -np.inf], 1.0).fillna(1.0)
                    return vol_ratio
            return pd.Series(1.0, index=close.index)
        
        def calc_vol_state():
            vol_ratio = calc_vol_ratio()
            vol_state = pd.Series(0, index=close.index)
            vol_state[vol_ratio > self.i_vol_exp_mult] = 1
            vol_state[vol_ratio < self.i_vol_con_mult] = -1
            return vol_state
        
        def calc_regime():
            adx = calc_adx()
            vol_state = calc_vol_state()
            
            regime = pd.Series(0, index=close.index)
            regime[(vol_state == 1) & (adx < self.i_trend_thresh)] = 3
            regime[adx >= self.i_trend_thresh] = 1
            regime[(vol_state == -1) & (adx < self.i_trend_thresh)] = 2
            
            return regime
        
        def calc_confirmed_regime():
            raw_regime = calc_regime()
            confirmed = pd.Series(0, index=close.index, dtype=int)
            counter = 0
            smooth_regime = 0
            
            for i in range(len(raw_regime)):
                if i == 0:
                    counter = 0
                    smooth_regime = raw_regime.iloc[i]
                else:
                    if raw_regime.iloc[i] == raw_regime.iloc[i-1]:
                        counter = min(counter + 1, self.i_regime_smooth)
                    else:
                        counter = 0
                    
                    if counter >= self.i_regime_smooth:
                        smooth_regime = raw_regime.iloc[i]
                
                confirmed.iloc[i] = smooth_regime
            
            return confirmed
        
        def calc_trend_dir():
            ema_fast = calc_ema_fast()
            ema_slow = calc_ema_slow()
            ma_diff = ema_fast - ema_slow
            ma_slope = ema_fast.diff(self.i_adx_len)
            
            direction = pd.Series(0, index=close.index, dtype=int)
            direction[(ma_diff > 0) & (ma_slope > 0)] = 1
            direction[(ma_diff < 0) & (ma_slope < 0)] = -1
            
            return direction
        
        def calc_regime_strength():
            adx = calc_adx()
            vol_ratio = calc_vol_ratio()
            confirmed = calc_confirmed_regime()
            
            strength = pd.Series(50.0, index=close.index)
            strength[confirmed == 1] = np.minimum((adx[confirmed == 1] / 50.0) * 100, 100)
            strength[confirmed == 2] = np.minimum((1 - vol_ratio[confirmed == 2]) * 100, 100)
            strength[confirmed == 3] = np.minimum(vol_ratio[confirmed == 3] * 50, 100)
            
            return strength
        
        def calc_regime_persistence():
            confirmed = calc_confirmed_regime()
            persistence = pd.Series(0.0, index=close.index)
            persist_counter = 0
            
            for i in range(len(confirmed)):
                if i == 0:
                    persist_counter = 0
                else:
                    if confirmed.iloc[i] == confirmed.iloc[i-1]:
                        persist_counter = min(persist_counter + 1, 20)
                    else:
                        persist_counter = 0
                
                persistence.iloc[i] = (persist_counter / 20.0) * 100
            
            return persistence
        
        def calc_regime_quality():
            strength = calc_regime_strength()
            persistence = calc_regime_persistence()
            session_mult = 1.0
            quality = np.minimum((strength * 0.5 + persistence * 0.5) * session_mult, 100)
            return quality
        
        def calc_regime_bias():
            trend_dir = calc_trend_dir()
            adx = calc_adx()
            bias = trend_dir * (adx / 100.0)
            return bias
        
        def calc_momentum():
            strength = calc_regime_strength()
            momentum = strength.diff(5).fillna(0)
            return momentum
        
        self.adx = self.I(calc_adx)
        self.vol_ratio = self.I(calc_vol_ratio)
        self.confirmed_regime = self.I(calc_confirmed_regime)
        self.regime_strength = self.I(calc_regime_strength)
        self.trend_dir = self.I(calc_trend_dir)
        self.persistence = self.I(calc_regime_persistence)
        self.regime_quality = self.I(calc_regime_quality)
        self.regime_bias = self.I(calc_regime_bias)
        self.regime_momentum = self.I(calc_momentum)

    def next(self):
        current_regime = self.confirmed_regime[-1]
        
        if len(self.data) < 2:
            return
        
        prev_regime = self.confirmed_regime[-2]
        
        if current_regime == 1 and prev_regime != 1:
            if not self.position:
                self.buy()
        
        elif current_regime == 2 and prev_regime != 2:
            if self.position:
                self.position.close()
        
        elif current_regime == 3 and prev_regime != 3:
            if self.position:
                self.position.close()
        
        elif current_regime == 0 and prev_regime == 1:
            if self.position:
                self.position.close()


