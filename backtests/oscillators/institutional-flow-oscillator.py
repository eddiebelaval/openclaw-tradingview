import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    vLen = 20
    smoothLen = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume-Weighted RSI
        vwSrc = self.I(pta.vwma, close, volume, length=self.rsiLen)
        rawRsi = self.I(pta.rsi, vwSrc, length=self.rsiLen)
        
        # Normalize and Smooth
        oscVal_raw = self.I(lambda: (rawRsi - 50) if rawRsi is not None else pd.Series(0, index=close.index))
        self.oscVal = self.I(pta.ema, oscVal_raw, length=self.smoothLen)
        self.signal = self.I(pta.ema, self.oscVal, length=9)
        
        # Institutional Volume Detection
        volAvg = self.I(pta.sma, volume, length=self.vLen)
        volStd = self.I(lambda: volume.rolling(window=self.vLen).std())
        self.isInst = self.I(lambda: volume > (volAvg + volStd))
        
        # Track previous oscillator value for crossover detection
        self.prev_osc = None

    def next(self):
        # Get current values
        current_osc = self.oscVal[-1] if len(self.oscVal) > 0 else 0
        current_signal = self.signal[-1] if len(self.signal) > 0 else 0
        
        # Initialize previous value on first bar
        if self.prev_osc is None:
            self.prev_osc = current_osc
            return
        
        # Trading Logic: Use oscillator crossover with zero line and signal line
        # Buy when oscillator crosses above zero line or signal line from below
        # Sell when oscillator crosses below zero line or signal line from above
        
        # Bullish signal: oscillator crosses above 0
        if self.prev_osc <= 0 and current_osc > 0 and not self.position:
            self.buy()
        
        # Bearish signal: oscillator crosses below 0
        elif self.prev_osc >= 0 and current_osc < 0 and self.position:
            self.sell()
        
        # Additional exit: oscillator reaches overbought territory (-30)
        elif self.position and current_osc < -30:
            self.sell()
        
        self.prev_osc = current_osc


