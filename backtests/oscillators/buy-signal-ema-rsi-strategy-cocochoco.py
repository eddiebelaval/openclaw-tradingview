import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_min = 55
    rsi_max = 80
    atr_mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate indicators
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        self.rsi = self.I(pta.rsi, close, length=25)
        
        # DMI/ADX
        adx_result = self.I(pta.adx, high, low, close, length=14)
        self.adx = self.I(lambda: adx_result.iloc[:, 2] if adx_result is not None else pd.Series(0, index=close.index))
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Volume highest over 10 bars
        self.volume_highest = self.I(lambda: volume.rolling(10).max())
        
        self.trailing_stop = np.nan

    def next(self):
        if len(self.data) < 200:
            return
        
        close = self.data.Close[-1]
        ema50_val = self.ema50[-1]
        ema200_val = self.ema200[-1]
        rsi_val = self.rsi[-1]
        adx_val = self.adx[-1]
        atr_val = self.atr[-1]
        volume_val = self.data.Volume[-1]
        volume_highest_val = self.volume_highest[-1]
        
        # Previous RSI value
        rsi_prev = self.rsi[-2] if len(self.rsi) > 1 else self.rsi[-1]
        
        # Buy conditions
        rsi_cross = crossover(self.rsi, self.rsi_min)
        rsi_rising = rsi_val > rsi_prev
        volume_filter = volume_val > volume_highest_val
        
        buy_signal = (
            ema50_val > ema200_val and
            close > ema50_val and
            close > ema200_val and
            (rsi_cross or rsi_val > self.rsi_min) and
            rsi_val < self.rsi_max and
            rsi_rising and
            adx_val > 20 and
            volume_filter
        )
        
        # Trailing stop logic
        if buy_signal:
            self.trailing_stop = close - (atr_val * self.atr_mult)
        elif self.position and not np.isnan(self.trailing_stop):
            self.trailing_stop = max(self.trailing_stop, close - (atr_val * self.atr_mult))
        else:
            self.trailing_stop = np.nan
        
        # Entry logic
        if buy_signal and not self.position:
            self.buy()
        
        # Exit logic
        if self.position and close < self.trailing_stop:
            self.sell()