import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_z = 100
    len_d = 45
    ls_thresh = 0.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        def calculate_zscore():
            mean = pta.sma(close, length=self.len_z)
            stdev = close.rolling(window=self.len_z).std()
            zscore = (close - mean) / stdev
            return zscore
        
        def calculate_dema(src):
            e1 = pta.ema(src, length=self.len_d)
            e2 = pta.ema(e1, length=self.len_d)
            dema = 2.0 * e1 - e2
            return dema
        
        self.mvrv_z = self.I(calculate_zscore)
        self.d_mvrv = self.I(lambda: calculate_dema(self.mvrv_z))

    def next(self):
        if len(self.data) < self.len_z + self.len_d + 1:
            return
        
        if self.d_mvrv[-2] <= self.ls_thresh and self.d_mvrv[-1] > self.ls_thresh:
            if not self.position:
                self.buy()
        elif self.d_mvrv[-2] >= self.ls_thresh and self.d_mvrv[-1] < self.ls_thresh:
            if self.position:
                self.position.close()


