class TvStrategy(Strategy):
    momLength = 14
    rsiLength = 14
    exhaustCount = 9
    overbought = 70
    oversold = 30
    atrMult = 2.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hlc3 = (high + low + close) / 3

        self.mom = self.I(pta.mom, close, length=self.momLength)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        self.emaFast = self.I(pta.ema, close, length=9)
        self.vwapVal = self.I(pta.vwap, high, low, close)
        self.atrVal = self.I(pta.atr, high, low, close, length=14)

        self.bullExhaust = 0
        self.bearExhaust = 0

    def next(self):
        if len(self.data) < 5:
            return

        close = self.data.Close[-1]
        close_4 = self.data.Close[-5]

        if close > close_4:
            self.bullExhaust += 1
        else:
            self.bullExhaust = 0

        if close < close_4:
            self.bearExhaust += 1
        else:
            self.bearExhaust = 0

        if self.atrVal[-1] is None or self.atrVal[-1] == 0:
            distFromEMA = 0
        else:
            distFromEMA = (close - self.emaFast[-1]) / self.atrVal[-1]

        overExtUp = distFromEMA > self.atrMult
        overExtDown = distFromEMA < -self.atrMult

        bullMomentum = (
            self.mom[-1] > 0
            and self.rsi[-1] > 50
            and self.bullExhaust >= self.exhaustCount / 2
        )

        mom_prev = self.mom[-2] if len(self.mom) > 1 else self.mom[-1]
        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50
        mom_val = self.mom[-1] if self.mom[-1] is not None else 0

        exhaustUp = (
            (rsi_val > self.overbought or self.bullExhaust >= self.exhaustCount)
            and mom_val < mom_prev
            and overExtUp
        )

        exhaustDown = (
            (rsi_val < self.oversold or self.bearExhaust >= self.exhaustCount)
            and mom_val > mom_prev
            and overExtDown
        )

        if exhaustDown and not self.position:
            self.buy()
        elif exhaustUp and self.position:
            self.sell()


