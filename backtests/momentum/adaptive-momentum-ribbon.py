import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    smoothLength = 3
    lengthkc = 20
    atrLen = 14
    mult_kc = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Butterworth Low-Pass Filter
        def butterworth_filter(source_series, len_param):
            result = np.zeros(len(source_series))
            prev1 = source_series.iloc[0]
            prev2 = source_series.iloc[0]
            
            pi_val = 3.14159265359
            safe_len = max(len_param, 1)
            a = np.exp(-np.sqrt(2.0) * pi_val / safe_len)
            b = 2.0 * a * np.cos(np.sqrt(2.0) * pi_val / safe_len)
            c2 = b
            c3 = -a * a
            c1 = 1.0 - c2 - c3
            
            result[0] = source_series.iloc[0]
            
            for i in range(1, len(source_series)):
                result[i] = c1 * source_series.iloc[i] + c2 * prev1 + c3 * prev2
                prev2 = prev1
                prev1 = result[i]
            
            return pd.Series(result, index=source_series.index)
        
        # Confirmed source (previous bar's close)
        conf_src = close.shift(1)
        
        # Core Oscillator: MAD Z-Score
        def mad_zscore(src_series, period):
            median_val = src_series.rolling(period).apply(lambda x: x.quantile(0.5), raw=False)
            deviation = src_series - median_val
            med_dev = np.abs(deviation).rolling(period).apply(lambda x: x.quantile(0.5), raw=False)
            
            # Calculate standard deviation as fallback
            stdev = src_series.rolling(period).std()
            
            # Use median absolute deviation scaled by 1.4826, or stdev if mad is 0
            mad_scale = med_dev.copy()
            mad_scale[med_dev == 0] = stdev[med_dev == 0]
            mad_scale[med_dev != 0] = med_dev[med_dev != 0] * 1.4826
            
            raw_osc = np.zeros(len(src_series))
            for i in range(len(src_series)):
                if mad_scale.iloc[i] != 0:
                    raw_osc[i] = deviation.iloc[i] / mad_scale.iloc[i]
                else:
                    raw_osc[i] = 0.0
            
            return pd.Series(raw_osc, index=src_series.index)
        
        raw_osc_series = mad_zscore(conf_src, self.length)
        signal_osc_series = butterworth_filter(raw_osc_series, self.smoothLength)
        
        # Volatility zone
        tr = pta.true_range(high, low, close)
        vol_zone = pta.ema(tr, length=100)
        
        # Signal oscillator
        self.signal_osc = self.I(lambda: signal_osc_series)
        self.vol_zone = self.I(lambda: vol_zone)
        
        # Keltner Channel
        ma_ema = pta.ema(close, length=self.lengthkc)
        atr_val = pta.atr(high, low, close, length=self.atrLen)
        
        self.midline = self.I(lambda: ma_ema)
        self.upper_kc = self.I(lambda: ma_ema + self.mult_kc * atr_val if atr_val is not None else ma_ema)
        self.lower_kc = self.I(lambda: ma_ema - self.mult_kc * atr_val if atr_val is not None else ma_ema)
        
        self.invalidated = False

    def next(self):
        if len(self.data) < 2:
            return
        
        # Get current and previous oscillator values
        current_osc = self.signal_osc[-1]
        prev_osc = self.signal_osc[-2] if len(self.signal_osc) > 1 else current_osc
        
        # Crossover detection
        buy_sig = prev_osc <= 0 and current_osc > 0
        sell_sig = prev_osc >= 0 and current_osc < 0
        
        # Entry logic
        if buy_sig and not self.position:
            self.buy()
            self.invalidated = False
        elif sell_sig and self.position:
            self.sell()
            self.invalidated = False


