import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenrsi = 3
    lenupdown = 2
    lenroc = 100
    upperTh = 80
    lowerTh = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.lenrsi)
        
        # Calculate updown function
        def updown_func(src_series):
            ud_values = []
            ud_state = 0
            prev_val = None
            
            for val in src_series:
                if prev_val is None:
                    ud_values.append(0)
                    prev_val = val
                    continue
                
                if val == prev_val:
                    ud_values.append(0)
                    ud_state = 0
                elif val > prev_val:
                    if ud_state <= 0:
                        ud_state = 1
                    else:
                        ud_state += 1
                    ud_values.append(ud_state)
                else:  # val < prev_val
                    if ud_state >= 0:
                        ud_state = -1
                    else:
                        ud_state -= 1
                    ud_values.append(ud_state)
                
                prev_val = val
            
            return pd.Series(ud_values, index=src_series.index)
        
        updown_series = self.I(updown_func, close)
        self.updownrsi = self.I(pta.rsi, updown_series, length=self.lenupdown)
        
        # Calculate ROC and percent rank
        roc_series = self.I(lambda x: x.pct_change(periods=1) * 100, close)
        
        def percentrank_func(roc_vals):
            percentrank_vals = []
            for i in range(len(roc_vals)):
                if i < self.lenroc - 1:
                    percentrank_vals.append(50)
                else:
                    window = roc_vals[i - self.lenroc + 1:i + 1]
                    rank = (window < window.iloc[-1]).sum() / len(window) * 100
                    percentrank_vals.append(rank)
            return pd.Series(percentrank_vals, index=roc_vals.index)
        
        self.percentrank = self.I(percentrank_func, roc_series)
        
        # Calculate Connor RSI as average of three components
        def crsi_func(rsi_vals, updownrsi_vals, percentrank_vals):
            crsi_vals = []
