import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core Momentum Oscillator parameters
    fast_len = 9
    slow_len = 21
    sig_len = 5
    mom_smooth = 3
    atr_len = 14
    
    # DI and ADX parameters
    q_len = 14
    adx_len = 14
    adx_ma_len = 5
    ignition_bars = 4
    flow_inertia = 2
    ignition_accel_thr = 0.2
    ignition_vel_thr = 0.3
    thrust_vel_thr = 0.5
    adx_surge_thr = 1.5
    adx_strong_thr = 20.0
    di_spread_min_thr = 10.0
    
    # Regime detection parameters
    er_len = 10
    er_smooth = 5
    trend_thr = 0.4
    dz_mult = 0.5
    choppy_er = 0.30
    choppy_adx = 18.0
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR for normalization
        atr = self.I(lambda x, y, z, l: pta.atr(x, y, z, length=l) or pd.Series(1.0, index=x.index),
                     high, low, close, self.atr_len)
        
        # Zero-Lag EMA function
        def zlema(src, length):
            lag = max(0, int((length - 1) / 2))
            src_adj = src + (src - src.shift(lag).fillna(src))
            return pta.ema(src_adj, length=length)
        
        # Fast and slow ZLEMA
        fast_line = self.I(lambda x, l: zlema(x, l), close, self.fast_len)
        slow_line = self.I(lambda x, l: zlema(x, l), close, self.slow_len)
        
        # Raw momentum normalized by ATR
        def calc_mom(fl, sl, a):
            safe_atr = np.maximum(a, 0.001)
            return ((fl - sl) / safe_atr) * 100.0
        
        mom_raw = self.I(lambda fl, sl, a: calc_mom(fl, sl, a), fast_line, slow_line, atr)
        
        # Smooth momentum and signal
        self.mom = self.I(lambda x, l: pta.ema(x, length=l) or x, mom_raw, self.mom_smooth)
        self.sig = self.I(lambda x, l: pta.ema(x, length=l) or x, self.mom, self.sig_len)
        
        # Efficiency Ratio for regime detection
        def calc_er(c, l):
            price_dir = np.abs(c - c.shift(l))
            price_vol = np.abs(c - c.shift(1)).rolling(l).sum()
            price_vol = np.maximum(price_vol, 0.001)
            er_raw = price_dir / price_vol
            return pta.ema(er_raw, length=self.er_smooth)
        
        self.er = self.I(lambda c, l: calc_er(c, l), close, self.er_len)
        
        # Dead zone based on momentum stdev
        def calc_dead_zone(m):
            return np.maximum(m.rolling(50).std() * self.dz_mult, 0.5)
        
        self.dead_zone = self.I(lambda m: calc_dead_zone(m), self.mom)
        
        # DI calculation using Gaussian decay
        def calc_di(h, l, c):
            sum_plus = np.zeros(len(h))
            sum_minus = np.zeros(len(h))
            sum_tr = np.zeros(len(h))
            
            for i in range(len(h)):
                for k in range(min(self.q_len, i + 1)):
                    w = np.exp(-(k / self.q_len) ** 2)
                    hi_curr = h.iloc[i - k] if i - k >= 0 else h.iloc[0]
                    hi_prev = h.iloc[i - k - 1] if i - k - 1 >= 0 else hi_curr
                    lo_curr = l.iloc[i - k] if i - k >= 0 else l.iloc[0]
                    lo_prev = l.iloc[i - k - 1] if i - k - 1 >= 0 else lo_curr
                    
                    up_move = max(hi_curr - hi_prev, 0)
                    down_move = max(lo_prev - lo_curr, 0)
                    tr_val = max(hi_curr - lo_curr, hi_curr - hi_prev, lo_curr - lo_prev)
                    
                    sum_plus[i] += (up_move if up_move > down_move else 0) * w
                    sum_minus[i] += (down_move if down_move > up_move else 0) * w
                    sum_tr[i] += tr_val * w
            
            sum_tr = np.maximum(sum_tr, 0.001)
            plus_di = 100.0 * sum_plus / sum_tr
            minus_di = 100.0 * sum_minus / sum_tr
            
            return pd.Series(plus_di, index=h.index), pd.Series(minus_di, index=h.index)
        
        self.plus_di, self.minus_di = self.I(lambda h, l, c: calc_di(h, l, c), high, low, close)
        
        # DX and ADX
        def calc_adx(pdi, mdi):
            sum_di = pdi + mdi
            sum_di = np.maximum(sum_di, 0.001)
            dx = np.abs(pdi - mdi) / sum_di * 100.0
            
            # ZLEMA smoothing
            lag = max(0, int((self.adx_len - 1) / 2))
            dx_adj = dx + (dx - dx.shift(lag).fillna(dx))
            adx = pta.ema(dx_adj, length=self.adx_len)
            
            return adx
        
        self.adx = self.I(lambda pdi, mdi: calc_adx(pdi, mdi), self.plus_di, self.minus_di)
        self.adx_ma = self.I(lambda x, l: pta.ema(x, length=l) or x, self.adx, self.adx_ma_len)
        
        # DI spread and velocities
        def calc_spread_dynamics(pdi, mdi):
            di_spread = np.abs(pdi - mdi)
            spread_vel = di_spread - di_spread.shift(1)
            spread_vel_smooth = pta.ema(spread_vel.fillna(0), length=3)
            spread_accel = spread_vel - spread_vel.shift(1)
            spread_accel_smooth = pta.ema(spread_accel.fillna(0), length=3)
            
            return di_spread, spread_vel_smooth, spread_accel_smooth
        
        self.di_spread, self.spread_vel, self.spread_accel = self.I(
            lambda pdi, mdi: calc_spread_dynamics(pdi, mdi),
            self.plus_di, self.minus_di
        )
        
        # Momentum derivatives
        def calc_mom_derivatives(m):
            mom_slope = m - m.shift(1).fillna(m)
            mom_curve = mom_slope - mom_slope.shift(1).fillna(mom_slope)
            return mom_slope, mom_curve
        
        self.mom_slope, self.mom_curve = self.I(lambda m: calc_mom_derivatives(m), self.mom)
        
        # Phase tracking state
        self.flow_state = 0
        self.flow_hold_cnt = 0
        self.flow_pend_tgt = 0
        self.cross_age = 999
        self.in_position = False
        self.entry_phase = None

    def next(self):
        # Current bar values
        mom_val = self.mom[-1]
        sig_val = self.sig[-1]
        adx_val = self.adx[-1]
        adx_ma_val = self.adx_ma[-1]
        er_val = self.er[-1]
        di_spread = self.di_spread[-1]
        spread_vel = self.spread_vel[-1]
        spread_accel = self.spread_accel[-1]
        plus_di = self.plus_di[-1]
        minus_di = self.minus_di[-1]
        mom_slope = self.mom_slope[-1]
        dead_zone_val = self.dead_zone[-1]
        
        # DI crossover detection
        di_cross_up = len(self.data) > 1 and self.plus_di[-2] <= self.minus_di[-2] and plus_di > minus_di
        di_cross_dn = len(self.data) > 1 and self.plus_di[-2] >= self.minus_di[-2] and plus_di < minus_di
        di_cross = di_cross_up or di_cross_dn
        
        if di_cross:
            self.cross_age = 0
        else:
            self.cross_age = min(self.cross_age + 1, 999)
        
        # ADX behavior flags
        adx_rising = len(self.data) > 1 and adx_val > self.adx[-2]
        adx_waking = len(self.data) > 2 and adx_val > self.adx[-2] and self.adx[-2] > self.adx[-3]
        adx_surging = len(self.data) > 3 and (adx_val - self.adx[-4]) > self.adx_surge_thr
        adx_strong = adx_val >= self.adx_strong_thr
        adx_falling = len(self.data) > 1 and adx_val < self.adx[-2]
        
        # Flow direction
        flow_dir = 1.0 if plus_di > minus_di else -1.0
        
        # Regime assessment
        mom_alive = abs(mom_val) > dead_zone_val
        
        # Phase detection logic
        is_ignition = (self.cross_age <= self.ignition_bars and
                      spread_accel > self.ignition_accel_thr and
                      spread_vel > self.ignition_vel_thr and
                      adx_waking)
        
        is_thrust = (self.cross_age > self.ignition_bars and
                    self.cross_age <= self.ignition_bars * 3 and
                    spread_vel > self.thrust_vel_thr and
                    adx_surging)
        
        is_prime = (adx_strong and
                   (adx_rising or adx_val > adx_ma_val) and
                   di_spread > self.di_spread_min_thr)
        
        is_fading = ((adx_strong and adx_falling and adx_val < adx_ma_val) or
                    (adx_strong and spread_vel < -0.5))
        
        # Determine desired state
        flow_desired = 0
        if is_ignition:
            flow_desired = 1
        elif is_thrust:
            flow_desired = 2
        elif is_prime:
            flow_desired = 3
        elif is_fading:
            flow_desired = 4
        
        # Apply inertia
        if flow_desired != self.flow_state:
            if flow_desired == self.flow_pend_tgt:
                self.flow_hold_cnt += 1
            else:
                self.flow_pend_tgt = flow_desired
                self.flow_hold_cnt = 1
            
            required_inertia = 1 if (flow_desired == 1 or flow_desired == 2) else self.flow_inertia
            
            if self.flow_hold_cnt >= required_inertia:
                self.flow_state = flow_desired
                self.flow_hold_cnt = 0
        else:
            self.flow_hold_cnt = 0
            self.flow_pend_tgt = self.flow_state
        
        # Trading logic: Enter on IGNITION, exit on FADING
        if self.flow_state == 1 and not self.in_position:
            # IGNITION phase: enter position
            self.buy()
            self.in_position = True
            self.entry_phase = 1
        
        elif self.flow_state == 4 and self.in_position:
            # FADING phase: exit position
            self.sell()
            self.in_position = False
            self.entry_phase = None
        
        elif self.flow_state == 0 and self.in_position:
            # DEAD phase: exit if still in position
            self.sell()
            self.in_position = False
            self.entry_phase = None