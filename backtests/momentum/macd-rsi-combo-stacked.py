        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        hlcc4 = (high + low + close + close) / 4
        
        macd_result = self.I(pta.macd, close, fast=self.fastLength, slow=self.slowLength, signal=self.signalLength)
        self.macd_line = self.I(lambda: pta.macd(close, fast=self.fastLength, slow=self.slowLength, signal=self.signalLength)['MACD_12_26_9'] if pta.macd(close, fast=self.fastLength, slow=self.slowLength, signal=self.signalLength) is not None else pd.Series(0, index=close.index))
        self.signal_line = self.I(lambda: pta.macd(close, fast=self.fastLength, slow=self.slowLength, signal=self.signalLength)['MACDh_12_26_9'] if pta.macd(close, fast=self.fastLength, slow=self.slowLength, signal=self.signalLength) is not None else pd.Series(0, index=close.index))
