import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fast = 12
    slow = 26
    signal_len = 9

    def init(self):
        close = pd.Series(self.data.Close)
        
        macd_result = self.I(lambda: pta.macd(close, fast=self.fast, slow=self.slow, signal=self.signal_len))
        
        self.macd_line = self.I(lambda: pta.macd(close, fast=self.fast, slow=self.slow, signal=self.signal_len).iloc[:, 0] if pta.macd(close, fast=self.fast, slow=self.slow, signal=self.signal_len) is not None else pd.Series(0, index=close.index))
        self.signal_line = self.I(lambda: pta.macd(close, fast=self.fast, slow=self.slow, signal=self.signal_len).iloc[:, 2] if pta.macd(close, fast=self.fast, slow=self.slow, signal=self.signal_len) is not None else pd.Series(0, index=close.index))

    def next(self):
        if len(self.data) < max(self.fast, self.slow, self.signal_len) + 5:
            return
        
        macd_val = self.macd_line[-1]
        signal_val = self.signal_line[-1]
        
        prev_macd = self.macd_line[-2] if len(self.macd_line) > 1 else macd_val
        prev_signal = self.signal_line[-2] if len(self.signal_line) > 1 else signal_val
        
        if not self.position:
            if prev_macd <= prev_signal and macd_val > signal_val and macd_val > 0:
                self.buy()
        else:
            if prev_macd >= prev_signal and macd_val < signal_val and macd_val < 0:
                self.sell()


