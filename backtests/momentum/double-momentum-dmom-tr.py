import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Length_DMOM = 36
    Length_MA_DMOM = 365
    Source_MA_DMOM = 'EMA'
    T_Factor = 0.7
    Signal_DMOM = 'DMOM MA'

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate MOM
        mom = self.I(lambda: pta.mom(close, length=self.Length_DMOM))
        
        # Calculate DMOM (double momentum)
        dmom = self.I(lambda: 2 * mom - pta.mom(mom, length=self.Length_DMOM))
        
        # Calculate MA for DMOM based on selected type
        def calc_dmom_ma():
            if self.Source_MA_DMOM == 'EMA':
                return pta.ema(dmom, length=self.Length_MA_DMOM)
            elif self.Source_MA_DMOM == 'SMA':
                return pta.sma(dmom, length=self.Length_MA_DMOM)
            elif self.Source_MA_DMOM == 'RMA':
                return pta.rma(dmom, length=self.Length_MA_DMOM)
            elif self.Source_MA_DMOM == 'WMA':
                return pta.wma(dmom, length=self.Length_MA_DMOM)
            elif self.Source_MA_DMOM == 'VWMA':
                volume = pd.Series(self.data.Volume)
                return pta.vwma(dmom, volume, length=self.Length_MA_DMOM)
            elif self.Source_MA_DMOM == 'HMA':
                return pta.hma(dmom, length=self.Length_MA_DMOM)
            elif self.Source_MA_DMOM == 'DEMA':
                return pta.dema(dmom, length=self.Length_MA_DMOM)
            elif self.Source_MA_DMOM == 'TEMA':
                return pta.tema(dmom, length=self.Length_MA_DMOM)
            else:
                return pta.ema(dmom, length=self.Length_MA_DMOM)
        
        dmom_ma = self.I(calc_dmom_ma)
        
        # Determine entry signal
        entry_signal = dmom_ma if self.Signal_DMOM == 'DMOM MA' else self.I(lambda: pd.Series(0, index=close.index))
        
        self.dmom = dmom
        self.entry_signal = entry_signal

    def next(self):
        if len(self.data) < max(self.Length_DMOM, self.Length_MA_DMOM) + 10:
            return
        
        dmom_val = self.dmom[-1]
        signal_val = self.entry_signal[-1]
        
        if np.isnan(dmom_val) or np.isnan(signal_val):
            return
        
        # Bullish crossover: DMOM crosses above entry signal
        if crossover(self.dmom, self.entry_signal):
            if not self.position:
                self.buy()
        
        # Bearish crossover: DMOM crosses below entry signal
        elif crossover(self.entry_signal, self.dmom):
            if self.position:
                self.position.close()