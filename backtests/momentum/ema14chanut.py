import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaPeriod = 14

    def init(self):
        close = pd.Series(self.data.Close)
        self.ema = self.I(pta.ema, close, length=self.emaPeriod)

    def next(self):
        if len(self.data) < self.emaPeriod + 1:
            return
        
        current_close = self.data.Close[-1]
        current_ema = self.ema[-1]
        
        if current_close is None or current_ema is None:
            return
        
        if len(self.ema) < 2:
            return
        
        prev_close = self.data.Close[-2]
        prev_ema = self.ema[-2]
        
        if prev_close <= prev_ema and current_close > current_ema:
            if not self.position:
                self.buy()
        elif prev_close >= prev_ema and current_close < current_ema:
            if self.position:
                self.position.close()


