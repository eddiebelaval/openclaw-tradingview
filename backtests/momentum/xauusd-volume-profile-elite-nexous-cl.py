from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    alert_level = 60

    def init(self):
        self.buy_pct_history = []
        self.signal_history = []

    def next(self):
        if len(self.data) < 2:
            return

        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]

        p_range = max(high - low, 0.01)
        buy_pct = (close - low) / p_range
        buy_vol = volume * buy_pct
        sell_vol = volume * (1 - buy_pct)

        curr_delta = buy_vol - sell_vol
        curr_buy_pct = (buy_vol / max(buy_vol + sell_vol, 1)) * 100

        signal = "WAIT"
        if curr_delta > 0 and curr_buy_pct > self.alert_level:
            signal = "STRONG BUY"
        elif curr_delta < 0 and (100 - curr_buy_pct) > self.alert_level:
            signal = "STRONG SELL"

        self.signal_history.append(signal)

        if len(self.signal_history) >= 2:
            prev_signal = self.signal_history[-2]
            curr_signal = self.signal_history[-1]

            if prev_signal != "STRONG BUY" and curr_signal == "STRONG BUY":
                if not self.position:
                    self.buy()
            elif prev_signal != "STRONG SELL" and curr_signal == "STRONG SELL":
                if self.position:
                    self.position.close()


