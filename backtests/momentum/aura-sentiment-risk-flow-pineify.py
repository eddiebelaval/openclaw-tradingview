import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    smoothLen = 3
    atrLen = 22
    atrMult = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # 1. Sentiment Calculation (Normalized Momentum)
        rawRSI = self.I(pta.rsi, close, length=self.rsiLen)
        sentimentOsc_raw = rawRSI - 50
        self.sentimentOsc = self.I(pta.sma, sentimentOsc_raw, length=self.smoothLen)

        # 2. Risk Calculation (Chandelier Exit Logic)
        atrValue = self.I(pta.atr, high, low, close, length=self.atrLen)

        # Highest High and Lowest Low
        self.highestHigh = self.I(lambda: high.rolling(window=self.atrLen).max())
        self.lowestLow = self.I(lambda: low.rolling(window=self.atrLen).min())

        # Calculate Chandelier Exits
        self.chandLong = self.I(lambda: self.highestHigh - atrValue * self.atrMult)
        self.chandShort = self.I(lambda: self.lowestLow + atrValue * self.atrMult)

    def next(self):
        # Crossover Detection
        if len(self.sentimentOsc) < 2:
            return

        sentiment_current = self.sentimentOsc[-1]
        sentiment_prev = self.sentimentOsc[-2]

        # Buy Signal: Sentiment crosses above 0
        if sentiment_prev <= 0 and sentiment_current > 0:
            self.buy()

        # Sell Signal: Sentiment crosses below 0
        elif sentiment_prev >= 0 and sentiment_current < 0:
            self.sell()


