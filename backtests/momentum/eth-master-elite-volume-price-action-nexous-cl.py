import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    shark_mult = 2.0
    avg_length = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.avg_volume = self.I(lambda: pta.sma(volume, length=self.avg_length))
        
        self.pivot_high = self.I(self._calc_pivot_high, high, low, close)
        self.pivot_low = self.I(self._calc_pivot_low, high, low, close)
        
        self.buy_vol = self.I(self._calc_buy_vol, high, low, close, volume)
        self.sell_vol = self.I(self._calc_sell_vol, high, low, close, volume)
        self.total_vol = self.I(lambda: self.buy_vol + self.sell_vol)
        self.delta = self.I(lambda: self.buy_vol - self.sell_vol)
        
        self.is_shark = self.I(self._is_shark_signal)
        self.signal = self.I(self._get_signal)

    def _calc_pivot_high(self, high, low, close):
        h = pd.Series(high)
        result = pd.Series(np.nan, index=h.index)
        for i in range(3, len(h) - 3):
            if h.iloc[i] > h.iloc[i-3:i].max() and h.iloc[i] > h.iloc[i+1:i+4].max():
                result.iloc[i] = h.iloc[i]
        return result

    def _calc_pivot_low(self, high, low, close):
        l = pd.Series(low)
        result = pd.Series(np.nan, index=l.index)
        for i in range(3, len(l) - 3):
            if l.iloc[i] < l.iloc[i-3:i].min() and l.iloc[i] < l.iloc[i+1:i+4].min():
                result.iloc[i] = l.iloc[i]
        return result

    def _calc_buy_vol(self, high, low, close):
        h = pd.Series(high)
        l = pd.Series(low)
        c = pd.Series(close)
        v = pd.Series(self.data.Volume)
        
        buy_vol = pd.Series(0.0, index=h.index)
        for i in range(len(h)):
            p_range = max(h.iloc[i] - l.iloc[i], 1e-8)
            p = (c.iloc[i] - l.iloc[i]) / p_range
            buy_vol.iloc[i] = v.iloc[i] * p
        return buy_vol

    def _calc_sell_vol(self, high, low, close):
        h = pd.Series(high)
        l = pd.Series(low)
        c = pd.Series(close)
        v = pd.Series(self.data.Volume)
        
        sell_vol = pd.Series(0.0, index=h.index)
        for i in range(len(h)):
            p_range = max(h.iloc[i] - l.iloc[i], 1e-8)
            p = (c.iloc[i] - l.iloc[i]) / p_range
            sell_vol.iloc[i] = v.iloc[i] * (1 - p)
        return sell_vol

    def _is_shark_signal(self):
        if len(self.data) < self.avg_length:
            return pd.Series(False, index=pd.RangeIndex(len(self.data)))
        
        result = pd.Series(False, index=pd.RangeIndex(len(self.data)))
        for i in range(len(self.data)):
            if self.avg_volume[i] is not None and self.total_vol[i] is not None:
                result.iloc[i] = self.total_vol[i] >= (self.avg_volume[i] * self.shark_mult)
        return result

    def _get_signal(self):
        if len(self.data) < 1:
            return pd.Series("WAIT", index=pd.RangeIndex(len(self.data)))
        
        result = pd.Series("WAIT", index=pd.RangeIndex(len(self.data)))
        for i in range(len(self.data)):
            if self.is_shark[i] and self.delta[i] > 0:
                result.iloc[i] = "BUY"
            else:
                result.iloc[i] = "WAIT"
        return result

    def next(self):
        if len(self) < 2:
            return
        
        current_signal = self.signal[-1]
        current_shark = self.is_shark[-1]
        current_delta = self.delta[-1]
        
        if not self.position:
            if current_signal == "BUY":
                self.buy()
        else:
            if not current_shark or current_delta <= 0:
                self.sell()