import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # SuperTrend Inputs
    factor = 3.0
    sellFactor = 2.4
    atrLen = 10
    
    # Volume Inputs
    volLen = 20
    volMult = 1.5
    
    # EMA & RSI Inputs
    emaLen = 200
    rsiLen = 14
    rsiMax = 65.0
    
    # Trailing Stop Input
    trailPct = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Calculate SuperTrend (main)
        hl2 = (high + low) / 2
        self.basic_ub_main = hl2 + self.factor * self.atr
        self.basic_lb_main = hl2 - self.factor * self.atr
        
        # Calculate SuperTrend (sell)
        self.basic_ub_sell = hl2 + self.sellFactor * self.atr
        self.basic_lb_sell = hl2 - self.sellFactor * self.atr
        
        # Volume calculations
        self.avgVol = self.I(pta.sma, volume, length=self.volLen)
        
        # EMA and RSI
        self.ema200 = self.I(pta.ema, close, length=self.emaLen)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        # State variables
        self.trailStop = None
        self.inTrade = False

    def _calculate_supertrend_direction(self, close, ub, lb):
        """Calculate supertrend direction: -1 for green (uptrend), 1 for red (downtrend)"""
        direction = np.zeros(len(close))
        
        for i in range(1, len(close)):
            if i == 0:
                direction[i] = 1
                continue
                
            if close.iloc[i] <= ub.iloc[i]:
                direction[i] = 1
            elif close.iloc[i] >= lb.iloc[i]:
                direction[i] = -1
            else:
                direction[i] = direction[i-1]
        
        return direction

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        # Current bar index
        idx = len(self.data) - 1
        
        if idx < max(self.atrLen, self.emaLen, self.rsiLen):
            return
        
        # Get current values
        atr_val = self.atr[-1]
        hl2 = (high + low) / 2
        
        # Main SuperTrend values
        basic_ub_main = hl2 + self.factor * atr_val
        basic_lb_main = hl2 - self.factor * atr_val
        
        # Sell SuperTrend values
        basic_ub_sell = hl2 + self.sellFactor * atr_val
        basic_lb_sell = hl2 - self.sellFactor * atr_val
        
        # Calculate directions for current and previous bar
        close_series = pd.Series(self.data.Close)
        ub_main_series = pd.Series([basic_ub_main] * len(close_series))
        lb_main_series = pd.Series([basic_lb_main] * len(close_series))
        ub_sell_series = pd.Series([basic_ub_sell] * len(close_series))
        lb_sell_series = pd.Series([basic_lb_sell] * len(close_series))
        
        # Simplified direction: -1 if close > basic_lb (uptrend), 1 if close <= basic_ub (downtrend)
        dir_main = -1 if close > basic_lb_main else 1
        dir_sell = -1 if close > basic_lb_sell else 1
        
        # Get previous direction (from previous bar)
        if idx > 0:
            prev_close = self.data.Close[-2]
            prev_high = self.data.High[-2]
            prev_low = self.data.Low[-2]
            prev_hl2 = (prev_high + prev_low) / 2
            prev_atr = self.atr[-2]
            
            prev_basic_lb_main = prev_hl2 - self.factor * prev_atr
            prev_basic_lb_sell = prev_hl2 - self.sellFactor * prev_atr
            
            prev_dir_main = -1 if prev_close > prev_basic_lb_main else 1
            prev_dir_sell = -1 if prev_close > prev_basic_lb_sell else 1
        else:
            prev_dir_main = dir_main
            prev_dir_sell = dir_sell
        
        # Volume condition
        avgVol_val = self.avgVol[-1]
        volCondition = volume > (avgVol_val * self.volMult)
        
        # EMA condition (bullish trend)
        ema200_val = self.ema200[-1]
        emaBullCondition = close > ema200_val
        
        # RSI condition (not overbought)
        rsi_val = self.rsi[-1]
        rsiCondition = rsi_val < self.rsiMax
        
        # Buy Signal: Supertrend turns green (dir -1, prev dir 1) + conditions
        rawBuy = (dir_main == -1) and (prev_dir_main == 1)
        buySignal = rawBuy and volCondition and emaBullCondition and rsiCondition
        
        # Enter trade
        if buySignal and not self.inTrade:
            self.inTrade = True
            self.trailStop = close * (1 - (self.trailPct / 100))
            self.buy()
        
        # Manage existing trade
        if self.inTrade:
            # Update trailing stop (move up, never down)
            new_trail = close * (1 - (self.trailPct / 100))
            if self.trailStop is not None:
                self.trailStop = max(self.trailStop, new_trail)
            else:
                self.trailStop = new_trail
            
            # Exit condition A: Hit trailing stop loss
            hitStop = close < self.trailStop
            
            # Exit condition B: Early sell signal from sell supertrend
            rawSell = (dir_sell == 1) and (prev_dir_sell == -1)
            earlySell = rawSell and volCondition
            
            # Exit the trade
            if hitStop or earlySell:
                self.inTrade = False
                self.trailStop = None
                self.sell()