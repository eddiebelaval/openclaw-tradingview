import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MACD Parameters
    fastLength = 12
    slowLength = 26
    signalLength = 9
    
    # ATR Filter
    useATR = True
    atrLength = 14
    atrMultiplier = 1.0
    
    # Zero Line Filter
    useZeroFilter = False
    
    # Trend Filter
    useTrendFilter = False
    trendLength = 200
    
    # Histogram MA
    useHistMA = True
    histMALength = 9
    histMAType = "EMA"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate MACD components
        fastEMA = self.I(pta.ema, close, length=self.fastLength)
        slowEMA = self.I(pta.ema, close, length=self.slowLength)
        
        self.macdLine = self.I(lambda: fastEMA - slowEMA)
        self.signalLine = self.I(pta.ema, self.macdLine, length=self.signalLength)
        self.hist = self.I(lambda: self.macdLine - self.signalLine)
        
        # Histogram MA
        if self.histMAType == "EMA":
            self.histMA = self.I(pta.ema, self.hist, length=self.histMALength)
        elif self.histMAType == "SMA":
            self.histMA = self.I(pta.sma, self.hist, length=self.histMALength)
        elif self.histMAType == "WMA":
            self.histMA = self.I(pta.wma, self.hist, length=self.histMALength)
        else:  # RMA
            self.histMA = self.I(pta.ema, self.hist, length=self.histMALength)
        
        # Trend EMA
        self.trendEMA = self.I(pta.ema, close, length=self.trendLength)
        
        # ATR Filter
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        self.atrSMA = self.I(pta.sma, self.atr, length=self.atrLength)
        
    def next(self):
        if len(self.data) < max(self.slowLength, self.trendLength, self.histMALength) + 5:
            return
        
