        trendEMA = self.trendEMA[-1]
        atr = self.atr[-1]
        atrSMA = self.atrSMA[-1]
        
        # Crossover detection
        bullCross = crossover(self.macdLine, self.signalLine)
        bearCross = crossover(self.signalLine, self.macdLine)
        
        # Filters
        zeroBull = not self.useZeroFilter or macdLine > 0
        zeroBear = not self.useZeroFilter or macdLine < 0
        
        trendBull = not self.useTrendFilter or close > trendEMA
        trendBear = not self.useTrendFilter or close < trendEMA
        
        atrOk = not self.useATR or (atr > atrSMA * self.atrMultiplier)
        
        # Valid signals
        validBull = bullCross and zeroBull and trendBull and atrOk
        validBear = bearCross and zeroBear and trendBear and atrOk
        
        # Trading logic
        if validBull:
            if self.position:
                self.position.close()
            self.buy()
        elif validBear:
            if self.position:
                self.position.close()


