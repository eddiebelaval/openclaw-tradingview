import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    div_level = 120.0
    persist_bars = 3
    share_strong = 0.70
    share_weak = 0.40
    mag_trend_level = 0.30
    div_candles = 6
    div_amplitude = 0.40
    
    # MAG7 weights
    w_aapl = 0.095
    w_msft = 0.095
    w_nvda = 0.085
    w_amzn = 0.065
    w_meta = 0.055
    w_googl = 0.045
    w_tsla = 0.035

    def init(self):
        # Calculate divergence/breadth metrics
        close_series = pd.Series(self.data.Close)
        high_series = pd.Series(self.data.High)
        low_series = pd.Series(self.data.Low)
        volume_series = pd.Series(self.data.Volume)
        
        # Calculate HLC3 for VWAP
        hlc3 = (high_series + low_series + close_series) / 3
        
        # Daily VWAP calculation
        def calc_vwap():
            cumvol = np.zeros(len(close_series))
            cumpv = np.zeros(len(close_series))
            cumvol[0] = volume_series.iloc[0]
            cumpv[0] = hlc3.iloc[0] * volume_series.iloc[0]
            
            for i in range(1, len(close_series)):
                cumvol[i] = cumvol[i-1] + volume_series.iloc[i]
                cumpv[i] = cumpv[i-1] + hlc3.iloc[i] * volume_series.iloc[i]
            
            vwap = np.where(cumvol != 0, cumpv / cumvol, np.nan)
            return pd.Series(vwap, index=close_series.index)
        
        self.vwap = self.I(calc_vwap)
        
        # Simple divergence: difference between price momentum
        def calc_divergence():
            div = np.zeros(len(close_series))
            for i in range(len(close_series)):
                if i < self.div_candles:
                    div[i] = 0
                else:
                    bullish_amp = 0.0
                    bearish_amp = 0.0
                    
                    for j in range(i - self.div_candles + 1, i + 1):
                        open_price = self.data.Open[j]
                        close_price = self.data.Close[j]
                        
                        if close_price > open_price:
                            bullish_amp += (close_price - open_price) / open_price * 100
                        elif close_price < open_price:
                            bearish_amp += (open_price - close_price) / open_price * 100
                    
                    net_amplitude = bullish_amp - bearish_amp
                    div[i] = net_amplitude
            
            return pd.Series(div, index=close_series.index)
        
        self.divergence = self.I(calc_divergence)
        
        # Calculate divergence MA
        div_series = pd.Series(self.divergence)
        self.divergence_ma = self.I(pta.sma, div_series, length=20)
        
        # Track position state
        self.last_div = 0

    def next(self):
        # Get current divergence value
        current_div = self.divergence[-1] if len(self.divergence) > 0 else 0
        current_vwap = self.vwap[-1] if len(self.vwap) > 0 else self.data.Close[-1]
        current_price = self.data.Close[-1]
        
        # Trading logic based on divergence and VWAP
        # Buy signal: divergence crosses above negative threshold and price above VWAP
        if len(self.divergence) > 1:
            prev_div = self.divergence[-2]
            
            # Buy: divergence turning positive (accumulation signal) and above VWAP
            if prev_div < -self.div_amplitude and current_div > -self.div_amplitude:
                if current_price > current_vwap:
                    if not self.position:
                        self.buy()
            
            # Sell: divergence turning negative (absorption signal) and below VWAP
            elif prev_div > self.div_amplitude and current_div < self.div_amplitude:
                if current_price < current_vwap:
                    if self.position:
                        self.position.close()
            
            # Exit on divergence reversal
            elif current_div < -self.div_level and self.position:
                self.position.close()
            elif current_div > self.div_level and self.position:
                self.position.close()


