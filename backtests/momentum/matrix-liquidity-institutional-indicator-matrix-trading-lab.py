import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_len = 20
    eqThresholdATR = 0.10
    sweep_confirm_mode = "Wick Reclaim"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Calculate pivot points
        self.swingPH = self.I(self._pivot_high, high, self.swing_len)
        self.swingPL = self.I(self._pivot_low, low, self.swing_len)
        
        # State variables
        self.lastSwingHigh = np.nan
        self.lastSwingLow = np.nan
        self.prevSwingHigh = np.nan
        self.prevSwingLow = np.nan
        self.lastSwingHighBar = np.nan
        self.lastSwingLowBar = np.nan
        self.prevSwingHighBar = np.nan
        self.prevSwingLowBar = np.nan
        
        self.activeEQH = np.nan
        self.activeEQL = np.nan
        self.activeEQHSwept = False
        self.activeEQLSwept = False
        
        self.trailingTop = np.nan
        self.trailingBottom = np.nan
        
        self.bias = 0  # 0=NEUTRAL, 1=BULL, -1=BEAR
        
    def _pivot_high(self, high, length):
        """Calculate pivot high"""
        result = pd.Series(np.nan, index=high.index)
        for i in range(length, len(high) - length):
            if high.iloc[i] == high.iloc[i-length:i+length].max():
                result.iloc[i] = high.iloc[i]
        return result
    
    def _pivot_low(self, low, length):
        """Calculate pivot low"""
        result = pd.Series(np.nan, index=low.index)
        for i in range(length, len(low) - length):
            if low.iloc[i] == low.iloc[i-length:i+length].min():
                result.iloc[i] = low.iloc[i]
        return result

    def next(self):
        idx = len(self.data) - 1
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        
        # Process swing highs
        if not np.isnan(self.swingPH[-1]):
            self.prevSwingHigh = self.lastSwingHigh
            self.prevSwingHighBar = self.lastSwingHighBar
            self.lastSwingHigh = self.swingPH[-1]
            self.lastSwingHighBar = idx - self.swing_len
            
            if np.isnan(self.trailingTop) or self.lastSwingHigh >= self.trailingTop:
                self.trailingTop = self.lastSwingHigh
            
            # Detect equal highs
            if not np.isnan(self.prevSwingHigh):
                if abs(self.lastSwingHigh - self.prevSwingHigh) <= current_atr * self.eqThresholdATR:
                    self.activeEQH = max(self.lastSwingHigh, self.prevSwingHigh)
                    self.activeEQHSwept = False
        
        # Process swing lows
        if not np.isnan(self.swingPL[-1]):
            self.prevSwingLow = self.lastSwingLow
            self.prevSwingLowBar = self.lastSwingLowBar
            self.lastSwingLow = self.swingPL[-1]
            self.lastSwingLowBar = idx - self.swing_len
            
            if np.isnan(self.trailingBottom) or self.lastSwingLow <= self.trailingBottom:
                self.trailingBottom = self.lastSwingLow
            
            # Detect equal lows
            if not np.isnan(self.prevSwingLow):
                if abs(self.lastSwingLow - self.prevSwingLow) <= current_atr * self.eqThresholdATR:
                    self.activeEQL = min(self.lastSwingLow, self.prevSwingLow)
                    self.activeEQLSwept = False
        
        # Update bias
        if not np.isnan(self.lastSwingHigh) and current_close > self.lastSwingHigh:
            self.bias = 1  # BULL
        if not np.isnan(self.lastSwingLow) and current_close < self.lastSwingLow:
            self.bias = -1  # BEAR
        
        # Sweep detection - buy side (EQH)
        if not np.isnan(self.activeEQH) and not self.activeEQHSwept:
            if self.sweep_confirm_mode == "Wick Reclaim":
                if current_high > self.activeEQH and current_close < self.activeEQH:
                    self.activeEQHSwept = True
                    if not self.position:
                        self.buy()
            else:  # Close Back Inside
                if current_high > self.activeEQH and current_close <= self.activeEQH:
                    self.activeEQHSwept = True
                    if not self.position:
                        self.buy()
        
        # Sweep detection - sell side (EQL)
        if not np.isnan(self.activeEQL) and not self.activeEQLSwept:
            if self.sweep_confirm_mode == "Wick Reclaim":
                if current_low < self.activeEQL and current_close > self.activeEQL:
                    self.activeEQLSwept = True
                    if self.position:
                        self.sell()
            else:  # Close Back Inside
                if current_low < self.activeEQL and current_close >= self.activeEQL:
                    self.activeEQLSwept = True
                    if self.position:
                        self.sell()
        
        # Zone-based trading
        if not np.isnan(self.trailingTop) and not np.isnan(self.trailingBottom):
            if self.trailingTop > self.trailingBottom:
                zone_range = self.trailingTop - self.trailingBottom
                premium_threshold = self.trailingTop - zone_range * 0.25
                discount_threshold = self.trailingBottom + zone_range * 0.25
                
                # Sell in premium zone
                if current_close >= premium_threshold and self.position:
                    self.sell()
                
                # Buy in discount zone
                if current_close <= discount_threshold and not self.position:
                    self.buy()


