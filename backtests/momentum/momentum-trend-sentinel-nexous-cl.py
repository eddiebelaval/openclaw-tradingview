class TvStrategy(Strategy):
    atrPeriod = 14
    mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)
        
        # Store close for reference
        self.close_data = close
        self.high_data = high
        self.low_data = low
        
        # Initialize trend tracking variables
        self.trendStop = 0.0
        self.trendDir = 0
        self.prev_trendDir = 0

    def next(self):
        if len(self.data) < self.atrPeriod + 1:
            return
        
        # Get current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_atr = self.atr[-1]
        
        if current_atr is None or np.isnan(current_atr):
            return
        
        # Calculate bands
        upperBand = current_close + (current_atr * self.mult)
        lowerBand = current_close - (current_atr * self.mult)
        
        # Update trend direction and stop
        if len(self) == 1 or self.trendDir == 0:
            # Initial setup
            self.trendDir = 1
            self.trendStop = lowerBand
        else:
            # Check for crossover/crossunder
            prev_close = self.data.Close[-2] if len(self.data) > 1 else current_close
            
            if current_close > self.trendStop and prev_close <= self.trendStop:
                # Crossover
                self.prev_trendDir = self.trendDir
                self.trendDir = 1
                self.trendStop = lowerBand
            elif current_close < self.trendStop and prev_close >= self.trendStop:
                # Crossunder
                self.prev_trendDir = self.trendDir
                self.trendDir = -1
                self.trendStop = upperBand
            else:
                # Update trailing stop
                if self.trendDir == 1:
                    self.trendStop = max(lowerBand, self.trendStop)
                else:
                    self.trendStop = min(upperBand, self.trendStop)
        
        # Generate signals
        longSignal = self.trendDir == 1 and self.prev_trendDir == -1
        shortSignal = self.trendDir == -1 and self.prev_trendDir == 1
        
        # Trading logic
        if longSignal:
            if not self.position:
                self.buy()
        elif shortSignal:
            if self.position:
                self.position.close()


