import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Pressure Settings
    i_pressure_len = 14
    i_smooth_len = 5
    i_momentum_len = 10
    
    # Thresholds
    i_extreme_high = 0.7
    i_extreme_low = 0.3
    i_momentum_thresh = 0.05
    
    # WaveTrend Integration
    i_use_wt = True
    i_wt_channel = 9
    i_wt_avg = 12

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Raw buying/selling pressure
        def calc_raw_pressure():
            range_val = high - low
            buy_pressure = np.where(range_val > 0, (close - low) / range_val, 0.5)
            return pd.Series(buy_pressure, index=close.index)
        
        raw_buy = self.I(calc_raw_pressure)
        
        # Smoothed pressure ratio
        pressure_ratio = self.I(pta.ema, raw_buy, length=self.i_pressure_len)
        self.pressure_smooth = self.I(pta.ema, pressure_ratio, length=self.i_smooth_len)
        
        # Pressure momentum
        def calc_momentum():
            result = self.pressure_smooth
            if len(result) > self.i_momentum_len:
                return pd.Series(
                    [result.iloc[i] - result.iloc[max(0, i - self.i_momentum_len)] 
                     for i in range(len(result))],
                    index=result.index
                )
            return pd.Series(0.0, index=result.index)
        
        self.pressure_momentum = self.I(calc_momentum)
        
        # Volume analysis
        vol_sma = self.I(pta.sma, volume, length=self.i_pressure_len)
        
        def calc_vol_ratio():
            ratio = np.where(vol_sma > 0, volume / vol_sma, 1.0)
            return pd.Series(ratio, index=volume.index)
        
        vol_ratio = self.I(calc_vol_ratio)
        
        # Volume weight (capped at 3x)
        def calc_vol_weight():
            w = np.minimum(vol_ratio, 3.0) / 3.0
            return pd.Series(w, index=volume.index)
        
        vol_weight = self.I(calc_vol_weight)
        
        # Volume-weighted pressure
        def calc_vw_pressure():
            return pd.Series(
                self.pressure_smooth * (0.7 + vol_weight * 0.3),
                index=close.index
            )
        
        self.vw_pressure = self.I(calc_vw_pressure)
        
        # WaveTrend Oscillator
        def calc_wavetrend():
            ap = (high + low + close) / 3.0
            esa = pta.ema(ap, length=self.i_wt_channel)
            d = pta.ema(np.abs(ap - esa), length=self.i_wt_channel)
            ci = np.where(d > 0, (ap - esa) / (0.015 * d), 0.0)
            wt1_local = pta.ema(pd.Series(ci, index=close.index), length=self.i_wt_avg)
            wt2_local = pta.sma(wt1_local, length=4)
            return pd.DataFrame({
                'wt1': wt1_local,
                'wt2': wt2_local
            })
        
        if self.i_use_wt:
            wt_data = self.I(calc_wavetrend)
            self.wt1 = wt_data['wt1']
            self.wt2 = wt_data['wt2']
        else:
            self.wt1 = pd.Series(0.0, index=close.index)
            self.wt2 = pd.Series(0.0, index=close.index)
        
        # Energy calculation
        atr_14 = self.I(pta.atr, high, low, close, length=14)
        
        def calc_energy():
            vol_energy = np.where(vol_sma > 0, (volume - vol_sma) / vol_sma * 100, 0)
            price_energy = np.where(atr_14 > 0, (close - pd.Series(self.data.Open)) / atr_14 * 100, 0)
            combined = (self.pressure_momentum * 100 + vol_energy * 0.3 + price_energy * 0.2) / 1.5
            return pd.Series(combined, index=close.index)
        
        combined_energy = self.I(calc_energy)
        self.energy_smooth = self.I(pta.ema, combined_energy, length=5)
        
        # Price direction for divergence
        def calc_price_change():
            return pd.Series(
                [close.iloc[i] - close.iloc[max(0, i - self.i_momentum_len)] 
                 for i in range(len(close))],
                index=close.index
            )
        
        price_change = self.I(calc_price_change)
        
        # Composite score
        def calc_adjusted_score():
            composite = (self.pressure_smooth - 0.5) * 200
            momentum_adjustment = self.pressure_momentum * 100
            adjusted = composite + momentum_adjustment * 0.3
            adjusted = np.clip(adjusted, -100, 100)
            
            if self.i_use_wt:
                wt_contribution = (self.wt1 - self.wt2) * 0.5
                adjusted = np.clip(adjusted + wt_contribution, -100, 100)
            
            return pd.Series(adjusted, index=close.index)
        
        self.adjusted_score = self.I(calc_adjusted_score)
        
        # Confluence calculation
        def calc_confluence():
            pressure_state = np.where(self.pressure_smooth >= self.i_extreme_high, 2,
                                     np.where(self.pressure_smooth > 0.5 + self.i_momentum_thresh, 1,
                                             np.where(self.pressure_smooth <= self.i_extreme_low, -2,
                                                     np.where(self.pressure_smooth < 0.5 - self.i_momentum_thresh, -1, 0))))
            
            momentum_state = np.where(self.pressure_momentum > self.i_momentum_thresh / 2, 1,
                                     np.where(self.pressure_momentum < -self.i_momentum_thresh / 2, -1, 0))
            
            bull_count = np.where(pressure_state >= 1, 1, 0)
            bull_count += np.where(momentum_state == 1, 1, 0)
            bull_count += np.where(self.i_use_wt & (self.wt1 > self.wt2), 1, 0)
            bull_count += np.where(self.energy_smooth > 10, 1, 0)
            
            return pd.Series(bull_count, index=close.index)
        
        self.confluence_bull = self.I(calc_confluence)
        
        # Divergence detection
        def calc_divergence():
            price_dir = np.where(price_change > 0, 1,
                               np.where(price_change < 0, -1, 0))
            pressure_dir = np.where(self.pressure_momentum > self.i_momentum_thresh, 1,
                                   np.where(self.pressure_momentum < -self.i_momentum_thresh, -1, 0))
            
            bullish_div = (price_dir == -1) & (pressure_dir == 1)
            bearish_div = (price_dir == 1) & (pressure_dir == -1)
            
            return pd.Series(np.where(bullish_div, 1, np.where(bearish_div, -1, 0)), index=close.index)
        
        self.divergence = self.I(calc_divergence)

    def next(self):
        # Extract current values
        score = self.adjusted_score[-1] if len(self.adjusted_score) > 0 else 0
        pressure_smooth = self.pressure_smooth[-1] if len(self.pressure_smooth) > 0 else 0.5
        momentum = self.pressure_momentum[-1] if len(self.pressure_momentum) > 0 else 0
        confluence = self.confluence_bull[-1] if len(self.confluence_bull) > 0 else 0
        divergence = self.divergence[-1] if len(self.divergence) > 0 else 0
        
        # Determine pressure state
        if pressure_smooth >= self.i_extreme_high:
            pressure_state = 2
        elif pressure_smooth > 0.5 + self.i_momentum_thresh:
            pressure_state = 1
        elif pressure_smooth <= self.i_extreme_low:
            pressure_state = -2
        elif pressure_smooth < 0.5 - self.i_momentum_thresh:
            pressure_state = -1
        else:
            pressure_state = 0
        
        # Trading logic
        # Buy signals
        if not self.position:
            # Strong buying pressure
            if pressure_state >= 1 and momentum > 0 and score > 30:
                self.buy()
            # Bullish divergence with positive confluence
            elif divergence == 1 and confluence >= 2 and score > 0:
                self.buy()
        else:
            # Sell signals
            # Strong selling pressure
            if pressure_state <= -1 and momentum < 0 and score < -30:
                self.sell()
            # Bearish divergence with negative confluence
            elif divergence == -1 and score < 0:
                self.sell()
            # Profit taking
            elif self.position.pl_pct > 0.05:
                self.sell()
            # Stop loss
            elif self.position.pl_pct < -0.03:
                self.sell()