import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    tolerance = 0.7
    swing_period = 12
    expiry_bars = 100
    liquidity_lookback = 10

    def init(self):
        self.swing_highs = []
        self.swing_lows = []
        self.bear_potential = []
        self.bull_potential = []
        self.last_wicked_high_level = None
        self.last_wicked_low_level = None
        self.bars_since_high = 999999
        self.bars_since_low = 999999
        self.trend = 0
        self.active_bull_fvg_top = None
        self.active_bull_fvg_bot = None
        self.active_bear_fvg_top = None
        self.active_bear_fvg_bot = None
        self.active_bull_mitigated = False
        self.active_bear_mitigated = False
        self.cisd = 0
        self.origin_lvl = 0.0
        self.origin_idx = 0

    def next(self):
        idx = len(self.data) - 1
        
        if idx < self.swing_period:
            return

        close_data = self.data.Close
        high_data = self.data.High
        low_data = self.data.Low
        open_data = self.data.Open

        current_close = close_data.iloc[-1]
        current_high = high_data.iloc[-1]
        current_low = low_data.iloc[-1]
        current_open = open_data.iloc[-1]

        prev_close = close_data.iloc[-2]
        prev_open = open_data.iloc[-2]
        prev_high = high_data.iloc[-2]
        prev_low = low_data.iloc[-2]

        # Detect Pivot Highs and Lows
        if idx >= self.swing_period * 2:
            is_pivot_high = True
            is_pivot_low = True
            
            current_pivot_high = high_data.iloc[-self.swing_period]
            current_pivot_low = low_data.iloc[-self.swing_period]
            
            for i in range(1, self.swing_period + 1):
                if high_data.iloc[-self.swing_period - i] > current_pivot_high:
                    is_pivot_high = False
                if high_data.iloc[-self.swing_period + i] > current_pivot_high:
                    is_pivot_high = False
                if low_data.iloc[-self.swing_period - i] < current_pivot_low:
                    is_pivot_low = False
                if low_data.iloc[-self.swing_period + i] < current_pivot_low:
                    is_pivot_low = False

            if is_pivot_high:
                self.swing_highs.insert(0, (idx - self.swing_period, current_pivot_high))
            if is_pivot_low:
                self.swing_lows.insert(0, (idx - self.swing_period, current_pivot_low))

        # Clean up expired swing lines
        self.swing_highs = [(bar_idx, lvl) for bar_idx, lvl in self.swing_highs if idx - bar_idx < self.expiry_bars]
        self.swing_lows = [(bar_idx, lvl) for bar_idx, lvl in self.swing_lows if idx - bar_idx < self.expiry_bars]

        # Check if swing highs/lows were wicked
        wicked_high = False
        wicked_low = False
        
        for i, (bar_idx, lvl) in enumerate(self.swing_highs):
            if current_high >= lvl:
                self.swing_highs.pop(i)
                wicked_high = True
                self.last_wicked_high_level = lvl
                self.bars_since_high = 0
                break

        for i, (bar_idx, lvl) in enumerate(self.swing_lows):
            if current_low <= lvl:
                self.swing_lows.pop(i)
                wicked_low = True
                self.last_wicked_low_level = lvl
                self.bars_since_low = 0
                break

        # Track bars since wicks
        if self.bars_since_high != 999999:
            self.bars_since_high += 1
        if self.bars_since_low != 999999:
            self.bars_since_low += 1

        # Detect CISD Patterns
        if prev_close < prev_open and current_close > current_open:
            self.bear_potential.insert(0, current_open)
            self.bear_potential.insert(0, idx)

        if prev_close > prev_open and current_close < current_open:
            self.bull_potential.insert(0, current_open)
            self.bull_potential.insert(0, idx)

        # Process bear_potential for CISD
        self.cisd = 0
        if len(self.bear_potential) > 0:
            inloop = True
            while inloop and len(self.bear_potential) >= 2:
                potential_level = self.bear_potential[0]
                potential_idx = self.bear_potential[1]
                
                if current_close < potential_level:
                    highest = max(close_data.iloc[0:idx - potential_idx + 1])
                    
                    top = 0.0
                    init = idx - potential_idx + 1
                    running = True
                    while running and init < len(close_data):
                        if close_data.iloc[init] < open_data.iloc[init]:
                            top = open_data.iloc[init]
                            init += 1
                        else:
                            running = False
                    
                    if top > 0 and (highest - potential_level) / (top - potential_level) > self.tolerance:
                        self.origin_lvl = potential_level
                        self.origin_idx = potential_idx
                        self.bear_potential.clear()
                        self.cisd = 1
                        inloop = False
                    else:
                        self.bear_potential.pop(0)
                        if len(self.bear_potential) > 0:
                            self.bear_potential.pop(0)
                        if len(self.bear_potential) == 0:
                            inloop = False
                else:
                    inloop = False

        # Process bull_potential for CISD
        if len(self.bull_potential) > 0:
            inloop = True
            while inloop and len(self.bull_potential) >= 2:
                potential_level = self.bull_potential[0]
                potential_idx = self.bull_potential[1]
                
                if current_close > potential_level:
                    lowest = min(close_data.iloc[0:idx - potential_idx + 1])
                    
                    bottom = 0.0
                    init = idx - potential_idx + 1
                    running = True
                    while running and init < len(close_data):
                        if close_data.iloc[init] > open_data.iloc[init]:
                            bottom = open_data.iloc[init]
                            init += 1
                        else:
                            running = False
                    
                    if bottom > 0 and (potential_level - lowest) / (potential_level - bottom) > self.tolerance:
                        self.origin_lvl = potential_level
                        self.origin_idx = potential_idx
                        self.bull_potential.clear()
                        self.cisd = 2
                        inloop = False
                    else:
                        self.bull_potential.pop(0)
                        if len(self.bull_potential) > 0:
                            self.bull_potential.pop(0)
                        if len(self.bull_potential) == 0:
                            inloop = False
                else:
                    inloop = False

        # CISD and FVG Logic
        bearish_sweep = False
        bullish_sweep = False
        buy_retest = False
        sell_retest = False

        if self.cisd == 1:
            self.trend = -1
            if self.bars_since_high <= self.liquidity_lookback and self.last_wicked_high_level is not None and current_close < self.last_wicked_high_level:
                bearish_sweep = True
            
            if idx >= 2 and low_data.iloc[-3] > high_data.iloc[-1]:
                self.active_bear_fvg_top = low_data.iloc[-3]
                self.active_bear_fvg_bot = high_data.iloc[-1]
                self.active_bear_mitigated = False
                self.active_bull_fvg_top = None
                self.active_bull_fvg_bot = None
            else:
                self.active_bear_fvg_top = None

        if self.cisd == 2:
            self.trend = 1
            if self.bars_since_low <= self.liquidity_lookback and self.last_wicked_low_level is not None and current_close > self.last_wicked_low_level:
                bullish_sweep = True
            
            if idx >= 2 and high_data.iloc[-3] < low_data.iloc[-1]:
                self.active_bull_fvg_top = low_data.iloc[-1]
                self.active_bull_fvg_bot = high_data.iloc[-3]
                self.active_bull_mitigated = False
                self.active_bear_fvg_top = None
                self.active_bear_fvg_bot = None
            else:
                self.active_bull_fvg_top = None

        # Check FVG Retests
        if self.active_bull_fvg_top is not None and not self.active_bull_mitigated and self.trend == 1:
            if current_low <= self.active_bull_fvg_top:
                buy_retest = True
                self.active_bull_mitigated = True

        if self.active_bear_fvg_bot is not None and not self.active_bear_mitigated and self.trend == -1:
            if current_high >= self.active_bear_fvg_bot:
                sell_retest = True
                self.active_bear_mitigated = True

        # Trading Logic
        if buy_retest and not self.position:
            self.buy()
        elif sell_retest and self.position:
            self.sell()

        if bearish_sweep and self.position:
            self.sell()
        elif bullish_sweep and not self.position:
            self.buy()


