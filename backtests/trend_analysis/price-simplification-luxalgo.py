import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length_input = 500
    mult_input = 2.0
    atr_length_input = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length_input)
        
        self.threshold = self.mult_input
        self.prev_price = None
        self.simplified_points = []

    def get_distance(self, p1, p2, p0):
        x1, y1 = p1
        x2, y2 = p2
        x0, y0 = p0
        
        numerator = abs((y2 - y1) * x0 - (x2 - x1) * y0 + x2 * y1 - y2 * x1)
        denominator = np.sqrt((y2 - y1) ** 2 + (x2 - x1) ** 2)
        
        return 0 if denominator == 0 else numerator / denominator

    def rdp_simplify(self, points, threshold):
        if len(points) < 3:
            return points
        
        keep = [False] * len(points)
        keep[0] = True
        keep[len(points) - 1] = True
        
        stack = [(0, len(points) - 1)]
        
        while stack:
            first_idx, last_idx = stack.pop()
            
            max_dist = 0.0
            index = first_idx
            
            for i in range(first_idx + 1, last_idx):
                d = self.get_distance(points[first_idx], points[last_idx], points[i])
                if d > max_dist:
                    max_dist = d
                    index = i
            
            if max_dist > threshold:
                keep[index] = True
                stack.append((index, last_idx))
                stack.append((first_idx, index))
        
        return [points[i] for i in range(len(points)) if keep[i]]

    def next(self):
        if len(self) < self.length_input:
            return
        
        if pd.isna(self.atr[-1]) or self.atr[-1] <= 0:
            return
        
        close_data = pd.Series(self.data.Close)
        bar_indices = np.arange(len(close_data))
        
        window_size = min(self.length_input, len(self))
        start_idx = len(self) - window_size
        end_idx = len(self)
        
        norm_points = []
        orig_points = []
        
        for i in range(start_idx, end_idx):
            price = close_data.iloc[i]
            bar_idx = bar_indices[i]
            orig_points.append((bar_idx, price))
            norm_points.append((bar_idx, price / self.atr[-1]))
        
        simplified_norm = self.rdp_simplify(norm_points, self.threshold)
        simplified_orig = []
        
        for norm_point in simplified_norm:
            idx = norm_point[0]
            for orig_point in orig_points:
                if orig_point[0] == idx:
                    simplified_orig.append(orig_point)
                    break
        
        self.simplified_points = simplified_orig
        
        if len(simplified_orig) >= 2:
            p2_idx, p2_price = simplified_orig[-1]
            p1_idx, p1_price = simplified_orig[-2]
            
            if p2_idx != p1_idx:
                slope = (p2_price - p1_price) / (p2_idx - p1_idx)
                
                if slope > 0 and not self.position:
                    self.buy()
                elif slope < 0 and self.position:
                    self.sell()


