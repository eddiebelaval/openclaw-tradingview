import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    breakout_pct = 1.03
    slope_threshold = 1.05
    pivot_len = 3
    volume_breakout_pct = 50
    vol_len = 100
    vol_ma_len = 20

    def init(self):
        self.pivot_highs = self.I(self._get_pivot_highs)
        self.pivot_lows = self.I(self._get_pivot_lows)
        self.volume_ma = self.I(lambda: pta.sma(pd.Series(self.data.Volume), length=self.vol_ma_len))
        self.max_volume = self.I(lambda: pd.Series(self.data.Volume).rolling(self.vol_len).max())
        
        self.trend_lines = []
        self.last_pivot_idx = None
        self.last_pivot_val = None
        self.in_trade = False

    def _get_pivot_highs(self):
        highs = pd.Series(self.data.High)
        pivot_highs = pd.Series(np.nan, index=highs.index)
        for i in range(self.pivot_len, len(highs) - self.pivot_len):
            if highs.iloc[i] > highs.iloc[i - self.pivot_len:i].max() and \
               highs.iloc[i] > highs.iloc[i + 1:i + self.pivot_len + 1].max():
                pivot_highs.iloc[i] = highs.iloc[i]
        return pivot_highs

    def _get_pivot_lows(self):
        lows = pd.Series(self.data.Low)
        pivot_lows = pd.Series(np.nan, index=lows.index)
        for i in range(self.pivot_len, len(lows) - self.pivot_len):
            if lows.iloc[i] < lows.iloc[i - self.pivot_len:i].min() and \
               lows.iloc[i] < lows.iloc[i + 1:i + self.pivot_len + 1].min():
                pivot_lows.iloc[i] = lows.iloc[i]
        return pivot_lows

    def _get_low_in_range(self, left_idx, right_idx, current_idx):
        if left_idx < 0 or right_idx >= len(self.data):
            return float('inf'), -1
        lows = self.data.Low[left_idx:right_idx + 1]
        lowest = np.min(lows)
        lowest_idx = left_idx + np.argmin(lows)
        return lowest, lowest_idx

    def next(self):
        current_idx = len(self.data) - 1
        
        if not np.isnan(self.pivot_highs[-1]):
            pivot_idx = current_idx - self.pivot_len
            pivot_val = self.pivot_highs[-1]
            
            if self.last_pivot_idx is None:
                self.last_pivot_idx = pivot_idx
                self.last_pivot_val = pivot_val
            else:
                l_idx = self.last_pivot_idx
                l_val = self.last_pivot_val
                r_idx = pivot_idx
                r_val = pivot_val
                
                if l_val / r_val > self.slope_threshold:
                    lowest, lowest_idx = self._get_low_in_range(l_idx, r_idx, current_idx)
                    self.trend_lines.append({
                        'l_idx': l_idx,
                        'l_val': l_val,
                        'r_idx': r_idx,
                        'r_val': r_val,
                        'lowest': lowest,
                        'lowest_idx': lowest_idx,
                        'active': True,
                        'r_ext_idx': r_idx,
                        'r_ext': r_val
                    })
                
                self.last_pivot_idx = pivot_idx
                self.last_pivot_val = pivot_val

        volume_ma_val = self.volume_ma[-1] if self.volume_ma[-1] is not None else 1
        vol_percent = abs((self.data.Volume[-1] - volume_ma_val) * 100 / volume_ma_val) if volume_ma_val > 0 else 0

        for i, trend_line in enumerate(self.trend_lines):
            if trend_line['active']:
                slope = (trend_line['r_val'] - trend_line['l_val']) / (trend_line['r_idx'] - trend_line['l_idx'])
                expected = trend_line['l_val'] + slope * (current_idx - trend_line['l_idx'])
                
                breakout = self.data.Close[-1] > expected * self.breakout_pct
                
                new_lowest, new_lowest_idx = self._get_low_in_range(trend_line['l_idx'], current_idx, current_idx)
                trend_line['lowest'] = min(trend_line['lowest'], new_lowest)
                
                if breakout:
                    trend_line['active'] = False
                    trend_line['r_ext_idx'] = current_idx
                    trend_line['r_ext'] = expected
                    
                    if vol_percent > self.volume_breakout_pct and not self.in_trade:
                        self.buy()
                        self.in_trade = True
                
                else:
                    trend_line['r_ext_idx'] = current_idx
                    trend_line['r_ext'] = expected
        
        if self.in_trade and len(self.trend_lines) > 0:
            if all(not tl['active'] for tl in self.trend_lines):
                self.sell()
                self.in_trade = False