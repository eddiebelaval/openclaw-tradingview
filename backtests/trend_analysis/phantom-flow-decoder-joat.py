import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        if len(self.data) < 20:
            return
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        atr = pta.atr(high, low, close, length=14)
        sma_20 = pta.sma(close, length=20)
        sma_50 = pta.sma(close, length=50)
        rsi = pta.rsi(close, length=14)
        
        if atr is None or sma_20 is None or sma_50 is None or rsi is None:
            return
        
        current_atr = atr.iloc[-1]
        current_sma_20 = sma_20.iloc[-1]
        current_sma_50 = sma_50.iloc[-1]
        current_rsi = rsi.iloc[-1]
        current_price = close.iloc[-1]
        
        highest_high_14 = high.tail(14).max()
        lowest_low_14 = low.tail(14).min()
        
        trend_up = current_sma_20 > current_sma_50
        trend_down = current_sma_20 < current_sma_50
        
        rsi_oversold = current_rsi < 30
        rsi_overbought = current_rsi > 70
        rsi_turning_up = rsi.iloc[-1] > rsi.iloc[-2]
        rsi_turning_down = rsi.iloc[-1] < rsi.iloc[-2]
        
        in_premium = current_price > (lowest_low_14 + (highest_high_14 - lowest_low_14) * 0.8)
        in_discount = current_price < (lowest_low_14 + (highest_high_14 - lowest_low_14) * 0.2)
        
        if not self.position:
            if trend_up and rsi_oversold and rsi_turning_up and in_discount:
                self.buy()
            elif trend_down and rsi_overbought and rsi_turning_down and in_premium:
                self.sell()
        else:
            if self.position.is_long:
                if trend_down or (rsi_overbought and rsi_turning_down) or current_price < current_sma_50:
                    self.position.close()
