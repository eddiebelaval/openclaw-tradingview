import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length_input = 20
    index_smooth_input = 5
    mode_input = "Efficiency"  # "Efficiency" or "Complexity"

    def init(self):
        self.raw_index_series = []
        self.isotonic_index_series = []
        self.cum_mean_series = []

    def pava(self, data, non_decreasing):
        """Performs Pool Adjacent Violators Algorithm (PAVA) for isotonic regression"""
        n = len(data)
        pool_vals = []
        pool_weights = []

        for i in range(n):
            current_val = data[i]
            current_pool = current_val
            current_weight = 1

            while len(pool_vals) > 0:
                prev_pool = pool_vals[-1]
                violation = (prev_pool > current_pool) if non_decreasing else (prev_pool < current_pool)

                if violation:
                    prev_weight = pool_weights.pop()
                    last_pool = pool_vals.pop()
                    current_pool = (last_pool * prev_weight + current_pool * current_weight) / (prev_weight + current_weight)
                    current_weight += prev_weight
                else:
                    break

            pool_vals.append(current_pool)
            pool_weights.append(current_weight)

        total_error = 0.0
        idx = 0
        for j in range(len(pool_vals)):
            p_val = pool_vals[j]
            p_weight = pool_weights[j]
            for k in range(p_weight):
                total_error += (data[idx] - p_val) ** 2
                idx += 1

        mse = total_error / n
        pools = len(pool_vals)
        return {"mse": mse, "pools": pools, "vals": pool_vals, "weights": pool_weights}

    def next(self):
        if len(self.data) < self.length_input + 1:
            return

        bar_idx = len(self.data) - 1

        # Get the last 'length_input' closing prices in reverse order
        data = []
        for i in range(self.length_input):
            data.append(self.data.Close[bar_idx - (self.length_input - 1 - i)])

        # Perform isotonic regression fits
        inc_fit = self.pava(data, True)
        dec_fit = self.pava(data, False)

        best_fit = inc_fit if inc_fit["mse"] < dec_fit["mse"] else dec_fit

