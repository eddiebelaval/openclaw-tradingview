import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma13Length = 13
    range9Length = 9
    rsv60Length = 60
    trend20Length = 20
    signal5Length = 5
    troughLeftBars = 3
    troughRightBars = 15
    troughIndex = 1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate 13-day simple moving average
        self.price13MovingAverage = self.I(pta.sma, close, length=self.ma13Length)

        # Calculate 9-day price range
        self.priceRange9Days = self.I(
            lambda: high.rolling(self.range9Length).max() - low.rolling(self.range9Length).min()
        )

        # Calculate high to close range (9-day high minus close)
        self.highToCloseRange9Days = self.I(
            lambda: high.rolling(self.range9Length).max() - close
        )

        # Calculate close to low range (close minus 9-day low)
        self.closeToLowRange9Days = self.I(
            lambda: close - low.rolling(self.range9Length).min()
        )

        # Calculate price deviation measure
        self.priceDeviationMeasure = self.I(
            lambda: (self.highToCloseRange9Days[-len(self.highToCloseRange9Days):] / 
                    (self.priceRange9Days[-len(self.priceRange9Days):] + 1e-10) * 100 - 70)
        )

        # Calculate 60-day RSV value × 100
        self.rsv60Days = self.I(
            lambda: (close - low.rolling(self.rsv60Length).min()) / 
                    (high.rolling(self.rsv60Length).max() - low.rolling(self.rsv60Length).min() + 1e-10) * 100
        )

