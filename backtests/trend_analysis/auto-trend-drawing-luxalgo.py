import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 300
    multInput = 2.0
    atrLengthInput = 14
    tensionInput = 0.5
    resolutionInput = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLengthInput)
        
        self.spline_values = None
        self.last_spline_value = None
        self.trend_direction = None

    def next(self):
        if len(self.data) < self.lengthInput:
            return
        
        if np.isnan(self.atr[-1]) or self.atr[-1] <= 0:
            return
        
        current_atr = self.atr[-1]
        
        norm_points = []
        for i in range(self.lengthInput - 1, -1, -1):
            price = self.data.Close[-self.lengthInput + (self.lengthInput - 1 - i)]
            bar_idx = len(self.data) - self.lengthInput + (self.lengthInput - 1 - i)
            norm_points.append({
                'x': bar_idx,
                'y': price / current_atr,
                'price': price
            })
        
        n = len(norm_points)
        keep = [False] * n
        keep[0] = True
        keep[n - 1] = True
        
