    def _get_distance(self, p1, p2, p0):
        x1, y1 = p1['x'], p1['y']
        x2, y2 = p2['x'], p2['y']
        x0, y0 = p0['x'], p0['y']
        
        dx = x2 - x1
        dy = y2 - y1
        
        numerator = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1)
        denominator = np.sqrt(dy * dy + dx * dx)
        
        return 0.0 if denominator == 0 else numerator / denominator

    def _interpolate(self, p0, p1, p2, p3, t, tension):
        t2 = t * t
        t3 = t2 * t
        
        f1 = -tension * t3 + 2.0 * tension * t2 - tension * t
        f2 = (2.0 - tension) * t3 + (tension - 3.0) * t2 + 1.0
        f3 = (tension - 2.0) * t3 + (3.0 - 2.0 * tension) * t2 + tension * t
        f4 = tension * t3 - tension * t2
        
        res_x = p0['x'] * f1 + p1['x'] * f2 + p2['x'] * f3 + p3['x'] * f4
        res_y = p0['y'] * f1 + p1['y'] * f2 + p2['y'] * f3 + p3['y'] * f4
        
        return {'x': res_x, 'y': res_y}