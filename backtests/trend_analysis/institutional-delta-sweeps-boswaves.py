import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_left = 20
    swing_right = 20
    cooldown_bars = 10
    liq_zone_width = 0.3
    max_zone_age = 200
    zone_extension = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR for zone width calculation
        self.atr = self.I(pta.atr, high, low, close, length=200)
        
        # Pivot highs and lows detection using rolling max/min
        self.highest_left = self.I(
            lambda: high.rolling(window=self.swing_left * 2 + 1, center=True).max()
        )
        self.lowest_left = self.I(
            lambda: low.rolling(window=self.swing_left * 2 + 1, center=True).min()
        )
        
        # State tracking
        self.zones = []
        self.last_bull_sweep_bar = -self.cooldown_bars
        self.last_bear_sweep_bar = -self.cooldown_bars
        self.bull_sweep_signal = False
        self.bear_sweep_signal = False

    def next(self):
        if len(self) < self.swing_left + self.swing_right + 50:
            return
        
        current_atr = self.atr[-1]
        if current_atr is None or np.isnan(current_atr):
            return
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_bar = len(self) - 1
        
        # Detect pivot highs
        if len(self) >= self.swing_left + self.swing_right + 1:
            is_pivot_high = (
                current_high == self.highest_left[-1 - self.swing_right] and
                all(self.data.High[len(self) - 1 - i] <= current_high 
                    for i in range(1, self.swing_right + 1))
            )
            
            if is_pivot_high:
                zone = {
                    'price': current_high,
                    'start_bar': current_bar,
                    'is_high': True,
                    'swept': False,
                    'sweep_bar': None,
                    'wicked_at': None
                }
                self.zones.append(zone)
        
        # Detect pivot lows
        if len(self) >= self.swing_left + self.swing_right + 1:
            is_pivot_low = (
                current_low == self.lowest_left[-1 - self.swing_right] and
                all(self.data.Low[len(self) - 1 - i] >= current_low 
                    for i in range(1, self.swing_right + 1))
            )
            
            if is_pivot_low:
                zone = {
                    'price': current_low,
                    'start_bar': current_bar,
                    'is_high': False,
                    'swept': False,
                    'sweep_bar': None,
                    'wicked_at': None
                }
                self.zones.append(zone)
        
        # Process zones for sweeps
        zones_to_remove = []
        
        for i, zone in enumerate(self.zones):
            age = current_bar - zone['start_bar']
            
            # Remove old zones
            if age > self.max_zone_age:
                zones_to_remove.append(i)
                continue
            
            if zone['swept']:
                continue
            
            # Bearish sweep (liquidity above price gets swept)
            if zone['is_high']:
                if (current_high > zone['price'] and 
                    current_close < zone['price'] and 
                    current_open < zone['price']):
                    
                    if current_bar >= self.last_bear_sweep_bar + self.cooldown_bars:
                        zone['swept'] = True
                        zone['sweep_bar'] = current_bar
                        zone['wicked_at'] = current_high
                        self.last_bear_sweep_bar = current_bar
                        self.bear_sweep_signal = True
            
            # Bullish sweep (liquidity below price gets swept)
            else:
                if (current_low < zone['price'] and 
                    current_close > zone['price'] and 
                    current_open > zone['price']):
                    
                    if current_bar >= self.last_bull_sweep_bar + self.cooldown_bars:
                        zone['swept'] = True
                        zone['sweep_bar'] = current_bar
                        zone['wicked_at'] = current_low
                        self.last_bull_sweep_bar = current_bar
                        self.bull_sweep_signal = True
        
        # Remove old zones
        for i in sorted(zones_to_remove, reverse=True):
            self.zones.pop(i)
        
        # Trading logic based on sweep signals
        if self.bull_sweep_signal:
            if not self.position:
                self.buy()
            self.bull_sweep_signal = False
        
        if self.bear_sweep_signal:
            if self.position:
                self.position.close()
            self.bear_sweep_signal = False
        
        # Exit long positions after some bars if no new signals
        if self.position and current_bar - self.position.open_bar > 50:
            self.position.close()