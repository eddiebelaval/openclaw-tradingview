import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 5
    snappy_entries = True
    fvg_mitigation = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.pivot_highs = self.I(self._calc_pivot_highs, high, self.pivot_len)
        self.pivot_lows = self.I(self._calc_pivot_lows, low, self.pivot_len)
        
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        self.rsi = self.I(pta.rsi, close, length=14)
        
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14) or pd.DataFrame(0, index=close.index, columns=['ADX_14']))
        self.adx = self.I(lambda x=adx_result: x['ADX_14'] if isinstance(x, pd.DataFrame) else x)
        
        self.last_ph = np.nan
        self.last_pl = np.nan
        self.last_ph_bar = 0
        self.last_pl_bar = 0
        
        self.waiting_for_bull_retrace = False
        self.waiting_for_bear_retrace = False
        self.bull_touched_fvg = False
        self.bear_touched_fvg = False
        
        self.fvg_list = []
        self.in_position = False

    def _calc_pivot_highs(self, high, length):
        result = pd.Series(np.nan, index=high.index)
        for i in range(length, len(high) - length):
            if high.iloc[i] == high.iloc[i-length:i+length+1].max():
                result.iloc[i] = high.iloc[i]
        return result

    def _calc_pivot_lows(self, low, length):
        result = pd.Series(np.nan, index=low.index)
        for i in range(length, len(low) - length):
            if low.iloc[i] == low.iloc[i-length:i+length+1].min():
                result.iloc[i] = low.iloc[i]
        return result

    def next(self):
        idx = len(self.data) - 1
        
        if idx < self.pivot_len * 2:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_ = self.data.Open[-1]
        
        prev_close = self.data.Close[-2] if idx >= 1 else close
        prev_high = self.data.High[-2] if idx >= 1 else high
        prev_low = self.data.Low[-2] if idx >= 1 else low
        
        high_m2 = self.data.High[-3] if idx >= 2 else high
        low_m2 = self.data.Low[-3] if idx >= 2 else low
        
        if not np.isnan(self.pivot_highs[-1]):
            ph = self.pivot_highs[-1]
            if ph > self.last_ph or np.isnan(self.last_ph):
                self.last_ph = ph
                self.last_ph_bar = idx - self.pivot_len
        
        if not np.isnan(self.pivot_lows[-1]):
            pl = self.pivot_lows[-1]
            if pl < self.last_pl or np.isnan(self.last_pl):
                self.last_pl = pl
                self.last_pl_bar = idx - self.pivot_len
        
        if close > self.last_ph and not np.isnan(self.last_ph):
            self.waiting_for_bull_retrace = True
            self.waiting_for_bear_retrace = False
            self.bull_touched_fvg = False
            self.last_ph = np.nan
        elif close < self.last_pl and not np.isnan(self.last_pl):
            self.waiting_for_bear_retrace = True
            self.waiting_for_bull_retrace = False
            self.bear_touched_fvg = False
            self.last_pl = np.nan
        
        is_bull_fvg = low > high_m2
        is_bear_fvg = high < low_m2
        
        if is_bull_fvg:
            self.fvg_list.append({'type': 'bull', 'top': low, 'bottom': high_m2})
        if is_bear_fvg:
            self.fvg_list.append({'type': 'bear', 'top': low_m2, 'bottom': high})
        
        bull_entry = False
        bear_entry = False
        
        if self.waiting_for_bull_retrace:
            if not self.bull_touched_fvg:
                for fvg in self.fvg_list:
                    if fvg['type'] == 'bull' and low <= fvg['top'] and high >= fvg['bottom']:
                        self.bull_touched_fvg = True
                        break
            
            if self.snappy_entries:
                conf = close > open_
            else:
                conf = close > open_ and close > prev_high
            
            if self.bull_touched_fvg and conf:
                bull_entry = True
                self.waiting_for_bull_retrace = False
                self.bull_touched_fvg = False
        
        if self.waiting_for_bear_retrace:
            if not self.bear_touched_fvg:
                for fvg in self.fvg_list:
                    if fvg['type'] == 'bear' and high >= fvg['bottom'] and low <= fvg['top']:
                        self.bear_touched_fvg = True
                        break
            
            if self.snappy_entries:
                conf = close < open_
            else:
                conf = close < open_ and close < prev_low
            
            if self.bear_touched_fvg and conf:
                bear_entry = True
                self.waiting_for_bear_retrace = False
                self.bear_touched_fvg = False
        
        mitigated_indices = []
        for i, fvg in enumerate(self.fvg_list):
            if fvg['type'] == 'bull' and low < fvg['bottom']:
                mitigated_indices.append(i)
            elif fvg['type'] == 'bear' and high > fvg['top']:
                mitigated_indices.append(i)
        
        for i in sorted(mitigated_indices, reverse=True):
            if self.fvg_mitigation:
                self.fvg_list.pop(i)
        
        if bull_entry and not self.position:
            self.buy()
        elif bear_entry and self.position:
            self.sell()
        elif bull_entry and self.position:
            self.position.close()
            self.buy()
        elif bear_entry and not self.position:
            pass
        
        ema_aligned_bull = self.ema20[-1] > self.ema50[-1] > self.ema200[-1]
        ema_aligned_bear = self.ema20[-1] < self.ema50[-1] < self.ema200[-1]
        
        if self.position and ema_aligned_bear:
            self.position.close()
        elif not self.position and ema_aligned_bull and self.rsi[-1] < 70:
            pass


