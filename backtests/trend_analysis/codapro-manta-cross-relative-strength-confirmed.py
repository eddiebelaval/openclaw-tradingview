import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MANTA Index Settings
    manta_smoothing = 6
    
    # Market Cap Weights
    w_nvda = 31.5
    w_aapl = 28.0
    w_amzn = 17.5
    w_meta = 11.9
    w_tsla = 11.1
    
    # Cross Settings
    confirm_bars = 3
    whipsaw_filter = 3
    min_separation = 0.0
    
    # Trade Management
    enable_tm = True
    use_trailing_stop = True
    fixed_tp_pct = 4.0
    fixed_sl_pct = 6.0
    trail_offset = 1.4
    max_bars_input = 100
    min_hold_bars = 2
    
    # PDT Protection
    enable_pdt = True
    max_trades_per_week = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate SMA50 for chart
        self.chart_sma50 = self.I(pta.sma, close, length=50)
        
        # Since we're trading a single instrument, we'll use its SMA50 as base
        # and create a synthetic MANTA using price momentum relative to SMA50
        def calc_manta_price():
            sma50 = pta.sma(close, length=50)
            if sma50 is None:
                return pd.Series(0, index=close.index)
            momentum = (close - sma50) / sma50
            momentum_smoothed = pta.ema(momentum, length=self.manta_smoothing)
            if momentum_smoothed is None:
                momentum_smoothed = pd.Series(0, index=close.index)
            manta_price = sma50 * (1 + momentum_smoothed)
            return manta_price
        
        self.manta_price = self.I(calc_manta_price)
        
        # EMA ribbon layers for 3D matrix
        self.m_ema1 = self.I(pta.ema, pd.Series(self.data.Close), length=3)
        self.m_ema2 = self.I(pta.ema, pd.Series(self.data.Close), length=8)
        self.m_ema3 = self.I(pta.ema, pd.Series(self.data.Close), length=14)
        
        # State tracking
        self.trade_dir = 0  # 0=flat, 1=long, -1=short
        self.entry_price = None
        self.entry_bar = 0
        self.exit_bar = -999
        self.bars_above = 0
        self.bars_below = 0
        self.trades_this_period = []

    def next(self):
        close_price = self.data.Close[-1]
        manta = self.manta_price[-1]
        
        # Check if price is above or below MANTA
        is_above = close_price > manta
        is_below = close_price < manta
        
        # Track bars above/below
        if is_above:
            self.bars_above += 1
            self.bars_below = 0
        elif is_below:
            self.bars_below += 1
            self.bars_above = 0
        else:
            self.bars_above = 0
            self.bars_below = 0
        
        # Calculate separation
        separation_pct = abs(close_price - manta) / manta * 100 if manta != 0 else 0
        enough_separation = separation_pct >= self.min_separation
        
        # Confirmation logic
        confirmed_above = self.bars_above == self.confirm_bars and enough_separation
        confirmed_below = self.bars_below == self.confirm_bars and enough_separation
        
        # PDT check: clean old trades outside lookback window
        self.trades_this_period = [bar for bar in self.trades_this_period 
                                    if len(self.data) - bar <= 5]
        pdt_allowed = len(self.trades_this_period) < self.max_trades_per_week if self.enable_pdt else True
        
        # Flat state and cooldown check
        is_flat = self.trade_dir == 0
        cooldown_ok = (len(self.data) - self.exit_bar) >= self.whipsaw_filter
        bars_held = len(self.data) - self.entry_bar if self.trade_dir != 0 else 0
        min_hold_met = bars_held >= self.min_hold_bars
        
        # Entry signals
        long_signal = confirmed_above and is_flat and cooldown_ok and pdt_allowed
        short_signal = confirmed_below and is_flat and cooldown_ok and pdt_allowed
        
        # Exit logic
        exit_reason = ""
        
        if self.trade_dir == 1:
            # Long position checks
            tp_level = self.entry_price * (1 + self.fixed_tp_pct / 100)
            if self.use_trailing_stop:
                sl_level = manta * (1 - self.trail_offset / 100)
            else:
                sl_level = self.entry_price * (1 - self.fixed_sl_pct / 100)
            
            if self.data.High[-1] >= tp_level:
                exit_reason = "TP"
            elif self.data.Low[-1] <= sl_level:
                exit_reason = "SL"
            elif bars_held >= self.max_bars_input:
                exit_reason = "MAX_BARS"
            elif is_below and min_hold_met:
                exit_reason = "CROSS_BACK"
        
        elif self.trade_dir == -1:
            # Short position checks
            tp_level = self.entry_price * (1 - self.fixed_tp_pct / 100)
            if self.use_trailing_stop:
                sl_level = manta * (1 + self.trail_offset / 100)
            else:
                sl_level = self.entry_price * (1 + self.fixed_sl_pct / 100)
            
            if self.data.Low[-1] <= tp_level:
                exit_reason = "TP"
            elif self.data.High[-1] >= sl_level:
                exit_reason = "SL"
            elif bars_held >= self.max_bars_input:
                exit_reason = "MAX_BARS"
            elif is_above and min_hold_met:
                exit_reason = "CROSS_BACK"
        
        # Process exits
        if exit_reason != "":
            self.position.close()
            self.trade_dir = 0
            self.entry_price = None
            self.exit_bar = len(self.data)
        
        # Process entries
        elif long_signal:
            self.buy()
            self.trade_dir = 1
            self.entry_price = close_price
            self.entry_bar = len(self.data)
            self.exit_bar = -999
            self.trades_this_period.append(len(self.data))
        
        elif short_signal:
            self.sell()
            self.trade_dir = -1
            self.entry_price = close_price
            self.entry_bar = len(self.data)
            self.exit_bar = -999
            self.trades_this_period.append(len(self.data))


