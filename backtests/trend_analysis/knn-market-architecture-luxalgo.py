import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sensitivity_input = 5
    auto_sensitivity = True
    knn_k_input = 5
    min_confidence = 0.4
    show_st = True
    show_mt = True
    show_lt = True
    bias_source_input = "Auto"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR and volatility metrics
        self.atr = self.I(pta.atr, high, low, close, length=200)
        self.atr_sma = self.I(pta.sma, self.atr, length=200)
        
        # Calculate relative volume and ATR
        self.vol_sma = self.I(pta.sma, volume, length=100)
        self.atr_14 = self.I(pta.atr, high, low, close, length=14)
        self.atr_14_sma = self.I(pta.sma, self.atr_14, length=100)
        
        # Initialize pivot detection
        self.last_st_high = None
        self.last_st_low = None
        self.last_mt_high = None
        self.last_mt_low = None
        self.last_lt_high = None
        self.last_lt_low = None
        
        self.st_history_high = []
        self.st_history_low = []
        self.mt_history_high = []
        self.mt_history_low = []
        self.lt_history_high = []
        self.lt_history_low = []
        
        self.position_high = None
        self.position_low = None
        self.entry_bar = None

    def detect_pivots(self, length):
        """Detect pivot highs and lows"""
        if len(self.data) < length * 2 + 1:
            return None, None
        
        idx = len(self.data) - 1 - length
        if idx < length:
            return None, None
        
        # Get high and low arrays
        highs = self.data.High
        lows = self.data.Low
        
        # Pivot High
        ph = None
        if idx >= length and idx < len(highs) - length:
            current_high = highs.iloc[idx]
            is_pivot_high = True
            for i in range(1, length + 1):
                if idx - i >= 0 and highs.iloc[idx - i] >= current_high:
                    is_pivot_high = False
                    break
                if idx + i < len(highs) and highs.iloc[idx + i] >= current_high:
                    is_pivot_high = False
                    break
            if is_pivot_high:
                ph = float(current_high)
        
        # Pivot Low
        pl = None
        if idx >= length and idx < len(lows) - length:
            current_low = lows.iloc[idx]
            is_pivot_low = True
            for i in range(1, length + 1):
                if idx - i >= 0 and lows.iloc[idx - i] <= current_low:
                    is_pivot_low = False
                    break
                if idx + i < len(lows) and lows.iloc[idx + i] <= current_low:
                    is_pivot_low = False
                    break
            if is_pivot_low:
                pl = float(current_low)
        
        return ph, pl

    def calculate_dynamic_sensitivity(self):
        """Calculate dynamic base length for pivot detection"""
        if len(self.data) < 200:
            return 5
        
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        atr_avg = self.atr_sma[-1] if self.atr_sma[-1] is not None else atr_val
        
        if atr_avg == 0:
            vol_ratio = 1.0
        else:
            vol_ratio = atr_val / atr_avg
        
        # Apply exponential smoothing approximation
        smoothed_ratio = vol_ratio ** (1/50) if vol_ratio > 0 else 1.0
        
        dynamic_mult = (smoothed_ratio ** 1.5) if self.auto_sensitivity else 1.0
        base_len = max(3, int((11 - self.sensitivity_input) * dynamic_mult))
        
        return base_len

    def knn_score(self, current_features, history):
        """Calculate kNN confidence score"""
        if len(history) <= self.knn_k_input:
            return 0.5
        
        distances = []
        for hist_point in history:
            dist = abs(current_features[0] - hist_point[0]) + abs(current_features[1] - hist_point[1])
            distances.append(dist)
        
        # Sort by distance and take k nearest
        sorted_indices = sorted(range(len(distances)), key=lambda i: distances[i])
        k_nearest = sorted_indices[:self.knn_k_input]
        
        score = sum(1.0 for _ in k_nearest) / self.knn_k_input
        return min(1.0, max(0.0, score))

    def next(self):
        # Skip if we don't have enough data
        if len(self.data) < 100:
            return
        
        # Calculate current metrics
        base_len = self.calculate_dynamic_sensitivity()
        
        # Calculate relative ATR and volume
        atr_14_val = self.atr_14[-1] if self.atr_14[-1] is not None else 0
        atr_14_avg = self.atr_14_sma[-1] if self.atr_14_sma[-1] is not None else atr_14_val
        rel_atr = atr_14_val / max(atr_14_avg, 0.0001)
        
        vol_val = self.data.Volume[-1] if len(self.data) > 0 else 0
        vol_avg = self.vol_sma[-1] if self.vol_sma[-1] is not None else vol_val
        rel_vol = vol_val / max(vol_avg, 1)
        
        # Detect pivots for each timeframe
        st_ph, st_pl = self.detect_pivots(base_len)
        mt_ph, mt_pl = self.detect_pivots(base_len * 3)
        lt_ph, lt_pl = self.detect_pivots(base_len * 9)
        
        current_price = self.data.Close[-1]
        
        # Process ST pivots
        if st_ph is not None:
            features = [rel_atr, rel_vol]
            confidence = self.knn_score(features, self.st_history_high)
            if confidence >= self.min_confidence:
                self.last_st_high = st_ph
                self.st_history_high.append(features)
                if len(self.st_history_high) > 100:
                    self.st_history_high.pop(0)
        
        if st_pl is not None:
            features = [rel_atr, rel_vol]
            confidence = self.knn_score(features, self.st_history_low)
            if confidence >= self.min_confidence:
                self.last_st_low = st_pl
                self.st_history_low.append(features)
                if len(self.st_history_low) > 100:
                    self.st_history_low.pop(0)
        
        # Process MT pivots
        if mt_ph is not None:
            features = [rel_atr, rel_vol]
            confidence = self.knn_score(features, self.mt_history_high)
            if confidence >= self.min_confidence:
                self.last_mt_high = mt_ph
                self.mt_history_high.append(features)
                if len(self.mt_history_high) > 100:
                    self.mt_history_high.pop(0)
        
        if mt_pl is not None:
            features = [rel_atr, rel_vol]
            confidence = self.knn_score(features, self.mt_history_low)
            if confidence >= self.min_confidence:
                self.last_mt_low = mt_pl
                self.mt_history_low.append(features)
                if len(self.mt_history_low) > 100:
                    self.mt_history_low.pop(0)
        
        # Process LT pivots
        if lt_ph is not None:
            features = [rel_atr, rel_vol]
            confidence = self.knn_score(features, self.lt_history_high)
            if confidence >= self.min_confidence:
                self.last_lt_high = lt_ph
                self.lt_history_high.append(features)
                if len(self.lt_history_high) > 100:
                    self.lt_history_high.pop(0)
        
        if lt_pl is not None:
            features = [rel_atr, rel_vol]
            confidence = self.knn_score(features, self.lt_history_low)
            if confidence >= self.min_confidence:
                self.last_lt_low = lt_pl
                self.lt_history_low.append(features)
                if len(self.lt_history_low) > 100:
                    self.lt_history_low.pop(0)
        
        # Determine active term for bias
        if self.bias_source_input == "None":
            active_term = None
        elif self.bias_source_input != "Auto":
            active_term = self.bias_source_input
        else:
            if self.show_lt:
                active_term = "LT"
            elif self.show_mt:
                active_term = "MT"
            elif self.show_st:
                active_term = "ST"
            else:
                active_term = None
        
        # Get selected high and low based on active term
        selected_high = None
        selected_low = None
        
        if active_term == "LT":
            selected_high = self.last_lt_high
            selected_low = self.last_lt_low
        elif active_term == "MT":
            selected_high = self.last_mt_high
            selected_low = self.last_mt_low
        elif active_term == "ST":
            selected_high = self.last_st_high
            selected_low = self.last_st_low
        
        # Trading logic based on structure levels
        if selected_high is not None and selected_low is not None:
            range_size = selected_high - selected_low
            
            if range_size > 0:
                # Buy signal: price breaks above resistance
                if current_price > selected_high and not self.position:
                    self.buy()
                    self.position_high = selected_high
                    self.position_low = selected_low
                    self.entry_bar = len(self.data)
                
                # Sell signal: price breaks below support
                if current_price < selected_low and self.position:
                    self.sell()
                    self.position_high = None
                    self.position_low = None
                
                # Exit long on reversal at support
                if self.position and current_price < selected_low:
                    self.position.close()
                    self.position_high = None
                    self.position_low = None