import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    process_noise = 0.01
    measurement_noise = 0.5
    zero_lag_factor = 1.0
    velocity_weight = 0.5
    ribbon_spread = 0.003
    deviation_thresh = 1.5
    level_width = 0.25
    bos_swing_len = 5
    retest_cooldown = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        self.kalman_main = self.I(self._kalman_main)
        self.kalman_slow = self.I(self._kalman_slow)
        
        self.pivot_high = self.I(self._pivot_high)
        self.pivot_low = self.I(self._pivot_low)
        
        self.last_sh = None
        self.last_sh_bar = None
        self.last_sl = None
        self.last_sl_bar = None
        self.structure_trend = 0
        
        self.bars_since_retest = 0
        self.max_dist_since_retest = 0.0
        
        self.extreme_high = None
        self.extreme_high_bar = None
        self.extreme_low = None
        self.extreme_low_bar = None
        self.was_extended_up = False
        self.was_extended_down = False

    def _kalman_main(self):
        close = pd.Series(self.data.Close)
        return self._kalman_filter(close, self.process_noise, self.measurement_noise, 
                                   self.zero_lag_factor, self.velocity_weight)

    def _kalman_slow(self):
        close = pd.Series(self.data.Close)
        return self._kalman_filter(close, self.process_noise + self.ribbon_spread * 5, 
                                   self.measurement_noise, self.zero_lag_factor, self.velocity_weight)

    def _kalman_filter(self, src, q, r, zl_factor, vel_weight):
        est = np.full(len(src), np.nan)
        vel = np.full(len(src), 0.0)
        err_cov = np.full(len(src), 1.0)
        vel_cov = np.full(len(src), 1.0)
        zlk = np.full(len(src), np.nan)
        
        est[0] = src.iloc[0]
        vel[0] = 0.0
        err_cov[0] = 1.0
        vel_cov[0] = 1.0
        
        for i in range(1, len(src)):
            pred_est = est[i-1] + vel[i-1] * vel_weight
            pred_cov = err_cov[i-1] + q
            price_chg = src.iloc[i] - src.iloc[i-1]
            pred_vel = vel[i-1] * 0.95 + price_chg * 0.05
            
            k_gain = pred_cov / (pred_cov + r)
            innov = src.iloc[i] - pred_est
            est[i] = pred_est + k_gain * innov
            err_cov[i] = (1.0 - k_gain) * pred_cov
            
            vel_gain = vel_cov[i-1] / (vel_cov[i-1] + r * 2)
            vel[i] = pred_vel + vel_gain * (price_chg - pred_vel)
            vel_cov[i] = (1.0 - vel_gain) * vel_cov[i-1] + q * 0.5
            
            lag_err = src.iloc[i] - est[i]
            zl_est = est[i] + lag_err * zl_factor * k_gain
            zlk[i] = zl_est if np.isnan(zlk[i-1]) else zlk[i-1] * 0.8 + zl_est * 0.2
        
        return pd.Series(zlk, index=src.index)

    def _pivot_high(self):
        high = pd.Series(self.data.High)
        lookback = self.bos_swing_len
        pivot = np.full(len(high), np.nan)
        
        for i in range(lookback, len(high) - lookback):
            if high.iloc[i] == high.iloc[i-lookback:i+lookback+1].max():
                pivot[i] = high.iloc[i]
        
        return pd.Series(pivot, index=high.index)

    def _pivot_low(self):
        low = pd.Series(self.data.Low)
        lookback = self.bos_swing_len
        pivot = np.full(len(low), np.nan)
        
        for i in range(lookback, len(low) - lookback):
            if low.iloc[i] == low.iloc[i-lookback:i+lookback+1].min():
                pivot[i] = low.iloc[i]
        
        return pd.Series(pivot, index=low.index)

    def next(self):
        if len(self.data) < self.bos_swing_len + 1:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        kalman_main = self.kalman_main[-1]
        kalman_slow = self.kalman_slow[-1]
        atr_val = self.atr[-1]
        
        if np.isnan(kalman_main) or np.isnan(kalman_slow) or np.isnan(atr_val):
            return
        
        pivot_high = self.pivot_high[-1]
        pivot_low = self.pivot_low[-1]
        
        if not np.isnan(pivot_high):
            self.last_sh = pivot_high
            self.last_sh_bar = len(self.data) - self.bos_swing_len - 1
        
        if not np.isnan(pivot_low):
            self.last_sl = pivot_low
            self.last_sl_bar = len(self.data) - self.bos_swing_len - 1
        
        deviation = close - kalman_main
        
        is_extended_up = deviation > atr_val * self.deviation_thresh
        is_extended_down = deviation < -atr_val * self.deviation_thresh
        
        if is_extended_up:
            self.was_extended_up = True
            if self.extreme_high is None or high > self.extreme_high:
                self.extreme_high = high
                self.extreme_high_bar = len(self.data) - 1
        
        if is_extended_down:
            self.was_extended_down = True
            if self.extreme_low is None or low < self.extreme_low:
                self.extreme_low = low
                self.extreme_low_bar = len(self.data) - 1
        
        snapped_back_from_high = self.was_extended_up and not is_extended_up and deviation < atr_val * self.deviation_thresh * 0.5
        snapped_back_from_low = self.was_extended_down and not is_extended_down and deviation > -atr_val * self.deviation_thresh * 0.5
        
        if snapped_back_from_high:
            self.was_extended_up = False
            self.extreme_high = None
            self.extreme_high_bar = None
        
        if snapped_back_from_low:
            self.was_extended_down = False
            self.extreme_low = None
            self.extreme_low_bar = None
        
        self.bars_since_retest += 1
        
        dist_to_kalman = abs(close - kalman_main)
        self.max_dist_since_retest = max(self.max_dist_since_retest, dist_to_kalman)
        
        touch_zone = atr_val * 0.15
        price_near_kalman = low <= kalman_main + touch_zone and high >= kalman_main - touch_zone
        qualified_distance = self.max_dist_since_retest > atr_val * 0.5
        cooldown_ok = self.bars_since_retest >= self.retest_cooldown
        
        bull_retest = cooldown_ok and qualified_distance and price_near_kalman and close > kalman_main and kalman_main > kalman_slow
        bear_retest = cooldown_ok and qualified_distance and price_near_kalman and close < kalman_main and kalman_main < kalman_slow
        
        if bull_retest:
            if not self.position:
                self.buy()
            self.bars_since_retest = 0
            self.max_dist_since_retest = 0.0
        
        if bear_retest:
            if self.position:
                self.position.close()
            self.bars_since_retest = 0
            self.max_dist_since_retest = 0.0
        
        if self.last_sh is not None:
            if close > self.last_sh:
                if self.structure_trend == -1:
                    if not self.position:
                        self.buy()
                else:
                    if not self.position:
                        self.buy()
                
                self.structure_trend = 1
                self.last_sh = None
                self.last_sh_bar = None
        
        if self.last_sl is not None:
            if close < self.last_sl:
                if self.structure_trend == 1:
                    if self.position:
                        self.position.close()
                else:
                    if self.position:
                        self.position.close()
                
                self.structure_trend = -1
                self.last_sl = None
                self.last_sl_bar = None


