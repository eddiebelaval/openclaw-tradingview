import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    lookback = 50
    volMult = 1.5
    retracePct = 50.0
    minHeightATR = 5.0
    maxHeightATR = 10.0
    minWidthBarsPhaseA = 10
    maxWidthBarsPhaseA = 100
    useERFilter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=200)

        # Calculate lowest low
        self.lowest_low = self.I(lambda: low.rolling(window=self.lookback).min())

        # Volume calculations
        eps = 1e-10
        rng = np.maximum(high - low, eps)
        self.volume_bought = volume * ((close - low) / rng)
        self.volume_sold = volume * ((high - close) / rng)

        self.cumulative_vol = volume.cumsum()
        self.avg_vol = self.cumulative_vol / (np.arange(len(self.cumulative_vol)) + 1)

        self.cumB = self.volume_bought.cumsum()
        self.cumS = self.volume_sold.cumsum()

        # State variables
        self.pending = False
        self.pBar = None
        self.pHigh = None
        self.pLow = None
        self.pBaseCumB = None

        self.trackingAR = False
        self.scBar = None
        self.scLow = None
        self.scHigh = None
        self.arHigh = None
        self.arBar = None

        self.retraceHit = False
        self.retraceHitBar = None
        self.retraceLow = None

        self.arLocked = False
        self.arHighLock = None
        self.arBarLock = None

        self.arCumB_atTop = None
        self.arBaseCumS = None
        self.erOK = False

        self.frozen = False

    def atrRange(self, multi):
        if len(self.atr) > 0 and not pd.isna(self.atr[-1]):
            return self.atr[-1] * multi
        return (self.cumulative_vol.iloc[-1] / len(self.data)) if len(self.data) > 0 else 1.0

    def next(self):
        if len(self.data) < 2:
            return

        idx = len(self.data) - 1
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        current_volume = self.data.Volume[-1]

        # Check for SC candidate
        is_lowest = current_low <= self.lowest_low[-1] if not pd.isna(self.lowest_low[-1]) else False
        is_vol_climax = (self.volume_sold.iloc[-1] >= (self.volMult * self.avg_vol.iloc[-1]) or
                        self.volume_bought.iloc[-1] >= (self.volMult * self.avg_vol.iloc[-1]))
        sc_candidate = is_lowest and is_vol_climax

        # Start pending SC
        if sc_candidate:
            self.pending = True
            self.pBar = idx
            self.pHigh = current_high
            self.pLow = current_low
            self.pBaseCumB = self.cumB.iloc[-2] if idx > 0 else 0.0

            self.trackingAR = False
            self.frozen = False
            self.retraceHit = False
            self.retraceHitBar = None
            self.retraceLow = None

            self.arLocked = False
            self.arHighLock = None
            self.arBarLock = None

            self.arHigh = None
            self.arBar = None

            self.arCumB_atTop = None
            self.arBaseCumS = None
            self.erOK = False

        # Confirm/Invalidate SC
        if self.pending and idx > self.pBar:
            if current_low < self.pLow:
                self.pending = False
            elif current_close > self.pHigh:
                self.trackingAR = True
                self.frozen = False

                self.scBar = self.pBar
                self.scLow = self.pLow
                self.scHigh = self.pHigh

                self.arHigh = current_high
                self.arBar = idx

                self.retraceHit = False
                self.retraceHitBar = None
                self.retraceLow = None

                self.arLocked = False
                self.arHighLock = None
                self.arBarLock = None

                self.arCumB_atTop = self.cumB.iloc[-1]
                self.arBaseCumS = self.cumS.iloc[-2] if idx > 0 else 0.0
                self.erOK = False

                self.pending = False

        # Track AR + detect retrace-hit
        if self.trackingAR and not self.frozen:
            if not self.arLocked and current_high > (self.arHigh if self.arHigh is not None else current_high):
                self.arHigh = current_high
                self.arBar = idx

                self.arCumB_atTop = self.cumB.iloc[-1]
                self.arBaseCumS = self.cumS.iloc[-2] if idx > 0 else 0.0
                self.erOK = False

            ar_top_now = self.arHighLock if self.arLocked else self.arHigh
            swing = ar_top_now - self.scLow if ar_top_now is not None and self.scLow is not None else 0
            thr = ar_top_now - swing * (self.retracePct * 0.01) if ar_top_now is not None else ar_top_now

            eps = 1e-10
            if not self.retraceHit and swing > eps and current_close <= thr:
                self.retraceHit = True
                self.retraceHitBar = idx
                self.retraceLow = current_low

                self.arLocked = True
                self.arHighLock = self.arHigh
                self.arBarLock = self.arBar

                if self.useERFilter:
                    effortAR = (self.arCumB_atTop if self.arCumB_atTop is not None else 0.0) - (self.pBaseCumB if self.pBaseCumB is not None else 0.0)
                    effortST = self.cumS.iloc[-1] - (self.arBaseCumS if self.arBaseCumS is not None else 0.0)

                    resultAR = self.arHighLock - self.scLow if self.arHighLock is not None and self.scLow is not None else 0
                    resultST = self.arHighLock - current_close if self.arHighLock is not None else 0

                    self.erOK = (resultAR > eps and resultST > eps) and ((effortST / resultST) >= (effortAR / resultAR))

                    if not self.erOK:
                        self.trackingAR = False
                        self.retraceHit = False
                        self.arLocked = False

        # Freeze logic
        can_freeze_basic = self.trackingAR and not self.frozen and self.retraceHit and self.arLocked
        can_freeze_er = (not self.useERFilter) or self.erOK

        phase_a_height = (self.arHighLock - self.scLow) if (self.arHighLock is not None and self.scLow is not None) else None
        phase_a_width = (self.retraceHitBar - self.scBar + 1) if (self.scBar is not None and self.retraceHitBar is not None) else None

        can_freeze_height_atr = (phase_a_height is not None and
                                 phase_a_height >= self.atrRange(self.minHeightATR) and
                                 phase_a_height <= self.atrRange(self.maxHeightATR))

        can_freeze_width_bars = (phase_a_width is not None and
                                 phase_a_width >= self.minWidthBarsPhaseA and
                                 phase_a_width <= self.maxWidthBarsPhaseA)

        # Discard if size gate fails
        if can_freeze_basic and can_freeze_er and not (can_freeze_height_atr and can_freeze_width_bars):
            self.trackingAR = False
            self.retraceHit = False
            self.arLocked = False

        # Execute freeze and place trade
        if can_freeze_basic and can_freeze_er and can_freeze_height_atr and can_freeze_width_bars:
            self.frozen = True
            self.trackingAR = False

            # Buy at SC confirmation, sell at retrace point
            if not self.position:
                self.buy()
            elif self.position:
                self.sell()