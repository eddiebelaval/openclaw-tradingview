import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    internal_lookback = 5
    swing_lookback = 50
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate pivot highs and lows
        self.internal_high = self.I(
            lambda: high.rolling(window=self.internal_lookback * 2 + 1, center=True).max()
        )
        self.internal_low = self.I(
            lambda: low.rolling(window=self.internal_lookback * 2 + 1, center=True).min()
        )
        self.swing_high = self.I(
            lambda: high.rolling(window=self.swing_lookback * 2 + 1, center=True).max()
        )
        self.swing_low = self.I(
            lambda: low.rolling(window=self.swing_lookback * 2 + 1, center=True).min()
        )
        
        # Track structure trend
        self.internal_trend = 0
        self.swing_trend = 0
        self.last_internal_high = 0
        self.last_internal_low = 0
        self.last_swing_high = 0
        self.last_swing_low = 0
        
    def next(self):
        # Update current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Detect internal structure changes
        if len(self.data) > self.internal_lookback * 2 + 2:
            curr_int_high = self.internal_high[-1]
            curr_int_low = self.internal_low[-1]
            
            # Internal bullish structure
            if (self.internal_trend <= 0 and 
                current_close > self.last_internal_high and 
                not np.isnan(curr_int_high)):
                self.internal_trend = 1
                self.last_internal_high = curr_int_high
                self.buy()
            
            # Internal bearish structure
            elif (self.internal_trend >= 0 and 
                  current_close < self.last_internal_low and 
                  not np.isnan(curr_int_low)):
                self.internal_trend = -1
                self.last_internal_low = curr_int_low
                if self.position:
                    self.sell()
            
            # Update highs and lows
            if current_high > self.last_internal_high:
                self.last_internal_high = current_high
            if current_low < self.last_internal_low:
                self.last_internal_low = current_low
        
        # Detect swing structure changes
        if len(self.data) > self.swing_lookback * 2 + 2:
            curr_swing_high = self.swing_high[-1]
            curr_swing_low = self.swing_low[-1]
            
            # Swing bullish structure
            if (self.swing_trend <= 0 and 
                current_close > self.last_swing_high and 
                not np.isnan(curr_swing_high)):
                self.swing_trend = 1
                self.last_swing_high = curr_swing_high
                if not self.position:
                    self.buy()
            
            # Swing bearish structure
            elif (self.swing_trend >= 0 and 
                  current_close < self.last_swing_low and 
                  not np.isnan(curr_swing_low)):
                self.swing_trend = -1
                self.last_swing_low = curr_swing_low
                if self.position:
                    self.sell()
            
            # Update highs and lows
            if current_high > self.last_swing_high:
                self.last_swing_high = current_high
            if current_low < self.last_swing_low:
                self.last_swing_low = current_low
        
        # Exit on opposite structure confirmation
        if self.position and self.internal_trend < 0:
            self.sell()
        elif not self.position and self.internal_trend > 0 and len(self.data) > self.internal_lookback * 2 + 2:
            self.buy()


