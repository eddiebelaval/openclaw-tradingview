import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Baseline Engine
    kernel_len = 55
    bandwidth = 12.0
    
    # Adaptive Volatility Cloud
    atr_len = 14
    mom_mode = "ER"  # "ER" or "ADX"
    mom_len = 20
    base_mult = 1.60
    expand_mult = 1.20
    
    # Market Regime Filter
    chop_len = 21
    chop_thresh = 61.8
    slope_gate = True
    
    # Institutional Volume & Spread Gating
    vol_len = 20
    strong_rvol = 1.20
    spread_factor = 1.10
    close_pos_gate = 0.70
    
    # Reversal / Exhaustion
    z_len = 50
    z_warn = 2.50
    min_exhaust_gap = 20
    exhaust_reset = 1.25
    exhaust_close_max = 0.55

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate HLC3
        hlc3 = (high + low + close) / 3.0
        
        # True Range
        prev_close = close.shift(1).fillna(close)
        tr = np.maximum(
            high - low,
            np.maximum(
                np.abs(high - prev_close),
                np.abs(low - prev_close)
            )
        )
        
        # ATR
        self.atr = self.I(lambda: pta.rma(tr, length=self.atr_len) or pd.Series(0.0, index=close.index))
        
        # Gaussian Kernel Baseline
        def calc_kernel():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if i < self.kernel_len - 1:
                    result.iloc[i] = np.nan
                else:
                    num = 0.0
                    den = 0.0
                    for j in range(self.kernel_len):
                        w = np.exp(-(j * j) / (2.0 * self.bandwidth * self.bandwidth))
                        num += close.iloc[i - j] * w
                        den += w
                    result.iloc[i] = num / den if den != 0.0 else np.nan
            return result
        
        self.baseline = self.I(calc_kernel)
        
        # Baseline Slope
        def calc_baseline_slope():
            return self.baseline.diff()
        
        self.baseline_slope = self.I(calc_baseline_slope)
        
        # Efficiency Ratio
        def calc_er():
            result = pd.Series(0.0, index=close.index)
            for i in range(self.mom_len, len(close)):
                er_den = np.sum(np.abs(close.iloc[i-self.mom_len:i].diff().dropna()))
                er_num = np.abs(close.iloc[i] - close.iloc[i-self.mom_len])
                if er_den != 0:
                    result.iloc[i] = np.clip(er_num / er_den, 0.0, 1.0)
            return result
        
        self.er = self.I(calc_er)
        
        # ADX for momentum metric
        def calc_adx():
            adx_result = pta.adx(high, low, close, length=self.mom_len)
            if adx_result is not None and not adx_result.empty and 'ADX_' + str(self.mom_len) in adx_result.columns:
                adx_vals = adx_result['ADX_' + str(self.mom_len)]
                return np.clip(adx_vals / 100.0, 0.0, 1.0)
            return pd.Series(0.0, index=close.index)
        
        self.adx_metric = self.I(calc_adx)
        
        # Momentum metric selection
        def calc_momentum_metric():
            if self.mom_mode == "ADX":
                return self.adx_metric
            else:
                return self.er
        
        self.momentum_metric = self.I(calc_momentum_metric)
        
        # Cloud width
        def calc_cloud_width():
            return self.atr * (self.base_mult + self.momentum_metric * self.expand_mult)
        
        self.cloud_width = self.I(calc_cloud_width)
        
        # Bands
        def calc_upper_band():
            return self.baseline + self.cloud_width
        
        def calc_lower_band():
            return self.baseline - self.cloud_width
        
        self.upper_band = self.I(calc_upper_band)
        self.lower_band = self.I(calc_lower_band)
        
        # CHOP
        def calc_chop():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(self.chop_len - 1, len(close)):
                window_high = high.iloc[i-self.chop_len+1:i+1].max()
                window_low = low.iloc[i-self.chop_len+1:i+1].min()
                span = max(window_high - window_low, 1e-10)
                sum_tr = tr.iloc[i-self.chop_len+1:i+1].sum()
                result.iloc[i] = 100.0 * np.log(sum_tr / span) / np.log(self.chop_len)
            return result
        
        self.chop = self.I(calc_chop)
        
        # Volume metrics
        self.bar_range = self.I(lambda: high - low)
        self.avg_spread = self.I(lambda: pta.sma(self.bar_range, length=self.vol_len))
        self.avg_volume = self.I(lambda: pta.sma(volume, length=self.vol_len))
        
        def calc_rvol():
            return volume / (self.avg_volume + 1e-10)
        
        self.rvol = self.I(calc_rvol)
        
        # Close position
        def calc_bull_close_pos():
            return (close - low) / (self.bar_range + 1e-10)
        
        def calc_bear_close_pos():
            return (high - close) / (self.bar_range + 1e-10)
        
        self.bull_close_pos = self.I(calc_bull_close_pos)
        self.bear_close_pos = self.I(calc_bear_close_pos)
        
        # Distance from baseline Z-score
        def calc_dist():
            return close - self.baseline
        
        self.dist = self.I(calc_dist)
        
        def calc_dist_z():
            result = pd.Series(0.0, index=close.index)
            for i in range(self.z_len - 1, len(close)):
                dist_window = self.dist[max(0, i-self.z_len+1):i+1]
                mean = dist_window.mean()
                std = dist_window.std()
                if std != 0:
                    result.iloc[i] = (self.dist.iloc[i] - mean) / std
            return result
        
        self.dist_z = self.I(calc_dist_z)
        
        # State tracking
        self.trend = 0
        self.bull_exhaust_armed = True
        self.bear_exhaust_armed = True
        self.last_bull_ex_bar = None
        self.last_bear_ex_bar = None
        self.state_id = 0
        self.state_age = 0

    def next(self):
        if len(self.data) < max(self.kernel_len, self.chop_len, self.z_len, self.vol_len, self.mom_len):
            return
        
        # Current values
        close_val = self.data.Close[-1]
        baseline_val = self.baseline[-1]
        upper_band_val = self.upper_band[-1]
        lower_band_val = self.lower_band[-1]
        baseline_slope_val = self.baseline_slope[-1]
        chop_val = self.chop[-1]
        rvol_val = self.rvol[-1]
        bull_close_pos_val = self.bull_close_pos[-1]
        bear_close_pos_val = self.bear_close_pos[-1]
        dist_z_val = self.dist_z[-1]
        momentum_metric_val = self.momentum_metric[-1]
        bar_range_val = self.bar_range[-1]
        avg_spread_val = self.avg_spread[-1]
        
        if np.isnan(baseline_val) or np.isnan(chop_val):
            return
        
        ranging = chop_val > self.chop_thresh
        
        # Update exhaustion state
        if not ranging:
            if self.trend != 1 or dist_z_val < -self.exhaust_reset:
                self.bull_exhaust_armed = True
            if self.trend != -1 or dist_z_val > self.exhaust_reset:
                self.bear_exhaust_armed = True
        
        # Trend state machine
        bull_candidate = (
            not ranging and
            crossover(self.data.Close, self.upper_band) and
            (not self.slope_gate or baseline_slope_val > 0)
        )
        
        bear_candidate = (
            not ranging and
            crossover(self.lower_band, self.data.Close) and
            (not self.slope_gate or baseline_slope_val < 0)
        )
        
        if bull_candidate:
            self.trend = 1
        elif bear_candidate:
            self.trend = -1
        
        bull_flip = (self.trend == 1 and self.state_id != 1 and self.state_id != 3 and self.state_id != 2 and self.state_id != 4)
        bear_flip = (self.trend == -1 and self.state_id != -1 and self.state_id != -3 and self.state_id != -2 and self.state_id != -4)
        
        # Strong signals
        strong_bull = (
            bull_flip and
            rvol_val > self.strong_rvol and
            bar_range_val > avg_spread_val * self.spread_factor and
            bull_close_pos_val > self.close_pos_gate
        )
        
        strong_bear = (
            bear_flip and
            rvol_val > self.strong_rvol and
            bar_range_val > avg_spread_val * self.spread_factor and
            bear_close_pos_val > self.close_pos_gate
        )
        
        normal_bull = bull_flip and not strong_bull
        normal_bear = bear_flip and not strong_bear
        
        # Exhaustion signals
        bull_gap_ok = (
            self.last_bull_ex_bar is None or
            (len(self.data) - self.last_bull_ex_bar > self.min_exhaust_gap)
        )
        
        bear_gap_ok = (
            self.last_bear_ex_bar is None or
            (len(self.data) - self.last_bear_ex_bar > self.min_exhaust_gap)
        )
        
        bull_exhaust_setup = (
            self.trend == 1 and
            dist_z_val > self.z_warn and
            self.data.Close[-1] < self.data.Open[-1] and
            bull_close_pos_val < self.exhaust_close_max
        )
        
        bear_exhaust_setup = (
            self.trend == -1 and
            dist_z_val < -self.z_warn and
            self.data.Close[-1] > self.data.Open[-1] and
            bear_close_pos_val < self.exhaust_close_max
        )
        
        bull_exhaust = (
            self.bull_exhaust_armed and
            bull_gap_ok and
            bull_exhaust_setup
        )
        
        bear_exhaust = (
            self.bear_exhaust_armed and
            bear_gap_ok and
            bear_exhaust_setup
        )
        
        if bull_exhaust:
            self.bull_exhaust_armed = False
            self.last_bull_ex_bar = len(self.data)
        
        if bear_exhaust:
            self.bear_exhaust_armed = False
            self.last_bear_ex_bar = len(self.data)
        
        # Trading logic
        if strong_bull or normal_bull:
            if not self.position:
                self.buy()
            self.state_id = 3 if strong_bull else 2
        elif strong_bear or normal_bear:
            if self.position:
                self.position.close()
            self.state_id = -3 if strong_bear else -2
        elif bull_exhaust:
            if self.position and self.position.is_long:
                self.position.close()
            self.state_id = 6
        elif bear_exhaust:
            if self.position and self.position.is_long:
                self.position.close()
            self.state_id = -6
        elif self.trend == 1:
            if not self.position:
                self.buy()
            self.state_id = 4
        elif self.trend == -1:
            if self.position:
                self.position.close()
            self.state_id = -4
        else:
            if self.position:
                self.position.close()
            self.state_id = 0
        
        self.state_age += 1 if self.state_id == self.state_id else 1


