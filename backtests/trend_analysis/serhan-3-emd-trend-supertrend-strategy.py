import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    length = 50
    devLen = 20
    mult = 1.5
    atrPeriod = 8
    atrMult = 0.7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA Base
        self.emaBase = self.I(pta.ema, close, length=self.length)
        
        # EMD Deviation
        deviation_series = self.I(lambda: pta.ema(pd.Series(np.abs(close - pta.ema(close, length=self.length))), length=self.devLen) or pd.Series(0, index=close.index))
        self.dev = deviation_series
        
        # Upper and Lower Bands
        self.upper = self.I(lambda: pta.ema(close, length=self.length) + self.dev * self.mult)
        self.lower = self.I(lambda: pta.ema(close, length=self.length) - self.dev * self.mult)
        
        # Supertrend calculation
        self.st, self.direction = self.I(self._calculate_supertrend, high, low, close)

    def _calculate_supertrend(self, high, low, close):
        atr = pta.atr(high, low, close, length=self.atrPeriod)
        
        hl2 = (high + low) / 2
        matr = hl2 + self.atrMult * atr
        satr = hl2 - self.atrMult * atr
        
        st = pd.Series(index=close.index, dtype='float64')
        direction = pd.Series(index=close.index, dtype='float64')
        
        st.iloc[0] = matr.iloc[0]
        direction.iloc[0] = 1
        
        for i in range(1, len(close)):
            if matr.iloc[i] < st.iloc[i-1] or close.iloc[i-1] > st.iloc[i-1]:
                st.iloc[i] = matr.iloc[i]
            else:
                st.iloc[i] = st.iloc[i-1]
            
            if satr.iloc[i] > st.iloc[i] or close.iloc[i-1] < st.iloc[i]:
                st.iloc[i] = satr.iloc[i]
                direction.iloc[i] = -1
            else:
                direction.iloc[i] = direction.iloc[i-1]
        
        return st, direction

    def next(self):
        close = self.data.Close[-1]
        
        trendLong = close > self.upper[-1]
        trendShort = close < self.lower[-1]
        
        longCondition = trendLong and self.direction[-1] == 1
        shortCondition = trendShort and self.direction[-1] == -1
        
        if longCondition and not self.position:
            self.buy()
        
        if shortCondition and not self.position:
            self.sell()
        
        if self.position and self.position.is_long and self.direction[-1] == -1:
            self.position.close()
        
        if self.position and self.position.is_short and self.direction[-1] == 1:
            self.position.close()