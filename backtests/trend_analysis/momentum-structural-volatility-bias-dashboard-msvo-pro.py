import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_mom = 34
    len_vol = 20
    len_bias = 18
    vol_mult = 0.07

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate weighted price
        weighted_price = (2 * close + high + low) / 4
        
        # Phase A: Trend Momentum Oscillator
        lookback_low = self.I(lambda: low.rolling(self.len_mom).min())
        lookback_high = self.I(lambda: high.rolling(self.len_mom).max())
        
        momentum_raw = self.I(
            lambda: (weighted_price - lookback_low) / (lookback_high - lookback_low + 0.001) * 100
        )
        
        self.trend_oscillator = self.I(pta.ema, momentum_raw, length=3)
        self.trend_signal = self.I(pta.ema, self.trend_oscillator, length=3)
        
        # Phase B: Dynamic Volatility Support/Resistance
        base_sma_20 = self.I(pta.sma, close, length=self.len_vol)
        
        vol_deviation = self.I(
            lambda: np.abs(weighted_price - base_sma_20) / (base_sma_20 + 0.001)
        )
        
        # DMA Engine for floor
        self.dma_floor_base = self.I(self._dma_engine, close, vol_deviation)
        
        self.dynamic_floor = self.I(lambda: (1 - self.vol_mult) * self.dma_floor_base)
        self.dynamic_ceiling = self.I(lambda: (1 + self.vol_mult) * self.dma_floor_base)
        
        # Phase C: Deviation Regression Channel
        reference_ma = self.I(pta.sma, close, length=self.len_bias)
        
        bias_skew = self.I(
            lambda: np.abs(weighted_price - reference_ma) / (reference_ma + 0.001)
        )
        
        self.central_bias = self.I(self._dma_engine, close, bias_skew)
        
        # Take profit/Stop loss limits
        self.tp_inner_limit = self.I(lambda: self.central_bias * 1.06)
        self.sl_inner_limit = self.I(lambda: self.central_bias * 0.94)
        self.tp_outer_limit = self.I(lambda: self.tp_inner_limit * 1.05)
        self.sl_outer_limit = self.I(lambda: self.sl_inner_limit * 0.95)
        
        # Center of Gravity MA5
        wma2 = self.I(pta.wma, weighted_price, length=2)
        self.cog_ma5 = self.I(pta.wma, wma2, length=5)
        
        # Bullish/Bearish signals
        self.is_bullish = self.I(
            lambda: (self.trend_oscillator - self.trend_signal) >= 0
        )

    def _dma_engine(self, src, alpha):
        """Dynamic Moving Average with adaptive alpha"""
        result = pd.Series(index=src.index, dtype=float)
        dma_val = src.iloc[0]
        
        for i in range(len(src)):
            alpha_val = alpha.iloc[i] if isinstance(alpha, pd.Series) else alpha
            dma_val = alpha_val * src.iloc[i] + (1 - alpha_val) * dma_val
            result.iloc[i] = dma_val
        
        return result

