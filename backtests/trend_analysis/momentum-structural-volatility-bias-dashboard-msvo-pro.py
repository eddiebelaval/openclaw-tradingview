        current_sl_outer = self.sl_outer_limit[-1] if len(self.sl_outer_limit) > 0 else current_close
        
        # Bull cross signal
        bull_cross = current_bullish and not prev_bullish
        
        # Bear cross signal
        bear_cross = not current_bullish and prev_bullish
        
