import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fibPeriod = 120
    ema10Period = 10
    ema14Period = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)

        # EMA calculations
        self.ema10 = self.I(pta.ema, close, length=self.ema10Period)
        self.ema14 = self.I(pta.ema, close, length=self.ema14Period)

        # Highest and lowest over fibonacci period
        def get_highest_3bars_back():
            result = high.rolling(self.fibPeriod).max().shift(3)
            return result if result is not None else pd.Series(0, index=high.index)

        def get_lowest_3bars_back():
            result = low.rolling(self.fibPeriod).min().shift(3)
            return result if result is not None else pd.Series(0, index=low.index)

        self.highest120DaysAgo = self.I(get_highest_3bars_back)
        self.lowest120DaysAgo = self.I(get_lowest_3bars_back)

        # Fibonacci levels
        def calc_fib_levels():
            fib_range = self.highest120DaysAgo - self.lowest120DaysAgo
            fib191 = self.highest120DaysAgo - fib_range * 0.191
            fib382 = self.highest120DaysAgo - fib_range * 0.382
            fib500 = self.highest120DaysAgo - fib_range * 0.500
            fib618 = self.highest120DaysAgo - fib_range * 0.618
            fib809 = self.highest120DaysAgo - fib_range * 0.809
            return pd.concat([fib191, fib382, fib500, fib618, fib809], axis=1).mean(axis=1)

        self.fib_levels = self.I(calc_fib_levels)

        # EMA breakthrough percentage
        def calc_ema_breakthrough():
            breakthrough_level = self.ema14.shift(1)
            ema_breakthrough_pct = (self.ema10 - breakthrough_level) / breakthrough_level * 100
            return ema_breakthrough_pct if ema_breakthrough_pct is not None else pd.Series(0, index=close.index)

        self.emaBreakthroughPercent = self.I(calc_ema_breakthrough)

        # Signals
        def calc_upward_signal():
            return crossover(self.emaBreakthroughPercent, pd.Series(0, index=self.emaBreakthroughPercent.index))

        def calc_downward_signal():
            return crossover(pd.Series(0, index=self.emaBreakthroughPercent.index), self.emaBreakthroughPercent)

        self.upwardSignal = self.I(calc_upward_signal)
        self.downwardSignal = self.I(calc_downward_signal)

        # Price range analysis
        def calc_price_analysis():
            priceRangeThird = (high - low) / 3
            openAboveRange = open_ > priceRangeThird * 2 + low
            openBelowRange = open_ < priceRangeThird + low
            closeAboveRange = close > priceRangeThird * 2 + low
            closeBelowRange = close < priceRangeThird + low
            closeMiddleRange = ~(closeAboveRange | closeBelowRange)

            strongUpwardSignal = closeAboveRange | (openBelowRange & closeMiddleRange)
            weakSignal = openBelowRange & closeMiddleRange
            strongDownwardSignal = ~(strongUpwardSignal | weakSignal)

            midPrice = (high + low) / 2
            upwardTrend = midPrice > high.shift(1)
            downwardTrend = midPrice < low.shift(1)
            weakTrend = ~(upwardTrend | downwardTrend)

            return pd.concat([
                strongUpwardSignal.astype(int),
                strongDownwardSignal.astype(int),
                upwardTrend.astype(int),
                downwardTrend.astype(int),
                weakTrend.astype(int),
                weakSignal.astype(int)
            ], axis=1)

        price_analysis = self.I(calc_price_analysis)
        self.strongUpwardSignal = self.I(lambda: price_analysis.iloc[:, 0].astype(bool))
        self.strongDownwardSignal = self.I(lambda: price_analysis.iloc[:, 1].astype(bool))
        self.upwardTrend = self.I(lambda: price_analysis.iloc[:, 2].astype(bool))
        self.downwardTrend = self.I(lambda: price_analysis.iloc[:, 3].astype(bool))
        self.weakTrend = self.I(lambda: price_analysis.iloc[:, 4].astype(bool))
        self.weakSignal = self.I(lambda: price_analysis.iloc[:, 5].astype(bool))

        # Combined signals
        def calc_combined_signals():
            signal1 = self.strongUpwardSignal & self.upwardTrend
            signal2 = self.strongDownwardSignal & self.downwardTrend
            signal3 = self.strongUpwardSignal & self.downwardTrend
            signal4 = self.strongDownwardSignal & self.downwardTrend
            signal5 = self.strongUpwardSignal & self.weakTrend
            signal6 = self.strongDownwardSignal & self.weakTrend

            return pd.concat([
                signal1.astype(int),
                signal2.astype(int),
                signal3.astype(int),
                signal4.astype(int),
                signal5.astype(int),
                signal6.astype(int)
            ], axis=1)

        combined = self.I(calc_combined_signals)
        self.signal1 = self.I(lambda: combined.iloc[:, 0].astype(bool))
        self.signal2 = self.I(lambda: combined.iloc[:, 1].astype(bool))
        self.signal3 = self.I(lambda: combined.iloc[:, 2].astype(bool))
        self.signal4 = self.I(lambda: combined.iloc[:, 3].astype(bool))
        self.signal5 = self.I(lambda: combined.iloc[:, 4].astype(bool))
        self.signal6 = self.I(lambda: combined.iloc[:, 5].astype(bool))

    def next(self):
        if len(self.data) < self.fibPeriod + 10:
            return

        # Buy on upward signal with strong upward trend or strong upward signal
        if self.upwardSignal[-1] or (self.signal1[-1] or self.signal5[-1]):
            if not self.position:
                self.buy()

        # Sell on downward signal with strong downward trend
        elif self.downwardSignal[-1] or (self.signal2[-1] or self.signal4[-1] or self.signal6[-1]):
            if self.position:
                self.sell()


