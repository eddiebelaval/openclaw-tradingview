import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        if len(self.data) < 2:
            return

        # Current bar values
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]

        # Previous bar values
        prev_high = self.data.High[-2]
        prev_low = self.data.Low[-2]

        # Bearish CRT: high swept, close below sweep level
        bearish_crt = current_high > prev_high and current_close < prev_high
        
        # Bullish CRT: low swept, close above sweep level
        bullish_crt = current_low < prev_low and current_close > prev_low

        # Trading logic based on CRT detection
        if bearish_crt:
            # Bearish CRT detected - take short position
            if self.position.is_long:
                self.position.close()
            self.sell()
        
        if bullish_crt:
            # Bullish CRT detected - take long position
            if self.position.is_short:
                self.position.close()
            self.buy()


