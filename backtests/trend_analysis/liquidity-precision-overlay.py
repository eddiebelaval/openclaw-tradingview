import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rr = 2.0
    lookback = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate highest high and lowest low from previous bar lookback
        self.highest_high = self.I(lambda: high.shift(1).rolling(self.lookback).max())
        self.lowest_low = self.I(lambda: low.shift(1).rolling(self.lookback).min())
        
        # Track entry prices and stops for position management
        self.entry_price = None
        self.stop_price = None
        self.target_price = None
        self.position_type = None

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        prev_high = self.data.High[-2] if len(self.data) > 1 else high
        prev_low = self.data.Low[-2] if len(self.data) > 1 else low
        
        equal_high = self.highest_high[-1] if len(self.highest_high) > 0 and not np.isnan(self.highest_high[-1]) else None
        equal_low = self.lowest_low[-1] if len(self.lowest_low) > 0 and not np.isnan(self.lowest_low[-1]) else None
        
        if equal_high is None or equal_low is None:
            return
        
        # Liquidity grab conditions
        bullish_grab = low < equal_low and close > equal_low
        bearish_grab = high > equal_high and close < equal_high
        
        # Store previous bar conditions
        if len(self.data) == 1:
            self.prev_bullish_grab = False
            self.prev_bearish_grab = False
        else:
            self.prev_bullish_grab = getattr(self, 'curr_bullish_grab', False)
            self.prev_bearish_grab = getattr(self, 'curr_bearish_grab', False)
        
        self.curr_bullish_grab = bullish_grab
        self.curr_bearish_grab = bearish_grab
        
        # Confirmation conditions
        bull_confirm = self.prev_bullish_grab and close > prev_high
        bear_confirm = self.prev_bearish_grab and close < prev_low
        
        # Close existing position if target or stop is hit
        if self.position:
            if self.position_type == "long":
                if low <= self.stop_price:
                    self.position.close()
                    self.position_type = None
                elif high >= self.target_price:
                    self.position.close()
                    self.position_type = None
            elif self.position_type == "short":
                if high >= self.stop_price:
                    self.position.close()
                    self.position_type = None
                elif low <= self.target_price:
                    self.position.close()
                    self.position_type = None
        
        # Entry logic
        if bull_confirm and not self.position:
            self.entry_price = close
            self.stop_price = prev_low
            self.target_price = self.entry_price + (self.entry_price - self.stop_price) * self.rr
            self.buy()
            self.position_type = "long"
        
        if bear_confirm and not self.position:
            self.entry_price = close
            self.stop_price = prev_high
            self.target_price = self.entry_price - (self.stop_price - self.entry_price) * self.rr
            self.buy()
            self.position_type = "short"