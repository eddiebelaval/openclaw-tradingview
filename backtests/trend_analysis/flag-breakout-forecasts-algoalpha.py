import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_param = 7
    col_tol = 0.005

    def init(self):
        self.pattern_detected = False
        self.pattern_start_bar = None
        self.pattern_highs = []
        self.pattern_lows = []
        self.pattern_high_indices = []
        self.pattern_low_indices = []
        self.last_pivot_type = 0
        self.active_patterns = []
        self.breakout_occurred = False
        self.last_breakout_direction = None

        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.atr = self.I(pta.atr, high, low, close, length=14)

    def next(self):
        if len(self.data) < self.len_param * 3:
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        pivot_high = self._detect_pivot_high(self.len_param)
        pivot_low = self._detect_pivot_low(self.len_param)

        if pivot_high is not None:
            if self.last_pivot_type != 1:
                self.pattern_highs.insert(0, pivot_high)
                self.pattern_high_indices.insert(0, len(self.data) - 1 - self.len_param)
                self.last_pivot_type = 1
            else:
                if pivot_high > self.pattern_highs[0]:
                    self.pattern_highs.insert(0, pivot_high)
                    self.pattern_high_indices.insert(0, len(self.data) - 1 - self.len_param)

        if pivot_low is not None:
            if self.last_pivot_type != -1:
                self.pattern_lows.insert(0, pivot_low)
                self.pattern_low_indices.insert(0, len(self.data) - 1 - self.len_param)
                self.last_pivot_type = -1
            else:
                if pivot_low < self.pattern_lows[0]:
                    self.pattern_lows.insert(0, pivot_low)
                    self.pattern_low_indices.insert(0, len(self.data) - 1 - self.len_param)

        if (len(self.pattern_highs) >= 3 and len(self.pattern_lows) >= 3 and
                self.last_pivot_type != getattr(self, '_last_pivot_type_prev', None)):
            self._check_pattern_formation()

        self._check_pattern_breakout(close, high, low)

        self._last_pivot_type_prev = self.last_pivot_type

    def _detect_pivot_high(self, period):
        if len(self.data) < period * 2 + 1:
            return None
        idx = len(self.data) - 1 - period
        if idx < 0 or idx + period >= len(self.data):
            return None
        current = self.data.High[idx]
        is_high = True
        for i in range(1, period + 1):
            if self.data.High[idx - i] >= current or self.data.High[idx + i] >= current:
                is_high = False
                break
        return current if is_high else None

    def _detect_pivot_low(self, period):
        if len(self.data) < period * 2 + 1:
            return None
        idx = len(self.data) - 1 - period
        if idx < 0 or idx + period >= len(self.data):
            return None
        current = self.data.Low[idx]
        is_low = True
        for i in range(1, period + 1):
            if self.data.Low[idx - i] <= current or self.data.Low[idx + i] <= current:
                is_low = False
                break
        return current if is_low else None

    def _check_pattern_formation(self):
        if len(self.pattern_highs) >= 3 and len(self.pattern_lows) >= 3:
            if self._is_collinear_pattern(self.pattern_highs, self.pattern_high_indices):
                self.pattern_detected = True
                self.pattern_start_bar = len(self.data) - 1
                self.active_patterns.append({
                    'type': 'flag',
                    'start_bar': self.pattern_start_bar,
                    'highs': self.pattern_highs[:3].copy(),
                    'lows': self.pattern_lows[:3].copy(),
                })

    def _is_collinear_pattern(self, pivots, indices):
        if len(pivots) < 3:
            return False
        y1, y2, y3 = pivots[0], pivots[1], pivots[2]
        x1, x2, x3 = indices[0], indices[1], indices[2]

        if x1 == x3:
            return False

        y_interp = y1 + (y3 - y1) * (x2 - x1) / (x3 - x1)
        deviation = abs(y2 - y_interp) / abs(y1) if y1 != 0 else abs(y2 - y_interp)

        return deviation < self.col_tol

    def _check_pattern_breakout(self, close, high, low):
        if not self.active_patterns:
            return

        current_bar = len(self.data) - 1

        for pattern in self.active_patterns:
            pattern_highs = pattern['highs']
            pattern_lows = pattern['lows']

            pattern_top = max(pattern_highs)
            pattern_bottom = min(pattern_lows)

            if close > pattern_top:
                self.breakout_occurred = True
                self.last_breakout_direction = 'bull'
                if not self.position:
                    self.buy()
                self.active_patterns.remove(pattern)
            elif close < pattern_bottom:
                self.breakout_occurred = True
                self.last_breakout_direction = 'bear'
                if self.position:
                    self.position.close()
                self.active_patterns.remove(pattern)

        pattern_duration = current_bar - getattr(self, 'pattern_start_bar', current_bar)
        if pattern_duration > 50:
            self.active_patterns.clear()
            self.pattern_detected = False

    def exit_trade(self):
        if self.position:
            self.position.close()