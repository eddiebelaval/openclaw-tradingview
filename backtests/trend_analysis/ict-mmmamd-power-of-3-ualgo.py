    min_sweep_ticks = 0
    min_sweep_atr = 0.20
    use_wicks_for_sweep = True
    pivot_len_mss = 3
    
    # OTE / FVG parameters
    show_fvg = True
    disp_min_atr = 0.60
    disp_min_body_pct = 0.55
    require_displacement = True
    fvg_search_bars = 30
    remove_mitigated_fvg = True
