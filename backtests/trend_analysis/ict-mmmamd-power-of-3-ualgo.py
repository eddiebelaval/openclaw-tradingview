    cycles = []
    current_cycle = None
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr_val = self.I(
            lambda: pta.atr(high, low, close, length=self.atr_len) or pd.Series(0, index=close.index)
        )
        
        # Initialize cycle tracking
        self.cycle_states = []
        self.last_entry_bar = -1000
        self.in_position = False
        
    def next(self):
        if len(self.data) < max(self.pivot_len_mss + 1, self.dr_pivot_len + 1, self.fvg_search_bars):
            return
        
        # Get current bar data
        bar_idx = len(self.data) - 1
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_atr = self.atr_val[-1] if not np.isnan(self.atr_val[-1]) else 1.0
        
