        if len(self.data) > 1:
            velocity = (self.data.Close[-1] - self.data.Close[-2]) / self.data.Close[-2] if self.data.Close[-2] != 0 else 0.0
        else:
            velocity = 0.0

        # Volume entropy
        vol_mean = self.vol_mean[-1] if not pd.isna(self.vol_mean[-1]) else self.data.Volume[-1]
        vol_std = self.vol_std[-1] if not pd.isna(self.vol_std[-1]) else 0.0

        cv = vol_std / vol_mean if vol_mean != 0 else 1.0
        entropy_score = 1.0 + np.log(1.0 + cv) * self.entropy_mult

        # Energy Equilibrium Point (simplified)
        lookback_close = self.data.Close[-self.lookback:]
        eep = lookback_close.mean()

        # Resonance amplitude
        resonance_amp = current_atr * entropy_score * self.cycle_mult

        # Golden ratio levels
        phi = 1.6180339887498948482
        r1 = eep + resonance_amp * (phi ** 1)
        r2 = eep + resonance_amp * (phi ** 2)
        r3 = eep + resonance_amp * (phi ** 3)
        s1 = eep - resonance_amp * (phi ** 1)
        s2 = eep - resonance_amp * (phi ** 2)
        s3 = eep - resonance_amp * (phi ** 3)

        # Determine bias
        bias_raw = 1 if current_close > eep else (-1 if current_close < eep else 0)
        dist_atr = (current_close - eep) / current_atr if current_atr != 0 else 0.0

        # Detect pivot points
        if len(self.data) >= self.pL + self.pR + 1:
            pivot_h = self.pivot_high[-1] if not pd.isna(self.pivot_high[-1]) else None
            pivot_l = self.pivot_low[-1] if not pd.isna(self.pivot_low[-1]) else None

            if pivot_h is not None and pivot_h == current_high:
                self.last_swing_high = current_high
