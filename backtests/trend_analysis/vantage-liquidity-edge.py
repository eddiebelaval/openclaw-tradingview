import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters from the Pine Script
    lookback = 120
    atr_period = 14
    entropy_mult = 5.0
    cycle_mult = 5.0
    pL = 2
    pR = 2
    prob_smooth = 5
    decayBars = 180
    early_bars = 6
    noon_trend_threshold = 25.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)

        # Calculate volume statistics
        self.vol_mean = self.I(lambda: pta.sma(volume, length=self.lookback))
        self.vol_std = self.I(lambda: volume.rolling(self.lookback).std())

        # Pivot points using rolling max/min
        self.pivot_high = self.I(lambda: high.rolling(self.pL + self.pR + 1, center=True).max())
        self.pivot_low = self.I(lambda: low.rolling(self.pL + self.pR + 1, center=True).min())

        # Track swing points
        self.last_swing_high = None
        self.last_swing_low = None
        self.position_entry_bar = None

    def next(self):
        if len(self.data) < self.lookback + 10:
            return

        # Get current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_atr = self.atr[-1]

        if pd.isna(current_atr) or current_atr == 0:
            return

