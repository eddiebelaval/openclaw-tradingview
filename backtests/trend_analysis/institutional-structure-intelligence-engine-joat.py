import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_length = 10
    atr_length = 14
    velocity_length = 20
    ob_volume_threshold = 1.5
    max_atr_mult = 2.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Core indicators
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        self.avg_volume = self.I(pta.sma, volume, length=20)
        
        # Range compression
        self.range_ma = self.I(pta.sma, high - low, length=50)
        self.current_range = self.I(lambda: high - low)
        
        # Velocity
        self.price_velocity = self.I(lambda: (close - close.shift(self.velocity_length)) / self.velocity_length)
        self.velocity_ma = self.I(lambda: pta.sma(np.abs(self.price_velocity), length=self.velocity_length) if hasattr(self, 'price_velocity') else pd.Series(0, index=close.index))
        
        # Structure tracking variables
        self.last_swing_high = None
        self.last_swing_low = None
        self.trend_bullish = True
        self.bullish_obs = []
        self.bearish_obs = []
        self.bullish_fvgs = []
        self.bearish_fvgs = []
        self.compression_bars = 0
        self.in_compression = False
        self.choch_count = 0
        self.bos_count = 0

    def next(self):
        # Current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_volume = self.data.Volume[-1]
        current_atr = self.atr[-1] if len(self.atr) > 0 else 0
        avg_vol = self.avg_volume[-1] if len(self.avg_volume) > 0 else current_volume
        
        if current_atr == 0 or np.isnan(current_atr):
            return

        # Swing detection - simplified pivot logic
        if len(self.data) > self.swing_length * 2:
            # Check for swing high (local maximum)
            if (current_high > self.data.High[-self.swing_length] and 
                all(current_high >= self.data.High[-(self.swing_length + i)] for i in range(1, self.swing_length + 1))):
                self.last_swing_high = current_high
                self.trend_bullish = False

            # Check for swing low (local minimum)
            if (current_low < self.data.Low[-self.swing_length] and 
                all(current_low <= self.data.Low[-(self.swing_length + i)] for i in range(1, self.swing_length + 1))):
                self.last_swing_low = current_low
                self.trend_bullish = True

        # Compression detection
        range_ma = self.range_ma[-1] if len(self.range_ma) > 0 else (current_high - current_low)
        current_range = current_high - current_low
        
        compressed = (current_range < range_ma * 0.3 and current_volume < avg_vol * 0.8)
        expanding = (current_range > range_ma * 2.0 and current_volume > avg_vol * 1.3)

        if compressed:
            self.compression_bars += 1
            self.in_compression = True
        else:
            self.compression_bars = 0
            self.in_compression = False

        # Order Block Detection - Bullish
        if (len(self.data) > 3 and
            self.data.Close[-3] < self.data.Open[-3] and
            self.data.Close[-2] < self.data.Open[-2] and
            current_close > self.data.Open[-1] and
            self.data.Volume[-2] > avg_vol * self.ob_volume_threshold and
            current_close > self.data.High[-2] and
            (self.data.High[-2] - self.data.Low[-2]) <= current_atr * self.max_atr_mult):
            
            ob_info = {
                'type': 'bullish',
                'top': self.data.High[-2],
                'bottom': self.data.Low[-2],
                'bar': len(self.data),
                'volume': self.data.Volume[-2],
                'touched': 0,
                'breaker': False
            }
            self.bullish_obs.append(ob_info)
            
            # Bullish OB signal - buy
            if len(self.bullish_obs) <= 3:
                self.buy()

        # Order Block Detection - Bearish
        if (len(self.data) > 3 and
            self.data.Close[-3] > self.data.Open[-3] and
            self.data.Close[-2] > self.data.Open[-2] and
            current_close < self.data.Open[-1] and
            self.data.Volume[-2] > avg_vol * self.ob_volume_threshold and
            current_close < self.data.Low[-2] and
            (self.data.High[-2] - self.data.Low[-2]) <= current_atr * self.max_atr_mult):
            
            ob_info = {
                'type': 'bearish',
                'top': self.data.High[-2],
                'bottom': self.data.Low[-2],
                'bar': len(self.data),
                'volume': self.data.Volume[-2],
                'touched': 0,
                'breaker': False
            }
            self.bearish_obs.append(ob_info)
            
            # Bearish OB signal - sell
            if len(self.bearish_obs) <= 3 and self.position:
                self.sell()

        # FVG Detection - Bullish (gap between 2 bars ago high and current low)
        if (len(self.data) > 2 and
            current_low > self.data.High[-3] and
            (current_low - self.data.High[-3]) > current_atr * 0.3 and
            current_volume > avg_vol * 0.8):
            
            fvg_info = {
                'type': 'bullish',
                'top': current_low,
                'bottom': self.data.High[-3],
                'bar': len(self.data),
                'mitigated': False
            }
            self.bullish_fvgs.append(fvg_info)
            
            # Bullish FVG - potential buy setup
            if len(self.bullish_fvgs) <= 3:
                self.buy()

        # FVG Detection - Bearish (gap between 2 bars ago low and current high)
        if (len(self.data) > 2 and
            current_high < self.data.Low[-3] and
            (self.data.Low[-3] - current_high) > current_atr * 0.3 and
            current_volume > avg_vol * 0.8):
            
            fvg_info = {
                'type': 'bearish',
                'top': self.data.Low[-3],
                'bottom': current_high,
                'bar': len(self.data),
                'mitigated': False
            }
            self.bearish_fvgs.append(fvg_info)
            
            # Bearish FVG - potential sell setup
            if len(self.bearish_fvgs) <= 3 and self.position:
                self.sell()

        # Check FVG mitigation
        for fvg in self.bullish_fvgs:
            if not fvg['mitigated'] and current_low <= fvg['top'] and current_high >= fvg['bottom']:
                fvg['mitigated'] = True

        for fvg in self.bearish_fvgs:
            if not fvg['mitigated'] and current_low <= fvg['top'] and current_high >= fvg['bottom']:
                fvg['mitigated'] = True

        # Check OB touches and breakers
        for ob in self.bullish_obs:
            if not ob['breaker'] and current_low <= ob['top'] and current_high >= ob['bottom']:
                ob['touched'] += 1
            if current_low < ob['bottom']:
                ob['breaker'] = True

        for ob in self.bearish_obs:
            if not ob['breaker'] and current_low <= ob['top'] and current_high >= ob['bottom']:
                ob['touched'] += 1
            if current_high > ob['top']:
                ob['breaker'] = True

        # BOS/CHOCH Detection with trading signals
        if self.last_swing_high is not None and self.last_swing_low is not None:
            # Bullish BOS/CHOCH
            if current_close > self.last_swing_high:
                if not self.trend_bullish:
                    # CHOCH - trend reversal
                    self.choch_count += 1
                    if self.position:
                        self.sell()
                    else:
                        self.buy()
                self.trend_bullish = True

            # Bearish BOS/CHOCH
            if current_close < self.last_swing_low:
                if self.trend_bullish:
                    # CHOCH - trend reversal
                    self.choch_count += 1
                    if self.position:
                        self.sell()
                else:
                    self.bos_count += 1
                self.trend_bullish = False

        # Expansion after compression - strong momentum signal
        if self.in_compression and expanding:
            if self.trend_bullish:
                self.buy()
            else:
                if self.position:
                    self.sell()

        # Risk management - exit on stop loss
        if self.position:
            if self.trend_bullish and current_low < self.last_swing_low - current_atr:
                self.sell()
            elif not self.trend_bullish and current_high > self.last_swing_high + current_atr:
                self.sell()

        # Clean up old data
        if len(self.bullish_obs) > 20:
            self.bullish_obs = self.bullish_obs[-20:]
        if len(self.bearish_obs) > 20:
            self.bearish_obs = self.bearish_obs[-20:]
        if len(self.bullish_fvgs) > 20:
            self.bullish_fvgs = self.bullish_fvgs[-20:]
        if len(self.bearish_fvgs) > 20:
            self.bearish_fvgs = self.bearish_fvgs[-20:]


