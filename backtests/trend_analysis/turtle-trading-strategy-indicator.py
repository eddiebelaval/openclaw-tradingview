import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Calculate Donchian channels using rolling max/min
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # 20-Day entry breakout (highest high over 20 periods)
        self.chan20Hi = self.I(lambda: high.rolling(20).max())
        
        # 55-Day entry breakout (highest high over 55 periods)
        self.chan55Hi = self.I(lambda: high.rolling(55).max())
        
        # 20-Day exit (lowest low over 10 periods)
        self.chan10Lo = self.I(lambda: low.rolling(10).min())
        
        # 55-Day exit (lowest low over 20 periods)
        self.chan20Lo = self.I(lambda: low.rolling(20).min())
        
        # ATR for stop calculation
        self.atrN = self.I(pta.atr, high, low, close, length=20)
        
        # Trade state variables
        self.in_trade = False
        self.active_system = 0  # 20 or 55
        self.entry_price = 0.0
        self.stop_price = 0.0
        self.units = 0
        self.next_add = 0.0
        self.last_trade_winner = False
        self.skip_next_20day = False
        
        # Parameters
        self.atr_mult = 2.0
        self.pyramid_step = 0.5
        self.max_units = 4

    def next(self):
        # Need enough bars for calculations
        if len(self.data) < 55:
            return
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        
        # Get previous bar's channel values for breakout comparisons
        prev_chan20Hi = self.chan20Hi[-2] if len(self.chan20Hi) > 1 else 0
        prev_chan55Hi = self.chan55Hi[-2] if len(self.chan55Hi) > 1 else 0
        prev_chan10Lo = self.chan10Lo[-2] if len(self.chan10Lo) > 1 else float('inf')
        prev_chan20Lo = self.chan20Lo[-2] if len(self.chan20Lo) > 1 else float('inf')
        
        current_atr = self.atrN[-1] if self.atrN[-1] is not None else 0
        
        exit_triggered = False
        pyramid_triggered = False
        entry_triggered = False
        
        # -------------------- EXIT LOGIC --------------------
        if self.in_trade:
            
            # ATR Stop Exit
            if current_low <= self.stop_price:
                exit_triggered = True
                self.last_trade_winner = current_close > self.entry_price
                self.skip_next_20day = self.last_trade_winner
            
            # 20-Day System Channel Exit (10-day low)
            elif self.active_system == 20 and current_low <= prev_chan10Lo:
                exit_triggered = True
                self.last_trade_winner = current_close > self.entry_price
                self.skip_next_20day = self.last_trade_winner
            
            # 55-Day System Channel Exit (20-day low)
            elif self.active_system == 55 and current_low <= prev_chan20Lo:
                exit_triggered = True
                self.last_trade_winner = current_close > self.entry_price
                self.skip_next_20day = self.last_trade_winner
            
            # Pyramid Add (only if no exit and conditions met)
            elif self.units < self.max_units and current_high >= self.next_add:
                pyramid_triggered = True
                self.units += 1
                
                fill_price = self.next_add
                self.stop_price = fill_price - (self.atr_mult * current_atr)
                self.next_add = fill_price + (self.pyramid_step * current_atr)
            
            # Reset state after exit
            if exit_triggered:
                self.sell()
                self.in_trade = False
                self.active_system = 0
                self.entry_price = 0.0
                self.stop_price = 0.0
                self.units = 0
                self.next_add = 0.0
        
        # -------------------- ENTRY LOGIC --------------------
        if not self.in_trade and not exit_triggered:
            
            # 55-Day Breakout Entry (always allowed)
            if current_high > prev_chan55Hi:
                entry_triggered = True
                
                fill_price = current_high
                
                self.buy()
                self.in_trade = True
                self.active_system = 55
                self.entry_price = fill_price
                self.stop_price = fill_price - (self.atr_mult * current_atr)
                self.units = 1
                self.next_add = fill_price + (self.pyramid_step * current_atr)
            
            # 20-Day Breakout Entry (skip once after a winner)
            elif current_high > prev_chan20Hi:
                if not self.skip_next_20day:
                    entry_triggered = True
                    
                    fill_price = current_high
                    
                    self.buy()
                    self.in_trade = True
                    self.active_system = 20
                    self.entry_price = fill_price
                    self.stop_price = fill_price - (self.atr_mult * current_atr)
                    self.units = 1
                    self.next_add = fill_price + (self.pyramid_step * current_atr)
                else:
                    self.skip_next_20day = False