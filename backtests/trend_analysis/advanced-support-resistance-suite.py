    def _pivot_high(self, high, left_bars, right_bars):
        """Calculate pivot highs using rolling window"""
        h = pd.Series(high)
        pivot = pd.Series(np.nan, index=h.index)
        
        for i in range(left_bars + right_bars, len(h)):
            left_max = h.iloc[i - right_bars - left_bars:i - right_bars].max()
            current = h.iloc[i - right_bars]
            
            if current > left_max:
                is_pivot = True
                for j in range(i - right_bars + 1, i + 1):
                    if j < len(h) and h.iloc[j] > current:
                        is_pivot = False
                        break
                
                if is_pivot:
                    pivot.iloc[i - right_bars] = current
        
        return pivot.fillna(method='ffill')

    def _pivot_low(self, low, left_bars, right_bars):
        """Calculate pivot lows using rolling window"""
        l = pd.Series(low)
        pivot = pd.Series(np.nan, index=l.index)
        
        for i in range(left_bars + right_bars, len(l)):
            left_min = l.iloc[i - right_bars - left_bars:i - right_bars].min()
            current = l.iloc[i - right_bars]
            
