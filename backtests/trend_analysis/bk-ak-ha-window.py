import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        if len(self.data) < 2:
            return
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        ha_close = (self.data.Close[-1] + self.data.High[-1] + self.data.Low[-1] + self.data.Open[-1]) / 4
        ha_open = (self.data.Open[-2] + self.data.Close[-2]) / 2 if len(self.data) > 1 else self.data.Open[-1]
        
        rsi_val = pta.rsi(close, length=14)
        if rsi_val is not None:
            rsi_current = rsi_val.iloc[-1] if len(rsi_val) > 0 else 50
        else:
            rsi_current = 50
        
        atr_val = pta.atr(high, low, close, length=14)
        if atr_val is not None:
            atr_current = atr_val.iloc[-1] if len(atr_val) > 0 else 0
        else:
            atr_current = 0
        
        is_ha_bull = ha_close >= ha_open
        was_ha_bull = len(self.data) > 1 and (self.data.Close[-2] >= self.data.Open[-2])
        
        buy_signal = not was_ha_bull and is_ha_bull and rsi_current < 40
        sell_signal = was_ha_bull and not is_ha_bull and rsi_current > 60
        
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.position.close()


