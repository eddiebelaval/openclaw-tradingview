import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_period = 10
    multiplier = 8.5
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate True Range manually
        tr = pd.Series(index=close.index, dtype=float)
        tr.iloc[0] = high.iloc[0] - low.iloc[0]
        for i in range(1, len(close)):
            tr.iloc[i] = max(
                high.iloc[i] - low.iloc[i],
                abs(high.iloc[i] - close.iloc[i-1]),
                abs(low.iloc[i] - close.iloc[i-1])
            )
        
        # Calculate ATR as SMA of True Range
        atr_val = self.I(lambda: pta.sma(tr, length=self.atr_period))
        
        # Store for access in next()
        self.tr = tr
        self.atr_val = atr_val
        self.close_series = close
        self.high_series = high
        self.low_series = low
        
        # Initialize trend tracking
        self.trend = 1
        self.up_val = 0
        self.dn_val = 0

    def next(self):
        if len(self.data) < self.atr_period + 1:
            return
        
        idx = len(self.data) - 1
        
        # Get source as HL2 (high + low) / 2
        src = (self.high_series.iloc[idx] + self.low_series.iloc[idx]) / 2
        
        atr_current = self.atr_val[-1]
        if atr_current is None or np.isnan(atr_current):
            return
        
        # Calculate up and dn lines
        up = src - (self.multiplier * atr_current)
        dn = src + (self.multiplier * atr_current)
        
        # Get previous values
        up1 = self.up_val
        dn1 = self.dn_val
        
        # Update up line
        if idx > 0 and self.close_series.iloc[idx-1] > up1:
            up = max(up, up1)
        self.up_val = up
        
        # Update dn line
        if idx > 0 and self.close_series.iloc[idx-1] < dn1:
            dn = min(dn, dn1)
        self.dn_val = dn
        
        # Update trend
        current_close = self.close_series.iloc[idx]
        prev_trend = self.trend
        
        if prev_trend == -1 and current_close > dn1:
            self.trend = 1
        elif prev_trend == 1 and current_close < up1:
            self.trend = -1
        
        # Generate signals
        buy_signal = (self.trend == 1) and (prev_trend == -1)
        sell_signal = (self.trend == -1) and (prev_trend == 1)
        
        # Execute trades
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.position.close()


