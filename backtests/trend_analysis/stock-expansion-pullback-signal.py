import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLen = 14
    atrMult = 1.3
    rsiLen = 14
    emaFast = 20
    emaSlow = 50
    maxBars = 20
    vwapBand = 0.003

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        self.ema_fast = self.I(pta.ema, close, length=self.emaFast)
        self.ema_slow = self.I(pta.ema, close, length=self.emaSlow)
        self.vwap = self.I(pta.vwap, close, volume)

        self.bull_exp_index = -1
        self.bear_exp_index = -1

    def next(self):
        if len(self.data) < max(self.atrLen, self.rsiLen, self.emaFast, self.emaSlow):
            return

        current_idx = len(self.data) - 1

        candle_range = self.data.High[-1] - self.data.Low[-1]
        candle_body = abs(self.data.Close[-1] - self.data.Open[-1])

        if self.atr[-1] is None or candle_range is None:
            return

        is_expansion = candle_range > self.atr[-1] * self.atrMult and candle_body > candle_range * 0.6

        bull_momentum = self.rsi[-1] > 55
        bear_momentum = self.rsi[-1] < 45

        if is_expansion and bull_momentum:
            self.bull_exp_index = current_idx

        if is_expansion and bear_momentum:
            self.bear_exp_index = current_idx

        bull_active = self.bull_exp_index != -1 and (current_idx - self.bull_exp_index <= self.maxBars)
        bear_active = self.bear_exp_index != -1 and (current_idx - self.bear_exp_index <= self.maxBars)

        vwap_distance = abs(self.data.Close[-1] - self.vwap[-1]) / self.data.Close[-1] if self.data.Close[-1] != 0 else 0

        pullback_bull = (self.data.Close[-1] <= self.ema_fast[-1] and self.data.Close[-1] >= self.ema_slow[-1]) or (vwap_distance < self.vwapBand)
        pullback_bear = (self.data.Close[-1] >= self.ema_fast[-1] and self.data.Close[-1] <= self.ema_slow[-1]) or (vwap_distance < self.vwapBand)

        bull_signal = bull_active and bull_momentum and pullback_bull
        bear_signal = bear_active and bear_momentum and pullback_bear

        if bull_signal and not self.position:
            self.buy()
        elif bear_signal and self.position:
            self.sell()
        elif bear_signal and not self.position:
            self.buy()
        elif bull_signal and self.position:
            self.sell()