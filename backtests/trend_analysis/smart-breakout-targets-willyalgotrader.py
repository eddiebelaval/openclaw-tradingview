import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    squeeze_length = 20
    bb_mult = 2.0
    squeeze_thresh = 0.6
    atr_compress = 0.75
    min_squeeze = 5
    impulse_mult = 0.8
    sl_buffer = 0.5
    tp1_rr = 1.0
    tp2_rr = 2.0
    tp3_rr = 3.0
    use_vol_filter = False
    vol_mult = 1.5
    use_htf = False
    htf_ma_len = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        atr_period = max(int(self.squeeze_length / 2), 7)
        self.atr_raw = self.I(pta.atr, high, low, close, length=atr_period)
        self.atr_sma = self.I(lambda: pta.sma(self.atr_raw, length=self.squeeze_length) if self.atr_raw is not None else pd.Series(0, index=close.index))

        self.bb_basis = self.I(pta.sma, close, length=self.squeeze_length)
        self.bb_stdev = self.I(lambda: close.rolling(self.squeeze_length).std())
        
        self.bb_upper = self.I(lambda: self.bb_basis[-1] + self.bb_mult * (close.rolling(self.squeeze_length).std()[-1] if len(close.rolling(self.squeeze_length).std()) > 0 else 0) if len(self.bb_basis) > 0 else 0)
        self.bb_lower = self.I(lambda: self.bb_basis[-1] - self.bb_mult * (close.rolling(self.squeeze_length).std()[-1] if len(close.rolling(self.squeeze_length).std()) > 0 else 0) if len(self.bb_basis) > 0 else 0)
        
        self.bb_width = self.I(lambda: (self.bb_upper - self.bb_lower) / self.bb_basis[-1] if self.bb_basis[-1] != 0 and len(self.bb_basis) > 0 else 0)
        self.bb_width_sma = self.I(lambda: pd.Series(self.bb_width).rolling(self.squeeze_length).mean() if isinstance(self.bb_width, (int, float)) else self.bb_width.rolling(self.squeeze_length).mean())

        self.vol_sma = self.I(pta.sma, volume, length=20)

        self.squeeze_high_val = np.nan
        self.squeeze_low_val = np.nan
        self.squeeze_bars_count = 0
        self.in_squeeze = False
        self.last_breakout_idx = -999

        self.trade_dir = 0
        self.trade_active = False
        self.last_entry = np.nan
        self.last_sl = np.nan
        self.last_tp1 = np.nan
        self.last_tp2 = np.nan
        self.last_tp3 = np.nan

    def next(self):
        if len(self) < self.squeeze_length + 10:
            return

        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        open_val = self.data.Open[-1]
        
        atr_val = self.atr_raw[-1] if len(self.atr_raw) > 0 else 0
        atr_sma_val = self.atr_sma[-1] if len(self.atr_sma) > 0 else atr_val

        bb_basis_val = self.bb_basis[-1] if len(self.bb_basis) > 0 else close_val
        bb_stdev_val = close_val.rolling(self.squeeze_length).std() if hasattr(close_val, 'rolling') else pd.Series(self.data.Close).rolling(self.squeeze_length).std()[-1]
        if isinstance(bb_stdev_val, pd.Series):
            bb_stdev_val = bb_stdev_val.iloc[-1] if len(bb_stdev_val) > 0 else 0
        
        bb_upper_val = bb_basis_val + self.bb_mult * bb_stdev_val
        bb_lower_val = bb_basis_val - self.bb_mult * bb_stdev_val
        bb_width_val = (bb_upper_val - bb_basis_val) if bb_basis_val != 0 else 0

        bb_width_sma_val = pd.Series(self.data.Close).rolling(self.squeeze_length).std()[-1] if len(pd.Series(self.data.Close).rolling(self.squeeze_length).std()) > 0 else 0
        bb_width_basis_sma = pd.Series(self.data.Close).rolling(self.squeeze_length).mean()[-1] if len(pd.Series(self.data.Close).rolling(self.squeeze_length).mean()) > 0 else close_val

        bb_width_sma_val = (bb_width_basis_sma * self.bb_mult * self.squeeze_thresh) if bb_width_basis_sma != 0 else 0

        bb_squeeze = bb_width_val < bb_width_sma_val
        atr_compress = atr_sma_val != 0 and atr_val < atr_sma_val * self.atr_compress
        is_squeeze = bb_squeeze and atr_compress

        if is_squeeze:
            self.squeeze_bars_count += 1
            if not self.in_squeeze:
                self.squeeze_high_val = high_val
                self.squeeze_low_val = low_val
                self.in_squeeze = True
            else:
                self.squeeze_high_val = max(self.squeeze_high_val, high_val)
                self.squeeze_low_val = min(self.squeeze_low_val, low_val)
        else:
            if self.in_squeeze and self.squeeze_bars_count >= self.min_squeeze:
                pass
            self.squeeze_bars_count = 0
            self.in_squeeze = False

        vol_confirm = True
        if self.use_vol_filter:
            vol_sma_val = self.vol_sma[-1] if len(self.vol_sma) > 0 else self.data.Volume[-1]
            vol_confirm = self.data.Volume[-1] > vol_sma_val * self.vol_mult

        body_size = abs(close_val - open_val)
        is_bull_candle = close_val > open_val
        is_bear_candle = close_val < open_val
        impulse_up = is_bull_candle and body_size > atr_val * self.impulse_mult
        impulse_down = is_bear_candle and body_size > atr_val * self.impulse_mult

        if self.trade_active:
            if self.trade_dir == 1:
                if high_val >= self.last_tp3:
                    self.sell()
                    self.trade_active = False
                    self.trade_dir = 0
                elif low_val <= self.last_sl:
                    self.sell()
                    self.trade_active = False
                    self.trade_dir = 0
