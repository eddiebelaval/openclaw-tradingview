import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 10
    len2 = 10

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate smoothed Heikin-Ashi values
        o_ema = self.I(pta.ema, open_, length=self.len)
        c_ema = self.I(pta.ema, close, length=self.len)
        h_ema = self.I(pta.ema, high, length=self.len)
        l_ema = self.I(pta.ema, low, length=self.len)
        
        # Heikin-Ashi close
        def calc_ha_close():
            return (o_ema + h_ema + l_ema + c_ema) / 4
        
        self.haclose = self.I(calc_ha_close)
        
        # Heikin-Ashi open (cumulative)
        def calc_ha_open():
            ha_open = np.full(len(o_ema), np.nan)
            for i in range(len(o_ema)):
                if i == 0:
                    ha_open[i] = (o_ema.iloc[i] + c_ema.iloc[i]) / 2
                else:
                    if not np.isnan(ha_open[i-1]) and not np.isnan(self.haclose.iloc[i-1]):
                        ha_open[i] = (ha_open[i-1] + self.haclose.iloc[i-1]) / 2
                    else:
                        ha_open[i] = (o_ema.iloc[i] + c_ema.iloc[i]) / 2
            return pd.Series(ha_open, index=o_ema.index)
        
        self.haopen = self.I(calc_ha_open)
        
        # Heikin-Ashi high and low
        def calc_ha_high():
            return np.maximum(h_ema, np.maximum(self.haopen, self.haclose))
        
        def calc_ha_low():
            return np.minimum(l_ema, np.minimum(self.haopen, self.haclose))
        
        self.hahigh = self.I(calc_ha_high)
        self.halow = self.I(calc_ha_low)
        
        # Second smoothing
        self.o2 = self.I(pta.ema, self.haopen, length=self.len2)
        self.c2 = self.I(pta.ema, self.haclose, length=self.len2)
        self.h2 = self.I(pta.ema, self.hahigh, length=self.len2)
        self.l2 = self.I(pta.ema, self.halow, length=self.len2)
        
        # Track previous trend
        self.prev_bullish = None

    def next(self):
        if len(self.data) < 2:
            return
        
        # Determine current trend
        is_bullish = self.c2[-1] > self.o2[-1]
        
        # Initialize on first bar
        if self.prev_bullish is None:
            self.prev_bullish = is_bullish
            return
        
        # Buy on bullish trend start (bearish to bullish crossover)
        if is_bullish and not self.prev_bullish:
            if not self.position:
                self.buy()
        
        # Sell on bearish trend start (bullish to bearish crossover)
        elif not is_bullish and self.prev_bullish:
            if self.position:
                self.sell()
        
        self.prev_bullish = is_bullish