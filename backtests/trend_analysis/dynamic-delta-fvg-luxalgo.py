import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR for size filtering
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Calculate volume SMA for volume filtering
        self.vol_avg = self.I(pta.sma, volume, length=20)
        
        # Store FVG detection state
        self.fvg_tops = []
        self.fvg_bottoms = []
        self.fvg_is_bull = []
        
        # Parameters from inputs
        self.vol_mult = 0.0
        self.atr_mult = 0.2
        self.mit_mode = "Touch"
        self.filter_overlap = True
        self.max_gaps = 20

    def next(self):
        if len(self.data) < 3:
            return
        
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else (self.data.High[-1] - self.data.Low[-1])
        vol_avg_val = self.vol_avg[-1] if not np.isnan(self.vol_avg[-1]) else self.data.Volume[-1]
        
        # FVG Detection Logic
        is_bull_fvg = self.data.Low[-1] > self.data.High[-3]
        is_bear_fvg = self.data.High[-1] < self.data.Low[-3]
        
        # Volume filter
        vol_filter = self.data.Volume[-2] >= vol_avg_val * self.vol_mult if self.vol_mult > 0 else True
        
        # Size filters
        if is_bull_fvg:
            size_filter = (self.data.Low[-1] - self.data.High[-3]) >= atr_val * self.atr_mult
        elif is_bear_fvg:
            size_filter = (self.data.Low[-3] - self.data.High[-1]) >= atr_val * self.atr_mult
        else:
            size_filter = False
        
        # Detection logic
        if (is_bull_fvg or is_bear_fvg) and vol_filter and size_filter:
            if is_bull_fvg:
                top = self.data.Low[-1]
                bottom = self.data.High[-3]
            else:
                top = self.data.Low[-3]
                bottom = self.data.High[-1]
            
            mid = (top + bottom) / 2
            range_height = top - bottom
            
            # Estimate buy/sell percentages based on close vs open
            if self.data.Close[-2] > self.data.Open[-2]:
                buy_pct = 60.0
                sell_pct = 40.0
            elif self.data.Close[-2] < self.data.Open[-2]:
                buy_pct = 40.0
                sell_pct = 60.0
            else:
                buy_pct = 50.0
                sell_pct = 50.0
            
            # Overlap filtering
            if self.filter_overlap and len(self.fvg_tops) > 0:
                for i in range(len(self.fvg_tops) - 1, -1, -1):
                    fvg_top = self.fvg_tops[i]
                    fvg_bottom = self.fvg_bottoms[i]
                    if max(bottom, fvg_bottom) < min(top, fvg_top):
                        self.fvg_tops.pop(i)
                        self.fvg_bottoms.pop(i)
                        self.fvg_is_bull.pop(i)
            
            # Add new FVG
            self.fvg_tops.append(top)
            self.fvg_bottoms.append(bottom)
            self.fvg_is_bull.append(is_bull_fvg)
            
            # Limit active gaps
            if len(self.fvg_tops) > self.max_gaps:
                self.fvg_tops.pop(0)
                self.fvg_bottoms.pop(0)
                self.fvg_is_bull.pop(0)
        
        # Mitigation logic - check if price has mitigated any FVG
        if len(self.fvg_tops) > 0:
            for i in range(len(self.fvg_tops) - 1, -1, -1):
                fvg_top = self.fvg_tops[i]
                fvg_bottom = self.fvg_bottoms[i]
                is_bull = self.fvg_is_bull[i]
                
                mitigated = False
                if is_bull:
                    mitigated = self.data.Low[-1] < fvg_top
                else:
                    mitigated = self.data.High[-1] > fvg_bottom
                
                if mitigated:
                    self.fvg_tops.pop(i)
                    self.fvg_bottoms.pop(i)
                    self.fvg_is_bull.pop(i)
        
        # Simple trading logic based on FVG detection
        bull_count = sum(1 for is_bull in self.fvg_is_bull if is_bull)
        bear_count = len(self.fvg_is_bull) - bull_count
        
        if bull_count > bear_count and not self.position:
            self.buy()
        elif bear_count > bull_count and self.position:
            self.position.close()


