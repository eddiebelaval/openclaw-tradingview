    def _calc_hurst(self, close):
        length = self.i_hurstPer
        if len(close) < length:
            return pd.Series(0.5, index=close.index)
        
        result = []
        for i in range(len(close)):
            if i < length:
                result.append(0.5)
            else:
                window = close.iloc[i-length:i]
                mean = window.mean()
                dev = (window - mean).values
                cumsum = np.cumsum(dev)
                max_dev = np.max(cumsum)
                min_dev = np.min(cumsum)
                range_rs = max_dev - min_dev
                std_dev = window.std()
                rs = range_rs / (std_dev + 1e-10)
                h = np.log(rs + 1e-10) / np.log(length) if rs > 0 else 0.5
                result.append(np.clip(h, 0.2, 0.8))
        
        return pd.Series(result, index=close.index)

    def _calc_pressure(self, close, high, low, volume):
        result = []
        for i in range(len(close)):
            if i == 0:
                result.append(0.0)
            else:
                rng = high.iloc[i] - low.iloc[i] + 0.0001
                uW = high.iloc[i] - max(self.data.Open[i], close.iloc[i])
                lW = min(self.data.Open[i], close.iloc[i]) - low.iloc[i]
                uPct = uW / rng * 100.0
                lPct = lW / rng * 100.0
                netPressure = lPct - uPct
                fpDeltaRatio = (self.fpBuy[i] - self.fpSell[i]) / (self.fpBuy[i] + self.fpSell[i] + 0.0001)
                trend = 4.0 if close.iloc[i] > self.data.Open[i] else -4.0 if close.iloc[i] < self.data.Open[i] else 0.0
                pressure = np.clip(netPressure + fpDeltaRatio * 35.0 + trend, -100.0, 100.0)
                result.append(pressure)
        
        return pd.Series(result, index=close.index)

    def _calc_health(self, close, high, low):
        result = []
        for i in range(len(close)):
            if i < self.i_healthLen:
                result.append(0.0)
            else:
                window_close = close.iloc[i-self.i_healthLen:i]
                move_sum = np.sum(np.abs(np.diff(window_close)))
                eff = np.abs(close.iloc[i] - close.iloc[i-self.i_healthLen]) / (move_sum + 1e-10)
                trend_dist = (close.iloc[i] - self.ema21[i]) / (self.atr14[i] + 1e-10)
                health = np.clip((eff * 60.0 + trend_dist * 18.0) * (1.0 if close.iloc[i] > self.ema21[i] else -1.0), -100.0, 100.0)
                result.append(health)
        
        return pd.Series(result, index=close.index)

    def _calc_liquidity(self, close, volume):
        result = []
        for i in range(len(close)):
            if i < self.i_liqSlow:
                result.append(0.0)
            else:
                fast_delta = np.sum(self.fpDelta) if i >= self.i_liqFast else 0.0
                slow_delta = np.sum(self.fpDelta) if i >= self.i_liqSlow else 0.0
                liq_dir = 1.0 if (fast_delta + slow_delta) > 0 else -1.0 if (fast_delta + slow_delta) < 0 else 0.0
                liq_str = np.clip((np.abs(fast_delta) * 0.70 + np.abs(slow_delta)) * 20.0, 0.0, 100.0)
                liquidity = np.clip(liq_dir * liq_str, -100.0, 100.0)
                result.append(liquidity)
        
        return pd.Series(result, index=close.index)

