import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Vector Candles parameters
    vc_clim = 2.0
    vc_rise = 1.5
    
    # Market Structure parameters
    ms_len = 10
    
    # Premium/Discount parameters
    pd_len = 50
    
    # Pattern parameters
    pat_sim = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate volume and spread averages
        self.vol_avg = self.I(lambda: pta.sma(volume, length=20))
        self.spread_avg = self.I(lambda: pta.sma(high - low, length=20))
        
        # Premium/Discount levels
        self.pd_hi = self.I(lambda: high.rolling(self.pd_len).max())
        self.pd_lo = self.I(lambda: low.rolling(self.pd_len).min())
        
        # EMAs for trend confirmation
        self.ema9 = self.I(pta.ema, close, length=9)
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        
        # Pivot detection using rolling highs and lows
        self.ph_detected = False
        self.pl_detected = False
        self.last_swing_h = None
        self.last_swing_l = None
        
        # Trading state
        self.in_long = False
        self.in_short = False

    def next(self):
        if len(self.data) < self.ms_len + 1:
            return
        
        # Current values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        vol_avg = self.vol_avg[-1] if len(self.vol_avg) > 0 else 0
        spread_avg = self.spread_avg[-1] if len(self.spread_avg) > 0 else 0
        
        if vol_avg == 0 or spread_avg == 0:
            return
        
        # Vector Candles classification
        is_bull = close >= self.data.Open[-1]
        is_climax = (volume >= vol_avg * self.vc_clim and 
                     (high - low) >= spread_avg * self.vc_clim)
        is_rising = (volume >= vol_avg * self.vc_rise and not is_climax)
        
        # Premium/Discount zones
        pd_hi = self.pd_hi[-1]
        pd_lo = self.pd_lo[-1]
        rng = pd_hi - pd_lo
        eq_h = pd_lo + rng * 0.667
        eq_l = pd_lo + rng * 0.333
        
        in_premium = close >= eq_h
        in_discount = close <= eq_l
        in_equilibrium = not in_premium and not in_discount
        
        # EMA trend
        ema9 = self.ema9[-1]
        ema50 = self.ema50[-1]
        ema200 = self.ema200[-1]
        
        bullish_trend = ema9 > ema50 > ema200
        bearish_trend = ema9 < ema50 < ema200
        
        # Detect pivot highs (swing highs) - using rolling window
        if len(self.data) > self.ms_len * 2:
            is_pivot_high = (high > self.data.High[-self.ms_len:-1].max() and 
                            high > self.data.High[-(self.ms_len):-1].max())
            is_pivot_low = (low < self.data.Low[-self.ms_len:-1].min() and 
                           low < self.data.Low[-(self.ms_len):-1].min())
        else:
            is_pivot_high = False
            is_pivot_low = False
        
        # Store pivot information
        if is_pivot_high:
            self.last_swing_h = high
            self.ph_detected = True
        if is_pivot_low:
            self.last_swing_l = low
            self.pl_detected = True
        
        # Trading rules
        
        # LONG ENTRY: Bullish bias (discount zone + bull trend)
        # Confirmed by climax buy or rising buy candle
        if (not self.in_long and not self.position and
            in_discount and bullish_trend and 
            (is_climax and is_bull)):
            self.buy()
            self.in_long = True
        
        # SHORT ENTRY: Bearish bias (premium zone + bear trend)
        # Confirmed by climax sell or rising sell candle
        if (not self.in_short and not self.position and
            in_premium and bearish_trend and 
            (is_climax and not is_bull)):
            self.sell()
            self.in_short = True
        
        # EXIT LONG: Price moves into premium or breaks structure
        if self.in_long and self.position:
            if in_premium or close < ema50:
                self.position.close()
                self.in_long = False
        
        # EXIT SHORT: Price moves into discount or breaks structure
        if self.in_short and self.position:
            if in_discount or close > ema50:
                self.position.close()
                self.in_short = False
        
        # Alternative exit: Stop loss if reversal detected
        if self.position:
            if (is_climax and is_bull and not self.in_long) or (is_climax and not is_bull and not self.in_short):
                self.position.close()
                self.in_long = False
                self.in_short = False


