import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    factor = 4.0
    period = 30

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Parkinson volatility
        def calc_park_vol():
            ln_hl = np.log(high / low)
            ln_hl_sq = np.power(ln_hl, 2)
            c = 4 * np.log(2)
            park_var = pta.rma(ln_hl_sq / c, length=self.period)
            park_sigma = np.sqrt(park_var)
            park_vol = park_sigma * close
            
            # Use ATR as fallback if park_vol is NaN
            atr = pta.atr(high, low, close, length=self.period)
            result = park_vol.fillna(atr)
            return result
        
        vol = self.I(calc_park_vol)
        
