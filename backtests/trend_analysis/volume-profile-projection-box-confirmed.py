import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Session parameters
    session_start_hour = 19
    reset_on_trade = True
    
    # Volume Profile parameters
    num_rows = 34
    va_percent = 61.0
    prof_width = 0.20
    
    # Trade Management parameters
    confirm_bars = 4
    tp_pct = 0.25
    sl_pct = 0.6
    max_bars = 37
    cooldown = 9
    rsi_len = 50
    rsi_ob = 80
    rsi_os = 20

    def init(self):
        self.rsi = self.I(pta.rsi, pd.Series(self.data.Close), length=self.rsi_len)
        
        # Trade state tracking
        self.in_trade = False
        self.is_long = False
        self.entry_bar = -1
        self.entry_price = np.nan
        self.tp = np.nan
        self.sl = np.nan
        self.last_sig_bar = -999
        
        # Box state tracking
        self.box_start_bar = -1
        self.box_active = False
        self.vah = np.nan
        self.val = np.nan
        self.poc = np.nan
        self.prev_in_trade = False
        
        # Profile data
        self.profile_hi = np.nan
        self.profile_lo = np.nan
        self.profile_poc_idx = 0

    def _get_ny_hour(self, bar_index):
        """Get New York hour from bar timestamp"""
        if bar_index < len(self.data):
            timestamp = self.data.index[bar_index]
            # Convert to NY time (EST/EDT)
            ny_time = pd.Timestamp(timestamp).tz_localize('UTC').tz_convert('America/New_York')
            return ny_time.hour
        return -1

    def _value_area(self, vol_arr, poc_idx, rows, pct):
        """Calculate value area high and low indices"""
        target = np.sum(vol_arr) * pct / 100.0
        accum = vol_arr[poc_idx]
        hi = poc_idx
        lo = poc_idx
        
        while accum < target:
            if lo == 0 and hi == rows - 1:
                break
            v_up = vol_arr[hi + 1] if hi < rows - 1 else 0.0
            v_dn = vol_arr[lo - 1] if lo > 0 else 0.0
            
            if v_up == 0.0 and v_dn == 0.0:
                break
            
            if v_up >= v_dn:
                hi += 1
                accum += v_up
            else:
                lo -= 1
                accum += v_dn
        
        return hi, lo

    def _build_profile(self, box_start_bar, current_bar):
        """Build volume profile for the current box"""
        if box_start_bar < 0 or current_bar < box_start_bar:
            return np.nan, np.nan, np.nan, np.nan, np.nan
        
        bars_in_box = min(current_bar - box_start_bar + 1, 999)
        
        if bars_in_box < 1:
            return np.nan, np.nan, np.nan, np.nan, np.nan
        
        # Get range
        r_hi = np.max(self.data.High[max(0, current_bar - bars_in_box + 1):current_bar + 1])
        r_lo = np.min(self.data.Low[max(0, current_bar - bars_in_box + 1):current_bar + 1])
        
        price_step = (r_hi - r_lo) / self.num_rows
        
        if price_step <= 0:
            return np.nan, np.nan, np.nan, np.nan, np.nan
        
        # Build volume array
        vol_arr = np.zeros(self.num_rows)
        
        for b in range(max(0, current_bar - bars_in_box + 1), current_bar + 1):
            b_h = self.data.High[b]
            b_l = self.data.Low[b]
            b_v = self.data.Volume[b] if b < len(self.data.Volume) else 0
            b_rng = b_h - b_l
            
            for lvl in range(self.num_rows):
                lvl_lo = r_lo + lvl * price_step
                lvl_hi = lvl_lo + price_step
                
                if b_h >= lvl_lo and b_l < lvl_hi:
                    alloc = (b_v * price_step / b_rng) if b_rng > 0 else b_v
                    vol_arr[lvl] += alloc
        
        # Find POC
        poc_i = np.argmax(vol_arr)
        poc = r_lo + (poc_i + 0.5) * price_step
        
        # Find value area
        va_hi, va_lo = self._value_area(vol_arr, poc_i, self.num_rows, self.va_percent)
        vah = r_lo + (va_hi + 1.0) * price_step
        val = r_lo + va_lo * price_step
        
        return vah, val, poc, r_hi, r_lo

    def next(self):
        current_bar = len(self.data) - 1
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Check for session start
        ny_hour = self._get_ny_hour(current_bar)
        is_session_start = ny_hour == self.session_start_hour
        
        # Check for trade closure
        trade_just_closed = self.prev_in_trade and not self.in_trade and self.reset_on_trade
        self.prev_in_trade = self.in_trade
        
        # Box reset logic
        if (is_session_start or trade_just_closed) and current_bar > 0:
            self.box_start_bar = current_bar
            self.box_active = True
            self.vah = np.nan
            self.val = np.nan
            self.poc = np.nan
        
        if self.box_start_bar == -1 and is_session_start:
            self.box_start_bar = current_bar
            self.box_active = True
        
        # Build profile
        if self.box_active and self.box_start_bar >= 0:
            vah, val, poc, p_hi, p_lo = self._build_profile(self.box_start_bar, current_bar)
            if not np.isnan(vah):
                self.vah = vah
                self.val = val
                self.poc = poc
                self.profile_hi = p_hi
                self.profile_lo = p_lo
        
        # Exit logic (run first)
        if self.in_trade:
            tp_hit = (self.is_long and current_high >= self.tp) or (not self.is_long and current_low <= self.tp)
            sl_hit = (self.is_long and current_low <= self.sl) or (not self.is_long and current_high >= self.sl)
            time_exit = (current_bar - self.entry_bar) >= self.max_bars
            
            if tp_hit or sl_hit or time_exit:
                self.in_trade = False
                if self.is_long:
                    self.sell()
                else:
                    self.buy()
        
        # Signal logic
        cd_ok = current_bar - self.last_sig_bar >= self.cooldown
        ready = not self.in_trade and cd_ok and self.box_active
        levels_set = not np.isnan(self.vah) and not np.isnan(self.val)
        
        buy_signal = False
        sell_signal = False
        
        if ready and levels_set and current_bar >= self.confirm_bars:
            # BUY signal: close was below VAL, now all recent closes above VAL
            buy_was_below = self.data.Close[current_bar - self.confirm_bars] < self.val
            buy_all_above = True
            for i in range(self.confirm_bars):
                if self.data.Close[current_bar - i] <= self.val:
                    buy_all_above = False
            
            rsi_val = self.rsi[-1] if not np.isnan(self.rsi[-1]) else 50
            buy_signal = buy_was_below and buy_all_above and rsi_val < self.rsi_ob
            
            # SELL signal: close was above VAH, now all recent closes below VAH
            sell_was_above = self.data.Close[current_bar - self.confirm_bars] > self.vah
            sell_all_below = True
            for i in range(self.confirm_bars):
                if self.data.Close[current_bar - i] >= self.vah:
                    sell_all_below = False
            
            sell_signal = sell_was_above and sell_all_below and rsi_val > self.rsi_os
        
        # Entry logic
        if buy_signal and not self.in_trade:
            self.in_trade = True
            self.is_long = True
            self.entry_bar = current_bar
            self.entry_price = current_close
            self.last_sig_bar = current_bar
            self.tp = current_close * (1 + self.tp_pct / 100)
            self.sl = current_close * (1 - self.sl_pct / 100)
            self.buy()
        
        elif sell_signal and not self.in_trade:
            self.in_trade = True
            self.is_long = False
            self.entry_bar = current_bar
            self.entry_price = current_close
            self.last_sig_bar = current_bar
            self.tp = current_close * (1 - self.tp_pct / 100)
            self.sl = current_close * (1 + self.sl_pct / 100)
            self.sell()