import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.h4 = (high + low + close + close) / 4.0
        self.atr14 = self.I(pta.atr, high, low, close, length=14)
        self.eqMid = self.I(pta.ema, self.h4, length=21)
        self.emaFast = self.I(pta.ema, self.h4, length=6)
        
        self.mom = self.I(lambda: (self.emaFast - self.emaFast.shift(1)) / (self.atr14 + 1e-8))
        self.disp = self.I(lambda: (self.h4 - self.eqMid) / (self.atr14 + 0.5))
        
        self.angle = self.I(lambda: self._compute_angle())
        self.f369 = self.I(lambda: self._compute_f369())
        self.fGann = self.I(lambda: self._compute_fGann())
        self.fPitch = self.I(lambda: self._compute_fPitch(high, low, close))
        self.fPress = self.I(lambda: self._compute_fPress())
        
        self.confRT = self.I(lambda: self._compute_confRT())
        self.dirBias = self.I(lambda: self._compute_dirBias())
        
        self.P_long = self.I(lambda: np.clip(self.confRT * self.dirBias, 0, 1))
        self.P_short = self.I(lambda: np.clip(self.confRT * (1 - self.dirBias), 0, 1))
        
        self.last_long_bar = -999
        self.last_short_bar = -999

    def _compute_angle(self):
        baseAngle = 0
        disp_vals = self.disp[-1] if len(self.disp) > 0 else 0
        mom_vals = self.mom[-1] if len(self.mom) > 0 else 1e-8
        angle_rad = np.arctan(disp_vals / (mom_vals if mom_vals != 0 else 1e-8))
        angle_deg = np.degrees(angle_rad) + baseAngle
        return ((angle_deg % 360) + 360) % 360

    def _compute_f369(self):
        step369 = 360.0 / 369.0
        angle_val = self.angle[-1] if len(self.angle) > 0 else 0
        bin369 = round(angle_val / step369)
        return 1.0 if bin369 % 3 == 0 or bin369 % 6 == 0 else 0.0

    def _compute_fGann(self):
        gannDiv = 8
        angTol = 7.0
        gannStep = 360.0 / gannDiv
        angle_val = self.angle[-1] if len(self.angle) > 0 else 0
        nearest_gann = round(angle_val / gannStep) * gannStep
        delta = abs(((angle_val - nearest_gann) % 360 + 360) % 360)
        delta = min(delta, 360 - delta)
        return max(0.0, 1.0 - delta / max(1.0, angTol * 2.0))

    def _compute_fPitch(self, high, low, close):
        fibA, fibB, fibC = 15, 34, 61
        ampA, ampB, ampC = 0.8, 1.0, 1.2
        
        atr_val = self.atr14[-1] if len(self.atr14) > 0 else 1.0
        close_val = close.iloc[-1] if len(close) > 0 else 0
        h4_val = self.h4.iloc[-1] if len(self.h4) > 0 else close_val
        
        pfMidA = h4_val - (atr_val * 0.15)
        pfMidB = h4_val - (atr_val * 0.20)
        pfMidC = h4_val - (atr_val * 0.25)
        
        dA = min(abs(close_val - pfMidA), abs(close_val - (pfMidA + atr_val * ampA)), abs(close_val - (pfMidA - atr_val * ampA)))
        dB = min(abs(close_val - pfMidB), abs(close_val - (pfMidB + atr_val * ampB)), abs(close_val - (pfMidB - atr_val * ampB)))
        dC = min(abs(close_val - pfMidC), abs(close_val - (pfMidC + atr_val * ampC)), abs(close_val - (pfMidC - atr_val * ampC)))
        
        dMinATR = min(dA, dB, dC) / (atr_val + 1e-8)
        touchATR = 0.35
        return max(0.0, 1.0 - dMinATR / max(1e-6, touchATR * 2.0))

    def _compute_fPress(self):
        atr_val = self.atr14[-1] if len(self.atr14) > 0 else 1.0
        disp_val = self.disp[-1] if len(self.disp) > 0 else 0
        press = abs(disp_val) / max(0.5, atr_val)
        return np.clip(1.0 / (1.0 + np.exp(-press + 1.0)), 0, 1)

    def _compute_confRT(self):
        w369, wGann, wPitch, wPress = 0.35, 0.20, 0.25, 0.20
        f369_val = self.f369[-1] if len(self.f369) > 0 else 0
        fGann_val = self.fGann[-1] if len(self.fGann) > 0 else 0
        fPitch_val = self.fPitch[-1] if len(self.fPitch) > 0 else 0
        fPress_val = self.fPress[-1] if len(self.fPress) > 0 else 0
        return np.clip(w369 * f369_val + wGann * fGann_val + wPitch * fPitch_val + wPress * fPress_val, 0, 1)

    def _compute_dirBias(self):
        angle_val = self.angle[-1] if len(self.angle) > 0 else 0
        mom_val = self.mom[-1] if len(self.mom) > 0 else 0
        
        if angle_val <= 90 or angle_val >= 330:
            longLean = 1.0
        elif angle_val >= 150 and angle_val <= 210:
            longLean = 0.0
        else:
            longLean = 0.3
        
        return longLean if mom_val >= 0 else 1.0 - longLean

    def next(self):
        confRT_val = self.confRT[-1] if len(self.confRT) > 0 else 0
        P_long_val = self.P_long[-1] if len(self.P_long) > 0 else 0
        P_short_val = self.P_short[-1] if len(self.P_short) > 0 else 0
        
        sigMinConf = 0.55
        sigMinProb = 0.55
        sigCooldown = 3
        
        passConf = confRT_val >= sigMinConf
        passProb = max(P_long_val, P_short_val) >= sigMinProb
        isLongDir = P_long_val >= P_short_val
        isShortDir = P_short_val > P_long_val
        
        passCooldownL = (len(self.data) - self.last_long_bar) >= sigCooldown
        passCooldownS = (len(self.data) - self.last_short_bar) >= sigCooldown
        
        if passConf and passProb and isLongDir and passCooldownL:
            if not self.position:
                self.buy()
            self.last_long_bar = len(self.data)
        elif passConf and passProb and isShortDir and passCooldownS:
            if self.position:
                self.position.close()
            self.last_short_bar = len(self.data)
        elif self.position and P_long_val < 0.30:
            self.position.close()


