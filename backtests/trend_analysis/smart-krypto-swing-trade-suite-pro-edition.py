import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    htf_length = 50
    ob_delta_pct = 60
    vol_mult = 2.0
    div_lookback = 5
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume indicators
        self.avg_vol = self.I(pta.sma, volume, length=20)
        self.is_whale = volume > (self.avg_vol * self.vol_mult)
        
        # Delta and CVD calculation
        tw = high - low
        buy_vol = np.where(tw == 0, 0, volume * ((close - low) / tw))
        sell_vol = np.where(tw == 0, 0, volume * ((high - close) / tw))
        delta = buy_vol - sell_vol
        self.cvd = self.I(lambda: pd.Series(np.cumsum(delta)))
        
        # Pivot points for divergence
        self.pivot_low = self.I(pta.pivotlow, low, length=self.div_lookback)
        self.pivot_high = self.I(pta.pivothigh, high, length=self.div_lookback)
        
        # Trend indicators
        self.ema50 = self.I(pta.ema, close, length=50)
        self.wma200 = self.I(pta.wma, close, length=200)
        
        # HTF zones calculation
        self.htf_high = self.I(lambda: high.rolling(self.htf_length).max())
        self.htf_low = self.I(lambda: low.rolling(self.htf_length).min())
        
        # Range and zone calculations
        self.range_p = self.htf_high - self.htf_low
        self.a_sup = self.htf_high - (self.range_p * 0.05)
        self.a_dem = self.htf_low + (self.range_p * 0.05)
        
        # Track previous divergence state
        self.prev_divergence_bull = False
        self.prev_divergence_bear = False
        self.in_demand = False
        self.in_supply = False
        
    def next(self):
        # Update zone membership
        if len(self.data) > 1:
            self.in_demand = self.data.Low[-2] <= self.a_dem[-1]
            self.in_supply = self.data.High[-2] >= self.a_sup[-1]
        
        # FVG Bull condition: low > high[2] and price in demand zone
        fvg_bull = (len(self.data) > 2 and 
                   self.data.Low[-1] > self.data.High[-3] and 
                   self.in_demand)
        
        # FVG Bear condition: high < low[2] and price in supply zone
        fvg_bear = (len(self.data) > 2 and 
                   self.data.High[-1] < self.data.Low[-3] and 
                   self.in_supply)
        
        # Order Block Bull: price action with volume confirmation
        if len(self.data) > 1:
            pa_bull_e = (self.data.Close[-2] < self.data.Open[-2] and 
                        self.data.Close[-1] > self.data.Open[-1] and 
                        self.data.Close[-1] > self.data.High[-2] and 
                        (self.data.Close[-1] - self.data.Open[-1]) > 
                        (self.data.Open[-2] - self.data.Close[-2]) * 1.2)
            
            pa_bear_e = (self.data.Close[-2] > self.data.Open[-2] and 
                        self.data.Close[-1] < self.data.Open[-1] and 
                        self.data.Close[-1] < self.data.Low[-2] and 
                        (self.data.Open[-1] - self.data.Close[-1]) > 
                        (self.data.Close[-2] - self.data.Open[-2]) * 1.2)
            
            ob_vol_valid = self.data.Volume[-1] > self.avg_vol[-1]
            
            tw = self.data.High[-1] - self.data.Low[-1]
            if tw > 0:
                buy_vol_curr = self.data.Volume[-1] * ((self.data.Close[-1] - self.data.Low[-1]) / tw)
                sell_vol_curr = self.data.Volume[-1] * ((self.data.High[-1] - self.data.Close[-1]) / tw)
            else:
                buy_vol_curr = 0
                sell_vol_curr = 0
            
            bull_delta_valid = buy_vol_curr > (self.data.Volume[-1] * (self.ob_delta_pct / 100))
            bear_delta_valid = sell_vol_curr > (self.data.Volume[-1] * (self.ob_delta_pct / 100))
            
            is_bull_ob = pa_bull_e and ob_vol_valid and bull_delta_valid
            is_bear_ob = pa_bear_e and ob_vol_valid and bear_delta_valid
            
            # Divergence detection
            b_div = False
            s_div = False
            
            if not np.isnan(self.pivot_low[-1]):
                if (self.pivot_low[-1] < self.pivot_low[-self.div_lookback-1] and 
                    self.cvd[-self.div_lookback] > self.cvd[-1]):
                    b_div = True
            
            if not np.isnan(self.pivot_high[-1]):
                if (self.pivot_high[-1] > self.pivot_high[-self.div_lookback-1] and 
                    self.cvd[-self.div_lookback] < self.cvd[-1]):
                    s_div = True
            
            # Trading logic
            # Buy signals
            if (fvg_bull or is_bull_ob or b_div) and not self.position:
                self.buy()
            
            # Sell signals
            elif (fvg_bear or is_bear_ob or s_div) and self.position:
                self.position.close()
            
            # Trend-based exits
            if self.position and self.data.Close[-1] < self.wma200[-1]:
                self.position.close()
            
            if not self.position and self.data.Close[-1] > self.ema50[-1]:
                self.buy()