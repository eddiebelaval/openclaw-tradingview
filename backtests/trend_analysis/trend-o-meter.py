import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookbackPeriod = 20

    def init(self):
        pass

    def next(self):
        if len(self.data) < 5:
            return

        # Detect fractals
        high = self.data.High
        low = self.data.Low
        close = self.data.Close

        # Up fractal: high[2] > high[0,1,3,4]
        up_fractal = (
            high[-3] > high[-1] and
            high[-3] > high[-2] and
            high[-3] > high[-5] and
            high[-3] > high[-4]
        )

        # Down fractal: low[2] < low[0,1,3,4]
        down_fractal = (
            low[-3] < low[-1] and
            low[-3] < low[-2] and
            low[-3] < low[-5] and
            low[-3] < low[-4]
        )

        # Initialize storage on first run
        if not hasattr(self, 'fractal_high_levels'):
            self.fractal_high_levels = []
            self.fractal_high_bars = []
            self.fractal_high_broken = []
            self.fractal_low_levels = []
            self.fractal_low_bars = []
            self.fractal_low_broken = []

        # Save fractals
        if up_fractal:
            h_level = high[-3]
            if h_level not in self.fractal_high_levels:
                self.fractal_high_levels.append(h_level)
                self.fractal_high_bars.append(len(self.data) - 3)
                self.fractal_high_broken.append(False)

        if down_fractal:
            l_level = low[-3]
            if l_level not in self.fractal_low_levels:
                self.fractal_low_levels.append(l_level)
                self.fractal_low_bars.append(len(self.data) - 3)
                self.fractal_low_broken.append(False)

        # Limit fractals to lookbackPeriod
        total_fractals = len(self.fractal_high_levels) + len(self.fractal_low_levels)
        while total_fractals > self.lookbackPeriod:
            if len(self.fractal_high_levels) > len(self.fractal_low_levels):
                self.fractal_high_levels.pop(0)
                self.fractal_high_bars.pop(0)
                self.fractal_high_broken.pop(0)
            else:
                self.fractal_low_levels.pop(0)
                self.fractal_low_bars.pop(0)
                self.fractal_low_broken.pop(0)
            total_fractals -= 1

        # Analyze breakouts
        bullish_breaks = 0
        bearish_breaks = 0

        for i, lvl in enumerate(self.fractal_high_levels):
            if close[-1] > lvl:
                bullish_breaks += 1
                if not self.fractal_high_broken[i]:
                    self.fractal_high_broken[i] = True

        for i, lvl in enumerate(self.fractal_low_levels):
            if close[-1] < lvl:
                bearish_breaks += 1
                if not self.fractal_low_broken[i]:
                    self.fractal_low_broken[i] = True

        # Calculate power
        total_breaks = bullish_breaks + bearish_breaks
        if total_breaks > 0:
            bullish_power = (bullish_breaks / total_breaks) * 100
            bearish_power = (bearish_breaks / total_breaks) * 100
        else:
            bullish_power = 50
            bearish_power = 50

        # Trading logic based on power signals
        if bullish_power >= 70 and bullish_power > bearish_power:
            if not self.position:
                self.buy()
        elif bearish_power >= 70 and bearish_power > bullish_power:
            if self.position:
                self.position.close()
        elif bullish_power >= 60 and bullish_power > bearish_power:
            if not self.position:
                self.buy()
        elif bearish_power >= 60 and bearish_power > bullish_power:
            if self.position:
                self.position.close()


