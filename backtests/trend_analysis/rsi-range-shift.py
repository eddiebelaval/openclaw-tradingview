import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI Settings
    rsi_len = 14
    
    # Zone Levels
    ob_level = 70
    os_level = 30
    mid_level = 50
    
    # Signal Settings
    show_signals = True
    sig_on_shift = True
    sig_on_obos = False

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)

    def next(self):
        if len(self.data) < self.rsi_len + 1:
            return
        
        rsi_current = self.rsi[-1]
        rsi_prev = self.rsi[-2]
        
        # Range detection
        is_bullish = rsi_current >= self.mid_level
        was_bullish = rsi_prev >= self.mid_level
        
        # Range shifts (crossovers of midline)
        bullish_shift = rsi_prev < self.mid_level and rsi_current >= self.mid_level
        bearish_shift = rsi_prev >= self.mid_level and rsi_current < self.mid_level
        
        # OB / OS crosses
        cross_above_ob = rsi_prev <= self.ob_level and rsi_current > self.ob_level
        cross_below_ob = rsi_prev >= self.ob_level and rsi_current < self.ob_level
        cross_above_os = rsi_prev <= self.os_level and rsi_current > self.os_level
        cross_below_os = rsi_prev >= self.os_level and rsi_current < self.os_level
        
        # Signal logic
        buy_signal = (self.sig_on_shift and bullish_shift) or \
                     (self.sig_on_obos and cross_above_os)
        
        sell_signal = (self.sig_on_shift and bearish_shift) or \
                      (self.sig_on_obos and cross_below_ob)
        
        # Trading logic
        if self.show_signals:
            if buy_signal and not self.position:
                self.buy()
            elif sell_signal and self.position:
                self.sell()