import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma1_len = 100
    ma2_len = 200
    ma_type = "SMA"
    swing_lookback = 30
    pip_buffer = 10
    risk_reward_ratio = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate moving averages based on type
        if self.ma_type == "SMA":
            self.ma1 = self.I(pta.sma, close, length=self.ma1_len)
            self.ma2 = self.I(pta.sma, close, length=self.ma2_len)
        elif self.ma_type == "EMA":
            self.ma1 = self.I(pta.ema, close, length=self.ma1_len)
            self.ma2 = self.I(pta.ema, close, length=self.ma2_len)
        elif self.ma_type == "SMMA (RMA)":
            self.ma1 = self.I(pta.rma, close, length=self.ma1_len)
            self.ma2 = self.I(pta.rma, close, length=self.ma2_len)
        elif self.ma_type == "WMA":
            self.ma1 = self.I(pta.wma, close, length=self.ma1_len)
            self.ma2 = self.I(pta.wma, close, length=self.ma2_len)
        elif self.ma_type == "VWMA":
            self.ma1 = self.I(pta.vwma, close, volume, length=self.ma1_len)
            self.ma2 = self.I(pta.vwma, close, volume, length=self.ma2_len)
        else:
            self.ma1 = self.I(pta.sma, close, length=self.ma1_len)
            self.ma2 = self.I(pta.sma, close, length=self.ma2_len)
        
        # Swing high/low detection
        self.swing_low = self.I(lambda: low.rolling(self.swing_lookback).min())
        self.swing_high = self.I(lambda: high.rolling(self.swing_lookback).max())

    def next(self):
        # Ensure we have enough data
        if len(self.data) < max(self.ma1_len, self.ma2_len, self.swing_lookback):
            return
        
        # Calculate pip value (assuming 4 decimal places for forex)
        pip_value = 0.0001
        
        # Check for crossover conditions
        if crossover(self.ma1, self.ma2):
            # Long condition
            entry_price = self.data.Close[-1]
            sl_price = self.swing_low[-1] - (self.pip_buffer * pip_value)
            risk = abs(entry_price - sl_price)
            tp_price = entry_price + (risk * self.risk_reward_ratio)
            
            self.buy()
        
        elif crossover(self.ma2, self.ma1):
            # Short condition
            entry_price = self.data.Close[-1]
            sl_price = self.swing_high[-1] + (self.pip_buffer * pip_value)
            risk = abs(entry_price - sl_price)
            tp_price = entry_price - (risk * self.risk_reward_ratio)
            
            self.sell()
        
        # Exit logic based on position
        if self.position:
            if self.position.is_long:
                sl_price = self.swing_low[-1] - (self.pip_buffer * pip_value)
                if self.data.Close[-1] <= sl_price:
                    self.position.close()
            elif self.position.is_short:
                sl_price = self.swing_high[-1] + (self.pip_buffer * pip_value)
                if self.data.Close[-1] >= sl_price:
                    self.position.close()


