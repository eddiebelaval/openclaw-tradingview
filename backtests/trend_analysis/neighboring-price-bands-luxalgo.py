import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    buffer_size = 200
    k_neighbors = 50
    percentile = 90
    smooth = 5

    def init(self):
        self.price_array = []
        self.sorted_array = []
        self.bull_values = []
        self.bear_values = []
        
        self.bull_band = self.I(self._calculate_bull_band)
        self.bear_band = self.I(self._calculate_bear_band)
        self.avg_band = self.I(self._calculate_avg_band)

    def _calculate_bull_band(self):
        result = []
        for i in range(len(self.data)):
            close = self.data.Close[i]
            
            if len(self.price_array) >= self.buffer_size:
                self.price_array.pop(0)
                old_val = self.price_array[0] if self.price_array else None
                if old_val is not None and old_val in self.sorted_array:
                    self.sorted_array.remove(old_val)
            
            self.price_array.append(close)
            self._add_value_sorted(close)
            
            bull_val = self._calculate_bull_component()
            self.bull_values.append(bull_val)
            result.append(bull_val)
        
        bull_series = pd.Series(result)
        smoothed = bull_series.rolling(window=self.smooth).mean()
        return smoothed

    def _calculate_bear_band(self):
        result = []
        for i in range(len(self.data)):
            bear_val = self._calculate_bear_component()
            self.bear_values.append(bear_val)
            result.append(bear_val)
        
        bear_series = pd.Series(result)
        smoothed = bear_series.rolling(window=self.smooth).mean()
        return smoothed

    def _calculate_avg_band(self):
        bull_series = pd.Series(self.bull_values)
        bear_series = pd.Series(self.bear_values)
        return (bull_series + bear_series) / 2

    def _add_value_sorted(self, val):
        if len(self.sorted_array) == 0:
            self.sorted_array.append(val)
        else:
            idx = 0
            for i, v in enumerate(self.sorted_array):
                if val <= v:
                    idx = i
                    break
                idx = i + 1
            self.sorted_array.insert(idx, val)

    def _calculate_bull_component(self):
        if len(self.sorted_array) == 0:
            return np.nan
        
        close = self.data.Close[-1]
        idx = self._binary_search_leftmost(self.sorted_array, close)
        size = len(self.sorted_array)
        
        bull_end = min(size - 1, idx + self.k_neighbors)
        if bull_end > idx:
            bull_slice = self.sorted_array[idx:bull_end + 1]
            bull_val = self._get_percentile(bull_slice, self.percentile)
            return bull_val
        
        return np.nan

    def _calculate_bear_component(self):
        if len(self.sorted_array) == 0:
            return np.nan
        
        close = self.data.Close[-1]
        idx = self._binary_search_leftmost(self.sorted_array, close)
        
        bear_start = max(0, idx - self.k_neighbors)
        if idx > bear_start:
            bear_slice = self.sorted_array[bear_start:idx]
            bear_val = self._get_percentile(bear_slice, 100 - self.percentile)
            return bear_val
        
        return np.nan

    def _binary_search_leftmost(self, arr, val):
        left, right = 0, len(arr)
        while left < right:
            mid = (left + right) // 2
            if arr[mid] < val:
                left = mid + 1
            else:
                right = mid
        return left

    def _get_percentile(self, arr, p):
        if len(arr) == 0:
            return np.nan
        
        sorted_arr = sorted(arr)
        idx = (len(sorted_arr) - 1) * p / 100
        i1 = int(np.floor(idx))
        i2 = int(np.ceil(idx))
        
        if i1 == i2:
            return sorted_arr[i1]
        else:
            v1 = sorted_arr[i1]
            v2 = sorted_arr[i2]
            return v1 + (v2 - v1) * (idx - i1)

