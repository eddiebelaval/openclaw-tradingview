import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 3
    atr_mult = 0.5
    vol_len = 50
    vol_spike = 1.5
    lev1 = 50
    lev2 = 100
    mode = "Combo"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.vol_ma = self.I(pta.sma, volume, length=self.vol_len)
        self.vol_max = self.I(lambda: high.rolling(window=self.vol_len).max())
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        self.struct_zones_top = []
        self.struct_zones_bot = []
        self.math_levels = []
        self.last_zone_index = -1
        self.last_math_index = -1

    def next(self):
        if len(self.data) < self.pivot_len + 1:
            return
        
        current_idx = len(self.data) - 1
        high = self.data.High
        low = self.data.Low
        close = self.data.Close
        volume = self.data.Volume
        
        # Structural Mode
        if self.mode in ["Structural", "Combo"]:
            # Detect pivots
            if current_idx >= 2 * self.pivot_len:
                pivot_idx = current_idx - self.pivot_len
                
                # Check for pivot high
                is_pivot_high = True
                for i in range(1, self.pivot_len + 1):
                    if high[pivot_idx] <= high[pivot_idx - i] or high[pivot_idx] <= high[pivot_idx + i]:
                        is_pivot_high = False
                        break
                
                # Check for pivot low
                is_pivot_low = True
                for i in range(1, self.pivot_len + 1):
                    if low[pivot_idx] >= low[pivot_idx - i] or low[pivot_idx] >= low[pivot_idx + i]:
                        is_pivot_low = False
                        break
                
                if is_pivot_high:
                    atr_val = self.atr[-1] * self.atr_mult if self.atr[-1] is not None else 0.01
                    vol_val = volume[pivot_idx]
                    vol_ma_val = self.vol_ma[pivot_idx]
                    vol_max_val = self.vol_max[pivot_idx]
                    
                    intensity = min(1.0, max(0.0, (vol_val - vol_ma_val) / (vol_max_val - vol_ma_val + 1e-6)))
                    self.struct_zones_top.append({
                        'price': high[pivot_idx],
                        'atr': atr_val,
                        'intensity': intensity,
                        'created_at': pivot_idx
                    })
                
                if is_pivot_low:
                    atr_val = self.atr[-1] * self.atr_mult if self.atr[-1] is not None else 0.01
                    vol_val = volume[pivot_idx]
                    vol_ma_val = self.vol_ma[pivot_idx]
                    vol_max_val = self.vol_max[pivot_idx]
                    
                    intensity = min(1.0, max(0.0, (vol_val - vol_ma_val) / (vol_max_val - vol_ma_val + 1e-6)))
                    self.struct_zones_bot.append({
                        'price': low[pivot_idx],
                        'atr': atr_val,
                        'intensity': intensity,
                        'created_at': pivot_idx
                    })
            
            # Check if price hits zones
            for zone in self.struct_zones_top[:]:
                if high[current_idx] >= zone['price'] and low[current_idx] <= zone['price']:
                    self.struct_zones_top.remove(zone)
                    if not self.position:
                        self.sell()
            
            for zone in self.struct_zones_bot[:]:
                if high[current_idx] >= zone['price'] and low[current_idx] <= zone['price']:
                    self.struct_zones_bot.remove(zone)
                    if not self.position:
                        self.buy()
        
        # Leveraged Math Mode
        if self.mode in ["Leveraged Math", "Combo"]:
            vol_ma_val = self.vol_ma[-1]
            vol_max_val = self.vol_max[-1]
            
            if vol_ma_val is not None and vol_max_val is not None and vol_ma_val > 0:
                is_spike = (volume[-1] / vol_ma_val) >= self.vol_spike
                
                if is_spike and volume[-1] > 0:
                    intensity = min(1.0, max(0.0, (volume[-1] - vol_ma_val) / (vol_max_val - vol_ma_val + 1e-6)))
                    
                    s1 = high[-1] * (1 + (1 / self.lev1))
                    s2 = high[-1] * (1 + (1 / self.lev2))
                    l1 = low[-1] * (1 - (1 / self.lev1))
                    l2 = low[-1] * (1 - (1 / self.lev2))
                    
                    for lvl in [s1, s2, l1, l2]:
                        self.math_levels.append({
                            'price': lvl,
                            'intensity': intensity,
                            'created_at': current_idx
                        })
            
            # Check if price hits math levels
            for level in self.math_levels[:]:
                if high[current_idx] >= level['price'] and low[current_idx] <= level['price']:
                    self.math_levels.remove(level)
                    if level['price'] > close[current_idx]:
                        if not self.position:
                            self.sell()
                    else:
                        if not self.position:
                            self.buy()


