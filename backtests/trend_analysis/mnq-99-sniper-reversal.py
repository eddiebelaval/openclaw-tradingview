import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR for displacement filter
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Calculate volume SMA for volume spike confirmation
        self.vol_sma = self.I(pta.sma, volume, length=20)
        
        # Store PDH and PDL (Previous Day High/Low)
        # We'll calculate these in next() based on daily bars
        self.pdh_series = pd.Series(np.nan, index=close.index)
        self.pdl_series = pd.Series(np.nan, index=close.index)
        
        # Track previous day's high and low
        self.prev_pdh = 0
        self.prev_pdl = 0
        self.prev_date = None

    def next(self):
        # Update PDH/PDL at the start of each new day
        current_date = pd.Timestamp(self.data.index[-1]).date()
        
        if self.prev_date is None or current_date != self.prev_date:
            if len(self.data) > 1:
                # Previous day's high and low
                self.prev_pdh = max(self.data.High[-2], self.prev_pdh) if self.prev_pdh > 0 else self.data.High[-2]
                self.prev_pdl = min(self.data.Low[-2], self.prev_pdl) if self.prev_pdl > 0 else self.data.Low[-2]
            self.prev_date = current_date
        
        # If PDH and PDL haven't been set yet, skip
        if self.prev_pdh == 0 or self.prev_pdl == 0:
            return
        
        pdh = self.prev_pdh
        pdl = self.prev_pdl
        
        # Get current values
        open_price = self.data.Open[-1]
        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        vol = self.data.Volume[-1]
        
        # Check if we have enough data for indicators
        if self.atr[-1] is None or self.vol_sma[-1] is None:
            return
        
        atr_val = self.atr[-1]
        vol_sma_val = self.vol_sma[-1]
        
        # 1. Institutional Time Window (10:00-11:00 AM EST / 23456 = Mon-Fri)
        current_hour = pd.Timestamp(self.data.index[-1]).hour
        current_minute = pd.Timestamp(self.data.index[-1]).minute
        is_killzone = (current_hour == 10) or (current_hour == 11 and current_minute == 0)
        
        # 2. Displacement filter: abs(open - close) > ATR * 1.5
        displacement = abs(open_price - close_price) > atr_val * 1.5
        
        # 3. Volume spike: volume > SMA(volume, 20) * 1.2
        vol_spike = vol > vol_sma_val * 1.2
        
        # 4. Long Sniper: Price swept PDL + Reclaimed it + During Killzone + Displacement + Vol Spike
        long_sniper = (low_price < pdl and close_price > pdl and 
                       is_killzone and displacement and vol_spike)
        
        # 5. Short Sniper: Price swept PDH + Reclaimed it + During Killzone + Displacement + Vol Spike
        short_sniper = (high_price > pdh and close_price < pdh and 
                        is_killzone and displacement and vol_spike)
        
        # Entry logic
        if long_sniper:
            if not self.position:
                self.buy()
        
        if short_sniper:
            if self.position:
                self.position.close()
            else:
                self.sell()
        
        # Simple exit logic: close on opposite signal or after some bars
        if self.position:
            # Close long if short signal appears
            if self.position.is_long and short_sniper:
                self.position.close()
            # Close short if long signal appears
            elif self.position.is_short and long_sniper:
                self.position.close()


