import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.wma_baseline = self.I(pta.wma, close, length=50)
        self.atr = self.I(pta.atr, high, low, close, length=14)
        self.atr_smooth = self.I(pta.ema, self.atr, length=5)
        self.rsi = self.I(pta.rsi, close, length=14)
        self.adx_result = self.I(pta.adx, high, low, close, length=14)
        self.volume_ma = self.I(pta.sma, volume, length=20)
        self.vwap = self.I(pta.vwap, high, low, close, volume)
        
        # Swing detection
        self.swingHigh = self.I(lambda: high.rolling(window=11, center=True).max())
        self.swingLow = self.I(lambda: low.rolling(window=11, center=True).min())
        
        # Volatility band calculation
        self.band_width = self.I(lambda: (2.0 * self.atr_smooth) if self.atr_smooth is not None else pd.Series(0, index=close.index))
        self.upper_band = self.I(lambda: self.wma_baseline + self.band_width)
        self.lower_band = self.I(lambda: self.wma_baseline - self.band_width)
        
        # State tracking
        self.market_trend = 0
        self.last_swing_high = None
        self.last_swing_low = None
        self.trend_bars = 0
        self.last_signal_bar = -100
        self.last_signal_dir = 0

    def next(self):
        # Get current values
        curr_close = self.data.Close[-1]
        curr_high = self.data.High[-1]
        curr_low = self.data.Low[-1]
        curr_volume = self.data.Volume[-1]
        curr_atr = self.atr[-1] if len(self.atr) > 0 else 0
        curr_rsi = self.rsi[-1] if len(self.rsi) > 0 else 50
        curr_baseline = self.wma_baseline[-1] if len(self.wma_baseline) > 0 else curr_close
        curr_upper = self.upper_band[-1] if len(self.upper_band) > 0 else curr_close + curr_atr
        curr_lower = self.lower_band[-1] if len(self.lower_band) > 0 else curr_close - curr_atr
        curr_vol_avg = self.volume_ma[-1] if len(self.volume_ma) > 0 else curr_volume
        
        # Swing tracking
        if len(self.swingHigh) > 0 and not np.isnan(self.swingHigh[-1]):
            if self.last_swing_high is None or self.swingHigh[-1] != self.last_swing_high:
                self.last_swing_high = self.swingHigh[-1]
        
        if len(self.swingLow) > 0 and not np.isnan(self.swingLow[-1]):
            if self.last_swing_low is None or self.swingLow[-1] != self.last_swing_low:
                self.last_swing_low = self.swingLow[-1]
        
        # Trend detection
        bullish_break = (self.last_swing_high is not None and 
                        curr_close > self.last_swing_high and 
                        self.market_trend != 1)
        
        bearish_break = (self.last_swing_low is not None and 
                        curr_close < self.last_swing_low and 
                        self.market_trend != -1)
        
        # Confluence factors
        volume_surge = curr_volume > 1.5 * curr_vol_avg
        rsi_not_extreme_bull = curr_rsi < 75
        rsi_not_extreme_bear = curr_rsi > 25
        
        # Bullish signal conditions
        bullish_signal = (bullish_break and 
                         rsi_not_extreme_bull and
                         curr_close > curr_baseline and
                         volume_surge)
        
        # Bearish signal conditions
        bearish_signal = (bearish_break and 
                         rsi_not_extreme_bear and
                         curr_close < curr_baseline and
                         volume_surge)
        
        # Anti-whipsaw: require at least 5 bars between opposing signals
        bars_since_last = len(self.data) - self.last_signal_bar
        
        if bullish_signal:
            if self.last_signal_dir != -1 or bars_since_last >= 5:
                if not self.position:
                    self.buy()
                    self.market_trend = 1
                    self.trend_bars = 0
                    self.last_signal_bar = len(self.data)
                    self.last_signal_dir = 1
        
