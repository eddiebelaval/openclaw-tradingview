import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen = 50
    rr = 2.0
    lookback = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Trend EMA
        self.ema = self.I(pta.ema, close, length=self.emaLen)

        # Breakout levels
        self.highest_high = self.I(lambda: high.rolling(self.lookback).max())
        self.lowest_low = self.I(lambda: low.rolling(self.lookback).min())

        # ATR for risk management
        self.atr = self.I(pta.atr, high, low, close, length=14)

    def next(self):
        if len(self.data) < self.lookback + 1:
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        ema_val = self.ema[-1]
        highest_high_val = self.highest_high[-1]
        lowest_low_val = self.lowest_low[-1]
        
        if len(self.highest_high) >= 2:
            highest_high_prev = self.highest_high[-2]
        else:
            highest_high_prev = highest_high_val
            
        if len(self.lowest_low) >= 2:
            lowest_low_prev = self.lowest_low[-2]
        else:
            lowest_low_prev = lowest_low_val

        atr_val = self.atr[-1] if self.atr[-1] is not None else 0

        # Trend filters
        bull_trend = close > ema_val
        bear_trend = close < ema_val

        # Buy setup
        buy_break = crossover(self.data.Close, self.I(lambda: pd.Series(highest_high_prev, index=self.data.index))) and bull_trend
        buy_retest = low <= highest_high_prev

        buy_condition = buy_break and buy_retest

        # Sell setup
        sell_break = crossover(self.I(lambda: pd.Series(lowest_low_prev, index=self.data.index)), self.data.Close) and bear_trend
        sell_retest = high >= lowest_low_prev

        sell_condition = sell_break and sell_retest

        # Risk management
        sl_buy = close - atr_val
        tp_buy = close + (atr_val * self.rr)

        sl_sell = close + atr_val
        tp_sell = close - (atr_val * self.rr)

        # Execution
        if buy_condition and not self.position:
            self.buy(sl=sl_buy, tp=tp_buy)

        if sell_condition and not self.position:
            self.sell(sl=sl_sell, tp=tp_sell)