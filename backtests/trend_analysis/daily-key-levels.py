    def get_ny_time(self, timestamp):
        """Convert timestamp to NY timezone and extract hour/minute"""
        from datetime import timezone, timedelta
        utc_dt = pd.Timestamp(timestamp, tz='UTC')
        ny_tz = timezone(timedelta(hours=-5))
        ny_dt = utc_dt.tz_convert(ny_tz)
        return ny_dt.hour, ny_dt.minute, ny_dt.day, ny_dt.month, ny_dt.year

    def get_session_key(self, timestamp):
        """Get session key by shifting time 18 hours back"""
        from datetime import timezone, timedelta
        utc_dt = pd.Timestamp(timestamp, tz='UTC')
        ny_tz = timezone(timedelta(hours=-5))
        ny_dt = utc_dt.tz_convert(ny_tz)
        
        shift_dt = ny_dt - pd.Timedelta(hours=18)
        key_year = shift_dt.year
        key_month = shift_dt.month
        key_dom = shift_dt.day
        
        return key_year * 10000 + key_month * 100 + key_dom

