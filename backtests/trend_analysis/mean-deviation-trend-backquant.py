import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    meanLen = 21
    devLen = 14
    devAccum = 8
    bandTight = 0.7
    bandWide = 2.6
    fadeThr = 0.3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Mean & Deviation Engine
        self.mean = self.I(pta.ema, close, length=self.meanLen)
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Signed deviation normalized by ATR
        def calc_raw_dev():
            return (close - self.mean) / (self.atr + 1e-10)
        self.rawDev = self.I(calc_raw_dev)
        
        # Smooth the instantaneous deviation
        def calc_dev_smooth():
            rd = calc_raw_dev()
            return pta.ema(rd, length=self.devLen) if rd is not None else pd.Series(0, index=close.index)
        self.devSmooth = self.I(calc_dev_smooth)
        
        # Cumulative deviation = rolling sum
        def calc_cum_dev():
            ds = calc_dev_smooth()
            return pta.sma(ds, length=self.devAccum) if ds is not None else pd.Series(0, index=close.index)
        self.cumDev = self.I(calc_cum_dev)
        
        # Absolute magnitude
        def calc_dev_abs():
            cd = self.cumDev
            return cd.abs()
        self.devAbs = self.I(calc_dev_abs)
        
        # Highest deviation over 80 bars
        def calc_dev_high():
            da = self.devAbs
            return da.rolling(window=80).max()
        self.devHigh = self.I(calc_dev_high)
        
        # Normalized deviation
        def calc_dev_norm():
            da = self.devAbs
            dh = self.devHigh
            return ((da / (dh + 1e-10)).clip(upper=1.0)).fillna(0)
        self.devNorm = self.I(calc_dev_norm)
        
        # Trend direction
        def calc_trend_dir():
            cd = self.cumDev
            return (cd > 0).astype(int) * 2 - 1
        self.tDir = self.I(calc_trend_dir)
        
        # Adaptive Band
        def calc_band_mult():
            dn = self.devNorm
            return self.bandWide - dn * (self.bandWide - self.bandTight)
        self.bandMult = self.I(calc_band_mult)
        
        def calc_band_w():
            bm = self.bandMult
            a = self.atr
            return a * bm
        self.bandW = self.I(calc_band_w)
        
        # Active Band calculation
        def calc_active_band():
            td = self.tDir
            m = self.mean
            bw = self.bandW
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if i == 0 or pd.isna(td.iloc[i]) or pd.isna(m.iloc[i]) or pd.isna(bw.iloc[i]):
                    result.iloc[i] = np.nan
                else:
                    if td.iloc[i] == 1:
                        result.iloc[i] = m.iloc[i] - bw.iloc[i]
                    else:
                        result.iloc[i] = m.iloc[i] + bw.iloc[i]
            return result
        self.activeBand = self.I(calc_active_band)
        
        # Smooth active band
        def calc_active_band_ema():
            ab = self.activeBand
            return pta.ema(ab.fillna(method='ffill'), length=3) if ab is not None else ab
        self.activeBandSmoothed = self.I(calc_active_band_ema)
        
        # Flip detection
        def calc_flip():
            td = self.tDir
            td_prev = td.shift(1)
            return (td != td_prev).astype(int)
        self.flip = self.I(calc_flip)
        
        # Peak tracking for levels - simplified
        self.peak_dev = 0.0
        self.peak_price = np.nan
        self.peak_dir = 0
        self.level_prices = []

    def next(self):
        if len(self) < self.meanLen + self.devLen:
            return
        
        # Get current values
        try:
            cum_dev = self.cumDev[-1]
            dev_abs = self.devAbs[-1]
            dev_norm = self.devNorm[-1]
            t_dir = self.tDir[-1]
            flip = self.flip[-1]
            atr = self.atr[-1]
            close = self.data.Close[-1]
            high = self.data.High[-1]
            low = self.data.Low[-1]
            
            # Update peak tracking
            if dev_abs > self.peak_dev:
                self.peak_dev = dev_abs
                self.peak_price = high if t_dir == 1 else low
                self.peak_dir = t_dir
            
            # Level planting: deviation faded from peak
            faded = self.peak_dev > 0.3 and dev_abs < self.peak_dev * self.fadeThr
            if faded and not np.isnan(self.peak_price):
                self.level_prices.append(self.peak_price)
                self.peak_dev = 0.0
                self.peak_price = np.nan
            
            # Keep only recent levels
            self.level_prices = [p for p in self.level_prices if abs(close - p) < atr * 5]
            
            # Trading Logic
            # Buy on bullish flip with strong deviation
            if flip and t_dir == 1 and dev_norm > 0.3:
                if not self.position:
                    self.buy()
            
            # Sell on bearish flip
            elif flip and t_dir == -1:
                if self.position:
                    self.sell()
            
            # Exit on touch of extreme deviation
            elif dev_norm > 0.85:
                if self.position:
                    self.sell()
            
            # Exit if price breaks resistance
            if self.position and t_dir == -1:
                self.sell()
                
        except (IndexError, TypeError):
            pass


