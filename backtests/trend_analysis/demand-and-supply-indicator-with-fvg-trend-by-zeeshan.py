class TvStrategy(Strategy):
    # ND/NS + POSSIBLE by Body parameters
    thin_body_pct = 0.6
    min_vol = 1.0
    show_possible = True
    baseline_len = 5
    opp_wick_factor = 1.0
    vol_sma_len = 20
    very_low_vol_factor = 0.6
    
    # Pivot parameters
    lb = 5
    rb = 5
    
    # FVG parameters
    fvg_left_bars = 5
    fvg_right_bars = 5
    fvg_box_length = 10
    fvg_expiry_bars = 100

    def init(self):
        # Pre-calculate volume SMA for POSSIBLE signals
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        self.vol_sma = self.I(pta.sma, volume, length=self.vol_sma_len)
        
        # Track pivot highs and lows
        self.prev_ph_price = None
        self.prev_pl_price = None
        self.last_buy_signal = False
        self.last_sell_signal = False
        
        # Track FVG boxes for entry signals
        self.fvg_bull_active = False
        self.fvg_bear_active = False

    def next(self):
        if len(self.data) < 3:
            return
        
        # Current bar data
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        # Previous bar data
        close_prev = self.data.Close[-2]
        open_prev = self.data.Open[-2]
        high_prev = self.data.High[-2]
        low_prev = self.data.Low[-2]
        volume_prev = self.data.Volume[-2]
        
        # Two bars back
        close_2back = self.data.Close[-3]
        high_2back = self.data.High[-3]
        low_2back = self.data.Low[-3]
        
        # ND/NS Logic
        body = abs(close - open_)
        body_prev = abs(close_prev - open_prev)
        
        # Calculate baseline body (median of previous bar body over baseline_len bars)
        bodies = [abs(self.data.Close[i] - self.data.Open[i]) for i in range(-self.baseline_len, 0)]
        baseline_body = np.median(bodies) if bodies else body_prev
        
        thin_b = body < baseline_body * self.thin_body_pct if baseline_body > 0 else body == 0
        
        vol_prev_2 = self.data.Volume[-3] if len(self.data) >= 3 else volume_prev
        low_vol = volume >= self.min_vol and volume < volume_prev and volume < vol_prev_2
        
