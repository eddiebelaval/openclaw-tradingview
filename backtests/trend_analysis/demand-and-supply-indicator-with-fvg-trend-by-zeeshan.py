        p_vol_only_nd = self.show_possible and up and very_low_vol_flag and vol_up
        p_vol_only_ns = self.show_possible and dn and very_low_vol_flag and vol_dn
        
        # FVG Detection (Fair Value Gap)
        is_bull_fvg = low > high_2back
        is_bear_fvg = high < low_2back
        
        if is_bull_fvg:
            self.fvg_bull_active = True
        if is_bear_fvg:
            self.fvg_bear_active = True
        
