        dn = close <= close_prev
        
        # Opposing wick
        upper_wick = high - max(open_, close)
        lower_wick = min(open_, close) - low
        opposing_wick = upper_wick if up else lower_wick
        long_opposing = opposing_wick > body * self.opp_wick_factor
        
        nd = up and thin_b and low_vol and not long_opposing
        ns = dn and thin_b and low_vol and not long_opposing
        
        # POSSIBLE signals
        p_nd = self.show_possible and up and thin_b and not nd
        p_ns = self.show_possible and dn and thin_b and not ns
        
        vol_up = close > open_
        vol_dn = close < open_
        
        vol_sma_val = self.vol_sma[-1] if len(self.vol_sma) > 0 else volume
