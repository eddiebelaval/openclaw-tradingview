import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 200
    resolution = 30
    blur_radius = 3
    gamma = 0.7
    sr_threshold = 80.0
    
    def init(self):
        self.highest = self.I(lambda: pd.Series(self.data.High).rolling(self.lookback).max())
        self.lowest = self.I(lambda: pd.Series(self.data.Low).rolling(self.lookback).min())
        
        close = pd.Series(self.data.Close)
        self.ema_3 = self.I(pta.ema, close, length=3)
        self.linreg = self.I(lambda: pd.Series(self.data.Close).rolling(5).apply(
            lambda x: np.polyfit(np.arange(5), x.values, 1)[0] if len(x) == 5 else 0
        ))
        
        self.profile_values = []
        self.hot_zones = []
        self.current_status = "STABLE"
        
    def next(self):
        if len(self) < self.lookback + 5:
            return
        
        hi = self.highest[-1]
        lo = self.lowest[-1]
        
        if hi == lo:
            return
            
        bin_size = (hi - lo) / self.resolution
        
        close_price = self.data.Close[-1]
        price_bin = int((close_price - lo) / bin_size)
        price_bin = max(0, min(self.resolution - 1, price_bin))
        
        slope = self.linreg[-1] if self.linreg[-1] != 0 else 0
        
        current_profile = np.zeros(self.resolution)
        if len(self) > self.lookback:
            for i in range(max(0, len(self) - self.lookback), len(self)):
                bar_low = self.data.Low[i]
                bar_high = self.data.High[i]
                bar_vol = self.data.Volume[i]
                
                bin_start = int((bar_low - lo) / bin_size)
                bin_end = int((bar_high - lo) / bin_size)
                bin_start = max(0, min(self.resolution - 1, bin_start))
                bin_end = max(0, min(self.resolution - 1, bin_end))
                
                if bin_start <= bin_end:
                    vol_per_bin = bar_vol / (bin_end - bin_start + 1)
                    for j in range(bin_start, bin_end + 1):
                        current_profile[j] += vol_per_bin
        
        max_profile = np.max(current_profile) if np.max(current_profile) > 0 else 1e-10
        rel_value = current_profile[price_bin] / max_profile
        
        target_bin = price_bin + (1 if slope > 0 else -1)
        target_bin = max(0, min(self.resolution - 1, target_bin))
        target_value = current_profile[target_bin] / max_profile
        
        if rel_value > 0.80:
            self.current_status = "HOT"
            if not self.position:
                pass
            elif self.position.is_long:
                self.sell()
        elif rel_value < 0.20:
            self.current_status = "COLD"
            if not self.position:
                self.buy()
        elif target_value > rel_value:
            self.current_status = "WARM"
            if not self.position:
                self.buy()
        else:
            self.current_status = "STABLE"
            if self.position.is_long and rel_value > 0.60:
                self.sell()
        
        threshold_val = max_profile * (self.sr_threshold / 100.0)
        hot_zone_detected = current_profile[price_bin] >= threshold_val
        
        if hot_zone_detected and not self.position:
            self.buy()
        elif not hot_zone_detected and self.position.is_long:
            self.sell()


