import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    kama_len = 9
    fast_len = 3
    slow_len = 80
    sd_len = 23
    mult = 2.0
    sig_mode = "Band Break"
    confirm_close = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.kama = self.I(self._calculate_kama, close)
        self.sd = self.I(self._calculate_sd, close, high, low)
        self.upper = self.I(self._calculate_upper, close, high, low)
        self.lower = self.I(self._calculate_lower, close, high, low)
        
        self.state = 0
        self.prev_state = 0

    def _calculate_kama(self, close):
        kama_values = np.full(len(close), np.nan)
        
        for i in range(self.kama_len, len(close)):
            change = abs(close.iloc[i] - close.iloc[i - self.kama_len])
            vol = 0.0
            for j in range(self.kama_len):
                vol += abs(close.iloc[i - j] - close.iloc[i - j - 1])
            
            er = change / vol if vol != 0.0 else 0.0
            fast_sc = 2.0 / (self.fast_len + 1.0)
            slow_sc = 2.0 / (self.slow_len + 1.0)
            sc = (er * (fast_sc - slow_sc) + slow_sc) ** 2.0
            
            if i == self.kama_len:
                kama_values[i] = close.iloc[i]
            else:
                kama_values[i] = kama_values[i - 1] + sc * (close.iloc[i] - kama_values[i - 1])
        
        return pd.Series(kama_values)

    def _calculate_sd(self, close, high, low):
        kama = self._calculate_kama(close)
        resid = close - kama
        sd_values = resid.rolling(window=self.sd_len).std()
        return pd.Series(sd_values)

    def _calculate_upper(self, close, high, low):
        kama = self._calculate_kama(close)
        sd = self._calculate_sd(close, high, low)
        return kama + self.mult * sd

    def _calculate_lower(self, close, high, low):
        kama = self._calculate_kama(close)
        sd = self._calculate_sd(close, high, low)
        return kama - self.mult * sd

    def next(self):
        if len(self.data) < self.kama_len + 1:
            return
        
        close = self.data.Close[-1]
        kama_val = self.kama[-1]
        upper_val = self.upper[-1]
        lower_val = self.lower[-1]
        
        if np.isnan(kama_val) or np.isnan(upper_val) or np.isnan(lower_val):
            return
        
        bull_trig = close > upper_val
        bear_trig = close < lower_val
        
        if bull_trig and not bear_trig:
            self.state = 1
        elif bear_trig:
            self.state = -1
        
        bull_flip = self.state == 1 and self.prev_state != 1
        bear_flip = self.state == -1 and self.prev_state != -1
        
        if bull_flip and not self.position:
            self.buy()
        elif bear_flip and self.position:
            self.sell()
        
        self.prev_state = self.state


