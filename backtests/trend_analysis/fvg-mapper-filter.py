import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # FVG parameters
    htf_period = 4  # 240-minute bars = 4-hour HTF
    min_atr_frac = 0.25
    use_min_size_filter = True
    atr_length = 14
    
    def init(self):
        # Calculate ATR on 1-minute (current) timeframe
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr_1m = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Store HTF data
        self.htf_closes = []
        self.htf_highs = []
        self.htf_lows = []
        self.htf_atrs = []
        self.htf_times = []
        self.last_htf_idx = -1
        
        # FVG zones tracking: list of dicts
        self.fvg_zones = []
        
    def _extract_htf_data(self):
        """Extract HTF (4-bar) aggregated data"""
        if len(self.data) < self.htf_period:
            return None
        
        current_idx = len(self.data) - 1
        htf_idx = current_idx // self.htf_period
        
        # Check if we have a new HTF candle
        if htf_idx == self.last_htf_idx:
            return None
        
        self.last_htf_idx = htf_idx
        
        # Extract the last htf_period bars
        start_idx = max(0, current_idx - self.htf_period + 1)
        end_idx = current_idx + 1
        
        htf_high = max(self.data.High[start_idx:end_idx])
        htf_low = min(self.data.Low[start_idx:end_idx])
        htf_close = self.data.Close[current_idx]
        
        # Calculate HTF ATR approximation
        htf_atr = self.atr_1m[-1] * np.sqrt(self.htf_period) if self.atr_1m[-1] else 0
        
        return {
            'high': htf_high,
            'low': htf_low,
            'close': htf_close,
            'atr': htf_atr,
            'time': current_idx
        }
    
    def _detect_fvg(self):
        """Detect Fair Value Gaps in HTF data"""
        if len(self.htf_closes) < 3:
            return []
        
        new_fvgs = []
        
        # Current HTF candle (index -1)
        H0 = self.htf_highs[-1]
        L0 = self.htf_lows[-1]
        C0 = self.htf_closes[-1]
        atr_htf = self.htf_atrs[-1] if self.htf_atrs[-1] else 1
        
        # 2 candles back (index -3)
        if len(self.htf_closes) >= 3:
            H2 = self.htf_highs[-3]
            L2 = self.htf_lows[-3]
            
            # Bull FVG: L0 > H2
            if L0 > H2:
                bull_top = L0
                bull_bot = H2
                bull_sz = bull_top - bull_bot
                
                if not self.use_min_size_filter or bull_sz >= (atr_htf * self.min_atr_frac):
                    new_fvgs.append({
                        'type': 'bull',
                        'top': bull_top,
                        'bot': bull_bot,
                        'size': bull_sz,
                        'time_created': self.htf_times[-1],
                        'bar_created': len(self.data) - 1
                    })
            
            # Bear FVG: H0 < L2
            if H0 < L2:
                bear_top = L2
                bear_bot = H0
                bear_sz = bear_top - bear_bot
                
                if not self.use_min_size_filter or bear_sz >= (atr_htf * self.min_atr_frac):
                    new_fvgs.append({
                        'type': 'bear',
                        'top': bear_top,
                        'bot': bear_bot,
                        'size': bear_sz,
                        'time_created': self.htf_times[-1],
                        'bar_created': len(self.data) - 1
                    })
        
        return new_fvgs
    
    def _check_fvg_closure(self):
        """Check if any FVGs have been closed (touched)"""
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        closed_indices = []
        
        for i, zone in enumerate(self.fvg_zones):
            if zone.get('closed'):
                continue
            
            top = zone['top']
            bot = zone['bot']
            zone_type = zone['type']
            
            # Check wick touch (price touched zone)
            wick_touch = not (current_high < bot or current_low > top)
            
            # Check close inside
            close_inside = (current_close <= top and current_close >= bot)
            
            # Check invalidation (close through far side)
            if zone_type == 'bull':
                invalid = current_close < bot
            else:
                invalid = current_close > top
            
            # Mark closed on wick touch
            if wick_touch or close_inside or invalid:
                zone['closed'] = True
                zone['closed_bar'] = len(self.data) - 1
                closed_indices.append(i)
        
        return closed_indices
    
    def next(self):
        """Main strategy logic"""
        # Extract HTF candle data
        htf_data = self._extract_htf_data()
        
        if htf_data:
            self.htf_closes.append(htf_data['close'])
            self.htf_highs.append(htf_data['high'])
            self.htf_lows.append(htf_data['low'])
            self.htf_atrs.append(htf_data['atr'])
            self.htf_times.append(htf_data['time'])
            
            # Keep only last 3 HTF candles for FVG detection
            if len(self.htf_closes) > 3:
                self.htf_closes.pop(0)
                self.htf_highs.pop(0)
                self.htf_lows.pop(0)
                self.htf_atrs.pop(0)
                self.htf_times.pop(0)
            
            # Detect new FVGs
            new_fvgs = self._detect_fvg()
            self.fvg_zones.extend(new_fvgs)
        
        # Check for zone closures
        self._check_fvg_closure()
        
        # Simple trading logic based on FVG proximity
        if len(self.fvg_zones) > 0 and self.atr_1m[-1]:
            current_price = self.data.Close[-1]
            
            # Find nearest open bull FVG below price
            nearest_bull = None
            nearest_bull_dist = float('inf')
            
            for zone in self.fvg_zones:
                if not zone.get('closed') and zone['type'] == 'bull':
                    dist_to_top = current_price - zone['top']
                    if dist_to_top > 0 and dist_to_top < nearest_bull_dist:
                        nearest_bull = zone
                        nearest_bull_dist = dist_to_top
            
            # Find nearest open bear FVG above price
            nearest_bear = None
            nearest_bear_dist = float('inf')
            
            for zone in self.fvg_zones:
                if not zone.get('closed') and zone['type'] == 'bear':
                    dist_to_bot = zone['bot'] - current_price
                    if dist_to_bot > 0 and dist_to_bot < nearest_bear_dist:
                        nearest_bear = zone
                        nearest_bear_dist = dist_to_bot
            
            # Entry logic
            if not self.position:
                # Buy on approach to bull FVG
                if nearest_bull and nearest_bull_dist < 2 * self.atr_1m[-1]:
                    self.buy()
                
                # Sell on approach to bear FVG
                elif nearest_bear and nearest_bear_dist < 2 * self.atr_1m[-1]:
                    self.sell()
            
            # Exit logic
            else:
                if self.position.is_long and nearest_bear and nearest_bear_dist < self.atr_1m[-1]:
                    self.position.close()
                elif self.position.is_short and nearest_bull and nearest_bull_dist < self.atr_1m[-1]:
                    self.position.close()


