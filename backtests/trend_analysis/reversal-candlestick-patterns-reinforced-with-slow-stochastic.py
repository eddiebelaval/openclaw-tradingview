import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    useEmaFilter = True
    emaLength = 200
    kLength = 10
    kSmoothing = 6
    dSmoothing = 3
    bullZone = 25
    bearZone = 75

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # EMA Filter
        self.ema = self.I(pta.ema, close, length=self.emaLength)
        
        # Stochastic
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=self.kLength, d=self.kSmoothing, smooth_k=self.dSmoothing) or pd.DataFrame(index=close.index))
        self.slowK = self.I(lambda: stoch_result.iloc[:, 0] if isinstance(stoch_result, pd.DataFrame) and len(stoch_result.columns) > 0 else pd.Series(50, index=close.index))
        
        # Candlestick properties
        self.bodySize = self.I(lambda: (close - open_).abs())
        self.candleRng = self.I(lambda: high - low)
        self.isBullish = self.I(lambda: close > open_)
        self.isBearish = self.I(lambda: close < open_)
        
        self.lowerWick = self.I(lambda: (open_ - low).where(close > open_, close - low))
        self.upperWick = self.I(lambda: (high - close).where(close > open_, high - open_))
        
        # Pattern detectors
        self.isDojiBody = self.I(lambda: self.bodySize[-1] <= (self.candleRng[-1] * 0.1) if len(self.bodySize) > 0 and self.candleRng[-1] > 0 else False)
        self.isSmallBody = self.I(lambda: self.bodySize[-1] <= (self.candleRng[-1] * 0.3) if len(self.bodySize) > 0 and self.candleRng[-1] > 0 else False)
        self.isShavenBottom = self.I(lambda: self.lowerWick[-1] <= (self.candleRng[-1] * 0.05) if len(self.lowerWick) > 0 and self.candleRng[-1] > 0 else False)
        self.isShavenTop = self.I(lambda: self.upperWick[-1] <= (self.candleRng[-1] * 0.05) if len(self.upperWick) > 0 and self.candleRng[-1] > 0 else False)

    def next(self):
        if len(self.data) < 3:
            return
        
        # Current values
        close_curr = self.data.Close[-1]
        open_curr = self.data.Open[-1]
        high_curr = self.data.High[-1]
        low_curr = self.data.Low[-1]
        
        close_prev = self.data.Close[-2]
        open_prev = self.data.Open[-2]
        high_prev = self.data.High[-2]
        low_prev = self.data.Low[-2]
        
        body_curr = abs(close_curr - open_curr)
        rng_curr = high_curr - low_curr
        
        body_prev = abs(close_prev - open_prev)
        rng_prev = high_prev - low_prev
        
        is_bullish = close_curr > open_curr
        is_bearish = close_curr < open_curr
        is_bullish_prev = close_prev > open_prev
        is_bearish_prev = close_prev < open_prev
        
        lower_wick = open_curr - low_curr if is_bullish else close_curr - low_curr
        upper_wick = high_curr - close_curr if is_bullish else high_curr - open_curr
        
        ema_val = self.ema[-1]
        stoch_val = self.slowK[-1]
        
        # Filters
        bull_ema_cond = not self.useEmaFilter or (close_curr > ema_val)
        bear_ema_cond = not self.useEmaFilter or (close_curr < ema_val)
        
        bull_stoch_cond = stoch_val < self.bullZone
        bear_stoch_cond = stoch_val > self.bearZone
        
        # Candlestick patterns
        is_doji_body = body_curr <= (rng_curr * 0.1) if rng_curr > 0 else False
        is_small_body = body_curr <= (rng_curr * 0.3) if rng_curr > 0 else False
        is_shaven_bottom = lower_wick <= (rng_curr * 0.05) if rng_curr > 0 else False
        is_shaven_top = upper_wick <= (rng_curr * 0.05) if rng_curr > 0 else False
        
        # Pattern conditions
        bear_engulfing = is_bullish_prev and is_bearish and open_curr > close_prev and close_curr < open_prev
        bull_engulfing = is_bearish_prev and is_bullish and open_curr < close_prev and close_curr > open_prev
        
        prev_midpoint = (close_prev + (body_prev / 2)) if is_bearish_prev else (close_prev - (body_prev / 2))
        dark_cloud = is_bullish_prev and is_bearish and open_curr > close_prev and close_curr <= prev_midpoint and close_curr > open_prev
        piercing = is_bearish_prev and is_bullish and open_curr < close_prev and close_curr >= prev_midpoint and close_curr < open_prev
        
        gravestone_doji = is_doji_body and lower_wick <= (rng_curr * 0.1) and upper_wick > (rng_curr * 0.6) if rng_curr > 0 else False
        dragonfly_doji = is_doji_body and upper_wick <= (rng_curr * 0.1) and lower_wick > (rng_curr * 0.6) if rng_curr > 0 else False
        long_legged_doji = is_doji_body and lower_wick > (rng_curr * 0.4) and upper_wick > (rng_curr * 0.4) if rng_curr > 0 else False
        
        is_umbrella = is_small_body and lower_wick >= (2 * body_curr) and upper_wick <= (body_curr * 0.5) if body_curr > 0 else False
        is_inv_umbrella = is_small_body and upper_wick >= (2 * body_curr) and lower_wick <= (body_curr * 0.5) if body_curr > 0 else False
        
        bull_belt_hold = is_bullish and is_shaven_bottom and upper_wick > 0
        bear_belt_hold = is_bearish and is_shaven_top and lower_wick > 0
        marubozu = is_shaven_top and is_shaven_bottom and body_curr > 0
        
        bull_pattern = (bull_engulfing or piercing or dragonfly_doji or 
                       is_umbrella or is_inv_umbrella or 
                       bull_belt_hold or (marubozu and is_bullish))
        
        bear_pattern = (bear_engulfing or dark_cloud or gravestone_doji or 
                       is_umbrella or is_inv_umbrella or 
                       bear_belt_hold or (marubozu and is_bearish))
        
        bull_trigger = bull_ema_cond and bull_stoch_cond and bull_pattern
        bear_trigger = bear_ema_cond and bear_stoch_cond and bear_pattern
        
        # Trading logic
        if bull_trigger:
            if self.position:
                self.position.close()
            self.buy()
        elif bear_trigger:
            if self.position:
                self.position.close()
            self.sell()


