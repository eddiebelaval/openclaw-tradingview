    def init(self):
        # Close series for indicators
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Core SMI calculation
        def calc_smi_core():
            hh = high.rolling(self.kLen).max()
            ll = low.rolling(self.kLen).min()
            rng = hh - ll
            rel = close - (hh + ll) / 2.0
            
            # Double EMA
