import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.vol_ma = self.I(lambda: pta.sma(volume, length=20))
        
        self.fvg_bullish = self.I(lambda: pd.Series(0, index=close.index))
        self.fvg_bearish = self.I(lambda: pd.Series(0, index=close.index))
        
        self.last_fvg_type = None
        self.fvg_active = False

    def next(self):
        if len(self.data) < 4:
            return
        
        idx = len(self.data) - 1
        
        htf_high_c = self.data.High[idx-1] if idx >= 1 else self.data.High[idx]
        htf_low_c = self.data.Low[idx-1] if idx >= 1 else self.data.Low[idx]
        htf_high_a = self.data.High[idx-3] if idx >= 3 else self.data.High[idx]
        htf_low_a = self.data.Low[idx-3] if idx >= 3 else self.data.Low[idx]
        
        htf_vol_b = self.data.Volume[idx-2] if idx >= 2 else self.data.Volume[idx]
        
        vol_ma_val = self.vol_ma[-1] if self.vol_ma[-1] else 0
        vol_ok = htf_vol_b >= vol_ma_val * 1.0
        
        bullish_fvg = htf_low_c > htf_high_a and vol_ok
        bearish_fvg = htf_low_a > htf_high_c and vol_ok
        
        if bullish_fvg and not self.position:
            self.buy()
            self.fvg_active = True
            self.last_fvg_type = "bullish"
        elif bearish_fvg and not self.position:
            self.buy()
            self.fvg_active = True
            self.last_fvg_type = "bearish"
        
        if self.position:
            mid_price = (self.data.High[idx-1] + self.data.Low[idx-1]) / 2 if idx >= 1 else self.data.Close[idx]
            
            if self.last_fvg_type == "bullish":
                if self.data.Low[idx] <= mid_price * 0.99:
                    self.sell()
                    self.fvg_active = False
            elif self.last_fvg_type == "bearish":
                if self.data.High[idx] >= mid_price * 1.01:
                    self.sell()
                    self.fvg_active = False


