import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 100
    multInput = 2.0
    slopeDivInput = 1.5
    atrLengthInput = 200
    atrMultInput = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Linear regression calculation
        def calc_linreg_current():
            if len(close) < self.lengthInput:
                return np.nan
            x = np.arange(self.lengthInput)
            y = close.iloc[-self.lengthInput:].values
            z = np.polyfit(x, y, 1)
            return z[0] * (self.lengthInput - 1) + z[1]
        
        def calc_linreg_past():
            if len(close) < self.lengthInput * 2:
                return np.nan
            x = np.arange(self.lengthInput)
            y = close.iloc[-self.lengthInput*2:-self.lengthInput].values
            z = np.polyfit(x, y, 1)
            return z[0] * (self.lengthInput - 1) + z[1]
        
        def calc_slope():
            curr = calc_linreg_current()
            past = calc_linreg_past()
            if np.isnan(curr) or np.isnan(past):
                return np.nan
            return ((curr - past) / (self.lengthInput - 1)) / self.slopeDivInput
        
        def calc_deviation():
            if len(close) < self.lengthInput:
                return np.nan
            return close.iloc[-self.lengthInput:].std() * self.multInput
        
        def calc_atr():
            atr = pta.atr(high, low, close, length=self.atrLengthInput)
            return atr.iloc[-1] if atr is not None and len(atr) > 0 else np.nan
        
        # Initialize trendline tracking variables
        self.trend_value = None
        self.active_slope = None
        self.reset_atr = None
        self.lr_current = self.I(lambda: pd.Series([calc_linreg_current() for _ in range(len(close))]))
        self.lr_slope = self.I(lambda: pd.Series([calc_slope() for _ in range(len(close))]))
        self.deviation = self.I(lambda: pd.Series([calc_deviation() for _ in range(len(close))]))
        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.atrLengthInput) or pd.Series(0, index=close.index))

    def next(self):
        close_val = self.data.Close[-1]
        
        # Initialize on first valid bar
        if self.trend_value is None:
            self.trend_value = close_val
            self.active_slope = self.lr_slope[-1] if not np.isnan(self.lr_slope[-1]) else 0
            self.reset_atr = self.atr_val[-1] if not np.isnan(self.atr_val[-1]) else 0
            return
        
        # Calculate projected value and check deviation
        projected_value = self.trend_value + self.active_slope
        threshold = self.deviation[-1] if not np.isnan(self.deviation[-1]) else 0
        is_deviating = abs(close_val - projected_value) > threshold
        
        if is_deviating:
            self.trend_value = close_val
            self.active_slope = self.lr_slope[-1] if not np.isnan(self.lr_slope[-1]) else 0
            self.reset_atr = self.atr_val[-1] if not np.isnan(self.atr_val[-1]) else 0
        else:
            self.trend_value = projected_value
        
        # Calculate bands
        upper_band = self.trend_value + self.reset_atr * self.atrMultInput
        lower_band = self.trend_value - self.reset_atr * self.atrMultInput
        
        # Trading logic: buy when price touches lower band in uptrend, sell when price touches upper band in downtrend
        if self.active_slope >= 0:  # Bullish trend
            if close_val <= lower_band and not self.position:
                self.buy()
            elif close_val >= upper_band and self.position:
                self.sell()
        else:  # Bearish trend
            if close_val >= upper_band and not self.position:
                self.buy()
            elif close_val <= lower_band and self.position:
                self.sell()