import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    squeeze_len = 13
    bb_mult = 2.0
    kc_mult = 1.2
    use_adx = True
    adx_thresh = 21
    adx_len = 13
    use_vol = True
    vol_mult = 1.3
    vol_sma_len = 21
    min_sqz_bars = 5
    prevent_overlap = True
    tp1_mult = 0.618
    tp2_mult = 1.0
    tp3_mult = 1.618
    sl_pad = 0.2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Bollinger Bands
        self.bb = self.I(lambda: pta.bbands(close, length=self.squeeze_len, std=self.bb_mult))

        # ATR for Keltner Channel and SL padding
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.squeeze_len))

        # SMA for basis
        self.sma_basis = self.I(lambda: pta.sma(close, length=self.squeeze_len))

        # Volume SMA
        self.vol_sma = self.I(lambda: pta.sma(volume, length=self.vol_sma_len))

        # ADX
        self.adx_val = self.I(lambda: pta.adx(high, low, close, length=self.adx_len))

        # ATR for SL padding (14 period standard)
        self.atr_sl = self.I(lambda: pta.atr(high, low, close, length=14))

        # State variables
        self.sqz_count = 0
        self.rng_high = None
        self.rng_low = None
        self.rng_start = None
        self.rng_end = None
        self.rng_ready = False
        self.act_high = None
        self.act_low = None
        self.act_start = None
        self.last_rng_end = 0
        self.trade_dir = 0
        self.entry_px = None
        self.sl_px = None
        self.tp1_px = None
        self.tp2_px = None
        self.tp3_px = None
        self.in_trade = False
        self.tp1_hit = False
        self.tp2_hit = False
        self.tp3_hit = False
        self.sl_hit = False
        self.total_bull = 0
        self.total_bear = 0
        self.tp1_cnt = 0
        self.tp2_cnt = 0
        self.tp3_cnt = 0
        self.sl_cnt = 0

    def next(self):
        # Get current values
        if len(self.data) < self.squeeze_len + 50:
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1] if len(self.data.Volume) > 0 else 0

        # BB values
        bb_result = self.bb[-1]
        if bb_result is None or np.isnan(bb_result[0]):
            return

        bb_upper = bb_result[0]
        bb_lower = bb_result[2]

        # ATR
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        atr_val = 0 if np.isnan(atr_val) else atr_val

        # SMA basis
        sma_val = self.sma_basis[-1] if self.sma_basis[-1] is not None else close
        sma_val = close if np.isnan(sma_val) else sma_val

        # Keltner Channel
        kc_range = atr_val * self.kc_mult
        kc_upper = sma_val + kc_range
        kc_lower = sma_val - kc_range

        # Squeeze detection
        is_squeeze = bb_upper < kc_upper and bb_lower > kc_lower

        # ADX filter
        adx_result = self.adx_val[-1] if self.adx_val[-1] is not None else 50
        adx_result = 50 if np.isnan(adx_result) else adx_result
        adx_ok = (not self.use_adx) or (adx_result < self.adx_thresh)

        sqz_active = is_squeeze and adx_ok

        # Update squeeze count
        if sqz_active:
            self.sqz_count += 1
        else:
            self.sqz_count = 0

        # Track range during squeeze
        if sqz_active and self.sqz_count == 1:
            self.rng_high = high
            self.rng_low = low
            self.rng_start = len(self.data) - 1

        if sqz_active and self.sqz_count > 1:
            self.rng_high = max(self.rng_high, high) if self.rng_high else high
            self.rng_low = min(self.rng_low, low) if self.rng_low else low

        # Lock range when squeeze ends
        was_sqz = len(self.data) > 1 and self.sqz_count == 0
        prev_sqz = len(self.data) > 1
        sqz_just_ended = was_sqz and self.sqz_count == 0 and prev_sqz

        if not sqz_active and self.sqz_count == 0 and self.rng_high is not None and \
           self.sqz_count >= self.min_sqz_bars - 1:
            overlap_ok = (not self.prevent_overlap) or (self.rng_start > self.last_rng_end)
            if overlap_ok:
                self.rng_ready = True
                self.act_high = self.rng_high
                self.act_low = self.rng_low
                self.act_start = self.rng_start
                self.rng_end = len(self.data) - 2
                self.last_rng_end = len(self.data) - 2
                self.rng_high = None
                self.rng_low = None

        # Volume confirmation
        vol_sma_val = self.vol_sma[-1] if self.vol_sma[-1] is not None else 1
        vol_sma_val = 1 if np.isnan(vol_sma_val) else vol_sma_val
        vol_ok = (not self.use_vol) or (volume > vol_sma_val * self.vol_mult)

        # Breakout signals
        rng_width = (self.act_high - self.act_low) if (self.act_high and self.act_low) else 0
        atr_sl_val = self.atr_sl[-1] if self.atr_sl[-1] is not None else 0
        atr_sl_val = 0 if np.isnan(atr_sl_val) else atr_sl_val
        sl_pad_atr = atr_sl_val * self.sl_pad

        bull_break = self.rng_ready and close > self.act_high and vol_ok
        bear_break = self.rng_ready and close < self.act_low and vol_ok

        # Process breakouts
        if bull_break:
            self.trade_dir = 1
            self.entry_px = close
            self.sl_px = self.act_low - sl_pad_atr
            self.tp1_px = close + rng_width * self.tp1_mult
            self.tp2_px = close + rng_width * self.tp2_mult
            self.tp3_px = close + rng_width * self.tp3_mult
            self.in_trade = True
            self.total_bull += 1
            self.rng_ready = False
            self.tp1_hit = False
            self.tp2_hit = False
            self.tp3_hit = False
            self.sl_hit = False

        if bear_break:
            self.trade_dir = -1
            self.entry_px = close
            self.sl_px = self.act_high + sl_pad_atr
            self.tp1_px = close - rng_width * self.tp1_mult
            self.tp2_px = close - rng_width * self.tp2_mult
            self.tp3_px = close - rng_width * self.tp3_mult
            self.in_trade = True
            self.total_bear += 1
            self.rng_ready = False
            self.tp1_hit = False
            self.tp2_hit = False
            self.tp3_hit = False
            self.sl_hit = False

        # Track TP/SL hits
        if self.in_trade and not bull_break and not bear_break:
            if self.trade_dir == 1:
                if not self.tp1_hit and high >= self.tp1_px:
                    self.tp1_hit = True
                    self.tp1_cnt += 1
                if not self.tp2_hit and high >= self.tp2_px:
                    self.tp2_hit = True
                    self.tp2_cnt += 1
                if not self.tp3_hit and high >= self.tp3_px:
                    self.tp3_hit = True
                    self.tp3_cnt += 1
                    self.in_trade = False
                if not self.sl_hit and low <= self.sl_px:
                    self.sl_hit = True
                    self.sl_cnt += 1
                    self.in_trade = False

            elif self.trade_dir == -1:
                if not self.tp1_hit and low <= self.tp1_px:
                    self.tp1_hit = True
                    self.tp1_cnt += 1
                if not self.tp2_hit and low <= self.tp2_px:
                    self.tp2_hit = True
                    self.tp2_cnt += 1
                if not self.tp3_hit and low <= self.tp3_px:
                    self.tp3_hit = True
                    self.tp3_cnt += 1
                    self.in_trade = False
                if not self.sl_hit and high >= self.sl_px:
                    self.sl_hit = True
                    self.sl_cnt += 1
                    self.in_trade = False

        # Simple entry/exit logic
        if bull_break and not self.position:
            self.buy()
        elif bear_break and not self.position:
            self.sell()

        # Exit on TP3 or SL
        if self.position:
            if self.trade_dir == 1:
                if (self.tp3_hit and self.in_trade == False) or self.sl_hit:
                    self.position.close()
            elif self.trade_dir == -1:
                if (self.tp3_hit and self.in_trade == False) or self.sl_hit:
                    self.position.close()