import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Impulse Detection parameters
    i_impLen = 14
    i_impMul = 1.8
    i_velLen = 3
    
    # Decay Physics parameters
    i_halfLf = 8
    i_adapHL = True
    i_exhThr = 0.08
    
    # Volume Weighting parameters
    i_useVol = True
    i_volLen = 20
    
    # Visual Settings parameters
    i_maxW = 2.0
    i_fieldT = 80
    i_theme = True
    i_bullCS = "Lime"
    i_bearCS = "Magenta"
    
    # Signal Filtering parameters
    i_shSig = True
    i_shImp = True
    i_cdBars = 8
    
    # Exhaustion Memory parameters
    i_shMem = True
    i_memCnt = 5
    i_memFde = 80
    
    # Energy Divergence parameters
    i_shDiv = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.i_impLen)
        
        # Calculate velocity
        def calc_velocity():
            vel = np.abs(close - close.shift(self.i_velLen)) / max(self.i_velLen, 1)
            return vel
        self.velocity = self.I(calc_velocity)
        
        # Calculate average velocity
        self.avgVel = self.I(lambda: pta.sma(self.velocity, length=self.i_impLen) or pd.Series(0, index=close.index))
        
        # Calculate volume average and relative volume
        self.volAvg = self.I(lambda: pta.sma(volume, length=self.i_volLen) or pd.Series(1, index=close.index))
        
        # State tracking variables
        self.E0 = 0.0
        self.lam = 0.0
        self.barsSince = 0
        self.dir = 0
        self.isExh = False
        self.impPrice = 0.0
        self.prevE0Bull = 0.0
        self.prevE0Bear = 0.0
        self.prevHigh = 0.0
        self.prevLow = 0.0
        self.lastSigBar = -9999
        self.lastImpBar = -9999
        self.lastExhDir = 0
        self.totalImpulses = 0
        self.totalExhausts = 0
        self.totalDivs = 0
        self.lastBuyBar = -9999
        self.lastSellBar = -9999

    def next(self):
        if len(self.data) < max(self.i_impLen, self.i_velLen, self.i_volLen):
            return

        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        atr_val = self.atr[-1]
        velocity_val = self.velocity[-1]
        avgVel_val = self.avgVel[-1] if self.avgVel[-1] is not None else 0.0
        
        # Calculate relative volume
        volAvg_val = self.volAvg[-1] if self.volAvg[-1] is not None else 1.0
        relVol = self.data.Volume[-1] / max(volAvg_val, 1e-10) if self.i_useVol else 1.0
        relVol = np.clip(relVol, 0.5, 3.0)
        
        # Body size and ratio
        bodySize = abs(close_val - open_val)
        bodyRatio = bodySize / max(high_val - low_val, 1e-10)
        
        # Impulse detection
        bullImpulse = (close_val > open_val and
                       bodySize > atr_val * self.i_impMul * 0.5 and
                       (high_val - low_val) > atr_val * self.i_impMul * 0.7 and
                       bodyRatio > 0.45)
        
        bearImpulse = (close_val < open_val and
                       bodySize > atr_val * self.i_impMul * 0.5 and
                       (high_val - low_val) > atr_val * self.i_impMul * 0.7 and
                       bodyRatio > 0.45)
        
        isImpulse = bullImpulse or bearImpulse
        impDir = 1 if bullImpulse else (-1 if bearImpulse else 0)
        
        # Energy calculation
        velBoost = min(velocity_val / max(avgVel_val, 1e-10), 3.0) if avgVel_val > 0 else 1.0
        volBoost = relVol
        rawE0 = (bodySize / max(atr_val, 1e-10)) * velBoost * volBoost
        newE0 = min(rawE0, 5.0)
        
        # Lambda calculation
        def f_lambda(hl):
            return np.log(2) / max(hl, 1)
        
        # Decay calculation
        def f_decay(E0, lam, t):
            if E0 <= 0 or lam <= 0:
                return 0.0
            return E0 * np.exp(-lam * t)
        
        # Cooldown checks
        impCooldownOk = (len(self.data) - self.lastImpBar) >= max(int(self.i_cdBars * 0.5), 1)
        exhCooldownOk = (len(self.data) - self.lastSigBar) >= self.i_cdBars
        
        # Energy divergence detection
        bullDivergence = False
        bearDivergence = False
        
        if self.i_shDiv and isImpulse and impCooldownOk:
            if bullImpulse and self.prevE0Bull > 0:
                if high_val > self.prevHigh and newE0 < self.prevE0Bull * 0.75:
                    bullDivergence = True
                    self.totalDivs += 1
            if bearImpulse and self.prevE0Bear > 0:
                if low_val < self.prevLow and newE0 < self.prevE0Bear * 0.75:
                    bearDivergence = True
                    self.totalDivs += 1
        
        # State machine - energy lifecycle
        if isImpulse and impCooldownOk:
            adaptHL = self.i_halfLf * max(0.6, min(newE0 / 2.0, 2.2)) if self.i_adapHL else float(self.i_halfLf)
            
            if impDir == self.dir and not self.isExh:
                self.E0 = min(self.E0 * 0.4 + newE0 * 0.8, 5.0)
                self.lam = f_lambda(adaptHL)
                self.barsSince = 0
            else:
                if bullImpulse:
                    self.prevE0Bull = newE0
                    self.prevHigh = high_val
                if bearImpulse:
                    self.prevE0Bear = newE0
                    self.prevLow = low_val
                
                self.E0 = newE0
                self.lam = f_lambda(adaptHL)
                self.dir = impDir
                self.barsSince = 0
                self.isExh = False
                self.impPrice = close_val
            
            self.lastImpBar = len(self.data)
            self.totalImpulses += 1
        else:
            self.barsSince += 1
        
        # Current energy calculation
        curEnergy = f_decay(self.E0, self.lam, self.barsSince)
        energyRatio = curEnergy / self.E0 if self.E0 > 0 else 0.0
        energyNorm = max(0.0, min(1.0, curEnergy / 3.0))
        
        # Exhaustion detection
        justExhausted = False
        if energyRatio < self.i_exhThr and not self.isExh and self.E0 > 0.5 and self.barsSince > 3 and exhCooldownOk:
            if self.dir != self.lastExhDir or (len(self.data) - self.lastSigBar) > self.i_cdBars * 3:
                self.isExh = True
                justExhausted = True
                self.lastSigBar = len(self.data)
                self.lastExhDir = self.dir
                self.totalExhausts += 1
        
        # Trading logic based on signals
        # Buy on bullish impulse with energy
        if bullImpulse and impCooldownOk and not bullDivergence and energyNorm > 0.3:
            if len(self.data) - self.lastBuyBar > self.i_cdBars:
                self.buy()
                self.lastBuyBar = len(self.data)
        
        # Sell on bearish impulse or exhaustion
        if bearImpulse and impCooldownOk and not bearDivergence and energyNorm > 0.3:
            if len(self.data) - self.lastSellBar > self.i_cdBars:
                self.sell()
                self.lastSellBar = len(self.data)
        
        # Exit on exhaustion
        if justExhausted:
            if self.position:
                self.position.close()


