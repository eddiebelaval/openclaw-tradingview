import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR for reference
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # EMA for trend
        self.ema_fast = self.I(pta.ema, close, length=9)
        self.ema_slow = self.I(pta.ema, close, length=21)
        
        # RSI for momentum
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # Volume SMA for volume analysis
        volume = pd.Series(self.data.Volume)
        self.vol_sma = self.I(pta.sma, volume, length=20)
        
        self.in_position = False

    def next(self):
        if len(self) < 30:
            return
        
        current_atr = self.atr[-1] if self.atr[-1] is not None else 0
        current_ema_fast = self.ema_fast[-1]
        current_ema_slow = self.ema_slow[-1]
        current_rsi = self.rsi[-1]
        current_vol = self.data.Volume[-1]
        current_vol_sma = self.vol_sma[-1]
        
        if current_atr is None or np.isnan(current_atr):
            current_atr = 0
        
        # ENTRY LOGIC
        # Buy: Fast EMA crosses above Slow EMA + RSI not overbought + Volume confirmation
        if not self.position:
            if crossover(self.ema_fast, self.ema_slow):
                if current_rsi < 70:
                    if current_vol > current_vol_sma * 1.2:
                        self.buy()
                        self.in_position = True
            
            # Alternative buy: RSI oversold bounce with price above slow EMA
            elif current_rsi < 30 and current_rsi > current_rsi[-1]:
                if current_ema_fast > current_ema_slow:
                    if current_vol > current_vol_sma:
                        self.buy()
                        self.in_position = True
        
        # EXIT LOGIC
        # Sell: Fast EMA crosses below Slow EMA OR RSI overbought and turning down
        elif self.position:
            if crossover(self.ema_slow, self.ema_fast):
                self.sell()
                self.in_position = False
            
            # Alternative exit: RSI overbought and turning down
            elif current_rsi > 70 and current_rsi < self.rsi[-2]:
                self.sell()
                self.in_position = False
            
            # Stop loss: Price below slow EMA by more than 2 ATR
            elif current_ema_slow is not None and current_atr > 0:
                if self.data.Close[-1] < current_ema_slow - (current_atr * 2):
                    self.sell()
                    self.in_position = False


