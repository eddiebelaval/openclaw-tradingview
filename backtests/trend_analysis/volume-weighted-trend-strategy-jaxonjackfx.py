import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vwma_len = 34
    atr_mult = 1.5
    trade_dir = 'Both'
    use_sl = False
    sl_mult = 2.0
    use_tp = False
    tp_mult = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # VWMA calculation
        self.vwma = self.I(lambda: pta.vwma(close, volume, length=self.vwma_len) or pd.Series(0, index=close.index))
        
        # ATR calculation
        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.vwma_len) or pd.Series(0, index=close.index))
        
        # Upper and lower bands
        self.upper = self.I(lambda: self.vwma + self.atr_val * self.atr_mult)
        self.lower = self.I(lambda: self.vwma - self.atr_val * self.atr_mult)
        
        # Trend tracking
        self.trend = 0

    def next(self):
        close = self.data.Close[-1]
        upper = self.upper[-1]
        lower = self.lower[-1]
        
        # Update trend based on price crossing bands
        if close > upper:
            self.trend = 1
        elif close < lower:
            self.trend = -1
        
        # Detect trend changes (signals)
        prev_trend = self.trend if len(self) == 1 else self.trend
        
        # Determine if this is a new bullish signal
        bull_signal = False
        bear_signal = False
        
        if close > upper:
            if self.trend != 1 or len(self) == 1:
                bull_signal = True
                self.trend = 1
        
        if close < lower:
            if self.trend != -1 or len(self) == 1:
                bear_signal = True
                self.trend = -1
        
        atr_val = self.atr_val[-1]
        
        # Entry logic
        if bull_signal:
            if self.trade_dir != 'Short Only':
                if not self.position:
                    self.buy()
                elif self.position.is_short:
                    self.position.close()
                    self.buy()
            if self.trade_dir == 'Both':
                if self.position and self.position.is_short:
                    self.position.close()
        
        if bear_signal:
            if self.trade_dir != 'Long Only':
                if not self.position:
                    self.sell()
                elif self.position.is_long:
                    self.position.close()
                    self.sell()
            if self.trade_dir == 'Both':
                if self.position and self.position.is_long:
                    self.position.close()
        
        # Stop loss and take profit management
        if self.position:
            if self.position.is_long:
                if self.use_sl:
                    sl_price = self.position.open_price - atr_val * self.sl_mult
                    if close <= sl_price:
                        self.position.close()
                
                if self.use_tp:
                    tp_price = self.position.open_price + atr_val * self.tp_mult
                    if close >= tp_price:
                        self.position.close()
            
            elif self.position.is_short:
                if self.use_sl:
                    sl_price = self.position.open_price + atr_val * self.sl_mult
                    if close >= sl_price:
                        self.position.close()
                
                if self.use_tp:
                    tp_price = self.position.open_price - atr_val * self.tp_mult
                    if close <= tp_price:
                        self.position.close()


