class TvStrategy(Strategy):
    sweep_sensitivity = 5
    fvg_detection = True
    fvg_lookback = 50

    def init(self):
        self.pending_swings = []
        self.fvg_array = []
        self.last_pivot_high = None
        self.last_pivot_low = None
        self.last_pivot_high_bar = None
        self.last_pivot_low_bar = None

    def next(self):
        current_idx = len(self.data) - 1
        
        if current_idx < self.sweep_sensitivity + 2:
            return

        high = self.data.High
        low = self.data.Low
        close = self.data.Close
        open_ = self.data.Open

        # Detect pivot highs and lows
        if current_idx >= self.sweep_sensitivity * 2:
            is_pivot_high = (high[current_idx - self.sweep_sensitivity] == 
                           max(high[current_idx - self.sweep_sensitivity * 2:current_idx + 1]))
