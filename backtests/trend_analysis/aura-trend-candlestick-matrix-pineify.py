import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend Cloud Settings
    fastLen = 20
    slowLen = 50
    
    # Candlestick Pattern Settings
    showHams = True
    showEng = True
    showStars = True
    
    # Support & Resistance Settings
    pivotLen = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate trend cloud EMAs
        self.fastEma = self.I(pta.ema, close, length=self.fastLen)
        self.slowEma = self.I(pta.ema, close, length=self.slowLen)
        
        # Calculate support and resistance levels using rolling min/max
        self.resLevel = self.I(lambda: high.rolling(window=self.pivotLen * 2 + 1, center=True).max())
        self.supLevel = self.I(lambda: low.rolling(window=self.pivotLen * 2 + 1, center=True).min())
        
        # Store previous values for pattern detection
        self.prevClose = self.I(lambda: close.shift(1))
        self.prevOpen = self.I(lambda: pd.Series(self.data.Open).shift(1))
        self.prevHigh = self.I(lambda: high.shift(1))
        self.prevLow = self.I(lambda: low.shift(1))
        
        self.prev2Close = self.I(lambda: close.shift(2))
        self.prev2Open = self.I(lambda: pd.Series(self.data.Open).shift(2))
        self.prev2High = self.I(lambda: high.shift(2))
        self.prev2Low = self.I(lambda: low.shift(2))

    def next(self):
        # Get current trend
        if len(self.fastEma) < 1 or len(self.slowEma) < 1:
            return
            
        fastEmaVal = self.fastEma[-1]
        slowEmaVal = self.slowEma[-1]
        
        if fastEmaVal > slowEmaVal:
            trend = 1
        elif fastEmaVal < slowEmaVal:
            trend = -1
        else:
            trend = 0
        
        # Current candle anatomy
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        rc = close < open_  # Red candle
        gc = close > open_  # Green candle
        
        c_top = max(open_, close)
        c_bot = min(open_, close)
        hl_width = high - low
        bod_width = c_top - c_bot
        
        # Previous candle anatomy
        if len(self.prevClose) > 0:
            prev_close = self.prevClose[-1]
            prev_open = self.prevOpen[-1]
            prev_rc = prev_close < prev_open
            prev_gc = prev_close > prev_open
            prev_c_top = max(prev_open, prev_close)
            prev_c_bot = min(prev_open, prev_close)
            prev_bod_width = prev_c_top - prev_c_bot
        else:
            return
        
        # Two bars back anatomy
        if len(self.prev2Close) > 0:
            prev2_close = self.prev2Close[-1]
            prev2_open = self.prev2Open[-1]
            prev2_rc = prev2_close < prev2_open
            prev2_gc = prev2_close > prev2_open
            prev2_c_top = max(prev2_open, prev2_close)
            prev2_c_bot = min(prev2_open, prev2_close)
            prev2_bod_width = prev2_c_top - prev2_c_bot
        else:
            return
        
        # Shadow & body ratios
        if hl_width > 0:
            hw_per = (high - c_top) / hl_width
            lw_per = (c_bot - low) / hl_width
            b_per = bod_width / hl_width
        else:
            hw_per = 0
            lw_per = 0
            b_per = 0
        
        # Doji filter
        doji = bod_width < (hl_width * 0.1)
        
        # 1. Hammer & Shooting Star
        hammer = lw_per > (b_per * 2) and b_per < 0.5 and hw_per < 0.15 and not doji and gc
        sstar = hw_per > (b_per * 2) and b_per < 0.5 and lw_per < 0.15 and not doji and rc
        
        # 2. Engulfing Patterns
        bull_engulfing = prev_rc and gc and bod_width > (prev_bod_width * 1.2) and c_bot < prev_c_bot and c_top > prev_c_top
        bear_engulfing = prev_gc and rc and bod_width > (prev_bod_width * 1.2) and c_top > prev_c_top and c_bot < prev_c_bot
        
        # 3. Morning Star & Evening Star
        morning_star = prev2_rc and gc and bod_width < (prev_bod_width * 0.5) and c_top > prev2_c_top and close > (prev2_c_top + prev2_c_bot) / 2
        evening_star = prev2_gc and rc and bod_width < (prev_bod_width * 0.5) and c_bot < prev2_c_bot and close < (prev2_c_top + prev2_c_bot) / 2
        
        # Pattern Alignment
        valid_hammer = self.showHams and hammer and trend == 1
        valid_sstar = self.showHams and sstar and trend == -1
        
        valid_bull_eng = self.showEng and bull_engulfing and trend == 1
        valid_bear_eng = self.showEng and bear_engulfing and trend == -1
        
        valid_m_star = self.showStars and morning_star and trend == 1
        valid_e_star = self.showStars and evening_star and trend == -1
        
        # Trading logic
        bullish_signal = valid_bull_eng or valid_hammer or valid_m_star
        bearish_signal = valid_bear_eng or valid_sstar or valid_e_star
        
        # Entry and exit logic
        if bullish_signal:
            if not self.position:
                self.buy()
        elif bearish_signal:
            if self.position:
                self.sell()
        
        # Exit long on bearish signal
        if self.position and bearish_signal:
            self.sell()


