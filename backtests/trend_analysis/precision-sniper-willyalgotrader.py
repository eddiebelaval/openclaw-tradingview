import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Entry Engine Parameters
    ema_fast_len = 9
    ema_slow_len = 21
    ema_trend_len = 55
    min_score = 5
    rsi_len = 13
    
    # Risk Management Parameters
    atr_len = 14
    sl_mult = 1.5
    tp1_mult = 1.0
    tp2_mult = 2.0
    tp3_mult = 3.0
    use_trail = True
    use_structure_sl = True
    swing_lookback = 10
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Core EMAs
        self.ema_fast = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema_slow = self.I(pta.ema, close, length=self.ema_slow_len)
        self.ema_trend = self.I(pta.ema, close, length=self.ema_trend_len)
        
        # ATR for volatility and risk management
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # RSI for momentum
        self.rsi_val = self.I(pta.rsi, close, length=self.rsi_len)
        
        # MACD for confirmation
        macd_result = self.I(lambda x: pta.macd(x, fast=12, slow=26, signal=9), close)
        self.macd_hist = self.I(lambda x: (pta.macd(x, fast=12, slow=26, signal=9) or pd.DataFrame(0, index=x.index)).iloc[:, 2], close)
        self.macd_val = self.I(lambda x: (pta.macd(x, fast=12, slow=26, signal=9) or pd.DataFrame(0, index=x.index)).iloc[:, 0], close)
        self.macd_sig = self.I(lambda x: (pta.macd(x, fast=12, slow=26, signal=9) or pd.DataFrame(0, index=x.index)).iloc[:, 1], close)
        
        # Volume analysis
        volume = pd.Series(self.data.Volume)
        self.vol_sma = self.I(pta.sma, volume, length=20)
        
        # ADX for trend strength
        adx_result = self.I(lambda h, l, c: pta.adx(h, l, c, length=14), high, low, close)
        self.adx_val = self.I(lambda h, l, c: (pta.adx(h, l, c, length=14) or pd.DataFrame(50, index=h.index)).iloc[:, 0], high, low, close)
        self.di_plus = self.I(lambda h, l, c: (pta.adx(h, l, c, length=14) or pd.DataFrame(25, index=h.index)).iloc[:, 1], high, low, close)
        self.di_minus = self.I(lambda h, l, c: (pta.adx(h, l, c, length=14) or pd.DataFrame(25, index=h.index)).iloc[:, 2], high, low, close)
        
        # VWAP
        hlc3 = (high + low + close) / 3
        self.vwap = self.I(lambda h, l, c, v: pta.vwap(h, l, c, v) or c, high, low, close, volume)
        
        # Swing levels for structure-based SL
        self.swing_low = self.I(lambda l: l.rolling(self.swing_lookback).min(), low)
        self.swing_high = self.I(lambda h: h.rolling(self.swing_lookback).max(), high)
        
        # State tracking
        self.entry_price = None
        self.sl_price = None
        self.tp1_price = None
        self.tp2_price = None
        self.tp3_price = None
        self.trail_price = None
        self.trade_dir = 0  # 1 for long, -1 for short
        self.trade_risk = None
        self.entry_bar = None
        self.tp1_hit = False
        self.tp2_hit = False
        self.tp3_hit = False
        self.sl_hit = False
        self.last_direction = 0
        
    def next(self):
        # Skip warmup period
        if len(self.data) < max(self.ema_trend_len, 50):
            return
        
        # Safe value access
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        ema_f = self.ema_fast[-1] if not np.isnan(self.ema_fast[-1]) else close_val
        ema_s = self.ema_slow[-1] if not np.isnan(self.ema_slow[-1]) else close_val
        ema_t = self.ema_trend[-1] if not np.isnan(self.ema_trend[-1]) else close_val
        atr = self.atr_val[-1] if not np.isnan(self.atr_val[-1]) else (high_val - low_val)
        rsi = self.rsi_val[-1] if not np.isnan(self.rsi_val[-1]) else 50.0
        macd_h = self.macd_hist[-1] if not np.isnan(self.macd_hist[-1]) else 0.0
        macd_v = self.macd_val[-1] if not np.isnan(self.macd_val[-1]) else 0.0
        macd_s = self.macd_sig[-1] if not np.isnan(self.macd_sig[-1]) else 0.0
        
        vol_sma = self.vol_sma[-1] if not np.isnan(self.vol_sma[-1]) else volume_val
        vol_above = volume_val > vol_sma * 1.2 if vol_sma > 0 else True
        
        adx = self.adx_val[-1] if not np.isnan(self.adx_val[-1]) else 0.0
        di_p = self.di_plus[-1] if not np.isnan(self.di_plus[-1]) else 25.0
        di_m = self.di_minus[-1] if not np.isnan(self.di_minus[-1]) else 25.0
        strong_trend = adx > 20
        
        vwap = self.vwap[-1] if not np.isnan(self.vwap[-1]) else close_val
        
        swing_l = self.swing_low[-1] if not np.isnan(self.swing_low[-1]) else low_val
        swing_h = self.swing_high[-1] if not np.isnan(self.swing_high[-1]) else high_val
        
        # ── CONFLUENCE SCORING ──
        bull_score = 0.0
        bull_score += 1.0 if ema_f > ema_s else 0.0
        bull_score += 1.0 if close_val > ema_t else 0.0
        bull_score += 1.0 if 50 < rsi < 75 else 0.0
        bull_score += 1.0 if macd_h > 0 else 0.0
        bull_score += 1.0 if macd_v > macd_s else 0.0
        bull_score += 1.0 if close_val > vwap else 0.0
        bull_score += 1.0 if vol_above else 0.0
        bull_score += 1.0 if strong_trend and di_p > di_m else 0.0
        bull_score += 0.5 if close_val > ema_f else 0.0
        
        bear_score = 0.0
        bear_score += 1.0 if ema_f < ema_s else 0.0
        bear_score += 1.0 if close_val < ema_t else 0.0
        bear_score += 1.0 if 25 < rsi < 50 else 0.0
        bear_score += 1.0 if macd_h < 0 else 0.0
        bear_score += 1.0 if macd_v < macd_s else 0.0
        bear_score += 1.0 if close_val < vwap else 0.0
        bear_score += 1.0 if vol_above else 0.0
        bear_score += 1.0 if strong_trend and di_m > di_p else 0.0
        bear_score += 0.5 if close_val < ema_f else 0.0
        
        # ── SIGNAL GENERATION ──
        ema_bull_cross = crossover(self.ema_fast, self.ema_slow)
        ema_bear_cross = crossover(self.ema_slow, self.ema_fast)
        
        bull_momentum = close_val > ema_f and close_val > ema_s
        bear_momentum = close_val < ema_f and close_val < ema_s
        
        rsi_not_ob = rsi < 75
        rsi_not_os = rsi > 25
        
        raw_buy = ema_bull_cross and bull_momentum and rsi_not_ob and bull_score >= self.min_score
        raw_sell = ema_bear_cross and bear_momentum and rsi_not_os and bear_score >= self.min_score
        
        buy_condition = raw_buy and self.last_direction != 1
        sell_condition = raw_sell and self.last_direction != -1
        
        # Confirmed signals (non-repainting)
        confirmed_buy = buy_condition
        confirmed_sell = sell_condition
        
        # Mutual exclusion
        if confirmed_buy and confirmed_sell:
            confirmed_sell = False
        
        # ── CALCULATE SL/TP ──
        if confirmed_buy:
            self.entry_price = close_val
            self.trade_dir = 1
            
            # Calculate SL
            atr_stop = close_val - atr * self.sl_mult
            if self.use_structure_sl:
                struct_stop = swing_l - atr * 0.2
                final_stop = max(atr_stop, struct_stop)
                min_dist = atr * 0.5
                dist = abs(close_val - final_stop)
                if dist < min_dist:
                    final_stop = close_val - min_dist
                self.sl_price = final_stop
            else:
                self.sl_price = atr_stop
            
            self.trade_risk = abs(close_val - self.sl_price)
            self.tp1_price = close_val + self.trade_risk * self.tp1_mult
            self.tp2_price = close_val + self.trade_risk * self.tp2_mult
            self.tp3_price = close_val + self.trade_risk * self.tp3_mult
            self.trail_price = self.sl_price
            self.tp1_hit = False
            self.tp2_hit = False
            self.tp3_hit = False
            self.sl_hit = False
            self.entry_bar = len(self.data)
            self.last_direction = 1
            self.buy()
        
        elif confirmed_sell:
            self.entry_price = close_val
            self.trade_dir = -1
            
            # Calculate SL
            atr_stop = close_val + atr * self.sl_mult
            if self.use_structure_sl:
                struct_stop = swing_h + atr * 0.2
                final_stop = min(atr_stop, struct_stop)
                min_dist = atr * 0.5
                dist = abs(close_val - final_stop)
                if dist < min_dist:
                    final_stop = close_val + min_dist
                self.sl_price = final_stop
            else:
                self.sl_price = atr_stop
            
            self.trade_risk = abs(close_val - self.sl_price)
            self.tp1_price = close_val - self.trade_risk * self.tp1_mult
            self.tp2_price = close_val - self.trade_risk * self.tp2_mult
            self.tp3_price = close_val - self.trade_risk * self.tp3_mult
            self.trail_price = self.sl_price
            self.tp1_hit = False
            self.tp2_hit = False
            self.tp3_hit = False
            self.sl_hit = False
            self.entry_bar = len(self.data)
            self.last_direction = -1
            self.sell()
        
        # ── TP/SL MANAGEMENT ──
        if self.trade_dir == 1 and self.entry_bar is not None and len(self.data) > self.entry_bar:
            if high_val >= self.tp1_price and not self.tp1_hit:
                self.tp1_hit = True
                if self.use_trail:
                    self.trail_price = self.entry_price
            
            if high_val >= self.tp2_price and not self.tp2_hit:
                self.tp2_hit = True
                if self.use_trail:
                    self.trail_price = self.tp1_price
            
            if high_val >= self.tp3_price and not self.tp3_hit:
                self.tp3_hit = True
                if self.use_trail:
                    self.trail_price = self.tp2_price
            
            if low_val <= self.trail_price:
                self.sl_hit = True
                if self.position:
                    self.position.close()
        
        elif self.trade_dir == -1 and self.entry_bar is not None and len(self.data) > self.entry_bar:
            if low_val <= self.tp1_price and not self.tp1_hit:
                self.tp1_hit = True
                if self.use_trail:
                    self.trail_price = self.entry_price
            
            if low_val <= self.tp2_price and not self.tp2_hit:
                self.tp2_hit = True
                if self.use_trail:
                    self.trail_price = self.tp1_price
            
            if low_val <= self.tp3_price and not self.tp3_hit:
                self.tp3_hit = True
                if self.use_trail:
                    self.trail_price = self.tp2_price
            
            if high_val >= self.trail_price:
                self.sl_hit = True
                if self.position:
                    self.position.close()


