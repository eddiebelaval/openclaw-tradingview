import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivLeft = 5
    pivRight = 5
    maxSwings = 5
    useVolFilter = True
    volMult = 1.2
    volLookback = 20
    useWickFilter = False
    wickRatio = 1.2
    useMomFilter = True
    momLookback = 3

    def init(self):
        self.swing_highs = []
        self.swing_lows = []
        self.zones = []
        self.bull_zone_formed = self.I(lambda: pd.Series(0, index=self.data.Close.index))
        self.bear_zone_formed = self.I(lambda: pd.Series(0, index=self.data.Close.index))
        self.bull_retest = self.I(lambda: pd.Series(0, index=self.data.Close.index))
        self.bear_retest = self.I(lambda: pd.Series(0, index=self.data.Close.index))

    def next(self):
        if len(self.data) < self.pivLeft + self.pivRight + 1:
            return

        close_series = pd.Series(self.data.Close)
        high_series = pd.Series(self.data.High)
        low_series = pd.Series(self.data.Low)
        volume_series = pd.Series(self.data.Volume)
        open_series = pd.Series(self.data.Open)

        current_idx = len(self.data) - 1

        if current_idx >= self.pivRight:
            self.detect_swings(high_series, low_series, current_idx)

        if current_idx >= self.pivRight:
            self.check_sweep_conditions(
                high_series, low_series, close_series, open_series, 
                volume_series, current_idx
            )

        if current_idx > 0:
            self.update_zones(high_series, low_series, close_series, current_idx)

        self.execute_trades(current_idx)

    def detect_swings(self, high_series, low_series, current_idx):
        if current_idx < self.pivLeft + self.pivRight:
            return

        lookback_idx = current_idx - self.pivRight

        is_pivot_high = True
        is_pivot_low = True

        for i in range(self.pivLeft):
            if lookback_idx - i - 1 >= 0:
                if high_series.iloc[lookback_idx - i - 1] >= high_series.iloc[lookback_idx]:
                    is_pivot_high = False
            if lookback_idx + i + 1 < len(high_series):
                if high_series.iloc[lookback_idx + i + 1] >= high_series.iloc[lookback_idx]:
                    is_pivot_high = False

        for i in range(self.pivLeft):
            if lookback_idx - i - 1 >= 0:
                if low_series.iloc[lookback_idx - i - 1] <= low_series.iloc[lookback_idx]:
                    is_pivot_low = False
            if lookback_idx + i + 1 < len(low_series):
                if low_series.iloc[lookback_idx + i + 1] <= low_series.iloc[lookback_idx]:
                    is_pivot_low = False

        if is_pivot_high:
            self.swing_highs.append({
                'bar_idx': lookback_idx,
                'price': high_series.iloc[lookback_idx]
            })
            if len(self.swing_highs) > self.maxSwings:
                self.swing_highs.pop(0)

        if is_pivot_low:
            self.swing_lows.append({
                'bar_idx': lookback_idx,
                'price': low_series.iloc[lookback_idx]
            })
            if len(self.swing_lows) > self.maxSwings:
                self.swing_lows.pop(0)

    def check_momentum_fade(self, close_series, open_series, current_idx, lookback):
        if current_idx - lookback < 0:
            return False

        body_now = abs(close_series.iloc[current_idx] - open_series.iloc[current_idx])
        body_prev = abs(close_series.iloc[current_idx - lookback] - open_series.iloc[current_idx - lookback])

        atr_series = pta.atr(
            pd.Series(self.data.High),
            pd.Series(self.data.Low),
            pd.Series(self.data.Close),
            length=14
        )

        if atr_series is None or len(atr_series) < current_idx:
            return False

        atr_now = atr_series.iloc[current_idx] if current_idx < len(atr_series) else 0
        atr_prev = atr_series.iloc[current_idx - lookback] if current_idx - lookback < len(atr_series) else 0

        body_fade = body_now < body_prev
        atr_fade = atr_now < atr_prev

        return body_fade and atr_fade

    def check_sweep_conditions(self, high_series, low_series, close_series, open_series, 
                              volume_series, current_idx):
        if current_idx < self.pivRight:
            return

        sweep_idx = current_idx - self.pivRight
        sweep_high = high_series.iloc[sweep_idx]
        sweep_low = low_series.iloc[sweep_idx]
        sweep_close = close_series.iloc[sweep_idx]
        sweep_open = open_series.iloc[sweep_idx]
        sweep_vol = volume_series.iloc[sweep_idx]

        avg_vol = pta.sma(pd.Series(self.data.Volume), length=self.volLookback)
        if avg_vol is not None and len(avg_vol) > sweep_idx:
            avg_vol_val = avg_vol.iloc[sweep_idx]
        else:
            avg_vol_val = sweep_vol

        vol_ok = not self.useVolFilter or (sweep_vol >= avg_vol_val * self.volMult)
        mom_fade = self.check_momentum_fade(close_series, open_series, sweep_idx, self.momLookback)

        if len(self.swing_highs) > 0:
            prior_high = self.swing_highs[-1]['price']
            bear_sweep = sweep_high > prior_high and sweep_close < prior_high

            sweep_body = abs(sweep_close - sweep_open)
            upper_wick = sweep_high - max(sweep_close, sweep_open)
            bear_wick_ok = not self.useWickFilter or (sweep_body == 0.0 or upper_wick >= sweep_body * self.wickRatio)
            mom_ok_bear = not self.useMomFilter or mom_fade

            zone_exists = any(z['time'] == sweep_idx for z in self.zones)

            if bear_sweep and vol_ok and bear_wick_ok and mom_ok_bear and not zone_exists:
                self.zones.append({
                    'zone_top': sweep_high,
                    'zone_bot': prior_high,
                    'is_bullish': False,
                    'form_bar': sweep_idx,
                    'time': sweep_idx,
                    'retests': 0,
                    'is_active': True,
                    'in_zone': False,
                    'has_momentum_fade': mom_fade
                })

        if len(self.swing_lows) > 0:
            prior_low = self.swing_lows[-1]['price']
            bull_sweep = sweep_low < prior_low and sweep_close > prior_low

            sweep_body = abs(sweep_close - sweep_open)
            lower_wick = min(sweep_close, sweep_open) - sweep_low
            bull_wick_ok = not self.useWickFilter or (sweep_body == 0.0 or lower_wick >= sweep_body * self.wickRatio)
            mom_ok_bull = not self.useMomFilter or mom_fade

            zone_exists = any(z['time'] == sweep_idx for z in self.zones)

            if bull_sweep and vol_ok and bull_wick_ok and mom_ok_bull and not zone_exists:
                self.zones.append({
                    'zone_top': prior_low,
                    'zone_bot': sweep_low,
                    'is_bullish': True,
                    'form_bar': sweep_idx,
                    'time': sweep_idx,
                    'retests': 0,
                    'is_active': True,
                    'in_zone': False,
                    'has_momentum_fade': mom_fade
                })

    def update_zones(self, high_series, low_series, close_series, current_idx):
        current_high = high_series.iloc[current_idx]
        current_low = low_series.iloc[current_idx]
        current_close = close_series.iloc[current_idx]

        for zone in self.zones:
            if not zone['is_active']:
                continue

            now_inside = (current_high >= zone['zone_bot'] and current_low <= zone['zone_top'])
            if now_inside and not zone['in_zone']:
                zone['retests'] += 1
            zone['in_zone'] = now_inside

            if zone['is_bullish']:
                if current_close < zone['zone_bot']:
                    zone['is_active'] = False
            else:
                if current_close > zone['zone_top']:
                    zone['is_active'] = False

    def execute_trades(self, current_idx):
        active_bullish_zones = [z for z in self.zones if z['is_active'] and z['is_bullish']]
        active_bearish_zones = [z for z in self.zones if z['is_active'] and not z['is_bullish']]

        bull_retests = [z for z in active_bullish_zones if z['retests'] == 1 and z['in_zone']]
        bear_retests = [z for z in active_bearish_zones if z['retests'] == 1 and z['in_zone']]

        if bull_retests and not self.position:
            self.buy()
        elif bear_retests and self.position:
            self.position.close()

        if active_bearish_zones and self.position:
            for zone in active_bearish_zones:
                if zone['in_zone'] and zone['retests'] == 1:
                    self.position.close()
                    break


