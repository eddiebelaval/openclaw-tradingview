        self.fib_swing_low = np.nan
        self.fib_swing_high_idx = -1
        self.fib_swing_low_idx = -1
        self.fib_high_is_live = False
        self.fib_low_is_live = False
        
        self.bars_since_buy = 999
        self.bars_since_sell = 999
        
        self.confluence_weight = 0.0
        self.confluence_score = 0.0
        self.in_premium = False
        self.in_discount = False
        
