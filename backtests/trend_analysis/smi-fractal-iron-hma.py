import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_left = 5
    pivot_right = 1
    smi_scale = 100
    percent_d_length = 3
    percent_k_length = 5
    smi_limit = 30
    use_smi_filter = False
    cooldown_bars = 3
    use_alternating = True
    use_price_filter = False
    price_filter_atr = 0.75
    filter_atr_len = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # SMI Calculation
        min_low = self.I(lambda: low.rolling(self.percent_k_length).min())
        max_high = self.I(lambda: high.rolling(self.percent_k_length).max())
        rel_diff = self.I(lambda: close - (max_high + min_low) / 2.0)
        diffx = self.I(lambda: max_high - min_low)
        
        avgrel = self.I(lambda: pta.ema(pta.ema(rel_diff, length=self.percent_d_length), length=self.percent_d_length))
        avgdiff = self.I(lambda: pta.ema(pta.ema(diffx, length=self.percent_d_length), length=self.percent_d_length))
        
        self.smi_raw = self.I(lambda: (avgrel / (avgdiff / 2.0)) * self.smi_scale if (avgdiff != 0).all() else pd.Series(0, index=close.index))
        self.smi = self.I(lambda: pta.ema(self.smi_raw, length=3))
        
        # ATR for price filter
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.filter_atr_len))
        
        # Pivot detection using rolling max/min
        self.pivot_high = self.I(lambda: high.rolling(window=self.pivot_left + self.pivot_right + 1, center=True).max() == high)
        self.pivot_low = self.I(lambda: low.rolling(window=self.pivot_left + self.pivot_right + 1, center=True).min() == low)

    def next(self):
        if len(self.data) < self.pivot_left + self.pivot_right + 2:
            return
        
        # Check SMI state
        smi_rising = self.smi[-1] > self.smi[-2] if len(self.smi) > 1 else False
        smi_falling = self.smi[-1] < self.smi[-2] if len(self.smi) > 1 else False
        smi_in_chop = -self.smi_limit < self.smi[-1] < self.smi_limit
        
        # Pivot detection
        short_raw = self.pivot_high[-1] if len(self.pivot_high) > 0 else False
        long_raw = self.pivot_low[-1] if len(self.pivot_low) > 0 else False
        
        # Apply SMI filter
        long_base = long_raw and (smi_rising if self.use_smi_filter else True)
        short_base = short_raw and (smi_falling if self.use_smi_filter else True)
        
        # Cooldown filter
        cooldown_ok = (len(self.data) - self.last_signal_bar) >= self.cooldown_bars if hasattr(self, 'last_signal_bar') else True
        
        # Price filter
        price_move_ok = True
        if self.use_price_filter and hasattr(self, 'last_signal_price'):
            price_move_ok = abs(self.data.Close[-1] - self.last_signal_price) >= (self.atr[-1] * self.price_filter_atr)
        
        # Alternating filter
        if not hasattr(self, 'last_signal_dir'):
            self.last_signal_dir = 0
        alternate_ok_long = (self.last_signal_dir != 1) if self.use_alternating else True
        alternate_ok_short = (self.last_signal_dir != -1) if self.use_alternating else True
        
        # Final signal conditions
        filtered_long = long_base and cooldown_ok and price_move_ok and alternate_ok_long
