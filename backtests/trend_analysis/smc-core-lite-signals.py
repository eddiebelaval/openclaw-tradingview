import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Signal parameters
    rr_ratio = 2.0
    signal_cooldown = 10
    
    # Structure parameters
    swing_len = 5
    
    # Zone parameters
    zone_lookback = 50
    ob_strength = 1.5
    
    # ATR period
    atr_period = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # Calculate pivot highs and lows
        self.ph = self.I(self._pivot_high, high, self.swing_len)
        self.pl = self.I(self._pivot_low, low, self.swing_len)
        
        # State variables
        self.swing_h = np.nan
        self.swing_l = np.nan
        self.swing_h_bar = -1
        self.swing_l_bar = -1
        self.bias = 0  # 1 = bull, -1 = bear, 0 = neutral
        self.last_long = -1000
        self.last_short = -1000
        self.recent_bos_bull = False
        self.recent_bos_bear = False
        self.bos_bar = -1000
        
        # Zone storage
        self.fvg_top = []
        self.fvg_bot = []
        self.fvg_bull = []
        self.fvg_active = []
        
        self.ob_top = []
        self.ob_bot = []
        self.ob_bull = []
        self.ob_active = []
        
        # Signal tracking
        self.entry_price = np.nan
        self.sl_price = np.nan
        self.tp_price = np.nan
        self.in_long_signal = False
        self.in_short_signal = False

    def _pivot_high(self, high, length):
        """Calculate pivot highs"""
        result = pd.Series(np.nan, index=high.index)
        for i in range(length, len(high) - length):
            if high.iloc[i] == high.iloc[i-length:i+length+1].max():
                result.iloc[i] = high.iloc[i]
        return result

    def _pivot_low(self, low, length):
        """Calculate pivot lows"""
        result = pd.Series(np.nan, index=low.index)
        for i in range(length, len(low) - length):
            if low.iloc[i] == low.iloc[i-length:i+length+1].min():
                result.iloc[i] = low.iloc[i]
        return result

    def _check_bull_zone(self):
        """Check if price is in bullish zone (FVG or OB)"""
        current_low = self.data.Low[-1]
        
        # Check FVGs
        for i in range(len(self.fvg_active)):
            if self.fvg_active[i] and self.fvg_bull[i]:
                t = self.fvg_top[i]
                b = self.fvg_bot[i]
                if current_low <= t and current_low >= b:
                    return True, b
        
        # Check OBs
        for i in range(len(self.ob_active)):
            if self.ob_active[i] and self.ob_bull[i]:
                t = self.ob_top[i]
                b = self.ob_bot[i]
                if current_low <= t and current_low >= b:
                    return True, b
        
        return False, np.nan

    def _check_bear_zone(self):
        """Check if price is in bearish zone (FVG or OB)"""
        current_high = self.data.High[-1]
        
        # Check FVGs
        for i in range(len(self.fvg_active)):
            if self.fvg_active[i] and not self.fvg_bull[i]:
                t = self.fvg_top[i]
                b = self.fvg_bot[i]
                if current_high >= b and current_high <= t:
                    return True, t
        
        # Check OBs
        for i in range(len(self.ob_active)):
            if self.ob_active[i] and not self.ob_bull[i]:
                t = self.ob_top[i]
                b = self.ob_bot[i]
                if current_high >= b and current_high <= t:
                    return True, t
        
        return False, np.nan

    def next(self):
        idx = len(self.data) - 1
        current_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.1
        
        # Update swing points
        if not np.isnan(self.ph[-1]):
            self.swing_h = self.ph[-1]
            self.swing_h_bar = idx - self.swing_len

        if not np.isnan(self.pl[-1]):
            self.swing_l = self.pl[-1]
            self.swing_l_bar = idx - self.swing_len

        # BOS Detection
        bull_bos = (not np.isnan(self.swing_h) and 
                    self.data.Close[-1] > self.swing_h and 
                    self.data.Close[-2] <= self.swing_h)
        
        bear_bos = (not np.isnan(self.swing_l) and 
                    self.data.Close[-1] < self.swing_l and 
                    self.data.Close[-2] >= self.swing_l)

        if bull_bos:
            self.bias = 1
            self.recent_bos_bull = True
            self.recent_bos_bear = False
            self.bos_bar = idx
            self.swing_h = np.nan

        if bear_bos:
            self.bias = -1
            self.recent_bos_bear = True
            self.recent_bos_bull = False
            self.bos_bar = idx
            self.swing_l = np.nan

        # Reset BOS flags
        if idx - self.bos_bar > 15:
            self.recent_bos_bull = False
            self.recent_bos_bear = False

        # FVG Detection
        if idx > 3:
            # Bullish FVG
            if (self.data.Low[-1] > self.data.High[-3] and 
                self.data.Close[-2] > self.data.Open[-2]):
                self.fvg_top.append(self.data.Low[-1])
                self.fvg_bot.append(self.data.High[-3])
                self.fvg_bull.append(True)
                self.fvg_active.append(True)
            
            # Bearish FVG
            if (self.data.High[-1] < self.data.Low[-3] and 
                self.data.Close[-2] < self.data.Open[-2]):
                self.fvg_top.append(self.data.Low[-3])
                self.fvg_bot.append(self.data.High[-1])
                self.fvg_bull.append(False)
                self.fvg_active.append(True)

        # Order Block Detection
        if idx > 10 and not np.isnan(current_atr):
            impulse = current_atr * self.ob_strength
            
            # Bullish OB
            if ((self.data.Close[-1] - self.data.Open[-1]) > impulse and 
                self.data.Close[-1] > self.data.Open[-1]):
                for i in range(1, 11):
                    if idx - i >= 0 and self.data.Close[-i-1] < self.data.Open[-i-1]:
                        self.ob_top.append(self.data.High[-i-1])
                        self.ob_bot.append(self.data.Low[-i-1])
                        self.ob_bull.append(True)
                        self.ob_active.append(True)
                        break
            
            # Bearish OB
            if ((self.data.Open[-1] - self.data.Close[-1]) > impulse and 
                self.data.Close[-1] < self.data.Open[-1]):
                for i in range(1, 11):
                    if idx - i >= 0 and self.data.Close[-i-1] > self.data.Open[-i-1]:
                        self.ob_top.append(self.data.High[-i-1])
                        self.ob_bot.append(self.data.Low[-i-1])
                        self.ob_bull.append(False)
                        self.ob_active.append(True)
                        break

        # Signal Generation
        if idx > 50 and not np.isnan(current_atr):
            in_bull_zone, bull_zone_bot = self._check_bull_zone()
            in_bear_zone, bear_zone_top = self._check_bear_zone()
            
            bull_candle = self.data.Close[-1] > self.data.Open[-1]
            bear_candle = self.data.Close[-1] < self.data.Open[-1]
            
            # LONG Signal
            long_cond = (in_bull_zone and bull_candle and 
                        (self.recent_bos_bull or self.bias == 1))
            if long_cond and (idx - self.last_long > self.signal_cooldown):
                self.entry_price = self.data.Close[-1]
                sl_base = bull_zone_bot if not np.isnan(bull_zone_bot) else self.data.Low[-1] - current_atr * 0.5
                self.sl_price = sl_base - current_atr * 0.3 if not np.isnan(bull_zone_bot) else sl_base
                self.tp_price = self.entry_price + (self.entry_price - self.sl_price) * self.rr_ratio
                self.last_long = idx
                
                # Execute buy
                if not self.position:
                    self.buy()

            # SHORT Signal
            short_cond = (in_bear_zone and bear_candle and 
                         (self.recent_bos_bear or self.bias == -1))
            if short_cond and (idx - self.last_short > self.signal_cooldown):
                self.entry_price = self.data.Close[-1]
                sl_base = bear_zone_top if not np.isnan(bear_zone_top) else self.data.High[-1] + current_atr * 0.5
                self.sl_price = sl_base + current_atr * 0.3 if not np.isnan(bear_zone_top) else sl_base
                self.tp_price = self.entry_price - (self.sl_price - self.entry_price) * self.rr_ratio
                self.last_short = idx
                
                # Execute sell
                if self.position:
                    self.sell()

        # Position Management
        if self.position:
            if self.position.is_long:
                if self.data.Low[-1] <= self.sl_price or self.data.High[-1] >= self.tp_price:
                    self.sell()
            else:
                if self.data.High[-1] >= self.sl_price or self.data.Low[-1] <= self.tp_price:
                    self.buy()


