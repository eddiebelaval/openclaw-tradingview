import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLen = 10
    factor = 3.0
    rsiLen = 14
    obLevel = 70
    osLevel = 30
    rsiLookback = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Supertrend manually
        def supertrend_calc():
            hl_avg = (high + low) / 2
            atr = pta.atr(high, low, close, length=self.atrLen)
            
            if atr is None:
                return pd.Series(0, index=close.index), pd.Series(0, index=close.index)
            
            basic_ub = hl_avg + self.factor * atr
            basic_lb = hl_avg - self.factor * atr
            
            final_ub = basic_ub.copy()
            final_lb = basic_lb.copy()
            
            st_line = basic_ub.copy()
            st_dir = pd.Series(1, index=close.index)
            
            for i in range(1, len(close)):
                if basic_ub.iloc[i] < final_ub.iloc[i - 1] or close.iloc[i - 1] > final_ub.iloc[i - 1]:
                    final_ub.iloc[i] = basic_ub.iloc[i]
                else:
                    final_ub.iloc[i] = final_ub.iloc[i - 1]
                
                if basic_lb.iloc[i] > final_lb.iloc[i - 1] or close.iloc[i - 1] < final_lb.iloc[i - 1]:
                    final_lb.iloc[i] = basic_lb.iloc[i]
                else:
                    final_lb.iloc[i] = final_lb.iloc[i - 1]
                
                if st_dir.iloc[i - 1] == 1:
                    st_line.iloc[i] = final_lb.iloc[i]
                    if close.iloc[i] <= final_lb.iloc[i]:
                        st_dir.iloc[i] = -1
                    else:
                        st_dir.iloc[i] = 1
                else:
                    st_line.iloc[i] = final_ub.iloc[i]
                    if close.iloc[i] >= final_ub.iloc[i]:
                        st_dir.iloc[i] = 1
                    else:
                        st_dir.iloc[i] = -1
            
            return st_line, st_dir
        
        self.st_line, self.st_dir = self.I(supertrend_calc)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        # Lowest RSI over lookback
        self.lowest_rsi = self.I(lambda: close.rolling(1).apply(
            lambda x: pd.Series(self.rsi).rolling(self.rsiLookback).min().iloc[-1] if len(self.rsi) >= self.rsiLookback else self.rsi[-1],
            raw=False
        ))
        
        # Highest RSI over lookback
        self.highest_rsi = self.I(lambda: close.rolling(1).apply(
            lambda x: pd.Series(self.rsi).rolling(self.rsiLookback).max().iloc[-1] if len(self.rsi) >= self.rsiLookback else self.rsi[-1],
            raw=False
        ))

    def next(self):
        if len(self.data) < 2:
            return
        
        # Supertrend direction flip detection
        bull_flip = self.st_dir[-1] == -1 and self.st_dir[-2] == 1
        bear_flip = self.st_dir[-1] == 1 and self.st_dir[-2] == -1
        
        # RSI confirmation
        was_oversold = self.lowest_rsi[-1] <= self.osLevel
        was_overbought = self.highest_rsi[-1] >= self.obLevel
        
        # Confirmed signals
        buy_signal = bull_flip and was_oversold
        sell_signal = bear_flip and was_overbought
        
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()


