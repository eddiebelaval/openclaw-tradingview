import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    contract_qty = 4
    daily_profit_target = 2000.0
    daily_loss_limit = 350.0
    use_time_filter = False
    tp_ticks = 250
    sl_ticks = 45
    trail_activation = 20
    trade_ghosts = True
    atr_min = 2.2
    rsi_buy = 45
    rsi_sell = 55

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.rsi = self.I(pta.rsi, close, length=14)
        self.atr = self.I(pta.atr, high, low, close, length=14)

        self.highest_50 = self.I(lambda: high.rolling(window=50).max())
        self.lowest_50 = self.I(lambda: low.rolling(window=50).min())

        self.day_start_equity = self.equity

    def next(self):
        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]

        if len(self.data) < 2:
            return

        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0

        is_new_day = len(self.data) > 1 and self.data.index[len(self.data) - 1].date() != self.data.index[len(self.data) - 2].date()
        if is_new_day:
            self.day_start_equity = self.equity

        current_daily_profit = self.equity - self.day_start_equity
        can_trade_today = current_daily_profit < self.daily_profit_target and current_daily_profit > -self.daily_loss_limit

        length = 1
        is_pivot_high = len(self.data) >= length + 2 and high_price > self.data.High[-2] and self.data.High[-2] > self.data.High[-(length + 2)]
        is_pivot_low = len(self.data) >= length + 2 and low_price < self.data.Low[-2] and self.data.Low[-2] < self.data.Low[-(length + 2)]

        highest_50_val = self.highest_50[-1] if self.highest_50[-1] is not None else high_price
        lowest_50_val = self.lowest_50[-1] if self.lowest_50[-1] is not None else low_price

        ghost_high = is_pivot_high and len(self.data) >= length + 2 and self.data.High[-(length + 1)] < highest_50_val
        ghost_low = is_pivot_low and len(self.data) >= length + 2 and self.data.Low[-(length + 1)] > lowest_50_val

        buy_signal = can_trade_today and self.position.size == 0 and (is_pivot_low or (self.trade_ghosts and ghost_low)) and rsi_val < self.rsi_buy and atr_val > self.atr_min

        sell_signal = can_trade_today and self.position.size == 0 and (is_pivot_high or (self.trade_ghosts and ghost_high)) and rsi_val > self.rsi_sell and atr_val > self.atr_min

        if buy_signal:
            self.buy(size=self.contract_qty)

        if sell_signal:
            self.sell(size=self.contract_qty)

        if self.position.size > 0:
            exit_price = close_price
            entry_price = self.position.open_price
            profit_ticks = (exit_price - entry_price) * 10000
            loss_ticks = (entry_price - exit_price) * 10000

            if profit_ticks >= self.tp_ticks or loss_ticks >= self.sl_ticks:
                self.position.close()

        elif self.position.size < 0:
            exit_price = close_price
            entry_price = self.position.open_price
            profit_ticks = (entry_price - exit_price) * 10000
            loss_ticks = (exit_price - entry_price) * 10000

            if profit_ticks >= self.tp_ticks or loss_ticks >= self.sl_ticks:
                self.position.close()


