import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 3
    bull_threshold = -0.51
    bear_threshold = 0.43

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # hl2 = (high + low) / 2
        hl2 = (high + low) / 2
        
        # ValC = ta.sma(hl2, length)
        self.valc = self.I(pta.sma, hl2, length=self.length)
        
        # vol = ta.sma(ta.atr(length), length)
        atr = self.I(pta.atr, high, low, close, length=self.length)
        self.vol = self.I(pta.sma, atr, length=self.length)
        
        # cvi = (close - ValC) / (vol * math.sqrt(length))
        def calc_cvi():
            if self.valc[-1] is None or self.vol[-1] is None or self.vol[-1] == 0:
                return 0
            return (close.iloc[-1] - self.valc[-1]) / (self.vol[-1] * np.sqrt(self.length))
        
        self.cvi = self.I(calc_cvi)
        
        # Track previous cvi values for detecting crossovers
        self.cvi_prev = None

    def next(self):
        if len(self.data) < 2 or self.cvi[-1] is None or self.vol[-1] is None:
            return
        
        current_cvi = self.cvi[-1]
        
        # bull1 = cvi <= bull
        bull1_current = current_cvi <= self.bull_threshold
        
        # bear1 = cvi >= bear
        bear1_current = current_cvi >= self.bear_threshold
        
        # Get previous values
        if self.cvi_prev is None:
            self.cvi_prev = current_cvi
            return
        
        prev_cvi = self.cvi_prev
        bull1_prev = prev_cvi <= self.bull_threshold
        bear1_prev = prev_cvi >= self.bear_threshold
        
        # bull2 = bull1[1] and not bull1 (was below, now above threshold)
        bull2 = bull1_prev and not bull1_current
        
        # bear2 = bear1[1] and not bear1 (was above, now below threshold)
        bear2 = bear1_prev and not bear1_current
        
        # Trading logic
        if bull2:
            if self.position:
                self.position.close()
            self.buy()
        elif bear2:
            if self.position:
                self.position.close()
            self.sell()
        
        self.cvi_prev = current_cvi


