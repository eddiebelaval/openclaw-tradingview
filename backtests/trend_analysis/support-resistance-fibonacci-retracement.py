import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 21
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate highest high and lowest low over lookback period
        self.highest = self.I(lambda: high.rolling(self.lookback).max())
        self.lowest = self.I(lambda: low.rolling(self.lookback).min())
        
        # Calculate Fibonacci levels
        self.range_val = self.I(lambda: self.highest - self.lowest)
        self.fib_0236 = self.I(lambda: self.lowest + (self.range_val * 0.236))
        self.fib_0382 = self.I(lambda: self.lowest + (self.range_val * 0.382))
        self.fib_0500 = self.I(lambda: self.lowest + (self.range_val * 0.500))
        self.fib_0618 = self.I(lambda: self.lowest + (self.range_val * 0.618))
        self.fib_0786 = self.I(lambda: self.lowest + (self.range_val * 0.786))

    def next(self):
        # Check if we have valid indicator values
        if len(self.data) < self.lookback + 1:
            return
        
        # Entry: Price crosses above 0.236 Fibonacci level
        if crossover(self.data.Close, self.fib_0236):
            if not self.position:
                self.buy()
        
        # Exit: Price crosses below 0.618 Fibonacci level
        if crossover(self.fib_0618, self.data.Close):
            if self.position:
                self.position.close()


