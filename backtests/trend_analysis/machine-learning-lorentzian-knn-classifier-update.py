import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend Following
    trend_ema_fast = 21
    trend_ema_slow = 50
    trend_ema_filter = 200
    
    # MTF Filter
    mtf_ema_fast = 21
    mtf_ema_slow = 55
    
    # MA Ribbon
    ribbon_ma1 = 8
    ribbon_ma2 = 13
    ribbon_ma3 = 21
    ribbon_ma4 = 34
    ribbon_ma5 = 55
    ribbon_ma6 = 89
    ribbon_ma7 = 144
    ribbon_ma8 = 233
    ribbon_threshold = 6
    ribbon_type = "EMA"
    
    # Breakout
    breakout_length = 20
    breakout_atr_mult = 1.5
    
    # Mean Reversion
    bb_length = 20
    bb_mult = 2.0
    rsi_length = 14
    rsi_ob = 70
    rsi_os = 30
    
    # Risk Management
    atr_length = 14
    stop_atr_mult = 2.0
    tp_atr_mult = 3.0
    
    # Filters
    adx_length = 14
    adx_threshold = 20
    volume_mult = 1.2
    
    # Lorentzian KNN
    knn_neighbors = 8
    knn_lookback = 50
    knn_weight = 0.55
    knn_rsi_len = 14
    knn_wt_n1 = 10
    knn_wt_n2 = 21
    knn_cci_len = 20
    knn_adx_len = 14
    
    # Kernel
    kernel_len = 34
    kernel_atr_len = 20
    
    # Strategy flags
    use_mtf_filter = True
    use_ma_ribbon = True
    use_order_flow = True
    use_smc = True
    use_vol_regime = True
    cvd_length = 20
    cvd_threshold = 0.6
    fvg_min_size = 0.5
    ob_lookback = 10
    liquidity_lookback = 20
    bos_pivot_length = 5
    ds_impulse_mult = 1.5
    bb_vr_length = 20
    bb_vr_mult = 2.0
    atr_percentile_length = 100
    vol_expansion_threshold = 1.5
    vol_contraction_threshold = 0.7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Trend EMAs
        self.ema_fast = self.I(pta.ema, close, length=self.trend_ema_fast)
        self.ema_slow = self.I(pta.ema, close, length=self.trend_ema_slow)
        self.ema_filter = self.I(pta.ema, close, length=self.trend_ema_filter)
        
        # ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_length) or pd.DataFrame(0, index=close.index, columns=['ADX']))
        self.adx = self.I(lambda: adx_result['ADX'] if adx_result is not None and 'ADX' in adx_result.columns else pd.Series(20, index=close.index))
        
        # Bollinger Bands
        bb = self.I(lambda: pta.bbands(close, length=self.bb_length, std=self.bb_mult) or pd.DataFrame(index=close.index, columns=['BBL_20_2.0', 'BBM_20_2.0', 'BBU_20_2.0']))
        self.bb_upper = self.I(lambda: bb['BBU_'+str(self.bb_length)+'_'+str(self.bb_mult)] if bb is not None else pd.Series(0, index=close.index))
        self.bb_lower = self.I(lambda: bb['BBL_'+str(self.bb_length)+'_'+str(self.bb_mult)] if bb is not None else pd.Series(0, index=close.index))
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Volume SMA
        self.volume_sma = self.I(pta.sma, volume, length=20)
        
        # Highest/Lowest
        self.highest_high = self.I(lambda: pd.Series(high).rolling(self.breakout_length).max())
        self.lowest_low = self.I(lambda: pd.Series(low).rolling(self.breakout_length).min())
        
        # MA Ribbon
        self.r1 = self.I(pta.ema, close, length=self.ribbon_ma1)
        self.r2 = self.I(pta.ema, close, length=self.ribbon_ma2)
        self.r3 = self.I(pta.ema, close, length=self.ribbon_ma3)
        self.r4 = self.I(pta.ema, close, length=self.ribbon_ma4)
        self.r5 = self.I(pta.ema, close, length=self.ribbon_ma5)
        self.r6 = self.I(pta.ema, close, length=self.ribbon_ma6)
        self.r7 = self.I(pta.ema, close, length=self.ribbon_ma7)
        self.r8 = self.I(pta.ema, close, length=self.ribbon_ma8)
        
        # CCI
        self.cci = self.I(pta.cci, high, low, close, length=self.knn_cci_len)
        
        # RSI for KNN
        self.knn_rsi = self.I(pta.rsi, close, length=self.knn_rsi_len)

    def next(self):
        if len(self.data) < max(self.knn_lookback + 20, self.breakout_length + 10):
            return
        
        # Current values
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        atr_val = self.atr[-1]
        ema_fast_val = self.ema_fast[-1]
        ema_slow_val = self.ema_slow[-1]
        ema_filter_val = self.ema_filter[-1]
        adx_val = self.adx[-1]
        rsi_val = self.rsi[-1]
        bb_upper_val = self.bb_upper[-1]
        bb_lower_val = self.bb_lower[-1]
        volume_sma_val = self.volume_sma[-1]
        
        # Ribbon alignment
        ribbon_bullish_count = (
            (1 if self.r1[-1] > self.r2[-1] else 0) +
            (1 if self.r2[-1] > self.r3[-1] else 0) +
            (1 if self.r3[-1] > self.r4[-1] else 0) +
            (1 if self.r4[-1] > self.r5[-1] else 0) +
            (1 if self.r5[-1] > self.r6[-1] else 0) +
            (1 if self.r6[-1] > self.r7[-1] else 0) +
            (1 if self.r7[-1] > self.r8[-1] else 0)
        )
        ribbon_bearish_count = 7 - ribbon_bullish_count
        
        ribbon_bullish = ribbon_bullish_count >= (self.ribbon_threshold - 1)
        ribbon_bearish = ribbon_bearish_count >= (self.ribbon_threshold - 1)
        
        # Filters
        ribbon_filter_long = not self.use_ma_ribbon or ribbon_bullish
        ribbon_filter_short = not self.use_ma_ribbon or ribbon_bearish
        mtf_filter_long = not self.use_mtf_filter or ema_fast_val > ema_slow_val
        mtf_filter_short = not self.use_mtf_filter or ema_fast_val < ema_slow_val
        
        # Volume filter
        volume_spike = volume_val > volume_sma_val * self.volume_mult
        
        # Trend conditions
        is_trending = adx_val > self.adx_threshold
        bullish_trend = ema_fast_val > ema_slow_val and close_val > ema_filter_val
        bearish_trend = ema_fast_val < ema_slow_val and close_val < ema_filter_val
        
        ema_cross_up = crossover(self.ema_fast, self.ema_slow)
        ema_cross_down = crossover(self.ema_slow, self.ema_fast)
        rsi_cross_up = crossover(self.rsi, self.rsi_os)
        rsi_cross_down = crossover(self.rsi, self.rsi_ob)
        
        # Entry conditions
        trend_long = is_trending and bullish_trend and ema_cross_up and volume_spike
        trend_short = is_trending and bearish_trend and ema_cross_down and volume_spike
        
        breakout_long = close_val > self.highest_high[-2] and volume_spike and close_val > ema_filter_val
        breakout_short = close_val < self.lowest_low[-2] and volume_spike and close_val < ema_filter_val
        
        mean_reversion_long = not is_trending and close_val < bb_lower_val and rsi_val < self.rsi_os and rsi_cross_up
        mean_reversion_short = not is_trending and close_val > bb_upper_val and rsi_val > self.rsi_ob and rsi_cross_down
        
        long_condition = (trend_long or breakout_long or mean_reversion_long) and mtf_filter_long and ribbon_filter_long
        short_condition = (trend_short or breakout_short or mean_reversion_short) and mtf_filter_short and ribbon_filter_short
        
        # Execute trades
        if long_condition and self.position.size == 0:
            stop_loss = close_val - (atr_val * self.stop_atr_mult)
            take_profit = close_val + (atr_val * self.tp_atr_mult)
            self.buy()
            
        elif short_condition and self.position.size == 0:
            stop_loss = close_val + (atr_val * self.stop_atr_mult)
            take_profit = close_val - (atr_val * self.tp_atr_mult)
            self.sell()
        
        # Exit conditions - trailing stop on significant reversals
        if self.position.size > 0:
            if close_val < self.ema_filter[-1] or rsi_val > self.rsi_ob:
                self.position.close()
        
        elif self.position.size < 0:
            if close_val > self.ema_filter[-1] or rsi_val < self.rsi_os:
                self.position.close()