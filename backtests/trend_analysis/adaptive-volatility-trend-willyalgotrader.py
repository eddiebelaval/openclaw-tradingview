import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Main Settings
    length = 21
    atr_len = 14
    atr_mult = 2.0
    preset = "Default"
    
    # Filters
    use_rsi_filter = True
    rsi_len = 14
    rsi_ob = 70
    rsi_os = 30
    use_vol_filter = True
    vol_mult = 1.2
    
    # Advanced
    er_smooth = 5
    min_score = 40

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Determine effective parameters based on preset
        if self.preset == "Conservative":
            self.effective_length = 30
            self.effective_atr_len = 20
            self.effective_mult = 2.5
        elif self.preset == "Aggressive":
            self.effective_length = 12
            self.effective_atr_len = 10
            self.effective_mult = 1.5
        elif self.preset == "Scalping":
            self.effective_length = 8
            self.effective_atr_len = 7
            self.effective_mult = 1.2
        else:
            self.effective_length = self.length
            self.effective_atr_len = self.atr_len
            self.effective_mult = self.atr_mult
        
        # Calculate efficiency ratio
        def calc_efficiency_ratio():
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if i < self.effective_length:
                    result.iloc[i] = 0.0
                else:
                    direction = abs(close.iloc[i] - close.iloc[i - self.effective_length])
                    volatility = sum(abs(close.iloc[i - j] - close.iloc[i - j - 1]) 
                                   for j in range(self.effective_length))
                    result.iloc[i] = direction / volatility if volatility != 0 else 0.0
            return result
        
        self.efficiency_ratio = self.I(calc_efficiency_ratio)
        
        # Smooth efficiency ratio with EMA
        def smooth_efficiency():
            result = pd.Series(index=close.index, dtype=float)
            er = calc_efficiency_ratio()
            result.iloc[0] = 0.5
            alpha = 2.0 / (self.er_smooth + 1)
            for i in range(1, len(er)):
                result.iloc[i] = alpha * er.iloc[i] + (1 - alpha) * result.iloc[i - 1]
            return result
        
        self.er_smooth_line = self.I(smooth_efficiency)
        
        # Calculate adaptive MA
        def calc_adaptive_ma():
            result = pd.Series(index=close.index, dtype=float)
            er_smooth = smooth_efficiency()
            fast_sc = 2.0 / 3.0
            slow_sc = 2.0 / 31.0
            result.iloc[0] = close.iloc[0]
            for i in range(1, len(close)):
                sc = ((er_smooth.iloc[i] * (fast_sc - slow_sc) + slow_sc) ** 2)
                result.iloc[i] = result.iloc[i - 1] + sc * (close.iloc[i] - result.iloc[i - 1])
            return result
        
        self.adapt_line = self.I(calc_adaptive_ma)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.effective_atr_len)
        
        # Calculate band width
        def calc_band_width():
            er = self.efficiency_ratio
            atr_vals = self.atr
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                er_factor = 1.0 - (er.iloc[i] if not pd.isna(er.iloc[i]) else 0.5) * 0.4
                atr_val = atr_vals.iloc[i] if not pd.isna(atr_vals.iloc[i]) else 0.0
                result.iloc[i] = atr_val * self.effective_mult * er_factor
            return result
        
        self.band_width = self.I(calc_band_width)
        
        # Upper and lower bands
        def calc_upper_band():
            return self.adapt_line + self.band_width
        
        def calc_lower_band():
            return self.adapt_line - self.band_width
        
        self.upper_band = self.I(calc_upper_band)
        self.lower_band = self.I(calc_lower_band)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        # Volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=20)
        
        # Trend direction
        self.trend_dir = 0
        self.prev_adapt_line = None
        
        self.warmup_bars = max(self.effective_length * 2, 50)

    def next(self):
        # Check warmup
        if len(self.data) < self.warmup_bars:
            return
        
        # Current values
        current_adapt = self.adapt_line[-1]
        current_atr = self.atr[-1] if not pd.isna(self.atr[-1]) else 0.0
        current_source = self.data.Close[-1]
        current_rsi = self.rsi[-1] if not pd.isna(self.rsi[-1]) else 50.0
        current_vol = self.data.Volume[-1]
        current_vol_sma = self.vol_sma[-1] if not pd.isna(self.vol_sma[-1]) else current_vol
        
        # Calculate trend direction
        if len(self.data) > 1:
            prev_adapt = self.adapt_line[-2]
            threshold = current_atr * 0.05
            if (current_adapt - prev_adapt) > threshold:
                self.trend_dir = 1
            elif (current_adapt - prev_adapt) < -threshold:
                self.trend_dir = -1
        
        is_bull_trend = self.trend_dir == 1
        is_bear_trend = self.trend_dir == -1
        
        # Check if trend just flipped
        if len(self.data) > 1:
            prev_trend_dir = 1 if (self.adapt_line[-2] - self.adapt_line[-3]) > 0 else (-1 if (self.adapt_line[-2] - self.adapt_line[-3]) < 0 else 0)
            trend_flip_bull = is_bull_trend and prev_trend_dir != 1
            trend_flip_bear = is_bear_trend and prev_trend_dir != -1
        else:
            trend_flip_bull = False
            trend_flip_bear = False
        
        # Price position
        price_above = current_source > current_adapt
        price_below = current_source < current_adapt
        
        # Volume confirmation
        has_volume = current_vol > 0
        vol_ratio = (current_vol / current_vol_sma) if current_vol_sma > 0 else 1.0
        vol_confirm = (not self.use_vol_filter or not has_volume or 
                      (vol_ratio >= self.vol_mult))
        
        # RSI filters
        rsi_buy_ok = not self.use_rsi_filter or current_rsi < self.rsi_ob
        rsi_sell_ok = not self.use_rsi_filter or current_rsi > self.rsi_os
        
        # Base conditions
        buy_condition = trend_flip_bull and price_above and rsi_buy_ok and vol_confirm
        sell_condition = trend_flip_bear and price_below and rsi_sell_ok and vol_confirm
        
        # Signal scoring (0-100)
        def calc_score(is_bull, er_val, rsi_val, vol_r):
            # Trend strength (0-40)
            trend_score = min(er_val * 60.0, 40.0)
            # Momentum (0-30)
            rsi_dist = max(rsi_val - 50.0, 0.0) if is_bull else max(50.0 - rsi_val, 0.0)
            mom_score = min(rsi_dist * 1.0, 30.0)
            # Volume (0-30)
            vol_score = min(max(vol_r - 1.0, 0.0) * 30.0, 30.0) if has_volume else 15.0
            total = trend_score + mom_score + vol_score
            return int(min(total, 100.0))
        
        er_val = self.efficiency_ratio[-1] if not pd.isna(self.efficiency_ratio[-1]) else 0.0
        buy_score = calc_score(True, er_val, current_rsi, vol_ratio) if buy_condition else 0
        sell_score = calc_score(False, er_val, current_rsi, vol_ratio) if sell_condition else 0
        
        # Execute trades based on score
        if buy_condition and buy_score >= self.min_score:
            if not self.position:
                self.buy()
        
        if sell_condition and sell_score >= self.min_score:
            if self.position:
                self.position.close()


