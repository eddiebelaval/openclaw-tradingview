import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Pivot detection
    lookback_period = 200
    pivot_strength = 5
    
    # Clustering
    atr_multiplier = 1.0
    atr_length = 14
    
    # Zone filtering
    min_touches = 2
    breakout_atr_mult = 2.0
    
    # Auto mode
    auto_mode = True
    target_zones = 5

    def init(self):
        # Calculate ATR for clustering
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Store pivot data for clustering
        self.pivot_prices = []
        self.pivot_bars = []
        self.pivot_types = []
        
        # Track zones for trading
        self.support_zones = []
        self.resistance_zones = []

    def next(self):
        # Detect pivots
        if len(self.data) < self.pivot_strength * 2 + 1:
            return
        
        idx = len(self.data) - 1
        ps = self.pivot_strength
        
        # Check for pivot high
        if idx >= ps and idx < len(self.data) - ps:
            current_high = self.data.High[idx]
            is_pivot_high = True
            for i in range(1, ps + 1):
                if self.data.High[idx - i] >= current_high or self.data.High[idx + i] >= current_high:
                    is_pivot_high = False
                    break
            if is_pivot_high:
                self.pivot_prices.append(current_high)
                self.pivot_bars.append(idx - ps)
                self.pivot_types.append(1)
        
        # Check for pivot low
        if idx >= ps and idx < len(self.data) - ps:
            current_low = self.data.Low[idx]
            is_pivot_low = True
            for i in range(1, ps + 1):
                if self.data.Low[idx - i] <= current_low or self.data.Low[idx + i] <= current_low:
                    is_pivot_low = False
                    break
            if is_pivot_low:
                self.pivot_prices.append(current_low)
                self.pivot_bars.append(idx - ps)
                self.pivot_types.append(-1)
        
        # On last bar, perform full clustering and zone detection
        if idx == len(self.data) - 1:
            self._compute_zones()
            self._generate_signals()

    def _compute_zones(self):
        """Cluster pivots and compute support/resistance zones"""
        if len(self.pivot_prices) < 2:
            self.support_zones = []
            self.resistance_zones = []
            return
        
        # Filter pivots to lookback window
        cutoff_bar = len(self.data) - 1 - self.lookback_period
        window_prices = [p for p, b in zip(self.pivot_prices, self.pivot_bars) if b >= cutoff_bar]
        
        if len(window_prices) < 2:
            self.support_zones = []
            self.resistance_zones = []
            return
        
        # Determine clustering tolerance
        atr_val = self.atr[-1] if self.atr[-1] is not None else 1.0
        
        if self.auto_mode:
            final_tolerance = self._binary_search_tolerance(window_prices, atr_val)
            effective_min_touches = 1
        else:
            final_tolerance = atr_val * self.atr_multiplier
            effective_min_touches = self.min_touches
        
        # Perform clustering
        sorted_prices = sorted(window_prices)
        clusters = self._greedy_cluster(sorted_prices, final_tolerance)
        
        if not clusters:
            self.support_zones = []
            self.resistance_zones = []
            return
        
        # Count touches and bounces for each zone
        zone_data = []
        for mid, members in clusters:
            half_w = final_tolerance * 0.25
            upper = mid + half_w
            lower = mid - half_w
            
            touches = 0
            bounces = 0
            
            scan_bars = min(self.lookback_period, len(self.data) - 1)
            for i in range(1, scan_bars):
                bar_idx = len(self.data) - 1 - i
                if bar_idx < 0:
                    break
                
                b_high = self.data.High[bar_idx]
                b_low = self.data.Low[bar_idx]
                b_close = self.data.Close[bar_idx]
                p_close = self.data.Close[bar_idx + 1] if bar_idx + 1 < len(self.data) else b_close
                
                if b_low <= upper and b_high >= lower:
                    touches += 1
                    
                    if mid <= b_close and b_close > p_close:
                        bounces += 1
                    elif mid > b_close and b_close < p_close:
                        bounces += 1
            
            if touches >= effective_min_touches:
                zone_data.append({
                    'mid': mid,
                    'half_w': half_w,
                    'touches': touches,
                    'bounces': bounces,
                    'members': len(members),
                    'dist': abs(self.data.Close[-1] - mid)
                })
        
        # Prune broken zones
        break_dist = atr_val * self.breakout_atr_mult
        current_price = self.data.Close[-1]
        
        valid_zones = []
        for z in zone_data:
            upper = z['mid'] + z['half_w']
            lower = z['mid'] - z['half_w']
            
            broken_support = current_price < lower - break_dist
            broken_resistance = current_price > upper + break_dist
            
            if not (broken_support or broken_resistance):
                valid_zones.append(z)
        
        # Sort by distance and separate into support/resistance
        valid_zones.sort(key=lambda x: x['dist'])
        
        self.support_zones = [z for z in valid_zones if z['mid'] <= current_price][:self.target_zones]
        self.resistance_zones = [z for z in valid_zones if z['mid'] > current_price][:self.target_zones]

    def _binary_search_tolerance(self, prices, atr_val):
        """Binary search for tolerance that produces target number of zones"""
        tol_low = atr_val * 0.1
        tol_high = atr_val * 8.0
        
        for _ in range(15):
            mid_tol = (tol_low + tol_high) / 2.0
            cluster_count = len(self._greedy_cluster(sorted(prices), mid_tol))
            
            if cluster_count > self.target_zones + 1:
                tol_low = mid_tol
            elif cluster_count < self.target_zones - 1:
                tol_high = mid_tol
            else:
                break
        
        return (tol_low + tol_high) / 2.0

    def _greedy_cluster(self, sorted_prices, tolerance):
        """Greedy clustering: merge prices within tolerance"""
        if not sorted_prices:
            return []
        
        clusters = []
        run_sum = sorted_prices[0]
        run_n = 1
        run_min = sorted_prices[0]
        run_max = sorted_prices[0]
        
        for i in range(1, len(sorted_prices)):
            p = sorted_prices[i]
            current_mid = run_sum / run_n
            
            if abs(p - current_mid) <= tolerance:
                run_sum += p
                run_n += 1
                run_min = min(run_min, p)
                run_max = max(run_max, p)
            else:
                mid = run_sum / run_n
                clusters.append(([run_min, run_max], [run_sum / run_n] * run_n))
                run_sum = p
                run_n = 1
                run_min = p
                run_max = p
        
        mid = run_sum / run_n
        clusters.append(([run_min, run_max], [run_sum / run_n] * run_n))
        
        return [(c[1][0], c[1]) for c in clusters]

    def _generate_signals(self):
        """Generate buy/sell signals based on zones"""
        current_price = self.data.Close[-1]
        
        # Buy signal: price touches support zone
        for zone in self.support_zones:
            if current_price <= zone['mid'] + zone['half_w'] and current_price >= zone['mid'] - zone['half_w']:
                if not self.position:
                    self.buy()
                return
        
        # Sell signal: price touches resistance zone
        for zone in self.resistance_zones:
            if current_price <= zone['mid'] + zone['half_w'] and current_price >= zone['mid'] - zone['half_w']:
                if self.position:
                    self.sell()
                return
        
        # Exit support zone break
        if self.position and self.support_zones:
            lowest_support = min(z['mid'] - z['half_w'] for z in self.support_zones)
            if current_price < lowest_support:
                self.sell()


