import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    emaLen = 21
    pivotLength = 21
    adxLen = 14
    diLen = 14
    adx_threshold = 25

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI calculation (using RMA like Pine Script ta.rma)
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLen) or pd.Series(50, index=close.index))
        
        # RSI EMA and SMA
        self.rsiEma = self.I(lambda: pta.ema(self.rsi, length=self.emaLen) or pd.Series(50, index=close.index))
        self.rsiMa = self.I(lambda: pta.sma(self.rsi, length=14) or pd.Series(50, index=close.index))
        
        # SAR (Parabolic SAR)
        self.sar = self.I(lambda: pta.sar(high, low, close, iaf=0.02, maxaf=0.2) or pd.Series(0, index=close.index))
        
        # ADX and DI
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.diLen) or pd.DataFrame(index=close.index))
        self.adx = self.I(lambda: adx_result.iloc[:, 2] if isinstance(adx_result, pd.DataFrame) and len(adx_result.columns) > 2 else pd.Series(25, index=close.index))
        self.di_plus = self.I(lambda: adx_result.iloc[:, 0] if isinstance(adx_result, pd.DataFrame) and len(adx_result.columns) > 0 else pd.Series(20, index=close.index))
        
        # Pivot High and Low detection using rolling max/min
        self.pivot_high = self.I(lambda: self._detect_pivot_high(self.rsi, self.pivotLength))
        self.pivot_low = self.I(lambda: self._detect_pivot_low(self.rsi, self.pivotLength))
        
        # Divergence tracking
        self.last_ph_rsi = None
        self.last_ph_bar = None
        self.last_pl_rsi = None
        self.last_pl_bar = None
        self.bull_div_detected = False
        self.bear_div_detected = False

    def _detect_pivot_high(self, rsi_series, length):
        result = pd.Series(np.nan, index=rsi_series.index)
        for i in range(length, len(rsi_series) - length):
            if rsi_series.iloc[i] == rsi_series.iloc[i-length:i+length+1].max():
                result.iloc[i] = rsi_series.iloc[i]
        return result

    def _detect_pivot_low(self, rsi_series, length):
        result = pd.Series(np.nan, index=rsi_series.index)
        for i in range(length, len(rsi_series) - length):
            if rsi_series.iloc[i] == rsi_series.iloc[i-length:i+length+1].min():
                result.iloc[i] = rsi_series.iloc[i]
        return result

    def next(self):
        current_rsi = self.rsi[-1]
        current_rsi_ema = self.rsiEma[-1] if len(self.rsiEma) > 0 else 50
        current_rsi_ma = self.rsiMa[-1] if len(self.rsiMa) > 0 else 50
        current_sar = self.sar[-1] if len(self.sar) > 0 else 0
        current_adx = self.adx[-1] if len(self.adx) > 0 else 25
        current_close = self.data.Close[-1]
        
        # Detect pivot highs and lows
        if not np.isnan(self.pivot_high[-1]):
            self.last_ph_rsi = self.pivot_high[-1]
            self.last_ph_bar = len(self.data) - 1
            self.bear_div_detected = False
            if self.last_ph_rsi is not None and len(self.data) > 2:
                prev_ph_idx = self.last_ph_bar - 1
                while prev_ph_idx >= 0 and np.isnan(self.pivot_high[prev_ph_idx]):
                    prev_ph_idx -= 1
                if prev_ph_idx >= 0:
                    prev_ph_rsi = self.pivot_high[prev_ph_idx]
                    if not np.isnan(prev_ph_rsi) and self.last_ph_rsi < prev_ph_rsi:
                        self.bear_div_detected = True

        if not np.isnan(self.pivot_low[-1]):
            self.last_pl_rsi = self.pivot_low[-1]
            self.last_pl_bar = len(self.data) - 1
            self.bull_div_detected = False
            if self.last_pl_rsi is not None and len(self.data) > 2:
                prev_pl_idx = self.last_pl_bar - 1
                while prev_pl_idx >= 0 and np.isnan(self.pivot_low[prev_pl_idx]):
                    prev_pl_idx -= 1
                if prev_pl_idx >= 0:
                    prev_pl_rsi = self.pivot_low[prev_pl_idx]
                    if not np.isnan(prev_pl_rsi) and self.last_pl_rsi > prev_pl_rsi:
                        self.bull_div_detected = True

        # Trading logic based on divergences and RSI conditions
        if self.bull_div_detected and current_rsi < 30 and current_adx > self.adx_threshold:
            if not self.position:
                self.buy()
        elif self.bear_div_detected and current_rsi > 70 and current_adx > self.adx_threshold:
            if self.position:
                self.position.close()
            else:
                self.sell()

        # Additional exit logic on RSI levels
        if self.position:
            if current_rsi > 70:
                self.position.close()
