import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core calculation settings
    calc_p = 35
    atr_factor = 1.2
    start = 1
    end = 45
    
    # Signal settings
    thresL = 40
    thresS = -10
    enableLong = True
    enableShort = True
    
    # Exit management
    exit_mode = "SL/TP Only"  # "Signal Flip Only", "SL/TP Only", "Signal Flip + SL/TP"
    sl_atr_period = 14
    sl_atr_mult = 3.5
    tp_rr = 6.0
    use_trailing = True
    trail_atr_mult = 2.5
    
    # Session filter
    use_session = False
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.calc_p)
        
        # Calculate exit ATR
        self.exit_atr = self.I(pta.atr, high, low, close, length=self.sl_atr_period)
        
        # Core calculation: ATR band
        def calc_band():
            return self.atr * self.atr_factor
        
        self.band = self.I(calc_band)
        
        # Calculate trail (using rolling max/min logic)
        def calc_trail():
            trail = pd.Series(index=close.index, dtype=float)
            trail_val = close.iloc[0]
            
            for i in range(len(close)):
                up = close.iloc[i] + self.band[i]
                dn = close.iloc[i] - self.band[i]
                
                if dn > trail_val:
                    trail_val = dn
                if up < trail_val:
                    trail_val = up
                
                trail.iloc[i] = trail_val
            
            return trail
        
        self.trail = self.I(calc_trail)
        
        # Calculate score
        def calc_score():
            score = pd.Series(index=close.index, dtype=float)
            score[:] = 0.0
            
            for idx in range(len(close)):
                score_val = 0.0
                for i in range(self.start, self.end + 1):
                    if idx >= i:
                        if self.trail[idx] > self.trail[idx - i]:
                            score_val += 1
                        else:
                            score_val -= 1
                score.iloc[idx] = score_val
            
            return score
        
        self.score = self.I(calc_score)
        
        # Position tracking
        self.pos_entry = None
        self.pos_sl = None
        self.pos_tp = None
        self.signal_state = 1  # 1=long signal, -1=short signal
        self.can_trade = False
        
    def next(self):
        # Only trade after warmup period
        if len(self.data) <= self.end:
            self.can_trade = False
            return
        
        self.can_trade = True
        
        # Current values
        score = self.score[-1]
        score_prev = self.score[-2] if len(self.score) > 1 else score
        atr_exit = self.exit_atr[-1]
        close = self.data.Close[-1]
        
        # Determine conditions
        long_cond = score > self.thresL
        short_cond = score < self.thresS and score_prev >= self.thresS
        
        # Update signal state
        prev_signal = self.signal_state
        
        if long_cond and not short_cond:
            self.signal_state = 1
        elif short_cond:
            self.signal_state = -1
        
        # Detect signal flips
        long_signal = (self.signal_state == 1 and prev_signal == -1)
        short_signal = (self.signal_state == -1 and prev_signal == 1)
        
        use_sl_tp = (self.exit_mode == "SL/TP Only" or self.exit_mode == "Signal Flip + SL/TP")
        use_signal_exit = (self.exit_mode == "Signal Flip Only" or self.exit_mode == "Signal Flip + SL/TP")
        
        # --- ENTRIES ---
        if self.can_trade and long_signal:
            # Close short if open
            if self.position.is_short and use_signal_exit:
                self.position.close()
            
            # Enter long
            if self.enableLong and not self.position:
                sl_dist = atr_exit * self.sl_atr_mult
                self.pos_entry = close
                self.pos_sl = close - sl_dist
                self.pos_tp = close + sl_dist * self.tp_rr
                self.buy()
        
        if self.can_trade and short_signal:
            # Close long if open
            if self.position.is_long and use_signal_exit:
                self.position.close()
            
            # Enter short
            if self.enableShort and not self.position:
                sl_dist = atr_exit * self.sl_atr_mult
                self.pos_entry = close
                self.pos_sl = close + sl_dist
                self.pos_tp = close - sl_dist * self.tp_rr
                self.sell()
        
        # --- SIGNAL ONLY EXITS ---
        if self.exit_mode == "Signal Flip Only":
            if short_signal and self.position.is_long:
                self.position.close()
            if long_signal and self.position.is_short:
                self.position.close()
        
        # --- SL/TP EXITS ---
        if use_sl_tp and self.position:
            if self.position.is_long:
                if close <= self.pos_sl:
                    self.position.close()
                elif close >= self.pos_tp:
                    self.position.close()
                
                # Trailing stop
                if self.use_trailing:
                    trail_dist = atr_exit * self.trail_atr_mult
                    new_sl = close - trail_dist
                    if new_sl > self.pos_sl and new_sl > self.pos_entry:
                        self.pos_sl = new_sl
            
            elif self.position.is_short:
                if close >= self.pos_sl:
                    self.position.close()
                elif close <= self.pos_tp:
                    self.position.close()
                
                # Trailing stop
                if self.use_trailing:
                    trail_dist = atr_exit * self.trail_atr_mult
                    new_sl = close + trail_dist
                    if new_sl < self.pos_sl and new_sl < self.pos_entry:
                        self.pos_sl = new_sl


