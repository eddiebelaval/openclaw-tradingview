import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 20
    line_len = 10
    sens = 10.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate highest high and lowest low over lookback period
        self.hi_p = self.I(lambda: high.rolling(self.lookback).max())
        self.lo_p = self.I(lambda: low.rolling(self.lookback).min())
        
        # Initialize signal trackers
        self.sweep_down = self.I(lambda: pd.Series(0, index=close.index))
        self.sweep_up = self.I(lambda: pd.Series(0, index=close.index))

    def next(self):
        if len(self.data) < self.lookback + 1:
            return
        
        idx = len(self.data) - 1
        
        # Get current and previous values
        hi_p_curr = self.hi_p[-1]
        lo_p_curr = self.lo_p[-1]
        
        if idx < 1:
            return
            
        hi_p_prev = self.hi_p[-2] if len(self.hi_p) > 1 else hi_p_curr
        lo_p_prev = self.lo_p[-2] if len(self.lo_p) > 1 else lo_p_curr
        
        curr_high = self.data.High[-1]
        curr_low = self.data.Low[-1]
        curr_close = self.data.Close[-1]
        
        # Baselines for 4% magnet levels
        upper_4 = hi_p_prev * 1.04
        lower_4 = lo_p_prev * 0.96
        
        # Raw sweep detection
        s_down_raw = curr_low < lo_p_prev and curr_close > lo_p_prev
        s_up_raw = curr_high > hi_p_prev and curr_close < hi_p_prev
        
        # Distance calculations for sensitivity
        if upper_4 - hi_p_prev != 0:
            dist_up = (curr_high - hi_p_prev) / (upper_4 - hi_p_prev) * 100
        else:
            dist_up = 0
            
        if lo_p_prev - lower_4 != 0:
            dist_down = (lo_p_prev - curr_low) / (lo_p_prev - lower_4) * 100
        else:
            dist_down = 0
        
        # Apply sensitivity filter
        s_up = s_up_raw and dist_up >= self.sens
        s_down = s_down_raw and dist_down >= self.sens
        
        # Trading logic based on sweep signals
        if s_down:
            # Stop-run long: price swept below previous low then recovered
            if not self.position:
                self.buy()
        elif s_up:
            # Stop-run short: price swept above previous high then dropped
            if self.position:
                self.position.close()
        
        # Simple exit logic if position is open for too long
        if self.position:
            if len(self.data) - self.position.open_bar >= 20:
                self.position.close()


