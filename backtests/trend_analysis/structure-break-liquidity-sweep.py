import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_pivot_length = 5
    sweep_use_wicks = True
    signal_cooldown_bars = 0
    
    def init(self):
        self.pivot_high_prices = None
        self.pivot_low_prices = None
        self.last_detected_swing_high = None
        self.last_detected_swing_low = None
        self.last_detected_swing_high_bar = None
        self.last_detected_swing_low_bar = None
        self.last_signal_bar = None
        self.signal_bias = 0
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.pivot_highs = self.I(self._calculate_pivot_high, high, self.swing_pivot_length)
        self.pivot_lows = self.I(self._calculate_pivot_low, low, self.swing_pivot_length)
    
    def _calculate_pivot_high(self, high_series, length):
        result = []
        for i in range(len(high_series)):
            if i < length or i >= len(high_series) - length:
                result.append(np.nan)
            else:
                is_pivot = high_series.iloc[i] == high_series.iloc[i-length:i+length+1].max()
                result.append(high_series.iloc[i] if is_pivot else np.nan)
        return pd.Series(result)
    
    def _calculate_pivot_low(self, low_series, length):
        result = []
        for i in range(len(low_series)):
            if i < length or i >= len(low_series) - length:
                result.append(np.nan)
            else:
                is_pivot = low_series.iloc[i] == low_series.iloc[i-length:i+length+1].min()
                result.append(low_series.iloc[i] if is_pivot else np.nan)
        return pd.Series(result)
    
    def _detect_swing_points(self):
        if not np.isnan(self.pivot_highs[-1]):
            self.last_detected_swing_high = self.pivot_highs[-1]
            self.last_detected_swing_high_bar = len(self.data) - self.swing_pivot_length - 1
        
        if not np.isnan(self.pivot_lows[-1]):
            self.last_detected_swing_low = self.pivot_lows[-1]
            self.last_detected_swing_low_bar = len(self.data) - self.swing_pivot_length - 1
    
    def _check_bear_sweep(self):
        if self.last_detected_swing_high is None:
            return False
        
        if self.sweep_use_wicks:
            return self.data.High[-1] > self.last_detected_swing_high and self.data.Close[-1] < self.last_detected_swing_high
        else:
            return self.data.Close[-1] > self.last_detected_swing_high and self.data.Open[-1] < self.last_detected_swing_high
    
    def _check_bull_sweep(self):
        if self.last_detected_swing_low is None:
            return False
        
        if self.sweep_use_wicks:
            return self.data.Low[-1] < self.last_detected_swing_low and self.data.Close[-1] > self.last_detected_swing_low
        else:
            return self.data.Close[-1] < self.last_detected_swing_low and self.data.Open[-1] > self.last_detected_swing_low
    
    def _check_cooldown(self):
        if self.last_signal_bar is None:
            return True
        return len(self.data) - self.last_signal_bar > self.signal_cooldown_bars
    
    def next(self):
        self._detect_swing_points()
        
        bear_sweep = self._check_bear_sweep()
        bull_sweep = self._check_bull_sweep()
        
        cooldown_ok = self._check_cooldown()
        
        long_signal = bull_sweep and cooldown_ok
