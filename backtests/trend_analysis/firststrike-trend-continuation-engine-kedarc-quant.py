import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI / Trigger parameters
    rsiLen = 14
    rsiTrigger = 50
    triggerMode = "Any bar >= trigger"
    graceBars = 30
    sustainBars = 3
    requireDip = False
    rsiRearm = 45
    
    # Trend / Filters parameters
    emaFastLen = 20
    emaTrend = 200
    
    # Optional Hour Window
    useSession = False
    useTime = False
    startHour = 9
    endHour = 15
    
    # Volume Filter
    useVol = False
    volLen = 20
    
    # Risk / Exits parameters
    atrLen = 14
    atrMult = 1.5
    riskRR = 2.0
    useTrail = False
    trailMult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate indicators
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.ema200 = self.I(pta.ema, close, length=self.emaTrend)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.volSMA = self.I(pta.sma, volume, length=self.volLen)
        
        # Track state
        self.lastCrossBarIndex = None
        self.tookTradeToday = False
        self.rearmed = not self.requireDip
        self.lastDay = None
        self.hiSinceEntry = None
        self.entryPrice = None

    def next(self):
        # Get current values
        currentClose = self.data.Close[-1]
        currentHigh = self.data.High[-1]
        currentLow = self.data.Low[-1]
        currentVolume = self.data.Volume[-1]
        currentRSI = self.rsi[-1]
        currentATR = self.atr[-1]
        currentEMAFast = self.emaFast[-1]
        currentEMA200 = self.ema200[-1]
        currentVolSMA = self.volSMA[-1]
        
        # Check if new day
        if self.lastDay is None or self.lastDay != self.data.index[-1].day:
            self.tookTradeToday = False
            self.rearmed = not self.requireDip
            self.lastCrossBarIndex = None
            self.lastDay = self.data.index[-1].day
        
        # Rearm logic
        if self.requireDip and currentRSI < self.rsiRearm:
            self.rearmed = True
        
        # Time filters
        if self.useTime:
            currentHour = self.data.index[-1].hour
            inHours = (self.startHour <= self.endHour and 
                      currentHour >= self.startHour and currentHour <= self.endHour) or \
                     (self.startHour > self.endHour and 
                      (currentHour >= self.startHour or currentHour <= self.endHour))
        else:
            inHours = True
        
        # Trend and price filters
        trendOK = currentClose > currentEMA200
        priceOK = currentClose > currentEMAFast
        volOK = (not self.useVol) or (currentVolume > currentVolSMA)
        
        # Trigger logic
        crossNow = crossover(self.rsi, self.rsiTrigger)
        
        if crossNow:
            self.lastCrossBarIndex = len(self.data) - 1
        
        withinGrace = (self.graceBars > 0 and 
                      self.lastCrossBarIndex is not None and 
                      (len(self.data) - 1 - self.lastCrossBarIndex) <= self.graceBars and 
                      currentRSI >= self.rsiTrigger)
        
        # Sustain check - lowest RSI over sustainBars must be >= rsiTrigger
        if len(self.data) >= self.sustainBars:
            sustainOK = self.rsi[-self.sustainBars:].min() >= self.rsiTrigger
        else:
            sustainOK = currentRSI >= self.rsiTrigger
        
        anyBarOK = currentRSI >= self.rsiTrigger
        
        # Determine trigger based on mode
        if self.triggerMode == "Cross only":
            triggerOK = crossNow
        elif self.triggerMode == "Cross+Grace":
            triggerOK = crossNow or withinGrace
        elif self.triggerMode == "Cross+Grace+Sustain":
            triggerOK = (crossNow or withinGrace) and sustainOK
        else:  # "Any bar >= trigger"
            triggerOK = anyBarOK
        
        # Entry condition
        longCond = (inHours and trendOK and priceOK and self.rearmed and 
                   triggerOK and volOK and not self.tookTradeToday and 
                   not self.position)
        
        # Entry
        if longCond:
            self.buy()
            self.tookTradeToday = True
            self.rearmed = False
            self.hiSinceEntry = currentHigh
            self.entryPrice = currentClose
        
        # Exit logic
        if self.position:
            # Update highest since entry
            if self.hiSinceEntry is None:
                self.hiSinceEntry = currentHigh
            else:
                self.hiSinceEntry = max(self.hiSinceEntry, currentHigh)
            
            avg = self.position.open_price
            initialStop = avg - self.atrMult * currentATR
            riskPS = avg - initialStop
            limitPx = avg + self.riskRR * riskPS
            
            if self.useTrail:
                trailStop = self.hiSinceEntry - self.trailMult * currentATR
                finalStop = max(initialStop, trailStop)
            else:
                finalStop = initialStop
            
            # Exit with stop and limit
            if currentLow <= finalStop:
                self.position.close()
            elif currentHigh >= limitPx:
                self.position.close()
        else:
            self.hiSinceEntry = None
            self.entryPrice = None


