import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # CISD Settings
    cisd_lookback = 15
    sl_buffer_atr_mult = 0.1
    rr_ratio = 2.0
    be_trigger_rr = 1.0
    use_partial1 = True
    partial1_rr = 1.0
    partial1_pct = 50.0
    use_partial2 = False
    partial2_rr = 1.5
    partial2_pct = 25.0
    
    # Session filter
    use_session = False
    
    # Risk management
    risk_percent = 1.0
    account_size = 100000.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for stop loss buffer
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # State tracking
        self.can_look_for_bull_cisd = False
        self.can_look_for_bear_cisd = False
        self.post_touch_low = None
        self.post_touch_high = None
        self.bull_cisd_level = None
        self.bear_cisd_level = None
        self.bull_cisd_pending = False
        self.bear_cisd_pending = False
        self.last_touched_poi_bull = ""
        self.last_touched_poi_bear = ""
        
        # Trade tracking
        self.trade_entry = None
        self.trade_sl = None
        self.trade_tp = None
        self.trade_be = None
        self.trade_tp1 = None
        self.trade_tp2 = None
        self.trade_is_long = False
        self.trade_active = False
        self.be_triggered = False
        self.tp1_triggered = False
        self.tp2_triggered = False

    def next(self):
        # Simple FVG/OB detection placeholder - in real usage, would track multi-timeframe zones
        # For this backtest, we'll use a simplified CISD logic based on recent price action
        
        close_curr = self.data.Close[-1]
        high_curr = self.data.High[-1]
        low_curr = self.data.Low[-1]
        
        # Check if we have enough bars
        if len(self.data) < self.cisd_lookback + 5:
            return
        
        atr_val = self.atr[-1]
        if np.isnan(atr_val):
            return
        
        # Simple bullish setup: price touches recent low, then we look for CISD
        lookback_low = np.nanmin(self.data.Low[-self.cisd_lookback:])
        lookback_high = np.nanmax(self.data.High[-self.cisd_lookback:])
        
        # Bullish CISD detection
        if not self.can_look_for_bull_cisd and low_curr <= lookback_low * 1.001:
            self.can_look_for_bull_cisd = True
            self.post_touch_low = low_curr
            self.last_touched_poi_bull = "FVG/OB"
        
        if self.can_look_for_bull_cisd:
            if low_curr < self.post_touch_low:
                self.post_touch_low = low_curr
                self.bull_cisd_pending = False
                self.bull_cisd_level = None
            
            # Look for CISD pattern: bearish candle followed by bullish
            if len(self.data) >= 2:
                is_down_prev = self.data.Close[-2] < self.data.Open[-2]
                is_up_curr = self.data.Close[-1] > self.data.Open[-1]
                
                if is_down_prev and is_up_curr:
                    self.bull_cisd_level = self.data.Open[-2]
                    self.bull_cisd_pending = True
            
            # Confirm bullish CISD
            if self.bull_cisd_pending and self.bull_cisd_level and close_curr > self.bull_cisd_level and not self.position:
                sl_buffer = atr_val * self.sl_buffer_atr_mult
                entry = close_curr
                sl = self.post_touch_low - sl_buffer
                sl_dist = entry - sl
                
                self.trade_entry = entry
                self.trade_sl = sl
                self.trade_tp = entry + (sl_dist * self.rr_ratio)
                self.trade_be = entry + (sl_dist * self.be_trigger_rr)
                self.trade_tp1 = entry + (sl_dist * self.partial1_rr) if self.use_partial1 else None
                self.trade_tp2 = entry + (sl_dist * self.partial2_rr) if self.use_partial2 else None
                self.trade_is_long = True
                self.trade_active = True
                self.be_triggered = False
                self.tp1_triggered = False
                
