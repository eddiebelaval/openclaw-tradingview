import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_dema = 200
    len_jaw = 13
    off_jaw = 8
    len_teeth = 8
    off_teeth = 5
    len_lips = 5
    off_lips = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        ohlc4 = (self.data.Open + high + low + close) / 4
        ohlc4 = pd.Series(ohlc4)

        # Double EMA (Macro Filter)
        dema_e1 = self.I(pta.ema, close, length=self.len_dema)
        self.dema = self.I(pta.ema, dema_e1, length=self.len_dema)

        # Williams Alligator
        jaw_raw = self.I(pta.sma, ohlc4, length=self.len_jaw)
        teeth_raw = self.I(pta.sma, ohlc4, length=self.len_teeth)
        lips_raw = self.I(pta.sma, ohlc4, length=self.len_lips)

        self.jaw_raw = jaw_raw
        self.teeth_raw = teeth_raw
        self.lips_raw = lips_raw

        self.state = 0

    def next(self):
        if len(self.data) < max(self.len_dema * 2, self.off_jaw + 1):
            return

        close_current = self.data.Close[-1]
        dema_current = self.dema[-1]

        # Get offset values
        v_jaw = self.jaw_raw[-1 - self.off_jaw] if len(self.jaw_raw) > self.off_jaw else self.jaw_raw[-1]
        v_teeth = self.teeth_raw[-1 - self.off_teeth] if len(self.teeth_raw) > self.off_teeth else self.teeth_raw[-1]
        v_lips = self.lips_raw[-1 - self.off_lips] if len(self.lips_raw) > self.off_lips else self.lips_raw[-1]

        if v_jaw is None or v_teeth is None or v_lips is None or dema_current is None:
            return

        # Trend Regimes
        is_bull_macro = close_current > dema_current
        is_bear_macro = close_current < dema_current

        # Gator Phases
        gator_eat_bull = v_lips > v_teeth and v_teeth > v_jaw
        gator_eat_bear = v_lips < v_teeth and v_teeth < v_jaw

        # Entry Signals
        trig_buy = is_bull_macro and gator_eat_bull and crossover(self.lips_raw, v_lips)
        trig_sell = is_bear_macro and gator_eat_bear and crossover(v_lips, self.lips_raw)

        # Exit Signals
        exit_long = crossover(v_teeth, self.teeth_raw)
        exit_short = crossover(self.teeth_raw, v_teeth)

        # State Machine
        if trig_buy and self.state == 0:
            self.state = 1
            if not self.position:
                self.buy()
        elif self.state == 1 and exit_long:
            self.state = 0
            if self.position:
                self.position.close()

        if trig_sell and self.state == 0:
            self.state = -1
            if not self.position:
                self.sell()
        elif self.state == -1 and exit_short:
            self.state = 0
            if self.position:
                self.position.close()


