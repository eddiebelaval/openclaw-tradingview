import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_length = 20
    max_active_sweep_bull = 5
    max_active_sweep_bear = 5

    def init(self):
        self.bull_zones = []
        self.bear_zones = []
        self.pivot_highs = self.I(self._calculate_pivot_highs)
        self.pivot_lows = self.I(self._calculate_pivot_lows)

    def _calculate_pivot_highs(self):
        highs = pd.Series(self.data.High)
        pivot_highs = pd.Series(index=highs.index, dtype=float)
        for i in range(self.swing_length, len(highs) - self.swing_length):
            if highs.iloc[i] == highs.iloc[i - self.swing_length:i + self.swing_length + 1].max():
                pivot_highs.iloc[i] = highs.iloc[i]
            else:
                pivot_highs.iloc[i] = np.nan
        return pivot_highs

    def _calculate_pivot_lows(self):
        lows = pd.Series(self.data.Low)
        pivot_lows = pd.Series(index=lows.index, dtype=float)
        for i in range(self.swing_length, len(lows) - self.swing_length):
            if lows.iloc[i] == lows.iloc[i - self.swing_length:i + self.swing_length + 1].min():
                pivot_lows.iloc[i] = lows.iloc[i]
            else:
                pivot_lows.iloc[i] = np.nan
        return pivot_lows

    def next(self):
        current_idx = len(self.data) - 1
        close = self.data.Close[-1]
        low = self.data.Low[-1]
        high = self.data.High[-1]
        
        # Create bullish zones from pivot lows
        if not np.isnan(self.pivot_lows[-1]):
            pivot_idx = current_idx - self.swing_length
            if pivot_idx >= 0:
                pivot_low = self.data.Low[pivot_idx]
                pivot_open = self.data.Open[pivot_idx]
                pivot_close = self.data.Close[pivot_idx]
                bull_body = min(pivot_open, pivot_close)
                self.bull_zones.append({
                    'bottom': pivot_low,
                    'top': bull_body,
                    'created_at': pivot_idx
                })
                if len(self.bull_zones) > self.max_active_sweep_bull:
                    self.bull_zones.pop(0)

        # Create bearish zones from pivot highs
        if not np.isnan(self.pivot_highs[-1]):
            pivot_idx = current_idx - self.swing_length
            if pivot_idx >= 0:
                pivot_high = self.data.High[pivot_idx]
                pivot_open = self.data.Open[pivot_idx]
                pivot_close = self.data.Close[pivot_idx]
                bear_body = max(pivot_open, pivot_close)
                self.bear_zones.append({
                    'top': pivot_high,
                    'bottom': bear_body,
                    'created_at': pivot_idx
                })
                if len(self.bear_zones) > self.max_active_sweep_bear:
                    self.bear_zones.pop(0)

        # Check bullish zone interactions
        in_side_bull_zone = False
        bull_bounce = False
        zones_to_remove = []
        
        for i, zone in enumerate(self.bull_zones):
            if close > zone['bottom'] and close < zone['top']:
                in_side_bull_zone = True
            
            if close > zone['bottom'] and low < zone['bottom']:
                bull_bounce = True
            
            if close < zone['bottom']:
                zones_to_remove.append(i)
        
        for i in sorted(zones_to_remove, reverse=True):
            self.bull_zones.pop(i)

        # Check bearish zone interactions
        in_side_bear_zone = False
        bear_bounce = False
        zones_to_remove = []
        
        for i, zone in enumerate(self.bear_zones):
            if close > zone['bottom'] and close < zone['top']:
                in_side_bear_zone = True
            
            if close < zone['top'] and high > zone['top']:
                bear_bounce = True
            
            if close > zone['top']:
                zones_to_remove.append(i)
        
        for i in sorted(zones_to_remove, reverse=True):
            self.bear_zones.pop(i)

        # Trading logic based on sweep signals
        if bull_bounce and not self.position:
            self.buy()
        elif bear_bounce and self.position:
            self.sell()