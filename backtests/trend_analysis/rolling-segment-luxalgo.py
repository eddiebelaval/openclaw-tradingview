import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLengthInput = 5
    slowLengthInput = 10
    atrLengthInput = 200
    fastThresholdInput = 1.0
    reverseThresholdInput = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLengthInput)
        
        self.rollSeg = np.full(len(self.data), np.nan)
        self.trend = np.full(len(self.data), 0, dtype=int)
        self.activeSlope = np.full(len(self.data), 0.0)
        self.isFastMode = np.full(len(self.data), False, dtype=bool)
        self.bullReversal = np.full(len(self.data), False, dtype=bool)
        self.bearReversal = np.full(len(self.data), False, dtype=bool)
        
        self.rollSeg[0] = close.iloc[0]
        self.trend[0] = 1
        self.activeSlope[0] = 0.0
        self.isFastMode[0] = False

    def next(self):
        idx = len(self.data) - 1
        close_val = self.data.Close[-1]
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else None
        
        if atr_val is None or np.isnan(atr_val):
            self.rollSeg[idx] = close_val
            self.trend[idx] = self.trend[idx - 1] if idx > 0 else 1
            self.activeSlope[idx] = self.activeSlope[idx - 1] if idx > 0 else 0.0
            self.isFastMode[idx] = self.isFastMode[idx - 1] if idx > 0 else False
            return
        
        prev_rollSeg = self.rollSeg[idx - 1] if idx > 0 else close_val
        prev_trend = self.trend[idx - 1] if idx > 0 else 1
        prev_activeSlope = self.activeSlope[idx - 1] if idx > 0 else 0.0
        prev_isFastMode = self.isFastMode[idx - 1] if idx > 0 else False
        
        distFromSeg = close_val - prev_rollSeg
        
        bullReversal = prev_trend == -1 and distFromSeg > self.reverseThresholdInput * atr_val
        bearReversal = prev_trend == 1 and -distFromSeg > self.reverseThresholdInput * atr_val
        
        new_trend = prev_trend
        if bullReversal:
            new_trend = 1
        elif bearReversal:
            new_trend = -1
        
        newIsFastMode = abs(distFromSeg) > self.fastThresholdInput * atr_val
        speedChanged = newIsFastMode != prev_isFastMode
        
        new_activeSlope = prev_activeSlope
        new_isFastMode = prev_isFastMode
        
        if bullReversal or bearReversal or speedChanged or prev_activeSlope == 0.0:
            new_isFastMode = newIsFastMode
            new_activeSlope = atr_val / self.fastLengthInput if newIsFastMode else atr_val / self.slowLengthInput
        
        new_rollSeg = prev_rollSeg + (new_trend * new_activeSlope)
        
        self.rollSeg[idx] = new_rollSeg
        self.trend[idx] = new_trend
        self.activeSlope[idx] = new_activeSlope
        self.isFastMode[idx] = new_isFastMode
        self.bullReversal[idx] = bullReversal
        self.bearReversal[idx] = bearReversal
        
        if bullReversal and not self.position:
            self.buy()
        elif bearReversal and self.position:
            self.sell()


