import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ADX calculation
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = adx_result
        
        # RSI calculation
        self.rsi = self.I(lambda: pta.rsi(close, length=14))
        
        # ATR calculation
        self.atr = self.I(lambda: pta.atr(high, low, close, length=14))
        
        # Track previous state for entry/exit
        self.regime_ok_prev = False

    def next(self):
        # Check if we have enough data
        if len(self.data) < 14:
            return
        
        # Get current values
        adx = self.adx[-1] if self.adx[-1] is not None else 0
        rsi = self.rsi[-1] if self.rsi[-1] is not None else 50
        atr = self.atr[-1] if self.atr[-1] is not None else 0
        close = self.data.Close[-1]
        
        # Calculate volatility percentage
        volatility_pct = (atr / close) * 100 if close > 0 else 0
        
        # Get day of week (0=Monday, 1=Tuesday, ..., 6=Sunday)
        from datetime import datetime
        bar_time = pd.Timestamp(self.data.index[-1])
        day_of_week = bar_time.dayofweek
        
        # Trading conditions
        zaman_ok = day_of_week != 0  # Not Monday
        trend_ok = adx > 25
        rsi_ok = rsi > 50
        volatilite_ok = volatility_pct < 3
        
        # Combined condition
        regime_ok = zaman_ok and trend_ok and rsi_ok and volatilite_ok
        
        # Entry logic: when conditions become favorable
        if regime_ok and not self.regime_ok_prev:
            if not self.position:
                self.buy()
        
        # Exit logic: when conditions become unfavorable
        if not regime_ok and self.regime_ok_prev:
            if self.position:
                self.position.close()
        
        self.regime_ok_prev = regime_ok


