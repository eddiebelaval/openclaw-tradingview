class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate VWAP using pandas_ta
        vwap_result = self.I(lambda: pta.vwap(high, low, close, volume))
        self.vwap = vwap_result
        
    def next(self):
        if len(self.data) < 2:
            return
            
        if self.vwap[-1] is np.nan or pd.isna(self.vwap[-1]):
            return
            
        current_price = self.data.Close[-1]
        current_vwap = self.vwap[-1]
        prev_price = self.data.Close[-2]
        prev_vwap = self.vwap[-2] if not pd.isna(self.vwap[-2]) else current_vwap
        
        # Buy when price crosses above VWAP
        if prev_price <= prev_vwap and current_price > current_vwap:
            if not self.position:
                self.buy()
        
        # Sell when price crosses below VWAP
        elif prev_price >= prev_vwap and current_price < current_vwap:
            if self.position:
                self.sell()


