import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    smooth = 5
    squeezeMult = 0.8
    bandMult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate True Range
        def calc_tr():
            tr = pta.true_range(high, low, close)
            if tr is None:
                return pd.Series(0, index=close.index)
            return tr
        
        tr = self.I(calc_tr)
        
        # Smoothed True Range using EMA as RMA equivalent
        def calc_tr_smooth(tr_series):
            if tr_series is None or len(tr_series) < self.length:
                return pd.Series(0, index=close.index)
            return pta.ema(tr_series, length=self.length) or pd.Series(0, index=close.index)
        
        self.tr_smooth = self.I(calc_tr_smooth, tr)
        
        # Calculate directional moves
        def calc_up_move():
            changes = close.diff()
            return changes.clip(lower=0)
        
        def calc_dn_move():
            changes = close.diff()
            return (-changes).clip(lower=0)
        
        up_move = self.I(calc_up_move)
        dn_move = self.I(calc_dn_move)
        
        # Calculate directional volatility
        def calc_up_vol(up_move_series):
            if up_move_series is None or len(up_move_series) < self.length:
                return pd.Series(0, index=close.index)
            return pta.ema(up_move_series, length=self.length) or pd.Series(0, index=close.index)
        
        def calc_dn_vol(dn_move_series):
            if dn_move_series is None or len(dn_move_series) < self.length:
                return pd.Series(0, index=close.index)
            return pta.ema(dn_move_series, length=self.length) or pd.Series(0, index=close.index)
        
        up_vol = self.I(calc_up_vol, up_move)
        dn_vol = self.I(calc_dn_vol, dn_move)
        
        # Calculate bull and bear power
        def calc_bull_power(up_vol_series, tr_smooth_series):
            result = pd.Series(0, index=close.index)
            for i in range(len(result)):
                if tr_smooth_series[i] != 0:
                    result[i] = (up_vol_series[i] / tr_smooth_series[i]) * 100
            return result
        
        def calc_bear_power(dn_vol_series, tr_smooth_series):
            result = pd.Series(0, index=close.index)
            for i in range(len(result)):
                if tr_smooth_series[i] != 0:
                    result[i] = (dn_vol_series[i] / tr_smooth_series[i]) * 100
            return result
        
        self.bull_power = self.I(calc_bull_power, up_vol, self.tr_smooth)
        self.bear_power = self.I(calc_bear_power, dn_vol, self.tr_smooth)
        
        # Calculate Vortex Delta
        def calc_vortex_delta(bull_power_series, bear_power_series):
            delta = bull_power_series - bear_power_series
            smoothed = pta.sma(delta, length=self.smooth)
            if smoothed is None:
                return pd.Series(0, index=close.index)
            return smoothed
        
        self.vortex_delta = self.I(calc_vortex_delta, self.bull_power, self.bear_power)
        
        # Calculate squeeze detection
        def calc_squeeze(tr_series):
            long_tr = pta.sma(tr_series, length=self.length * 3)
            short_tr = pta.sma(tr_series, length=self.length)
            if long_tr is None or short_tr is None:
                return pd.Series(False, index=close.index)
            threshold = long_tr * self.squeezeMult
            return short_tr < threshold
        
        self.is_squeeze = self.I(calc_squeeze, tr)
        
        # Calculate volatility bands
        def calc_stdev(vortex_delta_series):
            result = vortex_delta_series.rolling(window=self.length * 2).std()
            return result
        
        self.vortex_stdev = self.I(calc_stdev, self.vortex_delta)
        
        def calc_basis(vortex_delta_series):
            basis = pta.sma(vortex_delta_series, length=self.length * 2)
            if basis is None:
                return pd.Series(0, index=close.index)
            return basis
        
        self.vortex_basis = self.I(calc_basis, self.vortex_delta)
        
        def calc_upper_band(basis_series, stdev_series):
            return basis_series + (stdev_series * self.bandMult)
        
        def calc_lower_band(basis_series, stdev_series):
            return basis_series - (stdev_series * self.bandMult)
        
        self.upper_band = self.I(calc_upper_band, self.vortex_basis, self.vortex_stdev)
        self.lower_band = self.I(calc_lower_band, self.vortex_basis, self.vortex_stdev)

    def next(self):
        # Check for bullish breakout: delta crosses above upper band and not in squeeze
        if len(self.vortex_delta) > 1:
            bull_break = (
                crossover(self.vortex_delta, self.upper_band) and
                not self.is_squeeze[-1]
            )
            
            # Check for bearish breakout: delta crosses below lower band and not in squeeze
            bear_break = (
                crossover(self.lower_band, self.vortex_delta) and
                not self.is_squeeze[-1]
            )
            
            # Trading logic
            if bull_break and not self.position:
                self.buy()
            elif bear_break and self.position:
                self.sell()


