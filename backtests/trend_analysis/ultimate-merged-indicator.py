    def _calc_angle(self, ma_val, lookback):
        if len(ma_val) < lookback + 1:
            return pd.Series([np.nan] * len(ma_val))
        slope = (ma_val - ma_val.shift(lookback)) / lookback
        atr_val = self.ma_atr[-1] if len(self.ma_atr) > 0 else 0.000001
        atr_val = max(atr_val, 0.000001)
        normalized_slope = slope / atr_val
        angle = np.arctan(normalized_slope) * 180 / np.pi
        return angle

    def _smooth_range(self, src, period, multiplier):
        wper = period * 2 - 1
        avrng = pta.ema(np.abs(src.diff()), length=period)
        smoothrng = pta.ema(avrng, length=wper) * multiplier
        return smoothrng

    def _range_filter(self, src, smoothrng):
        rngfilt = pd.Series([np.nan] * len(src), index=src.index)
        for i in range(len(src)):
            if i == 0:
                rngfilt.iloc[i] = src.iloc[i]
            else:
                prev_rngfilt = rngfilt.iloc[i-1]
                if src.iloc[i] > prev_rngfilt:
                    rngfilt.iloc[i] = max(src.iloc[i] - smoothrng.iloc[i], prev_rngfilt)
                else:
                    rngfilt.iloc[i] = min(src.iloc[i] + smoothrng.iloc[i], prev_rngfilt)
        return rngfilt

