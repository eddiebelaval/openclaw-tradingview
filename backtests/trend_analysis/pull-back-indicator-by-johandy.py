import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    tp_points = 60
    sl_points = 40
    cooldown = 10
    impulse_points = 100

    def init(self):
        # Pre-calculate high and low with 10-bar offset
        self.high_current = self.data.High
        self.low_current = self.data.Low
        self.close_current = self.data.Close
        
        # Store impulse tracking
        self.impulse_high = None
        self.impulse_low = None
        self.impulse_active = False
        self.last_trade_bar = None
        self.entry_price = None
        self.tp_price = None
        self.sl_price = None
        self.is_long = None

    def next(self):
        # Current bar index
        bar_idx = len(self.data) - 1
        
        # Get current values
        high = self.data.High[-1]
        low = self.data.Low[-1]
        close = self.data.Close[-1]
        
        # Get 10 bars ago values (if available)
        high_10 = self.data.High[-11] if len(self.data) > 10 else None
        low_10 = self.data.Low[-11] if len(self.data) > 10 else None
        
        # --- IMPULSE DETECTION ---
        if high_10 is not None and low_10 is not None:
            move_up = (high - low_10) >= self.impulse_points
            move_down = (high_10 - low) >= self.impulse_points
            
            if move_up:
                self.impulse_high = high
                self.impulse_low = low_10
                self.impulse_active = True
            
            if move_down:
                self.impulse_high = high_10
                self.impulse_low = low
                self.impulse_active = True
        
        # --- SWEEP CONDITIONS ---
        sell_sweep = False
        buy_sweep = False
        
        if self.impulse_active and self.impulse_high is not None and self.impulse_low is not None:
            sell_sweep = high > self.impulse_high and close < self.impulse_high
            buy_sweep = low < self.impulse_low and close > self.impulse_low
        
        # --- COOLDOWN CHECK ---
        can_trade = True
        if self.last_trade_bar is not None:
            if bar_idx - self.last_trade_bar <= self.cooldown:
                can_trade = False
        
        # --- ENTRY CONDITIONS ---
        can_sell = not self.position and sell_sweep and can_trade
        can_buy = not self.position and buy_sweep and can_trade
        
        # --- SELL ENTRY ---
        if can_sell:
            self.last_trade_bar = bar_idx
            self.entry_price = close
            self.tp_price = self.entry_price - self.tp_points
            self.sl_price = self.entry_price + self.sl_points
            self.is_long = False
            self.sell()
        
        # --- BUY ENTRY ---
        if can_buy:
            self.last_trade_bar = bar_idx
            self.entry_price = close
            self.tp_price = self.entry_price + self.tp_points
            self.sl_price = self.entry_price - self.sl_points
            self.is_long = True
            self.buy()
        
        # --- EXIT CONDITIONS ---
        if self.position:
            hit_tp = False
            hit_sl = False
            
            if self.is_long:
                hit_tp = close >= self.tp_price
                hit_sl = close <= self.sl_price
            else:
                hit_tp = close <= self.tp_price
                hit_sl = close >= self.sl_price
            
            if hit_tp or hit_sl:
                self.position.close()


