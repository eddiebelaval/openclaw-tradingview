import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    BBperiod = 21
    BBdeviations = 1.00
    UseATRfilter = True
    ATRperiod = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Bollinger Bands
        sma = self.I(pta.sma, close, length=self.BBperiod)
        stdev = self.I(lambda x: x.rolling(self.BBperiod).std(), close)
        self.bb_upper = self.I(lambda: sma + stdev * self.BBdeviations)
        self.bb_lower = self.I(lambda: sma - stdev * self.BBdeviations)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.ATRperiod)
        
        # Initialize trend arrays
        self.trend_line = np.zeros(len(self.data))
        self.i_trend = np.zeros(len(self.data))
        self.buy_signal = np.zeros(len(self.data))
        self.sell_signal = np.zeros(len(self.data))

    def next(self):
        idx = len(self.data) - 1
        
        if idx == 0:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Determine BB Signal
        if close > self.bb_upper[-1]:
            bb_signal = 1
        elif close < self.bb_lower[-1]:
            bb_signal = -1
        else:
            bb_signal = 0
        
        # Calculate TrendLine based on BBSignal and ATR filter
        if self.UseATRfilter:
            if bb_signal == 1:
                trend_line = low - self.atr[-1]
                if trend_line < self.trend_line[idx - 1]:
                    trend_line = self.trend_line[idx - 1]
            elif bb_signal == -1:
                trend_line = high + self.atr[-1]
                if trend_line > self.trend_line[idx - 1]:
                    trend_line = self.trend_line[idx - 1]
            else:
                trend_line = self.trend_line[idx - 1]
        else:
            if bb_signal == 1:
                trend_line = low
                if trend_line < self.trend_line[idx - 1]:
                    trend_line = self.trend_line[idx - 1]
            elif bb_signal == -1:
                trend_line = high
                if trend_line > self.trend_line[idx - 1]:
                    trend_line = self.trend_line[idx - 1]
            else:
                trend_line = self.trend_line[idx - 1]
        
        self.trend_line[idx] = trend_line
        
        # Calculate iTrend based on TrendLine
        i_trend = self.i_trend[idx - 1]
        if trend_line > self.trend_line[idx - 1]:
            i_trend = 1
        elif trend_line < self.trend_line[idx - 1]:
            i_trend = -1
        
        self.i_trend[idx] = i_trend
        
        # Generate buy/sell signals
        buy = 1 if self.i_trend[idx - 1] == -1 and i_trend == 1 else 0
        sell = 1 if self.i_trend[idx - 1] == 1 and i_trend == -1 else 0
        
        self.buy_signal[idx] = buy
        self.sell_signal[idx] = sell
        
        # Execute trades
        if buy == 1:
            if not self.position:
                self.buy()
        elif sell == 1:
            if self.position:
                self.position.close()