import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 200
    zone_width = 0.8

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate highest high and lowest low over lookback period
        self.hh = self.I(lambda: high.rolling(window=self.lookback).max())
        self.ll = self.I(lambda: low.rolling(window=self.lookback).min())
        
        # Calculate support and resistance levels
        self.rng = self.I(lambda: self.hh - self.ll)
        self.sell_lvl = self.I(lambda: self.ll + self.rng * 0.6667)
        self.pivot_lvl = self.I(lambda: self.ll + self.rng * 0.5000)
        self.buy_lvl = self.I(lambda: self.ll + self.rng * 0.3333)

    def next(self):
        # Avoid trading during warm-up period
        if len(self.data) < self.lookback + 10:
            return
        
        current_price = self.data.Close[-1]
        
        # Check if we have valid indicator values
        if pd.isna(self.sell_lvl[-1]) or pd.isna(self.buy_lvl[-1]):
            return
        
        sell_level = self.sell_lvl[-1]
        pivot_level = self.pivot_lvl[-1]
        buy_level = self.buy_lvl[-1]
        
        # BUY SIGNAL: Price touches or crosses above buy level (support)
        if not self.position:
            if current_price >= buy_level and self.data.Close[-2] < buy_level:
                self.buy()
            elif current_price > buy_level and current_price < pivot_level:
                if len(self.data) > 1 and self.data.Close[-2] <= buy_level:
                    self.buy()
        
        # SELL SIGNAL: Price touches or crosses below sell level (resistance)
        if self.position:
            if current_price <= sell_level and self.data.Close[-2] > sell_level:
                self.sell()
            elif current_price > pivot_level and current_price < sell_level:
                if len(self.data) > 1 and self.data.Close[-2] >= sell_level:
                    self.sell()
            # Also exit if price breaks above sell level
            elif current_price > sell_level:
                self.sell()


