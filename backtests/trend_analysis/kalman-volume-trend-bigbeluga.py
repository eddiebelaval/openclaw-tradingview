import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    process_noise = 0.0005
    measurement_noise = 0.4
    multiplier = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Kalman Filter implementation
        def kalman_filter_series(src, q, r):
            result = pd.Series(index=src.index, dtype=float)
            x = src.iloc[0]
            p = 1.0
            
            for i in range(len(src)):
                p = p + q
                k = p / (p + r)
                x = x + k * (src.iloc[i] - x)
                p = (1 - k) * p
                result.iloc[i] = x
            
            return result

        self.kf = self.I(lambda: kalman_filter_series(close, self.process_noise, self.measurement_noise))

        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=200)
        
        # Volume-based delta calculation
        def delta_calc(c, o, v):
            delta_sign = pd.Series(np.where(c > o, v, -v), index=c.index)
            hi = delta_sign.abs().rolling(100).max()
            hi = hi.fillna(1)
            delta = (delta_sign / hi * 2).fillna(0)
            return delta
        
        self.delta = self.I(lambda: delta_calc(close, open_, volume))

        # Trend bands
        def upkf_calc(kf, atr, mult):
            return kf + atr * mult
        
        def lokf_calc(kf, atr, mult):
            return kf - atr * mult
        
        self.up_kf = self.I(lambda: upkf_calc(self.kf, self.atr, self.multiplier))
        self.lo_kf = self.I(lambda: lokf_calc(self.kf, self.atr, self.multiplier))

        self.direction = True
        self.last_direction = True

    def next(self):
        if len(self.data) < 2:
            return

        close_curr = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        
        up_kf_curr = self.up_kf[-1]
        up_kf_prev = self.up_kf[-2]
        lo_kf_curr = self.lo_kf[-1]
        lo_kf_prev = self.lo_kf[-2]

        # Update direction based on trend bands
        if close_curr > up_kf_curr and close_prev < up_kf_prev:
            self.direction = True
        elif close_curr < lo_kf_curr and close_prev > lo_kf_prev:
            self.direction = False

        # Generate trading signals
        if self.direction and not self.last_direction:
            # Trend changed to uptrend
            if not self.position:
                self.buy()
        elif not self.direction and self.last_direction:
            # Trend changed to downtrend
            if self.position:
                self.sell()

        self.last_direction = self.direction