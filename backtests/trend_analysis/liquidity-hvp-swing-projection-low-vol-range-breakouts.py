import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Liquidity Detection Parameters
    liq_len = 7
    liq_mar = 10 / 6.9
    mar_buy = 2.3
    mar_sel = 2.3
    min_body_atr = 0.15
    require_dir_candle = True
    
    # HVP Parameters
    hvp_on = True
    left_bars = 15
    right_bars = 15
    filter_vol = 2.0
    
    # Swing Projection Parameters
    len_swing = 30
    offset_swing = 10
    data_qty = 5
    
    # LVRB Parameters
    len_vol = 20
    tr_mult = 1.00
    body_mult = 1.10
    use_body = True
    min_bars = 6
    min_good_frac = 0.65
    gap_max = 5
    height_mult = 1.5
    break_mode = "Wick"
    breakout_body_mult = 1.0
    require_candle_color = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR calculations
        self.atr_liq = self.I(pta.atr, high, low, close, length=10)
        self.atr_200_liq = self.I(pta.atr, high, low, close, length=200)
        
        # Pivot points for liquidity
        self.pivot_high = self.I(lambda: pta.pivothigh(high, low, self.liq_len) or pd.Series(np.nan, index=close.index))
        self.pivot_low = self.I(lambda: pta.pivotlow(high, low, self.liq_len) or pd.Series(np.nan, index=close.index))
        
        # LVRB indicators
        self.tr_now = self.I(pta.tr, high, low, close, drift=True)
        self.avg_tr = self.I(pta.sma, self.tr_now, length=self.len_vol)
        self.body_now = self.I(lambda: (close - pd.Series(self.data.Open)).abs())
        self.avg_body = self.I(pta.sma, self.body_now, length=self.len_vol)
        
        # Swing projection
        self.highest = self.I(lambda: high.rolling(self.len_swing).max())
        self.lowest = self.I(lambda: low.rolling(self.len_swing).min())
        self.atr_swing = self.I(lambda: pta.atr(high, low, close, length=200) * 0.5 or pd.Series(0, index=close.index))
        
        # HVP volume percentile
        self.vol_sum = self.I(lambda: volume.rolling(self.left_bars * 2).sum())
        
        # State tracking
        self.lvrb_in_seq = False
        self.lvrb_qualified = False
        self.lvrb_range_hi = None
        self.lvrb_range_lo = None
        self.lvrb_start_idx = None
        self.lvrb_total_bars = 0
        self.lvrb_good_bars = 0
        self.lvrb_fail_streak = 0
        self.lvrb_base_atr = None
        
        self.swing_high_val = None
        self.swing_high_idx = None
        self.swing_low_val = None
        self.swing_low_idx = None
        self.swing_direction = False
        
        self.liq_buy_levels = []
        self.liq_sell_levels = []
        
        self.buy_signal = False
        self.sell_signal = False

    def next(self):
        if len(self.data) < max(self.liq_len, self.len_swing, self.len_vol) + 5:
            return
        
        idx = len(self.data) - 1
        
        # Get current values
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        volume_val = self.data.Volume[-1]
        
        atr_liq = self.atr_liq[-1] if not np.isnan(self.atr_liq[-1]) else 0
        atr_swing = self.atr_swing[-1] if not np.isnan(self.atr_swing[-1]) else 0
        avg_tr = self.avg_tr[-1] if not np.isnan(self.avg_tr[-1]) else 0
        avg_body = self.avg_body[-1] if not np.isnan(self.avg_body[-1]) else 0
        
        highest = self.highest[-1] if not np.isnan(self.highest[-1]) else high_val
        lowest = self.lowest[-1] if not np.isnan(self.lowest[-1]) else low_val
        
        # Update swing direction and tracking
        if high_val == highest:
            self.swing_direction = True
        if low_val == lowest:
            self.swing_direction = False
        
        if len(self.data) >= 2:
            if self.data.High[-2] == self.highest[-2] and high_val < self.highest[-1]:
                self.swing_high_val = self.data.High[-2]
                self.swing_high_idx = idx - 1
            
            if self.data.Low[-2] == self.lowest[-2] and low_val > self.lowest[-1]:
                self.swing_low_val = self.data.Low[-2]
                self.swing_low_idx = idx - 1
        
        # LVRB Logic
        tr_now = self.tr_now[-1] if not np.isnan(self.tr_now[-1]) else 0
        body_now = abs(close_val - open_val)
        
        lv_tr = not np.isnan(avg_tr) and avg_tr > 0 and (tr_now <= avg_tr * self.tr_mult)
        lv_body = (not self.use_body) or (not np.isnan(avg_body) and avg_body > 0 and (body_now <= avg_body * self.body_mult))
        is_low_vol = lv_tr and lv_body
        
        bull_break_live = False
        bear_break_live = False
        
        if not self.lvrb_in_seq:
            if is_low_vol and not np.isnan(avg_tr) and avg_tr > 0:
                self.lvrb_in_seq = True
                self.lvrb_qualified = False
                self.lvrb_start_idx = idx
                self.lvrb_total_bars = 1
                self.lvrb_good_bars = 1
                self.lvrb_fail_streak = 0
                self.lvrb_range_hi = high_val
                self.lvrb_range_lo = low_val
                self.lvrb_base_atr = avg_tr
        else:
            if self.lvrb_qualified and self.lvrb_range_hi is not None and self.lvrb_range_lo is not None:
                up_wick_pierce = (high_val > self.lvrb_range_hi)
                dn_wick_pierce = (low_val < self.lvrb_range_lo)
                up_close_out = (close_val > self.lvrb_range_hi)
                dn_close_out = (close_val < self.lvrb_range_lo)
                
                up_cond = (up_wick_pierce and up_close_out) if self.break_mode == "Wick" else up_close_out
                dn_cond = (dn_wick_pierce and dn_close_out) if self.break_mode == "Wick" else dn_close_out
                
                big_ok = self.breakout_body_mult <= 1.0 or (body_now >= avg_body * self.breakout_body_mult)
                dir_ok_up = (not self.require_candle_color) or (close_val > open_val)
                dir_ok_dn = (not self.require_candle_color) or (close_val < open_val)
                
                bull_break_live = up_cond and big_ok and dir_ok_up
                bear_break_live = dn_cond and big_ok and dir_ok_dn
                
                if bull_break_live or bear_break_live:
                    self.buy_signal = bull_break_live
                    self.sell_signal = bear_break_live
                    self.lvrb_in_seq = False
                    self.lvrb_qualified = False
            
            if self.lvrb_in_seq:
                if np.isnan(avg_tr) or avg_tr <= 0:
                    self.lvrb_in_seq = False
                    self.lvrb_qualified = False
                else:
                    wick_out_but_reentered = self.lvrb_qualified and \
                        ((high_val > self.lvrb_range_hi) or (low_val < self.lvrb_range_lo)) and \
                        (close_val <= self.lvrb_range_hi) and (close_val >= self.lvrb_range_lo)
                    
                    next_hi = self.lvrb_range_hi if wick_out_but_reentered else max(self.lvrb_range_hi, high_val)
                    next_lo = self.lvrb_range_lo if wick_out_but_reentered else min(self.lvrb_range_lo, low_val)
                    
                    next_total = self.lvrb_total_bars + 1
                    next_good = self.lvrb_good_bars + (1 if is_low_vol else 0)
                    next_fail = 0 if is_low_vol else (self.lvrb_fail_streak + 1)
                    
                    min_good_bars = int(np.ceil(self.min_bars * self.min_good_frac))
                    next_frac = float(next_good) / float(next_total) if next_total > 0 else 0
                    next_qual = (next_total >= self.min_bars) and (next_good >= min_good_bars) and (next_frac >= self.min_good_frac)
                    
                    violates = ((next_hi - next_lo) > self.lvrb_base_atr * self.height_mult) or (next_fail > self.gap_max)
                    
                    if violates:
                        self.lvrb_in_seq = False
                        self.lvrb_qualified = False
                        
                        if is_low_vol and not np.isnan(avg_tr) and avg_tr > 0:
                            self.lvrb_in_seq = True
                            self.lvrb_qualified = False
                            self.lvrb_start_idx = idx
                            self.lvrb_total_bars = 1
                            self.lvrb_good_bars = 1
                            self.lvrb_fail_streak = 0
                            self.lvrb_range_hi = high_val
                            self.lvrb_range_lo = low_val
                            self.lvrb_base_atr = avg_tr
                    else:
                        self.lvrb_range_hi = next_hi
                        self.lvrb_range_lo = next_lo
                        self.lvrb_total_bars = next_total
                        self.lvrb_good_bars = next_good
                        self.lvrb_fail_streak = next_fail
                        
                        if next_qual and not self.lvrb_qualified:
                            self.lvrb_qualified = True
        
        # Entry/Exit Logic
        if self.buy_signal and not self.position:
            self.buy()
            self.buy_signal = False
        
        if self.sell_signal and self.position:
            self.sell()
            self.sell_signal = False
        
        if self.sell_signal and not self.position:
            self.sell()
            self.sell_signal = False
        
        if self.buy_signal and self.position:
            self.buy()
            self.buy_signal = False


