import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 200
    forecastLen = 30
    showOB = True
    ema_length = 20
    atr_length = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # Calculate EMA(20)
        self.ema20 = self.I(pta.ema, close, length=self.ema_length)
        
        # Calculate ATR(5)
        self.atr5 = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Calculate body size
        self.body_size = self.I(lambda: (close - open_).abs())
        
        # Determine if current bar is an OB (Order Block)
        def calc_is_ob():
            result = pd.Series(index=close.index, dtype=bool)
            for i in range(len(close)):
                if self.atr5[i] is not None and not np.isnan(self.atr5[i]):
                    atr_val = self.atr5[i]
                    body = abs(close.iloc[i] - open_.iloc[i])
                    result.iloc[i] = (atr_val < body) and (body > atr_val * 1.5)
                else:
                    result.iloc[i] = False
            return result
        
        self.isOB = self.I(calc_is_ob)

    def next(self):
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        ema20_val = self.ema20[-1]
        is_ob = self.isOB[-1]
        
        # Buy signal: close crosses above EMA(20) AND isOB AND close > open
        buy_signal = (
            crossover(self.data.Close, self.ema20) and
            is_ob and
            close_val > open_val
        )
        
        # Sell signal: close crosses below EMA(20) AND isOB AND close < open
        sell_signal = (
            crossover(self.ema20, self.data.Close) and
            is_ob and
            close_val < open_val
        )
        
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()


