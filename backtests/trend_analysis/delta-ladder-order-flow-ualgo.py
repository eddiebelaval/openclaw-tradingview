import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        if len(self.data) < 2:
            return
        
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        if not self.position:
            if close > open_price and low < self.data.Low[-2]:
                self.buy()
            elif close < open_price and high > self.data.High[-2]:
                self.sell()
        else:
            if self.position.is_long and close < open_price:
                self.position.close()
            elif self.position.is_short and close > open_price:
                self.position.close()


