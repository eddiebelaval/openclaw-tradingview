import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Market Structure Parameters
    length = 5
    
    # ATR Trailing Stop Parameters
    a = 2  # Key Value (sensitivity)
    c = 1  # ATR Period
    h = False  # Use Heikin Ashi
    
    # FVG Parameters
    numDays = 7
    showUP = True
    showDN = True
    CEcond = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR Trailing Stop indicators
        self.atr = self.I(pta.atr, high, low, close, length=self.c)
        self.ema = self.I(pta.ema, close, length=1)
        
        # Initialize trailing stop
        self.xATRTrailingStop = self.I(self._calc_trailing_stop, close, self.atr, self.a)
        
        # Position tracker
        self.pos = self.I(self._calc_position, close, self.xATRTrailingStop)
        
        # Buy/Sell signals
        self.above = self.I(lambda: crossover(self.ema, self.xATRTrailingStop))
        self.below = self.I(lambda: crossover(self.xATRTrailingStop, self.ema))
        
        # Buy/Sell conditions
        self.buy_signal = self.I(self._calc_buy_signal, close, self.xATRTrailingStop, self.above)
        self.sell_signal = self.I(self._calc_sell_signal, close, self.xATRTrailingStop, self.below)

    def _calc_trailing_stop(self, close, atr, a):
        nLoss = a * atr
        xATRTrailingStop = np.zeros(len(close))
        pos = 0
        
        for i in range(len(close)):
            if i == 0:
                xATRTrailingStop[i] = close[i]
            else:
                prev_stop = xATRTrailingStop[i-1]
                
                if close[i] > prev_stop:
                    iff_1 = close[i] - nLoss[i]
                else:
                    iff_1 = close[i] + nLoss[i]
                
                if close[i] < prev_stop and close[i-1] < prev_stop:
                    iff_2 = min(prev_stop, close[i] + nLoss[i])
                else:
                    iff_2 = iff_1
                
                if close[i] > prev_stop and close[i-1] > prev_stop:
                    xATRTrailingStop[i] = max(prev_stop, close[i] - nLoss[i])
                else:
                    xATRTrailingStop[i] = iff_2
        
        return pd.Series(xATRTrailingStop, index=close.index)

    def _calc_position(self, close, xATRTrailingStop):
        pos = np.zeros(len(close))
        
        for i in range(len(close)):
            if i == 0:
                pos[i] = 0
            else:
                prev_pos = pos[i-1]
                prev_stop = xATRTrailingStop[i-1]
                
                if close[i-1] > prev_stop and close[i] < prev_stop:
                    pos[i] = -1
                elif close[i-1] < prev_stop and close[i] > prev_stop:
                    pos[i] = 1
                else:
                    pos[i] = prev_pos
        
        return pd.Series(pos, index=close.index)

    def _calc_buy_signal(self, close, xATRTrailingStop, above):
        buy_sig = np.zeros(len(close), dtype=bool)
        
        for i in range(len(close)):
            if i == 0:
                buy_sig[i] = False
            else:
                barbuy = close[i] > xATRTrailingStop[i]
                buy_sig[i] = barbuy and above[i]
        
        return pd.Series(buy_sig, index=close.index)

    def _calc_sell_signal(self, close, xATRTrailingStop, below):
        sell_sig = np.zeros(len(close), dtype=bool)
        
        for i in range(len(close)):
            if i == 0:
                sell_sig[i] = False
            else:
                barsell = close[i] < xATRTrailingStop[i]
                sell_sig[i] = barsell and below[i]
        
        return pd.Series(sell_sig, index=close.index)

    def next(self):
        # Trading logic based on ATR Trailing Stop
        if len(self) < 2:
            return
        
        # Buy signal: price above stop line and EMA crosses above stop
        if self.buy_signal[-1]:
            if not self.position:
                self.buy()
        
        # Sell signal: price below stop line and stop crosses above EMA
        elif self.sell_signal[-1]:
            if self.position:
                self.position.close()
        
        # Close long if price falls below trailing stop
        elif self.position and self.pos[-1] == -1:
            self.position.close()
        
        # Close short if price rises above trailing stop
        elif self.position and self.pos[-1] == 1:
            self.position.close()


