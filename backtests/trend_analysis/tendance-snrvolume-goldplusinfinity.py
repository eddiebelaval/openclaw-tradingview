import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA parameters
    ma_len = 20
    ma_len_50 = 50
    
    # Big Trades parameters
    bt_mult = 3.0
    bt_lookback = 500
    trend_filter = True
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Moving Averages
        self.ma20 = self.I(pta.sma, close, length=self.ma_len)
        self.ma50 = self.I(pta.sma, close, length=self.ma_len_50)
        
        # Big Trades (Whale Logic)
        def calculate_buy_volume():
            range_size = high - low
            raw_buy_vol = np.where(
                range_size == 0,
                0,
                (close - low) / range_size * volume
            )
            return pd.Series(raw_buy_vol, index=close.index)
        
        def calculate_sell_volume():
            range_size = high - low
            raw_sell_vol = np.where(
                range_size == 0,
                0,
                (high - close) / range_size * volume
            )
            return pd.Series(raw_sell_vol, index=close.index)
        
        def calculate_avg_buy_vol():
            raw_buy_vol = calculate_buy_volume()
            avg_vol = pta.sma(raw_buy_vol, length=self.bt_lookback)
            return avg_vol if avg_vol is not None else pd.Series(0, index=close.index)
        
        def calculate_std_buy_vol():
            raw_buy_vol = calculate_buy_volume()
            std_vol = pd.Series(
                raw_buy_vol.rolling(window=self.bt_lookback).std(),
                index=close.index
            )
            return std_vol
        
        def calculate_avg_sell_vol():
            raw_sell_vol = calculate_sell_volume()
            avg_vol = pta.sma(raw_sell_vol, length=self.bt_lookback)
            return avg_vol if avg_vol is not None else pd.Series(0, index=close.index)
        
        def calculate_std_sell_vol():
            raw_sell_vol = calculate_sell_volume()
            std_vol = pd.Series(
                raw_sell_vol.rolling(window=self.bt_lookback).std(),
                index=close.index
            )
            return std_vol
        
        self.raw_buy_vol = self.I(calculate_buy_volume)
        self.raw_sell_vol = self.I(calculate_sell_volume)
        self.avg_buy_vol = self.I(calculate_avg_buy_vol)
        self.std_buy_vol = self.I(calculate_std_buy_vol)
        self.avg_sell_vol = self.I(calculate_avg_sell_vol)
        self.std_sell_vol = self.I(calculate_std_sell_vol)
    
    def next(self):
        # Avoid insufficient data
        if len(self.data) < max(self.ma_len, self.ma_len_50, self.bt_lookback):
            return
        
        # Calculate thresholds
        thresh_buy = self.avg_buy_vol[-1] + self.std_buy_vol[-1] * self.bt_mult
        thresh_sell = self.avg_sell_vol[-1] + self.std_sell_vol[-1] * self.bt_mult
        
        # Big Trades Detection
        is_bt_buy = (self.raw_buy_vol[-1] > thresh_buy and 
                     (not self.trend_filter or self.data.Close[-1] > self.ma20[-1]))
        is_bt_sell = (self.raw_sell_vol[-1] > thresh_sell and 
                      (not self.trend_filter or self.data.Close[-1] < self.ma20[-1]))
        
        # Trading Logic
        if is_bt_buy and not self.position:
            self.buy()
        elif is_bt_sell and self.position:
            self.position.close()