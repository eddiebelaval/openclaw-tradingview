class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        if not self.position:
            if len(self.data) > 20:
                recent_high = max(self.data.High[-20:])
                recent_low = min(self.data.Low[-20:])
                mid = (recent_high + recent_low) / 2
                
                if self.data.Close[-1] < mid and self.data.Close[-1] > recent_low:
                    self.buy()
        else:
            recent_high = max(self.data.High[-20:])
            recent_low = min(self.data.Low[-20:])
            mid = (recent_high + recent_low) / 2
            
            if self.data.Close[-1] > mid:
                self.sell()


