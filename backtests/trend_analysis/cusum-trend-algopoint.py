import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sensitivity = "Balanced (Swing)"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Set parameters based on sensitivity
        if self.sensitivity == "Fast (Day Trade)":
            self.base_len = 14
            self.k_mult = 0.4
            self.h_mult = 2.0
        elif self.sensitivity == "Balanced (Swing)":
            self.base_len = 21
            self.k_mult = 0.5
            self.h_mult = 3.0
        else:  # "Slow (Trend)"
            self.base_len = 50
            self.k_mult = 0.6
            self.h_mult = 4.0
        
        # Calculate HMA
        self.hma = self.I(lambda: pta.hma(close, length=self.base_len) or pd.Series(close.mean(), index=close.index))
        
        # Calculate residuals and standard deviation
        self.residual = self.I(lambda: close - self.hma)
        self.res_std = self.I(lambda: (close - self.hma).rolling(self.base_len).std().fillna(0.001))
        
        # Replace zero std with small value
        self.res_std = self.I(lambda: self.res_std.apply(lambda x: x if x != 0 else 0.001))
        
        # Initialize CUSUM pressures
        self.bull_pressure_values = [0.0]
        self.bear_pressure_values = [0.0]
        
        # Regime tracking
        self.regime_values = [0]
        
        # ATR for stop levels
        self.atr = self.I(lambda: pta.atr(high, low, close, length=30) or pd.Series(1.0, index=close.index))

    def next(self):
        # Current values
        close_val = self.data.Close[-1]
        residual_val = close_val - self.hma[-1]
        res_std_val = max(self.res_std[-1], 0.001)
        
        k_drift = res_std_val * self.k_mult
        h_thresh = res_std_val * self.h_mult
        
        # Update CUSUM pressures
        bull_pressure = max(0, self.bull_pressure_values[-1] + residual_val - k_drift)
        bear_pressure = max(0, self.bear_pressure_values[-1] - residual_val - k_drift)
        
        # Trigger conditions
        trig_bull = bull_pressure > h_thresh
        trig_bear = bear_pressure > h_thresh
        
        # Reset pressures on trigger
        if trig_bull or trig_bear:
            bull_pressure = 0.0
            bear_pressure = 0.0
        
        self.bull_pressure_values.append(bull_pressure)
        self.bear_pressure_values.append(bear_pressure)
        
        # Bands
        up_band = self.hma[-1] + h_thresh
        dn_band = self.hma[-1] - h_thresh
        
        # Update regime
        regime = self.regime_values[-1]
        
        if trig_bull:
            regime = 1
        elif trig_bear:
            regime = -1
        elif regime == 1 and close_val < dn_band:
            regime = 0
        elif regime == -1 and close_val > up_band:
            regime = 0
        
        prev_regime = self.regime_values[-1]
        self.regime_values.append(regime)
        
        # Trading logic
        bull_start = regime == 1 and prev_regime != 1
        bear_start = regime == -1 and prev_regime != -1
        
        # Entry and exit logic
        if bull_start:
            if not self.position:
                self.buy()
        elif bear_start:
            if self.position:
                self.position.close()


