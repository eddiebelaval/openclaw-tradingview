import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 13
    atr_len = 14
    min_swing_atr = 0.0
    strength_filter = "All"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atr_len) or pd.Series(0, index=close.index))
        
        self.warmup_bars = max(self.pivot_len * 2, 30)
        self.pivot_detected = False
        self.last_pivot_price = None
        self.last_pivot_was_high = False
        self.structure_direction = 0
        self.last_ph = None
        self.last_pl = None
        self.live_price = None
        self.live_is_high = False
        self.entry_made = False
        
    def detect_pivot_high(self):
        if len(self.data) < self.pivot_len * 2 + 1:
            return False, None
        
        lookback = self.pivot_len
        current_idx = len(self.data) - 1
        
        if current_idx - lookback < 0 or current_idx + lookback >= len(self.data):
            return False, None
        
        current_high = self.data.High[current_idx - lookback]
        is_high = True
        
        for i in range(current_idx - lookback - lookback, current_idx - lookback):
            if i >= 0 and self.data.High[i] >= current_high:
                is_high = False
                break
        
        if not is_high:
            return False, None
        
        for i in range(current_idx - lookback + 1, current_idx - lookback + lookback + 1):
            if i < len(self.data) and self.data.High[i] >= current_high:
                is_high = False
                break
        
        if is_high:
            atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
            if atr_val > 0 and not self.last_pivot_price:
                swing_size = 0
            elif atr_val > 0 and self.last_pivot_price:
                swing_size = abs(current_high - self.last_pivot_price)
            else:
                swing_size = float('inf')
            
            if self.min_swing_atr == 0 or swing_size >= atr_val * self.min_swing_atr:
                return True, current_high
        
        return False, None
    
    def detect_pivot_low(self):
        if len(self.data) < self.pivot_len * 2 + 1:
            return False, None
        
        lookback = self.pivot_len
        current_idx = len(self.data) - 1
        
        if current_idx - lookback < 0 or current_idx + lookback >= len(self.data):
            return False, None
        
        current_low = self.data.Low[current_idx - lookback]
        is_low = True
        
        for i in range(current_idx - lookback - lookback, current_idx - lookback):
            if i >= 0 and self.data.Low[i] <= current_low:
                is_low = False
                break
        
        if not is_low:
            return False, None
        
        for i in range(current_idx - lookback + 1, current_idx - lookback + lookback + 1):
            if i < len(self.data) and self.data.Low[i] <= current_low:
                is_low = False
                break
        
        if is_low:
            atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
            if atr_val > 0 and not self.last_pivot_price:
                swing_size = 0
            elif atr_val > 0 and self.last_pivot_price:
                swing_size = abs(current_low - self.last_pivot_price)
            else:
                swing_size = float('inf')
            
            if self.min_swing_atr == 0 or swing_size >= atr_val * self.min_swing_atr:
                return True, current_low
        
        return False, None
    
    def next(self):
        if len(self.data) < self.warmup_bars:
            return
        
        ph_detected, ph_val = self.detect_pivot_high()
        pl_detected, pl_val = self.detect_pivot_low()
        
        if ph_detected and ph_val:
            self.last_ph = ph_val
            self.last_pivot_price = ph_val
            self.last_pivot_was_high = True
            
            if self.last_pl is not None and ph_val > self.last_pl:
                if self.structure_direction == -1:
                    self.structure_direction = 1
                    if not self.position:
                        self.buy()
                        self.entry_made = True
            
            self.live_is_high = False
            self.live_price = self.data.Low[-1]
        
        if pl_detected and pl_val:
            self.last_pl = pl_val
            self.last_pivot_price = pl_val
            self.last_pivot_was_high = False
            
