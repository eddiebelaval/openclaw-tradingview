import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Kernel Engine
    kernelLen = 50
    bandwidth = 8.0
    alpha = 1.0
    fastMult = 0.35
    
    # Ribbon
    useRibbon = True
    ribbonSpread = 1.8
    
    # Filters
    useADX = True
    adxLen = 14
    adxThresh = 20.0
    useRSI = True
    rsiLen = 14
    rsiOB = 70.0
    rsiOS = 30.0
    useConfBar = True
    
    # Metal Intelligence
    useGSR = False
    gsrLen = 50
    gsrSens = 1.5
    useVolNorm = True
    spikeMulti = 3.0
    
    # Signal
    sigCooldown = 3
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Spike Protection
        barBody = np.abs(self.data.Close - self.data.Open)
        avgBody = self.I(lambda: pta.sma(pd.Series(barBody), length=20) or pd.Series(0, index=close.index))
        stdBody = self.I(lambda: pta.stdev(pd.Series(barBody), length=20) or pd.Series(0, index=close.index))
        
        # Kernel Regression calculation
        def calc_kernel_regression(src_series, length, bandwidth, alpha):
            def rq_kernel(idx, h, a):
                return (1.0 + (idx ** 2) / (2.0 * a * (h ** 2))) ** (-a)
            
            result = []
            for i in range(len(src_series)):
                sW = 0.0
                sS = 0.0
                for j in range(min(length, i + 1)):
                    w = rq_kernel(j, bandwidth, alpha)
                    sW += w * src_series.iloc[i - j] if (i - j) >= 0 else 0
                    sS += w
                if sS != 0:
                    result.append(sW / sS)
                else:
                    result.append(src_series.iloc[i])
            return pd.Series(result, index=src_series.index)
        
        def spike_filter(close_data, open_data, high_data, low_data, barBody_data, avgBody_data, stdBody_data):
            isSpike = barBody_data > (avgBody_data + self.spikeMulti * stdBody_data)
            filtered = np.where(isSpike, (high_data + low_data) / 2.0, close_data)
            return pd.Series(filtered, index=close_data.index)
        
        finalSrc = self.I(lambda: spike_filter(
            close.values, 
            pd.Series(self.data.Open).values, 
            high.values, 
            low.values,
            barBody,
            avgBody,
            stdBody
        ))
        
        # Calculate kernels
        fastLen = max(5, int(self.kernelLen * self.fastMult))
        fastBW = self.bandwidth * 0.5
        
        self.kSlow = self.I(lambda: calc_kernel_regression(finalSrc, self.kernelLen, self.bandwidth, self.alpha))
        self.kFast = self.I(lambda: calc_kernel_regression(finalSrc, fastLen, fastBW, self.alpha))
        
        bw2 = self.bandwidth * self.ribbonSpread
        bw3 = self.bandwidth * (self.ribbonSpread ** 2)
        self.kR2 = self.I(lambda: calc_kernel_regression(finalSrc, self.kernelLen, bw2, self.alpha))
        self.kR3 = self.I(lambda: calc_kernel_regression(finalSrc, self.kernelLen, bw3, self.alpha))
        
        # ATR and slope
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # ADX
        def calc_adx(high_data, low_data, close_data, length):
            adx_result = pta.adx(high_data, low_data, close_data, length=length)
            if adx_result is not None and len(adx_result) > 0:
                return adx_result.iloc[:, 0] if isinstance(adx_result, pd.DataFrame) else adx_result
            return pd.Series(20, index=close_data.index)
        
        self.adx = self.I(lambda: calc_adx(high, low, close, self.adxLen))
        
        # RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLen) or pd.Series(50, index=close.index))
        
        # Tracking variables
        self.bars_since_signal = 0
        self.last_signal = None
    
    def next(self):
        # Increment signal cooldown
        self.bars_since_signal += 1
        
        # Get current values
        if len(self.kSlow) < 2 or len(self.kFast) < 2:
            return
        
        kSlow_curr = self.kSlow[-1]
        kSlow_prev = self.kSlow[-2]
        kFast_curr = self.kFast[-1]
        kFast_prev = self.kFast[-2]
        
        kR2_curr = self.kR2[-1]
        kR3_curr = self.kR3[-1]
        
        adx_val = self.adx[-1] if len(self.adx) > 0 else 0
        rsi_val = self.rsi[-1] if len(self.rsi) > 0 else 50
        atr_val = self.atr[-1] if len(self.atr) > 0 else 0
        
        # Slope calculations
        rawSlope = kSlow_curr - kSlow_prev
        normSlope = (rawSlope / atr_val) if atr_val > 0 else 0
        
        slowBull = normSlope > 0
        slowBear = normSlope < 0
        
        # Crossover signals
        fastCrossUp = kFast_curr > kSlow_curr and kFast_prev <= kSlow_prev
        fastCrossDown = kFast_curr < kSlow_curr and kFast_prev >= kSlow_prev
        
        # Ribbon filter
        ribBull = (not self.useRibbon) or (kSlow_curr > kR2_curr and kR2_curr > kR3_curr and kSlow_curr > kSlow_prev)
        ribBear = (not self.useRibbon) or (kSlow_curr < kR2_curr and kR2_curr < kR3_curr and kSlow_curr < kSlow_prev)
        
        # ADX filter
        adxOK = (not self.useADX) or (adx_val >= self.adxThresh)
        
        # RSI filters
        rsiLongOK = (not self.useRSI) or (rsi_val < self.rsiOB)
        rsiShortOK = (not self.useRSI) or (rsi_val > self.rsiOS)
        
        # Confirmation bar logic
        confLong = (not self.useConfBar) or ((len(self) > 1) and fastCrossUp and kFast_curr > kSlow_curr)
        confShort = (not self.useConfBar) or ((len(self) > 1) and fastCrossDown and kFast_curr < kSlow_curr)
        
        rawLong = confLong if self.useConfBar else fastCrossUp
        rawShort = confShort if self.useConfBar else fastCrossDown
        
        # Combined filters
        filtersLong = ribBull and adxOK and rsiLongOK
        filtersShort = ribBear and adxOK and rsiShortOK
        
        # Final signals with cooldown
        longSig = rawLong and filtersLong and self.bars_since_signal >= self.sigCooldown
        shortSig = rawShort and filtersShort and self.bars_since_signal >= self.sigCooldown
        
        # Execute trades
        if longSig and not self.position:
            self.buy()
            self.bars_since_signal = 0
        
        elif shortSig:
            if self.position:
                self.position.close()
            self.bars_since_signal = 0