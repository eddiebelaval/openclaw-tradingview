import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    dcLen = 20
    atrLen = 14
    atrMult = 1.5
    useVol = True
    volLen = 20
    volMult = 1.3

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Donchian Channel
        self.dcHigh = self.I(lambda: high.rolling(self.dcLen).max())
        self.dcLow = self.I(lambda: low.rolling(self.dcLen).min())
        self.dcMid = self.I(lambda: (high.rolling(self.dcLen).max() + low.rolling(self.dcLen).min()) / 2)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Volume filter
        self.volMA = self.I(pta.sma, volume, length=self.volLen)
        
        # Body size
        self.bodySize = self.I(lambda: (close - open_).abs())
        
        self.lastSignal = 0

    def next(self):
        if len(self.data) < self.dcLen:
            return
        
        # Current values
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_volume = self.data.Volume[-1]
        
        dcHigh_val = self.dcHigh[-1]
        dcHigh_prev = self.dcHigh[-2] if len(self.dcHigh) > 1 else dcHigh_val
        dcLow_val = self.dcLow[-1]
        dcLow_prev = self.dcLow[-2] if len(self.dcLow) > 1 else dcLow_val
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        volMA_val = self.volMA[-1] if self.volMA[-1] is not None else current_volume
        bodySize_val = self.bodySize[-1]
        
        # Conditions
        volSurge = current_volume >= volMA_val * self.volMult
        strongCandle = bodySize_val >= atr_val * self.atrMult
        
        bullBreak = current_close > dcHigh_prev and strongCandle and (volSurge if self.useVol else True)
        bearBreak = current_close < dcLow_prev and strongCandle and (volSurge if self.useVol else True)
        
        buySignal = bullBreak and self.lastSignal != 1
        sellSignal = bearBreak and self.lastSignal != -1
        
        if buySignal:
            self.lastSignal = 1
            if not self.position:
                self.buy()
        
        if sellSignal:
            self.lastSignal = -1
            if self.position:
                self.position.close()


