import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from datetime import datetime


class TvStrategy(Strategy):
    pctThreshold = 0.001
    tickOffset = 8
    validBars = 5
    useHardStop = True
    hardStop = 40
    useTrailing = True
    trailTicks = 20
    useTP = True
    tpTicks = 40
    useBreakEven = True
    beTrigger = 15
    beOffset = 1
    useTimeFilter = True
    hardCloseTime = 1400
    sessionStartTime = 930
    sessionEndTime = 1400

    def init(self):
        self.pending_long = None
        self.pending_short = None
        self.timer = 0
        self.was_trade_taken = False
        self.entry_price = None

    def next(self):
        # Get current values
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        # Get current time
        current_time = self.data.index[-1]
        hour = current_time.hour
        minute = current_time.minute
        current_hhmm = hour * 100 + minute

        # Time filters
        in_session = (
            not self.useTimeFilter
            or (self.sessionStartTime <= current_hhmm < self.sessionEndTime)
        )
        is_hard_close = (
            self.useTimeFilter and current_hhmm >= self.hardCloseTime
        )

        # Calculate candle metrics
        candle_move = abs(close - open_) / open_ if open_ != 0 else 0
        is_power_candle = (
            candle_move >= self.pctThreshold
            and in_session
            and not is_hard_close
        )

        # Tick size (assuming 0.01 for most assets)
        tick_size = 0.01

        # Reset on power candle
        if is_power_candle:
            self.timer = 0
            self.was_trade_taken = False
            if close > open_:
                self.pending_long = high + (self.tickOffset * tick_size)
                self.pending_short = None
            else:
                self.pending_short = low - (self.tickOffset * tick_size)
                self.pending_long = None

        # Increment timer
        self.timer += 1
        if self.timer > self.validBars or is_hard_close:
            self.pending_long = None
            self.pending_short = None

        # Hard close all positions
        if is_hard_close and self.position:
            self.position.close()

        # Entry logic
        if (
            in_session
            and not is_hard_close
            and not self.position
            and not self.was_trade_taken
        ):
            if (
                self.pending_long is not None
                and high >= self.pending_long
            ):
                self.buy()
                self.entry_price = self.data.Close[-1]
                self.was_trade_taken = True

            elif (
                self.pending_short is not None
                and low <= self.pending_short
            ):
                self.sell()
                self.entry_price = self.data.Close[-1]
                self.was_trade_taken = True

        # Exit logic
        if self.position:
            if self.position.is_long:
                # Calculate exit levels for long
                take_profit = None
                stop_loss = None

                if self.useTP:
                    take_profit = (
                        self.entry_price + (self.tpTicks * tick_size)
                    )

                # Break even logic
                profit_ticks = (high - self.entry_price) / tick_size
                if (
                    self.useBreakEven
                    and profit_ticks >= self.beTrigger
                ):
                    stop_loss = (
                        self.entry_price + (self.beOffset * tick_size)
                    )
                elif self.useHardStop:
                    stop_loss = (
                        self.entry_price - (self.hardStop * tick_size)
                    )

                # Check exit conditions
                should_exit = False
                if take_profit is not None and high >= take_profit:
                    should_exit = True
                if stop_loss is not None and low <= stop_loss:
                    should_exit = True
                if self.useTrailing:
                    trailing_stop = (
                        high - (self.trailTicks * tick_size)
                    )
                    if low <= trailing_stop:
                        should_exit = True

                if should_exit:
                    self.position.close()

            elif self.position.is_short:
                # Calculate exit levels for short
                take_profit = None
                stop_loss = None

                if self.useTP:
                    take_profit = (
                        self.entry_price - (self.tpTicks * tick_size)
                    )

                # Break even logic
                profit_ticks = (self.entry_price - low) / tick_size
                if (
                    self.useBreakEven
                    and profit_ticks >= self.beTrigger
                ):
                    stop_loss = (
                        self.entry_price - (self.beOffset * tick_size)
                    )
                elif self.useHardStop:
                    stop_loss = (
                        self.entry_price + (self.hardStop * tick_size)
                    )

                # Check exit conditions
                should_exit = False
                if take_profit is not None and low <= take_profit:
                    should_exit = True
                if stop_loss is not None and high >= stop_loss:
                    should_exit = True
                if self.useTrailing:
                    trailing_stop = (
                        low + (self.trailTicks * tick_size)
                    )
                    if high >= trailing_stop:
                        should_exit = True

                if should_exit:
                    self.position.close()


