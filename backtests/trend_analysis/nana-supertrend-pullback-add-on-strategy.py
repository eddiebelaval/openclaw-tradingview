import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # SuperTrend parameters
    st_atr_len = 14
    st_factor = 3.5
    
    # RSI parameters
    use_rsi = True
    rsi_len = 14
    rsi_max_buy = 70
    rsi_max_add = 75
    
    # Add-on SuperTrend parameters
    st_add_len = 10
    st_add_factor = 2.5
    pullback_tol = 0.002
    allow_add = True
    
    # Stop loss parameters
    stop_pct = 7
    use_stop = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Main SuperTrend (14, 3.5)
        self.st_main = self.I(self._supertrend_main, high, low, close)
        
        # Add-on SuperTrend (10, 2.5)
        self.st_add = self.I(self._supertrend_add, high, low, close)
        
        # RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_len) or pd.Series(50, index=close.index))
        
        # State tracking
        self.in_long = False
        self.added_second = False
        self.sim_entry = np.nan
        self.entry_prices = []

    def _supertrend_main(self, high, low, close):
        """Calculate SuperTrend with st_atr_len and st_factor"""
        atr = pta.atr(high, low, close, length=self.st_atr_len)
        hl2 = (high + low) / 2
        
        basic_ub = hl2 + self.st_factor * atr
        basic_lb = hl2 - self.st_factor * atr
        
        final_ub = pd.Series(index=close.index, dtype='float64')
        final_lb = pd.Series(index=close.index, dtype='float64')
        
        for i in range(len(close)):
            if i == 0:
                final_ub.iloc[i] = basic_ub.iloc[i]
                final_lb.iloc[i] = basic_lb.iloc[i]
            else:
                final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
        
        st_line = pd.Series(index=close.index, dtype='float64')
        st_dir = pd.Series(index=close.index, dtype='float64')
        
        for i in range(len(close)):
            if i == 0:
                st_line.iloc[i] = final_ub.iloc[i]
                st_dir.iloc[i] = 1
            else:
                if st_dir.iloc[i-1] == 1:
                    st_line.iloc[i] = final_ub.iloc[i]
                    st_dir.iloc[i] = -1 if close.iloc[i] <= final_ub.iloc[i] else 1
                else:
                    st_line.iloc[i] = final_lb.iloc[i]
                    st_dir.iloc[i] = -1 if close.iloc[i] >= final_lb.iloc[i] else 1
        
        return st_dir

    def _supertrend_add(self, high, low, close):
        """Calculate SuperTrend with st_add_len and st_add_factor"""
        atr = pta.atr(high, low, close, length=self.st_add_len)
        hl2 = (high + low) / 2
        
        basic_ub = hl2 + self.st_add_factor * atr
        basic_lb = hl2 - self.st_add_factor * atr
        
        final_ub = pd.Series(index=close.index, dtype='float64')
        final_lb = pd.Series(index=close.index, dtype='float64')
        
        for i in range(len(close)):
            if i == 0:
                final_ub.iloc[i] = basic_ub.iloc[i]
                final_lb.iloc[i] = basic_lb.iloc[i]
            else:
                final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
        
        st_line = pd.Series(index=close.index, dtype='float64')
        
        for i in range(len(close)):
            if i == 0:
                st_line.iloc[i] = final_ub.iloc[i]
            else:
                if st_line.iloc[i-1] == final_ub.iloc[i-1]:
                    st_line.iloc[i] = final_ub.iloc[i]
                else:
                    st_line.iloc[i] = final_lb.iloc[i]
        
        return st_line

    def next(self):
        st_dir = self.st_main[-1]
        st_dir_prev = self.st_main[-2] if len(self.st_main) > 1 else st_dir
        
        in_uptrend = st_dir == -1
        buy_signal_raw = st_dir == -1 and st_dir_prev == 1
        sell_signal = st_dir == 1 and st_dir_prev == -1
        
        # RSI filtering
        rsi_val = self.rsi[-1]
        rsi_ok_buy = not self.use_rsi or rsi_val < self.rsi_max_buy
        rsi_ok_add = not self.use_rsi or rsi_val < self.rsi_max_add
        
        buy_signal = buy_signal_raw and rsi_ok_buy
        
        # Buy signal
        if buy_signal and not self.in_long:
            self.in_long = True
            self.added_second = False
            self.sim_entry = self.data.Close[-1]
            self.entry_prices = [self.sim_entry]
            self.buy()
        
        # Sell signal
        if sell_signal and self.in_long:
            self.in_long = False
            self.added_second = False
            self.entry_prices = []
            self.sell()
        
        # Add-on logic (pullback)
        if self.in_long and self.allow_add:
            lower_edge_add = self.st_add[-1]
            touched_lower = self.data.Low[-1] <= lower_edge_add * (1 + self.pullback_tol)
            
            can_add = (in_uptrend and not self.added_second and touched_lower 
                      and not buy_signal and rsi_ok_add)
            
            if can_add:
                self.added_second = True
                avg_entry = np.mean(self.entry_prices) if self.entry_prices else self.data.Close[-1]
                new_entry = (avg_entry + self.data.Close[-1]) / 2
                self.entry_prices.append(self.data.Close[-1])
                self.sim_entry = new_entry
        
        # Stop loss logic
        if self.use_stop and self.in_long and not np.isnan(self.sim_entry):
            loss_pct = (self.sim_entry - self.data.Close[-1]) / self.sim_entry * 100.0
            
            if loss_pct >= self.stop_pct:
                self.in_long = False
                self.added_second = False
                self.entry_prices = []
                self.sell()


