import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters
    show_outside_bar = True
    show_2bar_reversal = True
    use_bull_swing_filter = False
    use_bear_swing_filter = False
    swing_lookback = 20
    swing_strength = 3
    r_multiple = 2.0
    use_vwap_filter = False
    use_time_filter = False
    start_hour = 8
    start_minute = 0
    end_hour = 11
    end_minute = 0

    def init(self):
        self.vwap_values = self.I(self._calculate_vwap)
        self.swing_lows = []
        self.swing_highs = []
        self.active_trades = []
        self.trade_count = 0

    def _calculate_vwap(self):
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        hlc3 = (high + low + close) / 3
        vwap_result = pta.vwap(hlc3, volume)
        
        if vwap_result is not None:
            return vwap_result
        return pd.Series(close.mean(), index=close.index)

    def _find_recent_swing_low(self, bar_idx):
        """Find recent swing low within swingLookback bars"""
        if bar_idx < self.swing_lookback + self.swing_strength:
            return None
        
        for i in range(self.swing_strength, min(self.swing_lookback, bar_idx)):
            is_swing_low = True
            actual_idx = bar_idx - i
            
            if actual_idx < self.swing_strength or actual_idx + self.swing_strength >= len(self.data.Low):
                continue
            
            for j in range(1, self.swing_strength + 1):
                if (self.data.Low[actual_idx] >= self.data.Low[actual_idx - j] or 
                    self.data.Low[actual_idx] >= self.data.Low[actual_idx + j]):
                    is_swing_low = False
                    break
            
            if is_swing_low:
                return self.data.Low[actual_idx]
        
        return None

    def _find_recent_swing_high(self, bar_idx):
        """Find recent swing high within swingLookback bars"""
        if bar_idx < self.swing_lookback + self.swing_strength:
            return None
        
        for i in range(self.swing_strength, min(self.swing_lookback, bar_idx)):
            is_swing_high = True
            actual_idx = bar_idx - i
            
            if actual_idx < self.swing_strength or actual_idx + self.swing_strength >= len(self.data.High):
                continue
            
            for j in range(1, self.swing_strength + 1):
                if (self.data.High[actual_idx] <= self.data.High[actual_idx - j] or 
                    self.data.High[actual_idx] <= self.data.High[actual_idx + j]):
                    is_swing_high = False
                    break
            
            if is_swing_high:
                return self.data.High[actual_idx]
        
        return None

    def _check_in_time_window(self):
        """Check if current bar is within trading time window"""
        if not self.use_time_filter:
            return True
        
        bar_hour = len(self.data) - 1
        bar_minute = 0
        
        bar_time_minutes = bar_hour * 60 + bar_minute
        start_time_minutes = self.start_hour * 60 + self.start_minute
        end_time_minutes = self.end_hour * 60 + self.end_minute
        
        return bar_time_minutes >= start_time_minutes and bar_time_minutes < end_time_minutes

    def next(self):
        bar_idx = len(self.data) - 1
        
        if bar_idx < 2:
            return
        
        # Current and previous candles
        c0_high = self.data.High[-1]
        c0_low = self.data.Low[-1]
        c0_close = self.data.Close[-1]
        
        c1_open = self.data.Open[-2]
        c1_high = self.data.High[-2]
        c1_low = self.data.Low[-2]
        c1_close = self.data.Close[-2]
        
        c2_high = self.data.High[-3] if bar_idx >= 2 else self.data.High[-2]
        c2_low = self.data.Low[-3] if bar_idx >= 2 else self.data.Low[-2]
        c2_close = self.data.Close[-3] if bar_idx >= 2 else self.data.Close[-2]
        
        # Outside bar conditions
        bull_outside_bar = (
            c1_close < c1_open and
            c1_close < c2_close and
            c1_low < c2_low and
            c0_low < c1_low and
            c0_close > c1_open and
            c0_high > c1_high
        )
        
        bear_outside_bar = (
            c1_close > c1_open and
            c1_close > c2_close and
            c1_high > c2_high and
            c0_high > c1_high and
            c0_close < c1_open and
            c0_low < c1_low
        )
        
        # 2-bar reversal conditions
        bull_2bar_reversal = (
            c1_close < c2_low and
            c0_close > c1_open
        )
        
        bear_2bar_reversal = (
            c1_close > c2_high and
            c0_close < c1_open
        )
        
        # VWAP filter
        vwap_value = self.vwap_values[-1] if len(self.vwap_values) > 0 else c0_close
        bull_vwap_ok = not self.use_vwap_filter or c0_close > vwap_value
        bear_vwap_ok = not self.use_vwap_filter or c0_close < vwap_value
        
        # Time filter
        in_time_window = self._check_in_time_window()
        
        # Base signals
        bull_base_signal = (
            in_time_window and bull_vwap_ok and
            ((self.show_outside_bar and bull_outside_bar) or
             (self.show_2bar_reversal and bull_2bar_reversal))
        )
        
        bear_base_signal = (
            in_time_window and bear_vwap_ok and
            ((self.show_outside_bar and bear_outside_bar) or
             (self.show_2bar_reversal and bear_2bar_reversal))
        )
        
        # Swing filters
        bull_signal = bull_base_signal
        bear_signal = bear_base_signal
        
        if self.use_bull_swing_filter and bull_base_signal:
            swing_low = self._find_recent_swing_low(bar_idx)
            if swing_low is not None:
                bull_signal = c0_low < swing_low
            else:
                bull_signal = False
        
        if self.use_bear_swing_filter and bear_base_signal:
            swing_high = self._find_recent_swing_high(bar_idx)
            if swing_high is not None:
                bear_signal = c0_high > swing_high
            else:
                bear_signal = False
        
        # Update active trades
        for trade in list(self.active_trades):
            trade_idx, entry, sl, tp, is_bull = trade
            
            if is_bull:
                if c0_high >= tp or c0_low <= sl:
                    self.active_trades.remove(trade)
                    if c0_high >= tp:
                        self.trade_count += 1
                    else:
                        self.trade_count -= 1
            else:
                if c0_low <= tp or c0_high >= sl:
                    self.active_trades.remove(trade)
                    if c0_low <= tp:
                        self.trade_count += 1
                    else:
                        self.trade_count -= 1
        
        # Enter trades
        if bull_signal and not self.position:
            sl = c1_low
            entry = self.data.Open[-1]
            risk = entry - sl
            tp = entry + risk * self.r_multiple
            
            self.buy()
            self.active_trades.append((bar_idx, entry, sl, tp, True))
        
        elif bear_signal and not self.position:
            sl = c1_high
            entry = self.data.Open[-1]
            risk = sl - entry
            tp = entry - risk * self.r_multiple
            
            self.sell()
            self.active_trades.append((bar_idx, entry, sl, tp, False))
        
        # Exit trades
        if self.position:
            if self.position.is_long:
                sl = c1_low
                entry = self.position.open_price
                risk = entry - sl
                tp = entry + risk * self.r_multiple
                
                if self.data.Low[-1] <= sl or self.data.High[-1] >= tp:
                    self.position.close()
            else:
                sl = c1_high
                entry = self.position.open_price
                risk = sl - entry
                tp = entry - risk * self.r_multiple
                
                if self.data.High[-1] >= sl or self.data.Low[-1] <= tp:
                    self.position.close()


