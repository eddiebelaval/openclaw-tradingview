import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrPeriod = 10
    factor = 3.0
    emaPeriod = 21
    vwmaPeriod = 20
    volMaLen = 20
    startHour = 9
    startMinute = 15
    allowAfterMin = 15
    cutoffHour = 14
    cutoffMinute = 45
    useTimeVolFilter = True
    minVolVsAvg = 0.80

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.ema21 = self.I(pta.ema, close, length=self.emaPeriod)
        
        self.vwma = self.I(pta.vwma, close, volume, length=self.vwmaPeriod)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)
        
        def supertrend_calc():
            atr_vals = pta.atr(high, low, close, length=self.atrPeriod)
            if atr_vals is None:
                return pd.Series(0, index=close.index)
            
            midHL = (high + low) / 2.0
            upper = midHL + self.factor * atr_vals
            lower = midHL - self.factor * atr_vals
            
            st = pd.Series(index=close.index, dtype=float)
            dir_up = pd.Series(index=close.index, dtype=bool)
            
            st.iloc[0] = upper.iloc[0] if close.iloc[0] <= upper.iloc[0] else lower.iloc[0]
            dir_up.iloc[0] = close.iloc[0] > upper.iloc[0]
            
            for i in range(1, len(close)):
                if close.iloc[i] > st.iloc[i-1]:
                    st.iloc[i] = max(lower.iloc[i], st.iloc[i-1])
                    dir_up.iloc[i] = True
                else:
                    st.iloc[i] = min(upper.iloc[i], st.iloc[i-1])
                    dir_up.iloc[i] = False
            
            return st
        
        self.st = self.I(supertrend_calc)
        
        self.volMA = self.I(pta.sma, volume, length=self.volMaLen)
        
        self.last_signal_date = None

    def next(self):
        if len(self.data) < max(self.atrPeriod, self.emaPeriod, self.vwmaPeriod, self.volMaLen) + 5:
            return
        
        current_date = self.data.index[-1].date()
        if self.last_signal_date != current_date:
            self.last_signal_date = current_date
            signal_taken_today = False
        else:
            signal_taken_today = True
        
        current_time = self.data.index[-1]
        cur_hour = current_time.hour
        cur_minute = current_time.minute
        cur_mins = cur_hour * 60 + cur_minute
        
        market_open = self.startHour * 60 + self.startMinute
        first_allowed = market_open + self.allowAfterMin
        cutoff_time = self.cutoffHour * 60 + self.cutoffMinute
        
        is_allowed_time = cur_mins >= first_allowed and cur_mins <= cutoff_time
        
        avg_bar_vol = self.volMA[-1] if self.volMA[-1] is not None else 1
        vol_strength_ok = (self.data.Volume[-1] / avg_bar_vol) >= self.minVolVsAvg if avg_bar_vol > 0 else False
        time_vol_ok = vol_strength_ok if self.useTimeVolFilter else True
        
        can_fire_signal = not signal_taken_today and is_allowed_time and time_vol_ok
        
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        ema21_val = self.ema21[-1]
        vwma_val = self.vwma[-1]
        st_val = self.st[-1]
        volMA_val = self.volMA[-1]
        
        is_red = close < open_price
        is_green = close > open_price
        
        above_all = close > ema21_val and close > vwma_val and close > st_val
        below_all = close < ema21_val and close < vwma_val and close < st_val
        
        raw_buy = above_all and (self.data.Volume[-1] > volMA_val)
        raw_sell = below_all and (self.data.Volume[-1] > volMA_val) and is_red
        
        buy_signal = raw_buy and can_fire_signal
        sell_signal = raw_sell and can_fire_signal
        
        if buy_signal and not self.position:
            self.buy()
            self.last_signal_date = current_date
        elif sell_signal and self.position:
            self.sell()
            self.last_signal_date = current_date