import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    riskLen = 4
    trigLen = 10
    accelLen = 2
    
    floorLvl = 10.0
    watchLvl = 25.0
    warnLvl = 40.0
    riskLvl = 58.0
    crashLvl = 74.0
    
    resetLvl = 22.0
    resetBars = 10
    cooldownBars = 16

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Placeholder indicators since external data (VIX, HY, etc.) is not available in backtest
        # We'll use price-based metrics as proxy
        
        # ATR as volatility proxy
        atr = self.I(pta.atr, high, low, close, length=14)
        atr_pct = self.I(lambda: (atr / close * 100.0) if atr is not None else pd.Series(2.0, index=close.index))
        
        # RSI for price weakness
        rsi = self.I(pta.rsi, close, length=14)
        
        # EMA for trend
        ema50 = self.I(pta.ema, close, length=50)
        ema200 = self.I(pta.ema, close, length=200)
        
        # Highest close for drawdown calc
        highest = self.I(lambda: close.rolling(63).max() if len(close) > 0 else pd.Series(0, index=close.index))
        
        # Simple breadth proxy using price momentum
        momentum = self.I(lambda: close - close.shift(10) if len(close) > 10 else pd.Series(0, index=close.index))
        
        # Volatility structure proxy (price volatility)
        volatility = self.I(lambda: close.pct_change().rolling(14).std() * 100 if len(close) > 14 else pd.Series(2.0, index=close.index))
        
        # Store indicators
        self.atr_pct = atr_pct
        self.rsi = rsi
        self.ema50 = ema50
        self.ema200 = ema200
        self.highest = highest
        self.momentum = momentum
        self.volatility = volatility
        self.close = close
        
        # State tracking
        self.wave_active = False
        self.cooldown = 0
        self.last_signal = None

    def next(self):
        if len(self.data) < 65:
            return
        
        # Update cooldown
        self.cooldown += 1
        
        # Get current values
        c = self.close.iloc[-1]
        atr_pct = self.atr_pct[-1] if self.atr_pct[-1] is not None else 2.0
        atr_pct_prev = self.atr_pct[-2] if self.atr_pct[-2] is not None else 2.0
        rsi = self.rsi[-1] if self.rsi[-1] is not None else 50
        ema50 = self.ema50[-1] if self.ema50[-1] is not None else c
        ema200 = self.ema200[-1] if self.ema200[-1] is not None else c
        highest = self.highest[-1] if self.highest[-1] is not None else c
        momentum = self.momentum[-1] if self.momentum[-1] is not None else 0
        momentum_prev = self.momentum[-2] if self.momentum[-2] is not None else 0
        volatility = self.volatility[-1] if self.volatility[-1] is not None else 2.0
        
        # Calculate composite risk score
        drawdown_pct = ((highest - c) / highest * 100.0) if highest > 0 else 0.0
        dd_score = min(max((drawdown_pct - 2.0) / (12.0 - 2.0) * 100.0, 0.0), 100.0)
        
        below50_pct = ((ema50 - c) / ema50 * 100.0) if ema50 > 0 else 0.0
        below50_score = min(max((below50_pct - 0.5) / (4.5 - 0.5) * 100.0, 0.0), 100.0)
        
        below200_pct = ((ema200 - c) / ema200 * 100.0) if ema200 > 0 else 0.0
        below200_score = min(max((below200_pct - 0.0) / (8.0 - 0.0) * 100.0, 0.0), 100.0)
        
        trend_score = dd_score * 0.50 + below50_score * 0.35 + below200_score * 0.15
        
        rsi_weakness = min(max((52.0 - rsi) / 18.0 * 100.0, 0.0), 100.0)
        atr_score = min(max((atr_pct - 1.0) / (3.0 - 1.0) * 100.0, 0.0), 100.0)
        price_stress = rsi_weakness * 0.60 + atr_score * 0.40
        
        momentum_score = min(max(50.0 - momentum * 100.0, 0.0), 100.0)
        
        risk_raw = trend_score * 0.40 + price_stress * 0.35 + momentum_score * 0.25
        
        # Determine state based on risk score
        state = 0
        if risk_raw >= self.crashLvl:
            state = 4
        elif risk_raw >= self.riskLvl:
            state = 3
        elif risk_raw >= self.warnLvl:
            state = 2
        elif risk_raw >= self.watchLvl:
            state = 1
        else:
            state = 0
        
        # Conditions for signal
        trend_weak = c < ema50
        trend_bad = c < ema50 and c < ema200
        rsi_bad = rsi < 49.5
        price_bad = atr_pct > atr_pct_prev
        momentum_bad = momentum < 0 and momentum_prev < 0
        
        # Entry signals
        risk_build = (state >= 3 and trend_weak and (price_bad or momentum_bad))
        main_risk = (state >= 3 and trend_bad and rsi_bad and price_bad)
        early_warning = (state >= 2 and trend_weak and rsi_bad and momentum_bad)
        
        # Reset condition
        reset_condition = risk_raw < self.resetLvl and not trend_bad and momentum >= 0
        
        # Logic
        if self.wave_active and reset_condition:
            self.wave_active = False
            if self.last_signal and self.position:
                self.sell()
                self.last_signal = None
        
        if not self.wave_active and self.cooldown >= self.cooldownBars:
            if main_risk and not self.position:
                self.buy()
                self.wave_active = True
                self.cooldown = 0
                self.last_signal = "main"
            elif risk_build and not self.position:
                self.buy()
                self.wave_active = True
                self.cooldown = 0
                self.last_signal = "build"
            elif early_warning and not self.position:
                self.buy()
                self.wave_active = True
                self.cooldown = 0
                self.last_signal = "early"
        
        # Exit on reset if in position
        if self.position and reset_condition:
            self.sell()
            self.wave_active = False
            self.last_signal = None


