import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 15
    max_zones = 3
    
    def init(self):
        self.bsl_levels = []
        self.ssl_levels = []
        self.bsl_bars = []
        self.ssl_bars = []
        
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.pivot_highs = self.I(self._get_pivot_highs, high, self.pivot_len)
        self.pivot_lows = self.I(self._get_pivot_lows, low, self.pivot_len)
    
    def _get_pivot_highs(self, high, length):
        pivots = pd.Series(np.nan, index=high.index)
        for i in range(length, len(high) - length):
            if high.iloc[i] == high.iloc[i-length:i+length+1].max():
                pivots.iloc[i] = high.iloc[i]
        return pivots
    
    def _get_pivot_lows(self, low, length):
        pivots = pd.Series(np.nan, index=low.index)
        for i in range(length, len(low) - length):
            if low.iloc[i] == low.iloc[i-length:i+length+1].min():
                pivots.iloc[i] = low.iloc[i]
        return pivots
    
    def next(self):
        current_bar = len(self.data) - 1
        
        if not np.isnan(self.pivot_highs[-1]):
            ph_level = self.pivot_highs[-1]
            self.bsl_levels.append(ph_level)
            self.bsl_bars.append(current_bar)
            
            if len(self.bsl_levels) > self.max_zones:
                self.bsl_levels.pop(0)
                self.bsl_bars.pop(0)
        
        if not np.isnan(self.pivot_lows[-1]):
            pl_level = self.pivot_lows[-1]
            self.ssl_levels.append(pl_level)
            self.ssl_bars.append(current_bar)
            
            if len(self.ssl_levels) > self.max_zones:
                self.ssl_levels.pop(0)
                self.ssl_bars.pop(0)
        
        bsl_to_remove = []
        for i, level in enumerate(self.bsl_levels):
            if self.data.High[-1] >= level and current_bar > self.bsl_bars[i]:
                bsl_to_remove.append(i)
        
        for i in reversed(bsl_to_remove):
            self.bsl_levels.pop(i)
            self.bsl_bars.pop(i)
        
        ssl_to_remove = []
        for i, level in enumerate(self.ssl_levels):
            if self.data.Low[-1] <= level and current_bar > self.ssl_bars[i]:
                ssl_to_remove.append(i)
        
        for i in reversed(ssl_to_remove):
            self.ssl_levels.pop(i)
            self.ssl_bars.pop(i)
        
        if len(self.bsl_levels) > 0 and not self.position:
            closest_bsl = min(self.bsl_levels)
            if self.data.Low[-1] <= closest_bsl < self.data.Close[-1]:
                self.buy()
        
        if len(self.ssl_levels) > 0 and self.position:
            closest_ssl = max(self.ssl_levels)
            if self.data.High[-1] >= closest_ssl > self.data.Close[-1]:
                self.sell()


