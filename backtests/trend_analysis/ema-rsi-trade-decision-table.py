import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    ema50Len = 50
    ema100Len = 100
    ema200Len = 200
    emaTolPct = 0.15
    minEMADistPct = 0.50
    maxPriceEma50DistPct = 0.40
    bullRSILow = 40
    bullRSIHigh = 80
    bearRSILow = 20
    bearRSIHigh = 60
    useEMA200Regime = False
    gradeA_min = 75
    gradeB_min = 60
    rsiLongMin = 55
    rsiShortMax = 45
    cooldownBars = 15
    requireRejection = True
    tradeDecisionMinScore = 92

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.ema50 = self.I(pta.ema, close, length=self.ema50Len)
        self.ema100 = self.I(pta.ema, close, length=self.ema100Len)
        self.ema200 = self.I(pta.ema, close, length=self.ema200Len)
        self.rsiVal = self.I(pta.rsi, close, length=self.rsiLen)

        self.bull_cross_bar = self.I(lambda: self._bullcross_helper())
        self.bear_cross_bar = self.I(lambda: self._bearcross_helper())

        self.last_long_entry = False
        self.last_short_entry = False

    def _bullcross_helper(self):
        result = np.zeros(len(self.data.Close))
        for i in range(1, len(self.data.Close)):
            if self.ema50[i] > self.ema100[i] and self.ema50[i-1] <= self.ema100[i-1]:
                result[i] = i
            else:
                result[i] = result[i-1] if i > 0 else 0
        return result

    def _bearcross_helper(self):
        result = np.zeros(len(self.data.Close))
        for i in range(1, len(self.data.Close)):
            if self.ema50[i] < self.ema100[i] and self.ema50[i-1] >= self.ema100[i-1]:
                result[i] = i
            else:
                result[i] = result[i-1] if i > 0 else 0
        return result

    def next(self):
        close = self.data.Close[-1]
        ema50 = self.ema50[-1]
        ema100 = self.ema100[-1]
        ema200 = self.ema200[-1]
        rsi = self.rsiVal[-1]

        if np.isnan(ema50) or np.isnan(ema100) or np.isnan(ema200) or np.isnan(rsi):
            return

        priceToEma50Pct = abs(close - ema50) / ema50 * 100.0
        emaDistPct = abs(ema50 - ema100) / ema100 * 100.0

        priceTooFar = priceToEma50Pct > self.maxPriceEma50DistPct
        emaTooClose = emaDistPct < self.minEMADistPct

        emaBull = ema50 > ema100
        emaBear = ema50 < ema100

        bullRegime = emaBull
        bearRegime = emaBear

