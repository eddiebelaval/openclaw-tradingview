import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 14
    mlen = 14
    vlen = 14
    mulu = 1.35
    muld = 1.35

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # HMA calculation
        def calc_hma(src, length):
            result = pta.hma(src, length=length)
            return result if result is not None else pd.Series(0, index=src.index)
        
        hma_len = int(np.sqrt(self.len))
        self.xm = self.I(calc_hma, close, hma_len)
        
        # Find xr: value of HMA at bar with highest volume
        def calc_xr(src, hma_vals, vol, length):
            xr_series = pd.Series(index=src.index, dtype=float)
            for idx in range(len(src)):
                if idx < length:
                    xr_series.iloc[idx] = np.nan
                else:
                    highest_vol_idx = vol.iloc[idx-length+1:idx+1].idxmax()
                    bars_back = idx - highest_vol_idx
                    if bars_back >= 0 and bars_back < len(hma_vals):
                        xr_series.iloc[idx] = hma_vals.iloc[idx - bars_back]
                    else:
                        xr_series.iloc[idx] = np.nan
            return xr_series
        
        self.xr = self.I(calc_xr, close, self.xm, volume, self.len)
        
        # Median of xr
        def calc_median(xr_vals, length):
            result = pta.median(xr_vals, length=length)
            return result if result is not None else pd.Series(0, index=xr_vals.index)
        
        self.x = self.I(calc_median, self.xr, self.mlen)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.vlen)
        
        # Upper and lower bands
        def calc_bands(x_vals, atr_vals, mulu, muld):
            upper = x_vals + atr_vals * mulu
            lower = x_vals - atr_vals * muld
            return upper, lower
        
        self.upper = self.I(lambda: (self.x + self.atr * self.mulu) if (self.x is not None and self.atr is not None) else pd.Series(0, index=close.index))
        self.lower = self.I(lambda: (self.x - self.atr * self.muld) if (self.x is not None and self.atr is not None) else pd.Series(0, index=close.index))
        
        # Trend tracking
        self.trend = 0
        self.prev_trend = 0

    def next(self):
        if len(self.data) < self.len + self.mlen + self.vlen:
            return
        
        # Check for None values
        if (self.upper[-1] is None or self.lower[-1] is None or 
            self.data.Close[-1] is None or self.atr[-1] is None):
            return
        
        current_close = self.data.Close[-1]
        upper = self.upper[-1]
        lower = self.lower[-1]
        
        # Update trend
        L = current_close > upper
        S = current_close < lower
        
        if L and not S:
            self.trend = 1
        if S:
            self.trend = -1
        
        # Generate signals on trend change
        if self.trend > self.prev_trend and self.trend == 1:
            if self.position:
                self.position.close()
            self.buy()
        elif self.trend < self.prev_trend and self.trend == -1:
            if self.position:
                self.position.close()
            self.sell()
        
        self.prev_trend = self.trend


