import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vol_len = 20
    vol_mult = 3.0
    
    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # Calculate average volume
        self.avg_vol = self.I(pta.sma, volume, length=self.vol_len)
        
        # Volume anomaly detection
        self.is_anomaly = self.I(lambda: volume > (self.avg_vol * self.vol_mult))
        
        # Bull spike: volume anomaly + close > open
        self.is_bull_spike = self.I(lambda: self.is_anomaly & (close > open_))
        
        # Bear spike: volume anomaly + close < open
        self.is_bear_spike = self.I(lambda: self.is_anomaly & (close < open_))
        
        # Zone tracking
        self.bull_zones = []  # List of [top, bottom, bar_created]
        self.bear_zones = []  # List of [top, bottom, bar_created]
        
        # Trading signals
        self.in_bull_zone = False
        self.in_bear_zone = False
        self.last_signal = None

    def next(self):
        current_idx = len(self.data) - 1
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Check for new anomalies and create zones
        if len(self.is_bull_spike) > 0 and self.is_bull_spike[-1]:
            new_zone = {
                'top': current_high,
                'bottom': current_low,
                'created_at': current_idx,
                'type': 'bull'
            }
            self.bull_zones.append(new_zone)
        
        if len(self.is_bear_spike) > 0 and self.is_bear_spike[-1]:
            new_zone = {
                'top': current_high,
                'bottom': current_low,
                'created_at': current_idx,
                'type': 'bear'
            }
            self.bear_zones.append(new_zone)
        
        # Process bullish zones (demand zones)
        zones_to_remove = []
        for i, zone in enumerate(self.bull_zones):
            # If price dips into zone, shrink top
            if current_low < zone['top'] and current_low > zone['bottom']:
                zone['top'] = current_low
            
            # If price closes below bottom, destroy zone
            if current_close < zone['bottom']:
                zones_to_remove.append(i)
        
        # Remove destroyed zones (iterate backwards to preserve indices)
        for i in sorted(zones_to_remove, reverse=True):
            self.bull_zones.pop(i)
        
        # Process bearish zones (supply zones)
        zones_to_remove = []
        for i, zone in enumerate(self.bear_zones):
            # If price rallies into zone, shrink bottom
            if current_high > zone['bottom'] and current_high < zone['top']:
                zone['bottom'] = current_high
            
            # If price closes above top, destroy zone
            if current_close > zone['top']:
                zones_to_remove.append(i)
        
        # Remove destroyed zones
        for i in sorted(zones_to_remove, reverse=True):
            self.bear_zones.pop(i)
        
        # Trading logic based on zones
        in_bull_zone_now = False
        in_bear_zone_now = False
        
        # Check if price is in any bullish zone
        for zone in self.bull_zones:
            if current_low <= zone['top'] and current_high >= zone['bottom']:
                in_bull_zone_now = True
                break
        
        # Check if price is in any bearish zone
        for zone in self.bear_zones:
            if current_low <= zone['top'] and current_high >= zone['bottom']:
                in_bear_zone_now = True
                break
        
        # Buy signal: price enters bullish demand zone
        if in_bull_zone_now and not self.in_bull_zone:
            if not self.position:
                self.buy()
            self.last_signal = 'buy'
        
        # Sell signal: price enters bearish supply zone or exits bullish zone
        if (in_bear_zone_now and not self.in_bear_zone) or (self.in_bull_zone and not in_bull_zone_now):
            if self.position:
                self.sell()
            self.last_signal = 'sell'
        
        self.in_bull_zone = in_bull_zone_now
        self.in_bear_zone = in_bear_zone_now


