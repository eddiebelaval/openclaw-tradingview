import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 20
    slowLen = 50
    trendLen = 200
    zoneLength = 50
    zoneDeviation = 1.5
    liqLookback = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate HMA using WMA
        def calc_hma(src, length):
            wma1 = pta.wma(src, length=length // 2)
            wma2 = pta.wma(src, length=length)
            if wma1 is None or wma2 is None:
                return None
            combined = 2 * wma1 - wma2
            return pta.wma(combined, length=int(np.sqrt(length)))
        
        # Calculate moving averages
        self.fastMA = self.I(lambda: pta.hma(close, length=self.fastLen) or pd.Series(close.iloc[-1], index=close.index))
        self.slowMA = self.I(lambda: pta.hma(close, length=self.slowLen) or pd.Series(close.iloc[-1], index=close.index))
        self.trendMA = self.I(lambda: pta.hma(close, length=self.trendLen) or pd.Series(close.iloc[-1], index=close.index))
        
        # Calculate zones
        self.hmaHigh = self.I(lambda: pta.hma(high, length=self.zoneLength) or pd.Series(high.iloc[-1], index=high.index))
        self.hmaLow = self.I(lambda: pta.hma(low, length=self.zoneLength) or pd.Series(low.iloc[-1], index=low.index))
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Calculate pivot points
        self.swingHigh = self.I(lambda: pta.pivothigh(high, length=5) or pd.Series(np.nan, index=high.index))
        self.swingLow = self.I(lambda: pta.pivotlow(low, length=5) or pd.Series(np.nan, index=low.index))

    def next(self):
        if len(self.data) < max(self.fastLen, self.slowLen, self.trendLen) + 5:
            return
        
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        
        fastMA_val = self.fastMA[-1]
        slowMA_val = self.slowMA[-1]
        trendMA_val = self.trendMA[-1]
        hmaHigh_val = self.hmaHigh[-1]
        hmaLow_val = self.hmaLow[-1]
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        
        # Calculate resistance and support zones
        resistanceTop = hmaHigh_val + (atr_val * self.zoneDeviation)
        resistanceBottom = hmaHigh_val
        supportTop = hmaLow_val
        supportBottom = hmaLow_val - (atr_val * self.zoneDeviation)
        
        # Trend conditions
        bullTrend = fastMA_val > slowMA_val and close_val > trendMA_val
        bearTrend = fastMA_val < slowMA_val and close_val < trendMA_val
        
        # Signal conditions
        bullSignal = crossover(self.fastMA, self.slowMA) and close_val > trendMA_val
        bearSignal = crossover(self.slowMA, self.fastMA) and close_val < trendMA_val
        
        # Zone touch conditions
        supportTouch = low_val <= supportTop and low_val >= supportBottom and bullTrend
        resistanceTouch = high_val >= resistanceBottom and high_val <= resistanceTop and bearTrend
        
        # Entry and exit logic
        if not self.position:
            if bullSignal or supportTouch:
                self.buy()
            elif bearSignal or resistanceTouch:
                self.sell()
        else:
            # Exit long position
            if self.position.is_long:
                if bearSignal or (high_val >= resistanceBottom and high_val <= resistanceTop):
                    self.position.close()
            # Exit short position
            elif self.position.is_short:
                if bullSignal or (low_val <= supportTop and low_val >= supportBottom):
                    self.position.close()