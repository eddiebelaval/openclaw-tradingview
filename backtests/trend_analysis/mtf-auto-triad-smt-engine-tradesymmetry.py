        prev_velocity = self.velocity[-2] if len(self.velocity) > 1 and not np.isnan(self.velocity[-2]) else 0
        
        if not self.position:
            if prev_velocity <= 0 and current_velocity > 0:
                self.buy()
            elif prev_velocity >= 0 and current_velocity < 0:
                self.sell()
        else:
            if self.position.is_long and prev_velocity > 0 and current_velocity <= 0:
                self.position.close()
