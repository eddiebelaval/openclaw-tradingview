import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    anchor_res = "Daily"
    bins_input = 40
    width_mult = 3.0

    def init(self):
        self.price_history = []
        self.session_start_idx = 0
        self.poc_price = None
        self.node_prices = []
        
    def next(self):
        # Determine if we're in a new period
        current_bar = len(self.data) - 1
        
        # Simple session detection based on bar count
        # For Daily: roughly 252 bars per year, so ~1 bar per day on 1H timeframe
        # This is a simplified approach - in real usage, check actual timestamp
        bars_since_start = current_bar - self.session_start_idx
        
        # Reset on new session (simplified: every 20 bars for demo)
        if bars_since_start > 20 or current_bar == 0:
            self.price_history = []
            self.session_start_idx = current_bar
            self.poc_price = None
            self.node_prices = []
        
        # Accumulate prices
        close_price = self.data.Close[-1]
        self.price_history.append(close_price)
        
        # Calculate profile on last bar of session
        if len(self.price_history) > 10:
            self._calculate_profile()
            self._generate_signals()
    
    def _calculate_profile(self):
        """Calculate price accumulation profile"""
        if len(self.price_history) < 2:
            return
        
        price_array = np.array(self.price_history)
        max_p = np.max(price_array)
        min_p = np.min(price_array)
        range_p = max_p - min_p
        
        if range_p == 0:
            return
        
        bin_size = range_p / self.bins_input
        bin_counts = np.zeros(self.bins_input, dtype=int)
        
        # Populate bins
        for price in price_array:
            bin_idx = int(np.minimum(self.bins_input - 1, 
                         np.floor((price - min_p) / bin_size)))
            if bin_idx >= 0:
                bin_counts[bin_idx] += 1
        
        # Find POC (Point of Control - highest frequency bin)
        max_freq_idx = np.argmax(bin_counts)
        self.poc_price = min_p + (max_freq_idx * bin_size) + (bin_size / 2)
        
        # Find top 4 nodes
        sorted_indices = np.argsort(bin_counts)[::-1]
        self.node_prices = []
        for i in range(min(4, len(sorted_indices))):
            idx = sorted_indices[i]
            if bin_counts[idx] > 0:
                node_price = min_p + (idx * bin_size) + (bin_size / 2)
                self.node_prices.append(node_price)
    
    def _generate_signals(self):
        """Generate trading signals based on profile"""
        if self.poc_price is None:
            return
        
        current_price = self.data.Close[-1]
        
        # Buy signal: price bounces up from POC or lower nodes
        if len(self.node_prices) > 0:
            lowest_node = min(self.node_prices)
            highest_node = max(self.node_prices)
            
            # Buy when price is near support (lower node) and moving up
            if current_price <= lowest_node * 1.01:
                if len(self.data) > 1:
                    prev_price = self.data.Close[-2]
                    if current_price > prev_price and not self.position:
                        self.buy()
            
            # Sell when price reaches resistance (POC or upper node)
            if current_price >= self.poc_price * 0.99:
                if self.position:
                    self.sell()
            elif current_price >= highest_node * 0.99:
                if self.position:
                    self.sell()
        
        # Simple mean reversion: sell when price significantly above POC
        if current_price > self.poc_price * 1.02:
            if self.position:
                self.sell()
        
        # Buy when price significantly below POC
        if current_price < self.poc_price * 0.98:
            if not self.position:
                self.buy()


