        if buy_signal and not self.long_active and not self.short_active:
            self.long_entry = close
            self.long_sl = min(low, lower)
            self.long_risk = self.long_entry - self.long_sl
            self.long_tgt = self.long_entry + self.long_risk * self.rr
            self.long_start_bar = len(self.data)
            self.long_active = True
            self.buy()
        
        # ────── ORIGINAL SHORT ENTRY ──────
        if sell_signal and not self.short_active and not self.long_active:
            self.short_entry = close
            self.short_sl = max(high, upper)
            self.short_risk = self.short_sl - self.short_entry
            self.short_tgt = self.short_entry - self.short_risk * self.rr
            self.short_start_bar = len(self.data)
            self.short_active = True
            self.sell()
        
        # ────── EXTRA LONG ENTRY ──────
