import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Bollinger Bands parameters
    bb_length = 20
    bb_mult = 2.0
    
    # Risk/Reward ratios
    rr = 1.30
    rr_extra = 0.70
    
    # Extra trade parameters
    min_points = 15.0
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Bollinger Bands
        self.basis = self.I(pta.sma, close, length=self.bb_length)
        
        # Calculate standard deviation
        self.stdev = self.I(lambda x: x.rolling(self.bb_length).std(), close)
        
        self.dev = self.bb_mult * self.stdev
        self.upper = self.basis + self.dev
        self.lower = self.basis - self.dev
        
        # BB Percent
        self.bb_percent = self.I(
            lambda c, l, u: (c - l) / (u - l),
            close, self.lower, self.upper
        )
        
        # State variables for original long trade
        self.long_active = False
        self.long_entry = None
        self.long_sl = None
        self.long_tgt = None
        self.long_risk = None
        self.long_start_bar = None
        
        # State variables for original short trade
        self.short_active = False
        self.short_entry = None
        self.short_sl = None
        self.short_tgt = None
        self.short_risk = None
        self.short_start_bar = None
        
        # State variables for extra long trade
        self.long_extra_active = False
        self.long_extra_entry = None
        self.long_extra_sl = None
        self.long_extra_tgt = None
        self.long_extra_risk = None
        self.long_extra_start_bar = None
        
        # State variables for extra short trade
        self.short_extra_active = False
        self.short_extra_entry = None
        self.short_extra_sl = None
        self.short_extra_tgt = None
        self.short_extra_risk = None
        self.short_extra_start_bar = None

    def next(self):
        if len(self.data) < self.bb_length + 1:
            return
        
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        basis = self.basis[-1]
        upper = self.upper[-1]
        lower = self.lower[-1]
        bb_pct = self.bb_percent[-1]
        
        is_green = close > open_price
        is_red = close < open_price
        touch_lower = low <= lower
        touch_upper = high >= upper
        
        green_body = close - open_price
        red_body = open_price - close
        
        # Original signals
        buy_signal = is_green and touch_lower and bb_pct > 0.05
        sell_signal = is_red and touch_upper and bb_pct < 0.95
        
        # Extra signals
        extra_long_signal = is_green and (green_body >= self.min_points) and touch_upper
        extra_short_signal = is_red and (red_body >= self.min_points) and touch_lower
        
