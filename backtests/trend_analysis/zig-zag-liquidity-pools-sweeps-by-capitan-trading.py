class TvStrategy(Strategy):
    # Zig Zag parameters
    deviation_pct = 0.00001
    depth = 3
    
    # Liquidity levels parameters
    left_bars = 6
    right_bars = 4
    
    # Sweep/Mitigation parameters
    candle_type = "Wick"  # "Close" or "Wick"
    wait_confirm = False

    def init(self):
        # We'll track pivot highs and lows manually
        self.high_levels = []
        self.low_levels = []
        self.swept_highs = set()
        self.swept_lows = set()
        
    def next(self):
        # Calculate pivot highs and lows
        if len(self.data) < self.right_bars + self.left_bars + 1:
            return
        
        # Get current and past data
        idx = len(self.data) - 1
        
        # Check for pivot high
        if idx >= self.right_bars + self.left_bars:
            is_pivot_high = True
            current_high = self.data.High[idx - self.right_bars]
            
            # Check left bars
            for i in range(1, self.left_bars + 1):
                if self.data.High[idx - self.right_bars - i] >= current_high:
                    is_pivot_high = False
                    break
            
            # Check right bars
            if is_pivot_high:
                for i in range(1, self.right_bars + 1):
                    if self.data.High[idx - self.right_bars + i] >= current_high:
                        is_pivot_high = False
                        break
            
            if is_pivot_high:
                # Check if level already exists (within tick tolerance)
                level_exists = False
                for level_price, level_idx in self.high_levels:
                    if abs(level_price - current_high) < 0.0001:
                        level_exists = True
                        break
                
                if not level_exists:
                    self.high_levels.append((current_high, idx - self.right_bars))
        
        # Check for pivot low
        if idx >= self.right_bars + self.left_bars:
            is_pivot_low = True
            current_low = self.data.Low[idx - self.right_bars]
            
            # Check left bars
            for i in range(1, self.left_bars + 1):
                if self.data.Low[idx - self.right_bars - i] <= current_low:
                    is_pivot_low = False
                    break
            
            # Check right bars
            if is_pivot_low:
                for i in range(1, self.right_bars + 1):
                    if self.data.Low[idx - self.right_bars + i] <= current_low:
                        is_pivot_low = False
                        break
            
            if is_pivot_low:
                # Check if level already exists
                level_exists = False
