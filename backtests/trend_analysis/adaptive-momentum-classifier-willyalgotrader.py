import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Main Settings
    sensitivity = "Default"
    lookback = 89
    threshold = 0.618
    
    # Feature Engine
    rsi_len = 13
    roc_len = 9
    macd_fast = 12
    macd_slow = 26
    macd_sig = 9
    bb_len = 21
    mfi_len = 13
    obv_smooth = 21
    
    # Filters
    use_vol_regime = True
    use_trend_filter = True
    trend_ema_len = 34
    use_vol_filter = True
    min_accel = 0.02
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume) if len(self.data.Volume) > 0 else pd.Series(0, index=close.index)
        hlc3 = (high + low + close) / 3.0
        
        # Determine effective threshold and lookback based on sensitivity
        if self.sensitivity == "Conservative":
            self.effective_threshold = 0.80
            self.effective_lookback = 150
        elif self.sensitivity == "Aggressive":
            self.effective_threshold = 0.60
            self.effective_lookback = 60
        elif self.sensitivity == "Scalping":
            self.effective_threshold = 0.55
            self.effective_lookback = 40
        else:  # Default
            self.effective_threshold = self.threshold
            self.effective_lookback = self.lookback
        
        self.has_volume = (volume > 0).any()
        self.warmup_bars = max(self.effective_lookback, self.macd_slow, self.trend_ema_len, 50)
        
        # Core indicators
        self.atr = self.I(lambda: pta.atr(high, low, close, length=14) or pd.Series(0, index=close.index))
        self.trend_ema = self.I(lambda: pta.ema(close, length=self.trend_ema_len) or close)
        
        # Axis 1: Momentum (RSI + ROC)
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_len) or pd.Series(50, index=close.index))
        self.roc = self.I(lambda: pta.roc(close, length=self.roc_len) or pd.Series(0, index=close.index))
        
        # Axis 2: Trend (MACD)
        macd_result = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig) or pd.DataFrame(0, index=close.index, columns=['MACD_12_26_9', 'MACDh_12_26_9', 'MACDs_12_26_9']))
        self.macd_hist = self.I(lambda: macd_result.iloc[:, 1] if macd_result is not None and len(macd_result.columns) > 1 else pd.Series(0, index=close.index))
        self.ema_fast = self.I(lambda: pta.ema(close, length=self.macd_fast) or close)
        self.ema_slow = self.I(lambda: pta.ema(close, length=self.macd_slow) or close)
        
        # Axis 3: Volatility (Bollinger Bands)
        self.bb = self.I(lambda: pta.bbands(close, length=self.bb_len, std=2.0) or pd.DataFrame(0, index=close.index, columns=['BBL_21_2.0', 'BBM_21_2.0', 'BBU_21_2.0']))
        self.bb_basis = self.I(lambda: pta.sma(close, length=self.bb_len) or close)
        self.bb_dev = self.I(lambda: close.rolling(self.bb_len).std() or pd.Series(0, index=close.index))
        
        # Axis 4: Flow (MFI + OBV)
        self.mfi = self.I(lambda: pta.mfi(high, low, close, volume, length=self.mfi_len) or pd.Series(50, index=close.index)) if self.has_volume else self.I(lambda: pd.Series(50, index=close.index))
        self.obv = self.I(lambda: pta.obv(close, volume) or pd.Series(0, index=close.index)) if self.has_volume else self.I(lambda: pd.Series(0, index=close.index))
        self.obv_ema = self.I(lambda: pta.ema(self.obv, length=self.obv_smooth) or pd.Series(0, index=close.index)) if self.has_volume else self.I(lambda: pd.Series(0, index=close.index))
        
        # Store data for calculations
        self.close_data = close
        self.high_data = high
        self.low_data = low
        self.volume_data = volume
        self.hlc3_data = hlc3
        
        # Signal tracking
        self.last_signal_dir = 0
        self.last_buy_bar = -1000

    def pct_rank(self, src_series, lookback):
        """Calculate percentile rank (0 to 1) of current value vs lookback window"""
        if len(src_series) < lookback:
            return 0.5
        current = src_series.iloc[-1]
        if pd.isna(current):
            return 0.5
        window = src_series.iloc[-lookback:]
        count = (window < current).sum()
        total = len(window) - window.isna().sum()
        return count / total if total > 0 else 0.5

    def safe_div(self, num, den, fallback=0.0):
        """Safe division avoiding division by zero"""
        if den != 0 and not pd.isna(num) and not pd.isna(den):
            return num / den
        return fallback

    def next(self):
        if len(self) < self.warmup_bars:
            return
        
        idx = len(self) - 1
        
        # Get current values
        close_val = self.close_data.iloc[idx]
        atr_val = self.atr[-1] if not pd.isna(self.atr[-1]) else 0.001
        trend_ema_val = self.trend_ema[-1]
        
        rsi_val = self.rsi[-1] if not pd.isna(self.rsi[-1]) else 50.0
        roc_val = self.roc[-1] if not pd.isna(self.roc[-1]) else 0.0
        
        macd_hist_val = self.macd_hist[-1] if not pd.isna(self.macd_hist[-1]) else 0.0
        ema_fast_val = self.ema_fast[-1]
        ema_slow_val = self.ema_slow[-1]
        
        bb_basis_val = self.bb_basis[-1]
        bb_dev_val = self.bb_dev[-1] if not pd.isna(self.bb_dev[-1]) else 0.001
        bb_upper = bb_basis_val + 2.0 * bb_dev_val
        bb_lower = bb_basis_val - 2.0 * bb_dev_val
        bb_range = bb_upper - bb_lower if bb_upper > bb_lower else 0.001
        bb_pctb = (close_val - bb_lower) / bb_range
        
        # ATR regime
        atr_avg = self.atr.iloc[max(0, idx-self.effective_lookback):idx+1].mean()
        atr_ratio = self.safe_div(atr_val, atr_avg, 1.0)
        
        # Axis calculations
        rsi_for_rank = pd.Series([rsi_val - 50.0])
        pct_rsi = self.pct_rank(self.rsi.iloc[max(0, idx-self.effective_lookback):idx+1] - 50.0, self.effective_lookback)
        pct_roc = self.pct_rank(self.roc.iloc[max(0, idx-self.effective_lookback):idx+1], self.effective_lookback)
        axis_momentum = pct_rsi * 0.6 + pct_roc * 0.4
        
        # EMA slope
        ema_slope = self.safe_div(ema_fast_val - ema_slow_val, max(atr_val, 0.00001), 0.0)
        
        pct_macd = self.pct_rank(self.macd_hist.iloc[max(0, idx-self.effective_lookback):idx+1], self.effective_lookback)
        pct_slope = self.pct_rank(pd.Series([ema_slope]), 1)
        axis_trend = pct_macd * 0.6 + pct_slope * 0.4
        
        # Volatility axis
        vol_position_raw = (bb_pctb - 0.5) * min(atr_ratio, 2.5)
        pct_vol_pos = self.pct_rank(pd.Series([vol_position_raw]), 1)
        axis_volatility = pct_vol_pos
        
        # Flow axis
        mfi_val = self.mfi[-1] if self.has_volume and not pd.isna(self.mfi[-1]) else 50.0
        obv_ema_val = self.obv_ema[-1] if self.has_volume and not pd.isna(self.obv_ema[-1]) else 0.0
        obv_val = self.obv[-1] if self.has_volume and not pd.isna(self.obv[-1]) else 0.0
        obv_slope = self.safe_div(obv_ema_val - (self.obv_ema.iloc[max(0, idx-5)] if idx >= 5 else obv_ema_val), max(abs(obv_ema_val), 1.0), 0.0) if self.has_volume else 0.0
        
        pct_mfi = self.pct_rank(self.mfi.iloc[max(0, idx-self.effective_lookback):idx+1] - 50.0, self.effective_lookback) if self.has_volume else 0.5
        pct_obv_slope = self.pct_rank(pd.Series([obv_slope]), 1) if self.has_volume else 0.5
        axis_flow = (pct_mfi * 0.5 + pct_obv_slope * 0.5) if self.has_volume else 0.5
        
        # Composite score
        w_momentum = 1.0
        w_trend = 1.2
        w_volatility = 0.8
        w_flow = 1.0 if self.has_volume else 0.0
        total_weight = w_momentum + w_trend + w_volatility + w_flow
        
        composite_score = self.safe_div(
            w_momentum * axis_momentum + w_trend * axis_trend + w_volatility * axis_volatility + w_flow * axis_flow,
            total_weight,
            0.5
        )
        
        # Score acceleration
        prev_score = self.I(lambda: pd.Series(composite_score), overlay=False)[-2] if len(self) > 2 else composite_score
        score_accel = composite_score - prev_score
        
        # Feature agreement
        bull_count = 0
        if axis_momentum > 0.6:
            bull_count += 1
        if axis_trend > 0.6:
            bull_count += 1
        if axis_volatility > 0.6:
            bull_count += 1
        if axis_flow > 0.6 and self.has_volume:
            bull_count += 1
        
        bear_count = 0
        if axis_momentum < 0.4:
            bear_count += 1
        if axis_trend < 0.4:
            bear_count += 1
        if axis_volatility < 0.4:
            bear_count += 1
        if axis_flow < 0.4 and self.has_volume:
            bear_count += 1
        
        active_axes = 4 if self.has_volume else 3
        agreement_ratio = self.safe_div(max(bull_count, bear_count) * 1.0, active_axes * 1.0, 0.0)
        
        # Filters
        ema_bullish = close_val > trend_ema_val
        ema_bearish = close_val < trend_ema_val
        trend_allow_long = ema_bullish if self.use_trend_filter else True
        trend_allow_short = ema_bearish if self.use_trend_filter else True
        
        vol_regime_ok = (0.4 < atr_ratio < 3.0) if self.use_vol_regime else True
        
        vol_avg = self.volume_data.iloc[max(0, idx-19):idx+1].mean()
        vol_confirm = (self.volume_data.iloc[idx] > vol_avg * 0.8) if self.use_vol_filter and self.has_volume else True
        
        accel_ok = abs(score_accel) >= self.min_accel
        
        # Raw signals
        prev_composite = composite_score - score_accel if len(self) > 1 else 0.5
        raw_bull_signal = composite_score > self.effective_threshold and prev_composite <= self.effective_threshold and agreement_ratio >= 0.5
        raw_bear_signal = composite_score < (1.0 - self.effective_threshold) and prev_composite >= (1.0 - self.effective_threshold) and agreement_ratio >= 0.5
        
        # Apply filters
        filtered_bull = raw_bull_signal and trend_allow_long and vol_regime_ok and vol_confirm and accel_ok
        filtered_bear = raw_bear_signal and trend_allow_short and vol_regime_ok and vol_confirm and accel_ok
        
        # Direction lock
        buy_condition = filtered_bull and self.last_signal_dir <= 0
        sell_condition = filtered_bear and self.last_signal_dir >= 0
        
        # Execute trades
        if buy_condition:
            if not self.position:
                self.buy()
            self.last_signal_dir = 1
        
        if sell_condition:
            if self.position:
                self.position.close()
            self.last_signal_dir = -1


