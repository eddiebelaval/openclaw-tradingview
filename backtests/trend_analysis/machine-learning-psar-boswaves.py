import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    base_start = 0.02
    base_increment = 0.02
    base_max = 0.1
    use_kmeans = True
    training_period = 100
    choppy_threshold = 0.75
    trending_threshold = 0.25
    use_knn = True
    k_neighbors = 8
    knn_lookback = 200
    min_confidence = 15.0
    use_af_smoothing = True
    af_smooth_alpha = 0.01
    use_kalman = True
