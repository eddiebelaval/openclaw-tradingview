                    h1 = self.bars_since_flip_values[i + 1] / 50.0 if i + 1 < len(self.bars_since_flip_values) else 0
                    h2 = self.last_trend_duration_values[i] / 50.0 if i < len(self.last_trend_duration_values) else 0
                    h3 = self.af_at_last_flip_values[i] / self.base_max if i < len(self.af_at_last_flip_values) else 0
                    h4 = self.flip_frequency_values[i] / 10.0 if i < len(self.flip_frequency_values) else 0
                    h5 = min(self.ep_progress_values[i + 1] if i + 1 < len(self.ep_progress_values) else 0, 5.0) / 5.0

                    dist = np.sqrt((f1 - h1)**2 + (f2 - h2)**2 + (f3 - h3)**2 + (f4 - h4)**2 + (f5 - h5)**2)

