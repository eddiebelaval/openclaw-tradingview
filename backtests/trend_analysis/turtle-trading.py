        self.high_data = high
        self.low_data = low
        self.close_data = close
        
        # Track barssince values
        self.barssince_buysignal = np.zeros(len(self.data))
        self.barssince_sellsignal = np.zeros(len(self.data))
        self.barssince_buyexit = np.zeros(len(self.data))
        self.barssince_sellexit = np.zeros(len(self.data))
        
        self.barssince_buysignal2 = np.zeros(len(self.data))
        self.barssince_sellsignal2 = np.zeros(len(self.data))
        self.barssince_buyexit2 = np.zeros(len(self.data))
        self.barssince_sellexit2 = np.zeros(len(self.data))
        
        self.con_state = 0
        self.prev_lcon = False
        self.prev_scon = False

