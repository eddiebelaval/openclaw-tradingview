import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_period = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # Calculate highest high (20 period) and lowest low (20 period)
        self.upper = self.I(lambda: high.rolling(window=20).max())
        self.lower = self.I(lambda: low.rolling(window=20).min())
        
        # Initialize trend variable
        self.trend = np.zeros(len(self.data))
        
        # Calculate RSI and EMA200 for monitoring
        self.rsi = self.I(pta.rsi, close, length=14)
        self.ema200 = self.I(pta.ema, close, length=200)
        
        # Track previous trend for crossover detection
        self.prev_trend = 0

    def next(self):
        # Calculate current trend
        if len(self.data) < 2:
            return
        
        current_close = self.data.Close[-1]
        prev_close = self.data.Close[-2]
        upper_val = self.upper[-1]
        lower_val = self.lower[-1]
        
        if np.isnan(upper_val) or np.isnan(lower_val):
            return
        
        # Determine trend: 1 for bullish, -1 for bearish
        if current_close > upper_val:
            current_trend = 1
        elif current_close < lower_val:
            current_trend = -1
        else:
            current_trend = self.trend[-2] if len(self.trend) > 1 else 0
        
        self.trend[-1] = current_trend
        
        # Generate signals based on trend crossover
        # Long signal: trend crosses above 0 (from -1 to 1 or 0 to 1)
        if self.prev_trend <= 0 and current_trend > 0:
            self.buy()
        
        # Short signal: trend crosses below 0 (from 1 to -1 or 0 to -1)
        elif self.prev_trend >= 0 and current_trend < 0:
            self.sell()
        
        self.prev_trend = current_trend


