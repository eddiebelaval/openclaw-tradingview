import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaTrendLen = 50
    bbLen = 20
    bbMult = 1.8
    atrLen = 14
    atrMult = 1.8
    rr = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Trend EMA
        self.emaTrend = self.I(pta.ema, close, length=self.emaTrendLen)
        
        # Bollinger Bands for range filter
        self.basis = self.I(pta.sma, close, length=self.bbLen)
        dev = self.bbMult * self.I(lambda x: pta.stdev(x, self.bbLen), close)
        self.upperBB = self.basis + dev
        self.lowerBB = self.basis - dev
        
        # Highest and Lowest for structure break
        self.highestLevel = self.I(lambda: high.rolling(window=self.bbLen).max())
        self.lowestLevel = self.I(lambda: low.rolling(window=self.bbLen).min())
        
        # ATR for stop loss and target
        self.atrVal = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.entry_price = None
        self.stop_loss = None
        self.take_profit = None
        self.entry_type = None

    def next(self):
        close_val = self.data.Close[-1]
        emaTrend_val = self.emaTrend[-1]
        upperBB_val = self.upperBB[-1]
        lowerBB_val = self.lowerBB[-1]
        highestLevel_val = self.highestLevel[-1]
        lowestLevel_val = self.lowestLevel[-1]
        atrVal = self.atrVal[-1]
        
        # Trend filter
        trendUp = close_val > emaTrend_val
        trendDown = close_val < emaTrend_val
        
        # Range filter
        inRange = close_val >= lowerBB_val and close_val <= upperBB_val
        
        # Check if we have valid data for highest/lowest (skip early bars)
        if len(self.data) < self.bbLen + 2:
            return
        
        # Structure break - compare current close with previous highest/lowest
        prev_highestLevel = self.highestLevel[-2]
        prev_lowestLevel = self.lowestLevel[-2]
        
        breakHigh = close_val > prev_highestLevel and self.data.Close[-2] <= prev_highestLevel
        breakLow = close_val < prev_lowestLevel and self.data.Close[-2] >= prev_lowestLevel
        
        # Entry conditions
        longCond = breakHigh and trendUp and not inRange
        shortCond = breakLow and trendDown and not inRange
        
        # Entry logic
        if longCond and not self.position:
            self.entry_price = close_val
            self.entry_type = "long"
            self.stop_loss = self.entry_price - atrVal * self.atrMult
            self.take_profit = self.entry_price + atrVal * self.atrMult * self.rr
            self.buy()
        
        elif shortCond and not self.position:
            self.entry_price = close_val
            self.entry_type = "short"
            self.stop_loss = self.entry_price + atrVal * self.atrMult
            self.take_profit = self.entry_price - atrVal * self.atrMult * self.rr
            self.sell()
        
        # Exit logic
        elif self.position:
            if self.entry_type == "long":
                if close_val <= self.stop_loss or close_val >= self.take_profit:
                    self.position.close()
            elif self.entry_type == "short":
                if close_val >= self.stop_loss or close_val <= self.take_profit:
                    self.position.close()


