import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # CPR Settings
    show_daily_cpr = True
    show_weekly_cpr = True
    show_pdhl = True
    
    # Volume Analysis
    vol_ma_length = 20
    vol_threshold = 1.5
    
    # Divergence Detection
    rsi_length = 14
    pivot_lookback = 5
    show_divergence = True
    
    # Smart Money Concepts
    show_liquidity_sweeps = True
    show_fvg = True
    fvg_threshold = 0.5
    show_order_blocks = True
    ob_strength = 0.3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Daily CPR calculations
        self.d_high = self.I(lambda: pd.Series(self.data.High).shift(1), name='d_high')
        self.d_low = self.I(lambda: pd.Series(self.data.Low).shift(1), name='d_low')
        self.d_close = self.I(lambda: pd.Series(self.data.Close).shift(1), name='d_close')
        
        self.d_pivot = self.I(lambda: (pd.Series(self.data.High).shift(1) + 
                                        pd.Series(self.data.Low).shift(1) + 
                                        pd.Series(self.data.Close).shift(1)) / 3, name='d_pivot')
        self.d_bc = self.I(lambda: (pd.Series(self.data.High).shift(1) + 
                                     pd.Series(self.data.Low).shift(1)) / 2, name='d_bc')
        self.d_tc = self.I(lambda: ((pd.Series(self.data.High).shift(1) + 
                                      pd.Series(self.data.Low).shift(1) + 
                                      pd.Series(self.data.Close).shift(1)) / 3 - 
                                     (pd.Series(self.data.High).shift(1) + 
                                      pd.Series(self.data.Low).shift(1)) / 2) + 
                                    ((pd.Series(self.data.High).shift(1) + 
                                      pd.Series(self.data.Low).shift(1) + 
                                      pd.Series(self.data.Close).shift(1)) / 3), name='d_tc')
        
        self.d_r1 = self.I(lambda: 2 * ((pd.Series(self.data.High).shift(1) + 
                                          pd.Series(self.data.Low).shift(1) + 
                                          pd.Series(self.data.Close).shift(1)) / 3) - 
                                    pd.Series(self.data.High).shift(1), name='d_r1')
        self.d_s1 = self.I(lambda: 2 * ((pd.Series(self.data.High).shift(1) + 
                                          pd.Series(self.data.Low).shift(1) + 
                                          pd.Series(self.data.Close).shift(1)) / 3) - 
                                    pd.Series(self.data.Low).shift(1), name='d_s1')
        
        # Volume indicators
        self.vol_ma = self.I(pta.sma, volume, length=self.vol_ma_length)
        self.is_high_vol = self.I(lambda: volume > self.vol_ma * self.vol_threshold, name='is_high_vol')
        self.is_bullish_bar = self.I(lambda: close > pd.Series(self.data.Open), name='is_bullish_bar')
        
        # RSI for divergence
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Liquidity sweeps
        self.recent_high = self.I(lambda: high.rolling(20).max(), name='recent_high')
        self.recent_low = self.I(lambda: low.rolling(20).min(), name='recent_low')
        
        self.liquidity_sweep_high = self.I(lambda: (high > self.recent_high.shift(1)) & 
                                                     (close < self.recent_high.shift(1)), name='liq_sweep_h')
        self.liquidity_sweep_low = self.I(lambda: (low < self.recent_low.shift(1)) & 
                                                    (close > self.recent_low.shift(1)), name='liq_sweep_l')
        
        # Fair Value Gaps
        self.bullish_fvg = self.I(lambda: (low > high.shift(2)) & 
                                           (close.shift(1) > high.shift(2)), name='bull_fvg')
        self.bearish_fvg = self.I(lambda: (high < low.shift(2)) & 
                                           (close.shift(1) < low.shift(2)), name='bear_fvg')
        
        # Order Blocks
        self.bullish_ob = self.I(lambda: (close.shift(2) < pd.Series(self.data.Open).shift(2)) &
                                          (close.shift(1) < pd.Series(self.data.Open).shift(1)) &
                                          (close > pd.Series(self.data.Open)), name='bull_ob')
        self.bearish_ob = self.I(lambda: (close.shift(2) > pd.Series(self.data.Open).shift(2)) &
                                          (close.shift(1) > pd.Series(self.data.Open).shift(1)) &
                                          (close < pd.Series(self.data.Open)), name='bear_ob')
        
        # Track position state
        self.in_trade = False
        self.last_signal_bar = -100

    def next(self):
        if len(self) < self.pivot_lookback + 5:
            return
        
        # Current values
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        vol_val = self.data.Volume[-1]
        
        d_pivot_val = self.d_pivot[-1]
        d_r1_val = self.d_r1[-1]
        d_s1_val = self.d_s1[-1]
        
        rsi_val = self.rsi[-1]
        
        is_high_vol_val = vol_val > self.vol_ma[-1] * self.vol_threshold
        is_bullish = self.data.Close[-1] > self.data.Open[-1]
        
        bullish_fvg_val = self.bullish_fvg[-1] if not pd.isna(self.bullish_fvg[-1]) else False
        bearish_fvg_val = self.bearish_fvg[-1] if not pd.isna(self.bearish_fvg[-1]) else False
        
        liq_sweep_high_val = self.liquidity_sweep_high[-1] if not pd.isna(self.liquidity_sweep_high[-1]) else False
        liq_sweep_low_val = self.liquidity_sweep_low[-1] if not pd.isna(self.liquidity_sweep_low[-1]) else False
        
        bullish_ob_val = self.bullish_ob[-1] if not pd.isna(self.bullish_ob[-1]) else False
        bearish_ob_val = self.bearish_ob[-1] if not pd.isna(self.bearish_ob[-1]) else False
        
        # Buy conditions: Multiple bullish signals
        buy_signal = False
        if len(self) - self.last_signal_bar >= 5:
            # Condition 1: Price crosses above daily pivot with high volume
            if crossover(close_val, d_pivot_val) and is_high_vol_val:
                buy_signal = True
            
            # Condition 2: Bullish FVG with liquidity sweep low
            if bullish_fvg_val and liq_sweep_low_val and close_val > d_pivot_val:
                buy_signal = True
            
            # Condition 3: Bullish order block with RSI confirmation
            if bullish_ob_val and rsi_val < 70 and rsi_val > 40:
                buy_signal = True
            
            # Condition 4: Price bounces from daily support with high volume
            if close_val > d_s1_val and close_val[-1] <= d_s1_val and is_high_vol_val:
                buy_signal = True
        
        # Sell conditions: Multiple bearish signals
        sell_signal = False
        if len(self) - self.last_signal_bar >= 5:
            # Condition 1: Price crosses below daily pivot with high volume
            if crossover(d_pivot_val, close_val) and is_high_vol_val:
                sell_signal = True
            
            # Condition 2: Bearish FVG with liquidity sweep high
            if bearish_fvg_val and liq_sweep_high_val and close_val < d_pivot_val:
                sell_signal = True
            
            # Condition 3: Bearish order block with RSI confirmation
            if bearish_ob_val and rsi_val > 30 and rsi_val < 60:
                sell_signal = True
            
            # Condition 4: Price rejects from daily resistance with high volume
            if close_val < d_r1_val and close_val[-1] >= d_r1_val and is_high_vol_val:
                sell_signal = True
        
        # Execute trades
        if buy_signal and not self.position:
            self.buy()
            self.in_trade = True
            self.last_signal_bar = len(self)
        
        if sell_signal and self.position:
            self.position.close()
            self.in_trade = False
            self.last_signal_bar = len(self)
        
        # Exit conditions
        if self.position:
            # Exit long if price breaks below support significantly
            if close_val < d_s1_val * 0.98:
                self.position.close()
                self.in_trade = False
            
            # Exit long if RSI becomes overbought
            if rsi_val > 80:
                self.position.close()
                self.in_trade = False
            
            # Exit long after holding for 50 bars without profit
            if len(self) - self.last_signal_bar > 50 and self.position.pl <= 0:
                self.position.close()
                self.in_trade = False


