import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 15
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.pivot_high = self.I(lambda: self._pivot_high(high, self.length))
        self.pivot_low = self.I(lambda: self._pivot_low(low, self.length))
        
        self.daily_high = self.I(lambda: self._daily_high(high))
        self.daily_low = self.I(lambda: self._daily_low(low))
        self.weekly_high = self.I(lambda: self._weekly_high(high))
        self.weekly_low = self.I(lambda: self._weekly_low(low))
        
        self.in_long = False
        self.in_short = False
    
    def _pivot_high(self, high, length):
        result = pd.Series(np.nan, index=high.index)
        for i in range(length, len(high) - length):
            if high.iloc[i] == high.iloc[i-length:i+length+1].max():
                result.iloc[i] = high.iloc[i]
        return result
    
    def _pivot_low(self, low, length):
        result = pd.Series(np.nan, index=low.index)
        for i in range(length, len(low) - length):
            if low.iloc[i] == low.iloc[i-length:i+length+1].min():
                result.iloc[i] = low.iloc[i]
        return result
    
    def _daily_high(self, high):
        df = pd.DataFrame({'high': high})
        df['date'] = pd.to_datetime(range(len(df)), unit='D')
        df['day'] = df['date'].dt.date
        daily_max = df.groupby('day')['high'].transform('max')
        return pd.Series(daily_max.values, index=high.index)
    
    def _daily_low(self, low):
        df = pd.DataFrame({'low': low})
        df['date'] = pd.to_datetime(range(len(df)), unit='D')
        df['day'] = df['date'].dt.date
        daily_min = df.groupby('day')['low'].transform('min')
        return pd.Series(daily_min.values, index=low.index)
    
    def _weekly_high(self, high):
        df = pd.DataFrame({'high': high})
        df['date'] = pd.to_datetime(range(len(df)), unit='D')
        df['week'] = df['date'].dt.isocalendar().week
        weekly_max = df.groupby('week')['high'].transform('max')
        return pd.Series(weekly_max.values, index=high.index)
    
    def _weekly_low(self, low):
        df = pd.DataFrame({'low': low})
        df['date'] = pd.to_datetime(range(len(df)), unit='D')
        df['week'] = df['date'].dt.isocalendar().week
        weekly_min = df.groupby('week')['low'].transform('min')
        return pd.Series(weekly_min.values, index=low.index)
    
