import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 10
    mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate pivot highs and lows
        self.ph = self.I(self._pivot_high, high, self.len)
        self.pl = self.I(self._pivot_low, low, self.len)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=200)
        
        # Calculate h1 and l1 from pivots
        self.h1_series = self.I(self._get_h1, high, self.ph)
        self.l1_series = self.I(self._get_l1, low, self.pl)
        
        # Calculate mid line
        self.m = self.I(self._calc_mid, self.h1_series, self.l1_series, atr, self.len, self.mult)
        
        # Calculate upper and lower bands
        self.h = self.I(self._calc_upper, self.m, atr, self.len, self.mult)
        self.l = self.I(self._calc_lower, self.m, atr, self.len, self.mult)
        
        # Track trend
        self.trend = np.full(len(self.data), np.nan)
        self.sig_up = np.full(len(self.data), False)
        self.sig_dn = np.full(len(self.data), False)

    def _pivot_high(self, high, period):
        result = pd.Series(np.nan, index=high.index)
        for i in range(period, len(high) - period):
            if high.iloc[i] == high.iloc[i-period:i+period+1].max():
                result.iloc[i] = high.iloc[i]
        return result

    def _pivot_low(self, low, period):
        result = pd.Series(np.nan, index=low.index)
        for i in range(period, len(low) - period):
            if low.iloc[i] == low.iloc[i-period:i+period+1].min():
                result.iloc[i] = low.iloc[i]
        return result

    def _get_h1(self, high, ph):
        h1 = pd.Series(np.nan, index=high.index)
        last_h1 = np.nan
        for i in range(len(ph)):
            if not np.isnan(ph.iloc[i]):
                last_h1 = high.iloc[i]
            h1.iloc[i] = last_h1
        return h1

    def _get_l1(self, low, pl):
        l1 = pd.Series(np.nan, index=low.index)
        last_l1 = np.nan
        for i in range(len(pl)):
            if not np.isnan(pl.iloc[i]):
                last_l1 = low.iloc[i]
            l1.iloc[i] = last_l1
        return l1

    def _calc_mid(self, h1, l1, atr, period, mult):
        avg_hl = (h1 + l1) / 2
        m = pta.sma(avg_hl, length=period)
        return m

    def _calc_upper(self, m, atr, period, mult):
        atr_scaled = atr * mult
        h = pta.sma(m + atr_scaled, length=period * 2)
        return h

    def _calc_lower(self, m, atr, period, mult):
        atr_scaled = atr * mult
        l = pta.sma(m - atr_scaled, length=period * 2)
        return l

    def next(self):
        idx = len(self) - 1
        
        if idx < self.len * 3:
            return
        
        # Get current values
        curr_high = self.data.High[-1]
        curr_low = self.data.Low[-1]
        curr_close = self.data.Close[-1]
        
        h_val = self.h[-1] if not np.isnan(self.h[-1]) else curr_high
        l_val = self.l[-1] if not np.isnan(self.l[-1]) else curr_low
        m_val = self.m[-1] if not np.isnan(self.m[-1]) else curr_close
        
        prev_h_val = self.h[-2] if len(self.h) > 1 and not np.isnan(self.h[-2]) else curr_high
        prev_l_val = self.l[-2] if len(self.l) > 1 and not np.isnan(self.l[-2]) else curr_low
        prev_trend = self.trend[idx - 1] if idx > 0 and not np.isnan(self.trend[idx - 1]) else None
        
        # Detect crossovers
        cross_up = curr_high > h_val and (idx == 0 or self.data.High[-2] <= prev_h_val)
        cross_dn = curr_low < l_val and (idx == 0 or self.data.Low[-2] >= prev_l_val)
        
        # Update trend
        if cross_up:
            self.trend[idx] = True
            if prev_trend is False or prev_trend is None:
                self.sig_up[idx] = True
        elif cross_dn:
            self.trend[idx] = False
            if prev_trend is True or prev_trend is None:
                self.sig_dn[idx] = True
        else:
            self.trend[idx] = prev_trend if prev_trend is not None else (curr_close > m_val)
        
        # Trading logic
        if self.sig_up[idx] and not self.position:
            self.buy()
        elif self.sig_dn[idx] and self.position:
            self.sell()


