import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    zigzag_length = 21
    divergence_length = 21
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI manually
        self.rsi = self.I(self._calculate_rsi, close, self.rsi_length)
        
        # Calculate pivot highs and lows
        self.pivot_high = self.I(self._pivot_high, high, self.zigzag_length, self.zigzag_length)
        self.pivot_low = self.I(self._pivot_low, low, self.zigzag_length, self.zigzag_length)
        
        # Track divergence signals
        self.div_long_signal = False
        self.div_short_signal = False
        self.last_pivot_high_idx = -1
        self.last_pivot_high_val = 0
        self.last_pivot_low_idx = -1
        self.last_pivot_low_val = 0
        
    def _calculate_rsi(self, close, length):
        delta = close.diff()
        gain = (delta.where(delta > 0, 0)).rolling(window=length).mean()
        loss = (-delta.where(delta < 0, 0)).rolling(window=length).mean()
        rs = gain / loss.replace(0, 1e-10)
        rsi = 100 - (100 / (1 + rs))
        return rsi.fillna(50)
    
    def _pivot_high(self, high, left_bars, right_bars):
        pivot = pd.Series(index=high.index, dtype=float)
        for i in range(left_bars, len(high) - right_bars):
            if high.iloc[i] == high.iloc[max(0, i - left_bars):i + right_bars + 1].max():
                pivot.iloc[i] = 1
        return pivot.fillna(0)
    
    def _pivot_low(self, low, left_bars, right_bars):
        pivot = pd.Series(index=low.index, dtype=float)
        for i in range(left_bars, len(low) - right_bars):
            if low.iloc[i] == low.iloc[max(0, i - left_bars):i + right_bars + 1].min():
                pivot.iloc[i] = 1
        return pivot.fillna(0)
    
    def next(self):
        current_bar = len(self.data) - 1
        
        if current_bar < self.divergence_length * 2:
            return
        
        rsi_val = self.rsi[-1]
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        
        # Detect new pivot highs
        if self.pivot_high[-1] > 0:
            if self.last_pivot_high_idx > 0:
                prev_rsi_ph = self.rsi[self.last_pivot_high_idx]
                prev_close_ph = self.data.Close[self.last_pivot_high_idx]
                
                # Bearish divergence: RSI lower high but price higher high
                if rsi_val < prev_rsi_ph and high_val > prev_close_ph and rsi_val >= 65:
                    self.div_short_signal = True
            
            self.last_pivot_high_idx = current_bar
            self.last_pivot_high_val = rsi_val
        
        # Detect new pivot lows
        if self.pivot_low[-1] > 0:
            if self.last_pivot_low_idx > 0:
                prev_rsi_pl = self.rsi[self.last_pivot_low_idx]
                prev_close_pl = self.data.Close[self.last_pivot_low_idx]
                
                # Bullish divergence: RSI higher low but price lower low
                if rsi_val > prev_rsi_pl and low_val < prev_close_pl and rsi_val <= 35:
                    self.div_long_signal = True
            
            self.last_pivot_low_idx = current_bar
            self.last_pivot_low_val = rsi_val
        
        # Execute trades based on divergence signals
        if self.div_long_signal and not self.position:
            self.buy()
            self.div_long_signal = False
        elif self.div_short_signal and self.position:
            self.sell()
            self.div_short_signal = False
        
        # Alternative exit: RSI overbought/oversold cross
        if self.position:
            if crossover(self.rsi, 70):
                self.sell()
        else:
            if crossover(30, self.rsi):
                self.buy()


