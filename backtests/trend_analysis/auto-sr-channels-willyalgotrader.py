        for i in range(sz - 1, max(-1, sz - pairs_to_check - 1), -1):
            for j in range(i - 1, max(-1, i - 6), -1):
                ix1 = self.pivot_low_indices[j]
                iy1 = self.pivot_lows[j]
                ix2 = self.pivot_low_indices[i]
                iy2 = self.pivot_lows[i]
                
                span = ix2 - ix1
                if span < self.min_channel_bars or span > self.max_channel_bars:
                    continue
                if iy2 <= iy1:
                    continue
                
                max_off = 0.0
                if len(self.pivot_highs) > 0:
                    for k in range(len(self.pivot_highs)):
                        opp_bar = self.pivot_high_indices[k]
                        if opp_bar >= ix1 and opp_bar <= len(self.data) - 1:
                            opp_val = self.pivot_highs[k]
                            base_at_opp = self.line_price(ix1, iy1, ix2, iy2, opp_bar)
