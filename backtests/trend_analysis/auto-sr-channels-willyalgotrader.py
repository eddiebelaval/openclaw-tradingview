class TvStrategy(Strategy):
    pivot_len = 21
    atr_len = 14
    min_channel_bars = 10
    max_channel_bars = 400
    channel_quality = 0.55

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        self.pivot_highs = []
        self.pivot_lows = []
        self.pivot_high_indices = []
        self.pivot_low_indices = []
        
        self.up_channel_active = False
        self.down_channel_active = False
        self.up_channel_params = {}
        self.down_channel_params = {}
        
        self.up_bull_fired = False
        self.up_bear_fired = False
        self.down_bull_fired = False
        self.down_bear_fired = False
        
        self.last_signal = None

    def detect_pivots(self, idx):
        if idx < self.pivot_len * 2:
            return
        
        high = self.data.High
        low = self.data.Low
        
        lookback = self.pivot_len
        lookahead = self.pivot_len
        
        if idx - lookback < 0 or idx + lookahead >= len(high):
            return
        
        is_pivot_high = True
        is_pivot_low = True
        
        for i in range(max(0, idx - lookback), min(len(high), idx + lookahead + 1)):
            if i == idx:
                continue
            if high[i] > high[idx]:
                is_pivot_high = False
            if low[i] < low[idx]:
                is_pivot_low = False
        
        if is_pivot_high and len(self.pivot_highs) < 40:
            self.pivot_highs.append(high[idx])
            self.pivot_high_indices.append(idx)
            if len(self.pivot_highs) > 40:
                self.pivot_highs.pop(0)
                self.pivot_high_indices.pop(0)
        
        if is_pivot_low and len(self.pivot_lows) < 40:
            self.pivot_lows.append(low[idx])
            self.pivot_low_indices.append(idx)
            if len(self.pivot_lows) > 40:
                self.pivot_lows.pop(0)
                self.pivot_low_indices.pop(0)

    def line_price(self, x1, y1, x2, y2, bx):
        if x2 == x1:
            return y1
        return y1 + (y2 - y1) / (x2 - x1) * (bx - x1)

