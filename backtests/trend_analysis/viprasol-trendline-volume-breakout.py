import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trendline Detection
    pivot_len = 3
    slope_factor = 1.05
    
    # Breakout Settings
    breakout_pct = 3.0
    
    # Volume Confirmation
    vol_surge_pct = 50.0
    require_vol = True
    vol_ma_period = 20
    
    # TP / SL
    sl_atr_mult = 1.5
    tp1_rr = 1.5
    tp2_rr = 2.5
    
    # Retest Detection
    show_retest = True
    retest_window = 10
    retest_tolerance = 0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate indicators
        self.atr = self.I(pta.atr, high, low, close, length=14)
        self.vol_ma = self.I(pta.sma, volume, length=self.vol_ma_period)
        
        # Pivot highs and lows using rolling max/min
        self.pivot_high = self.I(lambda: high.rolling(window=self.pivot_len * 2 + 1, center=True).max())
        self.pivot_low = self.I(lambda: low.rolling(window=self.pivot_len * 2 + 1, center=True).min())
        
        # Track trendline segments
        self.bear_segments = []
        self.bull_segments = []
        
        self.prev_bear_pivot_bar = None
        self.prev_bear_pivot_price = None
        self.prev_bull_pivot_bar = None
        self.prev_bull_pivot_price = None
        
        self.total_bear_breakouts = 0
        self.total_bull_breakouts = 0
        self.last_breakout_score = 0
        self.last_breakout_dir = 0
        
        self.in_trade = False
        self.entry_price = None
        self.sl_price = None
        self.tp1_price = None
        self.tp2_price = None

    def detect_pivots(self):
        """Detect pivot points in current bar"""
        idx = len(self.data) - 1
        
        if idx < self.pivot_len:
            return None, None
        
        left_idx = idx - self.pivot_len
        right_idx = idx + self.pivot_len
        
        if right_idx > len(self.data) - 1:
            return None, None
        
        # Check if current bar is pivot high
        current_high = self.data.High[idx]
        is_pivot_high = all(
            current_high >= self.data.High[i] 
            for i in range(max(0, idx - self.pivot_len), min(len(self.data), idx + self.pivot_len + 1))
        )
        
        # Check if current bar is pivot low
        current_low = self.data.Low[idx]
        is_pivot_low = all(
            current_low <= self.data.Low[i] 
            for i in range(max(0, idx - self.pivot_len), min(len(self.data), idx + self.pivot_len + 1))
        )
        
        pivot_high = current_high if is_pivot_high else None
        pivot_low = current_low if is_pivot_low else None
        
        return pivot_high, pivot_low

    def calc_breakout_score(self, trend_age, has_vol_surge, slope_abs):
        """Calculate breakout quality score (0-10)"""
        score = 0
        
        # Trendline age: older = more significant
        if trend_age > 50:
            score += 3
        elif trend_age > 25:
            score += 2
        elif trend_age > 10:
            score += 1
        
        # Volume surge
        if has_vol_surge:
            score += 3
        
        # Slope steepness
        if slope_abs > 0.002:
            score += 2
        elif slope_abs > 0.001:
            score += 1
        
        # Body ratio
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_p = self.data.Open[-1]
        close_p = self.data.Close[-1]
        
        if high - low > 0:
            body_ratio = abs(close_p - open_p) / (high - low)
            if body_ratio > 0.65:
                score += 2
        
        return min(score, 10)

    def check_vol_surge(self):
        """Check if volume surge condition is met"""
        idx = len(self.data) - 1
        if idx < self.vol_ma_period:
            return False
        
        current_vol = self.data.Volume[idx]
        vol_ma = self.vol_ma[-1]
        
        if vol_ma <= 0:
            return False
        
        vol_surge_pct = abs((current_vol - vol_ma) * 100.0 / vol_ma)
        return current_vol > vol_ma * (1.0 + self.vol_surge_pct / 100.0)

    def detect_bearish_trendlines(self):
        """Detect descending trendlines from pivot highs"""
        pivot_high, _ = self.detect_pivots()
        
        if pivot_high is None:
            return
        
        idx = len(self.data) - 1 - self.pivot_len
        
        if self.prev_bear_pivot_bar is None:
            self.prev_bear_pivot_bar = idx
            self.prev_bear_pivot_price = pivot_high
        else:
            l_bar = self.prev_bear_pivot_bar
            l_price = self.prev_bear_pivot_price
            r_bar = idx
            r_price = pivot_high
            
            if l_price / r_price > self.slope_factor:
                # Valid trendline - descending
                segment = {
                    'left_bar': l_bar,
                    'left_price': l_price,
                    'right_bar': r_bar,
                    'right_price': r_price,
                    'direction': -1,  # bearish
                    'is_active': True,
                    'breakout_bar': None,
                    'breakout_price': None,
                }
                self.bear_segments.append(segment)
            
            self.prev_bear_pivot_bar = idx
            self.prev_bear_pivot_price = pivot_high

    def detect_bullish_trendlines(self):
        """Detect ascending trendlines from pivot lows"""
        _, pivot_low = self.detect_pivots()
        
        if pivot_low is None:
            return
        
        idx = len(self.data) - 1 - self.pivot_len
        
        if self.prev_bull_pivot_bar is None:
            self.prev_bull_pivot_bar = idx
            self.prev_bull_pivot_price = pivot_low
        else:
            l_bar = self.prev_bull_pivot_bar
            l_price = self.prev_bull_pivot_price
            r_bar = idx
            r_price = pivot_low
            
            if r_price / l_price > self.slope_factor:
                # Valid trendline - ascending
                segment = {
                    'left_bar': l_bar,
                    'left_price': l_price,
                    'right_bar': r_bar,
                    'right_price': r_price,
                    'direction': 1,  # bullish
                    'is_active': True,
                    'breakout_bar': None,
                    'breakout_price': None,
                }
                self.bull_segments.append(segment)
            
            self.prev_bull_pivot_bar = idx
            self.prev_bull_pivot_price = pivot_low

    def check_bearish_breakout(self):
        """Check for bearish trendline (bullish) breakout"""
        idx = len(self.data) - 1
        current_bar = idx
        close = self.data.Close[idx]
        
        for seg in self.bear_segments:
            if not seg['is_active']:
                continue
            
            slope = (seg['right_price'] - seg['left_price']) / (seg['right_bar'] - seg['left_bar'])
            projected = seg['left_price'] + slope * (current_bar - seg['left_bar'])
            
            breakout_mult = 1.0 + self.breakout_pct / 100.0
            breakout = close > projected * breakout_mult
            
            vol_gate_ok = self.check_vol_surge() if self.require_vol else True
            
            if breakout and vol_gate_ok:
                seg['is_active'] = False
                seg['breakout_bar'] = current_bar
                seg['breakout_price'] = projected
                
                trend_age = current_bar - seg['left_bar']
                slope_abs = abs(slope) / seg['left_price'] if seg['left_price'] != 0 else 0
                score = self.calc_breakout_score(trend_age, vol_gate_ok, slope_abs)
                
                self.total_bear_breakouts += 1
                self.last_breakout_score = score
                self.last_breakout_dir = 1  # bullish signal
                
                return True, score, projected
        
        return False, 0, None

    def check_bullish_breakout(self):
        """Check for bullish trendline (bearish) breakout"""
        idx = len(self.data) - 1
        current_bar = idx
        close = self.data.Close[idx]
        
        for seg in self.bull_segments:
            if not seg['is_active']:
                continue
            
            slope = (seg['right_price'] - seg['left_price']) / (seg['right_bar'] - seg['left_bar'])
            projected = seg['left_price'] + slope * (current_bar - seg['left_bar'])
            
            breakout_mult = 1.0 + self.breakout_pct / 100.0
            breakout = close < projected / breakout_mult
            
            vol_gate_ok = self.check_vol_surge() if self.require_vol else True
            
            if breakout and vol_gate_ok:
                seg['is_active'] = False
                seg['breakout_bar'] = current_bar
                seg['breakout_price'] = projected
                
                trend_age = current_bar - seg['left_bar']
                slope_abs = abs(slope) / seg['left_price'] if seg['left_price'] != 0 else 0
                score = self.calc_breakout_score(trend_age, vol_gate_ok, slope_abs)
                
                self.total_bull_breakouts += 1
                self.last_breakout_score = score
                self.last_breakout_dir = -1  # bearish signal
                
                return True, score, projected
        
        return False, 0, None

    def next(self):
        # Detect trendlines
        self.detect_bearish_trendlines()
        self.detect_bullish_trendlines()
        
        # Check for breakouts
        bear_bo, bear_score, bear_proj = self.check_bearish_breakout()
        bull_bo, bull_score, bull_proj = self.check_bullish_breakout()
        
        # Trading logic
        if not self.in_trade:
            # Bullish signal from bearish trendline breakout
            if bear_bo and self.last_breakout_score >= 3:
                if self.atr[-1] > 0:
                    self.entry_price = self.data.Close[-1]
                    self.sl_price = self.entry_price - (self.atr[-1] * self.sl_atr_mult)
                    self.tp1_price = self.entry_price + (self.atr[-1] * self.sl_atr_mult * self.tp1_rr)
                    self.tp2_price = self.entry_price + (self.atr[-1] * self.sl_atr_mult * self.tp2_rr)
                    self.buy()
                    self.in_trade = True
            
            # Bearish signal from bullish trendline breakout
            elif bull_bo and self.last_breakout_score >= 3:
                if self.atr[-1] > 0:
                    self.entry_price = self.data.Close[-1]
                    self.sl_price = self.entry_price + (self.atr[-1] * self.sl_atr_mult)
                    self.tp1_price = self.entry_price - (self.atr[-1] * self.sl_atr_mult * self.tp1_rr)
                    self.tp2_price = self.entry_price - (self.atr[-1] * self.sl_atr_mult * self.tp2_rr)
                    self.sell()
                    self.in_trade = True
        else:
            # Exit logic
            if self.position.is_long:
                # Exit long on SL or TP
                if self.data.Low[-1] <= self.sl_price or self.data.High[-1] >= self.tp2_price:
                    self.position.close()
                    self.in_trade = False
            elif self.position.is_short:
                # Exit short on SL or TP
                if self.data.High[-1] >= self.sl_price or self.data.Low[-1] <= self.tp2_price:
                    self.position.close()
                    self.in_trade = False


