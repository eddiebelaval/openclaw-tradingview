import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    LookbackPeriod = 15
    MomentumDays = 12
    VolIncreasePct = 20
    PriceIncreasePct = 20
    VolMA_Length = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate indicators
        self.ema10 = self.I(pta.ema, close, length=10)
        self.ema21 = self.I(pta.ema, close, length=21)
        self.sma50 = self.I(pta.sma, close, length=50)
        self.atr14 = self.I(pta.atr, high, low, close, length=14)
        
        # Volume indicators
        self.vol_sma_short = self.I(pta.sma, volume, length=self.LookbackPeriod)
        self.vol_sma_long = self.I(pta.sma, volume, length=self.VolMA_Length)
        
        # Green days counter - rolling sum of close > close[1]
        def count_green_days():
            green = (close > close.shift(1)).astype(int)
            return green.rolling(window=self.LookbackPeriod).sum()
        
        self.green_days_count = self.I(count_green_days)
        
        # Price change percentage over lookback period
        def price_change():
            return ((close - close.shift(self.LookbackPeriod)) / close.shift(self.LookbackPeriod)) * 100
        
        self.price_change_pct = self.I(price_change)
        
        # Volume change percentage
        def volume_change():
            vol_short = self.vol_sma_short
            vol_long = self.vol_sma_long
            result = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if vol_long.iloc[i] != 0:
                    result.iloc[i] = ((vol_short.iloc[i] - vol_long.iloc[i]) / vol_long.iloc[i]) * 100
                else:
                    result.iloc[i] = 0
            return result
        
        self.vol_change_pct = self.I(volume_change)

    def next(self):
        if len(self.data) < max(self.LookbackPeriod, self.VolMA_Length, 50):
            return
        
        # Check conditions
        green_days = self.green_days_count[-1]
        is_momentum = green_days >= self.MomentumDays
        
        vol_change = self.vol_change_pct[-1]
        is_volume = vol_change >= self.VolIncreasePct
        
        price_change = self.price_change_pct[-1]
        is_price = price_change >= self.PriceIncreasePct
        
        # Ant color logic
        is_green_ant = is_momentum and is_volume and is_price
        is_yellow_ant = is_momentum and is_volume and not is_price
        is_blue_ant = is_momentum and is_price and not is_volume
        is_gray_ant = is_momentum and not is_volume and not is_price
        
        # Entry signal: Any ant color (momentum detected)
        ant_detected = is_green_ant or is_yellow_ant or is_blue_ant or is_gray_ant
        
        # Exit signal: Loss of momentum or price decline
        if not self.position:
            if ant_detected:
                self.buy()
        else:
            # Exit if momentum breaks (green days drop below threshold)
            if not is_momentum:
                self.sell()
            # Also exit if price drops below 21 EMA (trend break)
            elif self.data.Close[-1] < self.ema21[-1]:
                self.sell()