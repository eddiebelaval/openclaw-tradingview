import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_fast_len = 5
    ema_mid_len = 8
    ema_slow_len = 13
    touch_buffer_ticks = 2
    use_vol_confirm = True
    stop_buffer_ticks = 2
    max_stop_ticks = 40
    take_profit_ticks = 40
    max_vwap_crosses = 4
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMAs
        self.ema5 = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema8 = self.I(pta.ema, close, length=self.ema_mid_len)
        self.ema13 = self.I(pta.ema, close, length=self.ema_slow_len)
        
        # NYSE Open VWAP (anchored at session start)
        self.open_vwap = self.I(self._calc_open_vwap, close, high, low, volume)
        
        # 18:00-16:00 VWAP
        self.vwap_1800 = self.I(self._calc_1800_vwap, close, high, low, volume)
        
        # Volume confirmation
        self.vol_highest = self.I(lambda: volume.rolling(2).max())
        
        # State tracking
        self.pending_long = False
        self.pending_short = False
        self.long_setup_high = None
        self.long_setup_low = None
        self.short_setup_high = None
        self.short_setup_low = None
        self.vwap_cross_count = 0
        self.reclaimed_long = False
        self.reclaimed_short = False
        self.below_count = 0
        self.above_count = 0
        
    def _calc_open_vwap(self, close, high, low, volume):
        hlc3 = (high + low + close) / 3
        cum_pv = (hlc3 * volume).cumsum()
        cum_v = volume.cumsum()
        vwap = cum_pv / cum_v
        return vwap
    
    def _calc_1800_vwap(self, close, high, low, volume):
        hlc3 = (high + low + close) / 3
        cum_pv = (hlc3 * volume).cumsum()
        cum_v = volume.cumsum()
        vwap = cum_pv / cum_v
        return vwap
    
    def next(self):
        if len(self) < self.ema_slow_len:
            return
            
        tick = 0.01
        buf = self.touch_buffer_ticks * tick
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        ema5_val = self.ema5[-1] if self.ema5[-1] else None
        ema8_val = self.ema8[-1] if self.ema8[-1] else None
        ema13_val = self.ema13[-1] if self.ema13[-1] else None
        open_vwap_val = self.open_vwap[-1] if self.open_vwap[-1] else None
        vol_highest = self.vol_highest[-1] if self.vol_highest[-1] else 0
        
        if any(v is None for v in [ema5_val, ema8_val, ema13_val, open_vwap_val]):
            return
        
        # EMA curl confluence
        ema_long_ok = (ema5_val > ema8_val and ema8_val > ema13_val and 
                       ema5_val > self.ema5[-2] and ema8_val > self.ema8[-2] and ema13_val > self.ema13[-2])
        ema_short_ok = (ema5_val < ema8_val and ema8_val < ema13_val and 
                        ema5_val < self.ema5[-2] and ema8_val < self.ema8[-2] and ema13_val < self.ema13[-2])
        
        # Reclaim logic
        close_above_vwap = close > open_vwap_val
        close_below_vwap = close < open_vwap_val
        
        self.above_count = (self.above_count + 1) if close_above_vwap else 0
        self.below_count = (self.below_count + 1) if close_below_vwap else 0
        
        accept_above_vwap = self.above_count >= 2
        accept_below_vwap = self.below_count >= 2
        
        if len(self) > 1:
            reclaim_long = close_above_vwap and (self.data.Close[-2] > open_vwap_val or close_above_vwap)
            reclaim_short = close_below_vwap and (self.data.Close[-2] < open_vwap_val or close_below_vwap)
        else:
            reclaim_long = close_above_vwap
            reclaim_short = close_below_vwap
        
        if accept_below_vwap:
            self.reclaimed_long = False
        elif reclaim_long:
            self.reclaimed_long = True
            
        if accept_above_vwap:
            self.reclaimed_short = False
        elif reclaim_short:
            self.reclaimed_short = True
        
        # Volume confirmation
        vol_ok = not self.use_vol_confirm or (volume > vol_highest)
        
        # VWAP crosses
        if len(self) > 1:
            cross_up = crossover(self.data.Close, self.open_vwap)
            cross_down = crossover(self.open_vwap, self.data.Close)
            if cross_up:
                self.vwap_cross_count += 1
            elif cross_down:
                self.vwap_cross_count += 1
        else:
            cross_up = False
            cross_down = False
        
        allow_new_trades = self.vwap_cross_count < self.max_vwap_crosses
        
        # Touch VWAP
        touched_vwap_long = low <= open_vwap_val + buf
        touched_vwap_short = high >= open_vwap_val - buf
        
        # Hold candle detection
        hold_candle_long = (allow_new_trades and self.reclaimed_long and ema_long_ok and 
                           touched_vwap_long and close > open_vwap_val and vol_ok)
        hold_candle_short = (allow_new_trades and self.reclaimed_short and ema_short_ok and 
                            touched_vwap_short and close < open_vwap_val and vol_ok)
        
        # Setup tracking
        if hold_candle_long:
            self.pending_long = True
            self.long_setup_high = high
            self.long_setup_low = low
        
        if hold_candle_short:
            self.pending_short = True
            self.short_setup_high = high
            self.short_setup_low = low
        
        # Cancel pending
        if self.pending_long and (accept_below_vwap or not ema_long_ok or not self.reclaimed_long or not allow_new_trades):
            self.pending_long = False
            
        if self.pending_short and (accept_above_vwap or not ema_short_ok or not self.reclaimed_short or not allow_new_trades):
            self.pending_short = False
        
        # Entry logic
        if self.position.size == 0 and allow_new_trades:
            if self.pending_long and self.long_setup_high is not None and self.long_setup_low is not None:
                stop_buf = self.stop_buffer_ticks * tick
                long_entry_stop = self.long_setup_high + tick
                long_stop_price = self.long_setup_low - stop_buf
                
                if long_entry_stop > long_stop_price:
                    risk_ticks = (long_entry_stop - long_stop_price) / tick
                    if risk_ticks <= self.max_stop_ticks:
                        tp_price = long_entry_stop + (self.take_profit_ticks * tick)
                        self.buy(size=1)
                        self.pending_long = False
            
            if self.pending_short and self.short_setup_high is not None and self.short_setup_low is not None:
                stop_buf = self.stop_buffer_ticks * tick
                short_entry_stop = self.short_setup_low - tick
                short_stop_price = self.short_setup_high + stop_buf
                
                if short_stop_price > short_entry_stop:
                    risk_ticks = (short_stop_price - short_entry_stop) / tick
                    if risk_ticks <= self.max_stop_ticks:
                        tp_price = short_entry_stop - (self.take_profit_ticks * tick)
                        self.sell(size=1)
                        self.pending_short = False
        
        # Exit logic
        if self.position.size > 0:
            stop_buf = self.stop_buffer_ticks * tick
            long_stop = self.long_setup_low - stop_buf if self.long_setup_low else None
            long_tp = self.long_setup_high + self.take_profit_ticks * tick
            
            if long_stop and low <= long_stop:
                self.position.close()
            elif close >= long_tp:
                self.position.close()
        
        if self.position.size < 0:
            stop_buf = self.stop_buffer_ticks * tick
            short_stop = self.short_setup_high + stop_buf if self.short_setup_high else None
            short_tp = self.short_setup_low - self.take_profit_ticks * tick
            
            if short_stop and high >= short_stop:
                self.position.close()
            elif close <= short_tp:
                self.position.close()


