        # Bullish: Trend up + in discount zone + bullish FVG or OB
        bullish_signal = (
            trend == 1 and 
            zone == -1 and 
            (self.bullish_fvg[-1] or self.ob_bull[-1])
        )
        
        # Bearish: Trend down + in premium zone + bearish FVG or OB
        bearish_signal = (
            trend == -1 and 
            zone == 1 and 
            (self.bearish_fvg[-1] or self.ob_bear[-1])
        )
        
        # Simple risk management
        atr_current = self.atr[-1] if len(self.atr) > 0 else 0
        
        if bullish_signal and not self.position:
            self.buy()
        elif bearish_signal and self.position:
            self.sell()
        
        # Exit conditions - simple stop loss
        if self.position:
            if self.position.is_long:
                # Exit on bearish signal or if price closes below support
                if bearish_signal or (trend == -1):
                    self.sell()
            else:
                # Exit on bullish signal or if price closes above resistance
                if bullish_signal or (trend == 1):
                    self.buy()