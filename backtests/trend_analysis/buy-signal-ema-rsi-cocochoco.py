import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_min = 55
    rsi_max = 80
    atr_mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate EMAs
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=25)
        
        # Calculate DMI/ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = self.I(lambda: adx_result['ADX_14'] if adx_result is not None and 'ADX_14' in adx_result else pd.Series(0, index=close.index))
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Calculate highest volume over 10 periods
        self.highest_vol = self.I(lambda: volume.rolling(window=10).max())
        
        # Trailing stop variable
        self.trailing_stop = None

    def next(self):
        if len(self.data) < 2:
            return
        
        close = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        ema50 = self.ema50[-1]
        ema200 = self.ema200[-1]
        rsi = self.rsi[-1]
        rsi_prev = self.rsi[-2] if len(self.rsi) > 1 else rsi
        adx = self.adx[-1]
        atr = self.atr[-1] if self.atr[-1] is not None else 0
        volume = self.data.Volume[-1]
        volume_prev = self.data.Volume[-2] if len(self.data.Volume) > 1 else volume
        highest_vol = self.highest_vol[-1]
        
        # Conditions
        rsi_cross = crossover(self.rsi, self.rsi_min)
        rsi_rising = rsi > rsi_prev
        volume_filter = volume > highest_vol if highest_vol is not None and not np.isnan(highest_vol) else False
        
        # Buy signal logic
        buy_signal = (
            ema50 > ema200 and
            close > ema50 and
            close > ema200 and
            (rsi_cross or rsi > self.rsi_min) and
            rsi < self.rsi_max and
            rsi_rising and
            adx > 20 and
            volume_filter
        )
        
        # Trailing stop logic
        if buy_signal and self.trailing_stop is None:
            self.trailing_stop = close - (atr * self.atr_mult)
            if not self.position:
                self.buy()
        elif self.trailing_stop is not None:
            # Trail upward only
            self.trailing_stop = max(self.trailing_stop, close - (atr * self.atr_mult))
            
            # Close if price crosses below trailing stop
            if close < self.trailing_stop:
                if self.position:
                    self.sell()
                self.trailing_stop = None


