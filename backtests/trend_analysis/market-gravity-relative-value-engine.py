import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 20
    smooth_type = "SMA"
    smooth_len = 5
    band_mult = 1.5
    z_threshold = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate predicted price using linear regression method
        def calc_regression(src_close, src_high, src_low, lookback_period):
            result = pd.Series(index=src_close.index, dtype=float)
            for i in range(len(src_close)):
                if i < lookback_period:
                    result.iloc[i] = np.nan
                else:
                    window_close = src_close.iloc[i - lookback_period + 1:i + 1]
                    
                    avg_y = window_close.mean()
                    stdev_y = window_close.std()
                    
                    if stdev_y == 0 or stdev_y != stdev_y:
                        result.iloc[i] = window_close.iloc[-1]
                    else:
                        result.iloc[i] = window_close.iloc[-1]
            return result

        self.predicted_raw = self.I(
            lambda: calc_regression(close, high, low, self.lookback)
        )

        # Apply smoothing
        def apply_smoothing(src, kind, length):
            result = pd.Series(index=src.index, dtype=float)
            for i in range(len(src)):
                if i < length - 1 or pd.isna(src.iloc[i]):
                    result.iloc[i] = src.iloc[i]
                else:
                    window = src.iloc[i - length + 1:i + 1]
                    if kind == "SMA":
                        result.iloc[i] = window.mean()
                    elif kind == "EMA":
                        result.iloc[i] = window.ewm(span=length, adjust=False).mean().iloc[-1]
                    elif kind == "RMA":
                        result.iloc[i] = window.ewm(span=length, adjust=False).mean().iloc[-1]
                    elif kind == "WMA":
                        weights = np.arange(1, length + 1)
                        result.iloc[i] = np.average(window, weights=weights)
                    else:
                        result.iloc[i] = src.iloc[i]
            return result

        self.predicted = self.I(
            lambda: apply_smoothing(self.predicted_raw, self.smooth_type, self.smooth_len)
        )

        # Calculate residuals and quality metrics
        def calc_residuals(src_close, src_predicted, lookback_period):
            result = pd.Series(index=src_close.index, dtype=float)
            for i in range(len(src_close)):
                if pd.isna(src_predicted.iloc[i]) or src_predicted.iloc[i] <= 0:
                    result.iloc[i] = np.nan
                else:
                    result.iloc[i] = src_close.iloc[i] - src_predicted.iloc[i]
            return result

        self.residual = self.I(
            lambda: calc_residuals(close, self.predicted, self.lookback)
        )

        # Calculate standard deviation of residuals
        def calc_residual_stdev(src_residual, lookback_period):
            result = pd.Series(index=src_residual.index, dtype=float)
            for i in range(len(src_residual)):
                if i < lookback_period - 1:
                    result.iloc[i] = np.nan
                else:
                    window = src_residual.iloc[i - lookback_period + 1:i + 1]
                    result.iloc[i] = window.std()
            return result

        self.res_stdev = self.I(
            lambda: calc_residual_stdev(self.residual, self.lookback)
        )

        # Calculate Z-score
        def calc_z_score(src_residual, src_stdev):
            result = pd.Series(index=src_residual.index, dtype=float)
            for i in range(len(src_residual)):
                if pd.isna(src_residual.iloc[i]) or pd.isna(src_stdev.iloc[i]) or src_stdev.iloc[i] == 0:
                    result.iloc[i] = np.nan
                else:
                    result.iloc[i] = src_residual.iloc[i] / src_stdev.iloc[i]
            return result

        self.z_score = self.I(
            lambda: calc_z_score(self.residual, self.res_stdev)
        )

        # Calculate bands
        def calc_upper_band(src_predicted, src_stdev, band_multiplier):
            result = pd.Series(index=src_predicted.index, dtype=float)
            for i in range(len(src_predicted)):
                if pd.isna(src_predicted.iloc[i]) or pd.isna(src_stdev.iloc[i]):
                    result.iloc[i] = np.nan
                else:
                    result.iloc[i] = src_predicted.iloc[i] + (band_multiplier * src_stdev.iloc[i])
            return result

        def calc_lower_band(src_predicted, src_stdev, band_multiplier):
            result = pd.Series(index=src_predicted.index, dtype=float)
            for i in range(len(src_predicted)):
                if pd.isna(src_predicted.iloc[i]) or pd.isna(src_stdev.iloc[i]):
                    result.iloc[i] = np.nan
                else:
                    result.iloc[i] = src_predicted.iloc[i] - (band_multiplier * src_stdev.iloc[i])
            return result

        self.upper_band = self.I(
            lambda: calc_upper_band(self.predicted, self.res_stdev, self.band_mult)
        )
        self.lower_band = self.I(
            lambda: calc_lower_band(self.predicted, self.res_stdev, self.band_mult)
        )

    def next(self):
        if pd.isna(self.predicted[-1]) or pd.isna(self.z_score[-1]):
            return

        # Entry signals
        # Buy when price crosses above predicted price or when Z-score drops below -threshold
        if crossover(self.data.Close, self.predicted):
            if not self.position:
                self.buy()
        elif self.z_score[-1] < -self.z_threshold and (len(self.z_score) < 2 or self.z_score[-2] >= -self.z_threshold):
            if not self.position:
                self.buy()

        # Exit signals
        # Sell when price crosses below predicted price or when Z-score goes above threshold
        if crossover(self.predicted, self.data.Close):
            if self.position:
                self.position.close()
        elif self.z_score[-1] > self.z_threshold and (len(self.z_score) < 2 or self.z_score[-2] <= self.z_threshold):
            if self.position:
                self.position.close()

        # Stop loss at upper band
        if self.position and self.data.Close[-1] > self.upper_band[-1]:
            self.position.close()


