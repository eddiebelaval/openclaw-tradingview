import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    per = 100
    mult = 3.0
    trendThreshold = 0.6
    volThreshold = 1.5
    regimeStrengthLength = 20
    ceLength = 22
    ceMult = 3.0
    ceUseClose = True
    catchFlat = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.close_data = close
        self.high_data = high
        self.low_data = low
        
        self.regime_value = self.I(self._calc_regime_value)
        self.trend_strength = self.I(self._calc_trend_strength)
        self.vol_ratio = self.I(self._calc_vol_ratio)
        self.in_transition = self.I(self._calc_in_transition)
        self.regime_strength = self.I(self._calc_regime_strength)
        self.alignment_score = self.I(self._calc_alignment_score)

    def _smoothrng(self, x, t, m):
        wper = t * 2 - 1
        avrng = pta.ema(pd.Series(np.abs(np.diff(np.concatenate([[x.iloc[0]], x.values])))), length=t)
        smoothrng = pta.ema(avrng, length=wper) * m
        return smoothrng

    def _rngfilt(self, x, r):
        rngfilt = x.copy()
        for i in range(1, len(x)):
            if x.iloc[i] > rngfilt.iloc[i-1]:
                rngfilt.iloc[i] = max(x.iloc[i] - r.iloc[i], rngfilt.iloc[i-1])
            else:
                rngfilt.iloc[i] = min(x.iloc[i] + r.iloc[i], rngfilt.iloc[i-1])
        return rngfilt

    def _calc_smma(self, src, length):
        smma = pd.Series(0.0, index=src.index)
        smma.iloc[0] = src.iloc[0]
        for i in range(1, len(src)):
            smma.iloc[i] = (smma.iloc[i-1] * (length - 1) + src.iloc[i]) / length
        return smma

    def _calc_zlema(self, src, length):
        ema1 = pta.ema(src, length=length)
        ema2 = pta.ema(ema1, length=length)
        if ema1 is not None and ema2 is not None:
            d = ema1 - ema2
            return ema1 + d
        return src

    def _check_impulse(self):
        impulse_length = 34
        impulse_strength = 9
        
        hi = self._calc_smma(self.high_data, impulse_length)
        lo = self._calc_smma(self.low_data, impulse_length)
        hlc3 = (self.high_data + self.low_data + self.close_data) / 3
        mi = self._calc_zlema(hlc3, impulse_length)
        
        md = pd.Series(0.0, index=self.close_data.index)
        for i in range(len(md)):
            if mi.iloc[i] > hi.iloc[i]:
                md.iloc[i] = mi.iloc[i] - hi.iloc[i]
            elif mi.iloc[i] < lo.iloc[i]:
                md.iloc[i] = mi.iloc[i] - lo.iloc[i]
        
        sb = pta.sma(md, length=impulse_strength)
        sh = md - sb
        is_impulse = (sh != 0).astype(float)
        return is_impulse

    def _calc_trend_strength_series(self):
        length = 50
        tr = pta.atr(self.high_data, self.low_data, self.close_data, length=length)
        atr = tr
        
        high_diff = self.high_data.diff()
        low_diff = self.low_data.diff()
        
        plus_dm = pd.Series(0.0, index=self.high_data.index)
        minus_dm = pd.Series(0.0, index=self.high_data.index)
        
        for i in range(1, len(self.high_data)):
            if high_diff.iloc[i] > low_diff.iloc[i]:
                plus_dm.iloc[i] = max(high_diff.iloc[i], 0)
            if low_diff.iloc[i] > high_diff.iloc[i]:
                minus_dm.iloc[i] = max(low_diff.iloc[i], 0)
        
        plus_dm_smooth = pta.sma(plus_dm, length=length)
        minus_dm_smooth = pta.sma(minus_dm, length=length)
        
        plus_di = (plus_dm_smooth / atr * 100).fillna(0)
        minus_di = (minus_dm_smooth / atr * 100).fillna(0)
        
        dx = (np.abs(plus_di - minus_di) / (plus_di + minus_di + 0.0001) * 100).fillna(0)
        adx = pta.sma(dx, length=length)
        
        trend_strength = (adx / 100).fillna(0.5)
        bullish = (plus_di > minus_di).astype(float)
        
        return trend_strength, bullish

    def _calc_vol_regime(self):
        length = 50
        atr = pta.atr(self.high_data, self.low_data, self.close_data, length=length)
        atr_ma = pta.sma(atr, length=length)
        vol_ratio = (atr / (atr_ma + 0.0001)).fillna(1.0)
        return vol_ratio

    def _calc_regime_value(self):
        smrng = self._smoothrng(self.close_data, self.per, self.mult)
        filt = self._rngfilt(self.close_data, smrng)
        
        upward = pd.Series(0.0, index=self.close_data.index)
        downward = pd.Series(0.0, index=self.close_data.index)
        
        for i in range(1, len(filt)):
            if filt.iloc[i] > filt.iloc[i-1]:
                upward.iloc[i] = upward.iloc[i-1] + 1
                downward.iloc[i] = 0
            elif filt.iloc[i] < filt.iloc[i-1]:
                downward.iloc[i] = downward.iloc[i-1] + 1
                upward.iloc[i] = 0
            else:
                upward.iloc[i] = upward.iloc[i-1]
                downward.iloc[i] = downward.iloc[i-1]
        
        trend_strength, bullish = self._calc_trend_strength_series()
        vol_ratio = self._calc_vol_regime()
        impulse = self._check_impulse()
        
        regime_value = pd.Series(0.0, index=self.close_data.index)
        
        for i in range(len(regime_value)):
            ts = trend_strength.iloc[i]
            vr = vol_ratio.iloc[i]
            imp = impulse.iloc[i]
            bull = bullish.iloc[i]
            
            if not imp and self.catchFlat:
                regime_value.iloc[i] = 0
            elif ts >= self.trendThreshold:
                if vr > self.volThreshold:
                    regime_value.iloc[i] = 3 if bull > 0.5 else -3
                else:
                    regime_value.iloc[i] = 2 if bull > 0.5 else -2
            else:
                regime_value.iloc[i] = 0
        
        return regime_value

    def _calc_trend_strength(self):
        ts, _ = self._calc_trend_strength_series()
        return ts

    def _calc_vol_ratio(self):
        return self._calc_vol_regime()

    def _calc_in_transition(self):
        trend_strength, _ = self._calc_trend_strength_series()
        vol_ratio = self._calc_vol_ratio()
        impulse = self._check_impulse()
        
        weak_trend = trend_strength < self.trendThreshold * 0.8
        vol_spike = vol_ratio > self.volThreshold * 1.5
        lost_impulse = (~impulse.astype(bool)) & self.catchFlat
        
        transition_prob = (weak_trend.astype(float) * 40 + 
                          vol_spike.astype(float) * 30 + 
                          lost_impulse.astype(float) * 30)
        
        in_transition = (transition_prob >= 50).astype(float)
        return in_transition

    def _calc_regime_strength(self):
        trend_strength, _ = self._calc_trend_strength_series()
        vol_ratio = self._calc_vol_ratio()
        impulse = self._check_impulse()
        
        regime_value = self._calc_regime_value()
        
        regime_bars = pd.Series(0.0, index=self.close_data.index)
        bars_count = 0
        last_regime = None
        
        for i in range(len(regime_value)):
            curr_regime = int(regime_value.iloc[i])
            if curr_regime != last_regime:
                bars_count = 1
                last_regime = curr_regime
            else:
                bars_count += 1
            regime_bars.iloc[i] = bars_count
        
        trend_score = trend_strength * 40
        vol_score = ((vol_ratio < self.volThreshold) * 20 + 
                     (vol_ratio >= self.volThreshold) * np.maximum(0, 20 - (vol_ratio - self.volThreshold) * 10))
        impulse_score = impulse * 20
        duration_score = np.minimum(regime_bars / 50.0, 1.0) * 20
        
        total_score = trend_score + vol_score + impulse_score + duration_score
        return total_score

    def _calc_alignment_score(self):
        return pd.Series(0.0, index=self.close_data.index)

    def next(self):
        if len(self.data) < self.per + 10:
            return
        
        regime = self.regime_value[-1]
        strength = self.regime_strength[-1]
        transition = self.in_transition[-1]
        
        strong_bull = regime >= 2 and strength > 70
        strong_bear = regime <= -2 and strength > 70
        
        if strong_bull and not self.position:
            self.buy()
        elif strong_bear and self.position:
            self.position.close()
        elif transition and self.position:
            self.position.close()