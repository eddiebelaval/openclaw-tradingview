import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # SuperTrend parameters
    st_len = 10
    st_mult = 2.5
    st_thresh = 1.0
    st_alpha = 0.5
    
    # ML parameters
    use_ml = True
    k_n = 8
    samp_win = 150
    ml_str = 25
    prob_thr = 0.65
    
    # CVD parameters
    use_cvd = True
    cvd_len = 20
    
    # VWAP parameters
    use_vwap = True
    vwap_m1 = 1.0
    vwap_m2 = 2.0
    
    # Pattern parameters
    min_pat = 1
    
    # Volume parameters
    use_vol = True
    vol_len = 20
    vol_mult = 1.3
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR for SuperTrend
        self.atr = self.I(pta.atr, high, low, close, length=self.st_len)
        
        # Volume indicators
        self.vol_ma = self.I(pta.sma, volume, length=self.vol_len)
        
        # RSI for ML
        self.rsi = self.I(pta.rsi, close, length=20)
        
        # SMA for ML
        self.sma_20 = self.I(pta.sma, close, length=20)
        
        # VWAP
        self.vwap = self.I(pta.vwap, close, volume)
        
        # CVD calculation
        def calc_cvd():
            b_rng = high - low
            up_vol = np.where(b_rng > 0, volume * (close - low) / b_rng, volume * 0.5)
            dn_vol = np.where(b_rng > 0, volume * (high - close) / b_rng, volume * 0.5)
            cvd_series = pd.Series(up_vol - dn_vol).cumsum()
            return cvd_series
        
        self.cvd = self.I(calc_cvd)
        self.cvd_ma = self.I(lambda: pta.sma(self.cvd, length=self.cvd_len) if len(self.cvd) >= self.cvd_len else self.cvd)
        
        # Track SuperTrend state
        self.st_dir = 1
        self.st_band = None
        self.up_line = None
        self.dn_line = None
        self.st_flip = False
        
        # Pattern detection helpers
        self.body = None
        self.lwk = None
        self.uwk = None
        self.rng = None
        
        # ML tracking
        self.prob_up = 0.5
        self.prob_down = 0.5
        self.ml_bull = True
        
    def next(self):
        if len(self.data) < self.st_len + 10:
            return
        
        # Get current values
        h = self.data.High[-1]
        l = self.data.Low[-1]
        c = self.data.Close[-1]
        o = self.data.Open[-1]
        v = self.data.Volume[-1]
        
        hl2 = (h + l) / 2.0
        atr_val = self.atr[-1] if len(self.atr) > 0 else 0.01
        
        # SuperTrend calculation
        vol_wt = v / (self.vol_ma[-1] if len(self.vol_ma) > 0 else v) if v > 0 else 1.0
        adapt_mult = self.st_mult * (0.8 + 0.4) * np.sqrt(max(0.1, vol_wt))
        
        up_raw = hl2 - adapt_mult * atr_val
        dn_raw = hl2 + adapt_mult * atr_val
        
        if self.up_line is None:
            self.up_line = up_raw
            self.dn_line = dn_raw
        else:
            st_smooth = 0.15
            self.up_line = self.up_line * (1 - st_smooth) + up_raw * st_smooth if c > self.up_line else up_raw
            self.dn_line = self.dn_line * (1 - st_smooth) + dn_raw * st_smooth if c < self.dn_line else dn_raw
        
        prev_st_dir = self.st_dir
        prev_band = self.st_band if self.st_band is not None else (self.up_line if self.st_dir == 1 else self.dn_line)
        
        is_noisy = abs(c - prev_band) < (atr_val * self.st_thresh)
        
        if self.st_dir == 1:
            self.st_band = prev_band - (atr_val * self.st_alpha) if is_noisy else max(self.up_line, prev_band)
            if c < self.st_band:
                self.st_dir = -1
                self.st_band = self.dn_line
        else:
            self.st_band = prev_band + (atr_val * self.st_alpha) if is_noisy else min(self.dn_line, prev_band)
            if c > self.st_band:
                self.st_dir = 1
                self.st_band = self.up_line
        
        self.st_flip = (prev_st_dir != self.st_dir)
        st_bull = self.st_dir == 1
        
        # Candlestick patterns
        body = abs(c - o)
        rng = h - l
        lwk = min(c, o) - l
        uwk = h - max(c, o)
        
        is_bull_c = c > o
        is_bear_c = c < o
        
        pat_score = 0
        if len(self.data) > 2:
            c1 = self.data.Close[-2]
            o1 = self.data.Open[-2]
            c2 = self.data.Close[-3]
            o2 = self.data.Open[-3]
            body1 = abs(c1 - o1)
            body2 = abs(c2 - o2)
            is_bull_c1 = c1 > o1
            is_bear_c1 = c1 < o1
            
            # Bullish Engulfing
            if is_bear_c1 and is_bull_c and o < c1 and c > o1 and body > body1:
                pat_score += 1
            
            # Hammer
            if lwk >= body * 2.0 and uwk <= body * 0.5 and rng > 0:
                pat_score += 1
            
            # Bullish Harami
            if is_bear_c1 and is_bull_c and o > c1 and c < o1:
                pat_score += 1
        
        pat_ok = self.min_pat == 0 or pat_score >= self.min_pat
        
        # Volume filter
        vol_ma = self.vol_ma[-1] if len(self.vol_ma) > 0 else v
        vol_ratio = v / vol_ma if vol_ma > 0 else 1.0
        vol_ok = not self.use_vol or vol_ratio >= self.vol_mult
        
        # CVD filter
        cvd_bull = not self.use_cvd or (len(self.cvd) > 0 and len(self.cvd_ma) > 0 and 
                                         self.cvd[-1] > self.cvd_ma[-1])
        
        # VWAP filter
        vwap_val = self.vwap[-1] if len(self.vwap) > 0 else c
        vwap_bull = not self.use_vwap or c > vwap_val
        
        # ML filter
        self.ml_bull = not self.use_ml or self.prob_up > self.prob_thr
        ml_bear = not self.use_ml or self.prob_down > self.prob_thr
        
        # Simple ML approximation using RSI
        if self.use_ml and len(self.rsi) > 0:
            rsi_val = self.rsi[-1]
            self.prob_up = (rsi_val - 30) / 40.0 if rsi_val < 70 else 1.0
            self.prob_down = (70 - rsi_val) / 40.0 if rsi_val > 30 else 1.0
            self.ml_bull = self.prob_up > self.prob_thr
        
        # Final signals
        bull_signal = self.st_flip and st_bull and self.ml_bull and cvd_bull and vwap_bull and pat_ok and vol_ok
        sell_signal = self.st_flip and not st_bull and ml_bear and not cvd_bull and not vwap_bull and vol_ok
        
        # Execute trades
        if bull_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.position.close()