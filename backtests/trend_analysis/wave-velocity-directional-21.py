class TvStrategy(Strategy):
    cci_len = 20
    cci_long_max = 80
    cci_short_min = -80
    ema_len = 200
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        hlc3 = (high + low + close) / 3
        
        self.cci = self.I(pta.cci, high, low, close, length=self.cci_len)
        self.ema200 = self.I(pta.ema, close, length=self.ema_len)
        
        self.in_trade = False
    
    def next(self):
        if len(self.data) < self.ema_len:
            return
        
        current_cci = self.cci[-1] if not np.isnan(self.cci[-1]) else None
        current_ema = self.ema200[-1] if not np.isnan(self.ema200[-1]) else None
        current_close = self.data.Close[-1]
        
        if current_cci is None or current_ema is None:
            return
        
        ema_up = self.ema200[-1] > self.ema200[-2] if len(self.ema200) > 1 else False
        ema_down = self.ema200[-1] < self.ema200[-2] if len(self.ema200) > 1 else False
        
        long_allowed = (current_close > current_ema) and ema_up
        short_allowed = (current_close < current_ema) and ema_down
        
        cci_long_ok = current_cci < self.cci_long_max
        cci_short_ok = current_cci > self.cci_short_min
        
        long_signal = long_allowed and cci_long_ok and current_cci > -80
        short_signal = short_allowed and cci_short_ok and current_cci < 80
        
        if long_signal and not self.position:
            self.buy()
            self.in_trade = True
        elif short_signal and self.position:
            self.sell()
            self.in_trade = False
        
        if self.position and current_cci > self.cci_long_max:
            self.sell()
            self.in_trade = False
        elif self.position and current_cci < self.cci_short_min:
            self.sell()
            self.in_trade = False


