        # Extract ADX value
        self.adx = self.I(lambda: pta.adx(high, low, close, length=14))

        # Alpha Trend Components
        self.at_atr = self.I(pta.sma, pta.atr(high, low, close, length=self.alpha_p), length=self.alpha_p)
        
        # ATR for UT Bot
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_p)

        # RSI and MFI
        self.f_rsi = self.I(pta.rsi, close, length=14)
        self.f_mfi = self.I(pta.mfi, high, low, close, volume, length=14)

        # EMA 50
        self.ema50 = self.I(pta.ema, close, length=50)

        # Magic Trend CCI
        self.magic_cci = self.I(pta.cci, high, low, close, length=self.magic_p)

        # Volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=20)

        # Alpha MFI
        self.alpha_mfi = self.I(pta.mfi, high, low, close, volume, length=self.alpha_p)

