import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vol_length = 20
    
    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        self.sma_vol = self.I(lambda: pta.sma(volume, length=self.vol_length) or pd.Series(0, index=volume.index))
    
    def next(self):
        if len(self) < self.vol_length + 1:
            return
        
        current_vol = self.data.Volume[-1]
        avg_vol = self.sma_vol[-1]
        
        if avg_vol == 0:
            return
        
        vol_ratio = current_vol / avg_vol
        
        if vol_ratio >= 2.0 and not self.position:
            self.buy()
        elif vol_ratio < 0.8 and self.position:
            self.sell()