import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    leftBars = 10
    rightBars = 10
    maxLevels = 5
    touchPct = 0.001
    proxPct = 0.003

    def init(self):
        self.pivot_highs_tf1 = []
        self.pivot_lows_tf1 = []
        self.pivot_highs_tf2 = []
        self.pivot_lows_tf2 = []
        
        self.touches_ph_tf1 = []
        self.touches_pl_tf1 = []
        self.touches_ph_tf2 = []
        self.touches_pl_tf2 = []
        
        self.last_signal = None

    def find_pivot_high(self, data, idx, left_bars, right_bars):
        if idx < left_bars or idx + right_bars >= len(data):
            return None
        
        pivot_idx = idx - right_bars
        if pivot_idx < left_bars:
            return None
        
        pivot_high = data.iloc[pivot_idx]['High']
        
        for i in range(pivot_idx - left_bars, pivot_idx):
            if data.iloc[i]['High'] >= pivot_high:
                return None
        
        for i in range(pivot_idx + 1, pivot_idx + right_bars + 1):
            if data.iloc[i]['High'] >= pivot_high:
                return None
        
        return pivot_high

    def find_pivot_low(self, data, idx, left_bars, right_bars):
        if idx < left_bars or idx + right_bars >= len(data):
            return None
        
        pivot_idx = idx - right_bars
        if pivot_idx < left_bars:
            return None
        
        pivot_low = data.iloc[pivot_idx]['Low']
        
        for i in range(pivot_idx - left_bars, pivot_idx):
            if data.iloc[i]['Low'] <= pivot_low:
                return None
        
        for i in range(pivot_idx + 1, pivot_idx + right_bars + 1):
            if data.iloc[i]['Low'] <= pivot_low:
                return None
        
        return pivot_low

    def add_if_new(self, arr, touch_arr, val):
        is_dup = False
        if len(arr) > 0:
            for existing in arr:
                if abs(existing - val) / val < 0.0005:
                    is_dup = True
                    break
        
        if not is_dup:
            arr.insert(0, val)
            touch_arr.insert(0, 1)
            if len(arr) > 20:
                arr.pop()
                touch_arr.pop()

    def count_touches(self, arr, touch_arr, high, low):
        if len(arr) > 0:
            for i in range(len(arr)):
                lvl = arr[i]
                near_high = abs(high - lvl) / lvl < self.touchPct
                near_low = abs(low - lvl) / lvl < self.touchPct
                if near_high or near_low:
                    touch_arr[i] += 1

    def next(self):
        if len(self.data) < self.leftBars + self.rightBars + 1:
            return
        
        current_idx = len(self.data) - 1
        
        ph_tf1 = self.find_pivot_high(self.data.df, current_idx, self.leftBars, self.rightBars)
        pl_tf1 = self.find_pivot_low(self.data.df, current_idx, self.leftBars, self.rightBars)
        
        if ph_tf1 is not None:
            self.add_if_new(self.pivot_highs_tf1, self.touches_ph_tf1, ph_tf1)
        if pl_tf1 is not None:
            self.add_if_new(self.pivot_lows_tf1, self.touches_pl_tf1, pl_tf1)
        
        self.count_touches(self.pivot_highs_tf1, self.touches_ph_tf1, self.data.High[-1], self.data.Low[-1])
        self.count_touches(self.pivot_lows_tf1, self.touches_pl_tf1, self.data.High[-1], self.data.Low[-1])
        self.count_touches(self.pivot_highs_tf2, self.touches_ph_tf2, self.data.High[-1], self.data.Low[-1])
        self.count_touches(self.pivot_lows_tf2, self.touches_pl_tf2, self.data.High[-1], self.data.Low[-1])
        
        current_price = self.data.Close[-1]
        
        near_res1 = False
        near_sup1 = False
        near_res2 = False
        near_sup2 = False
        
        if len(self.pivot_highs_tf1) > 0:
            for lvl in self.pivot_highs_tf1:
                if abs(current_price - lvl) / lvl < self.proxPct:
                    near_res1 = True
                    break
        
        if len(self.pivot_lows_tf1) > 0:
            for lvl in self.pivot_lows_tf1:
                if abs(current_price - lvl) / lvl < self.proxPct:
                    near_sup1 = True
                    break
        
        if len(self.pivot_highs_tf2) > 0:
            for lvl in self.pivot_highs_tf2:
                if abs(current_price - lvl) / lvl < self.proxPct:
                    near_res2 = True
                    break
        
        if len(self.pivot_lows_tf2) > 0:
            for lvl in self.pivot_lows_tf2:
                if abs(current_price - lvl) / lvl < self.proxPct:
                    near_sup2 = True
                    break
        
        signal = None
        if near_res2 or near_res1:
            signal = "sell"
        elif near_sup2 or near_sup1:
            signal = "buy"
        
        if signal == "buy" and self.last_signal != "buy":
            if not self.position:
                self.buy()
            self.last_signal = "buy"
        elif signal == "sell" and self.last_signal != "sell":
            if self.position:
                self.sell()
            self.last_signal = "sell"


