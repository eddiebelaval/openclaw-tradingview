import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    conversion_periods = 9
    base_periods = 26
    lagging_span2_periods = 52
    displacement = 26

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        def donchian(src, length):
            if isinstance(src, pd.Series):
                highest = src.rolling(length).max()
                lowest = src.rolling(length).min()
                return (highest + lowest) / 2
            return pd.Series(np.nan, index=close.index)
        
        self.tenkan = self.I(lambda: donchian(high.rolling(self.conversion_periods).max().combine(
            low.rolling(self.conversion_periods).min(), lambda h, l: (h + l) / 2) 
            if len(close) > 0 else pd.Series(np.nan, index=close.index)))
        
        self.kijun = self.I(lambda: donchian(high.rolling(self.base_periods).max().combine(
            low.rolling(self.base_periods).min(), lambda h, l: (h + l) / 2)
            if len(close) > 0 else pd.Series(np.nan, index=close.index)))
        
        self.senkou_a = self.I(lambda: (
            (high.rolling(self.conversion_periods).max() + low.rolling(self.conversion_periods).min()) / 2 +
            (high.rolling(self.base_periods).max() + low.rolling(self.base_periods).min()) / 2
        ) / 2 if len(close) > 0 else pd.Series(np.nan, index=close.index))
        
        self.senkou_b = self.I(lambda: (
            high.rolling(self.lagging_span2_periods).max() + low.rolling(self.lagging_span2_periods).min()
        ) / 2 if len(close) > 0 else pd.Series(np.nan, index=close.index))
        
        self.chikou = self.I(lambda: close.shift(self.displacement) if len(close) > 0 else pd.Series(np.nan, index=close.index))

    def next(self):
        if len(self.data) < self.displacement + max(self.conversion_periods, self.base_periods, self.lagging_span2_periods):
            return
        
        tenkan_val = self.tenkan[-1] if len(self.tenkan) > 0 and not np.isnan(self.tenkan[-1]) else None
        kijun_val = self.kijun[-1] if len(self.kijun) > 0 and not np.isnan(self.kijun[-1]) else None
        senkou_a_val = self.senkou_a[-1] if len(self.senkou_a) > 0 and not np.isnan(self.senkou_a[-1]) else None
        senkou_b_val = self.senkou_b[-1] if len(self.senkou_b) > 0 and not np.isnan(self.senkou_b[-1]) else None
        close_val = self.data.Close[-1]
        
        if tenkan_val is None or kijun_val is None or senkou_a_val is None or senkou_b_val is None:
            return
        
        kumo_top = max(senkou_a_val, senkou_b_val)
        kumo_bottom = min(senkou_a_val, senkou_b_val)
        
        bullish_signal = (
            tenkan_val > kijun_val and
            close_val > kumo_top and
            close_val > self.chikou[-self.displacement] if len(self.chikou) > self.displacement and not np.isnan(self.chikou[-self.displacement]) else False
        )
        
        bearish_signal = (
            tenkan_val < kijun_val and
            close_val < kumo_bottom and
            close_val < self.chikou[-self.displacement] if len(self.chikou) > self.displacement and not np.isnan(self.chikou[-self.displacement]) else False
        )
        
        if bullish_signal and not self.position:
            self.buy()
        elif bearish_signal and self.position:
            self.sell()