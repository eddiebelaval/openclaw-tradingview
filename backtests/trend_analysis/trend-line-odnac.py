    def find_donchian_high(self, idx):
        if idx < self.donchian_len + 1:
            return None
        
        if idx >= 1:
            max_high = max(self.data.High[idx - self.donchian_len:idx])
            if self.data.High[idx - 1] == max_high:
                return self.data.High[idx - 1]
        
        return None

    def find_donchian_low(self, idx):
        if idx < self.donchian_len + 1:
            return None
        
        if idx >= 1:
            min_low = min(self.data.Low[idx - self.donchian_len:idx])
            if self.data.Low[idx - 1] == min_low:
                return self.data.Low[idx - 1]
        
        return None

