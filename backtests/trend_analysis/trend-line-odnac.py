    def confirm_bearish(self, idx):
        right_bars = self.right_bars
        if idx < right_bars:
            return False
        
        last_bear_close = None
        renew_count = 0
        
        for i in range(right_bars):
            j = right_bars - 1 - i
            bar_idx = idx - j
            if bar_idx >= 0:
                if self.data.Close[bar_idx] < self.data.Open[bar_idx]:
                    if last_bear_close is None:
                        renew_count = 1
                        last_bear_close = self.data.Close[bar_idx]
                    elif self.data.Close[bar_idx] < last_bear_close:
                        renew_count += 1
                        last_bear_close = self.data.Close[bar_idx]
        
        consecutive_bears = 0
        max_consecutive = 0
        for i in range(1, right_bars + 1):
            bar_idx = idx - i
            if bar_idx >= 0:
                if self.data.Close[bar_idx] < self.data.Open[bar_idx]:
                    consecutive_bears += 1
                    max_consecutive = max(max_consecutive, consecutive_bears)
                else:
                    consecutive_bears = 0
        
        return renew_count >= 3 or max_consecutive >= 3

