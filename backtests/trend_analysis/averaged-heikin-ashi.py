import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 50
    len2 = 60
    method = "EMA"
    method2 = "EMA"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        def calculate_ha_direction():
            ha_close = (open_ + high + low + close) / 4.0
            ha_open = pd.Series(index=close.index, dtype=float)
            ha_open.iloc[0] = (open_.iloc[0] + close.iloc[0]) / 2.0
            
            for i in range(1, len(close)):
                ha_open.iloc[i] = (ha_open.iloc[i-1] + ha_close.iloc[i-1]) / 2.0
            
            ha_open_sm = self.apply_smoothing(ha_open, self.method, self.len)
            ha_close_sm = self.apply_smoothing(ha_close, self.method, self.len)
            ha_open_2 = self.apply_smoothing(ha_open_sm, self.method2, self.len2)
            ha_close_2 = self.apply_smoothing(ha_close_sm, self.method2, self.len2)
            
            ha_open_ultra = ha_open_2 + ha_open_sm * 0
            ha_close_ultra = ha_close_2 + ha_close_sm * 0
            
            direction = (ha_close_ultra >= ha_open_ultra).astype(int)
            return direction
        
        self.direction = self.I(calculate_ha_direction)

    def apply_smoothing(self, src, method, length):
        if method == "SMA":
            return pta.sma(src, length=length)
        elif method == "EMA":
            return pta.ema(src, length=length)
        elif method == "RMA":
            return pta.rma(src, length=length)
        elif method == "WMA":
            return pta.wma(src, length=length)
        elif method == "TEMA":
            ema1 = pta.ema(src, length=length)
            ema2 = pta.ema(ema1, length=length)
            ema3 = pta.ema(ema2, length=length)
            return (3 * ema1) - (3 * ema2) + ema3
        elif method == "LWMA":
            return pta.wma(src, length=length)
        else:
            return src

    def next(self):
        if len(self.data) < 2:
            return
        
        current_direction = self.direction[-1]
        prev_direction = self.direction[-2] if len(self.direction) > 1 else current_direction
        
        if prev_direction == 0 and current_direction == 1:
            if self.position:
                self.position.close()
            else:
                self.buy()
        elif prev_direction == 1 and current_direction == 0:
            if self.position:
                self.position.close()
            else:
                self.sell()