import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_length = 20
    lookback = 10
    use_30m_for_5m = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.sma = self.I(pta.sma, close, length=self.ma_length)
        
        self.convergence_state = {}
        self.last_status = {}
        self.last_alert_bar = {}
        
        for tf in ["1m", "5m", "15m", "1h", "4h", "D", "W", "M"]:
            self.convergence_state[tf] = False
            self.last_status[tf] = ""
            self.last_alert_bar[tf] = -1

    def next(self):
        if len(self.data) < self.lookback + 1:
            return
        
        current_price = self.data.Close[-1]
        current_sma = self.sma[-1]
        previous_sma = self.sma[-self.lookback - 1] if len(self.sma) > self.lookback else self.sma[0]
        
        if np.isnan(current_sma) or np.isnan(previous_sma):
            return
        
        crossed = crossover(self.sma[-self.lookback:], np.full(self.lookback, current_sma)) or \
                  crossover(np.full(self.lookback, current_sma), self.sma[-self.lookback:])
        
        is_above = current_sma > previous_sma
        conv = (current_sma < previous_sma) if is_above else (current_sma > previous_sma)
        
