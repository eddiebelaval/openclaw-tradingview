import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        self.swing_length = 50
        self.internal_length = 5
        self.equal_length = 3
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.highest_high = self.I(lambda: high.rolling(self.swing_length).max())
        self.lowest_low = self.I(lambda: low.rolling(self.swing_length).min())
        
        self.internal_highest = self.I(lambda: high.rolling(self.internal_length).max())
        self.internal_lowest = self.I(lambda: low.rolling(self.internal_length).min())
        
        self.atr_value = self.I(pta.atr, high, low, close, length=200)
        
        self.swing_trend = 0
        self.internal_trend = 0
        self.swing_high_level = 0
        self.swing_low_level = 0
        self.internal_high_level = 0
        self.internal_low_level = 0
        self.swing_high_crossed = False
        self.swing_low_crossed = False
        self.internal_high_crossed = False
        self.internal_low_crossed = False

    def next(self):
        if len(self.data) < self.swing_length + 5:
            return
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        
        swing_highest = self.highest_high[-1]
        swing_lowest = self.lowest_low[-1]
        internal_highest = self.internal_highest[-1]
        internal_lowest = self.internal_lowest[-1]
        
        if swing_highest > self.swing_high_level:
            self.swing_high_level = swing_highest
            self.swing_high_crossed = False
        
        if swing_lowest < self.swing_low_level:
            self.swing_low_level = swing_lowest
            self.swing_low_crossed = False
        
        if internal_highest > self.internal_high_level:
            self.internal_high_level = internal_highest
            self.internal_high_crossed = False
        
        if internal_lowest < self.internal_low_level:
            self.internal_low_level = internal_lowest
            self.internal_low_crossed = False
        
        if current_close > self.swing_high_level and not self.swing_high_crossed:
            self.swing_high_crossed = True
            if self.swing_trend == -1:
                self.swing_trend = 1
                if not self.position:
                    self.buy()
            elif self.swing_trend == 0:
                self.swing_trend = 1
        
        if current_close < self.swing_low_level and not self.swing_low_crossed:
            self.swing_low_crossed = True
            if self.swing_trend == 1:
                self.swing_trend = -1
                if self.position:
                    self.sell()
            elif self.swing_trend == 0:
                self.swing_trend = -1
        
        if current_close > self.internal_high_level and not self.internal_high_crossed:
            self.internal_high_crossed = True
            self.internal_trend = 1
        
        if current_close < self.internal_low_level and not self.internal_low_crossed:
            self.internal_low_crossed = True
            self.internal_trend = -1
        
        if self.position and self.internal_trend == -1 and self.swing_trend == -1:
            self.sell()
        elif not self.position and self.internal_trend == 1 and self.swing_trend == 1:
            self.buy()


