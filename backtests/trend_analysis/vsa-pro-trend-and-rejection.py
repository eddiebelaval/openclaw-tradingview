import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    st_period = 10
    st_multiplier = 3.0
    atr_length = 14
    min_vol_mult = 1.0
    effort_mult = 2.0
    result_mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Calculate average volume (SMA of volume)
        self.avg_vol = self.I(pta.sma, volume, length=50)
        
        # Body size calculation
        self.body_size = self.I(lambda: np.abs(close - pd.Series(self.data.Open)))
        
        # Is green/red candle
        self.is_green_candle = self.I(lambda: close > pd.Series(self.data.Open))
        self.is_red_candle = self.I(lambda: close < pd.Series(self.data.Open))
        
        # Relative body to ATR
        self.rel_body_atr = self.I(lambda: np.abs(close - pd.Series(self.data.Open)) / (pta.atr(high, low, close, length=self.atr_length) or pd.Series(1, index=close.index)))
        
        # Relative volume
        self.rel_vol = self.I(lambda: volume / (pta.sma(volume, length=50) or pd.Series(1, index=volume.index)))
        
        # Volume valid check
        self.is_volume_valid = self.I(lambda: volume > (pta.sma(volume, length=50) or pd.Series(0, index=volume.index)) * self.min_vol_mult)
        
        # SuperTrend calculation
        self.supertrend_val = self.I(lambda: self._calculate_supertrend(high, low, close))
        self.supertrend_dir = self.I(lambda: self._calculate_supertrend_dir(high, low, close))
        
        self.prev_dir = None

    def _calculate_supertrend(self, high, low, close):
        """Calculate SuperTrend value"""
        hl_avg = (high + low) / 2
        atr_vals = pta.atr(high, low, close, length=self.st_period)
        if atr_vals is None:
            return pd.Series(0, index=close.index)
        
        basic_ub = hl_avg + self.st_multiplier * atr_vals
        basic_lb = hl_avg - self.st_multiplier * atr_vals
        
        final_ub = pd.Series(0.0, index=close.index)
        final_lb = pd.Series(0.0, index=close.index)
        
        for i in range(len(close)):
            if i == 0:
                final_ub.iloc[i] = basic_ub.iloc[i]
                final_lb.iloc[i] = basic_lb.iloc[i]
            else:
                final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
        
        st = pd.Series(0.0, index=close.index)
        for i in range(len(close)):
            if close.iloc[i] <= final_ub.iloc[i]:
                st.iloc[i] = final_ub.iloc[i]
            else:
                st.iloc[i] = final_lb.iloc[i]
        
        return st

    def _calculate_supertrend_dir(self, high, low, close):
        """Calculate SuperTrend direction: -1 for uptrend (green), 1 for downtrend (red)"""
        st = self._calculate_supertrend(high, low, close)
        direction = pd.Series(0, index=close.index)
        
        for i in range(len(close)):
            if close.iloc[i] <= st.iloc[i]:
                direction.iloc[i] = 1
            else:
                direction.iloc[i] = -1
        
        return direction

    def next(self):
        if len(self.data) < self.st_period + 50:
            return
        
        current_dir = self.supertrend_dir[-1]
        prev_dir = self.supertrend_dir[-2] if len(self.supertrend_dir) > 1 else current_dir
        
        is_trend_new_green = current_dir == -1 and prev_dir == 1
        is_trend_new_red = current_dir == 1 and prev_dir == -1
        
        is_green_zone = current_dir == -1
        is_red_zone = current_dir == 1
        
        signal_al = is_trend_new_green
        signal_sat = is_trend_new_red
        
        # VSA conditions
        cond_l1 = self.is_green_candle[-1] and self.rel_body_atr[-1] > self.result_mult
        cond_l2 = self.is_red_candle[-1] and self.rel_vol[-1] > self.effort_mult and self.rel_body_atr[-1] < 0.8
        signal_ekle_gorsel = is_green_zone and (not is_trend_new_green) and self.is_volume_valid[-1] and (cond_l1 or cond_l2)
        
        cond_s1 = self.is_red_candle[-1] and self.rel_body_atr[-1] > self.result_mult
        cond_s2 = self.is_green_candle[-1] and self.rel_vol[-1] > self.effort_mult and self.rel_body_atr[-1] < 0.8
        signal_zayiflik_gorsel = is_red_zone and (not is_trend_new_red) and self.is_volume_valid[-1] and (cond_s1 or cond_s2)
        
        # Strategy entries and exits
        if signal_al:
            if not self.position:
                self.buy()
        
        if signal_sat:
            if self.position:
                self.position.close()


