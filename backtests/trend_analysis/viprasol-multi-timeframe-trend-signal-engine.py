import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Main Settings
    sensitivity = 2.5
    atr_factor = 11
    signal_mode = "All Signals"  # "All Signals" or "Filtered Signals"
    
    # Trend Settings
    main_ema_period = 200
    
    # Signal Settings
    rsi_period = 14
    filter_ma_len = 13
    
    # Constants
    adx_period = 14
    adx_smooth = 14
    bull_mult = 1.2
    bear_mult = 0.8
    chaos_amp = 3
    chaos_dev_mult = 2
    reversal_len = 25
    ob_level = 75.0
    os_level = 25.0
    pivot_bars = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Main EMA
        self.main_ema = self.I(pta.ema, close, length=self.main_ema_period)
        
        # SuperTrend calculation
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_factor)
        self.signal_filter_ma = self.I(pta.sma, close, length=self.filter_ma_len)
        
        # Compute SuperTrend bands
        def compute_supertrend_bands():
            atr = self.atr_val
            upper_band = self.data.Open + self.sensitivity * atr
            lower_band = self.data.Open - self.sensitivity * atr
            
            upper_band_arr = np.full(len(close), np.nan)
            lower_band_arr = np.full(len(close), np.nan)
            
            for i in range(len(close)):
                if i == 0:
                    upper_band_arr[i] = upper_band.iloc[i]
                    lower_band_arr[i] = lower_band.iloc[i]
                else:
                    lb = lower_band.iloc[i]
                    ub = upper_band.iloc[i]
                    lb = max(lb, lower_band_arr[i-1]) if close.iloc[i-1] > lower_band_arr[i-1] else lb
                    ub = min(ub, upper_band_arr[i-1]) if close.iloc[i-1] < upper_band_arr[i-1] else ub
                    lower_band_arr[i] = lb
                    upper_band_arr[i] = ub
            
            trend_line = np.full(len(close), np.nan)
            for i in range(len(close)):
                if i == 0:
                    trend_line[i] = lower_band_arr[i]
                else:
                    if trend_line[i-1] == upper_band_arr[i-1]:
                        trend_line[i] = lower_band_arr[i] if close.iloc[i] > upper_band_arr[i] else upper_band_arr[i]
                    else:
                        trend_line[i] = upper_band_arr[i] if close.iloc[i] < lower_band_arr[i] else lower_band_arr[i]
            
            return pd.Series(trend_line, index=close.index)
        
        self.st_line = self.I(compute_supertrend_bands)
        
        # RSI
        self.rsi_value = self.I(pta.rsi, close, length=self.rsi_period)
        
        # Ribbon (trend ribbon EMAs)
        self.ribbon_fast = self.I(pta.ema, close, length=20)
        self.ribbon_slow = self.I(pta.ema, close, length=55)
        self.ribbon_mid3 = self.I(pta.ema, close, length=25)
        self.ribbon_mid2 = self.I(pta.ema, close, length=35)
        self.ribbon_mid1 = self.I(pta.ema, close, length=45)
        
        # Cloud EMAs
        self.cloud_fast = self.I(pta.ema, close, length=150)
        self.cloud_slow = self.I(pta.ema, close, length=250)
        
        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=self.adx_period)
        self.adx_value = self.I(lambda: (adx_result or pd.DataFrame()).get('ADX_14', pd.Series(50, index=close.index)))
        
        # Reversal RSI (custom)
        def compute_reversal_rsi():
            up_rma = pta.rma(np.maximum(close.diff(), 0), length=self.reversal_len)
            dn_rma = pta.rma(-np.minimum(close.diff(), 0), length=self.reversal_len)
            rev_rsi = 100.0 - (100.0 / (1.0 + up_rma / (dn_rma + 1e-9)))
            return rev_rsi
        
        self.reversal_rsi = self.I(compute_reversal_rsi)
        
        # Track previous values for crossover detection
        self.prev_close = None
        self.prev_st_line = None
        self.prev_ribbon_fast = None
        self.prev_ribbon_slow = None
        self.prev_reversal_rsi = None
        self.prev_main_ema = None
        self.prev_rsi = None

    def next(self):
        # Current values
        close_val = self.data.Close[-1]
        st_line_val = self.st_line[-1]
        signal_filter_val = self.signal_filter_ma[-1]
        main_ema_val = self.main_ema[-1]
        rsi_val = self.rsi_value[-1]
        reversal_rsi_val = self.reversal_rsi[-1]
        ribbon_fast_val = self.ribbon_fast[-1]
        ribbon_slow_val = self.ribbon_slow[-1]
        
        # Initialize previous values on first bar
        if self.prev_close is None:
            self.prev_close = close_val
            self.prev_st_line = st_line_val
            self.prev_ribbon_fast = ribbon_fast_val
            self.prev_ribbon_slow = ribbon_slow_val
            self.prev_reversal_rsi = reversal_rsi_val
            self.prev_main_ema = main_ema_val
            self.prev_rsi = rsi_val
            return
        
        # Determine ribbon trend
        ribbon_bullish = ribbon_fast_val > ribbon_slow_val
        prev_ribbon_bullish = self.prev_ribbon_fast > self.prev_ribbon_slow
        
        # Determine main EMA direction
        above_main_ema = close_val > main_ema_val
        prev_above_main_ema = self.prev_close > self.prev_main_ema
        
        # SuperTrend crossovers
        buy_crossover = crossover(pd.Series([self.prev_close, close_val]), pd.Series([self.prev_st_line, st_line_val]))
        sell_crossover = crossover(pd.Series([self.prev_st_line, st_line_val]), pd.Series([self.prev_close, close_val]))
        
        # Signal conditions
        raw_buy = buy_crossover and close_val >= signal_filter_val
        raw_sell = sell_crossover and close_val <= signal_filter_val
        
        # Filtered signals
        unfiltered_buy = raw_buy and not above_main_ema
        unfiltered_sell = raw_sell and above_main_ema
        
        filtered_buy = raw_buy and above_main_ema
        filtered_sell = raw_sell and not above_main_ema
        
        # Reversal signals
        reversal_up = crossover(pd.Series([self.prev_reversal_rsi, reversal_rsi_val]), pd.Series([self.os_level, self.os_level]))
        reversal_down = crossover(pd.Series([self.ob_level, self.ob_level]), pd.Series([self.prev_reversal_rsi, reversal_rsi_val]))
        
        # Trading logic
        if self.signal_mode == "All Signals":
            if unfiltered_buy or reversal_up:
                if not self.position:
                    self.buy()
            elif unfiltered_sell or reversal_down:
                if self.position:
                    self.position.close()
        else:  # Filtered Signals
            if filtered_buy or reversal_up:
                if not self.position:
                    self.buy()
            elif filtered_sell or reversal_down:
                if self.position:
                    self.position.close()
        
        # Update previous values
        self.prev_close = close_val
        self.prev_st_line = st_line_val
        self.prev_ribbon_fast = ribbon_fast_val
        self.prev_ribbon_slow = ribbon_slow_val
        self.prev_reversal_rsi = reversal_rsi_val
        self.prev_main_ema = main_ema_val
        self.prev_rsi = rsi_val


