import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # ORB Ultimate parameters
    orb_session_start_hour = 9
    orb_session_start_minute = 30
    orb_session_end_hour = 10
    orb_session_end_minute = 30
    entry_strategy = 'Immediate Breakout'  # 'Immediate Breakout' or 'Retest'
    breakout_condition = 'Close'  # 'Close' or 'EMA'
    tp_method = 'RR'  # 'RR' or 'ATR'
    rr_multiplier = 2.0
    tp_atr_mult = 1.5
    sl_method = 'Other Side of ORB'  # 'Other Side of ORB', 'Breakout Candle', 'ATR', 'Pivot Structure'
    pivot_lookback = 10
    sl_atr_mult = 2.0
    adaptive_sl = True
    use_ema_filter = False
    ema_length = 9
    atr_length = 12

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate indicators
        self.ema = self.I(pta.ema, close, length=self.ema_length)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Recent pivot structure
        self.recent_high = self.I(lambda: high.rolling(self.pivot_lookback).max())
        self.recent_low = self.I(lambda: low.rolling(self.pivot_lookback).min())
        
        # ORB tracking
        self.orb_high = None
        self.orb_low = None
        self.orb_start_idx = None
        self.orb_active = False
        self.in_session = False
        self.session_just_started = False
        self.session_just_ended = False
        
        # Trade state
        self.entry_price = None
        self.entry_bullish = None
        self.sl_price = None
        self.tp_price = None
        self.trade_active = False
        self.entry_atr = None

    def is_in_orb_session(self, bar_idx):
        """Check if current bar is in ORB session"""
        if bar_idx >= len(self.data):
            return False
        
        dt = self.data.index[bar_idx]
        hour = dt.hour
        minute = dt.minute
        
        start_minutes = self.orb_session_start_hour * 60 + self.orb_session_start_minute
        end_minutes = self.orb_session_end_hour * 60 + self.orb_session_end_minute
        current_minutes = hour * 60 + minute
        
        return start_minutes <= current_minutes < end_minutes

    def next(self):
        idx = len(self.data) - 1
        
        # Check session state
        prev_in_session = self.in_session
        self.in_session = self.is_in_orb_session(idx)
        self.session_just_started = self.in_session and not prev_in_session
        self.session_just_ended = not self.in_session and prev_in_session
        
        # Session start: reset ORB
        if self.session_just_started:
            self.orb_high = self.data.High[-1]
            self.orb_low = self.data.Low[-1]
            self.orb_start_idx = idx
            self.orb_active = True
        
        # During session: update ORB high/low
        if self.orb_active and self.in_session:
            self.orb_high = max(self.orb_high, self.data.High[-1])
            self.orb_low = min(self.orb_low, self.data.Low[-1])
        
        # Session end: ORB formed, wait for breakout
        if self.session_just_ended and self.orb_active:
            self.orb_active = False
        
        # Trade management
        if self.trade_active:
            # Check TP hit
            if self.entry_bullish and self.data.High[-1] >= self.tp_price:
                self.sell()
                self.trade_active = False
                self.entry_price = None
            elif not self.entry_bullish and self.data.Low[-1] <= self.tp_price:
                self.buy()
                self.trade_active = False
                self.entry_price = None
            
            # Check SL hit
            if self.entry_bullish and self.data.Low[-1] < self.sl_price:
                if self.adaptive_sl and self.data.High[-1] >= self.tp_price:
                    self.sl_price = self.entry_price
                else:
                    self.sell()
                    self.trade_active = False
                    self.entry_price = None
            elif not self.entry_bullish and self.data.High[-1] > self.sl_price:
                if self.adaptive_sl and self.data.Low[-1] <= self.tp_price:
                    self.sl_price = self.entry_price
                else:
                    self.buy()
                    self.trade_active = False
                    self.entry_price = None
        
        # Breakout detection (after session ends)
        if not self.trade_active and self.orb_high is not None and self.orb_low is not None and not self.in_session:
            condition_price = self.ema[-1] if self.breakout_condition == 'EMA' else self.data.Close[-1]
            
            is_bull_break = condition_price > self.orb_high
            is_bear_break = condition_price < self.orb_low
            
            if self.use_ema_filter:
                is_bull_break = is_bull_break and self.data.Close[-1] > self.ema[-1]
                is_bear_break = is_bear_break and self.data.Close[-1] < self.ema[-1]
            
            if is_bull_break:
                # Bullish breakout - BUY
                self.entry_price = self.data.Close[-1]
                self.entry_bullish = True
                self.entry_atr = self.atr[-1] if self.atr[-1] is not None else 0.1
                
                # Calculate SL
                if self.sl_method == 'Other Side of ORB':
                    self.sl_price = self.orb_low
                elif self.sl_method == 'Breakout Candle':
                    self.sl_price = self.data.Low[-1]
                elif self.sl_method == 'ATR':
                    self.sl_price = self.entry_price - (self.entry_atr * self.sl_atr_mult)
                elif self.sl_method == 'Pivot Structure':
                    self.sl_price = self.recent_low[-1] if self.recent_low[-1] is not None else self.orb_low
                
                # Calculate TP
                if self.tp_method == 'ATR':
                    self.tp_price = self.entry_price + (self.entry_atr * self.tp_atr_mult)
                elif self.tp_method == 'RR':
                    risk_amount = abs(self.entry_price - self.sl_price)
                    self.tp_price = self.entry_price + (risk_amount * self.rr_multiplier)
                
                self.trade_active = True
                self.buy()
            
            elif is_bear_break:
                # Bearish breakout - SELL
                self.entry_price = self.data.Close[-1]
                self.entry_bullish = False
                self.entry_atr = self.atr[-1] if self.atr[-1] is not None else 0.1
                
                # Calculate SL
                if self.sl_method == 'Other Side of ORB':
                    self.sl_price = self.orb_high
                elif self.sl_method == 'Breakout Candle':
                    self.sl_price = self.data.High[-1]
                elif self.sl_method == 'ATR':
                    self.sl_price = self.entry_price + (self.entry_atr * self.sl_atr_mult)
                elif self.sl_method == 'Pivot Structure':
                    self.sl_price = self.recent_high[-1] if self.recent_high[-1] is not None else self.orb_high
                
                # Calculate TP
                if self.tp_method == 'ATR':
                    self.tp_price = self.entry_price - (self.entry_atr * self.tp_atr_mult)
                elif self.tp_method == 'RR':
                    risk_amount = abs(self.entry_price - self.sl_price)
                    self.tp_price = self.entry_price - (risk_amount * self.rr_multiplier)
                
                self.trade_active = True
                self.sell()


