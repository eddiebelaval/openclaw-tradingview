import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 6
    trend_mode = "Auto"
    
    def init(self):
        self.swings = []
        self.last_swing_idx = -1
        self.last_swing_price = 0
        self.last_swing_is_high = False
        
    def _find_pivot_high(self, idx):
        if idx < self.pivot_len or idx >= len(self.data.Close) - self.pivot_len:
            return None
        high_vals = self.data.High[idx - self.pivot_len:idx + self.pivot_len + 1]
        if len(high_vals) == 0:
            return None
        center_val = self.data.High[idx]
        if all(center_val >= high_vals):
            return center_val
        return None
    
    def _find_pivot_low(self, idx):
        if idx < self.pivot_len or idx >= len(self.data.Close) - self.pivot_len:
            return None
        low_vals = self.data.Low[idx - self.pivot_len:idx + self.pivot_len + 1]
        if len(low_vals) == 0:
            return None
        center_val = self.data.Low[idx]
        if all(center_val <= low_vals):
            return center_val
        return None
    
    def _push_alternating(self, point_type, idx, price):
        if len(self.swings) == 0:
            self.swings.append({'type': point_type, 'idx': idx, 'price': price})
        else:
            last = self.swings[-1]
            if last['type'] == point_type:
                if (point_type == 'high' and price >= last['price']) or \
                   (point_type == 'low' and price <= last['price']):
                    self.swings[-1] = {'type': point_type, 'idx': idx, 'price': price}
            else:
                self.swings.append({'type': point_type, 'idx': idx, 'price': price})
        
        if len(self.swings) > 120:
            self.swings.pop(0)
    
    def _get_last_pivot(self, pivot_type):
        for i in range(len(self.swings) - 1, -1, -1):
            if self.swings[i]['type'] == pivot_type:
                return self.swings[i]
        return None
    
    def _get_last_pivot_after(self, pivot_type, from_idx):
        for i in range(len(self.swings) - 1, -1, -1):
            if self.swings[i]['type'] == pivot_type and self.swings[i]['idx'] > from_idx:
                return self.swings[i]
        return None
    
    def next(self):
        current_idx = len(self.data) - 1
        
        if current_idx >= self.pivot_len:
            ph = self._find_pivot_high(current_idx - self.pivot_len)
            if ph is not None:
                self._push_alternating('high', current_idx - self.pivot_len, ph)
            
            pl = self._find_pivot_low(current_idx - self.pivot_len)
            if pl is not None:
                self._push_alternating('low', current_idx - self.pivot_len, pl)
        
        if len(self.swings) >= 2:
            last_high = self._get_last_pivot('high')
            last_low = self._get_last_pivot('low')
            
            auto_bull = last_low is not None and (last_high is None or last_low['idx'] > last_high['idx'])
            use_bull = auto_bull if self.trend_mode == "Auto" else self.trend_mode == "Bullish"
            
            if use_bull and last_low is not None:
                ctrl_high = self._get_last_pivot_after('high', last_low['idx'])
                x2 = ctrl_high['idx'] if ctrl_high is not None else current_idx
                y2 = ctrl_high['price'] if ctrl_high is not None else self.data.High[-1]
                
                if x2 > last_low['idx']:
                    slope = (y2 - last_low['price']) / (x2 - last_low['idx']) if x2 != last_low['idx'] else 0
                    
                    line_1x1_price = last_low['price'] + slope * 1.0 * (current_idx - last_low['idx'])
                    
                    if self.data.Close[-1] < line_1x1_price and len(self.data) > last_low['idx'] + 5:
                        if not self.position:
                            self.buy()
                    elif self.data.Close[-1] > line_1x1_price and self.position:
                        self.position.close()
            
            elif not use_bull and last_high is not None:
                ctrl_low = self._get_last_pivot_after('low', last_high['idx'])
                x2 = ctrl_low['idx'] if ctrl_low is not None else current_idx
                y2 = ctrl_low['price'] if ctrl_low is not None else self.data.Low[-1]
                
                if x2 > last_high['idx']:
                    slope = (y2 - last_high['price']) / (x2 - last_high['idx']) if x2 != last_high['idx'] else 0
                    
