import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # ZigZag parameters
    zz_pct = 0.005  # 0.5%
    zz_atr_len = 14
    zz_atr_mul = 1.5
    zz_mode = "Percentage"  # "Percentage" or "ATR"
    
    # Oscillator parameters
    osc_type = "RSI"
    osc_len = 14
    osc_smooth = 1
    
    # Detection parameters
    show_reg = True
    show_hid = False
    show_live = True
    show_conf = True
    
    # Filter parameters
    min_bars = 3
    min_leg_pct = 0.0
    max_ratio = 0.0
    min_osc_dv = 0.0
    use_obos = False
    ob_lvl = 70.0
    os_lvl = 30.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate oscillator based on type
        if self.osc_type == "RSI":
            osc_raw = self.I(pta.rsi, close, length=self.osc_len)
        elif self.osc_type == "CCI":
            osc_raw = self.I(pta.cci, high, low, close, length=self.osc_len)
        elif self.osc_type == "MFI":
            hlc3 = (high + low + close) / 3
            osc_raw = self.I(pta.mfi, high, low, close, self.data.Volume, length=self.osc_len)
        elif self.osc_type == "Stoch %K":
            stoch = self.I(pta.stoch, high, low, close, k=self.osc_len, d=3)
            osc_raw = stoch.iloc[:, 0] if stoch is not None else self.I(pta.rsi, close, length=self.osc_len)
        elif self.osc_type == "Williams %R":
            osc_raw = self.I(pta.willr, high, low, close, length=self.osc_len)
        elif self.osc_type == "ROC":
            osc_raw = self.I(pta.roc, close, length=self.osc_len)
        elif self.osc_type == "CMO":
            osc_raw = self.I(pta.cmo, close, length=self.osc_len)
        else:
            osc_raw = self.I(pta.rsi, close, length=self.osc_len)
        
        # Apply smoothing if needed
        if self.osc_smooth > 1:
            self.osc = self.I(pta.ema, osc_raw, length=self.osc_smooth)
        else:
            self.osc = osc_raw
        
        # ATR for ZigZag
        self.atr = self.I(pta.atr, high, low, close, length=self.zz_atr_len)
        
        # Store zigzag pivot data
        self.pv_prices = []
        self.pv_bars = []
        self.pv_oscs = []
        self.pv_types = []  # 1=high, -1=low
        
        # Live tracking state
        self.dir = 0  # 0=init, 1=up, -1=down
        self.ext_price = None
        self.ext_bar = None
        self.ext_osc = None
        
        # Signal tracking for trading
        self.last_signal_type = None  # "bull", "bear", "hid_bull", "hid_bear"
        self.last_signal_bar = -100
        
    def rev_from_high(self, ext_price):
        """Check if reversal from high"""
        if self.zz_mode == "ATR":
            return self.data.Low[-1] < ext_price - self.zz_atr_mul * self.atr[-1]
        else:
            return self.data.Low[-1] < ext_price * (1.0 - self.zz_pct)
    
    def rev_from_low(self, ext_price):
        """Check if reversal from low"""
        if self.zz_mode == "ATR":
            return self.data.High[-1] > ext_price + self.zz_atr_mul * self.atr[-1]
        else:
            return self.data.High[-1] > ext_price * (1.0 + self.zz_pct)
    
    def find_prev_same(self, pv_type):
        """Find last confirmed pivot of given type"""
        for k in range(len(self.pv_types) - 1, -1, -1):
            if self.pv_types[k] == pv_type:
                return k
        return -1
    
    def find_prev_same_2(self, pv_type):
        """Find second-to-last confirmed pivot of given type"""
        found = 0
        for k in range(len(self.pv_types) - 1, -1, -1):
            if self.pv_types[k] == pv_type:
                found += 1
                if found == 2:
                    return k
        return -1
    
    def classify_div(self, pv_type, p1, o1, p2, o2):
        """Classify divergence: 0=none, 1=reg bear, 2=reg bull, 3=hid bear, 4=hid bull"""
        if pv_type == 1:  # High
            if self.show_reg and p2 > p1 and o2 < o1:
                return 1  # Regular bearish
            elif self.show_hid and p2 < p1 and o2 > o1:
                return 3  # Hidden bearish
        elif pv_type == -1:  # Low
            if self.show_reg and p2 < p1 and o2 > o1:
                return 2  # Regular bullish
            elif self.show_hid and p2 > p1 and o2 < o1:
                return 4  # Hidden bullish
        return 0
    
    def leg_frac(self, start, end):
        """Compute leg size as fraction"""
        if start == 0:
            return 0
        return abs(end - start) / abs(start)
    
    def passes_filters(self, pv_type, b1, b2, o2, o1, leg_size, prev_leg):
        """Check if divergence passes all filters"""
        if b2 - b1 < self.min_bars:
            return False
        if self.min_osc_dv > 0.0 and abs(o2 - o1) < self.min_osc_dv:
            return False
        if self.min_leg_pct > 0.0 and leg_size < self.min_leg_pct:
            return False
        if self.max_ratio > 0.0 and prev_leg is not None and prev_leg > 0.0:
            if leg_size / prev_leg >= self.max_ratio:
                return False
        if self.use_obos:
            if pv_type == 1 and o2 < self.ob_lvl:
                return False
            if pv_type == -1 and o2 > self.os_lvl:
                return False
        return True
    
    def next(self):
        if len(self.data) < 2 or self.osc[-1] is None or np.isnan(self.osc[-1]):
            return
        
        # Initialize direction
        if self.dir == 0:
            self.ext_price = self.data.High[-1]
            self.ext_bar = len(self.data) - 1
            self.ext_osc = self.osc[-1]
            self.dir = 1
        
        # Track extremes and confirm pivots
        elif self.dir == 1:
            # Tracking UP
            if self.data.High[-1] > self.ext_price:
                self.ext_price = self.data.High[-1]
                self.ext_bar = len(self.data) - 1
                self.ext_osc = self.osc[-1]
            
            if self.rev_from_high(self.ext_price):
                # Confirm HIGH pivot
                self.pv_prices.append(self.ext_price)
                self.pv_bars.append(self.ext_bar)
                self.pv_oscs.append(self.ext_osc)
                self.pv_types.append(1)
                
                # Check for confirmed divergence
                if self.show_conf:
                    prev_idx = self.find_prev_same_2(1)
                    if prev_idx >= 0:
                        p1, o1, b1 = self.pv_prices[prev_idx], self.pv_oscs[prev_idx], self.pv_bars[prev_idx]
                        p2, o2, b2 = self.ext_price, self.ext_osc, self.ext_bar
                        
                        dv = self.classify_div(1, p1, o1, p2, o2)
                        if dv != 0:
                            sz = len(self.pv_prices)
                            cur_leg = self.leg_frac(self.pv_prices[sz - 2], p2) if sz >= 2 else 0.0
                            prv_leg = self.leg_frac(self.pv_prices[prev_idx - 1], p1) if prev_idx >= 1 else None
                            
                            if self.passes_filters(1, b1, b2, o2, o1, cur_leg, prv_leg):
                                if dv == 1:
                                    self.last_signal_type = "bear"
                                elif dv == 2:
                                    self.last_signal_type = "bull"
                                elif dv == 3:
                                    self.last_signal_type = "hid_bear"
                                elif dv == 4:
                                    self.last_signal_type = "hid_bull"
                                self.last_signal_bar = len(self.data) - 1
                
                # Begin tracking DOWN
                self.dir = -1
                self.ext_price = self.data.Low[-1]
                self.ext_bar = len(self.data) - 1
                self.ext_osc = self.osc[-1]
        
        elif self.dir == -1:
            # Tracking DOWN
            if self.data.Low[-1] < self.ext_price:
                self.ext_price = self.data.Low[-1]
                self.ext_bar = len(self.data) - 1
                self.ext_osc = self.osc[-1]
            
            if self.rev_from_low(self.ext_price):
                # Confirm LOW pivot
                self.pv_prices.append(self.ext_price)
                self.pv_bars.append(self.ext_bar)
                self.pv_oscs.append(self.ext_osc)
                self.pv_types.append(-1)
                
                # Check for confirmed divergence
                if self.show_conf:
                    prev_idx = self.find_prev_same_2(-1)
                    if prev_idx >= 0:
                        p1, o1, b1 = self.pv_prices[prev_idx], self.pv_oscs[prev_idx], self.pv_bars[prev_idx]
                        p2, o2, b2 = self.ext_price, self.ext_osc, self.ext_bar
                        
                        dv = self.classify_div(-1, p1, o1, p2, o2)
                        if dv != 0:
                            sz = len(self.pv_prices)
                            cur_leg = self.leg_frac(self.pv_prices[sz - 2], p2) if sz >= 2 else 0.0
                            prv_leg = self.leg_frac(self.pv_prices[prev_idx - 1], p1) if prev_idx >= 1 else None
                            
                            if self.passes_filters(-1, b1, b2, o2, o1, cur_leg, prv_leg):
                                if dv == 1:
                                    self.last_signal_type = "bear"
                                elif dv == 2:
                                    self.last_signal_type = "bull"
                                elif dv == 3:
                                    self.last_signal_type = "hid_bear"
                                elif dv == 4:
                                    self.last_signal_type = "hid_bull"
                                self.last_signal_bar = len(self.data) - 1
                
                # Begin tracking UP
                self.dir = 1
                self.ext_price = self.data.High[-1]
                self.ext_bar = len(self.data) - 1
                self.ext_osc = self.osc[-1]
        
        # Live divergence detection and trading
        if self.show_live and self.dir != 0:
            prev_idx = self.find_prev_same(self.dir)
            if prev_idx >= 0:
                p1, o1, b1 = self.pv_prices[prev_idx], self.pv_oscs[prev_idx], self.pv_bars[prev_idx]
                p2, o2, b2 = self.ext_price, self.ext_osc, len(self.data) - 1
                
                dv = self.classify_div(self.dir, p1, o1, p2, o2)
                if dv != 0:
                    sz = len(self.pv_prices)
                    cur_leg = self.leg_frac(self.pv_prices[sz - 1], p2) if sz >= 1 else 0.0
                    prv_leg = self.leg_frac(self.pv_prices[prev_idx - 1], p1) if prev_idx >= 1 else None
                    
                    if self.passes_filters(self.dir, b1, b2, o2, o1, cur_leg, prv_leg):
                        if dv == 2 and len(self.data) - self.last_signal_bar > 3:
                            if not self.position:
                                self.buy()
                        elif dv == 1 and len(self.data) - self.last_signal_bar > 3:
                            if self.position:
                                self.position.close()


