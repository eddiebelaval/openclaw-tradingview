import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Volume Profile parameters
    vp_len = 100
    vp_bins = 20
    
    # Liquidity Zones parameters
    lz_len = 100
    lz_bins = 30
    lz_mult = 1.5
    lz_max = 8
    
    # MTF parameters
    mtf_piv = 5
    mtf_max = 3
    mtf_back = 200
    
    # ATR Predictive Range parameters
    pr_atr = 14
    pr_mult = 1.5
    pr_fwd = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR for predictive range
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.pr_atr) or pd.Series(0, index=close.index))
        
        # Calculate highest and lowest for volume profile
        self.vp_high = self.I(lambda: high.rolling(self.vp_len).max())
        self.vp_low = self.I(lambda: low.rolling(self.vp_len).min())
        
        # Calculate highest and lowest for liquidity zones
        self.lz_high = self.I(lambda: high.rolling(self.lz_len).max())
        self.lz_low = self.I(lambda: low.rolling(self.lz_len).min())
        
        # Volume average for liquidity zones
        self.lz_vol_avg = self.I(lambda: volume.rolling(20).mean())
        
        # Tracking state for zones
        self.poc_price = None
        self.vah_price = None
        self.val_price = None
        self.lz_levels = []
        self.last_update_bar = -1
        self.buy_signal_active = False
        self.sell_signal_active = False

    def next(self):
        # Only update profiles and levels on new bars (avoid recalculation)
        if len(self.data) <= self.vp_len:
            return
        
        current_bar = len(self.data) - 1
        
        # Update profiles on last bar
        if current_bar != self.last_update_bar:
            self._update_volume_profile()
            self._update_liquidity_zones()
            self.last_update_bar = current_bar
        
        # Trading logic based on profiles and levels
        current_price = self.data.Close[-1]
        
        # Buy signal: price touches VAL (support from above) and bounces
        if self.val_price is not None:
            if self.data.Low[-1] <= self.val_price <= self.data.High[-1]:
                if not self.position:
                    self.buy_signal_active = True
            
            if self.buy_signal_active and current_price > self.val_price:
                if not self.position:
                    self.buy()
                self.buy_signal_active = False
        
        # Sell signal: price touches VAH (resistance from below) and reverses
        if self.vah_price is not None:
            if self.data.Low[-1] <= self.vah_price <= self.data.High[-1]:
                if self.position:
                    self.sell_signal_active = True
            
            if self.sell_signal_active and current_price < self.vah_price:
                if self.position:
                    self.sell()
                self.sell_signal_active = False
        
        # Stop loss at opposite extreme of range
        if self.position:
            if current_price < self.vp_low[-1] * 0.99:
                self.sell()
            elif current_price > self.vp_high[-1] * 1.01:
                self.sell()

    def _update_volume_profile(self):
        """Calculate Volume Profile: POC, VAH, VAL"""
        if len(self.data) < self.vp_len:
            return
        
        vp_hi = self.vp_high[-1]
        vp_lo = self.vp_low[-1]
        vp_rng = vp_hi - vp_lo
        
        if vp_rng <= 0:
            return
        
        # Initialize bin volumes
        vp_bin_vol = [0.0] * self.vp_bins
        bin_sz = vp_rng / self.vp_bins
        
        # Accumulate volume in bins
        for i in range(self.vp_len):
            idx = min(self.vp_bins - 1, max(0, int((self.data.Close[-(self.vp_len - i)] - vp_lo) / bin_sz)))
            vp_bin_vol[idx] += self.data.Volume[-(self.vp_len - i)]
        
        # Find POC
        max_vol = max(vp_bin_vol)
        if max_vol == 0:
            return
        
        poc_idx = vp_bin_vol.index(max_vol)
        
        # Calculate Value Area (70% of volume)
        total_vol = sum(vp_bin_vol)
        va_target = total_vol * 0.70
        va_lo = poc_idx
        va_hi = poc_idx
        va_acc = vp_bin_vol[poc_idx]
        
        while va_acc < va_target:
            can_dn = va_lo > 0
            can_up = va_hi < self.vp_bins - 1
            vol_dn = vp_bin_vol[va_lo - 1] if can_dn else 0.0
            vol_up = vp_bin_vol[va_hi + 1] if can_up else 0.0
            
            if not can_dn and not can_up:
                break
            
            if vol_dn >= vol_up and can_dn:
                va_lo -= 1
                va_acc += vol_dn
            elif can_up:
                va_hi += 1
                va_acc += vol_up
            else:
                break
        
        # Calculate price levels
        self.poc_price = vp_lo + poc_idx * bin_sz + bin_sz * 0.5
        self.vah_price = vp_lo + va_hi * bin_sz + bin_sz
        self.val_price = vp_lo + va_lo * bin_sz

    def _update_liquidity_zones(self):
        """Calculate Liquidity Zones based on volume concentration and delta"""
        if len(self.data) < self.lz_len:
            return
        
        lz_hi = self.lz_high[-1]
        lz_lo = self.lz_low[-1]
        lz_rng = lz_hi - lz_lo
        
        if lz_rng <= 0:
            return
        
        # Build per-bin accumulators
        lz_bin_tot = [0.0] * self.lz_bins
        lz_bin_bull = [0.0] * self.lz_bins
        lz_bin_sz = lz_rng / self.lz_bins
        
        for i in range(self.lz_len):
            b_idx = min(self.lz_bins - 1, max(0, int((self.data.Close[-(self.lz_len - i)] - lz_lo) / lz_bin_sz)))
            lz_bin_tot[b_idx] += self.data.Volume[-(self.lz_len - i)]
            if self.data.Close[-(self.lz_len - i)] > self.data.Open[-(self.lz_len - i)]:
                lz_bin_bull[b_idx] += self.data.Volume[-(self.lz_len - i)]
        
        # Average volume per bin
        lz_total = sum(lz_bin_tot)
        lz_avg_bin = lz_total / self.lz_bins if self.lz_bins > 0 else 1.0
        lz_threshold = lz_avg_bin * self.lz_mult
        
        # Collect qualifying bins
        lz_qual = []
        for i in range(self.lz_bins):
            bv = lz_bin_tot[i]
            if bv >= lz_threshold:
                bul_v = lz_bin_bull[i]
                ber_v = bv - bul_v
                delta = (bul_v - ber_v) / bv if bv > 0 else 0.0
                mid_p = lz_lo + i * lz_bin_sz + lz_bin_sz * 0.5
                lz_qual.append((mid_p, bv, delta))
        
        # Sort by volume descending
        lz_qual.sort(key=lambda x: x[1], reverse=True)
        
        # Store top zones
        self.lz_levels = lz_qual[:self.lz_max]


