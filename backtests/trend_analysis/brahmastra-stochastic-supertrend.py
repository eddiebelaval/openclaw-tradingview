import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLength = 10
    atrMult = 3.0
    kLength = 14
    dLength = 3
    kSmoothing = 3
    obLevel = 80
    osLevel = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hl2 = (high + low) / 2

        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)

        # Supertrend calculation (manual, non-repainting)
        def calc_supertrend():
            atr_vals = pta.atr(high, low, close, length=self.atrLength)
            if atr_vals is None:
                return pd.Series(np.nan, index=close.index)
            
            raw_upper = hl2 + self.atrMult * atr_vals
            raw_lower = hl2 - self.atrMult * atr_vals
            
            upper_band = pd.Series(index=close.index, dtype=float)
            lower_band = pd.Series(index=close.index, dtype=float)
            trend = pd.Series(index=close.index, dtype=int)
            st_value = pd.Series(index=close.index, dtype=float)
            
            upper_band.iloc[0] = raw_upper.iloc[0]
            lower_band.iloc[0] = raw_lower.iloc[0]
            trend.iloc[0] = 1
            st_value.iloc[0] = lower_band.iloc[0]
            
            for i in range(1, len(close)):
                if close.iloc[i-1] > upper_band.iloc[i-1]:
                    upper_band.iloc[i] = max(raw_upper.iloc[i], upper_band.iloc[i-1])
                else:
                    upper_band.iloc[i] = raw_upper.iloc[i]
                
                if close.iloc[i-1] < lower_band.iloc[i-1]:
                    lower_band.iloc[i] = min(raw_lower.iloc[i], lower_band.iloc[i-1])
                else:
                    lower_band.iloc[i] = raw_lower.iloc[i]
                
                if close.iloc[i] > upper_band.iloc[i-1]:
                    trend.iloc[i] = 1
                elif close.iloc[i] < lower_band.iloc[i-1]:
                    trend.iloc[i] = -1
                else:
                    trend.iloc[i] = trend.iloc[i-1]
                
                st_value.iloc[i] = lower_band.iloc[i] if trend.iloc[i] == 1 else upper_band.iloc[i]
            
            return st_value, trend, upper_band, lower_band
        
        result = self.I(calc_supertrend)
        self.st_value = result[0] if isinstance(result, tuple) else result
        self.trend = result[1] if isinstance(result, tuple) else pd.Series(1, index=close.index)
        self.upper_band = result[2] if isinstance(result, tuple) else pd.Series(np.nan, index=close.index)
        self.lower_band = result[3] if isinstance(result, tuple) else pd.Series(np.nan, index=close.index)

        # Stochastic calculation
        def calc_stoch():
            stoch = pta.stoch(high, low, close, k=self.kLength, d=self.dLength, smooth_k=self.kSmoothing)
            if stoch is None or stoch.empty:
                return pd.Series(50, index=close.index), pd.Series(50, index=close.index)
            k_col = [col for col in stoch.columns if 'STOCHk' in col or 'K' in col]
            d_col = [col for col in stoch.columns if 'STOCHd' in col or 'D' in col]
            smooth_k = stoch[k_col[0]] if k_col else pd.Series(50, index=close.index)
            smooth_d = stoch[d_col[0]] if d_col else pd.Series(50, index=close.index)
            return smooth_k.fillna(50), smooth_d.fillna(50)
        
        stoch_result = self.I(calc_stoch)
        self.smoothK = stoch_result[0] if isinstance(stoch_result, tuple) else pd.Series(50, index=close.index)
        self.smoothD = stoch_result[1] if isinstance(stoch_result, tuple) else pd.Series(50, index=close.index)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Get current values
        trend = self.trend[-1] if len(self.trend) > 0 else 1
        trend_prev = self.trend[-2] if len(self.trend) > 1 else 1
        smooth_k = self.smoothK[-1] if len(self.smoothK) > 0 else 50
        smooth_d = self.smoothD[-1] if len(self.smoothD) > 0 else 50
        smooth_k_prev = self.smoothK[-2] if len(self.smoothK) > 1 else 50
        smooth_d_prev = self.smoothD[-2] if len(self.smoothD) > 1 else 50
        
        # Stochastic conditions
        bullish_stoch = (smooth_k_prev <= smooth_d_prev and smooth_k > smooth_d) and smooth_k < 30
        bearish_stoch = (smooth_k_prev >= smooth_d_prev and smooth_k < smooth_d) and smooth_k > 70
        
        # Entry conditions
        buy_condition = trend == 1 and bullish_stoch
        sell_condition = trend == -1 and bearish_stoch
        
        # Execute trades
        if buy_condition and not self.position:
            self.buy()
        elif sell_condition and self.position:
            self.position.close()