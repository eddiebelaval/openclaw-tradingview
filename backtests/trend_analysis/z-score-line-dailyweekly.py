import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 21
    offset = 30
    malength = 13
    upper_line = 5.1
    lower_line = -4.7

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Linear regression calculation
        def linreg(data, length, offset):
            result = pd.Series(index=data.index, dtype=float)
            for i in range(len(data)):
                if i < length - 1:
                    result.iloc[i] = np.nan
                else:
                    x = np.arange(length)
                    y = data.iloc[i - length + 1:i + 1].values
                    coeffs = np.polyfit(x, y, 1)
                    result.iloc[i] = coeffs[0] * (length - 1 - offset) + coeffs[1]
            return result
        
        # Calculate linear regression
        reg = self.I(lambda: linreg(close, self.length, self.offset))
        
        # Calculate residuals and stdev
        def calc_residual_stdev(data, length):
            reg_0 = linreg(data, length, 0)
            residuals = data - reg_0
            result = pd.Series(index=data.index, dtype=float)
            for i in range(len(data)):
                if i < length - 1:
                    result.iloc[i] = np.nan
                else:
                    result.iloc[i] = residuals.iloc[i - length + 1:i + 1].std()
            return result
        
        residual_stdev = self.I(lambda: calc_residual_stdev(close, self.length))
        
        # Calculate residuals
        residual = self.I(lambda: close - linreg(close, self.length, self.offset))
        
        # Calculate z-score
        def calc_zscore(residual, residual_stdev):
            zscore = pd.Series(index=residual.index, dtype=float)
            for i in range(len(residual)):
                if pd.isna(residual.iloc[i]) or pd.isna(residual_stdev.iloc[i]):
                    zscore.iloc[i] = 0.0
                elif residual_stdev.iloc[i] != 0:
                    zscore.iloc[i] = residual.iloc[i] / residual_stdev.iloc[i]
                else:
                    zscore.iloc[i] = 0.0
            return zscore
        
        self.zscore = self.I(lambda: calc_zscore(residual, residual_stdev))
        
