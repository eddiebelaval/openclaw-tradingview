import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Timeframe settings
    i_tf1 = "15"
    i_tf2 = "60"
    i_tf3 = "240"
    i_tf4 = "D"
    
    # Weighting
    i_w1 = 0.15
    i_w2 = 0.25
    i_w3 = 0.30
    i_w4 = 0.30
    
    # Calculation settings
    i_ma_fast = 8
    i_ma_slow = 21
    i_rsi_len = 14
    i_macd_fast = 12
    i_macd_slow = 26
    i_macd_sig = 9
    
    # Thresholds
    i_strong_thresh = 60
    i_weak_thresh = 30
    
    # Trend integration
    i_use_trend = True
    i_trend_ma = 200
    i_trend_weight = 0.2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate bias components
        self.ma_fast = self.I(pta.ema, close, length=self.i_ma_fast)
        self.ma_slow = self.I(pta.ema, close, length=self.i_ma_slow)
        self.rsi = self.I(pta.rsi, close, length=self.i_rsi_len)
        
        # MACD components
        self.macd_line = self.I(lambda: pta.ema(close, length=self.i_macd_fast) - pta.ema(close, length=self.i_macd_slow))
        self.macd_signal = self.I(lambda: pta.ema(self.macd_line, length=self.i_macd_sig))
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Trend MA
        self.trend_ma = self.I(pta.ema, close, length=self.i_trend_ma)
        
        # Aggregate bias (simplified calculation)
        self.smooth_bias = self.I(self._calc_smooth_bias, close, high, low)
        
    def _calc_smooth_bias(self, close, high, low):
        result = pd.Series(index=close.index, dtype=float)
        for i in range(len(close)):
            if i < max(self.i_ma_slow, self.i_rsi_len, self.i_macd_slow):
                result.iloc[i] = 0
                continue
            
            # MA component
            ma_fast = self.ma_fast[i] if i < len(self.ma_fast) else 0
            ma_slow = self.ma_slow[i] if i < len(self.ma_slow) else 0
            ma_diff = (ma_fast - ma_slow) / ma_slow * 100 if ma_slow != 0 else 0
            ma_score = max(min(ma_diff * 10, 100), -100)
            
            # Price position
            c = close.iloc[i]
            price_pos = 0.0
            if c > ma_fast and ma_fast > ma_slow:
                price_pos = 100
            elif c < ma_fast and ma_fast < ma_slow:
                price_pos = -100
            elif c > ma_slow:
                price_pos = 50
            elif c < ma_slow:
                price_pos = -50
            
            # RSI component
            rsi_val = self.rsi[i] if i < len(self.rsi) else 50
            rsi_score = (rsi_val - 50) * 2
            
            # MACD component
            macd_hist = (self.macd_line[i] - self.macd_signal[i]) if i < len(self.macd_line) else 0
            atr_val = self.atr[i] if i < len(self.atr) and self.atr[i] else 1
            macd_score = (macd_hist / atr_val * 50) if atr_val > 0 else 0
            macd_score = max(min(macd_score, 100), -100)
            
            # Composite
            composite = ma_score * 0.35 + price_pos * 0.30 + rsi_score * 0.15 + macd_score * 0.20
            result.iloc[i] = composite
        
        return pta.ema(result, length=3)
    
    def next(self):
        bias = self.smooth_bias[-1] if len(self.smooth_bias) > 0 else 0
        
        trend_ma_val = self.trend_ma[-1] if len(self.trend_ma) > 0 else self.data.Close[-1]
        close_price = self.data.Close[-1]
        above_trend = close_price > trend_ma_val
        
        # Adjust bias with trend
        adjusted_bias = bias
        if self.i_use_trend:
            if above_trend and bias > 0:
                adjusted_bias = bias * (1 + self.i_trend_weight)
            elif not above_trend and bias < 0:
                adjusted_bias = bias * (1 + self.i_trend_weight)
            elif above_trend and bias < 0:
                adjusted_bias = bias * (1 - self.i_trend_weight * 0.5)
            elif not above_trend and bias > 0:
                adjusted_bias = bias * (1 - self.i_trend_weight * 0.5)
        
        adjusted_bias = max(min(adjusted_bias, 100), -100)
        
        # Trading logic
        if len(self.smooth_bias) > 1:
            prev_bias = self.smooth_bias[-2]
            
            # Buy signal: strong bullish bias with upward momentum
            if (adjusted_bias >= self.i_strong_thresh and 
                prev_bias < self.i_strong_thresh and 
                not self.position):
                self.buy()
            
