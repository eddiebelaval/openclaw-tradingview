    def _calculate_supertrend(self, high, low, close):
        hl2 = (high + low) / 2.0
        atr = pta.atr(high, low, close, length=self.atr_lookback)
        if atr is None:
            return pd.Series(0, index=close.index)
        basis = hl2
        dev = self.st_factor * atr
        upper_band = basis + dev
        lower_band = basis - dev
        
        supertrend = pd.Series(0.0, index=close.index)
        for i in range(len(close)):
            if i == 0:
                supertrend.iloc[i] = hl2.iloc[i]
            else:
                if close.iloc[i] <= upper_band.iloc[i]:
                    supertrend.iloc[i] = upper_band.iloc[i]
                else:
                    supertrend.iloc[i] = lower_band.iloc[i]
        return supertrend

    def _calculate_st_direction(self, high, low, close):
        st_line = self._calculate_supertrend(high, low, close)
        direction = pd.Series(0.0, index=close.index)
        for i in range(1, len(close)):
            if close.iloc[i] > st_line.iloc[i]:
                direction.iloc[i] = -1.0
            else:
                direction.iloc[i] = 1.0
        return direction

    def _calc_ma_dev(self, close, offset):
        shifted_close = close.shift(offset)
        ma = self._resolve_ma(shifted_close.shift(1), self.ma_period)
        if ma is None or ma.iloc[-1] == 0:
            return pd.Series(0, index=close.index)
        return (shifted_close - ma) / (ma + 0.00001)

    def _calc_rsi_sig_dist(self, rsi_series):
        sig = pta.sma(rsi_series.shift(1), length=self.signal_smooth)
        if sig is None or sig.iloc[-1] == 0:
            return pd.Series(0, index=rsi_series.index)
        return (rsi_series - sig) / (sig + 0.00001)

    def _calc_choppiness(self, high, low, close, offset):
        shifted_high = high.shift(offset)
        shifted_low = low.shift(offset)
        shifted_close = close.shift(offset)
        
        tr = pta.true_range(shifted_high, shifted_low, shifted_close)
        if tr is None:
            return pd.Series(50, index=high.index)
        
        tr_sum = tr.rolling(window=self.chop_period).sum()
        highest = shifted_high.rolling(window=self.chop_period).max()
        lowest = shifted_low.rolling(window=self.chop_period).min()
        
        range_val = highest - lowest
        range_val = range_val.replace(0, 0.00001)
        
        chop = 100.0 * np.log10(tr_sum / range_val) / np.log10(self.chop_period)
        return chop.fillna(50)

    def _resolve_ma(self, src, period):
        if self.feature_ma_type == "SMA":
            return pta.sma(src, length=period)
        elif self.feature_ma_type == "EMA":
            return pta.ema(src, length=period)
        elif self.feature_ma_type == "WMA":
            return pta.wma(src, length=period)
        elif self.feature_ma_type == "HMA":
            return pta.hma(src, length=period)
        else:
            return pta.sma(src, length=period)

    def _zscore_norm(self, src):
        mean = src.rolling(window=self.norm_window).mean()
        std = src.rolling(window=self.norm_window).std()
        std = std.replace(0, 0.00001)
        return (src - mean) / std

