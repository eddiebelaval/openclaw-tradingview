import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Main Settings
    engine = "Efficiency"
    fast_len = 8
    slow_len = 21
    signal_len = 7
    mode = "MACD"
    
    # Filters
    use_divergence = True
    div_lookback = 30
    use_zero_cross = True
    
    # Advanced
    smooth_factor = 0.7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate adaptive MAs based on engine selection
        if self.engine == "Efficiency":
            self.fast_ma = self.I(self._engine_efficiency, close, self.fast_len)
            self.slow_ma = self.I(self._engine_efficiency, close, self.slow_len)
        elif self.engine == "Volatility":
            self.fast_ma = self.I(self._engine_volatility, close, high, low, self.fast_len)
            self.slow_ma = self.I(self._engine_volatility, close, high, low, self.slow_len)
        elif self.engine == "Fractal":
            self.fast_ma = self.I(self._engine_fractal, close, self.fast_len)
            self.slow_ma = self.I(self._engine_fractal, close, self.slow_len)
        elif self.engine == "Momentum":
            self.fast_ma = self.I(self._engine_momentum, close, self.fast_len)
            self.slow_ma = self.I(self._engine_momentum, close, self.slow_len)
        elif self.engine == "Volume":
            self.fast_ma = self.I(self._engine_volume, close, volume, self.fast_len)
            self.slow_ma = self.I(self._engine_volume, close, volume, self.slow_len)
