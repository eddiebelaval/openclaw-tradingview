    def _safe_div(self, num, den, fallback=0.0):
        """Safe division helper"""
        if isinstance(num, pd.Series) and isinstance(den, pd.Series):
            result = pd.Series(fallback, index=num.index)
            mask = (den != 0) & (~num.isna()) & (~den.isna())
            result[mask] = num[mask] / den[mask]
            return result
        else:
            return num / den if den != 0 and not pd.isna(num) and not pd.isna(den) else fallback

    def _efficiency_ratio(self, src, length):
        """Kaufman Efficiency Ratio"""
        direction = np.abs(src - src.shift(length))
        volatility = src.diff().abs().rolling(length).sum()
        return self._safe_div(direction, volatility, 0.5)

    def _adaptive_ema(self, src, alpha):
        """Adaptive EMA core"""
        alpha = np.clip(alpha, 0.01, 1.0)
        return src.ewm(alpha=alpha, adjust=False).mean()

    def _engine_efficiency(self, src, length):
        """Engine: Efficiency (Kaufman AMA style)"""
        er = self._efficiency_ratio(src, length)
        fast_sc = 2.0 / 3.0
        slow_sc = 2.0 / 31.0
        sc = (er * (fast_sc - slow_sc) + slow_sc) ** 2
        return self._adaptive_ema(src, sc)

    def _engine_volatility(self, close, high, low, length):
        """Engine: Volatility (ATR-based)"""
        atr = pta.atr(high, low, close, length=length)
        atr_sma = atr.rolling(length * 2).mean()
        vol_ratio = self._safe_div(atr, atr_sma, 1.0)
        base_alpha = 2.0 / (length + 1.0)
        alpha = np.clip(base_alpha * vol_ratio, 0.01, 1.0)
        return self._adaptive_ema(close, alpha)

    def _engine_fractal(self, src, length):
        """Engine: Fractal (Hurst-inspired)"""
        half = max(2, int(length / 2))
        range_full = src.rolling(length).max() - src.rolling(length).min()
        range_h1 = src.rolling(half).max() - src.rolling(half).min()
        range_h2 = src.shift(half).rolling(half).max() - src.shift(half).rolling(half).min()
        sum_half = range_h1 + range_h2
        
        frac_dim = pd.Series(1.5, index=src.index)
        mask = (range_full > 0) & (sum_half > 0)
        frac_dim[mask] = 1.0 + np.log(sum_half[mask]) / np.log(2.0 * range_full[mask])
        
        alpha = np.exp(-4.6 * (frac_dim - 1.0))
        alpha = np.clip(alpha, 0.01, 1.0)
        return self._adaptive_ema(src, alpha)

    def _engine_momentum(self, src, length):
        """Engine: Momentum (ROC-based)"""
        roc = (src - src.shift(length)) / src.shift(length) * 100.0
        roc_abs = roc.abs()
        roc_max = roc_abs.rolling(length * 2).max()
        norm = roc_abs / roc_max
        norm = norm.fillna(0.5)
        norm = np.clip(norm, 0, 1.0)
        
        base_alpha = 2.0 / (length + 1.0)
        alpha = np.clip(base_alpha + norm * (1.0 - base_alpha) * 0.5, 0.01, 1.0)
        return self._adaptive_ema(src, alpha)

    def _engine_volume(self, src, volume, length):
        """Engine: Volume"""
        vol_sma = volume.rolling(length).mean()
        vol_ratio = self._safe_div(volume, vol_sma, 1.0)
        vol_ratio = vol_ratio.fillna(1.0)
        
        base_alpha = 2.0 / (length + 1.0)
        alpha = np.clip(base_alpha * np.sqrt(np.maximum(vol_ratio, 0.01)), 0.01, 1.0)
        return self._adaptive_ema(src, alpha)

    def _engine_composite(self, close, high, low, volume, length):
        """Engine: Composite (blended)"""
        e1 = self._engine_efficiency(close, length)
        e2 = self._engine_volatility(close, high, low, length)
        e3 = self._engine_fractal(close, length)
        e4 = self._engine_momentum(close, length)
        e5 = self._engine_volume(close, volume, length)
        
        has_vol = volume.sum() > 0
        if has_vol:
            result = e1 * 0.30 + e2 * 0.20 + e3 * 0.20 + e4 * 0.15 + e5 * 0.15
        else:
            result = e1 * 0.35 + e2 * 0.25 + e3 * 0.25 + e4 * 0.15
        return result

    def _jurik_smooth(self, src, length, phase):
        """Jurik-style signal smoothing"""
        beta = 0.45 * (length - 1.0) / (0.45 * (length - 1.0) + 2.0)
        alpha_j = beta ** 3
        
        e0 = pd.Series(0.0, index=src.index)
        e1 = pd.Series(0.0, index=src.index)
        e2 = pd.Series(0.0, index=src.index)
        
        for i in range(len(src)):
            safe_src = src.iloc[i] if not pd.isna(src.iloc[i]) else 0.0
            e0_val = safe_src if i == 0 else (1.0 - alpha_j) * safe_src + alpha_j * e0.iloc[i-1]
            e0.iloc[i] = e0_val
            
            e1_val = (safe_src - e0_val) * (1.0 - beta) if i == 0 else (safe_src - e0_val) * (1.0 - beta) + beta * e1.iloc[i-1]
            e1.iloc[i] = e1_val
            
            target = e0_val + phase * e1_val
            e2_val = target if i == 0 else (target - e2.iloc[i-1]) * ((1.0 - alpha_j) ** 2) + (alpha_j ** 2) * e2.iloc[i-1]
            e2.iloc[i] = e2_val
        
        return e2

    def _calc_oscillator(self, fast_ma, slow_ma, close):
        """Calculate oscillator based on mode"""
        if self.mode == "PPO":
            return self._safe_div(fast_ma - slow_ma, slow_ma, 0.0) * 100.0
        else:
            return fast_ma - slow_ma

    def next(self):
        # Check warmup
        if len(self.data) < self.warmup_bars:
            return

        osc_val = self.osc[-1] if len(self.osc) > 0 else 0.0
        signal_val = self.signal_line[-1] if len(self.signal_line) > 0 else 0.0
        
        # Crossover signals
        bull_cross = crossover(self.osc, self.signal_line)
        bear_cross = crossover(self.signal_line, self.osc)
        
        # Zero line crosses
        zero_bull_cross = self.use_zero_cross and crossover(self.osc, 0)
        zero_bear_cross = self.use_zero_cross and crossover(0, self.osc)
        
        # Trading logic: Buy on bullish crossover, sell on bearish crossover
        if bull_cross or zero_bull_cross:
            if not self.position:
                self.buy()
        elif bear_cross or zero_bear_cross:
            if self.position:
                self.position.close()