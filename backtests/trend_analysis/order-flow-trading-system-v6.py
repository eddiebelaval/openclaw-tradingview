import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Feature Engine
    i_obi_depth = 10
    i_cvd_len = 50
    i_ti_len = 10
    i_vol_short = 14
    i_vol_long = 50
    i_liq_depth = 20
    
    # Regime Classifier
    i_ema_fast = 9
    i_ema_slow = 21
    i_atr_len = 14
    i_trend_thresh = 0.5
    i_of_thresh = 0.3
    i_vol_low = 0.7
    i_vol_high = 1.5
    i_liq_min = 0.2
    
    # Signal Engine
    i_w1 = 0.30
    i_w2 = 0.25
    i_w3 = 0.20
    i_w4 = 0.15
    i_w5 = 0.10
    i_sig_thresh = 0.40
    i_abs_delta = 1.5
    i_abs_eps = 0.1
    
    # Market Making
    i_mm_spread_min = 0.05
    i_mm_gamma = 0.1
    i_mm_k = 1.5
    
    # Risk
    i_kelly_frac = 0.25
    i_max_inv = 0.10
    
    # Adaptive Learning
    i_eta = 0.01
    i_adapt_on = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume Delta
        bar_range = high - low
        close_pos = (close - low) / (bar_range + 1e-10)
        close_pos = close_pos.clip(0, 1)
        self.buy_vol = self.I(lambda: volume * close_pos)
        self.sell_vol = self.I(lambda: volume * (1 - close_pos))
        self.delta = self.I(lambda: self.buy_vol - self.sell_vol)
        
        # CVD
        self.cvd = self.I(lambda: self.delta.cumsum())
        self.cvd_ma = self.I(lambda: pta.ema(self.cvd, length=self.i_cvd_len) or pd.Series(0, index=self.cvd.index))
        self.cvd_slope_raw = self.I(lambda: (self.cvd_ma - self.cvd_ma.shift(self.i_cvd_len)) / self.i_cvd_len)
        self.cvd_slope_max = self.I(lambda: self.cvd_slope_raw.abs().rolling(200).max())
        self.cvd_slope_norm = self.I(lambda: self.cvd_slope_raw / (self.cvd_slope_max + 1e-10))
        
        # OBI
        hlc3 = (high + low + close) / 3
        rolling_mid = self.I(lambda: pta.ema(hlc3, length=self.i_obi_depth) or pd.Series(hlc3.mean(), index=hlc3.index))
        bid_proxy = self.I(lambda: volume.where(close < rolling_mid, 0))
        ask_proxy = self.I(lambda: volume.where(close > rolling_mid, 0))
        sum_bid = self.I(lambda: bid_proxy.rolling(self.i_obi_depth).sum())
        sum_ask = self.I(lambda: ask_proxy.rolling(self.i_obi_depth).sum())
        self.obi = self.I(lambda: (sum_bid - sum_ask) / (sum_bid + sum_ask + 1e-10))
        
        # Microprice
        vwap_val = self.I(lambda: pta.vwap(high, low, close, volume) or close.ewm(span=20).mean())
        mid_price = (high + low) / 2.0
        self.micro_price = self.I(lambda: (vwap_val * self.buy_vol + mid_price * self.sell_vol) / (self.buy_vol + self.sell_vol + 1e-10))
        micro_vs_mid = self.I(lambda: (self.micro_price - mid_price) / (mid_price + 1e-10))
        micro_max = self.I(lambda: micro_vs_mid.abs().rolling(200).max())
        self.micro_norm = self.I(lambda: micro_vs_mid / (micro_max + 1e-10))
        
        # Trade Intensity
        vol_ma = self.I(lambda: pta.ema(volume, length=self.i_ti_len) or pd.Series(volume.mean(), index=volume.index))
        trade_intensity = self.I(lambda: volume / (vol_ma + 1e-10) - 1.0)
        self.ti_clamped = self.I(lambda: trade_intensity.clip(0, 3.0) / 3.0)
        
        # Volatility
        log_ret = self.I(lambda: np.log(close / close.shift(1)))
        var_short = self.I(lambda: pta.ema(log_ret * log_ret, length=self.i_vol_short) or pd.Series(0.0001, index=log_ret.index))
        var_long = self.I(lambda: pta.ema(log_ret * log_ret, length=self.i_vol_long) or pd.Series(0.0001, index=log_ret.index))
        self.sigma_short = self.I(lambda: np.sqrt(var_short.clip(lower=0)))
        self.sigma_long = self.I(lambda: np.sqrt(var_long.clip(lower=0)))
        self.vol_state = self.I(lambda: self.sigma_short / (self.sigma_long + 1e-10))
        
        # Liquidity Score
        spread_pct = self.I(lambda: (high - low) / (mid_price + 1e-10))
        spread_norm = self.I(lambda: pta.ema(spread_pct, length=self.i_liq_depth) or pd.Series(0.0001, index=spread_pct.index))
        vol_depth = self.I(lambda: pta.ema(volume, length=self.i_liq_depth) or pd.Series(volume.mean(), index=volume.index))
        vol_depth_ma = self.I(lambda: pta.ema(vol_depth, length=self.i_liq_depth*2) or vol_depth)
        liq_score_raw = self.I(lambda: vol_depth / (vol_depth_ma + 1e-10))
        liq_score = self.I(lambda: liq_score_raw / (spread_norm * 1000 + 1e-10))
        self.liq_norm = self.I(lambda: pta.ema(liq_score, length=20) or pd.Series(1.0, index=liq_score.index))
        
        # Regime
        self.ema_fast = self.I(lambda: pta.ema(close, length=self.i_ema_fast) or close.ewm(span=self.i_ema_fast).mean())
        self.ema_slow = self.I(lambda: pta.ema(close, length=self.i_ema_slow) or close.ewm(span=self.i_ema_slow).mean())
        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.i_atr_len) or pd.Series(high - low).rolling(self.i_atr_len).mean())
        self.trend_score = self.I(lambda: (self.ema_fast - self.ema_slow).abs() / (self.atr_val + 1e-10))
        self.of_dominance = self.I(lambda: self.cvd_slope_norm.abs())
        
        # HTF Bias
        self.ema_htf = self.I(lambda: pta.ema(close, length=200) or close.ewm(span=200).mean())
        
        # Score
        self.score_long = self.I(lambda: self._calculate_score())
        
        # Absorption
        delta_threshold = self.I(lambda: pta.ema(self.delta.abs(), length=20) or pd.Series(self.delta.abs().mean(), index=self.delta.index) * self.i_abs_delta)
        price_chg_pct = self.I(lambda: (close - close.shift(1)).abs() / (close.shift(1) + 1e-10) * 100)
        self.buy_absorption = self.I(lambda: (self.delta < -delta_threshold) & (price_chg_pct < self.i_abs_eps))
        self.sell_absorption = self.I(lambda: (self.delta > delta_threshold) & (price_chg_pct < self.i_abs_eps))
        
        # Divergences
        self.bearish_div = self.I(lambda: (close > close.shift(5)) & (self.delta < self.delta.shift(5)))
        self.bullish_div = self.I(lambda: (close < close.shift(5)) & (self.delta > self.delta.shift(5)))
        
        # Breakouts
        recent_high = self.I(lambda: high.rolling(20).max().shift(1))
        recent_low = self.I(lambda: low.rolling(20).min().shift(1))
        self.breakout_up = self.I(lambda: (close > recent_high) & (self.obi > 0) & (self.cvd_slope_norm > 0) & (self.sigma_short > self.sigma_short.shift(3)))
        self.breakout_dn = self.I(lambda: (close < recent_low) & (self.obi < 0) & (self.cvd_slope_norm < 0) & (self.sigma_short > self.sigma_short.shift(3)))
        
        # Regime state
        self.regime = 2  # RANGE
        self.inventory = 0.0
        self.w1, self.w2, self.w3, self.w4, self.w5 = self.i_w1, self.i_w2, self.i_w3, self.i_w4, self.i_w5

    def _calculate_score(self):
        try:
            w_sum = self.w1 + self.w2 + self.w3 + self.w4 + self.w5
            if w_sum == 0:
                w_sum = 1.0
            w1n = self.w1 / w_sum
            w2n = self.w2 / w_sum
            w3n = self.w3 / w_sum
            w4n = self.w4 / w_sum
            w5n = self.w5 / w_sum
            
            score = (w1n * self.cvd_slope_norm[-1] +
                    w2n * self.obi[-1] +
                    w3n * self.micro_norm[-1] +
                    w4n * self.ti_clamped[-1] +
                    w5n * ((1.0 if self.data.Close[-1] > self.ema_htf[-1] else -1.0) * 0.5))
            return pd.Series(np.clip(score, -1.0, 1.0), index=pd.RangeIndex(1))
        except:
            return pd.Series(0.0)

    def next(self):
        # Update regime
        if (self.trend_score[-1] > self.i_trend_thresh and 
            self.of_dominance[-1] > self.i_of_thresh):
            self.regime = 1  # TREND
        elif self.vol_state[-1] > self.i_vol_high:
            self.regime = 3  # VOLATILE
        elif self.liq_norm[-1] < self.i_liq_min:
            self.regime = 4  # ILLIQUID
        elif self.vol_state[-1] < self.i_vol_low:
            self.regime = 2  # RANGE
        else:
            self.regime = 2  # RANGE
        
        # Entry conditions
        long_entry = self.score_long[-1] > self.i_sig_thresh and self.regime != 4
        short_entry = self.score_long[-1] < -self.i_sig_thresh and self.regime != 4
        abs_long = self.buy_absorption[-1] and self.regime == 1
        abs_short = self.sell_absorption[-1] and self.regime == 1
        
        # Exit conditions
        exit_long = self.score_long[-1] < 0 or (self.regime == 3 and self.bearish_div[-1])
        exit_short = self.score_long[-1] > 0 or (self.regime == 3 and self.bullish_div[-1])
        
        # Execute trades
        if self.position:
            if self.position.is_long and exit_long:
                self.position.close()
            elif self.position.is_short and exit_short:
                self.position.close()
        else:
            if long_entry or abs_long:
                self.buy()
                self.inventory += 1.0
            elif short_entry or abs_short:
                self.sell()
                self.inventory -= 1.0
        
        # Adaptive weight update
        if self.i_adapt_on and len(self.data) > 1:
            try:
                fwd_return = self.data.Close[-1] - self.data.Close[-2]
                reward_pnl = 0
                if len(self) > 1:
                    reward_pnl = fwd_return if long_entry else (-fwd_return if short_entry else 0)
                risk_penalty = self.sigma_short[-1] * 0.5
                reward = reward_pnl - risk_penalty
                
                if abs(reward) > 0:
                    self.w1 = max(0.01, self.w1 + self.i_eta * reward * self.cvd_slope_norm[-1])
                    self.w2 = max(0.01, self.w2 + self.i_eta * reward * self.obi[-1])
                    self.w3 = max(0.01, self.w3 + self.i_eta * reward * self.micro_norm[-1])
                    self.w4 = max(0.01, self.w4 + self.i_eta * reward * self.ti_clamped[-1])
                    self.w5 = max(0.01, self.w5 + self.i_eta * reward * ((1.0 if self.data.Close[-1] > self.ema_htf[-1] else -1.0) * 0.5))
            except:
                pass


