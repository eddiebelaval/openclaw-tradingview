import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_length = 10
    show_only_last = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate pivot highs and lows
        self.pivot_high = self.I(self._calc_pivot_high, high, self.pivot_length)
        self.pivot_low = self.I(self._calc_pivot_low, low, self.pivot_length)
        
        # State tracking
        self.pivots = []
        self.last_pattern_end = 0
        self.last_wave_targets = None
        self.position_entry_bar = None

    def _calc_pivot_high(self, high_series, length):
        """Calculate pivot highs"""
        result = pd.Series(np.nan, index=high_series.index)
        for i in range(length, len(high_series) - length):
            if high_series.iloc[i] == high_series.iloc[i-length:i+length+1].max():
                result.iloc[i] = high_series.iloc[i]
        return result

    def _calc_pivot_low(self, low_series, length):
        """Calculate pivot lows"""
        result = pd.Series(np.nan, index=low_series.index)
        for i in range(length, len(low_series) - length):
            if low_series.iloc[i] == low_series.iloc[i-length:i+length+1].min():
                result.iloc[i] = low_series.iloc[i]
        return result

    def _is_valid_uptrend(self, pA, pB, pC):
        """Check if pattern is valid uptrend"""
        return (not pA['is_high'] and pB['is_high'] and not pC['is_high'] and
                pB['price'] > pA['price'] and pB['price'] > pC['price'] and
                pC['price'] > pA['price'])

    def _is_valid_downtrend(self, pA, pB, pC):
        """Check if pattern is valid downtrend"""
        return (pA['is_high'] and not pB['is_high'] and pC['is_high'] and
                pB['price'] < pA['price'] and pB['price'] < pC['price'] and
                pC['price'] < pA['price'])

    def _calc_targets(self, pA, pB, pC, direction):
        """Calculate Hosoda targets"""
        time_n = pC['bar_index'] + (pB['bar_index'] - pA['bar_index'])
        
        if direction == 1:  # Uptrend
            v = pB['price'] + (pB['price'] - pC['price'])
            n = pC['price'] + (pB['price'] - pA['price'])
            e = pB['price'] + (pB['price'] - pA['price'])
            nt = pC['price'] + (pC['price'] - pA['price'])
        else:  # Downtrend
            v = pB['price'] - (pC['price'] - pB['price'])
            n = pC['price'] - (pA['price'] - pB['price'])
            e = pB['price'] - (pA['price'] - pB['price'])
            nt = pC['price'] - (pA['price'] - pC['price'])
        
        return {'v': v, 'n': n, 'e': e, 'nt': nt, 'time_n': time_n}

    def next(self):
        current_idx = len(self.data) - 1
        
        # Check for new pivot highs and lows
        if not np.isnan(self.pivot_high[-1]):
            self.pivots.append({
                'bar_index': current_idx - self.pivot_length,
                'price': self.pivot_high[-1],
                'is_high': True
            })
        
        if not np.isnan(self.pivot_low[-1]):
            self.pivots.append({
                'bar_index': current_idx - self.pivot_length,
                'price': self.pivot_low[-1],
                'is_high': False
            })
        
        # Keep only last 10 pivots
        if len(self.pivots) > 10:
            self.pivots.pop(0)
        
        # Check for wave pattern
        if len(self.pivots) >= 3 and (not np.isnan(self.pivot_high[-1]) or not np.isnan(self.pivot_low[-1])):
            pA = self.pivots[-3]
            pB = self.pivots[-2]
            pC = self.pivots[-1]
            
            is_valid_uptrend = self._is_valid_uptrend(pA, pB, pC)
            is_valid_downtrend = self._is_valid_downtrend(pA, pB, pC)
            is_not_overlapping = pA['bar_index'] >= self.last_pattern_end
            
            if (is_valid_uptrend or is_valid_downtrend) and is_not_overlapping:
                direction = 1 if is_valid_uptrend else -1
                targets = self._calc_targets(pA, pB, pC, direction)
                
                self.last_pattern_end = pC['bar_index']
                self.last_wave_targets = targets
                self.position_entry_bar = current_idx
                
                # Entry logic based on wave direction
                if direction == 1:  # Uptrend wave
                    if not self.position:
                        self.buy()
                else:  # Downtrend wave
                    if self.position:
                        self.sell()
        
        # Exit logic based on targets
        if self.last_wave_targets and self.position:
            current_price = self.data.Close[-1]
            
            # For uptrend: exit at target N or if price falls below entry
            if self.last_wave_targets['time_n'] <= current_idx:
                if current_price >= self.last_wave_targets['n']:
                    self.sell()
            
            # Safety exit if price retraces significantly
            if current_price < self.data.Close[self.position_entry_bar]:
                self.sell()
        
        # Exit short positions
        if self.last_wave_targets and not self.position:
            current_price = self.data.Close[-1]
            
            if self.last_wave_targets['time_n'] <= current_idx:
                if current_price <= self.last_wave_targets['n']:
                    if not self.position:
                        self.buy()


