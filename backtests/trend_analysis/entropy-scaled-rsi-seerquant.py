import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    emaLen = 8
    entropyLen = 20
    neutralZone = 5
    emaChoice = "RMA"
    entMode = "Returns (Binned)"
    stability = 0.60
    atrLen = 14
    bins = 12
    upper_limit = 90
    lower_limit = 10
    mid_line = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Calculate entropy and adaptive alpha
        self.ersi = self.I(self._calculate_ersi, close, high, low)
        
        # Calculate smoothed ERSI
        self.smoothed = self.I(lambda: self._apply_ma(self.ersi, self.emaLen, self.emaChoice))

    def _calculate_ersi(self, close):
        close_arr = close.values
        high_arr = pd.Series(self.data.High).values
        low_arr = pd.Series(self.data.Low).values
        
        ersi_values = np.full(len(close_arr), np.nan)
        
        # Parameters
        atrMult = 3.0 - 2.0 * self.stability
        entropySmoothLen = int(round(1 + self.stability * 6))
        alphaSmoothLen = int(round(1 + self.stability * 6))
        
        avgGain = np.nan
        avgLoss = np.nan
        seeded = False
        
        entropy_smoothed = np.full(len(close_arr), np.nan)
        alpha_smoothed = np.full(len(close_arr), np.nan)
        
        for i in range(1, len(close_arr)):
            # Calculate change
            chg = close_arr[i] - close_arr[i-1]
            
            # Calculate entropy (simplified returns binned approach)
            if i >= self.entropyLen:
                ret_window = (close_arr[i-self.entropyLen+1:i+1] - close_arr[i-self.entropyLen:i]) / np.abs(close_arr[i-self.entropyLen:i] + 1e-10)
                ret_lo = np.min(ret_window)
                ret_hi = np.max(ret_window)
                span = ret_hi - ret_lo
                
                if span > 1e-10:
                    h = 0.0
                    for bin_idx in range(self.bins):
                        lo = ret_lo + span * (bin_idx / self.bins)
                        hi = ret_lo + span * ((bin_idx + 1) / self.bins)
                        count = 0
                        for j in range(self.entropyLen):
                            rj = ret_window[j]
                            if bin_idx == self.bins - 1:
                                in_bin = (rj >= lo and rj <= hi)
                            else:
                                in_bin = (rj >= lo and rj < hi)
                            count += 1 if in_bin else 0
                        p = count / self.entropyLen
                        if p > 0:
                            h -= p * np.log2(p)
                    entropy_raw = min(1.0, max(0.0, h / np.log2(self.bins)))
                else:
                    entropy_raw = 0.0
                
                if not np.isnan(entropy_smoothed[i-1]):
                    entropy_smoothed[i] = entropy_raw * (2.0 / (entropySmoothLen + 1)) + entropy_smoothed[i-1] * (1.0 - 2.0 / (entropySmoothLen + 1))
                else:
                    entropy_smoothed[i] = entropy_raw
            else:
                if i > 0 and not np.isnan(entropy_smoothed[i-1]):
                    entropy_smoothed[i] = entropy_smoothed[i-1]
                else:
                    entropy_smoothed[i] = 0.0
            
            # Adaptive alpha
            entropy_val = entropy_smoothed[i] if not np.isnan(entropy_smoothed[i]) else 0.0
            fastAlpha = 2.0 / (max(self.length / 2.0, 2.0) + 1.0)
            slowAlpha = 2.0 / (self.length * 2.0 + 1.0)
            alphaRaw = fastAlpha + entropy_val * (slowAlpha - fastAlpha)
            
            if not np.isnan(alpha_smoothed[i-1]):
                alpha_smoothed[i] = alphaRaw * (2.0 / (alphaSmoothLen + 1)) + alpha_smoothed[i-1] * (1.0 - 2.0 / (alphaSmoothLen + 1))
            else:
                alpha_smoothed[i] = alphaRaw
            
            alpha = alpha_smoothed[i]
            
            # ATR shock limiter
            if not np.isnan(self.atr[-1]):
                cap = atrMult * self.atr[-1]
                delta = np.clip(chg, -cap, cap)
            else:
                delta = chg
            
            gainRaw = max(delta, 0)
            lossRaw = abs(min(delta, 0))
            
            # Seed with SMA
            if i == self.length:
                seedGain = np.mean([(max(close_arr[j] - close_arr[j-1], 0)) for j in range(1, i+1)])
                seedLoss = np.mean([abs(min(close_arr[j] - close_arr[j-1], 0)) for j in range(1, i+1)])
                avgGain = seedGain
                avgLoss = seedLoss
                seeded = True
            elif seeded and i > self.length:
                avgGain = alpha * gainRaw + (1.0 - alpha) * avgGain
                avgLoss = alpha * lossRaw + (1.0 - alpha) * avgLoss
            
            # Calculate ERSI
            if seeded:
                if avgLoss == 0 and avgGain == 0:
                    ersi = 50.0
                elif avgLoss == 0:
                    ersi = 100.0
                elif avgGain == 0:
                    ersi = 0.0
                else:
                    rs = avgGain / avgLoss
                    ersi = 100.0 - (100.0 / (1.0 + rs))
                ersi_values[i] = ersi
        
        return pd.Series(ersi_values)

    def _apply_ma(self, series, length, ma_type):
        if series is None or len(series) == 0:
            return pd.Series(np.nan, index=range(len(self.data)))
        
        if ma_type == "SMA":
            return pta.sma(series, length=length)
        elif ma_type == "EMA":
            return pta.ema(series, length=length)
        elif ma_type == "RMA":
            return pta.rma(series, length=length)
        elif ma_type == "WMA":
            return pta.wma(series, length=length)
        elif ma_type == "VWMA":
            return pta.vwma(series, pd.Series(self.data.Volume), length=length)
        else:
            return pta.sma(series, length=length)

    def next(self):
        if len(self.data) < self.length + self.entropyLen:
            return
        
        ersi_current = self.ersi[-1] if not np.isnan(self.ersi[-1]) else 50
        neutral_low = self.mid_line - self.neutralZone
        neutral_high = self.mid_line + self.neutralZone
        
        # Buy signal: ERSI crosses above neutral zone from below
        if len(self.ersi) > 1:
            ersi_prev = self.ersi[-2] if not np.isnan(self.ersi[-2]) else 50
            if ersi_prev <= neutral_low and ersi_current > neutral_low:
                if not self.position:
                    self.buy()
        
        # Sell signal: ERSI crosses below neutral zone from above
        if len(self.ersi) > 1:
            ersi_prev = self.ersi[-2] if not np.isnan(self.ersi[-2]) else 50
            if ersi_prev >= neutral_high and ersi_current < neutral_high:
                if self.position:
                    self.sell()
        
        # Exit on extreme overbought/oversold
        if ersi_current > self.upper_limit:
            if self.position:
                self.sell()
        elif ersi_current < self.lower_limit:
            if self.position:
                self.sell()


