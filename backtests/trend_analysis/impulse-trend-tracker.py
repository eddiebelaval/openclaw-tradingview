import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    phi = 1.5
    wickThreshold = 0.382
    targetDisplacement = 1.0
    candleCount = 3
    orderBlockDuration = 10

    def init(self):
        self.bullDisp = 0
        self.bearDisp = 0
        self.bullImpulseSignal = []
        self.bearImpulseSignal = []
        self.in_position = False

    def next(self):
        # Calculate candle properties
        body = abs(self.data.Close[-1] - self.data.Open[-1])
        prevBody = abs(self.data.Close[-2] - self.data.Open[-2]) if len(self.data) > 1 else 0
        range1 = self.data.High[-1] - self.data.Low[-1]
        upperWick = self.data.High[-1] - max(self.data.Open[-1], self.data.Close[-1])
        lowerWick = min(self.data.Open[-1], self.data.Close[-1]) - self.data.Low[-1]

        impulseRatio = body / prevBody if prevBody > 0 else float('nan')

        bullWickSuppressed = (upperWick / range1) < self.wickThreshold if range1 > 0 else False
        bearWickSuppressed = (lowerWick / range1) < self.wickThreshold if range1 > 0 else False

        # Bullish/bearish candle acceleration
        bullCandleAccel = (
            self.data.Close[-1] > self.data.Open[-1] and
            bullWickSuppressed and
            (impulseRatio >= self.phi or np.isnan(impulseRatio))
        )

        bearCandleAccel = (
            self.data.Close[-1] < self.data.Open[-1] and
            bearWickSuppressed and
            (impulseRatio >= self.phi or np.isnan(impulseRatio))
        )

        # Cumulative displacement
        if bullCandleAccel:
            self.bullDisp += body
        if bearCandleAccel:
            self.bearDisp += body

        # Gated impulses
        bullImpulse = self.bullDisp >= self.targetDisplacement
        bearImpulse = self.bearDisp >= self.targetDisplacement

        # Reset displacement
        if bullImpulse:
            self.bullDisp = 0
            self.bullImpulseSignal.append(True)
        else:
            self.bullImpulseSignal.append(False)

        if bearImpulse:
            self.bearDisp = 0
            self.bearImpulseSignal.append(True)
        else:
            self.bearImpulseSignal.append(False)

        # Trading logic
        if bullImpulse and not self.position:
            self.buy()
            self.in_position = True
        elif bearImpulse and self.position:
            self.sell()
            self.in_position = False