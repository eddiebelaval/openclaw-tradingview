import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    mad_len = 26
    mad_smooth = 3
    er_len = 10
    mult_min = 2.5
    mult_max = 3.0
    basis_len = 8
    basis_type = "T3"
    t3_vf = 0.85
    trade_mode = "Long/Cash"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hl2 = (high + low) / 2.0

        # Calculate basis MA (T3 by default)
        def calc_basis():
            e1 = pta.ema(close, length=self.basis_len)
            e2 = pta.ema(e1, length=self.basis_len)
            e3 = pta.ema(e2, length=self.basis_len)
            c1 = -(self.t3_vf ** 3)
            c2 = 3.0 * (self.t3_vf ** 2) + 3.0 * (self.t3_vf ** 3)
            c3 = -6.0 * (self.t3_vf ** 2) - 3.0 * self.t3_vf - 3.0 * (self.t3_vf ** 3)
            c4 = 1.0 + 3.0 * self.t3_vf + (self.t3_vf ** 3) + 3.0 * (self.t3_vf ** 2)
            e4 = pta.ema(e3, length=self.basis_len)
            e5 = pta.ema(e4, length=self.basis_len)
            e6 = pta.ema(e5, length=self.basis_len)
            result = c1 * e6 + c2 * e5 + c3 * e4 + c4 * e3
            return result if result is not None else close

        self.basis = self.I(calc_basis)

        # MAD calculation
        def calc_mad():
            rolling_mean = pta.sma(close, length=self.mad_len)
            raw_mad = pta.sma((close - rolling_mean).abs(), length=self.mad_len)
            if self.mad_smooth > 1:
                smooth_mad = pta.ema(raw_mad, length=self.mad_smooth)
                return smooth_mad if smooth_mad is not None else raw_mad
            return raw_mad

        self.mad = self.I(calc_mad)

        # ER calculation
        def calc_er():
            src = hl2
            er_series = pd.Series(0.0, index=close.index)
            for i in range(self.er_len, len(src)):
                net_move = abs(src.iloc[i] - src.iloc[i - self.er_len])
                total_path = sum(abs(src.iloc[j] - src.iloc[j - 1]) for j in range(i - self.er_len + 1, i + 1))
                if total_path > 0:
                    er_series.iloc[i] = min(1.0, net_move / total_path)
                else:
                    er_series.iloc[i] = 0.0
            return er_series

        self.er = self.I(calc_er)

        # Store trend state
        self.trend = 1
        self.st_line_val = None
        self.up_band = None
        self.dn_band = None

    def next(self):
        if len(self.data) < self.mad_len + self.er_len:
            return

        src = (self.data.High[-1] + self.data.Low[-1]) / 2.0
        close = self.data.Close[-1]
        basis = self.basis[-1]
        mad = self.mad[-1]
        er = self.er[-1]

        if pd.isna(basis) or pd.isna(mad) or pd.isna(er):
            return

        # Adaptive multiplier
        adapt_mult = self.mult_max - er * (self.mult_max - self.mult_min)
        band_dist = adapt_mult * mad

        # Band construction
        up_raw = basis + band_dist
        dn_raw = basis - band_dist

        # Ratchet logic
        if self.up_band is None:
            self.up_band = up_raw
            self.dn_band = dn_raw
        else:
            if close < self.up_band:
                self.up_band = min(up_raw, self.up_band)
            else:
                self.up_band = up_raw

            if close > self.dn_band:
                self.dn_band = max(dn_raw, self.dn_band)
            else:
                self.dn_band = dn_raw

        # Trend determination
        old_trend = self.trend
        if self.trend == -1 and close > self.up_band:
            self.trend = 1
        elif self.trend == 1 and close < self.dn_band:
            self.trend = -1

        # Supertrend line
        if self.trend == 1:
            self.st_line_val = self.dn_band
        else:
            self.st_line_val = self.up_band

        # Signal detection
        long_flip = old_trend == -1 and self.trend == 1
        short_flip = old_trend == 1 and self.trend == -1

        # Trading logic
        if long_flip:
            if not self.position:
                self.buy()
        elif short_flip:
            if self.position:
                self.position.close()
            if self.trade_mode == "Long/Short" and not self.position:
                self.buy()  # Signal for short would go here, but backtesting.py doesn't natively support shorts without margin