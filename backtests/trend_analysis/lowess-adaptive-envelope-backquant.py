import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length_input = 200
    bandwidth_input = 0.25
    env_mult_input = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate LOWESS fit and envelope
        self.fitted = self.I(self._calculate_lowess_fit, close)
        self.env_width = self.I(self._calculate_envelope_width, close)
        self.upper_band = self.I(lambda: self.fitted + self.env_width)
        self.lower_band = self.I(lambda: self.fitted - self.env_width)
        
    def _calculate_lowess_fit(self, close_series):
        length = self.length_input
        bandwidth = self.bandwidth_input
        
        if len(close_series) < length:
            return pd.Series(np.nan, index=close_series.index)
        
        fitted_values = []
        
        for end_idx in range(length - 1, len(close_series)):
            start_idx = end_idx - length + 1
            prices = close_series.iloc[start_idx:end_idx + 1].values
            
            fitted = self._lowess_point(prices, length, bandwidth, length - 1)
            fitted_values.append(fitted)
        
        result = pd.Series(np.nan, index=close_series.index)
        result.iloc[length - 1:] = fitted_values
        
        return result
    
    def _lowess_point(self, prices, length, bandwidth, point_idx):
        h = max(bandwidth * length / 2.0, 2.0)
        
        sum_w = 0.0
        sum_wx = 0.0
        sum_wy = 0.0
        sum_wxx = 0.0
        sum_wxy = 0.0
        
        j_start = max(0, int(point_idx - h) - 1)
        j_end = min(length - 1, int(point_idx + h) + 1)
        
        for j in range(j_start, j_end + 1):
            u = abs(float(point_idx - j)) / h
            if u < 1.0:
                w = (1.0 - u ** 3) ** 3
                x = float(j)
                y = prices[j]
                sum_w += w
                sum_wx += w * x
                sum_wy += w * y
                sum_wxx += w * x * x
                sum_wxy += w * x * y
        
        denom = sum_w * sum_wxx - sum_wx * sum_wx
        
        if abs(denom) > 1e-10:
            a = (sum_wxx * sum_wy - sum_wx * sum_wxy) / denom
            b = (sum_w * sum_wxy - sum_wx * sum_wy) / denom
            return a + b * float(point_idx)
        else:
            return prices[point_idx]
    
    def _calculate_envelope_width(self, close_series):
        length = self.length_input
        bandwidth = self.bandwidth_input
        env_mult = self.env_mult_input
        
        if len(close_series) < length:
            return pd.Series(np.nan, index=close_series.index)
        
        env_widths = []
        
        for end_idx in range(length - 1, len(close_series)):
            start_idx = end_idx - length + 1
            prices = close_series.iloc[start_idx:end_idx + 1].values
            
            h = max(bandwidth * length / 2.0, 2.0)
            
            fitted = []
            for i in range(length):
                fitted.append(self._lowess_point(prices, length, bandwidth, i))
            
            abs_res = [abs(prices[i] - fitted[i]) for i in range(length)]
            
            r_win = max(3, int(h * 0.8))
            point_idx = length - 1
            
            r_sum = 0.0
            r_cnt = 0
            r_s = max(0, point_idx - r_win)
            r_e = min(length - 1, point_idx + r_win)
            
            for j in range(r_s, r_e + 1):
                r_sum += abs_res[j]
                r_cnt += 1
            
            env_w = (r_sum / r_cnt) * env_mult if r_cnt > 0 else 0.0
            env_widths.append(env_w)
        
        result = pd.Series(np.nan, index=close_series.index)
        result.iloc[length - 1:] = env_widths
        
        return result
    
    def next(self):
        if len(self.data) < self.length_input:
            return
        
        current_price = self.data.Close[-1]
        current_fitted = self.fitted[-1]
        current_upper = self.upper_band[-1]
        current_lower = self.lower_band[-1]
        
        if np.isnan(current_fitted) or np.isnan(current_upper) or np.isnan(current_lower):
            return
        
        # Entry logic: Buy when price bounces from lower band and is above fitted line
        # Sell when price bounces from upper band and is below fitted line
        
        if len(self.data) > 1:
            prev_price = self.data.Close[-2]
            prev_fitted = self.fitted[-2]
            prev_lower = self.lower_band[-2]
            prev_upper = self.upper_band[-2]
            
            # Buy: price crosses above lower band
            if not self.position and prev_price <= prev_lower and current_price > current_lower:
                if current_price > current_fitted:
                    self.buy()
            
            # Sell: price crosses below upper band
            elif self.position and prev_price >= prev_upper and current_price < current_upper:
                if current_price < current_fitted:
                    self.sell()
            
            # Exit long if price goes below fitted line
            elif self.position and current_price < current_fitted:
                self.sell()