import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fractal_length = 10
    
    def init(self):
        self.pivot_highs = []
        self.pivot_lows = []
        self.fib_levels = [0.0, 0.236, 0.382, 0.5, 0.618, 1.0]
        self.last_valley_price = None
        self.last_valley_index = None
        self.last_swing_high = None
        self.last_swing_low = None
    
    def next(self):
        current_index = len(self.data) - 1
        
        if current_index < self.fractal_length * 2:
            return
        
        high_data = self.data.High
        low_data = self.data.Low
        
        is_pivot_high = self._is_pivot_high(high_data, current_index)
        is_pivot_low = self._is_pivot_low(low_data, current_index)
        
        if is_pivot_low:
            self.last_valley_price = low_data[current_index - self.fractal_length]
            self.last_valley_index = current_index - self.fractal_length
        
        if is_pivot_high and self.last_valley_index is not None and (current_index - self.fractal_length) > self.last_valley_index:
            swing_high = high_data[current_index - self.fractal_length]
            swing_low = self.last_valley_price
            diff = swing_high - swing_low
            
            if diff > 0:
                self.last_swing_high = swing_high
                self.last_swing_low = swing_low
                
                fib_prices = []
                for lvl in self.fib_levels:
                    price = swing_high - (diff * lvl)
                    fib_prices.append(price)
                
                support_level = self.last_swing_low
                resistance_level = self.last_swing_high
                
                mid_level = swing_high - (diff * 0.5)
                
                if len(self.data.Close) > 0:
                    current_price = self.data.Close[-1]
                    
                    if current_price <= support_level * 1.01 and not self.position:
                        self.buy()
                    
                    elif current_price >= resistance_level * 0.99 and self.position:
                        self.sell()
                    
                    elif self.position and current_price <= mid_level:
                        self.sell()
    
    def _is_pivot_high(self, high_data, index):
        if index < self.fractal_length or index >= len(high_data) - self.fractal_length:
            return False
        
        center_idx = index - self.fractal_length
        center_price = high_data[center_idx]
        
        for i in range(center_idx - self.fractal_length, center_idx):
            if i >= 0 and high_data[i] >= center_price:
                return False
        
        for i in range(center_idx + 1, center_idx + self.fractal_length + 1):
            if i < len(high_data) and high_data[i] >= center_price:
                return False
        
        return True
    
    def _is_pivot_low(self, low_data, index):
        if index < self.fractal_length or index >= len(low_data) - self.fractal_length:
            return False
        
        center_idx = index - self.fractal_length
        center_price = low_data[center_idx]
        
        for i in range(center_idx - self.fractal_length, center_idx):
            if i >= 0 and low_data[i] <= center_price:
                return False
        
        for i in range(center_idx + 1, center_idx + self.fractal_length + 1):
            if i < len(low_data) and low_data[i] <= center_price:
                return False
        
        return True


