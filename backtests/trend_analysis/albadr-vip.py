        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        basis = self.basis[-1]
        upper = self.upper[-1]
        lower = self.lower[-1]
        ema200 = self.ema200[-1]
