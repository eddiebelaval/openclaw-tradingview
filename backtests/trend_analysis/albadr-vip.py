        if close > ema200:
            success_buy += 30
        if rsi > 50:
            success_buy += 30
        if close > lower:
            success_buy += 40
        
        success_sell = 0
        if close < ema200:
            success_sell += 30
        if rsi < 50:
            success_sell += 30
        if close < upper:
            success_sell += 40
        
