import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ch_len = 20
    ch_mult = 2.0
    ema_len = 200
    rsi_len = 14
    atr_len = 14
    vol_ma_len = 20
    success_threshold = 60
    volume_multiplier = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Price channel
        self.basis = self.I(pta.sma, close, length=self.ch_len)
        
        # Standard deviation for channel width
        def stdev_calc(x):
            return pta.stdev(x, length=self.ch_len)
        
        self.stdev = self.I(stdev_calc, close)
        
        self.upper = self.basis + (self.ch_mult * self.stdev)
        self.lower = self.basis - (self.ch_mult * self.stdev)
        
        # Technical analysis
        self.ema200 = self.I(pta.ema, close, length=self.ema_len)
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.volMA = self.I(pta.sma, volume, length=self.vol_ma_len)

    def next(self):
        if len(self.data) < self.ema_len:
            return
        
