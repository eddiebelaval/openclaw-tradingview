import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    afficher_debut = True
    afficher_fin = True
    show_bt = True
    asset_type = "Automatique"
    custom_bt_mult = 1.0
    custom_lookback = 300
    trend_filter = False
    ma_length = 200
    final_bt_mult = 3.0
    final_lookback = 500

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate MA for trend filter
        self.ma = self.I(pta.sma, close, length=self.ma_length)
        
        # Calculate Big Trades indicators
        range_size = high - low
        range_size = range_size.replace(0, np.nan)
        
        self.raw_buy_vol = ((close - low) / range_size * volume).fillna(0)
        self.raw_sell_vol = ((high - close) / range_size * volume).fillna(0)
        
        self.avg_buy_vol = self.I(pta.sma, self.raw_buy_vol, length=self.final_lookback)
        self.std_buy_vol = self.I(pta.stdev, self.raw_buy_vol, length=self.final_lookback)
        self.avg_sell_vol = self.I(pta.sma, self.raw_sell_vol, length=self.final_lookback)
        self.std_sell_vol = self.I(pta.stdev, self.raw_sell_vol, length=self.final_lookback)
        
        # Calculate imbalances
        self.est_imb_h = self.I(self._calc_imb_h, high, low, close)
        self.est_imb_b = self.I(self._calc_imb_b, high, low, close)
        
        # Succession detection
        self.succession_h = self.I(self._calc_succession_h, self.est_imb_h)
        self.succession_b = self.I(self._calc_succession_b, self.est_imb_b)
        
        # Track zones
        self.active_zones = []
        self.last_buy_signal = False
        self.last_sell_signal = False

    def _calc_imb_h(self, high, low, close):
        h = pd.Series(high)
        l = pd.Series(low)
        c = pd.Series(close)
        o = pd.Series(self.data.Open)
        
        result = (l > h.shift(2)) & (c.shift(1) > o.shift(1))
        return result.astype(float)

    def _calc_imb_b(self, high, low, close):
        h = pd.Series(high)
        l = pd.Series(low)
        c = pd.Series(close)
        o = pd.Series(self.data.Open)
        
        result = (h < l.shift(2)) & (c.shift(1) < o.shift(1))
        return result.astype(float)

    def _calc_succession_h(self, est_imb_h):
        imb = pd.Series(est_imb_h)
        result = (imb > 0) & (imb.shift(1) > 0)
        return result.astype(float)

    def _calc_succession_b(self, est_imb_b):
        imb = pd.Series(est_imb_b)
        result = (imb > 0) & (imb.shift(1) > 0)
        return result.astype(float)

    def next(self):
        if len(self.data) < 5:
            return
        
        # Get current values
        est_imb_h_curr = self.est_imb_h[-1] > 0
        est_imb_b_curr = self.est_imb_b[-1] > 0
        succession_h_curr = self.succession_h[-1] > 0
        succession_b_curr = self.succession_b[-1] > 0
        succession_h_prev = self.succession_h[-2] > 0 if len(self.succession_h) > 1 else False
        succession_b_prev = self.succession_b[-2] > 0 if len(self.succession_b) > 1 else False
        
        # Big Trades detection
        if len(self.avg_buy_vol) > 1 and len(self.std_buy_vol) > 1:
            thresh_buy = self.avg_buy_vol[-2] + self.std_buy_vol[-2] * self.final_bt_mult
            thresh_sell = self.avg_sell_vol[-2] + self.std_sell_vol[-2] * self.final_bt_mult
            
            raw_buy = self.raw_buy_vol.iloc[-1] if len(self.raw_buy_vol) > 0 else 0
            raw_sell = self.raw_sell_vol.iloc[-1] if len(self.raw_sell_vol) > 0 else 0
            
            is_bt_buy = raw_buy > thresh_buy and (not self.trend_filter or self.data.Close[-1] > self.ma[-1])
            is_bt_sell = raw_sell > thresh_sell and (not self.trend_filter or self.data.Close[-1] < self.ma[-1])
        else:
            is_bt_buy = False
            is_bt_sell = False
        
        # Début d'impulsion detection
        debut_h = self.afficher_debut and (succession_h_curr and not succession_h_prev)
        debut_b = self.afficher_debut and (succession_b_curr and not succession_b_prev)
        
        # Fin d'impulsion detection
        fin_h = self.afficher_fin and (not est_imb_h_curr and succession_h_prev)
        fin_b = self.afficher_fin and (not est_imb_b_curr and succession_b_prev)
        
        # Trading signals
        buy_signal = self.show_bt and is_bt_buy or debut_h or fin_b
        sell_signal = self.show_bt and is_bt_sell or debut_b or fin_h
        
        # Execute trades
        if buy_signal and not self.last_buy_signal:
            if not self.position:
                self.buy()
            self.last_buy_signal = True
        
        if sell_signal and not self.last_sell_signal:
            if self.position:
                self.position.close()
            self.last_sell_signal = True
        
        # Reset signals
        if not buy_signal:
            self.last_buy_signal = False
        if not sell_signal:
            self.last_sell_signal = False


