import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    periodo1 = 32
    periodo2 = 154
    periodo3 = 495

    def init(self):
        close = pd.Series(self.data.Close)
        self.sma32 = self.I(pta.sma, close, length=self.periodo1)
        self.sma154 = self.I(pta.sma, close, length=self.periodo2)
        self.sma495 = self.I(pta.sma, close, length=self.periodo3)

    def next(self):
        # Buy when SMA32 crosses above SMA154 and SMA154 is above SMA495 (uptrend)
        if crossover(self.sma32, self.sma154) and self.sma154[-1] > self.sma495[-1]:
            if not self.position:
                self.buy()
        # Sell when SMA32 crosses below SMA154
        elif crossover(self.sma154, self.sma32):
            if self.position:
                self.sell()