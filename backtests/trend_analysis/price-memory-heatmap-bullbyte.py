import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters
    pivot_len = 5
    merge_dist = 1.0
    atr_len = 14
    
    # Memory parameters
    decay = 0.992
    heat_boost = 1.0
    death_thresh = 0.08
    max_levels = 20
    min_hits = 2
    
    # Detection parameters
    wick_react = True
    wick_min_pct = 0.55
    use_vol = True
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Calculate volume EMA for volume weighting
        volume = pd.Series(self.data.Volume)
        self.vol_ema = self.I(pta.ema, volume, length=20)
        
        # Initialize memory levels storage
        self.memory_levels = []
        self.last_high_heat_zone = False
        
    def next(self):
        if len(self.data) < self.pivot_len + 1:
            return
        
        # Get current ATR value
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.001
        if atr_val == 0:
            atr_val = 0.001
        
        tolerance = atr_val * self.merge_dist
        
        # Detect pivot highs and lows
        if len(self.data) > self.pivot_len * 2:
            # Check for pivot high
            is_pivot_high = True
            if len(self.data) >= self.pivot_len + 1:
                high_val = self.data.High[-self.pivot_len - 1]
                for i in range(1, self.pivot_len + 1):
                    if self.data.High[-self.pivot_len - 1 - i] >= high_val:
                        is_pivot_high = False
                        break
                    if self.data.High[-self.pivot_len - 1 + i] >= high_val:
                        is_pivot_high = False
                        break
                
                if is_pivot_high:
                    self._add_or_merge_level(high_val, tolerance, atr_val)
            
            # Check for pivot low
            is_pivot_low = True
            if len(self.data) >= self.pivot_len + 1:
                low_val = self.data.Low[-self.pivot_len - 1]
                for i in range(1, self.pivot_len + 1):
                    if self.data.Low[-self.pivot_len - 1 - i] <= low_val:
                        is_pivot_low = False
                        break
                    if self.data.Low[-self.pivot_len - 1 + i] <= low_val:
                        is_pivot_low = False
                        break
                
                if is_pivot_low:
                    self._add_or_merge_level(low_val, tolerance, atr_val)
        
        # Decay all levels
        for level in self.memory_levels:
            level['heat'] *= self.decay
        
        # Remove dead levels
        self.memory_levels = [lvl for lvl in self.memory_levels 
                             if lvl['heat'] >= self.death_thresh]
        
        # Limit to max levels
        if len(self.memory_levels) > self.max_levels:
            self.memory_levels.sort(key=lambda x: x['heat'])
            self.memory_levels = self.memory_levels[-self.max_levels:]
        
        # Calculate max heat for normalization
        max_heat = max([lvl['heat'] for lvl in self.memory_levels]) if self.memory_levels else 0.001
        
        # Check if price is in a high-heat zone
        in_hot_zone = False
        for level in self.memory_levels:
            if level['hits'] >= self.min_hits:
                norm = min(level['heat'] / max(max_heat, 0.001), 1.0)
                zone_half = atr_val * 0.12 * 0.5
                price_in_zone = (self.data.Close[-1] >= level['price'] - zone_half and 
                                self.data.Close[-1] <= level['price'] + zone_half)
                
                if norm > 0.5 and level['hits'] >= 3 and price_in_zone:
                    in_hot_zone = True
                    break
        
        # Trading logic based on memory levels
        if self.memory_levels:
            # Sort by heat
            sorted_levels = sorted(self.memory_levels, 
                                 key=lambda x: x['heat'], reverse=True)
            
            top_level = sorted_levels[0]
            
            # Buy signal: Price crosses above a support level with heat
            if (len(self.data) >= 2 and 
                self.data.Close[-2] < top_level['price'] and 
                self.data.Close[-1] > top_level['price'] and 
                top_level['hits'] >= self.min_hits):
                if not self.position:
                    self.buy()
            
            # Sell signal: Price crosses below a resistance level with heat
            elif (len(self.data) >= 2 and 
                  self.data.Close[-2] > top_level['price'] and 
                  self.data.Close[-1] < top_level['price'] and 
                  top_level['hits'] >= self.min_hits):
                if self.position:
                    self.position.close()
            
            # Exit on loss of proximity to hot zone
            if self.position and not in_hot_zone:
                if len(self.data) > 10:
                    self.position.close()
        
        self.last_high_heat_zone = in_hot_zone
    
    def _add_or_merge_level(self, price, tolerance, atr_val):
        """Add a new level or merge with existing nearby level"""
        # Find nearest level
        nearest_idx = -1
        nearest_dist = tolerance
        
        for i, level in enumerate(self.memory_levels):
            dist = abs(level['price'] - price)
            if dist < nearest_dist:
                nearest_dist = dist
                nearest_idx = i
        
        vol_weight = 1.0
        if self.use_vol and len(self.vol_ema) > 0:
            vol_ema_val = self.vol_ema[-1]
            if not np.isnan(vol_ema_val) and vol_ema_val > 0:
                current_vol = self.data.Volume[-1] if self.data.Volume[-1] > 0 else vol_ema_val
                vol_weight = min(2.5, max(0.4, current_vol / vol_ema_val))
        
        boost = self.heat_boost * vol_weight
        
        if nearest_idx >= 0:
            # Merge with existing level
            level = self.memory_levels[nearest_idx]
            w = level['heat']
            level['price'] = (level['price'] * w + price * boost) / (w + boost)
            level['heat'] += boost
            level['hits'] += 1
        else:
            # Create new level
            self.memory_levels.append({
                'price': price,
                'heat': boost,
                'hits': 1,
                'birth_bar': len(self.data)
            })