import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the indicator
    swing_len = 10
    atr_length = 14
    heat_decay = 80
    heat_zone_width = 0.3
    rsi_length = 14
    
    def init(self):
        # Calculate ATR for zone width
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # RSI for momentum
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Volume SMA for comparison
        self.vol_sma = self.I(pta.sma, volume, length=20)
        
        # Swing highs and lows using rolling max/min
        self.swing_high = self.I(lambda: high.rolling(window=self.swing_len*2+1, center=True).max())
        self.swing_low = self.I(lambda: low.rolling(window=self.swing_len*2+1, center=True).min())
        
        # Track state
        self.last_swing_high = None
        self.last_swing_low = None
        self.market_trend = 0  # 1 = bullish, -1 = bearish
        self.last_entry_signal = None
        
    def next(self):
        # Ensure we have enough data
        if len(self.data) < self.swing_len * 2 + 1:
            return
        
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_volume = self.data.Volume[-1]
        
        # Safety checks for indicators
        if (self.atr[-1] is None or np.isnan(self.atr[-1]) or 
            self.rsi[-1] is None or np.isnan(self.rsi[-1]) or
            self.vol_sma[-1] is None or np.isnan(self.vol_sma[-1]) or
            self.swing_high[-1] is None or np.isnan(self.swing_high[-1]) or
            self.swing_low[-1] is None or np.isnan(self.swing_low[-1])):
            return
        
        current_atr = self.atr[-1]
        current_rsi = self.rsi[-1]
        vol_ratio = current_volume / self.vol_sma[-1] if self.vol_sma[-1] > 0 else 1.0
        
        # Update swing point tracking
        if len(self.data) > 1:
            prev_high = self.swing_high[-2]
            prev_low = self.swing_low[-2]
            
            if not np.isnan(prev_high):
                self.last_swing_high = prev_high
            if not np.isnan(prev_low):
                self.last_swing_low = prev_low
        
        # Trading logic based on structure and momentum
        signal_generated = False
        
        # Bullish signals: BOS/CHoCH equivalent + RSI confirmation
        if (self.last_swing_high is not None and 
            current_close > self.last_swing_high and 
            len(self.data) > 1 and 
            self.data.Close[-2] <= self.last_swing_high):
            
            # Bullish break detected
            if current_rsi < 70 and vol_ratio > 0.9:  # Not overbought, normal volume
                self.market_trend = 1
                if not self.position:
                    self.buy()
                    signal_generated = True
        
        # Bearish signals: opposite logic
        elif (self.last_swing_low is not None and 
              current_close < self.last_swing_low and 
              len(self.data) > 1 and 
              self.data.Close[-2] >= self.last_swing_low):
            
            # Bearish break detected
            if current_rsi > 30 and vol_ratio > 0.9:  # Not oversold, normal volume
                self.market_trend = -1
                if self.position:
                    self.sell()
                    signal_generated = True
        
        # Exit conditions based on momentum and structure reversal
        if self.position:
            # Exit if momentum extreme reached and reverses
            if self.position.is_long:
                if current_rsi > 75:  # Overbought
                    self.sell()
                elif (self.last_swing_low is not None and 
                      current_low < self.last_swing_low):
                    # Liquidity sweep - take profit
                    self.sell()
            
            else:  # Short position
                if current_rsi < 25:  # Oversold
                    self.buy()
                elif (self.last_swing_high is not None and 
                      current_high > self.last_swing_high):
                    # Liquidity sweep - take profit
                    self.buy()
        
        # Additional entry on oversold/overbought recovery (mean reversion)
        if not self.position:
            if current_rsi < 20 and len(self.data) > 1 and self.rsi[-2] < current_rsi:
                # RSI oversold and starting to recover
                if vol_ratio > 1.0:  # Above average volume
                    self.buy()
            
            elif current_rsi > 80 and len(self.data) > 1 and self.rsi[-2] > current_rsi:
                # RSI overbought and starting to decline
                if vol_ratio > 1.0:  # Above average volume
                    self.sell()


