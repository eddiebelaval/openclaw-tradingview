import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Compression Engine
    compLen = 20
    compRatio = 0.6
    minBars = 5
    
    # Trade Management
    tpPct = 0.5
    slPct = 0.25
    maxBars = 40
    
    # Momentum Filter
    rsiLen = 14
    rsiObLvl = 75
    rsiOsLvl = 25
    volLen = 20
    useVolFil = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.atr14 = self.I(pta.atr, high, low, close, length=14)
        self.atrSlow = self.I(pta.atr, high, low, close, length=self.compLen * 2)
        self.rsi14 = self.I(pta.rsi, close, length=self.rsiLen)
        self.volMa = self.I(pta.sma, volume, length=self.volLen)
        
        # Vault high/low using rolling max/min
        self.vaultHigh = self.I(lambda: high.rolling(self.compLen).max())
        self.vaultLow = self.I(lambda: low.rolling(self.compLen).min())
        self.vaultMid = self.I(lambda: (high.rolling(self.compLen).max() + low.rolling(self.compLen).min()) / 2)
        
        # State tracking
        self.compBars = 0
        self.active_vaults = []
        self.in_trade = False
        self.trade_entry_bar = None
        self.trade_entry_price = None
        self.trade_is_long = None
        self.trade_tp = None
        self.trade_sl = None

    def next(self):
        if len(self.data) < self.compLen:
            return
        
        # Get current values
        current_atr = self.atr14[-1]
        atr_slow_val = self.atrSlow[-1]
        rsi = self.rsi14[-1]
        vol = self.data.Volume[-1]
        vol_ma = self.volMa[-1]
        
        if atr_slow_val == 0 or pd.isna(atr_slow_val):
            atr_slow_val = 0.0001
        
        is_compressed = current_atr / max(atr_slow_val, 0.0001) < self.compRatio
        
        vault_high = self.vaultHigh[-1]
        vault_low = self.vaultLow[-1]
        
        if pd.isna(vault_high) or pd.isna(vault_low):
            return
        
        # Update compression bar counter
        if is_compressed:
            self.compBars += 1
        else:
            self.compBars = 0
        
        vault_ready = self.compBars >= self.minBars
        
        # Breakout conditions
        bull_break = self.data.Close[-1] > vault_high
        bear_break = self.data.Close[-1] < vault_low
        
        # Volume confirmation
        vol_ok = not self.useVolFil or vol > vol_ma
        
        # Handle active trade
        if self.in_trade and self.trade_entry_bar is not None:
            bars_held = len(self.data) - self.trade_entry_bar
            
            # Check TP
            if self.trade_is_long:
                if self.data.High[-1] >= self.trade_tp:
                    self.sell()
                    self.in_trade = False
                    return
            else:
                if self.data.Low[-1] <= self.trade_tp:
                    self.buy()
                    self.in_trade = False
                    return
            
            # Check SL
            if self.trade_is_long:
                if self.data.Low[-1] <= self.trade_sl:
                    self.sell()
                    self.in_trade = False
                    return
            else:
                if self.data.High[-1] >= self.trade_sl:
                    self.buy()
                    self.in_trade = False
                    return
            
            # Check max bars
            if bars_held >= self.maxBars:
                if self.trade_is_long:
                    self.sell()
                else:
                    self.buy()
                self.in_trade = False
                return
        
        # Entry logic (only if not in trade)
        if not self.in_trade and vault_ready and vol_ok:
            rsi_ok_bull = rsi < self.rsiObLvl
            rsi_ok_bear = rsi > self.rsiOsLvl
            
            # Bull breakout
            if bull_break and rsi_ok_bull:
                self.buy()
                self.in_trade = True
                self.trade_entry_bar = len(self.data)
                self.trade_entry_price = self.data.Close[-1]
                self.trade_is_long = True
                self.trade_tp = self.trade_entry_price * (1 + self.tpPct / 100)
                self.trade_sl = self.trade_entry_price * (1 - self.slPct / 100)
            
            # Bear breakout
            elif bear_break and rsi_ok_bear:
                self.sell()
                self.in_trade = True
                self.trade_entry_bar = len(self.data)
                self.trade_entry_price = self.data.Close[-1]
                self.trade_is_long = False
                self.trade_tp = self.trade_entry_price * (1 - self.tpPct / 100)
                self.trade_sl = self.trade_entry_price * (1 + self.slPct / 100)