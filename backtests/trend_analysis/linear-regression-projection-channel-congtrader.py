import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 100
    mult = 2.0
    extendBars = 30
    pivotLen = 5

    def init(self):
        self.close = pd.Series(self.data.Close)
        self.high = pd.Series(self.data.High)
        self.low = pd.Series(self.data.Low)
        
        # Store linear regression values
        self.slope_vals = []
        self.intercept_vals = []
        self.regVal_vals = []
        self.stdDev_vals = []
        self.n_vals = []
        
        # Pivot tracking
        self.pivot1 = None
        self.pivot2 = None
        self.bar1 = None
        self.bar2 = None
        self.in_uptrend = False
        self.in_downtrend = False
        
        # Calculate linear regression for all bars
        self._calculate_linear_regression()
        
        # Calculate pivots
        self.pivot_highs = self._calculate_pivot_highs()
        self.pivot_lows = self._calculate_pivot_lows()

    def _calculate_linear_regression(self):
        closes = self.close.values
        
        for bar_idx in range(len(closes)):
            if bar_idx < self.length:
                start_idx = 0
                yVals = closes[start_idx:bar_idx + 1]
            else:
                yVals = closes[bar_idx - self.length + 1:bar_idx + 1]
            
            n = len(yVals)
            
            sumX = sum(range(n))
            sumY = np.sum(yVals)
            sumXY = sum(i * yVals[i] for i in range(n))
            sumXX = sum(i * i for i in range(n))
            
            denom = n * sumXX - sumX * sumX
            
            if denom != 0:
                slope = (n * sumXY - sumX * sumY) / denom
                intercept = (sumY - slope * sumX) / n
            else:
                slope = 0.0
                intercept = sumY / n
            
            regVal = slope * (n - 1) + intercept
            
            sumDev = sum((yVals[i] - (slope * i + intercept)) ** 2 for i in range(n))
            stdDev = np.sqrt(sumDev / n)
            
            self.slope_vals.append(slope)
            self.intercept_vals.append(intercept)
            self.regVal_vals.append(regVal)
            self.stdDev_vals.append(stdDev)
            self.n_vals.append(n)

    def _calculate_pivot_highs(self):
        pivot_highs = [np.nan] * len(self.high)
        
        for i in range(self.pivotLen, len(self.high) - self.pivotLen):
            is_pivot = True
            center_val = self.high.iloc[i]
            
            for j in range(1, self.pivotLen + 1):
                if self.high.iloc[i - j] >= center_val or self.high.iloc[i + j] >= center_val:
                    is_pivot = False
                    break
            
            if is_pivot:
                pivot_highs[i] = center_val
        
        return pivot_highs

    def _calculate_pivot_lows(self):
        pivot_lows = [np.nan] * len(self.low)
        
        for i in range(self.pivotLen, len(self.low) - self.pivotLen):
            is_pivot = True
            center_val = self.low.iloc[i]
            
            for j in range(1, self.pivotLen + 1):
                if self.low.iloc[i - j] <= center_val or self.low.iloc[i + j] <= center_val:
                    is_pivot = False
                    break
            
            if is_pivot:
                pivot_lows[i] = center_val
        
        return pivot_lows

    def next(self):
        idx = len(self.data) - 1
        
        if idx >= len(self.slope_vals):
            return
        
        slope = self.slope_vals[idx]
        regVal = self.regVal_vals[idx]
        stdDev = self.stdDev_vals[idx]
        
        trendUp = slope > 0
        trendDown = slope < 0
        
        upperNow = regVal + self.mult * stdDev
        lowerNow = regVal - self.mult * stdDev
        
        # Check for pivot high
        if idx >= self.pivotLen and not np.isnan(self.pivot_highs[idx]):
            if trendDown:
                self.pivot2 = self.pivot1
                self.bar2 = self.bar1
                
                self.pivot1 = self.pivot_highs[idx]
                self.bar1 = idx
                self.in_downtrend = True
                self.in_uptrend = False
        
        # Check for pivot low
        if idx >= self.pivotLen and not np.isnan(self.pivot_lows[idx]):
            if trendUp:
                self.pivot2 = self.pivot1
                self.bar2 = self.bar1
                
                self.pivot1 = self.pivot_lows[idx]
                self.bar1 = idx
                self.in_uptrend = True
                self.in_downtrend = False
        
        # Generate trading signals based on pivots and regression channel
        if self.in_uptrend and self.pivot1 is not None:
            # Buy signal: price near lower channel and uptrend with pivot low
            if self.data.Close[-1] <= lowerNow and not self.position:
                self.buy()
        
        if self.in_downtrend and self.pivot1 is not None:
            # Sell signal: price near upper channel and downtrend with pivot high
            if self.data.Close[-1] >= upperNow and self.position:
                self.sell()
        
        # Exit logic
        if self.position:
            if self.in_downtrend:
                self.sell()
            elif self.data.Close[-1] > regVal + self.mult * stdDev:
                self.sell()
        
        if not self.position and self.in_uptrend:
            if self.data.Close[-1] < lowerNow:
                self.buy()


