import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_mult = 1.5
    mu = 0.6

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=200)
        
        # Calculate threshold
        self.threshold = self.I(lambda: atr * self.atr_mult)
        
        # Initialize L1 Proximal Filter state
        self.z = np.full(len(self.data), np.nan)
        self.v = np.full(len(self.data), 0.0)
        self.trend = np.full(len(self.data), 0, dtype=int)

    def next(self):
        idx = len(self.data) - 1
        src = self.data.Close[-1]
        
        if idx == 0:
            self.z[idx] = src
            self.v[idx] = 0.0
            self.trend[idx] = 0
        else:
            z_prev = self.z[idx - 1]
            v_prev = self.v[idx - 1]
            z_pred = z_prev + v_prev
            
            z_temp = z_pred + self.mu * (src - z_pred)
            
            diff = z_temp - z_prev
            
            if abs(diff) > self.threshold[-1]:
                self.v[idx] = np.sign(diff) * (abs(diff) - self.threshold[-1])
            else:
                self.v[idx] = 0.0
            
            self.z[idx] = z_prev + self.v[idx]
        
        # Trend logic
        if self.z[idx] > self.z[idx - 1] if idx > 0 else False:
            self.trend[idx] = 1
        elif self.z[idx] < self.z[idx - 1] if idx > 0 else False:
            self.trend[idx] = -1
        else:
            self.trend[idx] = self.trend[idx - 1] if idx > 0 else 0
        
        # Detect trend changes
        up_change = (self.trend[idx] == 1 and idx > 0 and self.trend[idx - 1] == -1)
        down_change = (self.trend[idx] == -1 and idx > 0 and self.trend[idx - 1] == 1)
        
        # Trading logic
        if up_change:
            if not self.position:
                self.buy()
        elif down_change:
            if self.position:
                self.sell()


