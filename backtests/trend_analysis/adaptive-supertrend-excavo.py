        high = self.data.High[-1]
        low = self.data.Low[-1]
        src = (high + low) / 2.0
        
        atr_series = pd.Series(self.data.High) - pd.Series(self.data.Low)
        atr_series = atr_series.rolling(window=self.atr_len).mean()
        
