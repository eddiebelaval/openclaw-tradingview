import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 10
    base_mult = 2.5
    use_adapt = True
    adapt_len = 50
    adapt_str = 0.4
    alpha_raw = 8.0
    rec_thres = 1.0
    use_accel = True
    use_mom = False
    mom_len = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.rsi = self.I(pta.rsi, close, length=self.mom_len)
        
        self.trend = 1
        self.band = None
        self.switch_price = None
        self.prev_trend = 1

    def next(self):
        if len(self.data) < self.atr_len + 1:
            return
        
        atr_val = self.atr[-1]
        if atr_val is None or np.isnan(atr_val):
            return
        
