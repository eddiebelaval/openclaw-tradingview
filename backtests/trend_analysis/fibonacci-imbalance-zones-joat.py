import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fib_lookback = 50
    pivot_strength = 5
    min_fvg_size = 0.3
    confluence_tol = 0.3
    min_confluence_strength = 2
    institutional_threshold = 0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)

        # Calculate volume average
        self.vol_avg = self.I(pta.sma, volume, length=20)

        # Swing detection using highest/lowest
        self.highest_high = self.I(lambda: high.rolling(self.fib_lookback).max())
        self.lowest_low = self.I(lambda: low.rolling(self.fib_lookback).min())

        # State tracking
        self.swing_high_price = None
        self.swing_high_bar = None
        self.swing_low_price = None
        self.swing_low_bar = None
        self.trend_direction = 0
        self.fvg_zones = []
        self.active_fib_levels = []
        self.entry_signal_bull = False
        self.entry_signal_bear = False
        self.confluence_signal_bull = False
        self.confluence_signal_bear = False

    def detect_swings(self):
        if len(self.data) < self.pivot_strength + 1:
            return

        idx = len(self.data) - 1

        # Check for swing high
        if idx >= self.pivot_strength * 2:
            is_pivot_high = True
            for i in range(1, self.pivot_strength + 1):
                if self.data.High[idx - i] >= self.data.High[idx - self.pivot_strength]:
                    is_pivot_high = False
                    break
            for i in range(1, self.pivot_strength + 1):
                if self.data.High[idx + i - self.pivot_strength] >= self.data.High[idx - self.pivot_strength]:
                    is_pivot_high = False
                    break

            if is_pivot_high:
                pivot_high = self.data.High[idx - self.pivot_strength]
                if self.highest_high[-1] is not None:
                    highest = self.highest_high[-1]
                    if pivot_high >= highest or self.swing_high_price is None:
                        self.swing_high_price = pivot_high
                        self.swing_high_bar = idx - self.pivot_strength

        # Check for swing low
        if idx >= self.pivot_strength * 2:
            is_pivot_low = True
            for i in range(1, self.pivot_strength + 1):
                if self.data.Low[idx - i] <= self.data.Low[idx - self.pivot_strength]:
                    is_pivot_low = False
                    break
            for i in range(1, self.pivot_strength + 1):
                if self.data.Low[idx + i - self.pivot_strength] <= self.data.Low[idx - self.pivot_strength]:
                    is_pivot_low = False
                    break

            if is_pivot_low:
                pivot_low = self.data.Low[idx - self.pivot_strength]
                if self.lowest_low[-1] is not None:
                    lowest = self.lowest_low[-1]
                    if pivot_low <= lowest or self.swing_low_price is None:
                        self.swing_low_price = pivot_low
                        self.swing_low_bar = idx - self.pivot_strength

        if (self.swing_high_price is not None and self.swing_high_bar is not None and
            self.swing_low_price is not None and self.swing_low_bar is not None):
            if self.swing_high_bar > self.swing_low_bar:
                self.trend_direction = -1
            else:
                self.trend_direction = 1

    def detect_fvg(self):
        if len(self.data) < 3:
            return False, False, None, None

        bull_fvg = False
        bear_fvg = False
        fvg_top = None
        fvg_bottom = None

        bull_gap = self.data.Low[-1] > self.data.High[-3]
        bear_gap = self.data.High[-1] < self.data.Low[-3]

        if self.atr[-1] is None:
            return False, False, None, None

        atr_val = self.atr[-1]
        if self.vol_avg[-1] is None:
            return False, False, None, None

        min_size = atr_val * self.min_fvg_size

        if bull_gap:
            bull_gap_size = self.data.Low[-1] - self.data.High[-3]
            if bull_gap_size >= min_size:
                bull_fvg = True
                fvg_top = self.data.Low[-1]
                fvg_bottom = self.data.High[-3]

        if bear_gap:
            bear_gap_size = self.data.Low[-3] - self.data.High[-1]
            if bear_gap_size >= min_size:
                bear_fvg = True
                fvg_top = self.data.Low[-3]
                fvg_bottom = self.data.High[-1]

        return bull_fvg, bear_fvg, fvg_top, fvg_bottom

    def calc_fib_level(self, swing_h, swing_l, ratio):
        if self.trend_direction > 0:
            level = swing_l + (swing_h - swing_l) * ratio
        else:
            level = swing_h - (swing_h - swing_l) * ratio
        return level

    def update_fibonacci_levels(self):
        if (self.swing_high_price is None or self.swing_low_price is None or
            self.atr[-1] is None):
            return

        self.active_fib_levels = []

        fib_ratios = [0.236, 0.382, 0.500, 0.618, 0.786, 1.618, 2.272]

        for ratio in fib_ratios:
            level = self.calc_fib_level(self.swing_high_price, self.swing_low_price, ratio)
            self.active_fib_levels.append((level, ratio))

    def detect_confluence(self):
        bull_conf = False
        bear_conf = False
        conf_strength = 0

        if not self.active_fib_levels or not self.fvg_zones or self.atr[-1] is None:
            return bull_conf, bear_conf, conf_strength

        tolerance = self.atr[-1] * self.confluence_tol

        for fib_level, fib_ratio in self.active_fib_levels:
            for fvg in self.fvg_zones:
                if not fvg['mitigated']:
                    if abs(fib_level - fvg['mid']) < tolerance:
                        conf_strength += 1

                        if fvg['bullish'] and self.trend_direction > 0:
                            bull_conf = True
                        elif not fvg['bullish'] and self.trend_direction < 0:
                            bear_conf = True

        return bull_conf, bear_conf, conf_strength

    def detect_entry_signals(self):
        bull_entry = False
        bear_entry = False

        if self.atr[-1] is None:
            return bull_entry, bear_entry

        for fvg in self.fvg_zones:
            if not fvg['mitigated']:
                in_fvg = self.data.Low[-1] <= fvg['top'] and self.data.High[-1] >= fvg['bottom']

                if fvg['bullish'] and in_fvg and self.data.Close[-1] > self.data.Open[-1]:
                    for fib_level, fib_ratio in self.active_fib_levels:
                        if 0.5 <= fib_ratio <= 0.786:
                            if abs(self.data.Low[-1] - fib_level) < self.atr[-1] * 0.5:
                                bull_entry = True

                if not fvg['bullish'] and in_fvg and self.data.Close[-1] < self.data.Open[-1]:
                    for fib_level, fib_ratio in self.active_fib_levels:
                        if 0.5 <= fib_ratio <= 0.786:
                            if abs(self.data.High[-1] - fib_level) < self.atr[-1] * 0.5:
                                bear_entry = True

        return bull_entry, bear_entry

    def update_fvg_mitigation(self):
        if self.atr[-1] is None:
            return

        for fvg in self.fvg_zones:
            if not fvg['mitigated']:
                if fvg['bullish'] and self.data.Low[-1] <= fvg['mid']:
                    fvg['mitigated'] = True
                elif not fvg['bullish'] and self.data.High[-1] >= fvg['mid']:
                    fvg['mitigated'] = True

    def next(self):
        # Detect swings
        self.detect_swings()

        # Update Fibonacci levels
        if self.swing_high_price is not None and self.swing_low_price is not None:
            self.update_fibonacci_levels()

        # Detect FVG
        bull_fvg, bear_fvg, fvg_top, fvg_bottom = self.detect_fvg()

        if bull_fvg and fvg_top is not None and fvg_bottom is not None:
            fvg = {
                'top': fvg_top,
                'bottom': fvg_bottom,
                'mid': (fvg_top + fvg_bottom) / 2,
                'bullish': True,
                'mitigated': False,
                'bar_idx': len(self.data) - 1
            }
            self.fvg_zones.append(fvg)

        if bear_fvg and fvg_top is not None and fvg_bottom is not None:
            fvg = {
                'top': fvg_top,
                'bottom': fvg_bottom,
                'mid': (fvg_top + fvg_bottom) / 2,
                'bullish': False,
                'mitigated': False,
                'bar_idx': len(self.data) - 1
            }
            self.fvg_zones.append(fvg)

        # Update FVG mitigation
        self.update_fvg_mitigation()

        # Detect confluence
        conf_bull, conf_bear, conf_str = self.detect_confluence()
        self.confluence_signal_bull = conf_bull and conf_str >= self.min_confluence_strength
        self.confluence_signal_bear = conf_bear and conf_str >= self.min_confluence_strength

        # Detect entry signals
        entry_bull, entry_bear = self.detect_entry_signals()
        self.entry_signal_bull = entry_bull
        self.entry_signal_bear = entry_bear

        # Trading logic
        if self.confluence_signal_bull or self.entry_signal_bull:
            if not self.position:
                self.buy()
        elif self.confluence_signal_bear or self.entry_signal_bear:
            if self.position:
                self.position.close()
            else:
                self.sell()

        # Close long position on bear signals
        if self.position and self.position.is_long and (self.confluence_signal_bear or self.entry_signal_bear):
            self.position.close()

        # Close short position on bull signals
        if self.position and not self.position.is_long and (self.confluence_signal_bull or self.entry_signal_bull):
            self.position.close()


