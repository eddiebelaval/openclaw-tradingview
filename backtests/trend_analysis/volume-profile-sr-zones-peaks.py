    def update_zones(self):
        """Calculate S/R zones based on volume profile peaks"""
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate lookback period in bars
        bars_per_day = len(self.data) / (len(self.data) / 252)  # approximate
        lookback_bars = min(int(self.vp_profileDays * bars_per_day / 252), len(self.data) - 1)
        lookback_bars = max(1, lookback_bars)
        
        # Get price range
        recent_high = high[-lookback_bars:].max()
        recent_low = low[-lookback_bars:].min()
        
        if recent_high == recent_low:
            self.sr_zones = []
            return
        
        price_step = (recent_high - recent_low) / self.vp_profileNumberOfRows
        
        if price_step <= 0:
            self.sr_zones = []
            return
        
        # Build volume profile
        volume_profile = np.zeros(self.vp_profileNumberOfRows)
        bullish_volume = np.zeros(self.vp_profileNumberOfRows)
        
        for i in range(max(0, len(self.data) - lookback_bars), len(self.data)):
            bar_high = high.iloc[i]
            bar_low = low.iloc[i]
            bar_vol = volume.iloc[i]
            is_bullish = close.iloc[i] > close.iloc[i-1] if i > 0 else True
            
            start_slot = max(0, int((bar_low - recent_low) / price_step))
            end_slot = min(self.vp_profileNumberOfRows - 1, int((bar_high - recent_low) / price_step))
            
            for slot in range(start_slot, end_slot + 1):
                volume_profile[slot] += bar_vol
                if is_bullish:
                    bullish_volume[slot] += bar_vol
        
        # Find peaks (HVNs)
        if volume_profile.max() == 0:
            self.sr_zones = []
            return
        
        N = max(1, int(self.vp_profileNumberOfRows * 0.09))
        zones = []
        
        for lvl in range(self.vp_profileNumberOfRows):
            v = volume_profile[lvl]
            
            if v / volume_profile.max() < self.sr_relToMaxMin:
                continue
            
            # Check if peak
            left = max(0, lvl - N)
            right = min(self.vp_profileNumberOfRows - 1, lvl + N)
            
            is_peak = True
            neigh_sum = 0.0
            neigh_cnt = 0
            
            for k in range(left, right + 1):
                if k != lvl:
                    vk = volume_profile[k]
                    neigh_sum += vk
                    neigh_cnt += 1
                    if vk >= v:
                        is_peak = False
            
            neigh_avg = neigh_sum / neigh_cnt if neigh_cnt > 0 else v
            prom = v / neigh_avg if neigh_avg > 0 else 999.0
            
            if is_peak and prom >= self.sr_promMin:
                center = recent_low + (lvl + 0.5) * price_step
                atr_val = self.atr[-1] if self.atr[-1] is not None else price_step
                half_width = max(price_step, atr_val * self.sr_atrFrac)
                
                zones.append({
                    'center': center,
                    'bot': center - half_width,
                    'top': center + half_width,
                    'weight': v,
                    'bullish_vol': bullish_volume[lvl]
                })
        
        # Sort by center price and keep top N
        zones.sort(key=lambda z: z['center'])
        self.sr_zones = zones[:self.sr_topN]


