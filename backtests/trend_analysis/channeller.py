import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Detection Settings
    leftBars = 10
    rightBars = 5
    minPivots = 2
    maxPivots = 5
    
    # Trend Filters
    useADX = True
    adxLen = 14
    adxThreshold = 15.0
    requireHLLH = False
    
    # Volume Analysis
    showHighVolPivots = True
    volLen = 50
    volThreshold = 1.5
    
    # Quality Settings
    minR2 = 0.5
    
    # Display Settings
    extendLen = 50
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adxLen) or pd.DataFrame(index=close.index))
        
        # Extract ADX column (third column)
        self.adx_value = self.I(lambda: (
            pta.adx(high, low, close, length=self.adxLen)['ADX_' + str(self.adxLen)] 
            if isinstance(pta.adx(high, low, close, length=self.adxLen), pd.DataFrame) 
            else pd.Series(20, index=close.index)
        ))
        
        # Calculate volume MA
        self.vol_ma = self.I(pta.sma, volume, length=self.volLen)
        
        # Rolling highs and lows for pivot detection
        self.highest_high = self.I(lambda: high.rolling(self.leftBars + self.rightBars + 1).max())
        self.lowest_low = self.I(lambda: low.rolling(self.leftBars + self.rightBars + 1).min())
        
        # Store pivot detection state
        self.bull_pivots = []
        self.bear_pivots = []
        self.last_pivot_check = -1
        self.bull_channel_valid = False
        self.bear_channel_valid = False

    def detect_pivots(self):
        """Detect pivot highs and lows"""
        bar_idx = len(self.data) - 1
        
        if bar_idx < self.leftBars + self.rightBars:
            return False, False
        
        # Pivot high detection
        ph_found = False
        if bar_idx >= self.rightBars:
            check_idx = bar_idx - self.rightBars
            is_pivot_high = True
            
            # Check left bars
            for i in range(1, self.leftBars + 1):
                if check_idx - i >= 0 and self.data.High[check_idx] <= self.data.High[check_idx - i]:
                    is_pivot_high = False
                    break
            
            # Check right bars
            if is_pivot_high:
                for i in range(1, self.rightBars + 1):
                    if check_idx + i < len(self.data) and self.data.High[check_idx] <= self.data.High[check_idx + i]:
                        is_pivot_high = False
                        break
            
            if is_pivot_high:
                ph_found = True
                vol = self.data.Volume[check_idx]
                vol_ma = self.vol_ma[-1] if not np.isnan(self.vol_ma[-1]) else vol
                is_high_vol = vol > vol_ma * self.volThreshold
                self.bear_pivots.append((check_idx, self.data.High[check_idx], is_high_vol))
                if len(self.bear_pivots) > self.maxPivots:
                    self.bear_pivots.pop(0)
        
        # Pivot low detection
        pl_found = False
        if bar_idx >= self.rightBars:
            check_idx = bar_idx - self.rightBars
            is_pivot_low = True
            
            # Check left bars
            for i in range(1, self.leftBars + 1):
                if check_idx - i >= 0 and self.data.Low[check_idx] >= self.data.Low[check_idx - i]:
                    is_pivot_low = False
                    break
            
            # Check right bars
            if is_pivot_low:
                for i in range(1, self.rightBars + 1):
                    if check_idx + i < len(self.data) and self.data.Low[check_idx] >= self.data.Low[check_idx + i]:
                        is_pivot_low = False
                        break
            
            if is_pivot_low:
                pl_found = True
                vol = self.data.Volume[check_idx]
                vol_ma = self.vol_ma[-1] if not np.isnan(self.vol_ma[-1]) else vol
                is_high_vol = vol > vol_ma * self.volThreshold
                self.bull_pivots.append((check_idx, self.data.Low[check_idx], is_high_vol))
                if len(self.bull_pivots) > self.maxPivots:
                    self.bull_pivots.pop(0)
        
        return pl_found, ph_found

    def calc_linear_regression(self, prices):
        """Calculate linear regression for pivot prices"""
        if len(prices) < 2:
            return None, None, 0.0
        
        n = len(prices)
        x = np.arange(n)
        y = np.array(prices)
        
        x_mean = x.mean()
        y_mean = y.mean()
        
        numerator = np.sum((x - x_mean) * (y - y_mean))
        denominator = np.sum((x - x_mean) ** 2)
        
        if denominator == 0:
            return None, None, 0.0
        
        slope = numerator / denominator
        intercept = y_mean - slope * x_mean
        
        y_pred = slope * x + intercept
        ss_res = np.sum((y - y_pred) ** 2)
        ss_tot = np.sum((y - y_mean) ** 2)
        
        r2 = 1 - (ss_res / ss_tot) if ss_tot != 0 else 0
        
        return slope, intercept, r2

    def is_higher_lows(self, prices):
        """Check if prices form higher lows pattern"""
        if len(prices) < 2:
            return True
        for i in range(1, len(prices)):
            if prices[i] <= prices[i-1]:
                return False
        return True

    def is_lower_highs(self, prices):
        """Check if prices form lower highs pattern"""
        if len(prices) < 2:
            return True
        for i in range(1, len(prices)):
            if prices[i] >= prices[i-1]:
                return False
        return True

    def next(self):
        # Detect pivots
        pl_found, ph_found = self.detect_pivots()
        
        # Check ADX filter
        adx_val = self.adx_value[-1] if not np.isnan(self.adx_value[-1]) else 20
        adx_confirmed = not self.useADX or adx_val > self.adxThreshold
        
        # Validate bull channel
        if len(self.bull_pivots) >= self.minPivots and adx_confirmed:
            pivot_prices = [p[1] for p in self.bull_pivots]
            
            if self.is_higher_lows(pivot_prices):
                slope, intercept, r2 = self.calc_linear_regression(pivot_prices)
                
                if slope is not None and slope > 0 and r2 >= self.minR2:
                    self.bull_channel_valid = True
                else:
                    self.bull_channel_valid = False
            else:
                self.bull_channel_valid = False
        else:
            self.bull_channel_valid = False
        
        # Validate bear channel
        if len(self.bear_pivots) >= self.minPivots and adx_confirmed:
            pivot_prices = [p[1] for p in self.bear_pivots]
            
            if self.is_lower_highs(pivot_prices):
                slope, intercept, r2 = self.calc_linear_regression(pivot_prices)
                
                if slope is not None and slope < 0 and r2 >= self.minR2:
                    self.bear_channel_valid = True
                else:
                    self.bear_channel_valid = False
            else:
                self.bear_channel_valid = False
        else:
            self.bear_channel_valid = False
        
        # Trading logic based on channel validity and pivot signals
        has_position = len(self.position) > 0
        
        # Buy signals: strong bull channel with new low pivot
        if pl_found and self.bull_channel_valid and not has_position:
            # Check if this pivot has high volume
            if len(self.bull_pivots) > 0:
                _, _, is_high_vol = self.bull_pivots[-1]
                if is_high_vol:
                    self.buy()
        
        # Sell signals: strong bear channel with new high pivot
        elif ph_found and self.bear_channel_valid and has_position:
            # Check if this pivot has high volume
            if len(self.bear_pivots) > 0:
                _, _, is_high_vol = self.bear_pivots[-1]
                if is_high_vol:
                    self.sell()
        
        # Stop loss: price breaks channel
        if has_position:
            if self.position.is_long and self.bull_channel_valid and len(self.bull_pivots) > 0:
                lowest_pivot = min([p[1] for p in self.bull_pivots])
                if self.data.Low[-1] < lowest_pivot * 0.98:
                    self.sell()
            
            elif not self.position.is_long and self.bear_channel_valid and len(self.bear_pivots) > 0:
                highest_pivot = max([p[1] for p in self.bear_pivots])
                if self.data.High[-1] > highest_pivot * 1.02:
                    self.buy()