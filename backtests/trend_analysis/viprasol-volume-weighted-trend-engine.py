import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vwma_period = 34
    atr_mult = 1.5
    cooldown = 0
    vol_filter = False
    squeeze_thresh = 0.8
    vol_avg_len = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # VWMA calculation
        self.vwma = self.I(pta.vwma, close, volume, length=self.vwma_period)

        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.vwma_period)

        # Bands
        self.upper_band = self.I(lambda: self.vwma + self.atr * self.atr_mult)
        self.lower_band = self.I(lambda: self.vwma - self.atr * self.atr_mult)

        # Volume average
        self.vol_avg = self.I(pta.sma, volume, length=self.vol_avg_len)

        # Band width metrics
        self.band_width = self.I(lambda: self.upper_band - self.lower_band)
        self.band_width_pct = self.I(lambda: (self.band_width / self.vwma * 100.0) if self.vwma[-1] > 0 else pd.Series(0, index=close.index))
        self.band_width_avg = self.I(pta.sma, self.band_width_pct, length=50)

        # Trend strength
        self.trend_strength = self.I(lambda: self._calc_trend_strength())

        # Trend direction tracker
        self.trend_dir = 0
        self.last_signal_bar = -999
        self.in_position = False

    def _calc_trend_strength(self):
        if len(self.data) < 1:
            return pd.Series(0, index=pd.RangeIndex(len(self.data)))
        result = []
        for i in range(len(self.data)):
            bw = self.band_width[-1] if len(self.band_width) > 0 else 0
            if bw > 0:
                ts = ((self.data.Close[i] - self.vwma[i]) / (bw / 2.0)) * 100.0
                ts = max(-100.0, min(100.0, ts))
                result.append(ts)
            else:
                result.append(0.0)
        return pd.Series(result, index=pd.RangeIndex(len(result)))

    def next(self):
        price = self.data.Close[-1]
        upper = self.upper_band[-1] if len(self.upper_band) > 0 else price
        lower = self.lower_band[-1] if len(self.lower_band) > 0 else price
        vol = self.data.Volume[-1] if len(self.data.Volume) > 0 else 0
        vol_avg = self.vol_avg[-1] if len(self.vol_avg) > 0 else vol

        # Update trend direction
        if price > upper:
            self.trend_dir = 1
        elif price < lower:
            self.trend_dir = -1

        # Raw signals
        raw_bull = self.trend_dir == 1 and (len(self.data) < 2 or self._prev_trend_dir() != 1)
        raw_bear = self.trend_dir == -1 and (len(self.data) < 2 or self._prev_trend_dir() != -1)

        # Cooldown filter
        bar_index = len(self.data) - 1
        cooldown_ok = self.cooldown == 0 or (bar_index - self.last_signal_bar) >= self.cooldown

        # Volume filter
        vol_ok = (not self.vol_filter) or (vol > vol_avg)

        # Final signals
        bull_signal = raw_bull and cooldown_ok and vol_ok
        bear_signal = raw_bear and cooldown_ok and vol_ok

        if bull_signal or bear_signal:
            self.last_signal_bar = bar_index

        # Entry/Exit logic
        if bull_signal and not self.position:
            self.buy()
            self.in_position = True
        elif bear_signal and self.position:
            self.position.close()
            self.in_position = False
        elif bear_signal and not self.position:
            self.sell()
            self.in_position = True
        elif bull_signal and self.position and self.position.is_short:
            self.position.close()
            self.buy()

    def _prev_trend_dir(self):
        if len(self.data) < 2:
            return self.trend_dir
        prev_price = self.data.Close[-2]
        prev_upper = self.upper_band[-2] if len(self.upper_band) > 1 else prev_price
        prev_lower = self.lower_band[-2] if len(self.lower_band) > 1 else prev_price
        if prev_price > prev_upper:
            return 1
        elif prev_price < prev_lower:
            return -1
        return self.trend_dir


