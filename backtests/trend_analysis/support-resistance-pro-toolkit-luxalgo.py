        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atr_period) or pd.Series(np.nan, index=close.index))
        
        # Store support and resistance levels
        self.levels = []
        self.support_count = 0
        self.resistance_count = 0
        self.support_mitigated = 0
