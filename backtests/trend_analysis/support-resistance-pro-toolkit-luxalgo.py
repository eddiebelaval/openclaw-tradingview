class TvStrategy(Strategy):
    # Detection Settings
    method = 'Donchian'  # 'Pivots', 'Donchian', 'CSID', 'ZigZag'
    sensitivity = 10.0
    
    # Zone & Level Sizing
    display_type = 'Zones'  # 'Levels' or 'Zones'
    atr_period = 200
    atr_mult = 0.5
    security_mult = 0.0
    
