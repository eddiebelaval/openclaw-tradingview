    def _detect_donchian(self, current_bar):
        sens = int(self.sensitivity)
        if current_bar < sens:
            return None, None, None, None
        
        lookback = min(sens, current_bar + 1)
        recent_highs = self.data.High[-lookback:]
        recent_lows = self.data.Low[-lookback:]
        
        donch_high = recent_highs.max()
        donch_low = recent_lows.min()
        
        high_idx = recent_highs.idxmax() if len(recent_highs) > 0 else None
        low_idx = recent_lows.idxmin() if len(recent_lows) > 0 else None
        
        swing_high = donch_high if high_idx is not None else None
        swing_low = donch_low if low_idx is not None else None
        
        return swing_high, current_bar, swing_low, current_bar

    def _detect_pivots(self, current_bar):
        sens = int(self.sensitivity)
        if current_bar < sens * 2 + 1:
            return None, None, None, None
        
        lookback_start = max(0, current_bar - sens * 2)
        mid_point = current_bar - sens
        
        if mid_point - sens < 0 or mid_point + sens > current_bar:
            return None, None, None, None
        
        before_high = self.data.High[lookback_start:mid_point].max()
        mid_high = self.data.High[mid_point]
        after_high = self.data.High[mid_point:current_bar].max()
        
        before_low = self.data.Low[lookback_start:mid_point].min()
        mid_low = self.data.Low[mid_point]
        after_low = self.data.Low[mid_point:current_bar].min()
        
        swing_high = mid_high if mid_high >= before_high and mid_high >= after_high else None
        swing_low = mid_low if mid_low <= before_low and mid_low <= after_low else None
        
        return swing_high, mid_point if swing_high else None, swing_low, mid_point if swing_low else None

    def _detect_csid(self, current_bar):
        sens = int(self.sensitivity)
        if current_bar < sens:
            return None, None, None, None
        
        recent_closes = self.data.Close[max(0, current_bar - sens):current_bar + 1]
        recent_opens = self.data.Open[max(0, current_bar - sens):current_bar + 1]
        
        bull_count = (recent_closes > recent_opens).sum()
        bear_count = (recent_closes < recent_opens).sum()
        
        swing_high = None
        swing_low = None
        
        if bull_count >= sens:
            recent_highs = self.data.High[max(0, current_bar - sens):current_bar + 1]
            swing_high = recent_highs.max()
        
        if bear_count >= sens:
            recent_lows = self.data.Low[max(0, current_bar - sens):current_bar + 1]
            swing_low = recent_lows.min()
        
        return swing_high, current_bar if swing_high else None, swing_low, current_bar if swing_low else None

    def _detect_zigzag(self, current_bar):
        if not hasattr(self, 'zz_dir'):
            self.zz_dir = 0
            self.zz_high = self.data.High[-1] if len(self) > 0 else 0
            self.zz_low = self.data.Low[-1] if len(self) > 0 else 0
        
        dev = (self.data.Close[-1] * self.sensitivity) / 100
        swing_high = None
        swing_low = None
        
        if self.zz_dir == 0:
            self.zz_dir = 1 if self.data.Close[-1] > self.data.Open[-1] else -1
        elif self.zz_dir == 1:
            if self.data.High[-1] > self.zz_high:
                self.zz_high = self.data.High[-1]
            elif self.data.Low[-1] < self.zz_high - dev:
                swing_high = self.zz_high
                self.zz_low = self.data.Low[-1]
                self.zz_dir = -1
        else:
            if self.data.Low[-1] < self.zz_low:
                self.zz_low = self.data.Low[-1]
            elif self.data.High[-1] > self.zz_low + dev:
                swing_low = self.zz_low
                self.zz_high = self.data.High[-1]
                self.zz_dir = 1
        
        return swing_high, current_bar if swing_high else None, swing_low, current_bar if swing_low else None

    def _add_level(self, top, btm, base_price, start_bar, is_support):
        level = {
            'top': top,
            'btm': btm,
            'base_price': base_price,
            'start_bar': start_bar,
            'is_support': is_support,
            'mitigated': False,
            'entries': 0,
            'sweeps': 0,
            'volume': 0
        }
        
        # Handle overlaps
        should_add = True
        for existing_level in self.levels:
            if not existing_level['mitigated'] and existing_level['is_support'] == is_support:
                if max(btm, existing_level['btm']) < min(top, existing_level['top']):
                    if self.overlap_mode == 'Hide Overlapping (Oldest Precedence)':
                        should_add = False
                        break
                    elif self.overlap_mode == 'Merge Overlapping':
                        existing_level['top'] = max(existing_level['top'], top)
                        existing_level['btm'] = min(existing_level['btm'], btm)
                        should_add = False
                        break
        
        if should_add and len(self.levels) < 100:
            self.levels.append(level)