import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # WHF Core Parameters
    lookback = 100
    smoothing = 3
    healthy_thresh = 70.0
    failed_thresh = 40.0
    
    # Health Component Weights
    req_weight = 0.35
    pc_weight = 0.40
    se_weight = 0.25
    
    # Health Calculation Parameters
    particip_window = 14
    churn_thresh = 1.5
    failed_ff_max = 5
    
    # ML Parameters
    ml_enabled = True
    ml_warmup = 50
    
    # SPA Parameters
    spa_enabled = True
    
    # WPK Parameters
    wpk_enabled = True
    wpk_regime_lb = 100
    wpk_min_anomaly = 1.5
    wpk_cluster_lb = 50
    
    # Signal Parameters
    min_confidence = 0.5
    show_healthy = True
    show_failed = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate basic indicators
        self.rsi = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        self.atr = self.I(lambda: pta.atr(high, low, close, length=14) or pd.Series(1.0, index=close.index))
        self.ema8 = self.I(lambda: pta.ema(close, length=8) or close)
        self.ema21 = self.I(lambda: pta.ema(close, length=21) or close)
        self.ema50 = self.I(lambda: pta.ema(close, length=50) or close)
        
        # Wave health calculation
        self.wave_health = self.I(self._calculate_wave_health, close, high, low, volume)
        
        # Track previous state for signal generation
        self.prev_state = "NEUTRAL"
        self.bar_count = 0

    def _calculate_wave_health(self, close, high, low, volume):
        """Calculate Wave Health and Failure score"""
        if len(close) < self.lookback:
            return pd.Series(50, index=close.index)
        
        health_scores = []
        
        for i in range(len(close)):
            if i < self.lookback:
                health_scores.append(50.0)
                continue
            
            # Get lookback window
            lookback_idx = max(0, i - self.lookback)
            window_close = close.iloc[lookback_idx:i+1]
            window_high = high.iloc[lookback_idx:i+1]
            window_low = low.iloc[lookback_idx:i+1]
            window_volume = volume.iloc[lookback_idx:i+1]
            
            # REQ Score - Efficiency
            net_move = abs(window_close.iloc[-1] - window_close.iloc[0])
            sum_moves = abs(window_close.diff()).sum()
            efficiency = net_move / sum_moves if sum_moves > 0 else 0.0
            
            avg_range = window_high.iloc[-self.lookback:].sub(window_low.iloc[-self.lookback:]).mean() if len(window_high) > 0 else 1.0
            price_progress = net_move / avg_range if avg_range > 0 else 0.0
            
            avg_vol = window_volume.mean() if len(window_volume) > 0 else 1.0
            energy_cost = window_volume.mean() / avg_vol if avg_vol > 0 else 1.0
            energy_norm = min(1.0, price_progress / energy_cost) if energy_cost > 0 else 0.0
            
            recent_mom = abs(window_close.iloc[-1] - window_close.iloc[max(0, len(window_close)-self.lookback//3)])
            early_mom = abs(window_close.iloc[self.lookback//3] - window_close.iloc[0]) if len(window_close) > self.lookback//3 else 1.0
            decay_ratio = recent_mom / early_mom if early_mom > 0 else 1.0
            decay_score = min(1.0, decay_ratio)
            
            req_score = ((efficiency * 0.40) + (energy_norm * 0.30) + (decay_score * 0.30)) * 100
            
            # PC Score - Participation Consistency
            window_particip = window_close.iloc[-self.particip_window:] if len(window_close) >= self.particip_window else window_close
            
            buy_volume = window_volume[window_close > window_close.shift(1)].sum() if len(window_close) > 1 else 0.0
            sell_volume = window_volume[window_close < window_close.shift(1)].sum() if len(window_close) > 1 else 0.0
            total_pressure = buy_volume + sell_volume
            absorption_dom = max(buy_volume, sell_volume) / total_pressure if total_pressure > 0 else 0.5
            
            half_window = max(1, self.particip_window // 2)
            early_vol = window_volume.iloc[-self.particip_window:-half_window].sum() if len(window_volume) >= self.particip_window else 1.0
            late_vol = window_volume.iloc[-half_window:].sum() if len(window_volume) >= half_window else 1.0
            particip_ratio = late_vol / early_vol if early_vol > 0 else 1.0
            dropoff_score = min(1.0, particip_ratio if particip_ratio <= 0.8 else 0.8 / particip_ratio)
            
            pc_score = ((0.35 * 0.5) + (absorption_dom * 0.35) + (dropoff_score * 0.30)) * 100
            
            # SE Score - Structural Extension
            price_stddev = window_close.std()
            churn_index = price_stddev / avg_range if avg_range > 0 else 0.0
            churn_score = 1.0 if churn_index < self.churn_thresh else self.churn_thresh / churn_index
            
            compression_count = 0
            for j in range(max(0, len(window_high) - 49), len(window_high) - 1):
                re_j = (window_high.iloc[j] - window_low.iloc[j]) / avg_range if avg_range > 0 else 1.0
                re_j1 = (window_high.iloc[j+1] - window_low.iloc[j+1]) / avg_range if avg_range > 0 else 1.0
                if re_j < 0.8 and re_j1 > 1.2:
                    compression_count += 1
            
            compression_pen = 1.0 - min(1.0, compression_count / max(1.0, self.lookback / 5.0))
            
            failed_ff = 0
            for j in range(max(1, len(window_close) - 49), len(window_close) - 1):
                move_j = abs(window_close.iloc[j] - window_close.iloc[j+1])
                move_next = abs(window_close.iloc[j-1] - window_close.iloc[j])
                if move_j > avg_range * 0.7 and move_next < avg_range * 0.3:
                    failed_ff += 1
            
            followthru_score = 1.0 - min(1.0, failed_ff / float(self.failed_ff_max))
            se_score = ((churn_score * 0.40) + (compression_pen * 0.30) + (followthru_score * 0.30)) * 100
            
            # Total Health
            total_weight = self.req_weight + self.pc_weight + self.se_weight
            w_req = self.req_weight / total_weight
            w_pc = self.pc_weight / total_weight
            w_se = self.se_weight / total_weight
            
            raw_health = (req_score * w_req) + (pc_score * w_pc) + (se_score * w_se)
            health_scores.append(max(0.0, min(100.0, raw_health)))
        
        # Apply smoothing
        health_series = pd.Series(health_scores, index=close.index)
        smoothed = health_series.rolling(window=self.smoothing).mean()
        
        return smoothed

    def next(self):
        self.bar_count += 1
        
        if self.bar_count < self.ml_warmup:
            return
        
        current_health = self.wave_health[-1]
        
        # Determine wave state
        if current_health >= self.healthy_thresh:
            current_state = "HEALTHY"
        elif current_health >= self.failed_thresh:
            current_state = "FRAGILE"
        else:
            current_state = "FAILED"
        
        # Simple confidence based on distance from threshold
        if current_state == "HEALTHY":
            confidence = min((current_health - self.healthy_thresh) / 30.0, 1.0)
        elif current_state == "FAILED":
            confidence = min((self.failed_thresh - current_health) / 30.0, 1.0)
        else:
            confidence = 0.3
        
        confidence = max(self.min_confidence, confidence)
        
        # Determine direction based on price relative to EMAs
        price = self.data.Close[-1]
        ema8 = self.ema8[-1]
        ema21 = self.ema21[-1]
        
        if ema8 > ema21:
            direction = 1  # Bullish
        elif ema8 < ema21:
            direction = -1  # Bearish
        else:
            direction = 0
        
        # Generate signals
        healthy_entry = (self.prev_state != "HEALTHY" and current_state == "HEALTHY")
        failed_entry = (self.prev_state != "FAILED" and current_state == "FAILED")
        
        # Long entries
        if healthy_entry and direction == 1 and confidence >= self.min_confidence and self.show_healthy:
            if not self.position:
                self.buy()
        
        # Short entries (fade failed trends)
        elif failed_entry and direction == -1 and confidence >= self.min_confidence and self.show_failed:
            if not self.position:
                self.buy()  # Backtesting.py uses buy/sell for direction
        
        # Exit logic
        if self.position:
            # Exit if wave health deteriorates
            if current_health < self.failed_thresh and current_state == "FAILED":
                self.sell()
            
            # Exit on trend reversal
            elif crossover(self.ema21, self.ema8):
                self.sell()
        
        self.prev_state = current_state


