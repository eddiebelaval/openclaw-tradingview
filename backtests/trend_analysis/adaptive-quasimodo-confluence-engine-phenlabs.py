import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_threshold = 5
    qm_quality_weight = 0.6
    p25_threshold = 0.25
    p50_threshold = 0.50
    mae_window_bars = 20
    enable_confluence = True
    min_confluence_score = 0.65

    def init(self):
        self.qm_swing_high = 0.0
        self.qm_lower_high = 0.0
        self.qm_swing_low = 0.0
        self.qm_higher_low = 0.0
        self.qm_retest_level = 0.0
        self.qm_retest_detected = False
        self.qm_state = 'INIT'
        self.qm_structural_score = 0.0
        
        self.session_open_bar = 0
        self.session_high = 0.0
        self.session_low = 0.0
        self.session_open = 0.0
        self.session_distribution = 0.0
        
        self.mae_buffer = []
        
        self.p25_level = 0.0
        self.p50_level = 0.0
        self.mae_zone_high = 0.0
        self.mae_zone_low = 0.0
        
        self.last_premium_signal_bar = -100
        
        high_series = pd.Series(self.data.High)
        low_series = pd.Series(self.data.Low)
        
        self.highest_high = self.I(
            lambda: high_series.rolling(window=self.swing_threshold * 2 + 1, center=True).max()
        )
        self.lowest_low = self.I(
            lambda: low_series.rolling(window=self.swing_threshold * 2 + 1, center=True).min()
        )

    def next(self):
        idx = len(self.data) - 1
        high = self.data.High[idx]
        low = self.data.Low[idx]
        close = self.data.Close[idx]
        open_ = self.data.Open[idx]
        
        if self.highest_high[-1] is None or self.lowest_low[-1] is None:
            return
        
        is_swing_high = high == self.highest_high[-1]
        is_swing_low = low == self.lowest_low[-1]
        
        if is_swing_high:
            self.qm_swing_high = high
            self.qm_state = 'SH'
        
        if self.qm_state == 'SH' and is_swing_low and low < self.qm_swing_high:
            self.qm_swing_low = low
            self.qm_state = 'SL'
        
        if self.qm_state == 'SL' and is_swing_high and high > self.qm_swing_low and high < self.qm_swing_high:
            self.qm_lower_high = high
            self.qm_state = 'LH'
        
        if self.qm_state == 'LH' and is_swing_low and low > self.qm_swing_low:
            self.qm_higher_low = low
            self.qm_state = 'HL'
            self.qm_retest_level = self.qm_swing_low
            self.qm_structural_score = 1.0
        
        if self.qm_state == 'HL' and self.qm_retest_level > 0:
            if low <= self.qm_retest_level and high >= self.qm_retest_level:
                self.qm_retest_detected = True
            else:
                self.qm_retest_detected = False
        else:
            self.qm_retest_detected = False
        
        if self.session_open_bar == 0:
            self.session_open = open_
            self.session_open_bar = idx
            self.session_high = high
            self.session_low = low
        elif idx > self.session_open_bar:
            self.session_high = max(self.session_high, high)
            self.session_low = min(self.session_low, low)
        
        session_range = self.session_high - self.session_low
        if session_range > 0:
            dist_from_open = close - self.session_open
            percentile = dist_from_open / session_range
            self.session_distribution = max(0.0, min(1.0, percentile))
            
            self.p25_level = self.session_open + session_range * self.p25_threshold
            self.p50_level = self.session_open + session_range * self.p50_threshold
        
        if idx > self.session_open_bar and idx <= self.session_open_bar + self.mae_window_bars:
            mae = self.session_open - low
            self.mae_buffer.append(mae)
        
        mae_avg = 0.0
        if len(self.mae_buffer) > 0:
            mae_avg = sum(self.mae_buffer) / len(self.mae_buffer)
        
        self.mae_zone_high = self.session_open - mae_avg * 0.5
        self.mae_zone_low = self.session_open - mae_avg * 1.5
        
        qm_in_premium_zone = self.qm_retest_level >= self.p25_level and self.qm_retest_level <= self.p50_level
        
        structural_score = self.qm_structural_score * self.qm_quality_weight
        
        percentile_score = 0.0
        if qm_in_premium_zone:
            dist_from_p25 = self.qm_retest_level - self.p25_level
            range_p25_to_p50 = self.p50_level - self.p25_level
            if range_p25_to_p50 > 0:
                percentile_score = 0.9 + 0.1 * (1.0 - abs(dist_from_p25 - range_p25_to_p50 / 2) / (range_p25_to_p50 / 2))
            else:
                percentile_score = 0.85
        else:
            percentile_score = 0.4
        
        retest_in_mae_zone = self.qm_retest_level <= self.mae_zone_high and self.qm_retest_level >= self.mae_zone_low
        mae_score = 0.95 if retest_in_mae_zone else 0.50
        
        confluence_score = structural_score * percentile_score * mae_score
        
        premium_qm_retest = (
            self.qm_retest_detected and 
            confluence_score >= self.min_confluence_score and 
            self.enable_confluence
        )
        
        if premium_qm_retest and idx > self.last_premium_signal_bar + 5:
            if not self.position:
                self.buy()
            self.last_premium_signal_bar = idx
        
        elif not premium_qm_retest and self.position:
            self.sell()


