import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    maxFVGs = 8
    showFilledFVGs = True
    removeFilled = False
    extendFVGs = 50
    showMidline = True
    showSignals = True
    
    showBullFVG = True
    showBearFVG = True
    
    showMTF = False
    
    minFVGSize = 0.0
    useATRFilter = False
    atrMult = 0.1
    atrLen = 14
    
    showEntries = True
    entryMode = "CE Touch"
    confirmCandle = True
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.fvg_boxes = []
        self.fvg_top = []
        self.fvg_bot = []
        self.fvg_dir = []
        self.fvg_status = []
        self.fvg_bar = []
        self.fvg_triggered = []
        
        self.total_bull = 0
        self.total_bear = 0
        self.active_bull = 0
        self.active_bear = 0
        self.filled_bull = 0
        self.filled_bear = 0
        
        self.last_bull_cond = False
        self.last_bear_cond = False

    def next(self):
        if len(self.data) < 3:
            return
        
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        high_2 = self.data.High[-3]
        low_2 = self.data.Low[-3]
        
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.0
        
        if self.useATRFilter:
            min_fvg_size = max(self.minFVGSize, atr_val * self.atrMult)
        else:
            min_fvg_size = self.minFVGSize
        
        bull_cond = self.showBullFVG and (low > high_2) and ((low - high_2) >= min_fvg_size)
        bear_cond = self.showBearFVG and (high < low_2) and ((low_2 - high) >= min_fvg_size)
        
        if bull_cond and not self.last_bull_cond:
            self.fvg_top.append(low)
            self.fvg_bot.append(high_2)
            self.fvg_dir.append(1)
            self.fvg_status.append(0)
            self.fvg_bar.append(len(self.data) - 1)
            self.fvg_triggered.append(False)
            self.total_bull += 1
            self.active_bull += 1
        
        if bear_cond and not self.last_bear_cond:
            self.fvg_top.append(low_2)
            self.fvg_bot.append(high)
            self.fvg_dir.append(-1)
            self.fvg_status.append(0)
            self.fvg_bar.append(len(self.data) - 1)
            self.fvg_triggered.append(False)
            self.total_bear += 1
            self.active_bear += 1
        
        self.last_bull_cond = bull_cond
        self.last_bear_cond = bear_cond
        
        if len(self.fvg_top) > self.maxFVGs:
            idx = 0
            if self.fvg_status[idx] == 0:
                if self.fvg_dir[idx] == 1:
                    self.active_bull = max(self.active_bull - 1, 0)
                else:
                    self.active_bear = max(self.active_bear - 1, 0)
            
            self.fvg_top.pop(0)
            self.fvg_bot.pop(0)
            self.fvg_dir.pop(0)
            self.fvg_status.pop(0)
            self.fvg_bar.pop(0)
            self.fvg_triggered.pop(0)
        
        for i in range(len(self.fvg_top)):
            top = self.fvg_top[i]
            bot = self.fvg_bot[i]
            dir_ = self.fvg_dir[i]
            status = self.fvg_status[i]
            mid = (top + bot) / 2.0
            
            full_fill = (dir_ == 1 and close < bot) or (dir_ == -1 and close > top)
            part_fill = (dir_ == 1 and low < top and low > bot) or (dir_ == -1 and high > bot and high < top)
            
