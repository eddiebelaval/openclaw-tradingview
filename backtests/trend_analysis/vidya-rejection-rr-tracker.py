import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # VIDYA Settings
    vidya_length = 10
    vidya_momentum = 20
    
    # VIDYA Rejection Settings
    vidya_rej_ema_period = 5
    enable_vidya_tol = False
    vidya_tol_pips = 2.0
    
    # Filters
    enable_vwap_filter = True
    enable_ema750_filter = True
    ema750_filter_period = 750
    enable_atr_filter = False
    atr_mult = 10.0
    
    # Trade Settings
    rr_sl_pips = 10.0
    rr_ratio = 3.0
    overlap_trades = False
    
    # Session filter (simplified - always enabled in backtest)
    use_session_filter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hl2 = (high + low) / 2
        
        # Calculate VWAP
        self.vwap = self.I(lambda: pta.vwap(high, low, close, volume) or close)
        
        # Calculate EMA 750
        self.ema750 = self.I(lambda: pta.ema(close, length=self.ema750_filter_period) or close)
        
        # Calculate VIDYA Rejection EMA
        self.vidya_rej_ema = self.I(lambda: pta.ema(close, length=self.vidya_rej_ema_period) or close)
        
        # Calculate ATR and smoothed ATR
        atr_result = self.I(lambda: pta.atr(high, low, close, length=200) or pd.Series(0.0, index=close.index))
        self.smooth_atr = self.I(lambda: pta.ema(atr_result, length=750) or atr_result)
        
        # Calculate ATR bands
        self.upper_band = self.I(lambda: self.ema750[-1] + self.atr_mult * self.smooth_atr[-1] if len(self.smooth_atr) > 0 else close[-1])
        self.lower_band = self.I(lambda: self.ema750[-1] - self.atr_mult * self.smooth_atr[-1] if len(self.smooth_atr) > 0 else close[-1])
        
        # VIDYA calculation
        self.vidya_value = self.I(self._calculate_vidya, close, high, low)
        
        # Pip size
        self.pip_size = 0.0001  # Default for forex pairs
        
        # Trade tracking
        self.active_trades = []
        self.total_trades = 0
        self.total_wins = 0
        self.total_win_pips = 0.0
        self.total_loss_pips = 0.0
        
        # State tracking
        self.prev_bull_signal = False
        self.prev_bear_signal = False

    def _calculate_vidya(self, close_series, high_series, low_series):
        """Calculate VIDYA indicator"""
        result = pd.Series(index=close_series.index, dtype=float)
        
        if len(close_series) < max(self.vidya_length, self.vidya_momentum) + 1:
            return result
        
        vidya = close_series.iloc[0]
        alpha = 2 / (self.vidya_length + 1)
        
        for i in range(1, len(close_series)):
            momentum = close_series.iloc[i] - close_series.iloc[i-1]
            
            # Calculate sum of positive and negative momentum
            start_idx = max(0, i - self.vidya_momentum + 1)
            momentum_slice = close_series.iloc[start_idx:i+1].diff().dropna()
            
            sum_pos = (momentum_slice[momentum_slice >= 0]).sum()
            sum_neg = (-momentum_slice[momentum_slice < 0]).sum()
            
            # Calculate CMO
            if (sum_pos + sum_neg) > 0:
                abs_cmo = abs(100 * (sum_pos - sum_neg) / (sum_pos + sum_neg))
            else:
                abs_cmo = 0
            
            # Update VIDYA
            vidya = alpha * abs_cmo / 100 * close_series.iloc[i] + (1 - alpha * abs_cmo / 100) * vidya
            result.iloc[i] = vidya
        
        # Apply SMA smoothing with length 15
        result = pd.Series(
            result.rolling(window=15, min_periods=1).mean().values,
            index=result.index
        )
        
        return result

    def next(self):
        # Get current values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Get current indicator values
        vidya_val = self.vidya_value[-1]
        ema750_val = self.ema750[-1]
        vwap_val = self.vwap[-1]
        ema_rej_val = self.vidya_rej_ema[-1]
        upper_band_val = self.upper_band[-1] if isinstance(self.upper_band[-1], (int, float)) else self.upper_band[-1]
        lower_band_val = self.lower_band[-1] if isinstance(self.lower_band[-1], (int, float)) else self.lower_band[-1]
        
        # Skip if not enough data
        if pd.isna(vidya_val) or pd.isna(ema750_val):
            return
        
        # Determine pip size based on price
        if close > 0:
            self.pip_size = 0.0001 if close > 1 else 0.00001
        
        # Check for VIDYA Bull Rejection
        is_bullish_candle = close > self.data.Open[-1]
        lower_wick_touches_vidya = low <= vidya_val + (self.vidya_tol_pips * self.pip_size if self.enable_vidya_tol else 0)
        body_above_vidya = min(self.data.Open[-1], close) > vidya_val
        ema_cond_bull = not True or close > ema_rej_val  # useVidyaEMAFilter always true
        vwap_cond_bull = not self.enable_vwap_filter or close > vwap_val
        ema750_cond_bull = not self.enable_ema750_filter or close > ema750_val
        atr_cond_bull = not self.enable_atr_filter or close <= upper_band_val
        
        vidya_bull_rejection = (is_bullish_candle and lower_wick_touches_vidya and body_above_vidya and 
                               ema_cond_bull and vwap_cond_bull and ema750_cond_bull and atr_cond_bull)
        
        # Check for VIDYA Bear Rejection
        is_bearish_candle = close < self.data.Open[-1]
        upper_wick_touches_vidya = high >= vidya_val - (self.vidya_tol_pips * self.pip_size if self.enable_vidya_tol else 0)
        body_below_vidya = max(self.data.Open[-1], close) < vidya_val
        ema_cond_bear = not True or close < ema_rej_val  # useVidyaEMAFilter always true
        vwap_cond_bear = not self.enable_vwap_filter or close < vwap_val
        ema750_cond_bear = not self.enable_ema750_filter or close < ema750_val
        atr_cond_bear = not self.enable_atr_filter or close >= lower_band_val
        
        vidya_bear_rejection = (is_bearish_candle and upper_wick_touches_vidya and body_below_vidya and 
                               ema_cond_bear and vwap_cond_bear and ema750_cond_bear and atr_cond_bear)
        
        # Update active trades
        self._update_trades()
        
        # Entry logic
        can_open_trade = self.overlap_trades or len(self.active_trades) == 0
        
        if vidya_bull_rejection and can_open_trade and not self.position:
            self._open_trade(True, low, "backtest")
        
        elif vidya_bear_rejection and can_open_trade and not self.position:
            self._open_trade(False, high, "backtest")

    def _open_trade(self, is_bull, spike_wick, session):
        """Open a new trade with SL and TP"""
        entry = self.data.Close[-1]
        
        if is_bull:
            sl_dist = (entry - spike_wick) + self.rr_sl_pips * self.pip_size
            sl = entry - sl_dist
            tp = entry + sl_dist * self.rr_ratio
            self.buy()
        else:
            sl_dist = (spike_wick - entry) + self.rr_sl_pips * self.pip_size
            sl = entry + sl_dist
            tp = entry - sl_dist * self.rr_ratio
            self.sell()
        
        # Store trade info
        trade_info = {
            'entry': entry,
            'sl': sl,
            'tp': tp,
            'is_bull': is_bull,
            'session': session,
            'bar_index': len(self.data)
        }
        self.active_trades.append(trade_info)

    def _update_trades(self):
        """Check active trades for SL/TP hits"""
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        trades_to_remove = []
        
        for i, trade in enumerate(self.active_trades):
            sl_hit = (trade['is_bull'] and low <= trade['sl']) or (not trade['is_bull'] and high >= trade['sl'])
            tp_hit = (trade['is_bull'] and high >= trade['tp']) or (not trade['is_bull'] and low <= trade['tp'])
            
            if sl_hit or tp_hit:
                pips = abs(trade['tp' if tp_hit else 'sl'] - trade['entry']) / self.pip_size
                
                if tp_hit:
                    self.total_wins += 1
                    self.total_win_pips += pips
                else:
                    self.total_loss_pips += pips
                
                self.total_trades += 1
                trades_to_remove.append(i)
        
        # Remove closed trades (in reverse order to maintain indices)
        for i in reversed(trades_to_remove):
            self.active_trades.pop(i)