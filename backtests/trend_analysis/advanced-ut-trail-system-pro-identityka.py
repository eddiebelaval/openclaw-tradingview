    def _calculate_trailing_stop(self, src, atr, dyn_a):
        """Calculate ATR-based trailing stop"""
        if atr is None or len(src) < 2:
            return pd.Series(src.iloc[-1] if len(src) > 0 else 0, index=src.index)
        
        nLoss = dyn_a * atr
        trailing_stop = pd.Series(0.0, index=src.index)
        
        for i in range(len(src)):
            if i == 0:
                trailing_stop.iloc[i] = src.iloc[i]
            else:
                prev_stop = trailing_stop.iloc[i-1]
                curr_src = src.iloc[i]
                prev_src = src.iloc[i-1]
                curr_nloss = nLoss.iloc[i] if isinstance(nLoss, pd.Series) else nLoss
                
                if curr_src > prev_stop and prev_src > prev_stop:
                    trailing_stop.iloc[i] = max(prev_stop, curr_src - curr_nloss)
                elif curr_src < prev_stop and prev_src < prev_stop:
                    trailing_stop.iloc[i] = min(prev_stop, curr_src + curr_nloss)
                elif curr_src > prev_stop:
                    trailing_stop.iloc[i] = curr_src - curr_nloss
                else:
                    trailing_stop.iloc[i] = curr_src + curr_nloss
        
        return trailing_stop

