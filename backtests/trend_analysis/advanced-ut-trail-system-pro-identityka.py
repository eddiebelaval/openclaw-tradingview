    def _calculate_ha_close(self):
        """Calculate Heikin-Ashi close"""
        open_data = pd.Series(self.data.Open)
        high_data = pd.Series(self.data.High)
        low_data = pd.Series(self.data.Low)
        close_data = pd.Series(self.data.Close)
        
