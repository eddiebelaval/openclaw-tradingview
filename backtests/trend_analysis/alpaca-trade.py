import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters
    ma1_len = 20
    ma2_len = 50
    ema_len = 200
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # VWAP
        hlc3 = (high + high + close) / 3
        self.vwap = self.I(pta.vwap, hlc3)
        
        # EMA Trend Filter
        self.ema_trend = self.I(pta.ema, close, length=self.ema_len)
        
        # MAs for entry/exit
        self.ma1 = self.I(pta.ema, close, length=self.ma1_len)
        self.ma2 = self.I(pta.ema, close, length=self.ma2_len)
        
        # Swing detection for confirmation
        self.swing_high = self.I(lambda: high.rolling(window=11).max())
        self.swing_low = self.I(lambda: low.rolling(window=11).min())

    def next(self):
        # Only trade if we have valid indicator values
        if pd.isna(self.ma1[-1]) or pd.isna(self.ma2[-1]) or pd.isna(self.ema_trend[-1]):
            return
        
        # Trend filter: price above EMA 200 for longs
        uptrend = self.data.Close[-1] > self.ema_trend[-1]
        downtrend = self.data.Close[-1] < self.ema_trend[-1]
        
        # MA crossover signals
        ma_bullish = crossover(self.ma1, self.ma2)
        ma_bearish = crossover(self.ma2, self.ma1)
        
        # Entry logic
        if not self.position:
            # Long entry: MA1 crosses above MA2, price above EMA200, close above VWAP
            if ma_bullish and uptrend and self.data.Close[-1] > self.vwap[-1]:
                self.buy()
            # Short entry: MA1 crosses below MA2, price below EMA200, close below VWAP
            elif ma_bearish and downtrend and self.data.Close[-1] < self.vwap[-1]:
                self.sell()
        else:
            # Exit logic
            if self.position.is_long:
                # Exit long on MA bearish cross or price closes below EMA200
                if ma_bearish or self.data.Close[-1] < self.ema_trend[-1]:
                    self.position.close()
            elif self.position.is_short:
                # Exit short on MA bullish cross or price closes above EMA200
                if ma_bullish or self.data.Close[-1] > self.ema_trend[-1]:
                    self.position.close()


