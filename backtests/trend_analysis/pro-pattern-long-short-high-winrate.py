import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend Filter Parameters
    emaFastLength = 50
    emaSlowLength = 200
    supertrendMultiplier = 3.0
    supertrendPeriod = 10
    adxThreshold = 25
    
    # Volume Filter Parameters
    volumeMultiplier = 1.5
    volumePeriod = 20
    
    # RSI Filter Parameters
    rsiPeriod = 14
    rsiOverbought = 70
    rsiOversold = 30
    
    # Support/Resistance Parameters
    pivotLookback = 10
    srProximity = 0.5
    
    # Risk Management
    stopLossATR = 1.5
    riskRewardRatio = 2.0
    
    # Filter Toggles
    useTrendFilter = True
    useVolumeFilter = True
    useRSIFilter = True
    useSupportResistance = True
    useTimeFilter = True
    showBullishPatterns = True
    showBearishPatterns = True
    
    # Time Filter Parameters
    avoidFirstHour = True
    avoidLastHour = True
    tradingStartHour = 9
    tradingEndHour = 17

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Trend Filter Indicators
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLength)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLength)
        
        # ATR for SuperTrend and Stop Loss
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # ADX for trend strength
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14) or pd.DataFrame(0, index=close.index, columns=['ADX']))
        self.adx = self.I(lambda: adx_result['ADX'] if isinstance(adx_result, pd.DataFrame) else adx_result)
        
        # Volume Filter
        self.volumeSMA = self.I(pta.sma, volume, length=self.volumePeriod)
        
        # RSI Filter
        self.rsi = self.I(pta.rsi, close, length=self.rsiPeriod)
        
        # Support/Resistance - using rolling min/max
        self.highestHigh = self.I(lambda: high.rolling(window=self.pivotLookback).max())
        self.lowestLow = self.I(lambda: low.rolling(window=self.pivotLookback).min())
        
        # Candle patterns
        self.bodySize = self.I(lambda: np.abs(close - pd.Series(self.data.Open)))
        self.upperWick = self.I(lambda: high - np.maximum(close, pd.Series(self.data.Open)))
        self.lowerWick = self.I(lambda: np.minimum(close, pd.Series(self.data.Open)) - low)
        self.candleRange = self.I(lambda: high - low)
        self.avgRange = self.I(pta.sma, (high - low), length=14)
        
        # Tracking variables
        self.last_pattern = ""
        self.last_entry = None
        self.last_stop = None
        self.last_target = None
        self.trade_active = False
        self.trade_type = None

    def next(self):
        if len(self.data) < self.emaSlowLength + 5:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_price = self.data.Open[-1]
        volume = self.data.Volume[-1]
        
        # Get previous candle values
        close_prev = self.data.Close[-2] if len(self.data) >= 2 else close
        open_prev = self.data.Open[-2] if len(self.data) >= 2 else open_price
        high_prev = self.data.High[-2] if len(self.data) >= 2 else high
        low_prev = self.data.Low[-2] if len(self.data) >= 2 else low
        
        close_2 = self.data.Close[-3] if len(self.data) >= 3 else close
        open_2 = self.data.Open[-3] if len(self.data) >= 3 else open_price
        
        # ==== TREND FILTER ====
        uptrend = self.emaFast[-1] > self.emaSlow[-1]
        downtrend = self.emaFast[-1] < self.emaSlow[-1]
        
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        adx_val = self.adx[-1] if self.adx[-1] is not None else 0
        strongTrend = adx_val > self.adxThreshold
        
        trendFilterBullish = uptrend and strongTrend
        trendFilterBearish = downtrend and strongTrend
        
        # ==== VOLUME FILTER ====
        volumeSMA_val = self.volumeSMA[-1] if self.volumeSMA[-1] is not None else 0
        volumeFilter = volume > volumeSMA_val * self.volumeMultiplier if volumeSMA_val > 0 else False
        
        # ==== RSI FILTER ====
        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50
        rsiFilterBullish = rsi_val < self.rsiOverbought
        rsiFilterBearish = rsi_val > self.rsiOversold
        
        # ==== SUPPORT/RESISTANCE FILTER ====
        highest = self.highestHigh[-1] if self.highestHigh[-1] is not None else high
        lowest = self.lowestLow[-1] if self.lowestLow[-1] is not None else low
        
        proximityPercent = self.srProximity / 100
        nearSupport = abs(close - lowest) / lowest < proximityPercent if lowest > 0 else False
        nearResistance = abs(close - highest) / highest < proximityPercent if highest > 0 else False
        
        srFilterBullish = nearSupport
        srFilterBearish = nearResistance
        
        # ==== TIME FILTER ====
        timeFilter = True  # Simplified - backtesting doesn't have hour info
        
        # ==== CANDLE PATTERNS ====
        bodySize_val = abs(close - open_price)
        upperWick_val = high - max(close, open_price)
        lowerWick_val = min(close, open_price) - low
        candleRange_val = high - low
        avgRange_val = self.avgRange[-1] if self.avgRange[-1] is not None else candleRange_val
        
        # Engulfing patterns
        bullishEngulfing = (close_prev < open_prev and close > open_price and 
                           open_price <= close_prev and close >= open_prev)
        bearishEngulfing = (close_prev > open_prev and close < open_price and 
                           open_price >= close_prev and close <= open_prev)
        
        # Hammer and Shooting Star
        isHammer = (lowerWick_val > bodySize_val * 2 and upperWick_val < bodySize_val and 
                   close > open_price and low == self.lowestLow[-1])
        isShootingStar = (upperWick_val > bodySize_val * 2 and lowerWick_val < bodySize_val and 
                         close < open_price and high == self.highestHigh[-1])
        
        # Morning and Evening Stars
        avgBody2 = abs(close_2 - open_2)
        isMorningStar = (close_2 < open_2 and abs(close_prev - open_prev) < avgBody2 * 0.3 and 
                        close > open_price and close > (open_2 + close_2) / 2)
        isEveningStar = (close_2 > open_2 and abs(close_prev - open_prev) < avgBody2 * 0.3 and 
                        close < open_price and close < (open_2 + close_2) / 2)
        
        # Three White Soldiers and Three Black Crows
        close_3 = self.data.Close[-4] if len(self.data) >= 4 else close_2
        open_3 = self.data.Open[-4] if len(self.data) >= 4 else open_2
        
        threeWhiteSoldiers = (close_3 > open_3 and close_prev > open_prev and close > open_price and
                             close_prev > close_3 and close > close_prev and
                             open_prev > open_3 and open_price > open_prev and
                             open_prev < close_3 and open_price < close_prev)
        
        threeBlackCrows = (close_3 < open_3 and close_prev < open_prev and close < open_price and
                          close_prev < close_3 and close < close_prev and
                          open_prev < open_3 and open_price < open_prev and
                          open_prev > close_3 and open_price > close_prev)
        
        # Piercing Line and Dark Cloud Cover
        piercingLine = (close_prev < open_prev and close > open_price and 
                       open_price < close_prev and close > (open_prev + close_prev) / 2 and 
                       close < open_prev)
        darkCloudCover = (close_prev > open_prev and close < open_price and 
                         open_price > close_prev and close < (open_prev + close_prev) / 2 and 
                         close > open_prev)
        
        # Ham pattern signals
        bullishPattern = ((bullishEngulfing or isHammer or isMorningStar or 
                         threeWhiteSoldiers or piercingLine) and self.showBullishPatterns)
        bearishPattern = ((bearishEngulfing or isShootingStar or isEveningStar or 
                         threeBlackCrows or darkCloudCover) and self.showBearishPatterns)
        
        # ==== APPLY ALL FILTERS ====
        bullishSignal = (bullishPattern and 
                        (not self.useTrendFilter or trendFilterBullish) and
                        (not self.useVolumeFilter or volumeFilter) and
                        (not self.useRSIFilter or rsiFilterBullish) and
                        (not self.useSupportResistance or srFilterBullish) and
                        (not self.useTimeFilter or timeFilter))
        
        bearishSignal = (bearishPattern and 
                        (not self.useTrendFilter or trendFilterBearish) and
                        (not self.useVolumeFilter or volumeFilter) and
                        (not self.useRSIFilter or rsiFilterBearish) and
                        (not self.useSupportResistance or srFilterBearish) and
                        (not self.useTimeFilter or timeFilter))
        
        # ==== TRADE MANAGEMENT ====
        if self.trade_active and self.trade_type == "BUY":
            if high >= self.last_target:
                self.sell()
                self.trade_active = False
            elif low <= self.last_stop:
                self.sell()
                self.trade_active = False
        
        elif self.trade_active and self.trade_type == "SELL":
            if low <= self.last_target:
                self.buy()
                self.trade_active = False
            elif high >= self.last_stop:
                self.buy()
                self.trade_active = False
        
        # ==== ENTRY SIGNALS ====
        if bullishSignal and not self.position:
            self.last_entry = close
            self.last_stop = low - atr_val * self.stopLossATR
            self.last_target = self.last_entry + (self.last_entry - self.last_stop) * self.riskRewardRatio
            self.trade_active = True
            self.trade_type = "BUY"
            self.buy()
        
        elif bearishSignal and not self.position:
            self.last_entry = close
            self.last_stop = high + atr_val * self.stopLossATR
            self.last_target = self.last_entry - (self.last_stop - self.last_entry) * self.riskRewardRatio
            self.trade_active = True
            self.trade_type = "SELL"
            self.sell()