import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Logic parameters
    atr_len = 50
    basis_len = 21
    flip_atr = 0.35
    cont_atr = 0.15
    confirm_bars = 2
    cooldown_bars = 1
    max_seg_bars = 35
    detach_atr = 1.25
    detach_bars = 3
    basis_blend = 0.50
    step_atr = 0.50
    adverse_slope_atr = 0.015
    width_atr = 1.05
    width_std_mult = 1.00
    width_cap_atr = 2.20
    
    def init(self):
        # Calculate base indicators
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR
        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.atr_len) or pd.Series(0.0, index=close.index))
        
        # Basis (EMA of HL2)
        hl2 = (high + low) / 2
        self.basis = self.I(lambda: pta.ema(hl2, length=self.basis_len) or hl2)
        
        # Spread (Standard deviation)
        self.spread = self.I(lambda: pta.stdev(hl2, length=self.basis_len) or pd.Series(0.0, index=close.index))
        
        # Momentum Engine
        has_vol = volume > 0
        fast_vwma = self.I(lambda: pta.vwma(close, volume, length=10) if has_vol.any() else pta.ema(close, length=10))
        slow_vwma = self.I(lambda: pta.vwma(close, volume, length=30) if has_vol.any() else pta.ema(close, length=30))
        
        self.mom_delta = self.I(lambda: fast_vwma - slow_vwma)
        self.mom_smooth = self.I(lambda: pta.rma(self.mom_delta, length=20) or self.mom_delta)
        self.mom_accel = self.I(lambda: self.mom_delta - self.mom_smooth)
        
        # State tracking
        self.seg_mid = None
        self.seg_dir = 0
        self.seg_lock = 0
        self.seg_age_counter = 0
        self.last_event_bar = -100
        self.flip_streak = 0
        self.cont_streak = 0
        
    def next(self):
        if len(self.data) < self.basis_len + 10:
            return
            
        # Current values
        atr = self.atr_val[-1] if self.atr_val[-1] > 0 else 0.01
        basis = self.basis[-1]
        spread = self.spread[-1]
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Width seed
        width_seed_raw = atr * self.width_atr + spread * self.width_std_mult
        width_seed_cap = atr * self.width_cap_atr
        width_seed = min(width_seed_raw, width_seed_cap)
        
        # Initialize segment on first bar
        if self.seg_mid is None:
            basis_slope = basis - (self.basis[-2] if len(self.basis) > 1 else basis)
            init_dir = 1 if basis_slope > 0 else (-1 if basis_slope < 0 else 0)
            self.seg_mid = basis
            self.seg_dir = init_dir if init_dir != 0 else 1
            self.seg_width = width_seed
            self.seg_bar0 = len(self.data) - 1
            return
        
        # Age of current segment
        age = len(self.data) - 1 - self.seg_bar0
        mid = self.seg_mid
        width = max(self.seg_width, atr * 0.25)
        upper = mid + width
        lower = mid - width
        
        # Event detection logic
        up_flip_qual = self.seg_dir != 1 and close > upper + atr * self.flip_atr
        dn_flip_qual = self.seg_dir != -1 and close < lower - atr * self.flip_atr
        up_cont_qual = self.seg_dir == 1 and close > upper + atr * self.cont_atr
        dn_cont_qual = self.seg_dir == -1 and close < lower - atr * self.cont_atr
        
        self.flip_streak = (self.flip_streak + 1) if (up_flip_qual or dn_flip_qual) else 0
        self.cont_streak = (self.cont_streak + 1) if (up_cont_qual or dn_cont_qual) else 0
        
        # Event determination
        flip_up = self.seg_lock <= 0 and up_flip_qual and self.flip_streak >= self.confirm_bars
        flip_dn = self.seg_lock <= 0 and dn_flip_qual and self.flip_streak >= self.confirm_bars
        cont_up = self.seg_lock <= 0 and up_cont_qual and self.cont_streak >= self.confirm_bars
        cont_dn = self.seg_lock <= 0 and dn_cont_qual and self.cont_streak >= self.confirm_bars
        stale = age >= self.max_seg_bars
        
        did_flip_up = flip_up and self.seg_dir != 1
        did_flip_dn = flip_dn and self.seg_dir != -1
        did_cont_up = cont_up
        did_cont_dn = cont_dn
        
        # Trading logic: enter on regime flips and continuation steps
        if did_flip_up or did_cont_up:
            if not self.position:
                self.buy()
            self.seg_dir = 1
            self.seg_mid = close - atr * self.step_atr
            self.seg_bar0 = len(self.data) - 1
            self.seg_lock = self.cooldown_bars
            self.flip_streak = 0
            self.cont_streak = 0
            
        elif did_flip_dn or did_cont_dn:
            if self.position:
                self.position.close()
            self.seg_dir = -1
            self.seg_mid = close + atr * self.step_atr
            self.seg_bar0 = len(self.data) - 1
            self.seg_lock = self.cooldown_bars
            self.flip_streak = 0
            self.cont_streak = 0
        
        elif stale and self.seg_lock <= 0:
            # Refresh/re-anchor on stale segment
            basis_slope = basis - (self.basis[-2] if len(self.basis) > 1 else basis)
            new_dir = 1 if basis_slope >= 0 else -1
            self.seg_dir = new_dir
            self.seg_mid = basis
            self.seg_bar0 = len(self.data) - 1
            self.seg_lock = self.cooldown_bars
        
        # Decrement lock
        if self.seg_lock > 0:
            self.seg_lock -= 1
        
        # Exit on retest of opposite band (trailing stop logic)
        if self.position:
            if self.seg_dir == 1 and low < lower:
                self.position.close()
            elif self.seg_dir == -1 and high > upper:
                self.position.close()