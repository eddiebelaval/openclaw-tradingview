import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate pivot highs and lows
        self.pivot_high = self.I(self._calc_pivot_high, high, self.length)
        self.pivot_low = self.I(self._calc_pivot_low, low, self.length)
        
        # Track trendline values
        self.upper_line_price = self.I(self._calc_upper_trendline, high, self.length)
        self.lower_line_price = self.I(self._calc_lower_trendline, low, self.length)
        
        # Track last breakout
        self.last_bullish_break = False
        self.last_bearish_break = False

    def _calc_pivot_high(self, high, length):
        result = []
        for i in range(len(high)):
            if i < length or i >= len(high) - length:
                result.append(np.nan)
            else:
                window = high.iloc[i - length:i + length + 1]
                if high.iloc[i] == window.max():
                    result.append(high.iloc[i])
                else:
                    result.append(np.nan)
        return pd.Series(result, index=high.index)

    def _calc_pivot_low(self, low, length):
        result = []
        for i in range(len(low)):
            if i < length or i >= len(low) - length:
                result.append(np.nan)
            else:
                window = low.iloc[i - length:i + length + 1]
                if low.iloc[i] == window.min():
                    result.append(low.iloc[i])
                else:
                    result.append(np.nan)
        return pd.Series(result, index=low.index)

    def _calc_upper_trendline(self, high, length):
        result = []
        ph_y1, ph_x1 = None, None
        ph_y2, ph_x2 = None, None
        
        for i in range(len(high)):
            if i < length or i >= len(high) - length:
                result.append(np.nan)
            else:
                window = high.iloc[i - length:i + length + 1]
                if high.iloc[i] == window.max():
                    ph_y2, ph_x2 = ph_y1, ph_x1
                    ph_y1, ph_x1 = high.iloc[i], i
                
                if ph_y2 is not None and ph_x2 is not None:
                    x_range = ph_x1 - ph_x2
                    if x_range != 0:
                        slope = (ph_y1 - ph_y2) / x_range
                        line_val = ph_y2 + slope * (i - ph_x2)
                        result.append(line_val)
                    else:
                        result.append(np.nan)
                else:
                    result.append(np.nan)
        
        return pd.Series(result, index=high.index)

    def _calc_lower_trendline(self, low, length):
        result = []
        pl_y1, pl_x1 = None, None
        pl_y2, pl_x2 = None, None
        
        for i in range(len(low)):
            if i < length or i >= len(low) - length:
                result.append(np.nan)
            else:
                window = low.iloc[i - length:i + length + 1]
                if low.iloc[i] == window.min():
                    pl_y2, pl_x2 = pl_y1, pl_x1
                    pl_y1, pl_x1 = low.iloc[i], i
                
                if pl_y2 is not None and pl_x2 is not None:
                    x_range = pl_x1 - pl_x2
                    if x_range != 0:
                        slope = (pl_y1 - pl_y2) / x_range
                        line_val = pl_y2 + slope * (i - pl_x2)
                        result.append(line_val)
                    else:
                        result.append(np.nan)
                else:
                    result.append(np.nan)
        
        return pd.Series(result, index=low.index)

    def next(self):
        close = self.data.Close[-1]
        upper_val = self.upper_line_price[-1]
        lower_val = self.lower_line_price[-1]
        
        bullish_break = False
        bearish_break = False
        
        if len(self.data.Close) > 1:
            prev_close = self.data.Close[-2]
            
            if not np.isnan(upper_val):
                if prev_close <= upper_val and close > upper_val and not self.last_bullish_break:
                    bullish_break = True
                    self.last_bullish_break = True
                    self.last_bearish_break = False
            
            if not np.isnan(lower_val):
                if prev_close >= lower_val and close < lower_val and not self.last_bearish_break:
                    bearish_break = True
                    self.last_bearish_break = True
                    self.last_bullish_break = False
        
        if bullish_break:
            if not self.position:
                self.buy()
        elif bearish_break:
            if self.position:
                self.sell()