import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback_period = 60
    profile_buckets = 50
    value_area_pct = 0.70
    fib_618_level = 0.618
    fib_382_level = 0.382
    fib_50_level = 0.5

    def init(self):
        pass

    def next(self):
        if len(self.data) < self.lookback_period:
            return

        close_data = self.data.Close
        high_data = self.data.High
        low_data = self.data.Low
        volume_data = self.data.Volume

        lookback_idx = len(self.data) - self.lookback_period
        lookback_close = close_data[lookback_idx:]
        lookback_high = high_data[lookback_idx:]
        lookback_low = low_data[lookback_idx:]
        lookback_volume = volume_data[lookback_idx:]

        price_range_high = lookback_high.max()
        price_range_low = lookback_low.min()
        price_range_span = price_range_high - price_range_low

        if price_range_span <= 0:
            return

        bucket_height = price_range_span / self.profile_buckets

        buy_buckets = [0.0] * self.profile_buckets
        sell_buckets = [0.0] * self.profile_buckets

        for i in range(len(lookback_close)):
            bar_close = lookback_close.iloc[i]
            bar_open = close_data.iloc[lookback_idx + i - 1] if lookback_idx + i > 0 else bar_close
            bar_vol = lookback_volume.iloc[i]

            bucket_idx = max(0, min(self.profile_buckets - 1,
                                     int(np.floor((bar_close - price_range_low) / bucket_height))))

            if bar_close >= bar_open:
                buy_buckets[bucket_idx] += bar_vol
            else:
                sell_buckets[bucket_idx] += bar_vol

        total_buy_vol = sum(buy_buckets)
        total_sell_vol = sum(sell_buckets)
        total_profile_vol = total_buy_vol + total_sell_vol

        if total_profile_vol == 0:
            return

        peak_volume = 0
        poc_bucket_idx = 0

        for i in range(self.profile_buckets):
            bucket_total = buy_buckets[i] + sell_buckets[i]
            if bucket_total > peak_volume:
                peak_volume = bucket_total
                poc_bucket_idx = i

        poc_price = price_range_low + (poc_bucket_idx + 0.5) * bucket_height

        fib_level_0 = price_range_high
        fib_level_50 = price_range_high - self.fib_50_level * price_range_span
        fib_level_100 = price_range_low
        fib_618 = price_range_high - self.fib_618_level * price_range_span
        fib_382 = price_range_high - self.fib_382_level * price_range_span

        current_price = self.data.Close[-1]
        prev_price = self.data.Close[-2] if len(self.data) > 1 else current_price

        buy_pct = total_buy_vol / total_profile_vol * 100 if total_profile_vol > 0 else 50.0
        sell_pct = total_sell_vol / total_profile_vol * 100 if total_profile_vol > 0 else 50.0

        price_above_poc = current_price > poc_price
        price_below_poc = current_price < poc_price

        crossed_fib_618_up = prev_price <= fib_618 < current_price
        crossed_fib_618_down = current_price < fib_618 <= prev_price

        crossed_fib_382_up = prev_price <= fib_382 < current_price
        crossed_fib_382_down = current_price < fib_382 <= prev_price

        crossed_fib_50_up = prev_price <= fib_level_50 < current_price
        crossed_fib_50_down = current_price < fib_level_50 <= prev_price

        bullish_bias = buy_pct > sell_pct

        if not self.position:
            if crossed_fib_382_up and bullish_bias:
                self.buy()
            elif crossed_fib_618_up and bullish_bias and price_above_poc:
                self.buy()
            elif crossed_fib_50_up and buy_pct > 60:
                self.buy()
        else:
            if crossed_fib_618_down and not bullish_bias:
                self.sell()
            elif crossed_fib_382_down and sell_pct > 60:
                self.sell()
            elif crossed_fib_50_down and sell_pct > 55:
                self.sell()
            elif price_below_poc and not bullish_bias:
                self.sell()


