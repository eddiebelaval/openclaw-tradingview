import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Displacement settings
    require_fvg = True
    disp_type = "Open to Close"
    std_len = 100
    std_x = 4
    
    # FVG settings
    fvg_gapwidth = 0.009
    fvg_method = '%'
    mitigation_type_wick = True
    mitigation_pct = 100
    
    # NY session time parameters (in minutes from midnight)
    start_hour = 9
    start_minute = 30
    end_hour = 10
    end_minute = 0
    green_start_hour = 5
    green_start_minute = 0
    green_end_hour = 9
    green_end_minute = 15

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR for reference
        self.atr = self.I(lambda: pta.atr(high, low, close, length=14) or pd.Series(0, index=close.index))
        
        # Calculate displacement (yellow candle) logic
        def calc_displacement():
            candle_range = np.abs(open_ - close) if self.disp_type == "Open to Close" else high - low
            std = pta.stdev(candle_range, self.std_len) * self.std_x
            
            # FVG detection
            fvg = pd.Series(False, index=close.index)
            for i in range(2, len(close)):
                if close.iloc[i-1] > open_.iloc[i-1]:
                    fvg.iloc[i] = high.iloc[i-2] < low.iloc[i]
                else:
                    fvg.iloc[i] = low.iloc[i-2] > high.iloc[i]
            
            displacement = candle_range > std if not self.require_fvg else (candle_range.shift(1) > std.shift(1)) & fvg
            return displacement
        
        self.displacement = self.I(calc_displacement)
        
        # FVG detection
        def detect_fvgs():
            bullish_fvg = pd.Series(False, index=close.index)
            bearish_fvg = pd.Series(False, index=close.index)
            
            for i in range(2, len(close)):
                bullish_fvg.iloc[i] = low.iloc[i] > high.iloc[i-2] and close.iloc[i-1] > high.iloc[i-2]
                bearish_fvg.iloc[i] = high.iloc[i] < low.iloc[i-2] and close.iloc[i-1] < low.iloc[i-2]
            
            return bullish_fvg, bearish_fvg
        
        self.bullish_fvg, self.bearish_fvg = self.I(detect_fvgs)
        
        # Track breaker blocks (series of bullish/bearish candles)
        def track_blocks():
            is_bullish = close > open_
            is_bearish = close < open_
            
            bullish_series_high = pd.Series(np.nan, index=close.index)
            bullish_series_low = pd.Series(np.nan, index=close.index)
            bearish_series_high = pd.Series(np.nan, index=close.index)
            bearish_series_low = pd.Series(np.nan, index=close.index)
            
            for i in range(len(close)):
                if is_bullish.iloc[i]:
                    if i == 0 or not is_bullish.iloc[i-1]:
                        bullish_series_high.iloc[i] = high.iloc[i]
                        bullish_series_low.iloc[i] = low.iloc[i]
                    else:
                        bullish_series_high.iloc[i] = max(bullish_series_high.iloc[i-1], high.iloc[i])
                        bullish_series_low.iloc[i] = min(bullish_series_low.iloc[i-1], low.iloc[i])
                
                if is_bearish.iloc[i]:
                    if i == 0 or not is_bearish.iloc[i-1]:
                        bearish_series_high.iloc[i] = high.iloc[i]
                        bearish_series_low.iloc[i] = low.iloc[i]
                    else:
                        bearish_series_high.iloc[i] = max(bearish_series_high.iloc[i-1], high.iloc[i])
                        bearish_series_low.iloc[i] = min(bearish_series_low.iloc[i-1], low.iloc[i])
            
            return bullish_series_high, bullish_series_low, bearish_series_high, bearish_series_low
        
        self.bull_high, self.bull_low, self.bear_high, self.bear_low = self.I(track_blocks)

    def next(self):
        # Check if we have valid indicators
        if len(self.data) < 3:
            return
        
        # Get current values
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        is_bullish = current_close > current_open
        is_bearish = current_close < current_open
        
        # Trading logic based on FVG and breaker blocks
        
        # Bullish signal: FVG with displacement and price above blocks
        if (self.bullish_fvg[-1] and 
            not np.isnan(self.displacement[-1]) and 
            self.displacement[-1]):
            
            if not self.position:
                self.buy()
        
        # Bearish signal: FVG with displacement and price below blocks
        if (self.bearish_fvg[-1] and 
            not np.isnan(self.displacement[-1]) and 
            self.displacement[-1]):
            
            if self.position:
                self.position.close()
            elif not self.position:
                self.buy()  # For long bias, use buy for all signals
        
        # Exit conditions
        if self.position:
            # Simple exit on reversal
            if is_bearish and not is_bullish:
                pct_change = (current_close - self.position.open_price) / self.position.open_price
                if pct_change < -0.02:  # 2% loss
                    self.position.close()
            
            # Take profit on 3% gain
            pct_change = (current_close - self.position.open_price) / self.position.open_price
            if pct_change > 0.03:
                self.position.close()