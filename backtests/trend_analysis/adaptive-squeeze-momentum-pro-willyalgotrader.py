import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Main parameters
    length_input = 21
    bb_mult_input = 1.8
    atr_mult_input = 1.6
    mom_length_input = 20
    smooth_input = 3
    div_lookback_input = 3
    use_divergence = True
    use_htf_filter = False
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Preset adjustments (Default preset)
        adj_length = self.length_input
        adj_bb_mult = self.bb_mult_input
        adj_atr_mult = self.atr_mult_input
        adj_mom_len = self.mom_length_input
        adj_smooth = self.smooth_input
        
        # EMA basis for volatility bands
        self.ema_basis = self.I(pta.ema, close, length=adj_length)
        
        # Standard deviation for volatility bands
        self.stdev = self.I(lambda: close.rolling(adj_length).std().fillna(0))
        
        # ATR for channel
        self.atr_val = self.I(pta.atr, high, low, close, length=adj_length)
        
        # Highest high and lowest low for momentum
        self.highest_hi = self.I(lambda: high.rolling(adj_mom_len).max())
        self.lowest_lo = self.I(lambda: low.rolling(adj_mom_len).min())
        
        # EMA of source for momentum
        self.ema_mom = self.I(pta.ema, close, length=adj_mom_len)
        
        # ATR normalization
        self.atr_norm = self.I(pta.atr, high, low, close, length=adj_mom_len)
        
        # Calculate normalized momentum
        def calc_norm_mom():
            highest = self.highest_hi
            lowest = self.lowest_lo
            ema_m = self.ema_mom
            mid_all = ((highest + lowest) * 0.5 + ema_m) * 0.5
            raw_mom = close - mid_all
            atr_n = self.atr_norm
            atr_n = atr_n.replace(0, 1)
            norm_mom = raw_mom / atr_n
            return norm_mom
        
        self.norm_mom = self.I(calc_norm_mom)
        
        # Smooth momentum
        if adj_smooth <= 1:
            self.mom_value = self.norm_mom
