        mom_previous = self.mom_prev[-1]
        
        mom_rising = mom_current > mom_previous
        mom_falling = mom_current < mom_previous
        mom_above = mom_current > 0
        mom_below = mom_current <= 0
        
        sqz_on = self.sqz_on[-1]
        
