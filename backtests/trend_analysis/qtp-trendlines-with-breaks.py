import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    mult = 1.0
    calcMethod = "Atr"
    backpaint = True
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate pivot points
        self.ph = self.I(self._pivot_high, high, self.length)
        self.pl = self.I(self._pivot_low, low, self.length)
        
        # Calculate slope based on method
        if self.calcMethod == "Atr":
            atr = self.I(pta.atr, high, low, close, length=self.length)
            self.slope = self.I(lambda: (atr / self.length * self.mult).fillna(0))
        elif self.calcMethod == "Stdev":
            stdev = self.I(pta.stdev, close, length=self.length)
            self.slope = self.I(lambda: (stdev / self.length * self.mult).fillna(0))
        else:  # Linreg
            self.slope = self.I(self._linreg_slope, close, self.length, self.mult)
        
        # Track upper and lower trendlines
        self.upper = np.zeros(len(self.data))
        self.lower = np.zeros(len(self.data))
        self.slope_ph_val = 0.0
        self.slope_pl_val = 0.0
        
        # Breakout flags
        self.prev_bullBreak = False
        self.prev_bearBreak = False
    
    def _pivot_high(self, high, length):
        result = pd.Series(np.nan, index=high.index)
        for i in range(length, len(high) - length):
            if high.iloc[i] == high.iloc[i-length:i+length+1].max():
                result.iloc[i] = high.iloc[i]
        return result
    
    def _pivot_low(self, low, length):
        result = pd.Series(np.nan, index=low.index)
        for i in range(length, len(low) - length):
            if low.iloc[i] == low.iloc[i-length:i+length+1].min():
                result.iloc[i] = low.iloc[i]
        return result
    
    def _linreg_slope(self, close, length, mult):
        n = np.arange(len(close))
        result = pd.Series(0.0, index=close.index)
        for i in range(length, len(close)):
            window_close = close.iloc[i-length+1:i+1].values
            window_n = n[i-length+1:i+1]
            variance = np.var(window_n)
            if variance > 0:
                covariance = np.cov(window_n, window_close)[0, 1]
                slope_val = abs(covariance / variance) / 2 * mult
                result.iloc[i] = slope_val
        return result
    
    def next(self):
        idx = len(self.data) - 1
        
        # Get current values
        has_ph = not np.isnan(self.ph[-1])
        has_pl = not np.isnan(self.pl[-1])
        current_close = self.data.Close[-1]
        current_slope = self.slope[-1]
        
        # Update slope values
        if has_ph:
            self.slope_ph_val = current_slope
        if has_pl:
            self.slope_pl_val = current_slope
        
        # Update trendlines
        if has_ph:
            self.upper[idx] = self.ph[-1]
        else:
            self.upper[idx] = self.upper[idx-1] - self.slope_ph_val if idx > 0 else self.upper[idx-1]
        
        if has_pl:
            self.lower[idx] = self.pl[-1]
        else:
            self.lower[idx] = self.lower[idx-1] + self.slope_pl_val if idx > 0 else self.lower[idx-1]
        
        # Detect breakouts
        upper_threshold = self.upper[idx-1] - self.slope_ph_val * self.length if idx > 0 else self.upper[idx]
        lower_threshold = self.lower[idx-1] + self.slope_pl_val * self.length if idx > 0 else self.lower[idx]
        
        bull_break = current_close > upper_threshold and not has_ph
        bear_break = current_close < lower_threshold and not has_pl
        
        # Generate signals
        if bull_break and not self.prev_bullBreak:
            self.buy()
            self.prev_bullBreak = True
            self.prev_bearBreak = False
        elif bear_break and not self.prev_bearBreak:
            self.sell()
            self.prev_bearBreak = True
            self.prev_bullBreak = False