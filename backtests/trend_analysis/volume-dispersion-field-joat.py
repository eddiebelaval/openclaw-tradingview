        if self.position:
            sell_climax = (self.volRatio[-1] >= self.climaxThreshold and 
                          self.data.Close[-1] < self.data.Open[-1])
            
            cum_delta_reverse = (self.cumDelta[-1] < 0 and 
                                len(self.data) > self.cumDeltaLength)
            
            if sell_climax or cum_delta_reverse:
                self.sell()
        
        # Exit 4: Volume anomaly with negative dispersion
        if self.position and abs(self.zScore[-1]) > self.anomalyThreshold:
            if self.dispersion[-1] < -20:
                self.sell()


