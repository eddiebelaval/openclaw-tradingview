class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR for threshold calculations
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # EMA bias on HTF (simulated as standard timeframe)
        self.ema_fast = self.I(pta.ema, close, length=50)
        self.ema_slow = self.I(pta.ema, close, length=200)
        
        # ADX strength
        self.adx = self.I(pta.adx, high, low, close, length=14)
        
        # RSI extreme
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # Track swing highs and lows (simplified)
        self.swing_high = self.I(lambda: high.rolling(5).max())
        self.swing_low = self.I(lambda: low.rolling(5).min())
        
        # Score trackers
        self.bull_score = 0
        self.bear_score = 0
        self.last_bull_sweep = -100
        self.last_bear_sweep = -100

    def next(self):
        idx = len(self.data) - 1
        
        if idx < 20:
            return
        
        # Get current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        atr_val = self.atr[-1] if self.atr[-1] > 0 else 1
        
        ema_f = self.ema_fast[-1]
        ema_s = self.ema_slow[-1]
        adx_val = self.adx[-1] if self.adx[-1] is not None else 0
        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50
        
        # EMA bias
        htf_bull = ema_f > ema_s
        htf_bear = ema_f < ema_s
        
        # ADX strength scoring
        adx_score = 0
        if adx_val >= 30:
            adx_score = 2
        elif adx_val >= 20:
            adx_score = 1
        
        # RSI extreme
        rsi_bull_score = 1 if rsi_val <= 35 else 0
        rsi_bear_score = 1 if rsi_val >= 65 else 0
        
