import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Store pivot levels as indicators
        # We'll calculate them based on daily (prior session) data
        self.pp = self.I(self._calculate_pp)
        self.r1 = self.I(self._calculate_r1)
        self.s1 = self.I(self._calculate_s1)
        self.r2 = self.I(self._calculate_r2)
        self.s2 = self.I(self._calculate_s2)
        self.r3 = self.I(self._calculate_r3)
        self.s3 = self.I(self._calculate_s3)

    def _calculate_pp(self):
        """Calculate Pivot Point from prior session"""
        highs = pd.Series(self.data.High)
        lows = pd.Series(self.data.Low)
        closes = pd.Series(self.data.Close)
        
        # Shift to get prior session values
        ph = highs.shift(1)
        pl = lows.shift(1)
        pc = closes.shift(1)
        
        pp = (ph + pl + pc) / 3
        return pp.fillna(method='bfill')

    def _calculate_r1(self):
        """Calculate R1 (38.2% fibonacci)"""
        highs = pd.Series(self.data.High)
        lows = pd.Series(self.data.Low)
        closes = pd.Series(self.data.Close)
        
