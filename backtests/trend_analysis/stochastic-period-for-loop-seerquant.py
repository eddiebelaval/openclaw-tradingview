import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    kSmooth = 3
    sl = 5
    el = 55
    thrUp = 25
    thrDown = -25
    obLevel = 80
    osLevel = 20
    maLen = 21

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        def compute_score():
            scores = []
            for idx in range(len(close)):
                if idx < self.el:
                    scores.append(0.0)
                    continue
                
                score = 0.0
                midpoint = (self.obLevel + self.osLevel) / 2.0
                halfSpan = (self.obLevel - self.osLevel) / 2.0
                
                for period in range(self.sl, self.el + 1):
                    if period > idx:
                        continue
                    
                    close_slice = close.iloc[max(0, idx - period + 1):idx + 1]
                    high_slice = high.iloc[max(0, idx - period + 1):idx + 1]
                    low_slice = low.iloc[max(0, idx - period + 1):idx + 1]
                    
                    if len(close_slice) < period:
                        continue
                    
                    stoch_result = pta.stoch(high_slice, low_slice, close_slice, k=period)
                    if stoch_result is None or len(stoch_result) == 0:
                        continue
                    
                    k_raw = stoch_result.iloc[:, 0].iloc[-1]
                    
                    k_series = pd.Series([k_raw] * self.kSmooth)
                    k_smoothed = pta.sma(k_series, length=self.kSmooth)
                    if k_smoothed is None or len(k_smoothed) == 0:
                        k_val = k_raw
                    else:
                        k_val = k_smoothed.iloc[-1]
                    
                    if halfSpan != 0:
                        zoneScore = (k_val - midpoint) / halfSpan
                    else:
                        zoneScore = 0.0
                    
                    zoneScore = max(-1.0, min(1.0, zoneScore))
                    score += zoneScore
                
                scores.append(score)
            
            return pd.Series(scores, index=close.index)
        
        self.score = self.I(compute_score)
        
        def compute_signal_line():
            signal_line = []
            for idx in range(len(self.score)):
                if idx < 4:
                    signal_line.append(0.0)
                else:
                    score_slice = pd.Series(self.score[:idx + 1])
                    ema_result = pta.ema(score_slice, length=5)
                    if ema_result is None or len(ema_result) == 0:
                        signal_line.append(self.score[idx])
                    else:
                        signal_line.append(ema_result.iloc[-1])
            
            return pd.Series(signal_line, index=close.index)
        
        self.signalLine = self.I(compute_signal_line)
        
        self.ovMA = self.I(pta.ema, close, length=self.maLen)
        
        self.prevTrendState = 0
        self.currentTrendState = 0

    def next(self):
        if len(self.score) < 1 or self.score[-1] is None:
            return
        
        current_score = self.score[-1]
        
        goLong = current_score > self.thrUp
        goShort = current_score < self.thrDown
        
        if goLong and not goShort:
            if not self.position:
                self.buy()
        elif goShort:
            if self.position:
                self.sell()
        else:
            if self.position and current_score < self.thrUp:
                self.sell()