    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        self.ema_fast = self.I(pta.ema, close, length=self.trend_ema_fast)
        self.ema_slow = self.I(pta.ema, close, length=self.trend_ema_slow)
        self.ema_filter = self.I(pta.ema, close, length=self.trend_ema_filter)
        
        adx_result = self.I(pta.adx, high, low, close, length=self.adx_length)
        self.adx = adx_result
        
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Bollinger Bands
        bb = self.I(pta.bbands, close, length=self.bb_length, std=self.bb_mult)
        self.bb_upper = bb.iloc[:, 0]
        self.bb_lower = bb.iloc[:, 2]
        
        # Highest/Lowest
        self.highest_high = self.I(lambda: high.rolling(self.breakout_length).max())
        self.lowest_low = self.I(lambda: low.rolling(self.breakout_length).min())
        
        # Volume indicators
        self.volume_sma = self.I(pta.sma, volume, length=20)
        
        # NW Kernel Ribbon - simplified version
        self.nw1 = self.I(pta.ema, close, length=int(self.nw_lookback * 0.3))
        self.nw8 = self.I(pta.ema, close, length=int(self.nw_lookback * 1.5))
        
        # VWAP
        def calc_vwap():
            vwap_sum = (high + low + close) / 3.0 * volume
            vol_sum = volume
            vwap = vwap_sum.rolling(window=len(close)).sum() / vol_sum.rolling(window=len(volume)).sum()
            return vwap
        
        self.vwap = self.I(calc_vwap)
        
        # CVD
        def calc_cvd():
            buy_vol = pd.Series(np.where(close > close.shift(1), volume, 0))
            sell_vol = pd.Series(np.where(close < close.shift(1), volume, 0))
            delta = buy_vol - sell_vol
            cvd = delta.cumsum()
            return cvd
        
        self.cvd = self.I(calc_cvd)
        self.cvd_sma = self.I(pta.sma, self.cvd, length=self.cvd_length)
        
        # State tracking
        self.consecutive_losses = 0
        self.peak_equity = self.equity
        self.elm_accuracy = 0.5
        self.elm_confidence_weight = 1.0
        self.total_trades = 0
        self.winning_trades = 0
        self.equity_guard_active = False
        self.guard_cooldown_bars = 0

    def next(self):
        # Safety checks
        if len(self.data.Close) < max(self.nw_lookback, self.atr_length, self.trend_ema_filter):
            return
        
        # Get current values
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.01
        ema_fast_val = self.ema_fast[-1]
        ema_slow_val = self.ema_slow[-1]
        ema_filter_val = self.ema_filter[-1]
        adx_val = self.adx[-1] if not np.isnan(self.adx[-1]) else 20
        rsi_val = self.rsi[-1] if not np.isnan(self.rsi[-1]) else 50
        
        # Volume metrics
        volume_sma_val = self.volume_sma[-1]
        volume_spike = self.data.Volume[-1] > volume_sma_val * self.volume_mult
        
        # Highest/Lowest
        highest = self.highest_high[-1]
        lowest = self.lowest_low[-1]
        
        # Trend detection
        is_trending = adx_val > self.adx_threshold
        bullish_trend = ema_fast_val > ema_slow_val and self.data.Close[-1] > ema_filter_val
        bearish_trend = ema_fast_val < ema_slow_val and self.data.Close[-1] < ema_filter_val
        
        # Crossovers
        ema_cross_up = crossover(self.ema_fast, self.ema_slow)
        ema_cross_down = crossover(self.ema_slow, self.ema_fast)
        rsi_cross_up = crossover(self.rsi, self.rsi_os)
        rsi_cross_down = crossover(self.rsi_ob, self.rsi)
        
        # Bollinger Bands
        bb_upper = self.bb_upper[-1]
        bb_lower = self.bb_lower[-1]
        
        # RSI conditions
        is_ranging = adx_val <= self.adx_threshold
        mean_reversion_long = is_ranging and self.data.Close[-1] < bb_lower and rsi_val < self.rsi_os and rsi_cross_up
        mean_reversion_short = is_ranging and self.data.Close[-1] > bb_upper and rsi_val > self.rsi_ob and rsi_cross_down
        
        # Breakout conditions
        breakout_long = self.data.Close[-1] > highest and volume_spike and self.data.Close[-1] > ema_filter_val
        breakout_short = self.data.Close[-1] < lowest and volume_spike and self.data.Close[-1] < ema_filter_val
        
        # Trend following conditions
        trend_long = is_trending and bullish_trend and ema_cross_up and volume_spike
        trend_short = is_trending and bearish_trend and ema_cross_down and volume_spike
        
        # Order Flow signals
        cvd_val = self.cvd[-1]
        cvd_sma_val = self.cvd_sma[-1]
        buy_volume = self.data.Volume[-1] if self.data.Close[-1] > self.data.Open[-1] else 0
        sell_volume = self.data.Volume[-1] if self.data.Close[-1] < self.data.Open[-1] else 0
        volume_ratio = buy_volume / max(sell_volume, 1)
        
        of_bullish = (cvd_val > cvd_sma_val) and (volume_ratio > (1 + self.cvd_threshold))
        of_bearish = (cvd_val < cvd_sma_val) and (volume_ratio < (1 - self.cvd_threshold))
        
        # Smart Money - BOS detection
        bullish_bos = self.data.Close[-1] > self.data.Close[-2] and self.data.High[-1] > self.data.High[-2]
        bearish_bos = self.data.Close[-1] < self.data.Close[-2] and self.data.Low[-1] < self.data.Low[-2]
        
        # Risk/Reward calculation
        long_sl = self.data.Close[-1] - (atr_val * self.stop_atr_mult)
        long_tp = self.data.Close[-1] + (atr_val * self.tp_atr_mult)
        short_sl = self.data.Close[-1] + (atr_val * self.stop_atr_mult)
        short_tp = self.data.Close[-1] - (atr_val * self.tp_atr_mult)
        
        rr_long = (long_tp - self.data.Close[-1]) / max(self.data.Close[-1] - long_sl, 0.0001)
        rr_short = (self.data.Close[-1] - short_tp) / max(short_sl - self.data.Close[-1], 0.0001)
        rr_ok_long = rr_long >= self.min_rr_ratio
        rr_ok_short = rr_short >= self.min_rr_ratio
        
        # Cost filter
        total_cost_pips = self.est_spread_pips + self.est_commission_pips
        atr_in_pips = atr_val / 0.0001 if atr_val > 0 else 1
        cost_ratio = atr_in_pips / max(total_cost_pips, 0.1)
        cost_filter_ok = cost_ratio >= self.min_atr_cost_ratio
        
        # Equity guard
        current_equity = self.equity
        self.peak_equity = max(self.peak_equity, current_equity)
        current_drawdown_pct = (self.peak_equity - current_equity) / self.peak_equity * 100 if self.peak_equity > 0 else 0
        
        if self.consecutive_losses >= self.max_consec_losses or current_drawdown_pct >= self.max_drawdown_pct:
            self.equity_guard_active = True
            self.guard_cooldown_bars = self.guard_cooldown_length
        
        if self.equity_guard_active:
            self.guard_cooldown_bars -= 1
            if self.guard_cooldown_bars <= 0:
                self.equity_guard_active = False
        
        # Confluence scoring (simplified)
        signal_strength_long = 0.0
        signal_strength_short = 0.0
        
        if bullish_trend:
            signal_strength_long += self.w_mtf
        if bearish_trend:
            signal_strength_short += self.w_mtf
        
        if self.nw1[-1] > self.nw8[-1]:
            signal_strength_long += self.w_ribbon
        else:
            signal_strength_short += self.w_ribbon
        
        if of_bullish:
            signal_strength_long += self.w_of
        if of_bearish:
            signal_strength_short += self.w_of
        
        if bullish_bos:
            signal_strength_long += self.w_smc
        if bearish_bos:
            signal_strength_short += self.w_smc
        
        if adx_val > self.adx_threshold:
            signal_strength_long += self.w_adx if bullish_trend else 0
            signal_strength_short += self.w_adx if bearish_trend else 0
        
        confluence_score = max(signal_strength_long, signal_strength_short)
        
        # Entry conditions with confluence requirement
        long_condition = (
            (trend_long or breakout_long or mean_reversion_long) and
            rr_ok_long and
            cost_filter_ok and
            not self.equity_guard_active and
            confluence_score >= self.min_confluence_score
        )
        
        short_condition = (
            (trend_short or breakout_short or mean_reversion_short) and
            rr_ok_short and
            cost_filter_ok and
            not self.equity_guard_active and
            confluence_score >= self.min_confluence_score
        )
        
        # Execute trades
        if long_condition and not self.position:
            self.buy(size=0.95)
        elif short_condition and not self.position:
            self.sell(size=0.95)
        
        # Exit logic with trailing stop approximation
        if self.position:
            if self.position.is_long:
                if self.data.Close[-1] <= long_sl:
                    self.position.close()
                    self.consecutive_losses += 1
                elif self.data.Close[-1] >= long_tp:
                    self.position.close()
                    self.consecutive_losses = 0