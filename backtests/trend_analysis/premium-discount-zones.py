import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rangeLen = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate swing high and low using rolling max/min
        self.swingHigh = self.I(lambda: high.rolling(self.rangeLen).max())
        self.swingLow = self.I(lambda: low.rolling(self.rangeLen).min())
        
        # Calculate premium and discount levels
        self.premiumTop = self.I(lambda: self.swingHigh)
        self.premiumBottom = self.I(lambda: 0.95 * self.swingHigh + 0.05 * self.swingLow)
        
        self.discountTop = self.I(lambda: 0.95 * self.swingLow + 0.05 * self.swingHigh)
        self.discountBottom = self.I(lambda: self.swingLow)
        
        self.eqTop = self.I(lambda: 0.525 * self.swingHigh + 0.475 * self.swingLow)
        self.eqBottom = self.I(lambda: 0.525 * self.swingLow + 0.475 * self.swingHigh)
        self.eqLevel = self.I(lambda: (self.swingHigh + self.swingLow) / 2)

    def next(self):
        if len(self.data) < self.rangeLen:
            return
        
        # Get current price
        current_price = self.data.Close[-1]
        
        # Get current zone values
        prem_top = self.premiumTop[-1]
        prem_bottom = self.premiumBottom[-1]
        disc_top = self.discountTop[-1]
        disc_bottom = self.discountBottom[-1]
        eq_top = self.eqTop[-1]
        eq_bottom = self.eqBottom[-1]
        
        # Check if we have valid values
        if pd.isna(prem_top) or pd.isna(prem_bottom) or pd.isna(disc_top) or pd.isna(disc_bottom):
            return
        
        # Buy when price enters discount zone from below
        if current_price >= disc_bottom and current_price <= disc_top:
            if not self.position:
                self.buy()
        
        # Sell when price reaches premium zone
        if current_price >= prem_bottom and current_price <= prem_top:
            if self.position:
                self.sell()
        
        # Exit if price goes below discount zone
        if current_price < disc_bottom:
            if self.position:
                self.sell()


