import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime, timedelta


class TvStrategy(Strategy):
    rr_ratio = 2.0
    use_prev_candle_for_sl = False
    start_hour_est = 9
    start_min_est = 30
    end_hour_est = 16
    end_min_est = 0
    allow_sun = False
    allow_mon = True
    allow_tue = True
    allow_wed = True
    allow_thu = True
    allow_fri = True
    allow_sat = False

    def init(self):
        self.bull_target = np.nan
        self.bear_target = np.nan
        self.last_state = "Neutral"
        self.pending_long = False
        self.pending_short = False
        self.prev_allBullish = False
        self.prev_allBearish = False
        self.trade_dir = "None"
        self.entry_price = np.nan
        self.sl_price = np.nan
        self.tp_price = np.nan
        self.hit_tp = False
        self.hit_sl = False
        self.total_trades = 0
        self.wins = 0
        self.losses = 0

    def cisd_logic(self, idx):
        if idx < 1:
            return "Neutral", False, False

        high = self.data.High
        low = self.data.Low
        close = self.data.Close
        open_ = self.data.Open

        is_inside = high[idx] < high[idx - 1] and low[idx] > low[idx - 1]
        is_bearish = close[idx] < open_[idx]
        is_bullish = close[idx] > open_[idx]

        bullish_cisd = not np.isnan(self.bull_target) and (
            close[idx] > self.bull_target
        ) and (close[idx - 1] <= self.bull_target)
        bearish_cisd = not np.isnan(self.bear_target) and (
            close[idx] < self.bear_target
        ) and (close[idx - 1] >= self.bear_target)

        if bullish_cisd:
            self.last_state = "Bullish"
        if bearish_cisd:
            self.last_state = "Bearish"

        if is_bearish and not is_inside:
            self.bull_target = open_[idx]
        if is_bullish and not is_inside:
            self.bear_target = open_[idx]

        return self.last_state, bullish_cisd, bearish_cisd

    def is_time_allowed(self):
        bar_time = self.data.index[-1]
        entry_hour = bar_time.hour
        entry_min = bar_time.minute
        entry_dow = bar_time.weekday() + 1

        start_min_total = self.start_hour_est * 60 + self.start_min_est
        end_min_total = self.end_hour_est * 60 + self.end_min_est
        entry_min_total = entry_hour * 60 + entry_min

        if start_min_total <= end_min_total:
            time_in_window = entry_min_total >= start_min_total and entry_min_total <= end_min_total
        else:
            time_in_window = entry_min_total >= start_min_total or entry_min_total <= end_min_total

        day_allowed = False
        if entry_dow == 1:
            day_allowed = self.allow_sun
        elif entry_dow == 2:
            day_allowed = self.allow_mon
        elif entry_dow == 3:
            day_allowed = self.allow_tue
        elif entry_dow == 4:
            day_allowed = self.allow_wed
        elif entry_dow == 5:
            day_allowed = self.allow_thu
        elif entry_dow == 6:
            day_allowed = self.allow_fri
        elif entry_dow == 7:
            day_allowed = self.allow_sat

        return day_allowed and time_in_window

    def next(self):
        idx = len(self.data) - 1

        if idx < 1:
            return

        local_state, local_bullCISD, local_bearCISD = self.cisd_logic(idx)

        all_bullish = local_state == "Bullish"
        all_bearish = local_state == "Bearish"

        new_bull_alignment = all_bullish and not self.prev_allBullish
        new_bear_alignment = all_bearish and not self.prev_allBearish

        self.prev_allBullish = all_bullish
        self.prev_allBearish = all_bearish

        if new_bull_alignment:
            self.pending_long = True
            self.pending_short = False

        if new_bear_alignment:
            self.pending_short = True
            self.pending_long = False

        if not all_bullish:
            self.pending_long = False
        if not all_bearish:
            self.pending_short = False

        new_long = self.pending_long and local_bullCISD
        new_short = self.pending_short and local_bearCISD

        if new_long:
            self.pending_long = False
        if new_short:
            self.pending_short = False

        if self.trade_dir == "Long" and not self.hit_tp and not self.hit_sl:
            if self.data.High[idx] >= self.tp_price:
                self.hit_tp = True
            elif self.data.Low[idx] <= self.sl_price:
                self.hit_sl = True

        if self.trade_dir == "Short" and not self.hit_tp and not self.hit_sl:
            if self.data.Low[idx] <= self.tp_price:
                self.hit_tp = True
            elif self.data.High[idx] >= self.sl_price:
                self.hit_sl = True

        exit_long = self.trade_dir == "Long" and not all_bullish
        exit_short = self.trade_dir == "Short" and not all_bearish

        if exit_long or exit_short:
            if not np.isnan(self.entry_price):
                if self.hit_tp:
                    self.wins += 1
                else:
                    self.losses += 1
            self.trade_dir = "None"
            self.entry_price = np.nan
            self.sl_price = np.nan
            self.tp_price = np.nan
            self.hit_tp = False
            self.hit_sl = False
            if self.position:
                self.position.close()

        if new_long:
            if self.is_time_allowed():
                if self.position:
                    self.position.close()
                self.total_trades += 1
                ent = self.data.Close[idx]
                sl = self.data.Low[idx - 1] if self.use_prev_candle_for_sl else self.data.Open[idx]
                risk = ent - sl
                tp = ent + self.rr_ratio * risk
                self.trade_dir = "Long"
                self.entry_price = ent
                self.sl_price = sl
                self.tp_price = tp
                self.hit_tp = False
                self.hit_sl = False
                self.buy()

        if new_short:
            if self.is_time_allowed():
                if self.position:
                    self.position.close()
                self.total_trades += 1
                ent = self.data.Close[idx]
                sl = self.data.High[idx - 1] if self.use_prev_candle_for_sl else self.data.Open[idx]
                risk = sl - ent
                tp = ent - self.rr_ratio * risk
                self.trade_dir = "Short"
                self.entry_price = ent
                self.sl_price = sl
                self.tp_price = tp
                self.hit_tp = False
                self.hit_sl = False
                self.sell()


