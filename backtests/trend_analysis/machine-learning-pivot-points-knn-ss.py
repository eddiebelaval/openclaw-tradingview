import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    user_pivs = 10
    knn_clusters = 2
    len_param = 20
    
    def init(self):
        self.piv_hi_slopes = []
        self.piv_lo_slopes = []
        self.knn_class_prev = "Neutral"
        self.last_predicted_high = 0
        self.last_predicted_low = 0
        
    def get_historical_slope(self, src, start_index, window_len):
        if start_index + window_len > len(src):
            return None
        
        sumX = 0.0
        sumY = 0.0
        sumXY = 0.0
        sumX2 = 0.0
        
        for i in range(start_index, start_index + window_len):
            x = float(i)
            y = src[i]
            sumX += x
            sumY += y
            sumXY += x * y
            sumX2 += x * x
        
        denominator = window_len * sumX2 - sumX ** 2
        if denominator == 0:
            return 0.0
        
        slope = (window_len * sumXY - sumX * sumY) / denominator
        return slope
    
    def f_rolling_slope(self, src, length):
        if len(src) < length:
            return 0.0
        
        y_hat_0 = self._linreg(src, length, 0)
        y_hat_1 = self._linreg(src, length, 1)
        slope = y_hat_0 - y_hat_1
        return slope
    
    def _linreg(self, src, length, offset):
        if len(src) < length:
            return 0.0
        
        end_idx = len(src) - 1 - offset
        start_idx = end_idx - length + 1
        
        if start_idx < 0:
            return src[end_idx] if end_idx >= 0 else 0.0
        
        sumX = 0.0
        sumY = 0.0
        sumXY = 0.0
        sumX2 = 0.0
        
        for i in range(start_idx, end_idx + 1):
            x = float(i - start_idx)
            y = src[i]
            sumX += x
            sumY += y
            sumXY += x * y
            sumX2 += x * x
        
        denominator = length * sumX2 - sumX ** 2
        if denominator == 0:
            return np.mean(src[start_idx:end_idx + 1])
        
        slope = (length * sumXY - sumX * sumY) / denominator
        intercept = (sumY - slope * sumX) / length
        y_hat = slope * (length - 1 - offset) + intercept
        return y_hat
    
    def f_knn_k4_dist(self, current_val, history_array):
        k = self.knn_clusters
        avg_dist = 1000000.0
        
        if len(history_array) >= k:
            distances = [abs(current_val - val) for val in history_array]
            distances.sort()
            
            sum_dist = sum(distances[:k])
            avg_dist = sum_dist / k
        elif len(history_array) > 0:
            avg_dist = abs(current_val - history_array[0])
        
        return avg_dist
    
    def get_pivot_high(self, highs, left, right):
        idx = len(highs) - 1
        if idx < left + right:
            return None
        
        pivot = highs[idx - left]
        for i in range(idx - left - left, idx - left + right + 1):
            if i >= 0 and i < len(highs):
                if highs[i] > pivot:
                    return None
        
        return pivot
    
    def get_pivot_low(self, lows, left, right):
        idx = len(lows) - 1
        if idx < left + right:
            return None
        
        pivot = lows[idx - left]
        for i in range(idx - left - left, idx - left + right + 1):
            if i >= 0 and i < len(lows):
                if lows[i] < pivot:
                    return None
        
        return pivot
    
    def next(self):
        high_list = list(self.data.High)
        low_list = list(self.data.Low)
        close_list = list(self.data.Close)
        
        piv_hi = self.get_pivot_high(high_list, 10, 10)
        piv_lo = self.get_pivot_low(low_list, 10, 10)
        
        if piv_hi is not None:
            slope_sig = self.get_historical_slope(high_list, 10, self.len_param)
            if slope_sig is not None:
                self.piv_hi_slopes.append(slope_sig)
        
        if piv_lo is not None:
            slope_sig = self.get_historical_slope(low_list, 10, self.len_param)
