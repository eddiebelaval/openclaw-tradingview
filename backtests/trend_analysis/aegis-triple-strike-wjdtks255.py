import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # [1] High-Performance Momentum Engine
        lenSmooth = 8
        lenFast = 20
        lenSlow = 50
        
        # Calculate EMA chain
        glide = self.I(pta.ema, close, length=lenSmooth)
        fast = self.I(pta.ema, glide, length=lenFast)
        slow = self.I(pta.ema, glide, length=lenSlow)
        
        # Oscillator and signal
        self.osc = self.I(lambda: fast - slow)
        self.sig = self.I(pta.sma, self.osc, length=lenSmooth)
        
        # ATR for target calculation
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Track position state
        self.position_open = False
        self.position_type = None  # 'long' or 'short'
        self.entry_price = 0
        self.tp1_price = 0
        self.tp2_price = 0
        self.tp3_price = 0
        self.sl_price = 0

    def next(self):
        if len(self.data) < 2:
            return
        
        current_osc = self.osc[-1]
        current_sig = self.sig[-1]
        prev_osc = self.osc[-2]
        prev_sig = self.sig[-2]
        current_atr = self.atr[-1]
        
        if pd.isna(current_osc) or pd.isna(current_sig) or pd.isna(current_atr):
            return
        
        close_price = self.data.Close[-1]
        
        # Check for crossovers
        long_signal = prev_osc <= prev_sig and current_osc > current_sig
        short_signal = prev_osc >= prev_sig and current_osc < current_sig
        
        # Exit conditions
        if self.position_open:
            if self.position_type == 'long':
                # Exit on TP3, TP2, TP1, or SL
                if close_price >= self.tp3_price:
                    self.sell()
                    self.position_open = False
                elif close_price >= self.tp2_price and close_price < self.tp3_price:
                    self.sell()
                    self.position_open = False
                elif close_price >= self.tp1_price and close_price < self.tp2_price:
                    self.sell()
                    self.position_open = False
                elif close_price <= self.sl_price:
                    self.sell()
                    self.position_open = False
            
            elif self.position_type == 'short':
                # Exit on TP3, TP2, TP1, or SL
                if close_price <= self.tp3_price:
                    self.buy()
                    self.position_open = False
                elif close_price <= self.tp2_price and close_price > self.tp3_price:
                    self.buy()
                    self.position_open = False
                elif close_price <= self.tp1_price and close_price > self.tp2_price:
                    self.buy()
                    self.position_open = False
                elif close_price >= self.sl_price:
                    self.buy()
                    self.position_open = False
        
        # Entry signals
        if long_signal and not self.position_open:
            self.buy()
            self.position_open = True
            self.position_type = 'long'
            self.entry_price = close_price
            self.sl_price = close_price - (current_atr * 2.0)
            self.tp1_price = close_price + (current_atr * 2.0)
            self.tp2_price = close_price + (current_atr * 4.0)
            self.tp3_price = close_price + (current_atr * 6.0)
        
