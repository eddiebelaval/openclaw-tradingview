import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_length = 5
    min_gap_ticks = 2.0

    def init(self):
        self.close = pd.Series(self.data.Close)
        self.open = pd.Series(self.data.Open)
        self.high = pd.Series(self.data.High)
        self.low = pd.Series(self.data.Low)
        
        # Calculate pivot highs and lows
        self.pivot_high = self.I(self._calc_pivot_high, self.close, self.pivot_length)
        self.pivot_low = self.I(self._calc_pivot_low, self.close, self.pivot_length)
        
        # Track support and resistance levels
        self.resistance_levels = []
        self.support_levels = []
        self.gap_levels = []
        self.last_pivot_high_idx = -1
        self.last_pivot_low_idx = -1
        self.last_gap_idx = -1

    def _calc_pivot_high(self, close):
        pivot_highs = pd.Series(index=close.index, dtype=float)
        for i in range(self.pivot_length, len(close)):
            window = close.iloc[i-self.pivot_length:i+self.pivot_length+1]
            mid_idx = self.pivot_length
            if i >= self.pivot_length and i < len(close) - self.pivot_length:
                is_pivot = True
                mid_val = close.iloc[i]
                for j in range(len(window)):
                    if j != mid_idx and window.iloc[j] >= mid_val:
                        is_pivot = False
                        break
                if is_pivot:
                    pivot_highs.iloc[i] = close.iloc[i]
        return pivot_highs

    def _calc_pivot_low(self, close):
        pivot_lows = pd.Series(index=close.index, dtype=float)
        for i in range(self.pivot_length, len(close)):
            if i >= self.pivot_length and i < len(close) - self.pivot_length:
                window = close.iloc[i-self.pivot_length:i+self.pivot_length+1]
                mid_idx = self.pivot_length
                is_pivot = True
                mid_val = close.iloc[i]
                for j in range(len(window)):
                    if j != mid_idx and window.iloc[j] <= mid_val:
                        is_pivot = False
                        break
                if is_pivot:
                    pivot_lows.iloc[i] = close.iloc[i]
        return pivot_lows

    def _detect_bullish_gap(self, idx):
        if idx < 1:
            return False, np.nan
        prev_bullish = self.open[idx-1] < self.close[idx-1]
        curr_bullish = self.open[idx] < self.close[idx]
        if prev_bullish and curr_bullish:
            gap_size = (self.open[idx] - self.close[idx-1]) / self.data.Close[idx] * 10000
            if gap_size >= self.min_gap_ticks:
                return True, self.close[idx-1]
        return False, np.nan

    def _detect_bearish_gap(self, idx):
        if idx < 1:
            return False, np.nan
        prev_bearish = self.open[idx-1] > self.close[idx-1]
        curr_bearish = self.open[idx] > self.close[idx]
        if prev_bearish and curr_bearish:
            gap_size = (self.close[idx-1] - self.open[idx]) / self.data.Close[idx] * 10000
            if gap_size >= self.min_gap_ticks:
                return True, self.close[idx-1]
        return False, np.nan

    def next(self):
        idx = len(self.data) - 1
        
        # Detect new pivot high (resistance)
        if not np.isnan(self.pivot_high[-1]) and idx != self.last_pivot_high_idx:
            resistance = self.pivot_high[-1]
            if resistance not in self.resistance_levels:
                self.resistance_levels.append(resistance)
            self.last_pivot_high_idx = idx
        
        # Detect new pivot low (support)
        if not np.isnan(self.pivot_low[-1]) and idx != self.last_pivot_low_idx:
            support = self.pivot_low[-1]
            if support not in self.support_levels:
                self.support_levels.append(support)
            self.last_pivot_low_idx = idx
        
        # Detect gaps
        is_bullish_gap, gap_price_bull = self._detect_bullish_gap(idx)
        is_bearish_gap, gap_price_bear = self._detect_bearish_gap(idx)
        
        if is_bullish_gap:
            if gap_price_bull not in self.gap_levels:
                self.gap_levels.append(gap_price_bull)
        elif is_bearish_gap:
            if gap_price_bear not in self.gap_levels:
                self.gap_levels.append(gap_price_bear)
        
        # Trading logic based on support and resistance levels
        current_price = self.data.Close[-1]
        
        # Check for bounces off support levels
        for support in self.support_levels:
            if self.data.Low[-1] <= support <= self.data.Close[-1]:
                if not self.position:
                    self.buy()
        
        # Check for rejection at resistance levels
        for resistance in self.resistance_levels:
            if self.data.High[-1] >= resistance >= self.data.Close[-1]:
                if self.position:
                    self.position.close()
                else:
                    self.buy()  # Short signal
        
        # Close position if price crosses above resistance
        if self.position and current_price > max(self.resistance_levels) if self.resistance_levels else False:
            self.position.close()
        
        # Close position if price crosses below support
        if self.position and current_price < min(self.support_levels) if self.support_levels else False:
            self.position.close()
        
        # Simple trend-following with levels
        if self.resistance_levels and self.support_levels:
            if current_price > max(self.resistance_levels[-3:] if len(self.resistance_levels) >= 3 else self.resistance_levels):
                if not self.position:
                    self.buy()
            elif current_price < min(self.support_levels[-3:] if len(self.support_levels) >= 3 else self.support_levels):
                if self.position:
                    self.position.close()


