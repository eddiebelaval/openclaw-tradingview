import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adxLen = 14
    erLen = 20
    slopeLen = 50
    atrLen = 14
    threshold = 55
    confirmBars = 1
    strongOffset = 15
    useHTFConfirm = True
    cooldownBars = 2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        def calc_adx():
            adx_result = pta.adx(high, low, close, length=self.adxLen)
            if adx_result is None or adx_result.empty:
                return pd.Series(50, index=close.index)
            return adx_result.iloc[:, 0]

        def calc_dmi():
            adx_result = pta.adx(high, low, close, length=self.adxLen)
            if adx_result is None or adx_result.empty:
                return pd.Series(50, index=close.index)
            return adx_result.iloc[:, 0]

        def calc_er():
            erStep = (close - close.shift(1)).abs()
            erDen = pta.sma(erStep, length=self.erLen) * self.erLen
            erNum = (close - close.shift(self.erLen)).abs()
            er = erNum / erDen.replace(0, np.nan)
            er = er.fillna(0).clip(0, 1)
            return er

        def calc_slope():
            emaVal = pta.ema(close, length=self.slopeLen)
            atrVal = pta.atr(high, low, close, length=self.atrLen)
            slopeRaw = (emaVal - emaVal.shift(1)).abs()
            slopeNorm = (slopeRaw / atrVal.replace(0, np.nan) * 10).fillna(0).clip(0, 1)
            return slopeNorm

        def calc_score():
            adx_vals = calc_dmi()
            adxNorm = (adx_vals / 50.0).clip(0, 1)
            
            erNorm = calc_er()
            slopeNorm = calc_slope()
            
            score = 100.0 * (0.45 * adxNorm + 0.35 * erNorm + 0.20 * slopeNorm)
            return score

        def calc_dir():
            adx_result = pta.adx(high, low, close, length=self.adxLen)
            if adx_result is None or adx_result.empty:
                return pd.Series(True, index=close.index)
            pdi = adx_result.iloc[:, 1] if len(adx_result.columns) > 1 else pd.Series(50, index=close.index)
            mdi = adx_result.iloc[:, 2] if len(adx_result.columns) > 2 else pd.Series(50, index=close.index)
            return pdi >= mdi

        self.score = self.I(calc_score)
        self.direction_up = self.I(calc_dir)

    def next(self):
        if len(self.data) < self.confirmBars + 1:
            return

        current_score = self.score[-1]
        prev_score = self.score[-2] if len(self.score) > 1 else current_score

        threshold_upper = self.threshold + 3.0
        threshold_lower = self.threshold - 3.0

        is_trend = current_score > threshold_upper
        is_chop = current_score < threshold_lower

        if crossover(self.score, self.threshold):
            if not self.position:
                self.buy()
        elif crossover(self.threshold, self.score):
            if self.position:
                self.position.close()


