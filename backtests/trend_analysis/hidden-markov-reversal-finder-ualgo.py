class TvStrategy(Strategy):
    # Model parameters
    bull_stay = 0.92
    balance_stay = 0.86
    bear_stay = 0.90
    learning_rate = 0.055
    confidence_threshold = 0.58
    
    # Observation parameters
    return_smooth_length = 3
    return_z_length = 34
    vol_length = 14
    vol_baseline_length = 55
    obs_clamp = 3.5
    
    # Reversal logic parameters
    stretch_length = 34
    peak_lookback = 6
    stretch_threshold = 1.4
    probability_peak = 0.68
    probability_fade = 0.04
    flip_threshold = 0.12
    cooldown_bars = 10
    
    STATE_BULL = 0
    STATE_BALANCE = 1
    STATE_BEAR = 2
    STATE_COUNT = 3
    EPS = 0.000001

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate log returns
        def calc_log_return():
            returns = np.log(close / close.shift(1))
            return returns.fillna(0)
        
        log_return = self.I(calc_log_return)
        
        # Smoothed return
        smoothed_return = self.I(lambda: pta.ema(log_return, length=self.return_smooth_length) or pd.Series(0, index=close.index))
        
        # Return standardization
        def calc_return_obs():
            stdev = np.maximum(log_return.rolling(self.return_z_length).std(), self.EPS)
            obs = smoothed_return / stdev
            return np.clip(obs, -self.obs_clamp, self.obs_clamp)
        
        self.return_obs = self.I(calc_return_obs)
        
        # Volatility calculations
