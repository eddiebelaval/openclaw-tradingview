import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MasterTrend Parameters
    rsiMTPeriod = 14
    ema4Period = 4
    ema5Period = 5
    ema21Period = 21
    sma50Period = 50
    ema55Period = 55
    ema750Period = 750
    ema89Period = 89
    atrMult = 10.0
    rrSlPips = 10.0
    rrRatio = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hl2 = (high + low) / 2

        # Calculate indicators
        self.vwap = self.I(pta.vwap, hl2, volume)
        self.ema750 = self.I(pta.ema, close, length=self.ema750Period)
        self.ema4 = self.I(pta.ema, close, length=self.ema4Period)
        self.ema5 = self.I(pta.ema, close, length=self.ema5Period)
        self.ema21 = self.I(pta.ema, close, length=self.ema21Period)
        self.sma50 = self.I(pta.sma, close, length=self.sma50Period)
        self.ema55 = self.I(pta.ema, close, length=self.ema55Period)
        self.ema89 = self.I(pta.ema, close, length=self.ema89Period)
        self.rsiMT = self.I(pta.rsi, close, length=self.rsiMTPeriod)

        # Stochastic calculation
        stoch_result = self.I(pta.stoch, high, low, close, k=10, d=3, smooth_k=3)
        self.stoK = stoch_result

        # ATR bands
        tr = self.I(pta.tr, high, low, close)
        self.smoothATR = self.I(pta.ema, tr, length=self.ema750Period)
        self.upperBand = self.I(lambda: self.ema750 + self.atrMult * self.smoothATR if self.ema750 is not None and self.smoothATR is not None else pd.Series(0, index=close.index))
        self.lowerBand = self.I(lambda: self.ema750 - self.atrMult * self.smoothATR if self.ema750 is not None and self.smoothATR is not None else pd.Series(0, index=close.index))

        self.pipSize = 0.0001
        self.last_signal = None
        self.entry_price = None
        self.sl_level = None
        self.tp_level = None
        self.is_bull_trade = False

    def next(self):
        if len(self.data) < max(self.ema750Period, self.ema89Period, self.sma50Period):
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        # Engulfing detection
        open_prev = self.data.Open[-2] if len(self.data) > 1 else self.data.Open[-1]
        close_prev = self.data.Close[-2] if len(self.data) > 1 else self.data.Close[-1]
        open_curr = self.data.Open[-1]
        close_curr = self.data.Close[-1]

        bull_engulf = close_prev < open_prev and close_curr > open_curr and open_curr <= close_prev and close_curr >= open_prev
        bear_engulf = close_prev > open_prev and close_curr < open_curr and open_curr >= close_prev and close_curr <= open_prev

        is_bull_valid = bull_engulf and close > self.ema750[-1]
        is_bear_valid = bear_engulf and close < self.ema750[-1]
        is_orange = is_bull_valid or is_bear_valid

        # EMA crossovers
        ema4_cross_above5 = crossover(self.ema4, self.ema5)
        ema4_cross_below5 = crossover(self.ema5, self.ema4)

        # Close crossovers with EMA89
        ema89_bull_break = crossover(pd.Series(self.data.Close), pd.Series(self.ema89))
        ema89_bear_break = crossover(pd.Series(self.ema89), pd.Series(self.data.Close))

        # Bullish/Bearish conditions
        is_bullish_cond = (self.stoK[-1] > 52 if self.stoK[-1] is not None else False) or ema89_bull_break or (is_orange and is_bull_valid)
        is_bearish_cond = (self.stoK[-1] < 48 if self.stoK[-1] is not None else False) or ema89_bear_break or (is_orange and is_bear_valid)

        # VWAP filter
        vwap_cond_bull = close > self.vwap[-1] if self.vwap[-1] is not None else True
        vwap_cond_bear = close < self.vwap[-1] if self.vwap[-1] is not None else True

        # ATR filter
        atr_cond_bull = close <= self.upperBand[-1] if self.upperBand[-1] is not None else True
        atr_cond_bear = close >= self.lowerBand[-1] if self.lowerBand[-1] is not None else True

        # MasterTrend Bull Signal
        mt_bull = (
            ema4_cross_above5 and
            self.rsiMT[-1] > 50 and
            close > self.ema21[-1] and
            close > self.sma50[-1] and
            close > self.ema55[-1] and
            close > self.ema89[-1] and
            close > self.ema750[-1] and
            is_bullish_cond and
            vwap_cond_bull and
            atr_cond_bull
        )

        # MasterTrend Bear Signal
        mt_bear = (
            ema4_cross_below5 and
            self.rsiMT[-1] < 50 and
            close < self.ema21[-1] and
            close < self.sma50[-1] and
            close < self.ema55[-1] and
            close < self.ema89[-1] and
            close < self.ema750[-1] and
            is_bearish_cond and
            vwap_cond_bear and
            atr_cond_bear
        )

        # Exit existing position
        if self.position:
            if self.position.is_long and self.sl_level is not None:
                if low <= self.sl_level or high >= self.tp_level:
                    self.position.close()
                    self.last_signal = None
            elif self.position.is_short and self.sl_level is not None:
                if high >= self.sl_level or low <= self.tp_level:
                    self.position.close()
                    self.last_signal = None

        # Entry logic
        if mt_bull and not self.position:
            entry = close
            spike_wick = low
            sl_dist = (entry - spike_wick) + self.rrSlPips * self.pipSize
            sl = entry - sl_dist
            tp = entry + sl_dist * self.rrRatio

            self.entry_price = entry
            self.sl_level = sl
            self.tp_level = tp
            self.is_bull_trade = True
            self.last_signal = "bull"
            self.buy()

        elif mt_bear and not self.position:
            entry = close
            spike_wick = high
            sl_dist = (spike_wick - entry) + self.rrSlPips * self.pipSize
            sl = entry + sl_dist
            tp = entry - sl_dist * self.rrRatio

            self.entry_price = entry
            self.sl_level = sl
            self.tp_level = tp
            self.is_bull_trade = False
            self.last_signal = "bear"
            self.sell()