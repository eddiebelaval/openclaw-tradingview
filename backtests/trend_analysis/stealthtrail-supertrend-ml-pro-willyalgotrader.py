        momentum_ok = not self.use_momentum_filter or \
                     (self.trend_dir == 1 and rsi_val >= self.rsi_thresh) or \
                     (self.trend_dir == -1 and rsi_val <= (100.0 - self.rsi_thresh))
        
        session_ok = True
