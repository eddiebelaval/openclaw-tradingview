import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.highest_20 = self.I(lambda: high.rolling(window=20).max())
        self.lowest_20 = self.I(lambda: low.rolling(window=20).min())
        self.mid = self.I(lambda: (high.rolling(window=20).max() + low.rolling(window=20).min()) / 2)

    def next(self):
        if len(self.data) < 20:
            return
        
        if self.data.Close[-1] > self.mid[-1] and self.data.Close[-2] <= self.mid[-2]:
            if not self.position:
                self.buy()
        elif self.data.Close[-1] < self.mid[-1] and self.data.Close[-2] >= self.mid[-2]:
            if self.position:
                self.position.close()


