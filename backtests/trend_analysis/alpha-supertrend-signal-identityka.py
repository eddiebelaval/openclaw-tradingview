import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_length = 10
    manual_factor = 3.0
    use_auto = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Calculate HL2 (average of high and low)
        hl2 = self.I(lambda: (high + low) / 2)
        
        # Determine smart factor based on auto-adaptive logic
        def calculate_smart_factor():
            return self.manual_factor
        
        smart_factor = self.manual_factor
        
        # Calculate basic supertrend components
        # hl2 = (high + low) / 2
        # basic_ub = hl2 + smart_factor * atr
        # basic_lb = hl2 - smart_factor * atr
        
        def supertrend_calc():
            result_ub = pd.Series(index=close.index, dtype='float64')
            result_lb = pd.Series(index=close.index, dtype='float64')
            result_st = pd.Series(index=close.index, dtype='float64')
            result_dir = pd.Series(index=close.index, dtype='float64')
            
            hl2_vals = (high + low) / 2
            atr_vals = pta.atr(high, low, close, length=self.atr_length)
            
            if atr_vals is None:
                return None, None
            
            ub = hl2_vals + smart_factor * atr_vals
            lb = hl2_vals - smart_factor * atr_vals
            
            result_st.iloc[0] = close.iloc[0]
            result_dir.iloc[0] = 1
            
            for i in range(1, len(close)):
                if pd.isna(ub.iloc[i]) or pd.isna(lb.iloc[i]):
                    result_st.iloc[i] = result_st.iloc[i-1]
                    result_dir.iloc[i] = result_dir.iloc[i-1]
                    continue
                
                if close.iloc[i] <= ub.iloc[i]:
                    result_st.iloc[i] = ub.iloc[i]
                    result_dir.iloc[i] = 1
                else:
                    result_st.iloc[i] = lb.iloc[i]
                    result_dir.iloc[i] = -1
            
            return result_st, result_dir
        
        st_result = supertrend_calc()
        if st_result[0] is not None:
            self.supertrend = self.I(lambda: st_result[0])
            self.direction = self.I(lambda: st_result[1])
        else:
            self.supertrend = self.I(lambda: pd.Series(close.mean(), index=close.index))
            self.direction = self.I(lambda: pd.Series(1, index=close.index))

    def next(self):
        if len(self.data) < self.atr_length + 5:
            return
        
        # Detect crossover of direction through 0
        # buy_signal: direction crosses below 0 (from 1 to -1)
        # sell_signal: direction crosses above 0 (from -1 to 1)
        
        current_dir = self.direction[-1]
        prev_dir = self.direction[-2] if len(self.direction) > 1 else current_dir
        
        # Buy signal: direction was 1 (up), now becomes -1 (down crossover means reversal to down)
        # But based on the Pine Script: buy_signal = ta.crossunder(direction, 0)
        # This means direction crosses UNDER 0, so from positive to negative
        # sell_signal = ta.crossover(direction, 0)
        # This means direction crosses OVER 0, so from negative to positive
        
        buy_signal = prev_dir > 0 and current_dir < 0
        sell_signal = prev_dir < 0 and current_dir > 0
        
        if buy_signal:
            if not self.position:
                self.buy()
        elif sell_signal:
            if self.position:
                self.position.close()