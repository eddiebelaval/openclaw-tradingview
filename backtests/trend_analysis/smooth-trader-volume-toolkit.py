import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hlc3 = (high + low + close) / 3
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # EMA for MV Cloud
        self.ema_21 = self.I(pta.ema, close, length=21)
        
        # Running VWAP calculation
        def running_vwap(src, length=50):
            pv = src * volume
            cum_pv = pv.rolling(length).sum()
            cum_vol = volume.rolling(length).sum()
            vwap = cum_pv / cum_vol
            return vwap
        
        self.mv_cloud_vwap = self.I(running_vwap, hlc3, length=50)
        
        # RSI for additional confirmation
        self.rsi = self.I(pta.rsi, close, length=14)
        
        self.last_signal = None

    def next(self):
        if len(self.data) < 2:
            return
        
        # MV Cloud strategy: Buy when EMA crosses above VWAP, Sell when crosses below
        ema_val = self.ema_21[-1]
        vwap_val = self.mv_cloud_vwap[-1]
        ema_prev = self.ema_21[-2]
        vwap_prev = self.mv_cloud_vwap[-2]
        
        # Avoid division by zero and NaN values
        if pd.isna(ema_val) or pd.isna(vwap_val) or pd.isna(ema_prev) or pd.isna(vwap_prev):
            return
        
        bullish_crossover = (ema_prev <= vwap_prev) and (ema_val > vwap_val)
        bearish_crossover = (ema_prev >= vwap_prev) and (ema_val < vwap_val)
        
        if bullish_crossover and self.last_signal != "buy":
            if self.position:
                self.position.close()
            self.buy()
            self.last_signal = "buy"
        elif bearish_crossover and self.last_signal != "sell":
            if self.position:
                self.position.close()
            self.last_signal = "sell"