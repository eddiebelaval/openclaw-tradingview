        low_arr = self.data.Low
        close_arr = self.data.Close
        
        current_high = high_arr[-1]
        current_low = low_arr[-1]
        current_close = close_arr[-1]
        
        if idx >= self.major_ph_len + 1:
            lookback_idx = idx - self.major_ph_len
            
