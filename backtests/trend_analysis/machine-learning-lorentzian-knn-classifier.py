import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend Following
    trend_ema_fast = 21
    trend_ema_slow = 50
    trend_ema_filter = 200
    
    # MA Ribbon
    use_ma_ribbon = True
    ribbon_type = "EMA"
    ribbon_ma1 = 8
    ribbon_ma2 = 13
    ribbon_ma3 = 21
    ribbon_ma4 = 34
    ribbon_ma5 = 55
    ribbon_ma6 = 89
    ribbon_ma7 = 144
    ribbon_ma8 = 233
    ribbon_threshold = 6
    
    # Breakout
    breakout_length = 20
    breakout_atr_mult = 1.5
    
    # Mean Reversion
    bb_length = 20
    bb_mult = 2.0
    rsi_length = 14
    rsi_ob = 70
    rsi_os = 30
    
    # Risk Management
    atr_length = 14
    stop_atr_mult = 2.0
    tp_atr_mult = 3.0
    use_trailing = True
    trailing_atr_mult = 1.5
    
    # Filters
    adx_length = 14
    adx_threshold = 20
    volume_mult = 1.2
    
    # KNN
    knn_neighbors = 8
    knn_lookback = 50
    knn_weight = 0.55
    knn_rsi_len = 14
    knn_wt_n1 = 10
    knn_wt_n2 = 21
    knn_cci_len = 20
    knn_adx_len = 14
    
    # Kernel
    kernel_len = 34
    kernel_atr_len = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        self.ema_fast = self.I(pta.ema, close, length=self.trend_ema_fast)
        self.ema_slow = self.I(pta.ema, close, length=self.trend_ema_slow)
        self.ema_filter = self.I(pta.ema, close, length=self.trend_ema_filter)
        
        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=self.adx_length)
        self.adx = adx_result['ADX_14'] if isinstance(adx_result, pd.DataFrame) else adx_result
        
        # Bollinger Bands
        bb_result = self.I(pta.bbands, close, length=self.bb_length, std=self.bb_mult)
        self.bb_upper = bb_result[f'BBU_{self.bb_length}_{self.bb_mult}'] if isinstance(bb_result, pd.DataFrame) else None
        self.bb_lower = bb_result[f'BBL_{self.bb_length}_{self.bb_mult}'] if isinstance(bb_result, pd.DataFrame) else None
        self.bb_basis = bb_result[f'BB_{self.bb_length}_{self.bb_mult}'] if isinstance(bb_result, pd.DataFrame) else None
        
        if self.bb_upper is None:
            self.bb_upper = self.I(lambda: (close.rolling(self.bb_length).mean() + self.bb_mult * close.rolling(self.bb_length).std()))
            self.bb_lower = self.I(lambda: (close.rolling(self.bb_length).mean() - self.bb_mult * close.rolling(self.bb_length).std()))
            self.bb_basis = self.I(pta.sma, close, length=self.bb_length)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Volume
        self.volume_sma = self.I(pta.sma, volume, length=20)
        
        # Highest/Lowest
        self.highest_high = self.I(lambda: high.rolling(self.breakout_length).max())
        self.lowest_low = self.I(lambda: low.rolling(self.breakout_length).min())
        
        # MA Ribbon
        self.r1 = self.I(pta.ema, close, length=self.ribbon_ma1)
        self.r2 = self.I(pta.ema, close, length=self.ribbon_ma2)
        self.r3 = self.I(pta.ema, close, length=self.ribbon_ma3)
        self.r4 = self.I(pta.ema, close, length=self.ribbon_ma4)
        self.r5 = self.I(pta.ema, close, length=self.ribbon_ma5)
        self.r6 = self.I(pta.ema, close, length=self.ribbon_ma6)
        self.r7 = self.I(pta.ema, close, length=self.ribbon_ma7)
        self.r8 = self.I(pta.ema, close, length=self.ribbon_ma8)
        
        # KNN Features
        self.knn_rsi = self.I(pta.rsi, close, length=self.knn_rsi_len)
        
        # WaveTrend
        hlc3 = (high + low + close) / 3
        wt_esa = self.I(pta.ema, hlc3, length=self.knn_wt_n1)
        wt_d = self.I(lambda: pta.ema(np.abs(pd.Series(self.data.High) + pd.Series(self.data.Low) + pd.Series(self.data.Close)).div(3) - wt_esa, length=self.knn_wt_n1))
        self.knn_wt = self.I(lambda: pta.ema((hlc3 - wt_esa) / (0.015 * (wt_d + 1e-10)), length=self.knn_wt_n2))
        
        # CCI
        self.knn_cci = self.I(pta.cci, high, low, close, length=self.knn_cci_len)
        
        # ADX for KNN
        knn_adx_result = self.I(pta.adx, high, low, close, length=self.knn_adx_len)
        self.knn_adx = knn_adx_result['ADX_14'] if isinstance(knn_adx_result, pd.DataFrame) else knn_adx_result
        
        # Kernel
        self.kernel_center = self.I(pta.ema, close, length=self.kernel_len)
        self.kernel_atr = self.I(pta.atr, high, low, close, length=self.kernel_atr_len)

    def next(self):
        if len(self.data) < self.knn_lookback + 20:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        atr_val = self.atr[-1] if self.atr[-1] else 0
        ema_fast_val = self.ema_fast[-1]
        ema_slow_val = self.ema_slow[-1]
        ema_filter_val = self.ema_filter[-1]
        adx_val = self.adx[-1] if not np.isnan(self.adx[-1]) else 0
        
        rsi_val = self.rsi[-1] if not np.isnan(self.rsi[-1]) else 50
        volume_sma_val = self.volume_sma[-1]
        highest_high_val = self.highest_high[-1] if self.highest_high[-1] else high
        lowest_low_val = self.lowest_low[-1] if self.lowest_low[-1] else low
        
        volume_spike = volume > volume_sma_val * self.volume_mult if volume_sma_val > 0 else False
        
        # MA Ribbon
        ribbon_bullish_count = 0
        if self.r1[-1] > self.r2[-1]: ribbon_bullish_count += 1
        if self.r2[-1] > self.r3[-1]: ribbon_bullish_count += 1
        if self.r3[-1] > self.r4[-1]: ribbon_bullish_count += 1
        if self.r4[-1] > self.r5[-1]: ribbon_bullish_count += 1
        if self.r5[-1] > self.r6[-1]: ribbon_bullish_count += 1
        if self.r6[-1] > self.r7[-1]: ribbon_bullish_count += 1
        if self.r7[-1] > self.r8[-1]: ribbon_bullish_count += 1
        
        ribbon_bearish_count = 0
        if self.r1[-1] < self.r2[-1]: ribbon_bearish_count += 1
        if self.r2[-1] < self.r3[-1]: ribbon_bearish_count += 1
        if self.r3[-1] < self.r4[-1]: ribbon_bearish_count += 1
        if self.r4[-1] < self.r5[-1]: ribbon_bearish_count += 1
        if self.r5[-1] < self.r6[-1]: ribbon_bearish_count += 1
        if self.r6[-1] < self.r7[-1]: ribbon_bearish_count += 1
        if self.r7[-1] < self.r8[-1]: ribbon_bearish_count += 1
        
        ribbon_bullish = ribbon_bullish_count >= (self.ribbon_threshold - 1)
        ribbon_bearish = ribbon_bearish_count >= (self.ribbon_threshold - 1)
        ribbon_filter_long = not self.use_ma_ribbon or ribbon_bullish
        ribbon_filter_short = not self.use_ma_ribbon or ribbon_bearish
        
        # Trend conditions
        is_trending = adx_val > self.adx_threshold
        bullish_trend = ema_fast_val > ema_slow_val and close > ema_filter_val
        bearish_trend = ema_fast_val < ema_slow_val and close < ema_filter_val
        
        # Entry conditions
        ema_cross_up = crossover(self.ema_fast, self.ema_slow)
        ema_cross_down = crossover(self.ema_slow, self.ema_fast)
        rsi_cross_up = crossover(self.rsi, self.rsi_os)
        rsi_cross_down = crossover(self.rsi_ob, self.rsi)
        
        trend_long = is_trending and bullish_trend and ema_cross_up and volume_spike
        trend_short = is_trending and bearish_trend and ema_cross_down and volume_spike
        
        breakout_long = close > highest_high_val and volume_spike and close > ema_filter_val
        breakout_short = close < lowest_low_val and volume_spike and close < ema_filter_val
        
        mean_reversion_long = not is_trending and close < self.bb_lower[-1] and rsi_val < self.rsi_os and rsi_cross_up
        mean_reversion_short = not is_trending and close > self.bb_upper[-1] and rsi_val > self.rsi_ob and rsi_cross_down
        
        long_condition = (trend_long or breakout_long or mean_reversion_long) and ribbon_filter_long
        short_condition = (trend_short or breakout_short or mean_reversion_short) and ribbon_filter_short
        
        if long_condition and self.position.size == 0:
            stop_loss = close - (atr_val * self.stop_atr_mult)
            take_profit = close + (atr_val * self.tp_atr_mult)
            self.buy()
        
        if short_condition and self.position.size == 0:
            stop_loss = close + (atr_val * self.stop_atr_mult)
            take_profit = close - (atr_val * self.tp_atr_mult)
            self.sell()
        
        # Exit logic with stop loss and take profit
        if self.position.size > 0:
            stop_loss = close - (atr_val * self.stop_atr_mult)
            take_profit = close + (atr_val * self.tp_atr_mult)
            if close <= stop_loss or close >= take_profit:
                self.position.close()
        
        if self.position.size < 0:
            stop_loss = close + (atr_val * self.stop_atr_mult)
            take_profit = close - (atr_val * self.tp_atr_mult)
            if close >= stop_loss or close <= take_profit:
                self.position.close()


