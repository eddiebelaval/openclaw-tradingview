import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    respect_len = 10

    def init(self):
        # We need daily data to calculate the pivot
        # Since backtesting.py works with the data we provide,
        # we'll calculate the pivot based on the close prices with proper lookback
        
        close = pd.Series(self.data.Close)
        
        # Calculate ROC(2) Pivot for each bar
        # Pivot = (close[1] - close[3]) + close[2]
        # We need to shift appropriately
        def calc_pivot(series):
            result = pd.Series(np.nan, index=series.index)
            for i in range(3, len(series)):
                result.iloc[i] = (series.iloc[i-1] - series.iloc[i-3]) + series.iloc[i-2]
            return result
        
        self.pivot = self.I(lambda: calc_pivot(close))
        
        # Calculate bias: price > pivot
        def calc_bias(series, pivot_series):
            result = pd.Series(False, index=series.index)
            for i in range(len(series)):
                if not np.isnan(pivot_series.iloc[i]):
                    result.iloc[i] = series.iloc[i] > pivot_series.iloc[i]
            return result
        
        self.is_long = self.I(lambda: calc_bias(close, self.pivot))
        
        # Track previous bias for crossover detection
        self.prev_is_long = False

    def next(self):
        # Skip if pivot is not yet calculated
        if np.isnan(self.pivot[-1]):
            return
        
        current_is_long = self.is_long[-1]
        
        # Detect bias flip from short to long
        if current_is_long and not self.prev_is_long:
            if self.position:
                self.position.close()
            self.buy()
        
        # Detect bias flip from long to short
        elif not current_is_long and self.prev_is_long:
            if self.position:
                self.position.close()
            self.sell()
        
        self.prev_is_long = current_is_long


