import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        # Initialize tracking variables on first bar
        if len(self.data) == 1:
            self.current_ext_low = self.data.Low[-1]
            self.ext_low_bar_index = 0
            self.current_ext_high = self.data.High[-1]
            self.ext_high_bar_index = 0
            self.last_confirmed_price = np.nan
            self.last_confirmed_index = np.nan
            self.looking_for_sl = True
            self.swing_lows = []
            self.swing_highs = []
            return
        
        # Ensure tracking variables exist
        if not hasattr(self, 'current_ext_low'):
            self.current_ext_low = self.data.Low[-1]
            self.ext_low_bar_index = len(self.data) - 1
            self.current_ext_high = self.data.High[-1]
            self.ext_high_bar_index = len(self.data) - 1
            self.last_confirmed_price = np.nan
            self.last_confirmed_index = np.nan
            self.looking_for_sl = True
            self.swing_lows = []
            self.swing_highs = []
        
        current_idx = len(self.data) - 1
        current_low = self.data.Low[-1]
        current_high = self.data.High[-1]
        current_close = self.data.Close[-1]
        prev_high = self.data.High[-2] if len(self.data) > 1 else current_high
        prev_low = self.data.Low[-2] if len(self.data) > 1 else current_low
        
        # SWING LOW LOGIC
        if current_low < self.current_ext_low or np.isnan(self.current_ext_low):
            self.current_ext_low = current_low
            self.ext_low_bar_index = current_idx
        
        if self.looking_for_sl and not np.isnan(self.current_ext_low) and current_close > prev_high:
            # Swing low confirmed
            self.swing_lows.append((self.ext_low_bar_index, self.current_ext_low))
            
            # Entry signal on swing low confirmation
            if not self.position:
                self.buy()
            
            self.last_confirmed_price = self.current_ext_low
            self.last_confirmed_index = self.ext_low_bar_index
            self.looking_for_sl = False
            self.current_ext_low = np.nan
            self.current_ext_high = current_high
            self.ext_high_bar_index = current_idx
        
        # SWING HIGH LOGIC
        if current_high > self.current_ext_high or np.isnan(self.current_ext_high):
            self.current_ext_high = current_high
            self.ext_high_bar_index = current_idx
        
        if not self.looking_for_sl and not np.isnan(self.current_ext_high) and current_close < prev_low:
            # Swing high confirmed
            self.swing_highs.append((self.ext_high_bar_index, self.current_ext_high))
            
            # Exit signal on swing high confirmation
            if self.position:
                self.position.close()
            
            self.last_confirmed_price = self.current_ext_high
            self.last_confirmed_index = self.ext_high_bar_index
            self.looking_for_sl = True
            self.current_ext_high = np.nan
            self.current_ext_low = current_low
            self.ext_low_bar_index = current_idx


