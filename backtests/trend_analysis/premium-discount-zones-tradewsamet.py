import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rangeLen = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate highest high and lowest low over range
        self.swing_high = self.I(lambda: high.rolling(self.rangeLen).max())
        self.swing_low = self.I(lambda: low.rolling(self.rangeLen).min())
        
        # Calculate zone levels
        self.premium_top = self.I(self._calc_premium_top, high, low)
        self.premium_bottom = self.I(self._calc_premium_bottom, high, low)
        self.discount_top = self.I(self._calc_discount_top, high, low)
        self.discount_bottom = self.I(self._calc_discount_bottom, high, low)
        self.eq_level = self.I(self._calc_eq_level, high, low)

    def _calc_premium_top(self, high, low):
        swing_high = high.rolling(self.rangeLen).max()
        swing_low = low.rolling(self.rangeLen).min()
        return swing_high

    def _calc_premium_bottom(self, high, low):
        swing_high = high.rolling(self.rangeLen).max()
        swing_low = low.rolling(self.rangeLen).min()
        return 0.95 * swing_high + 0.05 * swing_low

    def _calc_discount_top(self, high, low):
        swing_high = high.rolling(self.rangeLen).max()
        swing_low = low.rolling(self.rangeLen).min()
        return 0.95 * swing_low + 0.05 * swing_high

    def _calc_discount_bottom(self, high, low):
        swing_high = high.rolling(self.rangeLen).max()
        swing_low = low.rolling(self.rangeLen).min()
        return swing_low

    def _calc_eq_level(self, high, low):
        swing_high = high.rolling(self.rangeLen).max()
        swing_low = low.rolling(self.rangeLen).min()
        return (swing_high + swing_low) / 2

    def next(self):
        if len(self.data) < self.rangeLen:
            return

        current_price = self.data.Close[-1]
        
        premium_top = self.premium_top[-1]
        premium_bottom = self.premium_bottom[-1]
        discount_top = self.discount_top[-1]
        discount_bottom = self.discount_bottom[-1]
        eq_level = self.eq_level[-1]

        if pd.isna(premium_top) or pd.isna(premium_bottom) or pd.isna(discount_top) or pd.isna(discount_bottom) or pd.isna(eq_level):
            return

        # Entry in premium zone (overbought) - sell signal
        if premium_bottom <= current_price <= premium_top:
            if not self.position:
                self.sell()
        
        # Entry in discount zone (oversold) - buy signal
        elif discount_bottom <= current_price <= discount_top:
            if not self.position:
                self.buy()
        
        # Exit when price touches equilibrium level
        elif abs(current_price - eq_level) < 0.001 * current_price:
            if self.position:
                self.position.close()


