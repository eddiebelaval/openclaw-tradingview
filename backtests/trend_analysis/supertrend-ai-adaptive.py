import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    i_atLen = 10
    i_bMult = 3.0
    i_regLen = 40
    i_adxLen = 14
    i_adxThr = 20
    i_adapt = True
    i_trendLen = 50
    i_volLen = 20
    i_minSc = 40
    i_sigCD = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.i_atLen) or pd.Series(0.1, index=close.index))
        
        self.atr_ma = self.I(lambda: pta.sma(self.atr, length=self.i_regLen) or pd.Series(0.1, index=close.index))
        
        self.vol_ma = self.I(lambda: pta.sma(volume, length=self.i_volLen) or pd.Series(1, index=volume.index))
        
        self.trend_ema = self.I(lambda: pta.ema(close, length=self.i_trendLen) or close)
        
        def calc_adx():
            result = pta.adx(high, low, close, length=self.i_adxLen)
            if result is not None and not result.empty:
                adx_col = [col for col in result.columns if 'ADX' in col.upper()]
                if adx_col:
                    return result[adx_col[0]]
            return pd.Series(20, index=close.index)
        
        self.adx = self.I(calc_adx)
        
        self.regime = None
        self.st_band = None
        self.st_dir = 1
        self.adapt_mult = self.i_bMult
        self.last_signal_bar = -self.i_sigCD - 1
        self.last_signal_score = 0
        self.prev_st_dir = 1
        self.signal_triggered = False

    def next(self):
        if len(self.data) < max(self.i_atLen, self.i_regLen, self.i_adxLen, self.i_trendLen) + 5:
            return

        atr_val = self.atr[-1]
        atr_ma_val = self.atr_ma[-1]
        safe_atr = max(atr_val, 0.001)
        
        atr_ratio = atr_val / max(atr_ma_val, 0.001)
        
        if atr_ratio > 1.4:
            self.regime = 2
        elif self.adx[-1] < self.i_adxThr and atr_ratio < 0.9:
            self.regime = 0
        else:
            self.regime = 1
        
        self.adapt_mult = self.i_bMult
        if self.i_adapt:
            if self.regime == 2:
                self.adapt_mult = self.i_bMult * (1.0 + max(0, atr_ratio - 1.0) * 0.4)
            elif self.regime == 0:
                self.adapt_mult = self.i_bMult * 0.85
        
        self.adapt_mult = max(min(self.adapt_mult, self.i_bMult * 2.0), self.i_bMult * 0.5)
        
        src = (self.data.High[-1] + self.data.Low[-1]) / 2
        upper_base = src + self.adapt_mult * safe_atr
        lower_base = src - self.adapt_mult * safe_atr
        
        if self.st_band is None:
            self.st_band = lower_base if self.st_dir == 1 else upper_base
        else:
            prev_band = self.st_band
            
            if self.st_dir == 1:
                self.st_band = max(lower_base, prev_band)
                if self.data.Close[-1] < self.st_band:
                    self.st_dir = -1
                    self.st_band = upper_base
            else:
                self.st_band = min(upper_base, prev_band)
                if self.data.Close[-1] > self.st_band:
                    self.st_dir = 1
                    self.st_band = lower_base
        
        trend_flip = self.st_dir != self.prev_st_dir
        self.prev_st_dir = self.st_dir
        
        trend_up = self.data.Close[-1] > self.trend_ema[-1]
        trend_dn = self.data.Close[-1] < self.trend_ema[-1]
        
        bull_signal = False
        bear_signal = False
        sig_score = 0
        
        if trend_flip and (len(self.data) - self.last_signal_bar) > self.i_sigCD:
            if self.st_dir == 1:
                sig_score = self._score_signal(True, src, safe_atr, trend_up)
            else:
                sig_score = self._score_signal(False, src, safe_atr, trend_dn)
            
            if sig_score >= self.i_minSc:
                if self.st_dir == 1:
                    bull_signal = True
                else:
                    bear_signal = True
                
                self.last_signal_bar = len(self.data) - 1
                self.last_signal_score = sig_score
        
        if bull_signal and not self.position:
            self.buy()
        elif bear_signal and self.position:
            self.sell()

    def _score_signal(self, is_bull, src, safe_atr, trend_aligned):
        score = 0
        
        vol_ratio = self.data.Volume[-1] / max(self.vol_ma[-1], 1)
        if vol_ratio >= 2.5:
            score += 20
        elif vol_ratio >= 1.5:
            score += 14
        elif vol_ratio >= 1.0:
            score += 8
        else:
            score += 3
        
        disp = (self.data.Close[-1] - self.st_band) if is_bull else (self.st_band - self.data.Close[-1])
        disp_atr = disp / safe_atr if safe_atr > 0 else 0
        
        if disp_atr >= 1.5:
            score += 25
        elif disp_atr >= 0.8:
            score += 18
        elif disp_atr >= 0.3:
            score += 12
        elif disp_atr > 0:
            score += 5
        
        ema_dist = abs(self.data.Close[-1] - self.trend_ema[-1]) / safe_atr
        if trend_aligned and ema_dist > 0.5:
            score += 20
        elif trend_aligned:
            score += 14
        elif ema_dist < 0.3:
            score += 8
        else:
            score += 2
        
        if self.regime == 1:
            score += 15
        elif self.regime == 2:
            score += 8
        else:
            score += 3
        
        score += 10
        
        return min(int(score), 100)