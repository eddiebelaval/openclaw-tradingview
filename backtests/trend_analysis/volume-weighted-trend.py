import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vwma_len = 34
    atr_mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate VWMA (Volume Weighted Moving Average)
        self.basis = self.I(pta.vwma, close, volume, length=self.vwma_len)
        
        # Calculate ATR
        self.atr_val = self.I(pta.atr, high, low, close, length=self.vwma_len)
        
        # Calculate bands
        self.upper = self.I(lambda: self.basis + self.atr_val * self.atr_mult)
        self.lower = self.I(lambda: self.basis - self.atr_val * self.atr_mult)
        
        # Track trend state
        self.trend = 0
        self.prev_trend = 0

    def next(self):
        # Get current values
        current_close = self.data.Close[-1]
        current_upper = self.upper[-1]
        current_lower = self.lower[-1]
        
        # Handle NaN values
        if np.isnan(current_close) or np.isnan(current_upper) or np.isnan(current_lower):
            return
        
        # Update trend
        self.prev_trend = self.trend
        
        if current_close > current_upper:
            self.trend = 1
        elif current_close < current_lower:
            self.trend = -1
        
        # Generate signals
        bull_signal = self.trend == 1 and self.prev_trend != 1
        bear_signal = self.trend == -1 and self.prev_trend != -1
        
        # Trading logic
        if bull_signal:
            if self.position:
                self.position.close()
            self.buy()
        elif bear_signal:
            if self.position:
                self.position.close()


