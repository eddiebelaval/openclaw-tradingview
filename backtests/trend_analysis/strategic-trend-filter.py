import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 28
    cl = 11

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate OHLC average
        ohlc = (open_ + high + low + close) / 4

        # Calculate factors for each OHLC component
        def calc_correlation(src, ohlc_series, length):
            return src.rolling(window=length).apply(
                lambda x: ohlc_series.iloc[-length:].corr(x) if len(x) == length else 0,
                raw=False
            )

        def calc_roc(src, length):
            return ((src - src.shift(length)) / src.shift(length)).abs()

        fo1 = calc_correlation(low, ohlc, self.len)
        fo2 = low.rolling(window=self.len).std()
        fo3 = calc_roc(low, self.len)

        fh1 = calc_correlation(low, ohlc, self.len)
        fh2 = low.rolling(window=self.len).std()
        fh3 = calc_roc(low, self.len)

        fl1 = calc_correlation(low, ohlc, self.len)
        fl2 = low.rolling(window=self.len).std()
        fl3 = calc_roc(low, self.len)

        fc1 = calc_correlation(close, ohlc, self.len)
        fc2 = close.rolling(window=self.len).std()
        fc3 = calc_roc(close, self.len)

        # Handle NaN values with forward fill
        fo1 = fo1.fillna(method='bfill').fillna(0)
        fo2 = fo2.fillna(method='bfill').fillna(0)
        fo3 = fo3.fillna(method='bfill').fillna(0)
        fh1 = fh1.fillna(method='bfill').fillna(0)
        fh2 = fh2.fillna(method='bfill').fillna(0)
        fh3 = fh3.fillna(method='bfill').fillna(0)
        fl1 = fl1.fillna(method='bfill').fillna(0)
        fl2 = fl2.fillna(method='bfill').fillna(0)
        fl3 = fl3.fillna(method='bfill').fillna(0)
        fc1 = fc1.fillna(method='bfill').fillna(0)
        fc2 = fc2.fillna(method='bfill').fillna(0)
        fc3 = fc3.fillna(method='bfill').fillna(0)

        fo = fo1 * fo2 * fo3
        fh = fh1 * fh2 * fh3
        fl = fl1 * fl2 * fl3
        fc = fc1 * fc2 * fc3

        om = (open_.rolling(window=self.len).max() + open_.rolling(window=self.len).min()) / 2
        hm = (high.rolling(window=self.len).max() + high.rolling(window=self.len).min()) / 2
        lm = (low.rolling(window=self.len).max() + low.rolling(window=self.len).min()) / 2
        cm = (close.rolling(window=self.len).max() + close.rolling(window=self.len).min()) / 2

        denominator = fo + fh + fl + fc
        denominator = denominator.replace(0, 1)

        filter_ = (om * fo + hm * fh + lm * fl + cm * fc) / denominator

        # Apply volume filter
        self.filter = self.I(
            lambda: filter_.where(volume >= volume.shift(1), filter_.shift(1)).fillna(filter_)
        )

        # True Range and Median True Range
        tr = self.I(pta.tr, high, low, close, talib=False)
        tr = tr.fillna(0)

        mtr = self.I(lambda: tr.rolling(window=self.cl).median().fillna(0))

        self.tr = tr
        self.mtr = mtr
        self.low = low
        self.high = high

    def next(self):
        if len(self) < max(self.len, self.cl) + 1:
            return

        current_filter = self.filter[-1]
        current_tr = self.tr[-1]
        current_mtr = self.mtr[-1]
        current_low = self.low[-1]
        current_high = self.high[-1]

        prev_filter = self.filter[-2] if len(self.filter) > 1 else current_filter

        # Trend conditions
        L = current_low > current_filter and current_tr > current_mtr
        S = current_high < current_filter and current_tr > current_mtr

        # Determine trend
        if not hasattr(self, 'trend'):
            self.trend = 0

        prev_trend = self.trend

        if L and not S:
            self.trend = 1
        elif S:
            self.trend = -1

        # Trading logic based on trend changes
        if self.trend > prev_trend and self.trend == 1:
            # Trend changed to long
            if self.position.is_short:
                self.position.close()
            if not self.position:
                self.buy()
        elif self.trend < prev_trend and self.trend == -1:
            # Trend changed to short
            if self.position.is_long:
                self.position.close()