import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    left_bars = 5
    right_bars = 3
    use_ema = False
    ema_len = 200
    use_rsi = False
    rsi_len = 14
    rsi_ob = 70
    rsi_os = 30

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_len) or pd.Series(50, index=close.index))
        
        # Calculate EMA
        self.ema = self.I(lambda: pta.ema(close, length=self.ema_len) or pd.Series(close, index=close.index))
        
        # Pivot High and Low detection using rolling windows
        def detect_pivot_high(h, l, lb, rb):
            result = pd.Series(np.nan, index=h.index)
            for i in range(lb, len(h) - rb):
                if h.iloc[i] == h.iloc[i-lb:i+1].max() and h.iloc[i] == h.iloc[i:i+rb+1].max():
                    result.iloc[i] = h.iloc[i]
            return result
        
        def detect_pivot_low(h, l, lb, rb):
            result = pd.Series(np.nan, index=l.index)
            for i in range(lb, len(l) - rb):
                if l.iloc[i] == l.iloc[i-lb:i+1].min() and l.iloc[i] == l.iloc[i:i+rb+1].min():
                    result.iloc[i] = l.iloc[i]
            return result
        
        self.pivot_high = self.I(lambda: detect_pivot_high(high, low, self.left_bars, self.right_bars))
        self.pivot_low = self.I(lambda: detect_pivot_low(high, low, self.left_bars, self.right_bars))
        
        self.in_position = False

    def next(self):
        if len(self.data) <= self.right_bars:
            return
        
        # Get values at confirmation bar offset
        offset_idx = len(self.data) - self.right_bars - 1
        if offset_idx < 0:
            return
        
        rsi_val = self.rsi[-1] if len(self.rsi) > 0 else 50
        ema_val = self.ema[-1] if len(self.ema) > 0 else self.data.Close[-1]
        close_val = self.data.Close[-1]
        
        # Check for valid pivot high (TOP)
        ph_valid = not np.isnan(self.pivot_high[-1])
        ph_rsi_check = (not self.use_rsi) or (rsi_val >= self.rsi_ob)
        ph_ema_check = (not self.use_ema) or (close_val < ema_val)
        valid_ph = ph_valid and ph_rsi_check and ph_ema_check
        
        # Check for valid pivot low (BOTTOM)
        pl_valid = not np.isnan(self.pivot_low[-1])
        pl_rsi_check = (not self.use_rsi) or (rsi_val <= self.rsi_os)
        pl_ema_check = (not self.use_ema) or (close_val > ema_val)
        valid_pl = pl_valid and pl_rsi_check and pl_ema_check
        
        # Trading logic
        if valid_pl and not self.position:
            self.buy()
        elif valid_ph and self.position:
            self.position.close()