        prev_close = self.data.Close[-2]

        if not self.position:
            if close < self.lower_band[-1] and prev_close >= self.lower_band[-2]:
                self.buy()
            elif close > self.upper_band[-1] and prev_close <= self.upper_band[-2]:
                self.sell()
        else:
            if self.position.is_long:
                if close > self.upper_band[-1]:
                    self.position.close()
                elif close < self.mid_band[-1]:
                    self.position.close()
            elif self.position.is_short:
                if close < self.lower_band[-1]:
                    self.position.close()
                elif close > self.mid_band[-1]:
                    self.position.close()


