        pivot_idx = right_bars
        if pivot_idx >= len(highs):
            return None
        pivot_high = highs.iloc[pivot_idx]
        is_pivot = all(highs.iloc[i] <= pivot_high for i in range(len(highs)) if i != pivot_idx)
        return pivot_high if is_pivot else None

