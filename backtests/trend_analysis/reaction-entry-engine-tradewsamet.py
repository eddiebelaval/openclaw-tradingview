    def _impulse_check_supply(self, check_idx):
        if not self.sd_useImp:
            return True
        
        ok = True
        for k in range(1, self.sd_impBars + 1):
            off = self.sd_rightBars - k
            if off < 0 or check_idx - off < 0:
                ok = False
                break
            
            bar_idx = len(self.data) - 1 - off
            if bar_idx < 0 or bar_idx >= len(self.data):
                ok = False
                break
            
