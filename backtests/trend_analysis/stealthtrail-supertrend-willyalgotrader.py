import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLengthInput = 13
    baseMultInput = 2.5
    adaptiveInput = True
    adaptSmoothInput = 55
    cushionInput = 0.15
    cooldownInput = 3
    useMomentumInput = True
    rsiLengthInput = 13
    rsiThreshInput = 45.0
    useVolumeInput = False
    volMultInput = 1.2
    minMultInput = 1.0
    maxMultInput = 5.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atrLengthInput) or pd.Series(0.01, index=close.index))
        self.atr_sma = self.I(lambda: pta.sma(self.atr, length=self.adaptSmoothInput) or pd.Series(self.atr.iloc[-1] if len(self.atr) > 0 else 0.01, index=close.index))
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLengthInput) or pd.Series(50.0, index=close.index))
        self.vol_sma = self.I(lambda: pta.sma(volume, length=20) or pd.Series(volume.iloc[-1] if len(volume) > 0 else 1.0, index=volume.index))

        self.trend_dir = 1
        self.st_band = None
        self.bars_since_flip = 100
        self.last_signal = "—"
        self.bars_since_signal = 0
        self.warmup_bars = max(max(self.atrLengthInput, self.adaptSmoothInput), 50)

    def next(self):
        idx = len(self.data) - 1

        if idx < self.warmup_bars:
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1] if len(self.data.Volume) > 0 else 0

        atr_val = max(self.atr[-1], high - low) if self.atr[-1] is not None else (high - low)
        atr_sma_val = max(self.atr_sma[-1], atr_val) if self.atr_sma[-1] is not None else atr_val

        vol_ratio = atr_sma_val / atr_val if atr_val > 0 else 1.0
        adaptive_mult = self.baseMultInput * vol_ratio if self.adaptiveInput else self.baseMultInput
        adaptive_mult = max(self.minMultInput, min(self.maxMultInput, adaptive_mult))

        mid_price = (high + low) / 2.0
        upper_band = mid_price + adaptive_mult * atr_val
        lower_band = mid_price - adaptive_mult * atr_val

        prev_band = self.st_band if self.st_band is not None else (lower_band if self.trend_dir == 1 else upper_band)
        flip_cushion = self.cushionInput * atr_val

        cool_down_ok = self.bars_since_flip >= self.cooldownInput

        raw_flip = False

        if self.trend_dir == 1:
            self.st_band = max(lower_band, prev_band)
            if close < (self.st_band - flip_cushion) and cool_down_ok:
                self.trend_dir = -1
                self.st_band = upper_band
                self.bars_since_flip = 0
                raw_flip = True
        else:
            self.st_band = min(upper_band, prev_band)
            if close > (self.st_band + flip_cushion) and cool_down_ok:
                self.trend_dir = 1
                self.st_band = lower_band
                self.bars_since_flip = 0
                raw_flip = True

        self.bars_since_flip += 1

        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50.0
        momentum_ok = not self.useMomentumInput or (
            self.trend_dir == 1 and rsi_val >= self.rsiThreshInput
        ) or (
            self.trend_dir == -1 and rsi_val <= (100.0 - self.rsiThreshInput)
        )

        vol_sma_val = self.vol_sma[-1] if self.vol_sma[-1] is not None else 1.0
        volume_ok = not self.useVolumeInput or volume <= 0 or (volume > vol_sma_val * self.volMultInput)

        filters_ok = momentum_ok and volume_ok

        confirmed_buy = raw_flip and self.trend_dir == 1 and filters_ok
        confirmed_sell = raw_flip and self.trend_dir == -1 and filters_ok

        self.bars_since_signal += 1

        if confirmed_buy:
            if not self.position:
                self.buy()
            self.last_signal = "BUY"
            self.bars_since_signal = 0

        elif confirmed_sell:
            if self.position:
                self.position.close()
            self.last_signal = "SELL"
            self.bars_since_signal = 0