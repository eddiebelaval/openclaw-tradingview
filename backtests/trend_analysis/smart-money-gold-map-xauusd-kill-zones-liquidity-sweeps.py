        # Calculate nearest psychological levels
        nearest_major_above = np.ceil(close / self.major_step) * self.major_step
        nearest_major_below = np.floor(close / self.major_step) * self.major_step
        
        # Calculate position in psychological zone (0-100%)
        if self.major_step > 0:
            zone_pct = (close - nearest_major_below) / self.major_step * 100
