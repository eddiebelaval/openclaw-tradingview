import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Calculation parameters
    support_period = 150
    support_shift = 3
    signal_lookback = 10
    cooldown_bars = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate support lines (150-period high/low shifted by 3 bars)
        def highest_shifted(data, period, shift):
            rolling_max = data.rolling(window=period).max()
            if shift > 0:
                return rolling_max.shift(shift)
            return rolling_max

        def lowest_shifted(data, period, shift):
            rolling_min = data.rolling(window=period).min()
            if shift > 0:
                return rolling_min.shift(shift)
            return rolling_min

        self.high_support = self.I(
            lambda: highest_shifted(high, self.support_period, self.support_shift)
        )
        self.low_support = self.I(
            lambda: lowest_shifted(low, self.support_period, self.support_shift)
        )

        # Calculate moving averages
        self.ma5 = self.I(pta.sma, close, length=5)
        self.ma10 = self.I(pta.sma, close, length=10)
        self.ma30 = self.I(pta.sma, close, length=30)

        # Calculate bias rates (deviation from moving averages)
        self.bias5 = self.I(lambda: (close - self.ma5) / self.ma5 * 100)
        self.bias30 = self.I(lambda: (close - self.ma30) / self.ma30 * 100)

        # Calculate slope angles
        def calc_slope5():
            ma5_series = self.ma5
            if len(ma5_series) < 2:
                return pd.Series([0] * len(close), index=close.index)
            slope = (ma5_series / ma5_series.shift(1) - 1) * 100
            angle = np.arctan(slope) * 180 / np.pi
            return angle.fillna(0)

        def calc_slope30():
            ma30_series = self.ma30
            if len(ma30_series) < 2:
                return pd.Series([0] * len(close), index=close.index)
            slope = (ma30_series / ma30_series.shift(1) - 1) * 100
            angle = np.arctan(slope) * 180 / np.pi
            return angle.fillna(0)

        self.slope5 = self.I(calc_slope5)
        self.slope30 = self.I(calc_slope30)

        # Calculate RSI for additional confirmation
        self.rsi_value = self.I(pta.rsi, close, length=14)

        # Track last buy/sell bars for cooldown
        self.last_buy_bar = -100
        self.last_sell_bar = -100

    def next(self):
        # Check for crossovers
        golden_cross = crossover(self.ma5, self.ma10)
        death_cross = crossover(self.ma10, self.ma5)
        price_above_ma30 = crossover(self.data.Close, self.ma30)
        price_below_ma30 = crossover(self.ma30, self.data.Close)

        # Get current values
        close = self.data.Close[-1]
        ma5 = self.ma5[-1]
        ma10 = self.ma10[-1]
        ma30 = self.ma30[-1]
        bias5 = self.bias5[-1]
        rsi = self.rsi_value[-1] if self.rsi_value[-1] is not None else 50

        # Determine trend direction
        if ma5 > ma10 and ma10 > ma30:
            trend_direction = "BULLISH"
        elif ma5 < ma10 and ma10 < ma30:
            trend_direction = "BEARISH"
        else:
            trend_direction = "NEUTRAL"

        # Strong Buy: Golden Cross + Price above MA30 + Bias5 positive + RSI not overbought
        strong_buy_condition = (
            golden_cross and price_above_ma30 and bias5 > 0 and rsi < 70
        )

        # Medium Buy: Golden Cross + Bias5 increasing
        prev_bias5 = self.bias5[-2] if len(self.bias5) >= 2 else bias5
        medium_buy_condition = golden_cross and bias5 > prev_bias5

        # Strong Sell: Death Cross + Price below MA30 + Bias5 negative + RSI not oversold
        strong_sell_condition = (
            death_cross and price_below_ma30 and bias5 < 0 and rsi > 30
        )

        # Medium Sell: Death Cross + Bias5 decreasing
        medium_sell_condition = death_cross and bias5 < prev_bias5

        # Combine conditions
        buy_condition = strong_buy_condition or medium_buy_condition
        sell_condition = strong_sell_condition or medium_sell_condition

        # Apply cooldown
        current_bar = len(self.data) - 1
        buy_cooldown = current_bar - self.last_buy_bar < self.cooldown_bars
        sell_cooldown = current_bar - self.last_sell_bar < self.cooldown_bars

        # Final signals with cooldown
        buy_signal = buy_condition and not buy_cooldown
        sell_signal = sell_condition and not sell_cooldown

        # Execute trades
        if buy_signal and not self.position:
            self.buy()
            self.last_buy_bar = current_bar
        elif sell_signal and self.position:
            self.position.close()
            self.last_sell_bar = current_bar


