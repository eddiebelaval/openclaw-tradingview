import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 21
    multOuter = 2.0
    multInner = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Baseline: EMA
        self.basis = self.I(pta.ema, close, length=self.length)

        # Volatility measure: ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.length)

        # Four bands around baseline
        self.upperOuter = self.I(lambda: self.basis + self.atr * self.multOuter)
        self.upperInner = self.I(lambda: self.basis + self.atr * self.multInner)
        self.lowerInner = self.I(lambda: self.basis - self.atr * self.multInner)
        self.lowerOuter = self.I(lambda: self.basis - self.atr * self.multOuter)

        # Trend detection
        self.trend = 1

    def next(self):
        # Check if basis is rising or falling
        if len(self.data) < 3:
            return

        basis_now = self.basis[-1]
        basis_prev1 = self.basis[-2]
        basis_prev2 = self.basis[-3]

        rising = basis_now > basis_prev1 > basis_prev2
        falling = basis_now < basis_prev1 < basis_prev2

        if rising:
            self.trend = 1
        elif falling:
            self.trend = -1

        # Trading signals
        close_now = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        basis_prev = self.basis[-2]

        # Buy: price crosses above basis AND trend is bullish
        buy_signal = close_prev <= basis_prev and close_now > basis_now and self.trend == 1

        # Sell: price crosses below basis AND trend is bearish
        sell_signal = close_prev >= basis_prev and close_now < basis_now and self.trend == -1

        if buy_signal:
            self.buy()
        elif sell_signal:
            self.sell()