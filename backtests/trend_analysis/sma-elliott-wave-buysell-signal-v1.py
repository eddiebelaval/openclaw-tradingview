import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    sma_fast_len = 10
    sma_med_len = 20
    sma_slow_len = 50
    adx_len = 14
    adx_threshold = 20
    vol_len = 20
    vol_mult = 1.3
    rsi_len = 14
    macd_fast = 12
    macd_slow = 26
    macd_signal = 9
    ewo_fast = 5
    ewo_slow = 35
    highest_len = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Moving Averages
        self.sma10 = self.I(pta.sma, close, length=self.sma_fast_len)
        self.sma20 = self.I(pta.sma, close, length=self.sma_med_len)
        self.sma50 = self.I(pta.sma, close, length=self.sma_slow_len)

        # ADX for trend strength
        adx_result = self.I(pta.adx, high, low, close, length=self.adx_len)
        self.adx = adx_result

        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)

        # MACD
        macd_result = self.I(pta.macd, close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_signal)
        self.macd_line = macd_result.iloc[:, 0] if macd_result is not None else pd.Series(0, index=close.index)
        self.macd_signal_line = macd_result.iloc[:, 1] if macd_result is not None else pd.Series(0, index=close.index)
        self.macd_hist = macd_result.iloc[:, 2] if macd_result is not None else pd.Series(0, index=close.index)

        # Volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=self.vol_len)

        # EWO (Elliott Wave Oscillator)
        sma5 = self.I(pta.sma, close, length=self.ewo_fast)
        sma35 = self.I(pta.sma, close, length=self.ewo_slow)
        self.ewo = sma5 - sma35

        # Highest high and lowest low
        self.highest_high = self.I(lambda: high.rolling(self.highest_len).max())
        self.lowest_low = self.I(lambda: low.rolling(self.highest_len).min())

    def next(self):
        # Check if we have enough data
        if len(self.data) < max(self.sma_slow_len, self.ewo_slow, self.highest_len):
            return

        # --- Trend Strength Filter (ADX) ---
        is_trending = self.adx[-1] > self.adx_threshold if self.adx[-1] is not None else False

        # --- SMA Stack Conditions ---
        sma_stack_buy = (self.sma10[-1] > self.sma20[-1]) and (self.sma20[-1] > self.sma50[-1])
        sma_stack_sell = (self.sma10[-1] < self.sma20[-1]) and (self.sma20[-1] < self.sma50[-1])

        # --- RSI Conditions ---
        rsi_buy = self.rsi[-1] > 52 if self.rsi[-1] is not None else False
        rsi_sell = self.rsi[-1] < 48 if self.rsi[-1] is not None else False

        # --- MACD Conditions ---
        macd_trend_buy = False
        macd_trend_sell = False
        if len(self.data) > 1:
            macd_trend_buy = (self.macd_line[-1] > self.macd_signal_line[-1]) and (self.macd_hist[-1] > self.macd_hist[-2])
            macd_trend_sell = (self.macd_line[-1] < self.macd_signal_line[-1]) and (self.macd_hist[-1] < self.macd_hist[-2])

        # --- Volume Condition ---
        high_vol = self.data.Volume[-1] > (self.vol_sma[-1] * self.vol_mult) if self.vol_sma[-1] is not None else False

        # --- Elliott Wave Impulse Filter ---
        is_impulse_buy = False
        is_impulse_sell = False
        if len(self.data) > 1 and self.highest_high[-1] is not None and self.lowest_low[-1] is not None:
            is_impulse_buy = (self.ewo[-1] > 0) and (self.ewo[-1] > self.ewo[-2]) and (self.data.High[-1] > self.highest_high[-2])
            is_impulse_sell = (self.ewo[-1] < 0) and (self.ewo[-1] < self.ewo[-2]) and (self.data.Low[-1] < self.lowest_low[-2])

        # --- Strong Buy/Sell Signals ---
        strong_buy = is_trending and sma_stack_buy and macd_trend_buy and rsi_buy and high_vol and is_impulse_buy
        strong_sell = is_trending and sma_stack_sell and macd_trend_sell and rsi_sell and high_vol and is_impulse_sell

        # Track previous signal state to avoid multiple entries
        if not hasattr(self, 'prev_buy_signal'):
            self.prev_buy_signal = False
        if not hasattr(self, 'prev_sell_signal'):
            self.prev_sell_signal = False

        # Entry/Exit Logic
        if strong_buy and not self.prev_buy_signal:
            if self.position:
                self.position.close()
            self.buy()
            self.prev_buy_signal = True
            self.prev_sell_signal = False
        elif strong_sell and not self.prev_sell_signal:
            if self.position:
                self.position.close()
            self.prev_sell_signal = True
            self.prev_buy_signal = False
        else:
            self.prev_buy_signal = strong_buy
            self.prev_sell_signal = strong_sell


