import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # ZCT Levels inputs
    showPD = True
    show4H = True
    show1H = True
    show15m = True
    
    # SMMA inputs
    useSMMA = True
    smmaLen = 30
    
    # Rule Engine inputs
    lookbackHours = 8
    recycledTouches = 2
    touchTolATR = 0.15
    grindBars = 8
    bodyMaxATR = 0.9
    volLen = 20
    volSlopeBars = 8
    maxSMMAcrosses = 2
    crossLookback = 30
    retestWindowBars = 50
    atrLen = 14
    
    # Signal inputs
    onlyAgrade = True
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Calculate tolerance
        self.tol = self.atr * self.touchTolATR
        
        # Calculate SMMA (RMA)
        self.smma = self.I(pta.rma, close, length=self.smmaLen)
        
        # Calculate average body size
        abs_body = pd.Series(np.abs(self.data.Close - self.data.Open))
        self.avgBody = self.I(pta.sma, abs_body, length=self.grindBars)
        
        # Slow grind conditions
        self.slowGrindRes = self.I(self._slow_grind_res, low)
        self.slowGrindSup = self.I(self._slow_grind_sup, high)
        
        # Volume conditions
        self.vma = self.I(pta.sma, volume, length=self.volLen)
        self.volOk = self.I(self._vol_ok, volume)
        
        # SMMA crossover count
        self.crossCount = self.I(self._cross_count, close)
        
        # Trend conditions
        self.trendLongOk = self.I(self._trend_long_ok, close)
        self.trendShortOk = self.I(self._trend_short_ok, close)
        
        # Grade filters
        self.AgradeLongOk = self.I(self._agrade_long, close)
        self.AgradeShortOk = self.I(self._agrade_short, close)
        self.BgradeLongOk = self.I(self._bgrade_long, close)
        self.BgradeShortOk = self.I(self._bgrade_short, close)
        
        # Track break confirmations
        self.breakResIdx = {}  # level -> bar_index
        self.breakSupIdx = {}  # level -> bar_index
        
        # Previous highs/lows from higher timeframes (simplified for backtest)
        self.prevDayHigh = self.I(self._prev_day_high)
        self.prevDayLow = self.I(self._prev_day_low)
        self.prev4HHigh = self.I(self._prev_4h_high)
        self.prev4HLow = self.I(self._prev_4h_low)
        self.prev1HHigh = self.I(self._prev_1h_high)
        self.prev1HLow = self.I(self._prev_1h_low)
        self.prev15mHigh = self.I(self._prev_15m_high)
        self.prev15mLow = self.I(self._prev_15m_low)
    
    def _slow_grind_res(self, low):
        # Rising lows with small bodies
        if len(low) < self.grindBars:
            return pd.Series(False, index=low.index)
        rising_low = low.diff().rolling(self.grindBars).apply(lambda x: (x > 0).sum() == self.grindBars)
        return rising_low & (self.avgBody[-1] <= self.atr[-1] * self.bodyMaxATR) if self.avgBody[-1] else False
    
    def _slow_grind_sup(self, high):
        # Falling highs with small bodies
        if len(high) < self.grindBars:
            return pd.Series(False, index=high.index)
        falling_high = high.diff().rolling(self.grindBars).apply(lambda x: (x < 0).sum() == self.grindBars)
        return falling_high & (self.avgBody[-1] <= self.atr[-1] * self.bodyMaxATR) if self.avgBody[-1] else False
    
    def _vol_ok(self, volume):
        if self.vma[-1] is None or self.vma[-1] == 0:
            return False
        vol_rising = self.vma[-1] > self.vma[-self.volSlopeBars] if len(self.vma) > self.volSlopeBars else False
        vol_above = volume[-1] >= self.vma[-1]
        return vol_rising and vol_above
    
    def _cross_count(self, close):
        if len(close) < self.crossLookback:
            return 0
        cross_array = ((close[-self.crossLookback:] > self.smma[-self.crossLookback:]) & 
                       (close[-self.crossLookback-1:-1] <= self.smma[-self.crossLookback-1:-1])).astype(int)
        return cross_array.sum() + ((close[-self.crossLookback:-1] < self.smma[-self.crossLookback:-1]) & 
                                     (close[-self.crossLookback-1:-1] >= self.smma[-self.crossLookback-1:-1])).astype(int).sum()
    
    def _trend_long_ok(self, close):
        if not self.useSMMA:
            return True
        return close[-1] > self.smma[-1]
    
    def _trend_short_ok(self, close):
        if not self.useSMMA:
            return True
        return close[-1] < self.smma[-1]
    
    def _agrade_long(self, close):
        return (self.slowGrindRes[-1] if self.slowGrindRes[-1] is not None else False and 
                self.volOk[-1] and 
                self.crossCount[-1] <= self.maxSMMAcrosses and 
                self.trendLongOk[-1])
    
    def _agrade_short(self, close):
        return (self.slowGrindSup[-1] if self.slowGrindSup[-1] is not None else False and 
                self.volOk[-1] and 
                self.crossCount[-1] <= self.maxSMMAcrosses and 
                self.trendShortOk[-1])
    
    def _bgrade_long(self, close):
        return (self.slowGrindRes[-1] if self.slowGrindRes[-1] is not None else False and 
                self.trendLongOk[-1])
    
    def _bgrade_short(self, close):
        return (self.slowGrindSup[-1] if self.slowGrindSup[-1] is not None else False and 
                self.trendShortOk[-1])
    
    def _prev_day_high(self):
        return pd.Series(self.data.High).rolling(20).max()
    
    def _prev_day_low(self):
        return pd.Series(self.data.Low).rolling(20).min()
    
    def _prev_4h_high(self):
        return pd.Series(self.data.High).rolling(16).max()
    
    def _prev_4h_low(self):
        return pd.Series(self.data.Low).rolling(16).min()
    
    def _prev_1h_high(self):
        return pd.Series(self.data.High).rolling(4).max()
    
    def _prev_1h_low(self):
        return pd.Series(self.data.Low).rolling(4).min()
    
    def _prev_15m_high(self):
        return pd.Series(self.data.High).rolling(1).max()
    
    def _prev_15m_low(self):
        return pd.Series(self.data.Low).rolling(1).min()
    
    def _touches(self, level):
        if pd.isna(level) or level is None:
            return 0
        cnt = 0
        lookback = min(int(self.lookbackHours * 60 / 15), len(self.data))
        for i in range(lookback):
            if (self.data.High[-(i+1)] >= (level - self.tol[-1]) and 
                self.data.Low[-(i+1)] <= (level + self.tol[-1])):
                cnt += 1
        return cnt
    
    def _is_fresh(self, level):
        return self._touches(level) < self.recycledTouches
    
    def _break_confirmed_up(self, level):
        if pd.isna(level) or level is None:
            return False
        return self.data.Close[-1] > level and self.data.Close[-2] > level
    
    def _break_just_confirmed_up(self, level):
        if pd.isna(level) or level is None:
            return False
        return (self.data.Close[-1] > level and 
                self.data.Close[-2] > level and 
                self.data.Close[-3] <= level)
    
    def _retest_long(self, level):
        if pd.isna(level) or level is None:
            return False
        return (self.data.Low[-1] <= (level + self.tol[-1]) and 
                self.data.Close[-1] > level)
    
    def _break_confirmed_dn(self, level):
        if pd.isna(level) or level is None:
            return False
        return self.data.Close[-1] < level and self.data.Close[-2] < level
    
    def _break_just_confirmed_dn(self, level):
        if pd.isna(level) or level is None:
            return False
        return (self.data.Close[-1] < level and 
                self.data.Close[-2] < level and 
                self.data.Close[-3] >= level)
    
    def _retest_short(self, level):
        if pd.isna(level) or level is None:
            return False
        return (self.data.High[-1] >= (level - self.tol[-1]) and 
                self.data.Close[-1] < level)
    
    def next(self):
        if len(self) < max(self.grindBars, self.volLen, self.crossLookback) + 10:
            return
        
        filters_long_ok = self.AgradeLongOk[-1] if self.onlyAgrade else self.BgradeLongOk[-1]
        filters_short_ok = self.AgradeShortOk[-1] if self.onlyAgrade else self.BgradeShortOk[-1]
        
        # Check all levels
        levels_res = [self.prevDayHigh[-1], self.prev4HHigh[-1], self.prev1HHigh[-1], self.prev15mHigh[-1]]
        levels_sup = [self.prevDayLow[-1], self.prev4HLow[-1], self.prev1HLow[-1], self.prev15mLow[-1]]
        
        entry_long = False
        entry_short = False
        
        # LONG signals
        for lvl in levels_res:
            if pd.isna(lvl) or lvl is None:
                continue
            if self._is_fresh(lvl) and filters_long_ok and self._break_just_confirmed_up(lvl):
                self.breakResIdx[lvl] = len(self)
            
            if lvl in self.breakResIdx:
                bars_since = len(self) - self.breakResIdx[lvl]
                if bars_since <= self.retestWindowBars and self._retest_long(lvl):
                    entry_long = True
                    break
        
        # SHORT signals
        for lvl in levels_sup:
            if pd.isna(lvl) or lvl is None:
                continue
            if self._is_fresh(lvl) and filters_short_ok and self._break_just_confirmed_dn(lvl):
                self.breakSupIdx[lvl] = len(self)
            
            if lvl in self.breakSupIdx:
                bars_since = len(self) - self.breakSupIdx[lvl]
                if bars_since <= self.retestWindowBars and self._retest_short(lvl):
                    entry_short = True
                    break
        
        if entry_long and not self.position:
            self.buy()
        elif entry_short and not self.position:
            self.sell()
        elif entry_long and self.position.is_short:
            self.position.close()
            self.buy()
        elif entry_short and self.position.is_long:
            self.position.close()
            self.sell()


