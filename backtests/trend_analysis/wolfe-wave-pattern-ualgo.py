import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Parameters
        self.len_left = 5
        self.len_right = 5
        
        # Store pivot points
        self.pivots = []
        
        # Track if we have a valid wolfe wave
        self.bullish_wave = False
        self.bearish_wave = False
        self.wave_entry_bar = -1
        
    def get_pivot_high(self, idx, left, right):
        """Find pivot high at idx if it exists"""
        if idx < left or idx >= len(self.data) - right:
            return None
        
        highs = self.data.High
        current_high = highs[idx]
        
        # Check if highest within left bars before and right bars after
        is_pivot = True
        for i in range(max(0, idx - left), idx):
            if highs[i] >= current_high:
                is_pivot = False
                break
        for i in range(idx + 1, min(len(self.data), idx + right + 1)):
            if highs[i] >= current_high:
                is_pivot = False
                break
        
        return current_high if is_pivot else None
    
    def get_pivot_low(self, idx, left, right):
        """Find pivot low at idx if it exists"""
        if idx < left or idx >= len(self.data) - right:
            return None
        
        lows = self.data.Low
        current_low = lows[idx]
        
        # Check if lowest within left bars before and right bars after
        is_pivot = True
        for i in range(max(0, idx - left), idx):
            if lows[i] <= current_low:
                is_pivot = False
                break
        for i in range(idx + 1, min(len(self.data), idx + right + 1)):
            if lows[i] <= current_low:
                is_pivot = False
                break
        
        return current_low if is_pivot else None
    
    def get_slope(self, p_a_idx, p_a_price, p_b_idx, p_b_price):
        """Calculate slope between two pivots"""
        if p_b_idx == p_a_idx:
            return 0
        return (p_b_price - p_a_price) / (p_b_idx - p_a_idx)
    
    def get_projected_price(self, p_a_idx, p_a_price, p_b_idx, p_b_price, target_idx):
        """Get projected price at target index based on two pivot points"""
        slope = (p_b_price - p_a_price) / (p_b_idx - p_a_idx) if p_b_idx != p_a_idx else 0
        return p_a_price + slope * (target_idx - p_a_idx)
    
    def next(self):
        current_idx = len(self.data) - 1
        
        # Check for pivot high at current - len_right position
        check_idx = current_idx - self.len_right
        if check_idx >= 0:
            ph = self.get_pivot_high(check_idx, self.len_left, self.len_right)
            if ph is not None:
                self.pivots.append((check_idx, ph, True))  # True = High
            
            pl = self.get_pivot_low(check_idx, self.len_left, self.len_right)
            if pl is not None:
                self.pivots.append((check_idx, pl, False))  # False = Low
        
        # Pattern recognition - need at least 5 pivots
        if len(self.pivots) >= 5:
            p1_idx, p1_price, p1_is_high = self.pivots[-5]
            p2_idx, p2_price, p2_is_high = self.pivots[-4]
            p3_idx, p3_price, p3_is_high = self.pivots[-3]
            p4_idx, p4_price, p4_is_high = self.pivots[-2]
            p5_idx, p5_price, p5_is_high = self.pivots[-1]
            
            # Check alternation
            alternating = (p1_is_high != p2_is_high and 
                          p2_is_high != p3_is_high and 
                          p3_is_high != p4_is_high and 
                          p4_is_high != p5_is_high)
            
            if alternating:
                # BULLISH WOLFE WAVE: L, H, L, H, L
                if (not p1_is_high and p2_is_high and not p3_is_high and 
                    p4_is_high and not p5_is_high):
                    
                    if p3_price < p1_price and p4_price < p2_price:
                        m13 = self.get_slope(p1_idx, p1_price, p3_idx, p3_price)
                        m24 = self.get_slope(p2_idx, p2_price, p4_idx, p4_price)
                        
                        proj13_at_5 = self.get_projected_price(p1_idx, p1_price, p3_idx, p3_price, p5_idx)
                        
                        if p5_price < proj13_at_5 and m24 < m13:
                            self.bullish_wave = True
                            self.bearish_wave = False
                            self.wave_entry_bar = current_idx
                
                # BEARISH WOLFE WAVE: H, L, H, L, H
                elif (p1_is_high and not p2_is_high and p3_is_high and 
                      not p4_is_high and p5_is_high):
                    
                    if p3_price > p1_price and p4_price > p2_price:
                        m13 = self.get_slope(p1_idx, p1_price, p3_idx, p3_price)
                        m24 = self.get_slope(p2_idx, p2_price, p4_idx, p4_price)
                        
                        proj13_at_5 = self.get_projected_price(p1_idx, p1_price, p3_idx, p3_price, p5_idx)
                        
                        if p5_price > proj13_at_5 and m24 > m13:
                            self.bullish_wave = False
                            self.bearish_wave = True
                            self.wave_entry_bar = current_idx
        
        # Trading logic based on detected patterns
        # Bullish Wolfe Wave: buy on break above P5 high or at P5 low
        if self.bullish_wave and not self.position:
            if self.data.Close[-1] > self.pivots[-1][1]:
                self.buy()
                self.bullish_wave = False
        
        # Bearish Wolfe Wave: sell on break below P5 low or at P5 high
        if self.bearish_wave and not self.position:
            if self.data.Close[-1] < self.pivots[-1][1]:
                self.sell()
                self.bearish_wave = False
        
        # Exit logic
        if self.position:
            # Simple exit: stop loss and profit target based on pattern
            if len(self.pivots) >= 5:
                p1_price = self.pivots[-5][1]
                p3_price = self.pivots[-3][1]
                p5_price = self.pivots[-1][1]
                
                if self.position.is_long:
                    # Stop loss at pivot low
                    if self.data.Close[-1] < p5_price:
                        self.position.close()
                    # Take profit at previous high
                    elif self.data.Close[-1] > p1_price * 1.02:
                        self.position.close()
                else:
                    # Stop loss at pivot high
                    if self.data.Close[-1] > p5_price:
                        self.position.close()
                    # Take profit at previous low
                    elif self.data.Close[-1] < p1_price * 0.98:
                        self.position.close()


