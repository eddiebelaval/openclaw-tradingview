        # Buy when cumulative delta is strongly positive and normalized delta is positive
        # Sell when cumulative delta is strongly negative or normalized delta is negative
        
        if len(self.data) < 2:
            return
        
        current_norm_delta = self.norm_delta[-1]
        prev_norm_delta = self.norm_delta[-2]
        
        if np.isnan(current_norm_delta) or np.isnan(prev_norm_delta):
            return
        
        # Buy signal: normalized delta crosses above 0
