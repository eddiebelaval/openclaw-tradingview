import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    norm_len = 200
    use_z_score = False

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate volume-based delta
        # Buy volume: when close > open
        buy_vol = volume.where(close > open_, 0.0)
        # Sell volume: when close < open
        sell_vol = volume.where(close < open_, 0.0)
        
        self.buy_vol = self.I(lambda: buy_vol)
        self.sell_vol = self.I(lambda: sell_vol)
        
        # Delta calculation
        delta = buy_vol - sell_vol
        self.delta = self.I(lambda: delta)
        
        # Normalization
        delta_mean = self.I(pta.sma, close=delta, length=self.norm_len)
        delta_std = self.I(lambda: delta.rolling(window=self.norm_len).std())
        
        # Normalized delta (with Z-score if enabled)
        if self.use_z_score:
            self.norm_delta = self.I(lambda: (delta - delta_mean) / (delta_std + 1e-10))
        else:
            self.norm_delta = self.I(lambda: delta)
        
        # Cumulative delta
        self.cum_delta_value = 0.0

    def next(self):
        # Update cumulative delta
        if len(self.data) > 0:
            current_delta = self.delta[-1]
            if not np.isnan(current_delta):
                self.cum_delta_value += current_delta
        
