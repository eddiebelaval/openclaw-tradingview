import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate True Range
        tr = self.I(lambda: pta.atr(high, low, close, length=1)['ATRr_1'] if pta.atr(high, low, close, length=1) is not None else pd.Series(0, index=close.index))
        
        # Volume metrics
        vol_mean = self.I(pta.sma, volume, length=self.length)
        vol_std = self.I(lambda: pd.Series(volume).rolling(window=self.length).std() or pd.Series(0, index=volume.index))
        
        # Effort Z-score (volume)
        self.effort_z = self.I(lambda: ((volume - vol_mean) / vol_std.replace(0, np.nan)).fillna(0) if vol_std.max() > 0 else pd.Series(0, index=volume.index))
        
        # Safe spread calculation (True Range)
        safe_spread = self.I(lambda: tr.replace(0, 0.0001))
        
        # Result Z-score (spread/TR)
        spread_mean = self.I(pta.sma, safe_spread, length=self.length)
        spread_std = self.I(lambda: pd.Series(safe_spread).rolling(window=self.length).std() or pd.Series(0, index=safe_spread.index))
        
        self.result_z = self.I(lambda: ((safe_spread - spread_mean) / spread_std.replace(0, np.nan)).fillna(0) if spread_std.max() > 0 else pd.Series(0, index=safe_spread.index))
        
        # Delta Z
        self.delta_z = self.I(lambda: self.effort_z - self.result_z)
        
        # Absorption signal: high effort, low result
        self.is_absorption = self.I(lambda: (self.effort_z > 1.5) & (self.result_z < 0.0))
        
        # Vacuum signal: high result, low effort
        self.is_vacuum = self.I(lambda: (self.result_z > 1.5) & (self.effort_z < 0.0))

    def next(self):
        # Buy on vacuum (price expansion with low effort)
        if self.is_vacuum[-1] and not self.position:
            self.buy()
        
        # Sell on absorption (price compression with high effort)
        elif self.is_absorption[-1] and self.position:
            self.position.close()
        
        # Exit long if delta_z crosses below 0 after being positive
        elif self.position and self.delta_z[-1] < 0 and self.delta_z[-2] >= 0:
            self.position.close()