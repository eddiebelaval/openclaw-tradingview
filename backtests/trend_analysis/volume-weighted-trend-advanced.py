import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters
    vwma_len = 34
    vwma_fast_len = 21
    atr_mult_inp = 1.5
    
    # Adaptive engine
    use_adaptive = True
    adapt_lookback = 100
    adapt_min = 0.5
    adapt_max = 3.5
    use_blend = False
    chop_len = 14
    
    # Filters
    use_chop = True
    chop_thresh = 61.8
    use_adx = False
    adx_len = 14
    adx_thresh = 20
    use_vol = True
    vol_ma_len = 20
    vol_mult = 1.0
    
    # Risk management
    use_sl = True
    use_tp = True
    sl_mult = 1.5
    tp_mult = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # VWMA calculations
        self.vwma_slow = self.I(pta.vwma, close, volume, length=self.vwma_len)
        self.vwma_fast = self.I(pta.vwma, close, volume, length=self.vwma_fast_len)
        
        # ATR
        self.raw_atr = self.I(pta.atr, high, low, close, length=self.vwma_len)
        
        # Choppiness Index
        def chop_index(close_series, high_series, low_series, length):
            atr1 = pta.atr(high_series, low_series, close_series, length=1)
            if atr1 is None:
                return pd.Series(50.0, index=close_series.index)
            chop_sum = atr1.rolling(window=length).sum()
            chop_hi = high_series.rolling(window=length).max()
            chop_lo = low_series.rolling(window=length).min()
            chop_range = chop_hi - chop_lo
            with np.errstate(divide='ignore', invalid='ignore'):
                chop_val = np.where(
                    chop_range > 0,
                    100.0 * np.log10(chop_sum / chop_range) / np.log10(length),
                    50.0
                )
            return pd.Series(chop_val, index=close_series.index)
        
        self.chop_val = self.I(chop_index, close, high, low, self.chop_len)
        
        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=self.adx_len)
        self.adx_val = adx_result
        
        # Volume MA
        self.vol_ma = self.I(pta.sma, volume, length=self.vol_ma_len)
        
        # ATR adaptive multiplier
        def calc_adaptive_mult(atr_series, lookback, min_mult, max_mult, use_adapt, fixed_mult):
            atr_hi = atr_series.rolling(window=lookback).max()
            atr_lo = atr_series.rolling(window=lookback).min()
            atr_rng = atr_hi - atr_lo
            with np.errstate(divide='ignore', invalid='ignore'):
                vol_pct = np.where(atr_rng > 0, (atr_series - atr_lo) / atr_rng, 0.5)
            eff_mult = np.where(
                use_adapt,
                min_mult + vol_pct * (max_mult - min_mult),
                fixed_mult
            )
            return pd.Series(eff_mult, index=atr_series.index)
        
        self.eff_mult = self.I(calc_adaptive_mult, self.raw_atr, self.adapt_lookback,
                               self.adapt_min, self.adapt_max, self.use_adaptive, self.atr_mult_inp)
        
        # Choppiness normalization for blending
        def calc_blend(chop_series, use_blend_flag):
            chop_norm = np.clip((chop_series - 30.0) / 60.0, 0, 1)
            blend_w = np.where(use_blend_flag, chop_norm, 1.0)
            return pd.Series(blend_w, index=chop_series.index)
        
        self.blend_w = self.I(calc_blend, self.chop_val, self.use_blend)
        
        # Basis (blended VWMA)
        def calc_basis(vwma_slow, vwma_fast, blend_w):
            basis = blend_w * vwma_slow + (1.0 - blend_w) * vwma_fast
            return pd.Series(basis, index=vwma_slow.index)
        
        self.basis = self.I(calc_basis, self.vwma_slow, self.vwma_fast, self.blend_w)
        
        # Bands
        def calc_upper(basis, atr, eff_mult):
            return basis + atr * eff_mult
        
        def calc_lower(basis, atr, eff_mult):
            return basis - atr * eff_mult
        
        self.upper = self.I(calc_upper, self.basis, self.raw_atr, self.eff_mult)
        self.lower = self.I(calc_lower, self.basis, self.raw_atr, self.eff_mult)
        
        # Trend tracking
        self.trend = 0
        self.prev_trend = 0

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        basis_val = self.basis[-1]
        upper_val = self.upper[-1]
        lower_val = self.lower[-1]
        atr_val = self.raw_atr[-1]
        chop_val = self.chop_val[-1]
        adx_val = self.adx_val[-1]
        vol_ma_val = self.vol_ma[-1]
        
        # Update trend
        self.prev_trend = self.trend
        if close > upper_val:
            self.trend = 1
        elif close < lower_val:
            self.trend = -1
        
        to_bull = self.trend == 1 and self.prev_trend != 1
        to_bear = self.trend == -1 and self.prev_trend != -1
        
        # Filters
        f_chop = not self.use_chop or chop_val < self.chop_thresh
        f_adx = not self.use_adx or adx_val >= self.adx_thresh
        f_vol = not self.use_vol or volume >= vol_ma_val * self.vol_mult
        
        gate_bull = f_chop and f_adx and f_vol
        gate_bear = f_chop and f_adx and f_vol
        
        sig_bull = to_bull and gate_bull
        sig_bear = to_bear and gate_bear
        
        # SL/TP distances
        sl_dist = atr_val * self.sl_mult
        tp_dist = atr_val * self.tp_mult
        
        long_sl = close - sl_dist
        long_tp = close + tp_dist
        short_sl = close + sl_dist
        short_tp = close - tp_dist
        
        # Entry and exit logic
        if sig_bull:
            if self.position.is_short:
                self.position.close()
            self.buy()
            
        if sig_bear:
            if self.position.is_long:
                self.position.close()
            self.sell()
        
        # Exit logic
        if self.position.is_long:
            if self.use_sl and close <= long_sl:
                self.position.close()
            elif self.use_tp and close >= long_tp:
                self.position.close()
        
        if self.position.is_short:
            if self.use_sl and close >= short_sl:
                self.position.close()
            elif self.use_tp and close <= short_tp:
                self.position.close()