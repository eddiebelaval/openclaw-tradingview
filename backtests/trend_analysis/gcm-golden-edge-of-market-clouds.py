import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trading Mode Parameters
    trading_mode = "Classic Swing"  # "Classic Swing" or "Fast Scalping"
    
    # Dynamic settings based on mode
    lookback = 2 if trading_mode == "Fast Scalping" else 10
    conv_len = 6 if trading_mode == "Fast Scalping" else 9
    base_len = 13 if trading_mode == "Fast Scalping" else 26
    lead_span_b = 26 if trading_mode == "Fast Scalping" else 52
    ichi_offset = 5 if trading_mode == "Fast Scalping" else 26
    actual_prd = 2 if trading_mode == "Fast Scalping" else 10
    
    # Market Structure Parameters
    displacement = 1.2
    fvg_min_size = 0.2
    
    # Bollinger Bands Parameters
    bb_len = 20
    bb_mult = 2.0
    
    # Scalper Parameters
    len_scalp = 7
    
    # Pivot S/R Parameters
    sr_prd = 10
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Ichimoku Cloud - Donchian calculations
        def donchian_high(series, length):
            return series.rolling(window=length).max()
        
        def donchian_low(series, length):
            return series.rolling(window=length).min()
        
        # Conversion Line (9-period Donchian)
        conv_high = self.I(lambda: donchian_high(high, self.conv_len))
        conv_low = self.I(lambda: donchian_low(low, self.conv_len))
        self.conversion_line = self.I(lambda: (conv_high + conv_low) / 2)
        
        # Base Line (26-period Donchian)
        base_high = self.I(lambda: donchian_high(high, self.base_len))
        base_low = self.I(lambda: donchian_low(low, self.base_len))
        self.base_line = self.I(lambda: (base_high + base_low) / 2)
        
        # Lead Span A (average of conversion and base, offset forward)
        self.lead_span_a = self.I(lambda: (conv_high + base_high) / 2)
        
        # Lead Span B (52-period Donchian, offset forward)
        lead2_high = self.I(lambda: donchian_high(high, self.lead_span_b))
        lead2_low = self.I(lambda: donchian_low(low, self.lead_span_b))
        self.lead_span_b = self.I(lambda: (lead2_high + lead2_low) / 2)
        
        # Bollinger Bands
        self.bb_basis = self.I(pta.sma, close, length=self.bb_len)
        self.bb_dev = self.I(lambda: self.bb_mult * close.rolling(window=self.bb_len).std())
        self.bb_upper = self.I(lambda: self.bb_basis + self.bb_dev)
        self.bb_lower = self.I(lambda: self.bb_basis - self.bb_dev)
        
        # ATR for volatility
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # RSI for momentum
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # HMA for scalper trend
        self.scalp_val = self.I(pta.hma, close, length=self.len_scalp)
        
        # Volume average
        self.vol_avg = self.I(pta.sma, volume, length=20)
        
        # Pivot High/Low for market structure
        def pivot_high(h, l, period):
            return h.rolling(window=period*2+1, center=True).apply(
                lambda x: x[period] if all(x[period] >= x[i] for i in range(len(x)) if i != period) else np.nan,
                raw=False
            )
        
        def pivot_low(h, l, period):
            return l.rolling(window=period*2+1, center=True).apply(
                lambda x: x[period] if all(x[period] <= x[i] for i in range(len(x)) if i != period) else np.nan,
                raw=False
            )
        
        self.ph = self.I(lambda: pivot_high(high, low, self.lookback))
        self.pl = self.I(lambda: pivot_low(high, low, self.lookback))
        
        # Track structure state
        self.is_bull_struct = True
        self.v_high = np.nan
        self.v_low = np.nan
        self.last_buy_price = np.nan
        self.last_sell_price = np.nan
        
    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_ = self.data.Open[-1]
        volume = self.data.Volume[-1]
        
        # Get current indicator values
        bb_upper = self.bb_upper[-1]
        bb_lower = self.bb_lower[-1]
        atr_val = self.atr[-1]
        rsi_val = self.rsi[-1]
        scalp_val = self.scalp_val[-1]
        vol_avg = self.vol_avg[-1]
        
        body_size = abs(close - open_)
        avg_body = pd.Series(self.data.Close[-20:]).rolling(window=20).mean().iloc[-1] if len(self.data.Close) >= 20 else body_size
        
        # Check for Bollinger Band extremes
        is_bb_extreme = high >= bb_upper or low <= bb_lower
        is_bull_candle = close > open_
        is_bear_candle = close < open_
        
        # Volume condition
        vol_cond = "Surging" if volume > vol_avg * 1.5 else "Steady" if volume > vol_avg else "Thin"
        
        # Check for scalper trend changes
        scalp_turn_up = crossover(self.scalp_val, np.full_like(self.scalp_val, self.scalp_val[-2]))
        scalp_turn_dn = crossover(np.full_like(self.scalp_val, self.scalp_val[-2]), self.scalp_val)
        
        # Market structure - simplified version
        if not np.isnan(self.ph[-1]):
            self.v_high = self.ph[-1]
        if not np.isnan(self.pl[-1]):
            self.v_low = self.pl[-1]
        
        is_disp = body_size > (avg_body * self.displacement) if not np.isnan(avg_body) else False
        
        # BOS/CHOCH conditions
        bos_bull = close > self.v_high and self.is_bull_struct and is_disp if not np.isnan(self.v_high) else False
        bos_bear = close < self.v_low and not self.is_bull_struct and is_disp if not np.isnan(self.v_low) else False
        
        if bos_bull:
            self.is_bull_struct = True
            self.v_high = np.nan
        
        if bos_bear:
            self.is_bull_struct = False
            self.v_low = np.nan
        
        # Trading Logic
        # Primary entry: BB extreme + structure alignment + RSI confirmation
        
        # Bullish entry: Price at lower BB, RSI oversold, bullish structure
        if (low <= bb_lower and is_bull_candle and rsi_val < 40 and 
            self.is_bull_struct and vol_cond in ["Surging", "Steady"]):
            if self.position.size == 0:
                self.buy()
        
        # Bearish entry: Price at upper BB, RSI overbought, bearish structure
        elif (high >= bb_upper and is_bear_candle and rsi_val > 60 and 
              not self.is_bull_struct and vol_cond in ["Surging", "Steady"]):
            if self.position.size > 0:
                self.position.close()
        
        # Exit conditions
        # Exit long on reversal signal or RSI overbought
        if self.position.size > 0:
            if scalp_turn_dn or rsi_val > 70 or high >= bb_upper:
                self.position.close()
        
        # Exit short on reversal signal or RSI oversold
        elif self.position.size < 0:
            if scalp_turn_up or rsi_val < 30 or low <= bb_lower:
                self.position.close()


