import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_len = 5
    disp_multiplier = 2.0
    disp_atr_len = 14
    str_atr_len = 14
    liq_lookback = 20
    pd_lookback = 50
    eq_tolerance = 0.02

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Core indicators
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        self.rsi = self.I(pta.rsi, close, length=14)
        self.atr = self.I(pta.atr, high, low, close, length=14)

        # Displacement detection
        self.disp_atr = self.I(pta.atr, high, low, close, length=self.disp_atr_len)

        # Swing detection using rolling max/min
        self.pivot_high = self.I(lambda: high.rolling(window=2*self.swing_len+1, center=True).max())
        self.pivot_low = self.I(lambda: low.rolling(window=2*self.swing_len+1, center=True).min())

        # Premium/Discount zones
        self.range_high = self.I(lambda: high.rolling(window=self.pd_lookback).max())
        self.range_low = self.I(lambda: low.rolling(window=self.pd_lookback).min())

        # Liquidity reference
        self.prev_recent_high = self.I(lambda: high.shift(1).rolling(window=self.liq_lookback).max())
        self.prev_recent_low = self.I(lambda: low.shift(1).rolling(window=self.liq_lookback).min())

        # Tracking variables
        self.last_swing_high = None
        self.last_swing_low = None
        self.prior_swing_high = None
        self.prior_swing_low = None
        self.market_trend = 0
        self.in_position = False

    def next(self):
        if len(self.data) < max(self.swing_len * 2 + 1, self.pd_lookback, self.liq_lookback):
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_price = self.data.Open[-1]

        # Update swing points
        if len(self.data) > self.swing_len * 2 and not np.isnan(self.pivot_high[-1]):
            if self.data.High[-self.swing_len-1] == self.pivot_high[-self.swing_len-1]:
                self.prior_swing_high = self.last_swing_high
                self.last_swing_high = self.pivot_high[-self.swing_len-1]

        if len(self.data) > self.swing_len * 2 and not np.isnan(self.pivot_low[-1]):
            if self.data.Low[-self.swing_len-1] == self.pivot_low[-self.swing_len-1]:
                self.prior_swing_low = self.last_swing_low
                self.last_swing_low = self.pivot_low[-self.swing_len-1]

        # Structure detection
        bull_bos = False
        bear_bos = False
        bull_choch = False
        bear_choch = False

        if self.last_swing_high is not None:
            if close > self.last_swing_high and self.data.Close[-2] <= self.last_swing_high:
                if self.market_trend == 1:
                    bull_bos = True
                else:
                    bull_choch = True
                    self.market_trend = 1

        if self.last_swing_low is not None:
            if close < self.last_swing_low and self.data.Close[-2] >= self.last_swing_low:
                if self.market_trend == -1:
                    bear_bos = True
                else:
                    bear_choch = True
                    self.market_trend = -1

        # Displacement detection
        candle_body = abs(close - open_price)
        candle_range = high - low
        body_ratio = candle_body / candle_range if candle_range > 0 else 0

        is_bull_disp = (close > open_price and 
                       candle_body > self.disp_atr[-1] * self.disp_multiplier and 
                       body_ratio > 0.6)
        is_bear_disp = (close < open_price and 
                       candle_body > self.disp_atr[-1] * self.disp_multiplier and 
                       body_ratio > 0.6)

        # Liquidity sweeps
        if not np.isnan(self.prev_recent_high[-1]):
            buy_side_sweep = (high > self.prev_recent_high[-1] and 
                            close < self.prev_recent_high[-1] and 
                            close < open_price)
        else:
            buy_side_sweep = False

        if not np.isnan(self.prev_recent_low[-1]):
            sell_side_sweep = (low < self.prev_recent_low[-1] and 
                             close > self.prev_recent_low[-1] and 
                             close > open_price)
        else:
            sell_side_sweep = False

        # Fair Value Gap detection
        bull_fvg = (low > self.data.High[-3] and 
                   self.data.Close[-2] > self.data.Open[-2])
        bear_fvg = (high < self.data.Low[-3] and 
                   self.data.Close[-2] < self.data.Open[-2])

        # Order Block detection
        bearish_engulf = (close < open_price and 
                         self.data.Close[-2] > self.data.Open[-2] and
                         close < self.data.Open[-2] and 
                         open_price > self.data.Close[-2])
        bullish_engulf = (close > open_price and 
                         self.data.Close[-2] < self.data.Open[-2] and
                         close > self.data.Open[-2] and 
                         open_price < self.data.Close[-2])

        strong_bear_move = (close < self.data.Low[-2] and 
                           close < self.data.Low[-3] and 
                           close < open_price)
        strong_bull_move = (close > self.data.High[-2] and 
                           close > self.data.High[-3] and 
                           close > open_price)

        ob_bearish = bearish_engulf or strong_bear_move
        ob_bullish = bullish_engulf or strong_bull_move

        # Trading logic
        if not self.position:
            # Entry signals
            if (bull_bos or bull_choch or is_bull_disp or 
                ob_bullish or sell_side_sweep or bull_fvg):
                self.buy()
            elif (bear_bos or bear_choch or is_bear_disp or 
                  ob_bearish or buy_side_sweep or bear_fvg):
                self.sell()
        else:
            # Exit signals
            if self.position.is_long:
                if (bear_bos or bear_choch or is_bear_disp or 
                    ob_bearish or buy_side_sweep):
                    self.position.close()
            elif self.position.is_short:
                if (bull_bos or bull_choch or is_bull_disp or 
                    ob_bullish or sell_side_sweep):
                    self.position.close()

            # ATR-based stop loss and take profit
            if self.position.is_long:
                if low < self.position.open_price - 2 * self.atr[-1]:
                    self.position.close()
            elif self.position.is_short:
                if high > self.position.open_price + 2 * self.atr[-1]:
                    self.position.close()


