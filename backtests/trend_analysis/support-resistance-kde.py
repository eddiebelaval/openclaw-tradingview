import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback_period = 400
    piv_left = 10
    piv_right = 5
    num_levels = 5
    min_dist_atr = 1.5
    zone_width_atr = 0.5
    kde_steps = 100

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=100)
        
        self.pivot_prices = []
        self.pivot_widths = []
        self.pivot_times = []
        self.support_resistance_levels = []
        self.last_computed_bar = -1

    def identify_pivots(self, idx):
        if idx < self.piv_left + self.piv_right:
            return None, None
        
        center = idx - self.piv_right
        
        high_vals = self.data.High[max(0, center - self.piv_left):center + self.piv_right + 1]
        low_vals = self.data.Low[max(0, center - self.piv_left):center + self.piv_right + 1]
        
        if len(high_vals) < self.piv_left + self.piv_right + 1:
            return None, None
        
        center_high = high_vals.iloc[self.piv_left]
        center_low = low_vals.iloc[self.piv_left]
        
        is_pivot_high = center_high == high_vals.max()
        is_pivot_low = center_low == low_vals.min()
        
        if is_pivot_high:
            return float(center_high), 'high'
        elif is_pivot_low:
            return float(center_low), 'low'
        
        return None, None

    def kde_density(self, test_price, pivot_prices, pivot_widths):
        density = 0.0
        for p_val, p_wid in zip(pivot_prices, pivot_widths):
            if p_wid > 0:
                u = abs(test_price - p_val) / p_wid
                if u <= 1.0:
                    density += (1.0 - u)
        return density

    def compute_support_resistance(self):
        lookback = min(self.lookback_period, len(self.data))
        start_idx = max(0, len(self.data) - lookback)
        
        for i in range(start_idx, len(self.data)):
            pivot_price, pivot_type = self.identify_pivots(i)
            if pivot_price is not None:
                bar_idx = i - self.piv_right
                if bar_idx >= 0:
                    bar_range = self.data.High[max(0, i - self.piv_right):i + 1]
                    if len(bar_range) > 0:
                        bar_width = self.data.High[i] - self.data.Low[i] if i < len(self.data) else 0
                        self.pivot_prices.append(pivot_price)
                        self.pivot_widths.append(max(bar_width, 0.0001))
                        self.pivot_times.append(i)
        
        min_dist = self.atr[-1] * self.min_dist_atr if self.atr[-1] is not None else 0.01
        
        if len(self.pivot_prices) == 0:
            self.support_resistance_levels = []
            return
        
        min_p = min(self.data.Low[max(0, len(self.data) - self.lookback_period):])
        max_p = max(self.data.High[max(0, len(self.data) - self.lookback_period):])
        
        step_size = (max_p - min_p) / max(1, self.kde_steps)
        kde_results_p = []
        kde_results_d = []
        max_density = 0.0
        
        for i in range(self.kde_steps + 1):
            test_price = min_p + (i * step_size)
            density = self.kde_density(test_price, self.pivot_prices, self.pivot_widths)
            kde_results_p.append(test_price)
            kde_results_d.append(density)
            max_density = max(max_density, density)
        
        peak_prices = []
        peak_densities = []
        
        for i in range(1, len(kde_results_d) - 1):
            d_prev = kde_results_d[i - 1]
            d_curr = kde_results_d[i]
            d_next = kde_results_d[i + 1]
            
            if d_curr > d_prev and d_curr > d_next and d_curr > 0:
                peak_prices.append(kde_results_p[i])
                peak_densities.append(d_curr)
        
        sorted_pairs = sorted(zip(peak_densities, peak_prices), reverse=True)
        
        final_levels = []
        for density, curr_p in sorted_pairs:
            is_too_close = False
            for level in final_levels:
                if abs(curr_p - level) < min_dist:
                    is_too_close = True
                    break
            
            if not is_too_close:
                final_levels.append(curr_p)
            
            if len(final_levels) >= self.num_levels:
                break
        
        self.support_resistance_levels = sorted(final_levels)

    def next(self):
        if self.last_computed_bar < len(self.data) - 1:
            self.compute_support_resistance()
            self.last_computed_bar = len(self.data) - 1
        
        if len(self.support_resistance_levels) == 0:
            return
        
        current_price = self.data.Close[-1]
        closest_resistance = None
        closest_support = None
        
        for level in self.support_resistance_levels:
            if level > current_price:
                if closest_resistance is None or level < closest_resistance:
                    closest_resistance = level
            else:
                if closest_support is None or level > closest_support:
                    closest_support = level
        
        if closest_support is not None and closest_resistance is not None:
            support_dist = current_price - closest_support
            resistance_dist = closest_resistance - current_price
            
            if support_dist < resistance_dist and support_dist > 0:
                if not self.position:
                    self.buy()
            elif resistance_dist < support_dist and resistance_dist > 0:
                if self.position:
                    self.sell()


