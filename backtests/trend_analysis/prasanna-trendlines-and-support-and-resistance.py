import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Channel parameters
    CH_len = 100
    CH_divlen = 2.0
    
    # Support/Resistance parameters
    SR_lb = 15
    SR_rb = 15
    SR_vol = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Channel calculation
        def calc_channel():
            result_list = []
            for i in range(len(close)):
                if i < self.CH_len - 1:
                    result_list.append(np.nan)
                else:
                    src_slice = close.iloc[i - self.CH_len + 1:i + 1]
                    md = src_slice.mean()
                    
                    # Linear regression slope
                    x = np.arange(len(src_slice))
                    z = np.polyfit(x, src_slice.values, 1)
                    Ugl = z[0]
                    
                    # Initial point
                    ip = md - Ugl * np.floor(self.CH_len / 2) + (1 - self.CH_len % 2) / 2 * Ugl
                    
                    # Last point
                    lst = ip + Ugl * (self.CH_len - 1)
                    
                    # Deviation calculation
                    dev = 0.0
                    for x_idx in range(self.CH_len):
                        fitted = Ugl * (self.CH_len - x_idx) + ip
                        dev += (src_slice.iloc[x_idx] - fitted) ** 2
                    dev = np.sqrt(dev / self.CH_len)
                    
                    result_list.append((ip, lst, dev, Ugl))
            
            return result_list
        
        self.channel_data = self.I(lambda: pd.Series(calc_channel(), index=close.index))
        
        # Pivot High/Low for Support/Resistance
        def calc_pivot_high():
            result = []
            for i in range(len(high)):
                if i < self.SR_lb or i < len(high) - self.SR_rb - 1:
                    result.append(np.nan)
                else:
                    left_slice = high.iloc[i - self.SR_lb:i]
                    right_slice = high.iloc[i + 1:i + self.SR_rb + 1]
                    current = high.iloc[i]
                    
                    if len(left_slice) == self.SR_lb and len(right_slice) == self.SR_rb:
                        if current >= left_slice.max() and current >= right_slice.max():
                            result.append(current)
                        else:
                            result.append(np.nan)
                    else:
                        result.append(np.nan)
            
            return pd.Series(result, index=high.index)
        
        def calc_pivot_low():
            result = []
            for i in range(len(low)):
                if i < self.SR_lb or i < len(low) - self.SR_rb - 1:
                    result.append(np.nan)
                else:
                    left_slice = low.iloc[i - self.SR_lb:i]
                    right_slice = low.iloc[i + 1:i + self.SR_rb + 1]
                    current = low.iloc[i]
                    
                    if len(left_slice) == self.SR_lb and len(right_slice) == self.SR_rb:
                        if current <= left_slice.min() and current <= right_slice.min():
                            result.append(current)
                        else:
                            result.append(np.nan)
                    else:
                        result.append(np.nan)
            
            return pd.Series(result, index=low.index)
        
        self.pivot_high = self.I(calc_pivot_high)
        self.pivot_low = self.I(calc_pivot_low)
        
        # Volume EMA for support/resistance confirmation
        self.vol_short = self.I(pta.ema, volume, length=5)
        self.vol_long = self.I(pta.ema, volume, length=10)
        
        # Trend detection from Ugl
        def calc_ugl():
            result = []
            for i in range(len(close)):
                if i < self.CH_len - 1:
                    result.append(np.nan)
                else:
                    src_slice = close.iloc[i - self.CH_len + 1:i + 1]
                    x = np.arange(len(src_slice))
                    z = np.polyfit(x, src_slice.values, 1)
                    result.append(z[0])
            
            return pd.Series(result, index=close.index)
        
        self.ugl = self.I(calc_ugl)

    def next(self):
        if len(self.data) < self.CH_len + self.SR_rb + 1:
            return
        
        close = self.data.Close[-1]
        volume = self.data.Volume[-1]
        
        # Get channel data
        try:
            channel_tuple = self.channel_data[-1]
            if isinstance(channel_tuple, tuple) and len(channel_tuple) == 4:
                y1_, y2_, dev, Ugl = channel_tuple
            else:
                return
        except (TypeError, ValueError):
            return
        
        # Volume delta percentage
        if self.vol_long[-1] != 0:
            vol_dlt = 100 * (self.vol_short[-1] - self.vol_long[-1]) / self.vol_long[-1]
        else:
            vol_dlt = 0
        
        # Support/Resistance levels
        sr_high = self.pivot_high[-1]
        sr_low = self.pivot_low[-1]
        
        # Trading signals
        
        # Signal 1: Resistance broken with volume
        if not np.isnan(sr_high) and sr_high > 0:
            if len(self.data) > 1:
                prev_close = self.data.Close[-2]
                if prev_close <= sr_high and close > sr_high and vol_dlt > self.SR_vol:
                    if not self.position:
                        self.buy()
        
        # Signal 2: Support broken with volume
        if not np.isnan(sr_low) and sr_low > 0:
            if len(self.data) > 1:
                prev_close = self.data.Close[-2]
                if prev_close >= sr_low and close < sr_low and vol_dlt > self.SR_vol:
                    if self.position:
                        self.position.close()
                    else:
                        self.sell()
        
        # Signal 3: Channel break - uptrend
        if not np.isnan(Ugl):
            if len(self.data) > 1:
                try:
                    prev_tuple = self.channel_data[-2]
                    if isinstance(prev_tuple, tuple):
                        prev_Ugl = prev_tuple[3]
                        if np.sign(prev_Ugl) != np.sign(Ugl) and Ugl > 0:
                            if not self.position:
                                self.buy()
                except (TypeError, ValueError):
                    pass
        
        # Signal 4: Channel break - downtrend
        if not np.isnan(Ugl):
            if len(self.data) > 1:
                try:
                    prev_tuple = self.channel_data[-2]
                    if isinstance(prev_tuple, tuple):
                        prev_Ugl = prev_tuple[3]
                        if np.sign(prev_Ugl) != np.sign(Ugl) and Ugl < 0:
                            if self.position:
                                self.position.close()
                except (TypeError, ValueError):
                    pass


