import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Fractal Engine
    fractal_periods = 2
    htf_res = "60"
    
    # Cluster Engine
    atr_period = 14
    cluster_mult = 0.4
    min_points = 3
    
    # Strength Engine
    max_zones = 20
    decay_factor = 200.0
    
    # Sweep Engine
    min_penetration = 0.1
    wick_body_ratio = 1.5
    use_mss = False
    
    # Trend Engine
    show_ema = True
    ema_slope_len = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # EMA calculations
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        
        # EMA slope detection
        self.ema50_slope = self.I(lambda: self.ema50 > self.ema50.shift(self.ema_slope_len).fillna(self.ema50))
        self.ema200_slope = self.I(lambda: self.ema200 > self.ema200.shift(self.ema_slope_len).fillna(self.ema200))
        
        # Pivot highs and lows for fractal detection
        self.ltf_top = self.I(self._pivot_high, high, self.fractal_periods)
        self.ltf_bot = self.I(self._pivot_low, low, self.fractal_periods)
        
        # Zone tracking
        self.zones = []  # List of dicts: {price, is_top, count, birth_bar, sum_val}
        self.last_bull_sweep = False
        self.last_bear_sweep = False

    def _pivot_high(self, high_series):
        result = pd.Series(np.nan, index=high_series.index)
        for i in range(self.fractal_periods, len(high_series) - self.fractal_periods):
            if high_series.iloc[i] == high_series.iloc[i - self.fractal_periods:i + self.fractal_periods + 1].max():
                result.iloc[i] = high_series.iloc[i]
        return result

    def _pivot_low(self, low_series):
        result = pd.Series(np.nan, index=low_series.index)
        for i in range(self.fractal_periods, len(low_series) - self.fractal_periods):
            if low_series.iloc[i] == low_series.iloc[i - self.fractal_periods:i + self.fractal_periods + 1].min():
                result.iloc[i] = low_series.iloc[i]
        return result

    def _get_zone_score(self, zone, current_bar):
        if zone['count'] == 0:
            return 0
        return zone['count'] * np.exp(-(current_bar - zone['birth_bar']) / self.decay_factor)

    def _manage_zones(self, f_price, is_top, is_htf, current_bar):
        if f_price is None or np.isnan(f_price):
            return
        
        tolerance = self.atr[-1] * self.cluster_mult if self.atr[-1] else 0
        if tolerance == 0:
            return
        
        weight = 3 if is_htf else 1
        found = False
        
        for zone in self.zones:
            if zone['is_top'] == is_top and abs(f_price - zone['price']) <= tolerance:
                zone['count'] += weight
                zone['sum'] += f_price * weight
                zone['price'] = zone['sum'] / zone['count']
                found = True
                break
        
        if not found and len(self.zones) < self.max_zones:
            self.zones.append({
                'price': f_price,
                'is_top': is_top,
                'count': weight,
                'sum': f_price * weight,
                'birth_bar': current_bar
            })
        
        # Prune zones if exceeded
        if len(self.zones) > self.max_zones:
            min_zone = min(self.zones, key=lambda z: self._get_zone_score(z, current_bar))
            self.zones.remove(min_zone)

    def _detect_sweep(self, current_bar):
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        body = abs(close - open_)
        lower_wick = min(open_, close) - low
        upper_wick = high - max(open_, close)
        
        bull_wick_valid = lower_wick > body * self.wick_body_ratio if body > 0 else False
        bear_wick_valid = upper_wick > body * self.wick_body_ratio if body > 0 else False
        
        bull_mss = True if not self.use_mss else (len(self.data) > 1 and close > self.data.High[-2])
        bear_mss = True if not self.use_mss else (len(self.data) > 1 and close < self.data.Low[-2])
        
        is_bull_sweep = False
        is_bear_sweep = False
        
        if self.atr[-1] and self.atr[-1] > 0:
            sweep_depth = self.atr[-1] * self.min_penetration
            tolerance = self.atr[-1] * self.cluster_mult
            
            for zone in self.zones[:]:
                if zone['count'] < self.min_points:
                    continue
                
                z_avg = zone['price']
                z_top = z_avg + (tolerance / 2)
                z_bot = z_avg - (tolerance / 2)
                is_zone_top = zone['is_top']
                
                # Remove crossed zones
                if (is_zone_top and close > z_top) or (not is_zone_top and close < z_bot):
                    self.zones.remove(zone)
                    continue
                
                # Detect sweeps
                if (not is_zone_top and low <= (z_bot - sweep_depth) and 
                    close > z_bot and bull_wick_valid and bull_mss):
                    is_bull_sweep = True
                
                if (is_zone_top and high >= (z_top + sweep_depth) and 
                    close < z_top and bear_wick_valid and bear_mss):
                    is_bear_sweep = True
        
        return is_bull_sweep, is_bear_sweep

    def next(self):
        current_bar = len(self.data) - 1
        close = self.data.Close[-1]
        
        # Update zones with new fractals
        if not np.isnan(self.ltf_top[-1]):
            self._manage_zones(self.ltf_top[-1], True, False, current_bar)
        if not np.isnan(self.ltf_bot[-1]):
            self._manage_zones(self.ltf_bot[-1], False, False, current_bar)
        
        # Detect sweeps
        is_bull_sweep, is_bear_sweep = self._detect_sweep(current_bar)
        
        # Trend conditions
        ema50_up = self.ema50_slope[-1]
        ema200_up = self.ema200_slope[-1]
        ema50_dn = not ema50_up
        ema200_dn = not ema200_up
        
        is_uptrend = (close > self.ema200[-1] and self.ema50[-1] > self.ema200[-1] and 
                      ema200_up and ema50_up)
        is_downtrend = (close < self.ema200[-1] and self.ema50[-1] < self.ema200[-1] and 
                        ema200_dn and ema50_dn)
        
        # Valid signals
        valid_long = (is_bull_sweep and is_uptrend) if self.show_ema else is_bull_sweep
        valid_short = (is_bear_sweep and is_downtrend) if self.show_ema else is_bear_sweep
        
        # Entry logic
        if valid_long and not self.position:
            self.buy()
        elif valid_short and self.position:
            self.position.close()
        
        if valid_short and not self.position:
            self.sell()
        elif valid_long and self.position and self.position.is_short:
            self.position.close()


