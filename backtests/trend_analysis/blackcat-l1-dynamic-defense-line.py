class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ninePeriodRange: 9-period high - 9-period low
        nine_period_high = self.I(lambda: high.rolling(window=9).max())
        nine_period_low = self.I(lambda: low.rolling(window=9).min())
        self.nine_period_range = self.I(lambda: nine_period_high - nine_period_low)
        
        # Calculate distanceFromHigh9: 9-period high - close
        self.distance_from_high9 = self.I(lambda: nine_period_high - close)
        
