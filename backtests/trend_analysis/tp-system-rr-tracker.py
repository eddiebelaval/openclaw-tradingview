import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # TP System parameters
    tp_rsi_len = 25
    tp_rsi_ob = 55
    tp_rsi_os = 45
    tp_stoch_k_len = 14
    tp_stoch_d_len = 3
    tp_stoch_smooth_k = 3
    tp_st_atr_mult = 3.0
    tp_st_atr_len = 10
    tp_cci_len = 20
    tp_cci_ob = 100
    tp_cci_os = -100
    tp_lookback_bars = 5
    min_tp_conf = 5
    
    # Toggles
    use_tp_rsi = True
    use_tp_stoch = True
    use_tp_st = True
    use_tp_cci = True
    use_tp_price_action = True
    
    # Filters
    enable_vwap_filter = True
    enable_atr_filter = False
    atr_mult = 10.0
    
    # Trade settings
    rr_sl_pips = 10.0
    rr_ratio = 3.0
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA 750
        self.ema750 = self.I(lambda: pta.ema(close, length=750))
        
        # VWAP
        hl2 = (high + low) / 2
        self.vwap = self.I(lambda: pta.vwap(hl2, self.data.Volume))
        
        # ATR bands
        tr = self.I(lambda: pta.tr(high, low, close))
        self.smooth_atr = self.I(lambda: pta.ema(tr, length=750))
        
        self.upper_band = self.I(lambda: self.ema750 + self.atr_mult * self.smooth_atr)
        self.lower_band = self.I(lambda: self.ema750 - self.atr_mult * self.smooth_atr)
        
        # TP RSI
        self.tp_rsi = self.I(lambda: pta.rsi(close, length=self.tp_rsi_len))
        
        # TP Stochastic
        stoch = self.I(lambda: pta.stoch(high, low, close, k=self.tp_stoch_k_len, d=self.tp_stoch_d_len, smooth_k=self.tp_stoch_smooth_k))
        if stoch is not None:
            self.tp_k = self.I(lambda: stoch.iloc[:, 0] if stoch.shape[1] > 0 else pd.Series(50, index=close.index))
            self.tp_d = self.I(lambda: stoch.iloc[:, 1] if stoch.shape[1] > 1 else pd.Series(50, index=close.index))
        else:
            self.tp_k = self.I(lambda: pd.Series(50, index=close.index))
            self.tp_d = self.I(lambda: pd.Series(50, index=close.index))
        
        # TP Supertrend (manual implementation)
        atr = self.I(lambda: pta.atr(high, low, close, length=self.tp_st_atr_len))
        self.tp_st_dir = self.I(lambda: self._supertrend_dir(high, low, close, atr))
        
        # TP CCI
        self.tp_cci = self.I(lambda: pta.cci(high, low, close, length=self.tp_cci_len))
        
        self.in_position = False

    def _supertrend_dir(self, high, low, close, atr):
        """Calculate supertrend direction: 1 for uptrend, -1 for downtrend"""
        if atr is None or len(atr) < 2:
            return pd.Series(1, index=close.index)
        
        hl_avg = (high + low) / 2
        basic_ub = hl_avg + self.tp_st_atr_mult * atr
        basic_lb = hl_avg - self.tp_st_atr_mult * atr
        
        final_ub = basic_ub.copy()
        final_lb = basic_lb.copy()
        
        for i in range(1, len(close)):
            final_ub.iloc[i] = min(basic_ub.iloc[i], final_ub.iloc[i-1]) if close.iloc[i-1] > final_ub.iloc[i-1] else basic_ub.iloc[i]
            final_lb.iloc[i] = max(basic_lb.iloc[i], final_lb.iloc[i-1]) if close.iloc[i-1] < final_lb.iloc[i-1] else basic_lb.iloc[i]
        
        trend = pd.Series(1, index=close.index)
        for i in range(1, len(close)):
            if trend.iloc[i-1] == 1:
                trend.iloc[i] = -1 if close.iloc[i] <= final_lb.iloc[i] else 1
            else:
                trend.iloc[i] = 1 if close.iloc[i] >= final_ub.iloc[i] else -1
        
        return trend

    def next(self):
        if len(self.data) < self.tp_lookback_bars + 1:
            return
        
        close_curr = self.data.Close[-1]
        close_past = self.data.Close[-self.tp_lookback_bars-1]
        
        # Price action
        tp_price_act_bull = close_curr > close_past
        tp_price_act_bear = close_curr < close_past
        
        # RSI conditions
        tp_rsi_bull = self.use_tp_rsi and self.tp_rsi[-1] > self.tp_rsi_ob
        tp_rsi_bear = self.use_tp_rsi and self.tp_rsi[-1] < self.tp_rsi_os
        
        # Stochastic conditions
        tp_stoch_bull = self.use_tp_stoch and crossover(self.tp_d, self.tp_k) and self.tp_k[-1] > 80
        tp_stoch_bear = self.use_tp_stoch and crossover(self.tp_k, self.tp_d) and self.tp_k[-1] < 20
        
        # Supertrend conditions
        tp_st_bull = self.use_tp_st and self.tp_st_dir[-1] == -1
        tp_st_bear = self.use_tp_st and self.tp_st_dir[-1] == 1
        
        # CCI conditions
        tp_cci_bull = self.use_tp_cci and self.tp_cci[-1] > self.tp_cci_ob
        tp_cci_bear = self.use_tp_cci and self.tp_cci[-1] < self.tp_cci_os
        
        # Price action toggle
        tp_price_act_bull = self.use_tp_price_action and tp_price_act_bull
        tp_price_act_bear = self.use_tp_price_action and tp_price_act_bear
        
        # Count confirmations
        tp_bull_count = sum([tp_rsi_bull, tp_stoch_bull, tp_st_bull, tp_cci_bull, tp_price_act_bull])
        tp_bear_count = sum([tp_rsi_bear, tp_stoch_bear, tp_st_bear, tp_cci_bear, tp_price_act_bear])
        
        # Filter conditions
        vwap_cond_buy = not self.enable_vwap_filter or close_curr > self.vwap[-1]
        vwap_cond_sell = not self.enable_vwap_filter or close_curr < self.vwap[-1]
        atr_cond_buy = not self.enable_atr_filter or close_curr <= self.upper_band[-1]
        atr_cond_sell = not self.enable_atr_filter or close_curr >= self.lower_band[-1]
        
        # Final signals (reversed logic: original bearish = BUY, original bullish = SELL)
        tp_buy_signal = (tp_bear_count >= self.min_tp_conf and 
                        tp_bear_count > tp_bull_count and 
                        close_curr > self.ema750[-1] and 
                        vwap_cond_buy and 
                        atr_cond_buy)
        
        tp_sell_signal = (tp_bull_count >= self.min_tp_conf and 
                         tp_bull_count > tp_bear_count and 
                         close_curr < self.ema750[-1] and 
                         vwap_cond_sell and 
                         atr_cond_sell)
        
        # Trading logic
        if tp_buy_signal and not self.position:
            self.buy()
            self.in_position = True
        elif tp_sell_signal and self.position:
            self.position.close()
            self.in_position = False


