import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.pivot_high = self.I(lambda: pta.pivothigh(high, 15, 5) or pd.Series(np.nan, index=close.index))
        self.pivot_low = self.I(lambda: pta.pivotlow(low, 15, 5) or pd.Series(np.nan, index=close.index))
        
        self.last_pivot_high = np.nan
        self.last_pivot_low = np.nan
        self.entry_triggered = False

    def next(self):
        current_pivot_high = self.pivot_high[-1]
        current_pivot_low = self.pivot_low[-1]
        
        current_close = self.data.Close[-1]
        
        if not np.isnan(current_pivot_high) and np.isnan(self.last_pivot_high):
            self.last_pivot_high = current_pivot_high
            self.entry_triggered = False
        
        if not np.isnan(current_pivot_low) and np.isnan(self.last_pivot_low):
            self.last_pivot_low = current_pivot_low
            self.entry_triggered = False
        
        if not np.isnan(self.last_pivot_low) and current_close > self.last_pivot_low and not self.entry_triggered:
            if not self.position:
                self.buy()
            self.entry_triggered = True
        
        if not np.isnan(self.last_pivot_high) and current_close < self.last_pivot_high and not self.entry_triggered:
            if self.position:
                self.sell()
            self.entry_triggered = True
        
        if self.position and not np.isnan(self.last_pivot_high) and current_close < self.last_pivot_high:
            self.sell()


