import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLength = 50
    atrPeriod = 10
    atrMultiplier = 3.0
    profitMultiplier = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMA for High and Low
        self.emaHigh = self.I(pta.ema, high, length=self.emaLength)
        self.emaLow = self.I(pta.ema, low, length=self.emaLength)
        
        # Calculate Supertrend manually using ATR
        atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)
        
        # Supertrend calculation
        def calc_supertrend():
            hl2 = (high + low) / 2
            matr = atr * self.atrMultiplier
            basic_ub = hl2 + matr
            basic_lb = hl2 - matr
            
            final_ub = pd.Series(np.nan, index=close.index)
            final_lb = pd.Series(np.nan, index=close.index)
            supertrend = pd.Series(np.nan, index=close.index)
            direction = pd.Series(np.nan, index=close.index)
            
            for i in range(len(close)):
                if i == 0:
                    final_ub.iloc[i] = basic_ub.iloc[i]
                    final_lb.iloc[i] = basic_lb.iloc[i]
                else:
                    final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                    final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
                
                if i == 0:
                    supertrend.iloc[i] = final_ub.iloc[i]
                    direction.iloc[i] = -1
                else:
                    if supertrend.iloc[i-1] == final_ub.iloc[i-1]:
                        supertrend.iloc[i] = final_ub.iloc[i] if close.iloc[i] <= final_ub.iloc[i] else final_lb.iloc[i]
                        direction.iloc[i] = -1 if close.iloc[i] <= final_ub.iloc[i] else 1
                    else:
                        supertrend.iloc[i] = final_lb.iloc[i] if close.iloc[i] >= final_lb.iloc[i] else final_ub.iloc[i]
                        direction.iloc[i] = 1 if close.iloc[i] >= final_lb.iloc[i] else -1
            
            return supertrend
        
        self.supertrend = self.I(calc_supertrend)
        
        # Track direction: < 0 means uptrend
        def calc_direction():
            hl2 = (high + low) / 2
            matr = atr * self.atrMultiplier
            basic_ub = hl2 + matr
            basic_lb = hl2 - matr
            
            final_ub = pd.Series(np.nan, index=close.index)
            final_lb = pd.Series(np.nan, index=close.index)
            direction = pd.Series(np.nan, index=close.index)
            
            for i in range(len(close)):
                if i == 0:
                    final_ub.iloc[i] = basic_ub.iloc[i]
                    final_lb.iloc[i] = basic_lb.iloc[i]
                else:
                    final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                    final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
                
                if i == 0:
                    direction.iloc[i] = -1
                else:
                    if close.iloc[i] <= final_ub.iloc[i]:
                        direction.iloc[i] = -1
                    else:
                        direction.iloc[i] = 1
            
            return direction
        
        self.direction = self.I(calc_direction)
        
        self.buy_price = None
        self.has_active_buy = False

    def next(self):
        close = self.data.Close[-1]
        emaHigh = self.emaHigh[-1]
        emaLow = self.emaLow[-1]
        direction = self.direction[-1]
        
        isSuperTrendUp = direction < 0
        
        # Check for crossovers
        priceCrossAboveHigh = crossover(self.data.Close, self.emaHigh)
        priceCrossBelowLow = crossover(self.emaLow, self.data.Close)
        
        # Calculate extension ratio
        emaDifference = emaHigh - emaLow
        priceExtension = close - emaHigh
        extensionRatio = priceExtension / emaDifference if emaDifference > 0 else 0
        
        # BUY Signal
        if priceCrossAboveHigh and isSuperTrendUp and not self.has_active_buy:
            self.buy()
            self.buy_price = close
            self.has_active_buy = True
        
        # SELL Signal (price crosses below EMA Low)
        elif priceCrossBelowLow and self.has_active_buy:
            self.sell()
            self.has_active_buy = False
            self.buy_price = None
        
        # BOOK PROFIT Signal (extension >= profitMultiplier)
        elif self.has_active_buy and extensionRatio >= self.profitMultiplier:
            self.sell()
            self.has_active_buy = False
            self.buy_price = None