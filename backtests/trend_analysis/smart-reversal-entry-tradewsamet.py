        trades_to_remove = []
        
        for i, trade in enumerate(self.active_trades):
            if current_bar <= trade['signal_bar']:
                continue
            
            direction = trade['direction']
            tp_price = trade['tp']
            sl_price = trade['sl']
            
            tp_hit = False
            sl_hit = False
            
            if direction == 1:
                # Long trade
                tp_hit = high[-1] >= tp_price
                sl_hit = low[-1] <= sl_price
