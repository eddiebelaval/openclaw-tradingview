import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Signal Settings
    ema_length = 100
    minimum_move_pips = 400
    
    # Pip Settings
    pip_size = 0.01  # XAUUSD / Gold preset
    
    # Risk Management
    stop_loss_pips = 500
    rr_mode = "1:1"  # 1:1 risk/reward ratio
    
    # Hidden Engine Settings
    cooldown_bars = 10
    dollar_per_pip = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMA
        self.ema_main = self.I(pta.ema, close, length=self.ema_length)
        
        # Pre-calculate RR multiplier
        self.rr_multiplier = 1.0 if self.rr_mode == "1:1" else \
                            1.5 if self.rr_mode == "1:1.5" else \
                            2.0 if self.rr_mode == "1:2" else 3.0
        
        # Track active trades: list of dicts with direction, entry, tp, sl, signal_bar
        self.active_trades = []
        self.closed_trades = []
        
        # Statistics
        self.total_entries = 0
        self.winning_trades = 0
        self.losing_trades = 0
        self.gross_profit_r = 0.0
        self.gross_loss_r = 0.0
        self.gross_profit_pips = 0.0
        self.gross_loss_pips = 0.0
        self.equity_r = 0.0
        self.peak_equity_r = 0.0
        self.max_drawdown_r = 0.0
        self.current_win_streak = 0
        self.current_loss_streak = 0
        self.best_win_streak = 0
        self.best_loss_streak = 0
        
        # Cooldown tracking
        self.last_signal_bar = -np.inf

    def next(self):
        if len(self.data) < 4:
            return
        
        close = self.data.Close
        open_ = self.data.Open
        high = self.data.High
        low = self.data.Low
        
        # Get current and previous candles
        # Current candle (index -1)
        current_green = close[-1] > open_[-1]
        current_red = close[-1] < open_[-1]
        
        # Last 3 candles (indices -4, -3, -2)
        red1 = close[-4] < open_[-4]
        red2 = close[-3] < open_[-3]
        red3 = close[-2] < open_[-2]
        
        green1 = close[-4] > open_[-4]
        green2 = close[-3] > open_[-3]
        green3 = close[-2] > open_[-2]
        
        three_red_sequence = red1 and red2 and red3
        three_green_sequence = green1 and green2 and green3
        
        # Calculate pips movement
        down_move_pips = (open_[-4] - close[-2]) / self.pip_size
        up_move_pips = (close[-2] - open_[-4]) / self.pip_size
        
        enough_down_move = down_move_pips >= self.minimum_move_pips
        enough_up_move = up_move_pips >= self.minimum_move_pips
        
        # EMA filter
        ema_val = self.ema_main[-1]
        
        # Signal detection
        raw_long_signal = (close[-1] > ema_val and 
                          three_red_sequence and 
                          enough_down_move and 
                          current_green)
        
        raw_short_signal = (close[-1] < ema_val and 
                           three_green_sequence and 
                           enough_up_move and 
                           current_red)
        
        # Cooldown filter
        current_bar = len(self.data) - 1
        cooldown_passed = (current_bar - self.last_signal_bar) > self.cooldown_bars
        
        long_signal = raw_long_signal and cooldown_passed
        short_signal = raw_short_signal and cooldown_passed
        
        # Create new trades
        if long_signal:
            entry_price = close[-1]
            sl_price = entry_price - self.stop_loss_pips * self.pip_size
            tp_price = entry_price + self.stop_loss_pips * self.rr_multiplier * self.pip_size
            
            self.active_trades.append({
                'direction': 1,
                'entry': entry_price,
                'tp': tp_price,
                'sl': sl_price,
                'signal_bar': current_bar
            })
            
            self.total_entries += 1
            self.last_signal_bar = current_bar
        
        if short_signal:
            entry_price = close[-1]
            sl_price = entry_price + self.stop_loss_pips * self.pip_size
            tp_price = entry_price - self.stop_loss_pips * self.rr_multiplier * self.pip_size
            
            self.active_trades.append({
                'direction': -1,
                'entry': entry_price,
                'tp': tp_price,
                'sl': sl_price,
                'signal_bar': current_bar
            })
            
            self.total_entries += 1
            self.last_signal_bar = current_bar
        
