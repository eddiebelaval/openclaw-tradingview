import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 20

    def init(self):
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate highest high and lowest low over lookback period
        self.highest_high = self.I(lambda: high.rolling(window=self.lookback).max())
        self.lowest_low = self.I(lambda: low.rolling(window=self.lookback).min())

    def next(self):
        # Need at least lookback + 1 bars to have previous values
        if len(self.data) < self.lookback + 1:
            return
        
        # Current values
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        
        # Previous values
        prev_high = self.data.High[-2]
        prev_low = self.data.Low[-2]
        prev_close = self.data.Close[-2]
        
        # Previous highest high and lowest low
        prev_highest_high = self.highest_high[-2]
        prev_lowest_low = self.lowest_low[-2]
        
        # Long condition: low < lowestLow[1] and close > high[1]
        long_condition = current_low < prev_lowest_low and current_close > prev_high
        
        # Short condition: high > highestHigh[1] and close < low[1]
        short_condition = current_high > prev_highest_high and current_close < prev_low
        
        if long_condition:
            if not self.position:
                self.buy()
            elif self.position.is_short:
                self.position.close()
                self.buy()
        
        if short_condition:
            if not self.position:
                self.sell()
            elif self.position.is_long:
                self.position.close()
                self.sell()