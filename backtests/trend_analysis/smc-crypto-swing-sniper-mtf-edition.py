import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 5
    volMult = 2.0
    cvd_len = 21
    divLb = 2
    maxDivBars = 60
    sr_len = 50
    rsi_os_lvl = 15
    rsi_ob_lvl = 85

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume indicators
        self.avg_vol = self.I(lambda: pta.sma(volume, length=20))
        
        # RSI for alerts
        self.rsi = self.I(lambda: pta.rsi(close, length=14))
        
        # EMA and WMA for trend
        self.ema50 = self.I(lambda: pta.ema(close, length=50))
        self.wma200 = self.I(lambda: pta.wma(close, length=200))
        
        # ATR for volatility
        self.atr = self.I(lambda: pta.atr(high, low, close, length=14))
        
        # Pivot points
        self.pivot_high = self.I(lambda: self._pivot_high(high, self.pivot_len))
        self.pivot_low = self.I(lambda: self._pivot_low(low, self.pivot_len))
        
        # MACD for trend confirmation
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macd_line = macd_result['MACD_12_26_9'] if macd_result is not None else self.I(lambda: pd.Series(0, index=close.index))
        self.macd_signal = macd_result['MACDs_12_26_9'] if macd_result is not None else self.I(lambda: pd.Series(0, index=close.index))
        
        # DMI/ADX for trend strength
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.di_plus = adx_result['DMP_14'] if adx_result is not None else self.I(lambda: pd.Series(0, index=close.index))
        self.di_minus = adx_result['DMN_14'] if adx_result is not None else self.I(lambda: pd.Series(0, index=close.index))
        self.adx = adx_result['ADX_14'] if adx_result is not None else self.I(lambda: pd.Series(0, index=close.index))
        
        self.smc_trend = 0
        self.last_swing_h = None
        self.last_swing_l = None
        self.entry_price = None

    def _pivot_high(self, series, lookback):
        result = pd.Series(index=series.index, dtype='float64')
        for i in range(lookback, len(series) - lookback):
            if series.iloc[i] == series.iloc[i-lookback:i+lookback+1].max():
                result.iloc[i] = series.iloc[i]
        return result

    def _pivot_low(self, series, lookback):
        result = pd.Series(index=series.index, dtype='float64')
        for i in range(lookback, len(series) - lookback):
            if series.iloc[i] == series.iloc[i-lookback:i+lookback+1].min():
                result.iloc[i] = series.iloc[i]
        return result

    def next(self):
        current_price = self.data.Close[-1]
        current_rsi = self.rsi[-1] if len(self.rsi) > 0 else 50
        current_ema = self.ema50[-1] if len(self.ema50) > 0 else current_price
        current_wma = self.wma200[-1] if len(self.wma200) > 0 else current_price
        current_adx = self.adx[-1] if len(self.adx) > 0 else 0
        current_di_plus = self.di_plus[-1] if len(self.di_plus) > 0 else 0
        current_di_minus = self.di_minus[-1] if len(self.di_minus) > 0 else 0
        current_macd = self.macd_line[-1] if len(self.macd_line) > 0 else 0
        current_macd_sig = self.macd_signal[-1] if len(self.macd_signal) > 0 else 0
        
        pivot_h = self.pivot_high[-1] if len(self.pivot_high) > 0 else None
        pivot_l = self.pivot_low[-1] if len(self.pivot_low) > 0 else None
        
        # Update swing levels
        if pd.notna(pivot_h) and pivot_h > 0:
            self.last_swing_h = pivot_h
        
        if pd.notna(pivot_l) and pivot_l > 0:
            self.last_swing_l = pivot_l
        
        # Detect breakouts
        breakout_up = False
        breakout_dn = False
        
        if self.last_swing_h is not None and len(self.data.Close) > 1:
            if current_price > self.last_swing_h and self.data.Close[-2] <= self.last_swing_h:
                breakout_up = True
        
        if self.last_swing_l is not None and len(self.data.Close) > 1:
            if current_price < self.last_swing_l and self.data.Close[-2] >= self.last_swing_l:
                breakout_dn = True
        
        # Trend detection
        if breakout_up:
            self.smc_trend = 1
        elif breakout_dn:
            self.smc_trend = -1
        
        # Entry signals based on SMC structure + RSI + MACD + ADX
        buy_signal = False
        sell_signal = False
        
        # Buy conditions: Uptrend + RSI oversold + MACD bullish + ADX strong
        if self.smc_trend == 1:
            if current_rsi < self.rsi_os_lvl and current_macd > current_macd_sig:
                if current_adx >= 25 and current_di_plus > current_di_minus:
                    if current_price > current_ema > current_wma:
                        buy_signal = True
        
        # Sell conditions: Downtrend + RSI overbought + MACD bearish + ADX strong
        if self.smc_trend == -1:
            if current_rsi > self.rsi_ob_lvl and current_macd < current_macd_sig:
                if current_adx >= 25 and current_di_minus > current_di_plus:
                    if current_price < current_ema < current_wma:
                        sell_signal = True
        
        # Execute trades
        if buy_signal and not self.position:
            self.buy()
            self.entry_price = current_price
        
        elif sell_signal and not self.position:
            self.position.close()
        
        # Exit logic
        if self.position:
            if self.position.is_long:
                # Exit long on RSI overbought or trend reversal
                if current_rsi > self.rsi_ob_lvl or self.smc_trend == -1:
                    self.position.close()
                # Stop loss: below last swing low
                if self.last_swing_l is not None and current_price < self.last_swing_l:
                    self.position.close()
            
            else:  # Short position
                # Exit short on RSI oversold or trend reversal
                if current_rsi < self.rsi_os_lvl or self.smc_trend == 1:
                    self.position.close()
                # Stop loss: above last swing high
                if self.last_swing_h is not None and current_price > self.last_swing_h:
                    self.position.close()


