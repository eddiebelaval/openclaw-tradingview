import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    maType = "EMA"
    maLength = 40
    slopeLookback = 5
    flatThresh = 0.02
    useVol = True
    volMult = 1.2
    useWick = True
    wickMult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        if self.maType == "SMA":
            self.myMA = self.I(pta.sma, close, length=self.maLength)
        elif self.maType == "WMA":
            self.myMA = self.I(pta.wma, close, length=self.maLength)
        else:
            self.myMA = self.I(pta.ema, close, length=self.maLength)

        self.maSlope = self.I(pta.roc, self.myMA, length=self.slopeLookback)
        
        self.priceDist = self.I(
            lambda: (np.abs(close - self.myMA) / self.myMA) * 100
        )

        self.open_ = open_
        self.high = high
        self.low = low
        self.close = close
        self.volume = volume

        self.avgVol = self.I(pta.sma, volume, length=20)

        self.regime = 0

    def next(self):
        if len(self.data) < self.maLength + self.slopeLookback:
            return

        close_val = self.close.iloc[-1]
        open_val = self.open_.iloc[-1]
        high_val = self.high.iloc[-1]
        low_val = self.low.iloc[-1]
        volume_val = self.volume.iloc[-1]

        if len(self.data) >= 2:
            prev_high = self.high.iloc[-2]
            prev_low = self.low.iloc[-2]
            prev_close = self.close.iloc[-2]
        else:
            prev_high = high_val
            prev_low = low_val
            prev_close = close_val

        ma_val = self.myMA[-1]
        slope_val = self.maSlope[-1]
        price_dist_val = self.priceDist[-1]

        if len(self.data) >= 2:
            prev_ma = self.myMA[-2]
            prev_close_comp = self.close.iloc[-2]
        else:
            prev_ma = ma_val
            prev_close_comp = close_val

        isGapUp = open_val > prev_high
        isGapDown = open_val < prev_low

        bullTrigger = (slope_val > self.flatThresh and close_val > ma_val) or \
                      (isGapUp and close_val > ma_val) or \
                      (close_val > ma_val and price_dist_val > self.flatThresh)
        bearTrigger = (slope_val < -self.flatThresh and close_val < ma_val) or \
                      (isGapDown and close_val < ma_val) or \
                      (close_val < ma_val and price_dist_val > self.flatThresh)
        flatTrigger = abs(slope_val) <= self.flatThresh and price_dist_val <= self.flatThresh

        if bullTrigger:
            self.regime = 1
        elif bearTrigger:
            self.regime = -1
        elif flatTrigger:
            self.regime = 0

        isBullish = (self.regime == 1)
        isBearish = (self.regime == -1)

        safeVol = volume_val if volume_val > 0 else 0
        avgVol_val = self.avgVol[-1]
        isVolSpike = safeVol > (avgVol_val * self.volMult)
        passVol = isVolSpike if self.useVol else True

        bodySize = abs(close_val - open_val)
        safeBody = bodySize if bodySize > 0 else 0.0001

        lowerWick = min(open_val, close_val) - low_val
        upperWick = high_val - max(open_val, close_val)

        passBullWick = (lowerWick >= (safeBody * self.wickMult)) if self.useWick else True
        passBearWick = (upperWick >= (safeBody * self.wickMult)) if self.useWick else True

        bullBounce = isBullish and \
                     (slope_val > self.flatThresh) and \
                     (prev_close_comp > prev_ma) and \
                     (low_val <= ma_val) and \
                     (open_val > ma_val) and \
                     (close_val > ma_val) and \
                     passVol and \
                     passBullWick

        bearBounce = isBearish and \
                     (slope_val < -self.flatThresh) and \
                     (prev_close_comp < prev_ma) and \
                     (high_val >= ma_val) and \
                     (open_val < ma_val) and \
                     (close_val < ma_val) and \
                     passVol and \
                     passBearWick

        if bullBounce and not self.position:
            self.buy()
        elif bearBounce and self.position:
            self.sell()
        elif bearBounce and not self.position:
            self.sell()
        elif bullBounce and self.position:
            self.position.close()


