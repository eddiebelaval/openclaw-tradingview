import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len1 = 10
    len2 = 10

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # First EMA smoothing
        o_ema1 = self.I(pta.ema, open_, length=self.len1)
        c_ema1 = self.I(pta.ema, close, length=self.len1)
        h_ema1 = self.I(pta.ema, high, length=self.len1)
        l_ema1 = self.I(pta.ema, low, length=self.len1)

        # Heikin Ashi calculation
        def calc_ha():
            ha_close = (o_ema1 + h_ema1 + l_ema1 + c_ema1) / 4
            
            ha_open = np.full_like(ha_close, np.nan)
            ha_open[0] = (o_ema1[0] + c_ema1[0]) / 2
            
            for i in range(1, len(ha_close)):
                if np.isnan(ha_open[i-1]) or np.isnan(ha_close[i-1]):
                    ha_open[i] = (o_ema1[i] + c_ema1[i]) / 2
                else:
                    ha_open[i] = (ha_open[i-1] + ha_close[i-1]) / 2
            
            ha_high = np.maximum(h_ema1, np.maximum(ha_open, ha_close))
            ha_low = np.minimum(l_ema1, np.minimum(ha_open, ha_close))
            
            return pd.Series(ha_open), pd.Series(ha_high), pd.Series(ha_low), pd.Series(ha_close)

        ha_o, ha_h, ha_l, ha_c = calc_ha()

        # Second EMA smoothing
        self.mtf_o = self.I(pta.ema, ha_o, length=self.len2)
        self.mtf_h = self.I(pta.ema, ha_h, length=self.len2)
        self.mtf_l = self.I(pta.ema, ha_l, length=self.len2)
        self.mtf_c = self.I(pta.ema, ha_c, length=self.len2)

    def next(self):
        if len(self.data) < 2:
            return

        # Determine if current candle is up or down
        current_open = self.mtf_o[-1]
        current_close = self.mtf_c[-1]
        
        prev_open = self.mtf_o[-2]
        prev_close = self.mtf_c[-2]

        current_is_up = current_open <= current_close
        prev_was_down = prev_open > prev_close

        # Buy signal: transition from down candle to up candle
        if prev_was_down and current_is_up and not self.position:
            self.buy()

        # Sell signal: candle turns down
        if current_open > current_close and self.position:
            self.sell()