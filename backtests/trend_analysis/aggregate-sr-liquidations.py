import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    threshold_plusplus = 4.0
    threshold_plus = 2.5
    atr_length = 50
    mean_length = 610
    std_length = 610

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for zone sizing
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Calculate long liquidations proxy (using volume-based metric)
        self.liq_long_raw = self.I(lambda: pd.Series(self.data.Volume) * (close / close.iloc[0]))
        
        # Calculate short liquidations proxy
        self.liq_short_raw = self.I(lambda: pd.Series(self.data.Volume) * (close.iloc[0] / close))
        
        # Mean and standard deviation for long liquidations
        self.mean_long = self.I(pta.sma, self.liq_long_raw, length=self.mean_length)
        self.std_long = self.I(lambda: self.liq_long_raw.rolling(window=self.std_length).std())
        
        # Mean and standard deviation for short liquidations
        self.mean_short = self.I(pta.sma, self.liq_short_raw, length=self.mean_length)
        self.std_short = self.I(lambda: self.liq_short_raw.rolling(window=self.std_length).std())
        
        # Calculate standardized bars
        self.stdbar_long = self.I(
            lambda: ((self.liq_long_raw - self.mean_long) / (self.std_long + 1e-10)).fillna(0)
        )
        self.stdbar_short = self.I(
            lambda: ((self.liq_short_raw - self.mean_short) / (self.std_short + 1e-10)).fillna(0)
        )
        
        # Track zones for support/resistance levels
        self.support_zones = []
        self.resistance_zones = []

    def next(self):
        current_atr = self.atr[-1] if len(self.atr) > 0 else 0
        current_stdbar_long = self.stdbar_long[-1] if len(self.stdbar_long) > 0 else 0
        current_stdbar_short = self.stdbar_short[-1] if len(self.stdbar_short) > 0 else 0
        
        # Create support zones from long liquidations (at low)
        if current_stdbar_long > self.threshold_plusplus:
            support_price = self.data.Low[-1]
            self.support_zones.append(support_price)
            # Buy signal near support zone
            if len(self.support_zones) > 0 and not self.position:
                nearest_support = min(self.support_zones, key=lambda x: abs(x - self.data.Close[-1]))
                if abs(self.data.Close[-1] - nearest_support) < current_atr * 0.5:
                    self.buy()
        
        elif current_stdbar_long > self.threshold_plus:
            support_price = self.data.Low[-1]
            if len(self.support_zones) == 0 or support_price not in self.support_zones:
                self.support_zones.append(support_price)
                if len(self.support_zones) > 0 and not self.position:
                    nearest_support = min(self.support_zones, key=lambda x: abs(x - self.data.Close[-1]))
                    if abs(self.data.Close[-1] - nearest_support) < current_atr:
                        self.buy()
        
        # Create resistance zones from short liquidations (at high)
        if current_stdbar_short > self.threshold_plusplus:
            resistance_price = self.data.High[-1]
            self.resistance_zones.append(resistance_price)
            # Sell signal near resistance zone
            if len(self.resistance_zones) > 0 and self.position:
                nearest_resistance = max(self.resistance_zones, key=lambda x: abs(x - self.data.Close[-1]))
                if abs(self.data.Close[-1] - nearest_resistance) < current_atr * 0.5:
                    self.sell()
        
        elif current_stdbar_short > self.threshold_plus:
            resistance_price = self.data.High[-1]
            if len(self.resistance_zones) == 0 or resistance_price not in self.resistance_zones:
                self.resistance_zones.append(resistance_price)
                if len(self.resistance_zones) > 0 and self.position:
                    nearest_resistance = max(self.resistance_zones, key=lambda x: abs(x - self.data.Close[-1]))
                    if abs(self.data.Close[-1] - nearest_resistance) < current_atr:
                        self.sell()
        
        # Clean up old zones
        if len(self.support_zones) > 20:
            self.support_zones = self.support_zones[-20:]
        if len(self.resistance_zones) > 20:
            self.resistance_zones = self.resistance_zones[-20:]
        
        # Exit logic based on price crossing zones
        if self.position:
            if len(self.resistance_zones) > 0:
                max_resistance = max(self.resistance_zones)
                if self.data.Close[-1] > max_resistance:
                    self.sell()
        
        # Entry on support break with momentum
        if not self.position:
            if len(self.support_zones) > 0:
                min_support = min(self.support_zones)
                if self.data.Close[-1] < min_support and self.data.Close[-2] >= min_support:
                    self.buy()


