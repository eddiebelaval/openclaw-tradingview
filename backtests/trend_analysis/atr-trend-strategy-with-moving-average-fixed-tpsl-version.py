import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA Input
    MAtype = "EMA"
    MAlen = 100
    
    # ATR Input
    ATRtype = "RMA"
    ATRmult = 3
    ATRlen = 7
    
    # Bars confirmed input
    ConfirmBars = 1
    ConfirmSrc = "Close"
    
    # Entry Method
    entryMethod = "Breakout"
    
    # Threshold(%) input
    TPthresh = 5.0
    SLthresh = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate MA
        if self.MAtype == "EMA":
            self.ma = self.I(pta.ema, close, length=self.MAlen)
        elif self.MAtype == "SMA":
            self.ma = self.I(pta.sma, close, length=self.MAlen)
        elif self.MAtype == "WMA":
            self.ma = self.I(pta.wma, close, length=self.MAlen)
        elif self.MAtype == "Hull MA":
            self.ma = self.I(pta.hma, close, length=self.MAlen)
        elif self.MAtype == "VWMA":
            self.ma = self.I(pta.vwma, close, volume, length=self.MAlen)
        elif self.MAtype == "RMA":
            self.ma = self.I(pta.rma, close, length=self.MAlen)
        elif self.MAtype == "TEMA":
            self.ma = self.I(pta.tema, close, length=self.MAlen)
        else:
            self.ma = self.I(pta.ema, close, length=self.MAlen)
        
        # Calculate True Range
        tr = self.I(lambda: pta.atr(high, low, close, length=1))
        
        # Calculate ATR using specified type
        if self.ATRtype == "EMA":
            self.atr = self.I(lambda: pta.ema(tr if tr is not None else pd.Series(0, index=close.index), length=self.ATRlen))
        elif self.ATRtype == "SMA":
            self.atr = self.I(lambda: pta.sma(tr if tr is not None else pd.Series(0, index=close.index), length=self.ATRlen))
        elif self.ATRtype == "WMA":
            self.atr = self.I(lambda: pta.wma(tr if tr is not None else pd.Series(0, index=close.index), length=self.ATRlen))
        elif self.ATRtype == "RMA":
            self.atr = self.I(lambda: pta.rma(tr if tr is not None else pd.Series(0, index=close.index), length=self.ATRlen))
        else:
            self.atr = self.I(lambda: pta.rma(tr if tr is not None else pd.Series(0, index=close.index), length=self.ATRlen))
        
        # Initialize trend and breakpoint tracking
        self.trend = 0
        self.breakPoint = 0
        self.crossUsed = False
        self.bars_since_uptrend_raw = 0
        self.bars_since_downtrend_raw = 0

    def next(self):
        if len(self.data) < max(self.MAlen, self.ATRlen) + 5:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        ma_val = self.ma[-1]
        atr_val = self.atr[-1]
        
        if ma_val is None or atr_val is None or np.isnan(ma_val) or np.isnan(atr_val):
            return
        
        atr_upper = ma_val + atr_val * self.ATRmult
        atr_lower = ma_val - atr_val * self.ATRmult
        
        # Determine uptrend/downtrend
        uptrend_price = close if self.ConfirmSrc == "Close" else high
        downtrend_price = close if self.ConfirmSrc == "Close" else low
        
        is_uptrend_raw = uptrend_price > atr_upper
        is_downtrend_raw = downtrend_price < atr_lower
        
        # Track bars since raw condition
        if is_uptrend_raw:
            self.bars_since_uptrend_raw = 0
        else:
            self.bars_since_uptrend_raw += 1
        
        if is_downtrend_raw:
            self.bars_since_downtrend_raw = 0
        else:
            self.bars_since_downtrend_raw += 1
        
        is_uptrend_confirmed = self.bars_since_uptrend_raw == self.ConfirmBars
        is_downtrend_confirmed = self.bars_since_downtrend_raw == self.ConfirmBars
        
        # Update trend
        if is_uptrend_confirmed and self.trend != 1:
            self.trend = 1
            self.breakPoint = 1
            self.crossUsed = False
        
        if is_downtrend_confirmed and self.trend != -1:
            self.trend = -1
            self.breakPoint = -1
            self.crossUsed = False
        
        # Entry logic
        if self.entryMethod == "Breakout":
            if self.breakPoint == 1 and len(self.position) == 0:
                self.buy()
                self.breakPoint = 0
            elif self.breakPoint == -1 and len(self.position) == 0:
                self.sell()
                self.breakPoint = 0
        
        elif self.entryMethod == "MA Cross":
            cross_under = crossover(self.ma, pd.Series([ma_val]))
            cross_over = crossover(pd.Series([ma_val]), self.ma)
            
            if self.trend == 1 and cross_under and len(self.position) == 0 and not self.crossUsed:
                self.buy()
                self.crossUsed = True
            elif self.trend == -1 and cross_over and len(self.position) == 0 and not self.crossUsed:
                self.sell()
                self.crossUsed = True
        
        # Exit logic with TP/SL
        if len(self.position) > 0:
            if self.position.is_long:
                entry_price = self.position.open_price
                tp = entry_price * (1 + self.TPthresh / 100)
                sl = entry_price * (1 - self.SLthresh / 100)
                
                if close >= tp or close <= sl:
                    self.position.close()
            else:
                entry_price = self.position.open_price
                tp = entry_price * (1 - self.TPthresh / 100)
                sl = entry_price * (1 + self.SLthresh / 100)
                
                if close <= tp or close >= sl:
                    self.position.close()


