import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenMA = 80
    maType = "HMA"
    atrLength = 200
    mult = 1.8
    smoothType = "EMA"
    smoothLen = 100
    trendBandMult = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate base MA
        def calc_base_ma():
            if self.maType == "EMA":
                return pta.ema(close, length=self.lenMA)
            elif self.maType == "WMA":
                return pta.wma(close, length=self.lenMA)
            elif self.maType == "HMA":
                return pta.hma(close, length=self.lenMA)
            else:
                return pta.sma(close, length=self.lenMA)
        
        self.baseMA = self.I(calc_base_ma)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # Calculate deviation and validity
        def calc_deviation():
            return np.abs(close - self.baseMA)
        
        self.deviation = self.I(calc_deviation)
        
        # Calculate filtered MA (with state tracking)
        self.filteredMA_values = []
        
        # Calculate smoothed MA
        def calc_smoothed_ma():
            filtered_series = pd.Series(self.filteredMA_values, index=close.index)
            if self.smoothType == "EMA":
                return pta.ema(filtered_series, length=self.smoothLen)
            elif self.smoothType == "RMA":
                return pta.rma(filtered_series, length=self.smoothLen)
            elif self.smoothType == "WMA":
                return pta.wma(filtered_series, length=self.smoothLen)
            else:
                return pta.sma(filtered_series, length=self.smoothLen)
        
        self.smoothedMA = self.I(calc_smoothed_ma)
        
        # Road levels
        def calc_road_up():
            return self.smoothedMA + (self.atr * self.trendBandMult)
        
        def calc_road_low():
            return self.smoothedMA - (self.atr * self.trendBandMult)
        
        self.roadUp = self.I(calc_road_up)
        self.roadLow = self.I(calc_road_low)
        
        # Regime tracking
        self.regime = 0
        self.prev_regime = 0
        
        # Previous close for re-entry detection
        self.prev_close = None

    def next(self):
        # Build filtered MA values during init phase
        if len(self.filteredMA_values) < len(self.data.Close):
            if not np.isnan(self.atr[-1]) and not np.isnan(self.baseMA[-1]):
                valid = self.deviation[-1] > self.atr[-1] * self.mult
                if valid:
                    self.filteredMA_values.append(self.baseMA[-1])
                else:
                    if self.filteredMA_values:
                        self.filteredMA_values.append(self.filteredMA_values[-1])
                    else:
                        self.filteredMA_values.append(self.baseMA[-1])
        
        current_close = self.data.Close[-1]
        
        # Skip if indicators not ready
        if np.isnan(self.roadUp[-1]) or np.isnan(self.roadLow[-1]) or np.isnan(self.smoothedMA[-1]):
            return
        
        # Update regime
        self.prev_regime = self.regime
        if current_close > self.roadUp[-1]:
            self.regime = 1
        elif current_close < self.roadLow[-1]:
            self.regime = -1
        
        # Bull signal: regime changes to 1
        bullSignal = self.regime == 1 and self.prev_regime != 1
        
        # Bear signal: regime changes to -1
        bearSignal = self.regime == -1 and self.prev_regime != -1
        
        # Re-entry: price crosses back into the channel
        reEntry = False
        if self.prev_close is not None:
            reEntry = (current_close < self.roadUp[-1] and current_close > self.roadLow[-1] and 
                      (self.prev_close > self.roadUp[-1] or self.prev_close < self.roadLow[-1]))
        
        self.prev_close = current_close
        
        # Trading logic
        if bullSignal:
            if self.position:
                self.position.close()
            self.buy()
        elif bearSignal:
            if self.position:
                self.position.close()
            self.sell()
        elif reEntry:
            # Re-entry: close opposite position if any
            if self.position:
                self.position.close()


