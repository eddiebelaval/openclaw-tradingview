import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    h = 8.0
    mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        window = int(np.floor(self.h * 10))
        window = max(1, window)
        sigma = self.h
        offset = 0.85
        
        self.alma_val = self.I(lambda: pta.alma(close, length=window, offset=offset, sigma=sigma) or pd.Series(close.iloc[-1], index=close.index))
        
        self.atr_val = self.I(pta.atr, high, low, close, length=100)
        
        self.upper_band = self.I(lambda: self.alma_val[-1] + (self.atr_val[-1] * self.mult) if self.atr_val[-1] is not None else close.iloc[-1], name="upper_band")
        
        self.lower_band = self.I(lambda: self.alma_val[-1] - (self.atr_val[-1] * self.mult) if self.atr_val[-1] is not None else close.iloc[-1], name="lower_band")
        
        self.bullish_rev = self.I(lambda: self._bullish_reversal(low), name="bullish_rev")
        
        self.bearish_rev = self.I(lambda: self._bearish_reversal(high), name="bearish_rev")
        
        self.in_position = False

    def _bullish_reversal(self, low):
        if len(self.alma_val) < 2 or len(self.lower_band) < 2:
            return False
        return low.iloc[-2] >= self.lower_band[-2] and low.iloc[-1] < self.lower_band[-1]

    def _bearish_reversal(self, high):
        if len(self.alma_val) < 2 or len(self.upper_band) < 2:
            return False
        return high.iloc[-2] <= self.upper_band[-2] and high.iloc[-1] > self.upper_band[-1]

    def next(self):
        if len(self.alma_val) < 2:
            return
        
        if self.bullish_rev[-1] and not self.position:
            self.buy()
            self.in_position = True
        elif self.bearish_rev[-1] and self.position:
            self.sell()
            self.in_position = False