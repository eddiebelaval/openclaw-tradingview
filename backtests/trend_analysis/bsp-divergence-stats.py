import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    typeCM = 'Delta Volume'  # 'Delta Volume' or 'Pressure'
    lb = 100  # Lookback bars for stats
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # Store raw data for calculations
        self.close_data = close
        self.high_data = high
        self.low_data = low
        self.volume_data = volume
        self.open_data = open_
        
        # Calculate HMA of buy/sell pressure
        def calc_bp_dv():
            bp_values = []
            for i in range(len(close)):
                h = high.iloc[i]
                l = low.iloc[i]
                c = close.iloc[i]
                v = volume.iloc[i]
                rng = h - l
                if rng > 0:
                    buy_v = v * (c - l) / rng
                    sel_v = v * (h - c) / rng
                else:
                    buy_v = v * 0.5
                    sel_v = v * 0.5
                bp_values.append(buy_v - sel_v)
            return pd.Series(bp_values, index=close.index)
        
        def calc_sp_dv():
            sp_values = []
            for i in range(len(close)):
                h = high.iloc[i]
                l = low.iloc[i]
                c = close.iloc[i]
                v = volume.iloc[i]
                rng = h - l
                if rng > 0:
                    buy_v = v * (c - l) / rng
                    sel_v = v * (h - c) / rng
                else:
                    buy_v = v * 0.5
                    sel_v = v * 0.5
                sp_values.append(sel_v - buy_v)
            return pd.Series(sp_values, index=close.index)
        
        bp_raw = self.I(calc_bp_dv)
        sp_raw = self.I(calc_sp_dv)
        
        # HMA(2) of pressure
        self.bpma = self.I(lambda: pta.hma(bp_raw, length=2) or pd.Series(0, index=bp_raw.index))
        self.spma = self.I(lambda: pta.hma(sp_raw, length=2) or pd.Series(0, index=sp_raw.index))
        
        # Current candle delta volume ratio
        def calc_dv_ratio():
            ratios = []
            for i in range(len(close)):
                h = high.iloc[i]
                l = low.iloc[i]
                c = close.iloc[i]
                v = volume.iloc[i]
                rng = h - l
                if rng > 0:
                    buy_v = v * (c - l) / rng
                    sel_v = v * (h - c) / rng
                else:
                    buy_v = v * 0.5
                    sel_v = v * 0.5
                dv_total = buy_v + sel_v
                if dv_total > 0:
                    ratios.append(buy_v / dv_total)
                else:
                    ratios.append(0.5)
            return pd.Series(ratios, index=close.index)
        
        self.dv_ratio = self.I(calc_dv_ratio)
        
        # Track divergences and hidden signals
        self.bull_div_signal = self.I(lambda: pd.Series([False] * len(close), index=close.index))
        self.bear_div_signal = self.I(lambda: pd.Series([False] * len(close), index=close.index))
        self.hidden_buy_signal = self.I(lambda: pd.Series([False] * len(close), index=close.index))
        self.hidden_sell_signal = self.I(lambda: pd.Series([False] * len(close), index=close.index))
        
        self.position_open = False
    
    def next(self):
        # Current values
        if len(self.data) < 2:
            return
        
        idx = len(self.data) - 1
        close_curr = self.close_data.iloc[idx]
        close_prev = self.close_data.iloc[idx - 1]
        high_curr = self.high_data.iloc[idx]
        low_curr = self.low_data.iloc[idx]
        open_curr = self.open_data.iloc[idx]
        
        bpma_curr = self.bpma[-1]
        bpma_prev = self.bpma[-2] if len(self.bpma) > 1 else bpma_curr
        spma_curr = self.spma[-1]
        spma_prev = self.spma[-2] if len(self.spma) > 1 else spma_curr
        dv_ratio_curr = self.dv_ratio[-1]
        
        # Detect signals
        bull_div = (bpma_curr < bpma_prev) and (close_curr > close_prev)
        bear_div = (spma_curr < spma_prev) and (close_curr < close_prev)
        
        is_green = close_curr > open_curr
        hidden_buy = (dv_ratio_curr > 0.55) and (not is_green)
        hidden_sell = (dv_ratio_curr < 0.45) and is_green
        
        # Trading logic based on signals
        # Buy on: bull divergence, hidden buy, or dv_ratio strong buy
        # Sell on: bear divergence, hidden sell, or dv_ratio strong sell
        
        buy_signal = bull_div or hidden_buy or (dv_ratio_curr > 0.65)
        sell_signal = bear_div or hidden_sell or (dv_ratio_curr < 0.35)
        
        # Execute trades
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.position.close()
        elif sell_signal and not self.position:
            # Allow short selling
            self.sell()
        elif buy_signal and self.position.is_short:
            self.position.close()


