import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Base Signal Parameters
    hma_open_len = 5
    hma_close_len = 12
    rsi_len = 9
    atr_periods = 10
    multiplier = 2.0
    
    # TP/SL Parameters
    atr_tp_multiplier = 2.0
    atr_sl_multiplier = 1.0
    
    # Liquidation Filter Parameters
    use_liq_filter = True
    use_adaptive_filter = True
    liq_len = 15
    liq_len2 = 30
    liq_pct_window = 89
    liq_require_cluster = False
    liq_cluster_lookback = 3
    liq_tolerance = 1.0
    adapt_strength = 0.3
    
    # Position Management
    prevent_multiple_positions = True

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Base Signal Calculations
        self.hma_open = self.I(lambda: pta.hma(open_, length=self.hma_open_len) or pd.Series(0, index=open_.index))
        self.hma_close = self.I(lambda: pta.hma(close, length=self.hma_close_len) or pd.Series(0, index=close.index))
        
        self.rsi_calc = self.I(lambda: pta.rsi(close, length=self.rsi_len) or pd.Series(50, index=close.index))
        
        # ATR Calculation
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atr_periods) or pd.Series(0, index=close.index))
        
        # Trend Calculation
        self.trend = self.I(self._calculate_trend, close, high, low)
        
        # Liquidation Filter Components
        self.liq_signal = self.I(self._calculate_liq_filter, close, high, low)
        
        # Entry signals
        self.buy_signal = self.I(self._get_buy_signal, close, high, low)
        self.sell_signal = self.I(self._get_sell_signal, close, high, low)

    def _calculate_trend(self, close):
        close_array = np.array(close)
        high_array = np.array(self.data.High)
        low_array = np.array(self.data.Low)
        hl2_array = (high_array + low_array) / 2.0
        
        atr_vals = np.array(self.atr)
        
        trend = np.zeros(len(close))
        up = np.zeros(len(close))
        dn = np.zeros(len(close))
        
        for i in range(len(close)):
            if i == 0:
                trend[i] = 1
                up[i] = hl2_array[i] - (self.multiplier * atr_vals[i])
                dn[i] = hl2_array[i] + (self.multiplier * atr_vals[i])
            else:
                trend[i] = trend[i-1]
                
                up[i] = hl2_array[i] - (self.multiplier * atr_vals[i])
                if close_array[i-1] > up[i-1]:
                    up[i] = max(up[i], up[i-1])
                
                dn[i] = hl2_array[i] + (self.multiplier * atr_vals[i])
                if close_array[i-1] < dn[i-1]:
                    dn[i] = min(dn[i], dn[i-1])
                
                if trend[i] == -1 and close_array[i] > dn[i-1]:
                    trend[i] = 1
                elif trend[i] == 1 and close_array[i] < up[i-1]:
                    trend[i] = -1
        
        return pd.Series(trend, index=close.index)

    def _calculate_liq_filter(self, close):
        close_array = np.array(close)
        
        # Volatility ratio
        atr_vals = np.array(self.atr)
        smooth_atr = pd.Series(atr_vals).rolling(30).mean().fillna(method='bfill').values
        vol_ratio = atr_vals / (smooth_atr + 1e-10)
        vol_ratio = np.maximum(vol_ratio, 0.1)
        
        # Adaptive lengths
        if self.use_adaptive_filter:
            adj_liq_len = np.round(self.liq_len / (vol_ratio ** self.adapt_strength)).astype(int)
            adj_liq_len2 = np.round(self.liq_len2 / (vol_ratio ** self.adapt_strength)).astype(int)
        else:
            adj_liq_len = np.full(len(close), self.liq_len, dtype=int)
            adj_liq_len2 = np.full(len(close), self.liq_len2, dtype=int)
        
        adj_liq_len = np.clip(adj_liq_len, 5, 120)
        adj_liq_len2 = np.clip(adj_liq_len2, 10, 200)
        
        # Use a fixed adaptive length for rolling calculations (use the last value)
        fixed_liq_len = max(5, int(np.round(adj_liq_len[-1])))
        fixed_liq_len2 = max(10, int(np.round(adj_liq_len2[-1])))
        
        # MA1 (SMA)
        ma1 = pd.Series(close_array).rolling(fixed_liq_len).mean().values
        
        # MA2 (EMA)
        ma2_series = pd.Series(close_array).ewm(span=fixed_liq_len2, adjust=False).mean().values
        
        # Average line
        avg_line = (ma1 + ma2_series) / 2.0
        
        # Distance percentage
        dist_val = ((close_array - avg_line) / (avg_line + 1e-10)) * 100.0
        
        # Apply tolerance
        dist_adj = np.where(np.abs(dist_val) > self.liq_tolerance, dist_val, 0)
        
        # Find peaks and troughs
        dist_series = pd.Series(dist_adj)
        ph = dist_series.rolling(self.liq_pct_window, center=False).max().values
        pl = dist_series.rolling(self.liq_pct_window, center=False).min().values
        
        # Long/Short raw signals
        long_liq_raw = (ph == dist_adj) & (dist_adj > 0)
        short_liq_raw = (pl == dist_adj) & (dist_adj < 0)
        
        # Cluster check
        if self.liq_require_cluster:
            long_cluster = pd.Series(long_liq_raw.astype(float)).rolling(self.liq_cluster_lookback).sum().values >= 1
            short_cluster = pd.Series(short_liq_raw.astype(float)).rolling(self.liq_cluster_lookback).sum().values >= 1
        else:
            long_cluster = long_liq_raw
            short_cluster = short_liq_raw
        
        # Return signal (1 for long confirmed, -1 for short confirmed, 0 for none)
        signal = np.zeros(len(close))
        signal[long_cluster] = 1
        signal[short_cluster] = -1
        
        return pd.Series(signal, index=close.index)

    def _get_buy_signal(self, close):
        trend_vals = np.array(self.trend)
        liq_vals = np.array(self.liq_signal)
        
        signal = np.zeros(len(close))
        
        for i in range(1, len(close)):
            buy_trend = (trend_vals[i] == 1) and (trend_vals[i-1] == -1)
            liq_allow = (not self.use_liq_filter) or (liq_vals[i] == 1)
            
            if buy_trend and liq_allow:
                signal[i] = 1
        
        return pd.Series(signal, index=close.index)

    def _get_sell_signal(self, close):
        trend_vals = np.array(self.trend)
        liq_vals = np.array(self.liq_signal)
        
        signal = np.zeros(len(close))
        
        for i in range(1, len(close)):
            sell_trend = (trend_vals[i] == -1) and (trend_vals[i-1] == 1)
            liq_allow = (not self.use_liq_filter) or (liq_vals[i] == -1)
            
            if sell_trend and liq_allow:
                signal[i] = 1
        
        return pd.Series(signal, index=close.index)

    def next(self):
        # Get current values
        current_atr = self.atr[-1]
        current_close = self.data.Close[-1]
        buy_sig = self.buy_signal[-1]
        sell_sig = self.sell_signal[-1]
        
        # Check if we can enter (prevent multiple positions)
        can_trade = (not self.prevent_multiple_positions) or (len(self.position) == 0 or self.position.size == 0)
        
        # Long entry
        if buy_sig > 0.5 and can_trade:
            sl = current_close - (self.atr_sl_multiplier * current_atr)
            tp = current_close + (self.atr_tp_multiplier * current_atr)
            self.buy(sl=sl, tp=tp)
        
        # Short entry
        elif sell_sig > 0.5 and can_trade:
            sl = current_close + (self.atr_sl_multiplier * current_atr)
            tp = current_close - (self.atr_tp_multiplier * current_atr)
            self.sell(sl=sl, tp=tp)


