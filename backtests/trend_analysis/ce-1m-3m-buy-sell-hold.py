import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 7
    mult = 2.0
    useClose = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.length)
        
        # Calculate highest and lowest using rolling
        highest_close = self.I(lambda: close.rolling(window=self.length).max())
        lowest_close = self.I(lambda: close.rolling(window=self.length).min())
        highest_high = self.I(lambda: high.rolling(window=self.length).max())
        lowest_low = self.I(lambda: low.rolling(window=self.length).min())
        
        self.atr = atr
        self.highest_close = highest_close
        self.lowest_close = lowest_close
        self.highest_high = highest_high
        self.lowest_low = lowest_low
        
        # Store direction state
        self.dir_1m_prev = 1
        self.dir_3m_prev = 1
        self.state_prev = 0
        
        # Store stop levels
        self.long_stop_prev = None
        self.short_stop_prev = None

    def next(self):
        if len(self.data) < self.length + 1:
            return
        
        close = self.data.Close
        
        # Get current values
        atr_val = self.atr[-1]
        
        # Determine which price to use
        if self.useClose:
            highest_val = self.highest_close[-1]
            lowest_val = self.lowest_close[-1]
        else:
            highest_val = self.highest_high[-1]
            lowest_val = self.lowest_low[-1]
        
        if pd.isna(atr_val) or pd.isna(highest_val) or pd.isna(lowest_val):
            return
        
        # Calculate long stop and short stop for 1M
        long_stop = highest_val - (self.mult * atr_val)
        short_stop = lowest_val + (self.mult * atr_val)
        
        # Initialize previous stops if not set
        if self.long_stop_prev is None:
            self.long_stop_prev = long_stop
            self.short_stop_prev = short_stop
        
        # Update long stop: maintain floor if price was above previous short stop
        if len(self.data) > 1 and close[-2] > self.short_stop_prev:
            long_stop = max(long_stop, self.long_stop_prev)
        
        # Update short stop: maintain ceiling if price was below previous long stop
        if len(self.data) > 1 and close[-2] < self.long_stop_prev:
            short_stop = min(short_stop, self.short_stop_prev)
        
        # Determine direction for 1M
