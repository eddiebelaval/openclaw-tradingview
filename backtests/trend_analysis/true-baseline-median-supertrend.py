import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    alen = 27
    blen = 21
    fac = 1.75
    smooth = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate True Range
        def calc_tr():
            tr_vals = []
            for i in range(len(close)):
                if i == 0:
                    tr = high.iloc[i] - low.iloc[i]
                else:
                    tr = max(
                        high.iloc[i] - low.iloc[i],
                        abs(high.iloc[i] - close.iloc[i-1]),
                        abs(low.iloc[i] - close.iloc[i-1])
                    )
                tr_vals.append(tr)
            return pd.Series(tr_vals, index=close.index)
        
        tr = self.I(calc_tr)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.alen)
        
        # Calculate Median ATR
        def calc_median_atr():
            return atr.rolling(window=self.blen).median()
        
        median_atr = self.I(calc_median_atr)
        
        # Calculate baseline
        def calc_baseline():
            baseline_vals = []
            for i in range(len(close)):
                if i < self.blen - 1:
                    baseline_vals.append(np.nan)
                else:
                    median_atr_val = median_atr.iloc[i]
                    if pd.isna(median_atr_val):
                        baseline_vals.append(np.nan)
                    else:
                        sum_val = 0.0
                        samples = 0
                        for j in range(i - self.blen + 1, i + 1):
                            if tr.iloc[j] >= median_atr_val:
                                sum_val += close.iloc[j]
                                samples += 1
                        if samples > 0:
                            baseline_vals.append(sum_val / samples)
                        else:
                            baseline_vals.append(np.nan)
            return pd.Series(baseline_vals, index=close.index)
        
        baseline = self.I(calc_baseline)
        
        # Calculate upper and lower bands
        def calc_upper():
            return baseline + atr * self.fac
        
        def calc_lower():
            return baseline - atr * self.fac
        
        upper_raw = self.I(calc_upper)
        lower_raw = self.I(calc_lower)
        
        # Smooth with median
        def calc_upper_smooth():
            return upper_raw.rolling(window=self.smooth).median()
        
        def calc_lower_smooth():
            return lower_raw.rolling(window=self.smooth).median()
        
        self.upper = self.I(calc_upper_smooth)
        self.lower = self.I(calc_lower_smooth)
        
        self.src = close
        self.trend = None
        self.prev_trend = None

    def next(self):
        if len(self.data) < self.smooth + self.blen:
            return
        
        src_val = self.src.iloc[-1]
        upper_val = self.upper[-1]
        lower_val = self.lower[-1]
        
        if pd.isna(upper_val) or pd.isna(lower_val):
            return
        
        L = src_val > upper_val
        S = src_val < lower_val
        
        prev_trend = self.trend
        
        if L and not S:
            self.trend = 1
        if S:
            self.trend = -1
        
        # Generate signals on trend change
        if prev_trend is not None:
            if self.trend == 1 and prev_trend != 1:
                if self.position:
                    self.position.close()
                self.buy()
            elif self.trend == -1 and prev_trend != -1:
                if self.position:
                    self.position.close()