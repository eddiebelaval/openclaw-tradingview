import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivotLength = 5
    useCloseConfirmation = True
    minBreakAtrFilter = 0.10
    atrLength = 14
    maxBarsForRetest = 10
    retestToleranceAtr = 0.20
    retestCooldownBars = 15
    useVolumeConfirmation = False
    minGradeForConfirm = "B"
    minGradeForDisplay = "B"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        self.sma_vol = self.I(lambda: pta.sma(volume, length=20) or pd.Series(1.0, index=volume.index))
        
        self.active_direction = 0
        self.active_level = np.nan
        self.active_atr_at_break = np.nan
        self.active_break_bar = np.nan
        self.active_retest_seen = False
        self.next_eligible_break_bar = 0
        
        self.last_pivot_high = np.nan
        self.last_pivot_low = np.nan
        self.last_pivot_high_bar = np.nan
        self.last_pivot_low_bar = np.nan
        self.last_used_bull_pivot_bar = np.nan
        self.last_used_bear_pivot_bar = np.nan

    def f_clamp(self, value, min_value, max_value):
        return max(min_value, min(max_value, value))

    def f_grade_threshold(self, grade_text):
        if grade_text == "A":
            return 80
        elif grade_text == "B":
            return 65
        elif grade_text == "C":
            return 50
        else:
            return 0

    def f_grade_from_score(self, score):
        if score >= 80:
            return "A"
        elif score >= 65:
            return "B"
        elif score >= 50:
            return "C"
        else:
            return "F"

    def f_outcome_from_score(self, score):
        if score >= 80:
            return "Strong Retest"
        elif score >= 65:
            return "Valid Retest"
        elif score >= 50:
            return "Weak Retest"
        else:
            return "Failed Retest"

    def f_reclaim_score(self, direction, close_price, level, atr):
        atr_safe = max(atr, 1e-6)
        if direction == 1:
            raw = (close_price - level) / (atr_safe * 0.60)
        else:
            raw = (level - close_price) / (atr_safe * 0.60)
        return int(round(self.f_clamp(raw, 0.0, 1.0) * 25.0))

    def f_rejection_score(self, direction, open_price, high_price, low_price, close_price):
        candle_range = max(high_price - low_price, 1e-6)
        bullish_lower_wick = max(min(open_price, close_price) - low_price, 0.0)
        bearish_upper_wick = max(high_price - max(open_price, close_price), 0.0)
        body = abs(close_price - open_price)
        
        if direction == 1:
            wick_part = bullish_lower_wick / candle_range
            body_bonus = 0.20 if close_price > open_price else 0.0
        else:
            wick_part = bearish_upper_wick / candle_range
            body_bonus = 0.20 if close_price < open_price else 0.0
        
        raw = wick_part + body_bonus + (body / candle_range) * 0.20
        return int(round(self.f_clamp(raw / 1.20, 0.0, 1.0) * 20.0))

    def f_depth_score(self, direction, level, extreme_price, atr):
        atr_safe = max(atr, 1e-6)
        if direction == 1:
            overshoot = max(level - extreme_price, 0.0)
        else:
            overshoot = max(extreme_price - level, 0.0)
        raw = 1.0 - (overshoot / (atr_safe * 0.80))
        return int(round(self.f_clamp(raw, 0.0, 1.0) * 20.0))

    def f_speed_score(self, bars_since_break, max_bars):
        max_bars_safe = max(max_bars, 1)
        raw = 1.0 - ((bars_since_break - 1.0) / max(max_bars_safe - 1.0, 1.0))
        return int(round(self.f_clamp(raw, 0.0, 1.0) * 15.0))

    def f_volatility_score(self, high_price, low_price, atr):
        atr_safe = max(atr, 1e-6)
        bar_range = high_price - low_price
        raw = 1.0 - max(bar_range - atr_safe, 0.0) / (atr_safe * 2.0)
        return int(round(self.f_clamp(raw, 0.0, 1.0) * 10.0))

    def f_volume_score(self):
        if not self.useVolumeConfirmation:
            return 10
        else:
            vol_base = max(self.sma_vol[-1], 1.0)
            raw = self.data.Volume[-1] / vol_base
            return int(round(self.f_clamp(raw / 1.50, 0.0, 1.0) * 10.0))

    def f_total_score(self, direction, level, atr, bars_since_break):
        reclaim_part = self.f_reclaim_score(direction, self.data.Close[-1], level, atr)
        rejection_part = self.f_rejection_score(direction, self.data.Open[-1], self.data.High[-1], self.data.Low[-1], self.data.Close[-1])
        depth_extreme = self.data.Low[-1] if direction == 1 else self.data.High[-1]
        depth_part = self.f_depth_score(direction, level, depth_extreme, atr)
        speed_part = self.f_speed_score(bars_since_break, self.maxBarsForRetest)
        volatility_part = self.f_volatility_score(self.data.High[-1], self.data.Low[-1], atr)
        volume_part = self.f_volume_score()
        
        return reclaim_part + rejection_part + depth_part + speed_part + volatility_part + volume_part

    def detect_pivot_high(self, idx):
        if idx < self.pivotLength or idx - self.pivotLength < 0:
            return np.nan
        
        pivot_idx = idx - self.pivotLength
        pivot_val = self.data.High[pivot_idx]
        
        is_pivot = True
        for i in range(1, self.pivotLength + 1):
            left_idx = pivot_idx - i
            right_idx = pivot_idx + i
            
            if left_idx >= 0 and self.data.High[left_idx] >= pivot_val:
                is_pivot = False
                break
            if right_idx < idx and self.data.High[right_idx] >= pivot_val:
                is_pivot = False
                break
        
        return pivot_val if is_pivot else np.nan

    def detect_pivot_low(self, idx):
        if idx < self.pivotLength or idx - self.pivotLength < 0:
            return np.nan
        
        pivot_idx = idx - self.pivotLength
        pivot_val = self.data.Low[pivot_idx]
        
        is_pivot = True
        for i in range(1, self.pivotLength + 1):
            left_idx = pivot_idx - i
            right_idx = pivot_idx + i
            
            if left_idx >= 0 and self.data.Low[left_idx] <= pivot_val:
                is_pivot = False
                break
            if right_idx < idx and self.data.Low[right_idx] <= pivot_val:
                is_pivot = False
                break
        
        return pivot_val if is_pivot else np.nan

    def next(self):
        if len(self.data) < self.pivotLength + 1:
            return
        
        current_idx = len(self.data) - 1
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.01
        min_break_distance = atr_val * self.minBreakAtrFilter
        confirm_threshold = self.f_grade_threshold(self.minGradeForConfirm)
        
        pivot_high = self.detect_pivot_high(current_idx)
        pivot_low = self.detect_pivot_low(current_idx)
        
        if not np.isnan(pivot_high):
            self.last_pivot_high = pivot_high
            self.last_pivot_high_bar = current_idx - self.pivotLength
        
        if not np.isnan(pivot_low):
            self.last_pivot_low = pivot_low
            self.last_pivot_low_bar = current_idx - self.pivotLength
        
        can_look_for_new_break = self.active_direction == 0 and current_idx >= self.next_eligible_break_bar
        
        bull_break_now = (
            can_look_for_new_break and 
            not np.isnan(self.last_pivot_high) and 
            not np.isnan(self.last_pivot_high_bar) and 
            (np.isnan(self.last_used_bull_pivot_bar) or self.last_pivot_high_bar != self.last_used_bull_pivot_bar) and
            current_idx > self.last_pivot_high_bar and
            (
                (self.useCloseConfirmation and self.data.Close[-1] > self.last_pivot_high + min_break_distance) or
                (not self.useCloseConfirmation and self.data.High[-1] > self.last_pivot_high + min_break_distance)
            )
        )
        
        bear_break_now = (
            can_look_for_new_break and 
            not np.isnan(self.last_pivot_low) and 
            not np.isnan(self.last_pivot_low_bar) and 
            (np.isnan(self.last_used_bear_pivot_bar) or self.last_pivot_low_bar != self.last_used_bear_pivot_bar) and
            current_idx > self.last_pivot_low_bar and
            (
                (self.useCloseConfirmation and self.data.Close[-1] < self.last_pivot_low - min_break_distance) or
                (not self.useCloseConfirmation and self.data.Low[-1] < self.last_pivot_low - min_break_distance)
            )
        )
        
        if bull_break_now:
            self.active_direction = 1
            self.active_level = self.last_pivot_high
            self.active_atr_at_break = atr_val
            self.active_break_bar = current_idx
            self.active_retest_seen = False
            self.last_used_bull_pivot_bar = self.last_pivot_high_bar
            self.buy()
        
        if bear_break_now:
            self.active_direction = -1
            self.active_level = self.last_pivot_low
            self.active_atr_at_break = atr_val
            self.active_break_bar = current_idx
            self.active_retest_seen = False
            self.last_used_bear_pivot_bar = self.last_pivot_low_bar
            self.sell()
        
        if self.active_direction != 0:
            bars_since_break = current_idx - self.active_break_bar
            retest_band = max(self.active_atr_at_break * self.retestToleranceAtr, 1e-6)
            
            bull_retest_now = (
                self.active_direction == 1 and 
                bars_since_break > 0 and 
                bars_since_break <= self.maxBarsForRetest and
                self.data.Low[-1] <= self.active_level + retest_band and
                self.data.High[-1] >= self.active_level - retest_band
            )
            
            bear_retest_now = (
                self.active_direction == -1 and 
                bars_since_break > 0 and 
                bars_since_break <= self.maxBarsForRetest and
                self.data.High[-1] >= self.active_level - retest_band and
                self.data.Low[-1] <= self.active_level + retest_band
            )
            
            retest_now = not self.active_retest_seen and (bull_retest_now or bear_retest_now)
            
            if retest_now:
                self.active_retest_seen = True
                score = self.f_total_score(self.active_direction, self.active_level, self.active_atr_at_break, bars_since_break)
                grade = self.f_grade_from_score(score)
                accepted = score >= confirm_threshold and (
                    (self.active_direction == 1 and self.data.Close[-1] >= self.active_level) or
                    (self.active_direction == -1 and self.data.Close[-1] <= self.active_level)
                )
                
                if accepted:
                    if self.active_direction == 1:
                        self.sell()
                    else:
                        self.buy()
                
                self.next_eligible_break_bar = current_idx + self.retestCooldownBars
                self.active_direction = 0
                self.active_level = np.nan
                self.active_atr_at_break = np.nan
                self.active_break_bar = np.nan
                self.active_retest_seen = False
            
            if bars_since_break > self.maxBarsForRetest and not self.active_retest_seen:
                self.next_eligible_break_bar = current_idx + self.retestCooldownBars
                self.active_direction = 0
                self.active_level = np.nan
                self.active_atr_at_break = np.nan
                self.active_break_bar = np.nan
                self.active_retest_seen = False


