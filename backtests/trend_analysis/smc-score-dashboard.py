import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate indicators for structure scoring
        self.atr = self.I(pta.atr, high, low, close, length=14)
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # Volume SMA for scoring
        vol_sma = self.I(pta.sma, volume, length=20)
        self.rel_vol = volume / vol_sma
        
        # Swing structure tracking (using 50-bar swing)
        self.swing_high = self.I(lambda: high.rolling(window=50).max())
        self.swing_low = self.I(lambda: low.rolling(window=50).min())
        
        # Internal structure tracking (using 5-bar swings)
        self.internal_high = self.I(lambda: high.rolling(window=5).max())
        self.internal_low = self.I(lambda: low.rolling(window=5).min())
        
        # Track previous values for crossover detection
        self.prev_close = None
        self.swing_high_crossed = False
        self.swing_low_crossed = False
        self.internal_high_crossed = False
        self.internal_low_crossed = False

    def next(self):
        # Skip if insufficient data
        if len(self.data) < 50:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Get current structure levels
        swing_high = self.swing_high[-1]
        swing_low = self.swing_low[-1]
        internal_high = self.internal_high[-1]
        internal_low = self.internal_low[-1]
        
        # Avoid NaN values
        if pd.isna(swing_high) or pd.isna(swing_low) or pd.isna(internal_high) or pd.isna(internal_low):
            return
        
        if pd.isna(self.atr[-1]) or pd.isna(self.rsi[-1]) or pd.isna(self.rel_vol[-1]):
            return
        
        # Bullish Signal: Price crosses above swing low (BOS - Break of Structure)
        if self.prev_close is not None and self.prev_close <= swing_low and close > swing_low and not self.swing_low_crossed:
            self.swing_low_crossed = True
            self.internal_high_crossed = False
            
            # Calculate structure score for entry confirmation
            rsi_feature = max(self.rsi[-1] - 50.0, 0.0) / 50.0
            atr_val = self.atr[-1]
            if atr_val > 0:
                dist_feature = (close - swing_low) / atr_val
            else:
                dist_feature = 0
            
            vol_weight = 0.4
            rsi_weight = 0.3
            dist_weight = 0.3
            
            weighted_avg = ((self.rel_vol[-1] * vol_weight) + (rsi_feature * rsi_weight) + (dist_feature * dist_weight)) / (vol_weight + rsi_weight + dist_weight)
            score = 100.0 / (1.0 + np.exp(-weighted_avg * 2.0 + 1.0))
            
            if score > 45:  # Threshold for entry
                if not self.position:
                    self.buy()
        
        # Bearish Signal: Price crosses below swing high (BOS - Break of Structure)
        if self.prev_close is not None and self.prev_close >= swing_high and close < swing_high and not self.swing_high_crossed:
            self.swing_high_crossed = True
            self.internal_low_crossed = False
            
            # Calculate structure score for entry confirmation
            rsi_feature = max(50.0 - self.rsi[-1], 0.0) / 50.0
            atr_val = self.atr[-1]
            if atr_val > 0:
                dist_feature = (swing_high - close) / atr_val
            else:
                dist_feature = 0
            
            vol_weight = 0.4
            rsi_weight = 0.3
            dist_weight = 0.3
            
            weighted_avg = ((self.rel_vol[-1] * vol_weight) + (rsi_feature * rsi_weight) + (dist_feature * dist_weight)) / (vol_weight + rsi_weight + dist_weight)
            score = 100.0 / (1.0 + np.exp(-weighted_avg * 2.0 + 1.0))
            
            if score > 45:  # Threshold for entry
                if self.position:
                    self.sell()
        
        # Internal structure signals for confirmation
        if close > internal_high and not self.internal_high_crossed:
            self.internal_high_crossed = True
            # Can be used for adding to positions
        
        if close < internal_low and not self.internal_low_crossed:
            self.internal_low_crossed = True
            # Can be used for adding to positions
        
        # Exit management: Exit long if price breaks internal high
        if self.position and self.position.is_long:
            if close < swing_low:
                self.position.close()
        
        # Exit management: Exit short if price breaks internal low
        if self.position and not self.position.is_long:
            if close > swing_high:
                self.position.close()
        
        # Update previous close
        self.prev_close = close