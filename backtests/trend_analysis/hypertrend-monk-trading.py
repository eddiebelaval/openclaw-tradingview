        # Volume filter
        def calc_vol_filter(vol):
            ema15 = pta.ema(vol, length=15)
            ema20 = pta.ema(vol, length=20)
            ema25 = pta.ema(vol, length=25)
            return (ema15 - ema20) / ema25 > 0
        
        self.vol_filter = self.I(calc_vol_filter, pd.Series(self.data.Volume))
        
        # EMA 200 for strong filter
        self.ema200 = self.I(pta.ema, close, length=200)
        
        # Wavetrend for pullback signals
        def calc_wavetrend(c):
            esa = pta.ema(c, length=5*self.MSTuner)
            d = pta.ema(np.abs(c - esa), length=5*self.MSTuner)
            ci = (c - esa) / (0.015 * d + 1e-10)
            wt1 = pta.ema(ci, length=10*self.MSTuner)
            wt2 = pta.sma(wt1, length=3)
            return wt1, wt2
        
        self.wt1, self.wt2 = self.I(calc_wavetrend, close), None
        
        self.last_bull = False
        self.last_bear = False
        self.entry_price = None
        self.stop_loss = None
        self.tp1 = None
        self.tp2 = None
        self.tp3 = None

