import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Main parameters
    sensitivity = 3.1
    STuner = 25
    MSTuner = 5
    length = 50
    SSF = 30
    CSFSELL = 60
    CSFBUY = 40
    LTAsensitivity = 250
    multTP1 = 1.0
    multTP2 = 2.0
    multTP3 = 3.0
    percTrailingSL = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI with EMA smoothing for Trend Shifter
        rsi_raw = self.I(pta.rsi, close, length=self.length)
        self.rsi_ema = self.I(lambda c=close: pta.ema(pta.rsi(c, length=self.length), length=self.SSF))
        
        # TR and WWMA calculation
        def calc_tr():
            tr = np.zeros(len(close))
            for i in range(1, len(close)):
                tr[i] = max(high.iloc[i] - low.iloc[i], 
                           abs(high.iloc[i] - close.iloc[i-1]),
                           abs(low.iloc[i] - close.iloc[i-1]))
            return pd.Series(tr, index=close.index)
        
        tr = self.I(calc_tr)
        
        # ATRRSI calculation
        wwalpha = 1 / self.length
        def calc_atrrsi(tr_series):
            wwma = np.zeros(len(tr_series))
            atrrsi = np.zeros(len(tr_series))
            for i in range(1, len(tr_series)):
                wwma[i] = wwalpha * tr_series.iloc[i] + (1 - wwalpha) * wwma[i-1]
                atrrsi[i] = wwalpha * wwma[i] + (1 - wwalpha) * atrrsi[i-1]
            return pd.Series(atrrsi, index=tr_series.index)
        
        self.atrrsi = self.I(calc_atrrsi, tr)
        
        # TsFast and bands
        def calc_ts_fast(c=close):
            rsi_ema = pta.ema(pta.rsi(c, length=self.length), length=self.SSF)
            tr_vals = np.zeros(len(c))
            for i in range(1, len(c)):
                tr_vals[i] = max(high.iloc[i] - low.iloc[i],
                                abs(high.iloc[i] - c.iloc[i-1]),
                                abs(low.iloc[i] - c.iloc[i-1]))
            tr_s = pd.Series(tr_vals, index=c.index)
            
            wwma = np.zeros(len(c))
            atrrsi_vals = np.zeros(len(c))
            for i in range(1, len(c)):
                wwma[i] = wwalpha * tr_s.iloc[i] + (1 - wwalpha) * wwma[i-1]
                atrrsi_vals[i] = wwalpha * wwma[i] + (1 - wwalpha) * atrrsi_vals[i-1]
            
            ts_fast = rsi_ema
            return ts_fast
        
        self.ts_fast = self.I(calc_ts_fast)
        
        def calc_ts_slow(ts_f, atr_r):
            ts_slow = np.full(len(ts_f), np.nan)
            up = ts_f + atr_r * 4.236
            dn = ts_f - atr_r * 4.236
            
            ts_slow[0] = ts_f.iloc[0]
            for i in range(1, len(ts_f)):
                prev_slow = ts_slow[i-1] if not np.isnan(ts_slow[i-1]) else ts_f.iloc[i]
                if up.iloc[i] < prev_slow:
                    ts_slow[i] = up.iloc[i]
                elif ts_f.iloc[i] > prev_slow and ts_f.iloc[i-1] < prev_slow:
                    ts_slow[i] = dn.iloc[i]
                elif dn.iloc[i] > prev_slow:
                    ts_slow[i] = dn.iloc[i]
                elif ts_f.iloc[i] < prev_slow and ts_f.iloc[i-1] > prev_slow:
                    ts_slow[i] = up.iloc[i]
                else:
                    ts_slow[i] = prev_slow
            return pd.Series(ts_slow, index=ts_f.index)
        
        self.ts_slow = self.I(calc_ts_slow, self.ts_fast, self.atrrsi)
        
        # Supertrend
        def calc_supertrend(c, h, l, factor, atr_len):
            atr = pta.atr(h, l, c, length=atr_len)
            if atr is None:
                atr = pd.Series(0, index=c.index)
            
            upper_band = c + factor * atr
            lower_band = c - factor * atr
            
            st = np.full(len(c), np.nan)
            direction = np.zeros(len(c))
            
            direction[0] = 1
            st[0] = lower_band.iloc[0]
            
            for i in range(1, len(c)):
                prev_lower = lower_band.iloc[i-1]
                prev_upper = upper_band.iloc[i-1]
                
                lower_band.iloc[i] = lower_band.iloc[i] if lower_band.iloc[i] > prev_lower or c.iloc[i-1] < prev_lower else prev_lower
                upper_band.iloc[i] = upper_band.iloc[i] if upper_band.iloc[i] < prev_upper or c.iloc[i-1] > prev_upper else prev_upper
                
                prev_st = st[i-1] if not np.isnan(st[i-1]) else upper_band.iloc[i-1]
                
                if prev_st == prev_upper:
                    direction[i] = 1 if c.iloc[i] > upper_band.iloc[i] else -1
                else:
                    direction[i] = -1 if c.iloc[i] < lower_band.iloc[i] else 1
                
                st[i] = lower_band.iloc[i] if direction[i] == 1 else upper_band.iloc[i]
            
            return pd.Series(st, index=c.index)
        
