        # Main trend via donchian channel
        def calc_dchannel(h, l):
            trend = np.zeros(len(h))
            for i in range(1, len(h)):
                hh = h.iloc[max(0, i-29):i].max()
                ll = l.iloc[max(0, i-29):i].min()
                if h.iloc[i] > hh:
                    trend[i] = 1
                elif l.iloc[i] < ll:
                    trend[i] = -1
                else:
                    trend[i] = trend[i-1]
            return pd.Series(trend, index=h.index)
        
        self.maintrend = self.I(calc_dchannel, high, low)
        
        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=14)
