class TvStrategy(Strategy):
    def init(self):
        # We'll calculate CPR levels based on previous hour's data
        # Since we're working with minute data, we need to track hourly values
        self.hour_high = None
        self.hour_low = None
        self.hour_close = None
        self.last_hour = None
        self.pivot = None
        self.bc = None
        self.tc = None
        
    def next(self):
        current_time = pd.Timestamp(self.data.index[-1])
        current_hour = current_time.floor('H')
        
        # Initialize on first bar
        if self.last_hour is None:
            self.last_hour = current_hour
        
        # Check if we've moved to a new hour
        if current_hour != self.last_hour:
            self.last_hour = current_hour
            
            # Get the previous hour's OHLC
            # Look back to find bars from the previous hour
            prev_hour = current_hour - pd.Timedelta(hours=1)
            
            # Find all bars in the previous hour
            prev_hour_start = prev_hour
            prev_hour_end = current_hour
            
            hour_bars = []
            for i in range(len(self.data) - 1, -1, -1):
                bar_time = pd.Timestamp(self.data.index[i])
                if prev_hour_start <= bar_time < prev_hour_end:
                    hour_bars.append(i)
                elif bar_time < prev_hour_start:
                    break
            
            if len(hour_bars) > 0:
                hour_bars.reverse()
                hour_highs = [self.data.High[i] for i in hour_bars]
                hour_lows = [self.data.Low[i] for i in hour_bars]
                
                self.hour_high = max(hour_highs)
                self.hour_low = min(hour_lows)
                self.hour_close = self.data.Close[hour_bars[-1]]
                
                # Calculate Pivot
                self.pivot = (self.hour_high + self.hour_low + self.hour_close) / 3
                
                # Raw BC & TC
                bc_raw = (self.hour_high + self.hour_low) / 2
                tc_raw = 2 * self.pivot - bc_raw
                
                # Ensure proper ordering
                self.bc = min(bc_raw, tc_raw)
                self.tc = max(bc_raw, tc_raw)
        
        # Trading logic based on CPR levels
        if self.pivot is not None:
            current_price = self.data.Close[-1]
            
            # Buy when price touches lower band (BC) with a small buffer
            if current_price <= self.bc and not self.position:
                self.buy()
            
            # Sell when price touches upper band (TC)
            elif current_price >= self.tc and self.position:
                self.sell()
            
            # Exit long if price goes below pivot
            elif current_price < self.pivot and self.position and self.position.is_long:
                self.sell()


