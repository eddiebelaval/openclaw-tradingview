    ext_bars = 10
    max_levels = 8

    def init(self):
        # Initialize storage for support/resistance levels
        self.sr_levels = []
        self.sr_types = []
        self.sr_times = []
        self.sr_broken = []
        
        # Calculate pivots on current timeframe using body highs/lows
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_p = pd.Series(self.data.Open)
        
        # Body highs and lows
        self.body_high = self.I(lambda: np.maximum(open_p.values, close.values))
        self.body_low = self.I(lambda: np.minimum(open_p.values, close.values))
        
        # Pivot high/low detection using rolling max/min
        self.pivot_length = self.piv_H1
        
        # Simple highest high and lowest low over pivot period
        self.highest = self.I(
            lambda: pd.Series(self.body_high).rolling(window=self.pivot_length*2+1, center=True).max()
        )
        self.lowest = self.I(
            lambda: pd.Series(self.body_low).rolling(window=self.pivot_length*2+1, center=True).min()
        )

    def next(self):
        # Trading logic based on support/resistance levels
        current_price = self.data.Close[-1]
        
        # Detect pivot highs (resistance)
        if len(self) > self.pivot_length * 2 + 2:
            if (self.body_high[-self.pivot_length] == self.highest[-self.pivot_length] and 
                self.body_high[-self.pivot_length] != self.body_high[-1]):
                
                pivot_price = self.body_high[-self.pivot_length]
                
                # Buy when price breaks above resistance
                if current_price > pivot_price and self.data.Close[-2] <= pivot_price:
                    if not self.position:
                        self.buy()
        
        # Detect pivot lows (support)
        if len(self) > self.pivot_length * 2 + 2:
            if (self.body_low[-self.pivot_length] == self.lowest[-self.pivot_length] and 
                self.body_low[-self.pivot_length] != self.body_low[-1]):
                
                pivot_price = self.body_low[-self.pivot_length]
                
                # Sell when price breaks below support
                if current_price < pivot_price and self.data.Close[-2] >= pivot_price:
                    if self.position:
                        self.position.close()
        
        # Risk management: exit if price moves significantly against position
        if self.position:
            if self.position.is_long:
                # Exit long if price falls below recent support
                if len(self.lowest) > 0 and current_price < self.lowest[-1]:
                    self.position.close()
            else:
                # Exit short if price rises above recent resistance
                if len(self.highest) > 0 and current_price > self.highest[-1]:
                    self.position.close()


