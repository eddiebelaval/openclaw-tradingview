import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA parameters
    ema1_len = 20
    ema2_len = 50
    ema3_len = 100
    ema4_len = 200
    
    # Squeeze Momentum parameters
    bb_length = 20
    bb_mult = 2.0
    kc_length = 20
    kc_mult = 1.5
    use_true_range = True
    sqz_height_pct = 25.0
    sqz_pos_pct = 15.0
    
    # ADX / DMI parameters
    adx_len = 14
    di_len = 14
    key_val = 23
    
    # Signal parameters
    use_adx_filter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema1 = self.I(pta.ema, close, length=self.ema1_len)
        self.ema2 = self.I(pta.ema, close, length=self.ema2_len)
        self.ema3 = self.I(pta.ema, close, length=self.ema3_len)
        self.ema4 = self.I(pta.ema, close, length=self.ema4_len)
        
        # Squeeze Momentum calculation
        basis = self.I(pta.sma, close, length=self.bb_length)
        dev = self.I(lambda: self.bb_mult * close.rolling(self.bb_length).std())
        upper_bb = self.I(lambda: basis[-1] + dev[-1] if len(basis) > 0 and len(dev) > 0 else np.nan for _ in range(len(close)))
        lower_bb = self.I(lambda: basis[-1] - dev[-1] if len(basis) > 0 and len(dev) > 0 else np.nan for _ in range(len(close)))
        
        ma_kc = self.I(pta.sma, close, length=self.kc_length)
        
        # True Range or High-Low
        def calc_range():
            if self.use_true_range:
                return pta.tr(high, low, close)
            else:
                return high - low
        
        range_sqz = self.I(calc_range)
        rangema = self.I(pta.sma, range_sqz, length=self.kc_length)
        
        upper_kc = self.I(lambda: ma_kc[-1] + rangema[-1] * self.kc_mult if len(ma_kc) > 0 and len(rangema) > 0 else np.nan for _ in range(len(close)))
        lower_kc = self.I(lambda: ma_kc[-1] - rangema[-1] * self.kc_mult if len(ma_kc) > 0 and len(rangema) > 0 else np.nan for _ in range(len(close)))
        
        # Squeeze momentum value
        highest_high = self.I(lambda: high.rolling(self.kc_length).max())
        lowest_low = self.I(lambda: low.rolling(self.kc_length).min())
        avg_hl = self.I(lambda: (highest_high + lowest_low) / 2)
        mid_line = self.I(lambda: ma_kc)
        momentum_raw = self.I(lambda: close - (avg_hl + mid_line) / 2)
        
        def linreg_calc(src, length):
            if len(src) < length:
                return src
            result = []
            for i in range(len(src)):
                if i < length - 1:
                    result.append(np.nan)
                else:
                    subset = src[i - length + 1:i + 1]
                    x = np.arange(length)
                    if len(subset) == length:
                        z = np.polyfit(x, subset, 1)
                        result.append(z[0] * (length - 1) + z[1])
                    else:
                        result.append(np.nan)
            return pd.Series(result, index=src.index)
        
        self.sqz_val_raw = self.I(lambda: linreg_calc(momentum_raw, self.kc_length))
        
        # ADX / DMI calculation
        def calc_dirmov(length):
            up = high.diff()
            down = -low.diff()
            tr = pta.tr(high, low, close)
            tr_rma = pta.rma(tr, length)
            
            plus_raw = np.where((up > down) & (up > 0), up, 0)
            minus_raw = np.where((down > up) & (down > 0), down, 0)
            
            plus = 100 * pta.rma(pd.Series(plus_raw, index=close.index), length) / tr_rma
            minus = 100 * pta.rma(pd.Series(minus_raw, index=close.index), length) / tr_rma
            
            return plus.fillna(0), minus.fillna(0)
        
        plus_di, minus_di = calc_dirmov(self.di_len)
        self.plus_di = self.I(lambda: plus_di)
        self.minus_di = self.I(lambda: minus_di)
        
        def calc_adx(di_length, adx_length):
            plus, minus = calc_dirmov(di_length)
            sum_di = plus + minus
            di_diff = np.abs(plus - minus)
            di_sum = np.where(sum_di == 0, 1, sum_di)
            adx_raw = 100 * di_diff / di_sum
            adx = pta.rma(pd.Series(adx_raw, index=close.index), adx_length)
            return adx.fillna(0)
        
        self.adx = self.I(lambda: calc_adx(self.di_len, self.adx_len))
        
        # Squeeze state tracking
        self.sqz_on_prev = False

