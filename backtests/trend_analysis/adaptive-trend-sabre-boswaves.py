import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_type = "HMA"
    ma_len = 34
    trail_factor = 3.25
    snap_thresh = 2.0
    level_buffer = 0.25
    max_levels = 8
    show_retests = True
    retest_cd = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate MA based on type
        if self.ma_type == "EMA":
            self.ma = self.I(pta.ema, close, length=self.ma_len)
        elif self.ma_type == "SMA":
            self.ma = self.I(pta.sma, close, length=self.ma_len)
        elif self.ma_type == "WMA":
            self.ma = self.I(pta.wma, close, length=self.ma_len)
        elif self.ma_type == "HMA":
            self.ma = self.I(pta.hma, close, length=self.ma_len)
        elif self.ma_type == "DEMA":
            self.ma = self.I(pta.dema, close, length=self.ma_len)
        elif self.ma_type == "VWMA":
            volume = pd.Series(self.data.Volume)
            self.ma = self.I(pta.vwma, close, volume, length=self.ma_len)
        elif self.ma_type == "ALMA":
            self.ma = self.I(pta.alma, close, length=self.ma_len, offset=0.85, sigma=6)
        elif self.ma_type == "LSMA":
            self.ma = self.I(pta.linreg, close, length=self.ma_len)
        else:
            self.ma = self.I(pta.ema, close, length=self.ma_len)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Tension
        self.tension = self.I(lambda: (close - self.ma) / (self.atr + 0.0001))
        
        # Trail tracking
        self.trail_var = None
        self.trend_var = None
        self.last_retest_bar = 0
        self.bull_signal_flag = False
        self.bear_signal_flag = False
        self.bull_retest_flag = False
        self.bear_retest_flag = False

    def next(self):
        if len(self.data) < self.ma_len + 5:
            return
        
        close_val = self.data.Close[-1]
        ma_val = self.ma[-1]
        atr_val = self.atr[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        tension_val = self.tension[-1]
        
        if pd.isna(ma_val) or pd.isna(atr_val) or pd.isna(tension_val):
            return
        
        # Initialize trail and trend
        if self.trail_var is None:
            self.trail_var = ma_val - atr_val * self.trail_factor if close_val > ma_val else ma_val + atr_val * self.trail_factor
            self.trend_var = 1 if close_val > ma_val else -1
        
        # Calculate raw levels
        raw_up = ma_val - atr_val * self.trail_factor
        raw_dn = ma_val + atr_val * self.trail_factor
        
        # Update trail based on trend
        prev_trend = self.trend_var
        
        if self.trend_var == 1:
            self.trail_var = max(raw_up, self.trail_var)
            if close_val < self.trail_var:
                self.trend_var = -1
                self.trail_var = raw_dn
        else:
            self.trail_var = min(raw_dn, self.trail_var)
            if close_val > self.trail_var:
                self.trend_var = 1
                self.trail_var = raw_up
        
        # Signals on trend change
        self.bull_signal_flag = (self.trend_var == 1 and prev_trend == -1)
        self.bear_signal_flag = (self.trend_var == -1 and prev_trend == 1)
        
        # Retest detection
        self.bull_retest_flag = False
        self.bear_retest_flag = False
        
        if self.show_retests:
            bars_since_retest = len(self.data) - self.last_retest_bar
            if bars_since_retest > self.retest_cd:
                if self.trend_var == 1 and low_val <= self.trail_var and close_val > self.trail_var:
                    self.bull_retest_flag = True
                    self.last_retest_bar = len(self.data)
                elif self.trend_var == -1 and high_val >= self.trail_var and close_val < self.trail_var:
                    self.bear_retest_flag = True
                    self.last_retest_bar = len(self.data)
        
        # Trading logic
        if self.bull_signal_flag or self.bull_retest_flag:
            if not self.position:
                self.buy()
        elif self.bear_signal_flag or self.bear_retest_flag:
            if self.position:
                self.position.close()


