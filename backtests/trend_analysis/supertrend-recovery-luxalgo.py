import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 10
    multiplierInput = 3.0
    alphaInput = 5.0
    thresholdInput = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.lengthInput)
        
        self.stBand = None
        self.switchPrice = None
        self.trend = 1
        self.prev_trend = 1

    def next(self):
        if len(self.data) < self.lengthInput:
            return
        
        atr_val = self.atr[-1]
        if atr_val is None or np.isnan(atr_val):
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        src = (high + low) / 2.0
        
        alpha = self.alphaInput / 100.0
        upperBase = src + self.multiplierInput * atr_val
        lowerBase = src - self.multiplierInput * atr_val
        
        deviation = self.thresholdInput * atr_val
        
        if self.switchPrice is None:
            self.switchPrice = close
        
        isAtLoss = (self.trend == 1 and (self.switchPrice - close) > deviation) or \
                   (self.trend == -1 and (close - self.switchPrice) > deviation)
        
