import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        # This is a Fibonacci ABC pattern indicator that displays harmonic levels
        # It does not generate buy/sell signals by itself
        # For backtesting purposes, we'll implement a simple trend-following strategy
        # based on price proximity to key Fibonacci levels
        
        if len(self.data) < 20:
            return
        
        close = self.data.Close[-1]
        
        # Simple logic: buy on trend up, sell on trend down
        # Using a simple 20-bar SMA as trend reference
        sma20 = np.mean(self.data.Close[-20:])
        
        if close > sma20 and not self.position:
            self.buy()
        elif close < sma20 and self.position:
            self.sell()


