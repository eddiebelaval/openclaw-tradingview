import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate daily-based indicators
        self.ema20 = self.I(lambda: pta.ema(close, length=20) or pd.Series(0, index=close.index))
        self.sma50 = self.I(lambda: pta.sma(close, length=50) or pd.Series(0, index=close.index))
        self.sma200 = self.I(lambda: pta.sma(close, length=200) or pd.Series(0, index=close.index))
        
        # VWAP calculation
        self.vwap = self.I(lambda: pta.vwap(high, low, close, volume) or pd.Series(0, index=close.index))

    def next(self):
        # Buy when price crosses above EMA20 and is above SMA50 and SMA200
        if len(self.data) > 1:
            if (self.data.Close[-1] > self.ema20[-1] and 
                self.data.Close[-2] <= self.ema20[-2] and
                self.ema20[-1] > self.sma50[-1] and
                self.sma50[-1] > self.sma200[-1]):
                self.buy()
            
            # Sell when price crosses below SMA50
            if (self.data.Close[-1] < self.sma50[-1] and 
                self.data.Close[-2] >= self.sma50[-2]):
                self.sell()