import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length_period = 14
    mixed_strategy_len = 21
    nash_threshold = 0.65

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # RSI for momentum
        self.rsi = self.I(lambda: pta.rsi(close, length=self.length_period) or pd.Series(50, index=close.index))

        # ATR for volatility
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.length_period) or pd.Series(0, index=close.index))

        # SMA for average volume
        self.avg_volume = self.I(lambda: pta.sma(volume, length=self.length_period) or pd.Series(volume.iloc[0], index=volume.index))

        # Price change
        self.price_change = self.I(lambda: close.pct_change() * 100 or pd.Series(0, index=close.index))

        # EMA for bullish frequency
        self.bullish_freq = self.I(lambda: pta.ema((close > close.shift(1)).astype(float), length=self.length_period) or pd.Series(0.5, index=close.index))

        # Utility differential
        self.utility_diff = self.I(self._calc_utility_diff, close, high, low, volume)

        # Replicator dynamics
        self.replicator = self.I(self._calc_replicator, close)

        # Minimax
        self.minimax = self.I(self._calc_minimax, close)

        # Best response and confidence
        self.best_response = self.I(self._calc_best_response, close, high, low, volume)

        # Composite score
        self.composite_score = self.I(self._calc_composite_score, close, high, low, volume)

    def _calc_utility_diff(self, close, high, low, volume):
        result = []
        close_series = pd.Series(close)
        high_series = pd.Series(high)
        low_series = pd.Series(low)
        volume_series = pd.Series(volume)

        for i in range(len(close)):
            if i < self.length_period:
                result.append(0)
                continue

            momentum = pta.rsi(close_series[:i+1], length=self.length_period)
            if momentum is None or len(momentum) == 0:
                result.append(0)
                continue
            momentum_val = momentum.iloc[-1]

            atr_val = pta.atr(high_series[:i+1], low_series[:i+1], close_series[:i+1], length=self.length_period)
            if atr_val is None or len(atr_val) == 0:
                result.append(0)
                continue
            atr_val = atr_val.iloc[-1]

            volatility = (atr_val / close[i] * 100) if close[i] != 0 else 0.0001

            agg_payoff = (momentum_val - 50) / volatility if volatility > 0 else 0
            def_payoff = (50 - momentum_val) / volatility if volatility > 0 else 0

            eu_buyer = agg_payoff
            eu_seller = def_payoff

            utility_diff = abs(eu_buyer - eu_seller)
            result.append(utility_diff)

        return pd.Series(result, index=close.index)

    def _calc_replicator(self, close):
        result = []
        close_series = pd.Series(close)

        for i in range(len(close)):
            if i < self.length_period:
                result.append(0)
                continue

            bullish = (close_series[:i+1] > close_series[:i+1].shift(1)).astype(float)
            bullish_freq = pta.ema(bullish, length=self.length_period)
            if bullish_freq is None or len(bullish_freq) == 0:
                result.append(0)
                continue
            bullish_freq_val = bullish_freq.iloc[-1]

            rsi_val = pta.rsi(close_series[:i+1], length=self.length_period)
            if rsi_val is None or len(rsi_val) == 0:
                result.append(0)
                continue
            rsi_val = rsi_val.iloc[-1]

            bull_fitness = rsi_val / 100.0
            bear_fitness = 1.0 - bull_fitness
            avg_fitness = bullish_freq_val * bull_fitness + (1.0 - bullish_freq_val) * bear_fitness

            dx_dt = bullish_freq_val * (bull_fitness - avg_fitness)
            result.append(dx_dt)

        return pd.Series(result, index=close.index)

    def _calc_minimax(self, close):
        result = []
        close_series = pd.Series(close)

        for i in range(len(close)):
            if i < self.mixed_strategy_len:
                result.append(1.0)
                continue

            wins = 0.0
            losses = 0.0

            for j in range(1, min(self.mixed_strategy_len + 1, i + 1)):
                if i - j >= 0:
                    returns = (close_series.iloc[i-j] - close_series.iloc[i-j+1]) / close_series.iloc[i-j]
                    if returns > 0:
                        wins += returns
                    else:
                        losses += abs(returns)

            minimax_value = wins / losses if losses > 0 else 2.0
            result.append(minimax_value)

        return pd.Series(result, index=close.index)

    def _calc_best_response(self, close, high, low, volume):
        result = []
        close_series = pd.Series(close)
        high_series = pd.Series(high)
        low_series = pd.Series(low)
        volume_series = pd.Series(volume)

        for i in range(len(close)):
            if i < self.length_period:
                result.append(0)
                continue

            momentum = pta.rsi(close_series[:i+1], length=self.length_period)
            if momentum is None or len(momentum) == 0:
                result.append(0)
                continue
            momentum_val = momentum.iloc[-1]

            atr_val = pta.atr(high_series[:i+1], low_series[:i+1], close_series[:i+1], length=self.length_period)
            if atr_val is None or len(atr_val) == 0:
                result.append(0)
                continue
            atr_val = atr_val.iloc[-1]

            volatility = (atr_val / close[i] * 100) if close[i] != 0 else 0.0001

            agg_payoff = (momentum_val - 50) / volatility if volatility > 0 else 0
            def_payoff = (50 - momentum_val) / volatility if volatility > 0 else 0

            eu_buyer = agg_payoff
            eu_seller = def_payoff

            best_resp = 1 if eu_buyer > eu_seller else (-1 if eu_seller > eu_buyer else 0)
            result.append(best_resp)

        return pd.Series(result, index=close.index)

    def _calc_composite_score(self, close, high, low, volume):
        result = []
        close_series = pd.Series(close)

        for i in range(len(close)):
            if i < self.length_period:
                result.append(0)
                continue

            best_resp_val = self.best_response[-1] if i > 0 else 0
            replicator_val = self.replicator[-1] if i > 0 else 0
            minimax_val = self.minimax[-1] if i > 0 else 1.0

            confidence = abs(best_resp_val) if best_resp_val != 0 else 0.1
            composite = (best_resp_val * confidence * 0.4) + (replicator_val * 0.3) + ((minimax_val - 1.0) * 0.3)
            result.append(composite)

        return pd.Series(result, index=close.index)

    def next(self):
        if len(self) < self.length_period + 1:
            return

        composite = self.composite_score[-1]
        utility_diff = self.utility_diff[-1]
        max_utility = max(abs(self.utility_diff[-self.length_period:]) or [0.0001])
        equilibrium_score = 1.0 - (utility_diff / max_utility) if max_utility > 0 else 0.0
        is_nash = equilibrium_score > self.nash_threshold

        best_resp = self.best_response[-1]

        long_signal = composite > 0.5 and not is_nash and best_resp > 0
        short_signal = composite < -0.5 and not is_nash and best_resp < 0

        if long_signal and not self.position:
            self.buy()
        elif short_signal and self.position:
            self.position.close()


