class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        if len(self.data) < 5:
            return
        
        current_date = self.data.index[-1]
        current_dow = current_date.dayofweek
        
        if current_dow == 4 and len(self.data) >= 240:
            weekly_high = max(self.data.High[-240:])
            weekly_low = min(self.data.Low[-240:])
            
            if weekly_high > weekly_low:
                weekly_range = weekly_high - weekly_low
                retrace_20_pct = 0.20 * weekly_range
                retrace_30_pct = 0.30 * weekly_range
                
                lower_retrace_level_20 = weekly_low + retrace_20_pct
                lower_retrace_level_30 = weekly_low + retrace_30_pct
                upper_retrace_level_20 = weekly_high - retrace_20_pct
                upper_retrace_level_30 = weekly_high - retrace_30_pct
                
                if close <= lower_retrace_level_30 and not self.position:
                    self.buy()
                
                if self.position and close >= upper_retrace_level_30:
                    self.position.close()


