    def _get_pivot_high(self, high_data, current_idx, length):
        if current_idx < length * 2:
            return None
        
        pivot_idx = current_idx - length
        if pivot_idx < length or pivot_idx >= len(high_data) - length:
            return None
        
        pivot_val = high_data.iloc[pivot_idx]
        for i in range(1, length + 1):
            if high_data.iloc[pivot_idx - i] >= pivot_val or high_data.iloc[pivot_idx + i] >= pivot_val:
                return None
        
        return pivot_val

    def _get_pivot_low(self, low_data, current_idx, length):
        if current_idx < length * 2:
            return None
        
        pivot_idx = current_idx - length
        if pivot_idx < length or pivot_idx >= len(low_data) - length:
            return None
        
        pivot_val = low_data.iloc[pivot_idx]
        for i in range(1, length + 1):
            if low_data.iloc[pivot_idx - i] <= pivot_val or low_data.iloc[pivot_idx + i] <= pivot_val:
                return None
        
        return pivot_val

    def _init_profile(self, top_price, bottom_price, rows_count):
        step = (top_price - bottom_price) / rows_count
        profile = []
        for i in range(rows_count):
            p_bottom = bottom_price + (i * step)
            p_top = p_bottom + step
            profile.append({
                'price_top': p_top,
                'price_bottom': p_bottom,
                'volume_total': 0.0
            })
        return profile

    def _add_volume(self, range_data, b_high, b_low, b_vol):
        top_price = range_data['top_price']
        bottom_price = range_data['bottom_price']
        
        overlap_high = min(b_high, top_price)
        overlap_low = max(b_low, bottom_price)
        
        if b_high == b_low and b_high <= top_price and b_high >= bottom_price:
            for row in range_data['profile']:
                if b_high >= row['price_bottom'] and b_high <= row['price_top']:
                    row['volume_total'] += b_vol
                    range_data['total_volume'] += b_vol
                    break
        elif overlap_high > overlap_low:
            overlap_height = overlap_high - overlap_low
            total_height = b_high - b_low
            effective_vol = b_vol * (overlap_height / total_height) if total_height > 0 else b_vol
            
            for row in range_data['profile']:
                row_overlap_high = min(overlap_high, row['price_top'])
                row_overlap_low = max(overlap_low, row['price_bottom'])
                
                if row_overlap_high > row_overlap_low:
                    row_overlap_height = row_overlap_high - row_overlap_low
                    row_ratio = row_overlap_height / overlap_height
                    added_vol = effective_vol * row_ratio
                    
                    row['volume_total'] += added_vol
                    range_data['total_volume'] += added_vol

    def _calc_value_area(self, range_data, pct):
        if range_data['total_volume'] <= 0 or len(range_data['profile']) == 0:
            return
        
        max_vol = -1.0
        p_index = -1
        for i, row in enumerate(range_data['profile']):
            if row['volume_total'] > max_vol:
                max_vol = row['volume_total']
                p_index = i
        
        range_data['poc_index'] = p_index
        range_data['poc_volume'] = max_vol
        
        poc_row = range_data['profile'][p_index]
        range_data['poc_price'] = (poc_row['price_top'] + poc_row['price_bottom']) / 2.0
        
        target_vol = range_data['total_volume'] * (pct / 100.0)
        current_vol = max_vol
        up_index = p_index + 1
        down_index = p_index - 1
        
        while current_vol < target_vol and (up_index < len(range_data['profile']) or down_index >= 0):
            up_vol = range_data['profile'][up_index]['volume_total'] if up_index < len(range_data['profile']) else -1.0
            down_vol = range_data['profile'][down_index]['volume_total'] if down_index >= 0 else -1.0
            
            if up_vol == -1.0 and down_vol == -1.0:
                break
            
            add_up = False
            if up_vol > down_vol:
                add_up = True
            elif down_vol > up_vol:
                add_up = False
            else:
                dist_up = up_index - p_index
                dist_down = p_index - down_index
                add_up = dist_up <= dist_down
            
            if add_up:
                if current_vol + up_vol > target_vol and current_vol > max_vol:
                    break
                current_vol += up_vol
                up_index += 1
            else:
                if current_vol + down_vol > target_vol and current_vol > max_vol:
                    break
                current_vol += down_vol
                down_index -= 1
        
        final_up = min(up_index - 1, len(range_data['profile']) - 1)
        final_down = max(down_index + 1, 0)
        
        range_data['vah'] = range_data['profile'][final_up]['price_top']
        range_data['val'] = range_data['profile'][final_down]['price_bottom']


