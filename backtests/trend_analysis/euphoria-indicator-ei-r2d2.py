import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    n1 = 10
    n2 = 15
    sig_len = 3
    ob_level = 60
    os_level = -60

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # HLC3 source
        hlc3 = (high + low + close) / 3
        
        # Calculate ESA (EMA of source)
        esa = self.I(pta.ema, hlc3, length=self.n1)
        
        # Calculate deviation
        abs_diff = self.I(lambda: (hlc3 - esa).abs())
        d = self.I(pta.ema, abs_diff, length=self.n1)
        
        # Calculate CI (Commodity Index-like)
        ci = self.I(lambda: (hlc3 - esa) / (0.015 * d.fillna(0.015)))
        
        # Main euphoria score
        self.euphoria_score = self.I(pta.ema, ci, length=self.n2)
        
        # Signal line
        self.signal_line = self.I(pta.sma, self.euphoria_score, length=self.sig_len)

    def next(self):
        if len(self.data) < self.sig_len + self.n2 + self.n1:
            return
        
        current_euphoria = self.euphoria_score[-1]
        prev_euphoria = self.euphoria_score[-2] if len(self.euphoria_score) > 1 else current_euphoria
        signal = self.signal_line[-1]
        
        # Entry: Euphoria score crosses above overbought level
        if crossover(self.euphoria_score, self.ob_level):
            if not self.position:
                self.buy()
        
        # Exit: Peak detected (euphoria crosses below signal line while in overbought zone)
        if prev_euphoria >= self.ob_level and current_euphoria < signal:
            if self.position:
                self.position.close()
        
        # Entry: Euphoria score crosses below oversold level (reverse trade or hedge)
        if crossover(self.os_level, self.euphoria_score):
            if self.position:
                self.position.close()
        
        # Exit: Trough detected (euphoria crosses above signal line while in oversold zone)
        if prev_euphoria <= self.os_level and current_euphoria > signal:
            if not self.position:
                self.buy()


