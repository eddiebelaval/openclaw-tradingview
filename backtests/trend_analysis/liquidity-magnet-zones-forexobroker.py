import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Detection parameters
    swing_length = 5
    zone_buffer_pct = 0.05
    equal_thresh_pct = 0.1
    
    # Alert parameters
    approach_mult = 1.5
    
    def init(self):
        # Calculate ATR for distance measurements
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Calculate swing highs and lows
        def pivot_high(h, length):
            result = pd.Series(index=h.index, dtype=float)
            for i in range(len(h)):
                if i < length or i >= len(h) - length:
                    result.iloc[i] = np.nan
                else:
                    window = h.iloc[i - length:i + length + 1]
                    center = h.iloc[i]
                    if center == window.max() and i - length >= 0:
                        result.iloc[i] = center
                    else:
                        result.iloc[i] = np.nan
            return result
        
        def pivot_low(l, length):
            result = pd.Series(index=l.index, dtype=float)
            for i in range(len(l)):
                if i < length or i >= len(l) - length:
                    result.iloc[i] = np.nan
                else:
                    window = l.iloc[i - length:i + length + 1]
                    center = l.iloc[i]
                    if center == window.min() and i - length >= 0:
                        result.iloc[i] = center
                    else:
                        result.iloc[i] = np.nan
            return result
        
        self.swing_hi = self.I(lambda: pivot_high(high, self.swing_length))
        self.swing_lo = self.I(lambda: pivot_low(low, self.swing_length))
        
        # State tracking
        self.buy_zones = []
        self.sell_zones = []
        self.last_sweep_signal = False
        
    def next(self):
        if len(self) < self.swing_length + 1:
            return
        
        current_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        
        # Detect buyside sweep (price breaks above swing high)
        swing_high = self.swing_hi[-1]
        swing_low = self.swing_lo[-1]
        
        buyside_sweep = False
        sellside_sweep = False
        
        # Buyside liquidity sweep detection
        if not np.isnan(swing_high) and current_high > swing_high:
            buyside_sweep = True
        
        # Sellside liquidity sweep detection
        if not np.isnan(swing_low) and current_low < swing_low:
            sellside_sweep = True
        
        # Trading logic based on liquidity sweeps
        if buyside_sweep and not self.position:
            # Liquidity sweep above swing high suggests bullish breakout
            self.buy()
        elif sellside_sweep and self.position:
            # Liquidity sweep below swing low suggests reversal or stop loss
            self.sell()
        
        # Additional logic: approach to liquidity zones
        if current_atr > 0:
            # If price approaches swing high from below, consider buying
            dist_to_high = swing_high - current_close if not np.isnan(swing_high) else float('inf')
            dist_to_low = current_close - swing_low if not np.isnan(swing_low) else float('inf')
            
            if dist_to_high > 0 and dist_to_high < current_atr * self.approach_mult:
                if not self.position:
                    self.buy()
            
            # If price approaches swing low from above, consider selling
            if dist_to_low > 0 and dist_to_low < current_atr * self.approach_mult:
                if self.position:
                    self.sell()
        
        # Exit on extreme reversals
        if len(self) > 20:
            if self.position and sellside_sweep:
                self.sell()


