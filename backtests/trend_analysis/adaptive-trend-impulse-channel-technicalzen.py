import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLen = 50
    basisLen = 21
    flipATR = 0.35
    contATR = 0.15
    confirmBars = 2
    cooldownBars = 1
    maxSegBars = 35
    detachATR = 1.25
    detachBars = 3
    basisBlend = 0.50
    stepATR = 0.50
    adverseSlopeATR = 0.015
    widthATR = 1.05
    widthStdMult = 1.00
    widthCapATR = 2.20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hl2 = (high + low) / 2

        self.atr_val = self.I(lambda: pta.atr(high, low, close, length=self.atrLen) or pd.Series(np.nan, index=close.index))
        self.basis = self.I(lambda: pta.ema(hl2, length=self.basisLen) or pd.Series(np.nan, index=close.index))
        self.spread = self.I(lambda: hl2.rolling(self.basisLen).std() or pd.Series(np.nan, index=close.index))

        self.segMid0 = np.nan
        self.segSlope = 0.0
        self.segWidth = np.nan
        self.segBar0 = 0
        self.segDir = 0
        self.segLock = 0
        self.upFlipStreak = 0
        self.dnFlipStreak = 0
        self.upContStreak = 0
        self.dnContStreak = 0
        self.detachStreak = 0

        self.in_position = False

    def next(self):
        if len(self.data) < max(self.atrLen, self.basisLen, self.detachBars) + 2:
            return

        bar_idx = len(self.data) - 1
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        hl2_val = (high + low) / 2

        atr_val = self.atr_val[-1] if len(self.atr_val) > 0 else np.nan
        basis = self.basis[-1] if len(self.basis) > 0 else np.nan
        spread = self.spread[-1] if len(self.spread) > 0 else np.nan

        if np.isnan(atr_val) or np.isnan(basis) or np.isnan(spread):
            return

        atr_val = max(atr_val, 0.0001)
        spread = max(spread, 0.0)

        if np.isnan(self.segMid0):
            basis_slope = basis - (self.basis[-2] if len(self.basis) > 1 else basis)
            init_dir = 1 if basis_slope > 0 else (-1 if basis_slope < 0 else 0)
            self.segMid0 = basis
            self.segSlope = 0.0
            self.segWidth = min(atr_val * self.widthATR + spread * self.widthStdMult, atr_val * self.widthCapATR)
            self.segBar0 = bar_idx
            self.segDir = init_dir
            self.segLock = 0

        age_pre = bar_idx - self.segBar0
        mid_pre = self.segMid0 + self.segSlope * age_pre
        width_pre = max(self.segWidth if not np.isnan(self.segWidth) else 0.0, atr_val * 0.25)
        upper_pre = mid_pre + width_pre
        lower_pre = mid_pre - width_pre

        basis_slope = basis - (self.basis[-2] if len(self.basis) > 1 else basis)

        up_flip_qual = self.segDir != 1 and close > upper_pre + atr_val * self.flipATR
        dn_flip_qual = self.segDir != -1 and close < lower_pre - atr_val * self.flipATR
        up_cont_qual = self.segDir == 1 and close > upper_pre + atr_val * self.contATR
        dn_cont_qual = self.segDir == -1 and close < lower_pre - atr_val * self.contATR

        self.upFlipStreak = self.upFlipStreak + 1 if up_flip_qual else 0
        self.dnFlipStreak = self.dnFlipStreak + 1 if dn_flip_qual else 0
        self.upContStreak = self.upContStreak + 1 if up_cont_qual else 0
        self.dnContStreak = self.dnContStreak + 1 if dn_cont_qual else 0

        detached_now = abs(basis - mid_pre) > atr_val * self.detachATR
        self.detachStreak = self.detachStreak + 1 if detached_now else 0

        flip_up = self.segLock <= 0 and self.upFlipStreak >= self.confirmBars
        flip_dn = self.segLock <= 0 and self.dnFlipStreak >= self.confirmBars
        cont_up = self.segLock <= 0 and self.upContStreak >= self.confirmBars
        cont_dn = self.segLock <= 0 and self.dnContStreak >= self.confirmBars

        stale = age_pre >= self.maxSegBars
        refresh = self.segLock <= 0 and not (flip_up or flip_dn or cont_up or cont_dn) and (stale or self.detachStreak >= self.detachBars)

        event_type = 0
        if flip_up:
            event_type = 1
        elif flip_dn:
            event_type = -1
        elif cont_up:
            event_type = 2
        elif cont_dn:
            event_type = -2
        elif refresh:
            event_type = 3

        did_event = event_type != 0
        prev_dir = self.segDir

        if did_event:
            if event_type == 1:
                new_dir = 1
            elif event_type == -1:
                new_dir = -1
            elif event_type == 2:
                new_dir = 1
            elif event_type == -2:
                new_dir = -1
            else:
                new_dir = self.segDir if self.segDir != 0 else (1 if basis_slope >= 0 else -1)

            is_lead = True
            if is_lead:
                anchor_base = close
                step_size = 0.0 if event_type == 3 else atr_val * self.stepATR
                new_mid0 = anchor_base - new_dir * step_size
            else:
                anchor_base = mid_pre + self.basisBlend * (basis - mid_pre)
                step_size = 0.0 if event_type == 3 else atr_val * self.stepATR
                new_mid0 = anchor_base + new_dir * step_size

            slope_mag = atr_val * self.adverseSlopeATR
            new_slope = -new_dir * slope_mag
            new_width = min(atr_val * self.widthATR + spread * self.widthStdMult, atr_val * self.widthCapATR)

            self.segMid0 = new_mid0
            self.segSlope = new_slope
            self.segWidth = new_width
            self.segBar0 = bar_idx
            self.segDir = new_dir
            self.segLock = self.cooldownBars
            self.upFlipStreak = 0
            self.dnFlipStreak = 0
            self.upContStreak = 0
            self.dnContStreak = 0
            self.detachStreak = 0
        else:
            self.segLock = max(self.segLock - 1, 0)

        age = bar_idx - self.segBar0
        mid = self.segMid0 + self.segSlope * age
        width = max(self.segWidth if not np.isnan(self.segWidth) else 0.0, atr_val * 0.25)
        upper = mid + width
        lower = mid - width

        bull_regime_flip = did_event and event_type == 1 and prev_dir != 1
        bear_regime_flip = did_event and event_type == -1 and prev_dir != -1
        bull_step = did_event and event_type == 2
        bear_step = did_event and event_type == -2

        cross_lower = crossover(low, lower) if len(self.data) > 1 else False
        cross_upper = crossover(high, upper) if len(self.data) > 1 else False

        retest_long = self.segDir == 1 and cross_lower
        retest_short = self.segDir == -1 and cross_upper

        if bull_regime_flip or bull_step:
            if not self.in_position:
                self.buy()
                self.in_position = True
        elif bear_regime_flip or bear_step:
            if self.in_position:
                self.sell()
                self.in_position = False

        if retest_long and self.in_position:
            self.sell()
            self.in_position = False
        elif retest_short and not self.in_position:
            self.buy()
            self.in_position = True


