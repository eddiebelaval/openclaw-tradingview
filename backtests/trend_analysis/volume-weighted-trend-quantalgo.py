import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vwma_length = 34
    atr_multiplier = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate VWMA
        self.vwma_basis = self.I(pta.vwma, close, volume, length=self.vwma_length)
        
        # Calculate ATR
        self.atr_value = self.I(pta.atr, high, low, close, length=self.vwma_length)
        
        # Calculate bands
        self.upper_band = self.I(lambda: self.vwma_basis + self.atr_value * self.atr_multiplier)
        self.lower_band = self.I(lambda: self.vwma_basis - self.atr_value * self.atr_multiplier)
        
        # Track trend direction
        self.trend_direction = 0
        self.prev_trend = 0

    def next(self):
        if len(self.data.Close) < self.vwma_length + 1:
            return
        
        current_close = self.data.Close[-1]
        current_upper = self.upper_band[-1]
        current_lower = self.lower_band[-1]
        
        # Update trend direction
        if current_close > current_upper:
            self.trend_direction = 1
        elif current_close < current_lower:
            self.trend_direction = -1
        
        # Detect trend changes
        trend_turned_bullish = (self.trend_direction == 1 and self.prev_trend != 1)
        trend_turned_bearish = (self.trend_direction == -1 and self.prev_trend != -1)
        
        # Trading logic
        if trend_turned_bullish:
            if self.position:
                self.position.close()
            self.buy()
        elif trend_turned_bearish:
            if self.position:
                self.position.close()
        
        self.prev_trend = self.trend_direction


