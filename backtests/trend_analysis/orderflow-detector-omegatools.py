import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        
        # Volume calculations
        self.volma = self.I(pta.sma, volume, length=21)
        self.maxvol = self.I(lambda: volume.rolling(window=21).max())
        self.vol_stdev = self.I(pta.stdev, volume, length=21)
        
        # Lowest low and highest high (shifted by 1)
        self.ll = self.I(lambda: low.shift(1).rolling(window=11).min())
        self.hh = self.I(lambda: high.shift(1).rolling(window=11).max())
        
        # High wick and low wick calculations
        high_wick_raw = high - np.maximum(close, open_)
        low_wick_raw = np.minimum(close, open_) - low
        self.high_wick = self.I(pta.sma, high_wick_raw, length=7)
        self.low_wick = self.I(pta.sma, low_wick_raw, length=7)
        
        # True range
        tr = high - low
        self.trma = self.I(pta.sma, tr, length=21)
        
        # ATR for positioning
        self.atr = self.I(pta.atr, high, low, close, length=21)
        
        # Delta calculations
        up_vol = volume.where(close > open_, 0)
        dn_vol = volume.where(close < open_, 0)
        self.up_vol_sum = self.I(lambda: up_vol.cumsum())
        self.dn_vol_sum = self.I(lambda: dn_vol.cumsum())
        
        # Delta and resistance
        self.delta = self.I(lambda: self.up_vol_sum - self.dn_vol_sum)
        self.delta_stdev = self.I(pta.stdev, self.delta, length=21)
        
        # Range metric
        rng = (np.abs(close - open_) * 2 - (high - low) + np.maximum(close - low, high - close)) / 3
        self.avgrng = self.I(pta.sma, rng, length=21)
        self.rangex = self.I(lambda: rng / (self.avgrng + 0.0001))
        self.resistance = self.I(lambda: (np.abs(self.delta) / (self.delta_stdev + 0.0001)) / (self.rangex + 0.0001))
        
        self.high_thresh = 3
        self.low_thresh = 0.5

    def next(self):
        # Access current values
        if len(self.data) < 11:
            return
            
        deltaz = abs(self.delta[-1]) if self.delta[-1] is not None else 0
        resistance = self.resistance[-1] if self.resistance[-1] is not None else 0
        
        # Thresholds
        high_delta = deltaz > self.high_thresh
        low_delta = deltaz > self.low_thresh
        
        # Simple trading logic based on delta and resistance
        # Buy on high positive delta with low resistance
        if high_delta and self.delta[-1] > 0 and resistance < 1:
            if not self.position:
                self.buy()
        
        # Sell on high negative delta with low resistance
        elif high_delta and self.delta[-1] < 0 and resistance < 1:
            if self.position:
                self.position.close()
        
        # Exit on resistance spike
        elif resistance > 2:
            if self.position:
                self.position.close()


