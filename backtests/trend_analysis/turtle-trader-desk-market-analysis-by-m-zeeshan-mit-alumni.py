import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.fast_ema = self.I(pta.ema, close, length=34)
        self.slow_ema = self.I(pta.ema, close, length=89)
        self.atr = self.I(pta.atr, high, low, close, length=14)
        self.atr_ma = self.I(pta.sma, self.atr, length=14)
        self.vol_ma = self.I(pta.sma, volume, length=20)
        
        # Pivot highs and lows
        self.pivot_high = self.I(lambda: self._pivot_high(high, 20))
        self.pivot_low = self.I(lambda: self._pivot_low(low, 20))
        
        # Recent swing levels
        self.recent_high = self.I(lambda: high.rolling(20).max())
        self.recent_low = self.I(lambda: low.rolling(20).min())
        
    def _pivot_high(self, high_series, period):
        result = pd.Series(index=high_series.index, dtype=float)
        for i in range(period, len(high_series) - period):
            if high_series.iloc[i] == high_series.iloc[i-period:i+period+1].max():
                result.iloc[i] = high_series.iloc[i]
        return result
    
    def _pivot_low(self, low_series, period):
        result = pd.Series(index=low_series.index, dtype=float)
        for i in range(period, len(low_series) - period):
            if low_series.iloc[i] == low_series.iloc[i-period:i+period+1].min():
                result.iloc[i] = low_series.iloc[i]
        return result

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_ = self.data.Open[-1]
        volume = self.data.Volume[-1]
        
        fast = self.fast_ema[-1]
        slow = self.slow_ema[-1]
        atr = self.atr[-1]
        atr_ma = self.atr_ma[-1]
        vol_ma = self.vol_ma[-1]
        recent_high = self.recent_high[-1]
        recent_low = self.recent_low[-1]
        
        # Trend conditions
        ema_bull = fast > slow
        ema_bear = fast < slow
