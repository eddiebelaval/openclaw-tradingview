        prev_low = self.data.Low[-2] if len(self.data.Low) > 1 else low
        prev_range = prev_high - prev_low
        
        bullish_sweep = (low < prev_low and upper_wick <= cande_range * 0.3 and 
                        volume > prev_volume and close > open_ and prev_close < prev_open)
        bearish_sweep = (high > prev_high and lower_wick <= cande_range * 0.3 and 
                        volume > prev_volume and close < open_ and prev_close > prev_open)
        
