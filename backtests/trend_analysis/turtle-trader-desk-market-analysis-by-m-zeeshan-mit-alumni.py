        slope_bear = fast < self.fast_ema[-2] if len(self.fast_ema) > 1 else False
        
        # Structure
        struct_bull = close > recent_low
        struct_bear = close < recent_high
        
        # Volatility conditions
        vol_exp = volume > vol_ma
        atr_exp = atr > atr_ma
        atr_compression = atr < atr_ma * 0.45
        slope_abs = abs(fast - self.fast_ema[-2]) if len(self.fast_ema) > 1 else 0
        flat_slope = slope_abs < atr * 0.1
        
        no_struct = not struct_bull and not struct_bear
        is_ranging = atr_compression and flat_slope and no_struct
        
        # Breakout conditions
        breakout_up = close > recent_high * 1.001
        breakout_down = close < recent_low * 0.999
        
        # Raw signals
        raw_bull_possible = (ema_bull and slope_bull and struct_bull and not is_ranging) or breakout_up
        raw_bear_possible = (ema_bear and slope_bear and struct_bear and not is_ranging) or breakout_down
        
        # Sweep logic
        cande_range = high - low
        lower_wick = min(open_, close) - low
        upper_wick = high - max(open_, close)
        
        prev_close = self.data.Close[-2] if len(self.data.Close) > 1 else close
        prev_open = self.data.Open[-2] if len(self.data.Open) > 1 else open_
        prev_volume = self.data.Volume[-2] if len(self.data.Volume) > 1 else volume
