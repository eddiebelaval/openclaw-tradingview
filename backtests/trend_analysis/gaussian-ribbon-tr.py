import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length_gaussian = 49
    factor_1 = 0.85
    sigma_1 = 6.0
    factor_2 = 0.55
    sigma_2 = 7.0
    ma_type = 'ALMA'

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate ALMA indicators
        if self.ma_type == 'ALMA':
            alma_1 = self.I(lambda: pta.alma(close, length=self.length_gaussian, offset=self.factor_1, sigma=self.sigma_1) or pd.Series(close.iloc[-1], index=close.index))
            alma_2 = self.I(lambda: pta.alma(close, length=self.length_gaussian, offset=self.factor_2, sigma=self.sigma_2) or pd.Series(close.iloc[-1], index=close.index))
        else:
            alma_1 = self.I(lambda: pta.alma(close, length=self.length_gaussian, offset=self.factor_1, sigma=self.sigma_1) or pd.Series(close.iloc[-1], index=close.index))
            alma_2 = self.I(lambda: pta.alma(close, length=self.length_gaussian, offset=self.factor_2, sigma=self.sigma_2) or pd.Series(close.iloc[-1], index=close.index))
        
        self.alma_1 = alma_1
        self.alma_2 = alma_2

    def next(self):
        if len(self.data) < self.length_gaussian + 5:
            return
        
        # Check for crossover conditions
        if crossover(self.alma_1, self.alma_2):
            if not self.position:
                self.buy()
        elif crossover(self.alma_2, self.alma_1):
            if self.position:
                self.position.close()


