import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smaLen = 9
    thresholdMode = "Absolute"
    inchAbove = 4.0
    inchBelow = 4.0
    atrLen = 4
    maxBars = 2
    minBarsBetween = 7
    autoUniversal = True
    normMode = "ATR"
    normLookback = 100
    breakMult = 0.60
    bandMult = 0.40
    roundToTick = True
    pbBandMode = "ATR"
    pbBandValue = 0.25
    useReclaimExtreme = False
    useADXFilter = False
    diLen = 16
    adxSmoothing = 30
    adxMin = 18.0
    useSlopeFilter = False
    slopeLen = 10
    slopeMinMult = 0.20
    useNormFloor = True
    minNormTicks = 20
    enforceAlternation = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.sma = self.I(pta.sma, close, length=self.smaLen)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # ADX for filtering
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.diLen) if len(close) > self.diLen else None)
        self.adx = adx_result
        
        # Z-score calculation for normalization
        self.z_series = self.I(lambda: close - self.sma)
        self.z_std = self.I(lambda: (close - self.sma).rolling(self.normLookback).std())
        
        # Slope calculation
        self.slope = self.I(lambda: (self.sma - self.sma.shift(self.slopeLen)).abs())
        
        # Highest high and lowest low for extremes
        self.hi_lookback = self.I(lambda: high.rolling(self.maxBars + 1).max())
        self.lo_lookback = self.I(lambda: low.rolling(self.maxBars + 1).min())
        
        # State tracking
        self.in_buy = False
        self.pulled_buy = False
        self.fired_b = False
        self.start_b = None
        self.hi_b = None
        self.last_buy_bar = None
        
        self.in_sell = False
        self.pulled_sell = False
        self.fired_s = False
        self.start_s = None
        self.lo_s = None
        self.last_sell_bar = None
        
        self.last_signal = 0  # 1=buy, -1=sell, 0=none
        self.buy_signal_prev = False
        self.sell_signal_prev = False

    def next(self):
        idx = len(self.data) - 1
        
        sma_val = self.sma[-1]
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        
        # Calculate normalization unit
        z_std_raw = self.z_std[-1] if not np.isnan(self.z_std[-1]) else 0
        z_std_safe = max(z_std_raw, 0.0001)
        norm_unit_0 = atr_val if self.normMode == "ATR" else z_std_safe
        
        min_norm = self.minNormTicks * 0.0001
        norm_unit = max(norm_unit_0, min_norm) if self.useNormFloor else norm_unit_0
        
        # Effective thresholds
        eff_thr_above = self.breakMult * norm_unit if self.autoUniversal else self.inchAbove
        eff_thr_below = self.breakMult * norm_unit if self.autoUniversal else self.inchBelow
        eff_pb_band = self.bandMult * norm_unit if self.autoUniversal else self.pbBandValue
        
        # Regime filters
        trend_ok = True
        if self.useADXFilter:
            adx_val = self.adx[-1] if self.adx[-1] is not None and not np.isnan(self.adx[-1]) else 0
            trend_ok = adx_val >= self.adxMin
        
        slope_ok = True
        if self.useSlopeFilter:
            slope_val = self.slope[-1] if not np.isnan(self.slope[-1]) else 0
            slope_ok = slope_val >= self.slopeMinMult * norm_unit
        
        regime_ok = trend_ok and slope_ok
        
        # Alternation checks
        can_buy_by_alt = not self.enforceAlternation or (self.last_signal <= 0)
        can_sell_by_alt = not self.enforceAlternation or (self.last_signal >= 0)
        
        # === BUY FLOW ===
        if close_val < sma_val:
            self.in_buy = False
            self.pulled_buy = False
            self.fired_b = False
        
        if not self.in_buy and regime_ok and close_val > sma_val + eff_thr_above:
            self.in_buy = True
            self.pulled_buy = False
            self.fired_b = False
            self.start_b = idx
            self.hi_b = high_val
        
        if self.in_buy and not self.pulled_buy:
            self.hi_b = max(self.hi_b, high_val)
        
        if self.in_buy and self.start_b is not None and (idx - self.start_b > self.maxBars):
            self.in_buy = False
            self.pulled_buy = False
            self.fired_b = False
        
        buy_pulled = (self.in_buy and not self.pulled_buy and 
                     low_val <= sma_val + eff_pb_band and close_val > sma_val)
        if buy_pulled:
            self.pulled_buy = True
        
        buy_resume_ok = True
        if self.useReclaimExtreme and self.hi_b is not None:
            buy_resume_ok = close_val > self.hi_b
        
        buy_signal_raw = (self.in_buy and self.pulled_buy and not self.fired_b and
                         close_val > sma_val and close_val > open_val and
                         buy_resume_ok and
                         (self.start_b is None or idx - self.start_b <= self.maxBars) and
                         (self.last_buy_bar is None or idx - self.last_buy_bar >= self.minBarsBetween))
        
        buy_signal = buy_signal_raw and can_buy_by_alt
        
        if buy_signal:
            self.fired_b = True
            self.last_buy_bar = idx
            self.last_signal = 1
            self.buy()
        
        # === SELL FLOW ===
        if close_val > sma_val:
            self.in_sell = False
            self.pulled_sell = False
            self.fired_s = False
        
        if not self.in_sell and regime_ok and close_val < sma_val - eff_thr_below:
            self.in_sell = True
            self.pulled_sell = False
            self.fired_s = False
            self.start_s = idx
            self.lo_s = low_val
        
        if self.in_sell and not self.pulled_sell:
            self.lo_s = min(self.lo_s, low_val)
        
        if self.in_sell and self.start_s is not None and (idx - self.start_s > self.maxBars):
            self.in_sell = False
            self.pulled_sell = False
            self.fired_s = False
        
        sell_pulled = (self.in_sell and not self.pulled_sell and 
                      high_val >= sma_val - eff_pb_band and close_val < sma_val)
        if sell_pulled:
            self.pulled_sell = True
        
        sell_resume_ok = True
        if self.useReclaimExtreme and self.lo_s is not None:
            sell_resume_ok = close_val < self.lo_s
        
        sell_signal_raw = (self.in_sell and self.pulled_sell and not self.fired_s and
                          close_val < sma_val and close_val < open_val and
                          sell_resume_ok and
                          (self.start_s is None or idx - self.start_s <= self.maxBars) and
                          (self.last_sell_bar is None or idx - self.last_sell_bar >= self.minBarsBetween))
        
        sell_signal = sell_signal_raw and can_sell_by_alt
        
        if sell_signal:
            self.fired_s = True
            self.last_sell_bar = idx
            self.last_signal = -1
            self.sell()


