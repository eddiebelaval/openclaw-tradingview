import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    swing_len = 10
    internal_len = 5
    atr_len = 14
    vol_sma_len = 20
    
    def init(self):
        # Calculate ATR for analysis
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.vol_sma = self.I(pta.sma, volume, length=self.vol_sma_len)
        
        # Calculate pivot highs and lows using rolling max/min
        self.pivot_high = self.I(lambda: high.rolling(window=self.swing_len*2+1, center=True).max())
        self.pivot_low = self.I(lambda: low.rolling(window=self.swing_len*2+1, center=True).min())
        
        # Track swing structure
        self.swing_trend = 0  # 0=none, 1=bull, -1=bear
        self.last_swing_high = None
        self.last_swing_low = None
        self.swing_high_idx = None
        self.swing_low_idx = None
        
        # Track internal structure
        self.int_trend = 0
        self.last_int_high = None
        self.last_int_low = None
        self.int_high_idx = None
        self.int_low_idx = None
        
        # Order block tracking
        self.ob_list = []  # List of (type, price_top, price_bottom, bar_idx)
        self.max_obs = 5
        
        # FVG tracking
        self.fvg_list = []  # List of (type, price_top, price_bottom)
        self.max_fvgs = 5
        self.fvg_min_size = 0.0
        
        # Fibonacci tracking
        self.trail_high = None
        self.trail_low = None
        self.trail_high_idx = None
        self.trail_low_idx = None

    def next(self):
        if len(self.data) < self.swing_len * 3:
            return
        
        idx = len(self.data) - 1
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        current_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else (self.data.High[-1] - self.data.Low[-1])
        
        # Check for swing structure breaks (simplified pivot detection)
        # Detect higher highs and higher lows (bullish) or lower highs and lower lows (bearish)
        
        if len(self.data) > self.swing_len + 1:
            lookback_high = self.data.High[-self.swing_len-1:-1].max()
            lookback_low = self.data.Low[-self.swing_len-1:-1].min()
            
            # Bullish break of structure (close above previous resistance)
            if (self.last_swing_high is not None and 
                current_close > self.last_swing_high and 
                self.swing_trend != 1):
                
                self.swing_trend = 1
                self.last_swing_high = current_high
                self.swing_high_idx = idx
                self.last_swing_low = lookback_low
                self.swing_low_idx = idx - self.swing_len
                
                # Create order block on the break
                if len(self.ob_list) < self.max_obs:
                    # Find bearish candle before the bullish break
                    for i in range(1, min(11, len(self.data))):
                        if self.data.Open[-i] > self.data.Close[-i]:
                            ob_top = self.data.High[-i]
                            ob_bottom = self.data.Low[-i]
                            self.ob_list.insert(0, ('bull', ob_top, ob_bottom, idx - i))
                            break
            
            # Bearish break of structure (close below previous support)
            if (self.last_swing_low is not None and 
                current_close < self.last_swing_low and 
                self.swing_trend != -1):
                
                self.swing_trend = -1
                self.last_swing_low = current_low
                self.swing_low_idx = idx
                self.last_swing_high = lookback_high
                self.swing_high_idx = idx - self.swing_len
            
            # Initialize swing levels if not set
            if self.last_swing_high is None:
                self.last_swing_high = lookback_high
            if self.last_swing_low is None:
                self.last_swing_low = lookback_low
        
        # Fair Value Gap detection
        if len(self.data) > 2:
            # Bullish FVG: current low > 2 bars ago high
            if (current_low > self.data.High[-3] and 
                (current_low - self.data.High[-3]) > self.fvg_min_size):
                if len(self.fvg_list) < self.max_fvgs:
                    self.fvg_list.insert(0, ('bull', current_low, self.data.High[-3]))
            
            # Bearish FVG: current high < 2 bars ago low
            if (current_high < self.data.Low[-3] and 
                (self.data.Low[-3] - current_high) > self.fvg_min_size):
                if len(self.fvg_list) < self.max_fvgs:
                    self.fvg_list.insert(0, ('bear', self.data.Low[-3], current_high))
        
        # Update trailing highs/lows for Fibonacci
        if self.swing_trend == 1:
            if self.trail_high is None or current_high > self.trail_high:
                self.trail_high = current_high
                self.trail_high_idx = idx
        
        if self.swing_trend == -1:
            if self.trail_low is None or current_low < self.trail_low:
                self.trail_low = current_low
                self.trail_low_idx = idx
        
        # Trading logic based on swing structure breaks
        # Buy on bullish break of structure with confluence
        if self.swing_trend == 1 and not self.position:
            # Check for FVG confluence
            has_fvg = any(fvg[0] == 'bull' for fvg in self.fvg_list)
            
            # Check for volume confirmation
            vol_avg = self.vol_sma[-1] if not np.isnan(self.vol_sma[-1]) else 1
            has_vol = self.data.Volume[-1] > vol_avg * 1.5
            
            # Enter on structure break
            if has_fvg or has_vol:
                self.buy()
        
        # Sell on bearish break of structure
        if self.swing_trend == -1 and self.position:
            self.position.close()
        
        # Exit longs on bearish break
        if self.swing_trend == -1 and self.position and self.position.is_long:
            self.position.close()
        
        # Clean up old FVGs and OBs
        self.fvg_list = [fvg for fvg in self.fvg_list if len(self.data) - 50 < idx]
        self.ob_list = [ob for ob in self.ob_list if len(self.data) - 50 < idx]


