import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14
    zigzag_length = 21
    linear_reg_period = 140
    deviations_amount = 1.1
    lengthdiv = 21
    lengthright = 0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate RSI
        self.rsi = self.I(lambda: self._calculate_rsi(close))

        # Calculate pivot highs and lows
        self.ph = self.I(lambda: self._pivot_high(self.rsi, self.zigzag_length, self.zigzag_length))
        self.pl = self.I(lambda: self._pivot_low(self.rsi, self.zigzag_length, self.zigzag_length))

        self.ph_chart = self.I(lambda: self._pivot_high(close, self.lengthdiv, self.lengthright))
        self.pl_chart = self.I(lambda: self._pivot_low(close, self.lengthdiv, self.lengthright))

        # Track divergence signals
        self.last_ph_value = None
        self.last_ph_index = None
        self.last_pl_value = None
        self.last_pl_index = None
        self.last_ph_chart_value = None
        self.last_ph_chart_index = None
        self.last_pl_chart_value = None
        self.last_pl_chart_index = None

    def _calculate_rsi(self, close):
        deltas = close.diff()
        up = deltas.clip(lower=0)
        down = -deltas.clip(upper=0)

        rma_up = up.ewm(span=self.rsi_length, adjust=False).mean()
        rma_down = down.ewm(span=self.rsi_length, adjust=False).mean()

        rs = rma_up / rma_down
        rsi = 100 - (100 / (1 + rs))
        rsi = rsi.fillna(50)
        return rsi

    def _pivot_high(self, series, left_bars, right_bars):
        result = pd.Series(np.nan, index=series.index)
        for i in range(left_bars, len(series) - right_bars):
            if series.iloc[i] == series.iloc[i - left_bars:i + right_bars + 1].max():
                result.iloc[i] = series.iloc[i]
        return result

    def _pivot_low(self, series, left_bars, right_bars):
        result = pd.Series(np.nan, index=series.index)
        for i in range(left_bars, len(series) - right_bars):
            if series.iloc[i] == series.iloc[i - left_bars:i + right_bars + 1].min():
                result.iloc[i] = series.iloc[i]
        return result

    def next(self):
        current_idx = len(self.data) - 1

        # Track pivot highs on RSI
        if not np.isnan(self.ph[-1]):
            self.last_ph_value = self.rsi[-1]
            self.last_ph_index = current_idx

        # Track pivot lows on RSI
        if not np.isnan(self.pl[-1]):
            self.last_pl_value = self.rsi[-1]
            self.last_pl_index = current_idx

        # Track pivot highs on price
        if not np.isnan(self.ph_chart[-1]):
            self.last_ph_chart_value = self.data.Close[-1]
            self.last_ph_chart_index = current_idx

        # Track pivot lows on price
        if not np.isnan(self.pl_chart[-1]):
            self.last_pl_chart_value = self.data.Close[-1]
            self.last_pl_chart_index = current_idx

        # Bearish divergence (RSI HH, Price LH) - short signal
        if (self.last_ph_value is not None and self.rsi[-1] > self.last_ph_value and
            self.last_ph_chart_value is not None and self.data.Close[-1] < self.last_ph_chart_value):
            if not self.position:
                self.sell()

        # Bullish divergence (RSI LL, Price HL) - long signal
        if (self.last_pl_value is not None and self.rsi[-1] < self.last_pl_value and
            self.last_pl_chart_value is not None and self.data.Close[-1] > self.last_pl_chart_value):
            if not self.position:
                self.buy()

        # Exit on RSI overbought/oversold
        if self.position.is_long and self.rsi[-1] > 70:
            self.position.close()
        elif self.position.is_short and self.rsi[-1] < 30:
            self.position.close()


