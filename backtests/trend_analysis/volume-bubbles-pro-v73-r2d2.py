import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Z-Score Detection Parameters
    volume_ma_length = 50
    z_score_threshold = 2.0
    
    # VSA Parameters
    atr_length = 14
    enable_absorption = True
    
    # Offset Multiplier
    atr_offset_mult = 0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate Volume SMA and StDev
        self.vol_sma = self.I(pta.sma, volume, length=self.volume_ma_length)
        self.vol_stdev = self.I(
            lambda v=volume: v.rolling(window=self.volume_ma_length).std()
        )
        
        # Calculate Z-Score
        def calc_zscore(v=volume, sma=None, stdev=None):
            if sma is None or stdev is None:
                return pd.Series(0, index=v.index)
            result = pd.Series(0.0, index=v.index)
            for i in range(len(v)):
                if stdev.iloc[i] > 0:
                    result.iloc[i] = (v.iloc[i] - sma.iloc[i]) / stdev.iloc[i]
            return result
        
        self.z_score = self.I(calc_zscore)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Calculate Spread
        def calc_spread(h=high, l=low):
            return h - l
        
        self.spread = self.I(calc_spread)
        
        # Calculate Close Position (0.0 to 1.0)
        def calc_close_pos(h=high, l=low, c=close):
            result = pd.Series(0.5, index=c.index)
            for i in range(len(c)):
                if h.iloc[i] - l.iloc[i] > 0:
                    result.iloc[i] = (c.iloc[i] - l.iloc[i]) / (h.iloc[i] - l.iloc[i])
                else:
                    result.iloc[i] = 0.5
            return result
        
        self.close_pos = self.I(calc_close_pos)
        
        # Calculate Delta Volume Approximation
        def calc_delta_vol(v=volume, cp=None):
            if cp is None:
                return pd.Series(0, index=v.index)
            estimated_buy = v * cp
            estimated_sell = v * (1.0 - cp)
            return estimated_buy - estimated_sell
        
        self.delta_vol = self.I(calc_delta_vol)

    def next(self):
        # Safety check for sufficient data
        if len(self.data) < max(self.volume_ma_length, self.atr_length):
            return
        
        # Get current values
        z_score = self.z_score[-1]
        atr_val = self.atr[-1]
        spread = self.spread[-1]
        close_pos = self.close_pos[-1]
        delta_vol = self.delta_vol[-1]
        volume = self.data.Volume[-1]
        
