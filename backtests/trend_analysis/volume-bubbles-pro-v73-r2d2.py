        if z_score is None or pd.isna(z_score) or atr_val is None or pd.isna(atr_val):
            return
        
        if pd.isna(spread) or pd.isna(close_pos) or pd.isna(delta_vol):
            return
        
        # VSA Classifications
        is_high_volume = z_score >= self.z_score_threshold
        is_tight_spread = spread < (atr_val * 0.5)
        is_neutral_churn = close_pos >= 0.33 and close_pos <= 0.66
        is_absorption = self.enable_absorption and is_high_volume and (is_tight_spread or is_neutral_churn)
        
        # Trade Signals
        is_buy = (delta_vol > 0) and (close_pos > 0.5) and not is_absorption
        is_sell = (delta_vol < 0) and (close_pos < 0.5) and not is_absorption
        
        # Simple buy/sell logic
        # Buy on whale buy activity with positive delta
        if is_high_volume and is_buy:
            if not self.position:
                self.buy()
        
        # Sell on whale sell activity with negative delta
        elif is_high_volume and is_sell:
            if self.position:
                self.position.close()
        
        # Exit on absorption signals (potential reversals)
        elif is_absorption:
            if self.position:
                self.position.close()