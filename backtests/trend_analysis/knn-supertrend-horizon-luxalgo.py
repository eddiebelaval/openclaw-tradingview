import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # ML Settings
    neighborsK = 10
    windowSize = 500
    
    # Supertrend Settings
    atrLenInput = 10
    factorInput = 3.0
    
    # Noise Filter Settings
    smoothSource = True
    smoothLenVal = 10
    mlBuffer = 5.0
    
    # Rejection Signal Settings
    rejMult = 1.5
    bubbleGap = 5
    
    # Visual Settings
    smoothLen = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        
        # Smooth source if needed
        if self.smoothSource:
            self.src = self.I(lambda: pta.hma(close, length=self.smoothLenVal) or close)
        else:
            self.src = close
        
        # Calculate features
        self.f1 = self.I(lambda: pta.rsi(self.src, length=14) or pd.Series(50, index=close.index))
        
        # ATR-based volatility
        self.atr = self.I(lambda: pta.atr(high, low, close, length=14) or pd.Series(0, index=close.index))
        self.f2 = self.I(lambda: (self.atr / self.src * 100).fillna(0))
        
        # Supertrend calculation
        self.st_high = self.I(self._calculate_st_high, high, low, close)
        self.st_low = self.I(self._calculate_st_low, high, low, close)
        
        # ML Probability tracking
        self.mlProb = self.I(self._calculate_ml_prob, close, high, low, open_)
        self.smoothedProb = self.I(lambda: pta.ema(self.mlProb, length=self.smoothLen) or pd.Series(50, index=close.index))
        
        # ML trend state
        self.mlBullish = self.I(self._get_ml_bullish_state, self.smoothedProb)
        
        # Rejection detection
        self.bodySize = self.I(lambda: (close - open_).abs())
        self.upperWick = self.I(lambda: high - pd.concat([open_, close], axis=1).max(axis=1))
        self.lowerWick = self.I(lambda: pd.concat([open_, close], axis=1).min(axis=1) - low)
        
        self.lastBubbleBar = 0
        self.position_entered = False

    def _calculate_st_high(self, high, low, close):
        hl2 = (high + low) / 2
        atr = pta.atr(high, low, close, length=self.atrLenInput)
        if atr is None:
            atr = pd.Series(0, index=close.index)
        basic_ub = hl2 + self.factorInput * atr
        basic_lb = hl2 - self.factorInput * atr
        
        final_ub = pd.Series(index=close.index, dtype=float)
        final_lb = pd.Series(index=close.index, dtype=float)
        
        final_ub.iloc[0] = basic_ub.iloc[0]
        final_lb.iloc[0] = basic_lb.iloc[0]
        
        for i in range(1, len(close)):
            final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
            final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
        
        return final_ub

    def _calculate_st_low(self, high, low, close):
        hl2 = (high + low) / 2
        atr = pta.atr(high, low, close, length=self.atrLenInput)
        if atr is None:
            atr = pd.Series(0, index=close.index)
        basic_ub = hl2 + self.factorInput * atr
        basic_lb = hl2 - self.factorInput * atr
        
        final_ub = pd.Series(index=close.index, dtype=float)
        final_lb = pd.Series(index=close.index, dtype=float)
        
        final_ub.iloc[0] = basic_ub.iloc[0]
        final_lb.iloc[0] = basic_lb.iloc[0]
        
        for i in range(1, len(close)):
            final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
            final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
        
        return final_lb

    def _calculate_ml_prob(self, close, high, low, open_):
        f1 = pta.rsi(close, length=14)
        if f1 is None:
            f1 = pd.Series(50, index=close.index)
        atr = pta.atr(high, low, close, length=14)
        if atr is None:
            atr = pd.Series(0, index=close.index)
        f2 = (atr / close * 100).fillna(0)
        
        ml_prob = pd.Series(50.0, index=close.index)
        
        if len(close) > self.windowSize:
            for idx in range(self.windowSize, len(close)):
                current_f1 = f1.iloc[idx]
                current_f2 = f2.iloc[idx]
                
                window_start = max(0, idx - self.windowSize)
                window_f1 = f1.iloc[window_start:idx]
                window_f2 = f2.iloc[window_start:idx]
                
                distances = np.sqrt(
                    (current_f1 - window_f1) ** 2 + 
                    (current_f2 - window_f2) ** 2
                )
                
                k = min(self.neighborsK, len(distances))
                sorted_dists = np.sort(distances.values)
                threshold = sorted_dists[k - 1]
                
                neighbors_idx = np.where(distances <= threshold)[0]
                
                bull_votes = 0
                bear_votes = 0
                
                hl2_window = (high.iloc[window_start:idx] + low.iloc[window_start:idx]) / 2
                atr_window = pta.atr(high.iloc[window_start:idx], low.iloc[window_start:idx], 
                                     close.iloc[window_start:idx], length=self.atrLenInput)
                
                if atr_window is not None and len(atr_window) > 0:
                    basic_ub = hl2_window + self.factorInput * atr_window
                    basic_lb = hl2_window - self.factorInput * atr_window
                    
                    for n_idx in neighbors_idx:
                        actual_idx = window_start + n_idx
                        if actual_idx < idx:
                            st_val = basic_ub.iloc[n_idx] if close.iloc[actual_idx] > basic_lb.iloc[n_idx] else basic_lb.iloc[n_idx]
                            if st_val < close.iloc[actual_idx]:
                                bull_votes += 1
                            else:
                                bear_votes += 1
                
                total_votes = bull_votes + bear_votes
                if total_votes > 0:
                    ml_prob.iloc[idx] = (bull_votes / total_votes) * 100
        
        return ml_prob

    def _get_ml_bullish_state(self, smoothedProb):
        ml_bullish = pd.Series(False, index=smoothedProb.index)
        current_state = False
        
        for idx in range(len(smoothedProb)):
            if smoothedProb.iloc[idx] > 50 + self.mlBuffer:
                current_state = True
            elif smoothedProb.iloc[idx] < 50 - self.mlBuffer:
                current_state = False
            ml_bullish.iloc[idx] = current_state
        
        return ml_bullish

    def next(self):
        if len(self.data) < self.windowSize + 10:
            return
        
        current_ml_bullish = self.mlBullish[-1]
        current_st_high = self.st_high[-1]
        current_st_low = self.st_low[-1]
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        body_size = abs(self.data.Close[-1] - self.data.Open[-1])
        upper_wick = self.upperWick[-1]
        lower_wick = self.lowerWick[-1]
        
        # Entry conditions
        if not self.position:
            # Buy on bullish ML confirmation with lower wick rejection
            if current_ml_bullish and lower_wick > body_size * self.rejMult:
                self.buy()
                self.position_entered = True
            
            # Sell on bearish ML confirmation with upper wick rejection
            elif not current_ml_bullish and upper_wick > body_size * self.rejMult:
                self.sell()
                self.position_entered = True
        else:
            # Exit logic
            if self.position.is_long:
                # Exit long on bearish reversal or price breaking ST low
                if not current_ml_bullish or current_close < current_st_low:
                    self.position.close()
            else:
                # Exit short on bullish reversal or price breaking ST high
                if current_ml_bullish or current_close > current_st_high:
                    self.position.close()


