import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Indicator parameters
        basisLen = 50
        atrLen = 14
        atrMult = 2.0
        rsiLen = 14
        macdFast = 12
        macdSlow = 26
        macdSig = 9
        smoothLen = 8
        
        # Calculate basis (EMA)
        basis = self.I(pta.ema, close, length=basisLen)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=atrLen)
        
        # Calculate bands
        upBand = self.I(lambda: basis + atrMult * atr)
        dnBand = self.I(lambda: basis - atrMult * atr)
        
        # Impulse conditions
        self.impulseUp = self.I(lambda: (close > basis) & (close > upBand))
        self.impulseDn = self.I(lambda: (close < basis) & (close < dnBand))
        
        # Calculate RSI
        rsi = self.I(pta.rsi, close, length=rsiLen)
        
        # Calculate MACD components
        emaFast = self.I(pta.ema, close, length=macdFast)
        emaSlow = self.I(pta.ema, close, length=macdSlow)
        macdLine = self.I(lambda: emaFast - emaSlow)
        macdSigLn = self.I(pta.ema, macdLine, length=macdSig)
        macdHist = self.I(lambda: macdLine - macdSigLn)
        
        # Momentum conditions
        self.momUp = self.I(lambda: (rsi > 50) & (macdHist > 0))
        self.momDn = self.I(lambda: (rsi < 50) & (macdHist < 0))
        
        # Smoothed bands for visualization
        self.basisSmoothed = self.I(pta.ema, basis, length=smoothLen)
        self.upBandSmoothed = self.I(pta.ema, upBand, length=smoothLen)
        self.dnBandSmoothed = self.I(pta.ema, dnBand, length=smoothLen)
        
        self.lastSignal = "NONE"
    
    def next(self):
        # Long condition: impulseUp and momUp
        longCond = self.impulseUp[-1] and self.momUp[-1]
        
        # Short condition: impulseDn and momDn
        shortCond = self.impulseDn[-1] and self.momDn[-1]
        
        # New buy signal
        newBuy = longCond and self.lastSignal != "BUY"
        
        # New sell signal
        newSell = shortCond and self.lastSignal != "SELL"
        
        if newBuy:
            self.lastSignal = "BUY"
            if not self.position:
                self.buy()
        elif newSell:
            self.lastSignal = "SELL"
            if self.position:
                self.position.close()
            self.sell()
        
        # Exit short on long signal
        if newBuy and self.position and self.position.is_short:
            self.position.close()
            self.buy()


