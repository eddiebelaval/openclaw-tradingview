import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 10
    zone_width_pct = 0.15
    merge_dist_pct = 0.3
    min_touches = 1
    alert_prox = 0.1
    
    def init(self):
        self.levels = []
        self.level_touches = []
        self.level_bars = []
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.pivot_highs = self.I(self._get_pivot_highs, high, self.pivot_len)
        self.pivot_lows = self.I(self._get_pivot_lows, low, self.pivot_len)
        
        self.last_near_res = False
        self.last_near_sup = False
    
    def _get_pivot_highs(self, high):
        result = pd.Series(np.nan, index=high.index)
        for i in range(self.pivot_len, len(high) - self.pivot_len):
            if high.iloc[i] == high.iloc[i-self.pivot_len:i+self.pivot_len+1].max():
                result.iloc[i] = high.iloc[i]
        return result
    
    def _get_pivot_lows(self, low):
        result = pd.Series(np.nan, index=low.index)
        for i in range(self.pivot_len, len(low) - self.pivot_len):
            if low.iloc[i] == low.iloc[i-self.pivot_len:i+self.pivot_len+1].min():
                result.iloc[i] = low.iloc[i]
        return result
    
    def _add_level(self, p):
        merge_dist = p * self.merge_dist_pct / 100.0
        idx = -1
        
        for i in range(len(self.levels)):
            if abs(self.levels[i] - p) <= merge_dist:
                idx = i
                break
        
        if idx >= 0:
            old_p = self.levels[idx]
            old_t = self.level_touches[idx]
            self.levels[idx] = (old_p * old_t + p) / (old_t + 1)
            self.level_touches[idx] = old_t + 1
            self.level_bars[idx] = len(self.data) - self.pivot_len
        else:
            self.levels.append(p)
            self.level_touches.append(1)
            self.level_bars.append(len(self.data) - self.pivot_len)
    
    def next(self):
        if len(self.data) < self.pivot_len * 2 + 1:
            return
        
        if not np.isnan(self.pivot_highs[-1]):
            self._add_level(self.pivot_highs[-1])
        
        if not np.isnan(self.pivot_lows[-1]):
            self._add_level(self.pivot_lows[-1])
        
        cur_price = self.data.Close[-1]
        a_dist = cur_price * self.alert_prox / 100.0
        
        near_res = False
        near_sup = False
        
        for i in range(len(self.levels)):
            if self.level_touches[i] >= self.min_touches:
                p = self.levels[i]
                if abs(cur_price - p) <= a_dist:
                    if p > cur_price:
                        near_res = True
                    else:
                        near_sup = True
        
        if near_res and not self.last_near_res:
            if self.position:
                self.position.close()
            else:
                self.sell()
            self.last_near_res = True
        elif not near_res:
            self.last_near_res = False
        
        if near_sup and not self.last_near_sup:
            if self.position:
                self.position.close()
            else:
                self.buy()
            self.last_near_sup = True
        elif not near_sup:
            self.last_near_sup = False


