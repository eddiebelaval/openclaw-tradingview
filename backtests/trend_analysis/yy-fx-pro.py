import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR for risk calculation
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Highest high and lowest low (20 periods, previous bar)
        self.highest_20 = self.I(lambda: high.rolling(window=20).max().shift(1))
        self.lowest_20 = self.I(lambda: low.rolling(window=20).min().shift(1))
        
        # Highest high and lowest low (5 periods, previous bar)
        self.highest_5 = self.I(lambda: high.rolling(window=5).max().shift(1))
        self.lowest_5 = self.I(lambda: low.rolling(window=5).min().shift(1))
        
        # Track last bar index of entry
        self.last_entry_bar = -100
        self.entry_sl = 0.0
        self.entry_tp = 0.0

    def next(self):
        if len(self.data) < 20:
            return
        
        # Current values
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_low = self.data.Low[-1]
        current_high = self.data.High[-1]
        current_bar = len(self.data) - 1
        
        # ATR value
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        
        # Support/Resistance levels
        hi = self.highest_20[-1] if self.highest_20[-1] is not None else 0
        lo = self.lowest_20[-1] if self.lowest_20[-1] is not None else 0
        
        highest_5 = self.highest_5[-1] if self.highest_5[-1] is not None else 0
        lowest_5 = self.lowest_5[-1] if self.lowest_5[-1] is not None else 0
        
        # Swing patterns
        sw_b = current_low < lo and current_close > lo
        sw_s = current_high > hi and current_close < hi
        
        # Moving crossovers (5-period)
        m_u = len(self.data) >= 2 and self.data.Close[-2] <= highest_5 and current_close > highest_5
        m_d = len(self.data) >= 2 and self.data.Close[-2] >= lowest_5 and current_close < lowest_5
        
        # Buy and sell signals
        buy = (sw_b or m_u) and current_close > current_open and current_bar > self.last_entry_bar + 5
        sell = (sw_s or m_d) and current_close < current_open and current_bar > self.last_entry_bar + 5
        
        rr = 2.0
        
        # Buy logic
        if buy and not self.position:
            self.entry_sl = current_low - (atr_val * 0.2)
            self.entry_tp = current_close + ((current_close - self.entry_sl) * rr)
            self.last_entry_bar = current_bar
            self.buy()
        
        # Sell logic (exit long)
        if self.position and (current_close <= self.entry_sl or current_close >= self.entry_tp):
            self.position.close()
        
        # Sell signal (short entry if we want to support shorts)
        if sell and not self.position:
            self.entry_sl = current_high + (atr_val * 0.2)
            self.entry_tp = current_close - ((self.entry_sl - current_close) * rr)
            self.last_entry_bar = current_bar
            self.sell()
        
        # Exit short logic
        if self.position and self.position.is_short and (current_close >= self.entry_sl or current_close <= self.entry_tp):
            self.position.close()


