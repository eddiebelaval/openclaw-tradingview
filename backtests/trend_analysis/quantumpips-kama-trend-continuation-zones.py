import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # KAMA Engine parameters
    kama_slow_len = 93
    kama_fast_len = 50
    fast_sc_per = 2
    slow_sc_per = 30
    
    # Volatility Bands parameters
    stdev_len = 93
    band_mult = 2.0
    thin_factor = 6.0
    
    # Regime Filter parameters
    atr_len = 14
    width_ma_len = 50
    trend_width_k = 1.10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate source (hl2)
        source = (high + low) / 2
        
        # Calculate KAMA components
        self.kama_slow = self.I(self._kama, source, self.kama_slow_len, 
                                 self.fast_sc_per, self.slow_sc_per)
        self.kama_fast = self.I(self._kama, source, self.kama_fast_len, 
                                 self.fast_sc_per, self.slow_sc_per)
        
        # ATR for volatility and regime
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Standard deviation for bands
        self.stdev = self.I(pta.stdev, source, length=self.stdev_len)
        
        # Volatility bands
        self.upper = self.I(lambda: self.kama_slow + self.band_mult * self.stdev)
        self.lower = self.I(lambda: self.kama_slow - self.band_mult * self.stdev)
        
        # Inner bands
        dev_inner = self.band_mult / self.thin_factor
        self.upper1 = self.I(lambda: self.upper + dev_inner * self.stdev)
        self.lower1 = self.I(lambda: self.lower - dev_inner * self.stdev)
        
        # Value zone (pullback area between fast and slow)
        self.vz_top = self.I(lambda: np.maximum(self.kama_fast, self.kama_slow))
        self.vz_bot = self.I(lambda: np.minimum(self.kama_fast, self.kama_slow))
        
        # Regime calculation
        self.width = self.I(self._calc_width)
        self.width_base = self.I(lambda: pta.sma(self._calc_width_series(), length=self.width_ma_len))
        
        # Trend direction
        self.trend_up = self.I(lambda: pd.Series(
            [self.kama_slow[i] > self.kama_slow[i-1] if i > 0 else False 
             for i in range(len(self.kama_slow))],
            index=close.index
        ))

    def _kama(self, src, er_len, fast_per, slow_per):
        """Calculate KAMA indicator"""
        fast_sc = 2.0 / (fast_per + 1.0)
        slow_sc = 2.0 / (slow_per + 1.0)
        
        src_values = src.values if isinstance(src, pd.Series) else src
        kama_values = np.full(len(src_values), np.nan)
        
        for i in range(len(src_values)):
            if i == 0:
                kama_values[i] = src_values[i]
            else:
                if i >= er_len:
                    change = abs(src_values[i] - src_values[i - er_len])
                    volatility = sum(abs(src_values[i - j] - src_values[i - j - 1]) 
                                   for j in range(er_len))
                    er = change / volatility if volatility != 0 else 0
                else:
                    er = 0
                
                sc = (er * (fast_sc - slow_sc) + slow_sc) ** 2
                kama_values[i] = kama_values[i - 1] + sc * (src_values[i] - kama_values[i - 1])
        
        return pd.Series(kama_values, index=src.index)

    def _calc_width(self):
        """Calculate normalized band width"""
        atr_val = self.atr[-1] if self.atr[-1] is not None and self.atr[-1] > 0 else 1e-10
        width_val = (self.upper[-1] - self.lower[-1]) / atr_val
        return width_val

    def _calc_width_series(self):
        """Calculate width series for SMA"""
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        source = (high + low) / 2
        
        stdev_series = pta.stdev(source, length=self.stdev_len)
        upper_series = self.kama_slow + self.band_mult * stdev_series
        lower_series = self.kama_slow - self.band_mult * stdev_series
        
        atr_series = pta.atr(high, low, pd.Series(self.data.Close), length=self.atr_len)
        atr_series = atr_series.fillna(1e-10)
        atr_series = atr_series.replace(0, 1e-10)
        
        width_series = (upper_series - lower_series) / atr_series
        return width_series.fillna(0)

    def next(self):
        # Get current values
        kama_slow_curr = self.kama_slow[-1]
        kama_fast_curr = self.kama_fast[-1]
