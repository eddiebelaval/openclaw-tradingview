            # Buy on pullback to value zone in uptrend
            if (close_curr >= vz_bot_curr and 
                close_curr <= vz_top_curr and 
                trend_up and 
                not self.position):
                self.buy()
            
            # Sell on exit from value zone upside or trend break
            if ((close_curr > vz_top_curr or not trend_up) and self.position):
                self.sell()


