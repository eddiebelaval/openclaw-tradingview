import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    leftBars = 5
    rightBars = 3
    zoneExtend = 50
    showLabels = True
    showEMA21 = True
    showEMA50 = True
    showEMA200 = True
    colorBarsByEMA = True
    useEMABiasFilter = True
    requireDisplacement = True
    atrLength = 14
    impulseATRMult = 1.2
    lookAheadBars = 4
    maxBaseCandles = 6

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema21 = self.I(pta.ema, close, length=21)
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        self.supply_zones = []
        self.demand_zones = []
        self.last_signal = None

    def _is_bull(self, idx):
        return self.data.Close[idx] > self.data.Open[idx]

    def _is_bear(self, idx):
        return self.data.Close[idx] < self.data.Open[idx]

    def _find_last_bullish(self, start_idx, max_lookback):
        for x in range(start_idx, min(start_idx + max_lookback, len(self.data))):
            if x < len(self.data) and self._is_bull(x):
                return x
        return None

    def _find_last_bearish(self, start_idx, max_lookback):
        for x in range(start_idx, min(start_idx + max_lookback, len(self.data))):
            if x < len(self.data) and self._is_bear(x):
                return x
        return None

    def _highest_from_offset(self, start_idx, bars_count):
        hh = self.data.High[start_idx]
        for x in range(start_idx, max(start_idx - bars_count, -1), -1):
            if x >= 0 and x < len(self.data):
                hh = max(hh, self.data.High[x])
        return hh

    def _lowest_from_offset(self, start_idx, bars_count):
        ll = self.data.Low[start_idx]
        for x in range(start_idx, max(start_idx - bars_count, -1), -1):
            if x >= 0 and x < len(self.data):
                ll = min(ll, self.data.Low[x])
        return ll

    def _detect_pivot_high(self, left_bars, right_bars):
        idx = len(self.data) - 1
        if idx < left_bars + right_bars:
            return None
        
        center_idx = idx - right_bars
        center_high = self.data.High[center_idx]
        
        for x in range(center_idx - left_bars, center_idx):
            if x >= 0 and self.data.High[x] >= center_high:
                return None
        
        for x in range(center_idx + 1, center_idx + right_bars + 1):
            if x < len(self.data) and self.data.High[x] >= center_high:
                return None
        
        return center_idx

    def _detect_pivot_low(self, left_bars, right_bars):
        idx = len(self.data) - 1
        if idx < left_bars + right_bars:
            return None
        
        center_idx = idx - right_bars
        center_low = self.data.Low[center_idx]
        
        for x in range(center_idx - left_bars, center_idx):
            if x >= 0 and self.data.Low[x] <= center_low:
                return None
        
        for x in range(center_idx + 1, center_idx + right_bars + 1):
            if x < len(self.data) and self.data.Low[x] <= center_low:
                return None
        
        return center_idx

    def next(self):
        idx = len(self.data) - 1
        
        if idx < self.leftBars + self.rightBars:
            return
        
        if self.ema21[-1] is None or self.ema50[-1] is None or self.ema200[-1] is None or self.atr[-1] is None:
            return
        
        bull_stack = self.ema21[-1] > self.ema50[-1] and self.ema50[-1] > self.ema200[-1]
        bear_stack = self.ema21[-1] < self.ema50[-1] and self.ema50[-1] < self.ema200[-1]
        
        pivot_high_idx = self._detect_pivot_high(self.leftBars, self.rightBars)
        if pivot_high_idx is not None:
            pivot_idx = pivot_high_idx
            move_low = self._lowest_from_offset(pivot_idx, self.lookAheadBars)
            bearish_impulse = self.data.High[pivot_idx] - move_low
            has_bear_displacement = bearish_impulse >= self.atr[-1] * self.impulseATRMult
            
            supply_bias_ok = not self.useEMABiasFilter or bear_stack
            base_idx = self._find_last_bullish(pivot_idx, self.maxBaseCandles)
            valid_base = base_idx is not None
            
            if valid_base and supply_bias_ok and (not self.requireDisplacement or has_bear_displacement):
                zone_top = self.data.High[base_idx]
                zone_bottom = min(self.data.Open[base_idx], self.data.Close[base_idx])
                self.supply_zones.append({
                    'top': zone_top,
                    'bottom': zone_bottom,
                    'idx': base_idx
                })
        
        pivot_low_idx = self._detect_pivot_low(self.leftBars, self.rightBars)
        if pivot_low_idx is not None:
            pivot_idx = pivot_low_idx
            move_high = self._highest_from_offset(pivot_idx, self.lookAheadBars)
            bullish_impulse = move_high - self.data.Low[pivot_idx]
            has_bull_displacement = bullish_impulse >= self.atr[-1] * self.impulseATRMult
            
            demand_bias_ok = not self.useEMABiasFilter or bull_stack
            base_idx = self._find_last_bearish(pivot_idx, self.maxBaseCandles)
            valid_base = base_idx is not None
            
            if valid_base and demand_bias_ok and (not self.requireDisplacement or has_bull_displacement):
                zone_top = max(self.data.Open[base_idx], self.data.Close[base_idx])
                zone_bottom = self.data.Low[base_idx]
                self.demand_zones.append({
                    'top': zone_top,
                    'bottom': zone_bottom,
                    'idx': base_idx
                })
        
        self.supply_zones = [z for z in self.supply_zones if self.data.High[-1] <= z['top']]
        self.demand_zones = [z for z in self.demand_zones if self.data.Low[-1] >= z['bottom']]
        
        active_demand = any(z['bottom'] <= self.data.Close[-1] <= z['top'] for z in self.demand_zones)
        active_supply = any(z['bottom'] <= self.data.Close[-1] <= z['top'] for z in self.supply_zones)
        
        if bull_stack and active_demand and self.last_signal != 'buy':
            if not self.position:
                self.buy()
                self.last_signal = 'buy'
        
        if bear_stack and active_supply and self.last_signal != 'sell':
            if self.position:
                self.position.close()
                self.last_signal = 'sell'
        
        if not active_demand and self.position and bull_stack:
            pass
        
        if not active_supply and not self.position and bear_stack:
            pass


