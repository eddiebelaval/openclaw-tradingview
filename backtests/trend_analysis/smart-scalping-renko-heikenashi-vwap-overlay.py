import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 14
    atr_mult = 1.0
    percent = 0.6
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Renko brick size (using ATR * preset multiplier)
        self.brick_size = self.I(lambda: self.atr * self.atr_mult)
        
        # WMA calculations for HMA
        self.wma1 = self.I(pta.wma, close, length=int(self.atr_len / 3))
        self.wma2 = self.I(pta.wma, close, length=self.atr_len)
        self.wma3 = self.I(pta.wma, close, length=self.atr_len * 3)
        
        # HMA calculation
        def calc_hma1():
            wma1 = pta.wma(close, length=int(self.atr_len / 3))
            wma2 = pta.wma(close, length=self.atr_len)
            if wma1 is None or wma2 is None:
                return pd.Series(0, index=close.index)
            diff = 2 * wma1 - wma2
            hma_len = int(np.sqrt(self.atr_len))
            result = pta.wma(diff, length=hma_len)
            return result if result is not None else pd.Series(0, index=close.index)
        
        def calc_hma2():
            wma2 = pta.wma(close, length=self.atr_len)
            wma3 = pta.wma(close, length=self.atr_len * 3)
            if wma2 is None or wma3 is None:
                return pd.Series(0, index=close.index)
            diff = 2 * wma2 - wma3
            hma_len = int(np.sqrt(self.atr_len))
            result = pta.wma(diff, length=hma_len)
            return result if result is not None else pd.Series(0, index=close.index)
        
        self.hma = self.I(calc_hma1)
        self.hma_slow = self.I(calc_hma2)
        
        # Renko SMA (simplified using close as proxy)
        self.renko_sma = self.I(pta.sma, close, length=int(self.atr_len / 2))
        self.renko_sma_sma = self.I(pta.sma, self.renko_sma, length=int(self.atr_len / 2))
        
        # Average calculation
        def calc_avg():
            avg_series = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                vals = []
                if i < len(self.renko_sma) and not pd.isna(self.renko_sma.iloc[i]):
                    vals.append(self.renko_sma.iloc[i])
                if i < len(self.renko_sma_sma) and not pd.isna(self.renko_sma_sma.iloc[i]):
                    vals.append(self.renko_sma_sma.iloc[i])
                if i < len(self.hma) and not pd.isna(self.hma.iloc[i]):
                    vals.append(self.hma.iloc[i])
                if i < len(self.hma_slow) and not pd.isna(self.hma_slow.iloc[i]):
                    vals.append(self.hma_slow.iloc[i])
                avg_series.iloc[i] = np.mean(vals) if vals else np.nan
            return avg_series
        
        self.avg = self.I(calc_avg)
        
        # AVGEMA and AVGSMA
        self.avgema = self.I(pta.ema, self.avg, length=int(self.atr_len / 7))
        self.avgsma = self.I(pta.sma, self.avg, length=int(self.atr_len / 2))
        
        # OTT (Optimization Trailing Target) calculations
        def calc_hott():
            hott_series = pd.Series(index=close.index, dtype=float)
            mavg = self.avgema
            percent = self.percent
            
            for i in range(len(close)):
                if i == 0:
                    long_stop = mavg.iloc[i] - (mavg.iloc[i] * percent * 0.01) if not pd.isna(mavg.iloc[i]) else np.nan
                    hott_series.iloc[i] = long_stop
                else:
                    if pd.isna(mavg.iloc[i]) or pd.isna(hott_series.iloc[i-1]):
                        hott_series.iloc[i] = hott_series.iloc[i-1] if i > 0 else np.nan
                        continue
                    
                    fark = mavg.iloc[i] * percent * 0.01
                    long_stop = mavg.iloc[i] - fark
                    long_stop_prev = hott_series.iloc[i-1]
                    
                    if mavg.iloc[i] > long_stop_prev:
                        long_stop = max(long_stop, long_stop_prev)
                    
                    hott_series.iloc[i] = long_stop * (200 + percent) / 200 if mavg.iloc[i] > long_stop else long_stop * (200 - percent) / 200
            
            return hott_series
        
        def calc_lott():
            lott_series = pd.Series(index=close.index, dtype=float)
            mavg = self.avgsma
            percent = self.percent
            
            for i in range(len(close)):
                if i == 0:
                    long_stop = mavg.iloc[i] - (mavg.iloc[i] * percent * 0.01) if not pd.isna(mavg.iloc[i]) else np.nan
                    lott_series.iloc[i] = long_stop
                else:
                    if pd.isna(mavg.iloc[i]) or pd.isna(lott_series.iloc[i-1]):
                        lott_series.iloc[i] = lott_series.iloc[i-1] if i > 0 else np.nan
                        continue
                    
                    fark = mavg.iloc[i] * percent * 0.01
                    long_stop = mavg.iloc[i] - fark
                    long_stop_prev = lott_series.iloc[i-1]
                    
                    if mavg.iloc[i] > long_stop_prev:
                        long_stop = max(long_stop, long_stop_prev)
                    
                    lott_series.iloc[i] = long_stop * (200 + percent) / 200 if mavg.iloc[i] > long_stop else long_stop * (200 - percent) / 200
            
            return lott_series
        
        self.hott = self.I(calc_hott)
        self.lott = self.I(calc_lott)

    def next(self):
        # Entry signal: AVGEMA crosses above AVGSMA
        if len(self.avgema) > 2 and len(self.avgsma) > 2:
            if crossover(self.avgema, self.avgsma):
                if not self.position:
                    self.buy()
            
            # Exit signal: AVGEMA crosses below AVGSMA
            elif crossover(self.avgsma, self.avgema):
                if self.position:
                    self.position.close()


