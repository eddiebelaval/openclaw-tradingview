import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Session and structure parameters
    swing_sensitivity = 2
    max_mss_per_session = 2
    
    # OB and FVG parameters
    ob_max_age = 50
    ob_mitigate = True
    fvg_max_age = 80
    fvg_fill_threshold = 0.5
    
    # OTE parameters
    ote_fib_hi = 0.62
    ote_fib_lo = 0.79
    ote_max_bars = 20
    
    # TP/SL parameters
    rr_tp1 = 1.5
    rr_tp2 = 2.5
    rr_tp3 = 4.0
    
    # Displacement filter
    use_displace = True
    displace_mult = 1.5
    displace_body = 0.6

    def init(self):
        # Calculate ATR for displacement and confluence scoring
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Swing point detection using rolling max/min
        self.pivot_high = self.I(lambda: self._calc_pivot_high(high, low))
        self.pivot_low = self.I(lambda: self._calc_pivot_low(high, low))
        
        # Volume SMA for confluence
        self.vol_sma = self.I(pta.sma, volume, length=20)
        
        # State tracking
        self.asia_range_high = None
        self.asia_range_low = None
        self.recent_swing_high = None
        self.recent_swing_low = None
        
        self.asia_high_swept = False
        self.asia_low_swept = False
        
        self.bull_mss_count = 0
        self.bear_mss_count = 0
        
        self.last_bull_score = 0
        self.last_bear_score = 0
        
        self.last_bull_entry = None
        self.last_bear_entry = None
        self.last_bull_sl = None
        self.last_bear_sl = None
        self.last_bull_risk = None
        self.last_bear_risk = None
        
        self.entry_bar = None
        self.position_type = None  # 'bull' or 'bear'

    def _calc_pivot_high(self, high, lookback=2):
        """Detect swing highs"""
        if len(high) < lookback * 2 + 1:
            return pd.Series(np.nan, index=high.index)
        
        result = pd.Series(np.nan, index=high.index)
        for i in range(lookback, len(high) - lookback):
            if high.iloc[i] == high.iloc[max(0, i-lookback):i+1].max() and \
               high.iloc[i] == high.iloc[i+1:min(len(high), i+lookback+1)].max():
                result.iloc[i] = high.iloc[i]
        return result
    
    def _calc_pivot_low(self, low, lookback=2):
        """Detect swing lows"""
        if len(low) < lookback * 2 + 1:
            return pd.Series(np.nan, index=low.index)
        
        result = pd.Series(np.nan, index=low.index)
        for i in range(lookback, len(low) - lookback):
            if low.iloc[i] == low.iloc[max(0, i-lookback):i+1].min() and \
               low.iloc[i] == low.iloc[i+1:min(len(low), i+lookback+1)].min():
                result.iloc[i] = low.iloc[i]
        return result

    def _is_displacement_candle(self, atr_val):
        """Check if current candle shows institutional displacement"""
        if atr_val is None or np.isnan(atr_val):
            return False
        
        candle_range = self.data.High[-1] - self.data.Low[-1]
        body_size = abs(self.data.Close[-1] - self.data.Open[-1])
        body_ratio = body_size / candle_range if candle_range > 0 else 0.0
        
        range_ok = candle_range > atr_val * self.displace_mult
        body_ok = body_ratio >= self.displace_body
        
        return range_ok and body_ok

    def _calc_confluence_score(self, is_bull):
        """Calculate confluence score for MSS signal"""
        score = 0
        atr_val = self.atr[-1]
        
        if is_bull:
            score += 2 if self.asia_low_swept else 0
            score += 1 if self.data.Low[-1] < self.data.Low[-2] else 0
        else:
            score += 2 if self.asia_high_swept else 0
            score += 1 if self.data.High[-1] > self.data.High[-2] else 0
        
        if self.use_displace and self._is_displacement_candle(atr_val):
            score += 2
        
        if self.vol_sma[-1] and self.data.Volume[-1] > self.vol_sma[-1] * 1.2:
            score += 1
        
        candle_range = self.data.High[-1] - self.data.Low[-1]
        if candle_range > 0:
            if is_bull:
                close_ratio = (self.data.Close[-1] - self.data.Low[-1]) / candle_range
                score += 1 if close_ratio > 0.65 else 0
            else:
                close_ratio = (self.data.High[-1] - self.data.Close[-1]) / candle_range
                score += 1 if close_ratio > 0.65 else 0
        
        if self.asia_range_low and atr_val:
            dist = abs(self.data.Low[-1] - self.asia_range_low) / atr_val
            score += 1 if dist < 1.5 else 0
        
        return min(score, 10)

    def next(self):
        # Update pivot points
        if not np.isnan(self.pivot_high[-1]):
            self.recent_swing_high = self.pivot_high[-1]
        if not np.isnan(self.pivot_low[-1]):
            self.recent_swing_low = self.pivot_low[-1]
        
        # Initialize Asia range on first bar
        if self.asia_range_high is None:
            self.asia_range_high = self.data.High[-1]
            self.asia_range_low = self.data.Low[-1]
        else:
            # Update Asia range (simplified: just track running extremes in session)
            self.asia_range_high = max(self.asia_range_high, self.data.High[-1])
            self.asia_range_low = min(self.asia_range_low, self.data.Low[-1])
        
        # Sweep detection
        atr_val = self.atr[-1]
        if atr_val is None or np.isnan(atr_val):
            return
        
        sweep_high_event = False
        sweep_low_event = False
        
        if self.data.High[-1] > self.asia_range_high and not self.asia_high_swept:
            self.asia_high_swept = True
            sweep_high_event = True
        
        if self.data.Low[-1] < self.asia_range_low and not self.asia_low_swept:
            self.asia_low_swept = True
            sweep_low_event = True
        
        # Market Structure Shift detection
        bull_mss = False
        bear_mss = False
        
        # Bullish MSS: low swept + break above recent swing high
        if self.asia_low_swept and self.recent_swing_high is not None:
            if self.data.Close[-1] > self.recent_swing_high and self.data.Close[-2] <= self.recent_swing_high:
                bull_displace_ok = (not self.use_displace) or (self._is_displacement_candle(atr_val) and self.data.Close[-1] > self.data.Open[-1])
                if bull_displace_ok and self.bull_mss_count < self.max_mss_per_session:
                    bull_mss = True
                    self.bull_mss_count += 1
        
        # Bearish MSS: high swept + break below recent swing low
        if self.asia_high_swept and self.recent_swing_low is not None:
            if self.data.Close[-1] < self.recent_swing_low and self.data.Close[-2] >= self.recent_swing_low:
                bear_displace_ok = (not self.use_displace) or (self._is_displacement_candle(atr_val) and self.data.Close[-1] < self.data.Open[-1])
                if bear_displace_ok and self.bear_mss_count < self.max_mss_per_session:
                    bear_mss = True
                    self.bear_mss_count += 1
        
        # Calculate confluence scores
        if bull_mss:
            self.last_bull_score = self._calc_confluence_score(True)
        if bear_mss:
            self.last_bear_score = self._calc_confluence_score(False)
        
        # Entry logic
        if bull_mss and not self.position:
            self.last_bull_entry = self.data.Close[-1]
            self.last_bull_sl = self.asia_range_low - atr_val * 0.2
            self.last_bull_risk = self.last_bull_entry - self.last_bull_sl
            self.entry_bar = len(self.data)
            self.position_type = 'bull'
            self.buy()
        
        elif bear_mss and not self.position:
            self.last_bear_entry = self.data.Close[-1]
            self.last_bear_sl = self.asia_range_high + atr_val * 0.2
            self.last_bear_risk = self.last_bear_sl - self.last_bear_entry
            self.entry_bar = len(self.data)
            self.position_type = 'bear'
            self.sell()
        
        # Exit logic
        if self.position:
            if self.position_type == 'bull':
                # Check stop loss
                if self.data.Low[-1] < self.last_bull_sl:
                    self.position.close()
                # Check take profits
                elif self.data.High[-1] >= self.last_bull_entry + self.last_bull_risk * self.rr_tp3:
                    self.position.close()
                elif self.data.High[-1] >= self.last_bull_entry + self.last_bull_risk * self.rr_tp2:
                    self.position.close()
                elif self.data.High[-1] >= self.last_bull_entry + self.last_bull_risk * self.rr_tp1:
                    self.position.close()
            
            elif self.position_type == 'bear':
                # Check stop loss
                if self.data.High[-1] > self.last_bear_sl:
                    self.position.close()
                # Check take profits
                elif self.data.Low[-1] <= self.last_bear_entry - self.last_bear_risk * self.rr_tp3:
                    self.position.close()
                elif self.data.Low[-1] <= self.last_bear_entry - self.last_bear_risk * self.rr_tp2:
                    self.position.close()
                elif self.data.Low[-1] <= self.last_bear_entry - self.last_bear_risk * self.rr_tp1:
                    self.position.close()


