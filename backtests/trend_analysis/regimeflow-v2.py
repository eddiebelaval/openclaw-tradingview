class TvStrategy(Strategy):
    # Donchian Channel
    dc_length = 20
    touch_margin = 0.1
    lookback = 180
    
    # Fear & Greed
    fg_rsi_len = 14
    fg_atr_len = 14
    fg_atr_base = 50
    fg_vol_len = 20
    fg_ma_len = 50
    w_rsi = 25
    w_atr = 20
    w_vol = 15
    w_ma = 20
    w_dc = 20
    lvl_xtrm_fear = 36
    lvl_fear = 44
    lvl_greed = 59
    lvl_xtrm_greed = 67
    smooth_fg = True
    smooth_fg_len = 5
    
    # ADX Divergence
    enable_divergence = True
    pivot_left = 5
    pivot_right = 4
    max_pivot_dist = 24
    div_adx_filter = False
    
    # Fisher Transform
    show_fisher = True
    fisher_len = 10
    f_lvl_ext_ob = 2.0
    f_lvl_ob = 1.0
    f_lvl_os = -1.0
    f_lvl_ext_os = -2.0
    
    # Volume
    vol_spike_mult = 2.5
    
    # HTF
    show_htf_bias = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hl2 = (high + low) / 2
        
        # Donchian Channel
        self.dc_upper = self.I(lambda: high.rolling(self.dc_length).max().shift(1))
        self.dc_lower = self.I(lambda: low.rolling(self.dc_length).min().shift(1))
        self.dc_mid = (self.dc_upper + self.dc_lower) / 2
        
        # Touch detection
        margin_upper = self.dc_upper * (1 - self.touch_margin / 100)
        margin_lower = self.dc_lower * (1 + self.touch_margin / 100)
        self.upper_touch = self.I(lambda: high >= margin_upper)
        self.lower_touch = self.I(lambda: low <= margin_lower)
        
        # Rolling touch counts
        self.upper_90 = self.I(lambda: (high >= margin_upper).rolling(90).sum())
        self.lower_90 = self.I(lambda: (low <= margin_lower).rolling(90).sum())
        self.upper_180 = self.I(lambda: (high >= margin_upper).rolling(180).sum())
        self.lower_180 = self.I(lambda: (low <= margin_lower).rolling(180).sum())
        self.upper_270 = self.I(lambda: (high >= margin_upper).rolling(270).sum())
        self.lower_270 = self.I(lambda: (low <= margin_lower).rolling(270).sum())
        
        self.net_90 = self.upper_90 - self.lower_90
        self.net_180 = self.upper_180 - self.lower_180
        self.net_270 = self.upper_270 - self.lower_270
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.fg_rsi_len)
        
        # ADX/DMI
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = self.I(lambda: pta.adx(high, low, close, length=14))
        
        # ATR for volatility
        self.atr = self.I(pta.atr, high, low, close, length=self.fg_atr_len)
        self.atr_avg = self.I(lambda: pta.sma(pta.atr(high, low, close, length=self.fg_atr_len), length=self.fg_atr_base))
        
        # Volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=self.fg_vol_len)
        
