    def _calculate_fisher(self, hl2):
        """Simple Fisher Transform calculation"""
        try:
            fh = hl2.rolling(self.fisher_len).max()
            fl = hl2.rolling(self.fisher_len).min()
            f_range = fh - fl
            f_val = np.where(f_range > 0, 2.0 * ((hl2 - fl) / f_range - 0.5), 0.0)
            f_clamped = np.clip(f_val, -0.999, 0.999)
            fisher = 0.5 * np.log((1 + f_clamped) / (1 - np.abs(f_clamped) - 1e-10) + 1e-10)
            return pd.Series(fisher, index=hl2.index)
        except:
            return pd.Series(0, index=hl2.index)

    def _calculate_fg_score(self, close, high, low, volume, hl2):
        """Calculate Fear & Greed score"""
        try:
            total_weight = self.w_rsi + self.w_atr + self.w_vol + self.w_ma + self.w_dc
            if total_weight == 0:
                return pd.Series(50, index=close.index)
            
            # RSI component
            rsi = pta.rsi(close, length=self.fg_rsi_len)
            rsi_comp = np.clip(rsi, 0, 100)
            
            # Volatility component (inverted)
            atr = pta.atr(high, low, close, length=self.fg_atr_len)
            atr_avg = pta.sma(atr, length=self.fg_atr_base)
            atr_ratio = np.where(atr_avg > 0, atr / atr_avg, 1.0)
            vol_comp = np.clip(100 * (1.5 - atr_ratio), 0, 100)
            
            # Volume pressure component
            vol_sma = pta.sma(volume, length=self.fg_vol_len)
            rel_vol = np.where(vol_sma > 0, volume / vol_sma, 1.0)
            price_chg = close - close.shift(1)
            vol_dir = np.where(rel_vol > 1.0,
                              np.where(price_chg >= 0, 50 + np.minimum(50, (rel_vol - 1.0) * 50), 50 - np.minimum(50, (rel_vol - 1.0) * 50)),
                              50.0)
            vol_press_comp = np.clip(vol_dir, 0, 100)
            
            # Price vs MA component
            price_ma = pta.sma(close, length=self.fg_ma_len)
            ma_dev_pct = np.where(price_ma > 0, (close - price_ma) / price_ma * 100, 0)
            ma_comp = np.clip(50 + ma_dev_pct * 5, 0, 100)
            
            # Channel position component
            dc_upper = high.rolling(self.dc_length).max().shift(1)
            dc_lower = low.rolling(self.dc_length).min().shift(1)
            chan_range = dc_upper - dc_lower
            chan_pos = np.where(chan_range > 0, (close - dc_lower) / chan_range * 100, 50)
            chan_comp = np.clip(chan_pos, 0, 100)
            
            # Weighted blend
            fg_score = (rsi_comp * self.w_rsi + vol_comp * self.w_atr + vol_press_comp * self.w_vol + 
                       ma_comp * self.w_ma + chan_comp * self.w_dc) / total_weight
            
            # Apply smoothing if enabled
            if self.smooth_fg:
                fg_score = pta.ema(pd.Series(fg_score, index=close.index), length=self.smooth_fg_len)
            
            return pd.Series(fg_score, index=close.index)
        except:
            return pd.Series(50, index=close.index)

    def next(self):
        close_val = self.data.Close[-1]
        net_180 = self.net_180[-1] if len(self.net_180) > 0 else 0
        fg_score = self.fg_score[-1] if len(self.fg_score) > 0 else 50
        fisher = self.fisher[-1] if len(self.fisher) > 0 else 0
        rsi = self.rsi[-1] if len(self.rsi) > 0 else 50
        upper_touch = self.upper_touch[-1] if len(self.upper_touch) > 0 else False
        lower_touch = self.lower_touch[-1] if len(self.lower_touch) > 0 else False
        adx = self.adx[-1] if len(self.adx) > 0 and self.adx[-1] is not None else 20
        vol_spike = self.vol_spike[-1] if len(self.vol_spike) > 0 else False
        
        # Entry logic based on Fear & Greed + Donchian + Fisher
        
        # Buy signals
        # 1. Fear zone + lower touch + fisher oversold = accumulation setup
        if (fg_score < self.lvl_fear and lower_touch and fisher < self.f_lvl_os):
            if not self.position:
                self.buy()
        
        # 2. Neutral zone break after fear + price above MA = recovery
        elif (fg_score >= self.lvl_fear and fg_score < self.lvl_greed and 
              net_180 > 2 and rsi > 50):
            if not self.position:
                self.buy()
        
        # Sell signals
        # 1. Greed zone + upper touch + fisher overbought = distribution setup
        if (fg_score >= self.lvl_greed and upper_touch and fisher > self.f_lvl_ob):
            if self.position:
                self.sell()
        
        # 2. Greed zone breakdown = exit
        elif (fg_score < self.lvl_fear and self.position and net_180 < -2):
            self.sell()
        
        # 3. Extreme fear reversal - close longs
        if (self.position and fg_score < self.lvl_xtrm_fear and rsi < 30):
            self.sell()
        
        # 4. Extreme greed pullback - close shorts
        if (not self.position and fg_score >= self.lvl_xtrm_greed and rsi > 70):
            if self.position:
                self.sell()