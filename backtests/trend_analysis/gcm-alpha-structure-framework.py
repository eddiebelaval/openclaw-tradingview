import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 10
    displacement = 1.2
    show_fvg = True
    show_ob = True
    max_zones = 4
    fvg_min_size = 0.2
    bb_len = 20
    bb_mult = 2.0
    pivotLen = 10
    extLen = 5
    len_scalp = 7
    use_alerts = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Bollinger Bands
        self.bb_basis = self.I(pta.sma, close, length=self.bb_len)
        self.bb_dev = self.I(lambda: self.bb_mult * close.rolling(self.bb_len).std())
        self.bb_upper = self.I(lambda: self.bb_basis[-1] + self.bb_dev[-1])
        self.bb_lower = self.I(lambda: self.bb_basis[-1] - self.bb_dev[-1])
        
        # ATR for FVG sizing
        self.atr_val = self.I(pta.atr, high, low, close, length=14)
        
        # HMA for scalper trend
        self.scalp_val = self.I(pta.hma, close, length=self.len_scalp)
        
        # Pivot highs and lows
        self.ph = self.I(lambda: high.rolling(2 * self.lookback + 1).apply(
            lambda x: x[self.lookback] if self.lookback < len(x) and all(x[self.lookback] >= x[i] for i in range(len(x)) if i != self.lookback) else np.nan
        ))
        self.pl = self.I(lambda: low.rolling(2 * self.lookback + 1).apply(
            lambda x: x[self.lookback] if self.lookback < len(x) and all(x[self.lookback] <= x[i] for i in range(len(x)) if i != self.lookback) else np.nan
        ))
        
        # State tracking
        self.is_bull = True
        self.v_high = np.nan
        self.v_low = np.nan
        self.v_high_idx = -1
        self.v_low_idx = -1
        self.active_state = 0
        self.last_scalp_val = np.nan
        self.in_bull_ob = False
        self.in_bear_ob = False
        self.alert_triggered = False

    def next(self):
        idx = len(self.data) - 1
        close_price = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        
        # Update Bollinger Bands
        bb_upper = self.bb_basis[-1] + self.bb_dev[-1]
        bb_lower = self.bb_basis[-1] - self.bb_dev[-1]
        
        is_bb_extreme = high_price >= bb_upper or low_price <= bb_lower
        is_bull_candle = close_price > open_price
        is_bear_candle = close_price < open_price
        
        # Update pivot values
        if not np.isnan(self.ph[-1]) and self.ph[-1] != self.v_high:
            self.v_high = self.ph[-1]
            self.v_high_idx = idx
        
        if not np.isnan(self.pl[-1]) and self.pl[-1] != self.v_low:
            self.v_low = self.pl[-1]
            self.v_low_idx = idx
        
        # Calculate average body and ATR
        avg_body = self.data.Close[-20:].rolling(20).mean()[-1] if len(self.data) >= 20 else np.abs(close_price - open_price)
        avg_body = np.abs(close_price - open_price) if np.isnan(avg_body) else avg_body
        atr_val = self.atr_val[-1] if not np.isnan(self.atr_val[-1]) else 0
        
        is_disp = np.abs(close_price - open_price) > (avg_body * self.displacement)
        
        # BOS/CHoCH logic
        bos_bull = close_price > self.v_high and self.is_bull and is_disp if not np.isnan(self.v_high) else False
        choch_bull = close_price > self.v_high and not self.is_bull and is_disp if not np.isnan(self.v_high) else False
        bos_bear = close_price < self.v_low and not self.is_bull and is_disp if not np.isnan(self.v_low) else False
        choch_bear = close_price < self.v_low and self.is_bull and is_disp if not np.isnan(self.v_low) else False
        
        # Scalper trend crossover
        scalp_val = self.scalp_val[-1] if not np.isnan(self.scalp_val[-1]) else close_price
        scalp_val_prev = self.scalp_val[-2] if len(self.scalp_val) >= 2 and not np.isnan(self.scalp_val[-2]) else scalp_val
        
        scalp_turn_up = scalp_val > scalp_val_prev and not (self.last_scalp_val >= scalp_val_prev)
        scalp_turn_dn = scalp_val < scalp_val_prev and not (self.last_scalp_val <= scalp_val_prev)
        self.last_scalp_val = scalp_val_prev
        
        if scalp_turn_up:
            self.active_state = 1
        elif scalp_turn_dn:
            self.active_state = -1
        
        # Entry signals based on market structure + Bollinger extremes
        if (bos_bull or choch_bull) and is_bb_extreme and is_bull_candle:
            self.is_bull = True
            self.v_high = np.nan
            if not self.position:
                self.buy()
            self.alert_triggered = True
        
        if (bos_bear or choch_bear) and is_bb_extreme and is_bear_candle:
            self.is_bull = False
            self.v_low = np.nan
            if self.position:
                self.sell()
            self.alert_triggered = True
        
        # Exit on trend reversal
        if self.position:
            if self.active_state == -1 and self.position.is_long:
                self.sell()
            elif self.active_state == 1 and not self.position.is_long:
                self.buy()
        
        # Simple exit if no position and counter-trend forms
        if not self.position and self.active_state == 0:
            if len(self.data) > 1:
                # Exit on extended move or trend reversal signal
                if self.active_state == -1:
                    self.buy()
                elif self.active_state == 1:
                    self.sell()


