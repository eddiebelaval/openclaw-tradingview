import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # SuperTrend Core
    i_atLen = 10
    i_bMult = 3.0
    
    # Regime Detection
    i_regLen = 40
    i_adxLen = 14
    i_adxThr = 20.0
    i_adapt = True
    
    # AI Scoring
    i_trendLen = 50
    i_volLen = 20
    i_minSc = 65
    
    # Risk Management
    i_slMode = "ATR"
    i_slAtr = 2.5
    i_slPct = 3.0
    i_tpMode = "RR"
    i_tpRR = 2.5
    i_tpPct = 6.0
    i_trail = True
    i_trailAtr = 2.5
    
    # Filters
    i_trendF = True
    i_regF = True
    i_volF = True
    i_sigCD = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.i_atLen)
        
        # Regime Detection - ATR SMA and ratio
        atr_series = self.atr
        self.atr_ma = self.I(lambda: pta.sma(atr_series, length=self.i_regLen))
        
        # ADX calculation components
        self.adx_val = self.I(pta.adx, high, low, close, length=self.i_adxLen)
        
        # Trend EMA
        self.trend_ema = self.I(pta.ema, close, length=self.i_trendLen)
        
        # Volume MA
        self.vol_ma = self.I(pta.sma, volume, length=self.i_volLen)
        
        # SuperTrend calculation
        hl2 = (high + low) / 2
        self.st_source = self.I(lambda: hl2)
        
        # Track state
        self.st_dir = 1
        self.st_band = None
        self.last_entry_bar = -999
        self.entry_price = 0.0
        self.sl_price = 0.0
        self.tp_price = 0.0

    def next(self):
        if len(self.data) < max(self.i_atLen, self.i_regLen, self.i_adxLen, self.i_trendLen, self.i_volLen) + 5:
            return
        
        # Get current values
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0.001
        atr_ma_val = self.atr_ma[-1] if self.atr_ma[-1] is not None else atr_val
        adx_val = self.adx_val[-1] if self.adx_val[-1] is not None else 20
        trend_ema_val = self.trend_ema[-1] if self.trend_ema[-1] is not None else close_val
        vol_ma_val = self.vol_ma[-1] if self.vol_ma[-1] is not None else volume_val
        
        # Regime Detection
        atr_ratio = atr_val / atr_ma_val if atr_ma_val > 0 else 1.0
        
        if atr_ratio > 1.4:
            regime = 2
        elif adx_val < self.i_adxThr and atr_ratio < 0.9:
            regime = 0
        else:
            regime = 1
        
        # Adaptive Multiplier
        adapt_mult = self.i_bMult
        if self.i_adapt:
            if regime == 2:
                adapt_mult = self.i_bMult * (1.0 + (atr_ratio - 1.0) * 0.4)
            elif regime == 0:
                adapt_mult = self.i_bMult * 0.85
        adapt_mult = max(min(adapt_mult, self.i_bMult * 2.0), self.i_bMult * 0.5)
        
        # SuperTrend calculation
        hl2_val = (high_val + low_val) / 2
        upper_base = hl2_val + adapt_mult * atr_val
        lower_base = hl2_val - adapt_mult * atr_val
        
        prev_band = self.st_band if self.st_band is not None else (lower_base if self.st_dir == 1 else upper_base)
        
        trend_flip = False
        if self.st_dir == 1:
            self.st_band = max(lower_base, prev_band)
            if close_val < self.st_band:
                self.st_dir = -1
                self.st_band = upper_base
                trend_flip = True
        else:
            self.st_band = min(upper_base, prev_band)
            if close_val > self.st_band:
                self.st_dir = 1
                self.st_band = lower_base
                trend_flip = True
        
        # Trend direction
        trend_up = close_val > trend_ema_val
        trend_dn = close_val < trend_ema_val
        
        # AI Signal Scoring
        def calc_score(is_bull):
            score = 0.0
            
            # Factor 1: Volume surge
            v_ratio = volume_val / vol_ma_val if vol_ma_val > 0 else 1.0
            if v_ratio >= 2.5:
                score += 20
            elif v_ratio >= 1.5:
                score += 14
            elif v_ratio >= 1.0:
                score += 8
            else:
                score += 3
            
            # Factor 2: Displacement beyond band
            disp = (close_val - self.st_band) if is_bull else (self.st_band - close_val)
            disp_atr = disp / atr_val if atr_val > 0 else 0
            if disp_atr >= 1.5:
                score += 25
            elif disp_atr >= 0.8:
                score += 18
            elif disp_atr >= 0.3:
                score += 12
            elif disp_atr > 0:
                score += 5
            
            # Factor 3: EMA trend alignment
            aligned = (is_bull and trend_up) or (not is_bull and trend_dn)
            ema_dist = abs(close_val - trend_ema_val) / atr_val if atr_val > 0 else 0
            if aligned and ema_dist > 0.5:
                score += 20
            elif aligned:
                score += 14
            elif ema_dist < 0.3:
                score += 8
            else:
                score += 2
            
            # Factor 4: Regime quality
            if regime == 1:
                score += 15
            elif regime == 2:
                score += 8
            else:
                score += 3
            
            # Factor 5: Band distance
            score += 8
            
            return min(int(round(score)), 100)
        
        # Entry signals
        long_entry = False
        short_entry = False
        sig_score = 0
        
        cd_ok = (len(self.data) - self.last_entry_bar) > self.i_sigCD
        
