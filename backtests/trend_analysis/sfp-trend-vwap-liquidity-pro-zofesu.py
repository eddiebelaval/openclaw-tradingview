import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_a = 2000
    len_b = 5000
    lookback = 150
    type_a = "VWAP"
    type_b = "VWAP"
    vwap_anchor = "Session"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hlc3 = (high + low + close) / 3

        # Calculate Filter A
        if self.type_a == "HMA":
            self.val_a = self.I(pta.hma, close, length=self.len_a)
        elif self.type_a == "EMA":
            self.val_a = self.I(pta.ema, close, length=self.len_a)
        elif self.type_a == "SMA":
            self.val_a = self.I(pta.sma, close, length=self.len_a)
        elif self.type_a == "VWAP":
            self.val_a = self.I(self._calculate_vwap, hlc3, self.vwap_anchor)
        else:
            self.val_a = self.I(lambda: pd.Series(np.nan, index=close.index))

        # Calculate Filter B
        if self.type_b == "HMA":
            self.val_b = self.I(pta.hma, close, length=self.len_b)
        elif self.type_b == "EMA":
            self.val_b = self.I(pta.ema, close, length=self.len_b)
        elif self.type_b == "SMA":
            self.val_b = self.I(pta.sma, close, length=self.len_b)
        elif self.type_b == "VWAP":
            self.val_b = self.I(self._calculate_vwap, hlc3, self.vwap_anchor)
        else:
            self.val_b = self.I(lambda: pd.Series(np.nan, index=close.index))

        # Pivot High and Low
        self.swh = self.I(self._pivot_high, high, self.lookback)
        self.swl = self.I(self._pivot_low, low, self.lookback)

        # Track last swing high and low
        self.last_swh_val = np.nan
        self.last_swl_val = np.nan

    def _calculate_vwap(self, hlc3, anchor):
        # Simple VWAP calculation - resets daily by default
        cumsum = (hlc3 * self.data.Volume).cumsum()
        cumvol = self.data.Volume.cumsum()
        vwap = cumsum / cumvol
        return vwap

    def _pivot_high(self, high, lookback):
        result = pd.Series(np.nan, index=high.index)
        for i in range(lookback, len(high) - lookback):
            if high.iloc[i] == high.iloc[i-lookback:i+lookback+1].max():
                result.iloc[i] = high.iloc[i]
        return result

    def _pivot_low(self, low, lookback):
        result = pd.Series(np.nan, index=low.index)
        for i in range(lookback, len(low) - lookback):
            if low.iloc[i] == low.iloc[i-lookback:i+lookback+1].min():
                result.iloc[i] = low.iloc[i]
        return result

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        # Update last swing high and low
        if not np.isnan(self.swh[-1]):
            self.last_swh_val = self.swh[-1]
        if not np.isnan(self.swl[-1]):
            self.last_swl_val = self.swl[-1]

        # Determine trends
        trend_up_a = np.isnan(self.val_a[-1]) or close > self.val_a[-1]
        trend_up_b = np.isnan(self.val_b[-1]) or close > self.val_b[-1]
        trend_dn_a = np.isnan(self.val_a[-1]) or close < self.val_a[-1]
        trend_dn_b = np.isnan(self.val_b[-1]) or close < self.val_b[-1]

        # Bullish SFP: low breaks below last swing low, then closes above it
        sfp_bullish = (
            low < self.last_swl_val
            and close > self.last_swl_val
            and self.data.Low[-2] > self.last_swl_val
            and trend_up_a
            and trend_up_b
        )

        # Bearish SFP: high breaks above last swing high, then closes below it
        sfp_bearish = (
            high > self.last_swh_val
            and close < self.last_swh_val
            and self.data.High[-2] < self.last_swh_val
            and trend_dn_a
            and trend_dn_b
        )

        if sfp_bullish and not self.position:
            self.buy()
        elif sfp_bearish and self.position:
            self.sell()