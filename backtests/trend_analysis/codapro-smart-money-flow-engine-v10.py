import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Volume Analysis
    volLength = 24
    volMultiplier = 2.0
    deltaSmoothing = 15.0
    instSensitivity = 1.3
    
    # Smart Money Zones
    obLookback = 5
    minFVGsize = 0.3
    
    # Signals
    signalMode = "Balanced"
    cooldownBars = 20
    
    # Reversal Protection
    useReversalProtection = True
    rsiWeight = 30
    volClimaxWeight = 25
    stretchWeight = 20
    conseCandleWeight = 25
    reversalThreshold = 50
    
    # RSI Settings
    rsiLength = 14
    rsiOversold = 30
    rsiOverbought = 70
    volClimaxMult = 2.5
    stretchEmaLength = 50
    stretchPercent = 2.0
    conseCandleCount = 4
    
    # Trade Management
    enableTradeManagement = True
    takeProfitPct = 0.5
    stopLossPct = 0.3
    maxBarsInTrade = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume calculations
        self.bullVol = self.I(lambda: close > pd.Series(self.data.Open) and 1.0 or 0.0)
        self.bearVol = self.I(lambda: close <= pd.Series(self.data.Open) and 1.0 or 0.0)
        
        self.avgTotalVol = self.I(pta.sma, volume, length=self.volLength)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        
        # EMAs
        self.stretchEma = self.I(pta.ema, close, length=self.stretchEmaLength)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Track consecutive candles
        self.consecutive_reds = 0
        self.consecutive_greens = 0
        
        # Trade tracking
        self.in_trade = False
        self.is_long = False
        self.entry_price = None
        self.entry_bar = None
        self.tp_price = None
        self.sl_price = None
        self.last_buy_bar = None
        self.last_sell_bar = None

    def next(self):
        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        open_price = self.data.Open[-1]
        volume_val = self.data.Volume[-1]
        
        if len(self.data) < max(self.volLength, self.rsiLength, self.stretchEmaLength) + 5:
            return
        
        # Volume analysis
        avg_total_vol = self.avgTotalVol[-1]
        if avg_total_vol is None or np.isnan(avg_total_vol):
            return
        
        high_volume = volume_val > avg_total_vol * self.volMultiplier
        
        # RSI analysis
        rsi_val = self.rsi[-1]
        if rsi_val is None or np.isnan(rsi_val):
            return
        
        is_oversold = rsi_val < self.rsiOversold
        is_overbought = rsi_val > self.rsiOverbought
        
        # Stretch analysis
        stretch_ema = self.stretchEma[-1]
        if stretch_ema is None or np.isnan(stretch_ema) or stretch_ema == 0:
            return
        
        distance_from_ema = ((close_price - stretch_ema) / stretch_ema) * 100
        stretched_down = distance_from_ema < -self.stretchPercent
        stretched_up = distance_from_ema > self.stretchPercent
        
        # Consecutive candle tracking
        if close_price < open_price:
            self.consecutive_reds += 1
            self.consecutive_greens = 0
        else:
            self.consecutive_greens += 1
            self.consecutive_reds = 0
        
        exhausted_selling = self.consecutive_reds >= self.conseCandleCount
        exhausted_buying = self.consecutive_greens >= self.conseCandleCount
        
        # Reversal score calculation
        bullish_reversal_score = 0.0
        if is_oversold:
            bullish_reversal_score += self.rsiWeight
        if exhausted_selling:
            bullish_reversal_score += self.conseCandleWeight
        if stretched_down:
            bullish_reversal_score += self.stretchWeight
        
        bearish_reversal_score = 0.0
        if is_overbought:
            bearish_reversal_score += self.rsiWeight
        if exhausted_buying:
            bearish_reversal_score += self.conseCandleWeight
        if stretched_up:
            bearish_reversal_score += self.stretchWeight
        
        bullish_reversal = self.useReversalProtection and bullish_reversal_score >= self.reversalThreshold
        bearish_reversal = self.useReversalProtection and bearish_reversal_score >= self.reversalThreshold
        
        # Simple buy/sell confluence
        buy_confluence = 0
        if high_volume and close_price > open_price:
            buy_confluence += 2
        if is_oversold:
            buy_confluence += 1
        if stretched_down:
            buy_confluence += 1
        
        sell_confluence = 0
        if high_volume and close_price < open_price:
            sell_confluence += 2
        if is_overbought:
            sell_confluence += 1
        if stretched_up:
            sell_confluence += 1
        
        min_confluence = 2 if self.signalMode == "Aggressive" else 3
        
        # Cooldown check
        enough_time_buy = self.last_buy_bar is None or (len(self.data) - self.last_buy_bar) >= self.cooldownBars
        enough_time_sell = self.last_sell_bar is None or (len(self.data) - self.last_sell_bar) >= self.cooldownBars
        
        buy_condition_met = buy_confluence >= min_confluence and enough_time_buy
        sell_condition_met = sell_confluence >= min_confluence and enough_time_sell
        
        buy_signal = buy_condition_met and not bearish_reversal
        sell_signal = sell_condition_met and not bullish_reversal
        
        # Trade management
        if self.in_trade and self.enableTradeManagement:
            bars_in_trade = len(self.data) - self.entry_bar
            
            if self.is_long:
                if high_price >= self.tp_price or low_price <= self.sl_price or bars_in_trade >= self.maxBarsInTrade:
                    self.sell()
                    self.in_trade = False
                    self.is_long = False
            else:
                if low_price <= self.tp_price or high_price >= self.sl_price or bars_in_trade >= self.maxBarsInTrade:
                    self.buy()
                    self.in_trade = False
        
        # Entry logic
        can_take_new_trade = (not self.in_trade) or (not self.enableTradeManagement)
        
        if can_take_new_trade and buy_signal:
            self.buy()
            self.in_trade = True
            self.is_long = True
            self.entry_price = close_price
            self.entry_bar = len(self.data)
            self.tp_price = close_price * (1 + self.takeProfitPct / 100)
            self.sl_price = close_price * (1 - self.stopLossPct / 100)
            self.last_buy_bar = len(self.data)
        
        elif can_take_new_trade and sell_signal:
            if self.position:
                self.position.close()
            else:
                self.sell()
            self.in_trade = True
            self.is_long = False
            self.entry_price = close_price
            self.entry_bar = len(self.data)
            self.tp_price = close_price * (1 - self.takeProfitPct / 100)
            self.sl_price = close_price * (1 + self.stopLossPct / 100)
            self.last_sell_bar = len(self.data)