import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lr_len = 11
    sm_len = 7
    ema_len = 200
    pv_len_l = 25
    pv_len_r = 15

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Linear Regression calculations
        self.lr_close = self.I(lambda: pd.Series(
            np.polyfit(np.arange(len(close)), close.values, 1)[0] * np.arange(len(close)) + np.polyfit(np.arange(len(close)), close.values, 1)[1],
            index=close.index
        ).rolling(self.lr_len).mean())
        
        self.lr_open = self.I(lambda: pd.Series(
            np.polyfit(np.arange(len(open_)), open_.values, 1)[0] * np.arange(len(open_)) + np.polyfit(np.arange(len(open_)), open_.values, 1)[1],
            index=open_.index
        ).rolling(self.lr_len).mean())

        # Signal Line - SMA of LR Close
        self.signal_line = self.I(lambda: pta.sma(self.lr_close, length=self.sm_len) if pta.sma(self.lr_close, length=self.sm_len) is not None else pd.Series(0, index=close.index))

        # EMA 200
        self.ema_200 = self.I(pta.ema, close, length=self.ema_len)

    def next(self):
        # Buy signal: LR Close crosses above Signal Line
        if len(self.data) > max(self.lr_len, self.sm_len, self.ema_len):
            if crossover(self.lr_close, self.signal_line):
                if not self.position:
                    self.buy()
            
            # Sell signal: LR Close crosses below Signal Line
            elif crossover(self.signal_line, self.lr_close):
                if self.position:
                    self.position.close()