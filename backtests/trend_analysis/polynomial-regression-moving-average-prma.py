import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 100
    degree = 4.0
    smoothType = "EMA"
    smoothLen = 5
    smoothIter = 1

    def init(self):
        close = pd.Series(self.data.Close)
        
        def calculate_prma():
            prma_values = []
            
            for bar_idx in range(len(close)):
                if bar_idx < self.length:
                    prma_values.append(np.nan)
                    continue
                
                # Calculate OLS weights for polynomial regression
                deg_f = int(np.floor(self.degree))
                deg_c = int(np.ceil(self.degree))
                weight = self.degree - deg_f
                
                # Build design matrix X
                X_floor = np.column_stack([np.arange(self.length) ** j for j in range(deg_f + 1)])
                
                # Calculate (X^T X)^-1 X^T
                try:
                    XtX = X_floor.T @ X_floor
                    XtX_inv = np.linalg.inv(XtX)
                    H_floor = XtX_inv @ X_floor.T
                    
                    # Get prediction weights for last point
                    x_last_floor = np.array([self.length - 1 ** j for j in range(deg_f + 1)])
                    weights_floor = H_floor @ x_last_floor
                    
                    if deg_f == deg_c:
                        weights = weights_floor
                    else:
                        X_ceil = np.column_stack([np.arange(self.length) ** j for j in range(deg_c + 1)])
                        XtX = X_ceil.T @ X_ceil
                        XtX_inv = np.linalg.inv(XtX)
                        H_ceil = XtX_inv @ X_ceil.T
                        x_last_ceil = np.array([self.length - 1 ** j for j in range(deg_c + 1)])
                        weights_ceil = H_ceil @ x_last_ceil
                        weights = (1.0 - weight) * weights_floor[:deg_f + 1] + weight * weights_ceil[:deg_c + 1]
                        if len(weights) < len(weights_floor):
                            weights = np.concatenate([weights, np.zeros(len(weights_floor) - len(weights))])
                    
                    # Get source values for regression window
                    window_start = bar_idx - self.length + 1
                    window_end = bar_idx + 1
                    source_vals = close.iloc[window_start:window_end].values[:self.length]
                    
                    if len(source_vals) < self.length:
                        prma_values.append(np.nan)
                        continue
                    
                    nr_pred = np.sum(weights[:len(source_vals)] * source_vals[::-1])
                    
                    # Apply smoothing
                    smoothed = self.apply_smoothing_value(nr_pred, bar_idx)
                    prma_values.append(smoothed)
                    
                except:
                    prma_values.append(np.nan)
            
            return pd.Series(prma_values, index=close.index)
        
        self.prma = self.I(calculate_prma)
    
    def apply_smoothing_value(self, value, bar_idx):
        if self.smoothType == "None":
            return value
        
        result = value
        for _ in range(self.smoothIter):
            result = self.smooth_once(result, bar_idx)
        return result
    
    def smooth_once(self, value, bar_idx):
        close = pd.Series(self.data.Close)
        
        if self.smoothType == "SMA":
            if bar_idx < self.smoothLen - 1:
                return value
            return close.iloc[bar_idx - self.smoothLen + 1:bar_idx + 1].mean()
        elif self.smoothType == "EMA":
            if bar_idx < 1:
                return value
            alpha = 2.0 / (self.smoothLen + 1)
            ema_val = close.iloc[0]
            for i in range(1, min(bar_idx + 1, len(close))):
                ema_val = alpha * close.iloc[i] + (1 - alpha) * ema_val
            return ema_val
        elif self.smoothType == "WMA":
            if bar_idx < self.smoothLen - 1:
                return value
            weights = np.arange(1, self.smoothLen + 1)
            window = close.iloc[bar_idx - self.smoothLen + 1:bar_idx + 1].values
            return np.sum(weights * window) / np.sum(weights)
        elif self.smoothType == "RMA":
            if bar_idx < self.smoothLen - 1:
                return value
            alpha = 1.0 / self.smoothLen
            rma_val = close.iloc[0]
            for i in range(1, min(bar_idx + 1, len(close))):
                rma_val = alpha * close.iloc[i] + (1 - alpha) * rma_val
            return rma_val
        else:
            return value

    def next(self):
        if len(self.data) < self.length + 1:
            return
        
        prma_current = self.prma[-1] if not np.isnan(self.prma[-1]) else None
        prma_prev = self.prma[-2] if len(self.prma) > 1 and not np.isnan(self.prma[-2]) else None
        
        if prma_current is None or prma_prev is None:
            return
        
        close_current = self.data.Close[-1]
        
        prma_up = prma_current > prma_prev
        prma_dn = prma_current < prma_prev
        
        if len(self.prma) > 2:
            prma_prev2 = self.prma[-3] if not np.isnan(self.prma[-3]) else prma_prev
            prma_was_dn = prma_prev < prma_prev2
            prma_was_up = prma_prev > prma_prev2
            
            sig_buy = prma_up and prma_was_dn and close_current > prma_current
            sig_sell = prma_dn and prma_was_up and close_current < prma_current
            
