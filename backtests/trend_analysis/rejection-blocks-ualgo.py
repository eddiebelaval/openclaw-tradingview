import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        self.swing_left = 5
        self.swing_right = 5
        self.min_sweep_ticks = 0
        self.use_shape_filter = True
        self.min_wick_to_body = 2.0
        self.min_dom_wick_pct = 0.55
        self.max_opp_wick_pct = 0.30
        self.max_body_pct = 0.60
        self.close_filter = "Close in favorable half"
        self.rb_zone_mode = "Wick-to-Body"
        self.strength_model = "Close location"
        self.show_bull = True
        self.show_bear = True
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.pivot_high = self.I(self._pivot_high, high, self.swing_left, self.swing_right)
        self.pivot_low = self.I(self._pivot_low, low, self.swing_left, self.swing_right)
        
        self.last_swing_high = np.nan
        self.last_swing_low = np.nan
        self.trend_dir = 0
        self.rejection_blocks = []
        self.pending_confirmations = []

    def _pivot_high(self, high_series, left, right):
        result = pd.Series(np.nan, index=high_series.index)
        for i in range(left, len(high_series) - right):
            window = high_series.iloc[i-left:i+right+1]
            if high_series.iloc[i] == window.max():
                result.iloc[i] = high_series.iloc[i]
        return result

    def _pivot_low(self, low_series, left, right):
        result = pd.Series(np.nan, index=low_series.index)
        for i in range(left, len(low_series) - right):
            window = low_series.iloc[i-left:i+right+1]
            if low_series.iloc[i] == window.min():
                result.iloc[i] = low_series.iloc[i]
        return result

    def _get_candle_parts(self, idx):
        open_val = self.data.Open[idx]
        close_val = self.data.Close[idx]
        high_val = self.data.High[idx]
        low_val = self.data.Low[idx]
        
        b_top = max(open_val, close_val)
        b_bot = min(open_val, close_val)
        u_w = high_val - b_top
        l_w = b_bot - low_val
        rng = high_val - low_val
        body = b_top - b_bot
        
        return {
            'range': rng,
            'body': body,
            'upper_wick': u_w,
            'lower_wick': l_w,
            'body_top': b_top,
            'body_bot': b_bot,
            'open': open_val,
            'close': close_val,
            'high': high_val,
            'low': low_val
        }

    def _is_rb_candle(self, idx, direction, level):
        if np.isnan(level):
            return False
        
        parts = self._get_candle_parts(idx)
        rng_adj = max(parts['range'], 1e-8)
        body_adj = max(parts['body'], 1e-8)
        
        dom_w = parts['lower_wick'] if direction == 1 else parts['upper_wick']
        opp_w = parts['upper_wick'] if direction == 1 else parts['lower_wick']
        dom_pct = dom_w / rng_adj
        opp_pct = opp_w / rng_adj
        body_pct = parts['body'] / rng_adj
        
        shape_ok = True
        if self.use_shape_filter:
            shape_ok = (
                rng_adj > 1e-8 and
                dom_w >= body_adj * self.min_wick_to_body and
                dom_pct >= self.min_dom_wick_pct and
                opp_pct <= self.max_opp_wick_pct and
                body_pct <= self.max_body_pct
            )
        
        sweep_ok = False
        if direction == 1:
            sweep_ok = parts['low'] < level and parts['close'] > level
        else:
            sweep_ok = parts['high'] > level and parts['close'] < level
        
        close_ok = True
        if self.close_filter == "Close in favorable half":
            mid = (parts['high'] + parts['low']) * 0.5
            close_ok = (parts['close'] >= mid if direction == 1 else parts['close'] <= mid)
        
        return sweep_ok and shape_ok and close_ok

    def _get_zone(self, idx, direction):
        parts = self._get_candle_parts(idx)
        body_top = parts['body_top']
        body_bot = parts['body_bot']
        
        if self.rb_zone_mode == "Wick-to-Body":
            if direction == 1:
                return body_bot, parts['low']
            else:
                return parts['high'], body_top
        elif self.rb_zone_mode == "Open-to-Extreme":
            if direction == 1:
                return parts['open'], parts['low']
            else:
                return parts['high'], parts['open']
        elif self.rb_zone_mode == "Full Candle":
            return parts['high'], parts['low']
        else:
            return body_top, body_bot

    def _get_strength(self, idx, direction):
        parts = self._get_candle_parts(idx)
        rng_adj = max(parts['range'], 1e-8)
        close_loc = np.clip((parts['close'] - parts['low']) / rng_adj, 0.0, 1.0)
        buy = close_loc
        
        if self.strength_model == "Close + Wick":
            dom_wick_pct = (parts['lower_wick'] if direction == 1 else parts['upper_wick']) / rng_adj
            wick_signal = dom_wick_pct if direction == 1 else (1.0 - dom_wick_pct)
            buy = np.clip(close_loc * 0.7 + wick_signal * 0.3, 0.0, 1.0)
        
        sell = 1.0 - buy
        return buy, sell

    def next(self):
        idx = len(self.data) - 1
        
        if not np.isnan(self.pivot_high[-1]):
            self.last_swing_high = self.pivot_high[-1]
        
        if not np.isnan(self.pivot_low[-1]):
            self.last_swing_low = self.pivot_low[-1]
        
        if not np.isnan(self.last_swing_high) and self.show_bear:
            if self._is_rb_candle(idx, -1, self.last_swing_high):
                top, bottom = self._get_zone(idx, -1)
                if top > bottom:
                    buy_str, sell_str = self._get_strength(idx, -1)
                    self.pending_confirmations.append({
                        'direction': -1,
                        'top': top,
                        'bottom': bottom,
                        'level': self.last_swing_low,
                        'buy_strength': buy_str,
                        'sell_strength': sell_str
                    })
        
        if not np.isnan(self.last_swing_low) and self.show_bull:
            if self._is_rb_candle(idx, 1, self.last_swing_low):
                top, bottom = self._get_zone(idx, 1)
                if top > bottom:
                    buy_str, sell_str = self._get_strength(idx, 1)
                    self.pending_confirmations.append({
                        'direction': 1,
                        'top': top,
                        'bottom': bottom,
                        'level': self.last_swing_high,
                        'buy_strength': buy_str,
                        'sell_strength': sell_str
                    })
        
        confirmed = []
        for pending in self.pending_confirmations:
            if pending['direction'] == 1:
                if self.data.Close[idx] > pending['level'] and self.data.Close[idx-1] <= pending['level']:
                    confirmed.append(pending)
            else:
                if self.data.Close[idx] < pending['level'] and self.data.Close[idx-1] >= pending['level']:
                    confirmed.append(pending)
        
        for block in confirmed:
            if block['direction'] == 1:
                if not self.position:
                    self.buy()
            else:
                if self.position:
                    self.position.close()
        
        self.pending_confirmations = [p for p in self.pending_confirmations if p not in confirmed]
        
        if self.position:
            if self.position.is_long:
                if self.data.Low[idx] < self.last_swing_low * 0.99:
                    self.position.close()
            else:
                if self.data.High[idx] > self.last_swing_high * 1.01:
                    self.position.close()


