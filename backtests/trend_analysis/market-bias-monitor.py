import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    min_tf_agreement = 5
    
    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema8 = self.I(pta.ema, close, length=8)
        self.ema21 = self.I(pta.ema, close, length=21)
        self.ema50 = self.I(pta.ema, close, length=50)
        
        self.bias_signal = self.I(self._calculate_bias)
    
    def _calculate_bias(self):
        close = pd.Series(self.data.Close)
        ema8 = pta.ema(close, length=8)
        ema21 = pta.ema(close, length=21)
        ema50 = pta.ema(close, length=50)
        
        bullish = (close > ema21) & (ema8 > ema21) & (ema21 > ema50)
        bearish = (close < ema21) & (ema8 < ema21) & (ema21 < ema50)
        
        signal = pd.Series(0, index=close.index)
        signal[bullish] = 1
        signal[bearish] = -1
        
        return signal
    
    def next(self):
        if len(self) < 2:
            return
        
        current_bias = self.bias_signal[-1]
        previous_bias = self.bias_signal[-2]
        
        if previous_bias <= 0 and current_bias > 0:
            if not self.position:
                self.buy()
        elif previous_bias >= 0 and current_bias < 0:
            if self.position:
                self.position.close()


