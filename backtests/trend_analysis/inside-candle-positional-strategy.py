import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rr = 3.0
    use_tsl = True
    atr_period = 10
    atr_multiplier = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        self.mother_high = None
        self.mother_low = None
        self.mother_active = False
        self.breakout_taken = False
        
        self.initial_sl = None
        self.target = None
        self.trailing_sl = None
        self.entry_price = None

    def next(self):
        high_current = self.data.High[-1]
        high_prev = self.data.High[-2] if len(self.data) > 1 else high_current
        low_current = self.data.Low[-1]
        low_prev = self.data.Low[-2] if len(self.data) > 1 else low_current
        close_current = self.data.Close[-1]
        
        inside_bar = high_current < high_prev and low_current > low_prev
        
        if inside_bar and not self.position:
            self.mother_high = high_prev
            self.mother_low = low_prev
            self.mother_active = True
            self.breakout_taken = False
        
        long_condition = (
            self.mother_active and 
            not self.breakout_taken and 
            close_current > self.mother_high and 
            not self.position
        )
        
        short_condition = (
            self.mother_active and 
            not self.breakout_taken and 
            close_current < self.mother_low and 
            not self.position
        )
        
        if long_condition:
            self.entry_price = close_current
            risk = self.entry_price - self.mother_low
            self.initial_sl = self.mother_low
            self.target = self.entry_price + risk * self.rr
            self.trailing_sl = self.initial_sl
            self.buy()
            self.breakout_taken = True
        
        if short_condition:
            self.entry_price = close_current
            risk = self.mother_high - self.entry_price
            self.initial_sl = self.mother_high
            self.target = self.entry_price - risk * self.rr
            self.trailing_sl = self.initial_sl
            self.sell()
            self.breakout_taken = True
        
        atr_value = self.atr[-1] * self.atr_multiplier if self.atr[-1] is not None else 0
        
        if self.position and self.position.is_long and self.use_tsl:
            new_tsl = close_current - atr_value
            self.trailing_sl = max(self.trailing_sl, new_tsl)
            self.trailing_sl = max(self.trailing_sl, self.initial_sl)
        
        if self.position and self.position.is_short and self.use_tsl:
            new_tsl = close_current + atr_value
            self.trailing_sl = min(self.trailing_sl, new_tsl)
            self.trailing_sl = min(self.trailing_sl, self.initial_sl)
        
        active_sl = self.trailing_sl if self.use_tsl else self.initial_sl
        
        if self.position and self.position.is_long:
            if close_current <= active_sl or close_current >= self.target:
                self.position.close()
                self.mother_active = False
                self.initial_sl = None
                self.target = None
                self.trailing_sl = None
                self.entry_price = None
        
        if self.position and self.position.is_short:
            if close_current >= active_sl or close_current <= self.target:
                self.position.close()
                self.mother_active = False
                self.initial_sl = None
                self.target = None
                self.trailing_sl = None
                self.entry_price = None


