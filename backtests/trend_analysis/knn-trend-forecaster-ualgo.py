import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    k_neighbors = 12
    forecast_len = 18
    expansion = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        
        # Calculate ROC and normalize
        roc = self.I(lambda: pta.roc(close, length=10) or pd.Series(0, index=close.index))
        self.roc_norm = self.I(lambda: self._normalize(roc, 100))
        
        # Calculate ATR and normalize
        atr = self.I(lambda: pta.atr(high, low, close, length=14) or pd.Series(0, index=close.index))
        self.atr_norm = self.I(lambda: self._normalize(atr, 100))
        
        # EMA for projection basis
        self.ema21 = self.I(pta.ema, close, length=21)
        
        # Store historical data for KNN
        self.training_memory = []
        self.prediction = 0.0
        self.last_prediction = 0.0

    def _normalize(self, series, scale):
        """Normalize series to 0-100 range"""
        mn = series.rolling(100).min()
        mx = series.rolling(100).max()
        normalized = (series - mn) / (mx - mn + 0.000001) * scale
        return normalized.fillna(50)

    def _calculate_distance(self, f1, f2, f3, ref_f1, ref_f2, ref_f3):
        """Euclidean distance between two feature vectors"""
        return np.sqrt((f1 - ref_f1)**2 + (f2 - ref_f2)**2 + (f3 - ref_f3)**2)

    def _knn_prediction(self):
        """KNN-based prediction"""
        if len(self.training_memory) < self.k_neighbors:
            return 0.0
        
        current_features = (self.rsi[-1], self.roc_norm[-1], self.atr_norm[-1])
        
        # Calculate distances to all training points
        distances = []
        changes = []
        
        for point in self.training_memory:
            dist = self._calculate_distance(
                current_features[0], current_features[1], current_features[2],
                point['features'][0], point['features'][1], point['features'][2]
            )
            distances.append(dist)
            changes.append(point['change'])
        
        # Find k nearest neighbors
        distances = np.array(distances)
        changes = np.array(changes)
        
        # Get indices of k smallest distances
        k_indices = np.argsort(distances)[:self.k_neighbors]
        
        # Weighted average using inverse distance weighting
        weights = 1.0 / np.maximum(distances[k_indices], 0.0001)
        weighted_sum = np.sum(changes[k_indices] * weights)
        weight_sum = np.sum(weights)
        
        prediction = weighted_sum / weight_sum if weight_sum > 0 else 0.0
        return prediction

    def next(self):
        # Add training point every 10 bars
        if len(self) > 10 and len(self) % 10 == 0:
            if len(self) >= 10:
                past_close = self.data.Close[-11]
                current_close = self.data.Close[-1]
                outcome = (current_close - past_close) / past_close * 100
                
                features = (self.rsi[-11] if len(self.rsi) >= 11 else self.rsi[-1],
                           self.roc_norm[-11] if len(self.roc_norm) >= 11 else self.roc_norm[-1],
                           self.atr_norm[-11] if len(self.atr_norm) >= 11 else self.atr_norm[-1])
                
                self.training_memory.append({
                    'features': features,
                    'change': outcome
                })
                
                # Keep memory size reasonable
                if len(self.training_memory) > 1000:
                    self.training_memory.pop(0)
        
        # Calculate prediction
        if len(self.training_memory) >= self.k_neighbors:
            self.prediction = self._knn_prediction()
        
        # Trading logic based on prediction
        if self.prediction > 0.005:
            # Bullish signal
            if not self.position:
                self.buy()
            elif not self.position.is_long:
                self.position.close()
                self.buy()
        elif self.prediction < -0.005:
            # Bearish signal
            if self.position:
                self.position.close()
        else:
            # Neutral - exit position if open
            if self.position:
                self.position.close()


