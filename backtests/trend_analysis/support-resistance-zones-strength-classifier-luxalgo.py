import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 10
    zone_mult = 2.0
    min_tests = 2
    max_zones = 10
    max_height_mult = 10.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.support_zones = []
        self.resistance_zones = []
        self.zone_width_values = []
        self.pivot_highs = []
        self.pivot_lows = []
        
        self.dist_series = self._calculate_dist(high, low, close)
        self.zone_width_series = self.dist_series * self.zone_mult
        
        self.pivot_highs = self._calculate_pivot_highs(high)
        self.pivot_lows = self._calculate_pivot_lows(low)

    def _calculate_dist(self, high, low, close):
        cum_dist = (high - low).abs().cumsum()
        bar_indices = np.arange(1, len(close) + 1)
        dist = cum_dist / bar_indices
        return dist

    def _calculate_pivot_highs(self, high):
        pivot_highs = []
        for i in range(len(high)):
            if i >= self.pivot_len and i < len(high) - self.pivot_len:
                window = high.iloc[i - self.pivot_len:i + self.pivot_len + 1]
                if high.iloc[i] == window.max():
                    pivot_highs.append(high.iloc[i])
                else:
                    pivot_highs.append(np.nan)
            else:
                pivot_highs.append(np.nan)
        return pd.Series(pivot_highs, index=high.index)

    def _calculate_pivot_lows(self, low):
        pivot_lows = []
        for i in range(len(low)):
            if i >= self.pivot_len and i < len(low) - self.pivot_len:
                window = low.iloc[i - self.pivot_len:i + self.pivot_len + 1]
                if low.iloc[i] == window.min():
                    pivot_lows.append(low.iloc[i])
                else:
                    pivot_lows.append(np.nan)
            else:
                pivot_lows.append(np.nan)
        return pd.Series(pivot_lows, index=low.index)

    def _find_or_create_zone(self, zones, price, width, is_support):
        for zone in zones:
            if price <= zone['top'] and price >= zone['bottom']:
                zone['test_count'] += 1
                return True
        
        if len(zones) < self.max_zones:
            if is_support:
                top = price + width / 2
                bottom = price - width
            else:
                top = price + width
                bottom = price - width / 2
            
            zones.append({
                'top': top,
                'bottom': bottom,
                'test_count': 1,
                'is_support': is_support,
                'is_broken': False
            })
        
        return False

    def _merge_zones(self, zones, max_height):
        i = 0
        while i < len(zones):
            z1 = zones[i]
            j = i + 1
            merged = False
            
            while j < len(zones):
                z2 = zones[j]
                if not (z1['bottom'] > z2['top'] or z1['top'] < z2['bottom']):
                    z1['top'] = max(z1['top'], z2['top'])
                    z1['bottom'] = min(z1['bottom'], z2['bottom'])
                    z1['test_count'] += z2['test_count']
                    zones.pop(j)
                    merged = True
                else:
                    j += 1
            
            if (z1['top'] - z1['bottom']) > max_height:
                zones.pop(i)
                continue
            
            i += 1

    def _check_zone_breaks(self, zones, price):
        zones_to_remove = []
        for idx, zone in enumerate(zones):
            if zone['is_support'] and price < zone['bottom']:
                zone['is_broken'] = True
                zones_to_remove.append(idx)
            elif not zone['is_support'] and price > zone['top']:
                zone['is_broken'] = True
                zones_to_remove.append(idx)
        
        for idx in reversed(zones_to_remove):
            zones.pop(idx)

    def next(self):
        current_idx = len(self.data) - 1
