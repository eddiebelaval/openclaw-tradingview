        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_dist = self.dist_series.iloc[current_idx]
        current_width = self.zone_width_series.iloc[current_idx]
        max_height = current_dist * self.max_height_mult
        
        ph = self.pivot_highs.iloc[current_idx]
