import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_len = 10
    min_mult = 1.5
    sec_mult = 4.0
    pri_mult = 10.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Initialize Dow engines for three trend scales
        self.minor_trend = 1
        self.minor_ext_p = self.data.Close[0]
        self.minor_ext_b = 0
        self.minor_last_ph = np.nan
        self.minor_last_pl = np.nan
        self.minor_defense = np.nan
        
        self.sec_trend = 1
        self.sec_ext_p = self.data.Close[0]
        self.sec_ext_b = 0
        self.sec_last_ph = np.nan
        self.sec_last_pl = np.nan
        self.sec_defense = np.nan
        
        self.pri_trend = 1
        self.pri_ext_p = self.data.Close[0]
        self.pri_ext_b = 0
        self.pri_last_ph = np.nan
        self.pri_last_pl = np.nan
        self.pri_defense = np.nan

    def process_engine(self, c_price, c_atr, atr_mult, 
                       trend, ext_p, ext_b, last_ph, last_pl, defense, dir_flag, engine_name):
        """
        Process a single Dow engine and return updated values
        """
        # Trend break detection
        if trend == 1 and not np.isnan(defense) and c_price < defense:
            trend = -1
            defense = np.nan
        elif trend == -1 and not np.isnan(defense) and c_price > defense:
            trend = 1
            defense = np.nan
        
        # Structural price swing detection
        if dir_flag == 1:  # Hunting a peak
            if c_price > ext_p:
                ext_p = c_price
                ext_b = len(self.data) - 1
            elif c_price < ext_p - (atr_mult * c_atr):
                # Peak found
                if np.isnan(last_ph) or ext_p > last_ph:
                    # Higher High
                    pass
                else:
                    # Lower High - set defense line
                    defense = ext_p
                
                last_ph = ext_p
                dir_flag = -1
                ext_p = c_price
                ext_b = len(self.data) - 1
        else:  # Hunting a trough
            if c_price < ext_p:
                ext_p = c_price
                ext_b = len(self.data) - 1
            elif c_price > ext_p + (atr_mult * c_atr):
                # Trough found
                if np.isnan(last_pl) or ext_p < last_pl:
                    # Lower Low
                    pass
                else:
                    # Higher Low - set defense line
                    defense = ext_p
                
                last_pl = ext_p
                dir_flag = 1
                ext_p = c_price
                ext_b = len(self.data) - 1
        
        return trend, ext_p, ext_b, last_ph, last_pl, defense, dir_flag

    def next(self):
        if len(self.data) < self.atr_len + 1:
            return
        
        c_price = self.data.Close[-1]
        c_atr = self.atr[-1]
        
        if c_atr is None or np.isnan(c_atr):
            return
        
        # Process minor trend engine
        self.minor_trend, self.minor_ext_p, self.minor_ext_b, self.minor_last_ph, self.minor_last_pl, \
            self.minor_defense, _ = self.process_engine(
            c_price, c_atr, self.min_mult, self.minor_trend, self.minor_ext_p, self.minor_ext_b,
            self.minor_last_ph, self.minor_last_pl, self.minor_defense, 1, "minor"
        )
        
        # Process secondary trend engine
        self.sec_trend, self.sec_ext_p, self.sec_ext_b, self.sec_last_ph, self.sec_last_pl, \
            self.sec_defense, _ = self.process_engine(
            c_price, c_atr, self.sec_mult, self.sec_trend, self.sec_ext_p, self.sec_ext_b,
            self.sec_last_ph, self.sec_last_pl, self.sec_defense, 1, "secondary"
        )
        
        # Process primary trend engine
        self.pri_trend, self.pri_ext_p, self.pri_ext_b, self.pri_last_ph, self.pri_last_pl, \
            self.pri_defense, _ = self.process_engine(
            c_price, c_atr, self.pri_mult, self.pri_trend, self.pri_ext_p, self.pri_ext_b,
            self.pri_last_ph, self.pri_last_pl, self.pri_defense, 1, "primary"
        )
        
        # Trading logic based on primary trend
        if self.pri_trend == 1 and not self.position:
            self.buy()
        elif self.pri_trend == -1 and self.position:
            self.sell()


