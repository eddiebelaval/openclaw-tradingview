import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swingLen = 16
    zoneATR = 0.3
    maxAge = 300
    samples = 20
    method = "Weighted"
    fwdBars = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for zone width
        self.atr = self.I(pta.atr, high, low, close, length=200)
        
        # Calculate highest high and lowest low
        self.highest_high = self.I(lambda: high.rolling(self.swingLen).max())
        self.lowest_low = self.I(lambda: low.rolling(self.swingLen).min())
        
        # Track state
        self.direction = False
        self.swings = []
        self.percentages = []
        self.durations = []
        self.last_swing_idx = 0
        self.last_swing_price = 0
        self.prev_direction = False

    def next(self):
        if len(self.data) < self.swingLen + 1:
            return
        
        # Get current values
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        highest = self.highest_high[-1]
        lowest = self.lowest_low[-1]
        
        # Skip if indicators not ready
        if pd.isna(highest) or pd.isna(lowest):
            return
        
        # Determine direction
        if current_high == highest:
            self.direction = True
        if current_low == lowest:
            self.direction = False
        
        # Detect swing highs
        if len(self.data) > self.swingLen:
            prev_high = self.data.High[-2]
            prev_highest = self.highest_high[-2]
            
            if pd.notna(prev_highest) and prev_high == prev_highest and prev_high > highest:
                swing_high_price = prev_high
                swing_high_idx = len(self.data) - 2
                
                if self.prev_direction != self.direction and not self.direction:
                    if self.last_swing_price > 0:
                        pct_move = abs((swing_high_price - self.last_swing_price) / self.last_swing_price * 100)
                        bar_duration = swing_high_idx - self.last_swing_idx
                        self.percentages.append(pct_move)
                        self.durations.append(bar_duration)
                        
                        if len(self.percentages) > self.samples:
                            self.percentages.pop(0)
                            self.durations.pop(0)
                    
                    self.last_swing_price = swing_high_price
                    self.last_swing_idx = swing_high_idx
        
        # Detect swing lows
        if len(self.data) > self.swingLen:
            prev_low = self.data.Low[-2]
            prev_lowest = self.lowest_low[-2]
            
            if pd.notna(prev_lowest) and prev_low == prev_lowest and prev_low < lowest:
                swing_low_price = prev_low
                swing_low_idx = len(self.data) - 2
                
                if self.prev_direction != self.direction and self.direction:
                    if self.last_swing_price > 0:
                        pct_move = abs((swing_low_price - self.last_swing_price) / self.last_swing_price * 100)
                        bar_duration = swing_low_idx - self.last_swing_idx
                        self.percentages.append(pct_move)
                        self.durations.append(bar_duration)
                        
                        if len(self.percentages) > self.samples:
                            self.percentages.pop(0)
                            self.durations.pop(0)
                    
                    self.last_swing_price = swing_low_price
                    self.last_swing_idx = swing_low_idx
        
        # Generate forecast and trading signals
        if len(self.percentages) >= 2:
            if self.method == "Weighted":
                tw = 0.0
                wp = 0.0
                wb = 0.0
                for i, pct in enumerate(self.percentages):
                    w = i + 1.0
                    wp += pct * w
                    wb += self.durations[i] * w
                    tw += w
                fpct = wp / tw if tw > 0 else 0
            elif self.method == "Median":
                fpct = float(np.median(self.percentages))
            else:
                fpct = float(np.mean(self.percentages))
            
            # Calculate standard deviation for bands
            variance = sum((p - fpct) ** 2 for p in self.percentages) / len(self.percentages)
            stddev = np.sqrt(max(variance, 0))
            
            atr_val = self.atr[-1] if not pd.isna(self.atr[-1]) else 1.0
            band_half = max(self.data.Close[-1] * stddev / 100.0, atr_val * 0.1)
            
            # Trading logic based on swing direction and forecast
            is_bear = not self.direction
            
            if is_bear and fpct > 5:
                # Expecting downmove, sell
                if not self.position:
                    self.sell()
            elif not is_bear and fpct > 5:
                # Expecting upmove, buy
                if not self.position:
                    self.buy()
            
            # Exit logic on reversal
            if self.position:
                if is_bear and self.direction:
                    self.position.close()
                elif not is_bear and not self.direction:
                    self.position.close()
        
        self.prev_direction = self.direction


