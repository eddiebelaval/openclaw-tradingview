import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ribbonLen = 21
    cloudMult = 1.5
    atrLen = 14
    volMult = 1.0
    adxThresh = 20
    retestCooldown = 8
    useMomentum = True
    useVol = True
    useAdx = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume) if len(self.data.Volume) > 0 else pd.Series(0, index=close.index)
        
        # Calculate ATR
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atrLen) or pd.Series(0, index=close.index))
        
        # Calculate Hull-weighted midline using WMA
        def calc_hull_mid():
            half_len = max(int(self.ribbonLen / 2), 1)
            sqrt_len = max(int(np.sqrt(self.ribbonLen)), 1)
            wma1 = pta.wma(close, length=half_len)
            wma2 = pta.wma(close, length=self.ribbonLen)
            if wma1 is None or wma2 is None:
                return pd.Series(0, index=close.index)
            raw = wma1.fillna(close) * 2.0 - wma2.fillna(close)
            result = pta.wma(raw, length=sqrt_len)
            return result.fillna(close) if result is not None else pd.Series(close)
        
        self.midLine = self.I(calc_hull_mid)
        
        # Calculate fast and slow EMA for trend
        self.fastEma = self.I(lambda: pta.ema(close, length=max(int(self.ribbonLen / 2), 2)) or pd.Series(close))
        self.slowEma = self.I(lambda: pta.ema(close, length=self.ribbonLen) or pd.Series(close))
        
        # Calculate RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        
        # Calculate ADX
        def calc_adx():
            adx_result = pta.adx(high, low, close, length=14)
            if adx_result is None or 'ADX_14' not in adx_result.columns:
                return pd.Series(20, index=close.index)
            return adx_result['ADX_14'].fillna(20)
        
        self.adx = self.I(calc_adx)
        
        # Calculate volume SMA
        def calc_vol_sma():
            if volume.sum() == 0:
                return pd.Series(1, index=close.index)
            vol_sma = pta.sma(volume, length=20)
            return vol_sma.fillna(1) if vol_sma is not None else pd.Series(1, index=close.index)
        
        self.volSma = self.I(calc_vol_sma)
        
        # Tracking variables
        self.last_retest_bar = -999
        self.in_position = False
        self.position_type = None

    def next(self):
        if len(self) < 50:
            return
        
        # Current values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        mid = self.midLine[-1]
        atr_val = self.atr[-1]
        fast_ema = self.fastEma[-1]
        slow_ema = self.slowEma[-1]
        rsi = self.rsi[-1]
        adx = self.adx[-1]
        vol_sma = self.volSma[-1]
        
        # Trend detection
        trend_up = fast_ema > slow_ema
        trend_down = fast_ema < slow_ema
        
        # Cloud calculation
        envelope_width = atr_val * self.cloudMult
        upper_cloud = mid + envelope_width
        lower_cloud = mid - envelope_width
        
        # Filters
        vol_ok = (not self.useVol) or (volume > vol_sma * self.volMult)
        momentum_bull_ok = (not self.useMomentum) or (rsi > 40)
        momentum_bear_ok = (not self.useMomentum) or (rsi < 60)
        adx_ok = (not self.useAdx) or (adx > self.adxThresh)
        
        cooldown_ok = len(self) - self.last_retest_bar > self.retestCooldown
        
        # Retest signals
        bull_retest = (low <= upper_cloud and close > mid and close > self.data.Open[-1] 
                      and trend_up and cooldown_ok and vol_ok and momentum_bull_ok and adx_ok)
        
        bear_retest = (high >= lower_cloud and close < mid and close < self.data.Open[-1] 
                      and trend_down and cooldown_ok and vol_ok and momentum_bear_ok and adx_ok)
        
        # Exit logic
        if self.in_position:
            if self.position_type == "long":
                if trend_down or close < lower_cloud:
                    self.sell()
                    self.in_position = False
                    self.position_type = None
            elif self.position_type == "short":
                if trend_up or close > upper_cloud:
                    self.buy()
                    self.in_position = False
                    self.position_type = None
        
        # Entry logic
        if not self.in_position:
            if bull_retest:
                self.buy()
                self.in_position = True
                self.position_type = "long"
                self.last_retest_bar = len(self)
            elif bear_retest:
                self.sell()
                self.in_position = True
                self.position_type = "short"
                self.last_retest_bar = len(self)


