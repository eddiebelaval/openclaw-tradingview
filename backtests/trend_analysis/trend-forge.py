        if bull_entry and self.LongTrades and not self.position:
            self.buy()
        
        if bear_entry and self.ShortTrades and not self.position:
            self.sell()
        
        if bull_exit and self.position.is_long:
            self.sell()
        
        if bear_exit and self.position.is_short:
            self.buy()
        
        # Stop loss logic
        if self.position.is_long and self.long_stop_loss is not None:
            if close_val <= self.long_stop_loss:
                self.sell()
        
        if self.position.is_short and self.short_stop_loss is not None:
            if close_val >= self.short_stop_loss:
                self.buy()


