import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Trend_1 = "EMA"
    Trend1_Length = 21
    Trend_2 = "EMA"
    Trend2_Length = 55
    Trend_3 = "SMA"
    Trend3_Length = 89
    Multiplier = 2.5
    LongTrades = True
    ShortTrades = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hlc3 = (high + low + close) / 3
        
        # Trend 1 indicators
        ema1 = self.I(pta.ema, close, length=self.Trend1_Length)
        sma1 = self.I(pta.sma, close, length=self.Trend1_Length)
