        cci1 = self.I(pta.cci, high, low, close, length=self.Trend1_Length)
        
        esa1 = self.I(pta.ema, hlc3, length=self.Trend1_Length)
        d1 = self.I(pta.ema, np.abs(hlc3 - esa1), length=self.Trend1_Length)
        ci1 = (hlc3 - esa1) / (0.015 * d1 + 1e-10)
        wt1 = self.I(pta.ema, ci1, length=self.Trend1_Length)
        
        # Trend 2 indicators
        ema2 = self.I(pta.ema, close, length=self.Trend2_Length)
        sma2 = self.I(pta.sma, close, length=self.Trend2_Length)
        rsi2 = self.I(pta.rsi, close, length=self.Trend2_Length)
        cci2 = self.I(pta.cci, high, low, close, length=self.Trend2_Length)
        
        esa2 = self.I(pta.ema, hlc3, length=self.Trend2_Length)
        d2 = self.I(pta.ema, np.abs(hlc3 - esa2), length=self.Trend2_Length)
        ci2 = (hlc3 - esa2) / (0.015 * d2 + 1e-10)
        wt2 = self.I(pta.ema, ci2, length=self.Trend2_Length)
        
        # Trend 3 indicators
        ema3 = self.I(pta.ema, close, length=self.Trend3_Length)
        sma3 = self.I(pta.sma, close, length=self.Trend3_Length)
        rsi3 = self.I(pta.rsi, close, length=self.Trend3_Length)
        cci3 = self.I(pta.cci, high, low, close, length=self.Trend3_Length)
        
        esa3 = self.I(pta.ema, hlc3, length=self.Trend3_Length)
        d3 = self.I(pta.ema, np.abs(hlc3 - esa3), length=self.Trend3_Length)
        ci3 = (hlc3 - esa3) / (0.015 * d3 + 1e-10)
        wt3 = self.I(pta.ema, ci3, length=self.Trend3_Length)
        
        # Select which indicator to use based on trend type
        def select_trend_1():
            if self.Trend_1 == "EMA":
                return ema1
            elif self.Trend_1 == "SMA":
                return sma1
            elif self.Trend_1 == "RSI":
                return rsi1
            elif self.Trend_1 == "CCI":
                return cci1
            else:
                return wt1
        
        def select_trend_2():
            if self.Trend_2 == "EMA":
                return ema2
            elif self.Trend_2 == "SMA":
                return sma2
            elif self.Trend_2 == "RSI":
                return rsi2
            elif self.Trend_2 == "CCI":
                return cci2
            else:
                return wt2
        
        def select_trend_3():
            if self.Trend_3 == "EMA":
                return ema3
            elif self.Trend_3 == "SMA":
                return sma3
            elif self.Trend_3 == "RSI":
                return rsi3
            elif self.Trend_3 == "CCI":
                return cci3
            else:
                return wt3
        
        self.ma21 = self.I(select_trend_1)
        self.ma55 = self.I(select_trend_2)
        self.ma89 = self.I(select_trend_3)
        
