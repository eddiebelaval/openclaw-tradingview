        # State tracking
        self.bull_state = self.I(lambda: (self.ma21 < close) & (self.ma55 <= close) & (self.ma89 <= close))
        self.bear_state = self.I(lambda: (self.ma21 > close) & (self.ma55 > close) & (self.ma89 > close))
        
        # Store previous state for transition detection
        self.prev_bull = None
        self.prev_bear = None
