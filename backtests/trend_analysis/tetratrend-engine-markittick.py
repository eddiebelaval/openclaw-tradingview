import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime


class TvStrategy(Strategy):
    length1 = 20
    length2 = 50
    length3 = 100
    length4 = 200
    ma_type = 'SMA'
    adx_threshold = 20.0
    vol_length = 20
    rr_ratio = 2.0
    atr_period = 14
    dmi_period = 14
    swing_low_period = 10
    freeze_date = pd.Timestamp('2025-12-31 23:59')

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        if self.ma_type == 'SMA':
            self.ma1 = self.I(pta.sma, close, length=self.length1)
            self.ma2 = self.I(pta.sma, close, length=self.length2)
            self.ma3 = self.I(pta.sma, close, length=self.length3)
            self.ma4 = self.I(pta.sma, close, length=self.length4)
        elif self.ma_type == 'EMA':
            self.ma1 = self.I(pta.ema, close, length=self.length1)
            self.ma2 = self.I(pta.ema, close, length=self.length2)
            self.ma3 = self.I(pta.ema, close, length=self.length3)
            self.ma4 = self.I(pta.ema, close, length=self.length4)
        elif self.ma_type == 'WMA':
            self.ma1 = self.I(pta.wma, close, length=self.length1)
            self.ma2 = self.I(pta.wma, close, length=self.length2)
            self.ma3 = self.I(pta.wma, close, length=self.length3)
            self.ma4 = self.I(pta.wma, close, length=self.length4)
        elif self.ma_type == 'VWMA':
            self.ma1 = self.I(pta.vwma, close, volume, length=self.length1)
            self.ma2 = self.I(pta.vwma, close, volume, length=self.length2)
            self.ma3 = self.I(pta.vwma, close, volume, length=self.length3)
            self.ma4 = self.I(pta.vwma, close, volume, length=self.length4)
        else:
            self.ma1 = self.I(pta.sma, close, length=self.length1)
            self.ma2 = self.I(pta.sma, close, length=self.length2)
            self.ma3 = self.I(pta.sma, close, length=self.length3)
            self.ma4 = self.I(pta.sma, close, length=self.length4)

        self.atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        self.vol_sma = self.I(pta.sma, volume, length=self.vol_length)

        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.dmi_period))
        self.adx = self.I(lambda: adx_result['ADX'] if adx_result is not None and 'ADX' in adx_result.columns else pd.Series(50, index=close.index))

        self.swing_low = self.I(lambda: low.rolling(self.swing_low_period).min())

        self.frozen_ma1 = None
        self.frozen_ma2 = None
        self.frozen_ma3 = None
        self.frozen_ma4 = None
        self.frozen_atr = None
        self.is_frozen = False
        self.freeze_bar = None

        self.entry_price = None
        self.sl_price = None
        self.tp1_price = None
        self.tp2_price = None
        self.tp3_price = None

        self.in_trade = False

    def next(self):
        if not self.is_frozen and len(self.data) > 0:
            current_time = self.data.index[-1]
            if current_time >= self.freeze_date:
                self.frozen_ma1 = self.ma1[-1] if not np.isnan(self.ma1[-1]) else None
                self.frozen_ma2 = self.ma2[-1] if not np.isnan(self.ma2[-1]) else None
                self.frozen_ma3 = self.ma3[-1] if not np.isnan(self.ma3[-1]) else None
                self.frozen_ma4 = self.ma4[-1] if not np.isnan(self.ma4[-1]) else None
                self.frozen_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.0
                self.is_frozen = True
                self.freeze_bar = len(self.data)

        if not self.is_frozen:
            return

        if self.frozen_ma1 is None or np.isnan(self.ma1[-1]) or np.isnan(self.atr[-1]):
            return

        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        vol = self.data.Volume[-1]
        vol_sma_val = self.vol_sma[-1] if not np.isnan(self.vol_sma[-1]) else vol
        adx_val = self.adx[-1] if not np.isnan(self.adx[-1]) else 50.0
        swing_low_val = self.swing_low[-1] if not np.isnan(self.swing_low[-1]) else low_price
        atr_val = self.atr[-1]

        is_ranging = adx_val < self.adx_threshold or vol < vol_sma_val
        is_valid_trend = close_price > self.frozen_ma1

        price_above_ma1 = close_price > self.frozen_ma1
        prev_close = self.data.Close[-2] if len(self.data) > 1 else close_price
        prev_ma1 = self.ma1[-2] if len(self.ma1) > 1 else self.frozen_ma1

        price_cross_ma1 = (prev_close <= prev_ma1 and close_price > self.frozen_ma1) or \
                         (prev_close < self.frozen_ma1 and close_price >= self.frozen_ma1)

        is_valid_long = price_cross_ma1 and price_above_ma1 and is_valid_trend and not is_ranging

        if is_valid_long and not self.position:
            self.entry_price = close_price
            self.sl_price = swing_low_val - atr_val * 0.1
            risk_dist = self.entry_price - self.sl_price

            if risk_dist > 0:
                self.tp1_price = self.entry_price + (risk_dist * self.rr_ratio * 0.5)
                self.tp2_price = self.entry_price + (risk_dist * self.rr_ratio)
                self.tp3_price = self.entry_price + (risk_dist * self.rr_ratio * 1.5)
                self.buy()
                self.in_trade = True

        if self.position:
            if close_price <= self.sl_price:
                self.position.close()
                self.in_trade = False
            elif close_price >= self.tp3_price:
                self.position.close()
                self.in_trade = False
            elif close_price >= self.tp2_price:
                self.position.close()
                self.in_trade = False


