import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    min_wick_to_body_ratio = 3.0
    min_wick_to_range_percent = 0.65
    fast_length = 21
    slow_length = 100
    use_slope_filter = True

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # ZLEMA calculation
        def zlema_calc(src, length):
            lag = int((length - 1) / 2)
            adjusted = src + (src - src.shift(lag))
            return pta.ema(adjusted, length=length)

        self.fast_zlema = self.I(zlema_calc, close, self.fast_length)
        self.slow_zlema = self.I(zlema_calc, close, self.slow_length)

        # Candle structure calculations
        self.body = self.I(lambda: (close - open_).abs())
        self.candle_range = self.I(lambda: high - low)
        self.upper_wick = self.I(lambda: high - pd.concat([open_, close], axis=1).max(axis=1))
        self.lower_wick = self.I(lambda: pd.concat([open_, close], axis=1).min(axis=1) - low)

    def next(self):
        if len(self.data) < self.slow_length + 2:
            return

        # Current values
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        fast_z = self.fast_zlema[-1]
        slow_z = self.slow_zlema[-1]
        fast_z_prev = self.fast_zlema[-2]

        body = self.body[-1]
        candle_range = self.candle_range[-1]
        upper_wick = self.upper_wick[-1]
        lower_wick = self.lower_wick[-1]

        # Slope detection
        fast_slope_up = fast_z > fast_z_prev
        fast_slope_down = fast_z < fast_z_prev

        # Valid candle check
        valid_candle = candle_range > 0

        # Rejection logic
        bullish_raw = (
            valid_candle and
            lower_wick > body * self.min_wick_to_body_ratio and
            (lower_wick / candle_range) >= self.min_wick_to_range_percent and
            close > open_
        )

        bearish_raw = (
            valid_candle and
            upper_wick > body * self.min_wick_to_body_ratio and
            (upper_wick / candle_range) >= self.min_wick_to_range_percent and
            close < open_
        )

        # Trend conditions
        trend_bull = close > slow_z and fast_z > slow_z
        trend_bear = close < slow_z and fast_z < slow_z

        slope_bull = not self.use_slope_filter or fast_slope_up
        slope_bear = not self.use_slope_filter or fast_slope_down

        # Final signals
        bullish_signal = bullish_raw and trend_bull and slope_bull
        bearish_signal = bearish_raw and trend_bear and slope_bear

        # Trading logic
        if bullish_signal:
            self.buy()
        elif bearish_signal:
            self.sell()


