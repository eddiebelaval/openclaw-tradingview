import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters
    atr_length = 10
    sensitivity = 5.0
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hl2 = (high + low) / 2
        
        # EMA indicators
        self.ema9 = self.I(pta.ema, close, length=9)
        self.ema21 = self.I(pta.ema, close, length=21)
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        
        # RSI for trend bias
        self.rsi14 = self.I(pta.rsi, close, length=14)
        
        # ATR for normalization
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Adaptive Supertrend calculation
        min_mult = max(self.sensitivity - 4, 1)
        max_mult = min(self.sensitivity, 26)
        self.min_mult = min_mult
        self.max_mult = max_mult
        self.step_st = 0.5
        
        # Store supertrend values
        self.st_trend = self.I(self._calc_supertrend, high, low, close)
        
        # MACD for candle coloring and confirmation
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9) or pd.DataFrame(0, index=close.index, columns=['MACD_12_26_9', 'MACDh_12_26_9', 'MACDp_12_26_9']))
        self.macd = macd_result['MACD_12_26_9'] if 'MACD_12_26_9' in macd_result.columns else macd_result.iloc[:, 0]
        self.macd_hist = macd_result['MACDh_12_26_9'] if 'MACDh_12_26_9' in macd_result.columns else macd_result.iloc[:, 1]
        
        # Track position state
        self.position_state = 0

    def _calc_supertrend(self, high, low, close):
        """Calculate adaptive supertrend trend signal"""
        hl2 = (high + low) / 2
        atr_vals = pta.atr(high, low, close, length=self.atr_length)
        
        # Use middle multiplier from range
        factor = (self.min_mult + self.max_mult) / 2
        
        upper = hl2 + atr_vals * factor
        lower = hl2 - atr_vals * factor
        
        trend = pd.Series(0, index=close.index)
        for i in range(len(close)):
            if i == 0:
                trend.iloc[i] = 1
                continue
            if close.iloc[i] > upper.iloc[i-1]:
                trend.iloc[i] = 1
            elif close.iloc[i] < lower.iloc[i-1]:
                trend.iloc[i] = 0
            else:
                trend.iloc[i] = trend.iloc[i-1]
        
        return trend

    def _amf_score(self, is_buy):
        """AMF momentum score"""
        close_vals = pd.Series(self.data.Close)
        
        def dema(src, length):
            e1 = pta.ema(src, length=length)
            return 2 * e1 - pta.ema(e1, length=length)
        
        fast = dema(close_vals, 7)
        atr14 = pta.atr(pd.Series(self.data.High), pd.Series(self.data.Low), close_vals, length=14)
        
        n = 1.5 * (close_vals - fast) / (atr14 + 1e-10)
        sig = pta.ema(pta.sma(n * 100, length=10), length=10)
        line = pta.sma(n * 100, length=10)
        
        if is_buy:
            return 1.0 if line.iloc[-1] > sig.iloc[-1] else -0.6 if line.iloc[-1] < sig.iloc[-1] else 0.0
        else:
            return 1.0 if line.iloc[-1] < sig.iloc[-1] else -0.6 if line.iloc[-1] > sig.iloc[-1] else 0.0

    def _regime_score(self, is_buy):
        """Market regime score based on directional movement"""
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        # Simplified ADX calculation
        tr = pta.atr(high, low, close, length=1)
        pdm = pd.Series(0.0, index=close.index)
        mdm = pd.Series(0.0, index=close.index)
        
        for i in range(1, len(close)):
            up_move = high.iloc[i] - high.iloc[i-1]
            dn_move = low.iloc[i-1] - low.iloc[i]
            
            if up_move > dn_move and up_move > 0:
                pdm.iloc[i] = up_move
            if dn_move > up_move and dn_move > 0:
                mdm.iloc[i] = dn_move
        
        pdi = 100 * pta.rma(pdm, length=30) / (pta.atr(high, low, close, length=30) + 1e-10)
        mdi = 100 * pta.rma(mdm, length=30) / (pta.atr(high, low, close, length=30) + 1e-10)
        
        bull = pdi.iloc[-1] > mdi.iloc[-1]
        
        return 0.7 if (is_buy and bull) or (not is_buy and not bull) else -0.8

    def _nn_score(self, is_buy):
        """Neural network confidence score"""
        amf = self._amf_score(is_buy)
        regime = self._regime_score(is_buy)
        
        # Simple combined score
        score = (amf + regime) / 2
        score = max(-1, min(1, score))
        
        # Map -1..1 to 0..1 via sigmoid-like function
        return (score + 1) / 2

    def next(self):
        close = self.data.Close[-1]
        
        # Detect supertrend crossovers
        st_buy = self.st_trend[-1] > self.st_trend[-2]
        st_sell = self.st_trend[-1] < self.st_trend[-2]
        
        # EMA crossover conditions
        ema_bullish = self.ema9[-1] > self.ema21[-1] and self.ema50[-1] > self.ema200[-1]
        ema_bearish = self.ema9[-1] < self.ema21[-1] and self.ema50[-1] < self.ema200[-1]
        
        # MACD histogram confirmation
        macd_bullish = self.macd_hist[-1] > self.macd_hist[-2] and self.macd_hist[-1] > 0
        macd_bearish = self.macd_hist[-1] < self.macd_hist[-2] and self.macd_hist[-1] < 0
        
        # Buy signal: Supertrend reversal + EMA alignment + MACD confirmation
        if st_buy and ema_bullish and macd_bullish:
            confidence = self._nn_score(True)
            if confidence > 0.4 and not self.position:
                self.buy()
                self.position_state = 1
        
        # Sell signal: Supertrend reversal + EMA breakdown + MACD divergence
        if st_sell and ema_bearish and macd_bearish:
            confidence = self._nn_score(False)
            if confidence > 0.4 and self.position:
                self.sell()
                self.position_state = -1
        
        # RSI overbought/oversold exits
        if self.position_state == 1 and self.rsi14[-1] > 70:
            self.sell()
            self.position_state = 0
        
        if self.position_state == -1 and self.rsi14[-1] < 30:
            self.buy()
            self.position_state = 0


