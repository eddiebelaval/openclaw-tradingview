import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Pattern Detection
    pattern_range = 9
    pattern_offset = 0
    strict_mode = False
    
    # Pivot Settings
    pivot_left = 6
    pivot_right = 1
    
    # Level Management
    max_levels = 3
    level_strength_period = 50
    
    # Visual
    zone_width = 0.5
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for zone sizing
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Calculate pivot points
        self.pivot_high = self.I(self._calculate_pivot_high, high, self.pivot_left, self.pivot_right)
        self.pivot_low = self.I(self._calculate_pivot_low, low, self.pivot_left, self.pivot_right)
        
        # W pattern signal
        self.w_signal = self.I(self._detect_w_pattern, close)
        
        # M pattern signal
        self.m_signal = self.I(self._detect_m_pattern, close)
        
        # Support and resistance level tracking
        self.resistance_levels = []
        self.support_levels = []
        self.resistance_touches = []
        self.support_touches = []
    
    def _calculate_pivot_high(self, high):
        result = pd.Series(np.nan, index=high.index)
        for i in range(self.pivot_left + self.pivot_right, len(high)):
            window = high.iloc[i - self.pivot_left - self.pivot_right:i - self.pivot_right]
            if len(window) == self.pivot_left + 1:
                center = high.iloc[i - self.pivot_right]
                left = high.iloc[i - self.pivot_left - self.pivot_right:i - self.pivot_right].max()
                right = high.iloc[i - self.pivot_right + 1:i + 1].max() if i + 1 <= len(high) else high.iloc[-1]
                
                if center > left and center > right:
                    result.iloc[i - self.pivot_right] = center
        return result
    
    def _calculate_pivot_low(self, low):
        result = pd.Series(np.nan, index=low.index)
        for i in range(self.pivot_left + self.pivot_right, len(low)):
            window = low.iloc[i - self.pivot_left - self.pivot_right:i - self.pivot_right]
            if len(window) == self.pivot_left + 1:
                center = low.iloc[i - self.pivot_right]
                left = low.iloc[i - self.pivot_left - self.pivot_right:i - self.pivot_right].min()
                right = low.iloc[i - self.pivot_right + 1:i + 1].min() if i + 1 <= len(low) else low.iloc[-1]
                
                if center < left and center < right:
                    result.iloc[i - self.pivot_right] = center
        return result
    
    def _detect_w_pattern(self, close):
        result = pd.Series(0, index=close.index)
        
        for bar_idx in range(self.pattern_range + 5, len(close)):
            window = close.iloc[bar_idx - self.pattern_range:bar_idx].values
            
            # Simplified W pattern: two lows with a high in between
            if len(window) >= 5:
                first_low_idx = np.argmin(window[:2])
                mid_high_idx = first_low_idx + np.argmax(window[first_low_idx+1:first_low_idx+3]) + 1
                second_low_idx = mid_high_idx + np.argmin(window[mid_high_idx+1:]) + 1
                
                if (second_low_idx < len(window) and 
                    window[first_low_idx] > window[second_low_idx] and
                    window[mid_high_idx] > window[first_low_idx]):
                    result.iloc[bar_idx] = 1
        
        return result
    
    def _detect_m_pattern(self, close):
        result = pd.Series(0, index=close.index)
        
        for bar_idx in range(self.pattern_range + 5, len(close)):
            window = close.iloc[bar_idx - self.pattern_range:bar_idx].values
            
            # Simplified M pattern: two highs with a low in between
            if len(window) >= 5:
                first_high_idx = np.argmax(window[:2])
                mid_low_idx = first_high_idx + np.argmin(window[first_high_idx+1:first_high_idx+3]) + 1
                second_high_idx = mid_low_idx + np.argmax(window[mid_low_idx+1:]) + 1
                
                if (second_high_idx < len(window) and 
                    window[first_high_idx] < window[second_high_idx] and
                    window[mid_low_idx] < window[first_high_idx]):
                    result.iloc[bar_idx] = 1
        
        return result
    
    def next(self):
        # Update support and resistance levels based on pivot detection
        if not np.isnan(self.pivot_high[-1]):
            level = self.pivot_high[-1]
            if level not in self.resistance_levels:
                if len(self.resistance_levels) < self.max_levels:
                    self.resistance_levels.append(level)
                    self.resistance_touches.append(1)
            else:
                idx = self.resistance_levels.index(level)
                self.resistance_touches[idx] += 1
        
        if not np.isnan(self.pivot_low[-1]):
            level = self.pivot_low[-1]
            if level not in self.support_levels:
                if len(self.support_levels) < self.max_levels:
                    self.support_levels.append(level)
                    self.support_touches.append(1)
            else:
                idx = self.support_levels.index(level)
                self.support_touches[idx] += 1
        
        # W pattern (bullish) - buy signal
        if self.w_signal[-1] > 0 and not self.position:
            self.buy()
        
        # M pattern (bearish) - sell signal
        if self.m_signal[-1] > 0 and self.position:
            self.position.close()
        
        # Exit on resistance level touch
        if self.position:
            for resistance in self.resistance_levels:
                if self.data.High[-1] >= resistance:
                    self.position.close()
                    break
        
        # Buy on support level retest if not in position
        if not self.position:
            for support in self.support_levels:
                zone_size = self.atr[-1] * self.zone_width if not np.isnan(self.atr[-1]) else 0.1
                if (self.data.Low[-1] >= support - zone_size and 
                    self.data.Low[-1] <= support + zone_size):
                    self.buy()
                    break


