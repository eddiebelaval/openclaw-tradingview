import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing1Length = 20
    swing2Length = 50
    swing3Length = 100
    confluenceTolerance = 0.3
    minConfluence = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate swing highs and lows using rolling max/min
        self.swing_high_1 = self.I(
            lambda: high.rolling(window=self.swing1Length).max()
        )
        self.swing_low_1 = self.I(
            lambda: low.rolling(window=self.swing1Length).min()
        )
        
        self.swing_high_2 = self.I(
            lambda: high.rolling(window=self.swing2Length).max()
        )
        self.swing_low_2 = self.I(
            lambda: low.rolling(window=self.swing2Length).min()
        )
        
        self.swing_high_3 = self.I(
            lambda: high.rolling(window=self.swing3Length).max()
        )
        self.swing_low_3 = self.I(
            lambda: low.rolling(window=self.swing3Length).min()
        )
        
        # Store Fibonacci levels for confluence detection
        self.fib_levels_1 = None
        self.fib_levels_2 = None
        self.fib_levels_3 = None
        self.confluence_zones = []
        self.last_signal_bar = -100

    def calculate_fib_levels(self, high_val, low_val, is_uptrend):
        """Calculate Fibonacci retracement levels"""
        fib_ratios = [0.236, 0.382, 0.5, 0.618, 0.786, 1.272, 1.414, 1.618]
        
        if is_uptrend:
            fib_start = low_val
            fib_end = high_val
        else:
            fib_start = high_val
            fib_end = low_val
        
        fib_diff = fib_end - fib_start
        levels = []
        
        for ratio in fib_ratios:
            price = fib_start + (fib_diff * ratio)
            levels.append(price)
        
        return levels

    def find_confluence_zones(self, all_levels):
        """Find price levels with multiple Fibonacci confluences"""
        if not all_levels:
            return []
        
        confluence_zones = []
        all_levels_sorted = sorted(all_levels)
        
        for i, level in enumerate(all_levels_sorted):
            confluence_count = 0
            
            for j, other_level in enumerate(all_levels_sorted):
                if i != j:
                    diff_pct = abs(level - other_level) / level * 100
                    if diff_pct <= self.confluenceTolerance:
                        confluence_count += 1
            
            # Only add if significant confluence exists
            if confluence_count >= self.minConfluence - 1:
                # Check if not already in list
                is_new = True
                for existing_zone in confluence_zones:
                    if abs(level - existing_zone) / level * 100 <= self.confluenceTolerance:
                        is_new = False
                        break
                
                if is_new:
                    confluence_zones.append(level)
        
        return confluence_zones

    def check_proximity_to_confluence(self, current_price, confluence_zones):
        """Check if current price is near a confluence zone and return strength"""
        if not confluence_zones:
            return False, 0.0, None
        
        for zone_price in confluence_zones:
            dist_pct = abs(current_price - zone_price) / current_price * 100
            if dist_pct < 0.5:
                return True, dist_pct, zone_price
        
        return False, float('inf'), None

    def next(self):
        # Skip if insufficient data
        if len(self.data) < self.swing3Length + 10:
            return
        
        current_idx = len(self.data) - 1
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Get swing values
        swing_h1 = self.swing_high_1[-1]
        swing_l1 = self.swing_low_1[-1]
        swing_h2 = self.swing_high_2[-1]
        swing_l2 = self.swing_low_2[-1]
        swing_h3 = self.swing_high_3[-1]
        swing_l3 = self.swing_low_3[-1]
        
        if pd.isna(swing_h1) or pd.isna(swing_l1):
            return
        
        # Determine trends for each swing
        is_uptrend_1 = swing_l1 > swing_h1 if not pd.isna(swing_l1) and not pd.isna(swing_h1) else True
        is_uptrend_2 = swing_l2 > swing_h2 if not pd.isna(swing_l2) and not pd.isna(swing_h2) else True
        is_uptrend_3 = swing_l3 > swing_h3 if not pd.isna(swing_l3) and not pd.isna(swing_h3) else True
        
        # Calculate Fibonacci levels
        fib1 = self.calculate_fib_levels(swing_h1, swing_l1, is_uptrend_1)
        fib2 = self.calculate_fib_levels(swing_h2, swing_l2, is_uptrend_2)
        fib3 = self.calculate_fib_levels(swing_h3, swing_l3, is_uptrend_3)
        
        # Combine all levels
        all_fib_levels = fib1 + fib2 + fib3
        
        # Find confluence zones
        confluence_zones = self.find_confluence_zones(all_fib_levels)
        
        # Check proximity to confluence
        near_confluence, dist_to_zone, zone_price = self.check_proximity_to_confluence(
            current_close, confluence_zones
        )
        
        # Trading logic: Buy on confluence with uptrend confirmation
        # Sell on confluence with downtrend confirmation
        
        if near_confluence and current_idx > self.last_signal_bar + 5:
            # Check if price is approaching from below (potential support bounce)
            if current_close > zone_price and current_low < zone_price:
                if not self.position:
                    self.buy()
