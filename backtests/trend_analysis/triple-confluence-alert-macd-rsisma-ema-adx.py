import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MACD parameters
    macd_fast = 12
    macd_slow = 26
    macd_signal = 9
    
    # RSI parameters
    rsi_length = 14
    rsi_sma_len = 14
    
    # EMA parameters
    ema_mode = "Triple"
    ema_fast_len = 9
    ema_mid_len = 21
    ema_slow_len = 50
    
    # ADX parameters
    adx_length = 14
    adx_threshold = 20
    adx_enabled = True
    
    # Confluence window
    lookback = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_signal))
        self.macd_line = macd_result.iloc[:, 0] if macd_result is not None else pd.Series(0, index=close.index)
        self.macd_signal_line = macd_result.iloc[:, 1] if macd_result is not None else pd.Series(0, index=close.index)
        
        # RSI + RSI SMA
        self.rsi_val = self.I(lambda: pta.rsi(close, length=self.rsi_length) or pd.Series(50, index=close.index))
        self.rsi_sma = self.I(lambda: pta.sma(self.rsi_val, length=self.rsi_sma_len) or pd.Series(50, index=close.index))
        
        # EMA
        self.ema_fast = self.I(lambda: pta.ema(close, length=self.ema_fast_len) or pd.Series(close.iloc[0], index=close.index))
        self.ema_mid = self.I(lambda: pta.ema(close, length=self.ema_mid_len) or pd.Series(close.iloc[0], index=close.index))
        self.ema_slow = self.I(lambda: pta.ema(close, length=self.ema_slow_len) or pd.Series(close.iloc[0], index=close.index))
        
        # ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_length))
        self.adx_val = adx_result.iloc[:, 2] if adx_result is not None else pd.Series(0, index=close.index)
        
        # History tracking for confluence detection
        self.macd_bull_crosses = []
        self.macd_bear_crosses = []
        self.rsi_bull_crosses = []
        self.rsi_bear_crosses = []
        self.prev_bull_confluence = False
        self.prev_bear_confluence = False

    def next(self):
        # Current values
        macd_line = self.macd_line[-1]
        macd_signal = self.macd_signal_line[-1]
        rsi = self.rsi_val[-1]
        rsi_sma = self.rsi_sma[-1]
        ema_fast = self.ema_fast[-1]
        ema_mid = self.ema_mid[-1]
        ema_slow = self.ema_slow[-1]
        adx = self.adx_val[-1]
        
        # MACD crossovers
        macd_bull_cross = crossover(self.macd_line, self.macd_signal_line)
        macd_bear_cross = crossover(self.macd_signal_line, self.macd_line)
        
        if macd_bull_cross:
            self.macd_bull_crosses.append(len(self.data))
        if macd_bear_cross:
            self.macd_bear_crosses.append(len(self.data))
        
        # RSI crossovers
        rsi_bull_cross = crossover(self.rsi_val, self.rsi_sma)
        rsi_bear_cross = crossover(self.rsi_sma, self.rsi_val)
        
        if rsi_bull_cross:
            self.rsi_bull_crosses.append(len(self.data))
        if rsi_bear_cross:
            self.rsi_bear_crosses.append(len(self.data))
        
        # Check for recent crossovers within lookback window
        current_bar = len(self.data)
        macd_bull_recent = any(current_bar - bar <= self.lookback for bar in self.macd_bull_crosses)
        macd_bear_recent = any(current_bar - bar <= self.lookback for bar in self.macd_bear_crosses)
        rsi_bull_recent = any(current_bar - bar <= self.lookback for bar in self.rsi_bull_crosses)
        rsi_bear_recent = any(current_bar - bar <= self.lookback for bar in self.rsi_bear_crosses)
        
        # EMA conditions
        if self.ema_mode == "Triple":
            ema_bull_ok = ema_fast > ema_mid and ema_mid > ema_slow
            ema_bear_ok = ema_fast < ema_mid and ema_mid < ema_slow
        else:  # Dual mode
            ema_dual_bull = crossover(self.ema_fast, self.ema_slow)
            ema_dual_bear = crossover(self.ema_slow, self.ema_fast)
            ema_bull_ok = any(current_bar - bar <= self.lookback for bar in range(max(0, current_bar - self.lookback), current_bar + 1) 
                            if bar < len(self.data) and self.ema_fast[bar] > self.ema_slow[bar])
            ema_bear_ok = any(current_bar - bar <= self.lookback for bar in range(max(0, current_bar - self.lookback), current_bar + 1) 
                            if bar < len(self.data) and self.ema_fast[bar] < self.ema_slow[bar])
        
        # ADX filter
        adx_pass = not self.adx_enabled or (adx > self.adx_threshold)
        
        # Confluence detection
        bull_confluence = macd_bull_recent and rsi_bull_recent and ema_bull_ok and adx_pass
        bear_confluence = macd_bear_recent and rsi_bear_recent and ema_bear_ok and adx_pass
        
        # Edge detection - fire once per confluence event
        bull_trigger = bull_confluence and not self.prev_bull_confluence
        bear_trigger = bear_confluence and not self.prev_bear_confluence
        
        # Execute trades
        if bull_trigger and not self.position:
            self.buy()
        elif bear_trigger and self.position:
            self.position.close()
        
        # Update previous confluence states
        self.prev_bull_confluence = bull_confluence
        self.prev_bear_confluence = bear_confluence


