import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    normLength = 1000
    lookbackLeft = 21
    lookbackRight = 5
    rangeUpper = 60
    rangeLower = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        def calc_vol_norm():
            highest_vol = volume.rolling(window=self.normLength).max()
            vol_norm = (volume / highest_vol * 100.0).fillna(50)
            return vol_norm
        
        def calc_pivot_high():
            pivot_vals = []
            for i in range(len(close)):
                if i < self.lookbackLeft or i < self.lookbackRight:
                    pivot_vals.append(np.nan)
                else:
                    left_part = volume.iloc[i-self.lookbackLeft:i]
                    right_part = volume.iloc[i:i+self.lookbackRight]
                    if len(left_part) == self.lookbackLeft and len(right_part) == self.lookbackRight:
                        is_pivot = volume.iloc[i] > left_part.max() and volume.iloc[i] > right_part.max()
                        pivot_vals.append(volume.iloc[i] if is_pivot else np.nan)
                    else:
                        pivot_vals.append(np.nan)
            return pd.Series(pivot_vals, index=volume.index)
        
        self.vol_norm = self.I(calc_vol_norm)
        self.pivot_high = self.I(calc_pivot_high)
        self.last_pivot_vol = None
        self.last_pivot_low = None
        self.last_pivot_high = None
        self.last_pivot_bar = None
        self.bull_signal = False
        self.bear_signal = False

    def next(self):
        current_idx = len(self.data) - 1
        
        if current_idx < self.lookbackLeft + self.lookbackRight:
            return
        
        is_pivot = not np.isnan(self.pivot_high[-1])
        
        if is_pivot:
            self.last_pivot_vol = self.data.Volume[-1]
            self.last_pivot_low = self.data.Low[-1]
            self.last_pivot_high = self.data.High[-1]
            self.last_pivot_bar = current_idx
        
        self.bull_signal = False
        self.bear_signal = False
        
        if self.last_pivot_bar is not None:
            bars_since = current_idx - self.last_pivot_bar
            
            if self.rangeLower <= bars_since <= self.rangeUpper and is_pivot:
                vol_higher = self.data.Volume[-1] > self.last_pivot_vol
                price_lower = self.data.Low[-1] < self.last_pivot_low
                
                if vol_higher and price_lower:
                    self.bull_signal = True
                
                vol_lower = self.data.Volume[-1] < self.last_pivot_vol
                price_higher = self.data.High[-1] > self.last_pivot_high
                
                if vol_lower and price_higher:
                    self.bear_signal = True
        
        if self.bull_signal:
            if not self.position:
                self.buy()
        
        if self.bear_signal:
            if self.position:
                self.position.close()
            elif not self.position:
                pass


