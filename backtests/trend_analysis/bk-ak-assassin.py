import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Base parameters
    use_heikin = True
    
    # MA parameters
    ma_type = "ZLEMA"
    ma_main = 9
    ma_fast = 7
    ma_slow = 18
    alma_off = 0.85
    alma_sig = 6
    speed_factor = 0.75
    
    # Proto parameters
    proto_fast_len = 7
    proto_slow_len = 9
    proto_ma_type = "ZLEMA"
    
    # Directional parameters
    dir_fast_len = 7
    dir_slow_len = 18
    dir_ma_type = "ZLEMA"
    
    # Envelope/ATR
    env_len = 14
    env_mult = 0.9
    
    # Confluence
    require_regime_agree = True
    min_bar_gap = 1
    use_reversal_trigger = True
    
    # Trap detection
    trap_ma_compress = 0.15
    trap_require_cloud = True
    trap_require_mid_slow = True
    trap_fail_bars = 2
    
    # Risk/TP
    use_swing_sl = True
    tp_rr = 1.5
    
    # HTF
    use_htf_bias = True
    htf_timeframe_minutes = 60
    htf_bias_pair = "Custom"
    htf_ma_fast = 7
    htf_ma_slow = 18
    
    # Proto sweep
    pswp_window = 3
    pswp_reclaim = 0.5
    pcont_bars = 3

    def adj_len(self, x):
        return max(1, round(x * self.speed_factor))

    def ma_fun(self, src, length, ma_type):
        adj_length = self.adj_len(length)
        if ma_type == "SMA":
            return pta.sma(src, length=adj_length)
        elif ma_type == "EMA":
            return pta.ema(src, length=adj_length)
        elif ma_type == "WMA":
            return pta.wma(src, length=adj_length)
        elif ma_type == "ZLEMA":
            lag = max(0, (adj_length - 1) // 2)
            zlema_src = src + (src - src.shift(lag))
            return pta.ema(zlema_src, length=adj_length)
        elif ma_type == "ALMA":
            return pta.alma(src, length=adj_length, offset=self.alma_off, sigma=self.alma_sig)
        else:
            return pta.ema(src, length=adj_length)

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_price = pd.Series(self.data.Open)
        
        # Heikin Ashi calculation
        if self.use_heikin:
            ha_close = (open_price + high + low + close) / 4
            ha_open = ha_close.shift(1).fillna((open_price + close) / 2)
            for i in range(1, len(ha_open)):
                if pd.isna(ha_open.iloc[i]):
                    ha_open.iloc[i] = (ha_open.iloc[i-1] + ha_close.iloc[i-1]) / 2
            ha_high = pd.concat([high, ha_open, ha_close], axis=1).max(axis=1)
            ha_low = pd.concat([low, ha_open, ha_close], axis=1).min(axis=1)
        else:
            ha_open = open_price
            ha_close = close
            ha_high = high
            ha_low = low
        
        # Main MAs
        self.ma_open = self.I(self.ma_fun, ha_open, self.ma_main, self.ma_type)
        self.ma_close = self.I(self.ma_fun, ha_close, self.ma_main, self.ma_type)
        self.ma_high = self.I(self.ma_fun, ha_high, self.ma_main, self.ma_type)
        self.ma_low = self.I(self.ma_fun, ha_low, self.ma_main, self.ma_type)
        
        self.ma_fast = self.I(self.ma_fun, ha_close, self.ma_fast, self.ma_type)
        self.ma_mid = self.I(self.ma_fun, ha_close, self.ma_main, self.ma_type)
        self.ma_slow = self.I(self.ma_fun, ha_close, self.ma_slow, self.ma_type)
        
        # Proto MAs
        self.proto_fast = self.I(self.ma_fun, ha_close, self.proto_fast_len, self.proto_ma_type)
        self.proto_slow = self.I(self.ma_fun, ha_close, self.proto_slow_len, self.proto_ma_type)
        
        # Directional MAs
        self.dir_fast = self.I(self.ma_fun, ha_close, self.dir_fast_len, self.dir_ma_type)
        self.dir_slow = self.I(self.ma_fun, ha_close, self.dir_slow_len, self.dir_ma_type)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.adj_len(self.env_len))

    def next(self):
        if len(self.data) < max(self.ma_main, self.ma_slow, self.proto_slow_len, self.dir_slow_len, self.env_len) + 5:
            return
        
        # Current values
        fast = self.ma_fast[-1]
        slow = self.ma_slow[-1]
        mid = self.ma_mid[-1]
        
        proto_fast = self.proto_fast[-1]
        proto_slow = self.proto_slow[-1]
        
        dir_fast = self.dir_fast[-1]
        dir_slow = self.dir_slow[-1]
        
        ma_open = self.ma_open[-1]
        ma_close = self.ma_close[-1]
        
        # Trend determination
        body_hi = max(ma_open, ma_close)
        body_lo = min(ma_open, ma_close)
        body_ht = max(body_hi - body_lo, 0.0001)
        
        ak13_trend = 100.0 * (ma_close - ma_open) / body_ht if body_ht > 0 else 0
        alpha_reg = 1 if fast > slow else -1 if fast < slow else 0
        
        bull_ok = ak13_trend > 0 and alpha_reg == 1
        bear_ok = ak13_trend < 0 and alpha_reg == -1
        
        # Proto crosses
        proto_bull_cross = crossover(self.proto_fast, self.proto_slow)
        proto_bear_cross = crossover(self.proto_slow, self.proto_fast)
        
        # Directional crosses
        dir_bull_cross = crossover(self.dir_fast, self.dir_slow)
        dir_bear_cross = crossover(self.dir_slow, self.dir_fast)
        
        # Simple entry/exit logic
        if not self.position:
            # Entry on directional bull cross with proper conditions
            if dir_bull_cross and bull_ok and mid > slow:
                self.buy()
            # Entry on directional bear cross with proper conditions
            elif dir_bear_cross and bear_ok and mid < slow:
                self.sell()
        else:
            # Exit long on bear cross or trend reversal
            if self.position.is_long and (dir_bear_cross or (alpha_reg == -1 and not bull_ok)):
                self.position.close()
            # Exit short on bull cross or trend reversal
            elif self.position.is_short and (dir_bull_cross or (alpha_reg == 1 and not bear_ok)):
                self.position.close()


