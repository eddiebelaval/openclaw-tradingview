import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Regime Settings
    lookbackBars = 50
    emaFastLen = 20
    emaMidLen = 50
    emaSlowLen = 100
    
    # Bull Trend Definition
    bullAboveFast = 0.80
    bullAboveMid = 0.90
    bullAboveSlow = 1.00
    
    # Bear Trend Definition
    bearBelowFast = 0.80
    bearBelowMid = 0.90
    bearBelowSlow = 1.00

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMAs
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaMid = self.I(pta.ema, close, length=self.emaMidLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)
        
        # Calculate percentage of closes above/below each EMA
        def calc_above_fast():
            return pd.Series(np.where(close > self.emaFast, 1.0, 0.0), index=close.index).rolling(self.lookbackBars).mean()
        
        def calc_above_mid():
            return pd.Series(np.where(close > self.emaMid, 1.0, 0.0), index=close.index).rolling(self.lookbackBars).mean()
        
        def calc_above_slow():
            return pd.Series(np.where(close > self.emaSlow, 1.0, 0.0), index=close.index).rolling(self.lookbackBars).mean()
        
        def calc_below_fast():
            return pd.Series(np.where(close < self.emaFast, 1.0, 0.0), index=close.index).rolling(self.lookbackBars).mean()
        
        def calc_below_mid():
            return pd.Series(np.where(close < self.emaMid, 1.0, 0.0), index=close.index).rolling(self.lookbackBars).mean()
        
        def calc_below_slow():
            return pd.Series(np.where(close < self.emaSlow, 1.0, 0.0), index=close.index).rolling(self.lookbackBars).mean()
        
        self.pAboveFast = self.I(calc_above_fast)
        self.pAboveMid = self.I(calc_above_mid)
        self.pAboveSlow = self.I(calc_above_slow)
        
        self.pBelowFast = self.I(calc_below_fast)
        self.pBelowMid = self.I(calc_below_mid)
        self.pBelowSlow = self.I(calc_below_slow)
        
        # Track previous regime
        self.prev_regime = None

    def next(self):
        # Check if we have enough data
        if len(self.data) < self.emaSlowLen + self.lookbackBars:
            return
        
        # Determine current regime
        bullTrend = (self.pAboveFast[-1] >= self.bullAboveFast and 
                     self.pAboveMid[-1] >= self.bullAboveMid and 
                     self.pAboveSlow[-1] >= self.bullAboveSlow)
        
        bearTrend = (self.pBelowFast[-1] >= self.bearBelowFast and 
                     self.pBelowMid[-1] >= self.bearBelowMid and 
                     self.pBelowSlow[-1] >= self.bearBelowSlow)
        
        # Determine regime: 1 = Bull, -1 = Bear, 0 = Range
        if bullTrend:
            current_regime = 1
        elif bearTrend:
            current_regime = -1
        else:
            current_regime = 0
        
        # Entry/Exit logic based on regime transitions
        if self.prev_regime != current_regime:
            # Closing existing position on regime change
            if self.position:
                self.position.close()
            
            # Entry logic based on new regime
            if current_regime == 1 and not self.position:
                # Bull regime: enter long
                self.buy()
            elif current_regime == -1 and not self.position:
                # Bear regime: enter short
                self.sell()
            elif current_regime == 0 and self.position:
                # Range regime: close any position
                self.position.close()
        
        # Update previous regime
        self.prev_regime = current_regime


