import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Volume Profile parameters
    bins = 30
    hvn_pct = 75.0
    lvn_pct = 25.0
    daily_bins = 20

    def init(self):
        # Initialize tracking variables
        self.poc_price = None
        self.hvn_zones = []
        self.lvn_zones = []
        self.daily_lvn_zone = None
        self.last_bar_processed = -1

    def next(self):
        # Only process on the last bar to avoid excessive computation
        if len(self.data) == self.last_bar_processed:
            return
        
        self.last_bar_processed = len(self.data)
        
        # Use visible range (last N bars where N is meaningful)
        lookback = min(len(self.data), 500)
        
        if lookback < 2:
            return
        
        # Extract OHLCV data for the lookback period
        closes = self.data.Close[-lookback:]
        highs = self.data.High[-lookback:]
        lows = self.data.Low[-lookback:]
        volumes = self.data.Volume[-lookback:]
        
        # Calculate range
        range_high = highs.max()
        range_low = lows.min()
        
        bin_size = (range_high - range_low) / self.bins
        if bin_size <= 0:
            bin_size = 0.01
        
        # Accumulate volume into bins
        bin_vols = np.zeros(self.bins)
        
        for i in range(len(highs)):
            bar_h = highs.iloc[i]
            bar_l = lows.iloc[i]
            bar_v = volumes.iloc[i]
            wick_range = max(bar_h - bar_l, 0.01)
            
            for b in range(self.bins):
                bin_bottom = range_low + b * bin_size
                bin_top = bin_bottom + bin_size
                intersect_low = max(bar_l, bin_bottom)
                intersect_high = min(bar_h, bin_top)
                
                if intersect_high > intersect_low:
                    allocated = bar_v * (intersect_high - intersect_low) / wick_range
                    bin_vols[b] += allocated
        
        # Calculate thresholds
        sorted_vols = np.sort(bin_vols)
        hvn_idx = int(np.floor(self.bins * self.hvn_pct / 100.0))
        if hvn_idx >= self.bins:
            hvn_idx = self.bins - 1
        lvn_idx = int(np.floor(self.bins * self.lvn_pct / 100.0))
        if lvn_idx < 0:
            lvn_idx = 0
        
        hvn_thresh = sorted_vols[hvn_idx]
        lvn_thresh = sorted_vols[lvn_idx]
        
        # Find POC
        max_vol = bin_vols.max()
        poc_idx = np.argmax(bin_vols)
        self.poc_price = range_low + poc_idx * bin_size + bin_size / 2.0
        
        # Identify HVN and LVN zones
        self.hvn_zones = []
        self.lvn_zones = []
        
        for b in range(self.bins):
            vol = bin_vols[b]
            if vol == 0:
                continue
            
            bin_bottom = range_low + b * bin_size
            bin_top = bin_bottom + bin_size
            
            is_hvn = vol >= hvn_thresh
            is_lvn = vol <= lvn_thresh
            is_poc = b == poc_idx
            
            if is_hvn and not is_poc:
                self.hvn_zones.append((bin_bottom, bin_top))
            if is_lvn:
                self.lvn_zones.append((bin_bottom, bin_top))
        
        # Calculate daily LVN
        if len(self.data) >= self.daily_bins:
            day_lookback = min(len(self.data), 250)
            day_highs = self.data.High[-day_lookback:]
            day_lows = self.data.Low[-day_lookback:]
            day_volumes = self.data.Volume[-day_lookback:]
            
            day_high = day_highs.max()
            day_low = day_lows.min()
            
            day_bin_size = (day_high - day_low) / self.daily_bins
            if day_bin_size <= 0:
                day_bin_size = 0.01
            
            day_bin_vols = np.zeros(self.daily_bins)
            
            for i in range(len(day_highs)):
                bar_h = day_highs.iloc[i]
                bar_l = day_lows.iloc[i]
                bar_v = day_volumes.iloc[i]
                wick_range = max(bar_h - bar_l, 0.01)
                
                for b in range(self.daily_bins):
                    bin_bottom = day_low + b * day_bin_size
                    bin_top = bin_bottom + day_bin_size
                    i_low = max(bar_l, bin_bottom)
                    i_high = min(bar_h, bin_top)
                    
                    if i_high > i_low:
                        allocated = bar_v * (i_high - i_low) / wick_range
                        day_bin_vols[b] += allocated
            
            # Find lowest volume bin
            min_vol = float('inf')
            min_idx = -1
            for b in range(self.daily_bins):
                vol = day_bin_vols[b]
                if vol > 0 and vol < min_vol:
                    min_vol = vol
                    min_idx = b
            
            if min_idx >= 0:
                daily_lvn_bot = day_low + min_idx * day_bin_size
                daily_lvn_top = daily_lvn_bot + day_bin_size
                self.daily_lvn_zone = (daily_lvn_bot, daily_lvn_top)
        
        # Trading Logic: Buy when price touches LVN and bounces, Sell at HVN or POC
        current_price = self.data.Close[-1]
        
        # Check if price is in a Daily LVN zone
        if self.daily_lvn_zone and not self.position:
            daily_lvn_bot, daily_lvn_top = self.daily_lvn_zone
            if daily_lvn_bot <= current_price <= daily_lvn_top:
                # Buy at daily LVN support
                self.buy()
        
        # Check if price is in a LVN zone from visible range
        if self.lvn_zones and not self.position:
            for lvn_bot, lvn_top in self.lvn_zones:
                if lvn_bot <= current_price <= lvn_top:
                    self.buy()
                    break
        
        # Sell at POC or HVN resistance
        if self.position:
            if self.poc_price and current_price >= self.poc_price:
                self.sell()
            else:
                for hvn_bot, hvn_top in self.hvn_zones:
                    if current_price >= hvn_top:
                        self.sell()
                        break


