import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 50
    threshold = 0.85

    def init(self):
        self.degreeH_series = []
        self.degreeL_series = []
        self.isHubH_series = []
        self.isHubL_series = []
        self.maxDegH = 5
        self.maxDegL = 5

    def next(self):
        # Calculate Natural Visibility Graph metrics
        current_idx = len(self.data) - 1
        
        # Calculate In-Degree for Highs
        degreeH = 0
        furthestVisIdxH = 0
        
        for i in range(1, min(self.lookback + 1, current_idx + 1)):
            isVisible = True
            slope = (self.data.High[current_idx] - self.data.High[current_idx - i]) / float(i)
            
            # Check intermediate obstructions
            for k in range(1, i):
                y_projected = self.data.High[current_idx] - (slope * k)
                if self.data.High[current_idx - k] >= y_projected:
                    isVisible = False
                    break
            
            if isVisible:
                degreeH += 1
                furthestVisIdxH = i
        
        # Calculate In-Degree for Lows
        degreeL = 0
        furthestVisIdxL = 0
        
        for i in range(1, min(self.lookback + 1, current_idx + 1)):
            isVisible = True
            slope = (self.data.Low[current_idx] - self.data.Low[current_idx - i]) / float(i)
            
            # Check intermediate obstructions
            for k in range(1, i):
                y_projected = self.data.Low[current_idx] - (slope * k)
                if self.data.Low[current_idx - k] <= y_projected:
                    isVisible = False
                    break
            
            if isVisible:
                degreeL += 1
                furthestVisIdxL = i
        
        # Dynamic thresholding
        if current_idx % int(self.lookback / 2) == 0:
            self.maxDegH = int(max(5, self.maxDegH * 0.95))
            self.maxDegL = int(max(5, self.maxDegL * 0.95))
        
        self.maxDegH = max(self.maxDegH, degreeH)
        self.maxDegL = max(self.maxDegL, degreeL)
        
        # Hub detection
        isHubH = degreeH >= self.maxDegH * self.threshold
        isHubL = degreeL >= self.maxDegL * self.threshold
        
        self.degreeH_series.append(degreeH)
        self.degreeL_series.append(degreeL)
        self.isHubH_series.append(isHubH)
        self.isHubL_series.append(isHubL)
        
        # Trading logic based on hub detection
        if len(self.isHubH_series) >= 2:
            prev_isHubH = self.isHubH_series[-2]
            curr_isHubH = self.isHubH_series[-1]
            
            prev_isHubL = self.isHubL_series[-2]
            curr_isHubL = self.isHubL_series[-1]
            
            # Buy signal: transition from no high hub to high hub (potential reversal from valley)
            if not prev_isHubL and curr_isHubL and not self.position:
                self.buy()
            
            # Sell signal: transition from no low hub to low hub (potential reversal from peak)
            elif not prev_isHubH and curr_isHubH and self.position:
                self.sell()
            
            # Alternative: Exit long on high hub detection
            elif curr_isHubH and self.position:
                self.sell()


