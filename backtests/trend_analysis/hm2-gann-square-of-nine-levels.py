import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_mode = "Auto"
    manual_pivot = 0.0
    period = 64
    step_back = 10
    rotations = 2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate pivot
        lookback = self.period + self.step_back
        
        def calc_pivot():
            if self.pivot_mode == "Manual" and self.manual_pivot > 0:
                return pd.Series(self.manual_pivot, index=close.index)
            else:
                highest = high.rolling(window=lookback).max()
                lowest = low.rolling(window=lookback).min()
                return (highest + lowest) / 2.0
        
        self.pivot = self.I(calc_pivot)
        
        # Calculate Gann levels
        def calc_gann_up_90():
            sqrt_pivot = np.sqrt(self.pivot)
            return np.power(sqrt_pivot + 90.0 / 360.0, 2)
        
        def calc_gann_up_180():
            sqrt_pivot = np.sqrt(self.pivot)
            return np.power(sqrt_pivot + 180.0 / 360.0, 2)
        
        def calc_gann_up_360():
            sqrt_pivot = np.sqrt(self.pivot)
            return np.power(sqrt_pivot + 360.0 / 360.0, 2)
        
        def calc_gann_dn_90():
            sqrt_pivot = np.sqrt(self.pivot)
            v = sqrt_pivot - 90.0 / 360.0
            return np.where(v > 0, np.power(v, 2), np.nan)
        
        def calc_gann_dn_180():
            sqrt_pivot = np.sqrt(self.pivot)
            v = sqrt_pivot - 180.0 / 360.0
            return np.where(v > 0, np.power(v, 2), np.nan)
        
        def calc_gann_dn_360():
            sqrt_pivot = np.sqrt(self.pivot)
            v = sqrt_pivot - 360.0 / 360.0
            return np.where(v > 0, np.power(v, 2), np.nan)
        
        self.up_90 = self.I(calc_gann_up_90)
        self.up_180 = self.I(calc_gann_up_180)
        self.up_360 = self.I(calc_gann_up_360)
        self.dn_90 = self.I(calc_gann_dn_90)
        self.dn_180 = self.I(calc_gann_dn_180)
        self.dn_360 = self.I(calc_gann_dn_360)

    def next(self):
        # Get current values
        current_price = self.data.Close[-1]
        pivot_val = self.pivot[-1]
        up_90_val = self.up_90[-1]
        up_180_val = self.up_180[-1]
        up_360_val = self.up_360[-1]
        dn_90_val = self.dn_90[-1] if not np.isnan(self.dn_90[-1]) else None
        dn_180_val = self.dn_180[-1] if not np.isnan(self.dn_180[-1]) else None
        dn_360_val = self.dn_360[-1] if not np.isnan(self.dn_360[-1]) else None
        
        # Need at least 2 bars to detect crossover
        if len(self.data) < 2:
            return
        
        prev_price = self.data.Close[-2]
        
        # Entry: Buy when price crosses above support levels (from below)
        # Exit: Sell when price crosses above resistance levels
        
        # Strong signal: crossing 360° level (full cycle)
        if dn_360_val is not None:
            if prev_price <= dn_360_val and current_price > dn_360_val:
                if not self.position:
                    self.buy()
        
        if prev_price <= up_360_val and current_price > up_360_val:
            if self.position:
                self.position.close()
        
        # Medium signal: crossing 180° level
        if dn_180_val is not None:
            if prev_price <= dn_180_val and current_price > dn_180_val:
                if not self.position:
                    self.buy()
        
        if prev_price <= up_180_val and current_price > up_180_val:
            if self.position:
                self.position.close()
        
        # Standard signal: crossing 90° level
        if dn_90_val is not None:
            if prev_price <= dn_90_val and current_price > dn_90_val:
                if not self.position:
                    self.buy()
        
        if prev_price <= up_90_val and current_price > up_90_val:
            if self.position:
                self.position.close()
        
        # Sell signal: price crossing below pivot
        if prev_price >= pivot_val and current_price < pivot_val:
            if self.position:
                self.position.close()


