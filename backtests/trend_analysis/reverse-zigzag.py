import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    devPct = 5.0
    depth = 10
    minLegBars = 2
    maxBars = 500
    confirmedOnly = False

    def init(self):
        self.pivot_prices = []
        self.pivot_bars = []
        self.pivot_types = []
        self.last_zigzag_price = None
        self.zigzag_direction = 0

    def next(self):
        if len(self.data) < self.depth:
            return

        lookback = min(self.maxBars, len(self.data) - 1)
        dev = self.devPct / 100.0

        # PASS 1: Find ALL pivots (deviation only)
        # Phase 1: Find the first pivot from the right
        runHi = self.data.High[-1]
        runHiOff = 0
        runLo = self.data.Low[-1]
        runLoOff = 0
        dir = 0
        startOff = 1

        for i in range(1, min(lookback + 1, len(self.data))):
            if self.data.High[-i] > runHi:
                runHi = self.data.High[-i]
                runHiOff = i
            if self.data.Low[-i] < runLo:
                runLo = self.data.Low[-i]
                runLoOff = i

            if i >= self.depth and (runHi / runLo - 1.0) >= dev and runHiOff != runLoOff:
                beyondBoth = max(runHiOff, runLoOff) + 1
                if runHiOff < runLoOff:
                    if len(self.pivot_prices) == 0 or self.pivot_prices[-1] != runHi:
                        self.pivot_prices.append(runHi)
                        self.pivot_bars.append(len(self.data) - runHiOff)
                        self.pivot_types.append(1)
                        self.zigzag_direction = -1
                    dir = -1
                    startOff = beyondBoth
                else:
                    if len(self.pivot_prices) == 0 or self.pivot_prices[-1] != runLo:
                        self.pivot_prices.append(runLo)
                        self.pivot_bars.append(len(self.data) - runLoOff)
                        self.pivot_types.append(-1)
                        self.zigzag_direction = 1
                    dir = 1
                    startOff = beyondBoth
                break

        # Phase 2: Walk backwards — pure deviation logic
        if dir != 0:
            extreme = runLo if dir == -1 else runHi
            extremeOff = runLoOff if dir == -1 else runHiOff

            for i in range(startOff, min(lookback + 1, len(self.data))):
                h = self.data.High[-i]
                l = self.data.Low[-i]

                if dir == -1:
                    if l < extreme:
                        extreme = l
                        extremeOff = i
                    elif h >= extreme * (1.0 + dev):
                        if len(self.pivot_prices) == 0 or self.pivot_prices[-1] != extreme:
                            self.pivot_prices.append(extreme)
                            self.pivot_bars.append(len(self.data) - extremeOff)
                            self.pivot_types.append(-1)
                        dir = 1
                        extreme = h
                        extremeOff = i
                        self.zigzag_direction = 1

                elif dir == 1:
                    if h > extreme:
                        extreme = h
                        extremeOff = i
                    elif l <= extreme * (1.0 - dev):
                        if len(self.pivot_prices) == 0 or self.pivot_prices[-1] != extreme:
                            self.pivot_prices.append(extreme)
                            self.pivot_bars.append(len(self.data) - extremeOff)
                            self.pivot_types.append(1)
                        dir = -1
                        extreme = l
                        extremeOff = i
                        self.zigzag_direction = -1

            # Push the last unconfirmed extreme
            if not self.confirmedOnly and len(self.pivot_prices) > 0:
                lastP = self.pivot_prices[-1]
                if extreme != lastP:
                    self.pivot_prices.append(extreme)
                    self.pivot_bars.append(len(self.data) - extremeOff)
                    self.pivot_types.append(1 if dir == 1 else -1)
                    self.last_zigzag_price = extreme

        # PASS 2: Remove short legs (minLegBars filter)
        if self.minLegBars > 1:
            changed = True
            safety = 0
            maxIter = len(self.pivot_prices)

            while changed and safety < maxIter:
                changed = False
                safety += 1

                sz = len(self.pivot_prices)
                if sz < 3:
                    break

                shortIdx = -1
                shortBars = self.maxBars + 1

