import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    tolerance = 0.05
    use_rsi = True
    rsi_strength = 5
    expiryBars = 500
    sweepType = "body"
    showPDHL = True
    showPWHL = True
    levelLookback = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.rsi = self.I(pta.rsi, close, length=14)
        
        self.varian = self.I(
            lambda: pd.Series(
                np.abs(high.values - np.roll(high.values, 1)),
                index=high.index
            )
        )
        
        self.smoothvar = self.I(
            lambda: pta.ema(
                pd.Series(
                    np.abs(high.values - np.roll(high.values, 1)),
                    index=high.index
                ),
                length=500
            )
        )
        
        self.eqh_zones = []
        self.eql_zones = []
        self.pdh_value = None
        self.pdl_value = None
        self.pwh_value = None
        self.pwl_value = None
        self.pdhSwept = False
        self.pdlSwept = False
        self.pwhSwept = False
        self.pwlSwept = False
        self.sweepsToday = 0
        self.last_day = None
        self.last_week = None
        self.bull_sweep_bar = False
        self.bear_sweep_bar = False

    def next(self):
        idx = len(self.data) - 1
        current_date = pd.Timestamp(self.data.index[idx])
        
        if self.last_day is None or current_date.date() != self.last_day.date():
            self.sweepsToday = 0
            self.pdhSwept = False
            self.pdlSwept = False
            self.last_day = current_date

        if self.last_week is None or current_date.isocalendar()[1] != self.last_week.isocalendar()[1]:
            self.pwhSwept = False
            self.pwlSwept = False
            self.last_week = current_date

        if idx >= 1:
            self.pdh_value = self.data.High[idx - 1]
            self.pdl_value = self.data.Low[idx - 1]

        if idx >= 7:
            week_start = max(0, idx - 7)
            self.pwh_value = np.max(self.data.High[week_start:idx])
            self.pwl_value = np.min(self.data.Low[week_start:idx])

        self.bull_sweep_bar = False
        self.bear_sweep_bar = False

        if idx >= 500 and self.smoothvar[-1] is not None:
            varian_val = abs(self.data.High[idx] - self.data.High[idx - 1])
            eqh_raw = varian_val < self.smoothvar[-1] * self.tolerance
            eql_raw = abs(self.data.Low[idx] - self.data.Low[idx - 1]) < self.smoothvar[-1] * self.tolerance

            rsi_eqh = True
            rsi_eql = True
            if self.use_rsi and self.rsi[-1] is not None:
                rsi_eqh = self.rsi[-1] > 50 + self.rsi_strength
                rsi_eql = self.rsi[-1] < 50 - self.rsi_strength

            eqh_prev = False
            eql_prev = False
            if idx >= 1:
                varian_prev = abs(self.data.High[idx - 1] - self.data.High[idx - 2]) if idx >= 2 else 0
                eqh_prev = varian_prev < self.smoothvar[-1] * self.tolerance
                eql_prev = abs(self.data.Low[idx - 1] - self.data.Low[idx - 2]) < self.smoothvar[-1] * self.tolerance if idx >= 2 else False

            create_eqh = eqh_raw and rsi_eqh and not eqh_prev
            create_eql = eql_raw and rsi_eql and not eql_prev

            if create_eqh:
                wick_level = max(self.data.High[idx], self.data.High[idx - 1])
                self.eqh_zones.append({'level': wick_level, 'bar': idx, 'swept': False})

            if create_eql:
                wick_level = min(self.data.Low[idx], self.data.Low[idx - 1])
                self.eql_zones.append({'level': wick_level, 'bar': idx, 'swept': False})

        zones_to_remove = []
        for i, zone in enumerate(self.eqh_zones):
            age = idx - zone['bar']
            use_body = self.sweepType == "body"
            cross_body = self.data.Close[idx] > zone['level']
            cross_wick = self.data.High[idx] > zone['level']
            mitigated = cross_body if use_body else cross_wick

            if mitigated or age > self.expiryBars:
                if self.data.High[idx] > zone['level'] and self.data.Close[idx] < zone['level']:
                    self.bear_sweep_bar = True
                    self.sweepsToday += 1
                    zone['swept'] = True
                zones_to_remove.append(i)

        for i in reversed(zones_to_remove):
            self.eqh_zones.pop(i)

        zones_to_remove = []
        for i, zone in enumerate(self.eql_zones):
            age = idx - zone['bar']
            use_body = self.sweepType == "body"
            cross_body = self.data.Close[idx] < zone['level']
            cross_wick = self.data.Low[idx] < zone['level']
            mitigated = cross_body if use_body else cross_wick

            if mitigated or age > self.expiryBars:
                if self.data.Low[idx] < zone['level'] and self.data.Close[idx] > zone['level']:
                    self.bull_sweep_bar = True
                    self.sweepsToday += 1
                    zone['swept'] = True
                zones_to_remove.append(i)

        for i in reversed(zones_to_remove):
            self.eql_zones.pop(i)

        if self.showPDHL and self.pdh_value is not None:
            if not self.pdhSwept and self.data.High[idx] > self.pdh_value and self.data.Close[idx] < self.pdh_value:
                self.bear_sweep_bar = True
                self.sweepsToday += 1
                self.pdhSwept = True

            if not self.pdlSwept and self.data.Low[idx] < self.pdl_value and self.data.Close[idx] > self.pdl_value:
                self.bull_sweep_bar = True
                self.sweepsToday += 1
                self.pdlSwept = True

        if self.showPWHL and self.pwh_value is not None:
            if not self.pwhSwept and self.data.High[idx] > self.pwh_value and self.data.Close[idx] < self.pwh_value:
                self.bear_sweep_bar = True
                self.sweepsToday += 1
                self.pwhSwept = True

            if not self.pwlSwept and self.data.Low[idx] < self.pwl_value and self.data.Close[idx] > self.pwl_value:
                self.bull_sweep_bar = True
                self.sweepsToday += 1
                self.pwlSwept = True

        if self.bull_sweep_bar and not self.position:
            self.buy()
        elif self.bear_sweep_bar and self.position:
            self.sell()


