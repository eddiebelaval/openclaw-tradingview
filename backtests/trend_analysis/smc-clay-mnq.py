import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # SMC CLAY MNQ - Market Structure Indicator
    swings_length = 50
    equal_highs_lows_length = 3
    equal_highs_lows_threshold = 0.1
    internal_size = 5
    atr_length = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for volatility measure
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Track swing structure
        self.swing_high = self.I(lambda: high.rolling(self.swings_length).max())
        self.swing_low = self.I(lambda: low.rolling(self.swings_length).min())
        
        # Track internal structure
        self.internal_high = self.I(lambda: high.rolling(self.internal_size).max())
        self.internal_low = self.I(lambda: low.rolling(self.internal_size).min())
        
        # Track equal highs/lows
        self.equal_high = self.I(lambda: high.rolling(self.equal_highs_lows_length).max())
        self.equal_low = self.I(lambda: low.rolling(self.equal_highs_lows_length).min())
        
        # State tracking
        self.last_swing_high_price = None
        self.last_swing_low_price = None
        self.last_internal_high_price = None
        self.last_internal_low_price = None
        self.in_bullish_structure = False
        self.in_bearish_structure = False
        self.bullish_bos_triggered = False
        self.bearish_bos_triggered = False

    def next(self):
        if len(self.data) < self.swings_length:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Get current ATR for volatility filtering
        current_atr = self.atr[-1] if self.atr[-1] is not None else 0
        if current_atr == 0 or pd.isna(current_atr):
            current_atr = 1
        
        # Parse high/low based on volatility
        high_vol_bar = (high - low) >= (2 * current_atr)
        parsed_high = low if high_vol_bar else high
        parsed_low = high if high_vol_bar else low
        
        # Update swing structure
        swing_high_val = self.swing_high[-1]
        swing_low_val = self.swing_low[-1]
        
        if pd.notna(swing_high_val) and pd.notna(swing_low_val):
            if high > swing_high_val:
                # New swing high
                if self.last_swing_high_price is not None:
                    self.last_swing_high_price = swing_high_val
                else:
                    self.last_swing_high_price = swing_high_val
                self.in_bearish_structure = True
                self.in_bullish_structure = False
                self.bullish_bos_triggered = False
            
            if low < swing_low_val:
                # New swing low
                if self.last_swing_low_price is not None:
                    self.last_swing_low_price = swing_low_val
                else:
                    self.last_swing_low_price = swing_low_val
                self.in_bullish_structure = True
                self.in_bearish_structure = False
                self.bearish_bos_triggered = False
        
        # Bullish structure breakout (crossover swing low)
        if pd.notna(swing_low_val):
            if not self.in_bullish_structure and close > swing_low_val and self.last_swing_low_price is not None:
                if close > self.last_swing_low_price:
                    # Bullish BOS (Break of Structure)
                    self.in_bullish_structure = True
                    self.in_bearish_structure = False
                    self.bearish_bos_triggered = False
                    
                    if not self.position:
                        self.buy()
                    self.bullish_bos_triggered = True
        
        # Bearish structure breakout (crossunder swing high)
        if pd.notna(swing_high_val):
            if not self.in_bearish_structure and close < swing_high_val and self.last_swing_high_price is not None:
                if close < self.last_swing_high_price:
                    # Bearish BOS (Break of Structure)
                    self.in_bearish_structure = True
                    self.in_bullish_structure = False
                    self.bullish_bos_triggered = False
                    
                    if self.position:
                        self.sell()
                    self.bearish_bos_triggered = True
        
        # Exit logic based on structure reversals
        if self.position and self.in_bearish_structure:
            # Exit long on bearish structure confirmation
            if close < swing_low_val and len(self.data) > self.swings_length + 10:
                self.sell()
        
        if not self.position and self.in_bullish_structure:
            # Re-enter on bullish structure
            if close > swing_high_val and len(self.data) > self.swings_length + 10:
                self.buy()


