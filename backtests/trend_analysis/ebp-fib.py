import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fibLength = 5

    def init(self):
        pass

    def next(self):
        if len(self.data) < 2:
            return
        
        # EBP Logic
        current_low = self.data.Low[-1]
        current_high = self.data.High[-1]
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        
        prev_low = self.data.Low[-2]
        prev_high = self.data.High[-2]
        prev_close = self.data.Close[-2]
        prev_open = self.data.Open[-2]
        
        # Bullish Sweep: low < low[1] and close > open[1] and close > close[1]
        bullishSweep = (current_low < prev_low and 
                       current_close > prev_open and 
                       current_close > prev_close)
        
        # Bearish Sweep: high > high[1] and close < open[1] and close < close[1]
        bearishSweep = (current_high > prev_high and 
                       current_close < prev_open and 
                       current_close < prev_close)
        
        # Entry logic: Buy on bullish sweep, Sell on bearish sweep
        if bullishSweep:
            if not self.position:
                self.buy()
            elif self.position.is_short:
                self.position.close()
                self.buy()
        
        elif bearishSweep:
            if self.position:
                self.position.close()


