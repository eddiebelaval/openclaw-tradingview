import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend Following
    trend_ema_fast = 21
    trend_ema_slow = 50
    trend_ema_filter = 200
    
    # MA Ribbon
    ribbon_ma1 = 8
    ribbon_ma2 = 13
    ribbon_ma3 = 21
    ribbon_ma4 = 34
    ribbon_ma5 = 55
    ribbon_ma6 = 89
    ribbon_ma7 = 144
    ribbon_ma8 = 233
    ribbon_threshold = 6
    
    # Breakout
    breakout_length = 20
    breakout_atr_mult = 1.5
    
    # Mean Reversion
    bb_length = 20
    bb_mult = 2.0
    rsi_length = 14
    rsi_ob = 70
    rsi_os = 30
    
    # Risk Management
    atr_length = 14
    stop_atr_mult = 2.0
    tp_atr_mult = 3.0
    trailing_atr_mult = 1.5
    
    # Filters
    adx_length = 14
    adx_threshold = 20
    volume_mult = 1.2
    
    # Fibonacci
    fib_swing_lb = 15
    fib_min_atr = 1.0
    fib_zone = 0.6
    fib_wick_min = 0.25
    
    # Volatility
    bb_vr_length = 20
    bb_vr_mult = 2.0
    atr_percentile_length = 100
    vol_expansion_threshold = 1.5
    
    # Order Flow
    cvd_length = 20
    cvd_threshold = 0.6
    vwap_std_mult1 = 1.0
    vwap_std_mult2 = 2.0
    vwap_std_mult3 = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Trend EMAs
        self.ema_fast = self.I(pta.ema, close, length=self.trend_ema_fast)
        self.ema_slow = self.I(pta.ema, close, length=self.trend_ema_slow)
        self.ema_filter = self.I(pta.ema, close, length=self.trend_ema_filter)
        
        # ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_length))
        self.adx = self.I(lambda: adx_result['ADX_14'] if adx_result is not None and 'ADX_14' in adx_result else pd.Series(20, index=close.index))
        
        # Bollinger Bands
        bb_result = self.I(lambda: pta.bbands(close, length=self.bb_length, std=self.bb_mult))
        self.bb_upper = self.I(lambda: bb_result[f'BBU_{self.bb_length}_{self.bb_mult}'] if bb_result is not None else pd.Series(close.max(), index=close.index))
        self.bb_lower = self.I(lambda: bb_result[f'BBL_{self.bb_length}_{self.bb_mult}'] if bb_result is not None else pd.Series(close.min(), index=close.index))
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Volume SMA
        self.volume_sma = self.I(pta.sma, volume, length=20)
        
        # Highest/Lowest for breakout
        self.highest_high = self.I(lambda: high.rolling(self.breakout_length).max())
        self.lowest_low = self.I(lambda: low.rolling(self.breakout_length).min())
        
        # MA Ribbon
        self.r1 = self.I(pta.ema, close, length=self.ribbon_ma1)
        self.r2 = self.I(pta.ema, close, length=self.ribbon_ma2)
        self.r3 = self.I(pta.ema, close, length=self.ribbon_ma3)
        self.r4 = self.I(pta.ema, close, length=self.ribbon_ma4)
        self.r5 = self.I(pta.ema, close, length=self.ribbon_ma5)
        self.r6 = self.I(pta.ema, close, length=self.ribbon_ma6)
        self.r7 = self.I(pta.ema, close, length=self.ribbon_ma7)
        self.r8 = self.I(pta.ema, close, length=self.ribbon_ma8)
        
        # VWAP
        self.vwap = self.I(self._calc_vwap, close, high, low, volume)
        
        # Fibonacci swing detection
        self.fib_high = self.I(lambda: high.rolling(self.fib_swing_lb + 1).max())
        self.fib_low = self.I(lambda: low.rolling(self.fib_swing_lb + 1).min())

    def _calc_vwap(self, close, high, low, volume):
        hlc3 = (high + low + close) / 3
        vwap_sum = (volume * hlc3).rolling(self.cvd_length).sum()
        vol_sum = volume.rolling(self.cvd_length).sum()
        vwap = vwap_sum / vol_sum.replace(0, 1)
        return vwap.fillna(close)

    def next(self):
        if len(self.data) < self.trend_ema_filter:
            return
        
        # Get current values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        atr = self.atr[-1] if len(self.atr) > 0 else 0
        ema_fast = self.ema_fast[-1] if len(self.ema_fast) > 0 else close
        ema_slow = self.ema_slow[-1] if len(self.ema_slow) > 0 else close
        ema_filter = self.ema_filter[-1] if len(self.ema_filter) > 0 else close
        adx = self.adx[-1] if len(self.adx) > 0 else 20
        bb_upper = self.bb_upper[-1] if len(self.bb_upper) > 0 else close
        bb_lower = self.bb_lower[-1] if len(self.bb_lower) > 0 else close
        rsi = self.rsi[-1] if len(self.rsi) > 0 else 50
        volume_sma = self.volume_sma[-1] if len(self.volume_sma) > 0 else volume
        highest_high = self.highest_high[-1] if len(self.highest_high) > 0 else high
        lowest_low = self.lowest_low[-1] if len(self.lowest_low) > 0 else low
        vwap = self.vwap[-1] if len(self.vwap) > 0 else close
        
        # Ribbon alignment
        r1 = self.r1[-1] if len(self.r1) > 0 else close
        r2 = self.r2[-1] if len(self.r2) > 0 else close
        r3 = self.r3[-1] if len(self.r3) > 0 else close
        r4 = self.r4[-1] if len(self.r4) > 0 else close
        r5 = self.r5[-1] if len(self.r5) > 0 else close
        r6 = self.r6[-1] if len(self.r6) > 0 else close
        r7 = self.r7[-1] if len(self.r7) > 0 else close
        r8 = self.r8[-1] if len(self.r8) > 0 else close
        
        ribbon_bullish_count = sum([
            1 if r1 > r2 else 0,
            1 if r2 > r3 else 0,
            1 if r3 > r4 else 0,
            1 if r4 > r5 else 0,
            1 if r5 > r6 else 0,
            1 if r6 > r7 else 0,
            1 if r7 > r8 else 0,
        ])
        ribbon_bearish_count = 7 - ribbon_bullish_count
        ribbon_bullish = ribbon_bullish_count >= (self.ribbon_threshold - 1)
        ribbon_bearish = ribbon_bearish_count >= (self.ribbon_threshold - 1)
        
        # Filters
        volume_spike = volume > volume_sma * self.volume_mult
        is_trending = adx > self.adx_threshold
        is_ranging = not is_trending
        bullish_trend = ema_fast > ema_slow and close > ema_filter
        bearish_trend = ema_fast < ema_slow and close < ema_filter
        price_above_vwap = close > vwap
        price_below_vwap = close < vwap
        
        # Signals
        ema_cross_up = crossover(self.ema_fast, self.ema_slow)
        ema_cross_down = crossover(self.ema_slow, self.ema_fast)
        rsi_cross_up = crossover(self.rsi, self.rsi_os)
        rsi_cross_down = crossover(self.rsi_ob, self.rsi)
        
        # Strategy conditions
        trend_long = is_trending and bullish_trend and ema_cross_up and volume_spike
        trend_short = is_trending and bearish_trend and ema_cross_down and volume_spike
        
        if len(self.data) >= self.breakout_length + 1:
            breakout_long = close > self.data.High[-self.breakout_length - 1] and volume_spike and close > ema_filter
            breakout_short = close < self.data.Low[-self.breakout_length - 1] and volume_spike and close < ema_filter
        else:
            breakout_long = False
            breakout_short = False
        
        mean_reversion_long = is_ranging and close < bb_lower and rsi < self.rsi_os and rsi_cross_up
        mean_reversion_short = is_ranging and close > bb_upper and rsi > self.rsi_ob and rsi_cross_down
        
        # Combined conditions with filters
        long_condition = (trend_long or breakout_long or mean_reversion_long) and ribbon_bullish and price_above_vwap
        short_condition = (trend_short or breakout_short or mean_reversion_short) and ribbon_bearish and price_below_vwap
        
        # Execute trades
        if long_condition and not self.position:
            stop_loss = close - (atr * self.stop_atr_mult)
            take_profit = close + (atr * self.tp_atr_mult)
            self.buy()
        
        if short_condition and not self.position:
            stop_loss = close + (atr * self.stop_atr_mult)
            take_profit = close - (atr * self.tp_atr_mult)
            self.sell()
        
        # Exit logic
        if self.position and self.position.is_long:
            stop_loss = self.position.open_price - (atr * self.stop_atr_mult)
            if close <= stop_loss or (close >= self.position.open_price + (atr * self.tp_atr_mult)):
                self.position.close()
        
        if self.position and not self.position.is_long:
            stop_loss = self.position.open_price + (atr * self.stop_atr_mult)
            if close >= stop_loss or (close <= self.position.open_price - (atr * self.tp_atr_mult)):
                self.position.close()


