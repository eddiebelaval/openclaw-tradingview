import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Since this is a visual indicator without clear trading signals,
        # we'll create a simple trading rule based on price action
        # Buy on higher highs, sell on lower lows
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate 20-period highest high and lowest low for entry signals
        self.highest_20 = self.I(lambda: high.rolling(20).max())
        self.lowest_20 = self.I(lambda: low.rolling(20).min())
        
        # Calculate a simple SMA for trend confirmation
        self.sma_50 = self.I(pta.sma, close, length=50)

    def next(self):
        # Trading logic: Buy when price breaks above 20-bar high and above SMA50
        # Sell when price breaks below 20-bar low or drops below SMA50
        
        if len(self.data) < 51:
            return
        
        # Buy condition: price makes new 20-bar high and is above 50-SMA
        if (self.data.Close[-1] >= self.highest_20[-1] and 
            self.data.Close[-1] > self.sma_50[-1] and
            not self.position):
            self.buy()
        
        # Sell condition: price breaks below 20-bar low or closes below 50-SMA
        elif self.position and (self.data.Close[-1] <= self.lowest_20[-1] or 
                                self.data.Close[-1] < self.sma_50[-1]):
            self.position.close()


