            if breaker_bearish < self.ext_running_high - self.external_displacement and current_close < current_open:
                self.external_supply_signal = True
                self.ext_last_was_demand = False
                self.ext_first_signal = False
                self.ext_running_high = current_high
                self.ext_running_low = current_low
                self.supply_index = current_bar
        
