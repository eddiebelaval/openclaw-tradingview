import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Swing Detection Parameters
    use_auto_tf = True
    left_len_manual = 10
    right_len_manual = 5
    anchor_mode = "Auto"
    
    # Fib Levels Parameters
    use_382 = False
    use_705 = True
    use_786 = True
    show_ext = True
    pocket_mode = "0.618-0.705"
    
    def init(self):
        # Calculate ATR for reference
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Determine left and right lengths based on timeframe
        self.left_len = self.left_len_manual
        self.right_len = self.right_len_manual
        
        # Initialize pivot tracking
        self.pivot_high_prices = []
        self.pivot_high_bars = []
        self.pivot_low_prices = []
        self.pivot_low_bars = []
        
        self.swing_start_price = None
        self.swing_start_bar = None
        self.swing_start_type = None
        
        self.swing_end_price = None
        self.swing_end_bar = None
        self.swing_end_type = None
        
        self.in_pocket = False
        self.fib_618 = None
        self.fib_deep = None
        
    def detect_pivots(self):
        """Detect pivot highs and lows"""
        idx = len(self.data) - 1
        
        if idx < self.left_len + self.right_len:
            return
        
        # Get source data (using wick)
        high_prices = self.data.High
        low_prices = self.data.Low
        
        # Check for pivot high
        is_pivot_high = True
        if idx >= self.right_len:
            current_high = high_prices[idx - self.right_len]
            
            for i in range(1, self.left_len + 1):
                if idx - self.right_len - i >= 0:
                    if high_prices[idx - self.right_len - i] >= current_high:
                        is_pivot_high = False
                        break
            
            for i in range(1, self.right_len + 1):
                if idx - self.right_len + i < len(high_prices):
                    if high_prices[idx - self.right_len + i] >= current_high:
                        is_pivot_high = False
                        break
            
            if is_pivot_high:
                self.pivot_high_prices.append(current_high)
                self.pivot_high_bars.append(idx - self.right_len)
        
        # Check for pivot low
        is_pivot_low = True
        if idx >= self.right_len:
            current_low = low_prices[idx - self.right_len]
            
            for i in range(1, self.left_len + 1):
                if idx - self.right_len - i >= 0:
                    if low_prices[idx - self.right_len - i] <= current_low:
                        is_pivot_low = False
                        break
            
            for i in range(1, self.right_len + 1):
                if idx - self.right_len + i < len(low_prices):
                    if low_prices[idx - self.right_len + i] <= current_low:
                        is_pivot_low = False
                        break
            
            if is_pivot_low:
                self.pivot_low_prices.append(current_low)
                self.pivot_low_bars.append(idx - self.right_len)
    
    def update_swing_state(self):
        """Update swing state based on pivot detection"""
        if not self.pivot_high_prices and not self.pivot_low_prices:
            return
        
        # Process new pivot highs
        if self.pivot_high_prices:
            last_ph_price = self.pivot_high_prices[-1]
            last_ph_bar = self.pivot_high_bars[-1]
            
            if self.swing_start_type is None:
                self.swing_start_price = last_ph_price
                self.swing_start_bar = last_ph_bar
                self.swing_start_type = 1
            elif self.swing_start_type == 1:
                if last_ph_price >= self.swing_start_price:
                    self.swing_start_price = last_ph_price
                    self.swing_start_bar = last_ph_bar
            else:  # switching from low to high
                self.swing_end_price = last_ph_price
                self.swing_end_bar = last_ph_bar
                self.swing_end_type = 1
                self.swing_start_price = last_ph_price
                self.swing_start_bar = last_ph_bar
                self.swing_start_type = 1
        
        # Process new pivot lows
        if self.pivot_low_prices:
            last_pl_price = self.pivot_low_prices[-1]
            last_pl_bar = self.pivot_low_bars[-1]
            
            if self.swing_start_type is None:
                self.swing_start_price = last_pl_price
                self.swing_start_bar = last_pl_bar
                self.swing_start_type = -1
            elif self.swing_start_type == -1:
                if last_pl_price <= self.swing_start_price:
                    self.swing_start_price = last_pl_price
                    self.swing_start_bar = last_pl_bar
            else:  # switching from high to low
                self.swing_end_price = last_pl_price
                self.swing_end_bar = last_pl_bar
                self.swing_end_type = -1
                self.swing_start_price = last_pl_price
                self.swing_start_bar = last_pl_bar
                self.swing_start_type = -1
    
    def calculate_fib_levels(self):
        """Calculate Fibonacci levels based on current swing"""
        if (self.swing_start_price is None or self.swing_end_price is None or
            self.swing_start_price == self.swing_end_price):
            return
        
        diff = abs(self.swing_end_price - self.swing_start_price)
        
        if self.swing_start_type == -1 and self.swing_end_type == 1:
            # Upswing: fib levels below the high
            self.fib_618 = self.swing_end_price - 0.618 * diff
            if self.pocket_mode == "0.618-0.705":
                self.fib_deep = self.swing_end_price - 0.705 * diff
            else:
                self.fib_deep = self.swing_end_price - 0.786 * diff
        elif self.swing_start_type == 1 and self.swing_end_type == -1:
            # Downswing: fib levels above the low
            self.fib_618 = self.swing_end_price + 0.618 * diff
            if self.pocket_mode == "0.618-0.705":
                self.fib_deep = self.swing_end_price + 0.705 * diff
            else:
                self.fib_deep = self.swing_end_price + 0.786 * diff
    
    def check_pocket(self):
        """Check if price is in pocket zone"""
        if self.fib_618 is None or self.fib_deep is None or self.swing_start_type is None:
            self.in_pocket = False
            return
        
        current_price = self.data.Close[-1]
        
        if self.swing_start_type == -1 and self.swing_end_type == 1:
            # Upswing: pocket is between 0.618 and 0.705/0.786
            self.in_pocket = (current_price <= self.fib_618 and 
                             current_price >= self.fib_deep)
        elif self.swing_start_type == 1 and self.swing_end_type == -1:
            # Downswing: pocket is between 0.618 and 0.705/0.786
            self.in_pocket = (current_price >= self.fib_618 and 
                             current_price <= self.fib_deep)
        else:
            self.in_pocket = False
    
    def next(self):
        # Detect pivots each bar
        self.detect_pivots()
        
        # Update swing state
        self.update_swing_state()
        
        # Calculate fib levels
        self.calculate_fib_levels()
        
        # Check if price is in pocket
        self.check_pocket()
        
        # Trading logic: Buy when price enters pocket from above (upswing)
        if self.in_pocket and self.swing_start_type == -1 and self.swing_end_type == 1:
            if not self.position:
                self.buy()
        
        # Trading logic: Sell when price enters pocket from below (downswing)
        elif self.in_pocket and self.swing_start_type == 1 and self.swing_end_type == -1:
            if self.position:
                self.position.close()
        
        # Exit long if price breaks above the swing high
        elif self.position and self.swing_end_price is not None:
            if self.swing_start_type == -1 and self.data.Close[-1] > self.swing_end_price:
                self.position.close()
        
        # Exit short if price breaks below the swing low
        elif not self.position and self.swing_end_price is not None:
            if self.swing_start_type == 1 and self.data.Close[-1] < self.swing_end_price:
                self.buy()


