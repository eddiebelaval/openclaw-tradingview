        if sl is not None:
            self.swing_lows.append(sl)
            self.last_swing_low_price = sl
            # Cleanup old swings
            if len(self.swing_lows) > self.max_swings:
                self.swing_lows.pop(0)
            # Find equal lows
            self.find_equal_levels(self.swing_lows, zone_type=-1)
        
