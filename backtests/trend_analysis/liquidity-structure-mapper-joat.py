import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Swing Detection Parameters
    swing_left = 10
    swing_right = 5
    max_swings = 20
    
    # Equal Highs/Lows Parameters
    eq_threshold = 0.1
    eq_extend = 50
    
    # Liquidity Zones Parameters
    zone_lookback = 100
    min_touches = 2
    atr_buffer = 0.15
    
    def init(self):
        # Calculate ATR for zone detection and buffers
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Initialize state tracking
        self.swing_highs = []
        self.swing_lows = []
        self.liquidity_zones = []
        self.last_swing_high_price = None
        self.last_swing_low_price = None
        self.nearest_resistance = None
        self.nearest_support = None
        self.active_eqh_count = 0
        self.active_eql_count = 0
        
    def detect_swing_high(self):
        """Detect swing highs using pivot logic"""
        if len(self.data) < self.swing_left + self.swing_right + 1:
            return None
        
        idx = len(self.data) - 1 - self.swing_right
        if idx < self.swing_left:
            return None
        
        # Check if current bar (minus swing_right) is a pivot high
        current_high = self.data.High[idx]
        
        # Check left bars
        left_ok = all(current_high >= self.data.High[idx - i] for i in range(1, self.swing_left + 1))
        # Check right bars
        right_ok = all(current_high >= self.data.High[idx + i] for i in range(1, self.swing_right + 1))
        
        if left_ok and right_ok:
            return current_high
        return None
    
    def detect_swing_low(self):
        """Detect swing lows using pivot logic"""
        if len(self.data) < self.swing_left + self.swing_right + 1:
            return None
        
        idx = len(self.data) - 1 - self.swing_right
        if idx < self.swing_left:
            return None
        
        # Check if current bar (minus swing_right) is a pivot low
        current_low = self.data.Low[idx]
        
        # Check left bars
        left_ok = all(current_low <= self.data.Low[idx - i] for i in range(1, self.swing_left + 1))
        # Check right bars
        right_ok = all(current_low <= self.data.Low[idx + i] for i in range(1, self.swing_right + 1))
        
        if left_ok and right_ok:
            return current_low
        return None
    
    def pct_diff(self, p1, p2):
        """Calculate percentage difference between two prices"""
        if p1 == 0 or p2 == 0:
            return 100
        avg = (p1 + p2) / 2.0
        return abs(p1 - p2) / avg * 100
    
    def find_equal_levels(self, swings, zone_type):
        """Find equal highs/lows and create liquidity zones"""
        if len(swings) < 2:
            return
        
        latest = swings[-1]
        
        for i in range(len(swings) - 2, -1, -1):
            compare = swings[i]
            pct = self.pct_diff(latest, compare)
            
            if pct <= self.eq_threshold:
                zone_top = max(latest, compare)
                zone_bot = min(latest, compare)
                
                # Add small buffer
                atr_val = self.atr[-1] if len(self.atr) > 0 and self.atr[-1] is not None else 1
                zone_top += atr_val * 0.1
                zone_bot -= atr_val * 0.1
                
                zone = {
                    'top': zone_top,
                    'bottom': zone_bot,
                    'start_bar': len(self.data) - self.swing_right,
                    'touch_count': 2,
                    'is_active': True,
                    'zone_type': zone_type
                }
                
                self.liquidity_zones.append(zone)
                break
    
    def update_zone_interactions(self):
        """Track price interactions with liquidity zones"""
        if len(self.liquidity_zones) == 0:
            return
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        atr_val = self.atr[-1] if len(self.atr) > 0 and self.atr[-1] is not None else 1
        
        for zone in self.liquidity_zones:
            if not zone['is_active']:
                continue
            
            # Check if price swept the zone
            swept_high = zone['zone_type'] == 1 and current_high > zone['top']
            swept_low = zone['zone_type'] == -1 and current_low < zone['bottom']
            
            # Check for zone touches
            touching_high = zone['zone_type'] == 1 and current_high >= zone['bottom'] and current_high <= zone['top']
            touching_low = zone['zone_type'] == -1 and current_low <= zone['top'] and current_low >= zone['bottom']
            
            if (touching_high or touching_low) and not (swept_high or swept_low):
                zone['touch_count'] += 1
            
            if swept_high or swept_low:
                zone['is_active'] = False
    
    def calculate_structure_metrics(self):
        """Calculate nearest resistance, support, and zone counts"""
        self.nearest_resistance = None
        self.nearest_support = None
        self.active_eqh_count = 0
        self.active_eql_count = 0
        
        current_close = self.data.Close[-1]
        
        # Find nearest resistance from swing highs
        for sh in self.swing_highs:
            if sh > current_close:
                if self.nearest_resistance is None or sh < self.nearest_resistance:
                    self.nearest_resistance = sh
        
        # Find nearest support from swing lows
        for sl in self.swing_lows:
            if sl < current_close:
                if self.nearest_support is None or sl > self.nearest_support:
                    self.nearest_support = sl
        
        # Count active zones
        for zone in self.liquidity_zones:
            if zone['is_active']:
                if zone['zone_type'] == 1:
                    self.active_eqh_count += 1
                elif zone['zone_type'] == -1:
                    self.active_eql_count += 1
    
    def next(self):
        """Main trading logic"""
        # Detect new swing points
        sh = self.detect_swing_high()
        if sh is not None:
            self.swing_highs.append(sh)
            self.last_swing_high_price = sh
            # Cleanup old swings
            if len(self.swing_highs) > self.max_swings:
                self.swing_highs.pop(0)
            # Find equal highs
            self.find_equal_levels(self.swing_highs, zone_type=1)
        
