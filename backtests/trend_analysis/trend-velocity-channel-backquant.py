import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters from the Pine Script
    ma_len = 18
    crush_smooth = 5
    chan_pad = 0.5
    max_lvls = 8
    atr_len = 14
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Core calculations
        self.dema = self.I(pta.dema, close, length=self.ma_len)
        lag_ma_len = int(np.round(self.ma_len * 1.5))
        self.lag_ma = self.I(pta.ema, close, length=lag_ma_len)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Crush calculation
        def calc_raw_crush():
            dema_vals = self.dema
            lag_ma_vals = self.lag_ma
            atr_vals = self.atr
            if dema_vals is None or lag_ma_vals is None or atr_vals is None:
                return pd.Series(0, index=close.index)
            raw = (dema_vals - lag_ma_vals) / atr_vals.replace(0, 1)
            return raw
        
        self.raw_crush = self.I(calc_raw_crush)
        self.crush = self.I(pta.ema, self.raw_crush, length=self.crush_smooth)
        
        def calc_crush_abs():
            crush_vals = self.crush
            if crush_vals is None:
                return pd.Series(0, index=close.index)
            return crush_vals.abs()
        
        self.crush_abs = self.I(calc_crush_abs)
        
        def calc_crush_norm():
            crush_abs_vals = self.crush_abs
            if crush_abs_vals is None:
                return pd.Series(0, index=close.index)
            crush_high = crush_abs_vals.rolling(window=80).max()
            crush_norm = pd.Series(0, index=close.index)
            mask = crush_high > 0
            crush_norm[mask] = (crush_abs_vals[mask] / crush_high[mask]).clip(upper=1.0)
            return crush_norm
        
        self.crush_norm = self.I(calc_crush_norm)
        
        # Trend determination
        def calc_trend():
            crush_vals = self.crush
            if crush_vals is None:
                return pd.Series(1, index=close.index)
            trend = pd.Series(1, index=close.index)
            trend[crush_vals < 0] = -1
            return trend
        
        self.trend = self.I(calc_trend)
        
        # Detect trend flips
        def calc_flip():
            trend_vals = self.trend
            if trend_vals is None or len(trend_vals) < 2:
                return pd.Series(False, index=close.index)
            flip = pd.Series(False, index=close.index)
            flip.iloc[1:] = trend_vals.iloc[1:].values != trend_vals.iloc[:-1].values
            return flip
        
        self.flip = self.I(calc_flip)
        
        # Channel calculations
