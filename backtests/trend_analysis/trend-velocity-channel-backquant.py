            dema_vals = self.dema
            lag_ma_vals = self.lag_ma
            atr_vals = self.atr
            trend_vals = self.trend
            if dema_vals is None or lag_ma_vals is None or atr_vals is None or trend_vals is None:
                return pd.Series(0, index=close.index)
            outer = pd.Series(0.0, index=close.index)
            long_mask = trend_vals > 0
            short_mask = trend_vals < 0
            outer[long_mask] = lag_ma_vals[long_mask] - atr_vals[long_mask] * self.chan_pad
            outer[short_mask] = lag_ma_vals[short_mask] + atr_vals[short_mask] * self.chan_pad
            return outer
        
