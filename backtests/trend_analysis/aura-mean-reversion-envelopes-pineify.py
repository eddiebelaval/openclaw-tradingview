import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters
    length = 34  # Mean Tracking Period (HMA)
    atrLen = 21  # Volatility (ATR) Period
    
    # Band Multipliers
    innerMult = 1.618  # Inner Band Multiplier (golden ratio)
    outerMult = 3.0    # Outer Band (Exhaustion) Multiplier

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Central baseline: Hull Moving Average
        self.mean = self.I(pta.hma, close, length=self.length)
        
        # Volatility measure: Average True Range
        self.volatility = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Envelope construction
        self.upperOuter = self.I(lambda: self.mean + self.volatility * self.outerMult)
        self.upperInner = self.I(lambda: self.mean + self.volatility * self.innerMult)
        self.lowerInner = self.I(lambda: self.mean - self.volatility * self.innerMult)
        self.lowerOuter = self.I(lambda: self.mean - self.volatility * self.outerMult)

    def next(self):
        # Only trade if we have valid indicator values
        if np.isnan(self.mean[-1]) or np.isnan(self.volatility[-1]):
            return
        
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Bullish reversal: low pierces below lower outer, but closes above lower outer and close > open
        bullish_signal = (current_low < self.lowerOuter[-1] and 
                         current_close > current_open and 
                         current_close > self.lowerOuter[-1])
        
        # Bearish reversal: high pierces above upper outer, but closes below upper outer and close < open
        bearish_signal = (current_high > self.upperOuter[-1] and 
                         current_close < current_open and 
                         current_close < self.upperOuter[-1])
        
        # Trading logic
        if bullish_signal:
            if self.position:
                self.position.close()
            self.buy()
        elif bearish_signal:
            if self.position:
                self.position.close()
            else:
                self.sell()


