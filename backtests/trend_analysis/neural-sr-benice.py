import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Support & Resistance Detection Parameters
    first_left = 20
    first_right = 20
    second_left = 15
    second_right = 15
    atr_length = 14
    
    # Strength & Filter Parameters
    weight_touch = 1.0
    weight_reaction = 1.5
    weight_retest = 2.0
    strength_pct = 0.5
    reaction_bars = 10
    reaction_atr = 0.5
    
    # Break & Retest Parameters
    break_atr_buffer = 0.0
    retest_bars = 30
    
    # Merge Parameters
    merge_enable = True
    merge_atr = 0.2
    
    # Volume & Range Filters
    filter_vol_enable = False
    filter_vol_len = 50
    filter_vol_mult = 1.2
    filter_range_enable = False
    filter_range_atr_len = 14
    filter_range_atr_mult = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atr_length) or pd.Series(0.1, index=close.index))
        
        # Calculate pivot highs and lows using rolling max/min
        def pivot_high(src, left, right):
            result = pd.Series(np.nan, index=src.index)
            for i in range(left, len(src) - right):
                if src.iloc[i] == src.iloc[i-left:i+1].max() and src.iloc[i] == src.iloc[i:i+right+1].max():
                    result.iloc[i] = src.iloc[i]
            return result
        
        def pivot_low(src, left, right):
            result = pd.Series(np.nan, index=src.index)
            for i in range(left, len(src) - right):
                if src.iloc[i] == src.iloc[i-left:i+1].min() and src.iloc[i] == src.iloc[i:i+right+1].min():
                    result.iloc[i] = src.iloc[i]
            return result
        
        self.first_ph = self.I(lambda: pivot_high(high, self.first_left, self.first_right))
        self.first_pl = self.I(lambda: pivot_low(low, self.first_left, self.first_right))
        self.second_ph = self.I(lambda: pivot_high(high, self.second_left, self.second_right))
        self.second_pl = self.I(lambda: pivot_low(low, self.second_left, self.second_right))
        
        # Volume SMA for filtering
        self.vol_sma = self.I(lambda: pta.sma(volume, length=self.filter_vol_len) or pd.Series(0, index=volume.index))
        
        # Track SR levels and their properties
        self.sr_levels = {}  # {price: {'strength': value, 'last_touch': bar, 'touches': count}}
        self.min_sr_strength = 1.0

    def next(self):
        # Get current values
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        current_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.1
        current_bar = len(self.data) - 1
        
        # Detect new pivots
        ph = self.first_ph[-1]
        pl = self.first_pl[-1]
        
        # Add new support/resistance levels
        if not np.isnan(ph):
            self._add_sr_level(ph, 'resistance', current_bar)
        if not np.isnan(pl):
            self._add_sr_level(pl, 'support', current_bar)
        
        # Update SR levels based on touches and reactions
        self._update_sr_levels(current_high, current_low, current_close, current_atr, current_bar)
        
        # Calculate trading signals based on SR interactions
        signal = self._calculate_signal(current_high, current_low, current_close, current_atr)
        
        # Execute trades
        if signal == 1 and not self.position:
            self.buy()
        elif signal == -1 and self.position:
            self.sell()

    def _add_sr_level(self, price, sr_type, bar):
        """Add or update SR level"""
        tolerance = 0.01  # 1% tolerance for level merging
        
        for level_price in list(self.sr_levels.keys()):
            if abs(level_price - price) / price < tolerance:
                return
        
        self.sr_levels[price] = {
            'type': sr_type,
            'strength': 1.0,
            'last_touch': bar,
            'touch_count': 0,
            'reaction_count': 0,
            'retest_count': 0,
            'pending_dir': 0,
            'pending_expiry': -1,
        }

    def _update_sr_levels(self, high, low, close, atr, bar):
        """Update SR level statistics based on price action"""
        touch_tol = 0.0005 * close  # 0.05% tolerance
        
        levels_to_remove = []
        
        for price, data in self.sr_levels.items():
            # Check for touch
            if abs(close - price) <= touch_tol or (high >= price - touch_tol and low <= price + touch_tol):
                if data['last_touch'] != bar:
                    data['touch_count'] += 1
                    data['last_touch'] = bar
                    
                    # Determine touch direction
                    if close > price:
                        data['pending_dir'] = 1
                    elif close < price:
                        data['pending_dir'] = -1
                    else:
                        data['pending_dir'] = 0
                    
                    data['pending_expiry'] = bar + self.reaction_bars
            
            # Check for reaction
            if data['pending_dir'] != 0:
                if bar <= data['pending_expiry']:
                    if data['pending_dir'] > 0 and (high - price) >= self.reaction_atr * atr:
                        data['reaction_count'] += 1
                        data['pending_dir'] = 0
                    elif data['pending_dir'] < 0 and (price - low) >= self.reaction_atr * atr:
                        data['reaction_count'] += 1
                        data['pending_dir'] = 0
                else:
                    data['pending_dir'] = 0
            
            # Calculate strength
            data['strength'] = (
                data['touch_count'] * self.weight_touch +
                data['reaction_count'] * self.weight_reaction +
                data['retest_count'] * self.weight_retest
            )
            
            # Remove very old levels with low strength
            if bar - data['last_touch'] > 200 and data['strength'] < 1.0:
                levels_to_remove.append(price)
        
        for price in levels_to_remove:
            del self.sr_levels[price]

    def _calculate_signal(self, high, low, close, atr):
        """Calculate trading signal based on SR levels"""
        if not self.sr_levels:
            return 0
        
        # Find closest support and resistance
        support_level = None
        resistance_level = None
        
        for price, data in self.sr_levels.items():
            if data['strength'] >= self.min_sr_strength:
                if price < close:
                    if support_level is None or price > support_level:
                        support_level = price
                else:
                    if resistance_level is None or price < resistance_level:
                        resistance_level = price
        
        # Generate signals
        signal = 0
        
        # Buy signal: price bounces off support with strength
        if support_level is not None:
            bounce_tol = 0.005 * close
            if low <= support_level + bounce_tol and close > support_level:
                if self.sr_levels[support_level]['strength'] >= 1.5:
                    signal = 1
        
        # Sell signal: price rejects resistance with strength
        if resistance_level is not None:
            reject_tol = 0.005 * close
            if high >= resistance_level - reject_tol and close < resistance_level:
                if self.sr_levels[resistance_level]['strength'] >= 1.5:
                    signal = -1
        
        return signal