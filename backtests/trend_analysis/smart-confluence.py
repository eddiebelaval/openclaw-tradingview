import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Auto timeframe detection parameters
    swing_length = 5
    signal_cooldown = 15
    ob_lookback = 20
    min_confluence = 4
    sl_atr_buffer = 0.5
    min_rr = 1.5
    eq_tolerance = 0.05
    eq_max_age = 200
    setup_max_bars = 50
    sr_cluster_tolerance = 0.5
    
    # TP settings
    tp_mode = "Hybrid"
    tp1_rr = 1.5
    tp2_rr = 2.5
    tp3_rr = 3.0
    
    # Confirmation settings
    use_rsi_divergence = True
    use_volume_confirm = True
    use_ema_filter = True
    use_atr_filter = True
    use_htf = True
    vol_multiplier = 1.5
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.ema21 = self.I(pta.ema, close, length=21)
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        self.rsi = self.I(pta.rsi, close, length=14)
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Volume
        self.vol_sma = self.I(pta.sma, volume, length=20)
        
        # Support/Resistance helpers
        self.swing_high = self.I(lambda: high.rolling(self.swing_length * 2 + 1, center=True).max())
        self.swing_low = self.I(lambda: low.rolling(self.swing_length * 2 + 1, center=True).min())
        
        # State tracking
        self.last_bull_signal_bar = -999
        self.last_bear_signal_bar = -999
        self.active_setup = False
        self.active_is_long = True
        self.active_entry_top = None
        self.active_entry_bottom = None
        self.active_sl = None
        self.active_tp1 = None
        self.active_tp2 = None
        self.active_tp3 = None
        self.active_setup_bar = None
        
        # Historical tracking
        self.swing_high_history = []
        self.swing_low_history = []
        self.eq_highs = []
        self.eq_lows = []
        
    def next(self):
        if len(self) < self.swing_length + 10:
            return
            
        # Current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_volume = self.data.Volume[-1]
        current_atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0.01
        
        # Volume checks
        vol_sma_val = self.vol_sma[-1] if not np.isnan(self.vol_sma[-1]) else current_volume
        high_volume = current_volume > vol_sma_val * self.vol_multiplier
        
        # EMA values
        ema21_val = self.ema21[-1] if not np.isnan(self.ema21[-1]) else current_close
        ema50_val = self.ema50[-1] if not np.isnan(self.ema50[-1]) else current_close
        ema200_val = self.ema200[-1] if not np.isnan(self.ema200[-1]) else current_close
        
        # RSI value
        rsi_val = self.rsi[-1] if not np.isnan(self.rsi[-1]) else 50
        
        # Swing detection
        if len(self) > self.swing_length:
            recent_high = max(self.data.High[-self.swing_length:])
            recent_low = min(self.data.Low[-self.swing_length:])
            
            if current_high == recent_high and len(self.swing_high_history) == 0:
                self.swing_high_history.append((len(self), current_high))
            if current_low == recent_low and len(self.swing_low_history) == 0:
                self.swing_low_history.append((len(self), current_low))
        
        # Trend determination
        is_uptrend = ema21_val > ema50_val > ema200_val
        is_downtrend = ema21_val < ema50_val < ema200_val
        
        # Confluence scoring
        bull_confluence = 0
        bear_confluence = 0
        
        # EMA filter
        if self.use_ema_filter:
            if current_close > ema21_val and ema21_val > ema50_val:
                bull_confluence += 1
            if current_close < ema21_val and ema21_val < ema50_val:
                bear_confluence += 1
        
        # Volume confirmation
        if self.use_volume_confirm:
            if high_volume and current_close > self.data.Open[-1]:
                bull_confluence += 1
            if high_volume and current_close < self.data.Open[-1]:
                bear_confluence += 1
        
        # RSI divergence (simplified)
        if self.use_rsi_divergence:
            if rsi_val < 40 and current_close > self.data.Close[-2]:
                bull_confluence += 2
            if rsi_val > 60 and current_close < self.data.Close[-2]:
                bear_confluence += 2
        
        # Volatility filter
        if self.use_atr_filter:
            atr_sma = np.mean([self.atr[max(0, i)] for i in range(max(0, len(self.atr)-20), len(self.atr))])
            atr_sma = atr_sma if atr_sma > 0 else current_atr
            if current_atr < atr_sma * 0.8:
                bull_confluence -= 1
                bear_confluence -= 1
        
        # Cooldown check
        bull_cooldown_ok = len(self) - self.last_bull_signal_bar >= self.signal_cooldown
        bear_cooldown_ok = len(self) - self.last_bear_signal_bar >= self.signal_cooldown
        
        # Simple CHOCH + confluence signal
        has_bull_trigger = is_uptrend and high_volume
        has_bear_trigger = is_downtrend and high_volume
        
        bull_signal = (
            bull_confluence >= self.min_confluence and 
            bull_confluence > bear_confluence and 
            bull_cooldown_ok and 
            has_bull_trigger
        )
        
        bear_signal = (
            bear_confluence >= self.min_confluence and 
            bear_confluence > bull_confluence and 
            bear_cooldown_ok and 
            has_bear_trigger
        )
        
        # Setup activation
        if bull_signal and not self.active_setup:
            # Calculate entry zone and SL
            entry_top = current_high
            entry_bottom = current_low
            entry_mid = (entry_top + entry_bottom) / 2
            
            sl = entry_bottom - current_atr * self.sl_atr_buffer
            risk = entry_mid - sl
            
            if risk > 0:
                rr = (entry_mid + risk * self.tp1_rr - entry_mid) / risk
                
                if rr >= self.min_rr:
                    self.active_setup = True
                    self.active_is_long = True
                    self.active_entry_top = entry_top
                    self.active_entry_bottom = entry_bottom
                    self.active_sl = sl
                    self.active_tp1 = entry_mid + risk * self.tp1_rr
                    self.active_tp2 = entry_mid + risk * self.tp2_rr
                    self.active_tp3 = entry_mid + risk * self.tp3_rr
                    self.active_setup_bar = len(self)
                    self.last_bull_signal_bar = len(self)
                    
                    self.buy()
        
        elif bear_signal and not self.active_setup:
            # Calculate entry zone and SL
            entry_top = current_high
            entry_bottom = current_low
            entry_mid = (entry_top + entry_bottom) / 2
            
            sl = entry_top + current_atr * self.sl_atr_buffer
            risk = sl - entry_mid
            
            if risk > 0:
                rr = (entry_mid - risk * self.tp1_rr - entry_mid) / risk if risk != 0 else 0
                
                if abs(rr) >= self.min_rr:
                    self.active_setup = True
                    self.active_is_long = False
                    self.active_entry_top = entry_top
                    self.active_entry_bottom = entry_bottom
                    self.active_sl = sl
                    self.active_tp1 = entry_mid - risk * self.tp1_rr
                    self.active_tp2 = entry_mid - risk * self.tp2_rr
                    self.active_tp3 = entry_mid - risk * self.tp3_rr
                    self.active_setup_bar = len(self)
                    self.last_bear_signal_bar = len(self)
                    
                    self.sell()
        
        # Setup management
        if self.active_setup:
            bars_since_setup = len(self) - self.active_setup_bar
            
            # Exit conditions
            should_close = False
            
            if self.active_is_long:
                if current_close < self.active_sl or bars_since_setup > self.setup_max_bars:
                    should_close = True
                if current_close >= self.active_tp3:
                    should_close = True
            else:
                if current_close > self.active_sl or bars_since_setup > self.setup_max_bars:
                    should_close = True
                if current_close <= self.active_tp3:
                    should_close = True
            
            if should_close:
                self.position.close()
                self.active_setup = False


