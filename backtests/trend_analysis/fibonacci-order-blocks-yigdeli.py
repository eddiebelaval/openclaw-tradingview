import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    prd1 = 30
    maxLookback = 900
    levs = 24
    atrLen = 30
    mult = 0.5
    per = 10.0
    depth = 13
    threshold_multiplier = 6.0
    uzaklik = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.highest_high = self.I(
            lambda: high.rolling(self.prd1).max()
        )
        self.lowest_low = self.I(
            lambda: low.rolling(self.prd1).min()
        )

    def next(self):
        if len(self.data) < self.prd1 + 5:
            return
        
        if pd.isna(self.atr[-1]) or pd.isna(self.highest_high[-1]) or pd.isna(self.lowest_low[-1]):
            return
        
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        highest = self.highest_high[-1]
        lowest = self.lowest_low[-1]
        
        band = (self.atr[-1] * self.mult) / 2
        
        resistance_level = highest
        support_level = lowest
        
        resistance_upper = resistance_level
        resistance_lower = resistance_level - (band * 2)
        
        support_upper = support_level + (band * 2)
        support_lower = support_level
        
        if not self.position:
            if current_low <= support_lower and current_close > support_lower:
                if current_close > (support_lower + support_upper) / 2:
                    self.buy()
            elif current_high >= resistance_upper and current_close < resistance_upper:
                if current_close < (resistance_lower + resistance_upper) / 2:
                    self.sell()
        else:
            if self.position.is_long:
                if current_close < support_lower or current_high >= resistance_upper:
                    self.position.close()
            elif self.position.is_short:
                if current_close > resistance_upper or current_low <= support_lower:
                    self.position.close()


