import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Pivot detection parameters
    swing_len = 21
    major_swing_len = 55
    sd_lookback = 15
    comp_len = 13
    
    def init(self):
        # Calculate ATR for compression detection
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr_fast = self.I(pta.atr, high, low, close, length=7)
        self.atr_slow = self.I(pta.atr, high, low, close, length=50)
        
        # Bollinger Bands for squeeze detection
        bb = self.I(lambda: pta.bbands(close, length=20, std=2.0))
        self.bb_upper = self.I(lambda: pta.bbands(close, length=20, std=2.0)['BBU_20_2.0'] if pta.bbands(close, length=20, std=2.0) is not None else pd.Series(0, index=close.index))
        self.bb_lower = self.I(lambda: pta.bbands(close, length=20, std=2.0)['BBL_20_2.0'] if pta.bbands(close, length=20, std=2.0) is not None else pd.Series(0, index=close.index))
        self.bb_basis = self.I(pta.sma, close, length=20)
        
        # Keltner Channel for squeeze
        self.kc_basis = self.I(pta.ema, close, length=20)
        self.kc_atr = self.I(pta.atr, high, low, close, length=10)
        
        # Pivot highs and lows for entry/exit signals
        self.pivot_high = self.I(lambda: self._detect_pivots(high, self.swing_len, 'high'))
        self.pivot_low = self.I(lambda: self._detect_pivots(low, self.swing_len, 'low'))
        
        # RSI for confirmation
        self.rsi = self.I(pta.rsi, close, length=14)
        
        # Fair Value Gap tracking
        self.last_fvg_signal = 0
        
    def _detect_pivots(self, series, lookback, pivot_type):
        """Detect pivot highs or lows"""
        result = pd.Series(0, index=series.index)
        for i in range(lookback, len(series) - lookback):
            if pivot_type == 'high':
                if series.iloc[i] == series.iloc[i-lookback:i+lookback+1].max():
                    result.iloc[i] = series.iloc[i]
            else:
                if series.iloc[i] == series.iloc[i-lookback:i+lookback+1].min():
                    result.iloc[i] = series.iloc[i]
        return result
    
    def _check_squeeze(self):
        """Check if market is in squeeze condition"""
        if len(self.bb_basis) < 1 or len(self.kc_basis) < 1:
            return False
        
        bb_upper = self.bb_upper[-1]
        bb_lower = self.bb_lower[-1]
        kc_basis = self.kc_basis[-1]
        kc_range = self.kc_atr[-1] * 1.5 if self.kc_atr[-1] else 0
        
        in_squeeze = (bb_upper < (kc_basis + kc_range) and 
                     bb_lower > (kc_basis - kc_range))
        return in_squeeze
    
    def _check_compression(self):
        """Check if volatility is compressing"""
        if len(self.atr_fast) < 1 or len(self.atr_slow) < 1:
            return False
        
        if self.atr_slow[-1] == 0:
            return False
            
        atr_ratio = self.atr_fast[-1] / self.atr_slow[-1]
        return atr_ratio < 0.6
    
    def _check_fair_value_gap_bullish(self):
        """Detect bullish FVG: 3 consecutive bullish candles with gap"""
        if len(self.data) < 3:
            return False
        
        # Current and previous candles
        bull1 = self.data.Close[-1] > self.data.Open[-1]
        bull2 = self.data.Close[-2] > self.data.Open[-2]
        bull3 = self.data.Close[-3] > self.data.Open[-3]
        
        # Gap between candle[2].high and candle[0].low
        if bull1 and bull2 and bull3:
            if self.data.Low[-1] > self.data.High[-3]:
                gap_size = (self.data.Low[-1] - self.data.High[-3]) / self.data.High[-3] * 100
                if gap_size > 0.1:
                    return True
        return False
    
    def _check_fair_value_gap_bearish(self):
        """Detect bearish FVG: 3 consecutive bearish candles with gap"""
        if len(self.data) < 3:
            return False
        
        bear1 = self.data.Close[-1] < self.data.Open[-1]
        bear2 = self.data.Close[-2] < self.data.Open[-2]
        bear3 = self.data.Close[-3] < self.data.Open[-3]
        
        if bear1 and bear2 and bear3:
            if self.data.Low[-3] > self.data.High[-1]:
                gap_size = (self.data.Low[-3] - self.data.High[-1]) / self.data.High[-1] * 100
                if gap_size > 0.1:
                    return True
        return False
    
    def next(self):
        # Check for squeeze breakout
        is_squeezed = self._check_squeeze()
        is_compressed = self._check_compression()
        
        # Check FVG signals
        bullish_fvg = self._check_fair_value_gap_bullish()
        bearish_fvg = self._check_fair_value_gap_bearish()
        
        # Entry signals
        if not self.position:
            # Buy on bullish FVG or after squeeze release upward
            if bullish_fvg:
                if len(self.rsi) > 0 and self.rsi[-1] > 40:  # RSI confirmation
                    self.buy()
            
            # Sell on bearish FVG or after squeeze release downward
            elif bearish_fvg:
                if len(self.rsi) > 0 and self.rsi[-1] < 60:  # RSI confirmation
                    self.sell()
            
            # Additional entry on ATR expansion after compression
            elif is_compressed and len(self.atr_fast) > 1:
                if self.atr_fast[-1] > self.atr_fast[-2] * 1.1:  # ATR breaking out
                    if self.data.Close[-1] > self.data.Open[-1]:  # Bullish candle
                        self.buy()
                    elif self.data.Close[-1] < self.data.Open[-1]:  # Bearish candle
                        self.sell()
        
        else:
            # Exit conditions
            if self.position.is_long:
                # Exit on bearish FVG or when RSI overbought
                if bearish_fvg or (len(self.rsi) > 0 and self.rsi[-1] > 70):
                    self.position.close()
                # Stop loss on pivot low break
                elif len(self.pivot_low) > 0 and self.pivot_low[-1] > 0:
                    if self.data.Low[-1] < self.pivot_low[-1] * 0.99:
                        self.position.close()
            
            elif self.position.is_short:
                # Exit on bullish FVG or when RSI oversold
                if bullish_fvg or (len(self.rsi) > 0 and self.rsi[-1] < 30):
                    self.position.close()
                # Stop loss on pivot high break
                elif len(self.pivot_high) > 0 and self.pivot_high[-1] > 0:
                    if self.data.High[-1] > self.pivot_high[-1] * 1.01:
                        self.position.close()


