import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime, time as dt_time


class TvStrategy(Strategy):
    # Strategy Settings
    lot_size = 0.05
    contract_size = 100
    rr_ratio = 2.0
    
    # Retest Filters
    min_wick_pct = 2.0
    max_wick_pct = 30.0
    
    # Session times (in minutes from midnight for comparison)
    orb_start_hour = 9
    orb_start_min = 30
    orb_end_hour = 9
    orb_end_min = 35
    cutoff_hour = 16
    cutoff_min = 45

    def init(self):
        self.orb_high = None
        self.orb_low = None
        self.orb_mid = None
        self.range_set = False
        self.has_confirmed_breakout = False
        self.breakout_dir = 0  # 1 = bull, -1 = bear
        self.breakout_bar_index = None
        self.daily_trade_taken = False
        self.session_cancelled = False
        self.last_day = None

    def _get_time_minutes(self, idx):
        """Convert bar timestamp to minutes from midnight"""
        if idx >= len(self.data):
            return None
        bar_time = pd.Timestamp(self.data.index[idx])
        return bar_time.hour * 60 + bar_time.minute

    def _is_orb_candle(self, idx):
        """Check if candle is within ORB session"""
        time_min = self._get_time_minutes(idx)
        if time_min is None:
            return False
        orb_start = self.orb_start_hour * 60 + self.orb_start_min
        orb_end = self.orb_end_hour * 60 + self.orb_end_min
        return orb_start <= time_min <= orb_end

    def _is_within_entry_window(self, idx):
        """Check if candle is within entry window"""
        time_min = self._get_time_minutes(idx)
        if time_min is None:
            return False
        orb_start = self.orb_start_hour * 60 + self.orb_start_min
        cutoff = self.cutoff_hour * 60 + self.cutoff_min
        return orb_start <= time_min <= cutoff

    def _is_new_day(self, idx):
        """Check if we're on a new day"""
        if idx >= len(self.data):
            return False
        bar_time = pd.Timestamp(self.data.index[idx])
        current_day = bar_time.date()
        if self.last_day is None:
            self.last_day = current_day
            return True
        if current_day != self.last_day:
            self.last_day = current_day
            return True
        return False

    def next(self):
        idx = len(self.data) - 1
        
        # Reset daily
        if self._is_new_day(idx):
            self.orb_high = None
            self.orb_low = None
            self.orb_mid = None
            self.range_set = False
            self.has_confirmed_breakout = False
            self.breakout_dir = 0
            self.breakout_bar_index = None
            self.daily_trade_taken = False
            self.session_cancelled = False
        
        # Capture ORB High/Low during the session
        is_orb_candle = self._is_orb_candle(idx)
        
        if is_orb_candle:
            if not self.range_set:
                self.orb_high = self.data.High[idx]
                self.orb_low = self.data.Low[idx]
                self.orb_mid = (self.orb_high + self.orb_low) / 2
                self.range_set = True
            else:
                self.orb_high = max(self.orb_high, self.data.High[idx])
                self.orb_low = min(self.orb_low, self.data.Low[idx])
                self.orb_mid = (self.orb_high + self.orb_low) / 2
        
        # Trading logic only after ORB forms
        is_within_entry_window = self._is_within_entry_window(idx)
        can_trade = (self.range_set and not is_orb_candle and not self.daily_trade_taken 
                     and not self.session_cancelled and is_within_entry_window)
        
        if can_trade:
            # Check for Breakout
            if not self.has_confirmed_breakout:
                if self.data.Close[idx] > self.orb_high:
                    self.has_confirmed_breakout = True
                    self.breakout_dir = 1
                    self.breakout_bar_index = idx
                elif self.data.Close[idx] < self.orb_low:
                    self.has_confirmed_breakout = True
                    self.breakout_dir = -1
                    self.breakout_bar_index = idx
            
            # Check for Cancellation (Breakout Reversal)
            else:
                if self.breakout_dir == 1 and self.data.Close[idx] < self.orb_low:
                    self.session_cancelled = True
                elif self.breakout_dir == -1 and self.data.Close[idx] > self.orb_high:
                    self.session_cancelled = True
        
        # Entry Logic (Wick Retest)
        if (can_trade and self.has_confirmed_breakout and not self.session_cancelled 
            and not self.position and self.breakout_bar_index is not None 
            and idx > self.breakout_bar_index):
            
            sl_price = self.orb_mid
            dist_to_sl = (self.orb_high - sl_price) if self.breakout_dir == 1 else (sl_price - self.orb_low)
            
            # BULLISH SETUP
            if self.breakout_dir == 1:
                wick_depth = self.orb_high - self.data.Low[idx]
                wick_pct = (wick_depth / dist_to_sl * 100) if dist_to_sl > 0 else 0
                
                wick_in_range = self.min_wick_pct <= wick_pct <= self.max_wick_pct
                body_outside = min(self.data.Open[idx], self.data.Close[idx]) > self.orb_high
                wick_pierced = self.data.Low[idx] < self.orb_high
                
                if wick_pierced and body_outside and wick_in_range:
                    risk_per_share = self.data.Close[idx] - sl_price
                    tp_price = self.data.Close[idx] + (risk_per_share * self.rr_ratio)
                    
                    qty = self.lot_size * self.contract_size
                    self.buy(size=qty)
                    self.daily_trade_taken = True
            
            # BEARISH SETUP
            elif self.breakout_dir == -1:
                wick_depth = self.data.High[idx] - self.orb_low
                wick_pct = (wick_depth / dist_to_sl * 100) if dist_to_sl > 0 else 0
                
