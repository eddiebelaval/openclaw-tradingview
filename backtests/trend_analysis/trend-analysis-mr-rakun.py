import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    trend_period = 20
    trend_method = "Linear Regression"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate trend using linear regression method
        self.price_trend = self.I(self._calculate_trend, close, high, low)
        self.trend_strength = self.I(self._calculate_trend_strength, close)
        
    def _calculate_trend(self, close, high, low):
        """Calculate price trend: 1 (bullish), -1 (bearish), 0 (neutral)"""
        trend = np.zeros(len(close))
        
        for idx in range(self.trend_period, len(close)):
            window = close.iloc[idx - self.trend_period:idx]
            trend[idx] = self._linear_regression_trend(window)
        
        return trend
    
    def _linear_regression_trend(self, src):
        """Linear regression trend calculation"""
        length = len(src)
        sumX = sum(range(length))
        sumY = src.sum()
        sumXY = sum(i * src.iloc[length - 1 - i] for i in range(length))
        sumX2 = sum(i * i for i in range(length))
        
        numerator = length * sumXY - sumX * sumY
        denominator = length * sumX2 - sumX * sumX
        
        if denominator == 0:
            return 0
        
        slope = numerator / denominator
        average = src.mean()
        
        if average == 0:
            return 0
        
        normalized = (slope / average) * 100
        
        if normalized > 0.1:
            return 1
        elif normalized < -0.1:
            return -1
        else:
            return 0
    
    def _calculate_trend_strength(self, close):
        """Calculate trend strength using R-squared"""
        strength = np.zeros(len(close))
        
        for idx in range(self.trend_period, len(close)):
            window = close.iloc[idx - self.trend_period:idx]
            strength[idx] = self._linear_regression_r_squared(window)
        
        return strength
    
    def _linear_regression_r_squared(self, src):
        """Calculate R-squared for linear regression"""
        length = len(src)
        sumX = sum(range(length))
        sumY = src.sum()
        sumXY = sum(i * src.iloc[length - 1 - i] for i in range(length))
        sumX2 = sum(i * i for i in range(length))
        sumY2 = sum(src.iloc[length - 1 - i] ** 2 for i in range(length))
        
        n = float(length)
        numerator = n * sumXY - sumX * sumY
        denominator = np.sqrt((n * sumX2 - sumX * sumX) * (n * sumY2 - sumY * sumY))
        
        if denominator == 0:
            return 0
        
        r = numerator / denominator
        r_squared = (r * r) * 100
        
        return max(0, min(100, r_squared))
    
    def next(self):
        current_trend = self.price_trend[-1]
        current_strength = self.trend_strength[-1]
        prev_trend = self.price_trend[-2] if len(self.price_trend) > 1 else 0
        
        bullish_start = (prev_trend != 1) and (current_trend == 1)
        bearish_start = (prev_trend != -1) and (current_trend == -1)
        
        strong_bullish = bullish_start and current_strength > 50
        strong_bearish = bearish_start and current_strength > 50
        
        if strong_bullish:
            if not self.position:
                self.buy()
        elif strong_bearish:
            if self.position:
                self.sell()


