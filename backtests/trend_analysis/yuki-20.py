import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    min_fvg_ticks = 8
    min_engulf_ticks = 6

    def init(self):
        pass

    def next(self):
        if len(self.data) < 3:
            return

        tick = 0.0001
        
        high = self.data.High
        low = self.data.Low
        open_ = self.data.Open
        close = self.data.Close

        current_high = high[-1]
        current_low = low[-1]
        current_open = open_[-1]
        current_close = close[-1]

        prev_high = high[-2]
        prev_low = low[-2]
        prev_open = open_[-2]
        prev_close = close[-2]

        prev_prev_high = high[-3]
        prev_prev_low = low[-3]

        bull_fvg = current_low > prev_prev_high
        bear_fvg = current_high < prev_prev_low

        bull_top = current_low
        bull_bot = prev_prev_high
        bear_top = prev_prev_low
        bear_bot = current_high

        bull_ok_size = bull_fvg and ((bull_top - bull_bot) >= self.min_fvg_ticks * tick)
        bear_ok_size = bear_fvg and ((bear_top - bear_bot) >= self.min_fvg_ticks * tick)

        if not hasattr(self, 'last_bull_top'):
            self.last_bull_top = None
            self.last_bull_bot = None
            self.bull_active = False
            self.last_bear_top = None
            self.last_bear_bot = None
            self.bear_active = False

        if bull_ok_size:
            self.last_bull_top = bull_top
            self.last_bull_bot = bull_bot
            self.bull_active = True

        if bear_ok_size:
            self.last_bear_top = bear_top
            self.last_bear_bot = bear_bot
            self.bear_active = True

        prev_bull = prev_close > prev_open
        prev_bear = prev_close < prev_open
        cur_bull = current_close > current_open
        cur_bear = current_close < current_open

        prev_body_high = max(prev_open, prev_close)
        prev_body_low = min(prev_open, prev_close)
        cur_body_high = max(current_open, current_close)
        cur_body_low = min(current_open, current_close)

        body_ticks = abs(current_close - current_open) / tick
        big_enough_engulf = body_ticks >= self.min_engulf_ticks

        bull_engulf_confirmed = (big_enough_engulf and prev_bear and cur_bull and 
                                 cur_body_high >= prev_body_high and cur_body_low <= prev_body_low)
        bear_engulf_confirmed = (big_enough_engulf and prev_bull and cur_bear and 
                                 cur_body_high >= prev_body_high and cur_body_low <= prev_body_low)

        bull_early = (big_enough_engulf and prev_bear and current_close > current_open and 
                      current_high >= prev_body_high and current_low <= prev_body_low)
        bear_early = (big_enough_engulf and prev_bull and current_close < current_open and 
                      current_low <= prev_body_low and current_high >= prev_body_high)

        bull_ready = self.bull_active and self.last_bull_top is not None and self.last_bull_bot is not None
        bear_ready = self.bear_active and self.last_bear_top is not None and self.last_bear_bot is not None

        bull_touched = bull_ready and current_high >= self.last_bull_bot and current_low <= self.last_bull_top
        bear_touched = bear_ready and current_high >= self.last_bear_bot and current_low <= self.last_bear_top

        bull_close_outside = bull_ready and current_close > self.last_bull_top
        bear_close_outside = bear_ready and current_close < self.last_bear_bot

        conf_l = bull_engulf_confirmed and bull_touched and bull_close_outside
        conf_s = bear_engulf_confirmed and bear_touched and bear_close_outside

        early_l = bull_early and bull_touched
        early_s = bear_early and bear_touched

        if conf_l or early_l:
            if not self.position:
                self.buy()
        elif conf_s or early_s:
            if self.position:
                self.position.close()
            else:
                self.sell()