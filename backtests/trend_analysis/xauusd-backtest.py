import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastMaPeriod = 9
    slowMaPeriod = 21
    atrMultiplier = 1.5
    atrPeriod = 14
    minConfluenceScore = 4
    barCloseConfirm = True
    useConfluenceFilter = True
    targetCount = 5
    trailSlToBreakeven = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.fastMa = self.I(pta.ema, close, length=self.fastMaPeriod)
        self.slowMa = self.I(pta.ema, close, length=self.slowMaPeriod)
        self.vwap = self.I(lambda: pta.vwap(high, low, close, volume))
        self.atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)
        self.rsi = self.I(pta.rsi, close, length=14)
        
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macdMain = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9).iloc[:, 0] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        self.macdSignal = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9).iloc[:, 2] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        
        adx_result = self.I(pta.adx, high, low, close, length=14)
        self.adx = self.I(lambda: pta.adx(high, low, close, length=14).iloc[:, 2] if pta.adx(high, low, close, length=14) is not None else pd.Series(20, index=close.index))
        
        self.volumeAvg = self.I(pta.sma, volume, length=20)

        self.activeDirection = 0
        self.entryPrice = 0.0
        self.stopLossPrice = 0.0
        self.targetPrice = [0.0] * 5
        self.targetReached = [False] * 5
        self.slMovedToBreakeven = False

    def next(self):
        if len(self.data) < max(self.slowMaPeriod, 30):
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        open_ = self.data.Open[-1]

        fastMa = self.fastMa[-1]
        slowMa = self.slowMa[-1]
        vwap = self.vwap[-1]
        atr = self.atr[-1]
        rsi = self.rsi[-1]
        macdMain = self.macdMain[-1]
        macdSignal = self.macdSignal[-1]
        adx = self.adx[-1]
        volumeAvg = self.volumeAvg[-1]

        bullishScore = 0
        bullishScore += 1 if close > vwap else 0
        bullishScore += 1 if rsi > 50 else 0
        bullishScore += 1 if macdMain > macdSignal else 0
        bullishScore += 1 if fastMa > slowMa else 0
        bullishScore += 1 if adx > 25 and close > fastMa else 0
        bullishScore += 1 if volume > volumeAvg and close > open_ else 0
        bullishScore += 1 if rsi > 50 else 0

        bearishScore = 0
        bearishScore += 1 if close < vwap else 0
        bearishScore += 1 if rsi < 50 else 0
        bearishScore += 1 if macdMain < macdSignal else 0
        bearishScore += 1 if fastMa < slowMa else 0
        bearishScore += 1 if adx > 25 and close < fastMa else 0
        bearishScore += 1 if volume > volumeAvg and close < open_ else 0
        bearishScore += 1 if rsi < 50 else 0

        rawBullishCross = crossover(self.fastMa, self.slowMa)
        rawBearishCross = crossover(self.slowMa, self.fastMa)

        confluenceBullPass = (not self.useConfluenceFilter) or (bullishScore >= self.minConfluenceScore)
        confluenceBearPass = (not self.useConfluenceFilter) or (bearishScore >= self.minConfluenceScore)

        entryLongSignal = rawBullishCross and self.activeDirection <= 0 and confluenceBullPass
        entryShortSignal = rawBearishCross and self.activeDirection >= 0 and confluenceBearPass

        if entryLongSignal or entryShortSignal:
            self.activeDirection = 1 if entryLongSignal else -1
            self.entryPrice = close
            riskAmount = atr * self.atrMultiplier
            self.stopLossPrice = self.entryPrice - riskAmount if entryLongSignal else self.entryPrice + riskAmount
            
            for i in range(self.targetCount):
                if entryLongSignal:
                    self.targetPrice[i] = self.entryPrice + riskAmount * (i + 1)
                else:
                    self.targetPrice[i] = self.entryPrice - riskAmount * (i + 1)
            
            self.targetReached = [False] * 5
            self.slMovedToBreakeven = False

        if entryLongSignal:
            self.buy()

        if entryShortSignal:
            self.position.close() if self.position else None
            self.sell()

