import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 14
    rsiOverSold = 30
    rsiOverBought = 70
    smaFastLen = 50
    smaSlowLen = 200
    structLookback = 10
    useATRexit = True
    atrLen = 14
    atrMultSL = 1.5
    atrMultTP = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.rsi14 = self.I(pta.rsi, close, length=self.rsiLen)
        self.sma50 = self.I(pta.sma, close, length=self.smaFastLen)
        self.sma200 = self.I(pta.sma, close, length=self.smaSlowLen)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.lastSwingHigh = 0.0
        self.lastSwingLow = 0.0
        self.trendState = "Neutral"
        self.in_long = False
        self.in_short = False
        
        self.swingHighs = self._calculate_swing_highs(high)
        self.swingLows = self._calculate_swing_lows(low)

    def _calculate_swing_highs(self, high):
        result = []
        lookback = self.structLookback
        for i in range(len(high)):
            if i < lookback or i >= len(high) - lookback:
                result.append(np.nan)
            else:
                is_pivot = high[i] > high[i-lookback:i].max() and high[i] > high[i+1:i+lookback+1].max()
                result.append(high[i] if is_pivot else np.nan)
        return pd.Series(result, index=high.index)

    def _calculate_swing_lows(self, low):
        result = []
        lookback = self.structLookback
        for i in range(len(low)):
            if i < lookback or i >= len(low) - lookback:
                result.append(np.nan)
            else:
                is_pivot = low[i] < low[i-lookback:i].min() and low[i] < low[i+1:i+lookback+1].min()
                result.append(low[i] if is_pivot else np.nan)
        return pd.Series(result, index=low.index)

    def next(self):
        current_idx = len(self.data) - 1
        
        high_series = pd.Series(self.data.High)
        low_series = pd.Series(self.data.Low)
        
        swingHighs = self._calculate_swing_highs(high_series)
        swingLows = self._calculate_swing_lows(low_series)
        
        swingHigh = swingHighs.iloc[current_idx]
        swingLow = swingLows.iloc[current_idx]
        
        if not np.isnan(swingHigh):
            if swingHigh > self.lastSwingHigh:
                self.trendState = "Up"
            elif swingHigh < self.lastSwingHigh:
                self.trendState = "Down"
            self.lastSwingHigh = swingHigh
        
        if not np.isnan(swingLow):
            if swingLow < self.lastSwingLow:
                self.trendState = "Down"
            elif swingLow > self.lastSwingLow:
                self.trendState = "Up"
            self.lastSwingLow = swingLow
        
        rsi_val = self.rsi14[-1]
        sma50_val = self.sma50[-1]
        sma200_val = self.sma200[-1]
        atr_val = self.atr[-1]
        
        if rsi_val is None or sma50_val is None or sma200_val is None or atr_val is None:
            return
        
        rsiBuyTrigger = crossover(self.rsi14, self.rsiOverSold)
        rsiSellTrigger = crossover(self.rsiOverBought, self.rsi14)
        
        smaTrendUp = sma50_val > sma200_val
        smaTrendDown = sma50_val < sma200_val
        
        longCondition = rsiBuyTrigger and smaTrendUp and self.trendState == "Up"
        shortCondition = rsiSellTrigger and smaTrendDown and self.trendState == "Down"
        
        if self.position:
            if self.position.is_long:
                longSL = self.data.Close[-1] - atr_val * self.atrMultSL
                longTP = self.data.Close[-1] + atr_val * self.atrMultTP
                
                if self.useATRexit:
                    if self.data.Close[-1] <= longSL or self.data.Close[-1] >= longTP:
                        self.position.close()
            
            elif self.position.is_short:
                shortSL = self.data.Close[-1] + atr_val * self.atrMultSL
                shortTP = self.data.Close[-1] - atr_val * self.atrMultTP
                
                if self.useATRexit:
                    if self.data.Close[-1] >= shortSL or self.data.Close[-1] <= shortTP:
                        self.position.close()
        
        if longCondition and not self.position:
            self.buy()
        
        if shortCondition and not self.position:
            self.sell()


