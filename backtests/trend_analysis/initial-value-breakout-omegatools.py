import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        self.validity_hour = 16
        self.session_start_hour = 9
        self.session_start_minute = 30
        self.session_end_hour = 10
        self.session_end_minute = 0
        
        self.hh = None
        self.ll = None
        self.bias = 0
        self.hl_arr = []
        self.highest = None
        self.lowest = None
        self.up_arr = []
        self.dn_arr = []
        self.tot_arr = []
        self.first_bias = None
        self.level_that_broke = None
        self.bias_pred_arr = []
        self.prev_in_session = False
        self.session_started = False

    def is_in_session(self, dt):
        hour = dt.hour
        minute = dt.minute
        if hour == self.session_start_hour:
            return minute >= self.session_start_minute
        elif hour == self.session_end_hour:
            return minute < self.session_end_minute
        elif self.session_start_hour < hour < self.session_end_hour:
            return True
        return False

    def next(self):
        idx = len(self.data) - 1
        current_time = self.data.index[idx]
        current_hour = current_time.hour
        current_high = self.data.High[idx]
        current_low = self.data.Low[idx]
        current_close = self.data.Close[idx]
        current_hl2 = (current_high + current_low) / 2
        
        in_session = self.is_in_session(current_time)
        prev_in_session = self.prev_in_session if idx > 0 else False
        
        if in_session:
            if self.hh is None or self.ll is None:
                self.hh = current_high
                self.ll = current_low
                self.hl_arr = [current_hl2]
            else:
                self.hh = max(current_high, self.hh)
                self.ll = min(current_low, self.ll)
                self.hl_arr.append(current_hl2)
        
        if self.hh is not None and current_close > self.hh:
            self.bias = 1
        if self.ll is not None and current_close < self.ll:
            self.bias = -1
        
        if current_hour > self.validity_hour:
            self.hh = None
            self.ll = None
            self.hl_arr = []
            self.bias = 0
        
        if prev_in_session and not in_session:
            self.highest = current_high
            self.lowest = current_low
            self.session_started = True
        
        if current_hour <= self.validity_hour and self.session_started:
            if self.highest is not None:
                self.highest = max(current_high, self.highest)
            if self.lowest is not None:
                self.lowest = min(current_low, self.lowest)
        elif current_hour > self.validity_hour:
            self.highest = None
            self.lowest = None
        
        if idx > 0:
            prev_hh = self.hh
            prev_ll = self.ll
            prev_bias = self.bias
            
            prev_close = self.data.Close[idx - 1]
            
            prev_highest = self.highest
            prev_lowest = self.lowest
            
            if prev_in_session and not in_session:
                if prev_bias == 1 and prev_highest is not None and prev_hh is not None:
                    self.up_arr.append(prev_highest - prev_hh)
                if prev_bias == -1 and prev_lowest is not None and prev_ll is not None:
                    self.dn_arr.append(prev_ll - prev_lowest)
                if prev_highest is not None and prev_lowest is not None and prev_hh is not None and prev_ll is not None:
                    self.tot_arr.append(max(prev_ll - prev_lowest, prev_highest - prev_hh))
        
        if len(self.up_arr) > 3:
            self.up_arr.pop(0)
        if len(self.dn_arr) > 3:
            self.dn_arr.pop(0)
        if len(self.tot_arr) > 21:
            self.tot_arr.pop(0)
        
        if current_hour > self.validity_hour:
            if self.first_bias is not None and self.level_that_broke is not None:
                prev_close = self.data.Close[idx - 1]
                if (prev_close > self.level_that_broke and self.first_bias == 1) or \
                   (prev_close < self.level_that_broke and self.first_bias == -1):
                    self.bias_pred_arr.append(1)
                else:
                    self.bias_pred_arr.append(0)
            self.first_bias = None
        
        if self.first_bias is None and self.bias != 0:
            self.first_bias = self.bias
            self.level_that_broke = current_close
        
        if len(self.bias_pred_arr) > 100:
            self.bias_pred_arr.pop(0)
        
        signal = 0
        if len(self.bias_pred_arr) > 0:
            signal = sum(self.bias_pred_arr) / len(self.bias_pred_arr)
        
        if self.bias == 1 and signal > 0.5:
            if not self.position:
                self.buy()
        elif self.bias == -1 and signal < 0.5:
            if self.position:
                self.position.close()
        elif self.bias == 0:
            if self.position:
                self.position.close()
        
        self.prev_in_session = in_session


