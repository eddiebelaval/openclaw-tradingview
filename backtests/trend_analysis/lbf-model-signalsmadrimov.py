import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Filter parameters
    use_ema_filter = True
    ema_length = 100
    
    # Risk/Reward
    risk_reward_ratio = 3.0
    
    # FVG detection
    show_fvg = True
    fvg_extend = 20
    
    # Liquidity detection
    liq_length = 7
    liq_margin = 10 / 6.9

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA 100 filter
        self.ema_100 = self.I(pta.ema, close, length=self.ema_length)
        
        # Swing high/low for structure (20 period)
        self.swing_high = self.I(lambda: high.rolling(window=20).max())
        self.swing_low = self.I(lambda: low.rolling(window=20).min())
        
        # Track state
        self.fvg_active = False
        self.fvg_zone_low = 0
        self.fvg_zone_high = 0
        self.setup_active = False
        self.liquidity_level = 0
        self.in_trade = False
        self.entry_price = 0
        self.stop_loss = 0
        self.take_profit = 0
        
        # Performance tracking
        self.total_signals = 0
        self.tp_hits = 0
        self.sl_hits = 0

    def next(self):
        # Only process if we have enough data
        if len(self) < 30:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_price = self.data.Open[-1]
        
        prev_close = self.data.Close[-2]
        prev_open = self.data.Open[-2]
        prev_high = self.data.High[-2]
        prev_low = self.data.Low[-2]
        
        prev_prev_high = self.data.High[-3] if len(self) >= 3 else prev_high
        prev_prev_low = self.data.Low[-3] if len(self) >= 3 else prev_low
        
        ema_100 = self.ema_100[-1]
        swing_high = self.swing_high[-1]
        swing_low = self.swing_low[-1]
        
        # Check EMA filter
        price_above_ema = close > ema_100
        ema_allows_long = not self.use_ema_filter or price_above_ema
        
        # ═══════════════════════════════════════════════════════════════════
        # FAIR VALUE GAP (FVG) DETECTION
        # ═══════════════════════════════════════════════════════════════════
        
        # Bullish FVG: Current low > Previous 2 high, previous close > previous 2 high
        bullish_fvg = (low > prev_prev_high and prev_close > prev_prev_high and 
                       abs(close - prev_close) / prev_open > 0.001)
        
        # Bearish FVG: Current high < Previous 2 low, previous close < previous 2 low
        bearish_fvg = (high < prev_prev_low and prev_close < prev_prev_low and 
                       abs(close - prev_close) / prev_open > 0.001)
        
        # Create FVG zone on bullish gap
        if bullish_fvg and not self.fvg_active and ema_allows_long:
            self.fvg_active = True
            self.fvg_zone_low = prev_prev_high
            self.fvg_zone_high = low
            self.setup_active = True
        
        # ═══════════════════════════════════════════════════════════════════
        # LIQUIDITY SWEEP DETECTION (4H High/Low Concept)
        # ═══════════════════════════════════════════════════════════════════
        
        # Simple liquidity: track swing highs and lows
        prev_swing_high = self.swing_high[-2] if len(self) >= 2 else swing_high
        prev_swing_low = self.swing_low[-2] if len(self) >= 2 else swing_low
        
        # Liquidity sweep: price touches and breaks structure
        bull_liq_swept = (low <= prev_swing_low and close > prev_swing_low and 
                         ema_allows_long)
        
        if bull_liq_swept and self.setup_active:
            self.liquidity_level = prev_swing_low
        
        # ═══════════════════════════════════════════════════════════════════
        # ENTRY LOGIC - FVG RETEST
        # ═══════════════════════════════════════════════════════════════════
        
        bull_entry = False
        
        if self.fvg_active and self.setup_active and ema_allows_long:
            # Entry on FVG retest: price enters FVG zone from below
            if low <= self.fvg_zone_high and close >= self.fvg_zone_low:
                bull_entry = True
        
        # ═══════════════════════════════════════════════════════════════════
        # EXECUTE ENTRY
        # ═══════════════════════════════════════════════════════════════════
        
        if bull_entry and not self.in_trade and self.liquidity_level > 0:
            self.entry_price = close
            self.stop_loss = self.liquidity_level
            risk = self.entry_price - self.stop_loss
            
            if risk > 0:
                self.take_profit = self.entry_price + (risk * self.risk_reward_ratio)
                self.buy()
                self.in_trade = True
                self.total_signals += 1
                self.fvg_active = False
                self.setup_active = False
        
        # ═══════════════════════════════════════════════════════════════════
        # EXIT LOGIC - TP/SL
        # ═══════════════════════════════════════════════════════════════════
        
        if self.in_trade:
            if high >= self.take_profit:
                self.sell()
                self.in_trade = False
                self.tp_hits += 1
            elif low <= self.stop_loss:
                self.sell()
                self.in_trade = False
                self.sl_hits += 1


