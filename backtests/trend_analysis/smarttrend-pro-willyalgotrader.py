import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    sensitivity = 2.5
    atr_period = 21
    min_score = 55
    show_strong_only = False
    show_pullback = True
    pullback_sens = 8
    cloud_style = "Adaptive"
    tracer_len = 233
    use_trend_filter = False
    use_vol_filter = False
    use_adx_filter = False
    use_momentum_filter = False
    sl_mode = "ATR"
    sl_mult = 1.5
    sl_perc = 1.0
    tp1_mult = 1.5
    tp2_mult = 2.5
    tp3_mult = 4.0
    preset = "Balanced"
    swing_len = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Apply preset adjustments
        sensitivity = self.sensitivity
        atr_period = self.atr_period
        min_score = self.min_score

        if self.preset == "Conservative":
            sensitivity *= 1.4
            atr_period = int(atr_period * 1.3)
            min_score = max(min_score, 70)
        elif self.preset == "Aggressive":
            sensitivity *= 0.7
            atr_period = int(atr_period * 0.8)
            min_score = min(min_score, 45)
        elif self.preset == "Scalping":
            sensitivity *= 0.5
            atr_period = int(atr_period * 0.6)
            min_score = min(min_score, 40)

        self.sensitivity_eff = sensitivity
        self.atr_period_eff = max(atr_period, 5)
        self.min_score_eff = min_score
        self.sell_threshold = 100 - min_score

        # Core indicators
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atr_period_eff) or pd.Series(0.0, index=close.index))
        
        # EMA for trend
        self.ema50 = self.I(lambda: pta.ema(close, length=50) or pd.Series(close, index=close.index))
        self.ema200 = self.I(lambda: pta.ema(close, length=200) or pd.Series(close, index=close.index))
        
        # RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9) or pd.DataFrame(index=close.index))
        self.macd_hist = macd_result.iloc[:, 2] if len(macd_result.columns) > 2 else pd.Series(0.0, index=close.index)
        
        # ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14) or pd.DataFrame(index=close.index))
        self.adx = adx_result.iloc[:, 0] if len(adx_result.columns) > 0 else pd.Series(20, index=close.index)
        
        # Volume
        has_volume = volume.sum() > 0
        if has_volume:
            self.vol_ema_fast = self.I(lambda: pta.ema(volume, length=10) or pd.Series(volume.mean(), index=volume.index))
            self.vol_ema_slow = self.I(lambda: pta.ema(volume, length=25) or pd.Series(volume.mean(), index=volume.index))
        else:
            self.vol_ema_fast = pd.Series(1.0, index=close.index)
            self.vol_ema_slow = pd.Series(1.0, index=close.index)
        
        self.has_volume = has_volume
        
        # Cloud indicators
        cloud_fast_len = 34
        if self.cloud_style == "Fast":
            cloud_fast_len = 21
        elif self.cloud_style == "Smooth":
            cloud_fast_len = 55
        
        cloud_slow_len = int(cloud_fast_len * 2.618)
        
        self.cloud_fast = self.I(lambda: pta.ema(close, length=cloud_fast_len) or pd.Series(close, index=close.index))
        self.cloud_slow = self.I(lambda: pta.ema(close, length=min(cloud_slow_len, 200)) or pd.Series(close, index=close.index))
        
        # Tracer (long-term EMA)
        self.tracer = self.I(lambda: pta.ema(close, length=self.tracer_len) or pd.Series(close, index=close.index))
        
        # Pullback indicators
        self.pull_rsi = self.I(lambda: pta.rsi(close, length=self.pullback_sens) or pd.Series(50, index=close.index))
        self.pull_ema = self.I(lambda: pta.ema(close, length=self.pullback_sens * 3) or pd.Series(close, index=close.index))
        
        # Tracking variables
        self.last_signal_dir = 0  # 1 = buy, -1 = sell
        self.entry_price = None
        self.sl_price = None
        self.tp1_price = None
        self.tp2_price = None
        self.tp3_price = None
        self.bars_since_signal = 0
        self.frozen_sl_distance = None
        
        self.warmup_bars = max(self.atr_period_eff * 3, 200)

    def next(self):
        # Warmup check
        if len(self.data) < self.warmup_bars:
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Get current indicator values
        atr_val = self.atr[-1] if len(self.atr) > 0 else close * 0.01
        ema50 = self.ema50[-1]
        ema200 = self.ema200[-1]
        rsi_val = self.rsi[-1]
        macd_hist = self.macd_hist[-1] if len(self.macd_hist) > 0 else 0
        adx_val = self.adx[-1] if len(self.adx) > 0 else 20
        
        cloud_fast = self.cloud_fast[-1]
        cloud_slow = self.cloud_slow[-1]
        
        # Cloud direction
        cloud_bull = cloud_fast > cloud_slow
        cloud_bear = cloud_fast < cloud_slow
        
        # Previous cloud state
        prev_cloud_fast = self.cloud_fast[-2] if len(self.cloud_fast) > 1 else cloud_fast
        prev_cloud_slow = self.cloud_slow[-2] if len(self.cloud_slow) > 1 else cloud_slow
        prev_cloud_bull = prev_cloud_fast > prev_cloud_slow
        prev_cloud_bear = prev_cloud_fast < prev_cloud_slow
        
        trend_flip_bull = cloud_bull and prev_cloud_bear
        trend_flip_bear = cloud_bear and prev_cloud_bull
        
        # Momentum score calculation (0-100)
        score = 50.0
        
        # EMA alignment
        if close > ema50 and ema50 > ema200:
            score += 15.0
        elif close < ema50 and ema50 < ema200:
            score -= 15.0
        
        # RSI position
        if rsi_val > 50 and rsi_val < 70:
            score += 10.0
        elif rsi_val <= 50 and rsi_val > 30:
            score -= 10.0
        
        # MACD histogram
        prev_macd_hist = self.macd_hist[-2] if len(self.macd_hist) > 1 else macd_hist
        if macd_hist > 0 and macd_hist > prev_macd_hist:
            score += 12.0
        elif macd_hist < 0 and macd_hist < prev_macd_hist:
            score -= 12.0
        
        # Volume confirmation
        if self.has_volume:
            vol_ema_fast = self.vol_ema_fast[-1]
            vol_ema_slow = self.vol_ema_slow[-1]
            vol = self.data.Volume[-1]
            if vol > vol_ema_slow * 1.2:
                score += 8.0
        
        # ADX strength
        if adx_val > 25:
            score += 10.0
        elif adx_val > 20:
            score += 5.0
        
        score = max(0.0, min(100.0, score))
        
        # Filters
        vol_filter_ok = True
        if self.use_vol_filter and self.has_volume:
            vol_ema_fast = self.vol_ema_fast[-1]
            vol_ema_slow = self.vol_ema_slow[-1]
            vol_filter_ok = vol_ema_fast > vol_ema_slow
        
        adx_filter_ok = True
        if self.use_adx_filter:
            adx_filter_ok = adx_val > 20
        
        bull_trend_ok = not self.use_trend_filter or cloud_bull
        bear_trend_ok = not self.use_trend_filter or cloud_bear
        
        momentum_bull = macd_hist > 0 and macd_hist > prev_macd_hist
        momentum_bear = macd_hist < 0 and macd_hist < prev_macd_hist
        bull_mom_ok = not self.use_momentum_filter or momentum_bull
        bear_mom_ok = not self.use_momentum_filter or momentum_bear
        
        bull_filters_pass = bull_trend_ok and vol_filter_ok and adx_filter_ok and bull_mom_ok
        bear_filters_pass = bear_trend_ok and vol_filter_ok and adx_filter_ok and bear_mom_ok
        
        # Main signals
        min_score = self.min_score_eff
        if self.show_strong_only:
            min_score = max(min_score, 75)
        
        raw_buy = trend_flip_bull and score >= min_score and bull_filters_pass
        raw_sell = trend_flip_bear and score <= (100 - min_score) and bear_filters_pass
        
        confirmed_buy = raw_buy
        confirmed_sell = raw_sell
        
        # Pullback signals
        pullback_buy = False
        pullback_sell = False
        if self.show_pullback:
            pull_rsi = self.pull_rsi[-1]
            pull_ema = self.pull_ema[-1]
            prev_pull_rsi = self.pull_rsi[-2] if len(self.pull_rsi) > 1 else pull_rsi
            
            if cloud_bull and close <= pull_ema and pull_rsi < 35 and pull_rsi > prev_pull_rsi:
                pullback_buy = True
            
            if cloud_bear and close >= pull_ema and pull_rsi > 65 and pull_rsi < prev_pull_rsi:
                pullback_sell = True
        
        # Update signal tracking
        if confirmed_buy or pullback_buy:
            self.last_signal_dir = 1
            self.entry_price = close
            self.bars_since_signal = 0
        elif confirmed_sell or pullback_sell:
            self.last_signal_dir = -1
            self.entry_price = close
            self.bars_since_signal = 0
        else:
            self.bars_since_signal += 1
        
        # Calculate SL and TP
        if confirmed_buy or pullback_buy:
            if self.sl_mode == "Percentage":
                sl_distance = close * (self.sl_perc / 100.0)
            elif self.sl_mode == "Structure":
                recent_high = max(self.data.High[-self.swing_len:])
                recent_low = min(self.data.Low[-self.swing_len:])
                sl_distance = (recent_high - recent_low) * 0.5
            else:  # ATR
                sl_distance = atr_val * self.sl_mult
            
            self.sl_price = close - sl_distance
            self.frozen_sl_distance = sl_distance
            self.tp1_price = close + sl_distance * self.tp1_mult
            self.tp2_price = close + sl_distance * self.tp2_mult
            self.tp3_price = close + sl_distance * self.tp3_mult
        
        elif confirmed_sell or pullback_sell:
            if self.sl_mode == "Percentage":
                sl_distance = close * (self.sl_perc / 100.0)
            elif self.sl_mode == "Structure":
                recent_high = max(self.data.High[-self.swing_len:])
                recent_low = min(self.data.Low[-self.swing_len:])
                sl_distance = (recent_high - recent_low) * 0.5
            else:  # ATR
                sl_distance = atr_val * self.sl_mult
            
            self.sl_price = close + sl_distance
            self.frozen_sl_distance = sl_distance
            self.tp1_price = close - sl_distance * self.tp1_mult
            self.tp2_price = close - sl_distance * self.tp2_mult
            self.tp3_price = close - sl_distance * self.tp3_mult
        
        # Check SL and TP hits
        if self.last_signal_dir == 1:
            if self.sl_price is not None and low < self.sl_price and self.bars_since_signal > 0:
                if self.position:
                    self.position.close()
                self.last_signal_dir = 0
            elif self.tp3_price is not None and high >= self.tp3_price:
                if self.position:
                    self.position.close()
                self.last_signal_dir = 0
        
        elif self.last_signal_dir == -1:
            if self.sl_price is not None and high > self.sl_price and self.bars_since_signal > 0:
                if self.position:
                    self.position.close()
                self.last_signal_dir = 0
            elif self.tp3_price is not None and low <= self.tp3_price:
                if self.position:
                    self.position.close()
                self.last_signal_dir = 0
        
        # Execute trades
        if confirmed_buy or pullback_buy:
            if not self.position:
                self.buy()
        
        elif confirmed_sell or pullback_sell:
            if not self.position:
                self.sell()