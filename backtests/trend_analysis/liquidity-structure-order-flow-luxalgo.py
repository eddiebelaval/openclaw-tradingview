import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback_period = 300
    vol_threshold = 2.0
    delta_ema_len = 5
    vol_ma_len = 200
    vol_std_len = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate volume statistics
        self.vol_ma = self.I(pta.sma, volume, length=self.vol_ma_len)
        self.vol_std = self.I(
            lambda: volume.rolling(window=self.vol_std_len).std(),
            name="vol_std"
        )

        # Calculate raw bar delta
        def calc_raw_delta():
            delta = pd.Series(0.0, index=close.index)
            delta[close > self.data.Open] = volume[close > self.data.Open]
            delta[close < self.data.Open] = -volume[close < self.data.Open]
            return delta

        raw_delta = self.I(calc_raw_delta, name="raw_delta")

        # Smooth delta with EMA
        self.smooth_delta = self.I(pta.ema, raw_delta, length=self.delta_ema_len)

        # Calculate z-score for unusual volume detection
        def calc_z_score():
            z = pd.Series(0.0, index=close.index)
            mask = self.vol_std > 0
            z[mask] = (volume[mask] - self.vol_ma[mask]) / self.vol_std[mask]
            return z

        self.z_score = self.I(calc_z_score, name="z_score")

        # Calculate RVOL (Relative Volume)
        def calc_rvol():
            rvol = pd.Series(1.0, index=close.index)
            mask = self.vol_ma > 0
            rvol[mask] = volume[mask] / self.vol_ma[mask]
            return rvol

        self.rvol = self.I(calc_rvol, name="rvol")

        # Track highest high and lowest low over lookback period
        self.highest = self.I(
            lambda: high.rolling(window=self.lookback_period).max(),
            name="highest"
        )
        self.lowest = self.I(
            lambda: low.rolling(window=self.lookback_period).min(),
            name="lowest"
        )

        # Calculate price range and mid
        def calc_mid():
            return (self.highest + self.lowest) / 2

        self.mid = self.I(calc_mid, name="mid")

        # Initialize entry signal tracker
        self.last_unusual_idx = -1

