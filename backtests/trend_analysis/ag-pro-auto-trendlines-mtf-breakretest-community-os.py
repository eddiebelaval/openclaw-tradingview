import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # This is a complex multi-timeframe trendline indicator with no direct buy/sell signals
        # We'll create a simple trading logic based on Micro trendline breaks and retests
        
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for reference
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Simple logic: use price proximity to highest/lowest as proxy for trendline proximity
        # Buy when price touches support (lowest), Sell when price touches resistance (highest)
        self.highest_20 = self.I(lambda: close.rolling(20).max())
        self.lowest_20 = self.I(lambda: close.rolling(20).min())
        
        # Track if we've already acted on current level
        self.last_action_price = 0
        
    def next(self):
        # Simple trendline-inspired logic:
        # Buy when price breaks below and retests support (lowest 20)
        # Sell when price breaks above and retests resistance (highest 20)
        
        if len(self.data) < 21:
            return
        
        current_price = self.data.Close[-1]
        resistance = self.highest_20[-1]
        support = self.lowest_20[-1]
        atr_val = self.atr[-1]
        
        # Avoid trading too close to last trade
        price_distance = abs(current_price - self.last_action_price)
        min_distance = atr_val * 0.5
        
        # Buy signal: price near support, above minimum distance from last trade
        if current_price <= support * 1.01 and price_distance > min_distance:
            if not self.position:
                self.buy()
                self.last_action_price = current_price
        
        # Sell signal: price near resistance, above minimum distance from last trade
        if current_price >= resistance * 0.99 and price_distance > min_distance:
            if self.position:
                self.sell()
                self.last_action_price = current_price


