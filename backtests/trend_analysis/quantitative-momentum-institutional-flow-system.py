import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Capital basis calculation
        capital_basis = (close * 2 + high + low) / 4 * 10
        fast_capital_ema = self.I(pta.ema, capital_basis, length=13)
        slow_capital_ema = self.I(pta.ema, capital_basis, length=34)
        capital_diff = fast_capital_ema - slow_capital_ema
        capital_signal = self.I(pta.ema, capital_diff, length=5)
        
        # Net flow histogram
        self.net_flow_hist = self.I(lambda: 2 * (capital_diff - capital_signal) * 5.5)
        self.inst_flow_in = self.I(lambda: np.where(self.net_flow_hist >= 0, self.net_flow_hist, 0))
        self.inst_flow_out = self.I(lambda: np.where(self.net_flow_hist <= 0, self.net_flow_hist, 0))
        
        # Trend calculation
        highest_high_55 = self.I(lambda: high.rolling(55).max())
        lowest_low_55 = self.I(lambda: low.rolling(55).min())
        trend_raw = self.I(lambda: (close - lowest_low_55) / np.maximum(highest_high_55 - lowest_low_55, 0.001) * 100)
        
        sma_trend_raw = self.I(pta.sma, trend_raw, length=5)
        sma_sma_trend = self.I(pta.sma, sma_trend_raw, length=3)
        trend_smoothed = self.I(lambda: 3 * sma_trend_raw - 2 * sma_sma_trend)
        self.trend_main = self.I(pta.ema, trend_smoothed, length=3)
        
        # Momentum acceleration
        self.mom_accel = self.I(lambda: ((self.trend_main - np.roll(self.trend_main, 1)) / np.maximum(np.roll(self.trend_main, 1), 0.001)) * 100)
        
        # Signal flags
        self.is_accumulating = self.I(lambda: self.trend_main <= 13)
        self.is_breaking_out = self.I(lambda: (self.trend_main <= 13) & (self.mom_accel > 13))
        self.is_exhausted = self.I(lambda: (self.trend_main > 90) & (self.trend_main > np.roll(self.trend_main, 1)))
    
    def next(self):
        # Buy signals
        if len(self.data) > 1:
            if self.is_breaking_out[-1] and not self.is_breaking_out[-2]:
                if not self.position:
                    self.buy()
            
            # Sell signals
            if self.is_exhausted[-1] and not self.is_exhausted[-2]:
                if self.position:
                    self.position.close()
            
            # Exit if trend deteriorates
            if len(self.data) > 2:
                if self.position and self.trend_main[-1] > 90 and self.trend_main[-1] < self.trend_main[-2]:
                    if self.inst_flow_in[-1] < self.inst_flow_in[-2]:
                        self.position.close()


