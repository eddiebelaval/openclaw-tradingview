import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ha_length = 25

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        def calculate_heikin_ashi():
            ha_close = (open_ + high + low + close) / 4
            ha_open = pd.Series(index=close.index, dtype=float)
            ha_open.iloc[0] = (open_.iloc[0] + close.iloc[0]) / 2
            
            for i in range(1, len(close)):
                ha_open.iloc[i] = (ha_open.iloc[i-1] + ha_close.iloc[i-1]) / 2
            
            ha_high = pd.concat([open_, high, ha_close], axis=1).max(axis=1)
            ha_low = pd.concat([low, ha_open, ha_close], axis=1).min(axis=1)
            
            avg_ha = (ha_open + ha_high + ha_low + ha_close) / 4
            return avg_ha

        avg_ha = calculate_heikin_ashi()
        self.ha_ma = self.I(pta.wma, avg_ha, length=self.ha_length)

    def next(self):
        if len(self.data) < 2:
            return

        if crossover(self.ha_ma, self.ha_ma[-2]):
            if not self.position:
                self.buy()
        elif crossover(self.ha_ma[-2], self.ha_ma):
            if self.position:
                self.position.close()