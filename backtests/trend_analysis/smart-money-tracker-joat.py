import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Order Block Settings
    obLookback = 10
    obStrength = 0.5
    
    # Fair Value Gap Settings
    fvgMinSize = 0.3
    
    # Liquidity Settings
    liqLookback = 20
    
    # Market Structure Settings
    swingLength = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume analysis
        self.volMA = self.I(pta.sma, volume, length=20)
        self.highVolume = volume > self.volMA * 1.5
        
        # ATR for displacement detection
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Highest/Lowest for liquidity zones
        self.recentHigh = self.I(lambda: high.rolling(self.liqLookback).max())
        self.recentLow = self.I(lambda: low.rolling(self.liqLookback).min())
        
        # Pivot points for market structure
        self.swingHighs = self.I(lambda: self._pivothigh(high, self.swingLength, self.swingLength))
        self.swingLows = self.I(lambda: self._pivotlow(low, self.swingLength, self.swingLength))
        
        # Tracking variables
        self.lastSwingHigh = np.nan
        self.lastSwingLow = np.nan
        self.currentTrend = 0  # 1 = uptrend, -1 = downtrend
        self.equalHighCount = 0
        self.equalLowCount = 0
        self.lastEqualHigh = np.nan
        self.lastEqualLow = np.nan
        
        self.bullishOBCount = 0
        self.bearishOBCount = 0
        self.fvgCount = 0
        self.sweepSignal = 0

    def _pivothigh(self, series, leftBars, rightBars):
        """Detect pivot highs"""
        result = pd.Series(np.nan, index=series.index)
        for i in range(leftBars, len(series) - rightBars):
            if series.iloc[i] == series.iloc[max(0, i-leftBars):i+1].max() and \
               series.iloc[i] == series.iloc[i:min(len(series), i+rightBars+1)].max():
                result.iloc[i] = series.iloc[i]
        return result

    def _pivotlow(self, series, leftBars, rightBars):
        """Detect pivot lows"""
        result = pd.Series(np.nan, index=series.index)
        for i in range(leftBars, len(series) - rightBars):
            if series.iloc[i] == series.iloc[max(0, i-leftBars):i+1].min() and \
               series.iloc[i] == series.iloc[i:min(len(series), i+rightBars+1)].min():
                result.iloc[i] = series.iloc[i]
        return result

    def next(self):
        close = self.data.Close
        open_ = self.data.Open
        high = self.data.High
        low = self.data.Low
        volume = self.data.Volume
        
        if len(self.data) < self.swingLength + 5:
            return
        
        # Order Block Detection
        isBullishOB = (close[-3] < open_[-3] and 
                       close[-2] < open_[-2] and 
                       close[-1] > open_[-1] and
                       (close[-1] - low[-2]) / low[-2] * 100 > self.obStrength and
                       (self.highVolume[-2] or self.highVolume[-1]))
        
        isBearishOB = (close[-3] > open_[-3] and 
                       close[-2] > open_[-2] and 
                       close[-1] < open_[-1] and
                       (high[-2] - close[-1]) / close[-1] * 100 > self.obStrength and
                       (self.highVolume[-2] or self.highVolume[-1]))
        
        if isBullishOB:
            self.bullishOBCount += 1
        
        if isBearishOB:
            self.bearishOBCount += 1
        
        # Fair Value Gap Detection
        bullFVG = low[-1] > high[-3] and close[-2] > high[-3]
        fvgBullSize = (low[-1] - high[-3]) / high[-3] * 100 if high[-3] != 0 else 0
        
        bearFVG = high[-1] < low[-3] and close[-2] < low[-3]
        fvgBearSize = (low[-3] - high[-1]) / high[-1] * 100 if high[-1] != 0 else 0
        
        if bullFVG and fvgBullSize > self.fvgMinSize:
            self.fvgCount += 1
        
        if bearFVG and fvgBearSize > self.fvgMinSize:
            self.fvgCount += 1
        
        # Liquidity Sweep Detection
        sweepHigh = high[-1] > self.recentHigh[-2] and close[-1] < self.recentHigh[-2]
        sweepLow = low[-1] < self.recentLow[-2] and close[-1] > self.recentLow[-2]
        
        volConfirmedSweepHigh = sweepHigh and volume[-1] > self.volMA[-1] * 1.5
        volConfirmedSweepLow = sweepLow and volume[-1] > self.volMA[-1] * 1.5
        
        # Market Structure
        swingHigh = not np.isnan(self.swingHighs[-1])
        swingLow = not np.isnan(self.swingLows[-1])
        
        if swingHigh:
            if not np.isnan(self.lastSwingHigh):
                if self.swingHighs[-1] > self.lastSwingHigh:
                    if self.currentTrend == 1:
                        self.sweepSignal = 1
                    else:
                        self.currentTrend = 1
                        self.sweepSignal = 1
            self.lastSwingHigh = self.swingHighs[-1]
        
        if swingLow:
            if not np.isnan(self.lastSwingLow):
                if self.swingLows[-1] < self.lastSwingLow:
                    if self.currentTrend == -1:
                        self.sweepSignal = -1
                    else:
                        self.currentTrend = -1
                        self.sweepSignal = -1
            self.lastSwingLow = self.swingLows[-1]
        
        # Displacement Detection
        displacement = abs(close[-1] - open_[-1]) > self.atr[-1] * 2 and volume[-1] > self.volMA[-1] * 2
        
        # Trading Logic
        # Buy signals: Bullish OB, FVG filled from below, sweep low, displacement up
        if (isBullishOB or volConfirmedSweepLow or (displacement and close[-1] > open_[-1])):
            if not self.position:
                self.buy()
        
        # Sell signals: Bearish OB, FVG filled from above, sweep high, displacement down
        elif (isBearishOB or volConfirmedSweepHigh or (displacement and close[-1] < open_[-1])):
            if self.position:
                self.sell()
        
        # Exit on trend reversal
        if self.position and self.currentTrend == -1:
            if self.position.is_long:
                self.sell()
        elif self.position and self.currentTrend == 1:
            if not self.position.is_long:
                self.buy()