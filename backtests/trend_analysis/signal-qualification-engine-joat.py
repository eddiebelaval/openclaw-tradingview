import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend parameters
    i_trend_fast = 21
    i_trend_slow = 55
    i_adx_len = 14
    i_adx_thresh = 20
    
    # Momentum parameters
    i_rsi_len = 14
    i_rsi_ob = 70
    i_rsi_os = 30
    i_stoch_k = 14
    i_stoch_d = 3
    
    # Volume parameters
    i_vol_len = 20
    i_vol_mult = 1.2
    i_use_vol = True
    
    # Structure parameters
    i_swing_left = 5
    i_swing_right = 2
    i_use_structure = True
    
    # Signal parameters
    i_min_score = 4
    i_cooldown = 5
    i_confirm_close = True
    
    # Quality parameters
    i_min_rr = 1.5
    i_filter_time = False
    i_start_hour = 9
    i_end_hour = 16

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Trend indicators
        self.ma_fast = self.I(pta.ema, close, length=self.i_trend_fast)
        self.ma_slow = self.I(pta.ema, close, length=self.i_trend_slow)
        
        # ADX calculation
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.i_adx_len))
        self.adx = self.I(lambda: adx_result['ADX_14'] if adx_result is not None and 'ADX_14' in adx_result.columns else pd.Series(20, index=close.index))
        self.plus_di = self.I(lambda: adx_result['DMP_14'] if adx_result is not None and 'DMP_14' in adx_result.columns else pd.Series(20, index=close.index))
        self.minus_di = self.I(lambda: adx_result['DMN_14'] if adx_result is not None and 'DMN_14' in adx_result.columns else pd.Series(20, index=close.index))
        
        # Momentum indicators
        self.rsi = self.I(pta.rsi, close, length=self.i_rsi_len)
        
        # Stochastic
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=self.i_stoch_k, d=self.i_stoch_d, smooth_k=3))
        self.stoch_k = self.I(lambda: stoch_result['STOCHk_14_3_3'] if stoch_result is not None and 'STOCHk_14_3_3' in stoch_result.columns else pd.Series(50, index=close.index))
        self.stoch_d = self.I(lambda: stoch_result['STOCHd_14_3_3'] if stoch_result is not None and 'STOCHd_14_3_3' in stoch_result.columns else pd.Series(50, index=close.index))
        
        # Volume indicators
        self.vol_ma = self.I(pta.sma, volume, length=self.i_vol_len)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Swing highs and lows
        self.swing_high = self.I(lambda: high.rolling(self.i_swing_left + self.i_swing_right + 1).max().shift(self.i_swing_right))
        self.swing_low = self.I(lambda: low.rolling(self.i_swing_left + self.i_swing_right + 1).min().shift(self.i_swing_right))
        
        # State tracking
        self.bars_since_long = 999
        self.bars_since_short = 999
        self.last_swing_high = np.nan
        self.last_swing_low = np.nan

    def next(self):
        # Increment cooldown counters
        self.bars_since_long += 1
        self.bars_since_short += 1
        
        # Current values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        ma_fast = self.ma_fast[-1]
        ma_slow = self.ma_slow[-1]
        rsi = self.rsi[-1]
        stoch_k = self.stoch_k[-1]
        stoch_d = self.stoch_d[-1]
        vol_ma = self.vol_ma[-1]
        atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        adx = self.adx[-1] if not np.isnan(self.adx[-1]) else 20
        plus_di = self.plus_di[-1] if not np.isnan(self.plus_di[-1]) else 20
        minus_di = self.minus_di[-1] if not np.isnan(self.minus_di[-1]) else 20
        
        # Update swing tracking
        if len(self.data) > self.i_swing_left + self.i_swing_right + 1:
            if not np.isnan(self.swing_high[-1]):
                self.last_swing_high = self.swing_high[-1]
            if not np.isnan(self.swing_low[-1]):
                self.last_swing_low = self.swing_low[-1]
        
        # ═══════════ TREND LAYER ═══════════
        ma_bullish = ma_fast > ma_slow
        ma_bearish = ma_fast < ma_slow
        price_above_ma = close > ma_fast and close > ma_slow
        price_below_ma = close < ma_fast and close < ma_slow
        trend_strong = adx >= self.i_adx_thresh
        
        trend_score = 0
        if ma_bullish:
            trend_score += 1
        if price_above_ma:
            trend_score += 1
        if trend_strong and plus_di > minus_di:
            trend_score += 1
        
        trend_score_bear = 0
        if ma_bearish:
            trend_score_bear += 1
        if price_below_ma:
            trend_score_bear += 1
        if trend_strong and minus_di > plus_di:
            trend_score_bear += 1
        
        # ═══════════ MOMENTUM LAYER ═══════════
        rsi_bullish = rsi > 50 and rsi < self.i_rsi_ob
        rsi_bearish = rsi < 50 and rsi > self.i_rsi_os
        rsi_momentum_up = rsi > (self.rsi[-4] if len(self.data) >= 4 else rsi)
        rsi_momentum_down = rsi < (self.rsi[-4] if len(self.data) >= 4 else rsi)
        
        stoch_bullish = stoch_k > stoch_d and stoch_k < 80
        stoch_bearish = stoch_k < stoch_d and stoch_k > 20
        
        momentum_score = 0
        if rsi_bullish:
            momentum_score += 1
        if rsi_momentum_up:
            momentum_score += 1
        if stoch_bullish:
            momentum_score += 1
        
        momentum_score_bear = 0
        if rsi_bearish:
            momentum_score_bear += 1
        if rsi_momentum_down:
            momentum_score_bear += 1
        if stoch_bearish:
            momentum_score_bear += 1
        
        # ═══════════ VOLUME LAYER ═══════════
        volume_above_avg = volume > vol_ma
        volume_confirm = volume > vol_ma * self.i_vol_mult
        
        volume_score = 0
        if volume_above_avg:
            volume_score += 1
        if volume_confirm:
            volume_score += 1
        
        # ═══════════ STRUCTURE LAYER ═══════════
        higher_high = not np.isnan(self.last_swing_high) and high > self.last_swing_high
        lower_low = not np.isnan(self.last_swing_low) and low < self.last_swing_low
        above_swing_low = close > (self.last_swing_low if not np.isnan(self.last_swing_low) else low)
        below_swing_high = close < (self.last_swing_high if not np.isnan(self.last_swing_high) else high)
        
        structure_score = 0
        structure_score_bear = 0
        
        if self.i_use_structure:
            if above_swing_low:
                structure_score += 1
            if higher_high:
                structure_score += 1
            if below_swing_high:
                structure_score_bear += 1
            if lower_low:
                structure_score_bear += 1
        else:
            structure_score = 1
            structure_score_bear = 1
        
        # ═══════════ COMPOSITE QUALIFICATION ═══════════
        vol_score_adjusted = volume_score if self.i_use_vol else 2
        bull_total = trend_score + momentum_score + vol_score_adjusted + structure_score
        bear_total = trend_score_bear + momentum_score_bear + vol_score_adjusted + structure_score_bear
        max_score = 10
        
        bull_qual_pct = float(bull_total) / float(max_score) * 100
        bear_qual_pct = float(bear_total) / float(max_score) * 100
        
        bull_qualified = bull_total >= self.i_min_score
        bear_qualified = bear_total >= self.i_min_score
        
        bull_premium = bull_total >= self.i_min_score + 2 and trend_score >= 2 and momentum_score >= 2
        bear_premium = bear_total >= self.i_min_score + 2 and trend_score_bear >= 2 and momentum_score_bear >= 2
        
        # ═══════════ TRIGGER CONDITIONS ═══════════
        ma_cross_up = crossover(self.data.Close, self.ma_fast)
        ma_cross_down = crossover(self.ma_fast, self.data.Close)
        stoch_cross_up = crossover(self.stoch_k, self.stoch_d)
        stoch_cross_down = crossover(self.stoch_d, self.stoch_k)
        
        bull_trigger = ma_cross_up or (rsi_momentum_up and stoch_cross_up)
        bear_trigger = ma_cross_down or (rsi_momentum_down and stoch_cross_down)
        
        # ═══════════ SESSION FILTER ═══════════
        in_session = True
        if self.i_filter_time:
            current_hour = pd.Timestamp(self.data.index[-1]).hour
            in_session = current_hour >= self.i_start_hour and current_hour < self.i_end_hour
        
        # ═══════════ STOP AND TARGET CALCULATIONS ═══════════
        if atr > 0:
            long_stop = self.last_swing_low - atr * 0.2 if not np.isnan(self.last_swing_low) else close - atr * 2
            short_stop = self.last_swing_high + atr * 0.2 if not np.isnan(self.last_swing_high) else close + atr * 2
        else:
            long_stop = close - 0.02 * close
            short_stop = close + 0.02 * close
        
        long_risk = close - long_stop
        short_risk = short_stop - close
        
        long_target_1 = close + long_risk * self.i_min_rr if long_risk > 0 else close
        short_target_1 = close - short_risk * self.i_min_rr if short_risk > 0 else close
        
        # ═══════════ SIGNAL GENERATION ═══════════
        long_signal = bull_qualified and bull_trigger and self.bars_since_long > self.i_cooldown and in_session
        short_signal = bear_qualified and bear_trigger and self.bars_since_short > self.i_cooldown and in_session
        
        # ═══════════ EXECUTION ═══════════
        if long_signal:
            if not self.position:
                self.buy()
            self.bars_since_long = 0
        
        if short_signal:
            if self.position:
                self.position.close()
            self.sell()
            self.bars_since_short = 0
        
        # Exit long on target or stop
        if self.position and self.position.is_long:
            if close >= long_target_1 or close <= long_stop:
                self.position.close()
        
        # Exit short on target or stop
        if self.position and self.position.is_short:
            if close <= short_target_1 or close >= short_stop:
                self.position.close()