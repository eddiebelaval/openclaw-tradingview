import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthER = 10
    smoothLen = 3
    wickWeight = 0.25
    assetMode = "Crypto / High Volatility"
    
    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Set thresholds based on asset mode
        if self.assetMode == "Crypto / High Volatility":
            self.trendThresh = 0.40
            self.chopThresh = 0.18
        elif self.assetMode == "Forex / Low Volatility":
            self.trendThresh = 0.55
            self.chopThresh = 0.28
        elif self.assetMode == "Stocks / Medium Volatility":
            self.trendThresh = 0.48
            self.chopThresh = 0.22
        else:
            self.trendThresh = 0.45
            self.chopThresh = 0.20
        
        # Calculate net move
        def calc_net_move():
            return pd.Series([
                abs(close.iloc[i] - close.iloc[max(0, i - self.lengthER)])
                for i in range(len(close))
            ], index=close.index)
        
        # Calculate path sum
        def calc_path_sum():
            result = []
            for i in range(len(close)):
                if i < self.lengthER:
                    path = sum(abs(close.iloc[j] - close.iloc[j-1]) for j in range(1, i+1))
                else:
                    path = sum(abs(close.iloc[j] - close.iloc[j-1]) for j in range(i - self.lengthER + 1, i+1))
                result.append(path)
            return pd.Series(result, index=close.index)
        
        # Calculate raw ER
        def calc_raw_er():
            net_move = calc_net_move()
            path_sum = calc_path_sum()
            return net_move / path_sum.where(path_sum != 0, 1e-10)
        
        # Calculate wick ratio
        def calc_wick_ratio():
            body_size = abs(close - open_)
            total_range = high - low
            wick_ratio = 1.0 - (body_size / total_range.where(total_range > 0, 1e-10))
            return wick_ratio
        
        # Calculate adjusted ER
        def calc_adjusted_er():
            raw_er = calc_raw_er()
            wick_ratio = calc_wick_ratio()
            avg_wick = pta.sma(wick_ratio, length=self.lengthER)
            wick_penalty = 1.0 - (np.sqrt(avg_wick) * self.wickWeight)
            wick_penalty = np.maximum(wick_penalty, 0.0)
            return raw_er * wick_penalty
        
        self.rawER = self.I(calc_raw_er)
        self.adjustedER = self.I(calc_adjusted_er)
        self.efficiency = self.I(lambda: pta.ema(self.adjustedER, length=self.smoothLen))
        
        # Direction calculation
        def calc_direction():
            return close - close.shift(self.lengthER)
        
        self.direction = self.I(calc_direction)
    
    def next(self):
        if len(self.data) < self.lengthER + 1:
            return
        
        current_eff = self.efficiency[-1]
        
        # Determine regime
        is_clean_trend = current_eff >= self.trendThresh
        is_chop = current_eff <= self.chopThresh
        direction = self.direction[-1] if len(self.direction) > 0 else 0
        
        # Trading logic based on efficiency transitions
        # Enter long on bullish trend signal
        if is_clean_trend and direction > 0:
            if not self.position:
                self.buy()
        
        # Enter short on bearish trend signal
        elif is_clean_trend and direction < 0:
            if self.position:
                self.position.close()
        
        # Exit on entering chop zone
        elif is_chop:
            if self.position:
                self.position.close()