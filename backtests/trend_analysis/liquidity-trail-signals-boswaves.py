import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_len = 28
    atr_len = 15
    atr_mult = 1.25
    swing_len = 12
    entry_mode = "Signal Change"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.ma = self.I(pta.ema, close, length=self.ma_len)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)

        self.trend = 1
        self.trail = None
        self.pending_dir = 0
        self.pending_trail = None

        self.raw_up = self.I(lambda: self.ma - self.atr * self.atr_mult)
        self.raw_dn = self.I(lambda: self.ma + self.atr * self.atr_mult)

    def next(self):
        if len(self.data) < self.ma_len + self.atr_len:
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        ma_val = self.ma[-1]
        atr_val = self.atr[-1]

        raw_up = ma_val - atr_val * self.atr_mult
        raw_dn = ma_val + atr_val * self.atr_mult

        if self.trail is None:
            self.trail = raw_up if close > ma_val else raw_dn
            self.trend = 1 if close > ma_val else -1
        else:
            prev_trend = self.trend

            if self.trend == 1:
                self.trail = max(raw_up, self.trail)
                if close < self.trail:
                    self.trend = -1
                    self.trail = raw_dn
            else:
                self.trail = min(raw_dn, self.trail)
                if close > self.trail:
                    self.trend = 1
                    self.trail = raw_up

            flip_bull = self.trend == 1 and prev_trend == -1
            flip_bear = self.trend == -1 and prev_trend == 1

            if flip_bull:
                self.pending_dir = 1
                self.pending_trail = self.trail

            if flip_bear:
                self.pending_dir = -1
                self.pending_trail = self.trail

            retest_bull_entry = (
                self.entry_mode == "Trail Retest"
                and self.pending_dir == 1
                and low <= self.pending_trail
                and close >= self.pending_trail
            )
            retest_bear_entry = (
                self.entry_mode == "Trail Retest"
                and self.pending_dir == -1
                and high >= self.pending_trail
                and close <= self.pending_trail
            )

