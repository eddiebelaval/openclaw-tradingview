            sig_bear_entry = self.entry_mode == "Signal Change" and flip_bear

            do_bull_entry = sig_bull_entry or retest_bull_entry
            do_bear_entry = sig_bear_entry or retest_bear_entry

            if retest_bull_entry or retest_bear_entry:
                self.pending_dir = 0

            if do_bull_entry:
                if self.position:
                    self.position.close()
                self.buy()
            elif do_bear_entry:
                if self.position:
                    self.position.close()
                self.sell()