import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 14

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.roc = self.I(lambda: pta.roc(close, length=self.lookback))

    def next(self):
        if len(self) < self.lookback + 1:
            return
        
        roc_val = self.roc[-1]
        
        if roc_val is None:
            return
        
        if roc_val > 0 and (len(self) == 1 or self.roc[-2] <= 0):
            if not self.position:
                self.buy()
        elif roc_val < 0 and (len(self) == 1 or self.roc[-2] >= 0):
            if self.position:
                self.position.close()


