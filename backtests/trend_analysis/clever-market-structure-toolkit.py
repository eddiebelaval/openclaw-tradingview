import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_len = 7
    internal_len = 3
    v_mult = 1.5
    r_mult = 1.5
    atr_len = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # ATR for range detection
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)

        # Volume SMA for impulse detection
        self.vol_sma = self.I(pta.sma, volume, length=20)

        # Pivot detection using rolling max/min
        self.pivot_high_swing = self.I(
            lambda: high.rolling(window=2*self.swing_len+1, center=True).max()
        )
        self.pivot_low_swing = self.I(
            lambda: low.rolling(window=2*self.swing_len+1, center=True).min()
        )

        self.pivot_high_internal = self.I(
            lambda: high.rolling(window=2*self.internal_len+1, center=True).max()
        )
        self.pivot_low_internal = self.I(
            lambda: low.rolling(window=2*self.internal_len+1, center=True).min()
        )

        # State tracking
        self.last_swing_h = None
        self.last_swing_l = None
        self.last_int_h = None
        self.last_int_l = None
        self.trend = 0
        self.int_trend = 0
        self.range_h = None
        self.range_l = None
        self.idm_level = None
        self.idm_taken = False

    def next(self):
        if len(self) < self.swing_len + 1:
            return

        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]

        # Update pivot tracking
        if not pd.isna(self.pivot_high_swing[-1]):
            if self.pivot_high_swing[-1] == high_val or (
                len(self) > self.swing_len and
                self.data.High[-self.swing_len] == self.pivot_high_swing[-1]
            ):
                self.last_swing_h = self.pivot_high_swing[-1]

        if not pd.isna(self.pivot_low_swing[-1]):
            if self.pivot_low_swing[-1] == low_val or (
                len(self) > self.swing_len and
                self.data.Low[-self.swing_len] == self.pivot_low_swing[-1]
            ):
                self.last_swing_l = self.pivot_low_swing[-1]

        if not pd.isna(self.pivot_high_internal[-1]):
            self.last_int_h = self.pivot_high_internal[-1]

        if not pd.isna(self.pivot_low_internal[-1]):
            self.last_int_l = self.pivot_low_internal[-1]

        # BOS/CHoCH Logic - Swing Bullish (Strong)
        if (self.last_swing_h is not None and
            close_val > self.last_swing_h and
            len(self) > 1 and
            self.data.Close[-2] <= self.last_swing_h):

            if self.trend == -1:
                # CHoCH
                pass
            # BOS or CHoCH triggered
            self.trend = 1
            self.last_swing_h = None
            if self.last_swing_l is not None:
                self.range_l = self.last_swing_l
            self.range_h = high_val

        # BOS/CHoCH Logic - Swing Bearish (Strong)
        elif (self.last_swing_l is not None and
              close_val < self.last_swing_l and
              len(self) > 1 and
              self.data.Close[-2] >= self.last_swing_l):

            if self.trend == 1:
                # CHoCH
                pass
            # BOS or CHoCH triggered
            self.trend = -1
            self.last_swing_l = None
            if self.last_swing_h is not None:
                self.range_h = self.last_swing_h
            self.range_l = low_val

        # Live Range Expansion
        if self.trend == 1 and high_val > (self.range_h or -np.inf):
            self.range_h = high_val
        elif self.trend == -1 and low_val < (self.range_l or np.inf):
            self.range_l = low_val

        # IDM (Inducement) Logic
        if self.last_int_l is not None or self.last_int_h is not None:
            if self.trend == 1 and self.last_int_l is not None:
                self.idm_level = self.last_int_l
                self.idm_taken = False
            elif self.trend == -1 and self.last_int_h is not None:
                self.idm_level = self.last_int_h
                self.idm_taken = False

        # IDM Sweep Detection
        if self.idm_level is not None and not self.idm_taken:
            if self.trend == 1 and low_val < self.idm_level:
                self.idm_taken = True
            elif self.trend == -1 and high_val > self.idm_level:
                self.idm_taken = True

        # Impulse Detection (High Volume + High Range)
        atr_val = self.atr[-1] if not pd.isna(self.atr[-1]) else 0
        vol_avg = self.vol_sma[-1] if not pd.isna(self.vol_sma[-1]) else 0
        range_val = abs(close_val - self.data.Open[-1])

        is_impulse = (
            volume_val > vol_avg * self.v_mult and
            range_val > atr_val * self.r_mult
        )

        # Trading Logic
        # Buy signals
        if self.trend == 1:
            # BOS/CHoCH bullish + impulse confirmation
            if is_impulse and not self.position:
                self.buy()
            # IDM sweep provides confirmation
            elif self.idm_taken and not self.position:
                self.buy()

        # Sell signals
        elif self.trend == -1:
            # Close long positions on bearish CHoCH
            if self.position:
                self.sell()

        # Breakeven or profit protection
        if self.position and self.idm_level is not None:
            if self.trend == 1 and close_val > self.idm_level * 1.02:
                # Let winners run
                pass
            elif self.trend == -1 and self.position:
                self.sell()

        # Simple exit on trend reversal
        if self.position:
            if self.trend != 1:
                self.sell()


