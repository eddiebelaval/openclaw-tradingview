import pandas as pd
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        if len(self.data) < 2:
            return
        
        current_time = self.data.index[-1]
        prev_time = self.data.index[-2]
        
        current_hour = current_time.hour
        current_minute = current_time.minute
        prev_hour = prev_time.hour
        prev_minute = prev_time.minute
        
        current_time_minutes = current_hour * 60 + current_minute
        prev_time_minutes = prev_hour * 60 + prev_minute
        
        window_start = 8 * 60 + 20
        window_end = 9 * 60 + 20
        
        in_window = window_start <= current_time_minutes < window_end
        prev_in_window = window_start <= prev_time_minutes < window_end
        
        start_window = in_window and not prev_in_window
        
        if start_window:
            if not self.position:
                self.buy()
        elif in_window:
            if self.position:
                pass
        else:
            if self.position:
                self.sell()


