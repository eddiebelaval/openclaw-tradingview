    def _get_price_position(self, close, high, low):
        """Calculate price position in band (0-1)"""
        upper = self._get_upper_band(close, high, low)
        lower = self._get_lower_band(close, high, low)
        
        if len(upper) == 0 or len(lower) == 0:
            return pd.Series(0.5, index=close.index)
        
        position = (close - lower) / (upper - lower)
        return position.clip(0, 1)
    
    def _get_renko_level(self, close, high, low):
        """Get renko trend level"""
        # Simplified renko: use close with smoothing
        return pta.rma(close, length=self.renko_smoothing) or close
    
    def _get_renko_direction(self, close, high, low):
        """Get renko direction (1 for up, -1 for down)"""
        renko = pta.rma(close, length=self.renko_smoothing)
        if renko is None or len(renko) < 2:
            return pd.Series(1, index=close.index)
        
        direction = np.where(renko > renko.shift(1), 1, np.where(renko < renko.shift(1), -1, 0))
        return pd.Series(direction, index=close.index).fillna(method='ffill').fillna(1)
    
