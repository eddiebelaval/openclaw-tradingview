import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    pivot_len = 5

    def init(self):
        self.last_highs = [np.nan, np.nan, np.nan]
        self.last_lows = [np.nan, np.nan, np.nan]
        self.last_highs_bar_index = [np.nan, np.nan, np.nan]
        self.last_lows_bar_index = [np.nan, np.nan, np.nan]
        self.buy_signal_bar = np.nan
        self.sell_signal_bar = np.nan
        self.position_open = False

    def next(self):
        current_bar = len(self.data) - 1
        
        if current_bar < self.pivot_len * 2:
            return
        
        high = self.data.High
        low = self.data.Low
        
        ph = self._pivot_high(high, self.pivot_len)
        pl = self._pivot_low(low, self.pivot_len)
        
        if not np.isnan(ph):
            self.last_highs.pop(0)
            self.last_highs.append(ph)
            
            self.last_highs_bar_index.pop(0)
            self.last_highs_bar_index.append(current_bar - self.pivot_len)
        
        if not np.isnan(pl):
            self.last_lows.pop(0)
            self.last_lows.append(pl)
            
            self.last_lows_bar_index.pop(0)
            self.last_lows_bar_index.append(current_bar - self.pivot_len)
        
        if (not np.isnan(self.last_highs[0]) and 
            not np.isnan(self.last_highs[1]) and 
            not np.isnan(self.last_highs[2])):
            if (self.last_highs[2] > self.last_highs[1] and 
                self.last_highs[1] > self.last_highs[0]):
                self.buy_signal_bar = self.last_highs_bar_index[2]
        
        if (not np.isnan(self.last_lows[0]) and 
            not np.isnan(self.last_lows[1]) and 
            not np.isnan(self.last_lows[2])):
            if (self.last_lows[2] < self.last_lows[1] and 
                self.last_lows[1] < self.last_lows[0]):
                self.sell_signal_bar = self.last_lows_bar_index[2]
        
        if current_bar == self.buy_signal_bar and not self.position:
            self.buy()
            self.position_open = True
        
        if current_bar == self.sell_signal_bar and self.position:
            self.sell()
            self.position_open = False

    def _pivot_high(self, high, length):
        if len(high) < length * 2 + 1:
            return np.nan
        
        current_idx = len(high) - 1
        left_idx = current_idx - length
        right_idx = current_idx + length
        
        if right_idx >= len(high):
            return np.nan
        
        current_high = high[current_idx]
        
        is_pivot = True
        for i in range(left_idx, current_idx):
            if high[i] >= current_high:
                is_pivot = False
                break
        
        if is_pivot:
            for i in range(current_idx + 1, right_idx + 1):
                if high[i] >= current_high:
                    is_pivot = False
                    break
        
        return current_high if is_pivot else np.nan

    def _pivot_low(self, low, length):
        if len(low) < length * 2 + 1:
            return np.nan
        
        current_idx = len(low) - 1
        left_idx = current_idx - length
        right_idx = current_idx + length
        
        if right_idx >= len(low):
            return np.nan
        
        current_low = low[current_idx]
        
        is_pivot = True
        for i in range(left_idx, current_idx):
            if low[i] <= current_low:
                is_pivot = False
                break
        
        if is_pivot:
            for i in range(current_idx + 1, right_idx + 1):
                if low[i] <= current_low:
                    is_pivot = False
                    break
        
        return current_low if is_pivot else np.nan