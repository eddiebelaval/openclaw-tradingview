import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_p = 1
    atr_m = 5.0
    alpha_p = 14
    alpha_m = 1.0
    magic_p = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # DMI (ADX)
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        
        # ATR for alpha calculation
        at_atr = self.I(lambda: pta.sma(pta.atr(high, low, close, length=self.alpha_p), length=self.alpha_p))
        
        # Alpha lines
        self.alpha_up = self.I(lambda: low - (at_atr * self.alpha_m))
        self.alpha_dn = self.I(lambda: high + (at_atr * self.alpha_m))
        
        # MFI for alpha line logic
        mfi = self.I(lambda: pta.mfi(high, low, close, volume, length=self.alpha_p) or pd.Series(50, index=close.index))
        
        # Magic CCI
        magic_cci = self.I(lambda: pta.cci(high, low, close, length=self.magic_p) or pd.Series(0, index=close.index))
        
        # ATR for UT Bot
        atr_v = self.I(lambda: pta.atr(high, low, close, length=self.atr_p))
        
        # Volume check
        vol_sma = self.I(lambda: pta.sma(volume, length=20))
        
        self.mfi = mfi
        self.magic_cci = magic_cci
        self.atr_v = atr_v
        self.vol_sma = vol_sma
        self.trend = 0
        self.n_loss = close.iloc[0]
        self.alpha_line = close.iloc[0]

    def next(self):
        if len(self.data) < 2:
            return
            
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        close_prev = self.data.Close[-2]
        high_prev = self.data.High[-2]
        low_prev = self.data.Low[-2]
        
        # Update alpha_line
        if self.mfi[-1] is not None and self.mfi[-1] >= 50:
            if self.alpha_up[-1] is not None:
                self.alpha_line = max(self.alpha_line, self.alpha_up[-1]) if self.alpha_up[-1] < self.alpha_line else self.alpha_up[-1]
        else:
            if self.alpha_dn[-1] is not None:
                self.alpha_line = min(self.alpha_line, self.alpha_dn[-1]) if self.alpha_dn[-1] > self.alpha_line else self.alpha_dn[-1]
        
        # UT Bot Logic
        if self.atr_v[-1] is not None:
            x_atr = self.atr_v[-1] * self.atr_m
            prev_l = self.n_loss
            
            if close > prev_l and close_prev > prev_l:
                self.n_loss = max(prev_l, close - x_atr)
            elif close < prev_l and close_prev < prev_l:
                self.n_loss = min(prev_l, close + x_atr)
            elif close > prev_l:
                self.n_loss = close - x_atr
            else:
                self.n_loss = close + x_atr
        
        # Trend logic
        magic_bull = self.magic_cci[-1] > 0 if self.magic_cci[-1] is not None else False
        vol_ok = volume > self.vol_sma[-1] if self.vol_sma[-1] is not None else True
        
        is_bull = magic_bull and close > self.n_loss and close > self.alpha_line
        is_bear = not magic_bull and close < self.n_loss and close < self.alpha_line
        
        prev_trend = self.trend
        
        if is_bull:
            self.trend = 1
        elif is_bear:
            self.trend = -1
        
        trend_changed_to_bull = self.trend == 1 and prev_trend != 1
        trend_changed_to_bear = self.trend == -1 and prev_trend != -1
        
        # Trading signals
        if trend_changed_to_bull:
            if self.position:
                self.sell()
            else:
                self.buy()
        
        if trend_changed_to_bear:
            if self.position:
                self.sell()


