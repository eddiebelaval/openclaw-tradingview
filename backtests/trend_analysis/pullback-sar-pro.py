import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sarStart = 0.01
    sarStep = 0.01
    sarMax = 0.1
    useVWAP = True
    useVolume = True
    volLen = 20
    volMult = 1.0
    maxSignalsWindow = 222
    maxSignalsTrend = 1
    tpPerc = 0.035 / 100
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hlc3 = (high + low + close) / 3
        
        # SAR calculation
        self.sar = self.I(self._calculate_sar, high, low, close)
        
        # VWAP calculation
        self.vwap = self.I(lambda: pta.vwap(hlc3, volume) or pd.Series(0, index=close.index))
        
        # Volume MA
        self.volMA = self.I(pta.sma, volume, length=self.volLen)
        
        # Track state
        self.session_signals = 0
        self.trend_signals = 0
        self.last_bull_trend = None
        self.last_bear_trend = None
        self.in_session = False
        self.last_in_session = False
        
    def _calculate_sar(self, high, low, close):
        sar_values = []
        hp = high.iloc[0]
        lp = low.iloc[0]
        af = self.sarStart
        sar = lp if close.iloc[0] > low.iloc[0] else hp
        uptrend = close.iloc[0] > low.iloc[0]
        
        for i in range(len(close)):
            if uptrend:
                sar = sar + af * (hp - sar)
                sar = min(sar, low.iloc[max(0, i-1):i+1].min())
                if low.iloc[i] < sar:
                    uptrend = False
                    sar = hp
                    lp = low.iloc[i]
                    af = self.sarStart
                else:
                    if high.iloc[i] > hp:
                        hp = high.iloc[i]
                        af = min(af + self.sarStep, self.sarMax)
            else:
                sar = sar - af * (sar - lp)
                sar = max(sar, high.iloc[max(0, i-1):i+1].max())
                if high.iloc[i] > sar:
                    uptrend = True
                    sar = lp
                    hp = high.iloc[i]
                    af = self.sarStart
                else:
                    if low.iloc[i] < lp:
                        lp = low.iloc[i]
                        af = min(af + self.sarStep, self.sarMax)
            
            sar_values.append(sar)
        
        return pd.Series(sar_values, index=close.index)
    
    def next(self):
        if len(self.data) < 2:
            return
        
        close_curr = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        high_curr = self.data.High[-1]
        high_prev = self.data.High[-2]
        low_curr = self.data.Low[-1]
        low_prev = self.data.Low[-2]
        volume_curr = self.data.Volume[-1]
        sar_curr = self.sar[-1]
        sar_prev = self.sar[-2] if len(self.sar) > 1 else sar_curr
        vwap_curr = self.vwap[-1]
        volMA_curr = self.volMA[-1]
        
        bull_trend = close_curr > sar_curr
        bear_trend = close_curr < sar_curr
        
        bull_trend_prev = self.last_bull_trend if self.last_bull_trend is not None else bull_trend
        bear_trend_prev = self.last_bear_trend if self.last_bear_trend is not None else bear_trend
        
        # Check pullback conditions
        pullback_bull = bull_trend_prev and close_prev < self.data.Close[-3] if len(self.data) >= 3 else False
        pullback_bear = bear_trend_prev and close_prev > self.data.Close[-3] if len(self.data) >= 3 else False
        
        # Reentry signals
        long_signal_raw = pullback_bull and bull_trend and close_curr > close_prev
        short_signal_raw = pullback_bear and bear_trend and close_curr < close_prev
        
        # Filters
        long_vwap = not self.useVWAP or close_curr > vwap_curr
        short_vwap = not self.useVWAP or close_curr < vwap_curr
        volume_ok = not self.useVolume or volume_curr > volMA_curr * self.volMult
        
        # Session filter (simplified - always true for backtest)
        in_session = True
        
        # SAR flip detection
        sar_flipped = (bull_trend != bull_trend_prev) or (bear_trend != bear_trend_prev)
        if sar_flipped:
            self.trend_signals = 0
        
        # Final signals
        long_signal = (
            long_signal_raw
            and in_session
            and volume_ok
            and self.session_signals < self.maxSignalsWindow
            and self.trend_signals < self.maxSignalsTrend
            and long_vwap
        )
        
        short_signal = (
            short_signal_raw
            and in_session
            and volume_ok
            and self.session_signals < self.maxSignalsWindow
            and self.trend_signals < self.maxSignalsTrend
            and short_vwap
        )
        
        if long_signal:
            self.buy()
            self.session_signals += 1
            self.trend_signals += 1
        elif short_signal:
            self.sell()
            self.session_signals += 1
            self.trend_signals += 1
        
        # Take profit exit
        if self.position.is_long:
            tp_price = self.position.open_price * (1 + self.tpPerc)
            if close_curr >= tp_price:
                self.position.close()
        elif self.position.is_short:
            tp_price = self.position.open_price * (1 - self.tpPerc)
            if close_curr <= tp_price:
                self.position.close()
        
        self.last_bull_trend = bull_trend
        self.last_bear_trend = bear_trend
        self.last_in_session = in_session


