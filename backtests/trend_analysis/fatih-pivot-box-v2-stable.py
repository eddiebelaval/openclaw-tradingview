import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema1 = self.I(pta.ema, close, length=10)
        self.ema2 = self.I(pta.ema, close, length=21)
        
        # Calculate pivot points (using current bar values for simplicity)
        # In a real scenario with HTF, we'd need to resample, but for backtest we'll use current TF
        self.pp = self.I(lambda: (high + low + close) / 3)

    def next(self):
        # Simple trading rules based on EMA crossovers
        # Buy when fast EMA (10) crosses above slow EMA (21)
        if len(self.data) > 21:
            if crossover(self.ema1, self.ema2):
                if not self.position:
                    self.buy()
            # Sell when fast EMA (10) crosses below slow EMA (21)
            elif crossover(self.ema2, self.ema1):
                if self.position:
                    self.position.close()


