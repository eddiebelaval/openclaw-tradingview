import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    period_input = 120
    min_swing_bars = 8
    proj_choice = "0.618"
    forward_step_bars = 12
    rows_input = 26
    profile_width_bars = 18
    delta_width_bars = 10
    atr_len_input = 14
    row_size_mode = "Auto"
    manual_ticks_per_row = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len_input)
        
        self.swing_high = self.I(lambda: high.rolling(window=self.period_input).max())
        self.swing_low = self.I(lambda: low.rolling(window=self.period_input).min())
        
        self.in_position = False

    def next(self):
        if len(self.data) < self.period_input:
            return
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        
        swing_high = self.swing_high[-1]
        swing_low = self.swing_low[-1]
        swing_range = swing_high - swing_low
        
        if swing_range <= 0:
            return
        
        proj_base_ratio = {
            "0.236": 0.236,
            "0.382": 0.382,
            "0.500": 0.500,
            "0.618": 0.618,
            "0.786": 0.786
        }.get(self.proj_choice, 0.618)
        
        is_bullish = True
        if len(self.data) >= 2:
            recent_low_offset = self._find_recent_low(10)
            recent_high_offset = self._find_recent_high(10)
            is_bullish = recent_low_offset > recent_high_offset
        
        if is_bullish:
            fib_price = swing_high - swing_range * proj_base_ratio
        else:
            fib_price = swing_low + swing_range * proj_base_ratio
        
        target1 = swing_high + swing_range * 1.0 if is_bullish else swing_low - swing_range * 1.0
        target2 = swing_high + swing_range * 1.272 if is_bullish else swing_low - swing_range * 1.272
        target3 = swing_high + swing_range * 1.618 if is_bullish else swing_low - swing_range * 1.618
        
        if not self.position:
            if is_bullish:
                if current_close > fib_price and current_low <= swing_low:
                    self.buy()
                    self.in_position = True
            else:
                if current_close < fib_price and current_high >= swing_high:
                    self.buy()
                    self.in_position = True
        else:
            if is_bullish:
                if current_high >= target3:
                    self.sell()
                    self.in_position = False
                elif current_low <= swing_low * 0.95:
                    self.sell()
                    self.in_position = False
            else:
                if current_low <= target3:
                    self.sell()
                    self.in_position = False
                elif current_high >= swing_high * 1.05:
                    self.sell()
                    self.in_position = False

    def _find_recent_low(self, lookback):
        low_slice = self.data.Low[-lookback:]
        return lookback - 1 - np.argmin(low_slice.values)

    def _find_recent_high(self, lookback):
        high_slice = self.data.High[-lookback:]
        return lookback - 1 - np.argmax(high_slice.values)


