import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    signal_length = 11
    linreg_length = 11

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Triple RMA smoothing for OHLC
        bopen = self.I(lambda: pta.rma(pta.rma(pta.rma(open_, length=self.signal_length), length=self.signal_length), length=self.signal_length))
        bhigh = self.I(lambda: pta.rma(pta.rma(pta.rma(high, length=self.signal_length), length=self.signal_length), length=self.signal_length))
        blow = self.I(lambda: pta.rma(pta.rma(pta.rma(low, length=self.signal_length), length=self.signal_length), length=self.signal_length))
        bclose = self.I(lambda: pta.rma(pta.rma(pta.rma(close, length=self.signal_length), length=self.signal_length), length=self.signal_length))
        
        self.bopen = bopen
        self.bhigh = bhigh
        self.blow = blow
        self.bclose = bclose
        
        # Heikin-Ashi Close
        self.haclose = self.I(lambda: (self.bopen + self.bhigh + self.blow + self.bclose) / 4)
        
        # Signal line (triple RMA of haclose)
        self.signal = self.I(lambda: pta.rma(pta.rma(pta.rma(self.haclose, length=self.signal_length), length=self.signal_length), length=self.signal_length))

    def next(self):
        # Calculate haopen with history tracking
        if len(self.data) < 2:
            return
        
