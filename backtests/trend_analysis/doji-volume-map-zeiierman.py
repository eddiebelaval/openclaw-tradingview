import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback_length = 200
    vol_length = 20
    rel_vol_mult = 1.3
    body_pct = 25.0
    min_range_atr_frac = 0.20

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate body size and candle range
        self.body_size = self.I(lambda: np.abs(close - open_))
        self.candle_range = self.I(lambda: high - low)
        
        # Body percentage of range
        self.body_pct_series = self.I(
            lambda: np.where(
                self.candle_range > 0,
                (self.body_size / self.candle_range) * 100.0,
                100.0
            )
        )

        # Volume calculations
        vol_avg = self.I(lambda: pta.sma(volume, length=self.vol_length))
        vol_std = self.I(
            lambda: volume.rolling(window=self.vol_length).std()
        )
        
        self.vol_z = self.I(
            lambda: np.where(
                vol_std > 0,
                (volume - vol_avg) / vol_std,
                0.0
            )
        )

        # ATR calculation
        atr = self.I(lambda: pta.atr(high, low, close, length=14) or pd.Series(0, index=close.index))
        
        # Min range check
        self.min_range_ok = self.I(
            lambda: self.candle_range >= atr * self.min_range_atr_frac
        )

        # Relative volume check
        self.rel_high_vol = self.I(
            lambda: volume > vol_avg * self.rel_vol_mult
        )

        # Volume rising check
        self.vol_rising = self.I(
            lambda: volume > volume.shift(1).fillna(volume.iloc[0])
        )

        # Loose doji check (small body, reasonable range)
        self.loose_doji = self.I(
            lambda: (self.candle_range > 0) & 
                    (self.body_pct_series <= self.body_pct) & 
                    (self.min_range_ok)
        )

        # Main signal: relative high volume + rising volume + loose doji
        self.signal = self.I(
            lambda: self.rel_high_vol & self.vol_rising & self.loose_doji
        )

        # Signal price (hl2)
        self.signal_price = self.I(lambda: (high + low) / 2.0)

    def next(self):
        # Buy when signal is detected
        if len(self.data) > 0 and self.signal[-1]:
            if not self.position:
                self.buy()
        
        # Simple exit: if we have been in a position for more than 10 bars without another signal
        if self.position:
            bars_in_position = len(self.data) - self.position.open_time
            if bars_in_position > 10:
                self.position.close()


