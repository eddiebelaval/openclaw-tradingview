import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ath_price = 25476.40
    
    def init(self):
        self.current_anchor = self.ath_price
        self.anchor_history = []
        self.up_90_history = []
        self.up_180_history = []
        self.dn_90_history = []
        self.dn_180_history = []
        self.dn_270_history = []
        self.dn_360_history = []
        self.full_cycle_up_history = []
        self.full_cycle_down_history = []
    
    def get_price(self, r, step):
        return (r + step) ** 2
    
    def next(self):
        root_now = np.sqrt(self.current_anchor)
        full_cycle_up = self.get_price(root_now, 2.0)
        full_cycle_down = self.get_price(root_now, -2.0)
        
        if self.data.Close[-1] > full_cycle_up:
            self.current_anchor = full_cycle_up
        
        if self.data.Close[-1] < full_cycle_down:
            self.current_anchor = full_cycle_down
        
        active_root = np.sqrt(self.current_anchor)
        
        up_90 = self.get_price(active_root, 0.5)
        up_180 = self.get_price(active_root, 1.0)
        dn_90 = self.get_price(active_root, -0.5)
        dn_180 = self.get_price(active_root, -1.0)
        dn_270 = self.get_price(active_root, -1.5)
        dn_360 = self.get_price(active_root, -2.0)
        
        self.anchor_history.append(self.current_anchor)
        self.up_90_history.append(up_90)
        self.up_180_history.append(up_180)
        self.dn_90_history.append(dn_90)
        self.dn_180_history.append(dn_180)
        self.dn_270_history.append(dn_270)
        self.dn_360_history.append(dn_360)
        self.full_cycle_up_history.append(full_cycle_up)
        self.full_cycle_down_history.append(full_cycle_down)
        
        current_price = self.data.Close[-1]
        
        buy_signal = False
        sell_signal = False
        
        if len(self.dn_360_history) > 1:
            if current_price < dn_360 and self.data.Close[-2] >= self.dn_360_history[-2]:
                buy_signal = True
            elif current_price < dn_180 and current_price > dn_270:
                if len(self.dn_180_history) > 1 and self.data.Close[-2] <= self.dn_180_history[-2]:
                    buy_signal = True
        
        if len(self.full_cycle_up_history) > 1:
            if current_price > full_cycle_up and self.data.Close[-2] <= self.full_cycle_up_history[-2]:
                sell_signal = True
            elif current_price > up_180 and current_price < full_cycle_up:
                if len(self.up_180_history) > 1 and self.data.Close[-2] >= self.up_180_history[-2]:
                    sell_signal = True
        
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()


