import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # OB Settings
    zscore_length = 20
    zscore_threshold = 1.5
    ob_lookback = 5
    max_age_ob = 100
    rejection_threshold_ob = 50
    obEMAPeriod = 750

    # Filters
    enableVWAPFilter = True
    enableATRFilter = False
    atrMult = 10.0

    # Display
    showEMA750 = True
    showVWAP = True
    enableATRFill = False

    # Trade Settings
    rrSlPips = 10.0
    rrRatio = 3.0

    # Session
    useSessionFilter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hl2 = (high + low) / 2

        # Indicators
        self.vwap = self.I(lambda: pta.vwap(hl2, volume) or pd.Series(hl2.mean(), index=close.index))
        self.ema750 = self.I(lambda: pta.ema(close, length=750) or pd.Series(close.mean(), index=close.index))
        self.obEMA = self.I(lambda: pta.ema(close, length=self.obEMAPeriod) or pd.Series(close.mean(), index=close.index))

        tr = self.I(lambda: pta.true_range(high, low, close) or pd.Series(0, index=close.index))
        self.smoothATR = self.I(lambda: pta.ema(tr, length=750) or pd.Series(0.1, index=close.index))

        self.upperBand = self.I(lambda: self.ema750 + self.atrMult * self.smoothATR)
        self.lowerBand = self.I(lambda: self.ema750 - self.atrMult * self.smoothATR)

        # Z-score calculation
        price_change = close.diff()
        avg_change = price_change.rolling(window=self.zscore_length).mean()
        std_change = price_change.rolling(window=self.zscore_length).std()
        self.zscore = self.I(lambda: (price_change - avg_change) / (std_change + 1e-10))

        # Highest/Lowest for impulse detection
        self.highest_close = self.I(lambda: close.rolling(window=self.ob_lookback).max())
        self.lowest_close = self.I(lambda: close.rolling(window=self.ob_lookback).min())

        # State tracking
        self.active_zones = []
        self.active_trades = []
        self.in_trade = False
        self.last_signal = None

        # Stats
        self.total_trades = 0
        self.total_wins = 0
        self.total_win_pips = 0.0
        self.total_loss_pips = 0.0

    def detect_bullish_impulse(self):
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        ema750_val = self.ema750[-1]
        obEMA_val = self.obEMA[-1]
        vwap_val = self.vwap[-1]
        zscore_val = self.zscore[-1]
        upperBand_val = self.upperBand[-1]

        vwap_cond = not self.enableVWAPFilter or close > vwap_val
        atr_cond = not self.enableATRFilter or close <= upperBand_val
        ema_cond = not True or close > obEMA_val
        ema750_cond = close > ema750_val

        bullish_impulse = (
            zscore_val > self.zscore_threshold
            and close > open_price
            and ema_cond
            and atr_cond
            and vwap_cond
            and ema750_cond
        )

        if len(self.data) > self.ob_lookback:
            highest_val = self.highest_close[-1]
            if len(self.data) > 1:
                highest_prev = self.highest_close[-2] if len(self.highest_close) > 1 else highest_val
                strong_bull = bullish_impulse and close > highest_prev
            else:
                strong_bull = bullish_impulse and close > highest_val
        else:
            strong_bull = False

        return strong_bull

    def detect_bearish_impulse(self):
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        ema750_val = self.ema750[-1]
        obEMA_val = self.obEMA[-1]
        vwap_val = self.vwap[-1]
        zscore_val = self.zscore[-1]
        lowerBand_val = self.lowerBand[-1]

        vwap_cond = not self.enableVWAPFilter or close < vwap_val
        atr_cond = not self.enableATRFilter or close >= lowerBand_val
        ema_cond = not True or close < obEMA_val
        ema750_cond = close < ema750_val

        bearish_impulse = (
            zscore_val < -self.zscore_threshold
            and close < open_price
            and ema_cond
            and atr_cond
            and vwap_cond
            and ema750_cond
        )

        if len(self.data) > self.ob_lookback:
            lowest_val = self.lowest_close[-1]
            if len(self.data) > 1:
                lowest_prev = self.lowest_close[-2] if len(self.lowest_close) > 1 else lowest_val
                strong_bear = bearish_impulse and close < lowest_prev
            else:
                strong_bear = bearish_impulse and close < lowest_val
        else:
            strong_bear = False

        return strong_bear

    def detect_bull_rejection(self):
        if len(self.data) < 2:
            return False

        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        low = self.data.Low[-1]
        ema750_val = self.ema750[-1]
        obEMA_val = self.obEMA[-1]
        vwap_val = self.vwap[-1]
        upperBand_val = self.upperBand[-1]

        ema_c = not True or close > obEMA_val
        vwap_c = not self.enableVWAPFilter or close > vwap_val
        ema750_c = close > ema750_val
        atr_c = not self.enableATRFilter or close <= upperBand_val

        if len(self.active_zones) > 0:
            for zone in self.active_zones:
                if zone['is_bullish'] and zone['is_active']:
                    zone_height = zone['top'] - zone['bottom']
                    rejection_distance = zone_height * (self.rejection_threshold_ob / 100)

                    touches_zone = low <= zone['top'] and low >= zone['bottom']
                    bounces_up = close > open_price and (close - low) > rejection_distance

                    if touches_zone and bounces_up and ema_c and vwap_c and ema750_c and atr_c:
                        return True

        return False

    def detect_bear_rejection(self):
        if len(self.data) < 2:
            return False

        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high = self.data.High[-1]
        ema750_val = self.ema750[-1]
        obEMA_val = self.obEMA[-1]
        vwap_val = self.vwap[-1]
        lowerBand_val = self.lowerBand[-1]

        ema_c = not True or close < obEMA_val
        vwap_c = not self.enableVWAPFilter or close < vwap_val
        ema750_c = close < ema750_val
        atr_c = not self.enableATRFilter or close >= lowerBand_val

        if len(self.active_zones) > 0:
            for zone in self.active_zones:
                if not zone['is_bullish'] and zone['is_active']:
                    zone_height = zone['top'] - zone['bottom']
                    rejection_distance = zone_height * (self.rejection_threshold_ob / 100)

                    touches_zone = high >= zone['bottom'] and high <= zone['top']
                    bounces_down = close < open_price and (high - close) > rejection_distance

                    if touches_zone and bounces_down and ema_c and vwap_c and ema750_c and atr_c:
                        return True

        return False

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        current_bar = len(self.data) - 1

        # Update zone ages and status
        for zone in self.active_zones:
            zone['age'] = current_bar - zone['birth_bar']
            if zone['age'] > self.max_age_ob:
                zone['is_active'] = False

            # Check mitigation
            if zone['is_bullish']:
                if close < zone['bottom']:
                    zone['is_active'] = False
            else:
                if close > zone['top']:
                    zone['is_active'] = False

        # Create new zones
        if self.detect_bullish_impulse():
            low_lookback = low
            high_lookback = high
            for i in range(1, min(self.ob_lookback + 1, len(self.data))):
                if self.data.Low[-i] < low_lookback:
                    low_lookback = self.data.Low[-i]
                    high_lookback = self.data.High[-i]

            new_zone = {
                'top': high_lookback,
                'bottom': low_lookback,
                'birth_bar': current_bar,
                'is_bullish': True,
                'is_active': True,
                'age': 0
            }
            self.active_zones.append(new_zone)

        if self.detect_bearish_impulse():
            high_lookback = high
            low_lookback = low
            for i in range(1, min(self.ob_lookback + 1, len(self.data))):
                if self.data.High[-i] > high_lookback:
                    high_lookback = self.data.High[-i]
                    low_lookback = self.data.Low[-i]

            new_zone = {
                'top': high_lookback,
                'bottom': low_lookback,
                'birth_bar': current_bar,
                'is_bullish': False,
                'is_active': True,
                'age': 0
            }
            self.active_zones.append(new_zone)

        # Update trades
        closed_indices = []
        for idx, trade_info in enumerate(self.active_trades):
            sl_level = trade_info['sl']
            tp_level = trade_info['tp']
            is_bull = trade_info['is_bull']
            entry_price = trade_info['entry']

            sl_hit = (is_bull and low <= sl_level) or (not is_bull and high >= sl_level)
            tp_hit = (is_bull and high >= tp_level) or (not is_bull and low <= tp_level)

            if sl_hit or tp_hit:
                closed_indices.append(idx)
                pip_size = 0.0001
                pips = abs((tp_level if tp_hit else sl_level) - entry_price) / pip_size

                if tp_hit:
                    self.total_wins += 1
                    self.total_win_pips += pips
                else:
                    self.total_loss_pips += pips

                self.total_trades += 1

        for idx in sorted(closed_indices, reverse=True):
            self.active_trades.pop(idx)

        # Entry logic
        bull_rejection = self.detect_bull_rejection()
        bear_rejection = self.detect_bear_rejection()

        if bull_rejection and len(self.active_trades) == 0:
            entry = close
            sl_dist = (entry - low) + self.rrSlPips * 0.0001
            sl = entry - sl_dist
            tp = entry + sl_dist * self.rrRatio

            self.active_trades.append({
                'entry': entry,
                'sl': sl,
                'tp': tp,
                'is_bull': True
            })
            self.buy()

        if bear_rejection and len(self.active_trades) == 0:
            entry = close
            sl_dist = (high - entry) + self.rrSlPips * 0.0001
            sl = entry + sl_dist
            tp = entry - sl_dist * self.rrRatio

            self.active_trades.append({
                'entry': entry,
                'sl': sl,
                'tp': tp,
                'is_bull': False
            })
            self.sell()