import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_period = 20
    max_lines = 5
    use_vol_filter = False
    vol_multiplier = 1.0

    def init(self):
        self.resistance_levels = []
        self.support_levels = []
        
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        self.vol_avg = self.I(pta.sma, volume, length=20)
        self.vol_relative = self.I(lambda: (volume / (self.vol_avg + 1e-10)) * 100)
        
        self.pivot_high = self.I(self._calc_pivot_high, high, self.pivot_period)
        self.pivot_low = self.I(self._calc_pivot_low, low, self.pivot_period)
        
        self.buy_sweep_signal = self.I(lambda: pd.Series(0, index=close.index))
        self.sell_sweep_signal = self.I(lambda: pd.Series(0, index=close.index))

    def _calc_pivot_high(self, high_series, period):
        result = pd.Series(np.nan, index=high_series.index)
        for i in range(period, len(high_series) - period):
            window = high_series.iloc[i - period:i + period + 1]
            if high_series.iloc[i] == window.max():
                result.iloc[i] = high_series.iloc[i]
        return result

    def _calc_pivot_low(self, low_series, period):
        result = pd.Series(np.nan, index=low_series.index)
        for i in range(period, len(low_series) - period):
            window = low_series.iloc[i - period:i + period + 1]
            if low_series.iloc[i] == window.min():
                result.iloc[i] = low_series.iloc[i]
        return result

    def next(self):
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        current_vol = self.data.Volume[-1]
        
        vol_avg_val = self.vol_avg[-1] if len(self.vol_avg) > 0 else 1
        vol_relative_val = (current_vol / (vol_avg_val + 1e-10)) * 100
        
        is_vol_strong = not self.use_vol_filter or (current_vol > vol_avg_val * self.vol_multiplier)
        
        buy_sweep_occurred = False
        sell_sweep_occurred = False
        
        if not np.isnan(self.pivot_high[-1]):
            ph_price = self.pivot_high[-1]
            self.resistance_levels.append({
                'price': ph_price,
                'bar': len(self.data) - 1
            })
            
            if len(self.resistance_levels) > self.max_lines:
                self.resistance_levels.pop(0)
        
        if not np.isnan(self.pivot_low[-1]):
            pl_price = self.pivot_low[-1]
            self.support_levels.append({
                'price': pl_price,
                'bar': len(self.data) - 1
            })
            
            if len(self.support_levels) > self.max_lines:
                self.support_levels.pop(0)
        
        levels_to_remove_res = []
        for idx, lvl in enumerate(self.resistance_levels):
            price_swept = current_high > lvl['price'] and current_close <= lvl['price']
            broken = current_close > lvl['price']
            
            if price_swept and is_vol_strong:
                buy_sweep_occurred = True
                levels_to_remove_res.append(idx)
            elif broken:
                levels_to_remove_res.append(idx)
        
        for idx in sorted(levels_to_remove_res, reverse=True):
            self.resistance_levels.pop(idx)
        
        levels_to_remove_sup = []
        for idx, lvl in enumerate(self.support_levels):
            price_swept = current_low < lvl['price'] and current_close >= lvl['price']
            broken = current_close < lvl['price']
            
            if price_swept and is_vol_strong:
                sell_sweep_occurred = True
                levels_to_remove_sup.append(idx)
            elif broken:
                levels_to_remove_sup.append(idx)
        
        for idx in sorted(levels_to_remove_sup, reverse=True):
            self.support_levels.pop(idx)
        
        if buy_sweep_occurred and not self.position:
            self.buy()
        elif sell_sweep_occurred and self.position:
            self.position.close()


