import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema7 = self.I(pta.ema, close, length=7)
        self.ema25 = self.I(pta.ema, close, length=25)
        self.ema99 = self.I(pta.ema, close, length=99)
        
        self.lowest_low = self.I(lambda: low.rolling(window=500).min())
        self.highest_high = self.I(lambda: high.rolling(window=500).max())
        
        self.in_position = False

    def next(self):
        if len(self.data) < 100:
            return
        
        current_close = self.data.Close[-1]
        ema7_val = self.ema7[-1]
        ema25_val = self.ema25[-1]
        ema99_val = self.ema99[-1]
        
        if ema7_val is None or ema25_val is None or ema99_val is None:
            return
        
        lowest = self.lowest_low[-1]
        highest = self.highest_high[-1]
        
        if lowest is None or highest is None or np.isnan(lowest) or np.isnan(highest):
            return
        
        buy_signal = False
        sell_signal = False
        
        if len(self.ema7) > 1 and len(self.ema25) > 1:
            if crossover(self.ema7, self.ema25):
                buy_signal = True
            elif crossover(self.ema25, self.ema7):
                sell_signal = True
        
        if not self.in_position and buy_signal:
            if current_close <= lowest * 1.02:
                self.buy()
                self.in_position = True
        
        elif self.in_position and sell_signal:
            if current_close >= highest * 0.98:
                self.sell()
                self.in_position = False