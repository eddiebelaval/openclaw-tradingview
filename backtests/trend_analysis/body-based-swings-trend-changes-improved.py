        low = pd.Series(self.data.Low)
        
        # Calculate body extremes
        self.bodyHigh = self.I(lambda: np.maximum(open_, close))
        self.bodyLow = self.I(lambda: np.minimum(open_, close))
        
        # Calculate pivot highs and lows using rolling max/min
        def pivot_high(body_high, left_bars, right_bars):
            result = pd.Series(np.nan, index=body_high.index)
            for i in range(left_bars + right_bars, len(body_high)):
                if body_high.iloc[i - right_bars] == body_high.iloc[i - right_bars - left_bars:i - right_bars + 1].max():
                    result.iloc[i - right_bars] = body_high.iloc[i - right_bars]
            return result
        
