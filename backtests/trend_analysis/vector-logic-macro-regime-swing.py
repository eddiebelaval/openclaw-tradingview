import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_fast_len = 20
    ma_slow_len = 50
    ma_exit_len = 10
    obv_ma_len = 20
    use_macro = True
    macro_len = 60
    chop_confirm = 7
    max_zone_pct = 200.0
    tp_pct = 5.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.ma_fast = self.I(pta.ema, close, length=self.ma_fast_len)
        self.ma_slow = self.I(pta.ema, close, length=self.ma_slow_len)
        self.ma_exit = self.I(pta.ema, close, length=self.ma_exit_len)

        self.obv_val = self.I(pta.obv, close, volume)
        self.obv_ma = self.I(pta.ema, self.obv_val, length=self.obv_ma_len)

        self.mac_top = self.I(lambda: high.rolling(self.macro_len).max())
        self.mac_bot = self.I(lambda: low.rolling(self.macro_len).min())

        self.trade_state = 0
        self.entry_price = np.nan
        self.tp1_hit = False

    def next(self):
        if len(self.data) < self.macro_len + 1:
            return

        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        high_prev = self.data.High[-2]
        low_prev = self.data.Low[-2]

        ma_fast = self.ma_fast[-1]
        ma_slow = self.ma_slow[-1]
        ma_exit = self.ma_exit[-1]

        obv_val = self.obv_val[-1]
        obv_ma = self.obv_ma[-1]

        mac_top = self.mac_top[-1]
        mac_bot = self.mac_bot[-1]

        if mac_bot <= 0.001:
            mac_bot = low

        is_green = close > open_
        is_red = close < open_

        struct_bull = ma_fast > ma_slow
        struct_bear = ma_fast < ma_slow

        break_high = close > high_prev
        break_low = close < low_prev

        act_bull = close > ma_fast and is_green and break_high
        act_bear = close < ma_fast and is_red and break_low

        vol_bull = obv_val > obv_ma
        vol_bear = obv_val < obv_ma

        hi_bars = 0
        lo_bars = 0
        for i in range(1, min(self.macro_len + 1, len(self.data))):
            if self.data.High[-i] >= mac_top:
                hi_bars = i - 1
                break
        for i in range(1, min(self.macro_len + 1, len(self.data))):
            if self.data.Low[-i] <= mac_bot:
                lo_bars = i - 1
                break

        is_macro_chop = (hi_bars >= self.chop_confirm and lo_bars >= self.chop_confirm and len(self.data) > self.macro_len)

        zone_height_pct = ((mac_top - mac_bot) / mac_bot) * 100 if mac_bot > 0 else 999999
        if zone_height_pct > self.max_zone_pct:
            is_macro_chop = False

        macro_block = self.use_macro and is_macro_chop

        trig_long = struct_bull and act_bull and vol_bull and not macro_block
        trig_short = struct_bear and act_bear and vol_bear and not macro_block

        exit_long = close < ma_exit
        exit_short = close > ma_exit

        if self.trade_state == 0:
            if trig_long:
                self.buy()
                self.trade_state = 1
                self.entry_price = close
                self.tp1_hit = False
