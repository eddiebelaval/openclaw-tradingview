            score = 0.0
            if (is_buy and v_up) or (not is_buy and v_dn):
                score += 1
            if near(close, vwap_val):
                score += 1
            if is_buy and close < vwap_val:
                score += 1
            if not is_buy and close > vwap_val:
                score += 1
            return score
        
