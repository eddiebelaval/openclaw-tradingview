        high_2 = self.data.High[-2]
        low_2 = self.data.Low[-2]
        
        sp = max(high - low, 0.0001)
        vd = volume * (close - low) / sp - volume * (high - close) / sp
        v_up = vd > 0
        v_dn = vd < 0
        
