import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    internal_lookback = 5
    swing_lookback = 50
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Pivot highs and lows for internal structure
        self.iH = self.I(lambda: self._pivot_high(high, self.internal_lookback))
        self.iL = self.I(lambda: self._pivot_low(low, self.internal_lookback))
        
        # Pivot highs and lows for swing structure
        self.sH = self.I(lambda: self._pivot_high(high, self.swing_lookback))
        self.sL = self.I(lambda: self._pivot_low(low, self.swing_lookback))
        
        # Track trend states
        self.internal_trend = 0
        self.swing_trend = 0
        
        # Track last pivot levels
        self.last_internal_high = None
        self.last_internal_low = None
        self.last_swing_high = None
        self.last_swing_low = None
        
        # Track last lower low and higher high for CHoCH+ detection
        self.last_internal_high_2 = None
        self.last_internal_low_2 = None
        self.last_swing_high_2 = None
        self.last_swing_low_2 = None
    
    def _pivot_high(self, series, period):
        """Identify pivot highs"""
        if len(series) < period:
            return pd.Series(np.nan, index=series.index)
        
        pivots = pd.Series(np.nan, index=series.index)
        rolling_max = series.rolling(window=period*2+1, center=True).max()
        
        for i in range(period, len(series) - period):
            if series.iloc[i] == rolling_max.iloc[i]:
                pivots.iloc[i] = series.iloc[i]
        
        return pivots
    
    def _pivot_low(self, series, period):
        """Identify pivot lows"""
        if len(series) < period:
            return pd.Series(np.nan, index=series.index)
        
        pivots = pd.Series(np.nan, index=series.index)
        rolling_min = series.rolling(window=period*2+1, center=True).min()
        
        for i in range(period, len(series) - period):
            if series.iloc[i] == rolling_min.iloc[i]:
                pivots.iloc[i] = series.iloc[i]
        
        return pivots
    
