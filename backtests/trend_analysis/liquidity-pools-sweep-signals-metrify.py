class TvStrategy(Strategy):
    swinglen = 9
    mergeatr = 0.35
    activatescoring = False
    scoremintrigger = 65.0
    wickratioscale = 1.50
    usedisplacementconfirm = False
    volumemalen = 20
    volumespikemult = 1.2
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.atrfast = self.I(pta.atr, high, low, close, length=14)
        self.volmanow = self.I(pta.sma, volume, length=self.volumemalen)
        self.ema200 = self.I(pta.ema, close, length=200)
        
        self.h_sweeps = []
        self.l_sweeps = []
        self.last_bull_sweep = False
        self.last_bear_sweep = False
        
        self.ph_array = []
        self.pl_array = []
        self.calc_pivot_highs_lows()
    
    def calc_pivot_highs_lows(self):
        data_len = len(self.data.Close)
        if data_len < self.swinglen * 2 + 1:
            return
        
        high_data = self.data.High
        low_data = self.data.Low
        
        for i in range(self.swinglen, data_len - self.swinglen):
            is_ph = True
            is_pl = True
            
            for j in range(1, self.swinglen + 1):
                if high_data[i] <= high_data[i - j] or high_data[i] <= high_data[i + j]:
                    is_ph = False
                if low_data[i] >= low_data[i - j] or low_data[i] >= low_data[i + j]:
                    is_pl = False
            
            if is_ph:
                self.ph_array.append((i, high_data[i]))
            if is_pl:
                self.pl_array.append((i, low_data[i]))
    
    def f_clamp(self, v, lo, hi):
        return max(lo, min(hi, v))
    
    def f_norm01(self, x, lo, hi):
        span = max(hi - lo, 1e-6)
        return self.f_clamp((x - lo) / span, 0.0, 1.0)
    
    def f_scorepenetration(self, penatr):
        penatrmin, penatrmax = 0.05, 1.20
        lo, hi = penatrmin, penatrmax
        target = lo + (hi - lo) * 0.35
        halfspan = max((hi - lo) * 0.65, 0.20)
        tri = 1.0 - abs(penatr - target) / halfspan
        return self.f_clamp(tri, 0.0, 1.0)
    
    def f_scorereclaim(self, reclaimpct):
        reclaimmin = 50.0
        lo = reclaimmin * 0.60
        return self.f_norm01(reclaimpct, lo, 100.0)
    
    def f_scorewick(self, wickratio):
        scale = max(self.wickratioscale, 0.20)
        return self.f_clamp(wickratio / scale, 0.0, 1.0)
    
    def f_scorebodybias(self, bodyok):
        return 1.0 if bodyok else 0.30
    
    def f_scoreema(self, dir_val, closepx, emapx, atrref):
        if pd.isna(emapx) or atrref <= 0:
            return 0.5
        favoratr = (emapx - closepx) / atrref if dir_val == 1 else (closepx - emapx) / atrref
        return self.f_clamp(favoratr / 1.8, 0.0, 1.0)
    
    def f_scorelinelength(self, agebars):
        linelengthrefbars = 25
        return self.f_clamp(float(agebars) / (linelengthrefbars * 2.0), 0.0, 1.0)
    
    def f_linelengthpenalty(self, agebars):
        linelengthrefbars = 25
        ratio = self.f_clamp(float(agebars) / linelengthrefbars, 0.0, 1.0)
        shaped = pow(ratio, 1.6)
        return self.f_clamp(0.20 + shaped * 0.80, 0.20, 1.0)
    
    def f_scoremss(self, dir_val, reflevel, closepx, atrref):
        if pd.isna(reflevel) or atrref <= 0:
            return 0.0
        distatr = (reflevel - closepx) / atrref if dir_val == -1 else (closepx - reflevel) / atrref
        return self.f_clamp(distatr / 1.20, 0.0, 1.0)
    
    def f_scoreeffort(self, rangeatr, volratio):
        volscore = 0.5 if pd.isna(volratio) else self.f_norm01(volratio, 0.7, max(self.volumespikemult, 0.8))
        effortrangeatrmin = 0.80
        rangescore = self.f_norm01(rangeatr, 0.0, max(effortrangeatrmin, 0.1))
        return self.f_clamp(volscore * 0.60 + rangescore * 0.40, 0.0, 1.0)
    
    def f_scoredisplacement(self, dir_val, refbreak, closepx, bodyatr, atrref):
        if atrref <= 0 or pd.isna(refbreak):
            return 0.0
        displacementbodyatrmin = 0.35
        breakatr = (refbreak - closepx) / atrref if dir_val == -1 else (closepx - refbreak) / atrref
        breakscore = self.f_clamp(breakatr / 1.2, 0.0, 1.0)
        bodyscore = self.f_norm01(bodyatr, displacementbodyatrmin * 0.6, displacementbodyatrmin * 1.8)
        return self.f_clamp(breakscore * 0.55 + bodyscore * 0.45, 0.0, 1.0)
    
    def f_totalscore(self, basepart, mssscore, effortscore, dispscore, includedisp):
        scorewpen = 16.0
        scorewreclaim = 18.0
        scorewwick = 14.0
        scorewbody = 8.0
        scorewema = 10.0
        scorewlen = 12.0
        scorewmss = 16.0
        scoreweffort = 12.0
        scorewdisp = 8.0
        
        baseweight = scorewpen + scorewreclaim + scorewwick + scorewbody + scorewema + scorewlen
        wdisp = scorewdisp if includedisp else 0.0
        totalweight = baseweight + scorewmss + scoreweffort + wdisp
        totalpart = basepart + scorewmss * mssscore + scoreweffort * effortscore + wdisp * dispscore
        return (totalpart / totalweight * 100.0) if totalweight > 0 else 0.0
    
