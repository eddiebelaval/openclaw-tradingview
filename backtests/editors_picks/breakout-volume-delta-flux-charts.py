import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Swing detection parameters
    swing_left = 10
    swing_right = 10
    
    # Breakout configuration
    breakout_mode = "Close"  # "Close" or "Wick"
    max_levels = 5
    
    # Volume filter
    use_volume_filter = False
    volume_filter_pct = 60.0

    def init(self):
        # Store price data for swing detection
        self.swing_highs = []
        self.swing_lows = []
        self.breakout_levels_hi = []
        self.breakout_levels_lo = []
        self.mitigated_hi = []
        self.mitigated_lo = []
        
        self.last_signal = None
        self.in_position = False

    def next(self):
        # Detect swing highs and lows
        current_idx = len(self.data) - 1
        
        if current_idx >= self.swing_left + self.swing_right:
            # Check for swing high
            is_swing_high = True
            current_high = self.data.High[current_idx - self.swing_right]
            
            for i in range(self.swing_right):
                if self.data.High[current_idx - self.swing_right + i] > current_high:
                    is_swing_high = False
                    break
            
            for i in range(1, self.swing_left + 1):
                if self.data.High[current_idx - self.swing_right - i] >= current_high:
                    is_swing_high = False
                    break
            
            if is_swing_high and current_high not in self.swing_highs:
                self.swing_highs.append(current_high)
                self.breakout_levels_hi.append(current_high)
                self.mitigated_hi.append(False)
            
            # Check for swing low
            is_swing_low = True
            current_low = self.data.Low[current_idx - self.swing_right]
            
            for i in range(self.swing_right):
                if self.data.Low[current_idx - self.swing_right + i] < current_low:
                    is_swing_low = False
                    break
            
            for i in range(1, self.swing_left + 1):
                if self.data.Low[current_idx - self.swing_right - i] <= current_low:
                    is_swing_low = False
                    break
            
            if is_swing_low and current_low not in self.swing_lows:
                self.swing_lows.append(current_low)
                self.breakout_levels_lo.append(current_low)
                self.mitigated_lo.append(False)
        
        # Keep only the most recent levels
        if len(self.breakout_levels_hi) > self.max_levels:
            self.breakout_levels_hi.pop(0)
            self.mitigated_hi.pop(0)
        
        if len(self.breakout_levels_lo) > self.max_levels:
            self.breakout_levels_lo.pop(0)
            self.mitigated_lo.pop(0)
        
        # Check for breakouts of resistance levels (swing highs)
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        breakout_detected = False
        
        # Check resistance breakouts
        for i, level in enumerate(self.breakout_levels_hi):
            if not self.mitigated_hi[i]:
                if self.breakout_mode == "Wick":
                    if current_high > level:
                        self.mitigated_hi[i] = True
                        breakout_detected = True
                else:  # Close mode
                    if current_close > level:
                        self.mitigated_hi[i] = True
                        breakout_detected = True
        
        # Check support breakouts
        for i, level in enumerate(self.breakout_levels_lo):
            if not self.mitigated_lo[i]:
                if self.breakout_mode == "Wick":
                    if current_low < level:
                        self.mitigated_lo[i] = True
                        breakout_detected = True
                else:  # Close mode
                    if current_close < level:
                        self.mitigated_lo[i] = True
                        breakout_detected = True
        
        # Simple trading logic based on breakouts
        if breakout_detected and not self.position:
            # Buy on resistance breakout
            if self.data.Close[-1] > self.data.Close[-2]:
                self.buy()
                self.in_position = True
        
        # Exit on opposite breakout or simple stop loss
        if self.position:
            # Exit if price breaks support after buying
            if len(self.breakout_levels_lo) > 0:
                closest_support = min(self.breakout_levels_lo)
                if current_low < closest_support:
                    self.sell()
                    self.in_position = False
            
            # Simple stop loss at 2% below entry
            if self.data.Close[-1] < self.position.open_price * 0.98:
                self.sell()
                self.in_position = False