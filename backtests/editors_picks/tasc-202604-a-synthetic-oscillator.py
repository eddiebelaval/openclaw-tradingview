        def supersmoother(src, period):
            q = np.exp(-1.414 * np.pi / period)
            c1 = 2.0 * q * np.cos(1.414 * np.pi / period)
            c2 = q * q
            a0 = (1.0 - c1 + c2) / 2.0
            
