import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 200
    k_clusters = 5
    iters = 50
    rows_per_cluster = 20
    vp_width = 40

    def init(self):
        pass

    def next(self):
        if len(self.data) < self.lookback:
            return

        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        lookback_idx = max(0, len(self.data) - self.lookback)
        prices_lookback = close.iloc[lookback_idx:].values
        volumes_lookback = volume.iloc[lookback_idx:].values
        highs_lookback = high.iloc[lookback_idx:].values
        lows_lookback = low.iloc[lookback_idx:].values

        prices = (highs_lookback + lows_lookback) / 2.0
        min_price = np.min(lows_lookback)
        max_price = np.max(highs_lookback)

        centroids = np.linspace(min_price + (max_price - min_price) / (self.k_clusters + 1),
                                max_price - (max_price - min_price) / (self.k_clusters + 1),
                                self.k_clusters)

        assignments = np.zeros(len(prices), dtype=int)

        for _ in range(self.iters):
            for i in range(len(prices)):
                distances = np.abs(prices[i] - centroids)
                assignments[i] = np.argmin(distances)

            for j in range(self.k_clusters):
                cluster_mask = assignments == j
                if np.sum(cluster_mask) > 0:
                    weighted_sum = np.sum(prices[cluster_mask] * volumes_lookback[cluster_mask])
                    vol_sum = np.sum(volumes_lookback[cluster_mask])
                    if vol_sum > 0:
                        centroids[j] = weighted_sum / vol_sum

        cluster_vols = np.zeros(self.k_clusters)
        for j in range(self.k_clusters):
            cluster_mask = assignments == j
            cluster_vols[j] = np.sum(volumes_lookback[cluster_mask])

        poc_cluster = np.argmax(cluster_vols)

        if len(self.position) == 0:
            current_price = close.iloc[-1]
            poc_price = centroids[poc_cluster]

            if current_price < poc_price and cluster_vols[poc_cluster] > np.mean(cluster_vols):
                self.buy()
        else:
            current_price = close.iloc[-1]
            poc_price = centroids[poc_cluster]

            if current_price > poc_price * 1.02:
                self.sell()