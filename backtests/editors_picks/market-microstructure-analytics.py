import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    lookback = 20
    smooth = 5
    regime_win = 100
    w_cap = 0.70
    winsor = 3.0
    lsi_threshold = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Helper function for highest/lowest
        def highest(series, period):
            return series.rolling(window=period).max()

        def lowest(series, period):
            return series.rolling(window=period).min()

        def sma(series, period):
            return series.rolling(window=period).mean()

        def ema(series, period):
            return series.ewm(span=period, adjust=False).mean()

        def stdev(series, period):
            return series.rolling(window=period).std()

        def percentile_nearest_rank(series, period, percentile):
            return series.rolling(window=period).quantile(percentile / 100.0)

        # Base series
        dp = close.diff().fillna(0.0)
        dp_lag = dp.shift(1).fillna(0.0)

        r = np.log(close / close.shift(1)).fillna(0.0)
        mid_price = (high + low) / 2.0

        hl_valid = (high > 0) & (low > 0) & (high > low) & \
                   (high.shift(1) > 0) & (low.shift(1) > 0) & (high.shift(1) > low.shift(1))

        # Tick rule
        tick_dir = np.where(close > close.shift(1), 1,
                           np.where(close < close.shift(1), -1, 1))
        tick_dir = pd.Series(tick_dir, index=close.index).fillna(1).astype(float)
        tick_dir = tick_dir.fillna(tick_dir.shift(1)).fillna(1)

        # Signed volume for Kyle lambda
        q = tick_dir * volume

        # Layer 1: Spread estimators

        # Roll (1984)
        cov_roll = sma(dp * dp_lag, self.lookback) - \
                   sma(dp, self.lookback) * sma(dp_lag, self.lookback)
        roll_price = 2.0 * np.sqrt(np.maximum(0.0, -cov_roll))
        roll_pct_inst = np.where(close > 0, roll_price / close * 100.0, 0.0)
        spread_roll = ema(pd.Series(roll_pct_inst, index=close.index), self.smooth)

        # Corwin-Schultz (2012)
        cs_k = 3.0 - 2.0 * np.sqrt(2.0)
        beta_cs = np.where(hl_valid,
                          np.power(np.log(high / low), 2.0) +
                          np.power(np.log(high.shift(1) / low.shift(1)), 2.0), np.nan)
        gamma_cs = np.where(hl_valid,
                           np.power(np.log(np.maximum(high, high.shift(1)) /
                                         np.minimum(low, low.shift(1))), 2.0), np.nan)
        alpha_cs = np.where((~np.isnan(beta_cs)) & (~np.isnan(gamma_cs)),
                           np.maximum(0.0,
                                     (np.sqrt(2.0 * beta_cs) - np.sqrt(beta_cs)) / cs_k -
                                     np.sqrt(gamma_cs / cs_k)), np.nan)
        cs_raw = np.where(~np.isnan(alpha_cs),
                         2.0 * (np.exp(alpha_cs) - 1.0) / (1.0 + np.exp(alpha_cs)) * 100.0, np.nan)
        cs_inst = np.nan_to_num(cs_raw, nan=0.0)
        spread_cs = ema(pd.Series(cs_inst, index=close.index), self.smooth)

        # Abdi-Ranaldo (2017)
        ar_c = np.where(hl_valid,
                       np.log(close) - (np.log(high) + np.log(low)) / 2.0, np.nan)
        ar_pair_valid = np.where((hl_valid) & (hl_valid.shift(1)), 1.0, 0.0)
        ar_prod_valid = np.where(ar_pair_valid > 0,
                                np.nan_to_num(ar_c, nan=0.0) * np.nan_to_num(ar_c.shift(1), nan=0.0),
                                0.0)
        ar_n_valid = sma(pd.Series(ar_pair_valid, index=close.index), self.lookback) * float(self.lookback)
        ar_prod_sum_w = sma(pd.Series(ar_prod_valid, index=close.index), self.lookback) * float(self.lookback)
        ar_min_valid = np.maximum(3.0, np.ceil(float(self.lookback) * 0.5))
        ar_sufficient = ar_n_valid >= ar_min_valid
        ar_mean_prod = np.where(ar_sufficient, ar_prod_sum_w / ar_n_valid, 0.0)
        ar_raw = np.where(ar_sufficient,
                         2.0 * np.sqrt(np.maximum(0.0, -ar_mean_prod)) * 100.0, 0.0)
        spread_ar = ema(pd.Series(ar_raw, index=close.index), self.smooth)

        # Effective spread proxy
        eff_bar = np.where((close > 0) & (high > low),
                          2.0 * tick_dir * (close - mid_price) / close * 100.0, 0.0)
        eff_spread = sma(pd.Series(eff_bar, index=close.index), self.lookback)

        # HL range
        hl_raw = np.where((mid_price > 0) & (high > low),
                         (high - low) / mid_price * 100.0, 0.0)
        spread_hl = ema(pd.Series(hl_raw, index=close.index), self.smooth)

        # Layer 2: Liquidity metrics

        # Amihud (2002)
        dollar_vol = close * volume
        amihud_inst = np.where(dollar_vol > 0, np.abs(r) / dollar_vol, 0.0)
        amihud_sma = sma(pd.Series(amihud_inst, index=close.index), self.lookback) * 1e8

        # Kyle lambda (1985)
        cov_kl = sma(dp * q, self.lookback) - sma(dp, self.lookback) * sma(q, self.lookback)
        var_kl = np.power(stdev(q, self.lookback), 2.0)
        kl_raw = np.where(var_kl > 1e-20, cov_kl / var_kl, 0.0)
        kyle_lambda = ema(pd.Series(kl_raw * 1e6, index=close.index), self.smooth)

        # Parkinson (1980)
        park_k = 1.0 / (4.0 * np.log(2.0))
        park_inst = np.where(hl_valid,
                            park_k * np.power(np.log(high / low), 2.0), 0.0)
        park_var = sma(pd.Series(park_inst, index=close.index), self.lookback)
        park_vol = np.sqrt(np.maximum(0.0, park_var)) * 100.0

        # Layer 3: Derived signals

        # Composite spread with precision weighting
        n_comps = 3  # Roll, CS, AR

        roll_med_v = percentile_nearest_rank(pd.Series(roll_pct_inst, index=close.index), self.lookback, 50)
        roll_dev_v = np.abs(pd.Series(roll_pct_inst, index=close.index) - roll_med_v)
        roll_mad_v = percentile_nearest_rank(roll_dev_v, self.lookback, 50)
        var_roll_raw = np.power(1.4826 * roll_mad_v, 2.0)

        cs_med_v = percentile_nearest_rank(pd.Series(cs_inst, index=close.index), self.lookback, 50)
        cs_dev_v = np.abs(pd.Series(cs_inst, index=close.index) - cs_med_v)
        cs_mad_v = percentile_nearest_rank(cs_dev_v, self.lookback, 50)
        var_cs_raw = np.power(1.4826 * cs_mad_v, 2.0)

        ar_med_v = percentile_nearest_rank(pd.Series(ar_raw, index=close.index), self.lookback, 50)
        ar_dev_v = np.abs(pd.Series(ar_raw, index=close.index) - ar_med_v)
        ar_mad_v = percentile_nearest_rank(ar_dev_v, self.lookback, 50)
        var_ar_raw = np.power(1.4826 * ar_mad_v, 2.0)

        var_act_sum = var_roll_raw + var_cs_raw + var_ar_raw
        reg_eps = np.where(var_act_sum > 0, 0.05 * var_act_sum / float(n_comps), 1e-10)

        ivar_roll_r = 1.0 / (var_roll_raw + reg_eps)
        ivar_cs_r = 1.0 / (var_cs_raw + reg_eps)
        ivar_ar_r = 1.0 / (var_ar_raw + reg_eps)
        ivar_sum_r = ivar_roll_r + ivar_cs_r + ivar_ar_r

        w_roll_unc = np.where(ivar_sum_r > 0, ivar_roll_r / ivar_sum_r, 1.0 / float(n_comps))
        w_cs_unc = np.where(ivar_sum_r > 0, ivar_cs_r / ivar_sum_r, 1.0 / float(n_comps))
        w_ar_unc = np.where(ivar_sum_r > 0, ivar_ar_r / ivar_sum_r, 1.0 / float(n_comps))

        w_roll_cap = np.minimum(w_roll_unc, self.w_cap)
        w_cs_cap = np.minimum(w_cs_unc, self.w_cap)
        w_ar_cap = np.minimum(w_ar_unc, self.w_cap)
        w_cap_sum = w_roll_cap + w_cs_cap + w_ar_cap

        w_roll_f = np.where(w_cap_sum > 0, w_roll_cap / w_cap_sum, 1.0 / float(n_comps))
        w_cs_f = np.where(w_cap_sum > 0, w_cs_cap / w_cap_sum, 1.0 / float(n_comps))
        w_ar_f = np.where(w_cap_sum > 0, w_ar_cap / w_cap_sum, 1.0 / float(n_comps))

        spread_comp = w_roll_f * spread_roll + w_cs_f * spread_cs + w_ar_f * spread_ar

        # Robust z-score for composite spread
        rz_sp_med = percentile_nearest_rank(spread_comp, self.regime_win, 50)
        rz_sp_dev = np.abs(spread_comp - rz_sp_med)
        rz_sp_mad = percentile_nearest_rank(rz_sp_dev, self.regime_win, 50)
        spread_rz = np.where(rz_sp_mad > 1e-10,
                            (spread_comp - rz_sp_med) / (1.4826 * rz_sp_mad), 0.0)

        # Robust z-score for Amihud
        rz_ah_med = percentile_nearest_rank(amihud_sma, self.regime_win, 50)
        rz_ah_dev = np.abs(amihud_sma - rz_ah_med)
        rz_ah_mad = percentile_nearest_rank(rz_ah_dev, self.regime_win, 50)
        amihud_rz = np.where(rz_ah_mad > 1e-10,
                            (amihud_sma - rz_ah_med) / (1.4826 * rz_ah_mad), 0.0)

        # Robust z-score for Kyle lambda
        kyle_abs = np.abs(kyle_lambda)
        rz_kl_med = percentile_nearest_rank(kyle_abs, self.regime_win, 50)
        rz_kl_dev = np.abs(kyle_abs - rz_kl_med)
        rz_kl_mad = percentile_nearest_rank(rz_kl_dev, self.regime_win, 50)
        kyle_rz = np.where(rz_kl_mad > 1e-10,
                          (kyle_abs - rz_kl_med) / (1.4826 * rz_kl_mad), 0.0)

        # Liquidity Stress Index
        spread_rz_w = np.maximum(-self.winsor, np.minimum(self.winsor, spread_rz))
        amihud_rz_w = np.maximum(-self.winsor, np.minimum(self.winsor, amihud_rz))
        kyle_rz_w = np.maximum(-self.winsor, np.minimum(self.winsor, kyle_rz))
        lsi = (spread_rz_w + amihud_rz_w + kyle_rz_w) / 3.0

        # Spread trend
        s_fast = ema(spread_comp, 5)
        s_slow = ema(spread_comp, 20)
        spread_wide = s_fast > s_slow

        # Store indicators as self.I() wrappers
        self.spread_roll = self.I(lambda: spread_roll)
        self.spread_cs = self.I(lambda: spread_cs)
        self.spread_ar = self.I(lambda: spread_ar)
        self.spread_comp = self.I(lambda: spread_comp)
        self.park_vol = self.I(lambda: park_vol)
        self.amihud_sma = self.I(lambda: amihud_sma)
        self.kyle_lambda = self.I(lambda: kyle_lambda)
        self.lsi = self.I(lambda: lsi)
        self.spread_rz = self.I(lambda: spread_rz)
        self.kyle_rz = self.I(lambda: kyle_rz)
        self.spread_wide = self.I(lambda: spread_wide)
        self.lsi_threshold = self.lsi_threshold

