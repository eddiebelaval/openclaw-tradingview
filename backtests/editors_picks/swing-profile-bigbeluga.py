import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    swing_len = 50
    ma_type = "None"
    ma_length = 25

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate highest high and lowest low over swing_len
        self.highest_high = self.I(
            lambda: high.rolling(window=self.swing_len).max()
        )
        self.lowest_low = self.I(
            lambda: low.rolling(window=self.swing_len).min()
        )
        
        # Moving average based on type
        if self.ma_type == "SMA":
            self.ma = self.I(pta.sma, close, length=self.ma_length)
        elif self.ma_type == "EMA":
            self.ma = self.I(pta.ema, close, length=self.ma_length)
        elif self.ma_type == "SMMA (RMA)":
            self.ma = self.I(pta.rma, close, length=self.ma_length)
        elif self.ma_type == "WMA":
            self.ma = self.I(pta.wma, close, length=self.ma_length)
        elif self.ma_type == "VWMA":
            self.ma = self.I(pta.vwma, close, volume, length=self.ma_length)
        else:
            self.ma = self.I(lambda: pd.Series(0, index=close.index))
        
        # Track swing state
        self.is_down_move = False
        self.last_swing_high = None
        self.last_swing_low = None
        self.swing_direction_changed = False

    def next(self):
        if len(self.data) < self.swing_len:
            return
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        highest = self.highest_high[-1]
        lowest = self.lowest_low[-1]
        
        # Detect swing highs and lows
        if current_high == highest:
            self.is_down_move = True
            self.last_swing_high = current_high
        
        if current_low == lowest:
            self.is_down_move = False
            self.last_swing_low = current_low
        
        # Simple trading logic based on swing detection and MA
        if len(self) > self.swing_len:
            if self.ma[-1] != 0:
                # Buy signal: price crosses above MA and on upswing
                if not self.is_down_move and self.data.Close[-1] > self.ma[-1]:
                    if len(self) > 1 and self.data.Close[-2] <= self.ma[-2]:
                        if not self.position:
                            self.buy()
                
                # Sell signal: price crosses below MA or on downswing
                if self.is_down_move and self.data.Close[-1] < self.ma[-1]:
                    if len(self) > 1 and self.data.Close[-2] >= self.ma[-2]:
                        if self.position:
                            self.sell()
            else:
                # Simple swing-based trading without MA
                if not self.is_down_move and len(self) > 1:
                    if self.data.High[-1] > self.data.High[-2] and not self.position:
                        self.buy()
                
                if self.is_down_move and len(self) > 1:
                    if self.data.Low[-1] < self.data.Low[-2] and self.position:
                        self.sell()


