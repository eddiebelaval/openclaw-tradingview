import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate basic indicators for trading signals
        self.atr = self.I(pta.atr, high, low, close, length=14)
        self.sma_fast = self.I(pta.sma, close, length=10)
        self.sma_slow = self.I(pta.sma, close, length=20)

    def next(self):
        # Simple trend-following strategy based on moving averages
        # Buy when fast MA crosses above slow MA
        if len(self.data) > 20:
            if crossover(self.sma_fast, self.sma_slow):
                self.buy()
            # Sell when fast MA crosses below slow MA
            elif crossover(self.sma_slow, self.sma_fast):
                if self.position:
                    self.position.close()


