import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    hma_length = 200
    
    def init(self):
        close = pd.Series(self.data.Close)
        self.hma = self.I(pta.hma, close, length=self.hma_length)
    
    def next(self):
        if len(self.data) < self.hma_length:
            return
        
        current_close = self.data.Close[-1]
        current_hma = self.hma[-1]
        
        if current_hma is None or np.isnan(current_hma):
            return
        
        if not self.position:
            if current_close > current_hma:
                self.buy()
        else:
            if current_close < current_hma:
                self.sell()


