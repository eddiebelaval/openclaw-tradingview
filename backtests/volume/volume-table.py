import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vol_slots = 10
    abnormal_mul = 2.0
    sma_length = 20

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        self.avg_vol = self.I(pta.sma, volume, length=self.sma_length)

    def next(self):
        if len(self) < self.sma_length + 1:
            return
        
        current_vol = self.data.Volume[-1]
        current_avg = self.avg_vol[-1]
        
        is_bull = self.data.Close[-1] >= self.data.Open[-1]
        is_abnormal = current_vol >= current_avg * self.abnormal_mul
        
        if is_abnormal and is_bull:
            if not self.position:
                self.buy()
        elif is_abnormal and not is_bull:
            if self.position:
                self.sell()


