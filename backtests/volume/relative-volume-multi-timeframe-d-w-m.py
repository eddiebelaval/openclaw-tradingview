import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 30
    
    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        
        # Calculate SMA of volume for the lookback period
        self.avg_vol = self.I(pta.sma, volume, length=self.len)
        
        # Calculate RVOL (Relative Volume)
        def calc_rvol():
            rvol = np.where(
                self.avg_vol > 0,
                volume / self.avg_vol,
                np.nan
            )
            return pd.Series(rvol, index=volume.index)
        
        self.rvol = self.I(calc_rvol)
        
        # Determine candle direction for color logic
        def is_up():
            return close > open_
        
        def is_down():
            return close < open_
        
        self.is_up = self.I(is_up)
        self.is_down = self.I(is_down)
    
    def next(self):
        # Trading logic based on RVOL levels
        current_rvol = self.rvol[-1]
        
        # Skip if RVOL is NaN
        if np.isnan(current_rvol):
            return
        
        # Buy signal: RVOL crosses above 1.5 threshold with upward candle
        if current_rvol > 1.5 and self.is_up[-1]:
            if not self.position:
                self.buy()
        
        # Sell signal: RVOL falls below 1.0 or candle is downward
        elif current_rvol < 1.0 or self.is_down[-1]:
            if self.position:
                self.position.close()
        
        # Alternative: Close on extremely high RVOL (climax) as reversal
        elif current_rvol > 5.0 and self.position:
            self.position.close()


