import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrPeriod = 10
    factor = 3.0
    volFilter = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)
        
        # Calculate HL2 (average of high and low)
        hl2 = self.I(lambda: (high + low) / 2)
        
        # Calculate basic bands for supertrend
        basic_ub = self.I(lambda: hl2 + self.factor * atr)
        basic_lb = self.I(lambda: hl2 - self.factor * atr)
        
        # Calculate final supertrend bands
        self.final_ub = self.I(lambda: self._final_ub(basic_ub, close))
        self.final_lb = self.I(lambda: self._final_lb(basic_lb, close))
        
        # Determine supertrend direction
        self.supertrend = self.I(lambda: self._supertrend_value(close))
        self.direction = self.I(lambda: self._supertrend_direction(close))
        
        # Volume filter
        volAvg = self.I(pta.sma, volume, length=20)
        self.isVolHigh = self.I(lambda: volume > volAvg)
        
        # Previous direction for change detection
        self.prev_direction = None

    def _final_ub(self, basic_ub, close):
        final_ub = pd.Series(index=close.index, dtype='float64')
        for i in range(len(close)):
            if i == 0:
                final_ub.iloc[i] = basic_ub.iloc[i]
            else:
                final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
        return final_ub

    def _final_lb(self, basic_lb, close):
        final_lb = pd.Series(index=close.index, dtype='float64')
        for i in range(len(close)):
            if i == 0:
                final_lb.iloc[i] = basic_lb.iloc[i]
            else:
                final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
        return final_lb

    def _supertrend_value(self, close):
        st = pd.Series(index=close.index, dtype='float64')
        for i in range(len(close)):
            if i == 0:
                st.iloc[i] = self.final_lb.iloc[i]
            else:
                direction = 1 if close.iloc[i-1] <= self.final_ub.iloc[i-1] else -1
                st.iloc[i] = self.final_ub.iloc[i] if direction == 1 else self.final_lb.iloc[i]
        return st

    def _supertrend_direction(self, close):
        direction = pd.Series(index=close.index, dtype='float64')
        for i in range(len(close)):
            if i == 0:
                direction.iloc[i] = 1
            else:
                if close.iloc[i] <= self.final_ub.iloc[i]:
                    direction.iloc[i] = 1
                else:
                    direction.iloc[i] = -1
        return direction

    def next(self):
        if len(self.data) < 2:
            return
        
        current_direction = self.direction[-1]
        prev_direction = self.direction[-2] if len(self.direction) > 1 else current_direction
        
        direction_change_down = prev_direction > current_direction
        direction_change_up = prev_direction < current_direction
        
        vol_condition = self.isVolHigh[-1] if self.volFilter else True
        
        buySignal = direction_change_down and vol_condition
        sellSignal = direction_change_up and vol_condition
        
        if buySignal:
            if not self.position:
                self.buy()
        elif sellSignal:
            if self.position:
                self.position.close()