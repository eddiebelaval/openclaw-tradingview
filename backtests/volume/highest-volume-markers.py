class TvStrategy(Strategy):
    def init(self):
        # Pre-calculate highest volume in 252 bars using rolling max
        volume_series = pd.Series(self.data.Volume)
        self.hv252 = self.I(lambda: volume_series.rolling(window=252).max())
        
    def next(self):
        # Track highest volume ever (HVE)
        if len(self.data) == 1:
            self.hve = self.data.Volume[-1]
            self.hvipo = self.data.Volume[-1]
            self.hvle = self.data.Volume[-1]
        else:
            self.hve = max(self.data.Volume[-1], self.hve)
            self.hvipo = max(self.data.Volume[-1], self.hvipo)
            self.hvle = max(self.data.Volume[-1], self.hvle)
        
        # Calculate conditions
        is_hve = (self.data.Volume[-1] >= self.hve) and (len(self.data) > 1)
        is_hv1 = self.data.Volume[-1] >= self.hv252[-1] if self.hv252[-1] is not None else False
        is_hvipo = (len(self.data) > 1) and (self.data.Volume[-1] >= self.hvipo)
        is_hvle = (self.data.Volume[-1] >= self.hvle) and (self.hvle > 0)
        
        # Volume spike detected - buy on highest volume marker
        if is_hve or is_hv1 or is_hvipo or is_hvle:
            if not self.position:
                self.buy()
        
        # Exit on next bar if no continued volume strength
        if self.position and len(self.data) > 1:
            # Simple exit: if current volume drops below recent average
            recent_vol = pd.Series(self.data.Volume[-20:]).mean() if len(self.data) >= 20 else self.data.Volume[-1]
            if self.data.Volume[-1] < recent_vol * 0.5:
                self.position.close()