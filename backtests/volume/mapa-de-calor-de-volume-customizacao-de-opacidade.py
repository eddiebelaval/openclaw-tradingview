import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters from the Pine Script
    periodo_vol = 20
    opac_padrao = 25
    opac_lv3 = 50
    opac_lv4 = 100

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        
        # Calculate volume moving average
        vol_media = self.I(pta.sma, volume, length=self.periodo_vol)
        
        # Calculate relative volume
        def calc_relative_volume(v, vm):
            with np.errstate(divide='ignore', invalid='ignore'):
                result = np.divide(v, vm)
                result[~np.isfinite(result)] = 1.0
            return pd.Series(result, index=v.index)
        
        self.vol_relativo = self.I(calc_relative_volume, volume, vol_media)
        
        # Determine if candle is up or down
        self.eh_alta = self.I(lambda: (close >= open_).astype(float))
    
    def next(self):
        # Trading logic based on volume heatmap
        # Buy on high volume with up candles
        # Sell on high volume with down candles
        
        if len(self.data) < self.periodo_vol:
            return
        
        vol_rel_current = self.vol_relativo[-1]
        is_up = self.eh_alta[-1] > 0.5
        
        # Entry signals based on volume levels
        if vol_rel_current >= 3.0:
            if is_up:
                if not self.position:
                    self.buy()
            else:
                if self.position:
                    self.sell()
        elif vol_rel_current >= 2.0:
            if is_up:
                if not self.position:
                    self.buy()
            else:
                if self.position:
                    self.sell()
        else:
            # Low volume - maintain position or exit on down candle
            if not is_up and self.position:
                self.sell()
            elif is_up and not self.position:
                self.buy()


