import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    i_length = 20
    i_min_act = 500000
    i_min_prom = 2000000

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Calculate dollar volume
        vol_usd_actual = close * volume
        
        # Calculate SMA of dollar volume
        self.vol_usd_actual = self.I(lambda: vol_usd_actual)
        self.vol_usd_prom = self.I(pta.sma, vol_usd_actual, length=self.i_length)

    def next(self):
        # Get current values
        current_vol_usd = self.vol_usd_actual[-1]
        current_vol_prom = self.vol_usd_prom[-1]
        
        # Check if we have valid data
        if current_vol_prom is None or np.isnan(current_vol_prom):
            return
        
        # Buy signal: both current and average volume exceed thresholds
        if current_vol_usd >= self.i_min_act and current_vol_prom >= self.i_min_prom:
            if not self.position:
                self.buy()
        
        # Sell signal: either current or average volume falls below threshold
        elif current_vol_usd < self.i_min_act or current_vol_prom < self.i_min_prom:
            if self.position:
                self.sell()


