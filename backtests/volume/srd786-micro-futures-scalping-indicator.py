import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend Settings
    trendLength = 9
    trendSlowLength = 21
    
    # RSI Settings
    rsiLength = 7
    rsiOverbought = 70
    rsiOversold = 30
    
    # Volume Settings
    useVolume = True
    volumeSmaLength = 20
    
    # Scalping Settings
    scalpRange = 5
    tickSize = 0.25
    
    # Signal Consolidation Settings
    consolidationBars = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMAs for Trend
        self.fastEMA = self.I(pta.ema, close, length=self.trendLength)
        self.slowEMA = self.I(pta.ema, close, length=self.trendSlowLength)
        
        # RSI Calculation
        self.rsiValue = self.I(pta.rsi, close, length=self.rsiLength)
        
        # Volume Filter
        self.volumeSma = self.I(pta.sma, volume, length=self.volumeSmaLength)
        
        # ATR for support/resistance
        self.atrValue = self.I(pta.atr, high, low, close, length=14)
        
        # State tracking
        self.bars_since_long_signal = 0
        self.bars_since_short_signal = 0
        self.in_long_position = False
        self.in_short_position = False
        self.entry_long_price = None
        self.entry_short_price = None

    def next(self):
        # Check if we have enough data
        if len(self.data) < max(self.trendSlowLength, self.rsiLength, self.volumeSmaLength):
            return
        
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        # Get indicator values
        fast_ema = self.fastEMA[-1]
        slow_ema = self.slowEMA[-1]
        rsi_value = self.rsiValue[-1]
        volume_sma = self.volumeSma[-1]
        atr_value = self.atrValue[-1] if self.atrValue[-1] is not None else 0
        
        # Trend Direction
        is_uptrend = fast_ema > slow_ema
        is_downtrend = fast_ema < slow_ema
        
        # Volume Filter
        volume_filter = not self.useVolume or volume > volume_sma
        
        # RSI Crossovers
        rsi_oversold_cross = False
        rsi_overbought_cross = False
        
        if len(self.rsiValue) >= 2:
            if self.rsiValue[-2] <= self.rsiOversold and self.rsiValue[-1] > self.rsiOversold:
                rsi_oversold_cross = True
            if self.rsiValue[-2] >= self.rsiOverbought and self.rsiValue[-1] < self.rsiOverbought:
                rsi_overbought_cross = True
        
        # EMA Crossovers
        fast_crossunder_slow = False
        fast_crossover_slow = False
        
        if len(self.fastEMA) >= 2 and len(self.slowEMA) >= 2:
            if self.fastEMA[-2] >= self.slowEMA[-2] and self.fastEMA[-1] < self.slowEMA[-1]:
                fast_crossunder_slow = True
            if self.fastEMA[-2] <= self.slowEMA[-2] and self.fastEMA[-1] > self.slowEMA[-1]:
                fast_crossover_slow = True
        
        # Long Signal Conditions
        long_condition = (
            is_uptrend and
            rsi_oversold_cross and
            volume_filter and
            (close - open_price) >= (self.tickSize * self.scalpRange)
        )
        
        # Short Signal Conditions
        short_condition = (
            is_downtrend and
            rsi_overbought_cross and
            volume_filter and
            (open_price - close) >= (self.tickSize * self.scalpRange)
        )
        
        # Exit Signals
        long_exit = fast_crossunder_slow
        short_exit = fast_crossover_slow
        
        # Update bars since signal counters
        if long_condition:
            self.bars_since_long_signal = 0
        else:
            self.bars_since_long_signal += 1
        
        if short_condition:
            self.bars_since_short_signal = 0
        else:
            self.bars_since_short_signal += 1
        
        # Signal Consolidation Filter
        signal_consolidated = (
            self.bars_since_long_signal >= self.consolidationBars and
            self.bars_since_short_signal >= self.consolidationBars
        )
        
        # Apply signal consolidation
        consolidated_long_condition = long_condition and signal_consolidated
        consolidated_short_condition = short_condition and signal_consolidated
        
        # Handle Long Entry
        if consolidated_long_condition and not self.in_long_position:
            if self.in_short_position:
                self.position.close()
            self.buy()
            self.in_long_position = True
            self.in_short_position = False
            self.entry_long_price = close
            self.entry_short_price = None
        
        # Handle Short Entry
        if consolidated_short_condition and not self.in_short_position:
            if self.in_long_position:
                self.position.close()
            self.sell()
            self.in_short_position = True
            self.in_long_position = False
            self.entry_short_price = close
            self.entry_long_price = None
        
        # Handle Long Exit
        if long_exit and self.in_long_position:
            self.position.close()
            self.in_long_position = False
            self.entry_long_price = None
        
        # Handle Short Exit
        if short_exit and self.in_short_position:
            self.position.close()
            self.in_short_position = False
            self.entry_short_price = None


