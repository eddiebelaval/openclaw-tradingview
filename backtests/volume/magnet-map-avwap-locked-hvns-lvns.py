import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script inputs
    lookback = 300
    bins = 30
    hvn_count = 4
    lvn_count = 3
    atr_len = 14
    grid_step = 1.0
    grid_multiple = 2
    min_sep_fixed = 1.0
    min_sep_atr = 0.60
    zone_atr_mult = 0.10
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR for spacing and zones
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Calculate daily VWAP
        hlc3 = (high + low + close) / 3
        self.daily_vwap = self.I(self._calc_daily_vwap, hlc3, volume)
        
        # Storage for HVN and LVN levels
        self.hvn_levels = []
        self.lvn_levels = []
        self.last_compute_bar = -1
        
        # Track entry signal
        self.hvn_entry_triggered = False
        self.lvn_exit_triggered = False

    def _calc_daily_vwap(self, hlc3, volume):
        """Calculate daily VWAP"""
        vwap = pd.Series(index=hlc3.index, dtype='float64')
        cum_pv = 0.0
        cum_v = 0.0
        last_date = None
        
        for i in range(len(hlc3)):
            current_date = pd.Timestamp(self.data.index[i]).date()
            
            # Reset on new day
            if last_date is not None and current_date != last_date:
                cum_pv = 0.0
                cum_v = 0.0
            
            cum_pv += hlc3.iloc[i] * volume.iloc[i]
            cum_v += volume.iloc[i]
            
            vwap.iloc[i] = cum_pv / cum_v if cum_v != 0 else np.nan
            last_date = current_date
        
        return vwap

    def _round_to_step(self, x, step):
        """Round value to nearest grid step"""
        if step <= 0:
            return x
        return round(x / step) * step

    def _get_min_sep(self):
        """Calculate minimum separation between levels"""
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 1.0
        return self.grid_step * self.grid_multiple

    def _far_from_array(self, level, arr):
        """Check if level is far enough from array of levels"""
        sep = self._get_min_sep()
        for existing_level in arr:
            if abs(level - existing_level) < sep:
                return False
        return True

    def _compute_nodes(self):
        """Compute HVN and LVN levels based on volume distribution"""
        self.hvn_levels = []
        self.lvn_levels = []
        
        lb_bars = min(self.lookback, len(self.data))
        if lb_bars < 2:
            return
        
        high_data = self.data.High[-lb_bars:]
        low_data = self.data.Low[-lb_bars:]
        volume_data = self.data.Volume[-lb_bars:]
        
        hi = np.max(high_data)
        lo = np.min(low_data)
        rng = hi - lo
        
        if rng <= 0:
            return
        
        bin_size = rng / self.bins
        bin_vol = [0.0] * self.bins
        
        # Calculate volume in each price bin
        for i in range(lb_bars):
            close_val = self.data.Close[-lb_bars + i]
            idx_raw = int(np.floor((close_val - lo) / bin_size))
            idx = max(0, min(self.bins - 1, idx_raw))
            bin_vol[idx] += volume_data[i]
        
        # Find HVNs (highest volume bins)
        tmp_max = bin_vol.copy()
        for _ in range(self.hvn_count):
            best_v = -1.0
            best_i = -1
            for j in range(self.bins):
                if tmp_max[j] > best_v:
                    best_v = tmp_max[j]
                    best_i = j
            
            if best_i == -1 or best_v <= 0:
                break
            
            tmp_max[best_i] = -1.0
            lvl = lo + (best_i + 0.5) * bin_size
            lvl = self._round_to_step(lvl, self.grid_step)
            
            if self._far_from_array(lvl, self.hvn_levels):
                self.hvn_levels.append(lvl)
        
        # Find LVNs (lowest volume bins)
        tmp_min = bin_vol.copy()
        for _ in range(self.lvn_count):
            best_v = 1e100
            best_i = -1
            for j in range(self.bins):
                if tmp_min[j] >= 0 and tmp_min[j] < best_v:
                    best_v = tmp_min[j]
                    best_i = j
            
            if best_i == -1:
                break
            
            tmp_min[best_i] = -1.0
            lvl = lo + (best_i + 0.5) * bin_size
            lvl = self._round_to_step(lvl, self.grid_step)
            
            if self._far_from_array(lvl, self.lvn_levels) and self._far_from_array(lvl, self.hvn_levels):
                self.lvn_levels.append(lvl)

    def next(self):
        """Trading logic"""
        # Recompute nodes periodically
        if len(self.data) % 50 == 0:
            self._compute_nodes()
        
        if not self.hvn_levels or not self.lvn_levels:
            return
        
        close = self.data.Close[-1]
        vwap = self.daily_vwap[-1]
        atr_val = self.atr[-1]
        
        # Sort levels
        hvn_sorted = sorted(self.hvn_levels)
        lvn_sorted = sorted(self.lvn_levels)
        
        # Find nearest HVN support/resistance
        nearest_hvn_below = None
        nearest_hvn_above = None
        for hvn in hvn_sorted:
            if hvn <= close:
                nearest_hvn_below = hvn
            elif nearest_hvn_above is None:
                nearest_hvn_above = hvn
        
        # Entry logic: buy when price approaches HVN from below and crosses above it
        if nearest_hvn_below is not None:
            zone_range = atr_val * self.zone_atr_mult
            if (close >= nearest_hvn_below - zone_range and 
                close <= nearest_hvn_below + zone_range and
                close > vwap):
                if not self.position and not self.hvn_entry_triggered:
                    self.buy()
                    self.hvn_entry_triggered = True
        else:
            self.hvn_entry_triggered = False
        
        # Exit logic: sell when price touches LVN resistance or breaks below support
        if self.position:
            for lvn in lvn_sorted:
                zone_range = atr_val * self.zone_atr_mult
                if close >= lvn - zone_range and close <= lvn + zone_range:
                    self.sell()
                    break
            
            # Also exit if price falls below lowest HVN support
            if hvn_sorted and close < hvn_sorted[0]:
                self.sell()


