import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # FVG Detection Parameters
    atr_period = 14
    fvg_atr_multiplier = 0.3
    min_gap_atr = 150
    
    # RSI Divergence Parameters
    rsi_period = 14
    rsi_threshold = 5.0
    
    # ADX Parameters
    adx_period = 14
    adx_weak_threshold = 20.0
    
    # Volume Parameters
    volume_multiplier = 1.5
    
    # Position Management
    stop_loss_atr = 2.0
    take_profit_atr = 3.0

    def init(self):
        # Calculate indicators
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR for gap detection
        self.atr14 = self.I(pta.atr, high, low, close, length=self.atr_period)
        self.atr50 = self.I(pta.atr, high, low, close, length=50)
        self.atr150 = self.I(lambda: pta.atr(high, low, close, length=150) or pd.Series(0, index=close.index), )
        
        # RSI for divergence detection
        self.rsi = self.I(pta.rsi, close, length=self.rsi_period)
        
        # ADX for momentum confirmation
        adx_result = self.I(pta.adx, high, low, close, length=self.adx_period)
        self.adx = adx_result if adx_result is not None else self.I(lambda: pd.Series(50, index=close.index))
        
        # Volume indicators
        self.avg_volume = self.I(pta.sma, volume, length=50)
        
        # Store gap data
        self.bullish_gaps = []
        self.bearish_gaps = []
        self.position_entry_price = None
        self.position_type = None  # 'long' or 'short'

    def next(self):
        # Skip if insufficient data
        if len(self.data) < 10:
            return
        
        # Get current values
        current_price = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_volume = self.data.Volume[-1]
        current_atr = self.atr14[-1]
        
        # Skip if ATR is invalid
        if pd.isna(current_atr) or current_atr <= 0:
            return
        
        avg_vol = self.avg_volume[-1] if not pd.isna(self.avg_volume[-1]) else current_volume
        atr150_val = self.atr150[-1] * self.fvg_atr_multiplier if not pd.isna(self.atr150[-1]) else 0
        
        # Detect bullish FVG (Fair Value Gap)
        if len(self.data) >= 3:
            gap_low = current_low
            gap_high = self.data.High[-3] if len(self.data) >= 3 else 0
            
            bullish_fvg = (
                gap_low > gap_high and 
                (gap_low - gap_high) > atr150_val
            )
            
            # Detect bearish FVG
            gap_high_bear = current_high
            gap_low_bear = self.data.Low[-3] if len(self.data) >= 3 else float('inf')
            
            bearish_fvg = (
                gap_high_bear < gap_low_bear and 
                (gap_low_bear - gap_high_bear) > atr150_val
            )
            
            # Check for divergence signals
            rsi_val = self.rsi[-1] if not pd.isna(self.rsi[-1]) else 50
            rsi_prev = self.rsi[-11] if len(self.rsi) >= 11 and not pd.isna(self.rsi[-11]) else 50
            
            price_prev = self.data.Close[-11] if len(self.data) >= 11 else current_price
            
            bullish_rsi_div = (
                current_price < price_prev and 
                rsi_val > rsi_prev + self.rsi_threshold
            )
            
            bearish_rsi_div = (
                current_price > price_prev and 
                rsi_val < rsi_prev - self.rsi_threshold
            )
            
            adx_val = self.adx[-1] if not pd.isna(self.adx[-1]) else 25
            weak_momentum = adx_val < self.adx_weak_threshold
            
            # Volume confirmation
            institutional_volume = current_volume >= avg_vol * self.volume_multiplier
            
            # Entry Logic: Bullish setup
            if bullish_fvg and bullish_rsi_div and institutional_volume and not weak_momentum:
                if not self.position:
                    self.buy()
                    self.position_entry_price = current_price
                    self.position_type = 'long'
                    
                    # Set stop loss and take profit
                    stop_loss = current_price - (self.stop_loss_atr * current_atr)
                    take_profit = current_price + (self.take_profit_atr * current_atr)
                    self.stop_loss_price = stop_loss
                    self.take_profit_price = take_profit
            
            # Entry Logic: Bearish setup
            elif bearish_fvg and bearish_rsi_div and institutional_volume and not weak_momentum:
                if not self.position:
                    self.sell()
                    self.position_entry_price = current_price
                    self.position_type = 'short'
                    
                    # Set stop loss and take profit
                    stop_loss = current_price + (self.stop_loss_atr * current_atr)
                    take_profit = current_price - (self.take_profit_atr * current_atr)
                    self.stop_loss_price = stop_loss
                    self.take_profit_price = take_profit
        
        # Exit Logic: Stop loss and take profit management
        if self.position:
            if self.position_type == 'long':
                if current_price <= self.stop_loss_price or current_price >= self.take_profit_price:
                    self.position.close()
            elif self.position_type == 'short':
                if current_price >= self.stop_loss_price or current_price <= self.take_profit_price:
                    self.position.close()


