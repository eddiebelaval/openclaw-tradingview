import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate volume-based indicators
        self.sma_volume = self.I(lambda: pta.sma(volume, length=50))
        
        # Volume ratio calculation
        self.vol_ratio = self.I(lambda: volume / (pta.sma(volume, length=50) + 1e-10))
        
        # Percentile calculations for different windows
        self.short_percentile = self.I(lambda: volume.rolling(20).apply(lambda x: np.percentile(x, 75), raw=True))
        self.medium_percentile = self.I(lambda: volume.rolling(50).apply(lambda x: np.percentile(x, 90), raw=True))
        self.long_percentile = self.I(lambda: volume.rolling(100).apply(lambda x: np.percentile(x, 97), raw=True))
        
        # Detection flags
        self.volume_elevated_short = self.I(lambda: volume >= self.short_percentile)
        self.volume_elevated_medium = self.I(lambda: volume >= self.medium_percentile)
        self.volume_elevated_long = self.I(lambda: volume >= self.long_percentile)
        
        # Candle direction
        self.is_bullish = self.I(lambda: close >= self.data.Open)
        self.is_bearish = self.I(lambda: close < self.data.Open)
        
        # Track previous states
        self.prev_vol_ratio = 0

    def next(self):
        if len(self.data) < 100:
            return
        
        current_vol_ratio = self.vol_ratio[-1]
        current_is_bullish = self.is_bullish[-1]
        current_is_bearish = self.is_bearish[-1]
        
        # Check for elevated volume consensus (majority of 2 out of 3 windows)
        elevated_count = (
            (1 if self.volume_elevated_short[-1] else 0) +
            (1 if self.volume_elevated_medium[-1] else 0) +
            (1 if self.volume_elevated_long[-1] else 0)
        )
        
        is_elevated_volume = elevated_count >= 2
        
        # Buy signal: Elevated volume with bullish candle and volume ratio increases
        if (is_elevated_volume and 
            current_is_bullish and 
            current_vol_ratio > self.prev_vol_ratio and
            not self.position):
            self.buy()
        
        # Sell signal: Elevated volume with bearish candle
        elif (is_elevated_volume and 
              current_is_bearish and 
              self.position):
            self.sell()
        
        # Exit long if volume ratio drops significantly
        elif (self.position and 
              current_vol_ratio < 1.0):
            self.sell()
        
        self.prev_vol_ratio = current_vol_ratio


