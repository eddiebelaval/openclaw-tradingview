import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    volAvgLen = 20
    rsiLen = 14
    rsiOB = 70
    rsiGold = 55
    rsiOS = 30

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate volume EMA and ratio
        self.volAvg = self.I(pta.ema, volume, length=self.volAvgLen)
        self.volRatio = self.I(lambda: volume / self.volAvg.replace(0, np.nan))

        # Calculate RSI
        self.rsiVal = self.I(pta.rsi, close, length=self.rsiLen)

        # Calculate candle properties for trap detection
        self.bodySize = self.I(lambda: np.abs(close - open_))
        self.upperWick = self.I(lambda: high - np.maximum(open_, close))
        self.lowerWick = self.I(lambda: np.minimum(open_, close) - low)
        self.isUp = self.I(lambda: close > open_)

        # Trap detection
        self.longTrap = self.I(
            lambda: (self.upperWick[-1] > self.bodySize[-1] * 2.5) and
                    (self.upperWick[-1] > self.lowerWick[-1] * 2) and
                    (self.volRatio[-1] > 1.2)
            if len(self.data) > 0 and self.volRatio[-1] is not None else False
        )
        self.shortTrap = self.I(
            lambda: (self.lowerWick[-1] > self.bodySize[-1] * 2.5) and
                    (self.lowerWick[-1] > self.upperWick[-1] * 2) and
                    (self.volRatio[-1] > 1.2)
            if len(self.data) > 0 and self.volRatio[-1] is not None else False
        )

    def next(self):
        # Avoid trading if insufficient data
        if len(self.data) < max(self.volAvgLen, self.rsiLen):
            return

        # Check if current values are available
        if (self.volRatio[-1] is None or 
            self.rsiVal[-1] is None or 
            self.bodySize[-1] is None or
            self.upperWick[-1] is None or
            self.lowerWick[-1] is None):
            return

        # Long trap detected: sharp reversal expected downward
        longTrap = (self.upperWick[-1] > self.bodySize[-1] * 2.5 and
                    self.upperWick[-1] > self.lowerWick[-1] * 2 and
                    self.volRatio[-1] > 1.2)

        # Short trap detected: sharp reversal expected upward
        shortTrap = (self.lowerWick[-1] > self.bodySize[-1] * 2.5 and
                     self.lowerWick[-1] > self.upperWick[-1] * 2 and
                     self.volRatio[-1] > 1.2)

        # RSI-based signals
        rsi = self.rsiVal[-1]

        # Entry logic: Trade traps when RSI confirms
        if longTrap and rsi > self.rsiOB:
            # Long trap with overbought RSI = sell signal
            if not self.position:
                self.sell()
        elif shortTrap and rsi < self.rsiOS:
            # Short trap with oversold RSI = buy signal
            if not self.position:
                self.buy()

        # Additional entry from RSI extremes with volume confirmation
        if rsi < self.rsiOS and self.volRatio[-1] > 1.2 and self.isUp[-1]:
            # Oversold with high volume and up candle = buy
            if not self.position:
                self.buy()
        elif rsi > self.rsiOB and self.volRatio[-1] > 1.2 and not self.isUp[-1]:
            # Overbought with high volume and down candle = sell
            if not self.position:
                self.sell()

        # Exit logic: RSI mean reversion
        if self.position:
            # Exit long when RSI becomes overbought
            if self.position.is_long and rsi > self.rsiOB:
                self.position.close()
            # Exit short when RSI becomes oversold
            elif self.position.is_short and rsi < self.rsiOS:
                self.position.close()


