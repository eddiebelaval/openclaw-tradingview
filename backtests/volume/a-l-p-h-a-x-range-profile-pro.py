import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Range Profile parameters
    fixed_bars = 150
    rows = 24
    va_percent = 70.0
    display_mode = "Up/Down Split"

    def init(self):
        pass

    def next(self):
        # Only process on the last bar (when range is complete)
        if len(self.data) < self.fixed_bars:
            return

        # Get the lookback period
        lookback = min(self.fixed_bars, len(self.data) - 1)
        
        # Extract OHLCV data for the range
        closes = self.data.Close[-lookback:]
        opens = self.data.Open[-lookback:]
        highs = self.data.High[-lookback:]
        lows = self.data.Low[-lookback:]
        volumes = self.data.Volume[-lookback:]

        # Calculate range
        range_high = np.max(highs)
        range_low = np.min(lows)
        price_range = range_high - range_low

        if price_range <= 0:
            return

        # Build bins
        step = price_range / self.rows
        levels = [range_low + step * i for i in range(self.rows + 1)]

        # Initialize volume arrays
        up_vol = [0.0] * self.rows
        dn_vol = [0.0] * self.rows

        # Process each bar in the range
        for b in range(len(closes)):
            o = opens.iloc[b]
            c = closes.iloc[b]
            h = highs.iloc[b]
            l = lows.iloc[b]
            v = volumes.iloc[b] if not np.isnan(volumes.iloc[b]) else 0.0

            body_top = max(c, o)
            body_bot = min(c, o)
            is_green = c >= o
            top_wick = max(h - body_top, 0.0)
            bottom_wick = max(body_bot - l, 0.0)
            body_h = max(body_top - body_bot, 0.0)
            denom = 2.0 * top_wick + 2.0 * bottom_wick + body_h

            body_vol = (body_h * v / denom) if denom > 0 else v
            top_wick_vol = (2.0 * top_wick * v / denom) if denom > 0 else 0.0
            bot_wick_vol = (2.0 * bottom_wick * v / denom) if denom > 0 else 0.0

            for x in range(self.rows):
                bin_lo = levels[x]
                bin_hi = levels[x + 1]

                # Calculate up volume contribution
                up_add = 0.0
                if is_green:
                    up_add += self._get_vol(bin_lo, bin_hi, body_bot, body_top, body_h, body_vol)
                up_add += self._get_vol(bin_lo, bin_hi, body_top, h, top_wick, top_wick_vol) / 2.0
                up_add += self._get_vol(bin_lo, bin_hi, body_bot, l, bottom_wick, bot_wick_vol) / 2.0

                # Calculate down volume contribution
                dn_add = 0.0
                if not is_green:
                    dn_add += self._get_vol(bin_lo, bin_hi, body_bot, body_top, body_h, body_vol)
                dn_add += self._get_vol(bin_lo, bin_hi, body_top, h, top_wick, top_wick_vol) / 2.0
                dn_add += self._get_vol(bin_lo, bin_hi, body_bot, l, bottom_wick, bot_wick_vol) / 2.0

                up_vol[x] += up_add
                dn_vol[x] += dn_add

        # Calculate totals and POC
        total_vol = [up_vol[i] + dn_vol[i] for i in range(self.rows)]
        sum_vol = sum(total_vol)
        
        if sum_vol == 0:
            return

        max_row_vol = max(total_vol) if total_vol else 0.0
        poc_idx = total_vol.index(max_row_vol) if max_row_vol > 0 else 0
        poc_price = (levels[poc_idx] + levels[poc_idx + 1]) / 2.0

        # Calculate Value Area
        target = sum_vol * (self.va_percent / 100.0)
        va_total = total_vol[poc_idx]
        up_idx = poc_idx
        down_idx = poc_idx

        for _ in range(self.rows):
            if va_total >= target:
                break
            upper = total_vol[up_idx + 1] if up_idx < self.rows - 1 else 0.0
            lower = total_vol[down_idx - 1] if down_idx > 0 else 0.0
            if upper == 0 and lower == 0:
                break
            if upper >= lower:
                va_total += upper
                up_idx += 1
            else:
                va_total += lower
                down_idx -= 1

        vah = levels[up_idx + 1]
        val = levels[down_idx]

        # Trading logic based on POC and Value Area
        current_price = self.data.Close[-1]

        # Buy signal: price crosses above VAL (support)
        if len(self.data) > 1:
            prev_price = self.data.Close[-2]
            
            if prev_price <= val and current_price > val:
                if not self.position:
                    self.buy()
            
            # Sell signal: price crosses below VAH (resistance)
            elif prev_price >= vah and current_price < vah:
                if self.position:
                    self.position.close()

    def _get_vol(self, bin_lo, bin_hi, seg_a, seg_b, seg_h, seg_vol):
        """Calculate volume contribution for a bin segment"""
        if seg_h <= 0.0:
            return 0.0
        overlap = max(min(max(bin_lo, bin_hi), max(seg_a, seg_b)) - max(min(bin_lo, bin_hi), min(seg_a, seg_b)), 0.0)
        return overlap * seg_vol / seg_h if seg_h > 0 else 0.0


