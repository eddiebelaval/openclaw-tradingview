import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    volLength = 20
    percentageThreshold = 200.0

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Calculate average volume (using previous volume bar)
        volume_prev = volume.shift(1)
        avgVol = self.I(pta.sma, volume_prev, length=self.volLength)
        
        # Calculate volume increase percentage
        def calc_vol_increase():
            avg = avgVol
            vol_increase = ((volume - avg) / avg) * 100
            return vol_increase.fillna(0)
        
        self.volIncrease = self.I(calc_vol_increase)

    def next(self):
        if len(self.data) < self.volLength + 1:
            return
        
        current_vol_increase = self.volIncrease[-1]
        
        if current_vol_increase >= self.percentageThreshold:
            if not self.position:
                self.buy()
        else:
            if self.position:
                self.sell()