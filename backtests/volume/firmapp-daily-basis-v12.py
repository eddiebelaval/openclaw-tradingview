class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        # This is a dashboard/indicator script with no trading rules
        # Detecting fractals for basic trading logic
        
        if len(self.data) < 3:
            return
        
        # Upward fractal (low[1] < low[2] and low[1] < low)
        if (self.data.Low[-2] < self.data.Low[-3] and 
            self.data.Low[-2] < self.data.Low[-1]):
            if not self.position:
                self.buy()
        
        # Downward fractal (high[1] > high[2] and high[1] > high)
        elif (self.data.High[-2] > self.data.High[-3] and 
              self.data.High[-2] > self.data.High[-1]):
            if self.position:
                self.sell()


