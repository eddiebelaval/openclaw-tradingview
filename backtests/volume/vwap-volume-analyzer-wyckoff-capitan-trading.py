import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    recent_len = 9
    band_mult = 0.05
    atr_len = 14

    def init(self):
        # Initialize data series
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate ATR for distance calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Calculate VWAP manually using cumulative sums
        def calc_vwap():
            typ_price = (high + low + close) / 3
            vwap_sum = (typ_price * volume).cumsum()
            vwap_vol = volume.cumsum()
            vwap = vwap_sum / vwap_vol.replace(0, np.nan)
            return vwap
        
        self.vwap = self.I(calc_vwap)
        
        # Calculate VWAP standard deviation for bands
        def calc_vwap_stdev():
            typ_price = (high + low + close) / 3
            vwap_sum = (typ_price * volume).cumsum()
            vwap_vol = volume.cumsum()
            vwap = vwap_sum / vwap_vol.replace(0, np.nan)
            
            vwap_sq_sum = (typ_price ** 2 * volume).cumsum()
            expected_sq = vwap_sq_sum / vwap_vol.replace(0, np.nan)
            vwap_variance = np.maximum(0.0, expected_sq - vwap ** 2)
            vwap_stdev = np.sqrt(vwap_variance)
            return vwap_stdev
        
        self.vwap_stdev = self.I(calc_vwap_stdev)
        
        # Calculate buy/sell volume proxy
        def calc_net_volume():
            prev_close = close.shift(1).fillna(close.iloc[0])
            net_vols = []
            
            for i in range(len(close)):
                h = high.iloc[i]
                l = low.iloc[i]
                c = close.iloc[i]
                pc = prev_close.iloc[i]
                v = volume.iloc[i]
                
                true_high = max(h, pc)
                true_low = min(l, pc)
                d = max(true_high - true_low, 1e-6)
                buy_vol = v * (c - true_low) / d
                buy_vol = max(0.0, min(buy_vol, v))
                sell_vol = v - buy_vol
                net_vol = buy_vol - sell_vol
                net_vols.append(net_vol)
            
            return pd.Series(net_vols, index=close.index)
        
        self.net_volume = self.I(calc_net_volume)
        
        # Recent net volume (lookback)
        def calc_recent_net():
            return self.net_volume.rolling(self.recent_len).sum()
        
        self.recent_net = self.I(calc_recent_net)
        
        # Recent total volume
        def calc_recent_total():
            return volume.rolling(self.recent_len).sum()
        
        self.recent_total = self.I(calc_recent_total)
        
        # Calculate bias score
        def calc_bias_score():
            cumulative_net = self.net_volume.cumsum()
            cumulative_total = volume.cumsum()
            
            past_bias = np.where(cumulative_total > 0, 
                                (cumulative_net / cumulative_total * 100.0), 
                                0.0)
            
            recent_bias = np.where(self.recent_total > 0,
                                  (self.recent_net / self.recent_total * 100.0),
                                  0.0)
            
            score = (past_bias * 0.2) + (recent_bias * 0.8)
            return pd.Series(score, index=close.index)
        
        self.bias_score = self.I(calc_bias_score)
        
        # Calculate VWAP distance percentage
        def calc_vwap_dist():
            with np.errstate(divide='ignore', invalid='ignore'):
                dist = np.where(self.vwap != 0, 
                               (close - self.vwap) / self.vwap * 100.0,
                               0.0)
            return pd.Series(dist, index=close.index)
        
        self.vwap_dist_pct = self.I(calc_vwap_dist)
        
        # Calculate final confidence score with VWAP gravity
        def calc_confidence():
            atr_dist = np.where(self.atr > 0,
                               (close - self.vwap) / self.atr,
                               0.0)
            vwap_gravity = np.clip(atr_dist * 8.0, -40.0, 40.0)
            score = self.bias_score + vwap_gravity
            confidence = np.clip(np.abs(score), 0.0, 100.0)
            return pd.Series(confidence, index=close.index)
        
        self.confidence = self.I(calc_confidence)

    def next(self):
        # Skip if not enough data
        if len(self) < self.recent_len + self.atr_len:
            return
        
        # Get current values
        current_vwap = self.vwap[-1] if not np.isnan(self.vwap[-1]) else None
        current_bias = self.bias_score[-1]
        current_confidence = self.confidence[-1]
        current_price = self.data.Close[-1]
        
        if current_vwap is None:
            return
        
        # Buy signal: Strong bullish bias with price above VWAP
        if current_bias > 10 and current_confidence > 30 and current_price > current_vwap:
            if not self.position:
                self.buy()
        
        # Sell signal: Strong bearish bias with price below VWAP
        elif current_bias < -10 and current_confidence > 30 and current_price < current_vwap:
            if self.position:
                self.position.close()
        
        # Exit on crossing below VWAP from above
        if self.position and current_price < current_vwap and self.data.Close[-2] > self.vwap[-2]:
            self.position.close()


