import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    periodo = 20
    fator = 1.25

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Calculate volume EMA
        self.vol_ema = self.I(pta.ema, volume, length=self.periodo)
        
        # Calculate threshold
        self.threshold = self.I(lambda: self.vol_ema * self.fator)
        
        # Track previous values for crossover detection
        self.prev_volume = None
        self.prev_threshold = None

    def next(self):
        if len(self) < self.periodo + 1:
            return
        
        current_volume = self.data.Volume[-1]
        current_vol_ema = self.vol_ema[-1]
        current_threshold = self.threshold[-1]
        
        if current_vol_ema is None or current_threshold is None:
            return
        
        if self.prev_volume is None:
            self.prev_volume = current_volume
            self.prev_threshold = current_threshold
            return
        
        # Buy when volume crosses above threshold (high volume spike up)
        if self.prev_volume <= self.prev_threshold and current_volume > current_threshold:
            if not self.position:
                self.buy()
        
        # Sell when volume crosses below threshold (volume dries up)
        elif self.prev_volume > self.prev_threshold and current_volume <= current_threshold:
            if self.position:
                self.sell()
        
        self.prev_volume = current_volume
        self.prev_threshold = current_threshold


