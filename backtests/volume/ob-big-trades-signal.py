import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Order Blocks parameters
    lookback = 3
    threshold = 0.5 / 100
    max_blocks = 10
    proximity = 0.15 / 100
    
    # Volume parameters
    vol_calc_method = "Relative"
    vol_lookback = 20
    vol_threshold = 1.2
    
    # Big Trades parameters
    bt_lookback = 5
    bt_mult = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate daily VWAP
        self.daily_vwap = self.I(self._calc_daily_vwap, high, low, close, volume)
        
        # Big Trades calculations
        self.raw_buy = self.I(self._calc_raw_buy, high, low, close, volume)
        self.raw_sell = self.I(self._calc_raw_sell, high, low, close, volume)
        
        self.avg_buy = self.I(lambda: pta.sma(self.raw_buy, length=self.bt_lookback) or pd.Series(0, index=close.index))
        self.std_buy = self.I(lambda: pta.stdev(self.raw_buy, length=self.bt_lookback) or pd.Series(0, index=close.index))
        self.avg_sell = self.I(lambda: pta.sma(self.raw_sell, length=self.bt_lookback) or pd.Series(0, index=close.index))
        self.std_sell = self.I(lambda: pta.stdev(self.raw_sell, length=self.bt_lookback) or pd.Series(0, index=close.index))
        
        # Volume strength
        self.vol_strength = self.I(self._calc_vol_strength, volume)
        
        # Consolidation and breakout
        self.is_consol = self.I(self._calc_consolidation, high, low)
        self.bull_break = self.I(self._calc_bull_breakout, high, low, close)
        self.bear_break = self.I(self._calc_bear_breakout, high, low, close)
        
        # Order block tracking
        self.bull_blocks = []
        self.bear_blocks = []
        self.block_counter = 0

    def _calc_daily_vwap(self, high, low, close, volume):
        df = pd.DataFrame({
            'high': high,
            'low': low,
            'close': close,
            'volume': volume
        })
        df['tp'] = (df['high'] + df['low'] + df['close']) / 3
        df['day'] = pd.to_datetime(df.index).date if isinstance(df.index, pd.DatetimeIndex) else df.index
        
        df['cum_pv'] = df.groupby('day').apply(lambda x: (x['tp'] * x['volume']).cumsum()).values
        df['cum_vol'] = df.groupby('day').apply(lambda x: x['volume'].cumsum()).values
        
        vwap = df['cum_pv'] / df['cum_vol']
        return vwap

    def _calc_raw_buy(self, high, low, close, volume):
        rng = high - low
        rng = rng.replace(0, np.nan)
        raw_buy = ((close - low) / rng) * volume
        return raw_buy.fillna(0)

    def _calc_raw_sell(self, high, low, close, volume):
        rng = high - low
        rng = rng.replace(0, np.nan)
        raw_sell = ((high - close) / rng) * volume
        return raw_sell.fillna(0)

    def _calc_vol_strength(self, volume):
        if self.vol_calc_method == "Simple":
            vol = (volume + volume.shift(1)) / 2
        elif self.vol_calc_method == "Relative":
            avg_v = pta.sma(volume, length=self.vol_lookback)
            vol = volume / avg_v
        else:
            vol = (volume * 2.0 + volume.shift(1) * 1.0) / 3.0
        return vol.fillna(1.0)

    def _calc_consolidation(self, high, low):
        hr = high.rolling(self.lookback).max() - high.rolling(self.lookback).min()
        lr = low.rolling(self.lookback).max() - low.rolling(self.lookback).min()
        avg_r = (hr + lr) / 2
        cur_r = high.shift(1) - low.shift(1)
        is_consol = cur_r <= avg_r * (1 + self.threshold)
        return is_consol.fillna(False)

    def _calc_bull_breakout(self, high, low, close):
        bull_bo = (close > high.shift(2)) & (close > pd.Series(self.data.Open))
        return bull_bo.fillna(False)

    def _calc_bear_breakout(self, high, low, close):
        bear_bo = (close < low.shift(2)) & (close < pd.Series(self.data.Open))
        return bear_bo.fillna(False)

    def _is_near_bull_ob(self):
        close = self.data.Close[-1]
        for block in self.bull_blocks:
            s_top = block['top']
            s_bot = block['bottom']
            s_prx = s_top * self.proximity
            if close >= s_bot - s_prx and close <= s_top + s_prx:
                return True
        return False

    def _is_near_bear_ob(self):
        close = self.data.Close[-1]
        for block in self.bear_blocks:
            s_top = block['top']
            s_bot = block['bottom']
            s_prx = s_top * self.proximity
            if close >= s_bot - s_prx and close <= s_top + s_prx:
                return True
        return False

    def _cleanup_bull_blocks(self):
        self.bull_blocks = [b for b in self.bull_blocks if self.data.Low[-1] > b['bottom']]

    def _cleanup_bear_blocks(self):
        self.bear_blocks = [b for b in self.bear_blocks if self.data.High[-1] < b['top']]

    def next(self):
        # Cleanup mitigated blocks
        self._cleanup_bull_blocks()
        self._cleanup_bear_blocks()
        
        # Create new order blocks
        if len(self) > self.lookback + 1:
            if (self.is_consol[-1] and 
                self.vol_strength[-1] >= self.vol_threshold):
                
                if self.bull_break[-1]:
                    block = {
                        'top': self.data.High[-2],
                        'bottom': self.data.Low[-2],
                        'bar': len(self)
                    }
                    self.bull_blocks.append(block)
                    if len(self.bull_blocks) > self.max_blocks:
                        self.bull_blocks.pop(0)
                
                if self.bear_break[-1]:
                    block = {
                        'top': self.data.High[-2],
                        'bottom': self.data.Low[-2],
                        'bar': len(self)
                    }
                    self.bear_blocks.append(block)
                    if len(self.bear_blocks) > self.max_blocks:
                        self.bear_blocks.pop(0)
        
        # Calculate big trade signals
        if len(self) > self.bt_lookback + 1:
            is_big_buy = (self.raw_buy[-1] > 
                         self.avg_buy[-1] + self.std_buy[-1] * self.bt_mult)
            is_big_sell = (self.raw_sell[-1] > 
                          self.avg_sell[-1] + self.std_sell[-1] * self.bt_mult)
            
            near_bull_ob = self._is_near_bull_ob()
            near_bear_ob = self._is_near_bear_ob()
            
            # Trading signals
            long_signal = (is_big_buy and near_bull_ob and 
                          self.data.Close[-1] > self.daily_vwap[-1])
            short_signal = (is_big_sell and near_bear_ob and 
                           self.data.Close[-1] < self.daily_vwap[-1])
            
            # Entry logic
            if long_signal and not self.position:
                self.buy()
            elif short_signal and self.position:
                self.position.close()
            
            if short_signal and not self.position:
                self.sell()
            elif long_signal and self.position.is_short:
                self.position.close()
            
            # Exit logic
            if self.position.is_long and self.data.Close[-1] < self.daily_vwap[-1]:
                self.position.close()
            elif self.position.is_short and self.data.Close[-1] > self.daily_vwap[-1]:
                self.position.close()


