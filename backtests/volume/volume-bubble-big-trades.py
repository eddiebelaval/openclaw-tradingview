import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Since this is a volume/order flow indicator, we'll use volume-based signals
        # Calculate volume moving average and identify large volume bars
        self.vol_ma = self.I(pta.sma, volume, length=20)
        
        # Calculate volume percentile for bubble detection
        self.vol_percentile = self.I(
            lambda: volume.rolling(window=20).apply(
                lambda x: (x.iloc[-1] > x.quantile(0.60)) if len(x) > 0 else False
            )
        )
        
        # Track previous bar volume for change detection
        self.prev_volume = None
        
    def next(self):
        # Only trade if we have enough data
        if len(self.data) < 20:
            return
        
        current_vol = self.data.Volume[-1]
        vol_ma = self.vol_ma[-1]
        
        # Simple order flow strategy: buy on large volume with price above hl2, sell on large volume with price below hl2
        hl2 = (self.data.High[-1] + self.data.Low[-1]) / 2
        
        # Check if current volume is significantly above average (bubble detection)
        is_large_volume = current_vol > vol_ma * 1.5 if vol_ma and not np.isnan(vol_ma) else False
        
        if is_large_volume:
            # Buy signal: large volume at higher price (aggressive buying)
            if self.data.Close[-1] > hl2 and not self.position:
                self.buy()
            # Sell signal: large volume at lower price (aggressive selling)
            elif self.data.Close[-1] < hl2 and self.position:
                self.sell()
        
        # Exit on mean reversion: if price returns to hl2 after a bubble
        if self.position:
            # Exit long if price falls back below hl2
            if self.data.Close[-1] < hl2:
                self.sell()


