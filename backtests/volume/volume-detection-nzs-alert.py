import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    volume_ma_length = 20
    volume_multiplier = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate volume MA
        self.volume_ma = self.I(pta.sma, volume, length=self.volume_ma_length)
        
        # Calculate volume spike condition
        def calc_volume_spike():
            return volume > (self.volume_ma * self.volume_multiplier)
        
        self.volume_spike = self.I(calc_volume_spike)
        
        # Calculate candle range and volume delta
        def calc_volume_delta():
            candle_range = high - low
            safe_range = candle_range.copy()
            safe_range[safe_range == 0] = 1
            
            buy_vol = pd.Series(0.0, index=close.index)
            sell_vol = pd.Series(0.0, index=close.index)
            
            close_gt_open = close > open_
            close_lt_open = close < open_
            close_eq_open = close == open_
            
            buy_vol[close_gt_open] = volume[close_gt_open] * (0.5 + 0.3 * np.minimum((close[close_gt_open] - open_[close_gt_open]) / safe_range[close_gt_open], 1.0))
            sell_vol[close_gt_open] = volume[close_gt_open] - buy_vol[close_gt_open]
            
            sell_vol[close_lt_open] = volume[close_lt_open] * (0.5 + 0.3 * np.minimum((open_[close_lt_open] - close[close_lt_open]) / safe_range[close_lt_open], 1.0))
            buy_vol[close_lt_open] = volume[close_lt_open] - sell_vol[close_lt_open]
            
            buy_vol[close_eq_open] = volume[close_eq_open] * 0.5
            sell_vol[close_eq_open] = volume[close_eq_open] * 0.5
            
            return buy_vol - sell_vol
        
        self.volume_delta = self.I(calc_volume_delta)
        
        # Calculate pressure
        def calc_buying_pressure():
            return self.volume_delta > 0
        
        def calc_selling_pressure():
            return self.volume_delta < 0
        
        self.buying_pressure = self.I(calc_buying_pressure)
        self.selling_pressure = self.I(calc_selling_pressure)

    def next(self):
        # Buy on bullish volume spike
        if self.volume_spike[-1] and self.buying_pressure[-1]:
            if not self.position:
                self.buy()
        # Sell on bearish volume spike
        elif self.volume_spike[-1] and self.selling_pressure[-1]:
            if self.position:
                self.position.close()
        # Exit on neutral or opposite pressure
        elif self.selling_pressure[-1] and self.position:
            self.position.close()