import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Volume threshold parameters
    high_vol_threshold = 10000000
    avg_len = 20
    sig_vol_min = 9000000
    sig_vol_max = 20000000
    sig_thresh = 8
    
    # Time window parameters (15:00 to 15:30)
    start_hour = 15
    start_minute = 0
    end_hour = 15
    end_minute = 30
    
    def init(self):
        # Calculate average volume
        volume_series = pd.Series(self.data.Volume)
        self.avg_vol = self.I(pta.sma, volume_series, length=self.avg_len)
        
        # Initialize counters and state
        self.bull_count = 0
        self.bear_count = 0
        self.bull_sig_count = 0
        self.bear_sig_count = 0
        self.bull_snapshot = 0
        self.bear_snapshot = 0
        self.bull_sig_snapshot = 0
        self.bear_sig_snapshot = 0
        self.was_in_window = False
        self.signal_value = 0
        
        # Track previous signal for entry/exit
        self.prev_signal = 0

    def next(self):
        # Get current bar info
        current_time = pd.Timestamp(self.data.index[-1])
        current_hour = current_time.hour
        current_minute = current_time.minute
        
        bar_time_minutes = current_hour * 60 + current_minute
        start_minutes = self.start_hour * 60 + self.start_minute
        end_minutes = self.end_hour * 60 + self.end_minute
        
        in_window = bar_time_minutes >= start_minutes and bar_time_minutes < end_minutes
        
        # Candle and volume logic
        is_bullish = self.data.Close[-1] >= self.data.Open[-1]
        is_high_vol = self.data.Volume[-1] > self.high_vol_threshold
        in_sig_volume = self.data.Volume[-1] > self.sig_vol_min and self.data.Volume[-1] < self.sig_vol_max
        
        # Window state transitions
        window_just_ended = self.was_in_window and not in_window
        if window_just_ended:
            self.bull_snapshot = self.bull_count
            self.bear_snapshot = self.bear_count
            self.bull_sig_snapshot = self.bull_sig_count
            self.bear_sig_snapshot = self.bear_sig_count
            self.bull_count = 0
            self.bear_count = 0
            self.bull_sig_count = 0
            self.bear_sig_count = 0
        
        window_just_started = not self.was_in_window and in_window
        if window_just_started:
            self.bull_count = 0
            self.bear_count = 0
            self.bull_sig_count = 0
            self.bear_sig_count = 0
        
        # Count candles inside window
        if in_window:
            if is_bullish:
                self.bull_count += 1
                if in_sig_volume:
                    self.bull_sig_count += 1
            else:
                self.bear_count += 1
                if in_sig_volume:
                    self.bear_sig_count += 1
        
        self.was_in_window = in_window
        
        # Display values (live or snapshot)
        display_bull = self.bull_count if in_window else self.bull_snapshot
        display_bear = self.bear_count if in_window else self.bear_snapshot
        display_bull_sig = self.bull_sig_count if in_window else self.bull_sig_snapshot
        display_bear_sig = self.bear_sig_count if in_window else self.bear_sig_snapshot
        
        # Signal logic
        has_sig_vol_candles = (display_bull_sig + display_bear_sig) > 0
        
        if has_sig_vol_candles and display_bear_sig >= self.sig_thresh:
            self.signal_value = 1  # BUY PUT (short)
        elif has_sig_vol_candles and display_bull_sig >= self.sig_thresh:
            self.signal_value = 2  # BUY CALL (long)
        else:
            self.signal_value = 0  # IGNORE
        
        # Trading logic based on signal changes
        if self.prev_signal != self.signal_value:
            if self.signal_value == 2:  # BUY CALL - go long
                if self.position.is_short:
                    self.position.close()
                if not self.position:
                    self.buy()
            elif self.signal_value == 1:  # BUY PUT - go short
                if self.position.is_long:
                    self.position.close()
                if not self.position:
                    self.sell()
            elif self.signal_value == 0:  # IGNORE - close position
                if self.position:
                    self.position.close()
        
        self.prev_signal = self.signal_value


