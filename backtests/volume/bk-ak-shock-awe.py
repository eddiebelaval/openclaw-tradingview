import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate CVD (Cumulative Volume Delta)
        is_up = close > pd.Series(self.data.Open)
        vol_delta = np.where(is_up, volume, np.where(close < pd.Series(self.data.Open), -volume, 0))
        cvd_raw = np.cumsum(vol_delta)
        
        # CVD Moving Averages
        self.cvd_ma = self.I(pta.sma, cvd_raw, length=21)
        
        # CVD Bollinger Bands (AK-9 style)
        cvd_smooth = self.I(pta.sma, cvd_raw, length=3)
        cvd_stdev = self.I(lambda x: pd.Series(x).rolling(3).std().values, cvd_raw)
        self.cvd_bb_upper = cvd_smooth + 0.8 * cvd_stdev
        self.cvd_bb_lower = cvd_smooth - 0.8 * cvd_stdev
        
        # OBV for confluence
        self.obv = self.I(pta.obv, close, volume)
        
        # MACD for confluence
        macd_result = self.I(lambda x: pta.macd(x, fast=12, slow=26, signal=9), close)
        self.macd_hist = macd_result['MACDH_12_26_9'] if macd_result is not None else None
        
        # ADX for trend strength
        adx_result = self.I(lambda x, y, z: pta.adx(x, y, z, length=14), high, low, close)
        self.adx = adx_result['ADX_14'] if adx_result is not None else None
        
        # ATR for volatility
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # ROC (Rate of Change) for momentum
        self.roc = self.I(pta.roc, close, length=14)
        
        # Slope calculation
        self.cvd_slope = self.I(lambda x: pd.Series(x).diff(14).values, cvd_raw)
        self.obv_slope = self.I(lambda x: pd.Series(x).diff(14).values, self.obv)
        
        # Store raw CVD for analysis
        self.cvd_raw = self.I(lambda x: x, cvd_raw)
        
        # Session anchors
        self.position_size = 0

    def next(self):
        if len(self.data) < 30:
            return
        
        # Get current values
        cvd = self.cvd_raw[-1] if self.cvd_raw[-1] is not None else 0
        cvd_ma = self.cvd_ma[-1] if self.cvd_ma[-1] is not None else 0
        cvd_upper = self.cvd_bb_upper[-1] if self.cvd_bb_upper[-1] is not None else 0
        cvd_lower = self.cvd_bb_lower[-1] if self.cvd_bb_lower[-1] is not None else 0
        
        obv = self.obv[-1] if self.obv[-1] is not None else 0
        obv_prev = self.obv[-2] if len(self.obv) > 1 and self.obv[-2] is not None else obv
        obv_slope = obv - obv_prev
        
        cvd_slope = self.cvd_slope[-1] if self.cvd_slope[-1] is not None else 0
        cvd_slope_prev = self.cvd_slope[-2] if len(self.cvd_slope) > 1 else cvd_slope
        
        roc = self.roc[-1] if self.roc[-1] is not None else 0
        
        # Determine CVD trend state
        above_ma = cvd > cvd_ma
        above_upper = cvd > cvd_upper
        below_lower = cvd < cvd_lower
        
        # Divergence signals
        obv_cvd_bull_div = (cvd_slope < 0 and obv_slope > 0)
        obv_cvd_bear_div = (cvd_slope > 0 and obv_slope < 0)
        
        # BB extremes with momentum
        extreme_oversold = below_lower and cvd_slope < 0
        extreme_overbought = above_upper and cvd_slope > 0
        
        # Trading logic based on CVD confluence signals
        has_position = self.position.size != 0
        
        # BULLISH SIGNALS
        if not has_position:
            # Signal 1: Oversold + reversal
            if extreme_oversold and roc > -20:
                self.buy()
            # Signal 2: Hidden bullish divergence (CVD lower but recovering)
            elif below_lower and cvd_slope > cvd_slope_prev and obv_slope > 0:
                self.buy()
            # Signal 3: OBV bullish divergence
            elif obv_cvd_bull_div and cvd < cvd_lower:
                self.buy()
            # Signal 4: Cross above MA with BB positioning
            elif crossover(self.cvd_raw, self.cvd_ma) and not above_upper:
                self.buy()
        
