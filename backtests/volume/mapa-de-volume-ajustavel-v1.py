import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    mult_lv2 = 2.0
    mult_lv3 = 4.0
    mult_lv4 = 6.0
    opac_minima = 5
    opac_lv2 = 15
    opac_lv3 = 35
    opac_lv4 = 100

    def init(self):
        # Calculate volume-based indicators
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        
        # Calculate daily min/max volume
        self.daily_volume = self.I(self._calc_daily_volume, volume)
        self.volume_relative = self.I(self._calc_volume_relative, volume, self.daily_volume)
        self.is_up = self.I(lambda: (close >= open_).astype(float))
        self.opacity = self.I(self._calc_opacity, self.volume_relative)

    def _calc_daily_volume(self, volume):
        # Track minimum volume per day
        df = pd.DataFrame({'volume': volume})
        df['date'] = pd.to_datetime(range(len(df)), unit='D')
        df['day'] = df['date'].dt.date
        df['daily_min'] = df.groupby('day')['volume'].transform('min')
        return df['daily_min'].values

    def _calc_volume_relative(self, volume, daily_min):
        # Relative volume compared to daily minimum
        relative = np.where(daily_min > 0, volume / daily_min, 1.0)
        return relative

    def _calc_opacity(self, vol_relative):
        # Calculate opacity based on volume levels
        opacity = np.full_like(vol_relative, self.opac_minima, dtype=float)
        opacity = np.where(vol_relative >= self.mult_lv2, self.opac_lv2, opacity)
        opacity = np.where(vol_relative >= self.mult_lv3, self.opac_lv3, opacity)
        opacity = np.where(vol_relative >= self.mult_lv4, self.opac_lv4, opacity)
        return opacity

    def next(self):
        # Trading logic based on volume heatmap
        current_opacity = self.opacity[-1]
        current_vol_rel = self.volume_relative[-1]
        is_up = self.is_up[-1]
        
        # Buy signal: High volume spike with upcandle
        if current_opacity >= self.opac_lv3 and is_up and not self.position:
            self.buy()
        
        # Sell signal: High opacity reversal or downcandle with high volume
        elif current_opacity >= self.opac_lv2 and not is_up and self.position:
            self.sell()