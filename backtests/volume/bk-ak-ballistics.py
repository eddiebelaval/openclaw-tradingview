import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        # Initialize session tracking variables
        self.session_bars = 0
        self.buy_bars = 0
        self.sell_bars = 0
        self.buy_streak = 0
        self.sell_streak = 0
        self.delta_pos_streak = 0
        self.delta_neg_streak = 0
        self.session_buy_vol = 0.0
        self.session_sell_vol = 0.0
        self.cvd = 0.0
        self.cvd_high = 0.0
        self.cvd_low = 0.0
        self.session_high = 0.0
        self.session_low = 0.0
        self.prev_cvd = 0.0
        
        # Pre-calculate volume-based indicators
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Estimate buy/sell volumes based on price position
        range_val = high - low
        self.est_buy = self.I(lambda: volume * (close - low) / range_val.replace(0, 1))
        self.est_sell = self.I(lambda: volume - self.est_buy)
        self.est_delta = self.I(lambda: self.est_buy - self.est_sell)
        
        # Calculate buy/sell percentages
        total_vol = self.I(lambda: self.est_buy + self.est_sell)
        self.buy_pct = self.I(lambda: (self.est_buy / total_vol.replace(0, 1) * 100.0).fillna(50.0))
        self.sell_pct = self.I(lambda: 100.0 - self.buy_pct)
        
        # Price change tracking
        self.price_change = self.I(lambda: close.diff())
        
        # CVD tracking (cumulative volume delta)
        self.cvd_series = self.I(lambda: self.est_delta.cumsum())

    def next(self):
        # Update session tracking
        self.session_bars += 1
        
        # Get current values
        current_buy_pct = self.buy_pct[-1]
        current_sell_pct = self.sell_pct[-1]
        current_delta = self.est_delta[-1]
        current_price_chg = self.price_change[-1]
        current_cvd = self.cvd_series[-1]
        
        # Track buy/sell bars
        if current_buy_pct > current_sell_pct:
            self.buy_bars += 1
            self.buy_streak += 1
            self.sell_streak = 0
        else:
            self.sell_bars += 1
            self.sell_streak += 1
            self.buy_streak = 0
        
        # Track delta streaks
        if current_delta >= 0:
            self.delta_pos_streak += 1
            self.delta_neg_streak = 0
        else:
            self.delta_neg_streak += 1
            self.delta_pos_streak = 0
        
        # Track session extremes
        if len(self.data) == 1 or len(self.data) == 0:
            self.session_high = self.data.High[-1]
            self.session_low = self.data.Low[-1]
            self.cvd_high = current_cvd
            self.cvd_low = current_cvd
        else:
            self.session_high = max(self.session_high, self.data.High[-1])
            self.session_low = min(self.session_low, self.data.Low[-1])
            self.cvd_high = max(self.cvd_high, current_cvd)
            self.cvd_low = min(self.cvd_low, current_cvd)
        
        # ── TRADING LOGIC ──
        # Since this is a footprint/volume analysis indicator, we use volume + price action signals
        
        # Signal 1: Strong buyer dominance with sustained streak + positive delta + price rising
        buy_signal = (
            self.buy_streak >= 3 and
            current_delta >= 0 and
            current_price_chg > 0 and
            current_buy_pct > 60
        )
        
        # Signal 2: Strong seller dominance with sustained streak + negative delta + price falling
        sell_signal = (
            self.sell_streak >= 3 and
            current_delta < 0 and
            current_price_chg < 0 and
            current_sell_pct > 60
        )
        
        # Signal 3: Divergence signals for reversals
        # Buying into weakness (absorption)
        absorption_buy = (
            current_delta > 0 and
            current_price_chg < 0 and
            current_buy_pct > 55
        )
        
        # Selling into strength (distribution)
        distribution_sell = (
            current_delta < 0 and
            current_price_chg > 0 and
            current_sell_pct > 55
        )
        
        # Signal 4: CVD extreme reversals
        cvd_range = self.cvd_high - self.cvd_low if self.cvd_high > self.cvd_low else 1
        cvd_pct = (current_cvd - self.cvd_low) / cvd_range * 100.0 if cvd_range > 0 else 50.0
        
        cvd_low_with_price_up = cvd_pct < 20 and current_price_chg > 0
        cvd_high_with_price_dn = cvd_pct > 80 and current_price_chg < 0
        
        # Entry logic
        if not self.position:
            if (buy_signal or absorption_buy or cvd_low_with_price_up):
                self.buy()
            elif (sell_signal or distribution_sell or cvd_high_with_price_dn):
                self.sell()
        
        # Exit logic
        else:
            # Exit long on reversal signals
            if self.position.is_long:
                if (self.sell_streak >= 2 and current_delta < 0) or cvd_high_with_price_dn:
                    self.position.close()
            
            # Exit short on reversal signals
            if self.position.is_short:
                if (self.buy_streak >= 2 and current_delta > 0) or cvd_low_with_price_up:
                    self.position.close()


