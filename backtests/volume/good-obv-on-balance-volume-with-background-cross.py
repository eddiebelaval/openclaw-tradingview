import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    signal_length = 50
    sma_signal = 'EMA'

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Calculate OBV manually
        def calculate_obv():
            obv = np.zeros(len(close))
            for i in range(len(close)):
                if i == 0:
                    obv[i] = volume.iloc[i] if close.iloc[i] > 0 else -volume.iloc[i] if close.iloc[i] < 0 else 0
                else:
                    change = close.iloc[i] - close.iloc[i-1]
                    if change > 0:
                        obv[i] = obv[i-1] + volume.iloc[i]
                    elif change < 0:
                        obv[i] = obv[i-1] - volume.iloc[i]
                    else:
                        obv[i] = obv[i-1]
            return pd.Series(obv, index=close.index)
        
        self.obv = self.I(calculate_obv)
        
        # Calculate signal line (EMA or SMA of OBV)
        def calculate_signal():
            obv_series = self.obv
            if self.sma_signal == 'EMA':
                signal = pta.ema(obv_series, length=self.signal_length)
            else:
                signal = pta.sma(obv_series, length=self.signal_length)
            return signal if signal is not None else pd.Series(0, index=obv_series.index)
        
        self.signal = self.I(calculate_signal)

    def next(self):
        # Only trade when we have enough data for signal calculation
        if len(self.data) < self.signal_length + 1:
            return
        
        obv_val = self.obv[-1] if len(self.obv) > 0 else 0
        signal_val = self.signal[-1] if len(self.signal) > 0 else 0
        obv_prev = self.obv[-2] if len(self.obv) > 1 else obv_val
        signal_prev = self.signal[-2] if len(self.signal) > 1 else signal_val
        
        # Cross UP: signal was >= obv and now signal < obv (bullish crossover)
        cross_up = signal_prev >= obv_prev and signal_val < obv_val
        
        # Cross DN: signal was <= obv and now signal > obv (bearish crossover)
        cross_dn = signal_prev <= obv_prev and signal_val > obv_val
        
        if cross_up:
            if not self.position:
                self.buy()
        elif cross_dn:
            if self.position:
                self.sell()