import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    ma_slow_len = 20
    ma_fast_len = 9
    climax_mult = 2.0
    dry_up_pct = 0.4
    color_by_prev = False
    use_rvol = True
    show_climax = False
    show_dry_up = False

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # Calculate volume SMA (slow MA)
        self.vol_sma = self.I(lambda: pta.sma(volume, length=self.ma_slow_len))
        
        # Calculate volume EMA (fast MA)
        self.vol_ema = self.I(lambda: pta.ema(volume, length=self.ma_fast_len))
        
        # Calculate relative volume (volume / SMA)
        self.rel_vol = self.I(lambda: volume / (self.vol_sma + 1e-10))
        
        # Determine if bullish (close > open or close > previous close)
        self.is_bull = self.I(lambda: close > close.shift(1) if self.color_by_prev else close >= self.data.Open)
        
        # Volume above/below SMA
        self.above_sma = self.I(lambda: volume >= self.vol_sma)
        
        # Climax condition: relative volume >= climax multiplier
        self.is_climax = self.I(lambda: self.rel_vol >= self.climax_mult)
        
        # Dry-up condition: relative volume <= dry-up percentage
        self.is_dryup = self.I(lambda: self.rel_vol <= self.dry_up_pct)

    def next(self):
        # Entry logic based on volume analysis
        if len(self) < self.ma_slow_len + 1:
            return
        
        rel_vol_current = self.rel_vol[-1]
        is_climax = self.is_climax[-1] if self.show_climax else False
        is_dryup = self.is_dryup[-1] if self.show_dry_up else False
        is_bull = self.is_bull[-1]
        above_sma = self.above_sma[-1]
        
        # Buy signal: bullish bar with climax volume (high conviction)
        if self.show_climax and is_climax and is_bull and not self.position:
            self.buy()
        
        # Sell signal: bearish bar with climax volume (reversal)
        elif self.show_climax and is_climax and not is_bull and self.position:
            self.sell()
        
        # Alternative: Buy on volume expansion above MA with bullish close
        elif not self.show_climax and above_sma and is_bull and rel_vol_current > 1.0 and not self.position:
            self.buy()
        
        # Sell on volume dry-up or bearish reversal
        elif is_dryup and not is_bull and self.position:
            self.sell()
        elif not self.show_climax and not above_sma and not is_bull and self.position:
            self.sell()


