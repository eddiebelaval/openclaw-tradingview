import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    avgLen = 5
    totalMinInput = 240

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate volume ratio indicator
        def calculate_vol_ratio():
            result = pd.Series(index=close.index, dtype=float)
            
            # Calculate SMA of volume
            avg_vol_series = pta.sma(volume, length=self.avgLen)
            
            # For daily or higher timeframe logic (simplified for backtest)
            # We'll use daily-level calculation: volRatio = volume / avgVol
            for i in range(len(result)):
                if i < self.avgLen:
                    result.iloc[i] = np.nan
                else:
                    base_vol = avg_vol_series.iloc[i-1]
                    if base_vol != 0:
                        result.iloc[i] = volume.iloc[i] / base_vol
                    else:
                        result.iloc[i] = np.nan
            
            return result
        
        self.volRatio = self.I(calculate_vol_ratio)
        
        # Create trading signals based on volume ratio
        # Buy when volume ratio crosses above 1.0 (normal volume expansion)
        # Sell when volume ratio crosses below 1.0
        self.ratio_line = self.I(lambda: pd.Series(1.0, index=close.index))

    def next(self):
        # Skip if not enough data
        if len(self.data) < self.avgLen + 1:
            return
        
        # Buy signal: volume ratio crosses above 1.0 with increasing trend
        if not np.isnan(self.volRatio[-1]) and not np.isnan(self.volRatio[-2]):
            if crossover(self.volRatio, self.ratio_line):
                if not self.position:
                    self.buy()
            # Sell signal: volume ratio crosses below 1.0 or drops significantly
            elif crossover(self.ratio_line, self.volRatio):
                if self.position:
                    self.position.close()