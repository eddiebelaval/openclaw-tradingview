import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    # Parameters from the Pine Script
    i_buckets = 50
    i_decay = 0.98
    i_width = 100
    i_lookback = 1000
    i_imbRatio = 3.0

    def init(self):
        pass

    def next(self):
        # Volume Flow Analysis is a complex visualization indicator
        # Since it primarily displays volume distribution across price levels
        # and doesn't generate direct buy/sell signals, we implement a
        # simple trading rule based on buy/sell pressure ratio
        
        if len(self.data) < 2:
            return
        
        # Calculate volume flow metrics on the current bar
        high = self.data.High
        low = self.data.Low
        close = self.data.Close
        volume = self.data.Volume
        
        # Calculate lookback period
        n_calc = self.i_lookback if self.i_decay == 1.0 else int(np.ceil(np.log(0.01) / np.log(self.i_decay)))
        N = max(1, min(n_calc, self.i_lookback, len(self.data) - 1))
        
        # Get price range
        pH = np.max(high[-N:])
        pL = np.min(low[-N:])
        
        bSz = (pH - pL) / self.i_buckets if self.i_buckets > 0 else 1.0
        
        if bSz <= 0:
            return
        
        # Initialize volume arrays
        bVol = np.zeros(self.i_buckets)
        sVol = np.zeros(self.i_buckets)
        
        # Process bars with decay
        for i in range(N):
            idx = -(N - i)
            h_i = high[idx]
            l_i = low[idx]
            c_i = close[idx]
            v_i = volume[idx]
            rng = h_i - l_i
            d_m = np.power(self.i_decay, i)
            
            if rng == 0:
                b_v = v_i / 2
                s_v = v_i / 2
            else:
                b_v = v_i * (c_i - l_i) / rng
                s_v = v_i - b_v
            
            if rng > 0:
                minIdx = max(0, int(np.floor((l_i - pL) / bSz)))
                maxIdx = min(self.i_buckets - 1, int(np.floor((h_i - pL) / bSz)))
                
                for j in range(minIdx, maxIdx + 1):
                    b_min = pL + j * bSz
                    b_max = b_min + bSz
                    ovr = max(0, min(h_i, b_max) - max(l_i, b_min))
                    
                    if ovr > 0:
                        prop = ovr / rng
                        bVol[j] += b_v * prop * d_m
                        sVol[j] += s_v * prop * d_m
            else:
                idx_bucket = max(0, min(self.i_buckets - 1, int(np.floor((c_i - pL) / bSz))))
                bVol[idx_bucket] += b_v * d_m
                sVol[idx_bucket] += s_v * d_m
        
        # Calculate total volumes
        tB = np.sum(bVol)
        tS = np.sum(sVol)
        tV = tB + tS
        
        if tV <= 0:
            return
        
        pB = (tB / tV) * 100
        pS = (tS / tV) * 100
        
        # Trading logic based on buy/sell pressure
        # Buy when bullish pressure dominates and increasing
        # Sell when bearish pressure dominates and increasing
        
        if len(self) > 1:
            # Get previous bar's pressure if available from stored state
            if not hasattr(self, 'prev_pB'):
                self.prev_pB = 50.0
            
            # Buy signal: strong bullish pressure
            if pB > 60 and pB > self.prev_pB and not self.position:
                self.buy()
            
            # Sell signal: strong bearish pressure
