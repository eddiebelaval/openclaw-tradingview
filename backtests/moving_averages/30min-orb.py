class TvStrategy(Strategy):
    def init(self):
        self.orb_high = None
        self.orb_low = None
        self.session_start_idx = None
        self.breakout_triggered = False

    def next(self):
        current_time = pd.Timestamp(self.data.index[-1])
        current_hour = current_time.hour
        current_minute = current_time.minute
        
        # Check if we're in the 09:15-09:45 session (IST)
        in_session = (current_hour == 9 and current_minute >= 15 and current_minute < 45)
        
        # Check if session just started
        if len(self.data) > 1:
            prev_time = pd.Timestamp(self.data.index[-2])
            prev_hour = prev_time.hour
            prev_minute = prev_time.minute
            prev_in_session = (prev_hour == 9 and prev_minute >= 15 and prev_minute < 45)
            session_just_started = in_session and not prev_in_session
        else:
            session_just_started = in_session
            prev_in_session = False
        
        # Initialize ORB on first candle of session
        if session_just_started:
            self.orb_high = self.data.High[-1]
            self.orb_low = self.data.Low[-1]
            self.session_start_idx = len(self.data) - 1
            self.breakout_triggered = False
        
        # Update ORB high/low during session
        if in_session and self.orb_high is not None:
            self.orb_high = max(self.data.High[-1], self.orb_high)
            self.orb_low = min(self.data.Low[-1], self.orb_low)
        
        # Check if session ended (transition from in_session to not in_session)
        if len(self.data) > 1:
            session_ended = prev_in_session and not in_session
        else:
            session_ended = False
        
        # After session ends, trade breakouts
        if self.orb_high is not None and not in_session:
            # Buy on breakout above ORB high
            if self.data.Close[-1] > self.orb_high and not self.breakout_triggered:
                if not self.position:
                    self.buy()
                    self.breakout_triggered = True
            
            # Sell on breakdown below ORB low
            if self.data.Close[-1] < self.orb_low and not self.breakout_triggered:
                if not self.position:
                    self.sell()
                    self.breakout_triggered = True
            
            # Exit long on ORB low touch
            if self.position and self.position.is_long:
                if self.data.Low[-1] <= self.orb_low:
                    self.position.close()
            
            # Exit short on ORB high touch
            if self.position and not self.position.is_long:
                if self.data.High[-1] >= self.orb_high:
                    self.position.close()
        
        # Reset for new session
        if session_ended:
            self.orb_high = None
            self.orb_low = None
            self.breakout_triggered = False


