import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Since we can't fetch external symbols in backtesting context,
        # we'll simulate institutional aggression using price and volume analysis
        # on the current symbol being backtested
        
        def calc_local_aggression():
            """Calculate aggression score based on local price and volume"""
            c = pd.Series(self.data.Close)
            h = pd.Series(self.data.High)
            l = pd.Series(self.data.Low)
            v = pd.Series(self.data.Volume)
            
            # VWAP calculation
            vwap = pta.vwap(h, l, c, v)
            if vwap is None:
                vwap = pd.Series(c.iloc[0], index=c.index)
            
            # Volume moving average
            avg_vol = pta.sma(v, length=20)
            if avg_vol is None:
                avg_vol = pd.Series(v.iloc[0], index=v.index)
            
            # Calculate aggression for each bar
            is_bullish = c > vwap
            is_aggressive = v > (avg_vol * 1.5)
            
            scores = pd.Series(0.0, index=c.index)
            
            for i in range(len(c)):
                w = 10.0  # Base weight
                if is_bullish.iloc[i]:
                    scores.iloc[i] = w if is_aggressive.iloc[i] else w * 0.4
                else:
                    scores.iloc[i] = -w if is_aggressive.iloc[i] else -w * 0.4
            
            return scores
        
        # Calculate total aggression (using single symbol)
        self.aggression = self.I(calc_local_aggression)
        
        # Signal line - EMA of aggression
        self.signal = self.I(lambda: pta.ema(pd.Series(self.aggression), length=3) or pd.Series(0, index=pd.Series(self.aggression).index))

    def next(self):
        # Buy when aggression crosses above signal line and is positive
        if len(self.data) < 2:
            return
        
        agg_current = self.aggression[-1]
        agg_prev = self.aggression[-2]
        sig_current = self.signal[-1]
        sig_prev = self.signal[-2]
        
        if agg_prev is None or sig_prev is None:
            return
        
        # Entry: Bullish aggression crossover with signal
        if agg_prev <= sig_prev and agg_current > sig_current and agg_current > 0:
            if not self.position:
                self.buy()
        
        # Entry: Extreme buying pressure
        elif agg_current > 25 and agg_prev <= 25:
            if not self.position:
                self.buy()
        
        # Exit: Signal turns negative
        elif agg_current < 0 and agg_prev >= 0:
            if self.position:
                self.position.close()
        
        # Exit: Extreme selling pressure
        elif agg_current < -25 and agg_prev >= -25:
            if self.position:
                self.position.close()
        
        # Exit: Aggression falls below signal
        elif agg_prev >= sig_prev and agg_current < sig_current:
            if self.position:
                self.position.close()


