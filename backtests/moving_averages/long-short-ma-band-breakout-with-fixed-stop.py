import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    ma_type = 'EMA'
    maLen = 200
    bandUpPerc = 3.0
    bandDownPerc = 2.0
    stopLossPerc = 2.0
    mode = 'Long Only'

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate MA based on type
        if self.ma_type == 'EMA':
            self.ma = self.I(pta.ema, close, length=self.maLen)
        elif self.ma_type == 'SMA':
            self.ma = self.I(pta.sma, close, length=self.maLen)
        elif self.ma_type == 'TEMA':
            self.ma = self.I(self._tema, close)
        elif self.ma_type == 'ALMA':
            self.ma = self.I(self._alma, close)
        elif self.ma_type == 'HMA':
            self.ma = self.I(self._hma, close)
        
        # Calculate bands
        self.upperBand = self.I(lambda: self.ma * (1 + self.bandUpPerc / 100))
        self.lowerBand = self.I(lambda: self.ma * (1 - self.bandDownPerc / 100))
        
        self.entry_price = None

    def _tema(self, close):
        ema1 = pta.ema(close, length=self.maLen)
        if ema1 is None:
            return None
        ema2 = pta.ema(ema1, length=self.maLen)
        if ema2 is None:
            return None
        ema3 = pta.ema(ema2, length=self.maLen)
        if ema3 is None:
            return None
        return 3 * (ema1 - ema2) + ema3

    def _alma(self, close):
        length = self.maLen
        offset = 0.85
        sigma = 6
        m = offset * (length - 1)
        s = length / sigma
        
        result = []
        for i in range(len(close)):
            if i < length - 1:
                result.append(np.nan)
            else:
                sum_val = 0.0
                norm = 0.0
                for j in range(length):
                    idx = i - length + 1 + j
                    w = np.exp(-1 * np.power(j - m, 2) / (2 * np.power(s, 2)))
                    sum_val += close.iloc[idx] * w
                    norm += w
                result.append(sum_val / norm if norm != 0 else np.nan)
        
        return pd.Series(result, index=close.index)

    def _hma(self, close):
        length = self.maLen
        wma1 = pta.wma(close, length=length // 2)
        if wma1 is None:
            return None
        wma2 = pta.wma(close, length=length)
        if wma2 is None:
            return None
        diff = 2 * wma1 - wma2
        sqrt_len = int(np.round(np.sqrt(length)))
        hma_result = pta.wma(diff, length=sqrt_len)
        return hma_result

    def next(self):
        # Check if we have valid indicator values
        if len(self.ma) < self.maLen or pd.isna(self.ma[-1]):
            return
        
        current_close = self.data.Close[-1]
        current_upper = self.upperBand[-1]
        current_lower = self.lowerBand[-1]
        
        # Long Logic
        if (self.mode == 'Long Only' or self.mode == 'Long & Short'):
            # Long Entry
            if current_close > current_upper and not self.position:
                self.entry_price = current_close
                stop_price = current_close * (1 - self.stopLossPerc / 100)
                self.buy()
                self.stop_loss = stop_price
            
            # Exit Long on lower band breach
            if self.position.size > 0 and current_close < current_lower:
                self.position.close()
            
            # Exit Long on stop loss
            if self.position.size > 0 and current_close <= self.stop_loss:
                self.position.close()
        
        # Short Logic
        if (self.mode == 'Short Only' or self.mode == 'Long & Short'):
            # Short Entry
            if current_close < current_lower and not self.position:
                self.entry_price = current_close
                stop_price = current_close * (1 + self.stopLossPerc / 100)
                self.sell()
                self.stop_loss = stop_price
            
            # Exit Short on upper band breach
            if self.position.size < 0 and current_close > current_upper:
                self.position.close()
            
            # Exit Short on stop loss
            if self.position.size < 0 and current_close >= self.stop_loss:
                self.position.close()


