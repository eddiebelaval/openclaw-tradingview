import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema50 = self.I(pta.ema, close, length=50)
        
        self.high_series = high
        self.low_series = low
        self.open_series = open_

    def next(self):
        if len(self.data) < 2:
            return
        
        current_high = self.high_series.iloc[-1]
        current_low = self.low_series.iloc[-1]
        current_close = self.data.Close[-1]
        current_open = self.open_series.iloc[-1]
        
        ema20 = self.ema20[-1]
        ema50 = self.ema50[-1]
        
        if ema20 is None or ema50 is None:
            return
        
        bullWickTouch20 = current_low <= ema20 and current_close > ema20 and current_open > ema20
        bearWickTouch20 = current_high >= ema20 and current_close < ema20 and current_open < ema20
        
        bullWickTouch50 = current_low <= ema50 and current_close > ema50 and current_open > ema50
        bearWickTouch50 = current_high >= ema50 and current_close < ema50 and current_open < ema50
        
        condition20 = bullWickTouch20 or bearWickTouch20
        condition50 = bullWickTouch50 or bearWickTouch50
        
        if bullWickTouch20 or bullWickTouch50:
            if not self.position:
                self.buy()
        elif bearWickTouch20 or bearWickTouch50:
            if self.position:
                self.sell()


