import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters
    lookback_min = 10
    k_range = 0.15
    k_spread = 3.0
    use_strict_and = True
    max_crosses_n = 3
    on_confirm_bars = 2
    off_confirm_bars = 3
    spread_pts = 0.5
    tick_size_pts = 1.0
    min_ticks_eps = 2
    eps_spread_mult = 1.0
    hold_bars = 5
    hold_delta_mult = 1.0
    require_pullback = True
    rej_close_frac = 0.50

    def init(self):
        self.gate = False
        self.pass_streak = 0
        self.fail_streak = 0
        self.cum_pv = 0
        self.cum_v = 0
        self.last_nz = 0
        self.crosses_count = 0
        
        self.orb_high = None
        self.orb_low = None
        self.in_orb_session = False
        self.orb_session_started = False

    def next(self):
        if len(self.data) < self.lookback_min + 1:
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1] if self.data.Volume[-1] > 0 else 1.0
        hlc3 = (high + low + close) / 3.0

        # Initialize VWAP accumulators on first bar
        if len(self.data) == 1:
            self.cum_pv = hlc3 * volume
            self.cum_v = volume
        else:
            self.cum_pv += hlc3 * volume
            self.cum_v += volume

        vwap_rth = self.cum_pv / self.cum_v if self.cum_v != 0 else close

        # Calculate epsilon and delta
        eps_pts = max(self.min_ticks_eps * self.tick_size_pts, 
                      self.spread_pts * self.eps_spread_mult)
        delta_pts = max(2.0 * self.tick_size_pts, 
                        self.spread_pts * self.hold_delta_mult)

        vwap_upper = vwap_rth + eps_pts
        vwap_lower = vwap_rth - eps_pts

        # Calculate VWAP move
        vwap_move = abs(vwap_rth - self.data.Close[-self.lookback_min - 1] 
                       if len(self.data) > self.lookback_min else 0)

        # Calculate range
        high_lookback = self.data.High[-self.lookback_min:].max()
        low_lookback = self.data.Low[-self.lookback_min:].min()
        r_n = high_lookback - low_lookback

        thr_range = self.k_range * r_n
        thr_spr = self.k_spread * self.spread_pts

        # Check slope pass
        pass_slope = False
        if not np.isnan(vwap_move) and not np.isnan(r_n):
            if self.use_strict_and:
                pass_slope = (vwap_move >= thr_range) and (vwap_move >= thr_spr)
            else:
                pass_slope = vwap_move >= max(thr_range, thr_spr)

        # Check chop pass
        buffer = max(2.0 * self.tick_size_pts, self.spread_pts)
        state_side = 1 if close > vwap_rth + buffer else (-1 if close < vwap_rth - buffer else 0)
        
        if state_side != 0:
            self.last_nz = state_side

        cross_now = 1.0 if (self.last_nz != 0 and 
                            len(self.data) > 1 and 
                            self.last_nz != (1 if self.data.Close[-2] > self.data.Close[-1] else -1)) else 0.0
        
        # Simple crossing count
        if cross_now > 0:
            self.crosses_count += 1
            if len(self.data) > self.lookback_min:
                self.crosses_count = max(0, self.crosses_count - 1)
        
        pass_chop = self.crosses_count <= self.max_crosses_n

        raw_pass = pass_slope and pass_chop

        # Gate logic
        if raw_pass:
            self.pass_streak += 1
            self.fail_streak = 0
        else:
            self.fail_streak += 1
            self.pass_streak = 0

        if not self.gate and self.pass_streak >= self.on_confirm_bars:
            self.gate = True
        if self.gate and self.fail_streak >= self.off_confirm_bars:
            self.gate = False

        # Hold logic
        diff_long = close - (vwap_rth + delta_pts)
        diff_short = (vwap_rth - delta_pts) - close

        if len(self.data) >= self.hold_bars:
            hold_long = self.data.Close[-self.hold_bars:].apply(
                lambda i: close - (vwap_rth + delta_pts)
            ).min() > 0
            hold_short = self.data.Close[-self.hold_bars:].apply(
                lambda i: (vwap_rth - delta_pts) - close
            ).min() > 0
        else:
            hold_long = diff_long > 0
            hold_short = diff_short > 0

        vwap_slope = vwap_rth - (self.data.Close[-self.lookback_min - 1] 
                                 if len(self.data) > self.lookback_min else vwap_rth)
        hold_long_ok = hold_long and (vwap_slope > 0)
        hold_short_ok = hold_short and (vwap_slope < 0)

        # Entry logic
        touched_zone = (low <= vwap_upper) and (high >= vwap_lower)
        rej_long = touched_zone and (close > (vwap_rth + eps_pts * self.rej_close_frac))
        rej_short = touched_zone and (close < (vwap_rth - eps_pts * self.rej_close_frac))

        if len(self.data) > 1:
            prev_close = self.data.Close[-2]
            prev_trend_long = prev_close > self.data.Close[-1]
            prev_trend_short = prev_close < self.data.Close[-1]
        else:
            prev_trend_long = True
            prev_trend_short = True

        entry_long = (self.gate and hold_long_ok and rej_long and 
                      (not self.require_pullback or prev_trend_long))
        entry_short = (self.gate and hold_short_ok and rej_short and 
                       (not self.require_pullback or prev_trend_short))

        # Execute trades
        if entry_long and not self.position:
            self.buy()
        elif entry_short and not self.position:
            self.sell()
        elif self.position and (not entry_long and not entry_short):
            self.position.close()