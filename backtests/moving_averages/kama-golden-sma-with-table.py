        # KAMA calculation
        def calculate_kama(src, length):
            direction = np.abs(src - src.shift(length))
            volatility = np.abs(src - src.shift(1)).rolling(length).sum()
            efficiency_ratio = np.where(volatility != 0, direction / volatility, 0)
            fast = 2.0 / (2 + 1)
            slow = 2.0 / (30 + 1)
            smoothing_constant = np.power(efficiency_ratio * (fast - slow) + slow, 2)
            
            kama_values = np.zeros(len(src))
            for i in range(len(src)):
                if i == 0:
                    kama_values[i] = src.iloc[i]
                else:
                    kama_values[i] = kama_values[i-1] + smoothing_constant[i] * (src.iloc[i] - kama_values[i-1])
            
            return pd.Series(kama_values, index=src.index)
        
        # SMAs
        self.sma5 = self.I(pta.sma, close, length=5)
