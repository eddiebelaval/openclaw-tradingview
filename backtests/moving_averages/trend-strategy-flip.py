import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters from the Pine Script
    atr_mult = 1.5
    mu = 0.6
    entry_mode = "A"
    entry_sub_mode = "B1"
    exit_mode = "Both"
    use_longs = True
    use_shorts = True
    use_breakeven = True
    be_trigger_perc = 1.0
    be_offset_perc = 0.0

    def init(self):
        self.close = pd.Series(self.data.Close)
        self.high = pd.Series(self.data.High)
        self.low = pd.Series(self.data.Low)
        
        # ATR 200
        self.atr200 = self.I(pta.atr, self.high, self.low, self.close, length=200)
        
        # Initialize z and v series to track state
        self.z_values = []
        self.v_values = []
        self.trend_values = []
        self.up_change_values = []
        self.down_change_values = []
        
        # Track breakeven levels
        self.be_long_level = None
        self.be_short_level = None
        
        # Calculate z and v for all bars
        self._calculate_z_and_v()
        
        # Wrap as indicators
        self.z = self.I(lambda: pd.Series(self.z_values, index=self.close.index))
        self.v = self.I(lambda: pd.Series(self.v_values, index=self.close.index))
        self.trend = self.I(lambda: pd.Series(self.trend_values, index=self.close.index))
        self.up_change = self.I(lambda: pd.Series(self.up_change_values, index=self.close.index))
        self.down_change = self.I(lambda: pd.Series(self.down_change_values, index=self.close.index))

    def _calculate_z_and_v(self):
        """Pre-calculate z, v, trend, and change arrays for all bars"""
        z = self.close.iloc[0]
        v = 0.0
        prev_trend = 0
        
        for i in range(len(self.close)):
            src = self.close.iloc[i]
            threshold = self.atr200[i] * self.atr_mult if not np.isnan(self.atr200[i]) else 0
            
            if i == 0:
                self.z_values.append(z)
                self.v_values.append(v)
                self.trend_values.append(0)
                self.up_change_values.append(False)
                self.down_change_values.append(False)
            else:
                z_prev = z
                v_prev = v
                z_pred = z_prev + v_prev
                z_temp = z_pred + self.mu * (src - z_pred)
                diff = z_temp - z_prev
                
                # Calculate v
                v = np.sign(diff) * (np.abs(diff) - threshold) if np.abs(diff) > threshold else 0.0
                z = z_prev + v
                
                # Calculate trend
                if z > z_prev:
                    trend = 1
                elif z < z_prev:
                    trend = -1
                else:
                    trend = prev_trend
                
                # Calculate changes
                up_change = (trend == 1 and prev_trend == -1)
                down_change = (trend == -1 and prev_trend == 1)
                
                self.z_values.append(z)
                self.v_values.append(v)
                self.trend_values.append(trend)
                self.up_change_values.append(up_change)
                self.down_change_values.append(down_change)
                
                prev_trend = trend

    def next(self):
        # Current bar index
        idx = len(self) - 1
        
        # Get current values
        close = self.close.iloc[idx]
        z = self.z[-1]
        v = self.v[-1]
        trend = self.trend[-1]
        up_change = self.up_change[-1]
        down_change = self.down_change[-1]
        
        # Previous values
        z_prev = self.z[-2] if len(self.z) > 1 else z
        v_prev = self.v[-2] if len(self.v) > 1 else v
        
        # Entry conditions
        long_a = up_change
        short_a = down_change
        
        long_b1 = close > z and self.close.iloc[idx - 1] <= z_prev if idx > 0 else False
        short_b1 = close < z and self.close.iloc[idx - 1] >= z_prev if idx > 0 else False
        
        long_b2 = v > 0 and v_prev <= 0 if idx > 0 else False
        short_b2 = v < 0 and v_prev >= 0 if idx > 0 else False
        
        long_c = self.up_change_values[idx - 1] if idx > 0 else False
        short_c = self.down_change_values[idx - 1] if idx > 0 else False
        
        # Select entry based on mode
        if self.entry_mode == "A":
            long_entry = long_a and self.use_longs
            short_entry = short_a and self.use_shorts
        elif self.entry_mode == "B":
            if self.entry_sub_mode == "B1":
                long_entry = long_b1 and self.use_longs
                short_entry = short_b1 and self.use_shorts
            else:  # B2
                long_entry = long_b2 and self.use_longs
                short_entry = short_b2 and self.use_shorts
        else:  # C
            long_entry = long_c and self.use_longs
            short_entry = short_c and self.use_shorts
        
        in_long = self.position.size > 0
        in_short = self.position.size < 0
        
        # Exit conditions based on price and trend
        price_above = close > z
        price_below = close < z
        
        if self.exit_mode == "By Trend Change":
            exit_long = down_change
            exit_short = up_change
        elif self.exit_mode == "By Price Cross":
            exit_long = price_below
            exit_short = price_above
        else:  # Both
            exit_long = down_change or price_below
            exit_short = up_change or price_above
        
        # Flip logic
        flip_long_to_short = in_long and down_change
        flip_short_to_long = in_short and up_change
        
        # Handle flips (close and reverse position)
        if flip_long_to_short:
            self.position.close()
            self.sell()
        elif flip_short_to_long:
            self.position.close()
            self.buy()
        
        # Regular entries (only if not in a position)
        elif long_entry and not in_long and not in_short:
            self.buy()
        elif short_entry and not in_short and not in_long:
            self.sell()
        
        # Regular exits
        elif in_long and exit_long:
            self.position.close()
        elif in_short and exit_short:
            self.position.close()
        
        # Breakeven management
        if self.use_breakeven and self.position.size != 0:
            entry_price = self.position.open_price
            
            if in_long:
                profit_perc = (close - entry_price) / entry_price * 100
                if profit_perc >= self.be_trigger_perc:
                    self.be_long_level = entry_price * (1 + self.be_offset_perc / 100)
                    if close <= self.be_long_level:
                        self.position.close()
            
            elif in_short:
                profit_perc = (entry_price - close) / entry_price * 100
                if profit_perc >= self.be_trigger_perc:
                    self.be_short_level = entry_price * (1 - self.be_offset_perc / 100)
                    if close >= self.be_short_level:
                        self.position.close()


