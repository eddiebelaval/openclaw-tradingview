import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Risk parameters
    risk_ok = True
    rr_ok = True
    
    # Macro liquidity parameters
    liq_ok = True
    cb_ok = True
    usd_ok = True
    vix_ok = True
    
    # Wyckoff parameters
    wyckoff_ok = True
    
    # ICT Technical parameters
    ob_fvg_ok = True
    liq_grab_ok = True
    structure_ok = True
    
    # Final parameters
    asset_ok = True
    exit_ok = True

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate moving averages
        self.ma200 = self.I(pta.sma, close, length=200)
        self.ma50 = self.I(pta.sma, close, length=50)

    def next(self):
        # Check if we have enough data
        if len(self.data) < 200:
            return
        
        # Current values
        close_price = self.data.Close[-1]
        ma200_val = self.ma200[-1]
        ma50_val = self.ma50[-1]
        
        # Conditions for trading
        above200 = close_price > ma200_val
        above50 = close_price > ma50_val
        uptrend = ma50_val > ma200_val
        
        # All checklist items must be true
        all_conditions_met = (
            self.risk_ok and self.rr_ok and
            self.liq_ok and self.cb_ok and self.usd_ok and self.vix_ok and
            self.wyckoff_ok and
            self.ob_fvg_ok and self.liq_grab_ok and self.structure_ok and
            self.asset_ok and self.exit_ok and
            above200 and above50 and uptrend
        )
        
        # Buy when all conditions are met and we don't have a position
        if all_conditions_met and not self.position:
            self.buy()
        
        # Sell when any condition fails or price breaks below 50 MA
        elif self.position and (not above50 or not uptrend):
            self.sell()


