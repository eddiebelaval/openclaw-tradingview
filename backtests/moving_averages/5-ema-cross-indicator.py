import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema200_len = 200
    ema50_len = 50
    ema5_len = 5
    swing_lookback = 10
    rr_ratio = 5.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)

        self.ema200 = self.I(pta.ema, close, length=self.ema200_len)
        self.ema50 = self.I(pta.ema, close, length=self.ema50_len)
        self.ema5 = self.I(pta.ema, close, length=self.ema5_len)

        self.high_data = high
        self.low_data = low
        self.open_data = open_
        self.close_data = close

        self.wicked_long = False
        self.wicked_short = False
        self.in_position = False

    def next(self):
        if len(self.data) < max(self.ema200_len, self.ema50_len, self.ema5_len) + 2:
            return

        idx = len(self.data) - 1

        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        open_val = self.data.Open[-1]

        ema200_val = self.ema200[-1]
        ema50_val = self.ema50[-1]
        ema5_val = self.ema5[-1]

        ema200_prev = self.ema200[-2] if len(self.ema200) > 1 else ema200_val
        ema50_prev = self.ema50[-2] if len(self.ema50) > 1 else ema50_val
        ema5_prev = self.ema5[-2] if len(self.ema5) > 1 else ema5_val

        high_prev = self.data.High[-2] if len(self.data) > 1 else high_val
        low_prev = self.data.Low[-2] if len(self.data) > 1 else low_val

        wick_touch_long = low_val <= ema50_val and close_val > ema50_val and close_val > ema200_val
        wick_touch_short = high_val >= ema50_val and close_val < ema50_val and close_val < ema200_val

        if wick_touch_long:
            self.wicked_long = True
            self.wicked_short = False

        if wick_touch_short:
            self.wicked_short = True
            self.wicked_long = False

        prev_candle_away_long = high_prev < ema5_prev
        prev_candle_away_short = low_prev > ema5_prev

        crosses_5_up = crossover(self.close_data[:idx+1], self.ema5[:idx+1])
        crosses_5_down = crossover(self.ema5[:idx+1], self.close_data[:idx+1])

        long_signal = (self.wicked_long and prev_candle_away_long and crosses_5_up
                      and close_val > ema200_val)
        short_signal = (self.wicked_short and prev_candle_away_short and crosses_5_down
                       and close_val < ema200_val)

        if long_signal:
            self.wicked_long = False
            if not self.position:
                sl_price = open_val
                tp_price = close_val + abs(close_val - sl_price) * self.rr_ratio
                self.buy()
                self.in_position = True

        if short_signal:
            self.wicked_short = False
            if not self.position:
                sl_price = open_val
                tp_price = close_val - abs(close_val - sl_price) * self.rr_ratio
                self.sell()
                self.in_position = True

        if self.position:
            if self.position.is_long:
                if close_val < self.position.open_price * 0.95:
                    self.position.close()
                    self.in_position = False
            elif self.position.is_short:
                if close_val > self.position.open_price * 1.05:
                    self.position.close()
                    self.in_position = False


