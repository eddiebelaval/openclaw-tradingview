class TvStrategy(Strategy):
    ema_len = 9

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Daily 9 EMA (using current timeframe as proxy for daily)
        self.ema_d = self.I(lambda x: pta.ema(x, length=self.ema_len), close)
        
        # For Weekly and Monthly EMAs, we'll use the daily EMA as approximations
        # In a real scenario with MTF data, these would come from different timeframes
        # Using a longer EMA as proxy for weekly/monthly
        self.ema_w = self.I(lambda x: pta.ema(x, length=self.ema_len * 5), close)
        self.ema_m = self.I(lambda x: pta.ema(x, length=self.ema_len * 20), close)
        
        # Previous 1H candle highs and lows for Fibonacci calculation
        self.prev_high = self.I(lambda x: x.shift(1), high)
        self.prev_low = self.I(lambda x: x.shift(1), low)

    def next(self):
        # Skip if indicators are not yet calculated
        if np.isnan(self.ema_d[-1]) or np.isnan(self.ema_w[-1]) or np.isnan(self.ema_m[-1]):
            return
        
        close_curr = self.data.Close[-1]
        close_prev = self.data.Close[-2] if len(self.data.Close) > 1 else close_curr
        
        # Fibonacci 0.618 Exit Calculation (Previous candle)
        prev_h = self.prev_high[-1] if not np.isnan(self.prev_high[-1]) else self.data.High[-2]
        prev_l = self.prev_low[-1] if not np.isnan(self.prev_low[-1]) else self.data.Low[-2]
        fib_range = prev_h - prev_l
        fib_exit_long = prev_l + (fib_range * 0.382)
        fib_exit_short = prev_h - (fib_range * 0.382)
        
        # Entry Conditions
        long_condition = (close_curr > self.ema_d[-1] and 
                         close_prev > self.ema_d[-2] and 
                         self.position.size == 0)
        
        short_condition = (close_curr < self.ema_d[-1] and 
                          close_prev < self.ema_d[-2] and 
                          self.position.size == 0)
        
