import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    tolerance = 0.7
    swing_period = 12
    use_ema = True
    len9 = 9
    len18 = 18
    len27 = 27
    len50 = 50

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate moving averages
        if self.use_ema:
            self.ma9 = self.I(pta.ema, close, length=self.len9)
            self.ma18 = self.I(pta.ema, close, length=self.len18)
            self.ma27 = self.I(pta.ema, close, length=self.len27)
            self.ma50 = self.I(pta.ema, close, length=self.len50)
        else:
            self.ma9 = self.I(pta.sma, close, length=self.len9)
            self.ma18 = self.I(pta.sma, close, length=self.len18)
            self.ma27 = self.I(pta.sma, close, length=self.len27)
            self.ma50 = self.I(pta.sma, close, length=self.len50)
        
        # Store raw data for CISD calculation
        self.close_data = close
        self.open_data = open_
        self.high_data = high
        self.low_data = low
        
        # CISD state tracking
        self.bear_active = False
        self.bull_active = False
        self.bear_level = np.nan
        self.bull_level = np.nan
        self.bear_highest = np.nan
        self.bull_highest = np.nan
        self.bear_top = np.nan
        self.bull_bottom = np.nan
        
        self.cisd = 0
        self.trend = 0

    def next(self):
        if len(self) < 2:
            return
        
        idx = len(self) - 1
        
        # Get current and previous values
        curr_close = self.close_data.iloc[idx]
        curr_open = self.open_data.iloc[idx]
        prev_close = self.close_data.iloc[idx - 1]
        prev_open = self.open_data.iloc[idx - 1]
        
        # Check MA stack conditions
        ma9_val = self.ma9[-1]
        ma18_val = self.ma18[-1]
        ma27_val = self.ma27[-1]
        ma50_val = self.ma50[-1]
        
        stack_long = ma9_val > ma18_val and ma18_val >= ma27_val and ma27_val >= ma50_val
        stack_short = ma9_val < ma18_val and ma18_val <= ma27_val and ma27_val <= ma50_val
        chop = not stack_long and not stack_short
        
        # CISD mini state machine
        self.cisd = 0
        
        # Potential bearish CISD start: red -> green flip
        if prev_close < prev_open and curr_close > curr_open and not self.bear_active:
            self.bear_active = True
            self.bear_level = curr_open
            self.bear_highest = curr_close
            self.bear_top = np.nan
        
        # Potential bullish CISD start: green -> red flip
        if prev_close > prev_open and curr_close < curr_open and not self.bull_active:
            self.bull_active = True
            self.bull_level = curr_open
            self.bull_lowest = curr_close
            self.bull_bottom = np.nan
        
        # Bear tracking forward
        if self.bear_active:
            self.bear_highest = max(self.bear_highest, curr_close)
            if np.isnan(self.bear_top) and curr_close < curr_open:
                self.bear_top = curr_open
            if curr_close < self.bear_level and not np.isnan(self.bear_top):
                denom = self.bear_top - self.bear_level
                if denom != 0 and (self.bear_highest - self.bear_level) / denom > self.tolerance:
                    self.cisd = 1
                self.bear_active = False
        
        # Bull tracking forward
        if self.bull_active:
            self.bull_lowest = min(self.bull_lowest, curr_close)
            if np.isnan(self.bull_bottom) and curr_close > curr_open:
                self.bull_bottom = curr_open
            if curr_close > self.bull_level and not np.isnan(self.bull_bottom):
                denom = self.bull_level - self.bull_bottom
                if denom != 0 and (self.bull_level - self.bull_lowest) / denom > self.tolerance:
                    self.cisd = 2
                self.bull_active = False
        
        # Determine trend
        if self.cisd == 2:
            self.trend = 1
        elif self.cisd == 1:
            self.trend = -1
        else:
            self.trend = 0
        
        # Determine final signal
        signal = 0
        if stack_long:
            signal = 1
        elif stack_short:
            signal = -1
        elif self.trend > 0:
            signal = 1
        elif self.trend < 0:
            signal = -1
        
        # Simple trading logic
        if signal == 1 and not self.position:
            self.buy()
        elif signal == -1 and self.position:
            self.sell()


