import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema8 = self.I(pta.ema, close, length=8)
        self.ema9 = self.I(pta.ema, close, length=9)
        self.ema10 = self.I(pta.ema, close, length=10)
        self.ema19 = self.I(pta.ema, close, length=19)
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema21 = self.I(pta.ema, close, length=21)
        self.ema200 = self.I(pta.ema, close, length=200)
        
        self.pdh = np.full(len(self.data), np.nan)
        self.pdl = np.full(len(self.data), np.nan)
        self.pmh = np.full(len(self.data), np.nan)
        self.pml = np.full(len(self.data), np.nan)
        
        self.session_high = np.nan
        self.session_low = np.nan
        self.pm_session_high = np.nan
        self.pm_session_low = np.nan
        
        self.long_count = 0
        self.short_count = 0
        self.prev_bullish_setup = False
        self.prev_bearish_setup = False
        self.ema_entry_high = np.nan
        self.ema_entry_low = np.nan
        self.ema_tb = False
        self.ema_tbr = False
        
        self.trail_long = np.nan
        self.trail_short = np.nan
        self.use_trail_sl = False
        self.candle_close_pct = 0.5

    def next(self):
        idx = len(self.data) - 1
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        is_hour = self.data.index[-1].hour
        is_minute = self.data.index[-1].minute
        
        is_regular = 9 <= is_hour < 16
        is_premarket = 4 <= is_hour < 9 or (is_hour == 9 and is_minute < 30)
        
        was_regular = len(self.data) > 1 and (9 <= self.data.index[-2].hour < 16)
        was_premarket = len(self.data) > 1 and (4 <= self.data.index[-2].hour < 9 or (self.data.index[-2].hour == 9 and self.data.index[-2].minute < 30))
        
        new_regular_day = is_regular and not was_regular
        new_pm_day = is_premarket and not was_premarket
        
        if is_regular:
            if np.isnan(self.session_high):
                self.session_high = current_high
                self.session_low = current_low
            else:
                self.session_high = max(self.session_high, current_high)
                self.session_low = min(self.session_low, current_low)
        
        if new_regular_day:
            if not np.isnan(self.session_high):
                self.pdh[idx] = self.session_high
                self.pdl[idx] = self.session_low
                if idx > 0:
                    self.pdh[idx] = self.pdh[idx-1] if not np.isnan(self.pdh[idx-1]) else self.session_high
                    self.pdl[idx] = self.pdl[idx-1] if not np.isnan(self.pdl[idx-1]) else self.session_low
            self.session_high = current_high
            self.session_low = current_low
        elif idx > 0:
            self.pdh[idx] = self.pdh[idx-1]
            self.pdl[idx] = self.pdl[idx-1]
        
        if is_premarket:
            if np.isnan(self.pm_session_high):
                self.pm_session_high = current_high
                self.pm_session_low = current_low
            else:
                self.pm_session_high = max(self.pm_session_high, current_high)
                self.pm_session_low = min(self.pm_session_low, current_low)
        
        if new_pm_day:
            self.pm_session_high = current_high
            self.pm_session_low = current_low
        
        if new_regular_day:
            if not np.isnan(self.pm_session_high):
                self.pmh[idx] = self.pm_session_high
                self.pml[idx] = self.pm_session_low
            if idx > 0:
                self.pmh[idx] = self.pmh[idx-1] if not np.isnan(self.pmh[idx-1]) else self.pmh[idx]
                self.pml[idx] = self.pml[idx-1] if not np.isnan(self.pml[idx-1]) else self.pml[idx]
        elif idx > 0:
            self.pmh[idx] = self.pmh[idx-1]
            self.pml[idx] = self.pml[idx-1]
        
        pdh_val = self.pdh[idx] if not np.isnan(self.pdh[idx]) else np.nan
        pdl_val = self.pdl[idx] if not np.isnan(self.pdl[idx]) else np.nan
        pmh_val = self.pmh[idx] if not np.isnan(self.pmh[idx]) else np.nan
        pml_val = self.pml[idx] if not np.isnan(self.pml[idx]) else np.nan
        
        above_pdh_and_pmh = not np.isnan(pdh_val) and not np.isnan(pmh_val) and current_close > pdh_val and current_close > pmh_val
        below_pdl_and_pml = not np.isnan(pdl_val) and not np.isnan(pml_val) and current_close < pdl_val and current_close < pml_val
        between_pdh_and_pmh = not np.isnan(pdh_val) and not np.isnan(pmh_val) and current_close > pmh_val and current_close < pdh_val
        between_pdl_and_pml = not np.isnan(pdl_val) and not np.isnan(pml_val) and current_close < pml_val and current_close > pdl_val
        
        valid_levels = not np.isnan(pdh_val) and not np.isnan(pdl_val) and not np.isnan(pmh_val) and not np.isnan(pml_val)
        
        bullish_outside = valid_levels and is_regular and current_close > pdh_val and current_close > pmh_val
        bearish_outside = valid_levels and is_regular and current_close < pdl_val and current_close < pml_val
        bullish_inside = valid_levels and is_regular and current_close > pmh_val and current_close < pdh_val and current_close > pdl_val
        bearish_inside = valid_levels and is_regular and current_close < pml_val and current_close > pdl_val and current_close < pdh_val
        
        is_bullish_setup = bullish_outside or bullish_inside
        is_bearish_setup = bearish_outside or bearish_inside
        
        if is_bullish_setup and not self.prev_bullish_setup:
            self.long_count = 0
        if is_bearish_setup and not self.prev_bearish_setup:
            self.short_count = 0
        
        self.prev_bullish_setup = is_bullish_setup
        self.prev_bearish_setup = is_bearish_setup
        
        ema8_top = max(self.ema8[-1] if not np.isnan(self.ema8[-1]) else -np.inf,
                       self.ema9[-1] if not np.isnan(self.ema9[-1]) else -np.inf,
                       self.ema10[-1] if not np.isnan(self.ema10[-1]) else -np.inf)
        ema8_bottom = min(self.ema8[-1] if not np.isnan(self.ema8[-1]) else np.inf,
                          self.ema9[-1] if not np.isnan(self.ema9[-1]) else np.inf,
                          self.ema10[-1] if not np.isnan(self.ema10[-1]) else np.inf)
        
        buffer = current_close * 0.001
        
        bullish_level_retest = (bullish_outside and ((abs(current_low - pdh_val) < buffer * 5) or (abs(current_low - pmh_val) < buffer * 5))) or \
                               (bullish_inside and (abs(current_low - pmh_val) < buffer * 5))
        
        bearish_level_retest = (bearish_outside and ((abs(current_high - pdl_val) < buffer * 5) or (abs(current_high - pml_val) < buffer * 5))) or \
                               (bearish_inside and (abs(current_high - pml_val) < buffer * 5))
        
        touched_ema_bull = is_bullish_setup and current_low <= ema8_top and current_low >= ema8_bottom
        touched_ema_bear = is_bearish_setup and current_high >= ema8_bottom and current_high <= ema8_top
        
        if touched_ema_bull and not self.ema_tb:
            self.ema_tb = True
            self.ema_entry_high = current_high
        if touched_ema_bear and not self.ema_tbr:
            self.ema_tbr = True
            self.ema_entry_low = current_low
        
        bullish_ema_confirm = self.ema_tb and current_close > self.ema_entry_high
        bearish_ema_confirm = self.ema_tbr and current_close < self.ema_entry_low
        
        if not is_bullish_setup:
            self.ema_tb = False
            self.ema_entry_high = np.nan
        if not is_bearish_setup:
            self.ema_tbr = False
            self.ema_entry_low = np.nan
        
        long_l = bullish_level_retest
        long_e = bullish_ema_confirm
        short_l = bearish_level_retest
        short_e = bearish_ema_confirm
        
        raw_long = long_l or long_e
        raw_short = short_l or short_e
        
        long_sig = raw_long and self.long_count < 3
        short_sig = raw_short and self.short_count < 3
        
        if long_sig:
            self.long_count += 1
        if short_sig:
            self.short_count += 1
        
        if self.use_trail_sl:
            if long_sig:
                self.trail_long = current_low * (1 - self.candle_close_pct / 100)
            if self.long_count > 0 and not np.isnan(self.trail_long):
                self.trail_long = max(self.trail_long, current_low * (1 - self.candle_close_pct / 100))
            if short_sig:
                self.trail_short = current_high * (1 + self.candle_close_pct / 100)
            if self.short_count > 0 and not np.isnan(self.trail_short):
                self.trail_short = min(self.trail_short, current_high * (1 + self.candle_close_pct / 100))
            if self.long_count == 0:
                self.trail_long = np.nan
            if self.short_count == 0:
                self.trail_short = np.nan
            
            if not np.isnan(self.trail_long) and current_low <= self.trail_long:
                self.sell()
                self.long_count = 0
                self.trail_long = np.nan
            if not np.isnan(self.trail_short) and current_high >= self.trail_short:
                self.buy()
                self.short_count = 0
                self.trail_short = np.nan
        
        if long_sig:
            self.buy()
        elif short_sig:
            self.sell()