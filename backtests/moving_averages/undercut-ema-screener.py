import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_length = 10
    volume_multiplier = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        
        # Calculate EMA
        self.ema = self.I(pta.ema, close, length=self.ema_length)
        
        # Calculate volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=20)
        
        # Store series for conditions
        self.low_series = low
        self.open_series = open_
        self.close_series = close
        self.volume_series = volume
        
        self.in_position = False

    def next(self):
        if len(self) < max(self.ema_length, 20):
            return
        
        current_idx = len(self) - 1
        
        low_val = self.low_series.iloc[current_idx]
        close_val = self.close_series.iloc[current_idx]
        open_val = self.open_series.iloc[current_idx]
        ema_val = self.ema[-1]
        volume_val = self.volume_series.iloc[current_idx]
        vol_sma_val = self.vol_sma[-1]
        
        # Undercut condition: Low dips below EMA, but close reclaims it (green candle)
        undercut = (low_val < ema_val) and (close_val > ema_val) and (close_val > open_val)
        
        # Volume surge condition
        volume_surge = volume_val > vol_sma_val * self.volume_multiplier
        
        # Combined signal
        signal = undercut and volume_surge
        
        if signal and not self.position:
            self.buy()
            self.in_position = True
        elif self.position and not signal:
            self.sell()
            self.in_position = False