import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA 1 (Micro) Parameters
    ema_len = 200
    slope_bars = 10
    flat_thresh = 0.05
    
    # EMA 2 (Macro) Parameters
    ema2_len = 200
    
    # Magnitude Filter Parameters
    use_magnitude_filter = False
    magnitude_threshold = 0.35
    magnitude_target = "Both EMAs"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMA 1 (Micro)
        ema1 = self.I(pta.ema, close, length=self.ema_len)
        
        # Calculate slope for EMA 1
        def calc_slope1(close_series):
            ema1_series = pta.ema(close_series, length=self.ema_len)
            if ema1_series is None:
                return pd.Series(0, index=close_series.index)
            slope = ((ema1_series - ema1_series.shift(self.slope_bars)) / close_series.clip(lower=1e-10)) * 100.0
            return slope
        
        self.slope1 = self.I(calc_slope1, close)
        
        # Calculate EMA 2 (Macro)
        ema2 = self.I(pta.ema, close, length=self.ema2_len)
        
        # Calculate slope for EMA 2
        def calc_slope2(close_series):
            ema2_series = pta.ema(close_series, length=self.ema2_len)
            if ema2_series is None:
                return pd.Series(0, index=close_series.index)
            slope = ((ema2_series - ema2_series.shift(self.slope_bars)) / close_series.clip(lower=1e-10)) * 100.0
            return slope
        
        self.slope2 = self.I(calc_slope2, close)
        
        # State classification helpers
        self.prev_state1 = None
        self.prev_state2 = None

    def next(self):
        # Current slopes
        slope1 = self.slope1[-1] if len(self.slope1) > 0 else 0
        slope2 = self.slope2[-1] if len(self.slope2) > 0 else 0
        
        # Classify current state for EMA 1
        is_flat1 = abs(slope1) < self.flat_thresh
        is_bull1 = not is_flat1 and slope1 > 0
        is_bear1 = not is_flat1 and slope1 < 0
        
        # Classify current state for EMA 2
        is_flat2 = abs(slope2) < self.flat_thresh
        is_bull2 = not is_flat2 and slope2 > 0
        is_bear2 = not is_flat2 and slope2 < 0
        
        # Previous state
        if len(self.slope1) > 1:
            prev_slope1 = self.slope1[-2]
            prev_is_flat1 = abs(prev_slope1) < self.flat_thresh
            prev_is_bull1 = not prev_is_flat1 and prev_slope1 > 0
            prev_is_bear1 = not prev_is_flat1 and prev_slope1 < 0
        else:
            prev_is_bull1 = False
            prev_is_bear1 = False
            prev_is_flat1 = False
        
        if len(self.slope2) > 1:
            prev_slope2 = self.slope2[-2]
            prev_is_flat2 = abs(prev_slope2) < self.flat_thresh
            prev_is_bull2 = not prev_is_flat2 and prev_slope2 > 0
            prev_is_bear2 = not prev_is_flat2 and prev_slope2 < 0
        else:
            prev_is_bull2 = False
            prev_is_bear2 = False
            prev_is_flat2 = False
        
        # Detect transitions
        trans_e1_to_bull = is_bull1 and not prev_is_bull1
        trans_e1_to_bear = is_bear1 and not prev_is_bear1
        trans_e2_to_bull = is_bull2 and not prev_is_bull2
        trans_e2_to_bear = is_bear2 and not prev_is_bear2
        
        # Magnitude filter logic
        ema1_meets_magnitude = abs(slope1) >= self.magnitude_threshold
        ema2_meets_magnitude = abs(slope2) >= self.magnitude_threshold
        
        if self.magnitude_target == "EMA 1 Only":
            magnitude_filter_passes = ema1_meets_magnitude
        elif self.magnitude_target == "EMA 2 Only":
            magnitude_filter_passes = ema2_meets_magnitude
        elif self.magnitude_target == "Both EMAs":
            magnitude_filter_passes = ema1_meets_magnitude and ema2_meets_magnitude
        elif self.magnitude_target == "Either EMA":
            magnitude_filter_passes = ema1_meets_magnitude or ema2_meets_magnitude
        else:
            magnitude_filter_passes = True
        
        magnitude_gate = (not self.use_magnitude_filter) or magnitude_filter_passes
        
        # Confluence signals
        micro_buy_signal = trans_e1_to_bull and is_bull2 and magnitude_gate
        macro_buy_signal = trans_e2_to_bull and is_bull1 and magnitude_gate
        micro_sell_signal = trans_e1_to_bear and is_bear2 and magnitude_gate
        macro_sell_signal = trans_e2_to_bear and is_bear1 and magnitude_gate
        
        buy_signal = micro_buy_signal or macro_buy_signal
        sell_signal = micro_sell_signal or macro_sell_signal
        
        # Trading logic
        if buy_signal:
            if not self.position:
                self.buy()
        elif sell_signal:
            if self.position:
                self.sell()