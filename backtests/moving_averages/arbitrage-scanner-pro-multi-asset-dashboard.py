import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    rawStLength = 5
    rawStFactor = 1.0
    rawEmaLength = 20
    rawRsiLength = 14
    divider = 4.0  # Simulate 15s mode

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate effective lengths with divider
        self.effStLength = max(1, int(self.rawStLength / self.divider))
        self.effEmaLength = max(1, int(self.rawEmaLength / self.divider))
        self.effRsiLength = max(2, int(self.rawRsiLength / self.divider))

        # Asset A (Main) Indicators
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.effStLength))

        # Manual Supertrend calculation
        def calc_supertrend():
            hl2 = (high + low) / 2
            atr_val = pta.atr(high, low, close, length=self.effStLength)
            if atr_val is None:
                return pd.Series(0, index=close.index), pd.Series(-1, index=close.index)
            basic_ub = hl2 + self.rawStFactor * atr_val
            basic_lb = hl2 - self.rawStFactor * atr_val
            final_ub = basic_ub.copy()
            final_lb = basic_lb.copy()
            for i in range(1, len(basic_ub)):
                final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
            st_val = pd.Series(index=close.index, dtype=float)
            st_dir = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if i == 0:
                    st_val.iloc[i] = final_ub.iloc[i]
                    st_dir.iloc[i] = -1
                else:
                    if st_dir.iloc[i-1] == -1:
                        st_val.iloc[i] = final_ub.iloc[i]
                        st_dir.iloc[i] = -1 if close.iloc[i] > final_lb.iloc[i] else 1
                    else:
                        st_val.iloc[i] = final_lb.iloc[i]
                        st_dir.iloc[i] = 1 if close.iloc[i] < final_ub.iloc[i] else -1
            return st_val, st_dir

        st_result = calc_supertrend()
        self.st_val = self.I(lambda: st_result[0])
        self.st_dir = self.I(lambda: st_result[1])

        self.ema_high = self.I(lambda: pta.ema(high, length=self.effEmaLength))
        self.ema_low = self.I(lambda: pta.ema(low, length=self.effEmaLength))
        self.rsi_val = self.I(lambda: pta.rsi(close, length=self.effRsiLength) or pd.Series(50, index=close.index))
        self.rsi_ma = self.I(lambda: pta.sma(pta.rsi(close, length=self.effRsiLength) or pd.Series(50, index=close.index), length=14))

    def next(self):
        if len(self.data) < max(self.effStLength, self.effEmaLength, self.effRsiLength):
            return

        # Current values
        is_green = self.st_dir[-1] == -1
        is_red = self.st_dir[-1] == 1
        price_above = self.data.Close[-1] > self.ema_high[-1]
        price_below = self.data.Close[-1] < self.ema_low[-1]
        st_inside = self.st_val[-1] < self.ema_high[-1] and self.st_val[-1] > self.ema_low[-1]

        rsi_val_current = self.rsi_val[-1] if self.rsi_val[-1] is not None else 50
        rsi_ma_current = self.rsi_ma[-1] if self.rsi_ma[-1] is not None else 50

        # Buy condition
        buy_cond = is_green and price_above and rsi_val_current > 60 and rsi_val_current > rsi_ma_current and not st_inside

        # Sell condition
        sell_cond = is_red and price_below and not st_inside

        # Previous values for signal detection
        prev_is_green = self.st_dir[-2] == -1 if len(self.data) > 1 else is_green
        prev_buy_cond = prev_is_green and (self.data.Close[-2] > self.ema_high[-2]) and not st_inside

        prev_is_red = self.st_dir[-2] == 1 if len(self.data) > 1 else is_red
        prev_sell_cond = prev_is_red and (self.data.Close[-2] < self.ema_low[-2]) and not st_inside

        buy_signal = buy_cond and not prev_buy_cond
        sell_signal = sell_cond and not prev_sell_cond

        # Execute trades
        if buy_signal:
            if not self.position:
                self.buy()
        elif sell_signal:
            if self.position:
                self.sell()