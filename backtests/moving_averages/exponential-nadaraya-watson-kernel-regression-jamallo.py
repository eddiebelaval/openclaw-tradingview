    def _calc_ha_close(self, open_, high, low, close):
        return (open_ + high + low + close) / 4.0

    def _calc_ha_open(self, open_, close):
        ha_open = pd.Series(index=open_.index, dtype=float)
        ha_open.iloc[0] = (open_.iloc[0] + close.iloc[0]) / 2.0
        for i in range(1, len(open_)):
            ha_open.iloc[i] = (ha_open.iloc[i-1] + self.ha_close.iloc[i-1]) / 2.0
        return ha_open

    def _calc_ha_price(self, ha_open, high, low, ha_close):
        ha_high = np.maximum(high, np.maximum(ha_open, ha_close))
        ha_low = np.minimum(low, np.minimum(ha_open, ha_close))
        return (ha_open + ha_high + ha_low + ha_close) / 4.0

    def _calc_vervoort(self, ha_price, atr, multiplier):
        v_stop = pd.Series(index=ha_price.index, dtype=float)
        trend_is_up = pd.Series(index=ha_price.index, dtype=bool)
        
        loss = multiplier * atr
        
        v_stop.iloc[0] = ha_price.iloc[0] - loss.iloc[0]
        trend_is_up.iloc[0] = True
        
        for i in range(1, len(ha_price)):
            prev_v_stop = v_stop.iloc[i-1]
            trend_is_up_val = ha_price.iloc[i] > prev_v_stop
            
            if trend_is_up_val:
                v_stop.iloc[i] = max(prev_v_stop, ha_price.iloc[i] - loss.iloc[i])
            else:
                v_stop.iloc[i] = min(prev_v_stop, ha_price.iloc[i] + loss.iloc[i])
            
            if trend_is_up_val and ha_price.iloc[i] < v_stop.iloc[i]:
                trend_is_up_val = False
                v_stop.iloc[i] = ha_price.iloc[i] + loss.iloc[i]
            elif not trend_is_up_val and ha_price.iloc[i] > v_stop.iloc[i]:
                trend_is_up_val = True
                v_stop.iloc[i] = ha_price.iloc[i] - loss.iloc[i]
            
            trend_is_up.iloc[i] = trend_is_up_val
        
        return v_stop

