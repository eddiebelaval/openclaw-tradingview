    def _calc_enw_kernel(self, src, kernel_len, alpha):
        result = pd.Series(index=src.index, dtype=float)
        center = kernel_len / 2.0
        
        for bar in range(len(src)):
            if bar < kernel_len - 1:
                result.iloc[bar] = src.iloc[bar]
            else:
                sum_val = 0.0
                weight_sum = 0.0
                
                for i in range(kernel_len):
                    x = float(i)
                    price = src.iloc[bar - (kernel_len - 1 - i)]
                    
                    dist = abs(x - center)
                    recency_weight = np.exp(-alpha * (kernel_len - 1 - i) / kernel_len)
                    local_weight = np.exp(-((dist / (kernel_len / 3)) ** 2))
                    weight = recency_weight * local_weight
                    
                    sum_val += price * weight
                    weight_sum += weight
                
                result.iloc[bar] = sum_val / weight_sum if weight_sum > 0 else src.iloc[bar]
        
        return result

    def _calc_wavelet_volatility(self, price, baseline, kernel_len, alpha):
        deviation = np.abs(price - baseline)
        smoothed_vol = self._calc_enw_kernel(deviation, kernel_len, alpha)
        return smoothed_vol

