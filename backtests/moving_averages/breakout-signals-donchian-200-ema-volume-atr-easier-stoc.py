import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Breakout settings
    len_donchian = 20
    use_close_levels = False
    atr_len = 14
    atr_mult = 0.10
    confirm_close = True
    cooldown_bars = 0
    
    # Volume filter
    use_vol_filter = False
    vol_len = 30
    vol_mult = 1.2
    
    # EMA trend filter
    use_trend_filter = False
    ema_len = 200
    
    # Stop settings
    stop_mode = "Fixed From Entry"
    stop_atr_mult = 2.0
    stop_lookback = 22

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Donchian levels (using previous bars)
        if self.use_close_levels:
            src_high = close.shift(1)
            src_low = close.shift(1)
        else:
            src_high = high.shift(1)
            src_low = low.shift(1)
        
        self.upper = self.I(lambda: src_high.rolling(window=self.len_donchian).max())
        self.lower = self.I(lambda: src_low.rolling(window=self.len_donchian).min())
        
        # Volume filter
        if self.use_vol_filter:
            vol_sma = self.I(pta.sma, volume, length=self.vol_len)
            self.vol_ok = self.I(lambda: volume > vol_sma * self.vol_mult)
        else:
            self.vol_ok = self.I(lambda: pd.Series(True, index=close.index))
        
        # EMA trend filter
        if self.use_trend_filter:
            self.ema = self.I(pta.ema, close, length=self.ema_len)
        else:
            self.ema = self.I(lambda: pd.Series(0, index=close.index))
        
        # Track last signal bar for cooldown
        self.last_signal_bar = -np.inf
        
    def next(self):
        if len(self.data) < self.len_donchian + 1:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        atr_val = self.atr[-1]
        upper_val = self.upper[-1]
        lower_val = self.lower[-1]
        
        if atr_val is None or np.isnan(atr_val):
            return
        if upper_val is None or np.isnan(upper_val):
            return
        if lower_val is None or np.isnan(lower_val):
            return
        
        buf = atr_val * self.atr_mult
        
        # Check cooldown
        current_bar = len(self.data) - 1
        can_signal = (current_bar - self.last_signal_bar) > self.cooldown_bars
        
        # Volume filter
        vol_ok = self.vol_ok[-1] if isinstance(self.vol_ok[-1], (bool, np.bool_)) else True
        
        # Trend filter
        if self.use_trend_filter:
            trend_ok_long = close > self.ema[-1]
            trend_ok_short = close < self.ema[-1]
        else:
            trend_ok_long = True
            trend_ok_short = True
        
        # Breakout conditions
        if self.confirm_close:
            long_break = close > upper_val + buf
            short_break = close < lower_val - buf
        else:
            long_break = high > upper_val + buf
            short_break = low < lower_val - buf
        
        # Buy signal
        buy_signal = can_signal and vol_ok and trend_ok_long and long_break
        
        # Sell signal
        sell_signal = can_signal and vol_ok and trend_ok_short and short_break
        
        # Update last signal bar
        if buy_signal or sell_signal:
            self.last_signal_bar = current_bar
        
        # Execute trades
        if buy_signal:
            if not self.position:
                # Calculate stop price
                if self.stop_mode == "Chandelier":
                    stop_price = max(self.data.High[-self.stop_lookback:]) - self.stop_atr_mult * atr_val
                else:
                    stop_price = close - self.stop_atr_mult * atr_val
                
                self.buy()
                self.position.stop_loss = stop_price
        
        elif sell_signal:
            if self.position:
                # Calculate stop price
                if self.stop_mode == "Chandelier":
                    stop_price = min(self.data.Low[-self.stop_lookback:]) + self.stop_atr_mult * atr_val
                else:
                    stop_price = close + self.stop_atr_mult * atr_val
                
                self.sell()
                self.position.stop_loss = stop_price
        
        # Check stops
        if self.position:
            if self.position.is_long and low < self.position.stop_loss:
                self.sell()
            elif self.position.is_short and high > self.position.stop_loss:
                self.buy()


