import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 9
    emaSlowLen = 18
    slPercent = 1.5
    tpPercent = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)

    def next(self):
        if len(self.data) < max(self.emaFastLen, self.emaSlowLen) + 1:
            return

        if crossover(self.emaFast, self.emaSlow):
            if not self.position:
                self.buy()
        
        elif crossover(self.emaSlow, self.emaFast):
            if self.position:
                self.position.close()