import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters from the Pine Script
    use_time_filter = True
    use_htf_compression = True
    dist_threshold_htf = 3.0
    slope_bars_htf = 5
    slope_threshold_htf = 1.0
    use_ma_compression = True
    dist_threshold_ma = 1.5
    use_atr_spike_filter = True
    atr_len = 14
    spike_mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate SMAs
        self.sma89 = self.I(pta.sma, close, length=89)
        self.sma200 = self.I(pta.sma, close, length=200)
        self.sma5 = self.I(pta.sma, close, length=5)
        self.sma50 = self.I(pta.sma, close, length=50)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Track previous values for slope calculation
        self.sma89_history = []
        self.sma200_history = []

    def next(self):
        # Store history for slope calculation
        if len(self.sma89) > 0:
            self.sma89_history.append(self.sma89[-1])
        if len(self.sma200) > 0:
            self.sma200_history.append(self.sma200[-1])
        
        # Ensure we have enough data
        if len(self) < max(self.slope_bars_htf + 1, 2):
            return
        
        # Get current values
        sma89_current = self.sma89[-1]
        sma200_current = self.sma200[-1]
        sma5_current = self.sma5[-1]
        sma50_current = self.sma50[-1]
        
        # Get previous values for slope calculation
        sma89_prev = self.sma89_history[-min(self.slope_bars_htf + 1, len(self.sma89_history))] if len(self.sma89_history) >= self.slope_bars_htf + 1 else sma89_current
        sma200_prev = self.sma200_history[-min(self.slope_bars_htf + 1, len(self.sma200_history))] if len(self.sma200_history) >= self.slope_bars_htf + 1 else sma200_current
        
        # Get previous candle range for ATR spike filter
        if len(self) >= 2:
            prev_high = self.data.High[-2]
            prev_low = self.data.Low[-2]
            prev_range = prev_high - prev_low
        else:
            prev_range = 0
        
        # ===== TIME FILTER (UTC+8 / Singapore) =====
        # Simplified: block during specific hours
        # For backtesting, we'll use a simplified version
        current_time = self.data.index[-1]
        hour = current_time.hour
        
        # Block during: 04:00-07:00, 08:30-09:15, 16:00-20:45
        time_blocked = False
        if self.use_time_filter:
            time_blocked = (4 <= hour < 7) or (8 <= hour < 9) or (16 <= hour < 21)
        time_allowed = not time_blocked
        
        # ===== SMA89 / SMA200 COMPRESSION + FLAT FILTER =====
        ma_close_together_htf = abs(sma89_current - sma200_current) < self.dist_threshold_htf
        sma89_flat_htf = abs(sma89_current - sma89_prev) < self.slope_threshold_htf
        sma200_flat_htf = abs(sma200_current - sma200_prev) < self.slope_threshold_htf
        
        htf_blocked = False
        if self.use_htf_compression:
            htf_blocked = ma_close_together_htf and sma89_flat_htf and sma200_flat_htf
        htf_allowed = not htf_blocked
        
        # ===== SMA5 / SMA50 COMPRESSION FILTER =====
        ma_distance = abs(sma5_current - sma50_current)
        
        ma_compression_blocked = False
        if self.use_ma_compression:
            ma_compression_blocked = ma_distance < self.dist_threshold_ma
        ma_compression_allowed = not ma_compression_blocked
        
        # ===== ATR SPIKE FILTER =====
        atr_current = self.atr[-1] if len(self.atr) > 0 else 0
        
        atr_spike_blocked = False
        if self.use_atr_spike_filter and atr_current > 0:
            atr_spike_blocked = prev_range > atr_current * self.spike_mult
        atr_spike_allowed = not atr_spike_blocked
        
        # ===== FINAL FILTERS =====
        buy_allowed = time_allowed and htf_allowed and ma_compression_allowed and atr_spike_allowed
        sell_allowed = time_allowed and htf_allowed and ma_compression_allowed and atr_spike_allowed
        
        # ===== SIMPLE TRADING LOGIC =====
        # Buy when SMA5 crosses above SMA50 and all filters allow
        # Sell when SMA5 crosses below SMA50 and all filters allow
        
        if buy_allowed and len(self.sma5) >= 2 and len(self.sma50) >= 2:
            if crossover(self.sma5, self.sma50):
                if not self.position:
                    self.buy()
        
        if sell_allowed and len(self.sma5) >= 2 and len(self.sma50) >= 2:
            if crossover(self.sma50, self.sma5):
                if self.position:
                    self.position.close()


