import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # SMA parameters
    len1 = 50
    len2 = 100
    len3 = 200
    
    # EMA parameters
    len4 = 50
    len5 = 100
    len6 = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate SMAs
        self.sma1 = self.I(pta.sma, close, length=self.len1)
        self.sma2 = self.I(pta.sma, close, length=self.len2)
        self.sma3 = self.I(pta.sma, close, length=self.len3)
        
        # Calculate EMAs
        self.ema1 = self.I(pta.ema, close, length=self.len4)
        self.ema2 = self.I(pta.ema, close, length=self.len5)
        self.ema3 = self.I(pta.ema, close, length=self.len6)

    def next(self):
        # Buy signal: when short-term EMA crosses above medium-term EMA and price is above long-term SMA
        if (crossover(self.ema1, self.ema2) and 
            self.data.Close[-1] > self.sma3[-1]):
            if not self.position:
                self.buy()
        
        # Sell signal: when short-term EMA crosses below medium-term EMA or price falls below long-term SMA
        elif (crossover(self.ema2, self.ema1) or 
              self.data.Close[-1] < self.sma3[-1]):
            if self.position:
                self.position.close()