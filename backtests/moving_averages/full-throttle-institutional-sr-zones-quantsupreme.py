    def _calc_z_short(self, close, mu_short, sd_short):
        if len(mu_short) == 0 or len(sd_short) == 0:
            return pd.Series(0, index=close.index)
        result = pd.Series(0.0, index=close.index)
        for i in range(len(close)):
            if sd_short[i] is not None and sd_short[i] != 0:
                result.iloc[i] = (close.iloc[i] - mu_short[i]) / sd_short[i]
            else:
                result.iloc[i] = 0.0
        return result

    def _calc_z_mid(self, close, mu_mid, sd_mid):
        if len(mu_mid) == 0 or len(sd_mid) == 0:
            return pd.Series(0, index=close.index)
        result = pd.Series(0.0, index=close.index)
        for i in range(len(close)):
            if sd_mid[i] is not None and sd_mid[i] != 0:
                result.iloc[i] = (close.iloc[i] - mu_mid[i]) / sd_mid[i]
            else:
                result.iloc[i] = 0.0
        return result

    def _calc_z_long(self, close, mu_long, sd_long):
        if len(mu_long) == 0 or len(sd_long) == 0:
            return pd.Series(0, index=close.index)
        result = pd.Series(0.0, index=close.index)
        for i in range(len(close)):
            if sd_long[i] is not None and sd_long[i] != 0:
                result.iloc[i] = (close.iloc[i] - mu_long[i]) / sd_long[i]
            else:
                result.iloc[i] = 0.0
        return result

    def _calc_vol_ratio(self, volume, vol_ma):
        if len(vol_ma) == 0:
            return pd.Series(1.0, index=volume.index)
        result = pd.Series(1.0, index=volume.index)
        for i in range(len(volume)):
            if vol_ma[i] is not None and vol_ma[i] != 0:
                result.iloc[i] = volume.iloc[i] / vol_ma[i]
            else:
                result.iloc[i] = 1.0
        return result

