class TvStrategy(Strategy):
    # Zone Parameters
    i_short_len = 13
    i_mid_len = 24
    i_long_len = 52
    i_z_s1 = 1.0
    i_z_s2 = 1.5
    i_z_s3 = 2.0
    i_atr_mult = 1.5
    i_atr_len = 14
    
    # Signal Parameters
    i_buy_z = -1.0
    i_sell_z = 1.5
    i_use_vol = True
    i_vol_mult = 1.2
    i_vol_ma = 20
