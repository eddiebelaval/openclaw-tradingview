import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    calcPeriod = 20
    riskFreeRate = 0.0
    smaLength = 20

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate daily returns
        daily_returns = close.pct_change()
        
        # Calculate the mean of daily returns
        mean_return = self.I(pta.sma, daily_returns, length=self.calcPeriod)
        
        # Calculate the standard deviation of daily returns
        std_deviation = self.I(pta.stdev, daily_returns, length=self.calcPeriod)
        
        # Calculate the Sharpe Ratio
        def calculate_sharpe():
            returns = close.pct_change()
            mean_ret = pta.sma(returns, length=self.calcPeriod)
            std_dev = pta.stdev(returns, length=self.calcPeriod)
            
            if mean_ret is None or std_dev is None:
                return pd.Series(0, index=close.index)
            
            excess_return = mean_ret - (self.riskFreeRate / 100) / self.calcPeriod
            sharpe = (excess_return / std_dev) * np.sqrt(252)
            return sharpe.fillna(0)
        
        self.sharpe_ratio = self.I(calculate_sharpe)
        
        # Calculate SMA of Sharpe Ratio
        def calculate_sharpe_sma():
            returns = close.pct_change()
            mean_ret = pta.sma(returns, length=self.calcPeriod)
            std_dev = pta.stdev(returns, length=self.calcPeriod)
            
            if mean_ret is None or std_dev is None:
                return pd.Series(0, index=close.index)
            
            excess_return = mean_ret - (self.riskFreeRate / 100) / self.calcPeriod
            sharpe = (excess_return / std_dev) * np.sqrt(252)
            sharpe_sma = pta.sma(sharpe, length=self.smaLength)
            return sharpe_sma.fillna(0)
        
        self.sharpe_sma = self.I(calculate_sharpe_sma)

    def next(self):
        # Buy when Sharpe Ratio crosses above its SMA (positive momentum)
        if crossover(self.sharpe_ratio, self.sharpe_sma):
            if not self.position:
                self.buy()
        # Sell when Sharpe Ratio crosses below its SMA (negative momentum)
        elif crossover(self.sharpe_sma, self.sharpe_ratio):
            if self.position:
                self.position.close()