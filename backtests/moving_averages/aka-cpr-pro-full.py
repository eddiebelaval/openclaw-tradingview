import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma1_len = 20
    ma1_type = "EMA"
    ma2_len = 50
    ma2_type = "EMA"
    ma3_len = 200
    ma3_type = "EMA"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Moving Averages
        if self.ma1_type == "EMA":
            self.ma1 = self.I(pta.ema, close, length=self.ma1_len)
        else:
            self.ma1 = self.I(pta.sma, close, length=self.ma1_len)

        if self.ma2_type == "EMA":
            self.ma2 = self.I(pta.ema, close, length=self.ma2_len)
        else:
            self.ma2 = self.I(pta.sma, close, length=self.ma2_len)

        if self.ma3_type == "EMA":
            self.ma3 = self.I(pta.ema, close, length=self.ma3_len)
        else:
            self.ma3 = self.I(pta.sma, close, length=self.ma3_len)

        # VWAP
        self.vwap = self.I(pta.vwap, high, low, close, volume)

    def next(self):
        # Simple trading logic based on MA crossover
        # Buy when MA1 crosses above MA2
        if crossover(self.ma1, self.ma2):
            if not self.position:
                self.buy()
        # Sell when MA1 crosses below MA2
        elif crossover(self.ma2, self.ma1):
            if self.position:
                self.position.close()


