import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Moving Average Settings
    fast_len = 9
    medium_len = 27
    slow_len = 200
    
    # Cross Mode
    cross_mode = "Fast"  # "Fast", "Medium", or "Slow"
    
    # Risk Settings
    risk_mode = "Percent"  # "Percent" or "ATR"
    user_sl_pct = 2.0
    user_tp_pct = 4.0
    atr_len = 14
    risk_rr = 2.0
    atr_mult = 1.5
    
    # Trade Management
    management_mode = "Basic"  # "Basic", "BreakEven", "Partial + BE", "Advanced"
    be_rr = 1.0
    partial_rr = 1.5
    partial_percent = 50
    trail_atr_mult = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Moving Averages
        self.fast_ma = self.I(pta.ema, close, length=self.fast_len)
        self.medium_ma = self.I(pta.ema, close, length=self.medium_len)
        self.slow_ma = self.I(pta.hma, close, length=self.slow_len)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Determine short and long MA based on cross mode
        if self.cross_mode == "Fast":
            self.short_ma = self.fast_ma
            self.long_ma = self.medium_ma
        elif self.cross_mode == "Medium":
            self.short_ma = self.fast_ma
            self.long_ma = self.slow_ma
        else:  # Slow
            self.short_ma = self.medium_ma
            self.long_ma = self.slow_ma
        
        # Track position state
        self.break_even_activated = False
        self.partial_taken = False

    def next(self):
        close_price = self.data.Close[-1]
        
        if len(self.data) < max(self.fast_len, self.medium_len, self.slow_len):
            return
        
        # Get current indicator values
        short_ma = self.short_ma[-1]
        long_ma = self.long_ma[-1]
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        
        # Detect crossovers
        golden = crossover(self.short_ma, self.long_ma)
        death = crossover(self.long_ma, self.short_ma)
        
        # Entry conditions
        if golden and not self.position:
            self.buy()
        elif death and not self.position:
            self.sell()
        
        # Exit logic
        if self.position:
            entry_price = self.position.open_price
            pos_size = self.position.size
            
            # Calculate SL and TP based on risk mode
            if self.risk_mode == "ATR":
                if pos_size > 0:
                    long_sl = entry_price - atr_val * self.atr_mult
                    long_tp = entry_price + atr_val * self.atr_mult * self.risk_rr
                else:
                    short_sl = entry_price + atr_val * self.atr_mult
                    short_tp = entry_price - atr_val * self.atr_mult * self.risk_rr
            else:  # Percent mode
                if pos_size > 0:
                    long_sl = entry_price * (1 - self.user_sl_pct / 100)
                    long_tp = entry_price * (1 + self.user_tp_pct / 100)
                else:
                    short_sl = entry_price * (1 + self.user_sl_pct / 100)
                    short_tp = entry_price * (1 - self.user_tp_pct / 100)
            
            # Calculate current RR
            if pos_size > 0:
                current_rr = (close_price - entry_price) / (entry_price - long_sl) if entry_price != long_sl else 0
                sl_price = long_sl
                tp_price = long_tp
            else:
                current_rr = (entry_price - close_price) / (short_sl - entry_price) if short_sl != entry_price else 0
                sl_price = short_sl
                tp_price = short_tp
            
            # Trade management
            if self.management_mode == "Basic":
                if pos_size > 0:
                    if close_price <= sl_price or close_price >= tp_price:
                        self.position.close()
                else:
                    if close_price >= sl_price or close_price <= tp_price:
                        self.position.close()
            
            elif self.management_mode == "BreakEven":
                if not self.break_even_activated and current_rr >= self.be_rr:
                    self.break_even_activated = True
                
                be_sl = entry_price if self.break_even_activated else sl_price
                
                if pos_size > 0:
                    if close_price <= be_sl or close_price >= tp_price:
                        self.position.close()
                else:
                    if close_price >= be_sl or close_price <= tp_price:
                        self.position.close()
            
            elif self.management_mode == "Partial + BE":
                if not self.partial_taken and current_rr >= self.partial_rr:
                    self.position.close(qty=pos_size * self.partial_percent / 100)
                    self.partial_taken = True
                    self.break_even_activated = True
                
                be_sl = entry_price if self.break_even_activated else sl_price
                
                if pos_size > 0:
                    if close_price <= be_sl or close_price >= tp_price:
                        self.position.close()
                else:
                    if close_price >= be_sl or close_price <= tp_price:
                        self.position.close()
            
            elif self.management_mode == "Advanced":
                if not self.partial_taken and current_rr >= self.partial_rr:
                    self.position.close(qty=pos_size * self.partial_percent / 100)
                    self.partial_taken = True
                    self.break_even_activated = True
                
                if pos_size > 0:
                    trail_sl = close_price - atr_val * self.trail_atr_mult
                    final_sl = max(entry_price, trail_sl) if self.break_even_activated else sl_price
                    if close_price <= final_sl or close_price >= tp_price:
                        self.position.close()
                else:
                    trail_sl = close_price + atr_val * self.trail_atr_mult
                    final_sl = min(entry_price, trail_sl) if self.break_even_activated else sl_price
                    if close_price >= final_sl or close_price <= tp_price:
                        self.position.close()
        else:
            self.break_even_activated = False
            self.partial_taken = False


