import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_fast_len = 9
    ema_slow_len = 21
    hma_len = 55
    rvwap_len = 75
    rvwap2_len = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hlc3 = (high + low + close) / 3

        self.ema_fast = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema_slow = self.I(pta.ema, close, length=self.ema_slow_len)
        
        def hma_calc(c):
            return pta.hma(c, length=self.hma_len)
        self.hma = self.I(hma_calc, close)

        def daily_vwap_calc(c):
            return pta.vwap(c)
        self.daily_vwap = self.I(daily_vwap_calc, close)

        def rvwap_calc(c, v, h, l):
            hlc3_val = (h + l + c) / 3
            numerator = (hlc3_val * v).rolling(window=self.rvwap_len).sum()
            denominator = v.rolling(window=self.rvwap_len).sum()
            result = numerator / denominator
            return result.fillna(method='bfill').fillna(method='ffill')
        
        self.rvwap = self.I(rvwap_calc, close, volume, high, low)

        def rvwap2_calc(c, v, h, l):
            hlc3_val = (h + l + c) / 3
            numerator = (hlc3_val * v).rolling(window=self.rvwap2_len).sum()
            denominator = v.rolling(window=self.rvwap2_len).sum()
            result = numerator / denominator
            return result.fillna(method='bfill').fillna(method='ffill')
        
        self.rvwap2 = self.I(rvwap2_calc, close, volume, high, low)

    def next(self):
        if len(self.data) < max(self.ema_fast_len, self.ema_slow_len, self.hma_len) + 10:
            return

        ema_fast_val = self.ema_fast[-1]
        ema_slow_val = self.ema_slow[-1]
        hma_val = self.hma[-1]
        close_val = self.data.Close[-1]
        daily_vwap_val = self.daily_vwap[-1]
        rvwap_val = self.rvwap[-1]
        rvwap2_val = self.rvwap2[-1]

        if ema_fast_val is None or ema_slow_val is None or hma_val is None:
            return
        if pd.isna(ema_fast_val) or pd.isna(ema_slow_val) or pd.isna(hma_val):
            return

        if not self.position:
            if crossover(self.ema_fast, self.ema_slow):
                if close_val > daily_vwap_val and close_val > rvwap_val:
                    self.buy()
            elif crossover(self.ema_slow, self.ema_fast):
                if close_val < daily_vwap_val and close_val < rvwap_val:
                    self.sell()
        else:
            if self.position.is_long:
                if crossover(self.ema_slow, self.ema_fast):
                    self.position.close()
            elif self.position.is_short:
                if crossover(self.ema_fast, self.ema_slow):
                    self.position.close()


