import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        open_prices = pd.Series(self.data.Open)
        
        # Calculate EMAs
        self.fast_ema = self.I(pta.ema, close, length=10)
        self.slow_ema = self.I(pta.ema, close, length=20)

    def next(self):
        # Buy when fast EMA crosses above slow EMA
        if crossover(self.fast_ema, self.slow_ema):
            self.buy()
        # Sell when fast EMA crosses below slow EMA
        elif crossover(self.slow_ema, self.fast_ema):
            self.sell()