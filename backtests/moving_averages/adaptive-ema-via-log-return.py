import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lrLookback = 1
    emaLR_len = 5
    t1 = 0.3
    t2 = 0.6
    t3 = 0.9
    t4 = 1.3
    len10 = 10
    len20 = 20
    len40 = 40
    len60 = 60
    len80 = 80

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.emaLR = self.I(pta.ema, close, length=self.emaLR_len)
        self.ema10 = self.I(pta.ema, close, length=self.len10)
        self.ema20 = self.I(pta.ema, close, length=self.len20)
        self.ema40 = self.I(pta.ema, close, length=self.len40)
        self.ema60 = self.I(pta.ema, close, length=self.len60)
        self.ema80 = self.I(pta.ema, close, length=self.len80)
        
        self.ema_selected = self.I(self._adaptive_ema)

    def _adaptive_ema(self):
        result = pd.Series(index=self.data.Close.index, dtype=float)
        
        for i in range(len(self.data.Close)):
            if i < self.lrLookback:
                result.iloc[i] = np.nan
                continue
            
            emaLR_current = self.emaLR[i]
            emaLR_lookback = self.emaLR[i - self.lrLookback]
            
            if emaLR_lookback <= 0:
                result.iloc[i] = np.nan
                continue
            
            lr = np.log(emaLR_current / emaLR_lookback) * 10000
            
            if lr >= self.t4:
                result.iloc[i] = self.ema80[i]
            elif lr >= self.t3:
                result.iloc[i] = self.ema60[i]
            elif lr >= self.t2:
                result.iloc[i] = self.ema40[i]
            elif lr >= self.t1:
                result.iloc[i] = self.ema20[i]
            elif lr > 0:
                result.iloc[i] = self.ema10[i]
            elif lr > -self.t1:
                result.iloc[i] = self.ema10[i]
            elif lr > -self.t2:
                result.iloc[i] = self.ema20[i]
            elif lr > -self.t3:
                result.iloc[i] = self.ema40[i]
            elif lr > -self.t4:
                result.iloc[i] = self.ema60[i]
            else:
                result.iloc[i] = self.ema80[i]
        
        return result

    def next(self):
        if len(self.data) < 2:
            return
        
        if pd.isna(self.ema_selected[-1]) or pd.isna(self.ema_selected[-2]):
            return
        
        close_current = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        ema_current = self.ema_selected[-1]
        ema_prev = self.ema_selected[-2]
        
        if self.position:
            if crossover(ema_current, close_current) or close_current < ema_current:
                self.position.close()
        else:
            if crossover(close_current, ema_current) and close_prev <= ema_prev:
                self.buy()