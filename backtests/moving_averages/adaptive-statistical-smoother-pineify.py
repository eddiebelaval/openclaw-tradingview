import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    smooth = 10
    mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMA1 (forward pass)
        self.ema1 = self.I(pta.ema, close, length=self.smooth)
        
        # Calculate correlation and R-squared
        bar_index = pd.Series(np.arange(len(close)), index=close.index)
        correlation = self.I(lambda: pd.Series(
            [close.iloc[max(0, i-self.length+1):i+1].corr(
                bar_index.iloc[max(0, i-self.length+1):i+1]
            ) if i >= self.length - 1 else 0 for i in range(len(close))],
            index=close.index
        ))
        self.r2 = self.I(lambda: correlation ** 2)
        
        # Calculate standard deviation for bands
        self.stdev = self.I(lambda: close.rolling(self.length).std() * self.mult)
        
        # Initialize persistent variables for backward pass and aura_ma
        self.aura_ma_values = []
        self.os_values = [0.0]
        self.target_prev = [close.iloc[0]]
        
    def next(self):
        # Get current values
        close_current = self.data.Close[-1]
        ema1_current = self.ema1[-1] if len(self.ema1) > 0 else close_current
        r2_current = self.r2[-1] if len(self.r2) > 0 else 0
        stdev_current = self.stdev[-1] if len(self.stdev) > 0 and not np.isnan(self.stdev[-1]) else 0
        
        # Compute zero-lag target (backward pass EMA2)
        if len(self.ema1) < self.length:
            target = ema1_current
        else:
            ema2 = ema1_current
