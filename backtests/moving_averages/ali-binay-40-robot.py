import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    keyValue = 1.0
    atrPeriod = 10
    emaPeriod = 40

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMA40
        self.ema40 = self.I(pta.ema, close, length=self.emaPeriod)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrPeriod)
        
        # Initialize trailing stop
        self.trailing_stop = None
        self.trailing_stop_values = []

    def next(self):
        close = self.data.Close[-1]
        atr_val = self.atr[-1]
        ema40_val = self.ema40[-1]
        
        # Handle NaN values
        if pd.isna(atr_val) or pd.isna(ema40_val):
            return
        
        nLoss = self.keyValue * atr_val
        
        # Initialize trailing stop on first bar
        if self.trailing_stop is None:
            self.trailing_stop = close - nLoss
            self.trailing_stop_values.append(self.trailing_stop)
            return
        
        # Update trailing stop logic
        close_prev = self.data.Close[-2]
        
        if close > self.trailing_stop and close_prev > self.trailing_stop:
            self.trailing_stop = max(self.trailing_stop, close - nLoss)
        elif close < self.trailing_stop and close_prev < self.trailing_stop:
            self.trailing_stop = min(self.trailing_stop, close + nLoss)
        else:
            self.trailing_stop = close - nLoss if close > self.trailing_stop else close + nLoss
        
        self.trailing_stop_values.append(self.trailing_stop)
        
        # Generate signals
        buy_signal = crossover(self.data.Close, self.trailing_stop_values)
        sell_signal = crossover(self.trailing_stop_values, self.data.Close)
        
        # Filter buy signal: only buy if close < EMA40
        filtered_buy = buy_signal and close < ema40_val
        
        # Trading logic
        if filtered_buy:
            self.buy()
        elif sell_signal:
            self.sell()