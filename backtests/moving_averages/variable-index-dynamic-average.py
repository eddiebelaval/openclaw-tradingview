import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    longueurVIDYA = 200
    longueurCMO = 200

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate CMO (Chande Momentum Oscillator)
        cmo = self.I(pta.cmo, close, length=self.longueurCMO)
        
        # Calculate VI (Variable Index) as absolute CMO divided by 100
        vi = self.I(lambda: np.abs(cmo) / 100)
        
        # Calculate alpha using the VI
        alpha_base = 2.0 / (self.longueurVIDYA + 1)
        alpha = self.I(lambda: alpha_base * vi)
        
        # Calculate VIDYA using recursive formula
        vidya_values = []
        for i in range(len(close)):
            if i == 0:
                vidya_val = close.iloc[i]
            else:
                if pd.isna(alpha.iloc[i]):
                    alpha_val = 0.5
                else:
                    alpha_val = alpha.iloc[i]
                vidya_val = alpha_val * close.iloc[i] + (1 - alpha_val) * vidya_values[i - 1]
            vidya_values.append(vidya_val)
        
        self.vidya = self.I(lambda: pd.Series(vidya_values, index=close.index))

    def next(self):
        # Buy when price crosses above VIDYA
        if crossover(self.data.Close, self.vidya):
            if not self.position:
                self.buy()
        # Sell when price crosses below VIDYA
        elif crossover(self.vidya, self.data.Close):
            if self.position:
                self.position.close()