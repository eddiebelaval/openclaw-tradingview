import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 9
    slowLen = 21
    trendMode = "EMA200"
    htfEmaLen = 50
    useHeikin = True
    haConsec = 1
    useVWAP = True
    useADX = False
    diLen = 14
    adxSmooth = 14
    minAdx = 20.0
    cooldownBars = 6
    showLabels = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMAs
        self.fastEma = self.I(pta.ema, close, length=self.fastLen)
        self.slowEma = self.I(pta.ema, close, length=self.slowLen)
        
        # Trend line
        if self.trendMode == "EMA200":
            self.trendLine = self.I(pta.ema, close, length=200)
        else:
            self.trendLine = self.I(lambda: pd.Series(np.nan, index=close.index))
        
        # VWAP
        self.vwapVal = self.I(pta.vwap, high, low, close, volume)
        
        # ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.diLen, scalar=100) or pd.DataFrame(0, index=close.index, columns=['ADX_14']))
        self.adx = adx_result['ADX_14'] if isinstance(adx_result, pd.DataFrame) else adx_result
        
        # Heikin Ashi simulation (using close for simplicity)
        self.ha_close = self.I(lambda: (self.data.Open + self.data.High + self.data.Low + self.data.Close) / 4)
        self.ha_open = self.I(lambda: pd.Series(self.data.Open).rolling(2).mean())
        
        self.last_signal_bar = -np.inf

    def next(self):
        if len(self.data) < max(self.slowLen, 200):
            return
        
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        fast_ema = self.fastEma[-1]
        slow_ema = self.slowEma[-1]
        
        # Heikin Ashi filter
        heikin_buy_ok = True
        heikin_sell_ok = True
        
        if self.useHeikin:
            ha_close = self.ha_close[-1]
            ha_open = self.ha_open[-1]
            
            if not np.isnan(ha_close) and not np.isnan(ha_open):
                ha_bull = ha_close > ha_open
                ha_bear = ha_close < ha_open
                
                if self.haConsec == 2:
                    ha_close_prev = self.ha_close[-2] if len(self.ha_close) > 1 else np.nan
                    ha_open_prev = self.ha_open[-2] if len(self.ha_open) > 1 else np.nan
                    
                    if not np.isnan(ha_close_prev) and not np.isnan(ha_open_prev):
                        ha_bull_prev = ha_close_prev > ha_open_prev
                        ha_bear_prev = ha_close_prev < ha_open_prev
                        heikin_buy_ok = ha_bull and ha_bull_prev
                        heikin_sell_ok = ha_bear and ha_bear_prev
                    else:
                        heikin_buy_ok = ha_bull
                        heikin_sell_ok = ha_bear
                else:
                    heikin_buy_ok = ha_bull
                    heikin_sell_ok = ha_bear
        
        # Trend filter
        trend_buy_ok = True
        trend_sell_ok = True
        
        if self.trendMode != "None":
            trend_line = self.trendLine[-1]
            
            if not np.isnan(trend_line):
                cross_up_trend = (open_val < trend_line) and (close_val > trend_line)
                cross_down_trend = (open_val > trend_line) and (close_val < trend_line)
                
                trend_buy_ok = (close_val > trend_line) or cross_up_trend
                trend_sell_ok = (close_val < trend_line) or cross_down_trend
        
        # VWAP filter
        vwap_buy_ok = True
        vwap_sell_ok = True
        
        if self.useVWAP:
            vwap = self.vwapVal[-1]
            if not np.isnan(vwap):
                vwap_buy_ok = close_val > vwap
                vwap_sell_ok = close_val < vwap
        
        # ADX filter
        adx_ok = True
        
        if self.useADX:
            if not np.isnan(self.adx[-1]):
                adx_ok = self.adx[-1] >= self.minAdx
        
        # Cooldown
        cooldown_ok = (self.cooldownBars == 0) or (len(self.data) - 1 - self.last_signal_bar > self.cooldownBars)
        
        # Cross signals
        buy_raw = crossover(self.fastEma, self.slowEma)
        sell_raw = crossover(self.slowEma, self.fastEma)
        
        # Final signals
        buy_signal = cooldown_ok and buy_raw and trend_buy_ok and heikin_buy_ok and vwap_buy_ok and adx_ok
        sell_signal = cooldown_ok and sell_raw and trend_sell_ok and heikin_sell_ok and vwap_sell_ok and adx_ok
        
        if buy_signal:
            self.last_signal_bar = len(self.data) - 1
            if not self.position:
                self.buy()
        
        if sell_signal:
            self.last_signal_bar = len(self.data) - 1
            if self.position:
                self.sell()


