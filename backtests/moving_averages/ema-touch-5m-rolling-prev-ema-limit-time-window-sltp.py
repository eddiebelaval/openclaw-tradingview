import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime


class TvStrategy(Strategy):
    emaLen = 10
    qty = 1
    stopPts = 75.0
    targetPts = 150.0
    enableLongs = True
    enableShorts = True
    useTimeWindow = True
    startH = 9
    startM = 45
    endH = 15
    endM = 0
    maxFollowBars = 0
    reentryMode = "Wait for stop bar close"
    stretchPts = 30.0
    useForceFlat = True
    flatH = 16
    flatM = 45

    def init(self):
        close = pd.Series(self.data.Close)
        self.ema = self.I(pta.ema, close, length=self.emaLen)
        
        self.lastClosedCount = 0
        self.blockLong = False
        self.blockShort = False
        self.blockLongUntilBar = None
        self.blockShortUntilBar = None
        self.longStretchDone = False
        self.shortStretchDone = False
        self.longFollowBars = 0
        self.shortFollowBars = 0
        self.pending_long = False
        self.pending_short = False

    def next(self):
        if len(self.data.Close) < 2:
            return

        close_current = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        ema_current = self.ema[-1]
        ema_prev = self.ema[-2]
        current_bar = len(self.data.Close) - 1

        entry_limit = ema_prev

        trend_long = close_prev > ema_prev
        trend_short = close_prev < ema_prev

        ny_dt = self.data.index[-1]
        ny_h = ny_dt.hour
        ny_m = ny_dt.minute

        in_window = True
        if self.useTimeWindow:
            after_start = (ny_h > self.startH) or (ny_h == self.startH and ny_m >= self.startM)
            before_end = (ny_h < self.endH) or (ny_h == self.endH and ny_m <= self.endM)
            in_window = after_start and before_end

        force_flat = self.useForceFlat and ((ny_h > self.flatH) or (ny_h == self.flatH and ny_m >= self.flatM))

        flat = len(self.position) == 0

        long_wait_blocked = (self.reentryMode == "Wait for stop bar close") and self.blockLongUntilBar is not None and current_bar < self.blockLongUntilBar
        short_wait_blocked = (self.reentryMode == "Wait for stop bar close") and self.blockShortUntilBar is not None and current_bar < self.blockShortUntilBar

        if self.reentryMode == "Wait for stop bar close":
            if self.blockLongUntilBar is not None and current_bar >= self.blockLongUntilBar:
                self.blockLongUntilBar = None
            if self.blockShortUntilBar is not None and current_bar >= self.blockShortUntilBar:
                self.blockShortUntilBar = None

        if self.reentryMode == "Require flip confirmation":
            if self.blockLong and close_current > ema_current:
                self.blockLong = False
            if self.blockShort and close_current < ema_current:
                self.blockShort = False

        if self.reentryMode == "Require stretch + flip":
            if self.blockLong and not self.longStretchDone and close_current <= (ema_current - self.stretchPts):
                self.longStretchDone = True
            if self.blockLong and self.longStretchDone and close_current > ema_current:
                self.blockLong = False
                self.longStretchDone = False

            if self.blockShort and not self.shortStretchDone and close_current >= (ema_current + self.stretchPts):
                self.shortStretchDone = True
            if self.blockShort and self.shortStretchDone and close_current < ema_current:
                self.blockShort = False
                self.shortStretchDone = False

        if force_flat:
            self.blockLong = False
            self.blockShort = False
            self.blockLongUntilBar = None
            self.blockShortUntilBar = None
            self.longStretchDone = False
            self.shortStretchDone = False

        long_blocked = (
            (self.reentryMode == "Require flip confirmation" and self.blockLong) or
            (self.reentryMode == "Require stretch + flip" and self.blockLong) or
            (self.reentryMode == "Wait for stop bar close" and long_wait_blocked)
        )

        short_blocked = (
            (self.reentryMode == "Require flip confirmation" and self.blockShort) or
            (self.reentryMode == "Require stretch + flip" and self.blockShort) or
            (self.reentryMode == "Wait for stop bar close" and short_wait_blocked)
        )

        want_long_order = (not force_flat) and in_window and flat and self.enableLongs and trend_long and (self.reentryMode == "None" or not long_blocked)
        want_short_order = (not force_flat) and in_window and flat and self.enableShorts and trend_short and (self.reentryMode == "None" or not short_blocked)

        if not want_long_order:
            self.longFollowBars = 0
        else:
            self.longFollowBars += 1

        if not want_short_order:
            self.shortFollowBars = 0
        else:
            self.shortFollowBars += 1

        long_allowed = want_long_order and (self.maxFollowBars == 0 or self.longFollowBars <= self.maxFollowBars)
        short_allowed = want_short_order and (self.maxFollowBars == 0 or self.shortFollowBars <= self.maxFollowBars)

        if force_flat:
            if len(self.position) > 0:
                self.position.close()
        else:
            if long_allowed and flat and self.pending_long == False:
                self.buy()
                self.pending_long = True
            elif not long_allowed:
                self.pending_long = False

            if short_allowed and flat and self.pending_short == False:
                self.sell()
                self.pending_short = True
            elif not short_allowed:
                self.pending_short = False

            if len(self.position) > 0:
                self.longFollowBars = 0
                self.shortFollowBars = 0

            if len(self.position) > 0:
                avg = self.position.open_price
                if self.position.size > 0:
                    stop_price = avg - self.stopPts
                    target_price = avg + self.targetPts
                    if close_current <= stop_price or close_current >= target_price:
                        self.position.close()
                elif self.position.size < 0:
                    stop_price = avg + self.stopPts
                    target_price = avg - self.targetPts
                    if close_current >= stop_price or close_current <= target_price:
                        self.position.close()


