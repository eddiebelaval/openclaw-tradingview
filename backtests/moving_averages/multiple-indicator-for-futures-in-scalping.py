import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMAs
        self.ema8 = self.I(pta.ema, close, length=8)
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema100 = self.I(pta.ema, close, length=100)
        self.ema200 = self.I(pta.ema, close, length=200)
        self.ema500 = self.I(pta.ema, close, length=500)
        
        # VWAP
        hlc3 = (high + low + close) / 3
        self.vwap = self.I(pta.vwap, high, low, close, volume)
        
        # Bollinger Bands
        bb = self.I(pta.bbands, close, length=20, std=2.0)
        self.bb_upper = bb.iloc[:, 2] if bb is not None else None
        self.bb_basis = bb.iloc[:, 1] if bb is not None else None
        self.bb_lower = bb.iloc[:, 0] if bb is not None else None
        
    def next(self):
        if len(self) < 200:
            return
        
        close = self.data.Close[-1]
        
        # Trading logic based on EMA crossovers
        # Buy when EMA8 crosses above EMA20 and price is above EMA50
        if crossover(self.ema8, self.ema20):
            if close > self.ema50[-1]:
                self.buy()
        
        # Sell when EMA8 crosses below EMA20 or price touches BB lower
        elif crossover(self.ema20, self.ema8):
            if self.position:
                self.sell()
        
        # Exit if price falls below EMA100
        if self.position and close < self.ema100[-1]:
            self.sell()


