import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Moving Averages
        self.ema9 = self.I(pta.ema, close, length=9)
        self.ema21 = self.I(pta.ema, close, length=21)
        self.sma50 = self.I(pta.sma, close, length=50)
        self.sma100 = self.I(pta.sma, close, length=100)
        self.sma200 = self.I(pta.sma, close, length=200)
        
        # ATR
        self.atr14 = self.I(pta.atr, high, low, close, length=14)
        
        # RSI
        self.rsi14 = self.I(pta.rsi, close, length=14)
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macd_line = self.I(lambda: (pta.macd(close, fast=12, slow=26, signal=9) or pd.DataFrame()).iloc[:, 0] if not (pta.macd(close, fast=12, slow=26, signal=9) or pd.DataFrame()).empty else pd.Series(0, index=close.index))
        
        # Stochastic
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=14, d=3, smooth_k=3))
        self.k_val = self.I(lambda: (pta.stoch(high, low, close, k=14, d=3, smooth_k=3) or pd.DataFrame()).iloc[:, 0] if not (pta.stoch(high, low, close, k=14, d=3, smooth_k=3) or pd.DataFrame()).empty else pd.Series(50, index=close.index))
        self.d_val = self.I(lambda: (pta.stoch(high, low, close, k=14, d=3, smooth_k=3) or pd.DataFrame()).iloc[:, 1] if not (pta.stoch(high, low, close, k=14, d=3, smooth_k=3) or pd.DataFrame()).empty else pd.Series(50, index=close.index))
        
        # Volume average
        self.vol_avg = self.I(pta.sma, volume, length=20)
        
        # Highest/Lowest for BOS
        self.hi10 = self.I(lambda: high.rolling(window=10).max())
        self.lo10 = self.I(lambda: low.rolling(window=10).min())
        
        # Pivot Points
        self.pivot_high = self.I(lambda: pta.pivothigh(high, low, close, length=20) or pd.Series(np.nan, index=close.index))
        self.pivot_low = self.I(lambda: pta.pivotlow(high, low, close, length=20) or pd.Series(np.nan, index=close.index))
        
        # State tracking
        self.last_signal_bar = -100
        self.signal_state = 0
        self.trend_dir = 0
        self.last_hi = np.nan
        self.last_lo = np.nan
        self.int_hi = np.nan
        self.int_lo = np.nan
        
        self.atr_mult_sl = 1.5
        self.atr_mult_tp1 = 2.0
        self.atr_mult_tp2 = 3.5
        self.risk_reward_min = 1.5
        self.swing_len = 20
        self.ob_lookback = 10
        self.cooldown_bars = 5

    def next(self):
        # Get current values
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        idx = len(self.data) - 1
        
        # Update moving averages (they auto-calculate)
        ema9_val = self.ema9[-1] if not np.isnan(self.ema9[-1]) else close_val
        ema21_val = self.ema21[-1] if not np.isnan(self.ema21[-1]) else close_val
        sma50_val = self.sma50[-1] if not np.isnan(self.sma50[-1]) else close_val
        rsi14_val = self.rsi14[-1] if not np.isnan(self.rsi14[-1]) else 50
        atr14_val = self.atr14[-1] if not np.isnan(self.atr14[-1]) else 0
        
        # MACD signals
        macd_val = self.macd_line[-1] if len(self.macd_line) > 0 and not np.isnan(self.macd_line[-1]) else 0
        signal_val = self.d_val[-1] if len(self.d_val) > 0 and not np.isnan(self.d_val[-1]) else 0
        
        # Stochastic
        k_val = self.k_val[-1] if len(self.k_val) > 0 and not np.isnan(self.k_val[-1]) else 50
        d_val = self.d_val[-1] if len(self.d_val) > 0 and not np.isnan(self.d_val[-1]) else 50
        
        # Volume surge
        vol_avg_val = self.vol_avg[-1] if not np.isnan(self.vol_avg[-1]) else volume_val
        vol_surge = volume_val > vol_avg_val * 1.5
        
        # Highest/Lowest
        hi10_val = self.hi10[-1] if not np.isnan(self.hi10[-1]) else high_val
        lo10_val = self.lo10[-1] if not np.isnan(self.lo10[-1]) else low_val
        
        # Update internal support/resistance
        if idx >= 6:
            if high_val > hi10_val:
                self.int_hi = high_val
            if low_val < lo10_val:
                self.int_lo = low_val
        
        # BOS conditions
        bos_bull = False
        bos_bear = False
        if not np.isnan(self.int_hi) and crossover(pd.Series([close_val]), pd.Series([self.int_hi])):
            bos_bull = True
            self.trend_dir = 1
        if not np.isnan(self.int_lo) and crossover(pd.Series([self.int_lo]), pd.Series([close_val])):
            bos_bear = True
            self.trend_dir = -1
        
        # Calculate buy and sell scores
        buy_score = 0
        buy_score += 1 if close_val > ema9_val else 0
        buy_score += 1 if ema9_val > ema21_val else 0
        buy_score += 1 if close_val > sma50_val else 0
        buy_score += 1 if (rsi14_val > 50 and rsi14_val < 70) else 0
        buy_score += 1 if macd_val > signal_val else 0
        buy_score += 1 if (k_val > d_val and k_val < 80) else 0
        buy_score += 1 if vol_surge else 0
        buy_score += 1 if self.trend_dir == 1 else 0
        
        sell_score = 0
        sell_score += 1 if close_val < ema9_val else 0
        sell_score += 1 if ema9_val < ema21_val else 0
        sell_score += 1 if close_val < sma50_val else 0
        sell_score += 1 if (rsi14_val < 50 and rsi14_val > 30) else 0
        sell_score += 1 if macd_val < signal_val else 0
        sell_score += 1 if (k_val < d_val and k_val > 20) else 0
        sell_score += 1 if vol_surge else 0
        sell_score += 1 if self.trend_dir == -1 else 0
        
        # Signal confirmation
        raw_strong_buy = buy_score >= 6
        raw_strong_sell = sell_score >= 6
        raw_weak_buy = (buy_score >= 4 and buy_score < 6)
        raw_weak_sell = (sell_score >= 4 and sell_score < 6)
        
        # Cooldown check
        is_cooldown_over = (idx - self.last_signal_bar) >= self.cooldown_bars
        
        # Signal state management
        strong_buy = raw_strong_buy and (self.signal_state != 2 or is_cooldown_over)
        strong_sell = raw_strong_sell and (self.signal_state != -2 or is_cooldown_over)
        weak_buy = raw_weak_buy and self.signal_state <= 0
        weak_sell = raw_weak_sell and self.signal_state >= 0
        
        # Execute trades based on signals
        if strong_buy or weak_buy:
            if not self.position:
                self.buy()
            if strong_buy:
                self.signal_state = 2
                self.last_signal_bar = idx
            elif weak_buy:
                self.signal_state = 1
                self.last_signal_bar = idx
        
        elif strong_sell or weak_sell:
            if self.position:
                self.position.close()
            if strong_sell:
                self.signal_state = -2
                self.last_signal_bar = idx
            elif weak_sell:
                self.signal_state = -1
                self.last_signal_bar = idx
        
        # Stop loss and take profit management
        if self.position:
            if self.position.is_long:
                sl_price = low_val - atr14_val * self.atr_mult_sl
                tp_price = close_val + atr14_val * self.atr_mult_tp1
                
                if close_val <= sl_price or close_val >= tp_price:
                    self.position.close()
            else:
                sl_price = high_val + atr14_val * self.atr_mult_sl
                tp_price = close_val - atr14_val * self.atr_mult_tp1
                
                if close_val >= sl_price or close_val <= tp_price:
                    self.position.close()


