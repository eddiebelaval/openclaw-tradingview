import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # TICK.NY simulation - using price data as proxy
        tick_high = high
        tick_low = low
        tick_close = close
        
        # Clamp to ±800
        high_limit = 800.0
        low_limit = 800.0
        high_clamped = tick_high.apply(lambda x: min(x, high_limit))
        low_clamped = tick_low.apply(lambda x: max(x, -low_limit))
        
        # Base EMA bands
        sma_high = self.I(pta.ema, high_clamped, length=5)
        sma_low = self.I(pta.ema, low_clamped, length=5)
        
        # 30% displacement
        tick_range = tick_high - tick_low
        displace = tick_range * 0.30
        self.upper_band = self.I(lambda: tick_high + displace)
        self.lower_band = self.I(lambda: tick_low - displace)
        
        self.sma_high = sma_high
        self.sma_low = sma_low

    def next(self):
        if len(self.data) < 2:
            return
        
        current_upper = self.upper_band[-1]
        current_lower = self.lower_band[-1]
        current_close = self.data.Close[-1]
        prev_close = self.data.Close[-2]
        
        # Buy when price crosses above lower band with upward momentum
        if prev_close <= current_lower and current_close > current_lower:
            if not self.position:
                self.buy()
        
        # Sell when price crosses above upper band or drops below lower band
        elif current_close > current_upper or (prev_close >= current_lower and current_close < current_lower):
            if self.position:
                self.sell()