import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # ATR parameters
    atr_len = 14
    atr_pct_th = 4.0
    
    # Volume MA parameters
    vol_len_short = 5
    vol_len_long = 50
    vol_len_extra = 150
    
    # Price MA parameters
    ma_len_short = 10
    ma_len_long = 50
    
    # MA5 for cross detection
    ma5_len = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.atr_pct = self.I(lambda: (self.atr[-1] / close.iloc[-1] * 100.0) if self.atr[-1] is not None and close.iloc[-1] != 0 else 0)
        
        # Volume Moving Averages
        self.vol_ma_short = self.I(pta.sma, volume, length=self.vol_len_short)
        self.vol_ma_long = self.I(pta.sma, volume, length=self.vol_len_long)
        self.vol_ma_extra = self.I(pta.sma, volume, length=self.vol_len_extra)
        
        # Price Moving Averages
        self.ma_short = self.I(pta.sma, close, length=self.ma_len_short)
        self.ma_long = self.I(pta.sma, close, length=self.ma_len_long)
        self.ma5 = self.I(pta.sma, close, length=self.ma5_len)

    def next(self):
        # Trading logic based on MA5 crossovers
        # Buy signal: close crosses above MA5
        if len(self.data) > self.ma5_len:
            if crossover(self.data.Close, self.ma5):
                if not self.position:
                    self.buy()
            # Sell signal: close crosses below MA5
            elif crossover(self.ma5, self.data.Close):
                if self.position:
                    self.position.close()


