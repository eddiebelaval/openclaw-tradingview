import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLength = 20
    rsiLength = 5
    diLength = 14
    adxSmoothing = 14
    adxThreshold = 18
    rsiLongLevel = 55
    rsiShortLevel = 45

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.ema20 = self.I(pta.ema, close, length=self.emaLength)
        self.vwap_value = self.I(pta.vwap, close, volume)
        self.rsi_value = self.I(pta.rsi, close, length=self.rsiLength)
        
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.diLength) or pd.DataFrame(0, index=close.index, columns=['ADX_14', 'DMP_14', 'DMN_14']))
        self.adx_value = self.I(lambda: adx_result['ADX_14'] if isinstance(adx_result, pd.DataFrame) and 'ADX_14' in adx_result.columns else pd.Series(0, index=close.index))
        
        self.trade_state = 0

    def next(self):
        close_val = self.data.Close[-1]
        ema20_val = self.ema20[-1]
        vwap_val = self.vwap_value[-1]
        rsi_val = self.rsi_value[-1]
        adx_val = self.adx_value[-1]
        
        strong_trend = adx_val > self.adxThreshold
        
        bull_bias = close_val > ema20_val and close_val > vwap_val
        bear_bias = close_val < ema20_val and close_val < vwap_val
        
        rsi_cross_up = crossover(self.rsi_value, self.rsiLongLevel)
        rsi_cross_down = crossover(self.rsiShortLevel, self.rsi_value)
        
        long_entry = self.trade_state == 0 and strong_trend and bull_bias and rsi_cross_up
        short_entry = self.trade_state == 0 and strong_trend and bear_bias and rsi_cross_down
        
        exit_long = self.trade_state == 1 and (close_val < ema20_val or rsi_val < 50)
        exit_short = self.trade_state == -1 and (close_val > ema20_val or rsi_val > 50)
        
        if long_entry:
            self.buy()
            self.trade_state = 1
        elif short_entry:
            self.sell()
            self.trade_state = -1
        elif exit_long:
            if self.position:
                self.position.close()
            self.trade_state = 0
        elif exit_short:
            if self.position:
                self.position.close()
            self.trade_state = 0


