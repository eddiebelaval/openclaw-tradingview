import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Trend Settings
    emaFastLen = 9
    emaSlowLen = 21
    trendLen = 50
    ema200Len = 200
    
    # Momentum Settings
    rsiLen = 14
    rsiOverbought = 70
    rsiOversold = 30
    
    # Volume Settings
    volLen = 20
    volMultiplier = 1.5
    
    # FVG Settings
    fvgWidth = 3
    
    # Liquidity Settings
    major_length = 20
    minor_length = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Moving Averages
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)
        self.emaTrend = self.I(pta.ema, close, length=self.trendLen)
        self.ema200 = self.I(pta.ema, close, length=self.ema200Len)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        # Volume Analysis
        self.volMA = self.I(pta.sma, volume, length=self.volLen)
        
        # Pivot Highs and Lows for Liquidity
        self.major_high = self.I(lambda: self._pivot_high(high, self.major_length))
        self.major_low = self.I(lambda: self._pivot_low(low, self.major_length))
        self.minor_high = self.I(lambda: self._pivot_high(high, self.minor_length))
        self.minor_low = self.I(lambda: self._pivot_low(low, self.minor_length))

    def _pivot_high(self, series, length):
        """Calculate pivot highs"""
        result = pd.Series(np.nan, index=series.index)
        for i in range(length, len(series) - length):
            if series.iloc[i] == series.iloc[i-length:i+length+1].max():
                result.iloc[i] = series.iloc[i]
        return result

    def _pivot_low(self, series, length):
        """Calculate pivot lows"""
        result = pd.Series(np.nan, index=series.index)
        for i in range(length, len(series) - length):
            if series.iloc[i] == series.iloc[i-length:i+length+1].min():
                result.iloc[i] = series.iloc[i]
        return result

    def next(self):
        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        # Trend Detection
        bullishTrend = close > self.emaTrend[-1]
        bearishTrend = close < self.emaTrend[-1]
        
        # Volume Spike
        volSpike = volume > self.volMA[-1] * self.volMultiplier if self.volMA[-1] > 0 else False
        
        # Buy Signal: Fast EMA crosses above Slow EMA, price above trend, RSI not overbought
        if len(self.emaFast) > 1 and len(self.emaSlow) > 1:
            emaCrossUp = crossover(self.emaFast, self.emaSlow)
            buySignal = emaCrossUp and bullishTrend and self.rsi[-1] < self.rsiOverbought
            strongBuy = buySignal and volSpike
            
            if strongBuy or buySignal:
                if not self.position:
                    self.buy()
        
        # Sell Signal: Fast EMA crosses below Slow EMA, price below trend, RSI not oversold
        if len(self.emaFast) > 1 and len(self.emaSlow) > 1:
            emaCrossDown = crossover(self.emaSlow, self.emaFast)
            sellSignal = emaCrossDown and bearishTrend and self.rsi[-1] > self.rsiOversold
            strongSell = sellSignal and volSpike
            
            if strongSell or sellSignal:
                if self.position:
                    self.position.close()
        
        # FVG Detection (Bullish FVG: gap between candle 3's high and candle 1's low)
        if len(self.data.Low) > 2 and len(self.data.High) > 2 and len(self.data.Open) > 1 and len(self.data.Close) > 1:
            bullishFVG = (self.data.Low[-1] > self.data.High[-3]) and (self.data.Close[-2] > self.data.Open[-2])
            bearishFVG = (self.data.High[-1] < self.data.Low[-3]) and (self.data.Close[-2] < self.data.Open[-2])
            
            # Use FVG as additional signal confirmation
            if bullishFVG and not self.position:
                self.buy()
            elif bearishFVG and self.position:
                self.position.close()
        
        # Liquidity breaks (Price breaks major liquidity levels)
        if not np.isnan(self.major_high[-1]) and high > self.major_high[-1]:
            if self.position:
                self.position.close()
        
        if not np.isnan(self.major_low[-1]) and low < self.major_low[-1]:
            if not self.position:
                self.buy()


