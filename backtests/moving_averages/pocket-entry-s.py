import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    upper_ma_len = 80
    main_ma_len = 20
    lower_ma_len = 4
    near_threshold = 0.13
    ma_gap_threshold = 0.05

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        self.ma_red = self.I(pta.sma, close, length=self.upper_ma_len)
        self.ma_blue = self.I(pta.sma, close, length=self.main_ma_len)
        self.ma_white = self.I(pta.sma, close, length=self.lower_ma_len)
        
        self.close_series = close
        self.high_series = high
        self.low_series = low
        self.open_series = open_

    def next(self):
        if len(self.data) < 3:
            return
        
        idx = len(self.data) - 1
        
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        
        close_prev = self.data.Close[-2]
        open_prev = self.data.Open[-2]
        
        ma_red_val = self.ma_red[-1]
        ma_blue_val = self.ma_blue[-1]
        ma_white_val = self.ma_white[-1]
        
        ma_red_prev = self.ma_red[-2]
        ma_blue_prev = self.ma_blue[-2]
        
        if ma_red_val is None or ma_blue_val is None or ma_white_val is None:
            return
        
        if ma_red_val == 0:
            return
        
        ma_gap = abs(ma_red_val - ma_blue_val) / ma_red_val * 100
        
        is_perfect_order_s = ma_red_val > ma_blue_val
        is_near_cross_s = ma_red_val <= ma_blue_val and ma_gap <= self.ma_gap_threshold
        
        is_red_not_up = ma_red_val <= (ma_red_prev * 1.0001)
        is_4h_high_down = True
        
        is_trend_down = (is_perfect_order_s or is_near_cross_s) and is_red_not_up and is_4h_high_down
        
        dist_close = abs(close_val - ma_blue_val) / ma_blue_val * 100
        dist_high = abs(high_val - ma_blue_val) / ma_blue_val * 100
        is_break_through_s = open_val > ma_blue_val and close_val < ma_blue_val
        is_near_blue_s = dist_close <= self.near_threshold or dist_high <= (self.near_threshold * 0.7) or is_break_through_s
        
        body_high = max(open_val, close_val)
        body_low = min(open_val, close_val)
        body_size = body_high - body_low
        
        if body_size > 0:
            body_below_blue = min(body_high, ma_blue_val) - body_low
            is_min_body_below = (body_below_blue / body_size) >= (0.1 if is_break_through_s else 0.3)
        else:
            is_min_body_below = False
        
        is_price_conquer_mas_s = close_val < ma_white_val and close_val < ma_blue_val
        
        prev_body_low = min(open_prev, close_prev)
        is_break_prev_body_s = close_val <= prev_body_low
        
