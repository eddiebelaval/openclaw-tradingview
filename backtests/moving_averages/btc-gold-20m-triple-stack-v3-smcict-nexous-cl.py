import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLenST = 10
    atrMultST = 3.0
    rsiLen = 14
    useStrictRSI = True
    atrLenSlope = 14
    sweepLookback = 20
    sweepWickPct = 0.35
    fvgMinATR = 0.15
    pivotLen = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Supertrend calculation
        def calc_supertrend():
            hl2 = (high + low) / 2
            atr = pta.atr(high, low, close, length=self.atrLenST)
            if atr is None:
                return pd.Series(0, index=close.index), pd.Series(0, index=close.index)
            basic_ub = hl2 + self.atrMultST * atr
            basic_lb = hl2 - self.atrMultST * atr
            final_ub = pd.Series(index=close.index, dtype=float)
            final_lb = pd.Series(index=close.index, dtype=float)
            st_line = pd.Series(index=close.index, dtype=float)
            st_dir = pd.Series(index=close.index, dtype=float)

            for i in range(len(close)):
                if i == 0:
                    final_ub.iloc[i] = basic_ub.iloc[i]
                    final_lb.iloc[i] = basic_lb.iloc[i]
                else:
                    final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i - 1] or close.iloc[i - 1] > final_ub.iloc[i - 1] else final_ub.iloc[i - 1]
                    final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i - 1] or close.iloc[i - 1] < final_lb.iloc[i - 1] else final_lb.iloc[i - 1]

                if i == 0:
                    st_dir.iloc[i] = 1
                    st_line.iloc[i] = final_lb.iloc[i]
                else:
                    if st_dir.iloc[i - 1] == 1:
                        st_line.iloc[i] = final_lb.iloc[i]
                        st_dir.iloc[i] = 1 if close.iloc[i] >= final_lb.iloc[i] else -1
                    else:
                        st_line.iloc[i] = final_ub.iloc[i]
                        st_dir.iloc[i] = -1 if close.iloc[i] <= final_ub.iloc[i] else 1

            return st_line, st_dir

        self.st_line, self.st_dir = self.I(calc_supertrend)

        # VWAP
        def calc_vwap():
            hlc3 = (high + low + close) / 3
            return pta.vwap(hlc3, volume) or pd.Series(close.mean(), index=close.index)

        self.vwap_line = self.I(calc_vwap)

        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)

        # ATR for various uses
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atrLenST)

        # Pivot High/Low
        def calc_pivots():
            ph = pd.Series(index=close.index, dtype=float)
            pl = pd.Series(index=close.index, dtype=float)
            for i in range(self.pivotLen, len(high) - self.pivotLen):
                if high.iloc[i] == high.iloc[i - self.pivotLen:i + self.pivotLen + 1].max():
                    ph.iloc[i] = high.iloc[i]
                if low.iloc[i] == low.iloc[i - self.pivotLen:i + self.pivotLen + 1].min():
                    pl.iloc[i] = low.iloc[i]
            return ph.fillna(method='ffill'), pl.fillna(method='ffill')

        self.ph, self.pl = self.I(calc_pivots)

        # Sweep detection helpers
        def calc_sweeps():
            prev_high = high.shift(1).rolling(self.sweepLookback).max()
            prev_low = low.shift(1).rolling(self.sweepLookback).min()
            rng = np.maximum(high - low, 1e-6)
            upper_wick = (high - np.maximum(self.data.Open, close)) / rng
            lower_wick = (np.minimum(self.data.Open, close) - low) / rng
            sweep_high = (high > prev_high) & (close < prev_high) & (upper_wick >= self.sweepWickPct)
            sweep_low = (low < prev_low) & (close > prev_low) & (lower_wick >= self.sweepWickPct)
            return pd.Series(sweep_high, index=close.index), pd.Series(sweep_low, index=close.index)

        self.sweep_high, self.sweep_low = self.I(calc_sweeps)

        # FVG detection
        def calc_fvg():
            atr_f = pta.atr(high, low, close, length=14) or pd.Series(1.0, index=close.index)
            min_gap = atr_f * self.fvgMinATR
            bull_fvg = (low > high.shift(2)) & ((low - high.shift(2)) >= min_gap)
            bear_fvg = (high < low.shift(2)) & ((low.shift(2) - high) >= min_gap)
            return pd.Series(bull_fvg, index=close.index), pd.Series(bear_fvg, index=close.index)

        self.bull_fvg, self.bear_fvg = self.I(calc_fvg)

        self.last_ph = 0
        self.last_pl = 0

    def next(self):
        if len(self.data) < max(self.pivotLen + 1, 3):
            return

        # Current values
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        st_line_val = self.st_line[-1] if not np.isnan(self.st_line[-1]) else 0
        st_dir_val = self.st_dir[-1] if not np.isnan(self.st_dir[-1]) else 0
        vwap_val = self.vwap_line[-1] if not np.isnan(self.vwap_line[-1]) else close_val
        rsi_val = self.rsi[-1] if not np.isnan(self.rsi[-1]) else 50
        ph_val = self.ph[-1] if not np.isnan(self.ph[-1]) else 0
        pl_val = self.pl[-1] if not np.isnan(self.pl[-1]) else 0

        # Track pivots
        if ph_val > 0:
            self.last_ph = ph_val
        if pl_val > 0:
            self.last_pl = pl_val

        # Trend and price position
        is_bull_trend = st_dir_val == 1
        is_bear_trend = st_dir_val == -1
        above_vwap = close_val > vwap_val
        below_vwap = close_val < vwap_val

        # RSI signals
        rsi_bull = False
        rsi_bear = False
        if len(self.rsi) >= 2:
            prev_rsi = self.rsi[-2]
            if self.useStrictRSI:
                rsi_bull = crossover(self.rsi, 50)
                rsi_bear = crossover(50, self.rsi)
            else:
                rsi_bull = rsi_val > 50
                rsi_bear = rsi_val < 50

        # Market structure bias
        struct_bias = 0
        bull_break = self.last_ph > 0 and close_val > self.last_ph
        bear_break = self.last_pl > 0 and close_val < self.last_pl
        if bull_break:
            struct_bias = 1
        elif bear_break:
            struct_bias = -1

        # Base signals
        base_long = is_bull_trend and above_vwap and rsi_bull
        base_short = is_bear_trend and below_vwap and rsi_bear

        # With bias alignment
        long_ok = base_long and (struct_bias == 0 or struct_bias == 1)
        short_ok = base_short and (struct_bias == 0 or struct_bias == -1)

        # SMC signals as confirmation
        sweep_signal = self.sweep_high[-1] if not np.isnan(self.sweep_high[-1]) else False
        sweep_signal_low = self.sweep_low[-1] if not np.isnan(self.sweep_low[-1]) else False

        # Entry logic
        if long_ok and not self.position:
            self.buy()
        elif short_ok and self.position:
            self.position.close()
        elif short_ok and not self.position:
            self.buy()
        elif long_ok and self.position and self.position.is_short:
            self.position.close()

        # Exit logic based on trend reversal
        if self.position.is_long and is_bear_trend:
            self.position.close()
        elif self.position.is_short and is_bull_trend:
            self.position.close()