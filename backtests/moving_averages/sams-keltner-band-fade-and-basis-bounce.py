import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Keltner Channel parameters
    kc_len = 20
    kc_atr_len = 10
    kc_mult = 2.0
    kc_use_ema = False
    
    # Band Fade parameters
    fade_penetrate = 0.5
    fade_wick_pct = 0.15
    fade_require_opposite = True
    fade_opp_lookback = 60
    
    # Basis Bounce parameters
    basis_prox = 0.7
    require_band_touch = True
    band_touch_lookback = 50
    use_bounce_base = True
    basing_lookback = 5
    basing_min_hl = 1
    basing_min_lh = 1
    use_body_compress = True
    use_range_compress = True
    
    # Candle Confirmation parameters
    require_confirm_candle = True
    min_body_pct = 0.1
    
    # Signal Control
    min_bar_gap = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate basis (SMA or EMA)
        if self.kc_use_ema:
            self.basis = self.I(pta.ema, close, length=self.kc_len)
        else:
            self.basis = self.I(pta.sma, close, length=self.kc_len)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.kc_atr_len)
        
        # Store for band calculations
        self.upper_band = None
        self.lower_band = None
        self.last_signal_bar = -self.min_bar_gap
        
    def next(self):
        if len(self.data) < max(self.kc_len, self.kc_atr_len, self.band_touch_lookback) + 5:
            return
        
        # Current bar values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        open_price = self.data.Open[-1]
        
        # Band values
        basis_val = self.basis[-1] if self.basis[-1] is not None else close
        atr_val = self.atr[-1] if self.atr[-1] is not None and self.atr[-1] > 0 else 0.1
        
        upper = basis_val + atr_val * self.kc_mult
        lower = basis_val - atr_val * self.kc_mult
        
        self.upper_band = upper
        self.lower_band = lower
        
        # Candle metrics
        candle_range = high - low
        upper_wick = high - max(open_price, close)
        lower_wick = min(open_price, close) - low
        body_size = abs(close - open_price)
        
        bull_close = close > open_price
        bear_close = close < open_price
        
        # Body size filter
        body_pct = body_size / candle_range if candle_range > 0 else 0
        body_ok = body_pct >= self.min_body_pct
        
        # Candle confirmation
        long_candle_ok = (not self.require_confirm_candle or bull_close) and body_ok
        short_candle_ok = (not self.require_confirm_candle or bear_close) and body_ok
        
        # Proximity calculations
        prox_dist = atr_val * self.basis_prox
        max_pen_up = upper + atr_val * self.fade_penetrate
        max_pen_dn = lower - atr_val * self.fade_penetrate
        
        # Band touch detection (Fade signals)
        upper_touch = high >= upper and high <= max_pen_up
        lower_touch = low <= lower and low >= max_pen_dn
        
        upper_wick_ok = (upper_wick / candle_range) >= self.fade_wick_pct if candle_range > 0 else False
        lower_wick_ok = (lower_wick / candle_range) >= self.fade_wick_pct if candle_range > 0 else False
        
        # Check for opposite band touch in lookback
        prior_opp_upper = False
        prior_opp_lower = False
        
        if self.fade_require_opposite:
            for i in range(1, min(self.fade_opp_lookback + 1, len(self.data))):
                if self.data.High[-i] >= self.upper_band if self.upper_band else upper:
                    prior_opp_upper = True
                    break
            for i in range(1, min(self.fade_opp_lookback + 1, len(self.data))):
                if self.data.Low[-i] <= self.lower_band if self.lower_band else lower:
                    prior_opp_lower = True
                    break
        else:
            prior_opp_upper = True
            prior_opp_lower = True
        
        fade_opp_ok_long = prior_opp_upper
        fade_opp_ok_short = prior_opp_lower
        
        # Fade signals
        fade_long = lower_touch and lower_wick_ok and close > lower and long_candle_ok and fade_opp_ok_long
        fade_short = upper_touch and upper_wick_ok and close < upper and short_candle_ok and fade_opp_ok_short
        
        # Check for prior band puncture (Bounce signals)
        last_upper_bar = 0
        last_lower_bar = 0
        
        if self.require_band_touch:
            for i in range(1, min(self.band_touch_lookback + 1, len(self.data))):
                if self.data.High[-i] >= upper and last_upper_bar == 0:
                    last_upper_bar = i
                if self.data.Low[-i] <= lower and last_lower_bar == 0:
                    last_lower_bar = i
                if last_upper_bar > 0 and last_lower_bar > 0:
                    break
        
        prior_upper_valid = last_upper_bar > 0 and (last_lower_bar == 0 or last_upper_bar < last_lower_bar)
        prior_lower_valid = last_lower_bar > 0 and (last_upper_bar == 0 or last_lower_bar < last_upper_bar)
        
        band_touch_ok_long = prior_upper_valid if self.require_band_touch else True
        band_touch_ok_short = prior_lower_valid if self.require_band_touch else True
        
        # Basing structure detection
        higher_low_count = 0
        lower_high_count = 0
        body_sum = 0.0
        range_sum = 0.0
        
        for i in range(1, min(self.basing_lookback + 1, len(self.data))):
            if self.data.Low[-i] > self.data.Low[-(i + 1)]:
                higher_low_count += 1
            if self.data.High[-i] < self.data.High[-(i + 1)]:
                lower_high_count += 1
            body_sum += abs(self.data.Close[-i] - self.data.Open[-i])
            range_sum += self.data.High[-i] - self.data.Low[-i]
        
        avg_body = body_sum / self.basing_lookback if self.basing_lookback > 0 else 0
        avg_range = range_sum / self.basing_lookback if self.basing_lookback > 0 else 0
        
        ref_body = abs(self.data.Close[-(self.basing_lookback + 1)] - self.data.Open[-(self.basing_lookback + 1)]) if len(self.data) > self.basing_lookback + 1 else 0
        ref_range = self.data.High[-(self.basing_lookback + 1)] - self.data.Low[-(self.basing_lookback + 1)] if len(self.data) > self.basing_lookback + 1 else 0
        
        body_compress_ok = self.use_body_compress and ref_body > 0 and avg_body < ref_body * 0.8
        range_compress_ok = self.use_range_compress and ref_range > 0 and avg_range < ref_range * 0.8
        
        hl_ok = higher_low_count >= self.basing_min_hl
        lh_ok = lower_high_count >= self.basing_min_lh
        
        long_basing_ok = hl_ok or body_compress_ok or range_compress_ok
        short_basing_ok = lh_ok or body_compress_ok or range_compress_ok
        
        bounce_base_ok_l = long_basing_ok if self.use_bounce_base else True
        bounce_base_ok_s = short_basing_ok if self.use_bounce_base else True
        
        # Basis bounce signals
        basis_touch_long = low <= basis_val + prox_dist and close > basis_val
        basis_touch_short = high >= basis_val - prox_dist and close < basis_val
        
        bounce_long = basis_touch_long and long_candle_ok and bounce_base_ok_l and band_touch_ok_long
        bounce_short = basis_touch_short and short_candle_ok and bounce_base_ok_s and band_touch_ok_short
        
        # Combined signals
        long_signal = fade_long or bounce_long
        short_signal = fade_short or bounce_short
        
        # Deduplication
        bar_gap = len(self.data) - 1 - self.last_signal_bar
        gap_ok = bar_gap >= self.min_bar_gap
        
        long_filtered = long_signal and gap_ok
        short_filtered = short_signal and gap_ok
        
        # Execute trades
        if long_filtered:
            if not self.position:
                self.buy()
            self.last_signal_bar = len(self.data) - 1
        
        if short_filtered:
            if self.position:
                self.position.close()
            self.last_signal_bar = len(self.data) - 1
        
        # Close long on short signal
        if short_filtered and self.position.size > 0:
            self.position.close()


