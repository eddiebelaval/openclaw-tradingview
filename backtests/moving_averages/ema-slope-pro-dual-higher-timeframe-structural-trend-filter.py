import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA 1 Settings
    emaLen = 200
    slopeBars = 10
    flatThresh = 0.05
    
    # EMA 2 Settings
    ema2Len = 200
    
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMA 1
        self.ema1 = self.I(pta.ema, close, length=self.emaLen)
        
        # Calculate EMA 1 slope: ((EMA_now - EMA[n]) / close) * 100
        def calc_slope1():
            ema1_vals = pta.ema(close, length=self.emaLen)
            if ema1_vals is None or len(ema1_vals) < self.slopeBars + 1:
                return pd.Series(0, index=close.index)
            slope = ((ema1_vals - ema1_vals.shift(self.slopeBars)) / close.replace(0, 1e-10)) * 100.0
            return slope
        
        self.slope1 = self.I(calc_slope1)
        
        # Calculate EMA 2
        self.ema2 = self.I(pta.ema, close, length=self.ema2Len)
        
        # Calculate EMA 2 slope
        def calc_slope2():
            ema2_vals = pta.ema(close, length=self.ema2Len)
            if ema2_vals is None or len(ema2_vals) < self.slopeBars + 1:
                return pd.Series(0, index=close.index)
            slope = ((ema2_vals - ema2_vals.shift(self.slopeBars)) / close.replace(0, 1e-10)) * 100.0
            return slope
        
        self.slope2 = self.I(calc_slope2)
        
        # Track previous states for transition detection
        self.prev_bull = False
        self.prev_bear = False
        self.prev_flat = False
        self.prev_bull2 = False
        self.prev_bear2 = False
        self.prev_both_bull = False
        self.prev_both_bear = False

    def next(self):
        if len(self) < self.slopeBars + 2:
            return
        
        # Current slope values
        slope1 = self.slope1[-1] if len(self.slope1) > 0 else 0
        slope2 = self.slope2[-1] if len(self.slope2) > 0 else 0
        
        # Determine trend states for EMA 1
        is_flat = abs(slope1) < self.flatThresh
        is_bull = not is_flat and slope1 > 0
        is_bear = not is_flat and slope1 < 0
        
        # Determine trend states for EMA 2
        is_flat2 = abs(slope2) < self.flatThresh
        is_bull2 = not is_flat2 and slope2 > 0
        is_bear2 = not is_flat2 and slope2 < 0
        
        # Detect transitions
        transition_to_bull = is_bull and not self.prev_bull
        transition_to_bear = is_bear and not self.prev_bear
        transition_to_bull2 = is_bull2 and not self.prev_bull2
        transition_to_bear2 = is_bear2 and not self.prev_bear2
        
        both_bull = is_bull and is_bull2
        both_bear = is_bear and is_bear2
        transition_both_bull = both_bull and not self.prev_both_bull
        transition_both_bear = both_bear and not self.prev_both_bear
        
        # Trading logic based on EMA slope transitions
        # Buy on confluence bullish transition (both EMAs agree and turn bull)
        if transition_both_bull:
            if not self.position:
                self.buy()
        
        # Sell on confluence bearish transition (both EMAs agree and turn bear)
        elif transition_both_bear:
            if self.position:
                self.sell()
        
        # Alternative: Buy on EMA1 bullish, sell on EMA1 bearish
        # This provides more frequent signals
        elif transition_to_bull and is_bull2:
            # EMA1 turned bull and EMA2 is also bullish
            if not self.position:
                self.buy()
        
        elif transition_to_bear and is_bear2:
            # EMA1 turned bear and EMA2 is also bearish
            if self.position:
                self.sell()
        
        # Exit on flat zone if we're in a position (reducing noise)
        elif is_flat and self.position:
            self.sell()
        
        # Update previous states
        self.prev_bull = is_bull
        self.prev_bear = is_bear
        self.prev_flat = is_flat
        self.prev_bull2 = is_bull2
        self.prev_bear2 = is_bear2
        self.prev_both_bull = both_bull
        self.prev_both_bear = both_bear


