import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len1 = 10
    len2 = 20
    len3 = 50

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema1 = self.I(pta.ema, close, length=self.len1)
        self.ema2 = self.I(pta.ema, close, length=self.len2)
        self.ema3 = self.I(pta.ema, close, length=self.len3)

    def next(self):
        if len(self.data) < self.len3 + 1:
            return
        
        ema1_val = self.ema1[-1]
        ema2_val = self.ema2[-1]
        ema3_val = self.ema3[-1]
        
        if ema1_val is None or ema2_val is None or ema3_val is None:
            return
        
        if len(self.ema1) < 2 or len(self.ema2) < 2 or len(self.ema3) < 2:
            return
        
