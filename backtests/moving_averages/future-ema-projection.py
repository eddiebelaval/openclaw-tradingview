        ema2_prev = self.ema2[-2]
        
        if ema1_prev is None or ema2_prev is None:
            return
        
        if not self.position:
            if crossover(self.ema1, self.ema2):
                self.buy()
        else:
            if crossover(self.ema2, self.ema1):
                self.sell()