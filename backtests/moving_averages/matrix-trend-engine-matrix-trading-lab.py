import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 20
    slowLen = 50
    trendLen = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.fastEMA = self.I(pta.ema, close, length=self.fastLen)
        self.slowEMA = self.I(pta.ema, close, length=self.slowLen)
        self.trendEMA = self.I(pta.ema, close, length=self.trendLen)
        
        self.bullTrendPrev = False
        self.bearTrendPrev = False

    def next(self):
        if len(self.data) < self.trendLen:
            return
        
        close = self.data.Close[-1]
        low = self.data.Low[-1]
        high = self.data.High[-1]
        
        fastEMA = self.fastEMA[-1]
        slowEMA = self.slowEMA[-1]
        trendEMA = self.trendEMA[-1]
        
        if fastEMA is None or slowEMA is None or trendEMA is None:
            return
        
        bullTrend = fastEMA > slowEMA and close > trendEMA
        bearTrend = fastEMA < slowEMA and close < trendEMA
        
        bullShift = bullTrend and not self.bullTrendPrev
        bearShift = bearTrend and not self.bearTrendPrev
        
        bullPullback = bullTrend and low <= fastEMA and close >= fastEMA
        bearPullback = bearTrend and high >= fastEMA and close <= fastEMA
        
        self.bullTrendPrev = bullTrend
        self.bearTrendPrev = bearTrend
        
        if bullShift or bullPullback:
            if not self.position:
                self.buy()
        elif bearShift or bearPullback:
            if self.position:
                self.position.close()
            else:
                self.sell()