import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # DEMA Settings
    dema_fast_len = 8
    dema_slow_len = 21
    
    # EMA Floor
    ema_floor_len = 50
    
    # Ichimoku Cloud
    ich_conv_len = 9
    ich_base_len = 26
    ich_span_len = 52
    ich_displacement = 26
    
    # ATR Volatility Filter
    atr_len = 14
    atr_median_len = 50
    atr_mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # DEMA Calculation
        def calc_dema(src, length):
            ema1 = pta.ema(src, length=length)
            if ema1 is None:
                return pd.Series(0, index=src.index)
            ema2 = pta.ema(ema1, length=length)
            if ema2 is None:
                return pd.Series(0, index=src.index)
            return 2 * ema1 - ema2
        
        self.dema_fast = self.I(lambda: calc_dema(close, self.dema_fast_len))
        self.dema_slow = self.I(lambda: calc_dema(close, self.dema_slow_len))
        
        # EMA 50 (Floor for exits)
        self.ema_floor = self.I(pta.ema, close, length=self.ema_floor_len)
        
        # Ichimoku Cloud - Donchian function
        def donchian(src_high, src_low, length):
            highest = src_high.rolling(length).max()
            lowest = src_low.rolling(length).min()
            return (highest + lowest) / 2
        
        self.conversion_line = self.I(lambda: donchian(high, low, self.ich_conv_len))
        self.base_line = self.I(lambda: donchian(high, low, self.ich_base_len))
        self.lead_line_a = self.I(lambda: (donchian(high, low, self.ich_conv_len) + donchian(high, low, self.ich_base_len)) / 2)
        self.lead_line_b = self.I(lambda: donchian(high, low, self.ich_span_len))
        
        # ATR Volatility Filter
        atr_val = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.atr_pct = self.I(lambda: (atr_val / close * 100) if atr_val is not None else pd.Series(0, index=close.index))
        
        # ATR Median calculation
        def calc_atr_median():
            atr_pct_series = self.atr_pct
            if atr_pct_series is None or len(atr_pct_series) == 0:
                return pd.Series(0, index=close.index)
            return atr_pct_series.rolling(self.atr_median_len).median()
        
        self.atr_median = self.I(calc_atr_median)

    def next(self):
        if len(self.data) < max(self.dema_fast_len, self.dema_slow_len, self.ema_floor_len, self.ich_displacement + self.ich_span_len, self.atr_median_len) + 5:
            return
        
        # Current values
        dema_fast_curr = self.dema_fast[-1]
        dema_slow_curr = self.dema_slow[-1]
        ema_floor_curr = self.ema_floor[-1]
        close_curr = self.data.Close[-1]
        
        # Ichimoku displacement
        disp_idx = max(0, len(self.data) - self.ich_displacement - 1)
        senkou_a = self.lead_line_a[disp_idx] if disp_idx < len(self.data) else self.lead_line_a[-1]
        senkou_b = self.lead_line_b[disp_idx] if disp_idx < len(self.data) else self.lead_line_b[-1]
        
        # ATR Filter
        atr_pct_curr = self.atr_pct[-1] if len(self.atr_pct) > 0 else 0
        atr_median_curr = self.atr_median[-1] if len(self.atr_median) > 0 else 1
        atr_ok = atr_pct_curr < atr_median_curr * self.atr_mult
        
        # Entry Conditions
        dema_cross_up = crossover(self.dema_fast, self.dema_slow)
        price_above_cloud = close_curr > senkou_a and close_curr > senkou_b
        
        long_entry = dema_cross_up and price_above_cloud and atr_ok
        
        # Exit Conditions
        dema_cross_down = crossover(self.dema_slow, self.dema_fast)
        price_below_floor = close_curr < ema_floor_curr
        
        long_exit = dema_cross_down and price_below_floor
        
        # Strategy Execution
        if long_entry and not self.position:
            self.buy()
        
        if long_exit and self.position:
            self.position.close()