import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters
    ma_type = "EMA"
    mid_len = 20
    slow_len = 50
    
    # HTF parameters
    htf_slow_len = 50
    use_slope = True
    
    # ATR Noise Filter
    atr_len = 14
    atr_mult = 1.0
    use_noise_for_signals = False
    neutral_when_noise = True
    
    # Momentum Confirmation
    rsi_len = 14
    rsi_bull = 50
    rsi_bear = 50
    
    # Signals
