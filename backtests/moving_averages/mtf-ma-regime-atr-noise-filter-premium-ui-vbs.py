        if np.isnan(mid_ma) or np.isnan(rsi) or np.isnan(upper_band) or np.isnan(lower_band):
            return
        
        # Momentum conditions
        momo_bull = rsi > self.rsi_bull
        momo_bear = rsi < self.rsi_bear
        
        # Noise condition
        in_noise = close <= upper_band and close >= lower_band
        noise_gate_ok = not self.use_noise_for_signals or not in_noise
        
