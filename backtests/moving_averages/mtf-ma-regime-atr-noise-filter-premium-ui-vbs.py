        # Check for cooldown
        current_bar = len(self.data)
        
        def allow_with_cooldown(last_bar):
            if self.cooldown_bars == 0:
                return True
            return (current_bar - last_bar) > self.cooldown_bars
        
        # Pullback Buy: price dips to/through mid MA then reclaims it
