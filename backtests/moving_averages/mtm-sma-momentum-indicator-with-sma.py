import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    N = 21
    fast = 6
    slow = 55

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate MTM (Momentum)
        def calc_mtm():
            mtm = close - close.shift(self.N)
            return mtm
        
        self.mtm = self.I(calc_mtm)
        
        # Calculate SMA of MTM
        def calc_mtmma1():
            mtm = close - close.shift(self.N)
            mtmma1 = pta.sma(mtm, length=self.fast)
            return mtmma1 if mtmma1 is not None else pd.Series(0, index=close.index)
        
        def calc_mtmma2():
            mtm = close - close.shift(self.N)
            mtmma2 = pta.sma(mtm, length=self.slow)
            return mtmma2 if mtmma2 is not None else pd.Series(0, index=close.index)
        
        self.mtmma1 = self.I(calc_mtmma1)
        self.mtmma2 = self.I(calc_mtmma2)
        
        # Calculate histogram
        def calc_mtmhist():
            mtm = close - close.shift(self.N)
            mtmma1 = pta.sma(mtm, length=self.fast)
            mtmma2 = pta.sma(mtm, length=self.slow)
            if mtmma1 is None or mtmma2 is None:
                return pd.Series(0, index=close.index)
            mtmhist = mtmma1 - mtmma2
            return mtmhist
        
        self.mtmhist = self.I(calc_mtmhist)

    def next(self):
        # Buy when MTM Fast crosses above MTM Slow
        if crossover(self.mtmma1, self.mtmma2):
            if not self.position:
                self.buy()
        
        # Sell when MTM Fast crosses below MTM Slow
        elif crossover(self.mtmma2, self.mtmma1):
            if self.position:
                self.position.close()