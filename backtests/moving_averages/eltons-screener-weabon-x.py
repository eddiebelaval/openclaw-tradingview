import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Core indicators
        self.rsi2 = self.I(lambda: pta.rsi(close, length=2) or pd.Series(50, index=close.index))
        self.rsi3 = self.I(lambda: pta.rsi(close, length=3) or pd.Series(50, index=close.index))
        self.rsi14 = self.I(lambda: pta.rsi(close, length=14) or pd.Series(50, index=close.index))
        self.sma200 = self.I(lambda: pta.sma(close, length=200) or pd.Series(close, index=close.index))
        self.sma50 = self.I(lambda: pta.sma(close, length=50) or pd.Series(close, index=close.index))
        self.sma20 = self.I(lambda: pta.sma(close, length=20) or pd.Series(close, index=close.index))
        self.ema9 = self.I(lambda: pta.ema(close, length=9) or pd.Series(close, index=close.index))
        self.ema21 = self.I(lambda: pta.ema(close, length=21) or pd.Series(close, index=close.index))
        self.atr14 = self.I(lambda: pta.atr(high, low, close, length=14) or pd.Series(1, index=close.index))
        
        # Volume indicators
        self.vol_sma20 = self.I(lambda: pta.sma(volume, length=20) or pd.Series(1, index=volume.index))
        
        # ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14) or pd.DataFrame(index=close.index))
        self.adx = self.I(lambda: adx_result.iloc[:, 2] if isinstance(adx_result, pd.DataFrame) and adx_result.shape[1] > 2 else pd.Series(20, index=close.index))
        
        # Bollinger Bands
        bb_result = self.I(lambda: pta.bbands(close, length=20, std=2.0) or pd.DataFrame(index=close.index))
        self.bb_mid = self.I(lambda: bb_result.iloc[:, 1] if isinstance(bb_result, pd.DataFrame) and bb_result.shape[1] > 1 else pd.Series(close, index=close.index))
        self.bb_upper = self.I(lambda: bb_result.iloc[:, 0] if isinstance(bb_result, pd.DataFrame) and bb_result.shape[1] > 0 else pd.Series(close * 1.1, index=close.index))
        self.bb_lower = self.I(lambda: bb_result.iloc[:, 2] if isinstance(bb_result, pd.DataFrame) and bb_result.shape[1] > 2 else pd.Series(close * 0.9, index=close.index))
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9) or pd.DataFrame(index=close.index))
        self.macd_line = self.I(lambda: macd_result.iloc[:, 0] if isinstance(macd_result, pd.DataFrame) and macd_result.shape[1] > 0 else pd.Series(0, index=close.index))
        self.macd_signal = self.I(lambda: macd_result.iloc[:, 1] if isinstance(macd_result, pd.DataFrame) and macd_result.shape[1] > 1 else pd.Series(0, index=close.index))
        self.macd_hist = self.I(lambda: macd_result.iloc[:, 2] if isinstance(macd_result, pd.DataFrame) and macd_result.shape[1] > 2 else pd.Series(0, index=close.index))
        
        # Streak counter for ConnorsRSI
        self.streak = 0
        
        # Highest/Lowest for pivots
        self.high20 = self.I(lambda: high.rolling(window=20).max() or pd.Series(high, index=high.index))
        self.low20 = self.I(lambda: low.rolling(window=20).min() or pd.Series(low, index=low.index))
        
        # WMA for HMA
        self.wma25 = self.I(lambda: pta.wma(close, length=25) or pd.Series(close, index=close.index))
        self.wma50 = self.I(lambda: pta.wma(close, length=50) or pd.Series(close, index=close.index))
        
        # Entry/Exit tracking
        self.last_signal_bar = -1000
        self.signal_cooldown = 12

    def next(self):
        # Update streak counter for ConnorsRSI
        if len(self) > 1:
            if self.data.Close[-1] > self.data.Close[-2]:
                self.streak = (self.streak if self.streak >= 0 else 0) + 1
            elif self.data.Close[-1] < self.data.Close[-2]:
                self.streak = (self.streak if self.streak <= 0 else 0) - 1
            else:
                self.streak = 0
        
        # Trading logic based on multiple strategies
        signal_long = False
        signal_short = False
        confidence = 0.0
        
        # Strategy 1: ConnorsRSI-2
        if len(self) > 2:
            above_sma = self.data.Close[-1] > self.sma200[-1]
            below_sma = self.data.Close[-1] < self.sma200[-1]
            
            if self.rsi2[-1] < 10 and above_sma:
                signal_long = True
                confidence = max(confidence, 35.0)
            elif self.rsi2[-1] > 90 and below_sma:
                signal_short = True
                confidence = max(confidence, 35.0)
        
        # Strategy 2: MACD Momentum
        if len(self) > 2:
            if crossover(self.macd_line, self.macd_signal) and self.rsi14[-1] < 80:
                signal_long = True
                confidence = max(confidence, 35.0)
            elif crossover(self.macd_signal, self.macd_line) and self.rsi14[-1] > 20:
                signal_short = True
                confidence = max(confidence, 35.0)
        
        # Strategy 3: EMA Crossover
        if len(self) > 2:
            if crossover(self.ema9, self.ema21) and self.data.Close[-1] > self.sma50[-1]:
                signal_long = True
                confidence = max(confidence, 35.0)
            elif crossover(self.ema21, self.ema9) and self.data.Close[-1] < self.sma50[-1]:
                signal_short = True
                confidence = max(confidence, 35.0)
        
        # Strategy 4: Bollinger Squeeze Mean Reversion
        if len(self) > 2:
            mom = self.data.Close[-1] - self.bb_mid[-1]
            if self.data.Close[-1] < self.bb_lower[-1] and mom < 0:
                signal_long = True
                confidence = max(confidence, 30.0)
            elif self.data.Close[-1] > self.bb_upper[-1] and mom > 0:
                signal_short = True
                confidence = max(confidence, 30.0)
        
        # Strategy 5: VWAP Reversion (using SMA proxy for daily+)
        if len(self) > 2:
            vwap_proxy = self.sma20[-1]
            z_score = (self.data.Close[-1] - vwap_proxy) / self.atr14[-1] if self.atr14[-1] > 0 else 0
            
            if z_score < -1.5 and self.data.Close[-1] > self.data.Open[-1]:
                signal_long = True
                confidence = max(confidence, 30.0)
            elif z_score > 1.5 and self.data.Close[-1] < self.data.Open[-1]:
                signal_short = True
                confidence = max(confidence, 30.0)
        
        # Strategy 6: RSI Oversold/Overbought
        if len(self) > 2:
            if self.rsi14[-1] < 30 and self.data.Close[-1] > self.sma50[-1]:
                signal_long = True
                confidence = max(confidence, 32.0)
            elif self.rsi14[-1] > 70 and self.data.Close[-1] < self.sma50[-1]:
                signal_short = True
                confidence = max(confidence, 32.0)
        
        # Strategy 7: Swing Failure Pattern
        if len(self) > 20:
            swing_high = self.high20[-2]
            swing_low = self.low20[-2]
            range_size = self.data.High[-1] - self.data.Low[-1]
            
            if range_size > 0:
                wick_below = swing_low - self.data.Low[-1]
                wick_ratio = wick_below / range_size
                
                if self.data.Low[-1] < swing_low and self.data.Close[-1] > swing_low and wick_ratio > 0.25:
                    signal_long = True
                    confidence = max(confidence, 32.0)
                
                wick_above = self.data.High[-1] - swing_high
                wick_ratio = wick_above / range_size
                
                if self.data.High[-1] > swing_high and self.data.Close[-1] < swing_high and wick_ratio > 0.25:
                    signal_short = True
                    confidence = max(confidence, 32.0)
        
        # Strategy 8: HMA Trend
        if len(self) > 50:
            hma_half = self.wma25[-1]
            hma_full = self.wma50[-1]
            hma_diff = 2 * hma_half - hma_full
            
            if hma_diff > 0 and self.data.Close[-1] > self.sma50[-1] and self.rsi14[-1] < 75:
                signal_long = True
                confidence = max(confidence, 32.0)
            elif hma_diff < 0 and self.data.Close[-1] < self.sma50[-1] and self.rsi14[-1] > 25:
                signal_short = True
                confidence = max(confidence, 32.0)
        
        # Strategy 9: Volume confirmation
        if len(self) > 20:
            vol_ratio = self.data.Volume[-1] / self.vol_sma20[-1] if self.vol_sma20[-1] > 0 else 1.0
            vol_strong = vol_ratio >= 2.0
            
            if signal_long and vol_strong:
                confidence = min(95.0, confidence + 15.0)
            elif signal_short and vol_strong:
                confidence = min(95.0, confidence + 15.0)
        
        # Position management
        if confidence >= 40:
            if signal_long and not self.position:
                self.buy()
            elif signal_short and not self.position:
                self.sell()
        
        # Exit logic: opposite signal or RSI extreme reversals
        if self.position:
            if self.position.is_long:
                if signal_short or self.rsi2[-1] > 95:
                    self.position.close()
            elif self.position.is_short:
                if signal_long or self.rsi2[-1] < 5:
                    self.position.close()


