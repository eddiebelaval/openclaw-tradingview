import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Moving averages parameters
    ma_len_20 = 20
    ma_len_50 = 50
    
    # Pivot parameters
    lb_left = 1
    lb_right = 5
    touch_threshold = 1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate moving averages
        self.ma20 = self.I(pta.sma, close, length=self.ma_len_20)
        self.ma50 = self.I(pta.sma, close, length=self.ma_len_50)
        
        # Calculate pivot highs and pivot lows
        self.pivot_high = self.I(self._get_pivot_high, high, low, close)
        self.pivot_low = self.I(self._get_pivot_low, high, low, close)
        
        # Track swing high and low detection
        self.last_swing_high_idx = -999
        self.last_swing_low_idx = -999
        self.in_trade = False

    def _get_pivot_high(self, high, low, close):
        """Calculate pivot highs"""
        result = pd.Series(np.nan, index=high.index)
        for i in range(self.lb_left + self.lb_right, len(high)):
            is_pivot = True
            # Check left bars
            for j in range(1, self.lb_left + 1):
                if high.iloc[i - j] >= high.iloc[i]:
                    is_pivot = False
                    break
            # Check right bars
            if is_pivot:
                for j in range(1, self.lb_right + 1):
                    if high.iloc[i + j] >= high.iloc[i]:
                        is_pivot = False
                        break
            if is_pivot:
                result.iloc[i] = high.iloc[i]
        return result

    def _get_pivot_low(self, high, low, close):
        """Calculate pivot lows"""
        result = pd.Series(np.nan, index=low.index)
        for i in range(self.lb_left + self.lb_right, len(low)):
            is_pivot = True
            # Check left bars
            for j in range(1, self.lb_left + 1):
                if low.iloc[i - j] <= low.iloc[i]:
                    is_pivot = False
                    break
            # Check right bars
            if is_pivot:
                for j in range(1, self.lb_right + 1):
                    if low.iloc[i + j] <= low.iloc[i]:
                        is_pivot = False
                        break
            if is_pivot:
                result.iloc[i] = low.iloc[i]
        return result

    def next(self):
        # Entry and exit logic based on moving averages and pivots
        
        # Buy signal: MA20 crosses above MA50 and we're near a pivot low
        if crossover(self.ma20, self.ma50):
            if not self.position:
                self.buy()
        
        # Sell signal: MA20 crosses below MA50
        elif crossover(self.ma50, self.ma20):
            if self.position:
                self.position.close()
        
        # Alternative: Use pivot points for entry/exit
        # Buy on pivot low bounce
        if not np.isnan(self.pivot_low[-1]) and len(self) > self.lb_left + self.lb_right + 1:
            if self.data.Close[-1] > self.pivot_low[-1] and not self.position:
                self.buy()
        
        # Sell on pivot high touch
        if not np.isnan(self.pivot_high[-1]) and len(self) > self.lb_left + self.lb_right + 1:
            if self.data.Close[-1] >= self.pivot_high[-1] and self.position:
                self.position.close()
        
        # Stop loss / Take profit using moving averages
        if self.position:
            if self.data.Close[-1] < self.ma50[-1]:
                self.position.close()


