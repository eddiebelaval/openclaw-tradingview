import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 50
    emaSlowLen = 200
    rsiLen = 14
    rsiMid = 50
    atrLen = 14
    slMult = 1.5
    rr = 2.0
    
    useTrendBlock = True
    useMomentumBlock = True
    useVolBlock = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)
        self.rsiVal = self.I(pta.rsi, close, length=self.rsiLen)
        self.atrVal = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.atrSMA = self.I(pta.sma, self.atrVal, length=50)

    def next(self):
        if len(self.data) < max(self.emaSlowLen, self.rsiLen, self.atrLen, 50):
            return
        
        close_val = self.data.Close[-1]
        ema_fast = self.emaFast[-1]
        ema_slow = self.emaSlow[-1]
        rsi_val = self.rsiVal[-1]
        atr_val = self.atrVal[-1]
        atr_sma = self.atrSMA[-1]
        
        if ema_slow is None or atr_sma is None or np.isnan(ema_slow) or np.isnan(atr_sma):
            return
        
        trendUp = close_val > ema_slow
        trendDown = close_val < ema_slow
        trendPassLong = trendUp if self.useTrendBlock else True
        trendPassShort = trendDown if self.useTrendBlock else True
        
        momentumLong = rsi_val > self.rsiMid
        momentumShort = rsi_val < self.rsiMid
        momentumPassLong = momentumLong if self.useMomentumBlock else True
        momentumPassShort = momentumShort if self.useMomentumBlock else True
        
        volOk = atr_val > atr_sma
        volPass = volOk if self.useVolBlock else True
        
        longCond = trendPassLong and momentumPassLong and volPass and not self.position
        shortCond = trendPassShort and momentumPassShort and volPass and not self.position
        
        if longCond:
            self.buy()
        elif shortCond:
            self.sell()
        
        if self.position:
            if self.position.is_long:
                longStop = self.position.open_price - atr_val * self.slMult
                longLimit = self.position.open_price + atr_val * self.slMult * self.rr
                
                if close_val <= longStop or close_val >= longLimit:
                    self.position.close()
            
            elif self.position.is_short:
                shortStop = self.position.open_price + atr_val * self.slMult
                shortLimit = self.position.open_price - atr_val * self.slMult * self.rr
                
                if close_val >= shortStop or close_val <= shortLimit:
                    self.position.close()


