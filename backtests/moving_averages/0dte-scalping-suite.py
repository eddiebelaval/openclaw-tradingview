import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Settings
    ema_fast = 9
    ema_slow = 21
    
    # VWAP Settings
    vwap_std_mult = 1.0
    
    # Impulse MACD Settings
    macd_fast = 12
    macd_slow = 26
    macd_signal = 9
    macd_threshold = 0.05
    
    # Market Internals Filter
    use_internals_filter = True
    internals_bullish_threshold = 0.5
    internals_bearish_threshold = -0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMAs
        self.ema9 = self.I(pta.ema, close, length=self.ema_fast)
        self.ema21 = self.I(pta.ema, close, length=self.ema_slow)
        
        # VWAP and VWAP bands
        self.vwap = self.I(pta.vwap, high, low, close, volume)
        
        # VWAP Standard Deviation
        def vwap_stdev():
            vwap_vals = pta.vwap(pd.Series(self.data.High), pd.Series(self.data.Low), pd.Series(self.data.Close), pd.Series(self.data.Volume))
            if vwap_vals is None:
                return pd.Series(0, index=close.index)
            diff = close - vwap_vals
            return diff.rolling(window=20).std()
        
        self.vwap_std = self.I(vwap_stdev)
        
        # VWAP bands
        def vwap_upper():
            vwap_vals = pta.vwap(pd.Series(self.data.High), pd.Series(self.data.Low), pd.Series(self.data.Close), pd.Series(self.data.Volume))
            if vwap_vals is None:
                vwap_vals = pd.Series(0, index=close.index)
            diff = close - vwap_vals
            std_vals = diff.rolling(window=20).std()
            return vwap_vals + (std_vals * self.vwap_std_mult)
        
        self.vwap_upper = self.I(vwap_upper)
        
        def vwap_lower():
            vwap_vals = pta.vwap(pd.Series(self.data.High), pd.Series(self.data.Low), pd.Series(self.data.Close), pd.Series(self.data.Volume))
            if vwap_vals is None:
                vwap_vals = pd.Series(0, index=close.index)
            diff = close - vwap_vals
            std_vals = diff.rolling(window=20).std()
            return vwap_vals - (std_vals * self.vwap_std_mult)
        
        self.vwap_lower = self.I(vwap_lower)
        
        # MACD
        macd_result = self.I(pta.macd, close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_signal)
        
        def macd_histogram():
            result = pta.macd(pd.Series(self.data.Close), fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_signal)
            if result is None or result.empty:
                return pd.Series(0, index=close.index)
            return result.iloc[:, 2]
        
        self.macd_hist = self.I(macd_histogram)
        
        # Market Internals Simulation
        def price_change_pct():
            return close.pct_change() * 100
        
        self.price_change = self.I(price_change_pct)
        
        def volume_ratio():
            vol_sma = pta.sma(volume, length=20)
            if vol_sma is None:
                return pd.Series(1, index=volume.index)
            return volume / vol_sma
        
        self.vol_ratio = self.I(volume_ratio)
        
        def simulated_internals():
            price_chg = close.pct_change() * 100
            vol_sma = pta.sma(volume, length=20)
            if vol_sma is None:
                vol_r = pd.Series(1, index=volume.index)
            else:
                vol_r = volume / vol_sma
            return price_chg * vol_r
        
        self.internals = self.I(simulated_internals)

    def next(self):
        if len(self.data) < max(self.ema_slow, self.macd_slow, 20) + 2:
            return
        
        close_val = self.data.Close[-1]
        ema9_val = self.ema9[-1]
        ema21_val = self.ema21[-1]
        vwap_val = self.vwap[-1] if self.vwap[-1] is not None else close_val
        
        macd_hist_curr = self.macd_hist[-1]
        macd_hist_prev = self.macd_hist[-2] if len(self.macd_hist) > 1 else macd_hist_curr
        
        internals_val = self.internals[-1] if self.internals[-1] is not None else 0
        
        # EMA conditions
        ema_cross_up = crossover(self.ema9, self.ema21)
        ema_cross_down = crossover(self.ema21, self.ema9)
        ema_bullish = ema9_val > ema21_val
        
        # MACD conditions
        macd_bullish = (macd_hist_curr > 0 and 
                       macd_hist_curr > macd_hist_prev and 
                       abs(macd_hist_curr - macd_hist_prev) > self.macd_threshold)
        
        macd_bearish = (macd_hist_curr < 0 and 
                       macd_hist_curr < macd_hist_prev and 
                       abs(macd_hist_curr - macd_hist_prev) > self.macd_threshold)
        
        # Price vs VWAP
        price_above_vwap = close_val > vwap_val
        price_below_vwap = close_val < vwap_val
        
        # Market Internals
        internals_bullish = internals_val > self.internals_bullish_threshold
        internals_bearish = internals_val < self.internals_bearish_threshold
        
        # BUY Signal
        buy_signal = (ema_cross_up and macd_bullish and price_above_vwap and 
                     (not self.use_internals_filter or internals_bullish))
        
        # SELL Signal
        sell_signal = (ema_cross_down and macd_bearish and price_below_vwap and 
                      (not self.use_internals_filter or internals_bearish))
        
        # Execute trades
        if buy_signal:
            if not self.position:
                self.buy()
        elif sell_signal:
            if self.position:
                self.position.close()


