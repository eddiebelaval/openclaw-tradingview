import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length_fast = 20
    length_slow = 50
    offset_val = 0.85
    sigma_val = 6.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.alma_fast = self.I(lambda: pta.alma(close, length=self.length_fast, offset=self.offset_val, sigma=self.sigma_val) or pd.Series(0, index=close.index))
        self.alma_slow = self.I(lambda: pta.alma(close, length=self.length_slow, offset=self.offset_val, sigma=self.sigma_val) or pd.Series(0, index=close.index))

    def next(self):
        if len(self.data) < max(self.length_fast, self.length_slow) + 1:
            return
        
        alma_fast_current = self.alma_fast[-1]
        alma_slow_current = self.alma_slow[-1]
        alma_fast_prev = self.alma_fast[-2]
        alma_slow_prev = self.alma_slow[-2]
        
        bullish_trend = alma_fast_current > alma_slow_current
        bullish_trend_prev = alma_fast_prev > alma_slow_prev
        
        if not self.position:
            if bullish_trend and not bullish_trend_prev:
                self.buy()
        else:
            if not bullish_trend and bullish_trend_prev:
                self.sell()


