import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    coeff = 1.0
    ap = 14
    noVolumeData = False
    slAtrMult = 1.0
    tp1AtrMult = 1.0
    tp2AtrMult = 2.0
    tp3AtrMult = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hlc3 = (high + low + close) / 3
        
        # Calculate True Range
        tr = self.I(lambda: pd.Series(
            np.maximum(
                np.maximum(high - low, np.abs(high - close.shift(1))),
                np.abs(low - close.shift(1))
            )
        ))
        
        # Calculate ATR as SMA of TR
        self.atr = self.I(lambda: pta.sma(tr, length=self.ap) or pd.Series(0, index=close.index))
        
        # Calculate upT and downT
        self.upT = self.I(lambda: low - self.atr * self.coeff)
        self.downT = self.I(lambda: high + self.atr * self.coeff)
        
        # Calculate AlphaTrend
        self.alphaTrend = self.I(self._calc_alphatrend, close, hlc3, high, low)
        
        # Calculate buy and sell signals
        self.buySignal = self.I(self._calc_buy_signal)
        self.sellSignal = self.I(self._calc_sell_signal)
        
        # Track bars since signals
        self.barsSinceBuy = self.I(self._bars_since_buy)
        self.barsSinceSell = self.I(self._bars_since_sell)
        
        # Track position
        self.in_position = False
        self.entry_price = 0
        self.position_type = None

    def _calc_alphatrend(self, close, hlc3, high, low):
        alphaTrend = pd.Series(index=close.index, dtype=float)
        
        for i in range(len(close)):
            if i < self.ap:
                alphaTrend.iloc[i] = np.nan
                continue
            
            if self.noVolumeData:
                rsi_val = pta.rsi(close.iloc[:i+1], length=self.ap)
                condition = rsi_val.iloc[-1] >= 50 if len(rsi_val) > 0 and not pd.isna(rsi_val.iloc[-1]) else False
            else:
                mfi_val = pta.mfi(hlc3.iloc[:i+1], self.data.Volume.iloc[:i+1], length=self.ap)
                condition = mfi_val.iloc[-1] >= 50 if len(mfi_val) > 0 and not pd.isna(mfi_val.iloc[-1]) else False
            
            upT_val = low.iloc[i] - self.atr[-1] * self.coeff
            downT_val = high.iloc[i] + self.atr[-1] * self.coeff
            prev_val = alphaTrend.iloc[i-1] if i > 0 else np.nan
            
            if condition:
                if np.isnan(prev_val):
                    alphaTrend.iloc[i] = upT_val
                else:
                    alphaTrend.iloc[i] = upT_val if upT_val < prev_val else prev_val
            else:
                if np.isnan(prev_val):
                    alphaTrend.iloc[i] = downT_val
                else:
                    alphaTrend.iloc[i] = downT_val if downT_val > prev_val else prev_val
        
        return alphaTrend

    def _calc_buy_signal(self):
        signal = pd.Series(False, index=self.alphaTrend.index)
        for i in range(2, len(self.alphaTrend)):
            if not pd.isna(self.alphaTrend[i]) and not pd.isna(self.alphaTrend[i-2]):
                if self.alphaTrend[i] > self.alphaTrend[i-2] and self.alphaTrend[i-1] <= self.alphaTrend[i-3]:
                    signal.iloc[i] = True
        return signal

    def _calc_sell_signal(self):
        signal = pd.Series(False, index=self.alphaTrend.index)
        for i in range(2, len(self.alphaTrend)):
            if not pd.isna(self.alphaTrend[i]) and not pd.isna(self.alphaTrend[i-2]):
                if self.alphaTrend[i] < self.alphaTrend[i-2] and self.alphaTrend[i-1] >= self.alphaTrend[i-3]:
                    signal.iloc[i] = True
        return signal

    def _bars_since_buy(self):
        bars = pd.Series(np.inf, index=self.buySignal.index)
        count = 0
        for i in range(len(self.buySignal)):
            if self.buySignal.iloc[i]:
                count = 0
            else:
                count += 1
            bars.iloc[i] = count
        return bars

    def _bars_since_sell(self):
        bars = pd.Series(np.inf, index=self.sellSignal.index)
        count = 0
        for i in range(len(self.sellSignal)):
            if self.sellSignal.iloc[i]:
                count = 0
            else:
                count += 1
            bars.iloc[i] = count
        return bars

    def next(self):
        current_idx = len(self.data) - 1
        
        # Check for buy signal
        if current_idx >= 2:
            buy_sig = self.buySignal[-1] if len(self.buySignal) > 0 else False
            sell_sig = self.sellSignal[-1] if len(self.sellSignal) > 0 else False
            
            bars_since_buy_prev = self.barsSinceBuy[-2] if len(self.barsSinceBuy) > 1 else np.inf
            bars_since_sell = self.barsSinceSell[-1] if len(self.barsSinceSell) > 0 else np.inf
            
            if buy_sig and bars_since_buy_prev > bars_since_sell:
                if not self.in_position or self.position_type != "BUY":
                    if self.position:
                        self.position.close()
                    self.buy()
                    self.in_position = True
                    self.position_type = "BUY"
                    self.entry_price = self.data.Close[-1]
            
            bars_since_sell_prev = self.barsSinceSell[-2] if len(self.barsSinceSell) > 1 else np.inf
            bars_since_buy = self.barsSinceBuy[-1] if len(self.barsSinceBuy) > 0 else np.inf
            
            if sell_sig and bars_since_sell_prev > bars_since_buy:
                if not self.in_position or self.position_type != "SELL":
                    if self.position:
                        self.position.close()
                    self.sell()
                    self.in_position = True
                    self.position_type = "SELL"
                    self.entry_price = self.data.Close[-1]