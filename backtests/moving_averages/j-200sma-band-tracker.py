class TvStrategy(Strategy):
    mult = 2.5
    inner_band_mult = 0.1
    length = 200
    bb_mult = 0.2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Main Bollinger Bands
        bb_main = self.I(lambda: pta.bbands(close, length=self.length, std=self.mult))
        self.basis = self.I(lambda: pta.sma(close, length=self.length))
        self.upper = self.I(lambda: bb_main['BBU_200_2.5'] if bb_main is not None else pd.Series(close.iloc[-1], index=close.index))
        self.lower = self.I(lambda: bb_main['BBL_200_2.5'] if bb_main is not None else pd.Series(close.iloc[-1], index=close.index))
        
