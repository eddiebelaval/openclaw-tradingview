import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA Parameters
    ma1_length = 21
    ma1_type = "EMA"
    ma2_length = 50
    ma2_type = "EMA"
    ma3_length = 200
    ma3_type = "EMA"
    ma4_length = 800
    ma4_type = "EMA"
    
    # FVG Parameters
    fvg_extend = 1
    
    # OB Parameters
    ps_swing_length = 7
    ps_lookback = 20
    displacement_mult = 1.3
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate MAs
        self.ma1 = self.I(pta.ema, close, length=self.ma1_length)
        self.ma2 = self.I(pta.ema, close, length=self.ma2_length)
        self.ma3 = self.I(pta.ema, close, length=self.ma3_length)
        self.ma4 = self.I(pta.ema, close, length=self.ma4_length)
        
        # Volume analysis for FTB candles
        avg_volume = self.I(pta.sma, volume, length=10)
        hl_width = high * (high - low)
        
        # Pivot points for order blocks
        self.swing_high = self.I(lambda: self._get_pivot_high(high, self.ps_swing_length))
        self.swing_low = self.I(lambda: self._get_pivot_low(low, self.ps_swing_length))
        
    def _get_pivot_high(self, high_series, length):
        """Calculate pivot highs"""
        result = pd.Series(np.nan, index=high_series.index)
        for i in range(length, len(high_series) - length):
            if high_series.iloc[i] == high_series.iloc[i-length:i+length+1].max():
                result.iloc[i] = high_series.iloc[i]
        return result
    
    def _get_pivot_low(self, low_series, length):
        """Calculate pivot lows"""
        result = pd.Series(np.nan, index=low_series.index)
        for i in range(length, len(low_series) - length):
            if low_series.iloc[i] == low_series.iloc[i-length:i+length+1].min():
                result.iloc[i] = low_series.iloc[i]
        return result
    
    def _is_bullish_fvg(self):
        """Check for bullish fair value gap"""
        if len(self.data) < 3:
            return False
        return (self.data.Low[-1] > self.data.High[-3] and 
                self.data.Close[-2] > self.data.High[-3])
    
    def _is_bearish_fvg(self):
        """Check for bearish fair value gap"""
        if len(self.data) < 3:
            return False
        return (self.data.High[-1] < self.data.Low[-3] and 
                self.data.Close[-2] < self.data.Low[-3])
    
    def _find_bullish_ob(self):
        """Find bullish order block based on swing low"""
        if len(self.data) < self.ps_swing_length + self.ps_lookback + 1:
            return False
        
        if np.isnan(self.swing_low[-1]):
            return False
        
        swing_low_val = self.swing_low[-1]
        
        for i in range(self.ps_swing_length + 1, 
                      min(self.ps_swing_length + self.ps_lookback + 1, len(self.data))):
            bar_idx = len(self.data) - i
            if bar_idx < 0:
                continue
            
            hist_close = self.data.Close[bar_idx]
            hist_open = self.data.Open[bar_idx]
            hist_high = self.data.High[bar_idx]
            hist_low = self.data.Low[bar_idx]
            
            if hist_close < hist_open:
                disp = swing_low_val - hist_low
                rng = hist_high - hist_low
                if rng > 0 and disp > (rng * self.displacement_mult):
                    return True
        
        return False
    
    def _find_bearish_ob(self):
        """Find bearish order block based on swing high"""
        if len(self.data) < self.ps_swing_length + self.ps_lookback + 1:
            return False
        
        if np.isnan(self.swing_high[-1]):
            return False
        
        swing_high_val = self.swing_high[-1]
        
        for i in range(self.ps_swing_length + 1, 
                      min(self.ps_swing_length + self.ps_lookback + 1, len(self.data))):
            bar_idx = len(self.data) - i
            if bar_idx < 0:
                continue
            
            hist_close = self.data.Close[bar_idx]
            hist_open = self.data.Open[bar_idx]
            hist_high = self.data.High[bar_idx]
            hist_low = self.data.Low[bar_idx]
            
            if hist_close > hist_open:
                disp = hist_high - swing_high_val
                rng = hist_high - hist_low
                if rng > 0 and disp > (rng * self.displacement_mult):
                    return True
        
        return False
    
    def next(self):
        # MA Crossover Trading Logic
        if len(self.data) < max(self.ma1_length, self.ma2_length, self.ma3_length, self.ma4_length):
            return
        
        # Buy signal: MA1 crosses above MA2 and price above MA3
        if (not np.isnan(self.ma1[-1]) and not np.isnan(self.ma2[-1]) and 
            not np.isnan(self.ma3[-1])):
            
            ma1_prev = self.ma1[-2] if len(self.ma1) > 1 else np.nan
            ma2_prev = self.ma2[-2] if len(self.ma2) > 1 else np.nan
            
            if not np.isnan(ma1_prev) and not np.isnan(ma2_prev):
                if (ma1_prev <= ma2_prev and self.ma1[-1] > self.ma2[-1] and 
                    self.data.Close[-1] > self.ma3[-1]):
                    if not self.position:
                        self.buy()
        
        # Sell signal: MA1 crosses below MA2 or price below MA3
        if (not np.isnan(self.ma1[-1]) and not np.isnan(self.ma2[-1]) and 
            not np.isnan(self.ma3[-1])):
            
            ma1_prev = self.ma1[-2] if len(self.ma1) > 1 else np.nan
            ma2_prev = self.ma2[-2] if len(self.ma2) > 1 else np.nan
            
            if not np.isnan(ma1_prev) and not np.isnan(ma2_prev):
                if ((ma1_prev > ma2_prev and self.ma1[-1] <= self.ma2[-1]) or 
                    self.data.Close[-1] < self.ma3[-1]):
                    if self.position:
                        self.sell()
        
        # FVG Trading Logic
        if self._is_bullish_fvg():
            if not self.position:
                self.buy()
        
        if self._is_bearish_fvg():
            if self.position:
                self.sell()
        
        # Order Block Trading Logic
        if self._find_bullish_ob():
            if not self.position:
                self.buy()
        
        if self._find_bearish_ob():
            if self.position:
                self.sell()


