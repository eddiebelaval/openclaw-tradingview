        # Structure break check
        highest20_val = self.highest20[-1]
        lowest20_val = self.lowest20[-1]
        is_structure_break_up = close_val > highest20_val
        is_structure_break_dn = close_val < lowest20_val
        
        # Slope check
        is_slope_valid = len(self.sma100) > 5 and abs((sma100_val - self.sma100[-6]) / self.sma100[-6] * 100) > 0.01
        
        # Pierce action
        is_long_pierce = open_val < max_core and close_val > max_core and close_val > open_val
        is_short_pierce = open_val > min_core and close_val < min_core and close_val < open_val
        
        # Volume confirmation
        vol_sma20_val = self.vol_sma20[-1]
        is_vol_confirm = volume_val > vol_sma20_val * 1.2
        
