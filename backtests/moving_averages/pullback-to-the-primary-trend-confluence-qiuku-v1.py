        sma200_val = self.sma200[-1]
        
        # Max and Min of the three core MAs
        max_core = max(sma13_val, sma26_val, sma100_val)
        min_core = min(sma13_val, sma26_val, sma100_val)
        
        # Density check (MA convergence < 1%)
        is_dense = (max_core - min_core) / close_val < 0.01
        
