class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # 1. Basic Moving Averages
        self.sma13 = self.I(pta.sma, close, length=13)
        self.sma26 = self.I(pta.sma, close, length=26)
        self.sma100 = self.I(pta.sma, close, length=100)
        self.sma200 = self.I(pta.sma, close, length=200)
        
        # 2. ADX Trend Strength Filter
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.plus_di = self.I(lambda: pta.adx(high, low, close, length=14)['DMP_14'] if pta.adx(high, low, close, length=14) is not None else pd.Series(0, index=close.index))
        self.minus_di = self.I(lambda: pta.adx(high, low, close, length=14)['DMN_14'] if pta.adx(high, low, close, length=14) is not None else pd.Series(0, index=close.index))
        self.adx_value = self.I(lambda: pta.adx(high, low, close, length=14)['ADX_14'] if pta.adx(high, low, close, length=14) is not None else pd.Series(25, index=close.index))
        
        # 3. Structure Break Detection - Highest/Lowest of previous 20 bars
        self.highest20 = self.I(lambda: high.shift(1).rolling(window=20).max())
        self.lowest20 = self.I(lambda: low.shift(1).rolling(window=20).min())
        
        # 4. Moving Average Density and Slope
        self.slope100 = self.I(lambda: ((self.sma100[-1] - self.sma100[-6]) / self.sma100[-6] * 100) if len(self.sma100) > 5 else pd.Series(0, index=close.index))
        
        # 5. Volume Confirmation
        self.vol_sma20 = self.I(pta.sma, volume, length=20)

    def next(self):
        if len(self.data) < 100:
            return
        
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]
        
        # Get MA values
        sma13_val = self.sma13[-1]
