import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Preset mode selection
    mode = "Daily - Standard (8/21)"
    
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Map EMA lengths based on preset mode
        mode_map = {
            "Weekly - Standard (8/21)": (8, 21),
            "Weekly - Noise Filter (10/22)": (10, 22),
            "Daily - Standard (8/21)": (8, 21),
            "Daily - Smooth Trend (10/20)": (10, 20),
            "Daily - MACD Style (12/26)": (12, 26),
            "Intraday - Momentum (5/13)": (5, 13),
            "Intraday - Smooth Momentum (9/27)": (9, 27)
        }
        
        self.len1, self.len2 = mode_map.get(self.mode, (8, 21))
        
        # Calculate base EMAs
        self.ema1 = self.I(pta.ema, close, length=self.len1)
        self.ema2 = self.I(pta.ema, close, length=self.len2)
        
        # Smoothing EMAs for visual stability
        self.ema1_s = self.I(lambda: pta.ema(pd.Series(self.ema1), length=2) if self.ema1 is not None else pd.Series(np.nan, index=close.index))
        self.ema2_s = self.I(lambda: pta.ema(pd.Series(self.ema2), length=2) if self.ema2 is not None else pd.Series(np.nan, index=close.index))
        
        # Track trend state
        self.trend = 1

    def next(self):
        # Check if we have valid data
        if len(self.ema1_s) < 2 or len(self.ema2_s) < 2:
            return
        
        current_ema1 = self.ema1_s[-1]
        current_ema2 = self.ema2_s[-1]
        prev_ema1 = self.ema1_s[-2]
        prev_ema2 = self.ema2_s[-2]
        
        # Skip if any value is NaN
        if np.isnan(current_ema1) or np.isnan(current_ema2) or np.isnan(prev_ema1) or np.isnan(prev_ema2):
            return
        
        # Bullish cross: fast EMA crosses above slow EMA
        bullish_cross = (prev_ema1 <= prev_ema2) and (current_ema1 > current_ema2)
        
        # Bearish cross: fast EMA crosses below slow EMA
        bearish_cross = (prev_ema1 >= prev_ema2) and (current_ema1 < current_ema2)
        
        # Update trend state
        if bullish_cross:
            self.trend = 1
        if bearish_cross:
            self.trend = -1
        
        # Trading logic
        if bullish_cross:
            if not self.position:
                self.buy()
        elif bearish_cross:
            if self.position:
                self.position.close()


