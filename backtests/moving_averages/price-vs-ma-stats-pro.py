import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_type = "EMA"
    ma_length = 50

    def init(self):
        close = pd.Series(self.data.Close)
        
        if self.ma_type == "SMA":
            self.ma = self.I(pta.sma, close, length=self.ma_length)
        else:
            self.ma = self.I(pta.ema, close, length=self.ma_length)

    def next(self):
        if len(self.data) < self.ma_length + 1:
            return
        
        if self.ma[-1] is None:
            return
        
        close = self.data.Close[-1]
        ma_val = self.ma[-1]
        
        close_prev = self.data.Close[-2]
        ma_val_prev = self.ma[-2]
        
        cross_up = (close_prev <= ma_val_prev) and (close > ma_val)
        cross_down = (close_prev >= ma_val_prev) and (close < ma_val)
        
        if cross_up:
            if not self.position:
                self.buy()
        elif cross_down:
            if self.position:
                self.sell()