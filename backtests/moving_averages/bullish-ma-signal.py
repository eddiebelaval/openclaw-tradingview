import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate Moving Averages
        self.ma10 = self.I(pta.sma, close, length=10)
        self.ma20 = self.I(pta.sma, close, length=20)
        self.ma50 = self.I(pta.sma, close, length=50)
        self.ma200 = self.I(pta.sma, close, length=200)

    def next(self):
        # Current values
        current_close = self.data.Close[-1]
        current_ma10 = self.ma10[-1]
        current_ma20 = self.ma20[-1]
        current_ma50 = self.ma50[-1]
        current_ma200 = self.ma200[-1]
        
        # Previous values
        prev_ma10 = self.ma10[-2]
        prev_ma20 = self.ma20[-2]
        prev_ma50 = self.ma50[-2]
        prev_ma200 = self.ma200[-2]
        
        # Check slopes are positive (current MA > previous MA)
        slope10_pos = current_ma10 > prev_ma10
        slope20_pos = current_ma20 > prev_ma20
        slope50_pos = current_ma50 > prev_ma50
        slope200_pos = current_ma200 > prev_ma200
        
        # Check price above all MAs
        price_above_all = (current_close > current_ma10 and 
                          current_close > current_ma20 and 
                          current_close > current_ma50 and 
                          current_close > current_ma200)
        
        # Check the stacking conditions for 10 and 20 above 50
        ma10_above_50 = current_ma10 > current_ma50
        ma20_above_50 = current_ma20 > current_ma50
        
        # Overall bullish condition
        bullish_condition = (price_above_all and 
                           ma10_above_50 and 
                           ma20_above_50 and 
                           slope10_pos and 
                           slope20_pos and 
                           slope50_pos and 
                           slope200_pos)
        
        # Detect the entry into the bullish condition (first bar where it's true)
        if len(self.data) > 1:
            prev_bullish = False
            if len(self.data) >= 2:
                prev_close = self.data.Close[-2]
                prev_ma10_val = self.ma10[-2]
                prev_ma20_val = self.ma20[-2]
                prev_ma50_val = self.ma50[-2]
                prev_ma200_val = self.ma200[-2]
                
                prev_price_above_all = (prev_close > prev_ma10_val and 
                                       prev_close > prev_ma20_val and 
                                       prev_close > prev_ma50_val and 
                                       prev_close > prev_ma200_val)
                
                prev_ma10_above_50 = prev_ma10_val > prev_ma50_val
                prev_ma20_above_50 = prev_ma20_val > prev_ma50_val
                
                prev_ma10_prev = self.ma10[-3] if len(self.data) >= 3 else prev_ma10_val
                prev_ma20_prev = self.ma20[-3] if len(self.data) >= 3 else prev_ma20_val
                prev_ma50_prev = self.ma50[-3] if len(self.data) >= 3 else prev_ma50_val
                prev_ma200_prev = self.ma200[-3] if len(self.data) >= 3 else prev_ma200_val
                
                prev_slope10_pos = prev_ma10_val > prev_ma10_prev
                prev_slope20_pos = prev_ma20_val > prev_ma20_prev
                prev_slope50_pos = prev_ma50_val > prev_ma50_prev
                prev_slope200_pos = prev_ma200_val > prev_ma200_prev
                
                prev_bullish = (prev_price_above_all and 
                               prev_ma10_above_50 and 
                               prev_ma20_above_50 and 
                               prev_slope10_pos and 
                               prev_slope20_pos and 
                               prev_slope50_pos and 
                               prev_slope200_pos)
            
            bullish_signal = bullish_condition and not prev_bullish
            
            if bullish_signal:
                if not self.position:
                    self.buy()
        
        # Exit signal: if bullish condition breaks
