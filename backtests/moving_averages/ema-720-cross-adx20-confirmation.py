import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 7
    emaSlowLen = 20
    diLen = 14
    adxSmooth = 14
    adxThresh = 20.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)
        
        # Calculate ADX (which includes +DI, -DI, ADX)
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.diLen) or pd.DataFrame(index=close.index))
        
        # Extract ADX column from the result
        if isinstance(adx_result, pd.DataFrame) and not adx_result.empty:
            # ADX result has columns: ADX_14, DMP_14, DMN_14 (or similar naming)
            adx_cols = [col for col in adx_result.columns if 'ADX' in col.upper()]
            if adx_cols:
                self.adxVal = self.I(lambda: pta.adx(high, low, close, length=self.diLen)[adx_cols[0]] or pd.Series(0, index=close.index))
            else:
                self.adxVal = self.I(lambda: pd.Series(0, index=close.index))
        else:
            self.adxVal = self.I(lambda: pd.Series(0, index=close.index))

    def next(self):
        # Check if we have enough data
        if len(self.data) < max(self.emaFastLen, self.emaSlowLen, self.diLen) + self.adxSmooth:
            return
        
        # Crossover conditions
        bullCross = crossover(self.emaFast, self.emaSlow)
        bearCross = crossover(self.emaSlow, self.emaFast)
        
        # ADX validation
        adxOK = self.adxVal[-1] > self.adxThresh
        
        # Trading signals
        buySignal = bullCross and adxOK
        sellSignal = bearCross and adxOK
        
        # Execute trades
        if buySignal and not self.position:
            self.buy()
        elif sellSignal and self.position:
            self.position.close()


