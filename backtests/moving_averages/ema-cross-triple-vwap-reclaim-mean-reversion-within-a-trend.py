import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema9_len = 9
    ema20_len = 20
    h1_ema_len = 20
    atr_len = 14
    sl_multiplier = 0.5
    rr_ratio = 1.0
    lookback = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # M5 indicators
        self.ema9 = self.I(pta.ema, close, length=self.ema9_len)
        self.ema20 = self.I(pta.ema, close, length=self.ema20_len)
        self.m5_vwap = self.I(pta.vwap, close, volume=volume)

        # H1 indicators (simulated from current timeframe - in real trading would use request.security)
        self.h1_ema20 = self.I(pta.ema, close, length=self.h1_ema_len)
        self.h1_vwap = self.I(pta.vwap, close, volume=volume)
        self.h1_atr = self.I(pta.atr, high, low, close, length=self.atr_len)

        # VWAP reclaim logic helpers
        self.lowest_low = self.I(lambda: low.rolling(self.lookback).min())
        self.highest_high = self.I(lambda: high.rolling(self.lookback).max())

    def next(self):
        if len(self.data) < max(self.ema9_len, self.ema20_len, self.h1_ema_len, self.atr_len, self.lookback):
            return

        # Get current values
        ema9_val = self.ema9[-1]
        ema20_val = self.ema20[-1]
        m5_vwap_val = self.m5_vwap[-1]
        h1_close = self.data.Close[-1]
        h1_ema20_val = self.h1_ema20[-1]
        h1_vwap_val = self.h1_vwap[-1]
        h1_atr_val = self.h1_atr[-1]
        close_val = self.data.Close[-1]
        lowest_low_val = self.lowest_low[-1]
        highest_high_val = self.highest_high[-1]

        if (ema9_val is None or ema20_val is None or m5_vwap_val is None or
            h1_ema20_val is None or h1_vwap_val is None or h1_atr_val is None or
            lowest_low_val is None or highest_high_val is None):
            return

        # VWAP Reclaim logic
        was_below_vwap = lowest_low_val < m5_vwap_val
        reclaimed_vwap_long = was_below_vwap and close_val > m5_vwap_val

        was_above_vwap = highest_high_val > m5_vwap_val
        reclaimed_vwap_short = was_above_vwap and close_val < m5_vwap_val

        # H1 Trend Filters
        h1_buy_ok = h1_close > h1_ema20_val and h1_close > h1_vwap_val
        h1_sell_ok = h1_close < h1_ema20_val and h1_close < h1_vwap_val

        # Entry Triggers (EMA Cross)
        long_trigger = crossover(self.ema9, self.ema20)
        short_trigger = crossover(self.ema20, self.ema9)

        # Risk/Reward calculation
        if h1_atr_val is not None and h1_atr_val > 0:
            sl_dist = h1_atr_val * self.sl_multiplier
            tp_dist = sl_dist * self.rr_ratio
        else:
            sl_dist = 0
            tp_dist = 0

        # Long Entry
        if long_trigger and h1_buy_ok and reclaimed_vwap_long:
            if not self.position:
                self.buy()

        # Short Entry
        if short_trigger and h1_sell_ok and reclaimed_vwap_short:
            if self.position:
                self.position.close()
            self.sell()

        # Exit logic
        if self.position:
            if self.position.is_long:
                if close_val <= self.position.open_price - sl_dist or close_val >= self.position.open_price + tp_dist:
                    self.position.close()
            elif self.position.is_short:
                if close_val >= self.position.open_price + sl_dist or close_val <= self.position.open_price - tp_dist:
                    self.position.close()


