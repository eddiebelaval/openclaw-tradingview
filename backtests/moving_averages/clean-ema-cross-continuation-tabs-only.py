import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 9
    emaSlowLen = 21
    minBarsAfterCross = 3
    cooldownBars = 6
    pullbackMode = "Touch EMA9"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)

        self.zoneLow = self.I(
            lambda: pd.Series(
                np.minimum(self.emaFast, self.emaSlow),
                index=close.index
            )
        )
        self.zoneHigh = self.I(
            lambda: pd.Series(
                np.maximum(self.emaFast, self.emaSlow),
                index=close.index
            )
        )

        self.lastCrossBar = -10000
        self.lastContBuyBar = -10000
        self.lastContSellBar = -10000

    def next(self):
        if len(self.data) < max(self.emaFastLen, self.emaSlowLen) + 1:
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        emaFastVal = self.emaFast[-1]
        emaSlowVal = self.emaSlow[-1]
        zoneLowVal = self.zoneLow[-1]
        zoneHighVal = self.zoneHigh[-1]

        trendUp = emaFastVal > emaSlowVal
        trendDn = emaFastVal < emaSlowVal

        crossUp = crossover(self.emaFast, self.emaSlow)
        crossDn = crossover(self.emaSlow, self.emaFast)

        if crossUp or crossDn:
            self.lastCrossBar = len(self.data) - 1

        barsSinceCross = len(self.data) - 1 - self.lastCrossBar

        if self.pullbackMode == "Touch EMA9":
            touchBuy = low <= emaFastVal
            touchSell = high >= emaFastVal
        else:
            touchBuy = low <= zoneHighVal and high >= zoneLowVal
            touchSell = high >= zoneLowVal and low <= zoneHighVal

        confirmBuy = touchBuy and close > emaFastVal
        confirmSell = touchSell and close < emaFastVal

        canContBuy = len(self.data) - 1 - self.lastContBuyBar > self.cooldownBars
        canContSell = len(self.data) - 1 - self.lastContSellBar > self.cooldownBars

        contBuy = (
            trendUp
            and barsSinceCross >= self.minBarsAfterCross
            and canContBuy
            and confirmBuy
        )
        contSell = (
            trendDn
            and barsSinceCross >= self.minBarsAfterCross
            and canContSell
            and confirmSell
        )

        if crossUp:
            if not self.position:
                self.buy()

        elif crossDn:
            if self.position:
                self.sell()

        elif contBuy:
            if not self.position:
                self.buy()
                self.lastContBuyBar = len(self.data) - 1

        elif contSell:
            if self.position:
                self.sell()
                self.lastContSellBar = len(self.data) - 1


