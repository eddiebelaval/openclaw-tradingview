import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Donchian Channel parameters
    dc_length1 = 20
    dc_length2 = 50
    dc_length3 = 100
    
    # EMA parameters
    ema_len1 = 9
    ema_len2 = 21
    ema_len3 = 34
    ema_len4 = 89
    ema_len5 = 200
    ema_len6 = 500

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Donchian Channel 1
        self.dc_upper1 = self.I(lambda: high.rolling(self.dc_length1).max())
        self.dc_lower1 = self.I(lambda: low.rolling(self.dc_length1).min())
        self.dc_basis1 = self.I(lambda: (self.dc_upper1 + self.dc_lower1) / 2)
        
        # Donchian Channel 2
        self.dc_upper2 = self.I(lambda: high.rolling(self.dc_length2).max())
        self.dc_lower2 = self.I(lambda: low.rolling(self.dc_length2).min())
        self.dc_basis2 = self.I(lambda: (self.dc_upper2 + self.dc_lower2) / 2)
        
        # Donchian Channel 3
        self.dc_upper3 = self.I(lambda: high.rolling(self.dc_length3).max())
        self.dc_lower3 = self.I(lambda: low.rolling(self.dc_length3).min())
        self.dc_basis3 = self.I(lambda: (self.dc_upper3 + self.dc_lower3) / 2)
        
        # EMA Stack
        self.ema1 = self.I(pta.ema, close, length=self.ema_len1)
        self.ema2 = self.I(pta.ema, close, length=self.ema_len2)
        self.ema3 = self.I(pta.ema, close, length=self.ema_len3)
        self.ema4 = self.I(pta.ema, close, length=self.ema_len4)
        self.ema5 = self.I(pta.ema, close, length=self.ema_len5)
        self.ema6 = self.I(pta.ema, close, length=self.ema_len6)

    def next(self):
        # Buy signal: Price touches lower Donchian Channel 1 and is above EMA 1 and EMA 2
        if (len(self.data) > self.dc_length1 and 
            self.data.Low[-1] <= self.dc_lower1[-1] and 
            self.data.Close[-1] > self.ema1[-1] and 
            self.data.Close[-1] > self.ema2[-1]):
            if not self.position:
                self.buy()
        
        # Sell signal: Price touches upper Donchian Channel 1 or falls below EMA 1
        if (len(self.data) > self.dc_length1 and 
            (self.data.High[-1] >= self.dc_upper1[-1] or 
             self.data.Close[-1] < self.ema1[-1])):
            if self.position:
                self.position.close()
        
        # Additional sell on crossing below EMA 2
        if (len(self.data) > self.ema_len2 and 
            crossover(self.ema2, self.data.Close) and 
            self.position):
            self.position.close()


