class TvStrategy(Strategy):
    def init(self):
        # We'll calculate VIX indicators in next() since we need external data
        # For this backtest, we'll use the chart's own close as a proxy for VIX behavior
        # In a real scenario, you'd load actual VIX data
        close = pd.Series(self.data.Close)
        
        # Calculate moving averages
