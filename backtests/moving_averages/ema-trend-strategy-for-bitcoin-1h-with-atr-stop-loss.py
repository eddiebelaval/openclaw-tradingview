import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ma20 = self.I(pta.ema, close, length=20)
        self.ma50 = self.I(pta.ema, close, length=50)
        self.ma100 = self.I(pta.ema, close, length=100)
        self.ma200 = self.I(pta.ema, close, length=200)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Track entry point and stops
        self.entry_price = None
        self.stop_loss = None
        self.take_profit1 = None
        self.take_profit2 = None

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0
        
        # Check conditions
        long_cond = (crossover(self.ma20, self.ma50) and 
                    close > self.ma200[-1])
        short_cond = (crossover(self.ma50, self.ma20) and 
                     close < self.ma200[-1])
        
        # Entry logic
        if not self.position and long_cond:
            self.entry_price = close
            self.stop_loss = low - atr_val * 1.5
            self.take_profit1 = self.entry_price + (self.entry_price - self.stop_loss) * 1.5
            self.take_profit2 = self.entry_price + (self.entry_price - self.stop_loss) * 3.0
            self.buy()
        
        if not self.position and short_cond:
            self.entry_price = close
            self.stop_loss = high + atr_val * 1.5
            self.take_profit1 = self.entry_price - (self.stop_loss - self.entry_price) * 1.5
            self.take_profit2 = self.entry_price - (self.stop_loss - self.entry_price) * 3.0
            self.sell()
        
        # Exit logic
        if self.position:
            if self.position.is_long:
                if close <= self.stop_loss or close >= self.take_profit2:
                    self.position.close()
            elif self.position.is_short:
                if close >= self.stop_loss or close <= self.take_profit2:
                    self.position.close()