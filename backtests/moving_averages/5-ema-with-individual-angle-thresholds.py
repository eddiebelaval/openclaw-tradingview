import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Global parameters
    atr_length = 14
    
    # EMA 1 parameters
    ema1_length = 9
    ema1_lookback = 5
    ema1_buy_angle = 8.0
    ema1_sell_angle = -8.0
    
    # EMA 2 parameters
    ema2_length = 21
    ema2_lookback = 6
    ema2_buy_angle = 8.0
    ema2_sell_angle = -8.0
    
    # EMA 3 parameters
    ema3_length = 50
    ema3_lookback = 8
    ema3_buy_angle = 6.0
    ema3_sell_angle = -6.0
    
    # EMA 4 parameters
    ema4_length = 100
    ema4_lookback = 10
    ema4_buy_angle = 5.0
    ema4_sell_angle = -5.0
    
    # EMA 5 parameters
    ema5_length = 200
    ema5_lookback = 12
    ema5_buy_angle = 4.0
    ema5_sell_angle = -4.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema1 = self.I(pta.ema, close, length=self.ema1_length)
        self.ema2 = self.I(pta.ema, close, length=self.ema2_length)
        self.ema3 = self.I(pta.ema, close, length=self.ema3_length)
        self.ema4 = self.I(pta.ema, close, length=self.ema4_length)
        self.ema5 = self.I(pta.ema, close, length=self.ema5_length)
        
        # Calculate ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Calculate angles for each EMA
        self.angle1 = self.I(self._calc_angle, self.ema1, self.ema1_lookback, self.atr)
        self.angle2 = self.I(self._calc_angle, self.ema2, self.ema2_lookback, self.atr)
        self.angle3 = self.I(self._calc_angle, self.ema3, self.ema3_lookback, self.atr)
        self.angle4 = self.I(self._calc_angle, self.ema4, self.ema4_lookback, self.atr)
        self.angle5 = self.I(self._calc_angle, self.ema5, self.ema5_lookback, self.atr)
        
        # Track previous states for angle threshold crossing
        self.prev_angle1_state = None
        self.prev_angle2_state = None
        self.prev_angle3_state = None
        self.prev_angle4_state = None
        self.prev_angle5_state = None

    def _calc_angle(self, ema_series, lookback, atr_series):
        """Calculate angle for an EMA with ATR normalization"""
        if isinstance(ema_series, pd.Series):
            ema_values = ema_series.values
        else:
            ema_values = ema_series
        
        if isinstance(atr_series, pd.Series):
            atr_values = atr_series.values
        else:
            atr_values = atr_series
        
        angles = np.full(len(ema_values), np.nan)
        
        for i in range(lookback, len(ema_values)):
            slope = (ema_values[i] - ema_values[i - lookback]) / lookback
            atr_val = max(atr_values[i], 0.000001)
            normalized_slope = slope / atr_val
            angle = np.arctan(normalized_slope) * 180 / np.pi
            angles[i] = angle
        
        return pd.Series(angles)

    def _get_angle_state(self, angle, buy_level, sell_level):
        """Determine if angle is in BUY, SELL, or SIDEWAYS state"""
        if np.isnan(angle):
            return None
        if angle >= buy_level:
            return "BUY"
        elif angle <= sell_level:
            return "SELL"
        else:
            return "SIDEWAYS"

    def next(self):
        if len(self.data) < max(self.ema1_length, self.ema2_length, self.ema3_length, 
                               self.ema4_length, self.ema5_length, self.atr_length):
            return
        
        # Get current angles
        current_angle1 = self.angle1[-1] if len(self.angle1) > 0 else np.nan
        current_angle2 = self.angle2[-1] if len(self.angle2) > 0 else np.nan
        current_angle3 = self.angle3[-1] if len(self.angle3) > 0 else np.nan
        current_angle4 = self.angle4[-1] if len(self.angle4) > 0 else np.nan
        current_angle5 = self.angle5[-1] if len(self.angle5) > 0 else np.nan
        
        # Get states
        state1 = self._get_angle_state(current_angle1, self.ema1_buy_angle, self.ema1_sell_angle)
        state2 = self._get_angle_state(current_angle2, self.ema2_buy_angle, self.ema2_sell_angle)
        state3 = self._get_angle_state(current_angle3, self.ema3_buy_angle, self.ema3_sell_angle)
        state4 = self._get_angle_state(current_angle4, self.ema4_buy_angle, self.ema4_sell_angle)
        state5 = self._get_angle_state(current_angle5, self.ema5_buy_angle, self.ema5_sell_angle)
        
        # Count BUY and SELL signals
        buy_count = sum([1 for s in [state1, state2, state3, state4, state5] if s == "BUY"])
        sell_count = sum([1 for s in [state1, state2, state3, state4, state5] if s == "SELL"])
        
        # Entry logic: Buy when at least 3 EMAs show BUY signal
        if not self.position and buy_count >= 3:
            self.buy()
        
        # Exit logic: Sell when at least 3 EMAs show SELL signal
        if self.position and sell_count >= 3:
            self.sell()
        
        # Update previous states
        self.prev_angle1_state = state1
        self.prev_angle2_state = state2
        self.prev_angle3_state = state3
        self.prev_angle4_state = state4
        self.prev_angle5_state = state5