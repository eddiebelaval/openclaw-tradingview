import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adx_mode = "Scaled"
    min_level = 20
    adx_len = 14
    di_len = 14
    ma1_len = 20
    ma2_len = 50
    ma3_len = 100
    ma_type = "SMA"

    def init(self):
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.di_len))
        
        def get_adx_line():
            adx_calc = pta.adx(high, low, close, length=self.di_len)
            if adx_calc is None:
                return pd.Series(50, index=close.index)
            raw_adx = adx_calc.iloc[:, 0]
            
            if self.adx_mode == "Original":
                return raw_adx
            elif self.adx_mode == "Clipped":
                return np.maximum(raw_adx, self.min_level)
            else:
                scaling_factor = (100 - self.min_level) / 100
                return self.min_level + raw_adx * scaling_factor
        
        self.adx = self.I(get_adx_line)
        
        def get_ma1():
            adx_line = get_adx_line()
            if self.ma_type == "SMA":
                return pta.sma(adx_line, length=self.ma1_len)
            elif self.ma_type == "EMA":
                return pta.ema(adx_line, length=self.ma1_len)
            elif self.ma_type == "WMA":
                return pta.wma(adx_line, length=self.ma1_len)
            else:
                return pta.hma(adx_line, length=self.ma1_len)
        
        def get_ma2():
            adx_line = get_adx_line()
            if self.ma_type == "SMA":
                return pta.sma(adx_line, length=self.ma2_len)
            elif self.ma_type == "EMA":
                return pta.ema(adx_line, length=self.ma2_len)
            elif self.ma_type == "WMA":
                return pta.wma(adx_line, length=self.ma2_len)
            else:
                return pta.hma(adx_line, length=self.ma2_len)
        
        def get_ma3():
            adx_line = get_adx_line()
            if self.ma_type == "SMA":
                return pta.sma(adx_line, length=self.ma3_len)
            elif self.ma_type == "EMA":
                return pta.ema(adx_line, length=self.ma3_len)
            elif self.ma_type == "WMA":
                return pta.wma(adx_line, length=self.ma3_len)
            else:
                return pta.hma(adx_line, length=self.ma3_len)
        
        self.ma1 = self.I(get_ma1)
        self.ma2 = self.I(get_ma2)
        self.ma3 = self.I(get_ma3)

    def next(self):
        if len(self.data) < max(self.ma1_len, self.ma2_len, self.ma3_len) + self.adx_len + 10:
            return
        
        current_adx = self.adx[-1]
        
        if not self.position:
            if current_adx > 30 and crossover(self.ma1, self.ma2):
                self.buy()
            elif current_adx > 25 and crossover(self.adx, 25):
                self.buy()
        else:
            if current_adx < 20:
                self.sell()
            elif crossover(self.ma2, self.ma1):
                self.sell()