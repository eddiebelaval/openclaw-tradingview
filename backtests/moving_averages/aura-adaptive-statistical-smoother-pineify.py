import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 20
    smooth = 10
    mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Forward EMA
        ema1 = self.I(pta.ema, close, length=self.smooth)
        
        # Backward EMA approximation (zero-lag)
        def calc_ema2(close_series):
            ema1_vals = pta.ema(close_series, length=self.smooth)
            ema2 = ema1_vals.copy()
            alpha = 2 / (self.smooth + 1)
            for idx in range(len(ema1_vals)):
                for i in range(1, self.length):
                    if idx >= i:
                        ema2.iloc[idx] += alpha * (ema1_vals.iloc[idx - i] - ema2.iloc[idx])
            return ema2
        
        target = self.I(calc_ema2, close)
        
        # R-squared calculation
        def calc_r2(close_series):
            r2_series = pd.Series(index=close_series.index, dtype=float)
            for i in range(len(close_series)):
                if i < self.length:
                    r2_series.iloc[i] = 0.0
                else:
                    window_close = close_series.iloc[i - self.length + 1:i + 1]
                    window_idx = np.arange(self.length)
                    corr = np.corrcoef(window_close, window_idx)[0, 1]
                    if np.isnan(corr):
                        r2_series.iloc[i] = 0.0
                    else:
                        r2_series.iloc[i] = corr ** 2
            return r2_series
        
        self.r2 = self.I(calc_r2, close)
        
        # Standard deviation
        stdev = self.I(lambda: pta.stdev(close, length=self.length) * self.mult)
        
        # Aura MA calculation
        def calc_aura_ma(close_series, target_series, r2_series):
            aura_ma = pd.Series(index=close_series.index, dtype=float)
            aura_ma.iloc[0] = close_series.iloc[0]
            os = 0.0
            
            for i in range(1, len(close_series)):
                abs_diff = abs(target_series.iloc[i] - target_series.iloc[i - 1])
                r2_val = r2_series.iloc[i]
                
                if r2_val > 0.5:
                    os = 1.0 if close_series.iloc[i] > target_series.iloc[i] else (-1.0 if close_series.iloc[i] < target_series.iloc[i] else os)
                    aura_ma.iloc[i] = r2_val * target_series.iloc[i] + (1 - r2_val) * aura_ma.iloc[i - 1]
                else:
                    aura_ma.iloc[i] = aura_ma.iloc[i - 1] - abs_diff * os
            
            return aura_ma
        
        self.aura_ma = self.I(calc_aura_ma, close, target, self.r2)
        self.upper = self.I(lambda: self.aura_ma + stdev)
