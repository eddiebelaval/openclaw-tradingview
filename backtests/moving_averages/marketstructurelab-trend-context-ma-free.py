import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    maLen = 100
    maType = 'EMA'
    t3Factor = 0.7
    atrLen = 10
    atrMult = 0.5
    useAltAtr = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate base MA based on type
        if self.maType == 'SMA':
            self.baseMA = self.I(pta.sma, close, length=self.maLen)
        elif self.maType == 'EMA':
            self.baseMA = self.I(pta.ema, close, length=self.maLen)
        elif self.maType == 'WMA':
            self.baseMA = self.I(pta.wma, close, length=self.maLen)
        else:
            self.baseMA = self.I(pta.ema, close, length=self.maLen)
        
        # Calculate ATR
        if self.useAltAtr:
            atr_result = self.I(pta.atr, high, low, close, length=self.atrLen)
        else:
            tr = self.I(lambda: pd.Series(
                np.maximum(
                    np.maximum(high - low, np.abs(high - close.shift(1))),
                    np.abs(low - close.shift(1))
                )
            ))
            atr_result = self.I(pta.sma, tr, length=self.atrLen)
        
        self.atrVal = atr_result
        
        # Initialize trend direction
        self.trendDir = 1
        self.upperBand_prev = None
        self.lowerBand_prev = None

    def next(self):
        if len(self.data) < self.maLen + self.atrLen + 5:
            return
        
        close_curr = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        baseMA = self.baseMA[-1]
        atrVal = self.atrVal[-1]
        
        if baseMA is None or atrVal is None or np.isnan(baseMA) or np.isnan(atrVal):
            return
        
        # Calculate bands
        upperBand = baseMA - self.atrMult * atrVal
        lowerBand = baseMA + self.atrMult * atrVal
        
        # Adjust bands based on previous values
        if self.upperBand_prev is not None:
            if close_prev > self.upperBand_prev:
                upperBand = max(upperBand, self.upperBand_prev)
        
        if self.lowerBand_prev is not None:
            if close_prev < self.lowerBand_prev:
                lowerBand = min(lowerBand, self.lowerBand_prev)
        
        # Determine trend direction
        prev_trendDir = self.trendDir
        
        if self.trendDir == -1 and close_curr > self.lowerBand_prev:
            self.trendDir = 1
        elif self.trendDir == 1 and close_curr < self.upperBand_prev:
            self.trendDir = -1
        
        # Generate signals
        buySignal = (self.trendDir == 1 and prev_trendDir == -1)
        sellSignal = (self.trendDir == -1 and prev_trendDir == 1)
        
        # Execute trades
        if buySignal and not self.position:
            self.buy()
        elif sellSignal and self.position:
            self.sell()
        
        # Store previous band values
        self.upperBand_prev = upperBand
        self.lowerBand_prev = lowerBand


