import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    preset = "D1"
    lenMid_input = 20
    lenOffset_input = 20
    offsetMid_input = -10
    offsetUp_input = -10
    offsetDown_input = -10
    usePercent = False
    distValue = 90.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Preset configurations
        preset_len_D1 = 20
        preset_off_D1 = -10
        preset_len_H4 = 40
        preset_off_H4 = -20
