import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Default parameters from the Pine Script
    fastLenInput = 20
    slowLenInput = 50
    adxLenInput = 14
    adxThreshInput = 20
    useRsiFilter = True
    useVolFilter = False
    useEmaFilter = False
    tp1MultInput = 1.5
    tp2MultInput = 3.0
    stopMultInput = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Trend Components
        self.fastEma = self.I(pta.ema, close, length=self.fastLenInput)
        self.slowEma = self.I(pta.ema, close, length=self.slowLenInput)
        self.ema200 = self.I(pta.ema, close, length=200)
        
        # ADX calculation
        adx_result = self.I(
            lambda c, h, l: pta.adx(h, l, c, length=self.adxLenInput),
            close, high, low
        )
        self.adx = self.I(
            lambda: adx_result.iloc[:, 2] if adx_result is not None else pd.Series(0, index=close.index)
        )

        # Confluence Components
        self.rsi = self.I(pta.rsi, close, length=14)
        self.volAvg = self.I(pta.sma, volume, length=20)

        # ATR for Levels
        self.atr = self.I(pta.atr, high, low, close, length=14)

        # State tracking
        self.trendDir = 0
        self.tp1_level = None
        self.tp2_level = None
        self.initialSL = None
        self.trailingStop = None
        self.entry_price = None

    def next(self):
        if len(self.data) < 50:
            return

        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        volume_val = self.data.Volume[-1]

        fastEma_val = self.fastEma[-1]
        slowEma_val = self.slowEma[-1]
        ema200_val = self.ema200[-1]
        adx_val = self.adx[-1] if self.adx[-1] is not None else 0
        rsi_val = self.rsi[-1] if self.rsi[-1] is not None else 50
        volAvg_val = self.volAvg[-1] if self.volAvg[-1] is not None else volume_val
        atr_val = self.atr[-1] if self.atr[-1] is not None else 0

        # Filter Logic
        rsiLong = not self.useRsiFilter or rsi_val > 50
        rsiShort = not self.useRsiFilter or rsi_val < 50
        volCond = not self.useVolFilter or volume_val > volAvg_val
        emaLong = not self.useEmaFilter or close_val > ema200_val
        emaShort = not self.useEmaFilter or close_val < ema200_val

        # Core Trend Logic
        trendBull = fastEma_val > slowEma_val and adx_val > self.adxThreshInput
        trendBear = fastEma_val < slowEma_val and adx_val > self.adxThreshInput

        # Previous bar values
        if len(self.data) >= 2:
            fastEma_prev = self.fastEma[-2]
            slowEma_prev = self.slowEma[-2]
            rsi_prev = self.rsi[-2] if self.rsi[-2] is not None else 50
            volAvg_prev = self.volAvg[-2] if self.volAvg[-2] is not None else self.data.Volume[-2]
            ema200_prev = self.ema200[-2]
            close_prev = self.data.Close[-2]

            trendBull_prev = fastEma_prev > slowEma_prev and self.adx[-2] > self.adxThreshInput if self.adx[-2] is not None else False
            rsiLong_prev = not self.useRsiFilter or rsi_prev > 50
            volCond_prev = not self.useVolFilter or self.data.Volume[-2] > volAvg_prev
            emaLong_prev = not self.useEmaFilter or close_prev > ema200_prev

            trendBear_prev = fastEma_prev < slowEma_prev and self.adx[-2] > self.adxThreshInput if self.adx[-2] is not None else False
            rsiShort_prev = not self.useRsiFilter or rsi_prev < 50
            emaShort_prev = not self.useEmaFilter or close_prev < ema200_prev

            bullSignal = trendBull and rsiLong and volCond and emaLong and not (trendBull_prev and rsiLong_prev and volCond_prev and emaLong_prev)
            bearSignal = trendBear and rsiShort and volCond and emaShort and not (trendBear_prev and rsiShort_prev and volCond_prev and emaShort_prev)
        else:
            bullSignal = False
            bearSignal = False

        # Signal Processing and Trade Management
        if bullSignal and self.trendDir == 0:
            self.trendDir = 1
            self.tp1_level = high_val + (atr_val * self.tp1MultInput)
            self.tp2_level = high_val + (atr_val * self.tp2MultInput)
            self.initialSL = low_val - (atr_val * self.stopMultInput)
            self.trailingStop = self.initialSL
            self.entry_price = close_val
            self.buy()

        elif bearSignal and self.trendDir == 0:
            self.trendDir = -1
            self.tp1_level = low_val - (atr_val * self.tp1MultInput)
            self.tp2_level = low_val - (atr_val * self.tp2MultInput)
            self.initialSL = high_val + (atr_val * self.stopMultInput)
            self.trailingStop = self.initialSL
            self.entry_price = close_val
            self.sell()

        elif self.trendDir == 1:
            self.trailingStop = max(self.trailingStop, low_val - (atr_val * self.stopMultInput))
            if low_val <= self.trailingStop or fastEma_val < slowEma_val:
                self.trendDir = 0
                self.tp1_level = None
                self.tp2_level = None
                self.initialSL = None
                self.trailingStop = None
                self.entry_price = None
                if self.position:
                    self.position.close()

        elif self.trendDir == -1:
            self.trailingStop = min(self.trailingStop, high_val + (atr_val * self.stopMultInput))
            if high_val >= self.trailingStop or fastEma_val > slowEma_val:
                self.trendDir = 0
                self.tp1_level = None
                self.tp2_level = None
                self.initialSL = None
                self.trailingStop = None
                self.entry_price = None
                if self.position:
                    self.position.close()

        # Take Profit Logic
        if self.trendDir == 1 and self.position:
            if self.tp2_level and close_val >= self.tp2_level:
                self.position.close()
                self.trendDir = 0
            elif self.tp1_level and close_val >= self.tp1_level:
                self.position.close()
                self.trendDir = 0

        elif self.trendDir == -1 and self.position:
            if self.tp2_level and close_val <= self.tp2_level:
                self.position.close()
                self.trendDir = 0
            elif self.tp1_level and close_val <= self.tp1_level:
                self.position.close()
                self.trendDir = 0


