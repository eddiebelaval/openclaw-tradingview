import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLength = 14
    emaLength = 50
    rsiLength = 14
    atrMult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate indicators
        self.atrValue = self.I(pta.atr, high, low, close, length=self.atrLength)
        self.emaValue = self.I(pta.ema, close, length=self.emaLength)
        self.rsiValue = self.I(pta.rsi, close, length=self.rsiLength)
        
        # Dynamic bands
        self.upperLevel = self.I(lambda: self.emaValue[-len(self.data.Close):] + self.atrValue[-len(self.data.Close):] * self.atrMult)
        self.lowerLevel = self.I(lambda: self.emaValue[-len(self.data.Close):] - self.atrValue[-len(self.data.Close):] * self.atrMult)
        
        # Trend state tracking
        self.trend = 0
        self.prev_trend = 0

    def next(self):
        # Get current values
        current_close = self.data.Close[-1]
        current_rsi = self.rsiValue[-1]
        current_upper = self.upperLevel[-1]
        current_lower = self.lowerLevel[-1]
        
        # Handle NaN values from indicators
        if pd.isna(current_rsi) or pd.isna(current_upper) or pd.isna(current_lower):
            return
        
        # Trend logic
        bullTrend = current_close > current_upper and current_rsi > 55
        bearTrend = current_close < current_lower and current_rsi < 45
        
        # Update persistent trend state
        self.prev_trend = self.trend
        if bullTrend:
            self.trend = 1
        elif bearTrend:
            self.trend = -1
        
        # Signals on trend change
        buySignal = self.trend == 1 and self.prev_trend != 1
        sellSignal = self.trend == -1 and self.prev_trend != -1
        
        # Execute trades
        if buySignal and not self.position:
            self.buy()
        elif sellSignal and self.position:
            self.position.close()