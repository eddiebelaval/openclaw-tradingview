import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    st1_period = 14
    st1_mult = 3.0
    st2_period = 12
    st2_mult = 2.0
    ema_fast_len = 20
    ema_slow_len = 50
    bos_period = 5
    use_bos = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # SuperTrend 1
        self.st1_val, self.st1_dir = self.I(self._supertrend, high, low, close, self.st1_period, self.st1_mult)

        # SuperTrend 2
        self.st2_val, self.st2_dir = self.I(self._supertrend, high, low, close, self.st2_period, self.st2_mult)

        # EMA Ribbon
        self.ema_fast = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema_slow = self.I(pta.ema, close, length=self.ema_slow_len)

        # BoS Levels
        self.high_target = self.I(lambda: high.shift(1).rolling(self.bos_period).max())
        self.low_target = self.I(lambda: low.shift(1).rolling(self.bos_period).min())

    def _supertrend(self, high, low, close, period, mult):
        hl_avg = (high + low) / 2
        atr = pta.atr(high, low, close, length=period)
        
        if atr is None:
            return pd.Series(0, index=close.index), pd.Series(0, index=close.index)
        
        basic_ub = hl_avg + mult * atr
        basic_lb = hl_avg - mult * atr
        
        final_ub = pd.Series(index=close.index, dtype=float)
        final_lb = pd.Series(index=close.index, dtype=float)
        st_val = pd.Series(index=close.index, dtype=float)
        st_dir = pd.Series(index=close.index, dtype=float)
        
        final_ub.iloc[0] = basic_ub.iloc[0]
        final_lb.iloc[0] = basic_lb.iloc[0]
        st_val.iloc[0] = close.iloc[0]
        st_dir.iloc[0] = 0
        
        for i in range(1, len(close)):
            final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
            final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
            
            if st_dir.iloc[i-1] >= 0:
                if close.iloc[i] <= final_lb.iloc[i]:
                    st_val.iloc[i] = final_ub.iloc[i]
                    st_dir.iloc[i] = 1
                else:
                    st_val.iloc[i] = final_lb.iloc[i]
                    st_dir.iloc[i] = -1
            else:
                if close.iloc[i] >= final_ub.iloc[i]:
                    st_val.iloc[i] = final_lb.iloc[i]
                    st_dir.iloc[i] = -1
                else:
                    st_val.iloc[i] = final_ub.iloc[i]
                    st_dir.iloc[i] = 1
        
        return st_val, st_dir

    def next(self):
        if len(self.data) < max(self.st1_period, self.st2_period, self.ema_slow_len, self.bos_period) + 1:
            return

        ribbon_bullish = self.ema_fast[-1] > self.ema_slow[-1]

        bos_long_ok = self.data.Close[-1] > self.high_target[-1]
        bos_short_ok = self.data.Close[-1] < self.low_target[-1]

        long_entry = (
            crossover(self.st1_dir, 0) and
            self.st2_dir[-1] < 0 and
            ribbon_bullish and
            (not self.use_bos or bos_long_ok)
        )

        short_entry = (
            crossover(0, self.st1_dir) and
            self.st2_dir[-1] > 0 and
            not ribbon_bullish and
            (not self.use_bos or bos_short_ok)
        )

        if long_entry and not self.position:
            self.buy()
        elif short_entry and self.position:
            self.position.close()