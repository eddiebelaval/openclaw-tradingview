import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema1Len = 5
    ema2Len = 20
    ema3Len = 50
    ema4Len = 90
    ema5Len = 140
    ema6Len = 200
    
    useEma1 = True
    useEma2 = True
    useEma3 = True
    useEma4 = True
    useEma5 = True
    useEma6 = True

