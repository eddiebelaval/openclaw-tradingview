        bull_bias = True
        bear_bias = True
        
        if len(ema_vals) >= 2:
            for i in range(len(ema_vals) - 1):
                if ema_vals[i] <= ema_vals[i + 1]:
                    bull_bias = False
                if ema_vals[i] >= ema_vals[i + 1]:
                    bear_bias = False
        
        new_bull_bias = bull_bias and not self.prev_bull_bias
        new_bear_bias = bear_bias and not self.prev_bear_bias
        
