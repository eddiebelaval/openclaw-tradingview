import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Session Filter
    useSessionFilter = True
    sessionStartHour = 9
    sessionStartMin = 30
    sessionEndHour = 15
    sessionEndMin = 30
    
    # HTF Trend Filter
    useHTF = True
    htfEmaLen = 50
    
    # VWAP Filter
    useVWAP = True
    
    # MACD Entry Trigger
    macdFast = 12
    macdSlow = 26
    macdSignal = 9
    
    # Volume Confirmation
    useVolFilter = True
    volSmaLen = 20
    volMultReq = 1.2
    
    # Risk Management
    atrLength = 14
    slMult = 1.5
    tpRatio = 2.0
    
    # Trailing Stop
    useTrail = True
    trailTriggerR = 1.0
    trailOffsetATR = 0.75

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # VWAP
        hlc3 = (high + low + close) / 3
        self.vwap = self.I(lambda: pta.vwap(hlc3, volume) or pd.Series(np.nan, index=close.index))
        
        # HTF EMA (simulate with regular EMA on current timeframe for backtest)
        self.htf_ema = self.I(pta.ema, close, length=self.htfEmaLen)
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal))
        self.macd_line = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal)['MACD_' + str(self.macdFast) + '_' + str(self.macdSlow) + '_' + str(self.macdSignal)] if pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal) is not None else pd.Series(np.nan, index=close.index))
        self.macd_signal = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal)['MACDh_' + str(self.macdFast) + '_' + str(self.macdSlow) + '_' + str(self.macdSignal)] if pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal) is not None else pd.Series(np.nan, index=close.index))
        self.macd_hist = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal)['MACDh_' + str(self.macdFast) + '_' + str(self.macdSlow) + '_' + str(self.macdSignal)] if pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal) is not None else pd.Series(np.nan, index=close.index))
        
        # Volume SMA
        self.vol_sma = self.I(pta.sma, volume, length=self.volSmaLen)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # Track signal state
        self.signal_dir = 0
        self.sig_entry_price = None
        self.sig_sl = None
        self.sig_tp = None
        self.sig_trail_stop = None
        self.bars_since_signal = 0

    def next(self):
        if len(self.data) < max(self.macdSlow, self.atrLength, self.volSmaLen, self.htfEmaLen) + 5:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        # Session Filter (simplified for backtest - check if within session window)
        current_time = pd.Timestamp(self.data.index[-1])
        current_hour = current_time.hour
        current_min = current_time.minute
        time_in_mins = current_hour * 60 + current_min
        session_start_mins = self.sessionStartHour * 60 + self.sessionStartMin
        session_end_mins = self.sessionEndHour * 60 + self.sessionEndMin
        in_session = time_in_mins >= session_start_mins and time_in_mins < session_end_mins
        session_ok = in_session if self.useSessionFilter else True
        
        # Get current indicator values
        try:
            htf_ema_val = self.htf_ema[-1]
            vwap_val = self.vwap[-1]
            macd_hist_val = self.macd_hist[-1]
            macd_hist_prev = self.macd_hist[-2] if len(self.macd_hist) > 1 else 0
            macd_hist_prev2 = self.macd_hist[-3] if len(self.macd_hist) > 2 else 0
            vol_sma_val = self.vol_sma[-1]
            atr_val = self.atr[-1]
        except:
            return
        
        if np.isnan(htf_ema_val) or np.isnan(vwap_val) or np.isnan(macd_hist_val) or np.isnan(atr_val):
            return
        
        # MACD Histogram Reversal Logic
        hist_rising_from_neg = macd_hist_val > macd_hist_prev and macd_hist_prev <= 0 and macd_hist_val > 0
        hist_bull_reversal = macd_hist_val > 0 and macd_hist_prev <= 0 and macd_hist_prev2 <= 0
        long_momentum = hist_rising_from_neg or hist_bull_reversal
        
        hist_falling_from_pos = macd_hist_val < macd_hist_prev and macd_hist_prev >= 0 and macd_hist_val < 0
        hist_bear_reversal = macd_hist_val < 0 and macd_hist_prev >= 0 and macd_hist_prev2 >= 0
        short_momentum = hist_falling_from_pos or hist_bear_reversal
        
        # Volume Confirmation
        vol_spike = volume >= (vol_sma_val * self.volMultReq) if vol_sma_val > 0 else False
        volume_ok = vol_spike if self.useVolFilter else True
        
        # HTF and VWAP Filters
        htf_bullish = close > htf_ema_val if self.useHTF else True
        htf_bearish = close < htf_ema_val if self.useHTF else True
        vwap_bullish = close > vwap_val if self.useVWAP else True
        vwap_bearish = close < vwap_val if self.useVWAP else True
        
        # Signal Conditions
        long_signal = htf_bullish and vwap_bullish and long_momentum and volume_ok and session_ok
        short_signal = htf_bearish and vwap_bearish and short_momentum and volume_ok and session_ok
        
