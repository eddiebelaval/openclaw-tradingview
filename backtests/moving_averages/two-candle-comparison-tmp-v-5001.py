import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        
        # Moving Averages
        self.ma1 = self.I(pta.ema, close, length=20)
        self.ma2 = self.I(pta.ema, close, length=50)
        self.ma3 = self.I(pta.ema, close, length=100)
        self.ma4 = self.I(pta.ema, close, length=200)
        
        # SMI Calculation
        a = 5
        b = 3
        
        def calc_smi(high_series, low_series, close_series, k_len, d_len):
            ll = high_series.rolling(k_len).min()
            hh = high_series.rolling(k_len).max()
            diff = hh - ll
            rdiff = close_series - (hh + ll) / 2
            
            avgrel = pta.ema(pta.ema(rdiff, length=d_len), length=d_len)
            avgdiff = pta.ema(pta.ema(diff, length=d_len), length=d_len)
            
            smi = pd.Series(np.where(avgdiff != 0, (avgrel / (avgdiff / 2) * 100), 0), index=close_series.index)
            smi_signal = pta.ema(smi, length=d_len)
            
            return smi, smi_signal
        
        self.smi_data = self.I(lambda: calc_smi(high, low, close, a, b)[0])
        self.smi_signal = self.I(lambda: calc_smi(high, low, close, a, b)[1])
        
        # Volume SMA for spike detection
        self.vol_sma = self.I(pta.sma, volume, length=13)
        
        # Store previous bar data for comparison
        self.prev_high = None
        self.prev_low = None
        self.prev_close = None
        self.prev_open = None

    def get_close_comparison(self, open_curr, close_curr, high_curr, low_curr,
                            prev_high, prev_low, prev_open, prev_close):
        if (low_curr <= prev_low and prev_close < prev_open and close_curr > open_curr and
            (open_curr - low_curr) >= (high_curr - close_curr) and close_curr > prev_open and
            (open_curr - low_curr) < 2 * (close_curr - open_curr)):
            return 'Bull'
        elif (high_curr >= prev_high and prev_close > prev_open and close_curr < open_curr and
              (high_curr - open_curr) >= (close_curr - low_curr) and close_curr < prev_open and
              (high_curr - open_curr) < 2 * (open_curr - close_curr)):
            return 'Bear'
        else:
            return 'Range'

    def next(self):
        if len(self.data) < 2:
            self.prev_high = self.data.High[-1]
            self.prev_low = self.data.Low[-1]
            self.prev_close = self.data.Close[-1]
            self.prev_open = self.data.Open[-1]
            return
        
        # Current bar data
        open_curr = self.data.Open[-1]
        close_curr = self.data.Close[-1]
        high_curr = self.data.High[-1]
        low_curr = self.data.Low[-1]
        volume_curr = self.data.Volume[-1]
        
        # Previous bar data
        prev_high = self.data.High[-2]
        prev_low = self.data.Low[-2]
        prev_close = self.data.Close[-2]
        prev_open = self.data.Open[-2]
        
        # Get close comparison
        close_comp = self.get_close_comparison(open_curr, close_curr, high_curr, low_curr,
                                               prev_high, prev_low, prev_open, prev_close)
        
        # Volume spike filter
        vol_spike_threshold = 0.5
        vol_sma_val = self.vol_sma[-1] if not np.isnan(self.vol_sma[-1]) else 1
        vol_spike = volume_curr > (vol_sma_val * (1 + vol_spike_threshold)) if vol_sma_val > 0 else False
        
        # Trading logic based on close comparison and volume
        if close_comp == 'Bull' and vol_spike:
            if not self.position:
                self.buy()
        elif close_comp == 'Bear' and vol_spike:
            if self.position:
                self.sell()
        
        # Update previous bar data for next iteration
        self.prev_high = high_curr
        self.prev_low = low_curr
        self.prev_close = close_curr
        self.prev_open = open_curr


