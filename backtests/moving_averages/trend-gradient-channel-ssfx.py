class TvStrategy(Strategy):
    ema_len = 34

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMA channels
        self.ema_high = self.I(pta.ema, high, length=self.ema_len)
        self.ema_low = self.I(pta.ema, low, length=self.ema_len)
        
        # Calculate gradient levels
        self.lvl1 = self.I(lambda: self.ema_low + (self.ema_high - self.ema_low) * 0.20)
        self.lvl2 = self.I(lambda: self.ema_low + (self.ema_high - self.ema_low) * 0.40)
        self.lvl3 = self.I(lambda: self.ema_low + (self.ema_high - self.ema_low) * 0.60)
        self.lvl4 = self.I(lambda: self.ema_low + (self.ema_high - self.ema_low) * 0.80)

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        ema_high = self.ema_high[-1]
        ema_low = self.ema_low[-1]
        
        # Buy when price touches lower EMA channel and shows reversal
        if len(self) > 1:
            prev_low = self.data.Low[-2]
            if prev_low < ema_low and low >= ema_low and close > self.data.Close[-2]:
                if not self.position:
                    self.buy()
        
        # Sell when price touches upper EMA channel and shows reversal
        if len(self) > 1:
            prev_high = self.data.High[-2]
            if prev_high > ema_high and high <= ema_high and close < self.data.Close[-2]:
                if self.position:
                    self.sell()
        
        # Stop loss: if price breaks significantly below lower EMA
        if self.position and low < ema_low - (ema_high - ema_low) * 0.1:
            self.sell()
        
