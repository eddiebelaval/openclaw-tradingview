import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Moving Average Settings
    sma_long_len = 200
    sma_short_len = 50
    slope_period = 20
    short_momentum = 5
    
    # Transition Settings
    orange_bars = 4

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate SMAs
        self.sma_long = self.I(pta.sma, close, length=self.sma_long_len)
        self.sma_short = self.I(pta.sma, close, length=self.sma_short_len)
        
        # Calculate slope of long SMA
        self.sma_long_slope = self.I(self._calculate_slope, self.sma_long, self.slope_period)
        
        # Track regime state
        self.regime = None
        self.orange_count = 0
        self.prev_regime = None

    def _calculate_slope(self, sma_series, period):
        """Calculate slope of SMA over period bars"""
        result = pd.Series(np.nan, index=sma_series.index)
        for i in range(len(sma_series)):
            if i >= period:
                result.iloc[i] = sma_series.iloc[i] - sma_series.iloc[i - period]
            else:
                result.iloc[i] = np.nan
        return result

    def next(self):
        close = self.data.Close[-1]
        sma_long = self.sma_long[-1]
        sma_short = self.sma_short[-1]
        sma_long_slope = self.sma_long_slope[-1]
        
        # Check for NaN values
        if pd.isna(sma_long) or pd.isna(sma_short) or pd.isna(sma_long_slope):
            return
        
        # Base conditions
        is_red = close < sma_long and close < sma_short
        is_green = (close > sma_long and sma_long_slope > 0 and 
                   len(self) > self.short_momentum and 
                   sma_short > self.sma_short[-1 - self.short_momentum])
        is_yellow = not is_green and not is_red
        
        # Transition detection: Red → Non-Red
        red_to_non_red = (not is_red) and (self.prev_regime == 0 or (len(self) > 1 and self._was_red_previous()))
        
        # Orange counter (quarantine period)
        if is_red:
            self.orange_count = 0
        elif red_to_non_red:
            self.orange_count = 1
        elif self.orange_count > 0 and self.orange_count < self.orange_bars:
            self.orange_count += 1
        else:
            self.orange_count = 0
        
        # Orange condition
        is_orange = self.orange_count > 0 and self.orange_count <= self.orange_bars
        
        # Final regime (Orange has priority over Green)
        if is_orange:
            regime = 1  # ORANGE
        elif is_green:
            regime = 3  # GREEN
        elif is_red:
            regime = 0  # RED
        else:
            regime = 2  # YELLOW
        
        # Store current regime for next iteration
        self.prev_regime = regime
        
        # Trading logic based on regime
        # Buy on Green entry
        if regime == 3 and self.prev_regime != 3:
            if not self.position:
                self.buy()
        
        # Sell on Red entry or Orange transition
        if (regime == 0 or regime == 1) and self.position:
            self.sell()
        
        # Also exit on Yellow if we want to be conservative
        if regime == 2 and self.position:
            self.sell()

    def _was_red_previous(self):
        """Check if previous bar was in red regime"""
        if len(self) < 2:
            return False
        
        close_prev = self.data.Close[-2]
        sma_long_prev = self.sma_long[-2]
        sma_short_prev = self.sma_short[-2]
        
        if pd.isna(sma_long_prev) or pd.isna(sma_short_prev):
            return False
        
        return close_prev < sma_long_prev and close_prev < sma_short_prev


