import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA Ribbon parameters
    length1 = 10
    length2 = 20
    length3 = 50
    length4 = 100
    length5 = 150
    length6 = 200
    ma_type = "EMA"

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate moving averages
        if self.ma_type == "EMA":
            self.ma1 = self.I(pta.ema, close, length=self.length1)
            self.ma2 = self.I(pta.ema, close, length=self.length2)
            self.ma3 = self.I(pta.ema, close, length=self.length3)
            self.ma4 = self.I(pta.ema, close, length=self.length4)
            self.ma5 = self.I(pta.ema, close, length=self.length5)
            self.ma6 = self.I(pta.ema, close, length=self.length6)
        else:
            self.ma1 = self.I(pta.sma, close, length=self.length1)
            self.ma2 = self.I(pta.sma, close, length=self.length2)
            self.ma3 = self.I(pta.sma, close, length=self.length3)
            self.ma4 = self.I(pta.sma, close, length=self.length4)
            self.ma5 = self.I(pta.sma, close, length=self.length5)
            self.ma6 = self.I(pta.sma, close, length=self.length6)

    def next(self):
        # Macro trend: MA3 > MA4 > MA5 > MA6 (bullish) or MA3 < MA4 < MA5 < MA6 (bearish)
        macro_bullish = (self.ma3[-1] > self.ma4[-1] and 
                        self.ma4[-1] > self.ma5[-1] and 
                        self.ma5[-1] > self.ma6[-1])
        
        macro_bearish = (self.ma3[-1] < self.ma4[-1] and 
                        self.ma4[-1] < self.ma5[-1] and 
                        self.ma5[-1] < self.ma6[-1])
        
        # Fast cross signals: MA1 crossing MA2
        bull_cross = crossover(self.ma1, self.ma2)
        bear_cross = crossover(self.ma2, self.ma1)
        
        # Long signal: MA1 crosses above MA2 while macro ribbon is bullish
        if bull_cross and macro_bullish:
            if not self.position:
                self.buy()
        
        # Short signal: MA1 crosses below MA2 while macro ribbon is bearish
        elif bear_cross and macro_bearish:
            if self.position:
                self.position.close()
        
        # Exit long if macro trend turns bearish
        elif self.position and macro_bearish:
            self.position.close()