import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Settings
    ema1_length = 9
    ema2_length = 21
    ema3_length = 50
    ema200_length = 200
    
    # MACD Settings
    macd_fast = 12
    macd_slow = 26
    macd_signal = 9
    
    # Strategy Settings
    signals = "Long & Short"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema1 = self.I(pta.ema, close, length=self.ema1_length)
        self.ema2 = self.I(pta.ema, close, length=self.ema2_length)
        self.ema3 = self.I(pta.ema, close, length=self.ema3_length)
        self.ema200 = self.I(pta.ema, close, length=self.ema200_length)
        
        # Calculate MACD
        macd_result = self.I(pta.macd, close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_signal)
        self.macd_line = macd_result.iloc[:, 0]
        self.signal_line = macd_result.iloc[:, 1]
        self.hist_line = macd_result.iloc[:, 2]

    def next(self):
        # EMA Crossovers
        cross_1_above_2 = crossover(self.ema1, self.ema2)
        cross_1_above_3 = crossover(self.ema1, self.ema3)
        cross_2_above_3 = crossover(self.ema2, self.ema3)
        cross_1_below_2 = crossover(self.ema2, self.ema1)
        cross_1_below_3 = crossover(self.ema3, self.ema1)
        cross_2_below_3 = crossover(self.ema3, self.ema2)
        
        # MACD Crossovers
        macd_long = crossover(self.macd_line, self.signal_line)
        macd_short = crossover(self.signal_line, self.macd_line)
        
        # Combined entry signals
        long_entry = cross_1_above_2 or cross_1_above_3 or cross_2_above_3 or macd_long
        long_exit = cross_1_below_2 or cross_1_below_3 or cross_2_below_3 or macd_short
        
        short_entry = cross_1_below_2 or cross_1_below_3 or cross_2_below_3 or macd_short
        short_exit = cross_1_above_2 or cross_1_above_3 or cross_2_above_3 or macd_long
        
        # Strategy Logic
        if self.position:
            if self.position.is_long and long_exit:
                self.position.close()
            elif self.position.is_short and short_exit:
                self.position.close()
        else:
            if (self.signals == "Long Only" or self.signals == "Long & Short") and long_entry:
                self.buy()
            elif (self.signals == "Short Only" or self.signals == "Long & Short") and short_entry:
                self.sell()


