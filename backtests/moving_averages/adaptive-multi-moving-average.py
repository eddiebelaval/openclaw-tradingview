import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core Settings
    length = 50
    blend_mode = "Equal Blend"  # "Adaptive", "Equal Blend", "Custom Blend"
    src_type = "Close"
    
    # Custom Weights
    w_sma = 14
    w_ema = 14
    w_wma = 14
    w_rma = 14
    w_hma = 15
    w_alma = 15
    w_vwma = 14

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Select source
        if self.src_type == "Close":
            src = close
        elif self.src_type == "Open":
            src = open_
        elif self.src_type == "High":
            src = high
        elif self.src_type == "Low":
            src = low
        elif self.src_type == "HL2":
            src = (high + low) / 2
        elif self.src_type == "HLC3":
            src = (high + low + close) / 3
        elif self.src_type == "OHLC4":
            src = (open_ + high + low + close) / 4
        else:  # HLC3W
            src = (high + low + close + close) / 4
        
        # Calculate all 7 moving averages
        self.v_sma = self.I(pta.sma, close, length=self.length)
        self.v_ema = self.I(pta.ema, close, length=self.length)
        self.v_wma = self.I(pta.wma, close, length=self.length)
        self.v_rma = self.I(pta.rma, close, length=self.length)
        self.v_hma = self.I(pta.hma, close, length=self.length)
        self.v_alma = self.I(pta.alma, close, length=self.length, a=0.85, m=6)
        self.v_vwma = self.I(pta.vwma, close, volume, length=self.length)
        
        self.src = src
        
        # Calculate blended MA
        def calc_blended_ma():
            if len(self.data) < self.length:
                return pd.Series(0, index=close.index)
            
            sma = self.v_sma
            ema = self.v_ema
            wma = self.v_wma
            rma = self.v_rma
            hma = self.v_hma
            alma = self.v_alma
            vwma = self.v_vwma
            
            result = pd.Series(index=close.index, dtype=float)
            
            for i in range(len(close)):
                s = self.src.iloc[i] if i < len(self.src) else 0
                
                if pd.isna(sma.iloc[i]) or pd.isna(ema.iloc[i]) or pd.isna(wma.iloc[i]) or \
                   pd.isna(rma.iloc[i]) or pd.isna(hma.iloc[i]) or pd.isna(alma.iloc[i]) or \
                   pd.isna(vwma.iloc[i]):
                    result.iloc[i] = np.nan
                    continue
                
                if self.blend_mode == "Equal Blend":
                    result.iloc[i] = (sma.iloc[i] + ema.iloc[i] + wma.iloc[i] + rma.iloc[i] + 
                                     hma.iloc[i] + alma.iloc[i] + vwma.iloc[i]) / 7.0
                
                elif self.blend_mode == "Adaptive":
                    d_sma = max(abs(s - sma.iloc[i]), 0.0001)
                    d_ema = max(abs(s - ema.iloc[i]), 0.0001)
                    d_wma = max(abs(s - wma.iloc[i]), 0.0001)
                    d_rma = max(abs(s - rma.iloc[i]), 0.0001)
                    d_hma = max(abs(s - hma.iloc[i]), 0.0001)
                    d_alma = max(abs(s - alma.iloc[i]), 0.0001)
                    d_vwma = max(abs(s - vwma.iloc[i]), 0.0001)
                    
                    aw_sma = 1.0 / d_sma
                    aw_ema = 1.0 / d_ema
                    aw_wma = 1.0 / d_wma
                    aw_rma = 1.0 / d_rma
                    aw_hma = 1.0 / d_hma
                    aw_alma = 1.0 / d_alma
                    aw_vwma = 1.0 / d_vwma
                    a_total = aw_sma + aw_ema + aw_wma + aw_rma + aw_hma + aw_alma + aw_vwma
                    
                    result.iloc[i] = (sma.iloc[i]*aw_sma + ema.iloc[i]*aw_ema + wma.iloc[i]*aw_wma + 
                                     rma.iloc[i]*aw_rma + hma.iloc[i]*aw_hma + alma.iloc[i]*aw_alma + 
                                     vwma.iloc[i]*aw_vwma) / a_total
                
                else:  # Custom Blend
                    c_total = self.w_sma + self.w_ema + self.w_wma + self.w_rma + self.w_hma + self.w_alma + self.w_vwma
                    c_denom = c_total if c_total > 0 else 1.0
                    
                    result.iloc[i] = (sma.iloc[i]*self.w_sma + ema.iloc[i]*self.w_ema + wma.iloc[i]*self.w_wma + 
                                     rma.iloc[i]*self.w_rma + hma.iloc[i]*self.w_hma + alma.iloc[i]*self.w_alma + 
                                     vwma.iloc[i]*self.w_vwma) / c_denom
            
            return result
        
        self.blended_ma = self.I(calc_blended_ma)

    def next(self):
        # Trading logic: buy when price crosses above blended MA, sell when crosses below
        if crossover(self.src, self.blended_ma):
            if not self.position:
                self.buy()
        elif crossover(self.blended_ma, self.src):
            if self.position:
                self.sell()