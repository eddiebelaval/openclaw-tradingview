import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Zone Parameters
    i_short_len = 13
    i_mid_len = 24
    i_long_len = 52
    i_z_s1 = 1.0
    i_z_s2 = 1.5
    i_z_s3 = 2.0
    i_atr_mult = 1.5
    i_atr_len = 14
    
    # Signal Parameters
    i_buy_z = -1.0
    i_sell_z = 1.5
    i_use_vol = True
    i_vol_mult = 1.2
    i_vol_ma = 20
    i_stop_atr = 2.0
    i_risk_pct = 2.0
    i_capital = 10000000.0
    
    # OPT-1: K-Means Pivot Clustering
    i_kmeans_on = True
    i_pivot_lb = 10
    
    # OPT-2: HMM Regime Filter
    i_regime_on = True
    i_regime_fast = 20
    i_regime_slow = 50
    i_regime_vol_len = 20
    
    # OPT-3: Options Signal Layer
    i_options_on = True
    i_opt_dte = 30
    i_opt_iv_source = "ATR"
    
    # OPT-4: Bank Nifty Confluence
    i_bnf_on = True
    i_bnf_z_len = 24
    i_bnf_threshold = -0.8
    
    # OPT-5: India VIX Overlay
    i_vix_on = True
    i_vix_spike = 20.0
    i_vix_extreme = 30.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Base Z-Score Engine
        self.mu_long = self.I(pta.sma, close, length=self.i_long_len)
        self.sd_long = self.I(lambda: close.rolling(self.i_long_len).std())
        
        self.mu_mid = self.I(pta.sma, close, length=self.i_mid_len)
        self.sd_mid = self.I(lambda: close.rolling(self.i_mid_len).std())
        
        self.mu_short = self.I(pta.sma, close, length=self.i_short_len)
        self.sd_short = self.I(lambda: close.rolling(self.i_short_len).std())
        
        # Z-scores
        self.z_long = self.I(lambda: (close - self.mu_long) / (self.sd_long + 1e-10))
        self.z_mid = self.I(lambda: (close - self.mu_mid) / (self.sd_mid + 1e-10))
        self.z_short = self.I(lambda: (close - self.mu_short) / (self.sd_short + 1e-10))
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.i_atr_len)
        self.zone_half_width = self.I(lambda: self.atr * self.i_atr_mult / 2)
        
        # Volume
        self.vol_ma = self.I(pta.sma, volume, length=self.i_vol_ma)
        self.vol_ratio = self.I(lambda: volume / (self.vol_ma + 1e-10))
        
        # Support/Resistance Zones (Gaussian)
        self.s1_center = self.I(lambda: self.mu_long - self.i_z_s1 * self.sd_long)
        self.s2_center = self.I(lambda: self.mu_long - self.i_z_s2 * self.sd_long)
        self.s3_center = self.I(lambda: self.mu_long - self.i_z_s3 * self.sd_long)
        self.r1_center = self.I(lambda: self.mu_long + self.i_z_s1 * self.sd_long)
        self.r2_center = self.I(lambda: self.mu_long + self.i_z_s2 * self.sd_long)
        self.r3_center = self.I(lambda: self.mu_long + self.i_z_s3 * self.sd_long)
        
        self.s1_top = self.I(lambda: self.s1_center + self.zone_half_width)
        self.s1_bot = self.I(lambda: self.s1_center - self.zone_half_width)
        self.s2_top = self.I(lambda: self.s2_center + self.zone_half_width)
        self.s2_bot = self.I(lambda: self.s2_center - self.zone_half_width)
        self.s3_top = self.I(lambda: self.s3_center + self.zone_half_width)
        self.s3_bot = self.I(lambda: self.s3_center - self.zone_half_width)
        self.r1_top = self.I(lambda: self.r1_center + self.zone_half_width)
        self.r1_bot = self.I(lambda: self.r1_center - self.zone_half_width)
        self.r2_top = self.I(lambda: self.r2_center + self.zone_half_width)
        self.r2_bot = self.I(lambda: self.r2_center - self.zone_half_width)
        self.r3_top = self.I(lambda: self.r3_center + self.zone_half_width)
        self.r3_bot = self.I(lambda: self.r3_center - self.zone_half_width)
        
        # OPT-2: HMM Regime Filter
        self.fast_ema = self.I(pta.ema, close, length=self.i_regime_fast)
        self.slow_ema = self.I(pta.ema, close, length=self.i_regime_slow)
        
        self.rv_20 = self.I(lambda: close.rolling(self.i_regime_vol_len).std() / 
                                   (close.rolling(self.i_regime_vol_len).mean() + 1e-10) * 100)
        self.rv_ma = self.I(lambda: self.rv_20.rolling(self.i_regime_vol_len).mean())
        
        self.bull_score = self.I(lambda: (self.fast_ema > self.slow_ema).astype(int) + 
                                         (close > self.fast_ema).astype(int) +
                                         ((high > high.shift(1)) & (high.shift(1) > high.shift(2))).astype(int))
        
        self.bull_regime = self.I(lambda: self.bull_score >= 2)
        
        # Position tracking
        self.in_position = False
        self.entry_px = None
        self.stop_px = None
        self.target_px = None

    def next(self):
        # Current values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        z_mid = self.z_mid[-1]
        z_long = self.z_long[-1]
        atr = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
        vol_ratio = self.vol_ratio[-1] if not np.isnan(self.vol_ratio[-1]) else 1.0
        mu_long = self.mu_long[-1] if not np.isnan(self.mu_long[-1]) else close
        
        # Zone checks
        s1_bot = self.s1_bot[-1] if not np.isnan(self.s1_bot[-1]) else close
        s1_top = self.s1_top[-1] if not np.isnan(self.s1_top[-1]) else close
        s2_bot = self.s2_bot[-1] if not np.isnan(self.s2_bot[-1]) else close
        s2_top = self.s2_top[-1] if not np.isnan(self.s2_top[-1]) else close
        s3_bot = self.s3_bot[-1] if not np.isnan(self.s3_bot[-1]) else close
        s3_top = self.s3_top[-1] if not np.isnan(self.s3_top[-1]) else close
        
        r1_bot = self.r1_bot[-1] if not np.isnan(self.r1_bot[-1]) else close
        r1_top = self.r1_top[-1] if not np.isnan(self.r1_top[-1]) else close
        r2_bot = self.r2_bot[-1] if not np.isnan(self.r2_bot[-1]) else close
        r2_top = self.r2_top[-1] if not np.isnan(self.r2_top[-1]) else close
        r3_bot = self.r3_bot[-1] if not np.isnan(self.r3_bot[-1]) else close
        r3_top = self.r3_top[-1] if not np.isnan(self.r3_top[-1]) else close
        
        # Bull regime
        bull_regime = self.bull_regime[-1] if len(self.bull_regime) > 0 and not np.isnan(self.bull_regime[-1]) else True
        
        # Volume check
        vol_spike = vol_ratio >= self.i_vol_mult if self.i_use_vol else True
        
        # Zone proximity checks
        at_s1_zone = s1_bot <= close <= s1_top
        at_s2_zone = s2_bot <= close <= s2_top
        at_s3_zone = s3_bot <= close <= s3_top
        at_any_support = at_s1_zone or at_s2_zone or at_s3_zone
        
        at_r1_zone = r1_bot <= close <= r1_top
        at_r2_zone = r2_bot <= close <= r2_top
        at_r3_zone = r3_bot <= close <= r3_top
        at_any_resistance = at_r1_zone or at_r2_zone or at_r3_zone
        
        # Composite buy gate
        composite_buy_gate = vol_spike and bull_regime and at_any_support
        
        # Buy signal: Z-score crossover + gates
        buy_signal = False
        sell_signal = False
        
        if len(self.z_mid) >= 2:
            if crossover(self.z_mid, self.i_buy_z) and composite_buy_gate:
                buy_signal = True
            if crossover(self.z_mid, self.i_sell_z):
                sell_signal = True
        
        # Entry logic
        if buy_signal and not self.in_position:
            self.in_position = True
            self.entry_px = close * 1.0005
            
            # Stop loss based on ATR
            if atr > 0:
                self.stop_px = self.entry_px - self.i_stop_atr * atr
            else:
                self.stop_px = self.entry_px * 0.99
            
            # Target at mean or at R2
            self.target_px = mu_long + self.i_sell_z * (mu_long - self.s3_center) if mu_long != self.s3_center else close * 1.02
            
            self.buy()
        
        # Exit logic
        if self.in_position:
            if sell_signal or (self.stop_px and close <= self.stop_px) or (self.target_px and close >= self.target_px):
                self.in_position = False
                self.entry_px = None
                self.stop_px = None
                self.target_px = None
                self.sell()