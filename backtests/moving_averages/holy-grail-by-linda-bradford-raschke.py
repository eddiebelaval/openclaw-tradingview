import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adx_len = 14
    adx_thresh = 30
    exit_adx_weak = 25
    ema_len = 20
    use_ema = True
    trail_mult = 2.5
    atr_len = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Moving average
        if self.use_ema:
            self.ma = self.I(pta.ema, close, length=self.ema_len)
        else:
            self.ma = self.I(pta.sma, close, length=self.ema_len)
        
        # ADX and DMI
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adx_len))
        self.adx = self.I(lambda: pta.adx(high, low, close, length=self.adx_len)['ADX_14'] if pta.adx(high, low, close, length=self.adx_len) is not None else pd.Series(0, index=close.index))
        
        # ATR for trailing stop
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)

    def next(self):
        if len(self.data) < 2:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        close_prev = self.data.Close[-2]
        high_prev = self.data.High[-2]
        low_prev = self.data.Low[-2]
        
        ma = self.ma[-1]
        ma_prev = self.ma[-2]
        
        adx = self.adx[-1] if self.adx[-1] is not None else 0
        adx_prev = self.adx[-2] if self.adx[-2] is not None else 0
        
        atr = self.atr[-1] if self.atr[-1] is not None else 0
        
        # ADX conditions
        adx_rising = adx > adx_prev
        strong_up = adx > self.adx_thresh and adx_rising and close_prev > ma_prev
        strong_down = adx > self.adx_thresh and adx_rising and close_prev < ma_prev
        
        # Pull conditions (from previous bar)
        pull_long = low_prev <= ma_prev and strong_up
        pull_short = high_prev >= ma_prev and strong_down
        
        # Entry signals
        if pull_long and not self.position:
            self.buy()
        
        if pull_short and not self.position:
            self.sell()
        
        # Exit on ADX weakness
        if self.position.size > 0 and adx < self.exit_adx_weak:
            self.position.close()
        
        if self.position.size < 0 and adx < self.exit_adx_weak:
            self.position.close()
        
        # Trailing stop (ATR-based)
        if self.position.size > 0:
            trail_stop = self.position.open_price + (atr * self.trail_mult)
            if close < trail_stop and close > low_prev:
                self.position.close()
        
        if self.position.size < 0:
            trail_stop = self.position.open_price - (atr * self.trail_mult)
            if close > trail_stop and close < high_prev:
                self.position.close()


