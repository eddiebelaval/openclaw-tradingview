import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Intraday MA parameters
    intra_ma1_length = 10
    intra_ma1_type = 'EMA'
    intra_ma2_length = 20
    intra_ma2_type = 'EMA'
    intra_ma3_length = 50
    intra_ma3_type = 'EMA'
    intra_ma4_length = 100
    intra_ma4_type = 'EMA'
    
    # Daily MA parameters
    daily_ma1_length = 10
    daily_ma1_type = 'EMA'
    daily_ma2_length = 20
    daily_ma2_type = 'EMA'
    daily_ma3_length = 50
    daily_ma3_type = 'EMA'
    daily_ma4_length = 100
    daily_ma4_type = 'EMA'
    
    # Weekly MA parameters
    weekly_ma1_length = 10
    weekly_ma1_type = 'EMA'
    weekly_ma2_length = 20
    weekly_ma2_type = 'EMA'
    weekly_ma3_length = 30
    weekly_ma3_type = 'EMA'
    weekly_ma4_length = 40
    weekly_ma4_type = 'EMA'
    
    # Monthly MA parameters
    monthly_ma1_length = 10
    monthly_ma1_type = 'EMA'
    monthly_ma2_length = 20
    monthly_ma2_type = 'EMA'
    monthly_ma3_length = 50
    monthly_ma3_type = 'EMA'
    monthly_ma4_length = 100
    monthly_ma4_type = 'EMA'

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Intraday Moving Averages
        self.intra_ma1 = self.I(self._get_ma, close, self.intra_ma1_type, self.intra_ma1_length)
        self.intra_ma2 = self.I(self._get_ma, close, self.intra_ma1_type, self.intra_ma2_length)
        self.intra_ma3 = self.I(self._get_ma, close, self.intra_ma3_type, self.intra_ma3_length)
        self.intra_ma4 = self.I(self._get_ma, close, self.intra_ma4_type, self.intra_ma4_length)
        
        # Daily Moving Averages
        self.daily_ma1 = self.I(self._get_ma, close, self.daily_ma1_type, self.daily_ma1_length)
        self.daily_ma2 = self.I(self._get_ma, close, self.daily_ma2_type, self.daily_ma2_length)
        self.daily_ma3 = self.I(self._get_ma, close, self.daily_ma3_type, self.daily_ma3_length)
        self.daily_ma4 = self.I(self._get_ma, close, self.daily_ma4_type, self.daily_ma4_length)
        
        # Weekly Moving Averages
        self.weekly_ma1 = self.I(self._get_ma, close, self.weekly_ma1_type, self.weekly_ma1_length)
        self.weekly_ma2 = self.I(self._get_ma, close, self.weekly_ma2_type, self.weekly_ma2_length)
        self.weekly_ma3 = self.I(self._get_ma, close, self.weekly_ma3_type, self.weekly_ma3_length)
