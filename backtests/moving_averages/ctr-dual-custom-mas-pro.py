import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 21
    slowLen = 50
    fastType = "EMA"
    slowType = "EMA"
    globalBias = "Neutral"
    enableContFilter = True
    contN = 2
    useWickTouch = True
    useBodyStraddle = True
    useBodyCloseBeyond = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.fastMA = self.I(self._calculate_ma, close, self.fastLen, self.fastType)
        self.slowMA = self.I(self._calculate_ma, close, self.slowLen, self.slowType)
        self.atr = self.I(pta.atr, high, low, close, length=14)

        self.bullActive = False
        self.bearActive = False
        self.bullPB = 0
        self.bearPB = 0
        self.bullSepCount = 0
        self.bearSepCount = 0

    def _calculate_ma(self, close, length, ma_type):
        if ma_type == "EMA":
            return pta.ema(close, length=length)
        elif ma_type == "SMA":
            return pta.sma(close, length=length)
        elif ma_type == "WMA":
            return pta.wma(close, length=length)
        elif ma_type == "VWMA":
            return pta.vwma(close, pd.Series(self.data.Volume), length=length)
        elif ma_type == "RMA":
            return pta.rma(close, length=length)
        return close

    def next(self):
        if len(self.data) < 2:
            return

        fastMA_curr = self.fastMA[-1] if len(self.fastMA) > 0 else None
        slowMA_curr = self.slowMA[-1] if len(self.slowMA) > 0 else None
        atr_curr = self.atr[-1] if len(self.atr) > 0 and self.atr[-1] is not None else 0

        if fastMA_curr is None or slowMA_curr is None:
            return

        allowBull = self.globalBias != "Bearish"
        allowBear = self.globalBias != "Bullish"

        close = self.data.Close[-1]
        open_price = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        if len(self.fastMA) >= 2 and len(self.slowMA) >= 2:
            if crossover(self.fastMA, self.slowMA):
                self.bullActive = True
                self.bearActive = False
                self.bullPB = 0
                self.bullSepCount = 0

            if crossover(self.slowMA, self.fastMA):
                self.bearActive = True
                self.bullActive = False
                self.bearPB = 0
                self.bearSepCount = 0

        if self.bullActive:
            if close > fastMA_curr:
                self.bullSepCount += 1
            else:
                self.bullSepCount = 0

        if self.bearActive:
            if close < fastMA_curr:
                self.bearSepCount += 1
            else:
                self.bearSepCount = 0

        bullPullbackCond = self.bullActive and allowBull and (
            (self.useWickTouch and low <= fastMA_curr) or
            (self.useBodyStraddle and open_price > fastMA_curr and close < fastMA_curr) or
            (self.useBodyCloseBeyond and open_price < fastMA_curr and close < fastMA_curr)
        )

        bearPullbackCond = self.bearActive and allowBear and (
            (self.useWickTouch and high >= fastMA_curr) or
            (self.useBodyStraddle and open_price < fastMA_curr and close > fastMA_curr) or
            (self.useBodyCloseBeyond and open_price > fastMA_curr and close > fastMA_curr)
        )

        bullPBAllowed = self.bullPB == 0 or not self.enableContFilter or self.bullSepCount >= self.contN
        bearPBAllowed = self.bearPB == 0 or not self.enableContFilter or self.bearSepCount >= self.contN

        if bullPullbackCond and bullPBAllowed:
            self.bullPB += 1
            self.bullSepCount = 0
            if not self.position:
                self.buy()

        if bearPullbackCond and bearPBAllowed:
            self.bearPB += 1
            self.bearSepCount = 0
            if self.position:
                self.position.close()

        if self.bullActive and close < slowMA_curr:
            if self.position:
                self.position.close()

        if self.bearActive and close > slowMA_curr:
            if self.position:
                self.position.close()


