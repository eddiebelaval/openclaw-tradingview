import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Constants
        trendMaLen = 200
        adxLen = 14
        adxSmooth = 14
        emalen1 = 8
        emalen2 = 21
        atrfastlen = 14
        atrslowlen = 46
        
        # SMA 20 and EMA 21 for support band
        self.sma20 = self.I(pta.sma, close, length=20)
        self.ema21 = self.I(pta.ema, close, length=21)
        
        # 200 SMA for trend
        self.trendMa = self.I(pta.sma, close, length=trendMaLen)
        
        # DMI/ADX for trend direction
        adx_result = self.I(lambda: pta.adx(high, low, close, length=adxLen) or pd.DataFrame(0, index=close.index, columns=['DMP_14', 'DMN_14', 'ADX_14']))
        self.diPlus = adx_result['DMP_14'] if 'DMP_14' in adx_result.columns else self.I(lambda: pd.Series(0, index=close.index))
        self.diMinus = adx_result['DMN_14'] if 'DMN_14' in adx_result.columns else self.I(lambda: pd.Series(0, index=close.index))
        
        # ATR for volatility
        self.atrFast = self.I(pta.atr, high, low, close, length=atrfastlen)
        self.atrSlow = self.I(pta.atr, high, low, close, length=atrslowlen)
        
        # Tenkan/Kijun dynamic calculation
        self.dyntk = 19
        self.dynkj = 40
        
        # Dynamic Tenkan-Sen (9-30 period)
        self.tenkansen = self.I(self._calc_tenkan, high, low)
        
        # Dynamic Kijun-Sen (20-60 period)
        self.kijunsen = self.I(self._calc_kijun, high, low)
    
    def _calc_tenkan(self, high, low):
        dyntk = 19
        result = pd.Series(index=high.index, dtype=float)
        for i in range(len(high)):
            if i < dyntk - 1:
                result.iloc[i] = np.nan
            else:
                h = high.iloc[i-dyntk+1:i+1].max()
                l = low.iloc[i-dyntk+1:i+1].min()
                result.iloc[i] = (h + l) / 2.0
        return result
    
    def _calc_kijun(self, high, low):
        dynkj = 40
        result = pd.Series(index=high.index, dtype=float)
        for i in range(len(high)):
            if i < dynkj - 1:
                result.iloc[i] = np.nan
            else:
                h = high.iloc[i-dynkj+1:i+1].max()
                l = low.iloc[i-dynkj+1:i+1].min()
                result.iloc[i] = (h + l) / 2.0
        return result
    
    def next(self):
        # Ensure we have valid data
        if len(self) < 50:
            return
        
        close_val = self.data.Close[-1]
        
        # Determine trend bias
        isDomBull = self.diPlus[-1] > self.diMinus[-1] or (self.diPlus[-1] == self.diMinus[-1] and close_val > self.trendMa[-1])
        
        # Volatility check
        atrVolmeter = self.atrFast[-1] > self.atrSlow[-1]
        
        # Support band: SMA20 and EMA21
        sma20_val = self.sma20[-1]
        ema21_val = self.ema21[-1]
        band_width = abs(sma20_val - ema21_val)
        
        # Tenkan/Kijun crossover
        tk_above_kj = self.tenkansen[-1] > self.kijunsen[-1] if not np.isnan(self.tenkansen[-1]) and not np.isnan(self.kijunsen[-1]) else False
        tk_above_kj_prev = self.tenkansen[-2] > self.kijunsen[-2] if len(self) > 1 and not np.isnan(self.tenkansen[-2]) and not np.isnan(self.kijunsen[-2]) else False
        
        # Entry conditions
        # Bull signal: Price above support band, Tenkan > Kijun, trend is bullish
        if isDomBull and tk_above_kj and atrVolmeter:
            if close_val > max(sma20_val, ema21_val) and not self.position:
                self.buy()
        
        # Bear signal: Price below resistance band, Tenkan < Kijun, trend is bearish
        if not isDomBull and not tk_above_kj and atrVolmeter:
            if close_val < min(sma20_val, ema21_val) and self.position:
                self.sell()
        
        # Exit conditions
        # Close long if price breaks below support band
        if self.position and close_val < min(sma20_val, ema21_val):
            self.sell()
        
        # Close short if price breaks above resistance band
        if not self.position and close_val > max(sma20_val, ema21_val):
            self.sell()
        
        # Crossover-based exit: Tenkan crosses below Kijun
        if self.position and tk_above_kj_prev and not tk_above_kj:
            self.sell()


