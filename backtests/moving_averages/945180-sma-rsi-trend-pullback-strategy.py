import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smaFastLen = 9
    smaMidLen = 45
    smaLongLen = 180
    rsiLen = 14
    rsiBullLevel = 50
    rsiBearLevel = 50
    rrRatio = 2.0
    swingBars = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.smaFast = self.I(pta.sma, close, length=self.smaFastLen)
        self.smaMid = self.I(pta.sma, close, length=self.smaMidLen)
        self.smaLong = self.I(pta.sma, close, length=self.smaLongLen)
        self.rsiVal = self.I(pta.rsi, close, length=self.rsiLen)
        
        self.longStop = self.I(lambda: low.rolling(window=self.swingBars).min())
        self.shortStop = self.I(lambda: high.rolling(window=self.swingBars).max())

    def next(self):
        if len(self.data) < self.smaLongLen:
            return
        
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        smaFast = self.smaFast[-1]
        smaMid = self.smaMid[-1]
        smaLong = self.smaLong[-1]
        rsiVal = self.rsiVal[-1]
        
        longStop = self.longStop[-1]
        shortStop = self.shortStop[-1]
        
        if pd.isna(smaFast) or pd.isna(smaMid) or pd.isna(smaLong) or pd.isna(rsiVal):
            return
        if pd.isna(longStop) or pd.isna(shortStop):
            return
        
        bullTrend = close > smaLong and close > smaMid
        bearTrend = close < smaLong and close < smaMid
        
        pullbackBuy = low <= smaMid
        pullbackSell = high >= smaMid
        
        buyTrigger = close > smaFast and close > open_
        sellTrigger = close < smaFast and close < open_
        
        rsiBuyConfirm = rsiVal >= self.rsiBullLevel
        rsiSellConfirm = rsiVal <= self.rsiBearLevel
        
        upStructure = smaFast > smaMid and smaMid > smaLong
        downStructure = smaFast < smaMid and smaMid < smaLong
        
        buyCondition = bullTrend and upStructure and pullbackBuy and buyTrigger and rsiBuyConfirm
        sellCondition = bearTrend and downStructure and pullbackSell and sellTrigger and rsiSellConfirm
        
        longRisk = close - longStop
        shortRisk = shortStop - close
        
        longTarget = close + (longRisk * self.rrRatio)
        shortTarget = close - (shortRisk * self.rrRatio)
        
        if self.position:
            if self.position.is_long:
                if sellCondition or close <= longStop:
                    self.position.close()
                elif close >= longTarget:
                    self.position.close()
            elif self.position.is_short:
                if buyCondition or close >= shortStop:
                    self.position.close()
                elif close <= shortTarget:
                    self.position.close()
        else:
            if buyCondition and longRisk > 0:
                self.buy()
            elif sellCondition and shortRisk > 0:
                self.sell()


