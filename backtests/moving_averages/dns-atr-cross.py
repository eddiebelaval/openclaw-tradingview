import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLength = 14
    ma1Period = 10
    ma2Period = 21
    ma3Period = 50

    def init(self):
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        close = pd.Series(self.data.Close)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # Calculate SMAs of ATR
        self.atrMA1 = self.I(pta.sma, atr, length=self.ma1Period)
        self.atrMA2 = self.I(pta.sma, atr, length=self.ma2Period)
        self.atrMA3 = self.I(pta.sma, atr, length=self.ma3Period)

    def next(self):
        # Check if we have valid indicator values
        if len(self.atrMA1) < 2 or len(self.atrMA2) < 2:
            return
        
        # Bullish cross: 10 Day MA crosses above 21 Day MA
        if crossover(self.atrMA1, self.atrMA2):
            if not self.position:
                self.buy()
        
        # Bearish cross: 10 Day MA crosses below 21 Day MA
        elif crossover(self.atrMA2, self.atrMA1):
            if self.position:
                self.position.close()


