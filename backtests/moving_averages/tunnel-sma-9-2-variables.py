import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate SMA 9
        self.sma9 = self.I(pta.sma, close, length=9)
        
        # High and Low as variables
        self.var_haute = high
        self.var_basse = low

    def next(self):
        # Buy signal: when Low crosses above SMA 9
        if len(self.data) > 9:
            if crossover(self.var_basse, self.sma9):
                if not self.position:
                    self.buy()
            
            # Sell signal: when High crosses below SMA 9
            elif crossover(self.sma9, self.var_haute):
                if self.position:
                    self.position.close()