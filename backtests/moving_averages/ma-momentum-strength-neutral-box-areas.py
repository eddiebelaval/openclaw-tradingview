import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_type = "SMA"
    box_range = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        if self.ma_type == "EMA":
            self.ma9 = self.I(pta.ema, close, length=9)
            self.ma50 = self.I(pta.ema, close, length=50)
            self.ma200 = self.I(pta.ema, close, length=200)
        else:
            self.ma9 = self.I(pta.sma, close, length=9)
            self.ma50 = self.I(pta.sma, close, length=50)
            self.ma200 = self.I(pta.sma, close, length=200)

        self.in_box_zone = False
        self.prev_in_box_zone = False

    def next(self):
        if len(self.data) < 200:
            return

        close = self.data.Close[-1]
        ma9_val = self.ma9[-1]
        ma50_val = self.ma50[-1]
        ma200_val = self.ma200[-1]

        score9 = 1 if close > ma9_val else (-1 if close < ma9_val else 0)
        score50 = 1 if close > ma50_val else (-1 if close < ma50_val else 0)
        score200 = 1 if close > ma200_val else (-1 if close < ma200_val else 0)

        avg_score = (score9 + score50 + score200) / 3.0
        strength_percent = avg_score * 100.0

        self.prev_in_box_zone = self.in_box_zone
        self.in_box_zone = strength_percent >= -self.box_range and strength_percent <= self.box_range

        if self.in_box_zone and not self.prev_in_box_zone:
            if not self.position:
                self.buy()
        elif not self.in_box_zone and self.prev_in_box_zone:
            if self.position:
                self.position.close()


