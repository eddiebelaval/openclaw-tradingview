import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback_period = 60
    std_dev_mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Linear Regression Basis
        self.reg_basis = self.I(lambda: self._linreg(close, self.lookback_period, 0))
        
        # Basis Slope (current - previous)
        self.basis_slope = self.I(lambda: self._linreg(close, self.lookback_period, 0) - self._linreg(close, self.lookback_period, 1))
        
        # Standard Deviation
        self.sigma = self.I(lambda: close.rolling(self.lookback_period).std() or pd.Series(0, index=close.index))
        
        # Channels
        self.upper_channel = self.I(lambda: self.reg_basis + self.std_dev_mult * self.sigma)
        self.lower_channel = self.I(lambda: self.reg_basis - self.std_dev_mult * self.sigma)

    def _linreg(self, series, length, offset):
        """Calculate Linear Regression"""
        if len(series) < length:
            return pd.Series(series.iloc[-1], index=series.index)
        
        result = pd.Series(index=series.index, dtype=float)
        for i in range(length - 1, len(series)):
            x = np.arange(length)
            y = series.iloc[i - length + 1:i + 1].values
            if len(x) == len(y):
                coeffs = np.polyfit(x, y, 1)
                result.iloc[i] = coeffs[0] * (length - 1 - offset) + coeffs[1]
        
        return result.fillna(method='bfill').fillna(series.iloc[0])

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        reg_basis_val = self.reg_basis[-1]
        basis_slope_val = self.basis_slope[-1]
        upper_channel_val = self.upper_channel[-1]
        lower_channel_val = self.lower_channel[-1]
        
        # Exhaustion Signals
        signal_oversold = len(self.data) > 1 and low < lower_channel_val and self.data.Low[-2] >= lower_channel_val
        signal_overbought = len(self.data) > 1 and high > upper_channel_val and self.data.High[-2] <= upper_channel_val
        
        # Mean Reversion Signals
        target_reached = len(self.data) > 1 and close > reg_basis_val and self.data.Close[-2] <= reg_basis_val and basis_slope_val > 0
        mean_support = len(self.data) > 1 and low < reg_basis_val and self.data.Low[-2] >= reg_basis_val and close > reg_basis_val and basis_slope_val > 0
        mean_resistance = len(self.data) > 1 and high > reg_basis_val and self.data.High[-2] <= reg_basis_val and close < reg_basis_val and basis_slope_val < 0
        
        # Trading Logic
        if signal_oversold:
            if not self.position:
                self.buy()
        elif signal_overbought:
            if self.position:
                self.sell()
        elif target_reached:
            if not self.position:
                self.buy()
        elif mean_support:
            if not self.position:
                self.buy()
        elif mean_resistance:
            if self.position:
                self.sell()


