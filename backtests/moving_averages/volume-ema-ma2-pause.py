        self.vol_ma2_values.append(vol_ma2)
        
        # Check crossover conditions
        if self.prev_vol_ma2 is not None and self.prev_vol_ema is not None:
            cross_up = self.prev_vol_ma2 <= self.prev_vol_ema and vol_ma2 > vol_ema
