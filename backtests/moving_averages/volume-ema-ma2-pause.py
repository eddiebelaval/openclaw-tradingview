    def _calculate_hma(self, data, length):
        """Calculate Hull Moving Average"""
        if len(data) < length:
            return np.mean(data) if data else 0
        
        half_len = int(length / 2)
        sqrt_len = int(np.sqrt(length))
        
        # Calculate WMA for half length
        data_half = data[-half_len:] if len(data) >= half_len else data
        weights_half = np.arange(1, len(data_half) + 1)
        wma_half = np.average(data_half, weights=weights_half)
        
        # Calculate WMA for full length
        data_full = data[-length:] if len(data) >= length else data
        weights_full = np.arange(1, len(data_full) + 1)
        wma_full = np.average(data_full, weights=weights_full)
        
        # Raw HMA
        raw_hma = (wma_half * 2) - wma_full
        
        # WMA of raw HMA with sqrt length
        if len(self.vol_ma2_values) > 0:
            recent_hma = [raw_hma]
            if len(self.vol_ma2_values) > 0:
                recent_hma = [raw_hma]
            weights_sqrt = np.arange(1, len(recent_hma) + 1)
            hma = np.average(recent_hma, weights=weights_sqrt)
        else:
            hma = raw_hma
        
        return hma


