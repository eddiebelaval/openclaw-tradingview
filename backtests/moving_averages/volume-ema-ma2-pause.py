class TvStrategy(Strategy):
    # Parameters from the Pine Script
    emaLen = 10
    ma2Type = "HMA"
    ma2Len = 10
    volProxPct = 30.0
    useTime1 = True
    useTime2 = True
    
    def init(self):
        self.vol_ema_values = []
        self.vol_ma2_values = []
        self.prev_vol_ma2 = None
        self.prev_vol_ema = None
        
    def next(self):
        current_volume = self.data.Volume[-1]
        
        # Calculate EMA with pause logic (simplified - always active in backtest)
        if len(self.vol_ema_values) == 0:
            vol_ema = current_volume
        else:
            alpha = 2 / (self.emaLen + 1)
            vol_ema = (current_volume - self.vol_ema_values[-1]) * alpha + self.vol_ema_values[-1]
        self.vol_ema_values.append(vol_ema)
        
        # Calculate MA2 based on type
        if len(self.vol_ma2_values) < self.ma2Len:
            if self.ma2Type == "SMA":
                vol_ma2 = np.mean(list(self.data.Volume[-min(len(self.data.Volume), self.ma2Len):]))
            elif self.ma2Type == "EMA":
                if len(self.vol_ma2_values) == 0:
                    vol_ma2 = current_volume
                else:
                    alpha = 2 / (self.ma2Len + 1)
                    vol_ma2 = (current_volume - self.vol_ma2_values[-1]) * alpha + self.vol_ma2_values[-1]
