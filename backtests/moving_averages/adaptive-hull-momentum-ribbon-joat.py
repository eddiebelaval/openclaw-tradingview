import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # HMA Ribbon Settings
    hmaLength1 = 8
    hmaLength2 = 13
    hmaLength3 = 21
    hmaLength4 = 34
    hmaLength5 = 55
    
    # EMA Cloud Settings
    emaFast = 9
    emaSlow = 21
    
    # Key Moving Averages
    sma50_length = 50
    sma200_length = 200
    ema200_length = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Hull Moving Average calculation
        def hull_ma(src, length):
            wma1 = pta.wma(src, length=length // 2)
            wma2 = pta.wma(src, length=length)
            if wma1 is None or wma2 is None:
                return pd.Series(0, index=src.index)
            result = pta.wma(2 * wma1 - wma2, length=int(np.sqrt(length)))
            return result if result is not None else pd.Series(0, index=src.index)
        
        # HMA Ribbon
        self.hma1 = self.I(lambda: hull_ma(close, self.hmaLength1))
        self.hma2 = self.I(lambda: hull_ma(close, self.hmaLength2))
        self.hma3 = self.I(lambda: hull_ma(close, self.hmaLength3))
        self.hma4 = self.I(lambda: hull_ma(close, self.hmaLength4))
        self.hma5 = self.I(lambda: hull_ma(close, self.hmaLength5))
        
        # EMA Cloud
        self.emaFastLine = self.I(pta.ema, close, length=self.emaFast)
        self.emaSlowLine = self.I(pta.ema, close, length=self.emaSlow)
        
        # Key Moving Averages
        self.sma50 = self.I(pta.sma, close, length=self.sma50_length)
        self.sma200 = self.I(pta.sma, close, length=self.sma200_length)
        self.ema200 = self.I(pta.ema, close, length=self.ema200_length)

    def next(self):
        # Golden Cross / Death Cross
        if crossover(self.sma50, self.sma200):
            self.buy()
        elif crossover(self.sma200, self.sma50):
            self.sell()
        
        # EMA Crossovers
        elif crossover(self.emaFastLine, self.emaSlowLine):
            if not self.position:
                self.buy()
        elif crossover(self.emaSlowLine, self.emaFastLine):
            if self.position:
                self.sell()
        
        # HMA Fast Crossovers
        elif crossover(self.hma1, self.hma2):
            if not self.position:
                self.buy()
        elif crossover(self.hma2, self.hma1):
            if self.position:
                self.sell()


