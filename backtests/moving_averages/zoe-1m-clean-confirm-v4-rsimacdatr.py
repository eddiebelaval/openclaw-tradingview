import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 13
    slowLen = 34
    useVWAP = True
    
    rsiLen = 14
    rsiOB = 70
    rsiOS = 30
    
    macdFast = 12
    macdSlow = 26
    macdSig = 9
    
    atrLen = 14
    atrMult = 0.8

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMA calculations
        self.emaFast = self.I(pta.ema, close, length=self.fastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.slowLen)
        
        # VWAP calculation
        self.vwapVal = self.I(lambda: pta.vwap(high, low, close, volume) or pd.Series(np.nan, index=close.index))
        
        # RSI calculation
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        # MACD calculation
        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSig) or pd.DataFrame(index=close.index))
        self.macdLine = macd_result.iloc[:, 0] if macd_result is not None and len(macd_result.columns) > 0 else pd.Series(np.nan, index=close.index)
        self.sigLine = macd_result.iloc[:, 1] if macd_result is not None and len(macd_result.columns) > 1 else pd.Series(np.nan, index=close.index)
        self.hist = macd_result.iloc[:, 2] if macd_result is not None and len(macd_result.columns) > 2 else pd.Series(np.nan, index=close.index)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)

    def next(self):
        close_val = self.data.Close[-1]
        emaFast_val = self.emaFast[-1]
        emaSlow_val = self.emaSlow[-1]
        rsi_val = self.rsi[-1]
        macdLine_val = self.macdLine[-1]
        sigLine_val = self.sigLine[-1]
        hist_val = self.hist[-1]
        atr_val = self.atr[-1]
        
        # Handle VWAP
        vwap_val = self.vwapVal[-1]
        if pd.isna(vwap_val):
            vwap_val = close_val
        
        # Skip if any critical indicator is NaN
        if pd.isna(emaFast_val) or pd.isna(emaSlow_val) or pd.isna(rsi_val) or pd.isna(macdLine_val) or pd.isna(atr_val):
            return
        
        # Trend filter
        bullTrend = emaFast_val > emaSlow_val and (not self.useVWAP or close_val > vwap_val)
        bearTrend = emaFast_val < emaSlow_val and (not self.useVWAP or close_val < vwap_val)
        
        # ATR distance filter
        bullAtrOk = (close_val - emaFast_val) > atr_val * self.atrMult
        bearAtrOk = (emaFast_val - close_val) > atr_val * self.atrMult
        
        # MACD momentum confirm
        bullMacdOk = macdLine_val > sigLine_val and hist_val > 0
        bearMacdOk = macdLine_val < sigLine_val and hist_val < 0
        
        # RSI logic
        rsi_crossover_os = crossover(self.rsi, self.rsiOS)
        rsi_crossunder_ob = crossover(self.rsiOB, self.rsi)
        
        bullRsiOk = rsi_crossover_os or (rsi_val > 50 and rsi_val < self.rsiOB)
        bearRsiOk = rsi_crossunder_ob or (rsi_val < 50 and rsi_val > self.rsiOS)
        
        # Confirmation signals
        confLong = bullTrend and bullRsiOk and bullMacdOk and bullAtrOk
        confShort = bearTrend and bearRsiOk and bearMacdOk and bearAtrOk
        
        # Entry/Exit logic
        if confLong and not self.position:
            self.buy()
        elif confShort and self.position:
            self.sell()


