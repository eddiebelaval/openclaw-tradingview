import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lenFast = 33
    lenMed = 50
    lenSlow = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.emaFast = self.I(pta.ema, close, length=self.lenFast)
        self.emaMed = self.I(pta.ema, close, length=self.lenMed)
        self.emaSlow = self.I(pta.ema, close, length=self.lenSlow)

        self.close_series = close
        self.high_series = high
        self.low_series = low

        self.last_bull_fvg_low = None
        self.last_bull_fvg_top = None
        self.bull_inverted = True

        self.last_bear_fvg_high = None
        self.last_bear_fvg_bot = None
        self.bear_inverted = True

        self.setup_state = 0

    def next(self):
        if len(self.data) < 3:
            return

        idx = len(self.data) - 1
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        close_1 = self.data.Close[-2]
        open_1 = self.data.Open[-2]

        high_2 = self.data.High[-3]
        low_2 = self.data.Low[-3]
        close_2 = self.data.Close[-3]
        open_2 = self.data.Open[-3]

        ema_fast = self.emaFast[-1]
        ema_med = self.emaMed[-1]
        ema_slow = self.emaSlow[-1]

        is_bull_fvg = low > high_2 and close_1 > open_1
        is_bear_fvg = high < low_2 and close_1 < open_1

        if is_bull_fvg:
            self.last_bull_fvg_low = high_2
            self.last_bull_fvg_top = low
            self.bull_inverted = False

        if is_bear_fvg:
            self.last_bear_fvg_high = low_2
            self.last_bear_fvg_bot = high
            self.bear_inverted = False

        short_trend = close < ema_fast and close < ema_med and close < ema_slow
        long_trend = close > ema_fast and close > ema_med and close > ema_slow

        if short_trend and high >= ema_fast:
            self.setup_state = 1
        elif not short_trend and self.setup_state == 1:
            self.setup_state = 0

        if long_trend and low <= ema_fast:
            self.setup_state = -1
        elif not long_trend and self.setup_state == -1:
            self.setup_state = 0

        is_bull_flipped_now = (
            not self.bull_inverted
            and self.last_bull_fvg_low is not None
            and close < self.last_bull_fvg_low
        )
        is_bear_flipped_now = (
            not self.bear_inverted
            and self.last_bear_fvg_high is not None
            and close > self.last_bear_fvg_high
        )

        short_trigger = (
            self.setup_state == 1
            and is_bull_flipped_now
            and close < ema_fast
        )
        long_trigger = (
            self.setup_state == -1
            and is_bear_flipped_now
            and close > ema_fast
        )

        if is_bull_flipped_now:
            self.bull_inverted = True
            self.setup_state = 0

        if is_bear_flipped_now:
            self.bear_inverted = True
            self.setup_state = 0

        if short_trigger:
            if not self.position:
                self.sell()
            elif self.position.is_long:
                self.position.close()

        if long_trigger:
            if not self.position:
                self.buy()
            elif self.position.is_short:
                self.position.close()