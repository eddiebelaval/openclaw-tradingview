import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    shortPeriod = 35
    longPeriod = 252
    maType = "EMA"

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate moving averages based on type
        if self.maType == "EMA":
            self.maShort = self.I(pta.ema, close, length=self.shortPeriod)
            self.maLong = self.I(pta.ema, close, length=self.longPeriod)
        elif self.maType == "SMA":
            self.maShort = self.I(pta.sma, close, length=self.shortPeriod)
            self.maLong = self.I(pta.sma, close, length=self.longPeriod)
        elif self.maType == "WMA":
            self.maShort = self.I(pta.wma, close, length=self.shortPeriod)
            self.maLong = self.I(pta.wma, close, length=self.longPeriod)
        elif self.maType == "VWMA":
            volume = pd.Series(self.data.Volume)
            self.maShort = self.I(pta.vwma, close, volume, length=self.shortPeriod)
            self.maLong = self.I(pta.vwma, close, volume, length=self.longPeriod)
        elif self.maType == "RMA":
            self.maShort = self.I(pta.rma, close, length=self.shortPeriod)
            self.maLong = self.I(pta.rma, close, length=self.longPeriod)
        else:
            self.maShort = self.I(pta.ema, close, length=self.shortPeriod)
            self.maLong = self.I(pta.ema, close, length=self.longPeriod)

    def next(self):
        # Check for bullish crossover (short MA crosses above long MA)
        if crossover(self.maShort, self.maLong):
            if not self.position:
                self.buy()
        # Check for bearish crossover (short MA crosses below long MA)
        elif crossover(self.maLong, self.maShort):
            if self.position:
                self.position.close()