import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MACD Settings
    fast_length = 12
    slow_length = 25
    signal_length = 5
    
    # EMA Settings
    ema_fast = 13
    ema_slow = 34
    sma_50 = 50
    ema_8 = 8
    ema_20 = 20
    
    # Confidence toggles
    inc_01 = True
    inc_02 = True
    inc_03 = True
    inc_04 = True
    inc_05 = True
    inc_06 = True
    inc_07 = True
    inc_08 = True
    inc_09 = True
    inc_10 = True
    inc_11 = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Weekly calculations (using current close as proxy for weekly since we're on daily data)
        self.W_ema13 = self.I(lambda: pta.ema(close, length=self.ema_fast) or pd.Series(close, index=close.index))
        self.W_ema34 = self.I(lambda: pta.ema(close, length=self.ema_slow) or pd.Series(close, index=close.index))
        
        macd_result = pta.macd(close, fast=self.fast_length, slow=self.slow_length, signal=self.signal_length)
        if macd_result is not None:
            self.W_macd_line = self.I(lambda: macd_result.iloc[:, 0] if macd_result is not None else pd.Series(0, index=close.index))
            self.W_macd_hist = self.I(lambda: macd_result.iloc[:, 2] if macd_result is not None else pd.Series(0, index=close.index))
        else:
            self.W_macd_line = self.I(lambda: pd.Series(0, index=close.index))
            self.W_macd_hist = self.I(lambda: pd.Series(0, index=close.index))
        
        # Daily calculations
        self.D_ema8 = self.I(lambda: pta.ema(close, length=self.ema_8) or pd.Series(close, index=close.index))
        self.D_ema20 = self.I(lambda: pta.ema(close, length=self.ema_20) or pd.Series(close, index=close.index))
        self.D_sma50 = self.I(lambda: pta.sma(close, length=self.sma_50) or pd.Series(close, index=close.index))
        self.D_ema13 = self.I(lambda: pta.ema(close, length=self.ema_fast) or pd.Series(close, index=close.index))
        
        d_macd_result = pta.macd(close, fast=self.fast_length, slow=self.slow_length, signal=self.signal_length)
        if d_macd_result is not None:
            self.D_macd_line = self.I(lambda: d_macd_result.iloc[:, 0] if d_macd_result is not None else pd.Series(0, index=close.index))
            self.D_macd_hist = self.I(lambda: d_macd_result.iloc[:, 2] if d_macd_result is not None else pd.Series(0, index=close.index))
        else:
            self.D_macd_line = self.I(lambda: pd.Series(0, index=close.index))
            self.D_macd_hist = self.I(lambda: pd.Series(0, index=close.index))
        
        self.confidence_threshold = 80

    def next(self):
        # Weekly signals
        W_13MA_rising = len(self.W_ema13) > 1 and self.W_ema13[-1] > self.W_ema13[-2]
        W_34MA_rising = len(self.W_ema34) > 1 and self.W_ema34[-1] > self.W_ema34[-2]
        W_ema_cross = self.W_ema13[-1] > self.W_ema34[-1]
        W_macd_rising = len(self.W_macd_hist) > 1 and self.W_macd_hist[-1] > self.W_macd_hist[-2]
        
        # Daily signals
        D_macd_rising = len(self.D_macd_hist) > 1 and self.D_macd_hist[-1] > self.D_macd_hist[-2]
        D_8_above_20 = self.D_ema8[-1] > self.D_ema20[-1]
        D_price_ema13 = self.data.Close[-1] > self.D_ema13[-1]
        D_price_sma50 = self.data.Close[-1] > self.D_sma50[-1]
        D_macd_pos = self.D_macd_line[-1] > 0
        
        # Elder Impulse System
        W_13MA_rising_elder = len(self.W_ema13) > 1 and self.W_ema13[-1] > self.W_ema13[-2]
        W_macd_rising_elder = len(self.W_macd_hist) > 1 and self.W_macd_hist[-1] > self.W_macd_hist[-2]
        W_elder_red = (len(self.W_ema13) > 1 and self.W_ema13[-1] < self.W_ema13[-2]) and \
                      (len(self.W_macd_hist) > 1 and self.W_macd_hist[-1] < self.W_macd_hist[-2])
        W_elder_ok = not W_elder_red
        
        D_13MA_rising_elder = len(self.D_ema13) > 1 and self.D_ema13[-1] > self.D_ema13[-2]
        D_macd_rising_elder = len(self.D_macd_hist) > 1 and self.D_macd_hist[-1] > self.D_macd_hist[-2]
        D_elder_red = (len(self.D_ema13) > 1 and self.D_ema13[-1] < self.D_ema13[-2]) and \
                      (len(self.D_macd_hist) > 1 and self.D_macd_hist[-1] < self.D_macd_hist[-2])
        D_elder_ok = not D_elder_red
        
        # Build checks array
        checks = [
            W_13MA_rising if self.inc_01 else True,
            W_34MA_rising if self.inc_02 else True,
            W_ema_cross if self.inc_03 else True,
            W_macd_rising if self.inc_04 else True,
            D_macd_rising if self.inc_05 else True,
            D_8_above_20 if self.inc_06 else True,
            D_price_ema13 if self.inc_07 else True,
            D_price_sma50 if self.inc_08 else True,
            D_macd_pos if self.inc_09 else True,
            W_elder_ok if self.inc_10 else True,
            D_elder_ok if self.inc_11 else True,
        ]
        
        # Calculate confidence
        total = sum([
            1 if self.inc_01 else 0,
            1 if self.inc_02 else 0,
            1 if self.inc_03 else 0,
            1 if self.inc_04 else 0,
            1 if self.inc_05 else 0,
            1 if self.inc_06 else 0,
            1 if self.inc_07 else 0,
            1 if self.inc_08 else 0,
            1 if self.inc_09 else 0,
            1 if self.inc_10 else 0,
            1 if self.inc_11 else 0,
        ])
        
        passed = sum(checks) if total > 0 else 0
        confidence_pct = (passed / total * 100) if total > 0 else 0
        
        # Trading logic: Buy when confidence is high and all checks pass
        all_checks_pass = all(checks) and not W_elder_red and not D_elder_red
        
        if all_checks_pass and confidence_pct >= self.confidence_threshold:
            if not self.position:
                self.buy()
        
        # Sell on Elder Impulse Red signals or low confidence
        if self.position and (W_elder_red or D_elder_red or confidence_pct < 50):
            self.sell()