import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthInput = 24
    atrLengthInput = 14
    innerMultInput = 1.2
    outerMultInput = 2.4

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.basis = self.I(pta.hma, close, length=self.lengthInput)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLengthInput)
        
        atr_sma = self.I(pta.sma, self.atr, length=self.lengthInput)
        
        self.upperOuter = self.I(lambda: self.basis + (self.atr * self.outerMultInput))
        self.upperInner = self.I(lambda: self.basis + (self.atr * self.innerMultInput))
        self.lowerInner = self.I(lambda: self.basis - (self.atr * self.innerMultInput))
        self.lowerOuter = self.I(lambda: self.basis - (self.atr * self.outerMultInput))
        
        self.volExpanding = self.I(lambda: self.atr > atr_sma)
        
        self.trend = 0

    def next(self):
        if len(self.data.Close) < 2:
            return
        
        current_close = self.data.Close[-1]
        basis_val = self.basis[-1]
        vol_exp = self.volExpanding[-1]
        
        if current_close > basis_val:
            self.trend = 1
        elif current_close < basis_val:
            self.trend = -1
        
        buySignal = crossover(self.data.Close, self.basis) and vol_exp
        sellSignal = crossover(self.basis, self.data.Close) and vol_exp
        
        if buySignal:
            if not self.position:
                self.buy()
