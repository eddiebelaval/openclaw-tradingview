import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA 1 parameters
    show1 = True
    type1 = "EMA"
    len1 = 20
    
    # MA 2 parameters
    show2 = True
    type2 = "EMA"
    len2 = 50
    
    # MA 3 parameters
    show3 = True
    type3 = "SMA"
    len3 = 100
    
    # MA 4 parameters
    show4 = True
    type4 = "SMA"
    len4 = 200

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate MAs
        if self.show1:
            if self.type1 == "EMA":
                self.ma1 = self.I(pta.ema, close, length=self.len1)
            else:
                self.ma1 = self.I(pta.sma, close, length=self.len1)
        else:
            self.ma1 = None
        
        if self.show2:
            if self.type2 == "EMA":
                self.ma2 = self.I(pta.ema, close, length=self.len2)
            else:
                self.ma2 = self.I(pta.sma, close, length=self.len2)
        else:
            self.ma2 = None
        
        if self.show3:
            if self.type3 == "EMA":
                self.ma3 = self.I(pta.ema, close, length=self.len3)
            else:
                self.ma3 = self.I(pta.sma, close, length=self.len3)
        else:
            self.ma3 = None
        
        if self.show4:
            if self.type4 == "EMA":
                self.ma4 = self.I(pta.ema, close, length=self.len4)
            else:
                self.ma4 = self.I(pta.sma, close, length=self.len4)
        else:
            self.ma4 = None

    def next(self):
        # Simple trading logic: buy when fastest MA crosses above slowest MA, sell on cross below
        if self.ma1 is not None and self.ma4 is not None:
            if len(self.data) > 1:
                # Buy when MA1 crosses above MA4
                if crossover(self.ma1, self.ma4):
                    if not self.position:
                        self.buy()
                # Sell when MA1 crosses below MA4
                elif crossover(self.ma4, self.ma1):
                    if self.position:
                        self.position.close()