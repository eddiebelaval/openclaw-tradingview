class TvStrategy(Strategy):
    ema6_len = 6
    ema9_len = 9
    ema12_len = 12

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema6 = self.I(pta.ema, close, length=self.ema6_len)
        self.ema9 = self.I(pta.ema, close, length=self.ema9_len)
        self.ema12 = self.I(pta.ema, close, length=self.ema12_len)
        
        self.bull_signal = self.I(self._calculate_bull_signal)
        self.bear_signal = self.I(self._calculate_bear_signal)

    def _calculate_bull_signal(self):
        result = np.zeros(len(self.data.Close))
        for i in range(len(self.data.Close)):
            if self.ema6[i] is not None and self.ema9[i] is not None and self.ema12[i] is not None:
                if self.ema6[i] > self.ema9[i] and self.ema9[i] > self.ema12[i]:
                    result[i] = 1
        return pd.Series(result, index=pd.RangeIndex(len(result)))

    def _calculate_bear_signal(self):
        result = np.zeros(len(self.data.Close))
        for i in range(len(self.data.Close)):
            if self.ema6[i] is not None and self.ema9[i] is not None and self.ema12[i] is not None:
                if self.ema6[i] < self.ema9[i] and self.ema9[i] < self.ema12[i]:
                    result[i] = 1
        return pd.Series(result, index=pd.RangeIndex(len(result)))

    def next(self):
        if len(self) < 2:
            return
        
        bull_now = self.bull_signal[-1] > 0.5
        bull_prev = self.bull_signal[-2] > 0.5
        bear_now = self.bear_signal[-1] > 0.5
        bear_prev = self.bear_signal[-2] > 0.5
        
        if bull_now and not bull_prev:
            if self.position:
                self.position.close()
            self.buy()
        
        elif bear_now and not bear_prev:
            if self.position:
                self.position.close()
            self.sell()


