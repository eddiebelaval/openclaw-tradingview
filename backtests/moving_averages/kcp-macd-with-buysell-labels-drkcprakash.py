import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 12
    slowLen = 26
    signalLen = 9

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMAs
        fast_ema = self.I(pta.ema, close, length=self.fastLen)
        slow_ema = self.I(pta.ema, close, length=self.slowLen)
        
        # Calculate MACD line
        self.macd_line = self.I(lambda: fast_ema - slow_ema)
        
        # Calculate signal line (EMA of MACD line)
        self.signal_line = self.I(pta.ema, self.macd_line, length=self.signalLen)

    def next(self):
        # Buy signal: MACD line crosses above signal line
        if len(self.macd_line) > 1 and len(self.signal_line) > 1:
            if crossover(self.macd_line, self.signal_line):
                self.buy()
            # Sell signal: MACD line crosses below signal line
            elif crossover(self.signal_line, self.macd_line):
                self.sell()