import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA parameters
    ma_type = "EMA"
    ma50_len = 50
    ma200_len = 200
    
    # Bollinger Bands parameters
    bb_length = 20
    bb_stddev = 2.0
    
    # Parabolic SAR parameters
    psar_start = 0.02
    psar_increment = 0.02
    psar_maximum = 0.2
    
    # Two Candle Theory
    use_two_candle = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # MA 50
        if self.ma_type == "EMA":
            self.ma50 = self.I(pta.ema, close, length=self.ma50_len)
        else:
            self.ma50 = self.I(pta.sma, close, length=self.ma50_len)
        
        # MA 200
        if self.ma_type == "EMA":
            self.ma200 = self.I(pta.ema, close, length=self.ma200_len)
        else:
            self.ma200 = self.I(pta.sma, close, length=self.ma200_len)
        
        # Bollinger Bands
        bb = self.I(pta.bbands, close, length=self.bb_length, std=self.bb_stddev)
        self.bb_upper = bb.iloc[:, 2] if bb is not None and bb.shape[1] > 2 else pd.Series(0, index=close.index)
        self.bb_lower = bb.iloc[:, 0] if bb is not None and bb.shape[1] > 0 else pd.Series(0, index=close.index)
        self.bb_middle = bb.iloc[:, 1] if bb is not None and bb.shape[1] > 1 else pd.Series(0, index=close.index)
        
        # Parabolic SAR
        self.psar = self.I(self._calc_psar, high, low, close)
        
        # Two Candle Theory - calculate thirds
        self.high_third = self.I(lambda: high - (high - low) / 3)
        self.low_third = self.I(lambda: low + (high - low) / 3)

    def _calc_psar(self, high, low, close):
        """Calculate Parabolic SAR"""
        length = len(close)
        psar = np.zeros(length)
        af = self.psar_start
        hp = high.iloc[0]
        lp = low.iloc[0]
        trend = 1  # 1 for uptrend, -1 for downtrend
        
        for i in range(1, length):
            if trend == 1:
                psar[i] = psar[i-1] + af * (hp - psar[i-1])
                psar[i] = min(psar[i], low.iloc[i-1])
                if high.iloc[i] > hp:
                    hp = high.iloc[i]
                    af = min(af + self.psar_increment, self.psar_maximum)
                if low.iloc[i] < psar[i]:
                    trend = -1
                    psar[i] = hp
                    lp = low.iloc[i]
                    af = self.psar_start
            else:
                psar[i] = psar[i-1] - af * (psar[i-1] - lp)
                psar[i] = max(psar[i], high.iloc[i-1])
                if low.iloc[i] < lp:
                    lp = low.iloc[i]
                    af = min(af + self.psar_increment, self.psar_maximum)
                if high.iloc[i] > psar[i]:
                    trend = 1
                    psar[i] = lp
                    hp = high.iloc[i]
                    af = self.psar_start
        
        return pd.Series(psar, index=close.index)

    def next(self):
        # Ensure we have enough data
        if len(self.data) < max(self.ma50_len, self.ma200_len):
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        ma50 = self.ma50[-1] if len(self.ma50) > 0 else 0
        ma200 = self.ma200[-1] if len(self.ma200) > 0 else 0
        
        bb_upper = self.bb_upper.iloc[-1] if len(self.bb_upper) > 0 else 0
        bb_lower = self.bb_lower.iloc[-1] if len(self.bb_lower) > 0 else 0
        psar = self.psar[-1] if len(self.psar) > 0 else 0
        
        # Two Candle Theory calculations
        if self.use_two_candle and len(self.data) > 1:
            close_prev = self.data.Close[-2]
            high_prev = self.data.High[-2]
            low_prev = self.data.Low[-2]
            
            # Check if price is above previous candle (Bull Candle)
            is_bull_candle = close > high_prev
            # Check if price is below previous candle (Bear Candle)
            is_bear_candle = close < low_prev
            
            # High Close: in upper third
            high_third = high_prev - (high_prev - low_prev) / 3
            is_high_close = close >= high_third
            
            # Low Close: in lower third
            low_third = low_prev + (high_prev - low_prev) / 3
            is_low_close = close <= low_third
        else:
            is_bull_candle = False
            is_bear_candle = False
            is_high_close = False
            is_low_close = False
        
        # Entry conditions
        
        # 1. MA50 Bullish Crossover with confirmation
        if crossover(self.ma50, self.ma200):
            if close > ma50 and not self.position:
                self.buy()
        
        # 2. Price touches BB Lower (oversold) + close above MA50
        if len(self.data) > 1:
            if self.data.Low[-1] <= bb_lower and close > ma50 and not self.position:
                self.buy()
        
        # 3. Parabolic SAR Bullish Flip + MA50 confirmation
        if len(self.psar) > 1:
            if self.psar[-1] < close and self.psar[-2] >= self.data.Close[-2]:
                if close > ma50 and not self.position:
                    self.buy()
        
        # 4. Two Candle Theory: Bull Candle with High Close
        if is_bull_candle and is_high_close and not self.position:
            self.buy()
        
        # Exit conditions
        
        # 1. MA50 Bearish Crossover
        if crossover(self.ma200, self.ma50):
            if self.position:
                self.sell()
        
        # 2. Price touches BB Upper (overbought)
        if len(self.data) > 1:
            if self.data.High[-1] >= bb_upper and self.position:
                self.sell()
        
        # 3. Parabolic SAR Bearish Flip
        if len(self.psar) > 1:
            if self.psar[-1] > close and self.psar[-2] <= self.data.Close[-2]:
                if self.position:
                    self.sell()
        
        # 4. Price crosses below MA200
        if len(self.data) > 1:
            if self.data.Close[-2] > ma200 and close < ma200:
                if self.position:
                    self.sell()
        
        # 5. Two Candle Theory: Bear Candle with Low Close
        if is_bear_candle and is_low_close and self.position:
            self.sell()
        
        # 6. Stop loss: Price below lowest point of recent bars
        if self.position and len(self.data) > 5:
            recent_low = min(self.data.Low[-5:])
            if close < recent_low:
                self.sell()