import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fast_len = 6
    slow_len = 20
    signal_len = 10
    atr_len = 20
    include_atr = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        atr_smooth = self.I(lambda: pta.rma(atr, length=self.atr_len) if atr is not None else pd.Series(1, index=close.index))

        fast_ema = self.I(pta.ema, close, length=self.fast_len)
        slow_ema = self.I(pta.ema, close, length=self.slow_len)

        def calc_macd():
            f_ema = pta.ema(close, length=self.fast_len)
            s_ema = pta.ema(close, length=self.slow_len)
            atr_val = pta.atr(high, low, close, length=self.atr_len)
            atr_sm = pta.rma(atr_val, length=self.atr_len)
            if self.include_atr:
                return (f_ema - s_ema) / atr_sm * 100
            else:
                return (f_ema - s_ema) * 100

        self.macd = self.I(calc_macd)
        self.signal = self.I(pta.ema, self.macd, length=self.signal_len)
        self.hist = self.I(lambda: self.macd - self.signal if self.macd is not None and self.signal is not None else pd.Series(0, index=close.index))

    def next(self):
        if len(self.data) < self.signal_len + max(self.fast_len, self.slow_len) + 5:
            return

        if crossover(self.macd, self.signal):
            if not self.position:
                self.buy()
        elif crossover(self.signal, self.macd):
            if self.position:
                self.position.close()