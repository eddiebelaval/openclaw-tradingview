import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        self.fast_ema = self.I(pta.ema, close, length=50)
        self.slow_ema = self.I(pta.ema, close, length=200)
        self.rsi = self.I(pta.rsi, close, length=14)
    
    def next(self):
        if len(self.data) < 2:
            return
        
        # Buy signal: fast EMA crosses above slow EMA and RSI > 50
        if crossover(self.fast_ema, self.slow_ema):
            if self.rsi[-1] > 50:
                if not self.position:
                    self.buy()
        
        # Sell signal: fast EMA crosses below slow EMA and RSI < 50
        if crossover(self.slow_ema, self.fast_ema):
            if self.rsi[-1] < 50:
                if self.position:
                    self.position.close()


if __name__ == "__main__":
    from backtesting.test import GOOG
    
    bt = Backtest(GOOG, TvStrategy, cash=10000, commission=.002)
    results = bt.run()
    print(results)
