import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len1 = 12
    len2 = 22
    len3 = 55
    len4 = 100
    len5 = 200

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.sma1 = self.I(pta.sma, close, length=self.len1)
        self.sma2 = self.I(pta.sma, close, length=self.len2)
        self.sma3 = self.I(pta.sma, close, length=self.len3)
        self.sma4 = self.I(pta.sma, close, length=self.len4)
        self.sma5 = self.I(pta.sma, close, length=self.len5)

    def next(self):
        if crossover(self.sma1, self.sma2):
            self.buy()
        elif crossover(self.sma2, self.sma1):
            self.sell()


