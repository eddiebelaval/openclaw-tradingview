import numpy as np
import pandas as pd
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        pass

    def next(self):
        # Current candle
        current_open = self.data.Open[-1]
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        current_body = abs(current_close - current_open)
        current_up_shadow = current_high - max(current_open, current_close)
        current_down_shadow = min(current_open, current_close) - current_low
        
        # Previous candle
        if len(self.data) < 2:
            return
        
        prev_open = self.data.Open[-2]
        prev_close = self.data.Close[-2]
        prev_high = self.data.High[-2]
        prev_low = self.data.Low[-2]
        
        prev_body = abs(prev_close - prev_open)
        prev_up_shadow = prev_high - max(prev_open, prev_close)
        prev_down_shadow = min(prev_open, prev_close) - prev_low
        
        prev_bull = prev_close > prev_open
        prev_bear = prev_open > prev_close
        
        # Pinbar conditions
        bear_pinbar = (
            prev_bull and 
            (prev_body > current_body) and 
            (current_up_shadow > 0.5 * current_body) and 
            (current_up_shadow > 2 * current_down_shadow)
        )
        
        bull_pinbar = (
            prev_bear and 
            (prev_body > current_body) and 
            (current_down_shadow > 0.5 * current_body) and 
            (current_down_shadow > 2 * current_up_shadow)
        )
        
        # Trading logic
        if bull_pinbar and not self.position:
            self.buy()
        elif bear_pinbar and self.position:
            self.sell()