import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaShortLen = 15
    emaLongLen = 200
    macdFast = 12
    macdSlow = 26
    macdSignal = 9
    lookbackPeriod = 3
    rewardRatio = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.emaHigh = self.I(pta.ema, high, length=self.emaShortLen)
        self.emaLow = self.I(pta.ema, low, length=self.emaShortLen)
        self.ema200 = self.I(pta.ema, close, length=self.emaLongLen)

        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal))
        self.macdHist = self.I(lambda: pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal).iloc[:, 2] if pta.macd(close, fast=self.macdFast, slow=self.macdSlow, signal=self.macdSignal) is not None else pd.Series(0, index=close.index))

        self.bars_since_price_high = 0
        self.bars_since_price_low = 0
        self.bars_since_hist_high = 0
        self.bars_since_hist_low = 0

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        close_prev = self.data.Close[-2] if len(self.data.Close) > 1 else close

        emaHigh = self.emaHigh[-1]
        emaLow = self.emaLow[-1]
        ema200 = self.ema200[-1]
        macdHist = self.macdHist[-1]
        macdHist_prev = self.macdHist[-2] if len(self.macdHist) > 1 else macdHist

        priceCrossOverHigh = crossover(pd.Series([close_prev, close]), pd.Series([emaHigh, emaHigh]))
        priceCrossUnderLow = crossover(pd.Series([emaLow, emaLow]), pd.Series([close_prev, close]))
        histCrossOverZero = crossover(pd.Series([macdHist_prev, macdHist]), pd.Series([0, 0]))
        histCrossUnderZero = crossover(pd.Series([0, 0]), pd.Series([macdHist_prev, macdHist]))

        if priceCrossOverHigh:
            self.bars_since_price_high = 0
        else:
            self.bars_since_price_high += 1

        if priceCrossUnderLow:
            self.bars_since_price_low = 0
        else:
            self.bars_since_price_low += 1

        if histCrossOverZero:
            self.bars_since_hist_high = 0
        else:
            self.bars_since_hist_high += 1

        if histCrossUnderZero:
            self.bars_since_hist_low = 0
        else:
            self.bars_since_hist_low += 1

        isAbove200 = emaLow > ema200
        isBelow200 = emaHigh < ema200

        longCondition = (isAbove200 and macdHist > 0 and
                        self.bars_since_price_high <= self.lookbackPeriod and
                        self.bars_since_hist_high <= self.lookbackPeriod and
                        (priceCrossOverHigh or histCrossOverZero))

        shortCondition = (isBelow200 and macdHist < 0 and
                         self.bars_since_price_low <= self.lookbackPeriod and
                         self.bars_since_hist_low <= self.lookbackPeriod and
                         (priceCrossUnderLow or histCrossUnderZero))

        if self.position:
            if self.position.is_long:
                sl_price = self.position.open_price - (self.position.open_price - emaLow) / self.rewardRatio
                tp_price = self.position.open_price + (self.position.open_price - emaLow) * self.rewardRatio

                if close <= sl_price or close >= tp_price:
                    self.position.close()
            else:
                sl_price = self.position.open_price + (emaHigh - self.position.open_price) / self.rewardRatio
                tp_price = self.position.open_price - (emaHigh - self.position.open_price) * self.rewardRatio

                if close >= sl_price or close <= tp_price:
                    self.position.close()
        else:
            if longCondition:
                self.buy()
            elif shortCondition:
                self.sell()


