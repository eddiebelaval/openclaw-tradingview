import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lengthMA = 34
    lengthSignal = 9
    extension_threshold = 5.0
    breakeven_bars = 1
    ema_exit_length = 1
    use_supertrend = False
    st_factor = 2.0
    st_length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate HLC3
        hlc3 = (high + low + close) / 3.0
        
        # Calculate SMMA for high and low
        def calc_smma(src, length):
            result = pd.Series(index=src.index, dtype='float64')
            smma_val = src.rolling(window=length).mean().iloc[0]
            result.iloc[0] = smma_val
            for i in range(1, len(src)):
                smma_val = (smma_val * (length - 1) + src.iloc[i]) / length
                result.iloc[i] = smma_val
            return result
        
        # Calculate ZLEMA
        def calc_zlema(src, length):
            ema1 = src.ewm(span=length, adjust=False).mean()
            ema2 = ema1.ewm(span=length, adjust=False).mean()
            d = ema1 - ema2
            return ema1 + d
        
        self.hi = self.I(lambda: calc_smma(high, self.lengthMA))
        self.lo = self.I(lambda: calc_smma(low, self.lengthMA))
        self.mi = self.I(lambda: calc_zlema(hlc3, self.lengthMA))
        
        # Calculate Impulse MACD
        def calc_impulse_macd(mi, hi, lo, hlc3, signal_len):
            md = pd.Series(index=mi.index, dtype='float64')
            for i in range(len(mi)):
                if mi.iloc[i] > hi.iloc[i]:
                    md.iloc[i] = mi.iloc[i] - hi.iloc[i]
                elif mi.iloc[i] < lo.iloc[i]:
                    md.iloc[i] = mi.iloc[i] - lo.iloc[i]
                else:
                    md.iloc[i] = 0
            sb = md.rolling(window=signal_len).mean()
            return md, sb
        
        self.md = self.I(lambda: calc_impulse_macd(self.mi, self.hi, self.lo, hlc3, self.lengthSignal)[0])
        self.sb = self.I(lambda: calc_impulse_macd(self.mi, self.hi, self.lo, hlc3, self.lengthSignal)[1])
        
        # Calculate color phases
        def calc_color_bull(mi, hi, lo, hlc3):
            color_bull = pd.Series(index=mi.index, dtype='bool')
            for i in range(len(mi)):
                if hlc3.iloc[i] > mi.iloc[i]:
                    color_bull.iloc[i] = hlc3.iloc[i] > hi.iloc[i]
                elif hlc3.iloc[i] < lo.iloc[i]:
                    color_bull.iloc[i] = False
                else:
                    color_bull.iloc[i] = False
            return color_bull
        
        self.color_bull = self.I(lambda: calc_color_bull(self.mi, self.hi, self.lo, hlc3))
        
        # EMA for exits
        self.ema_exit = self.I(pta.ema, close, length=self.ema_exit_length)
        
        # Track state
        self.initialized = False
        self.is_color_bull = False
        self.bull_max = None
        self.bear_min = None
        self.entry_bar_index = None
        self.last_color_bull = False

    def next(self):
        if len(self) < max(self.lengthMA, self.lengthSignal) + 1:
            return
        
        current_md = self.md[-1]
        current_sb = self.sb[-1]
        current_color_bull = self.color_bull[-1]
        current_close = self.data.Close[-1]
        current_ema_exit = self.ema_exit[-1]
        
        # Initialize
        if not self.initialized:
            if not pd.isna(current_md) and not pd.isna(current_sb):
                self.is_color_bull = current_color_bull
                self.initialized = True
                if self.is_color_bull:
                    self.bull_max = current_md
                else:
                    self.bear_min = current_md
                self.last_color_bull = current_color_bull
            return
        
        # Update extensions
        if self.initialized and not pd.isna(current_md):
            if self.is_color_bull:
                if self.bull_max is None:
                    self.bull_max = current_md
                else:
                    self.bull_max = max(self.bull_max, current_md)
            else:
                if self.bear_min is None:
                    self.bear_min = current_md
                else:
                    self.bear_min = min(self.bear_min, current_md)
        
        # Detect phase changes
        change_to_bull = current_color_bull and not self.last_color_bull
        change_to_bear = not current_color_bull and self.last_color_bull
        
        # Entry logic
        if change_to_bull:
            if self.initialized and self.bear_min is not None and self.bear_min < -self.extension_threshold:
                if not self.position:
                    self.buy()
                    self.entry_bar_index = len(self.data) - 1
            self.is_color_bull = True
            self.bull_max = current_md
            self.bear_min = None
        
        if change_to_bear:
            if self.initialized and self.bull_max is not None and self.bull_max > self.extension_threshold:
                if not self.position:
                    self.sell()
                    self.entry_bar_index = len(self.data) - 1
            self.is_color_bull = False
            self.bear_min = current_md
            self.bull_max = None
        
        # Exit logic on EMA cross
        if self.position:
            if self.position.is_long and current_close < current_ema_exit:
                self.position.close()
            elif self.position.is_short and current_close > current_ema_exit:
                self.position.close()
        
        # Break even stops
        if self.position and self.entry_bar_index is not None:
            bars_held = len(self.data) - 1 - self.entry_bar_index
            if bars_held >= self.breakeven_bars:
                if self.position.is_long:
                    self.position.stop = self.position.open_price
                elif self.position.is_short:
                    self.position.stop = self.position.open_price
        
        self.last_color_bull = current_color_bull


