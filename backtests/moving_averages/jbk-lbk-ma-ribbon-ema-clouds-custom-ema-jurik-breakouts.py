import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA Ribbon parameters
    ma1_len = 96
    ma1_type = "EMA"
    
    ma2_len = 96
    ma2_type = "EMA"
    
    ma3_len = 96
    ma3_type = "EMA"
    
    # EMA Clouds parameters
    c1_s = 8
    c1_l = 14
    
    # Jurik parameters
    j_len = 9
    j_phase = 0.15
    pivot_len = 4

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hl2 = (high + low) / 2
        
        # MA Ribbon
        self.ma1 = self.I(self._calc_ma, close, self.ma1_len, self.ma1_type)
        self.ma2 = self.I(self._calc_ma, hl2, self.ma2_len, self.ma2_type)
        self.ma3 = self.I(self._calc_ma, low, self.ma3_len, self.ma3_type)
        
        # EMA Clouds
        self.ema1s = self.I(pta.ema, close, length=self.c1_s)
        self.ema1l = self.I(pta.ema, close, length=self.c1_l)
        
        # Jurik MA
        self.jma_values = self.I(self._calc_jma, close, self.j_len, self.j_phase)
        
        # Pivot highs and lows
        self.pivot_high = self.I(self._calc_pivot_high, high, self.pivot_len)
        self.pivot_low = self.I(self._calc_pivot_low, low, self.pivot_len)
        
        # ATR for breakout confirmation
        self.atr = self.I(pta.atr, high, low, close, length=200)

    def _calc_ma(self, src, length, ma_type):
        if ma_type == "EMA":
            return pta.ema(src, length=length)
        elif ma_type == "SMA":
            return pta.sma(src, length=length)
        elif ma_type == "RMA":
            return pta.rma(src, length=length)
        elif ma_type == "WMA":
            return pta.wma(src, length=length)
        elif ma_type == "VWMA":
            return pta.vwma(src, self.data.Volume, length=length)
        return src

    def _calc_jma(self, src, length, phase):
        result = pd.Series(np.nan, index=src.index)
        beta = 0.45 * (length - 1) / (0.45 * (length - 1) + 2)
        alpha = np.power(beta, phase)
        
        j_val = src.iloc[0]
        for i in range(len(src)):
            j_val = (1 - alpha) * src.iloc[i] + alpha * j_val
            result.iloc[i] = j_val
        
        return result

    def _calc_pivot_high(self, high, length):
        result = pd.Series(np.nan, index=high.index)
        for i in range(length, len(high) - length):
            window = high.iloc[i-length:i+length+1]
            if high.iloc[i] == window.max():
                result.iloc[i] = high.iloc[i]
        return result

    def _calc_pivot_low(self, low, length):
        result = pd.Series(np.nan, index=low.index)
        for i in range(length, len(low) - length):
            window = low.iloc[i-length:i+length+1]
            if low.iloc[i] == window.min():
                result.iloc[i] = low.iloc[i]
        return result

    def next(self):
        # Get current values
        if len(self.data) < max(self.ma1_len, self.ma2_len, self.ma3_len, self.j_len + 10, 50):
            return
        
        close_price = self.data.Close[-1]
        jma_current = self.jma_values[-1]
        jma_prev3 = self.jma_values[-4] if len(self.jma_values) >= 4 else jma_current
        
        ema_short = self.ema1s[-1]
        ema_long = self.ema1l[-1]
        
        ma1_val = self.ma1[-1]
        ma2_val = self.ma2[-1]
        ma3_val = self.ma3[-1]
        
        # Determine trend based on Jurik MA
        trend_up = jma_current >= jma_prev3
        
        # Cloud crossover signal
        cloud_bullish = ema_short >= ema_long
        
        # Ribbon alignment signal
        ribbon_bullish = (ma1_val >= ma2_val >= ma3_val)
        
        # Buy signal: Jurik trend up + cloud bullish + ribbon aligned + price above MAs
        buy_signal = (
            trend_up and 
            cloud_bullish and 
            ribbon_bullish and
            close_price > ma3_val
        )
        
        # Sell signal: Jurik trend down or price breaks below support
        sell_signal = (
            not trend_up or 
            (not cloud_bullish and not ribbon_bullish) or
            close_price < ma3_val
        )
        
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()