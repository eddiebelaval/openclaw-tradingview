import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vol_length = 50
    vol_z_threshold = 2.5
    max_anchors = 24
    anchor_cooldown = 5
    agg_method = "Average"
    color_smooth = 1
    mean_length = 9
    streak_window = 14
    sd_mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        def calc_vol_sma():
            return pta.sma(volume, length=self.vol_length)

        def calc_vol_sd():
            vol_sma = pta.sma(volume, length=self.vol_length)
            return volume.rolling(self.vol_length).std()

        def calc_vol_z():
            vol_sma = pta.sma(volume, length=self.vol_length)
            vol_sd = volume.rolling(self.vol_length).std()
            vol_z = np.where(vol_sd > 0, (volume - vol_sma) / vol_sd, 0)
            return pd.Series(vol_z, index=volume.index)

        def calc_ohlc4():
            ohlc4 = (self.data.Open + high + low + close) / 4
            return pd.Series(ohlc4, index=close.index)

        def calc_cluster_metrics():
            src_series = calc_ohlc4()
            vol_z_series = calc_vol_z()

            ema_prev_arr = [np.nan] * self.max_anchors
            count_arr = [0] * self.max_anchors
            bars_since_last_anchor = self.anchor_cooldown

            osc_vals = []
            env_tops = []
            env_bots = []
            signals = []

            for idx in range(len(src_series)):
                src_val = src_series.iloc[idx]
                vol_z_val = vol_z_series.iloc[idx]
                bars_since_last_anchor += 1

                is_anomaly = (vol_z_val >= self.vol_z_threshold) and (bars_since_last_anchor >= self.anchor_cooldown)

                if is_anomaly:
                    bars_since_last_anchor = 0
                    ema_prev_arr = [src_val] + ema_prev_arr[:-1]
                    count_arr = [1] + count_arr[:-1]

                active_ema_vals = []
                for i in range(self.max_anchors):
                    cnt = count_arr[i]
                    prev_ema = ema_prev_arr[i]

                    if cnt > 0:
                        alpha = 2.0 / (cnt + 1.0)
                        current_ema = (src_val - prev_ema) * alpha + prev_ema
                        ema_prev_arr[i] = current_ema
                        count_arr[i] = cnt + 1
                        active_ema_vals.append(current_ema)

                sz = len(active_ema_vals)
                if sz > 0:
                    cluster_high = max(active_ema_vals)
                    cluster_low = min(active_ema_vals)
                    if self.agg_method == "Average":
                        cluster_center = np.mean(active_ema_vals)
                    else:
                        cluster_center = np.median(active_ema_vals)
                    cluster_sd = np.std(active_ema_vals) if sz > 1 else 0
                else:
                    cluster_high = np.nan
                    cluster_low = np.nan
                    cluster_center = np.nan
                    cluster_sd = 0

                if cluster_sd > 0 and not np.isnan(cluster_center):
                    osc_val = (src_val - cluster_center) / cluster_sd
                    env_top = (cluster_high - cluster_center) / cluster_sd
                    env_bot = (cluster_low - cluster_center) / cluster_sd
                else:
                    osc_val = 0
                    env_top = np.nan
                    env_bot = np.nan

                osc_vals.append(osc_val)
                env_tops.append(env_top)
                env_bots.append(env_bot)

            osc_series = pd.Series(osc_vals, index=close.index)
            signal_series = pta.sma(osc_series, length=self.mean_length)
            if signal_series is None:
                signal_series = pd.Series(0, index=close.index)

            return osc_series, signal_series

        self.osc_val, self.signal = self.I(calc_cluster_metrics)

    def next(self):
        if len(self.data) < self.mean_length + 1:
            return

        current_osc = self.osc_val[-1]
        current_signal = self.signal[-1]

        prev_osc = self.osc_val[-2] if len(self.osc_val) > 1 else current_osc
        prev_signal = self.signal[-2] if len(self.signal) > 1 else current_signal

        if not self.position:
            if crossover(self.osc_val, 0):
                self.buy()
            elif crossover(self.signal, 2.0) and current_osc > 0:
                self.buy()
        else:
            if crossover(0, self.osc_val):
                self.position.close()
            elif crossover(2.0, self.signal) and current_osc < 0:
                self.position.close()


