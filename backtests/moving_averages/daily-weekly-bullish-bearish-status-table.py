import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastBullLen = 5
    slowBullLen = 12
    bearFastLen = 34
    bearSlowLen = 50

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Daily EMAs
        self.dEma5 = self.I(pta.ema, close, length=self.fastBullLen)
        self.dEma12 = self.I(pta.ema, close, length=self.slowBullLen)
        self.dEma34 = self.I(pta.ema, close, length=self.bearFastLen)
        self.dEma50 = self.I(pta.ema, close, length=self.bearSlowLen)

    def next(self):
        if len(self.data) < max(self.fastBullLen, self.slowBullLen, self.bearFastLen, self.bearSlowLen):
            return
        
        dClose = self.data.Close[-1]
        dEma5 = self.dEma5[-1]
        dEma12 = self.dEma12[-1]
        dEma34 = self.dEma34[-1]
        dEma50 = self.dEma50[-1]
        
        bullishDaily = dEma5 > dEma12
        bearishDaily = dClose < dEma34 and dClose < dEma50
        
        bullishCross = crossover(self.dEma5, self.dEma12)
        bearishCross = crossover(self.dEma12, self.dEma5)
        
        if bullishCross and not self.position:
            self.buy()
        elif bearishCross and self.position:
            self.sell()
        elif bearishDaily and self.position:
            self.sell()