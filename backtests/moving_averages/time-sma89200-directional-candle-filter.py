import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Settings from Pine Script
    dist_threshold = 3.0
    slope_bars = 5
    slope_threshold = 1.0
    doji_threshold = 0.10
    wick_ratio_block = 0.40

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # Calculate SMA89 and SMA200
        self.sma89 = self.I(pta.sma, close, length=89)
        self.sma200 = self.I(pta.sma, close, length=200)
        
        # Store previous values for slope calculation
        self.sma89_prev = self.I(lambda: self.sma89.shift(self.slope_bars))
        self.sma200_prev = self.I(lambda: self.sma200.shift(self.slope_bars))
        
        # Store OHLC for candle analysis
        self.open = open_
        self.high = high
        self.low = low
        self.close = close

    def next(self):
        # Check if we have enough data
        if len(self.data) < max(200, self.slope_bars + 1):
            return
        
        # =====================================
        # TIME FILTER (UTC+8 / Singapore)
        # =====================================
        # Simplified: check if current bar time is in blocked zones
        # In backtesting, we'll use a simpler approach based on hour
        current_time = pd.Timestamp(self.data.index[-1])
        hour = current_time.hour
        
        # Block times (UTC+8): 0400-0700, 0830-0915, 1600-2045
        time_blocked = (4 <= hour < 7) or (8 <= hour < 9) or (16 <= hour < 21)
        time_allowed = not time_blocked
        
        # =====================================
        # SMA89 / SMA200 COMPRESSION + FLAT FILTER
        # =====================================
        sma89_current = self.sma89[-1]
        sma200_current = self.sma200[-1]
        sma89_prev = self.sma89_prev[-1] if self.sma89_prev[-1] is not None else sma89_current
        sma200_prev = self.sma200_prev[-1] if self.sma200_prev[-1] is not None else sma200_current
        
        if pd.isna(sma89_current) or pd.isna(sma200_current):
            return
        
        ma_close_together = abs(sma89_current - sma200_current) < self.dist_threshold
        sma89_flat = abs(sma89_current - sma89_prev) < self.slope_threshold
        sma200_flat = abs(sma200_current - sma200_prev) < self.slope_threshold
        
        ma_blocked = ma_close_together and sma89_flat and sma200_flat
        ma_allowed = not ma_blocked
        
        # =====================================
        # LAST CLOSED CANDLE FILTER
        # =====================================
        if len(self.data) < 2:
            return
        
        prev_open = self.open[-2]
        prev_high = self.high[-2]
        prev_low = self.low[-2]
        prev_close = self.close[-2]
        
        prev_range = prev_high - prev_low
        prev_body = abs(prev_close - prev_open)
        
        upper_wick = prev_high - max(prev_open, prev_close)
        lower_wick = min(prev_open, prev_close) - prev_low
        
        if prev_range > 0:
            body_ratio = prev_body / prev_range
            upper_wick_ratio = upper_wick / prev_range
            lower_wick_ratio = lower_wick / prev_range
        else:
            body_ratio = 1.0
            upper_wick_ratio = 0.0
            lower_wick_ratio = 0.0
        
        # Doji detection
        doji = body_ratio < self.doji_threshold
        
        # Directional wick blocks
        buy_wick_blocked = not doji and upper_wick_ratio > self.wick_ratio_block
        sell_wick_blocked = not doji and lower_wick_ratio > self.wick_ratio_block
        
        buy_wick_allowed = not buy_wick_blocked
        sell_wick_allowed = not sell_wick_blocked
        
        # =====================================
        # FINAL BUY / SELL FILTERS
        # =====================================
        buy_allowed = time_allowed and ma_allowed and buy_wick_allowed
        sell_allowed = time_allowed and ma_allowed and sell_wick_allowed
        
        # =====================================
        # TRADING LOGIC
        # =====================================
        # Buy signal when conditions are met and price crosses above SMA89
        if buy_allowed and sma89_current is not None:
            if len(self.data) >= 2:
                prev_close = self.close[-2]
                if prev_close <= self.sma89[-2] and self.close[-1] > self.sma89[-1]:
                    if not self.position:
                        self.buy()
        
        # Sell signal when conditions are met and price crosses below SMA200
        if sell_allowed and sma200_current is not None:
            if len(self.data) >= 2:
                prev_close = self.close[-2]
                if prev_close >= self.sma200[-2] and self.close[-1] < self.sma200[-1]:
                    if self.position:
                        self.position.close()
        
        # Exit long if price breaks below SMA200
        if self.position and self.close[-1] < self.sma200[-1]:
            self.position.close()


