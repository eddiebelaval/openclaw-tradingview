class TvStrategy(Strategy):
    # DeltaFlow Filter parameters
    use_df_filter = True
    df_length = 60
    
    # Long settings
    use_long = True
    length_long = 55
    ma_type_long = 'EMA'
    length_long2 = 89
    ma_type_long2 = 'WMA'
    
    # Short settings
    use_short = True
    length_short = 34
    ma_type_short = 'EMA'
    length_short2 = 21
    ma_type_short2 = 'WMA'
    
    # Volume integration
    use_volume_integration = True
    
    # Volatility settings
    use_dynamic_cloud = True
    volatility_period = 14
    volatility_lookback = 100
    base_cloud_distance = 0.01
    
    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate CVD with volume
        def calc_cvd():
            if self.use_volume_integration:
                volume_delta = volume * (close - open_)
            else:
                volume_delta = volume * (close - open_) / (high - low + 1e-10)
            cvd = volume_delta.fillna(0).cumsum()
            return cvd
        
        self.cvd = self.I(calc_cvd)
        
        # Calculate moving averages for CVD
        def calc_ma_long():
            cvd_vals = self.cvd
            if self.ma_type_long == 'EMA':
                return pta.ema(cvd_vals, length=self.length_long)
            elif self.ma_type_long == 'WMA':
                return pta.wma(cvd_vals, length=self.length_long)
            elif self.ma_type_long == 'SMA':
                return pta.sma(cvd_vals, length=self.length_long)
            else:
                return pta.ema(cvd_vals, length=self.length_long)
        
        def calc_ma_long2():
            cvd_vals = self.cvd
            if self.ma_type_long2 == 'EMA':
                return pta.ema(cvd_vals, length=self.length_long2)
            elif self.ma_type_long2 == 'WMA':
                return pta.wma(cvd_vals, length=self.length_long2)
            elif self.ma_type_long2 == 'SMA':
                return pta.sma(cvd_vals, length=self.length_long2)
            else:
                return pta.ema(cvd_vals, length=self.length_long2)
        
