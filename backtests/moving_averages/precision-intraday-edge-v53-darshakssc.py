import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_fast = 8
    len_slow = 21
    swing_len = 3
    vol_mult = 1.2

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_price = pd.Series(self.data.Open)

        self.ema_fast = self.I(pta.ema, close, length=self.len_fast)
        self.ema_slow = self.I(pta.ema, close, length=self.len_slow)
        
        vol_sma = self.I(pta.sma, volume, length=20)
        self.vol_spike = self.I(lambda: volume > vol_sma * self.vol_mult)
        
        self.trend_up = self.I(lambda: self.ema_fast > self.ema_slow)
        
        self.pivot_high = self.I(self._calc_pivot_high, high)
        self.pivot_low = self.I(self._calc_pivot_low, low)
        
        self.in_zone = self.I(lambda: pd.Series(False, index=close.index))
        self.is_bull_zone = self.I(lambda: pd.Series(False, index=close.index))
        self.zone_level = self.I(lambda: pd.Series(np.nan, index=close.index))
        
        self.close_data = close
        self.open_data = open_price
        self.high_data = high
        self.low_data = low

    def _calc_pivot_high(self, high):
        result = pd.Series(index=high.index, dtype=float)
        for i in range(self.swing_len, len(high) - self.swing_len):
            if high.iloc[i] == high.iloc[i - self.swing_len:i + self.swing_len + 1].max():
                result.iloc[i] = high.iloc[i]
            else:
                result.iloc[i] = np.nan
        return result

    def _calc_pivot_low(self, low):
        result = pd.Series(index=low.index, dtype=float)
        for i in range(self.swing_len, len(low) - self.swing_len):
            if low.iloc[i] == low.iloc[i - self.swing_len:i + self.swing_len + 1].min():
                result.iloc[i] = low.iloc[i]
            else:
                result.iloc[i] = np.nan
        return result

    def next(self):
        if len(self.data) < self.swing_len + 1:
            return

        idx = len(self.data) - 1
        
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        
        ema_fast_val = self.ema_fast[-1]
        ema_slow_val = self.ema_slow[-1]
        trend_up = ema_fast_val > ema_slow_val
        vol_spike = self.vol_spike[-1]
        
        zone_level = np.nan
        is_bull_zone = False
        in_zone = False
        
        if idx >= self.swing_len:
            idx_check = idx - self.swing_len
            
            if idx_check >= 0 and idx_check < len(self.data) - self.swing_len:
                ph_val = self.pivot_high[idx_check]
                pl_val = self.pivot_low[idx_check]
                
                if not np.isnan(pl_val):
                    close_check = self.close_data.iloc[idx_check]
                    open_check = self.open_data.iloc[idx_check]
                    high_check = self.high_data.iloc[idx_check]
                    low_check = self.low_data.iloc[idx_check]
                    
                    impulse_up = (close_check > open_check and 
                                (close_check - low_check) > (high_check - low_check) * 0.7)
                    
                    if impulse_up:
                        zone_level = min(open_check, close_check)
                        is_bull_zone = True
                
                if not np.isnan(ph_val):
                    close_check = self.close_data.iloc[idx_check]
                    open_check = self.open_data.iloc[idx_check]
                    high_check = self.high_data.iloc[idx_check]
                    low_check = self.low_data.iloc[idx_check]
                    
                    impulse_down = (close_check < open_check and 
                                  (high_check - close_check) > (high_check - low_check) * 0.7)
                    
                    if impulse_down:
                        zone_level = max(open_check, close_check)
                        is_bull_zone = False
        
        if not np.isnan(zone_level):
            zone_pct_diff = abs(close_val - zone_level) / close_val
            in_zone = zone_pct_diff < 0.006
        
        bull_signal = (in_zone and is_bull_zone and trend_up and 
                      close_val > open_val and vol_spike)
        bear_signal = (in_zone and not is_bull_zone and not trend_up and 
                      close_val < open_val and vol_spike)
        
        if bull_signal and not self.position:
            self.buy()
        elif bear_signal and self.position:
            self.position.close()