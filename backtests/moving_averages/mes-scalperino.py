import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime


class TvStrategy(Strategy):
    # Signal type
    signal_type = "SMA(50) > SMA(200)"
    
    # Risk parameters
    tp_points = 3.0
    sl_points = 200.0
    max_hold_bars = 480
    gap_exit_min = 0
    
    # Session filter
    session_filter = "Custom"
    custom_session_start = 13
    custom_session_end = 16
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate SMAs
        self.sma20 = self.I(pta.sma, close, length=20)
        self.sma50 = self.I(pta.sma, close, length=50)
        self.sma100 = self.I(pta.sma, close, length=100)
        self.sma200 = self.I(pta.sma, close, length=200)
        
        # Calculate EMAs
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema100 = self.I(pta.ema, close, length=100)
        
        # Calculate RSI
        self.rsi9 = self.I(pta.rsi, close, length=9)
        self.rsi14 = self.I(pta.rsi, close, length=14)
        
        # Track entry info
        self.entry_price = None
        self.entry_bar = None
        
    def get_session_allowed(self):
        """Check if current bar is within allowed session window"""
        if len(self.data) == 0:
            return False
            
        bar_time = self.data.index[-1]
        current_hour = bar_time.hour
        
        if self.session_filter == "No Filter":
            return True
        elif self.session_filter == "RTH 9:30-16:00":
            return 9 <= current_hour < 16
        elif self.session_filter == "Core RTH 10-15":
            return 10 <= current_hour < 15
        elif self.session_filter == "Evening ETH 18-01":
            return current_hour >= 18 or current_hour < 1
        elif self.session_filter == "Full ETH (outside RTH)":
            return current_hour < 9 or current_hour >= 16
        elif self.session_filter == "Custom":
            if self.custom_session_start <= self.custom_session_end:
                return self.custom_session_start <= current_hour < self.custom_session_end
            else:
                return current_hour >= self.custom_session_start or current_hour < self.custom_session_end
        
        return True
    
    def get_signal_fired(self):
        """Determine if signal conditions are met"""
        if len(self.data) < 2:
            return False
        
        # Crossover signals (event-based)
        sma_cross = crossover(self.sma20, self.sma50)
        ema_cross = crossover(self.ema50, self.ema100)
        
        # RSI extreme signals
        rsi9_extreme = (self.rsi9[-1] < 20 or self.rsi9[-1] > 80) if self.rsi9[-1] is not None else False
        rsi14_25_75 = (self.rsi14[-1] < 25 or self.rsi14[-1] > 75) if self.rsi14[-1] is not None else False
        rsi14_20_80 = (self.rsi14[-1] < 20 or self.rsi14[-1] > 80) if self.rsi14[-1] is not None else False
        
        # State signals (fire every bar condition holds)
        sma_state = (self.sma50[-1] > self.sma200[-1]) if (self.sma50[-1] is not None and self.sma200[-1] is not None) else False
        ema_state = (self.ema50[-1] > self.ema100[-1]) if (self.ema50[-1] is not None and self.ema100[-1] is not None) else False
        
        # Select active signal based on signal type
        if self.signal_type == "SMA(20) x> SMA(50)":
            return sma_cross
        elif self.signal_type == "EMA(50) x> EMA(100)":
            return ema_cross
        elif self.signal_type == "RSI(9) <20 or >80":
            return rsi9_extreme
        elif self.signal_type == "RSI(14) <25 or >75":
            return rsi14_25_75
        elif self.signal_type == "RSI(14) <20 or >80":
            return rsi14_20_80
        elif self.signal_type == "SMA(50) > SMA(200)":
            return sma_state
        elif self.signal_type == "EMA(50) > EMA(100)":
            return ema_state
        elif self.signal_type == "All Crossovers":
            return sma_cross or ema_cross
        elif self.signal_type == "All RSI":
            return rsi9_extreme or rsi14_25_75
        
        return False
    
    def next(self):
        # Get session allowed status
        session_allowed = self.get_session_allowed()
        
        # Get signal (use previous bar signal for causality)
        if len(self.data) >= 2:
            # We need to check signal from bar[1]
            signal_fired = self.get_signal_fired()
        else:
            signal_fired = False
        
        # Entry logic: signal fired on previous bar, session allowed on entry bar, no open position
        if signal_fired and session_allowed and not self.position:
            self.entry_price = self.data.Open[-1]
            self.entry_bar = len(self.data) - 1
            self.buy()
        
        # Exit logic for open positions
        if self.position:
            bars_held = len(self.data) - 1 - self.entry_bar
            current_price = self.data.Close[-1]
            
            # Take profit exit
            if current_price >= self.entry_price + self.tp_points:
                self.position.close()
                return
            
            # Stop loss exit
            if current_price <= self.entry_price - self.sl_points:
                self.position.close()
                return
            
            # Time-based exit
            if bars_held >= self.max_hold_bars:
                self.position.close()
                return
            
            # Session gap exit (check for large time gap between bars)
            if self.gap_exit_min > 0 and len(self.data) >= 2:
                current_time = self.data.index[-1]
                prev_time = self.data.index[-2]
                time_diff_minutes = (current_time - prev_time).total_seconds() / 60
                
                if time_diff_minutes > self.gap_exit_min:
                    self.position.close()
                    return


