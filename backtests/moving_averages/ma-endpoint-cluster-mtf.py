import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    m1_len = 10
    m2_len = 20
    m3_len = 50
    m4_len = 100
    m5_len = 150
    m6_len = 200
    m7_len = 360

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ma_10 = self.I(lambda x=close: pta.sma(x, length=10))
        self.ma_20 = self.I(lambda x=close: pta.sma(x, length=20))
        self.ma_50 = self.I(lambda x=close: pta.sma(x, length=50))
        self.ma_100 = self.I(lambda x=close: pta.sma(x, length=100))
        self.ma_150 = self.I(lambda x=close: pta.sma(x, length=150))
        self.ma_200 = self.I(lambda x=close: pta.sma(x, length=200))
        self.ma_360 = self.I(lambda x=close: pta.sma(x, length=360))

    def next(self):
        if len(self.data) < self.m7_len + 1:
            return
        
        close_price = self.data.Close[-1]
        ma_10_val = self.ma_10[-1]
        ma_20_val = self.ma_20[-1]
        ma_50_val = self.ma_50[-1]
        ma_200_val = self.ma_200[-1]
        
        if pd.isna(ma_200_val) or pd.isna(ma_50_val):
            return
        
        if not self.position:
            if crossover(self.ma_10, self.ma_20) and close_price > ma_50_val > ma_200_val:
                self.buy()
            elif crossover(self.ma_20, self.ma_10) and close_price < ma_50_val < ma_200_val:
                self.buy()
        else:
            if crossover(self.ma_20, self.ma_10):
                self.sell()
            elif crossover(self.ma_10, self.ma_20):
                self.sell()