import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema9Length = 9
    ema50Length = 50
    ema200Length = 200

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema9 = self.I(pta.ema, close, length=self.ema9Length)
        self.ema50 = self.I(pta.ema, close, length=self.ema50Length)
        self.ema200 = self.I(pta.ema, close, length=self.ema200Length)

    def next(self):
        upTrend = self.ema50[-1] > self.ema200[-1]
        downTrend = self.ema50[-1] < self.ema200[-1]
        
        buyCondition = crossover(self.ema9, self.ema50) and upTrend
        sellCondition = crossover(self.ema50, self.ema9) and downTrend
        
        if buyCondition:
            self.buy()
        elif sellCondition:
            self.sell()


if __name__ == "__main__":
    from backtesting.test import GOOG
    
    bt = Backtest(GOOG, TvStrategy, cash=10000, commission=.002)
    results = bt.run()
    print(results)
