import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA 1 parameters
    ma1_type = "EMA"
    ma1_len = 5
    
    # MA 2 parameters
    ma2_type = "EMA"
    ma2_len = 8
    
    # MA 3 parameters
    ma3_type = "EMA"
    ma3_len = 13
    
    # MA 4 parameters
    ma4_type = "RMA"
    ma4_len = 200
    
    # Keltner Channel parameters
    kc_len = 20
    kc_atr_len = 10
    kc_mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # MA 1 - EMA 5
        self.ma1 = self.I(lambda: self._calc_ma(close, self.ma1_len, self.ma1_type))
        
        # MA 2 - EMA 8
        self.ma2 = self.I(lambda: self._calc_ma(close, self.ma2_len, self.ma2_type))
        
        # MA 3 - EMA 13
        self.ma3 = self.I(lambda: self._calc_ma(close, self.ma3_len, self.ma3_type))
        
        # MA 4 - RMA 200
        self.ma4 = self.I(lambda: self._calc_ma(close, self.ma4_len, self.ma4_type))
        
        # Keltner Channel
        ema_mid = self.I(lambda: pta.ema(close, length=self.kc_len))
        atr = self.I(lambda: pta.atr(high, low, close, length=self.kc_atr_len))
        
        self.kc_mid = ema_mid
        self.kc_upper = self.I(lambda: pta.ema(close, length=self.kc_len) + self.kc_mult * pta.atr(high, low, close, length=self.kc_atr_len))
        self.kc_lower = self.I(lambda: pta.ema(close, length=self.kc_len) - self.kc_mult * pta.atr(high, low, close, length=self.kc_atr_len))

    def _calc_ma(self, src, length, ma_type):
        if ma_type == "SMA":
            return pta.sma(src, length=length)
        elif ma_type == "EMA":
            return pta.ema(src, length=length)
        elif ma_type == "RMA":
            return pta.rma(src, length=length)
        elif ma_type == "HMA":
            half_len = length // 2
            sqrt_len = int(np.sqrt(length))
            wma1 = pta.wma(src, length=half_len)
            wma2 = pta.wma(src, length=length)
            return pta.wma(2 * wma1 - wma2, length=sqrt_len)
        elif ma_type == "TMA":
            half_len = length // 2 + 1
            sma1 = pta.sma(src, length=half_len)
            return pta.sma(sma1, length=half_len)
        elif ma_type == "LSMA":
            return pta.linreg(src, length=length)
        elif ma_type == "DEMA":
            ema1 = pta.ema(src, length=length)
            ema2 = pta.ema(ema1, length=length)
            return 2 * ema1 - ema2
        elif ma_type == "TEMA":
            ema1 = pta.ema(src, length=length)
            ema2 = pta.ema(ema1, length=length)
            ema3 = pta.ema(ema2, length=length)
            return 3 * ema1 - 3 * ema2 + ema3
        else:
            return pta.ema(src, length=length)

    def next(self):
        # Trading logic: Buy when fast MAs cross above slow MA, sell when crossing below
        # Using MA1 (5), MA2 (8), MA3 (13) as fast MAs and MA4 (200) as slow MA
        
        if len(self) < self.ma4_len + 50:
            return
        
        fast_ma = (self.ma1[-1] + self.ma2[-1] + self.ma3[-1]) / 3
        slow_ma = self.ma4[-1]
        
        # Buy signal: fast MAs above slow MA and price above Keltner upper band
        if not self.position:
            if fast_ma > slow_ma and self.data.Close[-1] > self.kc_mid[-1]:
                if crossover(self.ma1, self.ma2):
                    self.buy()
        
        # Sell signal: fast MAs below slow MA or price below Keltner lower band
        if self.position:
            if fast_ma < slow_ma or self.data.Close[-1] < self.kc_lower[-1]:
                self.sell()


