import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Cloud Settings
    ma_type = "EMA"
    ma_len_short = 9
    ma_len_long = 15
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate MAs based on hl2 (high + low) / 2
        hl2 = (high + low) / 2
        
        if self.ma_type == "EMA":
            self.short_ma = self.I(pta.ema, hl2, length=self.ma_len_short)
            self.long_ma = self.I(pta.ema, hl2, length=self.ma_len_long)
        else:
            self.short_ma = self.I(pta.sma, hl2, length=self.ma_len_short)
            self.long_ma = self.I(pta.sma, hl2, length=self.ma_len_long)
    
    def next(self):
        # Simple trading logic based on EMA Cloud crossover
        # Buy when short MA crosses above long MA (bullish cloud)
        if len(self.short_ma) > 1 and len(self.long_ma) > 1:
            if crossover(self.short_ma, self.long_ma):
                if not self.position:
                    self.buy()
            # Sell when short MA crosses below long MA (bearish cloud)
            elif crossover(self.long_ma, self.short_ma):
                if self.position:
                    self.position.close()