class TvStrategy(Strategy):
    frama_len = 100
    fast_const = 5
    slow_const = 8
    touch_limit = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # FRAMA Calculation
        len1 = int(self.frama_len / 2)
        w_val = np.log(2 / (self.slow_const + 1))
        
        def calculate_frama(close, high, low):
            frama_values = []
            frama_raw = close.iloc[0]
            
            for i in range(len(close)):
                if i < self.frama_len:
                    frama_values.append(close.iloc[i])
                    continue
                
                # Calculate fractal dimensions
                if i >= len1:
                    H1 = high.iloc[i-len1:i].max()
                    L1 = low.iloc[i-len1:i].min()
                    N1 = (H1 - L1) / len1 if len1 > 0 else 0
                else:
                    N1 = 0
                
                if i >= self.frama_len:
                    H2 = high.iloc[i-self.frama_len:i-len1].max() if i >= self.frama_len + len1 else 0
                    L2 = low.iloc[i-self.frama_len:i-len1].min() if i >= self.frama_len + len1 else 0
                    N2 = (H2 - L2) / len1 if len1 > 0 else 0
                else:
                    N2 = 0
                
                H3 = high.iloc[i-self.frama_len:i].max() if i >= self.frama_len else high.iloc[0:i].max()
                L3 = low.iloc[i-self.frama_len:i].min() if i >= self.frama_len else low.iloc[0:i].min()
                N3 = (H3 - L3) / self.frama_len if self.frama_len > 0 else 0
                
                # Fractal dimension
                if N1 > 0 and N2 > 0 and N3 > 0:
                    dimen = (np.log(N1 + N2) - np.log(N3)) / np.log(2)
                else:
                    dimen = 1.0
                
                alpha_exp = np.exp(w_val * (dimen - 1))
                alpha_raw = min(1.0, max(0.01, alpha_exp))
                
