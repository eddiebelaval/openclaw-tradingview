import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len20 = 20
    len50 = 50
    len200 = 200
    volLookback = 10
    volMultiplier = 2.0
    useHighestFilter = False
    touchBufferPct = 0.0
    showBounce50 = True
    showBounce200 = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # EMAs
        self.ema20 = self.I(pta.ema, close, length=self.len20)
        self.ema50 = self.I(pta.ema, close, length=self.len50)
        self.ema200 = self.I(pta.ema, close, length=self.len200)

        # Volume SMA
        self.volSMA = self.I(pta.sma, volume, length=self.volLookback)

        # Highest volume for filter
        def highest_volume():
            return volume.rolling(window=self.volLookback).max()

        self.highestVol = self.I(highest_volume)

        # High volume logic
        def high_vol_logic():
            highVolBySMA = volume > self.volSMA * self.volMultiplier
            if self.useHighestFilter:
                highVolByHighest = volume > self.highestVol
                return highVolBySMA & highVolByHighest
            else:
                return highVolBySMA

        self.highVol = self.I(high_vol_logic)

        # Buffer for bounce touch
        def buf50_calc():
            return self.ema50 * (self.touchBufferPct / 100.0)

        def buf200_calc():
            return self.ema200 * (self.touchBufferPct / 100.0)

        self.buf50 = self.I(buf50_calc)
        self.buf200 = self.I(buf200_calc)

        # Touch logic
        def touch50_logic():
            return (low <= self.ema50 + self.buf50) & (high >= self.ema50 - self.buf50)

        def touch200_logic():
            return (low <= self.ema200 + self.buf200) & (high >= self.ema200 - self.buf200)

        self.touch50 = self.I(touch50_logic)
        self.touch200 = self.I(touch200_logic)

        # Bounce signals
        def bull_bounce50_logic():
            return self.showBounce50 & self.touch50 & (close > self.ema50)

        def bear_bounce50_logic():
            return self.showBounce50 & self.touch50 & (close < self.ema50)

        def bull_bounce200_logic():
            return self.showBounce200 & self.touch200 & (close > self.ema200)

        def bear_bounce200_logic():
            return self.showBounce200 & self.touch200 & (close < self.ema200)

        self.bullBounce50 = self.I(bull_bounce50_logic)
        self.bearBounce50 = self.I(bear_bounce50_logic)
        self.bullBounce200 = self.I(bull_bounce200_logic)
        self.bearBounce200 = self.I(bear_bounce200_logic)

        # Cross signals
        def bull_cross_logic():
            ema20_cross_200 = crossover(self.ema20, self.ema200)
            ema50_cross_200 = crossover(self.ema50, self.ema200)
            return (ema20_cross_200 | ema50_cross_200) & self.highVol

        def bear_cross_logic():
            ema20_cross_200 = crossover(self.ema200, self.ema20)
            ema50_cross_200 = crossover(self.ema200, self.ema50)
            return (ema20_cross_200 | ema50_cross_200) & self.highVol

        self.bullCrossSignal = self.I(bull_cross_logic)
        self.bearCrossSignal = self.I(bear_cross_logic)

        # Bounce signals with volume filter
        def bull_bounce50_signal_logic():
            return self.bullBounce50 & self.highVol

        def bear_bounce50_signal_logic():
            return self.bearBounce50 & self.highVol

        def bull_bounce200_signal_logic():
            return self.bullBounce200 & self.highVol

        def bear_bounce200_signal_logic():
            return self.bearBounce200 & self.highVol

        self.bullBounce50Signal = self.I(bull_bounce50_signal_logic)
        self.bearBounce50Signal = self.I(bear_bounce50_signal_logic)
        self.bullBounce200Signal = self.I(bull_bounce200_signal_logic)
        self.bearBounce200Signal = self.I(bear_bounce200_signal_logic)

    def next(self):
        if len(self.data) < max(self.len20, self.len50, self.len200) + 5:
            return

        if not self.position:
            if self.bullCrossSignal[-1]:
                self.buy()
            elif self.bullBounce50Signal[-1]:
                self.buy()
            elif self.bullBounce200Signal[-1]:
                self.buy()
        else:
            if self.bearCrossSignal[-1]:
                self.sell()
            elif self.bearBounce50Signal[-1]:
                self.sell()
            elif self.bearBounce200Signal[-1]:
                self.sell()