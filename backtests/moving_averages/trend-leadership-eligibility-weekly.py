import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback_weeks = 30
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR for volatility normalization
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # Calculate standard deviation for orderliness
        self.stdev = self.I(
            lambda: pd.Series(close).rolling(window=20).std(),
            name='stdev'
        )
        
        # Calculate weekly range for structure analysis
        self.range_pct = self.I(
            lambda: (high - low) / close.clip(lower=0.001),
            name='range_pct'
        )
        
        # Calculate rolling highest and lowest of range for position
        self.range_hi = self.I(
            lambda: pd.Series(self.range_pct).rolling(window=20).max(),
            name='range_hi'
        )
        
        self.range_lo = self.I(
            lambda: pd.Series(self.range_pct).rolling(window=20).min(),
            name='range_lo'
        )
        
        # Track eligibility state for entry/exit
        self.was_eligible = False
        self.eligible_bars = 0
    
    def next(self):
        if len(self.data) < 30:
            return
        
        # 1. RELATIVE STRENGTH - using price trend as proxy
        # (without actual benchmark, we use simple price momentum)
        close_fast = pd.Series(self.data.Close[-20:]).mean()
        close_slow = pd.Series(self.data.Close[-40:]).mean()
        req_rs = close_fast > close_slow
        
        # 2. VARIANCE-ADJUSTED ORDERLINESS
        # trendSmoothness = stdev / atr
        if self.atr[-1] and self.stdev[-1]:
            trend_smoothness = self.stdev[-1] / max(self.atr[-1], 0.001)
            req_orderly = trend_smoothness < 2.5
        else:
            req_orderly = False
        
        # 3. STRUCTURE TIGHTNESS REGIME
        # rPos = (rangeW - rLo) / (rHi - rLo)
        if self.range_hi[-1] and self.range_lo[-1]:
            range_diff = max(self.range_hi[-1] - self.range_lo[-1], 1e-10)
            r_pos = (self.range_pct[-1] - self.range_lo[-1]) / range_diff
            req_structure = r_pos <= 0.65
        else:
            req_structure = False
        
        # Composite eligibility
        eligible = req_rs and req_orderly and req_structure
        
        # Entry: transition from not eligible to eligible
        if eligible and not self.was_eligible:
            if not self.position:
                self.buy()
            self.eligible_bars = 1
        
        # Exit: transition from eligible to not eligible
        elif not eligible and self.was_eligible:
            if self.position:
                self.position.close()
            self.eligible_bars = 0
        
        # Count bars while eligible
        elif eligible:
            self.eligible_bars += 1
        else:
            self.eligible_bars = 0
        
        self.was_eligible = eligible