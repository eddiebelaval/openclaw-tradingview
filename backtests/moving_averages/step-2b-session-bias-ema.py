import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMA and SMA
        self.ema = self.I(pta.ema, close, length=7)
        self.sma = self.I(pta.sma, self.ema, length=7)
        
        # Track bias state
        self.live_bias = 0
        self.crossed_after_bias = False
        self.last_bias_bar = -1

    def next(self):
        # Get 30M data equivalent - use current bar's OHLCV
        open_price = self.data.Open[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        close_price = self.data.Close[-1]
        
        # Calculate range and CSP (Cumulative Segment Percentage)
        rng = high_price - low_price
        if rng == 0:
            rng = 0.0001
        
        bull = close_price > open_price
        bear = close_price < open_price
        
        if bull:
            csp = ((close_price - low_price) / rng) * 100
        else:
            csp = ((high_price - close_price) / rng) * 100
        
        flip_level = 78.6
        
        # Bias determination logic
        buy_bias = (bull and csp >= 50 and csp <= flip_level) or \
                   (bear and (csp < 50 or csp > flip_level))
        
        sell_bias = (bear and csp >= 50 and csp <= flip_level) or \
                    (bull and (csp < 50 or csp > flip_level))
        
        bias_dir = 1 if buy_bias else -1
        
        # Update bias on every bar (simulating session detection)
        if self.live_bias != bias_dir:
            self.live_bias = bias_dir
            self.crossed_after_bias = False
            self.last_bias_bar = len(self.data) - 1
        
        # Check for crossover/crossunder after bias change
        if len(self) > 1:
            if self.live_bias == 1 and crossover(self.ema, self.sma):
                self.crossed_after_bias = True
            
            if self.live_bias == -1 and crossover(self.sma, self.ema):
                self.crossed_after_bias = True
        
        # Trading logic
        if self.crossed_after_bias:
            if self.live_bias == 1 and not self.position:
                self.buy()
                self.crossed_after_bias = False
            elif self.live_bias == -1 and self.position:
                self.sell()
                self.crossed_after_bias = False