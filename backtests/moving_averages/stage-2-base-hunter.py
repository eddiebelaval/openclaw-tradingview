import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_len = 30
    slope_lookback = 4
    base_min_bars = 4
    base_depth_pct = 25.0
    vcp_vol_ratio = 0.85
    base_min_flat = 3
    entry_ema = 10
    entry_vol_mult = 1.5
    w_atr_mult_sl = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Weekly data simulation (using current bar data with adjustments)
        self.w_close = close
        self.w_high = high
        self.w_low = low
        self.w_vol = volume

        # Calculate weekly equivalents
        self.w_ma = self.I(pta.sma, close, length=self.ma_len)
        self.w_atr = self.I(pta.atr, high, low, close, length=14)
        self.w_vol_ma = self.I(pta.sma, volume, length=10)

        # Entry indicators
        self.ema10 = self.I(pta.ema, close, length=self.entry_ema)
        self.vol_avg20 = self.I(pta.sma, volume, length=20)

        # Rolling highest/lowest for base detection
        self.roll_high = self.I(lambda: high.rolling(self.base_min_bars).max())
        self.roll_low = self.I(lambda: low.rolling(self.base_min_bars).min())

        # State tracking
        self.in_trade = False
        self.entry_price = None
        self.stop_loss = None
        self.trail_exit_level = None

    def next(self):
        if len(self.data) < max(self.ma_len, 20, self.base_min_bars):
            return

        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]

        w_ma_val = self.w_ma[-1] if self.w_ma[-1] else close
        w_atr_val = self.w_atr[-1] if self.w_atr[-1] else 0
        ema10_val = self.ema10[-1] if self.ema10[-1] else close
        vol_avg20_val = self.vol_avg20[-1] if self.vol_avg20[-1] else volume

        # Stage 2 detection
        if len(self.w_ma) >= self.slope_lookback + 1:
            w_ma_prev = self.w_ma[-self.slope_lookback - 1] if self.w_ma[-self.slope_lookback - 1] else w_ma_val
        else:
            w_ma_prev = w_ma_val

        ma_rising = w_ma_val > w_ma_prev
        price_above = close > w_ma_val
        is_stage2 = ma_rising and price_above

        # Entry conditions
        if is_stage2 and not self.in_trade:
            # Check entry signal conditions
            near_ema = abs(close - ema10_val) < w_atr_val * 0.5
            vol_surge = volume > (self.entry_vol_mult * vol_avg20_val)

            # Simple tight high check
            tight_high = high
            if len(self.data.High) > 5:
                tight_high = max(self.data.High[-5:])

            entry_signal = near_ema and close > tight_high * 0.99 and vol_surge

            if entry_signal and w_atr_val > 0:
                self.entry_price = close
                self.stop_loss = close - (self.w_atr_mult_sl * w_atr_val)
                self.trail_exit_level = w_ma_val
                self.in_trade = True
                self.buy()

        # Exit logic
        if self.in_trade:
            # Trail exit: close below 30W MA
            if close < self.trail_exit_level or close < self.stop_loss:
                self.in_trade = False
                self.sell()

        # Update trail exit level if price makes new highs
        if self.in_trade and close > self.trail_exit_level:
            self.trail_exit_level = max(self.trail_exit_level, w_ma_val)