import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate moving averages
        self.ma21 = self.I(pta.sma, close, length=21)
        self.ma50 = self.I(pta.sma, close, length=50)
        self.ma80 = self.I(pta.sma, close, length=80)
        self.ma100 = self.I(pta.sma, close, length=100)
        self.ma200 = self.I(pta.sma, close, length=200)

    def next(self):
        # Trading logic based on moving average crossovers
        # Buy when 21 MA crosses above 200 MA
        if crossover(self.ma21, self.ma200):
            self.buy()
        # Sell when 21 MA crosses below 200 MA
        elif crossover(self.ma200, self.ma21):
            self.sell()