import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma1_len = 50
    ma1_type = "EMA"
    ma2_len = 20
    ma2_type = "VWMA"
    ma3_len = 14
    ma3_type = "ZLEMA"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # MA 1 (Daily - EMA 50)
        self.ma1 = self.I(self._get_ma, close, self.ma1_len, self.ma1_type, high, low, volume)

        # MA 2 (Current TF - VWMA 20)
        self.ma2 = self.I(self._get_ma, close, self.ma2_len, self.ma2_type, high, low, volume)

        # MA 3 (Current TF - ZLEMA 14)
        self.ma3 = self.I(self._get_ma, close, self.ma3_len, self.ma3_type, high, low, volume)

        # Previous bar tracking
        self.prev_high = self.I(lambda: high.shift(1).fillna(high))
        self.prev_low = self.I(lambda: low.shift(1).fillna(low))

    def _get_ma(self, close, length, ma_type, high, low, volume):
        if ma_type == "SMA":
            result = pta.sma(close, length=length)
        elif ma_type == "EMA":
            result = pta.ema(close, length=length)
        elif ma_type == "VWMA":
            result = pta.vwma(close, volume, length=length)
        elif ma_type == "ZLEMA":
            lag = int((length - 1) / 2)
            src_adjusted = close + (close - close.shift(lag).fillna(close))
            result = pta.ema(src_adjusted, length=length)
        else:
            result = pta.ema(close, length=length)

        if result is None:
            return pd.Series(close.iloc[0], index=close.index)
        return result

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        prev_high = self.data.High[-2] if len(self.data) > 1 else high
        prev_low = self.data.Low[-2] if len(self.data) > 1 else low

        ma1 = self.ma1[-1]
        ma2 = self.ma2[-1]
        ma3 = self.ma3[-1]

        # Logic filters
        above1 = close > ma1
        above2 = close > ma2
        above3 = close > ma3
        below1 = close < ma1
        below2 = close < ma2
        below3 = close < ma3

        is_above_all = above1 and above2 and above3
        is_below_all = below1 and below2 and below3

        is_bullish_bar = high > prev_high and low > prev_low
        is_bearish_bar = high < prev_high and low < prev_low

        # Track state
        if not hasattr(self, 'last_signal'):
            self.last_signal = 0

        trigger_bullish = is_bullish_bar and is_above_all and self.last_signal != 1
        trigger_bearish = is_bearish_bar and is_below_all and self.last_signal != 2

        if trigger_bullish:
            self.last_signal = 1
            if not self.position:
                self.buy()
        elif trigger_bearish:
            self.last_signal = 2
            if self.position:
                self.position.close()
            else:
                self.sell()


