class TvStrategy(Strategy):
    # EMA Chart-Based parameters
    cEma1Len = 9
    cEma2Len = 15
    
    # PSY Levels parameters
    baseLevel = 56600
    levels = 10
    minorStep = 250  # BankNifty default
    
    # Previous Day levels
    use_pdh = True
    use_pdl = True
    use_pdc = True
    
    # Fibonacci parameters
    use_fib = True
    
    # Pivot points
    use_pivots = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Chart-based EMAs
        self.cEma1 = self.I(pta.ema, close, length=self.cEma1Len)
        self.cEma2 = self.I(pta.ema, close, length=self.cEma2Len)
        
        # Crossover signals for trading
        self.ema_cross_signal = 0

    def next(self):
        # Simple trading logic based on EMA crossovers
        # Buy when fast EMA (9) crosses above slow EMA (15)
        # Sell when fast EMA (9) crosses below slow EMA (15)
        
        if len(self.cEma1) < 2 or len(self.cEma2) < 2:
            return
        
        # Check if EMAs are valid (not NaN)
        if np.isnan(self.cEma1[-1]) or np.isnan(self.cEma2[-1]):
            return
        if np.isnan(self.cEma1[-2]) or np.isnan(self.cEma2[-2]):
            return
        
        # Bullish crossover: EMA1 crosses above EMA2
        if crossover(self.cEma1, self.cEma2):
            if not self.position:
                self.buy()
        
        # Bearish crossover: EMA1 crosses below EMA2
        elif crossover(self.cEma2, self.cEma1):
            if self.position:
                self.position.close()


