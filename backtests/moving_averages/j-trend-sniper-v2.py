import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 6
    ATRPeriod = 16
    ATRMultip = 9
    ATRMultip_fast = 5.1

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.ATRPeriod)
        
        # DefATR calculation
        def calc_def_atr(close_data, atr_data):
            result = pd.Series(index=close_data.index, dtype=float)
            nl = self.ATRMultip * atr_data
            
            result.iloc[0] = close_data.iloc[0]
            
            for i in range(1, len(close_data)):
                if pd.isna(atr_data.iloc[i]) or pd.isna(nl.iloc[i]):
                    result.iloc[i] = close_data.iloc[i]
                    continue
                    
                prev_result = result.iloc[i - 1]
                curr_close = close_data.iloc[i]
                prev_close = close_data.iloc[i - 1]
                
                if curr_close > prev_result and prev_close > prev_result:
                    result.iloc[i] = max(prev_result, curr_close - nl.iloc[i])
                elif curr_close < prev_result and prev_close < prev_result:
                    result.iloc[i] = min(prev_result, curr_close + nl.iloc[i])
                elif curr_close > prev_result:
                    result.iloc[i] = curr_close - nl.iloc[i]
                else:
                    result.iloc[i] = curr_close + nl.iloc[i]
            
            return result
        
        self.defATR = self.I(calc_def_atr, close, self.atr)
        
        # DefATR Fast calculation
        def calc_def_atr_fast(close_data, atr_data):
            result = pd.Series(index=close_data.index, dtype=float)
            nl_fast = self.ATRMultip_fast * atr_data
            
            result.iloc[0] = close_data.iloc[0]
            
            for i in range(1, len(close_data)):
                if pd.isna(atr_data.iloc[i]) or pd.isna(nl_fast.iloc[i]):
                    result.iloc[i] = close_data.iloc[i]
                    continue
                    
                prev_result = result.iloc[i - 1]
                curr_close = close_data.iloc[i]
                prev_close = close_data.iloc[i - 1]
                
                if curr_close > prev_result and prev_close > prev_result:
                    result.iloc[i] = max(prev_result, curr_close - nl_fast.iloc[i])
                elif curr_close < prev_result and prev_close < prev_result:
                    result.iloc[i] = min(prev_result, curr_close + nl_fast.iloc[i])
                elif curr_close > prev_result:
                    result.iloc[i] = curr_close - nl_fast.iloc[i]
                else:
                    result.iloc[i] = curr_close + nl_fast.iloc[i]
            
            return result
        
        self.defATR_fast = self.I(calc_def_atr_fast, close, self.atr)
        
        # Signal calculation
        def calc_signals(close_data, open_data, high_data, low_data):
            cc = pta.sma(close_data, length=self.fastLen)
            oo = pta.sma(open_data, length=self.fastLen)
            hh = pta.sma(high_data, length=self.fastLen)
            ll = pta.sma(low_data, length=self.fastLen)
            
            lv = np.abs(cc - oo) / (hh - ll + 1e-10)
            
            a = pd.Series(index=close_data.index, dtype=float)
            a.iloc[0] = close_data.iloc[0]
            
            for i in range(1, len(close_data)):
                prev_a = a.iloc[i - 1]
                if pd.isna(lv.iloc[i]):
                    a.iloc[i] = prev_a
                else:
                    a.iloc[i] = lv.iloc[i] * close_data.iloc[i] + (1 - lv.iloc[i]) * prev_a
            
            return a
        
        self.signal_a = self.I(calc_signals, close, open_, high, low)
        
        # Fast line (shortened)
        def calc_fast_line(defATR_fast_data, signal_a_data):
            result = pd.Series(index=defATR_fast_data.index, dtype=float)
            for i in range(len(defATR_fast_data)):
                if defATR_fast_data.iloc[i] > signal_a_data.iloc[i]:
                    result.iloc[i] = defATR_fast_data.iloc[i] - (defATR_fast_data.iloc[i] - signal_a_data.iloc[i]) / 2
                else:
                    result.iloc[i] = defATR_fast_data.iloc[i] + (signal_a_data.iloc[i] - defATR_fast_data.iloc[i]) / 2
            return result
        
        self.fast_line = self.I(calc_fast_line, self.defATR_fast, self.signal_a)

    def next(self):
        if len(self.data) < self.ATRPeriod + self.fastLen:
            return
        
        # Check if we have valid data
        if pd.isna(self.atr[-1]) or pd.isna(self.defATR[-1]) or pd.isna(self.signal_a[-1]):
            return
        
        # Long signal: signal_a crosses above defATR
        if crossover(self.signal_a, self.defATR):
            if not self.position:
                self.buy()
        
        # Short signal: signal_a crosses below defATR
        elif crossover(self.defATR, self.signal_a):
            if self.position:
                self.position.close()