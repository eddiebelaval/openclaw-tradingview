import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len1 = 9
    len2 = 21
    len3 = 50
    len4 = 100
    len5 = 200

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        # EMA indicators
        self.ema1 = self.I(pta.ema, close, length=self.len1)
        self.ema2 = self.I(pta.ema, close, length=self.len2)
        self.ema3 = self.I(pta.ema, close, length=self.len3)
        self.ema4 = self.I(pta.ema, close, length=self.len4)
        self.ema5 = self.I(pta.ema, close, length=self.len5)
        
        # WMA indicators
        self.wma1 = self.I(pta.wma, close, length=self.len1)
        self.wma2 = self.I(pta.wma, close, length=self.len2)
        self.wma3 = self.I(pta.wma, close, length=self.len3)
        self.wma4 = self.I(pta.wma, close, length=self.len4)
        self.wma5 = self.I(pta.wma, close, length=self.len5)
        
        # SMA indicators
        self.sma1 = self.I(pta.sma, close, length=self.len1)
        self.sma2 = self.I(pta.sma, close, length=self.len2)
        self.sma3 = self.I(pta.sma, close, length=self.len3)
        self.sma4 = self.I(pta.sma, close, length=self.len4)
        self.sma5 = self.I(pta.sma, close, length=self.len5)
        
        # VWMA indicators
        self.vwma1 = self.I(pta.vwma, close, volume, length=self.len1)
        self.vwma2 = self.I(pta.vwma, close, volume, length=self.len2)
        self.vwma3 = self.I(pta.vwma, close, volume, length=self.len3)
        self.vwma4 = self.I(pta.vwma, close, volume, length=self.len4)
        self.vwma5 = self.I(pta.vwma, close, volume, length=self.len5)
        
        # TEMA indicators
        self.tema1 = self.I(self._tema, close, self.len1)
        self.tema2 = self.I(self._tema, close, self.len2)
        self.tema3 = self.I(self._tema, close, self.len3)
        self.tema4 = self.I(self._tema, close, self.len4)
        self.tema5 = self.I(self._tema, close, self.len5)

    def _tema(self, src, length):
        ema1 = pta.ema(src, length=length)
        ema2 = pta.ema(ema1, length=length)
        ema3 = pta.ema(ema2, length=length)
        if ema1 is None or ema2 is None or ema3 is None:
            return pd.Series(0, index=src.index)
        return 3 * (ema1 - ema2) + ema3

    def next(self):
        # Primary signal: EMA 9/21 crossover
        if crossover(self.ema1, self.ema2):
            if not self.position:
                self.buy()
        elif crossover(self.ema2, self.ema1):
            if self.position:
                self.position.close()
        
        # Secondary confirmation: EMA 21/50 alignment
        # If 21 crosses above 50, strengthen buy signal
        if crossover(self.ema2, self.ema3):
            if not self.position:
                self.buy()
        elif crossover(self.ema3, self.ema2):
            if self.position:
                self.position.close()
        
        # Tertiary confirmation: EMA 50/100 trend
        # If 50 crosses above 100, major trend change
        if crossover(self.ema3, self.ema4):
            if not self.position:
                self.buy()
        elif crossover(self.ema4, self.ema3):
            if self.position:
                self.position.close()
        
        # Macro trend: EMA 100/200
        if crossover(self.ema4, self.ema5):
            if not self.position:
                self.buy()
        elif crossover(self.ema5, self.ema4):
            if self.position:
                self.position.close()


