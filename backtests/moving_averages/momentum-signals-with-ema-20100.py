import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLen = 14
    atrMult = 0.9
    rocLen = 3
    breakLen = 3
    volMult = 1.1

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # ATR & Momentum
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.roc = self.I(pta.roc, close, length=self.rocLen)

        # Candle Body Size
        self.body = self.I(lambda: np.abs(close - open_))

        # Breakout Detection - highest/lowest of previous bars
        self.highest = self.I(lambda: high.rolling(window=self.breakLen).max())
        self.lowest = self.I(lambda: low.rolling(window=self.breakLen).min())

        # Volume Filter
        self.vol_sma = self.I(pta.sma, volume, length=20)

        # EMA Channels
        self.ema20_high = self.I(pta.ema, high, length=20)
        self.ema20_low = self.I(pta.ema, low, length=20)
        self.ema100_high = self.I(pta.ema, high, length=100)
        self.ema100_low = self.I(pta.ema, low, length=100)

    def next(self):
        if len(self.data) < self.breakLen + 1:
            return

        # Get current values
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_volume = self.data.Volume[-1]

        atr = self.atr[-1]
        roc = self.roc[-1]
        body = self.body[-1]
        highest = self.highest[-1]
        lowest = self.lowest[-1]
        vol_sma = self.vol_sma[-1]
        ema20_high = self.ema20_high[-1]
        ema20_low = self.ema20_low[-1]
        ema100_high = self.ema100_high[-1]
        ema100_low = self.ema100_low[-1]

        # Check for None values
        if (atr is None or roc is None or body is None or 
            highest is None or lowest is None or vol_sma is None or
            ema20_high is None or ema20_low is None or 
            ema100_high is None or ema100_low is None):
            return

        # Momentum Impulse Condition
        vol_filter = current_volume > vol_sma * self.volMult
        momentum_impulse = body > atr * self.atrMult and vol_filter

        # Breakout Detection
        high_break = current_close > highest
        low_break = current_close < lowest

        # Trend Filters
        long_filter = current_close > ema100_low
        short_filter = current_close < ema100_high

        # Final Signals
        long_signal = momentum_impulse and roc > 0 and high_break and long_filter
        short_signal = momentum_impulse and roc < 0 and low_break and short_filter

        # Trading Logic
        if long_signal:
            if self.position:
                self.position.close()
            self.buy()
        elif short_signal:
            if self.position:
                self.position.close()
            self.sell()