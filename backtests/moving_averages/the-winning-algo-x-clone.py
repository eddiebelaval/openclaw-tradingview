import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 100
    atrLen = 14
    atrMult = 1.5
    useNextBarSig = False
    useTimeFilter = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate range high and low
        self.rangeHigh = self.I(lambda: high.rolling(self.len).max())
        self.rangeLow = self.I(lambda: low.rolling(self.len).min())
        
        # Range mid and width
        self.rangeMid = self.I(lambda: (high.rolling(self.len).max() + low.rolling(self.len).min()) / 2.0)
        self.rangeWidth = self.I(lambda: high.rolling(self.len).max() - low.rolling(self.len).min())
        
        # ATR and TP bands
        self.atrValue = self.I(pta.atr, high, low, close, length=self.atrLen)
        self.tpUpper = self.I(lambda: (high.rolling(self.len).max() + low.rolling(self.len).min()) / 2.0 + self.atrMult * pta.atr(high, low, close, length=self.atrLen))
        self.tpLower = self.I(lambda: (high.rolling(self.len).max() + low.rolling(self.len).min()) / 2.0 - self.atrMult * pta.atr(high, low, close, length=self.atrLen))
        
        self.longSignalRaw = False
        self.shortSignalRaw = False
        self.inLong = False
        self.inShort = False

    def next(self):
        if len(self.data) < self.len + 1:
            return
        
        close = self.data.Close[-1]
        closePrev = self.data.Close[-2] if len(self.data) >= 2 else close
        rangeHigh = self.rangeHigh[-1]
        rangeHighPrev = self.rangeHigh[-2] if len(self.data) >= 2 else rangeHigh
        rangeLow = self.rangeLow[-1]
        rangeLowPrev = self.rangeLow[-2] if len(self.data) >= 2 else rangeLow
        rangeWidth = self.rangeWidth[-1]
        rangeMid = self.rangeMid[-1]
        
        validRange = rangeWidth > 0
        
        # Raw signals
        if validRange:
            self.longSignalRaw = close > rangeHigh and closePrev <= rangeHighPrev
            self.shortSignalRaw = close < rangeLow and closePrev >= rangeLowPrev
        else:
            self.longSignalRaw = False
            self.shortSignalRaw = False
        
        # Apply signal delay if enabled
        longSignal = self.longSignalRaw
        shortSignal = self.shortSignalRaw
        
        # Entry logic
        if longSignal and not self.inLong and not self.inShort:
            self.buy()
            self.inLong = True
            self.inShort = False
        
        if shortSignal and not self.inLong and not self.inShort:
            self.sell()
            self.inShort = True
            self.inLong = False
        
        # Exit logic
        if self.inLong and (shortSignal or close < rangeMid):
            self.position.close()
            self.inLong = False
        
        if self.inShort and (longSignal or close > rangeMid):
            self.position.close()
            self.inShort = False


