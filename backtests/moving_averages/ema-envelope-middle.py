import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 20

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMA of close
        ema_close = self.I(pta.ema, close, length=self.len)
        
        # Calculate deviation: a = close - ema(close)
        a = close - ema_close
        
        # Calculate absolute deviation: b = abs(a)
        b = a.abs()
        
        # Calculate EMA of absolute deviation
        ema_b = self.I(pta.ema, b, length=self.len)
        
        # Basis is the EMA of close
        basis = ema_close
        
        # Upper and lower bands
        upper = basis + ema_b
        lower = basis - ema_b
        
        # Smooth upper band: EMA of max(upper, close)
        maxx = pd.concat([upper, close], axis=1).max(axis=1)
        self.smooth = self.I(pta.ema, maxx, length=self.len)
        
        # Smooth lower band: EMA of min(close, lower)
        minn = pd.concat([close, lower], axis=1).min(axis=1)
        self.smooth2 = self.I(pta.ema, minn, length=self.len)
        
        # Middle line: average of smooth and smooth2
        self.middle = (self.smooth + self.smooth2) / 2

    def next(self):
        # Buy when price crosses above the lower smoothed band (smooth2)
        if crossover(self.data.Close, self.smooth2):
            if not self.position:
                self.buy()
        
        # Sell when price crosses below the upper smoothed band (smooth)
        elif crossover(self.smooth, self.data.Close):
            if self.position:
                self.position.close()