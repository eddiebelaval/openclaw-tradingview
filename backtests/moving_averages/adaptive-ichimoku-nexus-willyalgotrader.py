import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Ichimoku parameters
    conversion_period = 9
    base_period = 26
    span_b_period = 52
    displacement = 26
    adapt_len = 50
    adapt_strength = 0.4
    min_score = 50
    
    # TP/SL parameters
    sl_atr_mult = 0.5
    tp1_mult = 1.5
    tp2_mult = 2.5
    tp3_mult = 4.0
    
    # Filters
    use_kumo_filter = True
    use_vol_filter = True
    use_chikou_filter = True
    use_breakout = True
    break_vol_mult = 1.3
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR for volatility and TP/SL
        self.atr = self.I(lambda: pta.atr(high, low, close, length=14) or pd.Series(0.0, index=close.index))
        
        # Ichimoku lines - using rolling max/min for Donchian
        self.tenkan = self.I(lambda: (high.rolling(self.conversion_period).max() + low.rolling(self.conversion_period).min()) / 2)
        self.kijun = self.I(lambda: (high.rolling(self.base_period).max() + low.rolling(self.base_period).min()) / 2)
        self.senkou_a = self.I(lambda: (self.tenkan + self.kijun) / 2)
        self.senkou_b = self.I(lambda: (high.rolling(self.span_b_period).max() + low.rolling(self.span_b_period).min()) / 2)
        
        # Chikou span (current close, displayed displacement bars back)
        self.chikou = close
        
        # Volume SMA
        self.vol_sma = self.I(lambda: pta.sma(volume, length=20) or pd.Series(0.0, index=volume.index))
        
        # Displaced cloud levels for current bar
        self.kumo_a_displaced = self.I(lambda: self.senkou_a.shift(self.displacement))
        self.kumo_b_displaced = self.I(lambda: self.senkou_b.shift(self.displacement))
        
        # Cloud thickness for filter
        self.kumo_thickness = self.I(lambda: (self.kumo_a_displaced - self.kumo_b_displaced).abs())
        self.kumo_thickness_avg = self.I(lambda: self.kumo_thickness.rolling(50).mean())
        
        # Momentum pulse
        self.tk_spread = self.I(lambda: self.tenkan - self.kijun)
        self.tk_spread_norm = self.I(lambda: self.tk_spread / (self.atr + 0.0001))
        self.tk_acceleration = self.I(lambda: self.tk_spread_norm.diff(3))
        self.cloud_slope = self.I(lambda: (self.senkou_a.diff(5)) - (self.senkou_b.diff(5)))
        self.cloud_slope_norm = self.I(lambda: self.cloud_slope / (self.atr + 0.0001))
        
        self.momentum_pulse = self.I(lambda: (self.tk_spread_norm * 40.0 + self.tk_acceleration * 100.0 + self.cloud_slope_norm * 30.0).clip(-100, 100))
        self.momentum_smooth = self.I(lambda: pta.ema(self.momentum_pulse, length=5) or pd.Series(0.0, index=self.momentum_pulse.index))
        
        # State variables for trade management
        self.position_entry = None
        self.position_sl = None
        self.position_tp1 = None
        self.position_tp2 = None
        self.position_tp3 = None
        self.position_dir = 0  # 1 for long, -1 for short
        self.tp1_hit = False
        self.tp2_hit = False
        self.tp3_hit = False
        self.last_buy_bar = -100
        self.last_sell_bar = -100
        
    def calc_confluence_score(self, is_bull):
        """Calculate confluence score 0-100 for signal strength"""
        score = 0.0
        
        # Get current values
        close_price = self.data.Close[-1]
        tenkan_val = self.tenkan[-1]
        kijun_val = self.kijun[-1]
        kumo_a = self.kumo_a_displaced[-1]
        kumo_b = self.kumo_b_displaced[-1]
        kumo_top = max(kumo_a, kumo_b)
        kumo_bot = min(kumo_a, kumo_b)
        chikou_val = self.chikou[-1]
        
        # Factor 1: Price vs Cloud (20 pts)
        if is_bull:
            if close_price > kumo_top:
                score += 20.0
            elif kumo_bot < close_price < kumo_top:
                score += 8.0
        else:
            if close_price < kumo_bot:
                score += 20.0
            elif kumo_bot < close_price < kumo_top:
                score += 8.0
        
        # Factor 2: TK alignment (15 pts)
        if is_bull and tenkan_val > kijun_val:
            score += 15.0
        elif not is_bull and tenkan_val < kijun_val:
            score += 15.0
        
        # Factor 3: Chikou confirmation (15 pts)
        price_at_chikou = self.data.Close[-self.displacement] if len(self.data) > self.displacement else close_price
        if is_bull and chikou_val > price_at_chikou:
            score += 15.0
        elif not is_bull and chikou_val < price_at_chikou:
            score += 15.0
        
        # Factor 4: Cloud direction (10 pts)
        senkou_a_prev = self.senkou_a[-4] if len(self.senkou_a) >= 4 else self.senkou_a[-1]
        senkou_b_prev = self.senkou_b[-4] if len(self.senkou_b) >= 4 else self.senkou_b[-1]
        span_a_slope = self.senkou_a[-1] - senkou_a_prev
        span_b_slope = self.senkou_b[-1] - senkou_b_prev
        future_cloud_bull = span_a_slope > span_b_slope
        if (is_bull and future_cloud_bull) or (not is_bull and not future_cloud_bull):
            score += 10.0
        
        # Factor 5: Kumo thickness (8 pts)
        if self.kumo_thickness[-1] > self.kumo_thickness_avg[-1] * 0.3:
            score += 8.0
        else:
            score += 2.0
        
        # Factor 6: Volume (10 pts)
        if self.data.Volume[-1] > self.vol_sma[-1] * 1.2:
            score += 10.0
        
        # Factor 7: Momentum alignment (12 pts)
        if is_bull:
            if self.momentum_smooth[-1] > 20:
                score += 12.0
            elif self.momentum_smooth[-1] > 0:
                score += 6.0
        else:
            if self.momentum_smooth[-1] < -20:
                score += 12.0
            elif self.momentum_smooth[-1] < 0:
                score += 6.0
        
        # Factor 8: Momentum acceleration (10 pts)
        momentum_prev = self.momentum_smooth[-2] if len(self.momentum_smooth) >= 2 else self.momentum_smooth[-1]
        if is_bull and self.momentum_smooth[-1] > momentum_prev and self.momentum_smooth[-1] > 0:
            score += 10.0
        elif not is_bull and self.momentum_smooth[-1] < momentum_prev and self.momentum_smooth[-1] < 0:
            score += 10.0
        
        return min(score, 100.0)
    
    def calc_sl(self, is_long, entry_price):
        """Calculate stop loss level"""
        atr_val = max(self.atr[-1], 0.0001)
        atr_buf = atr_val * self.sl_atr_mult
        kumo_bot = min(self.kumo_a_displaced[-1], self.kumo_b_displaced[-1])
        kumo_top = max(self.kumo_a_displaced[-1], self.kumo_b_displaced[-1])
        
        if is_long:
            return kumo_bot - atr_buf
        else:
            return kumo_top + atr_buf
    
    def next(self):
        # Skip warmup period
        if len(self.data) < self.span_b_period + self.displacement + 20:
            return
        
        close_price = self.data.Close[-1]
        tenkan_val = self.tenkan[-1]
        kijun_val = self.kijun[-1]
        kumo_a = self.kumo_a_displaced[-1]
        kumo_b = self.kumo_b_displaced[-1]
        kumo_top = max(kumo_a, kumo_b)
        kumo_bot = min(kumo_a, kumo_b)
        volume_val = self.data.Volume[-1]
        vol_sma_val = self.vol_sma[-1]
        atr_val = max(self.atr[-1], 0.0001)
        
        # Check TK crosses
        tk_crossover_up = crossover(self.tenkan, self.kijun)
        tk_crossover_down = crossover(self.kijun, self.tenkan)
        
        # Get confluence scores
        bull_score = self.calc_confluence_score(True)
        bear_score = self.calc_confluence_score(False)
        
        # Check Kumo breakout
        prev_close = self.data.Close[-2] if len(self.data) >= 2 else close_price
        prev_kumo_top = max(self.kumo_a_displaced[-2], self.kumo_b_displaced[-2]) if len(self.kumo_a_displaced) >= 2 else kumo_top
        prev_kumo_bot = min(self.kumo_a_displaced[-2], self.kumo_b_displaced[-2]) if len(self.kumo_b_displaced) >= 2 else kumo_bot
        
        kumo_break_up = (close_price > kumo_top and prev_close <= prev_kumo_top and volume_val > vol_sma_val * self.break_vol_mult)
        kumo_break_down = (close_price < kumo_bot and prev_close >= prev_kumo_bot and volume_val > vol_sma_val * self.break_vol_mult)
        
        # Trade management - close on TP3 or SL
        if self.position_dir != 0:
            if self.position_dir == 1:  # Long
                if close_price >= self.position_tp3:
                    self.position_dir = 0
                    self.sell()
                    return
                elif close_price <= self.position_sl:
                    self.position_dir = 0
                    self.sell()
                    return
            else:  # Short
                if close_price <= self.position_tp3:
                    self.position_dir = 0
                    self.buy()
                    return
                elif close_price >= self.position_sl:
                    self.position_dir = 0
                    self.buy()
                    return
        
        # Entry signals
        # TK Cross Buy
        if tk_crossover_up and bull_score >= self.min_score and self.position_dir == 0:
            if not self.use_kumo_filter or (self.kumo_thickness[-1] > self.kumo_thickness_avg[-1] * 0.3):
                if not self.use_vol_filter or (volume_val > vol_sma_val * 1.2):
                    # Entry
                    self.buy()
                    self.position_entry = close_price
                    self.position_dir = 1
                    self.position_sl = self.calc_sl(True, close_price)
                    risk_dist = max(abs(close_price - self.position_sl), atr_val * 0.5)
                    self.position_tp1 = close_price + risk_dist * self.tp1_mult
                    self.position_tp2 = close_price + risk_dist * self.tp2_mult
                    self.position_tp3 = close_price + risk_dist * self.tp3_mult
                    self.tp1_hit = False
                    self.tp2_hit = False
                    self.tp3_hit = False
                    self.last_buy_bar = len(self.data)
        
        # TK Cross Sell
        elif tk_crossover_down and bear_score >= self.min_score and self.position_dir == 0:
            if not self.use_kumo_filter or (self.kumo_thickness[-1] > self.kumo_thickness_avg[-1] * 0.3):
                if not self.use_vol_filter or (volume_val > vol_sma_val * 1.2):
                    # Entry
                    self.sell()
                    self.position_entry = close_price
                    self.position_dir = -1
                    self.position_sl = self.calc_sl(False, close_price)
                    risk_dist = max(abs(self.position_sl - close_price), atr_val * 0.5)
                    self.position_tp1 = close_price - risk_dist * self.tp1_mult
                    self.position_tp2 = close_price - risk_dist * self.tp2_mult
                    self.position_tp3 = close_price - risk_dist * self.tp3_mult
                    self.tp1_hit = False
                    self.tp2_hit = False
                    self.tp3_hit = False
                    self.last_sell_bar = len(self.data)
        
        # Kumo breakout signals
        elif self.use_breakout and kumo_break_up and self.position_dir == 0:
            self.buy()
            self.position_entry = close_price
            self.position_dir = 1
            self.position_sl = self.calc_sl(True, close_price)
            risk_dist = max(abs(close_price - self.position_sl), atr_val * 0.5)
            self.position_tp1 = close_price + risk_dist * self.tp1_mult
            self.position_tp2 = close_price + risk_dist * self.tp2_mult
            self.position_tp3 = close_price + risk_dist * self.tp3_mult
            self.tp1_hit = False
            self.tp2_hit = False
            self.tp3_hit = False
        
        elif self.use_breakout and kumo_break_down and self.position_dir == 0:
            self.sell()
            self.position_entry = close_price
            self.position_dir = -1
            self.position_sl = self.calc_sl