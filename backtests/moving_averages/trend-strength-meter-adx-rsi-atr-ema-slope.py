import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Weights
    wADX = 30
    wRSI = 30
    wATR = 20
    wSLOPE = 20
    
    # Basic settings
    lenADX = 14
    adxSm = 14
    lenRSI = 14
    lenATR = 14
    emaLen = 200
    smooth = 5
    
    # References/thresholds
    adxCap = 50
    atrRefLen = 50
    atrScale = 0.25
    bullTh = 60
    bearTh = 60

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA Base and Slope
        emaBase = self.I(pta.ema, close, length=self.emaLen)
        emaSlope = self.I(lambda: emaBase - emaBase.shift(1))
        
        # ATR and ATR MA
        atr = self.I(pta.atr, high, low, close, length=self.lenATR)
        atrMA = self.I(pta.sma, atr, length=self.atrRefLen)
        
        # RSI
        rsiV = self.I(pta.rsi, close, length=self.lenRSI)
        
        # ADX (via DMI)
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.lenADX))
        
        # Helper function for clamp
        def clamp(x, lo, hi):
            return np.where(x < lo, lo, np.where(x > hi, hi, x))
        
        # Helper function for normalization
        def norm01(x, lo, hi):
            return np.where(hi == lo, 0.0, clamp((x - lo) / (hi - lo), 0.0, 1.0))
        
        # Helper function for percentage conversion
        def toPct(x):
            return clamp(x * 100.0, 0.0, 100.0)
        
        # ADX Normalization
        def calc_adx_norm():
            adx_data = adx_result.iloc[:, 2] if adx_result is not None else pd.Series(25, index=close.index)
            return toPct(norm01(adx_data, 0, self.adxCap))
        
        self.adxNorm = self.I(calc_adx_norm)
        
        # RSI directional contribution
        self.rsiBull = self.I(lambda: toPct(norm01(rsiV, 50, 100)))
        self.rsiBear = self.I(lambda: toPct(norm01(50, rsiV, 0)))
        
        # ATR ratio normalization
        def calc_atr_norm():
            atr_vals = atr if atr is not None else pd.Series(1, index=close.index)
            atr_ma_vals = atrMA if atrMA is not None else pd.Series(1, index=close.index)
            atrRatio = np.where(atr_ma_vals == 0, 0.0, atr_vals / atr_ma_vals)
            atrNormRaw = (atrRatio - 1.0) / self.atrScale
            return toPct(np.where(atrNormRaw < 0, 0, atrNormRaw))
        
        self.atrNorm = self.I(calc_atr_norm)
        
        # EMA Slope normalization
        def calc_slope_norm():
            atr_vals = atr if atr is not None else pd.Series(1, index=close.index)
            ema_slope_vals = emaSlope if emaSlope is not None else pd.Series(0, index=close.index)
            slope_ratio = np.where(atr_vals == 0, 0, ema_slope_vals / atr_vals)
            return toPct(norm01(slope_ratio, -1.0, 1.0))
        
        self.slopeNorm = self.I(calc_slope_norm)
        
        # Direction filter
        def calc_bull_dir():
            ema_slope_vals = emaSlope if emaSlope is not None else pd.Series(0, index=close.index)
            ema_base_vals = emaBase if emaBase is not None else pd.Series(close.mean(), index=close.index)
            return (ema_slope_vals > 0) & (close > ema_base_vals)
        
        def calc_bear_dir():
            ema_slope_vals = emaSlope if emaSlope is not None else pd.Series(0, index=close.index)
            ema_base_vals = emaBase if emaBase is not None else pd.Series(close.mean(), index=close.index)
            return (ema_slope_vals < 0) & (close < ema_base_vals)
        
        self.bullDir = self.I(calc_bull_dir)
        self.bearDir = self.I(calc_bear_dir)
        
        # Scores calculation
        wSum = max(self.wADX + self.wRSI + self.wATR + self.wSLOPE, 1)
        
        def calc_bull_score():
            adx_bull = self.adxNorm if self.adxNorm is not None else pd.Series(25, index=close.index)
            rsi_bull = self.rsiBull if self.rsiBull is not None else pd.Series(50, index=close.index)
            atr_bull = self.atrNorm if self.atrNorm is not None else pd.Series(50, index=close.index)
            slope_bull = self.slopeNorm if self.slopeNorm is not None else pd.Series(50, index=close.index)
            
            bullScoreRaw = (
                self.wADX * adx_bull +
                self.wRSI * rsi_bull +
                self.wATR * atr_bull +
                self.wSLOPE * slope_bull
            ) / wSum
            return bullScoreRaw
        
        def calc_bear_score():
            adx_bear = self.adxNorm if self.adxNorm is not None else pd.Series(25, index=close.index)
            rsi_bear = self.rsiBear if self.rsiBear is not None else pd.Series(50, index=close.index)
            atr_bear = self.atrNorm if self.atrNorm is not None else pd.Series(50, index=close.index)
            slope_bear = self.slopeNorm if self.slopeNorm is not None else pd.Series(50, index=close.index)
            slopeBear = toPct(100 - slope_bear)
            
            bearScoreRaw = (
                self.wADX * adx_bear +
                self.wRSI * rsi_bear +
                self.wATR * atr_bear +
                self.wSLOPE * slopeBear
            ) / wSum
            return bearScoreRaw
        
        bullScoreRaw = self.I(calc_bull_score)
        bearScoreRaw = self.I(calc_bear_score)
        
        self.bullScore = self.I(pta.sma, bullScoreRaw, length=self.smooth)
        self.bearScore = self.I(pta.sma, bearScoreRaw, length=self.smooth)
        
        self.netSigned = self.I(lambda: self.bullScore - self.bearScore)
        self.netAbs = self.I(lambda: np.abs(self.netSigned))

    def next(self):
        if len(self.data) < self.emaLen + 5:
            return
        
        bullScore_val = self.bullScore[-1]
        bearScore_val = self.bearScore[-1]
        bullDir_val = self.bullDir[-1]
        bearDir_val = self.bearDir[-1]
        
        # Buy signal: bullScore crosses above bullTh and bullish direction
        if crossover(self.bullScore, self.bullTh) and bullDir_val:
            if not self.position:
                self.buy()
        
        # Sell signal: bearScore crosses above bearTh and bearish direction
        if crossover(self.bearScore, self.bearTh) and bearDir_val:
            if self.position:
                self.position.close()
        
        # Exit long if bearish direction becomes strong
        if self.position and bearScore_val > bullScore_val:
            self.position.close()


