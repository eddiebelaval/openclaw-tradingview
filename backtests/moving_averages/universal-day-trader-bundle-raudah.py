class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate EMA indicators
        self.ema1 = self.I(pta.ema, close, length=1)
        self.ema9 = self.I(pta.ema, close, length=9)
        self.ema20 = self.I(pta.ema, close, length=20)
        
        # Calculate VWAP
        self.vwap = self.I(pta.vwap, close, volume)

    def next(self):
        # Check if we have valid indicator values
        if len(self.data) < 20:
            return
        
        # Get current values
        ema9_current = self.ema9[-1]
        ema20_current = self.ema20[-1]
        
        # Skip if values are NaN
        if pd.isna(ema9_current) or pd.isna(ema20_current):
            return
        
        # Trading logic based on EMA 9 crossing EMA 20
        if crossover(self.ema9, self.ema20):
            # EMA 9 crossed above EMA 20 - bullish signal
            if not self.position:
                self.buy()
        elif crossover(self.ema20, self.ema9):
            # EMA 9 crossed below EMA 20 - bearish signal
            if self.position:
                self.position.close()


