import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # MACD 6-12-9
        macd_result = self.I(lambda x: pta.macd(x, fast=6, slow=12, signal=9), close)
        self.macd_line = self.I(lambda x: pta.macd(x, fast=6, slow=12, signal=9), close)
        
        # RSI calculations
        self.rsi13 = self.I(pta.rsi, close, length=13)
        self.rsi5 = self.I(pta.rsi, close, length=5)
        
        # EMA calculations
        self.ema1 = self.I(pta.ema, close, length=1)
        self.ema7 = self.I(pta.ema, close, length=7)
        self.ema10 = self.I(pta.ema, close, length=10)
        self.ema14 = self.I(pta.ema, close, length=14)
        
        # Extract MACD components
        self.macd_macdline = self.I(
            lambda x: pta.macd(x, fast=6, slow=12, signal=9).iloc[:, 0] if pta.macd(x, fast=6, slow=12, signal=9) is not None else pd.Series(0, index=x.index),
            close
        )
        self.macd_signal = self.I(
            lambda x: pta.macd(x, fast=6, slow=12, signal=9).iloc[:, 1] if pta.macd(x, fast=6, slow=12, signal=9) is not None else pd.Series(0, index=x.index),
            close
        )

    def next(self):
        # Check if we have sufficient data
        if len(self.data) < 15:
            return
        
        # Signal conditions
        macd_bull = self.macd_macdline[-1] > self.macd_signal[-1] if not np.isnan(self.macd_macdline[-1]) and not np.isnan(self.macd_signal[-1]) else False
        rsi13_bull = self.rsi13[-1] > 50 if not np.isnan(self.rsi13[-1]) else False
        rsi5_bull = self.rsi5[-1] > 50 if not np.isnan(self.rsi5[-1]) else False
        fastMA_bull = self.ema1[-1] > self.ema7[-1] if not np.isnan(self.ema1[-1]) and not np.isnan(self.ema7[-1]) else False
        slowMA_bull = self.ema10[-1] > self.ema14[-1] if not np.isnan(self.ema10[-1]) and not np.isnan(self.ema14[-1]) else False
        
        # All 5 agree conditions
        all_green = macd_bull and rsi13_bull and rsi5_bull and fastMA_bull and slowMA_bull
        all_red = not macd_bull and not rsi13_bull and not rsi5_bull and not fastMA_bull and not slowMA_bull
        
        # Entry logic: buy when all 5 meters turn green
        if all_green and not self.position:
            self.buy()
        
        # Exit logic: sell when all 5 meters turn red
        elif all_red and self.position:
            self.sell()


