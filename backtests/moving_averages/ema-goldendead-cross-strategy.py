import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 50
    slowLen = 200
    tradeDir = "Both"

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.fastEMA = self.I(pta.ema, close, length=self.fastLen)
        self.slowEMA = self.I(pta.ema, close, length=self.slowLen)

    def next(self):
        if len(self.data) < 2:
            return
        
        goldenCross = crossover(self.fastEMA, self.slowEMA)
        deadCross = crossover(self.slowEMA, self.fastEMA)
        
        if goldenCross:
            if self.tradeDir == "Long Only" or self.tradeDir == "Both":
                if self.position.is_short:
                    self.position.close()
                self.buy()
        
        if deadCross:
            if self.tradeDir == "Short Only" or self.tradeDir == "Both":
                if self.position.is_long:
                    self.position.close()
                self.sell()


if __name__ == "__main__":
    from backtesting.test import GOOG
    
    bt = Backtest(GOOG, TvStrategy, cash=10000, commission=.002)
