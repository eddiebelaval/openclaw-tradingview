import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Input parameters from Pine Script
    len_fast = 14
    len_med = 34
    len_slow = 89
    er_len = 34
    fast_alpha_len = 2
    slow_alpha_len = 30
    use_robust_clip = True
    clip_len = 34
    clip_k = 3.0
    use_zero_lag = True
    zl_strength = 0.6
    rel_slope_len = 14
    rel_min = 0.55

    def init(self):
        self.ma_fast = self.I(self._calc_ma_fast)
        self.ma_med = self.I(self._calc_ma_med)
        self.ma_slow = self.I(self._calc_ma_slow)
        self.rel = self.I(self._calc_reliability)
        self.align_bull = self.I(self._calc_align_bull)

    def _sma(self, series, length):
        """Simple Moving Average"""
        return series.rolling(window=length).mean()

    def _robust_clip(self, series, clip_len, clip_k):
        """Robust clipping using rolling baseline and MAD-like deviation"""
        base = self._sma(series, clip_len)
        dev = np.abs(series - base)
        mad = self._sma(dev, clip_len)
        scale = np.maximum(mad * 1.4826, 1e-10)
        lo = base - clip_k * scale
        hi = base + clip_k * scale
        return np.minimum(np.maximum(series, lo), hi)

    def _efficiency_ratio(self, series, n):
        """Efficiency ratio: directional change / path length"""
        change = np.abs(series.iloc[-1] - series.iloc[max(0, len(series) - n - 1)])
        vol = 0.0
        for i in range(min(n, len(series) - 1)):
            vol += np.abs(series.iloc[-(i + 1)] - series.iloc[-(i + 2)])
        vol = max(vol, 1e-10)
        return change / vol

    def _alpha_from_er(self, er, fast_n, slow_n):
        """Convert efficiency ratio to adaptive alpha"""
        fast_sc = 2.0 / (fast_n + 1.0)
        slow_sc = 2.0 / (slow_n + 1.0)
        sc = slow_sc + (fast_sc - slow_sc) * er
        return sc * sc

    def _adaptive_ma(self, series, base_len, er_n, fast_n, slow_n):
        """Adaptive moving average with efficiency ratio"""
        if len(series) < er_n + 1:
            return pd.Series(np.nan, index=series.index)

        result = []
        ma = series.iloc[0]
        shaped = ma

        for i in range(len(series)):
            if i == 0:
                result.append(ma)
                continue

            current_val = series.iloc[i]
            lookback_series = series.iloc[max(0, i - er_n):i + 1]

            er_val = self._efficiency_ratio(lookback_series, er_n)
            er_val = np.clip(er_val, 0, 1)
            alpha = self._alpha_from_er(er_val, fast_n, slow_n)

            ma = ma + alpha * (current_val - ma)
            a2 = 2.0 / (base_len + 1.0)
            shaped = shaped + a2 * (ma - shaped)

            result.append(shaped)

        return pd.Series(result, index=series.index)

    def _zero_lag(self, ma_line, strength):
        """Controlled phase compensation"""
        diff = ma_line.diff()
        return ma_line + strength * diff

    def _calc_ma_fast(self):
        """Calculate fast adaptive MA"""
        close = pd.Series(self.data.Close)
        x_in = self._robust_clip(close, self.clip_len, self.clip_k) if self.use_robust_clip else close
        ma_raw = self._adaptive_ma(x_in, self.len_fast, self.er_len, self.fast_alpha_len, self.slow_alpha_len)
        ma = self._zero_lag(ma_raw, self.zl_strength) if self.use_zero_lag else ma_raw
        return ma

    def _calc_ma_med(self):
        """Calculate medium adaptive MA"""
        close = pd.Series(self.data.Close)
        x_in = self._robust_clip(close, self.clip_len, self.clip_k) if self.use_robust_clip else close
        ma_raw = self._adaptive_ma(x_in, self.len_med, self.er_len, self.fast_alpha_len, self.slow_alpha_len)
        ma = self._zero_lag(ma_raw, self.zl_strength * 0.7) if self.use_zero_lag else ma_raw
        return ma

    def _calc_ma_slow(self):
        """Calculate slow adaptive MA"""
        close = pd.Series(self.data.Close)
        x_in = self._robust_clip(close, self.clip_len, self.clip_k) if self.use_robust_clip else close
        ma_raw = self._adaptive_ma(x_in, self.len_slow, self.er_len, self.fast_alpha_len, self.slow_alpha_len)
        ma = self._zero_lag(ma_raw, self.zl_strength * 0.4) if self.use_zero_lag else ma_raw
        return ma

    def _calc_reliability(self):
        """Calculate reliability score"""
        close = pd.Series(self.data.Close)
        x_in = self._robust_clip(close, self.clip_len, self.clip_k) if self.use_robust_clip else close

        ma_m = self._adaptive_ma(x_in, self.len_med, self.er_len, self.fast_alpha_len, self.slow_alpha_len)

        slope_m = ma_m.diff()
        slope_abs_base = self._sma(np.abs(slope_m), self.rel_slope_len)
        slope_strength = np.where(slope_abs_base > 0, np.minimum(1.0, np.abs(slope_m) / (slope_abs_base * 2.0)), 0.0)

        ma_f = self._adaptive_ma(x_in, self.len_fast, self.er_len, self.fast_alpha_len, self.slow_alpha_len)
        ma_s = self._adaptive_ma(x_in, self.len_slow, self.er_len, self.fast_alpha_len, self.slow_alpha_len)

        align_bull = (ma_f >= ma_m) & (ma_m >= ma_s)
        align_bear = (ma_f <= ma_m) & (ma_m <= ma_s)
        align_score = np.where((align_bull | align_bear), 1.0, 0.0)

        er_vals = []
        for i in range(len(x_in)):
            lookback = x_in.iloc[max(0, i - self.er_len):i + 1]
            er_vals.append(self._efficiency_ratio(lookback, self.er_len))
        er_m = pd.Series(er_vals, index=x_in.index)
        er_m = np.clip(er_m, 0, 1)

        rel = 0.55 * er_m + 0.25 * align_score + 0.20 * slope_strength
        rel = np.clip(rel, 0.0, 1.0)

        return pd.Series(rel, index=close.index)

    def _calc_align_bull(self):
        """Calculate bullish alignment"""
        close = pd.Series(self.data.Close)
        x_in = self._robust_clip(close, self.clip_len, self.clip_k) if self.use_robust_clip else close

        ma_f = self._adaptive_ma(x_in, self.len_fast, self.er_len, self.fast_alpha_len, self.slow_alpha_len)
        ma_m = self._adaptive_ma(x_in, self.len_med, self.er_len, self.fast_alpha_len, self.slow_alpha_len)
        ma_s = self._adaptive_ma(x_in, self.len_slow, self.er_len, self.fast_alpha_len, self.slow_alpha_len)

        align_bull = (ma_f >= ma_m) & (ma_m >= ma_s)
        return align_bull.astype(float)

    def next(self):
        # Buy when bullish alignment forms and price is above medium MA
        if len(self.data) < 2:
            return

        current_align = self.align_bull[-1]
        prev_align = self.align_bull[-2]

        # Entry: alignment forms AND close above medium MA AND reliability good
        if (current_align > prev_align and 
            self.data.Close[-1] >= self.ma_med[-1] and 
            self.rel[-1] >= self.rel_min):
            if not self.position:
                self.buy()

        # Exit: alignment breaks OR close below medium MA AND reliability drops
        if (self.position and 
            (current_align < 0.5 or 
             self.data.Close[-1] < self.ma_med[-1] or 
             self.rel[-1] < self.rel_min * 0.8)):
            self.position.close()