import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI
    rsiLength = 14
    # MACD
    fastMA = 12
    slowMA = 26
    signalLength = 9
    # Supertrend
    stPeriods = 10
    stMultiplier = 3.0
    # T3
    t3Length = 4
    t3VolumeFactor = 0.7
    # EMA Ribbon
    ema1Length = 5
    ema2Length = 8
    ema3Length = 13

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hl2 = (high + low) / 2

        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        self.rsiBull = self.I(lambda: (self.rsi > 50).astype(float))

        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=self.fastMA, slow=self.slowMA, signal=self.signalLength))
        self.macdLine = self.I(lambda: macd_result.iloc[:, 0] if macd_result is not None else pd.Series(0, index=close.index))
        self.macdBull = self.I(lambda: (self.macdLine > 0).astype(float))

        # Supertrend
        atr = self.I(pta.atr, high, low, close, length=self.stPeriods)
        self.upST = self.I(lambda: hl2 - self.stMultiplier * atr)
        self.dnST = self.I(lambda: hl2 + self.stMultiplier * atr)

        # T3 (Tilson T3)
        self.t3 = self.I(self._calc_t3, close, self.t3Length, self.t3VolumeFactor)
        self.t3SlopeUp = self.I(lambda: self._get_t3_slope_up())

        # EMA Ribbon
        self.ema1 = self.I(pta.ema, close, length=self.ema1Length)
        self.ema2 = self.I(pta.ema, close, length=self.ema2Length)
        self.ema3 = self.I(pta.ema, close, length=self.ema3Length)
        self.emaBull = self.I(lambda: self._get_ema_bull())
        self.emaBear = self.I(lambda: self._get_ema_bear())

        # Supertrend direction tracking
        self.supertrend_direction = None
        self.supertrend_value = None

    def _calc_t3(self, close, t3_len, v_factor):
        e1 = pta.ema(close, length=t3_len)
        e2 = pta.ema(e1, length=t3_len)
        e3 = pta.ema(e2, length=t3_len)
        e4 = pta.ema(e3, length=t3_len)
        e5 = pta.ema(e4, length=t3_len)
        e6 = pta.ema(e5, length=t3_len)

        c1 = -v_factor * v_factor * v_factor
        c2 = 3 * v_factor * v_factor + 3 * v_factor * v_factor * v_factor
        c3 = -6 * v_factor * v_factor - 3 * v_factor - 3 * v_factor * v_factor * v_factor
        c4 = 1 + 3 * v_factor + v_factor * v_factor * v_factor + 3 * v_factor * v_factor

        result = c1 * e6 + c2 * e5 + c3 * e4 + c4 * e3
        return result if result is not None else pd.Series(0, index=close.index)

    def _get_t3_slope_up(self):
        if len(self.t3) < 2:
            return False
        return float(self.t3[-1] > self.t3[-2])

    def _get_ema_bull(self):
        if len(self.ema1) < 1 or len(self.ema2) < 1 or len(self.ema3) < 1:
            return False
        return float(self.ema1[-1] > self.ema2[-1] and self.ema2[-1] > self.ema3[-1])

    def _get_ema_bear(self):
        if len(self.ema1) < 1 or len(self.ema2) < 1 or len(self.ema3) < 1:
            return False
        return float(self.ema1[-1] < self.ema2[-1] and self.ema2[-1] < self.ema3[-1])

    def _update_supertrend(self):
        if len(self.data) < 1:
            self.supertrend_direction = 1
            self.supertrend_value = self.data.Close[-1]
            return

        if self.supertrend_direction is None:
            self.supertrend_direction = 1
            self.supertrend_value = self.data.Close[-1]
            return

        current_close = self.data.Close[-1]
        up_val = self.upST[-1] if len(self.upST) > 0 else self.data.Close[-1]
        dn_val = self.dnST[-1] if len(self.dnST) > 0 else self.data.Close[-1]

        prev_supertrend = self.supertrend_value

        if self.supertrend_direction == -1 and current_close > dn_val:
            self.supertrend_direction = 1
        elif self.supertrend_direction == 1 and current_close < up_val:
            self.supertrend_direction = -1

        if self.supertrend_direction == 1:
            self.supertrend_value = max(up_val, prev_supertrend if prev_supertrend is not None else up_val)
        else:
            self.supertrend_value = min(dn_val, prev_supertrend if prev_supertrend is not None else dn_val)

    def next(self):
        self._update_supertrend()

        if len(self.rsi) < 1 or len(self.macdLine) < 1 or len(self.t3) < 1:
            return

        rsi_bull = float(self.rsiBull[-1]) > 0.5
        macd_bull = float(self.macdBull[-1]) > 0.5
        super_bull = self.supertrend_direction == 1
        t3_slope_up = self._get_t3_slope_up()
        ema_bull = self._get_ema_bull()
        ema_bear = self._get_ema_bear()

        all_bull = rsi_bull and macd_bull and super_bull and t3_slope_up and ema_bull
        all_bear = self.supertrend_direction == -1 and not t3_slope_up and ema_bear

        if all_bull and not self.position:
            self.buy()
        elif all_bear and self.position:
            self.sell()


