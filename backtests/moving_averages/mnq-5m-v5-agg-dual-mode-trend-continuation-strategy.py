import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Session
    use_rth = True
    rth_start = 9.5
    rth_end = 15.917
    flat_at_end = True
    
    # Trend + Filters
    fast_len = 21
    slow_len = 50
    slope_len = 5
    min_slope_pt = 2.0
    atr_len = 14
    atr_rise_lb = 6
    atr_rise_min = 0.0
    relax_atr_for_shorts = True
    
    # Breakdown shorts
    use_breakdown_short = True
    break_lookback = 10
    require_bear_body = True
    use_break_only_if_no_pb = False
    
    # Trade control
    cooldown_bars = 3
    
    # Exit modes
    mode = "Scalp"
    stop_atr = 2.0
    scalp_tp_atr = 3.0
    scalp_trail_atr = 1.6
    runner_tp_atr = 5.0
    runner_trail_atr = 2.4
    runner_trail_after = 1.6

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.fast_ema = self.I(pta.ema, close, length=self.fast_len)
        self.slow_ema = self.I(pta.ema, close, length=self.slow_len)
        
        # Calculate ATR
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Calculate slopes
        self.fast_slope = self.I(lambda: self.fast_ema - self.fast_ema.shift(self.slope_len))
        
        # Calculate ATR delta
        self.atr_delta = self.I(lambda: self.atr_val - self.atr_val.shift(self.atr_rise_lb))
        
        # Lowest low for breakdown
        self.lowest_low = self.I(lambda: low.shift(1).rolling(self.break_lookback).min())
        
        # Track state
        self.last_exit_bar = -1000
        self.pend_entry = None
        self.pend_atr = None
        self.pend_mode = None
        self.pend_dir = 0
        self.pend_short_type = "-"
        
        self.lock_entry = None
        self.lock_atr = None
        self.lock_sl = None
        self.lock_tp = None
        self.last_short_type = "-"
        
        self.hh = None
        self.ll = None
        self.vis_trail = None
        self.trade_id = 0

    def next(self):
        # Get current values
        if len(self.data) < self.slope_len + 1:
            return
        
        cur_close = self.data.Close[-1]
        cur_high = self.data.High[-1]
        cur_low = self.data.Low[-1]
        cur_open = self.data.Open[-1]
        bar_idx = len(self.data) - 1
        
        fast_ema_val = self.fast_ema[-1]
        slow_ema_val = self.slow_ema[-1]
        atr_val = self.atr_val[-1]
        fast_slope_val = self.fast_slope[-1]
        atr_delta_val = self.atr_delta[-1]
        
        # Trend determination
        trend_up = fast_ema_val > slow_ema_val
        trend_down = fast_ema_val < slow_ema_val
        
        # Slope checks
        slope_ok_long = fast_slope_val >= self.min_slope_pt
        slope_ok_short = fast_slope_val <= -self.min_slope_pt
        
        # ATR rising check
        atr_rising_ok = atr_delta_val > self.atr_rise_min
        
        # Filters
        filters_ok_long = slope_ok_long and atr_rising_ok
        filters_ok_short = slope_ok_short and (self.relax_atr_for_shorts or atr_rising_ok)
        
        # Entry logic (Pullback)
        raw_long = trend_up and (cur_low <= fast_ema_val) and (cur_close > fast_ema_val)
        raw_short = trend_down and (cur_high >= fast_ema_val) and (cur_close < fast_ema_val)
        
        long_pullback_signal = raw_long and filters_ok_long
        short_pullback_signal = raw_short and filters_ok_short
        
        # Breakdown shorts
        bear_body_ok = not self.require_bear_body or (cur_close < cur_open)
        lowest_val = self.lowest_low[-1] if not np.isnan(self.lowest_low[-1]) else cur_low
        breakdown_short = (self.use_breakdown_short and trend_down and slope_ok_short and 
                          bear_body_ok and cur_close < lowest_val)
        
        short_signal_base = (short_pullback_signal or 
                            (breakdown_short and (not self.use_break_only_if_no_pb or not short_pullback_signal)))
        long_signal_base = long_pullback_signal
        
        # Cooldown check
        cooldown_ok = (bar_idx - self.last_exit_bar) > self.cooldown_bars
        
        long_signal = cooldown_ok and long_signal_base
        short_signal = cooldown_ok and short_signal_base
        
        # Entry logic
        if long_signal and not self.position:
            self.pend_entry = cur_close
            self.pend_atr = atr_val
            self.pend_mode = self.mode
            self.pend_dir = 1
            self.pend_short_type = "-"
            self.buy()
        
        if short_signal and not self.position:
            self.pend_entry = cur_close
            self.pend_atr = atr_val
            self.pend_mode = self.mode
            self.pend_dir = -1
            self.pend_short_type = "BRK" if breakdown_short else ("PB" if short_pullback_signal else "S")
            self.sell()
        
        # Exit logic
        if self.position:
            is_long = self.position.size > 0
            
            # Determine entry point and ATR to use
            use_pending = (self.pend_entry is not None and self.pend_atr is not None and 
                          self.pend_dir == (1 if is_long else -1))
            
            entry = self.pend_entry if use_pending else self.position.open_price
            atr_use = self.pend_atr if use_pending else atr_val
            
            # Set lock values on entry
            if self.lock_entry is None:
                self.lock_entry = entry
                self.lock_atr = atr_use
                tp_mult_lock = self.scalp_tp_atr if self.mode == "Scalp" else self.runner_tp_atr
                self.lock_sl = entry - self.stop_atr * self.lock_atr if is_long else entry + self.stop_atr * self.lock_atr
                self.lock_tp = entry + tp_mult_lock * self.lock_atr if is_long else entry - tp_mult_lock * self.lock_atr
                self.last_short_type = self.pend_short_type if use_pending else "-"
                self.trade_id += 1
                
                # Reset pending
                self.pend_entry = None
                self.pend_atr = None
                self.pend_mode = None
                self.pend_dir = 0
                self.pend_short_type = ""
            
            # Trail approximation
            if self.hh is None:
                self.hh = cur_high
                self.ll = cur_low
            else:
                self.hh = max(self.hh, cur_high)
                self.ll = min(self.ll, cur_low)
            
            dist = self.scalp_trail_atr * atr_val if self.mode == "Scalp" else self.runner_trail_atr * atr_val
            
            trail_active = (self.mode == "Scalp" or 
                           (is_long and (self.hh - entry) >= self.runner_trail_after * atr_val) or
                           (not is_long and (entry - self.ll) >= self.runner_trail_after * atr_val))
            
            if trail_active:
                self.vis_trail = self.hh - dist if is_long else self.ll + dist
            else:
                self.vis_trail = None
            
            # Exit conditions
            if is_long:
                if cur_low <= self.lock_sl or cur_high >= self.lock_tp:
                    self.position.close()
                    self.last_exit_bar = bar_idx
                    self.lock_entry = None
                    self.lock_atr = None
                    self.lock_sl = None
                    self.lock_tp = None
                    self.hh = None
                    self.ll = None
                    self.vis_trail = None
            else:
                if cur_high >= self.lock_sl or cur_low <= self.lock_tp:
                    self.position.close()
                    self.last_exit_bar = bar_idx
                    self.lock_entry = None
                    self.lock_atr = None
                    self.lock_sl = None
                    self.lock_tp = None
                    self.hh = None
                    self.ll = None
                    self.vis_trail = None


