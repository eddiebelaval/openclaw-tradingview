import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Strategy Mode
    mode = "Normal (Balanced)"
    
    # Trend Filter
    use_trend = True
    ema_fast_l = 50
    ema_slow_l = 200
    
    # Visuals
    show_only_confirmed = True
    show_ama = False
    
    # Advanced
    use_ha = False
    dev_len = 20
    fast_per = 2
    slow_per = 30
    
    # Manual Override
    use_manual = False
    bs_in = 3
    bf_in = 2.0
    ss_in = 3
    sf_in = 1.3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Determine mode-based parameters
        is_aggressive = self.mode == "Aggressive (Scalp)"
        is_swing = self.mode == "Swing (Safe)"
        
        if is_aggressive:
            bs_p, bf_p, ss_p, sf_p = 2, 1.2, 2, 0.9
        elif is_swing:
            bs_p, bf_p, ss_p, sf_p = 5, 3.0, 5, 2.0
        else:
            bs_p, bf_p, ss_p, sf_p = 3, 2.0, 3, 1.3
        
        self.bs = self.bs_in if self.use_manual else bs_p
        self.bf = self.bf_in if self.use_manual else bf_p
        self.ss = self.ss_in if self.use_manual else ss_p
        self.sf = self.sf_in if self.use_manual else sf_p
        
        # Core mathematics
        self.fast = 2.0 / (self.fast_per + 1.0)
        self.slow = 2.0 / (self.slow_per + 1.0)
        
        # Buy calculation
        self.dirb = self.I(lambda: np.abs(close - close.shift(self.bs).fillna(close)))
        self.vstep_b = self.I(lambda: np.abs(close - close.shift(1)))
        self.volb = self.I(lambda: pta.sma(self.vstep_b, length=self.bs).fillna(0) * self.bs)
        self.ERb = self.I(lambda: np.where(self.volb != 0, self.dirb / self.volb, 0))
        self.scb = self.I(lambda: np.power(self.ERb * (self.fast - self.slow) + self.slow, 2.0))
        
        # Sell calculation
        self.dirs = self.I(lambda: np.abs(close - close.shift(self.ss).fillna(close)))
        self.vstep_s = self.I(lambda: np.abs(close - close.shift(1)))
        self.vols = self.I(lambda: pta.sma(self.vstep_s, length=self.ss).fillna(0) * self.ss)
        self.ERs = self.I(lambda: np.where(self.vols != 0, self.dirs / self.vols, 0))
        self.scs = self.I(lambda: np.power(self.ERs * (self.fast - self.slow) + self.slow, 2.0))
        
        # AMA lines (cumulative)
        self.xb = self.I(lambda: self._calc_ama(close, self.scb))
        self.xs = self.I(lambda: self._calc_ama(close, self.scs))
        
        # Delta
        self.dxb = self.I(lambda: self.xb - self.xb.shift(1).fillna(self.xb))
        self.dxs = self.I(lambda: self.xs - self.xs.shift(1).fillna(self.xs))
        
        # Thresholds
        self.flb = self.I(lambda: self.bf * pta.stdev(self.dxb, length=self.dev_len).fillna(0))
        self.fls = self.I(lambda: self.sf * pta.stdev(self.dxs, length=self.dev_len).fillna(0))
        
        # 3-bar momentum delta
        self.j = self.I(lambda: self.xb - self.xb.shift(3).fillna(self.xb))
        self.k = self.I(lambda: self.xs.shift(3).fillna(self.xs) - self.xs)
        
        # Trend filters
        self.ema_f = self.I(pta.ema, close, length=self.ema_fast_l)
        self.ema_s = self.I(pta.ema, close, length=self.ema_slow_l)
        
        # State tracking
        self.last_sig = 0  # 1=BUY, -1=SELL, 0=none

    def _calc_ama(self, close, sc):
        """Calculate AMA (Adaptive Moving Average) line"""
        ama = pd.Series(index=close.index, dtype=float)
        ama.iloc[0] = close.iloc[0]
        
        for i in range(1, len(close)):
            if pd.isna(sc.iloc[i]):
                ama.iloc[i] = ama.iloc[i-1]
            else:
                ama.iloc[i] = ama.iloc[i-1] + sc.iloc[i] * (close.iloc[i] - ama.iloc[i-1])
        
        return ama

    def next(self):
        # Get current values
        j_curr = self.j[-1] if len(self.j) > 0 else 0
        flb_curr = self.flb[-1] if len(self.flb) > 0 else 0
        k_curr = self.k[-1] if len(self.k) > 0 else 0
        fls_curr = self.fls[-1] if len(self.fls) > 0 else 0
        
        j_prev = self.j[-2] if len(self.j) > 1 else 0
        k_prev = self.k[-2] if len(self.k) > 1 else 0
        flb_prev = self.flb[-2] if len(self.flb) > 1 else 0
        fls_prev = self.fls[-2] if len(self.fls) > 1 else 0
        
        close_curr = self.data.Close[-1]
        ema_f_curr = self.ema_f[-1] if len(self.ema_f) > 0 else close_curr
        ema_s_curr = self.ema_s[-1] if len(self.ema_s) > 0 else close_curr
        
        # Trend definitions
        uptrend = close_curr > ema_s_curr and ema_f_curr > ema_s_curr
        downtrend = close_curr < ema_s_curr and ema_f_curr < ema_s_curr
        
        # Raw triggers (crossover logic)
        buy_raw = j_prev <= flb_prev and j_curr > flb_curr
        sell_raw = k_prev <= fls_prev and k_curr > fls_curr
        
        # Signal gating (remove duplicates)
        buy_gate = buy_raw and self.last_sig != 1
        sell_gate = sell_raw and self.last_sig != -1
        
        # Apply trend filter
        buy_cond = buy_gate and (not self.use_trend or uptrend)
        sell_cond = sell_gate and (not self.use_trend or downtrend)
        
        # Execute trades
        if buy_cond:
            if not self.position:
                self.buy()
            self.last_sig = 1
        
        if sell_cond:
            if self.position:
                self.position.close()
            self.last_sig = -1