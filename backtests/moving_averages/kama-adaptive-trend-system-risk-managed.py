import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # KAMA Settings
    lookback_period = 10
    fastma_length = 5
    slowma_length = 50
    
    # Strategy Settings
    kama_rising_period = 10
    kama_falling_period = 10
    
    # Risk Management & Filters
    filter_ma_len = 200
    risk_percent = 1.0
    atr_period = 14
    atr_multiplier = 2.5
    rsi_period = 14
    rsi_midline = 50
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate KAMA
        self.kama = self.I(self._calculate_kama, close)
        
        # Calculate Regime Filter MA
        self.filter_ma = self.I(pta.sma, close, length=self.filter_ma_len)
        
        # Calculate ATR for stop-loss
        self.atr_value = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # Calculate RSI for momentum filter
        self.rsi_value = self.I(pta.rsi, close, length=self.rsi_period)
        
        # Track previous KAMA state for rising/falling detection
        self.kama_rising_counter = 0
        self.kama_falling_counter = 0
        self.last_kama_trend = None
        
    def _calculate_kama(self, close):
        kama_values = pd.Series(index=close.index, dtype='float64')
        
        for i in range(len(close)):
            if i < self.lookback_period:
                kama_values.iloc[i] = close.iloc[i]
                continue
            
            price_change = abs(close.iloc[i] - close.iloc[i - self.lookback_period])
            sum_price_change = sum(abs(close.iloc[i - j] - close.iloc[i - j - 1]) 
                                   for j in range(self.lookback_period))
            
            if sum_price_change == 0:
                kama_values.iloc[i] = kama_values.iloc[i - 1]
                continue
            
            fastest = 2 / (self.fastma_length + 1)
            slowest = 2 / (self.slowma_length + 1)
            er = price_change / sum_price_change
            sc = (er * (fastest - slowest) + slowest) ** 2
            
            if i == self.lookback_period:
                kama_values.iloc[i] = close.iloc[i]
            else:
                kama_values.iloc[i] = kama_values.iloc[i - 1] + sc * (close.iloc[i] - kama_values.iloc[i - 1])
        
        return kama_values
    
    def _is_rising(self, series, period):
        if len(series) < period + 1:
            return False
        current_value = series[-1]
        past_value = series[-(period + 1)]
        return current_value > past_value
    
    def _is_falling(self, series, period):
        if len(series) < period + 1:
            return False
        current_value = series[-1]
        past_value = series[-(period + 1)]
        return current_value < past_value
    
    def next(self):
        if len(self.data) < max(self.lookback_period, self.filter_ma_len, self.rsa_period) + 10:
            return
        
        close_price = self.data.Close[-1]
        
        # Check regime filter
        is_bullish_regime = close_price > self.filter_ma[-1] if self.filter_ma[-1] is not None else True
        is_bearish_regime = close_price < self.filter_ma[-1] if self.filter_ma[-1] is not None else True
        
        # Check momentum filter
        is_bullish_momentum = self.rsi_value[-1] > self.rsi_midline if self.rsi_value[-1] is not None else True
        is_bearish_momentum = self.rsi_value[-1] < self.rsi_midline if self.rsi_value[-1] is not None else True
        
        # Check KAMA trend
        kama_rising = self._is_rising(self.kama, self.kama_rising_period)
        kama_falling = self._is_falling(self.kama, self.kama_falling_period)
        
        # Entry conditions
        long_condition = kama_rising and is_bullish_regime and is_bullish_momentum
        short_condition = kama_falling and is_bearish_regime and is_bearish_momentum
        
        # Calculate stop loss
        atr_val = self.atr_value[-1] if self.atr_value[-1] is not None else 0
        stop_loss_points = atr_val * self.atr_multiplier
        
        if long_condition and not self.position:
            self.buy()
        elif short_condition and self.position:
            self.sell()
        
        # Exit logic with stop loss
        if self.position:
            if self.position.is_long:
                stop_price = self.position.open_price - stop_loss_points
                if close_price <= stop_price:
                    self.sell()
            elif self.position.is_short:
                stop_price = self.position.open_price + stop_loss_points
                if close_price >= stop_price:
                    self.buy()


