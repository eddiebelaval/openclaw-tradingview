import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_len = 20
    macd_fast = 12
    macd_slow = 26
    macd_sig = 9

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema_htf = self.I(pta.ema, close, length=self.ema_len)
        
        macd_result = self.I(pta.macd, close, fast=self.macd_fast, slow=self.macd_slow, signal=self.macd_sig)
        self.macd_line = self.I(lambda: macd_result.iloc[:, 0] if macd_result is not None and len(macd_result.columns) > 0 else pd.Series(0, index=close.index))
        self.signal_line = self.I(lambda: macd_result.iloc[:, 2] if macd_result is not None and len(macd_result.columns) > 2 else pd.Series(0, index=close.index))
        
        self.open_series = self.I(lambda: pd.Series(self.data.Open))
        self.high_series = self.I(lambda: pd.Series(self.data.High))
        self.low_series = self.I(lambda: pd.Series(self.data.Low))
        self.volume_series = self.I(lambda: pd.Series(self.data.Volume))

    def next(self):
        if len(self.data) < 2:
            return
        
        h_o = self.open_series[-1]
        h_c = self.data.Close[-1]
        h_h = self.high_series[-1]
        h_l = self.low_series[-1]
        h_v = self.volume_series[-1]
        h_v_prev = self.volume_series[-2]
        
        is_bull = h_c > h_o
        is_bear = h_c < h_o
        body = abs(h_c - h_o)
        upper_wick = h_h - max(h_o, h_c)
        lower_wick = min(h_o, h_c) - h_l
        
        vol_up = h_v > h_v_prev
        
        ema_val = self.ema_htf[-1]
        signal_val = self.signal_line[-1]
        
        bull_ok = is_bull and vol_up and h_c > ema_val and signal_val > 0 and body > upper_wick
        bear_ok = is_bear and vol_up and h_c < ema_val and signal_val < 0 and body > lower_wick
        
        if bull_ok:
            if not self.position:
                self.buy()
        elif bear_ok:
            if self.position:
                self.position.close()