import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core parameters
    emaLen = 200
    atrLen = 14
    
    # ADX parameters
    useAdx = True
    adxLen = 14
    adxSmooth = 14
    adxMin = 20.0
    
    # MTF trend filter (not applicable in single timeframe backtest, set to False)
    useMTF = False
    mtfEmaLen = 200
    
    # Session filter (not applicable in backtest, set to False)
    useSession = False
    
    # Compression filter
    useCompression = True
    compLen = 20
    compMaxAtrMult = 1.2
    
    # Momentum candle
    useMomentum = True
    momBodyAtrMin = 0.60
    
    # Scoring
    minScoreGo = 55

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_price = pd.Series(self.data.Open)
        
        # EMA Trend
        self.emaTrend = self.I(pta.ema, close, length=self.emaLen)
        
        # ATR
        self.atrVal = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # ADX (DMI)
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adxLen, scalar=100) or pd.DataFrame(0, index=close.index, columns=['ADX_14', 'DMP_14', 'DMN_14']))
        self.adxVal = self.I(lambda: adx_result['ADX_14'] if isinstance(adx_result, pd.DataFrame) and 'ADX_14' in adx_result else pd.Series(0, index=close.index))
        self.diPlus = self.I(lambda: adx_result['DMP_14'] if isinstance(adx_result, pd.DataFrame) and 'DMP_14' in adx_result else pd.Series(0, index=close.index))
        self.diMinus = self.I(lambda: adx_result['DMN_14'] if isinstance(adx_result, pd.DataFrame) and 'DMN_14' in adx_result else pd.Series(0, index=close.index))
        
        # Highest/Lowest for compression
        self.highest = self.I(lambda: high.rolling(self.compLen).max())
        self.lowest = self.I(lambda: low.rolling(self.compLen).min())
        
        # Body and range
        self.body = self.I(lambda: np.abs(close - open_price))
        self.range = self.I(lambda: high - low)

    def next(self):
        # Current values
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        
        ema_val = self.emaTrend[-1]
        atr_val = self.atrVal[-1]
        adx_val = self.adxVal[-1]
        
        if atr_val is None or atr_val == 0 or ema_val is None:
            return
        
        # Trend
        trendLong = close_val > ema_val
        trendShort = close_val < ema_val
        
        # ADX OK
        adxOK = (not self.useAdx) or (adx_val >= self.adxMin)
        
        # MTF OK (disabled for single timeframe)
        mtfOKLong = True
        mtfOKShort = True
        
        # Session OK (disabled for backtest)
        sessionOK = True
        
        # Momentum candle
        body_val = self.body[-1]
        momBull = close_val > open_val and body_val >= (atr_val * self.momBodyAtrMin)
        momBear = close_val < open_val and body_val >= (atr_val * self.momBodyAtrMin)
        momOK = (not self.useMomentum) or momBull or momBear
        
        # Compression
        highest_val = self.highest[-1]
        lowest_val = self.lowest[-1]
        
        if highest_val is None or lowest_val is None or highest_val == lowest_val:
            rangeN = 0
        else:
            rangeN = highest_val - lowest_val
        
        compression = rangeN <= atr_val * self.compMaxAtrMult
        compOK = (not self.useCompression) or compression
        
        # Pullback setup
        close_prev = self.data.Close[-2] if len(self.data) > 1 else close_val
        open_prev = self.data.Open[-2] if len(self.data) > 1 else open_val
        
        pbLong = trendLong and close_val > open_val and close_prev < open_prev
        pbShort = trendShort and close_val < open_val and close_prev > open_prev
        
        goLongRaw = pbLong
        goShortRaw = pbShort
        
        # Scoring
        scoreTrendLong = 25 if trendLong else 0
        scoreTrendShort = 25 if trendShort else 0
        
        scoreMTFLong = 20 if mtfOKLong else 0
        scoreMTFShort = 20 if mtfOKShort else 0
        
        scoreADX = 15 if adxOK else 0
        scoreSess = 10 if sessionOK else 0
        scoreComp = 10 if compOK else 0
        scoreMom = 10 if momOK else 0
        
        # Body percentage
        range_val = self.range[-1]
        bodyPct = (body_val / range_val * 100.0) if range_val > 0 else 0.0
        scorePB = 10 if bodyPct >= 55 else 0
        
        scoreLong = scoreTrendLong + scoreMTFLong + scoreADX + scoreSess + scoreComp + scoreMom + scorePB
        scoreShort = scoreTrendShort + scoreMTFShort + scoreADX + scoreSess + scoreComp + scoreMom + scorePB
        
        goLong = goLongRaw and adxOK and sessionOK and compOK and momOK and mtfOKLong and (scoreLong >= self.minScoreGo)
        goShort = goShortRaw and adxOK and sessionOK and compOK and momOK and mtfOKShort and (scoreShort >= self.minScoreGo)
        
        # Trading logic
        if goLong and not self.position:
            self.buy()
        elif goShort and self.position:
            self.position.close()


