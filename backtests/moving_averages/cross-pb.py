import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fast_length = 9
    fast_src = "close"
    fast_type = "EMA"
    slow_length = 18
    slow_src = "close"
    slow_type = "EMA"
    filter_length = 99
    filter_src = "close"
    filter_type = "WMA"

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        fast_source = self._get_source(self.fast_src, open_, high, low, close)
        slow_source = self._get_source(self.slow_src, open_, high, low, close)
        filter_source = self._get_source(self.filter_src, open_, high, low, close)

        self.fast_ma = self.I(self._calc_ma, fast_source, self.fast_length, self.fast_type, volume)
        self.slow_ma = self.I(self._calc_ma, slow_source, self.slow_length, self.slow_type, volume)
        self.filter_ma = self.I(self._calc_ma, filter_source, self.filter_length, self.filter_type, volume)

    def _get_source(self, src_str, open_, high, low, close):
        if src_str == "open":
            return open_
        elif src_str == "high":
            return high
        elif src_str == "low":
            return low
        elif src_str == "hl2":
            return (high + low) / 2
        elif src_str == "hlc3":
            return (high + low + close) / 3
        elif src_str == "ohlc4":
            return (open_ + high + low + close) / 4
        else:
            return close

    def _calc_ma(self, src, length, ma_type, volume):
        if ma_type == "SMA":
            return pta.sma(src, length=length)
        elif ma_type == "EMA":
            return pta.ema(src, length=length)
        elif ma_type == "WMA":
            return pta.wma(src, length=length)
        elif ma_type == "HMA":
            sqrt_len = int(np.sqrt(length))
            wma1 = pta.wma(src, length=length // 2)
            wma2 = pta.wma(src, length=length)
            hma_src = 2 * wma1 - wma2
            return pta.wma(hma_src, length=sqrt_len)
        elif ma_type == "VWMA":
            return pta.vwma(src, volume, length=length)
        elif ma_type == "RMA":
            return pta.rma(src, length=length)
        elif ma_type == "ALMA":
            return self._alma(src, length, 0.85, 6)
        elif ma_type == "TMA":
            return self._tma(src, length)
        elif ma_type == "TSMA":
            return pta.linreg(src, length=length)
        elif ma_type == "KAMA":
            return self._kama(src, length, 2, 30)
        elif ma_type == "AMA":
            return self._ama(src, length)
        else:
            return pta.ema(src, length=length)

    def _alma(self, series, length, offset, sigma):
        alma_offset = offset * (length - 1)
        weights = np.array([np.exp(-((i - alma_offset) ** 2) / (2 * sigma ** 2)) for i in range(length)])
        weight_sum = weights.sum()
        
        result = pd.Series(index=series.index, dtype=float)
        for i in range(len(series)):
            if i < length - 1:
                result.iloc[i] = np.nan
            else:
                window = series.iloc[i - length + 1:i + 1].values
                result.iloc[i] = np.sum(window * weights) / weight_sum
        return result

    def _tma(self, src, length):
        half_length = int(np.floor((length + 1) / 2))
        sma1 = pta.sma(src, length=half_length)
        sma2 = pta.sma(sma1, length=half_length)
        return sma2

    def _kama(self, src, length, fast_sc, slow_sc):
        change = (src - src.shift(length)).abs()
        volatility = pd.Series(0.0, index=src.index)
        for i in range(length):
            volatility += (src - src.shift(i + 1)).abs()
        
        er = change / volatility
        er = er.fillna(0)
        er = er.clip(0, 1)
        
        fast = 2.0 / (fast_sc + 1)
        slow = 2.0 / (slow_sc + 1)
        alpha = (er * (fast - slow) + slow) ** 2
        
        kama_val = pd.Series(index=src.index, dtype=float)
        kama_val.iloc[0] = src.iloc[0]
        for i in range(1, len(src)):
            kama_val.iloc[i] = kama_val.iloc[i - 1] + alpha.iloc[i] * (src.iloc[i] - kama_val.iloc[i - 1])
        return kama_val

    def _ama(self, src, length):
        noise = pta.sma((src - src.shift(1)).abs(), length=length)
        signal = (src - src.shift(length)).abs()
        efficiency = (signal / noise).clip(0, 1)
        alpha = (efficiency * 0.5) ** 2
        
        ama_val = pd.Series(index=src.index, dtype=float)
        ama_val.iloc[0] = src.iloc[0]
        for i in range(1, len(src)):
            ama_val.iloc[i] = ama_val.iloc[i - 1] + alpha.iloc[i] * (src.iloc[i] - ama_val.iloc[i - 1])
        return ama_val

    def next(self):
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        fast_ma = self.fast_ma[-1]
        slow_ma = self.slow_ma[-1]

        if len(self.data) < 2:
            return

        bullish_candle = close > open_
        bearish_candle = close < open_

        # BUY Signal 1: Bullish Crossover + Bearish Candle closed below Fast MA
        if (crossover(self.fast_ma, self.slow_ma) and 
            bearish_candle and close < fast_ma):
            if not self.position:
                self.buy()

        # SELL Signal 1: Bearish Crossover + Bullish Candle closed above Fast MA
        if (crossover(self.slow_ma, self.fast_ma) and 
            bullish_candle and close > fast_ma):
            if self.position:
                self.sell()

        # BUY Signal 2: Bullish Crossover + Bearish Candle closed below Slow MA
        if (crossover(self.fast_ma, self.slow_ma) and 
            bearish_candle and close < slow_ma):
            if not self.position:
                self.buy()

        # SELL Signal 2: Bearish Crossover + Bullish Candle closed above Slow MA
        if (crossover(self.slow_ma, self.fast_ma) and 
            bullish_candle and close > slow_ma):
            if self.position:
                self.sell()