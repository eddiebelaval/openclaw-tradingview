import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        self.sma50 = self.I(pta.sma, close, length=50)
        self.sma100 = self.I(pta.sma, close, length=100)
        self.sma200 = self.I(pta.sma, close, length=200)

    def next(self):
        if not self.position:
            if crossover(self.sma50, self.sma200):
                self.buy()
            elif crossover(self.sma100, self.sma50):
                if crossover(self.sma200, self.sma100):
                    self.buy()
        else:
            if crossover(self.sma200, self.sma50):
                self.sell()
            elif crossover(self.sma200, self.sma100):
                self.sell()