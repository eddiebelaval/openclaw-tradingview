import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    hmaLen = 80

    def init(self):
        close = pd.Series(self.data.Close)
        self.whiteLine = self.I(pta.hma, close, length=self.hmaLen)

    def next(self):
        if len(self.data) < self.hmaLen + 1:
            return
        
        longSig = crossover(self.data.Close, self.whiteLine)
        shortSig = crossover(self.whiteLine, self.data.Close)
        
        if longSig:
            if not self.position:
                self.buy()
        elif shortSig:
            if self.position:
                self.sell()


