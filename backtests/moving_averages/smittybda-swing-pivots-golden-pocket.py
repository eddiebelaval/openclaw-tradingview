        low_arr = self.data.Low
        
        is_swing_high = self._is_swing_high(high_arr, idx)
        is_swing_low = self._is_swing_low(low_arr, idx)
        
        if is_swing_high:
            ph = high_arr[idx - self.rightBars]
            self.last_high_price = ph
            self.in_bullish_zone = False
            
            if self.last_low_price is not None:
                diff = ph - self.last_low_price
                bull_top = ph - (diff * 0.618)
                bull_bottom = ph - (diff * 0.650)
                self.bullish_zone_top = bull_top
                self.bullish_zone_bottom = bull_bottom
                self.in_bullish_zone = True
        
        if is_swing_low:
            pl = low_arr[idx - self.rightBars]
            self.last_low_price = pl
            self.in_bearish_zone = False
            
            if self.last_high_price is not None:
                diff = self.last_high_price - pl
                bear_bottom = pl + (diff * 0.618)
