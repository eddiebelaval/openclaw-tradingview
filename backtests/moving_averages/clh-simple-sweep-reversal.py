import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLength = 20
    slowLength = 200
    minWickPct = 20.0
    lookbackDaysBeyondPrior = 7
    maxDistanceToLookbackExtreme = 100.0
    lookbackWeeks = 2
    weeklyDistance = 100.0
    maOffset = 0.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.fastMA = self.I(pta.sma, close, length=self.fastLength)
        self.slowMA = self.I(pta.sma, close, length=self.slowLength)
        
        self.highest_high = self.I(lambda: high.rolling(window=self.lookbackDaysBeyondPrior).max())
        self.lowest_low = self.I(lambda: low.rolling(window=self.lookbackDaysBeyondPrior).min())
        
        self.highest_weekly_high = self.I(lambda: high.rolling(window=self.lookbackWeeks * 5).max())
        self.lowest_weekly_low = self.I(lambda: low.rolling(window=self.lookbackWeeks * 5).min())

    def next(self):
        if len(self.data) < self.slowLength + 1:
            return
        
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_open = self.data.Open[-1]
        
        prev_high = self.data.High[-2]
        prev_low = self.data.Low[-2]
        
        fastMA_val = self.fastMA[-1]
        slowMA_val = self.slowMA[-1]
        
        if pd.isna(fastMA_val) or pd.isna(slowMA_val):
            return
        
        highest_high_val = self.highest_high[-1] if not pd.isna(self.highest_high[-1]) else current_high
        lowest_low_val = self.lowest_low[-1] if not pd.isna(self.lowest_low[-1]) else current_low
        
        highest_weekly_high_val = self.highest_weekly_high[-1] if not pd.isna(self.highest_weekly_high[-1]) else current_high
        lowest_weekly_low_val = self.lowest_weekly_low[-1] if not pd.isna(self.lowest_weekly_low[-1]) else current_low
        
        candleRange = current_high - current_low
        if candleRange <= 0:
            return
        
        upperWick = current_high - max(current_open, current_close)
        lowerWick = min(current_open, current_close) - current_low
        
        largeUpperWick = upperWick >= candleRange * (self.minWickPct / 100.0)
        largeLowerWick = lowerWick >= candleRange * (self.minWickPct / 100.0)
        
        swingHigh = current_high > prev_high
        swingLow = current_low < prev_low
        
        aboveHighest = current_high > highest_high_val
        belowLowest = current_low < lowest_low_val
        
        tooCloseToWeeklyHigh = current_high < highest_weekly_high_val and (highest_weekly_high_val - current_high) <= self.weeklyDistance
        tooCloseToWeeklyLow = current_low > lowest_weekly_low_val and (current_low - lowest_weekly_low_val) <= self.weeklyDistance
        
        shortSignalRaw = (swingHigh and 
                         (aboveHighest) and 
                         largeUpperWick and 
                         (fastMA_val > slowMA_val + self.maOffset) and 
                         current_high > fastMA_val and
                         not tooCloseToWeeklyHigh)
        
        longSignalRaw = (swingLow and 
                        (belowLowest) and 
                        largeLowerWick and 
                        (fastMA_val < slowMA_val - self.maOffset) and 
                        current_low < fastMA_val and
                        not tooCloseToWeeklyLow)
        
        onlyLong = longSignalRaw and not shortSignalRaw
        onlyShort = shortSignalRaw and not longSignalRaw
        
        if onlyLong:
            if not self.position:
                self.buy()
        elif onlyShort:
            if self.position:
                self.position.close()
            else:
                self.sell()
        
        if self.position and onlyShort:
            self.position.close()
        elif not self.position and onlyShort:
            self.sell()


