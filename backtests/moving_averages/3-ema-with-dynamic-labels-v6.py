import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len1 = 13
    len2 = 48
    len3 = 200

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema1 = self.I(pta.ema, close, length=self.len1)
        self.ema2 = self.I(pta.ema, close, length=self.len2)
        self.ema3 = self.I(pta.ema, close, length=self.len3)

    def next(self):
        if len(self) < 2:
            return
        
        ema1_prev = self.ema1[-2]
        ema2_prev = self.ema2[-2]
        ema3_prev = self.ema3[-2]
        
        ema1_curr = self.ema1[-1]
        ema2_curr = self.ema2[-1]
        ema3_curr = self.ema3[-1]
        
        if pd.isna(ema1_curr) or pd.isna(ema2_curr) or pd.isna(ema3_curr):
            return
        
        if not self.position:
            if crossover(self.ema1, self.ema2) and ema1_curr > ema3_curr:
                self.buy()
            elif crossover(self.ema2, self.ema1) and ema1_curr < ema3_curr:
                self.sell()
        else:
            if self.position.is_long:
                if crossover(self.ema2, self.ema1):
                    self.position.close()
            elif self.position.is_short:
                if crossover(self.ema1, self.ema2):
                    self.position.close()


