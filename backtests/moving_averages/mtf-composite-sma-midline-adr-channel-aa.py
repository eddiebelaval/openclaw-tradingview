import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MTF Settings
    mtf_a_len1 = 7
    mtf_a_len2 = 14
    mtf_b_len1 = 7
    mtf_b_len2 = 14
    mtf_c_len1 = 7
    mtf_c_len2 = 14
    mtf_d_len1 = 7
    mtf_d_len2 = 14
    
    # ADR Settings
    adr_len = 14
    k_adr = 1.0
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate SMAs with double smoothing for each MTF level
        # MTF A (15min equivalent on current TF)
        sma_high_a_inner = self.I(lambda: pta.sma(high, length=self.mtf_a_len2) or pd.Series(high.iloc[-1], index=high.index))
        sma_high_a = self.I(lambda: pta.sma(sma_high_a_inner, length=self.mtf_a_len1) or pd.Series(high.iloc[-1], index=high.index))
        
        sma_low_a_inner = self.I(lambda: pta.sma(low, length=self.mtf_a_len2) or pd.Series(low.iloc[-1], index=low.index))
        sma_low_a = self.I(lambda: pta.sma(sma_low_a_inner, length=self.mtf_a_len1) or pd.Series(low.iloc[-1], index=low.index))
        
        self.h_a = sma_high_a
        self.l_a = sma_low_a
        self.m_a = self.I(lambda: (sma_high_a + sma_low_a) / 2.0)
        
        # MTF B (60min equivalent)
        sma_high_b_inner = self.I(lambda: pta.sma(high, length=self.mtf_b_len2) or pd.Series(high.iloc[-1], index=high.index))
        sma_high_b = self.I(lambda: pta.sma(sma_high_b_inner, length=self.mtf_b_len1) or pd.Series(high.iloc[-1], index=high.index))
        
        sma_low_b_inner = self.I(lambda: pta.sma(low, length=self.mtf_b_len2) or pd.Series(low.iloc[-1], index=low.index))
        sma_low_b = self.I(lambda: pta.sma(sma_low_b_inner, length=self.mtf_b_len1) or pd.Series(low.iloc[-1], index=low.index))
        
        self.h_b = sma_high_b
        self.l_b = sma_low_b
        self.m_b = self.I(lambda: (sma_high_b + sma_low_b) / 2.0)
        
        # MTF C (240min equivalent)
        sma_high_c_inner = self.I(lambda: pta.sma(high, length=self.mtf_c_len2) or pd.Series(high.iloc[-1], index=high.index))
        sma_high_c = self.I(lambda: pta.sma(sma_high_c_inner, length=self.mtf_c_len1) or pd.Series(high.iloc[-1], index=high.index))
        
        sma_low_c_inner = self.I(lambda: pta.sma(low, length=self.mtf_c_len2) or pd.Series(low.iloc[-1], index=low.index))
        sma_low_c = self.I(lambda: pta.sma(sma_low_c_inner, length=self.mtf_c_len1) or pd.Series(low.iloc[-1], index=low.index))
        
        self.h_c = sma_high_c
        self.l_c = sma_low_c
        self.m_c = self.I(lambda: (sma_high_c + sma_low_c) / 2.0)
        
        # MTF D (720min equivalent)
        sma_high_d_inner = self.I(lambda: pta.sma(high, length=self.mtf_d_len2) or pd.Series(high.iloc[-1], index=high.index))
        sma_high_d = self.I(lambda: pta.sma(sma_high_d_inner, length=self.mtf_d_len1) or pd.Series(high.iloc[-1], index=high.index))
        
        sma_low_d_inner = self.I(lambda: pta.sma(low, length=self.mtf_d_len2) or pd.Series(low.iloc[-1], index=low.index))
        sma_low_d = self.I(lambda: pta.sma(sma_low_d_inner, length=self.mtf_d_len1) or pd.Series(low.iloc[-1], index=low.index))
        
        self.h_d = sma_high_d
        self.l_d = sma_low_d
        self.m_d = self.I(lambda: (sma_high_d + sma_low_d) / 2.0)
        
        # Calculate median of 4 values for composite levels
        self.umid = self.I(self._calc_umid)
        self.u_high = self.I(self._calc_uhigh)
        self.u_low = self.I(self._calc_ulow)
        
        # ADR calculation
        adr_hl = self.I(lambda: pta.sma(high - low, length=self.adr_len) or pd.Series(0, index=high.index))
        self.adr_up = self.I(lambda: self.umid + self.k_adr * adr_hl)
        self.adr_dn = self.I(lambda: self.umid - self.k_adr * adr_hl)
    
    def _calc_umid(self):
        return self._median4(self.m_a[-1], self.m_b[-1], self.m_c[-1], self.m_d[-1])
    
    def _calc_uhigh(self):
        return self._median4(self.h_a[-1], self.h_b[-1], self.h_c[-1], self.h_d[-1])
    
    def _calc_ulow(self):
        return self._median4(self.l_a[-1], self.l_b[-1], self.l_c[-1], self.l_d[-1])
    
    def _median4(self, v1, v2, v3, v4):
        vals = sorted([v1, v2, v3, v4])
        return (vals[1] + vals[2]) / 2.0
    
    def next(self):
        # Trading logic based on MTF Composite crossovers
        if len(self.data) < 2:
            return
        
        # Buy signals
        if crossover(self.data.Close, self.umid):
            if not self.position:
                self.buy()
        
        if crossover(self.data.Close, self.adr_dn):
            if not self.position:
                self.buy()
        
        # Sell signals
        if crossover(self.umid, self.data.Close):
            if self.position:
                self.position.close()
        
        if crossover(self.adr_up, self.data.Close):
            if self.position:
                self.position.close()