import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Core indicators
        self.bb_mid = self.I(pta.sma, close, length=20)
        self.ma5_h = self.I(pta.wma, high, length=5)
        self.ma5_l = self.I(pta.wma, low, length=5)
        self.ma10_h = self.I(pta.wma, high, length=10)
        self.ma10_l = self.I(pta.wma, low, length=10)
        
        # Bollinger Bands
        self.bb_basis = self.I(pta.sma, close, length=20)
        self.bb_dev = self.I(lambda x: 2.0 * pta.stdev(x, length=20), close)
        self.bb_top = self.I(lambda: self.bb_basis[-1] + self.bb_dev[-1] if not np.isnan(self.bb_basis[-1]) and not np.isnan(self.bb_dev[-1]) else np.nan)
        self.bb_low = self.I(lambda: self.bb_basis[-1] - self.bb_dev[-1] if not np.isnan(self.bb_basis[-1]) and not np.isnan(self.bb_dev[-1]) else np.nan)
        
        self.open_prices = self.I(lambda x: x, pd.Series(self.data.Open))

    def next(self):
        if len(self.data) < 3:
            return
        
        # Current values
        o = self.open_prices[-1]
        c = self.data.Close[-1]
        h = self.data.High[-1]
        l = self.data.Low[-1]
        
        bb_mid_val = self.bb_mid[-1]
        ma5_h_val = self.ma5_h[-1]
        ma5_l_val = self.ma5_l[-1]
        ma10_h_val = self.ma10_h[-1]
        ma10_l_val = self.ma10_l[-1]
        bb_top_val = self.bb_basis[-1] + 2.0 * (self.bb_basis[-1] - self.bb_low[-1]) / 2.0 if len(self.bb_basis) > 0 else np.nan
        bb_low_val = self.bb_basis[-1] - 2.0 * (self.bb_basis[-1] - self.bb_low[-1]) / 2.0 if len(self.bb_basis) > 0 else np.nan
        
        if np.isnan(bb_mid_val) or np.isnan(ma5_h_val) or np.isnan(ma5_l_val):
            return
        
        # CSAK triggers
        csak_buy = o <= bb_mid_val and c > bb_mid_val and c > ma5_h_val and c > ma10_h_val
        csak_sell = o >= bb_mid_val and c < bb_mid_val and c < ma5_l_val and c < ma10_l_val
        
        # CSM triggers
        csm_buy = c > bb_top_val and ma5_h_val < bb_top_val and ma10_h_val < bb_top_val
        csm_sell = c < bb_low_val and ma5_l_val > bb_low_val and ma10_l_val > bb_low_val
        
        # Combined triggers
        buy_signal = csak_buy or csm_buy
        sell_signal = csak_sell or csm_sell
        
        # Simple entry/exit logic
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.position.close()


