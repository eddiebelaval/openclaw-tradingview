import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ma50 = self.I(pta.sma, close, length=50)
        self.ma100 = self.I(pta.sma, close, length=100)
        self.ma200 = self.I(pta.sma, close, length=200)

    def next(self):
        if len(self.data) < 200:
            return
        
        if self.ma50[-1] is None or self.ma100[-1] is None or self.ma200[-1] is None:
            return
        
        if not self.position:
            if self.ma50[-1] > self.ma100[-1] > self.ma200[-1]:
                if crossover(self.ma50, self.ma100):
                    self.buy()
        else:
            if self.ma50[-1] < self.ma100[-1]:
                self.sell()