import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_period = 14

    def init(self):
        close = pd.Series(self.data.Close)
        open_price = pd.Series(self.data.Open)
        
        self.oema = self.I(pta.ema, open_price, length=self.ema_period)
        self.cema = self.I(pta.ema, close, length=self.ema_period)

    def next(self):
        if len(self.data) < self.ema_period:
            return
        
        # Buy when cEMA crosses above oEMA (bullish momentum)
        if crossover(self.cema, self.oema):
            if not self.position:
                self.buy()
        
        # Sell when cEMA crosses below oEMA (bearish momentum)
        elif crossover(self.oema, self.cema):
            if self.position:
                self.position.close()