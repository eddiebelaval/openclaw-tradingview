import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_fast = 9
    ema_slow = 21
    swing_len = 5
    atr_len = 14
    sl_atr = 1.5
    e2_atr = 0.5
    e3_atr = 1.0
    tp1_r = 1.0
    tp2_r = 2.0
    tp3_r = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        self.ema9_ltf = self.I(pta.ema, close, length=self.ema_fast)
        self.ema21_ltf = self.I(pta.ema, close, length=self.ema_slow)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)

        self.ph_ltf = self.I(
            lambda: self._pivot_high(high, self.swing_len)
        )
        self.pl_ltf = self.I(
            lambda: self._pivot_low(low, self.swing_len)
        )

        self.ph1_ltf = None
        self.ph2_ltf = None
        self.pl1_ltf = None
        self.pl2_ltf = None

    def _pivot_high(self, series, length):
        result = pd.Series(np.nan, index=series.index)
        for i in range(length, len(series) - length):
            if series.iloc[i] == series.iloc[i - length:i + length + 1].max():
                result.iloc[i] = series.iloc[i]
        return result

    def _pivot_low(self, series, length):
        result = pd.Series(np.nan, index=series.index)
        for i in range(length, len(series) - length):
            if series.iloc[i] == series.iloc[i - length:i + length + 1].min():
                result.iloc[i] = series.iloc[i]
        return result

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        ema9 = self.ema9_ltf[-1]
        ema21 = self.ema21_ltf[-1]
        atr = self.atr[-1]

        if pd.isna(ema9) or pd.isna(ema21) or pd.isna(atr):
            return

        ltf_bearish = close < self.data.Open[-1]
        ltf_reject = high >= ema9 and close < ema9
        bear_ltf = ema9 < ema21 and close < ema21

        ph_val = self.ph_ltf[-1]
        pl_val = self.pl_ltf[-1]

        if not pd.isna(ph_val):
            self.ph2_ltf = self.ph1_ltf
            self.ph1_ltf = ph_val

        if not pd.isna(pl_val):
            self.pl2_ltf = self.pl1_ltf
            self.pl1_ltf = pl_val

        entry_signal = (
            ltf_bearish and
            ltf_reject and
            bear_ltf and
            self.ph1_ltf is not None and
            self.pl1_ltf is not None
        )

        if entry_signal and not self.position:
            e1_now = close
            sl_now = high + (atr * self.sl_atr)
            rk_now = sl_now - e1_now
            tp1_now = e1_now - (rk_now * self.tp1_r)

            self.buy()

        elif self.position and close <= (self.position.open_price - (self.atr[-1] * self.tp1_r)):
            self.position.close()

        elif self.position and close >= (self.data.High[-1] + (self.atr[-1] * self.sl_atr)):
            self.position.close()