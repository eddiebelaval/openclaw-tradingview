import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Macro settings
    macro_ma_length = 8
    macro_ma_type = "EMA"
    
    # Micro settings
    structure1_fast = 8
    structure1_slow = 16
    structure2_fast = 16
    structure2_slow = 30
    
    # Signal settings
    wait_candle_close = True
    detect_early_reversals = True
    
    # TP/SL settings
    trade_direction = "Long"
    manual_entry_price = 0.0
    tp_main_percent = 1.20
    tp1_percent = 0.0
    tp2_percent = 0.0
    sl_percent = 1.20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Structure 1 EMAs (micro timeframe)
        self.structure1_fast_ma = self.I(pta.ema, close, length=self.structure1_fast)
        self.structure1_slow_ma = self.I(pta.ema, close, length=self.structure1_slow)
        
        # Structure 2 EMAs (micro timeframe)
        self.structure2_fast_ma = self.I(pta.ema, close, length=self.structure2_fast)
        self.structure2_slow_ma = self.I(pta.ema, close, length=self.structure2_slow)
        
        # Macro trend MA (using current close as proxy for macro timeframe)
        self.macro_ma = self.I(pta.ema, close, length=self.macro_ma_length)
        
        # Track previous bar states for crossovers and color changes
        self.prev_fill1_bullish = False
        self.prev_fill2_bullish = False
        self.prev_fill2_bearish = False

    def next(self):
        # Current bar conditions
        fill1_bullish = self.structure1_fast_ma[-1] > self.structure1_slow_ma[-1]
        fill1_bearish = self.structure1_fast_ma[-1] < self.structure1_slow_ma[-1]
        
        fill2_bullish = self.structure2_fast_ma[-1] > self.structure2_slow_ma[-1]
        fill2_bearish = self.structure2_fast_ma[-1] < self.structure2_slow_ma[-1]
        
        macro_bullish = self.data.Close[-1] > self.macro_ma[-1]
        macro_bearish = self.data.Close[-1] < self.macro_ma[-1]
        
        # Crossover detection
        fill1_cross_bullish = crossover(self.structure1_fast_ma, self.structure1_slow_ma)
        fill1_cross_bearish = crossover(self.structure1_slow_ma, self.structure1_fast_ma)
        
        # Color change detection for Structure 2
        fill2_color_change_bull = (not self.prev_fill2_bullish and fill2_bullish)
        fill2_color_change_bear = (not self.prev_fill2_bearish and fill2_bearish)
        
        # Combined trend conditions
        trend_long = macro_bullish and fill2_bullish and fill1_bullish
        trend_short = macro_bearish and fill2_bearish and fill1_bearish
        
        # Entry trigger conditions
        dot_long_trigger = (fill1_cross_bullish or (self.detect_early_reversals and fill2_color_change_bull)) and macro_bullish
        dot_short_trigger = (fill1_cross_bearish or (self.detect_early_reversals and fill2_color_change_bear)) and macro_bearish
        
        # Execute trades
        if trend_long and dot_long_trigger and not self.position:
            self.buy()
        elif trend_short and dot_short_trigger and not self.position:
            self.position.close() if self.position else None
            self.sell()
        elif trend_long and self.position.is_short:
            self.position.close()
            self.buy()
        elif trend_short and self.position.is_long:
            self.position.close()
        
        # Update previous states for next iteration
        self.prev_fill1_bullish = fill1_bullish
        self.prev_fill2_bullish = fill2_bullish
        self.prev_fill2_bearish = fill2_bearish


