import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 8
    emaMidLen = 21
    emaSlowLen = 50
    rsiLen = 14
    rsiOB = 65
    rsiOS = 35
    volLen = 20
    volMult = 1.1
    atrLen = 14
    atrStopMult = 1.5
    atrTpMult = 2.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaMid = self.I(pta.ema, close, length=self.emaMidLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)

        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)

        self.volMA = self.I(pta.sma, volume, length=self.volLen)

        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)

        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macdLine = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACD_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        self.signalLine = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACDh_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))

        self.last_signal = 0
        self.buy_stop = None
        self.buy_tp = None
        self.sell_stop = None
        self.sell_tp = None

    def next(self):
        if len(self.data) < max(self.emaSlowLen, self.rsiLen, self.volLen, self.atrLen) + 2:
            return

        close = self.data.Close[-1]
        volume = self.data.Volume[-1]

        emaFast = self.emaFast[-1]
        emaMid = self.emaMid[-1]
        emaSlow = self.emaSlow[-1]

        trendBull = emaFast > emaMid and emaMid > emaSlow
        trendBear = emaFast < emaMid and emaMid < emaSlow

        rsi = self.rsi[-1]
        rsi_prev = self.rsi[-2] if len(self.rsi) > 1 else rsi

        rsiBullZone = rsi > self.rsiOS and rsi < self.rsiOB and rsi > rsi_prev
        rsiBearZone = rsi < self.rsiOB and rsi > self.rsiOS and rsi < rsi_prev

        volMA = self.volMA[-1]
        volConfirm = volume > volMA * self.volMult

        atr = self.atr[-1]

        macdLine = self.macdLine[-1]
        signalLine = self.signalLine[-1]
        macdLine_prev = self.macdLine[-2] if len(self.macdLine) > 1 else macdLine
        signalLine_prev = self.signalLine[-2] if len(self.signalLine) > 1 else signalLine

        macdBullCross = crossover(self.macdLine, self.signalLine)
        macdBearCross = crossover(self.signalLine, self.macdLine)

        macdBull = macdLine > signalLine
        macdBear = macdLine < signalLine

        htfBull = True
        htfBear = True
        htfBullGate = htfBull
        htfBearGate = htfBear

        bullScore = (1 if trendBull else 0) + (1 if rsiBullZone else 0) + (1 if macdBull else 0) + (1 if htfBullGate else 0)
        bearScore = (1 if trendBear else 0) + (1 if rsiBearZone else 0) + (1 if macdBear else 0) + (1 if htfBearGate else 0)

        buySignal = macdBullCross and bullScore >= 3 and self.last_signal != 1
