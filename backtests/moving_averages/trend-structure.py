import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    maLength = 20
    maMode = 'EMA'

    def init(self):
        close = pd.Series(self.data.Close)
        
        if self.maMode == 'SMA':
            self.trend_line = self.I(pta.sma, close, length=self.maLength)
        elif self.maMode == 'EMA':
            self.trend_line = self.I(pta.ema, close, length=self.maLength)
        elif self.maMode == 'WMA':
            self.trend_line = self.I(pta.wma, close, length=self.maLength)
        elif self.maMode == 'HMA':
            self.trend_line = self.I(pta.hma, close, length=self.maLength)
        elif self.maMode == 'VWMA':
            volume = pd.Series(self.data.Volume)
            self.trend_line = self.I(pta.vwma, close, volume, length=self.maLength)
        elif self.maMode == 'RMA':
            self.trend_line = self.I(pta.rma, close, length=self.maLength)
        elif self.maMode == 'TEMA':
            ema_fast = self.I(pta.ema, close, length=self.maLength)
            ema_mid = self.I(pta.ema, ema_fast, length=self.maLength)
            ema_slow = self.I(pta.ema, ema_mid, length=self.maLength)
            self.trend_line = self.I(lambda: 3.0 * (ema_fast - ema_mid) + ema_slow)
        else:
            self.trend_line = self.I(pta.ema, close, length=self.maLength)

    def next(self):
        if len(self.data) < 2:
            return
        
        current_trend = self.trend_line[-1]
        previous_trend = self.trend_line[-2]
        
        is_uptrend = current_trend >= previous_trend
        
        if is_uptrend and not self.position:
            self.buy()
        elif not is_uptrend and self.position:
            self.sell()