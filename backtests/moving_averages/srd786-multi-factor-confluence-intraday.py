import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Moving Averages
    emaFastLength = 9
    emaSlowLength = 21
    smaLongLength = 50
    
    # Momentum
    rsiLength = 14
    rsiOversoldLevel = 30
    rsiOverboughtLevel = 70
    macdFastLength = 12
    macdSlowLength = 26
    macdSignalLength = 9
    stochLength = 14
    stochLevel = 20
    
    # Volatility
    atrLength = 14
    bbLength = 20
    bbStdDev = 2.0
    
    # Volume
    volSMALength = 20
    volThreshold = 1.5
    
    # Risk Management
    atrStopMult = 1.5
    atrTargetMult = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Moving Averages
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLength)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLength)
        self.smaLong = self.I(pta.sma, close, length=self.smaLongLength)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLength)
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=self.macdFastLength, slow=self.macdSlowLength, signal=self.macdSignalLength))
        self.macdLine = self.I(lambda: pta.macd(close, fast=self.macdFastLength, slow=self.macdSlowLength, signal=self.macdSignalLength)['MACD_12_26_9'] if pta.macd(close, fast=self.macdFastLength, slow=self.macdSlowLength, signal=self.macdSignalLength) is not None else pd.Series(0, index=close.index))
        self.macdSignal = self.I(lambda: pta.macd(close, fast=self.macdFastLength, slow=self.macdSlowLength, signal=self.macdSignalLength)['MACDsh_12_26_9'] if pta.macd(close, fast=self.macdFastLength, slow=self.macdSlowLength, signal=self.macdSignalLength) is not None else pd.Series(0, index=close.index))
        
        # Stochastic
        stoch_result = self.I(lambda: pta.stoch(high, low, close, k=self.stochLength, d=3, smooth_k=3))
        self.stochK = self.I(lambda: pta.stoch(high, low, close, k=self.stochLength, d=3, smooth_k=3)['STOCHk_14_3_3'] if pta.stoch(high, low, close, k=self.stochLength, d=3, smooth_k=3) is not None else pd.Series(50, index=close.index))
        self.stochD = self.I(lambda: pta.stoch(high, low, close, k=self.stochLength, d=3, smooth_k=3)['STOCHd_14_3_3'] if pta.stoch(high, low, close, k=self.stochLength, d=3, smooth_k=3) is not None else pd.Series(50, index=close.index))
        
        # ATR
        self.atrValue = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # Bollinger Bands
        bb_result = self.I(lambda: pta.bbands(close, length=self.bbLength, std=self.bbStdDev))
        self.bbUpper = self.I(lambda: pta.bbands(close, length=self.bbLength, std=self.bbStdDev)['BBU_20_2.0'] if pta.bbands(close, length=self.bbLength, std=self.bbStdDev) is not None else pd.Series(close.max(), index=close.index))
        self.bbMiddle = self.I(lambda: pta.bbands(close, length=self.bbLength, std=self.bbStdDev)['BBM_20_2.0'] if pta.bbands(close, length=self.bbLength, std=self.bbStdDev) is not None else pd.Series(close.mean(), index=close.index))
        self.bbLower = self.I(lambda: pta.bbands(close, length=self.bbLength, std=self.bbStdDev)['BBL_20_2.0'] if pta.bbands(close, length=self.bbLength, std=self.bbStdDev) is not None else pd.Series(close.min(), index=close.index))
        
        # Volume SMA
        self.volSMA = self.I(pta.sma, volume, length=self.volSMALength)
        
        # Highest High and Lowest Low
        self.resistance = self.I(lambda: pd.Series(self.data.High).rolling(20).max())
        self.support = self.I(lambda: pd.Series(self.data.Low).rolling(20).min())

    def next(self):
        if len(self.data) < max(self.emaSlowLength, self.macdSlowLength, self.bbLength) + 10:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        volume = self.data.Volume[-1]
        
        emaFast = self.emaFast[-1]
        emaSlow = self.emaSlow[-1]
        smaLong = self.smaLong[-1]
        rsi = self.rsi[-1]
        macdLine = self.macdLine[-1]
        macdSignal = self.macdSignal[-1]
        stochK = self.stochK[-1]
        stochD = self.stochD[-1]
        atrValue = self.atrValue[-1]
        bbUpper = self.bbUpper[-1]
        bbLower = self.bbLower[-1]
        volSMA = self.volSMA[-1]
        
        # Conditions
        volConfirm = volume > volSMA * self.volThreshold
        rsiOversold = rsi < self.rsiOversoldLevel
        rsiOverbought = rsi > self.rsiOverboughtLevel
        rsiBullish = rsi > 50 and not rsiOverbought
        rsiBearish = rsi < 50 and not rsiOversold
        
        macdBullish = macdLine > macdSignal and macdLine > 0
        macdBearish = macdLine < macdSignal and macdLine < 0
        
        stochOversold = stochK < self.stochLevel and stochD < self.stochLevel
        stochOverbought = stochK > (100 - self.stochLevel) and stochD > (100 - self.stochLevel)
        stochBullish = stochK > stochD
        stochBearish = stochK < stochD
        
        emaTrendUp = close > smaLong and emaFast > emaSlow
        
        priceInBBUpper = close > bbUpper
        priceInBBLower = close < bbLower
        
        # Confluence scoring
        volScore = (10 if volConfirm else 0)
        trendScore = (15 if emaTrendUp else 0)
        rsiScore = (10 if rsiBullish else (10 if rsiBearish else 0))
        macdScore = (10 if macdBullish else (10 if macdBearish else 0))
        stochScore = (5 if (stochBullish and not stochOverbought) else (5 if (stochBearish and not stochOversold) else 0))
        momScore = rsiScore + macdScore + stochScore
        paScore = (10 if (not priceInBBUpper and not priceInBBLower) else 0)
        confluenceScore = volScore + trendScore + momScore + paScore
        
        # Long Signal
        longSignal = (
            crossover(self.emaFast, self.emaSlow) and
            volConfirm and
            (rsi > 50 or rsiOversold) and
            macdBullish and
            (not stochOverbought) and
            (close > smaLong) and
            (confluenceScore >= 40)
        )
        
        # Short Signal
        shortSignal = (
            crossover(self.emaSlow, self.emaFast) and
            volConfirm and
            (rsi < 50 or rsiOverbought) and
            macdBearish and
            (not stochOversold) and
            (close < smaLong) and
            (confluenceScore >= 40)
        )
        
        # Trading Logic
        if longSignal and not self.position:
            self.buy()
        elif shortSignal and self.position:
            self.sell()
        elif self.position and atrValue > 0:
            if self.position.is_long:
                stopLoss = self.position.open_price - (atrValue * self.atrStopMult)
                if close <= stopLoss:
                    self.sell()
                targetPrice = self.position.open_price + (atrValue * self.atrStopMult * self.atrTargetMult)
                if close >= targetPrice:
                    self.sell()
            elif self.position.is_short:
                stopLoss = self.position.open_price + (atrValue * self.atrStopMult)
                if close >= stopLoss:
                    self.buy()
                targetPrice = self.position.open_price - (atrValue * self.atrStopMult * self.atrTargetMult)
                if close <= targetPrice:
                    self.buy()


