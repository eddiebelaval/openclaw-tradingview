import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Instrument & Point Value
    instrument_preset = "NQ"
    point_value = 20.0
    
    # ATR & Volatility
    atr_len = 14
    min_atr_pct = 0.15
    
    # CVD
    cvd_sensitivity = 1.0
    cvd_atr_mult = 0.5
    
    # EMA / SMA
    ma_mode = "EMA"
    ma_fast_len = 9
    ma_slow_len = 21
    
    # Volume
    vol_avg_len = 20
    vol_high_mult = 1.5
    vol_low_mult = 0.5
    
    # RSI
    rsi_len = 14
    rsi_overbought = 70
    rsi_oversold = 30
    
    # Trend
    trend_strength_mult = 1.0
    
    # Market Structure
    struct_swing_len = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # VWAP
        hlc3 = (high + low + close) / 3.0
        self.vwap = self.I(pta.vwap, high, low, close, volume)
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # EMA / SMA
        if self.ma_mode == "EMA":
            self.ma_fast = self.I(pta.ema, close, length=self.ma_fast_len)
            self.ma_slow = self.I(pta.ema, close, length=self.ma_slow_len)
        else:
            self.ma_fast = self.I(pta.sma, close, length=self.ma_fast_len)
            self.ma_slow = self.I(pta.sma, close, length=self.ma_slow_len)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)
        
        # Volume
        self.vol_avg = self.I(pta.sma, volume, length=self.vol_avg_len)

    def next(self):
        # Guard against insufficient data
        if len(self.data) < max(self.ma_slow_len, self.rsi_len, self.atr_len) + 5:
            return
        
        # Check for valid indicator values
        if (np.isnan(self.ma_fast[-1]) or np.isnan(self.ma_slow[-1]) or 
            np.isnan(self.rsi[-1]) or np.isnan(self.atr[-1])):
            return
        
        # Trading Logic: Multi-indicator confirmation
        price = self.data.Close[-1]
        
        # MA Cross signals
        ma_bullish_cross = crossover(self.ma_fast, self.ma_slow)
        ma_bearish_cross = crossover(self.ma_slow, self.ma_fast)
        
        price_above_fast = price > self.ma_fast[-1]
        price_above_slow = price > self.ma_slow[-1]
        
        # RSI signals
        rsi_oversold = self.rsi[-1] < self.rsi_oversold
        rsi_overbought = self.rsi[-1] > self.rsi_overbought
        rsi_rising = self.rsi[-1] > self.rsi[-2] if len(self.rsi) > 1 else False
        rsi_falling = self.rsi[-1] < self.rsi[-2] if len(self.rsi) > 1 else False
        
        # ATR volatility check
        atr_pct = (self.atr[-1] / price) * 100 if price > 0 else 0
        vol_ok = atr_pct > self.min_atr_pct
        
        # VWAP trend
        price_above_vwap = price > self.vwap[-1]
        
        # Volume filter
        current_vol = self.data.Volume[-1]
        vol_avg = self.vol_avg[-1] if not np.isnan(self.vol_avg[-1]) else 1
        vol_ratio = current_vol / vol_avg if vol_avg > 0 else 1.0
        
        # BUY SIGNAL:
        # - MA bullish cross OR price above both MAs with RSI oversold turning up
        # - Price above VWAP
        # - RSI not overbought
        # - Volume acceptable
        # - ATR volatility sufficient
        buy_signal = (
            (ma_bullish_cross or (price_above_fast and price_above_slow and rsi_oversold and rsi_rising)) and
            price_above_vwap and
            not rsi_overbought and
            vol_ok and
            vol_ratio > 0.7
        )
        
        # SELL SIGNAL:
        # - MA bearish cross OR price below both MAs with RSI overbought turning down
        # - Price below VWAP
        # - RSI not oversold
        # - Volume acceptable
        # - ATR volatility sufficient
        sell_signal = (
            (ma_bearish_cross or (not price_above_fast and not price_above_slow and rsi_overbought and rsi_falling)) and
            not price_above_vwap and
            not rsi_oversold and
            vol_ok and
            vol_ratio > 0.7
        )
        
        # Execute trades
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()
        elif not buy_signal and not sell_signal and self.position:
            # Exit on reversal if no clear signal
            if ma_bearish_cross:
                self.sell()


