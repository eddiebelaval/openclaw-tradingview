import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    target_volume = 250000
    source_opt = "High & Low"
    slope_confirm_bars = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate HL2, HLC3, OHLC4
        hl2 = (high + low) / 2
        hlc3 = (high + low + close) / 3
        ohlc4 = (self.data.Open + high + low + close) / 4
        
        # Volume-based moving average calculation
        def calc_vma_single(src_series):
            vma_values = []
            for i in range(len(src_series)):
                vol_sum = 0.0
                price_sum = 0.0
                bars_used = 0
                total_bars = i + 1
                
                for j in range(total_bars):
                    vol_sum += volume.iloc[j]
                    price_sum += src_series.iloc[j]
                    bars_used += 1
                    if vol_sum >= self.target_volume:
                        break
                
                vma_values.append(price_sum / bars_used if bars_used > 0 else np.nan)
            
            return pd.Series(vma_values, index=src_series.index)
        
        # Calculate VMA based on source option
        if self.source_opt == "Close":
            self.vma_single = self.I(lambda: calc_vma_single(close))
            self.vma_high = None
            self.vma_low = None
        elif self.source_opt == "HL2":
            self.vma_single = self.I(lambda: calc_vma_single(hl2))
            self.vma_high = None
            self.vma_low = None
        elif self.source_opt == "HLC3":
            self.vma_single = self.I(lambda: calc_vma_single(hlc3))
            self.vma_high = None
            self.vma_low = None
        elif self.source_opt == "OHLC4":
            self.vma_single = self.I(lambda: calc_vma_single(ohlc4))
            self.vma_high = None
            self.vma_low = None
        else:  # "High & Low"
            self.vma_single = None
            self.vma_high = self.I(lambda: calc_vma_single(high))
            self.vma_low = self.I(lambda: calc_vma_single(low))
        
        # Track slope confirmation states
        self.up_count = 0
        self.down_count = 0
        self.vma_trending_up = False

    def next(self):
        # Determine which VMA to use for trading logic
        if self.vma_single is not None:
            current_vma = self.vma_single[-1]
            prev_vma = self.vma_single[-2] if len(self.vma_single) > 1 else None
        elif self.vma_high is not None and self.vma_low is not None:
            current_vma = (self.vma_high[-1] + self.vma_low[-1]) / 2
            prev_vma = (self.vma_high[-2] + self.vma_low[-2]) / 2 if len(self.vma_high) > 1 else None
        else:
            return
        
        # Handle NaN values
        if pd.isna(current_vma) or prev_vma is None or pd.isna(prev_vma):
            return
        
        # Slope confirmation logic
        if current_vma > prev_vma:
            self.up_count += 1
            self.down_count = 0
        elif current_vma < prev_vma:
            self.down_count += 1
            self.up_count = 0
        
        # Determine trend
        if self.up_count >= self.slope_confirm_bars:
            self.vma_trending_up = True
        elif self.down_count >= self.slope_confirm_bars:
            self.vma_trending_up = False
        
        # Trading logic: Buy when VMA trends up, sell when it trends down
        if self.vma_trending_up and not self.position:
            self.buy()
        elif not self.vma_trending_up and self.position:
            self.sell()