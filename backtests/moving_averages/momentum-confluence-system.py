import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Macro Bias
    tf_macro = "240"  # 4-hour timeframe (approximated in backtest)
    ma_len = 8
    
    # Slow Trend and Fast Momentum
    ema_f1_len = 8
    ema_s1_len = 16
    ema_f2_len = 16
    ema_s2_len = 30
    
    # Risk Management
    atr_len = 14
    sl_mult = 1.5
    tp1_mult = 1.5
    tp2_mult = 2.5
    tp3_mult = 4.0
    
    # Filters
    use_vol_filter = False
    vol_ma_len = 20
    vol_mult = 1.0
    use_adx_filter = False
    adx_len = 14
    adx_thresh = 20
    use_rsi_div = False
    rsi_len = 14
    use_cooldown = True
    cooldown_bars = 5
    
    # Wait for close
    wait_for_close = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMAs for Fast Ribbon
        self.ema1_f = self.I(pta.ema, close, length=self.ema_f1_len)
        self.ema1_s = self.I(pta.ema, close, length=self.ema_s1_len)
        
        # EMAs for Slow Ribbon
        self.ema2_f = self.I(pta.ema, close, length=self.ema_f2_len)
        self.ema2_s = self.I(pta.ema, close, length=self.ema_s2_len)
        
        # Macro EMA (using same timeframe as approximation)
        self.macro_ma = self.I(pta.ema, close, length=self.ma_len)
        
        # ATR
        self.atr_v = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # Volume MA
        self.vol_ma = self.I(pta.sma, volume, length=self.vol_ma_len)
        
        # ADX
        self.adx_val = self.I(self._calc_adx, high, low, close, self.adx_len)
        
        # RSI
        self.rsi_val = self.I(pta.rsi, close, length=self.rsi_len)
        
        # Tracking variables
        self.last_long_bar = -100
        self.last_short_bar = -100
        self.entry_price = None
        self.entry_type = None  # 'long' or 'short'
        self.tp1_price = None
        self.tp2_price = None
        self.tp3_price = None
        self.sl_price = None

    def _calc_adx(self, high, low, close, length):
        """Calculate ADX manually since pandas_ta might have issues"""
        h = high.copy()
        l = low.copy()
        c = close.copy()
        
        tr1 = h - l
        tr2 = abs(h - c.shift(1))
        tr3 = abs(l - c.shift(1))
        tr = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
        
        up = h.diff()
        down = -l.diff()
        
        plus_dm = np.where((up > down) & (up > 0), up, 0)
        minus_dm = np.where((down > up) & (down > 0), down, 0)
        
        atr = tr.rolling(length).mean()
        plus_di = 100 * pd.Series(plus_dm).rolling(length).mean() / atr
        minus_di = 100 * pd.Series(minus_dm).rolling(length).mean() / atr
        
        di_diff = abs(plus_di - minus_di)
        di_sum = plus_di + minus_di
        di_sum = di_sum.replace(0, 1)
        
        adx = 100 * (di_diff / di_sum).rolling(length).mean()
        return adx

    def _check_vol_condition(self):
        """Check volume filter condition"""
        if not self.use_vol_filter:
            return True
        if len(self.data) < self.vol_ma_len:
            return True
        return self.data.Volume[-1] > self.vol_ma[-1] * self.vol_mult

    def _check_adx_condition(self):
        """Check ADX filter condition"""
        if not self.use_adx_filter:
            return True
        if np.isnan(self.adx_val[-1]) or self.adx_val[-1] < 0:
            return True
        return self.adx_val[-1] > self.adx_thresh

    def _check_cooldown(self, signal_type):
        """Check cooldown condition"""
        if not self.use_cooldown:
            return True
        
        current_bar = len(self.data) - 1
        
        if signal_type == 'long':
            return (current_bar - self.last_long_bar) > self.cooldown_bars
        else:
            return (current_bar - self.last_short_bar) > self.cooldown_bars

    def next(self):
        # Skip if not enough data
        if len(self.data) < max(self.ema_s2_len, self.vol_ma_len, self.adx_len) + 2:
            return
        
        close_val = self.data.Close[-1]
        
        # Macro bias
        macro_bull = close_val > self.macro_ma[-1]
        
        # Fast ribbon state
        f1_bull = self.ema1_f[-1] > self.ema1_s[-1]
        
        # Slow ribbon state
        f2_bull = self.ema2_f[-1] > self.ema2_s[-1]
        
        # Raw signals (crossovers)
        raw_long_sig = crossover(self.ema1_f, self.ema1_s)
        raw_short_sig = crossover(self.ema1_s, self.ema1_f)
        
        # Apply filters
        vol_ok = self._check_vol_condition()
        adx_ok = self._check_adx_condition()
        
        # Final signals with all filters
        long_sig = (raw_long_sig and macro_bull and f2_bull and 
                   vol_ok and adx_ok and self._check_cooldown('long'))
        
        short_sig = (raw_short_sig and not macro_bull and not f2_bull and 
                    vol_ok and adx_ok and self._check_cooldown('short'))
        
        # Close existing position if signal reverses
        if self.position and self.entry_type == 'long' and short_sig:
            self.position.close()
            self.entry_price = None
            self.entry_type = None
        elif self.position and self.entry_type == 'short' and long_sig:
            self.position.close()
            self.entry_price = None
            self.entry_type = None
        
        # Long entry
        if long_sig and not self.position:
            self.buy()
            self.entry_price = close_val
            self.entry_type = 'long'
            self.last_long_bar = len(self.data) - 1
            
            # Calculate TP and SL
            if not np.isnan(self.atr_v[-1]) and self.atr_v[-1] > 0:
                atr = self.atr_v[-1]
                self.sl_price = close_val - (atr * self.sl_mult)
                self.tp1_price = close_val + (atr * self.tp1_mult)
                self.tp2_price = close_val + (atr * self.tp2_mult)
                self.tp3_price = close_val + (atr * self.tp3_mult)
        
        # Short entry
        elif short_sig and not self.position:
            self.sell()
            self.entry_price = close_val
            self.entry_type = 'short'
            self.last_short_bar = len(self.data) - 1
            
            # Calculate TP and SL
            if not np.isnan(self.atr_v[-1]) and self.atr_v[-1] > 0:
                atr = self.atr_v[-1]
                self.sl_price = close_val + (atr * self.sl_mult)
                self.tp1_price = close_val - (atr * self.tp1_mult)
                self.tp2_price = close_val - (atr * self.tp2_mult)
                self.tp3_price = close_val - (atr * self.tp3_mult)
        
        # Exit on TP/SL
        if self.position:
            if self.entry_type == 'long':
                # Check TP levels (exit at first TP1)
                if self.tp1_price and close_val >= self.tp1_price:
                    self.position.close()
                # Check SL
                elif self.sl_price and close_val <= self.sl_price:
                    self.position.close()
            
            elif self.entry_type == 'short':
                # Check TP levels
                if self.tp1_price and close_val <= self.tp1_price:
                    self.position.close()
                # Check SL
                elif self.sl_price and close_val >= self.sl_price:
                    self.position.close()


