import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    target_volume = 0.001
    disp_mode = "Wick (High-Low)"
    source_opt = "HLC3"
    min_consecutive = 3
    cdma_smooth_type = "SMA"
    cdma_smooth_len = 5

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        def calculate_cdma():
            cdma_values = []
            cdma_high_values = []
            cdma_low_values = []

            for i in range(len(close)):
                if self.disp_mode == "Wick (High-Low)":
                    art_vol = high.iloc[i] - low.iloc[i]
                else:
                    art_vol = abs(close.iloc[i] - open_.iloc[i])

                vol_sum = 0.0
                price_sum = 0.0
                bars_used = 0

                for j in range(i + 1):
                    if self.disp_mode == "Wick (High-Low)":
                        curr_vol = high.iloc[i - j] - low.iloc[i - j]
                    else:
                        curr_vol = abs(close.iloc[i - j] - open_.iloc[i - j])

                    vol_sum += curr_vol
                    bars_used += 1

                    if self.source_opt == "Close":
                        price_sum += close.iloc[i - j]
                    elif self.source_opt == "HL2":
                        price_sum += (high.iloc[i - j] + low.iloc[i - j]) / 2
                    elif self.source_opt == "HLC3":
                        price_sum += (high.iloc[i - j] + low.iloc[i - j] + close.iloc[i - j]) / 3
                    elif self.source_opt == "OHLC4":
                        price_sum += (open_.iloc[i - j] + high.iloc[i - j] + low.iloc[i - j] + close.iloc[i - j]) / 4

                    if vol_sum >= self.target_volume:
                        break

                cdma_values.append(price_sum / bars_used if bars_used > 0 else np.nan)

                if self.source_opt == "High & Low":
                    vol_sum = 0.0
                    price_sum_high = 0.0
                    bars_used = 0
                    for j in range(i + 1):
                        if self.disp_mode == "Wick (High-Low)":
                            curr_vol = high.iloc[i - j] - low.iloc[i - j]
                        else:
                            curr_vol = abs(close.iloc[i - j] - open_.iloc[i - j])
                        vol_sum += curr_vol
                        price_sum_high += high.iloc[i - j]
                        bars_used += 1
                        if vol_sum >= self.target_volume:
                            break
                    cdma_high_values.append(price_sum_high / bars_used if bars_used > 0 else np.nan)

                    vol_sum = 0.0
                    price_sum_low = 0.0
                    bars_used = 0
                    for j in range(i + 1):
                        if self.disp_mode == "Wick (High-Low)":
                            curr_vol = high.iloc[i - j] - low.iloc[i - j]
                        else:
                            curr_vol = abs(close.iloc[i - j] - open_.iloc[i - j])
                        vol_sum += curr_vol
                        price_sum_low += low.iloc[i - j]
                        bars_used += 1
                        if vol_sum >= self.target_volume:
                            break
                    cdma_low_values.append(price_sum_low / bars_used if bars_used > 0 else np.nan)

            return (
                pd.Series(cdma_values, index=close.index),
                pd.Series(cdma_high_values, index=close.index) if cdma_high_values else pd.Series([np.nan] * len(close), index=close.index),
                pd.Series(cdma_low_values, index=close.index) if cdma_low_values else pd.Series([np.nan] * len(close), index=close.index),
            )

        cdma_single, cdma_high, cdma_low = calculate_cdma()

        def smooth_cdma(series):
            if self.cdma_smooth_type == "None":
                return series
            elif self.cdma_smooth_type == "SMA":
                return pta.sma(series, length=self.cdma_smooth_len)
            elif self.cdma_smooth_type == "EMA":
                return pta.ema(series, length=self.cdma_smooth_len)
            elif self.cdma_smooth_type == "WMA":
                return pta.wma(series, length=self.cdma_smooth_len)
            else:
                return pta.rma(series, length=self.cdma_smooth_len)

        self.cdma_single_smooth = self.I(lambda: smooth_cdma(cdma_single))
        self.cdma_high_smooth = self.I(lambda: smooth_cdma(cdma_high))
        self.cdma_low_smooth = self.I(lambda: smooth_cdma(cdma_low))

        self.rise_count_single = 0
        self.fall_count_single = 0
        self.bullish_confirmed_single = False
        self.bearish_confirmed_single = False

        self.rise_count_high = 0
        self.fall_count_high = 0
        self.bullish_confirmed_high = False
        self.bearish_confirmed_high = False

        self.rise_count_low = 0
        self.fall_count_low = 0
        self.bullish_confirmed_low = False
        self.bearish_confirmed_low = False

    def next(self):
        if len(self.cdma_single_smooth) < 2:
            return

        cdma_val = self.cdma_single_smooth[-1]
        cdma_prev = self.cdma_single_smooth[-2]

        if pd.isna(cdma_val) or pd.isna(cdma_prev):
            return

        slope_up_single = cdma_val > cdma_prev
        slope_down_single = cdma_val < cdma_prev

        if slope_up_single:
            self.rise_count_single += 1
            self.fall_count_single = 0
        elif slope_down_single:
            self.fall_count_single += 1
            self.rise_count_single = 0
        else:
            self.rise_count_single = 0
            self.fall_count_single = 0

        self.bullish_confirmed_single = self.rise_count_single >= self.min_consecutive
        self.bearish_confirmed_single = self.fall_count_single >= self.min_consecutive

        if self.bullish_confirmed_single and not self.position:
            self.buy()
        elif self.bearish_confirmed_single and self.position:
            self.sell()


