import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    magicLen = 20
    magicMult = 1.0
    hmaLen = 50
    chopLen = 14
    chopLimit = 50
    volMult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        hlc3 = (high + low + close) / 3
        
        # CCI calculation
        self.cci = self.I(lambda: pta.cci(high, low, close, length=self.magicLen) or pd.Series(0, index=close.index))
        
        # HMA calculation
        self.hma = self.I(lambda: pta.hma(close, length=self.hmaLen) or close)
        
        # CHOP calculation (manual)
        def calc_chop():
            tr = pta.tr(high, low, close)
            if tr is None:
                tr = pd.Series(0, index=close.index)
            
            tr_sum = tr.rolling(window=self.chopLen).sum()
            highest_high = high.rolling(window=self.chopLen).max()
            lowest_low = low.rolling(window=self.chopLen).min()
            
            range_val = highest_high - lowest_low
            range_val = range_val.replace(0, np.nan)
            
            chop = 100 * np.log10(tr_sum / range_val) / np.log10(self.chopLen)
            return chop.fillna(50)
        
        self.chop = self.I(calc_chop)
        
        # Volume SMA
        self.vol_avg = self.I(pta.sma, volume, length=20)
        
        # Track previous CCI direction
        self.prev_cci_up = None

    def next(self):
        if len(self.data) < self.magicLen + 1:
            return
        
        # Current values
        cci_current = self.cci[-1]
        cci_prev = self.cci[-2] if len(self.cci) > 1 else cci_current
        
        hma_current = self.hma[-1]
        hma_prev = self.hma[-2] if len(self.hma) > 1 else hma_current
        
        chop_current = self.chop[-1]
        vol_current = self.data.Volume[-1]
        vol_avg_current = self.vol_avg[-1]
        
        # Trend conditions
        magic_trend_up = cci_current >= 0
        magic_trend_up_prev = cci_prev >= 0
        magic_trend_dn = cci_current < 0
        magic_trend_dn_prev = cci_prev < 0
        
        # HMA conditions
        hma_up = hma_current > hma_prev
        
        # CHOP conditions
        is_trending = chop_current < self.chopLimit
        
        # Volume conditions
        is_high_volume = vol_current > (vol_avg_current * self.volMult)
        
        # Signal logic
        long_signal = (magic_trend_up and not magic_trend_up_prev and 
                      hma_up and is_trending and is_high_volume)
        
        short_signal = (magic_trend_dn and not magic_trend_dn_prev and 
                       not hma_up and is_trending and is_high_volume)
        
        # Trading logic
        if long_signal:
            if self.position:
                self.position.close()
            self.buy()
        elif short_signal:
            if self.position:
                self.position.close()
            self.sell()


