import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    sfSens = 3.5
    exitWaveSel = 3
    lookback = 20
    slopeThreshold = 0.002

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)

        # Fast EMAs
        self.f1 = self.I(pta.ema, close, length=3)
        self.f2 = self.I(pta.ema, close, length=5)
        self.f3 = self.I(pta.ema, close, length=8)
        self.f4 = self.I(pta.ema, close, length=10)
        self.f5 = self.I(pta.ema, close, length=12)
        self.f6 = self.I(pta.ema, close, length=15)

        # Slow EMAs
        self.s1 = self.I(pta.ema, close, length=50)
        self.s2 = self.I(pta.ema, close, length=60)
        self.s3 = self.I(pta.ema, close, length=70)
        self.s4 = self.I(pta.ema, close, length=80)
        self.s5 = self.I(pta.ema, close, length=90)
        self.s6 = self.I(pta.ema, close, length=100)

        # Backbone
        self.backbone = self.I(pta.ema, close, length=200)

        # ATR
        self.atr_val = self.I(pta.atr, high, low, close, length=14)

        # Volume flow
        self.volflow = self.I(lambda: close.where(close > open_, volume).where(close <= open_, -volume))
        self.netVol = self.I(pta.sma, self.volflow, length=20)

        self.last_pos = 0
        self.sf_buy_triggered = False
        self.sf_sell_triggered = False

    def next(self):
        if len(self.data) < self.lookback + 1:
            return

        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        backbone = self.backbone[-1]
        f6 = self.f6[-1]
        s1 = self.s1[-1]
        f1 = self.f1[-1]
        atr_val = self.atr_val[-1]
        netVol = self.netVol[-1] if self.netVol[-1] is not None else 0

        if backbone is None or f6 is None or s1 is None or atr_val is None:
            return

        # Backbone trend via linear regression approximation
        backbone_vals = np.array([self.backbone[i] for i in range(-self.lookback, 0)])
        if len(backbone_vals) < 2:
            return

        x = np.arange(len(backbone_vals))
        z_current = np.polyfit(x, backbone_vals, 1)[0]
        z_prev = np.polyfit(x, backbone_vals[:-1], 1)[0] if len(backbone_vals) > 1 else z_current

        slopeDirection = z_current
        trendWeakeningUp = slopeDirection < z_prev

        # Distance from s1
        distOrange = close - s1

        # Squeeze condition
        waveDistance = abs(f6 - s1)
        isNotSqueezed = waveDistance > atr_val * 0.2

        # Overbought/Oversold
        isOverbought = distOrange > (atr_val * self.sfSens)
        isOversold = distOrange < -(atr_val * self.sfSens)
        isDistSafe = abs(distOrange) <= atr_val * self.sfSens

        # Candle colors
        isGreen = close > open_
        isRed = close < open_

        # Trend flags
        blueAboveOrange = f6 > s1
        blueBelowOrange = f6 < s1
        closeAboveBackbone = close > backbone
        openAboveBackbone = open_ > backbone
        closeBelowBackbone = close < backbone
        openBelowBackbone = open_ < backbone

        strongTrendUp = slopeDirection > 0
        strongTrendDown = slopeDirection < 0

        # Super signals
        superBuy = (blueAboveOrange and closeAboveBackbone and openAboveBackbone and isGreen
                    and isNotSqueezed and isDistSafe and strongTrendUp and netVol > 0
                    and not isOverbought)

        superSell = (blueBelowOrange and closeBelowBackbone and openBelowBackbone and isRed
                     and isNotSqueezed and isDistSafe and strongTrendDown and netVol < 0
                     and not isOversold)

        # Normal signals
        closeOverBackbone = crossover(close, backbone)
        normalBuy = (closeOverBackbone or (f6 > backbone and s1 > backbone)) and blueAboveOrange and strongTrendUp and isNotSqueezed

        normalSell = (f6 < backbone and s1 < backbone) and blueBelowOrange and strongTrendDown and isNotSqueezed

        # Signal management
        finalSPBuy = superBuy and self.last_pos != 1
        finalSPSell = superSell and self.last_pos != -1
        finalBuy = normalBuy and not superBuy and self.last_pos != 1
        finalSell = normalSell and not superSell and self.last_pos != -1

        # Update position tracking
        if finalBuy or finalSPBuy:
            self.last_pos = 1
        if finalSell or finalSPSell:
            self.last_pos = -1

        # Safe exit logic
        if (finalBuy or finalSPBuy):
            self.sf_buy_triggered = False
        if (finalSell or finalSPSell):
            self.sf_sell_triggered = False

        exitWave = self.f3[-1]
        sfBuySignal = (self.last_pos == 1 and isOverbought and
                       (close < exitWave or trendWeakeningUp) and not self.sf_buy_triggered)
        sfSellSignal = (self.last_pos == -1 and isOversold and
                        (close > exitWave or not trendWeakeningUp) and not self.sf_sell_triggered)

        if sfBuySignal:
            self.sf_buy_triggered = True
        if sfSellSignal:
            self.sf_sell_triggered = True

        # Trading logic
        if finalSPBuy or finalBuy:
            if not self.position:
                self.buy()
        elif finalSPSell or finalSell:
            if self.position:
                self.position.close()
        elif sfBuySignal:
            if self.position:
                self.position.close()
        elif sfSellSignal:
            if self.position:
                self.position.close()


