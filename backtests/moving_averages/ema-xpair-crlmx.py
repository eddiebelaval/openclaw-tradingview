import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len1 = 8
    len2 = 24
    ref_tf = "Day"

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Map reference timeframe to seconds
        tf_seconds_map = {
            "Chart": 1,
            "1min": 60,
            "2min": 120,
            "3min": 180,
            "5min": 300,
            "10min": 600,
            "15min": 900,
            "30min": 1800,
            "1H": 3600,
            "2H": 7200,
            "4H": 14400,
            "8H": 28800,
            "12H": 43200,
            "Day": 86400,
            "Week": 604800,
            "Month": 2592000,
        }
        
        ref_tf_secs = tf_seconds_map.get(self.ref_tf, 86400)
        chart_tf_secs = 86400
        bars_per_ref = max(1, ref_tf_secs / chart_tf_secs)
        
        eq_len1 = max(2, round(self.len1 * bars_per_ref))
        eq_len2 = max(2, round(self.len2 * bars_per_ref))
        
        self.ema1 = self.I(pta.ema, close, length=int(eq_len1))
        self.ema2 = self.I(pta.ema, close, length=int(eq_len2))

    def next(self):
        if len(self.data) < 2:
            return
        
        if self.ema1[-2] is None or self.ema2[-2] is None:
            return
        if self.ema1[-1] is None or self.ema2[-1] is None:
            return
        
        # Buy signal: EMA1 crosses above EMA2
        if crossover(self.ema1, self.ema2):
            if not self.position:
                self.buy()
        # Sell signal: EMA1 crosses below EMA2
        elif crossover(self.ema2, self.ema1):
            if self.position:
                self.position.close()