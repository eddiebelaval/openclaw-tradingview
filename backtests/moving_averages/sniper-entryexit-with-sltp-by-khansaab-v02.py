        self.macd_signal = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)[f'MACDh_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        
