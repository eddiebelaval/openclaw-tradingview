import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate 200 SMA for current timeframe
        self.ma200 = self.I(pta.sma, close, length=200)
        
    def next(self):
        if len(self.data) < 200:
            return
        
        # Buy when price crosses above 200 MA
        if crossover(self.data.Close, self.ma200):
            self.buy()
        
        # Sell when price crosses below 200 MA
        elif crossover(self.ma200, self.data.Close):
            self.sell()


