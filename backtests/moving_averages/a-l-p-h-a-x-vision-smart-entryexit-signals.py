class TvStrategy(Strategy):
    # Fusion System
    fusionLength = 108
    sens1 = 12
    sens2 = 5
    
    # EMA Settings
    emaFastLength = 21
    emaMediumLength = 55
    emaSlowLength = 120
    
    # AlphaX Pro Settings
    fastWPR_period = 14
    slowWPR_period = 48
    turtleWPR_period = 180
    oversold_level = -90
    overbought_level = -10
    proTrendLookback = 25
    minProConfidence = 35
    enableProTrendGate = True
    proTrendGateStrict = True
    proUptrendTurtleLevel = -35
    proUptrendSlowLevel = -40
    proDowntrendTurtleLevel = -65
    proDowntrendSlowLevel = -60
    enableProRecoveryReq = True
    proRecoveryBars = 3
    proRecoveryMinMove = 6
    
    # Trend Filters
    trendCooldown = 25

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # EMAs
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLength)
        self.emaMedium = self.I(pta.ema, close, length=self.emaMediumLength)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLength)
        
        # Fusion System
        emaVal = self.I(pta.ema, close, length=self.fusionLength)
        smaVal = self.I(pta.sma, close, length=self.fusionLength)
        wmaVal = self.I(pta.wma, close, length=self.fusionLength)
        almaVal = self.I(pta.alma, close, length=self.fusionLength, offset=0.85, sigma=6.0)
        vwapVal = self.I(pta.vwap, high, low, close)
        
        # Raw fusion average
        def calc_raw_fusion():
            df = pd.DataFrame({
                'ema': emaVal,
                'sma': smaVal,
                'wma': wmaVal,
                'alma': almaVal,
                'vwap': vwapVal
            })
            return df.mean(axis=1)
        
        rawFusion = self.I(calc_raw_fusion)
        self.fusionSlow = self.I(pta.ema, rawFusion, length=self.sens1)
        self.fusionFast = self.I(pta.ema, rawFusion, length=self.sens2)
        
        # RSI and related
        self.rsiVal = self.I(pta.rsi, close, length=14)
        self.rsiEma = self.I(pta.ema, self.rsiVal, length=7)
        
        # MACD
        macdResult = self.I(pta.macd, close, fast=12, slow=26, signal=9)
        self.macdLine = macdResult.iloc[:, 0] if isinstance(macdResult, pd.DataFrame) else macdResult
        self.signalLine = macdResult.iloc[:, 1] if isinstance(macdResult, pd.DataFrame) else pd.Series(0, index=close.index)
        self.histLine = macdResult.iloc[:, 2] if isinstance(macdResult, pd.DataFrame) else pd.Series(0, index=close.index)
        
        # Stochastic
        stochResult = self.I(pta.stoch, high, low, close, k=14, d=3, smooth_k=3)
        self.stochK = stochResult.iloc[:, 0] if isinstance(stochResult, pd.DataFrame) else stochResult
        self.stochD = stochResult.iloc[:, 1] if isinstance(stochResult, pd.DataFrame) else pd.Series(50, index=close.index)
        
        # WPR (Williams %R)
        self.fastWPR = self.I(pta.willr, high, low, close, length=self.fastWPR_period)
        self.slowWPR = self.I(pta.willr, high, low, close, length=self.slowWPR_period)
        self.turtleWPR = self.I(pta.willr, high, low, close, length=self.turtleWPR_period)
        
        # Additional indicators
        self.proRsi = self.I(pta.rsi, close, length=14)
        self.proEma200 = self.I(pta.ema, close, length=200)
        self.proEma50 = self.I(pta.ema, close, length=50)
        self.avgVolume = self.I(pta.sma, volume, length=20)
        
        # ATR for reference
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # State tracking
        self.currentTrend = 0
        self.hasEntrySignal = False
        self.lastTrendBar = -999
        self.lastTrendDirection = 0
        
    def next(self):
        if len(self.data) < 200:
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        fusionSlow = self.fusionSlow[-1]
        fusionFast = self.fusionFast[-1]
        
        # Trend detection
        bullishCondition = close > fusionSlow and self.fusionSlow[-1] > self.fusionSlow[-2]
        bearishCondition = close < fusionSlow and self.fusionSlow[-1] < self.fusionSlow[-2]
        
        # Trend changes
        wasBullish = len(self.fusionSlow) > 1 and self.data.Close[-2] > self.fusionSlow[-2] and self.fusionSlow[-2] > self.fusionSlow[-3] if len(self.fusionSlow) > 2 else False
        wasBearish = len(self.fusionSlow) > 1 and self.data.Close[-2] < self.fusionSlow[-2] and self.fusionSlow[-2] < self.fusionSlow[-3] if len(self.fusionSlow) > 2 else False
        wasNeutral = not wasBullish and not wasBearish
        
        colorChangedToGreen = bullishCondition and (wasBearish or wasNeutral)
        colorChangedToPurple = bearishCondition and (wasBullish or wasNeutral)
        
        # Cooldown logic
        bullCooldownOK = (self.lastTrendDirection != 1) or ((len(self.data) - self.lastTrendBar) >= self.trendCooldown)
        bearCooldownOK = (self.lastTrendDirection != -1) or ((len(self.data) - self.lastTrendBar) >= self.trendCooldown)
        
        fusionBullSignal = colorChangedToGreen and bullCooldownOK
        fusionBearSignal = colorChangedToPurple and bearCooldownOK
        
        if fusionBullSignal:
            self.lastTrendBar = len(self.data)
            self.lastTrendDirection = 1
            self.currentTrend = 1
            self.hasEntrySignal = False
        
        if fusionBearSignal:
            self.lastTrendBar = len(self.data)
            self.lastTrendDirection = -1
            self.currentTrend = -1
            self.hasEntrySignal = False
        
        # Pro confidence calculations
        proBuyConfidence = self._calc_buy_confidence()
        proSellConfidence = self._calc_sell_confidence()
        
        # WPR signal checks
        proFastCrossesUp = crossover(self.fastWPR, self.oversold_level)
        proFastCrossesDown = crossover(self.overbought_level, self.fastWPR)
        
        # Basic signal generation
        proAnyBuySignal = proFastCrossesUp and self.fastWPR[-1] < -80 and self.slowWPR[-1] < -70
        proAnySellSignal = proFastCrossesDown and self.fastWPR[-1] > -20 and self.slowWPR[-1] > -30
        
        proValidBuySignal = proAnyBuySignal and proBuyConfidence >= self.minProConfidence
        proValidSellSignal = proAnySellSignal and proSellConfidence >= self.minProConfidence
        
        # Trend gate logic
        proTrendGateBullPass = True
        proTrendGateBearPass = True
        
        if self.enableProTrendGate:
            proStrongDowntrendDetected = (self.turtleWPR[-1] < self.proDowntrendTurtleLevel and 
                                         self.slowWPR[-1] < self.proDowntrendSlowLevel)
            proStrongUptrendDetected = (self.turtleWPR[-1] > self.proUptrendTurtleLevel and 
                                       self.slowWPR[-1] > self.proUptrendSlowLevel)
            
            if proStrongDowntrendDetected:
                proTrendGateBullPass = False
            if proStrongUptrendDetected:
                proTrendGateBearPass = False
        
        proGatedBuySignal = proValidBuySignal and proTrendGateBullPass
        proGatedSellSignal = proValidSellSignal and proTrendGateBearPass
        
        # Entry/Exit logic
        doBullEntry = self.currentTrend == 1 and proGatedBuySignal
        doBearEntry = self.currentTrend == -1 and proGatedSellSignal
        doBullExit = self.currentTrend == 1 and proGatedSellSignal and self.hasEntrySignal
        doBearExit = self.currentTrend == -1 and proGatedBuySignal and self.hasEntrySignal
        
        if doBullEntry or doBearEntry:
            self.hasEntrySignal = True
        
        # Execute trades
        if doBullEntry and not self.position:
            self.buy()
        elif doBullExit and self.position:
            self.position.close()
        
        if doBearEntry and not self.position:
            self.sell()
        elif doBearExit and self.position:
            self.position.close()
    
