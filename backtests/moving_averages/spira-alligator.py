import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        hl2 = (high + low) / 2
        
        # Calculate all moving averages using RMA (SMMA equivalent)
        self.lips_raw = self.I(lambda: pta.rma(hl2, length=5) or pd.Series(0, index=close.index))
        self.teeth_raw = self.I(lambda: pta.rma(hl2, length=8) or pd.Series(0, index=close.index))
        self.jaw_raw = self.I(lambda: pta.rma(hl2, length=13) or pd.Series(0, index=close.index))
        self.trend_ma = self.I(lambda: pta.ema(close, length=144) or pd.Series(0, index=close.index))
        
        self.bear_pullback_seen = False
        self.bull_pullback_seen = False

    def next(self):
        if len(self.data) < 2:
            return
        
        lips_current = self.lips_raw[-1]
        lips_prev = self.lips_raw[-2]
        teeth_current = self.teeth_raw[-1]
        teeth_prev = self.teeth_raw[-2]
        close_current = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        trend_current = self.trend_ma[-1]
        
        # Detect crosses
        lips_cross_up = (lips_current > teeth_current) and (lips_prev <= teeth_prev)
        lips_cross_down = (lips_current < teeth_current) and (lips_prev >= teeth_prev)
        
        # Bear pullback logic
        if lips_cross_up and close_current < trend_current:
            self.bear_pullback_seen = True
        
        if close_current > trend_current:
            self.bear_pullback_seen = False
        
        # Bull pullback logic
        if lips_cross_down and close_current > trend_current:
            self.bull_pullback_seen = True
        
        if close_current < trend_current:
            self.bull_pullback_seen = False
        
        # Generate signals
        sell_signal = self.bear_pullback_seen and lips_cross_down and close_current < trend_current
        buy_signal = self.bull_pullback_seen and lips_cross_up and close_current > trend_current
        
        # Execute trades
        if sell_signal:
            if self.position:
                self.position.close()
            self.bear_pullback_seen = False
        
        if buy_signal:
            if self.position:
                self.position.close()
            self.buy()
            self.bull_pullback_seen = False


