import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Signal: Vervoort Stop
    vPeriod = 100
    vMultiplier = 0.5
    
    # Baseline: Kalman Filter
    kalmanAlpha = 0.01
    kalmanBeta = 0.1
    kalmanPeriod = 100
    
    # Bands: Original J-Trend
    dev_inner = 1.2
    dev_outer = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # Calculate xClose (hl2 equivalent)
        xclose = (open_ + high + low + close) / 4.0
        
        # Vervoort ATR
        atr = self.I(pta.atr, high, low, close, length=self.vPeriod)
        
        # Calculate Vervoort Stop signal line
        def calc_vervoort_stop():
            loss = self.vMultiplier * atr
            v_stop = np.full(len(close), np.nan)
            trend_is_up = True
            
            for i in range(len(close)):
                if i == 0:
                    v_stop[i] = close.iloc[i] - loss.iloc[i] if not np.isnan(loss.iloc[i]) else close.iloc[i]
                    trend_is_up = True
                else:
                    if np.isnan(loss.iloc[i]):
                        v_stop[i] = v_stop[i-1]
                        continue
                    
                    prev_v_stop = v_stop[i-1]
                    trend_is_up = close.iloc[i] > prev_v_stop
                    
                    if trend_is_up:
                        v_stop[i] = max(prev_v_stop, xclose.iloc[i] - loss.iloc[i])
                    else:
                        v_stop[i] = min(prev_v_stop, xclose.iloc[i] + loss.iloc[i])
                    
                    if trend_is_up and close.iloc[i] < v_stop[i]:
                        trend_is_up = False
                        v_stop[i] = xclose.iloc[i] + loss.iloc[i]
                    elif not trend_is_up and close.iloc[i] > v_stop[i]:
                        trend_is_up = True
                        v_stop[i] = xclose.iloc[i] - loss.iloc[i]
            
            return pd.Series(v_stop, index=close.index)
        
        self.signal_line = self.I(calc_vervoort_stop)
        
        # Kalman Filter baseline
        def calc_kalman_filter():
            v1 = np.full(len(close), np.nan)
            v2 = np.full(len(close), np.nan)
            
            v1[0] = close.iloc[0]
            v2[0] = 1.0
            
            for i in range(1, len(close)):
                v3 = self.kalmanAlpha * self.kalmanPeriod
                v4 = v2[i-1] / (v2[i-1] + v3)
                v1[i] = v1[i-1] + v4 * (close.iloc[i] - v1[i-1])
                v2[i] = (1 - v4) * v2[i-1] + self.kalmanBeta / self.kalmanPeriod
            
            return pd.Series(v1, index=close.index)
        
        self.baseline = self.I(calc_kalman_filter)
        
        # Volatility WMA
        hl_diff = high - low
        vola_wma = self.I(pta.wma, hl_diff, length=200)
        
        # Calculate bands
        def calc_upper_inner():
            return self.baseline + vola_wma * self.dev_inner
        
        def calc_lower_inner():
            return self.baseline - vola_wma * self.dev_inner
        
        self.upper_inner = self.I(calc_upper_inner)
        self.lower_inner = self.I(calc_lower_inner)

    def next(self):
        # Buy when signal_line crosses above baseline
        if crossover(self.signal_line, self.baseline):
            self.buy()
        # Sell when signal_line crosses below baseline
        elif crossover(self.baseline, self.signal_line):
            self.sell()


