import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    basisLen = 21
    slowLen = 50
    swing_length = 50
    atr_mult = 2.0
    num_targets = 3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.emaFast = self.I(pta.ema, close, length=self.basisLen)
        self.emaSlow = self.I(pta.ema, close, length=self.slowLen)
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        self.in_trade = False
        self.entry_price = 0
        self.stop_loss = 0
        self.targets = []
        self.is_long = False

    def next(self):
        if len(self.data) < self.swing_length + 1:
            return
        
        if np.isnan(self.emaFast[-1]) or np.isnan(self.emaSlow[-1]) or np.isnan(self.atr[-1]):
            return
        
        buy_sig = crossover(self.emaFast, self.emaSlow)
        sell_sig = crossover(self.emaSlow, self.emaFast)
        
        if buy_sig and not self.in_trade:
            self.entry_price = self.data.Close[-1]
            self.stop_loss = self.entry_price - (self.atr[-1] * self.atr_mult)
            self.targets = [
                self.entry_price + (self.atr[-1] * self.atr_mult * i)
                for i in range(1, self.num_targets + 1)
            ]
            self.is_long = True
            self.in_trade = True
            self.buy()
        
        elif sell_sig and not self.in_trade:
            self.entry_price = self.data.Close[-1]
            self.stop_loss = self.entry_price + (self.atr[-1] * self.atr_mult)
            self.targets = [
                self.entry_price - (self.atr[-1] * self.atr_mult * i)
                for i in range(1, self.num_targets + 1)
            ]
            self.is_long = False
            self.in_trade = True
            self.sell()
        
        if self.in_trade:
            current_price = self.data.Close[-1]
            
            if self.is_long:
                if current_price <= self.stop_loss:
                    self.position.close()
                    self.in_trade = False
                    return
                
                for target in self.targets:
                    if current_price >= target:
                        self.position.close()
                        self.in_trade = False
                        return
            
            else:
                if current_price >= self.stop_loss:
                    self.position.close()
                    self.in_trade = False
                    return
                
                for target in self.targets:
                    if current_price <= target:
                        self.position.close()
                        self.in_trade = False
                        return


