import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Preset: "Daily – Stable (34/55 EMA)"
    len1 = 34
    len2 = 55
    type1 = "EMA"
    type2 = "EMA"
    smoothe = 2
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate MA1
        if self.type1 == "SMA":
            self.ma1 = self.I(pta.sma, close, length=self.len1)
        elif self.type1 == "EMA":
            self.ma1 = self.I(pta.ema, close, length=self.len1)
        elif self.type1 == "WMA":
            self.ma1 = self.I(pta.wma, close, length=self.len1)
        elif self.type1 == "HMA":
            self.ma1 = self.I(pta.hma, close, length=self.len1)
        elif self.type1 == "VWMA":
            self.ma1 = self.I(pta.vwma, close, volume, length=self.len1)
        elif self.type1 == "RMA":
            self.ma1 = self.I(pta.rma, close, length=self.len1)
        else:  # TEMA
            self.ma1 = self.I(self._tema, close, self.len1)
        
        # Calculate MA2
        if self.type2 == "SMA":
            self.ma2 = self.I(pta.sma, close, length=self.len2)
        elif self.type2 == "EMA":
            self.ma2 = self.I(pta.ema, close, length=self.len2)
        elif self.type2 == "WMA":
            self.ma2 = self.I(pta.wma, close, length=self.len2)
        elif self.type2 == "HMA":
            self.ma2 = self.I(pta.hma, close, length=self.len2)
        elif self.type2 == "VWMA":
            self.ma2 = self.I(pta.vwma, close, volume, length=self.len2)
        elif self.type2 == "RMA":
            self.ma2 = self.I(pta.rma, close, length=self.len2)
        else:  # TEMA
            self.ma2 = self.I(self._tema, close, self.len2)
    
    def _tema(self, src, length):
        """Triple Exponential Moving Average"""
        l = max(1, length)
        e1 = pta.ema(src, length=l)
        e2 = pta.ema(e1, length=l)
        e3 = pta.ema(e2, length=l)
        return 3 * (e1 - e2) + e3
    
    def next(self):
        # Buy when MA1 crosses above MA2
        if len(self.ma1) > self.smoothe and len(self.ma2) > self.smoothe:
            if crossover(self.ma1, self.ma2):
                if not self.position:
                    self.buy()
            # Sell when MA1 crosses below MA2
            elif crossover(self.ma2, self.ma1):
                if self.position:
                    self.position.close()