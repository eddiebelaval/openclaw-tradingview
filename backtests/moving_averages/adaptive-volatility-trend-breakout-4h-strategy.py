import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_length = 30
    lookback = 100
    multiplier = 3.3

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMA
        self.base_ma = self.I(pta.ema, close, length=self.ma_length)
        
        # Calculate price change percentage
        def calc_price_change_pct(close_series):
            pct_change = np.abs(close_series.diff()) / close_series.shift(1)
            return pct_change
        
        self.price_change_pct = self.I(calc_price_change_pct, close)
        
        # Calculate standard deviation of price change percentage
        def calc_stddev_pct(close_series):
            pct_change = np.abs(close_series.diff()) / close_series.shift(1)
            return pct_change.rolling(window=self.lookback).std()
        
        self.stddev_pct = self.I(calc_stddev_pct, close)
        
        # Calculate dynamic percentage
        def calc_dynamic_pct(close_series):
            pct_change = np.abs(close_series.diff()) / close_series.shift(1)
            stddev = pct_change.rolling(window=self.lookback).std()
            return stddev * self.multiplier
        
        self.dynamic_pct = self.I(calc_dynamic_pct, close)
        
        # Calculate bands
        def calc_upper_band(close_series):
            ema = pta.ema(close_series, length=self.ma_length)
            pct_change = np.abs(close_series.diff()) / close_series.shift(1)
            stddev = pct_change.rolling(window=self.lookback).std()
            dynamic_pct = stddev * self.multiplier
            return ema * (1 + dynamic_pct)
        
        def calc_lower_band(close_series):
            ema = pta.ema(close_series, length=self.ma_length)
            pct_change = np.abs(close_series.diff()) / close_series.shift(1)
            stddev = pct_change.rolling(window=self.lookback).std()
            dynamic_pct = stddev * self.multiplier
            return ema * (1 - dynamic_pct)
        
        self.upper_band = self.I(calc_upper_band, close)
        self.lower_band = self.I(calc_lower_band, close)
        
        self.trend_state = 0

    def next(self):
        close = self.data.Close[-1]
        upper = self.upper_band[-1]
        lower = self.lower_band[-1]
        
        if upper is None or lower is None or np.isnan(upper) or np.isnan(lower):
            return
        
        # Check for long condition
        long_condition = crossover(self.data.Close, self.upper_band) and self.trend_state <= 0
        
        # Check for short condition
        short_condition = crossover(self.lower_band, self.data.Close) and self.trend_state >= 0
        
        if long_condition:
            self.trend_state = 1
            if not self.position:
                self.buy()
        
        if short_condition:
            self.trend_state = -1
            if self.position:
                self.position.close()
            self.sell()


