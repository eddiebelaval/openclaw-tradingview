import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA lengths - using Fibonacci Trio preset as default
    ema1_length = 8
    ema2_length = 13
    ema3_length = 21

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema1 = self.I(pta.ema, close, length=self.ema1_length)
        self.ema2 = self.I(pta.ema, close, length=self.ema2_length)
        self.ema3 = self.I(pta.ema, close, length=self.ema3_length)
        
        # Previous candle range metrics
        prev_len = 14
        
        # Previous candle range (high[1] - low[1])
        self.prev_range = self.I(lambda: pd.Series([
            max(0, self.data.High[i-1] - self.data.Low[i-1]) if i > 0 else 0
            for i in range(len(self.data.Close))
        ]))
        
        # Average range
        self.avg_range = self.I(lambda: pta.sma(
            pd.Series([max(0, self.data.High[i-1] - self.data.Low[i-1]) if i > 0 else 0
                      for i in range(len(self.data.Close))]), 
            length=prev_len
        ) or pd.Series(0, index=close.index))
        
        # Highest high and lowest low within prev_len period
        self.highest_high = self.I(lambda: pd.Series(
            [high.iloc[max(0, i-prev_len+1):i+1].max() for i in range(len(high))]
        ))
        self.lowest_low = self.I(lambda: pd.Series(
            [low.iloc[max(0, i-prev_len+1):i+1].min() for i in range(len(low))]
        ))
        self.range_hl = self.I(lambda: self.highest_high - self.lowest_low)

    def next(self):
        # Trading logic based on EMA cross strategy
        # Buy when EMA1 (fast) crosses above EMA2 (medium) and price is above EMA3 (slow)
        if len(self.data) < max(self.ema1_length, self.ema2_length, self.ema3_length) + 1:
            return
        
        ema1_val = self.ema1[-1]
        ema2_val = self.ema2[-1]
        ema3_val = self.ema3[-1]
        close_val = self.data.Close[-1]
        
        if np.isnan(ema1_val) or np.isnan(ema2_val) or np.isnan(ema3_val):
            return
        
        # Buy signal: EMA1 crosses above EMA2, and price is above EMA3 (uptrend)
        if crossover(self.ema1, self.ema2) and close_val > ema3_val:
            if not self.position:
                self.buy()
        
        # Sell signal: EMA1 crosses below EMA2 (downtrend)
        elif crossover(self.ema2, self.ema1):
            if self.position:
                self.position.close()
        
        # Additional exit: Price falls below EMA3 (strong downtrend)
        elif close_val < ema3_val and self.position:
            self.position.close()


