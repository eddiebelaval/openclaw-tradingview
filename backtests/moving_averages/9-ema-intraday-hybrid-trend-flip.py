import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate 9 EMA on current timeframe (assumed to be intraday/3m)
        self.ema_15m = self.I(pta.ema, close, length=9)
        
        # For daily and hourly EMAs, we'll use the close price as proxy
        # In a real scenario with multi-timeframe data, these would come from different timeframes
        self.ema_d = self.I(pta.ema, close, length=9)
        self.ema_h = self.I(pta.ema, close, length=9)
        
        # Calculate highest high and lowest low over 2 candles
        self.hi = self.I(lambda: high.rolling(2).max())
        self.lo = self.I(lambda: low.rolling(2).min())
        
        # Track bars since close crossed EMA for counter-trend logic
        self.bars_since_cross = 0

    def next(self):
        if len(self.data) < 2:
            return
        
        close_current = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        high_current = self.data.High[-1]
        low_current = self.data.Low[-1]
        
        # Get EMA values
        ema_15m = self.ema_15m[-1] if self.ema_15m[-1] is not None else close_current
        ema_d = self.ema_d[-1] if self.ema_d[-1] is not None else close_current
        ema_h = self.ema_h[-1] if self.ema_h[-1] is not None else close_current
        
        # Get Fibonacci levels
        hi = self.hi[-1] if self.hi[-1] is not None else high_current
        lo = self.lo[-1] if self.lo[-1] is not None else low_current
        fib_range = hi - lo
        
        fib_exit_long = lo + (fib_range * 0.382)
        fib_exit_short = hi - (fib_range * 0.382)
        
        # Counter-trend logic: count bars since close crossed EMA
        if close_current < ema_15m:
            self.bars_since_cross += 1
        else:
            self.bars_since_cross = 0
        
        count_15m_bull = self.bars_since_cross >= 2
        
        if close_current > ema_15m:
            self.bars_since_cross = 0
        else:
            self.bars_since_cross += 1
        
        count_15m_bear = self.bars_since_cross >= 2
        
        # 3-minute confirm conditions
        three_min_confirm_bull = close_current > close_prev and close_current > ema_15m
        three_min_confirm_bear = close_current < close_prev and close_current < ema_15m
        
        # Full trend alignment
        full_trend_long = close_current > ema_d and close_current > ema_h and close_current > ema_15m
        full_trend_short = close_current < ema_d and close_current < ema_h and close_current < ema_15m
        
        # Reversal override
        reversal_long = count_15m_bull and three_min_confirm_bull
        reversal_short = count_15m_bear and three_min_confirm_bear
        
        long_condition = full_trend_long or reversal_long
        short_condition = full_trend_short or reversal_short
        
        # Entry logic
        if long_condition and not self.position:
            self.buy()
        elif short_condition and not self.position:
            self.sell()
        
        # Exit logic
        if self.position and self.position.is_long and close_current < fib_exit_long:
            self.position.close()
        
