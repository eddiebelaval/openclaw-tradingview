import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fast_length = 8
    slow_length = 21
    min_bar_index = 50

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMA for fast DEMA
        ema1_fast = self.I(pta.ema, close, length=self.fast_length)
        ema2_fast = self.I(lambda: pta.ema(ema1_fast, length=self.fast_length) if ema1_fast is not None else pd.Series(np.nan, index=close.index))
        
        # Calculate DEMA fast: 2 * EMA1 - EMA2
        self.dema_fast = self.I(lambda: 2 * ema1_fast - ema2_fast)
        
        # Calculate EMA for slow DEMA
        ema1_slow = self.I(pta.ema, close, length=self.slow_length)
        ema2_slow = self.I(lambda: pta.ema(ema1_slow, length=self.slow_length) if ema1_slow is not None else pd.Series(np.nan, index=close.index))
        
        # Calculate DEMA slow: 2 * EMA1 - EMA2
        self.dema_slow = self.I(lambda: 2 * ema1_slow - ema2_slow)

    def next(self):
        # Skip signals during warmup period
        if len(self.data) < self.min_bar_index:
            return
        
        # Check if we have valid indicator values
        if np.isnan(self.dema_fast[-1]) or np.isnan(self.dema_slow[-1]):
            return
        
        # Detect crossover: fast DEMA crosses above slow DEMA
        if crossover(self.dema_fast, self.dema_slow):
            if not self.position:
                self.buy()
        
        # Detect crossunder: fast DEMA crosses below slow DEMA
        elif crossover(self.dema_slow, self.dema_fast):
            if self.position:
                self.position.close()


