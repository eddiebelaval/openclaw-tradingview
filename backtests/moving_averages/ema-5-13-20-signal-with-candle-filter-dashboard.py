import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema5 = self.I(pta.ema, close, length=5)
        self.ema13 = self.I(pta.ema, close, length=13)
        self.ema20 = self.I(pta.ema, close, length=20)
        
        # Calculate candle metrics
        def get_body():
            return np.abs(close - open_)
        
        def get_candle_range():
            return high - low
        
        def get_upper_wick():
            return high - np.maximum(close, open_)
        
        def get_lower_wick():
            return np.minimum(close, open_) - low
        
        def get_body_percent():
            body = np.abs(close - open_)
            candle_range = high - low
            return np.where(candle_range > 0, body / candle_range, 0)
        
        self.body = self.I(get_body)
        self.candle_range = self.I(get_candle_range)
        self.upper_wick = self.I(get_upper_wick)
        self.lower_wick = self.I(get_lower_wick)
        self.body_percent = self.I(get_body_percent)
    
    def next(self):
        # Current values
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        ema5 = self.ema5[-1]
        ema13 = self.ema13[-1]
        ema20 = self.ema20[-1]
        
        body = self.body[-1]
        candle_range = self.candle_range[-1]
        upper_wick = self.upper_wick[-1]
        lower_wick = self.lower_wick[-1]
        body_percent = self.body_percent[-1]
        
        # Candle filters
        strong_body = body_percent > 0.5
        doji = body_percent < 0.2
        
        # Pin bars
        bull_pin = lower_wick > body * 2 and upper_wick < body
        bear_pin = upper_wick > body * 2 and lower_wick < body
        
        # Cross conditions
        cross_up = crossover(self.ema5, self.ema13)
        cross_down = crossover(self.ema13, self.ema5)
        
        # Buy condition
        buy_condition = (
            cross_up and
            close > ema20 and
            strong_body and
            not doji and
            not bear_pin
        )
        
        # Sell condition
        sell_condition = (
            cross_down and
            close < ema20 and
            strong_body and
            not doji and
            not bull_pin
        )
        
        # Execute trades
        if buy_condition:
            self.buy()
        elif sell_condition:
            self.sell()


