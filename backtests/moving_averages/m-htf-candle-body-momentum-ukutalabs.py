import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    period = 21

    def init(self):
        close = pd.Series(self.data.Close)
        open_prices = pd.Series(self.data.Open)
        
        # Calculate EMA for close and open
        self.ema_close = self.I(pta.ema, close, length=self.period)
        self.ema_open = self.I(pta.ema, open_prices, length=self.period)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Determine current momentum direction
        # Bullish when EMA close is above EMA open
        current_bullish = self.ema_close[-1] > self.ema_open[-1]
        previous_bullish = self.ema_close[-2] > self.ema_open[-2]
        
        # Buy when momentum turns bullish (EMA close crosses above EMA open)
        if current_bullish and not previous_bullish:
            if not self.position:
                self.buy()
        
        # Sell when momentum turns bearish (EMA close crosses below EMA open)
        elif not current_bullish and previous_bullish:
            if self.position:
                self.sell()


