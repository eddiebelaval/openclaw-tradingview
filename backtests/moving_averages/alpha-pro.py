class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        hlc3 = (high + low + close) / 3
        
        # Calculate stdev_high and stdev_low using rolling calculations
        mid_oc = (close.shift(1) + open_) / 2
        stdev_high_calc = (mid_oc - high).abs() / high.replace(0, 1) * 100
        stdev_low_calc = (mid_oc - low).abs() / low.replace(0, 1) * 100
        
        self.stdev_high = self.I(lambda: pta.stdev(stdev_high_calc, length=63) or pd.Series(0, index=close.index))
        self.stdev_low = self.I(lambda: pta.stdev(stdev_low_calc, length=63) or pd.Series(0, index=close.index))
        
        # Calculate stdev_daily
        mid_oc_prev = (close.shift(1) + open_.shift(1)) / 2
        stdev_daily_calc = ((mid_oc - mid_oc_prev).abs() / mid_oc_prev.replace(0, 1) * 100)
        self.stdev_daily = self.I(lambda: pta.stdev(stdev_daily_calc, length=126) or pd.Series(0, index=close.index))
        
        # RSI GARCH(1,1)-HAR calculation
        self.rsi = self.I(self._calculate_rsi, close, high, low)
        
        # Dynamic HMA calculation
        self.ma_hull = self.I(self._calculate_hma, hlc3)
        
        # Candle patterns
        self.bull = close > open_
        self.bear = close < open_
        self.body_var = (close - open_).abs() / open_.replace(0, 1) * 100
        
        self.high_var_bull = (high / close.replace(0, 1) - 1) * 100
        self.low_var_bull = (open_ / low.replace(0, 1) - 1) * 100
        self.high_var_bear = (high / open_.replace(0, 1) - 1) * 100
        self.low_var_bear = (close / low.replace(0, 1) - 1) * 100

    def _calculate_rsi(self, close, high, low):
        """Calculate adaptive RSI with GARCH(1,1) and HAR"""
        rsi_values = np.full(len(close), np.nan)
        
        stdev_high_calc = (close.shift(1) + close.shift(0)) / 2
        stdev_low_calc = (close.shift(1) + close.shift(0)) / 2
        
        stdev_high = pd.Series(np.full(len(close), 0.5))
        stdev_low = pd.Series(np.full(len(close), 0.5))
        stdev_daily = pd.Series(np.full(len(close), 0.5))
        
        stdev_min = stdev_high.combine(stdev_low, min)
        stdev_max = stdev_high.combine(stdev_low, max)
        
        rma_up_d = np.full(len(close), 0.5)
        rma_dn_d = np.full(len(close), 0.5)
        rma_up_w = np.full(len(close), 0.5)
        rma_dn_w = np.full(len(close), 0.5)
        rma_up_m = np.full(len(close), 0.5)
        rma_dn_m = np.full(len(close), 0.5)
        
        sig2 = np.full(len(close), 1e-5)
        a_s, b_s = 0.10, 0.85
        
        for i in range(100, len(close)):
            eps = close.iloc[i] - close.iloc[i-1]
            sig2[i] = max(0.000002 + a_s * eps**2 + b_s * sig2[i-1], 1e-12)
            
            scale_t = np.sqrt(3.0 / 5.0)
            z_t = (eps / np.sqrt(sig2[i])) * scale_t if np.sqrt(sig2[i]) > 0 else 0
            
            up_z = max(z_t, 0.0)
            dn_z = max(-z_t, 0.0)
            
            rsi_n = max(2, min(200, int(10)))
            
            ad = 1.0 / rsi_n
            rma_up_d[i] = ad * up_z + (1.0 - ad) * rma_up_d[i-1]
            rma_dn_d[i] = ad * dn_z + (1.0 - ad) * rma_dn_d[i-1]
            
            nw = max(2, rsi_n * 5)
            aw = 1.0 / nw
            rma_up_w[i] = aw * up_z + (1.0 - aw) * rma_up_w[i-1]
            rma_dn_w[i] = aw * dn_z + (1.0 - aw) * rma_dn_w[i-1]
            
            nm = max(2, rsi_n * 22)
            am = 1.0 / nm
            rma_up_m[i] = am * up_z + (1.0 - am) * rma_up_m[i-1]
            rma_dn_m[i] = am * dn_z + (1.0 - am) * rma_dn_m[i-1]
            
            phi_d, phi_w, phi_m = 0.40, 0.35, 0.25
            up_har = phi_d * rma_up_d[i] + phi_w * rma_up_w[i] + phi_m * rma_up_m[i]
            dn_har = phi_d * rma_dn_d[i] + phi_w * rma_dn_w[i] + phi_m * rma_dn_m[i]
            
            if dn_har == 0:
                rsi_values[i] = 100
            elif up_har == 0:
                rsi_values[i] = 0
            else:
                rsi_values[i] = 100 - (100 / (1 + up_har / dn_har))
        
        return pd.Series(rsi_values)

    def _calculate_hma(self, src):
        """Calculate dynamic HMA with adaptive parameters"""
        hma_values = np.full(len(src), np.nan)
        
        for i in range(1, len(src)):
            if i < 10:
                hma_values[i] = src.iloc[i]
            else:
                length = max(2, min(120, int(10)))
                half_len = max(1, length // 2)
                sqrt_len = max(2, int(np.sqrt(length)))
                
                wma1 = src.iloc[max(0, i-half_len+1):i+1].mean()
                wma2 = src.iloc[max(0, i-length+1):i+1].mean()
                
                raw = 2 * wma1 - wma2
                hma_values[i] = raw
        
        return pd.Series(hma_values)

    def next(self):
        if len(self.data) < 5:
            return
        
        rsi_current = self.rsi[-1] if not np.isnan(self.rsi[-1]) else 50
        ma_hull_current = self.ma_hull[-1] if not np.isnan(self.ma_hull[-1]) else self.data.Close[-1]
        
        bull = self.data.Close[-1] > self.data.Open[-1]
        bear = self.data.Close[-1] < self.data.Open[-1]
        
        # Simple buy signal: RSI below 50 and price above MA
        if bull and rsi_current < 50 and self.data.Close[-1] > ma_hull_current:
            if not self.position:
                self.buy()
        
        # Simple sell signal: RSI above 50 and price below MA
        elif bear and rsi_current > 50 and self.data.Close[-1] < ma_hull_current:
            if self.position:
                self.position.close()


