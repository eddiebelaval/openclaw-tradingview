import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema50_length = 50
    ema2_length = 2
    tp_fixed_points = 350

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema50_high = self.I(pta.ema, high, length=self.ema50_length)
        self.ema50_low = self.I(pta.ema, low, length=self.ema50_length)
        self.ema2 = self.I(pta.ema, close, length=self.ema2_length)
        
        self.market_state = 0
        self.tp_price = None
        self.entry_price = None

    def next(self):
        if len(self.data.Close) < max(self.ema50_length, self.ema2_length):
            return
        
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        ema50_high = self.ema50_high[-1]
        ema50_low = self.ema50_low[-1]
        ema2 = self.ema2[-1]
        
        if ema50_high is None or ema50_low is None or ema2 is None:
            return
        
        pip_value = 0.00000001
        tp_distance = self.tp_fixed_points * pip_value
        
        above_zone = (ema2 > ema50_high) and (close > ema50_high)
        below_zone = (ema2 < ema50_low) and (close < ema50_low)
        
        if above_zone and self.market_state != 1:
            if not self.position:
                self.buy()
            self.market_state = 1
            self.tp_price = close + tp_distance
            self.entry_price = close
        
        elif below_zone and self.market_state != -1:
            if self.position:
                self.position.close()
            self.sell()
            self.market_state = -1
            self.tp_price = close - tp_distance
            self.entry_price = close
        
        if self.market_state == 1 and self.tp_price is not None:
            if high >= self.tp_price:
                if self.position:
                    self.position.close()
                self.tp_price = None
                self.market_state = 0
        
        elif self.market_state == -1 and self.tp_price is not None:
            if low <= self.tp_price:
                if self.position:
                    self.position.close()
                self.tp_price = None
                self.market_state = 0


