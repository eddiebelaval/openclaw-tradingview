import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 5
    smaSlowLen = 20
    trendLen = 200
    confirmBars = 7
    rsiLen = 14
    rsiOB = 70
    rsiOS = 30
    volMultiplier = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Moving Averages
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.smaSlow = self.I(pta.sma, close, length=self.smaSlowLen)
        self.emaTrend = self.I(pta.ema, close, length=self.trendLen)
        
        # RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        # MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macdLine = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACD_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        self.signalLine = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACDsignal_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        
        # Volume
        self.volAvg = self.I(pta.sma, volume, length=20)
        
        # Tracking bars since cross
        self.barsSinceBull = 0
        self.barsSinceBear = 0
        self.lastBullCross = -1000
        self.lastBearCross = -1000

    def next(self):
        # Trend filters
        bullTrend = self.data.Close[-1] > self.emaTrend[-1]
        bearTrend = self.data.Close[-1] < self.emaTrend[-1]
        
        # EMA crosses
        bullCross = crossover(self.emaFast, self.smaSlow)
        bearCross = crossover(self.smaSlow, self.emaFast)
        
        # RSI conditions
        rsiOversold = self.rsi[-1] <= self.rsiOS
        rsiOverbought = self.rsi[-1] >= self.rsiOB
        
        # MACD crosses
        macdBull = crossover(self.macdLine, self.signalLine)
        macdBear = crossover(self.signalLine, self.macdLine)
        
        # Volume spike
        volSpike = self.data.Volume[-1] > self.volAvg[-1] * self.volMultiplier
        
        # Track bars since cross
        currentBar = len(self.data) - 1
        if bullCross:
            self.lastBullCross = currentBar
        if bearCross:
            self.lastBearCross = currentBar
        
        barsSinceBull = currentBar - self.lastBullCross
        barsSinceBear = currentBar - self.lastBearCross
        
        withinBullWindow = barsSinceBull > 0 and barsSinceBull <= self.confirmBars
        withinBearWindow = barsSinceBear > 0 and barsSinceBear <= self.confirmBars
        
        # Signal definitions
        strongBuy = bullTrend and withinBullWindow and (rsiOversold or macdBull)
        strongSell = bearTrend and withinBearWindow and (rsiOverbought or macdBear)
        
        superBuy = bullTrend and withinBullWindow and rsiOversold and macdBull and volSpike
        superSell = bearTrend and withinBearWindow and rsiOverbought and macdBear and volSpike
        
        # Trading logic
        if not self.position:
            if superBuy:
                self.buy()
            elif strongBuy:
                self.buy()
            elif bullCross and bullTrend:
                self.buy()
        else:
            if superSell:
                self.sell()
            elif strongSell:
                self.sell()
            elif bearCross and bearTrend:
                self.sell()