class TvStrategy(Strategy):
    breadth_thresh = 4
    fast_len = 9
    slow_len = 21
    fp_ticks = 10
    imb_ratio = 3.0
    sigma_dev = 2.0
    min_delta = 100
    atrLen = 14
    riskMult = 1.2
    tp1Mult = 1.0
    tp2Mult = 2.0
    signal_cooldown = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Trend EMA
        self.trend_ema = self.I(pta.ema, close, length=20)
        
        # ATR for stop loss calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        # Initialize signal tracking
        self.last_signal_bar = 0
        self.signal_history = []
        
    def next(self):
        if len(self.data) < 20:
            return
        
        current_bar = len(self.data) - 1
        close = self.data.Close[-1]
        trend_ema = self.trend_ema[-1]
        atr = self.atr[-1]
        
        # Simplified breadth logic: simulate score based on price vs EMA
        trend_up = close > trend_ema
        
        # Mock breadth score (in real scenario this would need external data)
        # For backtesting, use price above/below EMA as proxy
        breadth_score = 3 if trend_up else -3
        
        breadth_bull = breadth_score >= self.breadth_thresh
        breadth_bear = breadth_score <= -self.breadth_thresh
        
        # Check cooldown
        cooldown_ok = (current_bar - self.last_signal_bar >= self.signal_cooldown) or self.last_signal_bar == 0
        
        # Entry logic
        if not self.position:
            if breadth_bull and cooldown_ok and trend_up:
                stop_price = close - (atr * self.riskMult)
                tp1_price = close + (atr * self.tp1Mult)
                tp2_price = close + (atr * self.tp2Mult)
                
                self.buy()
