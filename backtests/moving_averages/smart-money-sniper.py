import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # UT Bot parameters
    ut_key = 2.0
    ut_atr_period = 1
    use_ha = False
    
    # LinReg Candles parameters
    signal_length = 7
    use_sma_signal = True
    use_linreg = True
    linreg_length = 11

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Linear Regression for OHLC smoothing
        def linreg_calc(series, length):
            result = pd.Series(index=series.index, dtype=float)
            for i in range(len(series)):
                if i < length - 1:
                    result.iloc[i] = np.nan
                else:
                    x = np.arange(length)
                    y = series.iloc[i-length+1:i+1].values
                    z = np.polyfit(x, y, 1)
                    result.iloc[i] = z[0] * (length - 1) + z[1]
            return result
        
        self.lr_open = self.I(lambda: linreg_calc(open_, self.linreg_length) if self.use_linreg else open_)
        self.lr_high = self.I(lambda: linreg_calc(high, self.linreg_length) if self.use_linreg else high)
        self.lr_low = self.I(lambda: linreg_calc(low, self.linreg_length) if self.use_linreg else low)
        self.lr_close = self.I(lambda: linreg_calc(close, self.linreg_length) if self.use_linreg else close)
        
        # Signal line (SMA or EMA of smoothed close)
        self.lr_signal = self.I(
            lambda: pta.sma(self.lr_close, length=self.signal_length) 
            if self.use_sma_signal 
            else pta.ema(self.lr_close, length=self.signal_length)
        )
        
        # ATR for trailing stop
        self.atr = self.I(pta.atr, high, low, close, length=self.ut_atr_period)
        
        # Source for UT Bot (LinReg close, no Heikin Ashi for backtesting simplicity)
        self.src = self.lr_close
        
        # EMA of source for crossover detection
        self.ut_ema = self.I(pta.ema, self.src, length=1)
        
        # Trailing stop
        self.trail_stop = np.zeros(len(close))
        self.pos = 0
        
        # Track previous values for crossover
        self.prev_src = None
        self.prev_trail = None

    def next(self):
        # Calculate nLoss (ATR-based stop distance)
        if len(self.atr) < len(self.data) or self.atr[-1] is None or np.isnan(self.atr[-1]):
            n_loss = 0
        else:
            n_loss = self.ut_key * self.atr[-1]
        
        # Get current values
        src_val = self.src[-1]
        if np.isnan(src_val) or src_val is None:
            return
        
        # Initialize trail_stop on first valid bar
        if len(self) == 1 or np.isnan(self.trail_stop[-1]):
            self.trail_stop[-1] = src_val - n_loss
            self.prev_src = src_val
            self.prev_trail = self.trail_stop[-1]
            return
        
        # Get previous stop
        prev_stop = self.trail_stop[-1]
        
        # Trailing stop logic (UT Bot)
        if src_val > prev_stop and self.prev_src > prev_stop:
            new_stop = max(prev_stop, src_val - n_loss)
        elif src_val < prev_stop and self.prev_src < prev_stop:
            new_stop = min(prev_stop, src_val + n_loss)
        elif src_val > prev_stop:
            new_stop = src_val - n_loss
        else:
            new_stop = src_val + n_loss
        
        self.trail_stop[-1] = new_stop
        
        # Position tracking
        if self.prev_src < prev_stop and src_val > new_stop:
            self.pos = 1
        elif self.prev_src > prev_stop and src_val < new_stop:
            self.pos = -1
        
        # LinReg candle direction
        lr_close_val = self.lr_close[-1]
        lr_open_val = self.lr_open[-1]
        lr_bullish = lr_close_val > lr_open_val
        lr_bearish = lr_close_val < lr_open_val
        
        # Position relative to trailing stop
        above_stop = src_val > new_stop
        below_stop = src_val < new_stop
        
        # Crossover signals
        ut_above = crossover(self.ut_ema, pd.Series([new_stop] * len(self.ut_ema)))
        ut_below = crossover(pd.Series([new_stop] * len(self.ut_ema)), self.ut_ema)
        
        # Combined signals
        buy_signal = above_stop and ut_above and lr_bullish
        sell_signal = below_stop and ut_below and lr_bearish
        
        # Execute trades
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()
        
        # Update previous values
        self.prev_src = src_val
        self.prev_trail = new_stop


