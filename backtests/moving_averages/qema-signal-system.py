import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # QEMA parameters
    qema_len = 170
    
    # ADX parameters
    adx_len = 14
    adx_smooth = 14
    adx_threshold = 20
    adx_strong = 45
    require_adx = True
    
    # Volume parameters
    vol_avg_len = 20
    vol_threshold = 0.8
    require_vol = True
    
    # ATR parameters
    atr_len = 14
    atr_sl_mult = 1.0
    atr_tp1_mult = 2.0
    atr_tp2_mult = 2.5
    
    # Session parameters
    use_session = False
    cooldown_bars = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)
        
        # QEMA calculation: 4×EMA¹ − 6×EMA² + 4×EMA³ − EMA⁴
        def calc_qema():
            ema1 = pta.ema(close, length=self.qema_len)
            if ema1 is None:
                return pd.Series(close.iloc[0], index=close.index)
            ema2 = pta.ema(ema1, length=self.qema_len)
            if ema2 is None:
                return pd.Series(close.iloc[0], index=close.index)
            ema3 = pta.ema(ema2, length=self.qema_len)
            if ema3 is None:
                return pd.Series(close.iloc[0], index=close.index)
            ema4 = pta.ema(ema3, length=self.qema_len)
            if ema4 is None:
                return pd.Series(close.iloc[0], index=close.index)
            return 4 * ema1 - 6 * ema2 + 4 * ema3 - ema4
        
        self.qema = self.I(calc_qema)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # ADX calculation
        def calc_adx():
            adx_result = pta.adx(high, low, close, length=self.adx_len)
            if adx_result is not None and 'ADX_14' in adx_result.columns:
                return adx_result['ADX_14']
            return pd.Series(25, index=close.index)
        
        self.adx = self.I(calc_adx)
        
        # DI+ and DI- for bullish/bearish confirmation
        def calc_di():
            adx_result = pta.adx(high, low, close, length=self.adx_len)
            if adx_result is not None:
                if 'DMP_14' in adx_result.columns and 'DMN_14' in adx_result.columns:
                    di_plus = adx_result['DMP_14']
                    di_minus = adx_result['DMN_14']
                    return (di_plus - di_minus)
            return pd.Series(0, index=close.index)
        
        self.di_diff = self.I(calc_di)
        
        # Volume calculation
        def calc_vol_spike():
            vol_avg = pta.sma(volume, length=self.vol_avg_len)
            if vol_avg is None:
                return pd.Series(False, index=close.index)
            vol_spike = volume > (vol_avg * self.vol_threshold)
            return vol_spike
        
        self.vol_spike = self.I(calc_vol_spike)
        
        # Volume delta direction
        def calc_vol_delta_bull():
            candle_body = close - open_
            return candle_body > 0
        
        self.vol_delta_bull = self.I(calc_vol_delta_bull)
        
        # Cooldown counter
        self.bars_since_signal = 0

    def next(self):
        # Increment cooldown counter
        self.bars_since_signal += 1
        
        # Direction from QEMA only
        bull_direction = self.data.Close[-1] > self.qema[-1]
        bear_direction = self.data.Close[-1] < self.qema[-1]
        
        # ADX confirmation
        adx_ok_bull = (not self.require_adx) or (self.adx[-1] >= self.adx_threshold and self.di_diff[-1] > 0)
        adx_ok_bear = (not self.require_adx) or (self.adx[-1] >= self.adx_threshold and self.di_diff[-1] < 0)
        
        # Volume confirmation
        vol_ok_bull = (not self.require_vol) or (self.vol_spike[-1] and self.vol_delta_bull[-1])
        vol_ok_bear = (not self.require_vol) or (self.vol_spike[-1] and not self.vol_delta_bull[-1])
        
        # Session filter (always true if disabled)
        in_session = not self.use_session or True
        
        # Final signals
        bull_signal = bull_direction and adx_ok_bull and vol_ok_bull and in_session and self.bars_since_signal >= self.cooldown_bars
        bear_signal = bear_direction and adx_ok_bear and vol_ok_bear and in_session and self.bars_since_signal >= self.cooldown_bars
        
        # Execute trades
        if bull_signal:
            if not self.position:
                self.buy()
            self.bars_since_signal = 0
        elif bear_signal:
            if self.position:
                self.position.close()
            else:
                self.sell()
            self.bars_since_signal = 0
        
        # Exit logic with ATR-based stops
        if self.position:
            if self.position.is_long:
                stop_loss = self.data.Close[-1] - self.atr[-1] * self.atr_sl_mult
                take_profit = self.data.Close[-1] + self.atr[-1] * self.atr_tp2_mult
                
                if self.data.Close[-1] <= stop_loss:
                    self.position.close()
                elif self.data.Close[-1] >= take_profit:
                    self.position.close()
            else:
                stop_loss = self.data.Close[-1] + self.atr[-1] * self.atr_sl_mult
                take_profit = self.data.Close[-1] - self.atr[-1] * self.atr_tp2_mult
                
                if self.data.Close[-1] >= stop_loss:
                    self.position.close()
                elif self.data.Close[-1] <= take_profit:
                    self.position.close()


