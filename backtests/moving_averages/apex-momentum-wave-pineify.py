import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 14
    smooth = 7
    sigLen = 9
    obLevel = 80
    osLevel = 20

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Step 1: Apply Hull Moving Average to close price
        smooth_price = self.I(pta.hma, close, length=self.smooth)
        
        # Step 2: Compute RSI on HMA-smoothed price
        oscillator = self.I(pta.rsi, smooth_price, length=self.length)
        
        # Step 3: Derive signal line as EMA of oscillator
        signal = self.I(pta.ema, oscillator, length=self.sigLen)
        
        self.oscillator = oscillator
        self.signal = signal

    def next(self):
        if len(self.data) < max(self.length, self.smooth, self.sigLen) + 5:
            return
        
        # BUY condition: oscillator crosses above signal AND oscillator < 50
        if crossover(self.oscillator, self.signal):
            if self.oscillator[-1] < 50:
                self.buy()
        
        # SELL condition: oscillator crosses below signal AND oscillator > 50
        elif crossover(self.signal, self.oscillator):
            if self.oscillator[-1] > 50:
                self.sell()


