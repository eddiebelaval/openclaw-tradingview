import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len1 = 9
    len2 = 21
    len3 = 200

    def init(self):
        close = pd.Series(self.data.Close)
        self.ema1 = self.I(pta.ema, close, length=self.len1)
        self.ema2 = self.I(pta.ema, close, length=self.len2)
        self.ema3 = self.I(pta.ema, close, length=self.len3)

    def next(self):
        if len(self.data) < self.len3 + 1:
            return
        
        if crossover(self.ema1, self.ema2) and self.ema2[-1] > self.ema3[-1]:
            if not self.position:
                self.buy()
        elif crossover(self.ema2, self.ema1) or self.ema2[-1] < self.ema3[-1]:
            if self.position:
                self.position.close()