import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate VWAP using pandas_ta
        self.vwap = self.I(lambda: pta.vwap(high, low, close, volume) or pd.Series(0, index=close.index))
        
        # Simple moving average as support/resistance reference
        self.sma_20 = self.I(pta.sma, close, length=20)
        self.sma_50 = self.I(pta.sma, close, length=50)

    def next(self):
        if len(self.data) < 50:
            return
        
        current_close = self.data.Close[-1]
        current_vwap = self.vwap[-1]
        current_sma20 = self.sma_20[-1]
        current_sma50 = self.sma_50[-1]
        
        # Buy signal: price crosses above VWAP and SMA20 > SMA50 (uptrend)
        if len(self.vwap) > 1:
            prev_close = self.data.Close[-2]
            prev_vwap = self.vwap[-2]
            
            if prev_close <= prev_vwap and current_close > current_vwap:
                if current_sma20 > current_sma50 and not self.position:
                    self.buy()
            
            # Sell signal: price crosses below VWAP or SMA20 crosses below SMA50
            if prev_close >= prev_vwap and current_close < current_vwap:
                if self.position:
                    self.sell()
            
            if crossover(self.sma50, self.sma20):
                if self.position:
                    self.sell()