import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_length = 9
    bb_length = 20
    bb_mult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMA
        self.ema = self.I(pta.ema, close, length=self.ema_length)
        
        # Calculate SMA (middle of Bollinger Bands)
        self.sma = self.I(pta.sma, close, length=self.bb_length)
        
        # Calculate standard deviation for Bollinger Bands
        self.std = self.I(lambda x: x.rolling(window=self.bb_length).std(), close)
        
        # Calculate upper and lower Bollinger Bands
        self.upper_band = self.I(lambda: self.sma + self.bb_mult * self.std)
        self.lower_band = self.I(lambda: self.sma - self.bb_mult * self.std)

    def next(self):
        # Check if we have valid indicator values
        if len(self.data) < self.bb_length + 1:
            return
        
        # Buy signal: EMA crosses above SMA
        if crossover(self.ema, self.sma):
            if not self.position:
                self.buy()
        
        # Sell signal: EMA crosses below SMA
        elif crossover(self.sma, self.ema):
            if self.position:
                self.position.close()