import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Settings
    emaLen = 58
    atrFactor = 3.8
    stopLoss = -5.0
    adxThreshold = 20.5
    swingLen = 13
    beEnabled = True
    beThresh = 9.0
    BE_BUFFER = 0.1

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # EMA
        self.ema = self.I(pta.ema, close, length=self.emaLen)

        # ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14) or pd.DataFrame(0, index=close.index, columns=['ADX_14']))
        self.adx = self.I(lambda: adx_result.iloc[:, 0] if isinstance(adx_result, pd.DataFrame) else adx_result)

        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=50)

        # Swing detection using rolling max/min
        self.highest = self.I(lambda: high.rolling(self.swingLen * 2 + 1).max())
        self.lowest = self.I(lambda: low.rolling(self.swingLen * 2 + 1).min())

        # State variables
        self.lastSwingHigh = None
        self.lastSwingLow = None
        self.trend = 0
        self.beActivated = False
        self.bePrice = None
        self.entryPrice = None
        self.tp1 = None
        self.tp2 = None
        self.tp3 = None
        self.tp11 = None
        self.tp22 = None
        self.tp33 = None
        self.equityAtStartTrade = None

    def next(self):
        # Current values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        # EMA direction
        if len(self.ema) < 2:
            return
        emaUp = self.ema[-1] > self.ema[-2]
        emaDown = self.ema[-1] < self.ema[-2]

        # ADX check
        adxValue = self.adx[-1] if len(self.adx) > 0 else 0
        isTrending = adxValue > self.adxThreshold

        # Swing detection
        if len(self.highest) > self.swingLen and len(self.lowest) > self.swingLen:
            isSwingHigh = high == self.highest[-self.swingLen - 1]
            isSwingLow = low == self.lowest[-self.swingLen - 1]

            if isSwingHigh and self.lastSwingHigh is None:
                self.lastSwingHigh = high
            elif isSwingHigh:
                self.lastSwingHigh = high

            if isSwingLow and self.lastSwingLow is None:
                self.lastSwingLow = low
            elif isSwingLow:
                self.lastSwingLow = low

        # Dow theory trend
        if self.lastSwingHigh is not None and close > self.lastSwingHigh and self.trend != 1:
            self.trend = 1
        if self.lastSwingLow is not None and close < self.lastSwingLow and self.trend != -1:
            self.trend = -1

        # Entry conditions
        goLong = emaUp and self.trend == 1 and isTrending
        goShort = emaDown and self.trend == -1 and isTrending

        # ATR and TP calculation
        if len(self.atr) > 0:
            atrValue = self.atr[-1] * self.atrFactor
        else:
            atrValue = 0

        # PnL calculation
        if len(self.position.trades) > 0:
            lastTrade = self.position.trades[-1]
            entryPrice = lastTrade.entry_price
            if self.position.size > 0:
                pnl = ((close - entryPrice) / entryPrice) * 100.0
            elif self.position.size < 0:
                pnl = ((entryPrice - close) / entryPrice) * 100.0
            else:
                pnl = 0
        else:
            pnl = 0
            entryPrice = None

        # Break-even stop activation
        if self.beEnabled and self.position.size != 0 and not self.beActivated:
            if self.position.size > 0 and pnl >= self.beThresh:
                self.beActivated = True
                self.bePrice = entryPrice * (1 + self.BE_BUFFER / 100)
            elif self.position.size < 0 and pnl >= self.beThresh:
                self.beActivated = True
                self.bePrice = entryPrice * (1 - self.BE_BUFFER / 100)

        # Stop loss
        if pnl < self.stopLoss:
            if self.position.size > 0:
                self.position.close()
                self.beActivated = False
                self.bePrice = None
            elif self.position.size < 0:
                self.position.close()
                self.beActivated = False
                self.bePrice = None

        # Break-even stop
        if self.beEnabled and self.beActivated and self.bePrice is not None:
            if self.position.size > 0 and low <= self.bePrice:
                self.position.close()
                self.beActivated = False
                self.bePrice = None
            elif self.position.size < 0 and high >= self.bePrice:
                self.position.close()
                self.beActivated = False
                self.bePrice = None

        # Trend reversal close
        if self.trend == 1 and self.position.size < 0:
            self.position.close()
            self.beActivated = False
            self.bePrice = None
        elif self.trend == -1 and self.position.size > 0:
            self.position.close()
            self.beActivated = False
            self.bePrice = None

        # Take profit
        if self.position.size > 0:
            if self.tp1 is not None and high > self.tp1:
                self.sell(size=self.position.size * 0.3)
                self.tp1 = None
            if self.tp2 is not None and high > self.tp2:
                self.sell(size=self.position.size * 0.3)
                self.tp2 = None
            if self.tp3 is not None and high > self.tp3:
                self.sell(size=self.position.size * 0.3)
                self.tp3 = None
                self.entryPrice = None

        if self.position.size < 0:
            if self.tp11 is not None and low < self.tp11:
                self.buy(size=abs(self.position.size) * 0.3)
                self.tp11 = None
            if self.tp22 is not None and low < self.tp22:
                self.buy(size=abs(self.position.size) * 0.3)
                self.tp22 = None
            if self.tp33 is not None and low < self.tp33:
                self.buy(size=abs(self.position.size) * 0.3)
                self.tp33 = None
                self.entryPrice = None

        # Long entry
        if self.position.size <= 0 and goLong:
            if self.position.size < 0:
                self.position.close()
            if self.position.size == 0:
                self.equityAtStartTrade = self.equity
                self.beActivated = False
                self.bePrice = None
                self.buy()
                self.entryPrice = close
                self.tp1 = close + atrValue
                self.tp2 = close + atrValue * 2
                self.tp3 = close + atrValue * 3
                self.tp11 = None
                self.tp22 = None
                self.tp33 = None

        # Short entry
        if self.position.size >= 0 and goShort:
            if self.position.size > 0:
                self.position.close()
            if self.position.size == 0:
                self.equityAtStartTrade = self.equity
                self.beActivated = False
                self.bePrice = None
                self.sell()
                self.entryPrice = close
                self.tp11 = close - atrValue
                self.tp22 = close - atrValue * 2
                self.tp33 = close - atrValue * 3
                self.tp1 = None
                self.tp2 = None
                self.tp3 = None


