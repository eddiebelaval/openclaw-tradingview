class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Current Timeframe EMAs and SMAs
        self.c_ema = self.I(lambda x: pta.ema(x, length=21), close)
        self.c_jma = self.I(self._jma_wrapper, close, 7, 100, 2.0)
        self.c_sma = self.I(lambda x: pta.sma(x, length=200), close)
        
        # HTF EMAs and SMAs (using close for HTF approximation)
        self.h_ema = self.I(lambda x: pta.ema(x, length=21), close)
        self.h_ema2 = self.I(lambda x: pta.ema(x, length=50), close)
        self.h_jma = self.I(self._jma_wrapper, close, 7, 100, 2.0)
        self.h_sma = self.I(lambda x: pta.sma(x, length=200), close)
        
        # VWAP
        self.vwap = self.I(lambda c, v: pta.vwap(c, v), close, volume)
        
        # ATR for volatility
        self.atr = self.I(lambda h, l, c: pta.atr(h, l, c, length=20), high, low, close)
        
        # Pivot Points for SR levels
        self.pivot_high = self.I(self._pivot_high, high, 10)
        self.pivot_low = self.I(self._pivot_low, low, 10)
        
