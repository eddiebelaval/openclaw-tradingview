import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_type = "SMA"
    theme = "Theme 2"
    length = 1
    start = 2
    ma_number = 32
    colour_from = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        self.mas = []
        
        for idx in range(self.ma_number):
            ma_length = (self.length * self.start) + (self.length * idx)
            
            if self.ma_type == "SMA":
                ma = self.I(pta.sma, close, length=ma_length)
            elif self.ma_type == "EMA":
                ma = self.I(pta.ema, close, length=ma_length)
            elif self.ma_type == "WMA":
                ma = self.I(pta.wma, close, length=ma_length)
            elif self.ma_type == "VWMA":
                ma = self.I(pta.vwma, close, volume, length=ma_length)
            elif self.ma_type == "RMA":
                ma = self.I(pta.rma, close, length=ma_length)
            elif self.ma_type == "DEMA":
                ema1 = self.I(pta.ema, close, length=ma_length)
                ema2 = self.I(lambda c=close, l=ma_length: pta.ema(pta.ema(c, length=l), length=l))
                ma = self.I(lambda e1=ema1, e2=ema2: 2 * e1 - e2 if e1 is not None and e2 is not None else pd.Series(0, index=close.index))
            elif self.ma_type == "TEMA":
                ma = self.I(pta.tema, close, length=ma_length)
            elif self.ma_type == "ALMA":
                ma = self.I(pta.alma, close, length=ma_length, offset=0.0, sigma=6.0)
            elif self.ma_type == "HMA":
                ma = self.I(pta.hma, close, length=ma_length)
            elif self.ma_type == "LSMA":
                ma = self.I(pta.linreg, close, length=ma_length)
            elif self.ma_type == "MEDIANMA":
                ma = self.I(lambda c=close, l=ma_length: c.rolling(window=l).median())
            else:
                ma = self.I(pta.sma, close, length=ma_length)
            
            self.mas.append(ma)

    def next(self):
        if len(self.mas) < 2:
            return
        
        fastest_ma = self.mas[0][-1]
