import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate 8-EMA Ribbon
        self.ema1 = self.I(pta.ema, close, length=20)
        self.ema2 = self.I(pta.ema, close, length=25)
        self.ema3 = self.I(pta.ema, close, length=30)
        self.ema4 = self.I(pta.ema, close, length=35)
        self.ema5 = self.I(pta.ema, close, length=40)
        self.ema6 = self.I(pta.ema, close, length=45)
        self.ema7 = self.I(pta.ema, close, length=50)
        self.ema8 = self.I(pta.ema, close, length=55)

    def next(self):
        # Buy signal: EMA1 crosses above EMA8 (Bullish Trend)
        if crossover(self.ema1, self.ema8):
            if not self.position:
                self.buy()
        
        # Sell signal: EMA1 crosses below EMA8 (Bearish Trend)
        elif crossover(self.ema8, self.ema1):
            if self.position:
                self.position.close()


if __name__ == "__main__":
    from backtesting.test import GOOG
    
    bt = Backtest(GOOG, TvStrategy, cash=10000, commission=.002)
    results = bt.run()
