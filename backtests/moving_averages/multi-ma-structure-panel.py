import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA Parameters
    ma_type = "EMA"
    flat_th = 0.0
    
    use1 = True
    len1 = 20
    
    use2 = True
    len2 = 50
    
    use3 = True
    len3 = 75
    
    use4 = True
    len4 = 100
    
    use5 = True
    len5 = 200
    
    use6 = False
    len6 = 300
    
    # HTF Filter Parameters
    use_htf_filter = True
    htf_mode = "Price vs HTF MA"
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate MAs
        if self.ma_type == "EMA":
            self.ma1 = self.I(pta.ema, close, length=self.len1) if self.use1 else None
            self.ma2 = self.I(pta.ema, close, length=self.len2) if self.use2 else None
            self.ma3 = self.I(pta.ema, close, length=self.len3) if self.use3 else None
            self.ma4 = self.I(pta.ema, close, length=self.len4) if self.use4 else None
            self.ma5 = self.I(pta.ema, close, length=self.len5) if self.use5 else None
            self.ma6 = self.I(pta.ema, close, length=self.len6) if self.use6 else None
        else:
            self.ma1 = self.I(pta.sma, close, length=self.len1) if self.use1 else None
            self.ma2 = self.I(pta.sma, close, length=self.len2) if self.use2 else None
            self.ma3 = self.I(pta.sma, close, length=self.len3) if self.use3 else None
            self.ma4 = self.I(pta.sma, close, length=self.len4) if self.use4 else None
            self.ma5 = self.I(pta.sma, close, length=self.len5) if self.use5 else None
            self.ma6 = self.I(pta.sma, close, length=self.len6) if self.use6 else None
        
        # Calculate MA states (slope direction)
        def get_ma_state(ma_series):
            if len(self.data) < 2:
                return 0
            if ma_series is None or np.isnan(ma_series[-1]) or np.isnan(ma_series[-2]):
                return 0
            diff = ma_series[-1] - ma_series[-2]
            if diff > self.flat_th:
                return 1
            elif diff < -self.flat_th:
                return -1
            else:
                return 0
        
        self.get_ma_state = get_ma_state
        
        # Buy signal: when shortest MA (ma1) crosses above medium MA (ma2) and ma2 above ma5
        # Sell signal: when shortest MA (ma1) crosses below medium MA (ma2) or ma2 below ma5
        self.buy_signal_active = False
        self.sell_signal_active = False

    def next(self):
        if len(self.data) < self.len5 + 1:
            return
        
        close = self.data.Close[-1]
        
        # Check HTF filter
        htf_filter_ok = True
        if self.use_htf_filter:
            # Simplified HTF filter: check if we have enough data
            if self.ma5 is not None and not np.isnan(self.ma5[-1]):
                if self.htf_mode == "Price vs HTF MA":
                    # Use ma5 as proxy for HTF MA
                    htf_filter_ok = close > self.ma5[-1]
        
        # Entry logic: MA1 crosses above MA2 with proper alignment
        if self.use1 and self.use2 and self.use5:
            if (self.ma1 is not None and self.ma2 is not None and self.ma5 is not None and
                not np.isnan(self.ma1[-1]) and not np.isnan(self.ma2[-1]) and not np.isnan(self.ma5[-1])):
                
                # Buy signal: ma1 > ma2 > ma5 (bullish alignment)
                ma1_above_ma2 = self.ma1[-1] > self.ma2[-1]
                ma2_above_ma5 = self.ma2[-1] > self.ma5[-1]
                ma1_was_below_ma2 = len(self.data) > 1 and self.ma1[-2] <= self.ma2[-2]
                
                if ma1_above_ma2 and ma2_above_ma5 and ma1_was_below_ma2 and htf_filter_ok:
                    if not self.position:
                        self.buy()
                
                # Sell signal: ma1 crosses below ma2 or ma2 falls below ma5
                ma1_below_ma2 = self.ma1[-1] < self.ma2[-1]
                ma2_below_ma5 = self.ma2[-1] < self.ma5[-1]
                ma1_was_above_ma2 = len(self.data) > 1 and self.ma1[-2] >= self.ma2[-2]
                
                if (ma1_below_ma2 and ma1_was_above_ma2) or ma2_below_ma5:
                    if self.position:
                        self.position.close()