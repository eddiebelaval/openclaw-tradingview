        # Trading logic
        if pattern_bull and not self.position:
            self.buy()
        elif pattern_bear and self.position:
            self.sell()
        
        # Additional exit logic based on VStop
        if self.position:
            if self.position.is_long and not self.vstop_trend:
                self.sell()
            elif self.position.is_short and self.vstop_trend:
                self.buy()


