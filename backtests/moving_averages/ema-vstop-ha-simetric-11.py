import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Configuration
    ema_len = 9
    
    # Smoothing Configuration
    smoothing_type = "None"
    smoothing_len = 14
    
    # VStop Configuration
    vstop_len = 20
    vstop_factor = 2.0
    
    # Signal Configuration
    wick_threshold = 60.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMA
        self.ema = self.I(pta.ema, close, length=self.ema_len)
        
        # Calculate smoothing MA if needed
        if self.smoothing_type == "SMA":
            self.smoothing_ma = self.I(pta.sma, self.ema, length=self.smoothing_len)
        elif self.smoothing_type == "EMA":
            self.smoothing_ma = self.I(pta.ema, self.ema, length=self.smoothing_len)
        elif self.smoothing_type == "SMMA (RMA)":
            self.smoothing_ma = self.I(pta.rma, self.ema, length=self.smoothing_len)
        elif self.smoothing_type == "WMA":
            self.smoothing_ma = self.I(pta.wma, self.ema, length=self.smoothing_len)
        elif self.smoothing_type == "VWMA":
            volume = pd.Series(self.data.Volume)
            self.smoothing_ma = self.I(pta.vwma, self.ema, volume, length=self.smoothing_len)
        else:
            self.smoothing_ma = None
        
        # Calculate ATR for VStop
        self.atr = self.I(pta.atr, high, low, close, length=self.vstop_len)
        
        # Initialize VStop tracking variables
        self.vstop_value = None
        self.vstop_trend = True
        self.max_price = None
        self.min_price = None

    def next(self):
        # Get current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Initialize max/min prices on first call
        if self.vstop_value is None:
            self.max_price = current_close
            self.min_price = current_close
            self.vstop_value = current_close
            return
        
        # Calculate VStop
        atr_value = self.atr[-1] if len(self.atr) > 0 and self.atr[-1] is not None else 0
        atr_adjusted = atr_value * self.vstop_factor
        
        if self.vstop_trend:
            self.max_price = max(self.max_price, current_close)
            self.vstop_value = self.max_price - atr_adjusted
            if current_close < self.vstop_value:
                self.vstop_trend = False
                self.min_price = current_close
                self.vstop_value = self.min_price + atr_adjusted
        else:
            self.min_price = min(self.min_price, current_close)
            self.vstop_value = self.min_price + atr_adjusted
            if current_close > self.vstop_value:
                self.vstop_trend = True
                self.max_price = current_close
                self.vstop_value = self.max_price - atr_adjusted
        
        # Heikin Ashi calculations
        if len(self) < 2:
            return
        
        # Previous candle (index -2)
        prev_close = self.data.Close[-2]
        prev_open = self.data.Open[-2]
        prev_high = self.data.High[-2]
        prev_low = self.data.Low[-2]
        
        # Current candle (index -1)
        curr_open = self.data.Open[-1]
        curr_close = self.data.Close[-1]
        curr_high = self.data.High[-1]
        curr_low = self.data.Low[-1]
        
        # Heikin Ashi for previous candle (approximation)
        ha_v1_close = (prev_open + prev_high + prev_low + prev_close) / 4
        ha_v1_open = (prev_open + prev_close) / 2
        ha_v1_high = max(prev_high, ha_v1_open, ha_v1_close)
        ha_v1_low = min(prev_low, ha_v1_open, ha_v1_close)
        
        # Heikin Ashi for current candle
        ha_v2_close = (curr_open + curr_high + curr_low + curr_close) / 4
        ha_v2_open = (ha_v1_close + ha_v1_open) / 2
        ha_v2_high = max(curr_high, ha_v2_open, ha_v2_close)
        ha_v2_low = min(curr_low, ha_v2_open, ha_v2_close)
        
        # Vela 1 analysis (previous candle)
        v1_range = ha_v1_high - ha_v1_low
        v1_body = abs(ha_v1_close - ha_v1_open)
        v1_wick_pct = ((v1_range - v1_body) / v1_range * 100) if v1_range > 0 else 0
        
        # Contact of Vela 1 with EMA
        ema_prev = self.ema[-2] if len(self.ema) >= 2 else self.ema[-1]
        v1_contact = ha_v1_low <= ema_prev <= ha_v1_high
