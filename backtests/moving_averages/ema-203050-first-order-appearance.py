import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema30 = self.I(pta.ema, close, length=30)
        self.ema50 = self.I(pta.ema, close, length=50)
        
        self.bull_order = self.I(lambda: (self.ema20 > self.ema30) & (self.ema30 > self.ema50))
        self.bear_order = self.I(lambda: (self.ema20 < self.ema30) & (self.ema30 < self.ema50))

    def next(self):
        if len(self.data) < 2:
            return
        
        bull_now = self.bull_order[-1]
        bull_prev = self.bull_order[-2]
        bear_now = self.bear_order[-1]
        bear_prev = self.bear_order[-2]
        
        buy_signal = bull_now and not bull_prev
        sell_signal = bear_now and not bear_prev
        
        if buy_signal and not self.position:
            self.buy()
        elif sell_signal and self.position:
            self.sell()