import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length_input = 10
    attenuation_input = 1.0
    power_input = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Pre-smoothing sources using Length
        src = self.I(pta.sma, close, length=self.length_input)
        s_high = self.I(pta.sma, high, length=self.length_input)
        s_low = self.I(pta.sma, low, length=self.length_input)
        
        # Range boundaries - highest and lowest
        def highest_func():
            return pd.Series(s_high).rolling(window=self.length_input).max()
        
        def lowest_func():
            return pd.Series(s_low).rolling(window=self.length_input).min()
        
        h = self.I(highest_func)
        l = self.I(lowest_func)
        
        # Stochastic normalization
        def stoch_func():
            h_series = pd.Series(self.data.High).rolling(window=self.length_input).max()
            l_series = pd.Series(self.data.Low).rolling(window=self.length_input).min()
            stoch_result = pta.stoch(
                pd.Series(self.data.High),
                pd.Series(self.data.Low),
                pd.Series(self.data.Close),
                k=self.length_input,
                d=self.length_input,
                smooth_k=1
            )
            if stoch_result is not None and 'STOCHk_' + str(self.length_input) + '_' + str(self.length_input) + '_1' in stoch_result.columns:
                return stoch_result['STOCHk_' + str(self.length_input) + '_' + str(self.length_input) + '_1']
            return pd.Series(50, index=pd.Series(self.data.Close).index)
        
        stoch = self.I(stoch_func)
        
        # Adaptive AMA calculation
        def ama_func():
            close_arr = np.array(self.data.Close)
            high_arr = np.array(self.data.High)
            low_arr = np.array(self.data.Low)
            
            src_sma = pd.Series(close_arr).rolling(window=self.length_input).mean()
            s_high_sma = pd.Series(high_arr).rolling(window=self.length_input).mean()
            s_low_sma = pd.Series(low_arr).rolling(window=self.length_input).mean()
            
            h_highest = pd.Series(s_high_sma).rolling(window=self.length_input).max()
            l_lowest = pd.Series(s_low_sma).rolling(window=self.length_input).min()
            
            stoch_norm = ((src_sma - l_lowest) / (h_highest - l_lowest + 1e-10)) * 100
            stoch_norm = stoch_norm.fillna(50)
            
            alpha_base = np.abs(stoch_norm - 50) / 100 / self.attenuation_input
            alpha = np.power(alpha_base, self.power_input)
            
            mid = (h_highest + l_lowest) / 2
            src_ama = mid + (src_sma - mid) / self.attenuation_input
            
            ama_values = np.zeros(len(close_arr))
            ama_values[0] = src_sma.iloc[0] if not np.isnan(src_sma.iloc[0]) else close_arr[0]
            
            for i in range(1, len(close_arr)):
                if np.isnan(src_sma.iloc[i]) or np.isnan(src_ama.iloc[i]) or np.isnan(alpha.iloc[i]):
                    ama_values[i] = ama_values[i-1]
                else:
                    ama_values[i] = ama_values[i-1] + alpha.iloc[i] * (src_ama.iloc[i] - ama_values[i-1])
            
            return pd.Series(ama_values, index=pd.Series(close_arr).index)
        
        self.ama = self.I(ama_func)
        self.src = src

    def next(self):
        if len(self.data) < self.length_input + 5:
            return
        
        # Buy when price crosses above AMA
        if crossover(self.src, self.ama):
            if not self.position:
                self.buy()
        # Sell when price crosses below AMA
        elif crossover(self.ama, self.src):
            if self.position:
                self.position.close()


