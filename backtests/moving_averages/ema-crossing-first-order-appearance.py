import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMAs
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema30 = self.I(pta.ema, close, length=30)
        self.ema50 = self.I(pta.ema, close, length=50)
        
        # Track previous bull/bear order state
        self.prev_bull_order = False
        self.prev_bear_order = False

    def next(self):
        # Current order conditions
        bull_order = self.ema20[-1] > self.ema30[-1] and self.ema30[-1] > self.ema50[-1]
        bear_order = self.ema20[-1] < self.ema30[-1] and self.ema30[-1] < self.ema50[-1]
        
        # Detect first appearance (transition from False to True)
        buy_signal = bull_order and not self.prev_bull_order
        sell_signal = bear_order and not self.prev_bear_order
        
        # Execute trades
        if buy_signal:
            self.buy()
        elif sell_signal:
            self.sell()
        
        # Update previous state for next bar
        self.prev_bull_order = bull_order
        self.prev_bear_order = bear_order


