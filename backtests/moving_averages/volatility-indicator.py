import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    vix_len = 21
    buffer_pct = 0.008
    ema_len = 25
    atr_len = 14
    atr_base_mult = 1.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA calculation
        self.ema_val = self.I(pta.ema, close, length=self.ema_len)
        
        # VWAP calculation
        self.vwap_val = self.I(pta.vwap, high, low, close)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        # VIX SMA (using close as proxy since we don't have actual VIX data)
        self.vix_sma = self.I(pta.sma, close, length=self.vix_len)
        
        # Use close as VIX proxy
        self.vix = close
        
        self.trend_state = 0

    def next(self):
        if len(self.data) < self.vix_len + self.ema_len:
            return
        
        close = self.data.Close[-1]
        ema_val = self.ema_val[-1]
        vwap_val = self.vwap_val[-1]
        atr = self.atr[-1]
        vix = self.vix[-1]
        vix_sma = self.vix_sma[-1]
        
        if ema_val is None or vwap_val is None or atr is None or vix_sma is None:
            return
        
        # Calculate adaptive ATR multiplier based on VIX factor
        vix_factor = max(vix / vix_sma if vix_sma != 0 else 1.0, 0.5)
        adaptive_atr_mult = self.atr_base_mult * vix_factor
        
        # Calculate bands
        upper_band = ema_val + (atr * adaptive_atr_mult)
        lower_band = ema_val - (atr * adaptive_atr_mult)
        
        # Market state logic
        vix_spiking = vix > vix_sma * (1 + self.buffer_pct)
        
        # Signal conditions
        long_condition = close > upper_band and close > vwap_val and not vix_spiking
        short_condition = close < lower_band and close < vwap_val and vix > vix_sma
        
        # Update trend state
        prev_trend_state = self.trend_state
        
        if long_condition:
            self.trend_state = 1
        elif short_condition:
            self.trend_state = -1
        elif (self.trend_state == 1 and close < ema_val) or (self.trend_state == -1 and close > ema_val):
            self.trend_state = 0
        
        # Trading logic
        if self.trend_state == 1 and prev_trend_state != 1:
            if self.position:
                self.position.close()
            self.buy()
        elif self.trend_state == -1 and prev_trend_state != -1:
            if self.position:
                self.position.close()
            self.sell()
        elif self.trend_state == 0 and prev_trend_state != 0:
            if self.position:
                self.position.close()


