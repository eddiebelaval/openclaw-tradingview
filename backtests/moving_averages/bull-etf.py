import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate Moving Averages
        self.ma10 = self.I(pta.sma, close, length=10)
        self.ma20 = self.I(pta.sma, close, length=20)
        self.ma50 = self.I(pta.sma, close, length=50)
        self.ma200 = self.I(pta.sma, close, length=200)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Current values
        close = self.data.Close[-1]
        ma10_curr = self.ma10[-1]
        ma20_curr = self.ma20[-1]
        ma50_curr = self.ma50[-1]
        
        # Previous values
        ma10_prev = self.ma10[-2]
        ma20_prev = self.ma20[-2]
        ma50_prev = self.ma50[-2]
        
        # Check slopes are positive (current MA > previous MA)
        slope10_pos = ma10_curr > ma10_prev
        slope20_pos = ma20_curr > ma20_prev
        slope50_pos = ma50_curr > ma50_prev
        
        # Check price above 10, 20, 50 MAs
        price_above_key = close > ma10_curr and close > ma20_curr and close > ma50_curr
        
        # Check the stacking condition for 10 above 50
        ma10_above_50 = ma10_curr > ma50_curr
        
        # Overall bullish condition
        bullish_condition = price_above_key and ma10_above_50 and slope10_pos and slope20_pos and slope50_pos
        
        # Detect entry into bullish condition (first bar where it's true)
        bullish_condition_prev = False
        if len(self.data) >= 2:
            close_prev = self.data.Close[-2]
            ma10_prev2 = self.ma10[-2]
            ma20_prev2 = self.ma20[-2]
            ma50_prev2 = self.ma50[-2]
            
            if len(self.data) >= 3:
                ma10_prev3 = self.ma10[-3]
                ma20_prev3 = self.ma20[-3]
                ma50_prev3 = self.ma50[-3]
                
                slope10_pos_prev = ma10_prev2 > ma10_prev3
                slope20_pos_prev = ma20_prev2 > ma20_prev3
                slope50_pos_prev = ma50_prev2 > ma50_prev3
            else:
                slope10_pos_prev = False
                slope20_pos_prev = False
                slope50_pos_prev = False
            
            price_above_key_prev = close_prev > ma10_prev2 and close_prev > ma20_prev2 and close_prev > ma50_prev2
            ma10_above_50_prev = ma10_prev2 > ma50_prev2
