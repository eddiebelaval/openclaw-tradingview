import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fma_base = 21
    fma_d = 0.7
    adapt_len = 200
    tau_init = 14.0
    learn_rate = 0.05
    comp_pctile = 30.0
    spread_wide_pctile = 75.0
    use_vda = True
    vda_gain_init = 0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.fma_alpha = 2.0 / (self.fma_base + 1.0) * max(min(self.fma_d, 1.0), 0.3)
        
        self.fma_high_vals = np.full(len(self.data), np.nan)
        self.fma_low_vals = np.full(len(self.data), np.nan)
        self.ref_high_vals = np.full(len(self.data), np.nan)
        self.ref_low_vals = np.full(len(self.data), np.nan)
        self.spread_vals = np.full(len(self.data), np.nan)
        self.vd_smooth_vals = np.full(len(self.data), np.nan)
        self.vd_vel_vals = np.full(len(self.data), np.nan)
        self.vd_accel_vals = np.full(len(self.data), np.nan)
        self.vda_norm_vals = np.full(len(self.data), np.nan)
        self.bull_cross_vals = np.full(len(self.data), False)
        self.bear_cross_vals = np.full(len(self.data), False)
        self.in_compression_vals = np.full(len(self.data), False)
        
        self.atr = self.I(pta.atr, high, low, close, length=14)
        self.vol_sma = self.I(pta.sma, pd.Series(self.data.Volume), length=self.adapt_len)
        
        self.tau_bull = self.tau_init
        self.tau_bear = self.tau_init
        self.vd_gain_bull = self.vda_gain_init
        self.vd_gain_bear = self.vda_gain_init
        self.pend_bar = []
        self.pend_dir = []
        
        self.prev_bull_cross = False
        self.prev_bear_cross = False

    def next(self):
        idx = len(self.data) - 1
        
        if idx == 0:
            self.fma_high_vals[idx] = self.data.High[idx]
            self.fma_low_vals[idx] = self.data.Low[idx]
        else:
            self.fma_high_vals[idx] = (self.fma_high_vals[idx - 1] * (1.0 - self.fma_alpha) + 
                                       self.data.High[idx] * self.fma_alpha)
            self.fma_low_vals[idx] = (self.fma_low_vals[idx - 1] * (1.0 - self.fma_alpha) + 
                                      self.data.Low[idx] * self.fma_alpha)
        
        fma_high = self.fma_high_vals[idx]
        fma_low = self.fma_low_vals[idx]
        atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 1e-10
        
        fma_spread = (fma_high - fma_low) / max(atr_val, 1e-10)
        self.spread_vals[idx] = fma_spread
        
        spread_comp_thr = np.percentile(
            self.spread_vals[:idx+1][~np.isnan(self.spread_vals[:idx+1])],
            self.comp_pctile
        ) if idx > 0 else fma_spread
        
        spread_wide_thr = np.percentile(
            self.spread_vals[:idx+1][~np.isnan(self.spread_vals[:idx+1])],
            self.spread_wide_pctile
        ) if idx > 0 else fma_spread
        
        in_compression = fma_spread < spread_comp_thr
        self.in_compression_vals[idx] = in_compression
        
        vol_sma_val = self.vol_sma[-1] if not np.isnan(self.vol_sma[-1]) else 1e-10
        vd_raw = (self.data.Volume[idx] if self.data.Close[idx] >= self.data.Open[idx] 
                  else -self.data.Volume[idx]) / max(vol_sma_val, 1e-10)
        
        if idx == 0:
            self.vd_smooth_vals[idx] = vd_raw
        else:
            self.vd_smooth_vals[idx] = (self.vd_smooth_vals[idx - 1] * (1.0 - self.fma_alpha) + 
                                        vd_raw * self.fma_alpha)
        
        vd_smooth = self.vd_smooth_vals[idx]
        vd_vel = vd_smooth - (self.vd_smooth_vals[idx - 1] if idx > 0 else vd_smooth)
        self.vd_vel_vals[idx] = vd_vel
        
        vd_accel = vd_vel - (self.vd_vel_vals[idx - 1] if idx > 0 else 0.0)
        self.vd_accel_vals[idx] = vd_accel
        
        accel_abs = np.abs(self.vd_accel_vals[:idx+1][~np.isnan(self.vd_accel_vals[:idx+1])])
        vda_p75 = np.percentile(accel_abs, 75) if len(accel_abs) > 0 else 1e-10
        vda_norm = vd_accel / max(vda_p75, 1e-10)
        vda_c = max(min(vda_norm, 3.0), -3.0)
        self.vda_norm_vals[idx] = vda_c
        
        vda_bear_comp = max(-vda_c, 0.0)
        vda_bull_comp = max(vda_c, 0.0)
        
        tau_bull_eff = (self.tau_bull * (1.0 + vda_bear_comp * self.vd_gain_bull) 
                        if self.use_vda else self.tau_bull)
        tau_bull_eff = min(tau_bull_eff, 100.0)
        
        tau_bear_eff = (self.tau_bear * (1.0 + vda_bull_comp * self.vd_gain_bear) 
                        if self.use_vda else self.tau_bear)
        tau_bear_eff = min(tau_bear_eff, 100.0)
        
        tb_k0 = int(np.floor(tau_bull_eff))
        tb_frac = tau_bull_eff - tb_k0
        ref_high_0 = (self.fma_high_vals[idx - tb_k0] 
                      if idx - tb_k0 >= 0 and not np.isnan(self.fma_high_vals[idx - tb_k0]) 
                      else fma_high)
        ref_high_1 = (self.fma_high_vals[idx - tb_k0 - 1] 
                      if idx - tb_k0 - 1 >= 0 and not np.isnan(self.fma_high_vals[idx - tb_k0 - 1]) 
                      else fma_high)
        ref_high = ref_high_0 * (1.0 - tb_frac) + ref_high_1 * tb_frac
        self.ref_high_vals[idx] = ref_high
        
        ts_k0 = int(np.floor(tau_bear_eff))
        ts_frac = tau_bear_eff - ts_k0
        ref_low_0 = (self.fma_low_vals[idx - ts_k0] 
                     if idx - ts_k0 >= 0 and not np.isnan(self.fma_low_vals[idx - ts_k0]) 
                     else fma_low)
        ref_low_1 = (self.fma_low_vals[idx - ts_k0 - 1] 
                     if idx - ts_k0 - 1 >= 0 and not np.isnan(self.fma_low_vals[idx - ts_k0 - 1]) 
                     else fma_low)
        ref_low = ref_low_0 * (1.0 - ts_frac) + ref_low_1 * ts_frac
        self.ref_low_vals[idx] = ref_low
        
        fma_bull_cross = fma_low > ref_high
        fma_bear_cross = fma_high < ref_low
        
        self.bull_cross_vals[idx] = fma_bull_cross
        self.bear_cross_vals[idx] = fma_bear_cross
        
        comp_entry = False
        if idx > 0:
            prev_spread = self.spread_vals[idx - 1]
            if not np.isnan(prev_spread) and prev_spread >= spread_comp_thr and fma_spread < spread_comp_thr:
                comp_entry = True
        
        if comp_entry:
            fma_mid = (fma_high + fma_low) * 0.5
            hint_dir = 1 if self.data.Close[idx] >= fma_mid else -1
            self.pend_bar.append(idx)
            self.pend_dir.append(hint_dir)
        
        eval_win = int(max(self.tau_bull, self.tau_bear) * 3.0)
        qi = len(self.pend_bar) - 1
        while qi >= 0:
            pb = self.pend_bar[qi]
            pd = self.pend_dir[qi]
            elapsed = idx - pb
            
            correct = (pd == 1 and fma_bull_cross) or (pd == -1 and fma_bear_cross)
            adverse = (pd == 1 and fma_bear_cross) or (pd == -1 and fma_bull_cross)
            
            if correct and elapsed <= eval_win:
                t_actual = float(elapsed)
                if pd == 1:
                    self.tau_bull = max(min(
                        self.tau_bull * (1.0 - self.learn_rate) + t_actual * self.learn_rate,
                        100.0), 2.0)
                else:
                    self.tau_bear = max(min(
                        self.tau_bear * (1.0 - self.learn_rate) + t_actual * self.learn_rate,
                        100.0), 2.0)
                self.pend_bar.pop(qi)
                self.pend_dir.pop(qi)
            
            elif adverse or elapsed > eval_win:
                if elapsed > eval_win:
                    if pd == 1:
                        self.tau_bull = min(self.tau_bull * (1.0 + self.learn_rate * 0.5), 100.0)
                    else:
                        self.tau_bear = min(self.tau_bear * (1.0 + self.learn_rate * 0.5), 100.0)
                self.pend_bar.pop(qi)
                self.pend_dir.pop(qi)
            
            qi -= 1
        
        vd_lr = self.learn_rate * 0.5
        
        bull_edge = fma_bull_cross and not self.prev_bull_cross
        bear_edge = fma_bear_cross and not self.prev_bear_cross
        
        if self.use_vda:
            if bull_edge and vda_bear_comp > 1.0:
                self.vd_gain_bull = min(self.vd_gain_bull * (1.0 + vd_lr), 3.0)
            if bear_edge and vda_bear_comp > 1.0:
                self.vd_gain_bull = max(self.vd_gain_bull * (1.0 - vd_lr * 0.5), 0.1)
            if bear_edge and vda_bull_comp > 1.0:
                self.vd_gain_bear = min(self.vd_gain_bear * (1.0 + vd_lr), 3.0)
            if bull_edge and vda_bull_comp > 1.0:
                self.vd_gain_bear = max(self.vd_gain_bear * (1.0 - vd_lr * 0.5), 0.1)
        
        self.prev_bull_cross = fma_bull_cross
        self.prev_bear_cross = fma_bear_cross
        
        if fma_bull_cross and not self.position:
            self.buy()
        elif fma_bear_cross and self.position:
            self.sell()


