import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    longLossPerc = 0.035  # 3.5% stop loss
    startDate = 10
    startMonth = 3
    startYear = 1999

    def init(self):
        # Current ticker indicators
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Current ticker moving averages
        self.shortMA = self.I(pta.sma, close, length=7)
        self.longMA = self.I(pta.sma, close, length=107)
        self._14ema = self.I(pta.ema, close, length=14)
        self._21ema = self.I(pta.ema, close, length=21)
        self._50sma = self.I(pta.sma, close, length=50)
        self._200sma = self.I(pta.sma, close, length=200)

        # For tracking entry price
        self.qqqPriceAtEntry = np.nan

    def next(self):
        # Check date range
        current_time = pd.Timestamp(self.data.index[-1])
        start_date = pd.Timestamp(year=self.startYear, month=self.startMonth, day=self.startDate)
        
        if current_time < start_date:
            return

        # Current bar values
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]

        # Since we can't access external ticker data (SPX, QQQ) directly in backtesting.py,
        # we'll use the current ticker as a proxy for both entry and exit signals
        # This assumes the strategy is being applied to QQQ or similar tech index
        
        close_prev1 = self.data.Close[-2] if len(self.data.Close) >= 2 else close
        close_prev2 = self.data.Close[-3] if len(self.data.Close) >= 3 else close
        close_prev3 = self.data.Close[-4] if len(self.data.Close) >= 4 else close
        
        low_prev1 = self.data.Low[-2] if len(self.data.Low) >= 2 else low
        low_prev2 = self.data.Low[-3] if len(self.data.Low) >= 3 else low
        low_prev3 = self.data.Low[-4] if len(self.data.Low) >= 4 else low

        # ENTRY CONDITIONS
        # 1. Low > 21 EMA for 4 consecutive days
        ema21_val = self._21ema[-1] if not np.isnan(self._21ema[-1]) else close
        ema21_prev1 = self._21ema[-2] if len(self._21ema) >= 2 and not np.isnan(self._21ema[-2]) else close_prev1
        ema21_prev2 = self._21ema[-3] if len(self._21ema) >= 3 and not np.isnan(self._21ema[-3]) else close_prev2
        ema21_prev3 = self._21ema[-4] if len(self._21ema) >= 4 and not np.isnan(self._21ema[-4]) else close_prev3

        lowAbove21Ema4days = (
            low > ema21_val and
            low_prev1 > ema21_prev1 and
            low_prev2 > ema21_prev2 and
            low_prev3 > ema21_prev3
        )

        # 2. Low > 14 EMA and Low > 21 EMA
        ema14_val = self._14ema[-1] if not np.isnan(self._14ema[-1]) else close
        lowAboveKeyEmas = low > ema14_val and low > ema21_val

        # 3. Close not showing weakness (not 3 closes in a row)
        notShowingWeakness = not (close < close_prev1 and close < close_prev2 and close < close_prev3)

        # 4. Simple ADX proxy - use trend strength based on MA positioning
        # If short MA is above long MA, consider it trending
        shortMA_val = self.shortMA[-1] if not np.isnan(self.shortMA[-1]) else close
        longMA_val = self.longMA[-1] if not np.isnan(self.longMA[-1]) else close
        isTrending = shortMA_val > longMA_val

        longCondition = lowAbove21Ema4days and lowAboveKeyEmas and notShowingWeakness and isTrending

        # EXIT CONDITIONS
        # 1. Trend-Based Exit (Loose Stop)
        shortMA_prev1 = self.shortMA[-2] if len(self.shortMA) >= 2 else shortMA_val
        longMA_prev1 = self.longMA[-2] if len(self.longMA) >= 2 else longMA_val
        
        bearishCross = shortMA_val < longMA_prev1
        priceWeak = close < shortMA_val
        trendEstablishedLooseStop = bearishCross and priceWeak

        # 2. Initial Safety Exit (Tight Stop)
        sma50_val = self._50sma[-1] if not np.isnan(self._50sma[-1]) else close
        longStopPrice = self.qqqPriceAtEntry * (1 - self.longLossPerc)
        
        stopLevelHit = low < longStopPrice
        belowFiftySMA = low < sma50_val
        initialBuyTightStop = (not np.isnan(self.qqqPriceAtEntry)) and stopLevelHit and belowFiftySMA

        # Combine exit conditions
        exitCondition = trendEstablishedLooseStop or initialBuyTightStop

        # EXECUTION
        if longCondition and not self.position:
            self.qqqPriceAtEntry = close
            self.buy()
        elif exitCondition and self.position:
            self.sell()

        # Reset tracker when position is closed
        if not self.position:
            self.qqqPriceAtEntry = np.nan


