import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    maType1 = "SMA"
    len1 = 10
    maType2 = "SMA"
    len2 = 20
    maType3 = "SMA"
    len3 = 50
    maType4 = "SMA"
    len4 = 100
    maType5 = "SMA"
    len5 = 200
    maType6 = "SMA"
    len6 = 300
    maType7 = "SMA"
    len7 = 400

    def init(self):
        close = pd.Series(self.data.Close)
        
        def get_ma(ma_type, length):
            if ma_type == "SMA":
                return pta.sma(close, length=length)
            else:
                return pta.ema(close, length=length)
        
        self.ma1 = self.I(lambda: get_ma(self.maType1, self.len1))
        self.ma2 = self.I(lambda: get_ma(self.maType2, self.len2))
        self.ma3 = self.I(lambda: get_ma(self.maType3, self.len3))
        self.ma4 = self.I(lambda: get_ma(self.maType4, self.len4))
        self.ma5 = self.I(lambda: get_ma(self.maType5, self.len5))
        self.ma6 = self.I(lambda: get_ma(self.maType6, self.len6))
        self.ma7 = self.I(lambda: get_ma(self.maType7, self.len7))

    def next(self):
        if len(self.data) < self.len7 + 1:
            return
        
        close_price = self.data.Close[-1]
        
        ma1_val = self.ma1[-1] if not np.isnan(self.ma1[-1]) else None
        ma2_val = self.ma2[-1] if not np.isnan(self.ma2[-1]) else None
        ma3_val = self.ma3[-1] if not np.isnan(self.ma3[-1]) else None
        ma4_val = self.ma4[-1] if not np.isnan(self.ma4[-1]) else None
        ma5_val = self.ma5[-1] if not np.isnan(self.ma5[-1]) else None
        ma6_val = self.ma6[-1] if not np.isnan(self.ma6[-1]) else None
        ma7_val = self.ma7[-1] if not np.isnan(self.ma7[-1]) else None
        
        if all(v is not None for v in [ma1_val, ma2_val, ma3_val, ma4_val, ma5_val, ma6_val, ma7_val]):
            mas = [ma1_val, ma2_val, ma3_val, ma4_val, ma5_val, ma6_val, ma7_val]
            
            if len(self.data) > self.len7 + 1:
                ma1_prev = self.ma1[-2]
                ma2_prev = self.ma2[-2]
                ma3_prev = self.ma3[-2]
                ma4_prev = self.ma4[-2]
                ma5_prev = self.ma5[-2]
                ma6_prev = self.ma6[-2]
                ma7_prev = self.ma7[-2]
                
