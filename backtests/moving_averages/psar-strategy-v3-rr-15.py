        # Get previous values
        psar_prev = self.psarVal[-2] if len(self.psarVal) > 1 else None
        close_prev = self.data.Close[-2] if len(self.data.Close) > 1 else None
        
        if psar_prev is None or close_prev is None or pd.isna(psar_prev) or pd.isna(close_prev):
            self.last_psar = psar_current
            self.last_close = close
            return
        
        # PSAR flip detection
        psarFlipToLong = (psar_prev > close_prev) and (psar_current < close)
        psarFlipToShort = (psar_prev < close_prev) and (psar_current > close)
        
