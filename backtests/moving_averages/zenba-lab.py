import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    maType = "SMA"
    maLen = 9
    useBands = False
    bandMult = 1.5
    bandLen = 20
    rideMin = 7
    lookback = 25
    crossThresh = 0.16

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Reference MA calculation
        if self.maType == "SMA":
            self.ma = self.I(pta.sma, close, length=self.maLen)
        elif self.maType == "EMA":
            self.ma = self.I(pta.ema, close, length=self.maLen)
        elif self.maType == "VWMA":
            self.ma = self.I(pta.vwma, close, volume, length=self.maLen)
        else:
            self.ma = self.I(pta.sma, close, length=self.maLen)

        # Zenba Wave MAs (fixed 9 & 108 SMA)
        self.ma9 = self.I(pta.sma, close, length=9)
        self.ma108 = self.I(pta.sma, close, length=108)

        # Standard deviation for bands
        self.dev = self.I(pta.stdev, close, length=self.bandLen)

        # Cross detection
        def count_crosses(lookback_period):
            result = pd.Series(0.0, index=close.index)
            for i in range(len(close)):
                if i < lookback_period:
                    result.iloc[i] = 0
                else:
                    cross_count = 0
                    for j in range(i - lookback_period + 1, i + 1):
                        if j > 0:
                            prev_over = close.iloc[j - 1] > self.ma.iloc[j - 1]
                            curr_over = close.iloc[j] > self.ma.iloc[j]
                            if prev_over != curr_over:
                                cross_count += 1
                    result.iloc[i] = cross_count
            return result

        self.cross_count = self.I(count_crosses, self.lookback)

        # Streak tracking
        self.streak = self.I(lambda: self._calculate_streaks(close))

        # State calculations
        self.chopzone = self.I(lambda: self._calculate_chopzone())
        self.riding = self.I(lambda: self._calculate_riding())

        # Track previous state for ride/chop start detection
        self.prev_riding = False
        self.prev_chopzone = False

    def _calculate_streaks(self, close):
        streaks = pd.Series(0, index=close.index)
        up_streak = 0
        dn_streak = 0
        ma_series = self.ma

        for i in range(len(close)):
            if i < len(ma_series) or ma_series.iloc[i] is None:
                streaks.iloc[i] = 0
                continue

            over_ma = close.iloc[i] > ma_series.iloc[i]

            if over_ma:
                up_streak += 1
                dn_streak = 0
            else:
                dn_streak += 1
                up_streak = 0

            streaks.iloc[i] = max(up_streak, dn_streak)

        return streaks

    def _calculate_chopzone(self):
        if len(self.cross_count) == 0 or self.cross_count[-1] is None:
            return pd.Series(False, index=self.data.Close.index)

        threshold = self.lookback * self.crossThresh
        chopzone = (self.cross_count > threshold) | (self.streak < self.rideMin)
        return chopzone

    def _calculate_riding(self):
        if len(self.streak) == 0 or len(self.chopzone) == 0:
            return pd.Series(False, index=self.data.Close.index)

        riding = (self.streak >= self.rideMin) & ~self.chopzone
        return riding

