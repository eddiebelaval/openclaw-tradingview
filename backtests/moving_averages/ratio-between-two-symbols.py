import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    ma_duration = 36
    multiplier = 1.0
    
    def init(self):
        # Calculate ratio (using Close prices)
        # Since we don't have access to external symbol data in backtesting,
        # we'll use the close price as a proxy for ratio calculation
        close = pd.Series(self.data.Close)
        
        # Calculate SMA of the close price (ratio proxy)
        self.ratio = close
        self.ma = self.I(pta.sma, close, length=self.ma_duration)
    
    def next(self):
        # Trading logic: Buy when ratio crosses above MA, sell when crosses below
        if crossover(self.ratio, self.ma):
            if not self.position:
                self.buy()
        elif crossover(self.ma, self.ratio):
            if self.position:
                self.sell()


if __name__ == "__main__":
    # Load data
    data = pd.read_csv("data.csv", parse_dates=True, index_col=0)
    
    # Run backtest
    bt = Backtest(data, TvStrategy, cash=10000, commission=0.002)
    stats = bt.run()
