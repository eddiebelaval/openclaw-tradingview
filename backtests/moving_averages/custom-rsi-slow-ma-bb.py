import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLength = 14
    maLength = 50
    maType = "EMA"
    bbEnable = True
    bbLength = 20
    bbMult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate RSI
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsiLength) or pd.Series(50, index=close.index))
        
        # Calculate MA (EMA or SMA) on RSI
        if self.maType == "EMA":
            self.ma = self.I(lambda: pta.ema(self.rsi, length=self.maLength) or pd.Series(50, index=close.index))
        else:
            self.ma = self.I(lambda: pta.sma(self.rsi, length=self.maLength) or pd.Series(50, index=close.index))
        
        # Calculate Bollinger Bands on RSI
        if self.bbEnable:
            self.basis = self.I(lambda: pta.sma(self.rsi, length=self.bbLength) or pd.Series(50, index=close.index))
            
            # Standard deviation calculation
            def bb_dev():
                rsi_values = self.rsi
                if len(rsi_values) < self.bbLength:
                    return pd.Series(0, index=rsi_values.index)
                dev_series = rsi_values.rolling(window=self.bbLength).std() * self.bbMult
                return dev_series.fillna(0)
            
            self.dev = self.I(bb_dev)
            self.upper = self.I(lambda: self.basis + self.dev)
            self.lower = self.I(lambda: self.basis - self.dev)

    def next(self):
        # Buy on bullish cross (RSI crosses above MA)
        if len(self.rsi) > 1 and len(self.ma) > 1:
            if crossover(self.rsi, self.ma):
                self.buy()
        
        # Sell on bearish cross (RSI crosses below MA)
        if len(self.rsi) > 1 and len(self.ma) > 1:
            if crossover(self.ma, self.rsi):
                self.sell()


