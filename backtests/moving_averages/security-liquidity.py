import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    avgPeriod = 20
    alertVal = 500
    showTrend = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate HLC3 (typical price)
        hlc3 = (high + low + close) / 3
        
        # Calculate VWAP
        self.vwap = self.I(lambda: pta.vwap(high, low, close, volume) or pd.Series(0, index=close.index))
        
        # Calculate liquidity
        def calc_liquidity():
            vwap_vals = self.vwap
            vol_vals = volume
            
            liquidity_values = []
            for i in range(len(vwap_vals)):
                available_bars = min(self.avgPeriod, i + 1)
                
                # Check if start of window has 0 or NaN volume
                if available_bars > 0 and (vol_vals.iloc[i - available_bars + 1] == 0 or pd.isna(vol_vals.iloc[i - available_bars + 1])):
                    available_bars = max(0, available_bars - 1)
                
                if available_bars > 0:
                    vwap_sma = vwap_vals.iloc[max(0, i - available_bars + 1):i + 1].mean()
                    vol_sma = vol_vals.iloc[max(0, i - available_bars + 1):i + 1].mean()
                    raw_liquidity = vwap_sma * vol_sma
                    display_value = raw_liquidity / 1000000
                else:
                    display_value = 0.0
                
                liquidity_values.append(display_value)
            
            return pd.Series(liquidity_values, index=close.index)
        
        self.liquidity = self.I(calc_liquidity)
        
        # Calculate trend (5 bars ago comparison)
        def calc_trend():
            trend_values = []
            for i in range(len(self.liquidity)):
                if i >= 5:
                    is_up = self.liquidity[i] > self.liquidity[i - 5]
                    trend_values.append(1.0 if is_up else 0.0)
                else:
                    trend_values.append(0.0)
            return pd.Series(trend_values, index=close.index)
        
        self.trend = self.I(calc_trend)

    def next(self):
        # Buy when liquidity crosses above alert threshold and trend is up
        if len(self) > 5:
            current_liquidity = self.liquidity[-1]
            previous_liquidity = self.liquidity[-2]
            current_trend = self.trend[-1]
            
            # Entry: liquidity crosses above threshold with uptrend
            if (previous_liquidity <= self.alertVal and current_liquidity > self.alertVal and 
                current_trend > 0.5 and not self.position):
                self.buy()
            
            # Exit: liquidity falls below threshold or trend reverses
            elif self.position and (current_liquidity < self.alertVal or current_trend < 0.5):
                self.position.close()


