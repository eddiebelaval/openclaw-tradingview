import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smaShort = 20
    smaMedium = 50
    smaLong = 200

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.sma20 = self.I(pta.sma, close, length=self.smaShort)
        self.sma50 = self.I(pta.sma, close, length=self.smaMedium)
        self.sma200 = self.I(pta.sma, close, length=self.smaLong)

    def next(self):
        if crossover(self.sma20, self.sma50) and self.sma50[-1] > self.sma200[-1]:
            if not self.position:
                self.buy()
        elif crossover(self.sma50, self.sma20):
            if self.position:
                self.sell()