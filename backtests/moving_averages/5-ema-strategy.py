class TvStrategy(Strategy):
    ema_len = 5
    atr_len = 14
    y_offset_atr = 0.25
    reset_on_touch_ema = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        self.ema5 = self.I(pta.ema, close, length=self.ema_len)
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        self.is_red = close < open_
        self.is_green = close > open_
        
        self.pending = False
        self.signal_active = False
        self.alert_bar = None
        self.alert_high = None
        self.alert_low = None
        self.alert_close = None
        self.in_trade = False

    def next(self):
        if len(self.data) < max(self.ema_len, self.atr_len) + 1:
            return
        
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_bar = len(self.data) - 1
        
        ema5_val = self.ema5[-1]
        atr_val = self.atr_val[-1] if self.atr_val[-1] is not None else 0
        
        is_red_current = current_close < current_open
        is_green_current = current_close > current_open
        
        candle_above_ema = current_low > ema5_val
        is_alert_candle = is_red_current and candle_above_ema
        
