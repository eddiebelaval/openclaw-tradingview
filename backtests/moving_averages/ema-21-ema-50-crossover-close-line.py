import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 21
    slowLen = 50

    def init(self):
        close = pd.Series(self.data.Close)
        self.ema21 = self.I(pta.ema, close, length=self.fastLen)
        self.ema50 = self.I(pta.ema, close, length=self.slowLen)

    def next(self):
        if crossover(self.ema21, self.ema50):
            if not self.position:
                self.buy()
        elif crossover(self.ema50, self.ema21):
            if self.position:
                self.position.close()


