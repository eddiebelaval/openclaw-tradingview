import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Supertrend parameters
    st_atr_len = 10
    st_factor = 3.0
    
    # SMA parameter
    sma_len = 21
    
    # Strike step & width
    inst_type = "NIFTY"
    use_auto_step = True
    manual_step = 50
    use_auto_width = True
    manual_width = 200
    
    # Cooldown
    cooldown_bars = 0
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Supertrend manually
        def calc_supertrend():
            atr = pta.atr(high, low, close, length=self.st_atr_len)
            hl2_series = (high + low) / 2
            
            basic_ub = hl2_series + self.st_factor * atr
            basic_lb = hl2_series - self.st_factor * atr
            
            final_ub = pd.Series(index=close.index, dtype=float)
            final_lb = pd.Series(index=close.index, dtype=float)
            st_line = pd.Series(index=close.index, dtype=float)
            st_dir = pd.Series(index=close.index, dtype=float)
            
            for i in range(len(close)):
                if i == 0:
                    final_ub.iloc[i] = basic_ub.iloc[i]
                    final_lb.iloc[i] = basic_lb.iloc[i]
                else:
                    final_ub.iloc[i] = basic_ub.iloc[i] if basic_ub.iloc[i] < final_ub.iloc[i-1] or close.iloc[i-1] > final_ub.iloc[i-1] else final_ub.iloc[i-1]
                    final_lb.iloc[i] = basic_lb.iloc[i] if basic_lb.iloc[i] > final_lb.iloc[i-1] or close.iloc[i-1] < final_lb.iloc[i-1] else final_lb.iloc[i-1]
                
                if i == 0:
                    st_dir.iloc[i] = 1
                    st_line.iloc[i] = final_lb.iloc[i]
                else:
                    if st_dir.iloc[i-1] == 1:
                        st_line.iloc[i] = final_lb.iloc[i]
                        st_dir.iloc[i] = 1 if close.iloc[i] >= final_lb.iloc[i] else -1
                    else:
                        st_line.iloc[i] = final_ub.iloc[i]
                        st_dir.iloc[i] = -1 if close.iloc[i] <= final_ub.iloc[i] else 1
            
            return st_line, st_dir
        
        self.st_line, self.st_dir = self.I(calc_supertrend)
        
        # Calculate SMA
        self.sma21 = self.I(pta.sma, close, length=self.sma_len)
        
        # Weekly CPR levels (simulated with rolling max/min on current week proxy)
        def calc_weekly_pivots():
            # Use 5-day rolling to approximate weekly levels
            period = 5
            wh = high.rolling(window=period).max()
            wl = low.rolling(window=period).min()
            wc = close
            
            wp = (wh + wl + wc) / 3.0
            wbc = (wh + wl) / 2.0
            wtc = 2.0 * wp - wbc
            
            cpr_top = np.maximum(wtc, wbc)
            cpr_bot = np.minimum(wtc, wbc)
            
            return cpr_top, cpr_bot, wp
        
        self.cpr_top, self.cpr_bot, self.wp = self.I(calc_weekly_pivots)
        
        # Track state for entries and exits
        self.in_put_cs = False
        self.in_call_cs = False
        self.last_entry_bar = None

    def next(self):
        close_val = self.data.Close[-1]
        st_line_val = self.st_line[-1]
        sma21_val = self.sma21[-1]
        cpr_top_val = self.cpr_top[-1]
        cpr_bot_val = self.cpr_bot[-1]
        wp_val = self.wp[-1]
        
        # Skip if any value is NaN
