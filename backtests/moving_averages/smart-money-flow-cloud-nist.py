import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 34
    basisType = "EMA"
    almaOffset = 0.85
    almaSigma = 6.0
    basisSmooth = 3
    mfLen = 24
    mfSmooth = 5
    mfPower = 1.2
    atrLen = 14
    minMult = 0.9
    maxMult = 2.2
    dotCooldown = 12

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        open_ = pd.Series(self.data.Open)

        # Calculate basis
        if self.basisType == "ALMA":
            basis_raw = self.I(lambda: pta.alma(close, length=self.len, offset=self.almaOffset, sigma=self.almaSigma) or pd.Series(0, index=close.index))
        else:
            basis_raw = self.I(lambda: pta.ema(close, length=self.len) or pd.Series(0, index=close.index))

        if self.basisSmooth > 1:
            self.basis_main = self.I(lambda: pta.ema(basis_raw, length=self.basisSmooth) or pd.Series(0, index=close.index))
        else:
            self.basis_main = basis_raw

        # Calculate Money Flow
        def calc_mf():
            clv = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if high.iloc[i] == low.iloc[i]:
                    clv.iloc[i] = 0.0
                else:
                    clv.iloc[i] = ((close.iloc[i] - low.iloc[i]) - (high.iloc[i] - close.iloc[i])) / (high.iloc[i] - low.iloc[i])

            raw = clv * volume
            num = raw.rolling(window=self.mfLen).sum()
            den = raw.abs().rolling(window=self.mfLen).sum()
            mf = num / den.replace(0, np.nan)
            mf = mf.fillna(0)
            return mf

        mf = self.I(calc_mf)

        if self.mfSmooth > 1:
            mf_smooth = self.I(lambda: pta.ema(mf, length=self.mfSmooth) or pd.Series(0, index=close.index))
        else:
            mf_smooth = mf

        # Calculate flow strength
        def calc_strength(mf_smooth):
            strength = (mf_smooth.abs() ** self.mfPower).clip(0, 1)
            return strength

        self.strength = self.I(lambda: calc_strength(mf_smooth))

        # Calculate multiplier
        def calc_mult(strength):
            mult = self.minMult + (self.maxMult - self.minMult) * strength
            return mult

        self.mult = self.I(lambda: calc_mult(self.strength))

        # Calculate ATR and bands
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atrLen) or pd.Series(0, index=close.index))

        def calc_upper():
            return self.basis_main + self.atr * self.mult

        def calc_lower():
            return self.basis_main - self.atr * self.mult

        self.upper_band = self.I(lambda: calc_upper())
        self.lower_band = self.I(lambda: calc_lower())

        # Track signal state
        self.last_signal = 1  # 1 = long, -1 = short
        self.last_bear_dot_bar = -np.inf
        self.last_bull_dot_bar = -np.inf

    def next(self):
        # Update last signal based on price position relative to basis
        if self.data.Close[-1] >= self.basis_main[-1]:
            self.last_signal = 1
        else:
            self.last_signal = -1

        # Check for buy signal: price crosses above upper band (momentum breakout)
        if crossover(self.data.Close, self.upper_band):
            if not self.position:
                self.buy()
            self.last_signal = 1

        # Check for sell signal: price crosses below lower band (momentum breakdown)
        elif crossover(self.lower_band, self.data.Close):
            if self.position:
                self.position.close()
            self.last_signal = -1

        # Exit long on trend reversal (price crosses below basis in uptrend)
        elif self.position and self.last_signal == 1 and self.data.Close[-1] < self.basis_main[-1]:
            self.position.close()
            self.last_signal = -1

        # Exit short on trend reversal (price crosses above basis in downtrend)
        elif self.position and self.last_signal == -1 and self.data.Close[-1] > self.basis_main[-1]:
            self.position.close()
            self.last_signal = 1