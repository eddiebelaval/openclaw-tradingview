import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen = 21

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.emaHigh = self.I(pta.ema, high, length=self.emaLen)
        self.emaClose = self.I(pta.ema, close, length=self.emaLen)
        self.emaLow = self.I(pta.ema, low, length=self.emaLen)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Buy when EMA Close crosses above EMA Low (bullish signal)
        if crossover(self.emaClose, self.emaLow):
            if not self.position:
                self.buy()
        
        # Sell when EMA Close crosses below EMA Low (bearish signal)
        elif crossover(self.emaLow, self.emaClose):
            if self.position:
                self.position.close()
        
        # Alternative: Sell when EMA Close crosses below EMA High
        if crossover(self.emaHigh, self.emaClose):
            if self.position:
                self.position.close()