import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI KERNEL KDE Parameters
    rsi_length = 14
    kde_bandwidth = 2.71828
    kde_step = 100
    activation_threshold = 0.25
    
    # EMA Parameters
    len_fast = 9
    len_slow = 200
    
    # ATR Parameters
    atr_len = 14
    rr_mult = 1.5
    sl_mult = 1.0
    
    # SSL/Baseline Parameters
    baseline_len = 60
    ssl2_len = 5
    exit_len = 15
    atr_length = 14
    atr_mult = 1.0
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # RSI calculation
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_length) or pd.Series(50, index=close.index))
        
        # EMA calculations
        self.ema_fast = self.I(lambda: pta.ema(close, length=self.len_fast) or pd.Series(close.iloc[0], index=close.index))
        self.ema_slow = self.I(lambda: pta.ema(close, length=self.len_slow) or pd.Series(close.iloc[0], index=close.index))
        
        # ATR calculation
        self.atr = self.I(lambda: pta.atr(high, low, close, length=self.atr_len) or pd.Series(0, index=close.index))
        
        # Simple HMA for baseline
        self.baseline = self.I(self._calculate_hma, close, self.baseline_len)
        
        # State tracking
        self.last_signal = 0
        self.entry_price = 0
        self.stop_loss = 0
        self.take_profit_1 = 0
        self.take_profit_2 = 0
        self.take_profit_3 = 0
    
    def _calculate_hma(self, src, length):
        """Calculate Hull Moving Average"""
        wma1 = pta.wma(src, length=int(length / 2))
        wma2 = pta.wma(src, length=length)
        if wma1 is None or wma2 is None:
            return pd.Series(src.iloc[0], index=src.index)
        raw_hma = 2 * wma1 - wma2
        hma = pta.wma(raw_hma, length=int(np.sqrt(length)))
        if hma is None:
            return raw_hma
        return hma
    
    def next(self):
        # Get current values
        current_close = self.data.Close[-1]
        current_rsi = self.rsi[-1]
        current_ema_fast = self.ema_fast[-1]
        current_ema_slow = self.ema_slow[-1]
        current_atr = self.atr[-1]
        current_baseline = self.baseline[-1]
        
        # Check if we have valid data
        if np.isnan(current_rsi) or np.isnan(current_ema_fast) or np.isnan(current_atr):
            return
        
        # Trading Logic: EMA Crossover with Trend Filter
        # Buy Signal: Close crosses above Fast EMA, Fast EMA above Slow EMA (uptrend)
        # Sell Signal: Close crosses below Fast EMA, Fast EMA below Slow EMA (downtrend)
        
        trend_up = current_ema_fast > current_ema_slow
        trend_down = current_ema_fast < current_ema_slow
        
        # Check for crossovers
        cross_buy = crossover(self.data.Close, self.ema_fast)
        cross_sell = crossover(self.ema_fast, self.data.Close)
        
        # RSI overbought/oversold conditions for additional confirmation
        rsi_oversold = current_rsi < 40
        rsi_overbought = current_rsi > 60
        
        # Valid entry signals with state management
        valid_buy = cross_buy and trend_up and rsi_oversold and self.last_signal != 1
        valid_sell = cross_sell and trend_down and rsi_overbought and self.last_signal != -1
        
        # Execute trades
        if valid_buy and not self.position:
            self.entry_price = current_close
            self.stop_loss = current_close - (current_atr * self.sl_mult)
            self.take_profit_1 = current_close + (current_atr * self.rr_mult)
            self.take_profit_2 = current_close + (current_atr * self.rr_mult * 2)
            self.take_profit_3 = current_close + (current_atr * self.rr_mult * 3)
            self.buy()
            self.last_signal = 1
        
        elif valid_sell and self.position:
            self.sell()
            self.last_signal = -1
        
        # Exit management for long positions
        if self.position and self.position.is_long:
            # Exit if price hits stop loss
            if current_close <= self.stop_loss:
                self.sell()
                self.last_signal = 0
            # Partial exits at take profit levels (simplified - exit all at first TP)
            elif current_close >= self.take_profit_1:
                self.sell()
                self.last_signal = 0
        
        # Exit management for short positions
        elif self.position and not self.position.is_long:
            if current_close >= self.stop_loss:
                self.buy()
                self.last_signal = 0
            elif current_close <= self.take_profit_1:
                self.buy()
                self.last_signal = 0


