import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 8
    emaMidLen = 13
    emaSlowLen = 21
    rangeLen = 5
    useVolFilter = True
    volMaLen = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate EMAs on current timeframe
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaMid = self.I(pta.ema, close, length=self.emaMidLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)

        # Calculate highest high and lowest low for breakout detection
        self.rangeHigh = self.I(lambda: high.rolling(self.rangeLen).max())
        self.rangeLow = self.I(lambda: low.rolling(self.rangeLen).min())

        # Calculate volume filter
        self.avgVol = self.I(pta.sma, volume, length=self.volMaLen)

    def next(self):
        if len(self) < max(self.emaSlowLen, self.rangeLen, self.volMaLen) + 1:
            return

        # Current values
        close = self.data.Close[-1]
        emaFast = self.emaFast[-1]
        emaMid = self.emaMid[-1]
        emaSlow = self.emaSlow[-1]
        
        rangeHigh = self.rangeHigh[-2] if len(self.rangeHigh) > 1 else self.rangeHigh[-1]
        rangeLow = self.rangeLow[-2] if len(self.rangeLow) > 1 else self.rangeLow[-1]
        
        avgVol = self.avgVol[-1]
        currentVol = self.data.Volume[-1]

        # HTF trend simulation (using current timeframe EMAs as proxy since we can't fetch different timeframes in backtesting)
        htfBullish = emaFast > emaMid and emaMid > emaSlow
        htfBearish = emaFast < emaMid and emaMid < emaSlow

        # Volume filter
        highVol = currentVol > avgVol * 1.5 if avgVol > 0 else True

        # Long condition
        longCondition = (
            htfBullish and
            close > emaFast and
            emaFast > emaMid and
            emaMid > emaSlow and
            close > rangeHigh
        )

        if self.useVolFilter:
            longCondition = longCondition and highVol

        # Short condition
        shortCondition = (
            htfBearish and
            close < emaFast and
            emaFast < emaMid and
            emaMid < emaSlow and
            close < rangeLow
        )

        if self.useVolFilter:
            shortCondition = shortCondition and highVol

        # Execute trades
        if longCondition and not self.position:
            self.buy()
        elif shortCondition and self.position:
            self.position.close()


