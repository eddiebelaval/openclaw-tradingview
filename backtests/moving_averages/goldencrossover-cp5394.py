import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema5_len = 5
    ema13_len = 13
    ema26_len = 26

    def init(self):
        close = pd.Series(self.data.Close)
        self.ema5 = self.I(pta.ema, close, length=self.ema5_len)
        self.ema13 = self.I(pta.ema, close, length=self.ema13_len)
        self.ema26 = self.I(pta.ema, close, length=self.ema26_len)

    def next(self):
        if len(self.data) < 2:
            return

        # Buy condition: EMA5 was below both EMA13 and EMA26 in previous bar,
        # and EMA5 is now above both EMA13 and EMA26 in current bar
        if (self.ema5[-2] < self.ema13[-2] and self.ema5[-2] < self.ema26[-2] and
            self.ema5[-1] > self.ema13[-1] and self.ema5[-1] > self.ema26[-1]):
            if not self.position:
                self.buy()

        # Sell condition: EMA5 was above both EMA13 and EMA26 in previous bar,
        # and EMA5 is now below both EMA13 and EMA26 in current bar
        if (self.ema5[-2] > self.ema13[-2] and self.ema5[-2] > self.ema26[-2] and
            self.ema5[-1] < self.ema13[-1] and self.ema5[-1] < self.ema26[-1]):
            if self.position:
                self.position.close()


