import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atrLength = 10
    atrMultiplier = 3.0
    atrMaType = "RMA"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate True Range
        def calc_true_range():
            tr = pd.Series(index=close.index, dtype=float)
            for i in range(len(close)):
                if i == 0:
                    tr.iloc[i] = high.iloc[i] - low.iloc[i]
                else:
                    tr.iloc[i] = max(
                        high.iloc[i] - low.iloc[i],
                        abs(high.iloc[i] - close.iloc[i - 1]),
                        abs(low.iloc[i] - close.iloc[i - 1])
                    )
            return tr

        true_range = self.I(calc_true_range)

        # Apply selected MA type to True Range
        def calc_atr():
            tr_series = true_range
            if self.atrMaType == "RMA":
                atr_result = pta.rma(tr_series, length=self.atrLength)
            elif self.atrMaType == "EMA":
                atr_result = pta.ema(tr_series, length=self.atrLength)
            elif self.atrMaType == "WMA":
                atr_result = pta.wma(tr_series, length=self.atrLength)
            elif self.atrMaType == "VWMA":
                atr_result = pta.vwma(tr_series, volume, length=self.atrLength)
            else:  # SMA or default
                atr_result = pta.sma(tr_series, length=self.atrLength)

            if atr_result is None:
                return pd.Series(0, index=tr_series.index)
            return atr_result

        self.atr = self.I(calc_atr)

        # Initialize trail stop calculation
        def calc_trail_stop():
            trail_stop = pd.Series(index=low.index, dtype=float)
            trend_series = pd.Series(index=low.index, dtype=int)
            
            trail_stop_val = np.nan
            trend_val = 1

            for i in range(len(low)):
                if np.isnan(trail_stop_val):
                    up_stop = low.iloc[i] - (self.atrMultiplier * self.atr[-1]) if not np.isnan(self.atr[-1]) else low.iloc[i]
                    trail_stop_val = up_stop
                    trend_val = 1
                else:
                    atr_val = self.atr[-1] if not np.isnan(self.atr[-1]) else 0
                    
                    if trend_val == 1:
                        if low.iloc[i] < trail_stop_val:
                            trend_val = -1
                            trail_stop_val = trail_stop_val + (self.atrMultiplier * atr_val)
                        else:
                            up_stop = low.iloc[i] - (self.atrMultiplier * atr_val)
                            trail_stop_val = max(up_stop, trail_stop_val)
                    else:
                        if high.iloc[i] > trail_stop_val:
                            trend_val = 1
                            trail_stop_val = trail_stop_val - (self.atrMultiplier * atr_val)
                        else:
                            down_stop = high.iloc[i] + (self.atrMultiplier * atr_val)
                            trail_stop_val = min(down_stop, trail_stop_val)

                trail_stop.iloc[i] = trail_stop_val
                trend_series.iloc[i] = trend_val

            return trail_stop, trend_series

        trail_stop_result, trend_result = calc_trail_stop()
        self.trail_stop = self.I(lambda: trail_stop_result)
        self.trend = self.I(lambda: trend_result)
        
        self.prev_trend = None

    def next(self):
        current_trend = int(self.trend[-1])
        
        # Detect trend change
        if self.prev_trend is None:
            self.prev_trend = current_trend
        
        trend_changed = current_trend != self.prev_trend

        # Entry logic: Buy on trend change to uptrend (1)
        if trend_changed and current_trend == 1:
            if not self.position:
                self.buy()

        # Exit logic: Sell on trend change to downtrend (-1)
        if trend_changed and current_trend == -1:
            if self.position:
                self.position.close()

        self.prev_trend = current_trend


