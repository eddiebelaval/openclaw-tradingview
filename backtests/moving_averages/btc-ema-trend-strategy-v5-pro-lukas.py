        dmi_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = self.I(lambda: dmi_result['ADX_14'] if dmi_result is not None and 'ADX_14' in dmi_result else pd.Series(0, index=close.index))
        
        # SMA of ATR for volatility filter
        self.atr_sma14 = self.I(pta.sma, self.atr, length=14)
        self.atr_sma20 = self.I(pta.sma, self.atr, length=20)
        
        # Body and average body
        self.body = self.I(lambda: np.abs(close - open_))
        self.avgBody = self.I(pta.sma, self.body, length=20)
        
