import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate EMAs
        self.ema9 = self.I(pta.ema, close, length=9)
        self.ema20 = self.I(pta.ema, close, length=20)
        self.ema50 = self.I(pta.ema, close, length=50)
        self.ema200 = self.I(pta.ema, close, length=200)
        
        # Calculate VWAP
        self.vwap = self.I(pta.vwap, high, low, close, volume)
        
        # Track previous day high/low
        self.prev_day_high = np.nan
        self.prev_day_low = np.nan
        self.current_day_high = np.nan
        self.current_day_low = np.nan
        self.last_date = None
        
        # Opening range variables
        self.or_high = np.nan
        self.or_low = np.nan
        self.or_started = False
        self.or_ended = False
        self.prev_or_mid = np.nan
        
        # Session tracking
        self.in_rth = False
        self.in_premarket = False

    def next(self):
        # Simple trading logic based on EMA crossovers and VWAP
        
        # Entry signals based on EMA crossovers
        if len(self.data) < 2:
            return
        
        # Buy signal: EMA9 crosses above EMA20 and price above VWAP
        if (crossover(self.ema9, self.ema20) and 
            self.data.Close[-1] > self.vwap[-1] and
            self.data.Close[-1] > self.ema50[-1]):
            if not self.position:
                self.buy()
        
        # Sell signal: EMA9 crosses below EMA20 or price falls below VWAP
        elif (crossover(self.ema20, self.ema9) or 
              self.data.Close[-1] < self.vwap[-1]):
            if self.position:
                self.position.close()
        
        # Stop loss: Price falls significantly below EMA200
        if self.position and self.data.Close[-1] < self.ema200[-1] * 0.97:
            self.position.close()


