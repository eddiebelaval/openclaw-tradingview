import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Stage Analysis parameters
    base_weeks = 30
    
    # Bollinger Bands parameters
    bb_length = 20
    bb_mult = 2.0
    
    # Ichimoku parameters
    tenkan_period = 9
    kijun_period = 26
    senkou_span_b_period = 52
    displacement = 26

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Auto-adjust MA length (assume daily data: 150 days)
        ma_length = self.base_weeks * 5
        
        # Moving Average
        self.ma30 = self.I(pta.sma, close, length=ma_length)
        
        # Bollinger Bands
        self.bb_basis = self.I(pta.sma, close, length=self.bb_length)
        bb_dev = self.I(lambda: (close.rolling(self.bb_length).std()), )
        self.bb_upper = self.I(lambda: self.bb_basis[-len(self.data.Close):] + (self.bb_mult * bb_dev[-len(self.data.Close):]))
        self.bb_lower = self.I(lambda: self.bb_basis[-len(self.data.Close):] - (self.bb_mult * bb_dev[-len(self.data.Close):]))
        
        # Ichimoku - Tenkan-sen (Conversion Line)
        self.tenkan = self.I(lambda: (
            (high.rolling(self.tenkan_period).max() + low.rolling(self.tenkan_period).min()) / 2
        ))
        
        # Ichimoku - Kijun-sen (Base Line)
        self.kijun = self.I(lambda: (
            (high.rolling(self.kijun_period).max() + low.rolling(self.kijun_period).min()) / 2
        ))
        
        # Ichimoku - Senkou Span A
        self.senkou_span_a = self.I(lambda: (
            (self.tenkan[-len(self.data.Close):] + self.kijun[-len(self.data.Close):]) / 2
        ))
        
        # Ichimoku - Senkou Span B
        self.senkou_span_b = self.I(lambda: (
            (high.rolling(self.senkou_span_b_period).max() + low.rolling(self.senkou_span_b_period).min()) / 2
        ))
        
        # Price tracking
        self.price_above_ma = self.I(lambda: close > self.ma30[-len(self.data.Close):])
        self.ma_rising = self.I(lambda: self.ma30[-len(self.data.Close):] > self.ma30[:-1].shift(1).values)

