import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # RSI Settings
    rsiinp = 14
    rsi_ma_type = "EMA"
    rsi_ma_len = 8
    rsicross = 55
    
    # Strategy Settings
    signals = "Long & Short"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate RSI
        rsi = self.I(pta.rsi, close, length=self.rsiinp)
        
        # Calculate RSI MA based on type
        if self.rsi_ma_type == "SMA":
            rsi_ma = self.I(pta.sma, rsi, length=self.rsi_ma_len)
        elif self.rsi_ma_type == "EMA":
            rsi_ma = self.I(pta.ema, rsi, length=self.rsi_ma_len)
        elif self.rsi_ma_type == "WMA":
            rsi_ma = self.I(pta.wma, rsi, length=self.rsi_ma_len)
        elif self.rsi_ma_type == "LSMA":
            rsi_ma = self.I(pta.linreg, rsi, length=self.rsi_ma_len)
        elif self.rsi_ma_type == "VWMA":
            rsi_ma = self.I(pta.vwma, rsi, volume, length=self.rsi_ma_len)
        elif self.rsi_ma_type == "HMA":
            rsi_half = self.I(pta.wma, rsi, length=max(1, self.rsi_ma_len // 2))
            rsi_full = self.I(pta.wma, rsi, length=self.rsi_ma_len)
            rsi_ma = self.I(lambda: pta.wma(2 * rsi_half - rsi_full, length=max(1, int(np.sqrt(self.rsi_ma_len)))))
        elif self.rsi_ma_type == "DEMA":
            rsi_ema1 = self.I(pta.ema, rsi, length=self.rsi_ma_len)
            rsi_ema2 = self.I(pta.ema, rsi_ema1, length=self.rsi_ma_len)
            rsi_ma = self.I(lambda: 2 * rsi_ema1 - rsi_ema2)
        elif self.rsi_ma_type == "TEMA":
            rsi_ema1 = self.I(pta.ema, rsi, length=self.rsi_ma_len)
            rsi_ema2 = self.I(pta.ema, rsi_ema1, length=self.rsi_ma_len)
            rsi_ema3 = self.I(pta.ema, rsi_ema2, length=self.rsi_ma_len)
            rsi_ma = self.I(lambda: 3 * rsi_ema1 - 3 * rsi_ema2 + rsi_ema3)
        else:
            rsi_ma = self.I(pta.ema, rsi, length=self.rsi_ma_len)
        
        self.rsi_ma = rsi_ma
        self.rsicross_level = self.rsicross

