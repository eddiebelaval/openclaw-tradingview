import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_lookback = 5
    rsi_length = 14
    fib_entry_level = 0.5
    sl_fib_level = -0.2
    setup_duration = 30

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate main indicators
        self.vwap = self.I(lambda: pta.vwap(high, low, close))
        self.ma9 = self.I(lambda: pta.sma(close, length=9))
        self.ma20 = self.I(lambda: pta.sma(close, length=20))
        self.ma113 = self.I(lambda: pta.sma(close, length=113))
        
        # RSI for divergence detection
        self.rsi = self.I(lambda: pta.rsi(close, length=self.rsi_length))
        
        # Pivot detection using rolling max/min
        self.pivot_high = self.I(lambda: high.rolling(window=self.pivot_lookback * 2 + 1, center=True).max())
        self.pivot_low = self.I(lambda: low.rolling(window=self.pivot_lookback * 2 + 1, center=True).min())
        
        # Track structure trend and divergence
        self.structure_trend = 0
        self.last_pivot_high = None
        self.last_pivot_low = None
        self.last_pivot_high_idx = None
        self.last_pivot_low_idx = None
        
        # Track divergence pivots for RSI
        self.last_pl_price = None
        self.last_pl_rsi = None
        self.last_pl_idx = None
        self.last_ph_price = None
        self.last_ph_rsi = None
        self.last_ph_idx = None
        
        self.in_trade = False
        self.trade_entry_price = None
        self.trade_sl_price = None
        self.is_bullish_trade = False

    def next(self):
        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        current_idx = len(self.data) - 1
        
        if current_idx < self.pivot_lookback * 2 + self.rsi_length + 5:
            return
        
        # Check for pivot highs and lows
        if (self.pivot_high[-1] == high_price and 
            current_idx >= self.pivot_lookback and 
            all(self.data.High[current_idx - i] <= high_price for i in range(1, self.pivot_lookback + 1))):
            self.last_pivot_high = high_price
            self.last_pivot_high_idx = current_idx
        
        if (self.pivot_low[-1] == low_price and 
            current_idx >= self.pivot_lookback and 
            all(self.data.Low[current_idx - i] >= low_price for i in range(1, self.pivot_lookback + 1))):
            self.last_pivot_low = low_price
            self.last_pivot_low_idx = current_idx
        
        # Check for RSI divergence pivots
        rsi_val = self.rsi[-1]
        
        # Detect RSI pivot lows (bullish divergence setup)
        if (current_idx >= self.pivot_lookback and 
            all(self.rsi[current_idx - i] >= rsi_val for i in range(1, self.pivot_lookback + 1))):
            if self.last_pl_rsi is not None:
                if low_price < self.last_pl_price and rsi_val > self.last_pl_rsi:
                    # Bullish divergence confirmed
                    self.last_ph_price = None
                    self.last_ph_rsi = None
                    self.setup_bullish_trade(low_price, current_idx)
            self.last_pl_price = low_price
            self.last_pl_rsi = rsi_val
            self.last_pl_idx = current_idx
        
        # Detect RSI pivot highs (bearish divergence setup)
        if (current_idx >= self.pivot_lookback and 
            all(self.rsi[current_idx - i] <= rsi_val for i in range(1, self.pivot_lookback + 1))):
            if self.last_ph_rsi is not None:
                if high_price > self.last_ph_price and rsi_val < self.last_ph_rsi:
                    # Bearish divergence confirmed
                    self.last_pl_price = None
                    self.last_pl_rsi = None
                    self.setup_bearish_trade(high_price, current_idx)
            self.last_ph_price = high_price
            self.last_ph_rsi = rsi_val
            self.last_ph_idx = current_idx
        
        # CHoCH detection and structure trend
        if self.last_pivot_high is not None and crossover(self.data.Close, self.last_pivot_high):
            if self.structure_trend <= 0:
                self.structure_trend = 1
                self.last_pivot_high = None
        
        if self.last_pivot_low is not None and self.data.Close[-1] < self.last_pivot_low:
            if self.data.Close[-2] >= self.last_pivot_low and self.structure_trend >= 0:
                self.structure_trend = -1
                self.last_pivot_low = None
        
        # Execute trade if setup is confirmed
        if self.in_trade:
            if self.is_bullish_trade:
                # Exit on stop loss or take profit
                if close_price <= self.trade_sl_price:
                    self.sell()
                    self.in_trade = False
            else:
                # Bearish trade
                if close_price >= self.trade_sl_price:
                    self.sell()
                    self.in_trade = False

    def setup_bullish_trade(self, low_ref, current_idx):
        """Setup bullish trade from divergence"""
        if self.in_trade:
            return
        
        high_ref = self.data.High[current_idx]
        s_range = high_ref - low_ref
        
        entry_p = high_ref - (s_range * self.fib_entry_level)
        sl_p = low_ref + (s_range * self.sl_fib_level)
        
        if entry_p < self.data.Close[-1]:
            return
        
        self.trade_entry_price = entry_p
        self.trade_sl_price = sl_p
        self.is_bullish_trade = True
        self.in_trade = True
        
        self.buy()

    def setup_bearish_trade(self, high_ref, current_idx):
        """Setup bearish trade from divergence"""
        if self.in_trade:
            return
        
        low_ref = self.data.Low[current_idx]
        s_range = high_ref - low_ref
        
        entry_p = low_ref + (s_range * self.fib_entry_level)
        sl_p = high_ref - (s_range * self.sl_fib_level)
        
        if entry_p > self.data.Close[-1]:
            return
        
        self.trade_entry_price = entry_p
        self.trade_sl_price = sl_p
        self.is_bullish_trade = False
        self.in_trade = True
        
        self.buy()


