import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    instrument = "NIFTY"
    nifty_target = 15
    nifty_sl = 7.5
    crude_target = 10
    crude_sl = 2.5
    ng_target = 2
    ng_sl = 0.5
    stock_target = 5
    stock_sl = 2
    opt_target = 20
    opt_sl = 10
    rsi_len = 14
    tp1_rr = 1.0
    tp2_rr = 1.5
    tp3_rr = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.ema9 = self.I(pta.ema, close, length=9)
        self.ema30 = self.I(pta.ema, close, length=30)
        self.ema200 = self.I(pta.ema, close, length=200)

        self.rsi = self.I(pta.rsi, close, length=self.rsi_len)

        adx_result = self.I(pta.adx, high, low, close, length=14)
        self.adx = self.I(lambda: pta.adx(high, low, close, length=14)['ADX_14'] if pta.adx(high, low, close, length=14) is not None else pd.Series(50, index=close.index))

        self.high_prev = self.I(lambda: high.shift(1))
        self.low_prev = self.I(lambda: low.shift(1))
        self.volume_prev = self.I(lambda: volume.shift(1))

        self.last_signal = 0
        self.entry_price = None
        self.in_trade = False

    def next(self):
        close_curr = self.data.Close[-1]
        close_prev = self.data.Close[-2] if len(self.data.Close) > 1 else close_curr
        volume_curr = self.data.Volume[-1]
        volume_prev = self.data.Volume[-2] if len(self.data.Volume) > 1 else volume_curr
        high_prev = self.data.High[-2] if len(self.data.High) > 1 else self.data.High[-1]
        low_prev = self.data.Low[-2] if len(self.data.Low) > 1 else self.data.Low[-1]

        ema9_val = self.ema9[-1]
        ema30_val = self.ema30[-1]
        ema200_val = self.ema200[-1]
        rsi_val = self.rsi[-1]
        adx_val = self.adx[-1]

        price_up = close_curr > close_prev
        price_down = close_curr < close_prev
        vol_up = volume_curr > volume_prev
        vol_down = volume_curr < volume_prev

        smart_long = price_up and volume_curr > volume_prev * 1.5
        smart_short = price_down and volume_curr > volume_prev * 1.5

        score_bull = 0
        score_bull += 20 if ema9_val > ema30_val else 0
        score_bull += 15 if close_curr > ema200_val else 0
        score_bull += 15 if rsi_val > 55 else 0
        score_bull += 25 if smart_long else 0
        score_bull += 15 if (price_up and vol_up) else 0
        score_bull += 10 if close_curr > high_prev else 0

        score_bear = 0
        score_bear += 20 if ema9_val < ema30_val else 0
        score_bear += 15 if close_curr < ema200_val else 0
        score_bear += 15 if rsi_val < 45 else 0
        score_bear += 25 if smart_short else 0
        score_bear += 15 if (price_down and vol_up) else 0
        score_bear += 10 if close_curr < low_prev else 0

        if self.instrument == "NIFTY":
            target = self.nifty_target
            sl = self.nifty_sl
        elif self.instrument == "CRUDE":
            target = self.crude_target
            sl = self.crude_sl
        elif self.instrument == "NATURAL GAS":
            target = self.ng_target
            sl = self.ng_sl
        elif self.instrument == "STOCK":
            target = self.stock_target
            sl = self.stock_sl
        else:
            target = self.opt_target
            sl = self.opt_sl

        buy_signal = (
            close_curr > ema30_val and
            close_curr > high_prev and
            rsi_val > 55 and
            score_bull > score_bear and
            self.last_signal <= 0
        )

        sell_signal = (
            close_curr < ema30_val and
            close_curr < low_prev and
            rsi_val < 45 and
            score_bear > score_bull and
            self.last_signal >= 0
        )

        if buy_signal:
            if not self.position:
                self.buy()
            self.last_signal = 1
            self.entry_price = close_curr
            self.in_trade = True

        if sell_signal:
            if self.position:
                self.position.close()
            self.last_signal = -1
            self.entry_price = close_curr
            self.in_trade = True

        if self.in_trade and self.entry_price is not None:
            if self.last_signal == 1:
                tp1 = self.entry_price + target * self.tp1_rr
                tp2 = self.entry_price + target * self.tp2_rr
                tp3 = self.entry_price + target * self.tp3_rr
                sl_price = self.entry_price - sl

                if close_curr >= tp3 or close_curr <= sl_price:
                    if self.position:
                        self.position.close()
                    self.in_trade = False

            elif self.last_signal == -1:
                tp1 = self.entry_price - target * self.tp1_rr
                tp2 = self.entry_price - target * self.tp2_rr
                tp3 = self.entry_price - target * self.tp3_rr
                sl_price = self.entry_price + sl

                if close_curr <= tp3 or close_curr >= sl_price:
                    if self.position:
                        self.position.close()
                    self.in_trade = False