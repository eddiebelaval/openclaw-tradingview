import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    i_fast = 12
    i_slow = 26
    i_sig = 9
    garch_window = 20
    garch_long_window = 100

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume-Weighted MACD components
        self.vw_fast = self.I(pta.vwma, close, volume, length=self.i_fast)
        self.vw_slow = self.I(pta.vwma, close, volume, length=self.i_slow)
        
        # VW-MACD line
        self.vw_macd = self.I(lambda: self.vw_fast - self.vw_slow)
        
        # Signal line (EMA of MACD)
        self.vw_signal = self.I(lambda: pta.ema(pd.Series(self.vw_macd), length=self.i_sig) if len([x for x in self.vw_macd if x is not None]) > 0 else pd.Series(0, index=close.index))
        
        # GARCH volatility calculation
        self.garch_vol = self.I(self._calculate_garch_volatility)
        self.garch_sma = self.I(lambda: pta.sma(pd.Series(self.garch_vol), length=self.garch_window) if len([x for x in self.garch_vol if x is not None]) > 0 else pd.Series(0, index=close.index))

    def _calculate_garch_volatility(self):
        close = pd.Series(self.data.Close)
        
        ret = np.log(close / close.shift(1))
        ret_sq = ret ** 2
        
        garch_vol = pd.Series(index=close.index, dtype=float)
        variance = 0.0
        
        for i in range(len(close)):
            if i < 50:
                variance = ret_sq.iloc[:i+1].var() if i > 0 else 0.0
            else:
                omega = (1.0 - 0.1 - 0.85) * ret_sq.iloc[max(0, i-self.garch_long_window):i+1].var()
                variance = omega + (0.1 * ret_sq.iloc[i]) + (0.85 * variance)
            
            garch_vol.iloc[i] = np.sqrt(max(variance, 0)) * 100
        
        return garch_vol

    def next(self):
        if len(self.data) < max(self.i_slow, self.i_sig) + 10:
            return
        
