import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_len = 21

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema_high = self.I(pta.ema, high, length=self.ema_len)
        self.ema_close = self.I(pta.ema, close, length=self.ema_len)
        self.ema_low = self.I(pta.ema, low, length=self.ema_len)

    def next(self):
        if len(self.data) < 2:
            return
        
        current_close = self.data.Close[-1]
        prev_ema_close = self.ema_close[-2]
        curr_ema_close = self.ema_close[-1]
        curr_ema_high = self.ema_high[-1]
        curr_ema_low = self.ema_low[-1]
        
        ema_rising = curr_ema_close > prev_ema_close
        ema_falling = curr_ema_close < prev_ema_close
        
        if current_close > curr_ema_high and ema_rising:
            if not self.position:
                self.buy()
        elif current_close > curr_ema_close and ema_rising:
            if not self.position:
                self.buy()
        elif current_close < curr_ema_low and ema_falling:
            if self.position:
                self.position.close()
        elif current_close < curr_ema_close and ema_falling:
            if self.position:
                self.position.close()


