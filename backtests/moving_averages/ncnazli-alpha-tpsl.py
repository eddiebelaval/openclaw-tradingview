        if np.isnan(alpha_prev3):
            return

        # Improved signal detection using previous values
        prev_buy = self.alphaTrend[-2] > alpha_prev3
        prev_sell = self.alphaTrend[-2] < alpha_prev3

        final_buy = buy_signal and not prev_buy
        final_sell = sell_signal and not prev_sell

        if final_buy:
            if not self.position:
                self.buy()

        elif final_sell:
            if self.position:
                self.sell()


