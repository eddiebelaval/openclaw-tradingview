import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    coeff = 1.0
    ap = 14
    noVolumeData = False
    slAtrMult = 1.0
    tp1AtrMult = 1.0
    tp2AtrMult = 2.0
    tp3AtrMult = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        hlc3 = (high + low + close) / 3

        # Calculate True Range
        tr = pd.Series(index=close.index, dtype=float)
        tr.iloc[0] = high.iloc[0] - low.iloc[0]
        for i in range(1, len(close)):
            tr.iloc[i] = max(
                high.iloc[i] - low.iloc[i],
                abs(high.iloc[i] - close.iloc[i-1]),
                abs(low.iloc[i] - close.iloc[i-1])
            )

        # ATR calculation using SMA of TR
        atr_vals = pta.sma(tr, length=self.ap)
        self.atr = self.I(lambda: atr_vals if atr_vals is not None else pd.Series(0.0, index=close.index))

        # Calculate upT and downT
        self.upT = self.I(lambda: low - self.atr * self.coeff)
        self.downT = self.I(lambda: high + self.atr * self.coeff)

        # Calculate RSI or MFI for condition
        if self.noVolumeData:
            rsi_vals = pta.rsi(close, length=self.ap)
            self.condition = self.I(lambda: (rsi_vals >= 50) if rsi_vals is not None else pd.Series(False, index=close.index))
        else:
            mfi_vals = pta.mfi(high, low, close, volume, length=self.ap)
            self.condition = self.I(lambda: (mfi_vals >= 50) if mfi_vals is not None else pd.Series(False, index=close.index))

        # AlphaTrend calculation
        self.alphaTrend = self.I(self._calc_alpha_trend, close, low, high)

    def _calc_alpha_trend(self, close):
        result = pd.Series(index=close.index, dtype=float)
        alpha_val = np.nan

        for i in range(len(close)):
            if i < 2:
                result.iloc[i] = np.nan
                continue

            up_t = self.upT[-1 - (len(close) - 1 - i)] if i < len(self.upT) else np.nan
            down_t = self.downT[-1 - (len(close) - 1 - i)] if i < len(self.downT) else np.nan
            cond = self.condition[-1 - (len(close) - 1 - i)] if i < len(self.condition) else False

            if cond:
                if up_t < alpha_val or np.isnan(alpha_val):
                    alpha_val = alpha_val if not np.isnan(alpha_val) else up_t
                else:
                    alpha_val = up_t
            else:
                if down_t > alpha_val or np.isnan(alpha_val):
                    alpha_val = alpha_val if not np.isnan(alpha_val) else down_t
                else:
                    alpha_val = down_t

            result.iloc[i] = alpha_val

        return result

    def next(self):
        if len(self.data) < 3:
            return

        alpha_current = self.alphaTrend[-1]
        alpha_prev2 = self.alphaTrend[-3] if len(self.alphaTrend) >= 3 else np.nan

        if np.isnan(alpha_current) or np.isnan(alpha_prev2):
            return

        # Buy signal: alphaTrend crosses above alphaTrend[2]
        if crossover(self.alphaTrend[-3:-1], self.alphaTrend[-3:-1]):
            pass

        buy_signal = alpha_current > alpha_prev2
        sell_signal = alpha_current < alpha_prev2

        if len(self.data) < 4:
            return

