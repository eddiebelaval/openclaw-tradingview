import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA Type: "EMA" or "SMA"
    matype = "EMA"
    
    # Cloud visibility toggles
    ema1_on = True
    ema2_on = True
    ema3_on = True
    ema4_on = True
    show200sma = True
    
    # Length inputs
    len1s = 13
    len1l = 14
    len2s = 9
    len2l = 21
    len3s = 50
    len3l = 63
    len4s = 180
    len4l = 200

    def init(self):
        # Use hl2 (high + low) / 2 as source
        src = pd.Series((self.data.High + self.data.Low) / 2)
        close = pd.Series(self.data.Close)
        
        # Cloud 1
        if self.matype == "EMA":
            self.m1s = self.I(pta.ema, src, length=self.len1s)
            self.m1l = self.I(pta.ema, src, length=self.len1l)
        else:
            self.m1s = self.I(pta.sma, src, length=self.len1s)
            self.m1l = self.I(pta.sma, src, length=self.len1l)
        
        # Cloud 2
        if self.matype == "EMA":
            self.m2s = self.I(pta.ema, src, length=self.len2s)
            self.m2l = self.I(pta.ema, src, length=self.len2l)
        else:
            self.m2s = self.I(pta.sma, src, length=self.len2s)
            self.m2l = self.I(pta.sma, src, length=self.len2l)
        
        # Cloud 3
        if self.matype == "EMA":
            self.m3s = self.I(pta.ema, src, length=self.len3s)
            self.m3l = self.I(pta.ema, src, length=self.len3l)
        else:
            self.m3s = self.I(pta.sma, src, length=self.len3s)
            self.m3l = self.I(pta.sma, src, length=self.len3l)
        
        # Cloud 4
        if self.matype == "EMA":
            self.m4s = self.I(pta.ema, src, length=self.len4s)
            self.m4l = self.I(pta.ema, src, length=self.len4l)
        else:
            self.m4s = self.I(pta.sma, src, length=self.len4s)
            self.m4l = self.I(pta.sma, src, length=self.len4l)
        
        # 200 SMA
        self.sma200 = self.I(pta.sma, close, length=200)

    def next(self):
        # Trading logic based on cloud configurations
        # Buy when price is above all short MAs and they are above their long counterparts
        # Sell when price is below short MAs or they cross below long MAs
        
        if len(self) < self.len4l:
            return
        
        # Count how many clouds show bullish configuration (short > long)
        bullish_count = 0
        if self.ema1_on and self.m1s[-1] > self.m1l[-1]:
            bullish_count += 1
        if self.ema2_on and self.m2s[-1] > self.m2l[-1]:
            bullish_count += 1
        if self.ema3_on and self.m3s[-1] > self.m3l[-1]:
            bullish_count += 1
        if self.ema4_on and self.m4s[-1] > self.m4l[-1]:
            bullish_count += 1
        
        # Entry signal: at least 3 clouds are bullish
        if not self.position:
            if bullish_count >= 3:
                self.buy()
        else:
            # Exit signal: fewer than 2 clouds are bullish
            if bullish_count < 2:
                self.sell()


