import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_fast_len = 9
    ema_slow_len = 50
    sl_swing_lookback = 300
    tp_swing_lookback = 300
    sl_offset_ticks = 0
    trend_mode = "EMA Cross"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        hlc3 = (high + pd.Series(self.data.Close) + low) / 3

        self.mtf_fast = self.I(pta.ema, close, length=self.ema_fast_len)
        self.mtf_slow = self.I(pta.ema, close, length=self.ema_slow_len)
        
        self.hma_val = self.I(pta.hma, close, length=self.ema_fast_len)
        
        self.vwap_1 = self.I(pta.vwap, hlc3, volume=pd.Series(self.data.Volume))
        self.vwap_2 = self.I(pta.vwap, hlc3, volume=pd.Series(self.data.Volume))
        
        self.tp_long_level = self.I(lambda: high.rolling(self.tp_swing_lookback).max())
        self.sl_long_level = self.I(lambda: low.rolling(self.sl_swing_lookback).min())
        
        self.tp_short_level = self.I(lambda: low.rolling(self.tp_swing_lookback).min())
        self.sl_short_level = self.I(lambda: high.rolling(self.sl_swing_lookback).max())

    def next(self):
        if len(self.data) < max(self.ema_fast_len, self.ema_slow_len, self.sl_swing_lookback, self.tp_swing_lookback) + 1:
            return

        if self.trend_mode == "EMA Cross":
            h1_trend_bull = self.mtf_fast[-1] > self.mtf_slow[-1]
        else:
            h1_trend_bull = self.hma_val[-1] > self.hma_val[-2] if len(self.hma_val) > 1 else False

        current_price = self.data.Close[-1]

        if h1_trend_bull and not self.position:
            if current_price > self.vwap_1[-1]:
                self.buy()
        elif not h1_trend_bull and self.position:
            self.sell()

        if self.position:
            if h1_trend_bull:
                if self.position.is_long:
                    if current_price <= self.sl_long_level[-1]:
                        self.sell()
                    elif current_price >= self.tp_long_level[-1]:
                        self.sell()
            else:
                if self.position.is_long:
                    self.sell()