import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pivot_len = 5
    volMult = 2.0
    cvd_len = 21
    divLb = 2
    maxDivBars = 60
    sr_len = 50
    rsi_os_lvl = 15
    rsi_ob_lvl = 85

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Volume indicators
        self.avgVol = self.I(lambda: pta.sma(volume, length=20))
        
        # RSI for alarms
        self.rsi = self.I(lambda: pta.rsi(close, length=14))
        
        # EMA and WMA for trend
        self.ema50 = self.I(lambda: pta.ema(close, length=50))
        self.wma200 = self.I(lambda: pta.wma(close, length=200))
        
        # MACD for trend confirmation
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macd = macd_result.iloc[:, 0] if macd_result is not None else pd.Series(0, index=close.index)
        self.macd_signal = macd_result.iloc[:, 2] if macd_result is not None else pd.Series(0, index=close.index)
        
        # ADX for trend strength
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = adx_result.iloc[:, 2] if adx_result is not None else pd.Series(25, index=close.index)
        
        # Pivot highs and lows for SMC structure
        self.pivot_high = self.I(lambda: self._get_pivot_high(high))
        self.pivot_low = self.I(lambda: self._get_pivot_low(low))
        
