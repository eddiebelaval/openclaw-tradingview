import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime


class TvStrategy(Strategy):
    sl_ticks = 50
    tp1_ticks = 100
    tp2_ticks = 200
    ema_len = 50
    atr_len = 14
    cooldown_bars = 15

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema50 = self.I(pta.ema, close, length=self.ema_len)
        self.atr_val = self.I(pta.atr, high, low, close, length=self.atr_len)
        
        self.bars_since_exit = 0
        self.entry_price = None
        self.sl_price = None
        self.tp1_price = None
        self.tp2_price = None
        self.be_price = None
        self.is_buy = False
        self.status = "IDLE"
        self.tp1_hit = False
        self.tick = 0.01

    def next(self):
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_open = self.data.Open[-1]
        current_volume = self.data.Volume[-1]
        
        if len(self.data) < 2:
            return
        
        prev_close = self.data.Close[-2]
        prev_open = self.data.Open[-2]
        prev_high = self.data.High[-2]
        prev_low = self.data.Low[-2]
        prev_volume = self.data.Volume[-2]
        
        ema50_val = self.ema50[-1] if self.ema50[-1] is not None else prev_close
        atr_val = self.atr_val[-1] if self.atr_val[-1] is not None else 0
        
        trend_bull = current_close > ema50_val
        trend_bear = current_close < ema50_val
        
        et_hour = datetime.now().hour
        et_mins = et_hour * 60 + datetime.now().minute
        is_ny = et_mins >= 570 and et_mins < 960
        is_asia = et_mins >= 1200 or et_mins < 180
        session_ok = is_asia or is_ny
        
        self.bars_since_exit = 0 if len(self.position) > 0 else self.bars_since_exit + 1
        cooldown_ok = self.bars_since_exit >= self.cooldown_bars
        
        bull_candle = (current_close > current_open and 
                      current_high >= prev_high and 
                      current_low <= prev_low and 
                      current_close > prev_open)
        
        bear_candle = (current_close < current_open and 
                      current_high >= prev_high and 
                      current_low <= prev_low and 
                      current_close < prev_open)
        
        vol_ok = current_volume > prev_volume * 1.3
        
        ecv_buy = bull_candle and vol_ok and trend_bull and cooldown_ok and session_ok
        ecv_sell = bear_candle and vol_ok and trend_bear and cooldown_ok and session_ok
        
        if (ecv_buy or ecv_sell) and self.status == "IDLE":
            self.is_buy = ecv_buy
            self.entry_price = current_close
            
            if self.is_buy:
                self.sl_price = self.entry_price - self.sl_ticks * self.tick
                self.tp1_price = self.entry_price + self.tp1_ticks * self.tick
                self.tp2_price = self.entry_price + self.tp2_ticks * self.tick
                self.be_price = self.entry_price + self.sl_ticks * self.tick
            else:
                self.sl_price = self.entry_price + self.sl_ticks * self.tick
                self.tp1_price = self.entry_price - self.tp1_ticks * self.tick
                self.tp2_price = self.entry_price - self.tp2_ticks * self.tick
                self.be_price = self.entry_price - self.sl_ticks * self.tick
            
            self.status = "IN_TRADE"
            self.tp1_hit = False
            
            self.buy() if self.is_buy else self.sell()
        
        if len(self.position) > 0 and self.status == "IN_TRADE":
            if self.is_buy and current_close >= self.be_price and not self.tp1_hit:
                self.tp1_hit = True
                self.position.close(portion=0.5)
            
            elif not self.is_buy and current_close <= self.be_price and not self.tp1_hit:
                self.tp1_hit = True
                self.position.close(portion=0.5)
        
        if len(self.position) == 0 and self.status == "IN_TRADE":
            self.status = "IDLE"
            self.entry_price = None
            self.sl_price = None
            self.tp1_price = None
            self.tp2_price = None
            self.be_price = None
            self.tp1_hit = False


