import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 20
    slowLen = 200

    def init(self):
        close = pd.Series(self.data.Close)
        self.fastSMA = self.I(pta.sma, close, length=self.fastLen)
        self.slowSMA = self.I(pta.sma, close, length=self.slowLen)

    def next(self):
        if len(self.data) < self.slowLen:
            return
        
        if crossover(self.fastSMA, self.slowSMA):
            if not self.position:
                self.buy()
        elif crossover(self.slowSMA, self.fastSMA):
            if self.position:
                self.position.close()


if __name__ == "__main__":
    from backtesting.test import GOOG
    
    bt = Backtest(GOOG, TvStrategy, cash=10000, commission=.002)
    stats = bt.run()
    print(stats)
    bt.plot()