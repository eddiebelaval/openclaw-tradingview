import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_length = 200
    event_type = "Breakdown"
    cooldown_bars = 21

    def init(self):
        close = pd.Series(self.data.Close)
        self.ma = self.I(pta.sma, close, length=self.ma_length)
        self.last_event_bar = -9999
        self.in_cooldown = True

    def next(self):
        if len(self.data) < self.ma_length + 1:
            return

        current_close = self.data.Close[-1]
        current_ma = self.ma[-1]
        prev_close = self.data.Close[-2]
        prev_ma = self.ma[-2]

        if pd.isna(current_ma) or pd.isna(prev_ma):
            return

        breakdown = prev_close > prev_ma and current_close <= current_ma
        breakout = prev_close < prev_ma and current_close >= current_ma

        bars_since_event = len(self.data) - self.last_event_bar
        cooldown_ok = bars_since_event >= self.cooldown_bars

        event = False
        if self.event_type == "Breakdown" and breakdown and cooldown_ok:
            event = True
        elif self.event_type == "Breakout" and breakout and cooldown_ok:
            event = True

        if event:
            self.last_event_bar = len(self.data)
            if not self.position:
                self.buy()
            else:
                self.sell()
        elif self.position and len(self.data) % 252 == 0:
            self.sell()


