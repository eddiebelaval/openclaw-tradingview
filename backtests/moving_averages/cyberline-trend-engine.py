import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 10
    emaSlowLen = 50
    volMultiplier = 1.1
    volLookback = 20
    atrSens = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Calculate EMAs for ribbon
        step = (self.emaSlowLen - self.emaFastLen) / 7.0
        
        self.ema1 = self.I(pta.ema, close, length=int(self.emaFastLen + step * 0))
        self.ema2 = self.I(pta.ema, close, length=int(self.emaFastLen + step * 1))
        self.ema3 = self.I(pta.ema, close, length=int(self.emaFastLen + step * 2))
        self.ema4 = self.I(pta.ema, close, length=int(self.emaFastLen + step * 3))
        self.ema5 = self.I(pta.ema, close, length=int(self.emaFastLen + step * 4))
        self.ema6 = self.I(pta.ema, close, length=int(self.emaFastLen + step * 5))
        self.ema7 = self.I(pta.ema, close, length=int(self.emaFastLen + step * 6))
        self.ema8 = self.I(pta.ema, close, length=int(self.emaFastLen + step * 7))

        # Volume check
        self.avg_vol = self.I(pta.sma, volume, length=self.volLookback)

        # ATR for strength calculation
        self.atr = self.I(pta.atr, high, low, close, length=14)

        # VWAP
        self.vwap = self.I(pta.vwap, close, volume=volume)

        # Track last signal state to avoid consecutive same signals
        self.last_signal_state = 0

    def next(self):
        if len(self.data) < 50:
            return

        close = self.data.Close[-1]
        volume = self.data.Volume[-1]

        # Get ribbon bounds
        upper_main = max(self.ema1[-1], self.ema8[-1])
        lower_main = min(self.ema1[-1], self.ema8[-1])

        # Trend determination
        bullish = self.ema1[-1] > self.ema8[-1]
        bearish = self.ema1[-1] <= self.ema8[-1]

        # Volume confirmation
        avg_vol = self.avg_vol[-1] if self.avg_vol[-1] is not None else 0
        vol_confirmed = volume > (avg_vol * self.volMultiplier)

        # Strength calculation
        atr_val = self.atr[-1] if self.atr[-1] is not None else 1.0
        strength = abs(close - self.ema8[-1]) / (max(atr_val * self.atrSens, 1.0))

        # Signal conditions
        buy_cond = close > upper_main and bullish and vol_confirmed
        sell_cond = close < lower_main and bearish and vol_confirmed
        bull_rev_cond = close > upper_main and bearish
        bear_rev_cond = close < lower_main and bullish

        # Apply signal suppression logic
        buy_signal = buy_cond and self.last_signal_state != 1
        sell_signal = sell_cond and self.last_signal_state != 2
        bull_rev = bull_rev_cond and self.last_signal_state != 3
        bear_rev = bear_rev_cond and self.last_signal_state != 4

        if buy_signal:
            self.last_signal_state = 1
            if not self.position:
                self.buy()
        elif sell_signal:
            self.last_signal_state = 2
            if self.position:
                self.position.close()
        elif bull_rev:
            self.last_signal_state = 3
            if not self.position:
                self.buy()
        elif bear_rev:
            self.last_signal_state = 4
            if self.position:
                self.position.close()


