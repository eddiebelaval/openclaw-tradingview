import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema200Length = 200
    ema400Length = 400

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema200 = self.I(pta.ema, close, length=self.ema200Length)
        self.ema400 = self.I(pta.ema, close, length=self.ema400Length)

    def next(self):
        if len(self.data) < max(self.ema200Length, self.ema400Length):
            return
        
        ema200_val = self.ema200[-1]
        ema400_val = self.ema400[-1]
        close_val = self.data.Close[-1]
        
        if ema200_val is None or ema400_val is None:
            return
        
        if not self.position:
            if crossover(self.ema200, self.ema400):
                self.buy()
        else:
            if crossover(self.ema400, self.ema200):
                self.sell()


