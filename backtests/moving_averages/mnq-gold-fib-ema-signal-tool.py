import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 20
    ema_len = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA 200 for trend filter
        self.ema200 = self.I(pta.ema, close, length=self.ema_len)
        
        # Fibonacci levels using rolling highest/lowest
        self.hi = self.I(lambda: high.rolling(window=self.lookback).max())
        self.lo = self.I(lambda: low.rolling(window=self.lookback).min())
        
        # Range calculation
        self.range_ = self.I(lambda: self.hi[-len(self.hi):] - self.lo[-len(self.lo):])
        
        # Fibonacci levels
        self.fib_618 = self.I(lambda: self.hi[-len(self.hi):] - (self.range_[-len(self.range_):] * 0.618))

    def next(self):
        if len(self.data) < self.lookback + self.ema_len:
            return
        
        close = self.data.Close[-1]
        ema200 = self.ema200[-1]
        fib_618 = self.fib_618[-1]
        
        if ema200 is None or fib_618 is None:
            return
        
        # Bullish: Price is above EMA200 AND price crosses above 61.8% Fib
        long_signal = close > ema200 and crossover(self.data.Close[-2:], fib_618)
        
        # Bearish: Price is below EMA200 AND price crosses below 61.8% Fib
        short_signal = close < ema200 and crossover(fib_618, self.data.Close[-2:])
        
        if long_signal and not self.position:
            self.buy()
        elif short_signal and self.position:
            self.sell()


