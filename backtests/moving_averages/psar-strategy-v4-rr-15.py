import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    smaLength = 100
    bbLength = 20
    bbDev = 2.0
    psarStart = 0.01
    psarIncrement = 0.01
    psarMax = 0.2
    rrRatio = 6.0
    tradeDirection = "Both"
    useRSI = True
    rsiLength = 14
    rsiBuyLevel = 55
    rsiSellLevel = 45
    useBBFilter = True
    lookbackBars = 0
    useSessionFilter = False
    tradeAsian = True
    tradeLondon = True
    tradeNY = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # SMA
        self.smaVal = self.I(pta.sma, close, length=self.smaLength)
        
        # Bollinger Bands
        self.basis = self.I(pta.sma, close, length=self.bbLength)
        self.dev = self.I(lambda: self.bbDev * pta.stdev(close, length=self.bbLength))
        self.upperBB = self.I(lambda: self.basis + self.dev)
        self.lowerBB = self.I(lambda: self.basis - self.dev)
        
        # PSAR
        self.psarVal = self.I(pta.sar, high, low, close, 
                              iaf=self.psarStart, af=self.psarIncrement, maxaf=self.psarMax)
        
        # RSI
        if self.useRSI:
            self.rsiVal = self.I(pta.rsi, close, length=self.rsiLength)
        else:
            self.rsiVal = self.I(lambda: pd.Series(50, index=close.index))
        
        self.prev_psar = None
        self.prev_close = None

    def next(self):
        if len(self.data) < 2:
            return
        
        close_curr = self.data.Close[-1]
        close_prev = self.data.Close[-2]
        psar_curr = self.psarVal[-1]
        psar_prev = self.psarVal[-2] if len(self.psarVal) > 1 else None
        sma_curr = self.smaVal[-1]
        basis_curr = self.basis[-1]
        rsi_curr = self.rsiVal[-1]
        
        if pd.isna(psar_curr) or pd.isna(psar_prev) or pd.isna(sma_curr) or pd.isna(basis_curr):
            return
        
        # PSAR flip detection
        psarFlipToLong = psar_prev > close_prev and psar_curr < close_curr
        psarFlipToShort = psar_prev < close_prev and psar_curr > close_curr
        
        # BB Mid Filter
        noBelowMid = True
        noAboveMid = True
        
        if self.useBBFilter:
            for i in range(1, self.lookbackBars + 1):
                if len(self.data.Close) > i:
                    if self.data.Close[-i] < self.basis[-i]:
                        noBelowMid = False
                    if self.data.Close[-i] > self.basis[-i]:
                        noAboveMid = False
        
        # Session Filter
        sessionAllowed = True
        if self.useSessionFilter:
            bar_time = self.data.index[-1]
            currentHour = bar_time.hour
            currentMinute = bar_time.minute
            
            isAsianSession = currentHour >= 0 and (currentHour < 9 or (currentHour == 9 and currentMinute == 0))
            isLondonSession = currentHour >= 8 and (currentHour < 17 or (currentHour == 17 and currentMinute == 0))
            isNYSession = currentHour >= 13 and (currentHour < 22 or (currentHour == 22 and currentMinute == 0))
            
            sessionAllowed = ((self.tradeAsian and isAsianSession) or 
                             (self.tradeLondon and isLondonSession) or 
                             (self.tradeNY and isNYSession))
        
        # Entry conditions
        longCondition = (sessionAllowed and 
                        (self.tradeDirection == "Both" or self.tradeDirection == "Just Buy") and
                        psarFlipToLong and 
                        close_curr > sma_curr and 
                        close_curr > basis_curr and 
                        noBelowMid and 
                        (not self.useRSI or rsi_curr > self.rsiBuyLevel))
        
        shortCondition = (sessionAllowed and 
                         (self.tradeDirection == "Both" or self.tradeDirection == "Just Sell") and
                         psarFlipToShort and 
                         close_curr < sma_curr and 
                         close_curr < basis_curr and 
                         noAboveMid and 
                         (not self.useRSI or rsi_curr < self.rsiSellLevel))
        
        # Calculate SL/TP
        longSL = psar_curr
        shortSL = psar_curr
        longTP = close_curr + (close_curr - longSL) * self.rrRatio
        shortTP = close_curr - (shortSL - close_curr) * self.rrRatio
        
        # Execute trades
        if longCondition:
            if not self.position:
                self.buy()
        
        if shortCondition:
            if not self.position:
                self.sell()
        
        # Exit conditions
        if self.position:
            if self.position.is_long:
                if close_curr <= longSL or close_curr >= longTP:
                    self.position.close()
            elif self.position.is_short:
                if close_curr >= shortSL or close_curr <= shortTP:
                    self.position.close()


