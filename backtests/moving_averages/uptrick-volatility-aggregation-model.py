import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Ensemble parameters
    scoreBuy = 0.10
    scoreSell = -0.10
    
    # Trail parameters
    trailSmooth = 4
    atrLen = 14
    atrLayerMult = 0.90
    
    # 5 Speeds parameters
    len1 = 8
    len2 = 10
    len3 = 14
    len4 = 20
    len5 = 28
    
    mult1 = 1.05
    mult2 = 1.10
    mult3 = 1.15
    mult4 = 1.20
    mult5 = 1.25
    
    band1 = 1.15
    band2 = 1.20
    band3 = 1.25
    band4 = 1.30
    band5 = 1.35
    
    smooth1 = 2
    smooth2 = 2
    smooth3 = 3
    smooth4 = 3
    smooth5 = 4

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Helper function to compute r1Side engine
        def compute_side(src, length, mult, band_mult, smooth):
            tr = high - low
            tr = np.where(tr > (high - close.shift(1)).abs(), tr, (high - close.shift(1)).abs())
            tr = np.where(tr > (low - close.shift(1)).abs(), tr, (low - close.shift(1)).abs())
            tr = pd.Series(tr)
            
            r1_raw = pta.ema(tr, length=length) * mult
            r1 = pta.ema(r1_raw, length=smooth)
            
            center = pd.Series(index=src.index, dtype=float)
            center.iloc[0] = src.iloc[0]
            
            for i in range(1, len(src)):
                prev = center.iloc[i-1]
                diff = src.iloc[i] - prev
                if r1.iloc[i] > 0:
                    if diff > r1.iloc[i]:
                        center.iloc[i] = prev + (diff - r1.iloc[i])
                    elif diff < -r1.iloc[i]:
                        center.iloc[i] = prev + (diff + r1.iloc[i])
                    else:
                        center.iloc[i] = prev
                else:
                    center.iloc[i] = prev
            
            upper_raw = center + r1 * band_mult
            lower_raw = center - r1 * band_mult
            
            upper = pta.ema(upper_raw, length=smooth)
            lower = pta.ema(lower_raw, length=smooth)
            
            side = pd.Series(1, index=src.index)
            for i in range(1, len(src)):
                if src.iloc[i] > upper.iloc[i] and src.iloc[i-1] <= upper.iloc[i-1]:
                    side.iloc[i] = 1
                elif src.iloc[i] < lower.iloc[i] and src.iloc[i-1] >= lower.iloc[i-1]:
                    side.iloc[i] = -1
                else:
                    side.iloc[i] = side.iloc[i-1]
            
            return side, upper, lower
        
        # Compute 5 sides
        side1, upper1, lower1 = compute_side(close, self.len1, self.mult1, self.band1, self.smooth1)
        side2, upper2, lower2 = compute_side(close, self.len2, self.mult2, self.band2, self.smooth2)
        side3, upper3, lower3 = compute_side(close, self.len3, self.mult3, self.band3, self.smooth3)
        side4, upper4, lower4 = compute_side(close, self.len4, self.mult4, self.band4, self.smooth4)
        side5, upper5, lower5 = compute_side(close, self.len5, self.mult5, self.band5, self.smooth5)
        
        # Compute ensemble score
        score_raw = side1 + side2 + side3 + side4 + side5
        self.score = self.I(lambda: score_raw / 5.0)
        
        # Trail layers from Speed 3
        self.trail_lower1 = self.I(pta.ema, lower3, length=self.trailSmooth)
        self.trail_upper1 = self.I(pta.ema, upper3, length=self.trailSmooth)
        
        # ATR layer
        def compute_atr():
            tr = high - low
            tr = np.where(tr > (high - close.shift(1)).abs(), tr, (high - close.shift(1)).abs())
            tr = np.where(tr > (low - close.shift(1)).abs(), tr, (low - close.shift(1)).abs())
            tr = pd.Series(tr)
            return pta.ema(tr, length=self.atrLen)
        
        atr_layer = self.I(compute_atr)
        self.trail_lower2 = self.I(pta.ema, self.trail_lower1 - atr_layer * self.atrLayerMult, length=self.trailSmooth)
        self.trail_upper2 = self.I(pta.ema, self.trail_upper1 + atr_layer * self.atrLayerMult, length=self.trailSmooth)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Entry signals
        buy_sig = crossover(self.score, self.scoreBuy)
        sell_sig = crossover(self.scoreSell, self.score)
        
        if buy_sig and not self.position:
            self.buy()
        elif sell_sig and self.position:
            self.position.close()