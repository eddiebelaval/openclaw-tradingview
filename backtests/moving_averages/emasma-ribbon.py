        self.ema9 = self.I(pta.ema, ohlc4_series, length=self.ema9_len)
        self.ema20 = self.I(pta.ema, ohlc4_series, length=self.ema20_len)
        self.ema50 = self.I(pta.ema, ohlc4_series, length=self.ema50_len)
        self.sma100 = self.I(pta.sma, ohlc4_series, length=self.sma100_len)
        self.sma150 = self.I(pta.sma, ohlc4_series, length=self.sma150_len)
        self.sma200 = self.I(pta.sma, ohlc4_series, length=self.sma200_len)

