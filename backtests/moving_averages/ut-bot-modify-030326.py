            for i in range(1, len(close)):
                if close.iloc[i] > atr_line[i-1] and close.iloc[i-1] > atr_line[i-1]:
                    atr_line[i] = max(atr_line[i-1], close.iloc[i] - sl_disp.iloc[i])
