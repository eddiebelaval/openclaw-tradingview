        atr = self.I(pta.atr, high, low, close, length=ut_atr_len)
        
        # Calculate trailing stop for UT Bot
        def calc_ut_trail():
            trail = np.zeros(len(close))
            n_loss = ut_key * atr
            
            for i in range(1, len(close)):
                if close.iloc[i] > trail[i-1] and close.iloc[i-1] > trail[i-1]:
                    trail[i] = max(trail[i-1], close.iloc[i] - n_loss.iloc[i])
                elif close.iloc[i] < trail[i-1] and close.iloc[i-1] < trail[i-1]:
                    trail[i] = min(trail[i-1], close.iloc[i] + n_loss.iloc[i])
                elif close.iloc[i] > trail[i-1]:
                    trail[i] = close.iloc[i] - n_loss.iloc[i]
                else:
                    trail[i] = close.iloc[i] + n_loss.iloc[i]
            
            return pd.Series(trail, index=close.index)
        
        self.ut_trail = self.I(calc_ut_trail)
        
