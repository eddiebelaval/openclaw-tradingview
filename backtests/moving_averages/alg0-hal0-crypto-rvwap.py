import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rvwap_len = 20
    slope_len = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate typical price (hlc3)
        typical_price = (high + low + close) / 3
        
        # Calculate RVWAP: sum(typical_price * volume, lookback) / sum(volume, lookback)
        def calc_rvwap():
            pv_sum = typical_price.rolling(window=self.rvwap_len).apply(
                lambda x: (x * volume.iloc[-self.rvwap_len:].values).sum(), raw=False
            )
            vol_sum = volume.rolling(window=self.rvwap_len).sum()
            rvwap = pv_sum / vol_sum
            return rvwap
        
        self.rvwap = self.I(calc_rvwap)
        
        # Calculate slopes for current and previous bars
        def calc_slope_series():
            slopes = pd.Series(0.0, index=close.index)
            for i in range(len(close)):
                if i >= self.slope_len:
                    val = self.rvwap[i]
                    prev_val = self.rvwap[i - self.slope_len]
                    if prev_val != 0:
                        slopes.iloc[i] = ((val - prev_val) / prev_val) * 100
            return slopes
        
        self.slope = self.I(calc_slope_series)

    def next(self):
        # Buy when price crosses above RVWAP
        if len(self.data) > self.slope_len + 1:
            if crossover(self.data.Close, self.rvwap):
                if not self.position:
                    self.buy()
            # Sell when price crosses below RVWAP
            elif crossover(self.rvwap, self.data.Close):
                if self.position:
                    self.position.close()