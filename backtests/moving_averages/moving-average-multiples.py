import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma1_type = "EMA"
    ma1_length = 10
    ma2_type = "EMA"
    ma2_length = 20
    ma3_type = "EMA"
    ma3_length = 50
    ma4_type = "EMA"
    ma4_length = 100
    ma5_type = "EMA"
    ma5_length = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.ma1 = self.I(self._calc_ma, close, high, low, volume, self.ma1_type, self.ma1_length)
        self.ma2 = self.I(self._calc_ma, close, high, low, volume, self.ma2_type, self.ma2_length)
        self.ma3 = self.I(self._calc_ma, close, high, low, volume, self.ma3_type, self.ma3_length)
        self.ma4 = self.I(self._calc_ma, close, high, low, volume, self.ma4_type, self.ma4_length)
        self.ma5 = self.I(self._calc_ma, close, high, low, volume, self.ma5_type, self.ma5_length)

    def _calc_ma(self, close, high, low, volume, ma_type, length):
        if ma_type == "SMA":
            return pta.sma(close, length=length)
        elif ma_type == "EMA":
            return pta.ema(close, length=length)
        elif ma_type == "SMMA (RMA)":
            return pta.rma(close, length=length)
        elif ma_type == "WMA":
            return pta.wma(close, length=length)
        elif ma_type == "VWMA":
            return pta.vwma(close, volume, length=length)
        else:
            return pd.Series(np.nan, index=close.index)

    def next(self):
        if len(self.data) < self.ma5_length:
            return

        ma1_val = self.ma1[-1]
        ma2_val = self.ma2[-1]
        ma3_val = self.ma3[-1]
        ma4_val = self.ma4[-1]
        ma5_val = self.ma5[-1]

        if pd.isna(ma1_val) or pd.isna(ma2_val) or pd.isna(ma3_val) or pd.isna(ma4_val) or pd.isna(ma5_val):
            return

        close_price = self.data.Close[-1]

        if crossover(self.ma1, self.ma2):
            if not self.position:
                self.buy()
        elif crossover(self.ma2, self.ma1):
            if self.position:
                self.position.close()