import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema9 = self.I(pta.ema, close, length=9)
        self.ema15 = self.I(pta.ema, close, length=15)
        self.ema21 = self.I(pta.ema, close, length=21)
        
        # Calculate RSI
        self.rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Calculate MACD
        macd_result = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9))
        self.macd_line = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACD_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        self.macd_signal = self.I(lambda: pta.macd(close, fast=12, slow=26, signal=9)['MACDs_12_26_9'] if pta.macd(close, fast=12, slow=26, signal=9) is not None else pd.Series(0, index=close.index))
        
        # State tracking
        self.wait_for_buy_confirm = False
        self.wait_for_sell_confirm = False
        self.in_long = False
        self.in_short = False

    def next(self):
        close = self.data.Close[-1]
        ema9_val = self.ema9[-1]
        ema21_val = self.ema21[-1]
        rsi_val = self.rsi[-1]
        macd_line_val = self.macd_line[-1]
        macd_signal_val = self.macd_signal[-1]
        
        # Detect crossover events
        cross_up = crossover(self.ema9, self.ema21)
        cross_down = crossover(self.ema21, self.ema9)
        
        if cross_up:
            self.wait_for_buy_confirm = True
            self.wait_for_sell_confirm = False
        
        if cross_down:
            self.wait_for_sell_confirm = True
            self.wait_for_buy_confirm = False
        
        # BUY Signal conditions
        buy_signal = (
            self.wait_for_buy_confirm and 
            close > ema9_val and 
            rsi_val > 50 and 
            macd_line_val > macd_signal_val and 
            not self.in_long
        )
        
        # SELL Signal conditions
        sell_signal = (
            self.wait_for_sell_confirm and 
            close < ema9_val and 
            rsi_val < 50 and 
            macd_line_val < macd_signal_val and 
            not self.in_short
        )
        
        if buy_signal:
            self.wait_for_buy_confirm = False
            self.in_long = True
            self.in_short = False
            if not self.position:
                self.buy()
        
        if sell_signal:
            self.wait_for_sell_confirm = False
            self.in_short = True
            self.in_long = False
            if self.position:
                self.position.close()


