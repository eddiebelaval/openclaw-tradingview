import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    windowBars = 3

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema21 = self.I(pta.ema, close, length=21)
        self.ema89 = self.I(pta.ema, close, length=89)
        
        self.rsi5 = self.I(pta.rsi, close, length=5)
        self.rsi14 = self.I(pta.rsi, close, length=14)
        
        self.lastRSIBull = None
        self.lastRSIBear = None

    def next(self):
        bar_index = len(self.data) - 1
        
        # Check for EMA crossovers
        emaBull = crossover(self.ema21, self.ema89)
        emaBear = crossover(self.ema89, self.ema21)
        
        # Check for RSI crossovers
        rsiBull = crossover(self.rsi5, self.rsi14)
        rsiBear = crossover(self.rsi14, self.rsi5)
        
        # Track last RSI cross bars
        if rsiBull:
            self.lastRSIBull = bar_index
        
        if rsiBear:
            self.lastRSIBear = bar_index
        
        # Check if RSI cross is within window
        rsiBullInWindow = (self.lastRSIBull is not None and 
                          (bar_index - self.lastRSIBull <= self.windowBars))
        rsiBearInWindow = (self.lastRSIBear is not None and 
                          (bar_index - self.lastRSIBear <= self.windowBars))
        
        # Entry conditions
        longCondition = emaBull and rsiBullInWindow
        shortCondition = emaBear and rsiBearInWindow
        
        # Exit existing position
        if shortCondition and self.position.is_long:
            self.sell()
        
        if longCondition and self.position.is_short:
            self.buy()
        
        # Entry logic
        if longCondition and not self.position:
            self.buy()
        
        if shortCondition and not self.position:
            self.sell()


