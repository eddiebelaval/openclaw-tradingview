import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen = 100
    rsiLen = 14
    rsiBull = 55
    rsiBear = 45
    atrLen = 14
    stopATR = 1.0
    targetATR = 1.2
    pullbackPct = 0.10
    useSession = True
    useTimeExit = True
    maxBarsInTrade = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema = self.I(pta.ema, close, length=self.emaLen)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        self.atr = self.I(pta.atr, high, low, close, length=self.atrLen)
        
        self.bars_in_trade = 0

    def next(self):
        close = self.data.Close[-1]
        ema_val = self.ema[-1]
        rsi_val = self.rsi[-1]
        atr_val = self.atr[-1]
        
        if np.isnan(ema_val) or np.isnan(rsi_val) or np.isnan(atr_val):
            return
        
        band = ema_val * (self.pullbackPct / 100.0)
        near_ema = abs(close - ema_val) <= band
        
        bull_trend = close > ema_val
        bear_trend = close < ema_val
        
        bull_mom = rsi_val >= self.rsiBull
        bear_mom = rsi_val <= self.rsiBear
        
        long_signal = bull_trend and near_ema and bull_mom
        short_signal = bear_trend and near_ema and bear_mom
        
        if self.position:
            self.bars_in_trade += 1
            
            if self.position.is_long:
                long_stop = self.position.open_price - (atr_val * self.stopATR)
                long_limit = self.position.open_price + (atr_val * self.targetATR)
                
                if close <= long_stop or close >= long_limit:
                    self.position.close()
                elif self.useTimeExit and self.bars_in_trade >= self.maxBarsInTrade:
                    self.position.close()
            
            elif self.position.is_short:
                short_stop = self.position.open_price + (atr_val * self.stopATR)
                short_limit = self.position.open_price - (atr_val * self.targetATR)
                
                if close >= short_stop or close <= short_limit:
                    self.position.close()
                elif self.useTimeExit and self.bars_in_trade >= self.maxBarsInTrade:
                    self.position.close()
        else:
            self.bars_in_trade = 0
            
            if long_signal:
                self.buy()
            elif short_signal:
                self.sell()


