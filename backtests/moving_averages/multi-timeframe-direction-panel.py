import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_len = 50

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema = self.I(pta.ema, close, length=self.ema_len)

    def next(self):
        if len(self) < self.ema_len + 1:
            return
        
        close_val = self.data.Close[-1]
        ema_val = self.ema[-1]
        ema_prev = self.ema[-2]
        
        ema_rising = ema_val > ema_prev
        
        bullish = close_val > ema_val and ema_rising
        bearish = close_val < ema_val and not ema_rising
        
        if bullish and not self.position:
            self.buy()
        elif bearish and self.position:
            self.sell()


