import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Hardcoded parameters from the Pine Script
    vwma_fast_len = 20
    vwma_slow_len = 60
    div_pivot_len = 5
    vol_ma_len = 14
    div_min_pct = 40.0
    div_max_bars = 100
    spike_multiplier = 2.5
    spike_ma_length = 20
    conflict_min_pct = 55.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate volume EMA
        self.vol_ema = self.I(lambda: pta.ema(volume, length=self.vol_ma_len) or pd.Series(volume.mean(), index=volume.index))
        
        # Calculate buy/sell volume split estimation
        def estimate_buy_sell():
            result_buy = []
            result_sell = []
            for i in range(len(close)):
                rng = max(high.iloc[i] - low.iloc[i], 1e-10)
                buy_est = volume.iloc[i] * (close.iloc[i] - low.iloc[i]) / rng
                sell_est = volume.iloc[i] - buy_est
                result_buy.append(max(buy_est, 0.0))
                result_sell.append(-max(sell_est, 0.0))
            return pd.Series(result_buy, index=close.index), pd.Series(result_sell, index=close.index)
        
        buy_vol_series, sell_vol_series = estimate_buy_sell()
        self.buy_vol = self.I(lambda: buy_vol_series)
        self.sell_vol = self.I(lambda: sell_vol_series)
        
        # Calculate buy/sell percentages
        def calc_pct_buy():
            result = []
            for i in range(len(buy_vol_series)):
                tot = abs(sell_vol_series.iloc[i]) + buy_vol_series.iloc[i]
                pct = (buy_vol_series.iloc[i] / tot * 100.0) if tot != 0.0 else 0.0
                result.append(pct)
            return pd.Series(result, index=close.index)
        
        self.pct_buy = self.I(calc_pct_buy)
        
        # Volume spike detection
        spike_ma = self.I(lambda: pta.sma(volume, length=self.spike_ma_length))
        def calc_spike():
            result = []
            for i in range(len(volume)):
                ratio = (volume.iloc[i] / spike_ma[i]) if spike_ma[i] > 0 else 0.0
                result.append(ratio >= self.spike_multiplier)
            return pd.Series(result, index=volume.index)
        
        self.is_spike = self.I(calc_spike)
        
        # Candle-Volume conflict
        def calc_conflict():
            result_bull = []
            result_bear = []
            for i in range(len(close)):
                is_bullish = close.iloc[i] >= open.iloc[i] if i < len(self.data.Open) else False
                pct_sell = 100.0 - self.pct_buy[i]
                pct_buy_val = self.pct_buy[i]
                
                bull_conflict = is_bullish and pct_sell >= self.conflict_min_pct
                bear_conflict = (not is_bullish) and pct_buy_val >= self.conflict_min_pct
                
                result_bull.append(bull_conflict)
                result_bear.append(bear_conflict)
            return pd.Series(result_bull, index=close.index), pd.Series(result_bear, index=close.index)
        
        bull_conflict, bear_conflict = calc_conflict()
        self.bull_conflict = self.I(lambda: bull_conflict)
        self.bear_conflict = self.I(lambda: bear_conflict)
        
        # VWMA calculation
        def calc_vwma():
            abs_sell_vol = (-sell_vol_series).abs()
            
            buy_vwma = []
            sell_vwma = []
            
            for i in range(len(close)):
                # Buy VWMA (fast)
                start_idx = max(0, i - self.vwma_fast_len + 1)
                buy_slice = buy_vol_series.iloc[start_idx:i+1]
                price_slice = close.iloc[start_idx:i+1]
                sum_buy_vf = buy_slice.sum()
                buy_vwma_val = (price_slice * buy_slice).sum() / sum_buy_vf if sum_buy_vf > 0 else close.iloc[i]
                buy_vwma.append(buy_vwma_val)
                
                # Sell VWMA (slow)
                start_idx = max(0, i - self.vwma_slow_len + 1)
                sell_slice = abs_sell_vol.iloc[start_idx:i+1]
                price_slice = close.iloc[start_idx:i+1]
                sum_sell_vs = sell_slice.sum()
                sell_vwma_val = (price_slice * sell_slice).sum() / sum_sell_vs if sum_sell_vs > 0 else close.iloc[i]
                sell_vwma.append(sell_vwma_val)
            
            return pd.Series(buy_vwma, index=close.index), pd.Series(sell_vwma, index=close.index)
        
        self.buy_vwma, self.sell_vwma = calc_vwma()
        
        # VWMA crossover signals
        self.vwma_cross_over = self.I(lambda: crossover(self.buy_vwma, self.sell_vwma))
        self.vwma_cross_under = self.I(lambda: crossover(self.sell_vwma, self.buy_vwma))
        
        # Pivot highs and lows for divergence
        def calc_pivots():
            ph_series = []
            pl_series = []
            for i in range(len(high)):
                # Pivot high
                if i >= self.div_pivot_len and i < len(high) - self.div_pivot_len:
                    is_ph = high.iloc[i] == high.iloc[max(0, i-self.div_pivot_len):i+self.div_pivot_len+1].max()
                    ph_series.append(high.iloc[i] if is_ph else np.nan)
                else:
                    ph_series.append(np.nan)
                
                # Pivot low
                if i >= self.div_pivot_len and i < len(low) - self.div_pivot_len:
                    is_pl = low.iloc[i] == low.iloc[max(0, i-self.div_pivot_len):i+self.div_pivot_len+1].min()
                    pl_series.append(low.iloc[i] if is_pl else np.nan)
                else:
                    pl_series.append(np.nan)
            
            return pd.Series(ph_series, index=high.index), pd.Series(pl_series, index=low.index)
        
        self.pivot_high, self.pivot_low = calc_pivots()
        
        self.last_ph_price = None
        self.last_ph_vol_ema = None
        self.last_ph_bar = None
        self.last_pl_price = None
        self.last_pl_vol_ema = None
        self.last_pl_bar = None
        
        self.bullish_div_signal = False
        self.bearish_div_signal = False

    def next(self):
        # Main trading logic
        current_idx = len(self.data) - 1
        
        # Get current values
        buy_vwma_curr = self.buy_vwma[-1]
        sell_vwma_curr = self.sell_vwma[-1]
        close_curr = self.data.Close[-1]
        
        # Cloud extremes
        cloud_top = max(buy_vwma_curr, sell_vwma_curr)
        cloud_btm = min(buy_vwma_curr, sell_vwma_curr)
        
        # Check for bullish cloud cross above cloud
        if self.vwma_cross_over[-1] and close_curr > cloud_top:
            if not self.position:
                self.buy()
        
        # Check for bearish cloud cross below cloud
        elif self.vwma_cross_under[-1] and close_curr < cloud_btm:
            if self.position:
                self.sell()
        
        # Check for volume spike with direction
        if self.is_spike[-1]:
            pct_buy = self.pct_buy[-1]
            if pct_buy > 50 and not self.position:
                self.buy()
            elif pct_buy <= 50 and self.position:
                self.sell()
        
        # Check for conflict signals
        if self.bull_conflict[-1] and self.position:
            self.sell()
        elif self.bear_conflict[-1] and not self.position:
            self.buy()
        
        # Check for volume divergence
        current_ph = self.pivot_high[-1]
        current_pl = self.pivot_low[-1]
        
        if not np.isnan(current_ph):
            curr_vol_ema = self.vol_ema[-1]
            if self.last_ph_price is not None:
                vol_change = abs(curr_vol_ema - self.last_ph_vol_ema) / self.last_ph_vol_ema * 100.0 if self.last_ph_vol_ema > 0 else 0.0
                
                # Bearish divergence: price higher high but volume lower
                if current_ph > self.last_ph_price and curr_vol_ema < self.last_ph_vol_ema and vol_change >= self.div_min_pct:
                    if self.position:
                        self.sell()
                    self.bearish_div_signal = True
            
            self.last_ph_price = current_ph
            self.last_ph_vol_ema = curr_vol_ema
            self.last_ph_bar = current_idx
        
        if not np.isnan(current_pl):
            curr_vol_ema = self.vol_ema[-1]
            if self.last_pl_price is not None:
                vol_change = abs(curr_vol_ema - self.last_pl_vol_ema) / self.last_pl_vol_ema * 100.0 if self.last_pl_vol_ema > 0 else 0.0
                
                # Bullish divergence: price lower low but volume higher
                if current_pl < self.last_pl_price and curr_vol_ema > self.last_pl_vol_ema and vol_change >= self.div_min_pct:
                    if not self.position:
                        self.buy()
                    self.bullish_div_signal = True
            
            self.last_pl_price = current_pl
            self.last_pl_vol_ema = curr_vol_ema
            self.last_pl_bar = current_idx


