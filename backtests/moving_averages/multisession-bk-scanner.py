import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA parameters
    ema_len1 = 32
    ema_len2 = 50
    ema_len3 = 110
    ema_len4 = 200
    ema_len5 = 250
    ema_len6 = 8
    
    # EMA slope parameters
    ema_slope_len = 3
    slope_thresh = 0.15
    
    # Stochastic parameters
    k_len = 9
    k_sma = 6
    d_sma = 2
    
    # RSI Stochastic parameters
    length_rsi = 14
    length_stoch_rsi = 14
    smooth_k_rsi = 3
    smooth_d_rsi = 3
    
    # Imbalance parameters
    tiempo_minimo_imb = 1
    
    # CHOCH parameters
    pivot_length = 1
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.ema1 = self.I(pta.ema, close, length=self.ema_len1)
        self.ema2 = self.I(pta.ema, close, length=self.ema_len2)
        self.ema3 = self.I(pta.ema, close, length=self.ema_len3)
        self.ema4 = self.I(pta.ema, close, length=self.ema_len4)
        self.ema5 = self.I(pta.ema, close, length=self.ema_len5)
        self.ema6 = self.I(pta.ema, close, length=self.ema_len6)
        
        # Calculate Stochastic indicators
        def calc_stoch_5():
            stoch_result = pta.stoch(high, low, close, k=self.k_len, d=self.d_sma)
            if stoch_result is not None and 'STOCHk_9_2' in stoch_result.columns:
                k_vals = stoch_result['STOCHk_9_2']
                k_sma_vals = pta.sma(k_vals, length=self.k_sma)
                if k_sma_vals is not None:
                    d_vals = pta.sma(k_sma_vals, length=self.d_sma)
                    if d_vals is not None:
                        return k_sma_vals, d_vals
            return None, None
        
        # Store stochastic as separate indicators
        self.k_stoch = self.I(lambda: calc_stoch_5()[0] if calc_stoch_5()[0] is not None else pd.Series(50, index=close.index))
        self.d_stoch = self.I(lambda: calc_stoch_5()[1] if calc_stoch_5()[1] is not None else pd.Series(50, index=close.index))
        
        # Calculate RSI Stochastic
        def calc_rsi_stoch():
            rsi_vals = pta.rsi(close, length=self.length_rsi)
            if rsi_vals is not None:
                stoch_rsi_result = pta.stoch(rsi_vals, rsi_vals, rsi_vals, k=self.length_stoch_rsi, d=self.smooth_d_rsi)
                if stoch_rsi_result is not None:
                    k_rsi_cols = [col for col in stoch_rsi_result.columns if 'k' in col.lower()]
                    if k_rsi_cols:
                        k_rsi_raw = stoch_rsi_result[k_rsi_cols[0]]
                        k_rsi_sma = pta.sma(k_rsi_raw, length=self.smooth_k_rsi)
                        if k_rsi_sma is not None:
                            d_rsi_sma = pta.sma(k_rsi_sma, length=self.smooth_d_rsi)
                            if d_rsi_sma is not None:
                                return k_rsi_sma, d_rsi_sma
            return None, None
        
        self.k_rsi = self.I(lambda: calc_rsi_stoch()[0] if calc_rsi_stoch()[0] is not None else pd.Series(50, index=close.index))
        self.d_rsi = self.I(lambda: calc_rsi_stoch()[1] if calc_rsi_stoch()[1] is not None else pd.Series(50, index=close.index))
        
        # Calculate highest and lowest for pivots
        self.highest = self.I(lambda: high.rolling(2 * self.pivot_length + 1).max())
        self.lowest = self.I(lambda: low.rolling(2 * self.pivot_length + 1).min())
        
        # Previous day high/low
        def calc_prev_day():
            prev_high = high.shift(1)
            prev_low = low.shift(1)
            return prev_high, prev_low
        
        self.prev_high = self.I(lambda: calc_prev_day()[0])
        self.prev_low = self.I(lambda: calc_prev_day()[1])
        
        # Tracking variables
        self.in_long = False
        self.in_short = False

    def next(self):
        # Get current values
        close_val = self.data.Close[-1]
        ema1_val = self.ema1[-1]
        ema2_val = self.ema2[-1]
        ema6_val = self.ema6[-1]
        k_stoch_val = self.k_stoch[-1]
        k_rsi_val = self.k_rsi[-1]
        
        # Check for NaN values
        if pd.isna([ema1_val, ema2_val, k_stoch_val, k_rsi_val]).any():
            return
        
        # Strategy logic combining multiple signals
        
        # Signal 1: EMA alignment (bullish = ema6 > ema1 > ema2)
        ema_bullish = ema6_val > ema1_val > ema2_val
        ema_bearish = ema6_val < ema1_val < ema2_val
        
        # Signal 2: Stochastic oversold/overbought
        stoch_oversold = k_stoch_val < 20
        stoch_overbought = k_stoch_val > 80
        
        # Signal 3: RSI Stochastic crossover
        rsi_stoch_bullish = False
        rsi_stoch_bearish = False
        if len(self.k_rsi) > 1:
            rsi_stoch_bullish = crossover(self.k_rsi, self.d_rsi)
            rsi_stoch_bearish = crossover(self.d_rsi, self.k_rsi)
        
        # Signal 4: Price above/below key EMAs
        price_above_ema1 = close_val > ema1_val
        price_below_ema1 = close_val < ema1_val
        
        # Buy conditions
        buy_condition = (
            ema_bullish and price_above_ema1 and 
            (stoch_oversold or rsi_stoch_bullish)
        )
        
        # Sell conditions
        sell_condition = (
            ema_bearish and price_below_ema1 and 
            (stoch_overbought or rsi_stoch_bearish)
        )
        
        # Exit conditions
        exit_long = ema_bearish or crossover(self.ema2, self.ema1)
        exit_short = ema_bullish or crossover(self.ema1, self.ema2)
        
        # Execute trades
        if self.in_long and exit_long:
            self.sell()
            self.in_long = False
        elif self.in_short and exit_short:
            self.buy()
            self.in_short = False
        
        if buy_condition and not self.in_long and not self.in_short:
            self.buy()
            self.in_long = True
        elif sell_condition and not self.in_short and not self.in_long:
            self.sell()
            self.in_short = True


