import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Core EMA parameters
    ema_fast_len = 9
    ema_mid_len = 20
    ema_slow_len = 50
    ema_struct_len = 200
    
    # Signal triggers
    trim_pct = 0.09
    redeploy_pct = 0.025
    
    # Qualifiers
    require_bull_stack = True
    require_above_50 = True
    
    # Regime gate
    risk_off_below_bench_200 = True
    
    # RS filter
    use_rs = True
    rs_lookback = 126
    rs_pct = 50.0
    
    # Debounce
    debounce_daily = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate daily EMAs
        self.ema9 = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema20 = self.I(pta.ema, close, length=self.ema_mid_len)
        self.ema50 = self.I(pta.ema, close, length=self.ema_slow_len)
        self.ema200 = self.I(pta.ema, close, length=self.ema_struct_len)
        
        # Track last signal day to implement debounce
        self.last_trim_day = None
        self.last_redeploy_day = None
        self.in_trim_signal = False
        self.in_redeploy_signal = False

    def next(self):
        # Current values
        close = self.data.Close[-1]
        ema9 = self.ema9[-1]
        ema20 = self.ema20[-1]
        ema50 = self.ema50[-1]
        ema200 = self.ema200[-1]
        
        # Skip if insufficient data
        if pd.isna(ema9) or pd.isna(ema20) or pd.isna(ema50) or pd.isna(ema200):
            return
        
        # Bull stack check
        bull_stack = ema9 > ema20 and ema20 > ema50
        
        # Risk regime: simplified - assume risk_on if price > ema200
        # (In real scenario, would check benchmark QQQ vs its EMA200)
        risk_on = close > ema200
        
        # RS filter: simplified - assume pass if price > ema50
        # (In real scenario, would calculate RS ratio percentile vs SPY)
        rs_pass = close > ema50 if self.use_rs else True
        
        # Get current bar index as proxy for "day"
        current_day = len(self.data)
        
        # TRIM Signal: close > EMA9 * (1 + trim_pct)
        trim_signal = close > ema9 * (1 + self.trim_pct)
        
        # REDEPLOY Signal: close <= EMA20 * (1 + redeploy_pct) + qualifiers
        redeploy_signal = (
            close <= ema20 * (1 + self.redeploy_pct) and
            (not self.require_bull_stack or bull_stack) and
            (not self.require_above_50 or close > ema50) and
            rs_pass and
            risk_on
        )
        
        # Apply debounce: max 1 TRIM + 1 REDEPLOY per day
        trim_fire = trim_signal
        redeploy_fire = redeploy_signal
        
        if self.debounce_daily:
            if self.last_trim_day == current_day:
                trim_fire = False
            if self.last_redeploy_day == current_day:
                redeploy_fire = False
        
        # Execute trades
        # TRIM: take profit / close long position
        if trim_fire and self.position:
            self.sell()
            if self.debounce_daily:
                self.last_trim_day = current_day
        
        # REDEPLOY: enter long position
        if redeploy_fire and not self.position:
            self.buy()
            if self.debounce_daily:
                self.last_redeploy_day = current_day


