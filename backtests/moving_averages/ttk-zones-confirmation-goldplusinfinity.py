import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_length_20 = 20
    ma_length_50 = 50
    ma_length_trend = 200
    bt_mult = 3.0
    lookback_bt = 500
    trend_filter = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.ma20 = self.I(pta.sma, close, length=self.ma_length_20)
        self.ma50 = self.I(pta.sma, close, length=self.ma_length_50)
        self.ma_trend = self.I(pta.sma, close, length=self.ma_length_trend)

        def calc_raw_buy_vol():
            range_size = high - low
            raw_buy = np.where(
                range_size == 0,
                0,
                (close - low) / range_size * volume
            )
            return pd.Series(raw_buy, index=close.index)

        def calc_raw_sell_vol():
            range_size = high - low
            raw_sell = np.where(
                range_size == 0,
                0,
                (high - close) / range_size * volume
            )
            return pd.Series(raw_sell, index=close.index)

        def calc_avg_buy_vol():
            raw_buy = calc_raw_buy_vol()
            avg = pta.sma(raw_buy, length=self.lookback_bt)
            if avg is None:
                return pd.Series(0, index=close.index)
            return avg.shift(1).fillna(0)

        def calc_std_buy_vol():
            raw_buy = calc_raw_buy_vol()
            std = raw_buy.rolling(self.lookback_bt).std()
            if std is None:
                return pd.Series(0, index=close.index)
            return std.shift(1).fillna(0)

        def calc_avg_sell_vol():
            raw_sell = calc_raw_sell_vol()
            avg = pta.sma(raw_sell, length=self.lookback_bt)
            if avg is None:
                return pd.Series(0, index=close.index)
            return avg.shift(1).fillna(0)

        def calc_std_sell_vol():
            raw_sell = calc_raw_sell_vol()
            std = raw_sell.rolling(self.lookback_bt).std()
            if std is None:
                return pd.Series(0, index=close.index)
            return std.shift(1).fillna(0)

        self.raw_buy_vol = self.I(calc_raw_buy_vol)
        self.raw_sell_vol = self.I(calc_raw_sell_vol)
        self.avg_buy_vol = self.I(calc_avg_buy_vol)
        self.std_buy_vol = self.I(calc_std_buy_vol)
        self.avg_sell_vol = self.I(calc_avg_sell_vol)
        self.std_sell_vol = self.I(calc_std_sell_vol)

        def detect_imb_high():
            imb_h = (low[2:].values < high[:-2].values) & \
                    (close[1:-1].values > open[1:-1].values)
            result = np.concatenate([np.array([False, False]), imb_h])
            return pd.Series(result, index=close.index)

        def detect_imb_low():
            imb_b = (high[2:].values > low[:-2].values) & \
                    (close[1:-1].values < open[1:-1].values)
            result = np.concatenate([np.array([False, False]), imb_b])
            return pd.Series(result, index=close.index)

        self.est_imb_h = self.I(detect_imb_high)
        self.est_imb_b = self.I(detect_imb_low)

        self.last_close = None
        self.last_high = None
        self.last_low = None

    def next(self):
        close_val = self.data.Close[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]

        thresh_buy = self.avg_buy_vol[-1] + self.std_buy_vol[-1] * self.bt_mult
        thresh_sell = self.avg_sell_vol[-1] + self.std_sell_vol[-1] * self.bt_mult

        is_bt_buy = (self.raw_buy_vol[-1] > thresh_buy) and \
                    (not self.trend_filter or close_val > self.ma_trend[-1])
        is_bt_sell = (self.raw_sell_vol[-1] > thresh_sell) and \
                     (not self.trend_filter or close_val < self.ma_trend[-1])

        imb_signal = self.est_imb_h[-1] or self.est_imb_b[-1]

        if is_bt_buy or (imb_signal and self.est_imb_h[-1]):
            if not self.position:
                self.buy()
        elif is_bt_sell or (imb_signal and self.est_imb_b[-1]):
            if self.position:
                self.position.close()

        if crossover(self.ma20, self.ma50):
            if not self.position:
                self.buy()
        elif crossover(self.ma50, self.ma20):
            if self.position:
                self.position.close()


