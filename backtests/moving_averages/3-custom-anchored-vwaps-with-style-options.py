    def _calc_anchored_vwap(self, hlc3, volume, anchor_time, return_price=True):
        """Calculate anchored VWAP and deviation"""
        result_price = []
        result_dev = []
        
        sum_src_vol = 0.0
        sum_vol = 0.0
        sum_src_sq_vol = 0.0
        started = False
        
        for i in range(len(hlc3)):
            bar_time = self.data.index[i]
            
            if bar_time >= anchor_time and not started:
                started = True
            
            if started:
                src = hlc3.iloc[i]
                vol = volume.iloc[i]
                sum_src_vol += src * vol
                sum_vol += vol
                sum_src_sq_vol += (src ** 2) * vol
                
                if sum_vol > 0:
                    vwap_val = sum_src_vol / sum_vol
                    variance = (sum_src_sq_vol / sum_vol) - (vwap_val ** 2)
                    dev_val = np.sqrt(max(0, variance))
                else:
                    vwap_val = np.nan
                    dev_val = 0.0
            else:
                vwap_val = np.nan
                dev_val = 0.0
            
            result_price.append(vwap_val)
            result_dev.append(dev_val)
        
        return pd.Series(result_price if return_price else result_dev)

