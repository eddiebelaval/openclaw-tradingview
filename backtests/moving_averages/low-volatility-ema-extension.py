import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Basic EMA
        self.ema8 = self.I(pta.ema, close, length=8)
        self.ema34 = self.I(pta.ema, close, length=34)
        
        # Track state for preventing duplicate signals
        self.last_bullish_bar = -999
        self.last_bearish_bar = -999
    
    def next(self):
        # Check for EMA 8/34 crossover
        if len(self.data) < 4:
            return
        
        current_bar = len(self.data) - 1
        
        # Get the last few bars of EMA values
        ema8_vals = self.ema8[-4:] if len(self.ema8) >= 4 else None
        ema34_vals = self.ema34[-4:] if len(self.ema34) >= 4 else None
        
        if ema8_vals is None or ema34_vals is None:
            return
        
        close_vals = self.data.Close[-4:]
        
        # Detect crossover in recent bars (1-3 bars ago)
        crossover_up = False
        crossover_down = False
        
        for i in range(1, 4):
            if i < len(ema8_vals) and i < len(ema34_vals):
                prev_ema8 = ema8_vals[-(i+1)]
                prev_ema34 = ema34_vals[-(i+1)]
                curr_ema8 = ema8_vals[-i]
                curr_ema34 = ema34_vals[-i]
                
                if prev_ema8 is not None and prev_ema34 is not None and curr_ema8 is not None and curr_ema34 is not None:
                    if prev_ema8 <= prev_ema34 and curr_ema8 > curr_ema34:
                        crossover_up = True
                    elif prev_ema8 >= prev_ema34 and curr_ema8 < curr_ema34:
                        crossover_down = True
        
        # Check for 2 consecutive higher closes
        bullish_closes = (close_vals[-1] > close_vals[-2]) and (close_vals[-2] > close_vals[-3])
        
        # Check for 2 consecutive lower closes
        bearish_closes = (close_vals[-1] < close_vals[-2]) and (close_vals[-2] < close_vals[-3])
        
        # Bullish signal: crossover up + higher closes + not recently signaled
        if crossover_up and bullish_closes and (current_bar - self.last_bullish_bar) > 3:
            if not self.position:
                self.buy()
            self.last_bullish_bar = current_bar
        
        # Bearish signal: crossover down + lower closes + not recently signaled
        if crossover_down and bearish_closes and (current_bar - self.last_bearish_bar) > 3:
            if self.position:
                self.sell()
            self.last_bearish_bar = current_bar


