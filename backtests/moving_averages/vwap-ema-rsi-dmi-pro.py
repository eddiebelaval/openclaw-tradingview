import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_fast_len = 20
    ema_slow_len = 50
    ema_trend_len = 200
    rsi_len = 14
    dmi_len = 14
    adx_smooth = 14

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema_fast = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema_slow = self.I(pta.ema, close, length=self.ema_slow_len)
        self.ema_trend = self.I(pta.ema, close, length=self.ema_trend_len)
        
        self.vwap_val = self.I(pta.vwap, high, low, close)
        
        self.rsi_val = self.I(pta.rsi, close, length=self.rsi_len)
        
        dmi_result = self.I(lambda: pta.adx(high, low, close, length=self.dmi_len))
        
        def get_di_plus(dmi_result):
            if dmi_result is not None and not dmi_result.empty:
                di_plus_col = [col for col in dmi_result.columns if 'DMP' in col.upper()]
                if di_plus_col:
                    return dmi_result[di_plus_col[0]]
            return pd.Series(0, index=close.index)
        
        def get_di_minus(dmi_result):
            if dmi_result is not None and not dmi_result.empty:
                di_minus_col = [col for col in dmi_result.columns if 'DMN' in col.upper()]
                if di_minus_col:
                    return dmi_result[di_minus_col[0]]
            return pd.Series(0, index=close.index)
        
        def get_adx(dmi_result):
            if dmi_result is not None and not dmi_result.empty:
                adx_col = [col for col in dmi_result.columns if 'ADX' in col.upper()]
                if adx_col:
                    return dmi_result[adx_col[0]]
            return pd.Series(20, index=close.index)
        
        self.di_plus = self.I(get_di_plus, dmi_result)
        self.di_minus = self.I(get_di_minus, dmi_result)
        self.adx = self.I(get_adx, dmi_result)
        
        self.last_signal_bar = -np.inf

    def next(self):
        if len(self.data) < max(self.ema_trend_len, self.rsi_len, self.dmi_len) + 5:
            return
        
        close_val = self.data.Close[-1]
        vwap = self.vwap_val[-1]
        ema_f = self.ema_fast[-1]
        ema_s = self.ema_slow[-1]
        ema_t = self.ema_trend[-1]
        rsi = self.rsi_val[-1]
        di_p = self.di_plus[-1] if not np.isnan(self.di_plus[-1]) else 0
        di_m = self.di_minus[-1] if not np.isnan(self.di_minus[-1]) else 0
        
        if np.isnan(vwap) or np.isnan(ema_f) or np.isnan(ema_s) or np.isnan(ema_t) or np.isnan(rsi):
            return
        
        bull_condition = (close_val > vwap and 
                         ema_f > ema_s and 
                         ema_s > ema_t and 
                         rsi > 50 and 
                         di_p > di_m)
        
        bear_condition = (close_val < vwap and 
                         ema_f < ema_s and 
                         ema_s < ema_t and 
                         rsi < 50 and 
                         di_m > di_p)
        
        if bull_condition and not bear_condition:
            if len(self.data) - self.last_signal_bar > 3:
                if self.position:
                    self.position.close()
                self.buy()
                self.last_signal_bar = len(self.data)
        
        elif bear_condition and not bull_condition:
            if len(self.data) - self.last_signal_bar > 3:
                if self.position:
                    self.position.close()
                else:
                    self.sell()
                self.last_signal_bar = len(self.data)


