import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema20_length = 20
    ema200_length = 200
    
    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema20 = self.I(pta.ema, close, length=self.ema20_length)
        self.ema200 = self.I(pta.ema, close, length=self.ema200_length)
    
    def next(self):
        if len(self.data) < max(self.ema20_length, self.ema200_length):
            return
        
        if self.ema20[-1] is None or self.ema200[-1] is None:
            return
        
        if crossover(self.ema20, self.ema200):
            if not self.position:
                self.buy()
        elif crossover(self.ema200, self.ema20):
            if self.position:
                self.position.close()