    def _super_smoother(self, src, period):
        pi = math.pi
        a1 = math.exp(-math.sqrt(2) * pi / period)
        b1 = 2 * a1 * math.cos(math.sqrt(2) * pi / period)
        c2 = b1
        c3 = -a1 * a1
        c1 = 1 - c2 - c3
        
        result = pd.Series(index=src.index, dtype=float)
        ss = np.nan
        
        for i in range(len(src)):
            if i < 2:
                result.iloc[i] = src.iloc[i]
                ss = src.iloc[i]
            else:
                ss = c1 * (src.iloc[i] + src.iloc[i-1]) / 2.0 + c2 * result.iloc[i-1] + c3 * result.iloc[i-2]
                result.iloc[i] = ss
        
        return result

    def _parkinson(self, high, low, close, length):
        sum_sq = 0.0
        for i in range(min(length, len(close))):
            log_hl = math.log(high.iloc[-(i+1)] / low.iloc[-(i+1)])
            sum_sq += log_hl * log_hl
        
        result = pd.Series(index=close.index, dtype=float)
        
        for idx in range(len(close)):
            if idx < length:
                sum_sq_i = 0.0
                for i in range(idx + 1):
                    log_hl = math.log(high.iloc[idx-i] / low.iloc[idx-i])
                    sum_sq_i += log_hl * log_hl
                result.iloc[idx] = math.sqrt(sum_sq_i / (4.0 * (idx+1) * math.log(2))) * close.iloc[idx]
