    def _cmo(self, src, length):
        result = pd.Series(index=src.index, dtype=float)
        
        for i in range(len(src)):
            if i < length:
                end_idx = i
            else:
                end_idx = length
            
            up_sum = 0.0
            dn_sum = 0.0
            
            for j in range(1, end_idx + 1):
                mom = src.iloc[i] - src.iloc[i-j]
                if j > 1:
                    prev_mom = src.iloc[i-j+1] - src.iloc[i-j]
                    if prev_mom > 0:
                        up_sum += prev_mom
                    else:
                        dn_sum += abs(prev_mom)
            
            if i > 0:
                mom = src.iloc[i] - src.iloc[i-1]
                if mom > 0:
                    up_sum += mom
                else:
                    dn_sum += abs(mom)
            
            total = up_sum + dn_sum
            if total > 0:
                result.iloc[i] = 100 * (up_sum - dn_sum) / total
            else:
                result.iloc[i] = 0
        
        return result

    def _mid_raw(self, st_slow, bw_stop):
        result = pd.Series(index=st_slow.index, dtype=float)
        
        for i in range(len(st_slow)):
            if st_slow.iloc[i] > bw_stop.iloc[i]:
                result.iloc[i] = st_slow.iloc[i] - (st_slow.iloc[i] - bw_stop.iloc[i]) / 2.0
            else:
                result.iloc[i] = st_slow.iloc[i] + (bw_stop.iloc[i] - st_slow.iloc[i]) / 2.0
        
        return result

    def _kama(self, src, er_len, fast_len, slow_len):
        result = pd.Series(index=src.index, dtype=float)
        kama_val = src.iloc[0]
        
        for i in range(len(src)):
            if i < er_len:
                change_val = abs(src.iloc[i] - src.iloc[0])
                volatility = sum(abs(src.iloc[j] - src.iloc[j-1]) for j in range(1, i+1)) if i > 0 else 0
            else:
                change_val = abs(src.iloc[i] - src.iloc[i-er_len])
                volatility = sum(abs(src.iloc[j] - src.iloc[j-1]) for j in range(i-er_len+1, i+1))
            
            er = change_val / volatility if volatility != 0 else 0
            
            fast_sc = 2.0 / (fast_len + 1.0)
            slow_sc = 2.0 / (slow_len + 1.0)
            sc = (er * (fast_sc - slow_sc) + slow_sc) ** 2
            
            if i == 0:
                kama_val = src.iloc[i]
            else:
                kama_val = kama_val + sc * (src.iloc[i] - kama_val)
            
            result.iloc[i] = kama_val
        
        return result

