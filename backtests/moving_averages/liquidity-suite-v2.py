import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Hull Suite parameters
    hullLen = 55
    hullLenMult = 1.0
    hullVariant = "Hma"  # "Hma", "Ehma", or "Thma"
    
    # RSI parameters
    rsiLen = 14
    rsiOB = 70
    rsiOS = 30
    
    # Supertrend parameters
    stFactor = 3.0
    stAtrLen = 10
    
    # Liquidity level parameters
    enableBull = True
    enableBear = True
    
    # Micro-structure parameters
    enableMS = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Hull Suite calculation
        def calc_hma(src, n):
            n = int(n)
            wma1 = pta.wma(src, length=max(1, n // 2))
            wma2 = pta.wma(src, length=n)
            if wma1 is None or wma2 is None:
                return pd.Series(0, index=src.index)
            diff = 2 * wma1 - wma2
            sqrt_n = int(np.sqrt(n))
            result = pta.wma(diff, length=max(1, sqrt_n))
            return result if result is not None else pd.Series(0, index=src.index)
        
        def calc_ehma(src, n):
            n = int(n)
            ema1 = pta.ema(src, length=max(1, n // 2))
            ema2 = pta.ema(src, length=n)
            if ema1 is None or ema2 is None:
                return pd.Series(0, index=src.index)
            diff = 2 * ema1 - ema2
            sqrt_n = int(np.sqrt(n))
            result = pta.ema(diff, length=max(1, sqrt_n))
            return result if result is not None else pd.Series(0, index=src.index)
        
        def calc_thma(src, n):
            n = int(n)
            wma1 = pta.wma(src, length=max(1, n // 3))
            wma2 = pta.wma(src, length=max(1, n // 2))
            wma3 = pta.wma(src, length=n)
            if wma1 is None or wma2 is None or wma3 is None:
                return pd.Series(0, index=src.index)
            diff = 3 * wma1 - wma2 - wma3
            result = pta.wma(diff, length=n)
            return result if result is not None else pd.Series(0, index=src.index)
        
        eff_len = int(self.hullLen * self.hullLenMult)
        
        if self.hullVariant == "Ehma":
            self.hull = self.I(calc_ehma, close, eff_len)
        elif self.hullVariant == "Thma":
            self.hull = self.I(calc_thma, close, eff_len)
        else:  # Hma
            self.hull = self.I(calc_hma, close, eff_len)
        
        # RSI calculation
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        # ATR for Supertrend
        self.atr = self.I(pta.atr, high, low, close, length=self.stAtrLen)
        
        # Supertrend calculation (manual)
        def calc_supertrend(h, l, c, atr_vals, factor):
            if atr_vals is None:
                return pd.Series(0, index=c.index), pd.Series(0, index=c.index)
            
            hl_avg = (h + l) / 2
            matr = atr_vals * factor
            
            basic_ub = hl_avg + matr
            basic_lb = hl_avg - matr
            
            ub = pd.Series(index=c.index, dtype=float)
            lb = pd.Series(index=c.index, dtype=float)
            
            ub.iloc[0] = basic_ub.iloc[0]
            lb.iloc[0] = basic_lb.iloc[0]
            
            for i in range(1, len(c)):
                ub.iloc[i] = min(basic_ub.iloc[i], ub.iloc[i-1]) if c.iloc[i-1] > ub.iloc[i-1] else basic_ub.iloc[i]
                lb.iloc[i] = max(basic_lb.iloc[i], lb.iloc[i-1]) if c.iloc[i-1] < lb.iloc[i-1] else basic_lb.iloc[i]
            
            st = pd.Series(index=c.index, dtype=float)
            direction = pd.Series(index=c.index, dtype=float)
            
            st.iloc[0] = ub.iloc[0]
            direction.iloc[0] = 1
            
            for i in range(1, len(c)):
                if direction.iloc[i-1] == 1:
                    st.iloc[i] = lb.iloc[i]
                    if c.iloc[i] < lb.iloc[i]:
                        direction.iloc[i] = -1
                    else:
                        direction.iloc[i] = 1
                else:
                    st.iloc[i] = ub.iloc[i]
                    if c.iloc[i] > ub.iloc[i]:
                        direction.iloc[i] = 1
                    else:
                        direction.iloc[i] = -1
            
            return st, direction
        
        self.st_val, self.st_dir = self.I(lambda: calc_supertrend(high, low, close, self.atr, self.stFactor))
        
        # State variables for bullish sequence
        self.bull_seq = False
        self.bull_rsi_done = False
        self.bull_high_px = np.nan
        self.bull_cand_on = False
        self.bull_zone_top = np.nan
        self.bull_zone_bot = np.nan
        self.bull_validated = False
        self.bull_retest = False
        
        # State variables for bearish sequence
        self.bear_seq = False
        self.bear_rsi_done = False
        self.bear_low_px = np.nan
        self.bear_cand_on = False
        self.bear_zone_top = np.nan
        self.bear_zone_bot = np.nan
        self.bear_validated = False
        self.bear_retest = False
        
        # Micro-structure state
        self.g_count = 0
        self.r_count = 0
        self.had_two_g = False
        self.had_two_r = False
        self.ms_high_px = np.nan
        self.ms_low_px = np.nan

    def next(self):
        if len(self.data) < 3:
            return
        
        close_val = self.data.Close[-1]
        open_val = self.data.Open[-1]
        high_val = self.data.High[-1]
        low_val = self.data.Low[-1]
        
        hull_curr = self.hull[-1]
        hull_prev = self.hull[-2]
        hull_prev2 = self.hull[-3] if len(self.hull) >= 3 else hull_prev
        
        rsi_curr = self.rsi[-1]
        
        st_bull = self.st_dir[-1] < 0 if not np.isnan(self.st_dir[-1]) else False
        st_bear = self.st_dir[-1] > 0 if not np.isnan(self.st_dir[-1]) else False
        st_flip_bull = st_bull and (len(self.st_dir) < 2 or self.st_dir[-2] >= 0)
        st_flip_bear = st_bear and (len(self.st_dir) < 2 or self.st_dir[-2] <= 0)
        
        hull_turn_red = hull_curr < hull_prev2 and hull_prev >= self.hull[-4] if len(self.hull) >= 4 else False
        hull_turn_grn = hull_curr > hull_prev2 and hull_prev <= self.hull[-4] if len(self.hull) >= 4 else False
        
        # Bullish sequence logic
        if self.enableBull:
            if st_flip_bull:
                self.bull_seq = True
                self.bull_rsi_done = False
                self.bull_high_px = np.nan
            
            if st_flip_bear:
                self.bull_seq = False
                self.bull_cand_on = False
            
            if self.bull_seq:
                if rsi_curr >= self.rsiOB:
                    self.bull_rsi_done = True
                
                if self.bull_rsi_done:
                    if np.isnan(self.bull_high_px):
                        self.bull_high_px = high_val
                    else:
                        self.bull_high_px = max(self.bull_high_px, high_val)
                
                if self.bull_rsi_done and not np.isnan(self.bull_high_px) and hull_turn_red:
                    self.bull_zone_top = self.bull_high_px
                    self.bull_zone_bot = close_val
                    self.bull_cand_on = True
                    self.bull_validated = False
                    self.bull_retest = False
                    self.bull_rsi_done = False
                    self.bull_high_px = np.nan
            
            if self.bull_cand_on and not self.bull_validated:
                if high_val >= self.bull_zone_bot and close_val <= self.bull_zone_top:
                    self.bull_retest = True
                
                if self.bull_retest and hull_curr < hull_prev2 and close_val < self.bull_zone_top:
                    self.bull_validated = True
                    self.bull_cand_on = False
        
        # Bearish sequence logic
        if self.enableBear:
            if st_flip_bear:
                self.bear_seq = True
                self.bear_rsi_done = False
                self.bear_low_px = np.nan
            
            if st_flip_bull:
                self.bear_seq = False
                self.bear_cand_on = False
            
            if self.bear_seq:
                if rsi_curr <= self.rsiOS:
                    self.bear_rsi_done = True
                
                if self.bear_rsi_done:
                    if np.isnan(self.bear_low_px):
                        self.bear_low_px = low_val
                    else:
                        self.bear_low_px = min(self.bear_low_px, low_val)
                
                if self.bear_rsi_done and not np.isnan(self.bear_low_px) and hull_turn_grn:
                    self.bear_zone_bot = self.bear_low_px
                    self.bear_zone_top = close_val
                    self.bear_cand_on = True
                    self.bear_validated = False
                    self.bear_retest = False
                    self.bear_rsi_done = False
                    self.bear_low_px = np.nan
            
            if self.bear_cand_on and not self.bear_validated:
                if low_val <= self.bear_zone_top and close_val >= self.bear_zone_bot:
                    self.bear_retest = True
                
                if self.bear_retest and hull_curr > hull_prev2 and close_val > self.bear_zone_bot:
                    self.bear_validated = True
                    self.bear_cand_on = False
        
        # Micro-structure logic
        is_green = close_val >= open_val
        is_red = close_val < open_val
        
        if is_green:
            self.g_count += 1
            self.r_count = 0
        elif is_red:
            self.r_count += 1
            self.g_count = 0
        
        if self.g_count >= 2:
            self.had_two_g = True
            self.had_two_r = False
            if np.isnan(self.ms_high_px):
                self.ms_high_px = high_val
            else:
                self.ms_high_px = max(self.ms_high_px, high_val)
        
        if self.r_count >= 2:
            self.had_two_r = True
            self.had_two_g = False
            if np.isnan(self.ms_low_px):
                self.ms_low_px = low_val
            else:
                self.ms_low_px = min(self.ms_low_px, low_val)
        
        # Trading rules based on validated liquidity levels
        
        # Buy signal: Bull validated or bull flip + trend confirmation
        if self.bull_validated and st_bull:
            if not self.position:
                self.buy()
        
        # Sell signal: Bear validated or bear flip + trend confirmation
        if self.bear_validated and st_bear:
            if self.position:
                self.sell()
        
        # Stop losses and take profits based on zone boundaries
        if self.position:
            if self.bear_validated and close_val < self.bear_zone_bot:
                self.sell()
            elif self.bull_validated and close_val > self.bull_zone_top:
                self.sell()
        
        # Alternative: use RSI extremes with hull confirmation
        if not self.position and rsi_curr < self.rsiOS and hull_curr > hull_prev2 and st_bull:
            self.buy()
        elif self.position and rsi_curr > self.rsiOB and hull_curr < hull_prev2 and st_bear:
            self.sell()