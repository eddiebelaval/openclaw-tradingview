import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # A Line (Vervoort Stop) parameters
    vPeriod = 100
    vMultiplier = 1.0
    
    # K Line (Vervoort Stop + Kernel) parameters
    vPeriodSignal = 100
    vMultiplierSignal = 2.0
    kernelLenK = 100
    kernelAlphaK = 0.3
    
    # Percentile Bands parameters
    percentilePeriod = 14
    upperPercentile = 80
    lowerPercentile = 80
    outerUpperPercentile = 95
    outerLowerPercentile = 95

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # Calculate Heikin Ashi smoothed price
        self.ha_close = self.I(self._calc_ha_close, open_, high, low, close)
        self.ha_open = self.I(self._calc_ha_open, open_, close)
        self.ha_high = self.I(self._calc_ha_high, high, self.ha_open, self.ha_close)
        self.ha_low = self.I(self._calc_ha_low, low, self.ha_open, self.ha_close)
        self.ha_price = self.I(self._calc_ha_price, self.ha_open, self.ha_high, self.ha_low, self.ha_close)
        
        # Calculate A Line (Vervoort Stop)
        self.a_line = self.I(self._calc_vervoort, high, low, close, self.vPeriod, self.vMultiplier, self.ha_price, self.ha_close)
        
        # Calculate K Line (Vervoort Stop + Kernel)
        self.k_raw = self.I(self._calc_vervoort, high, low, close, self.vPeriodSignal, self.vMultiplierSignal, self.ha_price, self.ha_close)
        self.k_line = self.I(self._calc_kernel, self.k_raw, self.kernelLenK, self.kernelAlphaK)
        
        # Calculate signals
        self.long_signal = self.I(lambda: self._crossover_signal(self.a_line, self.k_line, direction='up'))
        self.short_signal = self.I(lambda: self._crossover_signal(self.a_line, self.k_line, direction='down'))

    def _calc_ha_close(self, open_, high, low, close):
        return (open_ + high + low + close) / 4.0

    def _calc_ha_open(self, open_, close):
        ha_open = pd.Series(index=open_.index, dtype=float)
        ha_open.iloc[0] = (open_.iloc[0] + close.iloc[0]) / 2.0
        for i in range(1, len(open_)):
            ha_open.iloc[i] = (ha_open.iloc[i-1] + self.ha_close.iloc[i-1]) / 2.0
        return ha_open

    def _calc_ha_high(self, high, ha_open, ha_close):
        return np.maximum(high, np.maximum(ha_open, ha_close))

    def _calc_ha_low(self, low, ha_open, ha_close):
        return np.minimum(low, np.minimum(ha_open, ha_close))

    def _calc_ha_price(self, ha_open, ha_high, ha_low, ha_close):
        return (ha_open + ha_high + ha_low + ha_close) / 4.0

    def _calc_vervoort(self, high, low, close, period, multiplier, ha_price, ha_close):
        atr = pta.atr(high, low, close, length=period)
        if atr is None:
            atr = pd.Series(0, index=close.index)
        
        loss = multiplier * atr
        v_stop = pd.Series(index=close.index, dtype=float)
        trend_is_up = pd.Series(index=close.index, dtype=bool)
        
        v_stop.iloc[0] = ha_close.iloc[0] - loss.iloc[0]
        trend_is_up.iloc[0] = True
        
        for i in range(1, len(close)):
            prev_v_stop = v_stop.iloc[i-1]
            trend_is_up_curr = ha_close.iloc[i] > prev_v_stop
            
            if trend_is_up_curr:
                v_stop.iloc[i] = max(prev_v_stop, ha_price.iloc[i] - loss.iloc[i])
            else:
                v_stop.iloc[i] = min(prev_v_stop, ha_price.iloc[i] + loss.iloc[i])
            
            if trend_is_up.iloc[i-1] and ha_close.iloc[i] < v_stop.iloc[i]:
                trend_is_up.iloc[i] = False
                v_stop.iloc[i] = ha_price.iloc[i] + loss.iloc[i]
            elif not trend_is_up.iloc[i-1] and ha_close.iloc[i] > v_stop.iloc[i]:
                trend_is_up.iloc[i] = True
                v_stop.iloc[i] = ha_price.iloc[i] - loss.iloc[i]
            else:
                trend_is_up.iloc[i] = trend_is_up.iloc[i-1]
        
        return v_stop

    def _calc_kernel(self, src, kernel_len, kernel_alpha):
        result = pd.Series(index=src.index, dtype=float)
        
        for idx in range(len(src)):
            if idx < kernel_len - 1:
                result.iloc[idx] = src.iloc[idx]
                continue
            
            start_idx = idx - kernel_len + 1
            window = src.iloc[start_idx:idx+1].values
            
            sum_val = 0.0
            weight_sum = 0.0
            center = kernel_len / 2.0
            
            for i in range(kernel_len):
                x = float(i)
                price = window[kernel_len - 1 - i]
                
                dist = abs(x - center)
                recency_weight = np.exp(-kernel_alpha * (kernel_len - 1 - i) / kernel_len)
                local_weight = np.exp(-np.power(dist / (kernel_len / 3), 2))
                weight = recency_weight * local_weight
                
                sum_val += price * weight
                weight_sum += weight
            
            result.iloc[idx] = sum_val / weight_sum if weight_sum > 0 else src.iloc[idx]
        
        return result

    def _crossover_signal(self, a_line, k_line, direction='up'):
        signal = pd.Series(False, index=a_line.index)
        
        for i in range(1, len(a_line)):
            if direction == 'up':
                if a_line.iloc[i-1] <= k_line.iloc[i-1] and a_line.iloc[i] > k_line.iloc[i]:
                    signal.iloc[i] = True
            else:
                if a_line.iloc[i-1] >= k_line.iloc[i-1] and a_line.iloc[i] < k_line.iloc[i]:
                    signal.iloc[i] = True
        
        return signal

    def next(self):
        if len(self.data) < self.kernelLenK + 10:
            return
        
        if self.long_signal[-1]:
            if not self.position:
                self.buy()
        elif self.short_signal[-1]:
            if self.position:
                self.position.close()