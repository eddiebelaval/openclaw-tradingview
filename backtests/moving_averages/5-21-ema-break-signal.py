import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        self.ema5 = self.I(pta.ema, close, length=5)
        self.ema21 = self.I(pta.ema, close, length=21)
        
        self.close = close
        self.high = high
        self.low = low
        self.open = open_

    def next(self):
        if len(self.data) < 2:
            return
        
        # Current values
        close_curr = self.close.iloc[-1]
        high_curr = self.high.iloc[-1]
        low_curr = self.low.iloc[-1]
        open_curr = self.open.iloc[-1]
        
        # Previous values
        close_prev = self.close.iloc[-2]
        high_prev = self.high.iloc[-2]
        low_prev = self.low.iloc[-2]
        open_prev = self.open.iloc[-2]
        
        ema5_curr = self.ema5[-1]
        ema21_curr = self.ema21[-1]
        ema5_prev = self.ema5[-2]
        ema21_prev = self.ema21[-2]
        
        # BUY CONDITIONS
        prevBullish = close_prev > open_prev
        prevBelowEMA = high_prev < ema5_prev and high_prev < ema21_prev
        currentAboveEMA = close_curr > ema5_curr and close_curr > ema21_curr
        buySignal = prevBullish and prevBelowEMA and currentAboveEMA
        
        # SELL CONDITIONS
        prevBearish = close_prev < open_prev
        prevAboveEMA = low_prev > ema5_prev and low_prev > ema21_prev
        currentBelowEMA = close_curr < ema5_curr and close_curr < ema21_curr
        sellSignal = prevBearish and prevAboveEMA and currentBelowEMA
        
        # Execute trades
        if buySignal and not self.position:
            self.buy()
        elif sellSignal and self.position:
            self.position.close()


