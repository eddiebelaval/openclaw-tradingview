import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema50Length = 50
    ema100Length = 100
    ema200Length = 200
    bbMult = 2.2
    adxLen = 10
    adxThresh = 15
    rsiLen = 14
    lenHA1_input = 10
    lenHA2_input = 10
    fastLen = 9
    slowLen = 20
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # Dynamic EMA Lengths
        self.fastLen = self.fastLen
        self.slowLen = self.slowLen
        
        # Automatic HA Lengths
        self.lenHA1 = self.lenHA1_input if self.lenHA1_input != 10 else 10
        self.lenHA2 = self.lenHA2_input if self.lenHA2_input != 10 else 35
        
        # Main EMAs
        self.emaFast = self.I(pta.ema, close, length=self.fastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.slowLen)
        
        # Support EMAs
        self.ema50 = self.I(pta.ema, close, length=self.ema50Length)
        self.ema100 = self.I(pta.ema, close, length=self.ema100Length)
        self.ema200 = self.I(pta.ema, close, length=self.ema200Length)
        
        # Bollinger Bands based on emaSlow
        stdev = self.I(lambda: close.rolling(self.slowLen).std())
        self.upper = self.I(lambda: self.emaSlow + self.bbMult * stdev)
        self.lower = self.I(lambda: self.emaSlow - self.bbMult * stdev)
        
        # ADX
        adx_result = self.I(pta.adx, high, low, close, length=self.adxLen)
        self.adx = self.I(lambda: adx_result if adx_result is not None else pd.Series(0, index=close.index))
        
        # Custom EMA for HA
        self.ha_o1 = self.I(self._ema_custom, open_, self.lenHA1)
        self.ha_h1 = self.I(self._ema_custom, high, self.lenHA1)
        self.ha_l1 = self.I(self._ema_custom, low, self.lenHA1)
        self.ha_c1 = self.I(self._ema_custom, close, self.lenHA1)
        
        # Initialize HA values
        self.haOpen_prev = None
        self.haClose_prev = None
        
        # RSI for trend detection
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        self.buy_signal = False
        self.sell_signal = False
        self.ha_bull_prev = False

    def _ema_custom(self, src_series):
        """Custom EMA calculation matching Pine Script"""
        length = self.lenHA1
        alpha = 2.0 / (length + 1.0)
        ema_vals = []
        sma_init = None
        prev_ema = None
        
        for i in range(len(src_series)):
            if i < length:
                if i == length - 1:
                    sma_init = src_series[:i+1].mean()
                    ema_vals.append(sma_init)
                    prev_ema = sma_init
                else:
                    ema_vals.append(np.nan)
            else:
                if prev_ema is not None:
                    new_ema = alpha * src_series.iloc[i] + (1.0 - alpha) * prev_ema
                    ema_vals.append(new_ema)
                    prev_ema = new_ema
                else:
                    ema_vals.append(np.nan)
        
        return pd.Series(ema_vals, index=src_series.index)

    def next(self):
        # Skip if not enough data
        if len(self.data) < max(self.slowLen, self.adxLen, self.lenHA1 + self.lenHA2):
            return
        
        # Get current values
        ema_fast = self.emaFast[-1]
        ema_slow = self.emaSlow[-1]
        adx_val = self.adx[-1] if not np.isnan(self.adx[-1]) else 0
        
        # EMA crossover signals with ADX filter
        ema_buy = crossover(self.emaFast, self.emaSlow) and adx_val > self.adxThresh
        ema_sell = crossover(self.emaSlow, self.emaFast) and adx_val > self.adxThresh
        
        # Heikin-Ashi calculations
        if len(self.data) >= self.lenHA1:
            ha_o1 = self.ha_o1[-1]
            ha_h1 = self.ha_h1[-1]
            ha_l1 = self.ha_l1[-1]
            ha_c1 = self.ha_c1[-1]
            
            ha_close = (ha_o1 + ha_h1 + ha_l1 + ha_c1) / 4
            
            if self.haOpen_prev is None:
                ha_open = (ha_o1 + ha_c1) / 2
            else:
                ha_open = (self.haOpen_prev + self.haClose_prev) / 2
            
            ha_high = max(ha_h1, max(ha_open, ha_close))
            ha_low = min(ha_l1, min(ha_open, ha_close))
            
            # Apply second smoothing
            if len(self.data) >= self.lenHA1 + self.lenHA2:
                ha_bull = ha_close >= ha_open
                ha_buy = ha_bull and not self.ha_bull_prev
                ha_sell = not ha_bull and self.ha_bull_prev
                
                self.ha_bull_prev = ha_bull
            else:
                ha_buy = False
                ha_sell = False
            
            self.haOpen_prev = ha_open
            self.haClose_prev = ha_close
        else:
            ha_buy = False
            ha_sell = False
        
        # Combined signals
        if ema_buy or ha_buy:
            if not self.position:
                self.buy()
        elif ema_sell or ha_sell:
            if self.position:
                self.sell()


