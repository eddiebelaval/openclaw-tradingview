import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLength = 12
    slowLength = 26
    signalLength = 9

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate MACD components
        fastMA = self.I(pta.ema, close, length=self.fastLength)
        slowMA = self.I(pta.ema, close, length=self.slowLength)
        
        # MACD line
        macd = self.I(lambda: fastMA - slowMA)
        
        # Signal line (SMA of MACD)
        macd_values = fastMA - slowMA
        signal = self.I(pta.sma, pd.Series(macd_values), length=self.signalLength)
        
        self.fastMA = fastMA
        self.slowMA = slowMA
        self.macd = macd
        self.signal = signal
        self.state = 0

    def next(self):
        # Check for MACD crossovers
        if len(self.macd) < 2 or len(self.signal) < 2:
            return
        
        # Bullish crossover: MACD crosses above signal
        bull_cross = crossover(self.macd, self.signal)
        
        # Bearish crossover: MACD crosses below signal
        bear_cross = crossover(self.signal, self.macd)
        
        # Trading logic with state memory
        if bull_cross and self.state != 1:
            self.buy()
            self.state = 1
        
        if bear_cross and self.state != -1:
            self.sell()
            self.state = -1