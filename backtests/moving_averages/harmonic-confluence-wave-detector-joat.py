        hlc3 = (high + low + close) / 3
        esa = self.I(pta.ema, hlc3, length=self.wtChannelLen)
        d = self.I(lambda: pta.ema(np.abs(hlc3 - esa), length=self.wtChannelLen))
        ci = self.I(lambda: (hlc3 - esa) / (0.015 * d))
        self.wt1 = self.I(pta.ema, ci, length=self.wtAverageLen)
        self.wt2 = self.I(pta.sma, self.wt1, length=self.wtMALen)
        
        # MFI Calculation
        def calc_mfi_custom(src_series, vol_series, length):
            mfi_upper = pd.Series(index=src_series.index, dtype=float)
            mfi_lower = pd.Series(index=src_series.index, dtype=float)
            
            for i in range(length, len(src_series)):
                upper_sum = 0
                lower_sum = 0
                for j in range(i - length, i):
                    if src_series.iloc[j] > src_series.iloc[j-1]:
                        upper_sum += vol_series.iloc[j] * (high.iloc[j] - low.iloc[j])
                    else:
                        lower_sum += vol_series.iloc[j] * (high.iloc[j] - low.iloc[j])
                
                if lower_sum == 0:
                    mfi_upper.iloc[i] = 0
                    mfi_lower.iloc[i] = 0
                else:
                    mfi_upper.iloc[i] = upper_sum
                    mfi_lower.iloc[i] = lower_sum
            
            mfi_raw = 100 - (100 / (1 + mfi_upper / mfi_lower.replace(0, 1)))
            mfi_raw = mfi_raw - 50
            return pta.sma(mfi_raw, length=9)
        
        self.mfi = self.I(calc_mfi_custom, close, volume, self.mfiLength)

