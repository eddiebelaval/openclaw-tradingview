        macd_result = self.I(lambda: pta.macd(close, fast=self.fastLength, slow=self.slowLength, signal=self.signalLength))
        self.macd = self.I(lambda: macd_result['MACD_12_26_9'] if macd_result is not None and 'MACD_12_26_9' in macd_result.columns else pd.Series(0, index=close.index))
        self.macd_signal = self.I(lambda: macd_result['MACDs_12_26_9'] if macd_result is not None and 'MACDs_12_26_9' in macd_result.columns else pd.Series(0, index=close.index))
        self.macd_hist = self.I(lambda: macd_result['MACDh_12_26_9'] if macd_result is not None and 'MACDh_12_26_9' in macd_result.columns else pd.Series(0, index=close.index))
        
