import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen = 9
    smaLen = 20
    rrRatio = 1.5
    tickBuffer = 0.5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema = self.I(pta.ema, close, length=self.emaLen)
        self.sma = self.I(pta.sma, close, length=self.smaLen)
        
        self.trades = []

    def next(self):
        # Check if we have enough data
        if len(self.data) < max(self.emaLen, self.smaLen) + 1:
            return
        
        current_time = pd.Timestamp(self.data.index[-1])
        
        # Simple time window check (approximate for intraday)
        hour = current_time.hour
        minute = current_time.minute
        current_time_minutes = hour * 60 + minute
        
        # Morning: 9:30-11:30 (570-690 minutes from midnight)
        # Power: 15:00-16:00 (900-960 minutes from midnight)
        is_morning = 570 <= current_time_minutes <= 690
        is_power = 900 <= current_time_minutes <= 960
        is_trade_window = is_morning or is_power
        
        if not is_trade_window:
            return
        
        # Check for crossover signals
        long_cross = crossover(self.ema, self.sma)
        short_cross = crossover(self.sma, self.ema)
        
        if long_cross:
            entry = self.data.Close[-1]
            sl = self.data.Low[-2] - self.tickBuffer
            risk = abs(entry - sl)
            tp = entry + (risk * self.rrRatio)
            
            self.buy()
            self.trades.append({
                'side': 'BUY',
                'entry': entry,
                'sl': sl,
                'tp': tp,
                'status': 'ACTIVE'
            })
        
        elif short_cross:
            entry = self.data.Close[-1]
            sl = self.data.High[-2] + self.tickBuffer
            risk = abs(entry - sl)
            tp = entry - (risk * self.rrRatio)
            
            self.sell()
            self.trades.append({
                'side': 'SELL',
                'entry': entry,
                'sl': sl,
                'tp': tp,
                'status': 'ACTIVE'
            })
        
        # Monitor active trades
        for trade in self.trades:
            if trade['status'] == 'ACTIVE':
                if trade['side'] == 'BUY':
                    if self.data.High[-1] >= trade['tp']:
                        trade['status'] = 'WIN'
                        if self.position:
                            self.position.close()
