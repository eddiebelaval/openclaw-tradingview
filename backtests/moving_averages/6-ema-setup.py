import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len1 = 9
    len2 = 21
    len3 = 34
    len4 = 89
    len5 = 200
    len6 = 500

    def init(self):
        close = pd.Series(self.data.Close)
        
        self.ema1 = self.I(pta.ema, close, length=self.len1)
        self.ema2 = self.I(pta.ema, close, length=self.len2)
        self.ema3 = self.I(pta.ema, close, length=self.len3)
        self.ema4 = self.I(pta.ema, close, length=self.len4)
        self.ema5 = self.I(pta.ema, close, length=self.len5)
        self.ema6 = self.I(pta.ema, close, length=self.len6)

    def next(self):
        if len(self.data) < self.len6 + 1:
            return
        
        ema1_prev = self.ema1[-2]
        ema1_curr = self.ema1[-1]
        ema2_prev = self.ema2[-2]
        ema2_curr = self.ema2[-1]
        
        price = self.data.Close[-1]
        
        if ema1_curr is None or ema2_curr is None:
            return
        
        if not self.position:
            if crossover(self.ema1, self.ema2):
                self.buy()
        else:
            if crossover(self.ema2, self.ema1):
                self.sell()


