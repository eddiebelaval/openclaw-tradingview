import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 20
    emaSlowLen = 100
    volEmaLen = 20
    rsiLen = 14
    rsiOB = 70
    rsiOS = 30

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)
        
        self.volEma = self.I(pta.ema, volume, length=self.volEmaLen)
        
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        
        self.last_trend = None

    def next(self):
        if len(self.data) < max(self.emaFastLen, self.emaSlowLen) + 1:
            return
        
        close = self.data.Close[-1]
        emaFast = self.emaFast[-1]
        emaSlow = self.emaSlow[-1]
        volume = self.data.Volume[-1]
        volEma = self.volEma[-1]
        rsi = self.rsi[-1]
        
        if pd.isna(emaFast) or pd.isna(emaSlow) or pd.isna(volEma) or pd.isna(rsi):
            return
        
        isUptrend = close > emaFast and emaFast > emaSlow
        isDowntrend = close < emaFast and emaFast < emaSlow
        
        volRatio = volume / volEma if volEma > 0 else 1.0
        volumeHigh = volRatio > 1.2
        
        buyersHigh = isUptrend and volumeHigh
        rsiOversold = rsi < self.rsiOS
        rsiOverbought = rsi > self.rsiOB
        
        if self.position:
            if isDowntrend or (self.position.is_long and rsiOverbought):
                self.position.close()
        else:
            if buyersHigh and rsiOversold:
                self.buy()
            elif isUptrend and not rsiOverbought:
                if crossover(self.emaFast, self.emaSlow):
                    self.buy()
        
        if self.position:
            if isDowntrend:
                self.position.close()