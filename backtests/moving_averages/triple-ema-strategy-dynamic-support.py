import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len1 = 20
    len2 = 50
    len3 = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema1 = self.I(pta.ema, close, length=self.len1)
        self.ema2 = self.I(pta.ema, close, length=self.len2)
        self.ema3 = self.I(pta.ema, close, length=self.len3)
        
        self.high_series = high
        self.low_series = low

    def next(self):
        if len(self.data) < self.len3:
            return
        
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_close = self.data.Close[-1]
        
        ema1_val = self.ema1[-1]
        ema2_val = self.ema2[-1]
        ema3_val = self.ema3[-1]
        
        if ema1_val is None or ema2_val is None or ema3_val is None:
            return
        
        in_uptrend = ema1_val > ema2_val > ema3_val
        in_downtrend = ema1_val < ema2_val < ema3_val
        
        toque_ema50 = current_low <= ema2_val and current_high >= ema2_val
        
        if not self.position:
            if in_uptrend and toque_ema50 and current_close > ema2_val:
                self.buy()
            elif in_downtrend and toque_ema50 and current_close < ema2_val:
                self.sell()
        else:
            if self.position.is_long:
                if crossover(self.ema2, self.ema3):
                    self.position.close()
                elif current_close < ema3_val:
                    self.position.close()
            elif self.position.is_short:
                if crossover(self.ema3, self.ema2):
                    self.position.close()
                elif current_close > ema3_val:
                    self.position.close()