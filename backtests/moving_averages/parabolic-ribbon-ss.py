import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 100
    sd_1 = 1.0
    sd_2 = 2.0
    sd_3 = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate SMA basis
        self.price_basis = self.I(pta.sma, close, length=self.lookback)
        
        # Calculate rolling standard deviation
        self.rolling_stdev = self.I(
            lambda c: pd.Series(c).rolling(self.lookback).std(),
            close
        )
        
        # Calculate band width
        self.band_width = self.I(
            lambda pb, rs: (pb + (rs * self.sd_3)) - (pb - (rs * self.sd_3)),
            self.price_basis,
            self.rolling_stdev
        )
        
        # Calculate average band width
        self.avg_band_width = self.I(
            lambda bw: pd.Series(bw).rolling(100).mean(),
            self.band_width
        )
        
        # Calculate volatility score
        self.vola_score = self.I(
            lambda bw, abw: (bw / abw) * 100,
            self.band_width,
            self.avg_band_width
        )
        
        # Calculate correlation for trend detection
        self.trend_corr = self.I(
            lambda c: pd.Series(c).rolling(self.lookback).apply(
                lambda x: np.corrcoef(np.arange(len(x)), x)[0, 1] if len(x) > 1 else 0
            ),
            close
        )
        
        # Calculate band levels
        self.h3 = self.I(
            lambda pb, rs: pb + (rs * self.sd_3),
            self.price_basis,
            self.rolling_stdev
        )
        self.h2 = self.I(
            lambda pb, rs: pb + (rs * self.sd_2),
            self.price_basis,
            self.rolling_stdev
        )
        self.h1 = self.I(
            lambda pb, rs: pb + (rs * self.sd_1),
            self.price_basis,
            self.rolling_stdev
        )
        self.l1 = self.I(
            lambda pb, rs: pb - (rs * self.sd_1),
            self.price_basis,
            self.rolling_stdev
        )
        self.l2 = self.I(
            lambda pb, rs: pb - (rs * self.sd_2),
            self.price_basis,
            self.rolling_stdev
        )
        self.l3 = self.I(
            lambda pb, rs: pb - (rs * self.sd_3),
            self.price_basis,
            self.rolling_stdev
        )
        
        # Track market state transitions
        self.market_state_prev = None
        self.last_signal = None

    def next(self):
        if len(self.data) < self.lookback + 1:
            return
        
        close = self.data.Close[-1]
        
        # Determine current market state
        current_bw = self.band_width[-1]
        avg_bw = self.avg_band_width[-1]
        
        if current_bw < avg_bw:
            market_state = "CONTRACTION"
        else:
            market_state = "EXPANSION"
        
        # Determine trend
        corr = self.trend_corr[-1]
        if corr >= 0.1:
            trend = "Uptrend"
        elif corr <= -0.1:
            trend = "Downtrend"
        else:
            trend = "No Trend"
        
        # Trading logic based on state transitions
        if len(self.data) > self.lookback + 1:
            # Transition from CONTRACTION to EXPANSION
            if (self.market_state_prev == "CONTRACTION" and 
                market_state == "EXPANSION"):
                
                if trend == "Uptrend" and not self.position:
                    self.buy()
                    self.last_signal = "Long"
                elif trend == "Downtrend" and self.position:
                    self.sell()
                    self.last_signal = "Short"
            
            # Transition from EXPANSION to CONTRACTION
            elif (self.market_state_prev == "EXPANSION" and 
                  market_state == "CONTRACTION"):
                if self.position:
                    self.sell()
                self.last_signal = "Consolidation"
        
        # Exit conditions based on price and bands
        if self.position:
            if self.last_signal == "Long":
                # Exit if price crosses below SMA
                if close < self.price_basis[-1]:
                    self.sell()
            elif self.last_signal == "Short":
                # Exit if price crosses above SMA
                if close > self.price_basis[-1]:
                    self.buy()
        
        self.market_state_prev = market_state


