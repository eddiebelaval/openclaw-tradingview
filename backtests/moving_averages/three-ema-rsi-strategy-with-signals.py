import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # EMA Settings
    ema_fast_len = 3
    ema_med_len = 21
    ema_slow_med_len = 50
    ema_slow_len = 200
    
    # RSI Settings
    rsi_avg_period = 20
    rsi_thresh_long = 55.0
    rsi_thresh_short = 45.0
    
    # EMA Slope Settings
    ema_slope_lookback = 3
    ema_slope_long_th = 0.05
    ema_slope_short_th = -0.05
    ema_slope_flat_th = 0.02
    ema_slope_flat_count = 3
    
    # Strong Candle Settings
    strong_body_multiplier = 1.5
    strong_lookback = 20
    strong_body_pct = 50.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        # Calculate EMAs
        self.ema_fast = self.I(pta.ema, close, length=self.ema_fast_len)
        self.ema_med = self.I(pta.ema, close, length=self.ema_med_len)
        self.ema_slow_med = self.I(pta.ema, close, length=self.ema_slow_med_len)
        self.ema_slow = self.I(pta.ema, close, length=self.ema_slow_len)
        
        # Calculate RSI
        self.rsi_mtf = self.I(pta.rsi, close, length=self.rsi_avg_period)
        
        # Strong candle detection
        self.body_size = self.I(lambda: np.abs(open_ - close))
        self.total_range = self.I(lambda: high - low)
        self.body_pct = self.I(lambda: (np.abs(open_ - close) / (high - low)).replace([np.inf, -np.inf], 0).fillna(0) * 100)
        self.avg_body = self.I(pta.sma, self.body_size, length=self.strong_lookback)
        
        # ATR for slope line
        self.atr = self.I(pta.atr, high, low, close, length=14)
        
        # State variables
        self.ema_cross_long = False
        self.ema_cross_short = False
        self.ema_cross_long_strong = False
        self.ema_cross_short_strong = False
        self.is_long_mode = False
        self.is_short_mode = False
        
        # Slope tracking
        self.slope_history = []
        self.last_ema_slope = 0.0
        self.slope_ready = False
        self.flat_counter = 0
        self.is_ranging = False
        self.last_htf_bar_index = -1

    def next(self):
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        # Detect new HTF bar (simplified: every bar in backtest)
        is_new_htf_bar = len(self.data) > 0
        
        if is_new_htf_bar and len(self.data) != self.last_htf_bar_index:
            self.last_htf_bar_index = len(self.data)
            
            # Update slope history
            self.slope_history.append(self.ema_slow_med[-1])
            if len(self.slope_history) > self.ema_slope_lookback + 1:
                self.slope_history.pop(0)
            
            if len(self.slope_history) > self.ema_slope_lookback:
                past_val = self.slope_history[0]
                if past_val != 0:
                    self.last_ema_slope = (self.ema_slow_med[-1] - past_val) / past_val * 100
                else:
                    self.last_ema_slope = 0.0
                self.slope_ready = True
                
                # Flat/Ranging detection
                if abs(self.last_ema_slope) < self.ema_slope_flat_th:
                    self.flat_counter += 1
                else:
                    self.flat_counter = 0
                
                self.is_ranging = self.flat_counter >= self.ema_slope_flat_count
        
        # Strong candle detection
        body_size = abs(close - open_)
        total_range = high - low
        body_pct = (body_size / total_range * 100) if total_range > 0 else 0.0
        avg_body = self.avg_body[-1] if len(self.avg_body) > 0 else 0
        
        is_strong = (total_range > 0 and 
                    body_size > avg_body * self.strong_body_multiplier and 
                    body_pct >= self.strong_body_pct)
        is_bull_strong = is_strong and close > open_
        is_bear_strong = is_strong and close < open_
        
        # EMA cross signals
        cross_long_signal = crossover(self.ema_slow_med, self.ema_slow)
        cross_short_signal = crossover(self.ema_slow, self.ema_slow_med)
        
        # LONG LOGIC
        if cross_long_signal:
            self.ema_cross_long = True
            self.ema_cross_short = False
            self.ema_cross_short_strong = False
            self.is_long_mode = True
            self.is_short_mode = False
        
        long_entry_signal = (self.ema_cross_long and 
                            is_bull_strong and 
                            close > self.ema_med[-1] and 
                            close > self.ema_slow_med[-1] and 
                            not self.ema_cross_long_strong and 
                            not self.is_ranging)
        
        if long_entry_signal:
            self.ema_cross_long_strong = True
            if not self.position:
                self.buy()
        
        long_exit_now = (self.ema_cross_long_strong and 
                        is_bear_strong and 
                        close < self.ema_med[-1])
        
        if long_exit_now:
            self.ema_cross_long_strong = False
            if self.position:
                self.position.close()
        
        # SHORT LOGIC
        if cross_short_signal:
            self.ema_cross_short = True
            self.ema_cross_long = False
            self.ema_cross_long_strong = False
            self.is_short_mode = True
            self.is_long_mode = False
        
        short_entry_signal = (self.ema_cross_short and 
                             is_bear_strong and 
                             close < self.ema_med[-1] and 
                             close < self.ema_slow_med[-1] and 
                             not self.ema_cross_short_strong and 
                             not self.is_ranging)
        
        if short_entry_signal:
            self.ema_cross_short_strong = True
            if not self.position:
                self.sell()
        
        short_exit_now = (self.ema_cross_short_strong and 
                         is_bull_strong and 
                         close > self.ema_med[-1])
        
        if short_exit_now:
            self.ema_cross_short_strong = False
            if self.position:
                self.position.close()