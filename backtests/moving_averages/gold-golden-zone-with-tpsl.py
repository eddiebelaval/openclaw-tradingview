import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_length = 50
    fib_swing_length = 20
    structure_lookback = 5
    atr_length = 14
    risk_reward = 2.0
    stop_buffer_atr = 1.5
    use_confirmation = False

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema = self.I(pta.ema, close, length=self.ema_length)
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        self.swing_high = self.I(self._pivot_high, high, self.fib_swing_length)
        self.swing_low = self.I(self._pivot_low, low, self.fib_swing_length)
        
        self.minor_high = self.I(self._pivot_high, high, self.structure_lookback)
        self.minor_low = self.I(self._pivot_low, low, self.structure_lookback)
        
        self.last_swing_high = np.nan
        self.last_swing_low = np.nan
        self.last_swing_high_bar = -1
        self.last_swing_low_bar = -1
        
        self.last_minor_high = np.nan
        self.last_minor_low = np.nan
        
        self.fib_50 = np.nan
        self.fib_618 = np.nan
        
        self.active_entry = np.nan
        self.active_stop = np.nan
        self.active_target = np.nan
        self.active_dir = None

    def _pivot_high(self, highs, lookback):
        result = pd.Series(np.nan, index=highs.index)
        for i in range(lookback, len(highs) - lookback):
            if highs.iloc[i] == highs.iloc[i-lookback:i+lookback+1].max():
                result.iloc[i] = highs.iloc[i]
        return result

    def _pivot_low(self, lows, lookback):
        result = pd.Series(np.nan, index=lows.index)
        for i in range(lookback, len(lows) - lookback):
            if lows.iloc[i] == lows.iloc[i-lookback:i+lookback+1].min():
                result.iloc[i] = lows.iloc[i]
        return result

    def next(self):
        if len(self) < self.fib_swing_length + 1:
            return
        
