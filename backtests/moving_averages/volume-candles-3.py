import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    lookback = 20
    volMult = 1.5
    bodyMult = 2.0

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        volume = pd.Series(self.data.Volume)
        
        # Calculate average body size (absolute difference between close and open)
        body_diff = (close - open_).abs()
        self.avgBody = self.I(pta.sma, body_diff, length=self.lookback)
        
        # Calculate average volume
        self.avgVol = self.I(pta.sma, volume, length=self.lookback)
        
        # Store open and close for condition checking
        self.open_prices = open_
        self.close_prices = close
        self.volumes = volume

    def next(self):
        if len(self.data) < self.lookback:
            return
        
        current_close = self.data.Close[-1]
        current_open = self.data.Open[-1]
        current_volume = self.data.Volume[-1]
        current_body = abs(current_close - current_open)
        
        avg_body = self.avgBody[-1]
        avg_vol = self.avgVol[-1]
        
        # Condition for Big Bull Candle
        isBigBull = (current_close > current_open and 
                     current_body > avg_body * self.bodyMult and 
                     current_volume > avg_vol * self.volMult)
        
        # Condition for Big Bear Candle
        isBigBear = (current_close < current_open and 
                     current_body > avg_body * self.bodyMult and 
                     current_volume > avg_vol * self.volMult)
        
        # Trading logic
        if isBigBull:
            if not self.position:
                self.buy()
            elif self.position.is_short:
                self.position.close()
                self.buy()
        
        elif isBigBear:
            if self.position:
                self.sell()