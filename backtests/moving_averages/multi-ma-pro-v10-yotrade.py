import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # MA Method: "SMA", "EMA", "WMA", "VWMA", "HMA"
    ma_type = "EMA"
    
    # Fast MA settings
    len_fast = 20
    
    # Slow MA settings
    len_slow = 50
    
    # Additional MAs
    len_ma3 = 100
    len_ma4 = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate MAs based on type
        self.ma_fast = self.I(self._get_ma, self.ma_type, close, self.len_fast)
        self.ma_slow = self.I(self._get_ma, self.ma_type, close, self.len_slow)
        self.ma3 = self.I(self._get_ma, self.ma_type, close, self.len_ma3)
        self.ma4 = self.I(self._get_ma, self.ma_type, close, self.len_ma4)

    def _get_ma(self, ma_type, src, length):
        if ma_type == "SMA":
            return pta.sma(src, length=length)
        elif ma_type == "EMA":
            return pta.ema(src, length=length)
        elif ma_type == "WMA":
            return pta.wma(src, length=length)
        elif ma_type == "VWMA":
            volume = pd.Series(self.data.Volume)
            return pta.vwma(src, volume, length=length)
        elif ma_type == "HMA":
            return pta.hma(src, length=length)
        else:
            return pta.ema(src, length=length)

    def next(self):
        # Buy signal: Fast MA crosses above Slow MA
        if crossover(self.ma_fast, self.ma_slow):
            self.buy()
        # Sell signal: Fast MA crosses below Slow MA
        elif crossover(self.ma_slow, self.ma_fast):
            self.sell()