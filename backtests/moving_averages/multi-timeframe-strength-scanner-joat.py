import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    adxLength = 14
    adxSmoothing = 14
    adxThreshold = 20
    trendLength = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Current timeframe ADX/DMI
        adx_result = self.I(lambda: pta.adx(high, low, close, length=self.adxLength))
        self.adx = adx_result
        
        # +DI and -DI from DMI
        dmi_result = self.I(lambda: pta.dmi(high, low, close, length=self.adxLength, mamode='ema'))
        self.dmi = dmi_result
        
        # Extract +DI (column 0) and -DI (column 1) from DMI result
        self.plus_di = self.I(lambda: pta.dmi(high, low, close, length=self.adxLength, mamode='ema').iloc[:, 0] if pta.dmi(high, low, close, length=self.adxLength, mamode='ema') is not None else pd.Series(50, index=close.index))
        self.minus_di = self.I(lambda: pta.dmi(high, low, close, length=self.adxLength, mamode='ema').iloc[:, 1] if pta.dmi(high, low, close, length=self.adxLength, mamode='ema') is not None else pd.Series(50, index=close.index))
        
        # Trend system using Donchian channels
        self.highest = self.I(lambda: pd.Series(close).rolling(window=self.trendLength).max())
        self.lowest = self.I(lambda: pd.Series(close).rolling(window=self.trendLength).min())
        
        # EMA for VWAP logic
        self.ema200 = self.I(pta.ema, close, length=200)

    def next(self):
        # Guard against insufficient data
        if len(self.data) < max(self.adxLength, self.trendLength, 200):
            return
        
        # Get current values
        adx = self.adx[-1] if len(self.adx) > 0 else 0
        plus_di = self.plus_di[-1] if len(self.plus_di) > 0 else 0
        minus_di = self.minus_di[-1] if len(self.minus_di) > 0 else 0
        close = self.data.Close[-1]
        ema200 = self.ema200[-1] if len(self.ema200) > 0 else close
        highest = self.highest[-1] if len(self.highest) > 0 else close
        lowest = self.lowest[-1] if len(self.lowest) > 0 else close
        
        # Trend determination
        trend = 0
        if len(self.data) > 1:
            prev_highest = self.highest[-2] if len(self.highest) > 1 else highest
            prev_lowest = self.lowest[-2] if len(self.lowest) > 1 else lowest
            
            if close > prev_highest:
                trend = 1
            elif close < prev_lowest:
                trend = -1
            else:
                trend = self.trend if hasattr(self, 'trend') else 0
        
        self.trend = trend
        
        # VWAP trend (using EMA200 as proxy)
        vwap_bullish = close > ema200
        
        # Entry signals
        # Strong bullish: ADX above threshold, +DI > -DI, close above EMA, uptrend
        strong_bull = (adx > self.adxThreshold and plus_di > minus_di and vwap_bullish and trend == 1)
        
        # Strong bearish: ADX above threshold, -DI > +DI, close below EMA, downtrend
        strong_bear = (adx > self.adxThreshold and minus_di > plus_di and not vwap_bullish and trend == -1)
        
        # DI crossover signals
        plus_cross_above = crossover(self.plus_di, self.minus_di) if len(self.plus_di) > 1 and len(self.minus_di) > 1 else False
        plus_cross_below = crossover(self.minus_di, self.plus_di) if len(self.minus_di) > 1 and len(self.plus_di) > 1 else False
        
        # Calculate overall strength (0-100 scale)
        overall_strength = min(100, max(0, (adx / 100) * 100))
        
        # Entry logic
        if not self.position:
            # Buy on strong bullish conditions or bullish DI cross with trend confirmation
            if strong_bull or (plus_cross_above and trend >= 0 and overall_strength > 25):
                self.buy()
            # Sell (short) on strong bearish conditions or bearish DI cross with trend confirmation
            elif strong_bear or (plus_cross_below and trend <= 0 and overall_strength > 25):
                self.sell()
        else:
            # Exit long positions
            if self.position.is_long:
                # Exit on bearish reversal
                if plus_cross_below or (trend == -1 and overall_strength < 20):
                    self.position.close()
            # Exit short positions
            elif self.position.is_short:
                # Exit on bullish reversal
                if plus_cross_above or (trend == 1 and overall_strength < 20):
                    self.position.close()


