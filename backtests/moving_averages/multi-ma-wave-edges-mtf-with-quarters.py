import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_type = "SMA"
    num_mas = 32
    start_len = 1
    max_len = 1440
    smooth_enable = False
    smooth_len = 5

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        # Build log-spaced lengths
        lengths = self._build_log_spaced_lengths()

        # Calculate MTF envelope
        upper, lower = self._calculate_envelope(close, high, low, volume, lengths)

        # Apply smoothing if enabled
        if self.smooth_enable:
            self.final_upper = self.I(pta.ema, upper, length=self.smooth_len)
            self.final_lower = self.I(pta.ema, lower, length=self.smooth_len)
        else:
            self.final_upper = upper
            self.final_lower = lower

        # Calculate internal levels
        self.range_wave = self.final_upper - self.final_lower
        self.midpoint = self.final_lower + 0.50 * self.range_wave
        self.level_25 = self.final_lower + 0.25 * self.range_wave
        self.level_75 = self.final_lower + 0.75 * self.range_wave

    def _build_log_spaced_lengths(self):
        lengths = []
        log_min = np.log(max(1, self.start_len))
        log_max = np.log(max(self.start_len + 1, self.max_len))

        for i in range(self.num_mas):
            t = i / max(1.0, self.num_mas - 1.0)
            log_l = log_min + t * (log_max - log_min)
            l = int(round(np.exp(log_l)))
            l = max(self.start_len, min(self.max_len, l))
            if l not in lengths:
                lengths.append(l)

        lengths.sort()
        return lengths

    def _calculate_envelope(self, close, high, low, volume, lengths):
        upper_vals = []
        lower_vals = []

        for i in range(len(close)):
            upper = None
            lower = None

            for length in lengths:
                if length >= 1 and i >= length - 1:
                    src = close
                    if self.ma_type == "SMA":
                        ma_val = close.iloc[:i+1].rolling(window=length).mean().iloc[-1]
                    elif self.ma_type == "EMA":
                        ma_val = close.iloc[:i+1].ewm(span=length, adjust=False).mean().iloc[-1]
                    elif self.ma_type == "RMA":
                        ma_val = close.iloc[:i+1].ewm(span=length, adjust=False).mean().iloc[-1]
                    elif self.ma_type == "WMA":
                        ma_val = self._wma(close.iloc[:i+1], length)
                    elif self.ma_type == "VWMA":
                        ma_val = self._vwma(close.iloc[:i+1], volume.iloc[:i+1], length)
                    else:
                        ma_val = close.iloc[:i+1].rolling(window=length).mean().iloc[-1]

                    if not np.isnan(ma_val):
                        upper = ma_val if upper is None else max(upper, ma_val)
                        lower = ma_val if lower is None else min(lower, ma_val)

            upper_vals.append(upper if upper is not None else np.nan)
            lower_vals.append(lower if lower is not None else np.nan)

        return pd.Series(upper_vals, index=close.index), pd.Series(lower_vals, index=close.index)

    def _wma(self, series, length):
        if len(series) < length:
            return np.nan
        weights = np.arange(1, length + 1)
        return np.sum(series.iloc[-length:].values * weights) / np.sum(weights)

    def _vwma(self, close, volume, length):
        if len(close) < length:
            return np.nan
        c = close.iloc[-length:].values
        v = volume.iloc[-length:].values
        return np.sum(c * v) / np.sum(v)

    def next(self):
        if len(self.data) < 2:
            return

        current_close = self.data.Close[-1]
        prev_close = self.data.Close[-2]

        upper = self.final_upper[-1] if not np.isnan(self.final_upper[-1]) else None
        lower = self.final_lower[-1] if not np.isnan(self.final_lower[-1]) else None

        if upper is None or lower is None:
            return

        # Buy signal: Price crosses above lower band
        if prev_close <= lower and current_close > lower:
            if not self.position:
                self.buy()
        # Sell signal: Price crosses above upper band
        elif prev_close <= upper and current_close > upper:
            if self.position:
                self.position.close()
        # Exit on reversal from midpoint
        elif self.position and current_close < self.midpoint[-1]:
            self.position.close()