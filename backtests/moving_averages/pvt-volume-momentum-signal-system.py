import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    pvtSmoothing = 1
    pvtAnchorLookback = 200
    volLength = 14
    volSmoothing = 3
    volEmaLength = 20
    requireBoth = True

    def init(self):
        close = pd.Series(self.data.Close)
        volume = pd.Series(self.data.Volume)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate PVT
        def calc_pvt():
            price_change = np.where(
                (close != 0) & (close.shift(1) != 0),
                (close - close.shift(1)) / close.shift(1),
                0
            )
            raw_pvt = pd.Series(volume.values * price_change).cumsum()
            return raw_pvt
        
        raw_pvt = self.I(calc_pvt)
        
        # Smooth PVT
        def smooth_pvt_func():
            if self.pvtSmoothing > 1:
                return pta.sma(raw_pvt, length=self.pvtSmoothing)
            else:
                return raw_pvt
        
        smoothed_pvt = self.I(smooth_pvt_func)
        
        # Anchor PVT to price level
        def calc_pvt_line():
            pvt_mean = pta.sma(smoothed_pvt, length=self.pvtAnchorLookback)
            pvt_std = pta.stdev(smoothed_pvt, length=self.pvtAnchorLookback)
            price_mean = pta.sma(close, length=self.pvtAnchorLookback)
            atr_val = pta.atr(high, low, close, length=self.pvtAnchorLookback)
            
            pvt_line = price_mean + (smoothed_pvt - pvt_mean) / (pvt_std.replace(0, 1)) * (atr_val * 2)
            return pvt_line
        
        self.pvt_line = self.I(calc_pvt_line)
        
        # PVT EMAs
        def ema10_func():
            return pta.ema(self.pvt_line, length=10)
        
        def ema20_func():
            return pta.ema(self.pvt_line, length=20)
        
        def ema50_func():
            return pta.ema(self.pvt_line, length=50)
        
        self.pvt_ema10 = self.I(ema10_func)
        self.pvt_ema20 = self.I(ema20_func)
        self.pvt_ema50 = self.I(ema50_func)
        
        # Volume Momentum
        def calc_smooth_vol():
            return pta.sma(volume, length=self.volSmoothing)
        
        smooth_vol = self.I(calc_smooth_vol)
        
        def calc_vol_momentum():
            vol_change = np.where(
                smooth_vol.shift(self.volLength) != 0,
                (smooth_vol - smooth_vol.shift(self.volLength)) / smooth_vol.shift(self.volLength) * 100,
                0
            )
            return pd.Series(vol_change)
        
        self.vol_momentum = self.I(calc_vol_momentum)
        
        def vol_mom_ema20_func():
            return pta.ema(self.vol_momentum, length=self.volEmaLength)
        
        self.vol_mom_ema20 = self.I(vol_mom_ema20_func)

    def next(self):
        # Check for crossovers
        pvt_cross_above_ema20 = crossover(self.pvt_line, self.pvt_ema20)
        pvt_cross_below_ema20 = crossover(self.pvt_ema20, self.pvt_line)
        
        vol_cross_above_ema20 = crossover(self.vol_momentum, self.vol_mom_ema20)
        vol_cross_below_ema20 = crossover(self.vol_mom_ema20, self.vol_momentum)
        
        # Determine signals
        if self.requireBoth:
            buy_signal = pvt_cross_above_ema20 and vol_cross_above_ema20
            sell_signal = pvt_cross_below_ema20 and vol_cross_below_ema20
        else:
            buy_signal = pvt_cross_above_ema20
            sell_signal = pvt_cross_below_ema20
        
        # Execute trades
        if buy_signal:
            if not self.position:
                self.buy()
        elif sell_signal:
            if self.position:
                self.position.close()