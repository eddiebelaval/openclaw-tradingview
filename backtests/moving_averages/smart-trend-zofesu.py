import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_length = 30
    multiplier = 1.8
    use_filter = True
    filter_len = 200
    use_vol = True
    vol_pct_target = 80

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # ATR calculation
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_length)
        
        # Volume percentile rank
        self.v_rank = self.I(
            lambda: pta.percentrank(volume, length=200) or pd.Series(50, index=volume.index)
        )
        
        # Main trend filter (HMA)
        self.main_trend_ma = self.I(pta.hma, close, length=self.filter_len)
        
        # Initialize trend state variables
        self.trend_line = None
        self.trend_dir = 1
        self.prev_trend_dir = 1

    def next(self):
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Volume confirmation
        vol_confirmed = not self.use_vol or self.v_rank[-1] > self.vol_pct_target
        
        # Check if we have valid ATR values
        if pd.isna(self.atr[-1]) or pd.isna(self.main_trend_ma[-1]):
            return
        
        # Calculate bands
        upper_band = current_high - (self.atr[-1] * self.multiplier)
        lower_band = current_low + (self.atr[-1] * self.multiplier)
        
        # Initialize trend_line on first valid bar
        if self.trend_line is None:
            self.trend_line = upper_band
        
        # Main trend bias
        main_trend_bull = current_close > self.main_trend_ma[-1]
        main_trend_bear = current_close < self.main_trend_ma[-1]
        
        # Update previous trend direction
        self.prev_trend_dir = self.trend_dir
        
        # Trend engine logic
        if self.trend_dir == 1:
            if current_close < self.trend_line and vol_confirmed:
                self.trend_dir = -1
                self.trend_line = lower_band
            else:
                self.trend_line = max(self.trend_line, upper_band)
        else:
            if current_close > self.trend_line and vol_confirmed:
                self.trend_dir = 1
                self.trend_line = upper_band
            else:
                self.trend_line = min(self.trend_line, lower_band)
        
        # Generate signals
        show_long = (self.trend_dir == 1 and self.prev_trend_dir == -1) and (
            not self.use_filter or main_trend_bull
        )
        show_short = (self.trend_dir == -1 and self.prev_trend_dir == 1) and (
            not self.use_filter or main_trend_bear
        )
        
        # Execute trades
        if show_long:
            if not self.position:
                self.buy()
        elif show_short:
            if self.position:
                self.sell()


