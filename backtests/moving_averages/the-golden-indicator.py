class TvStrategy(Strategy):
    # EMA parameters
    ema_9_length = 9
    ema_21_length = 21
    ema_50_length = 50
    ema_100_length = 100
    ema_200_length = 200
    
    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate EMAs
        self.ema_9 = self.I(pta.ema, close, length=self.ema_9_length)
        self.ema_21 = self.I(pta.ema, close, length=self.ema_21_length)
        self.ema_50 = self.I(pta.ema, close, length=self.ema_50_length)
        self.ema_100 = self.I(pta.ema, close, length=self.ema_100_length)
        self.ema_200 = self.I(pta.ema, close, length=self.ema_200_length)

    def next(self):
        # Simple EMA-based trading logic
        # Buy when 9 EMA crosses above 21 EMA and 21 is above 50
        if crossover(self.ema_9, self.ema_21) and self.ema_21[-1] > self.ema_50[-1]:
            if not self.position:
                self.buy()
        
        # Sell when 9 EMA crosses below 21 EMA
        elif crossover(self.ema_21, self.ema_9):
            if self.position:
                self.position.close()


