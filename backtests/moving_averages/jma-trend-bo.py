import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ma_length = 9
    ma_phase = 0.15
    pivot_len = 4
    atr_len = 200

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate Jurik MA
        self.jma = self.I(self._calculate_jma, close)
        
        # Calculate ATR for breakout confirmation
        atr_result = pta.atr(high, low, close, length=self.atr_len)
        self.atr = self.I(lambda: atr_result if atr_result is not None else pd.Series(0, index=close.index))
        
        # Calculate pivot points
        self.pivot_high = self.I(self._calculate_pivot_high, high)
        self.pivot_low = self.I(self._calculate_pivot_low, low)
        
        # Track state for breakout detection
        self.upper_level = None
        self.lower_level = None
        self.last_break_up_idx = -1000
        self.last_break_dn_idx = -1000
        self.trend_state = None
        
    def _calculate_jma(self, close):
        length = self.ma_length
        phase = self.ma_phase
        beta = 0.45 * (length - 1) / (0.45 * (length - 1) + 2)
        alpha = np.power(beta, phase)
        
        jma_values = np.full(len(close), np.nan)
        jma_values[0] = close.iloc[0]
        
        for i in range(1, len(close)):
            jma_values[i] = (1 - alpha) * close.iloc[i] + alpha * jma_values[i - 1]
        
        return pd.Series(jma_values, index=close.index)
    
    def _calculate_pivot_high(self, high):
        pivot_high = np.full(len(high), np.nan)
        
        for i in range(self.pivot_len, len(high) - self.pivot_len):
            is_pivot = True
            pivot_val = high.iloc[i]
            
            for j in range(1, self.pivot_len + 1):
                if high.iloc[i - j] >= pivot_val or high.iloc[i + j] >= pivot_val:
                    is_pivot = False
                    break
            
            if is_pivot:
                pivot_high[i] = pivot_val
        
        return pd.Series(pivot_high, index=high.index)
    
    def _calculate_pivot_low(self, low):
        pivot_low = np.full(len(low), np.nan)
        
        for i in range(self.pivot_len, len(low) - self.pivot_len):
            is_pivot = True
            pivot_val = low.iloc[i]
            
            for j in range(1, self.pivot_len + 1):
                if low.iloc[i - j] <= pivot_val or low.iloc[i + j] <= pivot_val:
                    is_pivot = False
                    break
            
            if is_pivot:
                pivot_low[i] = pivot_val
        
        return pd.Series(pivot_low, index=low.index)

    def next(self):
        if len(self.data) < self.pivot_len + 4:
            return
        
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        current_idx = len(self.data) - 1
        
        # Determine trend: JMA >= JMA[3 bars ago]
        jma_current = self.jma[-1]
        jma_prev = self.jma[-4] if len(self.jma) >= 4 else jma_current
        trend = jma_current >= jma_prev
        
        # Trend change detection
        trend_changed = False
        if self.trend_state is not None and self.trend_state != trend:
            trend_changed = True
            self.upper_level = None
            self.lower_level = None
        
        self.trend_state = trend
        
        # Uptrend logic
        if trend:
            current_pivot_high = self.pivot_high[-1]
            
            if not np.isnan(current_pivot_high):
                if self.upper_level is None:
                    self.upper_level = current_pivot_high
            
            # Check for break above upper level
            if self.upper_level is not None and current_close > self.upper_level:
                if current_idx - self.last_break_up_idx > 5:
                    if not self.position:
                        self.buy()
                    self.last_break_up_idx = current_idx
                    self.upper_level = None
        
        # Downtrend logic
        if not trend:
            current_pivot_low = self.pivot_low[-1]
            
            if not np.isnan(current_pivot_low):
                if self.lower_level is None:
                    self.lower_level = current_pivot_low
            
            # Check for break below lower level
            if self.lower_level is not None and current_close < self.lower_level:
                if current_idx - self.last_break_dn_idx > 5:
                    if self.position:
                        self.sell()
                    self.last_break_dn_idx = current_idx
                    self.lower_level = None
        
        # Exit logic based on trend reversal
        if trend_changed:
            if not trend and self.position:
                self.sell()
            elif trend and self.position:
                self.sell()


