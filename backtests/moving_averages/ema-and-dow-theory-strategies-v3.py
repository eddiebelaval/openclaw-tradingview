import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaLen = 50
    atrFactor = 4.0
    stopLoss = -6.0
    adxThreshold = 18.0
    swingLen = 4

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # EMA
        self.ema = self.I(pta.ema, close, length=self.emaLen)
        
        # EMA slope
        self.ema_up = self.I(lambda: pd.Series(
            [1 if i > 0 and self.ema[i] > self.ema[i-1] else 0 for i in range(len(self.ema))],
            index=close.index
        ))
        
        # ADX
        adx_result = self.I(lambda: pta.adx(high, low, close, length=14))
        self.adx = self.I(lambda: adx_result['ADX_14'] if adx_result is not None else pd.Series(0, index=close.index))
        
        # Swing High/Low detection
        def highest_func(idx):
            if idx < self.swingLen * 2:
                return np.nan
            return high.iloc[max(0, idx - self.swingLen * 2):idx+1].max()
        
        def lowest_func(idx):
            if idx < self.swingLen * 2:
                return np.nan
            return low.iloc[max(0, idx - self.swingLen * 2):idx+1].min()
        
        self.highest = self.I(lambda: pd.Series(
            [highest_func(i) for i in range(len(high))],
            index=high.index
        ))
        
        self.lowest = self.I(lambda: pd.Series(
            [lowest_func(i) for i in range(len(low))],
            index=low.index
        ))
        
        # ATR
        self.atr = self.I(pta.atr, high, low, close, length=50)
        
        # State variables
        self.last_swing_high = np.nan
        self.last_swing_low = np.nan
        self.trend = 0
        self.tp1 = np.nan
        self.tp2 = np.nan
        self.tp3 = np.nan
        self.tp11 = np.nan
        self.tp22 = np.nan
        self.tp33 = np.nan
        self.entry_price = np.nan
        self.equity_at_start = np.nan

    def next(self):
        idx = len(self.data) - 1
        close_price = self.data.Close[-1]
        high_price = self.data.High[-1]
        low_price = self.data.Low[-1]
        
        # Update swing highs/lows
        if idx >= self.swingLen:
            if high_price == self.highest[-1]:
                self.last_swing_high = high_price
            if low_price == self.lowest[-1]:
                self.last_swing_low = low_price
        
        # Determine trend based on Dow Theory
        if not np.isnan(self.last_swing_high) and close_price > self.last_swing_high and self.trend != 1:
            self.trend = 1
        if not np.isnan(self.last_swing_low) and close_price < self.last_swing_low and self.trend != -1:
            self.trend = -1
        
        # EMA slope conditions
        ema_up = self.ema[-1] > self.ema[-2] if len(self.ema) > 1 else False
        ema_down = self.ema[-1] < self.ema[-2] if len(self.ema) > 1 else False
        
        # ADX trending condition
        is_trending = self.adx[-1] > self.adxThreshold
        
        # Entry conditions
        go_long = ema_up and self.trend == 1 and is_trending
        go_short = ema_down and self.trend == -1 and is_trending
        
        # Calculate PnL
        if self.position:
            entry_price = self.position.open_price
            if self.position.size > 0:
                pnl = ((close_price - entry_price) / entry_price) * 100.0
            else:
                pnl = ((entry_price - close_price) / entry_price) * 100.0
        else:
            pnl = 0.0
        
        # Stop loss
        if pnl < self.stopLoss and self.position.size > 0:
            self.position.close()
        elif pnl < self.stopLoss and self.position.size < 0:
            self.position.close()
        
        # Trend reversal close
        if self.trend == 1 and self.position.size < 0:
            self.position.close()
        elif self.trend == -1 and self.position.size > 0:
            self.position.close()
        
        # Take profit for long
        if self.position.size > 0:
            atr_val = self.atr[-1] * self.atrFactor if not np.isnan(self.atr[-1]) else 0
            
            if np.isnan(self.tp1):
                self.tp1 = self.entry_price + atr_val
                self.tp2 = self.entry_price + atr_val * 2
                self.tp3 = self.entry_price + atr_val * 3
            
            if high_price > self.tp1 and not np.isnan(self.tp1):
                self.position.reduce(fraction=0.3)
                self.tp1 = np.nan
            if high_price > self.tp2 and not np.isnan(self.tp2):
                self.position.reduce(fraction=0.3)
                self.tp2 = np.nan
            if high_price > self.tp3 and not np.isnan(self.tp3):
                self.position.reduce(fraction=0.3)
                self.tp3 = np.nan
        
        # Take profit for short
        if self.position.size < 0:
            atr_val = self.atr[-1] * self.atrFactor if not np.isnan(self.atr[-1]) else 0
            
            if np.isnan(self.tp11):
                self.tp11 = self.entry_price - atr_val
                self.tp22 = self.entry_price - atr_val * 2
                self.tp33 = self.entry_price - atr_val * 3
            
            if low_price < self.tp11 and not np.isnan(self.tp11):
                self.position.reduce(fraction=0.3)
                self.tp11 = np.nan
            if low_price < self.tp22 and not np.isnan(self.tp22):
                self.position.reduce(fraction=0.3)
                self.tp22 = np.nan
            if low_price < self.tp33 and not np.isnan(self.tp33):
                self.position.reduce(fraction=0.3)
                self.tp33 = np.nan
        
        # Long entry
        if self.position.size <= 0 and go_long:
            if self.position.size < 0:
                self.position.close()
            if self.position.size == 0:
                self.equity_at_start = self.equity
                self.buy()
                self.entry_price = close_price
                self.tp1 = np.nan
                self.tp2 = np.nan
                self.tp3 = np.nan
        
        # Short entry
        if self.position.size >= 0 and go_short:
            if self.position.size > 0:
                self.position.close()
            if self.position.size == 0:
                self.equity_at_start = self.equity
                self.sell()
                self.entry_price = close_price
                self.tp11 = np.nan
                self.tp22 = np.nan
                self.tp33 = np.nan