import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    fastLen = 200
    fastLen1 = 200
    maType = "EMA"
    cci_length = 20

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate MA/EMA based on maType
        if self.maType == "EMA":
            self.fastEMA = self.I(pta.ema, high, length=self.fastLen)
            self.fastEMA1 = self.I(pta.ema, low, length=self.fastLen1)
        else:
            self.fastEMA = self.I(pta.sma, high, length=self.fastLen)
            self.fastEMA1 = self.I(pta.sma, low, length=self.fastLen1)
        
        # CCI calculation
        hlc3 = (high + low + close) / 3
        cci_ma = self.I(pta.sma, hlc3, length=self.cci_length)
        cci_dev = self.I(lambda x: x.rolling(self.cci_length).std(), hlc3)
        self.cci = self.I(lambda: (hlc3 - cci_ma) / (0.015 * cci_dev) if cci_dev is not None else pd.Series(0, index=close.index))
        
        self.prev_crossover_high = False
        self.prev_crossover_low = False
        self.cci_band1up_prev = False

    def next(self):
        if len(self.data) < self.fastLen + 1:
            return
        
        # Get previous day data (simplified - using bar offset)
        bar_offset = min(len(self.data) - 1, 1)
        
        # Current values
        current_close = self.data.Close[-1]
        current_high = self.data.High[-1]
        current_low = self.data.Low[-1]
        
        # Previous day levels (approximation using current bar)
        pdh = self.data.High[-bar_offset] if len(self.data) > bar_offset else self.data.High[-1]
        pdl = self.data.Low[-bar_offset] if len(self.data) > bar_offset else self.data.Low[-1]
        
        # Bull and bear zones
        bullzone = current_high > self.fastEMA[-1] and current_high > self.fastEMA1[-1]
        bearzone = current_low < self.fastEMA1[-1] and current_low < self.fastEMA[-1]
        
        # CCI crossovers
        cci_band1up = crossover(self.cci, 100)
        cci_band0up = crossover(self.cci, -100)
        
        # Previous day breakouts
        prev_high_bo = crossover(self.data.Close, pdh)
        prev_low_bo = crossover(self.data.Close, pdl)
        
        # Entry signals
        if cci_band1up and bullzone:
            if not self.position:
                self.buy()
        elif cci_band0up and bearzone:
            if not self.position:
                self.buy()
        elif prev_high_bo and bullzone:
            if not self.position:
                self.buy()
        elif prev_low_bo and bullzone:
            if not self.position:
                self.buy()
        
        # Exit signals
        if self.position:
            if self.cci[-1] < -100:
                self.position.close()
            elif bearzone and current_close < self.fastEMA1[-1]:
                self.position.close()