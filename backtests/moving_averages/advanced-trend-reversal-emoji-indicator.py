import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # Parameters from Pine Script
    fastLength = 21
    slowLength = 55
    trendLength = 200
    rsiLength = 14
    rsiBullLevel = 55
    rsiBearLevel = 45
    atrLength = 14
    atrMultiplier = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate EMAs
        self.fastEMA = self.I(pta.ema, close, length=self.fastLength)
        self.slowEMA = self.I(pta.ema, close, length=self.slowLength)
        self.trendEMA = self.I(pta.ema, close, length=self.trendLength)
        
        # Calculate RSI
        self.rsiValue = self.I(pta.rsi, close, length=self.rsiLength)
        
        # Calculate ATR
        self.atrValue = self.I(pta.atr, high, low, close, length=self.atrLength)
        
        # Calculate True Range
        self.tr = self.I(lambda: pta.true_range(high, low, close))

    def next(self):
        # Check if we have enough data
        if len(self.data) < self.trendLength:
            return
        
        # Get current values
        fastEMA_current = self.fastEMA[-1]
        slowEMA_current = self.slowEMA[-1]
        trendEMA_current = self.trendEMA[-1]
        rsi_current = self.rsiValue[-1]
        atr_current = self.atrValue[-1]
        tr_current = self.tr[-1]
        close_current = self.data.Close[-1]
        
        # Handle None values
        if (fastEMA_current is None or slowEMA_current is None or 
            trendEMA_current is None or rsi_current is None or 
            atr_current is None or tr_current is None):
            return
        
        # Volatility condition
        volatilityCondition = tr_current > atr_current * self.atrMultiplier
        
        # Bullish conditions
        bullishCross = crossover(self.fastEMA, self.slowEMA)
        bullishTrend = (close_current > trendEMA_current and 
                       rsi_current > self.rsiBullLevel and 
                       volatilityCondition)
        bullishSignal = bullishCross and bullishTrend
        
        # Bearish conditions
        bearishCross = crossover(self.slowEMA, self.fastEMA)
        bearishTrend = (close_current < trendEMA_current and 
                       rsi_current < self.rsiBearLevel and 
                       volatilityCondition)
        bearishSignal = bearishCross and bearishTrend
        
        # Execute trades
        if bullishSignal:
            if not self.position:
                self.buy()
        elif bearishSignal:
            if self.position:
                self.position.close()


