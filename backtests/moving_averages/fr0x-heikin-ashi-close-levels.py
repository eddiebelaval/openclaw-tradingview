import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    ema_period = 7

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema7 = self.I(pta.ema, close, length=self.ema_period)
        
        self.bull_levels = []
        self.bull_bars = []
        self.bear_levels = []
        self.bear_bars = []
        
        self.current_max = None
        self.current_max_bar = None
        self.current_min = None
        self.current_min_bar = None
        
        self.last_alert_bull = False
        self.last_alert_bear = False

    def next(self):
        close = self.data.Close[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        bar_idx = len(self.data) - 1
        
        ema_val = self.ema7[-1]
        
        cross_under = False
        cross_over = False
        
        if len(self.ema7) >= 2:
            if self.data.Close[-2] >= self.ema7[-2] and close < ema_val:
                cross_under = True
            if self.data.Close[-2] <= self.ema7[-2] and close > ema_val:
                cross_over = True
        
        if close > ema_val:
            if self.current_max is None or close > self.current_max:
                self.current_max = close
                self.current_max_bar = bar_idx
        elif close < ema_val:
            if self.current_min is None or close < self.current_min:
                self.current_min = close
                self.current_min_bar = bar_idx
        
        if cross_under and self.current_max is not None:
            self.bull_levels.append(self.current_max)
            self.bull_bars.append(self.current_max_bar)
            self.current_max = None
            self.current_max_bar = None
        
        if cross_over and self.current_min is not None:
            self.bear_levels.append(self.current_min)
            self.bear_bars.append(self.current_min_bar)
            self.current_min = None
            self.current_min_bar = None
        
        alert_bull = False
        alert_bear = False
        
        if len(self.bull_levels) > 0:
            indices_to_remove = []
            for i in range(len(self.bull_levels) - 1, -1, -1):
                if bar_idx > self.bull_bars[i] and high >= self.bull_levels[i]:
                    alert_bull = True
                    indices_to_remove.append(i)
            
            for i in sorted(indices_to_remove, reverse=True):
                self.bull_levels.pop(i)
                self.bull_bars.pop(i)
        
        if len(self.bear_levels) > 0:
            indices_to_remove = []
            for i in range(len(self.bear_levels) - 1, -1, -1):
                if bar_idx > self.bear_bars[i] and low <= self.bear_levels[i]:
                    alert_bear = True
                    indices_to_remove.append(i)
            
            for i in sorted(indices_to_remove, reverse=True):
                self.bear_levels.pop(i)
                self.bear_bars.pop(i)
        
        if alert_bull and not self.last_alert_bull:
            self.buy()
            self.last_alert_bull = True
        
        if alert_bear and not self.last_alert_bear:
            self.sell()
            self.last_alert_bear = True
        
        if not alert_bull:
            self.last_alert_bull = False
        if not alert_bear:
            self.last_alert_bear = False


