import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    length = 1.0

    def init(self):
        close = pd.Series(self.data.Close)
        self.ema = self.I(self._pine_ema, close, self.length)

    def _pine_ema(self, src, length):
        alpha = 2 / (length + 1)
        result = pd.Series(index=src.index, dtype='float64')
        
        for i in range(len(src)):
            if i == 0:
                result.iloc[i] = src.iloc[i]
            else:
                prev_val = result.iloc[i - 1]
                result.iloc[i] = alpha * src.iloc[i] + (1 - alpha) * prev_val
        
        return result

    def next(self):
        if len(self.data) < 2:
            return
        
        if self.ema[-2] < self.data.Close[-2] and self.ema[-1] > self.data.Close[-1]:
            if not self.position:
                self.buy()
        elif self.ema[-2] > self.data.Close[-2] and self.ema[-1] < self.data.Close[-1]:
            if self.position:
                self.position.close()