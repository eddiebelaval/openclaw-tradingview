import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    atr_period = 10
    factor = 3.0
    use_smooth = True
    smooth_len = 10
    ma_type = "HMA"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # Calculate ATR
        atr = self.I(pta.atr, high, low, close, length=self.atr_period)
        
        # Apply smoothing to source price
        if self.use_smooth:
            if self.ma_type == "SMA":
                smoothed_src = self.I(pta.sma, close, length=self.smooth_len)
            elif self.ma_type == "EMA":
                smoothed_src = self.I(pta.ema, close, length=self.smooth_len)
            elif self.ma_type == "HMA":
                smoothed_src = self.I(pta.hma, close, length=self.smooth_len)
            elif self.ma_type == "RMA":
                smoothed_src = self.I(pta.rma, close, length=self.smooth_len)
            elif self.ma_type == "WMA":
                smoothed_src = self.I(pta.wma, close, length=self.smooth_len)
            else:
                smoothed_src = close
        else:
            smoothed_src = close
        
        # SuperTrend calculation
        def calc_supertrend():
            result_upband = smoothed_src - (self.factor * atr)
            result_dnband = smoothed_src + (self.factor * atr)
            return result_upband, result_dnband
        
        self.upband, self.dnband = calc_supertrend()
        self.smoothed_src = smoothed_src
        
        # Track direction
        self.direction = 1
        self.trail_stop = None

    def next(self):
        if len(self.data) < self.atr_period + self.smooth_len:
            return
        
        upband_val = self.upband[-1]
        dnband_val = self.dnband[-1]
        close_val = self.data.Close[-1]
        
        if self.trail_stop is None:
            self.trail_stop = upband_val if self.direction == 1 else dnband_val
        
        prev_direction = self.direction
        
        if self.direction == 1:
            self.trail_stop = max(upband_val, self.trail_stop)
            if close_val < self.trail_stop:
                self.direction = -1
                self.trail_stop = dnband_val
        else:
            self.trail_stop = min(dnband_val, self.trail_stop)
            if close_val > self.trail_stop:
                self.direction = 1
                self.trail_stop = upband_val
        
        # Trading logic: Buy on trend change from -1 to 1, Sell on trend change from 1 to -1
        if prev_direction == -1 and self.direction == 1:
            if not self.position:
                self.buy()
        elif prev_direction == 1 and self.direction == -1:
            if self.position:
                self.sell()