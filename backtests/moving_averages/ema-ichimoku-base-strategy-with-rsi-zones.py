import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsiLen = 7
    rsiWmaLen = 5
    emaLen = 4
    smaLen = 6
    kijunLen = 10
    upperBand = 60.0
    middleBand = 40.0
    lowerBand = 32.0
    tpPercent = 0.30

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # RSI and RSI WMA
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)
        self.rsi_wma = self.I(pta.wma, self.rsi, length=self.rsiWmaLen)

        # EMA and SMA
        self.ema = self.I(pta.ema, close, length=self.emaLen)
        self.sma = self.I(pta.sma, close, length=self.smaLen)

        # Ichimoku Base Line (Kijun-sen)
        def calc_kijun():
            highest = high.rolling(window=self.kijunLen).max()
            lowest = low.rolling(window=self.kijunLen).min()
            return (highest + lowest) / 2

        self.kijun = self.I(calc_kijun)

        # Signal level tracker
        self.signal_level = np.nan

    def next(self):
        close_val = self.data.Close[-1]
        ema_val = self.ema[-1]
        sma_val = self.sma[-1]
        rsi_val = self.rsi[-1]
        kijun_val = self.kijun[-1]

        # Check if we have valid data
        if np.isnan(ema_val) or np.isnan(sma_val) or np.isnan(rsi_val) or np.isnan(kijun_val):
            return

        # RSI zone cross signals
        oversold_cross = (
            crossover(self.sma, self.rsi) and
            rsi_val <= self.lowerBand
        )
        overbought_cross = (
            len(self.sma) > 1 and
            self.sma[-2] < self.rsi[-2] and
            sma_val > rsi_val and
            rsi_val >= self.upperBand
        )

        if oversold_cross or overbought_cross:
            self.signal_level = close_val

        # Entry conditions
        long_entry = crossover(self.data.Close, self.ema)
        short_entry = (
            len(self.data.Close) > 1 and
            self.data.Close[-2] > self.ema[-2] and
            close_val <= ema_val
        )

        # Execute entries
        if long_entry:
            self.buy()

        if short_entry:
            self.sell()

        # Stop and target levels
        long_stop = kijun_val
        short_stop = kijun_val

        if self.position:
            if self.position.is_long:
                long_tp = self.position.open_price * (1 + self.tpPercent)
                # Exit on take profit
                if close_val >= long_tp:
                    self.position.close()
                # Exit on stop loss
                elif close_val <= long_stop:
                    self.position.close()
                # Exit on EMA crossunder
                elif (
                    len(self.data.Close) > 1 and
                    self.data.Close[-2] > self.ema[-2] and
                    close_val <= ema_val
                ):
                    self.position.close()

            elif self.position.is_short:
                short_tp = self.position.open_price * (1 - self.tpPercent)
                # Exit on take profit
                if close_val <= short_tp:
                    self.position.close()
                # Exit on stop loss
                elif close_val >= short_stop:
                    self.position.close()
                # Exit on EMA crossover
                elif crossover(self.data.Close, self.ema):
                    self.position.close()