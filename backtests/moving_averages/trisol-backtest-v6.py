class TvStrategy(Strategy):
    hmaLen1 = 30
    hmaLen2 = 44
    macdFast = 21
    macdSlow = 3
    macdSig = 9
    rsiLen = 9
    rsiMaLen = 3
    rsiWmaLen = 21
    swingLeft = 2
    swingRight = 2
    targetLookback = 26
    partialPct = 20.0
    partialDailyUp = 3.0
