        rsi_cross2 = crossover(self.rsi_ma3, self.rsi_wma21)
        rsi_confirm = rsi_cross1 and rsi_cross2
        
        entry_signal = price_between and macd_below_zero and rsi_confirm
        
        # Stop loss and target
        stop_price = self.last_swing_low
        
        # Target: highest high of last N bars (excluding current)
        target_price = None
