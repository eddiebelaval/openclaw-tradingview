import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    # First Bollinger Band Settings
    length1 = 20
    stddev1 = 0.5
    
    # Second Bollinger Band Settings
    length2 = 20
    stddev2 = 3.0

    def init(self):
        close = pd.Series(self.data.Close)
        
        # First Bollinger Band
        self.basis1 = self.I(pta.sma, close, length=self.length1)
        self.dev1 = self.I(lambda: self.stddev1 * close.rolling(self.length1).std())
        self.upper1 = self.I(lambda: self.basis1 + self.dev1)
        self.lower1 = self.I(lambda: self.basis1 - self.dev1)
        
        # Second Bollinger Band
        self.basis2 = self.I(pta.sma, close, length=self.length2)
        self.dev2 = self.I(lambda: self.stddev2 * close.rolling(self.length2).std())
        self.upper2 = self.I(lambda: self.basis2 + self.dev2)
        self.lower2 = self.I(lambda: self.basis2 - self.dev2)

    def next(self):
        # Buy when price touches lower band 1 and is above lower band 2
        if len(self.data.Close) < max(self.length1, self.length2) + 1:
            return
        
        current_price = self.data.Close[-1]
        
        # Buy signal: price touches or crosses below lower1, with confirmation from lower2
        if not self.position:
            if current_price <= self.lower1[-1] and current_price >= self.lower2[-1]:
                self.buy()
        else:
            # Sell signal: price reaches upper2 or crosses above it
            if current_price >= self.upper2[-1]:
                self.position.close()
            # Alternative exit: price crosses above upper1
            elif current_price >= self.upper1[-1]:
                self.position.close()


