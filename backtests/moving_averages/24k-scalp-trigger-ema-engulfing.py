class TvStrategy(Strategy):
    emaLength = 21
    ema9Length = 9

    def init(self):
        close = pd.Series(self.data.Close)
        open_ = pd.Series(self.data.Open)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.ema21 = self.I(pta.ema, close, length=self.emaLength)
        self.ema9 = self.I(pta.ema, close, length=self.ema9Length)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Current candle values
        close_curr = self.data.Close[-1]
        open_curr = self.data.Open[-1]
        high_curr = self.data.High[-1]
        low_curr = self.data.Low[-1]
        
        # Previous candle values
        close_prev = self.data.Close[-2]
        open_prev = self.data.Open[-2]
        
        # EMA values
        ema21_curr = self.ema21[-1]
        
        # Engulfing Logic
        isBullishEngulfing = (close_curr > open_prev and 
                              open_curr < close_prev and 
                              close_curr > open_curr)
        
        isBearishEngulfing = (close_curr < open_prev and 
                              open_curr > close_prev and 
                              close_curr < open_curr)
        
        # EMA Touch Logic
        nearEMA = (low_curr <= ema21_curr and high_curr >= ema21_curr)
        
        # Entry Signals
        longSignal = isBullishEngulfing and nearEMA and close_curr > ema21_curr
        shortSignal = isBearishEngulfing and nearEMA and close_curr < ema21_curr
        
        # Trading logic
        if longSignal:
            if self.position:
                self.position.close()
            self.buy()
        elif shortSignal:
            if self.position:
                self.position.close()
            self.sell()