import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 9
    maLengthInput = 14
    bbMultInput = 2.0
    maTypeInput = "SMA + Bollinger Bands"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)

        self.wma = self.I(pta.wma, close, length=self.len)

        if self.maTypeInput == "None":
            self.smoothingMA = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
            self.smoothingStDev = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
            self.bbUpperBand = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
            self.bbLowerBand = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
        elif self.maTypeInput == "SMA":
            self.smoothingMA = self.I(pta.sma, self.wma, length=self.maLengthInput)
            self.smoothingStDev = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
            self.bbUpperBand = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
            self.bbLowerBand = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
        elif self.maTypeInput == "SMA + Bollinger Bands":
            self.smoothingMA = self.I(pta.sma, self.wma, length=self.maLengthInput)
            self.smoothingStDev = self.I(
                lambda x: (x.rolling(self.maLengthInput).std() * self.bbMultInput),
                self.wma
            )
            self.bbUpperBand = self.I(
                lambda x, y: x + y,
                self.smoothingMA,
                self.smoothingStDev
            )
            self.bbLowerBand = self.I(
                lambda x, y: x - y,
                self.smoothingMA,
                self.smoothingStDev
            )
        elif self.maTypeInput == "EMA":
            self.smoothingMA = self.I(pta.ema, self.wma, length=self.maLengthInput)
            self.smoothingStDev = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
            self.bbUpperBand = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
            self.bbLowerBand = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
        elif self.maTypeInput == "SMMA (RMA)":
            self.smoothingMA = self.I(pta.rma, self.wma, length=self.maLengthInput)
            self.smoothingStDev = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
            self.bbUpperBand = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
            self.bbLowerBand = self.I(lambda x: pd.Series(np.nan, index=x.index), close)
        elif self.maTypeInput == "WMA":
            self.smoothingMA = self.I(pta.wma, self.wma, length=self.maLengthInput)
