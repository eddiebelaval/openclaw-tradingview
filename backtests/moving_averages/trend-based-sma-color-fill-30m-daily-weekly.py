import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        # SMA 65 for 30m timeframe logic
        self.sma65 = self.I(pta.sma, close, length=65)
        
        # Daily SMAs (we'll calculate them on the same data)
        self.sma18d = self.I(pta.sma, close, length=18)
        self.sma8d = self.I(pta.sma, close, length=8)
        
        # Weekly SMA (we'll calculate it on the same data)
        self.sma10w = self.I(pta.sma, close, length=10)

    def next(self):
        if len(self.data) < 2:
            return
        
        # Get current and previous values
        current_close = self.data.Close[-1]
        prev_close = self.data.Close[-2]
        current_high = self.data.High[-1]
        prev_high = self.data.High[-2]
        current_low = self.data.Low[-1]
        prev_low = self.data.Low[-2]
        
        # SMA 65 values
        current_sma65 = self.sma65[-1]
        prev_sma65 = self.sma65[-2] if len(self.sma65) > 1 else current_sma65
        
        # Determine trend direction
        is_sma_rising = current_sma65 > prev_sma65
        is_sma_falling = current_sma65 < prev_sma65
        
        # Signal conditions
        is_green = (prev_close > prev_sma65 and 
                   current_close > prev_high and 
                   is_sma_rising)
        is_red = (prev_close < prev_sma65 and 
                 current_close < prev_low and 
                 is_sma_falling)
        is_yellow = ((current_close < current_sma65 and prev_close > prev_sma65) or
                    (current_close > current_sma65 and prev_close < prev_sma65))
        
        # Daily SMA logic
        current_sma18d = self.sma18d[-1] if len(self.sma18d) > 0 else None
        current_sma8d = self.sma8d[-1] if len(self.sma8d) > 0 else None
        
        # Weekly SMA logic
        current_sma10w = self.sma10w[-1] if len(self.sma10w) > 0 else None
        
        # Trading logic based on signals
        # Buy on green signal (strong uptrend)
        if is_green:
            if not self.position:
                self.buy()
        # Sell on red signal (strong downtrend)
        elif is_red:
            if self.position:
                self.sell()
        # Yellow is a crossover signal - can be used for position management
        elif is_yellow:
            if self.position:
                self.sell()
        
        # Additional logic: use Daily SMAs for trend confirmation
        if current_sma18d is not None and current_sma8d is not None:
            # If 8D SMA crosses above 18D SMA, it's bullish
            if crossover(self.sma8d, self.sma18d):
                if not self.position:
                    self.buy()
            # If 8D SMA crosses below 18D SMA, it's bearish
            elif crossover(self.sma18d, self.sma8d):
                if self.position:
                    self.sell()


