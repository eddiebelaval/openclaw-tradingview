import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    Length = 50
    
    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        volume = pd.Series(self.data.Volume)
        
        # Calculate all MA types
        self.sma_val = self.I(pta.sma, close, length=self.Length)
        self.ema_val = self.I(pta.ema, close, length=self.Length)
        
        # VWMA calculation
        def calc_vwma():
            result = pta.vwma(close, volume, length=self.Length)
            return result if result is not None else pd.Series(close.iloc[-1], index=close.index)
        self.vwma_val = self.I(calc_vwma)
        
        # HMA calculation
        def calc_hma():
            result = pta.hma(close, length=self.Length)
            return result if result is not None else pd.Series(close.iloc[-1], index=close.index)
        self.hma_val = self.I(calc_hma)
        
        # DEMA calculation (2 * EMA - EMA(EMA))
        def calc_dema():
            ema1 = pta.ema(close, length=self.Length)
            if ema1 is None:
                return pd.Series(close.iloc[-1], index=close.index)
            ema2 = pta.ema(ema1, length=self.Length)
            if ema2 is None:
                return pd.Series(close.iloc[-1], index=close.index)
            dema = 2 * ema1 - ema2
            return dema
        self.dema_val = self.I(calc_dema)
        
        # Store MA types and selector logic
        self.ma_names = ['SMA', 'EMA', 'VWMA', 'HMA', 'DEMA']
        self.ma_values = [self.sma_val, self.ema_val, self.vwma_val, self.hma_val, self.dema_val]
        
        # Default to SMA for trading
        self.zone = 0
        self.ma_type = 'SMA'
    
    def next(self):
        # Use current MA (SMA by default)
        current_ma = self.ma_values[self.zone][-1]
        current_price = self.data.Close[-1]
        
        # Simple trading logic: buy when price crosses above MA, sell when crosses below
        if len(self.data) > 1:
            prev_ma = self.ma_values[self.zone][-2]
            prev_price = self.data.Close[-2]
            
            # Buy signal: price crosses above MA
            if prev_price <= prev_ma and current_price > current_ma:
                if not self.position:
                    self.buy()
            
            # Sell signal: price crosses below MA
            elif prev_price >= prev_ma and current_price < current_ma:
                if self.position:
                    self.position.close()


