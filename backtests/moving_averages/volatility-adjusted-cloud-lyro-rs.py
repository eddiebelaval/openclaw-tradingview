import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len_V_bb = 25
    len_VHist_bb = 35
    vidya_multp = 1.5
    vidya_multn = 0.7
    alma_length = 20
    alma_offset = 0
    alma_sigma = 20

    def init(self):
        close = pd.Series(self.data.Close)
        
        # VIDYA calculation
        def vidya_calc(src, length, hist_length):
            sc = 2.0 / (length + 1)
            sd_v = pta.stdev(src, length=length) / pta.stdev(src, length=hist_length)
            if sd_v is None or pta.stdev(src, length=hist_length) is None:
                return pd.Series(0, index=src.index)
            sd_v = sd_v.fillna(0)
            v = pd.Series(0.0, index=src.index)
            for i in range(len(src)):
                if i == 0:
                    v.iloc[i] = sd_v.iloc[i] * sc * src.iloc[i]
                else:
                    v.iloc[i] = sd_v.iloc[i] * sc * src.iloc[i] + (1 - sd_v.iloc[i] * sc) * v.iloc[i-1]
            return v
        
        # VIDYA baseline
        self.avg_bb = self.I(vidya_calc, close, self.len_V_bb, self.len_VHist_bb)
        
        # VIDYA-smoothed deviation
        abs_dev = self.I(lambda: (close - self.avg_bb).abs())
        self.vidya_dev_bb = self.I(vidya_calc, abs_dev, self.len_V_bb, self.len_VHist_bb)
        
        # Bands
        self.bb_positive_band = self.I(lambda: self.avg_bb + (self.vidya_dev_bb * self.vidya_multp))
        self.bb_negative_band = self.I(lambda: self.avg_bb - (self.vidya_dev_bb * self.vidya_multn))
        
        # ALMA for smoothing the midline
        def alma_calc(src, length, offset, sigma):
            result = pta.alma(src, length=length, a=offset, m=sigma)
            if result is None:
                return src
            return result
        
        self.alma_line = self.I(alma_calc, self.avg_bb, self.alma_length, self.alma_offset, self.alma_sigma)
        
        # Score tracking for signal detection
        self.score = self.I(lambda: pd.Series(0, index=close.index))

    def next(self):
        close_val = self.data.Close[-1]
        bb_pos_val = self.bb_positive_band[-1]
        bb_neg_val = self.bb_negative_band[-1]
        
        # Detect crossovers
        if len(self.data.Close) > 1:
            close_prev = self.data.Close[-2]
            bb_pos_prev = self.bb_positive_band[-2]
            bb_neg_prev = self.bb_negative_band[-2]
            
            # Crossover: close crosses above positive band
            if close_prev <= bb_pos_prev and close_val > bb_pos_val:
                if not self.position:
                    self.buy()
            
            # Crossunder: close crosses below negative band
            if close_prev >= bb_neg_prev and close_val < bb_neg_val:
                if self.position:
                    self.position.close()