import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover
from datetime import datetime


class TvStrategy(Strategy):
    ms_lookback = 20
    impulse_mult = 2.0
    zone_lookback = 20
    use_engulf = True
    use_wick = True
    wick_ratio = 2.0
    use_bos = True
    atr_len = 14
    sl_atr_mult = 1.0
    tp1_rr = 2.0
    tp2_rr = 3.0
    use_session = True

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        open_ = pd.Series(self.data.Open)
        
        self.atr = self.I(pta.atr, high, low, close, length=self.atr_len)
        self.avg_body = self.I(pta.sma, pd.Series(np.abs(close - open_)), length=self.zone_lookback)
        
        self.highest_5 = self.I(lambda: high.rolling(5).max())
        self.lowest_5 = self.I(lambda: low.rolling(5).min())
        
        self.demand_top = np.full(len(self.data), np.nan)
        self.demand_bot = np.full(len(self.data), np.nan)
        self.supply_top = np.full(len(self.data), np.nan)
        self.supply_bot = np.full(len(self.data), np.nan)
        
        self.last_ph = np.nan
        self.prev_ph = np.nan
        self.last_pl = np.nan
        self.prev_pl = np.nan
        
        self.trend = 0
        self.in_position = False

    def next(self):
        if len(self.data) < self.ms_lookback + 5:
            return
        
        idx = len(self.data) - 1
        close = self.data.Close[-1]
        open_ = self.data.Open[-1]
        high = self.data.High[-1]
        low = self.data.Low[-1]
        
        hour_utc = datetime.fromtimestamp(self.data.index[-1].timestamp()).hour
        hour_ny = (hour_utc - 5) % 24
        
        london_session = hour_ny >= 3 and hour_ny < 12
        ny_session = hour_ny >= 8 and hour_ny < 17
        midday_chop = hour_ny >= 12 and hour_ny < 14
        
        in_session = not self.use_session or (london_session or ny_session)
        session_ok = in_session and not midday_chop
        
        if idx >= self.ms_lookback:
            recent_high = self.data.High[max(0, idx-self.ms_lookback):idx].max()
            recent_low = self.data.Low[max(0, idx-self.ms_lookback):idx].min()
            
            is_ph = recent_high == high and all(self.data.High[max(0, i-self.ms_lookback):i].max() <= high 
                                               for i in range(max(1, idx-self.ms_lookback+1), idx))
            is_pl = recent_low == low and all(self.data.Low[max(0, i-self.ms_lookback):i].min() >= low 
                                             for i in range(max(1, idx-self.ms_lookback+1), idx))
            
            if is_ph:
                self.prev_ph = self.last_ph
                self.last_ph = high
            
            if is_pl:
                self.prev_pl = self.last_pl
                self.last_pl = low
        
        is_hh = not np.isnan(self.last_ph) and not np.isnan(self.prev_ph) and self.last_ph > self.prev_ph
        is_lh = not np.isnan(self.last_ph) and not np.isnan(self.prev_ph) and self.last_ph < self.prev_ph
        is_hl = not np.isnan(self.last_pl) and not np.isnan(self.prev_pl) and self.last_pl > self.prev_pl
        is_ll = not np.isnan(self.last_pl) and not np.isnan(self.prev_pl) and self.last_pl < self.prev_pl
        
        if is_hh and is_hl:
            self.trend = 1
        if is_lh and is_ll:
            self.trend = -1
        
        avg_body = self.avg_body[-1] if not np.isnan(self.avg_body[-1]) else 0
        bull_impulse = (close - open_) > avg_body * self.impulse_mult and close > open_
        bear_impulse = (open_ - close) > avg_body * self.impulse_mult and close < open_
        
        if bull_impulse:
            self.demand_top[idx] = max(open_, close)
            self.demand_bot[idx] = min(open_, close)
        else:
            self.demand_top[idx] = self.demand_top[idx-1] if idx > 0 else np.nan
            self.demand_bot[idx] = self.demand_bot[idx-1] if idx > 0 else np.nan
        
        if bear_impulse:
            self.supply_top[idx] = max(open_, close)
            self.supply_bot[idx] = min(open_, close)
        else:
            self.supply_top[idx] = self.supply_top[idx-1] if idx > 0 else np.nan
            self.supply_bot[idx] = self.supply_bot[idx-1] if idx > 0 else np.nan
        
        if not np.isnan(self.demand_bot[idx]) and close < self.demand_bot[idx]:
            self.demand_top[idx] = np.nan
            self.demand_bot[idx] = np.nan
        
        if not np.isnan(self.supply_top[idx]) and close > self.supply_top[idx]:
            self.supply_top[idx] = np.nan
            self.supply_bot[idx] = np.nan
        
        in_demand = not np.isnan(self.demand_top[idx]) and low <= self.demand_top[idx] and high >= self.demand_bot[idx]
        in_supply = not np.isnan(self.supply_top[idx]) and high >= self.supply_bot[idx] and low <= self.supply_top[idx]
        
        candle_body = abs(close - open_)
        upper_wick = high - max(open_, close)
        lower_wick = min(open_, close) - low
        
        bull_engulf = close > open_ and close > self.data.Open[-2] and open_ < self.data.Close[-2]
        bear_engulf = close < open_ and close < self.data.Open[-2] and open_ > self.data.Close[-2]
        
        bull_wick = lower_wick > candle_body * self.wick_ratio and close > open_ if candle_body > 0 else False
        bear_wick = upper_wick > candle_body * self.wick_ratio and close < open_ if candle_body > 0 else False
        
        recent_high_5 = self.highest_5[-2] if len(self.highest_5) > 1 else self.data.High[-1]
        recent_low_5 = self.lowest_5[-2] if len(self.lowest_5) > 1 else self.data.Low[-1]
        
        bull_bos = close > recent_high_5
        bear_bos = close < recent_low_5
        
        long_confirm = (self.use_engulf and bull_engulf) or (self.use_wick and bull_wick) or (self.use_bos and bull_bos)
        short_confirm = (self.use_engulf and bear_engulf) or (self.use_wick and bear_wick) or (self.use_bos and bear_bos)
        
        long_signal = self.trend == 1 and in_demand and long_confirm and session_ok
        short_signal = self.trend == -1 and in_supply and short_confirm and session_ok
        
        if long_signal and not self.position:
            self.buy()
            self.in_position = True
        elif short_signal and not self.position:
            self.sell()
            self.in_position = True
        
        if self.position and self.position.is_long:
            sl_price = self.demand_bot[idx] - self.atr[-1] * self.sl_atr_mult if not np.isnan(self.demand_bot[idx]) else close - self.atr[-1] * self.sl_atr_mult
            if low <= sl_price:
                self.position.close()
                self.in_position = False
        
        if self.position and not self.position.is_long:
            sl_price = self.supply_top[idx] + self.atr[-1] * self.sl_atr_mult if not np.isnan(self.supply_top[idx]) else close + self.atr[-1] * self.sl_atr_mult
            if high >= sl_price:
                self.position.close()
                self.in_position = False


