        isAbove = self.data.Close[-1] > self.emaValue[-1]
        
        # Buy when efficiency is high and price is above EMA
        if efficiencyScore > 70 and isAbove and not self.position:
            self.buy()
        
        # Sell when efficiency drops below 40 or price crosses below EMA
        if self.position and (efficiencyScore < 40 or not isAbove):
            self.position.close()


