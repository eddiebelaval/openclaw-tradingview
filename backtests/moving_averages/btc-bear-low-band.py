import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    len = 21
    ma_type = "EMA"
    lower_mult = 0.66
    upper_mult = 0.82
    extra_smooth = 2
    alert_basis = "Wick Touch (High/Low)"

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)

        # Calculate base MAs based on ma_type
        if self.ma_type == "EMA":
            hi_ma = self.I(pta.ema, high, length=self.len)
            lo_ma = self.I(pta.ema, low, length=self.len)
        elif self.ma_type == "RMA":
            hi_ma = self.I(pta.rma, high, length=self.len)
            lo_ma = self.I(pta.rma, low, length=self.len)
        elif self.ma_type == "WMA":
            hi_ma = self.I(pta.wma, high, length=self.len)
            lo_ma = self.I(pta.wma, low, length=self.len)
        else:  # SMA
            hi_ma = self.I(pta.sma, high, length=self.len)
            lo_ma = self.I(pta.sma, low, length=self.len)

        # Apply extra smoothing if needed
        if self.extra_smooth > 1:
            hi_ma_smooth = self.I(pta.ema, hi_ma, length=self.extra_smooth)
            lo_ma_smooth = self.I(pta.ema, lo_ma, length=self.extra_smooth)
        else:
            hi_ma_smooth = hi_ma
            lo_ma_smooth = lo_ma

        # Calculate bands
        self.upper = self.I(lambda: hi_ma_smooth * self.upper_mult)
        self.lower = self.I(lambda: lo_ma_smooth * self.lower_mult)
        self.mid = self.I(lambda: (self.upper + self.lower) / 2.0)

        # Determine source for alerts based on alert_basis
        if self.alert_basis == "Wick Touch (High/Low)":
            self.src_dn = low
            self.src_up = high
        else:  # Close Cross
            self.src_dn = close
            self.src_up = close

    def next(self):
        # Generate buy signal when price crosses over the lower band
        if crossover(self.src_up, self.lower):
            if not self.position:
                self.buy()
        
        # Generate sell signal when price crosses under the lower band
        elif crossover(self.lower, self.src_dn):
            if self.position:
                self.position.close()
        
        # Alternative: sell signal when price crosses under the upper band
        elif crossover(self.upper, self.src_dn):
            if self.position:
                self.position.close()


