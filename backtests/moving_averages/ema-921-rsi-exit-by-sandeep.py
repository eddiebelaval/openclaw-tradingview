from backtesting.lib import crossover


class TvStrategy(Strategy):
    emaFastLen = 9
    emaSlowLen = 21
    rsiLen = 14
    rsiUpper = 90
    rsiLower = 10

    def init(self):
        close = pd.Series(self.data.Close)
        high = pd.Series(self.data.High)
        low = pd.Series(self.data.Low)
        
        self.emaFast = self.I(pta.ema, close, length=self.emaFastLen)
        self.emaSlow = self.I(pta.ema, close, length=self.emaSlowLen)
        self.rsi = self.I(pta.rsi, close, length=self.rsiLen)

    def next(self):
        # Check for EMA crosses
        bullCross = crossover(self.emaFast, self.emaSlow)
        bearCross = crossover(self.emaSlow, self.emaFast)
        
        # Entry logic
        if bullCross:
            if self.position.is_short:
                self.position.close()
            self.buy()
        
        if bearCross:
            if self.position.is_long:
                self.position.close()
            self.sell()
        
        # RSI exit logic
        if self.position.is_long and self.rsi[-1] >= self.rsiUpper:
            self.position.close()
        
        if self.position.is_short and self.rsi[-1] <= self.rsiLower:
            self.position.close()


