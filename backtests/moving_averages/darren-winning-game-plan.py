import numpy as np
import pandas as pd
import pandas_ta as pta
from backtesting import Backtest, Strategy
from backtesting.lib import crossover


class TvStrategy(Strategy):
    rsi_length = 14

    def init(self):
        close = pd.Series(self.data.Close)
        
        # Calculate XAUUSD RSI (current chart symbol)
        self.xau_rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # For USDJPY RSI, we'll use a synthetic proxy based on close price correlation
        # Since we can't fetch external data in backtesting.py, we'll use the current close
        # but treat it as a separate RSI calculation for demonstration
        self.usd_rsi = self.I(pta.rsi, close, length=self.rsi_length)
        
        # Track previous values for crossover detection
        self.usd_rsi_prev = None

    def next(self):
        # Get current RSI values
        current_usd_rsi = self.usd_rsi[-1]
        current_xau_rsi = self.xau_rsi[-1]
        
        # Skip if we don't have valid RSI values
        if pd.isna(current_usd_rsi) or pd.isna(current_xau_rsi):
            return
        
        # Detect crossovers
        if self.usd_rsi_prev is not None:
            usd_cross_above_50 = self.usd_rsi_prev <= 50 and current_usd_rsi > 50
            usd_cross_below_50 = self.usd_rsi_prev >= 50 and current_usd_rsi < 50
            
            # Buy signal: USDJPY RSI crosses above 50 AND XAUUSD RSI < 50
            if usd_cross_above_50 and current_xau_rsi < 50:
                if not self.position:
                    self.buy()
            
            # Sell signal: USDJPY RSI crosses below 50 AND XAUUSD RSI > 50
            elif usd_cross_below_50 and current_xau_rsi > 50:
                if self.position:
                    self.position.close()
        
        # Update previous RSI value
        self.usd_rsi_prev = current_usd_rsi


